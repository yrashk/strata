; =============================================================================
; vm-jit.s: native code, the VM's side of it
; =============================================================================
;
; The JIT is Stratalk code (kernel/Jit.st): it translates a method's
; bytecodes to Strata code and installs it here. Native code lives in code
; units of 1 KiB in the program's arena (c0, from JIT_BASE), which the
; kernel pages into the I-LS after the VM's resident code on a miss (xslot
; 10), as it does a paged C program's. A method's native code is found
; through the native table (specials 15: pairs method, c0 offset; the
; method's header bit 53 says to look) and kept in its method cache entry.
;
; Native code keeps the interpreter's frames and registers (s1 fp, s2 hp,
; s3 the entry, s4 self, s10 the literals, s5..s8) and calls the resident
; VM with `jalr ra, gp, X - 0x10000` (gp = 0x10000). A send from native
; code passes the far address to come back to; the callee's frame keeps it
; (as NATIVE + address in its ip word) and the return goes there with xret,
; which pages the unit back in if it was evicted meanwhile.

JIT_BASE   = 0x10000                    ; native code: c0 [JIT_BASE, JIT_END)
JIT_END    = 0xC0000                    ; ...
JIT_UNIT   = 1024                       ; a unit (xslot 10); a method fits in one
JIT_XSLOT  = 10                         ; ...
JIT_HOT    = 200                        ; activations before a method is compiled
NATIVE     = 1 << 50                    ; a frame's ip word above this: a native return
SP_NATIVE  = 15                         ; the specials: the native table
SP_JIT     = 13                         ; ... what jitCompile: is sent to
SP_JITSEL  = 14                         ; ... #jitCompile:

; act_native: the method at s3 has native code (t0 = its c0 offset): go
act_native:
        ld    t1, v_nnative(zero)       ; counted
        addi  t1, t1, 1                 ; ...
        sd    t1, v_nnative(zero)       ; ...
        xcall zero, c0, t0              ; into it (paged in if need be)

; act_count: an interpreted activation; a method that gets hot is offered
; to the JIT (Jit jitCompile: method, sent from inside its own new frame:
; the answer stays on its operand stack, under what it pushes)
act_count:
        ld    t1, v_jiton(zero)         ; the JIT on and not at work?
        li    t2, 1                     ; ...
        bne   t1, t2, next              ; ...
        ld    t1, 16(s3)                ; the count
        addi  t1, t1, 1                 ; ...
        sd    t1, 16(s3)                ; ...
        li    t2, JIT_HOT               ; hot now?
        bne   t1, t2, next              ; ...
        ld    t0, v_specials(zero)      ; Jit jitCompile: method
        addi  a0, t0, 8 + 8 * SP_JIT    ; ...
        call  fld                       ; ...
        beqz  a0, next                  ; (no Jit)
        addi  sp, sp, -16               ; ...
        sd    a0, 8(sp)                 ; ...
        ld    t0, 0(s3)                 ; ...
        sd    t0, 0(sp)                 ; ...
        ld    t0, v_specials(zero)      ; ...
        addi  a0, t0, 8 + 8 * SP_JITSEL ; ...
        call  fld                       ; ...
        li    a1, 1                     ; ...
        j     send                      ; ...

; nat_lookup(a0 = a method with header bit 53) -> a0 = its native code's c0
; offset, or 0. Uses a2..a5.
nat_lookup:
        sd    ra, v_ra15(zero)          ; ...
        mv    a5, a0                    ; ...
        ld    t0, v_specials(zero)      ; the table
        addi  a0, t0, 8 + 8 * SP_NATIVE ; ...
        call  fld                       ; ...
        beqz  a0, nl_none               ; none
        andi  t0, a0, 7                 ; (an Array, far)
        bnez  t0, nl_none               ; ...
        mv    a4, a0                    ; ...
        call  fld                       ; its pairs: slots / 2
        srli  a3, a0, SIZE_SHIFT + 1    ; ...
        beqz  a3, nl_none               ; ...
        srli  a2, a5, 3                 ; probe from method >> 3
        addi  t0, a3, -1                ; ...
        and   a2, a2, t0                ; ...
        sd    zero, v_tmp7(zero)        ; (probes made)
nl_loop:
        slli  a0, a2, 4                 ; pair i: slots 2i, 2i + 1
        add   a0, a0, a4                ; ...
        addi  a0, a0, 8                 ; ...
        call  fld                       ; ...
        beq   a0, a5, nl_found          ; ...
        beqz  a0, nl_none               ; ...
        addi  a2, a2, 1                 ; next
        addi  t0, a3, -1                ; ...
        and   a2, a2, t0                ; ...
        ld    t0, v_tmp7(zero)          ; (all of them seen: none)
        addi  t0, t0, 1                 ; ...
        sd    t0, v_tmp7(zero)          ; ...
        bgeu  t0, a3, nl_none           ; ...
        j     nl_loop                   ; ...
nl_found:
        slli  a0, a2, 4                 ; its offset
        add   a0, a0, a4                ; ...
        addi  a0, a0, 16                ; ...
        call  fld                       ; ...
        srai  a0, a0, 1                 ; ...
        ld    ra, v_ra15(zero)          ; ...
        ret                             ; ...
nl_none:
        li    a0, 0                     ; ...
        ld    ra, v_ra15(zero)          ; ...
        ret                             ; ...

; ---- what native code calls --------------------------------------------------------

; jh_send(a0 = selector, a1 = nargs, a2 = the far address to come back to)
jh_send:
        li    t0, NATIVE                ; the caller's ip word: native
        add   t0, t0, a2                ; ...
        sd    t0, v_nret(zero)          ; ...
        j     send                      ; ...
; jh_super(a0 = selector, a1 = nargs, a2 = the far address to come back to)
jh_super:
        li    t0, NATIVE                ; ...
        add   t0, t0, a2                ; ...
        sd    t0, v_nret(zero)          ; ...
        j     super_send                ; ...
; jh_sendsp(a0 = k, a2 = the far address): special selector k, sent
jh_sendsp:
        li    t0, NATIVE                ; ...
        add   t0, t0, a2                ; ...
        sd    t0, v_nret(zero)          ; ...
        mv    t0, a0                    ; ...
        j     sp_send                   ; ...
; jh_mustbool(a2 = the far address of the test): the top is not a Boolean
jh_mustbool:
        li    t0, NATIVE                ; ...
        add   t0, t0, a2                ; ...
        sd    t0, v_nret(zero)          ; ...
        j     not_boolean               ; ...
; jh_return(a0 = value): the frame returns it to its caller
jh_return:
        j     ret_frame                 ; ...
; jh_rettop(a0 = value): ^ (from a block: from its home method)
jh_rettop:
        ld    t0, -40(s2)               ; a block's frame?
        andi  t0, t0, 2                 ; ...
        bnez  t0, nonlocal_return       ; ...
        j     ret_frame                 ; ...
; jh_closure(a0 = the block, a2 = n copied): a closure of the top n, pushed
jh_closure:
        sd    ra, v_ra16(zero)          ; ...
        call  mk_closure                ; ...
        ld    ra, v_ra16(zero)          ; ...
        ret                             ; ...
; jh_array(a2 = n): an Array of the top n, pushed
jh_array:
        sd    ra, v_ra16(zero)          ; ...
        call  mk_array                  ; ...
        ld    ra, v_ra16(zero)          ; ...
        ret                             ; ...
; jh_vector(a2 = n): an Array of n nils, pushed
jh_vector:
        sd    ra, v_ra16(zero)          ; ...
        li    a0, CI_ARRAY              ; ...
        li    a1, F_INDEX               ; ...
        li    a3, 0                     ; ...
        call  anew                      ; ...
        addi  sp, sp, -8                ; ...
        sd    a0, 0(sp)                 ; ...
        ld    ra, v_ra16(zero)          ; ...
        ret                             ; ...
; jh_classof(a0 = an object) -> a0 = its class
jh_classof:
        sd    ra, v_ra16(zero)          ; ...
        call  oclass                    ; ...
        mv    a1, a0                    ; ...
        ld    a0, v_classes(zero)       ; ...
        call  oload                     ; ...
        ld    ra, v_ra16(zero)          ; ...
        ret                             ; ...

; native_back: a primitive answered a send made from native code (v_nret):
; back into it
native_back:
        sd    zero, v_nret(zero)        ; ...
        li    t1, NATIVE                ; ...
        sub   t0, t0, t1                ; ...
        li    t1, 1                     ; a far link
        slli  t1, t1, 63                ; ...
        or    t0, t0, t1                ; ...
        xret  t0                        ; ...

; ---- the JIT's primitives ------------------------------------------------------------

; Jit helpers -> an Array of SmallIntegers: what native code calls (I-LS
; addresses) and the VM's numbers it needs
pj_helpers:
        li    a0, CI_ARRAY              ; ...
        li    a1, F_INDEX               ; ...
        li    a2, JH_N                  ; ...
        li    a3, 0                     ; ...
        call  anew                      ; ...
        mv    s11, a0                   ; ...
        li    a1, 0                     ; ...
pjh_loop:
        li    t0, JH_N                  ; ...
        bgeu  a1, t0, pjh_done          ; ...
        slli  t0, a1, 3                 ; ...
        la    t1, jh_table              ; ...
        add   t0, t0, t1                ; ...
        ld    a2, 0(t0)                 ; ...
        slli  a2, a2, 1                 ; ...
        ori   a2, a2, 1                 ; ...
        mv    a0, s11                   ; ...
        sd    a1, v_tmp0(zero)          ; ...
        call  ostore                    ; ...
        ld    a1, v_tmp0(zero)          ; ...
        addi  a1, a1, 1                 ; ...
        j     pjh_loop                  ; ...
pjh_done:
        mv    a0, s11                   ; ...
        j     prim_ok                   ; ...

; Jit reserve: n -> {c0 offset. far address}: where n bytes of code will go
; (in one unit), or nil: no room
pj_reserve:
        ld    t0, 0(sp)                 ; n
        andi  t1, t0, 1                 ; ...
        beqz  t1, prim_fail             ; ...
        srai  t0, t0, 1                 ; ...
        addi  t0, t0, 7                 ; whole words
        srli  t0, t0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        li    t1, JIT_UNIT              ; at most a unit
        bgtu  t0, t1, p_nil             ; ...
        ld    t2, v_jtop(zero)          ; the next free byte
        bnez  t2, pjr_1                 ; ...
        li    t2, JIT_BASE              ; ...
pjr_1:
        andi  t3, t2, JIT_UNIT - 1      ; does it fit in this unit?
        add   t3, t3, t0                ; ...
        bleu  t3, t1, pjr_2             ; ...
        addi  t2, t2, JIT_UNIT - 1      ; no: the next one
        andi  t3, t2, JIT_UNIT - 1      ; ...
        sub   t2, t2, t3                ; ...
pjr_2:
        add   t3, t2, t0                ; room?
        li    t4, JIT_END               ; ...
        bgtu  t3, t4, p_nil             ; ...
        sd    t2, v_tmp6(zero)          ; ...
        li    a0, CI_ARRAY              ; {offset. far address}
        li    a1, F_INDEX               ; ...
        li    a2, 2                     ; ...
        li    a3, 0                     ; ...
        call  anew                      ; ...
        mv    s11, a0                   ; ...
        ld    a2, v_tmp6(zero)          ; ...
        slli  a2, a2, 1                 ; ...
        ori   a2, a2, 1                 ; ...
        li    a1, 0                     ; ...
        call  ostore                    ; ...
        ld    a2, v_tmp6(zero)          ; ...
        cbase t0, c0                    ; ...
        add   a2, a2, t0                ; ...
        slli  a2, a2, 1                 ; ...
        ori   a2, a2, 1                 ; ...
        mv    a0, s11                   ; ...
        li    a1, 1                     ; ...
        call  ostore                    ; ...
        mv    a0, s11                   ; ...
        j     prim_ok                   ; ...

; Jit install: bytes at: offset for: method -> the method: the code goes
; out to c0 at the offset (reserved), into the native table, and the
; method's header says so
pj_install:
        li    t0, 3                     ; ...
        bne   a0, t0, prim_fail         ; ...
        ld    a0, 16(sp)                ; the bytes
        call  pb_bytes                  ; ...
        beqz  t0, prim_fail             ; ...
        li    t0, JIT_UNIT              ; ...
        bgtu  a3, t0, prim_fail         ; ...
        sd    a3, v_tmp5(zero)          ; ...
        ld    t0, 8(sp)                 ; the offset
        andi  t1, t0, 1                 ; ...
        beqz  t1, prim_fail             ; ...
        srai  t0, t0, 1                 ; ...
        sd    t0, v_tmp6(zero)          ; ...
        li    t4, 0                     ; the bytes -> iobuf
pji_copy:
        ld    t2, v_tmp5(zero)          ; ...
        bgeu  t4, t2, pji_out           ; ...
        sd    t4, v_tmp4(zero)          ; ...
        ld    a0, 16(sp)                ; ...
        mv    a1, t4                    ; ...
        call  obyte_ld                  ; ...
        ld    t4, v_tmp4(zero)          ; ...
        la    t0, iobuf                 ; ...
        add   t0, t0, t4                ; ...
        sb    a0, 0(t0)                 ; ...
        addi  t4, t4, 1                 ; ...
        j     pji_copy                  ; ...
pji_out:
        ld    t1, v_tmp5(zero)          ; whole words
        addi  t1, t1, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        la    t0, iobuf                 ; -> c0
        ld    t2, v_tmp6(zero)          ; ...
        tput  tg3, t0, c0, t2, t1       ; ...
        twait 1 << 3                    ; (before anything can run it)
        add   t2, t2, t1                ; the next free byte
        ld    t3, v_jtop(zero)          ; ...
        bgeu  t3, t2, pji_tab           ; ...
        sd    t2, v_jtop(zero)          ; ...
pji_tab:
        li    t0, 16                    ; a unit that is in the cache now holds old code:
        li    t1, 0                     ;   forget the overlay map (pages in again)
pji_unmap:
        bgeu  t1, t0, pji_um_d          ; ...
        addi  t1, t1, 1                 ; ...
        j     pji_unmap                 ; ...
pji_um_d:
        call  unmap_all                 ; ...
        ld    a0, v_specials(zero)      ; the native table
        addi  a0, a0, 8 + 8 * SP_NATIVE ; ...
        call  fld                       ; ...
        beqz  a0, prim_fail             ; ...
        mv    a4, a0                    ; ...
        call  fld                       ; pairs
        srli  a3, a0, SIZE_SHIFT + 1    ; ...
        ld    a5, 0(sp)                 ; the method (far: it does not move)
        srli  a2, a5, 3                 ; ...
        addi  t0, a3, -1                ; ...
        and   a2, a2, t0                ; ...
pji_probe:
        slli  a0, a2, 4                 ; ...
        add   a0, a0, a4                ; ...
        addi  a0, a0, 8                 ; ...
        call  fld                       ; ...
        beqz  a0, pji_put               ; a free pair (or this method's)
        beq   a0, a5, pji_put           ; ...
        addi  a2, a2, 1                 ; ...
        addi  t0, a3, -1                ; ...
        and   a2, a2, t0                ; ...
        j     pji_probe                 ; ...
pji_put:
        slli  a0, a2, 4                 ; method, offset
        add   a0, a0, a4                ; ...
        addi  a0, a0, 8                 ; ...
        mv    a1, a5                    ; ...
        sd    a0, v_tmp4(zero)          ; ...
        call  fsd                       ; ...
        ld    a0, v_tmp4(zero)          ; ...
        addi  a0, a0, 8                 ; ...
        ld    a1, v_tmp6(zero)          ; ...
        slli  a1, a1, 1                 ; ...
        ori   a1, a1, 1                 ; ...
        call  fsd                       ; ...
        ld    a0, 0(sp)                 ; the header: bit 53 (as a SmallInteger: 54)
        addi  a0, a0, 8                 ; ...
        call  fld                       ; ...
        li    t0, 1                     ; ...
        slli  t0, t0, 54                ; ...
        or    a1, a0, t0                ; ...
        ld    a0, 0(sp)                 ; ...
        addi  a0, a0, 8                 ; ...
        call  fsd                       ; ...
        ld    a0, 0(sp)                 ; no cached copy without its code
        call  mc_forget                 ; ...
        ld    a0, 0(sp)                 ; ...
        j     prim_ok                   ; ...

; unmap_all(): every overlay map entry forgotten (xunmap); the kernel's
; page_in maps units again as they are called
unmap_all:
        xunmap 0                        ; (NXMAP is at least 8; 16 by default)
        xunmap 1                        ; ...
        xunmap 2                        ; ...
        xunmap 3                        ; ...
        xunmap 4                        ; ...
        xunmap 5                        ; ...
        xunmap 6                        ; ...
        xunmap 7                        ; ...
        ret                             ; ...

; Jit enable: n -> 0 off, 1 on, 2 at work (no compiling is offered meanwhile)
pj_enable:
        ld    t0, 0(sp)                 ; ...
        andi  t1, t0, 1                 ; ...
        beqz  t1, prim_fail             ; ...
        srai  t0, t0, 1                 ; ...
        sd    t0, v_jiton(zero)         ; ...
        bnez  t0, p_self                ; (on: units of 1 KiB from now)
        j     p_self                    ; ...

        .data                           ; D-LS
        .align 8                        ; ...
JH_N       = 14                         ; jh_table's entries
jh_table:  .dword jh_send               ; 1 what native code calls
           .dword jh_super              ; 2
           .dword jh_sendsp             ; 3
           .dword jh_mustbool           ; 4
           .dword jh_return             ; 5
           .dword jh_rettop             ; 6
           .dword jh_closure            ; 7
           .dword jh_array              ; 8
           .dword jh_vector             ; 9
           .dword jh_classof            ; 10
           .dword oload                 ; 11 (a0 object, a1 slot) -> a0
           .dword ostore                ; 12 (a0 object, a1 slot, a2 value)
           .dword NATIVE                ; 13 the native mark
           .dword 0x10000               ; 14 gp
        .text                           ; ...
