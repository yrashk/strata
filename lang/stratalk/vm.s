; =============================================================================
; vm.s: the Stratalk virtual machine, a StrataOS program
; =============================================================================
;
;   stratalk [-m MIB] [-i IMAGE] [ARGUMENTS...]
;
; Runs a Stratalk image (lang/stratalk/README.md has the formats; the
; image is built by lang/stratalk/host/stratalk.py). The image is the far
; heap: it is read into an extra arena (c6, MIB megabytes, 6 by default)
; and every object there is reached with transfers. The core works on its
; Local Stores only:
;
;   - new objects are made in a nursery in the D-LS ("near" objects, their
;     references tagged 010); a scavenge copies the survivors out to the far
;     heap in one transfer (vm-mem.s);
;   - far objects are read through a software cache of 64-byte lines on the
;     hardware's ltag/linst, and written through it (every far store is a
;     transfer);
;   - methods run from a method cache in the D-LS, copied in whole;
;   - frames are on the stack in the D-LS (the program's stack, 8 KiB).
;
; An object reference (oop): bit 0 set: a SmallInteger (the value << 1);
; low bits 100: a Character (value << 3); 010: a near object (its header's
; D-LS address + 2); 000: a far object (its header's offset in the heap),
; 0 is nil. An object is a header word and slots (README).
;
; Registers, while the interpreter runs:
;   sp   the Smalltalk stack (grows down; frames and operands)
;   s0   ip: the next bytecode (D-LS)       s1   fp: temp 0 of the frame
;   s2   hp: the frame's header (below it)   s3   the method's cache entry
;   s4   self                                s5   nursery: next free byte
;   s6   nursery: its end                    s7   true   s8   false
;   s9   the bytecode table (I-LS)           s10  the literals (s3 + 16)
;   s11  scratch kept across helpers
;
; A frame, from the top: the receiver, the arguments (temp 0 is the first),
; the other temps, then six words below hp:
;   hp-8 the caller's fp  hp-16 the caller's hp (0: none)  hp-24 the
;   caller's ip, as an offset in its entry (SmallInteger)  hp-32 the method
;   hp-40 serial << 5 | flags (SmallInteger)  hp-48 self
; and the operands below. A frame is named by its hp (as a SmallInteger).
; Flags: 1 a block's frame, 2 ensure: (primitive 198), 4 on:do:
; (primitive 199), 8 unwound, 16 its handler is running.

        .include "vm-data.s"            ; the D-LS: variables, caches, nursery

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        call  sys_init                  ; handles, arguments
        call  vm_args                   ; -m, -i; where Smalltalk's arguments start
        ld    a0, v_heapsz(zero)        ; the far heap: an extra arena
        call  sys_more                  ; ... in c6
        bltz  a0, die_mem               ; none
        li    a0, 0                     ; its size
        call  sys_word                  ; ...
        sd    a0, v_hsize(zero)         ; ...
        call  fc_init                   ; the far cache
        call  img_load                  ; the image -> the heap
        call  vm_init                   ; registers, specials
        ld    t0, v_specials(zero)      ; the receiver of #start
        addi  a0, t0, 8 + 8 * SP_START_RCVR ; ...
        call  fld                       ; ...
        addi  sp, sp, -8                ; pushed
        sd    a0, 0(sp)                 ; ...
        ld    t0, v_specials(zero)      ; #start
        addi  a0, t0, 8 + 8 * SP_START_SEL ; ...
        call  fld                       ; ...
        li    a1, 0                     ; no arguments
        li    s1, 0                     ; no frame yet: the first one's caller is none
        li    s2, 0                     ; ...
        li    s0, 0                     ; ...
        li    s3, 0                     ; ...
        j     send                      ; Stratalk start

die_mem:
        la    a0, m_nomem               ; no memory for the heap
        li    a1, m_nomem_e - m_nomem   ; ...
        j     die                       ; ...
; die(a0 = message, a1 = length): say it on stderr, exit 3
die:
        call  err_str                   ; ...
        li    a0, 3                     ; ...
        call  sys_exit                  ; ...

; vm_init(): the interpreter's registers and the specials it keeps
vm_init:
        sd    ra, v_ra1(zero)           ; (fld calls)
        li    a0, 16                    ; the specials: header word 2
        call  fld                       ; ...
        sd    a0, v_specials(zero)      ; ...
        addi  a0, a0, 8 + 8 * SP_TRUE   ; true
        call  fld                       ; ...
        mv    s7, a0                    ; ...
        ld    a0, v_specials(zero)      ; false
        addi  a0, a0, 8 + 8 * SP_FALSE  ; ...
        call  fld                       ; ...
        mv    s8, a0                    ; ...
        ld    a0, v_specials(zero)      ; the class table
        addi  a0, a0, 8 + 8 * SP_CLASSES ; ...
        call  fld                       ; ...
        sd    a0, v_classes(zero)       ; ...
        ld    a0, v_specials(zero)      ; the special selectors
        addi  a0, a0, 8 + 8 * SP_SPSELS ; ...
        call  fld                       ; ...
        sd    a0, v_spsels(zero)        ; ...
        li    a0, 8                     ; the heap's top
        call  fld                       ; ...
        sd    a0, v_htop(zero)          ; ...
        li    a0, 24                    ; its free chunks
        call  fld                       ; ...
        sd    a0, v_free(zero)          ; ...
        li    t0, BIAS0                 ; the stack: all in the D-LS
        sd    t0, v_bias(zero)          ; ...
        ld    t0, v_hsize(zero)         ; the far stack: the arena's top FSSIZE bytes
        li    t1, LTOP                  ; far = logical + v_fsoff
        sub   t1, t0, t1                ; ...
        sd    t1, v_fsoff(zero)         ; ...
        li    t1, FSSIZE                ; the heap: below it
        sub   t0, t0, t1                ; ...
        sd    t0, v_hsize(zero)         ; ...
        la    s5, nursery               ; the nursery
        li    t0, NURSERY               ; ...
        add   s6, s5, t0                ; ...
        la    s9, optab                 ; the bytecodes' table
        li    t0, JIT_XSLOT             ; native code: units of 1 KiB, paged by the kernel
        csrw  xslot, t0                 ; ...
        li    gp, 0x10000               ; (what native code calls the VM through)
        li    t0, 0x1234                ; identity hashes start here
        sd    t0, v_hash(zero)          ; ...
        ld    ra, v_ra1(zero)           ; ...
        ret                             ; done

; vm_args(): the VM's own options at the front of the arguments
;   -m MIB    the far heap's size (6 MiB by default, 1 of them the far stack)
;   -i PATH   the image (/stratalk/stratalk.image)
; v_argp, v_arge: what is left, Smalltalk's (prim 103)
vm_args:
        sd    ra, v_ra1(zero)           ; save ra
        li    t0, 6 << 20               ; defaults
        sd    t0, v_heapsz(zero)        ; ...
        la    t0, m_image               ; ...
        sd    t0, v_imgp(zero)          ; ...
        li    t0, m_image_e - m_image   ; ...
        sd    t0, v_imgl(zero)          ; ...
        call  sys_cmdline               ; a0 = text, a1 = length
        add   a1, a0, a1                ; a1 = end
        sd    a1, v_arge(zero)          ; ...
        call  arg_next                  ; the program's name
        mv    a0, a2                    ; after it
va_loop:
        sd    a0, v_argp(zero)          ; Smalltalk's arguments start here (so far)
        ld    a1, v_arge(zero)          ; the next word
        call  arg_next                  ; a0 = word, a1 = length, a2 = after
        li    t0, 2                     ; an option is two characters
        bne   a1, t0, va_done           ; not one
        lbu   t1, 0(a0)                 ; '-' ...
        li    t2, '-'                   ; ...
        bne   t1, t2, va_done           ; ...
        lbu   t1, 1(a0)                 ; ... m or i
        sd    t1, v_tmp0(zero)          ; (keep it)
        mv    a0, a2                    ; its value
        ld    a1, v_arge(zero)          ; ...
        call  arg_next                  ; ...
        beqz  a1, va_done               ; none
        ld    t1, v_tmp0(zero)          ; which option
        li    t2, 'm'                   ; -m MIB
        beq   t1, t2, va_m              ; ...
        li    t2, 'i'                   ; -i PATH
        bne   t1, t2, va_done           ; neither: Smalltalk's
        sd    a0, v_imgp(zero)          ; the image's name
        sd    a1, v_imgl(zero)          ; ...
        mv    a0, a2                    ; next
        j     va_loop                   ; ...
va_m:
        sd    a2, v_tmp0(zero)          ; after it
        call  str_atoi                  ; a0 = MiB (a0 = text, a1 = length)
        slli  a0, a0, 20                ; bytes
        li    t0, 1 << 20               ; at least 1 MiB
        bgeu  a0, t0, va_m1             ; ...
        mv    a0, t0                    ; ...
va_m1:
        sd    a0, v_heapsz(zero)        ; ...
        ld    a0, v_tmp0(zero)          ; next
        j     va_loop                   ; ...
va_done:
        ld    ra, v_ra1(zero)           ; restore ra
        ret                             ; done

; =============================================================================
; The interpreter
; =============================================================================

next:
        lbu   t0, 0(s0)                 ; the bytecode
        andi  t0, t0, 63                ; (the table has 64 entries)
        slli  t0, t0, 2                 ; its entry: one jump
        add   t0, t0, s9                ; ...
        jr    t0                        ; ...

optab:
        j     op_pushself               ; 0 push self
        j     op_pushnil                ; 1 push nil
        j     op_pushtrue               ; 2 push true
        j     op_pushfalse              ; 3 push false
        j     op_bad                    ; 4
        j     op_dup                    ; 5 dup
        j     op_pop                    ; 6 pop
        j     op_rettop                 ; 7 return the top (from the home method)
        j     op_retself                ; 8 return self
        j     op_blkret                 ; 9 a block's value
        j     op_bad                    ; 10
        j     op_bad                    ; 11
        j     op_bad                    ; 12
        j     op_bad                    ; 13
        j     op_bad                    ; 14
        j     op_bad                    ; 15
        j     op_pushinst               ; 16 push inst var n
        j     op_pushtemp               ; 17 push temp n
        j     op_pushlit                ; 18 push literal n
        j     op_pushlitvar             ; 19 push the value of literal association n
        j     op_storeinst              ; 20 store into inst var n
        j     op_storetemp              ; 21 store into temp n
        j     op_storelitvar            ; 22 store into literal association n
        j     op_popstinst              ; 23 pop into inst var n
        j     op_popsttemp              ; 24 pop into temp n
        j     op_popstlitvar            ; 25 pop into literal association n
        j     op_pushint8               ; 26 push a small integer -128..127
        j     op_pushtvec               ; 27 push slot i of the vector in temp j
        j     op_storetvec              ; 28 store into it
        j     op_popsttvec              ; 29 pop into it
        j     op_pusharray              ; 30 an Array of the top n
        j     op_pushclosure            ; 31 a closure of block literal i, n copied
        j     op_send                   ; 32 send literal i with n arguments
        j     op_super                  ; 33 the same from the method's class's superclass
        j     op_sendsp                 ; 34 a special selector
        j     op_jump                   ; 35 jump (16-bit offset)
        j     op_jumpt                  ; 36 jump if true
        j     op_jumpf                  ; 37 jump if false
        j     op_pushvec                ; 38 a vector of n nils
        j     op_bad                    ; 39
        j     op_bad                    ; 40
        j     op_bad                    ; 41
        j     op_bad                    ; 42
        j     op_bad                    ; 43
        j     op_bad                    ; 44
        j     op_bad                    ; 45
        j     op_bad                    ; 46
        j     op_bad                    ; 47
        j     op_bad                    ; 48
        j     op_bad                    ; 49
        j     op_bad                    ; 50
        j     op_bad                    ; 51
        j     op_bad                    ; 52
        j     op_bad                    ; 53
        j     op_bad                    ; 54
        j     op_bad                    ; 55
        j     op_bad                    ; 56
        j     op_bad                    ; 57
        j     op_bad                    ; 58
        j     op_bad                    ; 59
        j     op_bad                    ; 60
        j     op_bad                    ; 61
        j     op_bad                    ; 62
        j     op_bad                    ; 63

op_bad:
        la    a0, m_badop               ; a byte that is not a bytecode
        li    a1, m_badop_e - m_badop   ; ...
        j     die                       ; ...

op_pushself:
        addi  s0, s0, 1                 ; ...
        addi  sp, sp, -8                ; push self
        sd    s4, 0(sp)                 ; ...
        j     next                      ; ...
op_pushnil:
        addi  s0, s0, 1                 ; ...
        addi  sp, sp, -8                ; push nil
        sd    zero, 0(sp)               ; ...
        j     next                      ; ...
op_pushtrue:
        addi  s0, s0, 1                 ; ...
        addi  sp, sp, -8                ; push true
        sd    s7, 0(sp)                 ; ...
        j     next                      ; ...
op_pushfalse:
        addi  s0, s0, 1                 ; ...
        addi  sp, sp, -8                ; push false
        sd    s8, 0(sp)                 ; ...
        j     next                      ; ...
op_dup:
        addi  s0, s0, 1                 ; ...
        ld    t0, 0(sp)                 ; the top, twice
        addi  sp, sp, -8                ; ...
        sd    t0, 0(sp)                 ; ...
        j     next                      ; ...
op_pop:
        addi  s0, s0, 1                 ; ...
        addi  sp, sp, 8                 ; drop the top
        j     next                      ; ...

op_pushtemp:
        lbu   t0, 1(s0)                 ; n
        addi  s0, s0, 2                 ; ...
        slli  t0, t0, 3                 ; temp n is at fp - 8n
        sub   t0, s1, t0                ; ...
        ld    t0, 0(t0)                 ; ...
        addi  sp, sp, -8                ; push it
        sd    t0, 0(sp)                 ; ...
        j     next                      ; ...
op_storetemp:
        lbu   t0, 1(s0)                 ; n
        addi  s0, s0, 2                 ; ...
        slli  t0, t0, 3                 ; temp n
        sub   t0, s1, t0                ; ...
        ld    t1, 0(sp)                 ; := the top
        sd    t1, 0(t0)                 ; ...
        j     next                      ; ...
op_popsttemp:
        lbu   t0, 1(s0)                 ; n
        addi  s0, s0, 2                 ; ...
        slli  t0, t0, 3                 ; temp n
        sub   t0, s1, t0                ; ...
        ld    t1, 0(sp)                 ; := the top, popped
        addi  sp, sp, 8                 ; ...
        sd    t1, 0(t0)                 ; ...
        j     next                      ; ...
op_pushlit:
        lbu   t0, 1(s0)                 ; n
        addi  s0, s0, 2                 ; ...
        slli  t0, t0, 3                 ; literal n
        add   t0, t0, s10               ; ...
        ld    t0, 0(t0)                 ; ...
        addi  sp, sp, -8                ; push it
        sd    t0, 0(sp)                 ; ...
        j     next                      ; ...
op_pushint8:
        lb    t0, 1(s0)                 ; the signed byte
        addi  s0, s0, 2                 ; ...
        slli  t0, t0, 1                 ; a SmallInteger
        ori   t0, t0, 1                 ; ...
        addi  sp, sp, -8                ; push it
        sd    t0, 0(sp)                 ; ...
        j     next                      ; ...
op_pushlitvar:
        lbu   t0, 1(s0)                 ; n
        addi  s0, s0, 2                 ; ...
        slli  t0, t0, 3                 ; the association
        add   t0, t0, s10               ; ...
        ld    a0, 0(t0)                 ; ...
        li    a1, 1                     ; its value
        call  oload                     ; ...
        addi  sp, sp, -8                ; push it
        sd    a0, 0(sp)                 ; ...
        j     next                      ; ...
op_storelitvar:
        lbu   t0, 1(s0)                 ; n
        addi  s0, s0, 2                 ; ...
        slli  t0, t0, 3                 ; the association
        add   t0, t0, s10               ; ...
        ld    a0, 0(t0)                 ; ...
        li    a1, 1                     ; its value := the top
        ld    a2, 0(sp)                 ; ...
        call  ostore                    ; ...
        j     next                      ; ...
op_popstlitvar:
        lbu   t0, 1(s0)                 ; n
        addi  s0, s0, 2                 ; ...
        slli  t0, t0, 3                 ; the association
        add   t0, t0, s10               ; ...
        ld    a0, 0(t0)                 ; ...
        li    a1, 1                     ; its value := the top
        ld    a2, 0(sp)                 ; (still pushed: a root while it is stored)
        call  ostore                    ; ...
        addi  sp, sp, 8                 ; popped
        j     next                      ; ...
op_pushinst:
        lbu   a1, 1(s0)                 ; n
        addi  s0, s0, 2                 ; ...
        mv    a0, s4                    ; self's slot n
        call  oload                     ; ...
        addi  sp, sp, -8                ; push it
        sd    a0, 0(sp)                 ; ...
        j     next                      ; ...
op_storeinst:
        lbu   a1, 1(s0)                 ; n
        addi  s0, s0, 2                 ; ...
        mv    a0, s4                    ; self's slot n := the top
        ld    a2, 0(sp)                 ; ...
        call  ostore                    ; ...
        j     next                      ; ...
op_popstinst:
        lbu   a1, 1(s0)                 ; n
        addi  s0, s0, 2                 ; ...
        mv    a0, s4                    ; self's slot n := the top
        ld    a2, 0(sp)                 ; ...
        call  ostore                    ; ...
        addi  sp, sp, 8                 ; popped
        j     next                      ; ...
op_pushtvec:
        lbu   a1, 1(s0)                 ; i
        lbu   t0, 2(s0)                 ; j
        addi  s0, s0, 3                 ; ...
        slli  t0, t0, 3                 ; the vector in temp j
        sub   t0, s1, t0                ; ...
        ld    a0, 0(t0)                 ; ...
        call  oload                     ; its slot i
        addi  sp, sp, -8                ; push it
        sd    a0, 0(sp)                 ; ...
        j     next                      ; ...
op_storetvec:
        lbu   a1, 1(s0)                 ; i
        lbu   t0, 2(s0)                 ; j
        addi  s0, s0, 3                 ; ...
        slli  t0, t0, 3                 ; the vector in temp j
        sub   t0, s1, t0                ; ...
        ld    a0, 0(t0)                 ; ...
        ld    a2, 0(sp)                 ; slot i := the top
        call  ostore                    ; ...
        j     next                      ; ...
op_popsttvec:
        lbu   a1, 1(s0)                 ; i
        lbu   t0, 2(s0)                 ; j
        addi  s0, s0, 3                 ; ...
        slli  t0, t0, 3                 ; the vector in temp j
        sub   t0, s1, t0                ; ...
        ld    a0, 0(t0)                 ; ...
        ld    a2, 0(sp)                 ; slot i := the top
        call  ostore                    ; ...
        addi  sp, sp, 8                 ; popped
        j     next                      ; ...

op_pushvec:
        lbu   a2, 1(s0)                 ; n slots
        addi  s0, s0, 2                 ; ...
        li    a0, CI_ARRAY              ; an Array of nils
        li    a1, F_INDEX               ; ...
        li    a3, 0                     ; ...
        call  anew                      ; ...
        addi  sp, sp, -8                ; push it
        sd    a0, 0(sp)                 ; ...
        j     next                      ; ...
op_pusharray:
        lbu   a2, 1(s0)                 ; n
        addi  s0, s0, 2                 ; ...
        call  mk_array                  ; ...
        j     next                      ; ...
; mk_array(a2 = n): the top n -> an Array, pushed
mk_array:
        sd    ra, v_ra17(zero)          ; ...
        sd    a2, v_tmp1(zero)          ; ...
        li    a0, CI_ARRAY              ; an Array (the items stay pushed meanwhile)
        li    a1, F_INDEX               ; ...
        li    a3, 0                     ; ...
        call  anew                      ; a0 = it (near or far)
        ld    t2, v_tmp1(zero)          ; n
        mv    s11, a0                   ; ...
        li    a1, 0                     ; slot i := item i
pa_loop:
        beq   a1, t2, pa_done           ; all
        sub   t0, t2, a1                ; item i is at sp + 8 (n - 1 - i)
        addi  t0, t0, -1                ; ...
        slli  t0, t0, 3                 ; ...
        add   t0, t0, sp                ; ...
        ld    a2, 0(t0)                 ; ...
        mv    a0, s11                   ; ...
        sd    a1, v_tmp2(zero)          ; ...
        call  ostore                    ; (an Array of more than the nursery takes is far)
        ld    a1, v_tmp2(zero)          ; ...
        ld    t2, v_tmp1(zero)          ; ...
        addi  a1, a1, 1                 ; ...
        j     pa_loop                   ; ...
pa_done:
        slli  t0, t2, 3                 ; pop the items
        add   sp, sp, t0                ; ...
        addi  sp, sp, -8                ; push the Array
        sd    s11, 0(sp)                ; ...
        ld    ra, v_ra17(zero)          ; ...
        ret                             ; ...

; a closure: slot 0 the block, 1 self, 2 the home frame's hp, 3 its serial,
; then the copied values (popped)
op_pushclosure:
        lbu   t0, 1(s0)                 ; the block literal
        lbu   a2, 2(s0)                 ; n copied
        addi  s0, s0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        add   t0, t0, s10               ; ...
        ld    a0, 0(t0)                 ; ...
        call  mk_closure                ; ...
        j     next                      ; ...
; mk_closure(a0 = the block, a2 = n copied): a closure of the top n, pushed
mk_closure:
        sd    ra, v_ra17(zero)          ; ...
        sd    a0, v_tmp0(zero)          ; (far: it does not move)
        sd    a2, v_tmp1(zero)          ; ...
        addi  a2, a2, 4                 ; four slots and the copied values
        li    a0, CI_CLOSURE            ; ...
        li    a1, F_FIXED               ; ...
        li    a3, 0                     ; ...
        call  anew                      ; a0 = the closure (near)
        mv    s11, a0                   ; ...
        ld    a2, v_tmp0(zero)          ; slot 0: the block
        li    a1, 0                     ; ...
        call  ostore                    ; ...
        mv    a0, s11                   ; slot 1: self
        li    a1, 1                     ; ...
        mv    a2, s4                    ; ...
        call  ostore                    ; ...
        ld    t0, -40(s2)               ; the frame's home: a method's frame is its own
        andi  t1, t0, 2                 ; (flag 1, shifted: a block's frame)
        bnez  t1, pc_blk                ; ...
        ld    a2, v_bias(zero)          ; hp, logical, as a SmallInteger
        add   a2, a2, s2                ; ...
        slli  a2, a2, 1                 ; ...
        ori   a2, a2, 1                 ; ...
        srli  t0, t0, 6                 ; the serial
        slli  t0, t0, 1                 ; ...
        ori   t0, t0, 1                 ; ...
        sd    t0, v_tmp2(zero)          ; ...
        j     pc_home                   ; ...
pc_blk:
        ld    a0, 8(s1)                 ; a block's frame: its closure's home
        li    a1, 3                     ; ...
        call  oload                     ; ...
        sd    a0, v_tmp2(zero)          ; ...
        ld    a0, 8(s1)                 ; ...
        li    a1, 2                     ; ...
        call  oload                     ; ...
        mv    a2, a0                    ; ...
pc_home:
        mv    a0, s11                   ; slot 2: the home's hp
        li    a1, 2                     ; ...
        call  ostore                    ; ...
        mv    a0, s11                   ; slot 3: its serial
        li    a1, 3                     ; ...
        ld    a2, v_tmp2(zero)          ; ...
        call  ostore                    ; ...
        ld    t2, v_tmp1(zero)          ; the copied values
        li    a1, 0                     ; ...
pcl_loop:
        beq   a1, t2, pcl_done          ; all
        sub   t0, t2, a1                ; value i is at sp + 8 (n - 1 - i)
        addi  t0, t0, -1                ; ...
        slli  t0, t0, 3                 ; ...
        add   t0, t0, sp                ; ...
        ld    a2, 0(t0)                 ; ...
        sd    a1, v_tmp0(zero)          ; ...
        addi  a1, a1, 4                 ; slot 4 + i
        mv    a0, s11                   ; ...
        call  ostore                    ; ...
        ld    a1, v_tmp0(zero)          ; ...
        ld    t2, v_tmp1(zero)          ; ...
        addi  a1, a1, 1                 ; ...
        j     pcl_loop                  ; ...
pcl_done:
        slli  t0, t2, 3                 ; pop them
        add   sp, sp, t0                ; ...
        addi  sp, sp, -8                ; push the closure
        sd    s11, 0(sp)                ; ...
        ld    ra, v_ra17(zero)          ; ...
        ret                             ; ...

op_jump:
        lb    t0, 1(s0)                 ; the offset (signed, high byte first)
        lbu   t1, 2(s0)                 ; ...
        slli  t0, t0, 8                 ; ...
        or    t0, t0, t1                ; ...
        addi  s0, s0, 3                 ; from after the jump
        add   s0, s0, t0                ; ...
        j     next                      ; ...
op_jumpt:
        ld    t2, 0(sp)                 ; the condition
        beq   t2, s7, oj_take           ; true: jump
        beq   t2, s8, oj_skip           ; false: go on
        j     not_boolean               ; ...
op_jumpf:
        ld    t2, 0(sp)                 ; the condition
        beq   t2, s8, oj_take           ; false: jump
        beq   t2, s7, oj_skip           ; true: go on
        j     not_boolean               ; ...
oj_take:
        addi  sp, sp, 8                 ; popped
        j     op_jump                   ; ...
oj_skip:
        addi  sp, sp, 8                 ; popped
        addi  s0, s0, 3                 ; ...
        j     next                      ; ...
; the condition is not a Boolean: send it #mustBeBoolean, and do the jump
; again with what that answers (ip stays at the jump)
not_boolean:
        ld    t0, v_specials(zero)      ; #mustBeBoolean
        addi  a0, t0, 8 + 8 * SP_MUSTBOOL ; ...
        call  fld                       ; ...
        li    a1, 0                     ; ...
        j     send                      ; (the receiver is the top)

; ---- sends -----------------------------------------------------------------------

op_send:
        lbu   t0, 1(s0)                 ; the selector: literal i
        lbu   a1, 2(s0)                 ; nargs
        addi  s0, s0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        add   t0, t0, s10               ; ...
        ld    a0, 0(t0)                 ; ...
        j     send                      ; ...
op_super:
        lbu   t0, 1(s0)                 ; the selector
        lbu   a1, 2(s0)                 ; nargs
        addi  s0, s0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        add   t0, t0, s10               ; ...
        ld    a0, 0(t0)                 ; ...
; super_send(a0 = selector, a1 = nargs): from the method's class's superclass
super_send:
        sd    a0, v_sel(zero)           ; ...
        sd    a1, v_nargs(zero)         ; ...
        ld    t0, 24(s3)                ; the method's class: the last literal
        srli  t0, t0, 17                ; (header bits 16..23, SmallInteger-shifted)
        andi  t0, t0, 255               ; ...
        slli  t0, t0, 3                 ; ...
        add   t0, t0, s10               ; ...
        ld    a0, -8(t0)                ; ...
        li    a1, 0                     ; its superclass
        call  oload                     ; ...
        beqz  a0, send_dnu0             ; none: not understood
        li    a1, 3                     ; its class index
        call  oload                     ; ...
        srai  a0, a0, 1                 ; ...
        ld    a1, v_sel(zero)           ; ...
        call  lookup                    ; a0 = method, a1 = header
        beqz  a0, send_dnu              ; not found
        j     send_found                ; ...

; send(a0 = selector, a1 = nargs): the receiver and the arguments are
; pushed; s0 is after the send
send:
        sd    a0, v_sel(zero)           ; ...
        sd    a1, v_nargs(zero)         ; ...
        ld    t0, v_sends(zero)         ; count it
        addi  t0, t0, 1                 ; ...
        sd    t0, v_sends(zero)         ; ...
        slli  t0, a1, 3                 ; the receiver
        add   t0, t0, sp                ; ...
        ld    a0, 0(t0)                 ; ...
        call  oclass                    ; a0 = its class index
        ld    a1, v_sel(zero)           ; ...
        call  lookup                    ; a0 = method, a1 = its header (SmallInteger)
        beqz  a0, send_dnu              ; not understood
send_found:
        ; a0 = the method, a1 = its header; v_nargs
        sub   t0, s0, s3                ; the caller's ip, kept (a primitive may run Smalltalk)
        ld    t1, v_nret(zero)          ; (native code: where to come back)
        beqz  t1, sf_ip                 ; ...
        mv    t0, t1                    ; ...
sf_ip:
        sd    t0, v_ipoff(zero)         ; ...
        srli  t1, a1, 25                ; the primitive: header bits 24..35
        andi  t1, t1, 4095              ; ...
        beqz  t1, activate              ; none
        li    t2, 198                   ; the markers activate the method
        bgeu  t1, t2, activate          ; ...
        sd    a0, v_meth(zero)          ; (for a failure)
        sd    a1, v_mhdr(zero)          ; ...
        li    t2, NPRIM                 ; a primitive the VM does not have fails
        bgeu  t1, t2, prim_fail         ; ...
        slli  t1, t1, 2                 ; its entry in the table
        la    t2, primtab               ; ...
        add   t1, t1, t2                ; ...
        ld    a0, v_nargs(zero)         ; a0 = nargs
        jr    t1                        ; ...

; prim_ok(a0 = result): the primitive succeeded: drop the receiver and the
; arguments, push the result
prim_ok:
        ld    t0, v_nargs(zero)         ; ...
        slli  t0, t0, 3                 ; ...
        add   sp, sp, t0                ; ...
        sd    a0, 0(sp)                 ; the result where the receiver was
        ld    t0, v_nret(zero)          ; sent from native code: back to it
        bnez  t0, native_back           ; ...
        j     next                      ; ...
; prim_fail: run the method's code instead
prim_fail:
        ld    a0, v_meth(zero)          ; ...
        ld    a1, v_mhdr(zero)          ; ...
        j     activate                  ; ...

; not understood: the arguments go into an Array, with the selector into
; a Message, which is sent with #doesNotUnderstand:
send_dnu0:
        ld    t0, v_nargs(zero)         ; ...
send_dnu:
        ld    a2, v_nargs(zero)         ; an Array of the arguments
        li    a0, CI_ARRAY              ; ...
        li    a1, F_INDEX               ; ...
        li    a3, 0                     ; ...
        call  anew                      ; ...
        mv    s11, a0                   ; ...
        li    a1, 0                     ; slot i := argument i
dnu_loop:
        ld    t2, v_nargs(zero)         ; ...
        beq   a1, t2, dnu_args          ; all
        sub   t0, t2, a1                ; argument i: sp + 8 (n - 1 - i)
        addi  t0, t0, -1                ; ...
        slli  t0, t0, 3                 ; ...
        add   t0, t0, sp                ; ...
        ld    a2, 0(t0)                 ; ...
        sd    a1, v_tmp2(zero)          ; ...
        mv    a0, s11                   ; ...
        call  ostore                    ; ...
        ld    a1, v_tmp2(zero)          ; ...
        addi  a1, a1, 1                 ; ...
        j     dnu_loop                  ; ...
dnu_args:
        ld    t0, v_nargs(zero)         ; pop the arguments, push the Array
        slli  t0, t0, 3                 ; ...
        add   sp, sp, t0                ; ...
        addi  sp, sp, -8                ; ...
        sd    s11, 0(sp)                ; ...
        li    a0, CI_MESSAGE            ; a Message (the Array stays pushed meanwhile)
        li    a1, F_FIXED               ; ...
        li    a2, 2                     ; ...
        li    a3, 0                     ; ...
        call  anew                      ; ...
        mv    s11, a0                   ; ...
        li    a1, 0                     ; its selector (far: it did not move)
        ld    a2, v_sel(zero)           ; ...
        call  ostore                    ; ...
        mv    a0, s11                   ; its arguments
        li    a1, 1                     ; ...
        ld    a2, 0(sp)                 ; ...
        call  ostore                    ; ...
        sd    s11, 0(sp)                ; the Message replaces the Array
        ld    t0, v_specials(zero)      ; #doesNotUnderstand:
        addi  a0, t0, 8 + 8 * SP_DNU    ; ...
        call  fld                       ; ...
        sd    a0, v_sel(zero)           ; ...
        li    t0, 1                     ; one argument
        sd    t0, v_nargs(zero)         ; ...
        ld    a0, 8(sp)                 ; the receiver's class
        call  oclass                    ; ...
        ld    a1, v_sel(zero)           ; ...
        call  lookup                    ; ...
        beqz  a0, die_dnu               ; not even that
        j     send_found                ; ...
die_dnu:
        la    a0, m_nodnu               ; ...
        li    a1, m_nodnu_e - m_nodnu   ; ...
        j     die                       ; ...

; activate(a0 = method, a1 = its header): a new frame for the receiver and
; v_nargs arguments pushed; the caller's ip offset is in v_ipoff
activate:
        li    a2, 0                     ; not a block: no closure
; activate_closure: a2 = the closure (block activations)
activate_closure:
        srai  t0, a1, 1                 ; the header
        ld    t1, v_nargs(zero)         ; fp = temp 0 = sp + 8 (nargs - 1)
        addi  t2, t1, -1                ; ...
        slli  t2, t2, 3                 ; ...
        add   t3, sp, t2                ; t3 = fp
        srli  t4, t0, 8                 ; the other temps
        andi  t4, t4, 255               ; ...
        srli  t5, t0, 45                ; the deepest the operands go
        andi  t5, t5, 255               ; ...
        add   t5, t5, t4                ; room: temps, header, operands, a margin
        slli  t5, t5, 3                 ; ...
        addi  t5, t5, 48 + 64           ; ...
        sub   t5, sp, t5                ; ...
        li    t6, STACK_LIMIT           ; ...
        ld    t2, v_ovf(zero)           ; (an overflow being handled may use the margin)
        beqz  t2, act_lim               ; ...
        addi  t6, t6, -512              ; ...
act_lim:
        bltu  t5, t6, act_spill         ; ...
        mv    t6, sp                    ; the temps: nils (a block: its copied values first)
        beqz  a2, act_nils              ; ...
        srli  t5, t0, 36                ; n copied
        andi  t5, t5, 255               ; ...
        sub   t4, t4, t5                ; the rest are nils
        sd    a0, v_tmp0(zero)          ; ...
        sd    t0, v_tmp1(zero)          ; ...
        sd    t3, v_tmp2(zero)          ; ...
        sd    t4, v_tmp3(zero)          ; ...
        sd    t5, v_tmp4(zero)          ; ...
        mv    s11, a2                   ; ...
        li    a1, 4                     ; copied value i: the closure's slot 4 + i
act_copy:
        ld    t5, v_tmp4(zero)          ; ...
        addi  t0, a1, -4                ; ...
        bge   t0, t5, act_copied        ; all
        sd    a1, v_tmp5(zero)          ; ...
        mv    a0, s11                   ; ...
        call  oload                     ; ...
        addi  sp, sp, -8                ; ...
        sd    a0, 0(sp)                 ; ...
        ld    a1, v_tmp5(zero)          ; ...
        addi  a1, a1, 1                 ; ...
        j     act_copy                  ; ...
act_copied:
        mv    a2, s11                   ; ...
        ld    a0, v_tmp0(zero)          ; ...
        ld    t0, v_tmp1(zero)          ; ...
        ld    t3, v_tmp2(zero)          ; ...
        ld    t4, v_tmp3(zero)          ; ...
act_nils:
        beqz  t4, act_hdr               ; the rest: nils
        addi  sp, sp, -8                ; ...
        sd    zero, 0(sp)               ; ...
        addi  t4, t4, -1                ; ...
        j     act_nils                  ; ...
act_hdr:
        mv    t6, sp                    ; hp
        li    t1, 0                     ; the caller's fp and hp, logical (0, 0: none)
        li    t2, 0                     ; ...
        beqz  s2, act_h1                ; ...
        ld    t5, v_bias(zero)          ; ...
        add   t1, s1, t5                ; ...
        add   t2, s2, t5                ; ...
act_h1:
        sd    t1, -8(t6)                ; ...
        sd    t2, -16(t6)               ; ...
        ld    t1, v_ipoff(zero)         ; the caller's ip offset (or its native return)
        slli  t1, t1, 1                 ; ...
        ori   t1, t1, 1                 ; ...
        sd    t1, -24(t6)               ; ...
        sd    zero, v_nret(zero)        ; ...
        sd    a0, -32(t6)               ; the method
        bnez  a2, act_bmark             ; a block: flag 1, no serial
        ld    t1, v_serial(zero)        ; a method: a serial, and flags from its primitive
        addi  t1, t1, 1                 ; ...
        sd    t1, v_serial(zero)        ; ...
        slli  t1, t1, 5                 ; ...
        srli  t2, t0, 24                ; the primitive
        andi  t2, t2, 4095              ; ...
        li    t5, 198                   ; ensure: / ifCurtailed:
        bne   t2, t5, act_m1            ; ...
        ori   t1, t1, 2                 ; ...
act_m1:
        li    t5, 199                   ; on:do:
        bne   t2, t5, act_m2            ; ...
        ori   t1, t1, 4                 ; ...
act_m2:
        mv    t2, t3                    ; self: the receiver
        ld    t2, 8(t2)                 ; ...
        j     act_mark                  ; ...
act_bmark:
        li    t1, 1                     ; a block's frame
        sd    t0, v_tmp1(zero)          ; (self: the closure's slot 1)
        sd    t3, v_tmp2(zero)          ; ...
        sd    t6, v_tmp3(zero)          ; ...
        sd    a0, v_tmp0(zero)          ; ...
        mv    a0, a2                    ; ...
        li    a1, 1                     ; ...
        call  oload                     ; ...
        mv    t2, a0                    ; ...
        ld    a0, v_tmp0(zero)          ; ...
        ld    t0, v_tmp1(zero)          ; ...
        ld    t3, v_tmp2(zero)          ; ...
        ld    t6, v_tmp3(zero)          ; ...
        li    t1, 1                     ; ...
act_mark:
        slli  t1, t1, 1                 ; serial and flags, as a SmallInteger
        ori   t1, t1, 1                 ; ...
        sd    t1, -40(t6)               ; ...
        sd    t2, -48(t6)               ; self
        addi  sp, t6, -48               ; the operands start below
        mv    s1, t3                    ; the new frame
        mv    s2, t6                    ; ...
        mv    s4, t2                    ; ...
        call  mc_get                    ; a0 = the method's cache entry
        mv    s3, a0                    ; ...
        addi  s10, a0, 32               ; the literals
        ld    t0, 24(a0)                ; the code: after them
        srli  t0, t0, 17                ; ...
        andi  t0, t0, 255               ; ...
        slli  t0, t0, 3                 ; ...
        add   s0, s10, t0               ; ...
        ld    t0, 8(s3)                 ; native code: run it
        bnez  t0, act_native            ; ...
        j     act_count                 ; ...

; the stack is full: its oldest frames go out to the far stack, then again
act_spill:
        sd    a0, v_sp0(zero)           ; the method (far)
        sd    a1, v_sp1(zero)           ; its header
        sd    a2, v_sp2(zero)           ; the closure, if any (it is pushed: the receiver)
        call  stack_spill               ; a0 = 0, or -1: no room
        bnez  a0, stack_overflow        ; ...
        ld    a0, v_sp0(zero)           ; ...
        ld    a1, v_sp1(zero)           ; ...
        ld    a2, v_sp2(zero)           ; a closure: read again (a scavenge moved it)
        beqz  a2, activate_closure      ; ...
        ld    t0, v_nargs(zero)         ; ...
        slli  t0, t0, 3                 ; ...
        add   t0, t0, sp                ; ...
        ld    a2, 0(t0)                 ; ...
        j     activate_closure          ; ...
stack_overflow:
        ld    t0, v_ovf(zero)           ; already handling one: give up
        bnez  t0, die_ovf               ; ...
        li    t0, 1                     ; ...
        sd    t0, v_ovf(zero)           ; ...
        ld    t0, v_nargs(zero)         ; drop the send, then Stratalk stackOverflow
        slli  t0, t0, 3                 ; (as if it had answered nil)
        add   sp, sp, t0                ; ...
        sd    zero, 0(sp)               ; ...
        ld    t0, v_specials(zero)      ; ...
        addi  a0, t0, 8 + 8 * SP_START_RCVR ; ...
        call  fld                       ; ...
        sd    a0, 0(sp)                 ; (replaces the receiver: the result is dropped)
        ld    t0, v_specials(zero)      ; ...
        addi  a0, t0, 8 + 8 * SP_OVERFLOW ; ...
        call  fld                       ; ...
        li    a1, 0                     ; ...
        j     send                      ; ...
die_ovf:
        la    a0, m_ovf                 ; ...
        li    a1, m_ovf_e - m_ovf       ; ...
        j     die                       ; ...

; ---- returns ---------------------------------------------------------------------

op_retself:
        mv    a0, s4                    ; self
        j     ret_frame                 ; ...
op_blkret:
        ld    a0, 0(sp)                 ; the block's value, to its caller
        j     ret_frame                 ; ...
op_rettop:
        ld    a0, 0(sp)                 ; the value
        ld    t0, -40(s2)               ; a block's frame: from its home method
        andi  t0, t0, 2                 ; ...
        bnez  t0, nonlocal_return       ; ...
; ret_frame(a0 = value): the frame (s1, s2) returns a0 to its caller
ret_frame:
        ld    t1, v_bias(zero)          ; the frame, logical
        add   a1, s2, t1                ; ...
        add   a2, s1, t1                ; ...
; ret_core(a0 = value, a1 = the frame's hp, a2 = its fp, logical): it
; returns a0 to its caller; the frames below it are dropped. The caller's
; frame comes back from the far stack if it was paged out.
ret_core:
        sd    a0, v_rv(zero)            ; ...
        sd    a1, v_rh(zero)            ; ...
        sd    a2, v_rf(zero)            ; ...
        addi  a0, a1, -16               ; the caller's hp
        call  f_rd                      ; ...
        beqz  a0, vm_exit               ; none: the end
        sd    a0, v_rch(zero)           ; ...
        ld    a0, v_rh(zero)            ; its fp
        addi  a0, a0, -8                ; ...
        call  f_rd                      ; ...
        sd    a0, v_rcf(zero)           ; ...
        ld    a0, v_rh(zero)            ; its ip offset
        addi  a0, a0, -24               ; ...
        call  f_rd                      ; ...
        srai  s11, a0, 1                ; ...
        ld    a0, v_rf(zero)            ; the stack from the receiver's slot up
        addi  a0, a0, 8                 ; ... to the caller's own receiver
        ld    a1, v_rcf(zero)           ; ...
        addi  a1, a1, 16                ; ...
        ld    t0, v_bias(zero)          ; all in the D-LS?
        li    t1, 0x10000               ; ...
        add   t1, t1, t0                ; ...
        bleu  a1, t1, rc_in             ; ...
        call  ensure_res                ; no: page it in
rc_in:
        sd    zero, v_nret(zero)        ; (a send from native code ends here too)
        ld    t0, v_bias(zero)          ; ...
        ld    t1, v_rf(zero)            ; the receiver's slot takes the result
        addi  t1, t1, 8                 ; ...
        sub   sp, t1, t0                ; ...
        ld    a0, v_rv(zero)            ; ...
        sd    a0, 0(sp)                 ; ...
        ld    s1, v_rcf(zero)           ; the caller's frame
        sub   s1, s1, t0                ; ...
        ld    s2, v_rch(zero)           ; ...
        sub   s2, s2, t0                ; ...
        ld    s4, -48(s2)               ; its self
        ld    a0, -32(s2)               ; its method's entry
        call  mc_get                    ; ...
        mv    s3, a0                    ; ...
        addi  s10, a0, 32               ; ...
        li    t0, NATIVE                ; back into native code?
        bgeu  s11, t0, rc_native        ; ...
        add   s0, a0, s11               ; ...
        ld    t0, v_ovf(zero)           ; out of an overflow? (nothing paged out, room)
        beqz  t0, next                  ; ...
        ld    t0, v_bias(zero)          ; ...
        li    t1, BIAS0                 ; ...
        bne   t0, t1, next              ; ...
        li    t0, STACK_LIMIT + 2048    ; ...
        bltu  sp, t0, next              ; ...
        sd    zero, v_ovf(zero)         ; ...
        j     next                      ; ...
rc_native:
        sub   t0, s11, t0               ; the far address, as a far link
        li    t1, 1                     ; ...
        slli  t1, t1, 63                ; ...
        or    t0, t0, t1                ; ...
        xret  t0                        ; ...
vm_exit:
        li    a0, 0                     ; the start method returned
        call  sys_exit                  ; ...

; nonlocal_return(a0 = value): ^ in a block returns from the method the
; block is in, if that is still running, through no ensure: blocks
nonlocal_return:
        sd    a0, v_tmp0(zero)          ; the value
        ld    a0, 8(s1)                 ; the closure: the home's hp and serial
        li    a1, 2                     ; ...
        call  oload                     ; ...
        srai  t0, a0, 1                 ; ...
        sd    t0, v_tmp1(zero)          ; home hp
        ld    a0, 8(s1)                 ; ...
        li    a1, 3                     ; ...
        call  oload                     ; ...
        srai  t0, a0, 1                 ; ...
        sd    t0, v_tmp2(zero)          ; home serial
        ld    t0, v_bias(zero)          ; walk up from here (logical)
        add   t0, s2, t0                ; ...
        sd    t0, v_tmp3(zero)          ; ...
nlr_walk:
        ld    t1, v_tmp3(zero)          ; ...
        beqz  t1, nlr_dead              ; the bottom: the home has returned
        ld    t3, v_tmp1(zero)          ; ...
        beq   t1, t3, nlr_found         ; ...
        addi  a0, t1, -40               ; an ensure: on the way?
        call  f_rd                      ; ...
        srli  t2, a0, 1                 ; ...
        andi  t2, t2, 10                ; ...
        li    t4, 2                     ; ...
        beq   t2, t4, nlr_unwind        ; ...
        ld    a0, v_tmp3(zero)          ; the caller
        addi  a0, a0, -16               ; ...
        call  f_rd                      ; ...
        sd    a0, v_tmp3(zero)          ; ...
        j     nlr_walk                  ; ...
nlr_found:
        addi  a0, t1, -40               ; the same frame (its serial)?
        call  f_rd                      ; ...
        srli  t4, a0, 6                 ; ...
        ld    t5, v_tmp2(zero)          ; ...
        bne   t4, t5, nlr_dead          ; no: another one took its place
        andi  t2, a0, 2                 ; and a method's
        bnez  t2, nlr_dead              ; ...
        ld    a0, v_tmp1(zero)          ; return from it
        call  frame_fp_l                ; ...
        mv    a2, a0                    ; ...
        ld    a1, v_tmp1(zero)          ; ...
        ld    a0, v_tmp0(zero)          ; ...
        j     ret_core                  ; ...
nlr_dead:
        ld    t0, 8(s1)                 ; closure cannotReturn: value
        addi  sp, sp, -16               ; ...
        sd    t0, 8(sp)                 ; ...
        ld    t0, v_tmp0(zero)          ; ...
        sd    t0, 0(sp)                 ; ...
        ld    t0, v_specials(zero)      ; ...
        addi  a0, t0, 8 + 8 * SP_CANNOTRET ; ...
        call  fld                       ; ...
        li    a1, 1                     ; ...
        j     send                      ; ...
nlr_unwind:
        ld    t0, 8(s1)                 ; closure unwindAndReturn: value to: home
        addi  sp, sp, -24               ; ...
        sd    t0, 16(sp)                ; ...
        ld    t0, v_tmp0(zero)          ; ...
        sd    t0, 8(sp)                 ; ...
        ld    t0, v_tmp1(zero)          ; ...
        slli  t0, t0, 1                 ; ...
        ori   t0, t0, 1                 ; ...
        sd    t0, 0(sp)                 ; ...
        ld    t0, v_specials(zero)      ; ...
        addi  a0, t0, 8 + 8 * SP_UNWIND ; ...
        call  fld                       ; ...
        li    a1, 2                     ; ...
        j     send                      ; ...

; frame_fp_l(a0 = a frame's hp, logical) -> a0 = its fp, logical:
; hp + 8 (nargs + temps - 1)
frame_fp_l:
        sd    ra, v_ra2(zero)           ; ...
        sd    a0, v_fpl(zero)           ; ...
        addi  a0, a0, -32               ; its method
        call  f_rd                      ; ...
        addi  a0, a0, 8                 ; its header (slot 0)
        call  fld                       ; ...
        srai  a0, a0, 1                 ; ...
        andi  t0, a0, 255               ; nargs
        srli  t1, a0, 8                 ; temps
        andi  t1, t1, 255               ; ...
        add   t0, t0, t1                ; ...
        addi  t0, t0, -1                ; ...
        slli  t0, t0, 3                 ; ...
        ld    a0, v_fpl(zero)           ; ...
        add   a0, a0, t0                ; ...
        ld    ra, v_ra2(zero)           ; ...
        ret                             ; ...

; ---- the stack in pages: frames have logical addresses (D-LS address +
; v_bias); the D-LS holds those below 0x10000 + v_bias, the far stack (the
; top FSSIZE bytes of the heap's arena) those above, up to LTOP.

; f_rd(a0 = a logical address in a frame) -> a0 = the word there
f_rd:
        ld    t0, v_bias(zero)          ; in the D-LS?
        li    t1, 0x10000               ; ...
        add   t1, t1, t0                ; ...
        bgeu  a0, t1, frd_far           ; ...
        sub   a0, a0, t0                ; ...
        ld    a0, 0(a0)                 ; ...
        ret                             ; ...
frd_far:
        ld    t0, v_fsoff(zero)         ; on the far stack
        add   a0, a0, t0                ; ...
        j     fld                       ; ...
; f_wr(a0 = a logical address, a1 = a word)
f_wr:
        ld    t0, v_bias(zero)          ; ...
        li    t1, 0x10000               ; ...
        add   t1, t1, t0                ; ...
        bgeu  a0, t1, fwr_far           ; ...
        sub   a0, a0, t0                ; ...
        sd    a1, 0(a0)                 ; ...
        ret                             ; ...
fwr_far:
        ld    t0, v_fsoff(zero)         ; ...
        add   a0, a0, t0                ; ...
        j     fsd                       ; ...

; stack_spill() -> a0 = 0, or -1 (no room): the frames above the current
; one (its receiver's slot and up) go out to the far stack in one transfer
; (after a scavenge: what goes out refers to nothing near); the rest of the
; stack moves up to the top of the D-LS.
stack_spill:
        sd    ra, v_ra8(zero)           ; ...
        beqz  s2, ssp_none              ; no frame yet
        ld    t0, v_bias(zero)          ; lo: above the current frame
        addi  t1, s1, 16                ; ...
        li    t2, 0x10000               ; ...
        bgeu  t1, t2, ssp_none          ; nothing above it: no room
        add   t1, t1, t0                ; (logical)
        sd    t1, v_sp3(zero)           ; ...
        li    t2, LTOP                  ; the far stack's room
        sub   t2, t2, t1                ; ...
        li    t3, FSSIZE                ; ...
        bgtu  t2, t3, ssp_none          ; ...
        call  scavenge                  ; nothing near goes out
        ld    t0, v_bias(zero)          ; ...
        ld    t1, v_sp3(zero)           ; ...
        sub   t3, t1, t0                ; D: [t3, 0x10000)
        li    t4, 0x10000               ; ...
        sub   t5, t4, t3                ; n bytes
        sd    t5, v_sp4(zero)           ; ...
        ld    t2, v_fsoff(zero)         ; far
        add   t2, t2, t1                ; ...
        tput  tg3, t3, c6, t2, t5       ; out
        mv    a0, t2                    ; no stale line of it stays cached
        add   a1, t2, t5                ; ...
        call  fc_forget                 ; ...
        ld    t5, v_sp4(zero)           ; move the rest up by n
        ld    t0, v_bias(zero)          ; ...
        ld    t1, v_sp3(zero)           ; ...
        sub   t3, t1, t0                ; ...
ssp_move:
        addi  t3, t3, -8                ; (downward: the regions overlap)
        bltu  t3, sp, ssp_moved         ; ...
        ld    t4, 0(t3)                 ; (waits while the transfer still reads it)
        add   t6, t3, t5                ; ...
        sd    t4, 0(t6)                 ; ...
        j     ssp_move                  ; ...
ssp_moved:
        add   sp, sp, t5                ; ...
        add   s1, s1, t5                ; ...
        add   s2, s2, t5                ; ...
        sub   t0, t0, t5                ; ...
        sd    t0, v_bias(zero)          ; ...
        ld    t0, v_nspill(zero)        ; counted
        addi  t0, t0, 1                 ; ...
        sd    t0, v_nspill(zero)        ; ...
        li    a0, 0                     ; ...
        ld    ra, v_ra8(zero)           ; ...
        ret                             ; ...
ssp_none:
        li    a0, -1                    ; ...
        ld    ra, v_ra8(zero)           ; ...
        ret                             ; ...

; ensure_res(a0 = lo, a1 = hi, logical): [lo, hi) in the D-LS, at its top:
; what is below lo is dropped (returns only). What is in the D-LS from lo
; goes out, then [lo, top) comes in.
ensure_res:
        sd    ra, v_ra8(zero)           ; ...
        sd    a0, v_sp3(zero)           ; ...
        addi  t0, a0, 4096              ; top: hi, or lo + 4 KiB, at most LTOP
        bgeu  a1, t0, er_1              ; ...
        mv    a1, t0                    ; ...
er_1:
        li    t0, LTOP                  ; ...
        bleu  a1, t0, er_2              ; ...
        mv    a1, t0                    ; ...
er_2:
        sd    a1, v_sp4(zero)           ; ...
        sub   t0, a1, a0                ; it must fit
        li    t1, 0x10000 - STACK_LIMIT - 1024 ; ...
        bgtu  t0, t1, die_ovf           ; ...
        ld    t0, v_bias(zero)          ; the D-LS part from lo out first
        li    t1, 0x10000               ; ...
        add   t1, t1, t0                ; rtop
        bgeu  a0, t1, er_in             ; none
        sub   t2, a0, t0                ; D
        sub   t3, t1, a0                ; bytes
        ld    t4, v_fsoff(zero)         ; far
        add   t4, t4, a0                ; ...
        tput  tg3, t2, c6, t4, t3       ; ...
        mv    a0, t4                    ; ...
        add   a1, t4, t3                ; ...
        call  fc_forget                 ; ...
er_in:
        ld    a1, v_sp4(zero)           ; the new bias: top at 0x10000
        li    t0, 0x10000               ; ...
        sub   t0, a1, t0                ; ...
        sd    t0, v_bias(zero)          ; ...
        ld    a0, v_sp3(zero)           ; [lo, top) in
        sub   t2, a0, t0                ; ...
        sub   t3, a1, a0                ; ...
        ld    t4, v_fsoff(zero)         ; ...
        add   t4, t4, a0                ; ...
        tget  tg3, t2, c6, t4, t3       ; (loads of it wait for it)
        ld    t0, v_nfill(zero)         ; counted
        addi  t0, t0, 1                 ; ...
        sd    t0, v_nfill(zero)         ; ...
        ld    ra, v_ra8(zero)           ; ...
        ret                             ; ...

; ---- the special selectors: the SmallInteger cases here, the rest sent ----------

op_sendsp:
        lbu   t0, 1(s0)                 ; k
        addi  s0, s0, 2                 ; ...
        li    t1, 15                    ; ==
        beq   t0, t1, sp_eq             ; ...
        li    t1, 26                    ; ~~
        beq   t0, t1, sp_ne             ; ...
        li    t1, 16                    ; class
        beq   t0, t1, sp_class          ; ...
        li    t1, 14                    ; the arithmetic ones need two SmallIntegers
        bgtu  t0, t1, sp_send           ; ...
        ld    a1, 0(sp)                 ; b
        ld    a0, 8(sp)                 ; a
        and   t1, a0, a1                ; ...
        andi  t1, t1, 1                 ; ...
        beqz  t1, sp_send               ; ...
        slli  t1, t0, 2                 ; ...
        la    t2, sptab                 ; ...
        add   t1, t1, t2                ; ...
        jr    t1                        ; ...
sptab:
        j     sp_add                    ; 0 +
        j     sp_sub                    ; 1 -
        j     sp_lt                     ; 2 <
        j     sp_gt                     ; 3 >
        j     sp_le                     ; 4 <=
        j     sp_ge                     ; 5 >=
        j     sp_eq                     ; 6 =
        j     sp_ne                     ; 7 ~=
        j     sp_mul                    ; 8 *
        j     sp_send                   ; 9 /
        j     sp_send                   ; 10 \\
        j     sp_send                   ; 11 //
        j     sp_and                    ; 12 bitAnd:
        j     sp_or                     ; 13 bitOr:
        j     sp_send                   ; 14 bitShift:
sp_add:
        add   t2, a0, a1                ; (2x+1) + (2y+1) - 1
        addi  t2, t2, -1                ; ...
        xor   t3, a0, t2                ; overflow: the result's sign differs from both
        xor   t4, a1, t2                ; ...
        and   t3, t3, t4                ; ...
        bltz  t3, sp_send               ; ...
        j     sp_push2                  ; ...
sp_sub:
        sub   t2, a0, a1                ; (2x+1) - (2y+1) + 1
        addi  t2, t2, 1                 ; ...
        xor   t3, a0, a1                ; overflow: operands' signs differ, and the result's from a's
        xor   t4, a0, t2                ; ...
        and   t3, t3, t4                ; ...
        bltz  t3, sp_send               ; ...
        j     sp_push2                  ; ...
sp_mul:
        srai  t3, a0, 1                 ; x
        srai  t4, a1, 1                 ; y
        slli  t5, t3, 32                ; both within 32 bits: the product fits
        srai  t5, t5, 32                ; ...
        bne   t5, t3, sp_send           ; ...
        slli  t5, t4, 32                ; ...
        srai  t5, t5, 32                ; ...
        bne   t5, t4, sp_send           ; ...
        mul   t2, t3, t4                ; ...
        slli  t2, t2, 1                 ; ...
        ori   t2, t2, 1                 ; ...
        j     sp_push2                  ; ...
sp_and:
        and   t2, a0, a1                ; the tag survives
        j     sp_push2                  ; ...
sp_or:
        or    t2, a0, a1                ; ...
        j     sp_push2                  ; ...
sp_lt:
        blt   a0, a1, sp_true           ; ...
        j     sp_false                  ; ...
sp_gt:
        blt   a1, a0, sp_true           ; ...
        j     sp_false                  ; ...
sp_le:
        bge   a1, a0, sp_true           ; ...
        j     sp_false                  ; ...
sp_ge:
        bge   a0, a1, sp_true           ; ...
        j     sp_false                  ; ...
sp_eq:
        ld    a1, 0(sp)                 ; identity (SmallIntegers: equality)
        ld    a0, 8(sp)                 ; ...
        beq   a0, a1, sp_true           ; ...
        j     sp_false                  ; ...
sp_ne:
        ld    a1, 0(sp)                 ; ...
        ld    a0, 8(sp)                 ; ...
        bne   a0, a1, sp_true           ; ...
        j     sp_false                  ; ...
sp_true:
        mv    t2, s7                    ; ...
        j     sp_push2                  ; ...
sp_false:
        mv    t2, s8                    ; ...
sp_push2:
        addi  sp, sp, 8                 ; two operands, one result
        sd    t2, 0(sp)                 ; ...
        j     next                      ; ...
sp_class:
        ld    a0, 0(sp)                 ; the receiver's class
        call  oclass                    ; ...
        mv    a1, a0                    ; ...
        ld    a0, v_classes(zero)       ; ...
        call  oload                     ; ...
        sd    a0, 0(sp)                 ; ...
        j     next                      ; ...
sp_send:
        sd    t0, v_tmp0(zero)          ; the selector from the table, sent
        ld    a0, v_spsels(zero)        ; ...
        mv    a1, t0                    ; ...
        call  oload                     ; ...
        ld    t0, v_tmp0(zero)          ; its argument count
        la    t1, spnargs               ; ...
        add   t1, t1, t0                ; ...
        lbu   a1, 0(t1)                 ; ...
        j     send                      ; ...

