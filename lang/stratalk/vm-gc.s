; =============================================================================
; vm-gc.s: the far heap's allocator and its collector (mark and sweep)
; =============================================================================
;
; Far memory is allocated first fit from a list of free chunks (a free
; chunk: a header of format 15 and its next chunk's address in slot 0,
; kept in far memory), then from the heap's top. The top RESERVE bytes
; are kept for the scavenger, so that the survivors of a full nursery can
; always go out. When it had to use them, the full collector runs at the
; end of that scavenge (the nursery and the remembered set are empty then):
; mark everything the roots reach (a mark bit in each far header, written
; through), then sweep the heap from bottom to top, one header after the
; other through the far cache, and make every run of dead objects one free
; chunk. Nothing moves.

F_FREE     = 15                         ; a free chunk, or filler (no slots)
RESERVE    = NURSERY + 64               ; the scavenger's room at the top

; falloc(a0 = bytes, a multiple of 8; a1 = 1: the reserve may be used)
; -> a0 = the far address, or 0. Uses a2..a5, v_gc*.
falloc:
        sd    ra, v_ra9(zero)           ; ...
        sd    a0, v_gc0(zero)           ; n
        sd    a1, v_gc1(zero)           ; ...
        sd    zero, v_gc2(zero)         ; the previous chunk (0: the list's head)
        ld    a4, v_free(zero)          ; the first chunk
fa_loop:
        beqz  a4, fa_top                ; none fits: the top
        mv    a0, a4                    ; its size
        call  fld                       ; ...
        srli  a5, a0, SIZE_SHIFT        ; ...
        slli  a5, a5, 3                 ; ...
        addi  a5, a5, 8                 ; ...
        ld    t0, v_gc0(zero)           ; enough?
        bgeu  a5, t0, fa_take           ; ...
        sd    a4, v_gc2(zero)           ; no: the next
        addi  a0, a4, 8                 ; ...
        call  fld                       ; ...
        mv    a4, a0                    ; ...
        j     fa_loop                   ; ...
fa_take:
        addi  a0, a4, 8                 ; the next chunk
        call  fld                       ; ...
        mv    a3, a0                    ; a3 = next
        ld    t0, v_gc0(zero)           ; the rest
        sub   t1, a5, t0                ; ...
        li    t2, 16                    ; a chunk of its own: it takes this one's place
        bltu  t1, t2, fa_small          ; ...
        add   a2, a4, t0                ; a2 = the rest's address
        addi  t1, t1, -8                ; its header: free, (rest - 8) / 8 slots
        srli  t1, t1, 3                 ; ...
        slli  a1, t1, SIZE_SHIFT        ; ...
        li    t2, F_FREE << 16          ; ...
        or    a1, a1, t2                ; ...
        mv    a0, a2                    ; ...
        call  fsd                       ; ...
        addi  a0, a2, 8                 ; its next
        mv    a1, a3                    ; ...
        call  fsd                       ; ...
        mv    a3, a2                    ; the link: to the rest
        j     fa_link                   ; ...
fa_small:
        beqz  t1, fa_link               ; exactly: the link to the next
        add   a0, a4, t0                ; 8 bytes left: a filler header
        li    a1, F_FREE << 16          ; ...
        call  fsd                       ; ...
fa_link:
        ld    t0, v_gc2(zero)           ; the previous chunk's link (or the head) := a3
        bnez  t0, fa_lk1                ; ...
        sd    a3, v_free(zero)          ; ...
        j     fa_got                    ; ...
fa_lk1:
        addi  a0, t0, 8                 ; ...
        mv    a1, a3                    ; ...
        call  fsd                       ; ...
fa_got:
        mv    a0, a4                    ; ...
        ld    ra, v_ra9(zero)           ; ...
        ret                             ; ...
fa_top:
        ld    t0, v_htop(zero)          ; from the top
        ld    t1, v_gc0(zero)           ; ...
        add   t2, t0, t1                ; ...
        ld    t3, v_hsize(zero)         ; (less the reserve, unless it may be used)
        ld    t4, v_gc1(zero)           ; ...
        bnez  t4, fa_t1                 ; ...
        li    t4, RESERVE               ; ...
        sub   t3, t3, t4                ; ...
fa_t1:
        bgtu  t2, t3, fa_none           ; ...
        sd    t2, v_htop(zero)          ; ...
        mv    a0, t0                    ; ...
        ld    ra, v_ra9(zero)           ; ...
        ret                             ; ...
fa_none:
        li    a0, 0                     ; ...
        ld    ra, v_ra9(zero)           ; ...
        ret                             ; ...

; ---- the full collection -------------------------------------------------------------

; full_gc(): mark and sweep the far heap. The nursery must be empty (a
; scavenge just ran). Empties the method and lookup caches (methods may
; have died), and finds the running method again.
full_gc:
        sd    ra, v_ra10(zero)          ; ...
        sd    zero, v_nmark(zero)       ; ...
        sd    zero, v_movf(zero)        ; ...
        ld    a0, v_specials(zero)      ; the roots: the specials (classes, globals, symbols)
        call  gm_mark                   ; ...
        mv    a4, sp                    ; the stack in the D-LS
        li    a5, 0x10000               ; ...
gc_stk:
        bgeu  a4, a5, gc_stk_d          ; ...
        ld    a0, 0(a4)                 ; ...
        call  gm_mark                   ; ...
        addi  a4, a4, 8                 ; ...
        j     gc_stk                    ; ...
gc_stk_d:
        ld    a4, v_bias(zero)          ; the far stack: [rtop, LTOP)
        li    t0, 0x10000               ; ...
        add   a4, a4, t0                ; ...
        li    a5, LTOP                  ; ...
gc_fs:
        bgeu  a4, a5, gc_fs_d           ; ...
        ld    a0, v_fsoff(zero)         ; ...
        add   a0, a0, a4                ; ...
        call  fld                       ; ...
        call  gm_mark                   ; ...
        addi  a4, a4, 8                 ; ...
        j     gc_fs                     ; ...
gc_fs_d:
        la    a4, v_roots               ; the VM's roots
        addi  a5, a4, 32                ; ...
gc_vr:
        bgeu  a4, a5, gc_vr_d           ; ...
        ld    a0, 0(a4)                 ; ...
        call  gm_mark                   ; ...
        addi  a4, a4, 8                 ; ...
        j     gc_vr                     ; ...
gc_vr_d:
        mv    a0, s4                    ; self
        call  gm_mark                   ; ...
gc_drain:
        call  gm_drain                  ; through everything marked
        ld    t0, v_movf(zero)          ; the mark stack overflowed: again over the heap
        beqz  t0, gc_sweep              ; ...
        sd    zero, v_movf(zero)        ; ...
        li    a4, 64                    ; every marked object's children
gc_rescan:
        ld    t0, v_htop(zero)          ; ...
        bgeu  a4, t0, gc_drain          ; ...
        mv    a0, a4                    ; ...
        call  fld                       ; ...
        sd    a0, v_gc3(zero)           ; ...
        srli  t1, a0, MARK_BIT          ; ...
        andi  t1, t1, 1                 ; ...
        beqz  t1, gc_rs_n               ; ...
        mv    a0, a4                    ; ...
        call  gm_children               ; ...
gc_rs_n:
        ld    t0, v_gc3(zero)           ; next
        srli  t0, t0, SIZE_SHIFT        ; ...
        slli  t0, t0, 3                 ; ...
        addi  t0, t0, 8                 ; ...
        add   a4, a4, t0                ; ...
        j     gc_rescan                 ; ...
gc_sweep:
        ; every object from the bottom: the marked ones lose the mark, runs of
        ; the others (and of free chunks) become one free chunk each
        sd    zero, v_free(zero)        ; a new list
        sd    zero, v_gc4(zero)         ; the run's start (0: none)
        li    a4, 64                    ; ...
gc_sw:
        ld    t0, v_htop(zero)          ; ...
        bgeu  a4, t0, gc_sw_end         ; ...
        mv    a0, a4                    ; ...
        call  fld                       ; ...
        mv    a5, a0                    ; a5 = the header
        srli  t0, a5, SIZE_SHIFT        ; t0 = its bytes
        slli  t0, t0, 3                 ; ...
        addi  t0, t0, 8                 ; ...
        sd    t0, v_gc5(zero)           ; ...
        srli  t1, a5, 16                ; free already?
        andi  t1, t1, 15                ; ...
        li    t2, F_FREE                ; ...
        beq   t1, t2, gc_dead           ; ...
        srli  t1, a5, MARK_BIT          ; marked: it lives
        andi  t1, t1, 1                 ; ...
        beqz  t1, gc_dead               ; ...
        call  gc_endrun                 ; (a run before it ends here)
        li    t1, 1                     ; unmark
        slli  t1, t1, MARK_BIT          ; ...
        xor   a1, a5, t1                ; ...
        mv    a0, a4                    ; ...
        call  fsd                       ; ...
        j     gc_sw_n                   ; ...
gc_dead:
        ld    t1, v_gc4(zero)           ; dead: in a run
        bnez  t1, gc_dd                 ; ...
        sd    a4, v_gc4(zero)           ; (it starts here)
gc_dd:
        ld    t1, v_freed(zero)         ; counted (free chunks included: they are found again)
        srli  t2, a5, 16                ; ...
        andi  t2, t2, 15                ; ...
        li    t3, F_FREE                ; ...
        beq   t2, t3, gc_sw_n           ; ...
        ld    t0, v_gc5(zero)           ; ...
        add   t1, t1, t0                ; ...
        sd    t1, v_freed(zero)         ; ...
gc_sw_n:
        ld    t0, v_gc5(zero)           ; next
        add   a4, a4, t0                ; ...
        j     gc_sw                     ; ...
gc_sw_end:
        ld    t0, v_gc4(zero)           ; a run up to the top: the top comes down
        beqz  t0, gc_done               ; ...
        sd    t0, v_htop(zero)          ; ...
        sd    zero, v_gc4(zero)         ; ...
gc_done:
        call  lc_flush                  ; methods may have died: look up again
        call  mc_flush                  ; ...
        call  reload_entry              ; ...
        ld    t0, v_ngc(zero)           ; counted
        addi  t0, t0, 1                 ; ...
        sd    t0, v_ngc(zero)           ; ...
        ld    ra, v_ra10(zero)          ; ...
        ret                             ; ...

; gc_endrun(): the run of dead bytes [v_gc4, a4) becomes a free chunk (or a
; filler, 8 bytes), put at the head of the list. Keeps a4, a5.
gc_endrun:
        ld    t0, v_gc4(zero)           ; ...
        beqz  t0, ger_ret               ; no run
        sd    ra, v_ra11(zero)          ; ...
        sub   t1, a4, t0                ; its bytes
        addi  t1, t1, -8                ; slots
        srli  t1, t1, 3                 ; ...
        slli  a1, t1, SIZE_SHIFT        ; a free header
        li    t2, F_FREE << 16          ; ...
        or    a1, a1, t2                ; ...
        sd    t1, v_gc6(zero)           ; ...
        mv    a0, t0                    ; ...
        call  fsd                       ; ...
        ld    t1, v_gc6(zero)           ; a chunk (at least a slot): into the list
        beqz  t1, ger_done              ; ...
        ld    a0, v_gc4(zero)           ; its next: the list's head
        addi  a0, a0, 8                 ; ...
        ld    a1, v_free(zero)          ; ...
        call  fsd                       ; ...
        ld    t0, v_gc4(zero)           ; ...
        sd    t0, v_free(zero)          ; ...
ger_done:
        sd    zero, v_gc4(zero)         ; ...
        ld    ra, v_ra11(zero)          ; ...
ger_ret:
        ret                             ; ...

; gm_mark(a0 = a reference): a far object in the heap, not marked yet, is
; marked (through the cache) and pushed. Uses t0..t3.
gm_mark:
        andi  t0, a0, 7                 ; far
        bnez  t0, gmm_ret               ; ...
        li    t0, 64                    ; in the heap (frame words above it are not objects)
        bltu  a0, t0, gmm_ret           ; ...
        ld    t0, v_htop(zero)          ; ...
        bgeu  a0, t0, gmm_ret           ; ...
        sd    ra, v_ra12(zero)          ; ...
        sd    a0, v_gc7(zero)           ; ...
        call  fld                       ; marked?
        srli  t1, a0, MARK_BIT          ; ...
        andi  t1, t1, 1                 ; ...
        bnez  t1, gmm_back              ; ...
        li    t1, 1                     ; mark it
        slli  t1, t1, MARK_BIT          ; ...
        or    a1, a0, t1                ; ...
        ld    a0, v_gc7(zero)           ; ...
        call  fsd                       ; ...
        ld    t2, v_nmark(zero)         ; push it
        li    t3, MARK_N                ; ...
        bgeu  t2, t3, gmm_ovf           ; ...
        slli  t3, t2, 3                 ; ...
        la    t1, markstk               ; ...
        add   t3, t3, t1                ; ...
        ld    t1, v_gc7(zero)           ; ...
        sd    t1, 0(t3)                 ; ...
        addi  t2, t2, 1                 ; ...
        sd    t2, v_nmark(zero)         ; ...
        j     gmm_back                  ; ...
gmm_ovf:
        li    t1, 1                     ; no room: found again by the rescan
        sd    t1, v_movf(zero)          ; ...
gmm_back:
        ld    ra, v_ra12(zero)          ; ...
gmm_ret:
        ret                             ; ...

; gm_drain(): mark what the pushed objects refer to, until none is left
gm_drain:
        sd    ra, v_ra13(zero)          ; ...
gmd_loop:
        ld    t2, v_nmark(zero)         ; ...
        beqz  t2, gmd_done              ; ...
        addi  t2, t2, -1                ; pop one
        sd    t2, v_nmark(zero)         ; ...
        slli  t3, t2, 3                 ; ...
        la    t1, markstk               ; ...
        add   t3, t3, t1                ; ...
        ld    a0, 0(t3)                 ; ...
        call  gm_children               ; ...
        j     gmd_loop                  ; ...
gmd_done:
        ld    ra, v_ra13(zero)          ; ...
        ret                             ; ...

; gm_children(a0 = a far object): mark its references (named and indexed
; slots; a method's literals). Uses a2, a3.
gm_children:
        sd    ra, v_ra14(zero)          ; ...
        sd    a0, v_gc8(zero)           ; ...
        call  fld                       ; the header
        srli  t1, a0, 16                ; the format
        andi  t1, t1, 15                ; ...
        srli  a3, a0, SIZE_SHIFT        ; slots
        li    t2, F_INDEX               ; pointers: every slot
        bleu  t1, t2, gmc_go            ; ...
        li    t2, F_METHOD              ; a method: the literals (slots 1 .. nlits)
        bne   t1, t2, gmc_done          ; ...
        ld    a0, v_gc8(zero)           ; ...
        addi  a0, a0, 8                 ; ...
        call  fld                       ; ...
        srai  a3, a0, 17                ; ...
        andi  a3, a3, 255               ; ...
        addi  a3, a3, 1                 ; ...
gmc_go:
        li    a2, 0                     ; slot i
gmc_loop:
        bgeu  a2, a3, gmc_done          ; ...
        ld    a0, v_gc8(zero)           ; ...
        slli  t0, a2, 3                 ; ...
        add   a0, a0, t0                ; ...
        addi  a0, a0, 8                 ; ...
        call  fld                       ; ...
        call  gm_mark                   ; ...
        addi  a2, a2, 1                 ; ...
        j     gmc_loop                  ; ...
gmc_done:
        ld    ra, v_ra14(zero)          ; ...
        ret                             ; ...
