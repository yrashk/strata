; ---- SmallIntegers: a1 = receiver, a2 = argument, both SmallIntegers ---------------

; pi_args: one argument, both SmallIntegers, or fail; a1, a2 = them
pi_args:
        li    t0, 1                     ; one argument
        bne   a0, t0, prim_fail         ; ...
        ld    a1, 8(sp)                 ; ...
        ld    a2, 0(sp)                 ; ...
        and   t0, a1, a2                ; ...
        andi  t0, t0, 1                 ; ...
        beqz  t0, prim_fail             ; ...
        ret                             ; ...
; pi_box(t2 = a value): a SmallInteger result, or fail if it does not fit
pi_box:
        slli  t3, t2, 1                 ; ...
        srai  t4, t3, 1                 ; it fits if it comes back
        bne   t4, t2, prim_fail         ; ...
        ori   a0, t3, 1                 ; ...
        j     prim_ok                   ; ...
pi_add:
        call  pi_args                   ; ...
        srai  t0, a1, 1                 ; ...
        srai  t1, a2, 1                 ; ...
        add   t2, t0, t1                ; (63-bit operands: no 64-bit overflow)
        j     pi_box                    ; ...
pi_sub:
        call  pi_args                   ; ...
        srai  t0, a1, 1                 ; ...
        srai  t1, a2, 1                 ; ...
        sub   t2, t0, t1                ; ...
        j     pi_box                    ; ...
pi_mul:
        call  pi_args                   ; ...
        srai  t0, a1, 1                 ; ...
        srai  t1, a2, 1                 ; ...
        beqz  t0, pim_zero              ; ...
        mul   t2, t0, t1                ; the product, if it did not overflow:
        div   t3, t2, t0                ;   it divides back
        bne   t3, t1, prim_fail         ; ...
        li    t3, -1                    ; (-1 * minimum overflows and divides back)
        bne   t0, t3, pi_box            ; ...
        slli  t3, t3, 63                ; ...
        beq   t1, t3, prim_fail         ; ...
        j     pi_box                    ; ...
pim_zero:
        li    t2, 0                     ; ...
        j     pi_box                    ; ...
pi_div:
        call  pi_args                   ; exact only
        srai  t0, a1, 1                 ; ...
        srai  t1, a2, 1                 ; ...
        beqz  t1, prim_fail             ; ...
        rem   t3, t0, t1                ; ...
        bnez  t3, prim_fail             ; ...
        div   t2, t0, t1                ; ...
        j     pi_box                    ; ...
pi_quo:
        call  pi_args                   ; toward zero
        srai  t0, a1, 1                 ; ...
        srai  t1, a2, 1                 ; ...
        beqz  t1, prim_fail             ; ...
        div   t2, t0, t1                ; ...
        j     pi_box                    ; ...
pi_rem:
        call  pi_args                   ; ...
        srai  t0, a1, 1                 ; ...
        srai  t1, a2, 1                 ; ...
        beqz  t1, prim_fail             ; ...
        rem   t2, t0, t1                ; ...
        j     pi_box                    ; ...
pi_idiv:
        call  pi_args                   ; toward minus infinity
        srai  t0, a1, 1                 ; ...
        srai  t1, a2, 1                 ; ...
        beqz  t1, prim_fail             ; ...
        div   t2, t0, t1                ; ...
        rem   t3, t0, t1                ; a remainder of the other sign: one less
        beqz  t3, pi_box                ; ...
        xor   t4, t3, t1                ; ...
        bgez  t4, pi_box                ; ...
        addi  t2, t2, -1                ; ...
        j     pi_box                    ; ...
pi_mod:
        call  pi_args                   ; the sign of the divisor
        srai  t0, a1, 1                 ; ...
        srai  t1, a2, 1                 ; ...
        beqz  t1, prim_fail             ; ...
        rem   t2, t0, t1                ; ...
        beqz  t2, pi_box                ; ...
        xor   t4, t2, t1                ; ...
        bgez  t4, pi_box                ; ...
        add   t2, t2, t1                ; ...
        j     pi_box                    ; ...
pi_and:
        call  pi_args                   ; ...
        and   a0, a1, a2                ; ...
        j     prim_ok                   ; ...
pi_or:
        call  pi_args                   ; ...
        or    a0, a1, a2                ; ...
        j     prim_ok                   ; ...
pi_xor:
        call  pi_args                   ; ...
        xor   a0, a1, a2                ; ...
        ori   a0, a0, 1                 ; ...
        j     prim_ok                   ; ...
pi_shift:
        call  pi_args                   ; ...
        srai  t0, a1, 1                 ; ...
        srai  t1, a2, 1                 ; ...
        bltz  t1, pis_right             ; ...
        li    t3, 63                    ; too far: fail
        bge   t1, t3, prim_fail         ; ...
        sll   t2, t0, t1                ; it must shift back
        sra   t3, t2, t1                ; ...
        bne   t3, t0, prim_fail         ; ...
        j     pi_box                    ; ...
pis_right:
        neg   t1, t1                    ; ...
        li    t3, 63                    ; ...
        blt   t1, t3, pis_r1            ; ...
        mv    t1, t3                    ; ...
pis_r1:
        sra   t2, t0, t1                ; ...
        j     pi_box                    ; ...
pi_lt:
        call  pi_args                   ; ...
        blt   a1, a2, p_true            ; ...
        j     p_false                   ; ...
pi_gt:
        call  pi_args                   ; ...
        blt   a2, a1, p_true            ; ...
        j     p_false                   ; ...
pi_le:
        call  pi_args                   ; ...
        bge   a2, a1, p_true            ; ...
        j     p_false                   ; ...
pi_ge:
        call  pi_args                   ; ...
        bge   a1, a2, p_true            ; ...
        j     p_false                   ; ...
pi_eq:
        call  pi_args                   ; ...
        beq   a1, a2, p_true            ; ...
        j     p_false                   ; ...
pi_ne:
        call  pi_args                   ; ...
        bne   a1, a2, p_true            ; ...
        j     p_false                   ; ...
p_true:
        mv    a0, s7                    ; ...
        j     prim_ok                   ; ...
p_false:
        mv    a0, s8                    ; ...
        j     prim_ok                   ; ...
p_nil:
        li    a0, 0                     ; ...
        j     prim_ok                   ; ...
p_self:
        ld    t0, v_nargs(zero)         ; the receiver
        slli  t0, t0, 3                 ; ...
        add   t0, t0, sp                ; ...
        ld    a0, 0(t0)                 ; ...
        j     prim_ok                   ; ...

; pi_print: a SmallInteger's decimal digits, as a new String
pi_print:
        ld    t0, 0(sp)                 ; the receiver
        andi  t1, t0, 1                 ; ...
        beqz  t1, prim_fail             ; ...
        srai  t0, t0, 1                 ; the value
        la    t5, iobuf + 32            ; digits from the end
        mv    t4, t5                    ; ...
        li    t3, 10                    ; ...
        mv    t2, t0                    ; |value|, digit by digit
pip_loop:
        rem   t1, t2, t3                ; (negative values: negative remainders)
        bgez  t1, pip_pos               ; ...
        neg   t1, t1                    ; ...
pip_pos:
        addi  t1, t1, '0'               ; ...
        addi  t4, t4, -1                ; ...
        sb    t1, 0(t4)                 ; ...
        div   t2, t2, t3                ; ...
        bnez  t2, pip_loop              ; ...
        bgez  t0, pip_done              ; ...
        addi  t4, t4, -1                ; the sign
        li    t1, '-'                   ; ...
        sb    t1, 0(t4)                 ; ...
pip_done:
        sub   a1, t5, t4                ; a1 = length
        mv    a0, t4                    ; a0 = bytes
        call  str_make                  ; a String of them
        j     prim_ok                   ; ...

; str_make(a0 = D-LS bytes, a1 = length) -> a0 = a new String with them
; (the bytes must not be in the nursery)
str_make:
        sd    ra, v_ra3(zero)           ; ...
        sd    a0, v_tmp0(zero)          ; ...
        sd    a1, v_tmp1(zero)          ; ...
        addi  a2, a1, 7                 ; slots
        srli  a2, a2, 3                 ; ...
        slli  a3, a2, 3                 ; unused bytes
        sub   a3, a3, a1                ; ...
        li    a0, CI_STRING             ; ...
        li    a1, F_BYTES               ; ...
        call  anew                      ; ...
        sd    a0, v_tmp2(zero)          ; ...
        li    a1, 0                     ; byte i
sm_loop:
        ld    t0, v_tmp1(zero)          ; ...
        bgeu  a1, t0, sm_done           ; ...
        ld    t0, v_tmp0(zero)          ; ...
        add   t0, t0, a1                ; ...
        lbu   a2, 0(t0)                 ; ...
        ld    a0, v_tmp2(zero)          ; ...
        sd    a1, v_tmp3(zero)          ; ...
        call  obyte_st                  ; ...
        ld    a1, v_tmp3(zero)          ; ...
        addi  a1, a1, 1                 ; ...
        j     sm_loop                   ; ...
sm_done:
        ld    a0, v_tmp2(zero)          ; ...
        ld    ra, v_ra3(zero)           ; ...
        ret                             ; ...

; obyte_ld(a0 = object, a1 = byte offset from slot 0) -> a0 = the byte. Leaf.
obyte_ld:
        andi  t0, a0, 7                 ; near?
        li    t1, 2                     ; ...
        bne   t0, t1, obl_far           ; ...
        add   t0, a0, a1                ; ...
        lbu   a0, 6(t0)                 ; ...
        ret                             ; ...
obl_far:
        sd    a1, v_wbuf(zero)          ; (fld keeps nothing)
        add   a0, a0, a1                ; the word
        addi  a0, a0, 8                 ; ...
        srli  a0, a0, 3                 ; ...
        slli  a0, a0, 3                 ; ...
        sd    ra, v_ra2(zero)           ; ...
        call  fld                       ; ...
        ld    ra, v_ra2(zero)           ; ...
        ld    t0, v_wbuf(zero)          ; its byte
        andi  t0, t0, 7                 ; ...
        slli  t0, t0, 3                 ; ...
        srl   a0, a0, t0                ; ...
        andi  a0, a0, 255               ; ...
        ret                             ; ...

; obyte_st(a0 = object, a1 = byte offset, a2 = byte). Leaf.
obyte_st:
        andi  t0, a0, 7                 ; near?
        li    t1, 2                     ; ...
        bne   t0, t1, obs_far           ; ...
        add   t0, a0, a1                ; ...
        sb    a2, 6(t0)                 ; ...
        ret                             ; ...
obs_far:
        add   a0, a0, a1                ; the word
        addi  a0, a0, 8                 ; ...
        andi  t0, a0, 7                 ; the byte's shift
        slli  t0, t0, 3                 ; ...
        sd    t0, v_ob2(zero)          ; ...
        sd    a2, v_ob1(zero)          ; ...
        srli  a0, a0, 3                 ; ...
        slli  a0, a0, 3                 ; ...
        sd    a0, v_ob0(zero)          ; ...
        sd    ra, v_ra2(zero)           ; ...
        call  fld                       ; read, change, write
        ld    t0, v_ob2(zero)          ; ...
        li    t1, 255                   ; ...
        sll   t1, t1, t0                ; ...
        li    t3, -1                    ; ...
        xor   t1, t1, t3                ; ...
        and   a1, a0, t1                ; ...
        ld    t2, v_ob1(zero)          ; ...
        sll   t2, t2, t0                ; ...
        or    a1, a1, t2                ; ...
        ld    a0, v_ob0(zero)          ; ...
        call  fsd                       ; ...
        ld    ra, v_ra2(zero)           ; ...
        ret                             ; ...

; ---- Characters -------------------------------------------------------------------------

pc_value:
        ld    t0, 0(sp)                 ; the receiver: a Character
        andi  t1, t0, 7                 ; ...
        li    t2, 4                     ; ...
        bne   t1, t2, prim_fail         ; ...
        srli  t0, t0, 3                 ; ...
        slli  a0, t0, 1                 ; ...
        ori   a0, a0, 1                 ; ...
        j     prim_ok                   ; ...
pc_make:
        ld    t0, 0(sp)                 ; the argument
        j     pc_mk                     ; ...
pc_asChar:
        ld    t0, 0(sp)                 ; the receiver
pc_mk:
        andi  t1, t0, 1                 ; a SmallInteger >= 0
        beqz  t1, prim_fail             ; ...
        bltz  t0, prim_fail             ; ...
        srli  t0, t0, 1                 ; ...
        slli  a0, t0, 3                 ; ...
        ori   a0, a0, 4                 ; ...
        j     prim_ok                   ; ...

; ---- objects -------------------------------------------------------------------------

; p_arg0 -> a1 = the receiver, a2 = argument 0, a3 = argument 1 (if any)
p_args:
        slli  t0, a0, 3                 ; ...
        add   t0, t0, sp                ; ...
        ld    a1, 0(t0)                 ; the receiver
        ld    a2, -8(t0)                ; argument 0
        ld    a3, -16(t0)               ; argument 1
        ret                             ; ...

; is_obj(a0 = oop) -> t0 = 1 if a near or far object (not an immediate, not nil)
is_obj:
        andi  t0, a0, 7                 ; ...
        beqz  t0, iso_far               ; ...
        addi  t0, t0, -2                ; near: tag 2
        seqz  t0, t0                    ; ...
        ret                             ; ...
iso_far:
        snez  t0, a0                    ; far, unless nil
        ret                             ; ...

po_eq:
        call  p_args                    ; ...
        beq   a1, a2, p_true            ; ...
        j     p_false                   ; ...
po_class:
        ld    a0, 0(sp)                 ; ...
        call  oclass                    ; ...
        mv    a1, a0                    ; ...
        ld    a0, v_classes(zero)       ; ...
        call  oload                     ; ...
        j     prim_ok                   ; ...
po_hash:
        ld    a0, 0(sp)                 ; ...
        andi  t0, a0, 1                 ; a SmallInteger: itself
        bnez  t0, prim_ok               ; ...
        andi  t0, a0, 7                 ; a Character: its value
        li    t1, 4                     ; ...
        bne   t0, t1, poh_1             ; ...
        srli  a0, a0, 3                 ; ...
        j     poh_box                   ; ...
poh_1:
        beqz  a0, poh_box               ; nil: 0
        call  ohdr                      ; the header's hash
        srli  a0, a0, HASH_SHIFT        ; ...
        li    t0, 0x1FFFF               ; ...
        and   a0, a0, t0                ; ...
poh_box:
        slli  a0, a0, 1                 ; ...
        ori   a0, a0, 1                 ; ...
        j     prim_ok                   ; ...

; o_layout(a0 = object) -> a0 = header, a1 = format, a2 = fixed slots, a3 =
; indexed size (elements); uses v_ra2... (calls fld, oload)
o_layout:
        sd    ra, v_ra3(zero)           ; ...
        sd    a0, v_ol0(zero)          ; ...
        call  ohdr                      ; ...
        sd    a0, v_ol1(zero)          ; ...
        srli  t0, a0, 16                ; the format
        andi  t0, t0, 15                ; ...
        sd    t0, v_ol2(zero)          ; ...
        slli  a1, a0, 48                ; the class's fixed slots
        srli  a1, a1, 48                ; ...
        ld    a0, v_classes(zero)       ; ...
        call  oload                     ; ...
        li    a1, 2                     ; its format slot
        call  oload                     ; ...
        srai  a2, a0, 1                 ; ...
        slli  a2, a2, 48                ; ...
        srli  a2, a2, 48                ; ...
        ld    a0, v_ol1(zero)          ; ...
        ld    a1, v_ol2(zero)          ; ...
        srli  t0, a0, SIZE_SHIFT        ; slots
        li    t1, F_BYTES               ; bytes: slots * 8 - unused
        bne   a1, t1, ol_nb             ; ...
        slli  a3, t0, 3                 ; ...
        srli  t1, a0, 20                ; ...
        andi  t1, t1, 7                 ; ...
        sub   a3, a3, t1                ; ...
        li    a2, 0                     ; ...
        j     ol_ret                    ; ...
ol_nb:
        li    t1, F_INDEX               ; indexed: slots - fixed
        bne   a1, t1, ol_nw             ; ...
        sub   a3, t0, a2                ; ...
        j     ol_ret                    ; ...
ol_nw:
        li    t1, F_WORDS               ; words: slots
        bne   a1, t1, ol_none           ; ...
        mv    a3, t0                    ; ...
        li    a2, 0                     ; ...
        j     ol_ret                    ; ...
ol_none:
        mv    a2, t0                    ; fixed (or a method): none indexed
        li    a3, 0                     ; ...
ol_ret:
        ld    ra, v_ra3(zero)           ; ...
        ret                             ; ...

po_size:
        ld    a0, 0(sp)                 ; ...
        call  is_obj                    ; immediates and nil: 0
        beqz  t0, pos_zero              ; ...
        call  o_layout                  ; ...
        slli  a0, a3, 1                 ; ...
        ori   a0, a0, 1                 ; ...
        j     prim_ok                   ; ...
pos_zero:
        li    a0, 1                     ; ...
        j     prim_ok                   ; ...

; p_index(a0 = nargs) -> s11 = the receiver, a5 = the 0-based index (checked
; against the indexed size), a0 = header, a1 = format, a2 = fixed slots
p_index:
        sd    ra, v_ra4(zero)           ; ...
        call  p_args                    ; ...
        sd    a3, v_tmp7(zero)          ; (the value, for at:put:)
        mv    s11, a1                   ; ...
        andi  t0, a2, 1                 ; the index: a SmallInteger
        beqz  t0, prim_fail             ; ...
        srai  a5, a2, 1                 ; ...
        addi  a5, a5, -1                ; ...
        mv    a0, s11                   ; an object
        call  is_obj                    ; ...
        beqz  t0, prim_fail             ; ...
        mv    a0, s11                   ; ...
        call  o_layout                  ; ...
        bltz  a5, prim_fail             ; within the indexed size
        bgeu  a5, a3, prim_fail         ; ...
        ld    ra, v_ra4(zero)           ; ...
        ret                             ; ...

po_at:
        call  p_index                   ; ...
po_at1:
        li    t0, F_BYTES               ; bytes: integers
        beq   a1, t0, poa_bytes         ; ...
        li    t0, F_WORDS               ; words
        beq   a1, t0, poa_words         ; ...
        li    t0, F_INDEX               ; pointers
        bne   a1, t0, prim_fail         ; ...
        add   a1, a5, a2                ; slot fixed + i
        mv    a0, s11                   ; ...
        call  oload                     ; ...
        j     prim_ok                   ; ...
poa_bytes:
        mv    a0, s11                   ; ...
        mv    a1, a5                    ; ...
        call  obyte_ld                  ; ...
        slli  a0, a0, 1                 ; ...
