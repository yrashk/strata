; py_snapshot: the far heap -> a file: everything near moves out first
py_snapshot:
        ld    a0, 0(sp)                 ; the name: a byte object, into iobuf
        call  pb_bytes                  ; ...
        beqz  t0, prim_fail             ; ...
        li    t0, IOBUF - 1             ; ...
        bgeu  a3, t0, prim_fail         ; ...
        sd    a3, v_tmp5(zero)          ; ...
        li    t4, 0                     ; ...
pyn_name:
        ld    t2, v_tmp5(zero)          ; ...
        bgeu  t4, t2, pyn_named         ; ...
        sd    t4, v_tmp4(zero)          ; ...
        ld    a0, 0(sp)                 ; ...
        mv    a1, t4                    ; ...
        call  obyte_ld                  ; ...
        ld    t4, v_tmp4(zero)          ; ...
        la    t0, iobuf                 ; ...
        add   t0, t0, t4                ; ...
        sb    a0, 0(t0)                 ; ...
        addi  t4, t4, 1                 ; ...
        j     pyn_name                  ; ...
pyn_named:
        call  scavenge                  ; nothing near
        li    a0, 8                     ; the header: the heap's top
        ld    a1, v_htop(zero)          ; ...
        call  fsd                       ; ...
        la    a0, iobuf                 ; open it for writing
        ld    a1, v_tmp5(zero)          ; ...
        li    a2, 1                     ; ...
        call  sys_open                  ; ...
        bltz  a0, pyn_fail              ; ...
        sd    a0, v_tmp6(zero)          ; ...
        call  mc_flush                  ; the method cache's memory is the buffer
        sd    zero, v_tmp7(zero)        ; the far offset
pyn_loop:
        ld    t2, v_tmp7(zero)          ; ...
        ld    t3, v_htop(zero)          ; ...
        bgeu  t2, t3, pyn_end           ; ...
        sub   t1, t3, t2                ; ...
        li    t4, SYS_MAX               ; ...
        bleu  t1, t4, pyn_n             ; ...
        mv    t1, t4                    ; ...
pyn_n:
        sd    t1, v_tmp4(zero)          ; ...
        la    t0, mcode                 ; ...
        tget  tg3, t0, c6, t2, t1       ; ...
        ld    a0, v_tmp6(zero)          ; ...
        la    a1, mcode                 ; (sys_write's loads wait for it)
        ld    a2, v_tmp4(zero)          ; ...
        call  sys_write                 ; ...
        bltz  a0, pyn_wfail             ; ...
        ld    t2, v_tmp7(zero)          ; ...
        ld    t1, v_tmp4(zero)          ; ...
        add   t2, t2, t1                ; ...
        sd    t2, v_tmp7(zero)          ; ...
        j     pyn_loop                  ; ...
pyn_end:
        ld    a0, v_tmp6(zero)          ; ...
        call  sys_close                 ; ...
        call  reload_entry              ; the running method, again
        j     p_self                    ; ...
pyn_wfail:
        ld    a0, v_tmp6(zero)          ; ...
        call  sys_close                 ; ...
        call  reload_entry              ; ...
pyn_fail:
        j     prim_fail                 ; ...
