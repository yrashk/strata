        li    a1, 0                     ; ...
        call  oload                     ; ...
        srai  a0, a0, 1                 ; ...
        andi  t0, a0, 255               ; nargs
        srli  t1, a0, 36                ; copied
        andi  t1, t1, 255               ; ...
        add   t0, t0, t1                ; ...
        slli  t0, t0, 3                 ; the first nil temp
