; ---- the object format (README) -----------------------------------------------------
F_FIXED    = 0                          ; named slots
F_INDEX    = 1                          ; indexed slots
F_BYTES    = 2                          ; bytes
F_METHOD   = 3                          ; a header, literals, bytecodes
F_WORDS    = 4                          ; raw 64-bit words
IMM_BIT    = 23                         ; header: cannot be changed
MARK_BIT   = 24                         ; header: marked (the collectors)
HASH_SHIFT = 27                         ; header: identity hash (17 bits)
SIZE_SHIFT = 44                         ; header: slots (20 bits)
MAGIC_LO   = 0x41525453                 ; "STRA"
MAGIC_HI   = 0x314B4C54                 ; "TLK1"

