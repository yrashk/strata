MC_N       = 64                         ; method cache index entries (16 bytes)
MC_SIZE    = 4096                       ; method cache: the methods' bytes
FC_SETS    = 32                         ; far cache: sets of 2 lines of 64 bytes
FC_GEOM    = 6 | 5 << 6 | 2 << 12       ; tgeom: 64-byte lines, 32 sets, 2 ways
REM_N      = 64                         ; remembered set: far slots holding near references
MARK_N     = 128                        ; the scavenger's mark stack
IOBUF      = 512                        ; strings in and out
NPRIM      = 128
BIAS0      = 1 << 40                    ; the stack's first bias (logical = D-LS address + bias)
LTOP       = 0x10000 + BIAS0            ; the stack's logical top
FSSIZE     = 1 << 20                    ; the far stack                        ; primitives the VM does (198, 199 are markers)

