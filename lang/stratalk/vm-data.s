; ---- sizes ---------------------------------------------------------------------------
NURSERY    = 8192                       ; the nursery (near objects)
NBIG       = 2048                       ; an object larger than this is made far
STACK_LIMIT = 0xE000 + 768              ; the stack's floor (room for the library's calls)
