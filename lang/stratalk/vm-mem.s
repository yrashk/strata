; =============================================================================
; vm-mem.s: far memory and the caches in the D-LS
; =============================================================================
;
; Helpers keep their links in v_ra* (not on the stack, which holds only
; references and frames): fld, fsd, oload, ohdr, oclass are leaves (v_ra
; free); ostore and lookup use v_ra3, anew v_ra4, mc_get v_ra5, scavenge
; v_ra6. Transfer tags: tg1 far cache lines, tg2 far stores, tg3 bulk.

; ---- the far cache: 64-byte lines, two ways, write-through ---------------------

; fc_init(): an empty cache
fc_init:
        la    t0, ftags                 ; the tags
        csrw  ttag, t0                  ; ...
        la    t1, fdata                 ; the lines
        csrw  tdata, t1                 ; ...
        li    t1, FC_GEOM               ; the geometry
        csrw  tgeom, t1                 ; ...
        li    t1, FC_SETS * 3           ; all invalid
fci_loop:
        sd    zero, 0(t0)               ; ...
        addi  t0, t0, 8                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, fci_loop              ; ...
        ret                             ; done

; fld(a0 = far address) -> a0 = the word there. Leaf: t0, t1, t2.
fld:
        ltag  t0, a0                    ; the line, or a victim
        bltz  t0, fld_miss              ; ...
        ld    a0, 0(t0)                 ; a hit
        ret                             ; ...
fld_miss:
        slli  t0, t0, 1                 ; the victim's storage
        srli  t0, t0, 1                 ; ...
        srli  t1, a0, 6                 ; the line's far address
        slli  t1, t1, 6                 ; ...
        li    t2, 64                    ; ...
        tget  tg1, t0, c6, t1, t2       ; the line comes in
        linst a0                        ; ... and is recorded
        andi  t1, a0, 63                ; the word (waits for the line)
        add   t0, t0, t1                ; ...
        ld    a0, 0(t0)                 ; ...
        ld    t1, v_fmiss(zero)         ; counted
        addi  t1, t1, 1                 ; ...
        sd    t1, v_fmiss(zero)         ; ...
        ld    t1, v_fread(zero)         ; ...
        addi  t1, t1, 64                ; ...
        sd    t1, v_fread(zero)         ; ...
        ret                             ; ...

; fsd(a0 = far address, a1 = value): the word, into the line if it is
; cached, and to far memory. Leaf: t0, t1.
fsd:
        ltag  t0, a0                    ; cached?
        bltz  t0, fsd_miss              ; ...
        sd    a1, 0(t0)                 ; into the line
        li    t1, 8                     ; and through
        tput  tg2, t0, c6, a0, t1       ; ...
        j     fsd_n                     ; ...
fsd_miss:
        sd    a1, v_wbuf(zero)          ; (waits while the last store still reads it)
        la    t0, v_wbuf                ; ...
        li    t1, 8                     ; ...
        tput  tg2, t0, c6, a0, t1       ; ...
fsd_n:
        ld    t1, v_fwrite(zero)        ; counted
        addi  t1, t1, 8                 ; ...
        sd    t1, v_fwrite(zero)        ; ...
        ret                             ; ...

; fc_forget(a0 = far address, a1 = end): no line of the range stays cached
; (it was written around the cache). Leaf: t0..t4.
fc_forget:
        srli  a0, a0, 6                 ; whole lines
        slli  a0, a0, 6                 ; ...
fcf_loop:
        bgeu  a0, a1, fcf_done          ; ...
        ltag  t0, a0                    ; cached?
        bltz  t0, fcf_next              ; no
        la    t1, fdata                 ; line k = set * 2 + way
        sub   t0, t0, t1                ; ...
        srli  t0, t0, 6                 ; ...
        srli  t2, t0, 1                 ; set
        andi  t3, t0, 1                 ; way
        li    t4, 24                    ; its tag: ftags + set * 24 + way * 8
        mul   t2, t2, t4                ; ...
        slli  t3, t3, 3                 ; ...
        add   t2, t2, t3                ; ...
        la    t4, ftags                 ; ...
        add   t2, t2, t4                ; ...
        sd    zero, 0(t2)               ; invalid
fcf_next:
        addi  a0, a0, 64                ; ...
        j     fcf_loop                  ; ...
fcf_done:
        ret                             ; ...

; ---- objects, near or far ---------------------------------------------------------

; oload(a0 = oop, a1 = slot) -> a0 = the slot's contents. Leaf: t0..t2.
oload:
        andi  t0, a0, 7                 ; near?
        li    t1, 2                     ; ...
        bne   t0, t1, ol_far            ; ...
        slli  t1, a1, 3                 ; header at oop - 2, slot i at oop + 6 + 8i
        add   t1, t1, a0                ; ...
        ld    a0, 6(t1)                 ; ...
        ret                             ; ...
ol_far:
        slli  t1, a1, 3                 ; far: header at oop, slot i at oop + 8 + 8i
        add   a0, a0, t1                ; ...
        addi  a0, a0, 8                 ; ...
        j     fld                       ; ...

; ohdr(a0 = a near or far object) -> a0 = its header. Leaf.
ohdr:
        andi  t0, a0, 7                 ; near?
        li    t1, 2                     ; ...
        bne   t0, t1, fld               ; far: the word at oop
        ld    a0, -2(a0)                ; ...
        ret                             ; ...

; oclass(a0 = oop) -> a0 = its class index. Leaf.
oclass:
        andi  t0, a0, 1                 ; a SmallInteger
        bnez  t0, ocl_int               ; ...
        andi  t0, a0, 7                 ; a Character
        li    t1, 4                     ; ...
        beq   t0, t1, ocl_char          ; ...
        beqz  a0, ocl_nil               ; nil
        li    t1, 2                     ; near
        bne   t0, t1, ocl_far           ; ...
        ld    a0, -2(a0)                ; ...
        j     ocl_ci                    ; ...
ocl_far:
        sd    ra, v_ra2(zero)           ; (fld is a leaf too: ra is ours to keep)
        call  fld                       ; ...
        ld    ra, v_ra2(zero)           ; ...
ocl_ci:
        slli  a0, a0, 48                ; the low 16 bits
        srli  a0, a0, 48                ; ...
        ret                             ; ...
ocl_int:
        li    a0, CI_SMALLINT           ; ...
        ret                             ; ...
ocl_char:
        li    a0, CI_CHAR               ; ...
        ret                             ; ...
ocl_nil:
        li    a0, CI_NIL                ; ...
        ret                             ; ...

; ostore(a0 = oop, a1 = slot, a2 = value): the slot := the value. A near
; value stored into a far object is remembered (the scavenger finds it).
; When the remembered set is full, a scavenge runs first: a2 must be a
; root then (it is pushed, or held in v_roots by the caller); it is read
; again from v_roots + 24. Leaf apart from that.
ostore:
        andi  t0, a0, 7                 ; near?
        li    t1, 2                     ; ...
        bne   t0, t1, os_far            ; ...
        slli  t1, a1, 3                 ; ...
        add   t1, t1, a0                ; ...
        sd    a2, 6(t1)                 ; ...
        ret                             ; ...
os_far:
        slli  t1, a1, 3                 ; the slot's far address
        add   a0, a0, t1                ; ...
        addi  a0, a0, 8                 ; ...
        andi  t0, a2, 7                 ; a near value?
        li    t1, 2                     ; ...
        bne   t0, t1, os_fsd            ; no
        ld    t0, v_nrem(zero)          ; remember the slot
        li    t1, REM_N                 ; room?
        bgeu  t0, t1, os_full           ; ...
os_rem:
        slli  t1, t0, 3                 ; ...
        la    t2, remset                ; ...
        add   t1, t1, t2                ; ...
        sd    a0, 0(t1)                 ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, v_nrem(zero)          ; ...
        ld    t0, v_nremd(zero)         ; counted
        addi  t0, t0, 1                 ; ...
        sd    t0, v_nremd(zero)         ; ...
os_fsd:
        mv    a1, a2                    ; ...
        j     fsd                       ; ...
os_full:
        sd    ra, v_ra3(zero)           ; a scavenge empties it (and moves the value far)
        sd    a0, v_os0(zero)           ; (a far address: it does not move)
        sd    a2, v_roots + 24(zero)    ; ...
        call  scavenge                  ; ...
        ld    a1, v_roots + 24(zero)    ; the value, far now
        sd    zero, v_roots + 24(zero)  ; ...
        ld    a0, v_os0(zero)           ; ...
        ld    ra, v_ra3(zero)           ; ...
        j     fsd                       ; ...

; ---- allocation ---------------------------------------------------------------------

; anew(a0 = class index, a1 = format, a2 = slots, a3 = unused bytes in the
; last word) -> a0 = a new object, its slots nil (zero). Near, unless it is
; larger than NBIG. May scavenge: every reference in use must be pushed or
; in v_roots. Keeps s registers.
anew:
        sd    ra, v_ra4(zero)           ; ...
        slli  t0, a2, 3                 ; its bytes: the forwarding word, the header, the slots
        addi  t0, t0, 16                ; ...
        li    t1, NBIG                  ; large: far
        bgtu  t0, t1, an_far            ; ...
        add   t1, s5, t0                ; room?
        bleu  t1, s6, an_room           ; ...
        sd    a0, v_an0(zero)           ; no: scavenge first
        sd    a1, v_an1(zero)           ; ...
        sd    a2, v_an2(zero)           ; ...
        sd    a3, v_an3(zero)           ; ...
        call  scavenge                  ; ...
        ld    a0, v_an0(zero)           ; ...
        ld    a1, v_an1(zero)           ; ...
        ld    a2, v_an2(zero)           ; ...
        ld    a3, v_an3(zero)           ; ...
        slli  t0, a2, 3                 ; ...
        addi  t0, t0, 16                ; ...
an_room:
        sd    zero, 0(s5)               ; the forwarding word
        call  an_header                 ; t1 = the header
        sd    t1, 8(s5)                 ; ...
        addi  t2, s5, 16                ; the slots: nil
        add   t3, s5, t0                ; ...
an_zero:
        bgeu  t2, t3, an_done           ; ...
        sd    zero, 0(t2)               ; ...
        addi  t2, t2, 8                 ; ...
        j     an_zero                   ; ...
an_done:
        addi  a0, s5, 10                ; the reference: the header's address + 2
        mv    s5, t3                    ; ...
        ld    ra, v_ra4(zero)           ; ...
        ret                             ; ...
an_far:
        call  afar_raw                  ; ...
        ld    ra, v_ra4(zero)           ; ...
        ret                             ; ...

; an_header (a0..a3 as anew) -> t1 = the header, with a new identity hash.
; Leaf: t1, t4, t5.
an_header:
        ld    t4, v_hash(zero)          ; the next hash
        li    t5, 0x9E37                ; ...
        add   t4, t4, t5                ; ...
        li    t5, 0x1FFFF               ; ...
        and   t4, t4, t5                ; ...
        sd    t4, v_hash(zero)          ; ...
        slli  t1, t4, HASH_SHIFT        ; ...
        or    t1, t1, a0                ; the class index
        slli  t5, a1, 16                ; the format
        or    t1, t1, t5                ; ...
        slli  t5, a3, 20                ; the unused bytes
        or    t1, t1, t5                ; ...
        slli  t5, a2, SIZE_SHIFT        ; the slots
        or    t1, t1, t5                ; ...
        ret                             ; ...

; afar(a0..a3 as anew) -> a0 = a new far object (never moved: symbols,
; methods, classes, large objects). Keeps s registers.
afar:
        sd    ra, v_ra4(zero)           ; ...
        call  afar_raw                  ; ...
        ld    ra, v_ra4(zero)           ; ...
        ret                             ; ...
; afar_raw: the same; its caller keeps ra in v_ra4. Uses v_ra1.
afar_raw:
        sd    ra, v_ra1(zero)           ; ...
        sd    a0, v_af2(zero)           ; (the arguments, across a collection)
        sd    a1, v_af3(zero)           ; ...
        sd    a2, v_af4(zero)           ; ...
        sd    a3, v_af5(zero)           ; ...
        slli  a0, a2, 3                 ; its bytes
        addi  a0, a0, 8                 ; ...
        li    a1, 0                     ; (not the reserve)
        call  falloc                    ; ...
        bnez  a0, af_got                ; ...
        call  scavenge                  ; none: collect everything, then again
        call  full_gc                   ; ...
        ld    a2, v_af4(zero)           ; ...
        slli  a0, a2, 3                 ; ...
        addi  a0, a0, 8                 ; ...
        li    a1, 0                     ; ...
        call  falloc                    ; ...
        beqz  a0, heap_full             ; ...
af_got:
        sd    a0, v_af0(zero)           ; the object
        ld    a0, v_af2(zero)           ; its header
        ld    a1, v_af3(zero)           ; ...
        ld    a2, v_af4(zero)           ; ...
        ld    a3, v_af5(zero)           ; ...
        call  an_header                 ; ...
        sd    t1, v_af1(zero)           ; ...
        ld    t2, v_af0(zero)           ; zeros over it, 256 bytes at a time
        ld    t3, v_af4(zero)           ; ...
        slli  t3, t3, 3                 ; ...
        addi  t3, t3, 8                 ; ...
        add   t3, t3, t2                ; ...
        sd    t3, v_af6(zero)           ; (its end)
af_zero:
        bgeu  t2, t3, af_zeroed         ; ...
        sub   t4, t3, t2                ; ...
        li    t5, 256                   ; ...
        bleu  t4, t5, af_z1             ; ...
        mv    t4, t5                    ; ...
af_z1:
        la    t5, zerobuf               ; ...
        tput  tg3, t5, c6, t2, t4       ; ...
        add   t2, t2, t4                ; ...
        j     af_zero                   ; ...
af_zeroed:
        ld    a0, v_af0(zero)           ; no stale line of it stays cached
        ld    a1, v_af6(zero)           ; ...
        call  fc_forget                 ; ...
        ld    a0, v_af0(zero)           ; the header
        ld    a1, v_af1(zero)           ; ...
        call  fsd                       ; ...
        ld    a0, v_af0(zero)           ; ...
        ld    ra, v_ra1(zero)           ; ...
        ret                             ; ...
heap_full:
        la    a0, m_full                ; ...
        li    a1, m_full_e - m_full     ; ...
        j     die                       ; ...

; ---- the scavenger -------------------------------------------------------------------
;
; Every near object reachable from the stack, v_roots and the remembered
; slots moves to the far heap. Mark (from those, through near objects),
; give each marked object its far address (in its forwarding word), point
; every reference at the far address, slide the marked objects together
; down the nursery, then copy them out in one transfer. The nursery is
; then empty.

scavenge:
        sd    ra, v_ra6(zero)           ; ...
        sd    zero, v_nmark(zero)       ; an empty mark stack
        sd    zero, v_movf(zero)        ; ...
        ; the roots: the stack
        mv    a4, sp                    ; ...
        li    a5, 0x10000               ; ...
sc_stk:
        bgeu  a4, a5, sc_stk_d          ; ...
        ld    a0, 0(a4)                 ; ...
        call  sc_mark                   ; ...
        addi  a4, a4, 8                 ; ...
        j     sc_stk                    ; ...
sc_stk_d:
        la    a4, v_roots               ; the VM's roots
        addi  a5, a4, 32                ; ...
sc_vr:
        bgeu  a4, a5, sc_vr_d           ; ...
        ld    a0, 0(a4)                 ; ...
        call  sc_mark                   ; ...
        addi  a4, a4, 8                 ; ...
        j     sc_vr                     ; ...
sc_vr_d:
        la    a4, remset                ; the remembered slots
        ld    a5, v_nrem(zero)          ; ...
        slli  a5, a5, 3                 ; ...
        add   a5, a5, a4                ; ...
sc_rs:
        bgeu  a4, a5, sc_rs_d           ; ...
        ld    a0, 0(a4)                 ; the slot's far address
        call  fld                       ; what it holds now
        call  sc_mark                   ; ...
        addi  a4, a4, 8                 ; ...
        j     sc_rs                     ; ...
sc_rs_d:
        call  sc_drain                  ; through the near objects
        ld    t0, v_movf(zero)          ; the mark stack overflowed?
        beqz  t0, sc_assign             ; ...
        sd    zero, v_movf(zero)        ; scan every marked object again
        la    a4, nursery               ; ...
sc_rescan:
        bgeu  a4, s5, sc_rs_d           ; (and drain, and check again)
        ld    t0, 8(a4)                 ; marked?
        srli  t1, t0, MARK_BIT          ; ...
        andi  t1, t1, 1                 ; ...
        beqz  t1, sc_rescan_n           ; ...
        addi  a0, a4, 10                ; ...
        call  sc_children               ; ...
        ld    t0, 8(a4)                 ; ...
sc_rescan_n:
        srli  t0, t0, SIZE_SHIFT        ; next object
        slli  t0, t0, 3                 ; ...
        addi  t0, t0, 16                ; ...
        add   a4, a4, t0                ; ...
        j     sc_rescan                 ; ...
sc_assign:
        ; the survivors' bytes in far memory: one region for them all
        li    a5, 0                     ; ...
        la    a4, nursery               ; ...
sc_sum:
        bgeu  a4, s5, sc_sum_d          ; ...
        ld    t0, 8(a4)                 ; ...
        srli  t2, t0, SIZE_SHIFT        ; ...
        slli  t2, t2, 3                 ; ...
        addi  t2, t2, 8                 ; ...
        srli  t1, t0, MARK_BIT          ; ...
        andi  t1, t1, 1                 ; ...
        beqz  t1, sc_sum_n              ; ...
        add   a5, a5, t2                ; ...
sc_sum_n:
        add   a4, a4, t2                ; ...
        addi  a4, a4, 8                 ; ...
        j     sc_sum                    ; ...
sc_sum_d:
        sd    zero, v_sc2(zero)         ; (none survived: nowhere)
        beqz  a5, sc_as0                ; ...
        mv    a0, a5                    ; first fit, or the top (the reserve may be used)
        li    a1, 1                     ; ...
        call  falloc                    ; ...
        beqz  a0, heap_full             ; ...
        sd    a0, v_sc2(zero)           ; ...
sc_as0:
        ; the far addresses: in nursery order, from the region's start
        ld    a5, v_sc2(zero)           ; a5 = the next far address
        la    a4, nursery               ; ...
sc_as:
        bgeu  a4, s5, sc_as_d           ; ...
        ld    t0, 8(a4)                 ; ...
        srli  t2, t0, SIZE_SHIFT        ; t2 = its bytes in far memory (header, slots)
        slli  t2, t2, 3                 ; ...
        addi  t2, t2, 8                 ; ...
        srli  t1, t0, MARK_BIT          ; marked?
        andi  t1, t1, 1                 ; ...
        beqz  t1, sc_as_n               ; ...
        sd    a5, 0(a4)                 ; its forwarding word
        add   a5, a5, t2                ; ...
sc_as_n:
        add   a4, a4, t2                ; next (+ the forwarding word)
        addi  a4, a4, 8                 ; ...
        j     sc_as                     ; ...
sc_as_d:
        ; every reference to a near object -> its far address
        mv    a4, sp                    ; the stack
        li    a5, 0x10000               ; ...
sc_u1:
        bgeu  a4, a5, sc_u1d            ; ...
        ld    a0, 0(a4)                 ; ...
        call  sc_fwd                    ; ...
        sd    a0, 0(a4)                 ; ...
        addi  a4, a4, 8                 ; ...
        j     sc_u1                     ; ...
sc_u1d:
        la    a4, v_roots               ; the VM's roots
        addi  a5, a4, 32                ; ...
sc_u2:
        bgeu  a4, a5, sc_u2d            ; ...
        ld    a0, 0(a4)                 ; ...
        call  sc_fwd                    ; ...
        sd    a0, 0(a4)                 ; ...
        addi  a4, a4, 8                 ; ...
        j     sc_u2                     ; ...
sc_u2d:
        andi  t0, s4, 7                 ; self, if it is near (it is in the frame too)
        li    t1, 2                     ; ...
        bne   t0, t1, sc_u3s            ; ...
        mv    a0, s4                    ; ...
        call  sc_fwd                    ; ...
        mv    s4, a0                    ; ...
sc_u3s:
        la    a4, remset                ; the remembered slots
        ld    a5, v_nrem(zero)          ; ...
        slli  a5, a5, 3                 ; ...
        add   a5, a5, a4                ; ...
sc_u3:
        bgeu  a4, a5, sc_u3d            ; ...
        ld    a0, 0(a4)                 ; ...
        call  fld                       ; ...
        andi  t0, a0, 7                 ; still near?
        li    t1, 2                     ; ...
        bne   t0, t1, sc_u3n            ; ...
        call  sc_fwd                    ; ...
        mv    a1, a0                    ; ...
        ld    a0, 0(a4)                 ; ...
        call  fsd                       ; ...
sc_u3n:
        addi  a4, a4, 8                 ; ...
        j     sc_u3                     ; ...
sc_u3d:
        la    a4, nursery               ; the marked objects' slots
sc_u4:
        bgeu  a4, s5, sc_u4d            ; ...
        ld    t0, 8(a4)                 ; ...
        srli  a5, t0, SIZE_SHIFT        ; a5 = slots
        srli  t1, t0, MARK_BIT          ; marked?
        andi  t1, t1, 1                 ; ...
        beqz  t1, sc_u4n                ; ...
        srli  t1, t0, 16                ; pointers? (fixed or indexed)
        andi  t1, t1, 15                ; ...
        li    t2, F_INDEX               ; ...
        bgtu  t1, t2, sc_u4n            ; ...
        addi  a3, a4, 16                ; ...
        slli  t2, a5, 3                 ; ...
        add   t2, t2, a3                ; ...
        sd    t2, v_sc0(zero)           ; ...
sc_u4s:
        ld    t2, v_sc0(zero)           ; ...
        bgeu  a3, t2, sc_u4n            ; ...
        ld    a0, 0(a3)                 ; ...
        call  sc_fwd                    ; ...
        sd    a0, 0(a3)                 ; ...
        addi  a3, a3, 8                 ; ...
        j     sc_u4s                    ; ...
sc_u4n:
        slli  a5, a5, 3                 ; next
        addi  a5, a5, 16                ; ...
        add   a4, a4, a5                ; ...
        j     sc_u4                     ; ...
sc_u4d:
        ; slide the marked objects (header and slots) down the nursery
        la    a4, nursery               ; source
        la    a5, nursery               ; destination
sc_sl:
        bgeu  a4, s5, sc_sld            ; ...
        ld    t0, 8(a4)                 ; ...
        srli  t2, t0, SIZE_SHIFT        ; slots
        srli  t1, t0, MARK_BIT          ; marked?
        andi  t1, t1, 1                 ; ...
        beqz  t1, sc_sl_n               ; ...
        li    t1, 1                     ; unmark
        slli  t1, t1, MARK_BIT          ; ...
        xor   t0, t0, t1                ; ...
        sd    t0, 0(a5)                 ; the header
        addi  a5, a5, 8                 ; ...
        addi  t3, a4, 16                ; the slots
        slli  t4, t2, 3                 ; ...
        add   t4, t4, t3                ; ...
sc_slw:
        bgeu  t3, t4, sc_sl_n           ; ...
        ld    t1, 0(t3)                 ; ...
        sd    t1, 0(a5)                 ; ...
        addi  t3, t3, 8                 ; ...
        addi  a5, a5, 8                 ; ...
        j     sc_slw                    ; ...
sc_sl_n:
        slli  t2, t2, 3                 ; next
        addi  t2, t2, 16                ; ...
        add   a4, a4, t2                ; ...
        j     sc_sl                     ; ...
sc_sld:
        ; ... and out, in one transfer
        la    t0, nursery               ; ...
        sub   t1, a5, t0                ; the bytes
        ld    t2, v_sc2(zero)           ; to the region
        beqz  t1, sc_out                ; nothing survived
        tput  tg3, t0, c6, t2, t1       ; (the nursery's next stores wait for it)
        ld    t3, v_promo(zero)         ; counted
        add   t3, t3, t1                ; ...
        sd    t3, v_promo(zero)         ; ...
        ld    t3, v_fwrite(zero)        ; ...
        add   t3, t3, t1                ; ...
        sd    t3, v_fwrite(zero)        ; ...
        mv    a0, t2                    ; no stale line of it stays cached
        add   a1, t2, t1                ; ...
        call  fc_forget                 ; ...
sc_out:
        la    s5, nursery               ; the nursery is empty
        sd    zero, v_nrem(zero)        ; and nothing far refers into it
        ld    t0, v_nscav(zero)         ; counted
        addi  t0, t0, 1                 ; ...
        sd    t0, v_nscav(zero)         ; ...
        ld    t0, v_htop(zero)          ; into the reserve: a full collection now
        ld    t1, v_hsize(zero)         ; (nothing is near, nothing remembered)
        li    t2, RESERVE               ; ...
        sub   t1, t1, t2                ; ...
        bleu  t0, t1, sc_ret            ; ...
        call  full_gc                   ; ...
sc_ret:
        ld    ra, v_ra6(zero)           ; ...
        ret                             ; ...

; sc_mark(a0 = a reference): a near one is marked and pushed. Leaf: t0..t3.
sc_mark:
        andi  t0, a0, 7                 ; near?
        li    t1, 2                     ; ...
        bne   t0, t1, scm_ret           ; ...
        ld    t0, -2(a0)                ; marked already?
        srli  t1, t0, MARK_BIT          ; ...
        andi  t1, t1, 1                 ; ...
        bnez  t1, scm_ret               ; ...
        li    t1, 1                     ; mark it
        slli  t1, t1, MARK_BIT          ; ...
        or    t0, t0, t1                ; ...
        sd    t0, -2(a0)                ; ...
        ld    t2, v_nmark(zero)         ; push it
        li    t3, MARK_N                ; ...
        bgeu  t2, t3, scm_ovf           ; ...
        slli  t3, t2, 3                 ; ...
        la    t1, markstk               ; ...
        add   t3, t3, t1                ; ...
        sd    a0, 0(t3)                 ; ...
        addi  t2, t2, 1                 ; ...
        sd    t2, v_nmark(zero)         ; ...
scm_ret:
        ret                             ; ...
scm_ovf:
        li    t1, 1                     ; no room: it is scanned in a second pass
        sd    t1, v_movf(zero)          ; ...
        ret                             ; ...

; sc_drain(): mark what the pushed objects refer to, until none is left.
sc_drain:
        sd    ra, v_ra5(zero)           ; ...
scd_loop:
        ld    t2, v_nmark(zero)         ; ...
        beqz  t2, scd_done              ; ...
        addi  t2, t2, -1                ; pop one
        sd    t2, v_nmark(zero)         ; ...
        slli  t3, t2, 3                 ; ...
        la    t1, markstk               ; ...
        add   t3, t3, t1                ; ...
        ld    a0, 0(t3)                 ; ...
        call  sc_children               ; ...
        j     scd_loop                  ; ...
scd_done:
        ld    ra, v_ra5(zero)           ; ...
        ret                             ; ...

; sc_children(a0 = a near object): mark its near slots. Uses a2, a3.
sc_children:
        sd    ra, v_ra2(zero)           ; ...
        ld    t0, -2(a0)                ; ...
        srli  t1, t0, 16                ; pointers? (fixed or indexed)
        andi  t1, t1, 15                ; ...
        li    t2, F_INDEX               ; ...
        bgtu  t1, t2, scc_done          ; ...
        srli  t0, t0, SIZE_SHIFT        ; ...
        addi  a2, a0, 6                 ; slot 0
        slli  t0, t0, 3                 ; ...
        add   a3, a2, t0                ; ...
scc_loop:
        bgeu  a2, a3, scc_done          ; ...
        ld    a0, 0(a2)                 ; ...
        call  sc_mark                   ; ...
        addi  a2, a2, 8                 ; ...
        j     scc_loop                  ; ...
scc_done:
        ld    ra, v_ra2(zero)           ; ...
        ret                             ; ...

; sc_fwd(a0 = a reference) -> a0 = the same, or a near object's far address.
; Leaf: t0, t1.
sc_fwd:
        andi  t0, a0, 7                 ; near?
        li    t1, 2                     ; ...
        bne   t0, t1, scf_ret           ; ...
        ld    a0, -10(a0)               ; its forwarding word
scf_ret:
        ret                             ; ...

; ---- the method cache: methods copied in whole, run from the D-LS -----------

; mc_get(a0 = a method, far) -> a0 = its entry: [method][its slots]. When
; the cache is full it is emptied first (frames keep their method and an
; offset, and find it again when they are returned to).
mc_get:
        srli  t0, a0, 3                 ; the index entry
        andi  t0, t0, MC_N - 1          ; ...
        slli  t0, t0, 4                 ; ...
        la    t1, mtab                  ; ...
        add   t0, t0, t1                ; ...
        ld    t1, 0(t0)                 ; this method?
        bne   t1, a0, mc_miss           ; ...
        ld    a0, 8(t0)                 ; ...
        ret                             ; ...
mc_miss:
        sd    ra, v_ra5(zero)           ; ...
        sd    a0, v_tmp6(zero)          ; ...
        sd    t0, v_tmp7(zero)          ; ...
        call  fld                       ; its size: header >> 44 slots
        srli  t3, a0, SIZE_SHIFT        ; ...
        slli  t3, t3, 3                 ; ...
        addi  t4, t3, 24                ; the entry: the method, its native code, a count, the slots
        li    t0, MC_SIZE               ; too large for the cache at all?
        bgtu  t4, t0, mc_big            ; ...
        ld    t5, v_mctop(zero)         ; room?
        bnez  t5, mc_m1                 ; (0: never used)
        la    t5, mcode                 ; ...
mc_m1:
        add   t6, t5, t4                ; ...
        la    t0, mcode_end             ; ...
        bleu  t6, t0, mc_room           ; ...
        la    t0, mtab                  ; no: empty it
        li    t1, MC_N * 2              ; ...
mc_clr:
        sd    zero, 0(t0)               ; ...
        addi  t0, t0, 8                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, mc_clr                ; ...
        la    t5, mcode                 ; ...
        add   t6, t5, t4                ; ...
mc_room:
        sd    t6, v_mctop(zero)         ; ...
        ld    a0, v_tmp6(zero)          ; the method
        sd    a0, 0(t5)                 ; ...
        sd    zero, 8(t5)               ; no native code (yet)
        sd    zero, 16(t5)              ; activations
        addi  t1, t5, 24                ; its slots come in
        addi  t2, a0, 8                 ; ...
        tget  tg3, t1, c6, t2, t3       ; ...
        ld    t0, v_tmp7(zero)          ; indexed
        sd    a0, 0(t0)                 ; ...
        sd    t5, 8(t0)                 ; ...
        ld    t1, v_mcmiss(zero)        ; counted
        addi  t1, t1, 1                 ; ...
        sd    t1, v_mcmiss(zero)        ; ...
        ld    t1, v_fread(zero)         ; ...
        add   t1, t1, t3                ; ...
        sd    t1, v_fread(zero)         ; ...
        ld    t0, 24(t5)                ; native code? (header bit 53: look it up)
        srli  t0, t0, 54                ; ...
        andi  t0, t0, 1                 ; ...
        beqz  t0, mc_done               ; ...
        sd    t5, v_tmp6(zero)          ; ...
        ld    a0, 0(t5)                 ; ...
        call  nat_lookup                ; ...
        ld    t5, v_tmp6(zero)          ; ...
        sd    a0, 8(t5)                 ; ...
mc_done:
        mv    a0, t5                    ; ...
        ld    ra, v_ra5(zero)           ; ...
        ret                             ; ...
mc_big:
        la    a0, m_bigm                ; ...
        li    a1, m_bigm_e - m_bigm     ; ...
        j     die                       ; ...

; mc_forget(a0 = a method): if it is cached, it is not any more (it changed)
mc_forget:
        srli  t0, a0, 3                 ; ...
        andi  t0, t0, MC_N - 1          ; ...
        slli  t0, t0, 4                 ; ...
        la    t1, mtab                  ; ...
        add   t0, t0, t1                ; ...
        ld    t1, 0(t0)                 ; ...
        bne   t1, a0, mcf_ret           ; ...
        sd    zero, 0(t0)               ; ...
mcf_ret:
        ret                             ; ...

; reload_entry(): find the running method's entry again (after the method
; cache was emptied or its memory used for something else)
reload_entry:
        sd    ra, v_ra3(zero)           ; ...
        sub   t0, s0, s3                ; the offset of ip
        sd    t0, v_tmp0(zero)          ; ...
        ld    a0, -32(s2)               ; the method
        call  mc_get                    ; ...
        mv    s3, a0                    ; ...
        addi  s10, a0, 32               ; ...
        ld    t0, v_tmp0(zero)          ; ...
        add   s0, a0, t0                ; ...
        ld    ra, v_ra3(zero)           ; ...
        ret                             ; ...

; mc_flush(): empty the method cache (its memory is about to be a buffer)
mc_flush:
        la    t0, mtab                  ; ...
        li    t1, MC_N * 2              ; ...
mcfl_loop:
        sd    zero, 0(t0)               ; ...
        addi  t0, t0, 8                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, mcfl_loop             ; ...
        sd    zero, v_mctop(zero)       ; ...
        ret                             ; ...

; ---- method lookup -------------------------------------------------------------------

; lookup(a0 = class index, a1 = selector) -> a0 = the method (0: none),
; a1 = its header (a SmallInteger). Uses a2..a5.
lookup:
        srli  t0, a1, 3                 ; the cache entry: (selector >> 3 ^ class) mod LC_N
        xor   t0, t0, a0                ; ...
        andi  t0, t0, LC_N - 1          ; ...
        slli  t1, t0, 4                 ; * 24
        slli  t0, t0, 3                 ; ...
        add   t0, t0, t1                ; ...
        la    t1, lcache                ; ...
        add   t0, t0, t1                ; ...
        slli  t2, a0, 40                ; the key
        or    t2, t2, a1                ; ...
        ld    t1, 0(t0)                 ; ...
        bne   t1, t2, lk_miss           ; ...
        ld    a0, 8(t0)                 ; ...
        ld    a1, 16(t0)                ; ...
        ret                             ; ...
lk_miss:
        sd    ra, v_ra3(zero)           ; ...
        sd    t0, v_tmp0(zero)          ; the entry
        sd    t2, v_tmp1(zero)          ; the key
        mv    a5, a1                    ; a5 = the selector
        mv    a1, a0                    ; the class: table slot ci
        ld    a0, v_classes(zero)       ; ...
        call  oload                     ; ...
        mv    a4, a0                    ; a4 = the class
        mv    a0, a5                    ; the selector's hash
        call  fld                       ; ...
        srli  a0, a0, HASH_SHIFT        ; ...
        li    t0, 0x1FFFF               ; ...
        and   a0, a0, t0                ; ...
        sd    a0, v_tmp2(zero)          ; ...
lk_class:
        beqz  a4, lk_none               ; no superclass left
        mv    a0, a4                    ; its method dictionary
        li    a1, 1                     ; ...
        call  oload                     ; ...
        beqz  a0, lk_super              ; ...
        sd    a0, v_tmp3(zero)          ; ...
        li    a1, 1                     ; its keys
        call  oload                     ; ...
        beqz  a0, lk_super              ; (none yet)
        mv    a3, a0                    ; a3 = keys
        call  fld                       ; their number: a power of two
        srli  a2, a0, SIZE_SHIFT        ; a2 = n
        beqz  a2, lk_super              ; ...
        ld    t0, v_tmp2(zero)          ; i = hash mod n
        addi  t1, a2, -1                ; ...
        and   t0, t0, t1                ; ...
        sd    t0, v_tmp4(zero)          ; ...
lk_probe:
        ld    a1, v_tmp4(zero)          ; keys[i]
        mv    a0, a3                    ; ...
        call  oload                     ; ...
        beq   a0, a5, lk_found          ; ...
        beqz  a0, lk_super              ; an empty slot: not here
        ld    t0, v_tmp4(zero)          ; next
        addi  t0, t0, 1                 ; ...
        addi  t1, a2, -1                ; ...
        and   t0, t0, t1                ; ...
        sd    t0, v_tmp4(zero)          ; ...
        j     lk_probe                  ; ...
lk_super:
        mv    a0, a4                    ; the superclass
        li    a1, 0                     ; ...
        call  oload                     ; ...
        mv    a4, a0                    ; ...
        j     lk_class                  ; ...
lk_found:
        ld    a0, v_tmp3(zero)          ; values[i]
        li    a1, 2                     ; ...
        call  oload                     ; ...
        ld    a1, v_tmp4(zero)          ; ...
        call  oload                     ; ...
        mv    a4, a0                    ; a4 = the method
        li    a1, 0                     ; its header
        call  oload                     ; ...
        mv    a1, a0                    ; ...
        mv    a0, a4                    ; ...
        ld    t0, v_tmp0(zero)          ; into the cache (a selector made at run
        andi  t1, a5, 7                 ;   time is far as well: always)
        bnez  t1, lk_ret                ; ...
        ld    t2, v_tmp1(zero)          ; ...
        sd    t2, 0(t0)                 ; ...
        sd    a0, 8(t0)                 ; ...
        sd    a1, 16(t0)                ; ...
lk_ret:
        ld    t1, v_lcmiss(zero)        ; counted
        addi  t1, t1, 1                 ; ...
        sd    t1, v_lcmiss(zero)        ; ...
        ld    ra, v_ra3(zero)           ; ...
        ret                             ; ...
lk_none:
        li    a0, 0                     ; not understood
        li    a1, 0                     ; ...
        ld    ra, v_ra3(zero)           ; ...
        ret                             ; ...

; lc_flush(): empty the lookup cache (methods were added or removed)
lc_flush:
        la    t0, lcache                ; ...
        li    t1, LC_N * 3              ; ...
lcf_loop:
        sd    zero, 0(t0)               ; ...
        addi  t0, t0, 8                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, lcf_loop              ; ...
        ret                             ; ...

