; img_load(): the image file -> the far heap from offset 0, through the
; method cache's memory (not in use yet)
img_load:
        sd    ra, v_ra1(zero)           ; ...
        ld    a0, v_imgp(zero)          ; open it
        ld    a1, v_imgl(zero)          ; ...
        li    a2, 0                     ; ...
        call  sys_open                  ; ...
        bltz  a0, il_nofile             ; ...
        sd    a0, v_tmp0(zero)          ; the handle
        sd    zero, v_tmp1(zero)        ; the far offset
img_loop:
        ld    a0, v_tmp0(zero)          ; the next part
        la    a1, mcode                 ; ...
        li    a2, SYS_MAX               ; ...
        call  sys_read                  ; ...
        blez  a0, img_end               ; ...
        addi  t1, a0, 7                 ; whole words
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        ld    t2, v_tmp1(zero)          ; ...
        add   t3, t2, t1                ; room?
        ld    t4, v_hsize(zero)         ; ...
        bgtu  t3, t4, heap_full         ; ...
        la    t0, mcode                 ; out to the heap
        tput  tg3, t0, c6, t2, t1       ; (the next read waits until it has left)
        add   t2, t2, a0                ; ...
        sd    t2, v_tmp1(zero)          ; ...
        j     img_loop                  ; ...
img_end:
        ld    a0, v_tmp0(zero)          ; ...
        call  sys_close                 ; ...
        li    a0, 0                     ; the magic number
        call  fld                       ; ...
        li    t0, MAGIC_HI              ; ...
        slli  t0, t0, 32                ; ...
        li    t1, MAGIC_LO              ; ...
        or    t0, t0, t1                ; ...
        bne   a0, t0, il_bad            ; ...
        ld    ra, v_ra1(zero)           ; ...
        ret                             ; ...
il_nofile:
        la    a0, m_noimg               ; ...
        li    a1, m_noimg_e - m_noimg   ; ...
        j     die                       ; ...
il_bad:
        la    a0, m_badimg              ; ...
        li    a1, m_badimg_e - m_badimg ; ...
        j     die                       ; ...
