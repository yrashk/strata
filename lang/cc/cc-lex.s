; =============================================================================
; cc-lex.s: the scanner: characters to tokens
; =============================================================================
;
; next() reads the next token into tok / tk_val / tk_ty / tk_sym / tk_tag. An
; identifier or number's spelling is left in TB (zero-terminated), a string's
; bytes in STRBUF. Adjacent string literals are joined by the parser: while
; str_cat is set a string is appended to STRBUF after the bytes already there.
; Macros and directives belong to cc-pp.s, which next() calls.

CL_ID1   = 1                            ; character class bits: may start an identifier
CL_ID    = 2                            ; may continue one (letters, digits, _)
CL_DIG   = 4                            ; a decimal digit
CL_SP    = 8                            ; a blank other than newline

Y_VOID   = TYPES + 0 * TYSZ             ; the basic types, at fixed places in the type table
Y_BOOL   = TYPES + 1 * TYSZ             ; _Bool
Y_CHAR   = TYPES + 2 * TYSZ             ; char (signed)
Y_UCHAR  = TYPES + 3 * TYSZ             ; unsigned char
Y_SHORT  = TYPES + 4 * TYSZ             ; short
Y_USHORT = TYPES + 5 * TYSZ             ; unsigned short
Y_INT    = TYPES + 6 * TYSZ             ; int
Y_UINT   = TYPES + 7 * TYSZ             ; unsigned
Y_LONG   = TYPES + 8 * TYSZ             ; long, long long
Y_ULONG  = TYPES + 9 * TYSZ             ; unsigned long, unsigned long long
Y_FLOAT  = TYPES + 10 * TYSZ            ; float
Y_DOUBLE = TYPES + 11 * TYSZ            ; double, long double
Y_CHARP  = TYPES + 12 * TYSZ            ; char *
Y_VOIDP  = TYPES + 13 * TYSZ            ; void *
Y_FIRST  = TYPES + 14 * TYSZ            ; the first type made by declarations

        .data                           ; the scanner's tables
        .align 8                        ; (words first)
CC:       .space 128                    ; character classes
str_cat:  .dword 0                      ; 1: the next string literal is appended to STRBUF
str_len:  .dword 0                      ; bytes in STRBUF
pp_mode:  .dword 0                      ; 1: scanning the expression of #if (a newline ends it)
; two-character punctuators: first, second, token
op2:      .byte '+', '+', T_INC, '-', '-', T_DEC, '-', '>'; .
          .byte T_ARROW, '&', '&', T_LAND; .
          .byte '|', '|', T_LOR, '=', '=', T_EQ, '!', '='; .
          .byte T_NE, '<', '=', T_LE    ; .
          .byte '>', '=', T_GE, '<', '<', T_SHL, '>', '>'; .
          .byte T_SHR, '+', '=', T_ASG  ; .
          .byte '-', '=', T_ASG + 1, '*', '=', T_ASG + 2, '/', '='; .
          .byte T_ASG + 3               ; .
          .byte '%', '=', T_ASG + 4, '&', '=', T_ASG + 5, '|', '='; .
          .byte T_ASG + 6               ; .
          .byte '^', '=', T_ASG + 7, 0  ; (the end)
; the keywords, in token order from K_FIRST
kw_tab:   .asciz "auto"                 ; .
          .asciz "break"                ; .
          .asciz "case"                 ; .
          .asciz "char"                 ; .
          .asciz "const"                ; .
          .asciz "continue"             ; .
          .asciz "default"              ; .
          .asciz "do"                   ; .
          .asciz "double"               ; .
          .asciz "else"                 ; .
          .asciz "enum"                 ; .
          .asciz "extern"               ; .
          .asciz "float"                ; .
          .asciz "for"                  ; .
          .asciz "goto"                 ; .
          .asciz "if"                   ; .
          .asciz "inline"               ; .
          .asciz "int"                  ; .
          .asciz "long"                 ; .
          .asciz "register"             ; .
          .asciz "restrict"             ; .
          .asciz "return"               ; .
          .asciz "short"                ; .
          .asciz "signed"               ; .
          .asciz "sizeof"               ; .
          .asciz "static"               ; .
          .asciz "struct"               ; .
          .asciz "switch"               ; .
          .asciz "typedef"              ; .
          .asciz "union"                ; .
          .asciz "unsigned"             ; .
          .asciz "void"                 ; .
          .asciz "volatile"             ; .
          .asciz "while"                ; .
          .asciz "_Bool"                ; .
          .byte 0                       ; (the end)
        .align 8                        ; ...

        .far                            ; code units
        .align 4096                     ; ---- unit: lex ----
u_lex:
; lex_init(): character classes, keywords
lex_init:
        jalr  t6, gp, ent2-R            ; s1 = cursor in kw_tab, s2 = token
        li    t0, 0                     ; classes of the 128 characters
lxi_c:
        li    t1, 0                     ; ...
        addi  t2, t0, -'0'              ; a digit: continues an identifier
        sltiu t2, t2, 10                ; ...
        beqz  t2, lxi_a                 ; ...
        li    t1, CL_ID | CL_DIG        ; ...
lxi_a:
        ori   t2, t0, 32                ; a letter (either case)
        addi  t2, t2, -'a'              ; ...
        sltiu t2, t2, 26                ; ...
        beqz  t2, lxi_u                 ; ...
        li    t1, CL_ID | CL_ID1        ; ...
lxi_u:
        li    t2, '_'                   ; the underscore counts as a letter
        bne   t0, t2, lxi_s             ; ...
        li    t1, CL_ID | CL_ID1        ; ...
lxi_s:
        li    t2, ' '                   ; blanks: space, \t, \v, \f, \r
        beq   t0, t2, lxi_sp            ; ...
        addi  t2, t0, -9                ; ...
        sltiu t2, t2, 5                 ; ...
        beqz  t2, lxi_put               ; ...
        li    t2, 10                    ; (not the newline)
        beq   t0, t2, lxi_put           ; ...
lxi_sp:
        li    t1, CL_SP                 ; ...
lxi_put:
        sb    t1, CC(t0)                ; ...
        addi  t0, t0, 1                 ; ...
        slti  t2, t0, 128               ; ...
        bnez  t2, lxi_c                 ; ...
        li    s1, kw_tab                ; the keywords
        li    s2, K_FIRST               ; ...
lxi_k:
        lbu   t0, 0(s1)                 ; the end of the table?
        beqz  t0, lxi_ret               ; ...
        mv    a0, s1                    ; its length
        li    a1, 0                     ; ...
lxi_len:
        add   t0, s1, a1                ; ...
        lbu   t0, 0(t0)                 ; ...
        beqz  t0, lxi_in                ; ...
        addi  a1, a1, 1                 ; ...
        j     lxi_len                   ; ...
lxi_in:
        add   s1, s1, a1                ; (the next keyword)
        addi  s1, s1, 1                 ; ...
        jalr  ra, gp, intern-R          ; a0 = its record
        addi  a0, a0, 8                 ; set ID_KW: byte 4 of the record's second word
        li    t0, NUMB                  ; ...
        li    t1, 8                     ; ...
        tget  tg12, t0, c0, a0, t1      ; ...
        sb    s2, NUMB+4(zero)          ; ...
        tput  tg12, t0, c0, a0, t1      ; ...
        addi  s2, s2, 1                 ; ...
        j     lxi_k                     ; ...
lxi_ret:
        jalr  zero, gp, lv2-R           ; done

; next(): the next token
next:
        jalr  t6, gp, ent2-R            ; s1 = the character, s2 = scratch
nx_again:
        jalr  ra, gp, nextc-R           ; a character
        mv    s1, a0                    ; ...
        bltz  s1, nx_eof                ; the end
        slti  t0, s1, 128               ; ASCII?
        beqz  t0, nx_bad                ; no
        lbu   t0, CC(s1)                ; its class
        andi  t1, t0, CL_SP             ; a blank: skip it
        bnez  t1, nx_again              ; ...
        li    t1, 10                    ; a newline
        bne   s1, t1, nx_nonl           ; ...
        ld    t2, pp_mode(zero)         ; in a directive's expression: the end, and the newline stays
        beqz  t2, nx_nl                 ; ...
        mv    a0, s1                    ; ...
        call  lx_unget                  ; ...
        j     nx_eof                    ; ...
nx_nl:
        li    t1, 1                     ; the next token starts a line
        sd    t1, bol(zero)             ; ...
        ld    t2, in_kind(zero)         ; in a file: count it
        bne   t2, t1, nx_again          ; ...
        ld    t2, line(zero)            ; ...
        addi  t2, t2, 1                 ; ...
        sd    t2, line(zero)            ; ...
        j     nx_again                  ; ...
nx_nonl:
        li    t1, '\\'                  ; a backslash before a newline: nothing
        bne   s1, t1, nx_nobs           ; ...
        jalr  ra, gp, nextc-R           ; ...
        li    t1, 10                    ; ...
        bne   a0, t1, nx_bad            ; (a backslash anywhere else is an error)
        ld    t2, line(zero)            ; ...
        addi  t2, t2, 1                 ; ...
        sd    t2, line(zero)            ; ...
        j     nx_again                  ; ...
nx_nobs:
        li    t1, '/'                   ; a comment?
        bne   s1, t1, nx_nocom          ; ...
        jalr  ra, gp, nextc-R           ; ...
        li    t1, '/'                   ; //: to the end of the line
        beq   a0, t1, nx_lcom           ; ...
        li    t1, '*'                   ; /* ... */
        beq   a0, t1, nx_bcom           ; ...
        call  lx_unget                  ; neither: the character is not ours
        j     nx_punct                  ; ...
nx_lcom:
        jalr  ra, gp, nextc-R           ; skip to the newline, which is scanned again
        bltz  a0, nx_again              ; ...
        li    t1, 10                    ; ...
        bne   a0, t1, nx_lcom           ; ...
        call  lx_unget                  ; ...
        j     nx_again                  ; ...
nx_bcom:
        li    s2, 0                     ; s2 = the previous character
nx_bc:
        jalr  ra, gp, nextc-R           ; ...
        bltz  a0, nx_ueof               ; a comment must end
        li    t1, 10                    ; count its lines
        bne   a0, t1, nx_bc2            ; ...
        ld    t2, line(zero)            ; ...
        addi  t2, t2, 1                 ; ...
        sd    t2, line(zero)            ; ...
nx_bc2:
        li    t1, '/'                   ; "*/" ends it
        bne   a0, t1, nx_bc3            ; ...
        li    t1, '*'                   ; ...
        beq   s2, t1, nx_again          ; ...
nx_bc3:
        mv    s2, a0                    ; ...
        j     nx_bc                     ; ...
nx_nocom:
        li    t1, '#'                   ; a directive: # first on a line of a file
        bne   s1, t1, nx_tok            ; ...
        ld    t2, bol(zero)             ; ...
        beqz  t2, nx_tok                ; ...
        ld    t2, in_kind(zero)         ; ...
        addi  t2, t2, -1                ; ...
        bnez  t2, nx_tok                ; ...
        la    t6, pp_direct             ; ...
        xcall ra, c0, t6                ; ...
        j     nx_again                  ; ...
nx_tok:
        sd    zero, bol(zero)           ; a token: the line has started
        lbu   t0, CC(s1)                ; ...
        andi  t1, t0, CL_ID1            ; an identifier or keyword?
        bnez  t1, nx_id                 ; ...
        andi  t1, t0, CL_DIG            ; a number?
        bnez  t1, nx_num                ; ...
        li    t1, '"'                   ; a string?
        beq   s1, t1, nx_str            ; ...
        li    t1, 39                    ; a character constant?
        beq   s1, t1, nx_chr            ; ...
        li    t1, '.'                   ; . .. ... or a number like .5
        bne   s1, t1, nx_punct          ; ...
        jalr  ra, gp, nextc-R           ; ...
        mv    s2, a0                    ; ...
        call  lx_unget                  ; ...
        bltz  s2, nx_punct              ; ...
        lbu   t0, CC(s2)                ; a digit follows: a number
        andi  t0, t0, CL_DIG            ; ...
        bnez  t0, nx_num                ; ...
        li    t1, '.'                   ; "..."?
        bne   s2, t1, nx_punct          ; ...
        jalr  ra, gp, nextc-R           ; (the second dot)
        jalr  ra, gp, nextc-R           ; the third?
        li    t1, '.'                   ; ...
        bne   a0, t1, nx_bad            ; ".." is nothing
        li    s1, T_ELL                 ; ...
        j     nx_set                    ; ...
nx_punct:
        sd    zero, bol(zero)           ; (reached from the comment test too)
        jalr  ra, gp, nextc-R           ; a second character?
        mv    s2, a0                    ; ...
        li    t0, op2                   ; look the pair up
nx_p2:
        lbu   t1, 0(t0)                 ; ...
        beqz  t1, nx_p1                 ; not a pair
        bne   t1, s1, nx_p2n            ; ...
        lbu   t1, 1(t0)                 ; ...
        beq   t1, s2, nx_p2f            ; ...
nx_p2n:
        addi  t0, t0, 3                 ; ...
        j     nx_p2                     ; ...
nx_p2f:
        lbu   s1, 2(t0)                 ; the pair's token
        addi  t1, s1, -T_SHL            ; << or >>: an = may follow
        sltiu t1, t1, 2                 ; ...
        beqz  t1, nx_set                ; ...
        jalr  ra, gp, nextc-R           ; ...
        li    t1, '='                   ; ...
        bne   a0, t1, nx_p3n            ; ...
        addi  s1, s1, T_ASG + 8 - T_SHL ; <<= or >>=
        j     nx_set                    ; ...
nx_p3n:
        call  lx_unget                  ; ...
        j     nx_set                    ; ...
nx_p1:
        mv    a0, s2                    ; a single character: give the second one back
        call  lx_unget                  ; ...
nx_set:
        sd    s1, tok(zero)             ; ...
        jalr  zero, gp, lv2-R           ; done
nx_eof:
        sd    zero, tok(zero)           ; the end of the input
        jalr  zero, gp, lv2-R           ; done
nx_ueof:
        li    a0, m_eof                 ; ...
        jalr  zero, gp, error-R         ; ...
nx_bad:
        li    a0, m_badch               ; ...
        jalr  zero, gp, error-R         ; ...

nx_id:
        li    s2, TB                    ; gather the name
nx_idc:
        sb    s1, 0(s2)                 ; ...
        addi  s2, s2, 1                 ; ...
        jalr  ra, gp, nextc-R           ; ...
        mv    s1, a0                    ; ...
        sltiu t0, s1, 128               ; (the end of the input ends it)
        beqz  t0, nx_ide                ; ...
        lbu   t0, CC(s1)                ; ...
        andi  t0, t0, CL_ID             ; ...
        beqz  t0, nx_ide                ; ...
        li    t0, TB + ID_MAXLEN        ; (a longer name is cut)
        bltu  s2, t0, nx_idc            ; ...
        addi  s2, s2, -1                ; ...
        j     nx_idc                    ; ...
nx_ide:
        sb    zero, 0(s2)               ; ...
        addi  t0, s2, -TB - 1           ; L before a quote: a wide literal, read as a plain one
        bnez  t0, nx_idn0               ; ...
        lbu   t0, TB(zero)              ; ...
        addi  t0, t0, -'L'              ; ...
        bnez  t0, nx_idn0               ; ...
        li    t0, 39                    ; ...
        beq   s1, t0, nx_chr            ; ...
        li    t0, '"'                   ; ...
        beq   s1, t0, nx_str            ; ...
nx_idn0:
        mv    a0, s1                    ; the character after it is not ours
        call  lx_unget                  ; ...
        li    a0, TB                    ; its record
        addi  a1, s2, -TB               ; ...
        jalr  ra, gp, intern-R          ; ...
        sd    a0, tk_val(zero)          ; ...
        lbu   s1, IDR+ID_KW(zero)       ; a keyword?
        bnez  s1, nx_set                ; yes
        lwu   t0, IDR+ID_MAC(zero)      ; a macro?
        beqz  t0, nx_idsym              ; no
        sd    t0, tk_mac(zero)          ; ...
        la    t6, pp_expand             ; expand it: a0 = 1 if its text is the input now
        xcall ra, c0, t6                ; ...
        bnez  a0, nx_again              ; ...
nx_idsym:
        ld    t0, pp_mode(zero)         ; in a directive's expression a name is 0, or `defined`
        beqz  t0, nx_idn                ; ...
        la    t6, pp_defined            ; -> tk_val
        xcall ra, c0, t6                ; ...
        li    t0, Y_INT                 ; ...
        sd    t0, tk_ty(zero)           ; ...
        li    s1, T_NUM                 ; ...
        j     nx_set                    ; ...
nx_idn:
        lhu   t0, IDR+ID_SYM(zero)      ; what it names now
        sd    t0, tk_sym(zero)          ; ...
        lhu   t0, IDR+ID_TAG(zero)      ; ...
        sd    t0, tk_tag(zero)          ; ...
        li    s1, T_ID                  ; ...
        j     nx_set                    ; ...

nx_num:
        mv    a0, s1                    ; the first character
        la    t6, lex_num               ; ...
        xcall ra, c0, t6                ; sets tok, tk_val, tk_ty
        jalr  zero, gp, lv2-R           ; done

nx_chr:
        li    s2, 0                     ; s2 = the value
nx_chc:
        jalr  ra, gp, nextc-R           ; ...
        bltz  a0, nx_ueof               ; ...
        li    t1, 39                    ; the closing quote
        beq   a0, t1, nx_che            ; ...
        li    t1, '\\'                  ; an escape?
        bne   a0, t1, nx_chv            ; ...
        call  lx_esc                    ; ...
nx_chv:
        slli  s2, s2, 8                 ; (several characters: the last is the low byte)
        slli  a0, a0, 56                ; a char: sign-extended
        srai  a0, a0, 56                ; ...
        or    s2, s2, a0                ; ...
        j     nx_chc                    ; ...
nx_che:
        sd    s2, tk_val(zero)          ; an int
        li    t0, Y_INT                 ; ...
        sd    t0, tk_ty(zero)           ; ...
        li    s1, T_NUM                 ; ...
        j     nx_set                    ; ...

nx_str:
        li    s2, 0                     ; s2 = bytes in STRBUF
        ld    t0, str_cat(zero)         ; appending?
        beqz  t0, nx_sc                 ; no
        ld    s2, str_len(zero)         ; ...
nx_sc:
        jalr  ra, gp, nextc-R           ; ...
        bltz  a0, nx_ueof               ; ...
        li    t1, 10                    ; a string ends on its line
        beq   a0, t1, nx_ueof           ; ...
        li    t1, '"'                   ; the closing quote
        beq   a0, t1, nx_se             ; ...
        li    t1, '\\'                  ; an escape?
        bne   a0, t1, nx_sv             ; ...
        call  lx_esc                    ; ...
nx_sv:
        li    t1, STRMAX                ; room?
        bltu  s2, t1, nx_sput           ; ...
        li    a0, m_strbig              ; ...
        jalr  zero, gp, error-R         ; ...
nx_sput:
        sb    a0, STRBUF(s2)            ; ...
        addi  s2, s2, 1                 ; ...
        j     nx_sc                     ; ...
nx_se:
        sb    zero, STRBUF(s2)          ; (not counted)
        sd    s2, str_len(zero)         ; ...
        sd    s2, tk_val(zero)          ; ...
        li    s1, T_STR                 ; ...
        j     nx_set                    ; ...

; lx_unget(a0 = the character just read): give it back (the end is not a character)
lx_unget:
        bltz  a0, lxu_ret               ; ...
        ld    t0, in_pos(zero)          ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, in_pos(zero)          ; ...
lxu_ret:
        ret                             ; done

; lx_esc() -> a0 = the character an escape sequence stands for (after the backslash)
lx_esc:
        addi  sp, sp, -24               ; frame
        sd    ra, 16(sp)                ; ...
        jalr  ra, gp, nextc-R           ; ...
        li    t1, 'n'                   ; \n
        li    t0, 10                    ; ...
        beq   a0, t1, lxe_ret           ; ...
        li    t1, 't'                   ; \t
        li    t0, 9                     ; ...
        beq   a0, t1, lxe_ret           ; ...
        li    t1, 'r'                   ; \r
        li    t0, 13                    ; ...
        beq   a0, t1, lxe_ret           ; ...
        li    t1, 'a'                   ; \a
        li    t0, 7                     ; ...
        beq   a0, t1, lxe_ret           ; ...
        li    t1, 'b'                   ; \b
        li    t0, 8                     ; ...
        beq   a0, t1, lxe_ret           ; ...
        li    t1, 'f'                   ; \f
        li    t0, 12                    ; ...
        beq   a0, t1, lxe_ret           ; ...
        li    t1, 'v'                   ; \v
        li    t0, 11                    ; ...
        beq   a0, t1, lxe_ret           ; ...
        li    t1, 'e'                   ; \e
        li    t0, 27                    ; ...
        beq   a0, t1, lxe_ret           ; ...
        li    t1, 'x'                   ; \x hexadecimal digits
        beq   a0, t1, lxe_hex           ; ...
        addi  t1, a0, -'0'              ; \ and up to three octal digits
        sltiu t2, t1, 8                 ; ...
        mv    t0, a0                    ; anything else stands for itself
        beqz  t2, lxe_ret               ; ...
        sd    t1, 0(sp)                 ; the value
        li    t0, 2                     ; two more at most
        sd    t0, 8(sp)                 ; ...
lxe_oct:
        jalr  ra, gp, nextc-R           ; ...
        addi  t1, a0, -'0'              ; ...
        sltiu t2, t1, 8                 ; ...
        beqz  t2, lxe_oend              ; ...
        ld    t0, 0(sp)                 ; ...
        slli  t0, t0, 3                 ; ...
        add   t0, t0, t1                ; ...
        sd    t0, 0(sp)                 ; ...
        ld    t0, 8(sp)                 ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, 8(sp)                 ; ...
        bnez  t0, lxe_oct               ; ...
        j     lxe_val                   ; ...
lxe_oend:
        call  lx_unget                  ; ...
lxe_val:
        ld    t0, 0(sp)                 ; ...
        j     lxe_ret                   ; ...
lxe_hex:
        sd    zero, 0(sp)               ; the value
lxe_hd:
        jalr  ra, gp, nextc-R           ; ...
        addi  t1, a0, -'0'              ; a digit?
        sltiu t2, t1, 10                ; ...
        bnez  t2, lxe_hv                ; ...
        ori   t1, a0, 32                ; a..f?
        addi  t1, t1, -'a'              ; ...
        sltiu t2, t1, 6                 ; ...
        beqz  t2, lxe_oend              ; no: the end
        addi  t1, t1, 10                ; ...
lxe_hv:
        ld    t0, 0(sp)                 ; ...
        slli  t0, t0, 4                 ; ...
        add   t0, t0, t1                ; ...
        sd    t0, 0(sp)                 ; ...
        j     lxe_hd                    ; ...
lxe_ret:
        mv    a0, t0                    ; ...
        ld    ra, 16(sp)                ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; done

; lex_num(a0 = first character): scan a number; sets tok, tk_val, tk_ty
lex_num:
        jalr  t6, gp, ent4-R            ; s1 = cursor in TB, s2 = value, s3 = base, s4 = flags
        li    s1, TB                    ; gather the pp-number: digits, letters, dots,
        li    s4, 0                     ;   and a sign after an exponent letter; s4 bit 0: floating
lxn_g:
        sb    a0, 0(s1)                 ; ...
        addi  s1, s1, 1                 ; ...
        mv    s2, a0                    ; s2 = the previous character
        jalr  ra, gp, nextc-R           ; ...
        sltiu t0, a0, 128               ; ...
        beqz  t0, lxn_ge                ; ...
        li    t1, '.'                   ; a dot: floating
        bne   a0, t1, lxn_g2            ; ...
        ori   s4, s4, 1                 ; ...
        j     lxn_g                     ; ...
lxn_g2:
        lbu   t0, CC(a0)                ; a letter or digit?
        andi  t0, t0, CL_ID             ; ...
        bnez  t0, lxn_g                 ; ...
        li    t1, '+'                   ; a sign: only after e, E (not in hexadecimal), p, P
        beq   a0, t1, lxn_sign          ; ...
        li    t1, '-'                   ; ...
        bne   a0, t1, lxn_ge            ; ...
lxn_sign:
        ori   t0, s2, 32                ; ...
        li    t1, 'p'                   ; ...
        beq   t0, t1, lxn_exp           ; ...
        li    t1, 'e'                   ; ...
        bne   t0, t1, lxn_ge            ; ...
        lbu   t0, TB+1(zero)            ; (0x...e is a digit, not an exponent)
        ori   t0, t0, 32                ; ...
        li    t1, 'x'                   ; ...
        beq   t0, t1, lxn_ge            ; ...
lxn_exp:
        ori   s4, s4, 1                 ; floating
        j     lxn_g                     ; ...
lxn_ge:
        sb    zero, 0(s1)               ; ...
        ld    t0, in_pos(zero)          ; the character after it is not ours
        bltz  a0, lxn_scan              ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, in_pos(zero)          ; ...
lxn_scan:
        li    s1, TB                    ; now read it
        li    s3, 10                    ; the base
        lbu   t0, 0(s1)                 ; a leading 0: octal, or 0x
        li    t1, '0'                   ; ...
        bne   t0, t1, lxn_fl            ; ...
        lbu   t0, 1(s1)                 ; ...
        ori   t0, t0, 32                ; ...
        li    t1, 'x'                   ; ...
        bne   t0, t1, lxn_oct           ; ...
        li    s3, 16                    ; ...
        addi  s1, s1, 2                 ; ...
        j     lxn_fl                    ; ...
lxn_oct:
        li    s3, 8                     ; ...
lxn_fl:
        li    t0, 16                    ; an e in a decimal number makes it floating too
        beq   s3, t0, lxn_isfl          ; ...
        mv    t0, s1                    ; ...
lxn_fe:
        lbu   t1, 0(t0)                 ; ...
        beqz  t1, lxn_isfl              ; ...
        ori   t1, t1, 32                ; ...
        addi  t0, t0, 1                 ; ...
        li    t2, 'e'                   ; ...
        bne   t1, t2, lxn_fe            ; ...
        ori   s4, s4, 1                 ; ...
lxn_isfl:
        andi  t0, s4, 1                 ; floating?
        beqz  t0, lxn_int               ; ...
        la    t6, lex_float             ; ...
        xcall ra, c0, t6                ; ...
        jalr  zero, gp, lv4-R           ; ...
lxn_int:
        li    s2, 0                     ; the value
lxn_d:
        lbu   t0, 0(s1)                 ; a digit of the base?
        addi  t1, t0, -'0'              ; ...
        sltiu t2, t1, 10                ; ...
        bnez  t2, lxn_dv                ; ...
        ori   t1, t0, 32                ; ...
        addi  t1, t1, -'a'              ; ...
        sltiu t2, t1, 6                 ; ...
        beqz  t2, lxn_suf               ; ...
        addi  t1, t1, 10                ; ...
lxn_dv:
        bgeu  t1, s3, lxn_suf           ; ...
        mul   s2, s2, s3                ; ...
        add   s2, s2, t1                ; ...
        addi  s1, s1, 1                 ; ...
        j     lxn_d                     ; ...
lxn_suf:
        li    s4, 0                     ; suffixes: bit 0 u, bit 1 l
lxn_s:
        lbu   t0, 0(s1)                 ; ...
        beqz  t0, lxn_type              ; ...
        ori   t0, t0, 32                ; ...
        addi  s1, s1, 1                 ; ...
        li    t1, 'u'                   ; ...
        bne   t0, t1, lxn_sl            ; ...
        ori   s4, s4, 1                 ; ...
        j     lxn_s                     ; ...
lxn_sl:
        li    t1, 'l'                   ; ...
        bne   t0, t1, lxn_bad           ; ...
        ori   s4, s4, 2                 ; ...
        j     lxn_s                     ; ...
lxn_bad:
        li    a0, m_expect              ; a bad number
        li    a1, TB                    ; ...
        jalr  zero, gp, error2-R        ; ...
lxn_type:
        sd    s2, tk_val(zero)          ; its type: the first of the candidates that holds it
        li    t3, Y_ULONG               ; ...
        bltz  s2, lxn_tset              ; the top bit: only unsigned long
        srli  t0, s2, 31                ; t0 = 0 if it fits int
        srli  t1, s2, 32                ; t1 = 0 if it fits unsigned int
        addi  t2, s3, -10               ; t2 = 0 for a decimal constant
        andi  t4, s4, 2                 ; an l suffix?
        bnez  t4, lxn_tl                ; ...
        andi  t4, s4, 1                 ; a u suffix?
        bnez  t4, lxn_tu                ; ...
        li    t3, Y_INT                 ; int
        beqz  t0, lxn_tset              ; ...
        beqz  t2, lxn_tl                ; decimal: then long
        li    t3, Y_UINT                ; octal, hexadecimal: then unsigned
        beqz  t1, lxn_tset              ; ...
        j     lxn_tl                    ; then long
lxn_tu:
        li    t3, Y_UINT                ; unsigned
        beqz  t1, lxn_tset              ; ...
        li    t3, Y_ULONG               ; then unsigned long
        j     lxn_tset                  ; ...
lxn_tl:
        li    t3, Y_LONG                ; long
        andi  t4, s4, 1                 ; ...
        beqz  t4, lxn_tset              ; ...
        li    t3, Y_ULONG               ; ...
lxn_tset:
        sd    t3, tk_ty(zero)           ; ...
        li    t0, T_NUM                 ; ...
        sd    t0, tok(zero)             ; ...
        jalr  zero, gp, lv4-R           ; done

; lex_float(): the floating constant in TB (not supported yet)
lex_float:
        li    a0, m_nofp                ; ...
        jalr  zero, gp, error-R         ; ...
