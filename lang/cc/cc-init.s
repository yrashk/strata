; =============================================================================
; cc-init.s: initialisers
; =============================================================================
;
; One routine, init_obj, walks a type and the initialiser text together. A
; static object's values are constants written into the data image; an
; automatic object's are stored by code into the frame (after the object was
; cleared). An array of unknown size is walked twice: first a dry run that
; stores nothing and only counts, then, with the scanner put back at the
; initialiser's first token, for real.

        .data                           ; the initialiser being read
        .align 8                        ; (words first)
ini_static: .dword 0                    ; 1: a static object (constants into the data image)
ini_base: .dword 0                      ; its D-LS address, or its frame offset
ini_dry:  .dword 0                      ; 1: the dry run
ini_bf:   .dword 0                      ; the member being initialised is a bit-field: first bit | width << 8
str_ready: .dword 0                     ; 1: the string for init_str is in STRBUF already, the token after it read
m_memcpy: .asciz "memcpy"               ; the library routines initialisation calls
m_memset: .asciz "memset"               ; ...
m_inisz:  .asciz "cannot find the size of this array" ; ...
m_inimany: .asciz "too many initialisers" ; ...
        .align 8                        ; ...

        .far                            ; code units
        .align 4096                     ; ---- unit: init1 ----
u_init1:
; init_obj(a0 = type, a1 = offset in the object) -> a0 = for an array, the
; elements initialised: read the initialiser of this (sub)object
init_obj:
        jalr  t6, gp, ent6-R            ; s1 = type, s2 = offset, s3 = in braces, s4 = index / member, s5 = most elements, s6 = element type
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        li    s3, 0                     ; ...
        li    s5, 0                     ; ...
        lbu   t0, TY_KIND(s1)           ; ...
        li    t1, TK_ARRAY              ; ...
        beq   t0, t1, ino_arr           ; ...
        addi  t1, t0, -TK_STRUCT        ; ...
        sltiu t1, t1, 2                 ; ...
        bnez  t1, ino_su                ; ...
        ld    t0, tok(zero)             ; a scalar, perhaps in braces
        li    t1, '{'                   ; ...
        bne   t0, t1, ino_sc            ; ...
        li    s3, 1                     ; ...
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
ino_sc:
        mv    a0, s1                    ; ...
        mv    a1, s2                    ; ...
        la    t6, init_scalar           ; ...
        xcall ra, c0, t6                ; ...
        j     ino_close                 ; ...
ino_arr:
        lhu   s6, TY_BASE(s1)           ; ...
        ld    t0, tok(zero)             ; ...
        li    t1, '{'                   ; ...
        bne   t0, t1, ino_astr          ; ...
        li    s3, 1                     ; ...
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
ino_astr:
        lbu   t0, TY_KIND(s6)           ; a string for an array of char
        addi  t0, t0, -TK_CHAR          ; ...
        bnez  t0, ino_al0               ; ...
        ld    t0, tok(zero)             ; ...
        addi  t0, t0, -T_STR            ; ...
        ld    t1, str_ready(zero)       ; ...
        seqz  t0, t0                    ; ...
        or    t0, t0, t1                ; ...
        beqz  t0, ino_al0               ; ...
        mv    a0, s1                    ; ...
        mv    a1, s2                    ; ...
        la    t6, init_str              ; a0 = bytes with the zero
        xcall ra, c0, t6                ; ...
        mv    s5, a0                    ; ...
        j     ino_close                 ; ...
ino_al0:
        li    s4, 0                     ; the elements
ino_al:
        ld    t0, tok(zero)             ; ...
        lwu   t2, TY_COUNT(s1)          ; t2 = the array's length, 0 if not known
        beqz  s3, ino_ael               ; ...
        li    t1, '}'                   ; in braces: to the }
        beq   t0, t1, ino_close         ; ...
        li    t1, '['                   ; [ index ] =
        bne   t0, t1, ino_ae            ; ...
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        la    t6, const_expr            ; ...
        xcall ra, c0, t6                ; ...
        mv    s4, a0                    ; ...
        li    a0, ']'                   ; ...
        la    t6, skip                  ; ...
        xcall ra, c0, t6                ; ...
        li    a0, '='                   ; ...
        la    t6, skip                  ; ...
        xcall ra, c0, t6                ; ...
        j     ino_ae                    ; ...
ino_ael:
        beqz  t2, ino_ae                ; without braces: as many as the array has
        bgeu  s4, t2, ino_close         ; ...
ino_ae:
        lwu   t2, TY_COUNT(s1)          ; ...
        beqz  t2, ino_ago               ; ...
        bltu  s4, t2, ino_ago           ; ...
        li    a0, m_inimany             ; ...
        jalr  zero, gp, error-R         ; ...
ino_ago:
        mv    a0, s6                    ; ...
        lwu   t0, TY_SIZE(s6)           ; ...
        mul   t0, t0, s4                ; ...
        add   a1, s2, t0                ; ...
        la    t6, init_obj              ; ...
        xcall ra, c0, t6                ; ...
        addi  s4, s4, 1                 ; ...
        bgeu  s5, s4, ino_ac            ; ...
        mv    s5, s4                    ; ...
ino_ac:
        ld    t0, tok(zero)             ; a comma: another element, if there is room for one
        li    t1, ','                   ; ...
        bne   t0, t1, ino_close         ; ...
        bnez  s3, ino_acn               ; ...
        lwu   t2, TY_COUNT(s1)          ; ...
        beqz  t2, ino_acn               ; ...
        bgeu  s4, t2, ino_close         ; (the comma is the enclosing list's)
ino_acn:
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        j     ino_al                    ; ...
ino_su:
        ld    t0, tok(zero)             ; a struct or union
        li    t1, '{'                   ; ...
        bne   t0, t1, ino_sm0           ; ...
        li    s3, 1                     ; ...
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
ino_sm0:
        lhu   s4, TY_AUX(s1)            ; its members in order
ino_sl:
        ld    t0, tok(zero)             ; ...
        beqz  s3, ino_sel               ; ...
        li    t1, '}'                   ; ...
        beq   t0, t1, ino_close         ; ...
        li    t1, '.'                   ; . member =
        bne   t0, t1, ino_se            ; ...
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        lhu   s4, TY_AUX(s1)            ; ...
        ld    t1, tk_val(zero)          ; ...
ino_sf:
        beqz  s4, ino_many              ; ...
        lwu   t2, SY_ID(s4)             ; ...
        beq   t2, t1, ino_sfd           ; ...
        lhu   s4, SY_PREV(s4)           ; ...
        j     ino_sf                    ; ...
ino_sfd:
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        li    a0, '='                   ; ...
        la    t6, skip                  ; ...
        xcall ra, c0, t6                ; ...
        j     ino_se                    ; ...
ino_sel:
        beqz  s4, ino_close             ; without braces: as many as there are members
ino_se:
        bnez  s4, ino_sgo               ; ...
ino_many:
        li    a0, m_inimany             ; ...
        jalr  zero, gp, error-R         ; ...
ino_sgo:
        lhu   t0, SY_AUX(s4)            ; (a bit-field member: init_scalar needs its place)
        sd    t0, ini_bf(zero)          ; ...
        lhu   a0, SY_TYPE(s4)           ; ...
        lw    a1, SY_VAL(s4)            ; ...
        add   a1, a1, s2                ; ...
        la    t6, init_obj              ; ...
        xcall ra, c0, t6                ; ...
        sd    zero, ini_bf(zero)        ; ...
        lhu   s4, SY_PREV(s4)           ; the next member (a union has only its first)
        lbu   t0, TY_KIND(s1)           ; ...
        addi  t0, t0, -TK_UNION         ; ...
        bnez  t0, ino_scm               ; ...
        li    s4, 0                     ; ...
ino_scm:
        ld    t0, tok(zero)             ; ...
        li    t1, ','                   ; ...
        bne   t0, t1, ino_close         ; ...
        bnez  s3, ino_scn               ; ...
        beqz  s4, ino_close             ; (the comma is the enclosing list's)
ino_scn:
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        j     ino_sl                    ; ...
ino_close:
        beqz  s3, ino_ret               ; the closing brace, after an optional comma
        ld    t0, tok(zero)             ; ...
        li    t1, ','                   ; ...
        bne   t0, t1, ino_cb            ; ...
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
ino_cb:
        li    a0, '}'                   ; ...
        la    t6, skip                  ; ...
        xcall ra, c0, t6                ; ...
ino_ret:
        mv    a0, s5                    ; ...
        jalr  zero, gp, lv6-R           ; done

; init_scalar(a0 = type, a1 = offset): one expression for one scalar
init_scalar:
        jalr  t6, gp, ent3-R            ; s1 = type, s2 = offset, s3 = entry
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        ld    t0, ini_static(zero)      ; ...
        bnez  t0, isc_stat              ; ...
        li    a0, VK_LOC                ; automatic: object = expression
        mv    a1, s1                    ; ...
        ld    a2, ini_base(zero)        ; ...
        add   a2, a2, s2                ; ...
        jalr  ra, gp, vpush-R           ; ...
        li    t0, X_SP                  ; ...
        sb    t0, V_REG(a0)             ; ...
        ld    t0, ini_bf(zero)          ; ...
        sh    t0, V_BOFF(a0)            ; ...
        sd    zero, ini_bf(zero)        ; (the expression may hold initialisers of its own)
        la    t6, assign                ; ...
        xcall ra, c0, t6                ; ...
        ld    a0, vsp(zero)             ; ...
        mv    a1, s1                    ; ...
        la    t6, g_cast                ; ...
        xcall ra, c0, t6                ; ...
        la    t6, g_store               ; ...
        xcall ra, c0, t6                ; ...
        la    t6, vpop                  ; ...
        xcall ra, c0, t6                ; ...
        jalr  zero, gp, lv3-R           ; ...
isc_stat:
        ld    t0, ini_bf(zero)          ; (kept in the frame over the expression)
        sd    zero, ini_bf(zero)        ; ...
        addi  sp, sp, -8                ; ...
        sd    t0, 0(sp)                 ; ...
        la    t6, isc_static            ; ...
        xcall ra, c0, t6                ; ...
        addi  sp, sp, 8                 ; ...
        jalr  zero, gp, lv3-R           ; ...
; isc_static(): the static case of init_scalar (its s1 = type, s2 = offset; the
; bit-field word is on the caller's stack)
isc_static:
        jalr  t6, gp, ent0-R            ; ...
        la    t6, assign                ; static: a constant
        xcall ra, c0, t6                ; ...
        ld    s3, vsp(zero)             ; ...
        mv    a0, s3                    ; ...
        mv    a1, s1                    ; ...
        la    t6, g_cast                ; ...
        xcall ra, c0, t6                ; ...
        lbu   t0, V_KIND(s3)            ; ...
        addi  t0, t0, -VK_CONST         ; ...
        beqz  t0, isc_put               ; ...
        ld    t0, ini_dry(zero)         ; (the dry run does not care)
        bnez  t0, isc_pop               ; ...
        li    a0, m_const               ; ...
        jalr  zero, gp, error-R         ; ...
isc_put:
        ld    t0, ini_dry(zero)         ; ...
        bnez  t0, isc_pop               ; ...
        ld    t0, 8(sp)                 ; a bit-field: merged into the bytes of its unit
        beqz  t0, isc_whole             ; (8(sp): above ent0's frame)
        la    t6, isc_bits              ; ...
        xcall ra, c0, t6                ; ...
        j     isc_pop                   ; ...
isc_whole:
        ld    a0, ini_base(zero)        ; ...
        add   a0, a0, s2                ; ...
        ld    a1, V_VAL(s3)             ; ...
        lwu   a2, TY_SIZE(s1)           ; ...
        lhu   t0, V_SYM(s3)             ; an address not known yet: a fixup fills the word
        beqz  t0, isc_val               ; ...
        mv    a3, a1                    ; ...
        mv    a1, t0                    ; ...
        li    a2, FK_DATA               ; ...
        la    t6, fix_add               ; ...
        xcall ra, c0, t6                ; ...
        j     isc_pop                   ; ...
isc_val:
        jalr  ra, gp, data_put-R        ; ...
isc_pop:
        la    t6, vpop                  ; ...
        xcall ra, c0, t6                ; ...
        jalr  zero, gp, lv0-R           ; done
; isc_bits(): t0 = first bit | width << 8, s2 = the unit's offset, s3 = the
; constant's entry: or the value's bits into the data image, a bit at a time
isc_bits:
        jalr  t6, gp, ent4-R            ; s1 = bit number, s2 = bits left, s3 = value, s4 = byte address
        ld    t1, ini_base(zero)        ; ...
        add   s4, t1, s2                ; ...
        ld    s3, V_VAL(s3)             ; ...
        andi  s1, t0, 255               ; ...
        srli  s2, t0, 8                 ; ...
isb_l:
        beqz  s2, isb_ret               ; ...
        andi  t0, s3, 1                 ; the next bit of the value
        beqz  t0, isb_n                 ; (the image is zero where nothing was stored)
        srli  a0, s1, 3                 ; its byte
        add   a0, a0, s4                ; ...
        jalr  ra, gp, data_rb-R         ; ...
        andi  t0, s1, 7                 ; ...
        li    t1, 1                     ; ...
        sll   t1, t1, t0                ; ...
        or    a1, a0, t1                ; ...
        srli  a0, s1, 3                 ; ...
        add   a0, a0, s4                ; ...
        jalr  ra, gp, data_b-R          ; ...
isb_n:
        srli  s3, s3, 1                 ; ...
        addi  s1, s1, 1                 ; ...
        addi  s2, s2, -1                ; ...
        j     isb_l                     ; ...
isb_ret:
        jalr  zero, gp, lv4-R           ; done

; init_str(a0 = array of char type, a1 = offset) -> a0 = the string's bytes
; with its zero: a string literal initialises the array
init_str:
        jalr  t6, gp, ent4-R            ; s1 = bytes to copy, s2 = offset, s3 = index / address, s4 = type
        mv    s4, a0                    ; ...
        mv    s2, a1                    ; ...
        ld    t0, str_ready(zero)       ; read and joined already?
        sd    zero, str_ready(zero)     ; ...
        bnez  t0, isr_have              ; ...
        li    t0, 1                     ; adjacent literals are one string
        sd    t0, str_cat(zero)         ; ...
isr_cat:
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        ld    t0, tok(zero)             ; ...
        addi  t0, t0, -T_STR            ; ...
        beqz  t0, isr_cat               ; ...
        sd    zero, str_cat(zero)       ; ...
isr_have:
        ld    s1, str_len(zero)         ; with its zero, if the array has room for it
        addi  s1, s1, 1                 ; ...
        lwu   t0, TY_COUNT(s4)          ; ...
        beqz  t0, isr_n                 ; ...
        bleu  s1, t0, isr_n             ; ...
        mv    s1, t0                    ; ...
isr_n:
        ld    t0, ini_dry(zero)         ; ...
        bnez  t0, isr_ret               ; ...
        ld    t0, ini_static(zero)      ; ...
        beqz  t0, isr_auto              ; ...
        li    s3, 0                     ; static: its bytes into the object
isr_b:
        ld    a0, ini_base(zero)        ; ...
        add   a0, a0, s2                ; ...
        add   a0, a0, s3                ; ...
        lbu   a1, STRBUF(s3)            ; ...
        jalr  ra, gp, data_b-R          ; ...
        addi  s3, s3, 1                 ; ...
        bltu  s3, s1, isr_b             ; ...
        j     isr_ret                   ; ...
isr_auto:
        mv    a0, s1                    ; automatic: the bytes are kept in the data image
        li    a1, 1                     ;   and copied in by memcpy
        jalr  ra, gp, data_alloc-R      ; ...
        mv    s3, a0                    ; ...
        li    s4, 0                     ; ...
isr_ab:
        add   a0, s3, s4                ; ...
        lbu   a1, STRBUF(s4)            ; ...
        jalr  ra, gp, data_b-R          ; ...
        addi  s4, s4, 1                 ; ...
        bltu  s4, s1, isr_ab            ; ...
        li    a0, m_memcpy              ; memcpy(object + offset, bytes, n)
        li    a1, 6                     ; ...
        la    t6, lib_fn                ; ...
        xcall ra, c0, t6                ; ...
        li    a0, VK_LADDR              ; ...
        li    a1, Y_VOIDP               ; ...
        ld    a2, ini_base(zero)        ; ...
        add   a2, a2, s2                ; ...
        jalr  ra, gp, vpush-R           ; ...
        li    t0, X_SP                  ; ...
        sb    t0, V_REG(a0)             ; ...
        li    a0, VK_CONST              ; ...
        li    a1, Y_VOIDP               ; ...
        mv    a2, s3                    ; ...
        jalr  ra, gp, vpush-R           ; ...
        li    a0, VK_CONST              ; ...
        li    a1, Y_LONG                ; ...
        mv    a2, s1                    ; ...
        jalr  ra, gp, vpush-R           ; ...
        li    a0, 3                     ; ...
        la    t6, g_call                ; ...
        xcall ra, c0, t6                ; ...
        la    t6, vpop                  ; ...
        xcall ra, c0, t6                ; ...
isr_ret:
        mv    a0, s1                    ; ...
        jalr  zero, gp, lv4-R           ; done

; lib_fn(a0 = name, a1 = length): push the library function of that name as a
; function designator
lib_fn:
        jalr  t6, gp, ent2-R            ; s1 = identifier, s2 = symbol
        jalr  ra, gp, intern-R          ; ...
        mv    s1, a0                    ; ...
        lhu   s2, IDR+ID_SYM(zero)      ; declared already?
        bnez  s2, lfn_push              ; ...
        li    a0, TK_FUNC               ; no: void *name()
        li    a1, 0                     ; ...
        li    a2, 1                     ; ...
        li    a3, Y_VOIDP               ; ...
        jalr  ra, gp, ty_new-R          ; ...
        li    t0, TF_OLD                ; ...
        sb    t0, TY_FLAGS(a0)          ; ...
        mv    a1, a0                    ; ...
        mv    a0, s1                    ; ...
        la    t6, func_decl             ; ...
        xcall ra, c0, t6                ; ...
        mv    s2, a0                    ; ...
lfn_push:
        li    a0, VK_GLOB               ; ...
        lhu   a1, SY_TYPE(s2)           ; ...
        lw    a2, SY_VAL(s2)            ; ...
        jalr  ra, gp, vpush-R           ; ...
        lbu   t0, SY_FLAGS(s2)          ; (not defined: by a fixup)
        andi  t0, t0, SF_DEF            ; ...
        bnez  t0, lfn_ret               ; ...
        sh    s2, V_SYM(a0)             ; ...
        sd    zero, V_VAL(a0)           ; ...
lfn_ret:
        jalr  zero, gp, lv2-R           ; done

        .align 4096                     ; ---- unit: init2 ----
u_init2:
; init_count(a0 = array type of unknown length) -> a0 = the same type with the
; length its initialiser (at the current token) gives it
init_count:
        jalr  t6, gp, ent4-R            ; s1 = type, s2 = count, s3 = nocode as it was, s4 = input stack depth
        mv    s1, a0                    ; ...
        ld    t0, tok(zero)             ; a string for an array of char: read it now
        addi  t0, t0, -T_STR            ; ...
        bnez  t0, icn_dry               ; ...
        lhu   t0, TY_BASE(s1)           ; ...
        lbu   t0, TY_KIND(t0)           ; ...
        addi  t0, t0, -TK_CHAR          ; ...
        bnez  t0, icn_dry               ; ...
        li    t0, 1                     ; ...
        sd    t0, str_cat(zero)         ; ...
icn_cat:
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        ld    t0, tok(zero)             ; ...
        addi  t0, t0, -T_STR            ; ...
        beqz  t0, icn_cat               ; ...
        sd    zero, str_cat(zero)       ; ...
        li    t0, 1                     ; (init_str finds it in STRBUF)
        sd    t0, str_ready(zero)       ; ...
        ld    s2, str_len(zero)         ; ...
        addi  s2, s2, 1                 ; ...
        j     icn_type                  ; ...
icn_dry:
        addi  sp, sp, -64               ; the scanner's state, to come back to
        ld    t0, in_pos(zero)          ; ...
        sd    t0, 0(sp)                 ; ...
        ld    t0, line(zero)            ; ...
        sd    t0, 8(sp)                 ; ...
        ld    t0, bol(zero)             ; ...
        sd    t0, 16(sp)                ; ...
        ld    t0, tok(zero)             ; ...
        sd    t0, 24(sp)                ; ...
        ld    t0, tk_val(zero)          ; ...
        sd    t0, 32(sp)                ; ...
        ld    t0, tk_sym(zero)          ; ...
        sd    t0, 40(sp)                ; ...
        ld    t0, tk_ty(zero)           ; ...
        sd    t0, 48(sp)                ; ...
        ld    t0, tk_tag(zero)          ; ...
        sd    t0, 56(sp)                ; ...
        ld    s4, in_sp(zero)           ; ...
        ld    s3, nocode(zero)          ; ...
        li    t0, 1                     ; a walk that stores and emits nothing
        sd    t0, nocode(zero)          ; ...
        sd    t0, ini_dry(zero)         ; ...
        mv    a0, s1                    ; ...
        li    a1, 0                     ; ...
        la    t6, init_obj              ; ...
        xcall ra, c0, t6                ; ...
        mv    s2, a0                    ; ...
        sd    zero, ini_dry(zero)       ; ...
        sd    s3, nocode(zero)          ; ...
        ld    t0, in_sp(zero)           ; the text must still be the one we started in
        beq   t0, s4, icn_back          ; ...
        li    a0, m_inisz               ; ...
        jalr  zero, gp, error-R         ; ...
icn_back:
        ld    t0, 0(sp)                 ; ...
        sd    t0, in_pos(zero)          ; ...
        ld    t0, 8(sp)                 ; ...
        sd    t0, line(zero)            ; ...
        ld    t0, 16(sp)                ; ...
        sd    t0, bol(zero)             ; ...
        ld    t0, 24(sp)                ; ...
        sd    t0, tok(zero)             ; ...
        ld    t0, 32(sp)                ; ...
        sd    t0, tk_val(zero)          ; ...
        ld    t0, 40(sp)                ; ...
        sd    t0, tk_sym(zero)          ; ...
        ld    t0, 48(sp)                ; ...
        sd    t0, tk_ty(zero)           ; ...
        ld    t0, 56(sp)                ; ...
        sd    t0, tk_tag(zero)          ; ...
        addi  sp, sp, 64                ; ...
icn_type:
        lhu   a3, TY_BASE(s1)           ; the array type with that length
        lwu   a1, TY_SIZE(a3)           ; ...
        mul   a1, a1, s2                ; ...
        lbu   a2, TY_ALIGN(a3)          ; ...
        li    a0, TK_ARRAY              ; ...
        jalr  ra, gp, ty_new-R          ; ...
        sw    s2, TY_COUNT(a0)          ; ...
        jalr  zero, gp, lv4-R           ; done

; static_init(a0 = symbol): the initialiser of a static object
static_init:
        jalr  t6, gp, ent2-R            ; s1 = symbol, s2 = type
        mv    s1, a0                    ; ...
        lhu   s2, SY_TYPE(s1)           ; ...
        lwu   t0, TY_SIZE(s2)           ; an array of unknown length: count, then give it room
        bnez  t0, sti_go                ; ...
        lbu   t0, TY_KIND(s2)           ; ...
        addi  t0, t0, -TK_ARRAY         ; ...
        beqz  t0, sti_cnt               ; ...
        li    a0, m_incomp              ; ...
        jalr  zero, gp, error-R         ; ...
sti_cnt:
        mv    a0, s2                    ; ...
        la    t6, init_count            ; ...
        xcall ra, c0, t6                ; ...
        mv    s2, a0                    ; ...
        sh    s2, SY_TYPE(s1)           ; ...
        lwu   a0, TY_SIZE(s2)           ; ...
        lbu   a1, TY_ALIGN(s2)          ; ...
        jalr  ra, gp, data_alloc-R      ; ...
        sw    a0, SY_VAL(s1)            ; ...
        li    t0, SF_DEF                ; ...
        sb    t0, SY_FLAGS(s1)          ; ...
sti_go:
        li    t0, 1                     ; ...
        sd    t0, ini_static(zero)      ; ...
        lw    t0, SY_VAL(s1)            ; ...
        sd    t0, ini_base(zero)        ; ...
        mv    a0, s2                    ; ...
        li    a1, 0                     ; ...
        la    t6, init_obj              ; ...
        xcall ra, c0, t6                ; ...
        jalr  zero, gp, lv2-R           ; done

; auto_init_size(a0 = symbol): an automatic array of unknown length gets its
; type from the initialiser that follows the =
auto_init_size:
        jalr  t6, gp, ent1-R            ; s1 = symbol
        mv    s1, a0                    ; ...
        la    t6, next                  ; (the =)
        xcall ra, c0, t6                ; ...
        lhu   a0, SY_TYPE(s1)           ; ...
        la    t6, init_count            ; ...
        xcall ra, c0, t6                ; ...
        sh    a0, SY_TYPE(s1)           ; ...
        jalr  zero, gp, lv1-R           ; done

; auto_init(a0 = symbol): the initialiser of an automatic object
auto_init:
        jalr  t6, gp, ent3-R            ; s1 = symbol, s2 = type, s3 = scratch
        mv    s1, a0                    ; ...
        lhu   s2, SY_TYPE(s1)           ; ...
        sd    zero, ini_static(zero)    ; ...
        lw    t0, SY_VAL(s1)            ; ...
        sd    t0, ini_base(zero)        ; ...
        lbu   t0, TY_KIND(s2)           ; ...
        sltiu t1, t0, TK_ARRAY          ; a scalar: one assignment
        bnez  t1, aui_obj               ; ...
        ld    t1, tok(zero)             ; an aggregate in braces, or a string: cleared first
        li    t2, '{'                   ; ...
        beq   t1, t2, aui_zero          ; ...
        li    t2, T_STR                 ; ...
        beq   t1, t2, aui_zero          ; ...
        ld    t2, str_ready(zero)       ; ...
        bnez  t2, aui_zero              ; ...
        li    a0, VK_LOC                ; a struct = an expression of its type
        mv    a1, s2                    ; ...
        lw    a2, SY_VAL(s1)            ; ...
        jalr  ra, gp, vpush-R           ; ...
        li    t0, X_SP                  ; ...
        sb    t0, V_REG(a0)             ; ...
        la    t6, assign                ; ...
        xcall ra, c0, t6                ; ...
        la    t6, g_store               ; ...
        xcall ra, c0, t6                ; ...
        la    t6, vpop                  ; ...
        xcall ra, c0, t6                ; ...
        jalr  zero, gp, lv3-R           ; ...
aui_zero:
        lw    a0, SY_VAL(s1)            ; ...
        lwu   a1, TY_SIZE(s2)           ; ...
        lbu   a2, TY_ALIGN(s2)          ; ...
        la    t6, g_zero                ; ...
        xcall ra, c0, t6                ; ...
aui_obj:
        mv    a0, s2                    ; ...
        li    a1, 0                     ; ...
        la    t6, init_obj              ; ...
        xcall ra, c0, t6                ; ...
        jalr  zero, gp, lv3-R           ; done

; g_zero(a0 = frame offset, a1 = bytes, a2 = alignment): clear part of the frame
g_zero:
        jalr  t6, gp, ent4-R            ; s1 = offset, s2 = bytes left, s3 = piece, s4 = store opcode
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        mv    s3, a2                    ; ...
        li    t0, 65                    ; more than 64 bytes: memset(object, 0, n)
        bltu  s2, t0, gze_in            ; ...
        li    a0, m_memset              ; ...
        li    a1, 6                     ; ...
        la    t6, lib_fn                ; ...
        xcall ra, c0, t6                ; ...
        li    a0, VK_LADDR              ; ...
        li    a1, Y_VOIDP               ; ...
        mv    a2, s1                    ; ...
        jalr  ra, gp, vpush-R           ; ...
        li    t0, X_SP                  ; ...
        sb    t0, V_REG(a0)             ; ...
        li    a0, VK_CONST              ; ...
        li    a1, Y_INT                 ; ...
        li    a2, 0                     ; ...
        jalr  ra, gp, vpush-R           ; ...
        li    a0, VK_CONST              ; ...
        li    a1, Y_LONG                ; ...
        mv    a2, s2                    ; ...
        jalr  ra, gp, vpush-R           ; ...
        li    a0, 3                     ; ...
        la    t6, g_call                ; ...
        xcall ra, c0, t6                ; ...
        la    t6, vpop                  ; ...
        xcall ra, c0, t6                ; ...
        jalr  zero, gp, lv4-R           ; ...
gze_in:
        li    s4, OP_SD                 ; stores of the zero register, as wide as the alignment allows
        li    t0, 8                     ; ...
        beq   s3, t0, gze_l             ; ...
        li    s4, OP_SW                 ; ...
        li    t0, 4                     ; ...
        beq   s3, t0, gze_l             ; ...
        li    s4, OP_SH                 ; ...
        li    t0, 2                     ; ...
        beq   s3, t0, gze_l             ; ...
        li    s4, OP_SB                 ; ...
gze_l:
        blez  s2, gze_ret               ; ...
        mv    a0, s4                    ; ...
        li    a1, 0                     ; ...
        li    a2, X_SP                  ; ...
        ld    a3, sp_bias(zero)         ; ...
        add   a3, a3, s1                ; ...
        la    t6, g_mem                 ; ...
        xcall ra, c0, t6                ; ...
        add   s1, s1, s3                ; ...
        sub   s2, s2, s3                ; ...
        j     gze_l                     ; ...
gze_ret:
        jalr  zero, gp, lv4-R           ; done
