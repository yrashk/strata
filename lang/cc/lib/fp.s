; =============================================================================
; fp.s: IEEE 754 double arithmetic in software
; =============================================================================
;
; Strata has no floating-point instructions. These routines take and return
; doubles as 64-bit patterns in integer registers, with the C calling
; convention (a0, a1 -> a0; t0..t6 and a0..a5 are not kept; no stack, no data).
; They round to nearest, ties to even, and handle zeros, subnormals,
; infinities and NaNs; there are no exception flags.
;
; This file is only code and has no section directive: it is included by
; lib/libc.s (what compiled programs call) and by the compiler (cc-fp.s),
; which folds constant expressions with the same routines.
;
;   __fadd __fsub __fmul __fdiv (a, b)       __fcmp(a, b) -> -1, 0, 1; 2: unordered
;   __itof(long) __utof(unsigned long)       __ftoi(double) -> long, __ftou -> unsigned long
;   __f2d(float pattern) -> double           __d2f(double) -> float pattern

; __fpk: t0 = sign, t1 = exponent, a0 = mantissa: the double nearest to
; a0 * 2^(t1 - 1085), i.e. with the mantissa's leading bit at bit 62 the biased
; exponent is t1
__fpk:
        beqz  a0, __fpk_zero            ; nothing: a signed zero
        bltz  a0, __fpk_r1              ; the leading bit at 63: one place right
__fpk_nl:
        slli  t2, a0, 1                 ; left until it is at 62
        bltz  t2, __fpk_n               ; ...
        mv    a0, t2                    ; ...
        addi  t1, t1, -1                ; ...
        j     __fpk_nl                  ; ...
__fpk_r1:
        andi  t2, a0, 1                 ; (the bit shifted out is kept as a sticky bit)
        srli  a0, a0, 1                 ; ...
        or    a0, a0, t2                ; ...
        addi  t1, t1, 1                 ; ...
__fpk_n:
        bgtz  t1, __fpk_rnd             ; a normal number
        li    t2, 1                     ; subnormal: shift right until the exponent is 1
        sub   t2, t2, t1                ; ...
        slti  t3, t2, 64                ; ...
        beqz  t3, __fpk_tiny            ; ...
        srl   t3, a0, t2                ; ...
        sll   t4, t3, t2                ; (what was lost: sticky)
        xor   t4, t4, a0                ; ...
        snez  t4, t4                    ; ...
        or    a0, t3, t4                ; ...
        li    t1, 1                     ; ...
        j     __fpk_rnd                 ; ...
__fpk_tiny:
        li    a0, 1                     ; only the sticky bit is left
        li    t1, 1                     ; ...
__fpk_rnd:
        andi  t2, a0, 0x3ff             ; the ten bits below the 53 kept
        srli  a0, a0, 10                ; ...
        li    t3, 0x200                 ; half
        bltu  t2, t3, __fpk_pk          ; below: down
        bne   t2, t3, __fpk_up          ; above: up
        andi  t3, a0, 1                 ; a tie: to even
        beqz  t3, __fpk_pk              ; ...
__fpk_up:
        addi  a0, a0, 1                 ; ...
__fpk_pk:
        addi  t1, t1, -1                ; the mantissa's bit 52 adds one to the exponent
        slli  t1, t1, 52                ;   (a subnormal has none, a carry to bit 53 adds two)
        add   a0, a0, t1                ; ...
        srli  t2, a0, 52                ; too large: infinity
        li    t3, 0x7ff                 ; ...
        bltu  t2, t3, __fpk_sign        ; ...
        slli  a0, t3, 52                ; ...
__fpk_sign:
        slli  t0, t0, 63                ; ...
        or    a0, a0, t0                ; ...
        ret                             ; done
__fpk_zero:
        slli  a0, t0, 63                ; ...
        ret                             ; done

; __funp: unpack a0 -> t0 sign, t1 exponent, a2 mantissa (52 bits); a1 -> t2,
; t3, a3. Returns through t6.
__funp:
        srli  t0, a0, 63                ; ...
        slli  t1, a0, 1                 ; ...
        srli  t1, t1, 53                ; ...
        slli  a2, a0, 12                ; ...
        srli  a2, a2, 12                ; ...
        srli  t2, a1, 63                ; ...
        slli  t3, a1, 1                 ; ...
        srli  t3, t3, 53                ; ...
        slli  a3, a1, 12                ; ...
        srli  a3, a3, 12                ; ...
        jr    t6                        ; done
; __fnan: a quiet NaN
__fnan:
        li    a0, 0xfff                 ; 0x7FF8 << 48
        slli  a0, a0, 51                ; ...
        srli  a0, a0, 1                 ; ...
        slli  a0, a0, 1                 ; (the sign bit clear)
        srli  a0, a0, 1                 ; ...
        ret                             ; done
; __fnorm: give both mantissas their leading bit at bit 52 (the implicit bit of
; a normal number; a subnormal is shifted up, its exponent going below 1).
; Returns through t6.
__fnorm:
        li    t4, 1                     ; bit 52
        slli  t4, t4, 52                ; ...
        beqz  t1, __fnm_as              ; ...
        or    a2, a2, t4                ; ...
        j     __fnm_b                   ; ...
__fnm_as:
        li    t1, 1                     ; ...
__fnm_al:
        and   t5, a2, t4                ; ...
        bnez  t5, __fnm_b               ; ...
        beqz  a2, __fnm_b               ; (zero: the caller dealt with it)
        slli  a2, a2, 1                 ; ...
        addi  t1, t1, -1                ; ...
        j     __fnm_al                  ; ...
__fnm_b:
        beqz  t3, __fnm_bs              ; ...
        or    a3, a3, t4                ; ...
        jr    t6                        ; ...
__fnm_bs:
        li    t3, 1                     ; ...
__fnm_bl:
        and   t5, a3, t4                ; ...
        bnez  t5, __fnm_r               ; ...
        beqz  a3, __fnm_r               ; ...
        slli  a3, a3, 1                 ; ...
        addi  t3, t3, -1                ; ...
        j     __fnm_bl                  ; ...
__fnm_r:
        jr    t6                        ; done

; __fsub(a, b) = a + (-b)
__fsub:
        li    t0, 1                     ; flip b's sign
        slli  t0, t0, 63                ; ...
        xor   a1, a1, t0                ; ...
; __fadd(a, b)
__fadd:
        jal   t6, __funp                ; ...
        li    t4, 0x7ff                 ; an infinity or a NaN among them?
        bne   t1, t4, __fad_b           ; ...
        bnez  a2, __fad_ra              ; a is a NaN: that
        bne   t3, t4, __fad_ra          ; a is infinite, b finite: a
        bnez  a3, __fad_rb              ; b is a NaN: that
        beq   t0, t2, __fad_ra          ; the same infinity: it
        j     __fnan                    ; opposite infinities
__fad_b:
        beq   t3, t4, __fad_rb          ; b infinite or a NaN: b
        li    t4, 1                     ; the implicit bits (a subnormal's exponent counts as 1)
        slli  t4, t4, 52                ; ...
        beqz  t1, __fad_as              ; ...
        or    a2, a2, t4                ; ...
        j     __fad_bi                  ; ...
__fad_as:
        li    t1, 1                     ; ...
__fad_bi:
        beqz  t3, __fad_bs              ; ...
        or    a3, a3, t4                ; ...
        j     __fad_al                  ; ...
__fad_bs:
        li    t3, 1                     ; ...
__fad_al:
        slli  a2, a2, 10                ; room for guard bits: the leading bit at 62
        slli  a3, a3, 10                ; ...
        bge   t1, t3, __fad_ord         ; a is the one with the larger exponent
        mv    t4, t0                    ; (swap them)
        mv    t0, t2                    ; ...
        mv    t2, t4                    ; ...
        mv    t4, t1                    ; ...
        mv    t1, t3                    ; ...
        mv    t3, t4                    ; ...
        mv    t4, a2                    ; ...
        mv    a2, a3                    ; ...
        mv    a3, t4                    ; ...
__fad_ord:
        sub   t4, t1, t3                ; b shifted right to a's exponent, with a sticky bit
        beqz  t4, __fad_op              ; ...
        slti  t5, t4, 64                ; ...
        bnez  t5, __fad_sh              ; ...
        snez  a3, a3                    ; ...
        j     __fad_op                  ; ...
__fad_sh:
        srl   t5, a3, t4                ; ...
        sll   t3, t5, t4                ; ...
        xor   t3, t3, a3                ; ...
        snez  t3, t3                    ; ...
        or    a3, t5, t3                ; ...
__fad_op:
        bne   t0, t2, __fad_sub         ; the same sign: add
        add   a0, a2, a3                ; ...
        j     __fpk                     ; ...
__fad_sub:
        sub   a0, a2, a3                ; opposite signs: subtract
        bgez  a0, __fad_pos             ; ...
        neg   a0, a0                    ; (b was the larger: its sign)
        mv    t0, t2                    ; ...
        j     __fpk                     ; ...
__fad_pos:
        bnez  a0, __fpk                 ; ...
        li    t0, 0                     ; x - x is +0
        j     __fpk                     ; ...
__fad_ra:
        ret                             ; a0 is the result
__fad_rb:
        mv    a0, a1                    ; ...
        ret                             ; done

; __fmul(a, b)
__fmul:
        jal   t6, __funp                ; ...
        xor   t0, t0, t2                ; the result's sign
        li    t4, 0x7ff                 ; ...
        bne   t1, t4, __fmu_b           ; ...
        bnez  a2, __fad_ra              ; a is a NaN
        bne   t3, t4, __fmu_ai          ; ...
        bnez  a3, __fad_rb              ; b is a NaN
        j     __fmu_inf                 ; infinity times infinity
__fmu_ai:
        or    t5, t3, a3                ; infinity times zero is not a number
        beqz  t5, __fnan                ; ...
        j     __fmu_inf                 ; ...
__fmu_b:
        bne   t3, t4, __fmu_fin         ; ...
        bnez  a3, __fad_rb              ; b is a NaN
        or    t5, t1, a2                ; zero times infinity
        beqz  t5, __fnan                ; ...
__fmu_inf:
        slli  a0, t4, 52                ; ...
        slli  t0, t0, 63                ; ...
        or    a0, a0, t0                ; ...
        ret                             ; ...
__fmu_fin:
        or    t5, t1, a2                ; a zero factor: a signed zero
        beqz  t5, __fpk_zero            ; ...
        or    t5, t3, a3                ; ...
        beqz  t5, __fpk_zero            ; ...
        jal   t6, __fnorm               ; ...
        slli  a2, a2, 11                ; both leading bits at 63: the high word of the
        slli  a3, a3, 11                ;   product has its leading bit at 63 or 62
        mulhu a0, a2, a3                ; ...
        mul   t4, a2, a3                ; (the low word only as a sticky bit)
        snez  t4, t4                    ; ...
        or    a0, a0, t4                ; ...
        add   t1, t1, t3                ; ...
        addi  t1, t1, -1023             ; ...
        j     __fpk                     ; ...

; __fdiv(a, b)
__fdiv:
        jal   t6, __funp                ; ...
        xor   t0, t0, t2                ; the result's sign
        li    t4, 0x7ff                 ; ...
        bne   t1, t4, __fdv_b           ; ...
        bnez  a2, __fad_ra              ; a is a NaN
        bne   t3, t4, __fmu_inf         ; infinity / finite
        bnez  a3, __fad_rb              ; b is a NaN
        j     __fnan                    ; infinity / infinity
__fdv_b:
        bne   t3, t4, __fdv_fin         ; ...
        bnez  a3, __fad_rb              ; b is a NaN
        j     __fpk_zero                ; finite / infinity
__fdv_fin:
        or    t5, t3, a3                ; a zero divisor
        bnez  t5, __fdv_nz              ; ...
        or    t5, t1, a2                ; 0 / 0
        beqz  t5, __fnan                ; ...
        j     __fmu_inf                 ; x / 0
__fdv_nz:
        or    t5, t1, a2                ; 0 / x
        beqz  t5, __fpk_zero            ; ...
        jal   t6, __fnorm               ; ...
        li    a0, 0                     ; the quotient, a bit at a time: one bit, then 62 more
        bltu  a2, a3, __fdv_l0          ; ...
        sub   a2, a2, a3                ; ...
        li    a0, 1                     ; ...
__fdv_l0:
        li    t4, 62                    ; ...
__fdv_l:
        slli  a2, a2, 1                 ; ...
        slli  a0, a0, 1                 ; ...
        bltu  a2, a3, __fdv_n           ; ...
        sub   a2, a2, a3                ; ...
        ori   a0, a0, 1                 ; ...
__fdv_n:
        addi  t4, t4, -1                ; ...
        bnez  t4, __fdv_l               ; ...
        snez  a2, a2                    ; a remainder: sticky
        or    a0, a0, a2                ; ...
        sub   t1, t1, t3                ; ...
        addi  t1, t1, 1023              ; ...
        j     __fpk                     ; ...

; __fcmp(a, b) -> -1 if a < b, 0 if equal, 1 if a > b, 2 if either is a NaN
__fcmp:
        slli  t0, a0, 1                 ; without the signs
        slli  t1, a1, 1                 ; ...
        li    t2, 0x7ff                 ; above infinity: a NaN
        slli  t2, t2, 53                ; ...
        bgtu  t0, t2, __fcm_un          ; ...
        bgtu  t1, t2, __fcm_un          ; ...
        or    t2, t0, t1                ; both zero (of either sign): equal
        beqz  t2, __fcm_eq              ; ...
        srli  t2, a0, 63                ; different signs: the negative one is less
        srli  t3, a1, 63                ; ...
        beq   t2, t3, __fcm_mag         ; ...
        li    a0, 1                     ; ...
        beqz  t2, __fcm_ret             ; ...
        li    a0, -1                    ; ...
        ret                             ; ...
__fcm_mag:
        beq   a0, a1, __fcm_eq          ; the same sign: compare the magnitudes
        sltu  t0, a0, a1                ; ...
        xor   t0, t0, t2                ; (the other way round if negative)
        li    a0, 1                     ; ...
        beqz  t0, __fcm_ret             ; ...
        li    a0, -1                    ; ...
__fcm_ret:
        ret                             ; ...
__fcm_eq:
        li    a0, 0                     ; ...
        ret                             ; ...
__fcm_un:
        li    a0, 2                     ; ...
        ret                             ; done

; __itof(long) -> double, __utof(unsigned long) -> double
__itof:
        srli  t0, a0, 63                ; the sign and the magnitude
        beqz  t0, __utof_m              ; ...
        neg   a0, a0                    ; ...
        j     __utof_m                  ; ...
__utof:
        li    t0, 0                     ; ...
__utof_m:
        li    t1, 1085                  ; a0 * 2^0
        j     __fpk                     ; ...

; __ftoi(double) -> long, toward zero (out of range: the nearest long)
__ftoi:
        slli  t1, a0, 1                 ; the exponent
        srli  t1, t1, 53                ; ...
        srli  t0, a0, 63                ; the sign
        slti  t2, t1, 1023              ; below 1: 0
        bnez  t2, __fti_zero            ; ...
        slti  t2, t1, 1086              ; 2^63 and above (and NaN): the limit
        beqz  t2, __fti_sat             ; ...
        slli  a0, a0, 12                ; the mantissa with its implicit bit
        srli  a0, a0, 12                ; ...
        li    t2, 1                     ; ...
        slli  t2, t2, 52                ; ...
        or    a0, a0, t2                ; ...
        addi  t1, t1, -1075             ; shift it to the units
        bltz  t1, __fti_r               ; ...
        sll   a0, a0, t1                ; ...
        j     __fti_s                   ; ...
__fti_r:
        neg   t1, t1                    ; ...
        srl   a0, a0, t1                ; ...
__fti_s:
        beqz  t0, __fti_ret             ; ...
        neg   a0, a0                    ; ...
__fti_ret:
        ret                             ; ...
__fti_zero:
        li    a0, 0                     ; ...
        ret                             ; ...
__fti_sat:
        li    a0, 1                     ; the most negative long, or the most positive
        slli  a0, a0, 63                ; ...
        bnez  t0, __fti_ret             ; ...
        addi  a0, a0, -1                ; ...
        ret                             ; done
; __ftou(double) -> unsigned long, toward zero
__ftou:
        slli  t1, a0, 1                 ; ...
        srli  t1, t1, 53                ; ...
        srli  t0, a0, 63                ; a negative number: as __ftoi (it wraps)
        bnez  t0, __ftoi                ; ...
        slti  t2, t1, 1086              ; below 2^63: as __ftoi
        bnez  t2, __ftoi                ; ...
        slti  t2, t1, 1087              ; 2^64 and above: the largest
        beqz  t2, __ftu_max             ; ...
        slli  a0, a0, 11                ; 2^63 .. 2^64: the mantissa's leading bit at 63
        li    t2, 1                     ; ...
        slli  t2, t2, 63                ; ...
        or    a0, a0, t2                ; ...
        ret                             ; ...
__ftu_max:
        li    a0, -1                    ; ...
        ret                             ; done

; __f2d(float pattern) -> double
__f2d:
        srli  t0, a0, 31                ; sign
        andi  t0, t0, 1                 ; ...
        srli  t1, a0, 23                ; exponent
        andi  t1, t1, 255               ; ...
        slli  a0, a0, 41                ; mantissa (23 bits)
        srli  a0, a0, 41                ; ...
        li    t2, 255                   ; ...
        bne   t1, t2, __f2d_fin         ; ...
        li    t1, 0x7ff                 ; infinity or NaN
        j     __f2d_pk                  ; ...
__f2d_fin:
        bnez  t1, __f2d_n               ; ...
        beqz  a0, __f2d_z               ; zero
        li    t1, 1                     ; subnormal: bring its leading bit to bit 23
        li    t2, 1                     ; ...
        slli  t2, t2, 23                ; ...
__f2d_l:
        and   t3, a0, t2                ; ...
        bnez  t3, __f2d_s               ; ...
        slli  a0, a0, 1                 ; ...
        addi  t1, t1, -1                ; ...
        j     __f2d_l                   ; ...
__f2d_s:
        xor   a0, a0, t2                ; (the implicit bit goes)
__f2d_n:
        addi  t1, t1, 896               ; 1023 - 127
__f2d_pk:
        slli  a0, a0, 29                ; ...
        slli  t1, t1, 52                ; ...
        or    a0, a0, t1                ; ...
__f2d_z:
        slli  t0, t0, 63                ; ...
        or    a0, a0, t0                ; ...
        ret                             ; done

; __d2f(double) -> float pattern (sign-extended from bit 31)
__d2f:
        srli  t0, a0, 63                ; sign
        slli  t1, a0, 1                 ; exponent
        srli  t1, t1, 53                ; ...
        slli  a0, a0, 12                ; mantissa
        srli  a0, a0, 12                ; ...
        li    t2, 0x7ff                 ; ...
        bne   t1, t2, __d2f_fin         ; ...
        snez  a0, a0                    ; infinity, or a NaN
        slli  a0, a0, 22                ; ...
        li    t1, 255                   ; ...
        slli  t1, t1, 23                ; ...
        or    a0, a0, t1                ; ...
        j     __d2f_sign                ; ...
__d2f_fin:
        bnez  t1, __d2f_n               ; ...
        li    a0, 0                     ; a double's zero or subnormal: zero
        j     __d2f_sign                ; ...
__d2f_n:
        li    t2, 1                     ; the implicit bit
        slli  t2, t2, 52                ; ...
        or    a0, a0, t2                ; ...
        addi  t1, t1, -896              ; the float's exponent
        bgtz  t1, __d2f_rnd             ; ...
        li    t2, 1                     ; subnormal: shift right until it is 1
        sub   t2, t2, t1                ; ...
        slti  t3, t2, 60                ; ...
        bnez  t3, __d2f_sh              ; ...
        li    a0, 1                     ; ...
        j     __d2f_s1                  ; ...
__d2f_sh:
        srl   t3, a0, t2                ; ...
        sll   t4, t3, t2                ; ...
        xor   t4, t4, a0                ; ...
        snez  t4, t4                    ; ...
        or    a0, t3, t4                ; ...
__d2f_s1:
        li    t1, 1                     ; ...
__d2f_rnd:
        slli  t2, a0, 35                ; the 29 bits below the 24 kept
        srli  t2, t2, 35                ; ...
        srli  a0, a0, 29                ; ...
        li    t3, 1                     ; half
        slli  t3, t3, 28                ; ...
        bltu  t2, t3, __d2f_pk          ; ...
        bne   t2, t3, __d2f_up          ; ...
        andi  t3, a0, 1                 ; ...
        beqz  t3, __d2f_pk              ; ...
__d2f_up:
        addi  a0, a0, 1                 ; ...
__d2f_pk:
        addi  t1, t1, -1                ; (as in __fpk)
        slli  t1, t1, 23                ; ...
        add   a0, a0, t1                ; ...
        srli  t2, a0, 23                ; too large: infinity
        li    t3, 255                   ; ...
        bltu  t2, t3, __d2f_sign        ; ...
        slli  a0, t3, 23                ; ...
__d2f_sign:
        slli  t0, t0, 31                ; ...
        or    a0, a0, t0                ; ...
        slli  a0, a0, 32                ; ...
        srai  a0, a0, 32                ; ...
        ret                             ; done
