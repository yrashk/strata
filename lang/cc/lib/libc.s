; strtol(s, end, base), strtoul(s, end, base): base 0 reads 0x and 0 prefixes
strtol:
strtoul:
__st_sp:
        lbu   t0, 0(a0)                 ; skip white space
        li    t1, ' '                   ; ...
        beq   t0, t1, __st_spn          ; ...
        addi  t1, t0, -9                ; \t \n \v \f \r
        sltiu t1, t1, 5                 ; ...
        beqz  t1, __st_sign             ; ...
__st_spn:
        addi  a0, a0, 1                 ; ...
        j     __st_sp                   ; ...
__st_sign:
        li    t5, 0                     ; t5 = negative
        li    t1, '-'                   ; ...
        bne   t0, t1, __st_plus         ; ...
        li    t5, 1                     ; ...
        addi  a0, a0, 1                 ; ...
        j     __st_base                 ; ...
__st_plus:
        li    t1, '+'                   ; ...
        bne   t0, t1, __st_base         ; ...
        addi  a0, a0, 1                 ; ...
__st_base:
        lbu   t0, 0(a0)                 ; a 0x or 0 prefix
        li    t1, '0'                   ; ...
        bne   t0, t1, __st_dec          ; ...
        lbu   t0, 1(a0)                 ; ...
        ori   t0, t0, 32                ; ...
        li    t1, 'x'                   ; ...
        bne   t0, t1, __st_oct          ; ...
        beqz  a2, __st_hex              ; base 0 or 16 takes it
        li    t1, 16                    ; ...
        bne   a2, t1, __st_go           ; ...
__st_hex:
        li    a2, 16                    ; ...
        addi  a0, a0, 2                 ; ...
        j     __st_go                   ; ...
__st_oct:
        bnez  a2, __st_go               ; ...
        li    a2, 8                     ; ...
        j     __st_go                   ; ...
__st_dec:
        bnez  a2, __st_go               ; ...
        li    a2, 10                    ; ...
__st_go:
        li    t4, 0                     ; t4 = the value
__st_dig:
        lbu   t0, 0(a0)                 ; a digit?
        addi  t1, t0, -'0'              ; ...
        sltiu t2, t1, 10                ; ...
        bnez  t2, __st_have             ; ...
        ori   t0, t0, 32                ; a letter?
        addi  t1, t0, -'a'              ; ...
        sltiu t2, t1, 26                ; ...
        beqz  t2, __st_end              ; no
        addi  t1, t1, 10                ; ...
__st_have:
        bgeu  t1, a2, __st_end          ; not of this base
        mul   t4, t4, a2                ; ...
        add   t4, t4, t1                ; ...
        addi  a0, a0, 1                 ; ...
        j     __st_dig                  ; ...
__st_end:
        beqz  a1, __st_neg              ; *end = where it stopped
        sd    a0, 0(a1)                 ; ...
__st_neg:
        mv    a0, t4                    ; ...
        beqz  t5, __st_ret              ; ...
        neg   a0, a0                    ; ...
__st_ret:
        ret                             ; done

