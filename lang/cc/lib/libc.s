; malloc(n) -> a block of n bytes, 8-byte aligned, or 0
malloc:
        addi  a0, a0, 15                ; the header, and whole words
        srli  a0, a0, 3                 ; ...
        slli  a0, a0, 3                 ; ...
        ld    t0, __heap(zero)          ; t0 = a block
        ld    t1, __hend(zero)          ; t1 = the heap's end
__ma_loop:
        bgeu  t0, t1, __ma_none         ; no block is big enough
        ld    t2, 0(t0)                 ; its size and bit
        andi  t3, t2, 1                 ; used?
        beqz  t3, __ma_free             ; no
        addi  t2, t2, -1                ; skip it
        add   t0, t0, t2                ; ...
        j     __ma_loop                 ; ...
__ma_free:
        add   t3, t0, t2                ; the next block: free too?
        bgeu  t3, t1, __ma_fit          ; (there is none)
        ld    t4, 0(t3)                 ; ...
        andi  t5, t4, 1                 ; ...
        bnez  t5, __ma_fit              ; no
        add   t2, t2, t4                ; merge them
        sd    t2, 0(t0)                 ; ...
        j     __ma_free                 ; and look again
__ma_fit:
        bgeu  t2, a0, __ma_take         ; big enough
        add   t0, t0, t2                ; the next block
        j     __ma_loop                 ; ...
__ma_take:
        sub   t3, t2, a0                ; what is left over
        sltiu t4, t3, 16                ; too small to be a block?
        bnez  t4, __ma_all              ; yes: take all of it
        add   t4, t0, a0                ; the rest is a free block
        sd    t3, 0(t4)                 ; ...
        mv    t2, a0                    ; ...
__ma_all:
        ori   t2, t2, 1                 ; used
        sd    t2, 0(t0)                 ; ...
        addi  a0, t0, 8                 ; the payload
        ret                             ; done
__ma_none:
        li    a0, 0                     ; no memory
        ret                             ; done

; free(p)
free:
        beqz  a0, __fr_r                ; free(0) does nothing
        ld    t0, -8(a0)                ; clear the used bit
        andi  t1, t0, 1                 ; ...
        sub   t0, t0, t1                ; ...
        sd    t0, -8(a0)                ; ...
__fr_r:
        ret                             ; done

; calloc(n, size) -> zeroed memory, or 0
calloc:
        addi  sp, sp, -16               ; frame
        sd    ra, 8(sp)                 ; ...
        mul   a0, a0, a1                ; bytes
        sd    a0, 0(sp)                 ; ...
        call  malloc                    ; ...
        beqz  a0, __ca_ret              ; none
        li    a1, 0                     ; clear it
        ld    a2, 0(sp)                 ; ...
        call  memset                    ; (a0 is kept)
__ca_ret:
        ld    ra, 8(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; done

; realloc(p, n) -> a block of n bytes with p's contents, or 0
realloc:
        beqz  a0, __re_new              ; realloc(0, n) is malloc(n)
        addi  sp, sp, -32               ; frame
        sd    ra, 24(sp)                ; ...
        sd    a0, 0(sp)                 ; p
        sd    a1, 8(sp)                 ; n
        mv    a0, a1                    ; a new block
        call  malloc                    ; ...
        sd    a0, 16(sp)                ; ...
        beqz  a0, __re_ret              ; none: p stays
        ld    a1, 0(sp)                 ; copy the smaller of the two sizes
        ld    a2, -8(a1)                ; p's block size
        addi  a2, a2, -9                ; without header and bit
        ld    t0, 8(sp)                 ; ...
        bleu  a2, t0, __re_cp           ; ...
        mv    a2, t0                    ; ...
__re_cp:
        call  memcpy                    ; ...
        ld    a0, 0(sp)                 ; and free p
        call  free                      ; ...
__re_ret:
        ld    a0, 16(sp)                ; ...
        ld    ra, 24(sp)                ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; done
__re_new:
        mv    a0, a1                    ; ...
        j     malloc                    ; ...

