; memcpy(d, s, n) / memmove(d, s, n) -> d: overlap is handled in both
memcpy:
memmove:
        beqz  a2, __mc_ret              ; nothing
        bltu  a1, a0, __mc_back         ; the source is below: copy from the end
        mv    t0, a0                    ; forwards
        add   t2, a1, a2                ; end of the source
__mc_f:
        lbu   t1, 0(a1)                 ; ...
        sb    t1, 0(t0)                 ; ...
        addi  a1, a1, 1                 ; ...
        addi  t0, t0, 1                 ; ...
        bltu  a1, t2, __mc_f            ; ...
        ret                             ; ...
__mc_back:
        add   t0, a0, a2                ; backwards
        add   t2, a1, a2                ; ...
__mc_b:
        addi  t2, t2, -1                ; ...
        addi  t0, t0, -1                ; ...
        lbu   t1, 0(t2)                 ; ...
        sb    t1, 0(t0)                 ; ...
        bgtu  t2, a1, __mc_b            ; ...
__mc_ret:
        ret                             ; done

; memset(d, c, n) -> d
memset:
        add   t1, a0, a2                ; end
        mv    t0, a0                    ; cursor
__mst_l:
        bgeu  t0, t1, __mst_r           ; done
        sb    a1, 0(t0)                 ; ...
        addi  t0, t0, 1                 ; ...
        j     __mst_l                   ; ...
__mst_r:
        ret                             ; done

; memcmp(a, b, n) -> < 0, 0, > 0
memcmp:
        add   t2, a0, a2                ; end of a
__mcm_l:
        bgeu  a0, t2, __mcm_eq          ; the same
        lbu   t0, 0(a0)                 ; ...
        lbu   t1, 0(a1)                 ; ...
        addi  a0, a0, 1                 ; ...
        addi  a1, a1, 1                 ; ...
        beq   t0, t1, __mcm_l           ; ...
        sub   a0, t0, t1                ; the first difference
        ret                             ; ...
__mcm_eq:
        li    a0, 0                     ; equal
        ret                             ; done

; memchr(s, c, n) -> the first c, or 0
memchr:
        add   t2, a0, a2                ; end
        andi  a1, a1, 255               ; ...
__mch_l:
        bgeu  a0, t2, __mch_no          ; not there
        lbu   t0, 0(a0)                 ; ...
        beq   t0, a1, __mch_ret         ; found
        addi  a0, a0, 1                 ; ...
        j     __mch_l                   ; ...
__mch_no:
        li    a0, 0                     ; ...
__mch_ret:
        ret                             ; done

; strlen(s)
strlen:
        mv    t0, a0                    ; cursor
__sl_l:
        lbu   t1, 0(t0)                 ; ...
        beqz  t1, __sl_r                ; ...
        addi  t0, t0, 1                 ; ...
        j     __sl_l                    ; ...
__sl_r:
        sub   a0, t0, a0                ; ...
        ret                             ; done

; strcat(d, s) -> d
strcat:
        mv    t0, a0                    ; find d's end
__sct_l:
        lbu   t1, 0(t0)                 ; ...
        beqz  t1, __scp_l               ; then copy s there
        addi  t0, t0, 1                 ; ...
        j     __sct_l                   ; ...
; strcpy(d, s) -> d
strcpy:
        mv    t0, a0                    ; cursor
__scp_l:
        lbu   t1, 0(a1)                 ; a byte, the zero included
        sb    t1, 0(t0)                 ; ...
        addi  a1, a1, 1                 ; ...
        addi  t0, t0, 1                 ; ...
        bnez  t1, __scp_l               ; ...
        ret                             ; done

; strncat(d, s, n) -> d
strncat:
        mv    t0, a0                    ; find d's end
__snt_l:
        lbu   t1, 0(t0)                 ; ...
        beqz  t1, __snt_c               ; ...
        addi  t0, t0, 1                 ; ...
        j     __snt_l                   ; ...
__snt_c:
        beqz  a2, __snt_z               ; n bytes at most
        lbu   t1, 0(a1)                 ; ...
        beqz  t1, __snt_z               ; ...
        sb    t1, 0(t0)                 ; ...
        addi  a1, a1, 1                 ; ...
        addi  t0, t0, 1                 ; ...
        addi  a2, a2, -1                ; ...
        j     __snt_c                   ; ...
__snt_z:
        sb    zero, 0(t0)               ; and a zero
        ret                             ; done

; strncpy(d, s, n) -> d: n bytes exactly, padded with zeros
strncpy:
        mv    t0, a0                    ; cursor
__snc_l:
        beqz  a2, __snc_r               ; done
        lbu   t1, 0(a1)                 ; ...
        sb    t1, 0(t0)                 ; ...
        addi  t0, t0, 1                 ; ...
        addi  a2, a2, -1                ; ...
        beqz  t1, __snc_l               ; after the zero: keep storing it
        addi  a1, a1, 1                 ; ...
        j     __snc_l                   ; ...
__snc_r:
        ret                             ; done

; strcmp(a, b)
strcmp:
        li    a2, -1                    ; no limit
        srli  a2, a2, 1                 ; ...
; strncmp(a, b, n)
strncmp:
        beqz  a2, __scm_eq              ; n bytes compared
        lbu   t0, 0(a0)                 ; ...
        lbu   t1, 0(a1)                 ; ...
        bne   t0, t1, __scm_ne          ; ...
        beqz  t0, __scm_eq              ; both ended
        addi  a0, a0, 1                 ; ...
        addi  a1, a1, 1                 ; ...
        addi  a2, a2, -1                ; ...
        j     strncmp                   ; ...
__scm_ne:
        sub   a0, t0, t1                ; the first difference
        ret                             ; ...
__scm_eq:
        li    a0, 0                     ; equal
        ret                             ; done

; strchr(s, c) -> the first c (the zero counts), or 0
strchr:
        andi  a1, a1, 255               ; ...
__sch_l:
        lbu   t0, 0(a0)                 ; ...
        beq   t0, a1, __sch_r           ; found
        addi  a0, a0, 1                 ; ...
        bnez  t0, __sch_l               ; ...
        li    a0, 0                     ; not there
__sch_r:
        ret                             ; done

; strrchr(s, c) -> the last c, or 0
strrchr:
        andi  a1, a1, 255               ; ...
        li    t1, 0                     ; none yet
__srr_l:
        lbu   t0, 0(a0)                 ; ...
        bne   t0, a1, __srr_n           ; ...
        mv    t1, a0                    ; the latest
__srr_n:
        addi  a0, a0, 1                 ; ...
        bnez  t0, __srr_l               ; ...
        mv    a0, t1                    ; ...
        ret                             ; done

; strstr(h, n) -> the first n in h, or 0
strstr:
__sst_o:
        mv    t0, a0                    ; compare here
        mv    t1, a1                    ; ...
__sst_i:
        lbu   t2, 0(t1)                 ; the needle ended: found
        beqz  t2, __sst_r               ; ...
        lbu   t3, 0(t0)                 ; ...
        bne   t2, t3, __sst_n           ; ...
        addi  t0, t0, 1                 ; ...
        addi  t1, t1, 1                 ; ...
        j     __sst_i                   ; ...
__sst_n:
        lbu   t3, 0(a0)                 ; the haystack ended: not there
        addi  a0, a0, 1                 ; ...
        bnez  t3, __sst_o               ; ...
        li    a0, 0                     ; ...
__sst_r:
        ret                             ; done

