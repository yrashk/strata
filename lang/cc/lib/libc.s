; getchar() -> a byte, or -1 at the end
getchar:
        li    a0, 1                     ; stdin
; fgetc(f) / getc(f) -> a byte, or -1 at the end. One byte per message.
fgetc:
getc:
        addi  sp, sp, -24               ; frame
        sd    ra, 16(sp)                ; ...
        addi  a0, a0, -1                ; FILE * -> handle
        sd    a0, 0(sp)                 ; ...
        call  __flush                   ; what was written shows before we wait
        ld    a0, 0(sp)                 ; ...
        addi  a1, sp, 8                 ; one byte
        li    a2, 1                     ; ...
        call  read                      ; ...
        blez  a0, __gc_eof              ; the end, or an error
        lbu   a0, 8(sp)                 ; the byte
        j     __gc_ret                  ; ...
__gc_eof:
        li    a0, -1                    ; EOF
__gc_ret:
        ld    ra, 16(sp)                ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; done

; fgets(s, n, f) -> s, or 0 at the end with nothing read
fgets:
        addi  sp, sp, -40               ; frame
        sd    ra, 32(sp)                ; ...
        sd    s1, 0(sp)                 ; s1 = cursor
        sd    s2, 8(sp)                 ; s2 = room left
        sd    s3, 16(sp)                ; s3 = f
        sd    a0, 24(sp)                ; s
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        mv    s3, a2                    ; ...
__fg_loop:
        slti  t0, s2, 2                 ; room for a byte and the zero?
        bnez  t0, __fg_end              ; no
        mv    a0, s3                    ; a byte
        call  fgetc                     ; ...
        bltz  a0, __fg_end              ; the end
        sb    a0, 0(s1)                 ; ...
        addi  s1, s1, 1                 ; ...
        addi  s2, s2, -1                ; ...
        li    t0, 10                    ; a newline ends the line
        bne   a0, t0, __fg_loop         ; ...
__fg_end:
        sb    zero, 0(s1)               ; terminate
        ld    a0, 24(sp)                ; s, unless nothing was read
        bne   a0, s1, __fg_ret          ; ...
        li    a0, 0                     ; ...
__fg_ret:
        ld    s1, 0(sp)                 ; ...
        ld    s2, 8(sp)                 ; ...
        ld    s3, 16(sp)                ; ...
        ld    ra, 32(sp)                ; ...
        addi  sp, sp, 40                ; ...
        ret                             ; done

; fopen(name, mode) -> FILE *, or 0. mode "r", "w" or "a" (a "b" or "+" is ignored)
fopen:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        lbu   t0, 0(a1)                 ; the first letter decides
        li    a1, 0                     ; r
        li    t1, 'w'                   ; ...
        bne   t0, t1, __fo_a            ; ...
        li    a1, 1                     ; w
__fo_a:
        li    t1, 'a'                   ; ...
        bne   t0, t1, __fo_go           ; ...
        li    a1, 2                     ; a
__fo_go:
        call  open                      ; a0 = handle, or < 0
        addi  a0, a0, 1                 ; FILE *
        bgtz  a0, __fo_ret              ; ...
        li    a0, 0                     ; failed
__fo_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; done

; fclose(f) -> 0
fclose:
        addi  sp, sp, -16               ; frame
        sd    ra, 8(sp)                 ; ...
        addi  a0, a0, -1                ; FILE * -> handle
        sd    a0, 0(sp)                 ; ...
        call  __flush                   ; its bytes may be in the buffer
        ld    a0, 0(sp)                 ; ...
        call  close                     ; ...
        ld    ra, 8(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; done

; remove(name) -> 0, or < 0
remove:
        j     unlink                    ; the same thing

; fwrite(p, size, n, f) -> n
fwrite:
        addi  sp, sp, -40               ; frame
        sd    ra, 32(sp)                ; ...
        sd    s1, 0(sp)                 ; s1 = cursor
        sd    s2, 8(sp)                 ; s2 = end
        sd    s3, 16(sp)                ; s3 = handle
        sd    a2, 24(sp)                ; n
        mv    s1, a0                    ; ...
        mul   s2, a1, a2                ; bytes
        add   s2, s2, a0                ; ...
        addi  s3, a3, -1                ; ...
__fw_loop:
        bgeu  s1, s2, __fw_end          ; all written
        lbu   a0, 0(s1)                 ; through the buffer
        mv    a1, s3                    ; ...
        call  __oput                    ; ...
        addi  s1, s1, 1                 ; ...
        j     __fw_loop                 ; ...
__fw_end:
        ld    a0, 24(sp)                ; n
        ld    s1, 0(sp)                 ; ...
        ld    s2, 8(sp)                 ; ...
        ld    s3, 16(sp)                ; ...
        ld    ra, 32(sp)                ; ...
        addi  sp, sp, 40                ; ...
        ret                             ; done

; fread(p, size, n, f) -> whole items read
fread:
        addi  sp, sp, -48               ; frame
        sd    ra, 40(sp)                ; ...
        sd    s1, 0(sp)                 ; s1 = cursor
        sd    s2, 8(sp)                 ; s2 = bytes left
        sd    s3, 16(sp)                ; s3 = handle
        sd    s4, 24(sp)                ; s4 = start
        sd    a1, 32(sp)                ; size
        mv    s1, a0                    ; ...
        mv    s4, a0                    ; ...
        mul   s2, a1, a2                ; ...
        addi  s3, a3, -1                ; ...
        call  __flush                   ; output first
__fr_loop:
        beqz  s2, __fr_end              ; all read
        mv    a0, s3                    ; a piece
        mv    a1, s1                    ; ...
        mv    a2, s2                    ; ...
        call  read                      ; ...
        blez  a0, __fr_end              ; the end
        add   s1, s1, a0                ; ...
        sub   s2, s2, a0                ; ...
        j     __fr_loop                 ; ...
__fr_end:
        sub   a0, s1, s4                ; bytes read, in items
        ld    t0, 32(sp)                ; ...
        beqz  t0, __fr_ret              ; ...
        divu  a0, a0, t0                ; ...
__fr_ret:
        ld    s1, 0(sp)                 ; ...
        ld    s2, 8(sp)                 ; ...
        ld    s3, 16(sp)                ; ...
        ld    s4, 24(sp)                ; ...
        ld    ra, 40(sp)                ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; done

