; __ffmt(a0 = double, a1 = flags (FL_*), a2 = precision, a3 = conversion letter)
; -> a0 = text, a1 = its length, a2 = sign character or 0: %e %f %g, exactly:
; the double's binary value is expanded into decimal digits with two
; multi-word numbers (its integer part, divided by ten for each digit, and its
; fraction, multiplied by ten), rounded to nearest, ties to even, at the
; digit the conversion asks for, and laid out.
        .data                           ; ...
        .align 8                        ; ...
__fint:  .space 136                     ; the integer part: 34 words of 32 bits, the lowest first
__ffrac: .space 136                     ; the fraction: 34 words, the highest first
__fdig:  .space 384                     ; digits: the integer part ends at __fdig + FD_INT, the fraction follows
__fout:  .space 136                     ; the text
__finf:  .ascii "infnanINFNAN"          ; ...
        .align 8                        ; ...
FD_INT   = 316                          ; (room for the 309 digits of the largest double, and a carry)
        .text                           ; ...
__ffmt:
        addi  sp, sp, -104              ; frame: ra, s1..s11
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; s1 = flags
        sd    s2, 16(sp)                ; s2 = precision
        sd    s3, 24(sp)                ; s3 = conversion (lower case); bit 8: upper case
        sd    s4, 32(sp)                ; s4 = sign character
        sd    s5, 40(sp)                ; s5 = integer digits
        sd    s6, 48(sp)                ; s6 = the first significant digit
        sd    s7, 56(sp)                ; s7 = significant digits wanted
        sd    s8, 64(sp)                ; s8 = decimal exponent of the first digit
        sd    s9, 72(sp)                ; s9 = end of the digits made
        sd    s10, 80(sp)               ; s10 = output cursor
        sd    s11, 88(sp)               ; s11 = scratch
        mv    s1, a1                    ; ...
        mv    s2, a2                    ; ...
        ori   s3, a3, 32                ; ...
        andi  t0, a3, 32                ; ...
        bnez  t0, __ff_sign             ; ...
        ori   s3, s3, 256               ; ...
__ff_sign:
        li    s4, 0                     ; the sign
        bgez  a0, __ff_plus             ; ...
        li    s4, '-'                   ; ...
        j     __ff_un                   ; ...
__ff_plus:
        andi  t0, s1, FL_PLUS           ; ...
        beqz  t0, __ff_sp               ; ...
        li    s4, '+'                   ; ...
        j     __ff_un                   ; ...
__ff_sp:
        andi  t0, s1, FL_SPACE          ; ...
        beqz  t0, __ff_un               ; ...
        li    s4, ' '                   ; ...
__ff_un:
        slli  t1, a0, 1                 ; t1 = exponent, a0 = mantissa
        srli  t1, t1, 53                ; ...
        slli  a0, a0, 12                ; ...
        srli  a0, a0, 12                ; ...
        li    t0, 0x7ff                 ; ...
        bne   t1, t0, __ff_fin          ; ...
        li    t2, __finf                ; inf or nan, in the conversion's case
        beqz  a0, __ff_i1               ; ...
        addi  t2, t2, 3                 ; ...
__ff_i1:
        andi  t0, s3, 256               ; ...
        beqz  t0, __ff_i2               ; ...
        addi  t2, t2, 6                 ; ...
__ff_i2:
        mv    a0, t2                    ; ...
        li    a1, 3                     ; ...
        j     __ff_ret                  ; ...
__ff_fin:
        andi  t0, s1, FL_PREC           ; precision: 6 if not given, at most 50
        bnez  t0, __ff_p1               ; ...
        li    s2, 6                     ; ...
__ff_p1:
        slti  t0, s2, 51                ; ...
        bnez  t0, __ff_p2               ; ...
        li    s2, 50                    ; ...
__ff_p2:
        andi  t0, s3, 255               ; %g: a precision of 0 is 1
        addi  t0, t0, -'g'              ; ...
        or    t0, t0, s2                ; ...
        bnez  t0, __ff_big              ; ...
        li    s2, 1                     ; ...
__ff_big:
        li    t0, __fint                ; clear both numbers
        li    t2, 34                    ; ...
__ff_clr:
        sd    zero, 0(t0)               ; ...
        addi  t0, t0, 8                 ; ...
        addi  t2, t2, -1                ; ...
        bnez  t2, __ff_clr              ; ...
        beqz  t1, __ff_sub              ; the implicit bit; a subnormal's exponent is 1
        li    t0, 1                     ; ...
        slli  t0, t0, 52                ; ...
        or    a0, a0, t0                ; ...
        j     __ff_e2                   ; ...
__ff_sub:
        li    t1, 1                     ; ...
__ff_e2:
        addi  t1, t1, -1075             ; the value is a0 * 2^t1
        bltz  t1, __ff_frac             ; ...
        srli  t2, t1, 5                 ; an integer: a0 << t1, into three words
        slli  t2, t2, 2                 ; ...
        addi  t2, t2, __fint            ; ...
        andi  t3, t1, 31                ; ...
        sll   t4, a0, t3                ; ...
        sw    t4, 0(t2)                 ; ...
        srli  t5, t4, 32                ; ...
        sw    t5, 4(t2)                 ; ...
        beqz  t3, __ff_idig             ; ...
        li    t5, 64                    ; ...
        sub   t5, t5, t3                ; ...
        srl   t4, a0, t5                ; ...
        sw    t4, 8(t2)                 ; ...
        j     __ff_idig                 ; ...
__ff_frac:
        neg   t1, t1                    ; t1 = bits after the point (1..1074)
        slti  t0, t1, 64                ; the integer part: a0 >> t1
        beqz  t0, __ff_f64              ; ...
        srl   t4, a0, t1                ; ...
        sw    t4, __fint(zero)          ; ...
        srli  t4, t4, 32                ; ...
        sw    t4, __fint+4(zero)        ; ...
        li    t5, 64                    ; the fraction: the low t1 bits, at the top of 64
        sub   t5, t5, t1                ; ...
        sll   t4, a0, t5                ; ...
        srli  t5, t4, 32                ; ...
        sw    t5, __ffrac(zero)         ; ...
        sw    t4, __ffrac+4(zero)       ; ...
        j     __ff_idig                 ; ...
__ff_f64:
        addi  t1, t1, -64               ; the 64 bits of a0 start t1 bits below the point
        srli  t2, t1, 5                 ; ...
        slli  t2, t2, 2                 ; ...
        addi  t2, t2, __ffrac           ; ...
        andi  t3, t1, 31                ; ...
        srl   t4, a0, t3                ; ...
        srli  t5, t4, 32                ; ...
        sw    t5, 0(t2)                 ; ...
        sw    t4, 4(t2)                 ; ...
        beqz  t3, __ff_idig             ; ...
        li    t5, 32                    ; ...
        sub   t5, t5, t3                ; ...
        sll   t4, a0, t5                ; ...
        sw    t4, 8(t2)                 ; ...
__ff_idig:
        li    s6, __fdig + FD_INT       ; the integer part's digits, the last one first
        li    t6, 33                    ; t6 = its highest word that may not be zero
__ff_id1:
        slli  t0, t6, 2                 ; ...
        lwu   t1, __fint(t0)            ; ...
        bnez  t1, __ff_id2              ; ...
        addi  t6, t6, -1                ; ...
        bgez  t6, __ff_id1              ; ...
        j     __ff_idone                ; no more digits
__ff_id2:
        li    t2, 0                     ; divide by ten, from the top word down
        mv    t3, t6                    ; ...
        li    t5, 10                    ; ...
__ff_id3:
        slli  t0, t3, 2                 ; ...
        lwu   t1, __fint(t0)            ; ...
        slli  t2, t2, 32                ; ...
        or    t1, t1, t2                ; ...
        divu  t4, t1, t5                ; ...
        remu  t2, t1, t5                ; ...
        sw    t4, __fint(t0)            ; ...
        addi  t3, t3, -1                ; ...
        bgez  t3, __ff_id3              ; ...
        addi  t2, t2, '0'               ; the remainder is the digit
        addi  s6, s6, -1                ; ...
        sb    t2, 0(s6)                 ; ...
        j     __ff_id1                  ; ...
__ff_idone:
        li    s9, __fdig + FD_INT       ; ...
        sub   s5, s9, s6                ; s5 = integer digits
        addi  s8, s5, -1                ; the first one's power of ten
        bnez  s5, __ff_nsig             ; ...
        li    s8, -1                    ; no integer part: skip the fraction's leading zeros
__ff_lz:
        call  __ff_fd                   ; ...
        li    t0, '0'                   ; ...
        bne   a0, t0, __ff_l1           ; ...
        addi  s8, s8, -1                ; ...
        slti  t0, s8, -1100             ; (the value is zero)
        beqz  t0, __ff_lz               ; ...
        li    s8, 0                     ; ...
__ff_l1:
        sb    a0, 0(s9)                 ; the first significant digit (or the 0 of zero)
        addi  s9, s9, 1                 ; ...
__ff_nsig:
        andi  t0, s3, 255               ; how many significant digits: %f: to p places after
        li    t1, 'f'                   ;   the point; %e: p + 1; %g: p
        bne   t0, t1, __ff_ne           ; ...
        add   s7, s8, s2                ; ...
        addi  s7, s7, 1                 ; ...
        j     __ff_ncap                 ; ...
__ff_ne:
        mv    s7, s2                    ; ...
        li    t1, 'e'                   ; ...
        bne   t0, t1, __ff_ncap         ; ...
        addi  s7, s7, 1                 ; ...
__ff_ncap:
        addi  t0, s5, 60                ; (no more than the digits there is room for)
        ble   s7, t0, __ff_gen          ; ...
        mv    s7, t0                    ; ...
__ff_gen:
        bltz  s7, __ff_zero             ; nothing is left of the number at this precision
        sub   t0, s9, s6                ; one digit more than wanted, to round by
        bgt   t0, s7, __ff_rnd          ; ...
        call  __ff_fd                   ; ...
        sb    a0, 0(s9)                 ; ...
        addi  s9, s9, 1                 ; ...
        j     __ff_gen                  ; ...
__ff_rnd:
        add   t0, s6, s7                ; the digit after the last one kept
        lbu   t1, 0(t0)                 ; ...
        li    t2, '5'                   ; ...
        bltu  t1, t2, __ff_lay          ; below 5: down
        bne   t1, t2, __ff_up           ; above: up
        addi  t0, t0, 1                 ; exactly 5: is anything after it not zero?
__ff_st1:
        bgeu  t0, s9, __ff_st2          ; ...
        lbu   t1, 0(t0)                 ; ...
        addi  t0, t0, 1                 ; ...
        li    t2, '0'                   ; ...
        beq   t1, t2, __ff_st1          ; ...
        j     __ff_up                   ; ...
__ff_st2:
        li    t0, __ffrac               ; ... or of the fraction not yet turned into digits?
        li    t2, 17                    ; ...
