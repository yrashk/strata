; =============================================================================
; libc.s: the run-time library of programs compiled by cc
; =============================================================================
;
; This file is assembled once (sasm -T 0x8000) and its image is copied into
; every program cc writes: code from I-LS 0x8000, data from D-LS 0, the
; program after them. There is no linker: the library sits at fixed
; addresses and lib/mklib.py writes the table of the names cc may use, one per
; `.global` line below, into cc.lib.
;
; Calling convention (lang/cc/DESIGN.md): arguments in a0..a7, then on the
; stack from 0(sp); result in a0; t0..t6, tp and a0..a7 are not kept, s0..s11
; are; gp is the constant 0x10000. A variadic function stores a0..a7 below
; its caller's stack arguments, so that all its arguments are consecutive
; 8-byte words: va_list is a pointer to the next one.
;
; The first four words of the D-LS are written by cc into each image:
;   0  __main   address of main (a far offset if >= 0x10000: the code is paged)
;   8  __xslot  12 if the code is paged in 4 KiB units, else 0
;   16 __heap   first byte of the heap      24 __hend   one past its last
;
; FILE * is a handle plus one, so that 0 is NULL: stdin 1, stdout 2, stderr 3.
; Output goes through one buffer that belongs to one handle at a time; it is
; written out when it fills, when another handle is written to, before any
; read, after each write to stderr, and at exit.

        .data                           ; D-LS: the start-up words come first
__main:  .dword 0                       ; main (patched by cc)
__xslot: .dword 0                       ; log2 of the code unit size, or 0 (patched by cc)
__heap:  .dword 0                       ; heap start (patched by cc)
__hend:  .dword 0                       ; heap end (patched by cc)

        .text                           ; I-LS 0x8000
_start: j     __crt0                    ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS program
__crt0:
        lui   gp, 1                     ; gp = 0x10000, for good
        ld    t0, __xslot(zero)         ; code units?
        csrw  xslot, t0                 ; (0: none)
        call  __init                    ; handles 0..2, the start-up block
        ld    t0, __heap(zero)          ; the heap is one free block
        ld    t1, __hend(zero)          ; ...
        sub   t1, t1, t0                ; its size
        sd    t1, 0(t0)                 ; (bit 0 clear: free)
        li    t0, __sblk + 64           ; split the command line into words
        ld    t1, __sblk + 40(zero)     ; its length
        add   t1, t0, t1                ; t1 = end
        li    a1, __argv                ; a1 = argv
        li    a0, 0                     ; a0 = argc
__c0_sp:
        bgeu  t0, t1, __c0_go           ; end of the text
        lbu   t2, 0(t0)                 ; skip spaces, ending the word before them
        li    t3, ' '                   ; ...
        bne   t2, t3, __c0_w            ; a word starts
        sb    zero, 0(t0)               ; ...
        addi  t0, t0, 1                 ; ...
        j     __c0_sp                   ; ...
__c0_w:
        slti  t2, a0, 15                ; room in argv?
        beqz  t2, __c0_go               ; no: the rest is dropped
        slli  t2, a0, 3                 ; argv[argc++] = the word
        add   t2, a1, t2                ; ...
        sd    t0, 0(t2)                 ; ...
        addi  a0, a0, 1                 ; ...
__c0_c:
        addi  t0, t0, 1                 ; to the end of the word
        bgeu  t0, t1, __c0_go           ; end of the text
        lbu   t2, 0(t0)                 ; ...
        bne   t2, t3, __c0_c            ; ...
        j     __c0_sp                   ; a space
__c0_go:
        sb    zero, 0(t1)               ; the last word ends here
        ld    t0, __main(zero)          ; main: resident, or in a code unit
        srli  t1, t0, 16                ; ...
        bnez  t1, __c0_far              ; ...
        jalr  ra, t0, 0                 ; main(argc, argv)
        j     exit                      ; exit(its result)
__c0_far:
        xcall ra, c0, t0                ; main(argc, argv), paged in on demand
        j     exit                      ; exit(its result)

        .include "rt.s"                 ; messages, open, read, write, close, _exit

        .data                           ; library state
        .align 8                        ; words
__argv: .space 128                      ; argv: 15 words and a null
__on:   .dword 0                        ; bytes waiting in __ob
__ofd:  .dword 1                        ; the handle they belong to
__pfd:  .dword 1                        ; where formatted output goes (-1: into a string)
__sptr: .dword 0                        ; ... the string's next byte
__srem: .dword 0                        ; ... and the room left in it
__seed: .dword 1                        ; rand's state
__ob:   .space 256                      ; the output buffer
__null: .asciz "(null)"                 ; what %s prints for a null pointer
        .align 8                        ; ...

        .text                           ; library code

; =============================================================================
; Exit
; =============================================================================
        .global exit
        .global abort
        .global _exit
; exit(code): write out buffered output, end the process
exit:
        addi  sp, sp, -16               ; frame
        andi  a0, a0, 255               ; (a status is one byte)
        sd    a0, 0(sp)                 ; the code
        call  __flush                   ; nothing written may be lost
        ld    a0, 0(sp)                 ; ...
        j     _exit                     ; end
; abort(): end with status 134
abort:
        li    a0, 134                   ; as a shell shows SIGABRT
        j     exit                      ; ...

; =============================================================================
; Output
; =============================================================================
        .global putchar
        .global puts
        .global fputc
        .global putc
        .global fputs
        .global fflush
        .global printf
        .global fprintf
        .global sprintf
        .global snprintf
        .global vprintf
        .global vfprintf
        .global vsprintf
        .global vsnprintf
        .global write

; __flush(): write the output buffer out
__flush:
        ld    a2, __on(zero)            ; bytes waiting
        beqz  a2, __fl_ret              ; none
        sd    zero, __on(zero)          ; (taken)
        ld    a0, __ofd(zero)           ; their handle
        li    a1, __ob                  ; ...
        j     write                     ; write(fd, buffer, n)
__fl_ret:
        ret                             ; done

; __oput(a0 = byte, a1 = handle): one byte of buffered output
__oput:
        ld    t0, __ofd(zero)           ; the buffer's handle
        beq   t0, a1, __ou_put          ; ours
        addi  sp, sp, -24               ; another: write the buffer out first
        sd    ra, 16(sp)                ; ...
        sd    a0, 0(sp)                 ; ...
        sd    a1, 8(sp)                 ; ...
        call  __flush                   ; ...
        ld    a0, 0(sp)                 ; ...
        ld    a1, 8(sp)                 ; ...
        ld    ra, 16(sp)                ; ...
        addi  sp, sp, 24                ; ...
        sd    a1, __ofd(zero)           ; the buffer is this handle's now
__ou_put:
        ld    t0, __on(zero)            ; append
        sb    a0, __ob(t0)              ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, __on(zero)              ; ...
        slti  t1, t0, 256               ; full?
        beqz  t1, __flush               ; yes: write it out
        ret                             ; done

; __pc(a0 = byte): one byte of formatted output, to __pfd or into the string
__pc:
        ld    a1, __pfd(zero)           ; a handle?
        bgez  a1, __oput                ; yes
        ld    t0, __srem(zero)          ; room in the string (one byte is the zero's)
        slti  t1, t0, 2                 ; ...
        bnez  t1, __pc_ret              ; none: counted but dropped
        addi  t0, t0, -1                ; ...
        sd    t0, __srem(zero)          ; ...
        ld    t0, __sptr(zero)          ; store it
        sb    a0, 0(t0)                 ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, __sptr(zero)          ; ...
__pc_ret:
        ret                             ; done

; putchar(c) -> c
putchar:
        li    a1, 1                     ; standard output
        j     __fputc1                  ; ...
; fputc(c, f) / putc(c, f) -> c
fputc:
putc:
        addi  a1, a1, -1                ; FILE * -> handle
__fputc1:
        addi  sp, sp, -16               ; frame
        sd    ra, 8(sp)                 ; ...
        sd    a0, 0(sp)                 ; ...
        call  __oput                    ; ...
        ld    a0, 0(sp)                 ; the result is the byte
        andi  a0, a0, 255               ; ...
        ld    ra, 8(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; done

; puts(s): the string and a newline
puts:
        addi  sp, sp, -16               ; frame
        sd    ra, 8(sp)                 ; ...
        li    a1, 2                     ; stdout
        call  fputs                     ; the string
        li    a0, 10                    ; and a newline
        li    a1, 1                     ; ...
        call  __oput                    ; ...
        li    a0, 10                    ; (a non-negative result: the last byte written)
        ld    ra, 8(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; done

; fputs(s, f) -> 0
fputs:
        addi  sp, sp, -24               ; frame
        sd    ra, 16(sp)                ; ...
        sd    s1, 0(sp)                 ; s1 = cursor
        sd    s2, 8(sp)                 ; s2 = handle
        mv    s1, a0                    ; ...
        addi  s2, a1, -1                ; ...
__fs_loop:
        lbu   a0, 0(s1)                 ; a byte
        beqz  a0, __fs_end              ; the end
        mv    a1, s2                    ; ...
        call  __oput                    ; ...
        addi  s1, s1, 1                 ; next
        j     __fs_loop                 ; ...
__fs_end:
        li    t0, 2                     ; stderr is not buffered
        bne   s2, t0, __fs_ret          ; ...
        call  __flush                   ; ...
__fs_ret:
        li    a0, 0                     ; ...
        ld    s1, 0(sp)                 ; ...
        ld    s2, 8(sp)                 ; ...
        ld    ra, 16(sp)                ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; done

; fflush(f) -> 0
fflush:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        call  __flush                   ; there is one buffer
        li    a0, 0                     ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; done

; printf(fmt, ...) -> bytes written
printf:
        addi  sp, sp, -64               ; a0..a7 below the caller's stack arguments
        sd    a1, 8(sp)                 ; ...
        sd    a2, 16(sp)                ; ...
        sd    a3, 24(sp)                ; ...
        sd    a4, 32(sp)                ; ...
        sd    a5, 40(sp)                ; ...
        sd    a6, 48(sp)                ; ...
        sd    a7, 56(sp)                ; ...
        addi  a1, sp, 8                 ; the first variable argument
        li    a2, 1                     ; to standard output
        j     __fmt_v                   ; format, then drop the 64 bytes
; fprintf(f, fmt, ...)
fprintf:
        addi  sp, sp, -64               ; as printf
        sd    a2, 16(sp)                ; ...
        sd    a3, 24(sp)                ; ...
        sd    a4, 32(sp)                ; ...
        sd    a5, 40(sp)                ; ...
        sd    a6, 48(sp)                ; ...
        sd    a7, 56(sp)                ; ...
        addi  a2, a0, -1                ; FILE * -> handle
        mv    a0, a1                    ; the format
        addi  a1, sp, 16                ; the first variable argument
__fmt_v:
        addi  sp, sp, -8                ; keep the link
        sd    ra, 0(sp)                 ; ...
        call  __fmt                     ; a0 = bytes
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 72                ; the link and the argument words
        ret                             ; done
; sprintf(s, fmt, ...)
sprintf:
        addi  sp, sp, -64               ; as printf
        sd    a2, 16(sp)                ; ...
        sd    a3, 24(sp)                ; ...
        sd    a4, 32(sp)                ; ...
        sd    a5, 40(sp)                ; ...
        sd    a6, 48(sp)                ; ...
        sd    a7, 56(sp)                ; ...
        addi  a3, sp, 16                ; the first variable argument
        mv    a2, a1                    ; the format
        li    a1, -1                    ; no limit (as an unsigned number)
        srli  a1, a1, 1                 ; ...
        j     __sfmt_v                  ; ...
; snprintf(s, n, fmt, ...)
snprintf:
        addi  sp, sp, -64               ; as printf
        sd    a3, 24(sp)                ; ...
        sd    a4, 32(sp)                ; ...
        sd    a5, 40(sp)                ; ...
        sd    a6, 48(sp)                ; ...
        sd    a7, 56(sp)                ; ...
        addi  a3, sp, 24                ; the first variable argument
__sfmt_v:
        addi  sp, sp, -8                ; keep the link
        sd    ra, 0(sp)                 ; ...
        call  vsnprintf                 ; a0 = bytes
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 72                ; ...
        ret                             ; done
; vprintf(fmt, ap)
vprintf:
        li    a2, 1                     ; standard output
        j     __fmt                     ; ...
; vfprintf(f, fmt, ap)
vfprintf:
        addi  t0, a0, -1                ; FILE * -> handle
        mv    a0, a1                    ; the format
        mv    a1, a2                    ; the arguments
        mv    a2, t0                    ; ...
        j     __fmt                     ; ...
; vsprintf(s, fmt, ap)
vsprintf:
        mv    a3, a2                    ; the arguments
        mv    a2, a1                    ; the format
        li    a1, -1                    ; no limit
        srli  a1, a1, 1                 ; ...
; vsnprintf(s, n, fmt, ap) -> the bytes the whole text has
vsnprintf:
        addi  sp, sp, -16               ; frame
        sd    ra, 8(sp)                 ; ...
        sd    a1, 0(sp)                 ; the room
        sd    a0, __sptr(zero)          ; where the text goes
        sd    a1, __srem(zero)          ; ...
        mv    a0, a2                    ; the format
        mv    a1, a3                    ; the arguments
        li    a2, -1                    ; into the string
        call  __fmt                     ; a0 = bytes
        ld    t0, 0(sp)                 ; terminate, if there is any room
        beqz  t0, __vs_ret              ; ...
        ld    t0, __sptr(zero)          ; ...
        sb    zero, 0(t0)               ; ...
__vs_ret:
        ld    ra, 8(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; done

; __fmt(a0 = format, a1 = arguments, a2 = handle or -1) -> a0 = bytes produced
; s1 format cursor, s2 next argument, s3 count, s4 flags, s5 width,
; s6 precision, s7 text, s8 its length, s9 sign character, s10 prefix length,
; s11 zeros before the digits
FL_LEFT  = 1                            ; -
FL_ZERO  = 2                            ; 0
FL_PLUS  = 4                            ; +
FL_SPACE = 8                            ; space
FL_ALT   = 16                           ; #
FL_LONG  = 32                           ; l, ll, z, j, t
FL_PREC  = 64                           ; a precision was given
FL_SHORT = 128                          ; h
FL_CHAR  = 256                          ; hh
FL_UPPER = 512                          ; X
__fmt:
        addi  sp, sp, -144              ; frame: 12 registers, 40 bytes of digits
        sd    ra, 136(sp)               ; ...
        sd    s1, 128(sp)               ; ...
        sd    s2, 120(sp)               ; ...
        sd    s3, 112(sp)               ; ...
        sd    s4, 104(sp)               ; ...
        sd    s5, 96(sp)                ; ...
        sd    s6, 88(sp)                ; ...
        sd    s7, 80(sp)                ; ...
        sd    s8, 72(sp)                ; ...
        sd    s9, 64(sp)                ; ...
        sd    s10, 56(sp)               ; ...
        sd    s11, 48(sp)               ; ...
        ld    t0, __pfd(zero)           ; (a nested call must not change the target)
        sd    t0, 40(sp)                ; ...
        sd    a2, __pfd(zero)           ; where it goes
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        li    s3, 0                     ; nothing produced yet
__f_loop:
        lbu   a0, 0(s1)                 ; the next format byte
        addi  s1, s1, 1                 ; ...
        beqz  a0, __f_end               ; the end
        li    t0, '%'                   ; a conversion?
        beq   a0, t0, __f_spec          ; yes
__f_lit:
        call  __pc                      ; an ordinary byte
        addi  s3, s3, 1                 ; ...
        j     __f_loop                  ; ...
__f_spec:
        li    s4, 0                     ; no flags
        li    s5, 0                     ; no width
        li    s6, 0                     ; no precision
__f_flag:
        lbu   a0, 0(s1)                 ; flags, in any order
        addi  s1, s1, 1                 ; ...
        li    t1, FL_LEFT               ; -
        li    t0, '-'                   ; ...
        beq   a0, t0, __f_fset          ; ...
        li    t1, FL_ZERO               ; 0
        li    t0, '0'                   ; ...
        beq   a0, t0, __f_fset          ; ...
        li    t1, FL_PLUS               ; +
        li    t0, '+'                   ; ...
        beq   a0, t0, __f_fset          ; ...
        li    t1, FL_SPACE              ; space
        li    t0, ' '                   ; ...
        beq   a0, t0, __f_fset          ; ...
        li    t1, FL_ALT                ; #
        li    t0, '#'                   ; ...
        bne   a0, t0, __f_width         ; not a flag
__f_fset:
        or    s4, s4, t1                ; ...
        j     __f_flag                  ; ...
__f_width:
        li    t0, '*'                   ; the width from an argument?
        bne   a0, t0, __f_wdig          ; no
        ld    s5, 0(s2)                 ; ...
        addi  s2, s2, 8                 ; ...
        slli  s5, s5, 32                ; (an int)
        srai  s5, s5, 32                ; ...
        bgez  s5, __f_wnext             ; a negative width means -
        neg   s5, s5                    ; ...
        ori   s4, s4, FL_LEFT           ; ...
__f_wnext:
        lbu   a0, 0(s1)                 ; ...
        addi  s1, s1, 1                 ; ...
        j     __f_prec                  ; ...
__f_wdig:
        addi  t0, a0, -'0'              ; digits of the width
        sltiu t1, t0, 10                ; ...
        beqz  t1, __f_prec              ; ...
        li    t1, 10                    ; ...
        mul   s5, s5, t1                ; ...
        add   s5, s5, t0                ; ...
        lbu   a0, 0(s1)                 ; ...
        addi  s1, s1, 1                 ; ...
        j     __f_wdig                  ; ...
__f_prec:
        li    t0, '.'                   ; a precision?
        bne   a0, t0, __f_len           ; no
        ori   s4, s4, FL_PREC           ; ...
        lbu   a0, 0(s1)                 ; ...
        addi  s1, s1, 1                 ; ...
        li    t0, '*'                   ; from an argument?
        bne   a0, t0, __f_pdig          ; no
        ld    s6, 0(s2)                 ; ...
        addi  s2, s2, 8                 ; ...
        slli  s6, s6, 32                ; (an int)
        srai  s6, s6, 32                ; ...
        lbu   a0, 0(s1)                 ; ...
        addi  s1, s1, 1                 ; ...
        bgez  s6, __f_len               ; a negative precision is none
        li    s6, 0                     ; ...
        xori  s4, s4, FL_PREC           ; ...
        j     __f_len                   ; ...
__f_pdig:
        addi  t0, a0, -'0'              ; digits of the precision
        sltiu t1, t0, 10                ; ...
        beqz  t1, __f_len               ; ...
        li    t1, 10                    ; ...
        mul   s6, s6, t1                ; ...
        add   s6, s6, t0                ; ...
        lbu   a0, 0(s1)                 ; ...
        addi  s1, s1, 1                 ; ...
        j     __f_pdig                  ; ...
__f_len:
        li    t0, 'l'                   ; l, ll
        beq   a0, t0, __f_long          ; ...
        li    t0, 'z'                   ; z
        beq   a0, t0, __f_long          ; ...
        li    t0, 'j'                   ; j
        beq   a0, t0, __f_long          ; ...
        li    t0, 't'                   ; t
        beq   a0, t0, __f_long          ; ...
        li    t0, 'L'                   ; L (long double is double)
        beq   a0, t0, __f_lnext         ; ...
        li    t0, 'h'                   ; h, hh
        bne   a0, t0, __f_conv          ; none of them
        andi  t0, s4, FL_SHORT          ; the second h?
        ori   s4, s4, FL_SHORT          ; ...
        beqz  t0, __f_lnext             ; no
        ori   s4, s4, FL_CHAR           ; ...
        j     __f_lnext                 ; ...
__f_long:
        ori   s4, s4, FL_LONG           ; 64 bits
__f_lnext:
        lbu   a0, 0(s1)                 ; ...
        addi  s1, s1, 1                 ; ...
        j     __f_len                   ; ...
__f_conv:
        li    s9, 0                     ; no sign
        li    s10, 0                    ; no prefix
        li    s11, 0                    ; no zeros
        li    t0, 'd'                   ; signed decimal
        beq   a0, t0, __f_d             ; ...
        li    t0, 'i'                   ; ...
        beq   a0, t0, __f_d             ; ...
        li    a2, 10                    ; unsigned decimal
        li    t0, 'u'                   ; ...
        beq   a0, t0, __f_u             ; ...
        li    a2, 16                    ; hexadecimal
        li    t0, 'x'                   ; ...
        beq   a0, t0, __f_u             ; ...
        li    t0, 'X'                   ; ...
        beq   a0, t0, __f_ux            ; ...
        li    a2, 8                     ; octal
        li    t0, 'o'                   ; ...
        beq   a0, t0, __f_u             ; ...
        li    t0, 'c'                   ; a character
        beq   a0, t0, __f_c             ; ...
        li    t0, 's'                   ; a string
        beq   a0, t0, __f_s             ; ...
        li    t0, 'p'                   ; a pointer
        beq   a0, t0, __f_p             ; ...
        addi  t0, a0, -'e'              ; e f g: a double
        sltiu t0, t0, 3                 ; ...
        bnez  t0, __f_fl                ; ...
        addi  t0, a0, -'E'              ; E F G
        sltiu t0, t0, 3                 ; ...
        bnez  t0, __f_fl                ; ...
        bnez  a0, __f_lit               ; anything else (%%) prints itself
        addi  s1, s1, -1                ; the format ended inside a conversion
        j     __f_loop                  ; ...
__f_fl:
        mv    a1, s4                    ; flags
        mv    a2, s6                    ; precision
        mv    a3, a0                    ; the conversion letter
        ld    a0, 0(s2)                 ; the double
        addi  s2, s2, 8                 ; ...
        addi  a4, sp, 0                 ; 40 bytes for the text
        la    t0, __ffmt                ; (soft-float: at the end of this file)
        jalr  ra, t0, 0                 ; a0 = text, a1 = length, a2 = sign character
        mv    s7, a0                    ; ...
        mv    s8, a1                    ; ...
        mv    s9, a2                    ; ...
        andi  s4, s4, FL_LEFT | FL_ZERO ; (the precision is spent)
        j     __f_out                   ; ...
__f_c:
        ld    t0, 0(s2)                 ; the character
        addi  s2, s2, 8                 ; ...
        sb    t0, 0(sp)                 ; a text of one byte
        addi  s7, sp, 0                 ; ...
        li    s8, 1                     ; ...
        andi  s4, s4, FL_LEFT           ; (no zero padding)
        j     __f_out                   ; ...
__f_s:
        ld    s7, 0(s2)                 ; the string
        addi  s2, s2, 8                 ; ...
        bnez  s7, __f_slen              ; ...
        li    s7, __null                ; a null pointer
__f_slen:
        li    s8, 0                     ; its length, at most the precision
__f_sl:
        andi  t0, s4, FL_PREC           ; ...
        beqz  t0, __f_sl2               ; ...
        bge   s8, s6, __f_sdone         ; ...
__f_sl2:
        add   t0, s7, s8                ; ...
        lbu   t0, 0(t0)                 ; ...
        beqz  t0, __f_sdone             ; ...
        addi  s8, s8, 1                 ; ...
        j     __f_sl                    ; ...
__f_sdone:
        andi  s4, s4, FL_LEFT           ; (no zero padding)
        j     __f_out                   ; ...
__f_p:
        ld    a0, 0(s2)                 ; the pointer: 0x and hexadecimal
        addi  s2, s2, 8                 ; ...
        li    a2, 16                    ; ...
        ori   s4, s4, FL_ALT            ; ...
        li    s10, 2                    ; ...
        j     __f_digits                ; ...
__f_d:
        ld    a0, 0(s2)                 ; the argument
        addi  s2, s2, 8                 ; ...
        andi  t0, s4, FL_LONG           ; 64 bits?
        bnez  t0, __f_dsign             ; yes
        slli  a0, a0, 32                ; an int
        srai  a0, a0, 32                ; ...
        andi  t0, s4, FL_SHORT          ; a short?
        beqz  t0, __f_dsign             ; no
        slli  a0, a0, 48                ; ...
        srai  a0, a0, 48                ; ...
        andi  t0, s4, FL_CHAR           ; a char?
        beqz  t0, __f_dsign             ; no
        slli  a0, a0, 56                ; ...
        srai  a0, a0, 56                ; ...
__f_dsign:
        li    a2, 10                    ; decimal
        bgez  a0, __f_dpos              ; ...
        neg   a0, a0                    ; its magnitude
        li    s9, '-'                   ; ...
        j     __f_digits                ; ...
__f_dpos:
        andi  t0, s4, FL_PLUS           ; +?
        beqz  t0, __f_dsp               ; ...
        li    s9, '+'                   ; ...
        j     __f_digits                ; ...
__f_dsp:
        andi  t0, s4, FL_SPACE          ; space?
        beqz  t0, __f_digits            ; ...
        li    s9, ' '                   ; ...
        j     __f_digits                ; ...
__f_ux:
        ori   s4, s4, FL_UPPER          ; capital digits
__f_u:
        ld    a0, 0(s2)                 ; the argument
        addi  s2, s2, 8                 ; ...
        andi  t0, s4, FL_LONG           ; 64 bits?
        bnez  t0, __f_ualt              ; yes
        slli  a0, a0, 32                ; an unsigned int
        srli  a0, a0, 32                ; ...
        andi  t0, s4, FL_SHORT          ; a short?
        beqz  t0, __f_ualt              ; no
        slli  a0, a0, 48                ; ...
        srli  a0, a0, 48                ; ...
        andi  t0, s4, FL_CHAR           ; a char?
        beqz  t0, __f_ualt              ; no
        andi  a0, a0, 255               ; ...
__f_ualt:
        andi  t0, s4, FL_ALT            ; #: 0x before a non-zero hexadecimal number
        beqz  t0, __f_digits            ; ...
        li    t0, 16                    ; ...
        bne   a2, t0, __f_digits        ; ...
        beqz  a0, __f_digits            ; ...
        li    s10, 2                    ; ...
__f_digits:                             ; a0 = magnitude, a2 = base
        addi  s7, sp, 40                ; digits are made backwards from the end
        li    s8, 0                     ; ...
        li    t3, 'a' - 10              ; letters
        andi  t0, s4, FL_UPPER          ; ...
        beqz  t0, __f_dg                ; ...
        li    t3, 'A' - 10              ; ...
__f_dg:
        beqz  a0, __f_dgend             ; no more
        remu  t0, a0, a2                ; a digit
        divu  a0, a0, a2                ; ...
        slti  t1, t0, 10                ; ...
        addi  t2, t0, '0'               ; ...
        bnez  t1, __f_dgput             ; ...
        add   t2, t0, t3                ; ...
__f_dgput:
        addi  s7, s7, -1                ; ...
        sb    t2, 0(s7)                 ; ...
        addi  s8, s8, 1                 ; ...
        j     __f_dg                    ; ...
__f_dgend:
        andi  t0, s4, FL_PREC           ; the precision is the fewest digits
        bnez  t0, __f_dprec             ; ...
        li    s6, 1                     ; (1 when not given)
        j     __f_dz                    ; ...
__f_dprec:
        andi  s4, s4, ~FL_ZERO & 1023   ; and it turns the 0 flag off
__f_dz:
        sub   s11, s6, s8               ; zeros in front
        bgez  s11, __f_dalt             ; ...
        li    s11, 0                    ; ...
__f_dalt:
        li    t0, 8                     ; # with octal: at least one leading zero
        bne   a2, t0, __f_out           ; ...
        andi  t0, s4, FL_ALT            ; ...
        beqz  t0, __f_out               ; ...
        bnez  s11, __f_out              ; ...
        li    s11, 1                    ; ...
__f_out:                                ; sign s9, prefix s10, zeros s11, text s7/s8, flags s4, width s5
        snez  t0, s9                    ; padding = width - everything else
        add   t0, t0, s10               ; ...
        add   t0, t0, s11               ; ...
        add   t0, t0, s8                ; ...
        sub   s5, s5, t0                ; ...
        bgez  s5, __f_o1                ; ...
        li    s5, 0                     ; ...
__f_o1:
        andi  t0, s4, FL_LEFT | FL_ZERO ; spaces first, unless - or 0
        bnez  t0, __f_osign             ; ...
        li    a0, ' '                   ; ...
        call  __f_pad                   ; ...
__f_osign:
        beqz  s9, __f_opre              ; the sign
        mv    a0, s9                    ; ...
        call  __pc                      ; ...
        addi  s3, s3, 1                 ; ...
__f_opre:
        beqz  s10, __f_ozero            ; the prefix 0x / 0X
        li    a0, '0'                   ; ...
        call  __pc                      ; ...
        li    a0, 'x'                   ; ...
        andi  t0, s4, FL_UPPER          ; ...
        beqz  t0, __f_opx               ; ...
        li    a0, 'X'                   ; ...
__f_opx:
        call  __pc                      ; ...
        addi  s3, s3, 2                 ; ...
__f_ozero:
        andi  t0, s4, FL_LEFT           ; with 0 (and not -) the padding is zeros here
        bnez  t0, __f_oz2               ; ...
        andi  t0, s4, FL_ZERO           ; ...
        beqz  t0, __f_oz2               ; ...
        add   s11, s11, s5              ; ...
        li    s5, 0                     ; ...
__f_oz2:
        beqz  s11, __f_otext            ; the zeros
        li    a0, '0'                   ; ...
        call  __pc                      ; ...
        addi  s3, s3, 1                 ; ...
        addi  s11, s11, -1              ; ...
        j     __f_oz2                   ; ...
__f_otext:
        beqz  s8, __f_otail             ; the text
        lbu   a0, 0(s7)                 ; ...
        call  __pc                      ; ...
        addi  s3, s3, 1                 ; ...
        addi  s7, s7, 1                 ; ...
        addi  s8, s8, -1                ; ...
        j     __f_otext                 ; ...
__f_otail:
        li    a0, ' '                   ; what is left of the padding (with -)
        call  __f_pad                   ; ...
        j     __f_loop                  ; the next piece of the format
__f_pad:                                ; s5 times the byte a0
        addi  sp, sp, -16               ; frame
        sd    ra, 8(sp)                 ; ...
        sd    a0, 0(sp)                 ; ...
__f_pl:
        beqz  s5, __f_pe                ; done
        ld    a0, 0(sp)                 ; ...
        call  __pc                      ; ...
        addi  s3, s3, 1                 ; ...
        addi  s5, s5, -1                ; ...
        j     __f_pl                    ; ...
__f_pe:
        ld    ra, 8(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...
__f_end:
        ld    t0, __pfd(zero)           ; stderr is not buffered
        li    t1, 2                     ; ...
        bne   t0, t1, __f_ret           ; ...
        call  __flush                   ; ...
__f_ret:
        ld    t0, 40(sp)                ; the target as it was
        sd    t0, __pfd(zero)           ; ...
        mv    a0, s3                    ; the count
        ld    s11, 48(sp)               ; ...
        ld    s10, 56(sp)               ; ...
        ld    s9, 64(sp)                ; ...
        ld    s8, 72(sp)                ; ...
        ld    s7, 80(sp)                ; ...
        ld    s6, 88(sp)                ; ...
        ld    s5, 96(sp)                ; ...
        ld    s4, 104(sp)               ; ...
        ld    s3, 112(sp)               ; ...
        ld    s2, 120(sp)               ; ...
        ld    s1, 128(sp)               ; ...
        ld    ra, 136(sp)               ; ...
        addi  sp, sp, 144               ; ...
        ret                             ; done

