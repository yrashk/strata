; =============================================================================
; cc-main.s: the driver: command line, the library file, the image
; =============================================================================
        .data                           ; this unit's strings
        .align 8                        ; (words first)
m_toobig: .asciz "the code does not fit the instruction store: compile with -p" ; ...
m_imgbig: .asciz "the program is larger than 128 KiB" ; ...
m_ltext:  .asciz "libc.text"            ; its members
m_ldata:  .asciz "libc.data"            ; ...
m_lsym:   .asciz "libc.sym"             ; ...
m_main:   .asciz "main"                 ; the entry point's name
OUTNAME:  .space 40                     ; the default output name
        .align 8                        ; ...
lib_sym:  .dword 0                      ; arena offset of the library's symbol table
lib_nsym: .dword 0                      ; its records
src_name: .dword 0                      ; the source file's name

        .far                            ; code units
        .align 4096                     ; ---- unit: main ----
u_main:
; main(): compile the file named on the command line
main:
        jalr  t6, gp, ent4-R            ; s1 = cursor, s2 = end of the command line
        li    s1, __sblk + 64           ; the command line: "cc args"
        ld    s2, __sblk + 40(zero)     ; its length
        add   s2, s1, s2                ; ...
        sb    zero, 0(s2)               ; (terminated)
        call  m_word                    ; skip the program's name
ma_arg:
        call  m_word                    ; a0 = the next word, or 0
        beqz  a0, ma_done               ; no more
        lbu   t0, 0(a0)                 ; an option?
        li    t1, '-'                   ; ...
        bne   t0, t1, ma_src            ; no: the source file
        lbu   t0, 1(a0)                 ; which?
        li    t1, 'p'                   ; -p: paged code
        bne   t0, t1, ma_o              ; ...
        li    t1, 1                     ; ...
        sd    t1, paged(zero)           ; ...
        j     ma_arg                    ; ...
ma_o:
        li    t1, 'o'                   ; -o NAME
        bne   t0, t1, ma_h              ; ...
        call  m_word                    ; ...
        beqz  a0, ma_usage              ; ...
        sd    a0, out_name(zero)        ; ...
        j     ma_arg                    ; ...
ma_h:
        li    t1, 'h'                   ; -h KIB
        bne   t0, t1, ma_usage          ; anything else is an error
        call  m_word                    ; ...
        beqz  a0, ma_usage              ; ...
        li    t2, 0                     ; the number
ma_hd:
        lbu   t0, 0(a0)                 ; ...
        addi  t0, t0, -'0'              ; ...
        sltiu t1, t0, 10                ; ...
        beqz  t1, ma_hend               ; ...
        li    t1, 10                    ; ...
        mul   t2, t2, t1                ; ...
        add   t2, t2, t0                ; ...
        addi  a0, a0, 1                 ; ...
        j     ma_hd                     ; ...
ma_hend:
        slli  t2, t2, 10                ; KiB
        sd    t2, heapsz(zero)          ; ...
        j     ma_arg                    ; ...
ma_src:
        sd    a0, src_name(zero)        ; the source file
        j     ma_arg                    ; ...
ma_usage:
        li    a0, m_usage               ; say how
        jalr  ra, gp, eputs-R           ; ...
        li    a0, 2                     ; ...
        jalr  zero, gp, _exit-R         ; ...
ma_done:
        ld    a0, src_name(zero)        ; a source file is required
        beqz  a0, ma_usage              ; ...
        ld    t0, out_name(zero)        ; an output name?
        bnez  t0, ma_lib                ; yes
        mv    t1, a0                    ; no: the source's name without its tag path and ".c"
ma_base:
        lbu   t2, 0(t1)                 ; ...
        beqz  t2, ma_bend               ; ...
        addi  t1, t1, 1                 ; ...
        li    t3, '/'                   ; ...
        bne   t2, t3, ma_base           ; ...
        mv    a0, t1                    ; (what follows the last /)
        j     ma_base                   ; ...
ma_bend:
        li    t0, OUTNAME               ; ...
        sd    t0, out_name(zero)        ; ...
        li    t3, OUTNAME + 38          ; (room)
ma_on:
        lbu   t1, 0(a0)                 ; ...
        sb    t1, 0(t0)                 ; ...
        beqz  t1, ma_strip              ; ...
        addi  a0, a0, 1                 ; ...
        addi  t0, t0, 1                 ; ...
        bltu  t0, t3, ma_on             ; ...
        sb    zero, 0(t0)               ; (cut)
ma_strip:
        lbu   t1, -1(t0)                ; ends in ".c"?
        li    t2, 'c'                   ; ...
        bne   t1, t2, ma_lib            ; ...
        lbu   t1, -2(t0)                ; ...
        li    t2, '.'                   ; ...
        bne   t1, t2, ma_lib            ; ...
        sb    zero, -2(t0)              ; ...
ma_lib:
ma_lib2:
        li    a0, m_lsym                ; its symbol table
        call  m_member                  ; a0 = offset, a1 = size
        sd    a0, lib_sym(zero)         ; ...
        li    t0, 24                    ; records of 24 bytes
        divu  a1, a1, t0                ; ...
        sd    a1, lib_nsym(zero)        ; ...
        li    a0, m_ldata               ; its data: the start of the D-LS image
        call  m_member                  ; ...
        addi  a2, a1, 7                 ; whole words
        srli  a2, a2, 3                 ; ...
        slli  a2, a2, 3                 ; ...
        sd    a2, data_pc(zero)         ; the program's data follows
        mv    a1, a0                    ; ...
        li    a0, F_DATA                ; ...
        jalr  ra, gp, m_copy-R          ; ...
        li    a0, m_ltext               ; its code
        call  m_member                  ; ...
        addi  s3, a1, 7                 ; s3 = its size in whole words
        srli  s3, s3, 3                 ; ...
        slli  s3, s3, 3                 ; ...
        li    t0, 0x8000                ; the resident code ends after it
        add   t0, t0, s3                ; ...
        sd    t0, res_end(zero)         ; ...
        mv    a1, a0                    ; ...
        mv    a2, s3                    ; ...
        ld    t1, paged(zero)           ; where it goes depends on the code model
        bnez  t1, ma_paged              ; ...
        li    a0, F_CODE                ; resident: the program's code follows it
        jalr  ra, gp, m_copy-R          ; ...
        ld    t0, res_end(zero)         ; ...
        sd    t0, code_pc(zero)         ; ...
        srli  t1, t0, 11                ; the code window holding that address
        slli  t1, t1, 11                ; ...
        sd    t1, cw_base(zero)         ; ...
        li    t2, 0x8000                ; with what is already there
        sub   t2, t1, t2                ; ...
        li    t3, F_CODE                ; ...
        add   t2, t2, t3                ; ...
        li    t3, CW                    ; ...
        li    t4, CWSZ                  ; ...
        tget  tg14, t3, c0, t2, t4      ; ...
        j     ma_init                   ; ...
ma_paged:
        li    a0, F_RES                 ; paged: the library is the resident part
        jalr  ra, gp, m_copy-R          ; ...
        li    t0, 0x10000               ; and the program's code units start at arena 0x10000
        sd    t0, code_org(zero)        ; ...
        sd    t0, code_pc(zero)         ; ...
        sd    t0, cw_base(zero)         ; ...
ma_init:
        la    t6, lex_init              ; keywords
        xcall ra, c0, t6                ; ...
        la    t6, ty_init               ; the basic types
        xcall ra, c0, t6                ; ...
        la    t6, pp_init               ; the built-in macros
        xcall ra, c0, t6                ; ...
        ld    a0, src_name(zero)        ; the source -> the arena
        li    a1, F_SRC                 ; ...
        li    a2, F_SRCEND - F_SRC      ; ...
        jalr  ra, gp, m_load-R          ; a0 = size
        bltz  a0, ma_nosrc              ; ...
        mv    a1, a0                    ; without its backslash-newlines
        li    a0, F_SRC                 ; ...
        call  splice                    ; ...
        j     ma_src2                   ; ...
ma_nosrc:
        li    a0, m_nofile              ; ...
        ld    a1, src_name(zero)        ; ...
        jalr  zero, gp, error2-R        ; ...
ma_src2:
        li    t0, F_SRC                 ; read it
        sd    t0, in_pos(zero)          ; ...
        add   t0, t0, a0                ; ...
        sd    t0, in_end(zero)          ; ...
        addi  t0, t0, 8                 ; (the next file goes after it)
        srli  t0, t0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        sd    t0, src_top(zero)         ; ...
        li    t0, 1                     ; a file, at line 1
        sd    t0, in_kind(zero)         ; ...
        sd    t0, line(zero)            ; ...
        li    t0, FNAMES                ; its name, for messages
        sd    t0, fname(zero)           ; ...
        ld    t1, src_name(zero)        ; ...
        li    t3, FNAMES + 31           ; ...
ma_fn:
        lbu   t2, 0(t1)                 ; ...
        sb    t2, 0(t0)                 ; ...
        beqz  t2, ma_go                 ; ...
        addi  t1, t1, 1                 ; ...
        addi  t0, t0, 1                 ; ...
        bltu  t0, t3, ma_fn             ; ...
        sb    zero, 0(t0)               ; ...
ma_go:
        la    t6, next                  ; the first token
        xcall ra, c0, t6                ; ...
ma_unit:
        ld    t0, tok(zero)             ; external declarations until the end
        beqz  t0, ma_link               ; ...
        la    t6, ext_decl              ; ...
        xcall ra, c0, t6                ; ...
        j     ma_unit                   ; ...
ma_link:
        sd    zero, fname(zero)         ; (messages are no longer about a line)
        la    t6, link                  ; fixups, the start-up words
        xcall ra, c0, t6                ; ...
        la    t6, m_write               ; the image
        xcall ra, c0, t6                ; ...
        li    a0, 0                     ; done
        jalr  zero, gp, _exit-R         ; ...

; m_word() -> a0 = the next word of the command line (s1..s2), zero-terminated, or 0
m_word:
        li    t1, ' '                   ; ...
mw_sp:
        bgeu  s1, s2, mw_none           ; ...
        lbu   t0, 0(s1)                 ; skip spaces
        bne   t0, t1, mw_w              ; ...
        addi  s1, s1, 1                 ; ...
        j     mw_sp                     ; ...
mw_w:
        mv    a0, s1                    ; the word
mw_c:
        addi  s1, s1, 1                 ; to its end
        bgeu  s1, s2, mw_ret            ; ...
        lbu   t0, 0(s1)                 ; ...
        bne   t0, t1, mw_c              ; ...
        sb    zero, 0(s1)               ; terminate it
        addi  s1, s1, 1                 ; ...
mw_ret:
        ret                             ; ...
mw_none:
        li    a0, 0                     ; none
        ret                             ; done

; m_member(a0 = member name) -> a0 = arena offset of its bytes, a1 = its size.
; A missing member is an error. Also used for headers: lib_find returns 0 instead.
m_member:
        addi  sp, sp, -8                ; ...
        sd    ra, 0(sp)                 ; ...
        jalr  ra, gp, lib_find1-R       ; ...
        bnez  a0, mm_ret                ; ...
        li    a0, m_badlib              ; ...
        jalr  zero, gp, error-R         ; ...
mm_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; done
; lib_find(a0 = name) -> a0 = arena offset or 0, a1 = size  (for other units)
lib_find:
        jalr  t6, gp, ent0-R            ; ...
        jalr  ra, gp, lib_find1-R       ; ...
        jalr  zero, gp, lv0-R           ; ...

; link(): resolve the fixups, write the start-up words, close the images
link:
        jalr  t6, gp, ent4-R            ; s1 = main, s2 = fixup cursor, s3 = symbol, s4 = target
        li    a0, m_main                ; main must be a defined function
        li    a1, 4                     ; ...
        jalr  ra, gp, intern-R          ; ...
        lhu   s1, IDR+ID_SYM(zero)      ; ...
        beqz  s1, lk_nomain             ; ...
        lbu   t0, SY_CLASS(s1)          ; ...
        addi  t0, t0, -SC_FUNC          ; ...
        bnez  t0, lk_nomain             ; ...
        lbu   t0, SY_FLAGS(s1)          ; ...
        andi  t0, t0, SF_DEF            ; ...
        bnez  t0, lk_fix                ; ...
lk_nomain:
        li    a0, m_nomain              ; ...
        jalr  zero, gp, error-R         ; ...
lk_fix:
        sd    zero, nocode(zero)        ; (patching is writing code)
        li    s2, F_FIX                 ; every fixup
lk_loop:
        ld    t0, fix_top(zero)         ; ...
        bgeu  s2, t0, lk_done           ; ...
        li    t0, IOB                   ; the record
        li    t1, 16                    ; ...
        tget  tg14, t0, c0, s2, t1      ; ...
        lwu   a0, IOB+FX_ID(zero)       ; what its identifier names at file scope
        addi  a0, a0, 8                 ; ...
        jalr  ra, gp, far_ld-R          ; ...
        slli  s3, a0, 48                ; (ID_SYM: the low 16 bits)
        srli  s3, s3, 48                ; ...
        li    t0, IOB                   ; (the record again: far_ld used the scratch words)
        li    t1, 16                    ; ...
        tget  tg14, t0, c0, s2, t1      ; ...
        beqz  s3, lk_undef              ; nothing
        lbu   t0, SY_FLAGS(s3)          ; it must be defined by now
        andi  t0, t0, SF_DEF            ; ...
        bnez  t0, lk_def                ; ...
lk_undef:
        lwu   a0, IOB+FX_ID(zero)       ; name it
        jalr  ra, gp, id_name-R         ; ...
        mv    a1, a0                    ; ...
        li    a0, m_undefd              ; ...
        jalr  zero, gp, error2-R        ; ...
lk_def:
        lw    s4, SY_VAL(s3)            ; the target: its address plus the addend
        lw    t0, IOB+FX_ADD(zero)      ; ...
        add   s4, s4, t0                ; ...
        lwu   s3, IOB+FX_LOC(zero)      ; s3 = the place to patch
        lbu   t0, IOB+FX_KIND(zero)     ; how?
        li    t1, FK_JAL                ; ...
        beq   t0, t1, lk_jal            ; ...
        li    t1, FK_LUI                ; ...
        beq   t0, t1, lk_lui            ; ...
        li    t1, FK_MEM                ; ...
        beq   t0, t1, lk_mem            ; ...
        mv    a0, s3                    ; a data word
        mv    a1, s4                    ; ...
        li    a2, 8                     ; ...
        jalr  ra, gp, data_put-R        ; ...
        j     lk_next                   ; ...
lk_jal:
        mv    a0, s3                    ; jal: the 21-bit offset in instructions
        jalr  ra, gp, code_rd-R         ; ...
        sub   t0, s4, s3                ; ...
        srai  t0, t0, 2                 ; ...
        slli  t0, t0, 43                ; ...
        srli  t0, t0, 43                ; ...
        srli  a1, a0, 21                ; ...
        slli  a1, a1, 21                ; ...
        or    a1, a1, t0                ; ...
        mv    a0, s3                    ; ...
        jalr  ra, gp, code_wr-R         ; ...
        j     lk_next                   ; ...
lk_lui:
        mv    a0, s3                    ; lui: the high half
        jalr  ra, gp, code_rd-R         ; ...
        srli  a1, a0, 16                ; ...
        slli  a1, a1, 16                ; ...
        srli  t0, s4, 16                ; ...
        andi  t0, t0, 0xffff            ; ...
        or    a1, a1, t0                ; ...
        mv    a0, s3                    ; ...
        jalr  ra, gp, code_wr-R         ; ...
        addi  a0, s3, 4                 ; ori: the low half
        jalr  ra, gp, code_rd-R         ; ...
        srli  a1, a0, 16                ; ...
        slli  a1, a1, 16                ; ...
        andi  t0, s4, 0xffff            ; ...
        or    a1, a1, t0                ; ...
        addi  a0, s3, 4                 ; ...
        jalr  ra, gp, code_wr-R         ; ...
        j     lk_next                   ; ...
lk_mem:
        mv    a0, s3                    ; imm(zero) below 0x8000, else imm(gp)
        jalr  ra, gp, code_rd-R         ; ...
        srli  a1, a0, 21                ; keep the opcode and rd
        slli  a1, a1, 21                ; ...
        li    t0, 0x8000                ; ...
        bltu  s4, t0, lk_mlow           ; ...
        li    t0, X_GP << 16            ; base gp
        or    a1, a1, t0                ; ...
lk_mlow:
        andi  t0, s4, 0xffff            ; the address's low 16 bits are the immediate either way
        or    a1, a1, t0                ; ...
        mv    a0, s3                    ; ...
        jalr  ra, gp, code_wr-R         ; ...
lk_next:
        addi  s2, s2, 16                ; ...
        j     lk_loop                   ; ...
lk_done:
        li    a0, 0                     ; __main
        lw    a1, SY_VAL(s1)            ; ...
        li    a2, 8                     ; ...
        jalr  ra, gp, data_put-R        ; ...
        li    a0, 8                     ; __xslot
        ld    a1, paged(zero)           ; ...
        slli  t0, a1, 3                 ; 12 or 0
        slli  a1, a1, 2                 ; ...
        add   a1, a1, t0                ; ...
        li    a2, 8                     ; ...
        jalr  ra, gp, data_put-R        ; ...
        ld    s2, data_pc(zero)         ; the heap follows the data
        addi  s2, s2, 7                 ; ...
        srli  s2, s2, 3                 ; ...
        slli  s2, s2, 3                 ; ...
        ld    s3, heapsz(zero)          ; ...
        add   s3, s2, s3                ; ...
        li    t0, 0xA000                ; as far as the program's D-LS goes
        bleu  s3, t0, lk_heap           ; ...
        mv    s3, t0                    ; ...
lk_heap:
        li    a0, 16                    ; __heap
        mv    a1, s2                    ; ...
        li    a2, 8                     ; ...
        jalr  ra, gp, data_put-R        ; ...
        li    a0, 24                    ; __hend
        mv    a1, s3                    ; ...
        li    a2, 8                     ; ...
        jalr  ra, gp, data_put-R        ; ...
        sd    s3, data_pc(zero)         ; the data extent ends with the heap
        ld    t0, dw_dirty(zero)        ; write the data window out
        beqz  t0, lk_code               ; ...
        ld    t1, dw_base(zero)         ; ...
        li    t3, F_DATA                ; ...
        add   t3, t3, t1                ; ...
        li    t4, DW                    ; ...
        li    t5, DWSZ                  ; ...
        tput  tg14, t4, c0, t3, t5      ; ...
lk_code:
        jalr  ra, gp, cw_flush-R        ; and the code window
        jalr  zero, gp, lv4-R           ; done

; m_write(): write the image file
m_write:
        jalr  t6, gp, ent4-R            ; s1 = handle
        ld    t0, paged(zero)           ; resident code must fit the instruction store
        bnez  t0, mwr_sz                ; ...
        ld    t0, code_pc(zero)         ; ...
        lui   t1, 1                     ; ...
        bleu  t0, t1, mwr_sz            ; ...
        li    a0, m_toobig              ; ...
        jalr  zero, gp, error-R         ; ...
mwr_sz:
        ld    t0, code_pc(zero)         ; and the whole image the 128 KiB the kernel loads
        ld    t1, code_org(zero)        ; ...
        sub   t0, t0, t1                ; ...
        ld    t1, data_pc(zero)         ; ...
        add   t0, t0, t1                ; ...
        ld    t1, res_end(zero)         ; ...
        add   t0, t0, t1                ; (res_end - 0x8000: the library, counted twice in the
        li    t1, 0x8000 - 80           ;  resident model: it is small)
        sub   t0, t0, t1                ; ...
        lui   t1, 2                     ; ...
        bleu  t0, t1, mwr_cr            ; ...
        li    a0, m_imgbig              ; ...
        jalr  zero, gp, error-R         ; ...
mwr_cr:
        ld    a0, out_name(zero)        ; create it
        li    a1, 1                     ; ...
        jalr  ra, gp, open-R            ; ...
        bgez  a0, mwr_ok                ; ...
mwr_bad:
        li    a0, m_nowrite             ; ...
        ld    a1, out_name(zero)        ; ...
        jalr  zero, gp, error2-R        ; ...
mwr_ok:
        mv    s1, a0                    ; ...
        li    t0, 0x32585453            ; "STX2"
        sw    t0, IOB(zero)             ; ...
        ld    t1, paged(zero)           ; 2 sections, or 3
        addi  t1, t1, 2                 ; ...
        sw    t1, IOB+4(zero)           ; ...
        mv    a0, s1                    ; ...
        li    a1, IOB                   ; ...
        li    a2, 8                     ; ...
        jalr  ra, gp, write-R           ; ...
        bltz  a0, mwr_bad               ; ...
        ld    t0, paged(zero)           ; ...
        bnez  t0, mwr_paged             ; ...
        li    a0, 1                     ; I-LS: library and program
        li    a1, 0x8000                ; ...
        ld    a2, code_pc(zero)         ; ...
        sub   a2, a2, a1                ; ...
        li    a3, F_CODE                ; ...
        call  m_sect                    ; ...
        j     mwr_data                  ; ...
mwr_paged:
        li    a0, 1                     ; I-LS: the library
        li    a1, 0x8000                ; ...
        ld    a2, res_end(zero)         ; ...
        sub   a2, a2, a1                ; ...
        li    a3, F_RES                 ; ...
        call  m_sect                    ; ...
        li    a0, 3                     ; T3: the code units
        lui   a1, 1                     ; from arena offset 0x10000
        ld    a2, code_pc(zero)         ; ...
        sub   a2, a2, a1                ; ...
        li    a3, F_CODE                ; ...
        call  m_sect                    ; ...
mwr_data:
        li    a0, 2                     ; D-LS: data and heap
        li    a1, 0                     ; ...
        ld    a2, data_pc(zero)         ; ...
        li    a3, F_DATA                ; ...
        call  m_sect                    ; ...
        mv    a0, s1                    ; ...
        jalr  ra, gp, close-R           ; ...
        jalr  zero, gp, lv4-R           ; done

; m_sect(a0 = kind, a1 = base, a2 = size, a3 = arena offset): one section to handle s1
m_sect:
        addi  sp, sp, -8                ; (s2..s4 are the caller's to lose)
        sd    ra, 0(sp)                 ; ...
        addi  s2, a2, 7                 ; s2 = bytes left, whole words
        srli  s2, s2, 3                 ; ...
        slli  s2, s2, 3                 ; ...
        mv    s3, a3                    ; s3 = arena cursor
        sw    a0, IOB(zero)             ; the section header
        sw    a1, IOB+4(zero)           ; ...
        sw    s2, IOB+8(zero)           ; ...
        sw    zero, IOB+12(zero)        ; ...
        mv    a0, s1                    ; ...
        li    a1, IOB                   ; ...
        li    a2, 16                    ; ...
        jalr  ra, gp, write-R           ; ...
msc_loop:
        beqz  s2, msc_ret               ; ...
        li    s4, 1024                  ; a piece
        bleu  s4, s2, msc_n             ; ...
        mv    s4, s2                    ; ...
msc_n:
        li    t1, IOB                   ; arena -> D-LS -> file
        tget  tg14, t1, c0, s3, s4      ; ...
        mv    a0, s1                    ; ...
        li    a1, IOB                   ; ...
        mv    a2, s4                    ; ...
        jalr  ra, gp, write-R           ; (the copy in write waits for the tget)
        bltz  a0, mwr_bad               ; ...
        add   s3, s3, s4                ; ...
        sub   s2, s2, s4                ; ...
        j     msc_loop                  ; ...
msc_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; done

; lib_lookup(a0 = identifier record) -> a0 = the library's address for that
; name, or -1 if the library does not export it
lib_lookup:
        jalr  t6, gp, ent2-R            ; s1 = table cursor, s2 = records left
        jalr  ra, gp, id_name-R         ; the name -> IDR
        ld    s1, lib_sym(zero)         ; ...
        ld    s2, lib_nsym(zero)        ; ...
ll_loop:
        beqz  s2, ll_none               ; ...
        li    t0, IOB                   ; a record: name[20], address
        li    t1, 24                    ; ...
        tget  tg14, t0, c0, s1, t1      ; ...
        li    t2, IDR + ID_NAME         ; compare the names
ll_cmp:
        lbu   t3, 0(t0)                 ; ...
        lbu   t4, 0(t2)                 ; ...
        bne   t3, t4, ll_next           ; ...
        addi  t0, t0, 1                 ; ...
        addi  t2, t2, 1                 ; ...
        bnez  t3, ll_cmp                ; ...
        lwu   a0, IOB+20(zero)          ; found
        jalr  zero, gp, lv2-R           ; ...
ll_next:
        addi  s1, s1, 24                ; ...
        addi  s2, s2, -1                ; ...
        j     ll_loop                   ; ...
ll_none:
        li    a0, -1                    ; ...
        jalr  zero, gp, lv2-R           ; done

; load_file(a0 = name, a1 = arena offset, a2 = most bytes) -> a0 = size or -1:
; m_load for other units; backslash-newline pairs are removed from the text
load_file:
        jalr  t6, gp, ent2-R            ; s1 = start, s2 = size
        mv    s1, a1                    ; ...
        jalr  ra, gp, m_load-R          ; ...
        bltz  a0, ldf_ret               ; ...
        mv    a1, a0                    ; ...
        mv    a0, s1                    ; ...
        call  splice                    ; ...
ldf_ret:
        jalr  zero, gp, lv2-R           ; done

; splice(a0 = start of a text in the arena, a1 = its size) -> a0 = its size
; after removing every backslash-newline (and carriage return). The newlines
; removed are put back after the line's own, so that lines keep their numbers.
splice:
        addi  sp, sp, -48               ; frame
        sd    ra, 40(sp)                ; ...
        sd    s1, 0(sp)                 ; s1 = read cursor
        sd    s2, 8(sp)                 ; s2 = end
        sd    s3, 16(sp)                ; s3 = newlines owed
        sd    s4, 24(sp)                ; s4 = start
        mv    s1, a0                    ; ...
        mv    s4, a0                    ; ...
        add   s2, a0, a1                ; ...
        li    s3, 0                     ; ...
        jalr  ra, gp, wb_open-R         ; written back in place (the text only gets shorter)
spl_l:
        bgeu  s1, s2, spl_end           ; ...
        mv    a0, s1                    ; a character
        jalr  ra, gp, rb_get-R          ; ...
        addi  s1, s1, 1                 ; ...
        li    t0, 13                    ; a carriage return: dropped
        beq   a0, t0, spl_l             ; ...
        li    t0, 92                    ; a backslash: before a newline?
        bne   a0, t0, spl_nl            ; ...
        sd    a0, 32(sp)                ; ...
        mv    a0, s1                    ; ...
        jalr  ra, gp, rb_get-R          ; ...
        li    t0, 13                    ; (a carriage return may come between)
        bne   a0, t0, spl_bs            ; ...
        addi  a0, s1, 1                 ; ...
        jalr  ra, gp, rb_get-R          ; ...
        li    t0, 10                    ; ...
        bne   a0, t0, spl_keep          ; ...
        addi  s1, s1, 1                 ; ...
spl_bs:
        li    t0, 10                    ; ...
        bne   a0, t0, spl_keep          ; ...
        addi  s1, s1, 1                 ; both go; one newline is owed
        addi  s3, s3, 1                 ; ...
        j     spl_l                     ; ...
spl_keep:
        ld    a0, 32(sp)                ; an ordinary backslash
spl_nl:
        sd    a0, 32(sp)                ; ...
        jalr  ra, gp, wb_put-R          ; ...
        ld    a0, 32(sp)                ; after a newline come the owed ones
        li    t0, 10                    ; ...
        bne   a0, t0, spl_l             ; ...
spl_owe:
        beqz  s3, spl_l                 ; ...
        li    a0, 10                    ; ...
        jalr  ra, gp, wb_put-R          ; ...
        addi  s3, s3, -1                ; ...
        j     spl_owe                   ; ...
spl_end:
        jalr  ra, gp, wb_close-R        ; ...
        sub   a0, a0, s4                ; ...
        ld    s1, 0(sp)                 ; ...
        ld    s2, 8(sp)                 ; ...
        ld    s3, 16(sp)                ; ...
        ld    s4, 24(sp)                ; ...
        ld    ra, 40(sp)                ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; done
