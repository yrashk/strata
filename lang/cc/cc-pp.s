; =============================================================================
; cc-pp.s: the preprocessor
; =============================================================================
;
; The preprocessor works on text, under the scanner (cc-lex.s):
;   * A directive is handled when the scanner meets # first on a line of a
;     file (pp_direct). Conditionals skip lines here; the expression of #if is
;     read by the compiler's own expression parser, with the scanner in
;     pp_mode (a newline ends the tokens, a name that is not a macro is 0).
;   * A macro's body is stored as text in the arena (F_MAC), parameters
;     replaced by marker bytes. Expanding a macro (pp_expand) writes the body
;     with the arguments substituted into the expansion heap (F_XH) and pushes
;     that text on the input stack: the scanner simply reads it next.
;     Arguments are expanded first (pp_arg), unless they are operands of # or
;     ##. A macro is not expanded again while its own text is being read.
;
; Macro record (arena, 8-byte aligned): the body's bytes follow the header
MC_KIND  = 0                            ; u8: 0 object-like, 1 function-like, 2 __LINE__, 3 __FILE__
MC_BUSY  = 1                            ; u8: its expansion is being read
MC_NPAR  = 2                            ; u8: parameters
MC_VAR   = 3                            ; u8: the last parameter takes the rest (...)
MC_LEN   = 4                            ; u32: bytes of body
MC_BODY  = 16                           ; the body
; marker bytes in a body
MK_PAR   = 0x80                         ; + n: parameter n
MK_STR   = 0xC0                         ; + n: # parameter n
MK_CAT   = 0xFF                         ; ##
MAXPAR   = 32                           ; parameters of a macro
XBSZ     = 1536                         ; bytes of arguments being expanded at one time
NARGS    = 48                           ; arguments of all the expansions in progress

        .data                           ; the preprocessor's variables
        .align 8                        ; (words first)
if_sp:    .dword 0                      ; conditionals open
xb_top:   .dword 0                      ; bytes of XBUF in use
IFSTK:    .space 32                     ; per open conditional: 1 = a group of it was taken
MH:       .space 16                     ; a macro record's header
PARM:     .space MAXPAR * 8             ; #define: the parameters' identifier records
ARGS:     .space NARGS * 32             ; expansions in progress: per argument: raw start, raw end, expanded start, expanded end
args_top: .dword 0                      ; entries of ARGS in use
XBUF:     .space XBSZ                   ; arguments being expanded
pd_names: .asciz "define"               ; the directives, in the order of the jumps in pp_direct
          .asciz "undef"                ; .
          .asciz "include"              ; .
          .asciz "ifdef"                ; .
          .asciz "ifndef"               ; .
          .asciz "if"                   ; .
          .asciz "elif"                 ; .
          .asciz "else"                 ; .
          .asciz "endif"                ; .
          .asciz "error"                ; .
          .asciz "line"                 ; .
          .asciz "pragma"               ; .
          .byte 0                       ; (the end)
m_defined: .asciz "defined"             ; the operator of #if
m_va:     .asciz "__VA_ARGS__"          ; what ... is called in a body
m_line:   .asciz "__LINE__"             ; the built-in macros
m_file:   .asciz "__FILE__"             ; .
m_ppdir:  .asciz "unknown directive: "  ; messages
m_ppif:   .asciz "#if without #endif, or #endif without #if" ; .
m_pperr:  .asciz "#error "              ; .
m_ppargs: .asciz "wrong number of macro arguments: " ; .
m_ppbig:  .asciz "macro expansion too long" ; .
m_ppdef:  .asciz "bad macro definition" ; .
m_ppinc:  .asciz "cannot include "      ; .
        .align 8                        ; ...

        .far                            ; code units
        .align 4096                     ; ---- unit: pp1 ----
u_pp1:
; The helpers of this unit return with xret: they call only resident code,
; so this unit calls them with `call`, other units with xcall.

; pp_c() -> a0 = the next character of a directive line, comments removed (a
; comment is one space); the newline that ends the line is not consumed (it is
; returned each time); -1 at the end of the input   (leaf)
pp_c:
        addi  sp, sp, -16               ; frame: ra, the previous character of a comment
        sd    ra, 0(sp)                 ; ...
        jalr  ra, gp, nextc-R           ; ...
        li    t0, 10                    ; the newline stays
        bne   a0, t0, ppc_com           ; ...
ppc_back:
        ld    t1, in_pos(zero)          ; ...
        addi  t1, t1, -1                ; ...
        sd    t1, in_pos(zero)          ; ...
        j     ppc_ret                   ; ...
ppc_com:
        li    t0, '/'                   ; a comment?
        bne   a0, t0, ppc_ret           ; ...
        jalr  ra, gp, nextc-R           ; ...
        li    t0, '*'                   ; ...
        beq   a0, t0, ppc_blk           ; ...
        li    t0, '/'                   ; ...
        beq   a0, t0, ppc_line          ; ...
        bltz  a0, ppc_sl                ; not a comment: give the second character back
        ld    t1, in_pos(zero)          ; ...
        addi  t1, t1, -1                ; ...
        sd    t1, in_pos(zero)          ; ...
ppc_sl:
        li    a0, '/'                   ; ...
        j     ppc_ret                   ; ...
ppc_line:
        jalr  ra, gp, nextc-R           ; // to the end of the line
        bltz  a0, ppc_ret               ; ...
        li    t0, 10                    ; ...
        bne   a0, t0, ppc_line          ; ...
        j     ppc_back                  ; ...
ppc_blk:
        sd    zero, 8(sp)               ; /* ... */
ppc_b:
        jalr  ra, gp, nextc-R           ; ...
        bltz  a0, ppc_ret               ; ...
        li    t0, 10                    ; its lines count
        bne   a0, t0, ppc_b2            ; ...
        ld    t1, line(zero)            ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, line(zero)            ; ...
ppc_b2:
        ld    t5, 8(sp)                 ; the previous character
        sd    a0, 8(sp)                 ; ...
        li    t0, '/'                   ; ...
        bne   a0, t0, ppc_b             ; ...
        li    t0, '*'                   ; ...
        bne   t5, t0, ppc_b             ; ...
        li    a0, ' '                   ; the comment is a space
ppc_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        xret  ra                        ; done

; pp_blank() -> a0 = the next character that is not a blank (consumed)  (leaf)
pp_blank:
        addi  sp, sp, -8                ; ...
        sd    ra, 0(sp)                 ; ...
ppb_l:
        call  pp_c                      ; ...
        bltz  a0, ppb_ret               ; ...
        sltiu t0, a0, 128               ; ...
        beqz  t0, ppb_ret               ; ...
        lbu   t0, CC(a0)                ; ...
        andi  t0, t0, CL_SP             ; ...
        bnez  t0, ppb_l                 ; ...
ppb_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        xret  ra                        ; done
; pp_unget(a0 = character): give it back (not the end, not the newline, which was never taken)
pp_unget:
        bltz  a0, ppu_ret               ; ...
        li    t0, 10                    ; ...
        beq   a0, t0, ppu_ret           ; ...
        ld    t1, in_pos(zero)          ; ...
        addi  t1, t1, -1                ; ...
        sd    t1, in_pos(zero)          ; ...
ppu_ret:
        xret  ra                        ; done

; pp_word() -> a0 = length of the identifier that comes next (after blanks),
; copied to TB and zero-terminated; 0 if something else comes  (leaf)
pp_word:
        addi  sp, sp, -16               ; ...
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; s1 = cursor
        li    s1, TB                    ; ...
        call  pp_blank                  ; ...
        sltiu t0, a0, 128               ; ...
        beqz  t0, ppw_end               ; ...
        lbu   t0, CC(a0)                ; it must start like an identifier
        andi  t0, t0, CL_ID1            ; ...
        beqz  t0, ppw_end               ; ...
ppw_l:
        sb    a0, 0(s1)                 ; ...
        addi  s1, s1, 1                 ; ...
        jalr  ra, gp, nextc-R           ; (inside a word there are no comments)
        sltiu t0, a0, 128               ; ...
        beqz  t0, ppw_end2              ; ...
        lbu   t0, CC(a0)                ; ...
        andi  t0, t0, CL_ID             ; ...
        beqz  t0, ppw_end2              ; ...
        li    t0, TB + ID_MAXLEN        ; ...
        bltu  s1, t0, ppw_l             ; ...
        addi  s1, s1, -1                ; ...
        j     ppw_l                     ; ...
ppw_end2:
        bltz  a0, ppw_z                 ; the character after it is given back
        ld    t1, in_pos(zero)          ; ...
        addi  t1, t1, -1                ; ...
        sd    t1, in_pos(zero)          ; ...
        j     ppw_z                     ; ...
ppw_end:
        call  pp_unget                  ; ...
ppw_z:
        sb    zero, 0(s1)               ; ...
        addi  a0, s1, -TB               ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        xret  ra                        ; done

; pp_eol(): skip the rest of the line (the newline stays)  (leaf)
pp_eol:
        addi  sp, sp, -8                ; ...
        sd    ra, 0(sp)                 ; ...
ppe_l:
        call  pp_c                      ; ...
        bltz  a0, ppe_ret               ; ...
        li    t0, 10                    ; ...
        beq   a0, t0, ppe_ret           ; ...
        j     ppe_l                     ; ...
ppe_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        xret  ra                        ; done

; pp_which() -> a0 = the number (from 1) of the directive whose name is in TB, 0 if none  (leaf)
pp_which:
        li    t0, pd_names              ; ...
        li    a0, 1                     ; ...
pwh_l:
        lbu   t1, 0(t0)                 ; the end of the table?
        beqz  t1, pwh_no                ; ...
        li    t2, TB                    ; compare
pwh_c:
        lbu   t3, 0(t0)                 ; ...
        lbu   t4, 0(t2)                 ; ...
        bne   t3, t4, pwh_n             ; ...
        addi  t0, t0, 1                 ; ...
        addi  t2, t2, 1                 ; ...
        bnez  t3, pwh_c                 ; ...
        xret  ra                        ; found
pwh_n:
        lbu   t3, 0(t0)                 ; to the next name
        addi  t0, t0, 1                 ; ...
        bnez  t3, pwh_n                 ; ...
        addi  a0, a0, 1                 ; ...
        j     pwh_l                     ; ...
pwh_no:
        li    a0, 0                     ; ...
        xret  ra                        ; done

; pp_direct(): a directive: the # has been read
pp_direct:
        jalr  t6, gp, ent2-R            ; s1 = directive, s2 = scratch
        call  pp_word                   ; its name
        beqz  a0, ppd_ret               ; a # alone
        call  pp_which                  ; ...
        mv    s1, a0                    ; ...
        bnez  s1, ppd_go                ; ...
        li    a0, m_ppdir               ; ...
        li    a1, TB                    ; ...
        jalr  zero, gp, error2-R        ; ...
ppd_go:
        li    t0, 1                     ; define
        bne   s1, t0, ppd_2             ; ...
        la    t6, pp_define             ; ...
        xcall ra, c0, t6                ; ...
        j     ppd_ret                   ; ...
ppd_2:
        li    t0, 2                     ; undef
        bne   s1, t0, ppd_3             ; ...
        call  pp_word                   ; ...
        beqz  a0, ppd_eol               ; ...
        mv    a1, a0                    ; ...
        li    a0, TB                    ; ...
        jalr  ra, gp, intern-R          ; ...
        addi  a0, a0, ID_MAC            ; no macro record
        li    a1, 0                     ; ...
        jalr  ra, gp, far_sw-R          ; ...
        j     ppd_eol                   ; ...
ppd_3:
        li    t0, 3                     ; include
        bne   s1, t0, ppd_4             ; ...
        la    t6, pp_include            ; ...
        xcall ra, c0, t6                ; ...
        j     ppd_ret                   ; ...
ppd_4:
        addi  t0, s1, -4                ; ifdef, ifndef
        sltiu t1, t0, 2                 ; ...
        beqz  t1, ppd_6                 ; ...
        call  pp_word                   ; ...
        mv    a1, a0                    ; ...
        li    a0, TB                    ; ...
        jalr  ra, gp, intern-R          ; ...
        lwu   a0, IDR+ID_MAC(zero)      ; defined?
        snez  a0, a0                    ; ...
        addi  t0, s1, -4                ; ifndef: the opposite
        xor   a0, a0, t0                ; ...
        j     ppd_open                  ; ...
ppd_6:
        li    t0, 6                     ; if
        bne   s1, t0, ppd_7             ; ...
        la    t6, pp_eval               ; ...
        xcall ra, c0, t6                ; ...
ppd_open:
        ld    t0, if_sp(zero)           ; a conditional opens: was its first group taken?
        sb    a0, IFSTK(t0)             ; ...
        addi  t0, t0, 1                 ; ...
        andi  t0, t0, 31                ; (deeper than 32 wraps: not checked)
        sd    t0, if_sp(zero)           ; ...
        bnez  a0, ppd_eol               ; yes: go on reading
        la    t6, pp_skip               ; no: skip to the group that is
        xcall ra, c0, t6                ; ...
        j     ppd_ret                   ; ...
ppd_7:
        addi  t0, s1, -7                ; elif, else: the group being read ends; the rest is skipped
        sltiu t1, t0, 2                 ; ...
        beqz  t1, ppd_9                 ; ...
        ld    t0, if_sp(zero)           ; ...
        beqz  t0, ppd_bad               ; ...
        li    t1, 1                     ; ...
        addi  t0, t0, -1                ; ...
        sb    t1, IFSTK(t0)             ; ...
        la    t6, pp_skip               ; ...
        xcall ra, c0, t6                ; ...
        j     ppd_ret                   ; ...
ppd_9:
        li    t0, 9                     ; endif
        bne   s1, t0, ppd_10            ; ...
        ld    t0, if_sp(zero)           ; ...
        beqz  t0, ppd_bad               ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, if_sp(zero)           ; ...
        j     ppd_eol                   ; ...
ppd_10:
        li    t0, 10                    ; error
        bne   s1, t0, ppd_eol           ; line, pragma: ignored
        li    s2, TB                    ; the rest of the line is the message
ppd_em:
        call  pp_c                      ; ...
        bltz  a0, ppd_ee                ; ...
        li    t0, 10                    ; ...
        beq   a0, t0, ppd_ee            ; ...
        sb    a0, 0(s2)                 ; ...
        addi  s2, s2, 1                 ; ...
        li    t0, TB + 200              ; ...
        bltu  s2, t0, ppd_em            ; ...
ppd_ee:
        sb    zero, 0(s2)               ; ...
        li    a0, m_pperr               ; ...
        li    a1, TB                    ; ...
        jalr  zero, gp, error2-R        ; ...
ppd_bad:
        li    a0, m_ppif                ; ...
        jalr  zero, gp, error-R         ; ...
ppd_eol:
        call  pp_eol                    ; ...
ppd_ret:
        jalr  zero, gp, lv2-R           ; done

; pp_eval() -> a0 = 1 if the expression on the rest of the line is not zero
pp_eval:
        jalr  t6, gp, ent2-R            ; s1 = value, s2 = the token as it was
        ld    s2, tok(zero)             ; ...
        li    t0, 1                     ; the scanner stops at the newline
        sd    t0, pp_mode(zero)         ; ...
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        la    t6, const_expr            ; ...
        xcall ra, c0, t6                ; ...
        snez  s1, a0                    ; ...
        sd    zero, pp_mode(zero)       ; ...
        ld    t0, tok(zero)             ; nothing may follow it
        beqz  t0, pev_ok                ; ...
        li    a0, m_expect              ; ...
        jalr  zero, gp, errtok-R        ; ...
pev_ok:
        sd    s2, tok(zero)             ; ...
        mv    a0, s1                    ; ...
        jalr  zero, gp, lv2-R           ; done

; pp_defined(): in #if, the identifier just scanned (in TB, its record in IDR):
; tk_val = 0, or for `defined NAME` / `defined ( NAME )` whether NAME is a macro
pp_defined:
        jalr  t6, gp, ent1-R            ; s1 = 1: a ( was read
        sd    zero, tk_val(zero)        ; ...
        li    t0, TB                    ; "defined"?
        li    t1, m_defined             ; ...
pdd_c:
        lbu   t2, 0(t0)                 ; ...
        lbu   t3, 0(t1)                 ; ...
        bne   t2, t3, pdd_ret           ; ...
        addi  t0, t0, 1                 ; ...
        addi  t1, t1, 1                 ; ...
        bnez  t2, pdd_c                 ; ...
        li    s1, 0                     ; ...
        call  pp_blank                  ; ( ?
        li    t0, '('                   ; ...
        bne   a0, t0, pdd_np            ; ...
        li    s1, 1                     ; ...
        j     pdd_w                     ; ...
pdd_np:
        call  pp_unget                  ; ...
pdd_w:
        call  pp_word                   ; the name
        mv    a1, a0                    ; ...
        li    a0, TB                    ; ...
        jalr  ra, gp, intern-R          ; ...
        lwu   t0, IDR+ID_MAC(zero)      ; ...
        snez  t0, t0                    ; ...
        sd    t0, tk_val(zero)          ; ...
        beqz  s1, pdd_ret               ; ...
        call  pp_blank                  ; the )
pdd_ret:
        jalr  zero, gp, lv1-R           ; done

        .align 4096                     ; ---- unit: pp1b ----
u_pp1b:
; pp_skip(): skip lines to the group of the innermost conditional that is to
; be read (an #elif whose expression is true or an #else, if no group was
; taken yet), or past its #endif
pp_skip:
        jalr  t6, gp, ent2-R            ; s1 = conditionals opened inside the skipped lines, s2 = directive
        li    s1, 0                     ; ...
psk_line:
        la    t6, pp_eol            ; the rest of this line
        xcall ra, c0, t6                ; ...
        jalr  ra, gp, nextc-R           ; and its newline
        bltz  a0, psk_eof               ; ...
        ld    t0, line(zero)            ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, line(zero)            ; ...
        la    t6, pp_blank          ; a directive?
        xcall ra, c0, t6                ; ...
        li    t0, '#'                   ; ...
        beq   a0, t0, psk_dir           ; ...
        la    t6, pp_unget          ; ...
        xcall ra, c0, t6                ; ...
        j     psk_line                  ; ...
psk_dir:
        la    t6, pp_word           ; ...
        xcall ra, c0, t6                ; ...
        beqz  a0, psk_line              ; ...
        la    t6, pp_which          ; ...
        xcall ra, c0, t6                ; ...
        mv    s2, a0                    ; ...
        addi  t0, s2, -4                ; ifdef ifndef if: one more to close
        sltiu t0, t0, 3                 ; ...
        beqz  t0, psk_end               ; ...
        addi  s1, s1, 1                 ; ...
        j     psk_line                  ; ...
psk_end:
        li    t0, 9                     ; endif
        bne   s2, t0, psk_else          ; ...
        beqz  s1, psk_close             ; ours
        addi  s1, s1, -1                ; ...
        j     psk_line                  ; ...
psk_close:
        ld    t0, if_sp(zero)           ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, if_sp(zero)           ; ...
        j     psk_ret                   ; ...
psk_else:
        bnez  s1, psk_line              ; (an inner conditional's)
        addi  t0, s2, -7                ; elif, else
        sltiu t1, t0, 2                 ; ...
        beqz  t1, psk_line              ; ...
        ld    t2, if_sp(zero)           ; a group was taken already: keep skipping
        addi  t2, t2, -1                ; ...
        lbu   t3, IFSTK(t2)             ; ...
        bnez  t3, psk_line              ; ...
        li    a0, 1                     ; else: this is the group
        bnez  t0, psk_take              ; ...
        la    t6, pp_eval               ; elif: if its expression is true
        xcall ra, c0, t6                ; ...
        beqz  a0, psk_line              ; ...
psk_take:
        ld    t2, if_sp(zero)           ; ...
        addi  t2, t2, -1                ; ...
        li    t3, 1                     ; ...
        sb    t3, IFSTK(t2)             ; ...
psk_ret:
        la    t6, pp_eol            ; ...
        xcall ra, c0, t6                ; ...
        jalr  zero, gp, lv2-R           ; done
psk_eof:
        li    a0, m_ppif                ; ...
        jalr  zero, gp, error-R         ; ...

; pp_include(): #include "file" or <file>
pp_include:
        jalr  t6, gp, ent4-R            ; s1 = closing character, s2 = cursor, s3 = start, s4 = end
        la    t6, pp_blank          ; ...
        xcall ra, c0, t6                ; ...
        li    s1, '"'                   ; ...
        beq   a0, s1, pin_name          ; ...
        li    s1, '>'                   ; ...
        li    t0, '<'                   ; ...
        beq   a0, t0, pin_name          ; ...
pin_bad:
        li    a0, m_ppinc               ; ...
        li    a1, TB                    ; ...
        jalr  zero, gp, error2-R        ; ...
pin_name:
        li    s2, TB                    ; the name
pin_n:
        jalr  ra, gp, nextc-R           ; ...
        beq   a0, s1, pin_e             ; ...
        slti  t0, a0, 32                ; (it ends on its line)
        bnez  t0, pin_bad               ; ...
        sb    a0, 0(s2)                 ; ...
        addi  s2, s2, 1                 ; ...
        li    t0, TB + 30               ; ...
        bltu  s2, t0, pin_n             ; ...
        j     pin_bad                   ; ...
pin_e:
        sb    zero, 0(s2)               ; ...
        la    t6, pp_eol            ; (reading resumes at the end of this line)
        xcall ra, c0, t6                ; ...
        ld    s4, src_top(zero)         ; (what the file's end gives back)
        li    t0, '"'                   ; "file": the file system first
        bne   s1, t0, pin_lib           ; ...
        li    a0, TB                    ; ...
        ld    a1, src_top(zero)         ; ...
        li    a2, F_SRCEND              ; ...
        sub   a2, a2, a1                ; ...
        la    t6, load_file             ; a0 = size or -1
        xcall ra, c0, t6                ; ...
        bltz  a0, pin_lib               ; ...
        ld    s3, src_top(zero)         ; ...
        add   t0, s3, a0                ; ...
        mv    a1, t0                    ; ...
        addi  t0, t0, 8                 ; ...
        srli  t0, t0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        sd    t0, src_top(zero)         ; ...
        j     pin_push                  ; ...
pin_lib:
        li    a0, TB                    ; <file>: a member of cc.lib
        la    t6, lib_find              ; ...
        xcall ra, c0, t6                ; ...
        beqz  a0, pin_bad               ; ...
        mv    s3, a0                    ; ...
        add   a1, a0, a1                ; ...
pin_push:
        mv    a0, s3                    ; read it next
        li    a2, 1                     ; ...
        ld    a3, line(zero)            ; ...
        mv    a4, s4                    ; ...
        jalr  ra, gp, in_push-R         ; ...
        ld    t0, fname(zero)           ; its name, for messages
        addi  t0, t0, 32                ; ...
        li    t1, FNAMES + 7 * 32       ; ...
        bgtu  t0, t1, pin_deep          ; ...
        sd    t0, fname(zero)           ; ...
        li    t1, TB                    ; ...
pin_cp:
        lbu   t2, 0(t1)                 ; ...
        sb    t2, 0(t0)                 ; ...
        addi  t0, t0, 1                 ; ...
        addi  t1, t1, 1                 ; ...
        bnez  t2, pin_cp                ; ...
        li    t0, 1                     ; ...
        sd    t0, line(zero)            ; ...
        sd    t0, bol(zero)             ; ...
        jalr  zero, gp, lv4-R           ; done
pin_deep:
        li    a0, m_incl                ; ...
        jalr  zero, gp, error-R         ; ...

        .align 4096                     ; ---- unit: pp2 ----
u_pp2:
; pp_init(): the built-in macros __LINE__ and __FILE__
pp_init:
        jalr  t6, gp, ent0-R            ; ...
        li    a0, m_line                ; ...
        li    a1, 8                     ; ...
        li    a2, 2                     ; ...
        call  ppi_one                   ; ...
        li    a0, m_file                ; ...
        li    a1, 8                     ; ...
        li    a2, 3                     ; ...
        call  ppi_one                   ; ...
        jalr  zero, gp, lv0-R           ; done
; ppi_one(a0 = name, a1 = length, a2 = kind): a macro record of that kind  (leaf)
ppi_one:
        addi  sp, sp, -16               ; ...
        sd    ra, 0(sp)                 ; ...
        sd    a2, 8(sp)                 ; ...
        jalr  ra, gp, intern-R          ; ...
        addi  a0, a0, ID_MAC            ; its record is the next free one
        ld    a1, mac_top(zero)         ; ...
        jalr  ra, gp, far_sw-R          ; ...
        ld    a0, mac_top(zero)         ; a header with only the kind
        ld    a1, 8(sp)                 ; ...
        jalr  ra, gp, far_sd-R          ; ...
        ld    t0, mac_top(zero)         ; ...
        addi  t0, t0, 16                ; ...
        sd    t0, mac_top(zero)         ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; done

; pp_define(): #define NAME body, #define NAME(params) body
PD_SPACE = 1                            ; s5 bits: blanks were skipped since the last output
PD_NOSP  = 2                            ; no space before the next output (after ##)
PD_HASH  = 4                            ; a # waits for its parameter
PD_ANY   = 8                            ; something was output
pp_define:
        jalr  t6, gp, ent6-R            ; s1 = name's record, s2 = parameters, s3 = variadic, s4 = character, s5 = state, s6 = scratch
        la    t6, pp_word           ; the name
        xcall ra, c0, t6                ; ...
        bnez  a0, pdf_n                 ; ...
pdf_bad:
        li    a0, m_ppdef               ; ...
        jalr  zero, gp, error-R         ; ...
pdf_n:
        mv    a1, a0                    ; ...
        li    a0, TB                    ; ...
        jalr  ra, gp, intern-R          ; ...
        mv    s1, a0                    ; ...
        li    s2, 0                     ; ...
        li    s3, 0                     ; ...
        li    s6, 0                     ; s6 = kind: object-like
        jalr  ra, gp, nextc-R           ; a ( right after the name: parameters
        li    t0, '('                   ; ...
        beq   a0, t0, pdf_par           ; ...
        bltz  a0, pdf_body              ; ...
        ld    t1, in_pos(zero)          ; (not ours)
        addi  t1, t1, -1                ; ...
        sd    t1, in_pos(zero)          ; ...
        j     pdf_body                  ; ...
pdf_par:
        li    s6, 1                     ; function-like
pdf_p:
        la    t6, pp_word           ; a parameter's name
        xcall ra, c0, t6                ; ...
        beqz  a0, pdf_pd                ; ...
        mv    a1, a0                    ; ...
        li    a0, TB                    ; ...
pdf_padd:
        jalr  ra, gp, intern-R          ; ...
        slti  t0, s2, MAXPAR            ; ...
        beqz  t0, pdf_bad               ; ...
        slli  t0, s2, 3                 ; ...
        sd    a0, PARM(t0)              ; ...
        addi  s2, s2, 1                 ; ...
        j     pdf_pn                    ; ...
pdf_pd:
        la    t6, pp_blank          ; ) or ...
        xcall ra, c0, t6                ; ...
        li    t0, ')'                   ; ...
        beq   a0, t0, pdf_body          ; ...
        li    t0, '.'                   ; ...
        bne   a0, t0, pdf_bad           ; ...
        jalr  ra, gp, nextc-R           ; (the other two dots)
        jalr  ra, gp, nextc-R           ; ...
        li    s3, 1                     ; the rest of the arguments are __VA_ARGS__
        li    a0, m_va                  ; ...
        li    a1, 11                    ; ...
        j     pdf_padd                  ; ...
pdf_pn:
        la    t6, pp_blank          ; , or )
        xcall ra, c0, t6                ; ...
        li    t0, ','                   ; ...
        beq   a0, t0, pdf_p             ; ...
        li    t0, ')'                   ; ...
        bne   a0, t0, pdf_bad           ; ...
pdf_body:
        ld    a0, mac_top(zero)         ; the body is written after the header
        addi  a0, a0, MC_BODY           ; ...
        jalr  ra, gp, wb_open-R         ; ...
        li    s5, 0                     ; ...
pdf_l:
        la    t6, pp_c              ; a character of the line, comments removed
        xcall ra, c0, t6                ; ...
        mv    s4, a0                    ; ...
        bltz  s4, pdf_end               ; ...
        li    t0, 10                    ; ...
        beq   s4, t0, pdf_end           ; ...
        sltiu t0, s4, 128               ; ...
        beqz  t0, pdf_ch                ; ...
        lbu   t0, CC(s4)                ; ...
        andi  t1, t0, CL_SP             ; a blank: at most one space, later
        beqz  t1, pdf_nb                ; ...
        ori   s5, s5, PD_SPACE          ; ...
        j     pdf_l                     ; ...
pdf_nb:
        andi  t1, t0, CL_ID1            ; a name: maybe a parameter
        bnez  t1, pdf_id                ; ...
        andi  t1, t0, CL_DIG            ; a number: copied whole, its letters are not names
        bnez  t1, pdf_num               ; ...
        li    t0, '#'                   ; # and ##
        beq   s4, t0, pdf_hash          ; ...
        li    t0, '"'                   ; a literal: copied whole
        beq   s4, t0, pdf_lit           ; ...
        li    t0, 39                    ; ...
        beq   s4, t0, pdf_lit           ; ...
pdf_ch:
        call  pdf_sp                    ; an ordinary character
        mv    a0, s4                    ; ...
        jalr  ra, gp, wb_put-R          ; ...
        j     pdf_l                     ; ...
pdf_num:
        call  pdf_sp                    ; ...
pdf_nl:
        mv    a0, s4                    ; ...
        jalr  ra, gp, wb_put-R          ; ...
        jalr  ra, gp, nextc-R           ; ...
        mv    s4, a0                    ; ...
        sltiu t0, s4, 128               ; ...
        beqz  t0, pdf_nu                ; ...
        li    t0, '.'                   ; ...
        beq   s4, t0, pdf_nl            ; ...
        lbu   t0, CC(s4)                ; ...
        andi  t0, t0, CL_ID             ; ...
        bnez  t0, pdf_nl                ; ...
pdf_nu:
        bltz  s4, pdf_l                 ; the character after it is not the number's
        ld    t1, in_pos(zero)          ; ...
        addi  t1, t1, -1                ; ...
        sd    t1, in_pos(zero)          ; ...
        j     pdf_l                     ; ...
pdf_lit:
        call  pdf_sp                    ; ...
        mv    s6, s6                    ; (s6 is the kind; the quote is in s4)
        addi  sp, sp, -8                ; the quote that closes it
        sd    s4, 0(sp)                 ; ...
pdf_ll:
        mv    a0, s4                    ; ...
        jalr  ra, gp, wb_put-R          ; ...
        jalr  ra, gp, nextc-R           ; ...
        mv    s4, a0                    ; ...
        bltz  s4, pdf_le                ; ...
        li    t0, 10                    ; (a literal ends on its line)
        beq   s4, t0, pdf_lnl           ; ...
        li    t0, 92                    ; a backslash takes the next character with it
        bne   s4, t0, pdf_lq            ; ...
        mv    a0, s4                    ; ...
        jalr  ra, gp, wb_put-R          ; ...
        jalr  ra, gp, nextc-R           ; ...
        mv    s4, a0                    ; ...
        j     pdf_ll                    ; ...
pdf_lq:
        ld    t0, 0(sp)                 ; ...
        bne   s4, t0, pdf_ll            ; ...
        mv    a0, s4                    ; the closing quote
        jalr  ra, gp, wb_put-R          ; ...
pdf_le:
        addi  sp, sp, 8                 ; ...
        j     pdf_l                     ; ...
pdf_lnl:
        ld    t1, in_pos(zero)          ; (the newline stays)
        addi  t1, t1, -1                ; ...
        sd    t1, in_pos(zero)          ; ...
        j     pdf_le                    ; ...
pdf_hash:
        jalr  ra, gp, nextc-R           ; ## ?
        li    t0, '#'                   ; ...
        bne   a0, t0, pdf_h1            ; ...
        li    a0, MK_CAT                ; ##: no space on either side
        jalr  ra, gp, wb_put-R          ; ...
        andi  s5, s5, PD_ANY            ; ...
        ori   s5, s5, PD_NOSP           ; ...
        j     pdf_l                     ; ...
pdf_h1:
        bltz  a0, pdf_h2                ; a single #
        ld    t1, in_pos(zero)          ; ...
        addi  t1, t1, -1                ; ...
        sd    t1, in_pos(zero)          ; ...
pdf_h2:
        beqz  s6, pdf_ch                ; in an object-like macro it is a character
        call  pdf_sp                    ; in a function-like one it makes a string of the
        ori   s5, s5, PD_HASH | PD_NOSP ;   parameter that follows
        j     pdf_l                     ; ...
pdf_id:
        ld    t1, in_pos(zero)          ; the whole name -> TB
        addi  t1, t1, -1                ; ...
        sd    t1, in_pos(zero)          ; ...
        la    t6, pp_word           ; ...
        xcall ra, c0, t6                ; ...
        mv    a1, a0                    ; ...
        li    a0, TB                    ; ...
        jalr  ra, gp, intern-R          ; ...
        li    t0, 0                     ; a parameter?
pdf_pf:
        bge   t0, s2, pdf_notp          ; ...
        slli  t1, t0, 3                 ; ...
        ld    t1, PARM(t1)              ; ...
        beq   t1, a0, pdf_isp           ; ...
        addi  t0, t0, 1                 ; ...
        j     pdf_pf                    ; ...
pdf_isp:
        addi  s4, t0, MK_PAR            ; its marker (the string marker after #)
        andi  t1, s5, PD_HASH           ; ...
        beqz  t1, pdf_mk                ; ...
        addi  s4, t0, MK_STR            ; ...
        andi  s5, s5, PD_ANY            ; ...
        j     pdf_mk2                   ; ...
pdf_mk:
        call  pdf_sp                    ; ...
pdf_mk2:
        mv    a0, s4                    ; ...
        jalr  ra, gp, wb_put-R          ; ...
        ori   s5, s5, PD_ANY            ; ...
        j     pdf_l                     ; ...
pdf_notp:
        andi  t1, s5, PD_HASH           ; (a # before something that is no parameter: kept)
        beqz  t1, pdf_idsp              ; ...
        andi  s5, s5, PD_ANY            ; ...
        li    a0, '#'                   ; ...
        jalr  ra, gp, wb_put-R          ; ...
        j     pdf_idc                   ; ...
pdf_idsp:
        call  pdf_sp                    ; ...
pdf_idc:
        li    s4, TB                    ; the name as it is
pdf_idl:
        lbu   a0, 0(s4)                 ; ...
        beqz  a0, pdf_l                 ; ...
        jalr  ra, gp, wb_put-R          ; ...
        addi  s4, s4, 1                 ; ...
        j     pdf_idl                   ; ...
pdf_end:
        jalr  ra, gp, wb_close-R        ; a0 = the end of the body
        mv    s4, a0                    ; ...
        ld    t0, mac_top(zero)         ; the header: kind, parameters, variadic, length
        addi  t1, t0, MC_BODY           ; ...
        sub   t1, s4, t1                ; ...
        slli  a1, t1, 32                ; ...
        or    a1, a1, s6                ; ...
        slli  t2, s2, 16                ; ...
        or    a1, a1, t2                ; ...
        slli  t2, s3, 24                ; ...
        or    a1, a1, t2                ; ...
        mv    a0, t0                    ; ...
        jalr  ra, gp, far_sd-R          ; ...
        addi  a0, s1, ID_MAC            ; the name is this macro now
        ld    a1, mac_top(zero)         ; ...
        jalr  ra, gp, far_sw-R          ; ...
        addi  s4, s4, 7                 ; the next record
        srli  s4, s4, 3                 ; ...
        slli  s4, s4, 3                 ; ...
        li    t0, F_MACEND - 4096       ; ...
        bltu  s4, t0, pdf_ok            ; ...
        li    a0, m_ppbig               ; ...
        jalr  zero, gp, error-R         ; ...
pdf_ok:
        sd    s4, mac_top(zero)         ; ...
        jalr  zero, gp, lv6-R           ; done
; pdf_sp: before an output: the one space that stands for the blanks skipped  (leaf)
pdf_sp:
        andi  t0, s5, PD_SPACE | PD_NOSP | PD_ANY ; a space only between two outputs
        ori   s5, s5, PD_ANY            ; ...
        andi  s5, s5, PD_ANY | PD_HASH  ; ...
        addi  t0, t0, -(PD_SPACE | PD_ANY) ; ...
        bnez  t0, pds_ret               ; ...
        mv    t5, ra                    ; ...
        li    a0, ' '                   ; ...
        jalr  ra, gp, wb_put-R          ; (wb_put keeps t5)
        mv    ra, t5                    ; ...
pds_ret:
        ret                             ; done

        .align 4096                     ; ---- unit: pp3 ----
u_pp3:
; xh_room(a0 = the end of what was written to the expansion heap): it becomes
; the heap's top, rounded up to a word  (leaf, no frame)
xh_room:
        addi  a0, a0, 7                 ; ...
        srli  a0, a0, 3                 ; ...
        slli  a0, a0, 3                 ; ...
        li    t0, F_XHEND - 2048        ; ...
        bltu  a0, t0, xhr_ok            ; ...
        li    a0, m_ppbig               ; ...
        jalr  zero, gp, error-R         ; ...
xhr_ok:
        sd    a0, xh_top(zero)          ; ...
        ret                             ; done

; pp_expand() -> a0 = 1 if the macro tk_mac (whose name was just scanned) is
; being read now, 0 if the name stays an identifier (the macro is being
; expanded already, or it takes arguments and no ( follows)
pp_expand:
        jalr  t6, gp, ent6-R            ; s1 = macro record, s2 = arguments, s3 = heap mark, s4 = first ARGS entry, s5, s6 = scratch
        ld    s1, tk_mac(zero)          ; ...
        ld    s3, xh_top(zero)          ; ...
        li    t0, MH                    ; its header
        li    t1, 16                    ; ...
        tget  tg12, t0, c0, s1, t1      ; ...
        lbu   t0, MH+MC_BUSY(zero)      ; being expanded: not again
        bnez  t0, pxp_no                ; ...
        lbu   t0, MH+MC_KIND(zero)      ; ...
        li    t1, 1                     ; ...
        beq   t0, t1, pxp_fn            ; function-like
        bgtu  t0, t1, pxp_bi            ; built in
        lwu   t1, MH+MC_LEN(zero)       ; object-like: read its body
        addi  a0, s1, MC_BODY           ; ...
        add   a1, a0, t1                ; ...
        j     pxp_push                  ; ...
pxp_no:
        li    a0, 0                     ; ...
        jalr  zero, gp, lv6-R           ; ...
pxp_bi:
        mv    a0, s3                    ; __LINE__, __FILE__: a text made now
        jalr  ra, gp, wb_open-R         ; ...
        lbu   t0, MH+MC_KIND(zero)      ; ...
        li    t1, 2                     ; ...
        bne   t0, t1, pxp_file          ; ...
        ld    s5, line(zero)            ; the line, in decimal
        li    s6, 1                     ; s6 = the highest power of ten in it
pxp_lp:
        li    t0, 10                    ; ...
        mul   t1, s6, t0                ; ...
        bgtu  t1, s5, pxp_ld            ; ...
        mv    s6, t1                    ; ...
        j     pxp_lp                    ; ...
pxp_ld:
        divu  a0, s5, s6                ; a digit
        remu  s5, s5, s6                ; ...
        addi  a0, a0, '0'               ; ...
        jalr  ra, gp, wb_put-R          ; ...
        li    t0, 10                    ; ...
        divu  s6, s6, t0                ; ...
        bnez  s6, pxp_ld                ; ...
        j     pxp_bie                   ; ...
pxp_file:
        li    a0, '"'                   ; the file's name as a string
        jalr  ra, gp, wb_put-R          ; ...
        ld    s5, fname(zero)           ; ...
pxp_fl:
        lbu   a0, 0(s5)                 ; ...
        beqz  a0, pxp_fe                ; ...
        jalr  ra, gp, wb_put-R          ; ...
        addi  s5, s5, 1                 ; ...
        j     pxp_fl                    ; ...
pxp_fe:
        li    a0, '"'                   ; ...
        jalr  ra, gp, wb_put-R          ; ...
pxp_bie:
        jalr  ra, gp, wb_close-R        ; ...
        mv    s5, a0                    ; ...
        call  xh_room                   ; ...
        mv    a0, s3                    ; read it (no macro stays busy for it)
        mv    a1, s5                    ; ...
        li    a2, 2                     ; ...
        li    a3, 0                     ; ...
        mv    a4, s3                    ; ...
        jalr  ra, gp, in_push-R         ; ...
        li    a0, 1                     ; ...
        jalr  zero, gp, lv6-R           ; ...
pxp_fn:
        jalr  ra, gp, nextc-R           ; a ( must follow, after any blanks and newlines
        bltz  a0, pxp_no                ; ...
        li    t0, '('                   ; ...
        beq   a0, t0, pxp_args          ; ...
        sltiu t0, a0, 128               ; ...
        beqz  t0, pxp_nop               ; ...
        li    t0, 10                    ; ...
        bne   a0, t0, pxp_fb            ; ...
        ld    t1, in_kind(zero)         ; (a newline of a file counts)
        addi  t1, t1, -1                ; ...
        bnez  t1, pxp_fn                ; ...
        ld    t1, line(zero)            ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, line(zero)            ; ...
        j     pxp_fn                    ; ...
pxp_fb:
        lbu   t0, CC(a0)                ; ...
        andi  t0, t0, CL_SP             ; ...
        bnez  t0, pxp_fn                ; ...
pxp_nop:
        ld    t1, in_pos(zero)          ; something else: the name is just a name
        addi  t1, t1, -1                ; ...
        sd    t1, in_pos(zero)          ; ...
        j     pxp_no                    ; ...
pxp_args:
        la    t6, pp_collect            ; the arguments as written -> ARGS[s4 ..], s2 = how many
        xcall ra, c0, t6                ; ...
        li    t0, MH                    ; (the header again: collecting may have expanded nothing,
        li    t1, 16                    ;  but MH is shared with nested expansions below)
        tget  tg12, t0, c0, s1, t1      ; ...
        lbu   t0, MH+MC_NPAR(zero)      ; the right number?
        beq   s2, t0, pxp_exp           ; ...
        lbu   t1, MH+MC_VAR(zero)       ; one short of a variadic macro: an empty last one
        beqz  t1, pxp_cnt               ; ...
        addi  t2, s2, 1                 ; ...
        bne   t2, t0, pxp_cnt           ; ...
        add   t2, s4, s2                ; ...
        slli  t2, t2, 5                 ; ...
        ld    t3, xh_top(zero)          ; ...
        sd    t3, ARGS(t2)              ; ...
        sd    t3, ARGS+8(t2)            ; ...
        addi  s2, s2, 1                 ; ...
        j     pxp_exp                   ; ...
pxp_cnt:
        li    a0, m_ppargs              ; ...
        li    a1, 0                     ; ...
        jalr  zero, gp, error2-R        ; ...
pxp_exp:
        add   t0, s4, s2                ; our entries of ARGS are taken
        sd    t0, args_top(zero)        ; ...
        li    s5, 0                     ; expand each argument
pxp_el:
        bge   s5, s2, pxp_sub           ; ...
        add   a0, s4, s5                ; ...
        la    t6, pp_arg                ; ...
        xcall ra, c0, t6                ; ...
        addi  s5, s5, 1                 ; ...
        j     pxp_el                    ; ...
pxp_sub:
        li    t0, MH                    ; (the header again: expanding the arguments used MH)
        li    t1, 16                    ; ...
        tget  tg12, t0, c0, s1, t1      ; ...
        mv    a0, s1                    ; the body with the arguments in place -> the heap
        mv    a1, s4                    ; ...
        la    t6, pp_subst              ; a0 = start, a1 = end
        xcall ra, c0, t6                ; ...
        sd    s4, args_top(zero)        ; ...
pxp_push:
        mv    s5, a0                    ; ...
        mv    s6, a1                    ; ...
        li    t0, MH                    ; the macro is busy while its text is read
        li    t1, 8                     ; ...
        tget  tg12, t0, c0, s1, t1      ; ...
        li    t2, 1                     ; ...
        sb    t2, MH+MC_BUSY(zero)      ; ...
        tput  tg12, t0, c0, s1, t1      ; ...
        mv    a0, s5                    ; ...
        mv    a1, s6                    ; ...
        li    a2, 2                     ; ...
        mv    a3, s1                    ; ...
        mv    a4, s3                    ; ...
        jalr  ra, gp, in_push-R         ; ...
        li    a0, 1                     ; ...
        jalr  zero, gp, lv6-R           ; done

; pp_collect(): the ( of a macro call was read: copy its arguments as written
; to the expansion heap; the caller's s4 = its first ARGS entry, s2 = their number
pp_collect:
        jalr  t6, gp, ent0-R            ; (s5 = depth of parentheses, s6 = character: the caller's to lose)
        ld    s4, args_top(zero)        ; ...
        li    s2, 0                     ; ...
        li    s5, 0                     ; ...
        ld    a0, xh_top(zero)          ; ...
        slli  t0, s4, 5                 ; ...
        sd    a0, ARGS(t0)              ; ...
        jalr  ra, gp, wb_open-R         ; ...
pco_l:
        jalr  ra, gp, nextc-R           ; ...
        mv    s6, a0                    ; ...
        bgez  s6, pco_c                 ; ...
        li    a0, m_eof                 ; ...
        jalr  zero, gp, error-R         ; ...
pco_c:
        li    t0, 10                    ; a newline is a space (and counts, in a file)
        bne   s6, t0, pco_p             ; ...
        li    s6, ' '                   ; ...
        ld    t1, in_kind(zero)         ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, pco_put               ; ...
        ld    t1, line(zero)            ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, line(zero)            ; ...
        j     pco_put                   ; ...
pco_p:
        li    t0, '('                   ; ...
        bne   s6, t0, pco_rp            ; ...
        addi  s5, s5, 1                 ; ...
        j     pco_put                   ; ...
pco_rp:
        li    t0, ')'                   ; ...
        bne   s6, t0, pco_cm            ; ...
        beqz  s5, pco_end               ; the call's own )
        addi  s5, s5, -1                ; ...
        j     pco_put                   ; ...
pco_cm:
        li    t0, ','                   ; a comma of the call separates arguments,
        bne   s6, t0, pco_q             ; ...
        bnez  s5, pco_put               ; ...
        lbu   t0, MH+MC_VAR(zero)       ;   unless the variadic parameter has been reached
        beqz  t0, pco_sep               ; ...
        lbu   t0, MH+MC_NPAR(zero)      ; ...
        addi  t0, t0, -1                ; ...
        bge   s2, t0, pco_put           ; ...
pco_sep:
        ld    t1, wb_pos(zero)          ; ...
        add   t0, s4, s2                ; ...
        slli  t0, t0, 5                 ; ...
        sd    t1, ARGS+8(t0)            ; this one ends
        sd    t1, ARGS+32(t0)           ; the next begins
        addi  s2, s2, 1                 ; ...
        add   t0, s4, s2                ; ...
        slti  t0, t0, NARGS - 1         ; ...
        bnez  t0, pco_l                 ; ...
        li    a0, m_ppbig               ; ...
        jalr  zero, gp, error-R         ; ...
pco_q:
        li    t0, '"'                   ; a literal is copied whole
        beq   s6, t0, pco_lit           ; ...
        li    t0, 39                    ; ...
        bne   s6, t0, pco_put           ; ...
pco_lit:
        addi  sp, sp, -8                ; the quote that closes it
        sd    s6, 0(sp)                 ; ...
pco_ll:
        mv    a0, s6                    ; ...
        jalr  ra, gp, wb_put-R          ; ...
        jalr  ra, gp, nextc-R           ; ...
        mv    s6, a0                    ; ...
        bltz  s6, pco_le                ; ...
        li    t0, 92                    ; a backslash takes the next character with it
        bne   s6, t0, pco_lq            ; ...
        mv    a0, s6                    ; ...
        jalr  ra, gp, wb_put-R          ; ...
        jalr  ra, gp, nextc-R           ; ...
        mv    s6, a0                    ; ...
        j     pco_ll                    ; ...
pco_lq:
        ld    t0, 0(sp)                 ; ...
        bne   s6, t0, pco_ll            ; ...
pco_le:
        addi  sp, sp, 8                 ; ...
        bltz  s6, pco_l                 ; ...
pco_put:
        mv    a0, s6                    ; ...
        jalr  ra, gp, wb_put-R          ; ...
        j     pco_l                     ; ...
pco_end:
        ld    t1, wb_pos(zero)          ; the last argument ends
        add   t0, s4, s2                ; ...
        slli  t0, t0, 5                 ; ...
        sd    t1, ARGS+8(t0)            ; ...
        addi  s2, s2, 1                 ; ...
        jalr  ra, gp, wb_close-R        ; ...
        call  xh_room                   ; ...
        li    s5, 0                     ; trim the blanks around each argument
pco_t:
        bge   s5, s2, pco_one           ; ...
        add   s6, s4, s5                ; ...
        slli  s6, s6, 5                 ; ...
pco_tl:
        ld    a0, ARGS(s6)              ; leading
        ld    t0, ARGS+8(s6)            ; ...
        bgeu  a0, t0, pco_tn            ; ...
        jalr  ra, gp, rb_get-R          ; ...
        li    t0, ' '                   ; ...
        beq   a0, t0, pco_tli           ; ...
        li    t0, 9                     ; ...
        bne   a0, t0, pco_tt            ; ...
pco_tli:
        ld    t0, ARGS(s6)              ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, ARGS(s6)              ; ...
        j     pco_tl                    ; ...
pco_tt:
        ld    a0, ARGS+8(s6)            ; trailing
        ld    t0, ARGS(s6)              ; ...
        bleu  a0, t0, pco_tn            ; ...
        addi  a0, a0, -1                ; ...
        jalr  ra, gp, rb_get-R          ; ...
        li    t0, ' '                   ; ...
        beq   a0, t0, pco_tti           ; ...
        li    t0, 9                     ; ...
        bne   a0, t0, pco_tn            ; ...
pco_tti:
        ld    t0, ARGS+8(s6)            ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, ARGS+8(s6)            ; ...
        j     pco_tt                    ; ...
pco_tn:
        addi  s5, s5, 1                 ; ...
        j     pco_t                     ; ...
pco_one:
        li    t0, 1                     ; "()" is no argument, not one empty argument,
        bne   s2, t0, pco_ret           ;   for a macro without parameters
        lbu   t0, MH+MC_NPAR(zero)      ; ...
        bnez  t0, pco_ret               ; ...
        slli  t0, s4, 5                 ; ...
        ld    t1, ARGS(t0)              ; ...
        ld    t2, ARGS+8(t0)            ; ...
        bne   t1, t2, pco_ret           ; ...
        li    s2, 0                     ; ...
pco_ret:
        jalr  zero, gp, lv0-R           ; done

; pp_arg(a0 = ARGS entry number): expand the argument's text; the result goes
; to the expansion heap and into the entry
pp_arg:
        jalr  t6, gp, ent4-R            ; s1 = entry's offset, s2 = XBUF mark, s3 = character, s4 = scratch
        slli  s1, a0, 5                 ; ...
        ld    s2, xb_top(zero)          ; ...
        ld    a0, ARGS(s1)              ; read the argument, and stop at its end
        ld    a1, ARGS+8(s1)            ; ...
        li    a2, 3                     ; ...
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        jalr  ra, gp, in_push-R         ; ...
par_l:
        jalr  ra, gp, nextc-R           ; ...
        mv    s3, a0                    ; ...
        bltz  s3, par_end               ; ...
        sltiu t0, s3, 128               ; ...
        beqz  t0, par_ch                ; ...
        lbu   t0, CC(s3)                ; ...
        andi  t1, t0, CL_ID1            ; a name: a macro is expanded
        bnez  t1, par_id                ; ...
        andi  t1, t0, CL_DIG            ; a number: copied whole
        bnez  t1, par_num               ; ...
        li    t0, '"'                   ; a literal: copied whole
        beq   s3, t0, par_lit           ; ...
        li    t0, 39                    ; ...
        beq   s3, t0, par_lit           ; ...
par_ch:
        mv    a0, s3                    ; ...
        call  par_put                   ; ...
        j     par_l                     ; ...
par_num:
        mv    a0, s3                    ; ...
        call  par_put                   ; ...
        jalr  ra, gp, nextc-R           ; ...
        mv    s3, a0                    ; ...
        sltiu t0, s3, 128               ; ...
        beqz  t0, par_unget             ; ...
        li    t0, '.'                   ; ...
        beq   s3, t0, par_num           ; ...
        lbu   t0, CC(s3)                ; ...
        andi  t0, t0, CL_ID             ; ...
        bnez  t0, par_num               ; ...
par_unget:
        bltz  s3, par_l                 ; ...
        ld    t1, in_pos(zero)          ; ...
        addi  t1, t1, -1                ; ...
        sd    t1, in_pos(zero)          ; ...
        j     par_l                     ; ...
par_lit:
        mv    s4, s3                    ; s4 = the quote that closes it
par_ll:
        mv    a0, s3                    ; ...
        call  par_put                   ; ...
        jalr  ra, gp, nextc-R           ; ...
        mv    s3, a0                    ; ...
        bltz  s3, par_l                 ; ...
        li    t0, 92                    ; ...
        bne   s3, t0, par_lq            ; ...
        mv    a0, s3                    ; ...
        call  par_put                   ; ...
        jalr  ra, gp, nextc-R           ; ...
        mv    s3, a0                    ; ...
        j     par_ll                    ; ...
par_lq:
        bne   s3, s4, par_ll            ; ...
        j     par_ch                    ; ...
par_id:
        li    s4, TB                    ; the name -> TB
par_il:
        sb    s3, 0(s4)                 ; ...
        addi  s4, s4, 1                 ; ...
        jalr  ra, gp, nextc-R           ; ...
        mv    s3, a0                    ; ...
        sltiu t0, s3, 128               ; ...
        beqz  t0, par_ie                ; ...
        lbu   t0, CC(s3)                ; ...
        andi  t0, t0, CL_ID             ; ...
        beqz  t0, par_ie                ; ...
        li    t0, TB + ID_MAXLEN        ; ...
        bltu  s4, t0, par_il            ; ...
        addi  s4, s4, -1                ; ...
        j     par_il                    ; ...
par_ie:
        sb    zero, 0(s4)               ; ...
        bltz  s3, par_look              ; ...
        ld    t1, in_pos(zero)          ; ...
        addi  t1, t1, -1                ; ...
        sd    t1, in_pos(zero)          ; ...
par_look:
        li    a0, TB                    ; a macro?
        addi  a1, s4, -TB               ; ...
        jalr  ra, gp, intern-R          ; ...
        lwu   t0, IDR+ID_MAC(zero)      ; ...
        beqz  t0, par_name              ; ...
        sd    t0, tk_mac(zero)          ; ...
        addi  sp, sp, -72               ; the name: an expansion inside uses TB
        li    t0, TB                    ; ...
        mv    t1, sp                    ; ...
        li    t2, 8                     ; ...
par_sv:
        ld    t3, 0(t0)                 ; ...
        sd    t3, 0(t1)                 ; ...
        addi  t0, t0, 8                 ; ...
        addi  t1, t1, 8                 ; ...
        addi  t2, t2, -1                ; ...
        bnez  t2, par_sv                ; ...
        la    t6, pp_expand             ; ...
        xcall ra, c0, t6                ; ...
        li    t0, TB                    ; ...
        mv    t1, sp                    ; ...
        li    t2, 8                     ; ...
par_rs:
        ld    t3, 0(t1)                 ; ...
        sd    t3, 0(t0)                 ; ...
        addi  t0, t0, 8                 ; ...
        addi  t1, t1, 8                 ; ...
        addi  t2, t2, -1                ; ...
        bnez  t2, par_rs                ; ...
        addi  sp, sp, 72                ; ...
        bnez  a0, par_l                 ; its text is read next
par_name:
        li    s4, TB                    ; not a macro (or not to be expanded): the name itself
par_nl:
        lbu   a0, 0(s4)                 ; ...
        beqz  a0, par_l                 ; ...
        call  par_put                   ; ...
        addi  s4, s4, 1                 ; ...
        j     par_nl                    ; ...
par_end:
        jalr  ra, gp, in_pop-R          ; the argument's text is behind us
        ld    a0, xh_top(zero)          ; what was gathered goes to the heap
        sd    a0, ARGS+16(s1)           ; ...
        jalr  ra, gp, wb_open-R         ; ...
        mv    s4, s2                    ; ...
par_cp:
        ld    t0, xb_top(zero)          ; ...
        bgeu  s4, t0, par_cpe           ; ...
        lbu   a0, XBUF(s4)              ; ...
        jalr  ra, gp, wb_put-R          ; ...
        addi  s4, s4, 1                 ; ...
        j     par_cp                    ; ...
par_cpe:
        jalr  ra, gp, wb_close-R        ; ...
        sd    a0, ARGS+24(s1)           ; ...
        call  xh_room                   ; ...
        sd    s2, xb_top(zero)          ; ...
        jalr  zero, gp, lv4-R           ; done
; par_put(a0 = character): append it to XBUF  (leaf, no frame)
par_put:
        ld    t0, xb_top(zero)          ; ...
        li    t1, XBSZ                  ; ...
        bltu  t0, t1, ppt_ok            ; ...
        li    a0, m_ppbig               ; ...
        jalr  zero, gp, error-R         ; ...
ppt_ok:
        sb    a0, XBUF(t0)              ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, xb_top(zero)          ; ...
        ret                             ; done

        .align 4096                     ; ---- unit: pp4 ----
u_pp4:
; pp_subst(a0 = macro record, a1 = its first ARGS entry) -> a0, a1 = start and
; end of the body with the arguments substituted, in the expansion heap
pp_subst:
        jalr  t6, gp, ent6-R            ; s1 = body cursor, s2 = body end, s3 = first entry, s4 = byte, s5 = quote / cursor, s6 = start
        mv    s3, a1                    ; ...
        addi  s1, a0, MC_BODY           ; ...
        lwu   t0, MH+MC_LEN(zero)       ; ...
        add   s2, s1, t0                ; ...
        ld    s6, xh_top(zero)          ; ...
        mv    a0, s6                    ; ...
        jalr  ra, gp, wb_open-R         ; ...
        li    s5, 0                     ; s5 = the quote of the literal we are inside, or 0
psb_l:
        bgeu  s1, s2, psb_end           ; ...
        mv    a0, s1                    ; ...
        jalr  ra, gp, rb_get-R          ; ...
        mv    s4, a0                    ; ...
        addi  s1, s1, 1                 ; ...
        beqz  s5, psb_out               ; inside a literal: copied, to its closing quote
        li    t0, 92                    ; ...
        bne   s4, t0, psb_lq            ; ...
        mv    a0, s4                    ; (a backslash takes the next byte with it)
        jalr  ra, gp, wb_put-R          ; ...
        mv    a0, s1                    ; ...
        jalr  ra, gp, rb_get-R          ; ...
        mv    s4, a0                    ; ...
        addi  s1, s1, 1                 ; ...
        j     psb_put                   ; ...
psb_lq:
        bne   s4, s5, psb_put           ; ...
        li    s5, 0                     ; ...
        j     psb_put                   ; ...
psb_out:
        li    t0, '"'                   ; a literal starts
        beq   s4, t0, psb_q             ; ...
        li    t0, 39                    ; ...
        bne   s4, t0, psb_mk            ; ...
psb_q:
        mv    s5, s4                    ; ...
        j     psb_put                   ; ...
psb_mk:
        sltiu t0, s4, MK_PAR            ; an ordinary byte
        bnez  t0, psb_put               ; ...
        li    t0, MK_CAT                ; ##: the pieces on its sides simply meet
        beq   s4, t0, psb_l             ; ...
        sltiu t0, s4, MK_STR            ; ...
        beqz  t0, psb_str               ; ...
        addi  t0, s4, -MK_PAR           ; a parameter: its argument, expanded, unless it is
        add   t0, t0, s3                ;   an operand of ##
        slli  s4, t0, 5                 ; ...
        addi  a0, s1, -2                ; (## before it?)
        call  psb_iscat                 ; ...
        bnez  a0, psb_raw               ; ...
        mv    a0, s1                    ; (## after it?)
        bgeu  a0, s2, psb_xp            ; ...
        jalr  ra, gp, rb_get-R          ; ...
        addi  a0, a0, -MK_CAT           ; ...
        beqz  a0, psb_raw               ; ...
psb_xp:
        ld    a0, ARGS+16(s4)           ; ...
        ld    a1, ARGS+24(s4)           ; ...
        j     psb_copy                  ; ...
psb_raw:
        ld    a0, ARGS(s4)              ; ...
        ld    a1, ARGS+8(s4)            ; ...
psb_copy:
        addi  sp, sp, -16               ; copy that text
        sd    a0, 0(sp)                 ; ...
        sd    a1, 8(sp)                 ; ...
psb_cl:
        ld    a0, 0(sp)                 ; ...
        ld    t0, 8(sp)                 ; ...
        bgeu  a0, t0, psb_ce            ; ...
        addi  t0, a0, 1                 ; ...
        sd    t0, 0(sp)                 ; ...
        jalr  ra, gp, rb_get-R          ; ...
        jalr  ra, gp, wb_put-R          ; ...
        j     psb_cl                    ; ...
psb_ce:
        addi  sp, sp, 16                ; ...
        j     psb_l                     ; ...
psb_str:
        addi  t0, s4, -MK_STR           ; # parameter: the argument as written, as a string
        add   t0, t0, s3                ; ...
        slli  s4, t0, 5                 ; ...
        li    a0, '"'                   ; ...
        jalr  ra, gp, wb_put-R          ; ...
        addi  sp, sp, -24               ; cursor, end, the quote of a literal inside it
        ld    t0, ARGS(s4)              ; ...
        sd    t0, 0(sp)                 ; ...
        ld    t0, ARGS+8(s4)            ; ...
        sd    t0, 8(sp)                 ; ...
        sd    zero, 16(sp)              ; ...
psb_sl:
        ld    a0, 0(sp)                 ; ...
        ld    t0, 8(sp)                 ; ...
        bgeu  a0, t0, psb_se            ; ...
        addi  t0, a0, 1                 ; ...
        sd    t0, 0(sp)                 ; ...
        jalr  ra, gp, rb_get-R          ; ...
        mv    s4, a0                    ; ...
        ld    t1, 16(sp)                ; inside a literal, " and \ get a backslash
        li    t0, '"'                   ; ...
        beq   s4, t0, psb_sq            ; ...
        li    t0, 39                    ; ...
        beq   s4, t0, psb_sa            ; ...
        li    t0, 92                    ; ...
        bne   s4, t0, psb_sp            ; ...
        beqz  t1, psb_sp                ; ...
        j     psb_sb                    ; ...
psb_sa:
        bnez  t1, psb_sa2               ; a ' opens a literal, or closes the one it opened
        sd    s4, 16(sp)                ; ...
        j     psb_sp                    ; ...
psb_sa2:
        bne   t1, s4, psb_sp            ; ...
        sd    zero, 16(sp)              ; ...
        j     psb_sp                    ; ...
psb_sq:
        bnez  t1, psb_sq2               ; a " opens a literal, or closes the one it opened
        sd    s4, 16(sp)                ; ...
        j     psb_sb                    ; ...
psb_sq2:
        bne   t1, s4, psb_sb            ; ...
        sd    zero, 16(sp)              ; ...
psb_sb:
        li    a0, 92                    ; ...
        jalr  ra, gp, wb_put-R          ; ...
psb_sp:
        mv    a0, s4                    ; ...
        jalr  ra, gp, wb_put-R          ; ...
        j     psb_sl                    ; ...
psb_se:
        addi  sp, sp, 24                ; ...
        li    a0, '"'                   ; ...
        jalr  ra, gp, wb_put-R          ; ...
        j     psb_l                     ; ...
psb_put:
        mv    a0, s4                    ; ...
        jalr  ra, gp, wb_put-R          ; ...
        j     psb_l                     ; ...
psb_end:
        jalr  ra, gp, wb_close-R        ; ...
        mv    s1, a0                    ; ...
        addi  a0, a0, 7                 ; the heap's new top
        srli  a0, a0, 3                 ; ...
        slli  a0, a0, 3                 ; ...
        sd    a0, xh_top(zero)          ; ...
        mv    a0, s6                    ; ...
        mv    a1, s1                    ; ...
        jalr  zero, gp, lv6-R           ; done
; psb_iscat(a0 = arena offset of the byte before the marker just read) -> a0 =
; 1 if there is such a byte in the body and it is ##  (leaf)
psb_iscat:
        addi  sp, sp, -8                ; ...
        sd    ra, 0(sp)                 ; ...
        addi  t1, s1, -1                ; the marker's own offset: is it the body's first byte?
        sub   t1, t1, s2                ; ...
        lwu   t2, MH+MC_LEN(zero)       ; ...
        add   t1, t1, t2                ; t1 = its index in the body
        beqz  t1, pic_no                ; ...
        jalr  ra, gp, rb_get-R          ; ...
        addi  a0, a0, -MK_CAT           ; ...
        seqz  a0, a0                    ; ...
        j     pic_ret                   ; ...
pic_no:
        li    a0, 0                     ; ...
pic_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; done
