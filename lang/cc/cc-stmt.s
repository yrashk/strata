; =============================================================================
; cc-stmt.s: statements and local declarations
; =============================================================================

        .data                           ; this unit's variables
cnt_target: .dword 0                    ; the address `continue` jumps back to (0: forward, through cnt_chain)
loop_depth: .dword 0                    ; loops and switches around the current statement

        .far                            ; code units
        .align 4096                     ; ---- unit: stmt1 ----
u_stmt1:
; g_jback(a0 = target): an unconditional jump to an address already known
g_jback:
        jalr  t6, gp, ent0-R            ; ...
        ld    t0, code_pc(zero)         ; ...
        sub   t0, a0, t0                ; ...
        srai  t0, t0, 2                 ; ...
        slli  t0, t0, 43                ; ...
        srli  t0, t0, 43                ; ...
        li    a0, OP_JAL << 26          ; ...
        or    a0, a0, t0                ; ...
        jalr  ra, gp, emit-R            ; ...
        jalr  zero, gp, lv0-R           ; done

; block_body(): { declarations and statements } in the current scope
block_body:
        jalr  t6, gp, ent0-R            ; ...
        li    a0, '{'                   ; ...
        la    t6, skip                  ; ...
        xcall ra, c0, t6                ; ...
blb_l:
        ld    t0, tok(zero)             ; ...
        li    t1, '}'                   ; ...
        beq   t0, t1, blb_end           ; ...
        beqz  t0, blb_eof               ; ...
        la    t6, stmt                  ; ...
        xcall ra, c0, t6                ; ...
        j     blb_l                     ; ...
blb_eof:
        li    a0, m_eof                 ; ...
        jalr  zero, gp, error-R         ; ...
blb_end:
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        jalr  zero, gp, lv0-R           ; done

; block(): a compound statement with a scope of its own
block:
        jalr  t6, gp, ent2-R            ; s1 = symbol table mark, s2 = frame mark
        ld    s1, sym_top(zero)         ; ...
        ld    s2, fr_cur(zero)          ; ...
        ld    t0, scope(zero)           ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, scope(zero)           ; ...
        la    t6, block_body            ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s1                    ; ...
        la    t6, scope_exit            ; ...
        xcall ra, c0, t6                ; ...
        sd    s2, fr_cur(zero)          ; its locals' room is free again
        ld    t0, scope(zero)           ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, scope(zero)           ; ...
        jalr  zero, gp, lv2-R           ; done

; cond_paren(): ( expression ) -> a0 = a chain of jumps taken when it is false
cond_paren:
        jalr  t6, gp, ent0-R            ; ...
        li    a0, '('                   ; ...
        la    t6, skip                  ; ...
        xcall ra, c0, t6                ; ...
        la    t6, expr                  ; ...
        xcall ra, c0, t6                ; ...
        li    a0, ')'                   ; ...
        la    t6, skip                  ; ...
        xcall ra, c0, t6                ; ...
        li    a0, 1                     ; ...
        li    a1, 0                     ; ...
        la    t6, g_tst                 ; ...
        xcall ra, c0, t6                ; ...
        jalr  zero, gp, lv0-R           ; done

; stmt(): one statement (or, in a block, one declaration)
stmt:
        jalr  t6, gp, ent4-R            ; s1 = token, s2 = frame mark, s3, s4 = jumps
        ld    s1, tok(zero)             ; ...
        ld    s2, fr_cur(zero)          ; temporaries of the statement are released at its end
        li    t0, '{'                   ; ...
        bne   s1, t0, st_if             ; ...
        la    t6, block                 ; ...
        xcall ra, c0, t6                ; ...
        j     st_ret                    ; ...
st_if:
        li    t0, K_IF                  ; if ( e ) s [ else s ]
        bne   s1, t0, st_loops          ; ...
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        la    t6, cond_paren            ; ...
        xcall ra, c0, t6                ; ...
        mv    s3, a0                    ; ...
        la    t6, stmt                  ; ...
        xcall ra, c0, t6                ; ...
        ld    t0, tok(zero)             ; ...
        li    t1, K_ELSE                ; ...
        bne   t0, t1, st_ifend          ; ...
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        la    t6, g_jmp                 ; over the else part
        xcall ra, c0, t6                ; ...
        mv    s4, a0                    ; ...
        mv    a0, s3                    ; which starts here
        ld    a1, code_pc(zero)         ; ...
        la    t6, g_resolve             ; ...
        xcall ra, c0, t6                ; ...
        mv    s3, s4                    ; ...
        la    t6, stmt                  ; ...
        xcall ra, c0, t6                ; ...
st_ifend:
        mv    a0, s3                    ; ...
        ld    a1, code_pc(zero)         ; ...
        la    t6, g_resolve             ; ...
        xcall ra, c0, t6                ; ...
        j     st_ret                    ; ...
st_loops:
        addi  t0, s1, -K_DO             ; do, for, while: in the next unit
        seqz  t0, t0                    ; ...
        addi  t1, s1, -K_FOR            ; ...
        seqz  t1, t1                    ; ...
        or    t0, t0, t1                ; ...
        addi  t1, s1, -K_WHILE          ; ...
        seqz  t1, t1                    ; ...
        or    t0, t0, t1                ; ...
        beqz  t0, st_return             ; ...
        la    t6, loop_stmt             ; ...
        xcall ra, c0, t6                ; ...
        j     st_ret                    ; ...
st_return:
        li    t0, K_RETURN              ; return [ e ] ;
        bne   s1, t0, st_break          ; ...
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        ld    t0, tok(zero)             ; ...
        li    t1, ';'                   ; ...
        beq   t0, t1, st_retj           ; ...
        la    t6, expr                  ; the value, as the function's type, in a0
        xcall ra, c0, t6                ; ...
        ld    t0, fn_ret(zero)          ; (a void function may return a void expression)
        lbu   t0, TY_KIND(t0)           ; ...
        beqz  t0, st_retv               ; ...
        ld    a0, vsp(zero)             ; ...
        ld    a1, fn_ret(zero)          ; ...
        la    t6, g_cast                ; ...
        xcall ra, c0, t6                ; ...
        ld    a0, vsp(zero)             ; ...
        li    a1, X_A0                  ; ...
        la    t6, g_into                ; ...
        xcall ra, c0, t6                ; ...
        ld    t0, vsp(zero)             ; ...
        addi  t0, t0, -VSZ              ; ...
        sd    t0, vsp(zero)             ; ...
        j     st_retj                   ; ...
st_retv:
        la    t6, vpop                  ; ...
        xcall ra, c0, t6                ; ...
st_retj:
        li    a0, ';'                   ; ...
        la    t6, skip                  ; ...
        xcall ra, c0, t6                ; ...
        la    t6, g_jmp                 ; to the epilogue
        xcall ra, c0, t6                ; ...
        ld    a1, fn_rchain(zero)       ; ...
        la    t6, g_link                ; ...
        xcall ra, c0, t6                ; ...
        sd    a0, fn_rchain(zero)       ; ...
        j     st_ret                    ; ...
st_break:
        li    t0, K_BREAK               ; break ;
        bne   s1, t0, st_cont           ; ...
        call  st_inloop                 ; ...
        la    t6, g_jmp                 ; ...
        xcall ra, c0, t6                ; ...
        ld    a1, brk_chain(zero)       ; ...
        la    t6, g_link                ; ...
        xcall ra, c0, t6                ; ...
        sd    a0, brk_chain(zero)       ; ...
        j     st_semi2                  ; ...
st_cont:
        li    t0, K_CONTINUE            ; continue ;
        bne   s1, t0, st_empty          ; ...
        call  st_inloop                 ; ...
        ld    a0, cnt_target(zero)      ; back to a known place, or forward through the chain
        beqz  a0, st_cfwd               ; ...
        la    t6, g_jback               ; ...
        xcall ra, c0, t6                ; ...
        j     st_semi2                  ; ...
st_cfwd:
        la    t6, g_jmp                 ; ...
        xcall ra, c0, t6                ; ...
        ld    a1, cnt_chain(zero)       ; ...
        la    t6, g_link                ; ...
        xcall ra, c0, t6                ; ...
        sd    a0, cnt_chain(zero)       ; ...
st_semi2:
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        j     st_semi                   ; ...
st_empty:
        li    t0, ';'                   ; ;
        beq   s1, t0, st_semi           ; ...
        la    t6, stmt_other            ; switch, goto, labels (not written yet): a0 = 1 if it was one
        xcall ra, c0, t6                ; ...
        bnez  a0, st_ret                ; ...
        la    t6, is_type               ; a declaration?
        xcall ra, c0, t6                ; ...
        beqz  a0, st_expr               ; ...
        la    t6, local_decl            ; ...
        xcall ra, c0, t6                ; ...
        jalr  zero, gp, lv4-R           ; (its objects keep their room)
st_expr:
        la    t6, expr                  ; expression ;
        xcall ra, c0, t6                ; ...
        la    t6, vpop                  ; ...
        xcall ra, c0, t6                ; ...
st_semi:
        li    a0, ';'                   ; ...
        la    t6, skip                  ; ...
        xcall ra, c0, t6                ; ...
st_ret:
        sd    s2, fr_cur(zero)          ; ...
        jalr  zero, gp, lv4-R           ; done
; st_inloop: break and continue need a loop around them (no frame)
st_inloop:
        ld    t0, loop_depth(zero)      ; ...
        bnez  t0, sil_ret               ; ...
        li    a0, m_brk                 ; ...
        jalr  zero, gp, error-R         ; ...
sil_ret:
        ret                             ; done

; stmt_other(): -> a0 = 0: not one of its statements
stmt_other:
        li    a0, 0                     ; ...
        xret  ra                        ; done

; loop_stmt(): while, do, for (the keyword is the current token)
loop_stmt:
        jalr  t6, gp, ent6-R            ; s1 = keyword, s2 = top, s3 = exit chain, s4 = jump / increment
        ld    s1, tok(zero)             ; s5 = symbol table mark, s6 = frame mark
        addi  sp, sp, -32               ; the enclosing loop's chains and target
        ld    t0, brk_chain(zero)       ; ...
        sd    t0, 0(sp)                 ; ...
        ld    t0, cnt_chain(zero)       ; ...
        sd    t0, 8(sp)                 ; ...
        ld    t0, cnt_target(zero)      ; ...
        sd    t0, 16(sp)                ; ...
        sd    zero, brk_chain(zero)     ; ...
        sd    zero, cnt_chain(zero)     ; ...
        ld    t0, loop_depth(zero)      ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, loop_depth(zero)      ; ...
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        li    t0, K_WHILE               ; ...
        bne   s1, t0, lp_do             ; ...
        ld    s2, code_pc(zero)         ; while ( e ) s: the top is the continue point
        sd    s2, cnt_target(zero)      ; ...
        la    t6, cond_paren            ; ...
        xcall ra, c0, t6                ; ...
        mv    s3, a0                    ; ...
        la    t6, stmt                  ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s2                    ; ...
        la    t6, g_jback               ; ...
        xcall ra, c0, t6                ; ...
        j     lp_end                    ; ...
lp_do:
        li    t0, K_DO                  ; ...
        bne   s1, t0, lp_for            ; ...
        ld    s2, code_pc(zero)         ; do s while ( e ) ;
        sd    zero, cnt_target(zero)    ; (continue goes forward, to the test)
        la    t6, stmt                  ; ...
        xcall ra, c0, t6                ; ...
        ld    a0, cnt_chain(zero)       ; ...
        ld    a1, code_pc(zero)         ; ...
        la    t6, g_resolve             ; ...
        xcall ra, c0, t6                ; ...
        li    a0, K_WHILE               ; ...
        la    t6, skip                  ; ...
        xcall ra, c0, t6                ; ...
        li    a0, '('                   ; ...
        la    t6, skip                  ; ...
        xcall ra, c0, t6                ; ...
        la    t6, expr                  ; ...
        xcall ra, c0, t6                ; ...
        li    a0, ')'                   ; ...
        la    t6, skip                  ; ...
        xcall ra, c0, t6                ; ...
        li    a0, 0                     ; back to the top while it is true
        li    a1, 0                     ; ...
        la    t6, g_tst                 ; ...
        xcall ra, c0, t6                ; ...
        mv    a1, s2                    ; ...
        la    t6, g_resolve             ; ...
        xcall ra, c0, t6                ; ...
        li    a0, ';'                   ; ...
        la    t6, skip                  ; ...
        xcall ra, c0, t6                ; ...
        li    s3, 0                     ; ...
        j     lp_end                    ; ...
lp_for:
        ld    s5, sym_top(zero)         ; for ( init ; e ; step ) s: a scope for a declaration
        ld    s6, fr_cur(zero)          ; ...
        ld    t0, scope(zero)           ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, scope(zero)           ; ...
        li    a0, '('                   ; ...
        la    t6, skip                  ; ...
        xcall ra, c0, t6                ; ...
        ld    t0, tok(zero)             ; the init part
        li    t1, ';'                   ; ...
        beq   t0, t1, lp_f1             ; ...
        la    t6, is_type               ; ...
        xcall ra, c0, t6                ; ...
        beqz  a0, lp_fi                 ; ...
        la    t6, local_decl            ; (it takes the ;)
        xcall ra, c0, t6                ; ...
        j     lp_f2                     ; ...
lp_fi:
        la    t6, expr                  ; ...
        xcall ra, c0, t6                ; ...
        la    t6, vpop                  ; ...
        xcall ra, c0, t6                ; ...
lp_f1:
        li    a0, ';'                   ; ...
        la    t6, skip                  ; ...
        xcall ra, c0, t6                ; ...
lp_f2:
        ld    s2, code_pc(zero)         ; the test
        li    s3, 0                     ; ...
        ld    t0, tok(zero)             ; ...
        li    t1, ';'                   ; ...
        beq   t0, t1, lp_f3             ; ...
        la    t6, expr                  ; ...
        xcall ra, c0, t6                ; ...
        li    a0, 1                     ; ...
        li    a1, 0                     ; ...
        la    t6, g_tst                 ; ...
        xcall ra, c0, t6                ; ...
        mv    s3, a0                    ; ...
lp_f3:
        li    a0, ';'                   ; ...
        la    t6, skip                  ; ...
        xcall ra, c0, t6                ; ...
        sd    s2, cnt_target(zero)      ; without a step, continue goes to the test
        ld    t0, tok(zero)             ; the step is read before the body but runs after it:
        li    t1, ')'                   ;   jump over it to the body, come back to it from the end
        beq   t0, t1, lp_f4             ; ...
        la    t6, g_jmp                 ; ...
        xcall ra, c0, t6                ; ...
        mv    s4, a0                    ; ...
        ld    t0, code_pc(zero)         ; ...
        sd    t0, cnt_target(zero)      ; ...
        la    t6, expr                  ; ...
        xcall ra, c0, t6                ; ...
        la    t6, vpop                  ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s2                    ; then the test again
        la    t6, g_jback               ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s4                    ; the body starts here
        ld    a1, code_pc(zero)         ; ...
        sub   a1, a1, s4                ; ...
        la    t6, g_setoff              ; ...
        xcall ra, c0, t6                ; ...
lp_f4:
        li    a0, ')'                   ; ...
        la    t6, skip                  ; ...
        xcall ra, c0, t6                ; ...
        ld    s2, cnt_target(zero)      ; (kept: the body's loops change it)
        la    t6, stmt                  ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s2                    ; ...
        la    t6, g_jback               ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s5                    ; the scope ends
        la    t6, scope_exit            ; ...
        xcall ra, c0, t6                ; ...
        sd    s6, fr_cur(zero)          ; ...
        ld    t0, scope(zero)           ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, scope(zero)           ; ...
lp_end:
        mv    a0, s3                    ; the exit
        ld    a1, code_pc(zero)         ; ...
        la    t6, g_resolve             ; ...
        xcall ra, c0, t6                ; ...
        ld    a0, brk_chain(zero)       ; ...
        ld    a1, code_pc(zero)         ; ...
        la    t6, g_resolve             ; ...
        xcall ra, c0, t6                ; ...
        ld    t0, 0(sp)                 ; the enclosing loop again
        sd    t0, brk_chain(zero)       ; ...
        ld    t0, 8(sp)                 ; ...
        sd    t0, cnt_chain(zero)       ; ...
        ld    t0, 16(sp)                ; ...
        sd    t0, cnt_target(zero)      ; ...
        addi  sp, sp, 32                ; ...
        ld    t0, loop_depth(zero)      ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, loop_depth(zero)      ; ...
        jalr  zero, gp, lv6-R           ; done

        .align 4096                     ; ---- unit: stmt2 ----
u_stmt2:
; local_decl(): a declaration in a block: objects in the frame, or static
; objects, typedefs and function declarations of block scope
local_decl:
        jalr  t6, gp, ent6-R            ; s1 = base type, s2 = storage class, s3 = type, s4 = identifier, s5 = symbol, s6 = frame mark
        la    t6, decl_spec             ; ...
        xcall ra, c0, t6                ; ...
        mv    s1, a0                    ; ...
        ld    s2, ds_class(zero)        ; ...
        ld    t0, tok(zero)             ; specifiers alone
        li    t1, ';'                   ; ...
        beq   t0, t1, lcd_semi          ; ...
lcd_l:
        sd    zero, d_name(zero)        ; a declarator
        mv    a0, s1                    ; ...
        la    t6, declarator            ; ...
        xcall ra, c0, t6                ; ...
        mv    s3, a0                    ; ...
        ld    s4, d_name(zero)          ; ...
        bnez  s4, lcd_cls               ; ...
        li    a0, m_expect              ; ...
        jalr  zero, gp, errtok-R        ; ...
lcd_cls:
        li    t0, K_TYPEDEF             ; ...
        bne   s2, t0, lcd_fn            ; ...
        mv    a0, s4                    ; ...
        li    a1, SC_TYPEDEF            ; ...
        mv    a2, s3                    ; ...
        la    t6, sym_decl              ; ...
        xcall ra, c0, t6                ; ...
        j     lcd_next                  ; ...
lcd_fn:
        lbu   t0, TY_KIND(s3)           ; a function declared in a block
        li    t1, TK_FUNC               ; ...
        bne   t0, t1, lcd_st            ; ...
        mv    a0, s4                    ; ...
        mv    a1, s3                    ; ...
        la    t6, func_decl             ; ...
        xcall ra, c0, t6                ; ...
        j     lcd_next                  ; ...
lcd_st:
        li    t0, K_STATIC              ; static and extern objects live in the data image
        beq   s2, t0, lcd_stat          ; ...
        li    t0, K_EXTERN              ; ...
        bne   s2, t0, lcd_auto          ; ...
lcd_stat:
        mv    a0, s4                    ; ...
        mv    a1, s3                    ; ...
        mv    a2, s2                    ; ...
        la    t6, static_var            ; ...
        xcall ra, c0, t6                ; ...
        j     lcd_next                  ; ...
lcd_auto:
        mv    a0, s4                    ; an automatic object
        li    a1, SC_AUTO               ; ...
        mv    a2, s3                    ; ...
        la    t6, sym_decl              ; ...
        xcall ra, c0, t6                ; ...
        mv    s5, a0                    ; ...
        li    s6, 0                     ; s6 = 1: the = has been read already
        ld    t0, tok(zero)             ; an initialiser may complete an array's type first
        li    t1, '='                   ; ...
        bne   t0, t1, lcd_room          ; ...
        lwu   t0, TY_SIZE(s3)           ; ...
        bnez  t0, lcd_room              ; ...
        mv    a0, s5                    ; ...
        la    t6, auto_init_size        ; (it reads the =)
        xcall ra, c0, t6                ; ...
        lhu   s3, SY_TYPE(s5)           ; ...
        li    s6, 1                     ; ...
lcd_room:
        lwu   a0, TY_SIZE(s3)           ; its room in the frame
        bnez  a0, lcd_al                ; ...
        li    a0, m_incomp              ; ...
        jalr  zero, gp, error-R         ; ...
lcd_al:
        lbu   a1, TY_ALIGN(s3)          ; ...
        la    t6, fr_alloc_x            ; ...
        xcall ra, c0, t6                ; ...
        sw    a0, SY_VAL(s5)            ; ...
        bnez  s6, lcd_ini               ; ...
        ld    t0, tok(zero)             ; = initialiser
        li    t1, '='                   ; ...
        bne   t0, t1, lcd_next          ; ...
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
lcd_ini:
        ld    s6, fr_cur(zero)          ; ...
        mv    a0, s5                    ; ...
        la    t6, auto_init             ; ...
        xcall ra, c0, t6                ; ...
        sd    s6, fr_cur(zero)          ; (the initialiser's temporaries are free again)
lcd_next:
        ld    t0, tok(zero)             ; ...
        li    t1, ','                   ; ...
        bne   t0, t1, lcd_semi          ; ...
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        j     lcd_l                     ; ...
lcd_semi:
        li    a0, ';'                   ; ...
        la    t6, skip                  ; ...
        xcall ra, c0, t6                ; ...
        jalr  zero, gp, lv6-R           ; done
