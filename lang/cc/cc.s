; =============================================================================
; cc.s: a C99 compiler for Strata, written in Strata assembly
; =============================================================================
;
; `cc file.c` reads C source and writes a StrataOS program image. The design
; (data model, calling convention, why there is no assembler pass and no
; linker) is in lang/cc/DESIGN.md; the state of the work in PLAN-cc.md.
;
; How the program is laid out
;   * The compiler is larger than the instruction store, so only this file's
;     code is resident (I-LS from 0x8000). Everything else is in 4 KiB *code
;     units* in the `.far` section, paged in by StrataOS on demand (xslot = 12,
;     as os/progs/units.s shows).
;   * A unit can be evicted while one of its functions waits for a call to
;     return, and it may come back in another slot. So code in units calls
;     code in units with `la t6, f` / `xcall ra, c0, t6` (a far link) and
;     returns with `xret ra`; a plain `call` is used only for a leaf of the
;     same unit that calls nothing outside it.
;   * Resident routines are leaves with respect to paging: they call no unit.
;     Unit code reaches them in one instruction, `jalr ra, gp, name-R(gp)`
;     with gp = R = 0x10000 (jal is pc-relative and a unit runs in any slot).
;   * A function in a unit starts with `jalr t6, gp, entN-R` (save ra and
;     s1..sN) and ends with `jalr zero, gp, lvN-R` (restore them, xret).
;
; Registers: a0..a7 arguments and results, t0..t6 scratch (t6 is the link of
; entN and the target of far calls), s1..s6 kept by callees, gp = R.
; Variables are in the D-LS below 0x8000, so `ld t0, name(zero)` reaches them.
;
; The arena (c0): the compiler's own code units from 0; then
F_LIB    = 0x20000                      ; cc.lib, as read from the disk
F_SRC    = 0x2C000                      ; source files, one after another (a stack)
F_SRCEND = 0x5C000                      ; ...
F_IDH    = 0x5C000                      ; identifier hash heads: 1024 words
F_ID     = 0x5E000                      ; identifier records
F_IDEND  = 0x68000                      ; ...
F_MAC    = 0x68000                      ; macro records and bodies
F_MACEND = 0x74000                      ; ...
F_FIX    = 0x74000                      ; fixups, 16 bytes each
F_FIXEND = 0x78000                      ; ...
F_XH     = 0x78000                      ; macro expansions in progress (a stack)
F_XHEND  = 0x7F000                      ; (the start-up block is at 0x7F000)
F_CODE   = 0x80000                      ; the image: code (I-LS from 0x8000, or code units)
F_DATA   = 0xA0000                      ; the image: D-LS from 0
F_RES    = 0xB0000                      ; the image: the resident library, when the code is paged
F_END    = 0xC0000                      ; ...

