        xret  ra                        ; ...
lv0:    ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        xret  ra                        ; ...

; ---- messages --------------------------------------------------------------------------
; eputs(a0 = string): write it to standard error
eputs:
        mv    a1, a0                    ; its length
        mv    a2, a0                    ; ...
eputs_l:
        lbu   t0, 0(a2)                 ; ...
        beqz  t0, eputs_w               ; ...
        addi  a2, a2, 1                 ; ...
        j     eputs_l                   ; ...
eputs_w:
        sub   a2, a2, a1                ; ...
        li    a0, 2                     ; stderr
        j     write                     ; write(2, string, length)

; eputn(a0 = number): write it in decimal to standard error
eputn:
        li    t0, NUMB + 23             ; digits backwards from the end
        sb    zero, 0(t0)               ; ...
        li    t2, 10                    ; ...
eputn_l:
        remu  t1, a0, t2                ; a digit
        divu  a0, a0, t2                ; ...
        addi  t1, t1, '0'               ; ...
        addi  t0, t0, -1                ; ...
        sb    t1, 0(t0)                 ; ...
        bnez  a0, eputn_l               ; ...
        mv    a0, t0                    ; ...
        j     eputs                     ; ...

; error(a0 = message), error2(a0 = message, a1 = more text or 0): print
; "file:line: message more" and end with status 1. Do not return.
error:
        li    a1, 0                     ; nothing more
error2:
        mv    s1, a0                    ; (nothing is kept: we never return)
        mv    s2, a1                    ; ...
        ld    a0, fname(zero)           ; the file
        beqz  a0, err_msg               ; (none yet)
        call  eputs                     ; ...
        li    a0, m_col1                ; ":"
        call  eputs                     ; ...
        ld    a0, line(zero)            ; the line
        call  eputn                     ; ...
        li    a0, m_colon               ; ": "
        call  eputs                     ; ...
err_msg:
        mv    a0, s1                    ; the message
        call  eputs                     ; ...
        beqz  s2, err_nl                ; and what it is about
        mv    a0, s2                    ; ...
        call  eputs                     ; ...
err_nl:
        li    t0, 10                    ; a newline
        sb    t0, NUMB(zero)            ; ...
        li    a0, 2                     ; ...
        li    a1, NUMB                  ; ...
        li    a2, 1                     ; ...
        call  write                     ; ...
        li    a0, 1                     ; status 1
        j     _exit                     ; ...

; errtok(a0 = message): the message, followed by the current token's spelling
errtok:
        mv    s1, a0                    ; ...
        ld    t0, tok(zero)             ; what kind of token?
        li    a1, m_eofn                ; ...
        beqz  t0, errtok_go             ; the end of the file
        li    a1, TB                    ; identifiers, numbers: as scanned
        slti  t1, t0, 128               ; a punctuator?
        beqz  t1, errtok_go             ; no
        sb    t0, TB(zero)              ; ...
        sb    zero, TB+1(zero)          ; ...
errtok_go:
        mv    a0, s1                    ; ...
        j     error2                    ; ...

; ---- the arena, a word at a time -----------------------------------------------------
; far_ld(a0 = arena offset, a multiple of 8) -> a0 = the word there
far_ld:
        li    t0, NUMB                  ; a scratch word
        li    t1, 8                     ; ...
        tget  tg12, t0, c0, a0, t1      ; ...
        ld    a0, NUMB(zero)            ; (waits for the tget)
        ret                             ; done
; far_sd(a0 = arena offset, a multiple of 8, a1 = word)
far_sd:
        sd    a1, NUMB+8(zero)          ; from a scratch word
        li    t0, NUMB + 8              ; ...
        li    t1, 8                     ; ...
        tput  tg12, t0, c0, a0, t1      ; ...
        ret                             ; done
; far_lw(a0 = arena offset, a multiple of 4) -> a0 = the 32-bit word there (zero-extended)
far_lw:
        andi  t2, a0, 4                 ; which half of its 8-byte word
        sub   a0, a0, t2                ; ...
        li    t0, NUMB                  ; ...
        li    t1, 8                     ; ...
        tget  tg12, t0, c0, a0, t1      ; ...
        lwu   a0, NUMB(t2)              ; ...
        ret                             ; done
; far_sw(a0 = arena offset, a multiple of 4, a1 = 32-bit word): read, modify, write
far_sw:
        andi  t2, a0, 4                 ; which half
        sub   a0, a0, t2                ; ...
        li    t0, NUMB                  ; ...
        li    t1, 8                     ; ...
        tget  tg12, t0, c0, a0, t1      ; ...
        sw    a1, NUMB(t2)              ; (waits for the tget)
        tput  tg12, t0, c0, a0, t1      ; ...
        ret                             ; done

; ---- far byte streams ---------------------------------------------------------------
; rb_get(a0 = arena offset) -> a0 = the byte there, through a 64-byte window
rb_get:
        ld    t0, rb_base(zero)         ; in the window?
        sub   t1, a0, t0                ; ...
        sltiu t2, t1, 64                ; ...
        bnez  t2, rb_hit                ; yes
        srli  t0, a0, 6                 ; load the 64 bytes around it
        slli  t0, t0, 6                 ; ...
        sd    t0, rb_base(zero)         ; ...
        li    t2, RB                    ; ...
        li    t3, 64                    ; ...
        tget  tg12, t2, c0, t0, t3      ; ...
        sub   t1, a0, t0                ; ...
rb_hit:
        lbu   a0, RB(t1)                ; (waits for a tget)
        ret                             ; done
; wb_open(a0 = arena offset): start writing bytes there
wb_open:
        sd    a0, wb_pos(zero)          ; ...
        andi  t0, a0, 63                ; in the middle of a window: keep what is before it
        beqz  t0, wb_o_ret              ; ...
        sub   t1, a0, t0                ; ...
        li    t2, WB                    ; ...
        li    t3, 64                    ; ...
        tget  tg12, t2, c0, t1, t3      ; ...
wb_o_ret:
        ret                             ; done
; wb_put(a0 = byte): append it
wb_put:
        ld    t0, wb_pos(zero)          ; ...
        andi  t1, t0, 63                ; ...
        sb    a0, WB(t1)                ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, wb_pos(zero)          ; ...
        andi  t1, t0, 63                ; the window is full?
        bnez  t1, wb_p_ret              ; no
        addi  t0, t0, -64               ; write it out
        li    t2, WB                    ; ...
        li    t3, 64                    ; ...
        tput  tg12, t2, c0, t0, t3      ; ...
wb_p_ret:
        ret                             ; done
; wb_close() -> a0 = the offset after the last byte; everything written is in the arena
wb_close:
        ld    a0, wb_pos(zero)          ; ...
        andi  t1, a0, 63                ; a partial window?
        beqz  t1, wb_c_ret              ; no
        sub   t0, a0, t1                ; write all 64 bytes (the tail is rewritten later)
        li    t2, WB                    ; ...
        li    t3, 64                    ; ...
        tput  tg12, t2, c0, t0, t3      ; ...
wb_c_ret:
        li    t0, -1                    ; the reader's window may be stale now
        sd    t0, rb_base(zero)         ; ...
        sd    t0, sw_base(zero)         ; and the source window
        ret                             ; done

; ---- source characters ------------------------------------------------------------------
; nextc() -> a0 = the next character of the input, or -1 at the end of the
; outermost file or of an argument being expanded. A finished macro expansion
; or included file is left behind silently.
nextc:
        ld    t0, in_pos(zero)          ; anything left of this text?
        ld    t1, in_end(zero)          ; ...
        bgeu  t0, t1, nc_end            ; no
        ld    t2, sw_base(zero)         ; in the window?
        sub   t3, t0, t2                ; ...
        sltiu t4, t3, SWSZ              ; ...
        beqz  t4, nc_load               ; no
        lbu   a0, SW(t3)                ; the character (waits for a tget)
        addi  t0, t0, 1                 ; ...
        sd    t0, in_pos(zero)          ; ...
        ret                             ; done
nc_load:
        srli  t2, t0, 3                 ; the window starts at its word
        slli  t2, t2, 3                 ; ...
        sd    t2, sw_base(zero)         ; ...
        li    t3, SW                    ; ...
        li    t4, SWSZ                  ; ...
        tget  tg13, t3, c0, t2, t4      ; ...
        j     nextc                     ; again
nc_end:
        ld    t0, in_kind(zero)         ; what ended?
        li    t1, 3                     ; an argument: its expander sees the end
        beq   t0, t1, nc_eof            ; ...
        ld    t2, in_sp(zero)           ; the outermost file: the end of the input
        beqz  t2, nc_eof                ; ...
        li    t1, 2                     ; a macro's expansion?
        bne   t0, t1, nc_file           ; no: an included file
        ld    t3, in_aux(zero)          ; the macro may be expanded again
        beqz  t3, nc_mfree              ; (a text with no macro behind it)
        li    t4, NUMB                  ; clear the "being expanded" flag: byte 1 of its record
        li    t5, 8                     ; ...
        tget  tg12, t4, c0, t3, t5      ; ...
        sb    zero, NUMB+1(zero)        ; ...
        tput  tg12, t4, c0, t3, t5      ; ...
nc_mfree:
        ld    t3, in_mark(zero)         ; its text is free again
        sd    t3, xh_top(zero)          ; ...
        j     nc_pop                    ; ...
nc_file:
        ld    t3, in_mark(zero)         ; the file's text is free again
        sd    t3, src_top(zero)         ; ...
        ld    t3, in_aux(zero)          ; back to the including file's line
        sd    t3, line(zero)            ; ...
        ld    t3, fname(zero)           ; and its name
        addi  t3, t3, -32               ; ...
        sd    t3, fname(zero)           ; ...
        li    t3, 1                     ; what follows starts a line
        sd    t3, bol(zero)             ; ...
nc_pop:
        addi  t2, t2, -1                ; pop the entry
        sd    t2, in_sp(zero)           ; ...
        li    t3, INSZ                  ; ...
        mul   t2, t2, t3                ; ...
        addi  t2, t2, INSTK             ; ...
        ld    t3, IN_POS(t2)            ; ...
        sd    t3, in_pos(zero)          ; ...
        ld    t3, IN_END(t2)            ; ...
        sd    t3, in_end(zero)          ; ...
        ld    t3, IN_KIND(t2)           ; ...
        sd    t3, in_kind(zero)         ; ...
        ld    t3, IN_AUX(t2)            ; ...
        sd    t3, in_aux(zero)          ; ...
        ld    t3, IN_MARK(t2)           ; ...
        sd    t3, in_mark(zero)         ; ...
        j     nextc                     ; continue there
nc_eof:
        li    a0, -1                    ; the end
        ret                             ; done

; in_pop(): go back to the text that was being read before the last in_push
in_pop:
        ld    t2, in_sp(zero)           ; ...
        addi  t2, t2, -1                ; ...
        sd    t2, in_sp(zero)           ; ...
        li    t3, INSZ                  ; ...
        mul   t2, t2, t3                ; ...
        addi  t2, t2, INSTK             ; ...
        ld    t3, IN_POS(t2)            ; ...
        sd    t3, in_pos(zero)          ; ...
        ld    t3, IN_END(t2)            ; ...
        sd    t3, in_end(zero)          ; ...
        ld    t3, IN_KIND(t2)           ; ...
        sd    t3, in_kind(zero)         ; ...
        ld    t3, IN_AUX(t2)            ; ...
        sd    t3, in_aux(zero)          ; ...
        ld    t3, IN_MARK(t2)           ; ...
        sd    t3, in_mark(zero)         ; ...
        ret                             ; done

; in_push(a0 = start, a1 = end, a2 = kind, a3 = aux, a4 = mark): read this text next
in_push:
        ld    t0, in_sp(zero)           ; a free entry?
        slti  t1, t0, NINCL             ; ...
        bnez  t1, inp_ok                ; ...
        li    a0, m_incl                ; nested too deeply
        j     error                     ; ...
inp_ok:
        addi  t1, t0, 1                 ; ...
        sd    t1, in_sp(zero)           ; ...
        li    t1, INSZ                  ; save what was being read
        mul   t0, t0, t1                ; ...
        addi  t0, t0, INSTK             ; ...
        ld    t1, in_pos(zero)          ; ...
        sd    t1, IN_POS(t0)            ; ...
        ld    t1, in_end(zero)          ; ...
        sd    t1, IN_END(t0)            ; ...
        ld    t1, in_kind(zero)         ; ...
        sd    t1, IN_KIND(t0)           ; ...
        ld    t1, in_aux(zero)          ; ...
        sd    t1, IN_AUX(t0)            ; ...
        ld    t1, in_mark(zero)         ; ...
        sd    t1, IN_MARK(t0)           ; ...
        sd    a0, in_pos(zero)          ; and switch
        sd    a1, in_end(zero)          ; ...
        sd    a2, in_kind(zero)         ; ...
        sd    a3, in_aux(zero)          ; ...
        sd    a4, in_mark(zero)         ; ...
        ret                             ; done

; ---- identifiers -----------------------------------------------------------------------
; intern(a0 = name in the D-LS, a1 = length) -> a0 = its record (arena offset);
; IDR holds a copy of the record (ID_NAME bytes of it, and the name)
intern:
        addi  sp, sp, -40               ; frame
        sd    ra, 32(sp)                ; ...
        sd    a0, 0(sp)                 ; the name
        sd    a1, 8(sp)                 ; its length
        li    t0, 5381                  ; hash: h = h * 33 + c
        add   t2, a0, a1                ; ...
in_hash:
        bgeu  a0, t2, in_hend           ; ...
        lbu   t1, 0(a0)                 ; ...
        slli  t3, t0, 5                 ; ...
        add   t0, t0, t3                ; ...
        add   t0, t0, t1                ; ...
        addi  a0, a0, 1                 ; ...
        j     in_hash                   ; ...
in_hend:
        andi  t0, t0, 1023              ; the chain's head
        slli  t0, t0, 3                 ; ...
        li    t1, F_IDH                 ; ...
        add   a0, t0, t1                ; ...
        sd    a0, 16(sp)                ; (kept: a new record is linked there)
        call  far_ld                    ; a0 = first record, or 0
        sd    a0, 24(sp)                ; (the old head)
in_chain:
        beqz  a0, in_new                ; not there
        li    t0, IDR                   ; the record -> IDR
        li    t1, 80                    ; (header and the longest name)
        tget  tg12, t0, c0, a0, t1      ; ...
        lbu   t1, IDR+ID_LEN(zero)      ; the same length?
        ld    t2, 8(sp)                 ; ...
        bne   t1, t2, in_next           ; no
        ld    t3, 0(sp)                 ; the same bytes?
        li    t4, IDR + ID_NAME         ; ...
        add   t2, t3, t2                ; ...
in_cmp:
        bgeu  t3, t2, in_ret            ; yes: found (a0 = the record)
        lbu   t5, 0(t3)                 ; ...
        lbu   t6, 0(t4)                 ; ...
        bne   t5, t6, in_next           ; ...
        addi  t3, t3, 1                 ; ...
        addi  t4, t4, 1                 ; ...
        j     in_cmp                    ; ...
in_next:
        lwu   a0, IDR+ID_NEXT(zero)     ; the next record of the chain
        j     in_chain                  ; ...
in_new:
        li    t0, IDR                   ; build the record in IDR
        ld    t1, 24(sp)                ; next = the old head
        sd    t1, 0(t0)                 ; (and no macro)
        sd    zero, 8(t0)               ; no symbol, tag, keyword
        ld    t2, 8(sp)                 ; the length
        sb    t2, ID_LEN(t0)            ; ...
        ld    t3, 0(sp)                 ; the name
        addi  t4, t0, ID_NAME           ; ...
        add   t5, t3, t2                ; ...
in_cp:
        bgeu  t3, t5, in_cpd            ; ...
        lbu   t6, 0(t3)                 ; ...
        sb    t6, 0(t4)                 ; ...
        addi  t3, t3, 1                 ; ...
        addi  t4, t4, 1                 ; ...
        j     in_cp                     ; ...
in_cpd:
        sb    zero, 0(t4)               ; (a zero after it, for messages)
        addi  t2, t2, ID_NAME + 8       ; record size: header, name, zero, whole words
        srli  t2, t2, 3                 ; ...
        slli  t2, t2, 3                 ; ...
        ld    a0, id_top(zero)          ; where it goes
        add   t3, a0, t2                ; ...
        li    t4, F_IDEND               ; room?
        bleu  t3, t4, in_room           ; ...
        li    a0, m_idfull              ; ...
        j     error                     ; ...
in_room:
        sd    t3, id_top(zero)          ; ...
        tput  tg12, t0, c0, a0, t2      ; IDR -> the arena
        sd    a0, 24(sp)                ; ...
        mv    a1, a0                    ; the chain's head is this record now
        ld    a0, 16(sp)                ; ...
        call  far_sd                    ; ...
        ld    a0, 24(sp)                ; the record
in_ret:
        ld    ra, 32(sp)                ; ...
        addi  sp, sp, 40                ; ...
        ret                             ; done

; id_set(a0 = identifier record, a1 = field offset ID_SYM or ID_TAG, a2 = value):
; change one 16-bit field of the record
id_set:
        addi  a0, a0, 8                 ; the word holding both
        li    t0, NUMB                  ; ...
        li    t1, 8                     ; ...
        tget  tg12, t0, c0, a0, t1      ; ...
        addi  a1, a1, -8                ; ...
        sh    a2, NUMB(a1)              ; (waits for the tget)
        tput  tg12, t0, c0, a0, t1      ; ...
        ret                             ; done
; id_name(a0 = identifier record) -> a0 = its name as a string in IDR
id_name:
        li    t0, IDR                   ; ...
        li    t1, 80                    ; ...
        tget  tg12, t0, c0, a0, t1      ; ...
        li    a0, IDR + ID_NAME         ; ...
        lbu   t0, 0(a0)                 ; (waits for the tget)
        ret                             ; done

; ---- the code image ---------------------------------------------------------------------
; emit(a0 = instruction word)
emit:
        ld    t0, nocode(zero)          ; outside a function, inside sizeof: nothing
        bnez  t0, emit_ret              ; ...
        ld    t0, code_pc(zero)         ; where it goes
        ld    t1, cw_base(zero)         ; in the window
        sub   t2, t0, t1                ; ...
        sw    a0, CW(t2)                ; ...
        addi  t0, t0, 4                 ; ...
        sd    t0, code_pc(zero)         ; ...
        addi  t2, t2, 4                 ; the window is full?
        slti  t3, t2, CWSZ              ; ...
        bnez  t3, emit_ret              ; no
cw_flush:                               ; write the window out and start the next one
        ld    t1, cw_base(zero)         ; ...
        ld    t3, code_org(zero)        ; its place in the arena
        sub   t3, t1, t3                ; ...
        li    t4, F_CODE                ; ...
        add   t3, t3, t4                ; ...
        li    t4, F_DATA                ; the image must not run into the data image
        bltu  t3, t4, cwf_ok            ; (-CWSZ: this window fits)
        li    a0, m_codefull            ; ...
        j     error                     ; ...
cwf_ok:
        li    t4, CW                    ; ...
        li    t5, CWSZ                  ; ...
        tput  tg14, t4, c0, t3, t5      ; ...
        ld    t0, code_pc(zero)         ; advance, if the window was full
        sub   t2, t0, t1                ; ...
        slti  t3, t2, CWSZ              ; ...
        bnez  t3, emit_ret              ; (a flush in the middle: the window stays)
        addi  t1, t1, CWSZ              ; ...
        sd    t1, cw_base(zero)         ; ...
emit_ret:
        ret                             ; done

; enc_i(a0 = opcode, a1 = rd (store: the data register; branch: rs1), a2 = rs1
; (branch: rs2), a3 = 16-bit immediate) -> a0 = an I, S or B format instruction
enc_i:
        slli  a0, a0, 26                ; ...
        slli  a1, a1, 21                ; ...
        or    a0, a0, a1                ; ...
        slli  a2, a2, 16                ; ...
        or    a0, a0, a2                ; ...
        slli  a3, a3, 48                ; the low 16 bits
        srli  a3, a3, 48                ; ...
        or    a0, a0, a3                ; ...
        ret                             ; done
; e_i(the same): emit it
e_i:
        mv    t6, ra                    ; ...
        call  enc_i                     ; ...
        mv    ra, t6                    ; ...
        j     emit                      ; ...
; e_r(a0 = ALU function, a1 = rd, a2 = rs1, a3 = rs2): emit an ALU instruction
e_r:
        slli  a1, a1, 21                ; (the opcode is 0)
        or    a0, a0, a1                ; ...
        slli  a2, a2, 16                ; ...
        or    a0, a0, a2                ; ...
        slli  a3, a3, 11                ; ...
        or    a0, a0, a3                ; ...
        j     emit                      ; ...

; code_rd(a0 = address) -> a0 = the instruction there
code_rd:
        ld    t1, cw_base(zero)         ; in the window?
        bltu  a0, t1, crd_far           ; no
        sub   t2, a0, t1                ; ...
        lwu   a0, CW(t2)                ; ...
        ret                             ; ...
crd_far:
        ld    t3, code_org(zero)        ; in the arena
        sub   a0, a0, t3                ; ...
        li    t4, F_CODE                ; ...
        add   a0, a0, t4                ; ...
        j     far_lw                    ; ...
; code_wr(a0 = address, a1 = instruction): replace the instruction there
code_wr:
        ld    t1, nocode(zero)          ; (as emit)
        bnez  t1, emit_ret              ; ...
        ld    t1, cw_base(zero)         ; in the window?
        bltu  a0, t1, cwr_far           ; no
        sub   t2, a0, t1                ; ...
        sw    a1, CW(t2)                ; ...
        ret                             ; ...
cwr_far:
        ld    t3, code_org(zero)        ; in the arena
        sub   a0, a0, t3                ; ...
        li    t4, F_CODE                ; ...
        add   a0, a0, t4                ; ...
        j     far_sw                    ; ...

; ---- the data image ------------------------------------------------------------------
; dw_seek(a0 = D-LS address of the program) -> t0 = D-LS address here of that
; byte in the data window (loaded, the old window written out if need be)
dw_seek:
        ld    t1, dw_base(zero)         ; in the window?
        sub   t0, a0, t1                ; ...
        sltiu t2, t0, DWSZ              ; ...
        bnez  t2, dws_hit               ; yes
        ld    t2, dw_dirty(zero)        ; write the old one out
        beqz  t2, dws_load              ; (nothing changed in it)
        li    t3, F_DATA                ; ...
        add   t3, t3, t1                ; ...
        li    t4, DW                    ; ...
        li    t5, DWSZ                  ; ...
        tput  tg14, t4, c0, t3, t5      ; ...
        sd    zero, dw_dirty(zero)      ; ...
dws_load:
        srli  t1, a0, 8                 ; the window holding the address
        slli  t1, t1, 8                 ; ...
        sd    t1, dw_base(zero)         ; ...
        li    t3, F_DATA                ; ...
        add   t3, t3, t1                ; ...
        li    t4, DW                    ; ...
        li    t5, DWSZ                  ; ...
        tget  tg14, t4, c0, t3, t5      ; ...
        sub   t0, a0, t1                ; ...
dws_hit:
        addi  t0, t0, DW                ; ...
        ret                             ; done
; data_b(a0 = address, a1 = byte): store a byte into the data image
data_b:
        mv    t6, ra                    ; (dw_seek keeps t6)
        call  dw_seek                   ; ...
        sb    a1, 0(t0)                 ; (waits for a tget)
        li    t1, 1                     ; ...
        sd    t1, dw_dirty(zero)        ; ...
        jr    t6                        ; done
; data_rb(a0 = address) -> a0 = the byte of the data image there
data_rb:
        mv    t6, ra                    ; ...
        call  dw_seek                   ; ...
        lbu   a0, 0(t0)                 ; ...
        jr    t6                        ; done
; data_put(a0 = address, a1 = value, a2 = bytes 1..8): store a little-endian value
data_put:
        addi  sp, sp, -32               ; frame
        sd    ra, 24(sp)                ; ...
        sd    a0, 0(sp)                 ; ...
        sd    a1, 8(sp)                 ; ...
        sd    a2, 16(sp)                ; ...
dput_l:
        call  data_b                    ; the low byte
        ld    a0, 0(sp)                 ; next address
        addi  a0, a0, 1                 ; ...
        sd    a0, 0(sp)                 ; ...
        ld    a1, 8(sp)                 ; next byte
        srli  a1, a1, 8                 ; ...
        sd    a1, 8(sp)                 ; ...
        ld    a2, 16(sp)                ; one fewer
        addi  a2, a2, -1                ; ...
        sd    a2, 16(sp)                ; ...
        bnez  a2, dput_l                ; ...
        ld    ra, 24(sp)                ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; done
; data_alloc(a0 = bytes, a1 = alignment) -> a0 = a fresh D-LS address of the program
data_alloc:
        ld    t0, data_pc(zero)         ; align
        add   t0, t0, a1                ; ...
        addi  t0, t0, -1                ; ...
        neg   t1, a1                    ; ...
        and   t0, t0, t1                ; ...
        add   t1, t0, a0                ; its end
        li    t2, 0xA000                ; the program's D-LS ends at 40 KiB
        bleu  t1, t2, dal_ok            ; ...
        li    a0, m_datafull            ; ...
        j     error                     ; ...
dal_ok:
        sd    t1, data_pc(zero)         ; ...
        mv    a0, t0                    ; ...
        ret                             ; done

; ---- symbols and types: the small, hot helpers ----------------------------------------
; sym_new() -> a0 = a zeroed symbol record
sym_new:
        ld    a0, sym_top(zero)         ; ...
        li    t0, SYMEND                ; room?
        bltu  a0, t0, syn_ok            ; ...
        li    a0, m_symfull             ; ...
        j     error                     ; ...
syn_ok:
        addi  t0, a0, SYSZ              ; ...
        sd    t0, sym_top(zero)         ; ...
        sd    zero, 0(a0)               ; ...
        sd    zero, 8(a0)               ; ...
        ret                             ; done
; ty_new(a0 = kind, a1 = size, a2 = alignment, a3 = base type) -> a0 = a new type
ty_new:
        ld    t0, ty_top(zero)          ; ...
        li    t1, TYPES + NTYPES * TYSZ ; room?
        bltu  t0, t1, tyn_ok            ; ...
        li    a0, m_tyfull              ; ...
        j     error                     ; ...
tyn_ok:
        addi  t1, t0, TYSZ              ; ...
        sd    t1, ty_top(zero)          ; ...
        sd    zero, 0(t0)               ; ...
        sd    zero, 8(t0)               ; ...
        sb    a0, TY_KIND(t0)           ; ...
        sw    a1, TY_SIZE(t0)           ; ...
        sb    a2, TY_ALIGN(t0)          ; ...
        sh    a3, TY_BASE(t0)           ; ...
        mv    a0, t0                    ; ...
        ret                             ; done
; ty_ptr(a0 = type) -> a0 = pointer to it (an existing record if there is one)
ty_ptr:
        li    t0, TYPES                 ; look for one
        ld    t1, ty_top(zero)          ; ...
typ_l:
        bgeu  t0, t1, typ_new           ; none
        lbu   t2, TY_KIND(t0)           ; a pointer
        addi  t2, t2, -TK_PTR           ; ...
        bnez  t2, typ_n                 ; ...
        lhu   t2, TY_BASE(t0)           ; to this type?
        beq   t2, a0, typ_hit           ; ...
typ_n:
        addi  t0, t0, TYSZ              ; ...
        j     typ_l                     ; ...
typ_hit:
        mv    a0, t0                    ; ...
        ret                             ; ...
typ_new:
        mv    a3, a0                    ; a new one
        li    a0, TK_PTR                ; ...
        li    a1, 8                     ; ...
        li    a2, 8                     ; ...
        j     ty_new                    ; ...

; ---- value stack -------------------------------------------------------------------------
; vpush(a0 = kind, a1 = type, a2 = value) -> a0 = the new top entry (register, flags, symbol 0)
vpush:
        ld    t0, vsp(zero)             ; the next entry
        addi  t0, t0, VSZ               ; ...
        li    t1, VSTK + NVSTK * VSZ    ; room?
        bltu  t0, t1, vpu_ok            ; ...
        li    a0, m_vfull               ; ...
        j     error                     ; ...
vpu_ok:
        sd    t0, vsp(zero)             ; ...
        sd    zero, 0(t0)               ; ...
        sd    zero, 16(t0)              ; ...
        sb    a0, V_KIND(t0)            ; ...
        sh    a1, V_TYPE(t0)            ; ...
        sd    a2, V_VAL(t0)             ; ...
        mv    a0, t0                    ; ...
        ret                             ; done

