start:
        lui   gp, 1                     ; gp = R
        li    t0, 12                    ; 4 KiB code units
        csrw  xslot, t0                 ; ...
        call  __init                    ; handles
        li    a0, m_libname             ; the library file holds the compiler's own code units
        li    a1, F_SRC                 ;   as its last member: read all of it (where source
        li    a2, F_SRCEND - F_SRC      ;   text will go later)
        call  m_load                    ; a0 = its size, or -1
        bgez  a0, st_lib                ; ...
        li    a0, m_nolib               ; ...
        j     error                     ; ...
st_lib:
        li    t0, F_SRC                 ; ...
        sd    t0, lib_base(zero)        ; ...
        li    a0, m_units               ; the units go to the bottom of the arena, where their
        call  lib_find1                 ;   labels say they are
        bnez  a0, st_units              ; ...
        li    a0, m_badlib              ; ...
        j     error                     ; ...
st_units:
        mv    s1, a0                    ; (nothing to keep: s1 is free here)
        addi  a2, a1, 7                 ; ...
        srli  a2, a2, 3                 ; ...
        slli  a2, a2, 3                 ; ...
        mv    a1, a0                    ; ...
        li    a0, 0                     ; ...
        call  m_copy                    ; ...
        li    a0, F_LIB                 ; what comes before them (the library, the headers)
        li    a1, F_SRC                 ;   goes where the compiler looks for it
        li    a2, F_SRC                 ; ...
        sub   a2, s1, a2                ; ...
        li    t0, F_SRC - F_LIB         ; ...
        bleu  a2, t0, st_fits           ; ...
        li    a0, m_badlib              ; ...
        j     error                     ; ...
st_fits:
        call  m_copy                    ; ...
        li    t0, F_LIB                 ; ...
        sd    t0, lib_base(zero)        ; ...
        la    t6, main                  ; the compiler proper
        xcall ra, c0, t6                ; ...
        j     _exit                     ; (main exits by itself)

; m_load(a0 = file name, a1 = arena offset, a2 = most bytes) -> a0 = size, or
; -1 if it cannot be opened. Too large is an error. Zero bytes follow the file.
m_load:
        addi  sp, sp, -48               ; frame
        sd    ra, 40(sp)                ; ...
        sd    s1, 0(sp)                 ; s1 = handle
        sd    s2, 8(sp)                 ; s2 = arena cursor
        sd    s3, 16(sp)                ; s3 = bytes waiting in IOB
        sd    s4, 24(sp)                ; s4 = start
        sd    a2, 32(sp)                ; the limit
        mv    s2, a1                    ; ...
        mv    s4, a1                    ; ...
        li    a1, 0                     ; open for reading
        jalr  ra, gp, open-R            ; ...
        bltz  a0, ml_ret                ; cannot
        mv    s1, a0                    ; ...
        li    s3, 0                     ; ...
ml_loop:
        mv    a0, s1                    ; read a piece after what waits
        addi  a1, s3, IOB               ; ...
        li    a2, 1024                  ; ...
        sub   a2, a2, s3                ; ...
        jalr  ra, gp, read-R            ; ...
        blez  a0, ml_end                ; the end
        add   s3, s3, a0                ; ...
        srli  t0, s3, 3                 ; whole words go to the arena
        slli  t0, t0, 3                 ; ...
        beqz  t0, ml_loop               ; (none yet)
        sub   t1, s2, s4                ; room?
        add   t1, t1, t0                ; ...
        ld    t2, 32(sp)                ; ...
        addi  t2, t2, -16               ; ...
        bleu  t1, t2, ml_put            ; ...
        li    a0, m_big                 ; ...
        jalr  zero, gp, error-R         ; ...
ml_put:
        li    t1, IOB                   ; ...
        tput  tg14, t1, c0, s2, t0      ; ...
        add   s2, s2, t0                ; ...
        sub   s3, s3, t0                ; the rest moves to the front
        ld    t2, IOB(t0)               ; (at most 7 bytes; the load waits for the tput)
        sd    t2, IOB(zero)             ; ...
        j     ml_loop                   ; ...
ml_end:
        addi  t0, s3, IOB               ; zero bytes after the last ones, sixteen of them
        li    t1, 16                    ; ...
ml_z:
        sb    zero, 0(t0)               ; ...
        addi  t0, t0, 1                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, ml_z                  ; ...
        li    t1, IOB                   ; ...
        li    t0, 16                    ; ...
        tput  tg14, t1, c0, s2, t0      ; ...
        add   s2, s2, s3                ; the size
        mv    a0, s1                    ; ...
        jalr  ra, gp, close-R           ; ...
        li    t0, -1                    ; the windows over the arena may be stale
        sd    t0, sw_base(zero)         ; ...
        sd    t0, rb_base(zero)         ; ...
        sub   a0, s2, s4                ; ...
ml_ret:
        ld    s1, 0(sp)                 ; ...
        ld    s2, 8(sp)                 ; ...
        ld    s3, 16(sp)                ; ...
        ld    s4, 24(sp)                ; ...
        ld    ra, 40(sp)                ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; done

; lib_find1(a0 = name) -> a0 = arena offset (0: not there), a1 = size  (local leaf)
lib_find1:
        ld    t0, lib_base(zero)        ; the directory
        addi  t0, t0, 8                 ; ...
        li    t1, IOB                   ; an entry at a time
        li    t2, 32                    ; ...
lf_loop:
        tget  tg14, t1, c0, t0, t2      ; ...
        lbu   t3, IOB(zero)             ; the end of the directory?
        beqz  t3, lf_none               ; ...
        mv    t3, a0                    ; compare the names
        li    t4, IOB                   ; ...
lf_cmp:
        lbu   t5, 0(t3)                 ; ...
        lbu   t6, 0(t4)                 ; ...
        bne   t5, t6, lf_next           ; ...
        addi  t3, t3, 1                 ; ...
        addi  t4, t4, 1                 ; ...
        bnez  t5, lf_cmp                ; ...
        lwu   a0, IOB+24(zero)          ; found: offset in the file
        ld    t3, lib_base(zero)        ; ...
        add   a0, a0, t3                ; ...
        lwu   a1, IOB+28(zero)          ; size
        ret                             ; ...
lf_next:
        addi  t0, t0, 32                ; ...
        j     lf_loop                   ; ...
lf_none:
        li    a0, 0                     ; ...
        ret                             ; done
; m_copy(a0 = to, a1 = from, a2 = bytes, a multiple of 8): arena to arena
m_copy:
        beqz  a2, mc_ret                ; all copied
        li    t5, 1024                  ; a piece of at most 1 KiB
        bleu  t5, a2, mc_n              ; ...
        mv    t5, a2                    ; ...
mc_n:
        li    t1, IOB                   ; through the D-LS
        tget  tg14, t1, c0, a1, t5      ; ...
        tput  tg14, t1, c0, a0, t5      ; ...
        add   a0, a0, t5                ; ...
        add   a1, a1, t5                ; ...
        sub   a2, a2, t5                ; ...
        j     m_copy                    ; ...
mc_ret:
        ret                             ; done


; ---- entry and exit sequences of functions in units ----------------------------------
ent0:   addi  sp, sp, -8                ; frame: ra
        sd    ra, 0(sp)                 ; ...
        jr    t6                        ; back into the function
ent1:   addi  sp, sp, -16               ; frame: ra, s1
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        jr    t6                        ; ...
ent2:   addi  sp, sp, -24               ; frame: ra, s1, s2
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        jr    t6                        ; ...
ent3:   addi  sp, sp, -32               ; frame: ra, s1..s3
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        jr    t6                        ; ...
ent4:   addi  sp, sp, -40               ; frame: ra, s1..s4
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        jr    t6                        ; ...
ent6:   addi  sp, sp, -56               ; frame: ra, s1..s6
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        sd    s5, 40(sp)                ; ...
        sd    s6, 48(sp)                ; ...
        jr    t6                        ; ...
lv6:    ld    s6, 48(sp)                ; restore s6, s5 and fall into the shorter frames'
        ld    s5, 40(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 56                ; ...
        xret  ra                        ; return through a far link
lv4:    ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 40                ; ...
        xret  ra                        ; ...
lv3:    ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        xret  ra                        ; ...
lv2:    ld    s2, 16(sp)                ; ...
