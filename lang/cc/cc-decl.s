u_decl3:
; ext_decl(): one external declaration: a function definition, or declarations
; of objects, functions and types ended by ;
ext_decl:
        jalr  t6, gp, ent6-R            ; s1 = base type, s2 = storage class, s3 = type, s4 = identifier, s5 = symbol
        la    t6, decl_spec             ; ...
        xcall ra, c0, t6                ; ...
        mv    s1, a0                    ; ...
        ld    s2, ds_class(zero)        ; ...
        bnez  s1, exd_l0                ; ...
        li    s1, Y_INT                 ; no specifiers: `name(...) {` is a function returning int
        ld    t0, tok(zero)             ; ...
        li    t1, T_ID                  ; ...
        beq   t0, t1, exd_l             ; ...
        li    a0, m_expect              ; ...
        jalr  zero, gp, errtok-R        ; ...
exd_l0:
        ld    t0, tok(zero)             ; specifiers alone (a struct or enum declaration)
        li    t1, ';'                   ; ...
        beq   t0, t1, exd_semi          ; ...
exd_l:
        sd    zero, d_name(zero)        ; a declarator
        mv    a0, s1                    ; ...
        la    t6, declarator            ; ...
        xcall ra, c0, t6                ; ...
        mv    s3, a0                    ; ...
        ld    s4, d_name(zero)          ; ...
        bnez  s4, exd_cls               ; ...
        li    a0, m_expect              ; ...
        jalr  zero, gp, errtok-R        ; ...
exd_cls:
        li    t0, K_TYPEDEF             ; a typedef name
        bne   s2, t0, exd_fn            ; ...
        mv    a0, s4                    ; ...
        li    a1, SC_TYPEDEF            ; ...
        mv    a2, s3                    ; ...
        la    t6, sym_decl              ; ...
        xcall ra, c0, t6                ; ...
