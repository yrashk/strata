        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        j     exd_l                     ; ...
exd_semi:
        li    a0, ';'                   ; ...
        la    t6, skip                  ; ...
        xcall ra, c0, t6                ; ...
        jalr  zero, gp, lv6-R           ; done

; func_decl(a0 = identifier, a1 = function type) -> a0 = its symbol; a function
; the library exports is defined by that
func_decl:
        jalr  t6, gp, ent1-R            ; s1 = symbol
        mv    a2, a1                    ; ...
        li    a1, SC_FUNC               ; ...
        la    t6, sym_decl              ; ...
        xcall ra, c0, t6                ; ...
        mv    s1, a0                    ; ...
        lbu   t0, SY_FLAGS(s1)          ; known already?
        andi  t0, t0, SF_DEF            ; ...
        bnez  t0, fdc_ret               ; ...
        lwu   a0, SY_ID(s1)             ; in the library?
        la    t6, lib_lookup            ; ...
        xcall ra, c0, t6                ; ...
        bltz  a0, fdc_ret               ; ...
        sw    a0, SY_VAL(s1)            ; ...
        li    t0, SF_DEF | SF_EXT       ; (SF_EXT on a function: the library's, may be replaced)
        sb    t0, SY_FLAGS(s1)          ; ...
fdc_ret:
        mv    a0, s1                    ; ...
        jalr  zero, gp, lv1-R           ; done

; func_def(a0 = symbol): the function's body follows
func_def:
        jalr  t6, gp, ent6-R            ; s1 = symbol, s2 = symbol table mark, s3 = parameter, s4 = index, s5 = local
        mv    s1, a0                    ; ...
        lbu   t0, SY_FLAGS(s1)          ; defined twice? (the library's definition is replaced)
        li    t1, SF_DEF                ; ...
        bne   t0, t1, fdf_go            ; ...
        lwu   a0, SY_ID(s1)             ; ...
        jalr  ra, gp, id_name-R         ; ...
        mv    a1, a0                    ; ...
        li    a0, m_redef               ; ...
        jalr  zero, gp, error2-R        ; ...
fdf_go:
        sb    zero, SY_FLAGS(s1)        ; not defined until its end: calls to itself are fixups
        sd    s1, fn_sym(zero)          ; ...
        lhu   s6, SY_TYPE(s1)           ; s6 = its type
        lhu   t1, TY_BASE(s6)           ; ...
        sd    t1, fn_ret(zero)          ; ...
        lbu   t2, TY_KIND(t1)           ; s4 = 1 if it returns a structure: the first argument
        addi  t2, t2, -TK_STRUCT        ;   register holds the address for the result
        sltiu s4, t2, 2                 ; ...
        lbu   t0, TY_FLAGS(s6)          ; variadic, or more arguments than registers: the
        andi  t0, t0, TF_VARIADIC       ;   arguments are kept together, addressed from s0
        lwu   t1, TY_COUNT(s6)          ; ...
        add   t1, t1, s4                ; ...
        slti  t1, t1, 9                 ; ...
        xori  t1, t1, 1                 ; ...
        or    t0, t0, t1                ; ...
        snez  t0, t0                    ; ...
        sd    t0, fn_s0(zero)           ; ...
        la    t6, g_fn_begin            ; ...
        xcall ra, c0, t6                ; ...
        ld    s2, sym_top(zero)         ; the parameters and the body's block are one scope
        li    t0, 1                     ; ...
        sd    t0, scope(zero)           ; ...
        lhu   s3, TY_AUX(s6)            ; ...
        beqz  s4, fdf_p                 ; the result's address: argument 0
        sd    zero, fn_sret(zero)       ; (at 0(s0), or stored in the frame)
        ld    t0, fn_s0(zero)           ; ...
        bnez  t0, fdf_p                 ; ...
        li    a0, 8                     ; ...
        li    a1, 8                     ; ...
        la    t6, fr_alloc_x            ; ...
        xcall ra, c0, t6                ; ...
        sd    a0, fn_sret(zero)         ; ...
        mv    a3, a0                    ; ...
        li    a0, OP_SD                 ; ...
        li    a1, X_A0                  ; ...
        li    a2, X_SP                  ; ...
        la    t6, g_mem                 ; ...
        xcall ra, c0, t6                ; ...
fdf_p:
        beqz  s3, fdf_body              ; ...
        lwu   a0, SY_ID(s3)             ; a parameter: a local
        bnez  a0, fdf_pn                ; ...
        li    a0, m_expect              ; (it needs a name)
        jalr  zero, gp, errtok-R        ; ...
fdf_pn:
        li    a1, SC_AUTO               ; ...
        lhu   a2, SY_TYPE(s3)           ; ...
        la    t6, sym_decl              ; ...
        xcall ra, c0, t6                ; ...
        mv    s5, a0                    ; ...
        lhu   t0, SY_TYPE(s3)           ; a structure is passed as the address of a copy
        lbu   t0, TY_KIND(t0)           ; ...
        addi  t0, t0, -TK_STRUCT        ; ...
        sltiu t0, t0, 2                 ; ...
        slli  t0, t0, 3                 ; (SF_REF = 8)
        sb    t0, SY_FLAGS(s5)          ; ...
        ld    t1, fn_s0(zero)           ; kept by the prologue's block: at 8 * i (s0)
        beqz  t1, fdf_home              ; ...
        ori   t0, t0, SF_S0             ; ...
        sb    t0, SY_FLAGS(s5)          ; ...
        slli  t0, s4, 3                 ; ...
        sw    t0, SY_VAL(s5)            ; ...
        j     fdf_pnx                   ; ...
fdf_home:
        li    a0, 8                     ; else stored from its register into a word of the frame
        li    a1, 8                     ; ...
        la    t6, fr_alloc_x            ; ...
        xcall ra, c0, t6                ; ...
        sw    a0, SY_VAL(s5)            ; ...
        mv    a3, a0                    ; sd a_i, offset(sp)
        li    a0, OP_SD                 ; ...
        addi  a1, s4, X_A0              ; ...
        li    a2, X_SP                  ; ...
        la    t6, g_mem                 ; ...
        xcall ra, c0, t6                ; ...
fdf_pnx:
        lhu   s3, SY_PREV(s3)           ; ...
        addi  s4, s4, 1                 ; ...
        j     fdf_p                     ; ...
fdf_body:
        ld    t0, fr_cur(zero)          ; (what the statements may not reuse)
        la    t6, block_body            ; { declarations and statements }
        xcall ra, c0, t6                ; ...
        lwu   a0, SY_ID(s1)             ; main returns 0 when it runs off its end
        jalr  ra, gp, id_name-R         ; ...
        lwu   t0, 0(a0)                 ; "main"
        li    t1, 0x6E69616D            ; ...
        bne   t0, t1, fdf_end           ; ...
        lbu   t0, 4(a0)                 ; ...
        bnez  t0, fdf_end               ; ...
        li    a0, X_A0                  ; ...
        li    a1, 0                     ; ...
        la    t6, g_li                  ; ...
        xcall ra, c0, t6                ; ...
fdf_end:
        la    t6, lab_check             ; every label a goto names must be there
        xcall ra, c0, t6                ; ...
        la    t6, g_fn_end              ; ...
        xcall ra, c0, t6                ; ...
        ld    s4, fn_start(zero)        ; (where it ended up)
        mv    a0, s2                    ; the scope ends
        la    t6, scope_exit            ; ...
        xcall ra, c0, t6                ; ...
        sd    zero, scope(zero)         ; ...
        sw    s4, SY_VAL(s1)            ; the function is defined
        li    t0, SF_DEF                ; ...
        sb    t0, SY_FLAGS(s1)          ; ...
        sd    zero, fn_sym(zero)        ; ...
        jalr  zero, gp, lv6-R           ; done

; static_var(a0 = identifier, a1 = type, a2 = storage class keyword): declare an
; object with static storage (file scope, or static/extern in a block), give
; it room in the data image and read its initialiser
static_var:
        jalr  t6, gp, ent4-R            ; s1 = symbol, s2 = type, s3 = class, s4 = scratch
        mv    s2, a1                    ; ...
        mv    s3, a2                    ; ...
        li    a1, SC_STATIC             ; ...
        mv    a2, s2                    ; ...
        la    t6, sym_decl              ; ...
        xcall ra, c0, t6                ; ...
        mv    s1, a0                    ; ...
        lhu   s2, SY_TYPE(s1)           ; (the type may be an earlier, more complete one)
        lbu   t0, SY_FLAGS(s1)          ; it has an address already?
        andi  t0, t0, SF_DEF            ; ...
        bnez  t0, stv_init              ; ...
        li    t0, K_EXTERN              ; extern: the library's object, if it exports one
        bne   s3, t0, stv_alloc         ; ...
        lwu   a0, SY_ID(s1)             ; ...
        la    t6, lib_lookup            ; ...
        xcall ra, c0, t6                ; ...
        bltz  a0, stv_alloc             ; ...
        sw    a0, SY_VAL(s1)            ; ...
        li    t0, SF_DEF                ; ...
        sb    t0, SY_FLAGS(s1)          ; ...
        j     stv_init                  ; ...
stv_alloc:
        lwu   a0, TY_SIZE(s2)           ; room for it, unless its size is not known yet
        bnez  a0, stv_room              ; ...
        li    t0, SF_EXT                ; (its address is not known either)
        sb    t0, SY_FLAGS(s1)          ; ...
        j     stv_init                  ; ...
stv_room:
        lbu   a1, TY_ALIGN(s2)          ; ...
        jalr  ra, gp, data_alloc-R      ; ...
        sw    a0, SY_VAL(s1)            ; ...
        li    t0, SF_DEF                ; ...
        sb    t0, SY_FLAGS(s1)          ; ...
stv_init:
        ld    t0, tok(zero)             ; = initialiser
        li    t1, '='                   ; ...
        bne   t0, t1, stv_ret           ; ...
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s1                    ; ...
        la    t6, static_init           ; ...
        xcall ra, c0, t6                ; ...
stv_ret:
        mv    a0, s1                    ; ...
        jalr  zero, gp, lv4-R           ; done
