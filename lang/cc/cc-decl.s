; =============================================================================
; cc-decl.s: declarations: specifiers, declarators, symbols, functions
; =============================================================================

        .data                           ; this unit's variables
ds_class: .dword 0                      ; the storage class keyword of the specifiers just read (0: none)
d_name:   .dword 0                      ; the identifier a declarator named (0: none)
; the basic types, in the order of Y_VOID..Y_DOUBLE: kind, size, flags
ty_tab:   .byte TK_VOID, 0, 0, TK_BOOL, 1, TF_UNS, TK_CHAR, 1; .
          .byte 0, TK_CHAR, 1, TF_UNS   ; .
          .byte TK_SHORT, 2, 0, TK_SHORT, 2, TF_UNS, TK_INT, 4; .
          .byte 0, TK_INT, 4, TF_UNS    ; .
          .byte TK_LONG, 8, 0, TK_LONG, 8, TF_UNS, TK_FLOAT, 4; .
          .byte 0, TK_DOUBLE, 8, 0      ; .
        .align 8                        ; ...
; the keywords that start a declaration, as a set of (token - K_FIRST)
TYPE_KW  = 1 << 0 | 1 << 3 | 1 << 4 | 1 << 8 | 1 << 10 | 1 << 11 | 1 << 12 | 1 << 16 | 1 << 17 | 1 << 18 | 1 << 19 | 1 << 20 | 1 << 22 | 1 << 23 | 1 << 25 | 1 << 26 | 1 << 28 | 1 << 29 | 1 << 30 | 1 << 31 | 1 << 32 | 1 << 34 ; .
type_kw:  .dword TYPE_KW                ; ...

        .far                            ; code units
        .align 4096                     ; ---- unit: decl1 ----
u_decl1:
; ty_init(): the basic types
ty_init:
        jalr  t6, gp, ent2-R            ; s1 = table cursor, s2 = count
        li    t0, TYPES                 ; ...
        sd    t0, ty_top(zero)          ; ...
        li    s1, ty_tab                ; ...
        li    s2, 12                    ; ...
tyi_l:
        lbu   a0, 0(s1)                 ; kind
        lbu   a1, 1(s1)                 ; size
        mv    a2, a1                    ; alignment: the size (1 for void)
        bnez  a2, tyi_a                 ; ...
        li    a2, 1                     ; ...
tyi_a:
        li    a3, 0                     ; ...
        jalr  ra, gp, ty_new-R          ; ...
        lbu   t0, 2(s1)                 ; ...
        sb    t0, TY_FLAGS(a0)          ; ...
        addi  s1, s1, 3                 ; ...
        addi  s2, s2, -1                ; ...
        bnez  s2, tyi_l                 ; ...
        li    a0, TK_PTR                ; char *
        li    a1, 8                     ; ...
        li    a2, 8                     ; ...
        li    a3, Y_CHAR                ; ...
        jalr  ra, gp, ty_new-R          ; ...
        li    a0, TK_PTR                ; void *
        li    a1, 8                     ; ...
        li    a2, 8                     ; ...
        li    a3, Y_VOID                ; ...
        jalr  ra, gp, ty_new-R          ; ...
        jalr  zero, gp, lv2-R           ; done

; sym_decl(a0 = identifier, a1 = class, a2 = type) -> a0 = its symbol: declare
; the identifier in the current scope. A second declaration of a function or
; static object in the same scope is the same symbol.
sym_decl:
        jalr  t6, gp, ent4-R            ; s1 = identifier, s2 = class, s3 = type, s4 = the current symbol
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        mv    s3, a2                    ; ...
        addi  a0, s1, 8                 ; what it names now
        jalr  ra, gp, far_ld-R          ; ...
        slli  s4, a0, 48                ; (ID_SYM: the low 16 bits)
        srli  s4, s4, 48                ; ...
        beqz  s4, syd_new               ; nothing
        lhu   t0, SY_AUX(s4)            ; in this scope?
        ld    t1, scope(zero)           ; ...
        bne   t0, t1, syd_new           ; no: it is hidden
        lbu   t0, SY_CLASS(s4)          ; the same kind of thing, and a function or static object?
        bne   t0, s2, syd_redef         ; ...
        addi  t1, t0, -SC_STATIC        ; ...
        sltiu t1, t1, 2                 ; ...
        beqz  t1, syd_tdef              ; ...
        lhu   t1, SY_TYPE(s4)           ; the newer type wins if it says more: a prototype
        lbu   t2, TY_KIND(s3)           ;   after (), a size after []
        addi  t2, t2, -TK_FUNC          ; ...
        bnez  t2, syd_obj               ; ...
        lbu   t2, TY_FLAGS(s3)          ; ...
        andi  t2, t2, TF_OLD            ; ...
        bnez  t2, syd_same              ; ...
        sh    s3, SY_TYPE(s4)           ; ...
        j     syd_same                  ; ...
syd_obj:
        lwu   t2, TY_SIZE(s3)           ; ...
        beqz  t2, syd_same              ; ...
        sh    s3, SY_TYPE(s4)           ; ...
syd_same:
        mv    a0, s4                    ; ...
        jalr  zero, gp, lv4-R           ; ...
syd_tdef:
        li    t1, SC_TYPEDEF            ; a typedef may be repeated
        beq   t0, t1, syd_same          ; ...
syd_redef:
        mv    a0, s1                    ; ...
        jalr  ra, gp, id_name-R         ; ...
        mv    a1, a0                    ; ...
        li    a0, m_redef               ; ...
        jalr  zero, gp, error2-R        ; ...
syd_new:
        jalr  ra, gp, sym_new-R         ; ...
        sw    s1, SY_ID(a0)             ; ...
        sh    s3, SY_TYPE(a0)           ; ...
        sb    s2, SY_CLASS(a0)          ; ...
        sh    s4, SY_PREV(a0)           ; ...
        ld    t0, scope(zero)           ; ...
        sh    t0, SY_AUX(a0)            ; ...
        mv    s4, a0                    ; ...
        mv    a0, s1                    ; the identifier names it now
        li    a1, ID_SYM                ; ...
        mv    a2, s4                    ; ...
        jalr  ra, gp, id_set-R          ; ...
        mv    a0, s4                    ; ...
        jalr  zero, gp, lv4-R           ; done

; scope_exit(a0 = the symbol table's top when the scope was entered): the
; scope's symbols go; the identifiers name what they named before
scope_exit:
        jalr  t6, gp, ent2-R            ; s1 = limit, s2 = symbol
        mv    s1, a0                    ; ...
        ld    s2, sym_top(zero)         ; ...
sce_l:
        bleu  s2, s1, sce_ret           ; ...
        addi  s2, s2, -SYSZ             ; ...
        lbu   t0, SY_CLASS(s2)          ; members and prototype parameters name nothing
        li    a1, ID_TAG                ; a tag
        li    t1, SC_TAG                ; ...
        beq   t0, t1, sce_set           ; ...
        li    a1, ID_SYM                ; an ordinary identifier
        addi  t1, t0, -SC_MEMBER        ; ...
        beqz  t1, sce_l                 ; ...
        addi  t1, t0, -SC_PARAM         ; ...
        beqz  t1, sce_l                 ; ...
sce_set:
        lwu   a0, SY_ID(s2)             ; ...
        beqz  a0, sce_l                 ; (anonymous)
        lhu   a2, SY_PREV(s2)           ; ...
        jalr  ra, gp, id_set-R          ; ...
        j     sce_l                     ; ...
sce_ret:
        sd    s1, sym_top(zero)         ; ...
        jalr  zero, gp, lv2-R           ; done

; is_type() -> a0 = 1 if the current token starts a declaration or a type name
is_type:
        ld    t0, tok(zero)             ; ...
        li    a0, 0                     ; ...
        li    t1, T_ID                  ; a typedef name?
        bne   t0, t1, ist_kw            ; ...
        ld    t1, tk_sym(zero)          ; ...
        beqz  t1, ist_ret               ; ...
        lbu   t1, SY_CLASS(t1)          ; ...
        addi  t1, t1, -SC_TYPEDEF       ; ...
        seqz  a0, t1                    ; ...
        xret  ra                        ; ...
ist_kw:
        addi  t0, t0, -K_FIRST          ; one of the keywords of declarations?
        sltiu t1, t0, 64                ; ...
        beqz  t1, ist_ret               ; ...
        ld    t1, type_kw(zero)         ; ...
        srl   t1, t1, t0                ; ...
        andi  a0, t1, 1                 ; ...
ist_ret:
        xret  ra                        ; done

; const_expr() -> a0 = the value of the constant expression that follows
const_expr:
        jalr  t6, gp, ent1-R            ; s1 = entry
        la    t6, cond                  ; ...
        xcall ra, c0, t6                ; ...
        ld    s1, vsp(zero)             ; it must have folded to a constant
        lbu   t0, V_KIND(s1)            ; ...
        addi  t0, t0, -VK_CONST         ; ...
        lhu   t1, V_SYM(s1)             ; ...
        or    t0, t0, t1                ; ...
        beqz  t0, cex_ok                ; ...
        li    a0, m_const               ; ...
        jalr  zero, gp, error-R         ; ...
cex_ok:
        ld    a0, V_VAL(s1)             ; ...
        addi  s1, s1, -VSZ              ; ...
        sd    s1, vsp(zero)             ; ...
        jalr  zero, gp, lv1-R           ; done

; type_name() -> a0 = the type named by specifiers and an abstract declarator
type_name:
        jalr  t6, gp, ent2-R            ; s1, s2 = the caller's ds_class, d_name
        ld    s1, ds_class(zero)        ; ...
        ld    s2, d_name(zero)          ; ...
        la    t6, decl_spec             ; ...
        xcall ra, c0, t6                ; ...
        bnez  a0, tyn_d                 ; ...
        li    a0, m_expect              ; ...
        jalr  zero, gp, errtok-R        ; ...
tyn_d:
        la    t6, declarator            ; ...
        xcall ra, c0, t6                ; ...
        sd    s1, ds_class(zero)        ; ...
        sd    s2, d_name(zero)          ; ...
        jalr  zero, gp, lv2-R           ; done

; decl_spec() -> a0 = the type the declaration specifiers name, or 0 if there
; are none; ds_class = the storage class keyword among them
DS_VOID  = 1                            ; what was seen
DS_CHAR  = 2                            ; .
DS_SHORT = 4                            ; .
DS_INT   = 8                            ; .
DS_LONG  = 16                           ; .
DS_FLOAT = 32                           ; .
DS_DOUBLE = 64                          ; .
DS_SIGNED = 128                         ; .
DS_UNS   = 256                          ; .
DS_BOOL  = 512                          ; .
DS_TYPE  = 1024                         ; a struct, union, enum or typedef name: s3
decl_spec:
        jalr  t6, gp, ent3-R            ; s1 = token, s2 = what was seen, s3 = a named type
        li    s2, 0                     ; ...
        sd    zero, ds_class(zero)      ; ...
dsp_l:
        ld    s1, tok(zero)             ; ...
        li    t0, T_ID                  ; a typedef name, if no type was given yet
        bne   s1, t0, dsp_kw            ; ...
        bnez  s2, dsp_end               ; ...
        ld    t1, tk_sym(zero)          ; ...
        beqz  t1, dsp_end               ; ...
        lbu   t2, SY_CLASS(t1)          ; ...
        addi  t2, t2, -SC_TYPEDEF       ; ...
        bnez  t2, dsp_end               ; ...
        lhu   s3, SY_TYPE(t1)           ; ...
        li    s2, DS_TYPE               ; ...
        j     dsp_next                  ; ...
dsp_kw:
        li    t1, DS_VOID               ; the type keywords
        li    t0, K_VOID                ; ...
        beq   s1, t0, dsp_set           ; ...
        li    t1, DS_CHAR               ; ...
        li    t0, K_CHAR                ; ...
        beq   s1, t0, dsp_set           ; ...
        li    t1, DS_SHORT              ; ...
        li    t0, K_SHORT               ; ...
        beq   s1, t0, dsp_set           ; ...
        li    t1, DS_INT                ; ...
        li    t0, K_INT                 ; ...
        beq   s1, t0, dsp_set           ; ...
        li    t1, DS_LONG               ; ...
        li    t0, K_LONG                ; ...
        beq   s1, t0, dsp_set           ; ...
        li    t1, DS_FLOAT              ; ...
        li    t0, K_FLOAT               ; ...
        beq   s1, t0, dsp_set           ; ...
        li    t1, DS_DOUBLE             ; ...
        li    t0, K_DOUBLE              ; ...
        beq   s1, t0, dsp_set           ; ...
        li    t1, DS_SIGNED             ; ...
        li    t0, K_SIGNED              ; ...
        beq   s1, t0, dsp_set           ; ...
        li    t1, DS_UNS                ; ...
        li    t0, K_UNSIGNED            ; ...
        beq   s1, t0, dsp_set           ; ...
        li    t1, DS_BOOL               ; ...
        li    t0, K_BOOL                ; ...
        beq   s1, t0, dsp_set           ; ...
        li    t0, K_CONST               ; qualifiers and inline mean nothing here
        beq   s1, t0, dsp_next          ; ...
        li    t0, K_VOLATILE            ; ...
        beq   s1, t0, dsp_next          ; ...
        li    t0, K_RESTRICT            ; ...
        beq   s1, t0, dsp_next          ; ...
        li    t0, K_INLINE              ; ...
        beq   s1, t0, dsp_next          ; ...
        li    t0, K_TYPEDEF             ; a storage class
        beq   s1, t0, dsp_cls           ; ...
        li    t0, K_EXTERN              ; ...
        beq   s1, t0, dsp_cls           ; ...
        li    t0, K_STATIC              ; ...
        beq   s1, t0, dsp_cls           ; ...
        li    t0, K_AUTO                ; ...
        beq   s1, t0, dsp_cls           ; ...
        li    t0, K_REGISTER            ; ...
        beq   s1, t0, dsp_cls           ; ...
        li    t0, K_STRUCT              ; struct, union, enum
        beq   s1, t0, dsp_su            ; ...
        li    t0, K_UNION               ; ...
        beq   s1, t0, dsp_su            ; ...
        li    t0, K_ENUM                ; ...
        bne   s1, t0, dsp_end           ; anything else ends the specifiers
        la    t6, enum_spec             ; ...
        xcall ra, c0, t6                ; ...
        j     dsp_named                 ; ...
dsp_su:
        la    t6, struct_spec           ; ...
        xcall ra, c0, t6                ; ...
dsp_named:
        mv    s3, a0                    ; ...
        ori   s2, s2, DS_TYPE           ; ...
        j     dsp_l                     ; ...
dsp_cls:
        sd    s1, ds_class(zero)        ; ...
        j     dsp_next                  ; ...
dsp_set:
        or    s2, s2, t1                ; ...
dsp_next:
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        j     dsp_l                     ; ...
dsp_end:
        li    a0, 0                     ; nothing seen: not a declaration, unless a storage
        bnez  s2, dsp_res               ;   class stood alone (then the type is int)
        ld    t0, ds_class(zero)        ; ...
        beqz  t0, dsp_ret               ; ...
dsp_res:
        mv    a0, s3                    ; a named type
        andi  t0, s2, DS_TYPE           ; ...
        bnez  t0, dsp_ret               ; ...
        li    a0, Y_VOID                ; ...
        andi  t0, s2, DS_VOID           ; ...
        bnez  t0, dsp_ret               ; ...
        li    a0, Y_BOOL                ; ...
        andi  t0, s2, DS_BOOL           ; ...
        bnez  t0, dsp_ret               ; ...
        li    a0, Y_DOUBLE              ; (long double is double)
        andi  t0, s2, DS_DOUBLE         ; ...
        bnez  t0, dsp_ret               ; ...
        li    a0, Y_FLOAT               ; ...
        andi  t0, s2, DS_FLOAT          ; ...
        bnez  t0, dsp_ret               ; ...
        li    a0, Y_CHAR                ; the integers: char, short, long, else int
        andi  t0, s2, DS_CHAR           ; ...
        bnez  t0, dsp_sign              ; ...
        li    a0, Y_SHORT               ; ...
        andi  t0, s2, DS_SHORT          ; ...
        bnez  t0, dsp_sign              ; ...
        li    a0, Y_LONG                ; ...
        andi  t0, s2, DS_LONG           ; ...
        bnez  t0, dsp_sign              ; ...
        li    a0, Y_INT                 ; ...
dsp_sign:
        andi  t0, s2, DS_UNS            ; unsigned: the record after the signed one
        beqz  t0, dsp_ret               ; ...
        addi  a0, a0, TYSZ              ; ...
dsp_ret:
        jalr  zero, gp, lv3-R           ; done

        .align 4096                     ; ---- unit: decl2 ----
u_decl2:
; declarator(a0 = the type the specifiers gave) -> a0 = the declared type;
; d_name = the identifier declared, if there is one (the caller clears it)
declarator:
        jalr  t6, gp, ent3-R            ; s1 = type, s2 = placeholder, s3 = the inner declarator's type
        mv    s1, a0                    ; ...
dcl_ptr:
        ld    t0, tok(zero)             ; * [qualifiers] ...
        li    t1, '*'                   ; ...
        bne   t0, t1, dcl_dir           ; ...
        mv    a0, s1                    ; ...
        jalr  ra, gp, ty_ptr-R          ; ...
        mv    s1, a0                    ; ...
dcl_q:
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        ld    t0, tok(zero)             ; ...
        li    t1, K_CONST               ; ...
        beq   t0, t1, dcl_q             ; ...
        li    t1, K_VOLATILE            ; ...
        beq   t0, t1, dcl_q             ; ...
        li    t1, K_RESTRICT            ; ...
        beq   t0, t1, dcl_q             ; ...
        j     dcl_ptr                   ; ...
dcl_dir:
        li    t1, T_ID                  ; a name
        bne   t0, t1, dcl_par           ; ...
        ld    t1, tk_val(zero)          ; ...
        sd    t1, d_name(zero)          ; ...
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        j     dcl_suf                   ; ...
dcl_par:
        li    t1, '('                   ; ( declarator ), or the parameters of an abstract function
        bne   t0, t1, dcl_suf           ; ...
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        ld    t0, tok(zero)             ; a nested declarator starts with * ( [ or a name that
        li    t1, '*'                   ;   is not a type
        beq   t0, t1, dcl_nest          ; ...
        li    t1, '('                   ; ...
        beq   t0, t1, dcl_nest          ; ...
        li    t1, '['                   ; ...
        beq   t0, t1, dcl_nest          ; ...
        li    t1, T_ID                  ; ...
        bne   t0, t1, dcl_fn            ; ...
        la    t6, is_type               ; ...
        xcall ra, c0, t6                ; ...
        beqz  a0, dcl_nest              ; ...
dcl_fn:
        mv    a0, s1                    ; parameters: a function returning the type so far
        la    t6, func_params           ; ...
        xcall ra, c0, t6                ; ...
        mv    s1, a0                    ; ...
        j     dcl_suf                   ; ...
dcl_nest:
        li    a0, 0                     ; the inner declarator is built on a placeholder,
        li    a1, 0                     ;   which becomes the outer type once that is known
        li    a2, 0                     ; ...
        li    a3, 0                     ; ...
        jalr  ra, gp, ty_new-R          ; ...
        mv    s2, a0                    ; ...
        la    t6, declarator            ; ...
        xcall ra, c0, t6                ; ...
        mv    s3, a0                    ; ...
        li    a0, ')'                   ; ...
        la    t6, skip                  ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s1                    ; what follows the ) applies to the outer type
        la    t6, d_suffix              ; ...
        xcall ra, c0, t6                ; ...
        ld    t0, 0(a0)                 ; the placeholder is that type now
        sd    t0, 0(s2)                 ; ...
        ld    t0, 8(a0)                 ; ...
        sd    t0, 8(s2)                 ; ...
        mv    a0, s3                    ; ...
        beq   s3, s2, dcl_whole         ; (a declarator of just parentheses: the type itself)
        jalr  zero, gp, lv3-R           ; ...
dcl_whole:
        jalr  zero, gp, lv3-R           ; ...
dcl_suf:
        mv    a0, s1                    ; ...
        la    t6, d_suffix              ; ...
        xcall ra, c0, t6                ; ...
        jalr  zero, gp, lv3-R           ; done

; d_suffix(a0 = type) -> a0 = the type with the [ ] and ( ) that follow applied
d_suffix:
        jalr  t6, gp, ent3-R            ; s1 = type, s2 = element count, s3 = scratch
        mv    s1, a0                    ; ...
        ld    t0, tok(zero)             ; ...
        li    t1, '('                   ; ...
        bne   t0, t1, dsf_arr           ; ...
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s1                    ; ...
        la    t6, func_params           ; ...
        xcall ra, c0, t6                ; ...
        jalr  zero, gp, lv3-R           ; ...
dsf_arr:
        li    t1, '['                   ; ...
        beq   t0, t1, dsf_a             ; ...
        mv    a0, s1                    ; nothing: the type as it is
        jalr  zero, gp, lv3-R           ; ...
dsf_a:
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        li    s2, 0                     ; [] has no size yet
        ld    t0, tok(zero)             ; ...
        li    t1, ']'                   ; ...
        beq   t0, t1, dsf_c             ; ...
        la    t6, const_expr            ; ...
        xcall ra, c0, t6                ; ...
        mv    s2, a0                    ; ...
dsf_c:
        li    a0, ']'                   ; ...
        la    t6, skip                  ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s1                    ; the element type: what follows applies to it first
        la    t6, d_suffix              ; ...
        xcall ra, c0, t6                ; ...
        mv    a3, a0                    ; ...
        lwu   a1, TY_SIZE(a3)           ; ...
        mul   a1, a1, s2                ; ...
        lbu   a2, TY_ALIGN(a3)          ; ...
        li    a0, TK_ARRAY              ; ...
        jalr  ra, gp, ty_new-R          ; ...
        sw    s2, TY_COUNT(a0)          ; ...
        jalr  zero, gp, lv3-R           ; done

; func_params(a0 = return type) -> a0 = the function type; the ( is behind us
func_params:
        jalr  t6, gp, ent6-R            ; s1 = function type, s2 = last parameter, s3 = count
        mv    a3, a0                    ; s4, s5 = the caller's d_name, ds_class, s6 = type
        li    a0, TK_FUNC               ; ...
        li    a1, 0                     ; ...
        li    a2, 1                     ; ...
        jalr  ra, gp, ty_new-R          ; ...
        mv    s1, a0                    ; ...
        ld    s4, d_name(zero)          ; ...
        ld    s5, ds_class(zero)        ; ...
        li    s2, 0                     ; ...
        li    s3, 0                     ; ...
        ld    t0, tok(zero)             ; ()
        li    t1, ')'                   ; ...
        bne   t0, t1, fpa_l             ; ...
        li    t0, TF_OLD                ; nothing is known about the parameters
        sb    t0, TY_FLAGS(s1)          ; ...
        j     fpa_end                   ; ...
fpa_l:
        ld    t0, tok(zero)             ; ...
        li    t1, T_ELL                 ; ...
        bne   t0, t1, fpa_p             ; ...
        li    t0, TF_VARIADIC           ; ...
        sb    t0, TY_FLAGS(s1)          ; ...
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        j     fpa_end                   ; ...
fpa_p:
        la    t6, decl_spec             ; a parameter declaration
        xcall ra, c0, t6                ; ...
        bnez  a0, fpa_d                 ; ...
        li    a0, m_expect              ; ...
        jalr  zero, gp, errtok-R        ; ...
fpa_d:
        sd    zero, d_name(zero)        ; ...
        la    t6, declarator            ; ...
        xcall ra, c0, t6                ; ...
        mv    s6, a0                    ; ...
        lbu   t0, TY_KIND(s6)           ; (void) alone: no parameters
        bnez  t0, fpa_adj               ; ...
        bnez  s3, fpa_adj               ; ...
