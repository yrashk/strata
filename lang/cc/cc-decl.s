; func_decl(a0 = identifier, a1 = function type) -> a0 = its symbol; a function
; the library exports is defined by that
func_decl:
        jalr  t6, gp, ent1-R            ; s1 = symbol
        mv    a2, a1                    ; ...
        li    a1, SC_FUNC               ; ...
        la    t6, sym_decl              ; ...
        xcall ra, c0, t6                ; ...
        mv    s1, a0                    ; ...
        lbu   t0, SY_FLAGS(s1)          ; known already?
        andi  t0, t0, SF_DEF            ; ...
        bnez  t0, fdc_ret               ; ...
        lwu   a0, SY_ID(s1)             ; in the library?
        la    t6, lib_lookup            ; ...
        xcall ra, c0, t6                ; ...
        bltz  a0, fdc_ret               ; ...
        sw    a0, SY_VAL(s1)            ; ...
        li    t0, SF_DEF | SF_EXT       ; (SF_EXT on a function: the library's, may be replaced)
        sb    t0, SY_FLAGS(s1)          ; ...
fdc_ret:
        mv    a0, s1                    ; ...
        jalr  zero, gp, lv1-R           ; done

; func_def(a0 = symbol): the function's body follows
func_def:
        jalr  t6, gp, ent6-R            ; s1 = symbol, s2 = symbol table mark, s3 = parameter, s4 = index, s5 = local
        mv    s1, a0                    ; ...
        lbu   t0, SY_FLAGS(s1)          ; defined twice? (the library's definition is replaced)
        li    t1, SF_DEF                ; ...
        bne   t0, t1, fdf_go            ; ...
        lwu   a0, SY_ID(s1)             ; ...
        jalr  ra, gp, id_name-R         ; ...
        mv    a1, a0                    ; ...
        li    a0, m_redef               ; ...
        jalr  zero, gp, error2-R        ; ...
fdf_go:
        sb    zero, SY_FLAGS(s1)        ; not defined until its end: calls to itself are fixups
        sd    s1, fn_sym(zero)          ; ...
        lhu   t0, SY_TYPE(s1)           ; ...
        lhu   t1, TY_BASE(t0)           ; ...
        sd    t1, fn_ret(zero)          ; ...
        la    t6, g_fn_begin            ; ...
        xcall ra, c0, t6                ; ...
        ld    s2, sym_top(zero)         ; the parameters and the body's block are one scope
        li    t0, 1                     ; ...
        sd    t0, scope(zero)           ; ...
        lhu   t0, SY_TYPE(s1)           ; ...
        lhu   s3, TY_AUX(t0)            ; ...
        li    s4, 0                     ; ...
fdf_p:
        beqz  s3, fdf_body              ; ...
        lwu   a0, SY_ID(s3)             ; a parameter: a local, stored from its register
        bnez  a0, fdf_pn                ; ...
        li    a0, m_expect              ; (it needs a name)
        jalr  zero, gp, errtok-R        ; ...
fdf_pn:
        li    a1, SC_AUTO               ; ...
        lhu   a2, SY_TYPE(s3)           ; ...
        la    t6, sym_decl              ; ...
        xcall ra, c0, t6                ; ...
        mv    s5, a0                    ; ...
        li    a0, 8                     ; a word of the frame
        li    a1, 8                     ; ...
        la    t6, fr_alloc_x            ; ...
        xcall ra, c0, t6                ; ...
        sw    a0, SY_VAL(s5)            ; ...
        mv    a3, a0                    ; sd a_i, offset(sp)
        li    a0, OP_SD                 ; ...
        addi  a1, s4, X_A0              ; ...
        li    a2, X_SP                  ; ...
        slti  t0, s4, 8                 ; (the first eight)
        beqz  t0, fdf_pnx               ; ...
        la    t6, g_mem                 ; ...
        xcall ra, c0, t6                ; ...
fdf_pnx:
        lhu   s3, SY_PREV(s3)           ; ...
        addi  s4, s4, 1                 ; ...
        j     fdf_p                     ; ...
fdf_body:
        ld    t0, fr_cur(zero)          ; (what the statements may not reuse)
        la    t6, block_body            ; { declarations and statements }
        xcall ra, c0, t6                ; ...
        lwu   a0, SY_ID(s1)             ; main returns 0 when it runs off its end
        jalr  ra, gp, id_name-R         ; ...
        lwu   t0, 0(a0)                 ; "main"
        li    t1, 0x6E69616D            ; ...
        bne   t0, t1, fdf_end           ; ...
        lbu   t0, 4(a0)                 ; ...
        bnez  t0, fdf_end               ; ...
        li    a0, X_A0                  ; ...
        li    a1, 0                     ; ...
        la    t6, g_li                  ; ...
        xcall ra, c0, t6                ; ...
fdf_end:
        ld    s4, fn_start(zero)        ; ...
        la    t6, g_fn_end              ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s2                    ; the scope ends
        la    t6, scope_exit            ; ...
        xcall ra, c0, t6                ; ...
        sd    zero, scope(zero)         ; ...
        sw    s4, SY_VAL(s1)            ; the function is defined
        li    t0, SF_DEF                ; ...
        sb    t0, SY_FLAGS(s1)          ; ...
        sd    zero, fn_sym(zero)        ; ...
        jalr  zero, gp, lv6-R           ; done

; static_var(a0 = identifier, a1 = type, a2 = storage class keyword): declare an
; object with static storage (file scope, or static/extern in a block), give
; it room in the data image and read its initialiser
static_var:
        jalr  t6, gp, ent4-R            ; s1 = symbol, s2 = type, s3 = class, s4 = scratch
        mv    s2, a1                    ; ...
        mv    s3, a2                    ; ...
        li    a1, SC_STATIC             ; ...
        mv    a2, s2                    ; ...
        la    t6, sym_decl              ; ...
        xcall ra, c0, t6                ; ...
        mv    s1, a0                    ; ...
        lhu   s2, SY_TYPE(s1)           ; (the type may be an earlier, more complete one)
        lbu   t0, SY_FLAGS(s1)          ; it has an address already?
        andi  t0, t0, SF_DEF            ; ...
        bnez  t0, stv_init              ; ...
        li    t0, K_EXTERN              ; extern: the library's object, if it exports one
        bne   s3, t0, stv_alloc         ; ...
        lwu   a0, SY_ID(s1)             ; ...
        la    t6, lib_lookup            ; ...
        xcall ra, c0, t6                ; ...
        bltz  a0, stv_alloc             ; ...
        sw    a0, SY_VAL(s1)            ; ...
        li    t0, SF_DEF                ; ...
        sb    t0, SY_FLAGS(s1)          ; ...
        j     stv_init                  ; ...
stv_alloc:
        lwu   a0, TY_SIZE(s2)           ; room for it, unless its size is not known yet
        bnez  a0, stv_room              ; ...
        li    t0, SF_EXT                ; (its address is not known either)
        sb    t0, SY_FLAGS(s1)          ; ...
        j     stv_init                  ; ...
stv_room:
        lbu   a1, TY_ALIGN(s2)          ; ...
        jalr  ra, gp, data_alloc-R      ; ...
        sw    a0, SY_VAL(s1)            ; ...
        li    t0, SF_DEF                ; ...
        sb    t0, SY_FLAGS(s1)          ; ...
stv_init:
        ld    t0, tok(zero)             ; = initialiser
        li    t1, '='                   ; ...
        bne   t0, t1, stv_ret           ; ...
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s1                    ; ...
        la    t6, static_init           ; ...
        xcall ra, c0, t6                ; ...
stv_ret:
        mv    a0, s1                    ; ...
        jalr  zero, gp, lv4-R           ; done

