; =============================================================================
; cc-gen.s: the code generator: value descriptors to instructions
; =============================================================================
;
; The parser pushes descriptors of values on the value stack (VSTK, entries
; of VSZ bytes, layout V_*) and calls the routines here to combine them.
; Nothing is emitted for a constant or a variable until an operation needs
; it in a register. Evaluation registers are t0..t5 (indices 0..5 in V_REG,
; numbers in `ereg`) and a0 as index 6, which only a call's result uses.
; `nreg` is the set of indices in use, one bit each.
;
; A function marked (leaf) calls only resident code: its own unit may call it
; with a plain `call`; other units use xcall.

VF_INV   = 2                            ; VK_JMP: the jumps are taken when the value is false
VK_JMP   = 8                            ; the value is where control goes: V_VAL = a chain of jumps

        .data                           ; the generator's variables
        .align 8                        ; (words first)
sp_bias:  .dword 0                      ; bytes sp is below the frame (around a call with stack arguments)
FXB:      .space 16                     ; a fixup record being written

        .far                            ; code units
        .align 4096                     ; ---- unit: gen1 ----
u_gen1:
; ralloc() -> a0 = a free evaluation register index 0..5  (leaf, no frame)
ralloc:
        ld    t0, nreg(zero)            ; the set in use
        li    a0, 0                     ; the lowest free one
ral_l:
        srl   t1, t0, a0                ; ...
        andi  t1, t1, 1                 ; ...
        beqz  t1, ral_f                 ; ...
        addi  a0, a0, 1                 ; ...
        slti  t1, a0, 6                 ; ...
        bnez  t1, ral_l                 ; ...
        li    a0, m_vfull               ; none: the expression needs more than six
        jalr  zero, gp, error-R         ; ...
ral_f:
        li    t1, 1                     ; take it
        sll   t1, t1, a0                ; ...
        or    t0, t0, t1                ; ...
        sd    t0, nreg(zero)            ; ...
        ret                             ; done
; rfree(a0 = index)  (leaf, no frame)
rfree:
        li    t1, 1                     ; clear its bit
        sll   t1, t1, a0                ; ...
        ld    t0, nreg(zero)            ; ...
        or    t0, t0, t1                ; ...
        xor   t0, t0, t1                ; ...
        sd    t0, nreg(zero)            ; ...
        ret                             ; done
; v_rfree(a0 = entry): release the register the entry holds, if any  (leaf, no frame)
v_rfree:
        lbu   t0, V_KIND(a0)            ; a value in a register, or an address in one
        li    t1, VK_REG                ; ...
        beq   t0, t1, vrf_go            ; ...
        li    t1, VK_IND                ; ...
        bne   t0, t1, vrf_ret           ; ...
vrf_go:
        lbu   a0, V_REG(a0)             ; ...
        j     rfree                     ; ...
vrf_ret:
        ret                             ; done

; fr_alloc(a0 = bytes, a1 = alignment) -> a0 = a frame offset  (leaf, no frame)
fr_alloc:
        ld    t0, fr_cur(zero)          ; align
        add   t0, t0, a1                ; ...
        addi  t0, t0, -1                ; ...
        neg   t1, a1                    ; ...
        and   t0, t0, t1                ; ...
        add   t1, t0, a0                ; ...
        sd    t1, fr_cur(zero)          ; ...
        ld    t2, fr_max(zero)          ; the most the frame ever holds
        bgeu  t2, t1, fra_ret           ; ...
        sd    t1, fr_max(zero)          ; ...
fra_ret:
        mv    a0, t0                    ; ...
        ret                             ; done

; ralloc_x, st_op_x, ld_op_x, v_rfree_x, fr_alloc_x: the frame-less leaves above, for other units
ralloc_x:
        jalr  t6, gp, ent0-R            ; ...
        call  ralloc                    ; ...
        jalr  zero, gp, lv0-R           ; ...
st_op_x:
        jalr  t6, gp, ent0-R            ; ...
        call  st_op                     ; ...
        jalr  zero, gp, lv0-R           ; ...
ld_op_x:
        jalr  t6, gp, ent0-R            ; ...
        call  ld_op                     ; ...
        jalr  zero, gp, lv0-R           ; ...
v_rfree_x:
        jalr  t6, gp, ent0-R            ; ...
        call  v_rfree                   ; ...
        jalr  zero, gp, lv0-R           ; ...
fr_alloc_x:
        jalr  t6, gp, ent0-R            ; ...
        call  fr_alloc                  ; ...
        jalr  zero, gp, lv0-R           ; ...

; fix_add(a0 = location, a1 = symbol, a2 = kind, a3 = addend): a reference to be
; resolved when the symbol's address is known. The record names the symbol's
; identifier: the symbol itself may be a block's declaration, gone by then  (leaf)
fix_add:
        jalr  t6, gp, ent0-R            ; ...
        li    t0, FK_DATA               ; (a code fixup: not while nothing is emitted)
        beq   a2, t0, fxa_do            ; ...
        ld    t0, nocode(zero)          ; ...
        bnez  t0, fxa_ret               ; ...
fxa_do:
        sd    zero, FXB(zero)           ; the record
        sw    a0, FXB+FX_LOC(zero)      ; ...
        lwu   t0, SY_ID(a1)             ; ...
        sw    t0, FXB+FX_ID(zero)       ; ...
        sw    a3, FXB+FX_ADD(zero)      ; ...
        sb    a2, FXB+FX_KIND(zero)     ; ...
        ld    t0, fix_top(zero)         ; room?
        li    t1, F_FIXEND              ; ...
        bltu  t0, t1, fxa_ok            ; ...
        li    a0, m_fixfull             ; ...
        jalr  zero, gp, error-R         ; ...
fxa_ok:
        li    t1, FXB                   ; ...
        li    t2, 16                    ; ...
        tput  tg12, t1, c0, t0, t2      ; ...
        addi  t0, t0, 16                ; ...
        sd    t0, fix_top(zero)         ; ...
fxa_ret:
        jalr  zero, gp, lv0-R           ; done

; g_li(a0 = register number, a1 = value): load a constant  (leaf)
g_li:
        jalr  t6, gp, ent2-R            ; s1 = register, s2 = value
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        slli  t0, s2, 48                ; 16 signed bits: addi
        srai  t0, t0, 48                ; ...
        bne   t0, s2, gli_32            ; ...
        li    a0, OP_ADDI               ; ...
        mv    a1, s1                    ; ...
        li    a2, 0                     ; ...
        mv    a3, s2                    ; ...
        jalr  ra, gp, e_i-R             ; ...
        jalr  zero, gp, lv2-R           ; ...
gli_32:
        slli  t0, s2, 32                ; 32 signed bits: lui, ori
        srai  t0, t0, 32                ; ...
        bne   t0, s2, gli_64            ; ...
        li    a0, OP_LUI                ; ...
        mv    a1, s1                    ; ...
        li    a2, 0                     ; ...
        srai  a3, s2, 16                ; ...
        jalr  ra, gp, e_i-R             ; ...
gli_lo:
        andi  a3, s2, 0xffff            ; the low 16 bits, if any
        beqz  a3, gli_ret               ; ...
        li    a0, OP_ORI                ; ...
        mv    a1, s1                    ; ...
        mv    a2, s1                    ; ...
        jalr  ra, gp, e_i-R             ; ...
gli_ret:
        jalr  zero, gp, lv2-R           ; ...
gli_64:
        li    a0, OP_LUI                ; 64 bits: the top 32 as above
        mv    a1, s1                    ; ...
        li    a2, 0                     ; ...
        srai  a3, s2, 48                ; ...
        jalr  ra, gp, e_i-R             ; ...
        li    a0, OP_ORI                ; ...
        mv    a1, s1                    ; ...
        mv    a2, s1                    ; ...
        srli  a3, s2, 32                ; ...
        jalr  ra, gp, e_i-R             ; ...
        li    a0, OP_SLLI               ; then shifted up, 16 bits at a time
        mv    a1, s1                    ; ...
        mv    a2, s1                    ; ...
        li    a3, 16                    ; ...
        jalr  ra, gp, e_i-R             ; ...
        li    a0, OP_ORI                ; ...
        mv    a1, s1                    ; ...
        mv    a2, s1                    ; ...
        srli  a3, s2, 16                ; ...
        jalr  ra, gp, e_i-R             ; ...
        li    a0, OP_SLLI               ; ...
        mv    a1, s1                    ; ...
        mv    a2, s1                    ; ...
        li    a3, 16                    ; ...
        jalr  ra, gp, e_i-R             ; ...
        li    a0, OP_ORI                ; (this ori is emitted even when it adds nothing)
        mv    a1, s1                    ; ...
        mv    a2, s1                    ; ...
        mv    a3, s2                    ; ...
        jalr  ra, gp, e_i-R             ; ...
        jalr  zero, gp, lv2-R           ; done

; g_mem(a0 = opcode, a1 = data register, a2 = base register, a3 = offset):
; a load or store; an offset beyond 16 bits goes through tp  (leaf)
g_mem:
        jalr  t6, gp, ent4-R            ; s1 = opcode, s2 = register, s3 = base, s4 = offset
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        mv    s3, a2                    ; ...
        mv    s4, a3                    ; ...
        slli  t0, s4, 48                ; fits?
        srai  t0, t0, 48                ; ...
        beq   t0, s4, gme_go            ; ...
        li    a0, X_TP                  ; tp = offset + base
        mv    a1, s4                    ; ...
        call  g_li                      ; ...
        li    a0, A_ADD                 ; ...
        li    a1, X_TP                  ; ...
        li    a2, X_TP                  ; ...
        mv    a3, s3                    ; ...
        jalr  ra, gp, e_r-R             ; ...
        li    s3, X_TP                  ; ...
        li    s4, 0                     ; ...
gme_go:
        mv    a0, s1                    ; ...
        mv    a1, s2                    ; ...
        mv    a2, s3                    ; ...
        mv    a3, s4                    ; ...
        jalr  ra, gp, e_i-R             ; ...
        jalr  zero, gp, lv4-R           ; done

; g_addi(a0 = rd, a1 = rs, a2 = value): rd = rs + value  (leaf)
g_addi:
        jalr  t6, gp, ent3-R            ; s1 = rd, s2 = rs, s3 = value
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        mv    s3, a2                    ; ...
        bnez  s3, gad_do                ; adding nothing to itself: nothing
        beq   s1, s2, gad_ret           ; ...
gad_do:
        slli  t0, s3, 48                ; fits?
        srai  t0, t0, 48                ; ...
        bne   t0, s3, gad_big           ; ...
        li    a0, OP_ADDI               ; ...
        mv    a1, s1                    ; ...
        mv    a2, s2                    ; ...
        mv    a3, s3                    ; ...
        jalr  ra, gp, e_i-R             ; ...
        j     gad_ret                   ; ...
gad_big:
        li    a0, X_TP                  ; through tp
        mv    a1, s3                    ; ...
        call  g_li                      ; ...
        li    a0, A_ADD                 ; ...
        mv    a1, s1                    ; ...
        mv    a2, s2                    ; ...
        li    a3, X_TP                  ; ...
        jalr  ra, gp, e_r-R             ; ...
gad_ret:
        jalr  zero, gp, lv3-R           ; done

; ld_op(a0 = type) -> a0 = the opcode that loads a value of it  (leaf, no frame)
ld_op:
        lwu   t0, TY_SIZE(a0)           ; by size and signedness
        lbu   t1, TY_FLAGS(a0)          ; ...
        andi  t1, t1, TF_UNS            ; ...
        li    a0, OP_LD                 ; 8 bytes (and anything else: pointers)
        li    t2, 4                     ; ...
        bne   t0, t2, ldo_2             ; ...
        li    a0, OP_LW                 ; ...
        beqz  t1, ldo_ret               ; ...
        li    a0, OP_LWU                ; ...
        ret                             ; ...
ldo_2:
        li    t2, 2                     ; ...
        bne   t0, t2, ldo_1             ; ...
        li    a0, OP_LH                 ; ...
        beqz  t1, ldo_ret               ; ...
        li    a0, OP_LHU                ; ...
        ret                             ; ...
ldo_1:
        li    t2, 1                     ; ...
        bne   t0, t2, ldo_ret           ; ...
        li    a0, OP_LB                 ; ...
        beqz  t1, ldo_ret               ; ...
        li    a0, OP_LBU                ; ...
ldo_ret:
        ret                             ; done
; st_op(a0 = type) -> a0 = the opcode that stores a value of it  (leaf, no frame)
st_op:
        lwu   t0, TY_SIZE(a0)           ; by size
        li    a0, OP_SD                 ; ...
        li    t2, 4                     ; ...
        bne   t0, t2, sto_2             ; ...
        li    a0, OP_SW                 ; ...
        ret                             ; ...
sto_2:
        li    t2, 2                     ; ...
        bne   t0, t2, sto_1             ; ...
        li    a0, OP_SH                 ; ...
        ret                             ; ...
sto_1:
        li    t2, 1                     ; ...
        bne   t0, t2, sto_ret           ; ...
        li    a0, OP_SB                 ; ...
sto_ret:
        ret                             ; done

; g_ldst(a0 = opcode, a1 = data register, a2 = entry): load from or store to the
; lvalue the entry describes  (leaf)
g_ldst:
        jalr  t6, gp, ent3-R            ; s1 = opcode, s2 = register, s3 = entry
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        mv    s3, a2                    ; ...
        lbu   t0, V_KIND(s3)            ; ...
        li    t1, VK_LOC                ; a local: offset(sp) or offset(s0)
        bne   t0, t1, gls_glob          ; ...
        lbu   a2, V_REG(s3)             ; ...
        ld    a3, V_VAL(s3)             ; ...
        addi  t0, a2, -X_SP             ; (sp may be lowered for stack arguments)
        bnez  t0, gls_mem               ; ...
        ld    t0, sp_bias(zero)         ; ...
        add   a3, a3, t0                ; ...
        j     gls_mem                   ; ...
gls_glob:
        li    t1, VK_GLOB               ; a static object: address(zero) or address-R(gp)
        bne   t0, t1, gls_ind           ; ...
        lhu   a1, V_SYM(s3)             ; its address may not be known yet
        beqz  a1, gls_addr              ; ...
        ld    a0, code_pc(zero)         ; a fixup fills in base and offset
        li    a2, FK_MEM                ; ...
        ld    a3, V_VAL(s3)             ; ...
        call  fix_add                   ; ...
        li    a2, 0                     ; ...
        li    a3, 0                     ; ...
        j     gls_mem                   ; ...
gls_addr:
        ld    a3, V_VAL(s3)             ; ...
        li    a2, 0                     ; below 0x8000: from zero
        li    t0, 0x8000                ; ...
        bltu  a3, t0, gls_mem           ; ...
        li    a2, X_GP                  ; else from gp = 0x10000
        lui   t0, 1                     ; ...
        sub   a3, a3, t0                ; ...
        j     gls_mem                   ; ...
gls_ind:
        li    t1, VK_IND                ; through a register
        bne   t0, t1, gls_saved         ; ...
        lbu   t0, V_REG(s3)             ; ...
        lbu   a2, ereg(t0)              ; ...
        ld    a3, V_VAL(s3)             ; ...
        j     gls_mem                   ; ...
gls_saved:
        li    a0, OP_LD                 ; through an address kept in the frame: t6 = it
        li    a1, X_T6                  ; ...
        lbu   a2, V_REG(s3)             ; (the slot is addressed from sp or s0)
        lw    a3, V_SLOT(s3)            ; ...
        addi  t0, a2, -X_SP             ; ...
        bnez  t0, gls_sv2               ; ...
        ld    t0, sp_bias(zero)         ; ...
        add   a3, a3, t0                ; ...
gls_sv2:
        call  g_mem                     ; ...
        li    a2, X_T6                  ; ...
        ld    a3, V_VAL(s3)             ; ...
gls_mem:
        mv    a0, s1                    ; ...
        mv    a1, s2                    ; ...
        call  g_mem                     ; ...
        jalr  zero, gp, lv3-R           ; done

; gv(a0 = entry) -> a0 = evaluation register index: put the value in a register
; (the entry becomes VK_REG). The value of a narrow type may be dirty.  (leaf)
gv:
        jalr  t6, gp, ent3-R            ; s1 = entry, s2 = register index
        mv    s1, a0                    ; ...
        lbu   t0, V_KIND(s1)            ; ...
        li    t1, VK_REG                ; there already
        bne   t0, t1, gv_const          ; ...
        lbu   a0, V_REG(s1)             ; ...
        jalr  zero, gp, lv3-R           ; ...
gv_const:
        li    t1, VK_CONST              ; a constant
        bne   t0, t1, gv_laddr          ; ...
        call  ralloc                    ; ...
        mv    s2, a0                    ; ...
        lhu   a1, V_SYM(s1)             ; an address not known yet?
        beqz  a1, gv_li                 ; no
        ld    a0, code_pc(zero)         ; lui/ori, filled in by a fixup
        li    a2, FK_LUI                ; ...
        ld    a3, V_VAL(s1)             ; ...
        call  fix_add                   ; ...
        li    a0, OP_LUI                ; ...
        lbu   a1, ereg(s2)              ; ...
        li    a2, 0                     ; ...
        li    a3, 0                     ; ...
        jalr  ra, gp, e_i-R             ; ...
        li    a0, OP_ORI                ; ...
        lbu   a1, ereg(s2)              ; ...
        mv    a2, a1                    ; ...
        li    a3, 0                     ; ...
        jalr  ra, gp, e_i-R             ; ...
        j     gv_set                    ; ...
gv_li:
        lbu   a0, ereg(s2)              ; ...
        ld    a1, V_VAL(s1)             ; ...
        call  g_li                      ; ...
        j     gv_set                    ; ...
gv_laddr:
        li    t1, VK_LADDR              ; the address of a local
        bne   t0, t1, gv_jmp            ; ...
        call  ralloc                    ; ...
        mv    s2, a0                    ; ...
        lbu   a0, ereg(s2)              ; ...
        lbu   a1, V_REG(s1)             ; ...
        ld    a2, V_VAL(s1)             ; ...
        addi  t0, a1, -X_SP             ; ...
        bnez  t0, gv_la2                ; ...
        ld    t0, sp_bias(zero)         ; ...
        add   a2, a2, t0                ; ...
gv_la2:
        call  g_addi                    ; ...
        j     gv_set                    ; ...
gv_jmp:
        li    t1, VK_JMP                ; a pending jump: make it 0 or 1
        bne   t0, t1, gv_lval           ; ...
        mv    a0, s1                    ; ...
        la    t6, g_jmpval              ; (in another unit; it sets the entry)
        xcall ra, c0, t6                ; ...
        lbu   a0, V_REG(s1)             ; ...
        jalr  zero, gp, lv3-R           ; ...
gv_lval:
        li    t1, VK_IND                ; an lvalue: load it; one addressed by a register
        bne   t0, t1, gv_new            ;   loads into that register
        lbu   s2, V_REG(s1)             ; ...
        j     gv_load                   ; ...
gv_new:
        call  ralloc                    ; ...
        mv    s2, a0                    ; ...
gv_load:
        lhu   a0, V_TYPE(s1)            ; ...
        call  ld_op                     ; ...
        lbu   a1, ereg(s2)              ; ...
        mv    a2, s1                    ; ...
        call  g_ldst                    ; ...
        lbu   s3, V_BW(s1)              ; a bit-field: shift it to the top, and down again
        beqz  s3, gv_set                ; ...
        li    a3, 64                    ; ...
        sub   a3, a3, s3                ; ...
        lbu   t0, V_BOFF(s1)            ; ...
        sub   a3, a3, t0                ; ...
        li    a0, OP_SLLI               ; ...
        lbu   a1, ereg(s2)              ; ...
        mv    a2, a1                    ; ...
        jalr  ra, gp, e_i-R             ; ...
        li    a3, 64                    ; ...
        sub   a3, a3, s3                ; ...
        lhu   t0, V_TYPE(s1)            ; (logical if the field is unsigned)
        lbu   t0, TY_FLAGS(t0)          ; ...
        andi  t0, t0, TF_UNS            ; ...
        li    a0, OP_SRAI               ; ...
        sub   a0, a0, t0                ; ...
        lbu   a1, ereg(s2)              ; ...
        mv    a2, a1                    ; ...
        jalr  ra, gp, e_i-R             ; ...
        sb    zero, V_BW(s1)            ; ...
gv_set:
        li    t0, VK_REG                ; ...
        sb    t0, V_KIND(s1)            ; ...
        sb    s2, V_REG(s1)             ; ...
        sb    zero, V_FLAGS(s1)         ; (what a load or a constant gives is clean)
        sh    zero, V_SYM(s1)           ; ...
        sd    zero, V_VAL(s1)           ; ...
        mv    a0, s2                    ; ...
        jalr  zero, gp, lv3-R           ; done

; g_clean(a0 = entry in a register): extend a dirty narrow value to 64 bits  (leaf)
g_clean:
        jalr  t6, gp, ent3-R            ; s1 = entry, s2 = register number, s3 = shift
        mv    s1, a0                    ; ...
        lbu   t0, V_FLAGS(s1)           ; dirty?
        andi  t1, t0, VF_DIRTY          ; ...
        beqz  t1, gcl_ret               ; no
        xori  t0, t0, VF_DIRTY          ; not after this
        sb    t0, V_FLAGS(s1)           ; ...
        lhu   t2, V_TYPE(s1)            ; ...
        lwu   t3, TY_SIZE(t2)           ; 8 bytes are never dirty
        sltiu t4, t3, 8                 ; ...
        beqz  t4, gcl_ret               ; ...
        beqz  t3, gcl_ret               ; (nor is void)
        lbu   t0, V_REG(s1)             ; ...
        lbu   s2, ereg(t0)              ; ...
        slli  t3, t3, 3                 ; shift = 64 - bits
        li    s3, 64                    ; ...
        sub   s3, s3, t3                ; ...
        li    a0, OP_SLLI               ; up
        mv    a1, s2                    ; ...
        mv    a2, s2                    ; ...
        mv    a3, s3                    ; ...
        jalr  ra, gp, e_i-R             ; ...
        lhu   t2, V_TYPE(s1)            ; and down again: logical if unsigned
        lbu   t0, TY_FLAGS(t2)          ; ...
        andi  t0, t0, TF_UNS            ; ...
        li    a0, OP_SRAI               ; ...
        beqz  t0, gcl_dn                ; ...
        li    a0, OP_SRLI               ; ...
gcl_dn:
        mv    a1, s2                    ; ...
        mv    a2, s2                    ; ...
        mv    a3, s3                    ; ...
        jalr  ra, gp, e_i-R             ; ...
gcl_ret:
        jalr  zero, gp, lv3-R           ; done

; gv_c(a0 = entry) -> a0 = register index: in a register and clean  (leaf)
gv_c:
        jalr  t6, gp, ent1-R            ; s1 = entry
        mv    s1, a0                    ; ...
        la    t6, gv                    ; (gv may leave the unit: a far call)
        xcall ra, c0, t6                ; ...
        mv    a0, s1                    ; ...
        call  g_clean                   ; ...
        lbu   a0, V_REG(s1)             ; ...
        jalr  zero, gp, lv1-R           ; done

; g_into(a0 = entry, a1 = register number): the entry's clean value into that
; register; the entry's own register is released (the entry is dead)  (leaf)
g_into:
        jalr  t6, gp, ent2-R            ; s1 = entry, s2 = register
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        lbu   t0, V_KIND(s1)            ; ...
        li    t1, VK_CONST              ; a known constant: load it there
        bne   t0, t1, gin_lv            ; ...
        lhu   t1, V_SYM(s1)             ; ...
        bnez  t1, gin_reg               ; ...
        mv    a0, s2                    ; ...
        ld    a1, V_VAL(s1)             ; ...
        call  g_li                      ; ...
        j     gin_ret                   ; ...
gin_lv:
        addi  t1, t0, -VK_LOC           ; an lvalue (VK_LOC..VK_SAVED): load it there
        sltiu t1, t1, 4                 ; ...
        beqz  t1, gin_reg               ; ...
        lhu   a0, V_TYPE(s1)            ; ...
        call  ld_op                     ; ...
        mv    a1, s2                    ; ...
        mv    a2, s1                    ; ...
        call  g_ldst                    ; ...
        j     gin_free                  ; ...
gin_reg:
        mv    a0, s1                    ; anything else: through its register
        la    t6, gv_c                  ; ...
        xcall ra, c0, t6                ; ...
        lbu   a2, ereg(a0)              ; ...
        beq   a2, s2, gin_free          ; (it is there)
        li    a0, OP_ADDI               ; mv
        mv    a1, s2                    ; ...
        li    a3, 0                     ; ...
        jalr  ra, gp, e_i-R             ; ...
gin_free:
        mv    a0, s1                    ; ...
        call  v_rfree                   ; ...
gin_ret:
        li    t0, VK_CONST              ; the entry holds nothing now
        sb    t0, V_KIND(s1)            ; ...
        sh    zero, V_SYM(s1)           ; ...
        jalr  zero, gp, lv2-R           ; done

; vpop(): drop the top entry (a pending jump chain ends here)  (leaf)
vpop:
        jalr  t6, gp, ent1-R            ; s1 = entry
        ld    s1, vsp(zero)             ; ...
        lbu   t0, V_KIND(s1)            ; ...
        li    t1, VK_JMP                ; ...
        bne   t0, t1, vpo_r             ; ...
        ld    a0, V_VAL(s1)             ; its jumps land here
        ld    a1, code_pc(zero)         ; ...
        call  g_resolve                 ; ...
        j     vpo_d                     ; ...
vpo_r:
        mv    a0, s1                    ; ...
        call  v_rfree                   ; ...
vpo_d:
        addi  s1, s1, -VSZ              ; ...
        sd    s1, vsp(zero)             ; ...
        jalr  zero, gp, lv1-R           ; done

; g_spill(a0 = first entry to leave alone): every entry below it that holds a
; register is stored into the frame (before a call)  (leaf)
g_spill:
        jalr  t6, gp, ent3-R            ; s1 = entry, s2 = limit, s3 = slot
        mv    s2, a0                    ; ...
        li    s1, VSTK                  ; ...
gsp_l:
        bgeu  s1, s2, gsp_ret           ; ...
        ld    t0, nocode(zero)          ; nothing is emitted: what live code made stays in its register
        beqz  t0, gsp_k                 ; ...
        ld    t0, vlive(zero)           ; ...
        bleu  s1, t0, gsp_n             ; ...
gsp_k:
        lbu   t0, V_KIND(s1)            ; ...
        li    t1, VK_REG                ; a value
        beq   t0, t1, gsp_val           ; ...
        li    t1, VK_IND                ; an address
        beq   t0, t1, gsp_adr           ; ...
gsp_n:
        addi  s1, s1, VSZ               ; ...
        j     gsp_l                     ; ...
gsp_val:
        li    a0, 8                     ; a slot for it
        li    a1, 8                     ; ...
        call  fr_alloc                  ; ...
        mv    s3, a0                    ; ...
        lhu   a0, V_TYPE(s1)            ; stored with its own width: loading it back cleans it
        call  st_op                     ; ...
        lbu   t0, V_REG(s1)             ; ...
        lbu   a1, ereg(t0)              ; ...
        li    a2, X_SP                  ; ...
        ld    a3, sp_bias(zero)         ; ...
        add   a3, a3, s3                ; ...
        call  g_mem                     ; ...
        lbu   a0, V_REG(s1)             ; ...
        call  rfree                     ; ...
        li    t0, VK_LOC                ; it is a local now
        sb    t0, V_KIND(s1)            ; ...
        li    t0, X_SP                  ; ...
        sb    t0, V_REG(s1)             ; ...
        sb    zero, V_FLAGS(s1)         ; ...
        sd    s3, V_VAL(s1)             ; ...
        j     gsp_n                     ; ...
gsp_adr:
        li    a0, 8                     ; a slot for the address
        li    a1, 8                     ; ...
        call  fr_alloc                  ; ...
        mv    s3, a0                    ; ...
        li    a0, OP_SD                 ; ...
        lbu   t0, V_REG(s1)             ; ...
        lbu   a1, ereg(t0)              ; ...
        li    a2, X_SP                  ; ...
        ld    a3, sp_bias(zero)         ; ...
        add   a3, a3, s3                ; ...
        call  g_mem                     ; ...
        lbu   a0, V_REG(s1)             ; ...
        call  rfree                     ; ...
        li    t0, VK_SAVED              ; reached through the slot now
        sb    t0, V_KIND(s1)            ; ...
        li    t0, X_SP                  ; ...
        sb    t0, V_REG(s1)             ; ...
        sw    s3, V_SLOT(s1)            ; ...
        j     gsp_n                     ; ...
gsp_ret:
        jalr  zero, gp, lv3-R           ; done

; ---- jumps ---------------------------------------------------------------------------
; A forward jump is emitted with offset 0 and patched when its target is known.
; Jumps waiting for the same target form a chain through their offset fields:
; each holds the distance (in instructions) to the previous one, 0 in the first.

; g_jmp() -> a0 = the address of an unconditional jump to be patched  (leaf)
g_jmp:
        jalr  t6, gp, ent1-R            ; s1 = its address
        ld    s1, code_pc(zero)         ; ...
        li    a0, OP_JAL << 26          ; jal zero, 0
        jalr  ra, gp, emit-R            ; ...
        mv    a0, s1                    ; ...
        jalr  zero, gp, lv1-R           ; done

; g_setoff(a0 = address of a jump or branch, a1 = offset in bytes): set its offset field  (leaf)
g_setoff:
        jalr  t6, gp, ent2-R            ; s1 = address, s2 = offset
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        ld    t0, nocode(zero)          ; (nothing was emitted there)
        bnez  t0, gso_ret               ; ...
        jalr  ra, gp, code_rd-R         ; the instruction
        srai  s2, s2, 2                 ; in instructions
        srli  t0, a0, 26                ; jal has 21 bits, branches 16
        li    t1, 43                    ; ...
        addi  t0, t0, -OP_JAL           ; ...
        beqz  t0, gso_w                 ; ...
        li    t1, 48                    ; ...
gso_w:
        li    t3, 64                    ; t1 = 64 - the field's width, t3 = its width
        sub   t3, t3, t1                ; ...
        srl   a1, a0, t3                ; clear the field
        sll   a1, a1, t3                ; ...
        slli  t4, s2, 2                 ; (the target, for lab_pc)
        add   t4, t4, s1                ; ...
        sll   s2, s2, t1                ; the offset's low bits
        srl   s2, s2, t1                ; ...
        or    a1, a1, s2                ; ...
        ld    t5, lab_pc(zero)          ; remember the highest target
        bgeu  t5, t4, gso_put           ; ...
        sd    t4, lab_pc(zero)          ; ...
gso_put:
        mv    a0, s1                    ; ...
        jalr  ra, gp, code_wr-R         ; ...
gso_ret:
        jalr  zero, gp, lv2-R           ; done

; g_getoff(a0 = address of a jump or branch) -> a0 = its offset field in bytes  (leaf)
g_getoff:
        jalr  t6, gp, ent0-R            ; ...
        jalr  ra, gp, code_rd-R         ; ...
        srli  t0, a0, 26                ; ...
        li    t1, 43                    ; ...
        addi  t0, t0, -OP_JAL           ; ...
        beqz  t0, ggo_w                 ; ...
        li    t1, 48                    ; ...
ggo_w:
        sll   a0, a0, t1                ; sign-extend the field
        sra   a0, a0, t1                ; ...
        slli  a0, a0, 2                 ; ...
        jalr  zero, gp, lv0-R           ; done

; g_link(a0 = address of a jump, a1 = chain) -> a0 = the chain with the jump added  (leaf)
g_link:
        jalr  t6, gp, ent1-R            ; s1 = the jump
        mv    s1, a0                    ; ...
        beqz  a1, gln_ret               ; the first of its chain
        sub   a1, a1, s1                ; the distance to the previous one
        call  g_setoff                  ; ...
gln_ret:
        mv    a0, s1                    ; ...
        jalr  zero, gp, lv1-R           ; done

; g_resolve(a0 = chain, a1 = target): every jump of the chain goes to the target  (leaf)
g_resolve:
        jalr  t6, gp, ent3-R            ; s1 = a jump, s2 = target, s3 = the previous one
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        ld    t0, nocode(zero)          ; ...
        bnez  t0, grs_ret               ; ...
grs_l:
        beqz  s1, grs_ret               ; ...
        mv    a0, s1                    ; the link to the previous jump
        call  g_getoff                  ; ...
        li    s3, 0                     ; ...
        beqz  a0, grs_p                 ; ...
        add   s3, s1, a0                ; ...
grs_p:
        mv    a0, s1                    ; ...
        sub   a1, s2, s1                ; ...
        call  g_setoff                  ; ...
        mv    s1, s3                    ; ...
        j     grs_l                     ; ...
grs_ret:
        jalr  zero, gp, lv3-R           ; done

; g_join(a0 = chain, a1 = chain) -> a0 = one chain holding the jumps of both  (leaf)
g_join:
        jalr  t6, gp, ent3-R            ; s1 = first chain's head, s2 = second, s3 = cursor
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        beqz  s1, gjn_b                 ; one of them is empty
        beqz  s2, gjn_a                 ; ...
        ld    t0, nocode(zero)          ; ...
        bnez  t0, gjn_a                 ; ...
        mv    s3, s1                    ; find the first jump of the first chain
gjn_l:
        mv    a0, s3                    ; ...
        call  g_getoff                  ; ...
        beqz  a0, gjn_e                 ; ...
        add   s3, s3, a0                ; ...
        j     gjn_l                     ; ...
gjn_e:
        mv    a0, s3                    ; and link it to the second chain
        sub   a1, s2, s3                ; ...
        call  g_setoff                  ; ...
gjn_a:
        mv    a0, s1                    ; ...
        jalr  zero, gp, lv3-R           ; ...
gjn_b:
        mv    a0, s2                    ; ...
        jalr  zero, gp, lv3-R           ; done

        .align 4096                     ; ---- unit: gen2 ----
u_gen2:
; g_tst(a0 = sense, a1 = chain) -> a0 = chain: pop the top value and add to the
; chain a jump taken when the value is true (sense 0) or false (sense 1)
g_tst:
        jalr  t6, gp, ent4-R            ; s1 = sense, s2 = chain, s3 = entry, s4 = scratch
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        ld    s3, vsp(zero)             ; ...
        mv    a0, s3                    ; (an array or a function is tested as its address)
        la    t6, v_decay               ; ...
        xcall ra, c0, t6                ; ...
        lbu   t0, V_KIND(s3)            ; ...
        li    t1, VK_JMP                ; jumps already?
        bne   t0, t1, gts_const         ; ...
        lbu   t0, V_FLAGS(s3)           ; taken when false (1) or true (0)
        srli  t0, t0, 1                 ; ...
        andi  t0, t0, 1                 ; ...
        bne   t0, s1, gts_other         ; ...
        ld    a0, V_VAL(s3)             ; the same sense: they are our jumps
        mv    a1, s2                    ; ...
        la    t6, g_join                ; ...
        xcall ra, c0, t6                ; ...
        mv    s2, a0                    ; ...
        j     gts_drop                  ; ...
gts_other:
        la    t6, g_jmp                 ; the other sense: we jump from here,
        xcall ra, c0, t6                ; ...
        mv    a1, s2                    ; ...
        la    t6, g_link                ; ...
        xcall ra, c0, t6                ; ...
        mv    s2, a0                    ; ...
        ld    a0, V_VAL(s3)             ; and its jumps continue after ours
        ld    a1, code_pc(zero)         ; ...
        la    t6, g_resolve             ; ...
        xcall ra, c0, t6                ; ...
        j     gts_drop                  ; ...
gts_const:
        li    t1, VK_CONST              ; a constant: jump always or never
        bne   t0, t1, gts_reg           ; ...
        ld    t0, V_VAL(s3)             ; ...
        lhu   t1, V_SYM(s3)             ; (an address is true)
        or    t0, t0, t1                ; ...
        snez  t0, t0                    ; ...
        beq   t0, s1, gts_drop          ; never
        la    t6, g_jmp                 ; always
        xcall ra, c0, t6                ; ...
        mv    a1, s2                    ; ...
        la    t6, g_link                ; ...
        xcall ra, c0, t6                ; ...
        mv    s2, a0                    ; ...
        j     gts_drop                  ; ...
gts_reg:
        mv    a0, s3                    ; anything else: compare its register with zero
        la    t6, gv_c                  ; ...
        xcall ra, c0, t6                ; ...
        lbu   a1, ereg(a0)              ; ...
        ld    s4, code_pc(zero)         ; ...
        li    a0, OP_BNE                ; true: bne; false: beq
        sub   a0, a0, s1                ; ...
        li    a2, 0                     ; ...
        li    a3, 0                     ; ...
        jalr  ra, gp, e_i-R             ; ...
        mv    a0, s4                    ; ...
        mv    a1, s2                    ; ...
        la    t6, g_link                ; ...
        xcall ra, c0, t6                ; ...
        mv    s2, a0                    ; ...
        lbu   a0, V_REG(s3)             ; the register is free again
        li    t1, 1                     ; ...
        sll   t1, t1, a0                ; ...
        ld    t0, nreg(zero)            ; ...
        or    t0, t0, t1                ; ...
        xor   t0, t0, t1                ; ...
        sd    t0, nreg(zero)            ; ...
gts_drop:
        addi  s3, s3, -VSZ              ; pop
        sd    s3, vsp(zero)             ; ...
        mv    a0, s2                    ; ...
        jalr  zero, gp, lv4-R           ; done

; g_jmpval(a0 = entry of kind VK_JMP): make it 0 or 1 in a register
g_jmpval:
        jalr  t6, gp, ent4-R            ; s1 = entry, s2 = register index, s3 = sense, s4 = the jump
        mv    s1, a0                    ; ...
        lbu   s3, V_FLAGS(s1)           ; 1: the jumps are taken when it is false
        srli  s3, s3, 1                 ; ...
        andi  s3, s3, 1                 ; ...
        la    t6, ralloc_x              ; ...
        xcall ra, c0, t6                ; ...
        mv    s2, a0                    ; ...
        lbu   a0, ereg(s2)              ; falling through: the other value
        mv    a1, s3                    ; ...
        la    t6, g_li                  ; ...
        xcall ra, c0, t6                ; ...
        la    t6, g_jmp                 ; and over the jumps' value
        xcall ra, c0, t6                ; ...
        mv    s4, a0                    ; ...
        ld    a0, V_VAL(s1)             ; the jumps land here
        ld    a1, code_pc(zero)         ; ...
        la    t6, g_resolve             ; ...
        xcall ra, c0, t6                ; ...
        lbu   a0, ereg(s2)              ; ...
        xori  a1, s3, 1                 ; ...
        la    t6, g_li                  ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s4                    ; ...
        ld    a1, code_pc(zero)         ; ...
        sub   a1, a1, s4                ; ...
        la    t6, g_setoff              ; ...
        xcall ra, c0, t6                ; ...
        li    t0, VK_REG                ; an int in a register
        sb    t0, V_KIND(s1)            ; ...
        sb    s2, V_REG(s1)             ; ...
        sb    zero, V_FLAGS(s1)         ; ...
        li    t0, Y_INT                 ; ...
        sh    t0, V_TYPE(s1)            ; ...
        sd    zero, V_VAL(s1)           ; ...
        jalr  zero, gp, lv4-R           ; done

; g_store(): [lvalue, value] -> [value]: store the value (already of the
; lvalue's type) into the lvalue
g_store:
        jalr  t6, gp, ent4-R            ; s1 = lvalue, s2 = value, s3 = register number
        ld    s2, vsp(zero)             ; ...
        addi  s1, s2, -VSZ              ; ...
        lbu   t0, V_KIND(s1)            ; it must be an lvalue (VK_LOC..VK_SAVED)
        addi  t0, t0, -VK_LOC           ; ...
        sltiu t0, t0, 4                 ; ...
        bnez  t0, gst_ok                ; ...
        li    a0, m_lvalue              ; ...
        jalr  zero, gp, error-R         ; ...
gst_ok:
        lhu   t0, V_TYPE(s1)            ; a structure is copied
        lbu   t0, TY_KIND(t0)           ; ...
        addi  t0, t0, -TK_STRUCT        ; ...
        sltiu t0, t0, 2                 ; ...
        beqz  t0, gst_sc                ; ...
        la    t6, g_copy                ; ...
        xcall ra, c0, t6                ; ...
        jalr  zero, gp, lv4-R           ; ...
gst_sc:
        li    s3, 0                     ; the constant 0 is the zero register
        lbu   t0, V_KIND(s2)            ; ...
        addi  t0, t0, -VK_CONST         ; ...
        ld    t1, V_VAL(s2)             ; ...
        or    t0, t0, t1                ; ...
        lhu   t1, V_SYM(s2)             ; ...
        or    t0, t0, t1                ; ...
        beqz  t0, gst_st                ; ...
        mv    a0, s2                    ; anything else: in a register (dirty is fine)
        la    t6, gv                    ; ...
        xcall ra, c0, t6                ; ...
        lbu   s3, ereg(a0)              ; ...
gst_st:
        lbu   t0, V_BW(s1)              ; a bit-field is stored into its unit
        beqz  t0, gst_plain             ; ...
        la    t6, g_bfstore             ; (s1 = lvalue, s2 = value, s3 = the value's register)
        xcall ra, c0, t6                ; ...
        j     gst_done                  ; ...
gst_plain:
        lhu   a0, V_TYPE(s1)            ; ...
        la    t6, st_op_x               ; ...
        xcall ra, c0, t6                ; ...
        mv    a1, s3                    ; ...
        mv    a2, s1                    ; ...
        la    t6, g_ldst                ; ...
        xcall ra, c0, t6                ; ...
gst_done:
        mv    a0, s1                    ; the lvalue's register is free
        la    t6, v_rfree_x             ; ...
        xcall ra, c0, t6                ; ...
        ld    t0, 0(s2)                 ; the value takes the lvalue's place
        sd    t0, 0(s1)                 ; ...
        ld    t0, 8(s2)                 ; ...
        sd    t0, 8(s1)                 ; ...
        ld    t0, 16(s2)                ; ...
        sd    t0, 16(s1)                ; ...
        sd    s1, vsp(zero)             ; ...
        jalr  zero, gp, lv4-R           ; done

; g_fn_begin(): the prologue of the function being defined: two instructions,
; completed by g_fn_end when the frame's size is known. With fn_s0 set (a
; variadic function, or one with more than eight parameters) they come after
; a block that stores a0..a7 below the caller's stack arguments and points s0
; at them: every parameter is then at 8 * i (s0).
g_fn_begin:
        jalr  t6, gp, ent1-R            ; s1 = index
        sd    zero, nocode(zero)        ; code is emitted from here
        sd    zero, fr_cur(zero)        ; an empty frame
        sd    zero, fr_max(zero)        ; ...
        sd    zero, fr_keep(zero)       ; ...
        sd    zero, fn_rchain(zero)     ; ...
        sd    zero, nreg(zero)          ; ...
        ld    t1, paged(zero)           ; in the paged model a function starts on a word
        ld    t0, code_pc(zero)         ; ...
        andi  t0, t0, 4                 ; ...
        beqz  t0, gfb_go                ; ...
        beqz  t1, gfb_go                ; ...
        li    a0, 0                     ; padding (never executed)
        jalr  ra, gp, emit-R            ; ...
gfb_go:
        ld    t0, code_pc(zero)         ; ...
        sd    t0, fn_start(zero)        ; ...
        ld    t0, fix_top(zero)         ; (the fixups from here on are the function's)
        sd    t0, fn_fix0(zero)         ; ...
        ld    t0, fn_s0(zero)           ; ...
        beqz  t0, gfb_pro               ; ...
        li    a0, OP_ADDI               ; addi sp, sp, -80
        li    a1, X_SP                  ; ...
        li    a2, X_SP                  ; ...
        li    a3, -80                   ; ...
        jalr  ra, gp, e_i-R             ; ...
        li    a0, OP_SD                 ; sd s0, 0(sp)
        li    a1, X_S0                  ; ...
        li    a2, X_SP                  ; ...
        li    a3, 0                     ; ...
        jalr  ra, gp, e_i-R             ; ...
        li    s1, 0                     ; sd a_i, 16 + 8 i (sp)
gfb_a:
        li    a0, OP_SD                 ; ...
        addi  a1, s1, X_A0              ; ...
        li    a2, X_SP                  ; ...
        slli  a3, s1, 3                 ; ...
        addi  a3, a3, 16                ; ...
        jalr  ra, gp, e_i-R             ; ...
        addi  s1, s1, 1                 ; ...
        slti  t0, s1, 8                 ; ...
        bnez  t0, gfb_a                 ; ...
        li    a0, OP_ADDI               ; addi s0, sp, 16
        li    a1, X_S0                  ; ...
        li    a2, X_SP                  ; ...
        li    a3, 16                    ; ...
        jalr  ra, gp, e_i-R             ; ...
gfb_pro:
        ld    t0, code_pc(zero)         ; ...
        sd    t0, fn_pro(zero)          ; ...
        li    a0, 0                     ; addi sp, sp, -F
        jalr  ra, gp, emit-R            ; ...
        li    a0, 0                     ; sd ra, F-8(sp)
        jalr  ra, gp, emit-R            ; ...
        jalr  zero, gp, lv1-R           ; done

; g_fn_end(): the epilogue, and the prologue's two instructions
g_fn_end:
        jalr  t6, gp, ent2-R            ; s1 = frame size, s2 = scratch
        ld    s2, fn_rchain(zero)       ; a jump to the epilogue as the last instruction
        beqz  s2, gfe_res               ;   is dropped, unless something jumps past it
        ld    t0, code_pc(zero)         ; ...
        addi  t0, t0, -4                ; ...
        bne   s2, t0, gfe_res           ; ...
        ld    t1, lab_pc(zero)          ; ...
        bgtu  t1, t0, gfe_res           ; ...
        ld    t1, cw_base(zero)         ; (nor if it has left the code window)
        bltu  s2, t1, gfe_res           ; ...
        mv    a0, s2                    ; the rest of the chain
        la    t6, g_getoff              ; ...
        xcall ra, c0, t6                ; ...
        beqz  a0, gfe_one               ; ...
        add   a0, a0, s2                ; ...
gfe_one:
        sd    a0, fn_rchain(zero)       ; ...
        sd    s2, code_pc(zero)         ; ...
gfe_res:
        ld    a0, fn_rchain(zero)       ; returns jump here
        ld    a1, code_pc(zero)         ; ...
        la    t6, g_resolve             ; ...
        xcall ra, c0, t6                ; ...
        ld    s1, fr_max(zero)          ; F = locals, whole words, and ra
        addi  s1, s1, 15                ; ...
        srli  s1, s1, 3                 ; ...
        slli  s1, s1, 3                 ; ...
        li    t0, 32760                 ; ...
        bleu  s1, t0, gfe_ok            ; ...
        li    a0, m_frame               ; ...
        jalr  zero, gp, error-R         ; ...
gfe_ok:
        li    a0, OP_LD                 ; ld ra, F-8(sp)
        li    a1, X_RA                  ; ...
        li    a2, X_SP                  ; ...
        addi  a3, s1, -8                ; ...
        jalr  ra, gp, e_i-R             ; ...
        ld    t0, fn_s0(zero)           ; with the s0 block: s0 back, and its 80 bytes too
        beqz  t0, gfe_sp                ; ...
        li    a0, OP_LD                 ; ld s0, F(sp)
        li    a1, X_S0                  ; ...
        li    a2, X_SP                  ; ...
        mv    a3, s1                    ; ...
        jalr  ra, gp, e_i-R             ; ...
        addi  s2, s1, 80                ; ...
        j     gfe_add                   ; ...
gfe_sp:
        mv    s2, s1                    ; ...
gfe_add:
        li    a0, OP_ADDI               ; addi sp, sp, F
        li    a1, X_SP                  ; ...
        li    a2, X_SP                  ; ...
        mv    a3, s2                    ; ...
        jalr  ra, gp, e_i-R             ; ...
        ld    t0, paged(zero)           ; return: jalr zero, ra, 0, or xret ra
        bnez  t0, gfe_xret              ; ...
        li    a0, OP_JALR               ; ...
        li    a1, 0                     ; ...
        li    a2, X_RA                  ; ...
        li    a3, 0                     ; ...
        jalr  ra, gp, e_i-R             ; ...
        j     gfe_pro                   ; ...
gfe_xret:
        li    a0, OP_XCALL              ; ...
        li    a1, 0                     ; ...
        li    a2, X_RA                  ; ...
        li    a3, 16                    ; ...
        jalr  ra, gp, e_i-R             ; ...
gfe_pro:
        li    a0, OP_ADDI               ; the prologue: addi sp, sp, -F
        li    a1, X_SP                  ; ...
        li    a2, X_SP                  ; ...
        neg   a3, s1                    ; ...
        jalr  ra, gp, enc_i-R           ; ...
        mv    a1, a0                    ; ...
        ld    a0, fn_pro(zero)          ; ...
        jalr  ra, gp, code_wr-R         ; ...
        li    a0, OP_SD                 ; sd ra, F-8(sp)
        li    a1, X_RA                  ; ...
        li    a2, X_SP                  ; ...
        addi  a3, s1, -8                ; ...
        jalr  ra, gp, enc_i-R           ; ...
        mv    a1, a0                    ; ...
        ld    a0, fn_pro(zero)          ; ...
        addi  a0, a0, 4                 ; ...
        jalr  ra, gp, code_wr-R         ; ...
        ld    t0, paged(zero)           ; in the paged model the function must lie in one unit
        beqz  t0, gfe_done              ; ...
        la    t6, g_fn_place            ; ...
        xcall ra, c0, t6                ; ...
gfe_done:
        li    t0, 1                     ; no code outside functions
        sd    t0, nocode(zero)          ; ...
        jalr  zero, gp, lv2-R           ; done

        .align 4096                     ; ---- unit: gen2b ----
u_gen2b:
; g_fn_place(): paged model: if the function just emitted crosses a 4 KiB
; unit boundary, move it to the start of the next unit (its branches are
; relative; the fixups made inside it move with it)
F_TMP    = F_RES + 0x8000               ; where the function's code waits meanwhile
g_fn_place:
        jalr  t6, gp, ent6-R            ; s1 = start, s2 = end, s3 = distance, s4 = cursor, s5 = size, s6 = scratch
        ld    s1, fn_start(zero)        ; ...
        ld    s2, code_pc(zero)         ; ...
        addi  t0, s2, -4                ; in one unit already?
        srli  t0, t0, 12                ; ...
        srli  t1, s1, 12                ; ...
        beq   t0, t1, gfp_ret           ; ...
        sub   s5, s2, s1                ; ...
        li    t0, 4096                  ; ...
        bleu  s5, t0, gfp_mv            ; ...
        li    a0, m_fnbig               ; ...
        jalr  zero, gp, error-R         ; ...
gfp_mv:
        jalr  ra, gp, cw_flush-R        ; all of it is in the arena now
        addi  s5, s5, 7                 ; copy it aside, in whole words
        srli  s5, s5, 3                 ; ...
        slli  s5, s5, 3                 ; ...
        li    a0, F_TMP                 ; ...
        ld    t0, code_org(zero)        ; ...
        sub   a1, s1, t0                ; ...
        li    t0, F_CODE                ; ...
        add   a1, a1, t0                ; ...
        mv    a2, s5                    ; ...
        jalr  ra, gp, m_copy-R          ; ...
        srli  s3, s1, 12                ; the next unit's start
        addi  s3, s3, 1                 ; ...
        slli  s3, s3, 12                ; ...
        sub   s3, s3, s1                ; s3 = how far it moves
        sd    s1, code_pc(zero)         ; emit again from its old start: padding first
        srli  t0, s1, 10                ; (the code window holding that address)
        slli  t0, t0, 10                ; ...
        sd    t0, cw_base(zero)         ; ...
        ld    t1, code_org(zero)        ; ...
        sub   t1, t0, t1                ; ...
        li    t2, F_CODE                ; ...
        add   t1, t1, t2                ; ...
        li    t2, CW                    ; ...
        li    t3, CWSZ                  ; ...
        tget  tg14, t2, c0, t1, t3      ; ...
        mv    s4, s3                    ; ...
gfp_pad:
        beqz  s4, gfp_code              ; ...
        li    a0, 0                     ; ...
        jalr  ra, gp, emit-R            ; ...
        addi  s4, s4, -4                ; ...
        j     gfp_pad                   ; ...
gfp_code:
        li    s4, 0                     ; then the function's words
        sub   s5, s2, s1                ; ...
gfp_w:
        bgeu  s4, s5, gfp_fix           ; ...
        li    a0, F_TMP                 ; ...
        add   a0, a0, s4                ; ...
        jalr  ra, gp, far_lw-R          ; ...
        jalr  ra, gp, emit-R            ; ...
        addi  s4, s4, 4                 ; ...
        j     gfp_w                     ; ...
gfp_fix:
        ld    s4, fn_fix0(zero)         ; the fixups made inside the function
gfp_f:
        ld    t0, fix_top(zero)         ; ...
        bgeu  s4, t0, gfp_end           ; ...
        mv    a0, s4                    ; ...
        jalr  ra, gp, far_lw-R          ; its location
        bltu  a0, s1, gfp_fn            ; ...
        bgeu  a0, s2, gfp_fn            ; ...
        add   a1, a0, s3                ; ...
        mv    a0, s4                    ; ...
        jalr  ra, gp, far_sw-R          ; ...
gfp_fn:
        addi  s4, s4, 16                ; ...
        j     gfp_f                     ; ...
gfp_end:
        add   s1, s1, s3                ; the function starts there now
        sd    s1, fn_start(zero)        ; ...
gfp_ret:
        jalr  zero, gp, lv6-R           ; done

; g_bfstore(): for g_store (its s1 = bit-field lvalue, s2 = value entry, s3 =
; the value's register number, 0 for the constant 0): put the value's low
; bits into the field's place in its storage unit; the value's register is
; left holding the field's new value
g_bfstore:
        jalr  t6, gp, ent0-R            ; (s4 = the unit's register index: the caller's to lose)
        la    t6, ralloc_x              ; a register for the unit
        xcall ra, c0, t6                ; ...
        mv    s4, a0                    ; ...
        lhu   a0, V_TYPE(s1)            ; load it
        la    t6, ld_op_x               ; ...
        xcall ra, c0, t6                ; ...
        lbu   a1, ereg(s4)              ; ...
        mv    a2, s1                    ; ...
        la    t6, g_ldst                ; ...
        xcall ra, c0, t6                ; ...
        lbu   t0, V_BW(s1)              ; tp = ~(mask << first bit)
        li    a1, 1                     ; ...
        sll   a1, a1, t0                ; ...
        addi  a1, a1, -1                ; ...
        lbu   t1, V_BOFF(s1)            ; ...
        sll   a1, a1, t1                ; ...
        li    t2, -1                    ; ...
        xor   a1, a1, t2                ; ...
        li    a0, X_TP                  ; ...
        la    t6, g_li                  ; ...
        xcall ra, c0, t6                ; ...
        li    a0, A_AND                 ; unit &= tp
        lbu   a1, ereg(s4)              ; ...
        mv    a2, a1                    ; ...
        li    a3, X_TP                  ; ...
        jalr  ra, gp, e_r-R             ; ...
        beqz  s3, gbf_st                ; (storing the constant 0: nothing to or in)
        lbu   t0, V_BW(s1)              ; tp = (value << (64 - width)) >> (64 - width - first bit)
        li    a3, 64                    ; ...
        sub   a3, a3, t0                ; ...
        li    a0, OP_SLLI               ; ...
        li    a1, X_TP                  ; ...
        mv    a2, s3                    ; ...
        jalr  ra, gp, e_i-R             ; ...
        lbu   t0, V_BW(s1)              ; ...
        lbu   t1, V_BOFF(s1)            ; ...
        li    a3, 64                    ; ...
        sub   a3, a3, t0                ; ...
        sub   a3, a3, t1                ; ...
        li    a0, OP_SRLI               ; ...
        li    a1, X_TP                  ; ...
        li    a2, X_TP                  ; ...
        jalr  ra, gp, e_i-R             ; ...
        li    a0, A_OR                  ; unit |= tp
        lbu   a1, ereg(s4)              ; ...
        mv    a2, a1                    ; ...
        li    a3, X_TP                  ; ...
        jalr  ra, gp, e_r-R             ; ...
gbf_st:
        lhu   a0, V_TYPE(s1)            ; store the unit
        la    t6, st_op_x               ; ...
        xcall ra, c0, t6                ; ...
        lbu   a1, ereg(s4)              ; ...
        mv    a2, s1                    ; ...
        la    t6, g_ldst                ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s4                    ; ...
        la    t6, rfree_x               ; ...
        xcall ra, c0, t6                ; ...
        beqz  s3, gbf_ret               ; the value as the field holds it: extended from its width
        lbu   t0, V_BW(s1)              ; ...
        li    a3, 64                    ; ...
        sub   a3, a3, t0                ; ...
        li    a0, OP_SLLI               ; ...
        mv    a1, s3                    ; ...
        mv    a2, s3                    ; ...
        jalr  ra, gp, e_i-R             ; ...
        lbu   t0, V_BW(s1)              ; ...
        li    a3, 64                    ; ...
        sub   a3, a3, t0                ; ...
        lhu   t0, V_TYPE(s1)            ; ...
        lbu   t0, TY_FLAGS(t0)          ; ...
        andi  t0, t0, TF_UNS            ; ...
        li    a0, OP_SRAI               ; ...
        sub   a0, a0, t0                ; ...
        mv    a1, s3                    ; ...
        mv    a2, s3                    ; ...
        jalr  ra, gp, e_i-R             ; ...
        sb    zero, V_FLAGS(s2)         ; (clean now)
        lbu   t0, V_BW(s1)              ; (and an int, if the field is narrower than one)
        slti  t0, t0, 32                ; ...
        beqz  t0, gbf_ret               ; ...
        li    t0, Y_INT                 ; ...
        sh    t0, V_TYPE(s2)            ; ...
gbf_ret:
        jalr  zero, gp, lv0-R           ; done

; g_call(a0 = number of arguments): [function, arg1 .. argn] -> [result].
; Arguments go into a0..a7 and then onto the stack (sp is lowered for the
; call); a function returning a structure gets the address of a temporary as
; a hidden first argument, and that temporary is the result.
g_call:
        jalr  t6, gp, ent6-R            ; s1 = n, s2 = function entry, s3 = index, s4 = entry, s5 = function type, s6 = result slot or -1
        mv    s1, a0                    ; ...
        ld    s2, vsp(zero)             ; ...
        slli  t0, s1, 5                 ; (VSZ = 32)
        sub   s2, s2, t0                ; ...
        lhu   s5, V_TYPE(s2)            ; the function's type: a designator's, or a pointer's target
        lbu   t0, TY_KIND(s5)           ; ...
        li    t1, TK_FUNC               ; ...
        beq   t0, t1, gca_ty            ; ...
        li    t1, TK_PTR                ; ...
        bne   t0, t1, gca_notfn         ; ...
        lhu   s5, TY_BASE(s5)           ; ...
        lbu   t0, TY_KIND(s5)           ; ...
        li    t1, TK_FUNC               ; ...
        beq   t0, t1, gca_ty            ; ...
gca_notfn:
        li    a0, m_notfn               ; ...
        jalr  zero, gp, error-R         ; ...
gca_ty:
        li    s6, -1                    ; a structure result needs a temporary
        lhu   t0, TY_BASE(s5)           ; ...
        lbu   t1, TY_KIND(t0)           ; ...
        addi  t1, t1, -TK_STRUCT        ; ...
        sltiu t1, t1, 2                 ; ...
        beqz  t1, gca_sp                ; ...
        lwu   a0, TY_SIZE(t0)           ; ...
        lbu   a1, TY_ALIGN(t0)          ; ...
        la    t6, fr_alloc_x            ; ...
        xcall ra, c0, t6                ; ...
        mv    s6, a0                    ; ...
gca_sp:
        mv    a0, s2                    ; what is live below the call goes to the frame
        la    t6, g_spill               ; ...
        xcall ra, c0, t6                ; ...
        mv    s4, s2                    ; an earlier call's result in a0 would be overwritten:
        li    s3, 0                     ;   move it (only the first argument may stay there,
gca_mv:
        bgt   s3, s1, gca_stk           ;   and only if a0 is its place)
        li    t0, 1                     ; ...
        bne   s3, t0, gca_mv1           ; ...
        bltz  s6, gca_mvn               ; ...
gca_mv1:
        lbu   t0, V_KIND(s4)            ; ...
        addi  t0, t0, -VK_REG           ; ...
        bnez  t0, gca_mvn               ; ...
        lbu   t0, V_REG(s4)             ; ...
        addi  t0, t0, -6                ; ...
        bnez  t0, gca_mvn               ; ...
        mv    a0, s4                    ; (clean first: the move keeps the flag otherwise)
        la    t6, g_clean               ; ...
        xcall ra, c0, t6                ; ...
        la    t6, ralloc_x              ; ...
        xcall ra, c0, t6                ; ...
        sb    a0, V_REG(s4)             ; ...
        lbu   a1, ereg(a0)              ; mv
        li    a0, OP_ADDI               ; ...
        li    a2, X_A0                  ; ...
        li    a3, 0                     ; ...
        jalr  ra, gp, e_i-R             ; ...
        ld    t0, nreg(zero)            ; a0 is free
        andi  t0, t0, 63                ; ...
        sd    t0, nreg(zero)            ; ...
gca_mvn:
        addi  s3, s3, 1                 ; ...
        addi  s4, s4, VSZ               ; ...
        j     gca_mv                    ; ...
gca_stk:
        la    t6, g_callargs            ; the arguments into their places (s1, s2, s6 as here)
        xcall ra, c0, t6                ; ...
        la    t6, g_calljmp             ; the call itself (s2, s5)
        xcall ra, c0, t6                ; ...
        ld    a2, sp_bias(zero)         ; sp back above the stack arguments
        beqz  a2, gca_res               ; ...
        li    a0, X_SP                  ; ...
        li    a1, X_SP                  ; ...
        la    t6, g_addi                ; ...
        xcall ra, c0, t6                ; ...
        sd    zero, sp_bias(zero)       ; ...
gca_res:
        addi  t0, s2, -VSZ              ; pop the function and the arguments
        sd    t0, vsp(zero)             ; ...
        lhu   a1, TY_BASE(s5)           ; the result's type
        bltz  s6, gca_sc                ; a structure: the temporary
        li    a0, VK_LOC                ; ...
        mv    a2, s6                    ; ...
        jalr  ra, gp, vpush-R           ; ...
        li    t0, X_SP                  ; ...
        sb    t0, V_REG(a0)             ; ...
        jalr  zero, gp, lv6-R           ; ...
gca_sc:
        lbu   t0, TY_KIND(a1)           ; void: a value nobody may use
        bnez  t0, gca_val               ; ...
        li    a0, VK_CONST              ; ...
        li    a2, 0                     ; ...
        jalr  ra, gp, vpush-R           ; ...
        jalr  zero, gp, lv6-R           ; ...
gca_val:
        li    a0, VK_REG                ; in a0, clean
        li    a2, 0                     ; ...
        jalr  ra, gp, vpush-R           ; ...
        li    t0, 6                     ; (index 6)
        sb    t0, V_REG(a0)             ; ...
        ld    t0, nreg(zero)            ; ...
        ori   t0, t0, 64                ; ...
        sd    t0, nreg(zero)            ; ...
        jalr  zero, gp, lv6-R           ; done

; g_callargs(): for g_call (its s1 = n, s2 = function entry, s6 = result slot):
; lower sp for the arguments that do not fit eight registers and store them,
; load the others, and the address of the result's temporary
g_callargs:
        jalr  t6, gp, ent0-R            ; (s3 = index, s4 = entry: the caller's to lose)
        slti  t0, s6, 0                 ; t0 = 0 if a0 is taken by the result's address
        xori  t0, t0, 1                 ; ...
        add   t1, s1, t0                ; registers and stack words needed
        addi  t1, t1, -8                ; ...
        blez  t1, gcg_reg               ; ...
        slli  t1, t1, 3                 ; ...
        sd    t1, sp_bias(zero)         ; (locals are that much further from sp now)
        li    a0, X_SP                  ; ...
        li    a1, X_SP                  ; ...
        neg   a2, t1                    ; ...
        la    t6, g_addi                ; ...
        xcall ra, c0, t6                ; ...
        li    s3, 8                     ; the arguments from position 8 on
        slti  t0, s6, 0                 ; ...
        xori  t0, t0, 1                 ; ...
        sub   s3, s3, t0                ; s3 = the first such argument's index
gcg_s:
        bge   s3, s1, gcg_reg           ; ...
        addi  t0, s3, 1                 ; ...
        slli  t0, t0, 5                 ; ...
        add   a0, s2, t0                ; ...
        li    a1, X_TP                  ; through tp
        la    t6, g_into                ; ...
        xcall ra, c0, t6                ; ...
        li    a0, OP_SD                 ; sd tp, 8 * (position - 8) (sp)
        li    a1, X_TP                  ; ...
        li    a2, X_SP                  ; ...
        slti  t0, s6, 0                 ; ...
        xori  t0, t0, 1                 ; ...
        add   a3, s3, t0                ; ...
        addi  a3, a3, -8                ; ...
        slli  a3, a3, 3                 ; ...
        jalr  ra, gp, e_i-R             ; ...
        addi  s3, s3, 1                 ; ...
        j     gcg_s                     ; ...
gcg_reg:
        li    s3, 0                     ; the arguments in registers
gcg_r:
        bge   s3, s1, gcg_ret           ; ...
        slti  t0, s6, 0                 ; ...
        xori  t0, t0, 1                 ; ...
        add   a1, s3, t0                ; its position
        slti  t1, a1, 8                 ; ...
        beqz  t1, gcg_ret               ; ...
        addi  a1, a1, X_A0              ; ...
        addi  t0, s3, 1                 ; ...
        slli  t0, t0, 5                 ; ...
        add   a0, s2, t0                ; ...
        la    t6, g_into                ; ...
        xcall ra, c0, t6                ; ...
        addi  s3, s3, 1                 ; ...
        j     gcg_r                     ; ...
gcg_ret:
        bltz  s6, gcg_end               ; a0 = the address of the result's temporary
        li    a0, X_A0                  ; ...
        li    a1, X_SP                  ; ...
        ld    a2, sp_bias(zero)         ; ...
        add   a2, a2, s6                ; ...
        la    t6, g_addi                ; ...
        xcall ra, c0, t6                ; ...
gcg_end:
        jalr  zero, gp, lv0-R           ; done

; g_calljmp(): for g_call (its s2 = function entry, s5 = function type): emit the call
g_calljmp:
        jalr  t6, gp, ent0-R            ; (s4: the caller's to lose)
        lhu   t0, V_TYPE(s2)            ; a function designator: a direct call
        lbu   t0, TY_KIND(t0)           ; ...
        addi  t0, t0, -TK_FUNC          ; ...
        bnez  t0, gcj_ptr               ; ...
        lhu   a1, V_SYM(s2)             ; defined yet?
        beqz  a1, gcj_known             ; ...
        ld    a0, code_pc(zero)         ; no: a fixup
        li    a2, FK_JAL                ; ...
        ld    t0, paged(zero)           ; ...
        beqz  t0, gcj_fx                ; ...
        li    a2, FK_LUI                ; ...
gcj_fx:
        li    a3, 0                     ; ...
        la    t6, fix_add               ; ...
        xcall ra, c0, t6                ; ...
        li    s4, 0                     ; (address 0 for now)
        ld    t0, paged(zero)           ; ...
        bnez  t0, gcj_far               ; ...
        li    a0, OP_JAL                ; jal ra, 0
        li    a1, X_RA                  ; ...
        li    a2, 0                     ; ...
        li    a3, 0                     ; ...
        jalr  ra, gp, e_i-R             ; ...
        jalr  zero, gp, lv0-R           ; ...
gcj_known:
        ld    s4, V_VAL(s2)             ; s4 = its address
        ld    t0, paged(zero)           ; ...
        bnez  t0, gcj_pg                ; ...
        ld    t0, code_pc(zero)         ; jal ra, target
        sub   t0, s4, t0                ; ...
        srai  t0, t0, 2                 ; ...
        slli  t0, t0, 43                ; ...
        srli  t0, t0, 43                ; ...
        li    a0, OP_JAL << 26 | X_RA << 21 ; ...
        or    a0, a0, t0                ; ...
        jalr  ra, gp, emit-R            ; ...
        jalr  zero, gp, lv0-R           ; ...
gcj_pg:
        srli  t0, s4, 16                ; paged: a library function is resident,
        bnez  t0, gcj_far               ; ...
        li    a0, OP_JALR               ; reached from gp: jalr ra, gp, address - R
        li    a1, X_RA                  ; ...
        li    a2, X_GP                  ; ...
        mv    a3, s4                    ; (the low 16 bits are that difference)
        jalr  ra, gp, e_i-R             ; ...
        jalr  zero, gp, lv0-R           ; ...
gcj_far:
        li    a0, OP_LUI                ; a function in a code unit: lui/ori t6, xcall
        li    a1, X_T6                  ; ...
        li    a2, 0                     ; ...
        srli  a3, s4, 16                ; ...
        jalr  ra, gp, e_i-R             ; ...
        li    a0, OP_ORI                ; ...
        li    a1, X_T6                  ; ...
        li    a2, X_T6                  ; ...
        mv    a3, s4                    ; ...
        jalr  ra, gp, e_i-R             ; ...
        li    a0, OP_XCALL              ; xcall ra, c0, t6
        li    a1, X_RA                  ; ...
        li    a2, X_T6                  ; ...
        li    a3, 0                     ; ...
        jalr  ra, gp, e_i-R             ; ...
        jalr  zero, gp, lv0-R           ; ...
gcj_ptr:
        mv    a0, s2                    ; a pointer: its value into t6
        li    a1, X_T6                  ; ...
        la    t6, g_into                ; ...
        xcall ra, c0, t6                ; ...
        ld    t0, paged(zero)           ; ...
        beqz  t0, gcj_jalr              ; ...
        li    a0, OP_SRLI               ; paged: below 0x10000 it is resident
        li    a1, X_TP                  ; srli tp, t6, 16
        li    a2, X_T6                  ; ...
        li    a3, 16                    ; ...
        jalr  ra, gp, e_i-R             ; ...
        li    a0, OP_BEQ                ; beq tp, zero, +3
        li    a1, X_TP                  ; ...
        li    a2, 0                     ; ...
        li    a3, 3                     ; ...
        jalr  ra, gp, e_i-R             ; ...
        li    a0, OP_XCALL              ; xcall ra, c0, t6
        li    a1, X_RA                  ; ...
        li    a2, X_T6                  ; ...
        li    a3, 0                     ; ...
        jalr  ra, gp, e_i-R             ; ...
        li    a0, OP_JAL << 26 | 2      ; jal zero, +2
        jalr  ra, gp, emit-R            ; ...
gcj_jalr:
        li    a0, OP_JALR               ; jalr ra, t6, 0
        li    a1, X_RA                  ; ...
        li    a2, X_T6                  ; ...
        li    a3, 0                     ; ...
        jalr  ra, gp, e_i-R             ; ...
        jalr  zero, gp, lv0-R           ; done

        .align 4096                     ; ---- unit: gen3 ----
u_gen3:
; promote(a0 = type) -> a0: the integer promotions  (leaf, no frame)
promote:
        lbu   t0, TY_KIND(a0)           ; _Bool, char, short -> int
        addi  t0, t0, -TK_BOOL          ; ...
        sltiu t0, t0, 3                 ; ...
        beqz  t0, pro_ret               ; ...
        li    a0, Y_INT                 ; ...
pro_ret:
        ret                             ; done
; wrap(a0 = value, a1 = type) -> a0: the value as that type holds it  (leaf, no frame)
wrap:
        lwu   t0, TY_SIZE(a1)           ; 8 bytes (and void): as it is
        addi  t1, t0, -1                ; ...
        sltiu t1, t1, 7                 ; ...
        beqz  t1, wra_ret               ; ...
        slli  t0, t0, 3                 ; ...
        li    t1, 64                    ; ...
        sub   t1, t1, t0                ; ...
        sll   a0, a0, t1                ; ...
        lbu   t0, TY_FLAGS(a1)          ; ...
        andi  t0, t0, TF_UNS            ; ...
        bnez  t0, wra_u                 ; ...
        sra   a0, a0, t1                ; ...
        ret                             ; ...
wra_u:
        srl   a0, a0, t1                ; ...
wra_ret:
        ret                             ; done

; v_addrof(a0 = entry, a1 = type): the lvalue becomes its address, of that type
v_addrof:
        jalr  t6, gp, ent3-R            ; s1 = entry, s2 = type, s3 = register index
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        lbu   t0, V_KIND(s1)            ; ...
        li    t1, VK_LOC                ; a local: its address is not computed yet
        bne   t0, t1, vao_g             ; ...
        li    t0, VK_LADDR              ; ...
        j     vao_k                     ; ...
vao_g:
        li    t1, VK_GLOB               ; a static object: a constant
        bne   t0, t1, vao_i             ; ...
        li    t0, VK_CONST              ; ...
        j     vao_k                     ; ...
vao_i:
        li    t1, VK_IND                ; through a register: register + offset
        bne   t0, t1, vao_s             ; ...
        lbu   s3, V_REG(s1)             ; ...
        j     vao_add                   ; ...
vao_s:
        li    t1, VK_SAVED              ; through a frame slot: load the address
        beq   t0, t1, vao_sl            ; ...
        li    a0, m_lvalue              ; anything else has no address
        jalr  zero, gp, error-R         ; ...
vao_sl:
        la    t6, ralloc_x              ; ...
        xcall ra, c0, t6                ; ...
        mv    s3, a0                    ; ...
        li    a0, OP_LD                 ; ...
        lbu   a1, ereg(s3)              ; ...
        lbu   a2, V_REG(s1)             ; ...
        lw    a3, V_SLOT(s1)            ; ...
        addi  t0, a2, -X_SP             ; ...
        bnez  t0, vao_ld                ; ...
        ld    t0, sp_bias(zero)         ; ...
        add   a3, a3, t0                ; ...
vao_ld:
        la    t6, g_mem                 ; ...
        xcall ra, c0, t6                ; ...
vao_add:
        lbu   a0, ereg(s3)              ; ...
        mv    a1, a0                    ; ...
        ld    a2, V_VAL(s1)             ; ...
        la    t6, g_addi                ; ...
        xcall ra, c0, t6                ; ...
        sb    s3, V_REG(s1)             ; ...
        sd    zero, V_VAL(s1)           ; ...
        li    t0, VK_REG                ; ...
vao_k:
        sb    t0, V_KIND(s1)            ; ...
        sb    zero, V_FLAGS(s1)         ; ...
        sh    s2, V_TYPE(s1)            ; ...
        jalr  zero, gp, lv3-R           ; done

; v_decay(a0 = entry): an array becomes a pointer to its first element, a
; function a pointer to itself
v_decay:
        jalr  t6, gp, ent2-R            ; s1 = entry, s2 = type
        mv    s1, a0                    ; ...
        lhu   s2, V_TYPE(s1)            ; ...
        lbu   t0, TY_KIND(s2)           ; ...
        li    t1, TK_ARRAY              ; ...
        bne   t0, t1, vde_f             ; ...
        lhu   a0, TY_BASE(s2)           ; pointer to the element type
        j     vde_p                     ; ...
vde_f:
        li    t1, TK_FUNC               ; ...
        beq   t0, t1, vde_fn            ; ...
        lbu   t0, V_BW(s1)              ; a bit-field narrower than an int is an int
        beqz  t0, vde_ret               ; ...
        slti  t0, t0, 32                ; ...
        beqz  t0, vde_ret               ; ...
        mv    a0, s1                    ; ...
        la    t6, gv                    ; ...
        xcall ra, c0, t6                ; ...
        li    t0, Y_INT                 ; ...
        sh    t0, V_TYPE(s1)            ; ...
        j     vde_ret                   ; ...
vde_fn:
        mv    a0, s2                    ; pointer to the function type
vde_p:
        jalr  ra, gp, ty_ptr-R          ; ...
        mv    a1, a0                    ; ...
        mv    a0, s1                    ; ...
        la    t6, v_addrof              ; ...
        xcall ra, c0, t6                ; ...
vde_ret:
        jalr  zero, gp, lv2-R           ; done

; v_deref(a0 = entry): a pointer value becomes the lvalue it points to
v_deref:
        jalr  t6, gp, ent2-R            ; s1 = entry, s2 = type
        mv    s1, a0                    ; ...
        la    t6, v_decay               ; ...
        xcall ra, c0, t6                ; ...
        lhu   s2, V_TYPE(s1)            ; it must be a pointer
        lbu   t0, TY_KIND(s2)           ; ...
        addi  t0, t0, -TK_PTR           ; ...
        beqz  t0, vdr_ok                ; ...
        li    a0, m_type                ; ...
        jalr  zero, gp, error-R         ; ...
vdr_ok:
        lbu   t0, V_KIND(s1)            ; ...
        li    t1, VK_CONST              ; a constant address: a static object
        li    t2, VK_GLOB               ; ...
        beq   t0, t1, vdr_k             ; ...
        li    t1, VK_LADDR              ; the address of a local: the local
        li    t2, VK_LOC                ; ...
        beq   t0, t1, vdr_k             ; ...
        mv    a0, s1                    ; anything else: the pointer in a register
        la    t6, gv                    ; ...
        xcall ra, c0, t6                ; ...
        li    t2, VK_IND                ; ...
vdr_k:
        sb    t2, V_KIND(s1)            ; ...
        sb    zero, V_FLAGS(s1)         ; ...
        lhu   t0, TY_BASE(s2)           ; ...
        sh    t0, V_TYPE(s1)            ; ...
        jalr  zero, gp, lv2-R           ; done

; v_dupval(): push the value of the lvalue on top (the lvalue stays below it)
v_dupval:
        jalr  t6, gp, ent3-R            ; s1 = lvalue, s2 = the copy, s3 = register index
        ld    s1, vsp(zero)             ; ...
        lbu   t0, V_KIND(s1)            ; an lvalue?
        addi  t0, t0, -VK_LOC           ; ...
        sltiu t0, t0, 4                 ; ...
        bnez  t0, vdv_ok                ; ...
        li    a0, m_lvalue              ; ...
        jalr  zero, gp, error-R         ; ...
vdv_ok:
        li    a0, 0                     ; a new entry, the same as the lvalue
        li    a1, 0                     ; ...
        li    a2, 0                     ; ...
        jalr  ra, gp, vpush-R           ; ...
        mv    s2, a0                    ; ...
        ld    t0, 0(s1)                 ; ...
        sd    t0, 0(s2)                 ; ...
        ld    t0, 8(s1)                 ; ...
        sd    t0, 8(s2)                 ; ...
        ld    t0, 16(s1)                ; ...
        sd    t0, 16(s2)                ; ...
        lbu   t0, V_KIND(s1)            ; one addressed by a register is loaded now, into
        addi  t0, t0, -VK_IND           ;   another register; the others can wait
        bnez  t0, vdv_ret               ; ...
        la    t6, ralloc_x              ; ...
        xcall ra, c0, t6                ; ...
        mv    s3, a0                    ; ...
        lbu   t0, V_BW(s1)              ; (a bit-field: the copy gets the address in a register
        beqz  t0, vdv_ld                ;  of its own, and is loaded like any other)
        li    a0, OP_ADDI               ; ...
        lbu   a1, ereg(s3)              ; ...
        lbu   t0, V_REG(s1)             ; ...
        lbu   a2, ereg(t0)              ; ...
        li    a3, 0                     ; ...
        jalr  ra, gp, e_i-R             ; ...
        sb    s3, V_REG(s2)             ; ...
        j     vdv_ret                   ; ...
vdv_ld:
        lhu   a0, V_TYPE(s1)            ; ...
        la    t6, ld_op_x               ; ...
        xcall ra, c0, t6                ; ...
        lbu   a1, ereg(s3)              ; ...
        lbu   t0, V_REG(s1)             ; ...
        lbu   a2, ereg(t0)              ; ...
        ld    a3, V_VAL(s1)             ; ...
        la    t6, g_mem                 ; ...
        xcall ra, c0, t6                ; ...
        li    t0, VK_REG                ; ...
        sb    t0, V_KIND(s2)            ; ...
        sb    s3, V_REG(s2)             ; ...
        sb    zero, V_FLAGS(s2)         ; ...
        sd    zero, V_VAL(s2)           ; ...
vdv_ret:
        jalr  zero, gp, lv3-R           ; done

; g_cast(a0 = entry, a1 = type): convert the value to the type
g_cast:
        jalr  t6, gp, ent4-R            ; s1 = entry, s2 = to, s3 = from, s4 = scratch
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        la    t6, v_decay               ; ...
        xcall ra, c0, t6                ; ...
        lhu   s3, V_TYPE(s1)            ; ...
        beq   s2, s3, gct_ret           ; nothing to do
        lbu   t0, TY_KIND(s2)           ; to void or to a structure type: only the type changes
        beqz  t0, gct_type              ; ...
        sltiu t1, t0, TK_STRUCT         ; ...
        beqz  t1, gct_type              ; ...
        lbu   t1, TY_KIND(s3)           ; floating point on either side
        addi  t2, t0, -TK_FLOAT         ; ...
        sltiu t2, t2, 2                 ; ...
        addi  t3, t1, -TK_FLOAT         ; ...
        sltiu t3, t3, 2                 ; ...
        or    t2, t2, t3                ; ...
        beqz  t2, gct_int               ; ...
        mv    a0, s1                    ; ...
        mv    a1, s2                    ; ...
        la    t6, f_cast                ; ...
        xcall ra, c0, t6                ; ...
        j     gct_ret                   ; ...
gct_int:
        addi  t0, t0, -TK_BOOL          ; to _Bool: 0 or 1
        bnez  t0, gct_sz                ; ...
        lbu   t0, V_KIND(s1)            ; ...
        addi  t0, t0, -VK_CONST         ; ...
        bnez  t0, gct_breg              ; ...
        ld    t0, V_VAL(s1)             ; ...
        lhu   t1, V_SYM(s1)             ; ...
        or    t0, t0, t1                ; ...
        snez  t0, t0                    ; ...
        sd    t0, V_VAL(s1)             ; ...
        sh    zero, V_SYM(s1)           ; ...
        j     gct_type                  ; ...
gct_breg:
        mv    a0, s1                    ; ...
        la    t6, gv_c                  ; ...
        xcall ra, c0, t6                ; ...
        lbu   a1, ereg(a0)              ; sltu r, zero, r
        li    a0, A_SLTU                ; ...
        li    a2, 0                     ; ...
        mv    a3, a1                    ; ...
        jalr  ra, gp, e_r-R             ; ...
        j     gct_type                  ; ...
gct_sz:
        lwu   s4, TY_SIZE(s2)           ; s4 = size to; t4 = size from (a function: 8)
        lwu   t4, TY_SIZE(s3)           ; ...
        bnez  t4, gct_k                 ; ...
        li    t4, 8                     ; ...
gct_k:
        lbu   t0, V_KIND(s1)            ; ...
        li    t1, VK_CONST              ; a constant: converted here
        bne   t0, t1, gct_lv            ; ...
        lhu   t1, V_SYM(s1)             ; (an unknown address stays as it is)
        bnez  t1, gct_type              ; ...
        ld    a0, V_VAL(s1)             ; ...
        mv    a1, s2                    ; ...
        call  wrap                      ; ...
        sd    a0, V_VAL(s1)             ; ...
        j     gct_type                  ; ...
gct_lv:
        addi  t1, t0, -VK_LOC           ; an lvalue not loaded yet: a narrower or equal type
        sltiu t1, t1, 4                 ;   is read from the same bytes (not a bit-field)
        beqz  t1, gct_reg               ; ...
        lbu   t1, V_BW(s1)              ; ...
        bnez  t1, gct_reg               ; ...
        bleu  s4, t4, gct_type          ; ...
gct_reg:
        mv    a0, s1                    ; in a register
        la    t6, gv                    ; ...
        xcall ra, c0, t6                ; ...
        bleu  s4, t4, gct_narrow        ; ...
        mv    a0, s1                    ; wider: extend it as its old type says
        la    t6, g_clean               ; ...
        xcall ra, c0, t6                ; ...
        j     gct_type                  ; ...
gct_narrow:
        sltiu t0, s4, 8                 ; narrower, or the same size with another sign:
        beqz  t0, gct_type              ;   the upper bits are wrong until someone needs them
        lbu   t0, V_FLAGS(s1)           ; ...
        ori   t0, t0, VF_DIRTY          ; ...
        sb    t0, V_FLAGS(s1)           ; ...
gct_type:
        sh    s2, V_TYPE(s1)            ; ...
gct_ret:
        jalr  zero, gp, lv4-R           ; done

; g_unop(a0 = operator: - ~ ! +): apply it to the top value
g_unop:
        jalr  t6, gp, ent4-R            ; s1 = operator, s2 = entry, s3 = type, s4 = register number
        mv    s1, a0                    ; ...
        ld    s2, vsp(zero)             ; ...
        li    t0, '!'                   ; ...
        bne   s1, t0, gun_ar            ; ...
        lbu   t0, V_KIND(s2)            ; not: pending jumps change their sense
        addi  t0, t0, -VK_JMP           ; ...
        bnez  t0, gun_not               ; ...
        lbu   t0, V_FLAGS(s2)           ; ...
        xori  t0, t0, VF_INV            ; ...
        sb    t0, V_FLAGS(s2)           ; ...
        j     gun_ret                   ; ...
gun_not:
        mv    a0, s2                    ; ...
        la    t6, v_decay               ; ...
        xcall ra, c0, t6                ; ...
        lbu   t0, V_KIND(s2)            ; a constant
        addi  t0, t0, -VK_CONST         ; ...
        bnez  t0, gun_nreg              ; ...
        ld    t0, V_VAL(s2)             ; ...
        lhu   t1, V_SYM(s2)             ; ...
        or    t0, t0, t1                ; ...
        seqz  t0, t0                    ; ...
        sd    t0, V_VAL(s2)             ; ...
        sh    zero, V_SYM(s2)           ; ...
        j     gun_int                   ; ...
gun_nreg:
        mv    a0, s2                    ; sltiu r, r, 1
        la    t6, gv_c                  ; ...
        xcall ra, c0, t6                ; ...
        lbu   a1, ereg(a0)              ; ...
        li    a0, OP_SLTIU              ; ...
        mv    a2, a1                    ; ...
        li    a3, 1                     ; ...
        jalr  ra, gp, e_i-R             ; ...
gun_int:
        li    t0, Y_INT                 ; the result is an int
        sh    t0, V_TYPE(s2)            ; ...
        j     gun_ret                   ; ...
gun_ar:
        mv    a0, s2                    ; - ~ +: on the promoted operand
        la    t6, v_decay               ; ...
        xcall ra, c0, t6                ; ...
        lhu   a0, V_TYPE(s2)            ; ...
        lbu   t0, TY_KIND(a0)           ; floating point?
        addi  t0, t0, -TK_FLOAT         ; ...
        sltiu t0, t0, 2                 ; ...
        beqz  t0, gun_i                 ; ...
        mv    a0, s1                    ; ...
        la    t6, f_unop                ; ...
        xcall ra, c0, t6                ; ...
        j     gun_ret                   ; ...
gun_i:
        call  promote                   ; ...
        mv    s3, a0                    ; ...
        mv    a1, a0                    ; ...
        mv    a0, s2                    ; ...
        la    t6, g_cast                ; ...
        xcall ra, c0, t6                ; ...
        li    t0, '+'                   ; + does nothing more
        beq   s1, t0, gun_ret           ; ...
        lbu   t0, V_KIND(s2)            ; a constant
        addi  t0, t0, -VK_CONST         ; ...
        bnez  t0, gun_reg               ; ...
        ld    a0, V_VAL(s2)             ; ...
        neg   a0, a0                    ; ...
        li    t0, '-'                   ; ...
        beq   s1, t0, gun_cw            ; ...
        addi  a0, a0, -1                ; ~x = -x - 1
gun_cw:
        mv    a1, s3                    ; ...
        call  wrap                      ; ...
        sd    a0, V_VAL(s2)             ; ...
        j     gun_ret                   ; ...
gun_reg:
        mv    a0, s2                    ; sub r, zero, r
        la    t6, gv                    ; ...
        xcall ra, c0, t6                ; ...
        lbu   s4, ereg(a0)              ; ...
        li    a0, A_SUB                 ; ...
        mv    a1, s4                    ; ...
        li    a2, 0                     ; ...
        mv    a3, s4                    ; ...
        jalr  ra, gp, e_r-R             ; ...
        li    t0, '-'                   ; ...
        beq   s1, t0, gun_dirty         ; ...
        li    a0, OP_ADDI               ; ~: and addi r, r, -1
        mv    a1, s4                    ; ...
        mv    a2, s4                    ; ...
        li    a3, -1                    ; ...
        jalr  ra, gp, e_i-R             ; ...
gun_dirty:
        lwu   t0, TY_SIZE(s3)           ; an int result has garbage above bit 31
        sltiu t0, t0, 8                 ; ...
        beqz  t0, gun_ret               ; ...
        lbu   t0, V_FLAGS(s2)           ; ...
        ori   t0, t0, VF_DIRTY          ; ...
        sb    t0, V_FLAGS(s2)           ; ...
gun_ret:
        jalr  zero, gp, lv4-R           ; done

; g_copy(): [lvalue, value], both of a structure type: copy the value into
; the lvalue, a piece of the type's alignment at a time, through tp. The
; lvalue stays as the result.
g_copy:
        jalr  t6, gp, ent6-R            ; s1 = lvalue, s2 = value, s3 = bytes left, s4 = piece, s5 = load opcode, s6 = store opcode
        ld    s2, vsp(zero)             ; ...
        addi  s1, s2, -VSZ              ; ...
        lbu   t0, V_KIND(s2)            ; the value must be in memory too
        addi  t0, t0, -VK_LOC           ; ...
        sltiu t0, t0, 4                 ; ...
        bnez  t0, gcp_ok                ; ...
        li    a0, m_type                ; ...
        jalr  zero, gp, error-R         ; ...
gcp_ok:
        lhu   t0, V_TYPE(s1)            ; ...
        lwu   s3, TY_SIZE(t0)           ; ...
        lbu   s4, TY_ALIGN(t0)          ; ...
        li    s5, OP_LD                 ; the widest access the alignment allows
        li    s6, OP_SD                 ; ...
        li    t0, 8                     ; ...
        beq   s4, t0, gcp_l             ; ...
        li    s5, OP_LW                 ; ...
        li    s6, OP_SW                 ; ...
        li    t0, 4                     ; ...
        beq   s4, t0, gcp_l             ; ...
        li    s5, OP_LH                 ; ...
        li    s6, OP_SH                 ; ...
        li    t0, 2                     ; ...
        beq   s4, t0, gcp_l             ; ...
        li    s5, OP_LB                 ; ...
        li    s6, OP_SB                 ; ...
gcp_l:
        beqz  s3, gcp_end               ; ...
        mv    a0, s5                    ; tp = a piece of the value
        li    a1, X_TP                  ; ...
        mv    a2, s2                    ; ...
        la    t6, g_ldst                ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s6                    ; into the lvalue
        li    a1, X_TP                  ; ...
        mv    a2, s1                    ; ...
        la    t6, g_ldst                ; ...
        xcall ra, c0, t6                ; ...
        ld    t0, V_VAL(s1)             ; the next piece
        add   t0, t0, s4                ; ...
        sd    t0, V_VAL(s1)             ; ...
        ld    t0, V_VAL(s2)             ; ...
        add   t0, t0, s4                ; ...
        sd    t0, V_VAL(s2)             ; ...
        sub   s3, s3, s4                ; ...
        j     gcp_l                     ; ...
gcp_end:
        lhu   t0, V_TYPE(s1)            ; the lvalue as it was
        lwu   t0, TY_SIZE(t0)           ; ...
        ld    t1, V_VAL(s1)             ; ...
        sub   t1, t1, t0                ; ...
        sd    t1, V_VAL(s1)             ; ...
        mv    a0, s2                    ; the value goes
        la    t6, v_rfree_x             ; ...
        xcall ra, c0, t6                ; ...
        sd    s1, vsp(zero)             ; ...
        jalr  zero, gp, lv6-R           ; done

        .align 4096                     ; ---- unit: gen4 ----
u_gen4:
; arith(a0 = type, a1 = type) -> a0: the usual arithmetic conversions' common type  (leaf, no frame)
arith:
        lbu   t0, TY_KIND(a0)           ; promote both
        addi  t0, t0, -TK_BOOL          ; ...
        sltiu t0, t0, 3                 ; ...
        beqz  t0, ari_r                 ; ...
        li    a0, Y_INT                 ; ...
ari_r:
        lbu   t0, TY_KIND(a1)           ; ...
        addi  t0, t0, -TK_BOOL          ; ...
        sltiu t0, t0, 3                 ; ...
        beqz  t0, ari_c                 ; ...
        li    a1, Y_INT                 ; ...
ari_c:
        beq   a0, a1, ari_ret           ; the same: that one
        li    t0, Y_ULONG               ; unsigned long wins, then long, then unsigned
        beq   a0, t0, ari_ret           ; ...
        beq   a1, t0, ari_b             ; ...
        li    t0, Y_LONG                ; ...
        beq   a0, t0, ari_ret           ; ...
        beq   a1, t0, ari_b             ; ...
        li    a0, Y_UINT                ; ...
        ret                             ; ...
ari_b:
        mv    a0, a1                    ; ...
ari_ret:
        ret                             ; done
; pow2(a0 = value) -> a0 = log2 of it, or -1 if it is not a power of two  (leaf, no frame)
pow2:
        blez  a0, pw2_no                ; ...
        addi  t0, a0, -1                ; ...
        and   t0, t0, a0                ; ...
        bnez  t0, pw2_no                ; ...
        li    t0, 0                     ; ...
pw2_l:
        srli  a0, a0, 1                 ; ...
        beqz  a0, pw2_r                 ; ...
        addi  t0, t0, 1                 ; ...
        j     pw2_l                     ; ...
pw2_r:
        mv    a0, t0                    ; ...
        ret                             ; ...
pw2_no:
        li    a0, -1                    ; ...
        ret                             ; done

; g_binop(a0 = operator token): [left, right] -> [result]
g_binop:
        jalr  t6, gp, ent6-R            ; s1 = operator, s2 = left, s3 = right, s4 = type, s5, s6 = registers
        mv    s1, a0                    ; ...
        ld    s3, vsp(zero)             ; ...
        addi  s2, s3, -VSZ              ; ...
        mv    a0, s2                    ; arrays and functions are pointers here
        la    t6, v_decay               ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s3                    ; ...
        la    t6, v_decay               ; ...
        xcall ra, c0, t6                ; ...
        lhu   a0, V_TYPE(s2)            ; ...
        lhu   a1, V_TYPE(s3)            ; ...
        lbu   t0, TY_KIND(a0)           ; ...
        lbu   t1, TY_KIND(a1)           ; ...
        li    t2, TK_PTR                ; a pointer on either side
        beq   t0, t2, gbo_ptr           ; ...
        beq   t1, t2, gbo_ptr           ; ...
        addi  t2, t0, -1                ; both arithmetic (kinds 1..7)?
        sltiu t2, t2, 7                 ; ...
        addi  t3, t1, -1                ; ...
        sltiu t3, t3, 7                 ; ...
        and   t2, t2, t3                ; ...
        bnez  t2, gbo_ar                ; ...
gbo_bad:
        li    a0, m_type                ; ...
        jalr  zero, gp, error-R         ; ...
gbo_ar:
        sltiu t0, t0, TK_FLOAT          ; floating point on either side
        sltiu t1, t1, TK_FLOAT          ; ...
        and   t0, t0, t1                ; ...
        bnez  t0, gbo_int               ; ...
        mv    a0, s1                    ; ...
        la    t6, f_binop               ; ...
        xcall ra, c0, t6                ; ...
        jalr  zero, gp, lv6-R           ; ...
gbo_int:
        addi  t0, s1, -T_SHL            ; a shift: each operand is promoted by itself
        sltiu t0, t0, 2                 ; ...
        beqz  t0, gbo_common            ; ...
        la    t6, promote_x             ; ...
        xcall ra, c0, t6                ; ...
        mv    s4, a0                    ; the result has the left operand's type
        lhu   a0, V_TYPE(s3)            ; ...
        la    t6, promote_x             ; ...
        xcall ra, c0, t6                ; ...
        mv    a1, a0                    ; ...
        j     gbo_conv                  ; ...
gbo_common:
        call  arith                     ; ...
        mv    s4, a0                    ; ...
        mv    a1, a0                    ; ...
gbo_conv:
        mv    a0, s3                    ; convert both
        la    t6, g_cast                ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s2                    ; ...
        mv    a1, s4                    ; ...
        la    t6, g_cast                ; ...
        xcall ra, c0, t6                ; ...
gbo_go:
        lbu   t0, V_KIND(s2)            ; two constants: computed here
        lbu   t1, V_KIND(s3)            ; ...
        addi  t0, t0, -VK_CONST         ; ...
        addi  t1, t1, -VK_CONST         ; ...
        or    t0, t0, t1                ; ...
        lhu   t1, V_SYM(s2)             ; ...
        or    t0, t0, t1                ; ...
        lhu   t1, V_SYM(s3)             ; ...
        or    t0, t0, t1                ; ...
        bnez  t0, gbo_emit              ; ...
        la    t6, g_fold                ; ...
        xcall ra, c0, t6                ; (s1 = operator, s2, s3 = entries, s4 = type)
        j     gbo_pop                   ; ...
gbo_emit:
        slti  t0, s1, 128               ; a comparison? < > are characters, the others tokens
        beqz  t0, gbo_tk                ; ...
        li    t0, '<'                   ; ...
        beq   s1, t0, gbo_cmp           ; ...
        li    t0, '>'                   ; ...
        beq   s1, t0, gbo_cmp           ; ...
        j     gbo_arith                 ; ...
gbo_tk:
        addi  t0, s1, -T_EQ             ; T_EQ T_NE T_LE T_GE
        sltiu t0, t0, 4                 ; ...
        bnez  t0, gbo_cmp               ; ...
gbo_arith:
        la    t6, g_arith               ; s1..s4 as here
        xcall ra, c0, t6                ; ...
        j     gbo_pop                   ; ...
gbo_cmp:
        la    t6, g_cmp                 ; ...
        xcall ra, c0, t6                ; ...
gbo_pop:
        mv    a0, s3                    ; the right operand's register is free; pop it
        la    t6, v_rfree_x             ; ...
        xcall ra, c0, t6                ; ...
        sd    s2, vsp(zero)             ; ...
        jalr  zero, gp, lv6-R           ; done

gbo_ptr:
        slti  t2, s1, 128               ; comparisons: as unsigned long
        beqz  t2, gbo_ptk               ; ...
        li    t2, '<'                   ; ...
        beq   s1, t2, gbo_pcmp          ; ...
        li    t2, '>'                   ; ...
        beq   s1, t2, gbo_pcmp          ; ...
        li    t2, '-'                   ; ...
        beq   s1, t2, gbo_psub          ; ...
        li    t2, '+'                   ; ...
        bne   s1, t2, gbo_bad           ; ...
        li    t2, TK_PTR                ; pointer + integer, either way round: the pointer left
        beq   t0, t2, gbo_padd          ; ...
        ld    t0, 0(s2)                 ; swap the entries
        ld    t1, 0(s3)                 ; ...
        sd    t1, 0(s2)                 ; ...
        sd    t0, 0(s3)                 ; ...
        ld    t0, 8(s2)                 ; ...
        ld    t1, 8(s3)                 ; ...
        sd    t1, 8(s2)                 ; ...
        sd    t0, 8(s3)                 ; ...
        ld    t0, 16(s2)                ; ...
        ld    t1, 16(s3)                ; ...
        sd    t1, 16(s2)                ; ...
        sd    t0, 16(s3)                ; ...
        j     gbo_padd                  ; ...
gbo_ptk:
        addi  t2, s1, -T_EQ             ; ...
        sltiu t2, t2, 4                 ; ...
        beqz  t2, gbo_bad               ; ...
gbo_pcmp:
        li    s4, Y_ULONG               ; ...
        mv    a1, s4                    ; ...
        j     gbo_conv                  ; ...
gbo_psub:
        li    t2, TK_PTR                ; pointer - pointer?
        bne   t1, t2, gbo_padd          ; no: pointer - integer
        bne   t0, t2, gbo_bad           ; (integer - pointer is nothing)
gbo_padd:
        la    t6, g_ptrop               ; s1 = operator, s2, s3 = entries
        xcall ra, c0, t6                ; ...
        j     gbo_pop                   ; ...

; promote_x(a0 = type) -> a0: promote, for this unit
promote_x:
        lbu   t0, TY_KIND(a0)           ; ...
        addi  t0, t0, -TK_BOOL          ; ...
        sltiu t0, t0, 3                 ; ...
        beqz  t0, prx_ret               ; ...
        li    a0, Y_INT                 ; ...
prx_ret:
        xret  ra                        ; done

; g_fold(): s1 = operator, s2 = left, s3 = right (both constants), s4 = type:
; the left entry becomes the result  (the caller's registers are used as they are)
g_fold:
        jalr  t6, gp, ent0-R            ; ...
        ld    t0, V_VAL(s2)             ; a
        ld    t1, V_VAL(s3)             ; b
        lbu   t5, TY_FLAGS(s4)          ; t5 = unsigned
        andi  t5, t5, TF_UNS            ; ...
        li    t4, 0                     ; t4 = 1: a comparison (the result is an int)
        li    t2, '+'                   ; ...
        bne   s1, t2, gfo_1             ; ...
        add   a0, t0, t1                ; ...
        j     gfo_set                   ; ...
gfo_1:
        li    t2, '-'                   ; ...
        bne   s1, t2, gfo_2             ; ...
        sub   a0, t0, t1                ; ...
        j     gfo_set                   ; ...
gfo_2:
        li    t2, '*'                   ; ...
        bne   s1, t2, gfo_3             ; ...
        mul   a0, t0, t1                ; ...
        j     gfo_set                   ; ...
gfo_3:
        li    t2, '&'                   ; ...
        bne   s1, t2, gfo_4             ; ...
        and   a0, t0, t1                ; ...
        j     gfo_set                   ; ...
gfo_4:
        li    t2, '|'                   ; ...
        bne   s1, t2, gfo_5             ; ...
        or    a0, t0, t1                ; ...
        j     gfo_set                   ; ...
gfo_5:
        li    t2, '^'                   ; ...
        bne   s1, t2, gfo_6             ; ...
        xor   a0, t0, t1                ; ...
        j     gfo_set                   ; ...
gfo_6:
        li    t2, T_SHL                 ; ...
        bne   s1, t2, gfo_7             ; ...
        sll   a0, t0, t1                ; ...
        j     gfo_set                   ; ...
gfo_7:
        li    t2, T_SHR                 ; ...
        bne   s1, t2, gfo_8             ; ...
        sra   a0, t0, t1                ; ...
        beqz  t5, gfo_set               ; ...
        srl   a0, t0, t1                ; ...
        j     gfo_set                   ; ...
gfo_8:
        li    t2, '/'                   ; ...
        bne   s1, t2, gfo_9             ; ...
        li    a0, 0                     ; (division by zero: 0)
        beqz  t1, gfo_set               ; ...
        div   a0, t0, t1                ; ...
        beqz  t5, gfo_set               ; ...
        divu  a0, t0, t1                ; ...
        j     gfo_set                   ; ...
gfo_9:
        li    t2, '%'                   ; ...
        bne   s1, t2, gfo_c             ; ...
        li    a0, 0                     ; ...
        beqz  t1, gfo_set               ; ...
        rem   a0, t0, t1                ; ...
        beqz  t5, gfo_set               ; ...
        remu  a0, t0, t1                ; ...
        j     gfo_set                   ; ...
gfo_c:
        li    t4, 1                     ; comparisons
        slt   t2, t0, t1                ; t2 = a < b, t3 = b < a
        slt   t3, t1, t0                ; ...
        beqz  t5, gfo_c2                ; ...
        sltu  t2, t0, t1                ; ...
        sltu  t3, t1, t0                ; ...
gfo_c2:
        mv    a0, t2                    ; <
        li    t5, '<'                   ; ...
        beq   s1, t5, gfo_set           ; ...
        mv    a0, t3                    ; >
        li    t5, '>'                   ; ...
        beq   s1, t5, gfo_set           ; ...
        xori  a0, t3, 1                 ; <=
        li    t5, T_LE                  ; ...
        beq   s1, t5, gfo_set           ; ...
        xori  a0, t2, 1                 ; >=
        li    t5, T_GE                  ; ...
        beq   s1, t5, gfo_set           ; ...
        or    a0, t2, t3                ; !=
        li    t5, T_NE                  ; ...
        beq   s1, t5, gfo_set           ; ...
        xori  a0, a0, 1                 ; ==
gfo_set:
        bnez  t4, gfo_int               ; ...
        lwu   t0, TY_SIZE(s4)           ; wrap to the type (as `wrap`)
        addi  t1, t0, -1                ; ...
        sltiu t1, t1, 7                 ; ...
        beqz  t1, gfo_st                ; ...
        slli  t0, t0, 3                 ; ...
        li    t1, 64                    ; ...
        sub   t1, t1, t0                ; ...
        sll   a0, a0, t1                ; ...
        lbu   t0, TY_FLAGS(s4)          ; ...
        andi  t0, t0, TF_UNS            ; ...
        bnez  t0, gfo_wu                ; ...
        sra   a0, a0, t1                ; ...
        j     gfo_st                    ; ...
gfo_wu:
        srl   a0, a0, t1                ; ...
gfo_st:
        sh    s4, V_TYPE(s2)            ; ...
        sd    a0, V_VAL(s2)             ; ...
        jalr  zero, gp, lv0-R           ; ...
gfo_int:
        li    t0, Y_INT                 ; ...
        sh    t0, V_TYPE(s2)            ; ...
        sd    a0, V_VAL(s2)             ; ...
        jalr  zero, gp, lv0-R           ; done

; g_cmp(): s1 = comparison, s2 = left, s3 = right, s4 = their type: emit it;
; the left entry becomes the result, an int
g_cmp:
        jalr  t6, gp, ent0-R            ; (s5, s6 = register numbers: the caller's to lose)
        mv    a0, s2                    ; the left operand, clean
        la    t6, gv_c                  ; ...
        xcall ra, c0, t6                ; ...
        lbu   s5, ereg(a0)              ; ...
        addi  t0, s1, -T_EQ             ; == or != with the constant 0 needs no second register
        sltiu t0, t0, 2                 ; ...
        beqz  t0, gcm_r                 ; ...
        lbu   t0, V_KIND(s3)            ; ...
        addi  t0, t0, -VK_CONST         ; ...
        ld    t1, V_VAL(s3)             ; ...
        or    t0, t0, t1                ; ...
        lhu   t1, V_SYM(s3)             ; ...
        or    t0, t0, t1                ; ...
        beqz  t0, gcm_eq                ; ...
gcm_r:
        mv    a0, s3                    ; the right operand, clean
        la    t6, gv_c                  ; ...
        xcall ra, c0, t6                ; ...
        lbu   s6, ereg(a0)              ; ...
        addi  t0, s1, -T_EQ             ; ...
        sltiu t0, t0, 2                 ; ...
        beqz  t0, gcm_rel               ; ...
        li    a0, A_XOR                 ; == !=: xor, then compare with zero
        mv    a1, s5                    ; ...
        mv    a2, s5                    ; ...
        mv    a3, s6                    ; ...
        jalr  ra, gp, e_r-R             ; ...
gcm_eq:
        li    t0, T_EQ                  ; ...
        bne   s1, t0, gcm_ne            ; ...
        li    a0, OP_SLTIU              ; sltiu r, r, 1
        mv    a1, s5                    ; ...
        mv    a2, s5                    ; ...
        li    a3, 1                     ; ...
        jalr  ra, gp, e_i-R             ; ...
        j     gcm_done                  ; ...
gcm_ne:
        li    a0, A_SLTU                ; sltu r, zero, r
        mv    a1, s5                    ; ...
        li    a2, 0                     ; ...
        mv    a3, s5                    ; ...
        jalr  ra, gp, e_r-R             ; ...
        j     gcm_done                  ; ...
gcm_rel:
        lbu   t0, TY_FLAGS(s4)          ; slt or sltu
        andi  t0, t0, TF_UNS            ; ...
        li    a0, A_SLT                 ; ...
        add   a0, a0, t0                ; (A_SLTU = A_SLT + 1 = A_SLT + TF_UNS)
        mv    a1, s5                    ; ...
        mv    a2, s5                    ; < and >=: left < right
        mv    a3, s6                    ; ...
        li    t0, '<'                   ; ...
        beq   s1, t0, gcm_slt           ; ...
        li    t0, T_GE                  ; ...
        beq   s1, t0, gcm_slt           ; ...
        mv    a2, s6                    ; > and <=: right < left
        mv    a3, s5                    ; ...
gcm_slt:
        jalr  ra, gp, e_r-R             ; ...
        addi  t0, s1, -T_LE             ; <= and >= are the opposite: xori r, r, 1
        sltiu t0, t0, 2                 ; ...
        beqz  t0, gcm_done              ; ...
        li    a0, OP_XORI               ; ...
        mv    a1, s5                    ; ...
        mv    a2, s5                    ; ...
        li    a3, 1                     ; ...
        jalr  ra, gp, e_i-R             ; ...
gcm_done:
        li    t0, Y_INT                 ; ...
        sh    t0, V_TYPE(s2)            ; ...
        sb    zero, V_FLAGS(s2)         ; ...
        jalr  zero, gp, lv0-R           ; done

        .align 4096                     ; ---- unit: gen5 ----
u_gen5:
; g_arith(): s1 = operator, s2 = left, s3 = right, s4 = their type: emit the
; operation; the left entry becomes the result
g_arith:
        jalr  t6, gp, ent0-R            ; (s5, s6: the caller's to lose)
        lbu   t0, V_KIND(s3)            ; a constant on the right can be an immediate
        addi  t0, t0, -VK_CONST         ; ...
        lhu   t1, V_SYM(s3)             ; ...
        or    t0, t0, t1                ; ...
        bnez  t0, gar_gen               ; ...
        ld    s6, V_VAL(s3)             ; s6 = the constant
        li    t0, '+'                   ; ...
        beq   s1, t0, gar_addi          ; ...
        li    t0, '-'                   ; ...
        bne   s1, t0, gar_log           ; ...
        neg   s6, s6                    ; ...
gar_addi:
        slli  t0, s6, 48                ; 16 signed bits?
        srai  t0, t0, 48                ; ...
        bne   t0, s6, gar_gen           ; ...
        la    t6, gar_left              ; s5 = the left operand's register
        xcall ra, c0, t6                ; ...
        li    a0, OP_ADDI               ; ...
        mv    a1, s5                    ; ...
        mv    a2, s5                    ; ...
        mv    a3, s6                    ; ...
        jalr  ra, gp, e_i-R             ; ...
        j     gar_dirty                 ; ...
gar_log:
        srli  t1, s6, 16                ; & | ^ take 16 unsigned bits
        bnez  t1, gar_sh                ; ...
        li    a0, OP_ANDI               ; ...
        li    t0, '&'                   ; ...
        beq   s1, t0, gar_li            ; ...
        li    a0, OP_ORI                ; ...
        li    t0, '|'                   ; ...
        beq   s1, t0, gar_li            ; ...
        li    a0, OP_XORI               ; ...
        li    t0, '^'                   ; ...
        bne   s1, t0, gar_sh            ; ...
gar_li:
        mv    s4, a0                    ; (the type is not needed any more)
        la    t6, gar_left              ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s4                    ; ...
        mv    a1, s5                    ; ...
        mv    a2, s5                    ; ...
        mv    a3, s6                    ; ...
        jalr  ra, gp, e_i-R             ; ...
        li    t0, '&'                   ; and with 16 bits leaves a clean value
        bne   s1, t0, gar_ret           ; ...
        sb    zero, V_FLAGS(s2)         ; ...
        j     gar_ret                   ; ...
gar_sh:
        li    t0, T_SHL                 ; ...
        bne   s1, t0, gar_shr           ; ...
gar_slli:
        la    t6, gar_left              ; slli r, r, n
        xcall ra, c0, t6                ; ...
        li    a0, OP_SLLI               ; ...
        mv    a1, s5                    ; ...
        mv    a2, s5                    ; ...
        andi  a3, s6, 63                ; ...
        jalr  ra, gp, e_i-R             ; ...
        j     gar_dirty                 ; ...
gar_shr:
        li    t0, T_SHR                 ; ...
        bne   s1, t0, gar_mul           ; ...
        mv    a0, s2                    ; the value shifted right must be clean
        la    t6, gv_c                  ; ...
        xcall ra, c0, t6                ; ...
        lbu   s5, ereg(a0)              ; ...
        lbu   t0, TY_FLAGS(s4)          ; srai, or srli if unsigned
        andi  t0, t0, TF_UNS            ; ...
        li    a0, OP_SRAI               ; ...
        sub   a0, a0, t0                ; (OP_SRLI = OP_SRAI - 1)
        mv    a1, s5                    ; ...
        mv    a2, s5                    ; ...
        andi  a3, s6, 63                ; ...
        jalr  ra, gp, e_i-R             ; ...
        j     gar_ret                   ; ...
gar_mul:
        li    t0, '*'                   ; times a power of two: a shift
        bne   s1, t0, gar_gen           ; ...
        mv    a0, s6                    ; ...
        la    t6, pow2_x                ; ...
        xcall ra, c0, t6                ; ...
        bltz  a0, gar_gen               ; ...
        mv    s6, a0                    ; ...
        j     gar_slli                  ; ...
gar_gen:
        addi  t0, s1, -'/'              ; / % >> need clean operands
        seqz  t0, t0                    ; ...
        addi  t1, s1, -'%'              ; ...
        seqz  t1, t1                    ; ...
        or    t0, t0, t1                ; ...
        addi  t1, s1, -T_SHR            ; ...
        seqz  t1, t1                    ; ...
        or    s6, t0, t1                ; s6 = 1: clean them
        mv    a0, s2                    ; ...
        la    t6, gv                    ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s3                    ; ...
        la    t6, gv                    ; ...
        xcall ra, c0, t6                ; ...
        beqz  s6, gar_regs              ; ...
        mv    a0, s2                    ; ...
        la    t6, g_clean               ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s3                    ; ...
        la    t6, g_clean               ; ...
        xcall ra, c0, t6                ; ...
gar_regs:
        lbu   t0, V_REG(s2)             ; ...
        lbu   s5, ereg(t0)              ; ...
        lbu   t0, V_REG(s3)             ; ...
        lbu   a3, ereg(t0)              ; ...
        lbu   t5, TY_FLAGS(s4)          ; t5 = unsigned
        andi  t5, t5, TF_UNS            ; ...
        li    a0, A_ADD                 ; the ALU function
        li    t0, '+'                   ; ...
        beq   s1, t0, gar_er            ; ...
        li    a0, A_SUB                 ; ...
        li    t0, '-'                   ; ...
        beq   s1, t0, gar_er            ; ...
        li    a0, A_MUL                 ; ...
        li    t0, '*'                   ; ...
        beq   s1, t0, gar_er            ; ...
        li    a0, A_AND                 ; ...
        li    t0, '&'                   ; ...
        beq   s1, t0, gar_er            ; ...
        li    a0, A_OR                  ; ...
        li    t0, '|'                   ; ...
        beq   s1, t0, gar_er            ; ...
        li    a0, A_XOR                 ; ...
        li    t0, '^'                   ; ...
        beq   s1, t0, gar_er            ; ...
        li    a0, A_SLL                 ; ...
        li    t0, T_SHL                 ; ...
        beq   s1, t0, gar_er            ; ...
        li    a0, A_SRA                 ; (A_SRL = A_SRA - 1)
        sub   a0, a0, t5                ; ...
        li    t0, T_SHR                 ; ...
        beq   s1, t0, gar_er            ; ...
        slli  t5, t5, 1                 ; (A_DIVU = A_DIV - 2, A_REMU = A_REM - 2)
        li    a0, A_DIV                 ; ...
        sub   a0, a0, t5                ; ...
        li    t0, '/'                   ; ...
        beq   s1, t0, gar_er            ; ...
        li    a0, A_REM                 ; ...
        sub   a0, a0, t5                ; ...
gar_er:
        mv    a1, s5                    ; ...
        mv    a2, s5                    ; ...
        jalr  ra, gp, e_r-R             ; ...
        bnez  s6, gar_ret               ; / % >>: clean results from clean operands
        li    t0, '&'                   ; & | ^: dirty if either operand was
        beq   s1, t0, gar_or            ; ...
        li    t0, '|'                   ; ...
        beq   s1, t0, gar_or            ; ...
        li    t0, '^'                   ; ...
        bne   s1, t0, gar_dirty         ; ...
gar_or:
        lbu   t0, V_FLAGS(s2)           ; ...
        lbu   t1, V_FLAGS(s3)           ; ...
        andi  t1, t1, VF_DIRTY          ; ...
        or    t0, t0, t1                ; ...
        sb    t0, V_FLAGS(s2)           ; ...
        j     gar_ret                   ; ...
gar_dirty:
        lwu   t0, TY_SIZE(s4)           ; + - * <<: an int result has garbage above bit 31
        sltiu t0, t0, 8                 ; ...
        beqz  t0, gar_ret               ; ...
        lbu   t0, V_FLAGS(s2)           ; ...
        ori   t0, t0, VF_DIRTY          ; ...
        sb    t0, V_FLAGS(s2)           ; ...
gar_ret:
        jalr  zero, gp, lv0-R           ; done
; gar_left: s5 = the register number of the left operand, loaded (it may be dirty)
gar_left:
        jalr  t6, gp, ent0-R            ; ...
        mv    a0, s2                    ; ...
        la    t6, gv                    ; ...
        xcall ra, c0, t6                ; ...
        lbu   s5, ereg(a0)              ; ...
        jalr  zero, gp, lv0-R           ; done

; pow2_x(a0) -> a0 = log2 or -1: pow2 for this unit
pow2_x:
        blez  a0, p2x_no                ; ...
        addi  t0, a0, -1                ; ...
        and   t0, t0, a0                ; ...
        bnez  t0, p2x_no                ; ...
        li    t0, 0                     ; ...
p2x_l:
        srli  a0, a0, 1                 ; ...
        beqz  a0, p2x_r                 ; ...
        addi  t0, t0, 1                 ; ...
        j     p2x_l                     ; ...
p2x_r:
        mv    a0, t0                    ; ...
        xret  ra                        ; ...
p2x_no:
        li    a0, -1                    ; ...
        xret  ra                        ; done

; g_ptrop(): s1 = + or -, s2 = a pointer, s3 = an integer or (for -) a pointer:
; pointer arithmetic; the left entry becomes the result
g_ptrop:
        jalr  t6, gp, ent0-R            ; (s4 = element size, s5, s6: the caller's to lose)
        lhu   t0, V_TYPE(s2)            ; the size of what it points to (1 for void, functions)
        lhu   t0, TY_BASE(t0)           ; ...
        lwu   s4, TY_SIZE(t0)           ; ...
        bnez  s4, gpo_k                 ; ...
        li    s4, 1                     ; ...
gpo_k:
        lhu   t0, V_TYPE(s3)            ; pointer - pointer?
        lbu   t0, TY_KIND(t0)           ; ...
        li    t1, TK_PTR                ; ...
        beq   t0, t1, gpo_diff          ; ...
        addi  t0, t0, -1                ; the other must be an integer (kinds 1..5)
        sltiu t0, t0, 5                 ; ...
        bnez  t0, gpo_int               ; ...
        li    a0, m_type                ; ...
        jalr  zero, gp, error-R         ; ...
gpo_int:
        mv    a0, s3                    ; as a long
        li    a1, Y_LONG                ; ...
        la    t6, g_cast                ; ...
        xcall ra, c0, t6                ; ...
        lbu   t0, V_KIND(s3)            ; a constant?
        addi  t0, t0, -VK_CONST         ; ...
        lhu   t1, V_SYM(s3)             ; ...
        or    t0, t0, t1                ; ...
        bnez  t0, gpo_var               ; ...
        ld    s6, V_VAL(s3)             ; the byte offset
        mul   s6, s6, s4                ; ...
        li    t0, '-'                   ; ...
        bne   s1, t0, gpo_c             ; ...
        neg   s6, s6                    ; ...
gpo_c:
        lbu   t0, V_KIND(s2)            ; a constant address or the address of a local: still lazy
        li    t1, VK_CONST              ; ...
        beq   t0, t1, gpo_lazy          ; ...
        li    t1, VK_LADDR              ; ...
        bne   t0, t1, gpo_creg          ; ...
gpo_lazy:
        ld    t0, V_VAL(s2)             ; ...
        add   t0, t0, s6                ; ...
        sd    t0, V_VAL(s2)             ; ...
        jalr  zero, gp, lv0-R           ; ...
gpo_creg:
        mv    a0, s2                    ; addi r, r, offset
        la    t6, gv                    ; ...
        xcall ra, c0, t6                ; ...
        lbu   a0, ereg(a0)              ; ...
        mv    a1, a0                    ; ...
        mv    a2, s6                    ; ...
        la    t6, g_addi                ; ...
        xcall ra, c0, t6                ; ...
        jalr  zero, gp, lv0-R           ; ...
gpo_var:
        mv    a0, s3                    ; the index in a register, clean, times the size
        la    t6, gv_c                  ; ...
        xcall ra, c0, t6                ; ...
        lbu   s6, ereg(a0)              ; ...
        la    t6, gpo_scale             ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s2                    ; the pointer
        la    t6, gv                    ; ...
        xcall ra, c0, t6                ; ...
        lbu   a1, ereg(a0)              ; ...
        li    a0, A_ADD                 ; add or sub
        li    t0, '-'                   ; ...
        bne   s1, t0, gpo_er            ; ...
        li    a0, A_SUB                 ; ...
gpo_er:
        mv    a2, a1                    ; ...
        mv    a3, s6                    ; ...
        jalr  ra, gp, e_r-R             ; ...
        jalr  zero, gp, lv0-R           ; ...
gpo_diff:
        mv    a0, s2                    ; (p - q) / size, a long
        la    t6, gv                    ; ...
        xcall ra, c0, t6                ; ...
        lbu   s5, ereg(a0)              ; ...
        mv    a0, s3                    ; ...
        la    t6, gv                    ; ...
        xcall ra, c0, t6                ; ...
        lbu   a3, ereg(a0)              ; ...
        li    a0, A_SUB                 ; ...
        mv    a1, s5                    ; ...
        mv    a2, s5                    ; ...
        jalr  ra, gp, e_r-R             ; ...
        li    t0, Y_LONG                ; ...
        sh    t0, V_TYPE(s2)            ; ...
        li    t0, 1                     ; ...
        beq   s4, t0, gpo_dret          ; ...
        mv    a0, s4                    ; a power of two: srai
        call  gpo_log                   ; ...
        bltz  a0, gpo_ddiv              ; ...
        mv    a3, a0                    ; ...
        li    a0, OP_SRAI               ; ...
        mv    a1, s5                    ; ...
        mv    a2, s5                    ; ...
        jalr  ra, gp, e_i-R             ; ...
        j     gpo_dret                  ; ...
gpo_ddiv:
        li    a0, X_TP                  ; else div by tp
        mv    a1, s4                    ; ...
        la    t6, g_li                  ; ...
        xcall ra, c0, t6                ; ...
        li    a0, A_DIV                 ; ...
        mv    a1, s5                    ; ...
        mv    a2, s5                    ; ...
        li    a3, X_TP                  ; ...
        jalr  ra, gp, e_r-R             ; ...
gpo_dret:
        jalr  zero, gp, lv0-R           ; done
; gpo_log(a0) -> a0 = log2 or -1 (no frame)
gpo_log:
        addi  t0, a0, -1                ; ...
        and   t0, t0, a0                ; ...
        bnez  t0, gpl_no                ; ...
        li    t0, 0                     ; ...
gpl_l:
        srli  a0, a0, 1                 ; ...
        beqz  a0, gpl_r                 ; ...
        addi  t0, t0, 1                 ; ...
        j     gpl_l                     ; ...
gpl_r:
        mv    a0, t0                    ; ...
        ret                             ; ...
gpl_no:
        li    a0, -1                    ; ...
        ret                             ; done
; gpo_scale: register s6 times the element size s4 (uses tp)
gpo_scale:
        jalr  t6, gp, ent0-R            ; ...
        li    t0, 1                     ; ...
        beq   s4, t0, gps_ret           ; ...
        mv    a0, s4                    ; a power of two: slli
        call  gpo_log                   ; ...
        bltz  a0, gps_mul               ; ...
        mv    a3, a0                    ; ...
        li    a0, OP_SLLI               ; ...
        mv    a1, s6                    ; ...
        mv    a2, s6                    ; ...
        jalr  ra, gp, e_i-R             ; ...
        j     gps_ret                   ; ...
gps_mul:
        li    a0, X_TP                  ; else mul by tp
        mv    a1, s4                    ; ...
        la    t6, g_li                  ; ...
        xcall ra, c0, t6                ; ...
        li    a0, A_MUL                 ; ...
        mv    a1, s6                    ; ...
        mv    a2, s6                    ; ...
        li    a3, X_TP                  ; ...
        jalr  ra, gp, e_r-R             ; ...
gps_ret:
        jalr  zero, gp, lv0-R           ; done
