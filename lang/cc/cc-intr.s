        .align 4096                     ; ---- unit: intr ----
u_intr:
; in_find(a0 = a name, zero-terminated) -> a0 = its entry of in_tab, or 0
in_find:
        li    t0, in_tab                ; ...
inf_l:
        lbu   t1, 0(t0)                 ; ...
        beqz  t1, inf_no                ; ...
        mv    t2, t0                    ; compare the names
        mv    t3, a0                    ; ...
inf_c:
        lbu   t4, 0(t2)                 ; ...
        lbu   t5, 0(t3)                 ; ...
        bne   t4, t5, inf_n             ; ...
        addi  t2, t2, 1                 ; ...
        addi  t3, t3, 1                 ; ...
        bnez  t4, inf_c                 ; ...
        mv    a0, t0                    ; ...
        xret  ra                        ; ...
inf_n:
        addi  t0, t0, IN_SIZE           ; ...
        j     inf_l                     ; ...
inf_no:
        li    a0, 0                     ; ...
        xret  ra                        ; done

; intrinsic(a0 = table entry): the name was read, the ( is the current token:
; read the arguments, emit the instruction, push its result
intrinsic:
        jalr  t6, gp, ent6-R            ; s1 = entry, s2 = argument index, s3 = the word, s4 = register arguments, s5 = scratch, s6 = shift
        mv    s1, a0                    ; ...
        la    t6, next                  ; (the parenthesis)
        xcall ra, c0, t6                ; ...
        lwu   s3, IN_BASE(s1)           ; ...
        li    s2, 0                     ; ...
        li    s4, 0                     ; ...
        ld    a0, vsp(zero)             ; what is in registers goes to the frame: the
        addi  a0, a0, VSZ               ;   arguments take a0, a1, ...
        la    t6, g_spill               ; ...
        xcall ra, c0, t6                ; ...
itr_arg:
        lbu   t0, IN_NARG(s1)           ; ...
        bge   s2, t0, itr_close         ; ...
        beqz  s2, itr_a1                ; ...
        li    a0, ','                   ; ...
        la    t6, skip                  ; ...
        xcall ra, c0, t6                ; ...
itr_a1:
        add   t0, s1, s2                ; ...
        lbu   s6, IN_ARGS(t0)           ; ...
        andi  t0, s6, IN_K              ; a constant field?
        beqz  t0, itr_reg               ; ...
        la    t6, const_expr            ; ...
        xcall ra, c0, t6                ; ...
        andi  s6, s6, 63                ; ...
        sll   a0, a0, s6                ; ...
        or    s3, s3, a0                ; ...
        j     itr_next                  ; ...
itr_reg:
        la    t6, assign                ; a register argument: kept on the stack for now
        xcall ra, c0, t6                ; ...
        ld    a0, vsp(zero)             ; ...
        la    t6, v_decay               ; ...
        xcall ra, c0, t6                ; ...
        li    t0, 63                    ; its register's field (63: none, the instruction
        beq   s6, t0, itr_rn            ;   takes it from a0.. by itself)
        addi  t1, s4, X_A0              ; ...
        sll   t1, t1, s6                ; ...
        or    s3, s3, t1                ; ...
itr_rn:
        addi  s4, s4, 1                 ; ...
        ld    a0, vsp(zero)             ; (and out of the registers, for the next one)
        addi  a0, a0, VSZ               ; ...
        la    t6, g_spill               ; ...
        xcall ra, c0, t6                ; ...
itr_next:
        addi  s2, s2, 1                 ; ...
        j     itr_arg                   ; ...
itr_close:
        li    a0, ')'                   ; ...
        la    t6, skip                  ; ...
        xcall ra, c0, t6                ; ...
        li    s2, 0                     ; the register arguments into a0, a1, ...
        ld    s5, vsp(zero)             ; ...
        slli  t0, s4, 5                 ; ...
        sub   s5, s5, t0                ; s5 = the entry below the first of them
itr_ld:
        bge   s2, s4, itr_emit          ; ...
        addi  s5, s5, VSZ               ; ...
        mv    a0, s5                    ; ...
        addi  a1, s2, X_A0              ; ...
        la    t6, g_into                ; ...
        xcall ra, c0, t6                ; ...
        addi  s2, s2, 1                 ; ...
        j     itr_ld                    ; ...
itr_emit:
        ld    t0, vsp(zero)             ; pop them
        slli  t1, s4, 5                 ; ...
        sub   t0, t0, t1                ; ...
        sd    t0, vsp(zero)             ; ...
        lbu   s6, IN_RES(s1)            ; the result register: a0
        slti  t0, s6, 64                ; ...
        beqz  t0, itr_e2                ; ...
        li    t1, X_A0                  ; ...
        sll   t1, t1, s6                ; ...
        or    s3, s3, t1                ; ...
itr_e2:
        mv    a0, s3                    ; ...
        jalr  ra, gp, emit-R            ; ...
        li    t0, 255                   ; ...
        bne   s6, t0, itr_res           ; ...
        li    a0, VK_CONST              ; no result
        li    a1, Y_VOID                ; ...
        li    a2, 0                     ; ...
        jalr  ra, gp, vpush-R           ; ...
        jalr  zero, gp, lv6-R           ; ...
itr_res:
        li    a0, VK_REG                ; a long in a0
        li    a1, Y_LONG                ; ...
        li    a2, 0                     ; ...
        jalr  ra, gp, vpush-R           ; ...
        li    t0, 6                     ; ...
        sb    t0, V_REG(a0)             ; ...
        ld    t0, nreg(zero)            ; ...
        ori   t0, t0, 64                ; ...
        sd    t0, nreg(zero)            ; ...
        jalr  zero, gp, lv6-R           ; done

        .data                           ; the names of the stdarg builtins
m_bva:    .asciz "__builtin_va_"        ; ... and then start or arg
        .align 8                        ; ...
        .far                            ; ...
        .align 4096                     ; ---- unit: intr2 ----
u_intr2:
; va_find(a0 = a name, zero-terminated) -> a0 = 1 for __builtin_va_start, 2 for
; __builtin_va_arg, 0 for any other name
va_find:
        jalr  t6, gp, ent0-R            ; ...
        li    t0, m_bva                 ; the common part
vaf_l:
        lbu   t1, 0(t0)                 ; ...
        beqz  t1, vaf_end               ; ...
        lbu   t2, 0(a0)                 ; ...
        bne   t1, t2, vaf_no            ; ...
        addi  t0, t0, 1                 ; ...
        addi  a0, a0, 1                 ; ...
        j     vaf_l                     ; ...
vaf_end:
        lbu   t1, 0(a0)                 ; s...: start; a...: arg (nothing else is spelled so)
        li    t0, 's'                   ; ...
        li    t2, 1                     ; ...
        beq   t1, t0, vaf_yes           ; ...
        li    t0, 'a'                   ; ...
        li    t2, 2                     ; ...
        beq   t1, t0, vaf_yes           ; ...
vaf_no:
        li    t2, 0                     ; ...
vaf_yes:
        mv    a0, t2                    ; ...
        jalr  zero, gp, lv0-R           ; done

; va_builtin(a0 = 1 or 2): the name was read, the ( is the current token.
; In a variadic function every argument is a word of the row at 8 i (s0).
;   __builtin_va_start(ap, last)   ap = the address of the first unnamed word
;   __builtin_va_arg(ap, type)     the value in the next word (a structure: the
;                                  one whose address the word holds); ap moves on
va_builtin:
        jalr  t6, gp, ent2-R            ; s1 = which, s2 = type
        mv    s1, a0                    ; ...
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        la    t6, assign                ; ap
        xcall ra, c0, t6                ; ...
        li    a0, ','                   ; ...
        la    t6, skip                  ; ...
        xcall ra, c0, t6                ; ...
        li    t0, 1                     ; ...
        bne   s1, t0, vab_arg           ; ...
        la    t6, next                  ; (the last named parameter: not needed)
        xcall ra, c0, t6                ; ...
        li    a0, ')'                   ; ...
        la    t6, skip                  ; ...
        xcall ra, c0, t6                ; ...
        ld    t0, fn_sym(zero)          ; s0 + 8 (parameters, and the hidden one of a
        lhu   t0, SY_TYPE(t0)           ;   structure result)
        lwu   a2, TY_COUNT(t0)          ; ...
        ld    t1, fn_ret(zero)          ; ...
        lbu   t1, TY_KIND(t1)           ; ...
        addi  t1, t1, -TK_STRUCT        ; ...
        sltiu t1, t1, 2                 ; ...
        add   a2, a2, t1                ; ...
        slli  a2, a2, 3                 ; ...
        li    a0, VK_LADDR              ; ...
        li    a1, Y_CHARP               ; ...
        jalr  ra, gp, vpush-R           ; ...
        li    t0, X_S0                  ; ...
        sb    t0, V_REG(a0)             ; ...
        la    t6, g_store               ; ...
        xcall ra, c0, t6                ; ...
        la    t6, vpop                  ; ...
        xcall ra, c0, t6                ; ...
        li    a0, VK_CONST              ; (no value)
        li    a1, Y_VOID                ; ...
        li    a2, 0                     ; ...
        jalr  ra, gp, vpush-R           ; ...
        jalr  zero, gp, lv2-R           ; ...
vab_arg:
        la    t6, type_name             ; ...
        xcall ra, c0, t6                ; ...
        mv    s2, a0                    ; ...
        li    a0, ')'                   ; ...
        la    t6, skip                  ; ...
        xcall ra, c0, t6                ; ...
        la    t6, v_dupval              ; [ap, its value]
        xcall ra, c0, t6                ; ...
        li    a0, VK_CONST              ; ap = ap + 8
        li    a1, Y_INT                 ; ...
        li    a2, 8                     ; ...
        jalr  ra, gp, vpush-R           ; ...
        li    a0, '+'                   ; ...
        la    t6, g_binop               ; ...
        xcall ra, c0, t6                ; ...
        la    t6, g_store               ; ...
        xcall ra, c0, t6                ; ...
        li    a0, VK_CONST              ; the word it has passed
        li    a1, Y_INT                 ; ...
        li    a2, 8                     ; ...
        jalr  ra, gp, vpush-R           ; ...
        li    a0, '-'                   ; ...
        la    t6, g_binop               ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s2                    ; as a pointer to the type
        jalr  ra, gp, ty_ptr-R          ; ...
        lbu   t0, TY_KIND(s2)           ; (a structure: to a pointer to it)
        addi  t0, t0, -TK_STRUCT        ; ...
        sltiu s1, t0, 2                 ; ...
        beqz  s1, vab_ty                ; ...
        jalr  ra, gp, ty_ptr-R          ; ...
vab_ty:
        ld    t0, vsp(zero)             ; ...
        sh    a0, V_TYPE(t0)            ; ...
        mv    a0, t0                    ; ...
        la    t6, v_deref               ; ...
        xcall ra, c0, t6                ; ...
        beqz  s1, vab_ret               ; ...
        ld    a0, vsp(zero)             ; ...
        la    t6, v_deref               ; ...
        xcall ra, c0, t6                ; ...
vab_ret:
        jalr  zero, gp, lv2-R           ; done
