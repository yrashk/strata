;
; A call of one of the names below, when the program has not declared the
; name itself, is not a call: it compiles to the one instruction. Arguments
; that the instruction encodes in its word (a transfer tag, a capability
; register, a CSR number, a tag mask) must be integer constant expressions;
; the others are ordinary expressions, loaded into a0, a1, ... in order. A
; result comes back in a0, as a long. <strata.h> documents them.
;
; Table entry (IN_SIZE bytes): the name (12 bytes), the instruction word
; without its operands, the number of arguments, where the result register
; goes (a shift; 255: no result; 254: the instruction leaves it in a0), and
; per argument a shift, with IN_K set if the argument is a constant field
; (shift 63: a register argument the instruction finds in its a register).
IN_BASE  = 12                           ; u32
IN_NARG  = 16                           ; u8
IN_RES   = 17                           ; u8
IN_ARGS  = 18                           ; u8 each
IN_SIZE  = 24                           ; ...
IN_K     = 0x80                         ; a constant field

        .data                           ; the table
        .align 8                        ; (words first)
in_tab:
