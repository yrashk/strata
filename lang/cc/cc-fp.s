; =============================================================================
; cc-fp.s: floating point
; =============================================================================
;
; Strata has no floating-point instructions, so a double is its 64-bit
; pattern in an integer register and arithmetic is a call of the library's
; software routines (lib/fp.s: __fadd, __fmul, ...). The compiler includes the
; same routines to fold constant expressions and to read constants.
;
; A value of type float is its 32-bit pattern; it is converted to double
; before any arithmetic (the result of float arithmetic is a double here) and
; back when it is stored.

FP_ADD   = 0                            ; routine numbers: fp_op and fp_names
FP_SUB   = 1                            ; .
FP_MUL   = 2                            ; .
FP_DIV   = 3                            ; .
FP_CMP   = 4                            ; .
FP_ITOF  = 5                            ; .
FP_UTOF  = 6                            ; .
FP_FTOI  = 7                            ; .
FP_FTOU  = 8                            ; .
FP_F2D   = 9                            ; .
FP_D2F   = 10                           ; .

        .data                           ; the routines' names, 8 bytes each
        .align 8                        ; (words first)
fp_names: .asciz "__fadd"               ; .
          .byte 0                       ; .
          .asciz "__fsub"               ; .
          .byte 0                       ; .
          .asciz "__fmul"               ; .
          .byte 0                       ; .
          .asciz "__fdiv"               ; .
          .byte 0                       ; .
          .asciz "__fcmp"               ; .
          .byte 0                       ; .
          .asciz "__itof"               ; .
          .byte 0                       ; .
          .asciz "__utof"               ; .
          .byte 0                       ; .
          .asciz "__ftoi"               ; .
          .byte 0                       ; .
          .asciz "__ftou"               ; .
          .byte 0                       ; .
          .asciz "__f2d"                ; .
          .byte 0, 0                    ; .
          .asciz "__d2f"                ; .
          .byte 0, 0                    ; .
m_fpops:  .asciz "this operator does not take floating operands" ; ...
        .align 8                        ; ...

        .far                            ; code units
        .align 4096                     ; ---- unit: fp1 ----
u_fp1:
        .include "lib/fp.s"             ; the routines themselves (leaves, called with `call`)

; fp_op(a0 = routine number, a1 = x, a2 = y) -> a0 = its result, computed now
fp_op:
        jalr  t6, gp, ent0-R            ; ...
        mv    t0, a0                    ; ...
        mv    a0, a1                    ; ...
        mv    a1, a2                    ; ...
        slli  t0, t0, 3                 ; each entry of the table below is two instructions
        la    t1, fpo_tab               ; (the address in the arena; this unit's slot is found
        la    t2, fp_op                 ;  from where we are: pc-relative)
        sub   t1, t1, t2                ; t1 = the table's offset from fp_op
        jal   t2, fpo_here              ; t2 = the address of fpo_here
fpo_here:
        addi  t2, t2, fp_op - fpo_here  ; t2 = fp_op where it runs
        add   t1, t1, t2                ; ...
        add   t1, t1, t0                ; ...
        jr    t1                        ; ...
fpo_tab:
        call  __fadd                    ; 0
        j     fpo_ret                   ; .
        call  __fsub                    ; 1
        j     fpo_ret                   ; .
        call  __fmul                    ; 2
        j     fpo_ret                   ; .
        call  __fdiv                    ; 3
        j     fpo_ret                   ; .
        call  __fcmp                    ; 4
        j     fpo_ret                   ; .
        call  __itof                    ; 5
        j     fpo_ret                   ; .
        call  __utof                    ; 6
        j     fpo_ret                   ; .
        call  __ftoi                    ; 7
        j     fpo_ret                   ; .
        call  __ftou                    ; 8
        j     fpo_ret                   ; .
        call  __f2d                     ; 9
        j     fpo_ret                   ; .
        call  __d2f                     ; 10
fpo_ret:
        jalr  zero, gp, lv0-R           ; done

; lex_float(): the floating constant spelled in TB: tok = T_NUM, tk_val = its
; pattern, tk_ty = double (float with an f suffix)
lex_float:
        jalr  t6, gp, ent6-R            ; s1 = cursor, s2 = digits as an integer, s3 = decimal exponent, s4 = flags, s5 = binary exponent, s6 = scratch
        li    s1, TB                    ; ...
        li    s2, 0                     ; ...
        li    s3, 0                     ; ...
        li    s4, 0                     ; bit 0: after the point, bit 1: f suffix
        li    s6, 0                     ; (s6: the exponent's sign, then a binary exponent)
        lbu   t0, 1(s1)                 ; 0x: hexadecimal digits and a binary exponent
        ori   t0, t0, 32                ; ...
        li    t1, 'x'                   ; ...
        bne   t0, t1, lxf_m             ; ...
        addi  s1, s1, 2                 ; ...
lxf_h:
        lbu   t0, 0(s1)                 ; ...
        li    t1, '.'                   ; ...
        bne   t0, t1, lxf_hd            ; ...
        ori   s4, s4, 1                 ; ...
        addi  s1, s1, 1                 ; ...
        j     lxf_h                     ; ...
lxf_hd:
        addi  t1, t0, -'0'              ; a digit's value, or the p
        sltiu t2, t1, 10                ; ...
        bnez  t2, lxf_hv                ; ...
        ori   t1, t0, 32                ; ...
        addi  t1, t1, -'a'              ; ...
        sltiu t2, t1, 6                 ; ...
        beqz  t2, lxf_hp                ; ...
        addi  t1, t1, 10                ; ...
lxf_hv:
        addi  s1, s1, 1                 ; ...
        srli  t2, s2, 60                ; room for it?
        bnez  t2, lxf_hx                ; ...
        slli  s2, s2, 4                 ; ...
        or    s2, s2, t1                ; ...
        andi  t2, s4, 1                 ; a digit after the point: four binary places less
        slli  t2, t2, 2                 ; ...
        sub   s6, s6, t2                ; ...
        j     lxf_h                     ; ...
lxf_hx:
        andi  t2, s4, 1                 ; a digit dropped before the point: four more
        xori  t2, t2, 1                 ; ...
        slli  t2, t2, 2                 ; ...
        add   s6, s6, t2                ; ...
        j     lxf_h                     ; ...
lxf_hp:
        ori   t0, t0, 32                ; p, a sign, decimal digits
        li    t1, 'p'                   ; ...
        bne   t0, t1, lxf_suf           ; ...
        addi  s1, s1, 1                 ; ...
        li    t4, 0                     ; t4 = 1: negative
        lbu   t0, 0(s1)                 ; ...
        li    t1, '+'                   ; ...
        beq   t0, t1, lxf_hs            ; ...
        li    t1, '-'                   ; ...
        bne   t0, t1, lxf_he            ; ...
        li    t4, 1                     ; ...
lxf_hs:
        addi  s1, s1, 1                 ; ...
lxf_he:
        li    t3, 0                     ; ...
lxf_hl:
        lbu   t0, 0(s1)                 ; ...
        addi  t1, t0, -'0'              ; ...
        sltiu t2, t1, 10                ; ...
        beqz  t2, lxf_hz                ; ...
        li    t2, 10                    ; ...
        mul   t3, t3, t2                ; ...
        add   t3, t3, t1                ; ...
        addi  s1, s1, 1                 ; ...
        j     lxf_hl                    ; ...
lxf_hz:
        beqz  t4, lxf_hy                ; ...
        neg   t3, t3                    ; ...
lxf_hy:
        add   s6, s6, t3                ; ...
        j     lxf_suf                   ; ...
lxf_m:
        lbu   t0, 0(s1)                 ; the digits and the point
        li    t1, '.'                   ; ...
        bne   t0, t1, lxf_d             ; ...
        ori   s4, s4, 1                 ; ...
        addi  s1, s1, 1                 ; ...
        j     lxf_m                     ; ...
lxf_d:
        addi  t1, t0, -'0'              ; ...
        sltiu t2, t1, 10                ; ...
        beqz  t2, lxf_e                 ; ...
        addi  s1, s1, 1                 ; ...
        li    t2, 0x0DE0B6B3A763FFFF    ; room for another digit (below 10^18)?
        bgtu  s2, t2, lxf_drop          ; ...
        li    t2, 10                    ; ...
        mul   s2, s2, t2                ; ...
        add   s2, s2, t1                ; ...
        andi  t2, s4, 1                 ; a digit after the point: one power of ten less
        sub   s3, s3, t2                ; ...
        j     lxf_m                     ; ...
lxf_drop:
        andi  t2, s4, 1                 ; a digit dropped before the point: one power more
        xori  t2, t2, 1                 ; ...
        add   s3, s3, t2                ; ...
        j     lxf_m                     ; ...
lxf_e:
        ori   t0, t0, 32                ; e or E: the exponent
        li    t1, 'e'                   ; ...
        bne   t0, t1, lxf_suf           ; ...
        addi  s1, s1, 1                 ; ...
        li    s6, 0                     ; s6 = 1: negative
        lbu   t0, 0(s1)                 ; ...
        li    t1, '+'                   ; ...
        beq   t0, t1, lxf_es            ; ...
        li    t1, '-'                   ; ...
        bne   t0, t1, lxf_ed            ; ...
        li    s6, 1                     ; ...
lxf_es:
        addi  s1, s1, 1                 ; ...
lxf_ed:
        li    t3, 0                     ; ...
lxf_el:
        lbu   t0, 0(s1)                 ; ...
        addi  t1, t0, -'0'              ; ...
        sltiu t2, t1, 10                ; ...
        beqz  t2, lxf_ee                ; ...
        li    t2, 10                    ; ...
        mul   t3, t3, t2                ; ...
        add   t3, t3, t1                ; ...
        addi  s1, s1, 1                 ; ...
        slti  t2, t3, 10000             ; (a huge exponent stays huge)
        bnez  t2, lxf_el                ; ...
        li    t3, 10000                 ; ...
        j     lxf_el                    ; ...
lxf_ee:
        beqz  s6, lxf_ea                ; ...
        neg   t3, t3                    ; ...
lxf_ea:
        add   s3, s3, t3                ; ...
        li    s6, 0                     ; ...
lxf_suf:
        lbu   t0, 0(s1)                 ; suffixes: f makes it a float, l changes nothing
        beqz  t0, lxf_val               ; ...
        addi  s1, s1, 1                 ; ...
        ori   t0, t0, 32                ; ...
        li    t1, 'l'                   ; ...
        beq   t0, t1, lxf_suf           ; ...
        li    t1, 'f'                   ; ...
        bne   t0, t1, lxf_bad           ; ...
        ori   s4, s4, 2                 ; ...
        j     lxf_suf                   ; ...
lxf_bad:
        li    a0, m_expect              ; ...
        li    a1, TB                    ; ...
        jalr  zero, gp, error2-R        ; ...
lxf_val:
        li    a0, 0                     ; zero is zero
        beqz  s2, lxf_set               ; ...
        addi  s5, s6, 1085              ; the value is s2 * 2^(s5 - 1085) * 10^s3: bring the
lxf_n:
        bltz  s2, lxf_p                 ;   leading bit of s2 to bit 63, then the powers of ten
        slli  s2, s2, 1                 ;   one at a time, keeping 64 bits
        addi  s5, s5, -1                ; ...
        j     lxf_n                     ; ...
lxf_p:
        beqz  s3, lxf_pk                ; ...
        bltz  s3, lxf_div               ; ...
        li    t0, 10                    ; times ten: * (10 << 60), / 2^64, * 2^4
        slli  t0, t0, 60                ; ...
        mulhu s2, s2, t0                ; ...
        addi  s5, s5, 4                 ; ...
        addi  s3, s3, -1                ; ...
        j     lxf_n                     ; ...
lxf_div:
        li    t0, 0xCCCCCCCCCCCCCCCD    ; by ten: * (2^67 / 10), / 2^64, / 2^3
        mulhu s2, s2, t0                ; ...
        addi  s5, s5, -3                ; ...
        addi  s3, s3, 1                 ; ...
        slti  t0, s5, -1200             ; (too small for any double: stop)
        beqz  t0, lxf_n                 ; ...
        li    s3, 0                     ; ...
        j     lxf_n                     ; ...
lxf_pk:
        li    t0, 0                     ; positive (a sign is an operator)
        mv    t1, s5                    ; ...
        mv    a0, s2                    ; ...
        call  __fpk                     ; ...
lxf_set:
        li    t1, Y_DOUBLE              ; ...
        andi  t0, s4, 2                 ; ...
        beqz  t0, lxf_ty                ; ...
        call  __d2f                     ; ...
        li    t1, Y_FLOAT               ; ...
lxf_ty:
        sd    a0, tk_val(zero)          ; ...
        sd    t1, tk_ty(zero)           ; ...
        li    t0, T_NUM                 ; ...
        sd    t0, tok(zero)             ; ...
        jalr  zero, gp, lv6-R           ; done

        .align 4096                     ; ---- unit: fp2 ----
u_fp2:
; fp_call(a0 = routine number, a1 = number of arguments, 1 or 2): call the
; library routine with the top entries as arguments; its result takes their place
fp_call:
        jalr  t6, gp, ent2-R            ; s1 = arguments, s2 = the function's entry
        mv    s1, a1                    ; ...
        slli  a0, a0, 3                 ; its name
        addi  a0, a0, fp_names          ; ...
        li    a1, 0                     ; and the name's length
fpc_len:
        add   t0, a0, a1                ; ...
        lbu   t0, 0(t0)                 ; ...
        beqz  t0, fpc_fn                ; ...
        addi  a1, a1, 1                 ; ...
        j     fpc_len                   ; ...
fpc_fn:
        la    t6, lib_fn                ; [x, (y,) function]
        xcall ra, c0, t6                ; ...
        ld    s2, vsp(zero)             ; the function goes below its arguments
        ld    t0, 0(s2)                 ; ...
        ld    t1, 8(s2)                 ; ...
        ld    t2, 16(s2)                ; ...
        mv    t3, s1                    ; ...
fpc_rot:
        ld    t4, -VSZ(s2)              ; ...
        sd    t4, 0(s2)                 ; ...
        ld    t4, 8-VSZ(s2)             ; ...
        sd    t4, 8(s2)                 ; ...
        ld    t4, 16-VSZ(s2)            ; ...
        sd    t4, 16(s2)                ; ...
        addi  s2, s2, -VSZ              ; ...
        addi  t3, t3, -1                ; ...
        bnez  t3, fpc_rot               ; ...
        sd    t0, 0(s2)                 ; ...
        sd    t1, 8(s2)                 ; ...
        sd    t2, 16(s2)                ; ...
        mv    a0, s1                    ; ...
        la    t6, g_call                ; ...
        xcall ra, c0, t6                ; ...
        jalr  zero, gp, lv2-R           ; done

; f_cast(a0 = entry, the top one, a1 = type): a conversion from or to a
; floating type
f_cast:
        jalr  t6, gp, ent4-R            ; s1 = entry, s2 = to, s3 = from, s4 = scratch
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        lhu   s3, V_TYPE(s1)            ; ...
        ld    t0, vsp(zero)             ; (the routines are called on the top entry)
        beq   t0, s1, fca_top           ; ...
        li    a0, m_noimpl              ; ...
        li    a1, 0                     ; ...
        jalr  zero, gp, error2-R        ; ...
fca_top:
        lbu   t0, V_KIND(s1)            ; a constant is converted here
        addi  t0, t0, -VK_CONST         ; ...
        lhu   t1, V_SYM(s1)             ; ...
        or    t0, t0, t1                ; ...
        beqz  t0, fca_const             ; ...
        lbu   t0, TY_KIND(s3)           ; first to a double
        li    t1, TK_DOUBLE             ; ...
        beq   t0, t1, fca_to            ; ...
        li    t1, TK_FLOAT              ; ...
        bne   t0, t1, fca_int           ; ...
        mv    a0, s1                    ; a float: its pattern, widened
        la    t6, gv                    ; ...
        xcall ra, c0, t6                ; ...
        li    a0, FP_F2D                ; ...
        j     fca_c1                    ; ...
fca_int:
        mv    a0, s1                    ; an integer: extended, then __itof or __utof
        la    t6, gv_c                  ; ...
        xcall ra, c0, t6                ; ...
        lbu   t0, TY_FLAGS(s3)          ; ...
        andi  t0, t0, TF_UNS            ; ...
        addi  a0, t0, FP_ITOF           ; (FP_UTOF = FP_ITOF + 1)
fca_c1:
        li    a1, 1                     ; ...
        la    t6, fp_call               ; ...
        xcall ra, c0, t6                ; ...
        li    t0, Y_DOUBLE              ; ...
        sh    t0, V_TYPE(s1)            ; ...
fca_to:
        lbu   t0, TY_KIND(s2)           ; then to the target
        li    t1, TK_DOUBLE             ; ...
        beq   t0, t1, fca_ret           ; ...
        li    t1, TK_FLOAT              ; ...
        bne   t0, t1, fca_toint         ; ...
        li    a0, FP_D2F                ; ...
        li    a1, 1                     ; ...
        la    t6, fp_call               ; ...
        xcall ra, c0, t6                ; ...
        j     fca_type                  ; ...
fca_toint:
        li    t1, TK_BOOL               ; _Bool: not zero (of either sign)
        bne   t0, t1, fca_toi           ; ...
        mv    a0, s1                    ; ...
        la    t6, gv                    ; ...
        xcall ra, c0, t6                ; ...
        lbu   s4, ereg(a0)              ; ...
        li    a0, OP_SLLI               ; slli r, r, 1
        mv    a1, s4                    ; ...
        mv    a2, s4                    ; ...
        li    a3, 1                     ; ...
        jalr  ra, gp, e_i-R             ; ...
        li    a0, A_SLTU                ; sltu r, zero, r
        mv    a1, s4                    ; ...
        li    a2, 0                     ; ...
        mv    a3, s4                    ; ...
        jalr  ra, gp, e_r-R             ; ...
        j     fca_type                  ; ...
fca_toi:
        lbu   t0, TY_FLAGS(s2)          ; an integer: __ftou for unsigned long, else __ftoi,
        andi  t0, t0, TF_UNS            ;   then narrowed
        lwu   t1, TY_SIZE(s2)           ; ...
        addi  t1, t1, -8                ; ...
        seqz  t1, t1                    ; ...
        and   t0, t0, t1                ; ...
        addi  a0, t0, FP_FTOI           ; ...
        li    a1, 1                     ; ...
        la    t6, fp_call               ; ...
        xcall ra, c0, t6                ; ...
        li    t0, Y_LONG                ; ...
        sh    t0, V_TYPE(s1)            ; ...
        lbu   t0, TY_FLAGS(s2)          ; an unsigned type narrower than int: below zero
        andi  t0, t0, TF_UNS            ;   there is no value: 0
        beqz  t0, fca_nar               ; ...
        lwu   t1, TY_SIZE(s2)           ; ...
        sltiu t1, t1, 4                 ; ...
        beqz  t1, fca_nar               ; ...
        mv    a0, s1                    ; ...
        la    t6, gv                    ; ...
        xcall ra, c0, t6                ; ...
        lbu   s4, ereg(a0)              ; ...
        li    a0, OP_SRAI               ; srai tp, r, 63
        li    a1, X_TP                  ; ...
        mv    a2, s4                    ; ...
        li    a3, 63                    ; ...
        jalr  ra, gp, e_i-R             ; ...
        li    a0, OP_ADDI               ; addi tp, tp, 1
        li    a1, X_TP                  ; ...
        li    a2, X_TP                  ; ...
        li    a3, 1                     ; ...
        jalr  ra, gp, e_i-R             ; ...
        li    a0, A_MUL                 ; mul r, r, tp
        mv    a1, s4                    ; ...
        mv    a2, s4                    ; ...
        li    a3, X_TP                  ; ...
        jalr  ra, gp, e_r-R             ; ...
fca_nar:
        mv    a0, s1                    ; ...
        mv    a1, s2                    ; ...
        la    t6, g_cast                ; ...
        xcall ra, c0, t6                ; ...
        j     fca_ret                   ; ...
fca_const:
        ld    a1, V_VAL(s1)             ; the constant as a double
        lbu   t0, TY_KIND(s3)           ; ...
        li    t1, TK_DOUBLE             ; ...
        beq   t0, t1, fca_cd            ; ...
        li    a0, FP_F2D                ; ...
        li    t1, TK_FLOAT              ; ...
        beq   t0, t1, fca_c2d           ; ...
        lbu   t0, TY_FLAGS(s3)          ; ...
        andi  t0, t0, TF_UNS            ; ...
        addi  a0, t0, FP_ITOF           ; ...
fca_c2d:
        la    t6, fp_op                 ; ...
        xcall ra, c0, t6                ; ...
        mv    a1, a0                    ; ...
fca_cd:
        lbu   t0, TY_KIND(s2)           ; and as the target type
        li    t1, TK_DOUBLE             ; ...
        beq   t0, t1, fca_cset          ; ...
        li    a0, FP_D2F                ; ...
        li    t1, TK_FLOAT              ; ...
        beq   t0, t1, fca_cop           ; ...
        li    t1, TK_BOOL               ; ...
        bne   t0, t1, fca_ci            ; ...
        slli  a1, a1, 1                 ; ...
        snez  a1, a1                    ; ...
        j     fca_cset                  ; ...
fca_ci:
        lbu   t0, TY_FLAGS(s2)          ; ...
        andi  t0, t0, TF_UNS            ; ...
        lwu   t1, TY_SIZE(s2)           ; ...
        addi  t1, t1, -8                ; ...
        seqz  t1, t1                    ; ...
        and   t0, t0, t1                ; ...
        addi  a0, t0, FP_FTOI           ; ...
        la    t6, fp_op                 ; ...
        xcall ra, c0, t6                ; ...
        lbu   t0, TY_FLAGS(s2)          ; (a narrow unsigned type: below zero is 0)
        andi  t0, t0, TF_UNS            ; ...
        beqz  t0, fca_cn                ; ...
        lwu   t1, TY_SIZE(s2)           ; ...
        sltiu t1, t1, 4                 ; ...
        beqz  t1, fca_cn                ; ...
        bgez  a0, fca_cn                ; ...
        li    a0, 0                     ; ...
fca_cn:
        sd    a0, V_VAL(s1)             ; (then narrowed as any integer constant)
        li    t0, Y_LONG                ; ...
        sh    t0, V_TYPE(s1)            ; ...
        mv    a0, s1                    ; ...
        mv    a1, s2                    ; ...
        la    t6, g_cast                ; ...
        xcall ra, c0, t6                ; ...
        j     fca_ret                   ; ...
fca_cop:
        la    t6, fp_op                 ; ...
        xcall ra, c0, t6                ; ...
        mv    a1, a0                    ; ...
fca_cset:
        sd    a1, V_VAL(s1)             ; ...
fca_type:
        sh    s2, V_TYPE(s1)            ; ...
fca_ret:
        jalr  zero, gp, lv4-R           ; done

; f_swap(): exchange the two top entries
f_swap:
        ld    t0, vsp(zero)             ; ...
        ld    t1, 0(t0)                 ; ...
        ld    t2, -VSZ(t0)              ; ...
        sd    t2, 0(t0)                 ; ...
        sd    t1, -VSZ(t0)              ; ...
        ld    t1, 8(t0)                 ; ...
        ld    t2, 8-VSZ(t0)             ; ...
        sd    t2, 8(t0)                 ; ...
        sd    t1, 8-VSZ(t0)             ; ...
        ld    t1, 16(t0)                ; ...
        ld    t2, 16-VSZ(t0)            ; ...
        sd    t2, 16(t0)                ; ...
        sd    t1, 16-VSZ(t0)            ; ...
        ret                             ; done

; f_binop(a0 = operator): [left, right] -> [result], one of them floating
f_binop:
        jalr  t6, gp, ent4-R            ; s1 = operator, s2 = left entry, s3 = right entry, s4 = routine number
        mv    s1, a0                    ; ...
        ld    s3, vsp(zero)             ; ...
        addi  s2, s3, -VSZ              ; ...
        lhu   t0, V_TYPE(s2)            ; no double among them: the result is a float
        lbu   t0, TY_KIND(t0)           ; ...
        addi  t0, t0, -TK_DOUBLE        ; ...
        snez  t0, t0                    ; ...
        lhu   t1, V_TYPE(s3)            ; ...
        lbu   t1, TY_KIND(t1)           ; ...
        addi  t1, t1, -TK_DOUBLE        ; ...
        snez  t1, t1                    ; ...
        and   t0, t0, t1                ; ...
        sd    t0, fb_flt(zero)          ; ...
        mv    a0, s3                    ; both as doubles (each converted while it is on top)
        li    a1, Y_DOUBLE              ; ...
        la    t6, g_cast                ; ...
        xcall ra, c0, t6                ; ...
        call  f_swap                    ; ...
        mv    a0, s3                    ; ...
        li    a1, Y_DOUBLE              ; ...
        la    t6, g_cast                ; ...
        xcall ra, c0, t6                ; ...
        call  f_swap                    ; ...
        li    s4, FP_ADD                ; which routine?
        li    t0, '+'                   ; ...
        beq   s1, t0, fbo_ar            ; ...
        li    s4, FP_SUB                ; ...
        li    t0, '-'                   ; ...
        beq   s1, t0, fbo_ar            ; ...
        li    s4, FP_MUL                ; ...
        li    t0, '*'                   ; ...
        beq   s1, t0, fbo_ar            ; ...
        li    s4, FP_DIV                ; ...
        li    t0, '/'                   ; ...
        beq   s1, t0, fbo_ar            ; ...
        li    t0, '<'                   ; a comparison?
        beq   s1, t0, fbo_cmp           ; ...
        li    t0, '>'                   ; ...
        beq   s1, t0, fbo_cmp           ; ...
        addi  t0, s1, -T_EQ             ; ...
        sltiu t0, t0, 4                 ; ...
        bnez  t0, fbo_cmp               ; ...
        li    a0, m_fpops               ; ...
        jalr  zero, gp, error-R         ; ...
fbo_ar:
        call  fbo_consts                ; two constants: now
        beqz  a0, fbo_arc               ; ...
        mv    a0, s4                    ; ...
        ld    a1, V_VAL(s2)             ; ...
        ld    a2, V_VAL(s3)             ; ...
        la    t6, fp_op                 ; ...
        xcall ra, c0, t6                ; ...
        sd    a0, V_VAL(s2)             ; ...
        sd    s2, vsp(zero)             ; ...
        j     fbo_fl                    ; ...
fbo_arc:
        ld    t0, fb_flt(zero)          ; (kept over the call)
        addi  sp, sp, -8                ; ...
        sd    t0, 0(sp)                 ; ...
        mv    a0, s4                    ; else a call
        li    a1, 2                     ; ...
        la    t6, fp_call               ; ...
        xcall ra, c0, t6                ; ...
        li    t0, Y_DOUBLE              ; ...
        sh    t0, V_TYPE(s2)            ; ...
        ld    t0, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        sd    t0, fb_flt(zero)          ; ...
fbo_fl:
        ld    t0, fb_flt(zero)          ; of float operands: rounded to a float
        beqz  t0, fbo_ret               ; ...
        ld    a0, vsp(zero)             ; ...
        li    a1, Y_FLOAT               ; ...
        la    t6, g_cast                ; ...
        xcall ra, c0, t6                ; ...
        j     fbo_ret                   ; ...
fbo_cmp:
        li    t0, '>'                   ; a > b is b < a, a >= b is b <= a: then __fcmp's
        beq   s1, t0, fbo_sw            ;   result is compared with 0 (unordered is 2: false)
        li    t0, T_GE                  ; ...
        bne   s1, t0, fbo_c             ; ...
        li    s1, T_LE                  ; ...
        j     fbo_sw2                   ; ...
fbo_sw:
        li    s1, '<'                   ; ...
fbo_sw2:
        call  f_swap                    ; ...
fbo_c:
        call  fbo_consts                ; ...
        beqz  a0, fbo_cc                ; ...
        li    a0, FP_CMP                ; ...
        ld    a1, V_VAL(s2)             ; ...
        ld    a2, V_VAL(s3)             ; ...
        la    t6, fp_op                 ; ...
        xcall ra, c0, t6                ; ...
        sd    a0, V_VAL(s2)             ; ...
        sd    s2, vsp(zero)             ; ...
        j     fbo_c0                    ; ...
fbo_cc:
        li    a0, FP_CMP                ; ...
        li    a1, 2                     ; ...
        la    t6, fp_call               ; ...
        xcall ra, c0, t6                ; ...
fbo_c0:
        li    t0, Y_INT                 ; [__fcmp's result, 0] and the integer comparison
        sh    t0, V_TYPE(s2)            ; ...
        li    a0, VK_CONST              ; ...
        li    a1, Y_INT                 ; ...
        li    a2, 0                     ; ...
        jalr  ra, gp, vpush-R           ; ...
        mv    a0, s1                    ; ...
        la    t6, g_binop               ; ...
        xcall ra, c0, t6                ; ...
fbo_ret:
        jalr  zero, gp, lv4-R           ; done
; fbo_consts: a0 = 1 if both entries (s2, s3) are known constants  (no frame)
fbo_consts:
        lbu   t0, V_KIND(s2)            ; ...
        lbu   t1, V_KIND(s3)            ; ...
        addi  t0, t0, -VK_CONST         ; ...
        addi  t1, t1, -VK_CONST         ; ...
        or    t0, t0, t1                ; ...
        lhu   t1, V_SYM(s2)             ; ...
        or    t0, t0, t1                ; ...
        lhu   t1, V_SYM(s3)             ; ...
        or    t0, t0, t1                ; ...
        seqz  a0, t0                    ; ...
        ret                             ; done

; f_unop(a0 = operator): - or + of the floating value on top
f_unop:
        jalr  t6, gp, ent3-R            ; s1 = operator, s2 = entry, s3 = register number
        mv    s1, a0                    ; ...
        ld    s2, vsp(zero)             ; ...
        li    t0, '+'                   ; ...
        beq   s1, t0, fun_ret           ; ...
        li    t0, '-'                   ; ...
        beq   s1, t0, fun_neg           ; ...
        li    a0, m_fpops               ; ...
        jalr  zero, gp, error-R         ; ...
fun_neg:
        mv    a0, s2                    ; as a double
        li    a1, Y_DOUBLE              ; ...
        la    t6, g_cast                ; ...
        xcall ra, c0, t6                ; ...
        lbu   t0, V_KIND(s2)            ; a constant: flip the sign bit here
        addi  t0, t0, -VK_CONST         ; ...
        bnez  t0, fun_reg               ; ...
        ld    t0, V_VAL(s2)             ; ...
        li    t1, 1                     ; ...
        slli  t1, t1, 63                ; ...
        xor   t0, t0, t1                ; ...
        sd    t0, V_VAL(s2)             ; ...
        j     fun_ret                   ; ...
fun_reg:
        mv    a0, s2                    ; else: tp = 1 << 63; xor
        la    t6, gv                    ; ...
        xcall ra, c0, t6                ; ...
        lbu   s3, ereg(a0)              ; ...
        li    a0, OP_ADDI               ; ...
        li    a1, X_TP                  ; ...
        li    a2, 0                     ; ...
        li    a3, 1                     ; ...
        jalr  ra, gp, e_i-R             ; ...
        li    a0, OP_SLLI               ; ...
        li    a1, X_TP                  ; ...
        li    a2, X_TP                  ; ...
        li    a3, 63                    ; ...
        jalr  ra, gp, e_i-R             ; ...
        li    a0, A_XOR                 ; ...
        mv    a1, s3                    ; ...
        mv    a2, s3                    ; ...
        li    a3, X_TP                  ; ...
        jalr  ra, gp, e_r-R             ; ...
fun_ret:
        jalr  zero, gp, lv3-R           ; done
