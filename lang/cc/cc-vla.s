; =============================================================================
; cc-vla.s: variable-length arrays
; =============================================================================
;
; An array type whose size is not a constant (TF_VM) keeps its size in a frame
; word (TY_AUX), computed where the declarator stands; sizeof and pointer
; arithmetic read that word. The storage of such an array comes from malloc:
; its address is a frame word (the object is reached as a structure parameter
; is, SF_REF), given back at the end of its block and before a return.
;
; In a parameter list no code can be emitted: the text of a dimension that is
; not a constant is kept in the arena (TF_VMD, TY_COUNT = its record: the
; length, the text; TY_AUX = 1), and read again, as an expression, when the
; function is entered (vm_inst). An array of such arrays waits too (TF_VMD,
; TY_AUX = 0, TY_COUNT = its constant count).

        .data                           ; ...
m_malloc: .asciz "malloc"               ; where the storage comes from
m_free:   .asciz "free"                 ; ... and goes
m_dimmac: .asciz "an array dimension that a macro ends in" ; ...
        .align 8                        ; ...
fn_live:  .dword 0                      ; 1: inside a function's body (a dimension may be a value)
fn_vla:   .dword 0                      ; 1: the function has variable-length arrays
fn_sy0:   .dword 0                      ; the symbol table's top at its first local

        .far                            ; code units
        .align 4096                     ; ---- unit: vla ----
u_vla:
; vm_size(a0 = type): push its size: a constant, or the frame word of a
; variable array type
vm_size:
        jalr  t6, gp, ent1-R            ; s1 = type
        mv    s1, a0                    ; ...
        lbu   t0, TY_KIND(s1)           ; ...
        addi  t0, t0, -TK_ARRAY         ; ...
        bnez  t0, vms_c                 ; ...
        lbu   t0, TY_FLAGS(s1)          ; ...
        andi  t0, t0, TF_VM             ; ...
        beqz  t0, vms_c                 ; ...
        li    a0, VK_LOC                ; ...
        li    a1, Y_LONG                ; ...
        lhu   a2, TY_AUX(s1)            ; ...
        jalr  ra, gp, vpush-R           ; ...
        li    t0, X_SP                  ; ...
        sb    t0, V_REG(a0)             ; ...
        jalr  zero, gp, lv1-R           ; ...
vms_c:
        li    a0, VK_CONST              ; ...
        li    a1, Y_LONG                ; ...
        lwu   a2, TY_SIZE(s1)           ; ...
        jalr  ra, gp, vpush-R           ; ...
        jalr  zero, gp, lv1-R           ; done

; vm_store(s2 = frame offset): the value on top goes to that frame word and is popped
vm_store:
        jalr  t6, gp, ent0-R            ; ...
        ld    a0, vsp(zero)             ; ...
        la    t6, gv                    ; ...
        xcall ra, c0, t6                ; ...
        lbu   a1, ereg(a0)              ; sd r, slot(sp)
        li    a0, OP_SD                 ; ...
        li    a2, X_SP                  ; ...
        ld    a3, sp_bias(zero)         ; ...
        add   a3, a3, s2                ; ...
        jalr  ra, gp, e_i-R             ; ...
        la    t6, vpop                  ; ...
        xcall ra, c0, t6                ; ...
        jalr  zero, gp, lv0-R           ; done

; vm_set(a0 = array type): [count] -> : the type's size, count elements, is
; computed into a frame word
vm_set:
        jalr  t6, gp, ent2-R            ; s1 = type, s2 = frame offset
        mv    s1, a0                    ; ...
        li    a0, 8                     ; ...
        li    a1, 8                     ; ...
        la    t6, fr_alloc_x            ; ...
        xcall ra, c0, t6                ; ...
        mv    s2, a0                    ; ...
        lhu   a0, TY_BASE(s1)           ; ...
        la    t6, vm_size               ; ...
        xcall ra, c0, t6                ; ...
        li    a0, '*'                   ; ...
        la    t6, g_binop               ; ...
        xcall ra, c0, t6                ; ...
        la    t6, vm_store              ; ...
        xcall ra, c0, t6                ; ...
        li    t0, TF_VM                 ; ...
        sb    t0, TY_FLAGS(s1)          ; ...
        sh    s2, TY_AUX(s1)            ; ...
        sw    zero, TY_SIZE(s1)         ; ...
        jalr  zero, gp, lv2-R           ; done

; dim_save(a0 = start, a1 = end of a text in the arena) -> a0 = its record,
; kept with the macros: the length, the text
dim_save:
        jalr  t6, gp, ent3-R            ; s1 = cursor, s2 = end, s3 = record
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        ld    s3, mac_top(zero)         ; ...
        mv    a0, s3                    ; ...
        sub   a1, s2, s1                ; ...
        jalr  ra, gp, far_sd-R          ; ...
        addi  a0, s3, 8                 ; ...
        jalr  ra, gp, wb_open-R         ; ...
dms_l:
        bgeu  s1, s2, dms_e             ; ...
        mv    a0, s1                    ; ...
        jalr  ra, gp, rb_get-R          ; ...
        jalr  ra, gp, wb_put-R          ; ...
        addi  s1, s1, 1                 ; ...
        j     dms_l                     ; ...
dms_e:
        jalr  ra, gp, wb_close-R        ; ...
        addi  a0, a0, 7                 ; ...
        srli  a0, a0, 3                 ; ...
        slli  a0, a0, 3                 ; ...
        sd    a0, mac_top(zero)         ; ...
        mv    a0, s3                    ; ...
        jalr  zero, gp, lv3-R           ; done

; dim_eval(a0 = record): the kept dimension is read as an expression: its
; value, a long, stays on the stack
dim_eval:
        jalr  t6, gp, ent2-R            ; s1 = record, s2 = the token as it was
        mv    s1, a0                    ; ...
        ld    s2, tok(zero)             ; ...
        jalr  ra, gp, far_ld-R          ; its length
        addi  t0, s1, 8                 ; ...
        add   a1, t0, a0                ; ...
        mv    a0, t0                    ; ...
        li    a2, 3                     ; (the scanner sees the end of the text)
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        jalr  ra, gp, in_push-R         ; ...
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        la    t6, expr                  ; ...
        xcall ra, c0, t6                ; ...
        ld    a0, vsp(zero)             ; ...
        la    t6, v_decay               ; ...
        xcall ra, c0, t6                ; ...
        ld    a0, vsp(zero)             ; ...
        li    a1, Y_LONG                ; ...
        la    t6, g_cast                ; ...
        xcall ra, c0, t6                ; ...
        jalr  ra, gp, in_pop-R          ; ...
        sd    s2, tok(zero)             ; ...
        jalr  zero, gp, lv2-R           ; done

; vm_inst(a0 = type): the array types of a parameter that waited for the
; function's entry get their sizes (the element's first)
vm_inst:
        jalr  t6, gp, ent1-R            ; s1 = type
        mv    s1, a0                    ; ...
        lbu   t0, TY_KIND(s1)           ; ...
        addi  t0, t0, -TK_PTR           ; ...
        sltiu t0, t0, 2                 ; (a pointer or an array)
        beqz  t0, vmi_ret               ; ...
        lhu   a0, TY_BASE(s1)           ; ...
        la    t6, vm_inst               ; ...
        xcall ra, c0, t6                ; ...
        lbu   t0, TY_KIND(s1)           ; ...
        addi  t0, t0, -TK_ARRAY         ; ...
        bnez  t0, vmi_ret               ; ...
        lbu   t0, TY_FLAGS(s1)          ; ...
        andi  t0, t0, TF_VMD            ; ...
        beqz  t0, vmi_ret               ; ...
        lhu   t0, TY_AUX(s1)            ; its count: a kept text, or a constant
        beqz  t0, vmi_c                 ; ...
        lwu   a0, TY_COUNT(s1)          ; ...
        la    t6, dim_eval              ; ...
        xcall ra, c0, t6                ; ...
        j     vmi_set                   ; ...
vmi_c:
        li    a0, VK_CONST              ; ...
        li    a1, Y_LONG                ; ...
        lwu   a2, TY_COUNT(s1)          ; ...
        jalr  ra, gp, vpush-R           ; ...
vmi_set:
        mv    a0, s1                    ; ...
        la    t6, vm_set                ; ...
        xcall ra, c0, t6                ; ...
vmi_ret:
        jalr  zero, gp, lv1-R           ; done

; vla_new(a0 = symbol): the storage of a variable-length array: from malloc,
; its address in a frame word
vla_new:
        jalr  t6, gp, ent2-R            ; s1 = symbol, s2 = frame offset
        mv    s1, a0                    ; ...
        li    a0, 8                     ; ...
        li    a1, 8                     ; ...
        la    t6, fr_alloc_x            ; ...
        xcall ra, c0, t6                ; ...
        mv    s2, a0                    ; ...
        li    a0, m_malloc              ; malloc(size)
        li    a1, 6                     ; ...
        la    t6, lib_fn                ; ...
        xcall ra, c0, t6                ; ...
        lhu   a0, SY_TYPE(s1)           ; ...
        la    t6, vm_size               ; ...
        xcall ra, c0, t6                ; ...
        li    a0, 1                     ; ...
        la    t6, g_call                ; ...
        xcall ra, c0, t6                ; ...
        la    t6, vm_store              ; ...
        xcall ra, c0, t6                ; ...
        sw    s2, SY_VAL(s1)            ; ...
        li    t0, SF_REF | SF_VLA       ; ...
        sb    t0, SY_FLAGS(s1)          ; ...
        li    t0, 1                     ; ...
        sd    t0, fn_vla(zero)          ; ...
        jalr  zero, gp, lv2-R           ; done

; vla_free(a0 = a symbol record): the variable-length arrays declared from
; that record on are given back
vla_free:
        jalr  t6, gp, ent1-R            ; s1 = symbol
        mv    s1, a0                    ; ...
vlf_l:
        ld    t0, sym_top(zero)         ; ...
        bgeu  s1, t0, vlf_ret           ; ...
        lbu   t0, SY_CLASS(s1)          ; ...
        addi  t0, t0, -SC_AUTO          ; ...
        bnez  t0, vlf_n                 ; ...
        lbu   t0, SY_FLAGS(s1)          ; ...
        andi  t0, t0, SF_VLA            ; ...
        beqz  t0, vlf_n                 ; ...
        li    a0, m_free                ; free(its address)
        li    a1, 4                     ; ...
        la    t6, lib_fn                ; ...
        xcall ra, c0, t6                ; ...
        li    a0, VK_LOC                ; ...
        li    a1, Y_VOIDP               ; ...
        lw    a2, SY_VAL(s1)            ; ...
        jalr  ra, gp, vpush-R           ; ...
        li    t0, X_SP                  ; ...
        sb    t0, V_REG(a0)             ; ...
        li    a0, 1                     ; ...
        la    t6, g_call                ; ...
        xcall ra, c0, t6                ; ...
        la    t6, vpop                  ; ...
        xcall ra, c0, t6                ; ...
vlf_n:
        addi  s1, s1, SYSZ              ; ...
        j     vlf_l                     ; ...
vlf_ret:
        jalr  zero, gp, lv1-R           ; done

; st_vfree(): before a return: the value on top, if it is not a structure, is
; loaded, and the function's variable-length arrays are given back
st_vfree:
        jalr  t6, gp, ent0-R            ; ...
        ld    t0, fn_vla(zero)          ; ...
        beqz  t0, svf_ret               ; ...
        ld    t0, tok(zero)             ; (return ; has no value)
        li    t1, ';'                   ; ...
        ld    t2, vsp(zero)             ; ...
        li    t3, VSTK                  ; ...
        bltu  t2, t3, svf_free          ; ...
        lhu   t0, V_TYPE(t2)            ; ...
        lbu   t0, TY_KIND(t0)           ; ...
        beqz  t0, svf_free              ; (void)
        addi  t0, t0, -TK_STRUCT        ; ...
        sltiu t0, t0, 2                 ; ...
        bnez  t0, svf_free              ; ...
        mv    a0, t2                    ; ...
        la    t6, v_decay               ; ...
        xcall ra, c0, t6                ; ...
        ld    a0, vsp(zero)             ; ...
        la    t6, gv                    ; ...
        xcall ra, c0, t6                ; ...
svf_free:
        ld    a0, fn_sy0(zero)          ; ...
        la    t6, vla_free              ; ...
        xcall ra, c0, t6                ; ...
svf_ret:
        jalr  zero, gp, lv0-R           ; done
