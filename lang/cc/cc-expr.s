; =============================================================================
; cc-expr.s: expressions
; =============================================================================
;
; Recursive descent; every routine leaves one entry on the value stack and
; calls the code generator (cc-gen.s) as it goes.

        .data                           ; this unit's tables
        .align 8                        ; (words first)
; binary operators: token, precedence (higher binds tighter); 0 ends the table
bin_tab:  .byte '*', 10, '/', 10, '%', 10, '+', 9; .
          .byte '-', 9, T_SHL, 8, T_SHR, 8; .
          .byte '<', 7, '>', 7, T_LE, 7, T_GE, 7; .
          .byte T_EQ, 6, T_NE, 6, '&', 5, '^', 4; .
          .byte '|', 3, T_LAND, 2, T_LOR, 1, 0, 0 ; .
        .align 8                        ; ...
m_func:   .asciz "__func__"             ; (8 bytes: compared as one word)
        .align 8                        ; ...
; the operators of op= in the order of T_ASG + n
asg_tab:  .byte '+', '-', '*', '/', '%', '&', '|', '^'; .
          .byte T_SHL, T_SHR            ; .
        .align 8                        ; ...

        .far                            ; code units
        .align 4096                     ; ---- unit: expr1 ----
u_expr1:
; skip(a0 = token): the current token must be this one; read the next
skip:
        jalr  t6, gp, ent0-R            ; ...
        ld    t0, tok(zero)             ; ...
        beq   t0, a0, skp_ok            ; ...
        li    a0, m_expect              ; ...
        jalr  zero, gp, errtok-R        ; ...
skp_ok:
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        jalr  zero, gp, lv0-R           ; done

; expr(): expression { , expression }
expr:
        jalr  t6, gp, ent0-R            ; ...
ex_l:
        la    t6, assign                ; ...
        xcall ra, c0, t6                ; ...
        ld    t0, tok(zero)             ; a comma: the value so far is dropped
        li    t1, ','                   ; ...
        bne   t0, t1, ex_ret            ; ...
        la    t6, vpop                  ; ...
        xcall ra, c0, t6                ; ...
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        j     ex_l                      ; ...
ex_ret:
        jalr  zero, gp, lv0-R           ; done

; assign(): conditional, or unary = assign, or unary op= assign
assign:
        jalr  t6, gp, ent1-R            ; s1 = the operator of op=
        la    t6, cond                  ; ...
        xcall ra, c0, t6                ; ...
        ld    t0, tok(zero)             ; ...
        li    t1, '='                   ; ...
        bne   t0, t1, as_op             ; ...
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        la    t6, assign                ; the right side
        xcall ra, c0, t6                ; ...
        j     as_store                  ; ...
as_op:
        addi  t0, t0, -T_ASG            ; op= ?
        sltiu t1, t0, 10                ; ...
        beqz  t1, as_ret                ; no: not an assignment
        lbu   s1, asg_tab(t0)           ; ...
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        la    t6, v_dupval              ; [lvalue, its value]
        xcall ra, c0, t6                ; ...
        la    t6, assign                ; [lvalue, value, right side]
        xcall ra, c0, t6                ; ...
        mv    a0, s1                    ; [lvalue, result]
        la    t6, g_binop               ; ...
        xcall ra, c0, t6                ; ...
as_store:
        ld    a0, vsp(zero)             ; converted to the lvalue's type, and stored
        lhu   a1, V_TYPE-VSZ(a0)        ; ...
        la    t6, g_cast                ; ...
        xcall ra, c0, t6                ; ...
        la    t6, g_store               ; ...
        xcall ra, c0, t6                ; ...
as_ret:
        jalr  zero, gp, lv1-R           ; done

; cond(): binary [ ? expr : cond ]
cond:
        jalr  t6, gp, ent4-R            ; s1 = chain / the end jump, s2 = register index, s3 = type, s4 = scratch
        li    a0, 1                     ; ...
        la    t6, binary                ; ...
        xcall ra, c0, t6                ; ...
        ld    t0, tok(zero)             ; ...
        li    t1, '?'                   ; ...
        bne   t0, t1, co_ret            ; ...
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        ld    t0, vsp(zero)             ; a constant condition: only one branch is evaluated
        lbu   t1, V_KIND(t0)            ; ...
        addi  t1, t1, -VK_CONST         ; ...
        lhu   t2, V_SYM(t0)             ; ...
        or    t1, t1, t2                ; ...
        bnez  t1, co_var                ; ...
        la    t6, cond_const            ; ...
        xcall ra, c0, t6                ; ...
        j     co_ret                    ; ...
co_var:
        li    a0, 1                     ; jump to the second branch if false
        li    a1, 0                     ; ...
        la    t6, g_tst                 ; ...
        xcall ra, c0, t6                ; ...
        mv    s1, a0                    ; ...
        la    t6, expr                  ; the first branch
        xcall ra, c0, t6                ; ...
        li    a0, ':'                   ; ...
        la    t6, skip                  ; ...
        xcall ra, c0, t6                ; ...
        la    t6, co_val                ; its value in a register: s2, s3 = type (s2 = -1: void)
        xcall ra, c0, t6                ; ...
        bltz  s2, co_j                  ; ...
        li    t0, 6                     ; (not in a0: the other branch may call)
        bne   s2, t0, co_keep           ; ...
        la    t6, ralloc_x              ; ...
        xcall ra, c0, t6                ; ...
        mv    s2, a0                    ; ...
        lbu   a1, ereg(s2)              ; mv
        li    a0, OP_ADDI               ; ...
        li    a2, X_A0                  ; ...
        li    a3, 0                     ; ...
        jalr  ra, gp, e_i-R             ; ...
        ld    t0, nreg(zero)            ; ...
        andi  t0, t0, 63                ; ...
        sd    t0, nreg(zero)            ; ...
co_keep:
        ld    t0, vsp(zero)             ; the entry goes, the register stays reserved
        addi  t0, t0, -VSZ              ; ...
        sd    t0, vsp(zero)             ; ...
co_j:
        la    t6, g_jmp                 ; over the second branch
        xcall ra, c0, t6                ; ...
        mv    s4, a0                    ; ...
        mv    a0, s1                    ; which starts here
        ld    a1, code_pc(zero)         ; ...
        la    t6, g_resolve             ; ...
        xcall ra, c0, t6                ; ...
        mv    s1, s4                    ; s1 = the jump to the end
        la    t6, cond                  ; the second branch
        xcall ra, c0, t6                ; ...
        bltz  s2, co_void               ; ...
        ld    s4, vsp(zero)             ; ...
        mv    a0, s4                    ; ...
        la    t6, v_decay               ; ...
        xcall ra, c0, t6                ; ...
        lbu   t1, TY_KIND(s3)           ; structures: the second one's address too
        addi  t1, t1, -TK_STRUCT        ; ...
        sltiu t1, t1, 2                 ; ...
        beqz  t1, co_ar                 ; ...
        mv    a0, s3                    ; ...
        jalr  ra, gp, ty_ptr-R          ; ...
        mv    a1, a0                    ; ...
        mv    a0, s4                    ; ...
        la    t6, v_addrof              ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s4                    ; ...
        la    t6, gv                    ; ...
        xcall ra, c0, t6                ; ...
        j     co_mv                     ; ...
co_ar:
        lhu   a1, V_TYPE(s4)            ; the common type: arithmetic conversions, or the
        lbu   t0, TY_KIND(a1)           ;   pointer's type if one of them is a pointer
        lbu   t1, TY_KIND(s3)           ; ...
        li    t2, TK_PTR                ; ...
        beq   t1, t2, co_t1             ; ...
        beq   t0, t2, co_conv           ; ...
        addi  t0, t0, -1                ; both integers?
        sltiu t0, t0, 5                 ; ...
        addi  t1, t1, -1                ; ...
        sltiu t1, t1, 5                 ; ...
        and   t0, t0, t1                ; ...
        beqz  t0, co_t1                 ; ...
        mv    a0, s3                    ; ...
        la    t6, arith_x               ; ...
        xcall ra, c0, t6                ; ...
        mv    a1, a0                    ; ...
        j     co_conv                   ; ...
co_t1:
        mv    a1, s3                    ; ...
co_conv:
        xor   t0, a1, s3                ; (the first branch's value has that type? if not,
        snez  t0, t0                    ;  an int result is dirty)
        mv    s3, a1                    ; ...
        slli  t0, t0, 8                 ; ...
        or    s2, s2, t0                ; (kept in s2's bit 8)
        mv    a0, s4                    ; ...
        la    t6, g_cast                ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s4                    ; into the first branch's register
        la    t6, gv_c                  ; ...
        xcall ra, c0, t6                ; ...
co_mv:
        andi  t1, s2, 255               ; ...
        beq   a0, t1, co_same           ; ...
        lbu   a2, ereg(a0)              ; mv
        lbu   a1, ereg(t1)              ; ...
        sb    t1, V_REG(s4)             ; ...
        la    t6, rfree_x               ; ...
        xcall ra, c0, t6                ; (a0 = the index to free; a1, a2 are kept)
        li    a0, OP_ADDI               ; ...
        li    a3, 0                     ; ...
        jalr  ra, gp, e_i-R             ; ...
co_same:
        lbu   t0, TY_KIND(s3)           ; a structure: the register holds its address
        addi  t0, t0, -TK_STRUCT        ; ...
        sltiu t0, t0, 2                 ; ...
        beqz  t0, co_dt                 ; ...
        li    t0, VK_IND                ; ...
        sb    t0, V_KIND(s4)            ; ...
        sh    s3, V_TYPE(s4)            ; ...
        sd    zero, V_VAL(s4)           ; ...
        j     co_end                    ; ...
co_dt:
        srli  t0, s2, 8                 ; dirty?
        beqz  t0, co_end                ; ...
        lwu   t0, TY_SIZE(s3)           ; ...
        sltiu t0, t0, 8                 ; ...
        beqz  t0, co_end                ; ...
        li    t0, VF_DIRTY              ; ...
        sb    t0, V_FLAGS(s4)           ; ...
        j     co_end                    ; ...
co_void:
        la    t6, vpop                  ; neither branch has a value
        xcall ra, c0, t6                ; ...
        li    a0, VK_CONST              ; ...
        li    a1, Y_VOID                ; ...
        li    a2, 0                     ; ...
        jalr  ra, gp, vpush-R           ; ...
co_end:
        mv    a0, s1                    ; the end
        ld    a1, code_pc(zero)         ; ...
        sub   a1, a1, s1                ; ...
        la    t6, g_setoff              ; ...
        xcall ra, c0, t6                ; ...
co_ret:
        jalr  zero, gp, lv4-R           ; done
; co_val: the top value into a register: s2 = its index, s3 = its type; a void
; value is dropped (s2 = -1). Uses the caller's s registers.
co_val:
        jalr  t6, gp, ent0-R            ; ...
        ld    a0, vsp(zero)             ; ...
        la    t6, v_decay               ; ...
        xcall ra, c0, t6                ; ...
        ld    a0, vsp(zero)             ; ...
        lhu   s3, V_TYPE(a0)            ; ...
        lbu   t0, TY_KIND(s3)           ; void?
        bnez  t0, cv_v                  ; ...
        la    t6, vpop                  ; ...
        xcall ra, c0, t6                ; ...
        li    s2, -1                    ; ...
        jalr  zero, gp, lv0-R           ; ...
cv_v:
        addi  t0, t0, -TK_STRUCT        ; a structure: its address is what is selected
        sltiu t0, t0, 2                 ; ...
        beqz  t0, cv_g                  ; ...
        mv    a0, s3                    ; ...
        jalr  ra, gp, ty_ptr-R          ; ...
        mv    a1, a0                    ; ...
        ld    a0, vsp(zero)             ; ...
        la    t6, v_addrof              ; ...
        xcall ra, c0, t6                ; ...
cv_g:
        ld    a0, vsp(zero)             ; ...
        la    t6, gv_c                  ; ...
        xcall ra, c0, t6                ; ...
        mv    s2, a0                    ; ...
        jalr  zero, gp, lv0-R           ; done

; binary(a0 = lowest precedence taken): unary { operator binary }
binary:
        jalr  t6, gp, ent4-R            ; s1 = lowest precedence, s2 = operator, s3 = its precedence, s4 = chain
        mv    s1, a0                    ; ...
        la    t6, unary                 ; ...
        xcall ra, c0, t6                ; ...
bi_l:
        ld    s2, tok(zero)             ; a binary operator of enough precedence?
        li    t0, bin_tab               ; ...
bi_find:
        lbu   t1, 0(t0)                 ; ...
        beqz  t1, bi_ret                ; not an operator
        beq   t1, s2, bi_found          ; ...
        addi  t0, t0, 2                 ; ...
        j     bi_find                   ; ...
bi_found:
        lbu   s3, 1(t0)                 ; ...
        blt   s3, s1, bi_ret            ; ...
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        addi  t0, s2, -T_LAND           ; && or ||
        sltiu t0, t0, 2                 ; ...
        beqz  t0, bi_op                 ; ...
        ld    t0, vsp(zero)             ; a constant on the left decides here
        lbu   t1, V_KIND(t0)            ; ...
        addi  t1, t1, -VK_CONST         ; ...
        lhu   t2, V_SYM(t0)             ; ...
        or    t1, t1, t2                ; ...
        bnez  t1, bi_sc                 ; ...
        la    t6, bin_const             ; (s2 = operator, s3 = its precedence)
        xcall ra, c0, t6                ; ...
        j     bi_l                      ; ...
bi_sc:
        li    a0, T_LOR                 ; &&: jump if false (sense 1); ||: if true (0)
        sub   a0, a0, s2                ; ...
        li    a1, 0                     ; ...
        la    t6, g_tst                 ; ...
        xcall ra, c0, t6                ; ...
        mv    s4, a0                    ; ...
        addi  a0, s3, 1                 ; the right operand
        la    t6, binary                ; ...
        xcall ra, c0, t6                ; ...
        li    a0, T_LOR                 ; and the same test of it
        sub   a0, a0, s2                ; ...
        mv    a1, s4                    ; ...
        la    t6, g_tst                 ; ...
        xcall ra, c0, t6                ; ...
        mv    a2, a0                    ; the value is where control goes
        li    a0, VK_JMP                ; ...
        li    a1, Y_INT                 ; ...
        jalr  ra, gp, vpush-R           ; ...
        li    t0, T_LOR                 ; (&&: the jumps mean false)
        sub   t0, t0, s2                ; ...
        slli  t0, t0, 1                 ; ...
        sb    t0, V_FLAGS(a0)           ; ...
        j     bi_l                      ; ...
bi_op:
        ld    a0, vsp(zero)             ; pending jumps cannot wait while the right operand runs
        lbu   t0, V_KIND(a0)            ; ...
        addi  t0, t0, -VK_JMP           ; ...
        bnez  t0, bi_r                  ; ...
        la    t6, gv                    ; ...
        xcall ra, c0, t6                ; ...
bi_r:
        addi  a0, s3, 1                 ; the right operand
        la    t6, binary                ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s2                    ; ...
        la    t6, g_binop               ; ...
        xcall ra, c0, t6                ; ...
        j     bi_l                      ; ...
bi_ret:
        jalr  zero, gp, lv4-R           ; done

; cond_const(): c ? a : b with a constant c on top of the stack, after the ?:
; both branches are parsed, the one not chosen without code
cond_const:
        jalr  t6, gp, ent2-R            ; s1 = the condition's truth, s2 = nocode as it was
        ld    t0, vsp(zero)             ; ...
        ld    s1, V_VAL(t0)             ; ...
        snez  s1, s1                    ; ...
        addi  t0, t0, -VSZ              ; ...
        sd    t0, vsp(zero)             ; ...
        ld    s2, nocode(zero)          ; ...
        bnez  s1, cdc_a                 ; the first branch is not chosen: no code for it
        li    t0, 1                     ; ...
        sd    t0, nocode(zero)          ; ...
cdc_a:
        la    t6, expr                  ; ...
        xcall ra, c0, t6                ; ...
        sd    s2, nocode(zero)          ; ...
        bnez  s1, cdc_colon             ; ...
        la    t6, vpop                  ; ...
        xcall ra, c0, t6                ; ...
cdc_colon:
        li    a0, ':'                   ; ...
        la    t6, skip                  ; ...
        xcall ra, c0, t6                ; ...
        beqz  s1, cdc_b                 ; the second branch is not chosen: no code for it
        li    t0, 1                     ; ...
        sd    t0, nocode(zero)          ; ...
cdc_b:
        la    t6, cond                  ; ...
        xcall ra, c0, t6                ; ...
        sd    s2, nocode(zero)          ; ...
        beqz  s1, cdc_ret               ; ...
        la    t6, vpop                  ; ...
        xcall ra, c0, t6                ; ...
cdc_ret:
        jalr  zero, gp, lv2-R           ; done

; bin_const(): && or || (the caller's s2, precedence s3) whose left operand, on
; top of the stack, is a constant: the result is a constant, or the right
; operand's truth
bin_const:
        jalr  t6, gp, ent0-R            ; (s4: the caller's to lose)
        ld    t0, vsp(zero)             ; the left operand's truth
        ld    s4, V_VAL(t0)             ; ...
        snez  s4, s4                    ; ...
        addi  t0, t0, -VSZ              ; (popped)
        sd    t0, vsp(zero)             ; ...
        addi  t1, s2, -T_LAND           ; && with false, || with true: the right operand is
        xor   t1, t1, s4                ;   parsed but not evaluated
        bnez  t1, bic_right             ; (&& true, || false: the right operand decides)
        ld    t0, nocode(zero)          ; ...
        addi  sp, sp, -8                ; ...
        sd    t0, 0(sp)                 ; ...
        li    t0, 1                     ; ...
        sd    t0, nocode(zero)          ; ...
        addi  a0, s3, 1                 ; ...
        la    t6, binary                ; ...
        xcall ra, c0, t6                ; ...
        la    t6, vpop                  ; ...
        xcall ra, c0, t6                ; ...
        ld    t0, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        sd    t0, nocode(zero)          ; ...
        li    a0, VK_CONST              ; the left operand's truth is the result
        li    a1, Y_INT                 ; ...
        mv    a2, s4                    ; ...
        jalr  ra, gp, vpush-R           ; ...
        jalr  zero, gp, lv0-R           ; ...
bic_right:
        addi  a0, s3, 1                 ; ...
        la    t6, binary                ; ...
        xcall ra, c0, t6                ; ...
        ld    s4, vsp(zero)             ; a constant: its truth
        lbu   t1, V_KIND(s4)            ; ...
        addi  t1, t1, -VK_CONST         ; ...
        lhu   t2, V_SYM(s4)             ; ...
        or    t1, t1, t2                ; ...
        bnez  t1, bic_tst               ; ...
        ld    t0, V_VAL(s4)             ; ...
        snez  t0, t0                    ; ...
        sd    t0, V_VAL(s4)             ; ...
        li    t0, Y_INT                 ; ...
        sh    t0, V_TYPE(s4)            ; ...
        jalr  zero, gp, lv0-R           ; ...
bic_tst:
        li    a0, 1                     ; anything else: jumps taken when it is false
        li    a1, 0                     ; ...
        la    t6, g_tst                 ; ...
        xcall ra, c0, t6                ; ...
        mv    a2, a0                    ; ...
        li    a0, VK_JMP                ; ...
        li    a1, Y_INT                 ; ...
        jalr  ra, gp, vpush-R           ; ...
        li    t0, VF_INV                ; ...
        sb    t0, V_FLAGS(a0)           ; ...
        jalr  zero, gp, lv0-R           ; done

; arith_x(a0, a1 = types) -> a0 = their common type; rfree_x(a0 = index): for this unit
arith_x:
        jalr  t6, gp, ent2-R            ; ...
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        la    t6, promote_x             ; promote both
        xcall ra, c0, t6                ; ...
        mv    s1, a0                    ; ...
        mv    a0, s2                    ; ...
        la    t6, promote_x             ; ...
        xcall ra, c0, t6                ; ...
        beq   a0, s1, arx_ret           ; the same
        li    t0, Y_ULONG               ; unsigned long, then long, then unsigned
        beq   a0, t0, arx_ret           ; ...
        beq   s1, t0, arx_a             ; ...
        li    t0, Y_LONG                ; ...
        beq   a0, t0, arx_ret           ; ...
        beq   s1, t0, arx_a             ; ...
        li    a0, Y_UINT                ; ...
        j     arx_ret                   ; ...
arx_a:
        mv    a0, s1                    ; ...
arx_ret:
        jalr  zero, gp, lv2-R           ; done
rfree_x:
        li    t1, 1                     ; clear its bit (a1, a2 are kept)
        sll   t1, t1, a0                ; ...
        ld    t0, nreg(zero)            ; ...
        or    t0, t0, t1                ; ...
        xor   t0, t0, t1                ; ...
        sd    t0, nreg(zero)            ; ...
        xret  ra                        ; done

; unary(): the operators before an operand; then postfix
unary:
        jalr  t6, gp, ent3-R            ; s1 = the operator, s2 = type, s3 = scratch
        ld    s1, tok(zero)             ; ...
        li    t0, T_NUM                 ; a number
        bne   s1, t0, un_str            ; ...
        li    a0, VK_CONST              ; ...
        ld    a1, tk_ty(zero)           ; ...
        ld    a2, tk_val(zero)          ; ...
        jalr  ra, gp, vpush-R           ; ...
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        j     un_post                   ; ...
un_str:
        li    t0, T_STR                 ; a string
        bne   s1, t0, un_id             ; ...
        la    t6, str_lit               ; ...
        xcall ra, c0, t6                ; ...
        j     un_post                   ; ...
un_id:
        li    t0, T_ID                  ; a name
        bne   s1, t0, un_par            ; ...
        la    t6, prim_id               ; ...
        xcall ra, c0, t6                ; ...
        j     un_post                   ; ...
un_par:
        li    t0, '('                   ; ( expression ) or ( type ) operand
        bne   s1, t0, un_ops            ; ...
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        la    t6, is_type               ; ...
        xcall ra, c0, t6                ; ...
        bnez  a0, un_cast               ; ...
        la    t6, expr                  ; ...
        xcall ra, c0, t6                ; ...
        li    a0, ')'                   ; ...
        la    t6, skip                  ; ...
        xcall ra, c0, t6                ; ...
        j     un_post                   ; ...
un_cast:
        la    t6, type_name             ; ...
        xcall ra, c0, t6                ; ...
        mv    s2, a0                    ; ...
        li    a0, ')'                   ; ...
        la    t6, skip                  ; ...
        xcall ra, c0, t6                ; ...
        ld    t0, tok(zero)             ; ( type ) { ... }: a compound literal
        li    t1, '{'                   ; ...
        bne   t0, t1, un_cst            ; ...
        mv    a0, s2                    ; ...
