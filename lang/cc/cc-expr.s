        xcall ra, c0, t6                ; ...
szo_push:
        sd    s2, nocode(zero)          ; ...
        lwu   a2, TY_SIZE(s1)           ; ...
        li    a0, VK_CONST              ; an unsigned long
        li    a1, Y_ULONG               ; ...
        jalr  ra, gp, vpush-R           ; ...
        jalr  zero, gp, lv3-R           ; done
