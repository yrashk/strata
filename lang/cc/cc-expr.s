        jalr  t6, gp, ent3-R            ; s1 = length with the zero, s2 = address, s3 = index
        ld    s1, str_len(zero)         ; ...
        addi  s1, s1, 1                 ; ...
        li    s2, 0                     ; (a dry run of an initialiser stores nothing)
        ld    t0, ini_dry(zero)         ; ...
        bnez  t0, stl_ty                ; ...
        mv    a0, s1                    ; its bytes
        li    a1, 1                     ; ...
        jalr  ra, gp, data_alloc-R      ; ...
        mv    s2, a0                    ; ...
        li    s3, 0                     ; ...
stl_b:
        add   a0, s2, s3                ; ...
        lbu   a1, STRBUF(s3)            ; ...
        jalr  ra, gp, data_b-R          ; ...
