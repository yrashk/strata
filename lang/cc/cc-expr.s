        li    t1, TK_FLOAT              ; ...
        bne   t0, t1, pf_conv           ; ...
        li    a1, Y_DOUBLE              ; ...
pf_conv:
        la    t6, g_cast                ; ...
        xcall ra, c0, t6                ; ...
        ld    a0, vsp(zero)             ; a structure is passed as the address of a copy
        lhu   t0, V_TYPE(a0)            ; ...
        lbu   t0, TY_KIND(t0)           ; ...
