        bltu  s3, s1, stl_b             ; ...
stl_ty:
        li    a0, TK_ARRAY              ; char [length + 1]
        mv    a1, s1                    ; ...
        li    a2, 1                     ; ...
        li    a3, Y_CHAR                ; ...
        jalr  ra, gp, ty_new-R          ; ...
        sw    s1, TY_COUNT(a0)          ; ...
        mv    a1, a0                    ; ...
        li    a0, VK_GLOB               ; ...
        mv    a2, s2                    ; ...
