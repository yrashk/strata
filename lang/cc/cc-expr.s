; sizeof_x(): sizeof ( type ) or sizeof operand: the size as a constant
sizeof_x:
        jalr  t6, gp, ent3-R            ; s1 = type, s2 = nocode as it was, s3 = scratch
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        ld    s2, nocode(zero)          ; an operand is parsed, but no code comes of it
        li    t0, 1                     ; ...
        sd    t0, nocode(zero)          ; ...
        ld    t0, tok(zero)             ; ...
        li    t1, '('                   ; ...
        bne   t0, t1, szo_un            ; ...
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        la    t6, is_type               ; ...
        xcall ra, c0, t6                ; ...
        beqz  a0, szo_ex                ; ...
        la    t6, type_name             ; ...
        xcall ra, c0, t6                ; ...
        mv    s1, a0                    ; ...
        li    a0, ')'                   ; ...
        la    t6, skip                  ; ...
        xcall ra, c0, t6                ; ...
        j     szo_push                  ; ...
szo_ex:
        la    t6, expr                  ; ( expression ), and what may follow it
        xcall ra, c0, t6                ; ...
        li    a0, ')'                   ; ...
        la    t6, skip                  ; ...
        xcall ra, c0, t6                ; ...
        la    t6, postfix               ; ...
        xcall ra, c0, t6                ; ...
