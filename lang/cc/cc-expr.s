        la    t6, v_rfree_x             ; ...
        xcall ra, c0, t6                ; ...
        ld    t0, 0(s2)                 ; ...
        sd    t0, -VSZ(s2)              ; ...
        ld    t0, 8(s2)                 ; ...
        sd    t0, 8-VSZ(s2)             ; ...
        ld    t0, 16(s2)                ; ...
        sd    t0, 16-VSZ(s2)            ; ...
        addi  s2, s2, -VSZ              ; ...
        sd    s2, vsp(zero)             ; ...
        j     pf_l                      ; ...
