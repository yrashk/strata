        la    t6, next                  ; the member's name
        xcall ra, c0, t6                ; ...
        ld    t0, tok(zero)             ; ...
        addi  t0, t0, -T_ID             ; ...
        bnez  t0, pf_bad                ; ...
        ld    s2, vsp(zero)             ; ...
        lhu   s3, V_TYPE(s2)            ; a structure or union
        lbu   t0, TY_KIND(s3)           ; ...
        addi  t0, t0, -TK_STRUCT        ; ...
        sltiu t0, t0, 2                 ; ...
        beqz  t0, pf_type               ; ...
        lhu   t0, TY_AUX(s3)            ; look the member up
        ld    t1, tk_val(zero)          ; ...
pf_mf:
        beqz  t0, pf_nomem              ; ...
        lwu   t2, SY_ID(t0)             ; ...
        beq   t2, t1, pf_mhit           ; ...
        lhu   t0, SY_PREV(t0)           ; ...
        j     pf_mf                     ; ...
pf_mhit:
        lw    t1, SY_VAL(t0)            ; its offset is added to the lvalue's
        ld    t2, V_VAL(s2)             ; ...
        add   t2, t2, t1                ; ...
        sd    t2, V_VAL(s2)             ; ...
        lhu   t1, SY_TYPE(t0)           ; ...
        sh    t1, V_TYPE(s2)            ; ...
        lhu   t1, SY_AUX(t0)            ; a bit-field: its place in the unit
        sh    t1, V_BOFF(s2)            ; ...
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        j     pf_l                      ; ...
pf_nomem:
        li    a0, m_nomem               ; ...
        li    a1, TB                    ; ...
        jalr  zero, gp, error2-R        ; ...
pf_type:
        li    a0, m_type                ; ...
        jalr  zero, gp, error-R         ; ...
pf_bad:
        li    a0, m_expect              ; ...
        jalr  zero, gp, errtok-R        ; ...
pf_inc:
        addi  t0, s1, -T_INC            ; operand++ operand--
        sltiu t1, t0, 2                 ; ...
        beqz  t1, pf_ret                ; ...
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        la    t6, v_dupval              ; [lvalue, value]: the old value, in a register
        xcall ra, c0, t6                ; ...
        ld    a0, vsp(zero)             ; ...
        la    t6, gv_c                  ; ...
        xcall ra, c0, t6                ; ...
        lbu   s4, ereg(a0)              ; ...
        ld    s2, vsp(zero)             ; ...
        lhu   s3, V_TYPE(s2)            ; the step: 1, or the size of what a pointer points to
        li    a2, 1                     ; ...
        lbu   t0, TY_KIND(s3)           ; ...
        addi  t0, t0, -TK_PTR           ; ...
        bnez  t0, pf_step               ; ...
        lhu   t0, TY_BASE(s3)           ; ...
        lwu   a2, TY_SIZE(t0)           ; ...
        bnez  a2, pf_step               ; ...
        li    a2, 1                     ; ...
pf_step:
        li    t0, T_INC                 ; ...
        beq   s1, t0, pf_new            ; ...
        neg   a2, a2                    ; ...
pf_new:
        li    a0, X_TP                  ; tp = the new value
        mv    a1, s4                    ; ...
        la    t6, g_addi                ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s3                    ; store it
        la    t6, st_op_x               ; ...
        xcall ra, c0, t6                ; ...
        li    a1, X_TP                  ; ...
        addi  a2, s2, -VSZ              ; ...
        la    t6, g_ldst                ; ...
        xcall ra, c0, t6                ; ...
