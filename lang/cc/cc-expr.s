        jalr  zero, gp, lv4-R           ; done

; arg_struct(): the structure on top of the stack is copied into a temporary
; of the frame; the temporary's address takes its place
arg_struct:
        jalr  t6, gp, ent2-R            ; s1 = value, s2 = type
        ld    s1, vsp(zero)             ; ...
        lhu   s2, V_TYPE(s1)            ; ...
        lwu   a0, TY_SIZE(s2)           ; ...
        lbu   a1, TY_ALIGN(s2)          ; ...
        la    t6, fr_alloc_x            ; ...
        xcall ra, c0, t6                ; ...
        mv    a2, a0                    ; [value, temporary]
        li    a0, VK_LOC                ; ...
        mv    a1, s2                    ; ...
        jalr  ra, gp, vpush-R           ; ...
        li    t0, X_SP                  ; ...
        sb    t0, V_REG(a0)             ; ...
        ld    t0, 0(a0)                 ; [temporary, value]
        ld    t1, 0(s1)                 ; ...
        sd    t1, 0(a0)                 ; ...
        sd    t0, 0(s1)                 ; ...
        ld    t0, 8(a0)                 ; ...
        ld    t1, 8(s1)                 ; ...
        sd    t1, 8(a0)                 ; ...
        sd    t0, 8(s1)                 ; ...
        ld    t0, 16(a0)                ; ...
        ld    t1, 16(s1)                ; ...
        sd    t1, 16(a0)                ; ...
        sd    t0, 16(s1)                ; ...
        la    t6, g_store               ; [temporary], copied
        xcall ra, c0, t6                ; ...
        mv    a0, s2                    ; its address
        jalr  ra, gp, ty_ptr-R          ; ...
        mv    a1, a0                    ; ...
        mv    a0, s1                    ; ...
        la    t6, v_addrof              ; ...
        xcall ra, c0, t6                ; ...
        jalr  zero, gp, lv2-R           ; done

; prim_id(): the identifier that is the current token, as a value
prim_id:
        jalr  t6, gp, ent3-R            ; s1 = symbol, s2 = its identifier, s3 = entry
        ld    s1, tk_sym(zero)          ; ...
        ld    s2, tk_val(zero)          ; ...
        la    t6, next                  ; ...
        xcall ra, c0, t6                ; ...
        bnez  s1, pi_have               ; ...
        ld    t0, tok(zero)             ; not declared: a call declares a function returning int
        li    t1, '('                   ; ...
        beq   t0, t1, pi_impl           ; ...
        mv    a0, s2                    ; ...
        jalr  ra, gp, id_name-R         ; ...
        ld    t0, 0(a0)                 ; "__func__": the function's name as a string
        ld    t1, m_func(zero)          ; ...
        bne   t0, t1, pi_undef          ; ...
        lbu   t0, 8(a0)                 ; ...
        bnez  t0, pi_undef              ; ...
        ld    t0, fn_sym(zero)          ; ...
        beqz  t0, pi_undef              ; ...
        lwu   a0, SY_ID(t0)             ; ...
        jalr  ra, gp, id_name-R         ; ...
        li    t0, 0                     ; -> STRBUF
pi_fn:
        add   t1, a0, t0                ; ...
        lbu   t1, 0(t1)                 ; ...
        sb    t1, STRBUF(t0)            ; ...
        addi  t0, t0, 1                 ; ...
        bnez  t1, pi_fn                 ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, str_len(zero)         ; ...
        la    t6, str_data              ; ...
        xcall ra, c0, t6                ; ...
        j     pi_ret                    ; ...
pi_undef:
        mv    a1, a0                    ; ...
        li    a0, m_undef               ; ...
        jalr  zero, gp, error2-R        ; ...
pi_impl:
        li    a0, TK_FUNC               ; int name()
        li    a1, 0                     ; ...
        li    a2, 1                     ; ...
        li    a3, Y_INT                 ; ...
        jalr  ra, gp, ty_new-R          ; ...
        li    t0, TF_OLD                ; ...
        sb    t0, TY_FLAGS(a0)          ; ...
        mv    a1, a0                    ; (the library's, if it has one of that name)
        mv    a0, s2                    ; ...
        la    t6, func_decl             ; ...
        xcall ra, c0, t6                ; ...
        mv    s1, a0                    ; ...
pi_have:
        lhu   a1, SY_TYPE(s1)           ; ...
        lw    a2, SY_VAL(s1)            ; ...
        lbu   t0, SY_CLASS(s1)          ; ...
        li    t1, SC_PARAM              ; a parameter named in its own parameter list: a value
        beq   t0, t1, pi_loc            ;   nobody computes (the size of an array parameter)
        li    t1, SC_AUTO               ; a local
        bne   t0, t1, pi_stat           ; ...
pi_loc:
        li    a0, VK_LOC                ; ...
        jalr  ra, gp, vpush-R           ; ...
        li    t0, X_SP                  ; from sp, or from s0
        lbu   t1, SY_FLAGS(s1)          ; ...
        andi  t2, t1, SF_S0             ; ...
        beqz  t2, pi_base               ; ...
        li    t0, X_S0                  ; ...
pi_base:
        sb    t0, V_REG(a0)             ; ...
        andi  t2, t1, SF_REF            ; a structure parameter: the word holds its address
        beqz  t2, pi_ret                ; ...
        li    t0, VK_SAVED              ; ...
        sb    t0, V_KIND(a0)            ; ...
        ld    t0, V_VAL(a0)             ; ...
        sw    t0, V_SLOT(a0)            ; ...
        sd    zero, V_VAL(a0)           ; ...
        j     pi_ret                    ; ...
pi_stat:
        li    t1, SC_ENUM               ; an enumeration constant
        bne   t0, t1, pi_obj            ; ...
        li    a0, VK_CONST              ; ...
        li    a1, Y_INT                 ; ...
        jalr  ra, gp, vpush-R           ; ...
        j     pi_ret                    ; ...
pi_obj:
        addi  t1, t0, -SC_STATIC        ; a static object or a function
        sltiu t1, t1, 2                 ; ...
        bnez  t1, pi_glob               ; ...
        li    a0, m_expect              ; (a typedef name is not a value)
        jalr  zero, gp, errtok-R        ; ...
pi_glob:
        li    a0, VK_GLOB               ; ...
        jalr  ra, gp, vpush-R           ; ...
        lbu   t0, SY_FLAGS(s1)          ; its address may not be known yet:
        lbu   t1, SY_CLASS(s1)          ;   an undefined function, an extern object
        addi  t1, t1, -SC_FUNC          ; ...
        bnez  t1, pi_ext                ; ...
        andi  t0, t0, SF_DEF            ; ...
        bnez  t0, pi_ret                ; ...
        j     pi_unk                    ; ...
pi_ext:
        andi  t0, t0, SF_EXT            ; ...
        beqz  t0, pi_ret                ; ...
pi_unk:
        sh    s1, V_SYM(a0)             ; ...
        sd    zero, V_VAL(a0)           ; ...
pi_ret:
        jalr  zero, gp, lv3-R           ; done

; str_lit(): the string literal that is the current token (and those after it)
