; =============================================================================
; term.s: templates, findall, call/N, the clause store (code units)
; =============================================================================
;
; compile turns a term into a template at v_ctop: compounds are copied cell
; by cell, and each variable is bound (on the trail, undone afterwards) to
; TVAR i, so that its later occurrences compile to the same TVAR. A clause
; is a template in the clause store; a findall answer and an exception ball
; are templates in the findall area, as records:
;   0 the next record   8 variables   16 the template's root cell   24 cells

        .data                           ; this unit's variables
        .align 8                        ; ...
v_ctop:   .dword 0                      ; where compile writes
v_cend:   .dword 0                      ; its limit
v_nvars:  .dword 0                      ; variables numbered so far

        .far                            ; code units
        .align 4096                     ; ---- unit: templates ----
u_term:

; compile(a0 = term) -> a0 = its template cell (at v_ctop)
compile:
        jalr  t6, gp, ent4-R            ; s1 term, s2 block, s3 arguments left, s4 cell
        li    t0, SPMIN                 ; deep enough?
        bltu  sp, t0, cp_deep           ; ...
        jalr  ra, gp, deref-R           ; ...
        mv    s1, a0                    ; ...
        andi  t0, s1, 7                 ; ...
        beqz  t0, cp_var                ; a variable not seen yet
        li    t1, T_STR                 ; ...
        beq   t0, t1, cp_str            ; ...
        mv    a0, s1                    ; atomic, or a variable seen already (TVAR)
        jalr  zero, gp, lv4-R           ; ...
cp_var:
        ld    t0, v_nvars(zero)         ; TVAR i
        addi  t1, t0, 1                 ; ...
        sd    t1, v_nvars(zero)         ; ...
        slli  s4, t0, 3                 ; ...
        ori   s4, s4, T_TVAR            ; ...
        mv    a0, s1                    ; bound to it for now
        mv    a1, s4                    ; ...
        jalr  ra, gp, bindt-R           ; ...
        mv    a0, s4                    ; ...
        jalr  zero, gp, lv4-R           ; ...
cp_str:
        call  cp_block                  ; s2 = a block for s1's functor and arguments
        addi  s4, s2, T_STR             ; the result
cp_args:
        addi  s1, s1, 8                 ; next argument
        addi  s2, s2, 8                 ; ...
        addi  s3, s3, -1                ; the last?
        beqz  s3, cp_last               ; ...
        mv    a0, s1                    ; ...
        jalr  ra, gp, mrd-R             ; ...
        la    t6, compile               ; ...
        xcall ra, c0, t6                ; ...
        mv    a1, a0                    ; ...
        mv    a0, s2                    ; ...
        jalr  ra, gp, mwr-R             ; ...
        j     cp_args                   ; ...
cp_last:
        mv    a0, s1                    ; ...
        jalr  ra, gp, mrd-R             ; ...
        jalr  ra, gp, deref-R           ; ...
        andi  t0, a0, 7                 ; a compound: go on into it
        li    t1, T_STR                 ; ...
        bne   t0, t1, cp_lone           ; ...
        mv    s1, a0                    ; ...
        sd    s2, v_tmp(zero)           ; (the cell to link it into)
        call  cp_block                  ; ...
        ld    a0, v_tmp(zero)           ; ...
        addi  a1, s2, T_STR             ; ...
        jalr  ra, gp, mwr-R             ; ...
        j     cp_args                   ; ...
cp_lone:
        la    t6, compile               ; ...
        xcall ra, c0, t6                ; ...
        mv    a1, a0                    ; ...
        mv    a0, s2                    ; ...
        jalr  ra, gp, mwr-R             ; ...
        mv    a0, s4                    ; ...
        jalr  zero, gp, lv4-R           ; ...
cp_deep:
        jalr  zero, gp, err_depth-R     ; ...

; cp_block (leaf): s1 = a compound -> s2 = a new block at v_ctop with its
; functor written, s3 = its arity, s1 = its functor cell's offset
cp_block:
        addi  sp, sp, -8                ; ...
        sd    ra, 0(sp)                 ; ...
        addi  s1, s1, -T_STR            ; ...
        mv    a0, s1                    ; the functor
        jalr  ra, gp, mrd-R             ; ...
        mv    s3, a0                    ; ...
        srli  t0, a0, 3                 ; cells
        andi  t0, t0, 0x1FFF            ; ...
        addi  t0, t0, 1                 ; ...
        slli  t0, t0, 3                 ; ...
        ld    s2, v_ctop(zero)          ; ...
        add   t1, s2, t0                ; ...
        ld    t2, v_cend(zero)          ; room?
        bgtu  t1, t2, cb_full           ; ...
        sd    t1, v_ctop(zero)          ; ...
        mv    a0, s2                    ; ...
        mv    a1, s3                    ; ...
        jalr  ra, gp, mwr-R             ; ...
        srli  s3, s3, 3                 ; ...
        andi  s3, s3, 0x1FFF            ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...
cb_full:
        li    t0, A_FAEND               ; which area?
        beq   t2, t0, cb_fa             ; ...
        li    a0, at_clauses + T_ATM    ; resource_error(clauses)
        jalr  zero, gp, err_res-R       ; ...
cb_fa:
        li    a0, at_findall + T_ATM ; resource_error(findall)
        jalr  zero, gp, err_res-R       ; ...

; fa_add(a0 = term): a record of it at v_fatop
fa_add:
        jalr  t6, gp, ent3-R            ; s1 record, s2 trail top, s3 term
        mv    s3, a0                    ; ...
        ld    s1, v_fatop(zero)         ; ...
        ld    s2, v_TR(zero)            ; ...
        addi  t0, s1, 24                ; the cells follow the header
        sd    t0, v_ctop(zero)          ; ...
        li    t0, A_FAEND               ; ...
        sd    t0, v_cend(zero)          ; ...
        sd    zero, v_nvars(zero)       ; ...
        li    t0, A_FAEND - 24          ; room for the header?
        bgeu  s1, t0, cb_fa             ; ...
        mv    a0, s3                    ; ...
        la    t6, compile               ; ...
        xcall ra, c0, t6                ; ...
        addi  a1, s1, 16                ; the root
        xor   a0, a0, a1                ; (swap)
        xor   a1, a0, a1                ; ...
        xor   a0, a0, a1                ; ...
        jalr  ra, gp, mwr-R             ; ...
        addi  a0, s1, 8                 ; the variables
        ld    a1, v_nvars(zero)         ; ...
        jalr  ra, gp, mwr-R             ; ...
        mv    a0, s1                    ; the next record
        ld    a1, v_ctop(zero)          ; ...
        jalr  ra, gp, mwr-R             ; ...
        ld    t0, v_ctop(zero)          ; ...
        sd    t0, v_fatop(zero)         ; ...
        mv    a0, s2                    ; the variables are free again
        jalr  ra, gp, untrail-R         ; ...
        jalr  zero, gp, lv3-R           ; ...

; fa_build(a0 = record) -> a0 = a fresh copy of its term on the heap
fa_build:
        jalr  t6, gp, ent1-R            ; s1 record
        mv    s1, a0                    ; ...
        addi  a0, s1, 8                 ; its variables
        jalr  ra, gp, mrd-R             ; ...
        jalr  ra, gp, newframe-R        ; ...
        addi  a0, s1, 16                ; its root
        jalr  ra, gp, mrd-R             ; ...
        jalr  ra, gp, build-R           ; ...
        jalr  zero, gp, lv1-R           ; ...

; fa_collect(a0 = the first record) -> a0 = the list of the records' terms
; from there to v_fatop; v_fatop goes back to the first
fa_collect:
        jalr  t6, gp, ent4-R            ; s1 record, s2 the list, s3 its last pair, s4 term
        mv    s1, a0                    ; ...
        li    s2, at_nil + T_ATM        ; ...
        li    s3, 0                     ; ...
fc_next:
        ld    t0, v_fatop(zero)         ; any left?
        bgeu  s1, t0, fc_done           ; ...
        mv    a0, s1                    ; ...
        la    t6, fa_build              ; ...
        xcall ra, c0, t6                ; ...
        mv    a1, a0                    ; [Term | []]
        li    a0, ((at_dot >> 3) << 16) | (2 << 3) | T_FUN ; ...
        li    a2, at_nil + T_ATM        ; ...
        jalr  ra, gp, mkstr-R           ; ...
        mv    s4, a0                    ; ...
        bnez  s3, fc_link               ; ...
        mv    s2, s4                    ; the first pair is the list
        j     fc_linked                 ; ...
fc_link:
        addi  a0, s3, 16 - T_STR        ; the last pair's tail
        mv    a1, s4                    ; ...
        jalr  ra, gp, mwr-R             ; ...
fc_linked:
        mv    s3, s4                    ; ...
        mv    a0, s1                    ; the next record
        jalr  ra, gp, mrd-R             ; ...
        mv    s1, a0                    ; ...
        j     fc_next                   ; ...
fc_done:
        mv    a0, s2                    ; ...
        jalr  zero, gp, lv4-R           ; (fa_collect's caller resets v_fatop below)
u_term_end:

        .align 4096                     ; ---- unit: clauses ----
u_clause:

; fa_collect's twin for the solve loop: the list, and v_fatop back to the start
; (kept apart so that the reset happens after every record was read)
fa_collect2:
        jalr  t6, gp, ent1-R            ; s1 start
        mv    s1, a0                    ; ...
        la    t6, fa_collect            ; ...
        xcall ra, c0, t6                ; ...
        sd    s1, v_fatop(zero)         ; ...
        jalr  zero, gp, lv1-R           ; ...

; callgoal(a0 = call(G, A1, ..., An)) -> a0 = G with A1..An added
callgoal:
        jalr  t6, gp, ent6-R            ; s1 call/N, s2 G, s3 n - 1 extra, s4 G's arity, s5 new block, s6 i
        mv    s1, a0                    ; ...
        li    a1, 1                     ; G
        jalr  ra, gp, garg-R            ; ...
        mv    s2, a0                    ; ...
        andi  t0, s1, 7                 ; call/1: G itself
        li    t1, T_STR                 ; ...
        bne   t0, t1, cg_inst           ; (cannot happen: call/0 is no builtin)
        addi  a0, s1, -T_STR            ; n
        jalr  ra, gp, mrd-R             ; ...
        srli  s3, a0, 3                 ; ...
        andi  s3, s3, 0x1FFF            ; ...
        addi  s3, s3, -1                ; extra arguments
        andi  t0, s2, 7                 ; G
        beqz  t0, cg_inst               ; a variable
        beqz  s3, cg_check              ; none to add: G as it is
        li    t1, T_ATM                 ; an atom: name/extra
        beq   t0, t1, cg_atom           ; ...
        li    t1, T_STR                 ; a compound: more arguments
        bne   t0, t1, cg_type           ; ...
        addi  a0, s2, -T_STR            ; ...
        jalr  ra, gp, mrd-R             ; ...
        srli  s4, a0, 3                 ; ...
        andi  s4, s4, 0x1FFF            ; ...
        srli  t0, a0, 16                ; the name
        j     cg_make                   ; ...
cg_atom:
        li    s4, 0                     ; ...
        srli  t0, s2, 3                 ; ...
cg_make:
        add   t1, s4, s3                ; the new arity
        li    t2, MAXAR                 ; ...
        bgtu  t1, t2, cg_big            ; ...
        slli  t0, t0, 16                ; the new functor
        slli  t2, t1, 3                 ; ...
        or    t0, t0, t2                ; ...
        ori   t0, t0, T_FUN             ; ...
        sd    t0, v_tmp(zero)           ; ...
        addi  a0, t1, 1                 ; a block
        slli  a0, a0, 3                 ; ...
        jalr  ra, gp, halloc-R          ; ...
        mv    s5, a0                    ; ...
        ld    a1, v_tmp(zero)           ; ...
        jalr  ra, gp, mwr-R             ; ...
        li    s6, 1                     ; G's own arguments
cg_own:
        bgtu  s6, s4, cg_extra0         ; ...
        slli  a0, s6, 3                 ; ...
        add   a0, a0, s2                ; ...
        addi  a0, a0, -T_STR            ; ...
        jalr  ra, gp, mrd-R             ; ...
        mv    a1, a0                    ; ...
        slli  a0, s6, 3                 ; ...
        add   a0, a0, s5                ; ...
        jalr  ra, gp, mwr-R             ; ...
        addi  s6, s6, 1                 ; ...
        j     cg_own                    ; ...
cg_extra0:
        li    s2, 2                     ; then call/N's from the second on
cg_extra:                               ; (s6 continues the block's index)
        addi  t0, s3, 1                 ; done?
        bgtu  s2, t0, cg_fin           ; ...
        slli  a0, s2, 3                 ; ...
        add   a0, a0, s1                ; ...
        addi  a0, a0, -T_STR            ; ...
        jalr  ra, gp, mrd-R             ; ...
        mv    a1, a0                    ; ...
        slli  a0, s6, 3                 ; ...
        add   a0, a0, s5                ; ...
        jalr  ra, gp, mwr-R             ; ...
        addi  s6, s6, 1                 ; ...
        addi  s2, s2, 1                 ; ...
        j     cg_extra                  ; ...
cg_fin:
        addi  a0, s5, T_STR             ; ...
        jalr  zero, gp, lv6-R           ; ...
cg_check:
        li    t1, T_ATM                 ; G must be callable
        beq   t0, t1, cg_ok             ; ...
        li    t1, T_STR                 ; ...
        bne   t0, t1, cg_type           ; ...
cg_ok:
        mv    a0, s2                    ; ...
        jalr  zero, gp, lv6-R           ; ...
cg_inst:
        jalr  zero, gp, err_inst-R      ; ...
cg_type:
        li    a0, at_callable + T_ATM   ; ...
        mv    a1, s2                    ; ...
        jalr  zero, gp, err_type-R      ; ...
cg_big:
        li    a0, at_max_arity + T_ATM  ; ...
        jalr  zero, gp, err_repr-R      ; ...

; add_clause(a0 = clause term, a1 = 0 assertz / 1 asserta, a2 = 1 if
; consulting): compile it into the clause store and link it in
add_clause:
        jalr  t6, gp, ent6-R            ; s1 head, s2 body, s3 pred, s4 clause, s5 mode, s6 trail top
        mv    s5, a1                    ; ...
        slli  a2, a2, 1                 ; (consulting: bit 1)
        or    s5, s5, a2                ; ...
        jalr  ra, gp, deref-R           ; Head :- Body, or Head
        mv    s1, a0                    ; ...
        li    s2, at_true + T_ATM       ; ...
        andi  t0, s1, 7                 ; ...
        li    t1, T_STR                 ; ...
        bne   t0, t1, ac_head           ; ...
        addi  a0, s1, -T_STR            ; ...
        jalr  ra, gp, mrd-R             ; ...
        li    t0, ((at_neck >> 3) << 16) | (2 << 3) | T_FUN ; :-/2
        bne   a0, t0, ac_head           ; ...
        mv    a0, s1                    ; ...
        li    a1, 2                     ; ...
        jalr  ra, gp, garg-R            ; ...
        mv    s2, a0                    ; ...
        mv    a0, s1                    ; ...
        li    a1, 1                     ; ...
        jalr  ra, gp, garg-R            ; ...
        mv    s1, a0                    ; ...
ac_head:
        andi  t0, s1, 7                 ; the head: callable
        beqz  t0, cg_inst               ; ...
        li    t1, T_ATM                 ; ...
        beq   t0, t1, ac_atom           ; ...
        li    t1, T_STR                 ; ...
        bne   t0, t1, ac_type           ; ...
        addi  a0, s1, -T_STR            ; ...
        jalr  ra, gp, mrd-R             ; ...
        j     ac_fun                    ; ...
ac_atom:
        srli  a0, s1, 3                 ; name/0
        slli  a0, a0, 16                ; ...
        ori   a0, a0, T_FUN             ; ...
ac_fun:
        mv    s6, a0                    ; (the functor, for a moment)
        andi  t0, s2, 7                 ; the body: not a number
        li    t1, T_INT                 ; ...
        beq   t0, t1, ac_btype          ; ...
        la    t6, pred_get              ; the predicate
        xcall ra, c0, t6                ; ...
        mv    s3, a0                    ; ...
        addi  a0, s3, PR_BI             ; not a builtin
        jalr  ra, gp, mrd-R             ; ...
        bnez  a0, ac_perm               ; ...
        andi  t0, s5, 4                 ; assert: a consulted static predicate refuses,
        beqz  t0, ac_cons               ;   anything else becomes dynamic
        addi  a0, s3, PR_FLAGS          ; ...
        jalr  ra, gp, mrd-R             ; ...
        andi  t0, a0, PF_DYN            ; ...
        bnez  t0, ac_compile            ; ...
        addi  a0, s3, PR_CONS           ; ...
        jalr  ra, gp, mrd-R             ; ...
        bnez  a0, ac_perm               ; ...
        addi  a0, s3, PR_FLAGS          ; ...
        jalr  ra, gp, mrd-R             ; ...
        ori   a1, a0, PF_DYN            ; ...
        addi  a0, s3, PR_FLAGS          ; ...
        jalr  ra, gp, mwr-R             ; ...
        j     ac_compile                ; ...
ac_cons:
        andi  t0, s5, 2                 ; consulting: the first clause of this consult replaces
        beqz  t0, ac_compile            ; ...
        addi  a0, s3, PR_CONS           ; ...
        jalr  ra, gp, mrd-R             ; ...
        ld    t0, v_cons(zero)          ; ...
        beq   a0, t0, ac_compile        ; (seen already in this consult)
        addi  a0, s3, PR_CONS           ; ...
        mv    a1, t0                    ; ...
        jalr  ra, gp, mwr-R             ; ...
        addi  a0, s3, PR_FLAGS          ; a dynamic predicate keeps its clauses
        jalr  ra, gp, mrd-R             ; ...
        andi  a0, a0, PF_DYN            ; ...
        bnez  a0, ac_compile            ; ...
        mv    a0, s3                    ; drop the old clauses
        la    t6, pred_wipe             ; ...
        xcall ra, c0, t6                ; ...
ac_compile:
        ld    s6, v_TR(zero)            ; ...
        li    a0, CLSZ                  ; the record ...
        la    t6, db_alloc              ; ...
        xcall ra, c0, t6                ; ...
        mv    s4, a0                    ; ...
        ld    t0, v_dbtop(zero)         ; ... and its template after it
        sd    t0, v_ctop(zero)          ; ...
        li    t0, A_DBEND               ; ...
        sd    t0, v_cend(zero)          ; ...
        sd    zero, v_nvars(zero)       ; ...
        mv    a0, s1                    ; the head
        la    t6, compile               ; ...
        xcall ra, c0, t6                ; ...
        mv    s1, a0                    ; ...
        mv    a0, s2                    ; the body
        la    t6, compile               ; ...
        xcall ra, c0, t6                ; ...
        mv    s2, a0                    ; ...
        ld    t0, v_ctop(zero)          ; the store grew by the template
        sd    t0, v_dbtop(zero)         ; ...
        mv    a0, s6                    ; the variables are free again
        jalr  ra, gp, untrail-R         ; ...
        addi  a0, s4, CL_HEAD           ; the record
        mv    a1, s1                    ; ...
        jalr  ra, gp, mwr-R             ; ...
        addi  a0, s4, CL_BODY           ; ...
        mv    a1, s2                    ; ...
        jalr  ra, gp, mwr-R             ; ...
        addi  a0, s4, CL_NVARS          ; ...
        ld    a1, v_nvars(zero)         ; ...
        jalr  ra, gp, mwr-R             ; ...
        addi  a0, s4, CL_PRED           ; ...
        mv    a1, s3                    ; ...
        jalr  ra, gp, mwr-R             ; ...
        addi  a0, s4, CL_DIED           ; ...
        li    a1, ALIVE                 ; ...
        jalr  ra, gp, mwr-R             ; ...
        ld    a1, v_gen(zero)           ; born in a new generation
        addi  a1, a1, 1                 ; ...
        sd    a1, v_gen(zero)           ; ...
        addi  a0, s4, CL_BORN           ; ...
        jalr  ra, gp, mwr-R             ; ...
        li    a0, 0                     ; the key: the head's first argument
        andi  t0, s1, 7                 ; ...
        li    t1, T_STR                 ; ...
        bne   t0, t1, ac_key            ; ...
        addi  a0, s1, 8 - T_STR         ; ...
        jalr  ra, gp, mrd-R             ; ...
        andi  t0, a0, 7                 ; a template variable: none
        li    t1, T_TVAR                ; ...
        bne   t0, t1, ac_k2             ; ...
        li    a0, 0                     ; ...
        j     ac_key                    ; ...
ac_k2:
        li    t1, T_STR                 ; a compound: its functor
        bne   t0, t1, ac_key            ; ...
        addi  a0, a0, -T_STR            ; ...
        jalr  ra, gp, mrd-R             ; ...
ac_key:
        mv    a1, a0                    ; ...
        addi  a0, s4, CL_KEY            ; ...
        jalr  ra, gp, mwr-R             ; ...
        andi  t0, s5, 1                 ; asserta?
        bnez  t0, ac_front              ; ...
        mv    a0, s4                    ; assertz: last
        li    a1, 0                     ; ...
        jalr  ra, gp, mwr-R             ; ...
        addi  a0, s3, PR_LAST           ; ...
        jalr  ra, gp, mrd-R             ; ...
        beqz  a0, ac_only               ; the first
        mv    a1, s4                    ; after the last
        jalr  ra, gp, mwr-R             ; (CL_NEXT is word 0)
        j     ac_last                   ; ...
ac_front:
        addi  a0, s3, PR_FIRST          ; asserta: first
        jalr  ra, gp, mrd-R             ; ...
        mv    a1, a0                    ; ...
        mv    a0, s4                    ; ...
        jalr  ra, gp, mwr-R             ; ...
        addi  a0, s3, PR_FIRST          ; ...
        mv    a1, s4                    ; ...
        jalr  ra, gp, mwr-R             ; ...
        addi  a0, s3, PR_LAST           ; the last too, if it is alone
        jalr  ra, gp, mrd-R             ; ...
        bnez  a0, ac_done               ; ...
        j     ac_last                   ; ...
ac_only:
        addi  a0, s3, PR_FIRST          ; ...
        mv    a1, s4                    ; ...
        jalr  ra, gp, mwr-R             ; ...
ac_last:
        addi  a0, s3, PR_LAST           ; ...
        mv    a1, s4                    ; ...
        jalr  ra, gp, mwr-R             ; ...
ac_done:
        mv    a0, s4                    ; the clause
        jalr  zero, gp, lv6-R           ; ...
ac_type:
        li    a0, at_callable + T_ATM   ; ...
        mv    a1, s1                    ; ...
        jalr  zero, gp, err_type-R      ; ...
ac_btype:
        li    a0, at_callable + T_ATM   ; ...
        mv    a1, s2                    ; ...
        jalr  zero, gp, err_type-R      ; ...
ac_perm:
        mv    a0, s6                    ; permission_error(modify, static_procedure, N/A)
        la    t6, mk_pi                 ; ...
        xcall ra, c0, t6                ; ...
        mv    a2, a0                    ; ...
        li    a0, at_modify + T_ATM     ; ...
        li    a1, at_static_proc + T_ATM ; ...
        jalr  zero, gp, err_perm-R      ; ...

; pred_wipe(a0 = predicate): its clauses are retracted (the running calls
; that see them still do)
pred_wipe:
        jalr  t6, gp, ent2-R            ; s1 pred, s2 clause
        mv    s1, a0                    ; ...
        addi  a0, s1, PR_FIRST          ; ...
        jalr  ra, gp, mrd-R             ; ...
        mv    s2, a0                    ; ...
        ld    t0, v_gen(zero)           ; a new generation
        addi  t0, t0, 1                 ; ...
        sd    t0, v_gen(zero)           ; ...
pw_loop:
        beqz  s2, pw_done               ; ...
        addi  a0, s2, CL_DIED           ; ...
        ld    a1, v_gen(zero)           ; ...
        jalr  ra, gp, mwr-R             ; ...
        mv    a0, s2                    ; ...
        jalr  ra, gp, mrd-R             ; ...
        mv    s2, a0                    ; ...
        j     pw_loop                   ; ...
pw_done:
        addi  a0, s1, PR_FIRST          ; none now
        li    a1, 0                     ; ...
        jalr  ra, gp, mwr-R             ; ...
        addi  a0, s1, PR_LAST           ; ...
        li    a1, 0                     ; ...
        jalr  ra, gp, mwr-R             ; ...
        jalr  zero, gp, lv2-R           ; ...

