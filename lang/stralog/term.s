        srli  t1, a0, 3                 ; Arity
        andi  t1, t1, 0x1FFF            ; ...
        slli  t1, t1, 3                 ; ...
        ori   a2, t1, T_INT             ; ...
        li    a0, ((at_slash >> 3) << 16) | (2 << 3) | T_FUN ; ...
        jalr  ra, gp, mkstr-R           ; ...
        jalr  zero, gp, lv0-R           ; ...
