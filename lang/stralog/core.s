; =============================================================================
; core.s: cells in far memory, the windows, the far cache, unification (resident)
; =============================================================================
;
; Every cell is an arena offset. mrd/mwr reach one: inside the heap window
; it is a load or a store into the window's ring; anywhere else it goes
; through the far cache. wrd/wwr do the same for the trail and choicepoint
; windows. Nothing here calls a code unit: units call all of it.
;
; A window covers [WB, WB + size) of its stack and keeps WB a multiple of 64,
; so that no cache line ever straddles it. The cache never holds a line at
; or above a window's WB (win_slide writes such lines back and drops them).
;
; Clobbers, unless a routine says otherwise: mrd t0..t2 (a0 = the cell);
; mwr t0..t2 and a0; the rest t0..t6 and a0..a5.

; ---- the far cache ---------------------------------------------------------------------
; fc_init(): tell the tag table hardware where things are, mark every line empty
fc_init:
        li    t0, fc_tags               ; the tag table
        csrw  ttag, t0                  ; ...
        li    t0, fc_lines              ; the lines
        csrw  tdata, t0                 ; ...
        li    t0, FC_GEOM               ; geometry
        csrw  tgeom, t0                 ; ...
        li    t0, fc_tags               ; clear tags and dirty bytes (0: no line)
        li    t1, fc_dirty + FC_NL      ; ...
fi_clr:
        sd    zero, 0(t0)               ; ...
        addi  t0, t0, 8                 ; ...
        bltu  t0, t1, fi_clr            ; ...
        ret                             ; done

; fc_fill(a0 = arena offset, a1 = 1 if it will be written) -> a0 = the byte's
; D-LS address. A miss: write the victim line back if dirty, fetch the line.
; Clobbers t0..t2 only.
fc_fill:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; the offset
        sd    a1, 16(sp)                ; dirty?
        sd    t3, 24(sp)                ; kept for the caller
        sd    a2, 32(sp)                ; ...
        ltag  t0, a0                    ; the victim (bit 63: a miss)
        slli  t0, t0, 1                 ; its D-LS address
        srli  t0, t0, 1                 ; ...
        li    t1, fc_lines              ; t3 = its index
        sub   t3, t0, t1                ; ...
        srli  t3, t3, FC_LSH            ; ...
        lbu   t1, fc_dirty(t3)          ; dirty?
        beqz  t1, ff_clean              ; no
        srli  t1, t3, 1                 ; tag entry: set * span + way * 8
        li    t2, FC_SPAN               ; ...
        mul   t1, t1, t2                ; ...
        andi  t2, t3, 1                 ; ...
        slli  t2, t2, 3                 ; ...
        add   t1, t1, t2                ; ...
        ld    t1, fc_tags(t1)           ; the tag: line << 1 | 1
        srli  t1, t1, 1                 ; its far address
        slli  t1, t1, FC_LSH            ; ...
        li    a2, FC_LINE               ; one line
        tput  tg4, t0, c0, t1, a2       ; write it back
        sb    zero, fc_dirty(t3)        ; ...
        ld    t1, v_fcwb(zero)          ; count it
        addi  t1, t1, 1                 ; ...
        sd    t1, v_fcwb(zero)          ; ...
ff_clean:
        ld    a0, 8(sp)                 ; the line to fetch
        srli  t1, a0, FC_LSH            ; ...
        slli  t1, t1, FC_LSH            ; ...
        li    a2, FC_LINE               ; ...
        tget  tg5, t0, c0, t1, a2       ; far -> D-LS (loads wait for it)
        linst a0                        ; record it in the tag table
        ld    a1, 16(sp)                ; dirty if it will be written
        sb    a1, fc_dirty(t3)          ; ...
        ld    t1, v_fcmiss(zero)        ; count the miss
        addi  t1, t1, 1                 ; ...
        sd    t1, v_fcmiss(zero)        ; ...
        andi  a0, a0, FC_LINE - 1       ; the byte in the line
        add   a0, a0, t0                ; ...
        ld    a2, 32(sp)                ; ...
        ld    t3, 24(sp)                ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 40                ; ...
        ret                             ; done

; fc_flush(a0 = lo, a1 = hi): write back the dirty lines in [lo, hi) and drop
; every line there. Clobbers t0..t6, a2.
fc_flush:
        li    t3, 0                     ; t3 = line index
ffl_loop:
        srli  t1, t3, 1                 ; its tag entry
        li    t2, FC_SPAN               ; ...
        mul   t1, t1, t2                ; ...
        andi  t2, t3, 1                 ; ...
        slli  t2, t2, 3                 ; ...
        add   t4, t1, t2                ; t4 = entry offset
        ld    t1, fc_tags(t4)           ; the tag
        andi  t2, t1, 1                 ; a line?
        beqz  t2, ffl_next              ; no
        srli  t1, t1, 1                 ; its far address
        slli  t1, t1, FC_LSH            ; ...
        bltu  t1, a0, ffl_next          ; below the range
        bgeu  t1, a1, ffl_next          ; above it
        lbu   t2, fc_dirty(t3)          ; dirty?
        beqz  t2, ffl_drop              ; no
        slli  t5, t3, FC_LSH            ; its D-LS address
        li    t6, fc_lines              ; ...
        add   t5, t5, t6                ; ...
        li    a2, FC_LINE               ; ...
        tput  tg4, t5, c0, t1, a2       ; write it back
        sb    zero, fc_dirty(t3)        ; ...
        ld    t2, v_fcwb(zero)          ; count it
        addi  t2, t2, 1                 ; ...
        sd    t2, v_fcwb(zero)          ; ...
ffl_drop:
        sd    zero, fc_tags(t4)         ; no line there now
ffl_next:
        addi  t3, t3, 1                 ; next line
        li    t2, FC_NL                 ; ...
        bltu  t3, t2, ffl_loop          ; ...
        ret                             ; done

; crd(a0 = offset) -> a0: through the far cache only. Clobbers t0..t2.
crd:
        ltag  t0, a0                    ; there?
        bltz  t0, crd_miss              ; no
        ld    a0, 0(t0)                 ; yes
        ret                             ; ...
crd_miss:
        addi  sp, sp, -16               ; ...
        sd    ra, 0(sp)                 ; ...
        sd    a1, 8(sp)                 ; ...
        li    a1, 0                     ; reading
        call  fc_fill                   ; ...
        ld    a0, 0(a0)                 ; ...
        ld    a1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; done

; cwr(a0 = offset, a1 = cell): through the far cache only. Clobbers t0..t2, a0.
cwr:
        ltag  t0, a0                    ; there?
        bltz  t0, cwr_miss              ; no
        li    t1, fc_lines              ; dirty now
        sub   t1, t0, t1                ; ...
        srli  t1, t1, FC_LSH            ; ...
        li    t2, 1                     ; ...
        sb    t2, fc_dirty(t1)          ; ...
        sd    a1, 0(t0)                 ; ...
        ret                             ; ...
cwr_miss:
        addi  sp, sp, -16               ; ...
        sd    ra, 0(sp)                 ; ...
        sd    a1, 8(sp)                 ; ...
        li    a1, 1                     ; writing
        call  fc_fill                   ; ...
        ld    a1, 8(sp)                 ; ...
        sd    a1, 0(a0)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; done

; ---- cells ------------------------------------------------------------------------------
; mrd(a0 = offset) -> a0 = the cell (heap window, else the far cache)
mrd:
        ld    t0, wh+W_BASE(zero)       ; in the heap window?
        sub   t1, a0, t0                ; ...
        li    t2, HWSZ                  ; ...
        bgeu  t1, t2, crd               ; no: the cache
        andi  t1, a0, HWSZ - 1          ; its ring slot
        ld    a0, hring(t1)             ; ...
        ret                             ; done

; mwr(a0 = offset, a1 = cell)
mwr:
        ld    t0, wh+W_BASE(zero)       ; in the heap window?
        sub   t1, a0, t0                ; ...
        li    t2, HWSZ                  ; ...
        bgeu  t1, t2, cwr               ; no: the cache
        andi  t1, a0, HWSZ - 1          ; its ring slot
        sd    a1, hring(t1)             ; ...
        ret                             ; done

; mrdb(a0 = offset) -> a0 = the byte there
mrdb:
        addi  sp, sp, -16               ; ...
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        srli  a0, a0, 3                 ; its word
        slli  a0, a0, 3                 ; ...
        call  mrd                       ; ...
        ld    t0, 8(sp)                 ; the byte's place in it
        andi  t0, t0, 7                 ; ...
        slli  t0, t0, 3                 ; ...
        srl   a0, a0, t0                ; ...
        andi  a0, a0, 0xFF              ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; done

; wrd(a0 = descriptor, a1 = offset) -> a0: a trail or choicepoint cell
wrd:
        ld    t0, W_BASE(a0)            ; in the window?
        sub   t1, a1, t0                ; ...
        ld    t2, W_MASK(a0)            ; ...
        bgtu  t1, t2, wrd_far           ; no
        and   t1, a1, t2                ; its ring slot
        ld    t2, W_RING(a0)            ; ...
        add   t1, t1, t2                ; ...
        ld    a0, 0(t1)                 ; ...
        ret                             ; done
wrd_far:
        mv    a0, a1                    ; the cache
        j     crd                       ; ...

; wwr(a0 = descriptor, a1 = offset, a2 = cell)
wwr:
        ld    t0, W_BASE(a0)            ; in the window?
        sub   t1, a1, t0                ; ...
        ld    t2, W_MASK(a0)            ; ...
        bgtu  t1, t2, wwr_far           ; no
        and   t1, a1, t2                ; its ring slot
        ld    t2, W_RING(a0)            ; ...
        add   t1, t1, t2                ; ...
        sd    a2, 0(t1)                 ; ...
        ret                             ; done
wwr_far:
        mv    a0, a1                    ; the cache
        mv    a1, a2                    ; ...
        j     cwr                       ; ...

; ---- windows ----------------------------------------------------------------------------
; win_xfer(a0 = descriptor, a1 = D-LS address, a2 = arena offset, a3 = bytes,
; a4 = 0 put / 1 get): one transfer on the window's own tag (tg1..tg3)
win_xfer:
        ld    t0, W_ID(a0)              ; which window
        ld    t1, W_BYTES(a0)           ; count the bytes
        add   t1, t1, a3                ; ...
        sd    t1, W_BYTES(a0)           ; ...
        bnez  a4, wx_get                ; a get
        beqz  t0, wx_p1                 ; heap
        li    t1, 1                     ; trail?
        beq   t0, t1, wx_p2             ; ...
        tput  tg3, a1, c0, a2, a3       ; choicepoints: D-LS -> arena
        ret                             ; ...
wx_p1:
        tput  tg1, a1, c0, a2, a3       ; heap: D-LS -> arena
        ret                             ; ...
wx_p2:
        tput  tg2, a1, c0, a2, a3       ; trail: D-LS -> arena
        ret                             ; ...
wx_get:
        beqz  t0, wx_g1                 ; heap
        li    t1, 1                     ; trail?
        beq   t0, t1, wx_g2             ; ...
        tget  tg3, a1, c0, a2, a3       ; choicepoints: arena -> D-LS
        ret                             ; ...
wx_g1:
        tget  tg1, a1, c0, a2, a3       ; heap: arena -> D-LS
        ret                             ; ...
wx_g2:
        tget  tg2, a1, c0, a2, a3       ; trail: arena -> D-LS
        ret                             ; ...

; win_fit(a0 = descriptor, a1 = top T, a2 = bytes n): make [T, T + n) lie in
; the window. Below it: slide down. Past its end: spill halves. Keeps a0..a2.
win_fit:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; descriptor
        sd    a1, 16(sp)                ; T
        sd    a2, 24(sp)                ; n
        ld    t0, W_BASE(a0)            ; T below the window?
        bgeu  a1, t0, wf_up             ; no
        ; ---- slide down: the window starts at T's line; the lines between it
        ;      and the old base leave the cache; T's line, partly live, is read
        srli  t1, a1, FC_LSH            ; the new base
        slli  t1, t1, FC_LSH            ; ...
        sd    t1, 32(sp)                ; ...
        mv    a0, t1                    ; the cache keeps no line at or above it
        mv    a1, t0                    ; (above the old base it had none)
        call  fc_flush                  ; ...
        ld    a0, 8(sp)                 ; ...
        ld    t1, 32(sp)                ; ...
        sd    t1, W_BASE(a0)            ; ...
        ld    t2, W_SLIDE(a0)           ; count it
        addi  t2, t2, 1                 ; ...
        sd    t2, W_SLIDE(a0)           ; ...
        ld    t2, 16(sp)                ; T
        beq   t2, t1, wf_up             ; T on a line boundary: nothing live to read
        ld    t3, W_MASK(a0)            ; the line's ring slot
        and   a1, t1, t3                ; ...
        ld    t3, W_RING(a0)            ; ...
        add   a1, a1, t3                ; ...
        mv    a2, t1                    ; the line
        li    a3, FC_LINE               ; ...
        li    a4, 1                     ; a get
        call  win_xfer                  ; ...
wf_up:
        ld    a0, 8(sp)                 ; ...
        ld    t0, W_BASE(a0)            ; past the end?
        ld    t1, W_MASK(a0)            ; ...
        add   t1, t1, t0                ; t1 = WB + size - 1
        ld    t2, 16(sp)                ; T + n - 1
        ld    t3, 24(sp)                ; ...
        add   t2, t2, t3                ; ...
        addi  t2, t2, -1                ; ...
        bleu  t2, t1, wf_done           ; no
        ; ---- spill the lower half: [WB, WB + half), one or two pieces of the ring
        ld    t1, W_MASK(a0)            ; ring offset of WB
        and   t2, t0, t1                ; ...
        addi  t1, t1, 1                 ; size
        sub   t3, t1, t2                ; bytes to the ring's end
        ld    t4, W_HALF(a0)            ; ...
        sd    t4, 32(sp)                ; ...
        bgeu  t3, t4, wf_one            ; the half does not wrap
        sd    t3, 40(sp)                ; first piece: to the ring's end
        ld    a1, W_RING(a0)            ; ...
        add   a1, a1, t2                ; ...
        mv    a2, t0                    ; ...
        mv    a3, t3                    ; ...
        li    a4, 0                     ; a put
        call  win_xfer                  ; ...
        ld    a0, 8(sp)                 ; second piece: from the ring's start
        ld    a1, W_RING(a0)            ; ...
        ld    t0, W_BASE(a0)            ; ...
        ld    t3, 40(sp)                ; ...
        add   a2, t0, t3                ; ...
        ld    t4, 32(sp)                ; ...
        sub   a3, t4, t3                ; ...
        li    a4, 0                     ; ...
        call  win_xfer                  ; ...
        j     wf_moved                  ; ...
wf_one:
        ld    a1, W_RING(a0)            ; one piece
        add   a1, a1, t2                ; ...
        mv    a2, t0                    ; ...
        mv    a3, t4                    ; ...
        li    a4, 0                     ; ...
        call  win_xfer                  ; ...
wf_moved:
        ld    a0, 8(sp)                 ; WB moves up by half
        ld    t0, W_BASE(a0)            ; ...
        ld    t4, W_HALF(a0)            ; ...
        add   t0, t0, t4                ; ...
        sd    t0, W_BASE(a0)            ; ...
        ld    t1, W_SPILL(a0)           ; count it
        addi  t1, t1, 1                 ; ...
        sd    t1, W_SPILL(a0)           ; ...
        j     wf_up                     ; until it fits
wf_done:
        ld    a0, 8(sp)                 ; ...
        ld    a1, 16(sp)                ; ...
        ld    a2, 24(sp)                ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; done

; ---- allocation -------------------------------------------------------------------------
; halloc(a0 = bytes, at most half the heap window) -> a0 = the old heap top
halloc:
        ld    t0, v_H(zero)             ; T
        ld    t1, wh+W_BASE(zero)       ; inside the window?
        bltu  t0, t1, ha_slow           ; below it
        add   t2, t0, a0                ; T + n
        li    t3, HWSZ                  ; ...
        add   t3, t3, t1                ; ...
        bgtu  t2, t3, ha_slow           ; past it
ha_take:
        ld    t3, v_hlim(zero)          ; full?
        bgtu  t2, t3, ha_full           ; ...
        sd    t2, v_H(zero)             ; ...
        mv    a0, t0                    ; ...
        ret                             ; done
ha_slow:
        addi  sp, sp, -16               ; ...
        sd    ra, 0(sp)                 ; ...
        mv    a2, a0                    ; n
        mv    a1, t0                    ; T
        li    a0, wh                    ; ...
        call  win_fit                   ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        mv    t0, a1                    ; ...
        add   t2, a1, a2                ; ...
        j     ha_take                   ; ...
ha_full:
        ld    t3, v_heapend(zero)       ; the error term itself takes the reserve
        ld    t4, v_hlim(zero)          ; (unless it is taken already: then
        beq   t3, t4, ha_dead           ;   there is no way on)
        sd    t3, v_hlim(zero)          ; ...
        li    a0, at_memory + T_ATM     ; resource_error(memory)
        j     err_res                   ; ...
ha_dead:
        li    a0, 3                     ; ...
        call  sys_exit                  ; ...

; mkvar() -> a0 = a new unbound variable on the heap
mkvar:
        addi  sp, sp, -8                ; ...
        sd    ra, 0(sp)                 ; ...
        li    a0, 8                     ; one cell
        call  halloc                    ; ...
        mv    a1, a0                    ; it refers to itself
        mv    t3, a0                    ; ...
        call  mwr                       ; ...
        mv    a0, t3                    ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; done

; mkstr(a0 = functor cell, a1, a2, a3 = up to three arguments) -> a0 = the
; compound (as many arguments as the functor's arity says)
mkstr:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; functor
        sd    a1, 16(sp)                ; arguments
        sd    a2, 24(sp)                ; ...
        sd    a3, 32(sp)                ; ...
        srli  t0, a0, 3                 ; arity
        andi  t0, t0, 0x1FFF            ; ...
        addi  t0, t0, 1                 ; cells
        slli  a0, t0, 3                 ; ...
        sd    t0, 40(sp)                ; ...
        call  halloc                    ; ...
        mv    t3, a0                    ; t3 = its first cell
        mv    t4, a0                    ; t4 = cursor
        addi  t5, sp, 8                 ; t5 = the values: functor, arguments
        ld    t6, 40(sp)                ; t6 = cells left
mk_put:
        ld    a1, 0(t5)                 ; ...
        mv    a0, t4                    ; ...
        call  mwr                       ; ...
        addi  t4, t4, 8                 ; ...
        addi  t5, t5, 8                 ; ...
        addi  t6, t6, -1                ; ...
        bnez  t6, mk_put                ; ...
        addi  a0, t3, T_STR             ; the compound
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; done

; mkcont(a0 = goal, a1 = cut barrier (offset), a2 = next) -> a0 = '$cont'(G, CB, Next)
mkcont:
        mv    a3, a2                    ; next
        slli  a2, a1, 3                 ; the barrier as an integer
        ori   a2, a2, T_INT             ; ...
        mv    a1, a0                    ; the goal
        li    a0, ((at_dollar_cont >> 3) << 16) | (3 << 3) | T_FUN ; '$cont'/3
        j     mkstr                     ; (tail call)

; ---- variables ----------------------------------------------------------------------------
; deref(a0 = cell) -> a0: follow bound variables. Clobbers t0..t3.
deref:
        andi  t0, a0, 7                 ; a variable?
        bnez  t0, dr_ret                ; no: itself
        addi  sp, sp, -8                ; ...
        sd    ra, 0(sp)                 ; ...
dr_loop:
        mv    t3, a0                    ; the variable
        call  mrd                       ; its cell
        beq   a0, t3, dr_unb            ; refers to itself: unbound
        andi  t0, a0, 7                 ; another variable?
        beqz  t0, dr_loop               ; yes
        j     dr_out                    ; no: the value
dr_unb:
        mv    a0, t3                    ; the unbound variable
dr_out:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
dr_ret:
        ret                             ; done

; garg(a0 = compound, a1 = argument number from 1) -> a0 = the argument, dereferenced
garg:
        addi  sp, sp, -8                ; ...
        sd    ra, 0(sp)                 ; ...
        slli  a1, a1, 3                 ; its cell: offset + 8 i
        add   a0, a0, a1                ; ...
        addi  a0, a0, -T_STR            ; ...
        call  mrd                       ; ...
        call  deref                     ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; done

; bind(a0 = an unbound variable, a1 = value): trailed if older than the
; newest choicepoint
bind:
        addi  sp, sp, -16               ; ...
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        call  mwr                       ; ...
        ld    a0, 8(sp)                 ; ...
        ld    t0, v_HB(zero)            ; older than the choicepoint?
        bgeu  a0, t0, bd_ret            ; no: nothing to undo
        call  trpush                    ; yes
bd_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; done

; bindt(a0 = variable, a1 = value): bind and always trail (temporary bindings)
bindt:
        addi  sp, sp, -16               ; ...
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        call  mwr                       ; ...
        ld    a0, 8(sp)                 ; ...
        call  trpush                    ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; done

; trpush(a0 = offset of a bound cell)
trpush:
        ld    t0, v_TR(zero)            ; T
        ld    t1, wt+W_BASE(zero)       ; inside the window?
        bltu  t0, t1, tp_slow           ; ...
        addi  t2, t0, 8                 ; ...
        li    t3, TWSZ                  ; ...
        add   t3, t3, t1                ; ...
        bgtu  t2, t3, tp_slow           ; ...
tp_put:
        ld    t3, v_trailend(zero)      ; full?
        bgtu  t2, t3, tp_full           ; ...
        andi  t3, t0, TWSZ - 1          ; its slot
        sd    a0, tring(t3)             ; ...
        sd    t2, v_TR(zero)            ; ...
        ret                             ; done
tp_slow:
        addi  sp, sp, -16               ; ...
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        mv    a1, t0                    ; T
        li    a2, 8                     ; ...
        li    a0, wt                    ; ...
        call  win_fit                   ; ...
        mv    t0, a1                    ; ...
        addi  t2, a1, 8                 ; ...
        ld    a0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        j     tp_put                    ; ...
tp_full:
        li    a0, at_stack + T_ATM      ; resource_error(stack)
        j     err_res                   ; ...

; untrail(a0 = the trail top to go back to): unbind what was bound since
untrail:
        addi  sp, sp, -16               ; ...
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; s1 = the target
        mv    s1, a0                    ; ...
ut_loop:
        ld    a1, v_TR(zero)            ; anything left?
        bleu  a1, s1, ut_done           ; no
        addi  a1, a1, -8                ; the entry
        sd    a1, v_TR(zero)            ; ...
        li    a0, wt                    ; ...
        call  wrd                       ; a0 = the cell's offset
        mv    a1, a0                    ; unbound again: refers to itself
        call  mwr                       ; ...
        j     ut_loop                   ; ...
ut_done:
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; done

; ---- unification ---------------------------------------------------------------------------
; unify(a0, a1) -> a0 = 1 if they unify (the bindings made), else 0 (some may
; have been made: the caller fails and backtracking undoes them)
unify:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; s1, s2 = the two terms; then their argument cursors
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; s3 = arguments left
        sd    s4, 32(sp)                ; ...
        li    t0, SPMIN                 ; deep enough?
        bltu  sp, t0, err_depth         ; ...
un_loop:
        mv    s2, a1                    ; ...
        call  deref                     ; ...
        mv    s1, a0                    ; ...
        mv    a0, s2                    ; ...
        call  deref                     ; ...
        mv    s2, a0                    ; ...
        beq   s1, s2, un_true           ; identical
        andi  t0, s1, 7                 ; tags
        andi  t1, s2, 7                 ; ...
        beqz  t0, un_var1               ; the first is a variable
        beqz  t1, un_bind2              ; the second is
        bne   t0, t1, un_false          ; different kinds
        li    t2, T_STR                 ; atomic and not identical: no
        bne   t0, t2, un_false          ; ...
        addi  a0, s1, -T_STR            ; two compounds: the functors
        call  mrd                       ; ...
        mv    s3, a0                    ; ...
        addi  a0, s2, -T_STR            ; ...
        call  mrd                       ; ...
        bne   a0, s3, un_false          ; differ
        srli  s3, s3, 3                 ; arity
        andi  s3, s3, 0x1FFF            ; ...
        addi  s1, s1, 8 - T_STR         ; the first arguments
        addi  s2, s2, 8 - T_STR         ; ...
un_args:
        addi  s3, s3, -1                ; the last one?
        beqz  s3, un_last               ; yes: iterate, do not recurse
        mv    a0, s1                    ; ...
        call  mrd                       ; ...
        mv    s4, a0                    ; ...
        mv    a0, s2                    ; ...
        call  mrd                       ; ...
        mv    a1, a0                    ; ...
        mv    a0, s4                    ; ...
        call  unify                     ; ...
        beqz  a0, un_false              ; ...
        addi  s1, s1, 8                 ; next
        addi  s2, s2, 8                 ; ...
        j     un_args                   ; ...
un_last:
        mv    a0, s1                    ; ...
        call  mrd                       ; ...
        mv    s4, a0                    ; ...
        mv    a0, s2                    ; ...
        call  mrd                       ; ...
        mv    a1, a0                    ; ...
        mv    a0, s4                    ; ...
        j     un_loop                   ; ...
un_var1:
        bnez  t1, un_bind1              ; the second is not a variable
        bltu  s1, s2, un_bind2          ; both: the younger (higher) one is bound
un_bind1:
        mv    a0, s1                    ; s1 := s2
        mv    a1, s2                    ; ...
        call  bind                      ; ...
        j     un_true                   ; ...
un_bind2:
        mv    a0, s2                    ; s2 := s1
        mv    a1, s1                    ; ...
        call  bind                      ; ...
un_true:
        li    a0, 1                     ; ...
        j     un_ret                    ; ...
un_false:
        li    a0, 0                     ; ...
un_ret:
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 40                ; ...
        ret                             ; done

; ---- templates ------------------------------------------------------------------------
; A template is a term in the clause store or the findall area whose
; variables are TVAR i. v_frame is the heap block of its variables' cells.

; build(a0 = template cell) -> a0 = the term on the heap
build:
        andi  t0, a0, 7                 ; what is it?
        li    t1, T_TVAR                ; a variable: its frame cell
        beq   t0, t1, bu_var            ; ...
        li    t1, T_STR                 ; a compound: copy it
        beq   t0, t1, bu_str            ; ...
        ret                             ; atomic: itself
bu_var:
        srli  a0, a0, 3                 ; frame + 8 i
        slli  a0, a0, 3                 ; ...
        ld    t0, v_frame(zero)         ; ...
        add   a0, a0, t0                ; ...
        ret                             ; ...
bu_str:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; s1 = template cursor
        sd    s2, 16(sp)                ; s2 = copy cursor
        sd    s3, 24(sp)                ; s3 = arguments left
        sd    s4, 32(sp)                ; s4 = the result
        sd    s5, 40(sp)                ; ...
        li    t0, SPMIN                 ; deep enough?
        bltu  sp, t0, err_depth         ; ...
        addi  s1, a0, -T_STR            ; the template's functor cell
        li    s4, 0                     ; no result yet
        li    s5, 0                     ; (the cell to link the next block into)
bu_block:
        mv    a0, s1                    ; the functor
        call  mrd                       ; ...
        mv    s3, a0                    ; ...
        srli  a0, a0, 3                 ; arity + 1 cells
        andi  a0, a0, 0x1FFF            ; ...
        addi  a0, a0, 1                 ; ...
        slli  a0, a0, 3                 ; ...
        call  halloc                    ; ...
        mv    s2, a0                    ; ...
        addi  a1, s2, T_STR             ; link it
        bnez  s4, bu_link               ; ...
        mv    s4, a1                    ; the first block is the result
        j     bu_head                   ; ...
bu_link:
        mv    a0, s5                    ; into the previous block's last argument
        call  mwr                       ; ...
bu_head:
        mv    a0, s2                    ; the functor
        mv    a1, s3                    ; ...
        call  mwr                       ; ...
        srli  s3, s3, 3                 ; arity
        andi  s3, s3, 0x1FFF            ; ...
bu_args:
        addi  s1, s1, 8                 ; next argument
        addi  s2, s2, 8                 ; ...
        addi  s3, s3, -1                ; the last?
        beqz  s3, bu_last               ; ...
        mv    a0, s1                    ; ...
        call  mrd                       ; ...
        call  build                     ; ...
        mv    a1, a0                    ; ...
        mv    a0, s2                    ; ...
        call  mwr                       ; ...
        j     bu_args                   ; ...
bu_last:
        mv    a0, s1                    ; ...
        call  mrd                       ; ...
        andi  t0, a0, 7                 ; a compound: go on into it
        li    t1, T_STR                 ; ...
        bne   t0, t1, bu_lone           ; ...
        addi  s1, a0, -T_STR            ; ...
        mv    s5, s2                    ; ...
        j     bu_block                  ; ...
bu_lone:
        call  build                     ; ...
        mv    a1, a0                    ; ...
        mv    a0, s2                    ; ...
        call  mwr                       ; ...
        mv    a0, s4                    ; the result
        ld    s5, 40(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; done

; newframe(a0 = variables) -> v_frame = a heap block of that many unbound cells
newframe:
        addi  sp, sp, -16               ; ...
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        mv    s1, a0                    ; ...
        slli  a0, a0, 3                 ; ...
        call  halloc                    ; ...
        sd    a0, v_frame(zero)         ; ...
nf_loop:
        beqz  s1, nf_done               ; ...
        mv    a1, a0                    ; unbound: refers to itself
        mv    t3, a0                    ; ...
        call  mwr                       ; ...
        addi  a0, t3, 8                 ; ...
        addi  s1, s1, -1                ; ...
        j     nf_loop                   ; ...
nf_done:
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; done

; unify_t(a0 = template cell, a1 = term) -> a0 = 1 / 0: unify a term with a
; template under v_frame, building only what a variable of the term needs
unify_t:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; s1 = template cursor
        sd    s2, 16(sp)                ; s2 = term cursor
        sd    s3, 24(sp)                ; s3 = arguments left
        sd    s4, 32(sp)                ; s4 = the template cell
        li    t0, SPMIN                 ; deep enough?
        bltu  sp, t0, err_depth         ; ...
ut_top:
        mv    s4, a0                    ; ...
        andi  t0, a0, 7                 ; a template variable: plain unification
        li    t1, T_TVAR                ; ...
        bne   t0, t1, ut_nv             ; ...
        call  build                     ; its frame cell
        call  unify                     ; ...
        j     ut_ret                    ; ...
ut_nv:
        mv    a0, a1                    ; the term
        call  deref                     ; ...
        mv    s2, a0                    ; ...
        andi  t0, s2, 7                 ; a variable: bind it to a copy
        bnez  t0, ut_val                ; ...
        mv    a0, s4                    ; ...
        call  build                     ; ...
        mv    a1, a0                    ; ...
        mv    a0, s2                    ; ...
        call  bind                      ; ...
        j     ut_true                   ; ...
ut_val:
        andi  t1, s4, 7                 ; the template's tag
        li    t2, T_STR                 ; compound?
        beq   t1, t2, ut_str            ; ...
        beq   s2, s4, ut_true           ; atomic: identical or not
        j     ut_false                  ; ...
ut_str:
        bne   t0, t2, ut_false          ; the term is not a compound
        addi  a0, s4, -T_STR            ; functors
        call  mrd                       ; ...
        mv    s3, a0                    ; ...
        addi  a0, s2, -T_STR            ; ...
        call  mrd                       ; ...
        bne   a0, s3, ut_false          ; ...
        srli  s3, s3, 3                 ; arity
        andi  s3, s3, 0x1FFF            ; ...
        addi  s1, s4, 8 - T_STR         ; argument cursors
        addi  s2, s2, 8 - T_STR         ; ...
ut_args:
        addi  s3, s3, -1                ; the last?
        beqz  s3, ut_last               ; ...
        mv    a0, s2                    ; ...
        call  mrd                       ; ...
        mv    s4, a0                    ; ...
        mv    a0, s1                    ; ...
        call  mrd                       ; ...
        mv    a1, s4                    ; ...
        call  unify_t                   ; ...
        beqz  a0, ut_false              ; ...
        addi  s1, s1, 8                 ; ...
        addi  s2, s2, 8                 ; ...
        j     ut_args                   ; ...
ut_last:
        mv    a0, s2                    ; ...
        call  mrd                       ; ...
        mv    s4, a0                    ; ...
        mv    a0, s1                    ; ...
        call  mrd                       ; ...
        mv    a1, s4                    ; ...
        j     ut_top                    ; ...
ut_true:
        li    a0, 1                     ; ...
        j     ut_ret                    ; ...
ut_false:
        li    a0, 0                     ; ...
ut_ret:
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 40                ; ...
        ret                             ; done

; ---- choicepoints ----------------------------------------------------------------------
; cppush(a0 = kind, a1 = goal, a2 = continuation, a3 = alternative, a4 = aux):
; a new frame on top
cppush:
        addi  sp, sp, -64               ; frame: ra, then the fields from CP_KIND on
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; kind
        sd    a1, 32(sp)                ; goal
        sd    a2, 40(sp)                ; continuation
        sd    a3, 48(sp)                ; alternative
        sd    a4, 56(sp)                ; aux
        ld    t0, v_H(zero)             ; heap top
        sd    t0, 16(sp)                ; ...
        ld    t0, v_TR(zero)            ; trail top
        sd    t0, 24(sp)                ; ...
        ld    a1, v_B(zero)             ; the new frame's place
        addi  a1, a1, CPSZ              ; ...
        ld    t0, v_cpend(zero)         ; full?
        bgeu  a1, t0, cpp_full           ; ...
        li    a0, wc                    ; make room
        li    a2, CPSZ                  ; ...
        call  win_fit                   ; (keeps a1)
        andi  t0, a1, CWSZ - 1          ; its ring slot (a frame never wraps: 64 divides the size)
        ld    t1, v_B(zero)             ; prev
        sd    t1, cring+CP_PREV(t0)     ; ...
        ld    t1, 8(sp)                 ; kind
        sd    t1, cring+CP_KIND(t0)     ; ...
        ld    t1, 16(sp)                ; H
        sd    t1, cring+CP_H(t0)        ; ...
        ld    t1, 24(sp)                ; TR
        sd    t1, cring+CP_TR(t0)       ; ...
        ld    t1, 32(sp)                ; goal
        sd    t1, cring+CP_GOAL(t0)     ; ...
        ld    t1, 40(sp)                ; continuation
        sd    t1, cring+CP_CONT(t0)     ; ...
        ld    t1, 48(sp)                ; alternative
        sd    t1, cring+CP_ALT(t0)      ; ...
        ld    t1, 56(sp)                ; aux
        sd    t1, cring+CP_AUX(t0)      ; ...
        sd    a1, v_B(zero)             ; the newest frame
        ld    t1, v_H(zero)             ; bindings older than this are trailed
        sd    t1, v_HB(zero)            ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 64                ; ...
        ret                             ; done
cpp_full:
        li    a0, at_stack + T_ATM      ; resource_error(stack)
        j     err_res                   ; ...

; cpget(a0 = field) -> a0: a field of the newest frame
cpget:
        ld    a1, v_B(zero)             ; ...
        add   a1, a1, a0                ; ...
        li    a0, wc                    ; ...
        j     wrd                       ; ...

; cut_to(a0 = frame): it becomes the newest; its heap top bounds the trail again
cut_to:
        addi  sp, sp, -8                ; ...
        sd    ra, 0(sp)                 ; ...
        sd    a0, v_B(zero)             ; ...
        addi  a1, a0, CP_H              ; its heap top
        li    a0, wc                    ; ...
        call  wrd                       ; ...
        sd    a0, v_HB(zero)            ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; done
