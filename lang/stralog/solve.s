; =============================================================================
; solve.s: the solve loop (resident)
; =============================================================================
;
; The machine runs a continuation: '$cont'(Goal, CutBarrier, Next), ending in
; END. A step takes the first goal and calls it:
;   * a control construct (PR_BI < 256) rearranges the continuation or the
;     choicepoints here;
;   * a builtin (PR_BI = a routine's far address) is called in its unit with
;     a0 = the goal and answers a0 = 1 (true) or 0 (fail);
;   * a user predicate: the first clause whose first-argument key fits and
;     which the call's generation can see; a choicepoint if another one
;     could follow; a frame of fresh variables; the head unified against its
;     template; the body built and pushed with the cut barrier of the call.
; Failing goes to the newest choicepoint (sv_fail). An exception (throw_ball)
; goes back to v_ssp and unwinds the choicepoints to a catch/3 whose catcher
; unifies with a copy of the ball.
;
; Registers in the loop: s1 the continuation, s2 the goal, s3 its cut
; barrier, s4 its functor cell, s5 the predicate, s6 PR_BI, s7 the
; generation, s8 the first-argument key, s9 the clause, s10 the body's cut
; barrier. Units keep s1..s6 (they save what they use), and nothing that
; the loop calls keeps them across a call that might throw.

; solve(a0 = goal): run it; '$start' (boot.pl) never returns
solve:
        sd    sp, v_ssp(zero)           ; exceptions come back to this depth
        mv    s2, a0                    ; ...
        li    a0, K_TOP                 ; the bottom frame
        li    a1, 0                     ; ...
        li    a2, END                   ; ...
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        call  cppush                    ; ...
        mv    a0, s2                    ; the continuation: the goal
        ld    a1, v_B(zero)             ; ...
        li    a2, END                   ; ...
        call  mkcont                    ; ...
        sd    a0, v_CONT(zero)          ; ...

; ---- the next goal ---------------------------------------------------------------------
sv_loop:
        ld    t0, v_H(zero)             ; the heap past its mark: collect it first
        ld    t1, v_gclim(zero)         ; (gc.s: here only the continuation and the
        bltu  t0, t1, sv_next           ;   choicepoints refer into the heap)
        la    t6, gc                    ; ...
        xcall ra, c0, t6                ; ...
sv_next:
        ld    s1, v_CONT(zero)          ; the continuation
        li    t0, END                   ; nothing left: the goal succeeded
        beq   s1, t0, sv_success        ; ...
        addi  a0, s1, 8 - T_STR         ; '$cont'(Goal, CB, Next)
        call  mrd                       ; ...
        mv    s2, a0                    ; s2 = the goal
        addi  a0, s1, 16 - T_STR        ; ...
        call  mrd                       ; ...
        srai  s3, a0, 3                 ; s3 = its cut barrier
        addi  a0, s1, 24 - T_STR        ; ...
        call  mrd                       ; ...
        sd    a0, v_CONT(zero)          ; the rest
sv_call:
        ld    t0, v_infer(zero)         ; count the call
        addi  t0, t0, 1                 ; ...
        sd    t0, v_infer(zero)         ; ...
        mv    a0, s2                    ; ...
        call  deref                     ; ...
        mv    s2, a0                    ; ...
        andi  t0, s2, 7                 ; what is it?
        li    t1, T_STR                 ; a compound
        beq   t0, t1, sv_str            ; ...
        li    t1, T_ATM                 ; an atom
        beq   t0, t1, sv_atom           ; ...
        beqz  t0, sv_inst               ; a variable
        li    a0, at_callable + T_ATM   ; anything else
        mv    a1, s2                    ; ...
        j     err_type                  ; ...
sv_inst:
        j     err_inst                  ; ...
sv_atom:
        srli  s4, s2, 3                 ; the functor cell of name/0
        slli  s4, s4, 16                ; ...
        ori   s4, s4, T_FUN             ; ...
        j     sv_pred                   ; ...
sv_str:
        addi  a0, s2, -T_STR            ; the functor cell
        call  mrd                       ; ...
        mv    s4, a0                    ; ...
sv_pred:
        mv    a0, s4                    ; the predicate
        call  pred_of                   ; ...
        beqz  a0, sv_unknown            ; none
        mv    s5, a0                    ; ...
        addi  a0, s5, PR_BI             ; a builtin?
        call  mrd                       ; ...
        mv    s6, a0                    ; ...
        bnez  s6, sv_bi                 ; ...
        addi  a0, s5, PR_FIRST          ; the first clause
        call  mrd                       ; ...
        ld    s7, v_gen(zero)           ; the generation this call sees
        mv    s9, a0                    ; ...
        mv    a0, s2                    ; its key
        call  goal_key                  ; ...
        mv    s8, a0                    ; ...
        mv    a0, s9                    ; ...

; ---- resolution: a0 = the first candidate clause; s2, s4, s7, s8 set ------------------
sv_resolve:
        mv    a1, s8                    ; the first that fits
        mv    a2, s7                    ; ...
        call  next_clause               ; ...
        beqz  a0, sv_fail               ; none
        mv    s9, a0                    ; ...
        ld    s10, v_B(zero)            ; the body's cut barrier: below any choicepoint made here
        call  mrd                       ; is there another? (CL_NEXT is word 0)
        mv    a1, s8                    ; ...
        mv    a2, s7                    ; ...
        call  next_clause               ; ...
        beqz  a0, sv_det                ; no: no choicepoint
        mv    a3, a0                    ; yes: remember where to go on
        li    a0, K_CLAUSE              ; ...
        mv    a1, s2                    ; ...
        ld    a2, v_CONT(zero)          ; ...
        mv    a4, s7                    ; ...
        call  cppush                    ; ...
sv_det:
        addi  a0, s9, CL_NVARS          ; a frame of fresh variables
        call  mrd                       ; ...
        call  newframe                  ; ...
        addi  a0, s9, CL_HEAD           ; the head
        call  mrd                       ; ...
        andi  t0, a0, 7                 ; an atom: nothing to unify
        li    t1, T_STR                 ; ...
        bne   t0, t1, sv_body           ; ...
        mv    a1, s2                    ; unify it with the goal
        call  unify_t                   ; ...
        beqz  a0, sv_fail               ; ...
sv_body:
        addi  a0, s9, CL_BODY           ; the body
        call  mrd                       ; ...
        li    t0, at_true + T_ATM       ; true: nothing to push
        beq   a0, t0, sv_loop           ; ...
        call  build                     ; ...
        mv    a1, s10                   ; with the call's cut barrier
        ld    a2, v_CONT(zero)          ; ...
        call  mkcont                    ; ...
        sd    a0, v_CONT(zero)          ; ...
        j     sv_loop                   ; ...

sv_unknown:
        li    a0, at_procedure + T_ATM  ; existence_error(procedure, Name/Arity)
        mv    a1, s4                    ; ...
        j     err_exist_pi              ; ...

; ---- builtins --------------------------------------------------------------------------
sv_bi:
        li    t0, 256                   ; a control construct?
        bltu  s6, t0, sv_ctrl           ; ...
        mv    a0, s2                    ; a builtin in a unit: a0 = the goal
        mv    t6, s6                    ; ...
        xcall ra, c0, t6                ; ...
        beqz  a0, sv_fail               ; it failed
        j     sv_loop                   ; it succeeded
sv_ctrl:
        slli  t0, s6, 2                 ; the jump table
        la    t1, ctab                  ; ...
        add   t0, t0, t1                ; ...
        jr    t0                        ; ...
ctab:
        j     sv_fail                   ; 0 (unused)
        j     sv_loop                   ; C_TRUE
        j     sv_fail                   ; C_FAIL
        j     c_conj                    ; C_CONJ
        j     c_cut                     ; C_CUT
        j     c_or                      ; C_OR
        j     c_ite                     ; C_ITE
        j     c_soft                    ; C_SOFT
        j     c_not                     ; C_NOT
        j     c_call                    ; C_CALL
        j     c_catch                   ; C_CATCH
        j     c_throw                   ; C_THROW
        j     c_findall                 ; C_FINDALL
        j     c_faadd                   ; C_FAADD
        j     c_dcut                    ; C_DCUT
        j     c_exitc                   ; C_EXITC
        j     c_softcut                 ; C_SOFTCUT
        j     c_choice                  ; C_CHOICE
        j     c_halt                    ; C_HALT

; (A, B): push B, then A, both with this cut barrier
c_conj:
        mv    a0, s2                    ; B
        li    a1, 2                     ; ...
        call  garg                      ; ...
        mv    a1, s3                    ; ...
        ld    a2, v_CONT(zero)          ; ...
        call  mkcont                    ; ...
        sd    a0, v_CONT(zero)          ; ...
        mv    a0, s2                    ; A: called at once
        li    a1, 1                     ; ...
        call  garg                      ; ...
        mv    s2, a0                    ; ...
        j     sv_call                   ; ...

; !: back to the barrier
c_cut:
        mv    a0, s3                    ; ...
        call  cut_to                    ; ...
        j     sv_loop                   ; ...

; (A ; B), (C -> T ; E), (C *-> T ; E)
c_or:
        mv    a0, s2                    ; the left side
        li    a1, 1                     ; ...
        call  garg                      ; ...
        mv    s5, a0                    ; s5 = A
        mv    a0, s2                    ; s6 = the right side
        li    a1, 2                     ; ...
        call  garg                      ; ...
        mv    s6, a0                    ; ...
        ld    s10, v_B(zero)            ; s10 = the frame below the else branch's
        li    a0, K_OR                  ; the else branch, for later
        mv    a1, s6                    ; ...
        ld    a2, v_CONT(zero)          ; ...
        li    a3, 0                     ; ...
        mv    a4, s3                    ; its cut barrier: the clause's
        call  cppush                    ; ...
        andi  t0, s5, 7                 ; A = (C -> T) or (C *-> T)?
        li    t1, T_STR                 ; ...
        bne   t0, t1, co_plain          ; ...
        addi  a0, s5, -T_STR            ; ...
        call  mrd                       ; ...
        li    t0, ((at_arrow >> 3) << 16) | (2 << 3) | T_FUN ; ->/2
        beq   a0, t0, co_ite            ; ...
        li    t0, ((at_sarrow >> 3) << 16) | (2 << 3) | T_FUN ; *->/2
        beq   a0, t0, co_soft           ; ...
co_plain:
        mv    s2, s5                    ; A, with the clause's barrier
        j     sv_call                   ; ...
co_ite:
        mv    a0, s5                    ; T, after cutting back below the else branch
        li    a1, 2                     ; ...
        call  garg                      ; ...
        mv    a1, s3                    ; ...
        ld    a2, v_CONT(zero)          ; ...
        call  mkcont                    ; ...
        mv    s6, a0                    ; ...
        slli  a1, s10, 3                ; '$cut'(B0)
        ori   a1, a1, T_INT             ; ...
        li    a0, ((at_dollar_cut >> 3) << 16) | (1 << 3) | T_FUN ; ...
        call  mkstr                     ; ...
        li    a1, 0                     ; ...
        mv    a2, s6                    ; ...
        call  mkcont                    ; ...
        sd    a0, v_CONT(zero)          ; ...
co_cond:
        mv    a0, s5                    ; C, opaque to cut: barrier = now
        li    a1, 1                     ; ...
        call  garg                      ; ...
        mv    s2, a0                    ; ...
        ld    s3, v_B(zero)             ; ...
        j     sv_call                   ; ...
co_soft:
        mv    a0, s5                    ; T, after disabling the else branch only
        li    a1, 2                     ; ...
        call  garg                      ; ...
        mv    a1, s3                    ; ...
        ld    a2, v_CONT(zero)          ; ...
        call  mkcont                    ; ...
        mv    s6, a0                    ; ...
        ld    a1, v_B(zero)             ; '$softcut'(Bor)
        slli  a1, a1, 3                 ; ...
        ori   a1, a1, T_INT             ; ...
        li    a0, ((at_dollar_softcut >> 3) << 16) | (1 << 3) | T_FUN ; ...
        call  mkstr                     ; ...
        li    a1, 0                     ; ...
        mv    a2, s6                    ; ...
        call  mkcont                    ; ...
        sd    a0, v_CONT(zero)          ; ...
        j     co_cond                   ; ...

; (C -> T) without an else: C, cut back, T
c_ite:
        ld    s10, v_B(zero)            ; B0
        mv    s5, s2                    ; ...
        j     co_ite                    ; (same continuation; no else frame)

; (C *-> T) without an else: (C, T)
c_soft:
        mv    s5, s2                    ; ...
        mv    a0, s5                    ; T
        li    a1, 2                     ; ...
        call  garg                      ; ...
        mv    a1, s3                    ; ...
        ld    a2, v_CONT(zero)          ; ...
        call  mkcont                    ; ...
        sd    a0, v_CONT(zero)          ; ...
        j     co_cond                   ; C

; \+ G: (G -> fail ; true)
c_not:
        ld    s10, v_B(zero)            ; B0
        li    a0, K_OR                  ; the else branch: true
        li    a1, at_true + T_ATM       ; ...
        ld    a2, v_CONT(zero)          ; ...
        li    a3, 0                     ; ...
        mv    a4, s3                    ; ...
        call  cppush                    ; ...
        li    a0, at_fail + T_ATM       ; then: cut back and fail
        li    a1, 0                     ; ...
        li    a2, END                   ; ...
        call  mkcont                    ; ...
        mv    s6, a0                    ; ...
        slli  a1, s10, 3                ; '$cut'(B0)
        ori   a1, a1, T_INT             ; ...
        li    a0, ((at_dollar_cut >> 3) << 16) | (1 << 3) | T_FUN ; ...
        call  mkstr                     ; ...
        li    a1, 0                     ; ...
        mv    a2, s6                    ; ...
        call  mkcont                    ; ...
        sd    a0, v_CONT(zero)          ; ...
        mv    s5, s2                    ; G, opaque to cut
        mv    a0, s5                    ; ...
        li    a1, 1                     ; ...
        call  garg                      ; ...
        mv    s2, a0                    ; ...
        ld    s3, v_B(zero)             ; ...
        j     sv_call                   ; ...

; call(G, A1, ...): G with the arguments added, opaque to cut
c_call:
        mv    a0, s2                    ; the goal to call (a unit builds it)
        la    t6, callgoal              ; ...
        xcall ra, c0, t6                ; ...
        mv    s2, a0                    ; ...
        ld    s3, v_B(zero)             ; ...
        j     sv_call                   ; ...

; catch(G, C, R): a catch frame, then G, then leave the frame if G left nothing
c_catch:
        li    a0, K_CATCH               ; ...
        mv    a1, s2                    ; the catch/3 goal (C and R are its arguments)
        ld    a2, v_CONT(zero)          ; ...
        li    a3, 0                     ; ...
        mv    a4, s3                    ; ...
        call  cppush                    ; ...
        ld    a1, v_B(zero)             ; '$exit_catch'(Bc)
        slli  a1, a1, 3                 ; ...
        ori   a1, a1, T_INT             ; ...
        li    a0, ((at_dollar_exitc >> 3) << 16) | (1 << 3) | T_FUN ; ...
        call  mkstr                     ; ...
        li    a1, 0                     ; ...
        ld    a2, v_CONT(zero)          ; ...
        call  mkcont                    ; ...
        sd    a0, v_CONT(zero)          ; ...
        mv    a0, s2                    ; G
        li    a1, 1                     ; ...
        call  garg                      ; ...
        mv    s2, a0                    ; ...
        ld    s3, v_B(zero)             ; ...
        j     sv_call                   ; ...

; '$exit_catch'(Bc): the frame goes if it is the newest
c_exitc:
        mv    a0, s2                    ; ...
        li    a1, 1                     ; ...
        call  garg                      ; ...
        srai  a0, a0, 3                 ; ...
        ld    t0, v_B(zero)             ; ...
        bne   a0, t0, sv_loop           ; choicepoints inside G: it stays
        li    a0, CP_PREV               ; ...
        call  cpget                     ; ...
        call  cut_to                    ; ...
        j     sv_loop                   ; ...

; throw(Ball)
c_throw:
        mv    a0, s2                    ; ...
        li    a1, 1                     ; ...
        call  garg                      ; ...
        andi  t0, a0, 7                 ; a variable: instantiation error
        beqz  t0, sv_inst               ; ...
        j     throw_ball                ; ...

; findall(T, G, L): a findall frame, then G, then add T and fail
c_findall:
        li    a0, K_FINDALL             ; ...
        mv    a1, s2                    ; ...
        ld    a2, v_CONT(zero)          ; ...
        ld    a3, v_fatop(zero)         ; where its answers start
        mv    a4, s3                    ; ...
        call  cppush                    ; ...
        mv    a0, s2                    ; '$fa_add'(T)
        li    a1, 1                     ; ...
        call  garg                      ; ...
        mv    a1, a0                    ; ...
        li    a0, ((at_dollar_faadd >> 3) << 16) | (1 << 3) | T_FUN ; ...
        call  mkstr                     ; ...
        li    a1, 0                     ; ...
        li    a2, END                   ; ...
        call  mkcont                    ; ...
        sd    a0, v_CONT(zero)          ; ...
        mv    a0, s2                    ; G
        li    a1, 2                     ; ...
        call  garg                      ; ...
        mv    s2, a0                    ; ...
        ld    s3, v_B(zero)             ; ...
        j     sv_call                   ; ...

; '$fa_add'(T): a copy of T into the findall area, then fail
c_faadd:
        mv    a0, s2                    ; ...
        li    a1, 1                     ; ...
        call  garg                      ; ...
        la    t6, fa_add                ; ...
        xcall ra, c0, t6                ; ...
        j     sv_fail                   ; ...

; '$cut'(B)
c_dcut:
        mv    a0, s2                    ; ...
        li    a1, 1                     ; ...
        call  garg                      ; ...
        srai  a0, a0, 3                 ; ...
        call  cut_to                    ; ...
        j     sv_loop                   ; ...

; '$softcut'(B): that frame is skipped from now on
c_softcut:
        mv    a0, s2                    ; ...
        li    a1, 1                     ; ...
        call  garg                      ; ...
        srai  a1, a0, 3                 ; ...
        addi  a1, a1, CP_KIND           ; ...
        li    a0, wc                    ; ...
        li    a2, K_DEAD                ; ...
        call  wwr                       ; ...
        j     sv_loop                   ; ...

; '$choice'(B): B = the newest choicepoint (an integer)
c_choice:
        mv    a0, s2                    ; ...
        li    a1, 1                     ; ...
        call  garg                      ; ...
        ld    a1, v_B(zero)             ; ...
        slli  a1, a1, 3                 ; ...
        ori   a1, a1, T_INT             ; ...
        call  unify                     ; ...
        beqz  a0, sv_fail               ; ...
        j     sv_loop                   ; ...

; halt, halt(Code)
c_halt:
        li    s5, 0                     ; the code
        andi  t0, s2, 7                 ; halt/1?
        li    t1, T_STR                 ; ...
        bne   t0, t1, ch_go             ; ...
        mv    a0, s2                    ; ...
        li    a1, 1                     ; ...
        call  garg                      ; ...
        srai  s5, a0, 3                 ; ...
ch_go:
        la    t6, io_flushall           ; flush the files written
        xcall ra, c0, t6                ; ...
        mv    a0, s5                    ; ...
        call  sys_exit                  ; ...

sv_success:
        li    s5, 0                     ; '$start' ended: halt
        j     ch_go                     ; ...

; ---- failing -------------------------------------------------------------------------------
sv_fail:
        ld    s1, v_B(zero)             ; the newest frame
        li    a0, CP_TR                 ; undo the bindings since
        call  cpget                     ; ...
        call  untrail                   ; ...
        li    a0, CP_H                  ; give back the heap
        call  cpget                     ; ...
        sd    a0, v_H(zero)             ; ...
        li    a0, CP_KIND               ; ...
        call  cpget                     ; ...
        mv    s6, a0                    ; ...
        li    t0, K_CLAUSE              ; ...
        beq   s6, t0, sf_clause         ; ...
        li    t0, K_OR                  ; ...
        beq   s6, t0, sf_or             ; ...
        li    t0, K_FINDALL             ; ...
        beq   s6, t0, sf_findall        ; ...
        li    t0, K_TOP                 ; ...
        beq   s6, t0, sf_top            ; ...
        call  sf_pop                    ; catch, dead: just go
        j     sv_fail                   ; ...
sf_pop:
        addi  sp, sp, -8                ; pop the newest frame
        sd    ra, 0(sp)                 ; ...
        li    a0, CP_PREV               ; ...
        call  cpget                     ; ...
        call  cut_to                    ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...
sf_clause:
        li    a0, CP_GOAL               ; the call again, from the next clause
        call  cpget                     ; ...
        mv    s2, a0                    ; ...
        li    a0, CP_CONT               ; ...
        call  cpget                     ; ...
        sd    a0, v_CONT(zero)          ; ...
        li    a0, CP_AUX                ; ...
        call  cpget                     ; ...
        mv    s7, a0                    ; ...
        li    a0, CP_ALT                ; ...
        call  cpget                     ; ...
        mv    s9, a0                    ; ...
        call  sf_pop                    ; (sv_resolve pushes a new frame if there is more)
        mv    a0, s2                    ; the key again
        call  goal_key                  ; ...
        mv    s8, a0                    ; ...
        mv    a0, s9                    ; ...
        j     sv_resolve                ; ...
sf_or:
        li    a0, CP_GOAL               ; the else branch
        call  cpget                     ; ...
        mv    s2, a0                    ; ...
        li    a0, CP_CONT               ; ...
        call  cpget                     ; ...
        sd    a0, v_CONT(zero)          ; ...
        li    a0, CP_AUX                ; ...
        call  cpget                     ; ...
        mv    s3, a0                    ; ...
        call  sf_pop                    ; ...
        j     sv_call                   ; ...
sf_findall:
        li    a0, CP_GOAL               ; findall(T, G, L)
        call  cpget                     ; ...
        mv    s2, a0                    ; ...
        li    a0, CP_CONT               ; ...
        call  cpget                     ; ...
        sd    a0, v_CONT(zero)          ; ...
        li    a0, CP_ALT                ; where its answers start
        call  cpget                     ; ...
        mv    s5, a0                    ; ...
        call  sf_pop                    ; ...
        mv    a0, s5                    ; the answers as a list (a unit)
        la    t6, fa_collect2           ; ...
        xcall ra, c0, t6                ; ...
        mv    s5, a0                    ; ...
        mv    a0, s2                    ; L
        li    a1, 3                     ; ...
        call  garg                      ; ...
        mv    a1, s5                    ; ...
        call  unify                     ; ...
        beqz  a0, sv_fail               ; ...
        j     sv_loop                   ; ...
sf_top:
        li    s5, 1                     ; '$start' failed
        j     ch_go                     ; ...

; ---- exceptions -------------------------------------------------------------------------
; throw_ball(a0 = ball): never returns. Units may jump here (jalr zero, gp, ...).
throw_ball:
        ld    sp, v_ssp(zero)           ; back to the solve loop's depth
        lui   gp, 1                     ; (gp = R, whoever jumped here)
        mv    s1, a0                    ; s1 = the ball
        ld    s2, v_fatop(zero)         ; s2 = where its copy goes
        la    t6, fa_add                ; the copy survives the heap's unwinding
        xcall ra, c0, t6                ; ...
        mv    s3, s2                    ; s3 = the findall area's top after a catch
tb_loop:
        li    a0, CP_KIND               ; the newest frame
        call  cpget                     ; ...
        li    t0, K_CATCH               ; ...
        beq   a0, t0, tb_catch          ; ...
        li    t0, K_TOP                 ; ...
        beq   a0, t0, tb_uncaught       ; ...
        li    t0, K_FINDALL             ; a findall's answers go too
        bne   a0, t0, tb_pop            ; ...
        li    a0, CP_ALT                ; ...
        call  cpget                     ; ...
        bgeu  a0, s3, tb_pop            ; ...
        mv    s3, a0                    ; ...
tb_pop:
        call  sf_pop                    ; ...
        j     tb_loop                   ; ...
tb_catch:
        li    a0, CP_TR                 ; back to the catch's state
        call  cpget                     ; ...
        call  untrail                   ; ...
        li    a0, CP_H                  ; ...
        call  cpget                     ; ...
        sd    a0, v_H(zero)             ; ...
        li    a0, CP_GOAL               ; s4 = catch(G, C, R)
        call  cpget                     ; ...
        mv    s4, a0                    ; ...
        li    a0, CP_CONT               ; s5 = what follows it
        call  cpget                     ; ...
        mv    s5, a0                    ; ...
        call  sf_pop                    ; ...
