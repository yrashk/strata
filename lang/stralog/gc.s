; =============================================================================
; gc.s: the heap's garbage collector (a code unit)
; =============================================================================
;
; Sliding mark-compact, run by the solve loop between two goals when the
; heap passes v_gclim. Then the only references into the heap are the
; continuation, the goal and continuation of every choicepoint, and the
; cells the trail names.
;   1. mark: a bit per heap cell, in a bitmap put in the free heap above H;
;      a compound marks all its cells; a variable cell alone.
;   2. a prefix table, one word per 64 cells: the live cells before them.
;      A live cell's new place is the heap's start plus 8 times the live
;      cells below it; so is a choicepoint's saved heap top.
;   3. every live cell's references, and the roots, are rewritten.
;   4. the live cells slide down, in order (so choicepoints' heap segments
;      keep their order: backtracking still gives back what is above them).
; Every cell is read and written with mrd / mwr, through the heap window
; and the far cache like any other: the collector streams the heap through
; the D-LS that way. The far cache then drops what it held above the
; window's base (the bitmap and the table, dead now).

        .data                           ; the collector's state
        .align 8                        ; ...
g_lo:     .dword 0                      ; the heap's start
g_hi:     .dword 0                      ; its top when the collection began
g_bits:   .dword 0                      ; arena offset of the bitmap
g_pref:   .dword 0                      ; ... of the prefix table
g_stk:    .dword 0                      ; ... of the mark stack's bottom
g_sp:     .dword 0                      ; ... its top
g_send:   .dword 0                      ; ... its end
v_gclim:  .dword A_HEAPEND              ; collect when the heap top passes this (layout sets it)
v_gcs:    .dword 0                      ; collections
v_gcfreed: .dword 0                     ; bytes they gave back

        .far                            ; code units
        .align 4096                     ; ---- unit: the collector ----
u_gc:

; gc(): collect the heap
gc:
        jalr  t6, gp, ent6-R            ; s1..s6
        li    s1, A_HEAP                ; the heap
        sd    s1, g_lo(zero)            ; ...
        ld    s2, v_H(zero)             ; ...
        sd    s2, g_hi(zero)            ; ...
        sub   t0, s2, s1                ; cells
        srli  t0, t0, 3                 ; ...
        srli  t0, t0, 6                 ; bitmap words
        addi  t0, t0, 1                 ; ...
        sd    t0, v_tmp+24(zero)        ; (kept: words)
        slli  t0, t0, 3                 ; bytes
        sd    s2, g_bits(zero)          ; the bitmap at H
        add   t1, s2, t0                ; the prefix table after it (one more word)
        sd    t1, g_pref(zero)          ; ...
        add   t1, t1, t0                ; the mark stack after that
        addi  t1, t1, 8                 ; ...
        sd    t1, g_stk(zero)           ; ...
        sd    t1, g_sp(zero)            ; ...
        ld    t2, v_heapend(zero)       ; room for a stack of at least 4 KiB?
        sd    t2, g_send(zero)          ; ...
        addi  t2, t2, -4096             ; ...
        bgeu  t1, t2, gc_none           ; no: no collection (the heap will fill)
        ld    s3, v_tmp+24(zero)        ; clear the bitmap
        ld    s4, g_bits(zero)          ; ...
gc_clr:
        beqz  s3, gc_roots              ; ...
        mv    a0, s4                    ; ...
        li    a1, 0                     ; ...
        jalr  ra, gp, mwr-R             ; ...
        addi  s4, s4, 8                 ; ...
        addi  s3, s3, -1                ; ...
        j     gc_clr                    ; ...

; ---- 0. tidy the trail: an entry is needed only if its cell is older than
;      the heap top of the choicepoint whose segment holds it (a cut leaves
;      entries of frames that are gone; they would keep cells alive) ----
gc_roots:
        call  gtidy                     ; ...

; ---- 1. mark ----
        ld    a0, v_CONT(zero)          ; the continuation
        call  gmark                     ; ...
        ld    s3, v_B(zero)             ; every choicepoint: goal, continuation
        ld    s4, v_cp(zero)            ; ...
gc_mcp:
        bltu  s3, s4, gc_mtr            ; ...
        addi  a1, s3, CP_GOAL           ; ...
        li    a0, wc                    ; ...
        jalr  ra, gp, wrd-R             ; ...
        call  gmark                     ; ...
        addi  a1, s3, CP_CONT           ; ...
        li    a0, wc                    ; ...
        jalr  ra, gp, wrd-R             ; ...
        call  gmark                     ; ...
        mv    a1, s3                    ; CP_PREV
        li    a0, wc                    ; ...
        jalr  ra, gp, wrd-R             ; ...
        mv    s3, a0                    ; ...
        j     gc_mcp                    ; ...
gc_mtr:
        ld    s3, v_trail(zero)         ; every trailed cell (its variable, as a reference)
        ld    s4, v_TR(zero)            ; ...
gc_mtl:
        bgeu  s3, s4, gc_prefix         ; ...
        mv    a1, s3                    ; ...
        li    a0, wt                    ; ...
        jalr  ra, gp, wrd-R             ; (a cell's offset is a reference to it)
        call  gmark                     ; ...
        addi  s3, s3, 8                 ; ...
        j     gc_mtl                    ; ...

; ---- 2. the prefix table ----
gc_prefix:
        ld    s3, v_tmp+24(zero)        ; words
        ld    s4, g_bits(zero)          ; ...
        ld    s5, g_pref(zero)          ; ...
        li    s6, 0                     ; live cells so far
gc_pl:
        mv    a0, s5                    ; this block's count: those before it
        mv    a1, s6                    ; ...
        jalr  ra, gp, mwr-R             ; ...
        beqz  s3, gc_update             ; (one word more than blocks: the total)
        mv    a0, s4                    ; ...
        jalr  ra, gp, mrd-R             ; ...
        call  popcount                  ; ...
        add   s6, s6, a0                ; ...
        addi  s4, s4, 8                 ; ...
        addi  s5, s5, 8                 ; ...
        addi  s3, s3, -1                ; ...
        j     gc_pl                     ; ...

; ---- 3. references ----
gc_update:
        sd    s6, v_tmp+16(zero)        ; (live cells in all)
        ld    s3, g_lo(zero)            ; every live cell
gc_ul:
        ld    t0, g_hi(zero)            ; ...
        bgeu  s3, t0, gc_uroots         ; ...
        mv    a0, s3                    ; ...
        call  gisset                    ; ...
        beqz  a0, gc_unext              ; ...
        mv    a0, s3                    ; ...
        jalr  ra, gp, mrd-R             ; ...
        call  gfix                      ; its reference, moved
        mv    a1, a0                    ; ...
        mv    a0, s3                    ; ...
        jalr  ra, gp, mwr-R             ; ...
gc_unext:
        addi  s3, s3, 8                 ; ...
        j     gc_ul                     ; ...
gc_uroots:
        ld    a0, v_CONT(zero)          ; the continuation
        call  gfix                      ; ...
        sd    a0, v_CONT(zero)          ; ...
        ld    s3, v_B(zero)             ; the choicepoints: goal, continuation, heap top
        ld    s4, v_cp(zero)            ; ...
gc_ucp:
        bltu  s3, s4, gc_utr            ; ...
        addi  a1, s3, CP_GOAL           ; ...
        call  gfixcp                    ; ...
        addi  a1, s3, CP_CONT           ; ...
        call  gfixcp                    ; ...
        addi  a1, s3, CP_H              ; (a heap top: where the cells below it end up)
        li    a0, wc                    ; ...
        jalr  ra, gp, wrd-R             ; ...
        call  gfwd                      ; ...
        mv    a2, a0                    ; ...
        addi  a1, s3, CP_H              ; ...
        li    a0, wc                    ; ...
        jalr  ra, gp, wwr-R             ; ...
        mv    a1, s3                    ; CP_PREV
        li    a0, wc                    ; ...
        jalr  ra, gp, wrd-R             ; ...
        mv    s3, a0                    ; ...
        j     gc_ucp                    ; ...
gc_utr:
        ld    s3, v_trail(zero)         ; the trail: offsets of cells
        ld    s4, v_TR(zero)            ; ...
gc_utl:
        bgeu  s3, s4, gc_slide          ; ...
        mv    a1, s3                    ; ...
        li    a0, wt                    ; ...
        jalr  ra, gp, wrd-R             ; ...
        call  gfwd                      ; ...
        mv    a2, a0                    ; ...
        mv    a1, s3                    ; ...
        li    a0, wt                    ; ...
        jalr  ra, gp, wwr-R             ; ...
        addi  s3, s3, 8                 ; ...
        j     gc_utl                    ; ...

; ---- 4. slide ----
gc_slide:
        ld    s3, g_lo(zero)            ; every live cell, in order, down to its place
        mv    s4, s3                    ; s4 = where the next goes
gc_sl:
        ld    t0, g_hi(zero)            ; ...
        bgeu  s3, t0, gc_done           ; ...
        mv    a0, s3                    ; ...
        call  gisset                    ; ...
        beqz  a0, gc_snext              ; ...
        mv    a0, s3                    ; ...
        jalr  ra, gp, mrd-R             ; ...
        mv    a1, a0                    ; ...
        mv    a0, s4                    ; ...
        jalr  ra, gp, mwr-R             ; ...
        addi  s4, s4, 8                 ; ...
gc_snext:
        addi  s3, s3, 8                 ; ...
        j     gc_sl                     ; ...
gc_done:
        ld    a0, v_HB(zero)            ; the heap top of the newest choicepoint
        call  gfwd                      ; ...
        sd    a0, v_HB(zero)            ; ...
        ld    t0, g_hi(zero)            ; count what came back
        sub   t1, t0, s4                ; ...
        ld    t2, v_gcfreed(zero)       ; ...
        add   t2, t2, t1                ; ...
        sd    t2, v_gcfreed(zero)       ; ...
        ld    t2, v_gcs(zero)           ; ...
        addi  t2, t2, 1                 ; ...
        sd    t2, v_gcs(zero)           ; ...
        sd    s4, v_H(zero)             ; the new top
        ld    a0, wh+W_BASE(zero)       ; the cache keeps nothing at or above the window's base
        ld    a1, v_heapend(zero)       ; (the bitmap and the table went there)
        jalr  ra, gp, fc_flush-R        ; ...
        call  gc_limit                  ; ...
        jalr  zero, gp, lv6-R           ; ...
gc_none:
        call  gc_limit                  ; ...
        jalr  zero, gp, lv6-R           ; ...

; gtidy (leaf): the trail without the entries nothing would undo. The frames
; lie in the choicepoint stack from the oldest (v_cp) to the newest (v_B);
; frame f's segment is the trail from its CP_TR to the next frame's (or the
; top); its entries for cells at or above f's CP_H go. CP_TR moves with the
; entries kept.
gtidy:
        addi  sp, sp, -56               ; ...
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; s1 = frame
        sd    s2, 16(sp)                ; s2 = where the next kept entry goes
        sd    s3, 24(sp)                ; s3 = the entry looked at
        sd    s4, 32(sp)                ; s4 = its segment's end
        sd    s5, 40(sp)                ; s5 = the frame's heap top
        ld    s1, v_cp(zero)            ; the oldest frame
        ld    s2, v_trail(zero)         ; ...
        mv    s3, s2                    ; ...
gt_frame:
        ld    t0, v_B(zero)             ; past the newest?
        bgtu  s1, t0, gt_done           ; ...
        addi  a1, s1, CP_H              ; its heap top
        li    a0, wc                    ; ...
        jalr  ra, gp, wrd-R             ; ...
        mv    s5, a0                    ; ...
        addi  a1, s1, CP_TR             ; its segment starts where the kept entries are now
        li    a0, wc                    ; ...
        mv    a2, s2                    ; ...
        jalr  ra, gp, wwr-R             ; ...
        ld    s4, v_TR(zero)            ; its end: the next frame's TR, or the top
        ld    t0, v_B(zero)             ; ...
        bgeu  s1, t0, gt_seg            ; ...
        addi  a1, s1, CPSZ + CP_TR      ; ...
        li    a0, wc                    ; ...
        jalr  ra, gp, wrd-R             ; ...
        mv    s4, a0                    ; ...
gt_seg:
        bgeu  s3, s4, gt_next           ; ...
        mv    a1, s3                    ; the entry
        li    a0, wt                    ; ...
        jalr  ra, gp, wrd-R             ; ...
        bgeu  a0, s5, gt_drop           ; newer than the frame: nothing to undo
        mv    a2, a0                    ; kept
        mv    a1, s2                    ; ...
        li    a0, wt                    ; ...
        jalr  ra, gp, wwr-R             ; ...
        addi  s2, s2, 8                 ; ...
gt_drop:
        addi  s3, s3, 8                 ; ...
        j     gt_seg                    ; ...
gt_next:
        addi  s1, s1, CPSZ              ; the next frame
        j     gt_frame                  ; ...
gt_done:
        sd    s2, v_TR(zero)            ; the new top
        ld    s5, 40(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 56                ; ...
        ret                             ; ...

; gc_limit (leaf): the next collection when the heap has grown by half of
; what is free now, and by at least 64 KiB (or when it is full)
gc_limit:
        ld    t0, v_H(zero)             ; ...
        ld    t1, v_hlim(zero)          ; ...
        sub   t2, t1, t0                ; free
        srli  t2, t2, 1                 ; half of it
        li    t3, 0x10000               ; ...
        bgeu  t2, t3, gl_set            ; ...
        mv    t2, t3                    ; ...
gl_set:
        add   t0, t0, t2                ; ...
        sd    t0, v_gclim(zero)         ; ...
        ret                             ; ...

; gmark (leaf, a0 = a cell): mark everything it reaches
gmark:
        addi  sp, sp, -16               ; ...
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; s1 = the cell being followed
        ld    t0, g_stk(zero)           ; an empty stack
        sd    t0, g_sp(zero)            ; ...
gm_cell:
        mv    s1, a0                    ; ...
gm_loop:
        andi  t0, s1, 7                 ; a reference into the heap?
        beqz  t0, gm_ref                ; a variable
        li    t1, T_STR                 ; a compound
        beq   t0, t1, gm_str            ; ...
        j     gm_pop                    ; atomic: done
gm_ref:
        mv    a0, s1                    ; in the heap?
        call  ginheap                   ; ...
        beqz  a0, gm_pop                ; ...
        mv    a0, s1                    ; marked already?
        call  gsetbit                   ; ...
        bnez  a0, gm_pop                ; ...
        mv    a0, s1                    ; its value next
        jalr  ra, gp, mrd-R             ; ...
        mv    s1, a0                    ; ...
        j     gm_loop                   ; ...
gm_str:
        addi  s1, s1, -T_STR            ; the functor cell
        mv    a0, s1                    ; ...
        call  ginheap                   ; ...
        beqz  a0, gm_pop                ; ...
        mv    a0, s1                    ; marked already?
        call  gsetbit                   ; ...
        bnez  a0, gm_pop                ; ...
        mv    a0, s1                    ; its arity
        jalr  ra, gp, mrd-R             ; ...
        srli  t0, a0, 3                 ; ...
        andi  t0, t0, 0x1FFF            ; ...
        sd    t0, v_tmp(zero)           ; (arguments left)
gm_args:
        addi  s1, s1, 8                 ; the next argument's cell: live
        mv    a0, s1                    ; ...
        call  gsetbit                   ; ...
        ld    t0, v_tmp(zero)           ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, v_tmp(zero)           ; ...
        beqz  t0, gm_last               ; the last: followed at once
        mv    a0, s1                    ; the others: their values onto the stack
        jalr  ra, gp, mrd-R             ; ...
        call  gpush                     ; ...
        j     gm_args                   ; ...
gm_last:
        mv    a0, s1                    ; ...
        jalr  ra, gp, mrd-R             ; ...
        mv    s1, a0                    ; ...
        j     gm_loop                   ; ...
gm_pop:
        ld    t0, g_sp(zero)            ; anything stacked?
        ld    t1, g_stk(zero)           ; ...
        bleu  t0, t1, gm_done           ; ...
        addi  t0, t0, -8                ; ...
        sd    t0, g_sp(zero)            ; ...
        mv    a0, t0                    ; ...
        jalr  ra, gp, mrd-R             ; ...
        j     gm_cell                   ; ...
gm_done:
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; gpush (leaf, a0 = a cell): onto the mark stack
gpush:
        ld    t0, g_sp(zero)            ; ...
        ld    t1, g_send(zero)          ; full: the heap is too full to collect
        bgeu  t0, t1, gp_full           ; ...
        addi  t1, t0, 8                 ; ...
        sd    t1, g_sp(zero)            ; ...
        mv    a1, a0                    ; ...
        mv    a0, t0                    ; ...
        jalr  zero, gp, mwr-R           ; (tail call)
gp_full:
        li    a0, at_memory + T_ATM     ; resource_error(memory)
        jalr  zero, gp, err_res-R       ; ...

; ginheap (leaf, a0 = an offset) -> a0 = 1 if it is a cell of the heap below g_hi
ginheap:
        ld    t0, g_lo(zero)            ; ...
        ld    t1, g_hi(zero)            ; ...
        sltu  t2, a0, t0                ; ...
        sltu  t3, a0, t1                ; ...
        xori  t2, t2, 1                 ; ...
        and   a0, t2, t3                ; ...
        ret                             ; ...

; gbit (leaf, a0 = a heap cell) -> t4 = its bitmap word's offset, t5 = its mask
gbit:
        ld    t0, g_lo(zero)            ; ...
        sub   t0, a0, t0                ; ...
        srli  t0, t0, 3                 ; the cell's index
        andi  t1, t0, 63                ; its bit
        li    t5, 1                     ; ...
        sll   t5, t5, t1                ; ...
        srli  t0, t0, 6                 ; its word
        slli  t0, t0, 3                 ; ...
        ld    t4, g_bits(zero)          ; ...
        add   t4, t4, t0                ; ...
        ret                             ; ...

; gsetbit (leaf, a0 = a heap cell) -> a0 = its bit as it was; it is set now
gsetbit:
        addi  sp, sp, -24               ; ...
        sd    ra, 0(sp)                 ; ...
        call  gbit                      ; ...
        sd    t4, 8(sp)                 ; ...
        sd    t5, 16(sp)                ; ...
        mv    a0, t4                    ; ...
        jalr  ra, gp, mrd-R             ; ...
        ld    t5, 16(sp)                ; ...
        and   t0, a0, t5                ; ...
        bnez  t0, gsb_was                ; ...
        or    a1, a0, t5                ; ...
        ld    a0, 8(sp)                 ; ...
        jalr  ra, gp, mwr-R             ; ...
        li    a0, 0                     ; ...
        j     gsb_ret                    ; ...
gsb_was:
        li    a0, 1                     ; ...
gsb_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; gisset (leaf, a0 = a heap cell) -> a0 = its bit
gisset:
        addi  sp, sp, -16               ; ...
        sd    ra, 0(sp)                 ; ...
        call  gbit                      ; ...
        sd    t5, 8(sp)                 ; ...
        mv    a0, t4                    ; ...
        jalr  ra, gp, mrd-R             ; ...
        ld    t5, 8(sp)                 ; ...
        and   a0, a0, t5                ; ...
        snez  a0, a0                    ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; gfwd (leaf, a0 = a heap offset, a cell or a top) -> a0 = where it goes: the
; heap's start plus 8 for each live cell below it (offsets outside the heap
; collected are left as they are)
gfwd:
        ld    t0, g_lo(zero)            ; below the heap: itself
        bltu  a0, t0, gf_ret            ; ...
        ld    t1, g_hi(zero)            ; above its top: itself (the top itself: all of them)
        bgtu  a0, t1, gf_ret            ; ...
        addi  sp, sp, -32               ; ...
        sd    ra, 0(sp)                 ; ...
        sub   t0, a0, t0                ; the cell's index
        srli  t0, t0, 3                 ; ...
        andi  t1, t0, 63                ; its bit in its word
        sd    t1, 8(sp)                 ; ...
        srli  t0, t0, 6                 ; its word's offset
        slli  t0, t0, 3                 ; ...
        sd    t0, 16(sp)                ; ...
        ld    a0, g_pref(zero)          ; the live cells before the word
        add   a0, a0, t0                ; ...
        jalr  ra, gp, mrd-R             ; ...
        sd    a0, 24(sp)                ; ...
        ld    t0, 8(sp)                 ; and those before it in the word
        beqz  t0, gf_sum                ; (none)
        ld    a0, g_bits(zero)          ; ...
        ld    t1, 16(sp)                ; ...
        add   a0, a0, t1                ; ...
        jalr  ra, gp, mrd-R             ; ...
        ld    t0, 8(sp)                 ; ...
        li    t2, 1                     ; the bits below it
        sll   t2, t2, t0                ; ...
        addi  t2, t2, -1                ; ...
        and   a0, a0, t2                ; ...
        call  popcount                  ; ...
        ld    t3, 24(sp)                ; ...
        add   t3, t3, a0                ; ...
        sd    t3, 24(sp)                ; ...
gf_sum:
        ld    t3, 24(sp)                ; ...
        slli  t3, t3, 3                 ; ...
        ld    a0, g_lo(zero)            ; ...
        add   a0, a0, t3                ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
gf_ret:
        ret                             ; ...

; gfix (leaf, a0 = a cell) -> a0: the cell with its reference into the heap moved
gfix:
        andi  t0, a0, 7                 ; a variable or a compound
        beqz  t0, gx_go                 ; ...
        li    t1, T_STR                 ; ...
        bne   t0, t1, gx_ret            ; ...
gx_go:
        addi  sp, sp, -16               ; ...
        sd    ra, 0(sp)                 ; ...
        sd    t0, 8(sp)                 ; the tag
        sub   a0, a0, t0                ; the offset
        call  gfwd                      ; ...
        ld    t0, 8(sp)                 ; ...
        or    a0, a0, t0                ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
gx_ret:
        ret                             ; ...

; gfixcp (leaf, a1 = a choicepoint field holding a cell): fixed in place
gfixcp:
        addi  sp, sp, -16               ; ...
        sd    ra, 0(sp)                 ; ...
        sd    a1, 8(sp)                 ; ...
        li    a0, wc                    ; ...
        jalr  ra, gp, wrd-R             ; ...
        call  gfix                      ; ...
        mv    a2, a0                    ; ...
        ld    a1, 8(sp)                 ; ...
        li    a0, wc                    ; ...
        jalr  ra, gp, wwr-R             ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; popcount (leaf, a0) -> a0 = its one bits
popcount:
        li    t0, 0                     ; ...
pc_loop:
        beqz  a0, pc_done               ; ...
        addi  t1, a0, -1                ; clear the lowest
        and   a0, a0, t1                ; ...
        addi  t0, t0, 1                 ; ...
        j     pc_loop                   ; ...
pc_done:
        mv    a0, t0                    ; ...
        ret                             ; ...
u_gc_end:
