; =============================================================================
; db.s: atoms and predicates (a code unit)
; =============================================================================
;
; An atom is a record in the arena (atoms.s has its layout), found by name
; through a hash of NHASH chains at A_HASH. A predicate is a record in the
; clause store hanging off its name's atom (AT_PRED), one per arity.

        .far                            ; code units
        .align 4096                     ; ---- unit: atoms ----
u_atoms:

; atom_hash(a0 = D-LS name, a1 = length) -> a0 = chain index (leaf)
atom_hash:
        li    t0, 5381                  ; djb2
ah_loop:
        beqz  a1, ah_done               ; ...
        lbu   t1, 0(a0)                 ; ...
        slli  t2, t0, 5                 ; h * 33 + c
        add   t0, t0, t2                ; ...
        add   t0, t0, t1                ; ...
        addi  a0, a0, 1                 ; ...
        addi  a1, a1, -1                ; ...
        j     ah_loop                   ; ...
ah_done:
        andi  a0, t0, NHASH - 1         ; ...
        ret                             ; done

; atom_intern(a0 = D-LS name (8-byte aligned, room to pad), a1 = length)
; -> a0 = the atom cell (found, or made)
atom_intern:
        jalr  t6, gp, ent6-R            ; s1 name, s2 length, s3 chain head's offset, s4 record, s5 words, s6 i
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        li    t0, NAMEMAX               ; too long?
        bgtu  s2, t0, ai_long           ; ...
        add   t0, s1, s2                ; pad the name with zeros to a word
        addi  t1, s2, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        add   t1, s1, t1                ; ...
        addi  t1, t1, 8                 ; (and one more word: an empty name is one zero word)
ai_pad:
        bgeu  t0, t1, ai_padded         ; ...
        sb    zero, 0(t0)               ; ...
        addi  t0, t0, 1                 ; ...
        j     ai_pad                    ; ...
ai_padded:
        addi  s5, s2, 7                 ; words of name
        srli  s5, s5, 3                 ; ...
        mv    a0, s1                    ; the chain
        mv    a1, s2                    ; ...
        call  atom_hash                 ; ...
        slli  s3, a0, 3                 ; ...
        li    t0, A_HASH                ; ...
        add   s3, s3, t0                ; ...
        mv    a0, s3                    ; its first record
        jalr  ra, gp, mrd-R             ; ...
        mv    s4, a0                    ; ...
ai_look:
        beqz  s4, ai_new                ; not there
        addi  a0, s4, AT_LEN            ; same length?
        jalr  ra, gp, mrd-R             ; ...
        bne   a0, s2, ai_next           ; ...
        li    s6, 0                     ; same words?
ai_cmp:
        bgeu  s6, s5, ai_found          ; all equal
        slli  t0, s6, 3                 ; ...
        add   a0, s4, t0                ; ...
        addi  a0, a0, AT_NAME           ; ...
        jalr  ra, gp, mrd-R             ; ...
        slli  t0, s6, 3                 ; ...
        add   t0, s1, t0                ; ...
        ld    t0, 0(t0)                 ; ...
        bne   a0, t0, ai_next           ; ...
        addi  s6, s6, 1                 ; ...
        j     ai_cmp                    ; ...
ai_next:
        mv    a0, s4                    ; AT_NEXT
        jalr  ra, gp, mrd-R             ; ...
        mv    s4, a0                    ; ...
        j     ai_look                   ; ...
ai_found:
        addi  a0, s4, T_ATM             ; ...
        jalr  zero, gp, lv6-R           ; ...
ai_new:
        ld    s4, v_atop(zero)          ; a new record
        slli  t0, s5, 3                 ; ...
        addi  t0, t0, AT_NAME           ; ...
        add   t0, s4, t0                ; ...
        li    t1, A_ATOMEND             ; room?
        bgtu  t0, t1, ai_full           ; ...
        sd    t0, v_atop(zero)          ; ...
        mv    a0, s3                    ; AT_NEXT = the chain's head
        jalr  ra, gp, mrd-R             ; ...
        mv    a1, a0                    ; ...
        mv    a0, s4                    ; ...
        jalr  ra, gp, mwr-R             ; ...
        addi  a0, s4, AT_LEN            ; ...
        mv    a1, s2                    ; ...
        jalr  ra, gp, mwr-R             ; ...
        addi  a0, s4, AT_PRED           ; ...
        li    a1, 0                     ; ...
        jalr  ra, gp, mwr-R             ; ...
        addi  a0, s4, AT_OPS            ; ...
        li    a1, 0                     ; ...
        jalr  ra, gp, mwr-R             ; ...
        li    s6, 0                     ; the name's words
ai_copy:
        bgeu  s6, s5, ai_link           ; ...
        slli  t0, s6, 3                 ; ...
        add   t1, s1, t0                ; ...
        ld    a1, 0(t1)                 ; ...
        add   a0, s4, t0                ; ...
        addi  a0, a0, AT_NAME           ; ...
        jalr  ra, gp, mwr-R             ; ...
        addi  s6, s6, 1                 ; ...
        j     ai_copy                   ; ...
ai_link:
        mv    a0, s3                    ; the chain starts with it
        mv    a1, s4                    ; ...
        jalr  ra, gp, mwr-R             ; ...
        j     ai_found                  ; ...
ai_full:
        li    a0, at_atoms + T_ATM      ; resource_error(atoms)
        jalr  zero, gp, err_res-R       ; ...
ai_long:
        li    a0, at_too_long + T_ATM   ; ...
        jalr  zero, gp, err_syn-R       ; ...

; atom_hashin(a0 = record offset): put a predefined atom into its chain
atom_hashin:
        jalr  t6, gp, ent2-R            ; s1 record, s2 chain head
        mv    s1, a0                    ; ...
        addi  a0, s1, T_ATM             ; its name -> NB
        call  atom_name0                ; a0 = length
        mv    a1, a0                    ; ...
        li    a0, NB                    ; ...
        call  atom_hash                 ; ...
        slli  s2, a0, 3                 ; ...
        li    t0, A_HASH                ; ...
        add   s2, s2, t0                ; ...
        mv    a0, s2                    ; AT_NEXT = the head
        jalr  ra, gp, mrd-R             ; ...
        mv    a1, a0                    ; ...
        mv    a0, s1                    ; ...
        jalr  ra, gp, mwr-R             ; ...
        mv    a0, s2                    ; the head = it
        mv    a1, s1                    ; ...
        jalr  ra, gp, mwr-R             ; ...
        jalr  zero, gp, lv2-R           ; ...

; atom_name(a0 = atom cell) -> a0 = its length; the name in NB, then a zero byte
atom_name:
        jalr  t6, gp, ent0-R            ; ...
        call  atom_name0                ; ...
        jalr  zero, gp, lv0-R           ; ...
; atom_name0: the same, as a leaf of this unit
atom_name0:
        addi  sp, sp, -32               ; ...
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; s1 = record
        sd    s2, 16(sp)                ; s2 = length
        sd    s3, 24(sp)                ; s3 = word
        addi  s1, a0, -T_ATM            ; ...
        addi  a0, s1, AT_LEN            ; ...
        jalr  ra, gp, mrd-R             ; ...
        mv    s2, a0                    ; ...
        li    s3, 0                     ; ...
an_copy:
        slli  t0, s3, 3                 ; done?
        bgeu  t0, s2, anm_end            ; ...
        add   a0, s1, t0                ; ...
        addi  a0, a0, AT_NAME           ; ...
        jalr  ra, gp, mrd-R             ; ...
        slli  t0, s3, 3                 ; ...
        sd    a0, NB(t0)                ; ...
        addi  s3, s3, 1                 ; ...
        j     an_copy                   ; ...
anm_end:
        sb    zero, NB(s2)              ; ...
        mv    a0, s2                    ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; done

; pred_get(a0 = functor cell) -> a0 = its predicate, made if there is none
pred_get:
        jalr  t6, gp, ent2-R            ; s1 functor, s2 record
        mv    s1, a0                    ; ...
        jalr  ra, gp, pred_of-R         ; there?
        bnez  a0, pg_ret                ; ...
        li    a0, PRSZ                  ; a new one
        call  db_alloc0                 ; ...
        mv    s2, a0                    ; ...
        srli  a0, s1, 16                ; PR_NEXT = the atom's first
        slli  a0, a0, 3                 ; ...
        addi  a0, a0, AT_PRED           ; ...
        jalr  ra, gp, mrd-R             ; ...
        mv    a1, a0                    ; ...
        mv    a0, s2                    ; ...
        jalr  ra, gp, mwr-R             ; ...
        addi  a0, s2, PR_FUN            ; ...
        mv    a1, s1                    ; ...
        jalr  ra, gp, mwr-R             ; ...
        li    t3, 2                     ; the rest: zero
pg_zero:
        slli  a0, t3, 3                 ; ...
        add   a0, a0, s2                ; ...
        li    a1, 0                     ; ...
        jalr  ra, gp, mwr-R             ; (keeps t3)
        addi  t3, t3, 1                 ; ...
        li    t0, PRSZ / 8              ; ...
        bltu  t3, t0, pg_zero           ; ...
        addi  a0, s2, PR_ALL            ; on the list of all of them
        ld    a1, v_preds(zero)         ; ...
        jalr  ra, gp, mwr-R             ; ...
        sd    s2, v_preds(zero)         ; ...
        srli  a0, s1, 16                ; the atom's first is it
        slli  a0, a0, 3                 ; ...
        addi  a0, a0, AT_PRED           ; ...
        mv    a1, s2                    ; ...
        jalr  ra, gp, mwr-R             ; ...
        mv    a0, s2                    ; ...
pg_ret:
        jalr  zero, gp, lv2-R           ; ...

; db_alloc(a0 = bytes) -> a0 = their offset in the clause store
db_alloc:
        jalr  t6, gp, ent0-R            ; ...
        call  db_alloc0                 ; ...
        jalr  zero, gp, lv0-R           ; ...
db_alloc0:
        ld    t0, v_dbtop(zero)         ; ...
        add   t1, t0, a0                ; ...
        li    t2, A_DBEND               ; room?
        bgtu  t1, t2, da_full           ; ...
        sd    t1, v_dbtop(zero)         ; ...
        mv    a0, t0                    ; ...
        ret                             ; ...
da_full:
        li    a0, at_clauses + T_ATM    ; resource_error(clauses)
        jalr  zero, gp, err_res-R       ; ...

; set_ops(a0 = atom cell, a1 = kind 0 prefix / 1 infix / 2 postfix, a2 = priority | type << 12)
set_ops:
        jalr  t6, gp, ent3-R            ; s1 record field, s2 shift, s3 value
        addi  s1, a0, AT_OPS - T_ATM    ; ...
        slli  s2, a1, 4                 ; 16 bits a kind
        mv    s3, a2                    ; ...
        mv    a0, s1                    ; ...
        jalr  ra, gp, mrd-R             ; ...
        li    t0, 0xFFFF                ; clear the field
        sll   t0, t0, s2                ; ...
        li    t1, -1                    ; ...
        xor   t0, t0, t1                ; ...
        and   a0, a0, t0                ; ...
        sll   t1, s3, s2                ; the new value
        or    a1, a0, t1                ; ...
        mv    a0, s1                    ; ...
        jalr  ra, gp, mwr-R             ; ...
        jalr  zero, gp, lv3-R           ; ...

; get_ops(a0 = atom cell) -> a0 = its operator word
get_ops:
        jalr  t6, gp, ent0-R            ; ...
        addi  a0, a0, AT_OPS - T_ATM    ; ...
        jalr  ra, gp, mrd-R             ; ...
        jalr  zero, gp, lv0-R           ; ...

u_atoms_end:
