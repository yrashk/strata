; =============================================================================
; io.s: streams (a code unit)
; =============================================================================
;
; NSTREAM records in the D-LS (stralog.s has their layout), each with a
; buffer of SBUF bytes. Stream 0 is user_input (handle 0), 1 is user_output
; (handle 1: through sys.s's buffered output); the others are files opened
; by open/3 and text in the arena (boot.pl). A stream is the term
; '$stream'(N).

        .far                            ; code units
        .align 4096                     ; ---- unit: streams ----
u_io:

; srec(a0 = stream) -> a0 = its record (leaf)
srec:
        li    t0, SSZ                   ; ...
        mul   a0, a0, t0                ; ...
        addi  a0, a0, streams           ; ...
        ret                             ; ...

; io_init(): user_input and user_output
io_init:
        jalr  t6, gp, ent0-R            ; ...
        li    t0, streams               ; all free
        li    t1, streams + NSTREAM * SSZ ; ...
ii_clr:
        sd    zero, 0(t0)               ; ...
        addi  t0, t0, 8                 ; ...
        bltu  t0, t1, ii_clr            ; ...
        li    t0, streams               ; 0: input, handle 0
        li    t1, SK_IN                 ; ...
        sd    t1, S_KIND(t0)            ; ...
        li    t1, -2                    ; ...
        sd    t1, S_PEEK(t0)            ; ...
        li    t1, 1                     ; ...
        sd    t1, S_LINE(t0)            ; ...
        la    t0, sys_htab              ; is standard input the console (tty: register 3)?
        ld    t0, 0(t0)                 ; ...
        addi  t0, t0, -3                ; (the line editor puts the console into raw mode
        seqz  t0, t0                    ;   while a line is typed; a ws terminal's pipe
        sd    t0, v_tty(zero)           ;   brings the keys as they are)
        li    t0, streams + SSZ         ; 1: output, handle 1
        li    t1, SK_OUT                ; ...
        sd    t1, S_KIND(t0)            ; ...
        li    t1, 1                     ; ...
        sd    t1, S_HAND(t0)            ; ...
        jalr  zero, gp, lv0-R           ; ...

; getc(a0 = stream) -> a0 = the next character, -1 at the end
getc:
        jalr  t6, gp, ent2-R            ; s1 record, s2 stream
        mv    s2, a0                    ; ...
        call  srec                      ; ...
        mv    s1, a0                    ; ...
        ld    a0, S_PEEK(s1)            ; one pushed back?
        li    t0, -2                    ; ...
        beq   a0, t0, gc_buf            ; no
        sd    t0, S_PEEK(s1)            ; ...
        j     gc_ret                    ; ...
gc_buf:
        ld    t0, S_KIND(s1)            ; ...
        li    t1, SK_TEXT               ; text in the arena
        beq   t0, t1, gc_text           ; ...
        li    t1, SK_IN                 ; ...
        bne   t0, t1, gc_eof            ; not an input
gc_again:
        ld    t0, S_POS(s1)             ; anything buffered?
        ld    t1, S_LEN(s1)             ; ...
        bltu  t0, t1, gc_byte           ; ...
        ld    t0, S_EOF(s1)             ; the end was seen
        bnez  t0, gc_eof                ; ...
        bnez  s2, gc_read               ; user_input: show what was written first
        call  out_flush0                ; ...
gc_read:
        bnez  s2, gc_file               ; user_input: a line through the line editor
        la    t6, edit_line             ; ...
        xcall ra, c0, t6                ; ...
        sd    zero, S_POS(s1)           ; ...
        bgtz  a0, gc_got                ; ...
        li    t0, 1                     ; ...
        sd    t0, S_EOF(s1)             ; ...
        sd    zero, S_LEN(s1)           ; ...
        j     gc_eof                    ; ...
gc_file:
        ld    a0, S_HAND(s1)            ; ...
        li    a1, SBUF                  ; its buffer
        mul   a1, s2, a1                ; ...
        addi  a1, a1, sbufs             ; ...
        li    a2, SBUF                  ; ...
        jalr  ra, gp, sys_read-R        ; ...
        sd    zero, S_POS(s1)           ; ...
        bgtz  a0, gc_got                ; ...
        li    t0, 1                     ; the end (or an error)
        sd    t0, S_EOF(s1)             ; ...
        sd    zero, S_LEN(s1)           ; ...
        j     gc_eof                    ; ...
gc_got:
        sd    a0, S_LEN(s1)             ; ...
        j     gc_again                  ; ...
gc_byte:
        li    t1, SBUF                  ; ...
        mul   t1, s2, t1                ; ...
        add   t1, t1, t0                ; ...
        lbu   a0, sbufs(t1)             ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, S_POS(s1)             ; ...
        j     gc_count                  ; ...
gc_text:
        ld    a0, S_POS(s1)             ; ...
        ld    t1, S_LEN(s1)             ; ...
        bgeu  a0, t1, gc_eof            ; ...
        addi  t0, a0, 1                 ; ...
        sd    t0, S_POS(s1)             ; ...
        jalr  ra, gp, mrdb-R            ; ...
gc_count:
        li    t0, 10                    ; count lines
        bne   a0, t0, gc_ret            ; ...
        ld    t0, S_LINE(s1)            ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, S_LINE(s1)            ; ...
        j     gc_ret                    ; ...
gc_eof:
        li    a0, -1                    ; ...
gc_ret:
        jalr  zero, gp, lv2-R           ; ...

; ungetc(a0 = stream, a1 = character): the next getc answers it
ungetc:
        jalr  t6, gp, ent0-R            ; ...
        call  srec                      ; ...
        sd    a1, S_PEEK(a0)            ; ...
        jalr  zero, gp, lv0-R           ; ...

; out_flush0 (leaf): sys.s's buffered standard output goes out
out_flush0:
        addi  sp, sp, -8                ; ...
        sd    ra, 0(sp)                 ; ...
        jalr  ra, gp, out_flush-R       ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; putc(a0 = stream, a1 = character)
putc:
        jalr  t6, gp, ent2-R            ; s1 record, s2 stream
        mv    s2, a0                    ; ...
        call  srec                      ; ...
        mv    s1, a0                    ; ...
        li    t0, 1                     ; user_output: sys.s's buffer
        bne   s2, t0, pc_file           ; ...
        mv    a0, a1                    ; ...
        jalr  ra, gp, out_chr-R         ; ...
        jalr  zero, gp, lv2-R           ; ...
pc_file:
        ld    t0, S_KIND(s1)            ; an output file?
        li    t1, SK_OUT                ; ...
        bne   t0, t1, pc_ret            ; (anything else ignores it)
        ld    t0, S_POS(s1)             ; into its buffer
        li    t1, SBUF                  ; ...
        mul   t1, s2, t1                ; ...
        add   t1, t1, t0                ; ...
        sb    a1, sbufs(t1)             ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, S_POS(s1)             ; ...
        li    t1, SBUF                  ; full?
        bltu  t0, t1, pc_ret            ; ...
        mv    a0, s2                    ; ...
        call  sflush                    ; ...
pc_ret:
        jalr  zero, gp, lv2-R           ; ...

; sflush (leaf, a0 = stream): a file stream's buffer goes out
sflush:
        addi  sp, sp, -16               ; ...
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        li    t0, 1                     ; user_output
        bne   a0, t0, sf_file           ; ...
        call  out_flush0                ; ...
        j     sf_ret                    ; ...
sf_file:
        call  srec                      ; ...
        ld    t0, S_KIND(a0)            ; ...
        li    t1, SK_OUT                ; ...
        bne   t0, t1, sf_ret            ; ...
        ld    a2, S_POS(a0)             ; ...
        beqz  a2, sf_ret                ; ...
        sd    zero, S_POS(a0)           ; ...
        ld    t0, 8(sp)                 ; ...
        li    a1, SBUF                  ; ...
        mul   a1, t0, a1                ; ...
        addi  a1, a1, sbufs             ; ...
        ld    a0, S_HAND(a0)            ; ...
        jalr  ra, gp, sys_write-R       ; ...
sf_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; io_flush(a0 = stream)
io_flush:
        jalr  t6, gp, ent0-R            ; ...
        call  sflush                    ; ...
        jalr  zero, gp, lv0-R           ; ...

; io_flushall(): every output stream
io_flushall:
        jalr  t6, gp, ent1-R            ; s1 stream
        li    s1, 1                     ; ...
ifa_loop:
        mv    a0, s1                    ; ...
        call  sflush                    ; ...
        addi  s1, s1, 1                 ; ...
        li    t0, NSTREAM               ; ...
        bltu  s1, t0, ifa_loop          ; ...
        jalr  zero, gp, lv1-R           ; ...

; io_free() -> a0 = a free stream, or -1
io_free:
        li    a0, 2                     ; ...
if_loop:
        li    t0, NSTREAM               ; ...
        bgeu  a0, t0, if_none           ; ...
        li    t1, SSZ                   ; ...
        mul   t1, a0, t1                ; ...
        ld    t1, streams+S_KIND(t1)    ; ...
        beqz  t1, if_ret                ; ...
        addi  a0, a0, 1                 ; ...
        j     if_loop                   ; ...
if_none:
        li    a0, -1                    ; ...
if_ret:
        ret                             ; ...

; io_text(a0 = arena start, a1 = end) -> a0 = a stream reading that text
io_text:
        jalr  t6, gp, ent2-R            ; s1 start, s2 end
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        call  io_free                   ; ...
        bltz  a0, it_full               ; ...
        mv    t3, a0                    ; ...
        call  srec                      ; ...
        li    t0, SK_TEXT               ; ...
        sd    t0, S_KIND(a0)            ; ...
        sd    s1, S_POS(a0)             ; ...
        sd    s2, S_LEN(a0)             ; ...
        li    t0, 1                     ; ...
        sd    t0, S_LINE(a0)            ; ...
        li    t0, -2                    ; ...
        sd    t0, S_PEEK(a0)            ; ...
        sd    zero, S_EOF(a0)           ; ...
        mv    a0, t3                    ; ...
        jalr  zero, gp, lv2-R           ; ...
it_full:
        li    a0, at_stream + T_ATM     ; resource_error(stream)
        jalr  zero, gp, err_res-R       ; ...

; io_open(a0 = name length in NB, a1 = mode 0 read / 1 write / 2 append)
; -> a0 = a stream, or -1 if the file cannot be opened
io_open:
        jalr  t6, gp, ent3-R            ; s1 length, s2 mode, s3 stream
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        call  io_free                   ; ...
        bltz  a0, it_full               ; ...
        mv    s3, a0                    ; ...
        li    a0, NB                    ; ...
        mv    a1, s1                    ; ...
        mv    a2, s2                    ; ...
        jalr  ra, gp, sys_open-R        ; ...
        bltz  a0, io_fail               ; ...
        mv    t3, a0                    ; ...
        mv    a0, s3                    ; ...
        call  srec                      ; ...
        sd    t3, S_HAND(a0)            ; ...
        li    t0, SK_IN                 ; ...
        beqz  s2, io_kind               ; ...
        li    t0, SK_OUT                ; ...
io_kind:
        sd    t0, S_KIND(a0)            ; ...
        sd    zero, S_POS(a0)           ; ...
        sd    zero, S_LEN(a0)           ; ...
        sd    zero, S_EOF(a0)           ; ...
        li    t0, 1                     ; ...
        sd    t0, S_LINE(a0)            ; ...
        li    t0, -2                    ; ...
        sd    t0, S_PEEK(a0)            ; ...
        mv    a0, s3                    ; ...
        jalr  zero, gp, lv3-R           ; ...
io_fail:
        li    a0, -1                    ; ...
        jalr  zero, gp, lv3-R           ; ...

; io_close(a0 = stream)
io_close:
        jalr  t6, gp, ent1-R            ; s1 stream
        mv    s1, a0                    ; ...
        li    t0, 2                     ; the standard ones stay
        bltu  s1, t0, ic_ret            ; ...
        call  sflush                    ; ...
        mv    a0, s1                    ; ...
        call  srec                      ; ...
        mv    s1, a0                    ; ...
        ld    t0, S_KIND(s1)            ; a file: close its handle
        li    t1, SK_TEXT               ; ...
        beq   t0, t1, ic_free           ; ...
        beqz  t0, ic_ret                ; ...
        ld    a0, S_HAND(s1)            ; ...
        jalr  ra, gp, sys_close-R       ; ...
ic_free:
        sd    zero, S_KIND(s1)          ; ...
ic_ret:
        jalr  zero, gp, lv1-R           ; ...

; io_line(a0 = stream) -> a0 = its line number
io_line:
        jalr  t6, gp, ent0-R            ; ...
        call  srec                      ; ...
        ld    a0, S_LINE(a0)            ; ...
        jalr  zero, gp, lv0-R           ; ...
u_io_end:

        .align 4096                     ; ---- unit: the line editor ----
u_edit:

; edit_line() -> a0 = the bytes of a line put into user_input's buffer (with
; its newline), 0 at the end of the input. What is typed is echoed;
; Backspace (8, 127) rubs out, Ctrl-U the whole line, Ctrl-D on an empty line
; is the end, the arrows up and down go through the lines typed before. On
; the console the tty is raw while a line is typed; a ws terminal (a pipe)
; brings keys as they are.
edit_line:
        jalr  t6, gp, ent4-R            ; s1 length, s2 key, s3 history position, s4
        jalr  ra, gp, out_flush-R       ; the prompt first
        ld    t0, v_tty(zero)           ; ...
        beqz  t0, el_go                 ; ...
        li    a0, 1                     ; raw
        jalr  ra, gp, sys_conmode-R     ; ...
el_go:
        li    s1, 0                     ; ...
        ld    s3, v_hn(zero)            ; ...
el_key:
        call  keyget                    ; ...
        mv    s2, a0                    ; ...
        bltz  s2, el_end                ; the end of the input
        li    t0, 13                    ; Enter
        beq   s2, t0, el_cr             ; ...
        li    t0, 10                    ; ...
        beq   s2, t0, el_enter          ; ...
        li    t0, 8                     ; Backspace
        beq   s2, t0, el_rub            ; ...
        li    t0, 127                   ; ...
        beq   s2, t0, el_rub            ; ...
        li    t0, 21                    ; Ctrl-U
        beq   s2, t0, el_kill           ; ...
        li    t0, 4                     ; Ctrl-D
        beq   s2, t0, el_ctld           ; ...
        li    t0, 27                    ; Esc: an arrow?
        beq   s2, t0, el_esc            ; ...
        li    t0, 32                    ; other control characters: nothing
        bltu  s2, t0, el_key            ; ...
        li    t0, SBUF - 1              ; room?
        bgeu  s1, t0, el_key            ; ...
        sb    s2, sbufs(s1)             ; ...
        addi  s1, s1, 1                 ; ...
        mv    a0, s2                    ; ...
        call  echo                      ; ...
        j     el_key                    ; ...
el_cr:
        call  keypeek                   ; (a newline right after it is part of it)
        li    t0, 10                    ; ...
        bne   a0, t0, el_enter          ; ...
        call  keyget                    ; ...
el_enter:
        li    a0, 10                    ; ...
        call  echo                      ; ...
        call  hist_add                  ; ...
        li    t0, 10                    ; the line, and its newline
        sb    t0, sbufs(s1)             ; ...
        addi  s1, s1, 1                 ; ...
        j     el_done                   ; ...
el_rub:
        beqz  s1, el_key                ; ...
        call  rubout                    ; ...
        j     el_key                    ; ...
el_kill:
        beqz  s1, el_key                ; ...
        call  rubout                    ; ...
        j     el_kill                   ; ...
el_ctld:
        bnez  s1, el_key                ; only on an empty line
el_end:
        bnez  s1, el_enter              ; the end after some text: that text is a line
        li    a0, 10                    ; ...
        call  echo                      ; ...
el_done:
        ld    t0, v_tty(zero)           ; cooked again
        beqz  t0, el_ret                ; ...
        li    a0, 0                     ; ...
        jalr  ra, gp, sys_conmode-R     ; ...
el_ret:
        mv    a0, s1                    ; ...
        jalr  zero, gp, lv4-R           ; ...
el_esc:
        call  keyget                    ; ESC [ A / ESC [ B
        li    t0, '['                   ; ...
        bne   a0, t0, el_key            ; ...
        call  keyget                    ; ...
        li    t0, 'A'                   ; up: an older line
        beq   a0, t0, el_up             ; ...
        li    t0, 'B'                   ; down: a newer one
        bne   a0, t0, el_key            ; ...
        ld    t0, v_hn(zero)            ; ...
        bgeu  s3, t0, el_key            ; ...
        addi  s3, s3, 1                 ; ...
        call  recall                    ; ...
        j     el_key                    ; ...
el_up:
        beqz  s3, el_key                ; ...
        ld    t0, v_hn(zero)            ; (only the last NHIST are kept)
        sub   t0, t0, s3                ; ...
        li    t1, NHIST                 ; ...
        bgeu  t0, t1, el_key            ; ...
        addi  s3, s3, -1                ; ...
        call  recall                    ; ...
        j     el_key                    ; ...

; echo (leaf, a0 = character): shown at once
echo:
        addi  sp, sp, -8                ; ...
        sd    ra, 0(sp)                 ; ...
        jalr  ra, gp, out_chr-R         ; ...
        jalr  ra, gp, out_flush-R       ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; rubout (leaf): the last character goes, on the screen too
rubout:
        addi  sp, sp, -8                ; ...
        sd    ra, 0(sp)                 ; ...
        addi  s1, s1, -1                ; ...
        li    a0, 8                     ; back, space, back
        jalr  ra, gp, out_chr-R         ; ...
        li    a0, ' '                   ; ...
        jalr  ra, gp, out_chr-R         ; ...
        li    a0, 8                     ; ...
        call  echo                      ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; recall (leaf): the line becomes history line s3 (empty if s3 is the newest + 1)
recall:
        addi  sp, sp, -16               ; ...
        sd    ra, 0(sp)                 ; ...
rc_rub:
        beqz  s1, rc_copy               ; rub out what is there
        call  rubout                    ; ...
        j     rc_rub                    ; ...
rc_copy:
        ld    t0, v_hn(zero)            ; the newest + 1: empty
        bgeu  s3, t0, rc_done           ; ...
        andi  t0, s3, NHIST - 1         ; its slot
        slli  t1, t0, 3                 ; ...
        ld    t2, hist_len(t1)          ; ...
        sd    t2, 8(sp)                 ; ...
        slli  t0, t0, 7                 ; HLINE bytes a slot
        addi  s4, t0, hist              ; ...
rc_ch:
        ld    t2, 8(sp)                 ; ...
        bgeu  s1, t2, rc_done           ; ...
        add   t0, s4, s1                ; ...
        lbu   a0, 0(t0)                 ; ...
        sb    a0, sbufs(s1)             ; ...
        addi  s1, s1, 1                 ; ...
        call  echo                      ; ...
        j     rc_ch                     ; ...
rc_done:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; hist_add (leaf): the line (s1 bytes in sbufs) joins the history
hist_add:
        beqz  s1, ha_ret                ; not an empty one
        ld    t0, v_hn(zero)            ; its slot
        andi  t1, t0, NHIST - 1         ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, v_hn(zero)            ; ...
        mv    t2, s1                    ; at most HLINE bytes
        li    t3, HLINE                 ; ...
        bleu  t2, t3, ha_len            ; ...
        mv    t2, t3                    ; ...
ha_len:
        slli  t3, t1, 3                 ; ...
        sd    t2, hist_len(t3)          ; ...
        slli  t1, t1, 7                 ; ...
        addi  t1, t1, hist              ; ...
        li    t3, 0                     ; ...
ha_cp:
        bgeu  t3, t2, ha_ret            ; ...
        lbu   t4, sbufs(t3)             ; ...
        add   t5, t1, t3                ; ...
        sb    t4, 0(t5)                 ; ...
        addi  t3, t3, 1                 ; ...
        j     ha_cp                     ; ...
ha_ret:
        ret                             ; ...

; keyget (leaf) -> a0 = the next key, -1 at the end of the input; keypeek:
; the same, left there (-2 if none is waiting)
keyget:
        ld    t0, v_kpos(zero)          ; one waiting?
        ld    t1, v_klen(zero)          ; ...
        bltu  t0, t1, kg_take           ; ...
        addi  sp, sp, -8                ; read what there is
        sd    ra, 0(sp)                 ; ...
        li    a0, 0                     ; ...
        li    a1, kbuf                  ; ...
        li    a2, KBUF                  ; ...
        jalr  ra, gp, sys_read-R        ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        sd    zero, v_kpos(zero)        ; ...
        blez  a0, kg_end                ; ...
        sd    a0, v_klen(zero)          ; ...
        li    t0, 0                     ; ...
kg_take:
        lbu   a0, kbuf(t0)              ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, v_kpos(zero)          ; ...
        ret                             ; ...
kg_end:
        sd    zero, v_klen(zero)        ; ...
        li    a0, -1                    ; ...
        ret                             ; ...
keypeek:
        ld    t0, v_kpos(zero)          ; ...
        ld    t1, v_klen(zero)          ; ...
        li    a0, -2                    ; ...
        bgeu  t0, t1, kp_ret            ; ...
        lbu   a0, kbuf(t0)              ; ...
kp_ret:
        ret                             ; ...
u_edit_end:
