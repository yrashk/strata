; =============================================================================
; read.s: the reader (code units)
; =============================================================================
;
; read_term reads one clause, up to an end ('.' followed by layout), from a
; stream, and builds it on the heap. The tokenizer (u_lex) keeps one
; character of look-ahead in rd_ch; the parser (u_parse, u_prim) is
; operator precedence over the operator words of the atoms (AT_OPS) and
; recursive descent for everything else. A syntax error skips to the end of
; the clause and throws error(syntax_error(Message), _). Double-quoted text
; is a list of codes; there are no floats.
;
; Every function here that calls another unit is itself called with xcall
; (a unit may come back into another slot while it is away: only a far link
; finds it again). Plain `call` reaches only leaves that stay in the unit.

TK_ATOM  = 1                            ; tk_val: the atom
TK_VAR   = 2                            ; tk_val: its name (an atom); "_" alone: tk_val = 0
TK_INT   = 3                            ; tk_val: the value
TK_STR   = 4                            ; tk_val: the list of codes
TK_PUNCT = 5                            ; tk_val: ( ) [ ] { } , |
TK_END   = 6                            ; the end of a clause
TK_EOF   = 7                            ; the end of the stream
NVT      = 64                           ; variables in a clause
CL_LOW   = 1                            ; character classes (rd_ctab): a..z
CL_UP    = 2                            ; A..Z _
CL_DIG   = 3                            ; 0..9
CL_SYM   = 4                            ; + - * / \ ^ < > = ~ : . ? @ # & $
CL_SOLO  = 5                            ; ! ;
CL_PUN   = 6                            ; ( ) [ ] { } , |
CL_QUOTE = 7                            ; ' " `
CL_PCT   = 8                            ; %
MAXI     = 0x0FFFFFFFFFFFFFFF           ; the largest integer (61 bits)

        .data                           ; the reader's state
        .align 8                        ; ...
rd_s:     .dword 0                      ; the stream
rd_ch:    .dword -1                     ; the look-ahead character
tk:       .dword 0                      ; the token
tk_val:   .dword 0                      ; ...
tk_fn:    .dword 0                      ; a name directly followed by (
tk_lay:   .dword 0                      ; layout came before it
rd_nv:    .dword 0                      ; variables in the clause
rd_vt:    .space NVT * 16               ; the variables: name atom, variable
rd_ctab:                                ; character classes, 0..127 (0 layout, 9 not allowed)
        .byte 0, 9, 9, 9, 9, 9, 9, 9     ; 0..15 (tab, nl, vt, ff, cr: layout)
        .byte 9, 0, 0, 0, 0, 0, 9, 9     ; (continued)
        .byte 9, 9, 9, 9, 9, 9, 9, 9     ; 16..31
        .byte 9, 9, 9, 9, 9, 9, 9, 9     ; (continued)
        .byte 0, 5, 7, 4, 4, 8, 4, 7     ; space ! " # $ % & ' ( ) * + , - . /
        .byte 6, 6, 4, 4, 6, 4, 4, 4     ; (continued)
        .byte 3, 3, 3, 3, 3, 3, 3, 3     ; 0..9 : ; < = > ?
        .byte 3, 3, 4, 5, 4, 4, 4, 4     ; (continued)
        .byte 4, 2, 2, 2, 2, 2, 2, 2     ; @ A..O
        .byte 2, 2, 2, 2, 2, 2, 2, 2     ; (continued)
        .byte 2, 2, 2, 2, 2, 2, 2, 2     ; P..Z [ \ ] ^ _
        .byte 2, 2, 2, 6, 4, 6, 4, 2     ; (continued)
        .byte 7, 1, 1, 1, 1, 1, 1, 1     ; ` a..o
        .byte 1, 1, 1, 1, 1, 1, 1, 1     ; (continued)
        .byte 1, 1, 1, 1, 1, 1, 1, 1     ; p..z { | } ~ del
        .byte 1, 1, 1, 6, 6, 6, 4, 9     ; (continued)
esc_from: .ascii "ntrabfv\\'\"`es0"   ; the simple escapes ...
esc_to:   .byte 10, 9, 13, 7, 8, 12, 11, 0x5C ; ... what they mean
        .byte 0x27, 0x22, 0x60, 27, 32, 0 ; (continued)
NESC     = 14                           ; ...
        .align 8                        ; ...

        .far                            ; code units
        .align 4096                     ; ---- unit: the tokenizer ----
u_lex:

; cclass (leaf, a0 = character) -> a0 = its class; -1 at the end
cclass:
        bltz  a0, cc_ret                ; the end
        li    t0, 128                   ; beyond ASCII: a letter (lower case, as names go)
        bgeu  a0, t0, cc_hi             ; ...
        lbu   a0, rd_ctab(a0)           ; ...
cc_ret:
        ret                             ; ...
cc_hi:
        li    a0, CL_LOW                ; ...
        ret                             ; ...

; nextch() -> a0 = rd_ch = the next character of the stream
nextch:
        jalr  t6, gp, ent0-R            ; ...
        ld    a0, rd_s(zero)            ; ...
        la    t6, getc                  ; ...
        xcall ra, c0, t6                ; ...
        sd    a0, rd_ch(zero)           ; ...
        jalr  zero, gp, lv0-R           ; ...

; lx_err (a0 = message atom): a syntax error
lx_err:
        la    t6, syn_error             ; (does not return)
        xcall ra, c0, t6                ; ...

; alnum(a0 = its first character) -> a0 = the length of the name in NB: it
; and the letters, digits and _ after it
alnum:
        jalr  t6, gp, ent2-R            ; s1 character, s2 length
        mv    s1, a0                    ; ...
        li    s2, 0                     ; ...
al_loop:
        li    t0, NAMEMAX               ; ...
        bgeu  s2, t0, al_long           ; ...
        sb    s1, NB(s2)                ; ...
        addi  s2, s2, 1                 ; ...
        la    t6, nextch                ; ...
        xcall ra, c0, t6                ; ...
        mv    s1, a0                    ; ...
        call  cclass                    ; ...
        addi  a0, a0, -1                ; lower, upper, digit: classes 1..3
        sltiu a0, a0, 3                 ; ...
        bnez  a0, al_loop               ; ...
        mv    a0, s2                    ; ...
        jalr  zero, gp, lv2-R           ; ...
al_long:
        li    a0, at_too_long + T_ATM   ; ...
        j     lx_err                    ; ...

; escape(): rd_ch is the character after a backslash -> a0 = the character
; it means, -2 for a continued line, -1 if it is bad
escape:
        jalr  t6, gp, ent3-R            ; s1 value, s2 radix, s3 digits
        ld    t2, rd_ch(zero)           ; ...
        li    t1, 0                     ; the simple ones
es_find:
        li    t3, NESC                  ; ...
        bgeu  t1, t3, es_other          ; ...
        lbu   t3, esc_from(t1)          ; ...
        beq   t3, t2, es_simple         ; ...
        addi  t1, t1, 1                 ; ...
        j     es_find                   ; ...
es_simple:
        lbu   s1, esc_to(t1)            ; ...
        la    t6, nextch                ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s1                    ; ...
        jalr  zero, gp, lv3-R           ; ...
es_other:
        li    t0, 10                    ; a newline: the line goes on
        bne   t2, t0, es_x              ; ...
        la    t6, nextch                ; ...
        xcall ra, c0, t6                ; ...
        li    a0, -2                    ; ...
        jalr  zero, gp, lv3-R           ; ...
es_x:
        li    s2, 8                     ; \NNN\ octal or \xHH\ hexadecimal
        li    t0, 'x'                   ; ...
        bne   t2, t0, es_oct            ; ...
        li    s2, 16                    ; ...
        la    t6, nextch                ; ...
        xcall ra, c0, t6                ; ...
es_oct:
        li    s1, 0                     ; ...
        li    s3, 0                     ; digits seen
es_dig:
        ld    a0, rd_ch(zero)           ; ...
        mv    a1, s2                    ; ...
        call  digit                     ; ...
        bltz  a0, es_close              ; ...
        mul   s1, s1, s2                ; ...
        add   s1, s1, a0                ; ...
        addi  s3, s3, 1                 ; ...
        la    t6, nextch                ; ...
        xcall ra, c0, t6                ; ...
        j     es_dig                    ; ...
es_close:
        beqz  s3, es_bad                ; none
        ld    t0, rd_ch(zero)           ; the closing backslash
        li    t1, 0x5C                  ; ...
        bne   t0, t1, es_bad            ; ...
        la    t6, nextch                ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s1                    ; ...
        jalr  zero, gp, lv3-R           ; ...
es_bad:
        li    a0, -1                    ; ...
        jalr  zero, gp, lv3-R           ; ...

; digit (leaf, a0 = character, a1 = radix) -> a0 = its value, or -1
digit:
        li    t0, '0'                   ; ...
        sub   t1, a0, t0                ; ...
        li    t0, 10                    ; ...
        bltu  t1, t0, dg_got            ; 0..9
        ori   a0, a0, 0x20              ; a letter, either case
        li    t0, 'a'                   ; ...
        sub   t1, a0, t0                ; ...
        li    t0, 26                    ; ...
        bgeu  t1, t0, dg_no             ; ...
        addi  t1, t1, 10                ; ...
dg_got:
        bgeu  t1, a1, dg_no             ; not of this radix
        mv    a0, t1                    ; ...
        ret                             ; ...
dg_no:
        li    a0, -1                    ; ...
        ret                             ; ...

; token(): the next token into tk, tk_val, tk_fn, tk_lay
token:
        jalr  t6, gp, ent6-R            ; s1 character, s2 class, s3 length, s4 value, s5 radix, s6 quote
        sd    zero, tk_lay(zero)        ; ...
        sd    zero, tk_fn(zero)         ; ...
tk_skip:
        ld    s1, rd_ch(zero)           ; ...
        mv    a0, s1                    ; ...
        call  cclass                    ; ...
        mv    s2, a0                    ; ...
        bltz  s2, tk_eof                ; the end of the stream
        bnez  s2, tk_nolay              ; layout:
        li    t0, 1                     ; ...
        sd    t0, tk_lay(zero)          ; ...
        la    t6, nextch                ; ...
        xcall ra, c0, t6                ; ...
        j     tk_skip                   ; ...
tk_nolay:
        li    t0, CL_PCT                ; % comment: to the end of the line
        bne   s2, t0, tk_go             ; ...
tk_pct:
        la    t6, nextch                ; ...
        xcall ra, c0, t6                ; ...
        bltz  a0, tk_eof                ; ...
        li    t1, 10                    ; ...
        bne   a0, t1, tk_pct            ; ...
        li    t0, 1                     ; ...
        sd    t0, tk_lay(zero)          ; ...
        j     tk_skip                   ; ...
tk_eof:
        li    t0, TK_EOF                ; ...
        sd    t0, tk(zero)              ; ...
        jalr  zero, gp, lv6-R           ; ...
tk_go:
        li    t0, CL_DIG                ; ...
        beq   s2, t0, tk_num            ; ...
        li    t0, CL_LOW                ; ...
        beq   s2, t0, tk_name           ; ...
        li    t0, CL_UP                 ; ...
        beq   s2, t0, tk_var            ; ...
        li    t0, CL_SYM                ; ...
        beq   s2, t0, tk_sym            ; ...
        li    t0, CL_SOLO               ; ...
        beq   s2, t0, tk_solo           ; ...
        li    t0, CL_PUN                ; ...
        beq   s2, t0, tk_pun            ; ...
        li    t0, CL_QUOTE              ; ...
        beq   s2, t0, tk_quote          ; ...
        la    t6, nextch                ; (past it)
        xcall ra, c0, t6                ; ...
        li    a0, at_bad_char + T_ATM   ; ...
        j     lx_err                    ; ...

; ---- names: letters, digits, _ ----
tk_name:
        mv    a0, s1                    ; ...
        la    t6, alnum                 ; ...
        xcall ra, c0, t6                ; ...
        mv    s3, a0                    ; ...
tk_atom:
        li    a0, NB                    ; intern it
        mv    a1, s3                    ; ...
        la    t6, atom_intern           ; ...
        xcall ra, c0, t6                ; ...
        sd    a0, tk_val(zero)          ; ...
        li    t0, TK_ATOM               ; ...
        sd    t0, tk(zero)              ; ...
        ld    t0, rd_ch(zero)           ; functional notation: ( right after it
        li    t1, '('                   ; ...
        bne   t0, t1, tk_ret            ; ...
        li    t0, 1                     ; ...
        sd    t0, tk_fn(zero)           ; ...
tk_ret:
        jalr  zero, gp, lv6-R           ; ...
tk_var:
        mv    a0, s1                    ; ...
        la    t6, alnum                 ; ...
        xcall ra, c0, t6                ; ...
        mv    s3, a0                    ; ...
        li    t0, TK_VAR                ; ...
        sd    t0, tk(zero)              ; ...
        sd    zero, tk_val(zero)        ; "_": anonymous
        li    t0, 1                     ; ...
        bne   s3, t0, tk_vname          ; ...
        lbu   t0, NB(zero)              ; ...
        li    t1, '_'                   ; ...
        beq   t0, t1, tk_ret            ; ...
tk_vname:
        li    a0, NB                    ; ...
        mv    a1, s3                    ; ...
        la    t6, atom_intern           ; ...
        xcall ra, c0, t6                ; ...
        sd    a0, tk_val(zero)          ; ...
        jalr  zero, gp, lv6-R           ; ...

; ---- symbol atoms; the end; /* comments */ ----
tk_sym:
        li    s3, 0                     ; length
        li    t0, '.'                   ; '.' and then layout, %, or the end: the end of the clause
        bne   s1, t0, tk_sym2           ; ...
        la    t6, nextch                ; ...
        xcall ra, c0, t6                ; ...
        call  cclass                    ; ...
        blez  a0, tk_end                ; layout or the end
        li    t0, CL_PCT                ; ...
        beq   a0, t0, tk_end            ; ...
        li    s3, 1                     ; a symbol atom starting with .
        li    t0, '.'                   ; ...
        sb    t0, NB(zero)              ; ...
        j     tk_symc                   ; ...
tk_end:
        li    t0, TK_END                ; ...
        sd    t0, tk(zero)              ; ...
        jalr  zero, gp, lv6-R           ; ...
tk_sym2:
        li    t0, '/'                   ; /* comment?
        bne   s1, t0, tk_symn           ; ...
        la    t6, nextch                ; ...
        xcall ra, c0, t6                ; ...
        li    t1, '*'                   ; ...
        bne   a0, t1, tk_slash          ; ...
        la    t6, nextch                ; inside the comment
        xcall ra, c0, t6                ; ...
tk_cmt:
        ld    s1, rd_ch(zero)           ; ...
        bltz  s1, tk_eof                ; ...
        la    t6, nextch                ; ...
        xcall ra, c0, t6                ; ...
        li    t1, '*'                   ; */ ends it
        bne   s1, t1, tk_cmt            ; ...
        li    t1, '/'                   ; ...
        bne   a0, t1, tk_cmt            ; ...
        la    t6, nextch                ; ...
        xcall ra, c0, t6                ; ...
        li    t0, 1                     ; ...
        sd    t0, tk_lay(zero)          ; ...
        j     tk_skip                   ; ...
tk_slash:
        li    s3, 1                     ; a symbol atom starting with /
        li    t0, '/'                   ; ...
        sb    t0, NB(zero)              ; ...
        j     tk_symc                   ; ...
tk_symn:
        li    t0, NAMEMAX               ; ...
        bgeu  s3, t0, al_long           ; ...
        sb    s1, NB(s3)                ; ...
        addi  s3, s3, 1                 ; ...
        la    t6, nextch                ; ...
        xcall ra, c0, t6                ; ...
tk_symc:
        ld    s1, rd_ch(zero)           ; more symbol characters?
        mv    a0, s1                    ; ...
        call  cclass                    ; ...
        li    t0, CL_SYM                ; ...
        beq   a0, t0, tk_symn           ; ...
        j     tk_atom                   ; ...

; ---- ! ; (solo atoms); punctuation ----
tk_solo:
        sb    s1, NB(zero)              ; ...
        li    s3, 1                     ; ...
        la    t6, nextch                ; ...
        xcall ra, c0, t6                ; ...
        j     tk_atom                   ; ...
tk_pun:
        sd    s1, tk_val(zero)          ; ...
        li    t0, TK_PUNCT              ; ...
        sd    t0, tk(zero)              ; ...
        la    t6, nextch                ; ...
        xcall ra, c0, t6                ; ...
        jalr  zero, gp, lv6-R           ; ...

; ---- numbers ----
tk_num:
        li    s4, 0                     ; the value
        li    s5, 10                    ; decimal unless 0' 0x 0o 0b
        li    t0, '0'                   ; ...
        bne   s1, t0, tk_digits         ; ...
        la    t6, nextch                ; ...
        xcall ra, c0, t6                ; ...
        mv    s1, a0                    ; ...
        li    t0, 0x27                  ; 0'c: a character code
        beq   s1, t0, tk_code           ; ...
        li    s5, 16                    ; ...
        li    t0, 'x'                   ; ...
        beq   s1, t0, tk_radix          ; ...
        li    s5, 8                     ; ...
        li    t0, 'o'                   ; ...
        beq   s1, t0, tk_radix          ; ...
        li    s5, 2                     ; ...
        li    t0, 'b'                   ; ...
        beq   s1, t0, tk_radix          ; ...
        li    s5, 10                    ; ...
tk_digits:
        mv    a0, s1                    ; a digit of radix s5?
        mv    a1, s5                    ; ...
        call  digit                     ; ...
        bltz  a0, tk_numend             ; no
        mul   s4, s4, s5                ; ...
        add   s4, s4, a0                ; ...
        li    t0, MAXI                  ; too large?
        bgtu  s4, t0, tk_badnum         ; ...
        la    t6, nextch                ; ...
        xcall ra, c0, t6                ; ...
        mv    s1, a0                    ; ...
        j     tk_digits                 ; ...
tk_numend:
        li    t0, '.'                   ; 1.5: floats are not supported
        bne   s1, t0, tk_int            ; ...
        li    t0, 10                    ; (only after decimal digits)
        bne   s5, t0, tk_int            ; ...
        ld    a0, rd_s(zero)            ; look past the dot
        la    t6, getc                  ; ...
        xcall ra, c0, t6                ; ...
        mv    s6, a0                    ; ...
        mv    a1, a0                    ; and push it back
        ld    a0, rd_s(zero)            ; ...
        la    t6, ungetc                ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s6                    ; a digit after the dot: a float
        call  cclass                    ; ...
        li    t0, CL_DIG                ; ...
        beq   a0, t0, tk_badnum         ; ...
tk_int:
        sd    s4, tk_val(zero)          ; ...
        li    t0, TK_INT                ; ...
        sd    t0, tk(zero)              ; ...
        jalr  zero, gp, lv6-R           ; ...
tk_radix:
        la    t6, nextch                ; past the letter
        xcall ra, c0, t6                ; ...
        mv    s1, a0                    ; ...
        mv    a1, s5                    ; at least one digit
        call  digit                     ; ...
        bltz  a0, tk_badnum             ; ...
        j     tk_digits                 ; ...
tk_code:
        la    t6, nextch                ; the character
        xcall ra, c0, t6                ; ...
        mv    s1, a0                    ; ...
        bltz  s1, tk_badnum             ; ...
        li    t0, 0x5C                  ; an escape
        beq   s1, t0, tk_cesc           ; ...
        la    t6, nextch                ; ...
        xcall ra, c0, t6                ; ...
        li    t0, 0x27                  ; '' : the quote itself
        bne   s1, t0, tk_cval           ; ...
        li    t1, 0x27                  ; ...
        bne   a0, t1, tk_cval           ; ...
        la    t6, nextch                ; ...
        xcall ra, c0, t6                ; ...
tk_cval:
        mv    s4, s1                    ; ...
        j     tk_int                    ; ...
tk_cesc:
        la    t6, nextch                ; ...
        xcall ra, c0, t6                ; ...
        la    t6, escape                ; ...
        xcall ra, c0, t6                ; ...
        bltz  a0, tk_badnum             ; ...
        mv    s4, a0                    ; ...
        j     tk_int                    ; ...
tk_badnum:
        li    a0, at_bad_number + T_ATM ; ...
        j     lx_err                    ; ...

; ---- quoted: 'atom', "codes", `codes` ----
tk_quote:
        mv    s6, s1                    ; the quote
        li    s3, 0                     ; length
        la    t6, nextch                ; ...
        xcall ra, c0, t6                ; ...
tq_loop:
        ld    s1, rd_ch(zero)           ; ...
        bltz  s1, tq_unterm             ; ...
        la    t6, nextch                ; ...
        xcall ra, c0, t6                ; ...
        bne   s1, s6, tq_esc            ; the quote: doubled, or the end
        bne   a0, s6, tq_done           ; ...
        la    t6, nextch                ; doubled: one of it
        xcall ra, c0, t6                ; ...
        j     tq_put                    ; ...
tq_esc:
        li    t0, 0x5C                  ; a backslash
        bne   s1, t0, tq_put            ; ...
        la    t6, escape                ; ...
        xcall ra, c0, t6                ; ...
        li    t0, -2                    ; a continued line: nothing
        beq   a0, t0, tq_loop           ; ...
        bltz  a0, tq_badesc             ; ...
        mv    s1, a0                    ; ...
tq_put:
        li    t0, NAMEMAX               ; ...
        bgeu  s3, t0, al_long           ; ...
        sb    s1, NB(s3)                ; ...
        addi  s3, s3, 1                 ; ...
        j     tq_loop                   ; ...
tq_done:
        li    t0, 0x27                  ; 'atom'
        beq   s6, t0, tk_atom           ; ...
        li    s4, at_nil + T_ATM        ; "codes": the list, from the last
tq_build:
        beqz  s3, tq_built              ; ...
        addi  s3, s3, -1                ; ...
        lbu   a1, NB(s3)                ; ...
        slli  a1, a1, 3                 ; ...
        ori   a1, a1, T_INT             ; ...
        mv    a2, s4                    ; ...
        li    a0, ((at_dot >> 3) << 16) | (2 << 3) | T_FUN ; ...
        jalr  ra, gp, mkstr-R           ; ...
        mv    s4, a0                    ; ...
        j     tq_build                  ; ...
tq_built:
        sd    s4, tk_val(zero)          ; ...
        li    t0, TK_STR                ; ...
        sd    t0, tk(zero)              ; ...
        jalr  zero, gp, lv6-R           ; ...
tq_unterm:
        li    a0, at_bad_quote + T_ATM  ; ...
        j     lx_err                    ; ...
tq_badesc:
        li    a0, at_bad_escape + T_ATM ; ...
        j     lx_err                    ; ...
u_lex_end:

        .align 4096                     ; ---- unit: the parser ----
u_parse:

; read_term(a0 = stream) -> a0 = the clause (end_of_file at the end), a1 =
; its variable names as Name = Var pairs
read_term:
        jalr  t6, gp, ent2-R            ; s1 the term, s2 names
        sd    a0, rd_s(zero)            ; ...
        sd    zero, rd_nv(zero)         ; ...
        la    t6, nextch                ; the first character
        xcall ra, c0, t6                ; ...
        la    t6, token                 ; the first token
        xcall ra, c0, t6                ; ...
        ld    t0, tk(zero)              ; the end of the stream: end_of_file
        li    t1, TK_EOF                ; ...
        bne   t0, t1, rt_term           ; ...
        li    s1, at_eof + T_ATM        ; ...
        li    s2, at_nil + T_ATM        ; ...
        j     rt_ret                    ; ...
rt_term:
        li    a0, 1200                  ; ...
        la    t6, parse                 ; ...
        xcall ra, c0, t6                ; ...
        mv    s1, a0                    ; ...
        ld    t0, tk(zero)              ; the end must follow
        li    t1, TK_END                ; ...
        beq   t0, t1, rt_names          ; ...
        li    a0, at_bad_op + T_ATM     ; operator expected
        la    t6, syn_error             ; ...
        xcall ra, c0, t6                ; ...
rt_names:
        li    s2, at_nil + T_ATM        ; Name = Var, in order
        ld    t3, rd_nv(zero)           ; ...
rt_nloop:
        beqz  t3, rt_ret                ; ...
        addi  t3, t3, -1                ; ...
        sd    t3, v_tmp+24(zero)        ; ...
        slli  t0, t3, 4                 ; ...
        ld    a1, rd_vt(t0)             ; ...
        ld    a2, rd_vt+8(t0)           ; ...
        li    a0, ((at_eq >> 3) << 16) | (2 << 3) | T_FUN ; ...
        jalr  ra, gp, mkstr-R           ; ...
        mv    a1, a0                    ; ...
        mv    a2, s2                    ; ...
        li    a0, ((at_dot >> 3) << 16) | (2 << 3) | T_FUN ; ...
        jalr  ra, gp, mkstr-R           ; ...
        mv    s2, a0                    ; ...
        ld    t3, v_tmp+24(zero)        ; ...
        j     rt_nloop                  ; ...
rt_ret:
        ld    t0, rd_ch(zero)           ; a character read past the end goes back
        bltz  t0, rt_out                ; ...
        li    t1, 32                    ; (layout after the end is used up)
        bleu  t0, t1, rt_out            ; ...
        ld    a0, rd_s(zero)            ; ...
        mv    a1, t0                    ; ...
        la    t6, ungetc                ; ...
        xcall ra, c0, t6                ; ...
rt_out:
        mv    a0, s1                    ; ...
        mv    a1, s2                    ; ...
        jalr  zero, gp, lv2-R           ; ...

; syn_error(a0 = message): skip to the end of the clause, then throw
syn_error:
        jalr  t6, gp, ent1-R            ; s1 message
        mv    s1, a0                    ; ...
se_skip:
        ld    t0, tk(zero)              ; ...
        li    t1, TK_END                ; ...
        beq   t0, t1, se_throw          ; ...
        li    t1, TK_EOF                ; ...
        beq   t0, t1, se_throw          ; ...
        la    t6, token                 ; ...
        xcall ra, c0, t6                ; ...
        j     se_skip                   ; ...
se_throw:
        mv    a0, s1                    ; ...
        jalr  zero, gp, err_syn-R       ; ...

; parse(a0 = the highest priority allowed) -> a0 = the term, a1 = its priority
parse:
        jalr  t6, gp, ent6-R            ; s1 max, s2 left, s3 its priority, s4 operator atom, s5 ops, s6 priority
        mv    s1, a0                    ; ...
        li    t0, SPMIN + 256           ; deep enough?
        bltu  sp, t0, pa_deep           ; ...
        la    t6, primary               ; ...
        xcall ra, c0, t6                ; ...
        mv    s2, a0                    ; ...
        mv    s3, a1                    ; ...
pa_loop:
        ld    t0, tk(zero)              ; an infix or postfix operator?
        li    t1, TK_ATOM               ; ...
        beq   t0, t1, pa_atom           ; ...
        li    t1, TK_PUNCT              ; , and |
        bne   t0, t1, pa_done           ; ...
        ld    t0, tk_val(zero)          ; ...
        li    t1, ','                   ; ...
        li    s4, at_comma + T_ATM      ; ...
        beq   t0, t1, pa_ops            ; ...
        li    t1, '|'                   ; | as an infix operator is ;
        li    s4, at_bar + T_ATM        ; ...
        beq   t0, t1, pa_ops            ; ...
        j     pa_done                   ; ...
pa_atom:
        ld    s4, tk_val(zero)          ; ...
pa_ops:
        mv    a0, s4                    ; ...
        la    t6, get_ops               ; ...
        xcall ra, c0, t6                ; ...
        mv    s5, a0                    ; ...
        srli  t0, s5, 16                ; infix
        li    t1, 0xFFFF                ; ...
        and   t0, t0, t1                ; ...
        beqz  t0, pa_post               ; ...
        andi  s6, t0, 0x7FF             ; priority
        srli  t2, t0, 12                ; type
        bgtu  s6, s1, pa_post           ; too high here
        addi  t3, s6, -1                ; the left side's limit
        li    t4, OPT_YFX               ; ...
        bne   t2, t4, pa_l              ; ...
        mv    t3, s6                    ; ...
pa_l:
        bgtu  s3, t3, pa_post           ; the left side binds too loosely
        addi  t3, s6, -1                ; the right side's limit
        li    t4, OPT_XFY               ; ...
        bne   t2, t4, pa_r              ; ...
        mv    t3, s6                    ; ...
pa_r:
        sd    t3, v_tmp+24(zero)        ; ...
        la    t6, token                 ; past the operator
        xcall ra, c0, t6                ; ...
        ld    a0, v_tmp+24(zero)        ; the right side
        la    t6, parse                 ; ...
        xcall ra, c0, t6                ; ...
        mv    a2, a0                    ; Op(Left, Right)
        mv    a1, s2                    ; ...
        li    t0, at_bar + T_ATM        ; (| makes ;)
        bne   s4, t0, pa_mk             ; ...
        li    s4, at_semi + T_ATM       ; ...
pa_mk:
        srli  a0, s4, 3                 ; ...
        slli  a0, a0, 16                ; ...
        ori   a0, a0, (2 << 3) | T_FUN  ; ...
        jalr  ra, gp, mkstr-R           ; ...
        mv    s2, a0                    ; ...
        mv    s3, s6                    ; ...
        j     pa_loop                   ; ...
pa_post:
        srli  t0, s5, 32                ; postfix
        li    t1, 0xFFFF                ; ...
        and   t0, t0, t1                ; ...
        beqz  t0, pa_done               ; ...
        andi  s6, t0, 0x7FF             ; ...
        srli  t2, t0, 12                ; ...
        bgtu  s6, s1, pa_done           ; ...
        addi  t3, s6, -1                ; ...
        li    t4, OPT_YF                ; ...
        bne   t2, t4, pa_pl             ; ...
        mv    t3, s6                    ; ...
pa_pl:
        bgtu  s3, t3, pa_done           ; ...
        la    t6, token                 ; ...
        xcall ra, c0, t6                ; ...
        mv    a1, s2                    ; Op(Left)
        srli  a0, s4, 3                 ; ...
        slli  a0, a0, 16                ; ...
        ori   a0, a0, (1 << 3) | T_FUN  ; ...
        jalr  ra, gp, mkstr-R           ; ...
        mv    s2, a0                    ; ...
        mv    s3, s6                    ; ...
        j     pa_loop                   ; ...
pa_done:
        mv    a0, s2                    ; ...
        mv    a1, s3                    ; ...
        jalr  zero, gp, lv6-R           ; ...
pa_deep:
        li    a0, at_term_depth + T_ATM ; ...
        la    t6, syn_error             ; ...
        xcall ra, c0, t6                ; ...

; can_start() -> a0 = 1 if the token can begin a term
can_start:
        jalr  t6, gp, ent0-R            ; ...
        ld    t0, tk(zero)              ; ...
        li    t1, TK_PUNCT              ; ...
        beq   t0, t1, cs_pun            ; ...
        li    t1, TK_END                ; ...
        beq   t0, t1, cs_no             ; ...
        li    t1, TK_EOF                ; ...
        beq   t0, t1, cs_no             ; ...
        li    t1, TK_ATOM               ; an atom that is only an infix operator does not
        bne   t0, t1, cs_yes            ; ...
        ld    t0, tk_fn(zero)           ; (unless it is f(...))
        bnez  t0, cs_yes                ; ...
        ld    a0, tk_val(zero)          ; ...
        la    t6, get_ops               ; ...
        xcall ra, c0, t6                ; ...
        li    t1, 0xFFFF                ; prefix: yes
        and   t0, a0, t1                ; ...
        bnez  t0, cs_yes                ; ...
        srli  t0, a0, 16                ; infix or postfix: no
        bnez  t0, cs_no                 ; ...
        j     cs_yes                    ; ...
cs_pun:
        ld    t0, tk_val(zero)          ; ( [ { begin terms
        li    t1, '('                   ; ...
        beq   t0, t1, cs_yes            ; ...
        li    t1, '['                   ; ...
        beq   t0, t1, cs_yes            ; ...
        li    t1, '{'                   ; ...
        beq   t0, t1, cs_yes            ; ...
cs_no:
        li    a0, 0                     ; ...
        jalr  zero, gp, lv0-R           ; ...
cs_yes:
        li    a0, 1                     ; ...
        jalr  zero, gp, lv0-R           ; ...

; expect(a0 = punctuation character, a1 = message): it must come next
expect:
        jalr  t6, gp, ent0-R            ; ...
        ld    t0, tk(zero)              ; ...
        li    t1, TK_PUNCT              ; ...
        bne   t0, t1, ex_bad            ; ...
        ld    t0, tk_val(zero)          ; ...
        bne   t0, a0, ex_bad            ; ...
        la    t6, token                 ; ...
        xcall ra, c0, t6                ; ...
        jalr  zero, gp, lv0-R           ; ...
ex_bad:
        mv    a0, a1                    ; ...
        la    t6, syn_error             ; ...
        xcall ra, c0, t6                ; ...
u_parse_end:

        .align 4096                     ; ---- unit: primaries ----
u_prim:

; perr (a0 = message): a syntax error from here
perr:
        la    t6, syn_error             ; (does not return)
        xcall ra, c0, t6                ; ...

; primary(a0 = the highest priority allowed) -> a0 = a term, a1 = its priority
primary:
        jalr  t6, gp, ent6-R            ; s1 max, s2 term, s3 atom, s4 ops, s5 n, s6
        mv    s1, a0                    ; ...
        ld    t0, tk(zero)              ; ...
        li    t1, TK_INT                ; ...
        beq   t0, t1, pr_int            ; ...
        li    t1, TK_VAR                ; ...
        beq   t0, t1, pr_var            ; ...
        li    t1, TK_STR                ; ...
        beq   t0, t1, pr_str            ; ...
        li    t1, TK_ATOM               ; ...
        beq   t0, t1, pr_atom           ; ...
        li    t1, TK_PUNCT              ; ...
        bne   t0, t1, pr_bad            ; ...
        ld    t0, tk_val(zero)          ; ...
        li    t1, '('                   ; ...
        beq   t0, t1, pr_paren          ; ...
        li    t1, '['                   ; ...
        beq   t0, t1, pr_list           ; ...
        li    t1, '{'                   ; ...
        beq   t0, t1, pr_curly          ; ...
pr_bad:
        li    a0, at_bad_term + T_ATM   ; ...
        j     perr                      ; ...
pr_int:
        ld    t0, tk_val(zero)          ; ...
        slli  s2, t0, 3                 ; ...
        ori   s2, s2, T_INT             ; ...
pr_next0:
        la    t6, token                 ; ...
        xcall ra, c0, t6                ; ...
pr_ret0:
        li    a1, 0                     ; ...
pr_ret:
        mv    a0, s2                    ; ...
        jalr  zero, gp, lv6-R           ; ...
pr_str:
        ld    s2, tk_val(zero)          ; ...
        j     pr_next0                  ; ...
pr_var:
        ld    s3, tk_val(zero)          ; the name; 0: _
        beqz  s3, pr_anon               ; ...
        li    s5, 0                     ; seen before?
pr_vfind:
        ld    t0, rd_nv(zero)           ; ...
        bgeu  s5, t0, pr_vnew           ; ...
        slli  t0, s5, 4                 ; ...
        ld    t1, rd_vt(t0)             ; ...
        beq   t1, s3, pr_vold           ; ...
        addi  s5, s5, 1                 ; ...
        j     pr_vfind                  ; ...
pr_vold:
        slli  t0, s5, 4                 ; ...
        ld    s2, rd_vt+8(t0)           ; ...
        j     pr_next0                  ; ...
pr_vnew:
        li    t1, NVT                   ; room?
        bgeu  s5, t1, pr_vfull          ; ...
        jalr  ra, gp, mkvar-R           ; ...
        mv    s2, a0                    ; ...
        slli  t0, s5, 4                 ; ...
        sd    s3, rd_vt(t0)             ; ...
        sd    s2, rd_vt+8(t0)           ; ...
        addi  s5, s5, 1                 ; ...
        sd    s5, rd_nv(zero)           ; ...
        j     pr_next0                  ; ...
pr_anon:
        jalr  ra, gp, mkvar-R           ; ...
        mv    s2, a0                    ; ...
        j     pr_next0                  ; ...
pr_vfull:
        li    a0, at_too_many_vars + T_ATM ; ...
        j     perr                      ; ...
pr_paren:
        la    t6, token                 ; ( Term )
        xcall ra, c0, t6                ; ...
        li    a0, 1200                  ; ...
        la    t6, parse                 ; ...
        xcall ra, c0, t6                ; ...
        mv    s2, a0                    ; ...
        li    a0, ')'                   ; ...
        li    a1, at_bad_paren + T_ATM  ; ...
        la    t6, expect                ; ...
        xcall ra, c0, t6                ; ...
        j     pr_ret0                   ; ...
pr_curly:
        la    t6, token                 ; { Term } or {}
        xcall ra, c0, t6                ; ...
        ld    t0, tk(zero)              ; ...
        li    t1, TK_PUNCT              ; ...
        bne   t0, t1, pr_cterm          ; ...
        ld    t0, tk_val(zero)          ; ...
        li    t1, '}'                   ; ...
        bne   t0, t1, pr_cterm          ; ...
        li    s2, at_curly + T_ATM      ; {}
        j     pr_next0                  ; ...
pr_cterm:
        li    a0, 1200                  ; ...
        la    t6, parse                 ; ...
        xcall ra, c0, t6                ; ...
        mv    a1, a0                    ; ...
        li    a0, ((at_curly >> 3) << 16) | (1 << 3) | T_FUN ; ...
        jalr  ra, gp, mkstr-R           ; ...
        mv    s2, a0                    ; ...
        li    a0, '}'                   ; ...
        li    a1, at_bad_curly + T_ATM  ; ...
        la    t6, expect                ; ...
        xcall ra, c0, t6                ; ...
        j     pr_ret0                   ; ...
pr_list:
        la    t6, token                 ; [ ... ]
        xcall ra, c0, t6                ; ...
        ld    t0, tk(zero)              ; [] ?
        li    t1, TK_PUNCT              ; ...
        bne   t0, t1, pr_items          ; ...
        ld    t0, tk_val(zero)          ; ...
        li    t1, ']'                   ; ...
        bne   t0, t1, pr_items          ; ...
        li    s2, at_nil + T_ATM        ; ...
        j     pr_next0                  ; ...
pr_items:
        li    s2, 0                     ; the list
        li    s6, 0                     ; its last pair
pr_item:
        li    a0, 999                   ; an element
        la    t6, parse                 ; ...
        xcall ra, c0, t6                ; ...
        mv    a1, a0                    ; [E | []]
        li    a0, ((at_dot >> 3) << 16) | (2 << 3) | T_FUN ; ...
        li    a2, at_nil + T_ATM        ; ...
        jalr  ra, gp, mkstr-R           ; ...
        mv    s5, a0                    ; ...
        bnez  s6, pr_ilink              ; ...
        mv    s2, s5                    ; ...
        j     pr_ilinked                ; ...
pr_ilink:
        addi  a0, s6, 16 - T_STR        ; ...
        mv    a1, s5                    ; ...
        jalr  ra, gp, mwr-R             ; ...
pr_ilinked:
        mv    s6, s5                    ; ...
        ld    t0, tk(zero)              ; , | ]
        li    t1, TK_PUNCT              ; ...
        bne   t0, t1, pr_lbad           ; ...
        ld    t0, tk_val(zero)          ; ...
        li    t1, ','                   ; ...
        bne   t0, t1, pr_lbar           ; ...
        la    t6, token                 ; ...
        xcall ra, c0, t6                ; ...
        j     pr_item                   ; ...
pr_lbar:
        li    t1, '|'                   ; ...
        bne   t0, t1, pr_lend           ; ...
        la    t6, token                 ; the tail
        xcall ra, c0, t6                ; ...
        li    a0, 999                   ; ...
        la    t6, parse                 ; ...
        xcall ra, c0, t6                ; ...
        mv    a1, a0                    ; ...
        addi  a0, s6, 16 - T_STR        ; ...
        jalr  ra, gp, mwr-R             ; ...
pr_lend:
        li    a0, ']'                   ; ...
        li    a1, at_bad_list + T_ATM   ; ...
        la    t6, expect                ; ...
        xcall ra, c0, t6                ; ...
        j     pr_ret0                   ; ...
pr_lbad:
        li    a0, at_bad_list + T_ATM   ; ...
        j     perr                      ; ...

pr_atom:
        ld    s3, tk_val(zero)          ; the atom
        ld    t0, tk_fn(zero)           ; name( ... ): a compound
        bnez  t0, pr_compound           ; ...
        la    t6, token                 ; look at what follows
        xcall ra, c0, t6                ; ...
        li    t0, at_minus + T_ATM      ; - and a number right after it: a negative number
        bne   s3, t0, pr_prefix         ; ...
        ld    t0, tk(zero)              ; ...
        li    t1, TK_INT                ; ...
        bne   t0, t1, pr_prefix         ; ...
        ld    t0, tk_lay(zero)          ; ...
        bnez  t0, pr_prefix             ; ...
        ld    t0, tk_val(zero)          ; ...
        sub   t0, zero, t0              ; ...
        slli  s2, t0, 3                 ; ...
        ori   s2, s2, T_INT             ; ...
        j     pr_next0                  ; ...
pr_prefix:
        mv    a0, s3                    ; a prefix operator?
        la    t6, get_ops               ; ...
        xcall ra, c0, t6                ; ...
        li    t1, 0xFFFF                ; ...
        and   s4, a0, t1                ; ...
        mv    s2, s3                    ; (otherwise the atom alone)
        beqz  s4, pr_ret0               ; no
        la    t6, can_start             ; an operand follows?
        xcall ra, c0, t6                ; ...
        beqz  a0, pr_alone              ; no: the atom
        andi  s5, s4, 0x7FF             ; priority
        bleu  s5, s1, pr_pok            ; too high for here: take 999
        li    s5, 999                   ; ...
        bgtu  s5, s1, pr_alone          ; ...
pr_pok:
        srli  t2, s4, 12                ; type
        addi  a0, s5, -1                ; fx: the operand's limit is one less
        li    t3, OPT_FY                ; ...
        bne   t2, t3, pr_pfx            ; ...
        mv    a0, s5                    ; ...
pr_pfx:
        la    t6, parse                 ; ...
        xcall ra, c0, t6                ; ...
        mv    a1, a0                    ; Op(X)
        srli  a0, s3, 3                 ; ...
        slli  a0, a0, 16                ; ...
        ori   a0, a0, (1 << 3) | T_FUN  ; ...
        jalr  ra, gp, mkstr-R           ; ...
        mv    s2, a0                    ; ...
        mv    a1, s5                    ; ...
        j     pr_ret                    ; ...
pr_alone:
        andi  a1, s4, 0x7FF             ; an operator as an atom: its priority
        bleu  a1, s1, pr_ret            ; ...
        li    a1, 0                     ; (or 0 where that is too high)
        j     pr_ret                    ; ...

pr_compound:
        la    t6, token                 ; past the name: (
        xcall ra, c0, t6                ; ...
        la    t6, token                 ; past (
        xcall ra, c0, t6                ; ...
        li    s5, 0                     ; arguments, on the machine stack
pr_arg:
        li    a0, 999                   ; ...
        la    t6, parse                 ; ...
        xcall ra, c0, t6                ; ...
        addi  sp, sp, -8                ; ...
        sd    a0, 0(sp)                 ; ...
        addi  s5, s5, 1                 ; ...
        ld    t0, tk(zero)              ; , or )
        li    t1, TK_PUNCT              ; ...
        bne   t0, t1, pr_abad           ; ...
        ld    t0, tk_val(zero)          ; ...
        li    t1, ','                   ; ...
        bne   t0, t1, pr_aend           ; ...
        la    t6, token                 ; ...
        xcall ra, c0, t6                ; ...
        j     pr_arg                    ; ...
pr_aend:
        li    t1, ')'                   ; ...
        bne   t0, t1, pr_abad           ; ...
        li    t0, MAXAR                 ; ...
        bgtu  s5, t0, pr_abig           ; ...
        addi  a0, s5, 1                 ; the compound
        slli  a0, a0, 3                 ; ...
        jalr  ra, gp, halloc-R          ; ...
        mv    s6, a0                    ; ...
        srli  a1, s3, 3                 ; its functor
        slli  a1, a1, 16                ; ...
        slli  t0, s5, 3                 ; ...
        or    a1, a1, t0                ; ...
        ori   a1, a1, T_FUN             ; ...
        jalr  ra, gp, mwr-R             ; ...
pr_apop:
        beqz  s5, pr_adone              ; the arguments, last first
        ld    a1, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        slli  a0, s5, 3                 ; ...
        add   a0, a0, s6                ; ...
        jalr  ra, gp, mwr-R             ; ...
        addi  s5, s5, -1                ; ...
        j     pr_apop                   ; ...
pr_adone:
        addi  s2, s6, T_STR             ; ...
        j     pr_next0                  ; past )
pr_abad:
        li    a0, at_bad_args + T_ATM   ; (the stack goes back with the exception)
        j     perr                      ; ...
pr_abig:
        li    a0, at_max_arity + T_ATM  ; ...
        jalr  zero, gp, err_repr-R      ; ...
u_prim_end:
