#!/usr/bin/env python3
"""Writes boot.pl as assembly: the text, one .ascii line per source line,
between the labels boot_pl and boot_pl_end in the far section.

  python3 mkboot.py boot.pl > bootpl.s
"""
import sys

print('; bootpl.s: generated by lang/prolog/mkboot.py from boot.pl (do not edit)')
print('        .far                            ; the arena')
print('        .align 8                        ; ...')
print('boot_pl:                                ; the text')
for line in open(sys.argv[1], encoding='utf-8'):
    t = line.rstrip('\n').replace('\\', '\\\\').replace('"', '\\"')
    print(f'        .ascii "{t}\\n"')
print('boot_pl_end:                            ; one past its last byte')
