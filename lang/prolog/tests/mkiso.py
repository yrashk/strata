#!/usr/bin/env python3
"""Turns Logtalk's ISO Prolog conformance tests into Stralog test vectors.

  python3 mkiso.py LOGTALK/tests/prolog OUTDIR

Logtalk (https://logtalk.org/, Apache-2.0) keeps the standard's examples and
those of Szabo and Szeredi's conformance suite as lgtunit tests:

    test(iso_atom_length_2_01, true(N == 17)) :-
        {atom_length('enchanted evening', N)}.

Each test whose body is one {Goal} becomes a fact v(Name, Expected, Goal),
sharing its variables. Each directory of tests (one builtin or control
construct) becomes OUTDIR/NAME.pl: the plain Prolog that its tests.lgt has
before the test object (the fixtures the goals call), then the facts; and
OUTDIR/index.pl lists the files. Consulting one file replaces the previous
one's predicates, so the fixtures of different files do not meet. Tests that need what Stralog does not have are left
out: floats, Logtalk's own notation, options, tests disabled there, and
expectations other than true, true(Check), false, fail, error(E),
errors(Es) and ball(B). tests/iso.pl's header says where it came from.
"""
import os, re, sys

root, outdir = sys.argv[1], sys.argv[2]
os.makedirs(outdir, exist_ok=True)
SKIP = re.compile(r"\d\.\d|\d[eE][+-]?\d|::|\^\^|assertion\(|_flag\(|current_prolog_flag|"
                  r"set_prolog_flag|float|nan|inf\b|epsilon|max_tagged|min_tagged|"
                  r"max_integer|min_integer|0b|0o|0'\\\\|stream_property|set_stream|"
                  r"char_conversion|unicode|\bpi\b|\be\b|sin|cos|atan|sqrt|exp\(|log\(|"
                  r"truncate|round|ceiling|floor|float_|number_vars|"
                  r"read_term|write_term|write_canonical|\bopen\(|close\(|"
                  r"put_char|get_char|peek_char|get_byte|put_byte|peek_byte|get_code|"
                  r"put_code|peek_code|flush_output|nl\(|halt|"
                  r"atom_string|string|succ_or_fail|"
                  r"unify_with_occurs_check|subsumes_term|acyclic|cyclic|ground\(|"
                  r"term_variables\(.*,.*,|call_cleanup|setup_call|forall|"
                  r"\$|`|\boutput\b|\binput\b|\buser_\w+")
KINDS = ('true', 'false', 'fail', 'error', 'errors', 'ball')

HEADER = ("""% %s: ISO Prolog conformance vectors, from Logtalk's tests
% (tests/prolog/predicates and tests/prolog/control of
% https://github.com/LogtalkDotOrg/logtalk3), which are
%   SPDX-FileCopyrightText: 1998-2026 Paulo Moura <pmoura@logtalk.org>
%   SPDX-License-Identifier: Apache-2.0
% and carry the examples of the ISO/IEC 13211-1 standard and of the
% conformance testing framework of Peter Szabo and Peter Szeredi.
% Generated by lang/prolog/tests/mkiso.py: v(Name, Expected, Goal).

""")
FIXSKIP = re.compile(r":-\s*(if|elif|else|endif|import|use_module)\b|"
                     r"set_prolog_flag|ensure_loaded|initialization|encoding|"
                     r"\d\.\d|::|\^\^|\{|multifile")
# what Stralog does not have at all
DIRSKIP = {'call_nth_2', 'clause_references', 'evaluable_property_2', 'format_3',
           'portray_1', 'predicate_property_2', 'read_term_3', 'current_input_1',
           'current_output_1', 'numbervars_3', 'print_2', 'write_term_3'}
n, files = 0, []
for sub in ('control', 'predicates'):
    base = os.path.join(root, sub)
    for d in sorted(os.listdir(base)):
        f = os.path.join(base, d, 'tests.lgt')
        if d in DIRSKIP or not os.path.exists(f):
            continue
        text = open(f, encoding='utf-8').read()
        head = text.split(':- object(tests', 1)[0]
        head = re.sub(r'(?s)^%.*?\n(?=[^%])', '', head, count=1)
        fixtures = []
        for cl in re.split(r'(?m)(?<=\.)\s*\n(?=\S)', head):
            cl = '\n'.join(l for l in cl.split('\n') if not l.lstrip().startswith('%')).strip()
            if cl and not FIXSKIP.search(cl):
                fixtures.append(cl if cl.endswith('.') else cl + '.')
        vecs = []
        # a test clause: a line starting with (tab)test( and ending at a '.' at a line's end
        for m in re.finditer(r'^\ttest\((.*?)\.\s*$', text, re.M | re.S):
            clause = 'test(' + m.group(1)
            if '\n\t-' in clause or '\n\ttest(' in clause:
                continue
            hm = re.match(r'test\((\w+),\s*(.*?)\)\s*:-\s*\{(.*)\}\s*$', clause, re.S)
            if not hm:
                continue
            name, exp, goal = hm.groups()
            goal = ' '.join(goal.split())
            exp = ' '.join(exp.split())
            if not exp.split('(')[0] in KINDS or exp.startswith('true') and exp.startswith('true(') is False and exp != 'true':
                continue
            if SKIP.search(goal) or SKIP.search(exp) or '{' in goal or '}' in goal:
                continue
            if re.search(r',\s*\[', exp) and exp.startswith(('true(', 'false', 'error(')) and exp.count('(') == 0:
                continue
            vecs.append(f"v({name}, {exp}, ({goal})).\n")
            n += 1
        if vecs:
            fn = d + '.pl'
            files.append(fn)
            with open(os.path.join(outdir, fn), 'w', encoding='utf-8') as out:
                out.write(HEADER.replace("%s", fn, 1))
                for c in fixtures:
                    out.write(c + '\n')
                out.write('\n')
                out.writelines(vecs)
with open(os.path.join(outdir, 'index.pl'), 'w') as out:
    out.write(HEADER.replace("%s", "index.pl", 1))
    out.write('iso_files([\n' + ',\n'.join(f"    '{f[:-3]}'" for f in files) + '\n]).\n')
sys.stderr.write(f'{n} vectors\n')
