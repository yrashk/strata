; =============================================================================
; arith.s: arithmetic (a code unit)
; =============================================================================
;
; Integers only, of 61 bits: a result outside [-2^60, 2^60) raises
; evaluation_error(int_overflow). / divides and truncates (there are no
; floats). The builtins here are called by the solve loop with a0 = the goal
; and answer a0 = 1 or 0.

        .far                            ; code units
        .align 4096                     ; ---- unit: arithmetic ----
u_arith:

; fits (leaf, a0 = value) -> it, or an int_overflow error
fits:
        slli  t0, a0, 3                 ; does it survive the tag's shift?
        srai  t0, t0, 3                 ; ...
        bne   t0, a0, fi_ovf            ; ...
        ret                             ; ...
fi_ovf:
        li    a0, at_int_ovf + T_ATM    ; ...
        jalr  zero, gp, err_eval-R      ; ...

; eval(a0 = term) -> a0 = its value
eval:
        jalr  t6, gp, ent4-R            ; s1 term, s2 functor, s3 x, s4 y
        li    t0, SPMIN                 ; deep enough?
        bltu  sp, t0, ev_deep           ; ...
        jalr  ra, gp, deref-R           ; ...
        mv    s1, a0                    ; ...
        andi  t0, s1, 7                 ; ...
        li    t1, T_INT                 ; a number: itself
        bne   t0, t1, ev_nint           ; ...
        srai  a0, s1, 3                 ; ...
        jalr  zero, gp, lv4-R           ; ...
ev_deep:
        jalr  zero, gp, err_depth-R     ; ...
ev_nint:
        beqz  t0, ev_inst               ; a variable
        li    t1, T_ATM                 ; an atom: Name/0 is not evaluable
        beq   t0, t1, ev_atom           ; ...
        li    t1, T_STR                 ; ...
        bne   t0, t1, ev_type           ; ...
        addi  a0, s1, -T_STR            ; the functor
        jalr  ra, gp, mrd-R             ; ...
        mv    s2, a0                    ; ...
        srli  t0, s2, 3                 ; arity
        andi  t0, t0, 0x1FFF            ; ...
        li    t1, 2                     ; ...
        bgtu  t0, t1, ev_noteval        ; ...
        mv    a0, s1                    ; X
        li    a1, 1                     ; ...
        jalr  ra, gp, garg-R            ; ...
        la    t6, eval                  ; ...
        xcall ra, c0, t6                ; ...
        mv    s3, a0                    ; ...
        srli  t0, s2, 3                 ; one argument?
        andi  t0, t0, 0x1FFF            ; ...
        li    t1, 1                     ; ...
        beq   t0, t1, ev_unary          ; ...
        mv    a0, s1                    ; Y
        li    a1, 2                     ; ...
        jalr  ra, gp, garg-R            ; ...
        la    t6, eval                  ; ...
        xcall ra, c0, t6                ; ...
        mv    s4, a0                    ; ...
        li    t0, ((at_plus >> 3) << 16) | (2 << 3) | T_FUN ; X + Y
        bne   s2, t0, ev_2              ; ...
        add   a0, s3, s4                ; ...
        j     ev_fit                    ; ...
ev_2:
        li    t0, ((at_minus >> 3) << 16) | (2 << 3) | T_FUN ; X - Y
        bne   s2, t0, ev_3              ; ...
        sub   a0, s3, s4                ; ...
        j     ev_fit                    ; ...
ev_3:
        li    t0, ((at_star >> 3) << 16) | (2 << 3) | T_FUN ; X * Y
        bne   s2, t0, ev_4              ; ...
        mul   a0, s3, s4                ; ...
        beqz  s3, ev_fit                ; overflow: the product divided by X is not Y
        div   t0, a0, s3                ; ...
        bne   t0, s4, fi_ovf            ; ...
        j     ev_fit                    ; ...
ev_4:
        li    t0, ((at_idiv >> 3) << 16) | (2 << 3) | T_FUN ; X // Y
        beq   s2, t0, ev_div            ; ...
        li    t0, ((at_slash >> 3) << 16) | (2 << 3) | T_FUN ; X / Y (integers: the same)
        bne   s2, t0, ev_5              ; ...
ev_div:
        beqz  s4, ev_zero               ; ...
        div   a0, s3, s4                ; ...
        j     ev_fit                    ; ...
ev_5:
        li    t0, ((at_rem >> 3) << 16) | (2 << 3) | T_FUN ; X rem Y
        bne   s2, t0, ev_6              ; ...
        beqz  s4, ev_zero               ; ...
        rem   a0, s3, s4                ; ...
        j     ev_fit                    ; ...
ev_6:
        li    t0, ((at_mod >> 3) << 16) | (2 << 3) | T_FUN ; X mod Y: the sign of Y
        bne   s2, t0, ev_6b             ; ...
        beqz  s4, ev_zero               ; ...
        rem   a0, s3, s4                ; ...
        beqz  a0, ev_fit                ; ...
        xor   t0, a0, s4                ; signs differ: add Y
        bgez  t0, ev_fit                ; ...
        add   a0, a0, s4                ; ...
        j     ev_fit                    ; ...
ev_6b:
        li    t0, ((at_div >> 3) << 16) | (2 << 3) | T_FUN ; X div Y: rounded down
        bne   s2, t0, ev_7              ; ...
        beqz  s4, ev_zero               ; ...
        div   a0, s3, s4                ; ...
        rem   t0, s3, s4                ; ...
        beqz  t0, ev_fit                ; ...
        xor   t0, t0, s4                ; ...
        bgez  t0, ev_fit                ; ...
        addi  a0, a0, -1                ; ...
        j     ev_fit                    ; ...
ev_7:
        li    t0, ((at_min >> 3) << 16) | (2 << 3) | T_FUN ; min
        bne   s2, t0, ev_8              ; ...
        mv    a0, s3                    ; ...
        ble   s3, s4, ev_fit            ; ...
        mv    a0, s4                    ; ...
        j     ev_fit                    ; ...
ev_8:
        li    t0, ((at_max >> 3) << 16) | (2 << 3) | T_FUN ; max
        bne   s2, t0, ev_9              ; ...
        mv    a0, s3                    ; ...
        bge   s3, s4, ev_fit            ; ...
        mv    a0, s4                    ; ...
        j     ev_fit                    ; ...
ev_9:
        li    t0, ((at_shr >> 3) << 16) | (2 << 3) | T_FUN ; >>
        bne   s2, t0, ev_10             ; ...
        li    t0, 63                    ; ...
        bleu  s4, t0, ev_shr            ; ...
        mv    s4, t0                    ; ...
ev_shr:
        sra   a0, s3, s4                ; ...
        j     ev_fit                    ; ...
ev_10:
        li    t0, ((at_shl >> 3) << 16) | (2 << 3) | T_FUN ; <<
        bne   s2, t0, ev_11             ; ...
        li    t0, 63                    ; ...
        bgtu  s4, t0, fi_ovf            ; ...
        sll   a0, s3, s4                ; ...
        sra   t0, a0, s4                ; bits lost: overflow
        bne   t0, s3, fi_ovf            ; ...
        j     ev_fit                    ; ...
ev_11:
        li    t0, ((at_band >> 3) << 16) | (2 << 3) | T_FUN ; /\
        bne   s2, t0, ev_12             ; ...
        and   a0, s3, s4                ; ...
        j     ev_fit                    ; ...
ev_12:
        li    t0, ((at_bor >> 3) << 16) | (2 << 3) | T_FUN ; \/
        bne   s2, t0, ev_13             ; ...
        or    a0, s3, s4                ; ...
        j     ev_fit                    ; ...
ev_13:
        li    t0, ((at_xor >> 3) << 16) | (2 << 3) | T_FUN ; xor
        bne   s2, t0, ev_14             ; ...
        xor   a0, s3, s4                ; ...
        j     ev_fit                    ; ...
ev_14:
        li    t0, ((at_pow >> 3) << 16) | (2 << 3) | T_FUN ; ** and ^: integer powers
        beq   s2, t0, ev_pow            ; ...
        li    t0, ((at_caret >> 3) << 16) | (2 << 3) | T_FUN ; ...
        bne   s2, t0, ev_15             ; ...
ev_pow:
        bltz  s4, ev_negpow             ; ...
        li    a0, 1                     ; ...
ev_ploop:
        beqz  s4, ev_fit                ; ...
        mul   t1, a0, s3                ; ...
        beqz  a0, ev_pnext              ; ...
        div   t2, t1, a0                ; ...
        bne   t2, s3, fi_ovf            ; ...
ev_pnext:
        mv    a0, t1                    ; ...
        slli  t0, a0, 3                 ; ...
        srai  t0, t0, 3                 ; ...
        bne   t0, a0, fi_ovf            ; ...
        addi  s4, s4, -1                ; ...
        j     ev_ploop                  ; ...
ev_negpow:
        li    t0, 1                     ; 1 ** -N = 1, -1 ** -N = +-1, others: not an integer
        beq   s3, t0, ev_one            ; ...
        li    t0, -1                    ; ...
        bne   s3, t0, ev_negb           ; ...
        andi  t0, s4, 1                 ; ...
        li    a0, -1                    ; ...
        bnez  t0, ev_fit                ; ...
ev_one:
        li    a0, 1                     ; ...
        j     ev_fit                    ; ...
ev_negb:
        beqz  s3, ev_zero               ; ...
        li    a0, at_integer + T_ATM    ; type_error(float, ...): no floats; say it as ISO does for ints
        slli  a1, s3, 3                 ; ...
        ori   a1, a1, T_INT             ; ...
        jalr  zero, gp, err_type-R      ; ...
ev_15:
        li    t0, ((at_gcd >> 3) << 16) | (2 << 3) | T_FUN ; gcd
        bne   s2, t0, ev_noteval        ; ...
        bgez  s3, ev_g1                 ; ...
        sub   s3, zero, s3              ; ...
ev_g1:
        bgez  s4, ev_gl                 ; ...
        sub   s4, zero, s4              ; ...
ev_gl:
        beqz  s4, ev_gd                 ; ...
        rem   t0, s3, s4                ; ...
        mv    s3, s4                    ; ...
        mv    s4, t0                    ; ...
        j     ev_gl                     ; ...
ev_gd:
        mv    a0, s3                    ; ...
        j     ev_fit                    ; ...
ev_unary:
        li    t0, ((at_minus >> 3) << 16) | (1 << 3) | T_FUN ; - X
        bne   s2, t0, ev_u2             ; ...
        sub   a0, zero, s3              ; ...
        j     ev_fit                    ; ...
ev_u2:
        li    t0, ((at_plus >> 3) << 16) | (1 << 3) | T_FUN ; + X
        bne   s2, t0, ev_u3             ; ...
        mv    a0, s3                    ; ...
        j     ev_fit                    ; ...
ev_u3:
        li    t0, ((at_abs >> 3) << 16) | (1 << 3) | T_FUN ; abs
        bne   s2, t0, ev_u4             ; ...
        mv    a0, s3                    ; ...
        bgez  a0, ev_fit                ; ...
        sub   a0, zero, a0              ; ...
        j     ev_fit                    ; ...
ev_u4:
        li    t0, ((at_sign >> 3) << 16) | (1 << 3) | T_FUN ; sign
        bne   s2, t0, ev_u5             ; ...
        slt   a0, zero, s3              ; (1 if positive)
        slt   t0, s3, zero              ; ...
        sub   a0, a0, t0                ; ...
        j     ev_fit                    ; ...
ev_u5:
        li    t0, ((at_bnot >> 3) << 16) | (1 << 3) | T_FUN ; \ X
        bne   s2, t0, ev_u6             ; ...
        li    t0, -1                    ; ...
        xor   a0, s3, t0                ; ...
        j     ev_fit                    ; ...
ev_u6:
        li    t0, ((at_msb >> 3) << 16) | (1 << 3) | T_FUN ; msb
        bne   s2, t0, ev_noteval        ; ...
        blez  s3, ev_noteval            ; ...
        li    a0, -1                    ; ...
ev_msb:
        beqz  s3, ev_fit                ; ...
        srli  s3, s3, 1                 ; ...
        addi  a0, a0, 1                 ; ...
        j     ev_msb                    ; ...
ev_fit:
        call  fits                      ; ...
        jalr  zero, gp, lv4-R           ; ...
ev_inst:
        jalr  zero, gp, err_inst-R      ; ...
ev_type:
        li    a0, at_evaluable + T_ATM  ; (an integer goal cell cannot get here)
        mv    a1, s1                    ; ...
        jalr  zero, gp, err_type-R      ; ...
ev_zero:
        li    a0, at_zero_div + T_ATM   ; ...
        jalr  zero, gp, err_eval-R      ; ...
ev_atom:
        srli  s2, s1, 3                 ; Name/0
        slli  s2, s2, 16                ; ...
        ori   s2, s2, T_FUN             ; ...
ev_noteval:
        mv    a0, s2                    ; type_error(evaluable, Name/Arity)
        la    t6, mk_pi                 ; ...
        xcall ra, c0, t6                ; ...
        mv    a1, a0                    ; ...
        li    a0, at_evaluable + T_ATM  ; ...
        jalr  zero, gp, err_type-R      ; ...

; bi_is: X is E
bi_is:
        jalr  t6, gp, ent1-R            ; s1 goal
        mv    s1, a0                    ; ...
        li    a1, 2                     ; ...
        jalr  ra, gp, garg-R            ; ...
        la    t6, eval                  ; ...
        xcall ra, c0, t6                ; ...
        slli  a0, a0, 3                 ; ...
        ori   a0, a0, T_INT             ; ...
        sd    a0, v_tmp(zero)           ; ...
        mv    a0, s1                    ; ...
        li    a1, 1                     ; ...
        jalr  ra, gp, garg-R            ; ...
        ld    a1, v_tmp(zero)           ; ...
        jalr  ra, gp, unify-R           ; ...
        jalr  zero, gp, lv1-R           ; ...

; bi_acmp: =:= =\= < > =< >=, told apart by the functor
bi_acmp:
        jalr  t6, gp, ent3-R            ; s1 goal, s2 X, s3 Y
        mv    s1, a0                    ; ...
        li    a1, 1                     ; ...
        jalr  ra, gp, garg-R            ; ...
        la    t6, eval                  ; ...
        xcall ra, c0, t6                ; ...
        mv    s2, a0                    ; ...
        mv    a0, s1                    ; ...
        li    a1, 2                     ; ...
        jalr  ra, gp, garg-R            ; ...
        la    t6, eval                  ; ...
        xcall ra, c0, t6                ; ...
        mv    s3, a0                    ; ...
        addi  a0, s1, -T_STR            ; which?
        jalr  ra, gp, mrd-R             ; ...
        srli  a0, a0, 16                ; the atom's offset >> 3
        li    t0, at_aeq >> 3           ; =:=
        bne   a0, t0, ac_ne             ; ...
        xor   a0, s2, s3                ; ...
        seqz  a0, a0                    ; ...
        jalr  zero, gp, lv3-R           ; ...
ac_ne:
        li    t0, at_ane >> 3           ; =\=
        bne   a0, t0, ac_lt             ; ...
        xor   a0, s2, s3                ; ...
        snez  a0, a0                    ; ...
        jalr  zero, gp, lv3-R           ; ...
ac_lt:
        li    t0, at_lt >> 3            ; <
        bne   a0, t0, ac_gt             ; ...
        slt   a0, s2, s3                ; ...
        jalr  zero, gp, lv3-R           ; ...
ac_gt:
        li    t0, at_gt >> 3            ; >
        bne   a0, t0, ac_le             ; ...
        slt   a0, s3, s2                ; ...
        jalr  zero, gp, lv3-R           ; ...
ac_le:
        li    t0, at_le >> 3            ; =<
        bne   a0, t0, ac_ge             ; ...
        slt   a0, s3, s2                ; ...
        xori  a0, a0, 1                 ; ...
        jalr  zero, gp, lv3-R           ; ...
ac_ge:
        slt   a0, s2, s3                ; >=
        xori  a0, a0, 1                 ; ...
        jalr  zero, gp, lv3-R           ; ...
u_arith_end:
