; =============================================================================
; bi.s: builtins (code units)
; =============================================================================
;
; A builtin is called by the solve loop with a0 = its goal and answers
; a0 = 1 (true) or 0 (fail); errors are thrown (solve.s, err_*). Everything
; nondeterministic is written in Prolog over these (boot.pl).

        .far                            ; code units
        .align 4096                     ; ---- unit: types and comparison ----
u_bi1:

; arg1 (leaf, s1 = goal) -> a0 = its first argument, dereferenced
arg1:
        mv    a0, s1                    ; ...
        li    a1, 1                     ; ...
        jalr  zero, gp, garg-R          ; (tail call: garg returns to arg1's caller)

; var(X) nonvar(X) atom(X) number(X) integer(X) atomic(X) compound(X) callable(X) is_list
bi_var:
        jalr  t6, gp, ent1-R            ; ...
        mv    s1, a0                    ; ...
        call  arg1                      ; ...
        andi  a0, a0, 7                 ; ...
        seqz  a0, a0                    ; ...
        jalr  zero, gp, lv1-R           ; ...
bi_nonvar:
        jalr  t6, gp, ent1-R            ; ...
        mv    s1, a0                    ; ...
        call  arg1                      ; ...
        andi  a0, a0, 7                 ; ...
        snez  a0, a0                    ; ...
        jalr  zero, gp, lv1-R           ; ...
bi_atom:
        jalr  t6, gp, ent1-R            ; ...
        mv    s1, a0                    ; ...
        call  arg1                      ; ...
        andi  a0, a0, 7                 ; ...
        addi  a0, a0, -T_ATM            ; ...
        seqz  a0, a0                    ; ...
        jalr  zero, gp, lv1-R           ; ...
bi_integer:
        jalr  t6, gp, ent1-R            ; (number/1 too: integers are all the numbers)
        mv    s1, a0                    ; ...
        call  arg1                      ; ...
        andi  a0, a0, 7                 ; ...
        addi  a0, a0, -T_INT            ; ...
        seqz  a0, a0                    ; ...
        jalr  zero, gp, lv1-R           ; ...
bi_atomic:
        jalr  t6, gp, ent1-R            ; ...
        mv    s1, a0                    ; ...
        call  arg1                      ; ...
        andi  a0, a0, 7                 ; ...
        li    t0, T_ATM                 ; ...
        beq   a0, t0, bi_yes1           ; ...
        li    t0, T_INT                 ; ...
        beq   a0, t0, bi_yes1           ; ...
        li    a0, 0                     ; ...
        jalr  zero, gp, lv1-R           ; ...
bi_yes1:
        li    a0, 1                     ; ...
        jalr  zero, gp, lv1-R           ; ...
bi_compound:
        jalr  t6, gp, ent1-R            ; ...
        mv    s1, a0                    ; ...
        call  arg1                      ; ...
        andi  a0, a0, 7                 ; ...
        addi  a0, a0, -T_STR            ; ...
        seqz  a0, a0                    ; ...
        jalr  zero, gp, lv1-R           ; ...
bi_callable:
        jalr  t6, gp, ent1-R            ; ...
        mv    s1, a0                    ; ...
        call  arg1                      ; ...
        andi  a0, a0, 7                 ; ...
        li    t0, T_ATM                 ; ...
        beq   a0, t0, bi_yes1           ; ...
        li    t0, T_STR                 ; ...
        beq   a0, t0, bi_yes1           ; ...
        li    a0, 0                     ; ...
        jalr  zero, gp, lv1-R           ; ...

; X = Y
bi_unify:
        jalr  t6, gp, ent1-R            ; s1 goal
        mv    s1, a0                    ; ...
        addi  a0, s1, 16 - T_STR        ; ...
        jalr  ra, gp, mrd-R             ; ...
        sd    a0, v_tmp(zero)           ; ...
        addi  a0, s1, 8 - T_STR         ; ...
        jalr  ra, gp, mrd-R             ; ...
        ld    a1, v_tmp(zero)           ; ...
        jalr  ra, gp, unify-R           ; ...
        jalr  zero, gp, lv1-R           ; ...

; X \= Y: unify with every binding trailed, then undo them
bi_nunify:
        jalr  t6, gp, ent3-R            ; s1 goal, s2 trail top, s3 HB
        mv    s1, a0                    ; ...
        ld    s2, v_TR(zero)            ; ...
        ld    s3, v_HB(zero)            ; ...
        ld    t0, v_H(zero)             ; everything older than now is trailed
        sd    t0, v_HB(zero)            ; ...
        addi  a0, s1, 16 - T_STR        ; ...
        jalr  ra, gp, mrd-R             ; ...
        sd    a0, v_tmp(zero)           ; ...
        addi  a0, s1, 8 - T_STR         ; ...
        jalr  ra, gp, mrd-R             ; ...
        ld    a1, v_tmp(zero)           ; ...
        jalr  ra, gp, unify-R           ; ...
        sd    a0, v_tmp(zero)           ; ...
        mv    a0, s2                    ; ...
        jalr  ra, gp, untrail-R         ; ...
        sd    s3, v_HB(zero)            ; ...
        ld    a0, v_tmp(zero)           ; ...
        xori  a0, a0, 1                 ; ...
        jalr  zero, gp, lv3-R           ; ...

; tcompare(a0, a1) -> a0 = -1, 0 or 1 in the standard order:
; variables < numbers < atoms < compounds; compounds by arity, name, arguments
tcompare:
        jalr  t6, gp, ent6-R            ; s1 X, s2 Y, s3 class X, s4 class Y, s5 args left, s6
        li    t0, SPMIN                 ; deep enough?
        bltu  sp, t0, tc_deep           ; ...
tc_top:
        mv    s2, a1                    ; ...
        jalr  ra, gp, deref-R           ; ...
        mv    s1, a0                    ; ...
        mv    a0, s2                    ; ...
        jalr  ra, gp, deref-R           ; ...
        mv    s2, a0                    ; ...
        beq   s1, s2, tc_eq             ; identical
        mv    a0, s1                    ; ...
        call  tclass                    ; ...
        mv    s3, a0                    ; ...
        mv    a0, s2                    ; ...
        call  tclass                    ; ...
        mv    s4, a0                    ; ...
        bne   s3, s4, tc_cls            ; ...
        beqz  s3, tc_addr               ; variables: by age
        li    t0, 1                     ; numbers: by value
        beq   s3, t0, tc_num            ; ...
        li    t0, 2                     ; atoms: by name
        beq   s3, t0, tc_atom           ; ...
        addi  a0, s1, -T_STR            ; compounds: arity, name, arguments
        jalr  ra, gp, mrd-R             ; ...
        mv    s3, a0                    ; ...
        addi  a0, s2, -T_STR            ; ...
        jalr  ra, gp, mrd-R             ; ...
        mv    s4, a0                    ; ...
        srli  t0, s3, 3                 ; ...
        andi  t0, t0, 0x1FFF            ; ...
        srli  t1, s4, 3                 ; ...
        andi  t1, t1, 0x1FFF            ; ...
        bne   t0, t1, tc_ar             ; ...
        mv    s5, t0                    ; ...
        beq   s3, s4, tc_args           ; same functor
        srli  a0, s3, 16                ; the names
        slli  a0, a0, 3                 ; ...
        srli  a1, s4, 16                ; ...
        slli  a1, a1, 3                 ; ...
        call  atom_cmp                  ; ...
        jalr  zero, gp, lv6-R           ; ...
tc_ar:
        slt   a0, t1, t0                ; ...
        slt   t2, t0, t1                ; ...
        sub   a0, a0, t2                ; ...
        jalr  zero, gp, lv6-R           ; ...
tc_args:
        addi  s1, s1, 8 - T_STR         ; argument cursors
        addi  s2, s2, 8 - T_STR         ; ...
tc_aloop:
        addi  s5, s5, -1                ; the last: iterate
        beqz  s5, tc_alast              ; ...
        mv    a0, s2                    ; ...
        jalr  ra, gp, mrd-R             ; ...
        mv    s6, a0                    ; ...
        mv    a0, s1                    ; ...
        jalr  ra, gp, mrd-R             ; ...
        mv    a1, s6                    ; ...
        la    t6, tcompare              ; ...
        xcall ra, c0, t6                ; ...
        bnez  a0, tc_ret                ; ...
        addi  s1, s1, 8                 ; ...
        addi  s2, s2, 8                 ; ...
        j     tc_aloop                  ; ...
tc_alast:
        mv    a0, s2                    ; ...
        jalr  ra, gp, mrd-R             ; ...
        mv    s6, a0                    ; ...
        mv    a0, s1                    ; ...
        jalr  ra, gp, mrd-R             ; ...
        mv    a1, s6                    ; ...
        j     tc_top                    ; ...
tc_cls:
        slt   a0, s4, s3                ; ...
        slt   t2, s3, s4                ; ...
        sub   a0, a0, t2                ; ...
        jalr  zero, gp, lv6-R           ; ...
tc_addr:
        sltu  a0, s2, s1                ; ...
        sltu  t2, s1, s2                ; ...
        sub   a0, a0, t2                ; ...
        jalr  zero, gp, lv6-R           ; ...
tc_num:
        slt   a0, s2, s1                ; (the tagged values order as the numbers)
        slt   t2, s1, s2                ; ...
        sub   a0, a0, t2                ; ...
        jalr  zero, gp, lv6-R           ; ...
tc_atom:
        addi  a0, s1, -T_ATM            ; ...
        addi  a1, s2, -T_ATM            ; ...
        call  atom_cmp                  ; ...
        jalr  zero, gp, lv6-R           ; ...
tc_eq:
        li    a0, 0                     ; ...
tc_ret:
        jalr  zero, gp, lv6-R           ; ...
tc_deep:
        jalr  zero, gp, err_depth-R     ; ...

; tclass (leaf, a0 = cell) -> a0 = 0 variable, 1 number, 2 atom, 3 compound
tclass:
        andi  t0, a0, 7                 ; ...
        li    a0, 0                     ; ...
        beqz  t0, tcl_ret               ; ...
        li    a0, 1                     ; ...
        li    t1, T_INT                 ; ...
        beq   t0, t1, tcl_ret           ; ...
        li    a0, 2                     ; ...
        li    t1, T_ATM                 ; ...
        beq   t0, t1, tcl_ret           ; ...
        li    a0, 3                     ; ...
tcl_ret:
        ret                             ; ...

; atom_cmp (leaf, a0, a1 = two atom records) -> a0 = -1, 0, 1 by their names' bytes
atom_cmp:
        addi  sp, sp, -48               ; ...
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; X
        sd    a1, 16(sp)                ; Y
        addi  a0, a0, AT_LEN            ; lengths
        jalr  ra, gp, mrd-R             ; ...
        sd    a0, 24(sp)                ; ...
        ld    a0, 16(sp)                ; ...
        addi  a0, a0, AT_LEN            ; ...
        jalr  ra, gp, mrd-R             ; ...
        sd    a0, 32(sp)                ; ...
        sd    zero, 40(sp)              ; i
acm_loop:
        ld    t0, 40(sp)                ; past either end?
        ld    t1, 24(sp)                ; ...
        bgeu  t0, t1, acm_end           ; ...
        ld    t1, 32(sp)                ; ...
        bgeu  t0, t1, acm_end           ; ...
        ld    a0, 8(sp)                 ; X's byte
        add   a0, a0, t0                ; ...
        addi  a0, a0, AT_NAME           ; ...
        jalr  ra, gp, mrdb-R            ; ...
        mv    t3, a0                    ; ...
        ld    t0, 40(sp)                ; Y's byte
        ld    a0, 16(sp)                ; ...
        add   a0, a0, t0                ; ...
        addi  a0, a0, AT_NAME           ; ...
        sd    t3, v_tmp+16(zero)        ; ...
        jalr  ra, gp, mrdb-R            ; ...
        ld    t3, v_tmp+16(zero)        ; ...
        bne   t3, a0, acm_diff          ; ...
        ld    t0, 40(sp)                ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, 40(sp)                ; ...
        j     acm_loop                  ; ...
acm_diff:
        sltu  t1, a0, t3                ; ...
        sltu  t2, t3, a0                ; ...
        sub   a0, t1, t2                ; ...
        j     acm_ret                   ; ...
acm_end:
        ld    t1, 24(sp)                ; the shorter is first
        ld    t2, 32(sp)                ; ...
        sltu  a0, t2, t1                ; ...
        sltu  t3, t1, t2                ; ...
        sub   a0, a0, t3                ; ...
acm_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; ...

; == \== @< @> @=< @>=, told apart by the functor's name
bi_tcmp:
        jalr  t6, gp, ent2-R            ; s1 goal, s2 name
        mv    s1, a0                    ; ...
        addi  a0, s1, -T_STR            ; ...
        jalr  ra, gp, mrd-R             ; ...
        srli  s2, a0, 16                ; ...
        addi  a0, s1, 16 - T_STR        ; ...
        jalr  ra, gp, mrd-R             ; ...
        sd    a0, v_tmp(zero)           ; ...
        addi  a0, s1, 8 - T_STR         ; ...
        jalr  ra, gp, mrd-R             ; ...
        ld    a1, v_tmp(zero)           ; ...
        la    t6, tcompare              ; ...
        xcall ra, c0, t6                ; ...
        li    t0, at_eqeq >> 3          ; ==
        bne   s2, t0, bt_ne             ; ...
        seqz  a0, a0                    ; ...
        jalr  zero, gp, lv2-R           ; ...
bt_ne:
        li    t0, at_neqeq >> 3         ; \==
        bne   s2, t0, bt_lt             ; ...
        snez  a0, a0                    ; ...
        jalr  zero, gp, lv2-R           ; ...
bt_lt:
        li    t0, at_tlt >> 3           ; @<
        bne   s2, t0, bt_gt             ; ...
        slti  a0, a0, 0                 ; ...
        jalr  zero, gp, lv2-R           ; ...
bt_gt:
        li    t0, at_tgt >> 3           ; @>
        bne   s2, t0, bt_le             ; ...
        slt   a0, zero, a0              ; ...
        jalr  zero, gp, lv2-R           ; ...
bt_le:
        li    t0, at_tle >> 3           ; @=<
        bne   s2, t0, bt_ge             ; ...
        slti  a0, a0, 1                 ; ...
        jalr  zero, gp, lv2-R           ; ...
bt_ge:
        slti  a0, a0, 0                 ; @>=
        xori  a0, a0, 1                 ; ...
        jalr  zero, gp, lv2-R           ; ...

; compare(Order, X, Y)
bi_compare:
        jalr  t6, gp, ent1-R            ; s1 goal
        mv    s1, a0                    ; ...
        addi  a0, s1, 24 - T_STR        ; ...
        jalr  ra, gp, mrd-R             ; ...
        sd    a0, v_tmp(zero)           ; ...
        addi  a0, s1, 16 - T_STR        ; ...
        jalr  ra, gp, mrd-R             ; ...
        ld    a1, v_tmp(zero)           ; ...
        la    t6, tcompare              ; ...
        xcall ra, c0, t6                ; ...
        li    a1, at_eq + T_ATM         ; =
        beqz  a0, bc_go                 ; ...
        li    a1, at_lt + T_ATM         ; <
        bltz  a0, bc_go                 ; ...
        li    a1, at_gt + T_ATM         ; >
bc_go:
        sd    a1, v_tmp(zero)           ; ...
        call  arg1                      ; ...
        ld    a1, v_tmp(zero)           ; ...
        jalr  ra, gp, unify-R           ; ...
        jalr  zero, gp, lv1-R           ; ...
u_bi1_end:

        .align 4096                     ; ---- unit: terms ----
u_bi2:

; functor(T, Name, Arity)
bi_functor:
        jalr  t6, gp, ent6-R            ; s1 goal, s2 T, s3 name, s4 arity, s5 block, s6 i
        mv    s1, a0                    ; ...
        li    a1, 1                     ; ...
        jalr  ra, gp, garg-R            ; ...
        mv    s2, a0                    ; ...
        andi  t0, s2, 7                 ; ...
        beqz  t0, bf_make               ; a variable: make it
        li    t1, T_STR                 ; ...
        beq   t0, t1, bf_str            ; ...
        mv    s3, s2                    ; atomic: itself / 0
        li    s4, T_INT                 ; ...
        j     bf_out                    ; ...
bf_str:
        addi  a0, s2, -T_STR            ; ...
        jalr  ra, gp, mrd-R             ; ...
        srli  s3, a0, 16                ; ...
        slli  s3, s3, 3                 ; ...
        ori   s3, s3, T_ATM             ; ...
        srli  s4, a0, 3                 ; ...
        andi  s4, s4, 0x1FFF            ; ...
        slli  s4, s4, 3                 ; ...
        ori   s4, s4, T_INT             ; ...
bf_out:
        mv    a0, s1                    ; Name
        li    a1, 2                     ; ...
        jalr  ra, gp, garg-R            ; ...
        mv    a1, s3                    ; ...
        jalr  ra, gp, unify-R           ; ...
        beqz  a0, bf_ret                ; ...
        mv    a0, s1                    ; Arity
        li    a1, 3                     ; ...
        jalr  ra, gp, garg-R            ; ...
        mv    a1, s4                    ; ...
        jalr  ra, gp, unify-R           ; ...
bf_ret:
        jalr  zero, gp, lv6-R           ; ...
bf_make:
        mv    a0, s1                    ; Name, Arity must be given
        li    a1, 2                     ; ...
        jalr  ra, gp, garg-R            ; ...
        mv    s3, a0                    ; ...
        mv    a0, s1                    ; ...
        li    a1, 3                     ; ...
        jalr  ra, gp, garg-R            ; ...
        mv    s4, a0                    ; ...
        andi  t0, s3, 7                 ; ...
        beqz  t0, bf_inst               ; ...
        andi  t0, s4, 7                 ; ...
        beqz  t0, bf_inst               ; ...
        li    t1, T_INT                 ; ...
        bne   t0, t1, bf_tint           ; ...
        srai  s4, s4, 3                 ; ...
        bltz  s4, bf_neg                ; ...
        bnez  s4, bf_comp               ; arity 0: T = Name
        andi  t0, s3, 7                 ; (Name atomic)
        li    t1, T_STR                 ; ...
        beq   t0, t1, bf_tatomic        ; ...
        mv    a0, s2                    ; ...
        mv    a1, s3                    ; ...
        jalr  ra, gp, unify-R           ; ...
        jalr  zero, gp, lv6-R           ; ...
bf_comp:
        andi  t0, s3, 7                 ; Name must be an atom
        li    t1, T_ATM                 ; ...
        beq   t0, t1, bf_c2             ; ...
        li    t1, T_STR                 ; ...
        beq   t0, t1, bf_tatomic        ; ...
        j     bf_tatom                  ; ...
bf_c2:
        li    t0, MAXAR                 ; ...
        bgtu  s4, t0, bf_big            ; ...
        addi  a0, s4, 1                 ; ...
        slli  a0, a0, 3                 ; ...
        jalr  ra, gp, halloc-R          ; ...
        mv    s5, a0                    ; ...
        srli  a1, s3, 3                 ; ...
        slli  a1, a1, 16                ; ...
        slli  t0, s4, 3                 ; ...
        or    a1, a1, t0                ; ...
        ori   a1, a1, T_FUN             ; ...
        jalr  ra, gp, mwr-R             ; ...
        li    s6, 1                     ; fresh variables
bf_vars:
        bgtu  s6, s4, bf_done           ; ...
        slli  a0, s6, 3                 ; ...
        add   a0, a0, s5                ; ...
        mv    a1, a0                    ; ...
        jalr  ra, gp, mwr-R             ; ...
        addi  s6, s6, 1                 ; ...
        j     bf_vars                   ; ...
bf_done:
        mv    a0, s2                    ; ...
        addi  a1, s5, T_STR             ; ...
        jalr  ra, gp, unify-R           ; ...
        jalr  zero, gp, lv6-R           ; ...
bf_inst:
        jalr  zero, gp, err_inst-R      ; ...
bf_tint:
        li    a0, at_integer + T_ATM    ; ...
        mv    a1, s4                    ; ...
        jalr  zero, gp, err_type-R      ; ...
bf_tatomic:
        li    a0, at_atomic + T_ATM     ; ...
        mv    a1, s3                    ; ...
        jalr  zero, gp, err_type-R      ; ...
bf_tatom:
        li    a0, at_atom + T_ATM       ; (an integer Name with an arity)
        mv    a1, s3                    ; ...
        jalr  zero, gp, err_type-R      ; ...
bf_neg:
        li    a0, at_not_less + T_ATM   ; ...
        slli  a1, s4, 3                 ; ...
        ori   a1, a1, T_INT             ; ...
        jalr  zero, gp, err_dom-R       ; ...
bf_big:
        li    a0, at_max_arity + T_ATM  ; ...
        jalr  zero, gp, err_repr-R      ; ...

; arg(N, T, A)
bi_arg:
        jalr  t6, gp, ent3-R            ; s1 goal, s2 N, s3 T
        mv    s1, a0                    ; ...
        li    a1, 1                     ; ...
        jalr  ra, gp, garg-R            ; ...
        mv    s2, a0                    ; ...
        mv    a0, s1                    ; ...
        li    a1, 2                     ; ...
        jalr  ra, gp, garg-R            ; ...
        mv    s3, a0                    ; ...
        andi  t0, s2, 7                 ; ...
        beqz  t0, bf_inst               ; ...
        li    t1, T_INT                 ; ...
        bne   t0, t1, ba_tint           ; ...
        andi  t0, s3, 7                 ; ...
        beqz  t0, bf_inst               ; ...
        li    t1, T_STR                 ; ...
        bne   t0, t1, ba_tcomp          ; ...
        srai  s2, s2, 3                 ; ...
        blez  s2, ba_no                 ; ...
        addi  a0, s3, -T_STR            ; ...
        jalr  ra, gp, mrd-R             ; ...
        srli  t0, a0, 3                 ; ...
        andi  t0, t0, 0x1FFF            ; ...
        bgtu  s2, t0, ba_no             ; ...
        mv    a0, s3                    ; ...
        mv    a1, s2                    ; ...
        jalr  ra, gp, garg-R            ; ...
        sd    a0, v_tmp(zero)           ; ...
        mv    a0, s1                    ; ...
        li    a1, 3                     ; ...
        jalr  ra, gp, garg-R            ; ...
        ld    a1, v_tmp(zero)           ; ...
        jalr  ra, gp, unify-R           ; ...
        jalr  zero, gp, lv3-R           ; ...
ba_no:
        li    a0, 0                     ; ...
        jalr  zero, gp, lv3-R           ; ...
ba_tint:
        li    a0, at_integer + T_ATM    ; ...
        mv    a1, s2                    ; ...
        jalr  zero, gp, err_type-R      ; ...
ba_tcomp:
        li    a0, at_compound + T_ATM   ; ...
        mv    a1, s3                    ; ...
        jalr  zero, gp, err_type-R      ; ...

; T =.. List
bi_univ:
        jalr  t6, gp, ent6-R            ; s1 goal, s2 T, s3 list, s4 n, s5 block, s6
        mv    s1, a0                    ; ...
        li    a1, 1                     ; ...
        jalr  ra, gp, garg-R            ; ...
        mv    s2, a0                    ; ...
        andi  t0, s2, 7                 ; ...
        beqz  t0, bu_make               ; ...
        li    t1, T_STR                 ; ...
        beq   t0, t1, bu_list           ; ...
        mv    a1, s2                    ; atomic: [T]
        li    a2, at_nil + T_ATM        ; ...
        li    a0, ((at_dot >> 3) << 16) | (2 << 3) | T_FUN ; ...
