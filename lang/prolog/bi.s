        addi  a0, a0, PR_BI             ; ...
        jalr  ra, gp, mrd-R             ; ...
        snez  a0, a0                    ; ...
bib_ret:
        jalr  zero, gp, lv0-R           ; ...
head_funf:
        jalr  t6, gp, ent0-R            ; head_fun as a function
        andi  t0, a0, 7                 ; ...
        beqz  t0, hff_inst              ; ...
        li    t1, T_ATM                 ; ...
        beq   t0, t1, hff_atom          ; ...
        li    t1, T_STR                 ; ...
        bne   t0, t1, hff_type          ; ...
        addi  a0, a0, -T_STR            ; ...
        jalr  ra, gp, mrd-R             ; ...
        jalr  zero, gp, lv0-R           ; ...
hff_atom:
        srli  a0, a0, 3                 ; ...
        slli  a0, a0, 16                ; ...
        ori   a0, a0, T_FUN             ; ...
        jalr  zero, gp, lv0-R           ; ...
hff_inst:
        jalr  zero, gp, err_inst-R      ; ...
hff_type:
        mv    a1, a0                    ; ...
        li    a0, at_callable + T_ATM   ; ...
        jalr  zero, gp, err_type-R      ; ...

; '$now'(T): microseconds since start
bi_now:
        jalr  t6, gp, ent1-R            ; s1 goal
        mv    s1, a0                    ; ...
        jalr  ra, gp, sys_now-R         ; ...
        slli  a1, a0, 3                 ; ...
        ori   a1, a1, T_INT             ; ...
        sd    a1, v_tmp(zero)           ; ...
        mv    a0, s1                    ; ...
        li    a1, 1                     ; ...
        jalr  ra, gp, garg-R            ; ...
        ld    a1, v_tmp(zero)           ; ...
        jalr  ra, gp, unify-R           ; ...
        jalr  zero, gp, lv1-R           ; ...

; '$stats'(L): the machine's counters, as a list of integers (boot.pl's
; statistics/0 names them): calls, heap / trail / choicepoint stack tops,
; the three windows' spills, slides and bytes moved, far cache misses and
; write-backs, atom area and clause store used, findall area top
bi_stats:
        jalr  t6, gp, ent3-R            ; s1 goal, s2 list, s3 i
        mv    s1, a0                    ; ...
        li    s2, at_nil + T_ATM        ; from the last
        li    s3, NSTAT                 ; ...
bst_loop:
        beqz  s3, bst_done              ; ...
        addi  s3, s3, -1                ; ...
        slli  t0, s3, 1                 ; the table: an address and a base to subtract
        slli  t0, t0, 3                 ; ...
        la    t1, stat_tab              ; (far: read through the cache)
        add   a0, t1, t0                ; ...
        sd    a0, v_tmp+8(zero)         ; ...
        jalr  ra, gp, mrd-R             ; the D-LS address of the counter
        ld    t3, 0(a0)                 ; ...
        sd    t3, v_tmp(zero)           ; ...
        ld    a0, v_tmp+8(zero)         ; the base
        addi  a0, a0, 8                 ; ...
        jalr  ra, gp, mrd-R             ; (a D-LS variable holding the base)
        ld    a0, 0(a0)                 ; ...
        ld    t3, v_tmp(zero)           ; ...
        sub   a1, t3, a0                ; ...
        slli  a1, a1, 3                 ; ...
        ori   a1, a1, T_INT             ; ...
        mv    a2, s2                    ; ...
        li    a0, ((at_dot >> 3) << 16) | (2 << 3) | T_FUN ; ...
        jalr  ra, gp, mkstr-R           ; ...
        mv    s2, a0                    ; ...
        j     bst_loop                  ; ...
bst_done:
        mv    a0, s1                    ; ...
        li    a1, 1                     ; ...
        jalr  ra, gp, garg-R            ; ...
        mv    a1, s2                    ; ...
        jalr  ra, gp, unify-R           ; ...
        jalr  zero, gp, lv3-R           ; ...
        .align 8                        ; ...
stat_tab:
        .dword v_infer, v_k0            ; calls (each: a counter, a variable holding its base)
        .dword v_H, v_kheap             ; heap used
        .dword v_TR, v_trail            ; trail used
        .dword v_B, v_cp                ; choicepoint stack used
        .dword wh+W_SPILL, v_k0         ; heap window: spills
        .dword wh+W_SLIDE, v_k0         ; ... slides
        .dword wh+W_BYTES, v_k0         ; ... bytes
        .dword wt+W_SPILL, v_k0         ; trail window
        .dword wt+W_SLIDE, v_k0         ; ...
        .dword wt+W_BYTES, v_k0         ; ...
        .dword wc+W_SPILL, v_k0         ; choicepoint window
        .dword wc+W_SLIDE, v_k0         ; ...
        .dword wc+W_BYTES, v_k0         ; ...
        .dword v_fcmiss, v_k0           ; far cache misses
        .dword v_fcwb, v_k0             ; ... write-backs
        .dword v_atop, v_katom          ; atom area used
        .dword v_dbtop, v_kdb           ; clause store used
        .dword v_fatop, v_kfa           ; findall area used
        .dword v_heapend, v_kheap       ; the heap's size
        .dword v_cpend, v_k0            ; the arena's program memory
NSTAT    = 20                           ; entries
