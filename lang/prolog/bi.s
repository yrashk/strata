        remu  t2, s1, t1                ; ...
        divu  s1, s1, t1                ; ...
        addi  t2, t2, '0'               ; ...
        addi  t0, t0, -1                ; ...
        sb    t2, 0(t0)                 ; ...
        bnez  s1, ia_dig                ; ...
        beqz  s2, ia_copy               ; ...
        addi  t0, t0, -1                ; ...
