; =============================================================================
; write.s: the writer (code units)
; =============================================================================
;
; write_term(Stream, Term, Flags): operators as the atoms' AT_OPS say,
; lists as [a, b|T], {X}, '$VAR'(N) as a letter when numbervars is on, atoms
; quoted when quoted is on and they need it. A variable is _N (N: its offset
; in the heap, in cells).

WF_Q     = 1                            ; quoted
WF_IGN   = 2                            ; ignore_ops
WF_NV    = 4                            ; numbervars

        .data                           ; the writer's state
        .align 8                        ; ...
wr_s:     .dword 1                      ; the stream
wr_fl:    .dword 0                      ; the flags
wr_last:  .dword 0                      ; the class of the last character written (for spacing)
m_uncaught: .asciz "uncaught exception: " ; ...
        .align 8                        ; ...

        .far                            ; code units
        .align 4096                     ; ---- unit: the writer's helpers ----
u_wlow:

; write_term(a0 = stream, a1 = term, a2 = flags)
write_term:
        jalr  t6, gp, ent0-R            ; ...
        sd    a0, wr_s(zero)            ; ...
        sd    a2, wr_fl(zero)           ; ...
        sd    zero, wr_last(zero)       ; ...
        mv    a0, a1                    ; ...
        li    a1, 1200                  ; ...
        la    t6, w_term                ; ...
        xcall ra, c0, t6                ; ...
        jalr  zero, gp, lv0-R           ; ...

; wchar(a0 = character)
wchar:
        jalr  t6, gp, ent0-R            ; ...
        sd    a0, wr_last(zero)         ; ...
        ld    t0, wr_s(zero)            ; user_output: straight into sys.s's buffer
        li    t1, 1                     ; ...
        bne   t0, t1, wc_other          ; ...
        jalr  ra, gp, out_chr-R         ; ...
        jalr  zero, gp, lv0-R           ; ...
wc_other:
        mv    a1, a0                    ; ...
        mv    a0, t0                    ; ...
        la    t6, putc                  ; ...
        xcall ra, c0, t6                ; ...
        jalr  zero, gp, lv0-R           ; ...

; wstr(a0 = D-LS text, a1 = length)
wstr:
        jalr  t6, gp, ent2-R            ; s1 cursor, s2 end
        mv    s1, a0                    ; ...
        add   s2, a0, a1                ; ...
ws_loop:
        bgeu  s1, s2, ws_done           ; ...
        lbu   a0, 0(s1)                 ; ...
        la    t6, wchar                 ; ...
        xcall ra, c0, t6                ; ...
        addi  s1, s1, 1                 ; ...
        j     ws_loop                   ; ...
ws_done:
        jalr  zero, gp, lv2-R           ; ...

; wcstr(a0 = a zero-terminated D-LS text)
wcstr:
        jalr  t6, gp, ent0-R            ; ...
        mv    t0, a0                    ; its length
wcs_len:
        lbu   t1, 0(t0)                 ; ...
        beqz  t1, wcs_go                ; ...
        addi  t0, t0, 1                 ; ...
        j     wcs_len                   ; ...
wcs_go:
        sub   a1, t0, a0                ; ...
        la    t6, wstr                  ; ...
        xcall ra, c0, t6                ; ...
        jalr  zero, gp, lv0-R           ; ...

; w_int(a0 = value): decimal
w_int:
        jalr  t6, gp, ent1-R            ; s1 value
        mv    s1, a0                    ; ...
        bgez  s1, wi_pos                ; ...
        li    a0, '-'                   ; ...
        la    t6, wchar                 ; ...
        xcall ra, c0, t6                ; ...
        sub   s1, zero, s1              ; ...
wi_pos:
        li    t0, NB2 + 40              ; digits, right to left
        li    t1, 10                    ; ...
        mv    t3, s1                    ; ...
wi_dig:
        remu  t2, t3, t1                ; ...
        divu  t3, t3, t1                ; ...
        addi  t2, t2, '0'               ; ...
        addi  t0, t0, -1                ; ...
        sb    t2, 0(t0)                 ; ...
        bnez  t3, wi_dig                ; ...
        mv    a0, t0                    ; ...
        li    t1, NB2 + 40              ; ...
        sub   a1, t1, t0                ; ...
        la    t6, wstr                  ; ...
        xcall ra, c0, t6                ; ...
        jalr  zero, gp, lv1-R           ; ...

; aclass() -> a0: the atom in NB (length in a0 on entry): 0 letters and
; digits from a lower case letter, 1 symbol characters, 2 a solo atom that
; needs no quotes ([] {} ! ;), 3 anything else (it needs quotes)
aclass:
        jalr  t6, gp, ent2-R            ; s1 length, s2 i
        mv    s1, a0                    ; ...
        beqz  s1, ac_quote              ; '' needs them
        li    t0, 2                     ; [] and {}
        bne   s1, t0, ac_one            ; ...
        lbu   t0, NB(zero)              ; ...
        lbu   t1, NB+1(zero)            ; ...
        li    t2, '['                   ; ...
        bne   t0, t2, ac_curly          ; ...
        li    t2, ']'                   ; ...
        beq   t1, t2, ac_solo           ; ...
ac_curly:
        li    t2, '{'                   ; ...
        bne   t0, t2, ac_first          ; ...
        li    t2, '}'                   ; ...
        beq   t1, t2, ac_solo           ; ...
        j     ac_first                  ; ...
ac_one:
        li    t0, 1                     ; ! and ;
        bne   s1, t0, ac_first          ; ...
        lbu   t0, NB(zero)              ; ...
        li    t1, '!'                   ; ...
        beq   t0, t1, ac_solo           ; ...
        li    t1, ';'                   ; ...
        beq   t0, t1, ac_solo           ; ...
ac_first:
        lbu   t0, NB(zero)              ; the first character's class
        li    t1, 128                   ; ...
        bgeu  t0, t1, ac_quote          ; ...
        lbu   t0, rd_ctab(t0)           ; ...
        li    t1, CL_LOW                ; ...
        beq   t0, t1, ac_alnum          ; ...
        li    t1, CL_SYM                ; ...
        beq   t0, t1, ac_sym            ; ...
        j     ac_quote                  ; ...
ac_alnum:
        li    s2, 1                     ; the rest: letters, digits, _
aa_loop:
        bgeu  s2, s1, ac_plain          ; ...
        lbu   t0, NB(s2)                ; ...
        li    t1, 128                   ; ...
        bgeu  t0, t1, ac_quote          ; ...
        lbu   t0, rd_ctab(t0)           ; ...
        addi  t0, t0, -1                ; 1..3
        sltiu t0, t0, 3                 ; ...
        beqz  t0, ac_quote              ; ...
        addi  s2, s2, 1                 ; ...
        j     aa_loop                   ; ...
ac_sym:
        li    s2, 1                     ; the rest: symbol characters
as_loop:
        bgeu  s2, s1, ac_symb           ; ...
        lbu   t0, NB(s2)                ; ...
        li    t1, 128                   ; ...
        bgeu  t0, t1, ac_quote          ; ...
        lbu   t0, rd_ctab(t0)           ; ...
        li    t1, CL_SYM                ; ...
        bne   t0, t1, ac_quote          ; ...
        addi  s2, s2, 1                 ; ...
        j     as_loop                   ; ...
ac_plain:
        li    a0, 0                     ; ...
        jalr  zero, gp, lv2-R           ; ...
ac_symb:
        li    a0, 1                     ; ...
        jalr  zero, gp, lv2-R           ; ...
ac_solo:
        li    a0, 2                     ; ...
        jalr  zero, gp, lv2-R           ; ...
ac_quote:
        li    a0, 3                     ; ...
        jalr  zero, gp, lv2-R           ; ...

; w_atom(a0 = atom): its name, quoted if it must be and quoted is on
w_atom:
        jalr  t6, gp, ent3-R            ; s1 length, s2 i, s3 class
        la    t6, atom_name             ; NB
        xcall ra, c0, t6                ; ...
        mv    s1, a0                    ; ...
        ld    t0, wr_fl(zero)           ; quoted?
        andi  t0, t0, WF_Q              ; ...
        beqz  t0, wa_plain              ; ...
        mv    a0, s1                    ; ...
        la    t6, aclass                ; ...
        xcall ra, c0, t6                ; ...
        li    t0, 3                     ; ...
        beq   a0, t0, wa_quoted         ; ...
wa_plain:
        li    s2, 0                     ; as it is (NB may be reused: one character at a time)
wa_ploop:
        bgeu  s2, s1, wa_done           ; ...
        lbu   a0, NB(s2)                ; ...
        la    t6, wchar                 ; ...
        xcall ra, c0, t6                ; ...
        addi  s2, s2, 1                 ; ...
        j     wa_ploop                  ; ...
wa_quoted:
        li    a0, 0x27                  ; '
        la    t6, wchar                 ; ...
        xcall ra, c0, t6                ; ...
        li    s2, 0                     ; ...
wa_qloop:
        bgeu  s2, s1, wa_qend           ; ...
        lbu   s3, NB(s2)                ; ...
        li    t0, 0x27                  ; ' -> \'
        beq   s3, t0, wa_esc            ; ...
        li    t0, 0x5C                  ; \ -> \\
        beq   s3, t0, wa_esc            ; ...
        li    t0, 10                    ; newline -> \n
        bne   s3, t0, wa_tab            ; ...
        li    s3, 'n'                   ; ...
        j     wa_esc                    ; ...
wa_tab:
        li    t0, 9                     ; tab -> \t
        bne   s3, t0, wa_ch             ; ...
        li    s3, 't'                   ; ...
wa_esc:
        li    a0, 0x5C                  ; ...
        la    t6, wchar                 ; ...
        xcall ra, c0, t6                ; ...
wa_ch:
        mv    a0, s3                    ; ...
        la    t6, wchar                 ; ...
        xcall ra, c0, t6                ; ...
        addi  s2, s2, 1                 ; ...
        j     wa_qloop                  ; ...
wa_qend:
        li    a0, 0x27                  ; ...
        la    t6, wchar                 ; ...
        xcall ra, c0, t6                ; ...
wa_done:
        jalr  zero, gp, lv3-R           ; ...

; wr_uncaught(a0 = ball): "uncaught exception: " and the ball, quoted
wr_uncaught:
        jalr  t6, gp, ent1-R            ; s1 ball
        mv    s1, a0                    ; ...
        li    t0, 1                     ; user_output
        sd    t0, wr_s(zero)            ; ...
        li    a0, m_uncaught            ; ...
        la    t6, wcstr                 ; ...
        xcall ra, c0, t6                ; ...
        li    a0, 1                     ; ...
        mv    a1, s1                    ; ...
        li    a2, WF_Q | WF_NV          ; ...
        la    t6, write_term            ; ...
        xcall ra, c0, t6                ; ...
        li    a0, 10                    ; ...
        la    t6, wchar                 ; ...
        xcall ra, c0, t6                ; ...
        jalr  zero, gp, lv1-R           ; ...

; symstart(a0 = term) -> a0 = 1 if writing it starts with a symbol character:
; a negative number, an atom of symbols, or an operator term of one
symstart:
        jalr  t6, gp, ent1-R            ; s1 term
        jalr  ra, gp, deref-R           ; ...
        mv    s1, a0                    ; ...
        andi  t0, s1, 7                 ; ...
        li    t1, T_INT                 ; ...
        bne   t0, t1, ss_atom           ; ...
        slti  a0, s1, 0                 ; ...
        jalr  zero, gp, lv1-R           ; ...
ss_atom:
        li    t1, T_ATM                 ; ...
        beq   t0, t1, ss_name           ; ...
        li    t1, T_STR                 ; f(...) with f an operator of symbols, as written
        bne   t0, t1, ss_no             ; ...
        addi  a0, s1, -T_STR            ; ...
        jalr  ra, gp, mrd-R             ; ...
        srli  t0, a0, 3                 ; arity 1 or 2
        andi  t0, t0, 0x1FFF            ; ...
        addi  t0, t0, -1                ; ...
        li    t1, 2                     ; ...
        bgeu  t0, t1, ss_no             ; ...
        srli  a0, a0, 16                ; ...
        slli  a0, a0, 3                 ; ...
        ori   s1, a0, T_ATM             ; ...
        mv    a0, s1                    ; ...
        la    t6, get_ops               ; an operator?
        xcall ra, c0, t6                ; ...
        beqz  a0, ss_no                 ; ...
ss_name:
        mv    a0, s1                    ; the first character of its name
        la    t6, atom_name             ; ...
        xcall ra, c0, t6                ; ...
        beqz  a0, ss_no                 ; ...
        lbu   t0, NB(zero)              ; ...
        li    t1, 128                   ; ...
        bgeu  t0, t1, ss_no             ; ...
        lbu   t0, rd_ctab(t0)           ; ...
        addi  a0, t0, -CL_SYM           ; ...
        seqz  a0, a0                    ; ...
        jalr  zero, gp, lv1-R           ; ...
ss_no:
        li    a0, 0                     ; ...
        jalr  zero, gp, lv1-R           ; ...
u_wlow_end:

        .align 4096                     ; ---- unit: terms ----
u_wterm:

; w_term(a0 = term, a1 = the highest priority allowed without brackets)
w_term:
        jalr  t6, gp, ent6-R            ; s1 term, s2 max, s3 functor, s4 arity, s5 ops, s6 priority
        mv    s2, a1                    ; ...
        li    t0, SPMIN + 256           ; deep enough?
        bltu  sp, t0, wt_deep           ; ...
        jalr  ra, gp, deref-R           ; ...
        mv    s1, a0                    ; ...
        andi  t0, s1, 7                 ; ...
        beqz  t0, wt_var                ; ...
        li    t1, T_INT                 ; ...
        beq   t0, t1, wt_int            ; ...
        li    t1, T_ATM                 ; ...
        beq   t0, t1, wt_atom           ; ...
        li    t1, T_STR                 ; ...
        beq   t0, t1, wt_str            ; ...
        li    a0, '?'                   ; (a template variable: never seen here)
        la    t6, wchar                 ; ...
        xcall ra, c0, t6                ; ...
        j     wt_ret                    ; ...
wt_deep:
        jalr  zero, gp, err_depth-R     ; ...
wt_var:
        li    a0, '_'                   ; _N
        la    t6, wchar                 ; ...
        xcall ra, c0, t6                ; ...
        li    t0, A_HEAP                ; ...
        sub   a0, s1, t0                ; ...
        srai  a0, a0, 3                 ; ...
        la    t6, w_int                 ; ...
        xcall ra, c0, t6                ; ...
        j     wt_ret                    ; ...
wt_int:
        srai  a0, s1, 3                 ; ...
        la    t6, w_int                 ; ...
        xcall ra, c0, t6                ; ...
        j     wt_ret                    ; ...
wt_atom:
        mv    a0, s1                    ; an operator as an atom: (op) where it would be read as one
        la    t6, get_ops               ; ...
        xcall ra, c0, t6                ; ...
        beqz  a0, wt_aplain             ; ...
        li    t0, 999                   ; (only as an argument of an operator or a compound)
        bgtu  s2, t0, wt_aplain         ; ...
        li    t0, at_comma + T_ATM      ; (',' is quoted anyway)
        beq   s1, t0, wt_aplain         ; ...
        li    t0, at_nil + T_ATM        ; ...
        beq   s1, t0, wt_aplain         ; ...
        li    a0, '('                   ; ...
        la    t6, wchar                 ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s1                    ; ...
        la    t6, w_atom                ; ...
        xcall ra, c0, t6                ; ...
        li    a0, ')'                   ; ...
        la    t6, wchar                 ; ...
        xcall ra, c0, t6                ; ...
        j     wt_ret                    ; ...
wt_aplain:
        mv    a0, s1                    ; ...
        la    t6, w_atom                ; ...
        xcall ra, c0, t6                ; ...
        j     wt_ret                    ; ...
wt_str:
        addi  a0, s1, -T_STR            ; the functor
        jalr  ra, gp, mrd-R             ; ...
        mv    s3, a0                    ; ...
        srli  s4, a0, 3                 ; ...
        andi  s4, s4, 0x1FFF            ; ...
        li    t0, ((at_dot >> 3) << 16) | (2 << 3) | T_FUN ; a list
        beq   s3, t0, wt_list           ; ...
        li    t0, ((at_curly >> 3) << 16) | (1 << 3) | T_FUN ; {X}
        beq   s3, t0, wt_curly          ; ...
        ld    t0, wr_fl(zero)           ; '$VAR'(N)
        andi  t1, t0, WF_NV             ; ...
        beqz  t1, wt_noVAR              ; ...
        li    t1, ((at_dollar_var >> 3) << 16) | (1 << 3) | T_FUN ; ...
        beq   s3, t1, wt_VAR            ; ...
wt_noVAR:
        andi  t1, t0, WF_IGN            ; operators?
        bnez  t1, wt_canon              ; ...
        srli  a0, s3, 16                ; the name's operators
        slli  a0, a0, 3                 ; ...
        ori   a0, a0, T_ATM             ; ...
        la    t6, get_ops               ; ...
        xcall ra, c0, t6                ; ...
        mv    s5, a0                    ; ...
        li    t0, 2                     ; infix?
        beq   s4, t0, wt_infix          ; ...
        li    t0, 1                     ; prefix or postfix?
        beq   s4, t0, wt_prefix         ; ...
wt_canon:
        srli  a0, s3, 16                ; name(Args)
        slli  a0, a0, 3                 ; ...
        ori   a0, a0, T_ATM             ; ...
        la    t6, w_atom                ; ...
        xcall ra, c0, t6                ; ...
        li    a0, '('                   ; ...
        la    t6, wchar                 ; ...
        xcall ra, c0, t6                ; ...
        li    s6, 1                     ; ...
wt_carg:
        mv    a0, s1                    ; ...
        mv    a1, s6                    ; ...
        jalr  ra, gp, garg-R            ; ...
        li    a1, 999                   ; ...
        la    t6, w_term                ; ...
        xcall ra, c0, t6                ; ...
        beq   s6, s4, wt_cend           ; ...
        li    a0, ','                   ; ...
        la    t6, wchar                 ; ...
        xcall ra, c0, t6                ; ...
        addi  s6, s6, 1                 ; ...
        j     wt_carg                   ; ...
wt_cend:
        li    a0, ')'                   ; ...
        la    t6, wchar                 ; ...
        xcall ra, c0, t6                ; ...
        j     wt_ret                    ; ...
wt_list:
        li    a0, '['                   ; [
        la    t6, wchar                 ; ...
        xcall ra, c0, t6                ; ...
wt_litem:
        mv    a0, s1                    ; the element
        li    a1, 1                     ; ...
        jalr  ra, gp, garg-R            ; ...
        li    a1, 999                   ; ...
        la    t6, w_term                ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s1                    ; the tail
        li    a1, 2                     ; ...
        jalr  ra, gp, garg-R            ; ...
        mv    s1, a0                    ; ...
        li    t0, at_nil + T_ATM        ; ]
        beq   s1, t0, wt_lend           ; ...
        andi  t0, s1, 7                 ; another pair: ,
        li    t1, T_STR                 ; ...
        bne   t0, t1, wt_ltail          ; ...
        addi  a0, s1, -T_STR            ; ...
        jalr  ra, gp, mrd-R             ; ...
        li    t0, ((at_dot >> 3) << 16) | (2 << 3) | T_FUN ; ...
        bne   a0, t0, wt_ltail          ; ...
        li    a0, ','                   ; ...
        la    t6, wchar                 ; ...
        xcall ra, c0, t6                ; ...
        j     wt_litem                  ; ...
wt_ltail:
        li    a0, '|'                   ; |Tail
        la    t6, wchar                 ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s1                    ; ...
        li    a1, 999                   ; ...
        la    t6, w_term                ; ...
        xcall ra, c0, t6                ; ...
wt_lend:
        li    a0, ']'                   ; ...
        la    t6, wchar                 ; ...
        xcall ra, c0, t6                ; ...
        j     wt_ret                    ; ...
wt_curly:
        li    a0, '{'                   ; {X}
        la    t6, wchar                 ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s1                    ; ...
        li    a1, 1                     ; ...
        jalr  ra, gp, garg-R            ; ...
        li    a1, 1200                  ; ...
        la    t6, w_term                ; ...
        xcall ra, c0, t6                ; ...
        li    a0, '}'                   ; ...
        la    t6, wchar                 ; ...
        xcall ra, c0, t6                ; ...
        j     wt_ret                    ; ...
wt_VAR:
        mv    a0, s1                    ; '$VAR'(N): a letter, then N // 26 if not 0
        li    a1, 1                     ; ...
        jalr  ra, gp, garg-R            ; ...
        andi  t0, a0, 7                 ; (only an integer)
        li    t1, T_INT                 ; ...
        bne   t0, t1, wt_noVAR2         ; ...
        srai  s6, a0, 3                 ; ...
        li    t0, 26                    ; ...
        rem   a0, s6, t0                ; ...
        addi  a0, a0, 'A'               ; ...
        la    t6, wchar                 ; ...
        xcall ra, c0, t6                ; ...
        li    t0, 26                    ; ...
        div   a0, s6, t0                ; ...
        beqz  a0, wt_ret                ; ...
        la    t6, w_int                 ; ...
        xcall ra, c0, t6                ; ...
        j     wt_ret                    ; ...
wt_noVAR2:
        ld    t0, wr_fl(zero)           ; ...
        j     wt_noVAR                  ; ...

wt_infix:
        srli  t0, s5, 16                ; the infix operator
        li    t1, 0xFFFF                ; ...
        and   t0, t0, t1                ; ...
        beqz  t0, wt_canon              ; none
        andi  s6, t0, 0x7FF             ; priority
        srli  t2, t0, 12                ; type: the sides' limits on the stack
        addi  t3, s6, -1                ; ...
        addi  t4, s6, -1                ; ...
        li    t5, OPT_YFX               ; ...
        bne   t2, t5, wi_l              ; ...
        mv    t3, s6                    ; ...
wi_l:
        li    t5, OPT_XFY               ; ...
        bne   t2, t5, wi_r              ; ...
        mv    t4, s6                    ; ...
wi_r:
        addi  sp, sp, -16               ; ...
        sd    t3, 0(sp)                 ; left limit
        sd    t4, 8(sp)                 ; right limit
        bleu  s6, s2, wi_open           ; brackets if too loose for here
        li    a0, '('                   ; ...
        la    t6, wchar                 ; ...
        xcall ra, c0, t6                ; ...
wi_open:
        mv    a0, s1                    ; the left side
        li    a1, 1                     ; ...
        jalr  ra, gp, garg-R            ; ...
        ld    a1, 0(sp)                 ; ...
        la    t6, w_term                ; ...
        xcall ra, c0, t6                ; ...
        srli  a0, s3, 16                ; the operator
        slli  a0, a0, 3                 ; ...
        ori   a0, a0, T_ATM             ; ...
        li    t0, at_comma + T_ATM      ; , : no spaces, no quotes
        bne   a0, t0, wi_op             ; ...
        li    a0, ','                   ; ...
        la    t6, wchar                 ; ...
        xcall ra, c0, t6                ; ...
        j     wi_right                  ; ...
wi_op:
        mv    s5, a0                    ; ...
        la    t6, atom_name             ; letters: spaces around it
        xcall ra, c0, t6                ; ...
        lbu   t0, NB(zero)              ; ...
        li    t1, 128                   ; ...
        bgeu  t0, t1, wi_alpha          ; ...
        lbu   t0, rd_ctab(t0)           ; ...
        li    t1, CL_LOW                ; ...
        beq   t0, t1, wi_alpha          ; ...
        li    t1, CL_SYM                ; symbols: none, except before a negative number
        beq   t0, t1, wi_sym            ; ...
        mv    a0, s5                    ; (anything else: ; | ...)
        la    t6, w_atom                ; ...
        xcall ra, c0, t6                ; ...
        j     wi_right                  ; ...
wi_alpha:
        li    a0, ' '                   ; ...
        la    t6, wchar                 ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s5                    ; ...
        la    t6, w_atom                ; ...
        xcall ra, c0, t6                ; ...
        li    a0, ' '                   ; ...
        la    t6, wchar                 ; ...
        xcall ra, c0, t6                ; ...
        j     wi_right                  ; ...
wi_sym:
        mv    a0, s5                    ; ...
        la    t6, w_atom                ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s1                    ; a negative number or a symbol atom on the right: a space
        li    a1, 2                     ; ...
        jalr  ra, gp, garg-R            ; ...
        la    t6, symstart              ; ...
        xcall ra, c0, t6                ; ...
        beqz  a0, wi_right              ; ...
        li    a0, ' '                   ; ...
        la    t6, wchar                 ; ...
        xcall ra, c0, t6                ; ...
wi_right:
        mv    a0, s1                    ; the right side
        li    a1, 2                     ; ...
        jalr  ra, gp, garg-R            ; ...
        ld    a1, 8(sp)                 ; ...
        la    t6, w_term                ; ...
        xcall ra, c0, t6                ; ...
        addi  sp, sp, 16                ; ...
        bleu  s6, s2, wt_ret            ; ...
        li    a0, ')'                   ; ...
        la    t6, wchar                 ; ...
        xcall ra, c0, t6                ; ...
        j     wt_ret                    ; ...

wt_prefix:
        li    t1, 0xFFFF                ; a prefix operator?
        and   t0, s5, t1                ; ...
        beqz  t0, wt_postfix            ; ...
        li    t1, at_minus + T_ATM      ; (- and + of a number: - 1, not -1)
        andi  s6, t0, 0x7FF             ; priority
        srli  t2, t0, 12                ; its operand's limit
        addi  t3, s6, -1                ; ...
        li    t5, OPT_FY                ; ...
        bne   t2, t5, wp_l              ; ...
        mv    t3, s6                    ; ...
wp_l:
        addi  sp, sp, -16               ; ...
        sd    t3, 0(sp)                 ; ...
        bleu  s6, s2, wp_open           ; ...
        li    a0, '('                   ; ...
        la    t6, wchar                 ; ...
        xcall ra, c0, t6                ; ...
wp_open:
        srli  a0, s3, 16                ; the operator
        slli  a0, a0, 3                 ; ...
        ori   a0, a0, T_ATM             ; ...
        mv    s5, a0                    ; ...
        la    t6, w_atom                ; ...
        xcall ra, c0, t6                ; ...
        mv    a0, s1                    ; a space if the operand would run into it
        li    a1, 1                     ; ...
        jalr  ra, gp, garg-R            ; ...
        sd    a0, 8(sp)                 ; ...
        andi  t0, a0, 7                 ; a number: always
        li    t1, T_INT                 ; ...
        beq   t0, t1, wp_space          ; ...
        ld    t0, wr_last(zero)         ; the operator ends in a letter: always
        li    t1, 128                   ; ...
        bgeu  t0, t1, wp_space          ; ...
        lbu   t0, rd_ctab(t0)           ; ...
        addi  t0, t0, -1                ; ...
        sltiu t0, t0, 3                 ; ...
        bnez  t0, wp_space              ; ...
        ld    a0, 8(sp)                 ; a symbol operand
        la    t6, symstart              ; ...
        xcall ra, c0, t6                ; ...
        beqz  a0, wp_arg                ; ...
wp_space:
        li    a0, ' '                   ; ...
        la    t6, wchar                 ; ...
        xcall ra, c0, t6                ; ...
wp_arg:
        ld    a0, 8(sp)                 ; ...
        ld    a1, 0(sp)                 ; ...
        la    t6, w_term                ; ...
        xcall ra, c0, t6                ; ...
        addi  sp, sp, 16                ; ...
        bleu  s6, s2, wt_ret            ; ...
        li    a0, ')'                   ; ...
        la    t6, wchar                 ; ...
        xcall ra, c0, t6                ; ...
        j     wt_ret                    ; ...

wt_postfix:
        srli  t0, s5, 32                ; a postfix operator?
        li    t1, 0xFFFF                ; ...
        and   t0, t0, t1                ; ...
        beqz  t0, wt_canon              ; ...
        andi  s6, t0, 0x7FF             ; ...
        srli  t2, t0, 12                ; ...
        addi  t3, s6, -1                ; ...
        li    t5, OPT_YF                ; ...
        bne   t2, t5, wq_l              ; ...
        mv    t3, s6                    ; ...
wq_l:
        addi  sp, sp, -16               ; ...
        sd    t3, 0(sp)                 ; ...
        bleu  s6, s2, wq_open           ; ...
        li    a0, '('                   ; ...
        la    t6, wchar                 ; ...
        xcall ra, c0, t6                ; ...
wq_open:
        mv    a0, s1                    ; ...
        li    a1, 1                     ; ...
        jalr  ra, gp, garg-R            ; ...
        ld    a1, 0(sp)                 ; ...
        la    t6, w_term                ; ...
        xcall ra, c0, t6                ; ...
        srli  a0, s3, 16                ; ...
        slli  a0, a0, 3                 ; ...
        ori   a0, a0, T_ATM             ; ...
        la    t6, w_atom                ; ...
        xcall ra, c0, t6                ; ...
        addi  sp, sp, 16                ; ...
        bleu  s6, s2, wt_ret            ; ...
        li    a0, ')'                   ; ...
        la    t6, wchar                 ; ...
        xcall ra, c0, t6                ; ...
wt_ret:
        jalr  zero, gp, lv6-R           ; ...

