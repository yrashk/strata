; =============================================================================
; lang/forth/os/boot.s: what the StrataOS image puts directly into the I-LS
; =============================================================================
;
; Included by forth.s in place of its .text section. The kernel loads only
; this stub (the image's code section) at I-LS 0x8000; the Forth kernel proper
; is in the image's .far section, which StrataOS places in the arena at its
; own offsets: [0x8000, kend) of the arena is an identity mirror of the I-LS.
;
; Thread 0 (or the only thread) declares that mirror with svc SET_MIRROR
; *before* it installs anything: from then on the dispatcher reloads I-LS
; 0x8000.. from the mirror on every switch-in, so the kernel and every word
; compiled later survive preemption. That is also why the stub exists twice:
; the mirror replaces the image's code, so its first bytes must be this very
; stub (a thread can be switched out between the svc and the jump). The copy
; in .far below assembles to the same bytes: branches are pc-relative and the
; copy sits at the same addresses (far offset == I-LS address).
;
; Another thread of a `forth -n N` process waits for thread 0 to give it a
; page of its own (32 KiB, already holding a copy of thread 0's mirror), makes
; that page its code mirror, installs the kernel from it and goes on in
; plat_worker (platform.s).

SVC_MIRROR = 7                          ; svc SET_MIRROR: a1 = arena offset, a2 = length

        .text                           ; instruction Local Store, at ORIGIN
_start:                                 ; every thread starts here
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:                                   ; which thread are we?
        csrr  t0, corecount             ; t0 = cores in our window (0: a single thread)
        beqz  t0, boot0                 ; one thread: it is the interpreter
        csrr  t0, coreid                ; t0 = our number within the window
        bnez  t0, bootw                 ; another thread: a worker
boot0:                                  ; thread 0: declare the mirror, install the kernel
        li    a0, SVC_MIRROR            ; a0 = SET_MIRROR
        li    a1, ORIGIN                ; a1 = arena offset of the mirror (an identity map)
        li    a2, CODE_LIMIT - ORIGIN   ; a2 = all of the program's code range
        svc                             ; switch-ins reload the I-LS from the mirror now
        li    t0, KSTART                ; t0 = I-LS address of the kernel, also its c0 offset
        li    t1, kend - KSTART         ; t1 = kernel bytes (a multiple of 8)
        tgetx tg13, t0, c0, t0, t1      ; arena -> I-LS: the kernel arrives
        la    t0, cold                  ; t0 = the kernel's entry (fetching it waits for the tgetx)
        jr    t0                        ; go
bootw:                                  ; a worker thread: wait for our page
        ctake c0, zero                  ; the page, from thread 0 (the dispatcher emulates ctake)
        la    t0, pl_wh                 ; t0 = D-LS address for the page's header
        li    t1, PL_WHDR               ; t1 = where it is in the page
        li    t2, 16                    ; t2 = two words
        tget  tg13, t0, c0, t1, t2      ; the page's arena offset, the end of its code
        li    a0, SVC_MIRROR            ; a0 = SET_MIRROR
        ld    a1, pl_wh(zero)           ; a1 = arena offset of the page: all of it is the mirror
        li    a2, CODE_LIMIT - ORIGIN   ; a2 = all of the program's code range
        svc                             ; our switch-ins reload the I-LS from our page now
        li    t0, KSTART                ; t0 = I-LS address of the kernel
        ld    t1, pl_wh+8(zero)         ; t1 = end of the code thread 0 copied into the page
        sub   t1, t1, t0                ; t1 = bytes
        li    t3, KSTART - ORIGIN       ; t3 = the kernel's offset in the page
        tgetx tg13, t0, c0, t3, t1      ; page -> I-LS
        la    t0, plat_worker           ; t0 = the worker's entry in the kernel
        jr    t0                        ; go

        .org  TRAMP                     ; the trampolines (xexec installs into these)
tramp:  .space NTRAMP * 8               ; 8 slots: <instruction> ret

; ---- the embedded source text ----------------------------------------------------
; build/forth-os/corefs.s is generated by the Makefile from core.fs and
; os/os.fs: one .ascii line per source line. It sits below the mirror (an
; image is at most 128 KiB, and a far section is stored from its lowest
; address to its highest); the assembler refuses the .org below if the text
; outgrows these 32 KiB.
        .far                            ; system memory: the arena
        .org  FAR_SRC                   ; arena offset 0
core_fs:                                ; first byte of the text
        .include "corefs.s"             ; the text, as .ascii lines
core_fs_end:                            ; one past the last byte

; ---- the same stub again, in the mirror ------------------------------------------
; Keep this copy identical to the code above, instruction for instruction.
        .org  ORIGIN                    ; far offset == I-LS address
m_start:                                ; mirror of _start
        j     m_main                    ; skip the marker
        .word 0x32535953                ; "SYS2"
m_main:                                 ; which thread are we?
        csrr  t0, corecount             ; t0 = cores in our window (0: a single thread)
        beqz  t0, m_boot0               ; one thread: it is the interpreter
        csrr  t0, coreid                ; t0 = our number within the window
        bnez  t0, m_bootw               ; another thread: a worker
m_boot0:                                ; thread 0: declare the mirror, install the kernel
        li    a0, SVC_MIRROR            ; a0 = SET_MIRROR
        li    a1, ORIGIN                ; a1 = arena offset of the mirror (an identity map)
        li    a2, CODE_LIMIT - ORIGIN   ; a2 = all of the program's code range
        svc                             ; switch-ins reload the I-LS from the mirror now
        li    t0, KSTART                ; t0 = I-LS address of the kernel, also its c0 offset
        li    t1, kend - KSTART         ; t1 = kernel bytes (a multiple of 8)
        tgetx tg13, t0, c0, t0, t1      ; arena -> I-LS: the kernel arrives
        la    t0, cold                  ; t0 = the kernel's entry (fetching it waits for the tgetx)
        jr    t0                        ; go
m_bootw:                                ; a worker thread: wait for our page
