; =============================================================================
; lang/forth/guest/init.s: plat_init, the guest platform's start-up
; =============================================================================
;
; Run once, by cold, before core.fs is compiled. forth.s includes this file in
; its start-up part (kboot..kend), which compiled code later overwrites.
;
; The arena (c0, the writable part of what StrataOS gave the guest: its size
; less the image region at its top) is cut like bare metal's 64 MiB, only
; smaller and without a framebuffer:
;   c0  [0, 1 MiB)           the kernel's: I-LS mirror, the source text, snapshot
;   c5  [1 MiB, +4 KiB)      core 0's console message buffer
;   c1  [+4 KiB, +8 KiB)     the job board, made atomic (copyable)
;       then per worker      a 64 KiB private page and a 4 KiB message buffer
;   c8  [2 MiB, the end)     the heap behind far@ / far!
; Workers get their page, a copy of the board and their buffer, in that order
; (guest/boot.s takes them). At most 15 cores: 14 workers fit below 2 MiB.

PL_SYS     = 0x100000                   ; the kernel keeps [0, 1 MiB)
PL_HEAP    = 0x200000                   ; the heap starts at 2 MiB
PL_PAGE    = 0x10000                    ; a worker's private page
PL_BUF     = 4096                       ; a message buffer (StrataOS takes only 4 KiB requests from a guest)

; plat_init: carve the capabilities, set up the workers, v_ncores
plat_init:                              ; core 0, once
        csrr  t0, ncores                ; the guest's cores (corecount) are ours
        sd    t0, v_ncores(zero)        ; ...
        cclear c5                       ; nothing but c0, c2..c4 is ours yet
        cclear c6                       ; ...
        cclear c7                       ; ...
        cclear c8                       ; ...
        cclear c9                       ; (no framebuffer: gfx words fault)
        cclear c10                      ; ...
        cclear c11                      ; ...
        cclear c12                      ; (no cluster store either)
        cclear c13                      ; ...
        cclear c14                      ; ...
        cclear c15                      ; ...
        li    t0, PL_SYS                ; c0 = the kernel's, c10 = from 1 MiB on
        csplit c10, c0, t0              ; ...
        li    t0, PL_BUF                ; c5 = core 0's message buffer
        csplit c11, c10, t0             ; ...
        cmov  c5, c10                   ; ...
        cmov  c10, c11                  ; ...
        clen  t0, c10                   ; room for the board, the workers and a heap?
        li    t1, PL_HEAP - PL_SYS + 0x100000 ; (at least 1 MiB of heap: a 4 MiB arena)
        bltu  t0, t1, pi_small          ; no
        li    t0, PL_HEAP - PL_SYS - PL_BUF ; c8 = the heap [2 MiB, end), c10 = below it
        csplit c8, c10, t0              ; ...
        li    t0, PL_BUF                ; c1 = the board's 4 KiB
        csplit c11, c10, t0             ; ...
        catomic c1, c10                 ; the board, atomics only, copyable (c10 is empty now)
        cmov  c10, c11                  ; the rest back in c10
        li    a0, 1                     ; worker 1 first
pi_loop:                                ; one worker per iteration
        ld    t1, v_ncores(zero)        ; ...
        bgeu  a0, t1, pi_done           ; all set up
        li    t0, PL_PAGE               ; its page
        csplit c11, c10, t0             ; ...
        cgive c10, a0                   ; the page is the worker's now
        cmov  c10, c11                  ; ...
        cgive c1, a0                    ; a copy of the board
        li    t0, PL_BUF                ; its message buffer
        csplit c11, c10, t0             ; ...
        cgive c10, a0                   ; ...
        cmov  c10, c11                  ; the rest back in c10
        addi  a0, a0, 1                 ; next worker
        j     pi_loop                   ; ...
pi_done:                                ; ...
        ret                             ; done
pi_small:                               ; the arena is too small: say so and stop
        la    a0, s_gsmall              ; ...
        li    a1, s_gsmall_e - s_gsmall ; ...
        call  plat_write                ; ...
        li    a0, 1                     ; ...
        j     plat_bye                  ; give the console back and halt
