def pdf_link(labels, lab, text=None):
    info = labels.get(lab)
    return '<a class="pdf-ref" href="%s#nameddest=%s" title="This in the PDF manual">%s</a>' % (
        PDF, info["dest"], text or ("PDF §" + info["num"]))


# ---------------------------------------------------------------- ISA page
def iset_chapters():
    """The instruction chapters of ch-iset.tex: [(key, label, title, intro LaTeX)]."""
    s = T.strip_comments(T.read(os.path.join(MANUAL, "ch-iset.tex")))
    out = []
    for m in re.finditer(r"\\chapter\{([^}]*)\}\\label\{(ch:i-([a-z]+))\}(.*?)\\input\{gen-summary-\3\}", s, re.S):
        out.append((m.group(3), m.group(2), m.group(1), m.group(4).strip()))
    assert [k for (k, _, _, _) in out] == list(geninsns.CHAPTERS), out
    return out


def opcode_text(e):
    t = "0x%02X %s" % (geninsns.OP[e["opname"]], e["opname"])
    f = e["funct"]
    if f and "=" not in f:
        f = "funct = " + f
    return t + (", " + f if f else "")


def entry_html(e, labels, ctx):
    key = insn_key(e)
    info = labels.get("insn:" + key)
    h = ctx_html = lambda s: T.tex_to_html(s, ctx)  # noqa: E731
    syntax = "\n".join(e["syntax"])
    if e["exc"]:
        rows = "".join("<tr><td class=\"sf\">%s</td><td>%s</td><td>%s</td></tr>" % (
            esc(c), h(cond), h(tv)) for (c, cond, tv) in e["exc"])
        exc = ('<div class="tbl"><table class="exc"><thead><tr><th>Cause</th><th>Condition (checked in this '
               'order)</th><th><code>tval</code></th></tr></thead><tbody>%s</tbody></table></div>' % rows)
    else:
        exc = "<p>%s</p>" % h(geninsns.no_exc(e))
    notes = '<h4>Notes</h4>\n<p>%s</p>' % h(e["notes"]) if e["notes"] else ""
    search = " ".join([key, e["title"], syntax, e["opname"], e["fmt"] + "-format",
                       geninsns.CHAPTERS[e["chapter"]]]).lower()
    return """<article class="insn" id="%(id)s" data-k="%(k)s">
<header class="insn-h">
  <h3><a href="#%(id)s"><code>%(mn)s</code></a></h3>
  <p class="insn-t">%(title)s</p>
  <p class="insn-meta"><span>%(fmt)s format</span><span>op %(op)s</span><span>%(pdf)s</span></p>
</header>
<p>%(desc)s</p>
<h4>Encoding</h4>
%(enc)s
<h4>Assembler syntax</h4>
<pre class="syn"><code class="language-strata-asm">%(syn)s</code></pre>
<h4>Operation</h4>
%(op_html)s
<h4>Exceptions</h4>
%(exc)s
%(notes)s
</article>""" % dict(id=insn_id(key), k=esc(search), mn=esc(e["mn"]), title=h(e["title"]), fmt=esc(e["fmt"]),
                     op=esc(opcode_text(e)), pdf=pdf_link(labels, "insn:" + key, "PDF §" + info["num"]),
                     desc=h(e["desc"]), enc=T.encoding_html(e["lay"]), syn=esc(syntax),
                     op_html=T.pseudo_html(e["op"]), exc=exc, notes=notes)


def opmap_html():
    names = {v: k for (k, v) in geninsns.OP.items()}
    by_op = {}
    for e in geninsns.INSNS:
        by_op.setdefault(e["opname"], []).append(insn_key(e))
    head = "".join("<th><code>%s</code></th>" % geninsns.b(i, 3) for i in range(8))
    rows = []
    for r in range(8):
        cells = []
        for c in range(8):
            v = r * 8 + c
            if v in names:
                n = names[v]
                first = by_op[n][0]
                tip = " ".join(by_op[n])
                cells.append('<td><a href="#%s" title="%s"><code>%s</code></a><em>0x%02X</em></td>'
                             % (insn_id(first), esc(tip), esc(n), v))
            else:
                cells.append('<td class="nil"></td>')
        rows.append("<tr><th><code>%s</code></th>%s</tr>" % (geninsns.b(r, 3), "".join(cells)))
    return '<div class="tbl"><table class="opmap"><thead><tr><th></th>%s</tr></thead><tbody>%s</tbody></table></div>' % (
        head, "".join(rows))


def isa_page(labels, anchors):
    ctx = T.Ctx(labels, "isa", anchors, PDF, lambda k: "#" + insn_id(k))
    chapters = iset_chapters()
    side, main = [], []
    side.append('    <div class="doc-find"><input id="filter" type="search" placeholder="Filter instructions…  ( / )" '
                'autocomplete="off" spellcheck="false" aria-label="Filter instructions by mnemonic, name or syntax">'
                '<p id="count" class="doc-count" aria-live="polite"></p></div>')
    side.append('    <details class="doc-ix" id="ix" open><summary>Index</summary><nav class="doc-toc" aria-label="Instructions">')
    for (ch, lab, title, intro) in chapters:
        lst = [e for e in geninsns.INSNS if e["chapter"] == ch]
        info = labels.get(lab)
        side.append('      <div class="ix-group" data-ch="%s"><a class="ix-ch" href="#%s"><span>%s</span><em>%d</em></a>' % (
            ch, lab.replace(":", "-"), T.tex_to_html(title, ctx), len(lst)))
        for e in lst:
            k = insn_key(e)
            side.append('        <a class="ix" href="#%s" data-for="%s"><code>%s</code><span>%s</span></a>' % (
                insn_id(k), insn_id(k), esc(k), T.tex_to_html(e["title"], ctx)))
        side.append("      </div>")
        # the chapter
        rows = "".join('<tr data-for="%s"><td><a href="#%s"><code>%s</code></a></td><td>%s</td><td class="ctr">%s</td></tr>'
                       % (insn_id(insn_key(e)), insn_id(insn_key(e)), esc(insn_key(e)), T.tex_to_html(e["title"], ctx),
                          esc(e["fmt"])) for e in lst)
        main.append('<section class="chap" id="%s" data-ch="%s">\n<h2><span class="num">Chapter %s</span>%s %s</h2>\n%s\n'
                    '<div class="tbl summary"><table><thead><tr><th>Mnemonic</th><th>Operation</th><th>Format</th></tr>'
                    '</thead><tbody>%s</tbody></table></div>\n%s\n</section>' % (
                        lab.replace(":", "-"), ch, info["num"], T.tex_to_html(title, ctx), pdf_link(labels, lab, "PDF"),
                        T.blocks(intro, ctx), rows,
                        "\n".join(entry_html(e, labels, ctx) for e in lst)))
    side.append('      <div class="ix-group" id="ix-opcodes"><a class="ix-ch" href="#opcodes"><span>Opcode map and index</span></a></div>')
    side.append("    </nav></details>")
    side.append('    <p class="doc-keys"><kbd>/</kbd> filter · <kbd>Enter</kbd> first match · <kbd>Esc</kbd> clear</p>')

    # the opcode map and the alphabetical index
    om = labels.get("tab:opmap")
    ix = labels.get("tab:insindex")
    alpha = "".join('<tr data-for="%s"><td><a href="#%s"><code>%s</code></a></td><td>%s</td><td><code>0x%02X</code> %s</td>'
                    '<td>%s</td><td class="rgt">%s</td></tr>' % (
                        insn_id(insn_key(e)), insn_id(insn_key(e)), esc(insn_key(e)), T.tex_to_html(e["title"], ctx),
                        geninsns.OP[e["opname"]], esc(e["opname"]), esc(e["funct"]),
                        pdf_link(labels, "insn:" + insn_key(e), labels.get("insn:" + insn_key(e))["num"]))
                    for e in sorted(geninsns.INSNS, key=insn_key))
    main.append('''<section class="chap" id="opcodes">
<h2><span class="num">Tables</span>Opcode map and instruction index</h2>
<p>Every instruction is one 32-bit little-endian word; bits 31:26 hold the primary opcode. The formats
and the rules for reserved bits are in the <a href="../arch/#ch-encoding">encoding chapter of the
architecture outline</a>.</p>
<figure class="tblfig" id="tab-opmap"><figcaption><span class="tn">Table %s</span> %s</figcaption>%s</figure>
<figure class="tblfig" id="tab-insindex"><figcaption><span class="tn">Table %s</span> %s</figcaption>
<div class="tbl"><table class="alpha"><thead><tr><th>Mnemonic</th><th>Description</th><th>Opcode</th><th>Function</th><th class="rgt">§</th></tr></thead>
<tbody>%s</tbody></table></div></figure>
</section>''' % (om["num"], T.tex_to_html(om["title"], ctx), opmap_html(), ix["num"], T.tex_to_html(ix["title"], ctx), alpha))

    n = len(geninsns.INSNS)
    head = '''<header class="doc-head">
  <p class="kicker">Architecture Reference Manual · Part II</p>
  <h1>The instruction set</h1>
  <p class="doc-meta"><span>%d instructions</span><span>%d chapters</span><span>generated from the manual's source</span></p>
  <p class="doc-desc">Every Strata instruction, as the <a href="%s">Architecture Reference Manual</a>
    describes it: encoding, assembler syntax, operation in pseudocode, exceptions in the order they are
    checked, and notes. The entries are generated from the same data as the PDF; each links to its
    section there. Link to any instruction as <code>isa/#insn-<i>mnemonic</i></code>, e.g.
    <a href="#insn-tget"><code>#insn-tget</code></a>. The model behind them is in the
    <a href="../arch/">architecture outline</a>; the pseudocode notation is explained in
    %s.</p>
</header>''' % (n, len(chapters), PDF, ctx.ref("sec:pseudo", "Section"))
    main.insert(0, head)
    return page("isa", "Strata instruction set", "Every Strata instruction — encoding, syntax, operation, "
                "exceptions — generated from the Architecture Reference Manual's source.",
                "\n".join(side), "\n".join(main))


# ---------------------------------------------------------------- architecture outline
PH = re.compile(r"\{\{([a-z]+)(?::(.*?))?\}\}")


def arch_anchors(text, labels):
    """Labels that the outline shows, and their element ids."""
    out = {}
    for m in PH.finditer(text):
        kind, arg = m.group(1), m.group(2)
        if kind in ("chapter", "section", "table", "figcap") and arg and ".tex:" not in arg:
            out[arg] = ("arch", arg.replace(":", "-"))
    return out


def arch_page(labels, anchors):
    ctx = T.Ctx(labels, "arch", anchors, PDF, lambda k: "../isa/#" + insn_id(k))
    text = arch_source()
    toc = []
    state = {"open": False}

    def sub(m):
        kind, arg = m.group(1), m.group(2)
        if kind == "chapter":
            info = labels.get(arg)
            ident = arg.replace(":", "-")
            pre = "</section>\n" if state["open"] else ""
            state["open"] = True
            word = "Appendix" if info.get("appendix") else "Chapter"
            toc.append(('ch', ident, "%s %s" % (word if word == "Appendix" else "", info["num"]),
                        T.tex_to_html(info["title"], ctx)))
            return ('%s<section class="chap" id="%s">\n<h2><span class="num">%s %s</span>%s %s</h2>'
                    % (pre, ident, word, info["num"], T.tex_to_html(info["title"], ctx), pdf_link(labels, arg, "PDF")))
        if kind == "section":
            if ".tex:" in arg:
                fname, title = arg.split(":", 1)
                # an unlabelled section: found by its title among the sections of the file
                info = unlabelled_section(labels, fname, title)
                ident = slug(title)
                dest = info["dest"]
            else:
                info = labels.get(arg)
                ident = arg.replace(":", "-")
                dest = info["dest"]
            toc.append(("sec", ident, info["num"], T.tex_to_html(info["title"], ctx)))
            return ('<h3 id="%s"><span class="secno">%s</span>%s <a class="pdf-ref" href="%s#nameddest=%s" '
                    'title="This section in the PDF manual">PDF</a></h3>' % (
                        ident, info["num"], T.tex_to_html(info["title"], ctx), PDF, dest))
        if kind == "table":
            return T.table_by_label(labels, arg, ctx)
        if kind == "tabular":
            fname, header = arg.split(":", 1)
            return T.tabular_by_header(fname, header, ctx)
        if kind == "rule":
            fname, title = arg.split(":", 1)
            return T.rule_by_title(fname, title, ctx)
        if kind in ("asm", "pseudo"):
            fname, needle = arg.split(":", 1)
            body = T.listing(fname, kind, needle)
            return T.block_env(kind, body, ctx)
        if kind == "desc":
            fname, first = arg.split(":", 1)
            return T.description_items(fname, first, ctx)
        if kind == "figcap":
            info = labels.get(arg)
            return '<figcaption><span class="tn">Figure %s</span> %s</figcaption>' % (
                info["num"], T.tex_to_html(info["title"], ctx))
        if kind == "capfmt":
            fields, info = T.tikz_fields("fig:capfmt", labels)
            cells = "".join('<div><b>%s</b><span>%s</span></div>' % (esc(n), T.tex_to_html(w, ctx)) for (n, w) in fields)
            return ('<figure class="capfmt" id="fig-capfmt"><div class="capbox">%s</div><figcaption>'
                    '<span class="tn">Figure %s</span> %s</figcaption></figure>' % (
                        cells, info["num"], T.tex_to_html(info["title"], ctx)))
        if kind == "encodings":
            out = []
            for (name, users, enc) in T.encodings("ch-encoding.tex", ctx):
                out.append('<div class="fmt"><p class="fmt-h"><b>%s</b><span>%s</span></p>%s</div>' % (
                    T.tex_to_html(name, ctx), T.tex_to_html(users, ctx), enc))
            return "\n".join(out)
        if kind == "opmap":
            info = labels.get("tab:opmap")
            return ('<figure class="tblfig" id="tab-opmap"><figcaption><span class="tn">Table %s</span> %s</figcaption>%s</figure>'
                    % (info["num"], T.tex_to_html(info["title"], ctx), opmap_html().replace('href="#insn-', 'href="../isa/#insn-')))
        if kind == "ref":
            return ctx.ref(arg, {"chapter": "Chapter", "section": "Section", "table": "Table", "figure": "Figure",
                                 "part": "Part"}[labels.get(arg)["kind"]])
        if kind == "pdf":
            info = labels.get(arg)
            word = {"chapter": "Appendix" if info.get("appendix") else "Chapter", "section": "Section",
                    "table": "Table", "figure": "Figure", "part": "Part"}[info["kind"]]
            return '<a class="pdf" href="%s#nameddest=%s">%s\u00a0%s</a>' % (PDF, info["dest"], word, info["num"])
        if kind == "count":
            return str(len(geninsns.INSNS))
        raise ValueError("arch.html: unknown placeholder {{%s}}" % kind)

    body = PH.sub(sub, text)
    if state["open"]:
        body += "\n</section>"
    side = ['    <details class="doc-ix" id="ix" open><summary>Contents</summary><nav class="doc-toc" aria-label="Contents">']
    for (kind, ident, num, title) in toc:
        if kind == "ch":
            side.append('      <a class="ix-ch" href="#%s"><span>%s</span><em>%s</em></a>' % (ident, title, num.strip()))
        else:
            side.append('      <a class="ix toc-sec" href="#%s"><code>%s</code><span>%s</span></a>' % (ident, num, title))
    side.append("    </nav></details>")
    side.append('    <p class="doc-keys">An outline. The <a href="%s">PDF manual</a> has the full text; every heading links '
                'to its section there.</p>' % PDF)
    return page("arch", "Strata architecture", "An outline of the Strata architecture: Local Stores and transfers, "
                "linear capabilities, inter-core hand-overs, traps without interrupts, the memory model, the "
                "encoding and the prototype platform.", "\n".join(side), body)


def arch_source():
    """doc/manual/web/arch.html without its leading comment (which documents the placeholders)."""
    return re.sub(r"\A\s*<!--.*?-->\s*", "", T.read(os.path.join(WEB, "arch.html")), flags=re.S)


def slug(title):
    return "s-" + re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")


def unlabelled_section(labels, fname, title):
    for info in labels.sections:
        if info["file"] == fname and info["title"] == title:
            return info
    raise KeyError("%s: no section %r" % (fname, title))


# ---------------------------------------------------------------- links to the source browser
def browsable():
    """The repository paths the source browser (code/) shows: the file selection of
    tools/web-code.py, which builds its manifest."""
    import glob
    import importlib.util
    spec = importlib.util.spec_from_file_location("web_code", os.path.join(ROOT, "tools", "web-code.py"))
    wc = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(wc)
    out = set()
    for (_, pats) in wc.GROUPS:
        for pat in pats:
            for p in glob.glob(os.path.join(wc.ROOT, pat)):
                if os.path.isfile(p):
                    out.add(os.path.relpath(p, wc.ROOT).replace(os.sep, "/"))
    return out


def link_sources(page_html, files):
    """Links every source file the text names to the source browser: a path in
    <code> (\\texttt), and "the <code>name</code> example" (examples/name.s)."""
    def path(m):
        p = m.group(1)
        if p not in files:
            return m.group(0)
        return '<a class="srcpath" href="../code/#%s"><code>%s</code></a>' % (p, p)
    page_html = re.sub(r"<code>([\w./-]+\.(?:s|fs))</code>", path, page_html)

    def example(m):
        p = "examples/%s.s" % m.group(1)
        if p not in files:
            return m.group(0)
        return '<a class="srcpath" href="../code/#%s"><code>%s</code></a>' % (p, m.group(1))
    return re.sub(r"<code>(\w+)</code>(?=(?:,? (?:and )?<code>\w+</code>)* examples?\b)", example, page_html)


