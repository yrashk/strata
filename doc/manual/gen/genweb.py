#!/usr/bin/env python3
"""Generates the website's instruction-set reference and architecture outline.

    python3 doc/manual/gen/genweb.py OUTDIR     (make web-docs: OUTDIR = build/web-docs)

Writes OUTDIR/isa/index.html (every instruction, with stable anchors
#insn-<mnemonic>), OUTDIR/arch/index.html (an outline of Part I and the
platform chapter), OUTDIR/docs.css, OUTDIR/docs.js and the figures the outline
uses. Pages are published next to the site (site/), whose style.css and
hl.js they use. It also runs gen/genforth.py: OUTDIR/forth/index.html, the
Strata Forth words and playground, generated from lang/forth/.

Nothing is copied by hand. The instruction entries come from the same data
that gen/geninsns.py turns into the manual's LaTeX (geninsns.INSNS and
geninsns.OP); the chapter introductions, cross-reference numbers, tables,
rule boxes, listings and encoding diagrams of the outline are read from the
manual's .tex sources through gen/tex2html.py. Only the outline's own prose
(doc/manual/web/arch.html) is written for the web.
"""
