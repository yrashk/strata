; =============================================================================
; dbbench.s: the store's calls for programs, timed (tools/bench-store.sh)
; =============================================================================
;
;   dbbench N
;   put 200: 123456 ticks
;   get 200: 23456 ticks
;   scan 200: 3456 ticks
;
; N puts of a 100-byte value under keys k0000.. (each a commit), then N gets
; of them, then one scan of the tree from its start, in the tree bench/t.
; The times are the clock's ticks (NOW), so under -T virtual rounds / 100.

N_VAL   = 100                           ; a value's bytes

        .data                           ; data Local Store
        .align 8                        ; aligned buffers
args:   .space 512                      ; the argument text
val:    .space 1024                    ; a value, put and got
sbuf:   .space 4032                    ; a scan's records
key:    .ascii "k0000"                  ; the key, its digits counted up
        .align 8                        ; ...
t0v:    .dword 0                        ; the clock at a phase's start
s_tree: .ascii "bench/t"                ; the tree
m_put:  .ascii "put "                   ; output texts
m_get:  .ascii "get "                   ; ...
m_scan: .ascii "scan "                  ; ...
m_t:    .ascii " ticks\n"               ; ...
m_col:  .ascii ": "                     ; ...
m_err:  .ascii "dbbench: a call failed\n" ; ...

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        call  sys_init                  ; handles and arguments
        la    a0, args                  ; N
        call  sys_args                  ; ...
        mv    a1, a0                    ; ...
        la    a0, args                  ; ...
        call  str_atoi                  ; ...
        mv    s0, a0                    ; s0 = N
        la    a0, s_tree                ; the tree
        li    a1, 7                     ; ...
        call  kv_open                   ; ...
        la    t0, val                   ; a value of N_VAL bytes
        li    t1, 0                     ; ...
mv_l:
        addi  t2, t1, 'a'               ; ...
        sb    t2, 0(t0)                 ; ...
        addi  t0, t0, 1                 ; ...
        addi  t1, t1, 1                 ; ...
        li    t2, N_VAL                 ; ...
        bne   t1, t2, mv_l              ; ...
        call  sys_now                   ; the puts
        la    t0, t0v                   ; ...
        sd    a0, 0(t0)                 ; ...
        li    s1, 0                     ; s1 = keys done
put_l:
        beq   s1, s0, put_d             ; ...
        mv    a0, s1                    ; the key
        call  setkey                    ; ...
        la    a0, key                   ; ...
        li    a1, 5                     ; ...
        la    a2, val                   ; ...
        li    a3, N_VAL                 ; ...
        call  kv_put                    ; ...
        bnez  a0, fail                  ; ...
        addi  s1, s1, 1                 ; ...
        j     put_l                     ; ...
put_d:
        la    a0, m_put                 ; ...
        li    a1, 4                     ; ...
        call  report                    ; ...
        li    s1, 0                     ; the gets
get_l:
        beq   s1, s0, get_d             ; ...
        mv    a0, s1                    ; ...
        call  setkey                    ; ...
        la    a0, key                   ; ...
        li    a1, 5                     ; ...
        la    a2, val                   ; ...
        call  kv_get                    ; ...
        li    t0, N_VAL                 ; ...
        bne   a0, t0, fail              ; ...
        addi  s1, s1, 1                 ; ...
        j     get_l                     ; ...
get_d:
        la    a0, m_get                 ; ...
        li    a1, 4                     ; ...
        call  report                    ; ...
        li    s1, 0                     ; the scan: records seen
        li    a1, 0                     ; from the start
        li    a2, 0                     ; ...
sc_l:
        la    a0, key                   ; (the last key seen)
        la    a3, sbuf                  ; ...
        call  kv_scan                   ; ...
        bltz  a0, fail                  ; ...
        beqz  a0, sc_d                  ; ...
        add   s1, s1, a0                ; ...
        mv    s2, a0                    ; the last record's key
        la    t0, sbuf                  ; ...
sc_r:
        lhu   t1, 0(t0)                 ; key length
        lhu   t2, 2(t0)                 ; value length
        addi  t3, t0, 8                 ; the key
        addi  s2, s2, -1                ; the last one?
        beqz  s2, sc_k                  ; ...
        addi  t1, t1, 7                 ; past it
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        addi  t2, t2, 7                 ; ...
        srli  t2, t2, 3                 ; ...
        slli  t2, t2, 3                 ; ...
        add   t0, t3, t1                ; ...
        add   t0, t0, t2                ; ...
        j     sc_r                      ; ...
sc_k:
        la    t4, key                   ; copy it (5 bytes)
        li    t5, 0                     ; ...
sc_c:
        add   t6, t3, t5                ; ...
        lbu   t6, 0(t6)                 ; ...
        add   a0, t4, t5                ; ...
        sb    t6, 0(a0)                 ; ...
        addi  t5, t5, 1                 ; ...
        li    t6, 5                     ; ...
        bne   t5, t6, sc_c              ; ...
        li    a1, 5                     ; after it
        li    a2, 1                     ; ...
        j     sc_l                      ; ...
sc_d:
        bne   s1, s0, fail              ; every record seen
        la    a0, m_scan                ; ...
        li    a1, 5                     ; ...
        call  report                    ; ...
        li    a0, 0                     ; ...
        call  sys_exit                  ; ...
fail:
        la    a0, m_err                 ; ...
        li    a1, 23                    ; ...
        call  out_str                   ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...

; setkey(a0 = n): key = "k" and n in four digits
setkey:
        la    t0, key + 4               ; from the last digit
        li    t1, 4                     ; ...
        li    t2, 10                    ; ...
sk_l:
        remu  t3, a0, t2                ; ...
        divu  a0, a0, t2                ; ...
        addi  t3, t3, '0'               ; ...
        sb    t3, 0(t0)                 ; ...
        addi  t0, t0, -1                ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, sk_l                  ; ...
        ret                             ; ...

; report(a0 = text, a1 = length): "TEXT N: T ticks" since t0v; t0v = now
report:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        call  out_str                   ; ...
        mv    a0, s0                    ; ...
        call  out_dec                   ; ...
        la    a0, m_col                 ; ...
        li    a1, 2                     ; ...
        call  out_str                   ; ...
        call  sys_now                   ; ...
        la    t0, t0v                   ; ...
        ld    t1, 0(t0)                 ; ...
        sd    a0, 0(t0)                 ; ...
        sub   a0, a0, t1                ; ...
        call  out_dec                   ; ...
        la    a0, m_t                   ; ...
        li    a1, 7                     ; ...
        call  out_str                   ; ...
        call  out_flush                 ; ...
        call  sys_now                   ; (the output not counted)
        la    t0, t0v                   ; ...
        sd    a0, 0(t0)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

        .include "../../os/lib/sys.s"   ; the system interface
        .include "../../os/lib/kv.s"    ; the store's calls
