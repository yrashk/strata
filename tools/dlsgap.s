; =============================================================================
; dlsgap.s: what one process leaves in a core's D-LS must not reach the next
; =============================================================================
;
;   dlsgap fill           forever: a pattern into every part of its D-LS that a
;                         switch does not save (above its data extent, below
;                         its stack, its scratch range), then a 1 ms sleep
;   dlsgap scan N         N + 1 times, with a 3 ms sleep between: those parts of
;                         its own D-LS must hold no word of that pattern
;   dlsgap farfill        the pattern over all its far memory (c0, its program
;                         memory, and c5, its message buffer), then it exits
;   dlsgap farscan        no word of its far memory may hold the pattern: what
;                         the kernel did not scrub when it handed the arena out
;
; tools/test-isolate.sh runs `-c 6 dlsgap fill &` and `-c 6 dlsgap scan 8` on
; the same core: every sleep of the scanner lets the filler run there, and
; the scanner looks again after the switch back (its first look checks the
; first load). It prints "dlsgap: N looks, clean" and exits 0, or the first
; address that leaked and exits 1. The scanner declares its 1 KiB buffer `scr`
; scratch (svc SET_SCRATCH: undefined after a switch, but never another
; process's bytes). `-m 2 dlsgap farfill` followed by `dlsgap farscan` checks
; the arenas: the scanner's arena is the filler's granules again (first fit)
; and must come scrubbed ("dlsgap: far memory clean").
;
; Both are this one program, so the filler's gaps are exactly the scanner's.

PATTERN = 0x5a5aa5a55a5aa5a5            ; the filler's word
SCRLEN  = 1024                          ; the scratch buffer
STACKLO = 0xE000                        ; programs' stacks: 0xE000..0xFFFF

        .data                           ; data Local Store
        .align 8                        ; aligned buffers
args:   .space 512                      ; the arguments
scr:    .space SCRLEN                   ; scratch (scan) / patterned (fill)
looks:  .dword 0                        ; scans made
m_fill: .ascii "fill"                   ; the mode words
m_scan: .ascii "scan"                   ; ...
m_ffil: .ascii "farfill"                ; ...
m_fscn: .ascii "farscan"                ; ...
m_fok:  .ascii "dlsgap: far memory clean\n" ; output text
m_fok_e:                                ; end of the text above
m_fbad: .ascii "dlsgap: LEAK: the other process's word in far memory, c" ; output text
m_fbad_e:                               ; end of the text above
m_ok:   .ascii "dlsgap: "               ; output text
m_ok_e:                                 ; end of the text above
m_ok2:  .ascii " looks, clean\n"        ; output text
m_ok2_e:                                ; end of the text above
m_bad:  .ascii "dlsgap: LEAK: the other process's word at D-LS 0x" ; output text
m_bad_e:                                ; end of the text above
m_use:  .ascii "usage: dlsgap fill | scan N | farfill | farscan\n" ; output text
m_use_e:                                ; end of the text above

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        li    sp, 65536                 ; stack at the top of the D-LS
        call  sys_init                  ; handles and arguments
        la    a0, args                  ; the arguments
        call  sys_args                  ; a0 = their length
        la    s2, args                  ; s2 = cursor
        add   s3, s2, a0                ; s3 = end
        mv    a0, s2                    ; the mode
        mv    a1, s3                    ; ...
        call  arg_next                  ; a0 = word, a1 = length, a2 = cursor after
        mv    s2, a2                    ; ...
        mv    s4, a0                    ; ...
        mv    s5, a1                    ; ...
        mv    a0, s4                    ; "fill"?
        mv    a1, s5                    ; ...
        la    a2, m_fill                ; ...
        li    a3, 4                     ; ...
        call  str_eq                    ; ...
        bnez  a0, fill                  ; ...
        mv    a0, s4                    ; "farfill"?
        mv    a1, s5                    ; ...
        la    a2, m_ffil                ; ...
        li    a3, 7                     ; ...
        call  str_eq                    ; ...
        bnez  a0, farfill               ; ...
        mv    a0, s4                    ; "farscan"?
        mv    a1, s5                    ; ...
        la    a2, m_fscn                ; ...
        li    a3, 7                     ; ...
        call  str_eq                    ; ...
        bnez  a0, farscan               ; ...
        mv    a0, s4                    ; "scan"?
        mv    a1, s5                    ; ...
        la    a2, m_scan                ; ...
        li    a3, 4                     ; ...
        call  str_eq                    ; ...
        beqz  a0, usage                 ; ...
        mv    a0, s2                    ; N
        mv    a1, s3                    ; ...
        call  arg_next                  ; ...
        call  str_atoi                  ; ...
        mv    s0, a0                    ; s0 = sleeps left
        la    a0, scr                   ; the buffer is scratch
        li    a1, SCRLEN                ; ...
        call  sys_scratch               ; ...
scan:
        call  look                      ; a0 = 0, or the leaked address
        bnez  a0, leak                  ; ...
        la    t0, looks                 ; one more look
        ld    t1, 0(t0)                 ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, 0(t0)                 ; ...
        blez  s0, clean                 ; done
        addi  s0, s0, -1                ; ...
        li    a0, 3000                  ; 3 ms: the filler runs here meanwhile
        call  sys_sleep                 ; ...
        j     scan                      ; and look again
clean:
        la    a0, m_ok                  ; "dlsgap: N looks, clean"
        li    a1, m_ok_e - m_ok         ; ...
        call  out_str                   ; ...
        la    t0, looks                 ; ...
        ld    a0, 0(t0)                 ; ...
        call  out_dec                   ; ...
        la    a0, m_ok2                 ; ...
        li    a1, m_ok2_e - m_ok2       ; ...
        call  out_str                   ; ...
        li    a0, 0                     ; exit code
        call  sys_exit                  ; ...
leak:
        mv    s1, a0                    ; the address
        la    a0, m_bad                 ; ...
        li    a1, m_bad_e - m_bad       ; ...
        call  out_str                   ; ...
        mv    a0, s1                    ; ...
        li    a1, 4                     ; (four digits)
        call  out_hex                   ; ...
        call  out_nl                    ; ...
        li    a0, 1                     ; exit code
        call  sys_exit                  ; ...
usage:
        la    a0, m_use                 ; ...
        li    a1, m_use_e - m_use       ; ...
        call  err_str                   ; ...
        li    a0, 2                     ; ...
        call  sys_exit                  ; ...

; look() -> a0 = 0 if no word of the gaps holds PATTERN, or the first that does
; (above the data extent, below the stack (a margin under sp), the scratch buffer)
look:
        li    t2, PATTERN               ; ...
        la    t0, d_end                 ; above the data extent, to the end of its data
        addi  t1, t0, 1023              ;   window (whole KiB: what the Local Store windows
        srli  t1, t1, 10                ;   give it)
        slli  t1, t1, 10                ; ...
lk_d:
        bgeu  t0, t1, lk_s0             ; ...
        ld    t3, 0(t0)                 ; ...
        beq   t3, t2, lk_bad            ; ...
        addi  t0, t0, 8                 ; ...
        j     lk_d                      ; ...
lk_s0:
        li    t0, STACKLO               ; below the stack
        addi  t1, sp, -256              ; ...
lk_s:
        bgeu  t0, t1, lk_r0             ; ...
        ld    t3, 0(t0)                 ; ...
        beq   t3, t2, lk_bad            ; ...
        addi  t0, t0, 8                 ; ...
        j     lk_s                      ; ...
lk_r0:
        la    t0, scr                   ; the scratch buffer
        li    t1, SCRLEN                ; ...
        add   t1, t0, t1                ; ...
lk_r:
        bgeu  t0, t1, lk_ok             ; ...
        ld    t3, 0(t0)                 ; ...
        beq   t3, t2, lk_bad            ; ...
        addi  t0, t0, 8                 ; ...
        j     lk_r                      ; ...
lk_ok:
        li    a0, 0                     ; clean
        ret                             ; ...
lk_bad:
        mv    a0, t0                    ; the address
        ret                             ; ...

; the filler: the pattern everywhere a switch does not keep, then a short sleep
fill:
        li    t2, PATTERN               ; ...
        la    t0, d_end                 ; above the data extent, to the end of its data
        addi  t1, t0, 1023              ;   window
        srli  t1, t1, 10                ; ...
        slli  t1, t1, 10                ; ...
fl_d:
        bgeu  t0, t1, fl_s0             ; ...
        sd    t2, 0(t0)                 ; ...
        addi  t0, t0, 8                 ; ...
        j     fl_d                      ; ...
fl_s0:
        li    t0, STACKLO               ; below the stack
        addi  t1, sp, -256              ; ...
fl_s:
        bgeu  t0, t1, fl_r0             ; ...
        sd    t2, 0(t0)                 ; ...
        addi  t0, t0, 8                 ; ...
        j     fl_s                      ; ...
fl_r0:
        la    t0, scr                   ; its (not scratch) buffer: the scanner's scratch range
        li    t1, SCRLEN                ; ...
        add   t1, t0, t1                ; ...
fl_r:
        bgeu  t0, t1, fl_sl             ; ...
        sd    t2, 0(t0)                 ; ...
        addi  t0, t0, 8                 ; ...
        j     fl_r                      ; ...
fl_sl:
        li    a0, 1000                  ; 1 ms
        call  sys_sleep                 ; ...
        j     fill                      ; and again

; farfill: the pattern over c0 and c5, a buffer at a time, then exit
farfill:
        li    t2, PATTERN               ; the buffer full of it
        la    t0, scr                   ; ...
        li    t1, SCRLEN                ; ...
        add   t1, t0, t1                ; ...
ff_b:
        bgeu  t0, t1, ff_0              ; ...
        sd    t2, 0(t0)                 ; ...
        addi  t0, t0, 8                 ; ...
        j     ff_b                      ; ...
ff_0:
        la    t0, scr                   ; c0: all of it
        li    t1, SCRLEN                ; ...
        li    t2, 0                     ; ...
        clen  t3, c0                    ; ...
ff_c0:
        bgeu  t2, t3, ff_5              ; ...
        tput  tg1, t0, c0, t2, t1       ; ...
        add   t2, t2, t1                ; ...
        j     ff_c0                     ; ...
ff_5:
        li    t2, 0                     ; c5: all of it
        clen  t3, c5                    ; ...
ff_c5:
        bgeu  t2, t3, ff_w              ; ...
        tput  tg1, t0, c5, t2, t1       ; ...
        add   t2, t2, t1                ; ...
        j     ff_c5                     ; ...
ff_w:
        twait 1 << 1                    ; all written
        li    a0, 0                     ; exit code
        call  sys_exit                  ; ...

; farscan: c0, then c5, a buffer at a time: no word may hold the pattern
farscan:
        li    s1, 0                     ; s1 = which (0: c0, 5: c5)
        li    s2, 0                     ; s2 = offset
        clen  s3, c0                    ; s3 = its length
fs_l:
        bgeu  s2, s3, fs_next           ; ...
        la    t0, scr                   ; a buffer of it
        li    t1, SCRLEN                ; ...
        bnez  s1, fs_5                  ; ...
        tget  tg1, t0, c0, s2, t1       ; ...
        j     fs_w                      ; ...
fs_5:
        tget  tg1, t0, c5, s2, t1       ; ...
fs_w:
        twait 1 << 1                    ; ...
        li    t2, PATTERN               ; ...
        add   t1, t0, t1                ; ...
fs_c:
        bgeu  t0, t1, fs_n              ; ...
        ld    t3, 0(t0)                 ; ...
        beq   t3, t2, fs_bad            ; ...
        addi  t0, t0, 8                 ; ...
        j     fs_c                      ; ...
fs_n:
        li    t1, SCRLEN                ; ...
        add   s2, s2, t1                ; ...
        j     fs_l                      ; ...
fs_next:
        bnez  s1, fs_ok                 ; both done
        li    s1, 5                     ; now c5
        li    s2, 0                     ; ...
        clen  s3, c5                    ; ...
        j     fs_l                      ; ...
fs_ok:
        la    a0, m_fok                 ; "dlsgap: far memory clean"
        li    a1, m_fok_e - m_fok       ; ...
        call  out_str                   ; ...
        li    a0, 0                     ; exit code
        call  sys_exit                  ; ...
fs_bad:
        la    t1, scr                   ; the offset of that word
        sub   t0, t0, t1                ; ...
        add   s2, s2, t0                ; ...
        la    a0, m_fbad                ; "... c0 0x...", "... c5 0x..."
        li    a1, m_fbad_e - m_fbad     ; ...
        call  out_str                   ; ...
        mv    a0, s1                    ; ...
        call  out_dec                   ; ...
        li    a0, 32                    ; ...
        call  out_chr                   ; ...
        mv    a0, s2                    ; ...
        li    a1, 8                     ; ...
        call  out_hex                   ; ...
        call  out_nl                    ; ...
        li    a0, 1                     ; exit code
        call  sys_exit                  ; ...

        .include "../os/lib/sys.s"      ; the system interface
        .data                           ; the end of all data: the extent ends here
        .align 8                        ; ...
d_end:
