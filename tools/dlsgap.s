; =============================================================================
; dlsgap.s: what one process leaves in a core's D-LS must not reach the next
; =============================================================================
;
;   dlsgap fill           forever: a pattern into every part of its D-LS that a
;                         switch does not save (above its data extent, below
;                         its stack, its scratch range), then a 1 ms sleep
;   dlsgap scan N         N + 1 times, with a 3 ms sleep between: those parts of
;                         its own D-LS must hold no word of that pattern
;
; tools/test-isolate.sh runs `-c 6 dlsgap fill &` and `-c 6 dlsgap scan 8` on
; the same core: every sleep of the scanner lets the filler run there, and
; the scanner looks again after the switch back (its first look checks the
; first load). It prints "dlsgap: N looks, clean" and exits 0, or the first
; address that leaked and exits 1. The scanner declares its 1 KiB buffer `scr`
; scratch (svc SET_SCRATCH: undefined after a switch, but never another
; process's bytes).
;
; Both are this one program, so the filler's gaps are exactly the scanner's.

PATTERN = 0x5a5aa5a55a5aa5a5            ; the filler's word
SCRLEN  = 1024                          ; the scratch buffer
DATAMAX = 0xA000                        ; StrataOS: program data ends here
STACKLO = 0xE000                        ; programs' stacks: 0xE000..0xFFFF

        .data                           ; data Local Store
        .align 8                        ; aligned buffers
args:   .space 512                      ; the arguments
scr:    .space SCRLEN                   ; scratch (scan) / patterned (fill)
looks:  .dword 0                        ; scans made
m_fill: .ascii "fill"                   ; the mode words
m_scan: .ascii "scan"                   ; ...
m_ok:   .ascii "dlsgap: "               ; output text
m_ok_e:                                 ; end of the text above
m_ok2:  .ascii " looks, clean\n"        ; output text
m_ok2_e:                                ; end of the text above
m_bad:  .ascii "dlsgap: LEAK: the other process's word at D-LS 0x" ; output text
m_bad_e:                                ; end of the text above
m_use:  .ascii "usage: dlsgap fill | dlsgap scan N\n" ; output text
m_use_e:                                ; end of the text above

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        li    sp, 65536                 ; stack at the top of the D-LS
        call  sys_init                  ; handles and arguments
        la    a0, args                  ; the arguments
        call  sys_args                  ; a0 = their length
        la    s2, args                  ; s2 = cursor
        add   s3, s2, a0                ; s3 = end
        mv    a0, s2                    ; the mode
        mv    a1, s3                    ; ...
        call  arg_next                  ; a0 = word, a1 = length, a2 = cursor after
        mv    s2, a2                    ; ...
        mv    s4, a0                    ; ...
        mv    s5, a1                    ; ...
        mv    a0, s4                    ; "fill"?
        mv    a1, s5                    ; ...
        la    a2, m_fill                ; ...
        li    a3, 4                     ; ...
        call  str_eq                    ; ...
        bnez  a0, fill                  ; ...
        mv    a0, s4                    ; "scan"?
        mv    a1, s5                    ; ...
        la    a2, m_scan                ; ...
        li    a3, 4                     ; ...
        call  str_eq                    ; ...
        beqz  a0, usage                 ; ...
        mv    a0, s2                    ; N
        mv    a1, s3                    ; ...
        call  arg_next                  ; ...
        call  str_atoi                  ; ...
        mv    s0, a0                    ; s0 = sleeps left
        la    a0, scr                   ; the buffer is scratch
        li    a1, SCRLEN                ; ...
        call  sys_scratch               ; ...
scan:
        call  look                      ; a0 = 0, or the leaked address
        bnez  a0, leak                  ; ...
        la    t0, looks                 ; one more look
        ld    t1, 0(t0)                 ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, 0(t0)                 ; ...
        blez  s0, clean                 ; done
        addi  s0, s0, -1                ; ...
        li    a0, 3000                  ; 3 ms: the filler runs here meanwhile
        call  sys_sleep                 ; ...
        j     scan                      ; and look again
clean:
        la    a0, m_ok                  ; "dlsgap: N looks, clean"
        li    a1, m_ok_e - m_ok         ; ...
        call  out_str                   ; ...
        la    t0, looks                 ; ...
        ld    a0, 0(t0)                 ; ...
        call  out_dec                   ; ...
        la    a0, m_ok2                 ; ...
        li    a1, m_ok2_e - m_ok2       ; ...
        call  out_str                   ; ...
        li    a0, 0                     ; exit code
        call  sys_exit                  ; ...
leak:
        mv    s1, a0                    ; the address
        la    a0, m_bad                 ; ...
        li    a1, m_bad_e - m_bad       ; ...
        call  out_str                   ; ...
        mv    a0, s1                    ; ...
        li    a1, 4                     ; (four digits)
        call  out_hex                   ; ...
        call  out_nl                    ; ...
        li    a0, 1                     ; exit code
        call  sys_exit                  ; ...
usage:
        la    a0, m_use                 ; ...
        li    a1, m_use_e - m_use       ; ...
        call  err_str                   ; ...
        li    a0, 2                     ; ...
        call  sys_exit                  ; ...

; look() -> a0 = 0 if no word of the gaps holds PATTERN, or the first that does
; (above the data extent, below the stack (a margin under sp), the scratch buffer)
look:
        li    t2, PATTERN               ; ...
        la    t0, d_end                 ; above the data extent
        li    t1, DATAMAX               ; ...
lk_d:
        bgeu  t0, t1, lk_s0             ; ...
        ld    t3, 0(t0)                 ; ...
        beq   t3, t2, lk_bad            ; ...
        addi  t0, t0, 8                 ; ...
        j     lk_d                      ; ...
lk_s0:
        li    t0, STACKLO               ; below the stack
        addi  t1, sp, -256              ; ...
lk_s:
        bgeu  t0, t1, lk_r0             ; ...
        ld    t3, 0(t0)                 ; ...
        beq   t3, t2, lk_bad            ; ...
        addi  t0, t0, 8                 ; ...
        j     lk_s                      ; ...
lk_r0:
        la    t0, scr                   ; the scratch buffer
        li    t1, SCRLEN                ; ...
        add   t1, t0, t1                ; ...
lk_r:
        bgeu  t0, t1, lk_ok             ; ...
        ld    t3, 0(t0)                 ; ...
        beq   t3, t2, lk_bad            ; ...
        addi  t0, t0, 8                 ; ...
        j     lk_r                      ; ...
lk_ok:
        li    a0, 0                     ; clean
        ret                             ; ...
lk_bad:
        mv    a0, t0                    ; the address
        ret                             ; ...

; the filler: the pattern everywhere a switch does not keep, then a short sleep
fill:
        li    t2, PATTERN               ; ...
        la    t0, d_end                 ; above the data extent
        li    t1, DATAMAX               ; ...
fl_d:
        bgeu  t0, t1, fl_s0             ; ...
        sd    t2, 0(t0)                 ; ...
        addi  t0, t0, 8                 ; ...
        j     fl_d                      ; ...
fl_s0:
        li    t0, STACKLO               ; below the stack
        addi  t1, sp, -256              ; ...
fl_s:
        bgeu  t0, t1, fl_r0             ; ...
        sd    t2, 0(t0)                 ; ...
        addi  t0, t0, 8                 ; ...
        j     fl_s                      ; ...
fl_r0:
        la    t0, scr                   ; its (not scratch) buffer: the scanner's scratch range
        li    t1, SCRLEN                ; ...
        add   t1, t0, t1                ; ...
fl_r:
        bgeu  t0, t1, fl_sl             ; ...
        sd    t2, 0(t0)                 ; ...
        addi  t0, t0, 8                 ; ...
        j     fl_r                      ; ...
fl_sl:
        li    a0, 1000                  ; 1 ms
        call  sys_sleep                 ; ...
        j     fill                      ; and again

        .include "../os/lib/sys.s"      ; the system interface
        .data                           ; the end of all data: the extent ends here
        .align 8                        ; ...
d_end:
