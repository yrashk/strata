; =============================================================================
; lsprot.s: user mode cannot reach the kernel's part of a core's Local Stores
; =============================================================================
;
;   lsprot                try each way into the dispatcher's data (D-LS
;                         0xA000..0xDFFF) and the kernel's code (I-LS
;                         0x0000..0x7FFF), and the program's own parts
;
; StrataOS sets the Local Store windows (wdata, wstack, wcode) so that user
; mode reaches only the program's data [0, 0xA000), stack [0xE000, 0x10000)
; and code [0x8000, 0x10000). Each attempt here must trap: a user trap handler
; (utvec) counts the trap and its cause and resumes after the attempt. The
; program's own parts must not trap. It prints "lsprot: 7 of 7 refused, own
; parts fine" and exits 0, or the first attempt that went through and exits
; 1. tools/test-isolate.sh runs it.

C_LSFAULT = 2                           ; trap causes
C_IFAULT  = 7                           ; ...

        .data                           ; data Local Store
        .align 8                        ; aligned words
resume: .dword 0                        ; where the handler continues after a trap
ntrap:  .dword 0                        ; traps taken
lcause: .dword 0                        ; the last trap's cause
hsave:  .dword 0, 0                     ; the handler's t0, t1
buf:    .space 16                       ; a transfer buffer
m_ok:   .ascii "lsprot: 7 of 7 refused, own parts fine\n" ; output text
m_ok_e:                                 ; end of the text above
m_bad:  .ascii "lsprot: NOT REFUSED: attempt " ; output text
m_bad_e:                                ; end of the text above
m_own:  .ascii "lsprot: an own part trapped: check " ; output text
m_own_e:                                ; end of the text above

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        call  sys_init                  ; handles and arguments
        la    t0, uhandler              ; our own trap handler
        csrw  tvec, t0                  ; (in user mode: the user bank, utvec)
        li    s1, 0                     ; s1 = attempt number
; ---- the kernel's parts: each must trap with the cause in s2 ------------------------------------
        li    s2, C_LSFAULT             ; 1: a store into the dispatcher's data
        la    t0, a2                    ; ...
        sd    t0, resume(zero)          ; ...
        li    t1, 0xA000                ; ...
        sd    t1, 0(t1)                 ; ...
        j     refused                   ; (not reached if it trapped)
a2:     call  check                     ; ...
        la    t0, a3                    ; 2: a load from it (the dispatcher's stack)
        sd    t0, resume(zero)          ; ...
        li    t1, 0xDBF8                ; ...
        ld    t2, 0(t1)                 ; ...
        j     refused                   ; ...
a3:     call  check                     ; ...
        la    t0, a4                    ; 3: a tget into it
        sd    t0, resume(zero)          ; ...
        li    t1, 0xB000                ; ...
        li    t2, 0                     ; (from our own memory, c0)
        li    t3, 8                     ; ...
        tget  tg1, t1, c0, t2, t3       ; ...
        j     refused                   ; ...
a4:     call  check                     ; ...
        la    t0, a5                    ; 4: a tput out of it
        sd    t0, resume(zero)          ; ...
        li    t1, 0xC000                ; ...
        tput  tg1, t1, c0, t2, t3       ; ...
        j     refused                   ; ...
a5:     call  check                     ; ...
        la    t0, a6                    ; 5: a tgetx over the kernel's code
        sd    t0, resume(zero)          ; ...
        li    t1, 0x4000                ; ...
        tgetx tg1, t1, c0, t2, t3       ; ...
        j     refused                   ; ...
a6:     call  check                     ; ...
        la    t0, a7                    ; 6: xmap of the kernel's code
        sd    t0, resume(zero)          ; ...
        li    t1, 0x4000                ; ...
        xmap  0, t1, c0, t2             ; ...
        j     refused                   ; ...
a7:     call  check                     ; ...
        li    s2, C_IFAULT              ; 7: a jump into the kernel's code
        la    t0, a8                    ; ...
        sd    t0, resume(zero)          ; ...
        li    t1, 0x4000                ; ...
        jalr  zero, t1, 0               ; ...
        j     refused                   ; ...
a8:     call  check                     ; ...
; ---- the program's own parts: none may trap --------------------------------------------------------
        li    s1, 0                     ; s1 = which check
        la    t0, own_bad               ; any trap from here on is a failure
        sd    t0, resume(zero)          ; ...
        li    s1, 1                     ; the last word of its data
        li    t1, 0x9FF8                ; ...
        ld    t2, 0(t1)                 ; ...
        sd    t2, 0(t1)                 ; ...
        li    s1, 2                     ; the bottom of its stack
        li    t1, 0xE000                ; ...
        ld    t2, 0(t1)                 ; ...
        sd    t2, 0(t1)                 ; ...
        li    s1, 3                     ; a transfer into its data
        la    t1, buf                   ; ...
        li    t2, 0                     ; ...
        li    t3, 16                    ; ...
        tget  tg1, t1, c0, t2, t3       ; ...
        twait tg1                       ; ...
        la    a0, m_ok                  ; all as it should be
        li    a1, m_ok_e - m_ok         ; ...
        call  out_str                   ; ...
        li    a0, 0                     ; ...
        call  sys_exit                  ; ...

; check(): the attempt in s1 trapped with the cause in s2; on to the next
check:
        ld    t0, lcause(zero)          ; the cause
        bne   t0, s2, refused           ; another one: as good as through
        sd    zero, lcause(zero)        ; ...
        addi  s1, s1, 1                 ; the next attempt
        ret                             ; ...
refused:                                ; attempt s1 + 1 went through (or trapped wrongly)
        la    a0, m_bad                 ; ...
        li    a1, m_bad_e - m_bad       ; ...
        call  out_str                   ; ...
        addi  a0, s1, 1                 ; ...
        call  out_dec                   ; ...
        call  out_nl                    ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...
own_bad:                                ; an own part trapped
        la    a0, m_own                 ; ...
        li    a1, m_own_e - m_own       ; ...
        call  out_str                   ; ...
        mv    a0, s1                    ; ...
        call  out_dec                   ; ...
        call  out_nl                    ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...

; uhandler: a user trap: count it, keep its cause, continue at `resume`
uhandler:
        sd    t0, hsave(zero)           ; ...
        sd    t1, hsave+8(zero)         ; ...
        csrr  t0, cause                 ; (the user bank)
        sd    t0, lcause(zero)          ; ...
        ld    t0, ntrap(zero)           ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, ntrap(zero)           ; ...
        ld    t0, resume(zero)          ; ...
        csrw  epc, t0                   ; ...
        ld    t0, hsave(zero)           ; ...
        ld    t1, hsave+8(zero)         ; ...
        eret                            ; ...

        .include "../os/lib/sys.s"      ; the system interface
