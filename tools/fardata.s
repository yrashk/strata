; =============================================================================
; fardata.s: far loads and stores through the program's data cache (tgeom.FA)
; =============================================================================
;
;   fardata               write 256 KiB of the arena through a 4 KiB cache,
;                         a doubleword at a time, then bytes over part of it,
;                         and read it all back the same way
;   fardata bad           a far load past the end of the arena
;
; With tgeom bit 16 (FA) set, a load or store at or past the D-LS (64 KiB)
; goes through the tag table: its address is an offset in the arena (c0).
; A line that is not there traps with dmiss, and the dispatcher brings it in,
; writing the victim back first if a store made it dirty (os/kernel.s,
; xdmiss). The program does nothing about misses: it only gives the table
; and the lines a place in its data section and sets the three CSRs.
; 256 KiB through 4 KiB is 64 times the cache, so every line is evicted and
; written back several times. It prints "fardata: 32768 words, 2048 bytes,
; sum <hex>" and exits 0, or the first word or byte that came back wrong and
; exits 1. `fardata bad` must end with a dmiss fault: the dispatcher does
; not serve a line outside the arena. tools/test-far.sh runs both, two at a
; time on one core (so that switches happen between misses).

LSH   = 6                               ; 64-byte lines
SLG   = 5                               ; 32 sets
WAYS  = 2                               ; two ways
NSET  = 1 << SLG                        ; ...
FA    = 1 << 16                         ; tgeom: far access
GEOM  = LSH | SLG << 6 | WAYS << 12 | FA ; ...
BASE  = 0x80000                         ; the region, in the arena
NW    = 32768                           ; doublewords: 256 KiB
NB    = 2048                            ; bytes rewritten at the start
KEY   = 0x9e3779b97f4a7c15              ; word i holds i * KEY

        .data                           ; data Local Store
        .align 8                        ; aligned words
fc_tags: .space NSET * (WAYS + 1) * 8   ; the tag table (zero: empty)
fc_lines: .space NSET * WAYS << LSH     ; the lines
argb:   .space 64                       ; the command line
m_ok:   .ascii "fardata: 32768 words, 2048 bytes, sum " ; output text
m_ok_e:                                 ; end of the text above
m_bad:  .ascii "fardata: WRONG at offset " ; output text
m_bad_e:                                ; end of the text above

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        call  sys_init                  ; handles and arguments
        li    t0, fc_tags               ; the cache: its table,
        csrw  ttag, t0                  ; ...
        li    t0, fc_lines              ; its lines,
        csrw  tdata, t0                 ; ...
        li    t0, GEOM                  ; its geometry, far access on
        csrw  tgeom, t0                 ; ...
        la    a0, argb                  ; an argument?
        call  sys_args                  ; ...
        beqz  a0, good                  ; no
        clen  t0, c0                    ; "bad": past the end of the arena
        ld    t1, 0(t0)                 ; a dmiss the dispatcher refuses
        li    a0, 2                     ; (not reached)
        call  sys_exit                  ; ...
good:
        li    s1, BASE                  ; s1 = the address
        li    s2, 0                     ; s2 = i
        li    s3, 0                     ; s3 = i * KEY
        li    s4, NW                    ; ...
        li    t2, KEY                   ; ...
w1:     sd    s3, 0(s1)                 ; a far store
        addi  s1, s1, 8                 ; ...
        add   s3, s3, t2                ; ...
        addi  s2, s2, 1                 ; ...
        bltu  s2, s4, w1                ; ...
        li    s1, BASE                  ; bytes over the first NB: byte j = j * 7
        li    s2, 0                     ; ...
        li    s4, NB                    ; ...
w2:     li    t0, 7                     ; ...
        mul   t0, t0, s2                ; ...
        add   t1, s1, s2                ; ...
        sb    t0, 0(t1)                 ; ...
        addi  s2, s2, 1                 ; ...
        bltu  s2, s4, w2                ; ...
        li    s1, BASE                  ; read the bytes back
        li    s2, 0                     ; ...
r2:     li    t0, 7                     ; ...
        mul   t0, t0, s2                ; ...
        andi  t0, t0, 255               ; ...
        add   t1, s1, s2                ; ...
        lbu   t3, 0(t1)                 ; ...
        bne   t3, t0, wrong             ; ...
        addi  s2, s2, 1                 ; ...
        bltu  s2, s4, r2                ; ...
        li    s1, BASE + NB             ; and the words after them
        li    s2, NB / 8                ; ...
        li    s4, NW                    ; ...
        li    t2, KEY                   ; ...
        mul   s3, s2, t2                ; ...
        li    s5, 0                     ; s5 = the sum
r1:     ld    t3, 0(s1)                 ; a far load
        mv    t1, s1                    ; (for wrong)
        bne   t3, s3, wrong             ; ...
        add   s5, s5, t3                ; ...
        addi  s1, s1, 8                 ; ...
        add   s3, s3, t2                ; ...
        addi  s2, s2, 1                 ; ...
        bltu  s2, s4, r1                ; ...
        la    a0, m_ok                  ; all there
        li    a1, m_ok_e - m_ok         ; ...
        call  out_str                   ; ...
        mv    a0, s5                    ; ...
        call  out_hex                   ; ...
        call  out_nl                    ; ...
        li    a0, 0                     ; ...
        call  sys_exit                  ; ...
wrong:                                  ; t1 = the address that came back wrong
        mv    s1, t1                    ; ...
        la    a0, m_bad                 ; ...
        li    a1, m_bad_e - m_bad       ; ...
        call  out_str                   ; ...
        mv    a0, s1                    ; ...
        call  out_hex                   ; ...
        call  out_nl                    ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...

        .include "../os/lib/sys.s"      ; the system interface
