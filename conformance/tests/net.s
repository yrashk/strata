; =============================================================================
; net.s: the network interface (device window 0x4200), on the loopback link
; =============================================================================
; args: -N loop
;
; What it checks (common/platform.h, common/net.h; doc/strataos-0.2.md 1.2)
;   * STATUS (0x4210): u16 length of the next queued packet, u8 packets
;     queued, u8 bit 0 = link up (the loopback plug: up), u32 packets
;     dropped. Nothing queued and nothing dropped at reset.
;   * TX (0x4200): one transfer is one packet; on the loopback link it is
;     queued for receive at once.
;   * RX (0x4208): a read takes the head packet: byte i is packet byte i,
;     bytes past the packet's end read zero, and the part of a packet past
;     the read's length is lost (the next read gets the next packet).
;   * A TX transfer longer than the MTU (1500) is dropped and counted.
;   * The queue holds 16 packets; a 17th is dropped and counted.
;   * An RX read with nothing queued stays in flight (tag busy) until a
;     packet arrives or CANCEL (0x4218) completes it with zeros. A CANCEL
;     with no RX read waiting does nothing; a waiting read completes when a
;     packet is sent.

        .include "lib/conf.s"           ; harness: _start, sig/chk/chkt/done, trap recorder

N_TX = 0x4200                           ; network ports (device space)
N_RX = 0x4208                           ; ...
N_ST = 0x4210                           ; ...
N_CAN = 0x4218                          ; ...
LINK = 1 << 24                          ; STATUS: link up

        .data                           ; data Local Store
        .align 8                        ; transfer buffers
pkt:    .dword 0x0011223344556645, 0x8899aabbccddeeff, 0x0706050403020100 ; a 28-byte packet
        .dword 0x0f0e0d0c0b0a0908       ; (and more pattern after it)
rbuf:   .space 64                       ; RX destination
rbuf2:  .space 16                       ; a second RX destination
stb:    .dword 0                        ; STATUS read
big:    .space 1504                     ; an over-long packet

        .text                           ; instruction Local Store
main:
        csrr  t0, coreid                ; which core?
        bnez  t0, park                  ; only core 0 runs the test

; ---- reset state -----------------------------------------------------------------------
        call  status                    ; STATUS
        li    a1, LINK                  ; link up, empty, nothing dropped
        call  chk                       ; check

; ---- one packet through the loop ---------------------------------------------------------
        li    a0, 28                    ; 28 bytes
        call  send                      ; ...
        call  status                    ; queued
        li    a1, LINK | 1 << 16 | 28   ; one packet of 28 bytes
        call  chk                       ; check
        la    s1, rbuf                  ; s1 = RX buffer
        li    t0, -1                    ; fill it with ones (zeros past the packet are visible)
        sd    t0, 0(s1)                 ; ...
        sd    t0, 8(s1)                 ; ...
        sd    t0, 16(s1)                ; ...
        sd    t0, 24(s1)                ; ...
        li    t0, N_RX                  ; read 32 bytes
        li    t1, 32                    ; ...
        tget  tg1, s1, c3, t0, t1       ; the packet is there: completes
        twait tg1                       ; ...
        ld    a0, 0(s1)                 ; bytes 0..7
        li    a1, 0x0011223344556645    ; ...
        call  chk                       ; check
        ld    a0, 8(s1)                 ; bytes 8..15
        li    a1, 0x8899aabbccddeeff    ; ...
        call  chk                       ; check
        ld    a0, 16(s1)                ; bytes 16..23
        li    a1, 0x0706050403020100    ; ...
        call  chk                       ; check
        ld    a0, 24(s1)                ; bytes 24..27, then zeros
        li    a1, 0x0b0a0908            ; ...
        call  chk                       ; check
        call  status                    ; empty again
        li    a1, LINK                  ; ...
        call  chk                       ; check

; ---- a short read loses the rest; packets keep their order -----------------------------------
        li    a0, 10                    ; a 10-byte packet
        call  send                      ; ...
        li    a0, 20                    ; a 20-byte one
        call  send                      ; ...
        li    t0, N_RX                  ; read 8 bytes of the first
        li    t1, 8                     ; ...
        tget  tg1, s1, c3, t0, t1       ; ...
        twait tg1                       ; ...
        ld    a0, 0(s1)                 ; its first 8 bytes
        li    a1, 0x0011223344556645    ; ...
        call  chk                       ; check
        call  status                    ; the second is next
        li    a1, LINK | 1 << 16 | 20   ; ...
        call  chk                       ; check
        li    t0, N_RX                  ; read 24 bytes
        li    t1, 24                    ; ...
        tget  tg1, s1, c3, t0, t1       ; ...
        twait tg1                       ; ...
        ld    a0, 8(s1)                 ; bytes 8..15
        li    a1, 0x8899aabbccddeeff    ; ...
        call  chk                       ; check
        ld    a0, 16(s1)                ; bytes 16..19, then zeros
        li    a1, 0x03020100            ; ...
        call  chk                       ; check

; ---- too long: dropped ------------------------------------------------------------------------
        la    t0, big                   ; 1501 bytes
        li    t1, N_TX                  ; ...
        li    t2, 1501                  ; ...
        tput  tg2, t0, c3, t1, t2       ; ...
        twait tg2                       ; ...
        call  status                    ; nothing queued, one drop
        li    a1, LINK                  ; ...
        li    t0, 1                     ; (drops in bits 32..63)
        slli  t0, t0, 32                ; ...
        or    a1, a1, t0                ; ...
        call  chk                       ; check

; ---- the queue holds 16 ----------------------------------------------------------------------------
        li    s2, 17                    ; 17 packets of 8 bytes
q_send:
        li    a0, 8                     ; ...
        call  send                      ; ...
        addi  s2, s2, -1                ; ...
        bnez  s2, q_send                ; ...
        call  status                    ; 16 queued, two drops in all
        li    a1, LINK | 16 << 16 | 8   ; ...
        li    t0, 2                     ; ...
        slli  t0, t0, 32                ; ...
        or    a1, a1, t0                ; ...
        call  chk                       ; check
        li    s2, 16                    ; drain them
q_recv:
        li    t0, N_RX                  ; one packet
        li    t1, 8                     ; ...
        tget  tg1, s1, c3, t0, t1       ; ...
        twait tg1                       ; ...
        addi  s2, s2, -1                ; ...
        bnez  s2, q_recv                ; ...
        call  status                    ; empty
        li    a1, LINK                  ; ...
        li    t0, 2                     ; (the drops stay counted)
        slli  t0, t0, 32                ; ...
        or    a1, a1, t0                ; ...
        call  chk                       ; check

; ---- waiting reads: CANCEL, and a packet that arrives later ------------------------------------
        li    a0, N_CAN                 ; CANCEL with no read waiting
        li    a1, 0                     ; (the value is ignored)
        call  devwr                     ; does nothing
        li    t0, -1                    ; ones, so that the zeros of a CANCEL show
        sd    t0, 0(s1)                 ; ...
        li    t0, N_RX                  ; an RX read with nothing queued
        li    t1, 8                     ; ...
        tget  tg3, s1, c3, t0, t1       ; waits
        li    t2, 200                   ; spin a little: it stays in flight
nc_spin:
        addi  t2, t2, -1                ; count down
        bnez  t2, nc_spin               ; loop
        tpoll a0, tg3                   ; still busy (the earlier CANCEL did nothing)
        li    a1, 1 << 3                ; tag 3 busy
        call  chk                       ; check
        li    a0, N_CAN                 ; CANCEL
        li    a1, 0                     ; ...
        call  devwr                     ; completes it with zeros
        twait tg3                       ; done
        ld    a0, 0(s1)                 ; the value
        li    a1, 0                     ; zeros
        call  chk                       ; check
        call  status                    ; nothing was taken or added
        li    a1, LINK                  ; ...
        li    t0, 2                     ; ...
        slli  t0, t0, 32                ; ...
        or    a1, a1, t0                ; ...
        call  chk                       ; check
        la    s3, rbuf2                 ; a read that waits for a packet
        li    t0, N_RX                  ; ...
        li    t1, 16                    ; ...
        tget  tg4, s3, c3, t0, t1       ; waits
        li    a0, 12                    ; send 12 bytes (from another buffer)
        call  send                      ; the waiting read gets them
        twait tg4                       ; ...
        ld    a0, 0(s3)                 ; bytes 0..7
        li    a1, 0x0011223344556645    ; ...
        call  chk                       ; check
        ld    a0, 8(s3)                 ; bytes 8..11, then zeros
        li    a1, 0xccddeeff            ; ...
        call  chk                       ; check
        call  status                    ; empty
        li    a1, LINK                  ; ...
        li    t0, 2                     ; ...
        slli  t0, t0, 32                ; ...
        or    a1, a1, t0                ; ...
        call  chk                       ; check
        j     done                      ; print the signature and the verdict

; send(a0 = length): the first a0 bytes of pkt as one packet
send:
        la    t0, pkt                   ; the bytes
        li    t1, N_TX                  ; TX
        tput  tg2, t0, c3, t1, a0       ; one transfer, one packet
        twait tg2                       ; ...
        ret                             ; back

; status() -> a0 = STATUS
status:
        la    t0, stb                   ; 8 bytes
        li    t1, N_ST                  ; STATUS
        li    t2, 8                     ; ...
        tget  tg2, t0, c3, t1, t2       ; latched at byte 0
        twait tg2                       ; ...
        ld    a0, 0(t0)                 ; ...
        ret                             ; back
