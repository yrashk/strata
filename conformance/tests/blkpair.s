; =============================================================================
; blkpair.s: the block device pairs a command only with its submitter's buffer
; =============================================================================
;
; What it checks (manual: platform, block device, steps 2-4)
;   * The device records which core submitted each queued command and which
;     core gave each buffer, and pairs a command only with a buffer from the
;     core that submitted it (the oldest command first; among that core's
;     buffers the oldest).
;   * A buffer whose lender has no command queued is an orphan: the device
;     gives it straight back to its lender, from the device's node, unchanged
;     (and moves no data).
;   * A buffer goes back to the core that lent it, whatever core the
;     command's (reserved) byte 1 names.
; Core 0 and core 1 each have a 4 KiB buffer (B0, B1); the disk has a
; pattern at lba 10 (A) and lba 11 (B), written first by core 0.
;   1. core 1 gives B1 with no command: it comes back to core 1 (orphan);
;   2. core 0 submits "read lba 10" and gives nothing yet; core 1 submits
;      "read lba 11" and gives B1; then core 0 gives B0. Pairing by arrival
;      would put lba 10 into B1 and send it to core 0; instead B0 gets A and
;      returns to core 0, B1 gets B and returns to core 1, completions in
;      command order;
;   3. core 0 submits a command whose byte 1 names core 1, with B0: B0 comes
;      back to core 0.

        .include "lib/conf.s"           ; harness: _start, sig/chk/chkt/done, trap recorder

B_SQ = 0x100                            ; submission port (block device window offsets)
B_CQ = 0x200                            ; completion port
B_WIN = 0x2000                          ; the block device in the device space
OP_RD = 1                               ; read blocks into memory
OP_WR = 2                               ; write blocks from memory
B0 = 0x100000                           ; core 0's buffer (system memory)
B1 = 0x101000                           ; core 1's buffer
K = 0x9e3779b97f4a7c15                  ; pattern multiplier

        .data                           ; data Local Store
        .align 8                        ; transfer buffers
cmd:    .space 32                       ; one command
cqe:    .space 16                       ; one completion entry
rep:    .space 32                       ; core 1's report
blk:    .space 512                      ; one block

        .text                           ; instruction Local Store
main:
        csrr  t0, coreid                ; which core?
        beqz  t0, boss                  ; core 0 runs the test
        li    t1, 1                     ; core 1 is the other driver
        bne   t0, t1, park              ; the rest halt

; ---- core 1 ------------------------------------------------------------------------
        ctake c5, zero                  ; B1, from core 0
        ctake c6, zero                  ; the block device's window
        csrr  s0, ncores                ; s0 = the device's node
        ; 1. an orphan: no command of ours is queued
        cgive c5, s0                    ; ...
        ctake c5, s0                    ; back from the device's node
        cbase t0, c5                    ; unchanged
        sd    t0, rep(zero)             ; ...
        clen  t0, c5                    ; ...
        sd    t0, rep+8(zero)           ; ...
        cmov  c7, c6                    ; tell core 0 (a copy of the window as a token)
        cgive c7, zero                  ; ...
        ; 2. our command and our buffer, after core 0's command
        ctake c7, zero                  ; core 0's go
        cclear c7                       ; ...
        li    a0, OP_RD                 ; read lba 11 into B1
        li    a1, 1                     ; byte 1: this core
        li    a2, 0x1111                ; id
        li    a3, 11                    ; lba
        call  submit                    ; ...
        cgive c5, s0                    ; B1 to the device (after the command: see the manual)
        cmov  c7, c6                    ; tell core 0
        cgive c7, zero                  ; ...
        ctake c5, s0                    ; B1 back: our command ran
        ; report: the orphan's identity in B1 at 0x800 (the block is at 0)
        la    t0, rep                   ; ...
        li    t1, 0x800                 ; ...
        li    t2, 16                    ; ...
        tput  tg1, t0, c5, t1, t2       ; ...
        cgive c5, zero                  ; B1 to core 0 (after the tput)
        j     park                      ; done

; submit(a0 = op, a1 = byte 1, a2 = id, a3 = lba): one block, buffer offset 0, through c6
submit:
        la    t0, cmd                   ; t0 = command buffer
        sb    a0, 0(t0)                 ; op
        sb    a1, 1(t0)                 ; byte 1 (reserved)
        sh    a2, 2(t0)                 ; id
        li    t1, 1                     ; one block
        sw    t1, 4(t0)                 ; ...
        sd    a3, 8(t0)                 ; lba
        sd    zero, 16(t0)              ; byte offset 0
        sd    zero, 24(t0)              ; reserved
        li    t1, B_SQ                  ; submission port
        li    t2, 32                    ; one command
        tput  tg13, t0, c6, t1, t2      ; submit
        twait tg13                      ; (it is in the device's queue)
        ret                             ; back

; fill(a0 = lba): blk = the pattern of that lba
fill:
        la    t0, blk                   ; ...
        li    t1, 0                     ; word index
        li    t2, K                     ; ...
fl:     mul   t3, t1, t2                ; word i = i * K + lba
        add   t3, t3, a0                ; ...
        slli  t4, t1, 3                 ; ...
        add   t4, t0, t4                ; ...
        sd    t3, 0(t4)                 ; ...
        addi  t1, t1, 1                 ; ...
        li    t4, 64                    ; 512 bytes
        bne   t1, t4, fl                ; ...
        ret                             ; ...

; diff(a0 = lba) -> a0: words of blk that differ from that lba's pattern
diff:
        la    t0, blk                   ; ...
        li    t1, 0                     ; word index
        li    t2, K                     ; ...
        li    t5, 0                     ; differences
df:     mul   t3, t1, t2                ; ...
        add   t3, t3, a0                ; ...
        slli  t4, t1, 3                 ; ...
        add   t4, t0, t4                ; ...
        ld    t4, 0(t4)                 ; ...
        beq   t3, t4, df_same           ; ...
        addi  t5, t5, 1                 ; ...
df_same:
        addi  t1, t1, 1                 ; ...
        li    t4, 64                    ; ...
        bne   t1, t4, df                ; ...
        mv    a0, t5                    ; ...
        ret                             ; ...

; cqget -> a0: the next completion (id | status << 16 | blocks << 32), through c6
cqget:
        la    t0, cqe                   ; ...
        li    t1, B_CQ                  ; ...
        li    t2, 16                    ; ...
        tget  tg13, t0, c6, t1, t2      ; ...
        ld    a0, 0(t0)                 ; ...
        ret                             ; ...

; ---- core 0 ------------------------------------------------------------------------
boss:
        csrr  s0, ncores                ; s0 = the device's node
        cmov  c6, c3                    ; c6 = the block device's window [0x2000, 0x3000)
        li    t0, B_WIN                 ; ...
        csplit c7, c6, t0               ; ...
        li    t0, 0x1000                ; ...
        csplit c8, c7, t0               ; c7 = the window
        cclear c8                       ; ...
        cmov  c6, c7                    ; ...
        cclear c7                       ; ...
        li    t0, B0                    ; c5 = B0, c9 = B1
        csplit c5, c0, t0               ; ...
        li    t0, 0x1000                ; ...
        csplit c9, c5, t0               ; ...
        csplit c10, c9, t0              ; ...
        cclear c10                      ; ...
        ; the disk: lba 10 = A, lba 11 = B (through B0)
        li    a0, 10                    ; ...
        call  fill                      ; ...
        call  putblk                    ; B0[0..512) = blk
        li    a0, OP_WR                 ; ...
        li    a1, 0                     ; ...
        li    a2, 0x0a0a                ; ...
        li    a3, 10                    ; ...
        call  submit                    ; ...
        cgive c5, s0                    ; ...
        ctake c5, s0                    ; ...
        call  cqget                     ; ...
        li    a1, 0x0a0a | 1 << 32      ; OK, one block
        call  chk                       ; ...
        li    a0, 11                    ; ...
        call  fill                      ; ...
        call  putblk                    ; ...
        li    a0, OP_WR                 ; ...
        li    a1, 0                     ; ...
        li    a2, 0x0b0b                ; ...
        li    a3, 11                    ; ...
        call  submit                    ; ...
        cgive c5, s0                    ; ...
        ctake c5, s0                    ; ...
        call  cqget                     ; ...
        li    a1, 0x0b0b | 1 << 32      ; ...
        call  chk                       ; ...
        call  zeroblk                   ; B0[0..512) = 0
        ; core 1: B1 and the window
        li    t0, 1                     ; ...
        cgive c9, t0                    ; ...
        cmov  c7, c6                    ; ...
        cgive c7, t0                    ; ...

; 1. the orphan came back to core 1 (it tells us: a token)
        li    t0, 1                     ; ...
        ctake c7, t0                    ; ...
        cclear c7                       ; ...

; 2. our command first, our buffer last
        li    a0, OP_RD                 ; read lba 10 into B0 (not given yet)
        li    a1, 0                     ; ...
        li    a2, 0x2222                ; ...
        li    a3, 10                    ; ...
        call  submit                    ; ...
        cmov  c7, c2                    ; go, core 1 (a token)
        li    t0, 1                     ; ...
        cgive c7, t0                    ; ...
        li    t0, 1                     ; core 1 has submitted and given B1
        ctake c7, t0                    ; ...
        cclear c7                       ; ...
        li    t0, 500                   ; (time for a device that pairs by arrival to do so)
dly:    addi  t0, t0, -1                ; ...
        bnez  t0, dly                   ; ...
        cgive c5, s0                    ; B0 to the device
        ctake c5, s0                    ; and back
        cbase a0, c5                    ; B0 itself
        li    a1, B0                    ; ...
        call  chk                       ; ...
        call  getblk                    ; it holds lba 10
        li    a0, 10                    ; ...
        call  diff                      ; ...
        li    a1, 0                     ; ...
        call  chk                       ; ...
        li    t0, 1                     ; B1 with core 1's report
        ctake c9, t0                    ; ...
        cbase a0, c9                    ; ...
        li    a1, B1                    ; ...
        call  chk                       ; ...
        la    t0, rep                   ; the orphan, as core 1 got it back: B1, 4 KiB
        li    t1, 0x800                 ; ...
        li    t2, 16                    ; ...
        tget  tg1, t0, c9, t1, t2       ; ...
        ld    a0, rep(zero)             ; ...
        li    a1, B1                    ; ...
        call  chk                       ; ...
        ld    a0, rep+8(zero)           ; ...
        li    a1, 0x1000                ; ...
        call  chk                       ; ...
        la    t0, blk                   ; B1 holds lba 11
        li    t1, 512                   ; ...
        tget  tg1, t0, c9, zero, t1     ; ...
        twait tg1                       ; ...
        li    a0, 11                    ; ...
        call  diff                      ; ...
        li    a1, 0                     ; ...
        call  chk                       ; ...
        call  cqget                     ; the completions, in command order
        li    a1, 0x2222 | 1 << 32      ; ...
        call  chk                       ; ...
        call  cqget                     ; ...
        li    a1, 0x1111 | 1 << 32      ; ...
        call  chk                       ; ...

; 3. byte 1 names core 1: B0 still comes back here
        call  zeroblk                   ; ...
        li    a0, OP_RD                 ; ...
        li    a1, 1                     ; byte 1: core 1
        li    a2, 0x3333                ; ...
        li    a3, 11                    ; ...
        call  submit                    ; ...
        cgive c5, s0                    ; ...
        ctake c5, s0                    ; ...
        cbase a0, c5                    ; ...
        li    a1, B0                    ; ...
        call  chk                       ; ...
        call  cqget                     ; ...
        li    a1, 0x3333 | 1 << 32      ; ...
        call  chk                       ; ...
        call  getblk                    ; ...
        li    a0, 11                    ; ...
        call  diff                      ; ...
        li    a1, 0                     ; ...
        call  chk                       ; ...
        call  done                      ; print and halt

; putblk / getblk / zeroblk: blk <-> B0[0..512) (c5)
putblk:
        la    t0, blk                   ; ...
        li    t1, 512                   ; ...
        tput  tg2, t0, c5, zero, t1     ; ...
        twait tg2                       ; ...
        ret                             ; ...
getblk:
        la    t0, blk                   ; ...
        li    t1, 512                   ; ...
        tget  tg2, t0, c5, zero, t1     ; ...
        twait tg2                       ; ...
        ret                             ; ...
zeroblk:
        la    t0, blk                   ; ...
        li    t1, 0                     ; ...
zb:     slli  t2, t1, 3                 ; ...
        add   t2, t0, t2                ; ...
        sd    zero, 0(t2)               ; ...
        addi  t1, t1, 1                 ; ...
        li    t2, 64                    ; ...
        bne   t1, t2, zb                ; ...
        addi  sp, sp, -8                ; ...
        sd    ra, 0(sp)                 ; ...
        call  putblk                    ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...
