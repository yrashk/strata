; =============================================================================
; reset.s: the core-control reset request (bit 1 of a core-control word)
; =============================================================================
; stdin: open
;
; What it checks (manual: core control, "reset request")
;   * A reset request is taken in ANY mode: by a supervisor that spins and
;     ignores stop requests (core 1), by a halted core (core 2: a gift to it
;     is refused, capop, until the reset revives it), by a core in user mode
;     (core 3), and by a core that writes it to itself (core 4: the request
;     takes effect before its next instruction, which never runs).
;   * What a reset clears (core 1 sets each one first): the integer registers
;     (sp comes back as the D-LS size, the harness's rsp),
;     the capability registers (only the console capability c2 comes back),
;     the save table (crestore / crestorex of its slots: capinv), the CSRs
;     (scratch, sscratch, ccr, ttag, tdata, tgeom, xslot, corecount, utvec,
;     ucause, uepc, utval, cause, epc, tval, ipend: the stop request sent
;     before the reset is gone), instret (counts from the reset), the overlay
;     map (an entry made before: xmiss), the inbox (a gift waiting in it is
;     gone: the first gift after the reset is the first one taken), the
;     transfer tags (a console read left waiting: no tag busy).
;   * The Local Stores: the first 4 KiB of each come back from the boot image
;     (the boot ROM: a D-LS word and a string overwritten before; a routine in
;     the I-LS overwritten by tgetx runs as in the image again), the rest is
;     cleared (a word written before, and an initialised word of the image
;     above 4 KiB, both read 0).
;   * The core restarts at pc 0 in supervisor mode (status = 3) and runs the
;     image from its start: this harness's _start, then main.
; Every target core reports through a 4 KiB region of system memory that core
; 0 gives it (word 0: the phase, 1 before the reset and 2 after); the reset
; path (the harness, main's dispatch and every target's code) lies in the
; first 4 KiB of the I-LS, which is all a reset brings back.

        .include "lib/conf.s"           ; harness: _start, sig/chk/chkt/done, trap recorder

R1 = 0x100000                           ; core 1's region (system memory)
T_DL = 0x3010                           ; the timer's DEADLINE register: cores 3 and 4 signal through it
NRES1 = 18                              ; words core 1 reports
NRES = 4                                ; words the other targets report

        .far                            ; system memory image
        .org  0x100200                  ; inside core 1's region: the routine tgetx puts over imark
imark2: li    a0, 2                     ; the overwritten imark returns 2
        ret                             ; back

        .data                           ; data Local Store (each core has its own)
        .align 8                        ; transfer buffers
hi:     .dword 0x7777                   ; an image word above 4 KiB: a reset clears it
r_x:    .dword 0                        ; the integer registers ORed together, at entry
r_cv:   .dword 0                        ; capability registers valid at entry (but c2)
r_c2p:  .dword 0                        ; c2's cperms at entry
r_c2l:  .dword 0                        ; c2's length at entry
r_csr:  .dword 0                        ; the CSRs a reset clears, ORed together, at entry
r_ins:  .dword 0                        ; instret at entry
r_st:   .dword 0                        ; status at entry
r_tc:   .dword 0                        ; traps recorded at entry (the harness's tcount)
pbuf:   .dword 0                        ; the phase word read
inb:    .dword 0                        ; the console read that waits (core 1)
b4:     .space 24                       ; core 4's transfer words
ccbuf:  .dword 0                        ; core 0's core-control word
rres:   .space 8 * 32                   ; a target's report
bres:   .space 8 * 32                   ; core 0's copy of a report

        .text                           ; instruction Local Store
; ---- every core starts here (also after a reset); targets: cores 1..4 ----------
main:
        csrr  t0, coreid                ; which core?
        beqz  t0, boss                  ; core 0 runs the test
        li    t1, 5                     ; cores 5.. have nothing to do
        bgeu  t0, t1, park              ; halt
        ; what the core holds at entry (sp, t0, t1: _start's and this code's)
        or    t1, ra, gp                ; the integer registers, ORed
        or    t1, t1, tp                ; ...
        or    t1, t1, t2                ; ...
        or    t1, t1, s0                ; ...
        or    t1, t1, s1                ; ...
        or    t1, t1, a0                ; ...
        or    t1, t1, a1                ; ...
        or    t1, t1, a2                ; ...
        or    t1, t1, a3                ; ...
        or    t1, t1, a4                ; ...
        or    t1, t1, a5                ; ...
        or    t1, t1, a6                ; ...
        or    t1, t1, a7                ; ...
        or    t1, t1, s2                ; ...
        or    t1, t1, s3                ; ...
        or    t1, t1, s4                ; ...
        or    t1, t1, s5                ; ...
        or    t1, t1, s6                ; ...
        or    t1, t1, s7                ; ...
        or    t1, t1, s8                ; ...
        or    t1, t1, s9                ; ...
        or    t1, t1, s10               ; ...
        or    t1, t1, s11               ; ...
        or    t1, t1, t3                ; ...
        or    t1, t1, t4                ; ...
        or    t1, t1, t5                ; ...
        or    t1, t1, t6                ; ...
        ld    t2, rsp(zero)             ; and sp at entry (the harness kept it): the D-LS size,
        li    t3, 0x10000               ;   64 KiB here, also after a reset
        xor   t2, t2, t3                ; (0 if so)
        or    t1, t1, t2                ; ...
        sd    t1, r_x(zero)             ; keep it
        csrr  t1, instret               ; instructions since the reset (or power-on)
        sd    t1, r_ins(zero)           ; ...
        cvalid t1, c0                   ; capability registers valid (c2 apart)
        cvalid t2, c1                   ; ...
        add   t1, t1, t2                ; ...
        cvalid t2, c3                   ; ...
        add   t1, t1, t2                ; ...
        cvalid t2, c4                   ; ...
        add   t1, t1, t2                ; ...
        cvalid t2, c5                   ; ...
        add   t1, t1, t2                ; ...
        cvalid t2, c6                   ; ...
        add   t1, t1, t2                ; ...
        cvalid t2, c7                   ; ...
        add   t1, t1, t2                ; ...
        cvalid t2, c8                   ; ...
        add   t1, t1, t2                ; ...
        cvalid t2, c9                   ; ...
        add   t1, t1, t2                ; ...
        cvalid t2, c10                  ; ...
        add   t1, t1, t2                ; ...
        cvalid t2, c11                  ; ...
        add   t1, t1, t2                ; ...
        cvalid t2, c12                  ; ...
        add   t1, t1, t2                ; ...
        cvalid t2, c13                  ; ...
        add   t1, t1, t2                ; ...
        cvalid t2, c14                  ; ...
        add   t1, t1, t2                ; ...
        cvalid t2, c15                  ; ...
        add   t1, t1, t2                ; ...
        sd    t1, r_cv(zero)            ; ...
        cperms t1, c2                   ; the console capability
        sd    t1, r_c2p(zero)           ; ...
        clen  t1, c2                    ; ...
        sd    t1, r_c2l(zero)           ; ...
        csrr  t1, scratch               ; the CSRs a reset clears, ORed
        csrr  t2, sscratch              ; ...
        or    t1, t1, t2                ; ...
        csrr  t2, ccr                   ; ...
        or    t1, t1, t2                ; ...
        csrr  t2, ttag                  ; ...
        or    t1, t1, t2                ; ...
        csrr  t2, tdata                 ; ...
        or    t1, t1, t2                ; ...
        csrr  t2, tgeom                 ; ...
        or    t1, t1, t2                ; ...
        csrr  t2, xslot                 ; ...
        or    t1, t1, t2                ; ...
        csrr  t2, corecount             ; ...
        or    t1, t1, t2                ; ...
        csrr  t2, utvec                 ; ...
        or    t1, t1, t2                ; ...
        csrr  t2, ucause                ; ...
        or    t1, t1, t2                ; ...
        csrr  t2, uepc                  ; ...
        or    t1, t1, t2                ; ...
        csrr  t2, utval                 ; ...
        or    t1, t1, t2                ; ...
        csrr  t2, cause                 ; ...
        or    t1, t1, t2                ; ...
        csrr  t2, epc                   ; ...
        or    t1, t1, t2                ; ...
        csrr  t2, tval                  ; ...
        or    t1, t1, t2                ; ...
        csrr  t2, ipend                 ; ...
        or    t1, t1, t2                ; ...
        sd    t1, r_csr(zero)           ; ...
        csrr  t1, status                ; the mode (3: supervisor, eret to supervisor)
        sd    t1, r_st(zero)            ; ...
        ld    t1, tcount(zero)          ; traps recorded so far
        sd    t1, r_tc(zero)            ; ...
        ; the region from core 0, and the phase in its word 0
        ctake c5, zero                  ; from core 0
        la    t0, pbuf                  ; ...
        li    t1, 8                     ; ...
        tget  tg1, t0, c5, zero, t1     ; the phase
        ld    s10, 0(t0)                ; s10 = 1 before the reset, 2 after
        csrr  t0, coreid                ; dispatch
        li    t1, 1                     ; ...
        beq   t0, t1, w1                ; ...
        li    t1, 2                     ; ...
        beq   t0, t1, w2                ; ...
        li    t1, 3                     ; ...
        beq   t0, t1, w3                ; ...
        j     w4                        ; ...

        .align 8                        ; (a tgetx target: 8-byte aligned)
imark:  li    a0, 1                     ; as in the image: returns 1
        ret                             ; back
xhit:   li    s9, 0xbad                 ; reached only through a stale overlay entry
        ret                             ; back

; report(a0 = words): rres -> region offset 64, the region back to core 0, halt
report:
        la    t0, rres                  ; ...
        slli  t1, a0, 3                 ; bytes
        li    t2, 64                    ; ...
        tput  tg2, t0, c5, t2, t1       ; ...
        cgive c5, zero                  ; to core 0 (waits for the tput)
        j     park                      ; done

; the four words every target reports after its reset
basic:
        la    t0, rres                  ; ...
        ld    t1, r_x(zero)             ; 0: registers
        sd    t1, 0(t0)                 ; ...
        ld    t1, r_cv(zero)            ; 1: capabilities
        sd    t1, 8(t0)                 ; ...
        ld    t1, r_csr(zero)           ; 2: CSRs
        sd    t1, 16(t0)                ; ...
        ld    t1, r_st(zero)            ; 3: status
        sd    t1, 24(t0)                ; ...
        ret                             ; ...

; ---- core 1: a supervisor with state everywhere, spinning --------------------------
w1:
        li    t0, 1                     ; before the reset?
        bne   s10, t0, w1_after         ; no
        ctake c6, zero                  ; the console input port, from core 0
        ; capabilities: copies in registers and in the save table
        cmov  c7, c6                    ; (copyable)
        cmov  c8, c6                    ; ...
        cmov  c15, c6                   ; ...
        csave c6, 3                     ; slot 3
        li    t0, 100                   ; slot 100
        csavex c6, t0                   ; ...
        ; a trap: cause, epc, tval
        crestore c9, 50                 ; an empty slot: capinv
        ; CSRs
        li    t0, 0x5a                  ; ...
        csrw  scratch, t0               ; ...
        csrw  sscratch, t0              ; ...
        csrw  ttag, t0                  ; ...
        csrw  tdata, t0                 ; ...
        csrw  tgeom, t0                 ; ...
        csrw  utvec, t0                 ; ...
        csrw  ucause, t0                ; ...
        csrw  uepc, t0                  ; ...
        csrw  utval, t0                 ; ...
        li    t0, 8                     ; a window of all 8 cores (relative = physical)
        csrw  corecount, t0             ; ...
        ; the overlay map: R1 + 0x100 -> xhit
        li    t0, 0x100                 ; ...
        la    t1, xhit                  ; ...
        xmap  0, t1, c5, t0             ; ...
        li    t0, 4                     ; 16-byte slots
        csrw  xslot, t0                 ; ...
        ; the I-LS: imark returns 2 now
        la    t1, imark                 ; ...
        li    t2, 0x200                 ; imark2
        li    t3, 8                     ; ...
        tgetx tg2, t1, c5, t2, t3       ; ...
        ; the D-LS: below 4 KiB and above
        li    t0, 0x55                  ; ...
        sd    t0, dbuf(zero)            ; the harness's buffer (image: 0)
        la    t1, line                  ; its line buffer (image: "sig ...")
        sb    t0, 0(t1)                 ; ...
        li    t0, 0x1234                ; ...
        li    t1, 0xa000                ; ...
        sd    t0, 0(t1)                 ; ...
        ; a console read that waits (no input ever comes)
        la    t0, inb                   ; ...
        li    t1, 1                     ; ...
        tget  tg3, t0, c6, zero, t1     ; ...
        li    t0, 1                     ; CCR.PTRAP
        csrw  ccr, t0                   ; ...
        ; every register non-zero, then ready (R1 back) and spin
        li    ra, 1                     ; ...
        li    gp, 2                     ; ...
        li    tp, 3                     ; ...
        li    t0, 4                     ; ...
        li    t1, 5                     ; ...
        li    t2, 6                     ; ...
        li    s0, 7                     ; ...
        li    s1, 8                     ; ...
        li    a0, 9                     ; ...
        li    a1, 10                    ; ...
        li    a2, 11                    ; ...
        li    a3, 12                    ; ...
        li    a4, 13                    ; ...
        li    a5, 14                    ; ...
        li    a6, 15                    ; ...
        li    a7, 16                    ; ...
        li    s2, 17                    ; ...
        li    s3, 18                    ; ...
        li    s4, 19                    ; ...
        li    s5, 20                    ; ...
        li    s6, 21                    ; ...
        li    s7, 22                    ; ...
        li    s8, 23                    ; ...
        li    s9, 24                    ; ...
        li    s10, 25                   ; ...
        li    s11, 26                   ; ...
        li    t3, 27                    ; ...
        li    t4, 28                    ; ...
        li    t5, 29                    ; ...
        li    t6, 30                    ; ...
        cgive c5, zero                  ; ready: R1 back to core 0
w1_spin:
        j     w1_spin                   ; a supervisor never takes a stop

w1_after:
        call  basic                     ; rres[0..3]
        la    s1, rres                  ; s1 = the report
        ld    t0, r_c2p(zero)           ; 4: c2's perms
        sd    t0, 32(s1)                ; ...
        ld    t0, r_c2l(zero)           ; 5: c2's length
        sd    t0, 40(s1)                ; ...
        ld    t0, r_ins(zero)           ; 6: instret at entry
        sd    t0, 48(s1)                ; ...
        ld    t0, r_tc(zero)            ; 7: traps recorded at entry
        sd    t0, 56(s1)                ; ...
        crestore c7, 3                  ; 8: the save table is empty: capinv
        ld    t0, tcause(zero)          ; ...
        sd    t0, 64(s1)                ; ...
        sd    zero, tcause(zero)        ; ...
        li    t0, 100                   ; 9: slot 100 too
        crestorex c7, t0                ; ...
        ld    t0, tcause(zero)          ; ...
        sd    t0, 72(s1)                ; ...
        sd    zero, tcause(zero)        ; ...
        li    s9, 0                     ; 10: the overlay entry is gone: xmiss
        li    t0, 0x100                 ; ...
        xcall ra, c5, t0                ; ...
        ld    t0, tcause(zero)          ; ...
        sd    t0, 80(s1)                ; ...
        sd    zero, tcause(zero)        ; ...
        sd    s9, 88(s1)                ; 11: (xhit did not run)
        call  imark                     ; 12: the I-LS boot ROM is back: 1
        sd    a0, 96(s1)                ; ...
        ld    t0, dbuf(zero)            ; 13: the D-LS boot ROM is back: 0
        sd    t0, 104(s1)               ; ...
        la    t1, line                  ; 14: ... and "sig 0123"
        ld    t0, 0(t1)                 ; ...
        sd    t0, 112(s1)               ; ...
        ld    t0, hi(zero)              ; 15: above 4 KiB: cleared, image or not
        sd    t0, 120(s1)               ; ...
        li    t1, 0xa000                ; 16: ...
        ld    t0, 0(t1)                 ; ...
        sd    t0, 128(s1)               ; ...
        tpoll t0, 0xffff                ; 17: no tag busy (the waiting read is gone)
        sd    t0, 136(s1)               ; ...
        li    a0, NRES1                 ; ...
        j     report                    ; ...

; ---- core 2: halts, is revived by a reset --------------------------------------------
w2:
        li    t0, 1                     ; before the reset?
        bne   s10, t0, w2_after         ; no
        cgive c5, zero                  ; ready: the region back
        j     park                      ; and halt
w2_after:
        call  basic                     ; ...
        li    a0, NRES                  ; ...
        j     report                    ; ...

; ---- core 3: in user mode when reset -----------------------------------------------
w3:
        li    t0, 1                     ; before the reset?
        bne   s10, t0, w3_after         ; no
        ctake c6, zero                  ; the timer's DEADLINE register (the signal to core 0)
        la    a0, w3_user               ; on in user mode
        j     to_user                   ; ...
w3_user:
        li    t0, 0x3333                ; tell core 0: running in user mode
        la    t1, rres                  ; ...
        sd    t0, 0(t1)                 ; ...
        li    t3, 8                     ; ...
        tput  tg1, t1, c6, zero, t3     ; DEADLINE = 0x3333
w3_spin:
        j     w3_spin                   ; ...
w3_after:
        call  basic                     ; ...
        li    a0, NRES                  ; ...
        j     report                    ; ...

; ---- core 4: resets itself ---------------------------------------------------------
w4:
        li    t0, 1                     ; before the reset?
        bne   s10, t0, w4_after         ; no
        ctake c6, zero                  ; core control for this core alone
        ctake c7, zero                  ; DEADLINE
        la    t1, b4                    ; the three words first
        li    t0, 0x4441                ; "about to reset": DEADLINE = 0x4441
        sd    t0, 0(t1)                 ; ...
        li    t0, 2                     ; the reset request, to itself
        sd    t0, 8(t1)                 ; ...
        li    t0, 0x4442                ; DEADLINE = 0x4442: must never be written
        sd    t0, 16(t1)                ; ...
        addi  t4, t1, 8                 ; ...
        addi  t5, t1, 16                ; ...
        li    t3, 8                     ; ...
        tput  tg1, t1, c7, zero, t3     ; DEADLINE = 0x4441
        tput  tg2, t4, c6, zero, t3     ; the reset request (queued behind the DEADLINE write)
        tput  tg3, t5, c7, zero, t3     ; never runs: the request takes effect before it
w4_spin:
        j     w4_spin                   ; ...
w4_after:
        call  basic                     ; ...
        li    a0, NRES                  ; ...
        j     report                    ; ...

; =============================================================================
; core 0
; =============================================================================

; ccw(a0 = core, a1 = word): write a core-control word, wait until it is done
ccw:
        la    t0, ccbuf                 ; ...
        sd    a1, 0(t0)                 ; ...
        slli  t1, a0, 3                 ; offset 8 * core
        li    t2, 8                     ; ...
        tput  tg4, t0, c4, t1, t2       ; ...
        twait tg4                       ; ...
        ret                             ; ...

; phase(a0): word 0 of the region in c5 = a0
phase:
        la    t0, ccbuf                 ; ...
        sd    a0, 0(t0)                 ; ...
        li    t1, 8                     ; ...
        tput  tg4, t0, c5, zero, t1     ; ...
        twait tg4                       ; ...
        ret                             ; ...

; getres(a0 = words): bres = the report in c5 (offset 64)
getres:
        la    t0, bres                  ; ...
        slli  t1, a0, 3                 ; ...
        li    t2, 64                    ; ...
        tget  tg4, t0, c5, t2, t1       ; ...
        twait tg4                       ; ...
        ret                             ; ...

; givedl(a0 = core): give it a capability for the timer's DEADLINE register
givedl:
        cmov  c6, c3                    ; [T_DL, T_DL + 8) of the devices
        li    t0, T_DL                  ; ...
        csplit c7, c6, t0               ; ...
        li    t0, 8                     ; ...
        csplit c8, c7, t0               ; c7 = DEADLINE
        cgive c7, a0                    ; ...
        cclear c6                       ; ...
        cclear c8                       ; ...
        ret                             ; ...

; chkbasic: the four words every target reports (bres[0..3])
chkbasic:
        addi  sp, sp, -8                ; ...
        sd    ra, 0(sp)                 ; ...
        ld    a0, bres(zero)            ; registers: all zero
        li    a1, 0                     ; ...
        call  chk                       ; ...
        ld    a0, bres+8(zero)          ; capabilities: c2 only
        li    a1, 0                     ; ...
        call  chk                       ; ...
        ld    a0, bres+16(zero)         ; CSRs: zero
        li    a1, 0                     ; ...
        call  chk                       ; ...
        ld    a0, bres+24(zero)         ; supervisor mode
        li    a1, 3                     ; ...
        call  chk                       ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

boss:
        ; regions of system memory, kept in the save table
        li    t0, R1                    ; c5 = [1 MiB, ...)
        csplit c5, c0, t0               ; ...
        li    t0, 0x1000                ; 4 KiB each
        csplit c6, c5, t0               ; c5 = R1
        csave c5, 10                    ; slot 10: R1
        csplit c5, c6, t0               ; c6 = R2
        csave c6, 11                    ; slot 11: R2
        csplit c6, c5, t0               ; c5 = R3
        csave c5, 12                    ; slot 12: R3
        csplit c5, c6, t0               ; c6 = R3b
        csave c6, 13                    ; slot 13: R3b
        csplit c6, c5, t0               ; c5 = R4
        csave c5, 14                    ; slot 14: R4
        csplit c5, c6, t0               ; c6 = R4b
        csave c6, 15                    ; slot 15: R4b
        csplit c6, c5, t0               ; c5 = X (a stray gift)
        csave c5, 16                    ; slot 16: X
        cclear c6                       ; (the rest is not needed)

; ---- core 1 ------------------------------------------------------------------------
        crestore c5, 10                 ; R1, phase 1
        li    a0, 1                     ; ...
        call  phase                     ; ...
        li    t0, 1                     ; ...
        cgive c5, t0                    ; ...
        cmov  c6, c3                    ; the console input port: [8, 16) of the devices
        li    t0, 8                     ; ...
        csplit c7, c6, t0               ; ...
        csplit c8, c7, t0               ; c7 = [8, 16)
        li    t0, 1                     ; ...
        cgive c7, t0                    ; ...
        cclear c6                       ; ...
        cclear c8                       ; ...
        li    t0, 1                     ; ready: R1 comes back
        ctake c5, t0                    ; ...
        li    a0, 1                     ; a stop request: a supervisor does not take it
        li    a1, 1                     ; ...
        call  ccw                       ; ...
        crestore c6, 16                 ; a gift left in its inbox
        li    t0, 1                     ; ...
        cgive c6, t0                    ; ...
        li    a0, 1                     ; the reset request
        li    a1, 2                     ; ...
        call  ccw                       ; ...
        li    a0, 2                     ; R1 again, phase 2
        call  phase                     ; ...
        li    t0, 1                     ; ...
        cgive c5, t0                    ; ...
        li    t0, 1                     ; the report
        ctake c5, t0                    ; ...
        cbase a0, c5                    ; R1 itself (the stray gift was not taken first)
        li    a1, R1                    ; ...
        call  chk                       ; ...
        li    a0, NRES1                 ; ...
        call  getres                    ; ...
        call  chkbasic                  ; 0..3
        ld    a0, bres+32(zero)         ; 4: c2 is the console capability
        li    a1, SP_DEV << 8 | P_W | P_D ; ...
        call  chk                       ; ...
        ld    a0, bres+40(zero)         ; 5: one byte
        li    a1, 1                     ; ...
        call  chk                       ; ...
        ld    a0, bres+48(zero)         ; 6: instret counts from the reset
        call  sig                       ; (the exact count, in the signature)
        sltiu a0, a0, 64                ; a few dozen instructions
        li    a1, 1                     ; ...
        call  chk                       ; ...
        ld    a0, bres+56(zero)         ; 7: no trap recorded (the D-LS boot ROM is back)
        li    a1, 0                     ; ...
        call  chk                       ; ...
        ld    a0, bres+64(zero)         ; 8: save table slot 3: empty
