; =============================================================================
; lswin.s: the Local Store windows (wdata, wstack, wcode)
; =============================================================================
;
; What it checks (manual: Local Store windows). Written for 64 KiB stores,
; where a window unit (1/64 of a store) is 1 KiB; on other sizes it only
; says pass.
;   * The CSRs: supervisor-only (csrr and csrw in user mode trap with priv),
;     the reserved bits read as zero, and they change nothing in supervisor
;     mode.
;   * Loads and stores in user mode: inside wdata (identity here) and
;     wstack (relocated: virtual 0xF000.. is physical 0xD000..), outside
;     both (lsfault, tval = the virtual address, nothing written), wdata
;     before wstack where both cover an address.
;   * Transfers: a range inside a window is relocated; one that leaves its
;     window, or begins in one window and ends in the other, traps with
;     lsfault (tval = the virtual address); a range of no bytes is not
;     looked at.
;   * ltag/linst: the set's entry is relocated; one outside the windows
;     traps with lsfault, tval = the entry's virtual address.
;   * xmap: an I-LS address outside wcode traps with lsfault.
;   * Fetch: outside wcode, ifault (epc = tval = the virtual pc); a
;     relocated code window runs code from its physical unit, a user tgetx
;     into it lands there too, and running off the window's end faults at
;     the next unit's virtual address.
;   * With no window enabled, user mode reaches the whole store as before.

        .include "lib/conf.s"           ; harness: _start, sig/chk/chkt/done, trap recorder

FAR  = 0x200000                         ; system memory scratch (c0 offsets)
PATT = 0x5a5a00000000c0de               ; a pattern for the transfers

        .far                            ; system memory image (c0 offsets)
; image A: one I-LS unit (1 KiB), put at physical unit 62 (not the last: the word
; after it exists, so a fetch that runs on would find one); user mode runs it at
; virtual unit 1 through wcode (assembled at its own offsets: relative jumps only)
        .org  FAR
ua:     addi  a0, a0, 1000              ; offset 0: replaced by the user's tgetx (image B)
        j     ua_last                   ; ...
        .org  FAR + 0x3f0               ; the entry: the last four words of the unit
ua_go:  tgetx tg1, a1, c0, a2, a3       ; image B's first 8 bytes over offset 0 (a1 = virtual unit 1)
        twait tg1                       ; ...
        jalr  zero, a1, 0               ; run them
ua_last: addi a0, a0, 1                 ; a0 += 1, then the fetch runs off the window: ifault
; image B: the same layout; only its first two words are used
        .org  FAR + 0x400
ub:     addi  a0, a0, 100               ; offset 0
        j     ub_last                   ; ...
        .org  FAR + 0x7fc
ub_last: addi a0, a0, 1                 ; (not reached: image A's word is there)
        .org  FAR + 0x800               ; transfer source: eight doublewords
fsrc:   .dword PATT, PATT + 1, PATT + 2, PATT + 3, PATT + 4, PATT + 5, PATT + 6, PATT + 7
        .org  FAR + 0x900               ; transfer target
fdst:   .space 64

        .data                           ; data Local Store
        .align 8                        ; transfer buffer
tbl:    .space 32                       ; the platform table's header
tbuf:   .space 64                       ; a buffer of the test's own

        .text                           ; instruction Local Store
main:
        csrr  t0, coreid                ; which core?
        bnez  t0, park                  ; only core 0 runs the test
        la    s1, tbl                   ; the platform table's header: the stores' sizes
        li    t0, 0x1000                ; ...
        li    t1, 32                    ; ...
        tget  tg1, s1, c3, t0, t1       ; ...
        twait tg1                       ; ...
        lhu   t0, 24(s1)                ; D-LS KiB
        lhu   t1, 26(s1)                ; I-LS KiB
        li    t2, 64                    ; both 64?
        bne   t0, t2, wdone             ; no: nothing to check here
        bne   t1, t2, wdone             ; ...
        li    s0, 1                     ; s0 = the enable bit
        slli  s0, s0, 63                ; ...

; ---- the CSRs in supervisor mode -----------------------------------------------------------------
        li    t0, -1                    ; every bit
        csrw  wdata, t0                 ; ...
        csrr  a0, wdata                 ; only enable, vlo, len, pbase are kept
        li    a1, 0x7f7f7f              ; ...
        or    a1, a1, s0                ; ...
        call  chk                       ; check
        csrw  wstack, t0                ; the same for wstack
        csrr  a0, wstack                ; ...
        call  chk                       ; ...
        csrw  wcode, t0                 ; and wcode
        csrr  a0, wcode                 ; ...
        call  chk                       ; ...
        li    t0, 1 << 8                ; wdata: one unit at 0, enabled
        or    t0, t0, s0                ; ...
        csrw  wdata, t0                 ; ...
        csrw  wstack, zero              ; ...
        csrw  wcode, t0                 ; wcode: the same
        li    t1, 0xd000                ; supervisor mode: not restricted, not relocated
        li    t2, 0x77                  ; ...
        sd    t2, 0(t1)                 ; ...
        ld    a0, 0(t1)                 ; ...
        li    a1, 0x77                  ; ...
        call  chk                       ; check
        li    a0, 0                     ; no trap
        li    a1, 0                     ; ...
        li    a2, 0                     ; ...
        call  chkt                      ; check

; ---- user mode: loads, stores, transfers, ltag, xmap, the CSRs, the fetch -------------------------
        li    s3, 48                    ; wdata: identity over [0, 0xc000): the data and the
        slli  t0, s3, 8                 ;   harness's stack (s3 = its units)
        or    t0, t0, s0                ; ...
        csrw  wdata, t0                 ; ...
        li    t0, 60 | 4 << 8 | 52 << 16 ; wstack: virtual units 60..63 -> physical 52..55
        or    t0, t0, s0                ; ...
        csrw  wstack, t0                ; ...
        li    t0, 63 << 8               ; wcode: identity over units 0..62
        or    t0, t0, s0                ; ...
        csrw  wcode, t0                 ; ...
        li    t1, 0xd000                ; physical: zeros where the user's stores will land,
        sd    zero, 0(t1)               ;   0x1111 at 0xd008 for its load, zeros at 0xf000
        li    t2, 0x1111                ;   (what an unrelocated store would hit)
        sd    t2, 8(t1)                 ; ...
        sd    zero, 0x200(t1)           ; the ltag entry: an empty way
        sd    zero, 0x208(t1)           ; ...and its counter
        li    t1, 0xf000                ; ...
        sd    zero, 0(t1)               ; ...
        la    t0, back1                 ; where the user code's last trap comes back
        sd    t0, uexit(zero)           ; (and an svc UEXIT)
        la    a0, user1                 ; drop to user mode
        call  to_user                   ; ...

user1:
        li    t0, 0xf000                ; a store and a load in wstack: relocated
        li    t1, 0x2222                ; ...
        sd    t1, 0(t0)                 ; physical 0xd000
        ld    s2, 8(t0)                 ; physical 0xd008: 0x1111
        li    t0, 0xc800                ; outside both windows
u1a:    ld    s4, 0(t0)                 ; lsfault, tval = 0xc800
        li    a0, C_LSFAULT             ; expected cause
        la    a1, u1a                   ; expected epc
        li    a2, 0xc800                ; expected tval
        call  chkt                      ; check
        li    t0, 0xeff8                ; just below wstack
u1b:    sd    t1, 0(t0)                 ; lsfault
        li    a0, C_LSFAULT             ; ...
        la    a1, u1b                   ; ...
        li    a2, 0xeff8                ; ...
        call  chkt                      ; check
        li    t0, 0xf100                ; tget into wstack: relocated (physical 0xd100)
        li    t1, FAR + 0x800           ; ...
        li    t2, 64                    ; ...
        tget  tg2, t0, c0, t1, t2       ; ...
        twait tg2                       ; ...
        li    t1, FAR + 0x900           ; and back out with tput
        tput  tg2, t0, c0, t1, t2       ; ...
        twait tg2                       ; ...
        li    a0, 0                     ; no trap so far
        li    a1, 0                     ; ...
        li    a2, 0                     ; ...
        call  chkt                      ; check
        slli  t0, s3, 10                ; a range that runs past wdata's end
        addi  t0, t0, -8                ; ...
        li    t2, 16                    ; ...
u1c:    tget  tg2, t0, c0, t1, t2       ; lsfault, tval = the address
        li    a0, C_LSFAULT             ; ...
        la    a1, u1c                   ; ...
        mv    a2, t0                    ; ...
        call  chkt                      ; check
        li    t0, 0x100                 ; begins in wdata, ends in wstack
        li    t2, 0xf000                ; ...
u1d:    tget  tg2, t0, c0, t1, t2       ; lsfault
        li    a0, C_LSFAULT             ; ...
        la    a1, u1d                   ; ...
        li    a2, 0x100                 ; ...
        call  chkt                      ; check
        li    t0, 0xc800                ; no bytes, outside the windows: not looked at
        li    t2, 0                     ; ...
        tget  tg2, t0, c0, t1, t2       ; ...
        twait tg2                       ; ...
        li    a0, 0                     ; no trap
        li    a1, 0                     ; ...
        li    a2, 0                     ; ...
        call  chkt                      ; check
        li    t0, 6 | 0 << 6 | 1 << 12  ; ltag: 64-byte lines, one set, one way (16-byte entries)
        csrw  tgeom, t0                 ; ...
        li    t0, 0xf200                ; the entry in wstack: physical 0xd200
        csrw  ttag, t0                  ; ...
        li    t1, 0x40                  ; a line address
        linst t1                        ; its key (0x40 >> 6 << 1 | 1 = 3) into the way
        ltag  a0, t1                    ; a hit now: bit 63 clear
        srli  a0, a0, 63                ; ...
        li    a1, 0                     ; ...
        call  chk                       ; check
        li    t0, 0xc800                ; an entry outside the windows
        csrw  ttag, t0                  ; ...
u1e:    ltag  a0, t1                    ; lsfault, tval = the entry address
        li    a0, C_LSFAULT             ; ...
        la    a1, u1e                   ; ...
        li    a2, 0xc800                ; ...
        call  chkt                      ; check
        li    t0, 0xfc00                ; xmap of an I-LS address outside wcode
        li    t1, FAR                   ; ...
u1f:    xmap  0, t0, c0, t1             ; lsfault
        li    a0, C_LSFAULT             ; ...
        la    a1, u1f                   ; ...
        li    a2, 0xfc00                ; ...
        call  chkt                      ; check
        li    t0, 0x8000                ; and of one inside it: fine
        xmap  0, t0, c0, t1             ; ...
        xunmap 0                        ; ...
        li    a0, 0                     ; no trap
        li    a1, 0                     ; ...
        li    a2, 0                     ; ...
        call  chkt                      ; check
u1g:    csrr  a0, wdata                 ; the window CSRs are the supervisor's
        li    a0, C_PRIV                ; ...
        la    a1, u1g                   ; ...
        li    a2, 0x38 << 26 | 26       ; tval: the instruction (csrr zero... rd = a0)
        li    t0, 10 << 21              ; ...
        or    a2, a2, t0                ; ...
        call  chkt                      ; check
u1h:    csrw  wcode, zero               ; ...
        li    a0, C_PRIV                ; ...
        la    a1, u1h                   ; ...
        li    a2, 0x39 << 26 | 28       ; csrw wcode, zero
        call  chkt                      ; check
        la    t0, back1                 ; last: a jump outside wcode (ifault; back to the supervisor)
        sd    t0, tresume(zero)         ; ...
        li    t0, 0xfc00                ; ...
        jalr  zero, t0, 0               ; ...

back1:                                  ; supervisor mode again
        li    a0, C_IFAULT              ; the fetch outside wcode
        li    a1, 0xfc00                ; epc = tval = the pc
        li    a2, 0xfc00                ; ...
        call  chkt                      ; check
        mv    a0, s2                    ; the user's load through wstack
        li    a1, 0x1111                ; ...
        call  chk                       ; check
        li    t1, 0xd000                ; its store landed at physical 0xd000
        ld    a0, 0(t1)                 ; ...
        li    a1, 0x2222                ; ...
        call  chk                       ; check
        ld    a0, 0x100(t1)             ; the tget landed at physical 0xd100
        li    a1, PATT                  ; ...
        call  chk                       ; check
        ld    a0, 0x138(t1)             ; (its last doubleword)
        li    a1, PATT + 7              ; ...
        call  chk                       ; check
        ld    a0, 0x200(t1)             ; linst wrote its key at physical 0xd200
        li    a1, 3                     ; ...
        call  chk                       ; check
        li    t1, 0xf000                ; nothing at the unrelocated address
        ld    a0, 0(t1)                 ; ...
        li    a1, 0                     ; ...
        call  chk                       ; check
        ld    a0, 0x100(t1)             ; ...
        li    a1, 0                     ; ...
        call  chk                       ; check
        la    t0, tbuf                  ; the tput carried the relocated bytes back out
        li    t1, FAR + 0x900           ; ...
        li    t2, 64                    ; ...
        tget  tg2, t0, c0, t1, t2       ; ...
        twait tg2                       ; ...
        ld    a0, 0(t0)                 ; ...
        li    a1, PATT                  ; ...
        call  chk                       ; check
        ld    a0, 56(t0)                ; ...
        li    a1, PATT + 7              ; ...
        call  chk                       ; check

; ---- wdata before wstack where both cover an address ---------------------------------------------
        la    s4, tbuf                  ; wstack over tbuf's unit, relocated to physical unit 52
        srli  t0, s4, 10                ; ...
        li    t1, 1 << 8 | 52 << 16     ; ...
        or    t0, t0, t1                ; ...
        or    t0, t0, s0                ; ...
        csrw  wstack, t0                ; ...
        sd    zero, 0(s4)               ; ...
        andi  s5, s4, 1023              ; s5 = tbuf's place in physical unit 52: a marker
        li    t1, 52 << 10              ; ...
        add   s5, s5, t1                ; ...
        li    t1, 0x9999                ; ...
        sd    t1, 0(s5)                 ; ...
        la    t0, back2                 ; ...
        sd    t0, uexit(zero)           ; ...
        la    a0, user2                 ; ...
        call  to_user                   ; ...
user2:
        li    t0, 0x3333                ; a store to tbuf: wdata's (identity)
        sd    t0, 0(s4)                 ; ...
        li    a7, UEXIT                 ; back
        svc                             ; ...
back2:
        ld    a0, 0(s4)                 ; at tbuf
        li    a1, 0x3333                ; ...
        call  chk                       ; check
        ld    a0, 0(s5)                 ; not at its place in physical unit 52
        li    a1, 0x9999                ; ...
        call  chk                       ; check

; ---- no window: user mode reaches everything ------------------------------------------------------
        csrw  wdata, zero               ; ...
        csrw  wstack, zero              ; ...
        csrw  wcode, zero               ; ...
        li    t1, 0xc800                ; (above the harness's stack)
        li    t2, 0x4444                ; ...
        sd    t2, 0(t1)                 ; ...
        la    t0, back3                 ; ...
        sd    t0, uexit(zero)           ; ...
        la    a0, user3                 ; ...
        call  to_user                   ; ...
user3:
        li    t0, 0xc800                ; a load the windows would refuse
        ld    s5, 0(t0)                 ; ...
        li    a7, UEXIT                 ; back
        svc                             ; ...
back3:
        mv    a0, s5                    ; ...
        li    a1, 0x4444                ; ...
        call  chk                       ; check
        li    a0, 0                     ; no trap
        li    a1, 0                     ; ...
        li    a2, 0                     ; ...
        call  chkt                      ; check

; ---- a relocated code window ------------------------------------------------------------------------
        li    t0, 0xf800                ; image A into physical unit 62
        li    t1, FAR                   ; ...
        li    t2, 0x400                 ; ...
        tgetx tg3, t0, c0, t1, t2       ; ...
        twait tg3                       ; ...
        li    t0, 1 | 1 << 8 | 62 << 16 ; wcode: virtual unit 1 -> physical 62; no D-LS window
        or    t0, t0, s0                ; ...
        csrw  wcode, t0                 ; ...
        la    t0, back4                 ; the fetch that runs off the window comes back here
        sd    t0, tresume(zero)         ; ...
        li    a0, 5                     ; a0 = 5
        li    a1, 0x400                 ; image B over virtual 0x400 (physical 0xf800)
        li    a2, FAR + 0x400           ; ...
        li    a3, 8                     ; ...
        li    a0, 5                     ; ...
        li    t0, 0x7f0                 ; enter at virtual 0x7f0 (image A's 0x3f0)
        csrw  status, zero              ; (to_user is outside the window: do its work here)
        csrw  epc, t0                   ; ...
        eret                            ; ...
back4:
        li    a1, 5 + 100 + 1           ; image B's word ran (relocated tgetx), then A's last one
        call  chk                       ; check
        li    a0, C_IFAULT              ; then the fetch at virtual 0x800, outside the window
        li    a1, 0x800                 ; ...
        li    a2, 0x800                 ; ...
        call  chkt                      ; check
        csrw  wcode, zero               ; ...
wdone:
        call  done                      ; print the signature and the verdict
