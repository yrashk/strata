; =============================================================================
; pmap.s: the written-page map (device 0x4400)
; =============================================================================
;
; What it checks (doc/strataos.md section 1.2; common/platform.h)
;   * At power-on every bit is set: the word of an untouched granule (T3's
;     granule 100) reads all ones, and so does the last one (255).
;   * A write clears the bits written as 1: writing all ones makes it 0.
;   * A write to T3 sets the bit of its page (bit i of word n: page 64 n + i);
;     a burst that crosses a page boundary sets both pages' bits; a read
;     (tget) sets nothing; a far atomic (tamo) sets its page's bit; a write
;     to T2 sets nothing.
;   * A read is latched at byte 0: a T3 write between reading byte 0 and
;     bytes 1..7 does not show in those bytes; the next read shows it.
;   * A clear takes effect when byte 7 is written: bytes 0..3 of a mask
;     alone change nothing, bytes 4..7 later complete it with the bytes
;     buffered before.
;   * Ports past the map's 256 words read as zero.

        .include "lib/conf.s"           ; harness: _start, sig/chk/chkt/done, trap recorder

PM   = 0x4400                           ; the map's first word (T3 granule 0)
G    = 100                              ; the granule used: T3 [25 MiB, 25 MiB + 256 KiB)
GB   = G << 18                          ; its T3 address
WP   = PM + 8 * G                       ; its word's port
PAGE = 4096                             ; a page

        .data                           ; data Local Store
        .align 8                        ; transfer buffers
buf:    .space 16                       ; device words read / written
dat:    .space 16                       ; data for T3 and T2

        .text                           ; instruction Local Store
main:
        csrr  t0, coreid                ; which core?
        bnez  t0, park                  ; only core 0 runs the test
        la    s1, buf                   ; s1 = the device buffer
        la    s2, dat                   ; s2 = the data buffer
        li    t0, GB                    ; c5 = T3 from granule G on
        csplit c5, c0, t0               ; (c0 = below it)

; ---- power-on, clear ----------------------------------------------------------------------------------
        li    a0, WP                    ; every bit set at power-on
        call  pmrd                      ; ...
        li    a1, -1                    ; ...
        call  chk                       ; ...
        li    a0, PM + 8 * 255          ; the last word too
        call  pmrd                      ; ...
        li    a1, -1                    ; ...
        call  chk                       ; ...
        li    a0, WP                    ; clear them all
        li    a1, -1                    ; ...
        call  pmwr                      ; ...
        li    a0, WP                    ; ...
        call  pmrd                      ; ...
        li    a1, 0                     ; ...
        call  chk                       ; ...

; ---- writes set, reads do not -------------------------------------------------------------------------
        li    t0, 5 * PAGE + 16         ; a word in page 5
        li    t1, 8                     ; ...
        tput  tg1, s2, c5, t0, t1       ; ...
        twait tg1                       ; ...
        li    a0, WP                    ; bit 5
        call  pmrd                      ; ...
        li    a1, 1 << 5                ; ...
        call  chk                       ; ...
        li    t0, 8 * PAGE - 8          ; 16 bytes: the last word of page 7, the first of 8
        li    t1, 16                    ; ...
        tput  tg1, s2, c5, t0, t1       ; ...
        twait tg1                       ; ...
        li    a0, WP                    ; bits 5, 7, 8
        call  pmrd                      ; ...
        li    a1, 1 << 5 | 1 << 7 | 1 << 8 ; ...
        call  chk                       ; ...
        li    t0, 20 * PAGE             ; a read of page 20
        li    t1, 16                    ; ...
        tget  tg1, s2, c5, t0, t1       ; ...
        twait tg1                       ; ...
        li    a0, WP                    ; unchanged
        call  pmrd                      ; ...
        li    a1, 1 << 5 | 1 << 7 | 1 << 8 ; ...
        call  chk                       ; ...

; ---- a read is latched at byte 0 ----------------------------------------------------------------------
        sd    zero, 0(s1)               ; ...
        li    t0, WP                    ; byte 0
        li    t1, 1                     ; ...
        tget  tg1, s1, c3, t0, t1       ; ...
        twait tg1                       ; ...
        li    t0, 63 * PAGE             ; then page 63 written (bit 63: in byte 7)
        li    t1, 8                     ; ...
        tput  tg1, s2, c5, t0, t1       ; ...
        twait tg1                       ; ...
        li    t0, WP + 1                ; bytes 1..7: the word as it was at byte 0
        li    t1, 7                     ; ...
        addi  t2, s1, 1                 ; ...
        tget  tg1, t2, c3, t0, t1       ; ...
        twait tg1                       ; ...
        ld    a0, 0(s1)                 ; ...
        li    a1, 1 << 5 | 1 << 7 | 1 << 8 ; ...
        call  chk                       ; ...
        li    a0, WP                    ; the next read sees page 63
        call  pmrd                      ; ...
        li    a1, 1 << 63 | 1 << 5 | 1 << 7 | 1 << 8 ; ...
        call  chk                       ; ...

; ---- a clear takes effect at byte 7 ---------------------------------------------------------------------
        li    t0, 1 << 63 | 1 << 7 | 1 << 5 ; the mask: pages 63, 7 and 5
        sd    t0, 0(s1)                 ; ...
        li    t0, WP                    ; bytes 0..3 only: nothing yet
        li    t1, 4                     ; ...
        tput  tg1, s1, c3, t0, t1       ; ...
        twait tg1                       ; ...
        li    a0, WP                    ; ...
        call  pmrd                      ; (pmrd uses buf: the mask goes again below)
        li    a1, 1 << 63 | 1 << 5 | 1 << 7 | 1 << 8 ; ...
        call  chk                       ; ...
        li    t0, 1 << 63               ; bytes 4..7 of the mask (byte 7: bit 63)
        sd    t0, 0(s1)                 ; ...
        li    t0, WP + 4                ; ...
        li    t1, 4                     ; ...
        addi  t2, s1, 4                 ; ...
        tput  tg1, t2, c3, t0, t1       ; ...
        twait tg1                       ; ...
        li    a0, WP                    ; 63, 7, 5 cleared (bytes 0..3 from the first write)
        call  pmrd                      ; ...
        li    a1, 1 << 8                ; ...
        call  chk                       ; ...

; ---- a far atomic sets its page; T2 sets nothing ------------------------------------------------------
        li    t0, 9 * PAGE              ; c6 = from page 9 on (c5 = below)
        csplit c6, c5, t0               ; ...
        catomic c7, c6                  ; ...
        li    t3, 1                     ; ...
        tamo.add a0, c7, zero, t3       ; page 9
        li    a0, WP                    ; bits 8, 9
        call  pmrd                      ; ...
        li    a1, 1 << 8 | 1 << 9       ; ...
        call  chk                       ; ...
        li    a0, PM                    ; T3 granule 0's word, before and after a T2 write
        call  pmrd                      ; ...
        mv    s3, a0                    ; ...
        li    t1, 8                     ; ...
        tput  tg1, s2, c1, zero, t1     ; T2 offset 0
        twait tg1                       ; ...
        li    a0, PM                    ; ...
        call  pmrd                      ; ...
        xor   a0, a0, s3                ; unchanged
        li    a1, 0                     ; ...
        call  chk                       ; ...

; ---- past the map ----------------------------------------------------------------------------------------
        li    a0, PM + 8 * 256          ; reads zero
        call  pmrd                      ; ...
        li    a1, 0                     ; ...
        call  chk                       ; ...
        j     done                      ; print the signature and the verdict

; pmrd(a0 = port) -> a0 = the 8-byte register there
pmrd:
        li    t1, 8                     ; ...
        tget  tg1, s1, c3, a0, t1       ; ...
        twait tg1                       ; ...
        ld    a0, 0(s1)                 ; ...
        ret                             ; ...

; pmwr(a0 = port, a1 = value): an 8-byte write
pmwr:
        sd    a1, 8(s1)                 ; ...
        addi  t0, s1, 8                 ; ...
        li    t1, 8                     ; ...
        tput  tg1, t0, c3, a0, t1       ; ...
        twait tg1                       ; ...
        ret                             ; ...
