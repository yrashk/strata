#!/usr/bin/env python3
"""Generates conformance/tests/ls.s: loads and stores of every width, sign
and zero extension, little-endian byte order, offsets, and the D-LS bounds
and alignment faults (expected values computed here from the ISA rules).

   python3 conformance/gen/gen_ls.py > conformance/tests/ls.s
"""
M = (1 << 64) - 1
DLS = 0x10000
LOADS = [('ld', 8, False), ('lw', 4, True), ('lwu', 4, False), ('lh', 2, True), ('lhu', 2, False),
         ('lb', 1, True), ('lbu', 1, False)]
STORES = [('sd', 8), ('sw', 4), ('sh', 2), ('sb', 1)]
PAT = bytes([0x87, 0x06, 0xf5, 0x74, 0x83, 0x02, 0xf1, 0x80, 0x7f, 0xfe, 0x0d, 0x8c, 0x0b, 0xfa, 0x09, 0x98])

lines = []


def out(code, comment):
    lines.append('        %-32s; %s' % (code, comment))


def check(exp, what):
    out('li    a1, 0x%x' % (exp & M), 'a1 = expected: ' + what)
    out('call  chk', 'record a0, compare with a1')


def chkt(cause, epc_label, tval):
    out('li    a0, %s' % cause, 'expected cause')
    out('la    a1, %s' % epc_label, 'expected epc: the faulting instruction')
    out('li    a2, 0x%x' % (tval & M), 'expected tval: the effective address')
    out('call  chkt', 'check the recorded trap')


def le(b):
    return int.from_bytes(b, 'little')


def main():
    print('''; =============================================================================
; ls.s: loads and stores (generated by conformance/gen/gen_ls.py; do not
; edit by hand)
; =============================================================================
;
; What it checks
;   * loads of every width at every aligned offset of a 16-byte pattern:
;     ld (64), lw / lwu (32, sign / zero extended), lh / lhu (16), lb / lbu
;     (8); the D-LS is little endian;
;   * stores of every width (sd sw sh sb) write exactly their bytes;
;   * the effective address is rs1 + sign-extended imm16 (negative offsets);
;   * D-LS faults (cause 2, lsfault, tval = the effective address): an
;     access must lie wholly inside the 64 KiB D-LS and be naturally aligned
;     to its width; a faulting load leaves rd unchanged, a faulting store
;     leaves memory unchanged;
;   * a load into x0 is discarded.

        .include "lib/conf.s"           ; harness: _start, sig/chk/chkt/done, trap recorder

        .data                           ; data Local Store
        .align 8                        ; the pattern must be 8-byte aligned
pat:    .dword %s ; the 16-byte test pattern: bytes %s
wbuf:   .dword 0, 0                     ; scratch for the store tests

        .text                           ; instruction Local Store
main:
        csrr  t0, coreid                ; which core?
        bnez  t0, park                  ; only core 0 runs the test
        la    s0, pat                   ; s0 = the pattern's address
''' % (', '.join('0x%016x' % le(PAT[i:i + 8]) for i in (0, 8)), ' '.join('%02x' % b for b in PAT)))
    lines.append('; ---- every load width at every aligned offset of the pattern')
    for name, sz, sgn in LOADS:
        for off in range(0, 16, sz):
            v = le(PAT[off:off + sz])
            if sgn and v >> (8 * sz - 1): v -= 1 << (8 * sz)
            out('%-5s a0, %d(s0)' % (name, off), '%s at pattern + %d' % (name, off))
            check(v, '0x%x' % (v & M))
    lines.append('; ---- negative offsets: the immediate is sign-extended')
    out('addi  s1, s0, 16', 's1 = pattern + 16')
    out('ld    a0, -8(s1)', 'a0 = the dword at pattern + 8')
    check(le(PAT[8:16]), 'the second dword')
    out('lbu   a0, -16(s1)', 'a0 = the byte at pattern + 0')
    check(PAT[0], 'the first byte')
    lines.append('; ---- a load into x0 is discarded')
    out('ld    zero, 0(s0)', 'load into x0')
    out('mv    a0, zero', 'a0 = x0')
    check(0, 'x0 stays zero')
    lines.append('; ---- stores write exactly their width')
    for name, sz in STORES:
        for off in range(0, 8, sz):
            val = 0x1122334455667788
            out('la    s1, wbuf', 's1 = scratch dword')
            out('li    t0, -1', 't0 = all ones')
            out('sd    t0, 0(s1)', 'fill the scratch dword with 0xff')
            out('li    t1, 0x%x' % val, 't1 = value to store (only its low bytes are written)')
            out('%-5s t1, %d(s1)' % (name, off), 'store %d byte(s) at offset %d' % (sz, off))
            out('ld    a0, 0(s1)', 'a0 = the whole dword')
            mem = bytearray(b'\xff' * 8)
            mem[off:off + sz] = val.to_bytes(8, 'little')[:sz]
            check(le(mem), '0x%x' % le(mem))
    lines.append('; ---- the top of the D-LS: the last access of each width works')
    k = 0
    for name, sz, sgn in LOADS:
        out('li    t0, 0x%x' % (DLS - sz), 't0 = the last %d-byte slot of the D-LS' % sz)
        out('li    t1, -1', 't1 = all ones')
        out('li    t2, 0x%x' % (DLS - 8), 't2 = the last dword of the D-LS')
        out('sd    t1, 0(t2)', 'make the top 8 bytes all ones')
        out('%-5s a0, 0(t0)' % name, 'load the last %d byte(s)' % sz)
        v = (1 << (8 * sz)) - 1
        if sgn: v = M
        check(v, '0x%x' % v)
    lines.append('; ---- D-LS faults: out of range and misaligned (cause 2, tval = address)')
    cases = []
    for name, sz, sgn in LOADS:
        cases.append((name, sz, DLS, 'one past the end'))
        cases.append((name, sz, DLS - sz + (sz // 2 if sz > 1 else sz), 'straddles the end' if sz > 1 else 'past the end'))
        if sz > 1:
            for mis in sorted({1, sz // 2, sz - 1}):
                cases.append((name, sz, 0x2000 + mis, 'misaligned by %d' % mis))
        cases.append((name, sz, (-sz) & M, 'a negative address (wraps)'))
    for name, sz in STORES:
        cases.append((name, sz, DLS, 'one past the end'))
        if sz > 1:
            cases.append((name, sz, 0x2000 + 1, 'misaligned'))
        cases.append((name, sz, 0xffffffff0000, 'far above the D-LS'))
    for name, sz, addr, why in cases:
        k += 1
        lab = 'lsf%d' % k
        st = name.startswith('s')
        base = addr - 8 if addr > 8 and addr < (1 << 63) else addr + 8
        imm = addr - base
        out('li    t0, 0x%x' % (base & M), 't0 = base (the offset %d brings it to 0x%x)' % (imm, addr & M))
        out('li    s3, 0x5a5a', 's3 = a marker: a faulting load must leave it alone')
        if st:
            out('li    t1, 0x2000', 't1 = a probe address in range')
            out('sd    zero, 0(t1)', 'clear it')
        lines.append('%s:' % lab)
        out('%-5s s3, %d(t0)' % (name, imm), '%s %s: lsfault' % (name, why))
        chkt('C_LSFAULT', lab, addr)
        if st:
            out('li    t1, 0x2000', 't1 = the probe address')
            out('ld    a0, 0(t1)', 'a0 = what is there')
            check(0, 'the faulting store wrote nothing')
        else:
            out('mv    a0, s3', 'a0 = the load\'s destination register')
            check(0x5a5a, 'rd unchanged by the faulting load')
    out('j     done', 'print the signature and the verdict')
    print('\n'.join(lines))


main()
