#!/usr/bin/env python3
"""Generates conformance/tests/branch.s: every branch condition on signed /
unsigned edge pairs, backward branches, jal / jalr linking and target
rules, and instruction-fetch faults.

   python3 conformance/gen/gen_br.py > conformance/tests/branch.s
"""
M = (1 << 64) - 1
MIN = 1 << 63


def s64(v):
    return v - (1 << 64) if v & MIN else v


COND = {
    'beq': lambda a, b: a == b, 'bne': lambda a, b: a != b,
    'blt': lambda a, b: s64(a) < s64(b), 'bge': lambda a, b: s64(a) >= s64(b),
    'bltu': lambda a, b: a < b, 'bgeu': lambda a, b: a >= b,
}
VALS = [0, 1, M, MIN, MIN - 1, 0x80000000, (-2) & M]

lines = []


def out(code, comment):
    lines.append('        %-32s; %s' % (code, comment))


def main():
    print('''; =============================================================================
; branch.s: branches and jumps (generated by conformance/gen/gen_br.py; do not
; edit by hand)
; =============================================================================
;
; What it checks
;   * beq bne blt bge bltu bgeu on pairs of edge values: equal values,
;     0 / -1 / INT_MIN / INT_MAX, where signed and unsigned order disagree;
;     the branch compares rd-field and rs1-field registers, and its 16-bit
;     word offset is relative to the branch itself;
;   * a backward branch closes a loop;
;   * jal links pc + 4 into rd and jumps by a signed 21-bit word offset;
;     jal x0 is a plain jump;
;   * jalr jumps to (rs1 + sext(imm16)) with bits 0..1 cleared, links pc + 4,
;     and reads rs1 before writing rd (jalr ra, ra works);
;   * a fetch outside the 64 KiB I-LS is an ifault (cause 7) with epc = tval =
;     the bad pc; so is a misaligned pc, which only eret can produce.

        .include "lib/conf.s"           ; harness: _start, sig/chk/chkt/done, trap recorder

        .text                           ; instruction Local Store
main:
        csrr  t0, coreid                ; which core?
        bnez  t0, park                  ; only core 0 runs the test
''', end='')
    k = 0
    for name, f in COND.items():
        lines.append('; ---- %s: taken when %s' % (name, {
            'beq': 'equal', 'bne': 'not equal', 'blt': 'less, signed', 'bge': 'greater or equal, signed',
            'bltu': 'less, unsigned', 'bgeu': 'greater or equal, unsigned'}[name]))
        for a in VALS:
            for b in VALS:
                k += 1
                t = int(f(a, b))
                out('li    a2, 0x%x' % a, 'a2 = first operand')
                out('li    a3, 0x%x' % b, 'a3 = second operand')
                out('li    a0, 1', 'a0 = 1: "taken" unless the next-but-one instruction runs')
                out('%-5s a2, a3, br%d' % (name, k), 'branch if %s(0x%x, 0x%x)' % (name, a, b))
                out('li    a0, 0', 'not taken: a0 = 0')
                lines.append('br%d:' % k)
                out('li    a1, %d' % t, 'expected: %s' % ('taken' if t else 'not taken'))
                out('call  chk', 'record and compare')
    print('\n'.join(lines))
    print(TAIL)


TAIL = r'''
; ---- a backward branch: count down a loop of 10
        li    a0, 0                     ; a0 = iterations counted
        li    t0, 10                    ; t0 = trip count
bk_loop:
        addi  a0, a0, 1                 ; one more iteration
        addi  t0, t0, -1                ; one fewer to go
        bnez  t0, bk_loop               ; backward branch while t0 != 0
        li    a1, 10                    ; expected: 10 iterations
        call  chk                       ; record and compare

; ---- jal links pc + 4 and jumps; jal x0 is a plain jump
jl_site:
        jal   s1, jl_target             ; s1 = address of the next instruction
jl_after:
        j     jl_skip                   ; (never reached: jl_target jumps past this)
jl_target:
        mv    a0, s1                    ; a0 = the link value
        la    a1, jl_after              ; expected: jl_site + 4
        call  chk                       ; record and compare
        li    a0, 0                     ; a0 = 0
        jal   zero, jl_fwd              ; jump, no link
        li    a0, 99                    ; (skipped)
jl_fwd:
        li    a1, 0                     ; expected: the skipped instruction did not run
        call  chk                       ; record and compare
jl_skip:

; ---- jalr: target = (rs1 + sext(imm)) & ~3, link = pc + 4
        la    t0, jr_t1                 ; t0 = a target
        addi  t0, t0, 8                 ; t0 = target + 8
jr_site1:
        jalr  s1, t0, -8                ; negative offset brings it back to jr_t1
        j     jr_bad1                   ; (skipped)
jr_t1:
        mv    a0, s1                    ; a0 = the link
        la    a1, jr_site1+4            ; expected: the jalr's address + 4
        call  chk                       ; record and compare
        j     jr_ok1                    ; on to the next case
jr_bad1:
        li    a0, 0xbad                 ; marks the wrong path
        li    a1, 0                     ; never expected
        call  chk                       ; record the failure
jr_ok1:
        la    t0, jr_t2                 ; t0 = a target
        addi  t0, t0, 3                 ; low bits set: they are ignored
        li    a0, 0                     ; a0 = 0 unless we land in the right place
        jalr  zero, t0, 0               ; jump to (t0 & ~3) = jr_t2
        li    a0, 99                    ; (skipped)
jr_t2:
        li    a1, 0                     ; expected: landed exactly on jr_t2
        call  chk                       ; record and compare
        la    t0, jr_t3                 ; t0 = target
        addi  t0, t0, -2                ; target - 2
        jalr  zero, t0, 1               ; (target - 2 + 1) & ~3 = target - 4: the li below runs
        li    a0, 0x77                  ; runs: this is the instruction at target - 4
jr_t3:
        li    a1, 0x77                  ; expected: entered one instruction early
        call  chk                       ; record and compare
        la    ra, jr_t4                 ; ra = target
jr_site4:
        jalr  ra, ra, 0                 ; rs1 = rd: the old ra is the target, the new ra the link
jr_t4:
        mv    a0, ra                    ; a0 = link
        la    a1, jr_site4+4            ; expected: jalr + 4
        call  chk                       ; record and compare

; ---- instruction fetch faults (cause 7, epc = tval = the bad pc)
        la    t0, if_back1              ; t0 = where to continue after the trap
        sd    t0, tresume(zero)         ; the handler resumes there (epc + 4 is no good)
        li    t1, 0x10000               ; t1 = the first address past the I-LS
        jalr  zero, t1, 0               ; jump there: the fetch faults
if_back1:
        li    a0, C_IFAULT              ; expected cause
        li    a1, 0x10000               ; expected epc: the bad pc
        li    a2, 0x10000               ; expected tval: the bad pc
        call  chkt                      ; check
        la    t0, if_back2              ; resume point
        sd    t0, tresume(zero)         ; one-shot resume
        li    t1, -4                    ; t1 = 0xffff...fffc: far outside
        jalr  zero, t1, 0               ; jump there
if_back2:
        li    a0, C_IFAULT              ; expected cause
        li    a1, -4                    ; expected epc
        li    a2, -4                    ; expected tval
        call  chkt                      ; check
        la    t0, if_back3              ; resume point
        sd    t0, tresume(zero)         ; one-shot resume
        la    t1, if_back3              ; t1 = some instruction
        addi  t1, t1, 2                 ; t1 = misaligned by 2
        csrw  epc, t1                   ; eret goes exactly to epc: no masking
        li    t2, 2                     ; status bit 1: eret stays in supervisor mode
        csrw  status, t2                ; set it
        eret                            ; jump to the misaligned address
if_back3:
        li    a0, C_IFAULT              ; expected cause
        la    a1, if_back3+2            ; expected epc: the misaligned pc
        la    a2, if_back3+2            ; expected tval: the same
        call  chkt                      ; check
        j     done                      ; print the signature and the verdict
'''

main()
