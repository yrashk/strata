#!/usr/bin/env python3
"""Generates conformance/tests/alu.s: every integer ALU operation on edge
values, with the expected results computed here from the ISA's rules (an
implementation independent of emu/emu.c and the RTL).

   python3 conformance/gen/gen_alu.py > conformance/tests/alu.s
"""
M = (1 << 64) - 1
MIN = 1 << 63


def s64(v):
    v &= M
    return v - (1 << 64) if v & MIN else v


def sext(v, bits):
    v &= (1 << bits) - 1
    return v - (1 << bits) if v >> (bits - 1) else v


def tdiv(a, b):  # C-style truncating division of signed values
    q = abs(a) // abs(b)
    return q if (a < 0) == (b < 0) else -q


def alu(fn, a, b):
    a &= M
    b &= M
    sa, sb = s64(a), s64(b)
    if fn == 'add': return (a + b) & M
    if fn == 'sub': return (a - b) & M
    if fn == 'and': return a & b
    if fn == 'or': return a | b
    if fn == 'xor': return a ^ b
    if fn == 'sll': return (a << (b & 63)) & M
    if fn == 'srl': return a >> (b & 63)
    if fn == 'sra': return (sa >> (b & 63)) & M
    if fn == 'slt': return int(sa < sb)
    if fn == 'sltu': return int(a < b)
    if fn == 'mul': return (a * b) & M
    if fn == 'mulhu': return (a * b) >> 64
    if fn == 'divu': return M if b == 0 else a // b
    if fn == 'remu': return a if b == 0 else a % b
    if fn == 'div':
        if b == 0: return M
        if a == MIN and b == M: return MIN
        return tdiv(sa, sb) & M
    if fn == 'rem':
        if b == 0: return a
        if a == MIN and b == M: return 0
        return (sa - tdiv(sa, sb) * sb) & M
    raise ValueError(fn)


DESC = {
    'add': 'add: a + b, wrapping mod 2^64', 'sub': 'sub: a - b, wrapping', 'and': 'and: bitwise',
    'or': 'or: bitwise', 'xor': 'xor: bitwise',
    'sll': 'sll: shift left by b mod 64 (only the low 6 bits of b count)',
    'srl': 'srl: logical shift right by b mod 64', 'sra': 'sra: arithmetic shift right by b mod 64',
    'slt': 'slt: 1 if a < b as signed', 'sltu': 'sltu: 1 if a < b as unsigned',
    'mul': 'mul: low 64 bits of the product', 'mulhu': 'mulhu: high 64 bits of the unsigned 128-bit product',
    'divu': 'divu: unsigned quotient; x / 0 = all ones', 'remu': 'remu: unsigned remainder; x % 0 = x',
    'div': 'div: signed quotient rounded toward zero; x / 0 = -1; INT_MIN / -1 = INT_MIN',
    'rem': 'rem: signed remainder (sign of the dividend); x % 0 = x; INT_MIN % -1 = 0',
}

EDGE = [0, 1, 2, 7, 63, 64, 0x7fff, 0x8000, 0xffff, 0x7fffffff, 0x80000000, 0xffffffff,
        0x100000000, 0x7fffffffffffffff, MIN, M, M - 1, 0x0123456789abcdef, 0xfedcba9876543210,
        (-7) & M, (-3) & M]

lines = []


def out(code, comment):
    lines.append('        %-32s; %s' % (code, comment))


def li(reg, v, what):
    out('li    %s, 0x%x' % (reg, v & M), what)


def check(exp, what):
    li('a1', exp, 'a1 = expected: ' + what)
    out('call  chk', 'record a0, compare with a1')


def pairs(fn):
    """operand pairs for one function: edge cases first, then a sweep"""
    ps = []
    if fn in ('sll', 'srl', 'sra'):
        for a in (1, MIN, M, 0x0123456789abcdef, 0x8000000000000001):
            for b in (0, 1, 31, 32, 63, 64, 65, 127, M, 0x100000000 + 5):
                ps.append((a, b))
        return ps
    if fn in ('div', 'rem', 'divu', 'remu'):
        for a in (0, 1, 7, (-7) & M, MIN, 0x7fffffffffffffff, M, 0xfedcba9876543210):
            for b in (0, 1, M, 2, (-2) & M, 3, (-3) & M, MIN, 0x7fffffffffffffff):
                ps.append((a, b))
        return ps
    if fn in ('slt', 'sltu'):
        vals = [0, 1, M, MIN, 0x7fffffffffffffff, 0x80000000, (-2) & M]
        return [(a, b) for a in vals for b in vals]
    if fn in ('mul', 'mulhu'):
        vals = [0, 1, M, MIN, 0x7fffffffffffffff, 0xffffffff, 0x100000000, 0x0123456789abcdef, 3]
        return [(a, b) for a in vals for b in vals if a <= b or fn == 'mul' and a == M]
    vals = [0, 1, M, MIN, 0x7fffffffffffffff, 0x0123456789abcdef, 0xffffffff]
    return [(a, b) for a in vals for b in vals]


def main():
    hdr = '''; =============================================================================
; alu.s: every integer ALU operation on edge values (generated by
; conformance/gen/gen_alu.py; do not edit by hand)
; =============================================================================
;
; What it checks
;   * the sixteen register-register functions (opcode 0x00, funct 0..15):
;     add sub and or xor sll srl sra slt sltu mul mulhu divu remu div rem,
;     with shift amounts 0, 63 and wider than 63 (only the low 6 bits of the
;     amount count), division by zero (quotient all ones, remainder the
;     dividend) and INT_MIN / -1 (quotient INT_MIN, remainder 0): none of
;     these trap;
;   * immediates: addi / slti / sltiu sign-extend their 16-bit immediate
;     (sltiu compares against the sign-extended value as unsigned), andi /
;     ori / xori zero-extend it, slli / srli / srai take a 6-bit amount, lui
;     places the sign-extended 16 bits at bits 16..31 (and sign-extends);
;   * x0 reads as zero and ignores writes; rd may equal rs1 / rs2;
;   * an ALU instruction with funct bits 4..10 set is illegal (cause 1).
;
; Every check is "compute, then compare with the value this generator
; computed from the rules above".

        .include "lib/conf.s"           ; harness: _start, sig/chk/chkt/done, trap recorder

        .text                           ; instruction Local Store
main:
        csrr  t0, coreid                ; which core?
        bnez  t0, park                  ; only core 0 runs the test
'''
    print(hdr, end='')
    for fn in ['add', 'sub', 'and', 'or', 'xor', 'sll', 'srl', 'sra', 'slt', 'sltu', 'mul', 'mulhu',
               'divu', 'remu', 'div', 'rem']:
        lines.append('; ---- %s' % DESC[fn])
        for a, b in pairs(fn):
            r = alu(fn, a, b)
            li('a0', a, 'a0 = first operand')
            li('a2', b, 'a2 = second operand')
            out('%-5s a0, a0, a2' % fn, 'a0 = %s(0x%x, 0x%x)' % (fn, a, b))
            check(r, '0x%x' % r)
    # register aliasing and x0
    lines.append('; ---- register aliasing and x0')
    li('a0', 0x1234, 'a0 = 0x1234')
    out('add   a0, a0, a0', 'rs1 = rs2 = rd: a0 = a0 + a0')
    check(0x2468, '0x2468')
    li('a2', 5, 'a2 = 5')
    out('sub   a0, zero, a2', 'x0 reads as zero: a0 = 0 - 5')
    check((-5) & M, '-5')
    out('add   zero, a2, a2', 'a write to x0 is discarded')
    out('mv    a0, zero', 'a0 = x0')
    check(0, 'x0 is still zero')
    out('addi  zero, zero, 77', 'immediate write to x0, discarded too')
    out('or    a0, zero, zero', 'a0 = x0 | x0')
    check(0, 'still zero')
    # immediates
    lines.append('; ---- immediates: addi/slti/sltiu sign-extend, andi/ori/xori zero-extend')
    imms = [0, 1, 0x7fff, 0x8000, 0xffff, 0x1234, 0xfffe]
    srcs = [0, 1, M, MIN, 0x7fffffffffffffff, 0xffff, 0xffffffffffff0000, 0x8000]
    for op in ['addi', 'slti', 'sltiu', 'andi', 'ori', 'xori']:
        for a in srcs:
            for im in imms:
                if op in ('addi', 'slti', 'sltiu'):
                    se = sext(im, 16)
                    imtxt = str(se)
                    if op == 'addi': r = (a + se) & M
                    elif op == 'slti': r = int(s64(a) < se)
                    else: r = int(a < (se & M))
                else:
                    imtxt = '0x%x' % im
                    r = {'andi': a & im, 'ori': a | im, 'xori': a ^ im}[op]
                li('a0', a, 'a0 = source')
                out('%-5s a0, a0, %s' % (op, imtxt), '%s with immediate 0x%04x' % (op, im))
                check(r, '0x%x' % r)
    lines.append('; ---- immediate shifts: amounts 0..63')
    for op in ['slli', 'srli', 'srai']:
        for a in (1, MIN | 1, M, 0x0123456789abcdef):
            for sh in (0, 1, 31, 32, 63):
                fn = {'slli': 'sll', 'srli': 'srl', 'srai': 'sra'}[op]
                r = alu(fn, a, sh)
                li('a0', a, 'a0 = source')
                out('%-5s a0, a0, %d' % (op, sh), 'shift by %d' % sh)
                check(r, '0x%x' % r)
    lines.append('; ---- lui: imm16 << 16, sign-extended from bit 31')
    for im in (0, 1, 0x7fff, 0x8000, 0xffff, 0x1234):
        r = (sext(im, 16) << 16) & M
        out('lui   a0, 0x%x' % im, 'a0 = sext(0x%x) << 16' % im)
        check(r, '0x%x' % r)
    lines.append('; ---- encodings with nonzero funct bits 4..10 are illegal')
    for k, w in enumerate([0x00000010 | (10 << 21), 0x00000400 | (10 << 21) | 2]):
        lines.append('alu_ill%d:' % k)
        out('.word 0x%08x' % w, 'ALU opcode, rd = a0, funct = 0x%x: illegal' % (w & 0x7ff))
        out('li    a0, C_ILLEGAL', 'expected cause')
        out('la    a1, alu_ill%d' % k, 'expected epc: the instruction itself')
        out('li    a2, 0x%x' % w, 'expected tval: the instruction word')
        out('call  chkt', 'check the recorded trap')
    out('j     done', 'print the signature and the verdict')
    print('\n'.join(lines))


main()
