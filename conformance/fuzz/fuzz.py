#!/usr/bin/env python3
"""Differential fuzzer for the three Strata implementations: the emulator
interpreting (-j), the emulator with the JIT (-J) and the Verilated RTL.

Each seed generates one random, valid bare-metal program (Strata assembly,
so a failing case reads like any other program):
  * every ALU function and immediate form on random and edge values;
  * loads and stores of every width, mostly inside a 4 KiB D-LS window,
    sometimes through a random base (so out of range or misaligned);
  * transfers between that window and system memory (tget / tput with random
    tags, lengths and overlaps, immediately followed by loads and stores of
    the same bytes: the RTL's hazard logic must make them as if synchronous)
    and far atomics (tamo, every op);
  * forward branches, calls to small subroutines through jal / jalr, and
    the whole body in a counted loop;
  * a trap handler that folds cause, epc and tval into a register and skips
    the trapping instruction.
At the end the program stores x1..x31, a hash of the D-LS window and of
4 KiB of system memory, and the trap count, and prints those 272 bytes raw.
The three machines must print the same bytes and halt core 0 with the same
a0.

   conformance/fuzz/fuzz.py [-n SEEDS] [-s FIRST] [--keep] [--machines interp,jit,rtl]

A failing seed leaves its program in build/conformance/fuzz/seed-N.s
(reproduce with `-n 1 -s N`).
"""
import argparse
import os
import random
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
M64 = (1 << 64) - 1
SPECIAL = [0, 1, 2, 7, 8, 63, 64, 0xffff, 0x8000, 0x10000, 0x7fffffff, 0x80000000, 0xffffffff,
           0x7fffffffffffffff, 0x8000000000000000, M64, M64 - 1]
ALU = ['add', 'sub', 'and', 'or', 'xor', 'sll', 'srl', 'sra', 'slt', 'sltu', 'mul', 'mulhu',
       'divu', 'remu', 'div', 'rem']
IMM_S = ['addi', 'slti', 'sltiu']
IMM_U = ['andi', 'ori', 'xori']
SHIFT = ['slli', 'srli', 'srai']
LOADS = {'ld': 8, 'lw': 4, 'lwu': 4, 'lh': 2, 'lhu': 2, 'lb': 1, 'lbu': 1}
STORES = {'sd': 8, 'sw': 4, 'sh': 2, 'sb': 1}
BRANCH = ['beq', 'bne', 'blt', 'bge', 'bltu', 'bgeu']
AMO = ['tamo.add', 'tamo.swap', 'tamo.cas', 'tamo.and', 'tamo.or']
# registers: x1..x23 random; x24..x26 transfer temporaries; x27 link,
# x28 loop counter, x29 trap accumulator, x30 handler scratch, x31 window base
R = list(range(1, 24))
T1, T2, T3, LINK, CNT, ACC, HS, BASE = 24, 25, 26, 27, 28, 29, 30, 31
WIN = 0x4000      # the D-LS window: [WIN, WIN + 4096)
WLEN = 0x1000
FARW = 0x10000    # far window in c0 for transfers: [0, FARW)


def x(r):
    return 'x%d' % r


def gen(seed):
    rng = random.Random(seed)
    out = []

    def emit(code, comment=''):
        out.append('        %-36s; %s' % (code, comment) if comment else '        ' + code)

    def label(name):
        out.append('%s:' % name)

    init = [rng.choice(SPECIAL) if rng.random() < 0.4 else rng.getrandbits(64) for _ in range(23)]
    out.append('; fuzz seed %d (generated by conformance/fuzz/fuzz.py)' % seed)
    out.append('        .data')
    out.append('init:   .dword 0')
    for v in init:
        out.append('        .dword 0x%x' % v)
    out.append('        .text')
    label('_start')
    emit('csrr  x30, coreid', 'only core 0 runs')
    emit('bnez  x30, park', '')
    emit('la    x30, handler', 'trap handler')
    emit('csrw  tvec, x30', '')
    for r in R:
        emit('ld    %s, %d(zero)' % (x(r), 8 * r), 'initial register values')
    emit('li    x31, 0x%x' % WIN, 'D-LS window base')
    emit('li    x29, 0', 'trap accumulator')
    # capabilities: c0 = [0, 1 MiB) of T3 (R W X), c6 = atomic view of [1 MiB, 1 MiB + 4 KiB)
    emit('li    x24, 0x100000', '')
    emit('csplit c5, c0, x24', 'c0 = [0, 1M)')
    emit('li    x24, 0x1000', '')
    emit('csplit c7, c5, x24', 'c5 = [1M, 1M + 4K)')
    emit('catomic c6, c5', 'c6 = atomic view')
    iters = rng.choice([1, 2, 5, 20, 100])
    emit('li    x28, %d' % iters, 'loop count')
    label('loop')
    body = rng.randint(10, 250)
    nsub = 3
    for k in range(body):
        left = body - k - 1
        p = rng.random()
        rd = rng.choice(R + [0])
        rs1, rs2 = rng.choice(R + [0]), rng.choice(R + [0])
        if p < 0.28:
            emit('%-5s %s, %s, %s' % (rng.choice(ALU), x(rd), x(rs1), x(rs2)))
        elif p < 0.42:
            k2 = rng.random()
            if k2 < 0.4:
                emit('%-5s %s, %s, %d' % (rng.choice(IMM_S), x(rd), x(rs1),
                                          rng.choice([0, 1, -1, 0x7fff, -0x8000, rng.randrange(-0x8000, 0x8000)])))
            elif k2 < 0.7:
                emit('%-5s %s, %s, 0x%x' % (rng.choice(IMM_U), x(rd), x(rs1),
                                            rng.choice([0, 1, 0xffff, 0x8000, rng.randrange(0x10000)])))
            elif k2 < 0.9:
                emit('%-5s %s, %s, %d' % (rng.choice(SHIFT), x(rd), x(rs1), rng.choice([0, 1, 31, 32, 63, rng.randrange(64)])))
            else:
                emit('lui   %s, 0x%x' % (x(rd), rng.randrange(0x10000)))
        elif p < 0.62:
            store = rng.random() < 0.45
            op = rng.choice(list(STORES if store else LOADS))
            sz = (STORES if store else LOADS)[op]
            if rng.random() < 0.93:
                base = BASE
                off = rng.randrange(-16, WLEN + 16)
                if rng.random() < 0.9:
                    off &= ~(sz - 1)
            else:
                base = rng.choice(R)
                off = rng.randrange(-0x40, 0x40)
            emit('%-5s %s, %d(%s)' % (op, x(rng.choice(R + [0]) if store else rd), off, x(base)))
        elif p < 0.72:
            # a transfer between the window and system memory, then touch its bytes
            sub = rng.choice(['tget', 'tput'])
            ln = 8 * rng.randint(1, 16)
            ls = WIN + 8 * rng.randrange(0, (WLEN - ln) // 8 + 1)
            far = 8 * rng.randrange(0, (FARW - ln) // 8)
            if rng.random() < 0.05:
                far += rng.choice([4, FARW * 32])   # misaligned or out of bounds: a trap
            tag = rng.randrange(15)
            emit('li    %s, 0x%x' % (x(T1), ls), 'LS address')
            emit('li    %s, 0x%x' % (x(T2), far), 'far offset')
            emit('li    %s, %d' % (x(T3), ln), 'length')
            emit('%s  tg%d, %s, c0, %s, %s' % (sub, tag, x(T1), x(T2), x(T3)))
            # an access to the same bytes right away (a hazard on a real machine)
            o = 8 * rng.randrange(ln // 8)
            if rng.random() < 0.5:
                emit('ld    %s, %d(%s)' % (x(rd), o, x(T1)), 'hazard: load')
            else:
                emit('sd    %s, %d(%s)' % (x(rs1), o, x(T1)), 'hazard: store')
            if rng.random() < 0.3:
                emit('twait tg%d' % tag)
        elif p < 0.76:
            off = 8 * rng.randrange(0, 512)
            if rng.random() < 0.05:
                off += 4
            emit('li    %s, 0x%x' % (x(T1), off), 'atomic offset')
            emit('%s %s, c6, %s, %s' % (rng.choice(AMO), x(rd), x(T1), x(rs2)))
        elif p < 0.92 and left > 1:
            skip = rng.randint(1, min(6, left))
            out.append('        %-5s %s, %s, .+%d' % (rng.choice(BRANCH), x(rs1), x(rs2), 4 * (skip + 1)))
        else:
            emit('jal   x27, sub%d' % rng.randrange(nsub), 'call a subroutine')
    emit('addi  x28, x28, -1', 'loop count')
    emit('bnez  x28, loop', '')
    emit('tfence', 'all transfers done')
    for r in range(1, 32):
        emit('sd    %s, %d(zero)' % (x(r), 0x7000 + 8 * r), 'dump registers')
    # hash the D-LS window, then 4 KiB of system memory (fetched into 0x5000)
    emit('li    x24, 0x5000')
    emit('li    x25, 0')
    emit('li    x26, 0x1000')
    emit('tget  tg0, x24, c0, x25, x26', 'T3[0, 4K) -> D-LS 0x5000')
    emit('li    x1, 0', 'hash')
    emit('li    x2, 0x%x' % WIN, 'cursor')
    emit('li    x3, 0x6000', 'end: the window and the fetched memory')
    emit('li    x4, 0x100000001b3', 'FNV prime')
    label('hash')
    emit('ld    x5, 0(x2)')
    emit('xor   x1, x1, x5')
    emit('mul   x1, x1, x4')
    emit('addi  x2, x2, 8')
    emit('bltu  x2, x3, hash')
    emit('sd    x1, 0x7100(zero)', 'the hash')
    emit('sd    x29, 0x7108(zero)', 'trap accumulator')
    emit('li    x10, 0x7008')
    emit('li    x11, 0x108', '31 registers, hash, accumulator')
    emit('tput  tg15, x10, c2, zero, x11', 'print them raw')
    emit('mv    x10, x29', 'exit code')
    label('park')
    emit('halt')
    label('handler')
    emit('csrr  x30, cause')
    emit('add   x29, x29, x30')
    emit('slli  x30, x29, 7')
    emit('xor   x29, x29, x30')
    emit('csrr  x30, epc')
    emit('add   x29, x29, x30')
    emit('csrr  x30, tval')
    emit('xor   x29, x29, x30')
    emit('csrr  x30, epc')
    emit('addi  x30, x30, 4')
    emit('csrw  epc, x30')
    emit('eret')
    for s in range(nsub):
        label('sub%d' % s)
        for _ in range(rng.randint(1, 10)):
            emit('%-5s %s, %s, %s' % (rng.choice(ALU), x(rng.choice(R)), x(rng.choice(R + [0])), x(rng.choice(R + [0]))))
        emit('jalr  zero, x27, 0')
    return '\n'.join(out) + '\n'


def run(cmd, timeout=120):
    try:
        p = subprocess.run(cmd, capture_output=True, stdin=subprocess.DEVNULL, timeout=timeout)
        return p.returncode, p.stdout, p.stderr.decode(errors='replace')
    except subprocess.TimeoutExpired:
        return -1, b'', 'host timeout'


def halt_a0(err):
    for line in err.splitlines():
        if line.startswith('core 0: '):
            return line.split(' instret')[0]
    return '(no halt line)'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('-n', type=int, default=20, help='number of seeds')
    ap.add_argument('-s', type=int, default=1, help='first seed')
    ap.add_argument('--keep', action='store_true', help='keep every program, not just failing ones')
    ap.add_argument('--machines', default='interp,jit,rtl')
    a = ap.parse_args()
    b = os.path.join(ROOT, os.environ.get('BUILD', 'build'))
    ncores = os.environ.get('NCORES', '8')
    out = os.path.join(b, 'conformance', 'fuzz')
    os.makedirs(out, exist_ok=True)
    common = ['-T', 'virtual', '-g', 'none']
    machines = {
        'interp': [os.path.join(b, 'strata-emu'), '-c', ncores, '-j', '-m', '50000000'] + common,
        'jit': [os.path.join(b, 'strata-emu'), '-c', ncores, '-J', '-m', '50000000'] + common,
        'rtl': [os.path.join(b, 'strata-rtl'), '-m', '300000000'] + common,
    }
    use = a.machines.split(',')
    bad = 0
    for seed in range(a.s, a.s + a.n):
        src = os.path.join(out, 'seed-%d.s' % seed)
        img = os.path.join(out, 'seed-%d.stx' % seed)
        with open(src, 'w') as f:
            f.write(gen(seed))
        p = subprocess.run([os.path.join(b, 'sasm'), '-o', img, src], capture_output=True)
        if p.returncode:
            print('seed %d: ASSEMBLY FAILED\n%s' % (seed, p.stderr.decode()))
            bad += 1
            continue
        res = {m: run(machines[m] + [img]) for m in use}
        ref = res[use[0]]
        ok = True
        why = []
        for m in use:
            ec, so, se = res[m]
            if ec != 0 or 'timeout' in se or 'fault' in se:
                ok = False
                why.append('%s: exit %d %s' % (m, ec, se.strip().splitlines()[-1] if se.strip() else ''))
            if so != ref[1]:
                ok = False
                why.append('%s: output differs from %s' % (m, use[0]))
            if halt_a0(se) != halt_a0(ref[2]):
                ok = False
                why.append('%s: %s vs %s' % (m, halt_a0(se), halt_a0(ref[2])))
            if len(so) != 0x108:
                ok = False
                why.append('%s: printed %d bytes' % (m, len(so)))
        if ok:
            print('seed %-6d OK   %s  acc=%s' % (seed, ref[1][0xf8:0x100][::-1].hex(), halt_a0(ref[2]).split('a0=')[-1]))
            if not a.keep:
                os.remove(src)
                os.remove(img)
        else:
            bad += 1
            print('seed %-6d FAIL (program: %s)' % (seed, src))
            for w in why:
                print('    ' + w)
            for m in use:
                if res[m][1] != ref[1] and len(res[m][1]) == len(ref[1]) == 0x108:
                    for r in range(33):
                        va, vb = ref[1][8 * r:8 * r + 8], res[m][1][8 * r:8 * r + 8]
                        if va != vb:
                            name = 'x%d' % (r + 1) if r < 31 else ('hash' if r == 31 else 'traps')
                            print('    %s %s: %s=%s %s=%s' % (m, name, use[0], va[::-1].hex(), m, vb[::-1].hex()))
    print('fuzz: %d seeds, %d failed' % (a.n, bad))
    sys.exit(1 if bad else 0)


main()
