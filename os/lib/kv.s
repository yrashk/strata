; =============================================================================
; kv.s: the store for programs: keys and values in a tree of one's own
; =============================================================================
;
; A program keeps data in the store beside the file system (doc/strataos.md,
; "The store for programs"): in a namespace, in named trees of keys and
; values (bytes, in key order; a key of 1 to 480 bytes, a value of up to
; about 1,000, with 4 KiB pages). A namespace and a tree are made by the
; first write to them. These are the file server's calls DBGET, DBSCAN and
; DBBATCH (os/servers/fsops.s) for one tree at a time:
;
;   kv_open(text, length)     the tree "NAMESPACE/TREE" is the one at work ->
;                             a0 = 0, or -1 (no "/", a name too long)
;   kv_get(key, length, buffer)        -> a0 = the value's length, the value
;                             in the buffer (KV_VAL bytes); -4 no such key
;   kv_put(key, length, value, length) -> a0 = 0: it is on the disk
;   kv_del(key, length)                -> a0 = 0 (also when it was not there)
;   kv_scan(key, length, mode, buffer) the records from the key on (mode 0)
;                             or after it (mode 1), in key order, as many as
;                             fit -> a0 = records (0: no more), a1 = their
;                             bytes, in the buffer (SYS_MAX bytes): per
;                             record {u16 key length, u16 value length, u32
;                             0, the key, the value}, key and value each
;                             padded to 8 bytes. Ask again with the last key
;                             and mode 1.
; A negative answer: -1 a bad request or a namespace that is not the
; program's to name (fs), -4 nothing there, -5 the disk failed, -6 full.
; A put or a delete is one commit. Several in one commit: build a DBBATCH
; request by hand (db.s does not either).
;
; Include after sys.s. Clobbers t0..t6, a0..a7.

KV_KEY  = 480                           ; a key's most bytes
KV_VAL  = 1024                          ; room for a value
OP_DBGET   = 64                         ; fs: a value
OP_DBSCAN  = 65                         ; fs: records in key order
OP_DBBATCH = 66                         ; fs: puts and deletes, one commit

        .data                           ; D-LS
        .align 8                        ; dwords
kv_base: .dword 0                       ; the request's bytes up to the names' end
kv_rq:   .space 8 + 64 + 8 + 8 + KV_KEY + KV_VAL ; a request: lengths, names, an item
        .align 8                        ; ...
        .text                           ; code

; kv_open(a0 = "NAMESPACE/TREE", a1 = its length) -> a0 = 0 or -1
kv_open:
        li    t0, 0                     ; t0 = where the "/" is
kvo_sl:
        bgeu  t0, a1, kvo_bad           ; ...
        add   t1, a0, t0                ; ...
        lbu   t1, 0(t1)                 ; ...
        li    t2, '/'                   ; ...
        beq   t1, t2, kvo_n             ; ...
        addi  t0, t0, 1                 ; ...
        j     kvo_sl                    ; ...
kvo_n:
        sub   t1, a1, t0                ; t1 = the tree name's length
        addi  t1, t1, -1                ; ...
        beqz  t0, kvo_bad               ; ...
        beqz  t1, kvo_bad               ; ...
        li    t2, 32                    ; ...
        bgtu  t0, t2, kvo_bad           ; ...
        li    t2, 28                    ; ...
        bgtu  t1, t2, kvo_bad           ; ...
        la    t3, kv_rq                 ; the lengths, then the names without the "/"
        sd    zero, 0(t3)               ; ...
        sb    t0, 0(t3)                 ; ...
        sb    t1, 1(t3)                 ; ...
        addi  t3, t3, 8                 ; ...
        add   t4, a0, a1                ; t4 = the text's end
        add   t5, a0, t0                ; t5 = the "/"
kvo_c:
        bgeu  a0, t4, kvo_d             ; ...
        beq   a0, t5, kvo_s             ; ...
        lbu   t6, 0(a0)                 ; ...
        sb    t6, 0(t3)                 ; ...
        addi  t3, t3, 1                 ; ...
kvo_s:
        addi  a0, a0, 1                 ; ...
        j     kvo_c                     ; ...
kvo_d:
        la    t0, kv_rq                 ; ...
        sub   t3, t3, t0                ; ...
        la    t0, kv_base               ; ...
        sd    t3, 0(t0)                 ; ...
        li    a0, 0                     ; ...
        ret                             ; ...
kvo_bad:
        li    a0, -1                    ; ...
        ret                             ; ...

; kv_key(a0 = key, a1 = length, a2 = where in the request) -> a0 = after it,
; padded to 8 bytes with zeros; the key's length is not checked here
kv_key:
        add   t0, a0, a1                ; ...
kvk_l:
        bgeu  a0, t0, kvk_p             ; ...
        lbu   t1, 0(a0)                 ; ...
        sb    t1, 0(a2)                 ; ...
        addi  a0, a0, 1                 ; ...
        addi  a2, a2, 1                 ; ...
        j     kvk_l                     ; ...
kvk_p:
        andi  t1, a2, 7                 ; ...
        beqz  t1, kvk_r                 ; ...
        sb    zero, 0(a2)               ; ...
        addi  a2, a2, 1                 ; ...
        j     kvk_p                     ; ...
kvk_r:
        mv    a0, a2                    ; ...
        ret                             ; ...

; kv_get(a0 = key, a1 = length, a2 = buffer of KV_VAL bytes) -> a0 = the
; value's length (the value in the buffer), or < 0
kv_get:
        li    a3, OP_DBGET              ; ...
        li    a4, 0                     ; ...
        li    a5, KV_VAL                ; ...
        j     kv_ask                    ; ...
; kv_scan(a0 = key, a1 = length (0: from the start), a2 = mode, a3 = buffer
; of SYS_MAX bytes) -> a0 = records, a1 = their bytes; or a0 < 0
kv_scan:
        mv    a4, a2                    ; ...
        mv    a2, a3                    ; ...
        li    a3, OP_DBSCAN             ; ...
        li    a5, SYS_MAX               ; ...
; kv_ask(a0 = key, a1 = length, a2 = buffer, a3 = op, a4 = mode, a5 = the
; buffer's bytes): the request is the names and the key; the answer's data
; (its bytes are the reply's length word) -> the buffer
kv_ask:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a2, 8(sp)                 ; buffer
        sd    a3, 16(sp)                ; op
        sd    a4, 24(sp)                ; mode
        sd    a5, 32(sp)                ; room
        li    t0, KV_KEY                ; ...
        bgtu  a1, t0, kva_bad           ; ...
        la    t0, kv_rq                 ; ...
        sh    a1, 2(t0)                 ; ...
        la    t1, kv_base               ; ...
        ld    t1, 0(t1)                 ; ...
        add   a2, t0, t1                ; ...
        add   t1, t1, a1                ; the request's bytes
        sd    t1, 40(sp)                ; ...
        call  kv_key                    ; ...
        la    a0, kv_rq                 ; ...
        ld    a1, 40(sp)                ; ...
        call  sys_put                   ; ...
        li    a0, 2                     ; fs
        ld    a1, 16(sp)                ; ...
        li    a2, 0                     ; ...
        ld    a3, 40(sp)                ; ...
        ld    a4, 24(sp)                ; ...
        call  sys_msg                   ; a0 = the value's length / records
        blez  a0, kva_ret               ; ...
        sd    a0, 16(sp)                ; ...
        la    t0, sys_hdr               ; the data's bytes
        ld    a1, 16(t0)                ; ...
        ld    t0, 32(sp)                ; (no more than the buffer)
        bleu  a1, t0, kva_g             ; ...
        mv    a1, t0                    ; ...
kva_g:
        sd    a1, 24(sp)                ; ...
        ld    a0, 8(sp)                 ; ...
        call  sys_get                   ; ...
        ld    a0, 16(sp)                ; ...
        ld    a1, 24(sp)                ; ...
        j     kva_ret                   ; ...
kva_bad:
        li    a0, -1                    ; ...
kva_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; ...

; kv_del(a0 = key, a1 = length) -> a0 = 0, or < 0
kv_del:
        li    a2, 0                     ; ...
        li    a3, 0                     ; ...
        li    a4, 2                     ; an item that deletes
        j     kv_item                   ; ...
; kv_put(a0 = key, a1 = length, a2 = value, a3 = length) -> a0 = 0, or < 0
kv_put:
        li    a4, 1                     ; an item that puts
; kv_item(a0 = key, a1 = length, a2 = value, a3 = length, a4 = 1 put / 2
; delete): a batch of that one item, from the next multiple of 8 after the
; names: {u8 what, u8 0, u16 key length, u16 value length, u16 0, key, value}
kv_item:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a2, 8(sp)                 ; value
        sd    a3, 16(sp)                ; its length
        li    t0, KV_KEY                ; ...
        bgtu  a1, t0, kvi_bad           ; ...
        li    t0, KV_VAL                ; ...
        bgtu  a3, t0, kvi_bad           ; ...
        la    t0, kv_rq                 ; ...
        sh    zero, 2(t0)               ; ...
        la    t1, kv_base               ; ...
        ld    t1, 0(t1)                 ; ...
        add   t0, t0, t1                ; t0 = the item: at the next multiple of 8
kvi_p:
        andi  t1, t0, 7                 ; (zeros up to it)
        beqz  t1, kvi_i                 ; ...
        sb    zero, 0(t0)               ; ...
        addi  t0, t0, 1                 ; ...
        j     kvi_p                     ; ...
kvi_i:
        sd    zero, 0(t0)               ; ...
        sb    a4, 0(t0)                 ; ...
        sh    a1, 2(t0)                 ; ...
        sh    a3, 4(t0)                 ; ...
        addi  a2, t0, 8                 ; ...
        call  kv_key                    ; ...
        mv    a2, a0                    ; ...
        ld    a0, 8(sp)                 ; ...
        ld    a1, 16(sp)                ; ...
        call  kv_key                    ; (a value is copied and padded as a key is)
        la    t0, kv_rq                 ; ...
        sub   a1, a0, t0                ; ...
        sd    a1, 8(sp)                 ; the request's bytes
        mv    a0, t0                    ; ...
        call  sys_put                   ; ...
        li    a0, 2                     ; fs
        li    a1, OP_DBBATCH            ; ...
        li    a2, 1                     ; one item
        ld    a3, 8(sp)                 ; ...
        li    a4, 0                     ; ...
        call  sys_msg                   ; ...
        j     kvi_ret                   ; ...
kvi_bad:
        li    a0, -1                    ; ...
kvi_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...
