; =============================================================================
; srv.s: helpers for StrataOS servers (proc, dev, fs, tty, pipe)
; =============================================================================
;
; A server is an ordinary time-shared process that the kernel marks as its
; core's server: every request (a lent 4 KiB message buffer) that arrives at
; the core goes to it. The loop is
;
;   srv_recv  -> a request in c6 (header copied to srv_hdr), its attachment
;                (if any) in c7, a0 = the reply token
;   ...serve it...
;   srv_reply -> the result into the header, the buffer back to its owner
;
; A request that cannot be answered yet is PARKED: the kernel keeps the
; buffer (svc PARK) and gives it back later (svc UNPARK) so the server can
; answer it then. The sender's pid is in header byte 40 (stamped by the
; kernel, so it can be trusted). When a server ends, the kernel answers the
; requests still queued or parked for it with -1.
;
; Reference table: servers count who holds each of their handles as (pid, id)
; pairs, so that a process's handles can be dropped when it dies (CLEANUP).
;
; Include after sys.s. Clobbers t0..t6, a0..a7.

OP_DUPS    = 36                         ; proc -> servers: data u64 owner pid, u64 count, u64 ids
OP_CLEANUP = 37                         ; proc -> servers: handle = pid: drop everything it held
OP_CANCEL  = 38                         ; proc -> servers: handle = pid: held requests return -2
SVC_PARK   = 8                          ; svc: c6 -> kernel, a0 = park id
SVC_UNPARK = 9                          ; svc: a1 = park id -> c6
NREF       = 64                         ; reference table entries

        .data                           ; server state
        .align 8                        ; ...
srv_hdr:   .space 64                    ; the request header
srv_tok:   .dword 0                     ; its reply token
srv_gsp:   .dword 0                     ; srv_guard: the loop's stack pointer
srv_gpc:   .dword 0                     ; srv_guard: the loop's address
srv_ref:   .space NREF * 16             ; references: pid, id (pid 0 = free entry)

        .text                           ; server code

; srv_guard(a0 = the server's loop address): a request's owner may die while
; the server works on it; the kernel then dissolves the owner's domain, and
; the server's next transfer through the request (c6) or its attachment (c7)
; faults. That must not kill the server: this installs a user trap handler
; that drops the request and goes back to the loop with the loop's stack.
srv_guard:
        la    t0, srv_gpc               ; where to go back to
        sd    a0, 0(t0)                 ; ...
        la    t0, srv_gsp               ; with the caller's stack
        sd    sp, 0(t0)                 ; ...
        la    t0, srv_trap              ; faults come to srv_trap from now on
        csrw  tvec, t0                  ; (in user mode: the user trap vector)
        ret                             ; done
srv_trap:
        cclear c6                       ; the request whose owner is gone
        cclear c7                       ; and its attachment
        la    t0, srv_gsp               ; the loop's stack
        ld    sp, 0(t0)                 ; ...
        la    t0, srv_gpc               ; back to the loop
        ld    t0, 0(t0)                 ; ...
        jr    t0                        ; ...

; srv_recv(a0 = tag mask, a1 = timeout) -> a0 = token (request in c6, header in
; srv_hdr), or -1 with a1 = idle tags, or -8 timed out
srv_recv:
        mv    a2, a1                    ; timeout
        mv    a1, a0                    ; tags
        li    a0, SVC_RECV              ; RECEIVE
        svc                             ; ...
        bltz  a0, srr_ret               ; not a request
        la    t0, srv_tok               ; keep the token
        sd    a0, 0(t0)                 ; ...
        la    t0, srv_hdr               ; the header -> D-LS
        li    t1, 64                    ; ...
        tget  tg10, t0, c6, zero, t1    ; ...
        twait 1 << 10                   ; ...
srr_ret:
        ret                             ; done

; srv_reply(a0 = result, a1 = REPLY flags (bit2 send c4, bit0 send c7, bit1
; mint an endpoint for core a2)): answer the request in c6 (token srv_tok)
srv_reply:
        la    t0, srv_hdr               ; the result
        sd    a0, 32(t0)                ; ...
        li    t1, 64                    ; header -> the buffer
        tput  tg10, t0, c6, zero, t1    ; ...
        twait 1 << 10                   ; (before the buffer leaves)
        mv    a3, a2                    ; core for a minted endpoint
        mv    a2, a1                    ; flags
        la    t0, srv_tok               ; the token
        ld    a1, 0(t0)                 ; ...
        li    a0, SVC_REPLY             ; REPLY
        svc                             ; ...
        ret                             ; done

; srv_put(a0 = D-LS address (8-aligned), a1 = length): reply data -> c6 at 64
srv_put:
        beqz  a1, spt_ret               ; nothing
        addi  a1, a1, 7                 ; whole words
        srli  a1, a1, 3                 ; ...
        slli  a1, a1, 3                 ; ...
        li    t1, 64                    ; ...
        tput  tg10, a0, c6, t1, a1      ; ...
spt_ret:
        ret                             ; done

; srv_get(a0 = D-LS address (8-aligned), a1 = length): request data (c6 at 64) -> a0
srv_get:
        beqz  a1, sgt_ret               ; nothing
        addi  a1, a1, 7                 ; whole words
        srli  a1, a1, 3                 ; ...
        slli  a1, a1, 3                 ; ...
        li    t1, 64                    ; ...
        tget  tg10, a0, c6, t1, a1      ; ...
        twait 1 << 10                   ; ...
sgt_ret:
        ret                             ; done

; srv_park() -> a0 = park id of the request in c6 (-1 if the kernel has no room)
srv_park:
        li    a0, SVC_PARK              ; ...
        svc                             ; ...
        ret                             ; done

; srv_unpark(a0 = park id) -> a0 = 0 and the request in c6 (header in
; srv_hdr), or -1 if its owner died meanwhile
srv_unpark:
        mv    a1, a0                    ; ...
        li    a0, SVC_UNPARK            ; ...
        svc                             ; ...
        bnez  a0, sup_ret               ; gone
        la    t0, srv_hdr               ; its header -> D-LS
        li    t1, 64                    ; ...
        tget  tg10, t0, c6, zero, t1    ; ...
        twait 1 << 10                   ; ...
        li    a0, 0                     ; ...
sup_ret:
        ret                             ; done

; srv_pid() -> a0 = the sender of the current request
srv_pid:
        la    t0, srv_hdr               ; ...
        ld    a0, 40(t0)                ; ...
        ret                             ; done

; ---- references ---------------------------------------------------------------------
; ref_add(a0 = pid, a1 = id) -> a0 = 0, or -1 if the table is full
ref_add:
        la    t0, srv_ref               ; a free entry
        li    t1, NREF                  ; ...
rad_l:
        beqz  t1, rad_full              ; none
        ld    t2, 0(t0)                 ; ...
        beqz  t2, rad_put               ; ...
        addi  t0, t0, 16                ; ...
        addi  t1, t1, -1                ; ...
        j     rad_l                     ; ...
rad_put:
        sd    a0, 0(t0)                 ; ...
        sd    a1, 8(t0)                 ; ...
        li    a0, 0                     ; ...
        ret                             ; ...
rad_full:
        li    a0, -1                    ; ...
        ret                             ; ...

; ref_del(a0 = pid, a1 = id) -> a0 = 1 if one such reference was removed
ref_del:
        la    t0, srv_ref               ; ...
        li    t1, NREF                  ; ...
rdl_l:
        beqz  t1, rdl_no                ; ...
        ld    t2, 0(t0)                 ; ...
        bne   t2, a0, rdl_n             ; ...
        ld    t2, 8(t0)                 ; ...
        bne   t2, a1, rdl_n             ; ...
        sd    zero, 0(t0)               ; removed
        sd    zero, 8(t0)               ; ...
        li    a0, 1                     ; ...
        ret                             ; ...
rdl_n:
        addi  t0, t0, 16                ; ...
        addi  t1, t1, -1                ; ...
        j     rdl_l                     ; ...
rdl_no:
        li    a0, 0                     ; ...
        ret                             ; ...

; ref_count(a0 = id) -> a0 = references to it
ref_count:
        la    t0, srv_ref               ; ...
        li    t1, NREF                  ; ...
        li    t3, 0                     ; ...
rct_l:
        beqz  t1, rct_done              ; ...
        ld    t2, 0(t0)                 ; used?
        beqz  t2, rct_n                 ; ...
        ld    t2, 8(t0)                 ; that id?
        bne   t2, a0, rct_n             ; ...
        addi  t3, t3, 1                 ; ...
rct_n:
        addi  t0, t0, 16                ; ...
        addi  t1, t1, -1                ; ...
        j     rct_l                     ; ...
rct_done:
        mv    a0, t3                    ; ...
        ret                             ; ...

; ref_first(a0 = pid) -> a0 = an id that pid holds, or -1
ref_first:
        la    t0, srv_ref               ; ...
        li    t1, NREF                  ; ...
rfi_l:
        beqz  t1, rfi_no                ; ...
        ld    t2, 0(t0)                 ; ...
        bne   t2, a0, rfi_n             ; ...
        ld    a0, 8(t0)                 ; ...
        ret                             ; ...
rfi_n:
        addi  t0, t0, 16                ; ...
        addi  t1, t1, -1                ; ...
        j     rfi_l                     ; ...
rfi_no:
        li    a0, -1                    ; ...
        ret                             ; ...

; ref_dups(): the DUPS request in c6: add (owner, id) for each id -> a0 = 0 / -1
ref_dups:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        la    a0, sys_buf               ; the data: owner, count, ids
        li    a1, 64                    ; (at most 6 ids)
        call  srv_get                   ; ...
        la    s1, sys_buf               ; ...
        ld    s2, 8(s1)                 ; count
        li    t0, 6                     ; ...
        bleu  s2, t0, rdu_l             ; ...
        mv    s2, t0                    ; ...
rdu_l:
        beqz  s2, rdu_ok                ; ...
        ld    a0, 0(s1)                 ; owner
        ld    a1, 16(s1)                ; id
        sd    a1, 24(sp)                ; ...
        call  ref_add                   ; ...
        bltz  a0, rdu_ret               ; full
        addi  s1, s1, 8                 ; next id (owner stays at the old 0(s1)...
        la    t0, sys_buf               ; ...so copy it forward)
        ld    t0, 0(t0)                 ; ...
        sd    t0, 0(s1)                 ; ...
        addi  s2, s2, -1                ; ...
        j     rdu_l                     ; ...
rdu_ok:
        li    a0, 0                     ; ...
rdu_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; srv_bcopy(a0 = destination, a1 = source, a2 = bytes): D-LS byte copy
srv_bcopy:
        beqz  a2, sbc_ret               ; ...
        lbu   t0, 0(a1)                 ; ...
        sb    t0, 0(a0)                 ; ...
        addi  a0, a0, 1                 ; ...
        addi  a1, a1, 1                 ; ...
        addi  a2, a2, -1                ; ...
        j     srv_bcopy                 ; ...
sbc_ret:
        ret                             ; ...
