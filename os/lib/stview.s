; =============================================================================
; stview.s: looking into the store on the disk, for programs (db, wdb)
; =============================================================================
;
; The disk is a store of copy-on-write B+trees (doc/strata-fs-proposal.md;
; the format is at the top of tools/stdb/store.c). A program can read it as
; the file server last committed it, block by block, with fs READBLK: what a
; commit wrote is never written over before the next commit is whole, so
; the trees reached from the newer meta block are always consistent.
;
;   sv_init()                 the boot header and the newer meta block -> a0 =
;                             0, or -1 when the disk is not a store
;   sv_page(page)             -> a0 = the page, in sv_buf (0: not readable)
;   sv_first(root, height)    a walk over a tree's records begins
;   sv_next()                 -> a0 = the next record's cell in sv_buf, or 0
;   sv_cell(page buffer, i)   -> a0 = cell i of a page
; A leaf cell: u16 key length, u16 value length (bit 15: a stream: the value
; is u64 length, u64 id), the key at 8, the value after it at the next
; multiple of 8. A branch cell: u16 key length, the child page at 8, the key
; at 16 (cell 0 has none: its child holds everything below cell 1's key).
;
; Lines of text about what was read, for a terminal or a window: the
; sl_ routines build one in sl_buf (sl_len bytes):
;   sl_store()                the store: commit, pages, free pages
;   sl_page(page buffer)      a page: its number, kind, level, cells, fill
;   sl_cellline(page buffer, i)   cell i of a page: key and value, or child
;   sl_cellat(page buffer, cell)  the same for a cell at hand
; Keys and values are shown in quotes, bytes that do not print as \xx.
;
; sv_ep is the register of the endpoint to fs (2, unless the program moved
; it). Include after sys.s. Clobbers t0..t6, a0..a7.

SV_LEAF = 2                             ; a page's kind (byte 24): a leaf (1: a branch)
SL_MAX  = 150                           ; a line's most bytes

        .data                           ; D-LS
        .align 8                        ; dwords
sv_ep:     .dword 2                     ; the endpoint to fs
sv_ps:     .dword 0                     ; the page size
sv_bpp:    .dword 0                     ; blocks per page
sv_commit: .dword 0                     ; the meta block's words: the commit,
sv_npages: .dword 0                     ;   pages on the disk,
sv_first_: .dword 0                     ;   the first the store manages,
sv_cat:    .space 16                    ;   the catalog's root and height,
sv_fre:    .space 16                    ;   the free tree's,
sv_pend:   .space 16                    ;   the pending tree's,
sv_manif:  .dword 0                     ;   the boot manifest's page,
sv_nfree:  .dword 0                     ;   free pages
sv_cur:    .dword 0                     ; the page in sv_buf (0: none)
sv_dep:    .dword 0                     ; a walk: the tree's height (0: over)
sv_path:   .space 16 * 16               ;   page and next index, level by level
sl_len:    .dword 0                     ; the line being built
sl_buf:    .space SL_MAX + 10           ; ...
sv_buf:    .space 4096                  ; a page
sl_m1:     .ascii "store: commit "      ; texts
sl_m1e:
sl_m2:     .ascii " pages of "          ; ...
sl_m2e:
sl_m3:     .ascii " bytes, "            ; ...
sl_m3e:
sl_m4:     .ascii " free"               ; ...
sl_m4e:
sl_m5:     .ascii "page "               ; ...
sl_m5e:
sl_m6:     .ascii ": leaf, "            ; ...
sl_m6e:
sl_m7:     .ascii ": branch, level "    ; ...
sl_m7e:
sl_m8:     .ascii " cells, "            ; ...
sl_m8e:
sl_m9:     .ascii " bytes used, commit " ; ...
sl_m9e:
sl_m10:    .ascii " -> page "           ; ...
sl_m10e:
sl_m11:    .ascii "stream of "          ; ...
sl_m11e:
sl_m12:    .ascii " bytes, id "         ; ...
sl_m12e:
sl_m13:    .ascii "(below) "            ; ...
sl_m13e:
sl_hex:    .ascii "0123456789abcdef"    ; ...
        .align 8                        ; ...
        .text                           ; code

; sv_blk(a0 = block, a1 = where its 512 bytes go) -> a0 = 0, or -1
sv_blk:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a1, 8(sp)                 ; ...
        mv    a2, a0                    ; ...
        la    t0, sv_ep                 ; ...
        ld    a0, 0(t0)                 ; ...
        li    a1, 33                    ; READBLK
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        call  sys_msg                   ; ...
        li    t0, 512                   ; ...
        bne   a0, t0, svb_no            ; ...
        ld    a0, 8(sp)                 ; ...
        li    a1, 512                   ; ...
        call  sys_get                   ; ...
        li    a0, 0                     ; ...
        j     svb_ret                   ; ...
svb_no:
        li    a0, -1                    ; ...
svb_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; sv_page(a0 = page) -> a0 = sv_buf holding it, or 0
sv_page:
        la    t0, sv_cur                ; there already?
        ld    t1, 0(t0)                 ; ...
        bne   t1, a0, svp_rd            ; ...
        la    a0, sv_buf                ; ...
        ret                             ; ...
svp_rd:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        mv    s1, a0                    ; s1 = the page
        sd    zero, 0(t0)               ; ...
        li    s2, 0                     ; s2 = the block of it
        la    s3, sv_buf                ; ...
svp_l:
        la    t0, sv_bpp                ; ...
        ld    t0, 0(t0)                 ; ...
        bgeu  s2, t0, svp_ok            ; ...
        mul   a0, s1, t0                ; ...
        add   a0, a0, s2                ; ...
        mv    a1, s3                    ; ...
        call  sv_blk                    ; ...
        bltz  a0, svp_no                ; ...
        addi  s3, s3, 512               ; ...
        addi  s2, s2, 1                 ; ...
        j     svp_l                     ; ...
svp_ok:
        la    t0, sv_cur                ; ...
        sd    s1, 0(t0)                 ; ...
        la    a0, sv_buf                ; ...
        j     svp_ret                   ; ...
svp_no:
        li    a0, 0                     ; ...
svp_ret:
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; sv_init() -> a0 = 0, or -1 when the disk is not a store
sv_init:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        li    a0, 0                     ; block 0: "STDB", the page size
        la    a1, sv_buf                ; ...
        call  sv_blk                    ; ...
        bltz  a0, svi_no                ; ...
        la    t0, sv_buf                ; ...
        lwu   t1, 56(t0)                ; ...
        li    t2, 0x42445453            ; ...
        bne   t1, t2, svi_no            ; ...
        lwu   t1, 60(t0)                ; ...
        la    t2, sv_ps                 ; ...
        sd    t1, 0(t2)                 ; ...
        srli  t1, t1, 9                 ; ...
        la    t2, sv_bpp                ; ...
        sd    t1, 0(t2)                 ; ...
        mv    a0, t1                    ; the two meta blocks: pages 1 and 2
        la    a1, sv_buf                ; ...
        call  sv_blk                    ; ...
        bltz  a0, svi_no                ; ...
        la    t2, sv_bpp                ; ...
        ld    a0, 0(t2)                 ; ...
        slli  a0, a0, 1                 ; ...
        la    a1, sv_buf + 512          ; ...
        call  sv_blk                    ; ...
        bltz  a0, svi_no                ; ...
        li    s1, 0                     ; s1 = the newer one, s2 = its commit + 1
        li    s2, 0                     ; ...
        la    t0, sv_buf                ; ...
        li    t3, 2                     ; ...
svi_m:
        ld    t1, 8(t0)                 ; "STDBMETA"?
        li    t2, 0x4154454D42445453    ; ...
        bne   t1, t2, svi_n             ; ...
        ld    t1, 16(t0)                ; ...
        addi  t1, t1, 1                 ; ...
        bleu  t1, s2, svi_n             ; ...
        mv    s2, t1                    ; ...
        mv    s1, t0                    ; ...
svi_n:
        addi  t0, t0, 512               ; ...
        addi  t3, t3, -1                ; ...
        bnez  t3, svi_m                 ; ...
        beqz  s1, svi_no                ; ...
        la    t0, sv_commit             ; its words
        ld    t1, 16(s1)                ; ...
        sd    t1, 0(t0)                 ; ...
        ld    t1, 24(s1)                ; ...
        sd    t1, 8(t0)                 ; ...
        ld    t1, 32(s1)                ; ...
        sd    t1, 16(t0)                ; ...
        li    t2, 0                     ; the three roots and heights: words 40..80
svi_c:
        add   t3, s1, t2                ; ...
        ld    t1, 40(t3)                ; ...
        add   t3, t0, t2                ; ...
        sd    t1, 24(t3)                ; ...
        addi  t2, t2, 8                 ; ...
        li    t3, 48                    ; ...
        bne   t2, t3, svi_c             ; ...
        ld    t1, 88(s1)                ; ...
        la    t0, sv_manif              ; ...
        sd    t1, 0(t0)                 ; ...
        ld    t1, 104(s1)               ; ...
        la    t0, sv_nfree              ; ...
        sd    t1, 0(t0)                 ; ...
        la    t0, sv_cur                ; (sv_buf holds no page)
        sd    zero, 0(t0)               ; ...
        li    a0, 0                     ; ...
        j     svi_ret                   ; ...
svi_no:
        li    a0, -1                    ; ...
svi_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; sv_cell(a0 = page buffer, a1 = index) -> a0 = that cell
sv_cell:
        slli  a1, a1, 1                 ; ...
        add   a1, a1, a0                ; ...
        lhu   a1, 32(a1)                ; ...
        add   a0, a0, a1                ; ...
        ret                             ; ...

; sv_down(a0 = level): from that level of the walk's path down to a leaf, by
; each page's cell at its index (the levels below start at their first cell)
sv_down:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        mv    s1, a0                    ; ...
svd_l:
        la    t0, sv_dep                ; the leaf's level?
        ld    t0, 0(t0)                 ; ...
        addi  t0, t0, -1                ; ...
        bge   s1, t0, svd_ret           ; ...
        slli  t0, s1, 4                 ; ...
        la    t1, sv_path               ; ...
        add   t0, t0, t1                ; ...
        ld    a0, 0(t0)                 ; ...
        call  sv_page                   ; ...
        beqz  a0, svd_bad               ; ...
        slli  t0, s1, 4                 ; ...
        la    t1, sv_path               ; ...
        add   t0, t0, t1                ; ...
        ld    a1, 8(t0)                 ; ...
        call  sv_cell                   ; ...
        ld    t2, 8(a0)                 ; its child
        slli  t0, s1, 4                 ; ...
        la    t1, sv_path               ; ...
        add   t0, t0, t1                ; ...
        sd    t2, 16(t0)                ; ...
        sd    zero, 24(t0)              ; ...
        addi  s1, s1, 1                 ; ...
        j     svd_l                     ; ...
svd_bad:
        la    t0, sv_dep                ; (a page that cannot be read ends the walk)
        sd    zero, 0(t0)               ; ...
svd_ret:
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; sv_first(a0 = root, a1 = height): a walk over the tree's records begins
sv_first:
        la    t0, sv_dep                ; ...
        sd    a1, 0(t0)                 ; ...
        bnez  a0, svf_1                 ; (an empty tree: nothing to walk)
        sd    zero, 0(t0)               ; ...
svf_1:
        la    t0, sv_path               ; ...
        sd    a0, 0(t0)                 ; ...
        sd    zero, 8(t0)               ; ...
        beqz  a0, slc_ret               ; ...
        li    a0, 0                     ; ...
        j     sv_down                   ; ...

; sv_next() -> a0 = the next record's cell (in sv_buf), or 0 at the end
sv_next:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
svn_l:
        la    t0, sv_dep                ; ...
        ld    s1, 0(t0)                 ; ...
        beqz  s1, svn_end               ; ...
        addi  s1, s1, -1                ; s1 = the leaf's level
svn_p:
        slli  s2, s1, 4                 ; s2 = its path entry
        la    t1, sv_path               ; ...
        add   s2, s2, t1                ; ...
        ld    a0, 0(s2)                 ; ...
        call  sv_page                   ; ...
        beqz  a0, svn_end               ; ...
        ld    a1, 8(s2)                 ; a cell left in it?
        lhu   t0, 26(a0)                ; ...
        bgeu  a1, t0, svn_up            ; ...
        la    t0, sv_dep                ; at the leaf: this record, and on
        ld    t0, 0(t0)                 ; ...
        addi  t0, t0, -1                ; ...
        bne   s1, t0, svn_dn            ; ...
        addi  t1, a1, 1                 ; ...
        sd    t1, 8(s2)                 ; ...
        call  sv_cell                   ; ...
        j     svn_ret                   ; ...
svn_dn:
        mv    a0, s1                    ; a branch: down its next child
        call  sv_down                   ; ...
        j     svn_l                     ; ...
svn_up:
        beqz  s1, svn_end               ; the root is done: the end
        addi  s1, s1, -1                ; the page above goes on to its next cell
        slli  s2, s1, 4                 ; ...
        la    t1, sv_path               ; ...
        add   s2, s2, t1                ; ...
        ld    t0, 8(s2)                 ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, 8(s2)                 ; ...
        j     svn_p                     ; ...
svn_end:
        la    t0, sv_dep                ; ...
        sd    zero, 0(t0)               ; ...
        li    a0, 0                     ; ...
svn_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; ---- lines -------------------------------------------------------------------------

; sl_new(): an empty line
sl_new:
        la    t0, sl_len                ; ...
        sd    zero, 0(t0)               ; ...
        ret                             ; ...

; sl_ch(a0 = a character): onto the line (a full line takes no more)
sl_ch:
        la    t0, sl_len                ; ...
        ld    t1, 0(t0)                 ; ...
        li    t2, SL_MAX                ; ...
        bgeu  t1, t2, slc_ret           ; ...
        la    t2, sl_buf                ; ...
        add   t2, t2, t1                ; ...
        sb    a0, 0(t2)                 ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, 0(t0)                 ; ...
slc_ret:
        ret                             ; ...

; sl_str(a0 = text, a1 = its length): onto the line
sl_str:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        mv    s1, a0                    ; ...
        add   s2, a0, a1                ; ...
sls_l:
        bgeu  s1, s2, sls_ret           ; ...
        lbu   a0, 0(s1)                 ; ...
        call  sl_ch                     ; ...
        addi  s1, s1, 1                 ; ...
        j     sls_l                     ; ...
sls_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; sl_dec(a0 = a number): in decimal, onto the line
sl_dec:
        addi  sp, sp, -40               ; frame (24 bytes of digits)
        sd    ra, 0(sp)                 ; ...
        addi  t0, sp, 40                ; the digits, from the last
        li    t1, 10                    ; ...
sld_l:
        remu  t2, a0, t1                ; ...
        divu  a0, a0, t1                ; ...
        addi  t2, t2, '0'               ; ...
        addi  t0, t0, -1                ; ...
        sb    t2, 0(t0)                 ; ...
        bnez  a0, sld_l                 ; ...
        mv    a0, t0                    ; ...
        addi  a1, sp, 40                ; ...
        sub   a1, a1, t0                ; ...
        call  sl_str                    ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 40                ; ...
        ret                             ; ...

; sl_bytes(a0 = bytes, a1 = how many, a2 = the most to show): in quotes, the
; printable ones as they are, the others as \xx (two hex digits); ".." when
; cut short
sl_bytes:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s4, 24(sp)                ; ...
        mv    s1, a0                    ; s1 = the bytes
        mv    s2, a1                    ; s2 = how many are shown
        li    s4, 0                     ; s4 = cut short
        bleu  s2, a2, slb_1             ; ...
        mv    s2, a2                    ; ...
        li    s4, 1                     ; ...
slb_1:
        add   s2, s2, s1                ; ...
        li    a0, '"'                   ; ...
        call  sl_ch                     ; ...
slb_l:
        bgeu  s1, s2, slb_end           ; ...
        lbu   a0, 0(s1)                 ; ...
        li    t2, 32                    ; ...
        bltu  a0, t2, slb_x             ; ...
        li    t2, 127                   ; ...
        bgeu  a0, t2, slb_x             ; ...
        li    t2, 34                    ; (a quote too is written as \22)
        beq   a0, t2, slb_x             ; ...
        li    t2, 92                    ; (a backslash is written twice)
        bne   a0, t2, slb_c             ; ...
        call  sl_ch                     ; ...
        li    a0, 92                    ; ...
slb_c:
        call  sl_ch                     ; ...
        j     slb_n                     ; ...
slb_x:
        li    a0, 92                    ; ...
        call  sl_ch                     ; ...
        lbu   t0, 0(s1)                 ; ...
        srli  t1, t0, 4                 ; ...
        la    t2, sl_hex                ; ...
        add   t1, t1, t2                ; ...
        lbu   a0, 0(t1)                 ; ...
        call  sl_ch                     ; ...
        lbu   t0, 0(s1)                 ; ...
        andi  t0, t0, 15                ; ...
        la    t2, sl_hex                ; ...
        add   t0, t0, t2                ; ...
        lbu   a0, 0(t0)                 ; ...
        call  sl_ch                     ; ...
slb_n:
        addi  s1, s1, 1                 ; ...
        j     slb_l                     ; ...
slb_end:
        li    a0, '"'                   ; ...
        call  sl_ch                     ; ...
        beqz  s4, slb_ret               ; ...
        li    a0, '.'                   ; ...
        call  sl_ch                     ; ...
        li    a0, '.'                   ; ...
        call  sl_ch                     ; ...
slb_ret:
        ld    s4, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; sl_store(): the line about the store
sl_store:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        call  sl_new                    ; ...
        la    a0, sl_m1                 ; ...
        li    a1, sl_m1e - sl_m1        ; ...
        call  sl_str                    ; ...
        la    t0, sv_commit             ; ...
        ld    a0, 0(t0)                 ; ...
        call  sl_dec                    ; ...
        li    a0, ','                   ; ...
        call  sl_ch                     ; ...
        li    a0, ' '                   ; ...
        call  sl_ch                     ; ...
        la    t0, sv_npages             ; ...
        ld    a0, 0(t0)                 ; ...
        call  sl_dec                    ; ...
        la    a0, sl_m2                 ; ...
        li    a1, sl_m2e - sl_m2        ; ...
        call  sl_str                    ; ...
        la    t0, sv_ps                 ; ...
        ld    a0, 0(t0)                 ; ...
        call  sl_dec                    ; ...
        la    a0, sl_m3                 ; ...
        li    a1, sl_m3e - sl_m3        ; ...
        call  sl_str                    ; ...
        la    t0, sv_nfree              ; ...
        ld    a0, 0(t0)                 ; ...
        call  sl_dec                    ; ...
        la    a0, sl_m4                 ; ...
        li    a1, sl_m4e - sl_m4        ; ...
        call  sl_str                    ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; sl_page(a0 = page buffer): the line about a page
sl_page:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        mv    s1, a0                    ; ...
        call  sl_new                    ; ...
        la    a0, sl_m5                 ; ...
        li    a1, sl_m5e - sl_m5        ; ...
        call  sl_str                    ; ...
        ld    a0, 8(s1)                 ; ...
        call  sl_dec                    ; ...
        lbu   t0, 24(s1)                ; ...
        li    t1, SV_LEAF               ; ...
        bne   t0, t1, slp_br            ; ...
        la    a0, sl_m6                 ; ...
        li    a1, sl_m6e - sl_m6        ; ...
        call  sl_str                    ; ...
        j     slp_c                     ; ...
slp_br:
        la    a0, sl_m7                 ; ...
        li    a1, sl_m7e - sl_m7        ; ...
        call  sl_str                    ; ...
        lbu   a0, 25(s1)                ; ...
        call  sl_dec                    ; ...
        li    a0, ','                   ; ...
        call  sl_ch                     ; ...
        li    a0, ' '                   ; ...
        call  sl_ch                     ; ...
slp_c:
        lhu   a0, 26(s1)                ; ...
        call  sl_dec                    ; ...
        la    a0, sl_m8                 ; ...
        li    a1, sl_m8e - sl_m8        ; ...
        call  sl_str                    ; ...
        la    t0, sv_ps                 ; the bytes its cells and slots take
        ld    a0, 0(t0)                 ; ...
        lhu   t1, 28(s1)                ; ...
        sub   a0, a0, t1                ; ...
        lhu   t1, 26(s1)                ; ...
        slli  t1, t1, 1                 ; ...
        add   a0, a0, t1                ; ...
        call  sl_dec                    ; ...
        la    a0, sl_m9                 ; ...
        li    a1, sl_m9e - sl_m9        ; ...
        call  sl_str                    ; ...
        ld    a0, 16(s1)                ; ...
        call  sl_dec                    ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; sl_cellline(a0 = page buffer, a1 = index): the line about that cell: a
; leaf's "KEY = VALUE", a branch's "KEY -> page N"
sl_cellline:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        mv    s2, a0                    ; s2 = the page
        call  sv_cell                   ; ...
        mv    s1, a0                    ; s1 = the cell
        j     scl_go                    ; ...
; sl_cellat(a0 = page buffer, a1 = a cell of it): the same, for that cell
sl_cellat:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        mv    s2, a0                    ; ...
        mv    s1, a1                    ; ...
scl_go:
        call  sl_new                    ; ...
        lbu   t0, 24(s2)                ; ...
        li    t1, SV_LEAF               ; ...
        beq   t0, t1, scl_leaf          ; ...
        lhu   a1, 0(s1)                 ; a branch: the key (cell 0 has none)
        bnez  a1, scl_bk                ; ...
        la    a0, sl_m13                ; ...
        li    a1, sl_m13e - sl_m13      ; ...
        call  sl_str                    ; ...
        j     scl_bc                    ; ...
scl_bk:
        addi  a0, s1, 16                ; ...
        li    a2, 48                    ; ...
        call  sl_bytes                  ; ...
scl_bc:
        la    a0, sl_m10                ; ...
        li    a1, sl_m10e - sl_m10      ; ...
        call  sl_str                    ; ...
        ld    a0, 8(s1)                 ; ...
        call  sl_dec                    ; ...
        j     scx_ret                   ; ...
scl_leaf:
        addi  a0, s1, 8                 ; the key
        lhu   a1, 0(s1)                 ; ...
        li    a2, 48                    ; ...
        call  sl_bytes                  ; ...
        li    a0, ' '                   ; ...
        call  sl_ch                     ; ...
        li    a0, '='                   ; ...
        call  sl_ch                     ; ...
        li    a0, ' '                   ; ...
        call  sl_ch                     ; ...
        lhu   t0, 0(s1)                 ; s2 = the value
        addi  t0, t0, 7                 ; ...
        srli  t0, t0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        add   s2, s1, t0                ; ...
        addi  s2, s2, 8                 ; ...
        lhu   t1, 2(s1)                 ; ...
        srli  t2, t1, 15                ; ...
        bnez  t2, scl_st                ; ...
        mv    a0, s2                    ; ...
        mv    a1, t1                    ; ...
        li    a2, 40                    ; ...
        call  sl_bytes                  ; ...
        j     scx_ret                   ; ...
scl_st:
        la    a0, sl_m11                ; a stream: its length and id
        li    a1, sl_m11e - sl_m11      ; ...
        call  sl_str                    ; ...
        ld    a0, 0(s2)                 ; ...
        call  sl_dec                    ; ...
        la    a0, sl_m12                ; ...
        li    a1, sl_m12e - sl_m12      ; ...
        call  sl_str                    ; ...
        ld    a0, 8(s2)                 ; ...
        call  sl_dec                    ; ...
scx_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...
