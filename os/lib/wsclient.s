; =============================================================================
; wsclient.s: the window server's protocol for client programs
; =============================================================================
;
; A client of `ws` (os/ws/ws.s has the protocol) owns a window: a surface
; of XRGB8888 pixels that the *server* keeps. Memory capabilities are linear
; (no memory is ever shared), so the client does not draw into the surface.
; It draws into a BAND: its own arena (c0, 832 KiB once the start-up block
; has been read), used as a strip of the window, full width and as many rows
; as fit. To show what it drew it lends the band to the server with DAMAGE;
; the server copies those rows into the surface, composes the screen, and
; gives the band back with the reply.
;
;   wc_open(title, flags)        look up "ws", CREATE; -> a0 = id or < 0
;   wc_band(y0)                  the band now holds the window's rows from y0:
;                                draw with os/lib/gfx.s into `wc_surf` (the
;                                whole window as a surface; only rows
;                                y0 .. y0 + wc_rows - 1 exist), then
;   wc_damage(y, h)              lend the band: rows y .. y + h - 1 (y >= y0)
;   wc_event(mode, timeout)      -> a0 = 0 and wc_ev = kind, value, width (keys:
;                                their number), height; -3 none (mode 1);
;                                -8 the timeout passed; -1 the window is gone.
;                                A resize has already been applied to wc_surf.
;   wc_text(x, y, string, length, fg, bg)   wc_fill(x, y, w, h, colour)
;   wc_title(title)              wc_close()
; wc_keep (set before wc_open): bytes at the top of the arena the band leaves
; alone, for the client's own far data (term keeps its scrollback there).
; The server's endpoint goes into c2 (the client gives up its endpoint to
; fs; standard handles on the console or a pipe keep working). c6 must stay
; empty: the band comes back through it.
;
; Include after sys.s and gfx.s. Clobbers t0..t6, a0..a7.

WC_EP     = 2                           ; the register of the endpoint to ws
OP_WTITLE = 46                          ; ws: a window's title
WE_KEY    = 1                           ; event kinds: keys (value: up to 8 bytes)
WE_SIZE   = 2                           ; the surface has a new size
WE_CLOSE  = 3                           ; the window is closing: go away
WE_FOCUS  = 4                           ; keys come here now
WE_BLUR   = 5                           ; ... and no more
WE_PTR    = 6                           ; the pointer: value = u16 x, u16 y, u8 buttons, 0, 0, u8 kind
WE_WHEEL  = 7                           ; the wheel: value = u16 x, u16 y, u8 buttons, s8 y, s8 x, 3

        .data                           ; D-LS
        .align 8                        ; dwords
wc_id:    .dword 0                      ; our window
wc_surf:  .space S_SIZE                 ; the window as a surface (through the band)
wc_rows:  .dword 0                      ; rows the band holds at this width
wc_keep:  .dword 0                      ; bytes at the top of c0 that are not the band's
wc_y0:    .dword 0                      ; the window row at the band's start
wc_ev:    .space 32                     ; the last event
wc_d:     .space 48                     ; request data
wc_name:  .ascii "ws"                   ; the server's name
        .align 8                        ; ...
        .text                           ; code

; wc_size(a0 = width, a1 = height): the window's surface has that size
wc_size:                                ; routine entry
        la    t0, wc_surf               ; the descriptor
        sd    zero, S_CAP(t0)           ; through c0: the band
        sd    zero, S_OFF(t0)           ; (set by wc_band)
        sd    a0, S_W(t0)               ; ...
        sd    a1, S_H(t0)               ; ...
        slli  t1, a0, 2                 ; rows are width * 4 bytes apart
        sd    t1, S_STRIDE(t0)          ; ...
        clen  t2, c0                    ; rows that fit in the band
        la    t3, wc_keep               ; (less what the client keeps)
        ld    t3, 0(t3)                 ; ...
        sub   t2, t2, t3                ; ...
        divu  t2, t2, t1                ; ...
        la    t0, wc_rows               ; ...
        sd    t2, 0(t0)                 ; ...
        ret                             ; done

; wc_open(a0 = title: 8 bytes, NUL-padded; a1 = flags: bit 0 = the server
; interrupts us (SIGNAL) when events wait and we are not in wc_event)
; -> a0 = the window's id, or < 0 (-4: no window server)
wc_open:                                ; routine entry
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    a0, 8(sp)                 ; title
        sd    a1, 16(sp)                ; flags
        la    a0, wc_name               ; LOOKUP "ws" into c2
        li    a1, 2                     ; ...
        li    a2, WC_EP                 ; ...
        call  sys_lookup                ; ...
        li    t0, -4                    ; (none)
        bnez  a0, wo_fail               ; ...
        cclear c6                       ; (c6 stays empty: the band comes back there)
        la    t0, wc_d                  ; data: w, h (the tile decides), title
        sd    zero, 0(t0)               ; ...
        sd    zero, 8(t0)               ; ...
        ld    t1, 8(sp)                 ; ...
        ld    t1, 0(t1)                 ; ...
        sd    t1, 16(t0)                ; ...
        mv    a0, t0                    ; ...
        li    a1, 24                    ; ...
        call  sys_put                   ; ...
        li    a0, WC_EP                 ; CREATE
        li    a1, OP_WCREATE            ; ...
        li    a2, 0                     ; ...
        li    a3, 24                    ; ...
        ld    a4, 16(sp)                ; ...
        call  sys_msg                   ; a0 = id
        mv    t0, a0                    ; ...
        blez  a0, wo_fail               ; refused
        la    t1, wc_id                 ; ...
        sd    a0, 0(t1)                 ; ...
        la    a0, wc_d                  ; data: the surface's size
        li    a1, 16                    ; ...
        call  sys_get                   ; ...
        la    t0, wc_d                  ; ...
        ld    a0, 0(t0)                 ; ...
        ld    a1, 8(t0)                 ; ...
        call  wc_size                   ; ...
        la    t0, wc_id                 ; ...
        ld    t0, 0(t0)                 ; ...
wo_fail:
        mv    a0, t0                    ; id or error
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; wc_band(a0 = y0): from now on the band's first row is the window's row y0
wc_band:                                ; routine entry
        la    t0, wc_surf               ; pixel (0, 0) would lie y0 rows before the band
        ld    t1, S_STRIDE(t0)          ; ...
        mul   t1, t1, a0                ; ...
        neg   t1, t1                    ; ...
        sd    t1, S_OFF(t0)             ; ...
        la    t0, wc_y0                 ; ...
        sd    a0, 0(t0)                 ; ...
        ret                             ; done

; wc_damage(a0 = y, a1 = h): rows y .. y + h - 1 (drawn into the band since
; wc_band) are copied into the window by the server -> a0 = 0 or < 0
wc_damage:                              ; routine entry
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        twait (1 << 8) | (1 << 9)       ; gfx.s's transfers into the band are done
        la    t0, wc_d                  ; data: x, y, w, h, stride
        la    t1, wc_surf               ; ...
        sd    zero, 0(t0)               ; x = 0: full rows
        sd    a0, 8(t0)                 ; ...
        ld    t2, S_W(t1)               ; ...
        sd    t2, 16(t0)                ; ...
        sd    a1, 24(t0)                ; ...
        ld    t2, S_STRIDE(t1)          ; ...
        sd    t2, 32(t0)                ; ...
        la    t3, wc_y0                 ; (rows of the band before y are not sent: the
        ld    t3, 0(t3)                 ;   server wants row y at the band's offset 0,
        sub   t3, a0, t3                ;   so only y = y0 can be lent; callers set
        bnez  t3, wdm_bad               ;   the band to the first row they draw)
        mv    a0, t0                    ; ...
        li    a1, 40                    ; ...
        call  sys_put                   ; ...
        li    a0, WC_EP                 ; DAMAGE, with the band (c0) attached
        li    a1, OP_WDAMAGE            ; ...
        la    t0, wc_id                 ; ...
        ld    a2, 0(t0)                 ; ...
        li    a3, 40                    ; ...
        li    a4, 0                     ; ...
        li    a5, 0                     ; (register 0)
        call  sys_msga                  ; a0 = result; the band is back in c6
        cvalid t0, c6                   ; ...
        beqz  t0, wdm_ret               ; (nothing was sent)
        cmov  c0, c6                    ; home
        j     wdm_ret                   ; ...
wdm_bad:
        li    a0, -1                    ; ...
wdm_ret:
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; wc_event(a0 = 1: do not block, a1 = timeout in ticks (0: none)) -> a0 = 0
; and the event in wc_ev (kind, value, width or the number of key bytes,
; height); -3 none, -8 timed out, -1 no window
wc_event:                               ; routine entry
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        mv    a4, a0                    ; mode
        mv    a3, a1                    ; length = the timeout
        li    a0, WC_EP                 ; EVENT
        li    a1, OP_WEVENT             ; ...
        la    t0, wc_id                 ; ...
        ld    a2, 0(t0)                 ; ...
        call  sys_msg                   ; ...
        sd    a0, 8(sp)                 ; ...
        bnez  a0, wev_ret               ; no event
        la    a0, wc_ev                 ; the event
        li    a1, 32                    ; ...
        call  sys_get                   ; ...
        la    t0, wc_ev                 ; a resize: the surface's new size
        ld    t1, 0(t0)                 ; ...
        li    t2, WE_SIZE               ; ...
        bne   t1, t2, wev_ret           ; ...
        ld    a0, 16(t0)                ; ...
        ld    a1, 24(t0)                ; ...
        call  wc_size                   ; ...
wev_ret:
        ld    a0, 8(sp)                 ; the result
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 16                ; pop the frame
        ret                             ; done

; wc_fill(a0 = x, a1 = y, a2 = w, a3 = h, a4 = colour): the server fills
; that rectangle of the window
wc_fill:                                ; routine entry
        la    t0, wc_d                  ; data: x, y, w, h, colour
        sd    a0, 0(t0)                 ; ...
        sd    a1, 8(t0)                 ; ...
        sd    a2, 16(t0)                ; ...
        sd    a3, 24(t0)                ; ...
        sd    a4, 32(t0)                ; ...
        li    a1, OP_WFILL              ; ...
        li    a3, 40                    ; ...
        mv    a2, t0                    ; ...
        j     wc_call                   ; ...

; wc_title(a0 = title: 8 bytes, NUL-padded)
wc_title:                               ; routine entry
        mv    a2, a0                    ; the data
        li    a1, OP_WTITLE             ; ...
        li    a3, 8                     ; ...
        j     wc_call                   ; ...

; wc_close(): DESTROY the window
wc_close:                               ; routine entry
        li    a1, OP_WDESTROY           ; ...
        la    a2, wc_d                  ; (no data)
        li    a3, 0                     ; ...
; wc_call(a1 = op, a2 = data, a3 = its length) -> a0 = result: a request
; about our window
wc_call:                                ; routine entry
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    a1, 8(sp)                 ; op
        sd    a3, 16(sp)                ; length
        mv    a0, a2                    ; the data -> the buffer
        mv    a1, a3                    ; ...
        call  sys_put                   ; ...
        li    a0, WC_EP                 ; ...
        ld    a1, 8(sp)                 ; ...
        la    t0, wc_id                 ; ...
        ld    a2, 0(t0)                 ; ...
        ld    a3, 16(sp)                ; ...
        li    a4, 0                     ; ...
        call  sys_msg                   ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; wc_text(a0 = x, a1 = y, a2 = string, a3 = length (at most 160), a4 = fg,
; a5 = bg or -1): the server draws it into the window, 8 x 16 font
wc_text:                                ; routine entry
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    a3, 8(sp)                 ; the length
        la    t0, sys_buf               ; data: x, y, fg, bg, the string (in the
        sd    a0, 0(t0)                 ;   library's staging buffer: it is long)
        sd    a1, 8(t0)                 ; ...
        sd    a4, 16(t0)                ; ...
        sd    a5, 24(t0)                ; ...
        li    t1, 0                     ; ...
wtx_c:  beq   t1, a3, wtx_s             ; ...
        add   t2, a2, t1                ; ...
        lbu   t2, 0(t2)                 ; ...
        add   t3, t0, t1                ; ...
        sb    t2, 32(t3)                ; ...
        addi  t1, t1, 1                 ; ...
        j     wtx_c                     ; ...
wtx_s:  addi  t1, a3, 32 + 7            ; whole words
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        li    t2, 64                    ; after the header
        tput  tg10, t0, c5, t2, t1      ; (sys_msg's twait orders it before the send)
        li    a0, WC_EP                 ; TEXT
        li    a1, OP_WTEXT              ; ...
        la    t0, wc_id                 ; ...
        ld    a2, 0(t0)                 ; ...
        ld    a3, 8(sp)                 ; ...
        addi  a3, a3, 32                ; ...
        li    a4, 0                     ; ...
        call  sys_msg                   ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 16                ; pop the frame
        ret                             ; done
