#!/usr/bin/env python3
"""gen_font.py: the StrataOS fonts, drawn here as ASCII art, written out as
assembler data (os/lib/font/font.s).

Both fonts are original work made for StrataOS and dedicated to the public
domain. Nothing here is derived from another font.

  body  8 x 16 cells: the terminal and everything else that is read. Glyphs
        are 6 pixels wide (7 for the wide ones), one-pixel strokes, square
        shoulders with cut corners, cap height 10, x-height 7, descenders 3.
  mini  6 x 8 cells, 5 x 7 capitals: the HUD (tile tags, the core lattice,
        labels). Lower case maps to the capitals, so any text set in it reads
        as small caps.

Both cover ASCII 32..126 plus a few HUD glyphs at 0x80..0x87:
  0x80 ▸   0x81 ·   0x82 ›   0x83 ◂   0x84 ■   0x85 ▴   0x86 ▾   0x87 ‹

Table format (one byte per glyph row, bit 7 = leftmost pixel), see gfx.s
"Fonts":  body: 16 bytes per glyph, row 0 at the top of the cell;
          mini: 8 bytes per glyph.

    python3 os/lib/font/gen_font.py            # writes os/lib/font/font.s
    python3 os/lib/font/gen_font.py --ppm F    # also a preview image
"""
import sys, os

FIRST, LAST = 32, 0x87          # codes in the tables (0x7f..0x7f is a blank)
CAP_TOP = 3                      # body: cell row of the cap line

body = {}
mini = {}


def G(ch, top, rows):
    """A body glyph: rows of 7 characters (cell columns 0..6, '#' = ink),
    the first one at line `top` (line 0 = the cap line = cell row 3)."""
    code = ord(ch) if isinstance(ch, str) else ch
    assert code not in body, ch
    cell = [0] * 16
    for i, r in enumerate(rows):
        assert len(r) == 7, (ch, r)
        bits = 0
        for c, p in enumerate(r):
            if p == '#':
                bits |= 0x80 >> c
        cell[CAP_TOP + top + i] = bits
    body[code] = cell


def M(ch, top, rows):
    """A mini glyph: rows of 5 characters (cell columns 0..4), from row `top`."""
    code = ord(ch) if isinstance(ch, str) else ch
    assert code not in mini, ch
    cell = [0] * 8
    for i, r in enumerate(rows):
        assert len(r) == 5, (ch, r)
        bits = 0
        for c, p in enumerate(r):
            if p == '#':
                bits |= 0x80 >> c
        cell[top + i] = bits
    mini[code] = cell


