def table(font, rows):
    out = []
    for code in range(FIRST, LAST + 1):
        out.append(font.get(code, [0] * rows))
    return out


def name(code):
    if code == 0x7f:
        return "DEL"
    if code >= 0x80:
        return ["▸", "·", "›", "◂", "■", "▴", "▾", "‹"][code - 0x80]
    return repr(chr(code))


def emit(f, label, font, rows, title):
    f.write(f"; {title}\n")
    f.write(f"{label}:\n")
    for i, cell in enumerate(table(font, rows)):
        code = FIRST + i
        for k in range(0, len(cell), 8):
            bs = ", ".join(f"0x{b:02x}" for b in cell[k:k + 8])
            note = name(code) if k == 0 else "..."
            f.write(f"        .byte {bs} ; {note}\n")


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, "font.s")
    missing = [chr(c) for c in range(32, 127) if c not in body or c not in mini]
    assert not missing, missing
    with open(out, "w") as f:
        f.write("; =============================================================================\n")
        f.write("; font.s: the StrataOS fonts (GENERATED by os/lib/font/gen_font.py: edit that)\n")
        f.write("; =============================================================================\n")
        f.write(";\n")
        f.write("; Original designs, public domain. One byte per glyph row, bit 7 = leftmost\n")
        f.write("; pixel. Codes 32..135: ASCII 32..126, DEL (blank), then the HUD glyphs\n")
        f.write("; 0x80 ▸ 0x81 · 0x82 › 0x83 ◂ 0x84 ■ 0x85 ▴ 0x86 ▾ 0x87 ‹.\n")
        f.write(";\n")
        f.write("; A font descriptor (what gfx.s text items point at), 5 dwords:\n")
        f.write(";   0 glyph table   8 first code   16 number of codes   24 advance (pixels)\n")
        f.write(";   32 rows per glyph (= bytes per glyph)\n\n")
        f.write(f"FONT_FIRST = {FIRST}                         ; first code in the tables\n")
        f.write(f"FONT_COUNT = {LAST - FIRST + 1}                        ; codes in the tables\n\n")
        f.write("        .data                           ; fonts live in the data Local Store\n")
        f.write("        .align 8                        ; descriptors are dwords\n")
        f.write("font_body:                              ; descriptor of the 8 x 16 body font\n")
        f.write("        .dword glyphs_body              ; its glyph table\n")
        f.write("        .dword FONT_FIRST               ; first code\n")
        f.write("        .dword FONT_COUNT               ; number of codes\n")
        f.write("        .dword 8                        ; advance: 8 pixels\n")
        f.write("        .dword 16                       ; 16 rows per glyph\n")
        f.write("font_mini:                              ; descriptor of the 5 x 7 HUD font\n")
        f.write("        .dword glyphs_mini              ; its glyph table\n")
        f.write("        .dword FONT_FIRST               ; first code\n")
        f.write("        .dword FONT_COUNT               ; number of codes\n")
        f.write("        .dword 6                        ; advance: 6 pixels\n")
        f.write("        .dword 8                        ; 8 rows per glyph\n\n")
        emit(f, "glyphs_body", body, 16, "8 x 16 body font: 16 bytes per glyph (rows 0..15)")
        f.write("\n")
        emit(f, "glyphs_mini", mini, 8, "5 x 7 HUD capitals: 8 bytes per glyph (rows 0..7)")
        f.write("        .text                           ; back to the instruction Local Store\n")
    print("wrote", out)
    if "--ppm" in sys.argv:
        ppm = sys.argv[sys.argv.index("--ppm") + 1]
        preview(ppm)


