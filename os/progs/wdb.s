; =============================================================================
; wdb.s: the store's trees in a window
; =============================================================================
;
;   wdb             (from a shell in a terminal, or the palette: Alt+Space)
;
; A client of the window server that walks the B+trees of the store on the
; disk (doc/strata-fs-proposal.md), page by page: the window shows the
; store's line, where the page at hand is, the page's own line (kind, level,
; cells, fill, the commit that wrote it) and its cells, one a row: a branch's
; keys and the pages they lead to, a leaf's keys and values. It starts at
; the catalog's root: the catalog's records are the trees (namespace and
; name -> root, height), and opening one goes to that tree's root.
;
;   j, Down    the next cell           k, Up      the one before
;   Space      a screen further        b          a screen back
;   Enter, l   open: a branch's cell -> its child page; in the catalog, a
;              record -> that tree's root
;   Backspace, h   back to the page this one was opened from
;   c, f, p    the catalog, the free-space tree, the pending tree
;   q          quit
;
; The disk is read as it was last committed, below the file system, with
; READBLK (os/lib/stview.s; `db` prints the same on a terminal). A window
; client's endpoint register 2 is the window server's, so the endpoint to
; fs moves to register 4 first (the pipe server's: not needed here). The
; text is drawn by the server (wc_text): the program has no band to paint.

C_BG    = 0x10141A                      ; colours: the window,
C_FG    = 0xD8D8D8                      ;   text,
C_DIM   = 0x8090A0                      ;   the lines above the cells,
C_HEAD  = 0xFFB000                      ;   the page's line,
C_SEL   = 0x2A4A6A                      ;   the cell at hand
NSTACK  = 32                            ; pages one can go back through

        .text                           ; instruction Local Store
_start: j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program

        .include "../lib/gfx.s"         ; surfaces (the window's size)
        .include "../lib/sys.s"         ; the program library
        .include "../lib/wsclient.s"    ; the window server's protocol
        .include "../lib/stview.s"      ; the store, read from the disk

        .data                           ; D-LS
        .align 8                        ; dwords
wd_n:     .dword 0                      ; pages on the way here
wd_stk:   .space NSTACK * 16            ; each: the page, the cell that was at hand
wd_sel:   .dword 0                      ; the cell at hand
wd_top:   .dword 0                      ; the first cell shown
wd_rows:  .dword 0                      ; rows of cells the window has
wd_cols:  .dword 0                      ; characters a row holds
wd_cat:   .dword 0                      ; how many of those are the catalog's own (its records open trees)
wd_what:  .dword 0                      ; which tree: 0 catalog, 1 free, 2 pending
wd_title: .ascii "STORE\0\0\0"          ; the window's title
wd_nows:  .ascii "wdb: no window server (run ws first)\n"
wd_nows_e:
wd_nost:  .ascii "wdb: the disk is not a store\n"
wd_nost_e:
wd_help:  .ascii "j/k move  Enter open  Bksp back  c/f/p catalog, free, pending  q quit"
wd_help_e:
wd_t0:    .ascii "catalog"              ; the trees' names
wd_t1:    .ascii "free   "              ; ...
wd_t2:    .ascii "pending"              ; ...
wd_in:    .ascii ": page "              ; ...
wd_in_e:
wd_dep:   .ascii ": "                   ; ...
wd_dep_e:
wd_from:  .ascii " pages down from its root" ; ...
wd_from_e:
wd_tree:  .ascii "tree "                ; ...
wd_tree_e:
        .align 8                        ; ...
wd_ns:    .dword 0                      ; the tree opened from the catalog: its namespace,
wd_nlen:  .dword 0                      ;   its name
wd_name:  .space 40                     ;   ...
wd_bad:   .ascii "this page is not a tree page (or cannot be read)"
wd_bad_e:
wd_empty: .ascii "this tree is empty"   ; ...
wd_empty_e:
        .align 8                        ; ...
        .text                           ; code

main:
        call  sys_init                  ; handles
        cclear c4                       ; the endpoint to fs: out of the window server's way
        cmov  c4, c2                    ; ...
        la    t0, sv_ep                 ; ...
        li    t1, 4                     ; ...
        sd    t1, 0(t0)                 ; ...
        call  sv_init                   ; the store
        bgez  a0, wd_win                ; ...
        la    a0, wd_nost               ; ...
        li    a1, wd_nost_e - wd_nost   ; ...
        j     wd_fail                   ; ...
wd_win:
        la    a0, wd_title              ; our window
        li    a1, 0                     ; ...
        call  wc_open                   ; ...
        bgtz  a0, wd_go                 ; ...
        la    a0, wd_nows               ; no server
        li    a1, wd_nows_e - wd_nows   ; ...
wd_fail:
        call  err_str                   ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...
wd_go:
        li    a0, 0                     ; the catalog first
        call  wd_root                   ; ...
wd_loop:
        call  wd_draw                   ; ...
wd_ev:
        li    a0, 0                     ; an event
        li    a1, 0                     ; ...
        call  wc_event                  ; ...
        bnez  a0, wd_end                ; the window is gone
        la    t0, wc_ev                 ; its kind
        ld    t1, 0(t0)                 ; ...
        li    t2, WE_SIZE               ; a resize: draw at the new size
        beq   t1, t2, wd_loop           ; ...
        li    t2, WE_CLOSE              ; close: end
        beq   t1, t2, wd_end            ; ...
        li    t2, WE_KEY                ; keys
        bne   t1, t2, wd_ev             ; ...
        ld    s1, 8(t0)                 ; s1 = their bytes
        ld    s2, 16(t0)                ; s2 = how many
wd_kl:
        beqz  s2, wd_loop               ; all taken: draw
        andi  t4, s1, 0xff              ; the next one
        srli  s1, s1, 8                 ; ...
        addi  s2, s2, -1                ; ...
        li    t6, 27                    ; an arrow: ESC [ A / B / C / D
        bne   t4, t6, wd_k              ; ...
        li    t6, 2                     ; ...
        bltu  s2, t6, wd_kl             ; ...
        srli  t4, s1, 8                 ; ...
        andi  t4, t4, 0xff              ; ...
        srli  s1, s1, 16                ; ...
        addi  s2, s2, -2                ; ...
        li    t6, 'A'                   ; ...
        beq   t4, t6, wd_up             ; ...
        li    t6, 'B'                   ; ...
        beq   t4, t6, wd_down           ; ...
        li    t6, 'C'                   ; ...
        beq   t4, t6, wd_o              ; ...
        li    t6, 'D'                   ; ...
        beq   t4, t6, wd_b              ; ...
        j     wd_kl                     ; ...
wd_k:
        li    t6, 'q'                   ; ...
        beq   t4, t6, wd_end            ; ...
        li    t6, 'j'                   ; ...
        beq   t4, t6, wd_down           ; ...
        li    t6, 'k'                   ; ...
        beq   t4, t6, wd_up             ; ...
        li    t6, ' '                   ; ...
        beq   t4, t6, wd_pgdn           ; ...
        li    t6, 'b'                   ; ...
        beq   t4, t6, wd_pgup           ; ...
        li    t6, 13                    ; ...
        beq   t4, t6, wd_o              ; ...
        li    t6, 10                    ; ...
        beq   t4, t6, wd_o              ; ...
        li    t6, 'l'                   ; ...
        beq   t4, t6, wd_o              ; ...
        li    t6, 127                   ; ...
        beq   t4, t6, wd_b              ; ...
        li    t6, 8                     ; ...
        beq   t4, t6, wd_b              ; ...
        li    t6, 'h'                   ; ...
        beq   t4, t6, wd_b              ; ...
        li    a0, 0                     ; ...
        li    t6, 'c'                   ; ...
        beq   t4, t6, wd_jump           ; ...
        li    a0, 1                     ; ...
        li    t6, 'f'                   ; ...
        beq   t4, t6, wd_jump           ; ...
        li    a0, 2                     ; ...
        li    t6, 'p'                   ; ...
        beq   t4, t6, wd_jump           ; ...
        j     wd_kl                     ; ...
wd_jump:
        call  wd_root                   ; ...
        j     wd_kl                     ; ...
wd_o:
        call  wd_open                   ; ...
        j     wd_kl                     ; ...
wd_b:
        call  wd_back                   ; ...
        j     wd_kl                     ; ...
wd_down:
        li    a0, 1                     ; ...
        j     wd_mv                     ; ...
wd_up:
        li    a0, -1                    ; ...
        j     wd_mv                     ; ...
wd_pgdn:
        la    t0, wd_rows               ; ...
        ld    a0, 0(t0)                 ; ...
        j     wd_mv                     ; ...
wd_pgup:
        la    t0, wd_rows               ; ...
        ld    a0, 0(t0)                 ; ...
        neg   a0, a0                    ; ...
wd_mv:
        la    t0, wd_sel                ; the cell at hand moves (kept in the page by wd_clamp)
        ld    t1, 0(t0)                 ; ...
        add   t1, t1, a0                ; ...
        sd    t1, 0(t0)                 ; ...
        call  wd_clamp                  ; ...
        j     wd_kl                     ; ...

; wd_clamp() -> a0 = the page at hand (0: not a tree page): the cell at hand
; is one of its cells
wd_clamp:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        call  wd_page                   ; ...
        la    t0, wd_sel                ; ...
        ld    t1, 0(t0)                 ; ...
        bgez  t1, wcl_1                 ; ...
        li    t1, 0                     ; ...
wcl_1:
        beqz  a0, wcl_2                 ; ...
        lhu   t2, 26(a0)                ; ...
        bltu  t1, t2, wcl_2             ; ...
        addi  t1, t2, -1                ; ...
        bgez  t1, wcl_2                 ; ...
        li    t1, 0                     ; ...
wcl_2:
        sd    t1, 0(t0)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; wd_back(): back to the page this one was opened from
wd_back:
        la    t0, wd_n                  ; ...
        ld    t1, 0(t0)                 ; ...
        li    t2, 2                     ; ...
        bltu  t1, t2, wdb_ret           ; ...
        addi  t1, t1, -1                ; ...
        sd    t1, 0(t0)                 ; ...
        la    t2, wd_cat                ; (back among the catalog's pages, maybe)
        ld    t3, 0(t2)                 ; ...
        bleu  t3, t1, wd_bk1            ; ...
        sd    t1, 0(t2)                 ; ...
wd_bk1:
        addi  t1, t1, -1                ; and the cell that was at hand there
        slli  t1, t1, 4                 ; ...
        la    t2, wd_stk                ; ...
        add   t2, t2, t1                ; ...
        ld    t3, 8(t2)                 ; ...
        la    t0, wd_sel                ; ...
        sd    t3, 0(t0)                 ; ...
        la    t0, wd_top                ; ...
        sd    zero, 0(t0)               ; ...
wdb_ret:
        ret                             ; ...

; wd_open(): a branch's cell at hand -> its child page; in the catalog, a
; record -> that tree's root
wd_open:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s3, 8(sp)                 ; ...
        call  wd_clamp                  ; the page at hand
        beqz  a0, wdo_ret               ; ...
        mv    s3, a0                    ; ...
        lhu   t0, 26(s3)                ; ...
        beqz  t0, wdo_ret               ; ...
        la    t0, wd_sel                ; its cell at hand
        ld    a1, 0(t0)                 ; ...
        call  sv_cell                   ; ...
        la    t3, wd_cat                ; t1 = the catalog's pages on the way, t2 = all
        ld    t1, 0(t3)                 ; ...
        la    t2, wd_n                  ; ...
        ld    t2, 0(t2)                 ; ...
        lbu   t0, 24(s3)                ; ...
        li    t4, SV_LEAF               ; ...
        beq   t0, t4, wdo_rec           ; ...
        ld    a0, 8(a0)                 ; a branch: its child
        bne   t1, t2, wdo_push          ; (one more of the catalog's own pages?)
        addi  t1, t1, 1                 ; ...
        sd    t1, 0(t3)                 ; ...
        j     wdo_push                  ; ...
wdo_rec:
        bne   t1, t2, wdo_ret           ; a record: in the catalog's own pages it is a tree
        lhu   t0, 0(a0)                 ; its name: the key after the namespace
        addi  t4, t0, -4                ; ...
        li    t5, 40                    ; ...
        bleu  t4, t5, wdo_n             ; ...
        mv    t4, t5                    ; ...
wdo_n:
        la    t5, wd_nlen               ; ...
        sd    t4, 0(t5)                 ; ...
        lbu   t5, 11(a0)                ; (the namespace: its low byte will do here)
        la    t6, wd_ns                 ; ...
        sd    t5, 0(t6)                 ; ...
        la    t5, wd_name               ; ...
        addi  t6, a0, 12                ; ...
wdo_c:
        beqz  t4, wdo_v                 ; ...
        lbu   a1, 0(t6)                 ; ...
        sb    a1, 0(t5)                 ; ...
        addi  t5, t5, 1                 ; ...
        addi  t6, t6, 1                 ; ...
        addi  t4, t4, -1                ; ...
        j     wdo_c                     ; ...
wdo_v:
        addi  t0, t0, 7                 ; its value: the root
        srli  t0, t0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        add   t0, t0, a0                ; ...
        ld    a0, 8(t0)                 ; ...
        beqz  a0, wdo_ret               ; (an empty tree)
wdo_push:
        la    t0, wd_n                  ; one more page on the way
        ld    t1, 0(t0)                 ; ...
        li    t2, NSTACK                ; ...
        bgeu  t1, t2, wdo_ret           ; ...
        addi  t3, t1, 1                 ; ...
        sd    t3, 0(t0)                 ; ...
        slli  t1, t1, 4                 ; ...
        la    t2, wd_stk                ; ...
        add   t2, t2, t1                ; ...
        sd    a0, 0(t2)                 ; ...
        la    t0, wd_sel                ; (the cell at hand stays with the page left)
        ld    t3, 0(t0)                 ; ...
        sd    t3, -8(t2)                ; ...
        sd    zero, 0(t0)               ; ...
        la    t0, wd_top                ; ...
        sd    zero, 0(t0)               ; ...
wdo_ret:
        ld    s3, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...
wd_end:
        call  wc_close                  ; the window goes
        li    a0, 0                     ; ...
        call  sys_exit                  ; ...

; wd_root(a0 = 0 catalog / 1 free / 2 pending): the walk starts at that tree's root
wd_root:
        la    t0, wd_what               ; ...
        sd    a0, 0(t0)                 ; ...
        seqz  t1, a0                    ; in the catalog: one page of it on the way
        la    t0, wd_cat                ; ...
        sd    t1, 0(t0)                 ; ...
        slli  a0, a0, 4                 ; ...
        la    t0, sv_cat                ; ...
        add   t0, t0, a0                ; ...
        ld    t1, 0(t0)                 ; ...
        la    t0, wd_stk                ; ...
        sd    t1, 0(t0)                 ; ...
        sd    zero, 8(t0)               ; ...
        li    t1, 1                     ; ...
        la    t0, wd_n                  ; ...
        sd    t1, 0(t0)                 ; ...
        la    t0, wd_sel                ; ...
        sd    zero, 0(t0)               ; ...
        la    t0, wd_top                ; ...
        sd    zero, 0(t0)               ; ...
        ret                             ; ...

; wd_page() -> a0 = the page at hand in sv_buf, or 0 when it is not a tree page
wd_page:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        la    t0, wd_n                  ; ...
        ld    t0, 0(t0)                 ; ...
        addi  t0, t0, -1                ; ...
        slli  t0, t0, 4                 ; ...
        la    t1, wd_stk                ; ...
        add   t1, t1, t0                ; ...
        ld    s1, 0(t1)                 ; ...
        li    a0, 0                     ; ...
        beqz  s1, wdp_ret               ; ...
        la    t0, sv_npages             ; ...
        ld    t0, 0(t0)                 ; ...
        bgeu  s1, t0, wdp_ret           ; ...
        mv    a0, s1                    ; ...
        call  sv_page                   ; ...
        beqz  a0, wdp_ret               ; ...
        ld    t0, 8(a0)                 ; a tree page says its own number,
        bne   t0, s1, wdp_no            ; ...
        lbu   t0, 24(a0)                ; and is a branch or a leaf
        addi  t0, t0, -1                ; ...
        li    t1, 2                     ; ...
        bltu  t0, t1, wdp_ret           ; ...
wdp_no:
        li    a0, 0                     ; ...
wdp_ret:
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; wd_row(a0 = row, a1 = text colour, a2 = background or -1): the line built
; (sl_buf) on that row of the window, cut to its width
wd_row:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        mv    a4, a1                    ; ...
        mv    a5, a2                    ; ...
        slli  a1, a0, 4                 ; 16 pixels a row, 4 from the top
        addi  a1, a1, 4                 ; ...
        li    a0, 8                     ; ...
        la    a2, sl_buf                ; ...
        la    t0, sl_len                ; ...
        ld    a3, 0(t0)                 ; ...
        la    t0, wd_cols               ; ...
        ld    t0, 0(t0)                 ; ...
        bleu  a3, t0, wdr_1             ; ...
        mv    a3, t0                    ; ...
wdr_1:
        beqz  a3, wdr_ret               ; ...
        call  wc_text                   ; ...
wdr_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; wd_draw(): the whole window
wd_draw:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        la    t0, wc_surf               ; its size in rows and characters
        ld    a2, S_W(t0)               ; ...
        ld    a3, S_H(t0)               ; ...
        srli  t1, a2, 3                 ; ...
        addi  t1, t1, -2                ; ...
        li    t2, SL_MAX                ; ...
        bleu  t1, t2, wdd_1             ; ...
        mv    t1, t2                    ; ...
wdd_1:
        la    t2, wd_cols               ; ...
        sd    t1, 0(t2)                 ; ...
        srli  t1, a3, 4                 ; four rows above the cells
        addi  t1, t1, -4                ; ...
        bgtz  t1, wdd_2                 ; ...
        li    t1, 1                     ; ...
wdd_2:
        la    t2, wd_rows               ; ...
        sd    t1, 0(t2)                 ; ...
        li    a0, 0                     ; the background
        li    a1, 0                     ; ...
        li    a4, C_BG                  ; ...
        call  wc_fill                   ; ...
        call  sl_store                  ; row 0: the store
        li    a0, 0                     ; ...
        li    a1, C_DIM                 ; ...
        li    a2, -1                    ; ...
        call  wd_row                    ; ...
        call  sl_new                    ; row 1: which tree, and how far down
        la    t0, wd_n                  ; s3 = pages down from the tree's root
        ld    s3, 0(t0)                 ; ...
        addi  s3, s3, -1                ; ...
        la    t0, wd_cat                ; a tree opened from the catalog?
        ld    t0, 0(t0)                 ; ...
        beqz  t0, wdd_sys               ; ...
        addi  t1, s3, 1                 ; ...
        bleu  t1, t0, wdd_sys           ; ...
        sub   s3, s3, t0                ; ...
        la    a0, wd_tree               ; ...
        li    a1, wd_tree_e - wd_tree   ; ...
        call  sl_str                    ; ...
        la    t0, wd_ns                 ; ...
        ld    a0, 0(t0)                 ; ...
        call  sl_dec                    ; ...
        li    a0, '/'                   ; ...
        call  sl_ch                     ; ...
        la    a0, wd_name               ; ...
        la    t0, wd_nlen               ; ...
        ld    a1, 0(t0)                 ; ...
        call  sl_str                    ; ...
        j     wdd_3                     ; ...
wdd_sys:
        la    t0, wd_what               ; ...
        ld    t0, 0(t0)                 ; ...
        slli  t1, t0, 3                 ; (the names are 7 bytes each)
        sub   t1, t1, t0                ; ...
        la    a0, wd_t0                 ; ...
        add   a0, a0, t1                ; ...
        li    a1, 7                     ; ...
        call  sl_str                    ; ...
wdd_3:
        la    a0, wd_dep                ; ...
        li    a1, wd_dep_e - wd_dep     ; ...
        call  sl_str                    ; ...
        mv    a0, s3                    ; ...
        call  sl_dec                    ; ...
        la    a0, wd_from               ; ...
        li    a1, wd_from_e - wd_from   ; ...
        call  sl_str                    ; ...
        li    a0, 1                     ; ...
        li    a1, C_DIM                 ; ...
        li    a2, -1                    ; ...
        call  wd_row                    ; ...
        call  wd_page                   ; row 2: the page's own line
        mv    s1, a0                    ; s1 = the page
        bnez  s1, wdd_pg                ; ...
        call  sl_new                    ; (not a tree page, or an empty tree)
        la    a0, wd_bad                ; ...
        li    a1, wd_bad_e - wd_bad     ; ...
        la    t0, wd_stk                ; ...
        ld    t0, 0(t0)                 ; ...
        bnez  t0, wdd_b                 ; ...
        la    a0, wd_empty              ; ...
        li    a1, wd_empty_e - wd_empty ; ...
wdd_b:
        call  sl_str                    ; ...
        li    a0, 2                     ; ...
        li    a1, C_HEAD                ; ...
        li    a2, -1                    ; ...
        call  wd_row                    ; ...
        j     wdd_help                  ; ...
wdd_pg:
        mv    a0, s1                    ; ...
        call  sl_page                   ; ...
        li    a0, 2                     ; ...
        li    a1, C_HEAD                ; ...
        li    a2, -1                    ; ...
        call  wd_row                    ; ...
        lhu   s2, 26(s1)                ; s2 = its cells
        la    t0, wd_sel                ; the cell at hand: in the page,
        ld    t1, 0(t0)                 ; ...
        bltu  t1, s2, wdd_4             ; ...
        addi  t1, s2, -1                ; ...
        bgez  t1, wdd_4                 ; ...
        li    t1, 0                     ; ...
wdd_4:
        sd    t1, 0(t0)                 ; ...
        la    t0, wd_top                ; and among the rows shown
        ld    t2, 0(t0)                 ; ...
        bgeu  t1, t2, wdd_5             ; ...
        mv    t2, t1                    ; ...
wdd_5:
        la    t3, wd_rows               ; ...
        ld    t3, 0(t3)                 ; ...
        add   t4, t2, t3                ; ...
        bltu  t1, t4, wdd_6             ; ...
        sub   t2, t1, t3                ; ...
        addi  t2, t2, 1                 ; ...
wdd_6:
        sd    t2, 0(t0)                 ; ...
        mv    s3, t2                    ; s3 = the cell of the row
        li    s4, 0                     ; s4 = the row
wdd_c:
        la    t0, wd_rows               ; ...
