; =============================================================================
; wdb.s: the store's trees in a window
; =============================================================================
;
;   wdb             (from a shell in a terminal, or the palette: Alt+Space)
;
; A client of the window server that shows the B+trees of the store on the
; disk (doc/strata-fs-proposal.md). It opens on the list of trees, as `db`
; prints it: the three the meta block names (catalog, free, pending) and
; every tree of the catalog as NAMESPACE/NAME, each with its root page and
; height. Opening one shows the tree page by page: where the page is, the
; page's own line (kind, level, cells, fill, the commit that wrote it) and
; its cells, one a row: a branch's keys and the pages they lead to, a leaf's
; keys and values.
;
;   j, Down    the next row            k, Up      the one before
;   Space      a screen further        b          a screen back
;   Enter, l   open: a tree of the list -> its root page; a branch's cell
;              -> its child page
;   Backspace, h   back: to the page this one was opened from; from a
;              tree's root to the list
;   t          the list of trees       q          quit
;
; The disk is read as it was last committed, below the file system, with
; READBLK (os/lib/stview.s; `db` prints the same on a terminal). A window
; client's endpoint register 2 is the window server's, so the endpoint to
; fs moves to register 4 first (the pipe server's: not needed here). The
; text is drawn by the server (wc_text): the program has no band to paint.

C_BG    = 0x10141A                      ; colours: the window,
C_FG    = 0xD8D8D8                      ;   text,
C_DIM   = 0x8090A0                      ;   the lines above the rows,
C_HEAD  = 0xFFB000                      ;   the page's line,
C_SEL   = 0x2A4A6A                      ;   the row at hand
NSTACK  = 32                            ; pages one can go back through
NTREE   = 48                            ; trees the list holds
T_ROOT  = 0                             ; a tree of the list: its root page,
T_HGT   = 8                             ;   its height,
T_LEN   = 16                            ;   its label's length,
T_LAB   = 24                            ;   the label (40 bytes)
NNS     = 8                             ; namespaces whose names are kept

        .text                           ; instruction Local Store
_start: j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program

        .include "../lib/gfx.s"         ; surfaces (the window's size)
        .include "../lib/sys.s"         ; the program library
        .include "../lib/wsclient.s"    ; the window server's protocol
        .include "../lib/stview.s"      ; the store, read from the disk

        .data                           ; D-LS
        .align 8                        ; dwords
wd_view:  .dword 0                      ; 0: the list of trees; 1: a tree's pages
wd_nt:    .dword 0                      ; trees in the list
wd_cur:   .dword 0                      ; the tree opened
wd_n:     .dword 0                      ; pages on the way from its root to the one shown
wd_stk:   .space NSTACK * 16            ; each: the page, the cell that was at hand
wd_sel:   .dword 0                      ; the row at hand
wd_top:   .dword 0                      ; the first row shown
wd_rows:  .dword 0                      ; rows the window has under the top lines
wd_cols:  .dword 0                      ; characters a row holds
wd_nns:   .dword 0                      ; the namespaces: id, name length, name[32]
wd_ns:    .space NNS * 48               ; ...
wd_te:    .space NTREE * 64             ; the list of trees (64 bytes each)
wd_title: .ascii "STORE\0\0\0"          ; the window's title
wd_nows:  .ascii "wdb: no window server (run ws first)\n"
wd_nows_e:
wd_nost:  .ascii "wdb: the disk is not a store\n"
wd_nost_e:
wd_help:  .ascii "j/k move  Enter open  Bksp back  t trees  q quit"
wd_help_e:
wd_s0:    .ascii "catalog"              ; the three trees the meta block names
wd_s1:    .ascii "free"                 ; ...
wd_s2:    .ascii "pending"              ; ...
wd_lst:   .ascii " trees: Enter opens one" ; ...
wd_lst_e:
wd_rt:    .ascii "root page "           ; ...
wd_rt_e:
wd_ht:    .ascii ", height "            ; ...
wd_ht_e:
wd_dep:   .ascii ": "                   ; ...
wd_dep_e:
wd_from:  .ascii " pages down from its root" ; ...
wd_from_e:
wd_bad:   .ascii "this page is not a tree page (or cannot be read)"
wd_bad_e:
        .align 8                        ; ...
        .text                           ; code

main:
        call  sys_init                  ; handles
        cclear c4                       ; the endpoint to fs: out of the window server's way
        cmov  c4, c2                    ; ...
        la    t0, sv_ep                 ; ...
        li    t1, 4                     ; ...
        sd    t1, 0(t0)                 ; ...
        call  sv_init                   ; the store
        bgez  a0, wd_win                ; ...
        la    a0, wd_nost               ; ...
        li    a1, wd_nost_e - wd_nost   ; ...
        j     wd_fail                   ; ...
wd_win:
        call  wd_build                  ; the list of trees
        la    a0, wd_title              ; our window
        li    a1, 0                     ; ...
        call  wc_open                   ; ...
        bgtz  a0, wd_loop               ; ...
        la    a0, wd_nows               ; no server
        li    a1, wd_nows_e - wd_nows   ; ...
wd_fail:
        call  err_str                   ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...
wd_loop:
        call  wd_draw                   ; ...
wd_ev:
        li    a0, 0                     ; an event
        li    a1, 0                     ; ...
        call  wc_event                  ; ...
        bnez  a0, wd_end                ; the window is gone
        la    t0, wc_ev                 ; its kind
        ld    t1, 0(t0)                 ; ...
        li    t2, WE_SIZE               ; a resize: draw at the new size
        beq   t1, t2, wd_loop           ; ...
        li    t2, WE_CLOSE              ; close: end
        beq   t1, t2, wd_end            ; ...
        li    t2, WE_KEY                ; keys
        bne   t1, t2, wd_ev             ; ...
        ld    s1, 8(t0)                 ; s1 = their bytes
        ld    s2, 16(t0)                ; s2 = how many
wd_kl:
        beqz  s2, wd_loop               ; all taken: draw
        andi  t4, s1, 0xff              ; the next one
        srli  s1, s1, 8                 ; ...
        addi  s2, s2, -1                ; ...
        li    t6, 27                    ; an arrow: ESC [ A / B / C / D
        bne   t4, t6, wd_k              ; ...
        li    t6, 2                     ; ...
        bltu  s2, t6, wd_kl             ; ...
        srli  t4, s1, 8                 ; ...
        andi  t4, t4, 0xff              ; ...
        srli  s1, s1, 16                ; ...
        addi  s2, s2, -2                ; ...
        li    t6, 'A'                   ; ...
        beq   t4, t6, wd_up             ; ...
        li    t6, 'B'                   ; ...
        beq   t4, t6, wd_down           ; ...
        li    t6, 'C'                   ; ...
        beq   t4, t6, wd_o              ; ...
        li    t6, 'D'                   ; ...
        beq   t4, t6, wd_b              ; ...
        j     wd_kl                     ; ...
wd_k:
        li    t6, 'q'                   ; ...
        beq   t4, t6, wd_end            ; ...
        li    t6, 'j'                   ; ...
        beq   t4, t6, wd_down           ; ...
        li    t6, 'k'                   ; ...
        beq   t4, t6, wd_up             ; ...
        li    t6, ' '                   ; ...
        beq   t4, t6, wd_pgdn           ; ...
        li    t6, 'b'                   ; ...
        beq   t4, t6, wd_pgup           ; ...
        li    t6, 13                    ; ...
        beq   t4, t6, wd_o              ; ...
        li    t6, 10                    ; ...
        beq   t4, t6, wd_o              ; ...
        li    t6, 'l'                   ; ...
        beq   t4, t6, wd_o              ; ...
        li    t6, 127                   ; ...
        beq   t4, t6, wd_b              ; ...
        li    t6, 8                     ; ...
        beq   t4, t6, wd_b              ; ...
        li    t6, 'h'                   ; ...
        beq   t4, t6, wd_b              ; ...
        li    t6, 't'                   ; ...
        bne   t4, t6, wd_kl             ; ...
        call  wd_list                   ; ...
        j     wd_kl                     ; ...
wd_o:
        call  wd_open                   ; ...
        j     wd_kl                     ; ...
wd_b:
        call  wd_back                   ; ...
        j     wd_kl                     ; ...
wd_down:
        li    a0, 1                     ; ...
        j     wd_mv                     ; ...
wd_up:
        li    a0, -1                    ; ...
        j     wd_mv                     ; ...
wd_pgdn:
        la    t0, wd_rows               ; ...
        ld    a0, 0(t0)                 ; ...
        j     wd_mv                     ; ...
wd_pgup:
        la    t0, wd_rows               ; ...
        ld    a0, 0(t0)                 ; ...
        neg   a0, a0                    ; ...
wd_mv:
        la    t0, wd_sel                ; the row at hand moves (kept among the rows by wd_clamp)
        ld    t1, 0(t0)                 ; ...
        add   t1, t1, a0                ; ...
        sd    t1, 0(t0)                 ; ...
        call  wd_clamp                  ; ...
        j     wd_kl                     ; ...
wd_end:
        call  wc_close                  ; the window goes
        li    a0, 0                     ; ...
        call  sys_exit                  ; ...

; wd_count() -> a0 = the rows there are: the list's trees, or the cells of
; the page shown (0: not a tree page); a1 = that page
wd_count:
        la    t0, wd_view               ; ...
        ld    t0, 0(t0)                 ; ...
        bnez  t0, wdc_pg                ; ...
        la    t0, wd_nt                 ; ...
        ld    a0, 0(t0)                 ; ...
        ret                             ; ...
wdc_pg:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        call  wd_page                   ; ...
        mv    a1, a0                    ; ...
        li    a0, 0                     ; ...
        beqz  a1, wdc_ret               ; ...
        lhu   a0, 26(a1)                ; ...
wdc_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; wd_clamp(): the row at hand is one of the rows there are
wd_clamp:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        call  wd_count                  ; ...
        la    t0, wd_sel                ; ...
        ld    t1, 0(t0)                 ; ...
        blt   t1, a0, wcl_1             ; ...
        addi  t1, a0, -1                ; ...
wcl_1:
        bgez  t1, wcl_2                 ; ...
        li    t1, 0                     ; ...
wcl_2:
        sd    t1, 0(t0)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; wd_list(): the list of trees again, the tree that was open at hand
wd_list:
        la    t0, wd_view               ; ...
        ld    t1, 0(t0)                 ; ...
        beqz  t1, wdl_ret               ; ...
        sd    zero, 0(t0)               ; ...
        la    t0, wd_cur                ; ...
        ld    t1, 0(t0)                 ; ...
        la    t0, wd_sel                ; ...
        sd    t1, 0(t0)                 ; ...
        la    t0, wd_top                ; ...
        sd    zero, 0(t0)               ; ...
wdl_ret:
        ret                             ; ...

; wd_back(): back to the page this one was opened from; from a tree's root to the list
wd_back:
        la    t0, wd_view               ; ...
        ld    t0, 0(t0)                 ; ...
        beqz  t0, wdl_ret               ; ...
        la    t0, wd_n                  ; ...
        ld    t1, 0(t0)                 ; ...
        li    t2, 2                     ; ...
        bltu  t1, t2, wd_list           ; ...
        addi  t1, t1, -1                ; ...
        sd    t1, 0(t0)                 ; ...
        addi  t1, t1, -1                ; and the cell that was at hand there
        slli  t1, t1, 4                 ; ...
        la    t2, wd_stk                ; ...
        add   t2, t2, t1                ; ...
        ld    t3, 8(t2)                 ; ...
        la    t0, wd_sel                ; ...
        sd    t3, 0(t0)                 ; ...
        la    t0, wd_top                ; ...
        sd    zero, 0(t0)               ; ...
        ret                             ; ...

; wd_open(): a tree of the list -> its root page; a branch's cell -> its child page
wd_open:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s3, 8(sp)                 ; ...
        call  wd_clamp                  ; ...
        la    t0, wd_view               ; ...
        ld    t1, 0(t0)                 ; ...
        bnez  t1, wdo_pg                ; ...
        la    t2, wd_sel                ; a tree: its root (an empty one has none)
        ld    t2, 0(t2)                 ; ...
        slli  t3, t2, 6                 ; ...
        la    t4, wd_te                 ; ...
        add   t3, t3, t4                ; ...
        ld    a0, T_ROOT(t3)            ; ...
        beqz  a0, wdo_ret               ; ...
        li    t1, 1                     ; ...
        sd    t1, 0(t0)                 ; ...
        la    t0, wd_cur                ; ...
        sd    t2, 0(t0)                 ; ...
        la    t0, wd_n                  ; ...
        sd    zero, 0(t0)               ; ...
        j     wdo_push                  ; ...
wdo_pg:
        call  wd_page                   ; a page: a branch's cell at hand
        beqz  a0, wdo_ret               ; ...
        mv    s3, a0                    ; ...
        lhu   t0, 26(s3)                ; ...
        beqz  t0, wdo_ret               ; ...
        lbu   t0, 24(s3)                ; ...
        li    t4, SV_LEAF               ; ...
        beq   t0, t4, wdo_ret           ; (a record opens nothing)
        la    t0, wd_sel                ; ...
        ld    a1, 0(t0)                 ; ...
        call  sv_cell                   ; ...
        ld    a0, 8(a0)                 ; its child
wdo_push:
        la    t0, wd_n                  ; one more page on the way
        ld    t1, 0(t0)                 ; ...
        li    t2, NSTACK                ; ...
        bgeu  t1, t2, wdo_ret           ; ...
        addi  t3, t1, 1                 ; ...
        sd    t3, 0(t0)                 ; ...
        slli  t1, t1, 4                 ; ...
        la    t2, wd_stk                ; ...
        add   t2, t2, t1                ; ...
        sd    a0, 0(t2)                 ; ...
        la    t0, wd_sel                ; (the cell at hand stays with the page left)
        ld    t3, 0(t0)                 ; ...
        beqz  t1, wdo_1                 ; ...
        sd    t3, -8(t2)                ; ...
wdo_1:
        sd    zero, 0(t0)               ; ...
        la    t0, wd_top                ; ...
        sd    zero, 0(t0)               ; ...
wdo_ret:
        ld    s3, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; wd_add(a2 = root and height): the line built is one more tree's label
wd_add:
        la    t0, wd_nt                 ; ...
        ld    t1, 0(t0)                 ; ...
        li    t2, NTREE                 ; ...
        bgeu  t1, t2, wda_ret           ; ...
        addi  t2, t1, 1                 ; ...
        sd    t2, 0(t0)                 ; ...
        slli  t1, t1, 6                 ; ...
        la    t0, wd_te                 ; ...
        add   t0, t0, t1                ; ...
        ld    t1, 0(a2)                 ; ...
        sd    t1, T_ROOT(t0)            ; ...
        ld    t1, 8(a2)                 ; ...
        sd    t1, T_HGT(t0)             ; ...
        la    t1, sl_len                ; ...
        ld    t1, 0(t1)                 ; ...
        li    t2, 40                    ; ...
        bleu  t1, t2, wda_1             ; ...
        mv    t1, t2                    ; ...
wda_1:
        sd    t1, T_LEN(t0)             ; ...
        la    t2, sl_buf                ; ...
wda_c:
        beqz  t1, wda_ret               ; ...
        lbu   t3, 0(t2)                 ; ...
        sb    t3, T_LAB(t0)             ; ...
        addi  t0, t0, 1                 ; ...
        addi  t2, t2, 1                 ; ...
        addi  t1, t1, -1                ; ...
        j     wda_c                     ; ...
wda_ret:
        ret                             ; ...

; wd_sys(a0 = name, a1 = its length, a2 = root and height): one of the three
; trees the meta block names joins the list
wd_sys:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        sd    a2, 24(sp)                ; ...
        call  sl_new                    ; ...
        ld    a0, 8(sp)                 ; ...
        ld    a1, 16(sp)                ; ...
        call  sl_str                    ; ...
        ld    a2, 24(sp)                ; ...
        call  wd_add                    ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; wd_nsof(a0 = a catalog record) -> a0 = its namespace: the key's first 4 bytes, big-endian
wd_nsof:
        lbu   t0, 8(a0)                 ; ...
        slli  t0, t0, 8                 ; ...
        lbu   t1, 9(a0)                 ; ...
        or    t0, t0, t1                ; ...
        slli  t0, t0, 8                 ; ...
        lbu   t1, 10(a0)                ; ...
        or    t0, t0, t1                ; ...
        slli  t0, t0, 8                 ; ...
        lbu   t1, 11(a0)                ; ...
        or    a0, t0, t1                ; ...
        ret                             ; ...

; wd_val(a0 = a record) -> a0 = its value
wd_val:
        lhu   t0, 0(a0)                 ; ...
        addi  t0, t0, 7                 ; ...
        srli  t0, t0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        add   a0, a0, t0                ; ...
        addi  a0, a0, 8                 ; ...
        ret                             ; ...

; wd_build(): the list of trees: the three the meta block names, then every
; tree of the catalog, labelled NAMESPACE/NAME (the namespace by its name,
; from the tree "ns" of namespace 0)
wd_build:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        la    a0, wd_s0                 ; ...
        li    a1, 7                     ; ...
        la    a2, sv_cat                ; ...
        call  wd_sys                    ; ...
        la    a0, wd_s1                 ; ...
        li    a1, 4                     ; ...
        la    a2, sv_fre                ; ...
        call  wd_sys                    ; ...
        la    a0, wd_s2                 ; ...
        li    a1, 7                     ; ...
        la    a2, sv_pend               ; ...
        call  wd_sys                    ; ...
        li    s3, 0                     ; first the namespaces' names (s3 = 0), then the trees (1)
wdb_pass:
        la    t0, sv_cat                ; ...
        ld    a0, 0(t0)                 ; ...
        ld    a1, 8(t0)                 ; ...
        call  sv_first                  ; ...
wdb_l:
        call  sv_next                   ; ...
        beqz  a0, wdb_end               ; ...
        mv    s1, a0                    ; s1 = the catalog's record
        bnez  s3, wdb_tree              ; ...
        call  wd_nsof                   ; the tree "ns" of namespace 0?
        bnez  a0, wdb_l                 ; ...
        lhu   t0, 0(s1)                 ; ...
        li    t1, 6                     ; ...
        bne   t0, t1, wdb_l             ; ...
        lbu   t0, 12(s1)                ; ...
        li    t1, 'n'                   ; ...
        bne   t0, t1, wdb_l             ; ...
        lbu   t0, 13(s1)                ; ...
        li    t1, 's'                   ; ...
        bne   t0, t1, wdb_l             ; ...
        mv    a0, s1                    ; its records: name -> id
        call  wd_val                    ; ...
        ld    a1, 8(a0)                 ; ...
        ld    a0, 0(a0)                 ; ...
        call  sv_first                  ; ...
wdb_n:
        call  sv_next                   ; ...
        beqz  a0, wdb_end               ; ...
        mv    s1, a0                    ; ...
        la    t0, wd_nns                ; ...
        ld    t1, 0(t0)                 ; ...
        li    t2, NNS                   ; ...
        bgeu  t1, t2, wdb_end           ; ...
        lhu   t3, 0(s1)                 ; (a name of up to 32 bytes)
        li    t2, 32                    ; ...
        bgtu  t3, t2, wdb_n             ; ...
        addi  t2, t1, 1                 ; ...
        sd    t2, 0(t0)                 ; ...
        li    t2, 48                    ; ...
        mul   t1, t1, t2                ; ...
        la    s2, wd_ns                 ; ...
        add   s2, s2, t1                ; ...
        sd    t3, 8(s2)                 ; ...
        mv    a0, s1                    ; ...
        call  wd_val                    ; ...
        ld    t0, 0(a0)                 ; ...
        sd    t0, 0(s2)                 ; ...
        lhu   t3, 0(s1)                 ; ...
        li    t0, 0                     ; ...
wdb_nc:
        bgeu  t0, t3, wdb_n             ; ...
        add   t1, s1, t0                ; ...
        lbu   t1, 8(t1)                 ; ...
        add   t2, s2, t0                ; ...
        sb    t1, 16(t2)                ; ...
        addi  t0, t0, 1                 ; ...
        j     wdb_nc                    ; ...
wdb_tree:
        call  sl_new                    ; a tree: its namespace's name (or number), "/", its name
        mv    a0, s1                    ; ...
        call  wd_nsof                   ; ...
        la    t0, wd_ns                 ; ...
        la    t1, wd_nns                ; ...
        ld    t1, 0(t1)                 ; ...
wdb_f:
        beqz  t1, wdb_num               ; ...
        ld    t2, 0(t0)                 ; ...
        beq   t2, a0, wdb_nm            ; ...
        addi  t0, t0, 48                ; ...
        addi  t1, t1, -1                ; ...
        j     wdb_f                     ; ...
wdb_num:
        call  sl_dec                    ; ...
        j     wdb_sl                    ; ...
wdb_nm:
        addi  a0, t0, 16                ; ...
        ld    a1, 8(t0)                 ; ...
        call  sl_str                    ; ...
wdb_sl:
        li    a0, '/'                   ; ...
        call  sl_ch                     ; ...
        addi  a0, s1, 12                ; ...
        lhu   a1, 0(s1)                 ; ...
        addi  a1, a1, -4                ; ...
        call  sl_str                    ; ...
        mv    a0, s1                    ; ...
        call  wd_val                    ; ...
        mv    a2, a0                    ; ...
        call  wd_add                    ; ...
        j     wdb_l                     ; ...
wdb_end:
        addi  s3, s3, 1                 ; ...
        li    t0, 2                     ; ...
        bne   s3, t0, wdb_pass          ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; wd_page() -> a0 = the page shown, in sv_buf, or 0 when it is not a tree page
wd_page:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        la    t0, wd_n                  ; ...
        ld    t0, 0(t0)                 ; ...
        addi  t0, t0, -1                ; ...
        slli  t0, t0, 4                 ; ...
        la    t1, wd_stk                ; ...
        add   t1, t1, t0                ; ...
        ld    s1, 0(t1)                 ; ...
        li    a0, 0                     ; ...
        beqz  s1, wdp_ret               ; ...
        la    t0, sv_npages             ; ...
        ld    t0, 0(t0)                 ; ...
        bgeu  s1, t0, wdp_ret           ; ...
        mv    a0, s1                    ; ...
        call  sv_page                   ; ...
        beqz  a0, wdp_ret               ; ...
        ld    t0, 8(a0)                 ; a tree page says its own number,
        bne   t0, s1, wdp_no            ; ...
        lbu   t0, 24(a0)                ; and is a branch or a leaf
        addi  t0, t0, -1                ; ...
        li    t1, 2                     ; ...
        bltu  t0, t1, wdp_ret           ; ...
wdp_no:
        li    a0, 0                     ; ...
wdp_ret:
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; wd_row(a0 = row, a1 = text colour, a2 = background or -1): the line built
; (sl_buf) on that row of the window, cut to its width
wd_row:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        mv    a4, a1                    ; ...
        mv    a5, a2                    ; ...
        slli  a1, a0, 4                 ; 16 pixels a row, 4 from the top
        addi  a1, a1, 4                 ; ...
        li    a0, 8                     ; ...
        la    a2, sl_buf                ; ...
        la    t0, sl_len                ; ...
        ld    a3, 0(t0)                 ; ...
        la    t0, wd_cols               ; ...
        ld    t0, 0(t0)                 ; ...
        bleu  a3, t0, wdr_1             ; ...
        mv    a3, t0                    ; ...
wdr_1:
        beqz  a3, wdr_ret               ; ...
        call  wc_text                   ; ...
wdr_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; wd_label(): the opened tree's label -> the line. wd_lab: of the tree t0.
wd_label:
        la    t0, wd_cur                ; ...
        ld    t0, 0(t0)                 ; ...
wd_lab:
        slli  t0, t0, 6                 ; ...
        la    t1, wd_te                 ; ...
        add   t0, t0, t1                ; ...
        addi  a0, t0, T_LAB             ; ...
        ld    a1, T_LEN(t0)             ; ...
        j     sl_str                    ; ...

; wd_draw(): the whole window
wd_draw:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        la    t0, wc_surf               ; its size in rows and characters
        ld    a2, S_W(t0)               ; ...
        ld    a3, S_H(t0)               ; ...
        srli  t1, a2, 3                 ; ...
        addi  t1, t1, -2                ; ...
        li    t2, SL_MAX                ; ...
        bleu  t1, t2, wdd_1             ; ...
        mv    t1, t2                    ; ...
wdd_1:
        la    t2, wd_cols               ; ...
        sd    t1, 0(t2)                 ; ...
        srli  t1, a3, 4                 ; three lines above the rows, one under them
        addi  t1, t1, -4                ; ...
        bgtz  t1, wdd_2                 ; ...
        li    t1, 1                     ; ...
wdd_2:
        la    t2, wd_rows               ; ...
        sd    t1, 0(t2)                 ; ...
        li    a0, 0                     ; the background
        li    a1, 0                     ; ...
        li    a4, C_BG                  ; ...
        call  wc_fill                   ; ...
        call  sl_store                  ; line 0: the store
        li    a0, 0                     ; ...
        li    a1, C_DIM                 ; ...
        li    a2, -1                    ; ...
        call  wd_row                    ; ...
        call  wd_clamp                  ; the row at hand: among the rows,
        call  wd_count                  ; ...
        mv    s2, a0                    ; s2 = the rows there are
        mv    s1, a1                    ; s1 = the page shown (a tree's pages)
        la    t0, wd_sel                ; and among those shown
        ld    t1, 0(t0)                 ; ...
        la    t0, wd_top                ; ...
        ld    t2, 0(t0)                 ; ...
        bgeu  t1, t2, wdd_5             ; ...
        mv    t2, t1                    ; ...
wdd_5:
        la    t3, wd_rows               ; ...
        ld    t3, 0(t3)                 ; ...
        add   t4, t2, t3                ; ...
        bltu  t1, t4, wdd_6             ; ...
        sub   t2, t1, t3                ; ...
        addi  t2, t2, 1                 ; ...
wdd_6:
        sd    t2, 0(t0)                 ; ...
        call  sl_new                    ; lines 1 and 2
        la    t0, wd_view               ; ...
        ld    t0, 0(t0)                 ; ...
        bnez  t0, wdd_tree              ; ...
        la    t0, wd_nt                 ; the list: how many trees
        ld    a0, 0(t0)                 ; ...
        call  sl_dec                    ; ...
        la    a0, wd_lst                ; ...
        li    a1, wd_lst_e - wd_lst     ; ...
        call  sl_str                    ; ...
        li    a0, 2                     ; ...
        li    a1, C_HEAD                ; ...
        li    a2, -1                    ; ...
        call  wd_row                    ; ...
        j     wdd_rows                  ; ...
wdd_tree:
        call  wd_label                  ; a tree: its label, how far down this page is
        la    a0, wd_dep                ; ...
        li    a1, wd_dep_e - wd_dep     ; ...
        call  sl_str                    ; ...
        la    t0, wd_n                  ; ...
        ld    a0, 0(t0)                 ; ...
        addi  a0, a0, -1                ; ...
        call  sl_dec                    ; ...
        la    a0, wd_from               ; ...
        li    a1, wd_from_e - wd_from   ; ...
        call  sl_str                    ; ...
        li    a0, 1                     ; ...
        li    a1, C_DIM                 ; ...
        li    a2, -1                    ; ...
        call  wd_row                    ; ...
        bnez  s1, wdd_pg                ; the page's own line
        call  sl_new                    ; (not a tree page)
        la    a0, wd_bad                ; ...
        li    a1, wd_bad_e - wd_bad     ; ...
        call  sl_str                    ; ...
        j     wdd_pl                    ; ...
wdd_pg:
        mv    a0, s1                    ; ...
        call  sl_page                   ; ...
wdd_pl:
        li    a0, 2                     ; ...
        li    a1, C_HEAD                ; ...
        li    a2, -1                    ; ...
        call  wd_row                    ; ...
wdd_rows:
        la    t0, wd_top                ; ...
        ld    s3, 0(t0)                 ; s3 = the row's tree or cell
        li    s4, 0                     ; s4 = the row
wdd_c:
        la    t0, wd_rows               ; ...
        ld    t0, 0(t0)                 ; ...
        bgeu  s4, t0, wdd_help          ; ...
        bgeu  s3, s2, wdd_help          ; ...
        la    t0, wd_view               ; ...
        ld    t0, 0(t0)                 ; ...
        bnez  t0, wdd_cell              ; ...
        call  sl_new                    ; a tree: its label, padded; its root and height
        mv    t0, s3                    ; ...
        call  wd_lab                    ; ...
wdd_pad:
        la    t0, sl_len                ; ...
        ld    t0, 0(t0)                 ; ...
        li    t1, 20                    ; ...
        bgeu  t0, t1, wdd_rt            ; ...
        li    a0, ' '                   ; ...
        call  sl_ch                     ; ...
        j     wdd_pad                   ; ...
wdd_rt:
        la    a0, wd_rt                 ; ...
        li    a1, wd_rt_e - wd_rt       ; ...
        call  sl_str                    ; ...
        slli  t0, s3, 6                 ; ...
        la    t1, wd_te                 ; ...
        add   t0, t0, t1                ; ...
        ld    a0, T_ROOT(t0)            ; ...
        call  sl_dec                    ; ...
        la    a0, wd_ht                 ; ...
        li    a1, wd_ht_e - wd_ht       ; ...
        call  sl_str                    ; ...
        slli  t0, s3, 6                 ; ...
        la    t1, wd_te                 ; ...
        add   t0, t0, t1                ; ...
        ld    a0, T_HGT(t0)             ; ...
        call  sl_dec                    ; ...
        j     wdd_put                   ; ...
wdd_cell:
        mv    a0, s1                    ; a cell of the page
        mv    a1, s3                    ; ...
        call  sl_cellline               ; ...
wdd_put:
        addi  a0, s4, 3                 ; ...
        li    a1, C_FG                  ; ...
        li    a2, -1                    ; ...
        la    t0, wd_sel                ; ...
        ld    t0, 0(t0)                 ; ...
        bne   t0, s3, wdd_7             ; ...
        li    a2, C_SEL                 ; ...
wdd_7:
        call  wd_row                    ; ...
        addi  s3, s3, 1                 ; ...
        addi  s4, s4, 1                 ; ...
        j     wdd_c                     ; ...
wdd_help:
        call  sl_new                    ; the last line: the keys
        la    a0, wd_help               ; ...
        li    a1, wd_help_e - wd_help   ; ...
        call  sl_str                    ; ...
        la    t0, wd_rows               ; ...
        ld    a0, 0(t0)                 ; ...
        addi  a0, a0, 3                 ; ...
        li    a1, C_DIM                 ; ...
        li    a2, -1                    ; ...
        call  wd_row                    ; ...
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 40                ; ...
        ret                             ; ...
