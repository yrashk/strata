; ev_handle(): the event in wc_ev
ev_handle:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = key bytes
        sd    s1, 16(sp)                ; s1 = how many
        la    t0, wc_ev                 ; its kind
        ld    t1, 0(t0)                 ; ...
        li    t2, WE_SIZE               ; a resize (already applied to wc_surf)
        bne   t1, t2, ev_1              ; ...
        call  geom                      ; ...
        call  clamp_view                ; ...
        j     ev_r                      ; ...
ev_1:   li    t2, WE_CLOSE              ; close: end
        bne   t1, t2, ev_2              ; ...
        li    t2, 1                     ; ...
        sd    t2, g_quit - g(gp)        ; ...
        j     ev_r                      ; ...
ev_2:   li    t2, WE_BLUR               ; the focus went: wait
        bne   t1, t2, ev_3              ; ...
        li    t2, 1                     ; ...
        sd    t2, g_paused - g(gp)      ; ...
        j     ev_r                      ; ...
ev_3:   li    t2, WE_FOCUS              ; ... and came back
        bne   t1, t2, ev_4              ; ...
        ld    t2, g_demo - g(gp)        ; (a demo that is over stays still)
        bnez  t2, ev_r                  ; ...
        sd    zero, g_paused - g(gp)    ; ...
        j     ev_r                      ; ...
ev_4:   ld    t2, g_demo - g(gp)        ; (no pointer while the demo plays)
        bnez  t2, ev_5                  ; ...
        li    t2, WE_PTR                ; the pointer
        bne   t1, t2, ev_w              ; ...
        ld    a0, 8(t0)                 ; ...
        call  pointer                   ; ...
        j     ev_r                      ; ...
ev_w:   li    t2, WE_WHEEL              ; the wheel scrolls
        bne   t1, t2, ev_5              ; ...
        ld    t3, 8(t0)                 ; ...
        slli  t4, t3, 16                ; s8 y (> 0: away from the user: up)
        srai  t4, t4, 56                ; ...
        slli  t5, t3, 8                 ; s8 x (> 0: right)
        srai  t5, t5, 56                ; ...
        li    t6, 3                     ; three cells a notch
        mul   a0, t5, t6                ; ...
        mul   a1, t4, t6                ; ...
        neg   a1, a1                    ; ...
        call  scroll                    ; ...
        j     ev_r                      ; ...
ev_5:   li    t2, WE_KEY                ; keys
        bne   t1, t2, ev_r              ; ...
        ld    t2, g_demo - g(gp)        ; (not while the demo plays, but q)
        beqz  t2, ev_k0                 ; ...
        ld    t3, 8(t0)                 ; ...
        andi  t3, t3, 0xff              ; ...
        li    t2, 'q'                   ; ...
        bne   t3, t2, ev_r              ; ...
ev_k0:  la    t0, wc_ev                 ; ...
        ld    s0, 8(t0)                 ; ...
        ld    s1, 16(t0)                ; ...
ev_k:   beqz  s1, ev_r                  ; ...
        andi  a0, s0, 0xff              ; ...
        call  key                       ; ...
        srli  s0, s0, 8                 ; ...
        addi  s1, s1, -1                ; ...
        j     ev_k                      ; ...
ev_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; pointer(a0 = the event's value: u16 x, u16 y, u8 buttons, ...)
pointer:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = x
        sd    s1, 16(sp)                ; s1 = y
        sd    s2, 24(sp)                ; s2 = the buttons now
        sd    s3, 32(sp)                ; s3 = the buttons before
        li    t0, 0xffff                ; ...
        and   s0, a0, t0                ; ...
        srli  s1, a0, 16                ; ...
        and   s1, s1, t0                ; ...
        srli  s2, a0, 32                ; ...
        andi  s2, s2, 0xff              ; ...
        ld    s3, g_btn - g(gp)         ; ...
        sd    s2, g_btn - g(gp)         ; ...
        sd    s0, g_ptrx - g(gp)        ; the tooltip of what it is over (none while
        li    a0, -1                    ;   a button is held)
        bnez  s2, po_tp                 ; ...
        mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        call  tip_at                    ; ...
po_tp:  call  tip_set                   ; ...
        sd    zero, g_paused - g(gp)    ; (a press wakes a program that stands still)
        andi  t0, s2, 2                 ; the right button: it drags the map
        beqz  t0, po_nr                 ; ...
        andi  t1, s3, 2                 ; ...
        bnez  t1, po_pan                ; ...
        li    t0, 1                     ; pressed: from here
        sd    t0, g_pan - g(gp)         ; ...
        sd    s0, g_panx - g(gp)        ; ...
        sd    s1, g_pany - g(gp)        ; ...
        ld    t0, g_ox - g(gp)          ; ...
        sd    t0, g_pox - g(gp)         ; ...
        ld    t0, g_oy - g(gp)          ; ...
        sd    t0, g_poy - g(gp)         ; ...
        j     po_r                      ; ...
po_pan: ld    t0, g_pan - g(gp)         ; held: the map follows it, by whole cells
        beqz  t0, po_r                  ; ...
        ld    t2, g_cp - g(gp)          ; ...
        ld    t0, g_panx - g(gp)        ; ...
        sub   t0, t0, s0                ; ...
        div   t0, t0, t2                ; ...
        ld    a0, g_pox - g(gp)         ; ...
        add   a0, a0, t0                ; ...
        ld    t0, g_pany - g(gp)        ; ...
        sub   t0, t0, s1                ; ...
        div   t0, t0, t2                ; ...
        ld    a1, g_poy - g(gp)         ; ...
        add   a1, a1, t0                ; ...
        call  view_at                   ; ...
        j     po_r                      ; ...
po_nr:  sd    zero, g_pan - g(gp)       ; (released)
        andi  t0, s2, 1                 ; the left button
        bnez  t0, po_l                  ; ...
        li    t0, -1                    ; released: the drag is over
        sd    t0, g_lastx - g(gp)       ; ...
        j     po_r                      ; ...
po_l:   andi  t1, s3, 1                 ; held before: a drag
        bnez  t1, po_drag               ; ...
        ld    t0, g_h - g(gp)           ; pressed: the bar?
        addi  t0, t0, -BARH             ; ...
        blt   s1, t0, po_1              ; ...
        addi  t0, s0, -SPD_X            ; ... its speeds
        li    t1, SPD_DX                ; ...
        bltz  t0, po_r                  ; ...
        divu  a0, t0, t1                ; ...
        li    t1, 4                     ; ...
        bgeu  a0, t1, po_r              ; ...
        call  set_speed                 ; ...
        li    a0, SN_CLICK              ; ...
        call  snd_play                  ; ...
        j     po_r                      ; ...
po_1:   li    t0, TOOLW                 ; the tool column?
        bge   s0, t0, po_v              ; ...
        mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        call  tool_hit                  ; ...
        bltz  a0, po_r                  ; ...
        li    t0, NTOOL                 ; the zoom's buttons
        blt   a0, t0, po_tl             ; ...
        addi  a0, a0, -B_ZIN            ; (in: +1, out: -1)
        slli  a0, a0, 1                 ; ...
        li    t0, 1                     ; ...
        sub   a0, t0, a0                ; ...
        call  zoom                      ; ...
        li    a0, SN_CLICK              ; ...
        call  snd_play                  ; ...
        j     po_r                      ; ...
po_tl:  call  set_tool                  ; ...
        li    a0, SN_CLICK              ; ...
        call  snd_play                  ; ...
        j     po_r                      ; ...
po_v:   call  cur_off                   ; the map: the keyboard's cursor goes
        mv    a0, s0                    ; the cell
        mv    a1, s1                    ; ...
        call  cell_at                   ; ...
        bltz  a0, po_r                  ; ...
        sd    a0, g_lastx - g(gp)       ; ...
        sd    a1, g_lasty - g(gp)       ; ...
        li    a2, -1                    ; (no direction)
        call  use_tool                  ; ...
        j     po_r                      ; ...
po_drag:
        ld    t0, g_lastx - g(gp)       ; a drag that began on the map
        bltz  t0, po_r                  ; ...
        ld    t0, g_tool - g(gp)        ; (asking, zones and plants are not dragged)
        li    t1, TL_QUERY              ; ...
        bgeu  t0, t1, po_r              ; ...
        mv    a0, s0                    ; the cell under it (in the view)
        mv    a1, s1                    ; ...
        call  cell_near                 ; ...
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
po_dl:  ld    t0, g_lastx - g(gp)       ; step there a cell at a time, across first
        ld    t1, g_lasty - g(gp)       ; ...
        li    a2, 0                     ; (east-west)
        beq   t0, s0, po_dy             ; ...
        addi  t0, t0, 1                 ; ...
        blt   t0, s0, po_ds             ; (it was left of it)
        beq   t0, s0, po_ds             ; ...
        addi  t0, t0, -2                ; (right of it)
        j     po_ds                     ; ...
po_dy:  beq   t1, s1, po_r              ; (there)
        li    a2, 1                     ; (north-south)
        addi  t1, t1, 1                 ; ...
        ble   t1, s1, po_ds             ; (it was above it)
        addi  t1, t1, -2                ; (below it)
po_ds:  sd    t0, g_lastx - g(gp)       ; ...
        sd    t1, g_lasty - g(gp)       ; ...
        mv    a0, t0                    ; ...
        mv    a1, t1                    ; ...
        call  use_tool                  ; ...
        j     po_dl                     ; ...
po_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        addi  sp, sp, 40                ; pop the frame
        ret                             ; done

; cell_at(a0 = x, a1 = y in the window) -> a0, a1 = the map's cell there, or
; a0 < 0 if it is not on the map's view
cell_at:
        ld    t0, g_px - g(gp)          ; ...
        sub   a0, a0, t0                ; ...
        bltz  a0, ca_no                 ; ...
        ld    t0, g_py - g(gp)          ; ...
        sub   a1, a1, t0                ; ...
        bltz  a1, ca_no                 ; ...
        ld    t0, g_cp - g(gp)          ; ...
        divu  a0, a0, t0                ; ...
        divu  a1, a1, t0                ; ...
        ld    t1, g_vw - g(gp)          ; ...
        bgeu  a0, t1, ca_no             ; ...
        ld    t1, g_vh - g(gp)          ; ...
        bgeu  a1, t1, ca_no             ; ...
        ld    t0, g_ox - g(gp)          ; ...
        add   a0, a0, t0                ; ...
        ld    t0, g_oy - g(gp)          ; ...
        add   a1, a1, t0                ; ...
        ret                             ; ...
ca_no:  li    a0, -1                    ; ...
        ret                             ; done

; cell_near(a0 = x, a1 = y in the window) -> a0, a1 = the map's cell there,
; or the nearest one in the view
cell_near:
        ld    t0, g_px - g(gp)          ; ...
        sub   a0, a0, t0                ; ...
        bgez  a0, cn_0                  ; ...
        li    a0, 0                     ; ...
cn_0:   ld    t0, g_py - g(gp)          ; ...
        sub   a1, a1, t0                ; ...
        bgez  a1, cn_1                  ; ...
        li    a1, 0                     ; ...
cn_1:   ld    t0, g_cp - g(gp)          ; ...
        divu  a0, a0, t0                ; ...
        divu  a1, a1, t0                ; ...
        ld    t1, g_vw - g(gp)          ; ...
        bltu  a0, t1, cn_2              ; ...
        addi  a0, t1, -1                ; ...
cn_2:   ld    t1, g_vh - g(gp)          ; ...
        bltu  a1, t1, cn_3              ; ...
        addi  a1, t1, -1                ; ...
cn_3:   ld    t0, g_ox - g(gp)          ; ...
        add   a0, a0, t0                ; ...
        ld    t0, g_oy - g(gp)          ; ...
        add   a1, a1, t0                ; ...
        ret                             ; done

; cur_off(): the keyboard's cursor is not shown (the pointer is used)
cur_off:
        ld    t0, g_curon - g(gp)       ; ...
        beqz  t0, co_r                  ; ...
        sd    zero, g_curon - g(gp)     ; ...
        sd    zero, g_pen - g(gp)       ; (and its pen is up)
        ld    a0, g_curx - g(gp)        ; its cell is drawn again
        ld    a1, g_cury - g(gp)        ; ...
        j     dirty_cell                ; ...
co_r:   ret                             ; done

; key(a0 = a byte from the keyboard): arrows come as ESC [ A..D; capitals
; count as small letters
key:    ld    t0, g_esc - g(gp)         ; in a sequence?
        beqz  t0, ke_0                  ; ...
        li    t1, 1                     ; ...
        bne   t0, t1, ke_2              ; ...
        sd    zero, g_esc - g(gp)       ; after ESC: [ goes on, anything else is a key
        li    t1, '['                   ; ...
        bne   a0, t1, ke_0              ; ...
        li    t1, 2                     ; ...
        sd    t1, g_esc - g(gp)         ; ...
        ret                             ; ...
ke_2:   li    t1, '@'                   ; after ESC [: parameters, then the final byte
        bltu  a0, t1, ke_r              ; ...
        sd    zero, g_esc - g(gp)       ; ...
        addi  t0, a0, -'A'              ; A B C D: up, down, right, left
        li    t1, 4                     ; ...
        bgeu  t0, t1, ke_r              ; ...
        la    t1, k_arrow               ; ...
        add   t0, t0, t1                ; ...
        lbu   a0, 0(t0)                 ; ...
        j     do_key                    ; ...
ke_0:   li    t1, 0x1b                  ; ESC starts a sequence
        bne   a0, t1, ke_1              ; ...
        li    t1, 1                     ; ...
        sd    t1, g_esc - g(gp)         ; ...
        ret                             ; ...
ke_1:   li    t1, 'A'                   ; capitals count as small letters
        bltu  a0, t1, do_key            ; ...
        li    t1, 'Z'                   ; ...
        bgtu  a0, t1, do_key            ; ...
        ori   a0, a0, 0x20              ; ...
        j     do_key                    ; ...
ke_r:   ret                             ; done

; do_key(a0 = key: K_UP .. K_RIGHT, or a character)
do_key: addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the key
        mv    s0, a0                    ; ...
        li    t0, K_RIGHT               ; the arrows: the cursor
        bgtu  s0, t0, dk_c              ; ...
        beqz  s0, dk_r                  ; ...
        ld    t0, g_curon - g(gp)       ; (a cursor not shown is shown first, where it is)
        bnez  t0, dk_a1                 ; ...
        li    t0, 1                     ; ...
        sd    t0, g_curon - g(gp)       ; ...
        call  cur_in                    ; ...
        j     dk_dr                     ; ...
dk_a1:  ld    a0, g_curx - g(gp)        ; the cell it leaves is drawn again
        ld    a1, g_cury - g(gp)        ; ...
        call  dirty_cell                ; ...
        la    t0, k_dx - 1              ; where it goes
        add   t0, t0, s0                ; ...
        lb    t1, 0(t0)                 ; ...
        lb    t2, k_dy - k_dx(t0)       ; ...
        ld    a0, g_curx - g(gp)        ; ...
        add   a0, a0, t1                ; ...
        ld    a1, g_cury - g(gp)        ; ...
        add   a1, a1, t2                ; ...
        li    t3, MAPN                  ; (on the map)
        bgeu  a0, t3, dk_dr             ; ...
        bgeu  a1, t3, dk_dr             ; ...
        sd    a0, g_curx - g(gp)        ; ...
        sd    a1, g_cury - g(gp)        ; ...
        ld    t0, g_pen - g(gp)         ; the pen down: the tool is used there
        beqz  t0, dk_dr                 ; ...
        li    a2, 0                     ; (the direction: east-west, or north-south)
        li    t0, K_LEFT                ; ...
        bgeu  s0, t0, dk_u              ; ...
        li    a2, 1                     ; ...
dk_u:   call  use_tool                  ; ...
dk_dr:  ld    a0, g_curx - g(gp)        ; its new cell is drawn
        ld    a1, g_cury - g(gp)        ; ...
        call  dirty_cell                ; ...
        call  follow                    ; ...
        j     dk_r                      ; ...
dk_c:   li    t0, ' '                   ; Space: the tool, once, at the cursor
        bne   s0, t0, dk_e              ; ...
        call  cur_in                    ; ...
        ld    a0, g_curx - g(gp)        ; ...
        ld    a1, g_cury - g(gp)        ; ...
        li    a2, -1                    ; ...
        call  use_tool                  ; ...
        j     dk_r                      ; ...
dk_e:   li    t0, 13                    ; Enter: the pen down, or up
        beq   s0, t0, dk_e1             ; ...
        li    t0, 10                    ; ...
        bne   s0, t0, dk_t              ; ...
dk_e1:  call  cur_in                    ; ...
        ld    t0, g_pen - g(gp)         ; ...
        xori  t0, t0, 1                 ; ...
        sd    t0, g_pen - g(gp)         ; ...
        ld    a0, g_curx - g(gp)        ; (the cursor's colour says which)
        ld    a1, g_cury - g(gp)        ; ...
        call  dirty_cell                ; ...
        ld    t0, g_pen - g(gp)         ; (put down: used here at once)
        beqz  t0, dk_r                  ; ...
        ld    a0, g_curx - g(gp)        ; ...
        ld    a1, g_cury - g(gp)        ; ...
        li    a2, -1                    ; ...
        call  use_tool                  ; ...
        j     dk_r                      ; ...
dk_t:   la    t0, k_tools               ; a tool's letter
        li    t1, 0                     ; ...
dk_t1:  lbu   t2, 0(t0)                 ; ...
        beqz  t2, dk_o                  ; ...
        beq   t2, s0, dk_t2             ; ...
        addi  t0, t0, 2                 ; ...
        j     dk_t1                     ; ...
dk_t2:  lbu   a0, 1(t0)                 ; ...
        call  set_tool                  ; ...
        li    a0, SN_CLICK              ; ...
        call  snd_play                  ; ...
        j     dk_r                      ; ...
dk_o:   li    t0, 'z'                   ; Z: zoom in, X: out
        li    a0, 1                     ; ...
        beq   s0, t0, dk_z              ; ...
        li    t0, 'x'                   ; ...
        li    a0, -1                    ; ...
        bne   s0, t0, dk_p              ; ...
dk_z:   call  zoom                      ; ...
        j     dk_r                      ; ...
dk_p:   li    t0, '0'                   ; 0: pause, or go on
        bne   s0, t0, dk_s              ; ...
dk_p1:  ld    a0, g_speed - g(gp)       ; ...
        li    t0, 0                     ; ...
        beqz  a0, dk_p2                 ; ...
        mv    a0, t0                    ; ...
        j     dk_sp                     ; ...
dk_p2:  ld    a0, g_pspeed - g(gp)      ; ...
        j     dk_sp                     ; ...
dk_s:   li    t0, '-'                   ; -: slower
        bne   s0, t0, dk_f              ; ...
        ld    a0, g_speed - g(gp)       ; ...
        addi  a0, a0, -1                ; ...
