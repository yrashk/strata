; load_dat() -> a0 = 0, or -1: read /ws/plat.dat: its resident block into
; `res`, its far block into the top of the arena (through the row buffer)
load_dat:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = handle
        sd    s1, 16(sp)                ; s1 = where the next bytes go
        sd    s2, 24(sp)                ; s2 = bytes left
        la    a0, p_dat                 ; ...
        li    a1, p_dat_e - p_dat       ; ...
        li    a2, 0                     ; ...
        call  sys_open                  ; ...
        mv    s0, a0                    ; ...
        bltz  a0, ld_bad                ; ...
        la    s1, res                   ; the resident block
        li    s2, R_SIZE                ; ...
ld_r:   mv    a0, s0                    ; (a message of data at a time)
        mv    a1, s1                    ; ...
        mv    a2, s2                    ; ...
        call  sys_read                  ; ...
        blez  a0, ld_bad                ; ...
        add   s1, s1, a0                ; ...
        sub   s2, s2, a0                ; ...
        bgtz  s2, ld_r                  ; ...
        ld    s1, g_keepb - g(gp)       ; the far block
        li    s2, F_SIZE                ; ...
ld_f:   mv    a0, s0                    ; ...
        la    a1, rowbuf                ; ...
        mv    a2, s2                    ; ...
        li    t0, ROWBUF                ; (a buffer's worth at most)
        bleu  a2, t0, ld_f1             ; ...
        mv    a2, t0                    ; ...
ld_f1:  call  sys_read                  ; ...
        blez  a0, ld_bad                ; ...
        addi  t0, a0, 7                 ; (whole words)
        srli  t0, t0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        la    t1, rowbuf                ; ...
        tput  tg9, t1, c0, s1, t0       ; (the next read's stores wait for it)
        add   s1, s1, a0                ; ...
        sub   s2, s2, a0                ; ...
        bgtz  s2, ld_f                  ; ...
        twait 1 << 9                    ; ...
        mv    a0, s0                    ; ...
        call  sys_close                 ; ...
        li    a0, 0                     ; ...
        j     ld_ret                    ; ...
ld_bad: li    a0, -1                    ; ...
ld_ret: ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

