; demo(): the demo's next tic: when a step's wait is over, its key. At the
; demo's end the program stands still, as when the window loses the focus,
; until a key or the pointer wakes it.
demo:   ld    t0, g_demo - g(gp)        ; the step
        ld    t1, g_dleft - g(gp)       ; tics left of its wait
        bnez  t1, de_1                  ; ...
        lbu   t1, 0(t0)                 ; a new step
        bnez  t1, de_1                  ; ...
        sd    zero, g_demo - g(gp)      ; the end
        li    t1, 1                     ; ...
        sd    t1, g_paused - g(gp)      ; ...
        j     demo_say                  ; ...
de_1:   addi  t1, t1, -1                ; ...
        sd    t1, g_dleft - g(gp)       ; ...
        bnez  t1, de_r                  ; ...
        lbu   a0, 1(t0)                 ; ...
        addi  t0, t0, 2                 ; ...
        sd    t0, g_demo - g(gp)        ; ...
        li    t1, DK_LOOP               ; what follows, up to DK_END, so many times
        bne   a0, t1, de_e              ; ...
        lbu   t1, 0(t0)                 ; ...
        addi  t0, t0, 2                 ; ...
        sd    t0, g_demo - g(gp)        ; ...
        ld    t2, g_dsp - g(gp)         ; (one more loop open)
        slli  t3, t2, 4                 ; ...
        la    t4, g_dstk                ; ...
        add   t3, t3, t4                ; ...
        sd    t0, 0(t3)                 ; ...
        sd    t1, 8(t3)                 ; ...
        addi  t2, t2, 1                 ; ...
        sd    t2, g_dsp - g(gp)         ; ...
        ret                             ; ...
de_e:   li    t1, DK_END                ; ...
        bne   a0, t1, do_key            ; ...
        ld    t2, g_dsp - g(gp)         ; the innermost loop
        addi  t2, t2, -1                ; ...
        slli  t3, t2, 4                 ; ...
        la    t4, g_dstk                ; ...
        add   t3, t3, t4                ; ...
        ld    t1, 8(t3)                 ; ...
        addi  t1, t1, -1                ; ...
        sd    t1, 8(t3)                 ; ...
