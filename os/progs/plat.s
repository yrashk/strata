; =============================================================================
; plat.s: Plat, a city-building game, in a window
; =============================================================================
;
;   plat            (from a shell in a terminal, or the palette: Alt+Space)
;   plat demo N     plays demo N (tools/plat-assets.py: DEMOS) and stands still
;
; A client of the window server (os/lib/wsclient.s). The player plans a
; town on a map of 128 x 128 cells seen from above: roads, power lines,
; zones for homes, shops and offices, and industry, coal power plants, the
; bulldozer (os/progs/PLAN-city.md has the stages that follow). Every
; game's land is new: a river, lakes and woods made from a seed
; (plat/map.s). Once a month the town lives (plat/sim.s): power spreads
; from the plants, zones with power and a road grow when their kind is in
; demand, and the census counts the residents and the jobs. The art is
; drawn by tools/plat-art.py and converted, with the sounds, by
; tools/plat-assets.py into the file /ws/plat.dat, which is read at start.
;
; The window: the tool buttons in a column at the left, the map, and the
; bar at the bottom (speed, money, the date, the population, a message,
; the demand for each kind of zone).
; The mouse: the left button uses the tool (a drag lays a road or a line
; cell by cell), the right button drags the map, the wheel scrolls it, a
; click picks a tool or a speed. The keyboard: the arrows move a cell
; cursor (the map follows it), Space uses the tool there, Enter puts the
; pen down (the tool is used on every cell the cursor moves to) or lifts
; it; B bulldozer, R road, L power line, 1 2 3 homes, shops and offices,
; industry, P coal plant, I or ? ask what is there; Z and X zoom in and
; out (cells of 4 to 64 pixels: at 4 the whole map is in view); [ and ]
; the tax rate down and up; 0 pause, - and = slower and faster; S saves
; the town, O brings the saved one back, N makes new land; Q quits (and
; saves). A saved town (/ws/plat.sav, plat/file.s) is loaded at the start.
;
; Drawing (plat/draw.s): XRGB8888 at the window's size. Only what changed
; is drawn and lent to the server: the cells a tool or the town changed,
; the bar's numbers, a moved cursor; the whole map after a scroll or a
; zoom.

S_CAP    = 0                            ; os/lib/gfx.s's surface descriptor: register
S_OFF    = 8                            ; offset of pixel (0, 0)
S_W      = 16                           ; width
S_H      = 24                           ; height
S_STRIDE = 32                           ; bytes per row
S_SIZE   = 48                           ; bytes per descriptor
TIC_US   = 28571                        ; a tic in the clock's ticks (microseconds): 35 a second
K_UP     = 1                            ; keys: the arrows
K_DOWN   = 2                            ; ...
K_LEFT   = 3                            ; ...
K_RIGHT  = 4                            ; ...
DK_LOOP  = 0xfb                         ; in a demo: what follows, up to DK_END, N times (N, 0 follow)
DK_END   = 0xfc                         ; ...
NDLOOP   = 4                            ; loops a demo may nest
MSG_TICS = 245                          ; a message stays seven seconds
FUNDS0   = 20000                        ; the treasury at the start
TAX0     = 7                            ; the tax rate at the start (per cent)
TAXMAX   = 20                           ; ... at the most
ZOOM0    = 2                            ; the zoom at the start: cells of 16 pixels
NZOOM    = 5                            ; zooms: cells of 4, 8, 16, 32, 64 pixels
YEAR0    = 1900                         ; the first year

        .text                           ; instruction Local Store
_start: j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program

        .include "plat/dat.s"           ; the data file's layout
        .include "plat/map.s"           ; the map, the land, the tools
        .include "plat/sim.s"           ; the town: power, zones, census, demand
        .include "plat/draw.s"          ; the window
        .include "plat/file.s"          ; the town in a file
        .include "wdoom/sound.s"        ; the sounds: wdoom's mixer
        .include "../lib/sys.s"         ; the program library
        .include "../lib/wsclient.s"    ; the window server's protocol

KEEP     = ((F_SIZE + 4095) & ~4095) + MAPB ; the top of the arena: plat.dat's far block, the map

        .data                           ; D-LS
        .align 8                        ; dwords
g:                                      ; the globals (gp points here)
g_tic:    .dword 0                      ; tics since the start
g_last:   .dword 0                      ; the clock at the last tic
g_seed:   .dword 20261115               ; the random numbers' state
g_quit:   .dword 0                      ; time to go
g_paused: .dword 0                      ; the window lost the focus (or a demo is over)
g_esc:    .dword 0                      ; keys: 1 after ESC, 2 after ESC [
g_btn:    .dword 0                      ; the pointer's buttons at its last event
g_keepb:  .dword 0                      ; arena offset of the far block (= the band's size)
g_mapb:   .dword 0                      ; ... and of the map
g_demo:   .dword 0                      ; `plat demo N`: the next step of the demo (0: no demo)
g_dleft:  .dword 0                      ; ... and tics left before its key
g_dt0:    .dword 0                      ; the clock when the demo started
g_dsp:    .dword 0                      ; the demo's loops: how many are open
g_dstk:   .space NDLOOP * 16            ; ... each its first step and the times still to go
g_w:      .dword 0                      ; the window's size
g_h:      .dword 0                      ; ...
g_bw:     .dword 0                      ; the bar's width (the window's, at most MAXW)
g_zoom:   .dword ZOOM0                  ; cells of 4 << g_zoom pixels (4 .. 64)
g_cp:     .dword 16                     ; pixels a cell
g_step:   .dword 1                      ; ... a picture's pixels drawn: every g_step-th
g_rep:    .dword 1                      ; ... each g_rep times across and down
g_px:     .dword TOOLW                  ; the view's top left in the window (it is centred)
g_py:     .dword 0                      ; ...
g_vw:     .dword 0                      ; the map's cells in view, across and down
g_vh:     .dword 0                      ; ...
g_ox:     .dword 0                      ; the cell at the view's top left
g_oy:     .dword 0                      ; ...
g_tool:   .dword TL_ROAD                ; the tool in use
g_pen:    .dword 0                      ; the keyboard's pen is down
g_curx:   .dword MAPN / 2               ; the keyboard's cursor (a cell of the map)
g_cury:   .dword MAPN / 2               ; ...
g_curon:  .dword 0                      ; ... is shown (the keyboard was used last)
g_lastx:  .dword -1                     ; a drag: the last cell the tool was used on (-1: none)
g_lasty:  .dword -1                     ; ...
g_pan:    .dword 0                      ; the right button drags the map
g_panx:   .dword 0                      ; ... from this point
g_pany:   .dword 0                      ; ...
g_pox:    .dword 0                      ; ... and this view
g_poy:    .dword 0                      ; ...
g_funds:  .dword FUNDS0                 ; the treasury
g_month:  .dword 0                      ; the date: 0..11
g_year:   .dword YEAR0                  ; ...
g_speed:  .dword 2                      ; 0: paused, 1 slow, 2 normal, 3 fast
g_pspeed: .dword 2                      ; the speed before the pause
g_mtic:   .dword 0                      ; tics into the month
g_dview:  .dword 1                      ; to be drawn: the whole map
g_dtools: .dword 1                      ; ... the tool column
g_dbar:   .dword 1                      ; ... the bar
g_dtext:  .dword TX_ALL                 ; ... the bar's numbers and message (TX_*)
g_popr:   .dword 0                      ; the census: residents
g_popc:   .dword 0                      ; ... jobs in shops and offices
g_popi:   .dword 0                      ; ... jobs in industry
g_dr:     .dword 0                      ; demand for homes (-1000 .. 1000)
g_dc:     .dword 0                      ; ... shops and offices
g_di:     .dword 0                      ; ... industry
g_nplant: .dword 0                      ; plants (sim.s: plants)
g_tax:    .dword TAX0                   ; the tax rate (per cent)
g_upk:    .dword 0                      ; upkeep a year of what is built
g_ytax:   .dword 0                      ; this year's taxes so far
g_yupk:   .dword 0                      ; ... and upkeep
g_mile:   .dword 0                      ; the next milestone (sim.s: miles)
g_wopen:  .dword 0                      ; the window is open (file.s: fs_on)
g_tip:    .dword -1                     ; the tooltip shown (draw.s: tip_txt; -1: none)
g_tipd:   .dword 0                      ; ... it is to be drawn
g_tipt:   .dword 0                      ; ... tics it stays
g_tips:   .dword 0                      ; ... its text
g_tipl:   .dword 0                      ; ... its length
g_tipx:   .dword 0                      ; ... where it is
g_tipy:   .dword 0                      ; ...
g_tipw:   .dword 0                      ; ... its width
g_ptrx:   .dword 0                      ; the pointer's last place
g_hello:  .dword msg_hello              ; what is said first
g_short:  .dword 0                      ; this month the plants did not power every zone
g_shown:  .dword 0                      ; ... last month too (it was said)
g_dx0:    .dword 0                      ; ... the map's cells [x0, x1) x [y0, y1)
g_dy0:    .dword 0                      ; ...
g_dx1:    .dword 0                      ; ...
g_dy1:    .dword 0                      ; ...
g_msg:    .dword 0                      ; the message: its text (0: none)
g_msgl:   .dword 0                      ; ... its length
g_msgt:   .dword 0                      ; ... tics it stays
p_dmsg:   .ascii "plat: "               ; what is said at the demo's end, and at the last
p_dnum:   .space 120                    ; ... "demo: N frames in N ms; funds F; date M Y; map H\n"
p_ddemo:  .ascii "demo: \0"             ; (its pieces)
p_dfr:    .ascii " frames in \0"        ; ...
p_dms:    .ascii " ms; \0"              ; ...
p_dfunds: .ascii "funds \0"             ; ...
p_ddate:  .ascii "; date \0"            ; ...
p_dpop:   .ascii "; pop \0"             ; ...
p_dmap:   .ascii "; map \0"             ; ...
p_dnl:    .ascii "\n\0"                 ; ...
        .align 8                        ; ...
res:      .space R_SIZE                 ; the data file's resident block (dat.s)
p_title:  .ascii "PLAT\0\0\0\0"         ; the window's title
p_dat:    .ascii "/ws/plat.dat"         ; the data file
p_dat_e:                                ; (its end)
p_nows:   .ascii "plat: no window server (run ws first)\n"
p_nows_e:                               ; (its end)
p_nodat:  .ascii "plat: cannot read /ws/plat.dat\n"
p_nodat_e:                              ; (its end)
p_args:   .space 64                     ; the command line's arguments
        .align 8                        ; ...
        .text                           ; code

main:
        call  sys_init                  ; handles
        la    gp, g                     ; the globals
        clen  t0, c0                    ; the arena: the band, then the far block, the map
        li    t1, KEEP                  ; ...
        sub   t0, t0, t1                ; ...
        sd    t0, g_keepb - g(gp)       ; ...
        li    t1, KEEP - MAPB           ; ...
        add   t0, t0, t1                ; ...
        sd    t0, g_mapb - g(gp)        ; ...
        call  load_dat                  ; the data (before the window: the server's
        beqz  a0, m_arg                 ;   endpoint takes the place of fs's)
        la    a0, p_nodat               ; ...
        li    a1, p_nodat_e - p_nodat   ; ...
        j     m_fail                    ; ...
m_arg:  la    a0, p_args                ; `plat demo N`: play demo N (dat.s: R_DEMO)
        call  sys_args                  ; ...
        beqz  a0, m_seed                ; ...
        la    t0, p_args                ; ...
        lbu   t1, 0(t0)                 ; ...
        li    t2, 'd'                   ; ...
        bne   t1, t2, m_seed            ; ...
        add   t0, t0, a0                ; its number is the last character (1 if none)
        lbu   t1, -1(t0)                ; ...
        addi  t1, t1, -'1'              ; ...
        li    t2, 9                     ; ...
        bltu  t1, t2, m_d1              ; ...
        li    t1, 0                     ; ...
m_d1:   slli  t1, t1, 1                 ; ...
        la    t0, res + R_DEMO          ; ...
        add   t1, t1, t0                ; ...
        lhu   t1, 0(t1)                 ; ...
        add   t0, t0, t1                ; ...
        sd    t0, g_demo - g(gp)        ; ...
        j     m_land                    ; (its land comes from the fixed seed)
m_seed: call  sys_now                   ; every game has other land
        ld    t0, g_seed - g(gp)        ; ...
        xor   t0, t0, a0                ; ...
        sd    t0, g_seed - g(gp)        ; ...
        call  mark_load                 ; the marks over zones
        call  city_load                 ; the saved town, if there is one
        beqz  a0, m_win                 ; ...
        call  town_reset                ; (none, or not whole: new land)
        j     m_gen                     ; ...
m_land: call  mark_load                 ; the marks over zones
m_gen:  call  gen_land                  ; the river, the lakes, the woods
        j     m_win1                    ; ...
m_win:  la    t0, msg_load              ; ...
        sd    t0, g_hello - g(gp)       ; ...
m_win1:                                 ; ...
        la    t0, wc_keep               ; (the library's idea of the band agrees)
        li    t1, KEEP                  ; ...
        sd    t1, 0(t0)                 ; ...
        la    a0, p_title               ; our window (events are polled; the pointer's
        li    a1, 2                     ;   moves come with no button held: tooltips)
        call  wc_open                   ; ...
        bgtz  a0, m_go                  ; ...
        la    a0, p_nows                ; no server
        li    a1, p_nows_e - p_nows     ; ...
m_fail: call  err_str                   ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...
m_go:   li    t0, 1                     ; ...
        sd    t0, g_wopen - g(gp)       ; ...
        call  sys_now                   ; (a demo is timed)
        sd    a0, g_dt0 - g(gp)         ; ...
        ld    t0, g_demo - g(gp)        ; (and silent)
        bnez  t0, m_go2                 ; ...
        call  snd_open                  ; the sound device, if there is one
m_go2:  call  geom                      ; where everything goes
        call  centre                    ; the view: the middle of the map
        ld    a0, g_hello - g(gp)       ; ...
        call  say                       ; ...
        call  sys_now                   ; time starts now
        sd    a0, g_last - g(gp)        ; ...
m_loop: ld    t0, g_quit - g(gp)        ; ...
        bnez  t0, m_end                 ; ...
        li    a0, 1                     ; an event? (do not block)
        li    a1, 0                     ; ...
        call  wc_event                  ; ...
        li    t0, -3                    ; none
        beq   a0, t0, m_time            ; ...
        bnez  a0, m_end                 ; the window is gone
        call  ev_handle                 ; ...
        j     m_loop                    ; ...
m_time: ld    t0, g_paused - g(gp)      ; ...
        beqz  t0, m_run                 ; ...
        call  show                      ; standing still: the picture as it stands,
        li    a0, 0                     ; ... then wait for an event
        li    a1, 0                     ; ...
        call  wc_event                  ; ...
        bnez  a0, m_end                 ; ...
        call  ev_handle                 ; ...
        call  sys_now                   ; (no tics are owed for the pause)
        sd    a0, g_last - g(gp)        ; ...
        j     m_loop                    ; ...
m_run:  ld    t0, g_demo - g(gp)        ; the demo: a tic a frame, whatever the clock says
        beqz  t0, m_clk                 ; ...
        call  demo                      ; ...
        call  step                      ; ...
        j     m_draw                    ; ...
m_clk:  call  sys_now                   ; tics due?
        ld    t0, g_last - g(gp)        ; ...
        sub   t1, a0, t0                ; ...
        li    t2, TIC_US                ; ...
        bgeu  t1, t2, m_tics            ; ...
        call  dirty                     ; none: a frame anyway (a key, a click)?
        bnez  a0, m_draw                ; ...
        ld    t0, g_last - g(gp)        ; wait for the next tic, or an event
        call  sys_now                   ; ...
        sub   t1, a0, t0                ; ...
        li    a1, TIC_US                ; ...
        sub   a1, a1, t1                ; ...
        blez  a1, m_loop                ; ...
        li    a0, 0                     ; ...
        call  wc_event                  ; ...
        li    t0, -8                    ; (the time passed)
        beq   a0, t0, m_loop            ; ...
        bnez  a0, m_end                 ; ...
        call  ev_handle                 ; ...
        j     m_loop                    ; ...
m_tics: divu  s0, t1, t2                ; s0 = tics due
        mul   t3, s0, t2                ; ...
        add   t0, t0, t3                ; ...
        sd    t0, g_last - g(gp)        ; ...
        li    t3, 4                     ; (after a long frame: four at most)
        bleu  s0, t3, m_t1              ; ...
        mv    s0, t3                    ; ...
m_t1:   call  step                      ; ...
        addi  s0, s0, -1                ; ...
        bnez  s0, m_t1                  ; ...
m_draw: call  snd_pump                  ; the sounds, then the picture
        call  show                      ; ...
        j     m_loop                    ; ...
m_end:  ld    t0, g_demo - g(gp)        ; the town is kept (not a demo's)
        bnez  t0, m_end1                ; ...
        call  city_save                 ; ...
m_end1: call  state_say                 ; what the town has come to
        call  wc_close                  ; the window goes
        li    a0, 0                     ; ...
        call  sys_exit                  ; ...

; step(): a tic: the message's time, the plants' smoke, the calendar and,
; once a month, the town
step:   addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        ld    t0, g_tic - g(gp)         ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, g_tic - g(gp)         ; ...
        li    t1, PLANT_TICS            ; ...
        remu  t1, t0, t1                ; ...
        bnez  t1, st_0                  ; ...
        call  plants_turn               ; ...
st_0:   ld    t0, g_tipt - g(gp)        ; a tooltip goes when the pointer rests long
        blez  t0, st_00                 ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, g_tipt - g(gp)        ; ...
        bnez  t0, st_00                 ; ...
        li    a0, -1                    ; ...
        call  tip_set                   ; ...
st_00:  ld    t0, g_msgt - g(gp)        ; ...
        blez  t0, st_1                  ; the message goes when its time is up
        addi  t0, t0, -1                ; ...
        sd    t0, g_msgt - g(gp)        ; ...
        bnez  t0, st_1                  ; ...
        sd    zero, g_msg - g(gp)       ; ...
        ld    t1, g_dtext - g(gp)       ; ...
        ori   t1, t1, TX_MSG            ; ...
        sd    t1, g_dtext - g(gp)       ; ...
st_1:   ld    t0, g_speed - g(gp)       ; the calendar, at the speed chosen
        beqz  t0, st_r                  ; ...
        la    t1, tpm                   ; ...
        slli  t0, t0, 3                 ; ...
        add   t1, t1, t0                ; ...
        ld    t1, 0(t1)                 ; t1 = tics a month
        ld    t2, g_mtic - g(gp)        ; ...
        addi  t2, t2, 1                 ; ...
        sd    t2, g_mtic - g(gp)        ; ...
        bltu  t2, t1, st_r              ; ...
        sd    zero, g_mtic - g(gp)      ; a new month
        ld    t0, g_month - g(gp)       ; ...
        addi  t0, t0, 1                 ; ...
        li    t1, 12                    ; ...
        bltu  t0, t1, st_m              ; ...
        li    t0, 0                     ; ... and a new year
        ld    t1, g_year - g(gp)        ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, g_year - g(gp)        ; ...
st_m:   sd    t0, g_month - g(gp)       ; ...
        ld    t0, g_dtext - g(gp)       ; ...
        ori   t0, t0, TX_DATE           ; ...
        sd    t0, g_dtext - g(gp)       ; ...
        call  sim_month                 ; ...
st_r:   ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; say(a0 = message, NUL-terminated): it is shown in the bar (one shown
; already only stays longer)
say:    li    t0, MSG_TICS              ; ...
        ld    t1, g_msg - g(gp)         ; ...
        bne   t1, a0, sy_0              ; ...
        sd    t0, g_msgt - g(gp)        ; ...
        ret                             ; ...
sy_0:   sd    a0, g_msg - g(gp)         ; ...
        li    t0, 0                     ; its length
sy_l:   add   t1, a0, t0                ; ...
        lbu   t1, 0(t1)                 ; ...
        beqz  t1, sy_e                  ; ...
        addi  t0, t0, 1                 ; ...
        j     sy_l                      ; ...
sy_e:   sd    t0, g_msgl - g(gp)        ; ...
        li    t0, MSG_TICS              ; ...
        sd    t0, g_msgt - g(gp)        ; ...
        ld    t0, g_dtext - g(gp)       ; ...
        ori   t0, t0, TX_MSG            ; ...
        sd    t0, g_dtext - g(gp)       ; ...
        ret                             ; done

; set_tool(a0 = tool): it is in use; its button is pressed; the bar says what it costs
set_tool:
        ld    t0, g_tool - g(gp)        ; ...
        sd    a0, g_tool - g(gp)        ; ...
        li    t1, 1                     ; ...
        sd    t1, g_dtools - g(gp)      ; ...
        la    t1, tl_msg                ; ...
        slli  t2, a0, 3                 ; ...
        add   t1, t1, t2                ; ...
        ld    a0, 0(t1)                 ; ...
        j     say                       ; ...

; set_speed(a0 = 0..3)
set_speed:
        ld    t0, g_speed - g(gp)       ; (the speed before a pause is remembered)
        beqz  t0, ss_1                  ; ...
        sd    t0, g_pspeed - g(gp)      ; ...
ss_1:   sd    a0, g_speed - g(gp)       ; ...
        li    t0, 1                     ; ...
        sd    t0, g_dbar - g(gp)        ; ...
        ret                             ; done

; centre(): the view's middle on the cursor
centre: ld    t0, g_curx - g(gp)        ; ...
        ld    t1, g_vw - g(gp)          ; ...
        srli  t1, t1, 1                 ; ...
        sub   t0, t0, t1                ; ...
        sd    t0, g_ox - g(gp)          ; ...
        ld    t0, g_cury - g(gp)        ; ...
        ld    t1, g_vh - g(gp)          ; ...
        srli  t1, t1, 1                 ; ...
        sub   t0, t0, t1                ; ...
        sd    t0, g_oy - g(gp)          ; ...
; clamp_view(): the view stays on the map; it is to be drawn
clamp_view:
        li    t3, MAPN                  ; ...
        ld    t0, g_ox - g(gp)          ; x: 0 .. MAPN - vw
        ld    t1, g_vw - g(gp)          ; ...
        sub   t2, t3, t1                ; ...
        ble   t0, t2, cv_1              ; ...
        mv    t0, t2                    ; ...
cv_1:   bgez  t0, cv_2                  ; ...
        li    t0, 0                     ; ...
cv_2:   sd    t0, g_ox - g(gp)          ; ...
        ld    t0, g_oy - g(gp)          ; y likewise
        ld    t1, g_vh - g(gp)          ; ...
        sub   t2, t3, t1                ; ...
        ble   t0, t2, cv_3              ; ...
        mv    t0, t2                    ; ...
cv_3:   bgez  t0, cv_4                  ; ...
        li    t0, 0                     ; ...
cv_4:   sd    t0, g_oy - g(gp)          ; ...
        li    t0, 1                     ; ...
        sd    t0, g_dview - g(gp)       ; ...
        ret                             ; done

; scroll(a0 = cells right, a1 = cells down): the view moves (if it can)
scroll: ld    t0, g_ox - g(gp)          ; ...
        ld    t1, g_oy - g(gp)          ; ...
        add   a0, a0, t0                ; ...
        add   a1, a1, t1                ; ...
; view_at(a0 = x, a1 = y): the view's top left there (clamped); drawn if it moved
view_at:
        ld    t0, g_ox - g(gp)          ; (what it was)
        ld    t1, g_oy - g(gp)          ; ...
        ld    t2, g_dview - g(gp)       ; ...
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    t0, 8(sp)                 ; ...
        sd    t1, 16(sp)                ; ...
        sd    t2, 24(sp)                ; ...
        sd    a0, g_ox - g(gp)          ; ...
        sd    a1, g_oy - g(gp)          ; ...
        call  clamp_view                ; ...
        ld    t0, 8(sp)                 ; it did not move: not to be drawn for that
        ld    t1, 16(sp)                ; ...
        ld    t2, 24(sp)                ; ...
        ld    t3, g_ox - g(gp)          ; ...
        bne   t0, t3, va_r              ; ...
        ld    t3, g_oy - g(gp)          ; ...
        bne   t1, t3, va_r              ; ...
        sd    t2, g_dview - g(gp)       ; ...
va_r:   ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

; zoom(a0 = +1: larger cells, -1: smaller): the view keeps its middle
zoom:   ld    t0, g_zoom - g(gp)        ; (from the largest or the smallest, nothing)
        add   t0, t0, a0                ; ...
        li    t1, NZOOM                 ; ...
        bgeu  t0, t1, zm_r              ; ...
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        ld    t0, g_ox - g(gp)          ; the middle
        ld    t1, g_vw - g(gp)          ; ...
        srli  t1, t1, 1                 ; ...
        add   t0, t0, t1                ; ...
        sd    t0, 8(sp)                 ; ...
        ld    t0, g_oy - g(gp)          ; ...
        ld    t1, g_vh - g(gp)          ; ...
        srli  t1, t1, 1                 ; ...
        add   t0, t0, t1                ; ...
        sd    t0, 16(sp)                ; ...
        ld    t0, g_zoom - g(gp)        ; ...
        add   t0, t0, a0                ; ...
        sd    t0, g_zoom - g(gp)        ; ...
        call  geom                      ; ...
        ld    t0, 8(sp)                 ; ...
        ld    t1, g_vw - g(gp)          ; ...
        srli  t1, t1, 1                 ; ...
        sub   t0, t0, t1                ; ...
        sd    t0, g_ox - g(gp)          ; ...
        ld    t0, 16(sp)                ; ...
        ld    t1, g_vh - g(gp)          ; ...
        srli  t1, t1, 1                 ; ...
        sub   t0, t0, t1                ; ...
        sd    t0, g_oy - g(gp)          ; ...
        call  clamp_view                ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 24                ; pop the frame
zm_r:   ret                             ; done

; follow(): the view follows the cursor (it stays two cells inside it)
follow: ld    a0, g_ox - g(gp)          ; a0, a1 = the new top left
        ld    a1, g_oy - g(gp)          ; ...
        ld    t0, g_curx - g(gp)        ; ...
        addi  t1, t0, -2                ; left of the view?
        bge   t1, a0, fo_1              ; ...
        mv    a0, t1                    ; ...
fo_1:   ld    t2, g_vw - g(gp)          ; right of it?
        addi  t1, t0, 3                 ; ...
        sub   t1, t1, t2                ; ...
        ble   t1, a0, fo_2              ; ...
        mv    a0, t1                    ; ...
fo_2:   ld    t0, g_cury - g(gp)        ; above, below
        addi  t1, t0, -2                ; ...
        bge   t1, a1, fo_3              ; ...
        mv    a1, t1                    ; ...
fo_3:   ld    t2, g_vh - g(gp)          ; ...
        addi  t1, t0, 3                 ; ...
        sub   t1, t1, t2                ; ...
        ble   t1, a1, fo_4              ; ...
        mv    a1, t1                    ; ...
fo_4:   j     view_at                   ; ...

