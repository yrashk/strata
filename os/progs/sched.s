; =============================================================================
; sched.s: show or set the preemption time slice
; =============================================================================
;
;   sched              the time slice, and context switches and KiB moved per
;                      second since the last `sched`
;   sched 500us        set the slice (100us .. 100ms): a number of microseconds
;   sched 5ms          (no suffix), or with us / ms
;   sched 2000
;
; The system core stops (through core control) every worker core that has
; more than one runnable process once per time slice; the core's dispatcher
; then switches to the next one. A shorter slice gives more switches, and every
; switch moves Local Store contents in and out: that cost is what `sched`
; and `ps` show. A core with one runnable process is never stopped.

        .data                           ; data Local Store
        .align 8                        ; aligned buffers
args:   .space 512                      ; the argument text
info:   .space 24                       ; slice, switches/s, KiB/s
m_sl:   .ascii "time slice: "           ; output text
m_sl_e:                                 ; end of the text above
m_us:   .ascii " us; "                  ; output text
m_us_e:                                 ; end of the text above
m_sw:   .ascii " switches/s, "          ; output text
m_sw_e:                                 ; end of the text above
m_kb:   .ascii " KiB/s moved by switches\n" ; output text
m_kb_e:                                 ; end of the text above
m_use:  .ascii "usage: sched [N | Nus | Nms]  (100us .. 100ms)\n" ; error text
m_use_e:                                ; end of the text above

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        li    sp, 65536                 ; stack at the top of the D-LS
        call  sys_init                  ; handles and arguments
        la    a0, args                  ; the arguments
        call  sys_args                  ; a0 = their length
        mv    s1, a0                    ; s1 = length
        bnez  s1, set                   ; an argument: set the slice
        li    a0, 0                     ; read
        la    a1, info                  ; ...
        call  sys_sched                 ; ...
        bnez  a0, fail                  ; ...
        la    a0, m_sl                  ; "time slice: "
        li    a1, m_sl_e - m_sl         ; ...
        call  out_str                   ; ...
        la    t0, info                  ; the slice
        ld    a0, 0(t0)                 ; ...
        call  out_dec                   ; ...
        la    a0, m_us                  ; " us; "
        li    a1, m_us_e - m_us         ; ...
        call  out_str                   ; ...
        la    t0, info                  ; switches per second
        ld    a0, 8(t0)                 ; ...
        call  out_dec                   ; ...
        la    a0, m_sw                  ; " switches/s, "
        li    a1, m_sw_e - m_sw         ; ...
        call  out_str                   ; ...
        la    t0, info                  ; KiB per second
        ld    a0, 16(t0)                ; ...
        call  out_dec                   ; ...
        la    a0, m_kb                  ; " KiB/s moved ..."
        li    a1, m_kb_e - m_kb         ; ...
        call  out_str                   ; ...
        li    a0, 0                     ; done
        call  sys_exit                  ; ...
set:
        la    s0, args                  ; s0 = cursor
        add   s2, s0, s1                ; s2 = end
        li    s3, 0                     ; s3 = the number
        li    t3, 10                    ; ...
num:
        bgeu  s0, s2, unit              ; digits first
        lbu   t0, 0(s0)                 ; ...
        addi  t1, t0, -48               ; '0' -> 0
        bgeu  t1, t3, unit              ; not a digit: the unit
        mul   s3, s3, t3                ; ...
        add   s3, s3, t1                ; ...
        addi  s0, s0, 1                 ; ...
        j     num                       ; ...
unit:
        la    t0, args                  ; at least one digit
        beq   s0, t0, usage             ; ...
        sub   t1, s2, s0                ; what follows: nothing, "us" or "ms"
        beqz  t1, apply                 ; microseconds
        li    t2, 2                     ; two letters
        bne   t1, t2, usage             ; ...
        lbu   t0, 1(s0)                 ; ...s
        li    t2, 's'                   ; ...
        bne   t0, t2, usage             ; ...
        lbu   t0, 0(s0)                 ; u or m
        li    t2, 'u'                   ; ...
        beq   t0, t2, apply             ; ...
        li    t2, 'm'                   ; milliseconds: * 1000
        bne   t0, t2, usage             ; ...
        li    t2, 1000                  ; ...
        mul   s3, s3, t2                ; ...
apply:
        li    a0, 1                     ; set
        mv    a1, s3                    ; ...
        call  sys_sched                 ; 0, or -1 out of range
        bnez  a0, usage                 ; ...
        li    a0, 0                     ; done
        call  sys_exit                  ; ...
usage:
        la    a0, m_use                 ; usage, on standard error
        li    a1, m_use_e - m_use       ; ...
        call  err_str                   ; ...
        li    a0, 2                     ; ...
        call  sys_exit                  ; ...
fail:
        li    a0, 1                     ; no answer
        call  sys_exit                  ; ...

        .include "../lib/sys.s"         ; the system interface
