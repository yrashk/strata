; =============================================================================
; ls.s: list the files on the disk, or the files that carry tags
; =============================================================================
;
;   ls                    the files of the current tag path (cd; at "/":
;                         every file): name (padded to 26 columns), size
;   ls TAG/...  ls NAME   a path without the leading "/": under the current one
;   ls /TAG/TAG...        the files that carry every one of the tags
;   ls /TAG.../NAME       that one file, if it carries the tags
;   ls /TAG/-TAG...       "-TAG": files that do not carry it (ls /src/-demo)
;   ls -t [PATH]          the same, with each file's tags after its size
;
; The file system has no directories: a "directory" is a set of tags (see
; os/servers/fs.s). Asks the file server for the files with sys_list, part by
; part (a listing has no limit; each part's records hold a file's name, size
; and tag ids) and, with -t, for each file's tags with sys_tags2.
; Subdirectories are facets: after the files come the other tags they carry,
; as "TAG/" (the ids the records held, without the path's own; named by
; sys_tags2), the ways to narrow the listing (ls /src: demo/). Prints
; "(no files)" when there are none, and "ls: no such tag or file: PATH"
; (exit code 1) when a component of the path is neither.

NFAC    = 512                           ; facets remembered at most

        .data                           ; data Local Store
        .align 8                        ; aligned buffers
dir:    .space 4096                     ; one part of the listing
tagbuf: .space 4096                     ; tag records
args:   .space 512                      ; the argument text
aname:  .space 264                      ; "/" and a listed file's name
path:   .dword 0                        ; the path's address
plen:   .dword 0                        ; its length (0: every file)
flag_t: .dword 0                        ; -t: show the tags
cursor: .dword 0                        ; where the listing has got to
nfiles: .dword 0                        ; files listed so far
npt:    .dword 0                        ; the path's own tags
pt:     .space 16 * 4                   ; ...
nfac:   .dword 0                        ; the facets: tag ids the files carry
fac:    .space NFAC * 4                 ; ...
m_none: .ascii "(no files)\n"           ; output text
m_none_e:                               ; end of the text above
m_err:  .ascii "ls: no such tag or file: " ; error text
m_err_e:                                ; end of the text above
m_t:    .ascii "-t"                     ; the option
m_sl:   .ascii "/"                      ; after a facet

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        call  sys_init                  ; handles and arguments
        la    a0, args                  ; the arguments ...
        call  sys_args                  ; ... a0 = their length
        la    s0, args                  ; s0 = cursor
        add   s1, s0, a0                ; s1 = end
arg:
        mv    a0, s0                    ; the next word
        mv    a1, s1                    ; ...
        call  arg_next                  ; a0 = start, a1 = length, a2 = cursor after
        beqz  a1, query                 ; no more
        mv    s0, a2                    ; advance the cursor
        mv    s2, a0                    ; s2, s3 = the word
        mv    s3, a1                    ; ...
        la    a2, m_t                   ; -t?
        li    a3, 2                     ; ...
        call  str_eq                    ; ...
        beqz  a0, a_path                ; no
        li    t0, 1                     ; yes
        la    t1, flag_t                ; ...
        sd    t0, 0(t1)                 ; ...
        j     arg                       ; ...
a_path:
        la    t0, path                  ; the path (the last one given)
        sd    s2, 0(t0)                 ; ...
        la    t0, plen                  ; ...
        sd    s3, 0(t0)                 ; ...
        j     arg                       ; ...
query:
        la    a0, dir                   ; the next part of the listing
        la    a1, path                  ; ...
        ld    a1, 0(a1)                 ; ...
        la    a2, plen                  ; ...
        ld    a2, 0(a2)                 ; ...
        la    a3, cursor                ; ...
        ld    a3, 0(a3)                 ; ...
        call  sys_list                  ; a0 = files in it, a1 = the cursor
        bltz  a0, fail                  ; no such tag or file
        la    t0, cursor                ; ...
        sd    a1, 0(t0)                 ; ...
        mv    s0, a0                    ; s0 = records left
        la    t0, nfiles                ; ...
        ld    t1, 0(t0)                 ; ...
        add   t1, t1, s0                ; ...
        sd    t1, 0(t0)                 ; ...
        la    s1, dir                   ; the path's own tags come first
        ld    t0, 0(s1)                 ; ...
        la    t1, npt                   ; ...
        sd    t0, 0(t1)                 ; ...
        la    t1, pt                    ; ...
        addi  s1, s1, 8                 ; ...
        li    t2, 0                     ; ...
p_l:
        bgeu  t2, t0, p_d               ; ...
        lwu   t3, 0(s1)                 ; ...
        sw    t3, 0(t1)                 ; ...
        addi  s1, s1, 4                 ; ...
        addi  t1, t1, 4                 ; ...
        addi  t2, t2, 1                 ; ...
        j     p_l                       ; ...
p_d:
        addi  s1, s1, 7                 ; s1 = current record
        srli  s1, s1, 3                 ; ...
        slli  s1, s1, 3                 ; ...
entry:
        beqz  s0, e_part                ; this part is done
        lhu   s2, 2(s1)                 ; s2 = the name's length
        addi  a0, s1, 16                ; print the name
        mv    a1, s2                    ; ...
        call  out_str                   ; ...
        li    a0, 26                    ; pad it to 26 columns (a longer one: a space)
        sub   a0, a0, s2                ; ...
        bgtz  a0, e_pad                 ; ...
        li    a0, 1                     ; ...
e_pad:
        call  out_pad                   ; ...
        la    t0, flag_t                ; with the tags?
        ld    t0, 0(t0)                 ; ...
        bnez  t0, e_tags                ; yes
        ld    a0, 8(s1)                 ; the size
        call  out_dec                   ; ...
        j     e_end                     ; ...
e_tags:
        ld    a0, 8(s1)                 ; the size, in 7 columns
        li    a1, 7                     ; ...
        call  out_decw                  ; ...
        li    a0, 1                     ; a space before the tags
        call  out_pad                   ; ...
        la    t0, aname                 ; the file's tags, by "/NAME" (names are
        li    t1, '/'                   ; unique: wherever the current path is)
        sb    t1, 0(t0)                 ; ...
        li    t2, 0                     ; ...
e_an:
        bgeu  t2, s2, e_aq              ; ...
        add   t3, s1, t2                ; ...
        lbu   t3, 16(t3)                ; ...
        add   t4, t0, t2                ; ...
        sb    t3, 1(t4)                 ; ...
        addi  t2, t2, 1                 ; ...
        j     e_an                      ; ...
e_aq:
        li    s5, 0                     ; s5 = the cursor among its tags
e_tp:
        la    a0, tagbuf                ; ...
        la    a1, aname                 ; ...
        addi  a2, s2, 1                 ; ...
        mv    a3, s5                    ; ...
        call  sys_tags2                 ; a0 = how many, a1 = the cursor
        mv    s5, a1                    ; ...
        mv    s3, a0                    ; s3 = tags left
        la    s4, tagbuf                ; s4 = record
e_tl:
        blez  s3, e_tn                  ; no more in this part
        li    a0, 1                     ; a space, then the name
        call  out_pad                   ; ...
        addi  a0, s4, 16                ; ...
        lhu   a1, 2(s4)                 ; ...
        call  out_str                   ; ...
        lhu   t0, 0(s4)                 ; next tag
        add   s4, s4, t0                ; ...
        addi  s3, s3, -1                ; ...
        j     e_tl                      ; ...
e_tn:
        bnez  s5, e_tp                  ; more of its tags
e_end:
        call  out_nl                    ; end the line
        addi  t0, s2, 7                 ; its tag ids: facets, unless they are the path's own
        srli  t0, t0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        add   s3, s1, t0                ; s3 = the ids
        addi  s3, s3, 16                ; ...
        lwu   s4, 4(s1)                 ; s4 = how many
e_f:
        beqz  s4, e_next                ; ...
        lwu   a0, 0(s3)                 ; ...
        addi  s3, s3, 4                 ; ...
        addi  s4, s4, -1                ; ...
        la    a1, pt                    ; one of the path's?
        la    t0, npt                   ; ...
        ld    a2, 0(t0)                 ; ...
        call  id_in                     ; ...
        bnez  a1, e_f                   ; ...
        la    a1, fac                   ; known already?
        la    t0, nfac                  ; ...
        ld    a2, 0(t0)                 ; ...
        call  id_in                     ; ...
        bnez  a1, e_f                   ; ...
        la    t0, nfac                  ; no: one more facet
        ld    t1, 0(t0)                 ; ...
        li    t2, NFAC                  ; ...
        bgeu  t1, t2, e_f               ; ...
        slli  t2, t1, 2                 ; ...
        la    t3, fac                   ; ...
        add   t3, t3, t2                ; ...
        sw    a0, 0(t3)                 ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, 0(t0)                 ; ...
        j     e_f                       ; ...
e_next:
        lhu   t0, 0(s1)                 ; next record
        add   s1, s1, t0                ; ...
        addi  s0, s0, -1                ; one fewer
        j     entry                     ; ...
e_part:
        la    t0, cursor                ; more parts?
        ld    t0, 0(t0)                 ; ...
        bnez  t0, query                 ; ...
        la    t0, nfiles                ; ...
        ld    t0, 0(t0)                 ; ...
        beqz  t0, none                  ; ...
        la    t0, nfac                  ; then the facets, as "TAG/"
        ld    t0, 0(t0)                 ; ...
        beqz  t0, end                   ; none
        li    s5, 0                     ; every tag, part by part: the facets among them
f_p:
        la    a0, tagbuf                ; ...
        li    a1, 0                     ; ...
        li    a2, 0                     ; ...
        mv    a3, s5                    ; ...
        call  sys_tags2                 ; a0 = how many, a1 = the cursor
        mv    s5, a1                    ; ...
        mv    s0, a0                    ; s0 = records left
        la    s1, tagbuf                ; s1 = record
f_l:
        blez  s0, f_pn                  ; no more in this part
        lwu   a0, 4(s1)                 ; a facet?
        la    a1, fac                   ; ...
        la    t0, nfac                  ; ...
        ld    a2, 0(t0)                 ; ...
        call  id_in                     ; ...
        beqz  a1, f_n                   ; no
        addi  a0, s1, 16                ; its name
        lhu   a1, 2(s1)                 ; ...
        call  out_str                   ; ...
        la    a0, m_sl                  ; "/"
        li    a1, 1                     ; ...
        call  out_str                   ; ...
        call  out_nl                    ; ...
f_n:
        lhu   t0, 0(s1)                 ; next tag
        add   s1, s1, t0                ; ...
        addi  s0, s0, -1                ; ...
        j     f_l                       ; ...
f_pn:
        bnez  s5, f_p                   ; more tags
end:
        li    a0, 0                     ; exit code
        call  sys_exit                  ; flush stdout, end the process
none:
        la    a0, m_none                ; "(no files)"
        li    a1, m_none_e - m_none     ; ...
        call  out_str                   ; ...
        li    a0, 0                     ; exit code
        call  sys_exit                  ; flush stdout, end the process

; id_in(a0 = id, a1 = u32 ids, a2 = how many) -> a1 = 1 if it is among them (a0 kept)
id_in:
        beqz  a2, ii_no                 ; ...
        lwu   t0, 0(a1)                 ; ...
        beq   t0, a0, ii_yes            ; ...
        addi  a1, a1, 4                 ; ...
        addi  a2, a2, -1                ; ...
        j     id_in                     ; ...
ii_yes:
        li    a1, 1                     ; ...
        ret                             ; ...
ii_no:
        li    a1, 0                     ; ...
        ret                             ; ...
fail:
        la    a0, m_err                 ; complain on standard error
        li    a1, m_err_e - m_err       ; ...
        call  err_str                   ; ...
        la    a0, path                  ; the path
        ld    a0, 0(a0)                 ; ...
        la    a1, plen                  ; ...
        ld    a1, 0(a1)                 ; ...
        bnez  a1, f_say                 ; none: the current one (its tags went away)
        la    a0, dir                   ; ...
        call  sys_cwd                   ; a0 = its length
        mv    a1, a0                    ; ...
        la    a0, dir                   ; ...
        bgez  a1, f_say                 ; ...
        li    a1, 0                     ; ...
f_say:
        call  err_str                   ; ...
        la    a0, sys_nl                ; a newline
        li    a1, 1                     ; ...
        call  err_str                   ; ...
        li    a0, 1                     ; exit code
        call  sys_exit                  ; end the process

        .include "../lib/sys.s"         ; the system interface
