; =============================================================================
; ls.s: list the files on the disk, or the files that carry tags
; =============================================================================
;
;   ls                    every file: name (padded to 26 columns), size
;   ls /TAG/TAG...        the files that carry every one of the tags
;   ls /TAG.../NAME       that one file, if it carries the tags
;   ls /TAG/-TAG...       "-TAG": files that do not carry it (ls /src/-demo)
;   ls -t [PATH]          the same, with each file's tags after its size
;
; The file system has no directories: a "directory" is a set of tags (see
; os/servers/fs.s). Asks the file server for the files with sys_query
; (records of 32 bytes: a 24-byte name, zero-padded, and a 64-bit size) and,
; with -t, for each file's tags with sys_tags. Subdirectories are facets:
; after the files come the other tags they carry, as "TAG/" (sys_facets,
; named by sys_tags), the ways to narrow the listing (ls /src: demo/). Prints
; "(no files)" when there are none, and "ls: no such tag or file: PATH"
; (exit code 1) when a component of the path is neither.

        .data                           ; data Local Store
        .align 8                        ; aligned buffers
dir:    .space 128 * 32                 ; the directory records
tagbuf: .space 64 * 32                  ; one file's tag records
args:   .space 512                      ; the argument text
path:   .dword 0                        ; the path's address
plen:   .dword 0                        ; its length (0: every file)
flag_t: .dword 0                        ; -t: show the tags
facets: .dword 0                        ; the facets of the listing (a tag set)
m_none: .ascii "(no files)\n"           ; output text
m_none_e:                               ; end of the text above
m_err:  .ascii "ls: no such tag or file: " ; error text
m_err_e:                                ; end of the text above
m_t:    .ascii "-t"                     ; the option
m_sl:   .ascii "/"                      ; after a facet

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        li    sp, 65536                 ; stack at the top of the D-LS
        call  sys_init                  ; handles and arguments
        la    a0, args                  ; the arguments ...
        call  sys_args                  ; ... a0 = their length
        la    s0, args                  ; s0 = cursor
        add   s1, s0, a0                ; s1 = end
arg:
        mv    a0, s0                    ; the next word
        mv    a1, s1                    ; ...
        call  arg_next                  ; a0 = start, a1 = length, a2 = cursor after
        beqz  a1, query                 ; no more
        mv    s0, a2                    ; advance the cursor
        mv    s2, a0                    ; s2, s3 = the word
        mv    s3, a1                    ; ...
        la    a2, m_t                   ; -t?
        li    a3, 2                     ; ...
        call  str_eq                    ; ...
        beqz  a0, a_path                ; no
        li    t0, 1                     ; yes
        la    t1, flag_t                ; ...
        sd    t0, 0(t1)                 ; ...
        j     arg                       ; ...
a_path:
        la    t0, path                  ; the path (the last one given)
        sd    s2, 0(t0)                 ; ...
        la    t0, plen                  ; ...
        sd    s3, 0(t0)                 ; ...
        j     arg                       ; ...
query:
        la    a0, dir                   ; the files
        la    a1, path                  ; ...
        ld    a1, 0(a1)                 ; ...
        la    a2, plen                  ; ...
        ld    a2, 0(a2)                 ; ...
        call  sys_query                 ; a0 = number of files
        bltz  a0, fail                  ; no such tag or file
        beqz  a0, none                  ; none
        mv    s0, a0                    ; s0 = records left
        call  sys_facets                ; (before another request replaces it)
        la    t0, facets                ; ...
        sd    a0, 0(t0)                 ; ...
        la    s1, dir                   ; s1 = current record
entry:
        mv    a0, s1                    ; the name's length (zero-padded, 24 bytes)
        li    a1, 24                    ; ...
        call  str_len                   ; a0 = length
        mv    s2, a0                    ; s2 = length
        mv    a0, s1                    ; print the name
        mv    a1, s2                    ; ...
        call  out_str                   ; ...
        li    a0, 26                    ; pad it to 26 columns
        sub   a0, a0, s2                ; ...
        call  out_pad                   ; ...
        la    t0, flag_t                ; with the tags?
        ld    t0, 0(t0)                 ; ...
        bnez  t0, e_tags                ; yes
        ld    a0, 24(s1)                ; the size
        call  out_dec                   ; ...
        j     e_end                     ; ...
e_tags:
        ld    a0, 24(s1)                ; the size, in 7 columns
        li    a1, 7                     ; ...
        call  out_decw                  ; ...
        li    a0, 1                     ; a space before the tags
        call  out_pad                   ; ...
        la    a0, tagbuf                ; the file's tags
        mv    a1, s1                    ; ...
        mv    a2, s2                    ; ...
        call  sys_tags                  ; a0 = how many
        mv    s3, a0                    ; s3 = tags left
        la    s4, tagbuf                ; s4 = record
e_tl:
        blez  s3, e_end                 ; no more
        li    a0, 1                     ; a space, then the name
        call  out_pad                   ; ...
        mv    a0, s4                    ; ...
        li    a1, 16                    ; ...
        call  str_len                   ; ...
        mv    a1, a0                    ; ...
        mv    a0, s4                    ; ...
        call  out_str                   ; ...
        addi  s4, s4, 32                ; next tag
        addi  s3, s3, -1                ; ...
        j     e_tl                      ; ...
e_end:
        call  out_nl                    ; end the line
        addi  s1, s1, 32                ; next record
        addi  s0, s0, -1                ; one fewer
        bnez  s0, entry                 ; more
        la    t0, facets                ; then the facets, as "TAG/"
        ld    s5, 0(t0)                 ; s5 = the set
        beqz  s5, end                   ; none
        la    a0, tagbuf                ; every tag, with its number
        li    a1, 0                     ; ...
        li    a2, 0                     ; ...
        call  sys_tags                  ; a0 = how many
        mv    s0, a0                    ; s0 = records left
        la    s1, tagbuf                ; s1 = record
f_l:
        blez  s0, end                   ; no more
        ld    t0, 24(s1)                ; a facet?
        srl   t0, s5, t0                ; ...
        andi  t0, t0, 1                 ; ...
        beqz  t0, f_n                   ; no
        mv    a0, s1                    ; its name
        li    a1, 16                    ; ...
        call  str_len                   ; ...
        mv    a1, a0                    ; ...
        mv    a0, s1                    ; ...
        call  out_str                   ; ...
        la    a0, m_sl                  ; "/"
        li    a1, 1                     ; ...
        call  out_str                   ; ...
        call  out_nl                    ; ...
f_n:
        addi  s1, s1, 32                ; next tag
        addi  s0, s0, -1                ; ...
        j     f_l                       ; ...
end:
        li    a0, 0                     ; exit code
        call  sys_exit                  ; flush stdout, end the process
none:
        la    a0, m_none                ; "(no files)"
        li    a1, m_none_e - m_none     ; ...
        call  out_str                   ; ...
        li    a0, 0                     ; exit code
        call  sys_exit                  ; flush stdout, end the process
fail:
        la    a0, m_err                 ; complain on standard error
        li    a1, m_err_e - m_err       ; ...
        call  err_str                   ; ...
        la    a0, path                  ; the path
        ld    a0, 0(a0)                 ; ...
        la    a1, plen                  ; ...
        ld    a1, 0(a1)                 ; ...
        call  err_str                   ; ...
        la    a0, sys_nl                ; a newline
        li    a1, 1                     ; ...
        call  err_str                   ; ...
        li    a0, 1                     ; exit code
        call  sys_exit                  ; end the process

        .include "../lib/sys.s"         ; the system interface
