; =============================================================================
; cp.s: copy a file
; =============================================================================
;
;   cp SRC DST            DST gets SRC's bytes; a tag path gives it those tags
;   cp -t SRC DST         the same, and DST also gets SRC's tags
;
; Names are unique on the disk, so DST must name another file: `cp a /x/a`
; is refused ("tag a x" gives a the tag; `mv` renames).
;
; SRC is read with sys_open / sys_read and DST written chunk by chunk (opened
; for writing: created, or replaced keeping its tags; the path's tags are
; added, as for `echo hi > /notes/todo`). With -t each of SRC's tags
; (sys_tags2) is then given to DST with sys_tag. Errors go to standard error
; with exit code 1: "cp: no such file: SRC", "cp: same file: SRC DST", "cp:
; cannot write DST".

        .data                           ; data Local Store
        .align 8                        ; aligned buffers
args:   .space 512                      ; the argument text (a command line is at most 440 bytes)
buf:    .space 4096                     ; a chunk of the file
tagbuf: .space 4032                     ; SRC's tag records (-t): one message's worth
tpath:  .space 4040                     ; -t: SRC's tags' names, a zero byte between them
flag_t: .dword 0                        ; -t: copy the tags too
m_use:  .ascii "usage: cp [-t] SRC DST\n" ; error text
m_use_e:                                ; end of the text above
m_no:   .ascii "cp: no such file: "     ; error text
m_no_e:                                 ; end of the text above
m_wr:   .ascii "cp: cannot write "      ; error text
m_wr_e:                                 ; end of the text above
m_same: .ascii "cp: same file: "        ; error text
m_same_e:                               ; end of the text above
m_t:    .ascii "-t"                     ; the option
m_sp:   .ascii " "                      ; between two names

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        call  sys_init                  ; handles and arguments
        la    a0, args                  ; the arguments ...
        call  sys_args                  ; ... a0 = their length
        la    s0, args                  ; s0 = cursor
        add   s1, s0, a0                ; s1 = end
        mv    a0, s0                    ; the first word
        mv    a1, s1                    ; ...
        call  arg_next                  ; a0 = start, a1 = length, a2 = cursor after
        beqz  a1, usage                 ; none
        mv    s0, a2                    ; ...
        mv    s2, a0                    ; s2, s3 = SRC (or -t)
        mv    s3, a1                    ; ...
        la    a2, m_t                   ; -t?
        li    a3, 2                     ; ...
        call  str_eq                    ; ...
        beqz  a0, a_dst                 ; no
        la    t0, flag_t                ; yes
        li    t1, 1                     ; ...
        sd    t1, 0(t0)                 ; ...
        mv    a0, s0                    ; SRC
        mv    a1, s1                    ; ...
        call  arg_next                  ; ...
        beqz  a1, usage                 ; ...
        mv    s0, a2                    ; ...
        mv    s2, a0                    ; ...
        mv    s3, a1                    ; ...
a_dst:
        mv    a0, s0                    ; DST
        mv    a1, s1                    ; ...
        call  arg_next                  ; ...
        beqz  a1, usage                 ; ...
        mv    s0, a2                    ; ...
        mv    s6, a0                    ; s6, s5 = DST
        mv    s5, a1                    ; ...
        mv    a0, s0                    ; nothing after it
        mv    a1, s1                    ; ...
        call  arg_next                  ; ...
        bnez  a1, usage                 ; ...
        mv    a0, s2                    ; the same path: the same file (a name is unique
        mv    a1, s3                    ; in its directory only: /doc/x and /etc/x are two)
        mv    a2, s6                    ; ...
        mv    a3, s5                    ; ...
        call  str_eq                    ; ...
        bnez  a0, same                  ; yes
        mv    a0, s2                    ; does SRC exist?
        mv    a1, s3                    ; ...
        call  sys_stat                  ; a0 = size or < 0
        bltz  a0, nosrc                 ; no such file
        mv    a0, s2                    ; open SRC for reading
        mv    a1, s3                    ; ...
        li    a2, 0                     ; ...
        call  sys_open                  ; a0 = handle or < 0
        bltz  a0, nosrc                 ; ...
        mv    s0, a0                    ; s0 = its handle
        mv    a0, s6                    ; open DST for writing
        mv    a1, s5                    ; ...
        li    a2, 1                     ; ...
        call  sys_open                  ; a0 = handle or < 0
        bltz  a0, nowrite               ; bad name, no room
        mv    s1, a0                    ; s1 = its handle
chunk:
        mv    a0, s0                    ; read a chunk
        la    a1, buf                   ; ...
        li    a2, 4032                  ; ...
        call  sys_read                  ; a0 = bytes
        blez  a0, copied                ; the end of SRC
        mv    s4, a0                    ; s4 = bytes
        mv    a0, s1                    ; write them
        la    a1, buf                   ; ...
        mv    a2, s4                    ; ...
        call  sys_write                 ; a0 = bytes written
        bne   a0, s4, wfail             ; not all of them
        j     chunk                     ; next chunk
copied:
        mv    a0, s0                    ; close SRC
        call  sys_close                 ; ...
        mv    a0, s1                    ; close DST: the file server saves it
        call  sys_close                 ; ...
        la    t0, flag_t                ; and SRC's tags?
        ld    t0, 0(t0)                 ; ...
        beqz  t0, ok                    ; no
        la    a0, tagbuf                ; SRC's tags (one message's worth of them)
        mv    a1, s2                    ; ...
        mv    a2, s3                    ; ...
        li    a3, 0                     ; ...
        call  sys_tags2                 ; a0 = how many
        mv    s0, a0                    ; s0 = records left
        la    s1, tagbuf                ; s1 = record
        la    s4, tpath                 ; s4 = their names, a zero byte between them: DST goes
t_l:
        blez  s0, t_send                ; into the directory of its tags and these in one step
        addi  a1, s1, 16                ; ...
        lhu   a2, 2(s1)                 ; ...
        mv    a0, s4                    ; ...
        call  t_cp                      ; ...
        sb    zero, 0(a0)               ; ...
        addi  s4, a0, 1                 ; ...
        lhu   t0, 0(s1)                 ; next tag
        add   s1, s1, t0                ; ...
        addi  s0, s0, -1                ; ...
        j     t_l                       ; ...
t_send:
        la    a2, tpath                 ; ...
        sub   a3, s4, a2                ; ...
        beqz  a3, ok                    ; (SRC has none)
        mv    a0, s6                    ; ...
        mv    a1, s5                    ; ...
        call  sys_tag                   ; ...
ok:
        li    a0, 0                     ; exit code
        call  sys_exit                  ; flush stdout, end the process
wfail:
        mv    a0, s1                    ; close DST (what was written is kept)
        call  sys_close                 ; ...
nowrite:
        la    a0, m_wr                  ; "cp: cannot write "
        li    a1, m_wr_e - m_wr         ; ...
        call  err_str                   ; ...
        mv    a0, s6                    ; DST
        mv    a1, s5                    ; ...
        j     fail                      ; ...
same:
        la    a0, m_same                ; "cp: same file: SRC DST"
        li    a1, m_same_e - m_same     ; ...
        call  err_str                   ; ...
        mv    a0, s2                    ; ...
        mv    a1, s3                    ; ...
        call  err_str                   ; ...
        la    a0, m_sp                  ; " "
        li    a1, 1                     ; ...
        call  err_str                   ; ...
        mv    a0, s6                    ; DST
        mv    a1, s5                    ; ...
        j     fail                      ; ...
nosrc:
        la    a0, m_no                  ; "cp: no such file: "
        li    a1, m_no_e - m_no         ; ...
fail_src:
        call  err_str                   ; ...
        mv    a0, s2                    ; SRC
        mv    a1, s3                    ; ...
fail:
        call  err_str                   ; ...
        la    a0, sys_nl                ; a newline
        li    a1, 1                     ; ...
        call  err_str                   ; ...
        li    a0, 1                     ; exit code
        call  sys_exit                  ; end the process
usage:
        la    a0, m_use                 ; how to use it
        li    a1, m_use_e - m_use       ; ...
        call  err_str                   ; ...
        li    a0, 2                     ; exit code for a usage error
        call  sys_exit                  ; end the process

; base(a0 = path, a1 = length) -> a0, a1 = its last component (the name)
; t_cp(a0 = to, a1 = from, a2 = bytes) -> a0 = after them
t_cp:
        beqz  a2, tc_r                  ; ...
        lbu   t0, 0(a1)                 ; ...
        sb    t0, 0(a0)                 ; ...
        addi  a0, a0, 1                 ; ...
        addi  a1, a1, 1                 ; ...
        addi  a2, a2, -1                ; ...
        j     t_cp                      ; ...
tc_r:
        ret                             ; ...

base:
        add   t0, a0, a1                ; t0 = the end
        mv    t1, a0                    ; t1 = cursor
        li    t2, '/'                   ; ...
bs_l:
        bgeu  t1, t0, bs_r              ; ...
        lbu   t3, 0(t1)                 ; ...
        addi  t1, t1, 1                 ; ...
        bne   t3, t2, bs_l              ; ...
        mv    a0, t1                    ; after a "/"
        j     bs_l                      ; ...
bs_r:
        sub   a1, t0, a0                ; ...
        ret                             ; done

        .include "../lib/sys.s"         ; the system interface
