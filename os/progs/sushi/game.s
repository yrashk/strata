CF_SIT    = 0                           ; a customer's frames (dat.s: NCUSTF)
CF_BLINK  = 1                           ; ...
CF_WANT   = 2                           ; ...
CF_EAT0   = 3                           ; ...
CF_HAPPY  = 5                           ; ...
