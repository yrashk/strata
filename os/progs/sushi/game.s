; =============================================================================
; game.s: SushiBelt's evening: the belt, the customers, the cooks
; =============================================================================
;
; An evening runs from 17:00 to 22:00 on the clock in the bar, a minute every
; MIN_TICS tics. Customers come in and sit at one of the eight seats behind
; the belt, and each wants one piece of sushi at a time (a bubble shows it),
; one to three pieces in all. The player gives each order to one of the
; three cooks (1 2 3, or a click on the bubble and then on the cook); a cook
; makes the orders in their queue one after another and puts each piece on
; the belt in front of them. A plate rides the belt round (a lap is BELT_L
; tics); a customer who wants that piece takes it as it passes in front of
; them, eats, pays the plate's price and a tip for being quick, and wants
; the next piece or goes home happy. A customer who waits too long leaves
; grumbling. A plate that rides too long first tires and then goes stale
; (flies): a customer who takes a stale plate leaves without paying. A
; click on a plate (or Z for the oldest stale one) sweeps it off the belt,
; at the cost of its fish.
;
; The busy hours: from 18:00 to 18:40 and from 19:30 to 20:30 customers
; come in crowds (the sign by the door says RUSH, and SOON before). From
; the first rush on, some customers order a set (two pieces on a black
; plate, made by one cook), and some are VIPs (a star): they pay double and
; wait half as long. The plates a customer has eaten from stand stacked
; beside them. The first rush of a run opens a card that says all this.
;
; The belt, seen as a path: from the bottom right corner along the bottom
; lane to the left (the cooks put plates there), up the left lane, along
; the top lane to the right (the customers take them there), down the right
; lane. A plate's place is a position on that path, 0 .. BELT_L - 1, and
; moves one pixel a tic (plate_xy turns it into the screen's x and y).

BELT_L    = 744                         ; the path: bottom 302, left 70, top 302, right 70
BELT_TOP  = 372                         ; where the top lane starts on it
