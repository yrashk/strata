POP_X     = 0                           ;   the seat's x (u16)
POP_T     = 2                           ;   tics left (u16)
POP_PRICE = 4                           ;   the plate's price (u16)
POP_TIP   = 6                           ;   the tip (u16)
POP_ROW   = 8                           ;   for the pieces in a row (u16)
POP_SIZE  = 16                          ;   bytes
POP_TICS  = 60                          ; ... for so many tics
CARD_MONEY = 3                          ; g_card: 0..2 a cook's card, 3 how you earn,
