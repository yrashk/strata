; arrive(): the next customer comes in when it is time, to a free seat:
; more often as the evening goes on, and none in the last half hour
arrive: ld    t0, g_min - g(gp)         ; ...
        li    t1, LAST_IN               ; ...
        bge   t0, t1, ar_r              ; ...
        ld    t0, g_next - g(gp)        ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, g_next - g(gp)        ; ...
        bgtz  t0, ar_r                  ; ...
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = seat
        sd    s1, 16(sp)                ; s1 = its record
        li    t0, 1                     ; (no seat free: try again the next tic)
        sd    t0, g_next - g(gp)        ; ...
        li    a0, NSEAT                 ; a free seat, from one chosen at random
        call  rnd_n                     ; ...
        mv    s0, a0                    ; ...
        li    t3, NSEAT                 ; ...
ar_f:   slli  s1, s0, 4                 ; ...
        la    t0, seats                 ; ...
        add   s1, s1, t0                ; ...
        lbu   t0, CU_ST(s1)             ; ...
        beqz  t0, ar_in                 ; ...
        addi  s0, s0, 1                 ; ...
        andi  s0, s0, NSEAT - 1         ; ...
        addi  t3, t3, -1                ; ...
        bnez  t3, ar_f                  ; ...
        j     ar_x                      ; ...
ar_in:  li    a0, NCUST                 ; who: somebody not sitting here already
        call  rnd_n                     ; ...
        li    t3, NCUST                 ; ...
ar_w:   la    t0, seats                 ; ...
ar_wl:  lbu   t1, CU_ST(t0)             ; ...
        beqz  t1, ar_wn                 ; ...
        lbu   t1, CU_TYPE(t0)           ; ...
        beq   t1, a0, ar_wo             ; ...
ar_wn:  addi  t0, t0, CU_SIZE           ; ...
        la    t1, seats + NSEAT * CU_SIZE ; ...
        bltu  t0, t1, ar_wl             ; ...
        j     ar_t                      ; ...
ar_wo:  addi  a0, a0, 1                 ; (sitting here: the next one)
        andi  a0, a0, NCUST - 1         ; ...
        addi  t3, t3, -1                ; ...
        bnez  t3, ar_w                  ; ...
ar_t:   sb    a0, CU_TYPE(s1)           ; ...
        slli  t0, s0, 3                 ; no plates beside them yet; from the first
        la    t1, seatx                 ;   rush on, a VIP now and then
        add   t0, t0, t1                ; ...
        sd    zero, 0(t0)               ; ...
        ld    t1, g_min - g(gp)         ; ...
        li    t2, PART2                 ; ...
        blt   t1, t2, ar_m              ; ...
        li    a0, VIP_IN                ; ...
        call  rnd_n                     ; ...
        bnez  a0, ar_m                  ; ...
        slli  t0, s0, 3                 ; ...
        la    t1, seatx                 ; ...
        add   t0, t0, t1                ; ...
        li    t1, 1                     ; ...
        sb    t1, SX_VIP(t0)            ; ...
ar_m:   li    a0, 3                     ; one to three pieces
        call  rnd_n                     ; ...
        sb    a0, CU_MORE(s1)           ; ...
        mv    a0, s1                    ; the first
        call  order                     ; ...
        ld    t0, g_min - g(gp)         ; patience: less as the evening goes on
        slli  t0, t0, 1                 ; ...
        li    t1, 1400                  ; ...
        sub   t0, t1, t0                ; ...
        li    t1, 850                   ; ...
        bge   t0, t1, ar_p              ; ...
        mv    t0, t1                    ; ...
ar_p:   slli  t1, s0, 3                 ; (half of it for a VIP)
        la    t2, seatx                 ; ...
        add   t1, t1, t2                ; ...
        lbu   t1, SX_VIP(t1)            ; ...
        srl   t0, t0, t1                ; ...
        sh    t0, CU_PMAX(s1)           ; ...
        sh    t0, CU_PAT(s1)            ; ...
        li    t0, ST_RISE               ; ...
        sb    t0, CU_ST(s1)             ; ...
        li    t0, RISE_T                ; ...
        sh    t0, CU_T(s1)              ; ...
        li    a0, 60                    ; the next one
        call  rnd_n                     ; ...
        mv    a1, a0                    ; ...
        call  rush_now                  ; (in a rush, soon)
        li    t0, 1                     ; ...
        bne   a0, t0, ar_q              ; ...
        srli  t0, a1, 1                 ; ...
        addi  t0, t0, RUSH_IN           ; ...
        j     ar_n1                     ; ...
ar_q:   ld    t0, g_min - g(gp)         ; ...
        li    t1, 330                   ; ...
        sub   t0, t1, t0                ; ...
        li    t1, 90                    ; ...
        bge   t0, t1, ar_n              ; ...
        mv    t0, t1                    ; ...
ar_n:   add   t0, t0, a1                ; ...
ar_n1:  sd    t0, g_next - g(gp)        ; ...
        li    a0, SN_BELL               ; ...
        call  snd_play                  ; ...
ar_x:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; pop the frame
ar_r:   ret                             ; done

; order(a0 = a seat's record): they want a piece, chosen at random (from
; the first rush on, now and then a set); it is given to nobody yet
order:  addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    a0, 8(sp)                 ; ...
        ld    t0, g_min - g(gp)         ; ...
        li    t1, PART2                 ; ...
        blt   t0, t1, or_1              ; ...
        li    a0, SET_IN                ; ...
        call  rnd_n                     ; ...
        bnez  a0, or_1                  ; ...
        li    a0, NSET                  ; ...
        call  rnd_n                     ; ...
        addi  a0, a0, SET0              ; ...
        j     or_2                      ; ...
or_1:   li    a0, NKIND1                ; ...
        call  rnd_n                     ; ...
or_2:   ld    t0, 8(sp)                 ; ...
        sb    a0, CU_KIND(t0)           ; ...
        sb    zero, CU_ASG(t0)          ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 16                ; pop the frame
        ret                             ; done

; seats_step(): every customer's tic
seats_step:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = seat
        sd    s1, 16(sp)                ; s1 = its record
        li    s0, 0                     ; ...
        la    s1, seats                 ; ...
ss_l:   lbu   t0, CU_ST(s1)             ; ...
        beqz  t0, ss_n                  ; ...
        li    t1, ST_WAIT               ; waiting: patience runs out
        bne   t0, t1, ss_t              ; ...
        lhu   t0, CU_PAT(s1)            ; ...
        addi  t0, t0, -1                ; ...
        sh    t0, CU_PAT(s1)            ; ...
        bnez  t0, ss_n                  ; ...
        ld    t0, g_nleft - g(gp)       ; ... and they go
        addi  t0, t0, 1                 ; ...
        sd    t0, g_nleft - g(gp)       ; ...
        mv    a0, s0                    ; ...
        call  cross                     ; ...
        j     ss_n                      ; ...
ss_t:   lhu   t1, CU_T(s1)              ; any other state lasts so many tics
        addi  t1, t1, -1                ; ...
        sh    t1, CU_T(s1)              ; ...
        bnez  t1, ss_n                  ; ...
        li    t1, ST_RISE               ; seated: they wait
        bne   t0, t1, ss_e              ; ...
        li    t0, ST_WAIT               ; ...
        sb    t0, CU_ST(s1)             ; ...
        j     ss_n                      ; ...
ss_e:   li    t1, ST_EAT                ; eaten: they pay
        bne   t0, t1, ss_m              ; ...
        lhu   t0, CU_PAY(s1)            ; ...
        ld    t1, g_money - g(gp)       ; ...
        add   t1, t1, t0                ; ...
        sd    t1, g_money - g(gp)       ; ...
        slli  a0, s0, 5                 ; a coin rises
        addi  a0, a0, SEAT_X0 - 4       ; ...
        li    a1, 36                    ; ...
        li    a2, 0                     ; ...
        li    a3, -32768                ; ...
        li    a4, SP_COIN               ; ...
        li    a5, 30                    ; ...
        li    a6, 0                     ; ...
        call  p_spawn                   ; ...
        li    a0, SN_COINS              ; ...
        call  snd_play                  ; ...
        mv    a0, s0                    ; what they paid, rising over them
        call  pop                       ; ...
        lbu   t0, CU_MORE(s1)           ; ... and want the next piece (not after
        beqz  t0, ss_h                  ;   closing time: last orders),
        ld    t1, g_min - g(gp)         ; ...
        li    t2, CLOSE                 ; ...
        bge   t1, t2, ss_h              ; ...
        addi  t0, t0, -1                ; ...
        sb    t0, CU_MORE(s1)           ; ...
        mv    a0, s1                    ; ...
        call  order                     ; ...
        lhu   t0, CU_PMAX(s1)           ; ...
        sh    t0, CU_PAT(s1)            ; ...
        li    t0, ST_WAIT               ; ...
        sb    t0, CU_ST(s1)             ; ...
        j     ss_n                      ; ...
ss_h:   li    t0, ST_HAPPY              ; ... or go home happy
        sb    t0, CU_ST(s1)             ; ...
        li    t0, MOOD_T                ; ...
        sh    t0, CU_T(s1)              ; ...
        ld    t0, g_nhappy - g(gp)      ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, g_nhappy - g(gp)      ; ...
        slli  a0, s0, 5                 ; a heart
        addi  a0, a0, SEAT_X0 + 4       ; ...
        li    a1, 34                    ; ...
        li    a2, 8192                  ; ...
        li    a3, -24576                ; ...
        li    a4, SP_HEART_0            ; ...
        li    a5, MOOD_T                ; ...
        li    a6, -1                    ; ...
        call  p_spawn                   ; ...
        j     ss_n                      ; ...
ss_m:   li    t1, ST_SINK               ; gone
        bne   t0, t1, ss_g              ; ...
        sb    zero, CU_ST(s1)           ; ...
        j     ss_n                      ; ...
ss_g:   li    t1, CF_HAPPY              ; delighted or cross: they go, so
        li    t2, ST_HAPPY              ; ...
        beq   t0, t2, ss_g1             ; ...
        li    t1, CF_ANGRY              ; ...
ss_g1:  sb    t1, CU_FACE(s1)           ; ...
        li    t0, ST_SINK               ; ...
        sb    t0, CU_ST(s1)             ; ...
        li    t0, RISE_T                ; ...
        sh    t0, CU_T(s1)              ; ...
ss_n:   addi  s0, s0, 1                 ; ...
        addi  s1, s1, CU_SIZE           ; ...
        li    t0, NSEAT                 ; ...
        blt   s0, t0, ss_l              ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; cooks_step(): every cook's tic: the next order is begun, the piece made, put
; on the belt in front of the cook when there is room there
cooks_step:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = cook
        sd    s1, 16(sp)                ; s1 = its record
        li    s0, 0                     ; ...
        la    s1, cooks                 ; ...
cs_l:   lhu   t0, CK_FXT(s1)            ; a reaction fades
        beqz  t0, cs_0                  ; ...
        addi  t0, t0, -1                ; ...
        sh    t0, CK_FXT(s1)            ; ...
cs_0:   lbu   t0, CK_ST(s1)             ; ...
        bnez  t0, cs_w                  ; ...
        lbu   t1, CK_N(s1)              ; idle, with an order: begin it
        beqz  t1, cs_n                  ; ...
        lbu   a0, CK_Q(s1)              ; its making: how long this cook takes for it
        mv    a1, s0                    ; ...
        call  cook_tics                 ; ...
        sh    a0, CK_DUR(s1)            ; ...
        sh    zero, CK_T(s1)            ; ...
        li    t0, 1                     ; ...
        sb    t0, CK_ST(s1)             ; ...
        li    a0, SN_CHOP               ; ...
        call  snd_play                  ; ...
        j     cs_n                      ; ...
cs_w:   lhu   t1, CK_T(s1)              ; ...
        addi  t1, t1, 1                 ; ...
        sh    t1, CK_T(s1)              ; ...
        li    t2, 1                     ; making it
        bne   t0, t2, cs_p              ; ...
        lhu   t2, CK_DUR(s1)            ; ...
        bltu  t1, t2, cs_n              ; ...
        li    t0, 2                     ; made: onto the belt
        sb    t0, CK_ST(s1)             ; ...
        sh    zero, CK_T(s1)            ; ...
        j     cs_n                      ; ...
cs_p:   li    t2, PLACE_T               ; putting it on the belt: room there?
        bltu  t1, t2, cs_n              ; ...
        slli  t3, s0, 4                 ; t3 = the position in front of the cook:
        slli  t4, s0, 6                 ;   311 - x
        add   t3, t3, t4                ; ...
        li    t4, 311 - COOK_X0         ; ...
        sub   t3, t4, t3                ; ...
        la    t0, plates                ; no plate within 22 pixels of it,
        li    t5, -1                    ; t5 = a free plate
cs_r:   lbu   t1, PL_ON(t0)             ; ...
        bnez  t1, cs_r1                 ; ...
        mv    t5, t0                    ; ...
        j     cs_rn                     ; ...
cs_r1:  lhu   t1, PL_POS(t0)            ; ...
        sub   t1, t1, t3                ; ...
        addi  t1, t1, 22                ; ...
        li    t2, 44                    ; ...
        bltu  t1, t2, cs_n              ; (no room: the cook waits)
cs_rn:  addi  t0, t0, PL_SIZE           ; ...
        la    t1, plates + NPLATE * PL_SIZE ; ...
        bltu  t0, t1, cs_r              ; ...
        bltz  t5, cs_n                  ; (no plate free: the cook waits)
        sh    t3, PL_POS(t5)            ; the plate
        sh    zero, PL_AGE(t5)          ; ...
        lbu   t0, CK_Q(s1)              ; ...
        sb    t0, PL_KIND(t5)           ; ...
        li    t0, 1                     ; ...
        sb    t0, PL_ON(t5)             ; ...
        lbu   t0, CK_Q + 2(s1)          ; the queue moves up
        sb    t0, CK_Q(s1)              ; ...
        lbu   t0, CK_Q + 3(s1)          ; ...
        sb    t0, CK_Q + 1(s1)          ; ...
        lbu   t0, CK_Q + 4(s1)          ; ...
        sb    t0, CK_Q + 2(s1)          ; ...
        lbu   t0, CK_Q + 5(s1)          ; ...
        sb    t0, CK_Q + 3(s1)          ; ...
        lbu   t0, CK_N(s1)              ; ...
        addi  t0, t0, -1                ; ...
        sb    t0, CK_N(s1)              ; ...
        sb    zero, CK_ST(s1)           ; ...
        li    a0, SN_CLACK              ; ...
        call  snd_play                  ; ...
cs_n:   addi  s0, s0, 1                 ; ...
        addi  s1, s1, CK_SIZE           ; ...
        li    t0, NCOOK                 ; ...
        blt   s0, t0, cs_l              ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; cook_tics(a0 = sushi, a1 = cook) -> a0 = tics the cook takes to make it
; (a set: both its pieces). Clobbers t0, t1, t4, t5.
cook_tics:
        mv    t4, a0                    ; t4 = a piece, t5 = the next (-1: none)
        li    t5, -1                    ; ...
        li    t0, SET0                  ; ...
        bltu  a0, t0, ct_0              ; ...
        addi  t0, a0, -SET0             ; ...
        slli  t0, t0, 1                 ; ...
        la    t1, res + R_SETP          ; ...
        add   t0, t0, t1                ; ...
        lbu   t4, 0(t0)                 ; ...
        lbu   t5, 1(t0)                 ; ...
ct_0:   li    a0, 0                     ; ...
ct_l:   slli  t0, t4, 2                 ; how it is made
        la    t1, res + R_KIND          ; ...
        add   t0, t0, t1                ; ...
        lbu   t0, 1(t0)                 ; ...
        slli  t0, t0, 1                 ; ... and how long that takes the cook
        slli  t1, a1, 3                 ; ...
        add   t0, t0, t1                ; ...
        la    t1, res + R_COOK          ; ...
        add   t0, t0, t1                ; ...
        lhu   t0, 0(t0)                 ; ...
        add   a0, a0, t0                ; ...
        bltz  t5, ct_r                  ; ...
        mv    t4, t5                    ; ...
        li    t5, -1                    ; ...
        j     ct_l                      ; ...
ct_r:   ret                             ; done

; ---- what the player does -----------------------------------------------------

; sel_check(): the order chosen is still one being waited for, and one not
; given to a cook yet unless the player chose it; else the next not given
; yet is chosen, if any
sel_check:
        ld    a0, g_sel - g(gp)         ; ...
        bltz  a0, sc_f                  ; ...
        slli  t0, a0, 4                 ; ...
        la    t1, seats                 ; ...
        add   t0, t0, t1                ; ...
        lbu   t1, CU_ST(t0)             ; ...
        li    t2, ST_WAIT               ; ...
        bne   t1, t2, sc_f              ; ...
        ld    t1, g_selman - g(gp)      ; (the player chose it: it stays)
        bnez  t1, sc_r                  ; ...
        lbu   t1, CU_ASG(t0)            ; (given already: one not given, if any)
        beqz  t1, sc_r                  ; ...
sc_f:   sd    zero, g_selman - g(gp)    ; ...
        li    a1, 1                     ; ...
; sel_next(a0 = seat, a1 = 1 right or -1 left): the next waiting customer
; that way (from a0, not counting it) whose order is not given yet, or none
; (g_sel -1: every order is given). At sn_p with a2 = 0: the next waiting
; one, given or not (the arrows: the player may give an order twice).
sel_next:
        li    a2, 1                     ; not given yet
sn_p:   mv    t0, a0                    ; ...
        li    t3, NSEAT                 ; ...
sn_l:   add   t0, t0, a1                ; ...
        andi  t0, t0, NSEAT - 1         ; ...
        slli  t1, t0, 4                 ; ...
        la    t2, seats                 ; ...
        add   t1, t1, t2                ; ...
        lbu   t2, CU_ST(t1)             ; ...
        li    t4, ST_WAIT               ; ...
        bne   t2, t4, sn_n              ; ...
        beqz  a2, sn_y                  ; ...
        lbu   t2, CU_ASG(t1)            ; ...
        beqz  t2, sn_y                  ; ...
sn_n:   addi  t3, t3, -1                ; ...
        bnez  t3, sn_l                  ; ...
        li    t0, -1                    ; ...
sn_y:   sd    t0, g_sel - g(gp)         ; ...
sc_r:   ret                             ; done

; assign(a0 = cook): the chosen order goes into that cook's queue (unless it
; is full: the cook says so); the next order not given yet is chosen
assign: ld    t0, g_sel - g(gp)         ; ...
        bltz  t0, as_r                  ; ...
        slli  t1, a0, 4                 ; t1 = the cook
        la    t2, cooks                 ; ...
        add   t1, t1, t2                ; ...
        lbu   t2, CK_N(t1)              ; ...
        li    t3, QMAX                  ; ...
        bltu  t2, t3, as_q              ; ...
        li    t2, CF_OOPS               ; full
        sb    t2, CK_FX(t1)             ; ...
        li    t2, 30                    ; ...
        sh    t2, CK_FXT(t1)            ; ...
        li    a0, SN_OOPS               ; ...
        j     snd_play                  ; ...
