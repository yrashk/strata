RUSH_T    = 120                         ; tics the banner of a rush shows

MIN_TICS  = 20                          ; tics a minute of the evening
LAST_IN   = 270                         ; minutes after 17:00 the last customer comes in
CLOSE     = 300                         ; ... and the bar closes (22:00)
CLOSE_MAX = 330                         ; ... and the last customer has surely gone

        .data                           ; D-LS
