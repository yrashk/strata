SEAT_Y    = 69                          ; the customers' bottom row (the belt hides below)
CU_ST     = 0                           ; a seat: its state (ST_*) (u8)
CU_TYPE   = 1                           ; who sits there (u8)
CU_KIND   = 2                           ; the piece they want (u8)
CU_MORE   = 3                           ; pieces they want after it (u8)
CU_ASG    = 4                           ; the cook given the order, + 1 (0: none yet) (u8)
CU_FACE   = 5                           ; their frame while they sink (u8)
