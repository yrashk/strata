SX_VIP    = 0                           ; a seat's extras (seatx): 1 a VIP (u8)
SX_N      = 1                           ; plates stacked beside them (u8)
SX_STK    = 2                           ; ... their colours, from the bottom (STKMAX x u8)
SX_SIZE   = 8                           ; bytes
STKMAX    = 6                           ; plates a stack holds
PART2     = 60                          ; minutes after 17:00 sets and VIPs begin (the first rush)
