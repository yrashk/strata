; ev_new(): a new evening: nobody in, nothing on the belt, the clock at 17:00
ev_new: la    t0, g_belt                ; the evening's globals, g_belt .. g_flasht
        la    t1, g_evend               ; ...
en_g:   sd    zero, 0(t0)               ; ...
        addi  t0, t0, 8                 ; ...
        bltu  t0, t1, en_g              ; ...
        la    t0, plates                ; the plates, seats and cooks (one after another)
        la    t1, tbuf                  ; ...
en_t:   sd    zero, 0(t0)               ; ...
        addi  t0, t0, 8                 ; ...
        bltu  t0, t1, en_t              ; ...
        li    t0, 40                    ; the first customer is at the door
        sd    t0, g_next - g(gp)        ; ...
        li    t0, -1                    ; no order chosen, no card open
        sd    t0, g_sel - g(gp)         ; ...
        sd    t0, g_card - g(gp)        ; ...
        j     p_clear                   ; ...

; ---- the tic ----------------------------------------------------------------

; ev_step(): a tic of the evening
ev_step:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        li    t0, 1                     ; everything moves
        sd    t0, g_dirty - g(gp)       ; ...
        sd    t0, g_bardirty - g(gp)    ; ...
        ld    t0, g_flasht - g(gp)      ; ...
        beqz  t0, es_0                  ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, g_flasht - g(gp)      ; ...
es_0:   ld    t0, g_rusht - g(gp)       ; ...
        beqz  t0, es_0a                 ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, g_rusht - g(gp)       ; ...
es_0a:  la    t0, pops                  ; what was paid rises and fades
        li    t1, NPOP                  ; ...
es_p:   lhu   t2, POP_T(t0)             ; ...
        beqz  t2, es_pn                 ; ...
        addi  t2, t2, -1                ; ...
        sh    t2, POP_T(t0)             ; ...
es_pn:  addi  t0, t0, POP_SIZE          ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, es_p                  ; ...
        ld    t0, g_belt - g(gp)        ; the belt
        addi  t0, t0, 1                 ; ...
        sd    t0, g_belt - g(gp)        ; ...
        call  belt_step                 ; ...
        call  rush_now                  ; (a rush before the minute?)
        sd    a0, 8(sp)                 ; ...
        ld    t0, g_mint - g(gp)        ; the clock
        addi  t0, t0, 1                 ; ...
        li    t1, MIN_TICS              ; ...
        blt   t0, t1, es_1              ; ...
        ld    t1, g_min - g(gp)         ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, g_min - g(gp)         ; ...
        li    t0, 0                     ; ...
es_1:   sd    t0, g_mint - g(gp)        ; ...
        call  rush_now                  ; a rush begins
        li    t0, 1                     ; ...
        bne   a0, t0, es_2              ; ...
        ld    t1, 8(sp)                 ; ...
        beq   t1, t0, es_2              ; ...
        call  rush_begin                ; ...
es_2:   call  arrive                    ; ...
        call  seats_step                ; ...
        call  cooks_step                ; ...
        call  sel_check                 ; ...
        ld    t0, g_min - g(gp)         ; closing time, and everybody has gone?
        li    t1, CLOSE_MAX             ; ...
        bge   t0, t1, es_end            ; ...
        li    t1, CLOSE                 ; ...
        blt   t0, t1, es_r              ; ...
        la    t0, seats                 ; ...
        li    t1, NSEAT                 ; ...
es_s:   lbu   t2, CU_ST(t0)             ; ...
        bnez  t2, es_r                  ; ...
        addi  t0, t0, CU_SIZE           ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, es_s                  ; ...
es_end: la    t0, seats                 ; those still here are settled: who is eating
        li    t1, NSEAT                 ;   pays and goes happy, who still waits
es_x:   lbu   t2, CU_ST(t0)             ;   goes without
        li    t3, ST_EAT                ; ...
        bne   t2, t3, es_x1             ; ...
        lhu   t2, CU_PAY(t0)            ; ...
        ld    t3, g_money - g(gp)       ; ...
        add   t3, t3, t2                ; ...
        sd    t3, g_money - g(gp)       ; ...
        ld    t3, g_nhappy - g(gp)      ; ...
        addi  t3, t3, 1                 ; ...
        sd    t3, g_nhappy - g(gp)      ; ...
        j     es_x2                     ; ...
es_x1:  addi  t2, t2, -ST_RISE          ; (sitting down or waiting)
        li    t3, ST_WAIT - ST_RISE + 1 ; ...
        bgeu  t2, t3, es_x2             ; ...
        ld    t3, g_nleft - g(gp)       ; ...
        addi  t3, t3, 1                 ; ...
        sd    t3, g_nleft - g(gp)       ; ...
es_x2:  sb    zero, CU_ST(t0)           ; ...
        addi  t0, t0, CU_SIZE           ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, es_x                  ; ...
        la    t0, pops                  ; nothing rising over the results
        li    t1, NPOP                  ; ...
es_y:   sh    zero, POP_T(t0)           ; ...
        addi  t0, t0, POP_SIZE          ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, es_y                  ; ...
        call  p_clear                   ; ...
        li    t0, M_RESULT              ; the results
        sd    t0, g_mode - g(gp)        ; ...
        li    a0, SN_GONG               ; ...
        call  snd_play                  ; ...
es_r:   ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 16                ; pop the frame
        ret                             ; done

; rush_now() -> a0 = 1 in a rush hour, 2 in the SOON minutes before one, 0
; else. Clobbers t0..t2.
rush_now:
        ld    t0, g_min - g(gp)         ; ...
        la    t1, rushes                ; ...
        li    a0, 0                     ; ...
rn_l:   lhu   t2, 0(t1)                 ; when it begins
        beqz  t2, rn_r                  ; ...
        bge   t0, t2, rn_1              ; ...
        addi  t2, t2, -SOON             ; not yet: soon?
        blt   t0, t2, rn_n              ; ...
        li    a0, 2                     ; ...
        ret                             ; ...
rn_1:   lhu   t2, 2(t1)                 ; begun: over?
        bge   t0, t2, rn_n              ; ...
        li    a0, 1                     ; ...
        ret                             ; ...
rn_n:   addi  t1, t1, 4                 ; ...
        j     rn_l                      ; ...
rn_r:   ret                             ; done

; rush_begin(): a rush hour begins: the banner, the bell, the first of the
; crowd at the door; the first of a run opens the card that tells of it
rush_begin:
        li    t0, RUSH_T                ; ...
        sd    t0, g_rusht - g(gp)       ; ...
        li    t0, 1                     ; ...
        sd    t0, g_next - g(gp)        ; ...
        ld    t0, g_seen - g(gp)        ; ...
        bnez  t0, rb_s                  ; ...
        li    t0, 1                     ; ...
        sd    t0, g_seen - g(gp)        ; ...
        li    a0, CARD_BUSY             ; ...
        j     card_open                 ; ...
rb_s:   li    a0, SN_BELL               ; ...
        j     snd_play                  ; ...

; belt_step(): the plates ride one pixel on; a customer who wants a plate in
; front of them takes it
belt_step:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = plate
        la    s0, plates                ; ...
bs_l:   lbu   t0, PL_ON(s0)             ; ...
        beqz  t0, bs_n                  ; ...
        lhu   t0, PL_AGE(s0)            ; older (it stops counting at 65535)
        addi  t0, t0, 1                 ; ...
        srli  t1, t0, 16                ; ...
        bnez  t1, bs_a                  ; ...
        sh    t0, PL_AGE(s0)            ; ...
bs_a:   lhu   t0, PL_POS(s0)            ; further on
        addi  t0, t0, 1                 ; ...
        li    t1, BELT_L                ; ...
        bltu  t0, t1, bs_p              ; ...
        li    t0, 0                     ; ...
bs_p:   sh    t0, PL_POS(s0)            ; ...
        addi  t1, t0, -BELT_TOP         ; on the top lane, in front of a seat?
        li    t2, BELT_RT - BELT_TOP    ; ...
        bgeu  t1, t2, bs_n              ; ...
        addi  t1, t0, -(BELT_TOP - 9 + SEAT_X0) ; (x = position - (BELT_TOP - 9))
        bltz  t1, bs_n                  ; ...
        andi  t2, t1, 31                ; ...
        bnez  t2, bs_n                  ; ...
        srli  a0, t1, 5                 ; a0 = the seat
        li    t2, NSEAT                 ; ...
        bgeu  a0, t2, bs_n              ; ...
        slli  a1, a0, 4                 ; a1 = its record
        la    t2, seats                 ; ...
        add   a1, a1, t2                ; ...
        lbu   t2, CU_ST(a1)             ; waiting, for this piece?
        li    t3, ST_WAIT               ; ...
        bne   t2, t3, bs_n              ; ...
        lbu   t2, CU_KIND(a1)           ; ...
        lbu   t3, PL_KIND(s0)           ; ...
        bne   t2, t3, bs_n              ; ...
        mv    a2, s0                    ; ...
        call  take                      ; ...
bs_n:   addi  s0, s0, PL_SIZE           ; ...
        la    t0, plates + NPLATE * PL_SIZE ; ...
        bltu  s0, t0, bs_l              ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 16                ; pop the frame
        ret                             ; done

; take(a0 = seat, a1 = its record, a2 = the plate): the customer takes it. A
; stale one sends them away cross; any other is eaten, and paid for: the
; price, a tip for a fresh piece by how much patience is left, ten yen for
; every piece served in a row before it (ten at most)
take:   addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = seat
        sd    s1, 16(sp)                ; s1 = its record
        sd    s2, 24(sp)                ; s2 = the plate
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        mv    s2, a2                    ; ...
        sb    zero, PL_ON(s2)           ; off the belt
        lhu   t0, PL_AGE(s2)            ; stale?
        li    t1, AGE_STALE             ; ...
        bltu  t0, t1, tk_ok             ; ...
        ld    t0, g_nstale - g(gp)      ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, g_nstale - g(gp)      ; ...
        mv    a0, s0                    ; ...
        call  cross                     ; ...
        j     tk_r                      ; ...
tk_ok:  lbu   t0, CU_ASG(s1)            ; not given to a cook: the plate was made for
        bnez  t0, tk_p                  ;   somebody else waiting for this piece, whose
        lbu   t1, PL_KIND(s2)           ;   order is now no one's again (the first such)
        la    t0, seats                 ; ...
tk_w:   lbu   t2, CU_ST(t0)             ; ...
        li    t3, ST_WAIT               ; ...
        bne   t2, t3, tk_wn             ; ...
        lbu   t2, CU_ASG(t0)            ; ...
        beqz  t2, tk_wn                 ; ...
        lbu   t2, CU_KIND(t0)           ; ...
        bne   t2, t1, tk_wn             ; ...
        sb    zero, CU_ASG(t0)          ; ...
        j     tk_p                      ; ...
tk_wn:  addi  t0, t0, CU_SIZE           ; ...
        la    t2, seats + NSEAT * CU_SIZE ; ...
        bltu  t0, t2, tk_w              ; ...
tk_p:   lbu   t0, PL_KIND(s2)           ; the price
        slli  t0, t0, 2                 ; ...
        la    t1, res + R_KIND          ; ...
        add   t0, t0, t1                ; ...
        lhu   t2, 2(t0)                 ; t2 = price
        lbu   t0, 0(t0)                 ; t0 = the plate's colour
        slli  t4, s0, 3                 ; t4 = the seat's extras
        la    t1, seatx                 ; ...
        add   t4, t4, t1                ; ...
        lbu   t1, SX_VIP(t4)            ; a VIP pays double
        sll   t2, t2, t1                ; ...
        lbu   t1, SX_N(t4)              ; the plate goes on their stack
        li    t3, STKMAX                ; ...
        bgeu  t1, t3, tk_q              ; ...
        add   t3, t4, t1                ; ...
        sb    t0, SX_STK(t3)            ; ...
        addi  t1, t1, 1                 ; ...
        sb    t1, SX_N(t4)              ; ...
tk_q:   li    t3, 0                     ; t3 = the tip: none for a tired plate,
        lhu   t0, PL_AGE(s2)            ; ...
        li    t1, AGE_TIRED             ; ...
        bgeu  t0, t1, tk_t              ; ...
        lhu   t0, CU_PAT(s1)            ;   else price * patience left / all of it / 2,
        mul   t3, t2, t0                ;   in tens
        lhu   t0, CU_PMAX(s1)           ; ...
        slli  t0, t0, 1                 ; ...
        divu  t3, t3, t0                ; ...
        li    t0, 10                    ; ...
        divu  t3, t3, t0                ; ...
        mul   t3, t3, t0                ; ...
tk_t:   ld    t0, g_tips - g(gp)        ; ...
        add   t0, t0, t3                ; ...
        sd    t0, g_tips - g(gp)        ; ...
        add   t2, t2, t3                ; ...
        slli  t4, s0, 2                 ; t4 = the seat's pays (what is shown rising)
        la    t5, pays                  ; ...
        add   t4, t4, t5                ; ...
        sh    t3, 0(t4)                 ; ...
        ld    t0, g_streak - g(gp)      ; the pieces served in a row before it
        li    t1, 10                    ; ...
        ble   t0, t1, tk_s              ; ...
        mv    t0, t1                    ; ...
tk_s:   mul   t0, t0, t1                ; ...
        sh    t0, 2(t4)                 ; ...
        add   t2, t2, t0                ; ...
        sh    t2, CU_PAY(s1)            ; ...
        ld    t0, g_streak - g(gp)      ; one more in a row
        addi  t0, t0, 1                 ; ...
        sd    t0, g_streak - g(gp)      ; ...
        ld    t0, g_nserved - g(gp)     ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, g_nserved - g(gp)     ; ...
        li    t0, ST_EAT                ; ...
        sb    t0, CU_ST(s1)             ; ...
        li    t0, EAT_T                 ; ...
        sh    t0, CU_T(s1)              ; ...
        li    a0, SN_YUM                ; ...
        call  snd_play                  ; ...
        ld    t0, g_streak - g(gp)      ; every fifth in a row, the cooks are proud
        li    t1, 5                     ; ...
        remu  t0, t0, t1                ; ...
        bnez  t0, tk_r                  ; ...
        la    t0, cooks                 ; ...
        li    t1, NCOOK                 ; ...
        li    t2, CF_CHEER              ; ...
        li    t3, 40                    ; ...
tk_c:   sb    t2, CK_FX(t0)             ; ...
        sh    t3, CK_FXT(t0)            ; ...
        addi  t0, t0, CK_SIZE           ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, tk_c                  ; ...
tk_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

; cross(a0 = seat): the customer there is cross and goes; the run of pieces
; served in a row is over
cross:  addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        slli  t0, a0, 4                 ; ...
