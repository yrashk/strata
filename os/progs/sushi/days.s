; =============================================================================
; days.s: SushiBelt's days: the till, the shop between evenings, the file
; =============================================================================
;
; The bar keeps what each evening took in its till (g_bank). After the
; results, the shop: seven things to buy with it, each once, each for good
; (g_upg, a bit each: UP_*). Then the next day's evening, a little busier
; than the last (arrive: game.s). The restaurant (the day, the till, what
; was bought) is kept in /ws/sushi.sav: read when the program starts, written
; when an evening ends and when something is bought. A demo touches the file
; only when its first step says so (DK_FILE), so that its picture does not
; depend on it.
;
; The file is read before the window is opened. A window's client has the
; window server's endpoint where the file server's was (wsclient.s), so
; while it is open the file is written by looking `fs` up into that
; register, and `ws` again afterwards, as kira's garden does.

UP_TEA    = 0                           ; the tea station: a quarter more patience
UP_RICE   = 1                           ; the rice cooker: every piece a fifth quicker
UP_FAST   = 2                           ; the fast belt: half again as fast
UP_ICE    = 3                           ; the chilled belt: plates fresh twice as long
UP_IKURA  = 4                           ; salmon roe on the menu
UP_UNAGI  = 5                           ; eel
UP_URA    = 6                           ; inside-out rolls
NUP       = 7                           ; things to buy
UP_FISH   = UP_IKURA                    ; the first of the fish (they are in the order of
                                        ;   KINDS, after its first NKIND1)

SV_MAGIC  = 0                           ; the file: "SUSHISV1"
SV_DAY    = 8                           ; ... the day to come
SV_BANK   = 16                          ; ... the till
SV_UPG    = 24                          ; ... what was bought
SV_SIZE   = 32                          ; bytes

SH_Y0     = 53                          ; the shop: its first line's row (9 apart)

        .data                           ; D-LS
        .align 8                        ; dwords
svbuf:    .space SV_SIZE                ; the file's bytes
sv_magic: .ascii "SUSHISV1"             ; its first word
sv_name:  .ascii "/ws/sushi.sav"        ; its name
sv_name_e:                              ; (its end)
sv_fs:    .ascii "fs"                   ; the file server's name
sv_ws:    .ascii "ws"                   ; the window server's
        .align 8                        ; (halfwords)
up_price: .half 1500, 2000, 2500, 2000, 2500, 3000, 3500 ; what each costs
s_up0:    .ascii "TEA STATION\0"
s_up0a:   .ascii "CUSTOMERS WAIT 1/4 LONGER.\0"
s_up1:    .ascii "RICE COOKER\0"
s_up1a:   .ascii "EVERY PIECE 1/5 QUICKER.\0"
s_up2:    .ascii "FAST BELT\0"
s_up2a:   .ascii "THE BELT: 1.5 TIMES AS FAST.\0"
s_up3:    .ascii "CHILLED BELT\0"
s_up3a:   .ascii "PLATES FRESH TWICE AS LONG.\0"
s_up4:    .ascii "IKURA\0"
s_up4a:   .ascii "SALMON ROE. RED PLATE $200\0"
s_up5:    .ascii "UNAGI\0"
s_up5a:   .ascii "EEL NIGIRI. GOLD PLATE $300\0"
s_up6:    .ascii "URAMAKI\0"
s_up6a:   .ascii "INSIDE-OUT ROLL. GOLD $300\0"
        .align 8                        ; ...
up_text:  .dword s_up0, s_up0a         ; each: its name, what it does
        .dword s_up1, s_up1a         ; ...
        .dword s_up2, s_up2a         ; ...
        .dword s_up3, s_up3a         ; ...
        .dword s_up4, s_up4a         ; ...
        .dword s_up5, s_up5a         ; ...
        .dword s_up6, s_up6a         ; ...
s_till:   .ascii "IN THE TILL: \0"      ; the shop
s_owned:  .ascii "OURS\0"               ; ...
s_buy:    .ascii "B: BUY  SPACE: DAY \0" ; ...
s_day:    .ascii "DAY \0"               ; the title
s_newbar: .ascii "N: A NEW BAR\0"       ; ...
        .align 8                        ; ...
        .text                           ; code

; ---- the file ---------------------------------------------------------------

; fs_on() -> a0 = 0, or < 0: the file server's endpoint where the window
; server's is
fs_on:  la    a0, sv_fs                 ; ...
        li    a1, 2                     ; ...
        li    a2, WC_EP                 ; ...
        j     sys_lookup                ; ...

; fs_off(): the window server's endpoint back
fs_off: addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        la    a0, sv_ws                 ; ...
        li    a1, 2                     ; ...
        li    a2, WC_EP                 ; ...
        call  sys_lookup                ; ...
        cclear c6                       ; (c6 stays empty: the band comes back there)
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; sv_load(): the restaurant from its file, if there is one (and the file is
; ours to use: g_file), before the window is opened
sv_load:
        ld    t0, g_file - g(gp)        ; ...
        beqz  t0, sl_r0                 ; ...
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = handle
        la    a0, sv_name               ; ...
        li    a1, sv_name_e - sv_name   ; ...
        li    a2, 0                     ; ...
        call  sys_open                  ; ...
        mv    s0, a0                    ; ...
        bltz  a0, sl_x                  ; ...
        la    t0, svbuf                 ; (nothing read: no magic)
        sd    zero, SV_MAGIC(t0)        ; ...
        la    a1, svbuf                 ; ...
        li    a2, SV_SIZE               ; ...
        call  sys_read                  ; ...
        mv    a0, s0                    ; ...
        call  sys_close                 ; ...
        la    t0, svbuf                 ; ours?
        ld    t1, SV_MAGIC(t0)          ; ...
        la    t2, sv_magic              ; ...
        ld    t2, 0(t2)                 ; ...
        bne   t1, t2, sl_x              ; ...
        ld    t1, SV_DAY(t0)            ; ...
        blez  t1, sl_x                  ; ...
        sd    t1, g_day - g(gp)         ; ...
        ld    t1, SV_BANK(t0)           ; ...
        sd    t1, g_bank - g(gp)        ; ...
        ld    t1, SV_UPG(t0)            ; ...
        sd    t1, g_upg - g(gp)         ; ...
sl_x:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 16                ; pop the frame
sl_r0:  ret                             ; done

; sv_save(): the restaurant into its file (if the file is ours to use)
sv_save:
        ld    t0, g_file - g(gp)        ; ...
        beqz  t0, sl_r0                 ; ...
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = handle
        la    t0, svbuf                 ; ...
        la    t1, sv_magic              ; ...
        ld    t1, 0(t1)                 ; ...
        sd    t1, SV_MAGIC(t0)          ; ...
        ld    t1, g_day - g(gp)         ; ...
        sd    t1, SV_DAY(t0)            ; ...
        ld    t1, g_bank - g(gp)        ; ...
        sd    t1, SV_BANK(t0)           ; ...
        ld    t1, g_upg - g(gp)         ; ...
        sd    t1, SV_UPG(t0)            ; ...
        call  fs_on                     ; ...
        bnez  a0, ss_ws                 ; ...
        la    a0, sv_name               ; ...
        li    a1, sv_name_e - sv_name   ; ...
        li    a2, 1                     ; ...
        call  sys_open                  ; ...
        mv    s0, a0                    ; ...
        bltz  a0, ss_ws                 ; ...
        la    a1, svbuf                 ; ...
        li    a2, SV_SIZE               ; ...
        call  sys_write                 ; ...
        mv    a0, s0                    ; ...
        call  sys_close                 ; ...
ss_ws:  call  fs_off                    ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 16                ; pop the frame
        ret                             ; done

; ---- the days -----------------------------------------------------------------

; day_end(): the evening's takings go into the till; tomorrow is the next
; day; the restaurant is kept
day_end:
        ld    t0, g_bank - g(gp)        ; ...
        ld    t1, g_money - g(gp)       ; ...
        add   t0, t0, t1                ; ...
        sd    t0, g_bank - g(gp)        ; ...
        ld    t0, g_day - g(gp)         ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, g_day - g(gp)         ; ...
        j     sv_save                   ; ...

; bar_new(): a new restaurant: day 1, an empty till, nothing bought
bar_new:
        li    t0, 1                     ; ...
        sd    t0, g_day - g(gp)         ; ...
        sd    zero, g_bank - g(gp)      ; ...
        sd    zero, g_upg - g(gp)       ; ...
        li    t0, 1                     ; ...
        sd    t0, g_dirty - g(gp)       ; ...
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        call  sv_save                   ; ...
        li    a0, SN_WHOOSH             ; ...
        call  snd_play                  ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; has(a0 = UP_*) -> a0 = 1 if it was bought. Clobbers t0.
has:    ld    t0, g_upg - g(gp)         ; ...
        srl   a0, t0, a0                ; ...
        andi  a0, a0, 1                 ; ...
        ret                             ; done

; menu_new(): the kinds of sushi ordered this evening: the first five, and
; each fish bought (g_menu, g_nmenu)
menu_new:
        la    t0, g_menu                ; ...
        li    t1, 0                     ; t1 = kind
mn_f:   sb    t1, 0(t0)                 ; ...
        addi  t0, t0, 1                 ; ...
        addi  t1, t1, 1                 ; ...
        li    t2, NKIND1                ; ...
        blt   t1, t2, mn_f              ; ...
        ld    t3, g_upg - g(gp)         ; ...
        srli  t3, t3, UP_FISH           ; t3 = the fish bought, a bit each
mn_u:   andi  t2, t3, 1                 ; ...
        beqz  t2, mn_n                  ; ...
        sb    t1, 0(t0)                 ; ...
        addi  t0, t0, 1                 ; ...
mn_n:   srli  t3, t3, 1                 ; ...
        addi  t1, t1, 1                 ; ...
        li    t2, NKIND                 ; ...
        blt   t1, t2, mn_u              ; ...
        la    t1, g_menu                ; ...
        sub   t0, t0, t1                ; ...
        sd    t0, g_nmenu - g(gp)       ; ...
        ret                             ; done

; ---- the shop -----------------------------------------------------------------

; shop_key(a0 = key): 1..7 or the arrows choose a thing, B or Enter buys
; it, Space opens the bar for the next day
shop_key:
        li    t0, ' '                   ; ...
        beq   a0, t0, start             ; ...
        li    t0, 'b'                   ; ...
        beq   a0, t0, buy               ; ...
        li    t0, 10                    ; ...
        beq   a0, t0, buy               ; ...
        li    t0, 13                    ; ...
        beq   a0, t0, buy               ; ...
        addi  t0, a0, -'1'              ; ...
        li    t1, NUP                   ; ...
        bltu  t0, t1, sk_s              ; ...
        ld    t0, g_shsel - g(gp)       ; the arrows
        li    t1, K_UP                  ; ...
        beq   a0, t1, sk_u              ; ...
        li    t1, K_LEFT                ; ...
        beq   a0, t1, sk_u              ; ...
        li    t1, K_DOWN                ; ...
        beq   a0, t1, sk_d              ; ...
        li    t1, K_RIGHT               ; ...
        beq   a0, t1, sk_d              ; ...
        ret                             ; ...
sk_u:   addi  t0, t0, NUP - 1           ; ...
        j     sk_m                      ; ...
sk_d:   addi  t0, t0, 1                 ; ...
sk_m:   li    t1, NUP                   ; ...
        remu  t0, t0, t1                ; ...
sk_s:   sd    t0, g_shsel - g(gp)       ; ...
        li    t0, 1                     ; ...
        sd    t0, g_dirty - g(gp)       ; ...
        li    a0, SN_POP                ; ...
        j     snd_play                  ; ...

; shop_click(a0 = x, a1 = y): a click on a thing chooses it, a second buys
; it; on the line at the foot, the next day
shop_click:
        li    t0, SH_Y0 + 9 * NUP + 11  ; ...
        bge   a1, t0, start             ; ...
        addi  t0, a1, -(SH_Y0 - 1)      ; ...
        bltz  t0, sc2_r                 ; ...
        li    t1, 9                     ; ...
        divu  t0, t0, t1                ; ...
        li    t1, NUP                   ; ...
        bgeu  t0, t1, sc2_r             ; ...
        ld    t1, g_shsel - g(gp)       ; ...
        beq   t0, t1, buy               ; ...
        j     sk_s                      ; ...
sc2_r:  ret                             ; done

; buy(): the chosen thing, if it is not ours yet and the till holds its
; price; the restaurant is kept
buy:    ld    t0, g_shsel - g(gp)       ; ...
        ld    t1, g_upg - g(gp)         ; ...
        srl   t2, t1, t0                ; ...
        andi  t2, t2, 1                 ; ...
        bnez  t2, by_no                 ; ...
        slli  t2, t0, 1                 ; ...
        la    t3, up_price              ; ...
        add   t2, t2, t3                ; ...
        lhu   t2, 0(t2)                 ; ...
        ld    t3, g_bank - g(gp)        ; ...
        bltu  t3, t2, by_no             ; ...
        sub   t3, t3, t2                ; ...
        sd    t3, g_bank - g(gp)        ; ...
        li    t2, 1                     ; ...
        sll   t2, t2, t0                ; ...
        or    t1, t1, t2                ; ...
        sd    t1, g_upg - g(gp)         ; ...
        li    t0, 1                     ; ...
        sd    t0, g_dirty - g(gp)       ; ...
        sd    t0, g_bardirty - g(gp)    ; ...
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        li    a0, SN_COINS              ; ...
        call  snd_play                  ; ...
        call  sv_save                   ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; ...
by_no:  li    a0, SN_OOPS               ; ours already, or too dear
        j     snd_play                  ; ...

; shop_slab(): the shop on its board over the room: the till, each thing
; with its price (or OURS), what the chosen one does, how to go on
shop_slab:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = thing
        sd    s1, 16(sp)                ; s1 = its row
        sd    s2, 24(sp)                ; s2 = its texts
        li    a0, SP_PANEL              ; ...
        li    a1, 60                    ; ...
        li    a2, 24                    ; ...
        call  r_blit                    ; ...
        la    a0, s_till                ; IN THE TILL: $N
        li    a1, 88                    ; ...
        li    a2, 43                    ; ...
        call  r_text                    ; ...
        ld    a0, g_bank - g(gp)        ; ...
        li    a1, '$'                   ; ...
        call  num_text                  ; ...
        li    a1, 88 + 13 * 6           ; ...
        li    a2, 43                    ; ...
        call  r_text                    ; ...
        li    s0, 0                     ; the things
        li    s1, SH_Y0                 ; ...
        la    s2, up_text               ; ...
sh_l:   ld    t0, g_shsel - g(gp)       ; the chosen one on a strip
        bne   t0, s0, sh_1              ; ...
        li    a0, 74                    ; ...
        addi  a1, s1, -1                ; ...
        li    a2, 172                   ; ...
        li    a3, 10                    ; ...
        li    a4, C_GOLD                ; ...
        call  r_fill                    ; ...
sh_1:   addi  a0, s0, 1                 ; its number
        li    a1, 0                     ; ...
        call  num_text                  ; ...
        li    a1, 76                    ; ...
        mv    a2, s1                    ; ...
        call  r_text                    ; ...
        ld    a0, 0(s2)                 ; its name
        li    a1, 88                    ; ...
        mv    a2, s1                    ; ...
        call  r_text                    ; ...
        mv    a0, s0                    ; its price, or OURS
        call  has                       ; ...
        mv    t2, a0                    ; ...
        la    a0, s_owned               ; ...
        li    a1, 4                     ; ...
        bnez  t2, sh_2                  ; ...
        slli  t0, s0, 1                 ; ...
        la    t1, up_price              ; ...
        add   t0, t0, t1                ; ...
        lhu   a0, 0(t0)                 ; ...
        li    a1, '$'                   ; ...
        call  num_text                  ; ...
sh_2:   li    t0, 6                     ; (at the right)
        mul   t0, a1, t0                ; ...
        li    a1, 244                   ; ...
        sub   a1, a1, t0                ; ...
        mv    a2, s1                    ; ...
        call  r_text                    ; ...
        addi  s0, s0, 1                 ; ...
        addi  s1, s1, 9                 ; ...
        addi  s2, s2, 16                ; ...
        li    t0, NUP                   ; ...
        blt   s0, t0, sh_l              ; ...
        ld    t0, g_shsel - g(gp)       ; what the chosen one does
        slli  t0, t0, 4                 ; ...
        la    t1, up_text               ; ...
        add   s2, t0, t1                ; ...
        ld    a0, 8(s2)                 ; ...
        li    a1, 76                    ; ...
        li    a2, SH_Y0 + 9 * NUP + 2   ; ...
        call  r_text                    ; ...
        la    a0, s_buy                 ; B: BUY  SPACE: DAY N
        call  day_text                  ; ...
        li    a1, 160 - 63              ; ...
        li    a2, SH_Y0 + 9 * NUP + 13  ; ...
        call  r_text                    ; ...
sh_x:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

; day_text(a0 = text) -> a0 = tbuf: the text, then the day's number.
; Clobbers t0..t3, a1.
day_text:
        la    t0, tbuf                  ; ...
dt_c:   lbu   t1, 0(a0)                 ; ...
        beqz  t1, dt_n                  ; ...
        sb    t1, 0(t0)                 ; ...
        addi  a0, a0, 1                 ; ...
        addi  t0, t0, 1                 ; ...
        j     dt_c                      ; ...
dt_n:   ld    a0, g_day - g(gp)         ; the number, its digits from the last
        mv    t3, t0                    ; ...
        li    t1, 10                    ; ...
dt_d:   remu  t2, a0, t1                ; (counting them)
        divu  a0, a0, t1                ; ...
        addi  t3, t3, 1                 ; ...
        bnez  a0, dt_d                  ; ...
        sb    zero, 0(t3)               ; ...
        ld    a0, g_day - g(gp)         ; ...
dt_w:   remu  t2, a0, t1                ; ...
        divu  a0, a0, t1                ; ...
        addi  t2, t2, '0'               ; ...
        addi  t3, t3, -1                ; ...
        sb    t2, 0(t3)                 ; ...
        bnez  a0, dt_w                  ; ...
        la    a0, tbuf                  ; ...
        ret                             ; done

; title_day(): on the title, past the first day: DAY N, the till, how to
; begin again
title_day:
        ld    t0, g_day - g(gp)         ; ...
        li    t1, 1                     ; ...
        ble   t0, t1, td_r              ; ...
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        li    a0, 104                   ; ...
        li    a1, 136                   ; ...
        li    a2, 112                   ; ...
        li    a3, 19                    ; ...
        li    a4, C_INK                 ; ...
        call  r_fill                    ; ...
        la    a0, s_day                 ; ...
        call  day_text                  ; ...
        li    a1, 108                   ; ...
        li    a2, 137                   ; ...
        call  r_text                    ; ...
        ld    a0, g_bank - g(gp)        ; ...
        li    a1, '$'                   ; ...
        call  num_text                  ; ...
        li    t0, 6                     ; ...
        mul   t0, a1, t0                ; ...
        li    a1, 212                   ; ...
        sub   a1, a1, t0                ; ...
        li    a2, 137                   ; ...
        call  r_text                    ; ...
        la    a0, s_newbar              ; ...
        li    a1, 108                   ; ...
        li    a2, 146                   ; ...
        call  r_text                    ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
td_r:   ret                             ; done
