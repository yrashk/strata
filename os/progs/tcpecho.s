; =============================================================================
; tcpecho.s: a TCP echo server
; =============================================================================
;
;   tcpecho [PORT [COUNT]]
;
; Listens on PORT (7 by default) and serves one connection after another:
; everything a client sends comes back, until the client closes. Exits after
; COUNT connections (0, the default: never). Exit status 0, 1 on failure.

        .data                           ; data Local Store
        .align 8                        ; ...
buf:    .space 4096                     ; what a client sent
port:   .dword 7                        ; ...
count:  .dword 0                        ; ...
lsn:    .dword 0                        ; the listener's handle
s_nonet: .ascii "tcpecho: no network server\n" ; ...
s_nonet_e:
s_fail: .ascii "tcpecho: cannot listen: " ; ...
s_fail_e:
        .align 8                        ; ...

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        call  sys_init                  ; ...
        call  sys_cmdline               ; s1 = cursor, s2 = end
        add   s2, a0, a1                ; ...
        mv    a1, s2                    ; skip the program's name
        call  arg_next                  ; ...
        mv    a0, a2                    ; the port
        mv    a1, s2                    ; ...
        call  arg_next                  ; ...
        mv    s1, a2                    ; ...
        beqz  a1, m_go                  ; ...
        call  str_num                   ; ...
        blez  a0, m_go                  ; (not a number: the default)
        la    t0, port                  ; ...
        sd    a0, 0(t0)                 ; ...
        mv    a0, s1                    ; the count
        mv    a1, s2                    ; ...
        call  arg_next                  ; ...
        beqz  a1, m_go                  ; ...
        call  str_num                   ; ...
        bltz  a0, m_go                  ; ...
        la    t0, count                 ; ...
        sd    a0, 0(t0)                 ; ...
m_go:
        call  net_init                  ; the network server
        bnez  a0, m_nonet               ; ...
        la    a0, port                  ; listen
        ld    a0, 0(a0)                 ; ...
        call  net_listen                ; ...
        bltz  a0, m_fail                ; ...
        la    t0, lsn                   ; ...
        sd    a0, 0(t0)                 ; ...
next:
        la    a0, lsn                   ; the next client
        ld    a0, 0(a0)                 ; ...
        li    a1, 0                     ; ...
        call  net_accept                ; s3 = its handle
        bltz  a0, m_end                 ; ...
        mv    s3, a0                    ; ...
echo:
        mv    a0, s3                    ; what it sends ...
        la    a1, buf                   ; ...
        li    a2, 4032                  ; ...
        call  sys_read                  ; ...
        blez  a0, done1                 ; (it closed)
        mv    a2, a0                    ; ... goes back
        mv    a0, s3                    ; ...
        la    a1, buf                   ; ...
        call  sys_write                 ; ...
        bgtz  a0, echo                  ; ...
done1:
        mv    a0, s3                    ; ...
        call  sys_close                 ; ...
        la    t0, count                 ; enough?
        ld    t1, 0(t0)                 ; ...
        beqz  t1, next                  ; (0: never)
        addi  t1, t1, -1                ; ...
        sd    t1, 0(t0)                 ; ...
        bnez  t1, next                  ; ...
m_end:
        la    a0, lsn                   ; ...
        ld    a0, 0(a0)                 ; ...
        call  sys_close                 ; ...
        li    a0, 0                     ; ...
        call  sys_exit                  ; ...
m_fail:
        mv    s3, a0                    ; ...
        la    a0, s_fail                ; ...
        li    a1, s_fail_e - s_fail     ; ...
        call  out_str                   ; ...
        mv    a0, s3                    ; ...
        call  out_sdec                  ; ...
        call  out_nl                    ; ...
        call  out_flush                 ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...
m_nonet:
        la    a0, s_nonet               ; ...
        li    a1, s_nonet_e - s_nonet   ; ...
        call  err_str                   ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...

        .include "../lib/sys.s"         ; the program library
