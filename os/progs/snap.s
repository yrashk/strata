; =============================================================================
; snap.s: snapshots of the disk
; =============================================================================
;
;   snap                  the snapshots: name, and the commit each one is
;   snap NAME             take one: the whole disk as it is now, under NAME
;                         (1..32 bytes). Nothing is copied: the store keeps
;                         the pages the snapshot shows until it is deleted
;   snap -d NAME          delete it: the pages only it showed are free again
;
; A snapshot is read through a path whose first component is "@NAME":
;   ls /@monday/src       cat /@monday/notes       cp /@monday/notes notes
; (the last brings an old version back). A snapshot cannot be written.
; The file server does the work (SNAP, os/servers/fsops.s); `df` shows the
; space a snapshot keeps as used.

OP_SNAP = 45                            ; fs: snapshots

        .data                           ; data Local Store
        .align 8                        ; aligned buffers
args:   .space 512                      ; the argument text
recs:   .space 4096                     ; the snapshots: {u64 commit, name[32]}
m_d:    .ascii "-d"                     ; the option
m_none: .ascii "(no snapshots)\n"       ; texts
m_none_e:
m_com:  .ascii "commit "                ; ...
m_com_e:
m_take: .ascii "snap: cannot take (a name of 1..32 bytes, not taken yet): "
m_take_e:
m_del:  .ascii "snap: no such snapshot: "
m_del_e:
m_use:  .ascii "usage: snap [NAME | -d NAME]\n"
m_use_e:

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        call  sys_init                  ; handles and arguments
        la    a0, args                  ; the arguments ...
        call  sys_args                  ; ... a0 = their length
        la    t0, args                  ; the first word
        add   s1, t0, a0                ; s1 = the end
        mv    a1, s1                    ; ...
        mv    a0, t0                    ; ...
        call  arg_next                  ; a0 = start, a1 = length, a2 = after it
        beqz  a1, list                  ; none: list them
        mv    s2, a0                    ; s2, s3 = the word
        mv    s3, a1                    ; ...
        mv    s4, a2                    ; ...
        li    s5, 0                     ; s5 = the mode: take
        la    a2, m_d                   ; -d NAME?
        li    a3, 2                     ; ...
        call  str_eq                    ; ...
        beqz  a0, do                    ; ...
        li    s5, 1                     ; delete
        mv    a0, s4                    ; ...
        mv    a1, s1                    ; ...
        call  arg_next                  ; ...
        beqz  a1, usage                 ; ...
        mv    s2, a0                    ; ...
        mv    s3, a1                    ; ...
do:
        mv    a0, s2                    ; the name -> the request
        mv    a1, s3                    ; ...
        call  sys_put                   ; ...
        li    a0, 2                     ; fs
        li    a1, OP_SNAP               ; ...
        li    a2, 0                     ; ...
        mv    a3, s3                    ; ...
        mv    a4, s5                    ; ...
        call  sys_msg                   ; ...
        beqz  a0, done                  ; ...
        la    a0, m_take                ; ...
        li    a1, m_take_e - m_take     ; ...
        beqz  s5, fail                  ; ...
        la    a0, m_del                 ; ...
        li    a1, m_del_e - m_del       ; ...
fail:
        call  err_str                   ; the message, the name, a newline
        mv    a0, s2                    ; ...
        mv    a1, s3                    ; ...
        call  err_str                   ; ...
        la    a0, sys_nl                ; ...
        li    a1, 1                     ; ...
        call  err_str                   ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...
list:
        li    a0, 2                     ; fs
        li    a1, OP_SNAP               ; ...
        li    a2, 0                     ; ...
        li    a3, 0                     ; ...
        li    a4, 2                     ; list
        call  sys_msg                   ; a0 = how many
        blez  a0, none                  ; ...
        mv    s0, a0                    ; s0 = records left
        li    t0, 40                    ; ...
        mul   a1, a0, t0                ; ...
        la    a0, recs                  ; ...
        call  sys_get                   ; ...
        la    s1, recs                  ; s1 = the record
l_l:
        addi  a0, s1, 8                 ; its name
        li    a1, 32                    ; ...
        call  str_len                   ; ...
        mv    s2, a0                    ; ...
        mv    a1, a0                    ; ...
        addi  a0, s1, 8                 ; ...
        call  out_str                   ; ...
        li    a0, 26                    ; padded to 26 columns
        sub   a0, a0, s2                ; ...
        bgtz  a0, l_p                   ; ...
        li    a0, 1                     ; ...
l_p:
        call  out_pad                   ; ...
        la    a0, m_com                 ; ...
        li    a1, m_com_e - m_com       ; ...
        call  out_str                   ; ...
        ld    a0, 0(s1)                 ; ...
        call  out_dec                   ; ...
        call  out_nl                    ; ...
        addi  s1, s1, 40                ; ...
        addi  s0, s0, -1                ; ...
        bnez  s0, l_l                   ; ...
        j     done                      ; ...
none:
        la    a0, m_none                ; ...
        li    a1, m_none_e - m_none     ; ...
        call  out_str                   ; ...
done:
        li    a0, 0                     ; exit code
        call  sys_exit                  ; flush stdout, end the process
usage:
        la    a0, m_use                 ; ...
        li    a1, m_use_e - m_use       ; ...
        call  err_str                   ; ...
        li    a0, 2                     ; ...
        call  sys_exit                  ; ...

        .include "../lib/sys.s"         ; the system interface
