        li    t2, 1                     ; ...
        addi  t0, a0, -164              ; ...
        bgeu  t0, t1, cl_r              ; ...
cl_m1:  addi  t0, a1, -48               ; ...
        li    t1, 56                    ; ...
        bltu  t0, t1, menu_go           ; ...
        addi  t2, t2, 2                 ; ...
        addi  t0, a1, -108              ; ...
        bltu  t0, t1, menu_go           ; ...
cl_r:   ret                             ; done
; menu_go(t2 = button 0..3): that activity (they are numbered as the buttons)
