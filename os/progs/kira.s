; =============================================================================
; kira.s: Princess Kira: gentle games for a small child, in a window
; =============================================================================
;
;   kira            (from a shell in a terminal, or the palette: Alt+Space)
;
; A client of the window server (os/lib/wsclient.s): a menu and four
; activities, one at a time (os/progs/PLAN-kira.md):
;   Friends   Kira walks through her castle and garden and finds her seven
;             animal friends, who follow her to a picnic (kira/friends.s).
;             Every game has a new world (kira/world.s), seen from above
;             or through her eyes (kira/eyes.s).
;   Garden    seeds, a watering can, flowers, butterflies (kira/garden.s);
;             the garden is kept in a file.
;   Paint     three colouring pages and ten paints (kira/paint.s).
;   Music     a xylophone, the friends' voices, four songs (kira/music.s).
; There are no enemies, no timer and no way to lose. The art is drawn by
; tools/kira-art.py and converted, with the sounds, by tools/kira-assets.py
; into the file /ws/kira.dat, which is read at start.
;
; The mouse does everything: a click presses a button of the menu or of the
; bar under the picture, sends Kira to a place, plants, paints, strikes a
; bar. So does the keyboard: the arrows walk Kira, or move a hand that
; Space presses; 1..4 choose from the menu, and in an activity its tools,
; paints or notes; M or Backspace goes back to the menu, Q quits. In
; Friends Space (or V, or Tab) changes between the view from above and the
; one through her eyes.
;
; The screen is wdoom's (320 x 200 palette indices drawn in ten slabs of 32
; columns, scaled by a whole factor into the band: kira/draw.s), but a frame
; is drawn only when something changed. The window is as large as its tile;
; while it does not have the focus the program waits in EVENT.
;
; gfx.s is not included (its strips and display lists would cost 7 KiB of
; D-LS): the surface descriptor's layout, which wsclient.s needs, is below.

S_CAP    = 0                            ; os/lib/gfx.s's surface descriptor: register
S_OFF    = 8                            ; offset of pixel (0, 0)
S_W      = 16                           ; width
S_H      = 24                           ; height
S_STRIDE = 32                           ; bytes per row
S_SIZE   = 48                           ; bytes per descriptor
TIC_US   = 28571                        ; a tic in the clock's ticks (microseconds): 35 a second
M_MENU   = 0                            ; activities: the menu
M_FRIENDS = 1                           ; find the friends
M_GARDEN = 2                            ; plant the garden
M_PAINT  = 3                            ; colour a page
M_MUSIC  = 4                            ; play the xylophone
DK_CLICK = 0xfe                         ; in a demo: a click (x / 2 and y follow)
DK_ALL   = 0xfd                         ; ... and a jump to the game's end
DK_LOOP  = 0xfb                         ; ... what follows, up to DK_END, N times (N, 0 follow)
DK_END   = 0xfc                         ; ...
HAND_D   = 8                            ; pixels an arrow key moves the hand
BORDER   = 0x00d8c4f0                   ; the window around the picture: lilac

        .text                           ; instruction Local Store
_start: j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program

        .include "kira/dat.s"           ; the data file's layout
KEEP     = (F_SIZE + 4095) & ~4095      ; the top of the arena: kira.dat's far block
        .include "kira/draw.s"          ; the screen
        .include "kira/world.s"         ; the world, made anew for every game
        .include "kira/friends.s"       ; find the friends
        .include "kira/eyes.s"          ; ... seen through Kira's eyes
        .include "kira/garden.s"        ; plant the garden
        .include "kira/paint.s"         ; colour a page
        .include "kira/music.s"         ; play the xylophone
        .include "wdoom/sound.s"        ; the sounds: wdoom's mixer
        .include "../lib/sys.s"         ; the program library
        .include "../lib/wsclient.s"    ; the window server's protocol

        .data                           ; D-LS
        .align 8                        ; dwords
g:                                      ; the globals (gp points here)
g_mode:   .dword 0                      ; the activity (M_*)
g_tic:    .dword 0                      ; tics since the start
g_last:   .dword 0                      ; the clock at the last tic
g_seed:   .dword 20261113               ; the random numbers' state
g_bardirty: .dword 1                    ; the bar is to be drawn
g_dirty:  .dword 1                      ; the view is to be drawn
g_sx0:    .dword 0                      ; the slab being drawn: its first column
g_py0:    .dword 0                      ; the pass: its first row on the 320 x 200 screen
g_ph:     .dword 0                      ; ... and rows
g_stride: .dword 0                      ; bytes between rows in the band
g_scale:  .dword 0                      ; the factor: 1..3 (0: the window is too small)
g_ox:     .dword 0                      ; where the picture is in the window
g_oy:     .dword 0                      ; ...
g_grp:    .dword 0                      ; slabs of the view the band holds
g_keepb:  .dword 0                      ; arena offset of the far block (= the band's size)
g_sil:    .dword 0                      ; r_blit draws silhouettes of this colour (0: sprites)
g_esc:    .dword 0                      ; keys: 1 after ESC, 2 after ESC [
g_btn:    .dword 0                      ; the pointer's buttons at its last event
g_paused: .dword 0                      ; the window lost the focus
g_quit:   .dword 0                      ; time to go
g_curx:   .dword 160                    ; the hand that the arrow keys move
g_cury:   .dword 100                    ; ...
g_curon:  .dword 0                      ; ... is shown (the keyboard was used last)
g_msg:    .dword -1                     ; the message: a word's sprite (-1: none)
g_msgn:   .dword -1                     ; ... the numeral before it (-1: none)
g_msgt:   .dword 0                      ; ... tics it stays (-1: until taken away)
g_msgq:   .dword -1                     ; ... the word shown after it (-1: none)
g_tune:   .dword 0                      ; the song being played: its next note (0: none)
g_tunet:  .dword 0                      ; ... tics since the note before
g_demo:   .dword 0                      ; `kira demo N`: the next step of the demo (0: no demo)
g_dleft:  .dword 0                      ; ... and tics left before its key
g_dt0:    .dword 0                      ; the clock when the demo started
g_dmark:  .dword 0                      ; a demo's loop: its first step
g_dloop:  .dword 0                      ; ... and how many times it is still to be played
f_px:     .dword 0                      ; friends: Kira's position, 16.16 (a cell's middle is .5)
f_py:     .dword 0                      ; ...
f_dir:    .dword 0                      ; the way she faces (K_UP ..)
f_move:   .dword 0                      ; tics left of her step
f_dx:     .dword 0                      ; what she moves in each
f_dy:     .dword 0                      ; ...
f_want:   .dword 0                      ; the arrow pressed last (0: none)
f_path:   .dword 0                      ; she is walking to a clicked cell (f_flow)
f_edge:   .dword 0                      ; ... and on from it over the screen's edge, this way
f_view:   .dword 0                      ; 0: seen from above, 1: through her eyes
f_ang:    .dword 0                      ; the angle she looks at, 0..2047 (0: east, 512: south)
f_turn:   .dword 0                      ; tics left of her turn
f_dang:   .dword 0                      ; what she turns in each
f_wturn:  .dword 0                      ; a turn asked for: -1 left, 1 right
f_keep:   .dword 0                      ; the step asked for is a step back: she does not turn
f_picx:   .dword 0                      ; the picnic blanket's cell
f_picy:   .dword 0                      ; ...
w_next:   .dword 0                      ; world.s: where the next thing's record goes
e_dirx:   .dword 0                      ; eyes.s: the view's direction (a unit vector, 16.16)
e_diry:   .dword 0                      ; ...
e_plx:    .dword 0                      ; the screen plane: the direction turned right
e_ply:    .dword 0                      ; ...
e_nvis:   .dword 0                      ; visible things
gd_tool:  .dword 0                      ; garden.s: the tool in her hand
gd_nbl:   .dword 0                      ; flowers in bloom
gd_joy:   .dword 0                      ; tics her delight still lasts
gd_chg:   .dword 0                      ; the garden changed since it was saved
gd_vis:   .dword -1                     ; the friend walking by (-1: none)
gd_vx:    .dword 0                      ; ... and where
pt_page:  .dword 0                      ; paint.s: the page
pt_col:   .dword 0                      ; ... and the paint in use
f_scrx:   .dword 0                      ; the screen shown: its first cell
f_scry:   .dword 0                      ; ...
f_found:  .dword 0                      ; friends found
f_state:  .dword 0                      ; 1: the party
f_party:  .dword 0                      ; tics of it
k_dmsg:   .ascii "kira: demo: "         ; what is said at the demo's end
k_dnum:   .space 40                     ; ... "N frames in N ms\n"
k_dfr:    .ascii " frames in \0"        ; (its pieces)
k_dms:    .ascii " ms\n\0"              ; ...
        .align 8                        ; ...
res:      .space R_SIZE                 ; the data file's resident block (dat.s)
k_title:  .ascii "KIRA\0\0\0\0"         ; the window's title
k_dat:    .ascii "/ws/kira.dat"         ; the data file
k_dat_e:                                ; (its end)
k_nows:   .ascii "kira: no window server (run ws first)\n"
k_nows_e:                               ; (its end)
k_nodat:  .ascii "kira: cannot read /ws/kira.dat\n"
k_nodat_e:                              ; (its end)
        .align 8                        ; ...
        .text                           ; code

main:
        call  sys_init                  ; handles
        la    gp, g                     ; the globals
        clen  t0, c0                    ; the arena: the band, then the far block
        li    t1, KEEP                  ; ...
        sub   t0, t0, t1                ; ...
        sd    t0, g_keepb - g(gp)       ; ...
        call  load_dat                  ; the data and the garden (before the window:
        beqz  a0, m_arg                 ;   the server's endpoint takes the place of fs's)
        la    a0, k_nodat               ; ...
        li    a1, k_nodat_e - k_nodat   ; ...
        j     m_fail                    ; ...
m_arg:  la    a0, slab                  ; `kira demo N`: play demo N (dat.s: R_DEMO)
        call  sys_args                  ; ...
        beqz  a0, m_seed                ; ...
        la    t0, slab                  ; ...
        lbu   t1, 0(t0)                 ; ...
        li    t2, 'd'                   ; ...
        bne   t1, t2, m_seed            ; ...
        add   t0, t0, a0                ; its number is the last character (1 if none)
        lbu   t1, -1(t0)                ; ...
        addi  t1, t1, -'1'              ; ...
        li    t2, 8                     ; ...
        bltu  t1, t2, m_d1              ; ...
        li    t1, 0                     ; ...
m_d1:   slli  t1, t1, 1                 ; ...
        la    t0, res + R_DEMO          ; ...
        add   t1, t1, t0                ; ...
        lhu   t1, 0(t1)                 ; ...
        add   t0, t0, t1                ; ...
        sd    t0, g_demo - g(gp)        ; ...
        j     m_gard                    ; (its random numbers start from the fixed seed)
m_seed: call  sys_now                   ; every run has other worlds
        ld    t0, g_seed - g(gp)        ; ...
        xor   t0, t0, a0                ; ...
        sd    t0, g_seed - g(gp)        ; ...
m_gard: call  gd_load                   ; ...
        call  pt_init                   ; ...
        la    t0, wc_keep               ; (the library's idea of the band agrees)
        li    t1, KEEP                  ; ...
        sd    t1, 0(t0)                 ; ...
        la    a0, k_title               ; our window (events are polled: no flags)
        li    a1, 0                     ; ...
        call  wc_open                   ; ...
        bgtz  a0, m_go                  ; ...
        la    a0, k_nows                ; no server
        li    a1, k_nows_e - k_nows     ; ...
m_fail: call  err_str                   ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...
m_go:   call  sys_now                   ; (a demo is timed)
        sd    a0, g_dt0 - g(gp)         ; ...
        ld    t0, g_demo - g(gp)        ; (and silent)
        bnez  t0, m_go2                 ; ...
        call  snd_open                  ; the sound device, if there is one
m_go2:  call  e_init                    ; the floors' flats
        call  geom                      ; where the picture goes
        call  fr_init                   ; the friends hide
        call  sys_now                   ; time starts now
        sd    a0, g_last - g(gp)        ; ...
m_loop: ld    t0, g_quit - g(gp)        ; ...
        bnez  t0, m_end                 ; ...
        li    a0, 1                     ; an event? (do not block)
        li    a1, 0                     ; ...
        call  wc_event                  ; ...
        li    t0, -3                    ; none
        beq   a0, t0, m_time            ; ...
        bnez  a0, m_end                 ; the window is gone
        call  ev_handle                 ; ...
        j     m_loop                    ; ...
m_time: ld    t0, g_paused - g(gp)      ; ...
        beqz  t0, m_run                 ; ...
        call  m_show                    ; paused: the picture as it stands,
        li    a0, 0                     ; ... then wait for an event
        li    a1, 0                     ; ...
        call  wc_event                  ; ...
        bnez  a0, m_end                 ; ...
        call  ev_handle                 ; ...
        call  sys_now                   ; (no tics are owed for the pause)
        sd    a0, g_last - g(gp)        ; ...
        j     m_loop                    ; ...
m_run:  ld    t0, g_demo - g(gp)        ; the demo: a tic a frame, whatever the clock says
        beqz  t0, m_clk                 ; ...
        call  demo                      ; ...
        call  step                      ; ...
        j     m_draw                    ; ...
m_clk:  call  sys_now                   ; tics due?
        ld    t0, g_last - g(gp)        ; ...
        sub   t1, a0, t0                ; ...
        li    t2, TIC_US                ; ...
        bgeu  t1, t2, m_tics            ; ...
        ld    t3, g_dirty - g(gp)       ; none: a frame anyway (a resize, a key)?
        ld    t4, g_bardirty - g(gp)    ; ...
        or    t3, t3, t4                ; ...
        bnez  t3, m_draw                ; ...
        sub   a1, t2, t1                ; wait for the next tic, or an event
        li    a0, 0                     ; ...
        call  wc_event                  ; ...
        li    t0, -8                    ; (the time passed)
        beq   a0, t0, m_loop            ; ...
        bnez  a0, m_end                 ; ...
        call  ev_handle                 ; ...
        j     m_loop                    ; ...
m_tics: divu  s0, t1, t2                ; s0 = tics due
        mul   t3, s0, t2                ; ...
        add   t0, t0, t3                ; ...
        sd    t0, g_last - g(gp)        ; ...
        li    t3, 4                     ; (after a long frame: four at most)
        bleu  s0, t3, m_t1              ; ...
        mv    s0, t3                    ; ...
m_t1:   call  step                      ; ...
        addi  s0, s0, -1                ; ...
        bnez  s0, m_t1                  ; ...
m_draw: call  snd_pump                  ; the sounds, then the picture
        call  m_show                    ; ...
        j     m_loop                    ; ...
m_end:  call  gd_save                   ; the garden is kept
        call  wc_close                  ; the window goes
        li    a0, 0                     ; ...
        call  sys_exit                  ; ...

; m_show(): draw what changed: the view (and with it the bar, if it did),
; or the bar alone
m_show: addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        ld    t0, g_dirty - g(gp)       ; ...
        beqz  t0, mw_b                  ; ...
        sd    zero, g_dirty - g(gp)     ; ...
        call  r_frame                   ; ...
        j     mw_r                      ; ...
mw_b:   ld    t0, g_bardirty - g(gp)    ; ...
        beqz  t0, mw_r                  ; ...
        sd    zero, g_bardirty - g(gp)  ; ...
        ld    t0, g_scale - g(gp)       ; ...
        beqz  t0, mw_r                  ; ...
        call  r_bar                     ; ...
mw_r:   ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; step(): a tic: the message's time, the song, the particles, the activity
step:   addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        ld    t0, g_tic - g(gp)         ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, g_tic - g(gp)         ; ...
        ld    t0, g_msgt - g(gp)        ; the message goes when its time is up,
        blez  t0, st_1                  ;   and the next one comes
        addi  t0, t0, -1                ; ...
        sd    t0, g_msgt - g(gp)        ; ...
        bnez  t0, st_1                  ; ...
        ld    t0, g_msgq - g(gp)        ; ...
        sd    t0, g_msg - g(gp)         ; ...
        li    t1, -1                    ; ...
        sd    t1, g_msgn - g(gp)        ; ...
        sd    t1, g_msgq - g(gp)        ; ...
        li    t1, 1                     ; ...
        sd    t1, g_dirty - g(gp)       ; ...
        sd    t1, g_bardirty - g(gp)    ; ...
        bltz  t0, st_1                  ; ...
        li    t1, 100                   ; ...
        sd    t1, g_msgt - g(gp)        ; ...
st_1:   ld    t0, g_tune - g(gp)        ; the song: the next note when its time has come
        beqz  t0, st_3                  ; ...
        lbu   t1, 0(t0)                 ; ...
        li    t2, 255                   ; (its end)
        bne   t1, t2, st_2              ; ...
        sd    zero, g_tune - g(gp)      ; ...
        li    t1, 1                     ; ...
        sd    t1, g_bardirty - g(gp)    ; ...
        j     st_3                      ; ...
st_2:   ld    t2, g_tunet - g(gp)       ; ...
        addi  t3, t2, 1                 ; ...
        sd    t3, g_tunet - g(gp)       ; ...
        bltu  t2, t1, st_3              ; ...
        lbu   a0, 1(t0)                 ; ...
        addi  t0, t0, 2                 ; ...
        sd    t0, g_tune - g(gp)        ; ...
        sd    zero, g_tunet - g(gp)     ; ...
        ld    t0, g_mode - g(gp)        ; (in the music room the note strikes its bar)
        li    t1, M_MUSIC               ; ...
        bne   t0, t1, st_n              ; ...
        call  mu_note                   ; ...
        j     st_1                      ; ...
st_n:   addi  a0, a0, SN_NOTE0          ; ...
        call  snd_play                  ; ...
        j     st_1                      ; (notes that sound together)
st_3:   call  p_step                    ; ...
        ld    t0, g_mode - g(gp)        ; ...
        li    t1, M_FRIENDS             ; ...
        bne   t0, t1, st_4              ; ...
        call  fr_step                   ; ...
        j     st_r                      ; ...
st_4:   li    t1, M_GARDEN              ; ...
        bne   t0, t1, st_5              ; ...
        call  gd_step                   ; ...
        j     st_r                      ; ...
st_5:   li    t1, M_MUSIC               ; ...
        bne   t0, t1, st_r              ; ...
        call  mu_step                   ; ...
st_r:   ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; set_mode(a0 = activity): it takes the screen
set_mode:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        ld    t0, g_mode - g(gp)        ; ...
        sd    a0, g_mode - g(gp)        ; ...
        li    t1, M_GARDEN              ; (the garden that is left is kept)
        bne   t0, t1, sx_0              ; ...
        call  gd_save                   ; ...
sx_0:   li    t1, M_MUSIC               ; (a song ends with the music room)
        bne   t0, t1, sx_1              ; ...
        sd    zero, g_tune - g(gp)      ; ...
sx_1:
        li    t0, 1                     ; ...
        sd    t0, g_dirty - g(gp)       ; ...
        sd    t0, g_bardirty - g(gp)    ; ...
        ld    t0, g_msgt - g(gp)        ; a message that would go by itself goes now
        bltz  t0, sx_k                  ; ...
        li    t0, -1                    ; ...
        sd    t0, g_msg - g(gp)         ; ...
        sd    t0, g_msgq - g(gp)        ; ...
        sd    zero, g_msgt - g(gp)      ; ...
        call  p_clear                   ; ...
sx_k:   ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; view_slab(): the activity's picture in the slab
view_slab:
        ld    t0, g_mode - g(gp)        ; ...
        li    t1, M_FRIENDS             ; ...
        bne   t0, t1, vs_m              ; ...
        ld    t0, f_view - g(gp)        ; ...
        beqz  t0, td_slab               ; ...
        j     e_slab                    ; ...
vs_m:   li    t1, M_GARDEN              ; ...
        beq   t0, t1, gd_slab           ; ...
        li    t1, M_PAINT               ; ...
        beq   t0, t1, pt_slab           ; ...
        li    t1, M_MUSIC               ; ...
        beq   t0, t1, mu_slab           ; ...
        li    a0, PIC_MENU              ; ...
        j     pic_slab                  ; ...

; view_begin(): before a frame's slabs: what the activity works out once
view_begin:
        ld    t0, g_mode - g(gp)        ; ...
        li    t1, M_FRIENDS             ; ...
        bne   t0, t1, vb_r              ; ...
        ld    t0, f_view - g(gp)        ; ...
        bnez  t0, e_begin               ; ...
vb_r:   ret                             ; done

; bar_slab(): the activity's part of the bar: the way home, and its own
bar_slab:
        ld    t0, g_mode - g(gp)        ; ...
        beqz  t0, bs_r                  ; (the menu has none)
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        li    a0, SP_ICON_HOME          ; ...
        li    a1, 4                     ; ...
        li    a2, 172                   ; ...
        call  r_blit                    ; ...
        ld    t0, g_mode - g(gp)        ; ...
        li    t1, M_FRIENDS             ; ...
        bne   t0, t1, bs_1              ; ...
        call  fr_bar                    ; ...
        j     bs_d                      ; ...
bs_1:   li    t1, M_GARDEN              ; ...
        bne   t0, t1, bs_2              ; ...
        call  gd_bar                    ; ...
        j     bs_d                      ; ...
bs_2:   li    t1, M_PAINT               ; ...
        bne   t0, t1, bs_3              ; ...
        call  pt_bar                    ; ...
        j     bs_d                      ; ...
bs_3:   call  mu_bar                    ; ...
bs_d:   ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
bs_r:   ret                             ; done

; click(a0 = x, a1 = y on the 320 x 200 screen): a press there
click:  li    t0, VIEW_H                ; the bar: the way home is at its left
        blt   a1, t0, cl_v              ; ...
        ld    t0, g_mode - g(gp)        ; ...
        beqz  t0, cl_r                  ; ...
        li    t0, 32                    ; ...
        bge   a0, t0, cl_b              ; ...
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        li    a0, SN_POP                ; (a button pops)
        call  snd_play                  ; ...
        li    a0, M_MENU                ; ...
        call  set_mode                  ; ...
        j     cl_p                      ; ...
cl_b:   ld    t0, g_mode - g(gp)        ; ... and the rest is the activity's
        li    t1, M_GARDEN              ; ...
        beq   t0, t1, gd_barclick       ; ...
        li    t1, M_PAINT               ; ...
        beq   t0, t1, pt_barclick       ; ...
        li    t1, M_MUSIC               ; ...
        beq   t0, t1, mu_barclick       ; ...
        li    t0, 288                   ; Friends: its other view, at the right
        blt   a0, t0, cl_r              ; ...
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        li    a0, SN_POP                ; ...
        call  snd_play                  ; ...
        call  fr_toggle                 ; ...
cl_p:   ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done
cl_v:   ld    t0, g_mode - g(gp)        ; the view: the activity's
