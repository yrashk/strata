; demo(): the demo's next tic: when a step's wait is over, its key. At the
; demo's end the program stands still, as when the window loses the focus,
; until a key or the pointer wakes it.
demo:   ld    t0, g_demo - g(gp)        ; the step
        ld    t1, g_dleft - g(gp)       ; tics left of its wait
        bnez  t1, de_1                  ; ...
        lbu   t1, 0(t0)                 ; a new step
        bnez  t1, de_1                  ; ...
        sd    zero, g_demo - g(gp)      ; the end
        li    t1, 1                     ; ...
        sd    t1, g_paused - g(gp)      ; ...
        j     demo_say                  ; ...
de_1:   addi  t1, t1, -1                ; ...
        sd    t1, g_dleft - g(gp)       ; ...
        bnez  t1, de_r                  ; ...
        lbu   a0, 1(t0)                 ; ...
        addi  t0, t0, 2                 ; ...
        sd    t0, g_demo - g(gp)        ; ...
        li    t1, DK_CLICK              ; a click: the next two bytes are x / 2 and y
        beq   a0, t1, de_c              ; ...
        li    t1, DK_ALL                ; all friends found, Kira beside the picnic
        beq   a0, t1, fr_all            ; ...
        li    t1, DK_LOOP               ; what follows, up to DK_END, so many times
        bne   a0, t1, de_e              ; ...
        lbu   t1, 0(t0)                 ; ...
        sd    t1, g_dloop - g(gp)       ; ...
        addi  t0, t0, 2                 ; ...
        sd    t0, g_demo - g(gp)        ; ...
        sd    t0, g_dmark - g(gp)       ; ...
        ret                             ; ...
de_e:   li    t1, DK_END                ; ...
        bne   a0, t1, do_key            ; ...
        ld    t1, g_dloop - g(gp)       ; ...
        addi  t1, t1, -1                ; ...
        sd    t1, g_dloop - g(gp)       ; ...
        blez  t1, de_r                  ; ...
        ld    t0, g_dmark - g(gp)       ; ...
        sd    t0, g_demo - g(gp)        ; ...
        ret                             ; ...
de_c:   lbu   a0, 0(t0)                 ; ...
        slli  a0, a0, 1                 ; ...
        lbu   a1, 1(t0)                 ; ...
        addi  t0, t0, 2                 ; ...
        sd    t0, g_demo - g(gp)        ; ...
        j     click                     ; ...
de_r:   ret                             ; done

; demo_say(): on standard error: "kira: demo: N frames in N ms"
demo_say:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = where the text goes on
        sd    s1, 16(sp)                ; s1 = the milliseconds
        call  sys_now                   ; ...
        ld    t0, g_dt0 - g(gp)         ; ...
        sub   s1, a0, t0                ; ...
        li    t0, 1000                  ; ...
        divu  s1, s1, t0                ; ...
        la    s0, k_dnum                ; the frames: a tic each
        ld    a0, g_tic - g(gp)         ; ...
        call  dy_num                    ; ...
        la    a0, k_dfr                 ; ...
        call  dy_str                    ; ...
        mv    a0, s1                    ; the time
        call  dy_num                    ; ...
        la    a0, k_dms                 ; ...
        call  dy_str                    ; ...
        la    a0, k_dmsg                ; (the pieces follow one another in the data)
        la    t0, k_dmsg                ; ...
        sub   a1, s0, t0                ; ...
        call  err_str                   ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done
dy_str: lbu   t0, 0(a0)                 ; a0 = text, NUL-terminated: append it at s0
        beqz  t0, dy_r                  ; ...
        sb    t0, 0(s0)                 ; ...
        addi  a0, a0, 1                 ; ...
        addi  s0, s0, 1                 ; ...
        j     dy_str                    ; ...
dy_num: li    t1, 10                    ; a0 = number: append its decimal digits at s0
        li    t2, 0                     ; t2 = digits (on the stack, last first)
dy_n1:  remu  t0, a0, t1                ; ...
        divu  a0, a0, t1                ; ...
        addi  t0, t0, '0'               ; ...
        addi  sp, sp, -8                ; ...
        sd    t0, 0(sp)                 ; ...
        addi  t2, t2, 1                 ; ...
        bnez  a0, dy_n1                 ; ...
dy_n2:  ld    t0, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        sb    t0, 0(s0)                 ; ...
        addi  s0, s0, 1                 ; ...
        addi  t2, t2, -1                ; ...
        bnez  t2, dy_n2                 ; ...
dy_r:   ret                             ; done

; load_dat() -> a0 = 0, or -1: read /ws/kira.dat: its resident block into
; `res`, its far block into the top of the arena (through the slab)
load_dat:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = handle
        sd    s1, 16(sp)                ; s1 = where the next bytes go
        sd    s2, 24(sp)                ; s2 = bytes left
        la    a0, k_dat                 ; ...
        li    a1, k_dat_e - k_dat       ; ...
        li    a2, 0                     ; ...
        call  sys_open                  ; ...
        mv    s0, a0                    ; ...
        bltz  a0, ld_bad                ; ...
        la    s1, res                   ; the resident block
        li    s2, R_SIZE                ; ...
ld_r:   mv    a0, s0                    ; (a message of data at a time)
        mv    a1, s1                    ; ...
        mv    a2, s2                    ; ...
        call  sys_read                  ; ...
        blez  a0, ld_bad                ; ...
        add   s1, s1, a0                ; ...
        sub   s2, s2, a0                ; ...
        bgtz  s2, ld_r                  ; ...
        ld    s1, g_keepb - g(gp)       ; the far block
        li    s2, F_SIZE                ; ...
ld_f:   mv    a0, s0                    ; ...
        la    a1, slab                  ; ...
        mv    a2, s2                    ; ...
        call  sys_read                  ; ...
        blez  a0, ld_bad                ; ...
        addi  t0, a0, 7                 ; (whole words)
        srli  t0, t0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        la    t1, slab                  ; ...
        tput  tg9, t1, c0, s1, t0       ; (the next read's stores wait for it)
        add   s1, s1, a0                ; ...
        sub   s2, s2, a0                ; ...
        bgtz  s2, ld_f                  ; ...
        mv    a0, s0                    ; ...
        call  sys_close                 ; ...
        li    a0, 0                     ; ...
        j     ld_ret                    ; ...
ld_bad: li    a0, -1                    ; ...
ld_ret: ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

; geom(): the window has a (new) size: the largest whole factor at which
; 320 x 200 fits and a slab fits the band, the picture's place, how many
; slabs the band holds; the window is cleared
geom:   addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        la    t0, wc_surf               ; ...
        ld    a2, S_W(t0)               ; a2 = width
        ld    a3, S_H(t0)               ; a3 = height
        li    t1, VIEW_W                ; the factor: by the width ...
        divu  t2, a2, t1                ; ...
        li    t1, VIEW_H + BAR_H        ; ... and the height,
        divu  t3, a3, t1                ; ...
        bleu  t2, t3, ge_1              ; ...
        mv    t2, t3                    ; ...
ge_1:   li    t1, 3                     ; ... three at most
        bleu  t2, t1, ge_2              ; ...
        mv    t2, t1                    ; ...
ge_2:   sd    t2, g_scale - g(gp)       ; ...
        beqz  t2, ge_c                  ; (too small for it)
        mul   t3, t2, t2                ; the band holds how many slabs at that factor?
        li    t1, SLAB_W * VIEW_H * 4   ; ...
        mul   t3, t3, t1                ; ...
        ld    t4, g_keepb - g(gp)       ; ...
        divu  t4, t4, t3                ; ...
        bnez  t4, ge_3                  ; ...
        addi  t2, t2, -1                ; none: a smaller picture
        j     ge_2                      ; ...
ge_3:   li    t1, NSLAB                 ; ...
        bleu  t4, t1, ge_4              ; ...
        mv    t4, t1                    ; ...
ge_4:   sd    t4, g_grp - g(gp)         ; ...
        li    t1, VIEW_W                ; centred (at an even column)
        mul   t1, t1, t2                ; ...
        sub   t1, a2, t1                ; ...
        srli  t1, t1, 2                 ; ...
        slli  t1, t1, 1                 ; ...
        sd    t1, g_ox - g(gp)          ; ...
        li    t1, VIEW_H + BAR_H        ; ...
        mul   t1, t1, t2                ; ...
        sub   t1, a3, t1                ; ...
        srli  t1, t1, 1                 ; ...
        sd    t1, g_oy - g(gp)          ; ...
ge_c:   li    a0, 0                     ; lilac around it
        li    a1, 0                     ; ...
        li    a4, BORDER                ; ...
        call  wc_fill                   ; ...
        li    t0, 1                     ; everything is to be drawn
        sd    t0, g_bardirty - g(gp)    ; ...
        sd    t0, g_dirty - g(gp)       ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; ev_handle(): the event in wc_ev
ev_handle:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = key bytes
        sd    s1, 16(sp)                ; s1 = how many
        la    t0, wc_ev                 ; its kind
        ld    t1, 0(t0)                 ; ...
        li    t2, WE_SIZE               ; a resize (already applied to wc_surf)
        bne   t1, t2, ev_1              ; ...
        call  geom                      ; ...
        j     ev_r                      ; ...
ev_1:   li    t2, WE_CLOSE              ; close: end
        bne   t1, t2, ev_2              ; ...
        li    t2, 1                     ; ...
        sd    t2, g_quit - g(gp)        ; ...
        j     ev_r                      ; ...
ev_2:   li    t2, WE_BLUR               ; the focus went: wait
        bne   t1, t2, ev_3              ; ...
        li    t2, 1                     ; ...
        sd    t2, g_paused - g(gp)      ; ...
        j     ev_r                      ; ...
ev_3:   li    t2, WE_FOCUS              ; ... and came back
        bne   t1, t2, ev_4              ; ...
        sd    zero, g_paused - g(gp)    ; ...
        j     ev_r                      ; ...
ev_4:   li    t2, WE_PTR                ; the pointer
        bne   t1, t2, ev_5              ; ...
        ld    t3, 8(t0)                 ; x, y, buttons
        srli  t5, t3, 32                ; ...
        andi  t5, t5, 0xff              ; t5 = buttons
        ld    t6, g_btn - g(gp)         ; t6 = the buttons before
        sd    t5, g_btn - g(gp)         ; ...
        andi  t5, t5, 1                 ; the left button went down?
        beqz  t5, ev_r                  ; ...
        andi  t6, t6, 1                 ; ...
        bnez  t6, ev_r                  ; ...
        ld    t2, g_demo - g(gp)        ; (not while the demo plays)
        bnez  t2, ev_r                  ; ...
        sd    zero, g_paused - g(gp)    ; (a press wakes a program that stands still)
        ld    t4, g_scale - g(gp)       ; where, on the 320 x 200 screen
        beqz  t4, ev_r                  ; ...
        li    t1, 0xffff                ; ...
        and   a0, t3, t1                ; ...
        ld    t2, g_ox - g(gp)          ; ...
        sub   a0, a0, t2                ; ...
        bltz  a0, ev_r                  ; ...
        divu  a0, a0, t4                ; ...
        li    t2, VIEW_W                ; ...
        bgeu  a0, t2, ev_r              ; ...
        srli  a1, t3, 16                ; ...
        and   a1, a1, t1                ; ...
        ld    t2, g_oy - g(gp)          ; ...
        sub   a1, a1, t2                ; ...
        bltz  a1, ev_r                  ; ...
        divu  a1, a1, t4                ; ...
        li    t2, VIEW_H + BAR_H        ; ...
        bgeu  a1, t2, ev_r              ; ...
        ld    t0, g_curon - g(gp)       ; (the pointer is used: the hand goes)
        beqz  t0, ev_p                  ; ...
        sd    zero, g_curon - g(gp)     ; ...
        li    t0, 1                     ; ...
        sd    t0, g_dirty - g(gp)       ; ...
        sd    t0, g_bardirty - g(gp)    ; ...
ev_p:   call  click                     ; ...
        j     ev_r                      ; ...
ev_5:   li    t2, WE_KEY                ; keys
        bne   t1, t2, ev_r              ; ...
        ld    t2, g_demo - g(gp)        ; (not while the demo plays, but q)
        sd    zero, g_paused - g(gp)    ; (a key wakes a program that stands still)
        beqz  t2, ev_k0                 ; ...
        ld    t3, 8(t0)                 ; ...
        andi  t3, t3, 0xff              ; ...
        li    t2, 'q'                   ; ...
        bne   t3, t2, ev_r              ; ...
ev_k0:  la    t0, wc_ev                 ; ...
        ld    s0, 8(t0)                 ; ...
        ld    s1, 16(t0)                ; ...
ev_k:   beqz  s1, ev_r                  ; ...
        andi  a0, s0, 0xff              ; ...
        call  key                       ; ...
        srli  s0, s0, 8                 ; ...
        addi  s1, s1, -1                ; ...
        j     ev_k                      ; ...
ev_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; key(a0 = a byte from the keyboard): arrows come as ESC [ A..D; W A S D are
; arrows too; capitals count as small letters
key:    ld    t0, g_esc - g(gp)         ; in a sequence?
        beqz  t0, ke_0                  ; ...
        li    t1, 1                     ; ...
        bne   t0, t1, ke_2              ; ...
        sd    zero, g_esc - g(gp)       ; after ESC: [ goes on, anything else is a key
        li    t1, '['                   ; ...
        bne   a0, t1, ke_0              ; ...
        li    t1, 2                     ; ...
        sd    t1, g_esc - g(gp)         ; ...
        ret                             ; ...
ke_2:   li    t1, '@'                   ; after ESC [: parameters, then the final byte
        bltu  a0, t1, ke_r              ; ...
        sd    zero, g_esc - g(gp)       ; ...
        addi  t0, a0, -'A'              ; A B C D: up, down, right, left
        li    t1, 4                     ; ...
        bgeu  t0, t1, ke_r              ; ...
        la    t1, k_arrow               ; ...
        add   t0, t0, t1                ; ...
        lbu   a0, 0(t0)                 ; ...
        j     do_key                    ; ...
ke_0:   li    t1, 0x1b                  ; ESC starts a sequence
        bne   a0, t1, ke_1              ; ...
        li    t1, 1                     ; ...
        sd    t1, g_esc - g(gp)         ; ...
        ret                             ; ...
ke_1:   li    t1, 'A'                   ; capitals count as small letters
        bltu  a0, t1, ke_p              ; ...
        li    t1, 'Z'                   ; ...
        bgtu  a0, t1, ke_p              ; ...
        ori   a0, a0, 0x20              ; ...
ke_p:   li    t0, K_UP                  ; w a s d
        li    t1, 'w'                   ; ...
        beq   a0, t1, ke_a              ; ...
        li    t0, K_DOWN                ; ...
        li    t1, 's'                   ; ...
        beq   a0, t1, ke_a              ; ...
        li    t0, K_LEFT                ; ...
        li    t1, 'a'                   ; ...
        beq   a0, t1, ke_a              ; ...
        li    t0, K_RIGHT               ; ...
        li    t1, 'd'                   ; ...
        beq   a0, t1, ke_a              ; ...
        li    t1, ' '                   ; (control characters but Backspace, Enter
        bgeu  a0, t1, do_key            ;   and Tab mean nothing)
        li    t1, 8                     ; ...
        beq   a0, t1, do_key            ; ...
        li    t1, 10                    ; ...
        beq   a0, t1, do_key            ; ...
        li    t1, 13                    ; ...
        beq   a0, t1, do_key            ; ...
        li    t1, 9                     ; ...
        beq   a0, t1, do_key            ; ...
ke_r:   ret                             ; ...
ke_a:   mv    a0, t0                    ; ...
        j     do_key                    ; ...

        .data                           ; D-LS
k_arrow:  .byte K_UP, K_DOWN, K_RIGHT, K_LEFT ; ESC [ A, B, C, D
        .align 8                        ; ...
        .text                           ; code
