; =============================================================================
; wdoom.s: a first-person shooter in a window
; =============================================================================
;
;   wdoom           (from a shell in a terminal, or the palette: Alt+Space)
;
; A client of the window server (os/lib/wsclient.s) in the manner of Doom:
; textured walls, floor and ceiling, doors, three kinds of monster, a
; pistol, pickups, a status bar. The art and the sounds are Freedoom's
; (os/progs/wdoom/ATTRIBUTION.md), converted by tools/wdoom-assets.py into
; the file /ws/wdoom.dat, which is read at start.
;
; Keys: W S or Up Down walk, A D step sideways, Left Right turn, Space
; fires, E or Enter opens a door and throws the switch, Q quits. The
; pointer: a press of the left button fires; dragging with a button held
; turns. The keyboard is a stream of bytes with no key-up, so a key counts
; as held for a few tics after each byte (the host's key repeat keeps it so).
;
; How it fits the machine (os/progs/PLAN-wdoom.md has the numbers):
; - The D-LS has 40 KiB for a program's data. The view alone, 320 x 168
;   bytes, is 54 KiB, so it is drawn in ten slabs of 32 columns
;   (wdoom/render.s); only the tables, the level, two 64 x 64 flats and the
;   colour map are resident. The flats live in the library's 4 KiB buffers
;   for standard output and input (out_buf, in_buf): this program never
;   reads standard input, and writes nothing to standard output.
; - Everything else (wall textures, sprites, the bar, palettes, sounds: 421
;   KiB) is in the top of the arena, and is reached a column at a time with
;   `tget`. The rest of the arena is the band: finished slabs go into it as
;   XRGB8888 pixels, scaled 1, 2 or 3 times, and are lent to the server as
;   DAMAGE rectangles of as many slabs as the band holds.
; - The window is as large as its tile; the 320 x 200 picture is centred in
;   it at the largest whole factor that fits.
; - While the window does not have the focus the game is paused and the
;   program waits in EVENT; otherwise it waits there for the next tic.
;
; gfx.s is not included (its strips and display lists would cost 7 KiB of
; D-LS): the surface descriptor's layout, which wsclient.s needs, is below.

S_CAP    = 0                            ; os/lib/gfx.s's surface descriptor: register
S_OFF    = 8                            ; offset of pixel (0, 0)
S_W      = 16                           ; width
S_H      = 24                           ; height
S_STRIDE = 32                           ; bytes per row
S_SIZE   = 48                           ; bytes per descriptor
K_FIRST  = 9                            ; tics a walking key counts as held when first pressed
K_FIRSTT = 3                            ; ... a turning key (a tap is a small turn)
K_REPEAT = 4                            ; ... and when it comes again while held

        .text                           ; instruction Local Store
_start: j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program

        .include "wdoom/dat.s"          ; the data file's layout
KEEP     = (F_SIZE + 4095) & ~4095      ; the top of the arena: wdoom.dat's far block
        .include "wdoom/game.s"         ; the world
        .include "wdoom/render.s"       ; the renderer
        .include "wdoom/sound.s"        ; the sounds
        .include "../lib/sys.s"         ; the program library
        .include "../lib/wsclient.s"    ; the window server's protocol

        .data                           ; D-LS
        .align 8                        ; dwords
g:                                      ; the globals (gp points here)
g_zero:                                 ; ---- cleared when a level starts
g_px:     .dword 0                      ; the player: position, 16.16
g_py:     .dword 0                      ; ...
g_ang:    .dword 0                      ; angle, 0..2047 (0: east, 512: south)
g_vx:     .dword 0                      ; velocity, 16.16 a tic
g_vy:     .dword 0                      ; ...
g_health: .dword 0                      ; health
g_ammo:   .dword 0                      ; rounds
g_key:    .dword 0                      ; has the blue key
g_kills:  .dword 0                      ; monsters killed
g_nmon:   .dword 0                      ; monsters in the level
g_state:  .dword 0                      ; ST_PLAY, ST_DEAD, ST_WON
g_wst:    .dword 0                      ; tics left of the shot being fired
g_flash:  .dword 0                      ; how red the screen is
g_bonus:  .dword 0                      ; tics of gold left
g_fire:   .dword 0                      ; the trigger was pulled
g_use:    .dword 0                      ; "open" was pressed
g_hold:   .space 6 * 8                  ; the tic until which each key counts as held (H_*)
g_msg:    .dword 0                      ; the message shown (a sprite; -1: none)
g_msgt:   .dword 0                      ; tics it stays (-1: until the level starts again)
g_zero_e:                               ; ---- kept
g_dirx:   .dword 0                      ; the view's direction (a unit vector, 16.16)
g_diry:   .dword 0                      ; ...
g_plx:    .dword 0                      ; the screen plane: the direction turned right
g_ply:    .dword 0                      ; ...
g_tic:    .dword 0                      ; tics since the start
g_last:   .dword 0                      ; the clock at the last tic
g_seed:   .dword 20261113               ; the random numbers' state
g_palcur: .dword -1                     ; the palette in R_PAL
g_bardirty: .dword 1                    ; the bar is to be drawn
g_nvis:   .dword 0                      ; visible things (render.s)
g_sx0:    .dword 0                      ; the slab being drawn: its first column
g_py0:    .dword 0                      ; the pass: its first row on the 320 x 200 screen
g_ph:     .dword 0                      ; ... and rows
g_stride: .dword 0                      ; bytes between rows in the band
g_scale:  .dword 0                      ; the factor: 1..3 (0: the window is too small)
g_ox:     .dword 0                      ; where the picture is in the window
g_oy:     .dword 0                      ; ...
g_grp:    .dword 0                      ; slabs of the view the band holds
g_keepb:  .dword 0                      ; arena offset of the far block (= the band's size)
g_esc:    .dword 0                      ; keys: 1 after ESC, 2 after ESC [
g_btn:    .dword 0                      ; the pointer's buttons at its last event
g_lastx:  .dword 0                      ; ... and its x
g_paused: .dword 0                      ; the window lost the focus
g_quit:   .dword 0                      ; time to go
g_dirty:  .dword 1                      ; a frame is to be drawn although no tic passed
g_demo:   .dword 0                      ; `wdoom demo`: the next step of the demo (0: no demo)
g_dleft:  .dword 0                      ; ... and tics left of the step before it
g_dt0:    .dword 0                      ; the clock when the demo started
w_dmsg:   .ascii "wdoom: demo: "        ; what is said at the demo's end
w_dmsg_e:                               ; (its end)
w_dnum:   .space 40                     ; ... "N frames in N ms, N.N a second\n"
w_dfr:    .ascii " frames in \0"        ; (its pieces)
w_dms:    .ascii " ms, \0"              ; ...
w_dps:    .ascii " a second\n\0"        ; ...
        .align 8                        ; ...
res:      .space R_SIZE                 ; the data file's resident block (dat.s)
w_title:  .ascii "WDOOM\0\0\0"          ; the window's title
w_dat:    .ascii "/ws/wdoom.dat"        ; the data file
w_dat_e:                                ; (its end)
w_nows:   .ascii "wdoom: no window server (run ws first)\n"
w_nows_e:                               ; (its end)
w_nodat:  .ascii "wdoom: cannot read /ws/wdoom.dat\n"
w_nodat_e:                              ; (its end)
        .text                           ; code

main:
        call  sys_init                  ; handles
        la    gp, g                     ; the globals
        clen  t0, c0                    ; the arena: the band, then the far block
        li    t1, KEEP                  ; ...
        sub   t0, t0, t1                ; ...
        sd    t0, g_keepb - g(gp)       ; ...
        call  load_dat                  ; the data (before the window: the server's
        beqz  a0, m_win                 ;   endpoint takes the place of fs's)
        la    a0, w_nodat               ; ...
        li    a1, w_nodat_e - w_nodat   ; ...
        j     m_fail                    ; ...
m_win:  la    t0, wc_keep               ; (the library's idea of the band agrees)
        li    t1, KEEP                  ; ...
        sd    t1, 0(t0)                 ; ...
        la    a0, w_title               ; our window (events are polled: no flags)
        li    a1, 0                     ; ...
        call  wc_open                   ; ...
        bgtz  a0, m_go                  ; ...
        la    a0, w_nows                ; no server
        li    a1, w_nows_e - w_nows     ; ...
m_fail: call  err_str                   ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...
m_go:   la    a0, slab                  ; `wdoom demo`: play the demo (dat.s: R_DEMO)
        call  sys_args                  ; ...
        beqz  a0, m_go1                 ; ...
        la    t0, slab                  ; ...
        lbu   t0, 0(t0)                 ; ...
        li    t1, 'd'                   ; ...
        bne   t0, t1, m_go1             ; ...
        la    t0, res + R_DEMO          ; ...
        sd    t0, g_demo - g(gp)        ; ...
        call  sys_now                   ; (it is timed)
        sd    a0, g_dt0 - g(gp)         ; ...
        j     m_go2                     ; (and silent: standard error stays as it is)
m_go1:  call  snd_open                  ; the sound device, if there is one
m_go2:
        call  geom                      ; where the picture goes
        call  lvl_init                  ; the level
        call  sys_now                   ; time starts now
        sd    a0, g_last - g(gp)        ; ...
m_loop: ld    t0, g_quit - g(gp)        ; ...
        bnez  t0, m_end                 ; ...
        li    a0, 1                     ; an event? (do not block)
        li    a1, 0                     ; ...
        call  wc_event                  ; ...
        li    t0, -3                    ; none
        beq   a0, t0, m_time            ; ...
        bnez  a0, m_end                 ; the window is gone
        call  ev_handle                 ; ...
        j     m_loop                    ; ...
m_time: ld    t0, g_paused - g(gp)      ; ...
        beqz  t0, m_run                 ; ...
        ld    t0, g_dirty - g(gp)       ; paused: the picture as it stands, once,
        beqz  t0, m_blk                 ; ...
        sd    zero, g_dirty - g(gp)     ; ...
        call  r_frame                   ; ...
m_blk:  li    a0, 0                     ; ... then wait for an event
        li    a1, 0                     ; ...
        call  wc_event                  ; ...
        bnez  a0, m_end                 ; ...
        call  ev_handle                 ; ...
        call  sys_now                   ; (no tics are owed for the pause)
        sd    a0, g_last - g(gp)        ; ...
        j     m_loop                    ; ...
m_run:  ld    t0, g_demo - g(gp)        ; the demo: a tic a frame, whatever the clock says
        beqz  t0, m_clk                 ; ...
        call  demo                      ; ...
        call  g_step                    ; ...
        j     m_draw                    ; ...
m_clk:  call  sys_now                   ; tics due?
        ld    t0, g_last - g(gp)        ; ...
        sub   t1, a0, t0                ; ...
        li    t2, TIC_US                ; ...
        bgeu  t1, t2, m_tics            ; ...
        ld    t3, g_dirty - g(gp)       ; none: a frame anyway (a resize)?
        bnez  t3, m_draw                ; ...
        sub   a1, t2, t1                ; wait for the next tic, or an event
        li    a0, 0                     ; ...
        call  wc_event                  ; ...
        li    t0, -8                    ; (the time passed)
        beq   a0, t0, m_loop            ; ...
        bnez  a0, m_end                 ; ...
        call  ev_handle                 ; ...
        j     m_loop                    ; ...
m_tics: divu  s0, t1, t2                ; s0 = tics due
        mul   t3, s0, t2                ; ...
        add   t0, t0, t3                ; ...
        sd    t0, g_last - g(gp)        ; ...
        li    t3, 4                     ; (after a long frame: four at most)
        bleu  s0, t3, m_t1              ; ...
        mv    s0, t3                    ; ...
m_t1:   call  g_step                    ; ...
        addi  s0, s0, -1                ; ...
        bnez  s0, m_t1                  ; ...
m_draw: sd    zero, g_dirty - g(gp)     ; ...
        call  snd_pump                  ; the sounds, then the picture
        call  r_frame                   ; ...
        j     m_loop                    ; ...
m_end:  call  wc_close                  ; the window goes
        li    a0, 0                     ; ...
        call  sys_exit                  ; ...

; demo(): the keys of the demo's next tic. At its end the game stands still,
; as when the window loses the focus, until a key or the pointer wakes it.
demo:   ld    t0, g_demo - g(gp)        ; the step
        ld    t1, g_dleft - g(gp)       ; tics left of it
        bnez  t1, de_1                  ; ...
        lbu   t1, 0(t0)                 ; the next step: tics, keys
        bnez  t1, de_1                  ; ...
        sd    zero, g_demo - g(gp)      ; the end
        li    t1, 1                     ; ...
        sd    t1, g_paused - g(gp)      ; ...
        j     demo_say                  ; ...
de_1:   lbu   t2, 1(t0)                 ; t2 = the keys
        addi  t1, t1, -1                ; ...
        sd    t1, g_dleft - g(gp)       ; ...
        bnez  t1, de_2                  ; (the step's last tic: on to the next)
        addi  t0, t0, 2                 ; ...
        sd    t0, g_demo - g(gp)        ; ...
de_2:   ld    t3, g_tic - g(gp)         ; held through the tic about to run
        addi  t3, t3, 2                 ; ...
        la    t0, g_hold                ; ...
        li    t1, 6                     ; the six keys that are held
de_3:   andi  t4, t2, 1                 ; ...
        beqz  t4, de_4                  ; ...
        sd    t3, 0(t0)                 ; ...
de_4:   srli  t2, t2, 1                 ; ...
        addi  t0, t0, 8                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, de_3                  ; ...
        andi  t4, t2, 1                 ; fire
        beqz  t4, de_5                  ; ...
        sd    t4, g_fire - g(gp)        ; ...
de_5:   srli  t2, t2, 1                 ; open
        beqz  t2, de_6                  ; ...
        sd    t2, g_use - g(gp)         ; ...
de_6:   ret                             ; done

; demo_say(): on standard error: "wdoom: demo: N frames in N ms, N.N a second"
demo_say:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = where the text goes on
        sd    s1, 16(sp)                ; s1 = the milliseconds
        call  sys_now                   ; ...
        ld    t0, g_dt0 - g(gp)         ; ...
        sub   s1, a0, t0                ; ...
        li    t0, 1000                  ; ...
        divu  s1, s1, t0                ; ...
        bnez  s1, dy_1                  ; (at least one)
        li    s1, 1                     ; ...
dy_1:   la    s0, w_dnum                ; the frames: a tic each
        ld    a0, g_tic - g(gp)         ; ...
        call  dy_num                    ; ...
        la    a0, w_dfr                 ; ...
        call  dy_str                    ; ...
        mv    a0, s1                    ; the time
        call  dy_num                    ; ...
        la    a0, w_dms                 ; ...
        call  dy_str                    ; ...
        ld    t0, g_tic - g(gp)         ; frames a second, to a tenth
        li    t1, 10000                 ; ...
        mul   t0, t0, t1                ; ...
        divu  s1, t0, s1                ; s1 = ten times the rate
        li    t1, 10                    ; ...
        divu  a0, s1, t1                ; ...
        call  dy_num                    ; ...
        li    t0, '.'                   ; ...
        sb    t0, 0(s0)                 ; ...
        addi  s0, s0, 1                 ; ...
        li    t1, 10                    ; ...
        remu  a0, s1, t1                ; ...
        call  dy_num                    ; ...
        la    a0, w_dps                 ; ...
        call  dy_str                    ; ...
        la    a0, w_dmsg                ; (the pieces follow one another in the data)
        la    t0, w_dmsg                ; ...
        sub   a1, s0, t0                ; ...
        call  err_str                   ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done
dy_str: lbu   t0, 0(a0)                 ; a0 = text, NUL-terminated: append it at s0
        beqz  t0, dy_r                  ; ...
        sb    t0, 0(s0)                 ; ...
        addi  a0, a0, 1                 ; ...
        addi  s0, s0, 1                 ; ...
        j     dy_str                    ; ...
dy_num: li    t1, 10                    ; a0 = number: append its decimal digits at s0
        li    t2, 0                     ; t2 = digits (on the stack, last first)
dy_n1:  remu  t0, a0, t1                ; ...
        divu  a0, a0, t1                ; ...
        addi  t0, t0, '0'               ; ...
        addi  sp, sp, -8                ; ...
        sd    t0, 0(sp)                 ; ...
        addi  t2, t2, 1                 ; ...
        bnez  a0, dy_n1                 ; ...
dy_n2:  ld    t0, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        sb    t0, 0(s0)                 ; ...
        addi  s0, s0, 1                 ; ...
        addi  t2, t2, -1                ; ...
        bnez  t2, dy_n2                 ; ...
dy_r:   ret                             ; done

; load_dat() -> a0 = 0, or -1: read /ws/wdoom.dat: its resident block into
; `res`, its far block into the top of the arena (through the slab)
load_dat:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = handle
        sd    s1, 16(sp)                ; s1 = where the next bytes go
        sd    s2, 24(sp)                ; s2 = bytes left
        la    a0, w_dat                 ; ...
        li    a1, w_dat_e - w_dat       ; ...
        li    a2, 0                     ; ...
        call  sys_open                  ; ...
        mv    s0, a0                    ; ...
        bltz  a0, ld_bad                ; ...
        la    s1, res                   ; the resident block
        li    s2, R_SIZE                ; ...
ld_r:   mv    a0, s0                    ; (a message of data at a time)
        mv    a1, s1                    ; ...
        mv    a2, s2                    ; ...
        call  sys_read                  ; ...
        blez  a0, ld_bad                ; ...
        add   s1, s1, a0                ; ...
        sub   s2, s2, a0                ; ...
        bgtz  s2, ld_r                  ; ...
        ld    s1, g_keepb - g(gp)       ; the far block
        li    s2, F_SIZE                ; ...
ld_f:   mv    a0, s0                    ; ...
        la    a1, slab                  ; ...
        mv    a2, s2                    ; ...
        call  sys_read                  ; ...
        blez  a0, ld_bad                ; ...
        addi  t0, a0, 7                 ; (whole words)
        srli  t0, t0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        la    t1, slab                  ; ...
        tput  tg9, t1, c0, s1, t0       ; (the next read's stores wait for it)
        add   s1, s1, a0                ; ...
        sub   s2, s2, a0                ; ...
        bgtz  s2, ld_f                  ; ...
        mv    a0, s0                    ; ...
        call  sys_close                 ; ...
        li    a0, 0                     ; ...
        j     ld_ret                    ; ...
ld_bad: li    a0, -1                    ; ...
ld_ret: ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

; geom(): the window has a (new) size: the largest whole factor at which
; 320 x 200 fits and a slab fits the band, the picture's place, how many
; slabs the band holds; the window is cleared
geom:   addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        la    t0, wc_surf               ; ...
        ld    a2, S_W(t0)               ; a2 = width
        ld    a3, S_H(t0)               ; a3 = height
        li    t1, VIEW_W                ; the factor: by the width ...
        divu  t2, a2, t1                ; ...
        li    t1, VIEW_H + BAR_H        ; ... and the height,
        divu  t3, a3, t1                ; ...
        bleu  t2, t3, ge_1              ; ...
        mv    t2, t3                    ; ...
ge_1:   li    t1, 3                     ; ... three at most
        bleu  t2, t1, ge_2              ; ...
        mv    t2, t1                    ; ...
ge_2:   sd    t2, g_scale - g(gp)       ; ...
        beqz  t2, ge_c                  ; (too small for it)
        mul   t3, t2, t2                ; the band holds how many slabs at that factor?
        li    t1, SLAB_W * VIEW_H * 4   ; ...
        mul   t3, t3, t1                ; ...
        ld    t4, g_keepb - g(gp)       ; ...
        divu  t4, t4, t3                ; ...
        bnez  t4, ge_3                  ; ...
        addi  t2, t2, -1                ; none: a smaller picture
        j     ge_2                      ; ...
ge_3:   li    t1, NSLAB                 ; ...
        bleu  t4, t1, ge_4              ; ...
        mv    t4, t1                    ; ...
ge_4:   sd    t4, g_grp - g(gp)         ; ...
        li    t1, VIEW_W                ; centred (at an even column)
        mul   t1, t1, t2                ; ...
        sub   t1, a2, t1                ; ...
        srli  t1, t1, 2                 ; ...
        slli  t1, t1, 1                 ; ...
        sd    t1, g_ox - g(gp)          ; ...
        li    t1, VIEW_H + BAR_H        ; ...
        mul   t1, t1, t2                ; ...
        sub   t1, a3, t1                ; ...
        srli  t1, t1, 1                 ; ...
        sd    t1, g_oy - g(gp)          ; ...
ge_c:   li    a0, 0                     ; black around it
        li    a1, 0                     ; ...
        li    a4, 0                     ; ...
        call  wc_fill                   ; ...
        li    t0, 1                     ; everything is to be drawn
        sd    t0, g_bardirty - g(gp)    ; ...
        sd    t0, g_dirty - g(gp)       ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; ev_handle(): the event in wc_ev
ev_handle:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = key bytes
        sd    s1, 16(sp)                ; s1 = how many
        la    t0, wc_ev                 ; its kind
        ld    t1, 0(t0)                 ; ...
        li    t2, WE_SIZE               ; a resize (already applied to wc_surf)
        bne   t1, t2, ev_1              ; ...
        call  geom                      ; ...
        j     ev_r                      ; ...
ev_1:   li    t2, WE_CLOSE              ; close: end
        bne   t1, t2, ev_2              ; ...
        li    t2, 1                     ; ...
        sd    t2, g_quit - g(gp)        ; ...
        j     ev_r                      ; ...
ev_2:   li    t2, WE_BLUR               ; the focus went: pause
        bne   t1, t2, ev_3              ; ...
        li    t2, 1                     ; ...
        sd    t2, g_paused - g(gp)      ; ...
        j     ev_r                      ; ...
ev_3:   li    t2, WE_FOCUS              ; ... and came back
        bne   t1, t2, ev_4              ; ...
        sd    zero, g_paused - g(gp)    ; ...
        j     ev_r                      ; ...
ev_4:   li    t2, WE_PTR                ; the pointer
        bne   t1, t2, ev_5              ; ...
        ld    t3, 8(t0)                 ; x, buttons
        li    t4, 0xffff                ; ...
        and   t4, t3, t4                ; t4 = x
        srli  t5, t3, 32                ; ...
        andi  t5, t5, 0xff              ; t5 = buttons
        ld    t6, g_btn - g(gp)         ; t6 = the buttons before
        sd    t5, g_btn - g(gp)         ; ...
        ld    t2, g_lastx - g(gp)       ; ...
        sd    t4, g_lastx - g(gp)       ; ...
        andi  t1, t5, 1                 ; the left button went down: fire
        beqz  t1, ev_p1                 ; ...
        andi  t1, t6, 1                 ; ...
        bnez  t1, ev_p1                 ; ...
        li    t1, 1                     ; ...
        sd    t1, g_fire - g(gp)        ; ...
ev_p1:  beqz  t5, ev_r                  ; a move with a button held all along: turn,
        beqz  t6, ev_r                  ;   two angle units a pixel
        sub   t4, t4, t2                ; ...
        slli  t4, t4, 1                 ; ...
        ld    t1, g_ang - g(gp)         ; ...
        add   t1, t1, t4                ; ...
        andi  t1, t1, 2047              ; ...
        sd    t1, g_ang - g(gp)         ; ...
        j     ev_r                      ; ...
ev_5:   li    t2, WE_KEY                ; keys
        bne   t1, t2, ev_r              ; ...
        ld    t2, g_demo - g(gp)        ; (not while the demo plays, but q)
        sd    zero, g_paused - g(gp)    ; (a key wakes a game that stands still)
        beqz  t2, ev_k0                 ; ...
        ld    t3, 8(t0)                 ; ...
        andi  t3, t3, 0xff              ; ...
        li    t2, 'q'                   ; ...
        bne   t3, t2, ev_r              ; ...
ev_k0:  la    t0, wc_ev                 ; ...
        ld    s0, 8(t0)                 ; ...
        ld    s1, 16(t0)                ; ...
ev_k:   beqz  s1, ev_r                  ; ...
        andi  a0, s0, 0xff              ; ...
        call  key                       ; ...
        srli  s0, s0, 8                 ; ...
        addi  s1, s1, -1                ; ...
        j     ev_k                      ; ...
ev_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; key(a0 = a byte from the keyboard): arrows come as ESC [ A..D
key:    ld    t0, g_esc - g(gp)         ; in a sequence?
        beqz  t0, ke_0                  ; ...
        li    t1, 1                     ; ...
        bne   t0, t1, ke_2              ; ...
        sd    zero, g_esc - g(gp)       ; after ESC: [ goes on, anything else is a key
        li    t1, '['                   ; ...
        bne   a0, t1, ke_0              ; ...
        li    t1, 2                     ; ...
        sd    t1, g_esc - g(gp)         ; ...
        ret                             ; ...
ke_2:   li    t1, '@'                   ; after ESC [: parameters, then the final byte
        bltu  a0, t1, ke_r              ; ...
        sd    zero, g_esc - g(gp)       ; ...
        li    t2, H_FWD                 ; A: up
        li    t3, K_FIRST               ; ...
        li    t1, 'A'                   ; ...
        beq   a0, t1, ke_hold           ; ...
        li    t2, H_BACK                ; B: down
        li    t1, 'B'                   ; ...
        beq   a0, t1, ke_hold           ; ...
        li    t3, K_FIRSTT              ; ...
        li    t2, H_TR                  ; C: right
        li    t1, 'C'                   ; ...
        beq   a0, t1, ke_hold           ; ...
        li    t2, H_TL                  ; D: left
        li    t1, 'D'                   ; ...
        beq   a0, t1, ke_hold           ; ...
        ret                             ; ...
ke_0:   li    t1, 0x1b                  ; ESC starts a sequence
        bne   a0, t1, ke_1              ; ...
        li    t1, 1                     ; ...
        sd    t1, g_esc - g(gp)         ; ...
        ret                             ; ...
ke_1:   li    t1, 'A'                   ; capitals count as small letters
        bltu  a0, t1, ke_p              ; ...
        li    t1, 'Z'                   ; ...
        bgtu  a0, t1, ke_p              ; ...
        ori   a0, a0, 0x20              ; ...
ke_p:   li    t3, K_FIRST               ; ...
        li    t2, H_FWD                 ; w
        li    t1, 'w'                   ; ...
        beq   a0, t1, ke_hold           ; ...
        li    t2, H_BACK                ; s
        li    t1, 's'                   ; ...
        beq   a0, t1, ke_hold           ; ...
        li    t2, H_LEFT                ; a
        li    t1, 'a'                   ; ...
        beq   a0, t1, ke_hold           ; ...
        li    t2, H_RIGHT               ; d
        li    t1, 'd'                   ; ...
        beq   a0, t1, ke_hold           ; ...
        li    t1, ' '                   ; Space: fire
        bne   a0, t1, ke_p1             ; ...
        li    t1, 1                     ; ...
        sd    t1, g_fire - g(gp)        ; ...
        ret                             ; ...
ke_p1:  li    t1, 'e'                   ; e, Enter: open
        beq   a0, t1, ke_use            ; ...
        li    t1, 10                    ; ...
        bne   a0, t1, ke_p2             ; ...
ke_use: li    t1, 1                     ; ...
        sd    t1, g_use - g(gp)         ; ...
        ret                             ; ...
ke_p2:  li    t1, 'q'                   ; q: quit
        bne   a0, t1, ke_r              ; ...
        li    t1, 1                     ; ...
        sd    t1, g_quit - g(gp)        ; ...
ke_r:   ret                             ; ...
ke_hold:                                ; t2 = the key (H_*), t3 = tics if it is new
        la    t0, g_hold                ; ...
        add   t0, t0, t2                ; ...
        ld    t1, g_tic - g(gp)         ; ...
        ld    t4, 0(t0)                 ; held already: the repeat keeps it so
        ble   t4, t1, ke_h1             ; ...
        li    t3, K_REPEAT              ; ...
ke_h1:  add   t1, t1, t3                ; ...
        sd    t1, 0(t0)                 ; ...
        ret                             ; done
