ratio:  sub   t0, a0, a1                ; ...
        li    t1, 600                   ; ...
        mul   t0, t0, t1                ; ...
        addi  t1, a1, 40                ; ...
        div   a0, t0, t1                ; ...
        li    t1, 1000                  ; ...
        ble   a0, t1, ri_1              ; ...
