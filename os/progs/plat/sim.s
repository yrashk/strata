; money(): the month's taxes in and upkeep out; a milestone; at the end of a
; year (the month is January now) its summary
money:  addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the month's taxes
        ld    t0, g_popr - g(gp)        ; residents pay tax / 40 each month, jobs tax / 60
        ld    t1, g_tax - g(gp)         ; ...
        mul   t2, t0, t1                ; ...
        li    t3, 40                    ; ...
        divu  s0, t2, t3                ; ...
        ld    t0, g_popc - g(gp)        ; ...
        ld    t2, g_popi - g(gp)        ; ...
        add   t0, t0, t2                ; ...
        mul   t0, t0, t1                ; ...
        li    t3, 60                    ; ...
        divu  t0, t0, t3                ; ...
        add   s0, s0, t0                ; ...
        ld    t0, g_ytax - g(gp)        ; ...
        add   t0, t0, s0                ; ...
        sd    t0, g_ytax - g(gp)        ; ...
        ld    t1, g_upk - g(gp)         ; upkeep: a twelfth of the year's
        li    t2, 12                    ; ...
        divu  t1, t1, t2                ; ...
        ld    t2, g_yupk - g(gp)        ; ...
        add   t2, t2, t1                ; ...
        sd    t2, g_yupk - g(gp)        ; ...
        ld    t0, g_funds - g(gp)       ; ...
        add   t0, t0, s0                ; ...
        sub   t0, t0, t1                ; ...
        bgez  t0, mo_1                  ; (an empty treasury: said)
        li    t0, 0                     ; ...
        sd    t0, g_funds - g(gp)       ; ...
        la    a0, msg_broke             ; ...
        la    t6, say                   ; ...
        jalr  ra, t6, 0                 ; ...
        j     mo_2                      ; ...
mo_1:   sd    t0, g_funds - g(gp)       ; ...
mo_2:   ld    t0, g_dtext - g(gp)       ; ...
        ori   t0, t0, TX_FUNDS          ; ...
        sd    t0, g_dtext - g(gp)       ; ...
        ld    t0, g_mile - g(gp)        ; a milestone
        slli  t1, t0, 3                 ; ...
        la    t2, miles                 ; ...
        add   t2, t2, t1                ; ...
        ld    t2, 0(t2)                 ; ...
        ld    t3, g_popr - g(gp)        ; ...
        bltu  t3, t2, mo_3              ; ...
        addi  t2, t0, 1                 ; ...
        sd    t2, g_mile - g(gp)        ; ...
        la    t2, mile_msg              ; ...
        add   t2, t2, t1                ; ...
        ld    a0, 0(t2)                 ; ...
        la    t6, say                   ; ...
        jalr  ra, t6, 0                 ; ...
        li    a0, SN_COIN               ; ...
        la    t6, snd_play              ; ...
        jalr  ra, t6, 0                 ; ...
mo_3:   ld    t0, g_month - g(gp)       ; January: last year's summary
        bnez  t0, mo_r                  ; ...
        call  year_say                  ; ...
