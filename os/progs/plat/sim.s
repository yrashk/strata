; =============================================================================
; sim.s: Plat's town: power, zones that grow and decline, the census, demand
; =============================================================================

;

; Once a month (sim_month):
;   power   every cell's F_POWER is cleared, the plants are found, and power
;           spreads from them, breadth first, over the cells that carry it
;           (power lines, zones, plants). A plant can power CAP_COAL zones;
;           a zone's middle beyond that gets none.
;   zones   each zone's middle: does it have power, and a road within two
;           cells of its edge (F_ROAD)? An empty zone with both may get a
;           building site when its kind is in demand; a site becomes the
;           first density; a built zone grows while there is demand, and
;           declines without power or a road, or when the demand is low.
;           A zone without either has a mark drawn over its middle
;           (F_MARK says one is drawn).
;   census  residents (homes), and jobs in shops and offices and in
;           industry, from each zone's density (pop_tab).
;   demand  for each kind, from -1000 to 1000: homes want jobs; shops want
;           residents and industry; industry wants workers and a market
;           outside the town, which is there from the start.
; Every PLANT_TICS tics the plants' smoke moves (their two pictures).

CAP_COAL = 50                           ; zones a coal plant powers
MAXPLANT = 32                           ; plants the town keeps track of
RING     = 2048                         ; cells the power's front may hold
PLANT_TICS = 24                         ; tics between the plants' pictures

        .data                           ; D-LS
        .align 8                        ; dwords
plants:   .space MAXPLANT * 8           ; the plants: u32 x, y of their top left corner
pop_tab:  .dword 0, 20, 60, 140, 300    ; what a zone of each density holds: residents,
          .dword 0, 15, 45, 100, 220    ; ... jobs in shops and offices,
          .dword 0, 20, 50, 110, 200    ; ... jobs in industry
msg_short: .ascii "The plants cannot power every zone.\0" ; a message
msg_broke: .ascii "The treasury is empty.\0" ; a message
upk_cost: .byte 0, 0, 0, 0, 0, 1 ; upkeep a year of a cell of each kind (K_*)
          .byte 5, 1, 2, 2, 0, 7 ; ... (a plant's sixteen cells: 112)
        .align 8                        ; ...
miles:    .dword 500, 2000, 10000, 50000, 0x7fffffff ; the residents of each milestone
mile_msg: .dword mi_0, mi_1, mi_2, mi_3 ; ... and what is said
mi_0:     .ascii "Plat is a village now: 500 residents.\0" ; a message
mi_1:     .ascii "A town of 2,000 residents.\0" ; a message
mi_2:     .ascii "A city now: 10,000 residents!\0" ; a message
mi_3:     .ascii "50,000 residents: a capital.\0" ; a message
ysum_a:   .ascii ": taxes \0"            ; the year's summary: "1901: taxes N, upkeep N."
ysum_b:   .ascii ", upkeep \0"           ; ...
ysum_c:   .ascii ".\0"                   ; ...
ysum:     .space 64                     ; ...
        .align 8                        ; ...
        .text                           ; resident code
ys_str: lbu   t0, 0(a0)                 ; a0 = text, NUL-terminated: append it at s0
        beqz  t0, ys_r                  ; ...
        sb    t0, 0(s0)                 ; ...
        addi  a0, a0, 1                 ; ...
        addi  s0, s0, 1                 ; ...
        j     ys_str                    ; ...
ys_r:   ret                             ; done

        .far                            ; code units (paged in by the kernel)
        .align UNIT                     ; a unit
unit_sim1:
u_month:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; the far return link
        call  sim_month                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        xret  ra                        ; back (paged in again if it had to go)

; sim_month(): a month of the town
sim_month:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        call  power                     ; ...
        call  zones                     ; ...
        la    t5, u_demand              ; ...
        xcall ra, c0, t5                ; ...
        la    t5, u_money               ; ...
        xcall ra, c0, t5                ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; ---- power ----------------------------------------------------------------------

; conducts(a0 = the cell as stored) -> a0 = 1 if power goes through it
conducts:
        andi  a0, a0, PICMASK           ; ...
        la    t0, res + R_KIND          ; ...
        add   t0, t0, a0                ; ...
        lbu   t0, 0(t0)                 ; ...
        li    a0, 1                     ; ...
        li    t1, K_LINE                ; ...
        beq   t0, t1, cd_r              ; ...
        li    t1, K_LROAD               ; ...
        beq   t0, t1, cd_r              ; ...
        li    t1, K_LWATER              ; ...
        beq   t0, t1, cd_r              ; ...
        li    t1, K_ZONE                ; ...
        beq   t0, t1, cd_r              ; ...
        li    t1, K_PLANT               ; ...
        beq   t0, t1, cd_r              ; ...
        li    a0, 0                     ; ...
cd_r:   ret                             ; done

; power(): F_POWER where the plants' power reaches
power:  addi  sp, sp, -80               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = x; the ring's head
        sd    s1, 16(sp)                ; s1 = y; the ring's tail
        sd    s2, 24(sp)                ; s2 = zones powered
        sd    s3, 32(sp)                ; s3 = zones that may be powered
        sd    s4, 40(sp)                ; s4 = the cell taken from the ring
        sd    s5, 48(sp)                ; s5 = the way
        sd    s6, 56(sp)                ; s6 = the neighbour: x
        sd    s7, 64(sp)                ; s7 = ... y
        sd    zero, g_nplant - g(gp)    ; no plants yet
        sd    zero, g_upk - g(gp)       ; no upkeep yet
        li    s1, 0                     ; every row: no power; the plants
pw_y:   ld    t0, g_mapb - g(gp)        ; ...
        slli  t1, s1, 8                 ; ...
        add   t6, t0, t1                ; t6 = the row in the arena
        la    t1, maprow                ; ...
        li    t2, MAPN * 2              ; ...
        tget  tg11, t1, c0, t6, t2      ; ...
        twait 1 << 11                   ; ...
        li    s0, 0                     ; ...
pw_x:   la    t1, maprow                ; ...
        slli  t2, s0, 1                 ; ...
        add   t1, t1, t2                ; ...
        lhu   t3, 0(t1)                 ; ...
        li    t4, 0x7fff                ; (all but F_POWER)
        and   t3, t3, t4                ; ...
        sh    t3, 0(t1)                 ; ...
        andi  t3, t3, PICMASK           ; what upkeep it costs: count it
        la    t4, res + R_KIND          ; ...
        add   t4, t4, t3                ; ...
        lbu   t4, 0(t4)                 ; ...
        la    t5, upk_cost              ; ...
        add   t5, t5, t4                ; ...
        lbu   t5, 0(t5)                 ; ...
        ld    t4, g_upk - g(gp)         ; ...
        add   t4, t4, t5                ; ...
        sd    t4, g_upk - g(gp)         ; ...
        andi  t3, t3, PICMASK           ; a plant's top left corner (either picture)?
        addi  t3, t3, -T_COAL           ; ...
        li    t4, 32                    ; ...
        bgeu  t3, t4, pw_n              ; ...
        andi  t3, t3, 15                ; ...
        bnez  t3, pw_n                  ; ...
        ld    t3, g_nplant - g(gp)      ; ...
        li    t4, MAXPLANT              ; ...
        bgeu  t3, t4, pw_n              ; ...
        slli  t4, t3, 3                 ; ...
        la    t5, plants                ; ...
        add   t4, t4, t5                ; ...
        sw    s0, 0(t4)                 ; ...
        sw    s1, 4(t4)                 ; ...
        addi  t3, t3, 1                 ; ...
        sd    t3, g_nplant - g(gp)      ; ...
pw_n:   addi  s0, s0, 1                 ; ...
        li    t0, MAPN                  ; ...
        blt   s0, t0, pw_x              ; ...
        la    t1, maprow                ; ...
        li    t2, MAPN * 2              ; ...
        tput  tg11, t1, c0, t6, t2      ; ...
        twait 1 << 11                   ; ...
        addi  s1, s1, 1                 ; ...
        li    t0, MAPN                  ; ...
        blt   s1, t0, pw_y              ; ...
        ld    s3, g_nplant - g(gp)      ; what the plants can power
        li    t0, CAP_COAL              ; ...
        mul   s3, s3, t0                ; ...
        li    s2, 0                     ; ...
        li    s0, 0                     ; the ring: empty
        li    s1, 0                     ; ...
        li    s5, 0                     ; every plant's cells have power: the front
pw_p:   ld    t0, g_nplant - g(gp)      ; ...
        bge   s5, t0, pw_ring           ; ...
        slli  t0, s5, 3                 ; ...
        la    t1, plants                ; ...
        add   t0, t0, t1                ; ...
        lw    s6, 0(t0)                 ; ...
        lw    s7, 4(t0)                 ; ...
        li    s4, 0                     ; ...
pw_pc:  andi  a0, s4, 3                 ; ...
        add   a0, a0, s6                ; ...
        srli  a1, s4, 2                 ; ...
        add   a1, a1, s7                ; ...
        call  pw_on                     ; ...
        addi  s4, s4, 1                 ; ...
        li    t0, 16                    ; ...
        blt   s4, t0, pw_pc             ; ...
        addi  s5, s5, 1                 ; ...
        j     pw_p                      ; ...
pw_ring:
        beq   s0, s1, pw_done           ; the front: empty, it is done
        slli  t0, s0, 1                 ; take a cell
        la    t1, m_water               ; ...
        add   t0, t0, t1                ; ...
        lhu   s4, 0(t0)                 ; ...
        addi  s0, s0, 1                 ; ...
        andi  s0, s0, RING - 1          ; ...
        li    s5, 0                     ; its four neighbours
pw_nb:  la    t0, jm_dx                 ; ...
        add   t0, t0, s5                ; ...
        lb    s6, 0(t0)                 ; ...
        lb    s7, 4(t0)                 ; ...
        andi  t1, s4, MAPN - 1          ; ...
        add   s6, s6, t1                ; ...
        srli  t1, s4, 7                 ; ...
        add   s7, s7, t1                ; ...
        mv    a0, s6                    ; ...
        mv    a1, s7                    ; ...
        la    t6, m_getc                ; ...
        jalr  ra, t6, 0                 ; ...
        bltz  a0, pw_nn                 ; (off the map)
        li    t0, F_POWER               ; (it has it already)
        and   t0, t0, a0                ; ...
        bnez  t0, pw_nn                 ; ...
        sd    a0, 72(sp)                ; (the cell)
        call  conducts                  ; ...
        beqz  a0, pw_nn                 ; ...
        ld    a0, 72(sp)                ; a zone's middle: one more zone, if the
        andi  a0, a0, PICMASK           ;   plants can power it
        la    t6, zone_of               ; ...
        jalr  ra, t6, 0                 ; ...
        bltz  a0, pw_on1                ; ...
        li    t0, 4                     ; ...
        bne   a1, t0, pw_on1            ; ...
        blt   s2, s3, pw_z              ; ...
        li    t0, 1                     ; ...
        sd    t0, g_short - g(gp)       ; ...
        j     pw_nn                     ; ...
pw_z:   addi  s2, s2, 1                 ; ...
pw_on1: mv    a0, s6                    ; ...
        mv    a1, s7                    ; ...
        call  pw_on                     ; ...
pw_nn:  addi  s5, s5, 1                 ; ...
        li    t0, 4                     ; ...
        blt   s5, t0, pw_nb             ; ...
        j     pw_ring                   ; ...
pw_done:
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        ld    s5, 48(sp)                ; ...
        ld    s6, 56(sp)                ; ...
        ld    s7, 64(sp)                ; ...
        addi  sp, sp, 80                ; pop the frame
        ret                             ; done
; pw_on(a0 = x, a1 = y): the cell has power; it joins the front (s1: the
; ring's tail; it is dropped if the ring is full)
pw_on:  addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    a0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        la    t6, m_getc                ; ...
        jalr  ra, t6, 0                 ; ...
        li    t0, F_POWER               ; ...
        or    a2, a0, t0                ; ...
        ld    a0, 8(sp)                 ; ...
        ld    a1, 16(sp)                ; ...
        la    t6, m_setc                ; ...
        jalr  ra, t6, 0                 ; ...
        addi  t0, s1, 1                 ; ...
        andi  t0, t0, RING - 1          ; ...
        beq   t0, s0, po2_r             ; (full)
        ld    a0, 8(sp)                 ; ...
        ld    a1, 16(sp)                ; ...
        slli  t2, a1, 7                 ; ...
        add   t2, t2, a0                ; ...
        slli  t3, s1, 1                 ; ...
        la    t4, m_water               ; ...
        add   t3, t3, t4                ; ...
        sh    t2, 0(t3)                 ; ...
        mv    s1, t0                    ; ...
po2_r:  ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; ---- zones ----------------------------------------------------------------------

; road_near(a0 = x, a1 = y: a zone's middle) -> a0 = 1 if a road, a bridge
; or a road under a line is on the ring two cells from the middle
road_near:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = x
        sd    s1, 16(sp)                ; s1 = y
        sd    s2, 24(sp)                ; s2 = dx
        sd    s3, 32(sp)                ; s3 = dy
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        li    s3, -2                    ; ...
rn_y:   li    s2, -2                    ; ...
rn_x:   li    t0, 2                     ; (the ring only: |dx| or |dy| is 2)
        mul   t1, s2, s2                ; ...
        li    t2, 4                     ; ...
        beq   t1, t2, rn_c              ; ...
        mul   t1, s3, s3                ; ...
        bne   t1, t2, rn_n              ; ...
rn_c:   add   a0, s0, s2                ; ...
        add   a1, s1, s3                ; ...
        la    t6, m_kind                ; ...
        jalr  ra, t6, 0                 ; ...
        li    t0, K_ROAD                ; ...
        beq   a0, t0, rn_y1             ; ...
        li    t0, K_BRIDGE              ; ...
        beq   a0, t0, rn_y1             ; ...
        li    t0, K_LROAD               ; ...
        beq   a0, t0, rn_y1             ; ...
rn_n:   addi  s2, s2, 1                 ; ...
        li    t0, 2                     ; ...
        ble   s2, t0, rn_x              ; ...
        addi  s3, s3, 1                 ; ...
        ble   s3, t0, rn_y              ; ...
        li    a0, 0                     ; ...
        j     rn_r                      ; ...
rn_y1:  li    a0, 1                     ; ...
rn_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        addi  sp, sp, 40                ; pop the frame
        ret                             ; done

; zones(): every zone's middle, a row at a time: the zone grows, declines
; or stays; its mark; the census
zones:  addi  sp, sp, -96               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = x
        sd    s1, 16(sp)                ; s1 = y
        sd    s2, 24(sp)                ; s2 = the cell as stored
        sd    s3, 32(sp)                ; s3 = the zone's kind
        sd    s4, 40(sp)                ; s4 = its level (zone_of)
        sd    s5, 48(sp)                ; s5 = F_POWER | F_ROAD as it has them
        sd    s6, 56(sp)                ; s6 = the new level
        sd    s7, 64(sp)                ; s7 = the kind's demand
        sd    s8, 72(sp)                ; s8 = the density (0: none)
        sd    zero, g_popr - g(gp)      ; the census starts
        sd    zero, g_popc - g(gp)      ; ...
        sd    zero, g_popi - g(gp)      ; ...
        li    s1, 0                     ; ...
zn_y:   ld    t0, g_mapb - g(gp)        ; ...
        slli  t1, s1, 8                 ; ...
        add   t0, t0, t1                ; ...
        la    t1, maprow                ; ...
        li    t2, MAPN * 2              ; ...
        tget  tg11, t1, c0, t0, t2      ; ...
        twait 1 << 11                   ; ...
        li    s0, 0                     ; ...
zn_x:   la    t1, maprow                ; a zone's middle?
        slli  t2, s0, 1                 ; ...
        add   t1, t1, t2                ; ...
        lhu   s2, 0(t1)                 ; ...
        andi  a0, s2, PICMASK           ; ...
        la    t6, zone_of               ; ...
        jalr  ra, t6, 0                 ; ...
        bltz  a0, zn_n                  ; ...
        li    t0, 4                     ; ...
        bne   a1, t0, zn_n              ; ...
        li    t0, 10                    ; ...
        divu  s3, a0, t0                ; ...
        remu  s4, a0, t0                ; ...
        la    t0, g_dr                  ; its kind's demand
        slli  t1, s3, 3                 ; ...
        add   t0, t0, t1                ; ...
        ld    s7, 0(t0)                 ; ...
        li    t0, F_POWER               ; power, a road
        and   s5, s2, t0                ; ...
        mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        call  road_near                 ; ...
        beqz  a0, zn_1                  ; ...
        li    t0, F_ROAD                ; ...
        or    s5, s5, t0                ; ...
zn_1:   mv    s6, s4                    ; what becomes of it
        li    t0, F_POWER | F_ROAD      ; (t0: both)
        li    t1, 1                     ; a site: built, or given up
        bne   s4, t1, zn_2              ; ...
        li    s6, 0                     ; ...
        bne   s5, t0, zn_put            ; ...
        add   s6, s0, s1                ; ... the first density, one design or the other
        andi  s6, s6, 1                 ; ...
        addi  s6, s6, 2                 ; ...
        j     zn_put                    ; ...
zn_2:   bnez  s4, zn_3                  ; empty: a site, if wanted
        bne   s5, t0, zn_put            ; ...
        blez  s7, zn_put                ; ...
        li    a0, 1000                  ; ...
        la    t6, rndn                  ; ...
        jalr  ra, t6, 0                 ; ...
        bge   a0, s7, zn_put            ; ...
        li    s6, 1                     ; ...
        j     zn_put                    ; ...
zn_3:   addi  t1, s4, -2                ; built: density 1..4
        srli  s8, t1, 1                 ; ...
        addi  s8, s8, 1                 ; ...
        beq   s5, t0, zn_4              ; without power or a road: it declines
        li    a0, 100                   ; ...
        la    t6, rndn                  ; ...
        jalr  ra, t6, 0                 ; ...
        li    t0, 30                    ; ...
        bgeu  a0, t0, zn_put            ; ...
        j     zn_dn                     ; ...
zn_4:   blez  s7, zn_5                  ; in demand: it grows
        li    t0, 4                     ; ...
        bgeu  s8, t0, zn_put            ; ...
        li    a0, 2000                  ; ...
        la    t6, rndn                  ; ...
        jalr  ra, t6, 0                 ; ...
        bge   a0, s7, zn_put            ; ...
        addi  s8, s8, 1                 ; ...
        j     zn_lv                     ; ...
zn_5:   li    t0, -200                  ; little wanted: it may decline
        bge   s7, t0, zn_put            ; ...
        li    a0, 3000                  ; ...
        la    t6, rndn                  ; ...
        jalr  ra, t6, 0                 ; ...
        neg   t0, s7                    ; ...
        bge   a0, t0, zn_put            ; ...
zn_dn:  addi  s8, s8, -1                ; one density less
        li    s6, 0                     ; (none: empty)
        beqz  s8, zn_put                ; ...
zn_lv:  addi  s6, s8, -1                ; the level for the density, one design or the other
        slli  s6, s6, 1                 ; ...
        add   t0, s0, s1                ; ...
        add   t0, t0, s8                ; ...
        andi  t0, t0, 1                 ; ...
        add   s6, s6, t0                ; ...
        addi  s6, s6, 2                 ; ...
zn_put: beq   s6, s4, zn_f              ; a new level: its pictures
        li    t0, 90                    ; ...
        mul   a3, s3, t0                ; ...
        li    t0, 9                     ; ...
        mul   t0, s6, t0                ; ...
        add   a3, a3, t0                ; ...
        addi  a3, a3, T_RES_EMPTY       ; ...
        addi  a0, s0, -1                ; ...
        addi  a1, s1, -1                ; ...
        li    a2, 3                     ; ...
        li    a4, 1                     ; ...
        la    t6, put_block             ; ...
        jalr  ra, t6, 0                 ; ...
        li    t0, 90                    ; (the middle, as it is stored now)
        mul   s2, s3, t0                ; ...
        li    t0, 9                     ; ...
        mul   t0, s6, t0                ; ...
        add   s2, s2, t0                ; ...
        addi  s2, s2, T_RES_EMPTY + 4   ; ...
zn_f:   li    t0, F_POWER | F_ROAD      ; the middle's flags; a mark if it lacks power
        xor   t1, s5, t0                ; ...   or a road
        snez  t1, t1                    ; ...
        slli  t1, t1, 13                ; (F_MARK)
        or    t2, s5, t1                ; ...
        andi  a2, s2, PICMASK           ; ...
        or    a2, a2, t2                ; ...
        beq   a2, s2, zn_c              ; (as it was)
        li    t0, F_MARK                ; the mark comes or goes: drawn again
        xor   t1, a2, s2                ; ...
        and   t1, t1, t0                ; ...
        sd    a2, 80(sp)                ; ...
        beqz  t1, zn_s                  ; ...
        mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        la    t6, dirty_cell            ; ...
        jalr  ra, t6, 0                 ; ...
zn_s:   mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        ld    a2, 80(sp)                ; ...
        la    t6, m_setc                ; ...
        jalr  ra, t6, 0                 ; ...
zn_c:   beqz  s6, zn_n                  ; the census: what the zone holds
        li    t0, 1                     ; ...
        beq   s6, t0, zn_n              ; ...
        addi  t1, s6, -2                ; ...
        srli  t1, t1, 1                 ; ...
        addi  t1, t1, 1                 ; ...
        li    t0, 5                     ; ...
        mul   t0, t0, s3                ; ...
        add   t1, t1, t0                ; ...
        slli  t1, t1, 3                 ; ...
        la    t0, pop_tab               ; ...
        add   t0, t0, t1                ; ...
        ld    t0, 0(t0)                 ; ...
        la    t1, g_popr                ; ...
        slli  t2, s3, 3                 ; ...
        add   t1, t1, t2                ; ...
        ld    t2, 0(t1)                 ; ...
        add   t2, t2, t0                ; ...
        sd    t2, 0(t1)                 ; ...
zn_n:   addi  s0, s0, 1                 ; ...
        li    t0, MAPN                  ; ...
        blt   s0, t0, zn_x              ; ...
