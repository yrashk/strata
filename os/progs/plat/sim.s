; demand(): each kind's demand from the census; the bar shows the new
; numbers; a shortage of power is told
demand: addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        ld    t3, g_popr - g(gp)        ; homes: twice the jobs, and forty more
        ld    t4, g_popc - g(gp)        ; ...
        ld    t5, g_popi - g(gp)        ; ...
        add   a0, t4, t5                ; ...
        slli  a0, a0, 1                 ; ...
        addi  a0, a0, 40                ; ...
        mv    a1, t3                    ; ...
        call  ratio                     ; ...
        sd    a0, g_dr - g(gp)          ; ...
        ld    t3, g_popr - g(gp)        ; shops: a quarter of the residents, a fifth
        ld    t5, g_popi - g(gp)        ;   of the industry's jobs, and ten
        srli  a0, t3, 2                 ; ...
        li    t0, 5                     ; ...
        divu  t1, t5, t0                ; ...
        add   a0, a0, t1                ; ...
        addi  a0, a0, 10                ; ...
        ld    a1, g_popc - g(gp)        ; ...
        call  ratio                     ; ...
        sd    a0, g_dc - g(gp)          ; ...
        ld    t3, g_popr - g(gp)        ; industry: a third of the residents and
        li    t0, 3                     ;   sixty (the market outside)
        divu  a0, t3, t0                ; ...
        addi  a0, a0, 60                ; ...
        ld    a1, g_popi - g(gp)        ; ...
        call  ratio                     ; ...
        sd    a0, g_di - g(gp)          ; ...
        ld    t0, g_tax - g(gp)         ; taxes above seven per cent keep people away,
        addi  t0, t0, -TAX0             ;   below it bring them
        li    t1, 60                    ; ...
        mul   t0, t0, t1                ; ...
        la    t1, g_dr                  ; ...
        li    t2, 3                     ; ...
dm_t:   ld    a0, 0(t1)                 ; ...
        sub   a0, a0, t0                ; ...
        li    t3, 1000                  ; ...
        ble   a0, t3, dm_t1             ; ...
        mv    a0, t3                    ; ...
dm_t1:  neg   t3, t3                    ; ...
        bge   a0, t3, dm_t2             ; ...
        mv    a0, t3                    ; ...
dm_t2:  sd    a0, 0(t1)                 ; ...
        addi  t1, t1, 8                 ; ...
        addi  t2, t2, -1                ; ...
        bnez  t2, dm_t                  ; ...
        li    t0, 1                     ; the bar: its bars and numbers
        sd    t0, g_dbar - g(gp)        ; ...
        ld    t0, g_short - g(gp)       ; too little power: said once
        ld    t1, g_shown - g(gp)       ; ...
        sd    t0, g_shown - g(gp)       ; ...
        sd    zero, g_short - g(gp)     ; ...
        beqz  t0, dm_r                  ; ...
        bnez  t1, dm_r                  ; ...
        la    a0, msg_short             ; ...
        la    t6, say                   ; ...
        jalr  ra, t6, 0                 ; ...
dm_r:   ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; plants_turn(): every plant shows its other picture (the smoke moves)
plants_turn:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the plant
        sd    s1, 16(sp)                ; s1 = its cell
        sd    s2, 24(sp)                ; s2 = x
        sd    s3, 32(sp)                ; s3 = y
        li    s0, 0                     ; ...
pt_p:   ld    t0, g_nplant - g(gp)      ; ...
        bge   s0, t0, pt_r              ; ...
        slli  t0, s0, 3                 ; ...
        la    t1, plants                ; ...
        add   t0, t0, t1                ; ...
        li    s1, 0                     ; ...
pt_c:   slli  t0, s0, 3                 ; ...
        la    t1, plants                ; ...
        add   t0, t0, t1                ; ...
        lw    s2, 0(t0)                 ; ...
        lw    s3, 4(t0)                 ; ...
        andi  t1, s1, 3                 ; ...
        add   s2, s2, t1                ; ...
        srli  t1, s1, 2                 ; ...
        add   s3, s3, t1                ; ...
        mv    a0, s2                    ; ...
        mv    a1, s3                    ; ...
        la    t6, m_getc                ; ...
        jalr  ra, t6, 0                 ; ...
        andi  t0, a0, PICMASK           ; (still a plant)
        addi  t0, t0, -T_COAL           ; ...
        li    t1, 32                    ; ...
        bgeu  t0, t1, pt_n              ; ...
        li    t1, 16                    ; the other picture
        bltu  t0, t1, pt_o              ; ...
        li    t1, -16                   ; ...
pt_o:   add   a2, a0, t1                ; ...
        mv    a0, s2                    ; ...
        mv    a1, s3                    ; ...
        la    t6, m_setc                ; ...
        jalr  ra, t6, 0                 ; ...
        mv    a0, s2                    ; ...
        mv    a1, s3                    ; ...
        la    t6, dirty_cell            ; ...
        jalr  ra, t6, 0                 ; ...
pt_n:   addi  s1, s1, 1                 ; ...
        li    t0, 16                    ; ...
        blt   s1, t0, pt_c              ; ...
        addi  s0, s0, 1                 ; ...
