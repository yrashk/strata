; =============================================================================
; gallery.s: several towns: four places to keep one, and a panel to choose
; =============================================================================
;
; A town is kept in /ws/plat-N.sav, N = 1..4 its place (g_slot; file.s
; makes the name). O opens the gallery: how many towns are kept (a query of
; the file system: the files that have a population, /ws/population>0) and,
; for each place, the attributes its file carries (GETATTR: population,
; year, funds) or that it is empty. 1..4 opens that town, or makes new land
; there; any other key goes back.

MD_GALLERY = 4                          ; the gallery's panel (g_modal)

        .data                           ; D-LS
        .align 8                        ; dwords
gl_q:     .ascii "/ws/year>0"           ; the query: the towns kept
gl_q_e:                                 ; (its end)
gl_t0:    .ascii " PLAT: YOUR TOWNS, \0" ; the panel's lines
gl_t0b:   .ascii " kept\0"              ; ...
gl_res:   .ascii " residents, \0"       ; ...
gl_fun:   .ascii ", funds \0"           ; ...
gl_none:  .ascii "(empty)\0"            ; ...
gl_t7:    .ascii "1-4: that town, or new land there. Esc: back.\0" ; ...
gl_a_pop: .ascii "population"           ; the attributes read
gl_a_yr:  .ascii "year"                 ; ...
gl_a_fun: .ascii "funds"                ; ...
        .align 8                        ; ...
gl_val:   .space 4 * 4 * 8              ; each place: kept?, population, year, funds
gl_n:     .dword 0                      ; towns kept (the query's count)
        .text                           ; resident code
        .far                            ; code units (paged in by the kernel)
        .align UNIT                     ; a unit
unit_gal:
u_gldraw:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; the far return link
        call  gallery_draw              ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        xret  ra                        ; back (paged in again if it had to go)

; gallery_draw(): the panel
gallery_draw:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the panel's left
        sd    s1, 16(sp)                ; s1 = a line's top
        sd    s2, 24(sp)                ; s2 = the line
        sd    s3, 32(sp)                ; s3 = the place's numbers
        call  gl_read                   ; what the files say
        la    t6, panel_open            ; ...
        jalr  ra, t6, 0                 ; ...
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        li    s2, 0                     ; ...
gd2_l:  la    t6, bg_line               ; ...
        bnez  s2, gd2_1                 ; 0: the title and the count
        la    a1, gl_t0                 ; ...
        call  gl_str                    ; ...
        la    t0, gl_n                  ; ...
        ld    a0, 0(t0)                 ; ...
        call  gl_num                    ; ...
        la    a1, gl_t0b                ; ...
        call  gl_str                    ; ...
        j     gd2_o                     ; ...
gd2_1:  addi  t0, s2, -2                ; 2..5: the places
        li    t1, 4                     ; ...
        bgeu  t0, t1, gd2_7             ; ...
        li    t1, '>'                   ; (the place in use marked)
        ld    t2, g_slot - g(gp)        ; ...
        addi  t2, t2, -1                ; ...
        beq   t0, t2, gd2_m             ; ...
        li    t1, ' '                   ; ...
gd2_m:  sb    t1, 0(t6)                 ; ...
        addi  t2, t0, '1'               ; ...
        sb    t2, 1(t6)                 ; ...
        li    t1, ' '                   ; ...
        sb    t1, 2(t6)                 ; ...
        sb    t1, 3(t6)                 ; ...
        addi  t6, t6, 4                 ; ...
        slli  t0, t0, 5                 ; ...
        la    s3, gl_val                ; ...
        add   s3, s3, t0                ; ...
        ld    t0, 0(s3)                 ; ...
        bnez  t0, gd2_k                 ; ...
        la    a1, gl_none               ; ...
        call  gl_str                    ; ...
        j     gd2_o                     ; ...
gd2_k:  ld    a0, 8(s3)                 ; ...
        call  gl_num                    ; ...
        la    a1, gl_res                ; ...
        call  gl_str                    ; ...
        ld    a0, 16(s3)                ; (a year: no comma)
        call  gl_year                   ; ...
        la    a1, gl_fun                ; ...
        call  gl_str                    ; ...
        ld    a0, 24(s3)                ; ...
        call  gl_num                    ; ...
        j     gd2_o                     ; ...
gd2_7:  li    t0, 7                     ; 7: how to use it
        bne   s2, t0, gd2_o             ; ...
        la    a1, gl_t7                 ; ...
        call  gl_str                    ; ...
gd2_o:  mv    a0, s0                    ; the line
        mv    a1, s1                    ; ...
        la    t5, panel_line            ; ...
        jalr  ra, t5, 0                 ; ...
        addi  s1, s1, 20                ; ...
        addi  s2, s2, 1                 ; ...
        li    t0, 8                     ; ...
        blt   s2, t0, gd2_l             ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        addi  sp, sp, 48                ; pop the frame
        ret                             ; done

; gl_read(): gl_n and gl_val from the file system
gl_read:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the place
        sd    s1, 16(sp)                ; s1 = its numbers
        sd    s2, 24(sp)                ; s2 = records left; a record
        la    t0, gl_val                ; nothing yet
        li    t1, 16                    ; ...
gr_c:   sd    zero, 0(t0)               ; ...
        addi  t0, t0, 8                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, gr_c                  ; ...
        la    t0, gl_n                  ; ...
        sd    zero, 0(t0)               ; ...
        ld    t0, g_wopen - g(gp)       ; the file server, where the window
        beqz  t0, gr_1                  ;   server's endpoint is
        la    a0, sv_fs                 ; ...
        li    a1, 2                     ; ...
        li    a2, WC_EP                 ; ...
        la    t6, sys_lookup            ; ...
        jalr  ra, t6, 0                 ; ...
        bnez  a0, gr_ws                 ; ...
gr_1:   la    a0, gl_q                  ; the query: how many towns
        li    a1, gl_q_e - gl_q         ; ...
        la    t6, sys_count             ; ...
        jalr  ra, t6, 0                 ; ...
        bltz  a0, gr_2                  ; ...
        la    t0, gl_n                  ; ...
        sd    a0, 0(t0)                 ; ...
gr_2:   li    s0, 1                     ; each place: its file's attributes
gr_p:   addi  t0, s0, -1                ; ...
        slli  t0, t0, 5                 ; ...
        la    s1, gl_val                ; ...
        add   s1, s1, t0                ; ...
        mv    a0, s0                    ; its name
        la    t6, sv_slot               ; ...
        jalr  ra, t6, 0                 ; ...
        la    a0, sv_name               ; GETATTR
        li    a1, SV_NAME_L             ; ...
        la    t6, sys_put               ; ...
        jalr  ra, t6, 0                 ; ...
        li    a0, WC_EP                 ; ...
        li    a1, 43                    ; ...
        li    a2, 0                     ; ...
        li    a3, SV_NAME_L             ; ...
        li    a4, 0                     ; ...
        la    t6, sys_msg               ; ...
        jalr  ra, t6, 0                 ; ...
        blez  a0, gr_n                  ; (no file, or no attributes)
        mv    s2, a0                    ; ...
        li    t0, 1                     ; it is kept
        sd    t0, 0(s1)                 ; ...
        la    t0, sys_hdr               ; the records
        ld    a1, 16(t0)                ; ...
        li    t1, 1024                  ; ...
        bleu  a1, t1, gr_g              ; ...
        mv    a1, t1                    ; ...
gr_g:   la    a0, rowbuf                ; ...
        la    t6, sys_get               ; ...
        jalr  ra, t6, 0                 ; ...
        la    t3, rowbuf                ; t3 = the record
gr_r:   beqz  s2, gr_n                  ; ...
        lbu   t0, 4(t3)                 ; a number?
        bnez  t0, gr_rn                 ; ...
        lhu   t0, 2(t3)                 ; its value: after the name, padded
        addi  t1, t0, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        add   t1, t1, t3                ; ...
        ld    t1, 8(t1)                 ; ...
        lbu   t2, 8(t3)                 ; which: p(opulation), y(ear), f(unds)
        li    t4, 'p'                   ; ...
        li    t5, 8                     ; ...
        beq   t2, t4, gr_s              ; ...
        li    t4, 'y'                   ; ...
        li    t5, 16                    ; ...
        beq   t2, t4, gr_s              ; ...
        li    t4, 'f'                   ; ...
        li    t5, 24                    ; ...
        bne   t2, t4, gr_rn             ; ...
gr_s:   add   t5, t5, s1                ; ...
        sd    t1, 0(t5)                 ; ...
gr_rn:  lhu   t0, 0(t3)                 ; the next record
        add   t3, t3, t0                ; ...
        addi  s2, s2, -1                ; ...
        j     gr_r                      ; ...
gr_n:   addi  s0, s0, 1                 ; ...
        li    t0, 4                     ; ...
        ble   s0, t0, gr_p              ; ...
        ld    a0, g_slot - g(gp)        ; (the name of the town in use again)
        la    t6, sv_slot               ; ...
        jalr  ra, t6, 0                 ; ...
gr_ws:  ld    t0, g_wopen - g(gp)       ; the window server again
        beqz  t0, gr_r0                 ; ...
        la    a0, sv_ws                 ; ...
        li    a1, 2                     ; ...
        li    a2, WC_EP                 ; ...
        la    t6, sys_lookup            ; ...
        jalr  ra, t6, 0                 ; ...
        cclear c6                       ; (c6 stays empty: the band comes back there)
gr_r0:  ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

; gl_str(a1 = text) / gl_num(a0) / gl_year(a0): appended at t6
gl_str: lbu   t0, 0(a1)                 ; ...
        beqz  t0, gls_r                 ; ...
        sb    t0, 0(t6)                 ; ...
        addi  a1, a1, 1                 ; ...
        addi  t6, t6, 1                 ; ...
        j     gl_str                    ; ...
gls_r:  ret                             ; done
gl_year:                                ; ...
        la    t0, t_num                 ; ...
        j     gn_0                      ; ...
gl_num: la    t0, t_comma               ; ...
gn_0:   addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; ...
        mv    s0, t6                    ; ...
        jalr  ra, t0, 0                 ; ...
        mv    t6, s0                    ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

        .org  unit_gal + UNIT           ; (a unit fits its slot: else an error here)
        .text                           ; code
