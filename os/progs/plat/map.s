; =============================================================================
; map.s: Plat's map: the land made from a seed, the cells, the tools
; =============================================================================
;
; The map is MAPN x MAPN cells of 16 bits in the arena, row by row, above
; plat.dat's far block (g_mapb): each cell holds the number of its picture
; (dat.s: T_*); what the picture is (a road, water, ...) is its kind
; (R_KIND: K_*); its top bits are flags that the simulation keeps (F_*).
; A road's or a power line's picture is the one for the
; neighbours it joins (a mask: N 1, E 2, S 4, W 8), water's the one for its
; eight neighbours (R_BLOB); a tool that changes a cell makes its
; neighbours' pictures again (fix_around).
;
; A cell is read and written with an 8-byte transfer of the word that holds
; it (m_get, m_set); the land is written a row at a time (gen_land), and
; the drawing fetches whole rows (draw.s).

MAPN     = 128                          ; cells across and down
MAPB     = MAPN * MAPN * 2              ; bytes of the map
TL_DOZE  = 0                            ; tools: the bulldozer
TL_ROAD  = 1                            ; ... a road
TL_LINE  = 2                            ; ... a power line
TL_QUERY = 3                            ; ... ask what is there
NTOOL    = 13                           ; ... (tools.s has the rest)
C_DOZE   = 1                            ; what a cell costs: cleared
C_ROAD   = 10                           ; ... a road
C_BRIDGE = 50                           ; ... a bridge
C_LINE   = 5                            ; ... a power line
C_LWATER = 20                           ; ... over the water
TL_RES   = 4                            ; ... homes
TL_COM   = 5                            ; ... shops and offices
TL_IND   = 6                            ; ... industry
TL_COAL  = 7                            ; ... a coal power plant
C_ZONE   = 100                          ; ... a zone
C_COAL   = 3000                         ; ... a coal plant
PICMASK  = 0x3ff                        ; a cell: its picture
F_MARK   = 0x2000                       ; ... a zone's middle: a mark is drawn over it
F_ROAD   = 0x4000                       ; ... a zone's middle: a road is in reach
F_POWER  = 0x8000                       ; ... it has power
NZONEPIC = 30                           ; zone pictures (dat.s: T_RES_EMPTY ..)
D_EW     = 0                            ; a bridge's or a line's way: east-west
D_NS     = 1                            ; ... north-south

        .data                           ; D-LS
        .align 8                        ; dwords
m_word:   .dword 0                      ; the word of the map that holds a cell
maprow:   .space MAPN * 2               ; a row of the map
        .text                           ; code

; rnd() -> a0 = 0..32767, the next random number
rnd:    ld    a0, g_seed - g(gp)        ; the usual linear congruence
        li    t0, 1103515245            ; ...
        mul   a0, a0, t0                ; ...
        addi  a0, a0, 12345             ; ...
        sd    a0, g_seed - g(gp)        ; ...
        srli  a0, a0, 16                ; ...
        li    t0, 0x7fff                ; ...
        and   a0, a0, t0                ; ...
        ret                             ; done

; rndn(a0 = n) -> a0 = 0..n-1
rndn:   addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    a0, 8(sp)                 ; ...
        call  rnd                       ; ...
        ld    t0, 8(sp)                 ; ...
        remu  a0, a0, t0                ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 16                ; pop the frame
        ret                             ; done

; ---- the land -------------------------------------------------------------------

; bit_set(a0 = bitmap, a1 = x, a2 = y): that cell's bit (if it is on the map)
bit_set:
        li    t0, MAPN                  ; ...
        bgeu  a1, t0, bs_r              ; ...
        bgeu  a2, t0, bs_r              ; ...
        slli  t0, a2, 7                 ; the bit: y * 128 + x
        add   t0, t0, a1                ; ...
        srli  t1, t0, 3                 ; ...
        add   t1, t1, a0                ; ...
        andi  t0, t0, 7                 ; ...
        li    t2, 1                     ; ...
        sll   t2, t2, t0                ; ...
        lbu   t3, 0(t1)                 ; ...
        or    t3, t3, t2                ; ...
        sb    t3, 0(t1)                 ; ...
bs_r:   ret                             ; done

; bit_get(a0 = bitmap, a1 = x, a2 = y) -> a0 = that cell's bit; off the map:
; a3
bit_get:
        li    t0, MAPN                  ; ...
        bgeu  a1, t0, bg_off            ; ...
        bgeu  a2, t0, bg_off            ; ...
        slli  t0, a2, 7                 ; ...
        add   t0, t0, a1                ; ...
        srli  t1, t0, 3                 ; ...
        add   t1, t1, a0                ; ...
        andi  t0, t0, 7                 ; ...
        lbu   a0, 0(t1)                 ; ...
        srl   a0, a0, t0                ; ...
        andi  a0, a0, 1                 ; ...
        ret                             ; ...
bg_off: mv    a0, a3                    ; ...
        ret                             ; done

; blob(a0 = bitmap, a1 = cx, a2 = cy, a3 = radius): the cells around (cx, cy)
; within about that radius (an edge made ragged by chance) are set
blob:   addi  sp, sp, -64               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the bitmap
        sd    s1, 16(sp)                ; s1 = cx
        sd    s2, 24(sp)                ; s2 = cy
        sd    s3, 32(sp)                ; s3 = r
        sd    s4, 40(sp)                ; s4 = dy
        sd    s5, 48(sp)                ; s5 = dx
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        mv    s2, a2                    ; ...
        mv    s3, a3                    ; ...
        neg   s4, s3                    ; ...
bl_y:   neg   s5, s3                    ; ...
bl_x:   mul   t0, s4, s4                ; d2 = dx^2 + dy^2
        mul   t1, s5, s5                ; ...
        add   t0, t0, t1                ; ...
        mul   t1, s3, s3                ; inside r^2 less a random bit of 2r
        sd    t0, 56(sp)                ; ...
        slli  a0, s3, 1                 ; ...
        call  rndn                      ; ...
        mul   t1, s3, s3                ; ...
        sub   t1, t1, a0                ; ...
        ld    t0, 56(sp)                ; ...
        bgt   t0, t1, bl_n              ; ...
        mv    a0, s0                    ; ...
        add   a1, s1, s5                ; ...
        add   a2, s2, s4                ; ...
        call  bit_set                   ; ...
bl_n:   addi  s5, s5, 1                 ; ...
        ble   s5, s3, bl_x              ; ...
        addi  s4, s4, 1                 ; ...
        ble   s4, s3, bl_y              ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        ld    s5, 48(sp)                ; ...
        addi  sp, sp, 64                ; pop the frame
        ret                             ; done

; gen_land(): a new map from the random numbers: a river from the top edge
; to the bottom one, one to three lakes, clumps of woods, open land
gen_land:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = x; a counter
        sd    s1, 16(sp)                ; s1 = y
        sd    s2, 24(sp)                ; s2 = the river's width
        sd    s3, 32(sp)                ; s3 = its drift
        sd    s4, 40(sp)                ; s4 = the cell's picture
        la    t0, m_water               ; nothing yet
        li    t1, MAPN * MAPN / 4       ; (both bitmaps)
gl_c:   sd    zero, 0(t0)               ; ...
        addi  t0, t0, 8                 ; ...
        addi  t1, t1, -8                ; ...
        bnez  t1, gl_c                  ; ...
        li    a0, 72                    ; the river: it starts somewhere in the middle half
        call  rndn                      ; ...
        addi  s0, a0, 28                ; ...
        li    a0, 3                     ; ... 3 to 5 cells wide
        call  rndn                      ; ...
        addi  s2, a0, 3                 ; ...
        li    s3, 0                     ; ...
        li    s1, 0                     ; ...
gl_ry:  li    s4, 0                     ; a row of it
gl_rx:  la    a0, m_water               ; ...
        add   a1, s0, s4                ; ...
        mv    a2, s1                    ; ...
        call  bit_set                   ; ...
        addi  s4, s4, 1                 ; ...
        blt   s4, s2, gl_rx             ; ...
        li    a0, 16                    ; it wanders: a new drift now and then
        call  rndn                      ; ...
        li    t0, 3                     ; ...
        bgeu  a0, t0, gl_d1             ; ...
        li    s3, -1                    ; ...
gl_d1:  addi  t1, a0, -3                ; ...
        li    t0, 3                     ; ...
        bgeu  t1, t0, gl_d2             ; ...
        li    s3, 1                     ; ...
gl_d2:  addi  t1, a0, -6                ; ...
        li    t0, 3                     ; ...
        bgeu  t1, t0, gl_d3             ; ...
        li    s3, 0                     ; ...
gl_d3:  add   s0, s0, s3                ; ...
        li    t0, 4                     ; (it stays away from the sides)
        bge   s0, t0, gl_d4             ; ...
        mv    s0, t0                    ; ...
        li    s3, 1                     ; ...
gl_d4:  li    t0, MAPN - 4              ; ...
        sub   t0, t0, s2                ; ...
        ble   s0, t0, gl_d5             ; ...
        mv    s0, t0                    ; ...
        li    s3, -1                    ; ...
gl_d5:  addi  s1, s1, 1                 ; ...
        li    t0, MAPN                  ; ...
        blt   s1, t0, gl_ry             ; ...
        li    a0, 3                     ; lakes: one to three
        call  rndn                      ; ...
        addi  s0, a0, 1                 ; ...
gl_lk:  li    a0, MAPN - 16             ; ...
        call  rndn                      ; ...
        addi  s1, a0, 8                 ; ...
        li    a0, MAPN - 16             ; ...
        call  rndn                      ; ...
        addi  s2, a0, 8                 ; ...
        li    a0, 6                     ; radius 4..9
        call  rndn                      ; ...
        addi  a3, a0, 4                 ; ...
        la    a0, m_water               ; ...
        mv    a1, s1                    ; ...
        mv    a2, s2                    ; ...
        call  blob                      ; ...
        addi  s0, s0, -1                ; ...
        bnez  s0, gl_lk                 ; ...
        li    a0, 10                    ; woods: 16 to 25 clumps
        call  rndn                      ; ...
        addi  s0, a0, 16                ; ...
gl_wd:  li    a0, MAPN                  ; ...
        call  rndn                      ; ...
        mv    s1, a0                    ; ...
        li    a0, MAPN                  ; ...
        call  rndn                      ; ...
        mv    s2, a0                    ; ...
        li    a0, 6                     ; radius 2..7
        call  rndn                      ; ...
        addi  a3, a0, 2                 ; ...
        la    a0, m_woods               ; ...
        mv    a1, s1                    ; ...
        mv    a2, s2                    ; ...
        call  blob                      ; ...
        addi  s0, s0, -1                ; ...
        bnez  s0, gl_wd                 ; ...
        li    s1, 0                     ; the map, a row at a time
gl_y:   li    s0, 0                     ; ...
gl_x:   la    a0, m_water               ; water: by its eight neighbours
        mv    a1, s0                    ; ...
        mv    a2, s1                    ; ...
        li    a3, 0                     ; ...
        call  bit_get                   ; ...
        beqz  a0, gl_nw                 ; ...
        mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        la    a2, gl_isw                ; ...
        call  water_mask                ; ...
        la    t0, res + R_BLOB          ; ...
        add   t0, t0, a0                ; ...
        lbu   s4, 0(t0)                 ; ...
        addi  s4, s4, T_WATER           ; ...
        j     gl_put                    ; ...
gl_nw:  la    a0, m_woods               ; woods
        mv    a1, s0                    ; ...
        mv    a2, s1                    ; ...
        li    a3, 0                     ; ...
        call  bit_get                   ; ...
        beqz  a0, gl_gr                 ; ...
        call  rnd                       ; ...
        andi  s4, a0, 3                 ; ...
        addi  s4, s4, T_WOODS           ; ...
        j     gl_put                    ; ...
gl_gr:  call  rnd                       ; open land: mostly the plainest ground
        andi  a0, a0, 7                 ; ...
        li    s4, T_GROUND              ; ...
        li    t0, 4                     ; ...
        bltu  a0, t0, gl_put            ; ...
        andi  a0, a0, 3                 ; ...
        add   s4, s4, a0                ; ...
        bnez  a0, gl_put                ; ...
        li    s4, T_GROUND + 1          ; ...
gl_put: la    t0, maprow                ; ...
        slli  t1, s0, 1                 ; ...
        add   t0, t0, t1                ; ...
        sh    s4, 0(t0)                 ; ...
        addi  s0, s0, 1                 ; ...
        li    t0, MAPN                  ; ...
        blt   s0, t0, gl_x              ; ...
        ld    t0, g_mapb - g(gp)        ; the row into the map
        slli  t1, s1, 8                 ; ...
        add   t0, t0, t1                ; ...
        la    t1, maprow                ; ...
        li    t2, MAPN * 2              ; ...
        tput  tg11, t1, c0, t0, t2      ; ...
        twait 1 << 11                   ; ...
        addi  s1, s1, 1                 ; ...
        li    t0, MAPN                  ; ...
        blt   s1, t0, gl_y              ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        addi  sp, sp, 48                ; pop the frame
        ret                             ; done
gl_isw: mv    a2, a1                    ; gl_isw(a0 = x, a1 = y) -> a0: water there?
        mv    a1, a0                    ; (off the map: yes, the river goes on)
        la    a0, m_water               ; ...
        li    a3, 1                     ; ...
        j     bit_get                   ; ...

; water_mask(a0 = x, a1 = y, a2 = is_water(x, y) -> a0) -> a0 = the mask of
; the eight neighbours that are water (N 1, NE 2, E 4, SE 8, S 16, SW 32,
; W 64, NW 128)
water_mask:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = x
        sd    s1, 16(sp)                ; s1 = y
        sd    s2, 24(sp)                ; s2 = the test
        sd    s3, 32(sp)                ; s3 = the neighbour
        sd    s4, 40(sp)                ; s4 = the mask
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        mv    s2, a2                    ; ...
        li    s3, 0                     ; ...
        li    s4, 0                     ; ...
wm_l:   la    t0, wm_dx                 ; ...
        add   t0, t0, s3                ; ...
        lb    a0, 0(t0)                 ; ...
        lb    a1, 8(t0)                 ; ...
        add   a0, a0, s0                ; ...
        add   a1, a1, s1                ; ...
        jalr  ra, s2, 0                 ; ...
        sll   a0, a0, s3                ; ...
        or    s4, s4, a0                ; ...
        addi  s3, s3, 1                 ; ...
        li    t0, 8                     ; ...
        blt   s3, t0, wm_l              ; ...
        mv    a0, s4                    ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        addi  sp, sp, 48                ; pop the frame
        ret                             ; done

        .data                           ; D-LS
wm_dx:    .byte 0, 1, 1, 1, 0, -1, -1, -1 ; the eight neighbours: N NE E SE S SW W NW
wm_dy:    .byte -1, -1, 0, 1, 1, 1, 0, -1 ; ...
        .align 8                        ; ...
        .text                           ; code

; ---- cells ----------------------------------------------------------------------

; m_addr(a0 = x, a1 = y) -> t1 = the arena offset of the word that holds the
; cell, t2 = the cell's offset in it (x, y on the map)
m_addr: slli  t1, a1, 8                 ; ...
        slli  t2, a0, 1                 ; ...
        add   t1, t1, t2                ; ...
        andi  t2, t1, 7                 ; ...
        sub   t1, t1, t2                ; ...
        ld    t0, g_mapb - g(gp)        ; ...
        add   t1, t1, t0                ; ...
        ret                             ; done

; m_getc(a0 = x, a1 = y) -> a0 = the cell as it is stored (its picture and
; its flags, F_*); -1 off the map
m_getc: li    t0, MAPN                  ; ...
        bgeu  a0, t0, mg_off            ; ...
        bgeu  a1, t0, mg_off            ; ...
        slli  t1, a1, 8                 ; (m_addr)
        slli  t2, a0, 1                 ; ...
        add   t1, t1, t2                ; ...
        andi  t2, t1, 7                 ; ...
        sub   t1, t1, t2                ; ...
        ld    t0, g_mapb - g(gp)        ; ...
        add   t1, t1, t0                ; ...
        la    t0, m_word                ; ...
        li    t3, 8                     ; ...
        tget  tg11, t0, c0, t1, t3      ; ...
        twait 1 << 11                   ; ...
        add   t0, t0, t2                ; ...
        lhu   a0, 0(t0)                 ; ...
        ret                             ; ...
mg_off: li    a0, -1                    ; ...
        ret                             ; done

; m_get(a0 = x, a1 = y) -> a0 = the cell's picture; -1 off the map
m_get:  addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        call  m_getc                    ; ...
        bltz  a0, mgp_r                 ; ...
        andi  a0, a0, PICMASK           ; ...
mgp_r:  ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; m_setc(a0 = x, a1 = y, a2 = the cell as it is to be stored): it is (not
; to be drawn for that)
m_setc: li    t0, MAPN                  ; ...
        bgeu  a0, t0, ms_r              ; ...
        bgeu  a1, t0, ms_r              ; ...
        slli  t1, a1, 8                 ; (m_addr)
        slli  t2, a0, 1                 ; ...
        add   t1, t1, t2                ; ...
        andi  t2, t1, 7                 ; ...
        sub   t1, t1, t2                ; ...
        ld    t0, g_mapb - g(gp)        ; ...
        add   t1, t1, t0                ; ...
        la    t0, m_word                ; ...
        li    t3, 8                     ; ...
        tget  tg11, t0, c0, t1, t3      ; ...
        twait 1 << 11                   ; ...
        add   t4, t0, t2                ; ...
        sh    a2, 0(t4)                 ; ...
        tput  tg11, t0, c0, t1, t3      ; ...
        twait 1 << 11                   ; ...
ms_r:   ret                             ; done

; m_set(a0 = x, a1 = y, a2 = picture): the cell is that (its flags cleared);
; it is to be drawn
m_set:  li    t0, MAPN                  ; ...
        bgeu  a0, t0, ms_r              ; ...
        bgeu  a1, t0, ms_r              ; ...
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    a0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        call  m_setc                    ; ...
        ld    a0, 8(sp)                 ; ...
        ld    a1, 16(sp)                ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 24                ; pop the frame
        j     dirty_cell                ; ...

; zone_of(a0 = picture) -> a0 = the zone picture's number (kind * 10 +
; level: 0 empty, 1 a site, 2 + 2 * (density - 1) + variant), a1 = the
; cell in it (0..8, row by row: 4 is the middle); a0 = -1 if it is no zone
zone_of:
        addi  t0, a0, -T_RES_EMPTY      ; ...
        li    t1, NZONEPIC * 9          ; ...
        bgeu  t0, t1, zo_no             ; ...
        li    t1, 9                     ; ...
        divu  a0, t0, t1                ; ...
        remu  a1, t0, t1                ; ...
        ret                             ; ...
zo_no:  li    a0, -1                    ; ...
        ret                             ; done

; kind(a0 = picture) -> a0 = its kind (K_*); -1: off the map
kind:   bltz  a0, kd_r                  ; ...
        la    t0, res + R_KIND          ; ...
        add   t0, t0, a0                ; ...
        lbu   a0, 0(t0)                 ; ...
kd_r:   ret                             ; done

; m_kind(a0 = x, a1 = y) -> a0 = the cell's kind, a1 = its picture
m_kind: addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        call  m_get                     ; ...
        mv    a1, a0                    ; ...
        call  kind                      ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; dirty_cell(a0 = x, a1 = y): that cell is to be drawn
dirty_cell:
        ld    t0, g_dx0 - g(gp)         ; an empty rectangle: this cell
        ld    t1, g_dx1 - g(gp)         ; ...
        blt   t0, t1, dc_g              ; ...
        sd    a0, g_dx0 - g(gp)         ; ...
        sd    a1, g_dy0 - g(gp)         ; ...
        addi  t0, a0, 1                 ; ...
        sd    t0, g_dx1 - g(gp)         ; ...
        addi  t0, a1, 1                 ; ...
        sd    t0, g_dy1 - g(gp)         ; ...
        ret                             ; ...
dc_g:   ble   t0, a0, dc_1              ; otherwise it grows to hold it
        sd    a0, g_dx0 - g(gp)         ; ...
dc_1:   addi  t0, a0, 1                 ; ...
        ble   t0, t1, dc_2              ; ...
        sd    t0, g_dx1 - g(gp)         ; ...
dc_2:   ld    t0, g_dy0 - g(gp)         ; ...
        ble   t0, a1, dc_3              ; ...
        sd    a1, g_dy0 - g(gp)         ; ...
dc_3:   addi  t0, a1, 1                 ; ...
        ld    t1, g_dy1 - g(gp)         ; ...
        ble   t0, t1, dc_4              ; ...
        sd    t0, g_dy1 - g(gp)         ; ...
dc_4:   ret                             ; done

; is_water(a0 = x, a1 = y) -> a0 = 1 if the cell is water (a bridge or a
; line over it counts; off the map too)
is_water:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        call  m_kind                    ; ...
        li    t0, 1                     ; ...
        bltz  a0, iw_r                  ; ...
        li    t1, K_WATER               ; ...
        beq   a0, t1, iw_r              ; ...
        li    t1, K_BRIDGE              ; ...
        beq   a0, t1, iw_r              ; ...
        li    t1, K_LWATER              ; ...
        beq   a0, t1, iw_r              ; ...
        li    t1, K_RBRIDGE             ; ...
        beq   a0, t1, iw_r              ; ...
        li    t0, 0                     ; ...
iw_r:   mv    a0, t0                    ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; joins(a0 = picture, a1 = 0: roads, 1: power lines, 2: rail) -> a0 = the
; ways (N 1, E 2, S 4, W 8) in which it joins its neighbours: every way for
; a road, a line (lines also join what they power), a track; one way for a
; bridge, something over the water, a crossing (jn_tab says which)
joins:  addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    a0, 8(sp)                 ; ...
        mv    t5, a1                    ; ...
        call  kind                      ; ...
        ld    t4, 8(sp)                 ; t4 = the picture
        li    t0, 20                    ; t0 = what the kind is to this network:
        mul   t1, t5, t0                ;   jn_tab[network][kind]: 0 nothing, 1 every
        add   t1, t1, a0                ;   way, 2 a crossing's way (east-west at +0),
        la    t2, jn_tab                ;   3 the other way round, 4 a bridge's way
        add   t2, t2, t1                ;   (NBLOB pictures each way)
        lbu   t0, 0(t2)                 ; ...
        li    t6, 0                     ; ...
        beqz  t0, jn_r                  ; ...
        li    t6, 15                    ; ...
        li    t1, 1                     ; ...
        beq   t0, t1, jn_r              ; ...
        la    t2, jn_base               ; t1 = which picture of its kind
        add   t2, t2, a0                ; ...
        add   t2, t2, a0                ; ...
        lhu   t2, 0(t2)                 ; ...
        sub   t1, t4, t2                ; ...
        li    t2, 4                     ; ...
        bne   t0, t2, jn_c              ; ...
        li    t2, NBLOB                 ; ...
        divu  t1, t1, t2                ; ...
        j     jn_d                      ; ...
jn_c:   li    t2, 3                     ; ...
        bne   t0, t2, jn_d              ; ...
        xori  t1, t1, 1                 ; ...
jn_d:   li    t6, 10                    ; t1 = 0: east-west
        beqz  t1, jn_r                  ; ...
        li    t6, 5                     ; ... 1: north-south
jn_r:   mv    a0, t6                    ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 16                ; pop the frame
        ret                             ; done

        .data                           ; D-LS
jn_tab:   .byte 0, 0, 0, 0, 0           ; roads, by kind (K_*): road, bridge, under
          .byte 1, 4, 0, 2, 0           ; a line, under a track
          .byte 0, 0, 0, 0, 2           ; ...
          .byte 0, 0, 0, 0, 0           ; ...
          .byte 0, 0, 0, 0, 0           ; lines: line, over a road, over the water,
          .byte 0, 0, 1, 3, 4           ; zones, plants, over a track, stations
          .byte 1, 1, 0, 0, 0           ; ...
          .byte 3, 1, 1, 0, 0           ; ...
          .byte 0, 0, 0, 0, 0           ; rail: track, bridge, over a road,
          .byte 0, 0, 0, 0, 0           ; under a line
          .byte 0, 0, 1, 4, 3           ; ...
          .byte 2, 0, 0, 0, 0           ; ...
        .align 2                        ; ...
jn_base:  .half 0, 0, 0, 0, 0, T_ROAD, T_BRIDGE, T_LINE ; each kind's first picture
          .half T_LROAD, T_LWATER, T_RES_EMPTY, T_COAL ; ...
          .half T_RAIL, T_RBRIDGE, T_RROAD, T_LRAIL ; ...
          .half T_POLICE, T_FIREST, T_PARK, T_BURN ; ...
        .align 8                        ; ...
        .text                           ; code

; join_mask(a0 = x, a1 = y, a2 = 0 roads, 1 lines) -> a0 = the neighbours
; that join this cell (N 1, E 2, S 4, W 8)
join_mask:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = x
        sd    s1, 16(sp)                ; s1 = y
        sd    s2, 24(sp)                ; s2 = roads or lines
        sd    s3, 32(sp)                ; s3 = the way (0..3)
        sd    s4, 40(sp)                ; s4 = the mask
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        mv    s2, a2                    ; ...
        li    s3, 0                     ; ...
        li    s4, 0                     ; ...
jm_l:   la    t0, jm_dx                 ; the neighbour that way
        add   t0, t0, s3                ; ...
        lb    a0, 0(t0)                 ; ...
        lb    a1, 4(t0)                 ; ...
        add   a0, a0, s0                ; ...
        add   a1, a1, s1                ; ...
        call  m_get                     ; ...
        bltz  a0, jm_n                  ; ...
        mv    a1, s2                    ; does it join back (the opposite way)?
        call  joins                     ; ...
        addi  t0, s3, 2                 ; ...
        andi  t0, t0, 3                 ; ...
        srl   a0, a0, t0                ; ...
        andi  a0, a0, 1                 ; ...
        sll   a0, a0, s3                ; ...
        or    s4, s4, a0                ; ...
jm_n:   addi  s3, s3, 1                 ; ...
        li    t0, 4                     ; ...
        blt   s3, t0, jm_l              ; ...
        mv    a0, s4                    ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        addi  sp, sp, 48                ; pop the frame
        ret                             ; done

        .data                           ; D-LS
jm_dx:    .byte 0, 1, 0, -1             ; the four ways: N E S W
jm_dy:    .byte -1, 0, 1, 0             ; ...
        .align 8                        ; ...
        .text                           ; code

; fix_cell(a0 = x, a1 = y): a road's or a line's picture joins its
; neighbours as they are now
fix_cell:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = x
        sd    s1, 16(sp)                ; s1 = y
        sd    s2, 24(sp)                ; s2 = the first picture of its kind
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        call  m_kind                    ; ...
        li    a2, 0                     ; a road (with the traffic it has)
        li    t0, K_ROAD                ; ...
        bne   a0, t0, fc_0              ; ...
        li    s2, T_ROAD                ; ...
        addi  t0, a1, -T_TLIGHT         ; ...
        li    t1, 32                    ; ...
        bgeu  t0, t1, fc_1              ; ...
        srli  t0, t0, 4                 ; ...
        slli  t0, t0, 4                 ; ...
        addi  s2, t0, T_TLIGHT          ; ...
        j     fc_1                      ; ...
fc_0:   li    a2, 1                     ; a line
        li    s2, T_LINE                ; ...
        li    t0, K_LINE                ; ...
        beq   a0, t0, fc_1              ; ...
        li    a2, 2                     ; a track
        li    s2, T_RAIL                ; ...
        li    t0, K_RAIL                ; ...
        bne   a0, t0, fc_r              ; (anything else stays)
fc_1:   mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        call  join_mask                 ; ...
        add   a2, a0, s2                ; ...
        mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        call  m_set                     ; ...
fc_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

; fix_around(a0 = x, a1 = y): the cell and its four neighbours join again
fix_around:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = x
        sd    s1, 16(sp)                ; s1 = y
        sd    s2, 24(sp)                ; s2 = the way
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        call  fix_cell                  ; ...
        li    s2, 0                     ; ...
fa_l:   la    t0, jm_dx                 ; ...
        add   t0, t0, s2                ; ...
        lb    a0, 0(t0)                 ; ...
        lb    a1, 4(t0)                 ; ...
        add   a0, a0, s0                ; ...
        add   a1, a1, s1                ; ...
        call  fix_cell                  ; ...
        addi  s2, s2, 1                 ; ...
        li    t0, 4                     ; ...
        blt   s2, t0, fa_l              ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

; water_pic(a0 = x, a1 = y) -> a0 = the water picture for that cell
water_pic:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        la    a2, is_water              ; ...
        call  water_mask                ; ...
        la    t0, res + R_BLOB          ; ...
        add   t0, t0, a0                ; ...
        lbu   a0, 0(t0)                 ; ...
        addi  a0, a0, T_WATER           ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; put_block(a0 = x, a1 = y, a2 = size, a3 = picture, a4 = 1: the pictures
; follow one another row by row, 0: all the same one): the square is those
; pictures; the roads and lines round it join it again
put_block:
        addi  sp, sp, -64               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = x
        sd    s1, 16(sp)                ; s1 = y
        sd    s2, 24(sp)                ; s2 = size
        sd    s3, 32(sp)                ; s3 = the next picture
        sd    s4, 40(sp)                ; s4 = 1: it goes on
        sd    s5, 48(sp)                ; s5 = dx
        sd    s6, 56(sp)                ; s6 = dy
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        mv    s2, a2                    ; ...
        mv    s3, a3                    ; ...
        mv    s4, a4                    ; ...
        li    s6, 0                     ; ...
pb_y:   li    s5, 0                     ; ...
pb_x:   add   a0, s0, s5                ; ...
        add   a1, s1, s6                ; ...
        mv    a2, s3                    ; ...
        call  m_set                     ; ...
        add   s3, s3, s4                ; ...
        addi  s5, s5, 1                 ; ...
        blt   s5, s2, pb_x              ; ...
        addi  s6, s6, 1                 ; ...
        blt   s6, s2, pb_y              ; ...
        addi  s6, s1, -1                ; the ring round it: roads and lines join again
pb_ry:  addi  s5, s0, -1                ; ...
pb_rx:  mv    a0, s5                    ; ...
        mv    a1, s6                    ; ...
        call  fix_cell                  ; ...
        addi  s5, s5, 1                 ; ...
        add   t0, s0, s2                ; ...
        ble   s5, t0, pb_rx             ; ...
        addi  s6, s6, 1                 ; ...
        add   t0, s1, s2                ; ...
        ble   s6, t0, pb_ry             ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        ld    s5, 48(sp)                ; ...
        ld    s6, 56(sp)                ; ...
        addi  sp, sp, 64                ; pop the frame
        ret                             ; done

; map_hash() -> a0 = a 32-bit checksum of the map (for the demos' reports)
map_hash:
        li    t5, 0                     ; t5 = the sum
        li    t6, 0                     ; t6 = the row
mh_y:   ld    t0, g_mapb - g(gp)        ; ...
        slli  t1, t6, 8                 ; ...
        add   t0, t0, t1                ; ...
        la    t1, maprow                ; ...
        li    t2, MAPN * 2              ; ...
        tget  tg11, t1, c0, t0, t2      ; ...
        twait 1 << 11                   ; ...
        li    t3, MAPN                  ; ...
mh_x:   lhu   t0, 0(t1)                 ; sum = sum * 31 + cell
        slli  t2, t5, 5                 ; ...
        sub   t5, t2, t5                ; ...
        add   t5, t5, t0                ; ...
        addi  t1, t1, 2                 ; ...
        addi  t3, t3, -1                ; ...
        bnez  t3, mh_x                  ; ...
        addi  t6, t6, 1                 ; ...
        li    t0, MAPN                  ; ...
        blt   t6, t0, mh_y              ; ...
        slli  a0, t5, 32                ; (32 bits of it)
        srli  a0, a0, 32                ; ...
        ret                             ; done

