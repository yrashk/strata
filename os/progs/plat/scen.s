; =============================================================================
; scen.s: scenarios: invented towns, each with a trouble and a goal
; =============================================================================
;
; C opens the scenarios' panel; 1..3 starts one. The town being played is
; saved first (and kept as this year: Y brings it back). The scenario's
; town is made on the demos' land (their fixed seed) by a list of keys,
; the same kind a demo plays (tools/plat-assets.py: DEMOS 12..14), played
; at once without drawing; then its trouble starts, and a goal with a
; year it must be met by:
;
;   1  Ferrybank: a town on the river, which floods often.
;      Goal: 1,200 residents in 5 years.
;   2  Cinderford: next to nothing in the treasury, and its old coal plant
;      fails in its fourth month. Goal: 12,000 in the treasury in 4 years.
;   3  Hollow Reach: built, but never wired to its plant, and taxed at
;      12 %. Goal: 1,000 residents in 3 years.
;
; Once a month (scen_month) the trouble is kept up and the goal looked at:
; met, the town is told so; the year reached, the scenario ends; every
; January the bar says how far it is. The scenario's state (which, its end
; year, its months) is in the town's file (file.s: SV_SCEN).

MD_SCEN  = 7                            ; the scenarios' panel (g_modal)
SC_FLOOD = 1                            ; troubles: floods often (events.s)
SC_FAIL  = 2                            ; ... the coal plant fails in month 4
SC_GOAL_POP = 1                         ; goals: residents
SC_GOAL_FUNDS = 2                       ; ... the treasury
SC_ENT   = 64                           ; bytes of a scenario's entry (sc_tab)
NSCEN    = 3                            ; scenarios
SC_NSTK  = 4                            ; loops a script may nest

        .data                           ; D-LS
        .align 8                        ; dwords
sc_tab:   .dword 12, SC_GOAL_POP, 1200, 5 ; each: its demo (the keys), the goal, its
          .dword SC_FLOOD, 0, sc_n1, sc_i1 ;   number, years; the trouble, the funds
          .dword 13, SC_GOAL_FUNDS, 12000, 4 ;   at the start (0: as the keys leave
          .dword SC_FAIL, 900, sc_n2, sc_i2 ;   them), its name, what is said
          .dword 14, SC_GOAL_POP, 1000, 3 ; ...
          .dword 0, 0, sc_n3, sc_i3     ; ...
sc_stk:   .space SC_NSTK * 16           ; a script's open loops: where, how many left
sc_msg:   .space 72                     ; a message made
sc_n1:    .ascii "Ferrybank\0"          ; the scenarios' names
sc_n2:    .ascii "Cinderford\0"         ; ...
sc_n3:    .ascii "Hollow Reach\0"       ; ...
sc_i1:    .ascii "Ferrybank: the river floods. 1,200 residents in 5 years.\0" ; what each says
sc_i2:    .ascii "Cinderford: in debt; mind the old plant. 12,000 in 4 years.\0" ; ...
sc_i3:    .ascii "Hollow Reach: dark and taxed. 1,000 residents in 3 years.\0" ; ...
sc_t0:    .ascii " SCENARIOS: A TOWN, A TROUBLE, A GOAL\0" ; the panel's lines
sc_t1:    .ascii "1  FERRYBANK: on the river, which floods.\0" ; ...
sc_t2:    .ascii "   Goal: 1,200 residents in 5 years.\0" ; ...
sc_t3:    .ascii "2  CINDERFORD: in debt, its coal plant old.\0" ; ...
sc_t4:    .ascii "   Goal: 12,000 in the treasury in 4 years.\0" ; ...
sc_t5:    .ascii "3  HOLLOW REACH: unlit, and taxed at 12%.\0" ; ...
sc_t6:    .ascii "   Goal: 1,000 residents in 3 years.\0" ; ...
sc_t7:    .ascii "Your town is saved first (Y brings it back).\0" ; ...
sc_t8:    .ascii "1-3: start one. Esc: back.\0" ; ...
sc_won:   .ascii "Goal met! The town thanks its mayor.\0" ; messages
sc_lost:  .ascii "The years are up: the goal was not met.\0" ; ...
sc_g1:    .ascii "Goal: \0"             ; ... "Goal: N of T residents, by Y."
sc_g2:    .ascii " of \0"               ; ...
sc_g3:    .ascii " residents, by \0"    ; ...
sc_g4:    .ascii " in the treasury, by \0" ; ...
sc_g5:    .ascii ".\0"                  ; ...
        .align 8                        ; ...
sc_lines: .dword sc_t0, sc_t1, sc_t2, sc_t3, sc_t4 ; ...
          .dword sc_t5, sc_t6, sc_t7, sc_t8 ; ...
        .text                           ; resident code
; scen_go(a0 = 1..NSCEN): the town played now saved (and kept as this
; year), then that scenario started. Resident: its keys play the town's
; months, which page in more code units than there are slots, and a unit
; that called it could be gone when they return.
scen_go:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the scenario
        sd    s1, 16(sp)                ; s1 = the demo's step, kept
        mv    s0, a0                    ; ...
        ld    s1, g_demo - g(gp)        ; (not a demo's town)
        bnez  s1, sg_0                  ; ...
        ld    a0, g_year - g(gp)        ; ...
        call  keep                      ; ...
        li    t0, 1                     ; (while the keys play: as in a demo, no
        sd    t0, g_demo - g(gp)        ;   sound, no Ledger, nothing kept)
sg_0:   mv    a0, s0                    ; the land
        la    t5, u_smake               ; ...
        xcall ra, c0, t5                ; ...
        call  sc_run                    ; the town on it
        sd    s1, g_demo - g(gp)        ; ...
        mv    a0, s0                    ; the trouble, the goal
        la    t5, u_sset                ; ...
        xcall ra, c0, t5                ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; sc_run(a0 = keys, as a demo's): played at once: each step's tics (the
; town's time goes on), then its key
sc_run: addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the step
        sd    s1, 16(sp)                ; s1 = tics left
        sd    s2, 24(sp)                ; s2 = loops open
        sd    s3, 32(sp)                ; s3 = the key
        mv    s0, a0                    ; ...
        li    s2, 0                     ; ...
sr2_l:  lbu   s1, 0(s0)                 ; ...
        beqz  s1, sr2_r                 ; (the end)
        lbu   s3, 1(s0)                 ; ...
        addi  s0, s0, 2                 ; ...
sr2_t:  addi  s1, s1, -1                ; its tics (the first is the key's own)
        beqz  s1, sr2_k                 ; ...
        call  step                      ; ...
        j     sr2_t                     ; ...
sr2_k:  li    t0, DK_LOOP               ; a loop begins: its count
        bne   s3, t0, sr2_e             ; ...
        lbu   t1, 0(s0)                 ; ...
        addi  s0, s0, 2                 ; ...
        slli  t2, s2, 4                 ; ...
        la    t3, sc_stk                ; ...
        add   t2, t2, t3                ; ...
        sd    s0, 0(t2)                 ; ...
        sd    t1, 8(t2)                 ; ...
        addi  s2, s2, 1                 ; ...
        j     sr2_l                     ; ...
sr2_e:  li    t0, DK_END                ; a loop ends: again, or closed
        bne   s3, t0, sr2_d             ; ...
        addi  t2, s2, -1                ; ...
        slli  t2, t2, 4                 ; ...
        la    t3, sc_stk                ; ...
        add   t2, t2, t3                ; ...
        ld    t1, 8(t2)                 ; ...
        addi  t1, t1, -1                ; ...
        sd    t1, 8(t2)                 ; ...
        blez  t1, sr2_x                 ; ...
        ld    s0, 0(t2)                 ; ...
        j     sr2_l                     ; ...
sr2_x:  addi  s2, s2, -1                ; ...
        j     sr2_l                     ; ...
sr2_d:  mv    a0, s3                    ; any other: the key
        call  do_key                    ; ...
        j     sr2_l                     ; ...
sr2_r:  ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        addi  sp, sp, 40                ; pop the frame
        ret                             ; done

        .far                            ; code units (paged in by the kernel)
        .align UNIT                     ; a unit
unit_scen:
u_smake:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; the far return link
        call  scen_make                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        xret  ra                        ; back (paged in again if it had to go)
u_sset:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; the far return link
        call  scen_set                  ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        xret  ra                        ; back (paged in again if it had to go)
u_smonth:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; the far return link
        call  scen_month                ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        xret  ra                        ; back (paged in again if it had to go)
u_sdraw:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; the far return link
        call  scen_draw                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        xret  ra                        ; back (paged in again if it had to go)

; sc_ent(a0 = 1..NSCEN) -> a0 = its entry in sc_tab
sc_ent: addi  a0, a0, -1                ; ...
        li    t0, SC_ENT                ; ...
        mul   a0, a0, t0                ; ...
        la    t0, sc_tab                ; ...
        add   a0, a0, t0                ; ...
        ret                             ; done

; scen_make(a0 = 1..NSCEN) -> a0 = its keys: the demos' land made, nothing
; on it yet
scen_make:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        call  sc_ent                    ; ...
        sd    a0, 8(sp)                 ; ...
        la    t6, town_reset            ; the demos' land
        jalr  ra, t6, 0                 ; ...
        li    t0, SEED0                 ; ...
        sd    t0, g_seed - g(gp)        ; ...
        la    t6, gen_land              ; ...
        jalr  ra, t6, 0                 ; ...
        sd    zero, g_scen - g(gp)      ; (no scenario while it is made)
        sd    zero, g_sprob - g(gp)     ; ...
        sd    zero, g_evoff - g(gp)     ; ...
        la    t0, res + R_DEMO          ; its keys: that demo's
        ld    t1, 8(sp)                 ; ...
        ld    t1, 0(t1)                 ; ...
        addi  t1, t1, -1                ; ...
        slli  t1, t1, 1                 ; ...
        add   t1, t1, t0                ; ...
        lhu   t1, 0(t1)                 ; ...
        add   a0, t0, t1                ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 16                ; pop the frame
        ret                             ; done

; scen_set(a0 = 1..NSCEN): its town made: its funds, trouble and goal set
scen_set:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the scenario
        sd    s1, 16(sp)                ; s1 = its entry
        mv    s0, a0                    ; ...
        call  sc_ent                    ; ...
        mv    s1, a0                    ; ...
        ld    t0, 40(s1)                ; the funds it starts with
        beqz  t0, sst_1                 ; ...
        sd    t0, g_funds - g(gp)       ; ...
sst_1:  sd    s0, g_scen - g(gp)        ; the scenario: its end year, its trouble
        ld    t0, g_year - g(gp)        ; ...
        ld    t1, 24(s1)                ; ...
        add   t0, t0, t1                ; ...
        sd    t0, g_send - g(gp)        ; ...
        sd    zero, g_smon - g(gp)      ; ...
        ld    t0, 32(s1)                ; ...
        sd    t0, g_sprob - g(gp)       ; ...
        la    t6, town_shown            ; ...
        jalr  ra, t6, 0                 ; ...
        ld    a0, 56(s1)                ; what is said
        li    a1, SP_ADV_CLERK          ; ...
        la    t6, say_adv               ; ...
        jalr  ra, t6, 0                 ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; scen_month(): the scenario's month: its trouble, its goal
scen_month:
        ld    a0, g_scen - g(gp)        ; (none)
        beqz  a0, sm2_r0                ; ...
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the entry
        sd    s1, 16(sp)                ; s1 = how far it is
        call  sc_ent                    ; ...
        mv    s0, a0                    ; ...
        ld    t0, 32(s0)                ; the trouble (kept for events.s)
        sd    t0, g_sprob - g(gp)       ; ...
        ld    t1, g_smon - g(gp)        ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, g_smon - g(gp)        ; ...
        li    t2, SC_FAIL               ; the old plant fails in the fourth month
        bne   t0, t2, sm2_g             ; ...
        li    t2, 4                     ; ...
        bne   t1, t2, sm2_g             ; ...
        li    a0, 5                     ; ...
        li    a1, 0                     ; ...
        la    t5, u_event               ; ...
        xcall ra, c0, t5                ; ...
sm2_g:  ld    s1, g_popr - g(gp)        ; the goal: met?
        ld    t0, 8(s0)                 ; ...
        li    t1, SC_GOAL_POP           ; ...
        beq   t0, t1, sm2_1             ; ...
        ld    s1, g_funds - g(gp)       ; ...
sm2_1:  ld    t0, 16(s0)                ; ...
        blt   s1, t0, sm2_2             ; ...
        li    a0, SN_COIN               ; met
        la    t6, snd_play              ; ...
        jalr  ra, t6, 0                 ; ...
        la    a0, sc_won                ; ...
        j     sm2_end                   ; ...
sm2_2:  ld    t0, g_year - g(gp)        ; the years are up?
        ld    t1, g_send - g(gp)        ; ...
        blt   t0, t1, sm2_3             ; ...
        la    a0, sc_lost               ; ...
sm2_end:
        sd    zero, g_scen - g(gp)      ; (it is over)
        sd    zero, g_sprob - g(gp)     ; ...
        li    a1, SP_ADV_CLERK          ; ...
        la    t6, say_adv               ; ...
        jalr  ra, t6, 0                 ; ...
        j     sm2_r                     ; ...
sm2_3:  ld    t0, g_month - g(gp)       ; January: how far it is
        bnez  t0, sm2_r                 ; ...
        mv    s1, s0                    ; s1 = the entry now, s0 where text goes
        la    s0, sc_msg                ; "Goal: N of T residents, by Y."
        la    a0, sc_g1                 ; ...
        la    t6, dy_str                ; ...
        jalr  ra, t6, 0                 ; ...
        ld    t0, 8(s1)                 ; ...
        ld    a0, g_popr - g(gp)        ; ...
        li    t1, SC_GOAL_POP           ; ...
        beq   t0, t1, sm2_4             ; ...
        ld    a0, g_funds - g(gp)       ; ...
sm2_4:  la    t6, dy_num                ; ...
        jalr  ra, t6, 0                 ; ...
        la    a0, sc_g2                 ; ...
        la    t6, dy_str                ; ...
        jalr  ra, t6, 0                 ; ...
        ld    a0, 16(s1)                ; ...
        la    t6, dy_num                ; ...
        jalr  ra, t6, 0                 ; ...
        ld    t0, 8(s1)                 ; ...
        la    a0, sc_g3                 ; ...
        li    t1, SC_GOAL_POP           ; ...
        beq   t0, t1, sm2_5             ; ...
        la    a0, sc_g4                 ; ...
sm2_5:  la    t6, dy_str                ; ...
        jalr  ra, t6, 0                 ; ...
        ld    a0, g_send - g(gp)        ; ...
        la    t6, dy_num                ; ...
        jalr  ra, t6, 0                 ; ...
        la    a0, sc_g5                 ; ...
        la    t6, dy_str                ; ...
        jalr  ra, t6, 0                 ; ...
        sb    zero, 0(s0)               ; ...
        la    a0, sc_msg                ; ...
        li    a1, SP_ADV_CLERK          ; ...
        la    t6, say_adv               ; ...
        jalr  ra, t6, 0                 ; ...
sm2_r:  ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; pop the frame
sm2_r0: ret                             ; done

; scen_draw(): the scenarios' panel
scen_draw:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = where text goes (dy_str's)
        sd    s1, 16(sp)                ; s1 = a line's top
        sd    s2, 24(sp)                ; s2 = the line
        sd    s3, 32(sp)                ; s3 = the panel's left
        la    t6, panel_open            ; ...
        jalr  ra, t6, 0                 ; ...
        mv    s3, a0                    ; ...
        mv    s1, a1                    ; ...
        li    s2, 0                     ; ...
sd_l:   la    s0, bg_line               ; ...
        la    t0, sc_lines              ; ...
        slli  t1, s2, 3                 ; ...
        add   t0, t0, t1                ; ...
        ld    a0, 0(t0)                 ; ...
        la    t6, dy_str                ; ...
        jalr  ra, t6, 0                 ; ...
        mv    t6, s0                    ; the line
        mv    a0, s3                    ; ...
        mv    a1, s1                    ; ...
        la    t5, panel_line            ; ...
        jalr  ra, t5, 0                 ; ...
        addi  s1, s1, 20                ; ...
        addi  s2, s2, 1                 ; ...
        li    t0, 9                     ; ...
        blt   s2, t0, sd_l              ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        addi  sp, sp, 40                ; pop the frame
        ret                             ; done

        .org  unit_scen + UNIT          ; (a unit fits its slot: else an error here)
        .text                           ; code
