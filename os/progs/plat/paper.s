        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        xret  ra                        ; back (paged in again if it had to go)
graph_draw:
        addi  sp, sp, -56               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the panel's left
        sd    s1, 16(sp)                ; s1 = its top
        sd    s2, 24(sp)                ; s2 = the year
        sd    s3, 32(sp)                ; s3 = the largest residents
        sd    s4, 40(sp)                ; s4 = the largest treasury
        la    t6, panel_open            ; ...
        jalr  ra, t6, 0                 ; ...
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        la    t6, bg_line               ; its title
        la    a1, gr_t0                 ; ...
        call  gp_str                    ; ...
        mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        la    t5, panel_line            ; (t6 is the line's end)
        jalr  ra, t5, 0                 ; ...
        la    t6, bg_line               ; how to leave
        la    a1, gr_t1                 ; ...
        call  gp_str                    ; ...
        mv    a0, s0                    ; ...
        addi  a1, s1, (BG_LINES - 1) * 20 ; ...
        la    t5, panel_line            ; (t6 is the line's end)
        jalr  ra, t5, 0                 ; ...
        li    s3, 1                     ; the largest of each
        li    s4, 1                     ; ...
        la    t0, hist_pop              ; ...
        li    t1, NHIST                 ; ...
gd_m:   ld    t2, 0(t0)                 ; ...
        bleu  t2, s3, gd_m1             ; ...
        mv    s3, t2                    ; ...
gd_m1:  ld    t2, NHIST * 8(t0)         ; ...
        bleu  t2, s4, gd_m2             ; ...
        mv    s4, t2                    ; ...
gd_m2:  addi  t0, t0, 8                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, gd_m                  ; ...
        li    s2, 0                     ; the bars, 120 pixels high at the most
gd_y:   slli  t0, s2, 3                 ; residents
        la    t1, hist_pop              ; ...
        add   t1, t1, t0                ; ...
        ld    t0, 0(t1)                 ; ...
        li    t2, 120                   ; ...
        mul   t0, t0, t2                ; ...
        divu  t0, t0, s3                ; ...
        li    a0, C_RES                 ; ...
        li    a1, 0                     ; ...
        call  gd_bar                    ; ...
        slli  t0, s2, 3                 ; treasury
        la    t1, hist_fun              ; ...
        add   t1, t1, t0                ; ...
        ld    t0, 0(t1)                 ; ...
        li    t2, 120                   ; ...
        mul   t0, t0, t2                ; ...
        divu  t0, t0, s4                ; ...
        li    a0, C_IND                 ; ...
        li    a1, 12                    ; ...
        call  gd_bar                    ; ...
        addi  s2, s2, 1                 ; ...
        li    t0, NHIST                 ; ...
        blt   s2, t0, gd_y              ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        addi  sp, sp, 56                ; pop the frame
        ret                             ; done
; gp_str(a1 = text): appended at t6 (pp_str, for this unit)
gp_str: lbu   t0, 0(a1)                 ; ...
        beqz  t0, gps_r                 ; ...
        sb    t0, 0(t6)                 ; ...
        addi  a1, a1, 1                 ; ...
        addi  t6, t6, 1                 ; ...
        j     gp_str                    ; ...
gps_r:  ret                             ; done

; gd_bar(a0 = colour's index, a1 = its place in the year's slot, t0 = its
; height; s0, s1, s2 = the panel and the year)
gd_bar: addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    t0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        la    t6, pal                   ; ...
        jalr  ra, t6, 0                 ; ...
        mv    a4, a0                    ; ...
        li    t0, 32                    ; x: 16 + 32 a year + the place
        mul   a0, s2, t0                ; ...
        addi  a0, a0, 16                ; ...
        add   a0, a0, s0                ; ...
        ld    t0, 16(sp)                ; ...
        add   a0, a0, t0                ; ...
        ld    a3, 8(sp)                 ; y: up from the base line
        beqz  a3, gb_r                  ; ...
        addi  a1, s1, 30 + 120          ; ...
        sub   a1, a1, a3                ; ...
        li    a2, 10                    ; ...
        la    t6, wc_fill               ; ...
        jalr  ra, t6, 0                 ; ...
gb_r:   ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

