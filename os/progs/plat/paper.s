; paper_draw(): the Ledger's panel: the masthead, last year in review
paper_draw:
        addi  sp, sp, -56               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the panel's left
        sd    s1, 16(sp)                ; s1 = its top; a line's
        sd    s2, 24(sp)                ; s2 = the line
        sd    s3, 32(sp)                ; s3 = the worst trouble
        sd    s4, 40(sp)                ; s4 = the approval
        la    t6, panel_open            ; the panel; s0, s1 its corner
        jalr  ra, t6, 0                 ; ...
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        li    a0, SP_PAPER_HEAD         ; the masthead
        addi  a1, s0, (BG_W * 8 - 240) / 2 ; ...
        mv    a2, s1                    ; ...
        la    t6, r_sprite              ; ...
        jalr  ra, t6, 0                 ; ...
        addi  s1, s1, 40                ; ...
        la    t5, u_trouble             ; ...
        xcall ra, c0, t5                ; ...
        mv    s3, a0                    ; ...
        mv    s4, a1                    ; ...
        li    s2, 0                     ; ...
pd_l:   la    t6, bg_line               ; ...
        li    t0, 0                     ; 0: the year
        bne   s2, t0, pd_1              ; ...
        ld    a0, g_year - g(gp)        ; ...
        addi  a0, a0, -1                ; ...
        call  pp_year                   ; ...
        la    a1, pp_t1                 ; ...
        j     pd_s                      ; ...
pd_1:   li    t0, 1                     ; 1: the headline
        bne   s2, t0, pd_2              ; ...
        la    t0, hl_tab                ; ...
        slli  t1, s3, 3                 ; ...
        add   t0, t0, t1                ; ...
        ld    a1, 0(t0)                 ; ...
        j     pd_s                      ; ...
pd_2:   li    t0, 3                     ; 3: the residents
        bne   s2, t0, pd_3              ; ...
        la    a1, pp_t3                 ; ...
        call  pp_str                    ; ...
        ld    a0, g_popr - g(gp)        ; ...
        j     pd_n                      ; ...
pd_3:   li    t0, 4                     ; 4: the jobs
        bne   s2, t0, pd_4              ; ...
        la    a1, pp_t4                 ; ...
        call  pp_str                    ; ...
        ld    a0, g_popc - g(gp)        ; ...
        ld    t0, g_popi - g(gp)        ; ...
        add   a0, a0, t0                ; ...
        j     pd_n                      ; ...
pd_4:   li    t0, 5                     ; 5: the treasury
        bne   s2, t0, pd_5              ; ...
        la    a1, pp_t5                 ; ...
        call  pp_str                    ; ...
        ld    a0, g_funds - g(gp)       ; ...
        j     pd_n                      ; ...
pd_5:   li    t0, 6                     ; 6: the approval
        bne   s2, t0, pd_6              ; ...
        la    a1, pp_t6                 ; ...
        call  pp_str                    ; ...
        mv    a0, s4                    ; ...
        call  pp_num                    ; ...
        li    t0, '%'                   ; ...
        sb    t0, 0(t6)                 ; ...
        addi  t6, t6, 1                 ; ...
        j     pd_o                      ; ...
pd_6:   li    t0, 7                     ; 7: on to the budget
        bne   s2, t0, pd_o              ; ...
        la    a1, pp_t8                 ; ...
pd_s:   call  pp_str                    ; ...
        j     pd_o                      ; ...
pd_n:   call  pp_num                    ; ...
pd_o:   mv    a0, s0                    ; the line
        mv    a1, s1                    ; ...
        la    t5, panel_line            ; (t6 is the line's end)
        jalr  ra, t5, 0                 ; ...
        addi  s1, s1, 20                ; ...
        addi  s2, s2, 1                 ; ...
        li    t0, PP_LINES              ; ...
        blt   s2, t0, pd_l              ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        addi  sp, sp, 56                ; pop the frame
        ret                             ; done

; pp_str(a1 = text) / pp_num(a0 = number): appended at t6 (budget.s's helpers,
; through their absolute addresses: they are in another unit)
pp_str: lbu   t0, 0(a1)                 ; ...
        beqz  t0, pps_r                 ; ...
        sb    t0, 0(t6)                 ; ...
        addi  a1, a1, 1                 ; ...
        addi  t6, t6, 1                 ; ...
        j     pp_str                    ; ...
pps_r:  ret                             ; done
pp_year:                                ; (a year: no comma)
        la    t0, t_num                 ; ...
        j     pn_0                      ; ...
pp_num: la    t0, t_comma               ; ...
pn_0:   addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; ...
        mv    s0, t6                    ; ...
        jalr  ra, t0, 0                 ; ...
        mv    t6, s0                    ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; graph_draw(): the history: for each of the last years, a green bar for
; its residents and a gold one for its treasury, each against the largest
        .org  unit_graph + UNIT         ; (a unit fits its slot: else an error here)
        .align UNIT                     ; a unit
unit_graph2:
u_gdraw:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; the far return link
