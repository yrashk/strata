; =============================================================================
; paper.s: the town's voice: advisers, the mayor's approval, the Plat Ledger,
; the town's history
; =============================================================================
;
; Every third month an adviser says what worries them most, with their
; portrait in the bar (advise): the clerk (money), the engineer (power,
; roads), the shopkeeper (shops), a resident (homes, crime, smoke). At a
; year's end (but in a demo) the Plat Ledger opens: last year in review, a
; headline from the town's worst trouble, the mayor's approval; Enter goes
; on to the budget. H shows the town's history: residents and the
; treasury at the last twelve years' ends. Both are panels like the
; budget's (budget.s), drawn by the server; the Ledger's masthead is art.
;
; The approval: 100, less the town's troubles (crime, pollution, traffic,
; each the mean of its map where there is any, a quarter of it; taxes, 4 a
; point above 7 %; jobs: what the residents lack), at least 0.

NHIST    = 12                           ; years the history keeps
PP_LINES = 8                            ; the Ledger's lines of text
MD_PAPER = 2                            ; panels (g_modal): the Ledger
MD_GRAPH = 3                            ; ... the history

        .data                           ; D-LS
        .align 8                        ; dwords
hist_pop: .space NHIST * 8              ; residents at each year's end, the oldest first
hist_fun: .space NHIST * 8              ; ... the treasury
pp_t1:    .ascii " in review\0"         ; the Ledger's lines
pp_t3:    .ascii "Residents: \0"        ; ...
pp_t4:    .ascii "Jobs: \0"             ; ...
pp_t5:    .ascii "Treasury: \0"         ; ...
pp_t6:    .ascii "The mayor's approval: \0" ; ...
pp_t8:    .ascii "Enter: on to the budget.\0" ; ...
hl_crime: .ascii "CRIME WORRIES THE STREETS\0" ; headlines
hl_poll:  .ascii "SMOKE HANGS OVER THE TOWN\0" ; ...
hl_traf:  .ascii "JAMS ON EVERY MAIN ROAD\0" ; ...
hl_tax:   .ascii "TAXES TOO HIGH, SAY SHOPS\0" ; ...
hl_jobs:  .ascii "RESIDENTS LOOK FOR WORK\0" ; ...
hl_good:  .ascii "A GOOD YEAR FOR PLAT\0" ; ...
gr_t0:    .ascii "RESIDENTS (green), TREASURY (gold)\0" ; the history's
gr_t1:    .ascii "Any key: back.\0"     ;   lines
ad_power: .ascii "Engineer: the plants are not enough.\0" ; advice
ad_traf:  .ascii "Engineer: jams. Rail and roads help.\0" ; ...
ad_crime: .ascii "Resident: crime! We need police.\0" ; ...
ad_poll:  .ascii "Resident: the smoke! Parks, solar.\0" ; ...
ad_shops: .ascii "Shopkeeper: zone for more shops.\0" ; ...
ad_homes: .ascii "Resident: families want homes.\0" ; ...
ad_ind:   .ascii "Engineer: industry wants land.\0" ; ...
ad_money: .ascii "Clerk: the treasury runs low.\0" ; ...
ad_tax:   .ascii "Shopkeeper: taxes are too high!\0" ; ...
ad_jobs:  .ascii "Resident: there is too little work.\0" ; ...
        .text                           ; resident code
        .far                            ; code units (paged in by the kernel)
        .align UNIT                     ; a unit
unit_paper:
u_trouble:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; the far return link
        call  trouble                   ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        xret  ra                        ; back (paged in again if it had to go)
u_advise:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; the far return link
        call  advise                    ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        xret  ra                        ; back (paged in again if it had to go)
u_yearend:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; the far return link
        call  year_end                  ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        xret  ra                        ; back (paged in again if it had to go)

; trouble() -> a0 = the worst trouble (0 crime, 1 pollution, 2 traffic, 3
; taxes, 4 jobs, 5 none), a1 = the approval (per cent)
trouble:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the worst so far
        sd    s1, 16(sp)                ; s1 = how bad
        sd    s2, 24(sp)                ; s2 = the trouble being weighed
        sd    s3, 32(sp)                ; s3 = the approval
        li    s0, 5                     ; ...
        li    s1, 8                     ; (troubles under this are none)
        li    s3, 100                   ; ...
        li    s2, 0                     ; the maps: crime, pollution, traffic
tb_m:   la    t0, tb_cm                 ; ...
        add   t0, t0, s2                ; ...
        lbu   a1, 0(t0)                 ; ...
        la    a0, m_water               ; ...
        la    t5, u_cmget               ; (in another unit)
        xcall ra, c0, t5                ; ...
        la    t0, m_water               ; the mean where there is any
        li    t1, 4096                  ; ...
        li    t2, 0                     ; t2 = sum
        li    t3, 0                     ; t3 = count
tb_s:   lbu   t4, 0(t0)                 ; ...
        beqz  t4, tb_s1                 ; ...
        add   t2, t2, t4                ; ...
        addi  t3, t3, 1                 ; ...
tb_s1:  addi  t0, t0, 1                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, tb_s                  ; ...
        li    a0, 0                     ; ...
        beqz  t3, tb_s2                 ; ...
        divu  a0, t2, t3                ; ...
tb_s2:  srli  a0, a0, 2                 ; a quarter of it
        call  tb_weigh                  ; ...
        addi  s2, s2, 1                 ; ...
        li    t0, 3                     ; ...
        blt   s2, t0, tb_m              ; ...
        ld    a0, g_tax - g(gp)         ; taxes: 4 a point above 7 %
        addi  a0, a0, -TAX0             ; ...
        bgez  a0, tb_t                  ; ...
        li    a0, 0                     ; ...
tb_t:   slli  a0, a0, 2                 ; ...
        call  tb_weigh                  ; ...
        addi  s2, s2, 1                 ; ...
        ld    t0, g_popr - g(gp)        ; jobs: what the residents (half of them
        srli  t0, t0, 1                 ;   work) lack, a tenth of it
        ld    t1, g_popc - g(gp)        ; ...
        ld    t2, g_popi - g(gp)        ; ...
        add   t1, t1, t2                ; ...
        sub   a0, t0, t1                ; ...
        bgez  a0, tb_j                  ; ...
        li    a0, 0                     ; ...
tb_j:   li    t0, 10                    ; ...
        divu  a0, a0, t0                ; ...
        call  tb_weigh                  ; ...
        bgez  s3, tb_r                  ; ...
        li    s3, 0                     ; ...
tb_r:   mv    a0, s0                    ; ...
        mv    a1, s3                    ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        addi  sp, sp, 48                ; pop the frame
        ret                             ; done
tb_weigh:
        sub   s3, s3, a0                ; a0 = how bad trouble s2 is: off the approval,
        bleu  a0, s1, tbw_r             ;   and the worst so far?
        mv    s1, a0                    ; ...
        mv    s0, s2                    ; ...
tbw_r:  ret                             ; done

; advise(): every third month, an adviser on the worst trouble, or on what
; is most in demand, or on power and money
advise: addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        ld    t0, g_month - g(gp)       ; ...
        li    t1, 3                     ; ...
        remu  t0, t0, t1                ; ...
        bnez  t0, av_r                  ; ...
        ld    t0, g_shown - g(gp)       ; the plants are too few
        la    a0, ad_power              ; ...
        li    a1, SP_ADV_ENGINEER       ; ...
        bnez  t0, av_s                  ; ...
        ld    t0, g_funds - g(gp)       ; money runs low
        la    a0, ad_money              ; ...
        li    a1, SP_ADV_CLERK          ; ...
        li    t1, 1000                  ; ...
        bltu  t0, t1, av_s              ; ...
        call  trouble                   ; the worst trouble
        la    t0, av_tab                ; ...
        slli  t1, a0, 4                 ; ...
        add   t0, t0, t1                ; ...
        ld    a1, 8(t0)                 ; ...
        ld    a0, 0(t0)                 ; ...
        bnez  a0, av_s                  ; ...
        ld    t0, g_dc - g(gp)          ; none: what is most wanted
        la    a0, ad_shops              ; ...
        li    a1, SP_ADV_SHOPKEEPER     ; ...
        li    t1, 500                   ; ...
        bgt   t0, t1, av_s              ; ...
        ld    t0, g_dr - g(gp)          ; ...
        la    a0, ad_homes              ; ...
        li    a1, SP_ADV_RESIDENT       ; ...
        bgt   t0, t1, av_s              ; ...
        ld    t0, g_di - g(gp)          ; ...
        la    a0, ad_ind                ; ...
        li    a1, SP_ADV_ENGINEER       ; ...
        ble   t0, t1, av_r              ; ...
av_s:   la    t6, say_adv               ; ...
        jalr  ra, t6, 0                 ; ...
av_r:   ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; year_end(): the history moves on a year; the Ledger opens (but in a demo)
year_end:
        la    t0, hist_pop              ; the oldest goes, the year's numbers come
        li    t1, NHIST - 1             ; ...
ye_l:   ld    t2, 8(t0)                 ; ...
        sd    t2, 0(t0)                 ; ...
        ld    t2, NHIST * 8 + 8(t0)     ; ...
        sd    t2, NHIST * 8(t0)         ; ...
        addi  t0, t0, 8                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, ye_l                  ; ...
        ld    t2, g_popr - g(gp)        ; ...
        sd    t2, 0(t0)                 ; ...
        ld    t2, g_funds - g(gp)       ; ...
        sd    t2, NHIST * 8(t0)         ; ...
        ld    t0, g_demo - g(gp)        ; ...
        bnez  t0, ye_r                  ; ...
        ld    t0, g_year - g(gp)        ; the year that ended is kept (years.s)
        addi  t0, t0, -1                ; ...
        sd    t0, g_keep - g(gp)        ; ...
        li    t0, MD_PAPER              ; ...
        sd    t0, g_modal - g(gp)       ; ...
        li    t0, 1                     ; ...
        sd    t0, g_dbud - g(gp)        ; ...
ye_r:   ret                             ; done

        .org  unit_paper + UNIT         ; (a unit fits its slot: else an error here)
        .align UNIT                     ; a unit
unit_graph:
u_pdraw:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; the far return link
