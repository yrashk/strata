; =============================================================================
; fire.s: fires: they start, spread, burn out; fire stations keep them down
; =============================================================================
;
; Once a month (fire_month): every burning cell grows a month older (its
; age in the flags' bits 10..12) and after three is rubble; each spreads to
; the cells beside it that burn (zones, woods, parks, police stations) by
; chance, the less where the fire cover is strong; and a few cells picked
; by chance catch fire, again the less where the cover is strong (a
; resident says so). The cells burning are listed (f_list) so that their
; flames move every FIRE_TICS tics (fire_anim). The bulldozer puts a fire
; out (tools.s).

FIRE_TICS = 6                           ; tics between the flames' pictures
MAXFIRE  = 64                           ; fires listed
F_AGE    = 0x400                        ; a burning cell's age: one month
FIRE_OUT = 3                            ; months a cell burns

        .data                           ; D-LS
        .align 8                        ; dwords
f_list:   .space MAXFIRE * 2            ; the cells burning: u8 x, y
f_n:      .dword 0                      ; how many
msg_fire: .ascii "Resident: fire! Stations put it out.\0" ; a message
burns:    .byte 0, 0, 0, 1, 0           ; what burns, by kind (K_*): woods, zones, police
          .byte 0, 0, 0, 0, 0           ;   stations, parks
          .byte 1, 0, 0, 0, 0           ; ...
          .byte 0, 1, 0, 1, 0           ; ...
        .align 8                        ; ...
        .text                           ; resident code
        .far                            ; code units (paged in by the kernel)
        .align UNIT                     ; a unit
unit_fire:
u_fire:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; the far return link
        call  fire_month                ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        xret  ra                        ; back (paged in again if it had to go)
u_fanim:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; the far return link
        call  fire_anim                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        xret  ra                        ; back (paged in again if it had to go)

; fire_month(): the fires' month
fire_month:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = x; the fire
        sd    s1, 16(sp)                ; s1 = y; the way
        sd    s2, 24(sp)                ; s2 = the row changed
        sd    s3, 32(sp)                ; s3 = the cell as stored
        sd    s4, 40(sp)                ; s4 = tries left
        la    t0, f_n                   ; ...
        sd    zero, 0(t0)               ; ...
        li    s1, 0                     ; every burning cell: a month older
fm_y:   ld    t0, g_mapb - g(gp)        ; ...
        slli  t1, s1, 8                 ; ...
        add   t0, t0, t1                ; ...
        la    t1, maprow                ; ...
        li    t2, MAPN * 2              ; ...
        tget  tg11, t1, c0, t0, t2      ; ...
        twait 1 << 11                   ; ...
        li    s0, 0                     ; ...
        li    s2, 0                     ; ...
fm_x:   la    t1, maprow                ; ...
        slli  t2, s0, 1                 ; ...
        add   t1, t1, t2                ; ...
        lhu   s3, 0(t1)                 ; ...
        andi  t2, s3, PICMASK           ; ...
        addi  t2, t2, -T_BURN           ; ...
        li    t3, 4                     ; ...
        bgeu  t2, t3, fm_n              ; ...
        li    t3, F_AGE                 ; ...
        add   s3, s3, t3                ; ...
        srli  t4, s3, 10                ; ...
        andi  t4, t4, 7                 ; ...
        li    t3, FIRE_OUT              ; ...
        bltu  t4, t3, fm_l              ; burnt out: rubble
        andi  s3, s0, 1                 ; ...
        addi  s3, s3, T_RUBBLE          ; ...
        sh    s3, 0(t1)                 ; ...
        li    s2, 1                     ; ...
        mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        la    t6, dirty_cell            ; ...
        jalr  ra, t6, 0                 ; ...
        j     fm_n                      ; ...
fm_l:   sh    s3, 0(t1)                 ; still burning: listed
        li    s2, 1                     ; ...
        mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        call  f_add                     ; ...
fm_n:   addi  s0, s0, 1                 ; ...
        li    t0, MAPN                  ; ...
        blt   s0, t0, fm_x              ; ...
        beqz  s2, fm_ny                 ; ...
        ld    t0, g_mapb - g(gp)        ; ...
        slli  t1, s1, 8                 ; ...
        add   t0, t0, t1                ; ...
        la    t1, maprow                ; ...
        li    t2, MAPN * 2              ; ...
        tput  tg11, t1, c0, t0, t2      ; ...
        twait 1 << 11                   ; ...
fm_ny:  addi  s1, s1, 1                 ; ...
        li    t0, MAPN                  ; ...
        blt   s1, t0, fm_y              ; ...
        la    t0, f_n                   ; the listed fires spread (not those they
        ld    s4, 0(t0)                 ;   light now: they are listed after them)
        li    s0, 0                     ; ...
fm_s:   bge   s0, s4, fm_i              ; ...
        slli  t0, s0, 1                 ; ...
        la    t1, f_list                ; ...
        add   t1, t1, t0                ; ...
        li    s1, 0                     ; the four ways
fm_w:   slli  t0, s0, 1                 ; ...
        la    t1, f_list                ; ...
        add   t1, t1, t0                ; ...
        lbu   a0, 0(t1)                 ; ...
        lbu   a1, 1(t1)                 ; ...
        la    t2, jm_dx                 ; ...
        add   t2, t2, s1                ; ...
        lb    t3, 0(t2)                 ; ...
        add   a0, a0, t3                ; ...
        lb    t3, 4(t2)                 ; ...
        add   a1, a1, t3                ; ...
        li    a2, 35                    ; (35 in 100, less the cover)
        li    a3, 1                     ; ...
        call  f_try                     ; ...
        addi  s1, s1, 1                 ; ...
        li    t0, 4                     ; ...
        blt   s1, t0, fm_w              ; ...
        addi  s0, s0, 1                 ; ...
        j     fm_s                      ; ...
fm_i:   li    s4, 6                     ; new fires: six cells picked by chance
fm_il:  li    a0, MAPN                  ; ...
        la    t6, rndn                  ; ...
        jalr  ra, t6, 0                 ; ...
        mv    s0, a0                    ; ...
        li    a0, MAPN                  ; ...
        la    t6, rndn                  ; ...
        jalr  ra, t6, 0                 ; ...
        mv    a1, a0                    ; ...
        mv    a0, s0                    ; ...
        li    a2, 2                     ; (2 in 100, less the cover)
        li    a3, 0                     ; (not woods)
        call  f_try                     ; ...
        beqz  a0, fm_in                 ; ...
        la    a0, msg_fire              ; a resident says so
        li    a1, SP_ADV_RESIDENT       ; ...
        la    t6, say_adv               ; ...
        jalr  ra, t6, 0                 ; ...
fm_in:  addi  s4, s4, -1                ; ...
        bnez  s4, fm_il                 ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        addi  sp, sp, 48                ; pop the frame
        ret                             ; done

; f_try(a0 = x, a1 = y, a2 = the chance in 100, a3 = 1: woods too) -> a0 =
; 1 if the cell, one that burns, caught fire (the chance less as much as the
; fire cover there)
f_try:  addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = x
        sd    s1, 16(sp)                ; s1 = y
        sd    s2, 24(sp)                ; s2 = the chance
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        mv    s2, a2                    ; ...
        sd    a3, 32(sp)                ; ...
        la    t6, m_kind                ; it burns?
        jalr  ra, t6, 0                 ; ...
        bltz  a0, ft_no                 ; ...
        la    t0, burns                 ; ...
        add   t0, t0, a0                ; ...
        lbu   t0, 0(t0)                 ; ...
        beqz  t0, ft_no                 ; ...
        ld    t0, 32(sp)                ; (woods only if asked)
        bnez  t0, ft_1                  ; ...
        li    t0, K_WOODS               ; ...
        beq   a0, t0, ft_no             ; ...
ft_1:   li    a0, CM_FIRE               ; the cover there
        mv    a1, s0                    ; ...
        mv    a2, s1                    ; ...
        la    t6, cm_val                ; ...
        jalr  ra, t6, 0                 ; ...
        li    t0, 256                   ; the chance, less the cover
        sub   t0, t0, a0                ; ...
        mul   s2, s2, t0                ; ...
        sd    s2, 32(sp)                ; ...
        li    a0, 25600                 ; ...
        la    t6, rndn                  ; ...
        jalr  ra, t6, 0                 ; ...
        ld    t0, 32(sp)                ; ...
        bgeu  a0, t0, ft_no             ; ...
        mv    a0, s0                    ; it burns
        mv    a1, s1                    ; ...
        add   a2, s0, s1                ; ...
        andi  a2, a2, 3                 ; ...
        addi  a2, a2, T_BURN            ; ...
        la    t6, m_set                 ; ...
        jalr  ra, t6, 0                 ; ...
        mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        call  f_add                     ; ...
        li    a0, 1                     ; ...
        j     ft_r                      ; ...
ft_no:  li    a0, 0                     ; ...
ft_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 40                ; pop the frame
        ret                             ; done

; f_add(a0 = x, a1 = y): the cell is listed as burning (if there is room)
f_add:  la    t0, f_n                   ; ...
        ld    t1, 0(t0)                 ; ...
        li    t2, MAXFIRE               ; ...
        bgeu  t1, t2, fa2_r             ; ...
        slli  t2, t1, 1                 ; ...
        la    t3, f_list                ; ...
        add   t3, t3, t2                ; ...
        sb    a0, 0(t3)                 ; ...
        sb    a1, 1(t3)                 ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, 0(t0)                 ; ...
fa2_r:  ret                             ; done

; fire_anim(): the listed cells still burning show their next flames
fire_anim:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the fire
        sd    s1, 16(sp)                ; s1 = x
        sd    s2, 24(sp)                ; s2 = y
        li    s0, 0                     ; ...
fi_l:   la    t0, f_n                   ; ...
        ld    t0, 0(t0)                 ; ...
        bge   s0, t0, fi_r              ; ...
        slli  t0, s0, 1                 ; ...
        la    t1, f_list                ; ...
        add   t1, t1, t0                ; ...
        lbu   s1, 0(t1)                 ; ...
        lbu   s2, 1(t1)                 ; ...
        mv    a0, s1                    ; ...
        mv    a1, s2                    ; ...
        la    t6, m_getc                ; ...
        jalr  ra, t6, 0                 ; ...
        andi  t0, a0, PICMASK           ; (still burning)
        addi  t0, t0, -T_BURN           ; ...
        li    t1, 4                     ; ...
        bgeu  t0, t1, fi_n              ; ...
        addi  t2, t0, 1                 ; the next picture
        andi  t2, t2, 3                 ; ...
        sub   a2, a0, t0                ; ...
        add   a2, a2, t2                ; ...
        mv    a0, s1                    ; ...
        mv    a1, s2                    ; ...
        la    t6, m_setc                ; ...
        jalr  ra, t6, 0                 ; ...
        mv    a0, s1                    ; ...
        mv    a1, s2                    ; ...
        la    t6, dirty_cell            ; ...
        jalr  ra, t6, 0                 ; ...
fi_n:   addi  s0, s0, 1                 ; ...
        j     fi_l                      ; ...
fi_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

        .org  unit_fire + UNIT          ; (a unit fits its slot: else an error here)
        .text                           ; code
