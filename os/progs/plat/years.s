; =============================================================================
; years.s: the town's past years, kept as the file system's snapshots
; =============================================================================
;
; At every year's end (not in a demo), and when S saves it, the town is
; saved and a snapshot of the disk is taken under the name platN-YYYY (N
; the town's place, YYYY the year: one taken again the same year replaces
; it); a town keeps its last YR_MAX years, the older ones are deleted. A
; snapshot copies nothing: the disk as of that commit stays readable, at
; /@platN-YYYY. Y opens a panel with the town's years (fs SNAP, mode 2:
; the snapshots); 1..8 brings that year's town back, read from
; /@platN-YYYY/ws/plat-N.sav (it is not saved over the town's file until
; it is saved). `snap` in a shell lists them too.

MD_YEARS = 6                            ; the years' panel (g_modal)
YR_MAX   = 8                            ; years a town keeps
YR_REC   = 40                           ; a snapshot's record: u64 commit, name[32]
YR_NREC  = 48                           ; records read at most

        .data                           ; D-LS
        .align 8                        ; dwords
yr_name:  .ascii "plat1-1900"           ; a snapshot's name: platN-YYYY
yr_name_e:                              ; (its end)
YR_NAME_L = yr_name_e - yr_name         ; ...
yr_path:  .space 48                     ; /@platN-YYYY/ws/plat-N.sav
        .align 8                        ; ...
yr_n:     .dword 0                      ; the town's years listed
yr_rec:   .space YR_MAX * 8             ; ... each one's record (an address in rowbuf)
yr_t0:    .ascii " YOUR TOWN AT EACH YEAR'S END\0" ; the panel's lines
yr_tn:    .ascii "(none kept yet: a year's end keeps one, S too)\0" ; ...
yr_tl:    .ascii "1-8: that year's town back. Esc: back.\0" ; ...
yr_at:    .ascii "  in /@\0"            ; ...
msg_yr:   .ascii "The town as it was in \0" ; a message's start
msg_yno:  .ascii "That year could not be read.\0" ; a message
yr_msg:   .space 40                     ; the message made
        .align 8                        ; ...
        .text                           ; resident code
        .far                            ; code units (paged in by the kernel)
        .align UNIT                     ; a unit
unit_yr:
u_keep:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; the far return link
        call  yr_keep                   ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        xret  ra                        ; back (paged in again if it had to go)
u_ydraw:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; the far return link
        call  yr_draw                   ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        xret  ra                        ; back (paged in again if it had to go)
u_ypick:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; the far return link
        call  yr_pick                   ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        xret  ra                        ; back (paged in again if it had to go)

; yr_keep(a0 = the year): the town (saved just now) kept as that year's
; snapshot; the town's oldest years beyond YR_MAX deleted
yr_keep:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = years to delete
        sd    s1, 16(sp)                ; s1 = the next of them
        call  yr_nm                     ; the name
        la    t6, fs_on                 ; ...
        jalr  ra, t6, 0                 ; ...
        bnez  a0, yk_off                ; ...
        la    a0, yr_name               ; one of that name goes (if there is one)
        li    a1, 1                     ; ...
        call  yr_snap                   ; ...
        la    a0, yr_name               ; and it is taken
        li    a1, 0                     ; ...
        call  yr_snap                   ; ...
        call  yr_list                   ; the town's years: too many?
        la    t0, yr_n                  ; ...
        ld    s0, 0(t0)                 ; ...
        addi  s0, s0, -YR_MAX           ; ...
        blez  s0, yk_off                ; ...
        la    s1, rowbuf                ; the oldest go
yk_d:   mv    a0, s1                    ; this town's?
        call  yr_mine                   ; ...
        beqz  a0, yk_n                  ; ...
        addi  a0, s1, 8                 ; ...
        li    a1, 1                     ; ...
        call  yr_snap                   ; ...
        addi  s0, s0, -1                ; ...
        beqz  s0, yk_off                ; ...
yk_n:   addi  s1, s1, YR_REC            ; ...
        j     yk_d                      ; ...
yk_off: la    t6, fs_off                ; ...
        jalr  ra, t6, 0                 ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

; yr_nm(a0 = year): yr_name says it, for the town's place
yr_nm:  la    t0, yr_name               ; ...
        ld    t1, g_slot - g(gp)        ; ...
        addi  t1, t1, '0'               ; ...
        sb    t1, 4(t0)                 ; ...
        addi  t0, t0, YR_NAME_L - 1     ; the year's digits, last first
        li    t2, 4                     ; ...
        li    t3, 10                    ; ...
yn_l:   remu  t1, a0, t3                ; ...
        divu  a0, a0, t3                ; ...
        addi  t1, t1, '0'               ; ...
        sb    t1, 0(t0)                 ; ...
        addi  t0, t0, -1                ; ...
        addi  t2, t2, -1                ; ...
        bnez  t2, yn_l                  ; ...
        ret                             ; done

; yr_snap(a0 = a name, NUL-ended or 32 bytes, a1 = 0 take, 1 delete) -> a0
; = fs's answer (SNAP)
yr_snap:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    a1, 8(sp)                 ; ...
        li    a1, 0                     ; its length
yp_l:   add   t0, a0, a1                ; ...
        lbu   t0, 0(t0)                 ; ...
        beqz  t0, yp_1                  ; ...
        addi  a1, a1, 1                 ; ...
        li    t0, 32                    ; ...
        blt   a1, t0, yp_l              ; ...
yp_1:   mv    t0, a0                    ; (yr_name has no NUL: its own length)
        la    t1, yr_name               ; ...
        bne   t0, t1, yp_2              ; ...
        li    a1, YR_NAME_L             ; ...
yp_2:   sd    a1, g_tmp - g(gp)         ; ...
        la    t6, sys_put               ; ...
        jalr  ra, t6, 0                 ; ...
        li    a0, WC_EP                 ; ...
        li    a1, 45                    ; ...
        li    a2, 0                     ; ...
        ld    a3, g_tmp - g(gp)         ; ...
        ld    a4, 8(sp)                 ; ...
        la    t6, sys_msg               ; ...
        jalr  ra, t6, 0                 ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 16                ; pop the frame
        ret                             ; done

; yr_list(): the snapshots' records in rowbuf; yr_n: how many are the
; town's, yr_rec: its last YR_MAX, oldest first. Files must be reachable
; (fs_on).
yr_list:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = records left
        sd    s1, 16(sp)                ; s1 = a record
        la    t0, yr_n                  ; none yet
        sd    zero, 0(t0)               ; ...
        li    a0, WC_EP                 ; SNAP, list
        li    a1, 45                    ; ...
        li    a2, 0                     ; ...
        li    a3, 0                     ; ...
        li    a4, 2                     ; ...
        la    t6, sys_msg               ; ...
        jalr  ra, t6, 0                 ; ...
        blez  a0, yl_r                  ; ...
        li    t0, YR_NREC               ; ...
        bleu  a0, t0, yl_1              ; ...
        mv    a0, t0                    ; ...
yl_1:   mv    s0, a0                    ; ...
        li    t0, YR_REC                ; ...
        mul   a1, a0, t0                ; ...
        la    a0, rowbuf                ; ...
        la    t6, sys_get               ; ...
        jalr  ra, t6, 0                 ; ...
        la    s1, rowbuf                ; ...
yl_l:   beqz  s0, yl_r                  ; ...
        mv    a0, s1                    ; this town's: listed (the oldest goes
        call  yr_mine                   ;   when there are YR_MAX already)
        beqz  a0, yl_n                  ; ...
        la    t0, yr_n                  ; ...
        ld    t1, 0(t0)                 ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, 0(t0)                 ; ...
        la    t2, yr_rec                ; ...
        li    t3, YR_MAX                ; ...
        bleu  t1, t3, yl_a              ; ...
        addi  t3, t3, -1                ; (moved down a place)
yl_m:   ld    t4, 8(t2)                 ; ...
        sd    t4, 0(t2)                 ; ...
        addi  t2, t2, 8                 ; ...
        addi  t3, t3, -1                ; ...
        bnez  t3, yl_m                  ; ...
        sd    s1, 0(t2)                 ; ...
        j     yl_n                      ; ...
yl_a:   slli  t1, t1, 3                 ; ...
        add   t2, t2, t1                ; ...
        sd    s1, -8(t2)                ; ...
yl_n:   addi  s1, s1, YR_REC            ; ...
        addi  s0, s0, -1                ; ...
        j     yl_l                      ; ...
yl_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

; yr_mine(a0 = a record) -> a0 = 1 if it is this town's: platN-
yr_mine:
        addi  a0, a0, 8                 ; its name
        la    t0, yr_name               ; ...
        ld    t1, g_slot - g(gp)        ; ...
        addi  t1, t1, '0'               ; ...
        sb    t1, 4(t0)                 ; ...
        li    t2, 6                     ; ...
ym_l:   lbu   t3, 0(a0)                 ; ...
        lbu   t4, 0(t0)                 ; ...
        bne   t3, t4, ym_no             ; ...
        addi  a0, a0, 1                 ; ...
        addi  t0, t0, 1                 ; ...
        addi  t2, t2, -1                ; ...
        bnez  t2, ym_l                  ; ...
        li    a0, 1                     ; ...
        ret                             ; ...
ym_no:  li    a0, 0                     ; ...
        ret                             ; done

; yr_draw(): the years' panel
yr_draw:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = where text goes (dy_str's)
        sd    s1, 16(sp)                ; s1 = a line's top
        sd    s2, 24(sp)                ; s2 = the line
        sd    s3, 32(sp)                ; s3 = the panel's left
        la    t6, fs_on                 ; the town's years
        jalr  ra, t6, 0                 ; ...
        bnez  a0, yd_0                  ; ...
        call  yr_list                   ; ...
yd_0:   la    t6, fs_off                ; ...
        jalr  ra, t6, 0                 ; ...
        la    t6, panel_open            ; ...
        jalr  ra, t6, 0                 ; ...
        mv    s3, a0                    ; ...
        mv    s1, a1                    ; ...
        li    s2, 0                     ; ...
yd_l:   la    s0, bg_line               ; ...
        bnez  s2, yd_1                  ; 0: the title
        la    a0, yr_t0                 ; ...
        j     yd_s                      ; ...
yd_1:   li    t0, 9                     ; 9: how to use it
        bne   s2, t0, yd_2              ; ...
        la    a0, yr_tl                 ; ...
        j     yd_s                      ; ...
yd_2:   la    t0, yr_n                  ; 1..8: a year
        ld    t0, 0(t0)                 ; ...
        bnez  t0, yd_3                  ; ...
        li    t1, 1                     ; (none)
        bne   s2, t1, yd_o              ; ...
        la    a0, yr_tn                 ; ...
        j     yd_s                      ; ...
yd_3:   bgt   s2, t0, yd_o              ; ...
        li    t1, YR_MAX                ; ...
        bgt   s2, t1, yd_o              ; ...
        addi  t0, s2, '0'               ; its key
        sb    t0, 0(s0)                 ; ...
        li    t0, ' '                   ; ...
        sb    t0, 1(s0)                 ; ...
        sb    t0, 2(s0)                 ; ...
        addi  s0, s0, 3                 ; ...
        la    t0, yr_rec                ; its year: the name's last four
        slli  t1, s2, 3                 ; ...
        add   t0, t0, t1                ; ...
        ld    t0, -8(t0)                ; ...
        addi  t0, t0, 8 + 6             ; ...
        li    t1, 4                     ; ...
yd_y:   lbu   t2, 0(t0)                 ; ...
        sb    t2, 0(s0)                 ; ...
        addi  t0, t0, 1                 ; ...
        addi  s0, s0, 1                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, yd_y                  ; ...
        la    a0, yr_at                 ; and where it is
        la    t6, dy_str                ; ...
        jalr  ra, t6, 0                 ; ...
        la    t0, yr_rec                ; ...
        slli  t1, s2, 3                 ; ...
        add   t0, t0, t1                ; ...
        ld    a0, -8(t0)                ; ...
        addi  a0, a0, 8                 ; ...
yd_s:   la    t6, dy_str                ; ...
        jalr  ra, t6, 0                 ; ...
yd_o:   mv    t6, s0                    ; the line
        mv    a0, s3                    ; ...
        mv    a1, s1                    ; ...
        la    t5, panel_line            ; ...
        jalr  ra, t5, 0                 ; ...
        addi  s1, s1, 18                ; ...
        addi  s2, s2, 1                 ; ...
        li    t0, 10                    ; ...
        blt   s2, t0, yd_l              ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        addi  sp, sp, 40                ; pop the frame
        ret                             ; done

; yr_pick(a0 = 1..8): that year's town back, from its snapshot
yr_pick:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the record; where text goes
        sd    s1, 16(sp)                ; s1 = the choice
        mv    s1, a0                    ; ...
        la    t6, fs_on                 ; the town's years
        jalr  ra, t6, 0                 ; ...
        bnez  a0, ypk_0                 ; ...
        call  yr_list                   ; ...
ypk_0:  la    t6, fs_off                ; ...
        jalr  ra, t6, 0                 ; ...
        la    t0, yr_n                  ; there is such a year?
        ld    t0, 0(t0)                 ; ...
        li    t1, YR_MAX                ; ...
        bleu  t0, t1, ypk_1             ; ...
        mv    t0, t1                    ; ...
ypk_1:  bgt   s1, t0, ypk_r             ; ...
        la    t0, yr_rec                ; ...
        slli  t1, s1, 3                 ; ...
        add   t0, t0, t1                ; ...
        ld    t0, -8(t0)                ; ...
        addi  t0, t0, 8                 ; its name, kept (rowbuf is the file's buffer)
        la    t1, yr_name               ; ...
        li    t2, YR_NAME_L             ; ...
ypk_c:  lbu   t3, 0(t0)                 ; ...
        sb    t3, 0(t1)                 ; ...
        addi  t0, t0, 1                 ; ...
        addi  t1, t1, 1                 ; ...
        addi  t2, t2, -1                ; ...
        bnez  t2, ypk_c                 ; ...
        la    s0, yr_path               ; the path: /@NAME/ws/plat-N.sav
        li    t0, '/'                   ; ...
        sb    t0, 0(s0)                 ; ...
        li    t0, '@'                   ; ...
        sb    t0, 1(s0)                 ; ...
        addi  s0, s0, 2                 ; ...
        la    t0, yr_name               ; ...
        li    t2, YR_NAME_L             ; ...
ypk_n:  lbu   t3, 0(t0)                 ; ...
        sb    t3, 0(s0)                 ; ...
        addi  t0, t0, 1                 ; ...
        addi  s0, s0, 1                 ; ...
        addi  t2, t2, -1                ; ...
        bnez  t2, ypk_n                 ; ...
        la    t0, sv_name               ; ...
        li    t2, SV_NAME_L             ; ...
ypk_f:  lbu   t3, 0(t0)                 ; ...
        sb    t3, 0(s0)                 ; ...
        addi  t0, t0, 1                 ; ...
        addi  s0, s0, 1                 ; ...
        addi  t2, t2, -1                ; ...
        bnez  t2, ypk_f                 ; ...
        la    t0, yr_path               ; read from there
        sd    t0, g_lpath - g(gp)       ; ...
        sub   t0, s0, t0                ; ...
        sd    t0, g_llen - g(gp)        ; ...
        la    t5, u_load                ; ...
        xcall ra, c0, t5                ; ...
        mv    s1, a0                    ; ...
        la    t0, sv_name               ; (the town's own file again)
        sd    t0, g_lpath - g(gp)       ; ...
        li    t0, SV_NAME_L             ; ...
        sd    t0, g_llen - g(gp)        ; ...
        la    a0, msg_yno               ; ...
        bnez  s1, ypk_s                 ; ...
        la    t6, town_shown            ; ...
        jalr  ra, t6, 0                 ; ...
        la    s0, yr_msg                ; "The town as it was in YYYY."
        la    a0, msg_yr                ; ...
        la    t6, dy_str                ; ...
        jalr  ra, t6, 0                 ; ...
        la    t0, yr_name + 6           ; ...
        li    t2, 4                     ; ...
ypk_y:  lbu   t3, 0(t0)                 ; ...
        sb    t3, 0(s0)                 ; ...
        addi  t0, t0, 1                 ; ...
        addi  s0, s0, 1                 ; ...
        addi  t2, t2, -1                ; ...
        bnez  t2, ypk_y                 ; ...
        li    t0, '.'                   ; ...
        sb    t0, 0(s0)                 ; ...
        sb    zero, 1(s0)               ; ...
        la    a0, yr_msg                ; ...
ypk_s:  la    t6, say                   ; ...
        jalr  ra, t6, 0                 ; ...
ypk_r:  ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

        .org  unit_yr + UNIT            ; (a unit fits its slot: else an error here)
        .text                           ; code
