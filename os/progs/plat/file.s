; =============================================================================
; file.s: Plat's town in a file: saving it, loading it, a new one
; =============================================================================
;
; The town is kept in /ws/plat-N.sav (N its place: gallery.s): a header (SV_* below: the state of the
; random numbers, the date, the treasury, the tax rate, the census, the
; demand, the year's money so far) and the map's 32 KiB, which go through
; rowbuf a piece at a time. The file then gets attributes, so that a query
; finds a town by them (`attr /ws/plat.sav`, `ls /ws/population>1000`):
; population, year, funds.
;
; A window's client has the window server's endpoint where the file
; server's was (wsclient.s), so while the window is open a file is reached
; by looking `fs` up into that register, and `ws` again afterwards (fs_on,
; fs_off), as kira's garden does.

SV_MAGIC = 0                            ; the header: "PLATSAV2"
SV_SEED  = 8                            ; ... the random numbers' state
SV_MONTH = 16                           ; ... the date
SV_YEAR  = 24                           ; ...
SV_FUNDS = 32                           ; ... the treasury
SV_TAX   = 40                           ; ... the tax rate
SV_MTIC  = 48                           ; ... tics into the month
SV_MILE  = 56                           ; ... the next milestone
SV_POP   = 64                           ; ... the census: three dwords
SV_DEM   = 88                           ; ... the demand: three dwords
SV_YTAX  = 112                          ; ... the year's taxes and upkeep so far
SV_YUPK  = 120                          ; ...
SV_V1    = 128                          ; bytes of a first-version header ("PLATSAV1")
SV_SCEN  = 128                          ; ... the scenario: which (0: none), its end
SV_SEND  = 136                          ;   year, months since it began (scen.s)
SV_SMON  = 144                          ; ...
SV_SIZE  = 152                          ; bytes
SV_PIECE = 2048                         ; bytes of the map written or read at a time

        .data                           ; D-LS
        .align 8                        ; dwords
sv_magic: .ascii "PLATSAV2"             ; the header's first word
sv_magic1: .ascii "PLATSAV1"            ; ... before scenarios (read too)
sv_name:  .ascii "/ws/plat-1.sav"       ; the file (its place's digit: sv_slot)
sv_name_e:                              ; (its end)
SV_NAME_L = sv_name_e - sv_name         ; ...
sv_fs:    .ascii "fs"                   ; the file server's name
sv_ws:    .ascii "ws"                   ; the window server's
sv_a_pop: .ascii "population\0"         ; the file's attributes
sv_a_year: .ascii "year\0"              ; ...
sv_a_funds: .ascii "funds\0"            ; ...
msg_saved: .ascii "The town is saved.\0" ; a message
msg_load: .ascii "The saved town is back.\0" ; a message
msg_nosave: .ascii "No town is saved.\0" ; a message
msg_new:  .ascii "New land. Plan your town.\0" ; a message
msg_nofile: .ascii "The town could not be saved.\0" ; a message
p_dsave:  .ascii "plat: saved: map \0"  ; what a demo says when it saves
        .align 8                        ; ...
        .text                           ; resident code
; sv_slot(a0 = place 1..4): the town's file is that place's
sv_slot:
        addi  a0, a0, '0'               ; ...
        la    t0, sv_name + 9           ; ...
        sb    a0, 0(t0)                 ; ...
        ret                             ; done

; fs_on(): files can be reached (the file server's endpoint in WC_EP while
; the window is open) -> a0 = 0, or < 0
fs_on:  ld    t0, g_wopen - g(gp)       ; ...
        li    a0, 0                     ; ...
        beqz  t0, fo_r                  ; ...
        la    a0, sv_fs                 ; ...
        li    a1, 2                     ; ...
        li    a2, WC_EP                 ; ...
        la    t6, sys_lookup            ; ...
        jr    t6                        ; ...
fo_r:   ret                             ; done

; fs_off(): the window server's endpoint in WC_EP again (if the window is open)
fs_off: ld    t0, g_wopen - g(gp)       ; ...
        beqz  t0, ff_r                  ; ...
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        la    a0, sv_ws                 ; ...
        li    a1, 2                     ; ...
        li    a2, WC_EP                 ; ...
        la    t6, sys_lookup            ; ...
        jalr  ra, t6, 0                 ; ...
        cclear c6                       ; (c6 stays empty: the band comes back there)
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
ff_r:   ret                             ; done

town_reset:
        li    t0, FUNDS0                ; ...
        sd    t0, g_funds - g(gp)       ; ...
        sd    zero, g_month - g(gp)     ; ...
        li    t0, YEAR0                 ; ...
        sd    t0, g_year - g(gp)        ; ...
        li    t0, TAX0                  ; ...
        sd    t0, g_tax - g(gp)         ; ...
        sd    zero, g_mtic - g(gp)      ; ...
        sd    zero, g_mile - g(gp)      ; ...
        sd    zero, g_popr - g(gp)      ; ...
        sd    zero, g_popc - g(gp)      ; ...
        sd    zero, g_popi - g(gp)      ; ...
        sd    zero, g_dr - g(gp)        ; ...
        sd    zero, g_dc - g(gp)        ; ...
        sd    zero, g_di - g(gp)        ; ...
        sd    zero, g_ytax - g(gp)      ; ...
        sd    zero, g_yupk - g(gp)      ; ...
        sd    zero, g_nplant - g(gp)    ; ...
        ret                             ; done

; town_shown(): a town that came (loaded, or new): all of it is to be drawn
town_shown:
        li    t0, 1                     ; ...
        sd    t0, g_dbar - g(gp)        ; ...
        li    t0, MAPN / 2              ; the cursor in the middle, the view round it
        sd    t0, g_curx - g(gp)        ; ...
        sd    t0, g_cury - g(gp)        ; ...
        j     centre                    ; ...

        .far                            ; code units (paged in by the kernel)
        .align UNIT                     ; a unit
unit_file:
u_save:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; the far return link
        call  city_save                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        xret  ra                        ; back (paged in again if it had to go)
u_load:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; the far return link
        call  city_load                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        xret  ra                        ; back (paged in again if it had to go)

; city_save() -> a0 = 0, or < 0: the town into /ws/plat.sav, with its attributes
city_save:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = handle
        sd    s1, 16(sp)                ; s1 = the piece
        sd    s2, 24(sp)                ; s2 = the result
        li    s2, -1                    ; ...
        la    t6, fs_on                 ; ...
        jalr  ra, t6, 0                 ; ...
        bnez  a0, cs_off                ; ...
        la    a0, sv_name               ; ...
        li    a1, sv_name_e - sv_name   ; ...
        li    a2, 1                     ; ...
        la    t6, sys_open              ; ...
        jalr  ra, t6, 0                 ; ...
        mv    s0, a0                    ; ...
        bltz  a0, cs_off                ; ...
        call  sv_header                 ; the header, in rowbuf
        mv    a0, s0                    ; ...
        la    a1, rowbuf                ; ...
        li    a2, SV_SIZE               ; ...
        la    t6, sys_write             ; ...
        jalr  ra, t6, 0                 ; ...
        li    t0, SV_SIZE               ; ...
        bne   a0, t0, cs_cl             ; ...
        li    s1, 0                     ; the map, a piece at a time
cs_p:   ld    t0, g_mapb - g(gp)        ; ...
        add   t0, t0, s1                ; ...
        la    t1, rowbuf                ; ...
        li    t2, SV_PIECE              ; ...
        tget  tg11, t1, c0, t0, t2      ; ...
        twait 1 << 11                   ; ...
        mv    a0, s0                    ; ...
        la    a1, rowbuf                ; ...
        li    a2, SV_PIECE              ; ...
        la    t6, sys_write             ; ...
        jalr  ra, t6, 0                 ; ...
        li    t0, SV_PIECE              ; ...
        bne   a0, t0, cs_cl             ; ...
        li    t0, SV_PIECE              ; ...
        add   s1, s1, t0                ; ...
        li    t0, MAPB                  ; ...
        blt   s1, t0, cs_p              ; ...
        li    s2, 0                     ; written
cs_cl:  mv    a0, s0                    ; ...
        la    t6, sys_close             ; ...
        jalr  ra, t6, 0                 ; ...
        bnez  s2, cs_off                ; the attributes
        la    a0, sv_a_pop              ; ...
        ld    a1, g_popr - g(gp)        ; ...
        call  sv_attr                   ; ...
        la    a0, sv_a_year             ; ...
        ld    a1, g_year - g(gp)        ; ...
        call  sv_attr                   ; ...
        la    a0, sv_a_funds            ; ...
        ld    a1, g_funds - g(gp)       ; ...
        call  sv_attr                   ; ...
cs_off: la    t6, fs_off                ; ...
        jalr  ra, t6, 0                 ; ...
        la    a0, msg_saved             ; ...
        beqz  s2, cs_m                  ; ...
        la    a0, msg_nofile            ; ...
cs_m:   la    t6, say                   ; ...
        jalr  ra, t6, 0                 ; ...
        ld    t0, g_demo - g(gp)        ; (a demo says what it saved)
        beqz  t0, cs_r                  ; ...
        bnez  s2, cs_r                  ; ...
        la    t6, map_hash              ; ...
        jalr  ra, t6, 0                 ; ...
        mv    s1, a0                    ; ...
        la    s0, p_dnum                ; ...
        la    a0, p_dsave + 6           ; ("saved: map ")
        la    t6, dy_str                ; ...
        jalr  ra, t6, 0                 ; ...
        mv    a0, s1                    ; ...
        la    t6, dy_hex                ; ...
        jalr  ra, t6, 0                 ; ...
        la    a0, p_dnl                 ; ...
        la    t6, dy_str                ; ...
        jalr  ra, t6, 0                 ; ...
        la    a0, p_dmsg                ; ...
        la    t0, p_dmsg                ; ...
        sub   a1, s0, t0                ; ...
        la    t6, err_str               ; ...
        jalr  ra, t6, 0                 ; ...
cs_r:   mv    a0, s2                    ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

; sv_header(): the header in rowbuf
sv_header:
        la    t0, rowbuf                ; ...
        la    t1, sv_magic              ; ...
        ld    t1, 0(t1)                 ; ...
        sd    t1, SV_MAGIC(t0)          ; ...
        ld    t1, g_seed - g(gp)        ; ...
        sd    t1, SV_SEED(t0)           ; ...
        ld    t1, g_month - g(gp)       ; ...
        sd    t1, SV_MONTH(t0)          ; ...
        ld    t1, g_year - g(gp)        ; ...
        sd    t1, SV_YEAR(t0)           ; ...
        ld    t1, g_funds - g(gp)       ; ...
        sd    t1, SV_FUNDS(t0)          ; ...
        ld    t1, g_tax - g(gp)         ; ...
        sd    t1, SV_TAX(t0)            ; ...
        ld    t1, g_mtic - g(gp)        ; ...
        sd    t1, SV_MTIC(t0)           ; ...
        ld    t1, g_mile - g(gp)        ; ...
        sd    t1, SV_MILE(t0)           ; ...
        ld    t1, g_popr - g(gp)        ; ...
        sd    t1, SV_POP(t0)            ; ...
        ld    t1, g_popc - g(gp)        ; ...
        sd    t1, SV_POP + 8(t0)        ; ...
        ld    t1, g_popi - g(gp)        ; ...
        sd    t1, SV_POP + 16(t0)       ; ...
        ld    t1, g_dr - g(gp)          ; ...
        sd    t1, SV_DEM(t0)            ; ...
        ld    t1, g_dc - g(gp)          ; ...
        sd    t1, SV_DEM + 8(t0)        ; ...
        ld    t1, g_di - g(gp)          ; ...
        sd    t1, SV_DEM + 16(t0)       ; ...
        ld    t1, g_ytax - g(gp)        ; ...
        sd    t1, SV_YTAX(t0)           ; ...
        ld    t1, g_yupk - g(gp)        ; ...
        sd    t1, SV_YUPK(t0)           ; ...
        ld    t1, g_scen - g(gp)        ; ...
        sd    t1, SV_SCEN(t0)           ; ...
        ld    t1, g_send - g(gp)        ; ...
        sd    t1, SV_SEND(t0)           ; ...
        ld    t1, g_smon - g(gp)        ; ...
        sd    t1, SV_SMON(t0)           ; ...
        ret                             ; done

; sv_attr(a0 = name, NUL-terminated, a1 = number): the file gets that
; attribute (SETATTR: path, 0, name, 0, value in digits)
sv_attr:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = where the request goes on
        sd    a1, 16(sp)                ; ...
        mv    t2, a0                    ; ...
        la    s0, txtbuf                ; the path
        la    t0, sv_name               ; ...
        li    t1, sv_name_e - sv_name   ; ...
sa_p:   lbu   t3, 0(t0)                 ; ...
        sb    t3, 0(s0)                 ; ...
        addi  t0, t0, 1                 ; ...
        addi  s0, s0, 1                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, sa_p                  ; ...
        sb    zero, 0(s0)               ; ...
        addi  s0, s0, 1                 ; ...
        mv    a0, t2                    ; the name
        la    t6, ys_str                ; ...
        jalr  ra, t6, 0                 ; ...
        sb    zero, 0(s0)               ; ...
        addi  s0, s0, 1                 ; ...
        ld    a0, 16(sp)                ; the value
        la    t6, t_num                 ; ...
        jalr  ra, t6, 0                 ; ...
        la    a0, txtbuf                ; ...
        sub   s0, s0, a0                ; ...
        mv    a1, s0                    ; ...
        la    t6, sys_put               ; ...
        jalr  ra, t6, 0                 ; ...
        li    a0, WC_EP                 ; SETATTR, to the file server (now in WC_EP)
        li    a1, 42                    ; ...
        li    a2, 0                     ; ...
        mv    a3, s0                    ; ...
        li    a4, 0                     ; ...
        la    t6, sys_msg               ; ...
        jalr  ra, t6, 0                 ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; sv_read(a0 = handle, a1 = bytes) -> a0 = 0 if that many came into rowbuf
sv_read:
        la    t6, rowbuf                ; ...
; sv_read2(a0 = handle, a1 = bytes, t6 = where) -> a0 = 0 if that many came
sv_read2:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = handle
        sd    s1, 16(sp)                ; s1 = where the next bytes go
        sd    s2, 24(sp)                ; s2 = bytes left
        mv    s0, a0                    ; ...
        mv    s1, t6                    ; ...
        mv    s2, a1                    ; ...
sr_l:   mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        mv    a2, s2                    ; ...
        la    t6, sys_read              ; ...
        jalr  ra, t6, 0                 ; ...
        blez  a0, sr_no                 ; ...
        add   s1, s1, a0                ; ...
        sub   s2, s2, a0                ; ...
        bgtz  s2, sr_l                  ; ...
        li    a0, 0                     ; ...
        j     sr_r                      ; ...
sr_no:  li    a0, -1                    ; ...
sr_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

; city_load() -> a0 = 0, or < 0 (no file, or not a town: nothing changes
; but the map may be half read; the caller makes new land then)
city_load:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = handle
        sd    s1, 16(sp)                ; s1 = the piece; the result
        la    t6, fs_on                 ; ...
        jalr  ra, t6, 0                 ; ...
        li    s1, -1                    ; ...
        bnez  a0, cl_off                ; ...
        ld    a0, g_lpath - g(gp)       ; (the town's file, or a past year's: years.s)
        ld    a1, g_llen - g(gp)        ; ...
        li    a2, 0                     ; ...
        la    t6, sys_open              ; ...
        jalr  ra, t6, 0                 ; ...
        mv    s0, a0                    ; ...
        bltz  a0, cl_off                ; ...
        li    a1, SV_V1                 ; the header (its first version's part)
        call  sv_read                   ; ...
        bnez  a0, cl_cl                 ; ...
        la    t0, rowbuf                ; ...
        ld    t1, SV_MAGIC(t0)          ; ...
        la    t2, sv_magic1             ; (the first version: no scenario)
        ld    t2, 0(t2)                 ; ...
        sd    zero, g_scen - g(gp)      ; ...
        beq   t1, t2, cl_h              ; ...
        la    t2, sv_magic              ; ...
        ld    t2, 0(t2)                 ; ...
        bne   t1, t2, cl_cl             ; ...
        mv    a0, s0                    ; the rest of it, after the first part
        li    a1, SV_SIZE - SV_V1       ; ...
        la    t6, rowbuf + SV_V1        ; ...
        call  sv_read2                  ; ...
        bnez  a0, cl_cl                 ; ...
        la    t0, rowbuf                ; ...
        ld    t1, SV_SCEN(t0)           ; ...
        sd    t1, g_scen - g(gp)        ; ...
        ld    t1, SV_SEND(t0)           ; ...
        sd    t1, g_send - g(gp)        ; ...
        ld    t1, SV_SMON(t0)           ; ...
        sd    t1, g_smon - g(gp)        ; ...
cl_h:   la    t0, rowbuf                ; ...
        ld    t1, SV_SEED(t0)           ; ...
        sd    t1, g_seed - g(gp)        ; ...
        ld    t1, SV_MONTH(t0)          ; ...
        sd    t1, g_month - g(gp)       ; ...
        ld    t1, SV_YEAR(t0)           ; ...
        sd    t1, g_year - g(gp)        ; ...
        ld    t1, SV_FUNDS(t0)          ; ...
        sd    t1, g_funds - g(gp)       ; ...
        ld    t1, SV_TAX(t0)            ; ...
        sd    t1, g_tax - g(gp)         ; ...
        ld    t1, SV_MTIC(t0)           ; ...
        sd    t1, g_mtic - g(gp)        ; ...
        ld    t1, SV_MILE(t0)           ; ...
        sd    t1, g_mile - g(gp)        ; ...
        ld    t1, SV_POP(t0)            ; ...
        sd    t1, g_popr - g(gp)        ; ...
        ld    t1, SV_POP + 8(t0)        ; ...
        sd    t1, g_popc - g(gp)        ; ...
        ld    t1, SV_POP + 16(t0)       ; ...
        sd    t1, g_popi - g(gp)        ; ...
        ld    t1, SV_DEM(t0)            ; ...
        sd    t1, g_dr - g(gp)          ; ...
        ld    t1, SV_DEM + 8(t0)        ; ...
        sd    t1, g_dc - g(gp)          ; ...
        ld    t1, SV_DEM + 16(t0)       ; ...
        sd    t1, g_di - g(gp)          ; ...
        ld    t1, SV_YTAX(t0)           ; ...
        sd    t1, g_ytax - g(gp)        ; ...
        ld    t1, SV_YUPK(t0)           ; ...
        sd    t1, g_yupk - g(gp)        ; ...
        sd    zero, g_nplant - g(gp)    ; (the plants are found again next month)
        li    s1, 0                     ; the map, a piece at a time
cl_p:   mv    a0, s0                    ; ...
        li    a1, SV_PIECE              ; ...
        call  sv_read                   ; ...
        bnez  a0, cl_bad                ; ...
        ld    t0, g_mapb - g(gp)        ; ...
        add   t0, t0, s1                ; ...
        la    t1, rowbuf                ; ...
        li    t2, SV_PIECE              ; ...
        tput  tg11, t1, c0, t0, t2      ; ...
        twait 1 << 11                   ; ...
        li    t0, SV_PIECE              ; ...
        add   s1, s1, t0                ; ...
        li    t0, MAPB                  ; ...
        blt   s1, t0, cl_p              ; ...
        li    s1, 0                     ; read
        j     cl_cl                     ; ...
cl_bad: li    s1, -2                    ; (the map is half read)
cl_cl:  mv    a0, s0                    ; ...
        la    t6, sys_close             ; ...
        jalr  ra, t6, 0                 ; ...
cl_off: la    t6, fs_off                ; ...
        jalr  ra, t6, 0                 ; ...
        mv    a0, s1                    ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; town_reset(): a new town's numbers (the land is gen_land's)
        .org  unit_file + UNIT          ; (a unit fits its slot: else an error here)
        .text                           ; code
