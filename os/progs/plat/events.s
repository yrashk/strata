; hap_call(a0 = 1 a fire, 2 a flood, 3 a storm, 4 an earthquake, 5 a coal
; plant's failure, 6 events by chance on or off; a1 = 1: the bar says so if
; there is nothing for it): that event, now
hap_call:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    a1, 8(sp)                 ; ...
        li    t0, 1                     ; ...
        beq   a0, t0, hc_fire           ; ...
        li    t0, 2                     ; ...
        beq   a0, t0, hc_flood          ; ...
        li    t0, 3                     ; ...
        beq   a0, t0, hc_storm          ; ...
        li    t0, 4                     ; ...
        beq   a0, t0, hc_quake          ; ...
        li    t0, 5                     ; ...
