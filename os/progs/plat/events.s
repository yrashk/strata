; hap_storm() -> a0 = 1: a storm from one edge of the map to the other,
; through the town, drifting
hap_storm:
        addi  sp, sp, -56               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0, s1 = where it is
        sd    s1, 16(sp)                ; ...
        sd    s2, 24(sp)                ; s2, s3 = its way
        sd    s3, 32(sp)                ; ...
        sd    s4, 40(sp)                ; s4 = the edge it comes from
        call  town                      ; (none: the middle)
        bgez  a0, hs_0                  ; ...
        li    a0, MAPN / 2              ; ...
        li    a1, MAPN / 2              ; ...
hs_0:   mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        sd    a1, 48(sp)                ; (its y, kept)
        li    a0, 4                     ; ...
        la    t6, rndn                  ; ...
        jalr  ra, t6, 0                 ; ...
        mv    s4, a0                    ; ...
        li    s2, 0                     ; from the north
        li    s3, 1                     ; ...
        li    s1, 0                     ; ...
        beqz  s4, hs_l                  ; ...
        li    s3, -1                    ; from the south
        li    s1, MAPN - 1              ; ...
        li    t0, 1                     ; ...
        beq   s4, t0, hs_l              ; ...
        ld    s1, 48(sp)                ; across: from the west
        li    s3, 0                     ; ...
        li    s2, 1                     ; ...
        li    s0, 0                     ; ...
        li    t0, 2                     ; ...
        beq   s4, t0, hs_l              ; ...
        li    s2, -1                    ; from the east
        li    s0, MAPN - 1              ; ...
hs_l:   li    t0, MAPN                  ; till it leaves the map
        bgeu  s0, t0, hs_e              ; ...
        bgeu  s1, t0, hs_e              ; ...
        mv    a0, s0                    ; what it brings down
        mv    a1, s1                    ; ...
        li    a2, STORM_R               ; ...
        li    a3, HK_STORM              ; ...
        li    a4, 10                    ; ...
        call  ruin_box                  ; ...
        add   s0, s0, s2                ; on
        add   s1, s1, s3                ; ...
        li    a0, 3                     ; and a cell aside by chance
        la    t6, rndn                  ; ...
        jalr  ra, t6, 0                 ; ...
        addi  a0, a0, -1                ; ...
        bnez  s2, hs_v                  ; ...
        add   s0, s0, a0                ; ...
        j     hs_l                      ; ...
hs_v:   add   s1, s1, a0                ; ...
        j     hs_l                      ; ...
hs_e:   la    a0, msg_storm             ; the engineer says so
        li    a1, SP_ADV_ENGINEER       ; ...
        la    t6, say_adv               ; ...
        jalr  ra, t6, 0                 ; ...
        li    a0, 1                     ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        addi  sp, sp, 56                ; pop the frame
        ret                             ; done

