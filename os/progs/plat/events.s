; =============================================================================
; events.s: what else befalls the town: floods, storms, earthquakes, a coal
; plant that fails; the land made again (water, woods, plain land)
; =============================================================================
;
; Once a month (hap_month) the flood water grows a month older (its age in
; the flags' bits 10..12, as a fire's) and after FLOOD_OUT months it is
; cleared land again; and, now and then, an event comes by chance (unless
; the events panel, V, turned that off). The panel calls one down at once:
;
; - a flood: the water near the town rises over the land beside it, three
;   times, and stays a few months;
; - a storm: it crosses the map through the town and knocks down lines,
;   trees, buildings and parks on its way (rubble);
; - an earthquake: round a place in the town, what is built falls (rubble),
;   and some of it burns (fire.s takes the fires from there);
; - a coal plant fails: it burns, whole.
;
; The land tools (W water, F woods, A plain land) change open land, woods
; and water; tools.s uses them, fix_box makes the water's edges again.

HAP_CHANCE = 3                          ; in 1000, a month: an event by chance
FLOOD_OUT = 4                           ; months flood water stays
FLOOD_R  = 7                            ; how far a flood reaches from its start
NEAR_R   = 20                           ; ... and its start from the town
QUAKE_R  = 7                            ; an earthquake's reach
STORM_R  = 2                            ; a storm's width each side
MAXREC   = 128                          ; flood cells cleared in a month
TRIES    = 400                          ; cells tried when one of a kind is looked for
HK_QUAKE = 1                            ; hp_k: an earthquake brings it down
HK_STORM = 2                            ; ... a storm does
HK_FLOOD = 4                            ; ... water covers it
MD_EVENTS = 5                           ; the events' panel (g_modal)

        .data                           ; D-LS
        .align 8                        ; dwords
hp_rec:   .space MAXREC * 2             ; flood cells cleared this month: u8 x, y
hp_nrec:  .dword 0                      ; how many
hp_k:     .byte 4, 4, 4, 6, 0           ; what each event does to a kind (K_*): HK_*
          .byte 5, 0, 7, 1, 0           ; ...
          .byte 7, 0, 5, 0, 1           ; ...
          .byte 1, 1, 1, 7, 4           ; ...
        .align 8                        ; ...
tr_ok:    .half (1 << K_GROUND) | (1 << K_DIRT) | (1 << K_RUBBLE) | (1 << K_WOODS) ; the kinds each land tool changes: water
          .half (1 << K_GROUND) | (1 << K_DIRT) | (1 << K_RUBBLE) ; ... woods
          .half (1 << K_DIRT) | (1 << K_RUBBLE) | (1 << K_WOODS) | (1 << K_WATER) ; ... plain land
msg_flood: .ascii "Resident: the water rose over the land!\0" ; a message
msg_storm: .ascii "Engineer: a storm went through. Lines are down.\0" ; a message
msg_quake: .ascii "Engineer: an earthquake! Clear the rubble.\0" ; a message
msg_fail:  .ascii "Engineer: a coal plant failed and is burning!\0" ; a message
msg_none:  .ascii "Nothing here for that.\0" ; a message
hd_t0:    .ascii " EVENTS: CALL ONE DOWN ON THE TOWN\0" ; the panel's lines
hd_t1:    .ascii "1  a fire\0"              ; ...
hd_t2:    .ascii "2  a flood\0"             ; ...
hd_t3:    .ascii "3  a storm\0"             ; ...
hd_t4:    .ascii "4  an earthquake\0"       ; ...
hd_t5:    .ascii "5  a coal plant fails\0"  ; ...
hd_t6:    .ascii "6  events by chance: \0"  ; ...
hd_on:    .ascii "on\0"                     ; ...
hd_off:   .ascii "off\0"                    ; ...
hd_t7:    .ascii "Esc: back.\0"             ; ...
        .align 8                        ; ...
hd_lines: .dword hd_t0, hd_t1, hd_t2, hd_t3 ; ...
          .dword hd_t4, hd_t5, hd_t6, hd_t7 ; ...
        .text                           ; resident code
        .far                            ; code units (paged in by the kernel)
        .align UNIT                     ; a unit
unit_ev:
u_hmonth:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; the far return link
        call  hap_month                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        xret  ra                        ; back (paged in again if it had to go)
u_flood:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; the far return link
        call  hap_flood                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        xret  ra                        ; back (paged in again if it had to go)
u_fixbox:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; the far return link
        call  fix_box                   ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        xret  ra                        ; back (paged in again if it had to go)

; hap_month(): the flood water's month; an event by chance
hap_month:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = x; the cell cleared
        sd    s1, 16(sp)                ; s1 = y
        sd    s2, 24(sp)                ; s2 = the row changed
        sd    s3, 32(sp)                ; s3 = the cell as stored
        la    t0, hp_nrec               ; ...
        sd    zero, 0(t0)               ; ...
        li    s1, 0                     ; every flood cell: a month older
hm_y:   ld    t0, g_mapb - g(gp)        ; ...
        slli  t1, s1, 8                 ; ...
        add   t0, t0, t1                ; ...
        la    t1, maprow                ; ...
        li    t2, MAPN * 2              ; ...
        tget  tg11, t1, c0, t0, t2      ; ...
        twait 1 << 11                   ; ...
        li    s0, 0                     ; ...
        li    s2, 0                     ; ...
hm_x:   la    t1, maprow                ; ...
        slli  t2, s0, 1                 ; ...
        add   t1, t1, t2                ; ...
        lhu   s3, 0(t1)                 ; ...
        li    t2, 7 * F_AGE             ; (an age: flood water)
        and   t2, s3, t2                ; ...
        beqz  t2, hm_n                  ; ...
        andi  t2, s3, PICMASK           ; (and water)
        la    t3, res + R_KIND          ; ...
        add   t3, t3, t2                ; ...
        lbu   t3, 0(t3)                 ; ...
        li    t4, K_WATER               ; ...
        bne   t3, t4, hm_n              ; ...
        li    t3, F_AGE                 ; ...
        add   s3, s3, t3                ; ...
        srli  t4, s3, 10                ; ...
        andi  t4, t4, 7                 ; ...
        li    t3, FLOOD_OUT             ; ...
        bltu  t4, t3, hm_s              ; ...
        la    t0, hp_nrec               ; gone: cleared land, listed (if there is
        ld    t3, 0(t0)                 ;   no room, next month)
        li    t4, MAXREC                ; ...
        bgeu  t3, t4, hm_n              ; ...
        slli  t4, t3, 1                 ; ...
        la    t5, hp_rec                ; ...
        add   t5, t5, t4                ; ...
        sb    s0, 0(t5)                 ; ...
        sb    s1, 1(t5)                 ; ...
        addi  t3, t3, 1                 ; ...
        sd    t3, 0(t0)                 ; ...
        li    s3, T_DIRT                ; ...
hm_s:   sh    s3, 0(t1)                 ; ...
        li    s2, 1                     ; ...
hm_n:   addi  s0, s0, 1                 ; ...
        li    t0, MAPN                  ; ...
        blt   s0, t0, hm_x              ; ...
        beqz  s2, hm_ny                 ; ...
        ld    t0, g_mapb - g(gp)        ; ...
        slli  t1, s1, 8                 ; ...
        add   t0, t0, t1                ; ...
        la    t1, maprow                ; ...
        li    t2, MAPN * 2              ; ...
        tput  tg11, t1, c0, t0, t2      ; ...
        twait 1 << 11                   ; ...
hm_ny:  addi  s1, s1, 1                 ; ...
        li    t0, MAPN                  ; ...
        blt   s1, t0, hm_y              ; ...
        li    s3, 0                     ; the cells cleared: drawn, their
hm_c:   la    t0, hp_nrec               ;   neighbours' edges made again
        ld    t0, 0(t0)                 ; ...
        bge   s3, t0, hm_h              ; ...
        slli  t0, s3, 1                 ; ...
        la    t1, hp_rec                ; ...
        add   t1, t1, t0                ; ...
        lbu   s0, 0(t1)                 ; ...
        lbu   s1, 1(t1)                 ; ...
        mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        la    t6, dirty_cell            ; ...
        jalr  ra, t6, 0                 ; ...
        addi  a0, s0, -1                ; ...
        addi  a1, s1, -1                ; ...
        addi  a2, s0, 1                 ; ...
        addi  a3, s1, 1                 ; ...
        call  fix_box                   ; ...
        addi  s3, s3, 1                 ; ...
        j     hm_c                      ; ...
hm_h:   ld    t0, g_evoff - g(gp)       ; an event by chance
        bnez  t0, hm_r                  ; ...
        li    a0, 1000                  ; ...
        la    t6, rndn                  ; ...
        jalr  ra, t6, 0                 ; ...
        li    t0, HAP_CHANCE            ; ...
        bgeu  a0, t0, hm_r              ; ...
        li    a0, 4                     ; a flood, a storm, an earthquake, a failure
        la    t6, rndn                  ; ...
        jalr  ra, t6, 0                 ; ...
        addi  a0, a0, 2                 ; ...
        li    a1, 0                     ; (nothing said if there is nothing for it)
        la    t5, u_event               ; ...
        xcall ra, c0, t5                ; ...
hm_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        addi  sp, sp, 48                ; pop the frame
        ret                             ; done

; hap_flood() -> a0 = 1 if the water rose: it starts at water near the town
; (or anywhere) and covers the land beside it, three times over
hap_flood:
        addi  sp, sp, -56               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0, s1 = where it starts
        sd    s1, 16(sp)                ; ...
        sd    s2, 24(sp)                ; s2, s3 = a cell
        sd    s3, 32(sp)                ; ...
        sd    s4, 40(sp)                ; s4 = passes left
        la    t5, u_town                ; the town
        xcall ra, c0, t5                ; ...
        li    a2, MAPN / 2              ; (none: anywhere)
        li    a3, MAPN / 2              ; ...
        bltz  a0, hf_0                  ; ...
        call  shore                     ; the water nearest to it
        bgez  a0, hf_1                  ; ...
        li    a2, MAPN / 2              ; (none: anywhere)
        li    a3, MAPN / 2              ; ...
hf_0:   li    a1, MAPN / 2              ; ...
        li    a0, K_WATER               ; ...
        la    t5, u_near                ; ...
        xcall ra, c0, t5                ; ...
        bltz  a0, hf_r                  ; (no water: no flood)
hf_1:
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        li    s4, 3                     ; ...
hf_p:   addi  s3, s1, -FLOOD_R          ; ...
hf_y:   addi  s2, s0, -FLOOD_R          ; ...
hf_x:   mv    a0, s2                    ; what water covers
        mv    a1, s3                    ; ...
        la    t6, m_kind                ; ...
        jalr  ra, t6, 0                 ; ...
        bltz  a0, hf_n                  ; ...
        la    t0, hp_k                  ; ...
        add   t0, t0, a0                ; ...
        lbu   t0, 0(t0)                 ; ...
        andi  t0, t0, HK_FLOOD          ; ...
        beqz  t0, hf_n                  ; ...
        mv    a0, s2                    ; beside water
        mv    a1, s3                    ; ...
        call  wet                       ; ...
        beqz  a0, hf_n                  ; ...
        li    a0, 2                     ; half of it
        la    t6, rndn                  ; ...
        jalr  ra, t6, 0                 ; ...
        bnez  a0, hf_n                  ; ...
        mv    a0, s2                    ; flood water: a month old (its picture
        mv    a1, s3                    ;   comes with fix_box)
        li    a2, T_WATER | F_AGE       ; ...
        la    t6, m_setc                ; ...
        jalr  ra, t6, 0                 ; ...
hf_n:   addi  s2, s2, 1                 ; ...
        addi  t0, s0, FLOOD_R           ; ...
        ble   s2, t0, hf_x              ; ...
        addi  s3, s3, 1                 ; ...
        addi  t0, s1, FLOOD_R           ; ...
        ble   s3, t0, hf_y              ; ...
        addi  s4, s4, -1                ; ...
        bnez  s4, hf_p                  ; ...
        addi  a0, s0, -FLOOD_R - 1      ; the edges, the roads and lines again
        addi  a1, s1, -FLOOD_R - 1      ; ...
        addi  a2, s0, FLOOD_R + 1       ; ...
        addi  a3, s1, FLOOD_R + 1       ; ...
        call  fix_box                   ; ...
        la    a0, msg_flood             ; a resident says so
        li    a1, SP_ADV_RESIDENT       ; ...
        la    t6, say_adv               ; ...
        jalr  ra, t6, 0                 ; ...
        li    a0, 1                     ; ...
hf_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        addi  sp, sp, 56                ; pop the frame
        ret                             ; done

; shore(a0 = x, a1 = y) -> a0, a1 = the water nearest to (x, y), NEAR_R
; cells away at most; a0 = -1: none
shore:  addi  sp, sp, -64               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0, s1 = (x, y)
        sd    s1, 16(sp)                ; ...
        sd    s2, 24(sp)                ; s2 = dy
        sd    s3, 32(sp)                ; s3 = dx
        sd    s4, 40(sp)                ; s4 = the nearest's distance (squared)
        sd    s5, 48(sp)                ; s5 = the nearest (y << 8 | x)
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        li    s4, 1 << 20               ; ...
        li    s5, -1                    ; ...
        li    s2, -NEAR_R               ; ...
shr_y:   li    s3, -NEAR_R               ; ...
shr_x:   mul   t0, s2, s2                ; nearer than the nearest yet?
        mul   t1, s3, s3                ; ...
        add   t0, t0, t1                ; ...
        bgeu  t0, s4, shr_n              ; ...
        sd    t0, 56(sp)                ; ...
        add   a0, s0, s3                ; and water
        add   a1, s1, s2                ; ...
        la    t6, m_kind                ; ...
        jalr  ra, t6, 0                 ; ...
        li    t0, K_WATER               ; ...
        bne   a0, t0, shr_n              ; ...
        ld    s4, 56(sp)                ; ...
        add   t0, s1, s2                ; ...
        slli  s5, t0, 8                 ; ...
        add   t0, s0, s3                ; ...
        or    s5, s5, t0                ; ...
shr_n:   addi  s3, s3, 1                 ; ...
        li    t0, NEAR_R                ; ...
        ble   s3, t0, shr_x              ; ...
        addi  s2, s2, 1                 ; ...
        ble   s2, t0, shr_y              ; ...
        li    a0, -1                    ; ...
        bltz  s5, shr_r                  ; ...
        andi  a0, s5, 255               ; ...
        srli  a1, s5, 8                 ; ...
shr_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        ld    s5, 48(sp)                ; ...
        addi  sp, sp, 64                ; pop the frame
        ret                             ; done

; wet(a0 = x, a1 = y) -> a0 = 1 if one of the four cells beside it is water
wet:    addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = x
        sd    s1, 16(sp)                ; s1 = y
        sd    s2, 24(sp)                ; s2 = the way
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        li    s2, 0                     ; ...
wt_l:   la    t0, jm_dx                 ; ...
        add   t0, t0, s2                ; ...
        lb    a0, 0(t0)                 ; ...
        lb    a1, 4(t0)                 ; ...
        add   a0, a0, s0                ; ...
        add   a1, a1, s1                ; ...
        la    t6, m_kind                ; ...
        jalr  ra, t6, 0                 ; ...
        li    t0, K_WATER               ; ...
        beq   a0, t0, wt_y              ; ...
        addi  s2, s2, 1                 ; ...
        li    t0, 4                     ; ...
        blt   s2, t0, wt_l              ; ...
        li    a0, 0                     ; ...
        j     wt_r                      ; ...
wt_y:   li    a0, 1                     ; ...
wt_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

; fix_box(a0 = x0, a1 = y0, a2 = x1, a3 = y1): in that square (the edges
; in it) the roads, lines and rail join again and the water's edges are
; drawn as the water is now
fix_box:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = x0
        sd    s1, 16(sp)                ; s1 = y
        sd    s2, 24(sp)                ; s2 = x1
        sd    s3, 32(sp)                ; s3 = y1
        sd    s4, 40(sp)                ; s4 = x
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        mv    s2, a2                    ; ...
        mv    s3, a3                    ; ...
fb_y:   mv    s4, s0                    ; ...
fb_x:   mv    a0, s4                    ; ...
        mv    a1, s1                    ; ...
        la    t6, fix_cell              ; ...
        jalr  ra, t6, 0                 ; ...
        mv    a0, s4                    ; ...
        mv    a1, s1                    ; ...
        call  wfix                      ; ...
        addi  s4, s4, 1                 ; ...
        ble   s4, s2, fb_x              ; ...
        addi  s1, s1, 1                 ; ...
        ble   s1, s3, fb_y              ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        addi  sp, sp, 48                ; pop the frame
        ret                             ; done

; wfix(a0 = x, a1 = y): water's picture (or a bridge's, a line's over it)
; for the water round it now; its flags stay
wfix:   addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = x
        sd    s1, 16(sp)                ; s1 = y
        sd    s2, 24(sp)                ; s2 = the new picture
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        la    t6, m_kind                ; ...
        jalr  ra, t6, 0                 ; ...
        li    t1, T_WATER               ; t1 = the kind's first picture
        li    t0, K_WATER               ; ...
        beq   a0, t0, wx_1              ; ...
        li    t1, T_BRIDGE              ; ...
        li    t0, K_BRIDGE              ; ...
        beq   a0, t0, wx_1              ; ...
        li    t1, T_LWATER              ; ...
        li    t0, K_LWATER              ; ...
        beq   a0, t0, wx_1              ; ...
        li    t1, T_RBRIDGE             ; ...
        li    t0, K_RBRIDGE             ; ...
        bne   a0, t0, wx_r              ; (anything else stays)
wx_1:   sub   t0, a1, t1                ; its way (bridges, lines): which set of
        li    t2, NBLOB                 ;   the 47 water cells
        divu  t0, t0, t2                ; ...
        mul   t0, t0, t2                ; ...
        add   s2, t1, t0                ; ...
        mv    a0, s0                    ; and which of them
        mv    a1, s1                    ; ...
        la    t6, water_pic             ; ...
        jalr  ra, t6, 0                 ; ...
        addi  a0, a0, -T_WATER          ; ...
        add   s2, s2, a0                ; ...
        mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        la    t6, m_getc                ; ...
        jalr  ra, t6, 0                 ; ...
        andi  t1, a0, PICMASK           ; (the same: nothing to draw)
        beq   t1, s2, wx_r              ; ...
        sub   a2, a0, t1                ; the flags, the new picture
        or    a2, a2, s2                ; ...
        mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        la    t6, m_setc                ; ...
        jalr  ra, t6, 0                 ; ...
        mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        la    t6, dirty_cell            ; ...
        jalr  ra, t6, 0                 ; ...
wx_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

        .org  unit_ev + UNIT            ; (a unit fits its slot: else an error here)

        .align UNIT                     ; a unit
