; ruin_box(a0 = x, a1 = y, a2 = r, a3 = HK_*, a4 = 1 in n): round (x, y),
; r cells at most, what that event brings down falls, by chance
ruin_box:
        addi  sp, sp, -64               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0, s1 = the middle
        sd    s1, 16(sp)                ; ...
        sd    s2, 24(sp)                ; s2 = r
        sd    s3, 32(sp)                ; s3 = the event
        sd    s4, 40(sp)                ; s4 = n
        sd    s5, 48(sp)                ; s5 = dy
        sd    s6, 56(sp)                ; s6 = dx
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        mv    s2, a2                    ; ...
        mv    s3, a3                    ; ...
        mv    s4, a4                    ; ...
        neg   s5, s2                    ; ...
rx_y:   neg   s6, s2                    ; ...
rx_x:   mul   t0, s5, s5                ; (a round)
        mul   t1, s6, s6                ; ...
        add   t0, t0, t1                ; ...
        mul   t1, s2, s2                ; ...
        bgt   t0, t1, rx_n              ; ...
        add   a0, s0, s6                ; ...
        add   a1, s1, s5                ; ...
        call  ruin                      ; ...
rx_n:   addi  s6, s6, 1                 ; ...
        ble   s6, s2, rx_x              ; ...
        addi  s5, s5, 1                 ; ...
        ble   s5, s2, rx_y              ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        ld    s5, 48(sp)                ; ...
        ld    s6, 56(sp)                ; ...
        addi  sp, sp, 64                ; pop the frame
        ret                             ; done

; ruin(a0 = x, a1 = y; s3 = HK_*, s4 = 1 in n: ruin_box's): the cell falls
; if that event brings it down, by chance: rubble (after an earthquake, one
; in four burns)
ruin:   addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = x
        sd    s1, 16(sp)                ; s1 = y
        sd    s2, 24(sp)                ; s2 = the picture
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        la    t6, m_kind                ; ...
        jalr  ra, t6, 0                 ; ...
        bltz  a0, ru_r                  ; ...
        la    t0, hp_k                  ; ...
        add   t0, t0, a0                ; ...
        lbu   t0, 0(t0)                 ; ...
        and   t0, t0, s3                ; ...
        beqz  t0, ru_r                  ; ...
        mv    a0, s4                    ; ...
        la    t6, rndn                  ; ...
        jalr  ra, t6, 0                 ; ...
        bnez  a0, ru_r                  ; ...
        andi  s2, s0, 1                 ; ...
        addi  s2, s2, T_RUBBLE          ; ...
        li    t0, HK_QUAKE              ; ...
        bne   s3, t0, ru_s              ; ...
        li    a0, 4                     ; ...
        la    t6, rndn                  ; ...
        jalr  ra, t6, 0                 ; ...
        bnez  a0, ru_s                  ; ...
        add   s2, s0, s1                ; ...
        andi  s2, s2, 3                 ; ...
        addi  s2, s2, T_BURN            ; ...
ru_s:   mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        mv    a2, s2                    ; ...
        la    t6, m_set                 ; ...
        jalr  ra, t6, 0                 ; ...
        mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        la    t6, fix_around            ; ...
        jalr  ra, t6, 0                 ; ...
ru_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

