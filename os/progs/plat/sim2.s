; =============================================================================
; sim2.s: Plat's town, the fuller city: the maps of cover, pollution, crime,
; traffic and land value
; =============================================================================
;
; Each map is 64 x 64 bytes, a byte for every 2 x 2 cells of the town, kept
; in the arena after the town's map (g_cmb + CM_* * 4096). Once a month,
; after the zones (cm_month):
;   a scan of the town adds up, for every 2 x 2 cells, what makes pollution
;   (industry, coal plants, traffic), crime (homes, shops) and traffic (every
;   zone by its density), notes where rail runs, and lists the police and
;   fire stations that have power;
;   each map is then made from its sums, smoothed over the 3 x 3 around it:
;   cover: each station gives 255 at its place, less 24 a step away, to
;   ten steps; crime: less half the police cover; traffic: half where
;   there is rail; land value: 64, more by water, parks and woods, less half
;   the pollution and a third of the crime.
;   Roads then show their traffic: plain, light (over 70), heavy (over 150).
; The zones (sim.s) read these maps for their growth next month. The work
; buffers are the D-LS that drawing and the land's making use at other
; times: m_water (4 KiB), tilebuf (4 KiB), rowbuf (5 KiB).

CM_POLL  = 0                            ; the maps: pollution
CM_LAND  = 1                            ; ... land value
CM_CRIME = 2                            ; ... crime
CM_TRAF  = 3                            ; ... traffic
CM_POLICE = 4                           ; ... police cover
CM_FIRE  = 5                            ; ... fire cover
NCM      = 6                            ; ...
CMB      = NCM * 4096                   ; bytes of them all
CMW      = 64                           ; a map's width and height
MAXST    = 32                           ; stations of each kind the town keeps track of
T_LIGHT  = 70                           ; traffic: light from here
T_HEAVY  = 150                          ; ... heavy

        .data                           ; D-LS
        .align 8                        ; dwords
cm_police: .space MAXST * 2             ; the police stations with power: u8 x, y on the maps
cm_fire:  .space MAXST * 2              ; ... the fire stations
cm_npol:  .dword 0                      ; ... how many
cm_nfire: .dword 0                      ; ...
cm_row:   .space CMW                    ; a row of a map being made
        .text                           ; resident code
cm_val: srli  t0, a1, 1                 ; ...
        srli  t1, a2, 1                 ; ...
        slli  t1, t1, 6                 ; ...
        add   t0, t0, t1                ; ...
        slli  a0, a0, 12                ; ...
        add   t0, t0, a0                ; ...
        ld    t1, g_cmb - g(gp)         ; ...
        add   t0, t0, t1                ; ...
        andi  t2, t0, 7                 ; ...
        sub   t0, t0, t2                ; ...
        la    t1, m_word                ; ...
        li    t3, 8                     ; ...
        tget  tg11, t1, c0, t0, t3      ; ...
        twait 1 << 11                   ; ...
        add   t1, t1, t2                ; ...
        lbu   a0, 0(t1)                 ; ...
        ret                             ; done

        .data                           ; D-LS
lv_tab:   .byte 0, 0, 0, 4, 12          ; what a cell adds to the land's value, by kind:
          .byte 0, 0, 0, 0, 0           ;   woods 4, water 12, a park 24
          .byte 0, 0, 0, 0, 0           ; ...
          .byte 0, 0, 0, 24, 0          ; ...
        .align 8                        ; ...
        .text                           ; code

        .far                            ; code units (paged in by the kernel)
        .align UNIT                     ; a unit
unit_cm1:
u_cmonth:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; the far return link
        call  cm_month                  ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        xret  ra                        ; back (paged in again if it had to go)
u_cmget:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; the far return link
        call  cm_get                    ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        xret  ra                        ; back (paged in again if it had to go)

; cm_month(): the maps, made again; the roads' traffic
cm_month:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        call  cm_scan                   ; pollution, crime, traffic sums; the stations
        la    a0, m_water               ; pollution
        li    a1, CM_POLL               ; ...
        li    a2, 0                     ; ...
        la    t5, u_smooth              ; ...
        xcall ra, c0, t5                ; ...
        la    a0, cm_police             ; police cover
        la    t0, cm_npol               ; ...
        ld    a1, 0(t0)                 ; ...
        ld    a2, g_fpol - g(gp)        ; ...
        call  cm_cover                  ; ...
        li    a0, CM_POLICE             ; ...
        call  cm_put                    ; ...
        la    a0, tilebuf               ; crime (less the police's cover, in m_water)
        li    a1, CM_CRIME              ; ...
        li    a2, 1                     ; ...
        la    t5, u_smooth              ; ...
        xcall ra, c0, t5                ; ...
        la    a0, cm_fire               ; fire cover
        la    t0, cm_nfire              ; ...
        ld    a1, 0(t0)                 ; ...
        ld    a2, g_ffire - g(gp)       ; ...
        call  cm_cover                  ; ...
        li    a0, CM_FIRE               ; ...
        call  cm_put                    ; ...
        la    a0, rowbuf                ; traffic (half where rail runs)
        li    a1, CM_TRAF               ; ...
        li    a2, 2                     ; ...
        la    t5, u_smooth              ; ...
        xcall ra, c0, t5                ; ...
        call  cm_land                   ; land value: its sums, then the map
        la    a0, tilebuf               ; (pollution and crime, to take away)
        li    a1, CM_POLL               ; ...
        call  cm_get                    ; ...
        la    a0, rowbuf                ; ...
        li    a1, CM_CRIME              ; ...
        call  cm_get                    ; ...
        la    a0, m_water               ; ...
        li    a1, CM_LAND               ; ...
        li    a2, 3                     ; ...
        la    t5, u_smooth              ; ...
        xcall ra, c0, t5                ; ...
        la    t5, u_roads               ; the roads show their traffic
        xcall ra, c0, t5                ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; cm_clear(a0 = a 4 KiB buffer): zero
cm_clear:
        li    t0, 4096                  ; ...
cc_l:   sd    zero, 0(a0)               ; ...
        addi  a0, a0, 8                 ; ...
        addi  t0, t0, -8                ; ...
        bnez  t0, cc_l                  ; ...
        ret                             ; done

; cm_add(a0 = buffer, a1 = x, a2 = y on the town, a3 = amount): the map
; byte for that cell grows by it (up to 255)
cm_add: srli  t0, a1, 1                 ; ...
        srli  t1, a2, 1                 ; ...
        slli  t1, t1, 6                 ; ...
        add   t0, t0, t1                ; ...
        add   t0, t0, a0                ; ...
        lbu   t1, 0(t0)                 ; ...
        add   t1, t1, a3                ; ...
        li    t2, 255                   ; ...
        bleu  t1, t2, ca_s              ; ...
        mv    t1, t2                    ; ...
ca_s:   sb    t1, 0(t0)                 ; ...
        ret                             ; done

; cm_put(a0 = map) / cm_get(a0 = buffer, a1 = map): m_water <-> the arena
cm_put: mv    a1, a0                    ; (always from m_water)
        la    a0, m_water               ; ...
        li    t3, 1                     ; ...
        j     cg_0                      ; ...
cm_get: li    t3, 0                     ; ...
cg_0:   ld    t0, g_cmb - g(gp)         ; ...
        slli  a1, a1, 12                ; ...
        add   t0, t0, a1                ; ...
        li    t1, 4096                  ; ...
        bnez  t3, cg_p                  ; ...
        tget  tg11, a0, c0, t0, t1      ; ...
        twait 1 << 11                   ; ...
        ret                             ; ...
cg_p:   tput  tg11, a0, c0, t0, t1      ; ...
        twait 1 << 11                   ; ...
        ret                             ; done

; cm_scan(): every cell of the town: m_water = pollution's sums, tilebuf =
; crime's, rowbuf = traffic's (its last KiB: a bit for every map byte where
; rail runs); the stations with power
cm_scan:
        addi  sp, sp, -56               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = x
        sd    s1, 16(sp)                ; s1 = y
        sd    s2, 24(sp)                ; s2 = the cell as stored
        sd    s3, 32(sp)                ; s3 = its picture
        sd    s4, 40(sp)                ; s4 = a zone's density (0: none)
        la    a0, m_water               ; ...
        call  cm_clear                  ; ...
        la    a0, tilebuf               ; ...
        call  cm_clear                  ; ...
        la    a0, rowbuf                ; ...
        call  cm_clear                  ; ...
        la    t0, rowbuf + 4096         ; (the rail bits)
        li    t1, 512                   ; ...
cq_c:   sd    zero, 0(t0)               ; ...
        addi  t0, t0, 8                 ; ...
        addi  t1, t1, -8                ; ...
        bnez  t1, cq_c                  ; ...
        la    t0, cm_npol               ; (none yet)
        sd    zero, 0(t0)               ; ...
        sd    zero, cm_nfire - cm_npol(t0) ; ...
        li    s1, 0                     ; ...
cq_y:   ld    t0, g_mapb - g(gp)        ; a row of the town
        slli  t1, s1, 8                 ; ...
        add   t0, t0, t1                ; ...
        la    t1, maprow                ; ...
        li    t2, MAPN * 2              ; ...
        tget  tg11, t1, c0, t0, t2      ; ...
        twait 1 << 11                   ; ...
        li    s0, 0                     ; ...
cq_x:   la    t1, maprow                ; ...
        slli  t2, s0, 1                 ; ...
        add   t1, t1, t2                ; ...
        lhu   s2, 0(t1)                 ; ...
        andi  s3, s2, PICMASK           ; ...
        mv    a0, s3                    ; a zone: its kind and density
        la    t6, zone_of               ; ...
        jalr  ra, t6, 0                 ; ...
        bltz  a0, cq_nz                 ; ...
        li    t0, 10                    ; ...
        divu  t1, a0, t0                ; t1 = kind
        remu  t2, a0, t0                ; t2 = level: density (level - 2) / 2 + 1
        li    s4, 0                     ; ...
        li    t3, 2                     ; ...
        bltu  t2, t3, cq_z1             ; ...
        addi  s4, t2, -2                ; ...
        srli  s4, s4, 1                 ; ...
        addi  s4, s4, 1                 ; ...
cq_z1:  beqz  s4, cq_n                  ; (nothing built)
        sd    t1, 48(sp)                ; (the kind)
        la    a0, rowbuf                ; traffic: 8 a density, every kind
        mv    a1, s0                    ; ...
        mv    a2, s1                    ; ...
        slli  a3, s4, 3                 ; ...
        call  cm_add                    ; ...
        ld    t1, 48(sp)                ; ...
        li    t0, 2                     ; industry: pollution, 6 a density
        bne   t1, t0, cq_z2             ; ...
        la    a0, m_water               ; ...
        mv    a1, s0                    ; ...
        mv    a2, s1                    ; ...
        li    t0, 6                     ; ...
        mul   a3, s4, t0                ; ...
        call  cm_add                    ; ...
        j     cq_z3                     ; ...
cq_z2:  la    a0, tilebuf               ; homes and shops: crime, 5 a density
        mv    a1, s0                    ; ...
        mv    a2, s1                    ; ...
        li    t0, 5                     ; ...
        mul   a3, s4, t0                ; ...
        call  cm_add                    ; ...
cq_z3:  j     cq_n                      ; ...
cq_nz:  li    t0, T_COAL                ; a coal plant: pollution, 40 a cell
        sub   t0, s3, t0                ; ...
        li    t1, 32                    ; ...
        bgeu  t0, t1, cq_r              ; ...
        la    a0, m_water               ; ...
        mv    a1, s0                    ; ...
        mv    a2, s1                    ; ...
        li    a3, 40                    ; ...
        call  cm_add                    ; ...
        j     cq_n                      ; ...
cq_r:   li    t0, T_THEAVY              ; traffic on a road: pollution, 8 heavy, 3 light
        sub   t0, s3, t0                ; ...
        li    t1, 16                    ; ...
        li    a3, 8                     ; ...
        bltu  t0, t1, cq_rp             ; ...
        li    t0, T_TLIGHT              ; ...
        sub   t0, s3, t0                ; ...
        li    a3, 3                     ; ...
        bgeu  t0, t1, cq_t              ; ...
cq_rp:  la    a0, m_water               ; ...
        mv    a1, s0                    ; ...
        mv    a2, s1                    ; ...
        call  cm_add                    ; ...
        j     cq_n                      ; ...
cq_t:   mv    a0, s3                    ; rail: its bit
        la    t6, kind                  ; ...
        jalr  ra, t6, 0                 ; ...
        li    t0, K_RAIL                ; ...
        beq   a0, t0, cq_tb             ; ...
        li    t0, K_RBRIDGE             ; ...
        beq   a0, t0, cq_tb             ; ...
        li    t0, K_RROAD               ; ...
        beq   a0, t0, cq_tb             ; ...
        li    t0, K_LRAIL               ; ...
        beq   a0, t0, cq_tb             ; ...
        li    t0, F_POWER               ; a station with power, at its middle: listed
        and   t0, t0, s2                ; ...
        beqz  t0, cq_n                  ; ...
        li    t0, T_POLICE + 4          ; ...
        la    t1, cm_police             ; ...
        la    t2, cm_npol               ; ...
        beq   s3, t0, cq_st             ; ...
        li    t0, T_FIREST + 4          ; ...
        la    t1, cm_fire               ; ...
        la    t2, cm_nfire              ; ...
        bne   s3, t0, cq_n              ; ...
cq_st:  ld    t3, 0(t2)                 ; ...
        li    t4, MAXST                 ; ...
        bgeu  t3, t4, cq_n              ; ...
        slli  t4, t3, 1                 ; ...
        add   t1, t1, t4                ; ...
        srli  t4, s0, 1                 ; ...
        sb    t4, 0(t1)                 ; ...
        srli  t4, s1, 1                 ; ...
        sb    t4, 1(t1)                 ; ...
        addi  t3, t3, 1                 ; ...
        sd    t3, 0(t2)                 ; ...
        j     cq_n                      ; ...
cq_tb:  srli  t0, s0, 1                 ; the map byte's bit
        srli  t1, s1, 1                 ; ...
        slli  t1, t1, 6                 ; ...
        add   t0, t0, t1                ; ...
        srli  t1, t0, 3                 ; ...
        la    t2, rowbuf + 4096         ; ...
        add   t1, t1, t2                ; ...
        andi  t0, t0, 7                 ; ...
        li    t2, 1                     ; ...
        sll   t2, t2, t0                ; ...
        lbu   t3, 0(t1)                 ; ...
        or    t3, t3, t2                ; ...
        sb    t3, 0(t1)                 ; ...
cq_n:   addi  s0, s0, 1                 ; ...
        li    t0, MAPN                  ; ...
        blt   s0, t0, cq_x              ; ...
        addi  s1, s1, 1                 ; ...
        blt   s1, t0, cq_y              ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        addi  sp, sp, 56                ; pop the frame
        ret                             ; done

; cm_smooth(a0 = the sums (a 4 KiB buffer), a1 = the map, a2 = what more:
; 0 nothing, 1 crime: less half m_water's (police cover), 2 traffic: half
; where rail runs, 3 land value: 64 more, less half tilebuf's (pollution)
; and a third of rowbuf's (crime)): each byte the mean of the 3 x 3 sums
; round it (times two: the sums are small), into the map
cm_cover:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the station
        sd    s1, 16(sp)                ; s1 = stations left
        sd    s2, 24(sp)                ; s2 = the cover at a station
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        li    t0, 255                   ; ...
        mul   s2, a2, t0                ; ...
        li    t0, 100                   ; ...
        divu  s2, s2, t0                ; ...
        la    a0, m_water               ; ...
        call  cm_clear                  ; ...
cw_s:   beqz  s1, cw_r                  ; ...
        lbu   t5, 0(s0)                 ; t5, t6 = its place
        lbu   t6, 1(s0)                 ; ...
        li    t1, -10                   ; t1 = dy
cw_dy:  li    t0, -10                   ; t0 = dx
cw_dx:  add   t2, t5, t0                ; ...
        add   t3, t6, t1                ; ...
        li    t4, CMW                   ; ...
        bgeu  t2, t4, cw_n              ; ...
        bgeu  t3, t4, cw_n              ; ...
        mv    a2, t0                    ; the steps: the larger of |dx|, |dy|
        bgez  a2, cw_1                  ; ...
        neg   a2, a2                    ; ...
cw_1:   mv    a3, t1                    ; ...
        bgez  a3, cw_2                  ; ...
        neg   a3, a3                    ; ...
cw_2:   bge   a2, a3, cw_3              ; ...
        mv    a2, a3                    ; ...
cw_3:   li    a3, 24                    ; ...
        mul   a2, a2, a3                ; ...
        sub   a2, s2, a2                ; a2 = the cover
        blez  a2, cw_n                  ; ...
        slli  t3, t3, 6                 ; ...
        add   t2, t2, t3                ; ...
        la    t3, m_water               ; ...
        add   t2, t2, t3                ; ...
        lbu   t3, 0(t2)                 ; (the best of the stations)
        bgeu  t3, a2, cw_n              ; ...
        sb    a2, 0(t2)                 ; ...
cw_n:   addi  t0, t0, 1                 ; ...
        li    t4, 10                    ; ...
        ble   t0, t4, cw_dx             ; ...
        addi  t1, t1, 1                 ; ...
        ble   t1, t4, cw_dy             ; ...
        addi  s0, s0, 2                 ; ...
        addi  s1, s1, -1                ; ...
        j     cw_s                      ; ...
cw_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

; cm_land(): m_water = what makes land worth more, for every 2 x 2 cells:
; 12 a cell of water, 24 of park, 4 of woods
cm_land:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = x
        sd    s1, 16(sp)                ; s1 = y
        la    a0, m_water               ; ...
        call  cm_clear                  ; ...
        li    s1, 0                     ; ...
cl_y:   ld    t0, g_mapb - g(gp)        ; ...
        slli  t1, s1, 8                 ; ...
        add   t0, t0, t1                ; ...
        la    t1, maprow                ; ...
        li    t2, MAPN * 2              ; ...
        tget  tg11, t1, c0, t0, t2      ; ...
        twait 1 << 11                   ; ...
        li    s0, 0                     ; ...
cl_x:   la    t1, maprow                ; ...
        slli  t2, s0, 1                 ; ...
        add   t1, t1, t2                ; ...
        lhu   a0, 0(t1)                 ; ...
        andi  a0, a0, PICMASK           ; ...
        la    t6, kind                  ; ...
        jalr  ra, t6, 0                 ; ...
        la    t0, lv_tab                ; ...
        add   t0, t0, a0                ; ...
        lbu   a3, 0(t0)                 ; ...
        beqz  a3, cl_n                  ; ...
        la    a0, m_water               ; ...
        mv    a1, s0                    ; ...
        mv    a2, s1                    ; ...
        call  cm_add                    ; ...
cl_n:   addi  s0, s0, 1                 ; ...
        li    t0, MAPN                  ; ...
        blt   s0, t0, cl_x              ; ...
        addi  s1, s1, 1                 ; ...
        blt   s1, t0, cl_y              ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

; cm_roads(): every road shows its traffic: plain, light or heavy pictures,
; by the traffic map
        .org  unit_cm1 + UNIT           ; (a unit fits its slot: else an error here)
        .align UNIT                     ; a unit
unit_cm2:
u_smooth:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; the far return link
        call  cm_smooth                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        xret  ra                        ; back (paged in again if it had to go)
u_roads:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; the far return link
        call  cm_roads                  ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        xret  ra                        ; back (paged in again if it had to go)
cm_smooth:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the sums
        sd    s1, 16(sp)                ; s1 = the map
        sd    s2, 24(sp)                ; s2 = what more
        sd    s3, 32(sp)                ; s3 = y
        sd    s4, 40(sp)                ; s4 = x
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        mv    s2, a2                    ; ...
        li    s3, 0                     ; ...
mz_y:   li    s4, 0                     ; ...
mz_x:   li    t5, 0                     ; t5 = the sum of the 3 x 3
        li    t1, -1                    ; t1 = dy
mz_dy:  li    t0, -1                    ; t0 = dx
mz_dx:  add   t2, s4, t0                ; ...
        add   t3, s3, t1                ; ...
        li    t4, CMW                   ; (inside the map)
        bgeu  t2, t4, mz_n              ; ...
        bgeu  t3, t4, mz_n              ; ...
        slli  t3, t3, 6                 ; ...
        add   t2, t2, t3                ; ...
        add   t2, t2, s0                ; ...
        lbu   t2, 0(t2)                 ; ...
        add   t5, t5, t2                ; ...
mz_n:   addi  t0, t0, 1                 ; ...
        li    t4, 2                     ; ...
        blt   t0, t4, mz_dx             ; ...
        addi  t1, t1, 1                 ; ...
        blt   t1, t4, mz_dy             ; ...
        slli  t5, t5, 1                 ; twice the mean
        li    t0, 9                     ; ...
        divu  t5, t5, t0                ; ...
        slli  t6, s3, 6                 ; t6 = this byte's place
        add   t6, t6, s4                ; ...
        li    t0, 1                     ; crime: less half the police cover
        bne   s2, t0, mz_2              ; ...
        la    t1, m_water               ; ...
        add   t1, t1, t6                ; ...
        lbu   t1, 0(t1)                 ; ...
        srli  t1, t1, 1                 ; ...
        sub   t5, t5, t1                ; ...
        j     mz_c                      ; ...
mz_2:   li    t0, 2                     ; traffic: half where rail runs
        bne   s2, t0, mz_3              ; ...
        srli  t1, t6, 3                 ; ...
        la    t2, rowbuf + 4096         ; ...
        add   t1, t1, t2                ; ...
        lbu   t1, 0(t1)                 ; ...
        andi  t2, t6, 7                 ; ...
        srl   t1, t1, t2                ; ...
        andi  t1, t1, 1                 ; ...
        srl   t5, t5, t1                ; ...
        j     mz_c                      ; ...
mz_3:   li    t0, 3                     ; land value
        bne   s2, t0, mz_c              ; ...
        addi  t5, t5, 64                ; ...
        la    t1, tilebuf               ; ...
