        lbu   t1, 0(t1)                 ; ...
        li    t2, 3                     ; ...
        divu  t1, t1, t2                ; ...
        sub   t5, t5, t1                ; ...
mz_c:   bgez  t5, mz_c1                 ; within 0 .. 255
        li    t5, 0                     ; ...
mz_c1:  li    t0, 255                   ; ...
        ble   t5, t0, mz_c2             ; ...
