; cm_cover(a0 = the stations (u8 x, y each), a1 = how many, a2 = their
; funding, per cent): m_water = their cover: 255 at a station at full
; funding, 24 less a step away
cm_roads:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = x
        sd    s1, 16(sp)                ; s1 = y
        sd    s2, 24(sp)                ; s2 = the row changed
        sd    s3, 32(sp)                ; s3 = the cell as stored
        la    a0, m_water               ; the traffic map
        li    a1, CM_TRAF               ; ...
        la    t5, u_cmget               ; ...
        xcall ra, c0, t5                ; ...
        li    s1, 0                     ; ...
cr_y:   ld    t0, g_mapb - g(gp)        ; ...
        slli  t1, s1, 8                 ; ...
        add   t0, t0, t1                ; ...
        la    t1, maprow                ; ...
        li    t2, MAPN * 2              ; ...
        tget  tg11, t1, c0, t0, t2      ; ...
        twait 1 << 11                   ; ...
        li    s0, 0                     ; ...
        li    s2, 0                     ; ...
cr_x:   la    t1, maprow                ; ...
        slli  t2, s0, 1                 ; ...
        add   t1, t1, t2                ; ...
        lhu   s3, 0(t1)                 ; ...
        andi  t2, s3, PICMASK           ; a road (plain or with traffic)?
        addi  t3, t2, -T_ROAD           ; t3 = its mask
        li    t4, 16                    ; ...
        bltu  t3, t4, cr_1              ; ...
        addi  t3, t2, -T_TLIGHT         ; ...
        li    t4, 32                    ; ...
        bgeu  t3, t4, cr_n              ; ...
        andi  t3, t3, 15                ; ...
cr_1:   srli  t4, s0, 1                 ; the traffic there
        srli  t5, s1, 1                 ; ...
        slli  t5, t5, 6                 ; ...
        add   t4, t4, t5                ; ...
        la    t5, m_water               ; ...
        add   t4, t4, t5                ; ...
        lbu   t4, 0(t4)                 ; ...
        li    t5, T_ROAD                ; the pictures for it
        li    t6, T_LIGHT               ; ...
        bltu  t4, t6, cr_2              ; ...
        li    t5, T_TLIGHT              ; ...
        li    t6, T_HEAVY               ; ...
        bltu  t4, t6, cr_2              ; ...
        li    t5, T_THEAVY              ; ...
cr_2:   add   t5, t5, t3                ; ...
        beq   t5, t2, cr_n              ; (as it is)
        sub   t6, s3, t2                ; (its flags stay)
        add   t6, t6, t5                ; ...
        sh    t6, 0(t1)                 ; ...
        li    s2, 1                     ; ...
        mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        la    t6, dirty_cell            ; ...
        jalr  ra, t6, 0                 ; ...
cr_n:   addi  s0, s0, 1                 ; ...
        li    t0, MAPN                  ; ...
        blt   s0, t0, cr_x              ; ...
        beqz  s2, cr_ny                 ; the row back, if it changed
        ld    t0, g_mapb - g(gp)        ; ...
        slli  t1, s1, 8                 ; ...
        add   t0, t0, t1                ; ...
        la    t1, maprow                ; ...
        li    t2, MAPN * 2              ; ...
        tput  tg11, t1, c0, t0, t2      ; ...
        twait 1 << 11                   ; ...
cr_ny:  addi  s1, s1, 1                 ; ...
        li    t0, MAPN                  ; ...
        blt   s1, t0, cr_y              ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        addi  sp, sp, 40                ; pop the frame
        ret                             ; done

