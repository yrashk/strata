; =============================================================================
; budget.s: Plat's budget: a panel over the map, the town waits while it is open
; =============================================================================
;
; It opens with G, its button, or (but in a demo) when a year ends. It shows
; last year's taxes and upkeep and three lines that the arrows choose and
; change: the tax rate (0 to 20 %), the police's and the fire service's
; funding (0 to 100 %: their cover is as strong as their funding, and so is
; what they cost, 100 a station a year at full). Enter, Esc or G closes it;
; so does a click. It is drawn by the server (wc_fill, wc_text) over the
; map, and drawn again whenever the map under it is (g_dbud).

BG_W     = 50                           ; the panel: characters across
BG_LINES = 9                            ; ... lines
BG_SEL   = 3                            ; the line of the first choice
NB_CHOICE = 3                           ; choices: tax, police, fire
PANEL_H  = BG_LINES * 20 + 40           ; the panel's height (budget, Ledger, history)

        .data                           ; D-LS
        .align 8                        ; dwords
bg_line:  .space 64                     ; a line being made
bg_t0:    .ascii "               THE BUDGET\0" ; its lines
bg_t1:    .ascii " Last year: taxes \0"  ; ...
bg_t1b:   .ascii ", upkeep \0"           ; ...
bg_t3:    .ascii "Tax rate         \0"   ; ...
bg_t4:    .ascii "Police funding   \0"   ; ...
bg_t5:    .ascii "Fire funding     \0"   ; ...
bg_t7:    .ascii " Up, down: choose. Left, right: change.\0" ; ...
bg_t8:    .ascii " Enter or G: done.\0"  ; ...
        .align 8                        ; ...
bg_vals:  .dword g_tax, g_fpol, g_ffire ; the choices' numbers
bg_max:   .dword TAXMAX, 100, 100       ; ... and their largest
bg_step:  .dword 1, 10, 10              ; ... and their steps
bg_txt:   .dword bg_t3, bg_t4, bg_t5    ; ... and their names
        .text                           ; resident code

; budget_open(): the panel opens (the town waits)
budget_open:
        li    t0, 1                     ; ...
        sd    t0, g_budget - g(gp)      ; ...
        sd    t0, g_dbud - g(gp)        ; ...
        sd    zero, g_bsel - g(gp)      ; ...
        ret                             ; done

; budget_close(): it closes; the map under it is drawn again
budget_close:
        sd    zero, g_budget - g(gp)    ; ...
        li    t0, 1                     ; ...
        sd    t0, g_dview - g(gp)       ; ...
        ld    t0, g_dtext - g(gp)       ; (the tax rate may have changed)
        ori   t0, t0, TX_TAX            ; ...
        sd    t0, g_dtext - g(gp)       ; ...
        ret                             ; done

; budget_key(a0 = key) -> the key is the budget's while it is open
budget_key:
        li    t0, K_UP                  ; up, down: the choice
        bne   a0, t0, bk_1              ; ...
        ld    t1, g_bsel - g(gp)        ; ...
        beqz  t1, bk_r                  ; ...
        addi  t1, t1, -1                ; ...
        j     bk_s                      ; ...
bk_1:   li    t0, K_DOWN                ; ...
        bne   a0, t0, bk_2              ; ...
        ld    t1, g_bsel - g(gp)        ; ...
        addi  t1, t1, 1                 ; ...
        li    t0, NB_CHOICE             ; ...
        bgeu  t1, t0, bk_r              ; ...
bk_s:   sd    t1, g_bsel - g(gp)        ; ...
        j     bk_d                      ; ...
bk_2:   li    t2, -1                    ; left, right: less, more
        li    t0, K_LEFT                ; ...
        beq   a0, t0, bk_3              ; ...
        li    t2, 1                     ; ...
        li    t0, K_RIGHT               ; ...
        bne   a0, t0, bk_4              ; ...
bk_3:   ld    t1, g_bsel - g(gp)        ; ...
        slli  t1, t1, 3                 ; ...
        la    t3, bg_step               ; ...
        add   t3, t3, t1                ; ...
        ld    t3, 0(t3)                 ; ...
        mul   t2, t2, t3                ; ...
        la    t3, bg_vals               ; ...
        add   t3, t3, t1                ; ...
        ld    t3, 0(t3)                 ; t3 = where the number is
        ld    t4, 0(t3)                 ; ...
        add   t4, t4, t2                ; ...
        bltz  t4, bk_r                  ; (0 .. its largest)
        la    t5, bg_max                ; ...
        add   t5, t5, t1                ; ...
        ld    t5, 0(t5)                 ; ...
        bgtu  t4, t5, bk_r              ; ...
        sd    t4, 0(t3)                 ; ...
bk_d:   li    t0, 1                     ; drawn again
        sd    t0, g_dbud - g(gp)        ; ...
bk_r:   ret                             ; ...
bk_4:   li    t0, 13                    ; Enter, Esc, G: done
        beq   a0, t0, budget_close      ; ...
        li    t0, 10                    ; ...
        beq   a0, t0, budget_close      ; ...
        li    t0, 0x1b                  ; ...
        beq   a0, t0, budget_close      ; ...
        li    t0, 'g'                   ; ...
        beq   a0, t0, budget_close      ; ...
        ret                             ; done

; budget_draw(): the panel, in the middle of the map's view
; panel_open() -> a0, a1 = the corner of a panel (the budget's size) now
; drawn empty in the middle of the map's view, its text's first place
panel_open:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0, s1 = its corner
        sd    s1, 16(sp)                ; ...
        ld    t0, g_w - g(gp)           ; ...
        addi  t0, t0, TOOLW - BG_W * 8  ; ...
        srai  s0, t0, 1                 ; ...
        andi  s0, s0, 0xfffe            ; ...
        ld    t0, g_h - g(gp)           ; ...
        addi  t0, t0, -BARH - PANEL_H   ; ...
        srai  s1, t0, 1                 ; ...
        bgez  s1, po2_0                 ; ...
        li    s1, 0                     ; ...
po2_0:  li    a0, C_PANEL_DARK          ; its frame
        call  pal                       ; ...
        mv    a4, a0                    ; ...
        addi  a0, s0, -4                ; ...
        addi  a1, s1, -4                ; ...
        li    a2, BG_W * 8 + 8          ; ...
        li    a3, PANEL_H + 8           ; ...
        call  wc_fill                   ; ...
        li    a0, C_PANEL_LIGHT         ; its inside
        call  pal                       ; ...
        mv    a4, a0                    ; ...
        mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        li    a2, BG_W * 8              ; ...
        li    a3, PANEL_H               ; ...
        call  wc_fill                   ; ...
        mv    a0, s0                    ; ...
        addi  a1, s1, 8                 ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; panel_line(a0 = x, a1 = y; bg_line up to t6): the line, filled with
; spaces, drawn on a panel
panel_line:
        la    t0, bg_line               ; ...
        addi  t1, t0, BG_W              ; ...
        li    t2, ' '                   ; ...
pl2_f:  bgeu  t6, t1, pl2_w             ; ...
        sb    t2, 0(t6)                 ; ...
        addi  t6, t6, 1                 ; ...
        j     pl2_f                     ; ...
pl2_w:  addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    a0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        li    a0, C_PANEL_LIGHT         ; ...
        call  pal                       ; ...
        mv    a5, a0                    ; ...
        li    a0, C_TEXT                ; ...
        call  pal                       ; ...
        mv    a4, a0                    ; ...
        ld    a0, 8(sp)                 ; (a margin of a character)
        addi  a0, a0, 8                 ; ...
        ld    a1, 16(sp)                ; ...
        la    a2, bg_line               ; ...
        li    a3, BG_W - 2              ; ...
        call  wc_text                   ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; modal_key(a0 = key): a panel open (the Ledger, the history): any key
; closes it; the Ledger's closing opens the budget
modal_key:
        ld    t0, g_modal - g(gp)       ; ...
        li    t1, MD_GALLERY            ; the gallery: 1..4 choose a town
        bne   t0, t1, mk_0              ; ...
        addi  t2, a0, -'1'              ; ...
        li    t1, 4                     ; ...
        bgeu  t2, t1, mk_0              ; ...
        sd    zero, g_modal - g(gp)     ; ...
        li    t1, 1                     ; ...
        sd    t1, g_dview - g(gp)       ; ...
        addi  a0, t2, 1                 ; ...
        j     gallery_pick              ; ...
mk_0:   li    t1, MD_YEARS              ; the years: 1..8 bring one back
        bne   t0, t1, mk_y              ; ...
        addi  t2, a0, -'1'              ; ...
        li    t1, YR_MAX                ; ...
        bgeu  t2, t1, mk_1              ; ...
        sd    zero, g_modal - g(gp)     ; ...
        li    t1, 1                     ; ...
        sd    t1, g_dview - g(gp)       ; ...
        addi  a0, t2, 1                 ; ...
        la    t5, u_ypick               ; ...
        j     mk_x                      ; ...
mk_y:   li    t1, MD_EVENTS             ; the events: 1..6 call one down
        bne   t0, t1, mk_1              ; ...
        addi  t2, a0, -'1'              ; ...
        li    t1, 6                     ; ...
        bgeu  t2, t1, mk_1              ; ...
        sd    zero, g_modal - g(gp)     ; ...
        li    t1, 1                     ; ...
        sd    t1, g_dview - g(gp)       ; ...
        addi  a0, t2, 1                 ; ...
        li    a1, 1                     ; ...
        la    t5, u_event               ; ...
mk_x:   addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        xcall ra, c0, t5                ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done
mk_1:
        sd    zero, g_modal - g(gp)     ; ...
        li    t1, 1                     ; the map under it drawn again
        sd    t1, g_dview - g(gp)       ; ...
        li    t1, MD_PAPER              ; ...
        beq   t0, t1, budget_open       ; ...
        ret                             ; done

        .far                            ; code units (paged in by the kernel)
        .align UNIT                     ; a unit
unit_bud:
u_bdraw:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; the far return link
        call  budget_draw               ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        xret  ra                        ; back (paged in again if it had to go)
budget_draw:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the panel's left
        sd    s1, 16(sp)                ; s1 = its top
        sd    s2, 24(sp)                ; s2 = the line
        sd    s3, 32(sp)                ; s3 = the text's colour
        sd    s4, 40(sp)                ; s4 = the panel's
        li    a0, C_TEXT                ; ...
        la    t6, pal                   ; ...
        jalr  ra, t6, 0                 ; ...
        mv    s3, a0                    ; ...
        li    a0, C_PANEL_LIGHT         ; ...
        la    t6, pal                   ; ...
        jalr  ra, t6, 0                 ; ...
        mv    s4, a0                    ; ...
        ld    t0, g_w - g(gp)           ; centred over the map
        addi  t0, t0, TOOLW - BG_W * 8  ; ...
        srai  s0, t0, 1                 ; ...
        andi  s0, s0, 0xfffe            ; ...
        ld    t0, g_h - g(gp)           ; ...
        addi  t0, t0, -BARH - PANEL_H   ; ...
        srai  s1, t0, 1                 ; ...
        bgez  s1, bd_0                  ; ...
        li    s1, 0                     ; ...
bd_0:   li    a0, C_PANEL_DARK          ; its frame
        la    t6, pal                   ; ...
        jalr  ra, t6, 0                 ; ...
        mv    a4, a0                    ; ...
        addi  a0, s0, -4                ; ...
        addi  a1, s1, -4                ; ...
        li    a2, BG_W * 8 + 8          ; ...
        li    a3, PANEL_H + 8           ; ...
        la    t6, wc_fill               ; ...
        jalr  ra, t6, 0                 ; ...
        mv    a4, s4                    ; ... and its inside
        mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        li    a2, BG_W * 8              ; ...
        li    a3, PANEL_H               ; ...
        la    t6, wc_fill               ; ...
        jalr  ra, t6, 0                 ; ...
        addi  s1, s1, 8                 ; the lines
        li    s2, 0                     ; ...
bd_l:   la    a0, bg_line               ; ...
        mv    t6, a0                    ; t6 = where the line goes on
        li    t0, 1                     ; 1: last year's money
        beq   s2, t0, bd_m              ; ...
        addi  t1, s2, -BG_SEL           ; the choices
        li    t0, NB_CHOICE             ; ...
        bltu  t1, t0, bd_c              ; ...
        li    t0, 7                     ; 7, 8: how to use it
        la    a1, bg_t7                 ; ...
        beq   s2, t0, bd_s              ; ...
        li    t0, 8                     ; ...
        la    a1, bg_t8                 ; ...
        beq   s2, t0, bd_s              ; ...
        la    a1, bg_t0                 ; 0: the title
        beqz  s2, bd_s                  ; ...
        j     bd_out                    ; (empty)
bd_m:   la    a1, bg_t1                 ; ...
        call  bg_str                    ; ...
        ld    a0, g_lytax - g(gp)       ; ...
        call  bg_num                    ; ...
        la    a1, bg_t1b                ; ...
        call  bg_str                    ; ...
        ld    a0, g_lyupk - g(gp)       ; ...
        call  bg_num                    ; ...
        j     bd_out                    ; ...
bd_c:   li    t0, '>'                   ; a choice: marked if chosen
        ld    t2, g_bsel - g(gp)        ; ...
        beq   t1, t2, bd_c1             ; ...
        li    t0, ' '                   ; ...
bd_c1:  sb    t0, 0(t6)                 ; ...
        addi  t6, t6, 1                 ; ...
        slli  t1, t1, 3                 ; ...
        la    t0, bg_txt                ; ...
        add   t0, t0, t1                ; ...
        ld    a1, 0(t0)                 ; ...
        call  bg_str                    ; ...
        li    t0, '<'                   ; ...
        sb    t0, 0(t6)                 ; ...
        li    t0, ' '                   ; ...
        sb    t0, 1(t6)                 ; ...
        addi  t6, t6, 2                 ; ...
        slli  t1, s2, 3                 ; its number
        addi  t1, t1, -BG_SEL * 8       ; ...
        la    t0, bg_vals               ; ...
        add   t0, t0, t1                ; ...
        ld    t0, 0(t0)                 ; ...
        ld    a0, 0(t0)                 ; ...
        call  bg_num                    ; ...
        li    t0, '%'                   ; ...
        sb    t0, 0(t6)                 ; ...
        li    t0, ' '                   ; ...
        sb    t0, 1(t6)                 ; ...
        li    t0, '>'                   ; ...
        sb    t0, 2(t6)                 ; ...
        addi  t6, t6, 3                 ; ...
        j     bd_out                    ; ...
bd_s:   call  bg_str                    ; ...
bd_out: la    t0, bg_line               ; the line, filled with spaces, drawn
        addi  t1, t0, BG_W              ; ...
        li    t2, ' '                   ; ...
bd_f:   bgeu  t6, t1, bd_w              ; ...
        sb    t2, 0(t6)                 ; ...
        addi  t6, t6, 1                 ; ...
        j     bd_f                      ; ...
bd_w:   mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        la    a2, bg_line               ; ...
        li    a3, BG_W                  ; ...
        mv    a4, s3                    ; ...
        mv    a5, s4                    ; ...
        la    t6, wc_text               ; ...
        jalr  ra, t6, 0                 ; ...
        addi  s1, s1, 20                ; ...
        addi  s2, s2, 1                 ; ...
        li    t0, BG_LINES              ; ...
        blt   s2, t0, bd_l              ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        addi  sp, sp, 48                ; pop the frame
        ret                             ; done

; bg_str(a1 = text, NUL-terminated): appended at t6
bg_str: lbu   t0, 0(a1)                 ; ...
        beqz  t0, bgs_r                 ; ...
        sb    t0, 0(t6)                 ; ...
        addi  a1, a1, 1                 ; ...
        addi  t6, t6, 1                 ; ...
        j     bg_str                    ; ...
bgs_r:  ret                             ; done

; bg_num(a0 = number): its digits, with commas, appended at t6 (clobbers s0
; for the call: t_comma writes at s0)
bg_num: addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; ...
        mv    s0, t6                    ; ...
        la    t6, t_comma               ; ...
        jalr  ra, t6, 0                 ; ...
        mv    t6, s0                    ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

        .org  unit_bud + UNIT           ; (a unit fits its slot: else an error here)
        .text                           ; code
