; r_demand(a0 = the bar's row): that row of the three demand bars at the
; bar's right end (homes, shops and offices, industry): up from the middle
; row for demand, down from it for too much, 12 pixels at the most
r_demand:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the row
        sd    s1, 16(sp)                ; s1 = the kind
        sd    s2, 24(sp)                ; s2 = its colour
        mv    s0, a0                    ; ...
        li    s1, 0                     ; ...
dd_k:   la    t0, dd_col                ; ...
        add   t0, t0, s1                ; ...
        lbu   a0, 0(t0)                 ; ...
        call  pal                       ; ...
        mv    s2, a0                    ; ...
        la    t0, g_dr                  ; t1 = the bar's length
        slli  t1, s1, 3                 ; ...
        add   t0, t0, t1                ; ...
        ld    t0, 0(t0)                 ; ...
        li    t1, 12                    ; ...
        mul   t1, t1, t0                ; ...
        li    t2, 1000                  ; ...
        div   t1, t1, t2                ; ...
        li    t2, 16                    ; the middle row: always
        beq   s0, t2, dd_d              ; ...
        bltz  t1, dd_neg                ; ...
        sub   t3, t2, s0                ; above it: within the length
        blez  t3, dd_n                  ; ...
        bgt   t3, t1, dd_n              ; ...
        j     dd_d                      ; ...
dd_neg: sub   t3, s0, t2                ; below it
        blez  t3, dd_n                  ; ...
        neg   t1, t1                    ; ...
        bgt   t3, t1, dd_n              ; ...
dd_d:   ld    t0, g_bw - g(gp)          ; draw: six pixels at x = width - 40 + 10 * kind
        addi  t0, t0, -40               ; ...
        li    t1, 10                    ; ...
        mul   t1, t1, s1                ; ...
        add   t0, t0, t1                ; ...
        slli  t0, t0, 2                 ; ...
        la    t1, rowbuf                ; ...
        add   t0, t0, t1                ; ...
        li    t1, 6                     ; ...
dd_p:   sw    s2, 0(t0)                 ; ...
        addi  t0, t0, 4                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, dd_p                  ; ...
dd_n:   addi  s1, s1, 1                 ; ...
        li    t0, 3                     ; ...
        blt   s1, t0, dd_k              ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

; r_text(a0 = what changed: TX_*): the bar's text, drawn by the server in
; its font over the panel's colour: the treasury, the date, the
