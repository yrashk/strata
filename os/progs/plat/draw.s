; t_out(a0 = x, a1 = characters): txtbuf up to s0, filled with spaces to
; that many (and cut there), drawn at x on the bar's text row (s1, s2, s3)
t_out:  la    t0, txtbuf                ; ...
        add   t1, t0, a1                ; t1 = the end
        li    t2, ' '                   ; ...
to_s:   bgeu  s0, t1, to_d              ; ...
        sb    t2, 0(s0)                 ; ...
        addi  s0, s0, 1                 ; ...
        j     to_s                      ; ...
to_d:   mv    a3, a1                    ; ...
        mv    a1, s1                    ; ...
        mv    a2, t0                    ; ...
        mv    a4, s2                    ; ...
        mv    a5, s3                    ; ...
        j     wc_text                   ; ...

; t_num(a0 = number): its digits at s0
t_num:  li    t5, 0                     ; (no commas)
        j     tc_0                      ; ...
; t_comma(a0 = number): its digits, with a comma between thousands, at s0
t_comma:
        li    t5, 1                     ; ...
tc_0:   li    t1, 10                    ; ...
        li    t2, 0                     ; t2 = characters (on the stack, last first)
        li    t3, 0                     ; t3 = digits since the last comma
tc_1:   li    t4, 3                     ; ...
        bne   t3, t4, tc_2              ; ...
        beqz  t5, tc_2                  ; ...
        li    t0, ','                   ; ...
        addi  sp, sp, -8                ; ...
        sd    t0, 0(sp)                 ; ...
        addi  t2, t2, 1                 ; ...
        li    t3, 0                     ; ...
tc_2:   remu  t0, a0, t1                ; ...
        divu  a0, a0, t1                ; ...
        addi  t0, t0, '0'               ; ...
        addi  sp, sp, -8                ; ...
        sd    t0, 0(sp)                 ; ...
        addi  t2, t2, 1                 ; ...
        addi  t3, t3, 1                 ; ...
        bnez  a0, tc_1                  ; ...
tc_3:   ld    t0, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        sb    t0, 0(s0)                 ; ...
        addi  s0, s0, 1                 ; ...
        addi  t2, t2, -1                ; ...
        bnez  t2, tc_3                  ; ...
        ret                             ; done

