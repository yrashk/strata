        sd    s1, 16(sp)                ; s1 = the text's row
        sd    s2, 24(sp)                ; s2 = the colours: text
        sd    s3, 32(sp)                ; s3 = ... panel
        sd    s4, 40(sp)                ; s4 = what changed
        mv    s4, a0                    ; ...
        ld    s1, g_h - g(gp)           ; ...
        li    t0, BARH                  ; ...
        blt   s1, t0, rx_r              ; ...
        addi  s1, s1, -BARH + TEXT_Y    ; ...
