; r_cursor(a0 = the group's first column in the view, a1 = cells, a2 = the
; map's row, a3 = the row in the cell on the screen; the row in rowbuf
; stands for g_rep rows): the keyboard's cursor, a frame two pixels
; wide round its cell (yellow; red while the pen is down), over the row in
; rowbuf if it is there
r_cursor:
        ld    t0, g_curon - g(gp)       ; ...
        beqz  t0, rk_r                  ; ...
        ld    t0, g_cury - g(gp)        ; ...
        bne   t0, a2, rk_r              ; ...
        ld    t0, g_ox - g(gp)          ; its column in the group
        add   a0, a0, t0                ; ...
        ld    t0, g_curx - g(gp)        ; ...
        sub   t0, t0, a0                ; ...
        bgeu  t0, a1, rk_r              ; ...
        ld    t1, g_cp - g(gp)          ; t2 = its first pixel in rowbuf
        mul   t2, t0, t1                ; ...
        slli  t2, t2, 2                 ; ...
        la    t3, rowbuf                ; ...
        add   t2, t2, t3                ; ...
        li    a0, C_CURSOR              ; t4 = its colour
        ld    t0, g_pen - g(gp)         ; ...
        beqz  t0, rk_c                  ; ...
        li    a0, C_PEN                 ; ...
rk_c:   slli  a0, a0, 2                 ; ...
        la    t4, res + R_PAL           ; ...
        add   a0, a0, t4                ; ...
        lwu   t4, 0(a0)                 ; ...
        li    t5, 2                     ; the top rows and the bottom ones: across
        blt   a3, t5, rk_full           ; ...
        ld    t5, g_rep - g(gp)         ; ...
        add   t5, t5, a3                ; ...
        addi  t6, t1, -2                ; ...
        bgt   t5, t6, rk_full           ; ...
        sw    t4, 0(t2)                 ; between: the sides, two pixels each
        sw    t4, 4(t2)                 ; ...
        slli  t3, t1, 2                 ; ...
        add   t3, t3, t2                ; ...
        sw    t4, -4(t3)                ; ...
        sw    t4, -8(t3)                ; ...
        ret                             ; ...
rk_full:
        sw    t4, 0(t2)                 ; ...
        addi  t2, t2, 4                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, rk_full               ; ...
rk_r:   ret                             ; done

; fill_row(a0 = pixels, a1 = colour): rowbuf's first pixels are that colour
fill_row:
        la    t0, rowbuf                ; ...
fr_l:   sw    a1, 0(t0)                 ; ...
        addi  t0, t0, 4                 ; ...
        addi  a0, a0, -1                ; ...
        bnez  a0, fr_l                  ; ...
        ret                             ; done

; blit_row(a0 = sprite, a1 = its row, a2 = rowbuf's pixel x): that row of
; the sprite, over the pixels from x on (index 255 is transparent)
blit_row:
        slli  a0, a0, 3                 ; the sprite's entry
        la    t0, res + R_SPR           ; ...
        add   a0, a0, t0                ; ...
        lwu   t0, 0(a0)                 ; t0 = its far offset
        lhu   t1, 4(a0)                 ; t1 = its width
        addi  t2, t1, 7                 ; t2 = bytes a row
        andi  t2, t2, 0xfff8            ; ...
        mul   t3, a1, t2                ; the row
        add   t0, t0, t3                ; ...
        ld    t3, g_keepb - g(gp)       ; ...
        add   t0, t0, t3                ; ...
        la    t3, sprbuf                ; ...
        tget  tg8, t3, c0, t0, t2       ; ...
        twait 1 << 8                    ; ...
        la    t4, rowbuf                ; t4 = the first pixel
        slli  a2, a2, 2                 ; ...
        add   t4, t4, a2                ; ...
        la    a5, res + R_PAL           ; ...
        li    t6, 255                   ; ...
br_l:   lbu   t5, 0(t3)                 ; ...
        beq   t5, t6, br_n              ; ...
        slli  t5, t5, 2                 ; ...
        add   t5, t5, a5                ; ...
        lwu   t5, 0(t5)                 ; ...
        sw    t5, 0(t4)                 ; ...
br_n:   addi  t3, t3, 1                 ; ...
        addi  t4, t4, 4                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, br_l                  ; ...
        ret                             ; done

; tool_hit(a0 = x, a1 = y in the window) -> a0 = the tool whose button is
; there, or -1
tool_hit:
        li    t0, 0                     ; t0 = the tool
th_l:   andi  t1, t0, 1                 ; its button's corner
        li    t2, TB_DX                 ; ...
        mul   t1, t1, t2                ; ...
        addi  t1, t1, TB_X0             ; ...
        srli  t3, t0, 1                 ; ...
        mul   t3, t3, t2                ; ...
        addi  t3, t3, TB_Y0             ; ...
        sub   t1, a0, t1                ; inside it?
        sub   t3, a1, t3                ; ...
        li    t2, TB_SIZE               ; ...
        bgeu  t1, t2, th_n              ; ...
        bgeu  t3, t2, th_n              ; ...
        mv    a0, t0                    ; ...
        ret                             ; ...
th_n:   addi  t0, t0, 1                 ; ...
        li    t1, NBUTTON               ; ...
        blt   t0, t1, th_l              ; ...
        li    a0, -1                    ; ...
        ret                             ; done

