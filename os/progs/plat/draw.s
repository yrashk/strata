; fp_update(): the placement's preview: the tool's footprint at the cursor
; (if it is shown), green if the tool can be used there, red if not; its
; cells drawn again when it moves or changes
fp_update:
        addi  sp, sp, -56               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0..s3 = the new footprint
        sd    s1, 16(sp)                ; ...
        sd    s2, 24(sp)                ; ...
        sd    s3, 32(sp)                ; ...
        sd    s4, 40(sp)                ; s4 = its colour
        li    s0, 0                     ; (none)
        li    s1, 0                     ; ...
        li    s2, 0                     ; ...
        li    s3, 0                     ; ...
        li    s4, 0                     ; ...
        ld    t0, g_curon - g(gp)       ; ...
        beqz  t0, fu_c                  ; ...
        ld    t0, g_budget - g(gp)      ; (not under a panel)
        bnez  t0, fu_c                  ; ...
        ld    t0, g_modal - g(gp)       ; ...
        bnez  t0, fu_c                  ; ...
        ld    s0, g_curx - g(gp)        ; ...
        ld    s1, g_cury - g(gp)        ; ...
        ld    t0, g_tool - g(gp)        ; its size
        la    t1, cp_blk                ; ...
        add   t1, t1, t0                ; ...
        lbu   t1, 0(t1)                 ; ...
        li    t2, 1                     ; ...
        beqz  t1, fu_1                  ; ...
        mv    t2, t1                    ; ...
        addi  s0, s0, -1                ; ...
        addi  s1, s1, -1                ; ...
fu_1:   add   s2, s0, t2                ; ...
        add   s3, s1, t2                ; ...
        ld    a0, g_curx - g(gp)        ; can it be?
        ld    a1, g_cury - g(gp)        ; ...
        la    t5, u_canplace            ; ...
        xcall ra, c0, t5                ; ...
        li    s4, 0x00e03030            ; ...
        beqz  a0, fu_c                  ; ...
        li    s4, 0x0030c050            ; ...
fu_c:   ld    t0, g_fx0 - g(gp)         ; as it was: nothing to draw
        bne   t0, s0, fu_d              ; ...
        ld    t0, g_fy0 - g(gp)         ; ...
        bne   t0, s1, fu_d              ; ...
        ld    t0, g_fx1 - g(gp)         ; ...
        bne   t0, s2, fu_d              ; ...
        ld    t0, g_fpc - g(gp)         ; ...
        beq   t0, s4, fu_r              ; ...
fu_d:   ld    t0, g_fx0 - g(gp)         ; the old one's cells, and the new one's
        ld    t1, g_fx1 - g(gp)         ; ...
        bge   t0, t1, fu_n              ; ...
        mv    a0, t0                    ; ...
        ld    a1, g_fy0 - g(gp)         ; ...
        call  fu_dirty                  ; ...
        ld    a0, g_fx1 - g(gp)         ; ...
        addi  a0, a0, -1                ; ...
        ld    a1, g_fy1 - g(gp)         ; ...
        addi  a1, a1, -1                ; ...
        call  fu_dirty                  ; ...
fu_n:   sd    s0, g_fx0 - g(gp)         ; ...
        sd    s1, g_fy0 - g(gp)         ; ...
        sd    s2, g_fx1 - g(gp)         ; ...
        sd    s3, g_fy1 - g(gp)         ; ...
        sd    s4, g_fpc - g(gp)         ; ...
        bge   s0, s2, fu_r              ; ...
        mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        call  fu_dirty                  ; ...
        addi  a0, s2, -1                ; ...
        addi  a1, s3, -1                ; ...
        call  fu_dirty                  ; ...
fu_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        addi  sp, sp, 56                ; pop the frame
        ret                             ; done
fu_dirty:                               ; (a0, a1 on the map: a corner drawn again)
        li    t0, MAPN                  ; ...
        bgeu  a0, t0, fd_r              ; ...
        bgeu  a1, t0, fd_r              ; ...
        j     dirty_cell                ; ...
fd_r:   ret                             ; done

