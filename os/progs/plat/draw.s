; =============================================================================
; draw.s: Plat's window: the map, the tool column, the bar
; =============================================================================
;
; Everything is drawn as XRGB8888 rows in the D-LS (rowbuf), sent into the
; band (the arena between the code units and plat.dat's far block) with
; `tput` and lent to the server with DAMAGE, a rectangle at a time: the
; arena is split at the band's start (csplit), the part from there on is
; lent (from c6: the code units stay in c0), and it is joined to the
; units' part again when it comes back. Nothing is drawn that did not
; change (show): the whole map after a scroll or a zoom, otherwise only the
; cells a tool or the cursor changed (the rectangle g_dx0 .. g_dy1); the
; tool column when a tool is picked; the bar when the speed changes, and
; its numbers and message (drawn by the server in its font: r_text) when
; they do.
;
; The map (r_cells) is drawn a row of cells at a time, sixteen cells at a
; time: their pictures (256 bytes each) are fetched into tilebuf, and each
; of their 16 rows is turned into pixels through the palette, twice as wide
; and twice over when the cells are 32 pixels, into the band.

TOOLW    = 64                           ; the tool column's width
BARH     = 32                           ; the bar's height
MAXW     = 1280                         ; the widest bar drawn (a wider window's rest is plain)
ROWBUF   = MAXW * 4                     ; bytes of a row of pixels
TB_X0    = 4                            ; the tool buttons: the first one's corner
TB_Y0    = 6                            ; ...
TB_DX    = 30                           ; ... and from one to the next
TB_SIZE  = 28                           ; ... their size
NBUTTON  = NTOOL + 4                    ; the buttons: the tools, zoom in, zoom out,
B_BUDGET = NTOOL + 2                    ;   the budget, the maps over the town
B_ZIN    = NTOOL                        ; ...
B_ZOUT   = NTOOL + 1                    ; ...
B_MAP    = NTOOL + 3                    ; ...
TIP_T    = 140                          ; tics a tooltip stays without a move
OV_POWER = 1                            ; maps over the town (g_ovl): power
OV_MAPS  = 2                            ; ... from here, sim2.s's: land value,
OV_LAND  = 2                            ;   pollution, crime, traffic, police cover,
OV_GOOD  = 6                            ;   fire cover (from OV_GOOD on more is better)
NOV      = 8                            ; ... (0: none)
SPD_X    = 8                            ; the bar: the speed buttons
SPD_DX   = 20                           ; ...
FUNDS_X  = 120                          ; ... the treasury's text (its icon 16 to the left)
DATE_X   = 232                          ; ... the date's
POP_X    = 328                          ; ... the population's
TAX_X    = 416                          ; ... the tax rate's
MSG_X    = 496                          ; ... the message's
ICON_Y   = 10                           ; ... the icons' row
TEXT_Y   = 8                            ; ... the text's
TX_FUNDS = 1                            ; the bar's texts, as bits of g_dtext: the treasury
TX_DATE  = 2                            ; ... the date
TX_POP   = 4                            ; ... the population
TX_MSG   = 8                            ; ... the message
TX_TAX   = 16                           ; ... the tax rate
TX_ALL   = 31                           ; ...

        .data                           ; D-LS
        .align 8                        ; dwords
rowbuf:   .space ROWBUF                 ; a row of pixels
sprbuf:   .space 160                    ; a row of a sprite
txtbuf:   .space 96                     ; a text for the bar
tl_spr:   .dword SP_TOOL_BULLDOZE, SP_TOOL_ROAD, SP_TOOL_LINE, SP_TOOL_QUERY ; the tools' icons
          .dword SP_TOOL_RES, SP_TOOL_COM, SP_TOOL_IND, SP_TOOL_COAL ; ...
          .dword SP_TOOL_RAIL, SP_TOOL_POLICE, SP_TOOL_FIRE, SP_TOOL_PARK ; ...
          .dword SP_TOOL_SOLAR          ; ...
          .dword SP_TOOL_ZOOM_IN, SP_TOOL_ZOOM_OUT ; ... and the zoom's buttons,
          .dword SP_TOOL_BUDGET, SP_TOOL_MAP ; ... the budget's, the maps'
markbuf:  .space 2 * 256                ; the marks over a zone: no road, no power
ovrow:    .space 64                     ; a row of the map shown over the town
ovcol:    .space 16 * 4                 ; the group's cells: their colour of it (0: none)
ov_cm:    .byte CM_LAND, CM_POLL, CM_CRIME, CM_TRAF ; the maps shown (OV_MAPS on): which
          .byte CM_POLICE, CM_FIRE      ; ...
ov_cond:  .byte 0, 0, 0, 0, 0          ; what power goes through (power's map), by kind
          .byte 0, 0, 1, 1, 1           ; ...
          .byte 1, 1, 0, 0, 0           ; ...
          .byte 1, 1, 1, 0, 0           ; ...
        .align 8                        ; ...
ov_bad:   .word 0x0040b050, 0x0070c048, 0x00a0d040, 0x00d0d038 ; colours for pollution,
          .word 0x00e0b030, 0x00e08028, 0x00e05028, 0x00c02020 ;   crime, traffic: low to high
ov_good:  .word 0x00c04040, 0x00c07050, 0x00b0a060, 0x0090b070 ; for land value and cover:
          .word 0x0070b090, 0x0050a0b0, 0x004080c8, 0x003060e0 ;   low to high
marks:    .space 16                     ; the group's cells: their marks (0: none, 1, 2)
months:   .ascii "JanFebMarAprMayJunJulAugSepOctNovDec" ; the months' names
dd_col:   .byte C_RES, C_COM, C_IND     ; the demand bars' colours
tx_tax:   .ascii "Tax "                 ; the tax rate's text
        .align 8                        ; ...
        .text                           ; code

; pal(a0 = palette index) -> a0 = its colour
pal:    slli  a0, a0, 2                 ; ...
        la    t0, res + R_PAL           ; ...
        add   a0, a0, t0                ; ...
        lwu   a0, 0(a0)                 ; ...
        ret                             ; done

; geom(): the window has a (new) size, or the zoom changed: how many cells
; the view holds; the window is cleared to the panel's colour and
; everything is to be drawn
geom:   addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        la    t0, wc_surf               ; ...
        ld    a2, S_W(t0)               ; a2 = width
        ld    a3, S_H(t0)               ; a3 = height
        sd    a2, g_w - g(gp)           ; ...
        sd    a3, g_h - g(gp)           ; ...
        mv    t0, a2                    ; the bar's width
        li    t1, MAXW                  ; ...
        bleu  t0, t1, ge_1              ; ...
        mv    t0, t1                    ; ...
ge_1:   sd    t0, g_bw - g(gp)          ; ...
        li    t2, 4                     ; a cell's pixels
        ld    t0, g_zoom - g(gp)        ; ...
        sll   t2, t2, t0                ; ...
        sd    t2, g_cp - g(gp)          ; ...
        li    t0, 1                     ; the pictures' pixels: each once,
        sd    t0, g_step - g(gp)        ; ...
        sd    t0, g_rep - g(gp)         ; ...
        li    t1, 16                    ; ...
        bltu  t2, t1, ge_s              ; ...
        srli  t0, t2, 4                 ; ... or g_rep times (larger cells)
        sd    t0, g_rep - g(gp)         ; ...
        j     ge_s1                     ; ...
ge_s:   divu  t0, t1, t2                ; ... or only every g_step-th (smaller)
        sd    t0, g_step - g(gp)        ; ...
ge_s1:  li    t3, MAPN                  ; ...
        addi  t0, a2, -TOOLW            ; cells across
        bgtz  t0, ge_2                  ; ...
        li    t0, 0                     ; ...
ge_2:   divu  t0, t0, t2                ; ...
        bleu  t0, t3, ge_3              ; ...
        mv    t0, t3                    ; ...
ge_3:   sd    t0, g_vw - g(gp)          ; ...
        addi  t0, a3, -BARH             ; ... and down
        bgtz  t0, ge_4                  ; ...
        li    t0, 0                     ; ...
ge_4:   divu  t0, t0, t2                ; ...
        bleu  t0, t3, ge_5              ; ...
        mv    t0, t3                    ; ...
ge_5:   sd    t0, g_vh - g(gp)          ; ...
        ld    t1, g_vw - g(gp)          ; the view, centred in what is left
        mul   t1, t1, t2                ; ...
        addi  t3, a2, -TOOLW            ; ...
        sub   t1, t3, t1                ; ...
        srai  t1, t1, 2                 ; (at an even column)
        slli  t1, t1, 1                 ; ...
        bgez  t1, ge_6                  ; ...
        li    t1, 0                     ; ...
ge_6:   addi  t1, t1, TOOLW             ; ...
        sd    t1, g_px - g(gp)          ; ...
        mul   t1, t0, t2                ; ...
        addi  t3, a3, -BARH             ; ...
        sub   t1, t3, t1                ; ...
        srai  t1, t1, 1                 ; ...
        bgez  t1, ge_7                  ; ...
        li    t1, 0                     ; ...
ge_7:   sd    t1, g_py - g(gp)          ; ...
        li    a0, C_PANEL               ; the panel's colour everywhere
        call  pal                       ; ...
        mv    a4, a0                    ; ...
        li    a0, 0                     ; ...
        li    a1, 0                     ; ...
        call  wc_fill                   ; ...
        li    t0, 1                     ; everything is to be drawn
        sd    t0, g_dview - g(gp)       ; ...
        sd    t0, g_dtools - g(gp)      ; ...
        sd    t0, g_dbar - g(gp)        ; ...
        li    t0, TX_ALL                ; ...
        sd    t0, g_dtext - g(gp)       ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; dirty() -> a0 = something is to be drawn
dirty:  ld    a0, g_dview - g(gp)       ; ...
        ld    t0, g_dtools - g(gp)      ; ...
        or    a0, a0, t0                ; ...
        ld    t0, g_dbar - g(gp)        ; ...
        or    a0, a0, t0                ; ...
        ld    t0, g_dtext - g(gp)       ; ...
        or    a0, a0, t0                ; ...
        ld    t0, g_dx0 - g(gp)         ; ...
        ld    t1, g_dx1 - g(gp)         ; ...
        slt   t0, t0, t1                ; ...
        or    a0, a0, t0                ; ...
        ret                             ; done

; show(): draw what changed
show:   addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        call  fp_update                 ; the placement's preview where the cursor is
        ld    t0, g_dx0 - g(gp)         ; t0..t3: the changed cells, in the view
        ld    t1, g_dy0 - g(gp)         ; ...
        ld    t2, g_dx1 - g(gp)         ; ...
        ld    t3, g_dy1 - g(gp)         ; ...
        sd    zero, g_dx0 - g(gp)       ; (and no more)
        sd    zero, g_dx1 - g(gp)       ; ...
        ld    t4, g_vw - g(gp)          ; (no view: nothing of it)
        beqz  t4, sh_t                  ; ...
        ld    t4, g_vh - g(gp)          ; ...
        beqz  t4, sh_t                  ; ...
        ld    t4, g_dview - g(gp)       ; the whole view
        beqz  t4, sh_c                  ; ...
        sd    zero, g_dview - g(gp)     ; ...
        li    a0, 0                     ; ...
        li    a1, 0                     ; ...
        ld    a2, g_vw - g(gp)          ; ...
        ld    a3, g_vh - g(gp)          ; ...
        call  r_cells                   ; ...
        j     sh_t                      ; ...
sh_c:   ld    t4, g_ox - g(gp)          ; the changed cells: their part in the view
        ld    t5, g_oy - g(gp)          ; ...
        bge   t0, t4, sh_1              ; ...
        mv    t0, t4                    ; ...
sh_1:   bge   t1, t5, sh_2              ; ...
        mv    t1, t5                    ; ...
sh_2:   ld    t6, g_vw - g(gp)          ; ...
        add   t6, t6, t4                ; ...
        ble   t2, t6, sh_3              ; ...
        mv    t2, t6                    ; ...
sh_3:   ld    t6, g_vh - g(gp)          ; ...
        add   t6, t6, t5                ; ...
        ble   t3, t6, sh_4              ; ...
        mv    t3, t6                    ; ...
sh_4:   bge   t0, t2, sh_t              ; (none)
        bge   t1, t3, sh_t              ; ...
        sub   a0, t0, t4                ; ...
        sub   a1, t1, t5                ; ...
        sub   a2, t2, t0                ; ...
        sub   a3, t3, t1                ; ...
        call  r_cells                   ; ...
sh_t:   ld    t0, g_dtools - g(gp)      ; the tool column
        beqz  t0, sh_b                  ; ...
        sd    zero, g_dtools - g(gp)    ; ...
        call  r_tools                   ; ...
        li    t0, 1                     ; (and the minimap over it)
        sd    t0, g_dmini - g(gp)       ; ...
sh_b:   ld    t0, g_dbar - g(gp)        ; the bar (and so its text)
        beqz  t0, sh_x                  ; ...
        sd    zero, g_dbar - g(gp)      ; ...
        li    t0, TX_ALL                ; ...
        sd    t0, g_dtext - g(gp)       ; ...
        call  r_bar                     ; ...
sh_x:   ld    a0, g_dtext - g(gp)       ; the bar's text (what of it changed)
        beqz  a0, sh_mn                 ; ...
        sd    zero, g_dtext - g(gp)     ; ...
        call  r_text                    ; ...
sh_mn:  ld    t0, g_dmini - g(gp)       ; the minimap
        beqz  t0, sh_bu                 ; ...
        sd    zero, g_dmini - g(gp)     ; ...
        call  r_mini                    ; ...
sh_bu:  ld    t0, g_budget - g(gp)      ; the budget's panel, over what was drawn
        beqz  t0, sh_mo                 ; ...
        ld    t0, g_dbud - g(gp)        ; ...
        beqz  t0, sh_mo                 ; ...
        sd    zero, g_dbud - g(gp)      ; ...
        la    t5, u_bdraw               ; ...
        xcall ra, c0, t5                ; ...
sh_mo:  ld    t0, g_modal - g(gp)       ; the Ledger's or the history's panel
        beqz  t0, sh_tp                 ; ...
        ld    t1, g_dbud - g(gp)        ; ...
        beqz  t1, sh_tp                 ; ...
        sd    zero, g_dbud - g(gp)      ; ...
        la    t5, u_pdraw               ; ...
        li    t1, MD_PAPER              ; ...
        beq   t0, t1, sh_md             ; ...
        la    t5, u_gldraw              ; ...
        li    t1, MD_GALLERY            ; ...
        beq   t0, t1, sh_md             ; ...
        la    t5, u_hdraw               ; ...
        li    t1, MD_EVENTS             ; ...
        beq   t0, t1, sh_md             ; ...
        la    t5, u_gdraw               ; ...
sh_md:  xcall ra, c0, t5                ; ...
sh_tp:  ld    t0, g_tip - g(gp)         ; the tooltip: over what was drawn
        bltz  t0, sh_r                  ; ...
        ld    t0, g_tipd - g(gp)        ; ...
        beqz  t0, sh_r                  ; ...
        sd    zero, g_tipd - g(gp)      ; ...
        call  tip_draw                  ; ...
sh_r:   ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; r_damage(a0 = x, a1 = y, a2 = w, a3 = h, a4 = stride): lend the band: that
; rectangle of the window is in it, from its start
r_damage:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        twait (1 << 8) | (1 << 9)       ; our transfers are done
        la    t0, wc_d                  ; data: x, y, w, h, stride
        sd    a0, 0(t0)                 ; ...
        sd    a1, 8(t0)                 ; ...
        sd    a2, 16(t0)                ; ...
        sd    a3, 24(t0)                ; ...
        sd    a4, 32(t0)                ; ...
        mv    a0, t0                    ; ...
        li    a1, 40                    ; ...
        call  sys_put                   ; ...
        ld    t0, g_bandb - g(gp)       ; the arena from the band on, in c6 (lent from
        csplit c6, c0, t0               ;   c7, sys_now's clock would be gone after)
        li    a0, WC_EP                 ; DAMAGE, with it attached
        li    a1, OP_WDAMAGE            ; ...
        la    t0, wc_id                 ; ...
        ld    a2, 0(t0)                 ; ...
        li    a3, 40                    ; ...
        li    a4, 0                     ; ...
        li    a5, 6                     ; (register 6)
        call  sys_msga                  ; a0 = result; it is back in c6 (or never left)
        cjoin c0, c6                    ; the arena whole again
rd_r:   ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; r_cells(a0 = x, a1 = y, a2 = w, a3 = h: cells of the view): those cells,
; in as many pieces as the band needs
r_cells:
        addi  sp, sp, -112              ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the first column (of the view)
        sd    s1, 16(sp)                ; s1 = the piece's first row
        sd    s2, 24(sp)                ; s2 = columns
        sd    s3, 32(sp)                ; s3 = rows still to draw
        sd    s4, 40(sp)                ; s4 = a cell's pixels
        sd    s5, 48(sp)                ; s5 = the band's stride
        sd    s6, 56(sp)                ; s6 = rows of cells in this piece
        sd    s7, 64(sp)                ; s7 = the row in the piece
        sd    s8, 72(sp)                ; s8 = the group's first column
        sd    s9, 80(sp)                ; s9 = cells in the group
        sd    s10, 88(sp)               ; s10 = the pixel row in the cells
        sd    s11, 96(sp)               ; s11 = the map's row
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        mv    s2, a2                    ; ...
        mv    s3, a3                    ; ...
        ld    s4, g_cp - g(gp)          ; ...
        mul   s5, s2, s4                ; ...
        slli  s5, s5, 2                 ; ...
rc_p:   ld    t0, g_keepb - g(gp)       ; the piece: as many rows of cells as fit
        ld    t1, g_bandb - g(gp)       ; ...
        sub   t0, t0, t1                ; ...
        divu  t0, t0, s5                ; ...
        divu  s6, t0, s4                ; ...
        ble   s6, s3, rc_p1             ; ...
        mv    s6, s3                    ; ...
rc_p1:  li    s7, 0                     ; ...
rc_row: ld    s11, g_oy - g(gp)         ; a row of cells: the map's row
        add   s11, s11, s1              ; ...
        add   s11, s11, s7              ; ...
        ld    t0, g_mapb - g(gp)        ; ...
        slli  t1, s11, 8                ; ...
        add   t0, t0, t1                ; ...
        la    t1, maprow                ; ...
        li    t2, MAPN * 2              ; ...
        tget  tg8, t1, c0, t0, t2       ; ...
        ld    t3, g_ovl - g(gp)         ; a map shown over the town: its row
        li    t4, OV_MAPS               ; ...
        bltu  t3, t4, rc_r0             ; ...
        la    t4, ov_cm - OV_MAPS       ; ...
        add   t4, t4, t3                ; ...
        lbu   t4, 0(t4)                 ; ...
        slli  t4, t4, 12                ; ...
        ld    t0, g_cmb - g(gp)         ; ...
        add   t0, t0, t4                ; ...
        srli  t1, s11, 1                ; ...
        slli  t1, t1, 6                 ; ...
        add   t0, t0, t1                ; ...
        la    t1, ovrow                 ; ...
        li    t2, 64                    ; ...
        tget  tg8, t1, c0, t0, t2       ; ...
rc_r0:  twait 1 << 8                    ; ...
        li    s8, 0                     ; ...
rc_grp: sub   s9, s2, s8                ; a group: sixteen cells at most
        li    t0, 16                    ; ...
        ble   s9, t0, rc_g1             ; ...
        mv    s9, t0                    ; ...
rc_g1:  ld    t3, g_ox - g(gp)          ; t3 = the map's column of the group's first cell
        add   t3, t3, s0                ; ...
        add   t3, t3, s8                ; ...
        slli  t3, t3, 1                 ; ... as an offset in the row
        la    t4, maprow                ; ...
        add   t3, t3, t4                ; ...
        la    t4, tilebuf               ; t4 = where its picture goes
        mv    t5, s9                    ; ...
        ld    t6, g_keepb - g(gp)       ; ...
        li    a1, 256                   ; ...
        la    a2, marks                 ; a2 = its mark
rc_f:   lhu   t0, 0(t3)                 ; the cell's picture: fetch it
        li    a3, 0                     ; (a mark: no road, or no power)
        srli  a4, t0, 13                ; ...
        andi  a5, a4, 1                 ; (F_MARK)
        beqz  a5, rc_m                  ; ...
        li    a3, 1                     ; ...
        andi  a5, a4, 2                 ; (F_ROAD)
        beqz  a5, rc_m                  ; ...
        li    a3, 2                     ; ...
rc_m:   sb    a3, 0(a2)                 ; ...
        addi  a2, a2, 1                 ; ...
        andi  t0, t0, PICMASK           ; ...
        slli  t0, t0, 8                 ; ...
        add   t0, t0, t6                ; ...
        tget  tg8, t4, c0, t0, a1       ; ...
        addi  t3, t3, 2                 ; ...
        addi  t4, t4, 256               ; ...
        addi  t5, t5, -1                ; ...
        bnez  t5, rc_f                  ; ...
        twait 1 << 8                    ; ...
        ld    a0, g_ox - g(gp)          ; the map's colours over them
        add   a0, a0, s0                ; ...
        add   a0, a0, s8                ; ...
        mv    a1, s9                    ; ...
        mv    a2, s11                   ; ...
        call  r_ovprep                  ; ...
        li    s10, 0                    ; ...
rc_ty:  mv    a0, s9                    ; a row of the pictures as pixels
        mv    a1, s10                   ; ...
        call  r_expand                  ; ...
        mv    a0, s9                    ; ... and of the marks over them
        mv    a1, s10                   ; ...
        call  r_marks                   ; ...
        mv    a0, s9                    ; ... and the map's colours
        call  r_overlay                 ; ...
        ld    t0, g_step - g(gp)        ; t1 = its row in the cell on the screen
        divu  t1, s10, t0               ; ...
        ld    t0, g_rep - g(gp)         ; ...
        mul   t1, t1, t0                ; ...
        sd    t1, 104(sp)               ; ...
        mv    a0, s8                    ; the cursor over them?
        mv    a1, s9                    ; ...
        mv    a2, s11                   ; ...
        mv    a3, t1                    ; ...
        add   a0, a0, s0                ; ...
        call  r_cursor                  ; ...
        ld    t1, 104(sp)               ; into the band: the row, g_rep times
        mul   t2, s7, s4                ; ...
        add   t1, t1, t2                ; ...
        mul   t1, t1, s5                ; ...
        mul   t2, s8, s4                ; ...
        slli  t2, t2, 2                 ; ...
        add   t1, t1, t2                ; t1 = where (the band starts at g_bandb)
        ld    t2, g_bandb - g(gp)       ; ...
        add   t1, t1, t2                ; ...
        mul   t2, s9, s4                ; t2 = bytes
        slli  t2, t2, 2                 ; ...
        la    t3, rowbuf                ; ...
        ld    t0, g_rep - g(gp)         ; ...
rc_tp:  tput  tg9, t3, c0, t1, t2       ; (the next row's stores wait for it)
        add   t1, t1, s5                ; ...
        addi  t0, t0, -1                ; ...
        bnez  t0, rc_tp                 ; ...
        ld    t0, g_step - g(gp)        ; ...
        add   s10, s10, t0              ; ...
        li    t0, 16                    ; ...
        blt   s10, t0, rc_ty            ; ...
        add   s8, s8, s9                ; the next group
        blt   s8, s2, rc_grp            ; ...
        addi  s7, s7, 1                 ; the next row of cells
        blt   s7, s6, rc_row            ; ...
        ld    t0, g_cp - g(gp)          ; the piece is drawn: show it
        mul   a0, s0, t0                ; ...
        ld    t1, g_px - g(gp)          ; ...
        add   a0, a0, t1                ; ...
