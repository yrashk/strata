; r_expand(a0 = cells, a1 = pixel row): that row of the pictures in tilebuf
; as pixels in rowbuf: every g_step-th pixel of it, each g_rep times
r_expand:
        la    t0, tilebuf               ; t0 = the cell's row
        slli  a1, a1, 4                 ; ...
        add   t0, t0, a1                ; ...
        la    t1, rowbuf                ; t1 = the next pixel
        la    a5, res + R_PAL           ; a5 = the palette
        ld    a6, g_step - g(gp)        ; ...
        ld    a7, g_rep - g(gp)         ; ...
re_c:   mv    t3, t0                    ; a cell
        addi  t2, t0, 16                ; t2 = its row's end
re_p:   lbu   t4, 0(t3)                 ; a pixel ...
        slli  t4, t4, 2                 ; ...
        add   t4, t4, a5                ; ...
        lwu   t4, 0(t4)                 ; ... its colour ...
        mv    t5, a7                    ; ... g_rep times
re_r:   sw    t4, 0(t1)                 ; ...
        addi  t1, t1, 4                 ; ...
        addi  t5, t5, -1                ; ...
        bnez  t5, re_r                  ; ...
        add   t3, t3, a6                ; ...
        bltu  t3, t2, re_p              ; ...
        addi  t0, t0, 256               ; the next cell
        addi  a0, a0, -1                ; ...
        bnez  a0, re_c                  ; ...
        ret                             ; done

; r_marks(a0 = cells, a1 = pixel row): that row of the marks (marks) over
; the pictures' in rowbuf, as r_expand draws them
r_marks:
        la    t0, marks                 ; t0 = the cell's mark
        la    t1, rowbuf                ; t1 = its first pixel
        la    a5, res + R_PAL           ; ...
        ld    a6, g_step - g(gp)        ; ...
        ld    a7, g_rep - g(gp)         ; ...
        slli  a1, a1, 4                 ; a1 = the row's offset in a mark
rm_c:   lbu   t2, 0(t0)                 ; ...
        beqz  t2, rm_n                  ; ...
        addi  t2, t2, -1                ; t3 = the mark's row
        slli  t2, t2, 8                 ; ...
        la    t3, markbuf               ; ...
        add   t3, t3, t2                ; ...
        add   t3, t3, a1                ; ...
        addi  t2, t3, 16                ; t2 = its end
        mv    t4, t1                    ; t4 = the pixel
rm_p:   lbu   t5, 0(t3)                 ; ...
        li    t6, 255                   ; (transparent)
        beq   t5, t6, rm_s              ; ...
        slli  t5, t5, 2                 ; ...
        add   t5, t5, a5                ; ...
        lwu   t5, 0(t5)                 ; ...
        mv    t6, a7                    ; ...
rm_r:   sw    t5, 0(t4)                 ; ...
        addi  t4, t4, 4                 ; ...
        addi  t6, t6, -1                ; ...
        bnez  t6, rm_r                  ; ...
        j     rm_q                      ; ...
rm_s:   slli  t6, a7, 2                 ; ...
        add   t4, t4, t6                ; ...
rm_q:   add   t3, t3, a6                ; ...
        bltu  t3, t2, rm_p              ; ...
rm_n:   addi  t0, t0, 1                 ; the next cell
        ld    t2, g_cp - g(gp)          ; ...
        slli  t2, t2, 2                 ; ...
        add   t1, t1, t2                ; ...
        addi  a0, a0, -1                ; ...
        bnez  a0, rm_c                  ; ...
        ret                             ; done

; r_ovprep(a0 = the map's column of the group's first cell, a1 = cells, a2
; = the map's row): (and the placement's preview, g_fx0 .. g_fy1, over all)
; ovcol = each cell's colour of the map shown (0: none). Power: yellow where
; it reaches, red where it does not; the other maps: a colour by the map's
; byte there (ov_bad: green to red; ov_good: red to blue)
r_ovprep:
        la    t0, ovcol                 ; t0 = the colour's place
        ld    t1, g_ovl - g(gp)         ; t1 = the map shown
        la    t2, maprow                ; t2 = the cell
        slli  t3, a0, 1                 ; ...
        add   t2, t2, t3                ; ...
ro_c:   li    t3, 0                     ; ...
        beqz  t1, ro_s                  ; (none)
        li    t4, OV_POWER              ; ...
        bne   t1, t4, ro_m              ; ...
        lhu   t4, 0(t2)                 ; power: where it can go
        andi  t5, t4, PICMASK           ; ...
        la    t6, res + R_KIND          ; ...
        add   t6, t6, t5                ; ...
        lbu   t6, 0(t6)                 ; ...
        la    t5, ov_cond               ; ...
        add   t5, t5, t6                ; ...
        lbu   t5, 0(t5)                 ; ...
        beqz  t5, ro_s                  ; ...
        li    t3, 0x00e03030            ; ... red: none
        srli  t4, t4, 15                ; (F_POWER)
        beqz  t4, ro_s                  ; ...
        li    t3, 0x00f0d040            ; ... yellow: it has it
        j     ro_s                      ; ...
ro_m:   srli  t4, a0, 1                 ; a map: its byte
        la    t5, ovrow                 ; ...
        add   t5, t5, t4                ; ...
        lbu   t4, 0(t5)                 ; ...
        li    t6, OV_GOOD               ; (on a map where less is better, little is
        bgeu  t1, t6, ro_8              ;   not tinted)
        li    t6, OV_LAND               ; ...
        beq   t1, t6, ro_8              ; ...
        li    t6, 24                    ; ...
        bltu  t4, t6, ro_s              ; ...
ro_8:   srli  t4, t4, 5                 ; ... in eight steps
        slli  t4, t4, 2                 ; ...
        la    t5, ov_bad                ; ...
        li    t6, OV_GOOD               ; (land value and cover: more is better)
        bgeu  t1, t6, ro_g              ; ...
        li    t6, OV_LAND               ; ...
        bne   t1, t6, ro_b              ; ...
ro_g:   la    t5, ov_good               ; ...
ro_b:   add   t5, t5, t4                ; ...
        lwu   t3, 0(t5)                 ; ...
ro_s:   ld    t4, g_fx0 - g(gp)         ; the placement's preview over it all
        blt   a0, t4, ro_s1             ; ...
        ld    t4, g_fx1 - g(gp)         ; ...
        bge   a0, t4, ro_s1             ; ...
        ld    t4, g_fy0 - g(gp)         ; ...
        blt   a2, t4, ro_s1             ; ...
        ld    t4, g_fy1 - g(gp)         ; ...
        bge   a2, t4, ro_s1             ; ...
        ld    t3, g_fpc - g(gp)         ; ...
ro_s1:  sw    t3, 0(t0)                 ; ...
        addi  t0, t0, 4                 ; ...
        addi  t2, t2, 2                 ; ...
        addi  a0, a0, 1                 ; ...
        addi  a1, a1, -1                ; ...
        bnez  a1, ro_c                  ; ...
        ret                             ; done

; r_overlay(a0 = cells): each cell's pixels in rowbuf half its colour from ovcol
r_overlay:
        la    t0, ovcol                 ; ...
        la    t1, rowbuf                ; ...
        ld    t2, g_cp - g(gp)          ; ...
        li    a4, 0x7f7f7f              ; ...
rv_c:   lwu   t3, 0(t0)                 ; ...
        mv    t4, t2                    ; ...
        beqz  t3, rv_k                  ; ...
        srli  t3, t3, 1                 ; ...
        and   t3, t3, a4                ; ...
rv_p:   lwu   t5, 0(t1)                 ; ...
        srli  t5, t5, 1                 ; ...
        and   t5, t5, a4                ; ...
        add   t5, t5, t3                ; ...
        sw    t5, 0(t1)                 ; ...
        addi  t1, t1, 4                 ; ...
        addi  t4, t4, -1                ; ...
        bnez  t4, rv_p                  ; ...
        j     rv_n                      ; ...
rv_k:   slli  t4, t2, 2                 ; ...
        add   t1, t1, t4                ; ...
rv_n:   addi  t0, t0, 4                 ; ...
        addi  a0, a0, -1                ; ...
        bnez  a0, rv_c                  ; ...
rv_r:   ret                             ; done

; r_mini(): the minimap at the tool column's foot: every second cell's
