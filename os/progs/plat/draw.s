        li    a0, FUNDS_X               ; ...
        li    a1, 12                    ; ...
        call  t_out                     ; ...
rx_d:   andi  t0, s4, TX_DATE           ; the date
        beqz  t0, rx_p                  ; ...
        la    s0, txtbuf                ; ...
        ld    t0, g_month - g(gp)       ; ...
        li    t1, 3                     ; ...
        mul   t0, t0, t1                ; ...
        la    t1, months                ; ...
        add   t0, t0, t1                ; ...
        lbu   t1, 0(t0)                 ; ...
        sb    t1, 0(s0)                 ; ...
        lbu   t1, 1(t0)                 ; ...
        sb    t1, 1(s0)                 ; ...
        lbu   t1, 2(t0)                 ; ...
        sb    t1, 2(s0)                 ; ...
        li    t1, ' '                   ; ...
        sb    t1, 3(s0)                 ; ...
        addi  s0, s0, 4                 ; ...
