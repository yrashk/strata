        beqz  t0, rx_g                  ; ...
        la    s0, txtbuf                ; ...
        ld    a0, g_popr - g(gp)        ; ...
        call  t_comma                   ; ...
        li    a0, POP_X                 ; ...
        li    a1, 9                     ; ...
        call  t_out                     ; ...
        andi  t0, s4, TX_TAX            ; the tax rate: "Tax 7%"
        beqz  t0, rx_g                  ; ...
        la    s0, txtbuf                ; ...
        la    t0, tx_tax                ; ...
        lbu   t1, 0(t0)                 ; ...
        sb    t1, 0(s0)                 ; ...
        lbu   t1, 1(t0)                 ; ...
        sb    t1, 1(s0)                 ; ...
        lbu   t1, 2(t0)                 ; ...
        sb    t1, 2(s0)                 ; ...
        lbu   t1, 3(t0)                 ; ...
        sb    t1, 3(s0)                 ; ...
        addi  s0, s0, 4                 ; ...
