; =============================================================================
; draw.s: Plat's window: the map, the tool column, the bar
; =============================================================================
;
; Everything is drawn as XRGB8888 rows in the D-LS (rowbuf), sent into the
; band (the arena below plat.dat's far block) with `tput` and lent to the
; server with DAMAGE, a rectangle at a time. Nothing is drawn that did not
; change (show): the whole map after a scroll or a zoom, otherwise only the
; cells a tool or the cursor changed (the rectangle g_dx0 .. g_dy1); the
; tool column when a tool is picked; the bar when the speed changes, and
; its numbers and message (drawn by the server in its font: r_text) when
; they do.
;
; The map (r_cells) is drawn a row of cells at a time, sixteen cells at a
; time: their pictures (256 bytes each) are fetched into tilebuf, and each
; of their 16 rows is turned into pixels through the palette, twice as wide
; and twice over when the cells are 32 pixels, into the band.

TOOLW    = 64                           ; the tool column's width
BARH     = 32                           ; the bar's height
MAXW     = 1280                         ; the widest bar drawn (a wider window's rest is plain)
ROWBUF   = MAXW * 4                     ; bytes of a row of pixels
TB_X0    = 4                            ; the tool buttons: the first one's corner
TB_Y0    = 6                            ; ...
TB_DX    = 30                           ; ... and from one to the next
TB_SIZE  = 28                           ; ... their size
SPD_X    = 8                            ; the bar: the speed buttons
SPD_DX   = 20                           ; ...
FUNDS_X  = 120                          ; ... the treasury's text (its icon 16 to the left)
DATE_X   = 232                          ; ... the date's
POP_X    = 328                          ; ... the population's
MSG_X    = 408                          ; ... the message's
ICON_Y   = 10                           ; ... the icons' row
TEXT_Y   = 8                            ; ... the text's
TX_FUNDS = 1                            ; the bar's texts, as bits of g_dtext: the treasury
TX_DATE  = 2                            ; ... the date
TX_POP   = 4                            ; ... the population
TX_MSG   = 8                            ; ... the message
TX_ALL   = 15                           ; ...

        .data                           ; D-LS
        .align 8                        ; dwords
rowbuf:   .space ROWBUF                 ; a row of pixels
tilebuf:  .space 16 * 256               ; sixteen cell pictures
sprbuf:   .space 160                    ; a row of a sprite
txtbuf:   .space 96                     ; a text for the bar
tl_spr:   .dword SP_TOOL_BULLDOZE, SP_TOOL_ROAD, SP_TOOL_LINE, SP_TOOL_QUERY ; the tools' icons
months:   .ascii "JanFebMarAprMayJunJulAugSepOctNovDec" ; the months' names
        .align 8                        ; ...
        .text                           ; code

; pal(a0 = palette index) -> a0 = its colour
pal:    slli  a0, a0, 2                 ; ...
        la    t0, res + R_PAL           ; ...
        add   a0, a0, t0                ; ...
        lwu   a0, 0(a0)                 ; ...
        ret                             ; done

; geom(): the window has a (new) size, or the zoom changed: how many cells
; the view holds; the window is cleared to the panel's colour and
; everything is to be drawn
geom:   addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        la    t0, wc_surf               ; ...
        ld    a2, S_W(t0)               ; a2 = width
        ld    a3, S_H(t0)               ; a3 = height
        sd    a2, g_w - g(gp)           ; ...
        sd    a3, g_h - g(gp)           ; ...
        mv    t0, a2                    ; the bar's width
        li    t1, MAXW                  ; ...
        bleu  t0, t1, ge_1              ; ...
        mv    t0, t1                    ; ...
ge_1:   sd    t0, g_bw - g(gp)          ; ...
        li    t2, 16                    ; a cell's pixels
        ld    t0, g_zoom - g(gp)        ; ...
        sll   t2, t2, t0                ; ...
        sd    t2, g_cp - g(gp)          ; ...
        li    t3, MAPN                  ; ...
        addi  t0, a2, -TOOLW            ; cells across
        bgtz  t0, ge_2                  ; ...
        li    t0, 0                     ; ...
ge_2:   divu  t0, t0, t2                ; ...
        bleu  t0, t3, ge_3              ; ...
        mv    t0, t3                    ; ...
ge_3:   sd    t0, g_vw - g(gp)          ; ...
        addi  t0, a3, -BARH             ; ... and down
        bgtz  t0, ge_4                  ; ...
        li    t0, 0                     ; ...
ge_4:   divu  t0, t0, t2                ; ...
        bleu  t0, t3, ge_5              ; ...
        mv    t0, t3                    ; ...
ge_5:   sd    t0, g_vh - g(gp)          ; ...
        li    a0, C_PANEL               ; the panel's colour everywhere
        call  pal                       ; ...
        mv    a4, a0                    ; ...
        li    a0, 0                     ; ...
        li    a1, 0                     ; ...
        call  wc_fill                   ; ...
        li    t0, 1                     ; everything is to be drawn
        sd    t0, g_dview - g(gp)       ; ...
        sd    t0, g_dtools - g(gp)      ; ...
        sd    t0, g_dbar - g(gp)        ; ...
        li    t0, TX_ALL                ; ...
        sd    t0, g_dtext - g(gp)       ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; dirty() -> a0 = something is to be drawn
dirty:  ld    a0, g_dview - g(gp)       ; ...
        ld    t0, g_dtools - g(gp)      ; ...
        or    a0, a0, t0                ; ...
        ld    t0, g_dbar - g(gp)        ; ...
        or    a0, a0, t0                ; ...
        ld    t0, g_dtext - g(gp)       ; ...
        or    a0, a0, t0                ; ...
        ld    t0, g_dx0 - g(gp)         ; ...
        ld    t1, g_dx1 - g(gp)         ; ...
        slt   t0, t0, t1                ; ...
        or    a0, a0, t0                ; ...
        ret                             ; done

; show(): draw what changed
show:   addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        ld    t0, g_dx0 - g(gp)         ; t0..t3: the changed cells, in the view
        ld    t1, g_dy0 - g(gp)         ; ...
        ld    t2, g_dx1 - g(gp)         ; ...
        ld    t3, g_dy1 - g(gp)         ; ...
        sd    zero, g_dx0 - g(gp)       ; (and no more)
        sd    zero, g_dx1 - g(gp)       ; ...
        ld    t4, g_vw - g(gp)          ; (no view: nothing of it)
        beqz  t4, sh_t                  ; ...
        ld    t4, g_vh - g(gp)          ; ...
        beqz  t4, sh_t                  ; ...
        ld    t4, g_dview - g(gp)       ; the whole view
        beqz  t4, sh_c                  ; ...
        sd    zero, g_dview - g(gp)     ; ...
        li    a0, 0                     ; ...
        li    a1, 0                     ; ...
        ld    a2, g_vw - g(gp)          ; ...
        ld    a3, g_vh - g(gp)          ; ...
        call  r_cells                   ; ...
        j     sh_t                      ; ...
sh_c:   ld    t4, g_ox - g(gp)          ; the changed cells: their part in the view
        ld    t5, g_oy - g(gp)          ; ...
        bge   t0, t4, sh_1              ; ...
        mv    t0, t4                    ; ...
sh_1:   bge   t1, t5, sh_2              ; ...
        mv    t1, t5                    ; ...
sh_2:   ld    t6, g_vw - g(gp)          ; ...
        add   t6, t6, t4                ; ...
        ble   t2, t6, sh_3              ; ...
        mv    t2, t6                    ; ...
sh_3:   ld    t6, g_vh - g(gp)          ; ...
        add   t6, t6, t5                ; ...
        ble   t3, t6, sh_4              ; ...
        mv    t3, t6                    ; ...
sh_4:   bge   t0, t2, sh_t              ; (none)
        bge   t1, t3, sh_t              ; ...
        sub   a0, t0, t4                ; ...
        sub   a1, t1, t5                ; ...
        sub   a2, t2, t0                ; ...
        sub   a3, t3, t1                ; ...
        call  r_cells                   ; ...
sh_t:   ld    t0, g_dtools - g(gp)      ; the tool column
        beqz  t0, sh_b                  ; ...
        sd    zero, g_dtools - g(gp)    ; ...
        call  r_tools                   ; ...
sh_b:   ld    t0, g_dbar - g(gp)        ; the bar (and so its text)
        beqz  t0, sh_x                  ; ...
        sd    zero, g_dbar - g(gp)      ; ...
        li    t0, TX_ALL                ; ...
        sd    t0, g_dtext - g(gp)       ; ...
        call  r_bar                     ; ...
sh_x:   ld    a0, g_dtext - g(gp)       ; the bar's text (what of it changed)
        beqz  a0, sh_r                  ; ...
        sd    zero, g_dtext - g(gp)     ; ...
        call  r_text                    ; ...
sh_r:   ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; r_damage(a0 = x, a1 = y, a2 = w, a3 = h, a4 = stride): lend the band: that
; rectangle of the window is in it, from its start
r_damage:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        twait (1 << 8) | (1 << 9)       ; our transfers are done
        la    t0, wc_d                  ; data: x, y, w, h, stride
        sd    a0, 0(t0)                 ; ...
        sd    a1, 8(t0)                 ; ...
        sd    a2, 16(t0)                ; ...
        sd    a3, 24(t0)                ; ...
        sd    a4, 32(t0)                ; ...
        mv    a0, t0                    ; ...
        li    a1, 40                    ; ...
        call  sys_put                   ; ...
        li    a0, WC_EP                 ; DAMAGE, with the arena (c0) attached
        li    a1, OP_WDAMAGE            ; ...
        la    t0, wc_id                 ; ...
        ld    a2, 0(t0)                 ; ...
        li    a3, 40                    ; ...
        li    a4, 0                     ; ...
        li    a5, 0                     ; (register 0)
        call  sys_msga                  ; a0 = result; the arena is back in c6
        cvalid t0, c6                   ; ...
        beqz  t0, rd_r                  ; (nothing was sent)
        cmov  c0, c6                    ; home
rd_r:   ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; r_cells(a0 = x, a1 = y, a2 = w, a3 = h: cells of the view): those cells,
; in as many pieces as the band needs
r_cells:
        addi  sp, sp, -112              ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the first column (of the view)
        sd    s1, 16(sp)                ; s1 = the piece's first row
        sd    s2, 24(sp)                ; s2 = columns
        sd    s3, 32(sp)                ; s3 = rows still to draw
        sd    s4, 40(sp)                ; s4 = a cell's pixels
        sd    s5, 48(sp)                ; s5 = the band's stride
        sd    s6, 56(sp)                ; s6 = rows of cells in this piece
        sd    s7, 64(sp)                ; s7 = the row in the piece
        sd    s8, 72(sp)                ; s8 = the group's first column
        sd    s9, 80(sp)                ; s9 = cells in the group
        sd    s10, 88(sp)               ; s10 = the pixel row in the cells
        sd    s11, 96(sp)               ; s11 = the map's row
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        mv    s2, a2                    ; ...
        mv    s3, a3                    ; ...
        ld    s4, g_cp - g(gp)          ; ...
        mul   s5, s2, s4                ; ...
        slli  s5, s5, 2                 ; ...
rc_p:   ld    t0, g_keepb - g(gp)       ; the piece: as many rows of cells as fit
        divu  t0, t0, s5                ; ...
        divu  s6, t0, s4                ; ...
        ble   s6, s3, rc_p1             ; ...
        mv    s6, s3                    ; ...
rc_p1:  li    s7, 0                     ; ...
rc_row: ld    s11, g_oy - g(gp)         ; a row of cells: the map's row
        add   s11, s11, s1              ; ...
        add   s11, s11, s7              ; ...
        ld    t0, g_mapb - g(gp)        ; ...
        slli  t1, s11, 8                ; ...
        add   t0, t0, t1                ; ...
        la    t1, maprow                ; ...
        li    t2, MAPN * 2              ; ...
        tget  tg8, t1, c0, t0, t2       ; ...
        twait 1 << 8                    ; ...
        li    s8, 0                     ; ...
rc_grp: sub   s9, s2, s8                ; a group: sixteen cells at most
        li    t0, 16                    ; ...
        ble   s9, t0, rc_g1             ; ...
        mv    s9, t0                    ; ...
rc_g1:  ld    t3, g_ox - g(gp)          ; t3 = the map's column of the group's first cell
        add   t3, t3, s0                ; ...
        add   t3, t3, s8                ; ...
        slli  t3, t3, 1                 ; ... as an offset in the row
        la    t4, maprow                ; ...
        add   t3, t3, t4                ; ...
        la    t4, tilebuf               ; t4 = where its picture goes
        mv    t5, s9                    ; ...
        ld    t6, g_keepb - g(gp)       ; ...
        li    a1, 256                   ; ...
rc_f:   lhu   t0, 0(t3)                 ; the cell's picture: fetch it
        slli  t0, t0, 8                 ; ...
        add   t0, t0, t6                ; ...
        tget  tg8, t4, c0, t0, a1       ; ...
        addi  t3, t3, 2                 ; ...
        addi  t4, t4, 256               ; ...
        addi  t5, t5, -1                ; ...
        bnez  t5, rc_f                  ; ...
        twait 1 << 8                    ; ...
        li    s10, 0                    ; ...
rc_ty:  mv    a0, s9                    ; a row of the pictures as pixels
        mv    a1, s10                   ; ...
        call  r_expand                  ; ...
        mv    a0, s8                    ; the cursor over them?
        mv    a1, s9                    ; ...
        mv    a2, s11                   ; ...
        mv    a3, s10                   ; ...
        add   a0, a0, s0                ; ...
        call  r_cursor                  ; ...
        ld    t0, g_zoom - g(gp)        ; into the band: the row, twice at 32 pixels a cell
        sll   t1, s10, t0               ; ...
        mul   t2, s7, s4                ; ...
        add   t1, t1, t2                ; ...
        mul   t1, t1, s5                ; ...
        mul   t2, s8, s4                ; ...
        slli  t2, t2, 2                 ; ...
        add   t1, t1, t2                ; t1 = where
        mul   t2, s9, s4                ; t2 = bytes
        slli  t2, t2, 2                 ; ...
        la    t3, rowbuf                ; ...
        tput  tg9, t3, c0, t1, t2       ; (the next row's stores wait for it)
        beqz  t0, rc_t1                 ; ...
        add   t1, t1, s5                ; ...
        tput  tg9, t3, c0, t1, t2       ; ...
rc_t1:  addi  s10, s10, 1               ; ...
        li    t0, 16                    ; ...
        blt   s10, t0, rc_ty            ; ...
        add   s8, s8, s9                ; the next group
        blt   s8, s2, rc_grp            ; ...
        addi  s7, s7, 1                 ; the next row of cells
        blt   s7, s6, rc_row            ; ...
        ld    t0, g_cp - g(gp)          ; the piece is drawn: show it
        mul   a0, s0, t0                ; ...
        addi  a0, a0, TOOLW             ; ...
        mul   a1, s1, t0                ; ...
        mul   a2, s2, t0                ; ...
        mul   a3, s6, t0                ; ...
        mv    a4, s5                    ; ...
        call  r_damage                  ; ...
        add   s1, s1, s6                ; ...
        sub   s3, s3, s6                ; ...
        bgtz  s3, rc_p                  ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        ld    s5, 48(sp)                ; ...
        ld    s6, 56(sp)                ; ...
        ld    s7, 64(sp)                ; ...
        ld    s8, 72(sp)                ; ...
        ld    s9, 80(sp)                ; ...
        ld    s10, 88(sp)               ; ...
        ld    s11, 96(sp)               ; ...
        addi  sp, sp, 112               ; pop the frame
        ret                             ; done

; r_expand(a0 = cells, a1 = pixel row): that row of the pictures in tilebuf
; as pixels in rowbuf (each pixel twice at 32 pixels a cell)
r_expand:
        la    t0, tilebuf               ; t0 = the cell's row
        slli  a1, a1, 4                 ; ...
        add   t0, t0, a1                ; ...
        la    t1, rowbuf                ; t1 = the next pixel
        la    a5, res + R_PAL           ; a5 = the palette
        ld    t6, g_zoom - g(gp)        ; ...
        bnez  t6, rx_2                  ; ...
rx_c1:  li    t2, 16                    ; 16 pixels a cell
        mv    t3, t0                    ; ...
rx_p1:  lbu   t4, 0(t3)                 ; ...
        slli  t4, t4, 2                 ; ...
        add   t4, t4, a5                ; ...
        lwu   t4, 0(t4)                 ; ...
        sw    t4, 0(t1)                 ; ...
        addi  t3, t3, 1                 ; ...
        addi  t1, t1, 4                 ; ...
        addi  t2, t2, -1                ; ...
        bnez  t2, rx_p1                 ; ...
        addi  t0, t0, 256               ; the next cell
        addi  a0, a0, -1                ; ...
        bnez  a0, rx_c1                 ; ...
        ret                             ; ...
rx_2:   li    t2, 16                    ; 32 pixels a cell: each twice
        mv    t3, t0                    ; ...
rx_p2:  lbu   t4, 0(t3)                 ; ...
        slli  t4, t4, 2                 ; ...
        add   t4, t4, a5                ; ...
        lwu   t4, 0(t4)                 ; ...
        sw    t4, 0(t1)                 ; ...
        sw    t4, 4(t1)                 ; ...
        addi  t3, t3, 1                 ; ...
        addi  t1, t1, 8                 ; ...
        addi  t2, t2, -1                ; ...
        bnez  t2, rx_p2                 ; ...
        addi  t0, t0, 256               ; the next cell
        addi  a0, a0, -1                ; ...
        bnez  a0, rx_2                  ; ...
        ret                             ; done

; r_cursor(a0 = the group's first column in the view, a1 = cells, a2 = the
; map's row, a3 = the pixel row): the keyboard's cursor, a frame two pixels
; wide round its cell (yellow; red while the pen is down), over the row in
; rowbuf if it is there
r_cursor:
        ld    t0, g_curon - g(gp)       ; ...
        beqz  t0, rk_r                  ; ...
        ld    t0, g_cury - g(gp)        ; ...
        bne   t0, a2, rk_r              ; ...
        ld    t0, g_ox - g(gp)          ; its column in the group
        add   a0, a0, t0                ; ...
        ld    t0, g_curx - g(gp)        ; ...
        sub   t0, t0, a0                ; ...
        bgeu  t0, a1, rk_r              ; ...
        ld    t1, g_cp - g(gp)          ; t2 = its first pixel in rowbuf
        mul   t2, t0, t1                ; ...
        slli  t2, t2, 2                 ; ...
        la    t3, rowbuf                ; ...
        add   t2, t2, t3                ; ...
        li    a0, C_CURSOR              ; t4 = its colour
        ld    t0, g_pen - g(gp)         ; ...
        beqz  t0, rk_c                  ; ...
        li    a0, C_PEN                 ; ...
rk_c:   slli  a0, a0, 2                 ; ...
        la    t4, res + R_PAL           ; ...
        add   a0, a0, t4                ; ...
        lwu   t4, 0(a0)                 ; ...
        ld    t5, g_zoom - g(gp)        ; t5 = its width in the pictures' rows: 2 or 1
        li    t6, 2                     ; ...
        sub   t5, t6, t5                ; ...
        blt   a3, t5, rk_full           ; the top rows and the bottom ones: across
        li    t6, 16                    ; ...
        sub   t6, t6, t5                ; ...
        bge   a3, t6, rk_full           ; ...
        sw    t4, 0(t2)                 ; between: the sides, two pixels each
        sw    t4, 4(t2)                 ; ...
        slli  t3, t1, 2                 ; ...
        add   t3, t3, t2                ; ...
        sw    t4, -4(t3)                ; ...
        sw    t4, -8(t3)                ; ...
        ret                             ; ...
rk_full:
        sw    t4, 0(t2)                 ; ...
        addi  t2, t2, 4                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, rk_full               ; ...
rk_r:   ret                             ; done

; fill_row(a0 = pixels, a1 = colour): rowbuf's first pixels are that colour
fill_row:
        la    t0, rowbuf                ; ...
fr_l:   sw    a1, 0(t0)                 ; ...
        addi  t0, t0, 4                 ; ...
        addi  a0, a0, -1                ; ...
        bnez  a0, fr_l                  ; ...
        ret                             ; done

; blit_row(a0 = sprite, a1 = its row, a2 = rowbuf's pixel x): that row of
; the sprite, over the pixels from x on (index 255 is transparent)
blit_row:
        slli  a0, a0, 3                 ; the sprite's entry
        la    t0, res + R_SPR           ; ...
        add   a0, a0, t0                ; ...
        lwu   t0, 0(a0)                 ; t0 = its far offset
        lhu   t1, 4(a0)                 ; t1 = its width
        addi  t2, t1, 7                 ; t2 = bytes a row
        andi  t2, t2, 0xfff8            ; ...
        mul   t3, a1, t2                ; the row
        add   t0, t0, t3                ; ...
        ld    t3, g_keepb - g(gp)       ; ...
        add   t0, t0, t3                ; ...
        la    t3, sprbuf                ; ...
        tget  tg8, t3, c0, t0, t2       ; ...
        twait 1 << 8                    ; ...
        la    t4, rowbuf                ; t4 = the first pixel
        slli  a2, a2, 2                 ; ...
        add   t4, t4, a2                ; ...
        la    a5, res + R_PAL           ; ...
        li    t6, 255                   ; ...
br_l:   lbu   t5, 0(t3)                 ; ...
        beq   t5, t6, br_n              ; ...
        slli  t5, t5, 2                 ; ...
        add   t5, t5, a5                ; ...
        lwu   t5, 0(t5)                 ; ...
        sw    t5, 0(t4)                 ; ...
br_n:   addi  t3, t3, 1                 ; ...
        addi  t4, t4, 4                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, br_l                  ; ...
        ret                             ; done

; tool_hit(a0 = x, a1 = y in the window) -> a0 = the tool whose button is
; there, or -1
tool_hit:
        li    t0, 0                     ; t0 = the tool
th_l:   andi  t1, t0, 1                 ; its button's corner
        li    t2, TB_DX                 ; ...
        mul   t1, t1, t2                ; ...
        addi  t1, t1, TB_X0             ; ...
        srli  t3, t0, 1                 ; ...
        mul   t3, t3, t2                ; ...
        addi  t3, t3, TB_Y0             ; ...
        sub   t1, a0, t1                ; inside it?
        sub   t3, a1, t3                ; ...
        li    t2, TB_SIZE               ; ...
        bgeu  t1, t2, th_n              ; ...
        bgeu  t3, t2, th_n              ; ...
        mv    a0, t0                    ; ...
        ret                             ; ...
th_n:   addi  t0, t0, 1                 ; ...
        li    t1, NTOOL                 ; ...
        blt   t0, t1, th_l              ; ...
        li    a0, -1                    ; ...
        ret                             ; done

; r_tools(): the tool column: the panel, a darker edge at its right, the
; buttons (the one in use pressed) with their icons
r_tools:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the row
        sd    s1, 16(sp)                ; s1 = the rows
        sd    s2, 24(sp)                ; s2 = the tool
        sd    s3, 32(sp)                ; s3 = the row in its button
        ld    s1, g_h - g(gp)           ; ...
        addi  s1, s1, -BARH             ; ...
        blez  s1, rt_r                  ; ...
        li    s0, 0                     ; ...
rt_y:   li    a0, C_PANEL               ; the panel
        call  pal                       ; ...
        mv    a1, a0                    ; ...
        li    a0, TOOLW                 ; ...
        call  fill_row                  ; ...
        li    a0, C_PANEL_DARK          ; ... its edge
        call  pal                       ; ...
        la    t0, rowbuf                ; ...
        sw    a0, 252(t0)               ; (pixel TOOLW - 1)
        li    s2, 0                     ; the buttons
rt_b:   srli  t0, s2, 1                 ; ...
        li    t1, TB_DX                 ; ...
        mul   t0, t0, t1                ; ...
        addi  t0, t0, TB_Y0             ; ...
        sub   s3, s0, t0                ; ...
        li    t1, TB_SIZE               ; ...
        bgeu  s3, t1, rt_n              ; ...
        li    a0, SP_BUTTON             ; the button, pressed for the tool in use
        ld    t0, g_tool - g(gp)        ; ...
        bne   t0, s2, rt_b1             ; ...
        li    a0, SP_BUTTON_DOWN        ; ...
rt_b1:  mv    a1, s3                    ; ...
        andi  a2, s2, 1                 ; ...
        li    t1, TB_DX                 ; ...
        mul   a2, a2, t1                ; ...
        addi  a2, a2, TB_X0             ; ...
        call  blit_row                  ; ...
        addi  a1, s3, -4                ; the icon, 20 x 20 in the middle
        li    t1, 20                    ; ...
        bgeu  a1, t1, rt_n              ; ...
        la    t0, tl_spr                ; ...
        slli  t1, s2, 3                 ; ...
        add   t0, t0, t1                ; ...
        ld    a0, 0(t0)                 ; ...
        andi  a2, s2, 1                 ; ...
        li    t1, TB_DX                 ; ...
        mul   a2, a2, t1                ; ...
        addi  a2, a2, TB_X0 + 4         ; ...
        call  blit_row                  ; ...
rt_n:   addi  s2, s2, 1                 ; ...
        li    t0, NTOOL                 ; ...
        blt   s2, t0, rt_b              ; ...
        slli  t1, s0, 8                 ; the row into the band (256 bytes a row)
        la    t0, rowbuf                ; ...
        li    t2, TOOLW * 4             ; ...
        tput  tg9, t0, c0, t1, t2       ; ...
        addi  s0, s0, 1                 ; ...
        blt   s0, s1, rt_y              ; ...
        li    a0, 0                     ; show it
        li    a1, 0                     ; ...
        li    a2, TOOLW                 ; ...
        mv    a3, s1                    ; ...
        li    a4, TOOLW * 4             ; ...
        call  r_damage                  ; ...
rt_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        addi  sp, sp, 40                ; pop the frame
        ret                             ; done

; r_bar(): the bar: a dark line and a light one at its top, the speed
; buttons (the one in use on a darker square), the icons of the treasury,
; the date and the population (their text is r_text's)
r_bar:  addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the row
        sd    s1, 16(sp)                ; s1 = the width
        sd    s2, 24(sp)                ; s2 = a speed
        ld    t0, g_h - g(gp)           ; ...
        li    t1, BARH                  ; ...
        blt   t0, t1, rb_r              ; ...
        ld    s1, g_bw - g(gp)          ; ...
        li    s0, 0                     ; ...
rb_y:   li    a0, C_PANEL               ; the row's colour
        li    t0, 1                     ; ...
        bne   s0, t0, rb_y1             ; ...
        li    a0, C_PANEL_LIGHT         ; ...
rb_y1:  bnez  s0, rb_y2                 ; ...
        li    a0, C_PANEL_DARK          ; ...
rb_y2:  call  pal                       ; ...
        mv    a1, a0                    ; ...
        mv    a0, s1                    ; ...
        call  fill_row                  ; ...
        addi  t0, s0, -7                ; the speed in use: a darker square (18 x 18)
        li    t1, 18                    ; ...
        bgeu  t0, t1, rb_s              ; ...
        li    a0, C_PANEL_DARK          ; ...
        call  pal                       ; ...
        ld    t0, g_speed - g(gp)       ; ...
        li    t1, SPD_DX                ; ...
        mul   t0, t0, t1                ; ...
        addi  t0, t0, SPD_X             ; ...
        slli  t0, t0, 2                 ; ...
        la    t1, rowbuf                ; ...
        add   t0, t0, t1                ; ...
        li    t1, 18                    ; ...
rb_sq:  sw    a0, 0(t0)                 ; ...
        addi  t0, t0, 4                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, rb_sq                 ; ...
rb_s:   addi  t0, s0, -ICON_Y           ; the icons' rows
        li    t1, 12                    ; ...
        bgeu  t0, t1, rb_put            ; ...
        li    s2, 0                     ; the speeds
rb_sp:  addi  a0, s2, SP_SPEED_PAUSE    ; ...
        addi  a1, s0, -ICON_Y           ; ...
        li    t1, SPD_DX                ; ...
        mul   a2, s2, t1                ; ...
        addi  a2, a2, SPD_X + 3         ; ...
        call  blit_row                  ; ...
        addi  s2, s2, 1                 ; ...
        li    t0, 4                     ; ...
        blt   s2, t0, rb_sp             ; ...
        li    a0, SP_ICON_FUNDS         ; the treasury, the date, the population
        addi  a1, s0, -ICON_Y           ; ...
        li    a2, FUNDS_X - 16          ; ...
        call  blit_row                  ; ...
        li    a0, SP_ICON_DATE          ; ...
        addi  a1, s0, -ICON_Y           ; ...
        li    a2, DATE_X - 16           ; ...
        call  blit_row                  ; ...
        li    a0, SP_ICON_POP           ; ...
        addi  a1, s0, -ICON_Y           ; ...
        li    a2, POP_X - 16            ; ...
        call  blit_row                  ; ...
rb_put: slli  t0, s1, 2                 ; the row into the band
        mul   t1, s0, t0                ; ...
        la    t2, rowbuf                ; ...
        tput  tg9, t2, c0, t1, t0       ; ...
        addi  s0, s0, 1                 ; ...
        li    t0, BARH                  ; ...
        blt   s0, t0, rb_y              ; ...
        li    a0, 0                     ; show it
        ld    a1, g_h - g(gp)           ; ...
        addi  a1, a1, -BARH             ; ...
        mv    a2, s1                    ; ...
        li    a3, BARH                  ; ...
        slli  a4, s1, 2                 ; ...
        call  r_damage                  ; ...
rb_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

; r_text(a0 = what changed: TX_*): the bar's text, drawn by the server in
; its font over the panel's colour: the treasury, the date, the
; population, the message
r_text: addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = where the text goes on
        sd    s1, 16(sp)                ; s1 = the text's row
        sd    s2, 24(sp)                ; s2 = the colours: text
        sd    s3, 32(sp)                ; s3 = ... panel
        sd    s4, 40(sp)                ; s4 = what changed
        mv    s4, a0                    ; ...
        ld    s1, g_h - g(gp)           ; ...
        li    t0, BARH                  ; ...
        blt   s1, t0, rx_r              ; ...
        addi  s1, s1, -BARH + TEXT_Y    ; ...
        li    a0, C_TEXT                ; ...
        call  pal                       ; ...
        mv    s2, a0                    ; ...
        li    a0, C_PANEL               ; ...
        call  pal                       ; ...
        mv    s3, a0                    ; ...
        andi  t0, s4, TX_FUNDS          ; the treasury, with commas
        beqz  t0, rx_d                  ; ...
        la    s0, txtbuf                ; ...
        ld    a0, g_funds - g(gp)       ; ...
        call  t_comma                   ; ...
        li    a0, FUNDS_X               ; ...
        li    a1, 12                    ; ...
        call  t_out                     ; ...
rx_d:   andi  t0, s4, TX_DATE           ; the date
        beqz  t0, rx_p                  ; ...
        la    s0, txtbuf                ; ...
        ld    t0, g_month - g(gp)       ; ...
        li    t1, 3                     ; ...
        mul   t0, t0, t1                ; ...
        la    t1, months                ; ...
        add   t0, t0, t1                ; ...
        lbu   t1, 0(t0)                 ; ...
        sb    t1, 0(s0)                 ; ...
        lbu   t1, 1(t0)                 ; ...
        sb    t1, 1(s0)                 ; ...
        lbu   t1, 2(t0)                 ; ...
        sb    t1, 2(s0)                 ; ...
        li    t1, ' '                   ; ...
        sb    t1, 3(s0)                 ; ...
        addi  s0, s0, 4                 ; ...
        ld    a0, g_year - g(gp)        ; ...
        call  t_num                     ; ...
        li    a0, DATE_X                ; ...
        li    a1, 10                    ; ...
        call  t_out                     ; ...
rx_p:   andi  t0, s4, TX_POP            ; the population (none yet)
        beqz  t0, rx_g                  ; ...
        la    s0, txtbuf                ; ...
        li    a0, 0                     ; ...
        call  t_comma                   ; ...
        li    a0, POP_X                 ; ...
        li    a1, 9                     ; ...
        call  t_out                     ; ...
rx_g:   andi  t0, s4, TX_MSG            ; the message
        beqz  t0, rx_r                  ; ...
        la    s0, txtbuf                ; ...
        ld    t0, g_msg - g(gp)         ; ...
        beqz  t0, rx_m                  ; ...
        ld    t1, g_msgl - g(gp)        ; ...
rx_c:   beqz  t1, rx_m                  ; ...
        lbu   t2, 0(t0)                 ; ...
        sb    t2, 0(s0)                 ; ...
        addi  t0, t0, 1                 ; ...
        addi  s0, s0, 1                 ; ...
        addi  t1, t1, -1                ; ...
        j     rx_c                      ; ...
rx_m:   ld    a1, g_bw - g(gp)          ; as long as the bar has room for
        addi  a1, a1, -MSG_X - 8        ; ...
        blez  a1, rx_r                  ; ...
        srli  a1, a1, 3                 ; ...
        li    t0, 80                    ; ...
        ble   a1, t0, rx_m1             ; ...
        mv    a1, t0                    ; ...
rx_m1:  li    a0, MSG_X                 ; ...
        call  t_out                     ; ...
rx_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        addi  sp, sp, 48                ; pop the frame
        ret                             ; done

; t_out(a0 = x, a1 = characters): txtbuf up to s0, filled with spaces to
; that many (and cut there), drawn at x on the bar's text row (s1, s2, s3)
t_out:  la    t0, txtbuf                ; ...
        add   t1, t0, a1                ; t1 = the end
        li    t2, ' '                   ; ...
to_s:   bgeu  s0, t1, to_d              ; ...
        sb    t2, 0(s0)                 ; ...
        addi  s0, s0, 1                 ; ...
        j     to_s                      ; ...
to_d:   mv    a3, a1                    ; ...
        mv    a1, s1                    ; ...
        mv    a2, t0                    ; ...
        mv    a4, s2                    ; ...
        mv    a5, s3                    ; ...
        j     wc_text                   ; ...

; t_num(a0 = number): its digits at s0
t_num:  li    t5, 0                     ; (no commas)
        j     tc_0                      ; ...
; t_comma(a0 = number): its digits, with a comma between thousands, at s0
t_comma:
        li    t5, 1                     ; ...
tc_0:   li    t1, 10                    ; ...
        li    t2, 0                     ; t2 = characters (on the stack, last first)
        li    t3, 0                     ; t3 = digits since the last comma
tc_1:   li    t4, 3                     ; ...
        bne   t3, t4, tc_2              ; ...
        beqz  t5, tc_2                  ; ...
        li    t0, ','                   ; ...
        addi  sp, sp, -8                ; ...
        sd    t0, 0(sp)                 ; ...
        addi  t2, t2, 1                 ; ...
        li    t3, 0                     ; ...
tc_2:   remu  t0, a0, t1                ; ...
        divu  a0, a0, t1                ; ...
        addi  t0, t0, '0'               ; ...
        addi  sp, sp, -8                ; ...
        sd    t0, 0(sp)                 ; ...
        addi  t2, t2, 1                 ; ...
        addi  t3, t3, 1                 ; ...
        bnez  a0, tc_1                  ; ...
tc_3:   ld    t0, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        sb    t0, 0(s0)                 ; ...
        addi  s0, s0, 1                 ; ...
        addi  t2, t2, -1                ; ...
        bnez  t2, tc_3                  ; ...
        ret                             ; done
