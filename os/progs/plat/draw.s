        sw    s2, 0(t4)                 ; ...
        beq   s0, t2, rmi_f             ; its top and bottom
        bne   s0, t3, rmi_p             ; ...
rmi_f:  slli  t4, t0, 2                 ; ...
        add   t4, t4, t5                ; ...
rmi_fl: sw    s2, 0(t4)                 ; ...
        addi  t4, t4, 4                 ; ...
        addi  t0, t0, 1                 ; ...
