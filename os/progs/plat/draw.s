        beqz  t0, rx_r                  ; ...
        la    s0, txtbuf                ; ...
        ld    t0, g_msg - g(gp)         ; ...
        beqz  t0, rx_m                  ; ...
        ld    t1, g_msgl - g(gp)        ; ...
rx_c:   beqz  t1, rx_m                  ; ...
        lbu   t2, 0(t0)                 ; ...
        sb    t2, 0(s0)                 ; ...
        addi  t0, t0, 1                 ; ...
        addi  s0, s0, 1                 ; ...
