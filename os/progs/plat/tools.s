; =============================================================================
; tools.s: Plat's tools: what each does to the cell it is used on
; =============================================================================
;
; use_tool is a code unit (u_tool): the bulldozer; roads, power lines and
; rail on land, over the water (bridges) and across one another where the
; other runs straight (crossings); zones, police and fire stations (3 x 3),
; plants (4 x 4), parks; asking what a cell is. Every change is paid for
; from the treasury first (pay); a cell's neighbours join it again
; (fix_around, put_block).

TL_RAIL  = 8                            ; tools (TL_DOZE .. TL_COAL: map.s): rail
TL_POLICE = 9                           ; ... a police station
TL_FIREST = 10                          ; ... a fire station
TL_PARK  = 11                           ; ... a park
TL_SOLAR = 12                           ; ... a solar power plant
C_RAIL   = 20                           ; what it costs: a cell of rail
C_RBRIDGE = 100                         ; ... a rail bridge
C_STATION = 500                         ; ... a police or fire station
C_PARK   = 10                           ; ... a park
C_SOLAR  = 6000                         ; ... a solar plant
DRAGGED  = (1 << TL_DOZE) | (1 << TL_ROAD) | (1 << TL_LINE) | (1 << TL_RAIL) | (1 << TL_PARK) ; tools a drag uses on every cell

        .data                           ; D-LS
msg_rx2:  .ascii "Roads cross straight tracks.\0" ; a message
msg_tx:   .ascii "Tracks cross straight roads.\0" ; a message
msg_tx2:  .ascii "Tracks cross straight lines.\0" ; a message
msg_lx2:  .ascii "Lines cross straight tracks.\0" ; a message
msg_along: .ascii "Crossings go across, not along.\0" ; a message
        .align 8                        ; ...
        .text                           ; resident code
        .far                            ; code units (paged in by the kernel)
        .align UNIT                     ; a unit
unit_tool:
u_tool:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; the far return link
        call  use_tool                  ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        xret  ra                        ; back (paged in again if it had to go)

; road_mask(a0 = a road's picture, plain or with traffic) -> a0 = its mask
road_mask:
        addi  t0, a0, -T_TLIGHT         ; ...
        li    t1, 32                    ; (the two traffic sets follow each other)
        bgeu  t0, t1, rm_0              ; ...
        andi  a0, t0, 15                ; ...
        ret                             ; ...
rm_0:   addi  a0, a0, -T_ROAD           ; ...
        ret                             ; done

; use_tool(a0 = x, a1 = y, a2 = the way it was dragged (D_EW, D_NS; -1: not
; dragged)): the tool in use, on that cell
use_tool:
        addi  sp, sp, -56               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = x
        sd    s1, 16(sp)                ; s1 = y
        sd    s2, 24(sp)                ; s2 = the way
        sd    s3, 32(sp)                ; s3 = the cell's kind
        sd    s4, 40(sp)                ; s4 = its picture
        sd    s5, 48(sp)                ; s5 = the new picture; a size
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        mv    s2, a2                    ; ...
        la    t6, m_kind                ; ...
        jalr  ra, t6, 0                 ; ...
        bltz  a0, ut_r                  ; (off the map)
        mv    s3, a0                    ; ...
        mv    s4, a1                    ; ...
        ld    t0, g_tool - g(gp)        ; the tool's code (a unit is code that moves:
        li    t1, TL_DOZE               ;   its jumps are its own, no table of them)
        beq   t0, t1, ut_doze           ; ...
        li    t1, TL_ROAD               ; ...
        beq   t0, t1, ut_road           ; ...
        li    t1, TL_LINE               ; ...
        beq   t0, t1, ut_line           ; ...
        li    t1, TL_QUERY              ; ...
        beq   t0, t1, ut_query          ; ...
        li    t1, TL_COAL               ; ...
        beq   t0, t1, ut_coal           ; ...
        li    t1, TL_RAIL               ; ...
        beq   t0, t1, ut_rail           ; ...
        li    t1, TL_POLICE             ; ...
        beq   t0, t1, ut_police         ; ...
        li    t1, TL_FIREST             ; ...
        beq   t0, t1, ut_firest         ; ...
        li    t1, TL_PARK               ; ...
        beq   t0, t1, ut_park           ; ...
        li    t1, TL_SOLAR              ; ...
        beq   t0, t1, ut_solar          ; ...
        j     ut_zone                   ; (homes, shops and offices, industry)

; ---- asking
ut_query:
        li    t0, K_ZONE                ; a zone: its kind and how built up it is
        bne   s3, t0, ut_q              ; ...
        mv    a0, s4                    ; ...
        la    t6, zone_of               ; ...
        jalr  ra, t6, 0                 ; ...
        la    t0, zn_names              ; ...
        slli  t1, a0, 3                 ; ...
        add   t0, t0, t1                ; ...
        ld    a0, 0(t0)                 ; ...
        la    t6, say                   ; ...
        jalr  ra, t6, 0                 ; ...
        j     ut_r                      ; ...
ut_q:   la    t0, kd_names              ; anything else: its kind
        slli  t1, s3, 3                 ; ...
        add   t0, t0, t1                ; ...
        ld    a0, 0(t0)                 ; ...
        la    t6, say                   ; ...
        jalr  ra, t6, 0                 ; ...
        j     ut_r                      ; ...

; ---- the bulldozer: anything built and the woods go; what was over the
; water leaves the water; a zone, a station, a plant goes whole
ut_doze:
        la    t0, dz_what               ; by kind: 0 nothing, 1 cleared, 2 water again,
        add   t0, t0, s3                ;   3 a zone or station, 4 a plant
        lbu   t0, 0(t0)                 ; ...
        beqz  t0, ut_r                  ; ...
        li    t1, 3                     ; ...
        beq   t0, t1, ut_dz3            ; ...
        li    t1, 4                     ; ...
        beq   t0, t1, ut_dz4            ; ...
        li    s5, T_DIRT                ; ...
        li    t1, 1                     ; ...
        beq   t0, t1, ut_dz1            ; ...
        mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        la    t6, water_pic             ; ...
        jalr  ra, t6, 0                 ; ...
        mv    s5, a0                    ; ...
ut_dz1: li    a0, C_DOZE                ; ...
        call  pay                       ; ...
        bnez  a0, ut_r                  ; ...
        li    a0, SN_DOZE               ; ...
        j     ut_set                    ; ...
ut_dz3: addi  t0, s4, -T_RES_EMPTY      ; 3 x 3: its cell in it (zones are 9 apart,
        li    t1, NZONEPIC * 9          ;   and so are the stations)
        bltu  t0, t1, ut_dz3a           ; ...
        addi  t0, s4, -T_POLICE         ; ...
ut_dz3a:
        li    t1, 9                     ; ...
        remu  t0, t0, t1                ; ...
        li    t1, 3                     ; ...
        remu  t2, t0, t1                ; ...
        divu  t3, t0, t1                ; ...
        sub   s0, s0, t2                ; the top left corner
        sub   s1, s1, t3                ; ...
        li    s5, 3                     ; ...
        j     ut_dzx                    ; ...
ut_dz4: li    t0, T_COAL                ; 4 x 4: coal or solar
        bltu  s4, t0, ut_r              ; ...
        li    t1, T_SOLAR               ; ...
        bltu  s4, t1, ut_dz4a           ; ...
        mv    t0, t1                    ; ...
ut_dz4a:
        sub   t0, s4, t0                ; ...
        andi  t0, t0, 15                ; ...
        andi  t1, t0, 3                 ; ...
        srli  t2, t0, 2                 ; ...
        sub   s0, s0, t1                ; ...
        sub   s1, s1, t2                ; ...
        li    s5, 4                     ; ...
ut_dzx: mul   a0, s5, s5                ; 1 a cell
        call  pay                       ; ...
        bnez  a0, ut_r                  ; ...
        li    a0, SN_DOZE               ; ...
        la    t6, snd_play              ; ...
        jalr  ra, t6, 0                 ; ...
        mv    a0, s0                    ; cleared
        mv    a1, s1                    ; ...
        mv    a2, s5                    ; ...
        li    a3, T_DIRT                ; ...
        li    a4, 0                     ; ...
        la    t6, put_block             ; ...
        jalr  ra, t6, 0                 ; ...
        j     ut_r                      ; ...

; ---- a road: on land; over the water a bridge; across a straight line or
; a straight track
ut_road:
        li    t0, K_WOODS               ; land
        bleu  s3, t0, ut_rl             ; ...
        li    t0, K_WATER               ; ...
        beq   s3, t0, ut_rw             ; ...
        li    t0, K_LINE                ; ...
        bne   s3, t0, ut_r1             ; ...
        addi  a0, s4, -T_LINE           ; across a line: the line's crossing pictures
        li    a1, T_LROAD               ;   (+0: the road east-west)
        li    a2, 0                     ; ...
        la    a3, msg_rx                ; ...
        j     ut_xr                     ; ...
ut_r1:  li    t0, K_RAIL                ; ...
        bne   s3, t0, ut_r              ; ...
        addi  a0, s4, -T_RAIL           ; across a track (+0: the road east-west)
        li    a1, T_RROAD               ; ...
        li    a2, 0                     ; ...
        la    a3, msg_rx2               ; ...
ut_xr:  la    t5, u_crossing            ; ...
        xcall ra, c0, t5                ; ...
        bnez  a0, ut_r                  ; ...
        li    a0, C_ROAD                ; ...
        j     ut_rp                     ; ...
ut_rl:  li    s5, T_ROAD                ; (its joins come with fix_around)
        li    a0, C_ROAD                ; ...
        j     ut_rp                     ; ...
ut_rw:  li    a0, 0                     ; a bridge
        li    a1, T_BRIDGE              ; ...
        la    t5, u_overwater           ; ...
        xcall ra, c0, t5                ; ...
        li    a0, C_BRIDGE              ; ...
ut_rp:  call  pay                       ; ...
        bnez  a0, ut_r                  ; ...
        li    a0, SN_BUILD              ; ...
        j     ut_set                    ; ...

; ---- a power line: on land; over the water; across a straight road or a
; straight track
ut_line:
        li    t0, K_WOODS               ; land
        bleu  s3, t0, ut_ll             ; ...
        li    t0, K_WATER               ; ...
        beq   s3, t0, ut_lw             ; ...
        li    t0, K_ROAD                ; ...
        bne   s3, t0, ut_l1             ; ...
        mv    a0, s4                    ; across a road (+0: the line north-south)
        call  road_mask                 ; ...
        li    a1, T_LROAD               ; ...
        li    a2, 1                     ; ...
        la    a3, msg_lx                ; ...
        j     ut_xl                     ; ...
ut_l1:  li    t0, K_RAIL                ; ...
        bne   s3, t0, ut_r              ; ...
        addi  a0, s4, -T_RAIL           ; across a track (+0: the line north-south)
        li    a1, T_LRAIL               ; ...
        li    a2, 1                     ; ...
        la    a3, msg_lx2               ; ...
ut_xl:  la    t5, u_crossing            ; ...
        xcall ra, c0, t5                ; ...
        bnez  a0, ut_r                  ; ...
        li    a0, C_LINE                ; ...
        j     ut_lp                     ; ...
ut_ll:  li    s5, T_LINE                ; ...
        li    a0, C_LINE                ; ...
        j     ut_lp                     ; ...
ut_lw:  li    a0, 1                     ; over the water
        li    a1, T_LWATER              ; ...
        la    t5, u_overwater           ; ...
        xcall ra, c0, t5                ; ...
        li    a0, C_LWATER              ; ...
ut_lp:  call  pay                       ; ...
        bnez  a0, ut_r                  ; ...
        li    a0, SN_WIRE               ; ...
        j     ut_set                    ; ...

; ---- rail: on land; over the water a bridge; across a straight road or a
; straight line
ut_rail:
        li    t0, K_WOODS               ; land
        bleu  s3, t0, ut_tl             ; ...
        li    t0, K_WATER               ; ...
        beq   s3, t0, ut_tw             ; ...
        li    t0, K_ROAD                ; ...
        bne   s3, t0, ut_t1             ; ...
        mv    a0, s4                    ; across a road (+0: the track north-south)
        call  road_mask                 ; ...
        li    a1, T_RROAD               ; ...
        li    a2, 1                     ; ...
        la    a3, msg_tx                ; ...
        j     ut_xt                     ; ...
ut_t1:  li    t0, K_LINE                ; ...
        bne   s3, t0, ut_r              ; ...
        addi  a0, s4, -T_LINE           ; across a line (+0: the track east-west)
        li    a1, T_LRAIL               ; ...
        li    a2, 0                     ; ...
        la    a3, msg_tx2               ; ...
ut_xt:  la    t5, u_crossing            ; ...
        xcall ra, c0, t5                ; ...
        bnez  a0, ut_r                  ; ...
        li    a0, C_RAIL                ; ...
        j     ut_tp                     ; ...
ut_tl:  li    s5, T_RAIL                ; ...
        li    a0, C_RAIL                ; ...
        j     ut_tp                     ; ...
ut_tw:  li    a0, 2                     ; a rail bridge
        li    a1, T_RBRIDGE             ; ...
        la    t5, u_overwater           ; ...
        xcall ra, c0, t5                ; ...
        li    a0, C_RBRIDGE             ; ...
ut_tp:  call  pay                       ; ...
        bnez  a0, ut_r                  ; ...
        li    a0, SN_BUILD              ; ...
        j     ut_set                    ; ...

; ---- a park: one cell of land
ut_park:
        li    t0, K_WOODS               ; ...
        bgtu  s3, t0, ut_r              ; ...
        add   s5, s0, s1                ; one design or the other
        andi  s5, s5, 1                 ; ...
        addi  s5, s5, T_PARK            ; ...
        li    a0, C_PARK                ; ...
        call  pay                       ; ...
        bnez  a0, ut_r                  ; ...
        li    a0, SN_BUILD              ; ...
        j     ut_set                    ; ...

; ---- 3 x 3 round the cell pointed at, on clear land: a zone, a station
ut_zone:
        ld    t0, g_tool - g(gp)        ; a zone: the kind's empty lot
        addi  t0, t0, -TL_RES           ; ...
        li    t1, 90                    ; ...
        mul   s4, t0, t1                ; (s4: the first picture now)
        addi  s4, s4, T_RES_EMPTY       ; ...
        li    s3, C_ZONE                ; (s3: the cost now)
        j     ut_b3                     ; ...
ut_police:
        li    s4, T_POLICE              ; ...
        li    s3, C_STATION             ; ...
        j     ut_b3                     ; ...
ut_firest:
        li    s4, T_FIREST              ; ...
        li    s3, C_STATION             ; ...
ut_b3:  addi  s0, s0, -1                ; its top left corner
        addi  s1, s1, -1                ; ...
        li    s5, 3                     ; ...
        j     ut_blk                    ; ...
; ---- 4 x 4, the cell pointed at the second of the second row: a plant
ut_coal:
        li    s4, T_COAL                ; ...
        li    s3, C_COAL                ; ...
        j     ut_b4                     ; ...
ut_solar:
        li    s4, T_SOLAR               ; ...
        li    s3, C_SOLAR               ; ...
ut_b4:  addi  s0, s0, -1                ; ...
        addi  s1, s1, -1                ; ...
        li    s5, 4                     ; ...
ut_blk: mv    a0, s0                    ; clear land?
        mv    a1, s1                    ; ...
        mv    a2, s5                    ; ...
        la    t5, u_isclear             ; ...
        xcall ra, c0, t5                ; ...
        beqz  a0, ut_nc                 ; ...
        mv    a0, s3                    ; ...
        call  pay                       ; ...
        bnez  a0, ut_r                  ; ...
        li    a0, SN_BUILD              ; ...
        la    t6, snd_play              ; ...
        jalr  ra, t6, 0                 ; ...
        mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        mv    a2, s5                    ; ...
        mv    a3, s4                    ; ...
        li    a4, 1                     ; ...
        la    t6, put_block             ; ...
        jalr  ra, t6, 0                 ; ...
        j     ut_r                      ; ...
ut_nc:  la    a0, msg_clear             ; ...
        j     ut_no                     ; ...

ut_set: la    t6, snd_play              ; the sound, the cell, its neighbours
        jalr  ra, t6, 0                 ; ...
        mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        mv    a2, s5                    ; ...
        la    t6, m_set                 ; ...
        jalr  ra, t6, 0                 ; ...
        mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        la    t6, fix_around            ; ...
        jalr  ra, t6, 0                 ; ...
        j     ut_r                      ; ...
ut_no:  la    t6, say                   ; it cannot be: the bar says why
        jalr  ra, t6, 0                 ; ...
        li    a0, SN_NOPE               ; ...
        la    t6, snd_play              ; ...
        jalr  ra, t6, 0                 ; ...
ut_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        ld    s5, 48(sp)                ; ...
        addi  sp, sp, 56                ; pop the frame
        ret                             ; done

; pay(a0 = cost) -> a0 = 0: paid; 1: the treasury has too little (the bar
; says so)
pay:    ld    t0, g_funds - g(gp)       ; ...
        bltu  t0, a0, py_no             ; ...
        sub   t0, t0, a0                ; ...
        sd    t0, g_funds - g(gp)       ; ...
        ld    t0, g_dtext - g(gp)       ; ...
        ori   t0, t0, TX_FUNDS          ; ...
        sd    t0, g_dtext - g(gp)       ; ...
        li    a0, 0                     ; ...
        ret                             ; ...
py_no:  addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        la    a0, msg_money             ; ...
        la    t6, say                   ; ...
        jalr  ra, t6, 0                 ; ...
        li    a0, SN_NOPE               ; ...
        la    t6, snd_play              ; ...
        jalr  ra, t6, 0                 ; ...
        li    a0, 1                     ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

        .org  unit_tool + UNIT          ; (a unit fits its slot: else an error here)
        .align UNIT                     ; a unit
unit_tool2:
u_crossing:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; the far return link
        call  crossing                  ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        xret  ra                        ; back (paged in again if it had to go)
u_overwater:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; the far return link
        call  over_water                ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        xret  ra                        ; back (paged in again if it had to go)
u_isclear:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; the far return link
        call  is_clear                  ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        xret  ra                        ; back (paged in again if it had to go)

; way_of(a0 = x, a1 = y, a2 = 0 roads, 1 lines, 2 rail) -> a0 = the way
; (D_EW, D_NS) a bridge or a line over the water there goes: towards a
; neighbour that joins it from the east or the west, else north-south if
; one does from there, else east-west
way_of: addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        la    t6, join_mask             ; ...
        jalr  ra, t6, 0                 ; ...
        li    t0, D_EW                  ; ...
        andi  t1, a0, 10                ; ...
        bnez  t1, wo_r                  ; ...
        andi  t1, a0, 5                 ; ...
        beqz  t1, wo_r                  ; ...
        li    t0, D_NS                  ; ...
wo_r:   mv    a0, t0                    ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; crossing(a0 = the mask of what is there, a1 = the crossing's first
; picture, a2 = 1 if in that one the new piece runs north-south, a3 = what
; is said if what is there is not straight) -> a0 = 0 and s5 = the
; picture, or 1 (said why). Uses s2 (the way it was dragged).
crossing:
        li    t0, 10                    ; what is there runs east-west: the new
        beq   a0, t0, cx_ew             ;   piece north-south
        li    t0, 5                     ; ... north-south: the new one east-west
        beq   a0, t0, cx_ns             ; ...
        mv    a0, a3                    ; neither: no
        j     cx_no                     ; ...
cx_ew:  li    t1, D_NS                  ; t1 = the new piece's way
        xori  t2, a2, 1                 ; t2 = the picture after a1
        j     cx_w                      ; ...
cx_ns:  li    t1, D_EW                  ; ...
        mv    t2, a2                    ; ...
cx_w:   bltz  s2, cx_ok                 ; dragged along what is there: no
        beq   s2, t1, cx_ok             ; ...
        la    a0, msg_along             ; ...
        j     cx_no                     ; ...
cx_ok:  add   s5, a1, t2                ; ...
        li    a0, 0                     ; ...
        ret                             ; ...
cx_no:  addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        la    t6, say                   ; ...
        jalr  ra, t6, 0                 ; ...
        li    a0, SN_NOPE               ; ...
        la    t6, snd_play              ; ...
        jalr  ra, t6, 0                 ; ...
        li    a0, 1                     ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; over_water(a0 = 0 roads, 1 lines, 2 rail, a1 = the first picture over
; the water) -> s5 = the picture for this cell: the way it was dragged (or
; of its neighbours), over the water cell that is there
over_water:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    a1, 8(sp)                 ; ...
        mv    a2, a0                    ; ...
        mv    a0, s2                    ; ...
        bgez  a0, ow_1                  ; ...
        mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        call  way_of                    ; ...
ow_1:   li    t0, NBLOB                 ; ...
        mul   s5, a0, t0                ; ...
        add   s5, s5, s4                ; ...
        addi  s5, s5, -T_WATER          ; ...
        ld    t0, 8(sp)                 ; ...
        add   s5, s5, t0                ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 16                ; pop the frame
        ret                             ; done

; is_clear(a0 = x, a1 = y, a2 = size) -> a0 = 1 if every cell of that
; square is on the map and open land, cleared land, rubble or woods
is_clear:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = x
        sd    s1, 16(sp)                ; s1 = y
        sd    s2, 24(sp)                ; s2 = size
        sd    s3, 32(sp)                ; s3 = dx
        sd    s4, 40(sp)                ; s4 = dy
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        mv    s2, a2                    ; ...
        li    s4, 0                     ; ...
ic_y:   li    s3, 0                     ; ...
ic_x:   add   a0, s0, s3                ; ...
        add   a1, s1, s4                ; ...
        la    t6, m_kind                ; ...
        jalr  ra, t6, 0                 ; ...
        bltz  a0, ic_no                 ; (off the map)
