; =============================================================================
; db.s: look into the store on the disk
; =============================================================================
;
;   db                    the store (commit, pages, free pages) and its trees:
;                         the three the meta block names (catalog, free,
;                         pending) and every tree of the catalog, as
;                         NAMESPACE/NAME, each with its root page and height
;   db TREE               the tree's records, in key order: KEY = VALUE (a
;                         value that is a stream: its length and id). TREE is
;                         catalog, free, pending, or NAMESPACE/NAME as listed
;                         (the namespace by name or by number: fs/name, 1/obj)
;   db -p PAGE            one page of a tree: its kind, level and fill, and
;                         its cells: a leaf's records, a branch's keys and the
;                         pages they lead to (so a tree can be walked by hand
;                         from its root)
;   db put NS/TREE KEY VALUE   a record into a tree of a namespace of one's
;                         own (both are made by the first put; not "fs")
;   db get NS/TREE KEY    its value
;   db del NS/TREE KEY    the record goes
;
; The disk is a store of copy-on-write B+trees (doc/strata-fs-proposal.md);
; the file system's files, names, tags and indexes are trees of namespace
; "fs" (os/servers/fs.s). This reads the disk as it was last committed,
; below the file system, with os/lib/stview.s. Bytes that do not print are
; shown as \xx. `wdb` shows the same in a window. put, get and del go to
; the file server's store calls (DBBATCH, DBGET: os/servers/fsops.s): each
; put or del is one commit.

        .data                           ; data Local Store
        .align 8                        ; aligned buffers
args:   .space 512                      ; the argument text
tname:  .dword 0                        ; the tree's name as given
tlen:   .dword 0                        ; ...
root:   .dword 0                        ; the tree at work: root,
height: .dword 0                        ;   height
want:   .dword 0                        ; the namespace asked for (-1: not a number)
nns:    .dword 0                        ; the namespaces: id, name length, name[32]
ns:     .space 16 * 48                  ; ...
count:  .dword 0                        ; records shown
m_nost: .ascii "db: the disk is not a store\n"
m_nost_e:
m_notr: .ascii "db: no such tree: "
m_notr_e:
m_nopg: .ascii "db: not a tree page: "
m_nopg_e:
m_use:  .ascii "usage: db [TREE | -p PAGE | get NS/TREE KEY | put NS/TREE KEY VALUE | del NS/TREE KEY]\n"
m_use_e:
m_p:    .ascii "-p"
m_cat:  .ascii "catalog"
m_fre:  .ascii "free"
m_pend: .ascii "pending"
m_root: .ascii "  root page "
m_root_e:
m_hgt:  .ascii ", height "
m_hgt_e:
m_recs: .ascii " records\n"
m_recs_e:
m_nsn:  .ascii "ns"
m_put:  .ascii "put"
m_get:  .ascii "get"
m_dl:   .ascii "del"
m_dbe:  .ascii "db: refused (no such record, a private namespace, or too long)\n"
m_dbe_e:
        .align 8
rq:     .space 1024                     ; a request to the store
rv:     .space 1024                     ; a value
m_ind:  .ascii "  "

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        call  sys_init                  ; handles and arguments
        call  sv_init                   ; the store
        bltz  a0, nostore               ; ...
        la    a0, args                  ; the arguments ...
        call  sys_args                  ; ... a0 = their length
        la    t0, args                  ; the first word
        add   s1, t0, a0                ; s1 = the end
        mv    a1, s1                    ; ...
        mv    a0, t0                    ; ...
        call  arg_next                  ; a0 = start, a1 = length, a2 = after it
        beqz  a1, list                  ; none: the trees
        mv    s2, a0                    ; s2, s3 = the word
        mv    s3, a1                    ; ...
        mv    s4, a2                    ; ...
        li    s5, 0                     ; put, get, del?
        la    a2, m_get                 ; ...
        li    a3, 3                     ; ...
        call  str_eq                    ; ...
        bnez  a0, kv                    ; ...
        li    s5, 1                     ; ...
        mv    a0, s2                    ; ...
        mv    a1, s3                    ; ...
        la    a2, m_put                 ; ...
        li    a3, 3                     ; ...
        call  str_eq                    ; ...
        bnez  a0, kv                    ; ...
        li    s5, 2                     ; ...
        mv    a0, s2                    ; ...
        mv    a1, s3                    ; ...
        la    a2, m_dl                  ; ...
        li    a3, 3                     ; ...
        call  str_eq                    ; ...
        bnez  a0, kv                    ; ...
        mv    a0, s2                    ; ...
        mv    a1, s3                    ; ...
        la    a2, m_p                   ; -p PAGE?
        li    a3, 2                     ; ...
        call  str_eq                    ; ...
        beqz  a0, tree                  ; ...
        mv    a0, s4                    ; ...
        mv    a1, s1                    ; ...
        call  arg_next                  ; ...
        beqz  a1, usage                 ; ...
        mv    s2, a0                    ; ...
        mv    s3, a1                    ; ...
        call  str_num                   ; ...
        bltz  a0, usage                 ; ...
        j     page                      ; ...

; ---- db get / put / del NS/TREE KEY [VALUE]: the store's calls -------------------------
; s5 = 0 get, 1 put, 2 del; s4 = after the word, s1 = the arguments' end
kv:
        mv    a0, s4                    ; NS/TREE
        mv    a1, s1                    ; ...
        call  arg_next                  ; ...
        beqz  a1, usage                 ; ...
        mv    s2, a0                    ; ...
        mv    s3, a1                    ; ...
        mv    s4, a2                    ; ...
        li    s6, 0                     ; s6 = where the "/" is
kv_sl:
        bgeu  s6, s3, usage             ; ...
        add   t0, s2, s6                ; ...
        lbu   t0, 0(t0)                 ; ...
        li    t1, '/'                   ; ...
        beq   t0, t1, kv_n              ; ...
        addi  s6, s6, 1                 ; ...
        j     kv_sl                     ; ...
kv_n:
        la    a0, rq                    ; the request: the names' lengths, the names
        li    a1, 1024                  ; ...
        call  zero_mem                  ; ...
        la    t0, rq                    ; ...
        sb    s6, 0(t0)                 ; ...
        sub   t1, s3, s6                ; ...
        addi  t1, t1, -1                ; ...
        sb    t1, 1(t0)                 ; ...
        addi  a0, t0, 8                 ; ...
        mv    a1, s2                    ; ...
        mv    a2, s6                    ; ...
        call  mem_copy                  ; ...
        add   a1, s2, s6                ; ...
        addi  a1, a1, 1                 ; ...
        sub   a2, s3, s6                ; ...
        addi  a2, a2, -1                ; ...
        call  mem_copy                  ; (a0 = after the names)
        mv    s7, a0                    ; s7 = after the names
        mv    a0, s4                    ; KEY
        mv    a1, s1                    ; ...
        call  arg_next                  ; ...
        beqz  a1, usage                 ; ...
        mv    s2, a0                    ; s2, s3 = the key
        mv    s3, a1                    ; ...
        mv    s4, a2                    ; ...
        bnez  s5, kv_item               ; ...
        la    t0, rq                    ; get: the key after the names
        sh    s3, 2(t0)                 ; ...
        mv    a0, s7                    ; ...
        mv    a1, s2                    ; ...
        mv    a2, s3                    ; ...
        call  mem_copy                  ; ...
        la    t0, rq                    ; ...
        sub   s7, a0, t0                ; ...
        mv    a0, t0                    ; ...
        mv    a1, s7                    ; ...
        call  sys_put                   ; ...
        li    a0, 2                     ; fs
        li    a1, 64                    ; DBGET
        li    a2, 0                     ; ...
        mv    a3, s7                    ; ...
        li    a4, 0                     ; ...
        call  sys_msg                   ; ...
        bltz  a0, kv_err                ; ...
        mv    s7, a0                    ; ...
        la    a0, rv                    ; ...
        mv    a1, s7                    ; ...
        call  sys_get                   ; ...
        la    a0, rv                    ; ...
        mv    a1, s7                    ; ...
        call  out_str                   ; ...
        call  out_nl                    ; ...
        j     done                      ; ...
kv_item:
        la    t0, rq                    ; put, del: one item, at a multiple of 8
        sub   s7, s7, t0                ; ...
        addi  s7, s7, 7                 ; ...
        srli  s7, s7, 3                 ; ...
        slli  s7, s7, 3                 ; ...
        add   s7, s7, t0                ; ...
        sb    s5, 0(s7)                 ; ...
        sh    s3, 2(s7)                 ; ...
        addi  a0, s7, 8                 ; ...
        mv    a1, s2                    ; ...
        mv    a2, s3                    ; ...
        call  mem_copy                  ; ...
        addi  s6, s3, 7                 ; s6 = after the key, padded
        srli  s6, s6, 3                 ; ...
        slli  s6, s6, 3                 ; ...
        add   s6, s6, s7                ; ...
        addi  s6, s6, 8                 ; ...
        li    t0, 2                     ; ...
        beq   s5, t0, kv_send           ; ...
        mv    a0, s4                    ; VALUE
        mv    a1, s1                    ; ...
        call  arg_next                  ; ...
        beqz  a1, usage                 ; ...
        sh    a1, 4(s7)                 ; ...
        mv    a2, a1                    ; ...
        mv    a1, a0                    ; ...
        mv    a0, s6                    ; ...
        addi  t0, a2, 7                 ; ...
        srli  t0, t0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        add   s6, s6, t0                ; ...
        call  mem_copy                  ; ...
kv_send:
        la    a0, rq                    ; ...
        sub   s6, s6, a0                ; ...
        mv    a1, s6                    ; ...
        call  sys_put                   ; ...
        li    a0, 2                     ; fs
        li    a1, 66                    ; DBBATCH
        li    a2, 1                     ; one item
        mv    a3, s6                    ; ...
        li    a4, 0                     ; ...
        call  sys_msg                   ; ...
        beqz  a0, done                  ; ...
kv_err:
        la    a0, m_dbe                 ; ...
        li    a1, m_dbe_e - m_dbe       ; ...
        j     fail                      ; ...

; zero_mem(a0 = address, a1 = bytes)
zero_mem:
        beqz  a1, zm_ret                ; ...
        sb    zero, 0(a0)               ; ...
        addi  a0, a0, 1                 ; ...
        addi  a1, a1, -1                ; ...
        j     zero_mem                  ; ...
zm_ret:
        ret                             ; ...

; ---- db: the store and its trees -----------------------------------------------------
list:
        call  sl_store                  ; ...
        call  line                      ; ...
        la    a0, m_cat                 ; the three the meta block names
        li    a1, 7                     ; ...
        la    a2, sv_cat                ; ...
        call  treeline                  ; ...
        la    a0, m_fre                 ; ...
        li    a1, 4                     ; ...
        la    a2, sv_fre                ; ...
        call  treeline                  ; ...
        la    a0, m_pend                ; ...
        li    a1, 7                     ; ...
        la    a2, sv_pend               ; ...
        call  treeline                  ; ...
        call  nsload                    ; the namespaces' names
        la    t0, sv_cat                ; every tree of the catalog
        ld    a0, 0(t0)                 ; ...
        ld    a1, 8(t0)                 ; ...
        call  sv_first                  ; ...
l_l:
        call  sv_next                   ; ...
        beqz  a0, done                  ; ...
        mv    s1, a0                    ; s1 = the record: key = namespace (4 bytes), name
        call  sl_new                    ; ...
        mv    a0, s1                    ; ...
        call  nsof                      ; a0 = the namespace's id
        call  nsname                    ; its name, or its number
        li    a0, '/'                   ; ...
        call  sl_ch                     ; ...
        addi  a0, s1, 12                ; ...
        lhu   a1, 0(s1)                 ; ...
        addi  a1, a1, -4                ; ...
        call  sl_str                    ; ...
        lhu   t0, 0(s1)                 ; its value: root, height
        addi  t0, t0, 7                 ; ...
        srli  t0, t0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        add   a2, s1, t0                ; ...
        addi  a2, a2, 8                 ; ...
        call  rootline                  ; ...
        j     l_l                       ; ...

; treeline(a0 = name, a1 = its length, a2 = root and height): one line
treeline:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a2, 8(sp)                 ; ...
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        call  sl_new                    ; ...
        mv    a0, s1                    ; ...
        mv    a1, s2                    ; ...
        call  sl_str                    ; ...
        ld    a2, 8(sp)                 ; ...
        call  rootline                  ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; rootline(a2 = root and height): the line so far, padded, then they; printed
rootline:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s3, 8(sp)                 ; ...
        mv    s3, a2                    ; ...
rl_pad:
        la    t0, sl_len                ; to 20 columns
        ld    t0, 0(t0)                 ; ...
        li    t1, 20                    ; ...
        bgeu  t0, t1, rl_go             ; ...
        li    a0, ' '                   ; ...
        call  sl_ch                     ; ...
        j     rl_pad                    ; ...
rl_go:
        la    a0, m_root                ; ...
        li    a1, m_root_e - m_root     ; ...
        call  sl_str                    ; ...
        ld    a0, 0(s3)                 ; ...
        call  sl_dec                    ; ...
        la    a0, m_hgt                 ; ...
        li    a1, m_hgt_e - m_hgt       ; ...
        call  sl_str                    ; ...
        ld    a0, 8(s3)                 ; ...
        call  sl_dec                    ; ...
        call  line                      ; ...
        ld    s3, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; line(): the line built, and a newline -> standard output
line:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        la    a0, sl_buf                ; ...
        la    a1, sl_len                ; ...
        ld    a1, 0(a1)                 ; ...
        call  out_str                   ; ...
        call  out_nl                    ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; nsof(a0 = a catalog record) -> a0 = its namespace: the key's first 4 bytes, big-endian
nsof:
        lbu   t0, 8(a0)                 ; ...
        slli  t0, t0, 8                 ; ...
        lbu   t1, 9(a0)                 ; ...
        or    t0, t0, t1                ; ...
        slli  t0, t0, 8                 ; ...
        lbu   t1, 10(a0)                ; ...
        or    t0, t0, t1                ; ...
        slli  t0, t0, 8                 ; ...
        lbu   t1, 11(a0)                ; ...
        or    a0, t0, t1                ; ...
        ret                             ; ...

; catfind(a0 = namespace, a1 = name, a2 = its length) -> a0 = 1 and root,
; height, or 0: the tree of that name in the catalog
catfind:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        mv    s3, a2                    ; ...
        la    t0, sv_cat                ; ...
        ld    a0, 0(t0)                 ; ...
        ld    a1, 8(t0)                 ; ...
        call  sv_first                  ; ...
cf_l:
        call  sv_next                   ; ...
        beqz  a0, cf_ret                ; (a0 = 0: not there)
        mv    s4, a0                    ; ...
        call  nsof                      ; ...
        bne   a0, s1, cf_l              ; ...
        addi  a0, s4, 12                ; ...
        lhu   a1, 0(s4)                 ; ...
        addi  a1, a1, -4                ; ...
        mv    a2, s2                    ; ...
        mv    a3, s3                    ; ...
        call  str_eq                    ; ...
        beqz  a0, cf_l                  ; ...
        lhu   t0, 0(s4)                 ; its value
        addi  t0, t0, 7                 ; ...
        srli  t0, t0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        add   t0, t0, s4                ; ...
        ld    t1, 8(t0)                 ; ...
        la    t2, root                  ; ...
        sd    t1, 0(t2)                 ; ...
        ld    t1, 16(t0)                ; ...
        la    t2, height                ; ...
        sd    t1, 0(t2)                 ; ...
        li    a0, 1                     ; ...
cf_ret:
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 40                ; ...
        ret                             ; ...

; nsload(): the namespaces (tree "ns" of namespace 0: name -> id) -> ns, nns
nsload:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        li    a0, 0                     ; ...
        la    a1, m_nsn                 ; ...
        li    a2, 2                     ; ...
        call  catfind                   ; ...
        beqz  a0, nl_ret                ; ...
        la    t0, root                  ; ...
        ld    a0, 0(t0)                 ; ...
        la    t0, height                ; ...
        ld    a1, 0(t0)                 ; ...
        call  sv_first                  ; ...
nl_l:
        call  sv_next                   ; ...
        beqz  a0, nl_ret                ; ...
        la    t0, nns                   ; room?
        ld    t1, 0(t0)                 ; ...
        li    t2, 16                    ; ...
        bgeu  t1, t2, nl_ret            ; ...
        lhu   a2, 0(a0)                 ; a name of up to 32 bytes
        li    t2, 32                    ; ...
        bgtu  a2, t2, nl_l              ; ...
        addi  t2, t1, 1                 ; ...
        sd    t2, 0(t0)                 ; ...
        li    t2, 48                    ; ...
        mul   t1, t1, t2                ; ...
        la    s1, ns                    ; ...
        add   s1, s1, t1                ; ...
        sd    a2, 8(s1)                 ; ...
        addi  t0, a2, 7                 ; its id: the value
        srli  t0, t0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        add   t0, t0, a0                ; ...
        ld    t0, 8(t0)                 ; ...
        sd    t0, 0(s1)                 ; ...
        addi  a1, a0, 8                 ; ...
        addi  a0, s1, 16                ; ...
        call  mem_copy                  ; ...
        j     nl_l                      ; ...
nl_ret:
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; mem_copy(a0 = to, a1 = from, a2 = bytes)
mem_copy:
        beqz  a2, mc_ret                ; ...
        lbu   t0, 0(a1)                 ; ...
        sb    t0, 0(a0)                 ; ...
        addi  a0, a0, 1                 ; ...
        addi  a1, a1, 1                 ; ...
        addi  a2, a2, -1                ; ...
        j     mem_copy                  ; ...
mc_ret:
        ret                             ; ...

; nsname(a0 = a namespace's id): its name, or its number -> the line
nsname:
        la    t0, ns                    ; ...
        la    t1, nns                   ; ...
        ld    t1, 0(t1)                 ; ...
nn_l:
        beqz  t1, sl_dec                ; not among them: the number
        ld    t2, 0(t0)                 ; ...
        beq   t2, a0, nn_yes            ; ...
        addi  t0, t0, 48                ; ...
        addi  t1, t1, -1                ; ...
        j     nn_l                      ; ...
nn_yes:
        addi  a0, t0, 16                ; ...
        ld    a1, 8(t0)                 ; ...
        j     sl_str                    ; ...

; ---- db TREE: its records --------------------------------------------------------------
tree:
        la    t0, tname                 ; ...
        sd    s2, 0(t0)                 ; ...
        la    t0, tlen                  ; ...
        sd    s3, 0(t0)                 ; ...
        la    s5, sv_cat                ; one of the three?
        mv    a0, s2                    ; ...
        mv    a1, s3                    ; ...
        la    a2, m_cat                 ; ...
        li    a3, 7                     ; ...
        call  str_eq                    ; ...
        bnez  a0, t_sys                 ; ...
        la    s5, sv_fre                ; ...
        mv    a0, s2                    ; ...
        mv    a1, s3                    ; ...
        la    a2, m_fre                 ; ...
        li    a3, 4                     ; ...
        call  str_eq                    ; ...
        bnez  a0, t_sys                 ; ...
        la    s5, sv_pend               ; ...
        mv    a0, s2                    ; ...
        mv    a1, s3                    ; ...
        la    a2, m_pend                ; ...
        li    a3, 7                     ; ...
        call  str_eq                    ; ...
        bnez  a0, t_sys                 ; ...
        li    s4, 0                     ; NAMESPACE/NAME: s4 = where the "/" is
t_sl:
        bgeu  s4, s3, notree            ; ...
        add   t0, s2, s4                ; ...
        lbu   t0, 0(t0)                 ; ...
        li    t1, '/'                   ; ...
        beq   t0, t1, t_ns              ; ...
        addi  s4, s4, 1                 ; ...
        j     t_sl                      ; ...
t_ns:
        call  nsload                    ; the namespace: a number, or a name
        mv    a0, s2                    ; ...
        mv    a1, s4                    ; ...
        call  str_num                   ; ...
        mv    s5, a0                    ; ...
        bgez  s5, t_find                ; ...
        la    s1, ns                    ; ...
        la    t0, nns                   ; ...
        ld    s6, 0(t0)                 ; ...
t_nl:
        beqz  s6, notree                ; ...
        addi  a0, s1, 16                ; ...
        ld    a1, 8(s1)                 ; ...
        mv    a2, s2                    ; ...
        mv    a3, s4                    ; ...
        call  str_eq                    ; ...
        bnez  a0, t_nf                  ; ...
        addi  s1, s1, 48                ; ...
        addi  s6, s6, -1                ; ...
        j     t_nl                      ; ...
t_nf:
        ld    s5, 0(s1)                 ; ...
t_find:
        mv    a0, s5                    ; ...
        add   a1, s2, s4                ; ...
        addi  a1, a1, 1                 ; ...
        sub   a2, s3, s4                ; ...
        addi  a2, a2, -1                ; ...
        call  catfind                   ; ...
        beqz  a0, notree                ; ...
        j     t_walk                    ; ...
t_sys:
        ld    t0, 0(s5)                 ; ...
        la    t1, root                  ; ...
        sd    t0, 0(t1)                 ; ...
        ld    t0, 8(s5)                 ; ...
        la    t1, height                ; ...
        sd    t0, 0(t1)                 ; ...
t_walk:
        la    t0, root                  ; ...
        ld    a0, 0(t0)                 ; ...
        la    t0, height                ; ...
        ld    a1, 0(t0)                 ; ...
        call  sv_first                  ; ...
t_l:
        call  sv_next                   ; ...
        beqz  a0, t_end                 ; ...
        mv    a1, a0                    ; ...
        la    a0, sv_buf                ; ...
        call  sl_cellat                 ; ...
        call  line                      ; ...
        la    t0, count                 ; ...
        ld    t1, 0(t0)                 ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, 0(t0)                 ; ...
        j     t_l                       ; ...
t_end:
        la    t0, count                 ; ...
        ld    a0, 0(t0)                 ; ...
        call  out_dec                   ; ...
        la    a0, m_recs                ; ...
        li    a1, m_recs_e - m_recs     ; ...
        call  out_str                   ; ...
        j     done                      ; ...

; ---- db -p PAGE: one page ----------------------------------------------------------------
page:
        mv    s1, a0                    ; s1 = the page
        la    t0, sv_npages             ; on the disk?
        ld    t0, 0(t0)                 ; ...
        bgeu  s1, t0, nopage            ; ...
        call  sv_page                   ; ...
        beqz  a0, nopage                ; ...
        mv    s4, a0                    ; s4 = its buffer
        ld    t0, 8(s4)                 ; a tree page says its own number,
        bne   t0, s1, nopage            ; ...
        lbu   t0, 24(s4)                ; and is a branch or a leaf
        addi  t0, t0, -1                ; ...
        li    t1, 2                     ; ...
        bgeu  t0, t1, nopage            ; ...
        call  sl_page                   ; ...
        call  line                      ; ...
        li    s5, 0                     ; s5 = the cell
p_l:
        lhu   t0, 26(s4)                ; ...
        bgeu  s5, t0, done              ; ...
        la    a0, m_ind                 ; ...
        li    a1, 2                     ; ...
        call  out_str                   ; ...
        mv    a0, s4                    ; ...
        mv    a1, s5                    ; ...
        call  sl_cellline               ; ...
        call  line                      ; ...
        addi  s5, s5, 1                 ; ...
        j     p_l                       ; ...

done:
        li    a0, 0                     ; exit code
        call  sys_exit                  ; flush stdout, end the process
nostore:
        la    a0, m_nost                ; ...
        li    a1, m_nost_e - m_nost     ; ...
        j     fail                      ; ...
usage:
        la    a0, m_use                 ; ...
        li    a1, m_use_e - m_use       ; ...
        call  err_str                   ; ...
        li    a0, 2                     ; ...
        call  sys_exit                  ; ...
notree:
        la    a0, m_notr                ; ...
        li    a1, m_notr_e - m_notr     ; ...
        j     failw                     ; ...
nopage:
        la    a0, m_nopg                ; ...
        li    a1, m_nopg_e - m_nopg     ; ...
failw:
        call  err_str                   ; the message, the word, a newline
        mv    a0, s2                    ; ...
        mv    a1, s3                    ; ...
        call  err_str                   ; ...
        la    a0, sys_nl                ; ...
        li    a1, 1                     ; ...
fail:
        call  err_str                   ; ...
        li    a0, 1                     ; exit code
        call  sys_exit                  ; end the process

