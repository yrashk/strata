; =============================================================================
; nav.s: a two-panel file navigator with a search across the whole disk
; =============================================================================
;
;   nav [-e EDITOR] [-s TEXT] [LEFT [RIGHT]]
;                   LEFT and RIGHT are the panels' directories (tag paths from
;                   /; default: the current one and /); -s starts with a search
;                   for TEXT; -e names the editor F4 runs (default vi)
;
; A full-screen text program, like vi: it runs on the console, in a `term`
; window and in the browser's terminal. Two panels each show a directory (a
; tag path, the set of tags its files carry): its subdirectories, then its
; files with their sizes. A search's panel adds each file's directory. Under
; the panels: a line for the search (or the command line), prompts and
; messages, and the function keys.
;
; Keys:
;   Up Down PgUp PgDn Home End   move in the panel; Tab: the other panel
;   Enter                        into a directory (a file: the viewer)
;   Backspace                    up a directory (in a search: a character less)
;   Insert, Ctrl-T               mark the file and go down (several files)
;   F1 help   F2 tag: the other panel's tags too (the file moves to the
;   directory of both)   F3 view (h: hex)   F4 edit (vi, or the -e EDITOR)
;   F5 copy to the other panel's directory (a new file)   F6 move / rename
;   F7 a new directory: a tag on the marked files   F8 delete (asks; or only
;   the directory's last tag taken away: up a level)   F9 or Ctrl-Q
;   quick view in the other panel   F10 quit.  Esc and then a digit is that
;   F-key (Esc 0: F10), for terminals without function keys.
;   Any other printable key starts a search. Ctrl-X: typing goes to a command
;   line instead (and back): Enter runs it (sh -c) in the active panel's
;   directory; Ctrl-F puts the cursor's path into it.
;
; The search. What is typed is looked for in the whole file system as it is
; typed, and the panel shows what was found, as a listing that the keys work
; on (Enter, F3, F4, F5 ...). Plain text: the file server's FIND (46), first
; the names that begin with it (one seek per directory in the index of
; names: at once), then the directories whose names hold it, then the names
; that hold it anywhere in any case (read part by part, and a key typed in
; between starts the search again). A text with "/", "=", "<" or ">" is a
; path with terms, QUERY over every file: lang=asm, size>9000, /src/ls*.
; Ranked: the exact name, then directories and files that begin with the
; text, then the others; shorter names first. The line shows how many were
; found and how long the first results and all of them took (machine time).
; Esc (or Backspace on an empty text) ends the search.
;
; Snapshots are directories at the root, @NAME, read-only.
;
; The mouse: nav asks the terminal for SGR mouse reports (ESC [ ? 1000 h,
; ESC [ ? 1006 h): a click puts the cursor on an entry (and in that panel),
; a second click on it opens it, the wheel moves, a click on the bar is that
; F-key.
;
; Far memory: what grows with the disk (the panels' entries and their order,
; the tags' names) is in an extra arena from proc (c6, the heap below), which
; nav replaces with a bigger one when it fills. The arena it is born with (c0)
; holds the part of a file the viewer shows (768 KiB from VBASE) and the
; quick view's bytes (64 KiB from QBASE).

