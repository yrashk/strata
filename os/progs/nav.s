; ---- the heap: an extra arena (c6) from proc, in areas that grow -------------------
; Everything that grows with the disk is in one extra arena that proc lends
; (MORE; it starts at 1 MiB): the panels' entries and their order, the
; sort's other half, the tags' names, the tags a listing saw. Each is an
; AREA: a base, a capacity and the bytes in use, side by side in the arena.
; When one is full, area_grow asks proc for a new arena with room for that
; one at twice its size (and what the granules round up to), copies every
; area across, and gives the old arena back (LESS). So nav takes memory as
; the listings need it, and gives none of it up until it ends (when the
; kernel frees it in any case).

; heap_init() -> a0 = 0, or -6: the first arena, the areas laid out in it
heap_init:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s0, 8(sp)                 ; ...
        li    a0, 0x100000              ; 1 MiB to begin with
        call  sys_more                  ; ...
        bltz  a0, hi_r                  ; ...
        li    a0, 0                     ; its size
        call  sys_word                  ; ...
        sd    a0, h_size(zero)          ; ...
        li    t0, 0                     ; the areas' first capacities, one after the other
        li    t1, 0                     ; ...
hi_l:   li    t2, NAREA                 ; ...
        bgeu  t0, t2, hi_d              ; ...
        slli  t3, t0, 3                 ; ...
        ld    t4, acap0(t3)             ; ...
        li    t5, 24                    ; ...
        mul   t5, t0, t5                ; ...
        sd    t1, areas(t5)             ; base
        sd    t4, areas+8(t5)           ; capacity
        sd    zero, areas+16(t5)        ; in use
        add   t1, t1, t4                ; ...
        addi  t0, t0, 1                 ; ...
        j     hi_l                      ; ...
hi_d:   li    a0, 0                     ; ...
hi_r:   ld    ra, 0(sp)                 ; ...
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; area_at(a0 = area) -> a0 = its record (base, capacity, in use)
area_at:
        li    t0, 24                    ; ...
        mul   a0, a0, t0                ; ...
        addi  a0, a0, areas             ; ...
        ret                             ; ...

; area_need(a0 = area, a1 = bytes in use wanted) -> a0 = 0 when it holds that
; many, or -6 (no memory): it grows if it must
area_need:
        li    t0, 24                    ; ...
        mul   t0, a0, t0                ; ...
        ld    t1, areas+8(t0)           ; enough already?
        bgtu  a1, t1, area_grow         ; no: grow (tail call)
        li    a0, 0                     ; ...
        ret                             ; ...

; area_grow(a0 = area, a1 = bytes it must hold) -> a0 = 0 or -6
area_grow:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s0, 8(sp)                 ; s0 = the area
        sd    s1, 16(sp)                ; s1 = its new capacity
        sd    s2, 24(sp)                ; s2 = the new arena's size
        sd    s3, 32(sp)                ; s3 = an area being copied
        sd    s4, 40(sp)                ; s4 = its new base
        mv    s0, a0                    ; ...
        call  area_at                   ; the new capacity: twice, at least what is asked
        ld    s1, 8(a0)                 ; ...
        slli  s1, s1, 1                 ; ...
        addi  a1, a1, 7                 ; ...
        srli  a1, a1, 3                 ; ...
        slli  a1, a1, 3                 ; ...
        bgeu  s1, a1, ag_1              ; ...
        mv    s1, a1                    ; ...
ag_1:   li    s2, 0                     ; the new total
        li    t0, 0                     ; ...
ag_t:   li    t1, NAREA                 ; ...
        bgeu  t0, t1, ag_m              ; ...
        li    t2, 24                    ; ...
        mul   t2, t0, t2                ; ...
        ld    t3, areas+8(t2)           ; ...
        bne   t0, s0, ag_t1             ; ...
        mv    t3, s1                    ; ...
ag_t1:  add   s2, s2, t3                ; ...
        addi  t0, t0, 1                 ; ...
        j     ag_t                      ; ...
ag_m:   cclear c7                       ; the old arena to c7 (the clock comes back later)
        cmov  c7, c6                    ; ...
        mv    a0, s2                    ; a new one from proc
        call  sys_more                  ; ...
        bltz  a0, ag_no                 ; ...
        li    a0, 0                     ; its size: what rounding gives goes to this area
        call  sys_word                  ; ...
        sd    a0, h_size(zero)          ; ...
        sub   t0, a0, s2                ; ...
        add   s1, s1, t0                ; ...
        li    s3, 0                     ; every area copied to its new place
        li    s4, 0                     ; ...
ag_c:   li    t0, NAREA                 ; ...
        bgeu  s3, t0, ag_d              ; ...
        mv    a0, s3                    ; ...
        call  area_at                   ; ...
        ld    a1, 0(a0)                 ; the old base
        ld    a2, 16(a0)                ; the bytes in use
        sd    s4, 0(a0)                 ; the new base
        bne   s3, s0, ag_c1             ; (the growing one: its new capacity)
        sd    s1, 8(a0)                 ; ...
ag_c1:  ld    t0, 8(a0)                 ; ...
        sd    t0, 32+8(sp)              ; (kept: the copy below uses t registers)
        mv    a0, s4                    ; ...
        call  heap_move                 ; c7 [a1, a1 + a2) -> c6 [a0, ...)
        mv    a0, s3                    ; ...
        call  area_at                   ; ...
        ld    t0, 8(a0)                 ; ...
        add   s4, s4, t0                ; ...
        addi  s3, s3, 1                 ; ...
        j     ag_c                      ; ...
ag_d:   li    a0, 7                     ; the old arena back to proc
        call  sys_less                  ; ...
        call  sys_clock                 ; and c7 the clock again
        li    a0, 0                     ; ...
        j     ag_r                      ; ...
ag_no:  cmov  c6, c7                    ; none: the old one stays
        call  sys_clock                 ; ...
        li    a0, -6                    ; ...
ag_r:   ld    ra, 0(sp)                 ; ...
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; ...

; heap_move(a0 = offset in the new arena (c6), a1 = offset in the old one
; (c7), a2 = bytes, whole words): copied through rowb
heap_move:
        li    t3, rowb                  ; ...
hm_l:   blez  a2, hm_r                  ; ...
        li    t4, 2048                  ; ...
        bleu  t4, a2, hm_1              ; ...
        mv    t4, a2                    ; ...
hm_1:   tget  tg1, t3, c7, a1, t4       ; ...
        twait 1 << 1                    ; ...
        tput  tg1, t3, c6, a0, t4       ; ...
        twait 1 << 1                    ; ...
        add   a0, a0, t4                ; ...
        add   a1, a1, t4                ; ...
        sub   a2, a2, t4                ; ...
        j     hm_l                      ; ...
hm_r:   ret                             ; ...

; hget(a0 = area, a1 = offset, a2 = D-LS buffer, a3 = bytes, whole words)
hget:
        li    t0, 24                    ; ...
        mul   t0, a0, t0                ; ...
        ld    t0, areas(t0)             ; ...
        add   t0, t0, a1                ; ...
        tget  tg1, a2, c6, t0, a3       ; ...
        twait 1 << 1                    ; ...
        ret                             ; ...

; hput(a0 = area, a1 = offset, a2 = D-LS buffer, a3 = bytes, whole words)
hput:
        li    t0, 24                    ; ...
        mul   t0, a0, t0                ; ...
        ld    t0, areas(t0)             ; ...
        add   t0, t0, a1                ; ...
        tput  tg1, a2, c6, t0, a3       ; ...
        twait 1 << 1                    ; ...
        ret                             ; ...

; ---- entries: in a panel's pool, in the order its index gives -------------------
; An entry: u64 size, u16 name length, u8 kind, u8 rank, u16 tags, u8 marked,
; u8 0, the name (padded to a word), the file's tag ids (u32, padded). The
; index: per entry {u64 a sort key, u64 the entry's offset in the pool}; the
; key orders most entries by itself (ent_key), the names decide the rest.

; ent_size(a0 = entry) -> a0 = its bytes
ent_size:
        lhu   t0, E_NL(a0)              ; ...
        addi  t0, t0, 7                 ; ...
        srli  t0, t0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        lhu   t1, E_NT(a0)              ; ...
        slli  t1, t1, 2                 ; ...
        addi  t1, t1, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        add   a0, t0, t1                ; ...
        addi  a0, a0, E_NAME            ; ...
        ret                             ; ...

; ent_tags(a0 = entry) -> a0 = its tag ids
ent_tags:
        lhu   t0, E_NL(a0)              ; ...
        addi  t0, t0, 7                 ; ...
        srli  t0, t0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        add   a0, a0, t0                ; ...
        addi  a0, a0, E_NAME            ; ...
        ret                             ; ...

; ent_key(a0 = entry, a1 = 1 in a search) -> a0 = its sort key: the rank, then
; (in a search) the name's length, then the name's first bytes
ent_key:
        lbu   t0, E_RANK(a0)            ; ...
        lhu   t1, E_NL(a0)              ; t1 = the length
        li    t2, 7                     ; t2 = bytes of the name in the key
        beqz  a1, ek_1                  ; ...
        slli  t0, t0, 8                 ; ...
        li    t3, 255                   ; ...
        bleu  t1, t3, ek_0              ; ...
        mv    t1, t3                    ; ...
ek_0:   or    t0, t0, t1                ; ...
        li    t2, 6                     ; ...
ek_1:   li    t3, 0                     ; ...
ek_l:   bgeu  t3, t2, ek_r              ; ...
        slli  t0, t0, 8                 ; ...
        bgeu  t3, t1, ek_n              ; ...
        add   t4, a0, t3                ; ...
        lbu   t4, E_NAME(t4)            ; ...
        or    t0, t0, t4                ; ...
ek_n:   addi  t3, t3, 1                 ; ...
        j     ek_l                      ; ...
ek_r:   mv    a0, t0                    ; ...
        ret                             ; ...

; ent_get(a0 = panel, a1 = place in the order, a2 = buffer) -> a0 = the entry's
; offset in the pool (also in e_off); the entry in the buffer
ent_get:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s0, 8(sp)                 ; s0 = the panel
        sd    s1, 16(sp)                ; s1 = the buffer
        mv    s0, a0                    ; ...
        mv    s1, a2                    ; ...
        slli  a1, a1, 4                 ; its index element
        slli  a0, s0, 1                 ; ...
        addi  a0, a0, 1                 ; ...
        li    a2, ix                    ; ...
        li    a3, 16                    ; ...
        call  hget                      ; ...
        ld    a1, ix+8(zero)            ; the entry's head
        sd    a1, e_off(zero)           ; ...
        slli  a0, s0, 1                 ; ...
        mv    a2, s1                    ; ...
        li    a3, 16                    ; ...
        call  hget                      ; ...
        mv    a0, s1                    ; the rest
        call  ent_size                  ; ...
        addi  a3, a0, -16               ; ...
        beqz  a3, eg_r                  ; ...
        slli  a0, s0, 1                 ; ...
        ld    a1, e_off(zero)           ; ...
        addi  a1, a1, 16                ; ...
        addi  a2, s1, 16                ; ...
        call  hget                      ; ...
eg_r:   ld    a0, e_off(zero)           ; ...
        ld    ra, 0(sp)                 ; ...
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; ent_at: the same as ent_get (the place in the order names an entry)
ent_at = ent_get

; ent_mark(a0 = panel, a1 = the buffer that ent_get filled last): its head
; (the mark) written back
ent_mark:
        slli  a0, a0, 1                 ; ...
        mv    a2, a1                    ; ...
        ld    a1, e_off(zero)           ; ...
        li    a3, 16                    ; ...
        j     hput                      ; (tail call)

; ent_add(a0 = panel, a1 = entry) -> a0 = 0, or -1 when there is no memory
; for it (P_MORE set)
ent_add:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s0, 8(sp)                 ; s0 = the panel
        sd    s1, 16(sp)                ; s1 = the entry
        sd    s2, 24(sp)                ; s2 = its size
        sd    s3, 32(sp)                ; s3 = the pool's record
        sd    s4, 40(sp)                ; s4 = the index's
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        mv    a0, s1                    ; ...
        call  ent_size                  ; ...
        mv    s2, a0                    ; ...
        slli  a0, s0, 1                 ; room in the pool
        call  area_at                   ; ...
        ld    a1, 16(a0)                ; ...
        add   a1, a1, s2                ; ...
        slli  a0, s0, 1                 ; ...
        call  area_need                 ; ...
        bltz  a0, ea_full               ; ...
        slli  a0, s0, 1                 ; and in the index
        addi  a0, a0, 1                 ; ...
        call  area_at                   ; ...
        ld    a1, 16(a0)                ; ...
        addi  a1, a1, 16                ; ...
        slli  a0, s0, 1                 ; ...
        addi  a0, a0, 1                 ; ...
        call  area_need                 ; ...
        bltz  a0, ea_full               ; ...
        slli  a0, s0, 1                 ; (the records again: a growth moves them)
        call  area_at                   ; ...
        mv    s3, a0                    ; ...
        slli  a0, s0, 1                 ; ...
        addi  a0, a0, 1                 ; ...
        call  area_at                   ; ...
        mv    s4, a0                    ; ...
        mv    a0, s0                    ; the key
        call  pan_addr                  ; ...
        ld    a1, P_MODE(a0)            ; ...
        snez  a1, a1                    ; ...
        mv    a0, s1                    ; ...
        call  ent_key                   ; ...
        sd    a0, ix(zero)              ; the index element: key, offset
        ld    t0, 16(s3)                ; ...
        sd    t0, ix+8(zero)            ; ...
        slli  a0, s0, 1                 ; the entry -> the pool
        ld    a1, 16(s3)                ; ...
        mv    a2, s1                    ; ...
        mv    a3, s2                    ; ...
        call  hput                      ; ...
        ld    t0, 16(s3)                ; ...
        add   t0, t0, s2                ; ...
        sd    t0, 16(s3)                ; ...
        slli  a0, s0, 1                 ; the element -> the index
        addi  a0, a0, 1                 ; ...
        ld    a1, 16(s4)                ; ...
        li    a2, ix                    ; ...
        li    a3, 16                    ; ...
        call  hput                      ; ...
        ld    t0, 16(s4)                ; ...
        addi  t0, t0, 16                ; ...
        sd    t0, 16(s4)                ; ...
        mv    a0, s0                    ; one more
        call  pan_addr                  ; ...
        ld    t0, P_N(a0)               ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, P_N(a0)               ; ...
        li    a0, 0                     ; ...
        j     ea_r                      ; ...
ea_full:
        mv    a0, s0                    ; ...
        call  pan_addr                  ; ...
        li    t0, 1                     ; ...
        sd    t0, P_MORE(a0)            ; ...
        li    a0, -1                    ; ...
ea_r:   ld    ra, 0(sp)                 ; ...
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; ...

; ent_cmpo(a0 = offset, a1 = offset) -> a0 < 0, 0, > 0: two entries of the
; panel being sorted (srt_p) in full order: the rank, (in a search) the
; length, the name's bytes
ent_cmpo:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        mv    a1, a0                    ; the first: its head and name
        ld    a0, srt_p(zero)           ; ...
        slli  a0, a0, 1                 ; ...
        li    a2, eb                    ; ...
        li    a3, 16 + 256              ; ...
        call  hget                      ; ...
        ld    a0, srt_p(zero)           ; the second
        slli  a0, a0, 1                 ; ...
        ld    a1, 16(sp)                ; ...
        li    a2, eb2                   ; ...
        li    a3, 16 + 256              ; ...
        call  hget                      ; ...
        lbu   t0, eb+E_RANK(zero)       ; ...
        lbu   t1, eb2+E_RANK(zero)      ; ...
        sub   a0, t0, t1                ; ...
        bnez  a0, eco_r                 ; ...
        lhu   t2, eb+E_NL(zero)         ; ...
        lhu   t3, eb2+E_NL(zero)        ; ...
        ld    t0, srt_s(zero)           ; a search: shorter first
        beqz  t0, eco_n                 ; ...
        sub   a0, t2, t3                ; ...
        bnez  a0, eco_r                 ; ...
eco_n:  li    t4, 0                     ; ...
eco_l:  bgeu  t4, t2, eco_e             ; ...
        bgeu  t4, t3, eco_gt            ; ...
        lbu   t5, eb+E_NAME(t4)         ; ...
        lbu   t6, eb2+E_NAME(t4)        ; ...
        sub   a0, t5, t6                ; ...
        bnez  a0, eco_r                 ; ...
        addi  t4, t4, 1                 ; ...
        j     eco_l                     ; ...
eco_e:  sub   a0, t2, t3                ; ...
        j     eco_r                     ; ...
eco_gt: li    a0, 1                     ; ...
eco_r:  ld    ra, 0(sp)                 ; ...
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; pan_sort(a0 = panel): its index sorted, a merge sort bottom up between the
; index and the sort's area (the heads of the two runs read an element at a
; time, the merged run written through mbuf)
pan_sort:
        addi  sp, sp, -96               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s0, 8(sp)                 ; s0 = the panel
        sd    s1, 16(sp)                ; s1 = entries
        sd    s2, 24(sp)                ; s2 = the run's width
        sd    s3, 32(sp)                ; s3 = the source area; 40(sp) = the other
        sd    s4, 48(sp)                ; s4, s5 = the two runs' next places
        sd    s5, 56(sp)                ; ...
        sd    s6, 64(sp)                ; s6, s7 = their ends
        sd    s7, 72(sp)                ; ...
        sd    s8, 80(sp)                ; s8 = where the merged one goes
        mv    s0, a0                    ; ...
        sd    s0, srt_p(zero)           ; ...
        call  pan_addr                  ; ...
        ld    s1, P_N(a0)               ; ...
        ld    t0, P_MODE(a0)            ; ...
        snez  t0, t0                    ; ...
        sd    t0, srt_s(zero)           ; ...
        li    t0, 2                     ; ...
        bltu  s1, t0, ps_r              ; ...
        li    a0, AR_TMP                ; the other half's room
        slli  a1, s1, 4                 ; ...
        call  area_need                 ; ...
        bltz  a0, ps_r                  ; (no memory: left as it came)
        slli  s3, s0, 1                 ; ...
        addi  s3, s3, 1                 ; ...
        li    t0, AR_TMP                ; ...
        sd    t0, 40(sp)                ; ...
        li    s2, 1                     ; ...
ps_w:   bgeu  s2, s1, ps_end            ; ...
        li    s4, 0                     ; the runs at this width
ps_run: bgeu  s4, s1, ps_sw             ; ...
        add   s6, s4, s2                ; ...
        bleu  s6, s1, ps_1              ; ...
        mv    s6, s1                    ; ...
ps_1:   mv    s5, s6                    ; ...
        add   s7, s6, s2                ; ...
        bleu  s7, s1, ps_2              ; ...
        mv    s7, s1                    ; ...
ps_2:   mv    s8, s4                    ; ...
        sd    zero, mb_n(zero)          ; ...
        sd    s8, mb_at(zero)           ; ...
        mv    a0, s4                    ; the heads
        bgeu  a0, s6, ps_h1             ; ...
        li    a1, ha                    ; ...
        call  ps_read                   ; ...
ps_h1:  mv    a0, s5                    ; ...
        bgeu  a0, s7, ps_m              ; ...
        li    a1, hb                    ; ...
        call  ps_read                   ; ...
ps_m:   bgeu  s4, s6, ps_b              ; merge
        bgeu  s5, s7, ps_a              ; ...
        ld    t0, ha(zero)              ; the keys first
        ld    t1, hb(zero)              ; ...
        bltu  t0, t1, ps_a              ; ...
        bltu  t1, t0, ps_b              ; ...
        ld    a0, ha+8(zero)            ; the same key: the names
        ld    a1, hb+8(zero)            ; ...
        call  ent_cmpo                  ; ...
        bgtz  a0, ps_b                  ; ...
ps_a:   li    a0, ha                    ; from the first run
        call  ps_out                    ; ...
        addi  s4, s4, 1                 ; ...
        bgeu  s4, s6, ps_m              ; ...
        mv    a0, s4                    ; ...
        li    a1, ha                    ; ...
        call  ps_read                   ; ...
        j     ps_m                      ; ...
ps_b:   bgeu  s5, s7, ps_nx             ; from the second
        li    a0, hb                    ; ...
        call  ps_out                    ; ...
        addi  s5, s5, 1                 ; ...
        bgeu  s5, s7, ps_m              ; ...
        mv    a0, s5                    ; ...
        li    a1, hb                    ; ...
        call  ps_read                   ; ...
        j     ps_m                      ; ...
ps_nx:  call  ps_flush                  ; the merged run is out
        mv    s4, s7                    ; the next pair of runs
        j     ps_run                    ; ...
ps_sw:  ld    t0, 40(sp)                ; the other way round now
        sd    s3, 40(sp)                ; ...
        mv    s3, t0                    ; ...
        slli  s2, s2, 1                 ; ...
        j     ps_w                      ; ...
ps_end: li    t0, AR_TMP                ; the result in the sort's area: back
        bne   s3, t0, ps_r              ; ...
        li    s4, 0                     ; ...
        slli  s5, s1, 4                 ; ...
ps_cb:  bgeu  s4, s5, ps_r              ; ...
        sub   s6, s5, s4                ; ...
        li    t0, 1024                  ; ...
        bleu  s6, t0, ps_cb1            ; ...
        mv    s6, t0                    ; ...
ps_cb1: li    a0, AR_TMP                ; ...
        mv    a1, s4                    ; ...
        li    a2, mbuf                  ; ...
        mv    a3, s6                    ; ...
        call  hget                      ; ...
        ld    a0, 40(sp)                ; ...
        mv    a1, s4                    ; ...
        li    a2, mbuf                  ; ...
        mv    a3, s6                    ; ...
        call  hput                      ; ...
        add   s4, s4, s6                ; ...
        j     ps_cb                     ; ...
ps_r:   ld    ra, 0(sp)                 ; ...
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 48(sp)                ; ...
        ld    s5, 56(sp)                ; ...
        ld    s6, 64(sp)                ; ...
        ld    s7, 72(sp)                ; ...
        ld    s8, 80(sp)                ; ...
        addi  sp, sp, 96                ; ...
        ret                             ; ...
; ps_read(a0 = place, a1 = head): an element of the source (s3) into the head
ps_read:
        slli  a2, a0, 4                 ; ...
        mv    t0, a1                    ; ...
        mv    a1, a2                    ; ...
        mv    a2, t0                    ; ...
        mv    a0, s3                    ; ...
        li    a3, 16                    ; ...
        j     hget                      ; (tail call)
; ps_out(a0 = head): it goes to mbuf, which is written out when full
ps_out:
        ld    t0, mb_n(zero)            ; ...
        slli  t1, t0, 4                 ; ...
        ld    t2, 0(a0)                 ; ...
        sd    t2, mbuf(t1)              ; ...
        ld    t2, 8(a0)                 ; ...
        sd    t2, mbuf+8(t1)            ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, mb_n(zero)            ; ...
        li    t1, 64                    ; ...
        bltu  t0, t1, po_r              ; ...
        j     ps_flush                  ; (tail call)
po_r:   ret                             ; ...
; ps_flush(): mbuf -> the destination (40(sp) of pan_sort: dst_a) at mb_at
ps_flush:
        ld    a3, mb_n(zero)            ; ...
        beqz  a3, pf_r                  ; ...
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        ld    a0, 8+40(sp)              ; (pan_sort's frame is right above ours)
        ld    a1, mb_at(zero)           ; ...
        slli  a1, a1, 4                 ; ...
        li    a2, mbuf                  ; ...
        slli  a3, a3, 4                 ; ...
        call  hput                      ; ...
        ld    t0, mb_n(zero)            ; ...
        ld    t1, mb_at(zero)           ; ...
        add   t1, t1, t0                ; ...
        sd    t1, mb_at(zero)           ; ...
        sd    zero, mb_n(zero)          ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
pf_r:   ret                             ; ...

; =============================================================================
; The tags' names; a directory's listing
; =============================================================================

; tags_load(): every tag's name, by id (TAGS2): AR_TOFF holds per id the
; offset of its name in AR_TNAM ({u8 length, the name}, padded to a word;
; 0: no such tag)
tags_load:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s0, 8(sp)                 ; s0 = the cursor
        sd    s1, 16(sp)                ; s1 = a record
        sd    s2, 24(sp)                ; s2 = records left
        sd    s3, 32(sp)                ; s3 = its id
        li    a0, AR_TOFF               ; empty: no ids; names from offset 8
        call  area_at                   ; ...
        sd    zero, 16(a0)              ; ...
        li    a0, AR_TNAM               ; ...
        call  area_at                   ; ...
        li    t0, 8                     ; ...
        sd    t0, 16(a0)                ; ...
        sd    zero, tmax(zero)          ; ...
        li    s0, 0                     ; ...
tl_p:   li    a0, lbuf                  ; a part
        li    a1, 0                     ; ...
        li    a2, 0                     ; ...
        mv    a3, s0                    ; ...
        call  sys_tags2                 ; a0 = tags, a1 = the next cursor
        blez  a0, tl_r                  ; ...
        mv    s2, a0                    ; ...
        mv    s0, a1                    ; ...
        li    s1, lbuf                  ; ...
tl_rec: beqz  s2, tl_nx                 ; ...
        lwu   s3, 4(s1)                 ; its id
        ld    t0, tmax(zero)            ; ids up to it: offsets (0 for ids not seen)
        addi  t1, s3, 1                 ; ...
        bleu  t1, t0, tl_m              ; ...
        sd    t1, tmax(zero)            ; ...
        slli  a1, t1, 3                 ; ...
        li    a0, AR_TOFF               ; ...
        call  area_need                 ; ...
        bltz  a0, tl_r                  ; ...
tl_z:   li    a0, AR_TOFF               ; (zeros up to it)
        call  area_at                   ; ...
        ld    a1, 16(a0)                ; ...
        ld    t1, tmax(zero)            ; ...
        slli  t1, t1, 3                 ; ...
        bgeu  a1, t1, tl_m              ; ...
        addi  t2, a1, 8                 ; ...
        sd    t2, 16(a0)                ; ...
        sd    zero, ix(zero)            ; ...
        li    a0, AR_TOFF               ; ...
        li    a2, ix                    ; ...
        li    a3, 8                     ; ...
        call  hput                      ; ...
        j     tl_z                      ; ...
tl_m:   lhu   t1, 2(s1)                 ; its name: {length, the name} at the end of AR_TNAM
        sb    t1, tnm(zero)             ; ...
        li    a0, tnm+1                 ; ...
        addi  a1, s1, 16                ; ...
        mv    a2, t1                    ; ...
        call  bcopy                     ; ...
        li    a0, AR_TNAM               ; ...
        call  area_at                   ; ...
        ld    a1, 16(a0)                ; ...
        lbu   t1, tnm(zero)             ; ...
