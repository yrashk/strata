; bcopy(a0 = destination, a1 = source, a2 = bytes) -> a0 = past the destination
bcopy:
        beqz  a2, bc_r                  ; ...
        lbu   t0, 0(a1)                 ; ...
        sb    t0, 0(a0)                 ; ...
        addi  a0, a0, 1                 ; ...
        addi  a1, a1, 1                 ; ...
        addi  a2, a2, -1                ; ...
        j     bcopy                     ; ...
bc_r:   ret                             ; ...

; bzero(a0 = address, a1 = bytes)
bzero:
        beqz  a1, bz_r                  ; ...
        sb    zero, 0(a0)               ; ...
        addi  a0, a0, 1                 ; ...
        addi  a1, a1, -1                ; ...
        j     bzero                     ; ...
bz_r:   ret                             ; ...

; has_ci(a0 = text, a1 = length, a2 = pattern, a3 = its length) -> a0 = where
; the pattern is in the text, in any case (ASCII), or -1
