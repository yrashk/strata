        addi  t0, t0, 1                 ; ...
        sd    t0, errn(zero)            ; ...
        sd    a0, opc_last(zero)        ; ...
        ret                             ; ...
ops_end:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        li    a0, m_done                ; "done: N, failed: M (code)"
        li    a1, m_done_e - m_done     ; ...
        call  msg_set                   ; ...
        ld    a0, okn(zero)             ; ...
        call  msg_num                   ; ...
        ld    t0, errn(zero)            ; ...
        beqz  t0, ope_1                 ; ...
        li    a0, m_comma               ; ...
        li    a1, 2                     ; ...
        call  msg_add                   ; ...
        li    a0, m_fail                ; ...
        li    a1, m_fail_e - m_fail     ; ...
        call  msg_add                   ; ...
        ld    a0, errn(zero)            ; ...
        call  msg_num                   ; ...
        li    a0, m_paren               ; ...
        li    a1, 2                     ; ...
        call  msg_add                   ; ...
        ld    t0, opc_last(zero)        ; why, as the file server says it
        neg   t0, t0                    ; ...
        li    t1, 7                     ; ...
        bltu  t0, t1, ope_w             ; ...
        li    t0, 0                     ; ...
ope_w:  li    t1, 24                    ; ...
        mul   t0, t0, t1                ; ...
        addi  a0, t0, m_why             ; ...
        sd    a0, opc_last(zero)        ; (its text, kept over str_len)
        li    a1, 24                    ; ...
        call  str_len                   ; ...
        mv    a1, a0                    ; ...
        ld    a0, opc_last(zero)        ; ...
        call  msg_add                   ; ...
        li    a0, m_paren+3             ; ...
        li    a1, 1                     ; ...
        call  msg_add                   ; ...
