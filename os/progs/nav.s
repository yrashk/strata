; seen_set(a0 = tag id): it was seen
seen_set:
        li    t0, TBMD                  ; in the D-LS
        bgeu  a0, t0, ss2_far           ; ...
        srli  t1, a0, 3                 ; ...
        lbu   t2, tbm(t1)               ; ...
        andi  t3, a0, 7                 ; ...
        li    t4, 1                     ; ...
        sll   t4, t4, t3                ; ...
        or    t2, t2, t4                ; ...
        sb    t2, tbm(t1)               ; ...
        ret                             ; ...
ss2_far:
        ld    t0, tmax(zero)            ; (ids not in the table: not kept)
        bgeu  a0, t0, ss2_r             ; ...
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        srli  a1, a0, 6                 ; its word
        slli  a1, a1, 3                 ; ...
        li    a0, AR_TBM                ; ...
        li    a2, ix                    ; ...
        li    a3, 8                     ; ...
        call  hget                      ; ...
        ld    t0, 8(sp)                 ; ...
        andi  t0, t0, 63                ; ...
        li    t1, 1                     ; ...
        sll   t1, t1, t0                ; ...
        ld    t2, ix(zero)              ; ...
        or    t2, t2, t1                ; ...
        sd    t2, ix(zero)              ; ...
        ld    a1, 8(sp)                 ; ...
        srli  a1, a1, 6                 ; ...
        slli  a1, a1, 3                 ; ...
        li    a0, AR_TBM                ; ...
        li    a2, ix                    ; ...
        li    a3, 8                     ; ...
        call  hput                      ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
ss2_r:  ret                             ; ...

