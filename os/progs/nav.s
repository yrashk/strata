        lbu   t2, 0(t2)                 ; ...
        addi  t1, t2, -65               ; ...
        sltiu t1, t1, 26                ; ...
        slli  t1, t1, 5                 ; ...
        or    t2, t2, t1                ; ...
        bne   t0, t2, hc_n              ; ...
        addi  t4, t4, 1                 ; ...
        j     hc_c                      ; ...
hc_n:   addi  t5, t5, 1                 ; ...
        j     hc_p                      ; ...
hc_y:   mv    a0, t5                    ; ...
        ret                             ; ...
hc_no:  li    a0, -1                    ; ...
