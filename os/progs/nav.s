        li    a1, E_NAME                ; ...
        call  bzero                     ; ...
        li    t0, K_SNAP                ; ...
        sb    t0, ec+E_KIND(zero)       ; ...
        li    t0, 2                     ; ...
        sb    t0, ec+E_RANK(zero)       ; ...
        li    t0, '@'                   ; ...
        sb    t0, ec+E_NAME(zero)       ; ...
        addi  a0, s2, 8                 ; ...
        li    a1, 32                    ; ...
        call  str_len                   ; ...
        addi  t0, a0, 1                 ; ...
        sh    t0, ec+E_NL(zero)         ; ...
        mv    a2, a0                    ; ...
        addi  a1, s2, 8                 ; ...
        li    a0, ec+E_NAME+1           ; ...
        call  bcopy                     ; ...
        mv    a0, s0                    ; ...
        li    a1, ec                    ; ...
        call  ent_add                   ; ...
        addi  s2, s2, 40                ; ...
        addi  s1, s1, -1                ; ...
        j     psn_l                     ; ...
psn_r:  ld    ra, 0(sp)                 ; ...
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

