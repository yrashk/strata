; run_cmd(a0 = the command's length, in pth2): run it with our standard
; handles and wait for it; the screen is ours again afterwards
run_cmd:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s0, 8(sp)                 ; ...
        sd    s1, 16(sp)                ; ...
        mv    s1, a0                    ; ...
        call  bye                       ; the terminal as a program finds it
        li    a0, 0                     ; time-shared
        li    a1, 0                     ; ...
        li    a2, pth2                  ; ...
        mv    a3, s1                    ; ...
        li    a4, 0                     ; our handles
        li    a5, 1                     ; ...
        li    a6, 2                     ; ...
        call  sys_spawn                 ; a0 = pid
        mv    s0, a0                    ; ...
        blez  s0, rcm_no                 ; ...
        ld    t0, con(zero)             ; Ctrl-C goes to it
        beqz  t0, rcm_w                  ; ...
        mv    a0, s0                    ; ...
        call  sys_setfg                 ; ...
rcm_w:  mv    a0, s0                    ; ...
        li    a1, 0                     ; ...
        call  sys_wait                  ; ...
        li    t0, -2                    ; (interrupted: wait on)
        beq   a0, t0, rcm_w             ; ...
        ld    t0, rc_pause(zero)        ; a command line's: its output stays until a key
        beqz  t0, rcm_p                 ; ...
        call  raw_on                    ; ...
        li    a0, t_pause               ; ...
        li    a1, t_pause_e - t_pause   ; ...
        call  out_str                   ; ...
        call  out_flush                 ; ...
        call  getkey                    ; ...
rcm_p:
        ld    t0, con(zero)             ; ...
        beqz  t0, rcm_ok                 ; ...
        call  sys_pid                   ; ...
        call  sys_setfg                 ; ...
        j     rcm_ok                     ; ...
rcm_no:  li    a0, m_cant                ; ...
        li    a1, m_cant_e - m_cant     ; ...
        call  msg_set                   ; ...
        li    a0, pth2                  ; ...
        mv    a1, s1                    ; ...
        call  msg_add                   ; ...
rcm_ok:  call  raw_on                    ; ours again
        li    a0, s_mon                 ; ...
        li    a1, 16                    ; ...
        call  out_str                   ; ...
        li    t0, 1                     ; ...
        sd    t0, clear(zero)           ; ...
        ld    ra, 0(sp)                 ; ...
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

