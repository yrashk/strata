        call  rb_col10                  ; ...
        li    a0, ' '                   ; ...
        call  rb_chr                    ; ...
        li    a0, ec+E_NAME             ; ...
        lhu   a1, ec+E_NL(zero)         ; ...
        li    a2, 30                    ; ...
        call  rb_fit                    ; ...
        li    a0, ' '                   ; ...
        call  rb_chr                    ; ...
        ld    a0, v_top(zero)           ; ...
        call  num_txt                   ; ...
        call  rb_rawc                   ; ...
        li    a0, '/'                   ; ...
        call  rb_chr                    ; ...
        ld    a0, v_size(zero)          ; ...
        call  num_txt                   ; ...
        call  rb_rawc                   ; ...
        ld    t0, v_full(zero)          ; ...
        beqz  t0, vw_s1                 ; ...
        li    a0, '+'                   ; ...
        call  rb_chr                    ; ...
vw_s1:  li    a0, v_hint                ; ...
        li    a1, v_hint_e - v_hint     ; ...
        ld    t0, v_hex(zero)           ; ...
        beqz  t0, vw_s2                 ; ...
