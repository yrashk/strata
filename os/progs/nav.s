; run_line(): the command line runs (sh -c) in the active panel's directory;
; its output is on the screen until a key; then everything is listed again
run_line:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        call  run_dir                   ; nav's current directory: the panel's (the
        li    a2, cwdbuf                ;   command's starts as ours)
        call  sys_chdir                 ; ...
        li    a0, pth2                  ; "sh -c " and the text
        li    a1, w_shc                 ; ...
        li    a2, 6                     ; ...
        call  bcopy                     ; ...
        li    a0, pth2+6                ; ...
        li    a1, ctext                 ; ...
        ld    a2, c_len(zero)           ; ...
        call  bcopy                     ; ...
        li    t0, 1                     ; ...
        sd    t0, rc_pause(zero)        ; ...
        ld    a0, c_len(zero)           ; ...
        addi  a0, a0, 6                 ; ...
        call  run_cmd                   ; ...
        sd    zero, rc_pause(zero)      ; ...
        sd    zero, c_len(zero)         ; ...
        call  reload                    ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

