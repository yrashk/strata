; rb_raw(a0 = bytes, a1 = length): into the row, taking no columns
rb_raw:
        ld    t0, rbp(zero)             ; ...
        li    t1, 0                     ; ...
rr_l:   bgeu  t1, a1, rr_r              ; ...
        add   t2, a0, t1                ; ...
        lbu   t2, 0(t2)                 ; ...
        add   t3, t0, t1                ; ...
        sb    t2, rowb(t3)              ; ...
        addi  t1, t1, 1                 ; ...
        j     rr_l                      ; ...
rr_r:   add   t0, t0, a1                ; ...
        sd    t0, rbp(zero)             ; ...
        ret                             ; ...

; rb_col(a0 = colour: an SGR string of 10 bytes, or 4 for c_off etc.)
rb_col10:
        li    a1, 10                    ; ...
        j     rb_raw                    ; (tail call)
rb_col4:
        li    a1, 4                     ; ...
        j     rb_raw                    ; (tail call)

; rb_chr(a0 = character): one column (a control byte shows as "?")
rb_chr:
        addi  t0, a0, -32               ; ...
        li    t1, 95                    ; ...
        bltu  t0, t1, rc_ok             ; ...
        li    a0, '?'                   ; ...
rc_ok:  ld    t0, rbp(zero)             ; ...
        sb    a0, rowb(t0)              ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, rbp(zero)             ; ...
        ld    t0, rbc(zero)             ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, rbc(zero)             ; ...
        ret                             ; ...

; rb_pad(a0 = count): spaces
rb_pad:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s0, 8(sp)                 ; ...
        mv    s0, a0                    ; ...
rp_l:   blez  s0, rp_r                  ; ...
        li    a0, ' '                   ; ...
        call  rb_chr                    ; ...
        addi  s0, s0, -1                ; ...
        j     rp_l                      ; ...
rp_r:   ld    ra, 0(sp)                 ; ...
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; rb_fit(a0 = text, a1 = length, a2 = width): the text in exactly that many
; columns: padded, or cut with "~" in the last one
rb_fit:
        addi  sp, sp, -48               ; frame
        sd    a1, 40(sp)                ; the text's length
        sd    ra, 0(sp)                 ; ...
        sd    s0, 8(sp)                 ; ...
        sd    s1, 16(sp)                ; ...
        sd    s2, 24(sp)                ; ...
        sd    s3, 32(sp)                ; ...
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        mv    s2, a2                    ; ...
        blez  s2, rf_r                  ; ...
        li    s3, 0                     ; ...
        bleu  s1, s2, rf_l              ; too long: width - 1 bytes and "~"
        addi  s1, s2, -1                ; ...
rf_l:   bgeu  s3, s1, rf_e              ; ...
        add   t0, s0, s3                ; ...
        lbu   a0, 0(t0)                 ; ...
        call  rb_chr                    ; ...
        addi  s3, s3, 1                 ; ...
        j     rf_l                      ; ...
rf_e:   bgeu  s3, s2, rf_r              ; ...
        sub   a0, s2, s3                ; the rest
        ld    t1, 40(sp)                ; (cut: "~")
        bleu  t1, s2, rf_p              ; ...
        li    a0, '~'                   ; ...
        call  rb_chr                    ; ...
        j     rf_r                      ; ...
rf_p:   call  rb_pad                    ; ...
rf_r:   ld    ra, 0(sp)                 ; ...
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; ...

; num_txt(a0 = value) -> a0 = its digits (in numb), a1 = how many
num_txt:
        li    t0, numb + 24             ; right to left
        li    t1, 10                    ; ...
nt_l:   remu  t2, a0, t1                ; ...
        divu  a0, a0, t1                ; ...
        addi  t2, t2, '0'               ; ...
        addi  t0, t0, -1                ; ...
        sb    t2, 0(t0)                 ; ...
        bnez  a0, nt_l                  ; ...
        mv    a0, t0                    ; ...
        li    t1, numb + 24             ; ...
        sub   a1, t1, t0                ; ...
        ret                             ; ...

; rb_num(a0 = value, a1 = width): right-aligned; a size too wide for it in K
; or M
rb_num:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s0, 8(sp)                 ; ...
        sd    s1, 16(sp)                ; ...
        sd    s2, 24(sp)                ; ...
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        li    s2, 0                     ; s2 = the unit
        call  num_txt                   ; ...
        bleu  a1, s1, rn_w              ; ...
        srli  s0, s0, 10                ; K
        li    s2, 'K'                   ; ...
        mv    a0, s0                    ; ...
        call  num_txt                   ; ...
        addi  t0, s1, -1                ; ...
        bleu  a1, t0, rn_w              ; ...
        srli  s0, s0, 10                ; M
        li    s2, 'M'                   ; ...
        mv    a0, s0                    ; ...
        call  num_txt                   ; ...
rn_w:   sd    a0, numb+24(zero)         ; (keep the digits' place)
        sub   a0, s1, a1                ; the padding
        snez  t0, s2                    ; ...
        sub   a0, a0, t0                ; ...
        mv    s0, a1                    ; ...
        call  rb_pad                    ; ...
        ld    a0, numb+24(zero)         ; ...
        mv    a1, s0                    ; ...
        call  rb_rawc                   ; ...
        beqz  s2, rn_r                  ; ...
        mv    a0, s2                    ; ...
        call  rb_chr                    ; ...
rn_r:   ld    ra, 0(sp)                 ; ...
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; rb_rawc(a0 = text, a1 = length): printable text, a column a byte
rb_rawc:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s0, 8(sp)                 ; ...
        sd    s1, 16(sp)                ; ...
        mv    s0, a0                    ; ...
        add   s1, a0, a1                ; ...
rw2_l:  bgeu  s0, s1, rw2_r             ; ...
        lbu   a0, 0(s0)                 ; ...
        call  rb_chr                    ; ...
        addi  s0, s0, 1                 ; ...
        j     rw2_l                     ; ...
rw2_r:  ld    ra, 0(sp)                 ; ...
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; rb_ms(a0 = ticks): milliseconds with one decimal
rb_ms:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        li    t0, 1000                  ; ...
        divu  a0, a0, t0                ; ...
        call  num_txt                   ; ...
        call  rb_rawc                   ; ...
        li    a0, '.'                   ; ...
        call  rb_chr                    ; ...
        ld    a0, 8(sp)                 ; ...
        li    t0, 1000                  ; ...
        remu  a0, a0, t0                ; ...
        li    t0, 100                   ; ...
        divu  a0, a0, t0                ; ...
        addi  a0, a0, '0'               ; ...
        call  rb_chr                    ; ...
        li    a0, t_ms                  ; ...
        li    a1, 3                     ; ...
        call  rb_rawc                   ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; rb_out(a0 = row): the row built is sent if it differs from what is there
; (a hash of its bytes); the row is then empty again
rb_out:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s0, 8(sp)                 ; ...
        sd    s1, 16(sp)                ; ...
        mv    s0, a0                    ; ...
        li    t0, 0                     ; FNV-1a over the bytes
        li    s1, 0xCBF29CE484222325    ; ...
        li    t2, 0x100000001B3         ; ...
        ld    t1, rbp(zero)             ; ...
rbo_l:   bgeu  t0, t1, rbo_h              ; ...
        lbu   t3, rowb(t0)              ; ...
        xor   s1, s1, t3                ; ...
        mul   s1, s1, t2                ; ...
        addi  t0, t0, 1                 ; ...
        j     rbo_l                      ; ...
rbo_h:   slli  t0, s0, 3                 ; the same as before?
        ld    t1, rowh(t0)              ; ...
        sd    s1, rowh(t0)              ; ...
        beq   t1, s1, rbo_r              ; ...
