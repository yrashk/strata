; search(): the search text looked for, into panel s_pan: what was found so
; far is in the panel when a key cuts it short (s_part = 1)
search:
        addi  sp, sp, -64               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s0, 8(sp)                 ; s0 = the panel
        sd    s1, 16(sp)                ; s1 = the cursor of FIND or QUERY
        sd    s2, 24(sp)                ; s2 = a record
        sd    s3, 32(sp)                ; s3 = records left
        sd    s4, 40(sp)                ; s4 = 1: a path with terms
        sd    s5, 48(sp)                ; s5 = a tag id
        sd    s6, 56(sp)                ; s6 = the phase (FIND's mode)
        call  sys_now                   ; ...
        sd    a0, s_t0(zero)            ; ...
        sd    zero, s_t1(zero)          ; ...
        sd    zero, s_t2(zero)          ; ...
        sd    zero, s_part(zero)        ; ...
        ld    s0, s_pan(zero)           ; ...
        mv    a0, s0                    ; ...
        call  pan_clear                 ; ...
        mv    a0, s0                    ; ...
        call  pan_addr                  ; ...
        li    t0, 1                     ; ...
        sd    t0, P_MODE(a0)            ; ...
        sd    zero, P_RO(a0)            ; ...
        sd    zero, P_NPT(a0)           ; ...
        li    s4, 0                     ; a path with terms?
        li    t0, 0                     ; ...
        ld    t1, s_len(zero)           ; ...
        beqz  t1, se_end                ; ...
se_pc:  bgeu  t0, t1, se_plain          ; ...
        lbu   t2, stext(t0)             ; ...
        addi  t0, t0, 1                 ; ...
        li    t3, '/'                   ; ...
        beq   t2, t3, se_path           ; ...
        li    t3, '='                   ; ...
        beq   t2, t3, se_path           ; ...
        li    t3, '<'                   ; ...
        beq   t2, t3, se_path           ; ...
        li    t3, '>'                   ; ...
        beq   t2, t3, se_path           ; ...
        j     se_pc                     ; ...
se_path:                                ; ---- a path: QUERY over every file
        li    t0, '/'                   ; with a "/" in front
        sb    t0, pth(zero)             ; ...
        li    a0, pth+1                 ; ...
        li    a1, stext                 ; ...
        ld    a2, s_len(zero)           ; ...
        call  bcopy                     ; ...
        ld    t0, s_len(zero)           ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, pthl(zero)            ; ...
        li    s1, 0                     ; ...
sq_p:   li    t0, 2                     ; every file, wherever it is
        sd    t0, sys_lmode(zero)       ; ...
        li    a0, lbuf                  ; ...
        li    a1, pth                   ; ...
        ld    a2, pthl(zero)            ; ...
        mv    a3, s1                    ; ...
        call  sys_list                  ; ...
        sd    zero, sys_lmode(zero)     ; ...
        blez  a0, sq_d                  ; ...
        mv    s3, a0                    ; ...
        mv    s1, a1                    ; ...
        li    s2, lbuf                  ; past the path's own tags
        ld    t0, 0(s2)                 ; ...
        slli  t0, t0, 2                 ; ...
        addi  t0, t0, 15                ; ...
        srli  t0, t0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        add   s2, s2, t0                ; ...
sq_r:   beqz  s3, sq_n                  ; ...
        lw    t0, 4(s2)                 ; (a record without a name: not a file to show)
        bltz  t0, sq_sk                 ; ...
        mv    a0, s2                    ; ...
        li    a1, 2                     ; ...
        call  found                     ; ...
        bltz  a0, sq_d                  ; (full)
sq_sk:  lhu   t0, 0(s2)                 ; ...
        add   s2, s2, t0                ; ...
        addi  s3, s3, -1                ; ...
        j     sq_r                      ; ...
sq_n:   call  s_first                   ; the first files found: on the screen at once
        beqz  s1, sq_d                  ; ...
        call  s_key                     ; a key typed meanwhile: stop here
        beqz  a0, sq_p                  ; ...
        li    t0, 1                     ; ...
        sd    t0, s_part(zero)          ; ...
        j     se_cut                    ; ...
sq_d:   j     se_end                    ; ...
se_plain:                               ; ---- plain text
        li    s6, 0                     ; FIND mode 0: names that begin with it
        li    s1, 0                     ; ...
sf_p:   li    a0, stext                 ; ...
        ld    a1, s_len(zero)           ; ...
        call  sys_put                   ; ...
        li    a0, 2                     ; fs
        li    a1, 46                    ; FIND
        mv    a2, s1                    ; ...
        ld    a3, s_len(zero)           ; ...
        mv    a4, s6                    ; ...
        call  sys_msg                   ; a0 = files
        bltz  a0, sf_ph                 ; ...
        mv    s3, a0                    ; ...
        la    t0, sys_hdr               ; the cursor, the data's bytes
        ld    s1, 8(t0)                 ; ...
        ld    a1, 16(t0)                ; ...
        li    t1, 4096                  ; ...
        bleu  a1, t1, sf_g              ; ...
        mv    a1, t1                    ; ...
sf_g:   li    a0, lbuf                  ; ...
        call  sys_get                   ; ...
        li    s2, lbuf + 8              ; (no path tags)
sf_r:   beqz  s3, sf_n                  ; ...
        mv    a0, s2                    ; its rank
        call  rank_of                   ; ...
        bltz  a0, sf_sk                 ; (found already)
        mv    a1, a0                    ; ...
        mv    a0, s2                    ; ...
        call  found                     ; ...
        bltz  a0, se_end                ; (full)
sf_sk:  lhu   t0, 0(s2)                 ; ...
        add   s2, s2, t0                ; ...
        addi  s3, s3, -1                ; ...
        j     sf_r                      ; ...
sf_n:   call  s_first                   ; the first files found: on the screen at once
        beqz  s1, sf_ph                 ; the phase is done
        call  s_key                     ; a key typed meanwhile: stop here
        beqz  a0, sf_p                  ; ...
        li    t0, 1                     ; ...
        sd    t0, s_part(zero)          ; ...
        j     se_cut                    ; ...
sf_ph:  bnez  s6, se_end                ; after the first phase: the directories, then
        li    s5, 0                     ;   names that hold the text
sf_t:   ld    t0, tmax(zero)            ; directories whose names hold it
        bgeu  s5, t0, sf_td             ; ...
        mv    a0, s5                    ; ...
        call  tag_name                  ; ...
        beqz  a1, sf_tn                 ; ...
        li    a2, stext                 ; ...
        ld    a3, s_len(zero)           ; ...
        call  has_ci                    ; a0 = where, or -1
        bltz  a0, sf_tn                 ; ...
        li    a4, 3                     ; rank: 1 if it begins so, else 3
        bnez  a0, sf_tr                 ; ...
        li    a4, 1                     ; ...
sf_tr:  mv    a0, s0                    ; ...
        li    a1, tnm+1                 ; ...
        ld    a2, tl(zero)              ; ...
        mv    a3, s5                    ; ...
        call  dir_ent                   ; ...
sf_tn:  addi  s5, s5, 1                 ; ...
        j     sf_t                      ; ...
sf_td:  call  s_first                   ; what is there so far, at once
        mv    a0, s0                    ; ...
        call  pan_sort                  ; ...
        call  draw                      ; ...
        call  s_key                     ; a key typed meanwhile: stop here
        beqz  a0, sf_m1                 ; ...
        li    t0, 1                     ; ...
        sd    t0, s_part(zero)          ; ...
        j     se_cut                    ; ...
sf_m1:  li    s6, 1                     ; FIND mode 1
        li    s1, 0                     ; ...
        j     sf_p                      ; ...
se_end: call  sys_now                   ; all of it
        ld    t0, s_t0(zero)            ; ...
        sub   a0, a0, t0                ; ...
        sd    a0, s_t2(zero)            ; ...
        ld    t0, s_t1(zero)            ; ...
        bnez  t0, se_cut                ; ...
        sd    a0, s_t1(zero)            ; ...
se_cut: mv    a0, s0                    ; ...
        call  pan_sort                  ; ...
        mv    a0, s0                    ; ...
        call  pan_addr                  ; ...
        sd    zero, P_CUR(a0)           ; ...
        sd    zero, P_TOP(a0)           ; ...
        ld    ra, 0(sp)                 ; ...
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        ld    s5, 48(sp)                ; ...
        ld    s6, 56(sp)                ; ...
        addi  sp, sp, 64                ; ...
        ret                             ; ...

; s_key() -> a0 = 1 if a key waits (and the search may be cut short)
s_key:
        ld    t0, s_whole(zero)         ; ...
        li    a0, 0                     ; ...
        bnez  t0, sk_r                  ; ...
        j     rd_wait                   ; (a0 = 0 polls: tail call)
sk_r:   ret                             ; ...

; s_first(): the first time the search's panel has entries, they are sorted
; and drawn, and the time is taken (s_t1)
s_first:
        ld    t0, s_t1(zero)            ; once
        bnez  t0, sfi_r                 ; ...
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        ld    a0, s_pan(zero)           ; ...
        call  pan_addr                  ; ...
        ld    t0, P_N(a0)               ; ...
        beqz  t0, sfi_x                 ; ...
        ld    a0, s_pan(zero)           ; ...
        call  pan_sort                  ; ...
        call  sys_now                   ; ...
        ld    t0, s_t0(zero)            ; ...
        sub   a0, a0, t0                ; ...
        sd    a0, s_t1(zero)            ; ...
        call  draw                      ; ...
sfi_x:  ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
sfi_r:  ret                             ; ...

; rank_of(a0 = a FIND record) -> a0 = its rank: 0 the name is the text, 2 it
; begins with it, 4 it holds it at the start of a word (or in another case at
; the start), 5 elsewhere; -1 when FIND's first phase answered it already
; (mode 1 and it begins with the text exactly)
rank_of:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s0, 8(sp)                 ; ...
        mv    s0, a0                    ; ...
        lhu   a1, 2(s0)                 ; begins with the text exactly?
        ld    t0, s_len(zero)           ; ...
        bltu  a1, t0, rk_ci             ; ...
        addi  a0, s0, 16                ; ...
        mv    a1, t0                    ; ...
        li    a2, stext                 ; ...
        mv    a3, t0                    ; ...
        call  str_eq                    ; ...
        beqz  a0, rk_ci                 ; ...
        mv    t0, s6                    ; (the caller's phase: s6, FIND's mode)
        li    a0, -1                    ; mode 1: found by mode 0 already
        bnez  t0, rk_r                  ; ...
        lhu   t1, 2(s0)                 ; ...
        ld    t0, s_len(zero)           ; ...
        li    a0, 0                     ; ...
        beq   t1, t0, rk_r              ; ...
        li    a0, 2                     ; ...
        j     rk_r                      ; ...
rk_ci:  addi  a0, s0, 16                ; where, in any case?
        lhu   a1, 2(s0)                 ; ...
        li    a2, stext                 ; ...
        ld    a3, s_len(zero)           ; ...
        call  has_ci                    ; ...
        mv    t0, a0                    ; ...
        li    a0, 5                     ; ...
        bltz  t0, rk_r                  ; (cannot be: FIND said so)
        li    a0, 4                     ; at the start, or after _ - . space
        beqz  t0, rk_r                  ; ...
        add   t1, s0, t0                ; ...
        lbu   t1, 15(t1)                ; ...
        li    t2, '_'                   ; ...
        beq   t1, t2, rk_r              ; ...
        li    t2, '-'                   ; ...
        beq   t1, t2, rk_r              ; ...
        li    t2, '.'                   ; ...
        beq   t1, t2, rk_r              ; ...
        li    t2, ' '                   ; ...
        beq   t1, t2, rk_r              ; ...
        li    a0, 5                     ; ...
rk_r:   ld    ra, 0(sp)                 ; ...
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; found(a0 = a listing's record, a1 = rank) -> a0 = 0, or -1 when the panel is
; full: the file added to the search's panel
found:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a1, 8(sp)                 ; ...
        call  rec_ent                   ; ...
        li    t0, K_FILE                ; ...
        sb    t0, ec+E_KIND(zero)       ; ...
        ld    t0, 8(sp)                 ; ...
        sb    t0, ec+E_RANK(zero)       ; ...
        ld    a0, s_pan(zero)           ; ...
        li    a1, ec                    ; ...
        call  ent_add                   ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; search_end(): the search's panel shows its directory again
search_end:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        ld    t0, s_on(zero)            ; ...
        beqz  t0, sen_r                 ; ...
        sd    zero, s_on(zero)          ; ...
        sd    zero, s_part(zero)        ; ...
        ld    a0, s_pan(zero)           ; ...
        call  pan_load                  ; ...
sen_r:  ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

