; pan_load(a0 = panel): its directory listed again: "..", the files, the
; subdirectories (the other tags its files carry; at a root every tag), the
; snapshots (at "/"), sorted
pan_load:
        addi  sp, sp, -64               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s0, 8(sp)                 ; s0 = the panel
        sd    s1, 16(sp)                ; s1 = its state
        sd    s2, 24(sp)                ; s2 = the cursor of the listing
        sd    s3, 32(sp)                ; s3 = a record
        sd    s4, 40(sp)                ; s4 = records left
        sd    s5, 48(sp)                ; s5 = a counter
        sd    s6, 56(sp)                ; s6 = 1: the first part
        mv    s0, a0                    ; ...
        call  pan_addr                  ; ...
        mv    s1, a0                    ; ...
        mv    a0, s0                    ; ...
        call  pan_clear                 ; ...
        sd    zero, P_MODE(s1)          ; ...
        sd    zero, P_RO(s1)            ; ...
        sd    zero, P_NPT(s1)           ; ...
        ld    t0, P_PL(s1)              ; a snapshot: "/@..."
        li    t1, 2                     ; ...
        bltu  t0, t1, pl_nro            ; ...
        lbu   t1, P_PATH+1(s1)          ; ...
        li    t2, '@'                   ; ...
        bne   t1, t2, pl_nro            ; ...
        li    t1, 1                     ; ...
        sd    t1, P_RO(s1)              ; ...
pl_nro: call  seen_clear                ; no tags seen yet
        ld    t0, P_PL(s1)              ; "..", but at "/"
        li    t1, 1                     ; ...
        bleu  t0, t1, pl_q              ; ...
        li    a0, ec                    ; ...
        li    a1, ESZ                   ; ...
        call  bzero                     ; ...
        li    t0, K_UP                  ; ...
        sb    t0, ec+E_KIND(zero)       ; ...
        sb    zero, ec+E_RANK(zero)     ; ...
        li    t0, 2                     ; ...
        sh    t0, ec+E_NL(zero)         ; ...
        li    t0, '.'                   ; ...
        sb    t0, ec+E_NAME(zero)       ; ...
        sb    t0, ec+E_NAME+1(zero)     ; ...
        mv    a0, s0                    ; ...
        li    a1, ec                    ; ...
        call  ent_add                   ; ...
pl_q:   li    s2, 0                     ; the files, part by part
        li    t0, 1                     ; ...
        sd    t0, pl_first(zero)        ; ...
pl_p:   li    a0, lbuf                  ; ...
        addi  a1, s1, P_PATH            ; ...
        ld    a2, P_PL(s1)              ; ...
        mv    a3, s2                    ; ...
        call  sys_list                  ; a0 = files, a1 = the next cursor
        bltz  a0, pl_err                ; ...
        mv    s4, a0                    ; ...
        mv    s2, a1                    ; ...
        li    s3, lbuf                  ; the path's own tags
        ld    t0, 0(s3)                 ; ...
        ld    t1, pl_first(zero)        ; (the first part says them)
        beqz  t1, pl_pt                 ; ...
        sd    t0, P_NPT(s1)             ; ...
        li    t1, 0                     ; ...
pl_ptl: bgeu  t1, t0, pl_pt             ; ...
        li    t2, NPT                   ; ...
        bgeu  t1, t2, pl_pt             ; ...
        slli  t2, t1, 2                 ; ...
        add   t3, s3, t2                ; ...
        lwu   t4, 8(t3)                 ; ...
        add   t3, s1, t2                ; ...
        sw    t4, P_PT(t3)              ; ...
        addi  t1, t1, 1                 ; ...
        j     pl_ptl                    ; ...
pl_pt:  sd    zero, pl_first(zero)      ; ...
        slli  t0, t0, 2                 ; past them
        addi  t0, t0, 15                ; ...
        srli  t0, t0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        add   s3, s3, t0                ; ...
pl_rec: beqz  s4, pl_nx                 ; ...
        mv    a0, s3                    ; the record as an entry in ec
        call  rec_ent                   ; ...
        li    t0, K_FILE                ; ...
        sb    t0, ec+E_KIND(zero)       ; ...
        li    t0, 3                     ; ...
        sb    t0, ec+E_RANK(zero)       ; ...
        lwu   s5, 4(s3)                 ; its tags: seen (s5 left, s6 at; bit 31: the
        slli  s5, s5, 33                ;   record of a deeper directory's file)
        srli  s5, s5, 33                ; ...
        lhu   s6, 2(s3)                 ; ...
        addi  s6, s6, 7                 ; ...
        srli  s6, s6, 3                 ; ...
        slli  s6, s6, 3                 ; ...
        add   s6, s6, s3                ; ...
        addi  s6, s6, 16                ; ...
pl_tg:  beqz  s5, pl_add                ; ...
        lwu   a0, 0(s6)                 ; ...
        call  seen_set                  ; ...
        addi  s6, s6, 4                 ; ...
        addi  s5, s5, -1                ; ...
        j     pl_tg                     ; ...
pl_add: lw    t0, 4(s3)                 ; a record without a name (bit 31 of its count of
        bltz  t0, pl_nadd               ;   tags): a deeper directory's file, whose tags
                                        ;   are subdirectories
        mv    a0, s0                    ; ...
        li    a1, ec                    ; ...
        call  ent_add                   ; ...
pl_nadd:
        lhu   t0, 0(s3)                 ; the next record
        add   s3, s3, t0                ; ...
        addi  s4, s4, -1                ; ...
        j     pl_rec                    ; ...
pl_nx:  bnez  s2, pl_p                  ; ...
        mv    a0, s1                    ; the directories: at a root every tag
        call  is_root                   ; ...
        beqz  a0, pl_fac                ; ...
        mv    a0, s0                    ; ...
        call  pan_tags                  ; ...
        j     pl_snap                   ; ...
pl_fac: li    s5, 0                     ; the tags seen, but the path's own
pl_fl:  ld    t0, tmax(zero)            ; ...
        bgeu  s5, t0, pl_snap           ; ...
        mv    a0, s5                    ; ...
        call  seen_get                  ; ...
        beqz  a0, pl_fn                 ; ...
        ld    t0, P_NPT(s1)             ; ...
        li    t1, 0                     ; ...
pl_own: bgeu  t1, t0, pl_dir            ; ...
        slli  t2, t1, 2                 ; ...
        add   t2, t2, s1                ; ...
        lwu   t2, P_PT(t2)              ; ...
        beq   t2, s5, pl_fn             ; ...
        addi  t1, t1, 1                 ; ...
        j     pl_own                    ; ...
pl_dir: mv    a0, s5                    ; a directory entry
        call  tag_name                  ; ...
        mv    a2, a1                    ; ...
        mv    a1, a0                    ; ...
        mv    a0, s0                    ; ...
        mv    a3, s5                    ; ...
        li    a4, 1                     ; ...
        call  dir_ent                   ; ...
pl_fn:  addi  s5, s5, 1                 ; ...
        j     pl_fl                     ; ...
pl_snap:
        ld    t0, P_PL(s1)              ; the snapshots, at "/"
        li    t1, 1                     ; ...
        bgtu  t0, t1, pl_sort           ; ...
        mv    a0, s0                    ; ...
        call  pan_snaps                 ; ...
pl_sort:
        mv    a0, s0                    ; ...
        call  pan_sort                  ; ...
        j     pl_r                      ; ...
pl_err: ld    t0, P_PL(s1)              ; (the root itself failed: nothing more)
        li    t1, 1                     ; ...
        bleu  t0, t1, pl_r              ; ...
        li    a0, m_fail                ; no such directory: the root instead
        li    a1, m_fail_e - m_fail     ; ...
        call  msg_set                   ; ...
        addi  a0, s1, P_PATH            ; ...
        ld    a1, P_PL(s1)              ; ...
        call  msg_add                   ; ...
        li    t0, 1                     ; ...
        sd    t0, P_PL(s1)              ; ...
        mv    a0, s0                    ; ...
        ld    ra, 0(sp)                 ; ...
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        ld    s5, 48(sp)                ; ...
        ld    s6, 56(sp)                ; ...
        addi  sp, sp, 64                ; ...
        j     pan_load                  ; (the root always lists)
pl_r:   ld    ra, 0(sp)                 ; ...
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        ld    s5, 48(sp)                ; ...
        ld    s6, 56(sp)                ; ...
        addi  sp, sp, 64                ; ...
        ret                             ; ...

; rec_ent(a0 = a listing's record): it as an entry in ec (kind and rank not set)
rec_ent:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s0, 8(sp)                 ; ...
        mv    s0, a0                    ; ...
        li    a0, ec                    ; ...
        li    a1, E_NAME                ; ...
        call  bzero                     ; ...
        ld    t0, 8(s0)                 ; the size
        sd    t0, ec+E_SIZE(zero)       ; ...
        lwu   t0, 4(s0)                 ; the tags (a record holds 248 at most; bit 31
        slli  t0, t0, 33                ;   marks a deeper directory's file)
        srli  t0, t0, 33                ; ...
        li    t1, 248                   ; ...
        bleu  t0, t1, re_0              ; ...
        mv    t0, t1                    ; ...
re_0:   sh    t0, ec+E_NT(zero)         ; ...
        lhu   t1, 2(s0)                 ; the name
        sh    t1, ec+E_NL(zero)         ; ...
        li    a0, ec+E_NAME             ; ...
        addi  a1, s0, 16                ; ...
        mv    a2, t1                    ; ...
        call  bcopy                     ; ...
        li    a0, ec                    ; the tag ids after it
        call  ent_tags                  ; ...
        lhu   t1, 2(s0)                 ; ...
        addi  t1, t1, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        add   a1, s0, t1                ; ...
        addi  a1, a1, 16                ; ...
        lhu   a2, ec+E_NT(zero)         ; ...
        slli  a2, a2, 2                 ; ...
        sd    zero, 0(a0)               ; (the last word's padding)
        add   t0, a0, a2                ; ...
        addi  t0, t0, -4                ; ...
        blez  a2, re_r                  ; ...
        sw    zero, 0(t0)               ; ...
        sw    zero, 4(t0)               ; ...
        call  bcopy                     ; ...
re_r:   ld    ra, 0(sp)                 ; ...
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

