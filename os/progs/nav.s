; ent_path(a0 = panel, a1 = entry): the path that names it, in pth (pthl):
; a directory's path and the name; in a search, "/", the file's first
; directory, "/", the name (a directory found: "/" and its name)
ent_path:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s0, 8(sp)                 ; s0 = the panel's state
        sd    s1, 16(sp)                ; s1 = the entry
        sd    s2, 24(sp)                ; s2 = the length so far
        call  pan_addr                  ; ...
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        lbu   t0, E_KIND(s1)            ; "..": the directory above
        li    t1, K_UP                  ; ...
        bne   t0, t1, ep_1              ; ...
        li    a0, pth                   ; ...
        addi  a1, s0, P_PATH            ; ...
        ld    a2, P_PL(s0)              ; ...
        sd    a2, pthl(zero)            ; ...
        call  bcopy                     ; ...
        call  path_up                   ; ...
        j     ep_r                      ; ...
ep_1:   li    t0, '/'                   ; ...
        sb    t0, pth(zero)             ; ...
        li    s2, 1                     ; ...
        ld    t0, P_MODE(s0)            ; ...
        bnez  t0, ep_s                  ; ...
        lbu   t0, E_KIND(s1)            ; a snapshot: "/@NAME"
        li    t1, K_SNAP                ; ...
        beq   t0, t1, ep_n              ; ...
        ld    a2, P_PL(s0)              ; the directory's path
        li    t0, 1                     ; ...
        bleu  a2, t0, ep_n              ; ...
        li    a0, pth                   ; ...
        addi  a1, s0, P_PATH            ; ...
        mv    s2, a2                    ; ...
        call  bcopy                     ; ...
        li    t0, '/'                   ; ...
        sb    t0, pth(s2)               ; ...
        addi  s2, s2, 1                 ; ...
        j     ep_n                      ; ...
ep_s:   lbu   t0, E_KIND(s1)            ; a search: the file's directory, every tag
        bnez  t0, ep_n                  ; ...
        sd    zero, ep_i(zero)          ; ...
ep_t:   lhu   t0, E_NT(s1)              ; ...
        ld    t1, ep_i(zero)            ; ...
        bgeu  t1, t0, ep_n              ; ...
        addi  t2, t1, 1                 ; ...
        sd    t2, ep_i(zero)            ; ...
        mv    a0, s1                    ; ...
        call  ent_tags                  ; ...
        ld    t1, ep_i(zero)            ; ...
        slli  t1, t1, 2                 ; ...
        add   a0, a0, t1                ; ...
        lwu   a0, -4(a0)                ; ...
        call  tag_name                  ; ...
        beqz  a1, ep_t                  ; ...
        li    t0, 300                   ; (room)
        bgeu  s2, t0, ep_n              ; ...
        mv    a2, a1                    ; ...
        mv    a1, a0                    ; ...
        li    a0, pth                   ; ...
        add   a0, a0, s2                ; ...
        add   s2, s2, a2                ; ...
        call  bcopy                     ; ...
        li    t0, '/'                   ; ...
        sb    t0, pth(s2)               ; ...
        addi  s2, s2, 1                 ; ...
        j     ep_t                      ; ...
ep_n:   li    a0, pth                   ; the name
        add   a0, a0, s2                ; ...
        addi  a1, s1, E_NAME            ; ...
        lhu   a2, E_NL(s1)              ; ...
        add   s2, s2, a2                ; ...
        call  bcopy                     ; ...
        sd    s2, pthl(zero)            ; ...
ep_r:   ld    ra, 0(sp)                 ; ...
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; path_up(): pth (pthl) loses its last component ("/" stays)
path_up:
        ld    t0, pthl(zero)            ; ...
pu_l:   li    t1, 1                     ; ...
        bleu  t0, t1, pu_r              ; ...
        addi  t0, t0, -1                ; ...
        lbu   t2, pth(t0)               ; ...
        li    t1, '/'                   ; ...
        bne   t2, t1, pu_l              ; ...
        bnez  t0, pu_r                  ; (the root's "/" stays)
        li    t0, 1                     ; ...
pu_r:   sd    t0, pthl(zero)            ; ...
        ret                             ; ...

