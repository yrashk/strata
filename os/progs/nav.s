; command(a0 = key): what it does
command:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s0, 8(sp)                 ; s0 = the key
        sd    s1, 16(sp)                ; s1 = the active panel's state
        sd    s2, 24(sp)                ; ...
        mv    s0, a0                    ; ...
        ld    a0, act(zero)             ; ...
        call  pan_addr                  ; ...
        mv    s1, a0                    ; ...
        ld    t0, esc_p(zero)           ; Esc and then a digit: an F-key
        sd    zero, esc_p(zero)         ; ...
        beqz  t0, cm_0                  ; ...
        addi  t0, s0, -'0'              ; ...
        li    t1, 10                    ; ...
        bgeu  t0, t1, cm_0              ; ...
        addi  s0, t0, KY_F1 - 1         ; ...
        bnez  t0, cm_0                  ; (0: F10)
        li    s0, KY_F1 + 9             ; ...
cm_0:   li    t0, KY_SIZE               ; ...
        beq   s0, t0, cm_r              ; ...
        li    t0, KY_EOF                ; the end of input: leave
        beq   s0, t0, cm_quit           ; ...
        li    t0, KY_MOUSE              ; ...
        beq   s0, t0, cm_mouse          ; ...
        sd    zero, msgl(zero)          ; (a key clears the message)
        li    t0, 27                    ; Esc
        beq   s0, t0, cm_esc            ; ...
        li    t0, 9                     ; Tab
        beq   s0, t0, cm_tab            ; ...
        li    t0, KY_UP                 ; ...
        beq   s0, t0, cm_up             ; ...
        li    t0, KY_DOWN               ; ...
        beq   s0, t0, cm_down           ; ...
        li    t0, KY_PGUP               ; ...
        beq   s0, t0, cm_pgup           ; ...
        li    t0, KY_PGDN               ; ...
        beq   s0, t0, cm_pgdn           ; ...
        li    t0, KY_HOME               ; ...
        beq   s0, t0, cm_home           ; ...
        li    t0, KY_END                ; ...
        beq   s0, t0, cm_end            ; ...
        li    t0, 10                    ; Enter
        beq   s0, t0, cm_enter          ; ...
        li    t0, 13                    ; ...
        beq   s0, t0, cm_enter          ; ...
        li    t0, 127                   ; Backspace
        beq   s0, t0, cm_bs             ; ...
        li    t0, 8                     ; ...
        beq   s0, t0, cm_bs             ; ...
        li    t0, KY_INS                ; Insert, Ctrl-T: mark
        beq   s0, t0, cm_mark           ; ...
        li    t0, 20                    ; ...
        beq   s0, t0, cm_mark           ; ...
        li    t0, 17                    ; Ctrl-Q: quick view
        beq   s0, t0, cm_qv             ; ...
        li    t0, 12                    ; Ctrl-L: everything drawn again
        beq   s0, t0, cm_redraw         ; ...
        li    t0, 24                    ; Ctrl-X: the command line / the search
        beq   s0, t0, cm_mode           ; ...
        li    t0, 6                     ; Ctrl-F: the cursor's path into the command line
        beq   s0, t0, cm_ins            ; ...
        li    t0, 3                     ; Ctrl-C: the search ends
        beq   s0, t0, cm_esc            ; ...
        li    t0, KY_F1                 ; the F-keys
        sub   t0, s0, t0                ; ...
        li    t1, 10                    ; ...
        bltu  t0, t1, cm_fkey           ; ...
        addi  t0, s0, -33               ; printable (not space): the search
        li    t1, 94                    ; ...
        bltu  t0, t1, cm_type           ; ...
        li    t0, ' '                   ; space within a search or a command
        bne   s0, t0, cm_r              ; ...
        ld    t0, s_on(zero)            ; ...
        bnez  t0, cm_type               ; ...
        ld    t0, c_mode(zero)          ; ...
        bnez  t0, cm_type               ; ...
        j     cm_r                      ; ...
cm_mode:
        ld    t0, c_mode(zero)          ; the other one
        xori  t0, t0, 1                 ; ...
        sd    t0, c_mode(zero)          ; ...
        beqz  t0, cm_r                  ; (into the command line: a search ends)
        call  search_end                ; ...
        j     cm_r                      ; ...
cm_ins: call  search_end                ; the command line, and the cursor's path in it
        li    t0, 1                     ; ...
        sd    t0, c_mode(zero)          ; ...
        ld    t0, P_N(s1)               ; ...
        beqz  t0, cm_r                  ; ...
        ld    t0, P_MODE(s1)            ; (not a quick view)
        li    t1, 2                     ; ...
        beq   t0, t1, cm_r              ; ...
        ld    a0, act(zero)             ; ...
        ld    a1, P_CUR(s1)             ; ...
        li    a2, ea                    ; ...
        call  ent_at                    ; ...
        ld    a0, act(zero)             ; ...
        li    a1, ea                    ; ...
        call  ent_path                  ; ...
        ld    t0, c_len(zero)           ; (room for it and a space)
        ld    t1, pthl(zero)            ; ...
        add   t2, t0, t1                ; ...
        li    t3, 240                   ; ...
        bgeu  t2, t3, cm_r              ; ...
        li    a0, ctext                 ; ...
        add   a0, a0, t0                ; ...
        li    a1, pth                   ; ...
        mv    a2, t1                    ; ...
        call  bcopy                     ; ...
        li    t1, ' '                   ; ...
        sb    t1, 0(a0)                 ; ...
        li    t0, ctext - 1             ; ...
        sub   a0, a0, t0                ; ...
        sd    a0, c_len(zero)           ; ...
        j     cm_r                      ; ...
cm_fkey:
        slli  t0, t0, 3                 ; ...
        la    t1, fktab                 ; ...
        add   t1, t1, t0                ; ...
        ld    t1, 0(t1)                 ; ...
        jalr  ra, t1, 0                 ; ...
        j     cm_r                      ; ...
cm_quit:
        li    t0, 1                     ; ...
        sd    t0, quit(zero)            ; ...
        j     cm_r                      ; ...
cm_esc: li    t0, 1                     ; Esc: the next digit is an F-key
        sd    t0, esc_p(zero)           ; ...
        sd    zero, c_len(zero)         ; the command line is emptied
        ld    t0, s_on(zero)            ; and a search ends
        beqz  t0, cm_r                  ; ...
        call  search_end                ; ...
        j     cm_r                      ; ...
cm_tab: ld    t0, act(zero)             ; the other panel (not one in quick view)
        xori  t0, t0, 1                 ; ...
        mv    a0, t0                    ; ...
        call  pan_addr                  ; ...
        ld    t1, P_MODE(a0)            ; ...
        li    t2, 2                     ; ...
        beq   t1, t2, cm_r              ; ...
        ld    t0, act(zero)             ; ...
        xori  t0, t0, 1                 ; ...
        sd    t0, act(zero)             ; ...
        j     cm_r                      ; ...
cm_up:  li    a0, -1                    ; ...
        j     cm_mv                     ; ...
cm_down:
        li    a0, 1                     ; ...
        j     cm_mv                     ; ...
cm_pgup:
        call  pan_rows                  ; ...
        addi  a0, a0, -1                ; ...
        neg   a0, a0                    ; ...
        j     cm_mv                     ; ...
cm_pgdn:
        call  pan_rows                  ; ...
        addi  a0, a0, -1                ; ...
        j     cm_mv                     ; ...
cm_home:
        sd    zero, P_CUR(s1)           ; ...
        j     cm_r                      ; ...
cm_end: ld    t0, P_N(s1)               ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, P_CUR(s1)             ; ...
        j     cm_r                      ; ...
cm_mv:  mv    a1, a0                    ; ...
        ld    a0, act(zero)             ; ...
        call  cur_move                  ; ...
        j     cm_r                      ; ...
cm_enter:
        ld    t0, c_mode(zero)          ; a command typed: it runs
        beqz  t0, cm_en1                ; ...
        ld    t0, c_len(zero)           ; ...
        beqz  t0, cm_en1                ; ...
        call  run_line                  ; ...
        j     cm_r                      ; ...
cm_en1: ld    a0, act(zero)             ; ...
        call  open_cur                  ; ...
        j     cm_r                      ; ...
cm_bs:  ld    t0, c_mode(zero)          ; the command line: a character less
        beqz  t0, cm_bs1                ; ...
        ld    t0, c_len(zero)           ; ...
        beqz  t0, cm_bsup               ; (empty: up, as in a directory)
        addi  t0, t0, -1                ; ...
        sd    t0, c_len(zero)           ; ...
        j     cm_r                      ; ...
cm_bs1: ld    t0, s_on(zero)            ; a search: a character less
        beqz  t0, cm_bsup               ; ...
        ld    t1, s_pan(zero)           ; (in its panel)
        ld    t2, act(zero)             ; ...
        bne   t1, t2, cm_bsup           ; ...
        ld    t0, s_len(zero)           ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, s_len(zero)           ; ...
        bgtz  t0, cm_srch               ; ...
        call  search_end                ; (none left: the search ends)
        j     cm_r                      ; ...
cm_bsup:
        ld    t0, P_MODE(s1)            ; up a directory
        bnez  t0, cm_r                  ; ...
        ld    a0, act(zero)             ; ...
        call  go_up                     ; ...
        j     cm_r                      ; ...
cm_mark:
        ld    a0, act(zero)             ; ...
        call  mark_cur                  ; ...
        li    a1, 1                     ; ...
        ld    a0, act(zero)             ; ...
        call  cur_move                  ; ...
        j     cm_r                      ; ...
cm_qv:  call  f_quick                   ; ...
        j     cm_r                      ; ...
cm_redraw:
        li    t0, 1                     ; ...
        sd    t0, clear(zero)           ; ...
        j     cm_r                      ; ...
cm_type:
        ld    t0, c_mode(zero)          ; the command line takes it
        beqz  t0, cm_ty1                ; ...
        ld    t0, c_len(zero)           ; ...
        li    t1, 240                   ; ...
        bgeu  t0, t1, cm_r              ; ...
        li    t1, ctext                 ; ...
        add   t1, t1, t0                ; ...
        sb    s0, 0(t1)                 ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, c_len(zero)           ; ...
        j     cm_r                      ; ...
cm_ty1: ld    t0, s_on(zero)            ; a new search, in the active panel
        bnez  t0, cm_t1                 ; ...
        ld    t0, P_MODE(s1)            ; (not a quick view's)
        li    t1, 2                     ; ...
        beq   t0, t1, cm_r              ; ...
        li    t0, 1                     ; ...
        sd    t0, s_on(zero)            ; ...
        ld    t0, act(zero)             ; ...
        sd    t0, s_pan(zero)           ; ...
        sd    zero, s_len(zero)         ; ...
cm_t1:  ld    t0, s_pan(zero)           ; typing goes to the search's panel
        sd    t0, act(zero)             ; ...
        ld    t0, s_len(zero)           ; ...
        li    t1, 100                   ; ...
        bgeu  t0, t1, cm_r              ; ...
        sb    s0, stext(t0)             ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, s_len(zero)           ; ...
cm_srch:
        call  search                    ; ...
        j     cm_r                      ; ...
cm_mouse:
        call  mouse                     ; ...
cm_r:   ld    ra, 0(sp)                 ; ...
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...


; cur_move(a0 = panel, a1 = rows (+ down, - up)): the cursor moves, within
; the entries
cur_move:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a1, 8(sp)                 ; ...
        call  pan_addr                  ; ...
        ld    a1, 8(sp)                 ; ...
        ld    t0, P_CUR(a0)             ; ...
        add   t0, t0, a1                ; ...
        bgez  t0, cmv_1                 ; ...
        li    t0, 0                     ; ...
cmv_1:  ld    t1, P_N(a0)               ; ...
        bltu  t0, t1, cmv_2             ; ...
        addi  t0, t1, -1                ; ...
        bgez  t0, cmv_2                 ; ...
        li    t0, 0                     ; ...
cmv_2:  sd    t0, P_CUR(a0)             ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; mark_cur(a0 = panel): the cursor's entry marked or not (files only)
mark_cur:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s0, 8(sp)                 ; ...
        sd    s1, 16(sp)                ; ...
        mv    s0, a0                    ; ...
        call  pan_addr                  ; ...
        mv    s1, a0                    ; ...
        ld    t0, P_N(s1)               ; ...
        beqz  t0, mc_r                  ; ...
        mv    a0, s0                    ; ...
        ld    a1, P_CUR(s1)             ; ...
        li    a2, ea                    ; ...
        call  ent_at                    ; ...
        lbu   t0, ea+E_KIND(zero)       ; ...
        bnez  t0, mc_r                  ; ...
        lbu   t2, ea+E_MARK(zero)       ; the mark, in the entry
        xori  t2, t2, 1                 ; ...
        sb    t2, ea+E_MARK(zero)       ; ...
        sd    t2, 24(sp)                ; ...
        mv    a0, s0                    ; ...
        li    a1, ea                    ; ...
