; rb_also(a0 = panel, a1 = width): the third column for the entry in ed: a
; file's directory as a path of its tags but the panel's own (in a search:
; all of them, "/" for none)
rb_also:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s0, 8(sp)                 ; s0 = the panel's state
        sd    s1, 16(sp)                ; s1 = the width
        sd    s2, 24(sp)                ; s2 = the tag at hand
        sd    s3, 32(sp)                ; s3 = columns at the start
        sd    s4, 40(sp)                ; s4 = names written
        call  pan_addr                  ; ...
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        ld    s3, rbc(zero)             ; ...
        li    s4, 0                     ; ...
        lbu   t0, ed+E_KIND(zero)       ; only files
        bnez  t0, ral_pad               ; ...
        li    s2, 0                     ; ...
ral_l:  lhu   t0, ed+E_NT(zero)         ; ...
        bgeu  s2, t0, ral_e             ; ...
        li    a0, ed                    ; ...
        call  ent_tags                  ; ...
        slli  t1, s2, 2                 ; ...
        add   t1, t1, a0                ; ...
        lwu   a0, 0(t1)                 ; ...
        addi  s2, s2, 1                 ; the panel's own tag?
        ld    t2, P_NPT(s0)             ; ...
        li    t3, 0                     ; ...
ral_o:  bgeu  t3, t2, ral_n             ; ...
        slli  t4, t3, 2                 ; ...
        add   t4, t4, s0                ; ...
        lwu   t4, P_PT(t4)              ; ...
        beq   t4, a0, ral_l             ; ...
        addi  t3, t3, 1                 ; ...
        j     ral_o                     ; ...
ral_n:  call  tag_name                  ; ...
        beqz  a1, ral_l                 ; ...
        ld    t0, rbc(zero)             ; room?
        sub   t0, t0, s3                ; ...
        add   t0, t0, a1                ; ...
        addi  t0, t0, 1                 ; ...
        bgtu  t0, s1, ral_cut           ; ...
        li    a0, '/'                   ; "/" before each: the file's directory as a path
        call  rb_chr                    ; ...
        li    a0, tnm+1                 ; ...
        ld    a1, tl(zero)              ; ...
ral_w:  call  rb_rawc                   ; ...
        addi  s4, s4, 1                 ; ...
        j     ral_l                     ; ...
ral_cut:
        ld    t0, rbc(zero)             ; "~" when there is no room for more
        sub   t0, t0, s3                ; ...
        bgeu  t0, s1, ral_x             ; ...
        li    a0, '~'                   ; ...
        call  rb_chr                    ; ...
        j     ral_pad                   ; ...
ral_e:  bnez  s4, ral_pad               ; a search's file in no directory: "/"
        ld    t0, P_MODE(s0)            ; ...
        beqz  t0, ral_pad               ; ...
        li    a0, '/'                   ; ...
        call  rb_chr                    ; ...
ral_pad:
        ld    t0, rbc(zero)             ; ...
        sub   t0, t0, s3                ; ...
        sub   a0, s1, t0                ; ...
        call  rb_pad                    ; ...
ral_x:  ld    ra, 0(sp)                 ; ...
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; ...

; cmd_row(): the command line: a prompt, the search, a message, or a hint
