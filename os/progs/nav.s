        mv    a0, s1                    ; ...
        j     ql_x                      ; ...
ql_no:  li    a0, -1                    ; ...
ql_x:   ld    ra, 0(sp)                 ; ...
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; read_far(a0 = handle, a1 = c0 offset, a2 = most bytes, a multiple of 8) ->
; a0 = bytes read into far memory there (to the most, or the end of the file)
read_far:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s0, 8(sp)                 ; s0 = the handle
        sd    s1, 16(sp)                ; s1 = where
        sd    s2, 24(sp)                ; s2 = the most
        sd    s3, 32(sp)                ; s3 = bytes so far
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        mv    s2, a2                    ; ...
        li    s3, 0                     ; ...
rfa_l:  sub   a2, s2, s3                ; ...
        blez  a2, rfa_r                 ; ...
        li    t0, 4032                  ; (a multiple of 8: what follows stays aligned)
        bleu  a2, t0, rfa_1             ; ...
        mv    a2, t0                    ; ...
rfa_1:  sd    a2, rf_want(zero)         ; ...
        mv    a0, s0                    ; ...
        li    a1, lbuf                  ; ...
        call  read_full                 ; ...
        beqz  a0, rfa_r                 ; ...
        addi  t1, a0, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        add   t0, s1, s3                ; ...
        li    t2, lbuf                  ; ...
        tput  tg1, t2, c0, t0, t1       ; ...
        twait 1 << 1                    ; ...
        add   s3, s3, a0                ; ...
        ld    t0, rf_want(zero)         ; (short: the end)
        beq   a0, t0, rfa_l             ; ...
rfa_r:  mv    a0, s3                    ; ...
        ld    ra, 0(sp)                 ; ...
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        addi  sp, sp, 40                ; ...
        ret                             ; ...

; rb_hex2(a0 = byte): two hex digits
rb_hex2:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        srli  a0, a0, 4                 ; ...
        andi  a0, a0, 15                ; ...
        la    t0, sys_hexd              ; ...
        add   t0, t0, a0                ; ...
        lbu   a0, 0(t0)                 ; ...
        call  rb_chr                    ; ...
        ld    a0, 8(sp)                 ; ...
        andi  a0, a0, 15                ; ...
        la    t0, sys_hexd              ; ...
        add   t0, t0, a0                ; ...
        lbu   a0, 0(t0)                 ; ...
        call  rb_chr                    ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

