; f_view(): F3: the cursor's file on the whole screen, as text or in hex (h
; or F4 switch); the arrows, PgUp, PgDn, Home, End move; q, Esc, F3, F10 leave
f_view:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s0, 8(sp)                 ; ...
        sd    s1, 16(sp)                ; ...
        sd    s2, 24(sp)                ; ...
        call  cur_file                  ; ...
        beqz  a0, fv_r                  ; ...
        li    a0, pth                   ; its size; the bytes come as they are shown
        ld    a1, pthl(zero)            ; ...
        call  sys_stat                  ; ...
        bltz  a0, fv_r                  ; ...
        sd    a0, v_size(zero)          ; ...
        li    a0, vpath                 ; its path (pth is used for other things)
        li    a1, pth                   ; ...
        ld    a2, pthl(zero)            ; ...
        sd    a2, vpl(zero)             ; ...
        call  bcopy                     ; ...
        sd    zero, v_full(zero)        ; ...
        sd    zero, v_lo(zero)          ; nothing read yet
        sd    zero, v_len(zero)         ; ...

        sd    zero, v_top(zero)         ; ...
        li    t0, -1                    ; ...
        sd    t0, v_wb(zero)            ; ...
        li    a0, ec                    ; the entry kept (for its name)
        li    a1, ea                    ; ...
        li    a2, ESZ                   ; ...
        call  bcopy                     ; ...
        sd    zero, v_hex(zero)         ; text, unless it has zero bytes early
        call  v_istext                  ; ...
        seqz  a0, a0                    ; ...
        sd    a0, v_hex(zero)           ; ...
        li    t0, 1                     ; ...
        sd    t0, clear(zero)           ; ...
fv_l:   call  v_draw                    ; ---- the viewer's loop
        call  getkey                    ; ...
        mv    s0, a0                    ; ...
        li    t0, 'q'                   ; ...
        beq   s0, t0, fv_x              ; ...
        li    t0, 27                    ; ...
        beq   s0, t0, fv_x              ; ...
        li    t0, 3                     ; ...
        beq   s0, t0, fv_x              ; ...
        li    t0, KY_EOF                ; ...
        beq   s0, t0, fv_x              ; ...
        li    t0, KY_F1 + 2             ; F3
        beq   s0, t0, fv_x              ; ...
        li    t0, KY_F1 + 9             ; F10
        beq   s0, t0, fv_x              ; ...
        li    t0, 'h'                   ; hex / text
        beq   s0, t0, fv_h              ; ...
        li    t0, KY_F1 + 3             ; ...
        beq   s0, t0, fv_h              ; ...
        li    t0, KY_UP                 ; ...
        beq   s0, t0, fv_up             ; ...
        li    t0, 'k'                   ; ...
        beq   s0, t0, fv_up             ; ...
        li    t0, KY_DOWN               ; ...
        beq   s0, t0, fv_dn             ; ...
        li    t0, 'j'                   ; ...
        beq   s0, t0, fv_dn             ; ...
        li    t0, 10                    ; ...
        beq   s0, t0, fv_dn             ; ...
        li    t0, KY_PGDN               ; ...
        beq   s0, t0, fv_pd             ; ...
        li    t0, ' '                   ; ...
        beq   s0, t0, fv_pd             ; ...
        li    t0, KY_PGUP               ; ...
        beq   s0, t0, fv_pu             ; ...
        li    t0, 'b'                   ; ...
        beq   s0, t0, fv_pu             ; ...
        li    t0, KY_HOME               ; ...
        beq   s0, t0, fv_hm             ; ...
        li    t0, 'g'                   ; ...
        beq   s0, t0, fv_hm             ; ...
        li    t0, KY_END                ; ...
        beq   s0, t0, fv_en             ; ...
        li    t0, 'G'                   ; ...
        beq   s0, t0, fv_en             ; ...
        li    t0, KY_MOUSE              ; the wheel
        bne   s0, t0, fv_l              ; ...
        ld    t0, m_b(zero)             ; ...
        li    t1, 64                    ; ...
        beq   t0, t1, fv_w3u            ; ...
        li    t1, 65                    ; ...
        bne   t0, t1, fv_l              ; ...
        li    a0, 3                     ; ...
        call  v_down                    ; ...
        j     fv_l                      ; ...
fv_w3u: li    a0, 3                     ; ...
        call  v_up                      ; ...
        j     fv_l                      ; ...
fv_h:   ld    t0, v_hex(zero)           ; ...
        xori  t0, t0, 1                 ; ...
        sd    t0, v_hex(zero)           ; ...
        beqz  t0, fv_l                  ; (into hex: a row's start)
        ld    t0, v_top(zero)           ; ...
        srli  t0, t0, 4                 ; ...
        slli  t0, t0, 4                 ; ...
        sd    t0, v_top(zero)           ; ...
        j     fv_l                      ; ...
fv_up:  li    a0, 1                     ; ...
        call  v_up                      ; ...
        j     fv_l                      ; ...
fv_dn:  li    a0, 1                     ; ...
        call  v_down                    ; ...
        j     fv_l                      ; ...
fv_pd:  ld    a0, srows(zero)           ; ...
        addi  a0, a0, -2                ; ...
        call  v_down                    ; ...
        j     fv_l                      ; ...
fv_pu:  ld    a0, srows(zero)           ; ...
        addi  a0, a0, -2                ; ...
        call  v_up                      ; ...
        j     fv_l                      ; ...
fv_hm:  sd    zero, v_top(zero)         ; ...
        j     fv_l                      ; ...
fv_en:  ld    t0, v_size(zero)          ; from the end, a screen up
        sd    t0, v_top(zero)           ; ...
        ld    t1, v_hex(zero)           ; ...
        beqz  t1, fv_en2                ; ...
        addi  t0, t0, 15                ; ...
        srli  t0, t0, 4                 ; ...
        slli  t0, t0, 4                 ; ...
        sd    t0, v_top(zero)           ; ...
fv_en2: ld    a0, srows(zero)           ; ...
        addi  a0, a0, -1                ; ...
        call  v_up                      ; ...
        j     fv_l                      ; ...
fv_x:   li    t0, 1                     ; back to the panels
        sd    t0, clear(zero)           ; ...
fv_r:   ld    ra, 0(sp)                 ; ...
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; v_at(a0 = offset) -> a0 = the file's byte there, or -1 past its end. VREG
; bytes of the file are in far memory from v_lo on (v_fill reads them, around
; the offset asked for, when it is not among them), and a window of VWIN of
; those in vwin
v_at:
        ld    t0, v_size(zero)          ; ...
        bgeu  a0, t0, va_no             ; ...
        ld    t1, v_lo(zero)            ; among the bytes read?
        sub   t2, a0, t1                ; ...
        ld    t3, v_len(zero)           ; ...
        bltu  t2, t3, va_in             ; ...
        addi  sp, sp, -16               ; no: read them
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        call  v_fill                    ; ...
        ld    a0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ld    t1, v_lo(zero)            ; (a file that shrank: nothing there)
        sub   t2, a0, t1                ; ...
        ld    t3, v_len(zero)           ; ...
        bgeu  t2, t3, va_no             ; ...
va_in:  ld    t1, v_wb(zero)            ; in the window? (-1: none)
        li    t3, VWIN                  ; ...
        bltu  a0, t1, va_get            ; ...
        sub   t2, a0, t1                ; ...
        bltu  t2, t3, va_have           ; ...
va_get: srli  t1, a0, 11                ; (VWIN = 2048)
        slli  t1, t1, 11                ; ...
        sd    t1, v_wb(zero)            ; ...
        ld    t2, v_lo(zero)            ; ...
        sub   t2, t1, t2                ; ...
        addi  t2, t2, VBASE             ; ...
        li    t4, vwin                  ; ...
        tget  tg1, t4, c0, t2, t3       ; ...
        twait 1 << 1                    ; ...
        sub   t2, a0, t1                ; ...
va_have:
        lbu   a0, vwin(t2)              ; ...
        ret                             ; ...
va_no:  li    a0, -1                    ; ...
        ret                             ; ...

; v_fill(a0 = offset): the file's bytes around it into far memory: from the
; offset less half of VREG (whole 4 KiB) on, up to VREG of them. READ has no
; seek, so the bytes before them are read and dropped
v_fill:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s0, 8(sp)                 ; s0 = the handle
        sd    s1, 16(sp)                ; s1 = bytes still to skip
        li    t0, VREG / 2              ; ...
        sub   s1, a0, t0                ; ...
        bgez  s1, vf_1                  ; ...
        li    s1, 0                     ; ...
vf_1:   srli  s1, s1, 12                ; ...
        slli  s1, s1, 12                ; ...
        sd    s1, v_lo(zero)            ; ...
        sd    zero, v_len(zero)         ; ...
        li    t0, -1                    ; ...
        sd    t0, v_wb(zero)            ; ...
        li    a0, vpath                 ; ...
        ld    a1, vpl(zero)             ; ...
        li    a2, 0                     ; ...
        call  sys_open                  ; ...
        mv    s0, a0                    ; ...
        bltz  a0, vf_r                  ; ...
vf_sk:  beqz  s1, vf_rd                 ; ...
        mv    a2, s1                    ; ...
        li    t0, 4032                  ; ...
        bleu  a2, t0, vf_s1             ; ...
        mv    a2, t0                    ; ...
vf_s1:  mv    a0, s0                    ; ...
        li    a1, lbuf                  ; ...
        call  read_full                 ; ...
        beqz  a0, vf_c                  ; ...
        sub   s1, s1, a0                ; ...
        j     vf_sk                     ; ...
vf_rd:  mv    a0, s0                    ; ...
        li    a1, VBASE                 ; ...
        li    a2, VREG                  ; ...
        call  read_far                  ; ...
        sd    a0, v_len(zero)           ; ...
vf_c:   mv    a0, s0                    ; ...
        call  sys_close                 ; ...
vf_r:   ld    ra, 0(sp)                 ; ...
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; v_istext() -> a0 = 1 if the first 1024 bytes have no zero byte
v_istext:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s0, 8(sp)                 ; ...
        li    s0, 0                     ; ...
vit_l:  li    t0, 1024                  ; ...
        bgeu  s0, t0, vit_y             ; ...
        mv    a0, s0                    ; ...
        call  v_at                      ; ...
        bltz  a0, vit_y                 ; ...
        beqz  a0, vit_n                 ; ...
        addi  s0, s0, 1                 ; ...
        j     vit_l                     ; ...
vit_y:  li    a0, 1                     ; ...
        j     vit_r                     ; ...
vit_n:  li    a0, 0                     ; ...
vit_r:  ld    ra, 0(sp)                 ; ...
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; v_rowend(a0 = a row's start) -> a0 = the next row's start (text: a line,
; or as much of it as the screen is wide; hex: 16 bytes)
v_rowend:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s0, 8(sp)                 ; s0 = the offset
        sd    s1, 16(sp)                ; s1 = the column
        sd    s2, 24(sp)                ; ...
        mv    s0, a0                    ; ...
        ld    t0, v_hex(zero)           ; ...
        beqz  t0, vr_t                  ; ...
        addi  s0, s0, 16                ; ...
        j     vr_r                      ; ...
vr_t:   li    s1, 0                     ; ...
vr_l:   mv    a0, s0                    ; ...
        call  v_at                      ; ...
        bltz  a0, vr_r                  ; ...
        addi  s0, s0, 1                 ; ...
        li    t0, 10                    ; ...
        beq   a0, t0, vr_r              ; ...
        li    t0, 9                     ; a tab: to the next multiple of 8
        bne   a0, t0, vr_c              ; ...
        ori   s1, s1, 7                 ; ...
vr_c:   addi  s1, s1, 1                 ; ...
        ld    t0, scols(zero)           ; ...
        bltu  s1, t0, vr_l              ; ...
        mv    a0, s0                    ; (wrapped: unless a newline is next)
        call  v_at                      ; ...
        li    t0, 10                    ; ...
        bne   a0, t0, vr_r              ; ...
        addi  s0, s0, 1                 ; ...
vr_r:   mv    a0, s0                    ; ...
        ld    ra, 0(sp)                 ; ...
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; v_down(a0 = rows): the top moves down (not past the last row)
v_down:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s0, 8(sp)                 ; ...
        mv    s0, a0                    ; ...
vd_l:   blez  s0, vd_r                  ; ...
        ld    a0, v_top(zero)           ; ...
        call  v_rowend                  ; ...
        ld    t0, v_size(zero)          ; ...
        bgeu  a0, t0, vd_r              ; ...
        sd    a0, v_top(zero)           ; ...
        addi  s0, s0, -1                ; ...
        j     vd_l                      ; ...
vd_r:   ld    ra, 0(sp)                 ; ...
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; v_up(a0 = rows): the top moves up
v_up:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s0, 8(sp)                 ; s0 = rows left
        sd    s1, 16(sp)                ; s1 = a row's start
        sd    s2, 24(sp)                ; s2 = the one after it
        sd    s3, 32(sp)                ; ...
        mv    s0, a0                    ; ...
vu_l:   blez  s0, vu_r                  ; ...
        ld    t0, v_top(zero)           ; ...
        beqz  t0, vu_r                  ; ...
        ld    t1, v_hex(zero)           ; hex: 16 bytes back
        beqz  t1, vu_t                  ; ...
        addi  t0, t0, -16               ; ...
        sd    t0, v_top(zero)           ; ...
        addi  s0, s0, -1                ; ...
        j     vu_l                      ; ...
vu_t:   addi  s1, t0, -1                ; text: the line before the top starts after the
vu_b:   beqz  s1, vu_f                  ;   newline before it
        addi  a0, s1, -1                ; ...
        call  v_at                      ; ...
        li    t0, 10                    ; ...
        beq   a0, t0, vu_f              ; ...
        addi  s1, s1, -1                ; ...
        j     vu_b                      ; ...
vu_f:   mv    a0, s1                    ; then its rows: the last one before the top
        call  v_rowend                  ; ...
        ld    t0, v_top(zero)           ; ...
        bgeu  a0, t0, vu_g              ; ...
        mv    s1, a0                    ; ...
        j     vu_f                      ; ...
vu_g:   sd    s1, v_top(zero)           ; ...
        addi  s0, s0, -1                ; ...
        j     vu_l                      ; ...
vu_r:   ld    ra, 0(sp)                 ; ...
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        addi  sp, sp, 40                ; ...
        ret                             ; ...

; v_draw(): the viewer's screen: the rows from v_top, the status line
v_draw:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s0, 8(sp)                 ; s0 = the row
        sd    s1, 16(sp)                ; s1 = the offset
        sd    s2, 24(sp)                ; s2 = the next row's start
        sd    s3, 32(sp)                ; ...
        li    a0, s_hide                ; ...
        li    a1, 6                     ; ...
        call  out_str                   ; ...
        ld    t0, clear(zero)           ; ...
        beqz  t0, vw_0                  ; ...
        sd    zero, clear(zero)         ; ...
        li    a0, s_cls                 ; ...
        li    a1, 11                    ; ...
        call  out_str                   ; ...
        li    t0, 0                     ; ...
vw_h:   li    t1, NROWS                 ; ...
        bgeu  t0, t1, vw_0              ; ...
        slli  t1, t0, 3                 ; ...
        li    t2, 1                     ; ...
        sd    t2, rowh(t1)              ; ...
        addi  t0, t0, 1                 ; ...
        j     vw_h                      ; ...
vw_0:   li    s0, 0                     ; ...
        ld    s1, v_top(zero)           ; ...
vw_l:   ld    t0, srows(zero)           ; ...
        addi  t0, t0, -1                ; ...
        bgeu  s0, t0, vw_st             ; ...
        li    a0, c_off                 ; ...
        call  rb_col4                   ; ...
        mv    a0, s1                    ; ...
        call  v_rowend                  ; ...
        mv    s2, a0                    ; ...
        ld    t0, v_size(zero)          ; past the end: an empty row
        bgeu  s1, t0, vw_e              ; ...
        ld    t0, v_hex(zero)           ; ...
        bnez  t0, vw_hx                 ; ...
vw_tl:  bgeu  s1, s2, vw_e              ; a text row
        mv    a0, s1                    ; ...
        call  v_at                      ; ...
        addi  s1, s1, 1                 ; ...
        li    t0, 10                    ; ...
        beq   a0, t0, vw_tl             ; ...
        li    t0, 9                     ; ...
        bne   a0, t0, vw_tc             ; ...
vw_tab: li    a0, ' '                   ; ...
        call  rb_chr                    ; ...
        ld    t0, rbc(zero)             ; ...
        andi  t0, t0, 7                 ; ...
        bnez  t0, vw_tab                ; ...
        j     vw_tl                     ; ...
vw_tc:  ld    t0, rbc(zero)             ; (never past the screen)
        ld    t1, scols(zero)           ; ...
        bgeu  t0, t1, vw_tl             ; ...
        call  rb_chr                    ; ...
        j     vw_tl                     ; ...
vw_hx:  mv    a0, s1                    ; a hex row: the offset, 16 bytes, their characters
        li    a1, 8                     ; ...
        call  rb_hexn                   ; ...
        li    a0, 2                     ; ...
        call  rb_pad                    ; ...
        li    s3, 0                     ; ...
vw_hb:  li    t0, 16                    ; ...
        bgeu  s3, t0, vw_ha             ; ...
        add   a0, s1, s3                ; ...
        call  v_at                      ; ...
        bltz  a0, vw_hs                 ; ...
        call  rb_hex2                   ; ...
        li    a0, ' '                   ; ...
        call  rb_chr                    ; ...
        j     vw_hn                     ; ...
vw_hs:  li    a0, 3                     ; ...
        call  rb_pad                    ; ...
vw_hn:  li    t0, 7                     ; (a gap after 8)
        bne   s3, t0, vw_hn2            ; ...
        li    a0, ' '                   ; ...
        call  rb_chr                    ; ...
vw_hn2: addi  s3, s3, 1                 ; ...
        j     vw_hb                     ; ...
vw_ha:  li    a0, ' '                   ; ...
        call  rb_chr                    ; ...
        li    s3, 0                     ; ...
vw_hc:  li    t0, 16                    ; ...
        bgeu  s3, t0, vw_e              ; ...
        add   a0, s1, s3                ; ...
        call  v_at                      ; ...
        bltz  a0, vw_e                  ; ...
        addi  t0, a0, -32               ; (others: ".")
        li    t1, 95                    ; ...
        bltu  t0, t1, vw_hc2            ; ...
        li    a0, '.'                   ; ...
vw_hc2: call  rb_chr                    ; ...
        addi  s3, s3, 1                 ; ...
        j     vw_hc                     ; ...
vw_e:   ld    a0, scols(zero)           ; the rest of the row
        ld    t0, rbc(zero)             ; ...
        sub   a0, a0, t0                ; ...
        call  rb_pad                    ; ...
        mv    a0, s0                    ; ...
        call  rb_out                    ; ...
        mv    s1, s2                    ; ...
        addi  s0, s0, 1                 ; ...
