main:
        call  sys_init                  ; handles, arguments
        li    a0, 1                     ; Ctrl-C makes a read return -2 (it does not end us)
        call  sys_catch                 ; ...
        li    a0, 0                     ; standard input: the console?
        call  sys_hdesc                 ; (server register << 32 | id)
        srli  a0, a0, 32                ; 3 = tty
        addi  a0, a0, -3                ; ...
        seqz  a0, a0                    ; ...
        sd    a0, con(zero)             ; ...
        call  raw_on                    ; raw keys
        li    a0, args                  ; our arguments
        call  sys_args                  ; a0 = their length
        li    s0, args                  ; s0 = cursor
        add   s1, s0, a0                ; s1 = end
        li    s2, 0                     ; s2 = paths given
mn_arg: mv    a0, s0                    ; the next word
        mv    a1, s1                    ; ...
        call  arg_next                  ; a0 = start, a1 = length, a2 = after it
        beqz  a1, mn_argd               ; ...
        mv    s0, a2                    ; ...
        mv    s3, a0                    ; s3, s4 = the word
        mv    s4, a1                    ; ...
        li    a2, s_e                   ; -e EDITOR?
        li    a3, 2                     ; ...
        call  str_eq                    ; ...
        bnez  a0, mn_ed                 ; ...
        mv    a0, s3                    ; -s TEXT: a search at the start
        mv    a1, s4                    ; ...
        li    a2, s_s                   ; ...
        li    a3, 2                     ; ...
        call  str_eq                    ; ...
        beqz  a0, mn_path               ; ...
        mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        call  arg_next                  ; ...
        beqz  a1, mn_argd               ; ...
        mv    s0, a2                    ; ...
        li    t0, 100                   ; ...
        bgtu  a1, t0, mn_arg            ; ...
        sd    a1, s_len(zero)           ; ...
        mv    a2, a1                    ; ...
        mv    a1, a0                    ; ...
        li    a0, stext                 ; ...
        call  bcopy                     ; ...
        j     mn_arg                    ; ...
mn_ed:
        mv    a0, s0                    ; the editor's name
        mv    a1, s1                    ; ...
        call  arg_next                  ; ...
        beqz  a1, mn_argd               ; ...
        mv    s0, a2                    ; ...
        li    t0, 60                    ; ...
        bgtu  a1, t0, mn_arg            ; ...
        sd    a1, ed_len(zero)          ; ...
        mv    a2, a1                    ; ...
        mv    a1, a0                    ; ...
        li    a0, editor                ; ...
        call  bcopy                     ; ...
        j     mn_arg                    ; ...
mn_path:
        li    t0, 2                     ; a directory for a panel
        bgeu  s2, t0, mn_arg            ; ...
        mv    a0, s2                    ; ...
        mv    a1, s3                    ; ...
        mv    a2, s4                    ; ...
        call  set_path                  ; ...
        addi  s2, s2, 1                 ; ...
        j     mn_arg                    ; ...
mn_argd:
        bnez  s2, mn_r                  ; none: the left one is the current directory
        li    a0, pth                   ; ...
        call  sys_cwd                   ; a0 = its length
        mv    a2, a0                    ; ...
        li    a0, 0                     ; ...
        li    a1, pth                   ; ...
        call  set_path                  ; ...
        li    s2, 1                     ; ...
mn_r:   li    t0, 1                     ; no right one: the root
        bne   s2, t0, mn_go             ; ...
        li    a0, 1                     ; ...
        li    a1, pth                   ; ...
        li    a2, 0                     ; ...
        call  set_path                  ; ...
mn_go:  li    a0, s_ask                 ; ask the terminal its size; the answer comes
        li    a1, 14                    ;   while the disk is read
        call  out_str                   ; ...
        li    a0, s_mon                 ; mouse reports
        li    a1, 16                    ; ...
        call  out_str                   ; ...
        call  out_flush                 ; ...
        call  heap_init                 ; far memory that grows: the first 1 MiB from proc
        bltz  a0, mn_nomem              ; ...
        call  tags_load                 ; the tags' names
        li    a0, 0                     ; the two panels
        call  pan_load                  ; ...
        li    a0, 1                     ; ...
        call  pan_load                  ; ...
        li    a0, 100                   ; the size: an answer within 0.2 s
        call  rd_wait                   ; ...
        beqz  a0, ml_top                ; none: 80 x 24
        ld    t0, kb_pos(zero)          ; a key first (a script): no answer is coming
        lbu   t0, kbuf(t0)              ; ...
        li    t1, 27                    ; ...
        bne   t0, t1, ml_top            ; ...
        call  getkey                    ; a report sets the size; a key waits for its command
        li    t0, KY_SIZE               ; ...
        beq   a0, t0, ml_top            ; ...
        sd    a0, k_pend(zero)          ; ...
        ld    t0, s_len(zero)           ; -s: the search now
        beqz  t0, ml_top                ; ...
        li    t0, 1                     ; ...
        sd    t0, s_on(zero)            ; ...
        sd    zero, s_pan(zero)         ; ...
        sd    zero, act(zero)           ; ...
        li    t0, 1                     ; (to its end: keys typed already wait)
        sd    t0, s_whole(zero)         ; ...
        call  search                    ; ...
        sd    zero, s_whole(zero)       ; ...
ml_top: call  draw                      ; ---- the main loop: show, then one key
        call  getkey                    ; ...
        call  command                   ; ...
        ld    t0, s_on(zero)            ; a search that a key cut short goes on
        beqz  t0, ml_q                  ; ...
        ld    t0, s_part(zero)          ; ...
        beqz  t0, ml_q                  ; ...
        ld    t0, kb_pos(zero)          ; (unless more keys wait)
        ld    t1, kb_len(zero)          ; ...
        bltu  t0, t1, ml_q              ; ...
        ld    a0, s_pan(zero)           ; (the cursor stays where the keys put it)
        call  pan_addr                  ; ...
        ld    t0, P_CUR(a0)             ; ...
        sd    t0, s_keep(zero)          ; ...
        call  search                    ; ...
        ld    a0, s_pan(zero)           ; ...
        call  pan_addr                  ; ...
        ld    t0, s_keep(zero)          ; ...
        sd    t0, P_CUR(a0)             ; ...
        j     ml_q                      ; ...
mn_nomem:
        call  bye                       ; no memory for even the first MiB
        li    a0, m_nomem               ; ...
        li    a1, m_nomem_e - m_nomem   ; ...
        call  err_str                   ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...
ml_q:   ld    t0, quit(zero)            ; leaving?
        beqz  t0, ml_top                ; ...
        call  bye                       ; the screen and the terminal back
        li    a0, 0                     ; exit code
        call  sys_exit                  ; flush stdout, end the process

; bye(): the terminal as the shell wants it: no mouse reports, colours off,
; the screen cleared, the cursor on, cooked keys
bye:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        li    a0, s_moff                ; ...
        li    a1, 16                    ; ...
        call  out_str                   ; ...
        li    a0, s_cls                 ; ...
        li    a1, 11                    ; ...
        call  out_str                   ; ...
        li    a0, s_show                ; ...
        li    a1, 6                     ; ...
        call  out_str                   ; ...
        call  out_flush                 ; ...
        ld    t0, con(zero)             ; the console back to cooked mode
        beqz  t0, by_r                  ; ...
        li    a0, 0                     ; ...
        call  sys_conmode               ; ...
by_r:   ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; raw_on(): keys as they come, no echo (the console; a window's pipe is raw)
raw_on:
        ld    t0, con(zero)             ; ...
        beqz  t0, ro_r                  ; ...
        li    a0, 1                     ; ...
        j     sys_conmode               ; (tail call)
ro_r:   ret                             ; ...

; set_path(a0 = panel, a1 = text, a2 = length): the panel's directory; a path
; that does not start with "/" is made absolute ("/" in front)
set_path:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s0, 8(sp)                 ; ...
        sd    s1, 16(sp)                ; ...
        sd    s2, 24(sp)                ; ...
        call  pan_addr                  ; s0 = the panel
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        mv    s2, a2                    ; ...
        li    t0, PATHMAX - 2           ; (too long: the root)
        bleu  s2, t0, sp_1              ; ...
        li    s2, 0                     ; ...
sp_1:   li    t0, '/'                   ; the leading "/"
        sb    t0, P_PATH(s0)            ; ...
        li    t1, 1                     ; ...
        beqz  s2, sp_2                  ; ...
        lbu   t2, 0(s1)                 ; ...
        bne   t2, t0, sp_2              ; ...
        li    t1, 0                     ; (it has one)
sp_2:   add   a0, s0, t1                ; the text after it
        addi  a0, a0, P_PATH            ; ...
        add   t3, t1, s2                ; ...
        sd    t3, P_PL(s0)              ; ...
        mv    a1, s1                    ; ...
        mv    a2, s2                    ; ...
        call  bcopy                     ; ...
        mv    a0, s0                    ; tidy: no "/" at the end but the root's
        call  path_trim                 ; ...
        ld    ra, 0(sp)                 ; ...
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; path_trim(a0 = panel): its path loses a "/" at the end (not the root's)
path_trim:
        ld    t0, P_PL(a0)              ; ...
pt_l:   li    t1, 1                     ; ...
        bleu  t0, t1, pt_r              ; ...
        add   t2, a0, t0                ; ...
        lbu   t2, P_PATH-1(t2)          ; ...
        li    t1, '/'                   ; ...
        bne   t2, t1, pt_r              ; ...
        addi  t0, t0, -1                ; ...
        j     pt_l                      ; ...
pt_r:   sd    t0, P_PL(a0)              ; ...
        ret                             ; ...

; pan_addr(a0 = panel) -> a0 = its state
pan_addr:
        slli  a0, a0, 9                 ; (P_SIZE = 512: no register but a0 used)
        addi  a0, a0, pans              ; ...
        ret                             ; ...

; is_root(a0 = panel state) -> a0 = 1 if its path is "/" or "/@NAME"
is_root:
        ld    t0, P_PL(a0)              ; ...
        li    t1, 1                     ; ...
        bleu  t0, t1, ir_y              ; ...
        lbu   t1, P_PATH+1(a0)          ; ...
        li    t2, '@'                   ; ...
        bne   t1, t2, ir_n              ; ...
        addi  t3, a0, P_PATH+1          ; no other "/"
        add   t4, a0, t0                ; ...
        addi  t4, t4, P_PATH            ; ...
        li    t2, '/'                   ; ...
ir_l:   bgeu  t3, t4, ir_y              ; ...
        lbu   t1, 0(t3)                 ; ...
        beq   t1, t2, ir_n              ; ...
        addi  t3, t3, 1                 ; ...
        j     ir_l                      ; ...
ir_y:   li    a0, 1                     ; ...
        ret                             ; ...
ir_n:   li    a0, 0                     ; ...
        ret                             ; ...

