; rd_byte() -> a0 = the next input byte, -1 at the end of input, -2 interrupted
rd_byte:
        ld    t0, kb_pos(zero)          ; one waiting?
        ld    t1, kb_len(zero)          ; ...
        bltu  t0, t1, rb_have           ; yes
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save ra
        call  out_flush                 ; the screen is up to date before we wait
        li    a0, 0                     ; read standard input (raw: what is there)
        li    a1, kbuf                  ; ...
        li    a2, 64                    ; ...
        call  sys_read                  ; a0 = bytes, 0 the end, -2 interrupted
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 8                 ; release the frame
        sd    zero, kb_pos(zero)        ; the buffer starts again
        sd    zero, kb_len(zero)        ; ...
        bgtz  a0, rb_got                ; bytes
        li    t0, -2                    ; interrupted: -2
        beq   a0, t0, rb_r              ; ...
        li    a0, -1                    ; the end of input
rb_r:   ret                             ; done
rb_got: sd    a0, kb_len(zero)          ; ...
        li    t0, 0                     ; the first
rb_have:
        lbu   a0, kbuf(t0)              ; the byte
        addi  t0, t0, 1                 ; consumed
        sd    t0, kb_pos(zero)          ; ...
        ret                             ; done

; rd_wait(a0 = polls) -> a0 = 1 if an input byte is waiting (asking without
; blocking up to a0 times more, 2 ms apart), 0 if none came
rd_wait:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = polls left
        mv    s0, a0                    ; ...
rw_l:   ld    t0, kb_pos(zero)          ; one waiting?
        ld    t1, kb_len(zero)          ; ...
        li    a0, 1                     ; ...
        bltu  t0, t1, rw_r              ; yes
        call  out_flush                 ; (the screen first)
        li    a0, 0                     ; ask standard input without blocking
        li    a1, kbuf                  ; ...
        li    a2, 64                    ; ...
        call  sys_readnb                ; a0 = bytes, -3 none yet, 0 the end, -2
        blez  a0, rw_no                 ; ...
        sd    a0, kb_len(zero)          ; bytes
        sd    zero, kb_pos(zero)        ; ...
        li    a0, 1                     ; ...
        j     rw_r                      ; ...
rw_no:  li    t0, -3                    ; nothing yet: wait and ask again
        bne   a0, t0, rw_0              ; (the end, an interrupt: stop)
        beqz  s0, rw_0                  ; no polls left
        addi  s0, s0, -1                ; ...
        li    a0, 2000                  ; 2 ms
        call  sys_sleep                 ; -8, or -2 interrupted
        li    t0, -2                    ; interrupted: that is a Ctrl-C for getkey
        bne   a0, t0, rw_l              ; ...
        li    t0, 1                     ; ...
        sd    t0, sys_intrf(zero)       ; ...
rw_0:   li    a0, 0                     ; none
rw_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 16                ; release the frame
        ret                             ; done

; getkey() -> a0 = the next key: a byte, or KY_* (arrows, editing keys,
; F-keys, a mouse report, a size report, the end of input). An interrupt is
; the key 3 (Ctrl-C).
getkey:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = the number being read
        sd    s1, 16(sp)                ; s1 = numbers read before it (up to 3, in 24(sp)..)
        sd    s2, 40(sp)                ; s2 = 1: ESC [ <
gk_top: ld    a0, k_pend(zero)          ; a key put back?
        beqz  a0, gk_in                 ; ...
        sd    zero, k_pend(zero)        ; once
        j     gk_ret                    ; ...
gk_in:  ld    t0, sys_intrf(zero)       ; an interrupt came while we were busy?
        beqz  t0, gk_rd                 ; ...
        sd    zero, sys_intrf(zero)     ; ...
        li    a0, 3                     ; Ctrl-C
        j     gk_ret                    ; ...
gk_rd:  call  rd_byte                   ; a byte
        li    t0, -2                    ; interrupted: Ctrl-C
        bne   a0, t0, gk_b              ; ...
        sd    zero, sys_intrf(zero)     ; (seen)
        li    a0, 3                     ; ...
        j     gk_ret                    ; ...
gk_b:   bgez  a0, gk_nd                 ; the end of input
        li    a0, KY_EOF                ; ...
        j     gk_ret                    ; ...
gk_nd:  li    t0, 27                    ; ESC: the start of a sequence?
        bne   a0, t0, gk_ret            ; ...
        li    a0, 15                    ; a byte within 30 ms ...
        call  rd_wait                   ; ...
        beqz  a0, gk_esc                ; ...
        call  rd_byte                   ; ... that is "[" or "O"
        li    t0, '['                   ; ...
        beq   a0, t0, gk_csi            ; ...
        li    t0, 'O'                   ; ESC O P..S: F1..F4
        beq   a0, t0, gk_ss3            ; ...
        ld    t0, kb_pos(zero)          ; no: that byte is the next key
        addi  t0, t0, -1                ; ...
        sd    t0, kb_pos(zero)          ; ...
gk_esc: li    a0, 27                    ; the Esc key
        j     gk_ret                    ; ...
gk_ss3: call  rd_byte                   ; ...
        addi  a0, a0, -'P'              ; ...
        li    t0, 4                     ; ...
        bgeu  a0, t0, gk_top            ; ...
        addi  a0, a0, KY_F1             ; ...
        j     gk_ret                    ; ...
gk_csi: li    s0, 0                     ; ESC [
        li    s1, 0                     ; ...
        li    s2, 0                     ; ...
        sd    zero, 24(sp)              ; ...
        sd    zero, 32(sp)              ; ...
gk_cn:  call  rd_byte                   ; the next byte of the sequence
        bltz  a0, gk_top                ; (the end, an interrupt: the sequence is dropped)
        addi  t0, a0, -'0'              ; a digit?
        li    t1, 10                    ; ...
        bgeu  t0, t1, gk_cs             ; ...
        mul   s0, s0, t1                ; ...
        add   s0, s0, t0                ; ...
        j     gk_cn                     ; ...
gk_cs:  li    t1, ';'                   ; a separator
        bne   a0, t1, gk_lt             ; ...
        li    t1, 2                     ; (the first two kept)
        bgeu  s1, t1, gk_cs1            ; ...
        slli  t1, s1, 3                 ; ...
        add   t1, t1, sp                ; ...
        sd    s0, 24(t1)                ; ...
gk_cs1: addi  s1, s1, 1                 ; ...
        li    s0, 0                     ; ...
        j     gk_cn                     ; ...
gk_lt:  li    t1, '<'                   ; ESC [ <: a mouse report
        bne   a0, t1, gk_cf             ; ...
        li    s2, 1                     ; ...
        j     gk_cn                     ; ...
gk_cf:  li    t1, 0x40                  ; other bytes below the final one: skipped
        blt   a0, t1, gk_cn             ; ...
        beqz  s2, gk_cr                 ; ESC [ < b ; x ; y M / m
        ld    t0, 24(sp)                ; ...
        sd    t0, m_b(zero)             ; ...
        ld    t0, 32(sp)                ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, m_x(zero)             ; ...
        addi  t0, s0, -1                ; ...
        sd    t0, m_y(zero)             ; ...
        li    t1, 'm'                   ; ...
        sub   t1, a0, t1                ; ...
        seqz  t1, t1                    ; ...
        sd    t1, m_rel(zero)           ; ...
        li    a0, KY_MOUSE              ; ...
        j     gk_ret                    ; ...
gk_cr:  li    t1, 'R'                   ; ESC [ rows ; columns R: the size
        bne   a0, t1, gk_ct             ; ...
        ld    a0, 24(sp)                ; ...
        mv    a1, s0                    ; ...
        call  set_size                  ; ...
        li    a0, KY_SIZE               ; ...
        j     gk_ret                    ; ...
gk_ct:  li    t1, '~'                   ; ESC [ n ~
        bne   a0, t1, gk_cl             ; ...
        li    t1, 22                    ; ...
        bgeu  s0, t1, gk_top            ; ...
        lbu   a0, tildes(s0)            ; ...
        beqz  a0, gk_top                ; ...
        addi  a0, a0, 0x100             ; ...
        j     gk_ret                    ; ...
gk_cl:  li    t1, 0                     ; ESC [ A..D H F: arrows, Home, End
gk_cl1: lbu   t2, csilet(t1)            ; ...
        addi  t1, t1, 1                 ; ...
        beq   t2, a0, gk_cl2            ; ...
        li    t3, 6                     ; ...
        blt   t1, t3, gk_cl1            ; ...
        j     gk_top                    ; anything else: ignored
gk_cl2: addi  a0, t1, 0x100             ; KY_UP + index
gk_ret: ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 40(sp)                ; ...
        addi  sp, sp, 48                ; release the frame
        ret                             ; done


; set_size(a0 = rows, a1 = columns): the screen's size (from a report)
set_size:
        li    t0, 10                    ; nonsense is ignored
        blt   a0, t0, ss_r              ; ...
        li    t0, 40                    ; ...
        blt   a1, t0, ss_r              ; ...
        li    t0, NROWS                 ; at most NROWS x NCOLS are used
        ble   a0, t0, ss_1              ; ...
        mv    a0, t0                    ; ...
ss_1:   li    t0, NCOLS                 ; ...
        ble   a1, t0, ss_2              ; ...
        mv    a1, t0                    ; ...
ss_2:   sd    a0, srows(zero)           ; ...
        sd    a1, scols(zero)           ; ...
        srli  a1, a1, 1                 ; ...
        sd    a1, pw0(zero)             ; ...
        li    t0, 1                     ; the screen is cleared and drawn again
        sd    t0, clear(zero)           ; ...
ss_r:   ret                             ; done

