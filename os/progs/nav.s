; rb_hexn(a0 = value, a1 = digits): hex digits
rb_hexn:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s0, 8(sp)                 ; ...
        sd    s1, 16(sp)                ; ...
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
rh_l:   blez  s1, rh_r                  ; ...
        addi  s1, s1, -1                ; ...
        slli  t0, s1, 2                 ; ...
        srl   a0, s0, t0                ; ...
