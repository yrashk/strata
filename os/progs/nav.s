kr_l:   li    t0, 10                    ; ...
        bgeu  s0, t0, kr_e              ; ...
        li    a0, c_knum                ; ...
        call  rb_col4                   ; ...
        addi  a0, s0, 1                 ; ...
        call  num_txt                   ; ...
        mv    s2, a1                    ; ...
        call  rb_rawc                   ; ...
        li    a0, c_klab                ; ...
        call  rb_col10                  ; ...
        li    t0, 6                     ; ...
        mul   a0, s0, t0                ; ...
        addi  a0, a0, fkeys             ; ...
        li    a1, 6                     ; ...
        sub   a2, s1, s2                ; ...
        call  rb_fit                    ; ...
        addi  s0, s0, 1                 ; ...
        j     kr_l                      ; ...
kr_e:   li    a0, c_off                 ; ...
        call  rb_col4                   ; ...
        ld    a0, scols(zero)           ; ...
        addi  a0, a0, -1                ; ...
        ld    t0, rbc(zero)             ; ...
        sub   a0, a0, t0                ; ...
        call  rb_pad                    ; ...
        ld    ra, 0(sp)                 ; ...
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; msg_set(a0 = text, a1 = length): the message on the command line
msg_set:
