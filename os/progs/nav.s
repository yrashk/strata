        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s0, 8(sp)                 ; ...
        li    a0, c_line                ; ...
        call  rb_col4                   ; ...
        ld    t0, pr_on(zero)           ; a prompt
        beqz  t0, cr_s                  ; ...
        li    a0, prq                   ; ...
        ld    a1, pr_ql(zero)           ; ...
        call  rb_rawc                   ; ...
        li    a0, c_find                ; ...
        li    a1, 7                     ; ...
        call  rb_raw                    ; ...
        li    a0, pra                   ; ...
        ld    a1, pr_len(zero)          ; ...
        call  rb_rawc                   ; ...
        j     cr_pad                    ; ...
cr_s:   ld    t0, c_mode(zero)          ; the command line: the directory, "$ ", the text
        beqz  t0, cr_s0                 ; ...
        call  c_prompt                  ; ...
        call  rb_rawc                   ; ...
        li    a0, c_find                ; ...
        li    a1, 7                     ; ...
        call  rb_raw                    ; ...
        li    a0, ctext                 ; ...
        ld    a1, c_len(zero)           ; ...
        call  rb_rawc                   ; ...
        ld    t0, c_len(zero)           ; (empty: a hint after it, or the message)
        bnez  t0, cr_pad                ; ...
        li    a0, c_dim                 ; ...
        li    a1, 7                     ; ...
        call  rb_raw                    ; ...
        li    a0, 2                     ; ...
        call  rb_pad                    ; ...
        li    a0, msg                   ; ...
        ld    a1, msgl(zero)            ; ...
        bnez  a1, cr_cm                 ; ...
        li    a0, t_chint               ; ...
        li    a1, t_chint_e - t_chint   ; ...
cr_cm:  ld    a2, scols(zero)           ; ...
        ld    t0, rbc(zero)             ; ...
        sub   a2, a2, t0                ; ...
        call  rb_fit                    ; ...
        j     cr_pad                    ; ...
cr_s0:  ld    t0, s_on(zero)            ; the search
        beqz  t0, cr_m                  ; ...
        li    a0, t_find                ; ...
        li    a1, 6                     ; ...
        call  rb_rawc                   ; ...
        li    a0, c_find                ; ...
        li    a1, 7                     ; ...
        call  rb_raw                    ; ...
        li    a0, stext                 ; ...
        ld    a1, s_len(zero)           ; ...
        call  rb_rawc                   ; ...
        li    a0, c_dim                 ; ...
        li    a1, 7                     ; ...
        call  rb_raw                    ; ...
        li    a0, 3                     ; ...
        call  rb_pad                    ; ...
        ld    a0, s_pan(zero)           ; N found
        call  pan_addr                  ; ...
        mv    s0, a0                    ; ...
        ld    a0, P_N(s0)               ; ...
        call  num_txt                   ; ...
        call  rb_rawc                   ; ...
        ld    t0, P_MORE(s0)            ; ...
        beqz  t0, cr_s1                 ; ...
        li    a0, '+'                   ; ...
        call  rb_chr                    ; ...
cr_s1:  li    a0, t_fnd                 ; ...
        li    a1, 6                     ; ...
        call  rb_rawc                   ; ...
        ld    t0, s_t1(zero)            ; the times
        beqz  t0, cr_pad                ; ...
        li    a0, t_frst                ; ...
        li    a1, 8                     ; ...
        call  rb_rawc                   ; ...
        ld    a0, s_t1(zero)            ; ...
        call  rb_ms                     ; ...
        ld    t0, s_t2(zero)            ; ...
        beqz  t0, cr_pad                ; ...
        li    a0, t_all                 ; ...
        li    a1, 6                     ; ...
        call  rb_rawc                   ; ...
        ld    a0, s_t2(zero)            ; ...
        call  rb_ms                     ; ...
        j     cr_pad                    ; ...
cr_m:   ld    a1, msgl(zero)            ; a message
        beqz  a1, cr_h                  ; ...
        li    a0, msg                   ; ...
        call  rb_rawc                   ; ...
        j     cr_pad                    ; ...
cr_h:   li    a0, c_dim                 ; the hint
        li    a1, 7                     ; ...
        call  rb_raw                    ; ...
        li    a0, t_hint                ; ...
        li    a1, t_hint_e - t_hint     ; ...
        ld    a2, scols(zero)           ; ...
        call  rb_fit                    ; ...
cr_pad: li    a0, c_off                 ; ...
        call  rb_col4                   ; ...
        ld    a0, scols(zero)           ; the rest of the row
        ld    t0, rbc(zero)             ; ...
        sub   a0, a0, t0                ; ...
        bltz  a0, cr_r                  ; ...
        call  rb_pad                    ; ...
cr_r:   ld    ra, 0(sp)                 ; ...
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; key_row(): the function keys, as numbers and labels, in the columns there
