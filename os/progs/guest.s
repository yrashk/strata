; =============================================================================
; guest.s: start, stop and list guest operating systems
; =============================================================================
;
;   guest [-d] <image> [cores] [MiB]  boot <image> as a guest on `cores` cores
;                                 (default 2) with an arena of `MiB` (default 8),
;                                 and give it the console (-d: leave it detached)
;   guest attach <id>             give the console to a running guest
;   guest stop <id>               stop a guest: reset its cores and reclaim them
;   guest                         list the running guests
;   guest list                    the same
;
; A guest is a second operating system that StrataOS runs on whole worker cores
; in supervisor mode, beside itself (doc/strataos.md, "Guests"). `guest` asks
; the process server (proc), which gets an arena, loads the image into it and
; calls the kernel. The image is a file tagged `guest`: <image>, or else
; <image>.g (so `guest forth` boots forth.g, the bare-metal Forth: the name
; forth is the StrataOS program's). Example: `guest -d gdemo 2 8` boots
; os/guests/gdemo as a guest on 2 cores; `cores` then shows them as a guest's;
; `guest stop 240` ends it and the cores return to StrataOS.
;
; The console: without -d, `guest` then ATTACHes the console to the guest (a
; tty request, os/servers/tty.s) and waits: what is typed goes to the guest
; (its READs), and StrataOS's shell waits, until Ctrl-] is typed (or Ctrl-C,
; or the guest closes the console, or it is stopped). Then `guest` says how to
; go back (`guest attach <id>`) or end it (`guest stop <id>`), and the shell
; has the console again. A guest's output reaches the console either way.

GSTART  = 40                            ; proc operations
GSTOP   = 41                            ; ...
GLIST   = 42                            ; ...

        .data                           ; data Local Store
        .align 8                        ; ...
args:   .space 512                      ; the argument text
reqb:   .space 512                      ; the request data
tab:    .space 8 + 32 * 4               ; the guest list
m_start: .ascii "guest"                 ; "guest started: id N, core C"
m_start_e:
m_on:   .ascii " started: id "
m_on_e:
m_core: .ascii ", core "
m_core_e:
m_stopd: .ascii "guest stopped\n"
m_stopd_e:
m_none: .ascii "no guests running\n"
m_none_e:
m_hdr:  .ascii "  ID  CORES  ARENA(MiB)  STATE\n"
m_hdr_e:
m_live: .ascii "live"
m_live_e:
m_sp:   .ascii "       "                ; padding
m_usage: .ascii "usage: guest [-d] <image> [cores] [MiB] | guest attach <id> | guest stop <id> | guest\n"
m_usage_e:
m_att:  .ascii " has the console: Ctrl-] gives it back to StrataOS\n"
m_att_e:
m_det:  .ascii " detached: `guest attach "       ; ... N` returns to it, `guest stop N` ends it
m_det_e:
m_det2: .ascii "` returns to it, `guest stop "
m_det2_e:
m_det3: .ascii "` ends it\n"
m_det3_e:
m_clo:  .ascii " closed the console: `guest stop "
m_clo_e:
m_clo2: .ascii "` reclaims its cores\n"
m_clo2_e:
m_gone: .ascii " was stopped\n"
m_gone_e:
m_busy: .ascii "guest: the console is attached to a guest already\n"
m_busy_e:
m_nog:  .ascii "guest: no such guest\n"
m_nog_e:
s_pfx:  .ascii "/guest/"                ; images: files tagged guest
s_sfx:  .ascii ".g"                     ; ... named <image> or <image>.g
s_att:  .ascii "attach"                 ; the subcommand
s_dopt: .ascii "-d"                     ; start detached
        .align 8                        ; ...
detach: .dword 0                        ; 1: -d
m_fail: .ascii "guest: the process server refused the request\n"
m_fail_e:
s_stop: .ascii "stop"                   ; the subcommand
s_list: .ascii "list"                   ; ...

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        call  sys_init                  ; handles and arguments
        la    a0, args                  ; the arguments
        call  sys_args                  ; a0 = length
        mv    s0, a0                    ; s0 = length
        la    s1, args                  ; s1 = cursor
        add   s2, s1, s0                ; s2 = end
        mv    a0, s1                    ; the first word
        mv    a1, s2                    ; ...
        call  arg_next                  ; a0 = word, a1 = len, a2 = next
        beqz  a1, do_list               ; no args: list
        mv    s3, a0                    ; s3 = word 1 start
        mv    s4, a1                    ; s4 = its length
        mv    s1, a2                    ; advance the cursor
        la    t0, s_stop                ; "stop"?
        li    t1, 4                     ; ...
        bne   s4, t1, ck_list           ; ...
        mv    a0, s3                    ; ...
        mv    a1, t0                    ; ...
        li    a2, 4                     ; ...
        call  memeq                     ; a0 = 1 if equal
        bnez  a0, do_stop               ; ...
ck_list:
        la    t0, s_list                ; "list"?
        li    t1, 4                     ; ...
        bne   s4, t1, ck_att            ; ...
        mv    a0, s3                    ; ...
        mv    a1, t0                    ; ...
        li    a2, 4                     ; ...
        call  memeq                     ; ...
        bnez  a0, do_list               ; ...
ck_att:
        la    t0, s_att                 ; "attach"?
        li    t1, 6                     ; ...
        bne   s4, t1, ck_d              ; ...
        mv    a0, s3                    ; ...
        mv    a1, t0                    ; ...
        li    a2, 6                     ; ...
        call  memeq                     ; ...
        bnez  a0, do_attach             ; ...
ck_d:
        la    t0, s_dopt                ; "-d"?
        li    t1, 2                     ; ...
        bne   s4, t1, do_start          ; ...
        mv    a0, s3                    ; ...
        mv    a1, t0                    ; ...
        li    a2, 2                     ; ...
        call  memeq                     ; ...
        beqz  a0, do_start              ; ...
        la    t0, detach                ; yes: the image name follows
        li    t1, 1                     ; ...
        sd    t1, 0(t0)                 ; ...
        mv    a0, s1                    ; ...
        mv    a1, s2                    ; ...
        call  arg_next                  ; ...
        beqz  a1, usage                 ; ...
        mv    s3, a0                    ; ...
        mv    s4, a1                    ; ...
        mv    s1, a2                    ; ...
        j     do_start                  ; the word is an image name

; ---- guest [-d] <image> [cores] [MiB] --------------------------------------
do_start:
        ld    s5, 0(zero)               ; (clear) -- s5 = cores, s6 = MiB defaults below
        li    s5, 2                     ; default cores
        li    s6, 8                     ; default MiB
        mv    a0, s1                    ; the next word: cores?
        mv    a1, s2                    ; ...
        call  arg_next                  ; ...
        beqz  a1, st_build              ; none
        mv    s1, a2                    ; advance
        mv    t5, a0                    ; keep
        mv    t6, a1                    ; ...
        mv    a0, t5                    ; parse it
        mv    a1, t6                    ; ...
        call  str_atoi                  ; a0 = cores
        beqz  a0, st_build              ; (0: keep the default)
        mv    s5, a0                    ; ...
        mv    a0, s1                    ; the MiB word?
        mv    a1, s2                    ; ...
        call  arg_next                  ; ...
        beqz  a1, st_build              ; none
        mv    s1, a2                    ; ...
        call  str_atoi                  ; a0 = MiB
        beqz  a0, st_build              ; ...
        mv    s6, a0                    ; ...
st_build:
        li    s7, 0                     ; s7 = 0: <image>, then 1: <image>.g
st_try:
        la    t0, reqb                  ; the request data: cores, MiB, name
        sd    s5, 0(t0)                 ; ...
        sd    s6, 8(t0)                 ; ...
        addi  s8, t0, 16                ; s8 = where the name goes: "/guest/" first
        mv    a0, s8                    ; ...
        la    a1, s_pfx                 ; ...
        li    a2, 7                     ; ...
        call  bcopy                     ; ...
        addi  a0, s8, 7                 ; then the image name
        mv    a1, s3                    ; ...
        mv    a2, s4                    ; ...
        call  bcopy                     ; ...
        addi  s9, s4, 7                 ; s9 = the path's length
        beqz  s7, st_nul                ; the second try: ".g" too
        add   a0, s8, s9                ; ...
        la    a1, s_sfx                 ; ...
        li    a2, 2                     ; ...
        call  bcopy                     ; ...
        addi  s9, s9, 2                 ; ...
st_nul:
        add   t4, s8, s9                ; the terminator
        sb    zero, 0(t4)               ; ...
        addi  a1, s9, 17                ; data length: 16 + path + null
        la    a0, reqb                  ; the data -> the buffer
        call  sys_put                   ; ...
        li    a0, 1                     ; proc
        li    a1, GSTART                ; ...
        li    a2, 0                     ; ...
        addi  a3, s9, 17                ; length
        li    a4, 0                     ; ...
        call  sys_msg                   ; a0 = 0; data[0] = id, data[1] = core
        bgez  a0, st_ok                 ; started
        bnez  s7, fail                  ; refused both ways
        li    s7, 1                     ; try <image>.g
        j     st_try                    ; ...
st_ok:
        li    a0, 0                     ; id
        call  sys_word                  ; ...
        mv    s3, a0                    ; ...
        li    a0, 1                     ; core
        call  sys_word                  ; ...
        mv    s4, a0                    ; ...
        la    a0, m_start               ; "guest"
        li    a1, m_on_e - m_start      ; "guest ... started: id "
        call  out_str                   ; ...
        mv    a0, s3                    ; the id
        call  out_dec                   ; ...
        la    a0, m_core                ; ", core "
        li    a1, m_core_e - m_core     ; ...
        call  out_str                   ; ...
        mv    a0, s4                    ; the core
        call  out_dec                   ; ...
        call  out_nl                    ; ...
        call  out_flush                 ; ...
        la    t0, detach                ; -d: that is all
        ld    t0, 0(t0)                 ; ...
        bnez  t0, st_exit               ; ...
        mv    a0, s3                    ; give it the console
        j     attach                    ; ...
st_exit:
        li    a0, 0                     ; ...
        call  sys_exit                  ; ...

; ---- guest attach <id> -----------------------------------------------------
do_attach:
        mv    a0, s1                    ; the id word
        mv    a1, s2                    ; ...
        call  arg_next                  ; ...
        beqz  a1, usage                 ; none
        call  str_atoi                  ; a0 = id
        mv    s3, a0                    ; ...
        call  sys_put_none              ; is it running? (the list)
        li    a0, 1                     ; proc
        li    a1, GLIST                 ; ...
        li    a2, 0                     ; ...
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        call  sys_msg                   ; a0 = count
        mv    s0, a0                    ; ...
        la    a0, tab                   ; ...
        li    a1, 32 * 4                ; ...
        call  sys_get                   ; ...
        la    s1, tab                   ; ...
da_f:
        blez  s0, da_none               ; ...
        ld    t0, 0(s1)                 ; this id?
        beq   t0, s3, da_ok             ; ...
        addi  s1, s1, 32                ; ...
        addi  s0, s0, -1                ; ...
        j     da_f                      ; ...
da_none:
        la    a0, m_nog                 ; "no such guest"
        li    a1, m_nog_e - m_nog       ; ...
        call  err_str                   ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...
da_ok:
        mv    a0, s3                    ; ...
        j     attach                    ; ...

; attach(a0 = guest id): ATTACH the console to it and wait until it comes back
attach:
        mv    s3, a0                    ; s3 = the id
        call  m_guest_id                ; "guest N has the console: ..."
        la    a0, m_att                 ; ...
        li    a1, m_att_e - m_att       ; ...
        call  out_str                   ; ...
        call  out_flush                 ; ...
        call  sys_put_none              ; ...
        li    a0, 3                     ; the tty: ATTACH (answered when the console is back)
        li    a1, 20                    ; ...
        mv    a2, s3                    ; ...
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        call  sys_msg                   ; a0 = why it came back
        li    t0, -7                    ; another guest has it
        beq   a0, t0, at_busy           ; ...
        li    t0, 1                     ; the guest closed it
        beq   a0, t0, at_closed         ; ...
        li    t0, 2                     ; the guest was stopped
        beq   a0, t0, at_gone           ; ...
        li    t0, -1                    ; refused (not a guest's id; a guest asking)
        beq   a0, t0, at_bad            ; ...
        call  m_guest_id                ; Ctrl-] (0) or Ctrl-C (-2): "guest N detached: ..."
        la    a0, m_det                 ; ...
        li    a1, m_det_e - m_det       ; ...
        call  out_str                   ; ...
        mv    a0, s3                    ; ...
        call  out_dec                   ; ...
        la    a0, m_det2                ; ...
        li    a1, m_det2_e - m_det2     ; ...
        call  out_str                   ; ...
        mv    a0, s3                    ; ...
        call  out_dec                   ; ...
        la    a0, m_det3                ; ...
        li    a1, m_det3_e - m_det3     ; ...
        call  out_str                   ; ...
        j     at_out                    ; ...
at_closed:
        call  m_guest_id                ; "guest N closed the console: ..."
        la    a0, m_clo                 ; ...
        li    a1, m_clo_e - m_clo       ; ...
        call  out_str                   ; ...
        mv    a0, s3                    ; ...
        call  out_dec                   ; ...
        la    a0, m_clo2                ; ...
        li    a1, m_clo2_e - m_clo2     ; ...
        call  out_str                   ; ...
        j     at_out                    ; ...
at_gone:
        call  m_guest_id                ; "guest N was stopped"
        la    a0, m_gone                ; ...
        li    a1, m_gone_e - m_gone     ; ...
        call  out_str                   ; ...
at_out:
        call  out_flush                 ; ...
        li    a0, 0                     ; ...
        call  sys_exit                  ; ...
at_busy:
        la    a0, m_busy                ; "attached to a guest already"
        li    a1, m_busy_e - m_busy     ; ...
        call  err_str                   ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...
at_bad:
        la    a0, m_nog                 ; "no such guest"
        li    a1, m_nog_e - m_nog       ; ...
        call  err_str                   ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...

; m_guest_id(): print "guest N" (N = s3)
m_guest_id:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        la    a0, m_start               ; "guest "
        li    a1, m_start_e - m_start + 1 ; (with the space after it in m_on)
        call  out_str                   ; ...
        mv    a0, s3                    ; ...
        call  out_dec                   ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; bcopy(a0 = to, a1 = from, a2 = bytes)
bcopy:
        beqz  a2, bc_ret                ; ...
        lbu   t0, 0(a1)                 ; ...
        sb    t0, 0(a0)                 ; ...
        addi  a0, a0, 1                 ; ...
        addi  a1, a1, 1                 ; ...
        addi  a2, a2, -1                ; ...
        j     bcopy                     ; ...
bc_ret:
        ret                             ; ...

; ---- guest stop <id> -------------------------------------------------------
do_stop:
        mv    a0, s1                    ; the id word
        mv    a1, s2                    ; ...
        call  arg_next                  ; ...
        beqz  a1, usage                 ; none
        call  str_atoi                  ; a0 = id
        mv    s3, a0                    ; ...
        li    a0, 1                     ; proc
        li    a1, GSTOP                 ; ...
        mv    a2, s3                    ; handle = id
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        call  sys_msg                   ; ...
        la    a0, m_stopd               ; "guest stopped"
        li    a1, m_stopd_e - m_stopd   ; ...
        call  out_str                   ; ...
        call  out_flush                 ; ...
        li    a0, 0                     ; ...
        call  sys_exit                  ; ...

; ---- guest / guest list ----------------------------------------------------
do_list:
        la    a0, tab                   ; the records
        call  sys_put_none              ; (no data to send)
        li    a0, 1                     ; proc
        li    a1, GLIST                 ; ...
        li    a2, 0                     ; ...
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        call  sys_msg                   ; a0 = count
        mv    s0, a0                    ; ...
        la    a0, tab                   ; the data -> D-LS
        li    a1, 32 * 4                ; ...
        call  sys_get                   ; ...
        blez  s0, ls_none               ; ...
        la    a0, m_hdr                 ; the header
        li    a1, m_hdr_e - m_hdr       ; ...
        call  out_str                   ; ...
        la    s1, tab                   ; cursor
ls_row:
        blez  s0, ls_done               ; ...
        la    a0, m_sp                  ; pad
        li    a1, 2                     ; ...
        call  out_str                   ; ...
        ld    a0, 0(s1)                 ; id
        call  out_dec                   ; ...
        la    a0, m_sp                  ; pad
        li    a1, 5                     ; ...
        call  out_str                   ; ...
        ld    t0, 8(s1)                 ; core | cores << 8
        srli  a0, t0, 8                 ; cores
        andi  a0, a0, 255               ; ...
        call  out_dec                   ; ...
        la    a0, m_sp                  ; pad
        li    a1, 7                     ; ...
        call  out_str                   ; ...
        ld    a0, 16(s1)                ; arena bytes -> MiB
        srli  a0, a0, 20                ; ...
        call  out_dec                   ; ...
        la    a0, m_sp                  ; pad
        li    a1, 6                     ; ...
        call  out_str                   ; ...
        la    a0, m_live                ; "live"
        li    a1, m_live_e - m_live     ; ...
        call  out_str                   ; ...
        call  out_nl                    ; ...
        addi  s1, s1, 32                ; next record
        addi  s0, s0, -1                ; ...
        j     ls_row                    ; ...
ls_none:
        la    a0, m_none                ; "no guests running"
        li    a1, m_none_e - m_none     ; ...
        call  out_str                   ; ...
ls_done:
        call  out_flush                 ; ...
        li    a0, 0                     ; ...
        call  sys_exit                  ; ...

usage:
        la    a0, m_usage               ; usage
        li    a1, m_usage_e - m_usage   ; ...
        call  err_str                   ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...
fail:
        la    a0, m_fail                ; "refused"
        li    a1, m_fail_e - m_fail     ; ...
        call  err_str                   ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...

; memeq(a0, a1 = two strings, a2 = length) -> a0 = 1 if equal, else 0
memeq:
        li    t0, 0                     ; ...
me_l:
        bge   t0, a2, me_yes            ; ...
        add   t1, a0, t0                ; ...
        lbu   t1, 0(t1)                 ; ...
        add   t2, a1, t0                ; ...
        lbu   t2, 0(t2)                 ; ...
        bne   t1, t2, me_no             ; ...
        addi  t0, t0, 1                 ; ...
        j     me_l                      ; ...
me_yes:
        li    a0, 1                     ; ...
        ret                             ; ...
me_no:
        li    a0, 0                     ; ...
        ret                             ; ...

; sys_put_none(): mark the buffer empty (no data) for a request that sends none
sys_put_none:
        li    a0, 0                     ; length 0
        la    t0, sys_buf               ; (nothing to copy)
        ret                             ; done

        .include "../lib/sys.s"         ; the system interface
