; =============================================================================
; guest.s: start, stop and list guest operating systems
; =============================================================================
;
;   guest <image> [cores] [MiB]   boot <image> as a guest on `cores` cores
;                                 (default 2) with an arena of `MiB` (default 8)
;   guest stop <id>               stop a guest: reset its cores and reclaim them
;   guest                         list the running guests
;   guest list                    the same
;
; A guest is a second operating system that StrataOS runs on whole worker cores
; in supervisor mode, beside itself (doc/strataos.md, "Guests"). `guest` asks
; the process server (proc), which gets an arena, loads the image into it and
; calls the kernel. Example: `guest hello 2 8` boots os/guests/hello as a guest
; on 2 cores; `cores` then shows them as a guest's; `guest stop 240` ends it and
; the cores return to StrataOS.

GSTART  = 40                            ; proc operations
GSTOP   = 41                            ; ...
GLIST   = 42                            ; ...

        .data                           ; data Local Store
        .align 8                        ; ...
args:   .space 512                      ; the argument text
reqb:   .space 512                      ; the request data
tab:    .space 8 + 32 * 4               ; the guest list
m_start: .ascii "guest"                 ; "guest started: id N, core C"
m_start_e:
m_on:   .ascii " started: id "
m_on_e:
m_core: .ascii ", core "
m_core_e:
m_stopd: .ascii "guest stopped\n"
m_stopd_e:
m_none: .ascii "no guests running\n"
m_none_e:
m_hdr:  .ascii "  ID  CORES  ARENA(MiB)  STATE\n"
m_hdr_e:
m_live: .ascii "live"
m_live_e:
m_sp:   .ascii "       "                ; padding
m_usage: .ascii "usage: guest <image> [cores] [MiB] | guest stop <id> | guest\n"
m_usage_e:
m_fail: .ascii "guest: the process server refused the request\n"
m_fail_e:
s_stop: .ascii "stop"                   ; the subcommand
s_list: .ascii "list"                   ; ...

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        li    sp, 65536                 ; stack at the top of the D-LS
        call  sys_init                  ; handles and arguments
        la    a0, args                  ; the arguments
        call  sys_args                  ; a0 = length
        mv    s0, a0                    ; s0 = length
        la    s1, args                  ; s1 = cursor
        add   s2, s1, s0                ; s2 = end
        mv    a0, s1                    ; the first word
        mv    a1, s2                    ; ...
        call  arg_next                  ; a0 = word, a1 = len, a2 = next
        beqz  a1, do_list               ; no args: list
        mv    s3, a0                    ; s3 = word 1 start
        mv    s4, a1                    ; s4 = its length
        mv    s1, a2                    ; advance the cursor
        la    t0, s_stop                ; "stop"?
        li    t1, 4                     ; ...
        bne   s4, t1, ck_list           ; ...
        mv    a0, s3                    ; ...
        mv    a1, t0                    ; ...
        li    a2, 4                     ; ...
        call  memeq                     ; a0 = 1 if equal
        bnez  a0, do_stop               ; ...
ck_list:
        la    t0, s_list                ; "list"?
        li    t1, 4                     ; ...
        bne   s4, t1, do_start          ; ...
        mv    a0, s3                    ; ...
        mv    a1, t0                    ; ...
        li    a2, 4                     ; ...
        call  memeq                     ; ...
        bnez  a0, do_list               ; ...
        j     do_start                  ; the word is an image name

; ---- guest <image> [cores] [MiB] -------------------------------------------
do_start:
        ld    s5, 0(zero)               ; (clear) -- s5 = cores, s6 = MiB defaults below
        li    s5, 2                     ; default cores
        li    s6, 8                     ; default MiB
        mv    a0, s1                    ; the next word: cores?
        mv    a1, s2                    ; ...
        call  arg_next                  ; ...
        beqz  a1, st_build              ; none
        mv    s1, a2                    ; advance
        mv    t5, a0                    ; keep
        mv    t6, a1                    ; ...
        mv    a0, t5                    ; parse it
        mv    a1, t6                    ; ...
        call  str_atoi                  ; a0 = cores
        beqz  a0, st_build              ; (0: keep the default)
        mv    s5, a0                    ; ...
        mv    a0, s1                    ; the MiB word?
        mv    a1, s2                    ; ...
        call  arg_next                  ; ...
        beqz  a1, st_build              ; none
        mv    s1, a2                    ; ...
        call  str_atoi                  ; a0 = MiB
        beqz  a0, st_build              ; ...
        mv    s6, a0                    ; ...
st_build:
        la    t0, reqb                  ; the request data: cores, MiB, name
        sd    s5, 0(t0)                 ; ...
        sd    s6, 8(t0)                 ; ...
        mv    a0, s3                    ; the image name -> reqb+16 (null terminated)
        mv    a1, s4                    ; ...
        la    t1, reqb                  ; ...
        addi  t1, t1, 16                ; ...
        li    t2, 0                     ; ...
st_cp:
        bge   t2, a1, st_nul            ; ...
        add   t3, a0, t2                ; ...
        lbu   t3, 0(t3)                 ; ...
        add   t4, t1, t2                ; ...
        sb    t3, 0(t4)                 ; ...
        addi  t2, t2, 1                 ; ...
        j     st_cp                     ; ...
st_nul:
        add   t4, t1, t2                ; the terminator
        sb    zero, 0(t4)               ; ...
        addi  a1, s4, 17                ; data length: 16 + name + null
        la    a0, reqb                  ; the data -> the buffer
        call  sys_put                   ; ...
        li    a0, 1                     ; proc
        li    a1, GSTART                ; ...
        li    a2, 0                     ; ...
        la    a3, reqb                  ; (its address for the length)
        addi  a3, s4, 17                ; length
        li    a4, 0                     ; ...
        call  sys_msg                   ; a0 = 0; data[0] = id, data[1] = core
        bltz  a0, fail                  ; refused
        li    a0, 0                     ; id
        call  sys_word                  ; ...
        mv    s3, a0                    ; ...
        li    a0, 1                     ; core
        call  sys_word                  ; ...
        mv    s4, a0                    ; ...
        la    a0, m_start               ; "guest"
        li    a1, m_on_e - m_start      ; "guest ... started: id "
        call  out_str                   ; ...
        mv    a0, s3                    ; the id
        call  out_dec                   ; ...
        la    a0, m_core                ; ", core "
        li    a1, m_core_e - m_core     ; ...
        call  out_str                   ; ...
        mv    a0, s4                    ; the core
        call  out_dec                   ; ...
        call  out_nl                    ; ...
        call  out_flush                 ; ...
        li    a0, 0                     ; ...
        call  sys_exit                  ; ...

; ---- guest stop <id> -------------------------------------------------------
do_stop:
        mv    a0, s1                    ; the id word
        mv    a1, s2                    ; ...
        call  arg_next                  ; ...
        beqz  a1, usage                 ; none
        call  str_atoi                  ; a0 = id
        mv    s3, a0                    ; ...
        li    a0, 1                     ; proc
        li    a1, GSTOP                 ; ...
        mv    a2, s3                    ; handle = id
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        call  sys_msg                   ; ...
        la    a0, m_stopd               ; "guest stopped"
        li    a1, m_stopd_e - m_stopd   ; ...
        call  out_str                   ; ...
        call  out_flush                 ; ...
        li    a0, 0                     ; ...
        call  sys_exit                  ; ...

; ---- guest / guest list ----------------------------------------------------
do_list:
        la    a0, tab                   ; the records
        call  sys_put_none              ; (no data to send)
        li    a0, 1                     ; proc
        li    a1, GLIST                 ; ...
        li    a2, 0                     ; ...
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        call  sys_msg                   ; a0 = count
        mv    s0, a0                    ; ...
        la    a0, tab                   ; the data -> D-LS
        li    a1, 32 * 4                ; ...
        call  sys_get                   ; ...
        blez  s0, ls_none               ; ...
        la    a0, m_hdr                 ; the header
        li    a1, m_hdr_e - m_hdr       ; ...
        call  out_str                   ; ...
        la    s1, tab                   ; cursor
ls_row:
        blez  s0, ls_done               ; ...
        la    a0, m_sp                  ; pad
        li    a1, 2                     ; ...
        call  out_str                   ; ...
        ld    a0, 0(s1)                 ; id
        call  out_dec                   ; ...
        la    a0, m_sp                  ; pad
        li    a1, 5                     ; ...
        call  out_str                   ; ...
        ld    t0, 8(s1)                 ; core | cores << 8
        srli  a0, t0, 8                 ; cores
        andi  a0, a0, 255               ; ...
        call  out_dec                   ; ...
        la    a0, m_sp                  ; pad
        li    a1, 7                     ; ...
        call  out_str                   ; ...
        ld    a0, 16(s1)                ; arena bytes -> MiB
        srli  a0, a0, 20                ; ...
        call  out_dec                   ; ...
        la    a0, m_sp                  ; pad
        li    a1, 6                     ; ...
        call  out_str                   ; ...
        la    a0, m_live                ; "live"
        li    a1, m_live_e - m_live     ; ...
        call  out_str                   ; ...
        call  out_nl                    ; ...
        addi  s1, s1, 32                ; next record
        addi  s0, s0, -1                ; ...
        j     ls_row                    ; ...
ls_none:
        la    a0, m_none                ; "no guests running"
        li    a1, m_none_e - m_none     ; ...
        call  out_str                   ; ...
ls_done:
        call  out_flush                 ; ...
        li    a0, 0                     ; ...
        call  sys_exit                  ; ...

usage:
        la    a0, m_usage               ; usage
        li    a1, m_usage_e - m_usage   ; ...
        call  err_str                   ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...
fail:
        la    a0, m_fail                ; "refused"
        li    a1, m_fail_e - m_fail     ; ...
        call  err_str                   ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...

; memeq(a0, a1 = two strings, a2 = length) -> a0 = 1 if equal, else 0
memeq:
        li    t0, 0                     ; ...
me_l:
        bge   t0, a2, me_yes            ; ...
        add   t1, a0, t0                ; ...
        lbu   t1, 0(t1)                 ; ...
        add   t2, a1, t0                ; ...
        lbu   t2, 0(t2)                 ; ...
        bne   t1, t2, me_no             ; ...
        addi  t0, t0, 1                 ; ...
        j     me_l                      ; ...
me_yes:
        li    a0, 1                     ; ...
        ret                             ; ...
me_no:
        li    a0, 0                     ; ...
        ret                             ; ...

; sys_put_none(): mark the buffer empty (no data) for a request that sends none
sys_put_none:
        li    a0, 0                     ; length 0
        la    t0, sys_buf               ; (nothing to copy)
        ret                             ; done

        .include "../lib/sys.s"         ; the system interface
