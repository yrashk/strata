; =============================================================================
; mv.s: move or rename a file
; =============================================================================
;
;   mv SRC /DIR/DST       SRC is now DST in DIR, and in no other directory
;                         (mv /notes/a /todo/b; /DIR/DIR/DST: in both)
;   mv SRC /DIR/          DST ending in "/": the same name, there
;   mv SRC DST            DST without any "/": only the name changes, SRC
;                         stays where it is
; A file named DST where SRC goes is replaced if it is in no other
; directory; if it is, the move is refused.
;
; One request to the file server (sys_rename, fs RENAME): the file keeps its
; blocks, its directory entry and its tags, and gains the tags of DST's path
; (created if new). Nothing is copied. To take a tag away, use untag. Errors
; go to standard error with exit code 1: "mv: no such file: SRC", "mv: cannot
; rename SRC to DST" (a bad name: 1..24 bytes; a bad tag; 64 tags in use).

        .data                           ; data Local Store
        .align 8                        ; aligned buffers
args:   .space 512                      ; the argument text (a command line is at most 440 bytes)
dst:    .space 512                      ; DST, with SRC's name after a final "/"
m_use:  .ascii "usage: mv SRC DST\n"    ; error text
m_use_e:                                ; end of the text above
m_no:   .ascii "mv: no such file: "     ; error text
m_no_e:                                 ; end of the text above
m_bad:  .ascii "mv: cannot rename "     ; error text
m_bad_e:                                ; end of the text above
m_to:   .ascii " to "                   ; ...
m_to_e:                                 ; end of the text above

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        call  sys_init                  ; handles and arguments
        la    a0, args                  ; the arguments ...
        call  sys_args                  ; ... a0 = their length
        la    s0, args                  ; s0 = cursor
        add   s1, s0, a0                ; s1 = end
        mv    a0, s0                    ; SRC
        mv    a1, s1                    ; ...
        call  arg_next                  ; a0 = start, a1 = length, a2 = cursor after
        beqz  a1, usage                 ; none
        mv    s0, a2                    ; ...
        mv    s2, a0                    ; s2, s3 = SRC
        mv    s3, a1                    ; ...
        mv    a0, s0                    ; DST
        mv    a1, s1                    ; ...
        call  arg_next                  ; ...
        beqz  a1, usage                 ; ...
        mv    s0, a2                    ; ...
        call  mkdst                     ; -> dst; a0 = its length
        mv    s5, a0                    ; s5 = the length of DST
        mv    a0, s0                    ; nothing after it
        mv    a1, s1                    ; ...
        call  arg_next                  ; ...
        bnez  a1, usage                 ; ...
        mv    a0, s2                    ; rename
        mv    a1, s3                    ; ...
        la    a2, dst                   ; ...
        mv    a3, s5                    ; ...
        call  sys_rename                ; a0 = 0 or < 0
        bgez  a0, ok                    ; done
        li    t0, -4                    ; no such file?
        bne   a0, t0, bad               ; no: the new name
        la    a0, m_no                  ; "mv: no such file: "
        li    a1, m_no_e - m_no         ; ...
        call  err_str                   ; ...
        mv    a0, s2                    ; SRC
        mv    a1, s3                    ; ...
        j     fail                      ; ...
bad:
        la    a0, m_bad                 ; "mv: cannot rename "
        li    a1, m_bad_e - m_bad       ; ...
        call  err_str                   ; ...
        mv    a0, s2                    ; SRC
        mv    a1, s3                    ; ...
        call  err_str                   ; ...
        la    a0, m_to                  ; " to "
        li    a1, m_to_e - m_to         ; ...
        call  err_str                   ; ...
        la    a0, dst                   ; DST
        mv    a1, s5                    ; ...
fail:
        call  err_str                   ; ...
        la    a0, sys_nl                ; a newline
        li    a1, 1                     ; ...
        call  err_str                   ; ...
        li    a0, 1                     ; exit code
        call  sys_exit                  ; end the process
ok:
        li    a0, 0                     ; exit code
        call  sys_exit                  ; flush stdout, end the process
usage:
        la    a0, m_use                 ; how to use it
        li    a1, m_use_e - m_use       ; ...
        call  err_str                   ; ...
        li    a0, 2                     ; exit code for a usage error
        call  sys_exit                  ; end the process

; mkdst(a0 = DST, a1 = its length; s2, s3 = SRC) -> dst = DST, and if DST
; ends in "/", SRC's name (its last component) after it -> a0 = the length
mkdst:
        la    t0, dst                   ; t0 = the copy
        li    t1, 0                     ; t1 = index
md_c:
        beq   t1, a1, md_e              ; DST is copied
        add   t2, a0, t1                ; ...
        lbu   t3, 0(t2)                 ; ...
        add   t2, t0, t1                ; ...
        sb    t3, 0(t2)                 ; ...
        addi  t1, t1, 1                 ; ...
        j     md_c                      ; ...
md_e:
        mv    a0, t1                    ; a0 = the length so far
        add   t2, t0, t1                ; a final "/"?
        lbu   t3, -1(t2)                ; (DST has at least one byte)
        li    t4, '/'                   ; ...
        bne   t3, t4, md_r              ; no: DST is the name
        mv    t2, s2                    ; t6 = where SRC's last component starts
        add   t5, s2, s3                ; t5 = SRC's end
        mv    t6, s2                    ; ...
md_s:
        bgeu  t2, t5, md_a              ; ...
        lbu   t3, 0(t2)                 ; ...
        addi  t2, t2, 1                 ; ...
        bne   t3, t4, md_s              ; ...
        mv    t6, t2                    ; after a "/"
        j     md_s                      ; ...
md_a:
        bgeu  t6, t5, md_r              ; SRC's name goes after DST
        lbu   t3, 0(t6)                 ; ...
        add   t2, t0, a0                ; ...
        sb    t3, 0(t2)                 ; ...
        addi  a0, a0, 1                 ; ...
        addi  t6, t6, 1                 ; ...
        j     md_a                      ; ...
md_r:
        ret                             ; done

        .include "../lib/sys.s"         ; the system interface
