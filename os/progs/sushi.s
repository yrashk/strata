; =============================================================================
; sushi.s: SushiBelt: a conveyor-belt sushi bar, in a window
; =============================================================================
;
;   sushi           (from a shell in a terminal, or the palette: Alt+Space)
;
; A client of the window server (os/lib/wsclient.s). Three cooks make sushi
; behind a counter and put each piece on a plate on the belt that runs round
; them; customers sit behind the belt and each wants a piece at a time. The
; player gives every order to a cook, and sweeps off the plates that ride
; too long and go stale (os/progs/PLAN-sushi.md; the evening's rules are in
; sushi/game.s). The art is drawn by tools/sushi-art.py and converted, with
; the sounds, by tools/sushi-assets.py into the file /ws/sushi.dat, which is
; read at start.
;
; Keys: 1 2 3 give the chosen order (the bubble with a frame) to that cook;
; the arrows choose another; Z (or Backspace) sweeps the oldest stale plate
; off; Space goes from the title to how to play, from there into the
; evening, and from its results into the next one; Q quits. The mouse: a
; click on a bubble chooses it, on a cook (or on the cook's box in the bar)
; gives it to them, on a plate sweeps it off.
;
; The screen is kira's (320 x 200 palette indices drawn in ten slabs of 32
; columns, scaled by a whole factor into the band: sushi/draw.s). The belt
; moves all the time, so while the evening runs every tic is a frame. While
; the window does not have the focus the program waits in EVENT.

S_CAP    = 0                            ; os/lib/gfx.s's surface descriptor: register
S_OFF    = 8                            ; offset of pixel (0, 0)
S_W      = 16                           ; width
S_H      = 24                           ; height
S_STRIDE = 32                           ; bytes per row
S_SIZE   = 48                           ; bytes per descriptor
TIC_US   = 28571                        ; a tic in the clock's ticks (microseconds): 35 a second
M_TITLE  = 0                            ; modes: the title
M_PLAY   = 1                            ; the evening
M_RESULT = 2                            ; its results
M_HELP   = 3                            ; how to play, before it
K_UP     = 1                            ; keys: the arrows
K_DOWN   = 2                            ; ...
K_LEFT   = 3                            ; ...
K_RIGHT  = 4                            ; ...
DK_CLICK = 0xfe                         ; in a demo: a click (x / 2 and y follow)
DK_SEED  = 0xfa                         ; ... the random numbers start over from SEED0
SEED0    = 20261117                     ; where a demo's random numbers start
DK_LOOP  = 0xfb                         ; ... what follows, up to DK_END, N times (N, 0 follow)
DK_END   = 0xfc                         ; ...
DK_FAST  = 0xf9                         ; ... the tics that follow are not drawn, until the next one
BORDER   = 0x00403039                   ; the window around the picture: walnut

        .text                           ; instruction Local Store
_start: j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program

        .include "sushi/dat.s"          ; the data file's layout
KEEP     = (F_SIZE + 4095) & ~4095      ; the top of the arena: sushi.dat's far block
        .include "sushi/draw.s"         ; the screen
        .include "sushi/game.s"         ; the evening
        .include "wdoom/sound.s"        ; the sounds: wdoom's mixer
        .include "../lib/sys.s"         ; the program library
        .include "../lib/wsclient.s"    ; the window server's protocol

        .data                           ; D-LS
        .align 8                        ; dwords
g:                                      ; the globals (gp points here)
g_mode:   .dword 0                      ; M_*
g_tic:    .dword 0                      ; tics since the start
g_last:   .dword 0                      ; the clock at the last tic
g_seed:   .dword SEED0                  ; the random numbers' state
g_bardirty: .dword 1                    ; the bar is to be drawn
g_dirty:  .dword 1                      ; the view is to be drawn
g_sx0:    .dword 0                      ; the slab being drawn: its first column
g_py0:    .dword 0                      ; the pass: its first row on the 320 x 200 screen
g_ph:     .dword 0                      ; ... and rows
g_clipy:  .dword VIEW_H + BAR_H         ; ... and sprites are hidden from this row down
g_stride: .dword 0                      ; bytes between rows in the band
g_scale:  .dword 0                      ; the factor: 1..3 (0: the window is too small)
g_ox:     .dword 0                      ; where the picture is in the window
g_oy:     .dword 0                      ; ...
g_grp:    .dword 0                      ; slabs of the view the band holds
g_keepb:  .dword 0                      ; arena offset of the far block (= the band's size)
g_esc:    .dword 0                      ; keys: 1 after ESC, 2 after ESC [
g_btn:    .dword 0                      ; the pointer's buttons at its last event
g_paused: .dword 0                      ; the window lost the focus
g_quit:   .dword 0                      ; time to go
g_demo:   .dword 0                      ; `sushi demo N`: the next step of the demo (0: no demo)
g_dleft:  .dword 0                      ; ... and tics left before its key
g_dt0:    .dword 0                      ; the clock when the demo started
g_dmark:  .dword 0                      ; a demo's loop: its first step
g_dloop:  .dword 0                      ; ... and how many times it is still to be played
g_fast:   .dword 0                      ; ... its tics are not drawn (DK_FAST)
g_belt:   .dword 0                      ; the evening (ev_new clears g_belt .. g_evend):
                                        ;   tics the belt has moved
g_min:    .dword 0                      ; minutes since 17:00
g_mint:   .dword 0                      ; ... and tics into the minute
g_next:   .dword 0                      ; tics until the next customer comes in
g_money:  .dword 0                      ; yen taken
g_tips:   .dword 0                      ; ... of it tips
g_streak: .dword 0                      ; pieces served in a row
g_nserved: .dword 0                     ; pieces served
g_nhappy: .dword 0                      ; customers gone home happy
g_nleft:  .dword 0                      ; ... gone because they waited too long
g_nstale: .dword 0                      ; ... gone because their plate was stale
g_nswept: .dword 0                      ; plates swept off
g_sel:    .dword 0                      ; the chosen order: its seat (-1: none)
g_flash:  .dword 0                      ; the cook given an order last
g_flasht: .dword 0                      ; ... lit up for so many tics more
g_evend:                                ; (the end of the evening's globals)
s_dmsg:   .ascii "sushi: demo: "        ; what is said at the demo's end
s_dnum:   .space 40                     ; ... "N frames in N ms\n"
s_dfr:    .ascii " frames in \0"        ; (its pieces)
s_dms:    .ascii " ms\n\0"              ; ...
        .align 8                        ; ...
res:      .space R_SIZE                 ; the data file's resident block (dat.s)
s_title:  .ascii "SUSHI\0\0\0"          ; the window's title
s_dat:    .ascii "/ws/sushi.dat"        ; the data file
s_dat_e:                                ; (its end)
s_nows:   .ascii "sushi: no window server (run ws first)\n"
s_nows_e:                               ; (its end)
s_nodat:  .ascii "sushi: cannot read /ws/sushi.dat\n"
s_nodat_e:                              ; (its end)
        .align 8                        ; ...
        .text                           ; code

main:
        call  sys_init                  ; handles
        la    gp, g                     ; the globals
        clen  t0, c0                    ; the arena: the band, then the far block
        li    t1, KEEP                  ; ...
        sub   t0, t0, t1                ; ...
        sd    t0, g_keepb - g(gp)       ; ...
        call  load_dat                  ; the data (before the window: the server's
        beqz  a0, m_arg                 ;   endpoint takes the place of fs's)
        la    a0, s_nodat               ; ...
        li    a1, s_nodat_e - s_nodat   ; ...
        j     m_fail                    ; ...
m_arg:  la    a0, slab                  ; `sushi demo N`: play demo N (dat.s: R_DEMO)
        call  sys_args                  ; ...
        beqz  a0, m_seed                ; ...
        la    t0, slab                  ; ...
        lbu   t1, 0(t0)                 ; ...
        li    t2, 'd'                   ; ...
        bne   t1, t2, m_seed            ; ...
        add   t0, t0, a0                ; its number is the last character: 1..9
        lbu   t1, -1(t0)                ;   (1 if none)
        addi  t1, t1, -'1'              ; ...
        li    t2, NDEMO                 ; ...
        bltu  t1, t2, m_d1              ; ...
        li    t1, 0                     ; ...
m_d1:   slli  t1, t1, 1                 ; ...
        la    t0, res + R_DEMO          ; ...
        add   t1, t1, t0                ; ...
        lhu   t1, 0(t1)                 ; ...
        add   t0, t0, t1                ; ...
        sd    t0, g_demo - g(gp)        ; ...
        j     m_win                     ; (its random numbers start from the fixed seed)
m_seed: call  sys_now                   ; every evening is another
        ld    t0, g_seed - g(gp)        ; ...
        xor   t0, t0, a0                ; ...
        sd    t0, g_seed - g(gp)        ; ...
m_win:  la    t0, wc_keep               ; (the library's idea of the band agrees)
        li    t1, KEEP                  ; ...
        sd    t1, 0(t0)                 ; ...
        la    a0, s_title               ; our window (events are polled: no flags)
        li    a1, 0                     ; ...
        call  wc_open                   ; ...
        bgtz  a0, m_go                  ; ...
        la    a0, s_nows                ; no server
        li    a1, s_nows_e - s_nows     ; ...
m_fail: call  err_str                   ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...
m_go:   call  sys_now                   ; (a demo is timed)
        sd    a0, g_dt0 - g(gp)         ; ...
        ld    t0, g_demo - g(gp)        ; (and silent)
        bnez  t0, m_go2                 ; ...
        call  snd_open                  ; the sound device, if there is one
m_go2:  call  geom                      ; where the picture goes
        call  ev_new                    ; ...
        call  sys_now                   ; time starts now
        sd    a0, g_last - g(gp)        ; ...
m_loop: ld    t0, g_quit - g(gp)        ; ...
        bnez  t0, m_end                 ; ...
        li    a0, 1                     ; an event? (do not block)
        li    a1, 0                     ; ...
        call  wc_event                  ; ...
        li    t0, -3                    ; none
        beq   a0, t0, m_time            ; ...
        bnez  a0, m_end                 ; the window is gone
        call  ev_handle                 ; ...
        j     m_loop                    ; ...
m_time: ld    t0, g_paused - g(gp)      ; ...
        beqz  t0, m_run                 ; ...
        call  m_show                    ; paused: the picture as it stands,
        li    a0, 0                     ; ... then wait for an event
        li    a1, 0                     ; ...
        call  wc_event                  ; ...
        bnez  a0, m_end                 ; ...
        call  ev_handle                 ; ...
        call  sys_now                   ; (no tics are owed for the pause)
        sd    a0, g_last - g(gp)        ; ...
        j     m_loop                    ; ...
m_run:  ld    t0, g_demo - g(gp)        ; the demo: a tic a frame, whatever the clock says
        beqz  t0, m_clk                 ; ...
        call  demo                      ; ...
        call  step                      ; ...
        ld    t0, g_fast - g(gp)        ; (not drawn)
        bnez  t0, m_loop                ; ...
        j     m_draw                    ; ...
m_clk:  call  sys_now                   ; tics due?
        ld    t0, g_last - g(gp)        ; ...
        sub   t1, a0, t0                ; ...
        li    t2, TIC_US                ; ...
        bgeu  t1, t2, m_tics            ; ...
        ld    t3, g_dirty - g(gp)       ; none: a frame anyway (a resize, a key)?
        ld    t4, g_bardirty - g(gp)    ; ...
        or    t3, t3, t4                ; ...
        bnez  t3, m_draw                ; ...
        sub   a1, t2, t1                ; wait for the next tic, or an event
        li    a0, 0                     ; ...
        call  wc_event                  ; ...
        li    t0, -8                    ; (the time passed)
        beq   a0, t0, m_loop            ; ...
        bnez  a0, m_end                 ; ...
        call  ev_handle                 ; ...
        j     m_loop                    ; ...
m_tics: divu  s0, t1, t2                ; s0 = tics due
        mul   t3, s0, t2                ; ...
        add   t0, t0, t3                ; ...
        sd    t0, g_last - g(gp)        ; ...
        li    t3, 4                     ; (after a long frame: four at most)
        bleu  s0, t3, m_t1              ; ...
        mv    s0, t3                    ; ...
m_t1:   call  step                      ; ...
        addi  s0, s0, -1                ; ...
        bnez  s0, m_t1                  ; ...
m_draw: call  snd_pump                  ; the sounds, then the picture
        call  m_show                    ; ...
        j     m_loop                    ; ...
m_end:  call  wc_close                  ; the window goes
        li    a0, 0                     ; ...
        call  sys_exit                  ; ...

; m_show(): draw what changed: the view (and with it the bar, if it did),
; or the bar alone
m_show: addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        ld    t0, g_dirty - g(gp)       ; ...
        beqz  t0, mw_b                  ; ...
        sd    zero, g_dirty - g(gp)     ; ...
        call  r_frame                   ; ...
        j     mw_r                      ; ...
mw_b:   ld    t0, g_bardirty - g(gp)    ; ...
        beqz  t0, mw_r                  ; ...
        sd    zero, g_bardirty - g(gp)  ; ...
        ld    t0, g_scale - g(gp)       ; ...
        beqz  t0, mw_r                  ; ...
        call  r_bar                     ; ...
mw_r:   ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; step(): a tic: the particles and the evening; the title and the results
; blink
step:   ld    t0, g_tic - g(gp)         ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, g_tic - g(gp)         ; ...
        ld    t1, g_mode - g(gp)        ; ...
        li    t2, M_PLAY                ; ...
        bne   t1, t2, st_b              ; ...
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        call  p_step                    ; ...
        call  ev_step                   ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; ...
st_b:   andi  t0, t0, 15                ; ...
        bnez  t0, st_r                  ; ...
        li    t0, 1                     ; ...
        sd    t0, g_dirty - g(gp)       ; ...
st_r:   ret                             ; done

; start(): the evening begins
start:  addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        call  ev_new                    ; ...
        li    t0, M_PLAY                ; ...
        sd    t0, g_mode - g(gp)        ; ...
        li    t0, 1                     ; ...
        sd    t0, g_dirty - g(gp)       ; ...
        sd    t0, g_bardirty - g(gp)    ; ...
        li    a0, SN_BELL               ; ...
        call  snd_play                  ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; view_slab(): the mode's picture in the slab
view_slab:
        ld    t0, g_mode - g(gp)        ; ...
        bnez  t0, vs_p                  ; ...
        addi  sp, sp, -8                ; the title: its picture, PRESS SPACE blinking
        sd    ra, 0(sp)                 ; save the return address
        li    a0, PIC_TITLE             ; ...
        call  pic_slab                  ; ...
        ld    t0, g_tic - g(gp)         ; ...
        andi  t0, t0, 16                ; ...
        bnez  t0, vs_r                  ; ...
        la    a0, s_press               ; ...
        li    a1, 160 - 33              ; ...
        li    a2, 157                   ; ...
        call  r_text                    ; ...
vs_r:   ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; ...
vs_p:   li    t1, M_PLAY                ; the evening
        beq   t0, t1, play_slab         ; ...
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        li    t1, M_HELP                ; how to play, over the room
        bne   t0, t1, vs_e              ; ...
        li    a0, PIC_ROOM              ; ...
        call  pic_slab                  ; ...
        call  belt_slab                 ; ...
        call  help_slab                 ; ...
        j     vs_r                      ; ...
vs_e:   call  play_slab                 ; the results, over the evening
        call  result_slab               ; ...
        j     vs_r                      ; ...

; view_begin(): before a frame's slabs (nothing to work out once)
view_begin:
        ret                             ; done

; bar_slab(): the bar's money, clock and cooks (on the title: the evening
; to come)
bar_slab:
        j     game_bar                  ; ...

; click(a0 = x, a1 = y on the 320 x 200 screen): a press there
click:  ld    t0, g_mode - g(gp)        ; ...
        li    t1, M_PLAY                ; ...
        beq   t0, t1, ev_click          ; ...
        j     next                      ; (anywhere else: on)

; next(): from the title to how to play; from that, or the results, into
; the evening
next:   ld    t0, g_mode - g(gp)        ; ...
        bnez  t0, start                 ; ...
        li    t0, M_HELP                ; ...
        sd    t0, g_mode - g(gp)        ; ...
        li    t0, 1                     ; ...
        sd    t0, g_dirty - g(gp)       ; ...
        li    a0, SN_POP                ; ...
        j     snd_play                  ; ...

; do_key(a0 = key: K_UP .. K_RIGHT, or a character; 0 is no key)
do_key: beqz  a0, dk_r                  ; (0: a demo's wait, no key)
        li    t0, 'q'                   ; q: quit
        bne   a0, t0, dk_1              ; ...
        li    t0, 1                     ; ...
        sd    t0, g_quit - g(gp)        ; ...
        ret                             ; ...
dk_1:   ld    t1, g_mode - g(gp)        ; ...
        li    t0, M_PLAY                ; ...
        beq   t1, t0, ev_key            ; ...
        li    t0, ' '                   ; the title, how to play, the results:
        beq   a0, t0, next              ;   Space or Enter
        li    t0, 10                    ; ...
        beq   a0, t0, next              ; ...
        li    t0, 13                    ; ...
        beq   a0, t0, next              ; ...
dk_r:   ret                             ; done

; demo(): the demo's next tic: when a step's wait is over, its key. At the
; demo's end the program stands still, as when the window loses the focus,
; until a key or the pointer wakes it.
demo:   ld    t0, g_demo - g(gp)        ; the step
        ld    t1, g_dleft - g(gp)       ; tics left of its wait
        bnez  t1, de_1                  ; ...
        lbu   t1, 0(t0)                 ; a new step
        bnez  t1, de_1                  ; ...
        sd    zero, g_demo - g(gp)      ; the end
        sd    zero, g_fast - g(gp)      ; (the last picture is drawn)
        li    t1, 1                     ; ...
        sd    t1, g_paused - g(gp)      ; ...
        sd    t1, g_dirty - g(gp)       ; ...
        sd    t1, g_bardirty - g(gp)    ; ...
        j     demo_say                  ; ...
de_1:   addi  t1, t1, -1                ; ...
        sd    t1, g_dleft - g(gp)       ; ...
        bnez  t1, de_r                  ; ...
        lbu   a0, 1(t0)                 ; ...
        addi  t0, t0, 2                 ; ...
        sd    t0, g_demo - g(gp)        ; ...
        li    t1, DK_CLICK              ; a click: the next two bytes are x / 2 and y
        beq   a0, t1, de_c              ; ...
        li    t1, DK_FAST               ; the tics not drawn begin, or end
        bne   a0, t1, de_s              ; ...
        ld    t1, g_fast - g(gp)        ; ...
        xori  t1, t1, 1                 ; ...
        sd    t1, g_fast - g(gp)        ; ...
        li    t1, 1                     ; ...
        sd    t1, g_dirty - g(gp)       ; ...
        sd    t1, g_bardirty - g(gp)    ; ...
        ret                             ; ...
de_s:   li    t1, DK_SEED               ; the random numbers start over
        bne   a0, t1, de_l              ; ...
        li    t1, SEED0                 ; ...
        sd    t1, g_seed - g(gp)        ; ...
        ret                             ; ...
de_l:   li    t1, DK_LOOP               ; what follows, up to DK_END, so many times
        bne   a0, t1, de_e              ; ...
        lbu   t1, 0(t0)                 ; ...
        sd    t1, g_dloop - g(gp)       ; ...
        addi  t0, t0, 2                 ; ...
        sd    t0, g_demo - g(gp)        ; ...
        sd    t0, g_dmark - g(gp)       ; ...
        ret                             ; ...
de_e:   li    t1, DK_END                ; ...
        bne   a0, t1, do_key            ; ...
        ld    t1, g_dloop - g(gp)       ; ...
        addi  t1, t1, -1                ; ...
        sd    t1, g_dloop - g(gp)       ; ...
        blez  t1, de_r                  ; ...
        ld    t0, g_dmark - g(gp)       ; ...
        sd    t0, g_demo - g(gp)        ; ...
        ret                             ; ...
de_c:   lbu   a0, 0(t0)                 ; ...
        slli  a0, a0, 1                 ; ...
        lbu   a1, 1(t0)                 ; ...
        addi  t0, t0, 2                 ; ...
        sd    t0, g_demo - g(gp)        ; ...
        j     click                     ; ...
de_r:   ret                             ; done

; rnd() -> a0 = 0 .. 32767. Clobbers t0.
rnd:    ld    a0, g_seed - g(gp)        ; the usual linear congruence
        li    t0, 1103515245            ; ...
        mul   a0, a0, t0                ; ...
        addi  a0, a0, 12345             ; ...
        sd    a0, g_seed - g(gp)        ; ...
        srli  a0, a0, 16                ; ...
        li    t0, 0x7fff                ; ...
        and   a0, a0, t0                ; ...
        ret                             ; done

; rnd_n(a0 = n) -> a0 = 0 .. n - 1. Clobbers t0.
rnd_n:  addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    a0, 8(sp)                 ; n
        call  rnd                       ; ...
        ld    t0, 8(sp)                 ; ...
        remu  a0, a0, t0                ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 16                ; pop the frame
        ret                             ; done

; demo_say(): on standard error: "sushi: demo: N frames in N ms"
demo_say:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = where the text goes on
        sd    s1, 16(sp)                ; s1 = the milliseconds
        call  sys_now                   ; ...
        ld    t0, g_dt0 - g(gp)         ; ...
        sub   s1, a0, t0                ; ...
        li    t0, 1000                  ; ...
        divu  s1, s1, t0                ; ...
        la    s0, s_dnum                ; the frames: a tic each
        ld    a0, g_tic - g(gp)         ; ...
        call  dy_num                    ; ...
        la    a0, s_dfr                 ; ...
        call  dy_str                    ; ...
        mv    a0, s1                    ; the time
        call  dy_num                    ; ...
        la    a0, s_dms                 ; ...
        call  dy_str                    ; ...
        la    a0, s_dmsg                ; (the pieces follow one another in the data)
        la    t0, s_dmsg                ; ...
        sub   a1, s0, t0                ; ...
        call  err_str                   ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done
dy_str: lbu   t0, 0(a0)                 ; a0 = text, NUL-terminated: append it at s0
        beqz  t0, dy_r                  ; ...
        sb    t0, 0(s0)                 ; ...
        addi  a0, a0, 1                 ; ...
        addi  s0, s0, 1                 ; ...
        j     dy_str                    ; ...
dy_num: li    t1, 10                    ; a0 = number: append its decimal digits at s0
        li    t2, 0                     ; t2 = digits (on the stack, last first)
dy_n1:  remu  t0, a0, t1                ; ...
        divu  a0, a0, t1                ; ...
        addi  t0, t0, '0'               ; ...
        addi  sp, sp, -8                ; ...
        sd    t0, 0(sp)                 ; ...
        addi  t2, t2, 1                 ; ...
        bnez  a0, dy_n1                 ; ...
dy_n2:  ld    t0, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        sb    t0, 0(s0)                 ; ...
        addi  s0, s0, 1                 ; ...
        addi  t2, t2, -1                ; ...
        bnez  t2, dy_n2                 ; ...
dy_r:   ret                             ; done

; load_dat() -> a0 = 0, or -1: read /ws/sushi.dat: its resident block into
; `res`, its far block into the top of the arena (through the slab)
load_dat:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = handle
        sd    s1, 16(sp)                ; s1 = where the next bytes go
        sd    s2, 24(sp)                ; s2 = bytes left
        la    a0, s_dat                 ; ...
        li    a1, s_dat_e - s_dat       ; ...
        li    a2, 0                     ; ...
        call  sys_open                  ; ...
        mv    s0, a0                    ; ...
        bltz  a0, ld_bad                ; ...
        la    s1, res                   ; the resident block
        li    s2, R_SIZE                ; ...
ld_r:   mv    a0, s0                    ; (a message of data at a time)
        mv    a1, s1                    ; ...
        mv    a2, s2                    ; ...
        call  sys_read                  ; ...
        blez  a0, ld_bad                ; ...
        add   s1, s1, a0                ; ...
        sub   s2, s2, a0                ; ...
        bgtz  s2, ld_r                  ; ...
        ld    s1, g_keepb - g(gp)       ; the far block
        li    s2, F_SIZE                ; ...
ld_f:   mv    a0, s0                    ; ...
        la    a1, slab                  ; ...
        mv    a2, s2                    ; ...
        call  sys_read                  ; ...
        blez  a0, ld_bad                ; ...
        addi  t0, a0, 7                 ; (whole words)
        srli  t0, t0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        la    t1, slab                  ; ...
        tput  tg9, t1, c0, s1, t0       ; (the next read's stores wait for it)
        add   s1, s1, a0                ; ...
        sub   s2, s2, a0                ; ...
        bgtz  s2, ld_f                  ; ...
        mv    a0, s0                    ; ...
        call  sys_close                 ; ...
        li    a0, 0                     ; ...
        j     ld_ret                    ; ...
ld_bad: li    a0, -1                    ; ...
ld_ret: ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

; geom(): the window has a (new) size: the largest whole factor at which
; 320 x 200 fits and a slab fits the band, the picture's place, how many
; slabs the band holds; the window is cleared
geom:   addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        la    t0, wc_surf               ; ...
        ld    a2, S_W(t0)               ; a2 = width
        ld    a3, S_H(t0)               ; a3 = height
        li    t1, VIEW_W                ; the factor: by the width ...
        divu  t2, a2, t1                ; ...
        li    t1, VIEW_H + BAR_H        ; ... and the height,
        divu  t3, a3, t1                ; ...
        bleu  t2, t3, ge_1              ; ...
        mv    t2, t3                    ; ...
ge_1:   li    t1, 3                     ; ... three at most
        bleu  t2, t1, ge_2              ; ...
        mv    t2, t1                    ; ...
ge_2:   sd    t2, g_scale - g(gp)       ; ...
        beqz  t2, ge_c                  ; (too small for it)
        mul   t3, t2, t2                ; the band holds how many slabs at that factor?
        li    t1, SLAB_W * VIEW_H * 4   ; ...
        mul   t3, t3, t1                ; ...
        ld    t4, g_keepb - g(gp)       ; ...
        divu  t4, t4, t3                ; ...
        bnez  t4, ge_3                  ; ...
        addi  t2, t2, -1                ; none: a smaller picture
        j     ge_2                      ; ...
ge_3:   li    t1, NSLAB                 ; ...
        bleu  t4, t1, ge_4              ; ...
        mv    t4, t1                    ; ...
ge_4:   sd    t4, g_grp - g(gp)         ; ...
        li    t1, VIEW_W                ; centred (at an even column)
        mul   t1, t1, t2                ; ...
        sub   t1, a2, t1                ; ...
        srli  t1, t1, 2                 ; ...
        slli  t1, t1, 1                 ; ...
        sd    t1, g_ox - g(gp)          ; ...
        li    t1, VIEW_H + BAR_H        ; ...
        mul   t1, t1, t2                ; ...
        sub   t1, a3, t1                ; ...
        srli  t1, t1, 1                 ; ...
        sd    t1, g_oy - g(gp)          ; ...
ge_c:   li    a0, 0                     ; walnut around it
        li    a1, 0                     ; ...
        li    a4, BORDER                ; ...
        call  wc_fill                   ; ...
        li    t0, 1                     ; everything is to be drawn
        sd    t0, g_bardirty - g(gp)    ; ...
        sd    t0, g_dirty - g(gp)       ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; ev_handle(): the event in wc_ev
ev_handle:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = key bytes
        sd    s1, 16(sp)                ; s1 = how many
        la    t0, wc_ev                 ; its kind
        ld    t1, 0(t0)                 ; ...
        li    t2, WE_SIZE               ; a resize (already applied to wc_surf)
        bne   t1, t2, ev_1              ; ...
        call  geom                      ; ...
        j     ev_r                      ; ...
ev_1:   li    t2, WE_CLOSE              ; close: end
        bne   t1, t2, ev_2              ; ...
        li    t2, 1                     ; ...
        sd    t2, g_quit - g(gp)        ; ...
        j     ev_r                      ; ...
ev_2:   li    t2, WE_BLUR               ; the focus went: wait
        bne   t1, t2, ev_3              ; ...
        li    t2, 1                     ; ...
        sd    t2, g_paused - g(gp)      ; ...
        j     ev_r                      ; ...
ev_3:   li    t2, WE_FOCUS              ; ... and came back
        bne   t1, t2, ev_4              ; ...
        sd    zero, g_paused - g(gp)    ; ...
        j     ev_r                      ; ...
ev_4:   li    t2, WE_PTR                ; the pointer
        bne   t1, t2, ev_5              ; ...
        ld    t3, 8(t0)                 ; x, y, buttons
        srli  t5, t3, 32                ; ...
        andi  t5, t5, 0xff              ; t5 = buttons
        ld    t6, g_btn - g(gp)         ; t6 = the buttons before
        sd    t5, g_btn - g(gp)         ; ...
        andi  t5, t5, 1                 ; the left button went down?
        beqz  t5, ev_r                  ; ...
        andi  t6, t6, 1                 ; ...
        bnez  t6, ev_r                  ; ...
        ld    t2, g_demo - g(gp)        ; (not while the demo plays)
        bnez  t2, ev_r                  ; ...
        sd    zero, g_paused - g(gp)    ; (a press wakes a program that stands still)
        ld    t4, g_scale - g(gp)       ; where, on the 320 x 200 screen
        beqz  t4, ev_r                  ; ...
        li    t1, 0xffff                ; ...
        and   a0, t3, t1                ; ...
        ld    t2, g_ox - g(gp)          ; ...
        sub   a0, a0, t2                ; ...
        bltz  a0, ev_r                  ; ...
        divu  a0, a0, t4                ; ...
        li    t2, VIEW_W                ; ...
        bgeu  a0, t2, ev_r              ; ...
        srli  a1, t3, 16                ; ...
        and   a1, a1, t1                ; ...
        ld    t2, g_oy - g(gp)          ; ...
        sub   a1, a1, t2                ; ...
        bltz  a1, ev_r                  ; ...
        divu  a1, a1, t4                ; ...
        li    t2, VIEW_H + BAR_H        ; ...
        bgeu  a1, t2, ev_r              ; ...
        call  click                     ; ...
        j     ev_r                      ; ...
ev_5:   li    t2, WE_KEY                ; keys
        bne   t1, t2, ev_r              ; ...
        ld    t2, g_demo - g(gp)        ; (not while the demo plays, but q)
        sd    zero, g_paused - g(gp)    ; (a key wakes a program that stands still)
        beqz  t2, ev_k0                 ; ...
        ld    t3, 8(t0)                 ; ...
        andi  t3, t3, 0xff              ; ...
        li    t2, 'q'                   ; ...
        bne   t3, t2, ev_r              ; ...
ev_k0:  la    t0, wc_ev                 ; ...
        ld    s0, 8(t0)                 ; ...
        ld    s1, 16(t0)                ; ...
ev_k:   beqz  s1, ev_r                  ; ...
        andi  a0, s0, 0xff              ; ...
        call  key                       ; ...
        srli  s0, s0, 8                 ; ...
        addi  s1, s1, -1                ; ...
        j     ev_k                      ; ...
ev_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; key(a0 = a byte from the keyboard): arrows come as ESC [ A..D; W A S D are
; arrows too; capitals count as small letters
key:    ld    t0, g_esc - g(gp)         ; in a sequence?
        beqz  t0, ke_0                  ; ...
        li    t1, 1                     ; ...
        bne   t0, t1, ke_2              ; ...
        sd    zero, g_esc - g(gp)       ; after ESC: [ goes on, anything else is a key
        li    t1, '['                   ; ...
        bne   a0, t1, ke_0              ; ...
        li    t1, 2                     ; ...
        sd    t1, g_esc - g(gp)         ; ...
        ret                             ; ...
ke_2:   li    t1, '@'                   ; after ESC [: parameters, then the final byte
        bltu  a0, t1, ke_r              ; ...
        sd    zero, g_esc - g(gp)       ; ...
        addi  t0, a0, -'A'              ; A B C D: up, down, right, left
        li    t1, 4                     ; ...
        bgeu  t0, t1, ke_r              ; ...
        la    t1, k_arrow               ; ...
        add   t0, t0, t1                ; ...
        lbu   a0, 0(t0)                 ; ...
        j     do_key                    ; ...
ke_0:   li    t1, 0x1b                  ; ESC starts a sequence
        bne   a0, t1, ke_1              ; ...
        li    t1, 1                     ; ...
        sd    t1, g_esc - g(gp)         ; ...
        ret                             ; ...
ke_1:   li    t1, 'A'                   ; capitals count as small letters
        bltu  a0, t1, ke_p              ; ...
        li    t1, 'Z'                   ; ...
        bgtu  a0, t1, ke_p              ; ...
        ori   a0, a0, 0x20              ; ...
ke_p:   li    t0, K_UP                  ; w a s d
        li    t1, 'w'                   ; ...
        beq   a0, t1, ke_a              ; ...
        li    t0, K_DOWN                ; ...
        li    t1, 's'                   ; ...
        beq   a0, t1, ke_a              ; ...
        li    t0, K_LEFT                ; ...
        li    t1, 'a'                   ; ...
        beq   a0, t1, ke_a              ; ...
        li    t0, K_RIGHT               ; ...
        li    t1, 'd'                   ; ...
        beq   a0, t1, ke_a              ; ...
        li    t1, ' '                   ; (control characters but Backspace, Enter
        bgeu  a0, t1, do_key            ;   and Tab mean nothing)
        li    t1, 8                     ; ...
        beq   a0, t1, do_key            ; ...
        li    t1, 10                    ; ...
        beq   a0, t1, do_key            ; ...
        li    t1, 13                    ; ...
        beq   a0, t1, do_key            ; ...
        li    t1, 9                     ; ...
        beq   a0, t1, do_key            ; ...
ke_r:   ret                             ; ...
ke_a:   mv    a0, t0                    ; ...
        j     do_key                    ; ...

        .data                           ; D-LS
k_arrow:  .byte K_UP, K_DOWN, K_RIGHT, K_LEFT ; ESC [ A, B, C, D
        .align 8                        ; ...
        .text                           ; code
