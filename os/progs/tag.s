; =============================================================================
; tag.s: give a file tags, take them away, or replace them
; =============================================================================
;
;   tag FILE TAG...       FILE now carries each TAG (a new tag is created)
;   untag FILE TAG...     FILE no longer carries them
;   retag FILE [TAG...]   FILE carries exactly these TAGs (none: no tags)
;
; One program, three names: the disk carries it as `tag`, `untag` and
; `retag`, and it looks at the name it was started by (the first word of its
; command line, after any tags in front of it: /bin/untag is untag). FILE is
; a path like any other ("/doc/motd" names motd if it carries doc). Each tag
; goes to the file server with sys_tag / sys_untag; retag first asks for the
; file's tags (sys_tags2), gives it the new ones, then takes away the old ones
; not among them. Errors go to standard error and make the exit code 1:
; "tag: no such file: FILE", "tag: cannot tag FILE with TAG" (a bad tag name:
; 1..16 bytes, no "/", not starting with "-"; or all 64 tags in use).

        .data                           ; data Local Store
        .align 8                        ; aligned buffer
args:   .space 512                      ; the argument text (a command line is at most 440 bytes)
tname:  .dword 0                        ; the tag being given
tlen:   .dword 0                        ; its length
tcur:   .dword 0                        ; retag: where the tags start in args
tcnt:   .dword 0                        ; retag: the file's old tags
tagbuf: .space 4032                     ; retag: their records (sys_tags2: one message's worth)
m_use:  .ascii "usage: tag FILE TAG... / untag FILE TAG... / retag FILE [TAG...]\n" ; error text
m_use_e:                                ; end of the text above
m_no:   .ascii "tag: no such file: "    ; error text
m_no_e:                                 ; end of the text above
m_bad:  .ascii "tag: cannot tag "       ; error text
m_bad_e:                                ; end of the text above
m_with: .ascii " with "                 ; ...
m_with_e:                               ; end of the text above
m_un:   .ascii "untag"                  ; the other names
m_re:   .ascii "retag"                  ; ...

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        call  sys_init                  ; handles and arguments
        li    s5, 0                     ; s5 = 0 tag, 1 untag, 2 retag
        call  sys_cmdline               ; the name we were started by
        mv    t0, a0                    ; t0 = cursor, t1 = end
        add   t1, a0, a1                ; ...
        mv    t2, a0                    ; t2 = where its last component starts
nm_l:
        bgeu  t0, t1, nm_end            ; the end of the line
        lbu   t3, 0(t0)                 ; ...
        li    t4, ' '                   ; the end of the name
        beq   t3, t4, nm_end            ; ...
        addi  t0, t0, 1                 ; ...
        li    t4, '/'                   ; a separator: the name starts after it
        bne   t3, t4, nm_l              ; ...
        mv    t2, t0                    ; ...
        j     nm_l                      ; ...
nm_end:
        mv    s6, t2                    ; s6, s7 = the name
        sub   s7, t0, t2                ; ...
        mv    a0, s6                    ; is it "untag"?
        mv    a1, s7                    ; ...
        la    a2, m_un                  ; ...
        li    a3, 5                     ; ...
        call  str_eq                    ; ...
        mv    s5, a0                    ; ...
        bnez  s5, nm_done               ; untag
        mv    a0, s6                    ; is it "retag"?
        mv    a1, s7                    ; ...
        la    a2, m_re                  ; ...
        li    a3, 5                     ; ...
        call  str_eq                    ; ...
        slli  s5, a0, 1                 ; 2 if so
nm_done:
        li    s4, 0                     ; s4 = exit code
        la    a0, args                  ; the arguments ...
        call  sys_args                  ; ... a0 = their length
        la    s0, args                  ; s0 = cursor
        add   s1, s0, a0                ; s1 = end
        mv    a0, s0                    ; the file
        mv    a1, s1                    ; ...
        call  arg_next                  ; a0 = start, a1 = length, a2 = cursor after
        beqz  a1, usage                 ; none
        mv    s0, a2                    ; ...
        mv    s2, a0                    ; s2, s3 = the file
        mv    s3, a1                    ; ...
        li    t0, 2                     ; retag?
        beq   s5, t0, re_old            ; yes: no tag at all is fine
        mv    a0, s0                    ; at least one tag
        mv    a1, s1                    ; ...
        call  arg_next                  ; ...
        beqz  a1, usage                 ; ...
next:
        mv    a0, s0                    ; the next tag
        mv    a1, s1                    ; ...
        call  arg_next                  ; a0 = start, a1 = length, a2 = cursor after
        beqz  a1, n_end                 ; no more
        mv    s0, a2                    ; advance the cursor
        mv    a2, a0                    ; the tag
        mv    a3, a1                    ; ...
        la    t0, tname                 ; (kept for a message)
        sd    a2, 0(t0)                 ; ...
        la    t0, tlen                  ; ...
        sd    a3, 0(t0)                 ; ...
        mv    a0, s2                    ; the file
        mv    a1, s3                    ; ...
        li    t0, 1                     ; tag (or retag) or untag?
        bne   s5, t0, n_tag             ; ...
        call  sys_untag                 ; a0 = 0 or < 0
        j     n_res                     ; ...
n_tag:
        call  sys_tag                   ; a0 = 0 or < 0
n_res:
        bgez  a0, next                  ; done
        li    s4, 1                     ; remember the failure
        li    t0, -4                    ; no such file?
        bne   a0, t0, n_bad             ; no: the tag
n_nofile:
        la    a0, m_no                  ; "tag: no such file: "
        li    a1, m_no_e - m_no         ; ...
        call  err_str                   ; ...
        mv    a0, s2                    ; the file
        mv    a1, s3                    ; ...
        call  err_str                   ; ...
        la    a0, sys_nl                ; a newline
        li    a1, 1                     ; ...
        call  err_str                   ; ...
        j     done                      ; the other tags would fail too
n_bad:
        la    a0, m_bad                 ; "tag: cannot tag "
        li    a1, m_bad_e - m_bad       ; ...
        call  err_str                   ; ...
        mv    a0, s2                    ; the file
        mv    a1, s3                    ; ...
        call  err_str                   ; ...
        la    a0, m_with                ; " with "
        li    a1, m_with_e - m_with     ; ...
        call  err_str                   ; ...
        la    a0, tname                 ; the tag
        ld    a0, 0(a0)                 ; ...
        la    a1, tlen                  ; ...
        ld    a1, 0(a1)                 ; ...
        call  err_str                   ; ...
        la    a0, sys_nl                ; a newline
        li    a1, 1                     ; ...
        call  err_str                   ; ...
        j     next                      ; the next tag
n_end:
        li    t0, 2                     ; retag: the old tags not given go
        bne   s5, t0, done              ; ...
        la    s0, tagbuf                ; s0 = an old tag's record
        la    t0, tcnt                  ; s5 = records left (the mode is not
        ld    s5, 0(t0)                 ; needed any more)
re_l:
        blez  s5, done                  ; no more
        lhu   a0, 2(s0)                 ; its name's length
        la    t0, tlen                  ; ...
        sd    a0, 0(t0)                 ; ...
        la    t0, tcur                  ; s6 = the tags given, again
        ld    s6, 0(t0)                 ; ...
re_a:
        mv    a0, s6                    ; the next one given
        mv    a1, s1                    ; ...
        call  arg_next                  ; a0 = start, a1 = length, a2 = cursor after
        beqz  a1, re_un                 ; not among them: it goes
        mv    s6, a2                    ; ...
        addi  a2, s0, 16                ; the same name?
        la    a3, tlen                  ; ...
        ld    a3, 0(a3)                 ; ...
        call  str_eq                    ; ...
        beqz  a0, re_a                  ; no: the next one
        j     re_n                      ; yes: it stays
re_un:
        mv    a0, s2                    ; take it away
        mv    a1, s3                    ; ...
        addi  a2, s0, 16                ; ...
        la    a3, tlen                  ; ...
        ld    a3, 0(a3)                 ; ...
        call  sys_untag                 ; ...
re_n:
        lhu   t0, 0(s0)                 ; the next old tag
        add   s0, s0, t0                ; ...
        addi  s5, s5, -1                ; ...
        j     re_l                      ; ...
re_old:
        la    t0, tcur                  ; the tags given start here
        sd    s0, 0(t0)                 ; ...
        la    a0, tagbuf                ; the file's tags now
        mv    a1, s2                    ; ...
        mv    a2, s3                    ; ...
        li    a3, 0                     ; ...
        call  sys_tags2                 ; a0 = how many, or < 0
        bltz  a0, re_no                 ; no such file
        la    t0, tcnt                  ; ...
        sd    a0, 0(t0)                 ; ...
        j     next                      ; give it the new ones first
re_no:
        li    s4, 1                     ; remember the failure
        j     n_nofile                  ; ...
usage:
        la    a0, m_use                 ; how to use it
        li    a1, m_use_e - m_use       ; ...
        call  err_str                   ; ...
        li    s4, 2                     ; exit code for a usage error
done:
        mv    a0, s4                    ; exit code
        call  sys_exit                  ; flush stdout, end the process

        .include "../lib/sys.s"         ; the system interface
