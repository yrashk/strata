; =============================================================================
; tag.s: give a file tags, take them away, or replace them
; =============================================================================
;
;   tag FILE TAG...       FILE goes into the directory of its tags and these
;                         (a new tag is created)
;   untag FILE TAG...     into the one without them
;   retag FILE [TAG...]   into the one of exactly these (none: the root)
;
; A file's directory is the set of its tags, so each of these moves the file:
; `tag /src/x demo` makes it /src/demo/x. One program, three names: the disk
; carries it as `tag`, `untag` and `retag`, and it looks at the name it was
; started by (the last component of the first word of its command line).
; FILE is a path like any other. All the tags go to the file server in one
; request (sys_tag / sys_untag: the names with a zero byte between them; for
; retag a first name "/", which empties the set), so the file moves once.
; Errors go to standard error and make the exit code 1: "tag: no such file:
; FILE", "tag: cannot tag FILE with TAG..." (a bad tag name; a file of that
; name is in the directory it would go to; too many tags).

        .data                           ; data Local Store
        .align 8                        ; aligned buffer
args:   .space 512                      ; the argument text (a command line is at most 440 bytes)
tbuf:   .space 520                      ; the tags' names, a zero byte between them
m_use:  .ascii "usage: tag FILE TAG... / untag FILE TAG... / retag FILE [TAG...]\n" ; error text
m_use_e:                                ; end of the text above
m_no:   .ascii "tag: no such file: "    ; error text
m_no_e:                                 ; end of the text above
m_bad:  .ascii "tag: cannot tag "       ; error text
m_bad_e:                                ; end of the text above
m_with: .ascii " with "                 ; ...
m_with_e:                               ; end of the text above
m_un:   .ascii "untag"                  ; the other names
m_re:   .ascii "retag"                  ; ...

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        call  sys_init                  ; handles and arguments
        li    s5, 0                     ; s5 = 0 tag, 1 untag, 2 retag
        call  sys_cmdline               ; the name we were started by
        mv    t0, a0                    ; t0 = cursor, t1 = end
        add   t1, a0, a1                ; ...
        mv    t2, a0                    ; t2 = where its last component starts
nm_l:
        bgeu  t0, t1, nm_end            ; the end of the line
        lbu   t3, 0(t0)                 ; ...
        li    t4, ' '                   ; the end of the name
        beq   t3, t4, nm_end            ; ...
        addi  t0, t0, 1                 ; ...
        li    t4, '/'                   ; a separator: the name starts after it
        bne   t3, t4, nm_l              ; ...
        mv    t2, t0                    ; ...
        j     nm_l                      ; ...
nm_end:
        mv    s6, t2                    ; s6, s7 = the name
        sub   s7, t0, t2                ; ...
        mv    a0, s6                    ; is it "untag"?
        mv    a1, s7                    ; ...
        la    a2, m_un                  ; ...
        li    a3, 5                     ; ...
        call  str_eq                    ; ...
        mv    s5, a0                    ; ...
        bnez  s5, nm_done               ; untag
        mv    a0, s6                    ; is it "retag"?
        mv    a1, s7                    ; ...
        la    a2, m_re                  ; ...
        li    a3, 5                     ; ...
        call  str_eq                    ; ...
        slli  s5, a0, 1                 ; 2 if so
nm_done:
        li    s4, 0                     ; s4 = exit code
        la    a0, args                  ; the arguments ...
        call  sys_args                  ; ... a0 = their length
        la    s0, args                  ; s0 = cursor
        add   s1, s0, a0                ; s1 = end
        mv    a0, s0                    ; the file
        mv    a1, s1                    ; ...
        call  arg_next                  ; a0 = start, a1 = length, a2 = cursor after
        beqz  a1, usage                 ; none
        mv    s0, a2                    ; ...
        mv    s2, a0                    ; s2, s3 = the file
        mv    s3, a1                    ; ...
        la    s6, tbuf                  ; s6 = the names as they are sent
        li    t0, 2                     ; retag: from no tag at all ("/" first), and none
        bne   s5, t0, t_need            ; given is fine
        li    t1, '/'                   ; ...
        sb    t1, 0(s6)                 ; ...
        sb    zero, 1(s6)               ; ...
        addi  s6, s6, 2                 ; ...
        j     t_copy                    ; ...
t_need:
        mv    a0, s0                    ; at least one tag
        mv    a1, s1                    ; ...
        call  arg_next                  ; ...
        beqz  a1, usage                 ; ...
t_copy:
        mv    t0, s0                    ; the rest of the line: a zero byte for a space
t_c:
        bgeu  t0, s1, t_send            ; ...
        lbu   t1, 0(t0)                 ; ...
        addi  t0, t0, 1                 ; ...
        li    t2, ' '                   ; ...
        bne   t1, t2, t_b               ; ...
        li    t1, 0                     ; ...
t_b:
        sb    t1, 0(s6)                 ; ...
        addi  s6, s6, 1                 ; ...
        j     t_c                       ; ...
t_send:
        mv    a0, s2                    ; the file
        mv    a1, s3                    ; ...
        la    a2, tbuf                  ; ...
        sub   a3, s6, a2                ; ...
        li    t0, 1                     ; untag, or tag (retag is a tag from nothing)
        bne   s5, t0, t_tag             ; ...
        call  sys_untag                 ; a0 = 0 or < 0
        j     t_res                     ; ...
t_tag:
        call  sys_tag                   ; a0 = 0 or < 0
t_res:
        bgez  a0, done                  ; done
        li    s4, 1                     ; the failure
        li    t0, -4                    ; no such file?
        bne   a0, t0, t_bad             ; ...
        la    a0, m_no                  ; "tag: no such file: "
        li    a1, m_no_e - m_no         ; ...
        call  err_str                   ; ...
        mv    a0, s2                    ; the file
        mv    a1, s3                    ; ...
        j     t_nl                      ; ...
t_bad:
        la    a0, m_bad                 ; "tag: cannot tag "
        li    a1, m_bad_e - m_bad       ; ...
        call  err_str                   ; ...
        mv    a0, s2                    ; the file
        mv    a1, s3                    ; ...
        call  err_str                   ; ...
        la    a0, m_with                ; " with "
        li    a1, m_with_e - m_with     ; ...
        call  err_str                   ; ...
        mv    a0, s0                    ; the tags as they were written (after the space)
        sub   a1, s1, s0                ; ...
        beqz  a1, t_nl2                 ; ...
        lbu   t0, 0(a0)                 ; ...
        li    t1, ' '                   ; ...
        bne   t0, t1, t_nl              ; ...
        addi  a0, a0, 1                 ; ...
        addi  a1, a1, -1                ; ...
t_nl:
        call  err_str                   ; ...
t_nl2:
        la    a0, sys_nl                ; a newline
        li    a1, 1                     ; ...
        call  err_str                   ; ...
        j     done                      ; ...
usage:
        la    a0, m_use                 ; how to use it
        li    a1, m_use_e - m_use       ; ...
        call  err_str                   ; ...
        li    s4, 2                     ; exit code for a usage error
done:
        mv    a0, s4                    ; exit code
        call  sys_exit                  ; flush stdout, end the process

        .include "../lib/sys.s"         ; the system interface
