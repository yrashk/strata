; =============================================================================
; wmandel.s: the Mandelbrot set in a window
; =============================================================================
;
;   wmandel         (from a shell in a terminal, or the palette: Alt+Space)
;
; A client of the window server (os/lib/wsclient.s). It computes the set a
; few rows at a time (os/ws/wmandel.s: each batch is one pass of the strip
; renderer over an item whose handler computes a row of points), into its
; band, and lends each batch to the server (DAMAGE), so the picture grows
; on the screen as it is computed. Between batches it looks for events
; without blocking: a resize starts the picture again at the new size, `q`
; or a close event ends the program. When the picture is complete it waits
; in EVENT and uses no processor time at all.

MW_BATCH  = 8                           ; rows computed between looks at the events

        .text                           ; instruction Local Store
_start: j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program

        .include "../ws/theme.s"        ; the palette
        .include "../lib/gfx.s"         ; surfaces and display lists
        .include "../ws/wmandel.s"      ; the renderer
        .include "../lib/sys.s"         ; the program library
        .include "../lib/wsclient.s"    ; the window server's protocol

        .data                           ; D-LS
        .align 8                        ; dwords
mw_md:    .space MD_SIZE                ; the renderer's state
mw_title: .ascii "WMANDEL\0"            ; the window's title
mw_nows:  .ascii "wmandel: no window server (run ws first)\n"
mw_nows_e:                              ; (its end)
        .text                           ; code

main:
        li    sp, 65536                 ; stack at the top of the D-LS
        call  sys_init                  ; handles
        la    a0, mw_title              ; our window (events are polled: no flags)
        li    a1, 0                     ; ...
        call  wc_open                   ; ...
        bgtz  a0, mw_new                ; ...
        la    a0, mw_nows               ; no server
        li    a1, mw_nows_e - mw_nows   ; ...
        call  err_str                   ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...
mw_new: la    a0, mw_md                 ; a new picture at the window's size
        la    a1, wc_surf               ; ...
        call  md_start                  ; ...
mw_loop:
        li    a0, 1                     ; an event? (do not block)
        li    a1, 0                     ; ...
        call  wc_event                  ; ...
        li    t0, -3                    ; none
        beq   a0, t0, mw_draw           ; ...
        j     mw_ev                     ; ...
mw_draw:
        la    t0, mw_md                 ; the band starts at the next row to compute
        ld    a0, MD_ROW(t0)            ; ...
        call  wc_band                   ; ...
        la    a0, mw_md                 ; a batch: a0 = first row, a1 = past the last
        li    a1, MW_BATCH              ; ...
        la    t0, wc_rows               ; (never more than the band holds)
        ld    t0, 0(t0)                 ; ...
        bge   t0, a1, mw_d1             ; ...
        mv    a1, t0                    ; ...
mw_d1:  call  md_step                   ; ...
        beq   a0, a1, mw_wait           ; the picture is complete
        sub   a1, a1, a0                ; lend those rows
        call  wc_damage                 ; ...
        bltz  a0, mw_end                ; the window is gone
        j     mw_loop                   ; ...
mw_wait:
        li    a0, 0                     ; nothing to compute: wait for an event
        li    a1, 0                     ; ...
        call  wc_event                  ; ...
mw_ev:  bnez  a0, mw_end                ; the window is gone
        la    t0, wc_ev                 ; its kind
        ld    t1, 0(t0)                 ; ...
        li    t2, WE_SIZE               ; a resize: again, at the new size
        beq   t1, t2, mw_new            ; ...
        li    t2, WE_CLOSE              ; close: end
        beq   t1, t2, mw_end            ; ...
        li    t2, WE_KEY                ; a key: q ends
        bne   t1, t2, mw_loop           ; ...
        ld    t3, 16(t0)                ; its bytes
        ld    t4, 8(t0)                 ; ...
mw_k:   beqz  t3, mw_loop               ; ...
        andi  t5, t4, 0xff              ; ...
        li    t6, 'q'                   ; ...
        beq   t5, t6, mw_end            ; ...
        srli  t4, t4, 8                 ; ...
        addi  t3, t3, -1                ; ...
        j     mw_k                      ; ...
mw_end: call  wc_close                  ; the window goes
        li    a0, 0                     ; ...
        call  sys_exit                  ; ...
