; =============================================================================
; wmandel.s: the Mandelbrot set in a window
; =============================================================================
;
;   wmandel         (from a shell in a terminal, or the palette: Alt+Space)
;
; A client of the window server (os/lib/wsclient.s). It computes the set a
; few rows at a time (os/ws/wmandel.s: each batch is one pass of the strip
; renderer over an item whose handler computes a row of points), into its
; band, and lends each batch to the server (DAMAGE), so the picture grows
; on the screen as it is computed. Between batches it looks for events
; without blocking: a resize starts the picture again at the new size, `q`
; or a close event ends the program. When the picture is complete it waits
; in EVENT and uses no processor time at all. The pointer: the wheel zooms
; in (away from the user) or out around the point under it; dragging with
; the left button pans.

MW_BATCH  = 8                           ; rows computed between looks at the events

        .text                           ; instruction Local Store
_start: j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program

        .include "../ws/theme.s"        ; the palette
        .include "../lib/gfx.s"         ; surfaces and display lists
        .include "../ws/wmandel.s"      ; the renderer
        .include "../lib/sys.s"         ; the program library
        .include "../lib/wsclient.s"    ; the window server's protocol

        .data                           ; D-LS
        .align 8                        ; dwords
mw_md:    .space MD_SIZE                ; the renderer's state
mw_title: .ascii "WMANDEL\0"            ; the window's title
        .align 8                        ; dwords
mw_drag:  .dword 0                      ; a drag: 1 while the left button is held
mw_px:    .dword 0                      ; where it was pressed
mw_py:    .dword 0                      ; ...
mw_x0:    .dword 0                      ; the view then
mw_y0:    .dword 0                      ; ...
mw_nows:  .ascii "wmandel: no window server (run ws first)\n"
mw_nows_e:                              ; (its end)
        .text                           ; code

main:
        li    sp, 65536                 ; stack at the top of the D-LS
        call  sys_init                  ; handles
        la    a0, mw_title              ; our window (events are polled: no flags)
        li    a1, 0                     ; ...
        call  wc_open                   ; ...
        bgtz  a0, mw_new                ; ...
        la    a0, mw_nows               ; no server
        li    a1, mw_nows_e - mw_nows   ; ...
        call  err_str                   ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...
mw_new: la    a0, mw_md                 ; a new picture at the window's size
        la    a1, wc_surf               ; ...
        call  md_start                  ; ...
mw_loop:
        li    a0, 1                     ; an event? (do not block)
        li    a1, 0                     ; ...
        call  wc_event                  ; ...
        li    t0, -3                    ; none
        beq   a0, t0, mw_draw           ; ...
        j     mw_ev                     ; ...
mw_draw:
        la    t0, mw_md                 ; the band starts at the next row to compute
        ld    a0, MD_ROW(t0)            ; ...
        call  wc_band                   ; ...
        la    a0, mw_md                 ; a batch: a0 = first row, a1 = past the last
        li    a1, MW_BATCH              ; ...
        la    t0, wc_rows               ; (never more than the band holds)
        ld    t0, 0(t0)                 ; ...
        bge   t0, a1, mw_d1             ; ...
        mv    a1, t0                    ; ...
mw_d1:  call  md_step                   ; ...
        beq   a0, a1, mw_wait           ; the picture is complete
        sub   a1, a1, a0                ; lend those rows
        call  wc_damage                 ; ...
        bltz  a0, mw_end                ; the window is gone
        j     mw_loop                   ; ...
mw_wait:
        li    a0, 0                     ; nothing to compute: wait for an event
        li    a1, 0                     ; ...
        call  wc_event                  ; ...
mw_ev:  bnez  a0, mw_end                ; the window is gone
        la    t0, wc_ev                 ; its kind
        ld    t1, 0(t0)                 ; ...
        li    t2, WE_SIZE               ; a resize: again, at the new size
        beq   t1, t2, mw_new            ; ...
        li    t2, WE_CLOSE              ; close: end
        beq   t1, t2, mw_end            ; ...
        li    t2, WE_WHEEL              ; the wheel: zoom
        beq   t1, t2, mw_zoom           ; ...
        li    t2, WE_PTR                ; the pointer: drag
        beq   t1, t2, mw_ptr            ; ...
        li    t2, WE_KEY                ; a key: q ends
        bne   t1, t2, mw_loop           ; ...
        ld    t3, 16(t0)                ; its bytes
        ld    t4, 8(t0)                 ; ...
mw_k:   beqz  t3, mw_loop               ; ...
        andi  t5, t4, 0xff              ; ...
        li    t6, 'q'                   ; ...
        beq   t5, t6, mw_end            ; ...
        srli  t4, t4, 8                 ; ...
        addi  t3, t3, -1                ; ...
        j     mw_k                      ; ...
; the wheel at (x, y): one step in (3/4) or out (4/3), the point under it stays
mw_zoom:
        ld    t3, 8(t0)                 ; the value
        slli  t4, t3, 16                ; wheel y (signed)
        srai  t4, t4, 56                ; ...
        beqz  t4, mw_loop               ; ...
        li    t5, 0xffff                ; t5 = x, t6 = y
        and   a2, t3, t5                ; ...
        srli  a3, t3, 16                ; ...
        and   a3, a3, t5                ; ...
        la    t0, mw_md                 ; ...
        ld    t1, MD_STEP(t0)           ; the step now
        mv    t2, t1                    ; the new one
        bltz  t4, mz_out                ; ...
        slli  t2, t1, 1                 ; in: 3/4 of it
        add   t2, t2, t1                ; ...
        srli  t2, t2, 2                 ; ...
        li    t5, 16                    ; (not finer than 16 / 2^24)
        bltu  t2, t5, mw_loop           ; ...
        j     mz_set                    ; ...
mz_out: slli  t2, t1, 2                 ; out: 4/3 of it
        li    t5, 3                     ; ...
        divu  t2, t2, t5                ; ...
        li    t5, 1 << (MD_FRAC - 4)    ; (not coarser than 1/16)
        bgeu  t2, t5, mw_loop           ; ...
mz_set: mul   t5, a2, t1                ; x0 += x * (step - new)
        mul   t6, a2, t2                ; ...
        sub   t5, t5, t6                ; ...
        ld    t6, MD_X0(t0)             ; ...
        add   t6, t6, t5                ; ...
        sd    t6, MD_X0(t0)             ; ...
        mul   t5, a3, t1                ; y0 += y * (step - new)
        mul   t6, a3, t2                ; ...
        sub   t5, t5, t6                ; ...
        ld    t6, MD_Y0(t0)             ; ...
        add   t6, t6, t5                ; ...
        sd    t6, MD_Y0(t0)             ; ...
        sd    t2, MD_STEP(t0)           ; ...
        sd    zero, MD_ROW(t0)          ; draw it again
        j     mw_loop                   ; ...

; the pointer: a left press starts a drag, moves while it is held pan
mw_ptr: ld    t3, 8(t0)                 ; the value
        li    t5, 0xffff                ; a2 = x, a3 = y
        and   a2, t3, t5                ; ...
        srli  a3, t3, 16                ; ...
        and   a3, a3, t5                ; ...
        srli  t4, t3, 32                ; the left button held?
        andi  t4, t4, 1                 ; ...
        la    t5, mw_drag               ; ...
        bnez  t4, mp_held               ; ...
        sd    zero, 0(t5)               ; released: the drag ends
        j     mw_loop                   ; ...
mp_held:
        ld    t6, 0(t5)                 ; a drag already?
        la    t0, mw_md                 ; ...
        bnez  t6, mp_pan                ; ...
        li    t6, 1                     ; no: it starts here
        sd    t6, 0(t5)                 ; ...
        sd    a2, mw_px - mw_drag(t5)   ; ...
        sd    a3, mw_py - mw_drag(t5)   ; ...
        ld    t6, MD_X0(t0)             ; ...
        sd    t6, mw_x0 - mw_drag(t5)   ; ...
        ld    t6, MD_Y0(t0)             ; ...
        sd    t6, mw_y0 - mw_drag(t5)   ; ...
        j     mw_loop                   ; ...
mp_pan: ld    t1, MD_STEP(t0)           ; x0 = x0 then - (x - px) * step
        ld    t6, mw_px - mw_drag(t5)   ; ...
        sub   t6, a2, t6                ; ...
        mul   t6, t6, t1                ; ...
        ld    t2, mw_x0 - mw_drag(t5)   ; ...
        sub   t2, t2, t6                ; ...
        sd    t2, MD_X0(t0)             ; ...
        ld    t6, mw_py - mw_drag(t5)   ; y0 likewise
        sub   t6, a3, t6                ; ...
        mul   t6, t6, t1                ; ...
        ld    t2, mw_y0 - mw_drag(t5)   ; ...
        sub   t2, t2, t6                ; ...
        sd    t2, MD_Y0(t0)             ; ...
        sd    zero, MD_ROW(t0)          ; draw it again
        j     mw_loop                   ; ...

mw_end: call  wc_close                  ; the window goes
        li    a0, 0                     ; ...
        call  sys_exit                  ; ...
