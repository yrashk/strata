; =============================================================================
; fsck.s: check the store on the disk
; =============================================================================
;
;   fsck          the last commit on the disk, checked: every tree page and
;                 every page's use
;
; The disk is a store of copy-on-write B+trees (doc/strata-store-format.md).
; fsck reads it as the file server last committed it, block by block (fs
; READBLK, os/lib/stview.s), and checks what `stdb check` checks of the
; store on the host:
;   - the meta block's checksum;
;   - every tree reached from it (the catalog, the free and pending trees,
;     every tree the catalog names): each page's checksum, its own number,
;     its kind and level, its keys in order;
;   - the boot manifest's page;
;   - every page from the first the store manages: in exactly one tree, one
;     stream's extent, one free or pending extent, a snapshot's dead list,
;     or the spare extent; and the count of free pages in the meta block.
; It does not look into the file system's records (names, tags, the index):
; `stdb check` does, on the host. Run it when nothing is writing: two commits
; while it reads can give it pages of different states, and it then reports
; problems that are not there.
;
; Prints a line per problem (the first 20) and a summary; the exit code is 1
; when there are problems or the disk is not a store.

BM_BYTES = 8192                         ; the page map: a bit a page (256 MiB of 4 KiB pages)
NTREE    = 255                          ; trees of the catalog it can remember
NSHOW    = 20                           ; problems it prints

        .data                           ; data Local Store
        .align 8                        ; dwords
nprob:  .dword 0                        ; problems found
ntp:    .dword 0                        ; tree pages
nsp:    .dword 0                        ; stream pages
nfree:  .dword 0                        ; free pages found
ndead:  .dword 0                        ; pages kept for snapshots
ntree:  .dword 0                        ; trees in the table
nomap:  .dword 0                        ; 1: the disk has more pages than the map
w_h:    .dword 0                        ; a walk: the tree's height,
w_mode: .dword 0                        ;   what its records are (0 nothing to do, 1 the
                                        ;   catalog's, 2 free extents, 3 pending, 4 extents)
w_stk:  .space 16 * 16                  ;   page and next cell, level by level
trees:  .space NTREE * 24               ; the catalog's trees: root, height, mode
meta:   .space 512                      ; the meta block
bm:     .space BM_BYTES                 ; the page map
m_nost: .ascii "fsck: the disk is not a store\n"
m_nost_e:
m_big:  .ascii "fsck: the disk has more pages than fsck can map: the trees are checked, the pages' use is not\n"
m_big_e:
m_meta: .ascii "fsck: bad checksum in the meta block of commit "
m_meta_e:
m_rng:  .ascii "fsck: not a page of the store: "
m_rng_e:
m_twi:  .ascii "fsck: used twice: page "
m_twi_e:
m_rd:   .ascii "fsck: cannot read page "
m_rd_e:
m_sum:  .ascii "fsck: bad checksum in page "
m_sum_e:
m_num:  .ascii "fsck: another page's number in page "
m_num_e:
m_lev:  .ascii "fsck: wrong level or kind in page "
m_lev_e:
m_ord:  .ascii "fsck: keys out of order in page "
m_ord_e:
m_deep: .ascii "fsck: a tree too deep, its root is page "
m_deep_e:
m_many: .ascii "fsck: more trees than fsck can remember; not checked from tree "
m_many_e:
m_lost: .ascii "fsck: neither used nor free: pages, "
m_lost_e:
m_cnt:  .ascii "fsck: the meta block's count of free pages is not what was found: "
m_cnt_e:
m_man:  .ascii "fsck: not a boot manifest: page "
m_man_e:
m_s1:   .ascii "fsck: commit "
m_s1e:
m_s2:   .ascii " trees, "
m_s2e:
m_s3:   .ascii " tree pages, "
m_s3e:
m_s4:   .ascii " stream pages, "
m_s4e:
m_s5:   .ascii " free, "
m_s5e:
m_s6:   .ascii " kept for snapshots: "
m_s6e:
m_ok:   .ascii "no problems\n"
m_ok_e:
m_bad:  .ascii " problems\n"
m_bad_e:
m_col:  .ascii ": "
        .align 8                        ; ...

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        call  sys_init                  ; handles and arguments
        call  sv_init                   ; the boot header and the newer meta block
        bgez  a0, m_go                  ; ...
        la    a0, m_nost                ; "fsck: the disk is not a store"
        li    a1, m_nost_e - m_nost     ; ...
        call  out_str                   ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...
m_go:
        la    t0, sv_npages             ; more pages than the map has bits?
        ld    t0, 0(t0)                 ; ...
        li    t1, BM_BYTES * 8          ; ...
        bleu  t0, t1, m_meta0           ; ...
        la    t0, nomap                 ; ...
        li    t1, 1                     ; ...
        sd    t1, 0(t0)                 ; ...
        la    a0, m_big                 ; ...
        li    a1, m_big_e - m_big       ; ...
        call  out_str                   ; ...
m_meta0:
        la    t0, sv_commit             ; the meta block again, whole: page 1 + (commit & 1)
        ld    s1, 0(t0)                 ; ...
        andi  s1, s1, 1                 ; ...
        addi  s1, s1, 1                 ; s1 = its page
        la    t0, sv_bpp                ; ...
        ld    t0, 0(t0)                 ; ...
        mul   a0, s1, t0                ; ...
        la    a1, meta                  ; ...
        call  sv_blk                    ; ...
        la    a0, meta                  ; its checksum
        li    a1, 512                   ; ...
        mv    a2, s1                    ; ...
        call  sum                       ; ...
        la    t0, meta                  ; ...
        ld    t1, 0(t0)                 ; ...
        beq   a0, t1, m_spare           ; ...
        la    a0, m_meta                ; ...
        li    a1, m_meta_e - m_meta     ; ...
        ld    a2, 16(t0)                ; ...
        call  prob                      ; ...
m_spare:
        la    t0, meta                  ; the spare extent: free pages in no tree
        ld    a0, 120(t0)               ; ...
        ld    a1, 128(t0)               ; ...
        beqz  a1, m_manif               ; ...
        la    t0, nfree                 ; ...
        ld    t1, 0(t0)                 ; ...
        add   t1, t1, a1                ; ...
        sd    t1, 0(t0)                 ; ...
        call  mark_range                ; ...
m_manif:
        la    t0, sv_manif              ; the boot manifest's page
        ld    s1, 0(t0)                 ; ...
        beqz  s1, m_trees               ; none
        mv    a0, s1                    ; ...
        call  mark                      ; ...
        bnez  a0, m_trees               ; ...
        mv    a0, s1                    ; ...
        call  sv_page                   ; ...
        beqz  a0, m_manbad              ; ...
        mv    s2, a0                    ; ...
        la    t0, sv_ps                 ; ...
        ld    a1, 0(t0)                 ; ...
        mv    a2, s1                    ; ...
        call  sum                       ; ...
        ld    t0, 0(s2)                 ; ...
        bne   a0, t0, m_manbad          ; ...
        lbu   t0, 24(s2)                ; (kind 3)
        li    t1, 3                     ; ...
        bne   t0, t1, m_manbad          ; ...
        la    t0, ntp                   ; ...
        ld    t1, 0(t0)                 ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, 0(t0)                 ; ...
        j     m_trees                   ; ...
m_manbad:
        la    a0, m_man                 ; ...
        li    a1, m_man_e - m_man       ; ...
        mv    a2, s1                    ; ...
        call  prob                      ; ...
m_trees:
        la    t0, sv_cat                ; the catalog: its trees are remembered
        ld    a0, 0(t0)                 ; ...
        ld    a1, 8(t0)                 ; ...
        li    a2, 1                     ; ...
        call  walk                      ; ...
        la    t0, sv_fre                ; the free tree
        ld    a0, 0(t0)                 ; ...
        ld    a1, 8(t0)                 ; ...
        li    a2, 2                     ; ...
        call  walk                      ; ...
        la    t0, sv_pend               ; the pending tree
        ld    a0, 0(t0)                 ; ...
        ld    a1, 8(t0)                 ; ...
        li    a2, 3                     ; ...
        call  walk                      ; ...
        li    s1, 0                     ; every tree of the catalog
m_tl:
        la    t0, ntree                 ; ...
        ld    t0, 0(t0)                 ; ...
        bgeu  s1, t0, m_map             ; ...
        slli  t0, s1, 3                 ; (24 bytes an entry)
        slli  t1, s1, 4                 ; ...
        add   t0, t0, t1                ; ...
        la    t1, trees                 ; ...
        add   t0, t0, t1                ; ...
        ld    a0, 0(t0)                 ; ...
        ld    a1, 8(t0)                 ; ...
        ld    a2, 16(t0)                ; ...
        call  walk                      ; ...
        addi  s1, s1, 1                 ; ...
        j     m_tl                      ; ...
m_map:
        la    t0, nomap                 ; every page of the store has one use?
        ld    t0, 0(t0)                 ; ...
        bnez  t0, m_count               ; (not mapped)
        la    t0, sv_first_             ; s1 = the page, s2 = the end
        ld    s1, 0(t0)                 ; ...
        la    t0, sv_npages             ; ...
        ld    s2, 0(t0)                 ; ...
        li    s3, 0                     ; s3 = pages with no use, s4 = the first
        la    s5, bm                    ; ...
m_ml:
        bgeu  s1, s2, m_md              ; ...
        srli  t0, s1, 3                 ; ...
        add   t0, t0, s5                ; ...
        lbu   t0, 0(t0)                 ; ...
        andi  t1, s1, 7                 ; ...
        srl   t0, t0, t1                ; ...
        andi  t0, t0, 1                 ; ...
        bnez  t0, m_mn                  ; ...
        bnez  s3, m_mc                  ; ...
        mv    s4, s1                    ; ...
m_mc:
        addi  s3, s3, 1                 ; ...
m_mn:
        addi  s1, s1, 1                 ; ...
        j     m_ml                      ; ...
m_md:
        beqz  s3, m_count               ; ...
        la    t0, nprob                 ; "... pages, N: the first is P" as one problem
        ld    t1, 0(t0)                 ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, 0(t0)                 ; ...
        la    a0, m_lost                ; ...
        li    a1, m_lost_e - m_lost     ; ...
        call  out_str                   ; ...
        mv    a0, s3                    ; ...
        call  out_dec                   ; ...
        la    a0, m_col                 ; ...
        li    a1, 2                     ; ...
        call  out_str                   ; ...
        mv    a0, s4                    ; ...
        call  out_dec                   ; ...
        call  out_nl                    ; ...
m_count:
        la    t0, nomap                 ; the meta block's count of free pages
        ld    t0, 0(t0)                 ; ...
        bnez  t0, m_sumry               ; ...
        la    t0, nfree                 ; ...
        ld    a2, 0(t0)                 ; ...
        la    t0, sv_nfree              ; ...
        ld    t0, 0(t0)                 ; ...
        beq   a2, t0, m_sumry           ; ...
        la    a0, m_cnt                 ; ...
        li    a1, m_cnt_e - m_cnt       ; ...
        call  prob                      ; ...
m_sumry:
        la    a0, m_s1                  ; "fsck: commit C: T trees, ..."
        li    a1, m_s1e - m_s1          ; ...
        call  out_str                   ; ...
        la    t0, sv_commit             ; ...
        ld    a0, 0(t0)                 ; ...
        call  out_dec                   ; ...
        la    a0, m_col                 ; ...
        li    a1, 2                     ; ...
        call  out_str                   ; ...
        la    t0, ntree                 ; (and the three of the meta block)
        ld    a0, 0(t0)                 ; ...
        addi  a0, a0, 3                 ; ...
        call  out_dec                   ; ...
        la    a0, m_s2                  ; ...
        li    a1, m_s2e - m_s2          ; ...
        call  out_str                   ; ...
        la    t0, ntp                   ; ...
        ld    a0, 0(t0)                 ; ...
        call  out_dec                   ; ...
        la    a0, m_s3                  ; ...
        li    a1, m_s3e - m_s3          ; ...
        call  out_str                   ; ...
        la    t0, nsp                   ; ...
        ld    a0, 0(t0)                 ; ...
        call  out_dec                   ; ...
        la    a0, m_s4                  ; ...
        li    a1, m_s4e - m_s4          ; ...
        call  out_str                   ; ...
        la    t0, nfree                 ; ...
        ld    a0, 0(t0)                 ; ...
        call  out_dec                   ; ...
        la    a0, m_s5                  ; ...
        li    a1, m_s5e - m_s5          ; ...
        call  out_str                   ; ...
        la    t0, ndead                 ; ...
        ld    a0, 0(t0)                 ; ...
        call  out_dec                   ; ...
        la    a0, m_s6                  ; ...
        li    a1, m_s6e - m_s6          ; ...
        call  out_str                   ; ...
        la    t0, nprob                 ; ...
        ld    s1, 0(t0)                 ; ...
        bnez  s1, m_probs               ; ...
        la    a0, m_ok                  ; "no problems"
        li    a1, m_ok_e - m_ok         ; ...
        call  out_str                   ; ...
        li    a0, 0                     ; ...
        call  sys_exit                  ; ...
m_probs:
        mv    a0, s1                    ; "N problems"
        call  out_dec                   ; ...
        la    a0, m_bad                 ; ...
        li    a1, m_bad_e - m_bad       ; ...
        call  out_str                   ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...

; prob(a0 = text, a1 = its length, a2 = a number): a problem: counted, and
; (the first NSHOW) printed: the text, the number
prob:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a2, 8(sp)                 ; ...
        la    t0, nprob                 ; ...
        ld    t1, 0(t0)                 ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, 0(t0)                 ; ...
        li    t2, NSHOW                 ; ...
        bgtu  t1, t2, pr_ret            ; ...
        call  out_str                   ; ...
        ld    a0, 8(sp)                 ; ...
        call  out_dec                   ; ...
        call  out_nl                    ; ...
pr_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; sum(a0 = address, a1 = bytes, a2 = seed) -> a0 = the checksum of a page or
; a meta block: over its 8-byte words but the first
sum:
        li    t0, 0x9E3779B97F4A7C15    ; ...
        mul   t1, a2, t0                ; ...
        li    t0, 0xCBF29CE484222325    ; ...
        add   t1, t1, t0                ; ...
        li    t0, 0x100000001B3         ; ...
        addi  t2, a0, 8                 ; ...
        add   t3, a0, a1                ; ...
sum_l:
        bgeu  t2, t3, sum_d             ; ...
        ld    t4, 0(t2)                 ; ...
        xor   t1, t1, t4                ; ...
        mul   t1, t1, t0                ; ...
        addi  t2, t2, 8                 ; ...
        j     sum_l                     ; ...
sum_d:
        srli  t4, t1, 32                ; ...
        xor   a0, t1, t4                ; ...
        ret                             ; ...

; be64(a0 = address) -> a0 = the big-endian u64 there
be64:
        li    t0, 0                     ; ...
        li    t1, 8                     ; ...
be_l:
        lbu   t2, 0(a0)                 ; ...
        slli  t0, t0, 8                 ; ...
        or    t0, t0, t2                ; ...
        addi  a0, a0, 1                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, be_l                  ; ...
        mv    a0, t0                    ; ...
        ret                             ; ...

; mark(a0 = page) -> a0 = 0: it has this one use; 1: it is no page of the
; store, or has a use already (a problem, reported)
mark:
        la    t0, sv_first_             ; a page of the store?
        ld    t0, 0(t0)                 ; ...
        bltu  a0, t0, mk_rng            ; ...
        la    t0, sv_npages             ; ...
        ld    t0, 0(t0)                 ; ...
        bgeu  a0, t0, mk_rng            ; ...
        la    t0, nomap                 ; ...
        ld    t0, 0(t0)                 ; ...
        bnez  t0, mk_ok                 ; (not mapped)
        srli  t0, a0, 3                 ; ...
        la    t1, bm                    ; ...
        add   t0, t0, t1                ; ...
        lbu   t1, 0(t0)                 ; ...
        andi  t2, a0, 7                 ; ...
        li    t3, 1                     ; ...
        sll   t3, t3, t2                ; ...
        and   t4, t1, t3                ; ...
        bnez  t4, mk_twi                ; ...
        or    t1, t1, t3                ; ...
        sb    t1, 0(t0)                 ; ...
mk_ok:
        li    a0, 0                     ; ...
        ret                             ; ...
mk_rng:
        mv    a2, a0                    ; ...
        la    a0, m_rng                 ; ...
        li    a1, m_rng_e - m_rng       ; ...
        j     mk_p                      ; ...
mk_twi:
        mv    a2, a0                    ; ...
        la    a0, m_twi                 ; ...
        li    a1, m_twi_e - m_twi       ; ...
mk_p:
        addi  sp, sp, -8                ; ...
        sd    ra, 0(sp)                 ; ...
        call  prob                      ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        li    a0, 1                     ; ...
        ret                             ; ...

; mark_range(a0 = first page, a1 = pages): each has this one use (the first
; that has not ends it: one problem an extent)
mark_range:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        mv    s1, a0                    ; ...
        add   s2, a0, a1                ; s2 = the end
        la    t0, sv_npages             ; (an extent past the disk: its end is the problem)
        ld    t0, 0(t0)                 ; ...
        bleu  s2, t0, mr_l              ; ...
        bgeu  s2, s1, mr_e              ; ...
        mv    s2, s1                    ; ...
mr_e:
        mv    a0, s2                    ; ...
        call  mark                      ; ...
        j     mr_ret                    ; ...
mr_l:
        bgeu  s1, s2, mr_ret            ; ...
        mv    a0, s1                    ; ...
        call  mark                      ; ...
        bnez  a0, mr_ret                ; ...
        addi  s1, s1, 1                 ; ...
        j     mr_l                      ; ...
mr_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; kcmp(a0 = key, a1 = its length, a2 = key, a3 = its length) -> a0 < 0, 0, > 0
kcmp:
        mv    t0, a1                    ; t0 = the shorter length
        bleu  a1, a3, kc_l              ; ...
        mv    t0, a3                    ; ...
kc_l:
        beqz  t0, kc_len                ; ...
        lbu   t1, 0(a0)                 ; ...
        lbu   t2, 0(a2)                 ; ...
        bne   t1, t2, kc_d              ; ...
        addi  a0, a0, 1                 ; ...
        addi  a2, a2, 1                 ; ...
        addi  t0, t0, -1                ; ...
        j     kc_l                      ; ...
kc_d:
        sub   a0, t1, t2                ; ...
        ret                             ; ...
kc_len:
        sub   a0, a1, a3                ; ...
        ret                             ; ...

; chk(a0 = page, a1 = the level it must have) -> a0 = the page in sv_buf, a
; good tree page with this one use; or 0 (a problem, reported)
chk:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        sd    s5, 40(sp)                ; ...
        mv    s1, a0                    ; s1 = the page, s2 = the level
        mv    s2, a1                    ; ...
        call  mark                      ; ...
        bnez  a0, ck_no                 ; ...
        mv    a0, s1                    ; ...
        call  sv_page                   ; ...
        mv    s3, a0                    ; s3 = the page's bytes
        la    a0, m_rd                  ; ...
        li    a1, m_rd_e - m_rd         ; ...
        beqz  s3, ck_p                  ; ...
        mv    a0, s3                    ; its checksum
        la    t0, sv_ps                 ; ...
        ld    a1, 0(t0)                 ; ...
        mv    a2, s1                    ; ...
        call  sum                       ; ...
        mv    t1, a0                    ; ...
        ld    t0, 0(s3)                 ; ...
        la    a0, m_sum                 ; ...
        li    a1, m_sum_e - m_sum       ; ...
        bne   t0, t1, ck_p              ; ...
        ld    t0, 8(s3)                 ; its own number
        la    a0, m_num                 ; ...
        li    a1, m_num_e - m_num       ; ...
        bne   t0, s1, ck_p              ; ...
        lbu   t0, 25(s3)                ; its level, and the kind that goes with it
        la    a0, m_lev                 ; ...
        li    a1, m_lev_e - m_lev       ; ...
        bne   t0, s2, ck_p              ; ...
        lbu   t0, 24(s3)                ; ...
        li    t1, 2                     ; (2 a leaf, 1 a branch)
        beqz  s2, ck_k                  ; ...
        li    t1, 1                     ; ...
ck_k:
        bne   t0, t1, ck_p              ; ...
        beqz  s2, ck_o                  ; a branch has a child
        lhu   t0, 26(s3)                ; ...
        beqz  t0, ck_p                  ; ...
ck_o:
        la    t0, ntp                   ; one more tree page
        ld    t1, 0(t0)                 ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, 0(t0)                 ; ...
        li    s4, 1                     ; its keys in order: s4 = the cell (a branch's
        beqz  s2, ck_ol                 ; cell 0 has no key that counts)
        li    s4, 2                     ; ...
ck_ol:
        lhu   t0, 26(s3)                ; ...
        bgeu  s4, t0, ck_yes            ; ...
        mv    a0, s3                    ; ...
        mv    a1, s4                    ; ...
        call  sv_cell                   ; ...
        mv    s5, a0                    ; s5 = this cell
        mv    a0, s3                    ; ...
        addi  a1, s4, -1                ; ...
        call  sv_cell                   ; a0 = the one before
        li    t0, 8                     ; where a key is in its cell
        beqz  s2, ck_oc                 ; ...
        li    t0, 16                    ; ...
ck_oc:
        lhu   a1, 0(a0)                 ; ...
        add   a0, a0, t0                ; ...
        lhu   a3, 0(s5)                 ; ...
        add   a2, s5, t0                ; ...
        call  kcmp                      ; ...
        addi  s4, s4, 1                 ; ...
        bltz  a0, ck_ol                 ; ...
        la    a0, m_ord                 ; ...
        li    a1, m_ord_e - m_ord       ; ...
        mv    a2, s1                    ; ...
        call  prob                      ; (the page is walked all the same)
ck_yes:
        mv    a0, s3                    ; ...
        j     ck_ret                    ; ...
ck_p:
        mv    a2, s1                    ; ...
        call  prob                      ; ...
ck_no:
        li    a0, 0                     ; ...
ck_ret:
        ld    s5, 40(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; ...

; walk(a0 = root, a1 = height, a2 = what its records are): every page of the
; tree checked, every record of its leaves looked at (leaf)
walk:
        addi  sp, sp, -56               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        sd    s5, 40(sp)                ; ...
        sd    s6, 48(sp)                ; ...
        beqz  a1, wk_ret                ; an empty tree
        li    t0, 16                    ; ...
        bleu  a1, t0, wk_go             ; ...
        mv    a2, a0                    ; ...
        la    a0, m_deep                ; ...
        li    a1, m_deep_e - m_deep     ; ...
        call  prob                      ; ...
        j     wk_ret                    ; ...
wk_go:
        la    t0, w_h                   ; ...
        sd    a1, 0(t0)                 ; ...
        la    t0, w_mode                ; ...
        sd    a2, 0(t0)                 ; ...
        li    s1, 0                     ; s1 = the level of the walk (0: the root)
        la    t0, w_stk                 ; ...
        sd    a0, 0(t0)                 ; ...
        sd    zero, 8(t0)               ; ...
        addi  a1, a1, -1                ; ...
        call  chk                       ; ...
        beqz  a0, wk_ret                ; ...
wk_l:
        slli  s2, s1, 4                 ; s2 = this level's entry
        la    t0, w_stk                 ; ...
        add   s2, s2, t0                ; ...
        ld    a0, 0(s2)                 ; ...
        call  sv_page                   ; ...
        beqz  a0, wk_pop                ; ...
        mv    s3, a0                    ; s3 = the page
        lbu   t0, 25(s3)                ; a leaf?
        bnez  t0, wk_br                 ; ...
        mv    a0, s3                    ; ...
        call  leaf                      ; ...
        j     wk_pop                    ; ...
wk_br:
        ld    s4, 8(s2)                 ; the next child
        lhu   t0, 26(s3)                ; ...
        bgeu  s4, t0, wk_pop            ; ...
        addi  t1, s4, 1                 ; ...
        sd    t1, 8(s2)                 ; ...
        lbu   s6, 25(s3)                ; s6 = the level its children have
        addi  s6, s6, -1                ; ...
        mv    a0, s3                    ; ...
        mv    a1, s4                    ; ...
        call  sv_cell                   ; ...
        ld    s5, 8(a0)                 ; s5 = the child
        addi  s1, s1, 1                 ; down
        sd    s5, 16(s2)                ; ...
        sd    zero, 24(s2)              ; ...
        mv    a0, s5                    ; ...
        mv    a1, s6                    ; ...
        call  chk                       ; ...
        bnez  a0, wk_l                  ; ...
wk_pop:
        beqz  s1, wk_ret                ; ...
        addi  s1, s1, -1                ; ...
        j     wk_l                      ; ...
wk_ret:
        ld    s6, 48(sp)                ; ...
        ld    s5, 40(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 56                ; ...
        ret                             ; ...

; leaf(a0 = a leaf): its records, by the walk's mode: the catalog's are
; trees to remember; free, pending and stream extents are pages in use
leaf:
        addi  sp, sp, -56               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        sd    s5, 40(sp)                ; ...
        sd    s6, 48(sp)                ; ...
        mv    s1, a0                    ; s1 = the page
        la    t0, w_mode                ; s2 = the mode
        ld    s2, 0(t0)                 ; ...
        beqz  s2, lf_ret                ; nothing to do
        li    s3, 0                     ; s3 = the cell's index
lf_l:
        lhu   t0, 26(s1)                ; ...
        bgeu  s3, t0, lf_ret            ; ...
        mv    a0, s1                    ; ...
        mv    a1, s3                    ; ...
        call  sv_cell                   ; ...
        addi  s3, s3, 1                 ; ...
        addi  s4, a0, 8                 ; s4 = the key, s5 = the value
        lhu   s6, 0(a0)                 ; s6 = the key's length
        addi  t0, s6, 7                 ; ...
        srli  t0, t0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        add   s5, s4, t0                ; ...
        li    t0, 1                     ; ...
        beq   s2, t0, lf_cat            ; ...
        li    t0, 2                     ; ...
        beq   s2, t0, lf_free           ; ...
        li    t0, 3                     ; ...
        beq   s2, t0, lf_pend           ; ...
        ld    a0, 0(s5)                 ; a stream's extent: first page, pages
        ld    a1, 8(s5)                 ; ...
        la    t0, nsp                   ; ...
        j     lf_ext                    ; ...
lf_free:
        mv    a0, s4                    ; a free extent: its end -> pages
        call  be64                      ; ...
        ld    a1, 0(s5)                 ; ...
        sub   a0, a0, a1                ; ...
        la    t0, nfree                 ; ...
        j     lf_ext                    ; ...
lf_pend:
        addi  a0, s4, 8                 ; a pending extent: commit, start -> pages (and
        call  be64                      ; whose they were, above them)
        mv    s6, a0                    ; ...
        mv    a0, s4                    ; ...
        call  be64                      ; ...
        mv    t1, a0                    ; ...
        mv    a0, s6                    ; ...
        lwu   a1, 0(s5)                 ; ...
        la    t0, nfree                 ; free, unless it is a snapshot's dead list
        bgez  t1, lf_ext                ; ...
        la    t0, ndead                 ; ...
lf_ext:
        ld    t1, 0(t0)                 ; counted, and each page has this use
        add   t1, t1, a1                ; ...
        sd    t1, 0(t0)                 ; ...
        call  mark_range                ; ...
        j     lf_l                      ; ...
lf_cat:
        la    t0, ntree                 ; a tree: remembered, with its mode (".ext": a
        ld    t1, 0(t0)                 ; namespace's extents)
        li    t2, NTREE                 ; ...
        bltu  t1, t2, lf_add            ; ...
        bne   t1, t2, lf_l              ; (said once)
        la    a0, m_many                ; ...
        li    a1, m_many_e - m_many     ; ...
        mv    a2, t1                    ; ...
        call  prob                      ; ...
        la    t0, ntree                 ; ...
        li    t1, NTREE + 1             ; ...
        sd    t1, 0(t0)                 ; ...
        j     lf_l                      ; ...
lf_add:
        addi  t2, t1, 1                 ; ...
        sd    t2, 0(t0)                 ; ...
        slli  t2, t1, 3                 ; ...
        slli  t3, t1, 4                 ; ...
        add   t2, t2, t3                ; ...
        la    t3, trees                 ; ...
        add   t2, t2, t3                ; ...
        ld    t3, 0(s5)                 ; ...
        sd    t3, 0(t2)                 ; ...
        ld    t3, 8(s5)                 ; ...
        sd    t3, 8(t2)                 ; ...
        li    t3, 0                     ; ...
        li    t4, 8                     ; (namespace id, ".ext")
        bne   s6, t4, lf_m              ; ...
        lwu   t4, 4(s4)                 ; ...
        li    t5, 0x7478652E            ; ...
        bne   t4, t5, lf_m              ; ...
        li    t3, 4                     ; ...
lf_m:
        sd    t3, 16(t2)                ; ...
        j     lf_l                      ; ...
lf_ret:
        ld    s6, 48(sp)                ; ...
        ld    s5, 40(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 56                ; ...
        ret                             ; ...

