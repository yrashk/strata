; w_str(a0 = address, a1 = length): append to the response (sent when full)
w_str:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        mv    s1, a0                    ; s1 = cursor
        add   s2, a0, a1                ; s2 = end
ws_l:
        sub   t5, s2, s1                ; bytes left
        beqz  t5, ws_ret                ; ...
        la    t0, olen                  ; room in the buffer?
        ld    t1, 0(t0)                 ; ...
        li    t2, OBUFSZ                ; ...
        sub   t2, t2, t1                ; ...
        bnez  t2, ws_cp                 ; ...
        call  w_flush                   ; no: send it
        j     ws_l                      ; ...
ws_cp:
        bleu  t5, t2, ws_n              ; as much as fits
        mv    t5, t2                    ; ...
ws_n:
        add   t2, t1, t5                ; ...
        sd    t2, 0(t0)                 ; ...
        la    t4, obuf                  ; ...
        add   t4, t4, t1                ; ...
ws_b:
        lbu   t3, 0(s1)                 ; ...
        sb    t3, 0(t4)                 ; ...
        addi  s1, s1, 1                 ; ...
        addi  t4, t4, 1                 ; ...
        addi  t5, t5, -1                ; ...
        bnez  t5, ws_b                  ; ...
        j     ws_l                      ; ...
ws_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; w_chr(a0 = a byte)
w_chr:
        la    t0, numb                  ; one byte of scratch
        sb    a0, 0(t0)                 ; ...
        mv    a0, t0                    ; ...
        li    a1, 1                     ; ...
        j     w_str                     ; (tail call)

; w_crlf(): CR LF
w_crlf:
        la    a0, s_crlf                ; ...
        li    a1, 2                     ; ...
        j     w_str                     ; (tail call)

; w_dec(a0 = value): unsigned decimal
w_dec:
        la    t0, numend                ; digits from the right
        mv    t1, t0                    ; ...
        li    t2, 10                    ; ...
wd_l:
        remu  t3, a0, t2                ; ...
        divu  a0, a0, t2                ; ...
        addi  t3, t3, '0'               ; ...
        addi  t1, t1, -1                ; ...
        sb    t3, 0(t1)                 ; ...
        bnez  a0, wd_l                  ; ...
        mv    a0, t1                    ; ...
        sub   a1, t0, t1                ; ...
        j     w_str                     ; (tail call)

; w_esc(a0 = text, a1 = length): HTML-escaped (& < > ")
w_esc:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        mv    s1, a0                    ; s1 = cursor
        add   s2, a0, a1                ; s2 = end
we_l:
        beq   s1, s2, we_ret            ; ...
        lbu   a0, 0(s1)                 ; ...
        addi  s1, s1, 1                 ; ...
        li    t0, '&'                   ; ...
        beq   a0, t0, we_amp            ; ...
        li    t0, '<'                   ; ...
        beq   a0, t0, we_lt             ; ...
        li    t0, '>'                   ; ...
        beq   a0, t0, we_gt             ; ...
        li    t0, '"'                   ; ...
        beq   a0, t0, we_q              ; ...
        call  w_chr                     ; ...
        j     we_l                      ; ...
we_amp:
        la    a0, e_amp                 ; ...
        li    a1, 5                     ; ...
        j     we_put                    ; ...
we_lt:
        la    a0, e_lt                  ; ...
        li    a1, 4                     ; ...
        j     we_put                    ; ...
we_gt:
        la    a0, e_gt                  ; ...
        li    a1, 4                     ; ...
        j     we_put                    ; ...
we_q:
        la    a0, e_quot                ; ...
        li    a1, 6                     ; ...
we_put:
        call  w_str                     ; ...
        j     we_l                      ; ...
we_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; w_url(a0 = text, a1 = length): as a URL path (%XX for bytes other than
; letters, digits and u_safe)
w_url:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        mv    s1, a0                    ; s1 = cursor
        add   s2, a0, a1                ; s2 = end
wu_l:
        beq   s1, s2, wu_ret            ; ...
        lbu   a0, 0(s1)                 ; ...
        addi  s1, s1, 1                 ; ...
        addi  t0, a0, -97               ; a..z
        li    t1, 26                    ; ...
        bltu  t0, t1, wu_ok             ; ...
        addi  t0, a0, -65               ; A..Z
        bltu  t0, t1, wu_ok             ; ...
        addi  t0, a0, -48               ; 0..9
        li    t1, 10                    ; ...
        bltu  t0, t1, wu_ok             ; ...
        la    t2, u_safe                ; safe punctuation
        li    t3, u_safe_e - u_safe     ; ...
wu_s:
        beqz  t3, wu_enc                ; ...
        lbu   t4, 0(t2)                 ; ...
        beq   t4, a0, wu_ok             ; ...
        addi  t2, t2, 1                 ; ...
        addi  t3, t3, -1                ; ...
        j     wu_s                      ; ...
wu_ok:
        call  w_chr                     ; ...
        j     wu_l                      ; ...
wu_enc:
        mv    s3, a0                    ; %XX
        li    a0, '%'                   ; ...
        call  w_chr                     ; ...
        la    t0, hexd                  ; ...
        srli  t1, s3, 4                 ; ...
        add   t0, t0, t1                ; ...
        lbu   a0, 0(t0)                 ; ...
        call  w_chr                     ; ...
        la    t0, hexd                  ; ...
        andi  t1, s3, 15                ; ...
        add   t0, t0, t1                ; ...
        lbu   a0, 0(t0)                 ; ...
        call  w_chr                     ; ...
        j     wu_l                      ; ...
wu_ret:
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; w_flush(): send what the buffer holds
w_flush:
        la    t0, olen                  ; ...
        ld    a1, 0(t0)                 ; ...
        beqz  a1, wf_ret                ; ...
        sd    zero, 0(t0)               ; ...
        la    a0, obuf                  ; ...
        j     w_send                    ; (tail call)
wf_ret:
        ret                             ; ...

; w_send(a0 = address, a1 = length): straight to the client, counted; after
; a failure (the client went away) nothing more is sent
w_send:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        la    t0, ofail                 ; ...
        ld    t0, 0(t0)                 ; ...
        bnez  t0, wse_ret               ; ...
        mv    a2, a1                    ; ...
        mv    a1, a0                    ; ...
        la    t0, osock                 ; ...
        ld    a0, 0(t0)                 ; ...
        call  sys_write                 ; a0 = bytes taken
        bgtz  a0, wse_ok                ; ...
        la    t0, ofail                 ; ...
        li    t1, 1                     ; ...
        sd    t1, 0(t0)                 ; ...
        j     wse_ret                   ; ...
wse_ok:
        la    t0, ototal                ; ...
        ld    t1, 0(t0)                 ; ...
        add   t1, t1, a0                ; ...
        sd    t1, 0(t0)                 ; ...
wse_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

