; =============================================================================
; httpd.s: a small HTTP server over the network server and the tag file system
; =============================================================================
;
;   httpd [-p PORT] [-c CONNS]
;
; Listens on PORT (80 by default) and answers HTTP/1.0 and HTTP/1.1 GET and
; HEAD requests, one response per connection (Connection: close). Up to
; CONNS connections (1..3, default 3: net has 4 sockets and the listener is
; one) are read at once, so a client that connects and says nothing does
; not hold up the others; a connection that sends no complete request in
; 10 s is closed. Each request is logged on standard output as
; "METHOD TARGET STATUS BYTES" (BYTES: the body sent).
;
; URLs are tag paths (doc/strataos.md 2.4):
;   /                   the file named index.html (any tags), or else the
;                       listing of every file
;   /TAG/TAG/NAME       the file NAME, if it carries those tags
;   /TAG/TAG/           a generated listing of the files carrying every tag
;                       of the path ("-TAG" excludes, as in ls), with each
;                       file's tags as links and the facets (the other tags
;                       the listed files carry: fs DIR's facet set) as links
;                       that narrow the listing
;   /TAG                (a tag, not a file) 301 to /TAG/
;   /~/                 the listing of every file
;   /~ps                what the machine is doing: proc's INFO, CORES and PS
; The query string (?...) is ignored; %XX escapes are decoded.
;
; Files go out in chunks of 4032 bytes (sys_read, sys_write) with a
; Content-Length and a Content-Type from the extension (html, txt, css, js,
; png, s, fs, ...; a file with no extension is text/plain if its first chunk
; looks like text, else application/octet-stream). Generated pages have no
; Content-Length: the end of the body is the end of the connection.
; Errors: 400 (a malformed request line), 404, 405 (methods other than GET
; and HEAD). The request's headers are read up to the blank line (or the
; client's half-close) and otherwise ignored; only the request line and the
; last bytes are kept once 1 KiB has arrived.
;
; No connection is waiting: httpd blocks in ACCEPT. Connections are open: it
; polls them (non-blocking READ and ACCEPT) and sleeps 5 ms when nothing
; happened. While a response is written, the other connections wait.
; Exit status 1 if there is no network server or the port is taken.
;
; D-LS: 31,280 bytes of data with the library, measured (0x7a30 of the 40 KiB
; data extent): the response buffer 4 KiB, dirbuf 4 KiB (DIR records, file
; chunks, PS records), two tag tables 4 KiB, requests 3 KiB, the library
; 13 KiB. Code: 12.3 KiB of the 32 KiB I-LS.

