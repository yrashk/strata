        call  w_html                    ; ...
        la    a0, h_nost                ; (always fresh)
        li    a1, h_nost_e - h_nost     ; ...
        call  w_str                     ; ...
        call  w_endh                    ; ...
        bnez  a0, st_ret                ; (HEAD)
        la    a0, q_tit                 ; ...
        li    a1, q_tite - q_tit        ; ...
        li    a2, 0                     ; ...
        call  page_top                  ; ...
        la    a0, q_h1                  ; "Up S.T s; "
        li    a1, q_h1e - q_h1          ; ...
        call  w_str                     ; ...
        call  sys_now                   ; ...
        li    t0, 100000                ; tenths of a second
        divu  s2, a0, t0                ; ...
        li    t0, 10                    ; ...
        divu  a0, s2, t0                ; ...
        call  w_dec                     ; ...
        li    a0, '.'                   ; ...
        call  w_chr                     ; ...
        li    t0, 10                    ; ...
        remu  a0, s2, t0                ; ...
        call  w_dec                     ; ...
        la    a0, q_1                   ; ...
        li    a1, q_1e - q_1            ; ...
        call  w_str                     ; ...
        ld    a0, 0(s1)                 ; cores
        call  w_dec                     ; ...
        la    a0, q_2                   ; ...
        li    a1, q_2e - q_2            ; ...
        call  w_str                     ; ...
        ld    a0, 24(s1)                ; processes
        call  w_dec                     ; ...
        la    a0, q_3                   ; ...
        li    a1, q_3e - q_3            ; ...
        call  w_str                     ; ...
        ld    a0, 32(s1)                ; kernel units
        call  w_dec                     ; ...
        la    a0, q_4                   ; ...
        li    a1, q_4e - q_4            ; ...
        call  w_str                     ; ...
        ld    a0, 40(s1)                ; switches
        call  w_dec                     ; ...
        la    a0, q_5                   ; ...
        li    a1, q_5e - q_5            ; ...
        call  w_str                     ; ...
        ld    a0, 48(s1)                ; KiB moved
        call  w_dec                     ; ...
        la    a0, q_6                   ; ...
        li    a1, q_6e - q_6            ; ...
        call  w_str                     ; ...
        ld    a0, 8(s1)                 ; free heap
        srli  a0, a0, 10                ; ...
        call  w_dec                     ; ...
        la    a0, q_7                   ; ...
        li    a1, q_7e - q_7            ; ...
        call  w_str                     ; ...
        ld    a0, 16(s1)                ; total memory
        srli  a0, a0, 10                ; ...
        call  w_dec                     ; ...
        la    a0, q_8                   ; the cores' table
        li    a1, q_8e - q_8            ; ...
        call  w_str                     ; ...
        la    a0, tagbuf                ; ...
        call  sys_cores                 ; ...
        mv    s2, a0                    ; s2 = records left, s3 = record
        la    s3, tagbuf                ; ...
        li    t0, 16                    ; (at most 16)
        bleu  s2, t0, st_c              ; ...
        mv    s2, t0                    ; ...
st_c:
        blez  s2, st_ce                 ; ...
        la    a0, l_tr                  ; <tr><td>core</td>
        li    a1, l_tre - l_tr          ; ...
        call  w_str                     ; ...
        lbu   a0, 0(s3)                 ; ...
        call  w_dec                     ; ...
        la    a0, l_tde                 ; ...
        li    a1, l_tdee - l_tde        ; ...
        call  w_str                     ; ...
        lbu   t0, 0(s3)                 ; core 0: the system
        bnez  t0, st_c1                 ; ...
        la    a0, q_sys                 ; ...
        li    a1, q_syse - q_sys        ; ...
        call  w_str                     ; ...
        j     st_c2                     ; ...
st_c1:
        lbu   a0, 1(s3)                 ; the pid running
        beqz  a0, st_cidle              ; ...
        call  w_tdn                     ; ...
        j     st_c2                     ; ...
st_cidle:
        la    a0, q_idle                ; ...
        li    a1, q_idlee - q_idle      ; ...
        call  w_str                     ; ...
st_c2:
        lbu   a0, 2(s3)                 ; runnable
        call  w_tdn                     ; ...
        lbu   a0, 3(s3)                 ; processes
        call  w_tdn                     ; ...
        lwu   a0, 8(s3)                 ; switches
        call  w_tdn                     ; ...
        lwu   a0, 12(s3)                ; KiB moved
        call  w_tdn                     ; ...
        la    a0, l_trn + 5             ; </tr>
        li    a1, l_trne - l_trn - 5    ; ...
        call  w_str                     ; ...
        addi  s3, s3, 32                ; ...
        addi  s2, s2, -1                ; ...
        j     st_c                      ; ...
st_ce:
        la    a0, q_9                   ; the processes' table
        li    a1, q_9e - q_9            ; ...
        call  w_str                     ; ...
        la    a0, dirbuf                ; ...
        call  sys_ps                    ; ...
        mv    s2, a0                    ; s2 = records left, s3 = record
        la    s3, dirbuf                ; ...
        li    t0, 126                   ; (one reply's worth)
        bleu  s2, t0, st_p              ; ...
        mv    s2, t0                    ; ...
st_p:
        blez  s2, st_pe                 ; ...
        la    a0, l_tr                  ; <tr><td>pid</td>
        li    a1, l_tre - l_tr          ; ...
        call  w_str                     ; ...
        lbu   a0, 0(s3)                 ; ...
        call  w_dec                     ; ...
        la    a0, l_tde                 ; ...
        li    a1, l_tdee - l_tde        ; ...
        call  w_str                     ; ...
        lbu   a0, 3(s3)                 ; parent
        call  w_tdn                     ; ...
        la    a0, l_td                  ; state
        li    a1, l_tdz - l_td          ; ...
        call  w_str                     ; ...
        lbu   t0, 1(s3)                 ; (1..4; others "?")
        li    t1, 5                     ; ...
        bltu  t0, t1, st_s              ; ...
        li    t0, 0                     ; ...
st_s:
        slli  t0, t0, 3                 ; ...
        la    s4, q_st                  ; ...
        add   s4, s4, t0                ; ...
        mv    a0, s4                    ; (without the padding)
        li    a1, 8                     ; ...
        call  str_len_sp                ; ...
        mv    a1, a0                    ; ...
        mv    a0, s4                    ; ...
        call  w_str                     ; ...
        la    a0, l_tde                 ; ...
        li    a1, l_tdee - l_tde        ; ...
        call  w_str                     ; ...
        lbu   a0, 2(s3)                 ; core
        call  w_tdn                     ; ...
        lbu   a0, 5(s3)                 ; threads
        call  w_tdn                     ; ...
        lwu   a0, 8(s3)                 ; switches
        call  w_tdn                     ; ...
        lwu   a0, 12(s3)                ; KiB moved
        call  w_tdn                     ; ...
        la    a0, l_td                  ; name
        li    a1, l_tdz - l_td          ; ...
        call  w_str                     ; ...
        addi  a0, s3, 16                ; ...
        li    a1, 16                    ; ...
        call  str_len                   ; ...
        mv    a1, a0                    ; ...
        addi  a0, s3, 16                ; ...
        call  w_esc                     ; ...
        la    a0, l_trn                 ; ...
        li    a1, l_trne - l_trn        ; ...
        call  w_str                     ; ...
        addi  s3, s3, 32                ; ...
        addi  s2, s2, -1                ; ...
        j     st_p                      ; ...
st_pe:
        la    a0, q_10                  ; ...
        li    a1, q_10e - q_10          ; ...
        call  w_str                     ; ...
        call  w_foot                    ; ...
st_ret:
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 40                ; ...
        ret                             ; ...

; str_len_sp(a0 = text, a1 = maximum) -> a0 = its length before the first space
str_len_sp:
        li    t0, 0                     ; ...
        li    t2, ' '                   ; ...
sls_l:
        beq   t0, a1, sls_d             ; ...
        add   t1, a0, t0                ; ...
        lbu   t1, 0(t1)                 ; ...
        beq   t1, t2, sls_d             ; ...
        addi  t0, t0, 1                 ; ...
        j     sls_l                     ; ...
sls_d:
        mv    a0, t0                    ; ...
        ret                             ; ...

