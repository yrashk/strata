        li    a1, s_hello_e - s_hello   ; ...
        call  out_str                   ; ...
        la    a0, port                  ; ...
        ld    a0, 0(a0)                 ; ...
        call  out_dec                   ; ...
        call  out_nl                    ; ...
        call  out_flush                 ; ...
loop:
        call  nactive                   ; connections open?
        bnez  a0, l_poll                ; yes: poll them
        la    a0, lsn                   ; no: wait for one
        ld    a0, 0(a0)                 ; ...
        li    a1, 0                     ; ...
        call  net_accept                ; ...
        bltz  a0, m_end                 ; (interrupted, or the listener is gone)
        call  slot_add                  ; ...
        j     loop                      ; ...
l_poll:
        li    s5, 0                     ; s5 = something happened
        la    t0, conns                 ; room for another?
        ld    t0, 0(t0)                 ; ...
        bgeu  a0, t0, l_read            ; no
        la    a0, lsn                   ; a new connection, if one waits
        ld    a0, 0(a0)                 ; ...
        li    a1, 1                     ; ...
        call  net_accept                ; ...
        bltz  a0, l_read                ; (-3: none)
        call  slot_add                  ; ...
        li    s5, 1                     ; ...
l_read:
        la    s3, slots                 ; s3 = slot, s4 = its index
        li    s4, 0                     ; ...
l_rl:
        li    t0, NSLOT                 ; all seen?
        beq   s4, t0, l_done            ; ...
        ld    t0, SL_H(s3)              ; open?
        bltz  t0, l_rn                  ; ...
        mv    a0, s3                    ; what it sent
        mv    a1, s4                    ; ...
        call  slot_poll                 ; a0 = 1 if something happened
        or    s5, s5, a0                ; ...
l_rn:
        addi  s3, s3, SLSZ              ; next slot
        addi  s4, s4, 1                 ; ...
        j     l_rl                      ; ...
