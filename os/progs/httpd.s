        la    t0, port                  ; ...
        sd    a0, 0(t0)                 ; ...
        j     m_arg                     ; ...
m_conns:
        call  next_num                  ; ...
        blez  a0, m_use                 ; ...
        li    t1, NSLOT                 ; at most NSLOT
        bleu  a0, t1, m_c1              ; ...
        mv    a0, t1                    ; ...
m_c1:
        la    t0, conns                 ; ...
        sd    a0, 0(t0)                 ; ...
        j     m_arg                     ; ...
m_go:
        call  net_init                  ; the network server
        bnez  a0, m_nonet               ; ...
        la    a0, port                  ; listen
        ld    a0, 0(a0)                 ; ...
        call  net_listen                ; ...
        bltz  a0, m_fail                ; ...
        la    t0, lsn                   ; ...
        sd    a0, 0(t0)                 ; ...
        la    t0, slots                 ; every slot free
        li    t1, NSLOT                 ; ...
        li    t2, -1                    ; ...
m_clr:
        sd    t2, SL_H(t0)              ; ...
        addi  t0, t0, SLSZ              ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, m_clr                 ; ...
