; nactive() -> a0 = slots in use
nactive:
        la    t0, slots                 ; ...
        li    t1, NSLOT                 ; ...
        li    a0, 0                     ; ...
na_l:
        ld    t2, SL_H(t0)              ; ...
        bltz  t2, na_n                  ; ...
        addi  a0, a0, 1                 ; ...
na_n:
        addi  t0, t0, SLSZ              ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, na_l                  ; ...
        ret                             ; ...

; slot_add(a0 = a new connection's handle): into a free slot
slot_add:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; the handle
        la    t0, slots                 ; a free slot
        li    t1, NSLOT                 ; ...
sa_l:
        ld    t2, SL_H(t0)              ; ...
        bltz  t2, sa_put                ; ...
        addi  t0, t0, SLSZ              ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, sa_l                  ; ...
        call  sys_close                 ; (none: cannot happen) let it go
        j     sa_ret                    ; ...
sa_put:
        sd    a0, SL_H(t0)              ; ...
        sd    zero, SL_LEN(t0)          ; ...
        sd    t0, 16(sp)                ; ...
        call  sys_now                   ; when
        ld    t0, 16(sp)                ; ...
        sd    a0, SL_T0(t0)             ; ...
sa_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; slot_poll(a0 = slot, a1 = its index) -> a0 = 1 if something happened: reads
; what the connection sent; a complete request is answered and the
; connection closed; so is one that ended, failed or stayed silent too long
slot_poll:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        mv    s1, a0                    ; s1 = the slot
        la    s2, rqbuf                 ; s2 = its buffer
        slli  t0, a1, 10                ; (RQMAX = 1024 bytes each)
        add   s2, s2, t0                ; ...
        ld    a0, SL_H(s1)              ; read what is there
        ld    t0, SL_LEN(s1)            ; ...
        add   a1, s2, t0                ; ...
        li    a2, RQMAX                 ; ...
        sub   a2, a2, t0                ; ...
        call  sys_readnb                ; ...
        li    t0, -3                    ; nothing yet
        beq   a0, t0, sp_idle           ; ...
        bltz  a0, sp_drop               ; failed (reset): drop it
        beqz  a0, sp_eof                ; the client has finished sending
        ld    t0, SL_LEN(s1)            ; ...
        add   t0, t0, a0                ; ...
        sd    t0, SL_LEN(s1)            ; ...
        mv    a0, s2                    ; the end of the head?
        mv    a1, t0                    ; ...
        call  rq_end                    ; ...
        bnez  a0, sp_serve              ; yes
        ld    a1, SL_LEN(s1)            ; full?
        li    t1, RQMAX                 ; ...
        bltu  a1, t1, sp_busy           ; no: wait for more
        mv    a0, s2                    ; keep the request line and the last bytes
        call  rq_trim                   ; ...
        bltz  a0, sp_serve              ; (no room for that: answer what is there)
        sd    a0, SL_LEN(s1)            ; ...
sp_busy:
        li    a0, 1                     ; ...
        j     sp_ret                    ; ...
sp_eof:
        ld    t0, SL_LEN(s1)            ; it sent nothing: just close
        beqz  t0, sp_drop               ; ...
sp_serve:
        mv    a0, s2                    ; answer it
        ld    a1, SL_LEN(s1)            ; ...
        ld    a2, SL_H(s1)              ; ...
        call  serve                     ; ...
sp_drop:
        ld    a0, SL_H(s1)              ; close it
        call  sys_close                 ; ...
        li    t0, -1                    ; the slot is free
        sd    t0, SL_H(s1)              ; ...
        li    a0, 1                     ; ...
        j     sp_ret                    ; ...
sp_idle:
        call  sys_now                   ; silent too long?
        ld    t0, SL_T0(s1)             ; ...
        sub   a0, a0, t0                ; ...
        li    t1, IDLE                  ; ...
        bgeu  a0, t1, sp_drop           ; yes: close it
        li    a0, 0                     ; ...
sp_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; rq_end(a0 = buffer, a1 = length) -> a0 = 1 if a blank line ("\n\n" or
; "\n\r\n") ends the request's head
rq_end:
        li    t0, 0                     ; t0 = index
        li    t4, 10                    ; '\n'
        li    t5, 13                    ; '\r'
re_l:
        addi  t1, t0, 1                 ; two bytes from here?
        bgeu  t1, a1, re_no             ; ...
        add   t2, a0, t0                ; ...
        lbu   t3, 0(t2)                 ; a newline ...
        bne   t3, t4, re_n              ; ...
        lbu   t3, 1(t2)                 ; ... and another
        beq   t3, t4, re_yes            ; ...
        bne   t3, t5, re_n              ; ... or CR LF
        addi  t1, t0, 2                 ; ...
        bgeu  t1, a1, re_no             ; ...
        lbu   t3, 2(t2)                 ; ...
        beq   t3, t4, re_yes            ; ...
re_n:
        addi  t0, t0, 1                 ; next
        j     re_l                      ; ...
re_yes:
        li    a0, 1                     ; ...
        ret                             ; ...
re_no:
        li    a0, 0                     ; ...
        ret                             ; ...

; rq_trim(a0 = buffer, a1 = length) -> a0 = the new length: the request line
; with its newline, a marker byte and the last 3 bytes (where the blank line
; may have begun); -1 if there is no newline or no room is won
rq_trim:
        li    t0, 0                     ; t0 = index
        li    t3, 10                    ; '\n'
rt_l:
        beq   t0, a1, rt_none           ; ...
        add   t1, a0, t0                ; ...
        lbu   t2, 0(t1)                 ; ...
        beq   t2, t3, rt_nl             ; ...
        addi  t0, t0, 1                 ; ...
        j     rt_l                      ; ...
rt_nl:
        addi  t0, t0, 1                 ; the line with its newline
        addi  t4, t0, 4                 ; and 4 more bytes: room left after?
        bgeu  t4, a1, rt_none           ; ...
        add   t1, a0, t0                ; the marker ('x': no blank line across it)
        li    t2, 'x'                   ; ...
        sb    t2, 0(t1)                 ; ...
        add   t5, a0, a1                ; the last 3 bytes after it
        lbu   t2, -3(t5)                ; ...
        sb    t2, 1(t1)                 ; ...
        lbu   t2, -2(t5)                ; ...
        sb    t2, 2(t1)                 ; ...
        lbu   t2, -1(t5)                ; ...
        sb    t2, 3(t1)                 ; ...
        mv    a0, t4                    ; ...
        ret                             ; ...
rt_none:
        li    a0, -1                    ; ...
        ret                             ; ...

; ---- a request -----------------------------------------------------------------------------

; serve(a0 = request, a1 = its length, a2 = the socket): parse the request
; line, answer, log
serve:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        mv    s1, a0                    ; s1 = the request
        mv    s2, a1                    ; s2 = its length
        la    t0, osock                 ; the response goes there
        sd    a2, 0(t0)                 ; ...
        la    t0, rqa                   ; ...
        sd    a0, 0(t0)                 ; ...
        la    t0, olen                  ; a fresh response
        sd    zero, 0(t0)               ; ...
        la    t0, ototal                ; ...
        sd    zero, 0(t0)               ; ...
        la    t0, ohdr                  ; ...
        sd    zero, 0(t0)               ; ...
        la    t0, ofail                 ; ...
        sd    zero, 0(t0)               ; ...
        la    t0, ohead                 ; ...
        sd    zero, 0(t0)               ; ...
        la    t0, rqm                   ; ...
        sd    zero, 0(t0)               ; ...
        li    t0, 0                     ; the request line ends at the first newline
        li    t2, 10                    ; ...
sv_nl:
        beq   t0, s2, sv_400            ; none
        add   t1, s1, t0                ; ...
        lbu   t1, 0(t1)                 ; ...
        beq   t1, t2, sv_hav            ; ...
        addi  t0, t0, 1                 ; ...
        j     sv_nl                     ; ...
sv_hav:
        mv    s3, t0                    ; s3 = its end
        beqz  s3, sv_400                ; (empty)
        add   t1, s1, s3                ; without a CR
        lbu   t1, -1(t1)                ; ...
        li    t2, 13                    ; ...
        bne   t1, t2, sv_m0             ; ...
        addi  s3, s3, -1                ; ...
sv_m0:
        li    t0, 0                     ; the method: up to a space
        li    t2, ' '                   ; ...
sv_m:
        beq   t0, s3, sv_400            ; (no space)
        add   t1, s1, t0                ; ...
        lbu   t1, 0(t1)                 ; ...
        beq   t1, t2, sv_mend           ; ...
        addi  t0, t0, 1                 ; ...
        j     sv_m                      ; ...
sv_mend:
        beqz  t0, sv_400                ; (empty)
        li    t1, 16                    ; (too long)
        bgtu  t0, t1, sv_400            ; ...
        la    t1, rqm                   ; ...
        sd    t0, 0(t1)                 ; ...
        addi  t0, t0, 1                 ; the target: up to a space or the end
        mv    t3, t0                    ; ...
sv_t:
        beq   t0, s3, sv_tend           ; ...
        add   t1, s1, t0                ; ...
        lbu   t1, 0(t1)                 ; ...
        beq   t1, t2, sv_tend           ; ...
        addi  t0, t0, 1                 ; ...
        j     sv_t                      ; ...
sv_tend:
        la    t1, rqts                  ; ...
        sd    t3, 0(t1)                 ; ...
        la    t1, rqte                  ; ...
        sd    t0, 0(t1)                 ; ...
        beq   t3, t0, sv_400            ; (empty)
        beq   t0, s3, sv_meth           ; no version (HTTP/0.9 style): fine
        addi  t0, t0, 1                 ; the version: HTTP/...
        add   a0, s1, t0                ; ...
        sub   a1, s3, t0                ; ...
        li    t1, 5                     ; ...
        bltu  a1, t1, sv_400            ; ...
        li    a1, 5                     ; ...
        la    a2, s_http                ; ...
        li    a3, 5                     ; ...
        call  str_eq                    ; ...
        beqz  a0, sv_400                ; ...
sv_meth:
        mv    a0, s1                    ; GET?
        la    t0, rqm                   ; ...
        ld    a1, 0(t0)                 ; ...
        la    a2, s_get                 ; ...
        li    a3, 3                     ; ...
        call  str_eq                    ; ...
        bnez  a0, sv_path               ; ...
        mv    a0, s1                    ; HEAD?
        la    t0, rqm                   ; ...
        ld    a1, 0(t0)                 ; ...
        la    a2, s_head                ; ...
        li    a3, 4                     ; ...
        call  str_eq                    ; ...
        beqz  a0, sv_other              ; ...
        la    t0, ohead                 ; no body
        li    t1, 1                     ; ...
        sd    t1, 0(t0)                 ; ...
        j     sv_path                   ; ...
sv_other:
        la    t0, rqm                   ; another method (capital letters): 405
        ld    t0, 0(t0)                 ; ...
        mv    t1, s1                    ; ...
        li    t3, 26                    ; ...
sv_o:
        beqz  t0, sv_405                ; ...
        lbu   t2, 0(t1)                 ; ...
        addi  t2, t2, -65               ; 'A'..'Z'?
        bgeu  t2, t3, sv_400            ; no: not a method
        addi  t1, t1, 1                 ; ...
        addi  t0, t0, -1                ; ...
        j     sv_o                      ; ...
sv_405:
        li    a0, 405                   ; ...
        call  reply_err                 ; ...
        j     sv_log                    ; ...
sv_path:
        la    t0, rqts                  ; decode the target
        ld    a0, 0(t0)                 ; ...
        add   a0, s1, a0                ; ...
        la    t0, rqte                  ; ...
        ld    a1, 0(t0)                 ; ...
        add   a1, s1, a1                ; ...
        call  decode                    ; ...
        bltz  a0, sv_400                ; ...
        call  route                     ; answer it
        j     sv_log                    ; ...
sv_400:
        li    a0, 400                   ; ...
        call  reply_err                 ; ...
sv_log:
        call  w_flush                   ; the rest of the response
        call  log_line                  ; (before the close: the client sees the end after it)
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 40                ; ...
        ret                             ; ...

; decode(a0 = target, a1 = its end) -> a0 = 0 and the path in pbuf/plen, or
; -1: not "/...", a bad %XX, a control character, or longer than PMAX. The
; query (?...) and a fragment (#...) are dropped
decode:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        mv    s1, a0                    ; s1 = cursor
        mv    s2, a1                    ; s2 = end
        li    s3, 0                     ; s3 = bytes out
        lbu   t1, 0(s1)                 ; an absolute path
        li    t2, '/'                   ; ...
        bne   t1, t2, dc_bad            ; ...
dc_l:
        beq   s1, s2, dc_done           ; ...
        lbu   s4, 0(s1)                 ; s4 = the next byte
        addi  s1, s1, 1                 ; ...
        li    t2, '?'                   ; the query: ignored
        beq   s4, t2, dc_done           ; ...
        li    t2, '#'                   ; ...
        beq   s4, t2, dc_done           ; ...
        li    t2, '%'                   ; an escape?
        bne   s4, t2, dc_put            ; ...
        sub   t0, s2, s1                ; two hex digits
        li    t1, 2                     ; ...
        blt   t0, t1, dc_bad            ; ...
        lbu   a0, 0(s1)                 ; ...
        call  hexv                      ; ...
        bltz  a0, dc_bad                ; ...
        slli  s4, a0, 4                 ; ...
        lbu   a0, 1(s1)                 ; ...
        call  hexv                      ; ...
        bltz  a0, dc_bad                ; ...
        or    s4, s4, a0                ; ...
        addi  s1, s1, 2                 ; ...
dc_put:
        li    t0, 32                    ; no control characters
        bltu  s4, t0, dc_bad            ; ...
        li    t0, 127                   ; ...
        beq   s4, t0, dc_bad            ; ...
        li    t0, PMAX                  ; room?
        bgeu  s3, t0, dc_bad            ; ...
        la    t0, pbuf                  ; ...
        add   t0, t0, s3                ; ...
        sb    s4, 0(t0)                 ; ...
        addi  s3, s3, 1                 ; ...
        j     dc_l                      ; ...
dc_done:
        la    t0, plen                  ; ...
        sd    s3, 0(t0)                 ; ...
        li    a0, 0                     ; ...
        j     dc_ret                    ; ...
dc_bad:
        li    a0, -1                    ; ...
dc_ret:
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 40                ; ...
        ret                             ; ...

; hexv(a0 = a character) -> a0 = its value as a hex digit, or -1
hexv:
        addi  t0, a0, -48               ; '0'..'9'
        li    t1, 10                    ; ...
        bltu  t0, t1, hv_ok             ; ...
        ori   t0, a0, 32                ; 'a'..'f', either case
        addi  t0, t0, -97               ; ...
        li    t1, 6                     ; ...
        bltu  t0, t1, hv_af             ; ...
        li    a0, -1                    ; ...
        ret                             ; ...
hv_af:
        addi  t0, t0, 10                ; ...
hv_ok:
        mv    a0, t0                    ; ...
        ret                             ; ...

; route(): answer the path in pbuf/plen (see the header)
route:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        la    s1, pbuf                  ; s1 = the path
        la    t0, plen                  ; s2 = its length
        ld    s2, 0(t0)                 ; ...
        li    t0, 1                     ; "/"?
        bne   s2, t0, rt_tilde          ; ...
        la    a0, s_index               ; the home page
        li    a1, s_index_e - s_index   ; ...
        call  send_file                 ; ...
        bgez  a0, rt_ret                ; ...
rt_all:
        la    a0, s_slash               ; none: every file
        li    a1, 1                     ; ...
        call  listing                   ; ...
        j     rt_ret                    ; ...
rt_tilde:
        lbu   t0, 1(s1)                 ; a generated page: /~...
        li    t1, '~'                   ; ...
        bne   t0, t1, rt_dir            ; ...
        li    t0, 2                     ; "/~"
        beq   s2, t0, rt_all            ; ...
        mv    a0, s1                    ; "/~/"
        mv    a1, s2                    ; ...
        la    a2, s_tall                ; ...
        li    a3, 3                     ; ...
        call  str_eq                    ; ...
        bnez  a0, rt_all                ; ...
        mv    a0, s1                    ; "/~ps"
        mv    a1, s2                    ; ...
        la    a2, s_tps                 ; ...
        li    a3, 4                     ; ...
        call  str_eq                    ; ...
        beqz  a0, rt_404                ; ...
        call  status                    ; ...
        j     rt_ret                    ; ...
rt_dir:
        add   t0, s1, s2                ; ".../": a listing
        lbu   t0, -1(t0)                ; ...
        li    t1, '/'                   ; ...
        bne   t0, t1, rt_file           ; ...
        mv    a0, s1                    ; ...
        addi  a1, s2, -1                ; ...
        call  listing                   ; ...
        j     rt_ret                    ; ...
rt_file:
        mv    a0, s1                    ; a file
        mv    a1, s2                    ; ...
        call  send_file                 ; ...
        bgez  a0, rt_ret                ; ...
        mv    a0, s1                    ; no such file: a tag path?
        mv    a1, s2                    ; ...
        call  sys_count                 ; ...
        bltz  a0, rt_404                ; ...
        li    a0, 301                   ; yes: to its listing
        call  reply_err                 ; ...
        j     rt_ret                    ; ...
rt_404:
        li    a0, 404                   ; ...
        call  reply_err                 ; ...
rt_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; log_line(): "METHOD TARGET STATUS BYTES" on standard output, flushed
log_line:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        la    t0, rqm                   ; the method (- if there was none)
        ld    a1, 0(t0)                 ; ...
        beqz  a1, ll_nom                ; ...
        la    t0, rqa                   ; ...
        ld    a0, 0(t0)                 ; ...
        call  log_text                  ; ...
        li    a0, ' '                   ; ...
        call  out_chr                   ; ...
        la    t0, rqa                   ; the target, as sent
        ld    a0, 0(t0)                 ; ...
        la    t0, rqts                  ; ...
        ld    t1, 0(t0)                 ; ...
        add   a0, a0, t1                ; ...
        la    t0, rqte                  ; ...
        ld    a1, 0(t0)                 ; ...
        sub   a1, a1, t1                ; ...
        li    t0, 200                   ; (at most 200 bytes of it)
        bleu  a1, t0, ll_t              ; ...
        mv    a1, t0                    ; ...
ll_t:
        call  log_text                  ; ...
        j     ll_st                     ; ...
ll_nom:
        li    a0, '-'                   ; ...
        call  out_chr                   ; ...
        li    a0, ' '                   ; ...
        call  out_chr                   ; ...
        li    a0, '-'                   ; ...
        call  out_chr                   ; ...
ll_st:
        li    a0, ' '                   ; the status
        call  out_chr                   ; ...
        la    t0, ostat                 ; ...
        ld    a0, 0(t0)                 ; ...
        call  out_dec                   ; ...
        li    a0, ' '                   ; the body's bytes
        call  out_chr                   ; ...
        la    t0, ototal                ; ...
        ld    a0, 0(t0)                 ; ...
        la    t0, ohdr                  ; ...
        ld    t1, 0(t0)                 ; ...
        sub   a0, a0, t1                ; ...
        bgez  a0, ll_n                  ; (the client left during the headers)
        li    a0, 0                     ; ...
ll_n:
        call  out_dec                   ; ...
        call  out_nl                    ; ...
        call  out_flush                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; log_text(a0 = text, a1 = length): to standard output, '?' for control bytes
log_text:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        mv    s1, a0                    ; s1 = cursor
        add   s2, a0, a1                ; s2 = end
lt_l:
        beq   s1, s2, lt_ret            ; ...
        lbu   a0, 0(s1)                 ; ...
        addi  s1, s1, 1                 ; ...
        addi  t0, a0, -32               ; printable ASCII?
        li    t1, 95                    ; ...
        bltu  t0, t1, lt_put            ; ...
        li    a0, '?'                   ; ...
lt_put:
        call  out_chr                   ; ...
        j     lt_l                      ; ...
lt_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; ---- responses -----------------------------------------------------------------------------

; w_status(a0 = code) -> a0, a1 = its reason ("404 Not Found"): the status line
; and the headers every response has
w_status:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        la    t0, ostat                 ; (for the log)
        sd    a0, 0(t0)                 ; ...
        la    t0, codes                 ; the reason
wst_l:
        ld    t1, 0(t0)                 ; ...
        beq   t1, a0, wst_f             ; ...
        addi  t0, t0, 24                ; ...
        ld    t1, 0(t0)                 ; (an unknown code: the last one)
        bnez  t1, wst_l                 ; ...
        addi  t0, t0, -24               ; ...
wst_f:
        ld    s1, 8(t0)                 ; s1, s2 = the reason
        ld    s2, 16(t0)                ; ...
        la    a0, h_ver                 ; "HTTP/1.0 "
        li    a1, h_ver_e - h_ver       ; ...
        call  w_str                     ; ...
        mv    a0, s1                    ; "404 Not Found"
        mv    a1, s2                    ; ...
        call  w_str                     ; ...
        la    a0, h_com                 ; Server, Connection
        li    a1, h_com_e - h_com       ; ...
        call  w_str                     ; ...
        mv    a0, s1                    ; ...
        mv    a1, s2                    ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; w_ctype(a0 = type, a1 = length): "Content-Type: type"
w_ctype:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        la    a0, h_ct                  ; ...
        li    a1, h_ct_e - h_ct         ; ...
        call  w_str                     ; ...
        ld    a0, 8(sp)                 ; ...
        ld    a1, 16(sp)                ; ...
        call  w_str                     ; ...
        call  w_crlf                    ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; w_clen(a0 = bytes): "Content-Length: bytes"
w_clen:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        la    a0, h_cl                  ; ...
        li    a1, h_cl_e - h_cl         ; ...
        call  w_str                     ; ...
        ld    a0, 8(sp)                 ; ...
        call  w_dec                     ; ...
        call  w_crlf                    ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; w_html(): "Content-Type: text/html"
w_html:
        la    a0, t_html                ; ...
        li    a1, t_html_e - t_html     ; ...
        j     w_ctype                   ; (tail call)

; w_endh() -> a0 = 1 if no body follows (HEAD): the end of the headers
w_endh:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        call  w_crlf                    ; the blank line
        la    t0, ototal                ; every byte so far is header
        ld    t1, 0(t0)                 ; ...
        la    t0, olen                  ; ...
        ld    t2, 0(t0)                 ; ...
        add   t1, t1, t2                ; ...
        la    t0, ohdr                  ; ...
        sd    t1, 0(t0)                 ; ...
        la    t0, ohead                 ; ...
        ld    a0, 0(t0)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; reply_err(a0 = code): a response with a small HTML page naming the status
; (301: a Location of the path with a slash; 405: Allow)
reply_err:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        mv    s1, a0                    ; s1 = the code
        call  w_status                  ; s2, s3 = the reason
        mv    s2, a0                    ; ...
        mv    s3, a1                    ; ...
        call  w_html                    ; ...
        slli  a0, s3, 1                 ; the page: the reason twice ...
        addi  a0, a0, b_3e - b_1        ; ... in the three pieces
        call  w_clen                    ; ...
        li    t0, 405                   ; ...
        bne   s1, t0, re_loc            ; ...
        la    a0, h_allow               ; ...
        li    a1, h_allow_e - h_allow   ; ...
        call  w_str                     ; ...
re_loc:
        li    t0, 301                   ; ...
        bne   s1, t0, re_end            ; ...
        la    a0, h_loc                 ; Location: /path/
        li    a1, h_loc_e - h_loc       ; ...
        call  w_str                     ; ...
        la    a0, pbuf                  ; ...
        la    t0, plen                  ; ...
        ld    a1, 0(t0)                 ; ...
        call  w_url                     ; ...
        li    a0, '/'                   ; ...
        call  w_chr                     ; ...
        call  w_crlf                    ; ...
re_end:
        call  w_endh                    ; ...
        bnez  a0, re_ret                ; (HEAD)
        la    a0, b_1                   ; the page
        li    a1, b_2 - b_1             ; ...
        call  w_str                     ; ...
        mv    a0, s2                    ; ...
        mv    a1, s3                    ; ...
        call  w_str                     ; ...
        la    a0, b_2                   ; ...
        li    a1, b_3 - b_2             ; ...
        call  w_str                     ; ...
        mv    a0, s2                    ; ...
        mv    a1, s3                    ; ...
        call  w_str                     ; ...
        la    a0, b_3                   ; ...
        li    a1, b_3e - b_3            ; ...
        call  w_str                     ; ...
re_ret:
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; send_file(a0 = path, a1 = length) -> a0 = 0 (sent), or < 0 with nothing
; sent (no such file): 200, its type and length, then the file in chunks
send_file:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        sd    s5, 40(sp)                ; ...
        mv    s1, a0                    ; s1, s2 = the path
        mv    s2, a1                    ; ...
        li    a2, 0                     ; open it
        call  sys_open                  ; ...
        bltz  a0, sf_ret                ; ...
        mv    s3, a0                    ; s3 = the handle
        mv    a0, s1                    ; s4 = its size
        mv    a1, s2                    ; ...
        call  sys_stat                  ; ...
        mv    s4, a0                    ; ...
        bgez  s4, sf_rd                 ; ...
        li    s4, 0                     ; ...
sf_rd:
        mv    a0, s3                    ; s5 = the first chunk
        la    a1, dirbuf                ; ...
        li    a2, CHUNK                 ; ...
        call  sys_read                  ; ...
        mv    s5, a0                    ; ...
        bgez  s5, sf_hd                 ; ...
        li    s5, 0                     ; ...
sf_hd:
        li    a0, 200                   ; the headers
        call  w_status                  ; ...
        mv    a0, s1                    ; the type
        mv    a1, s2                    ; ...
        la    a2, dirbuf                ; ...
        mv    a3, s5                    ; ...
        call  ctype                     ; ...
        call  w_ctype                   ; ...
        mv    a0, s4                    ; the length
        call  w_clen                    ; ...
        call  w_endh                    ; ...
        bnez  a0, sf_done               ; (HEAD)
        call  w_flush                   ; the headers go first
sf_l:
        blez  s5, sf_done               ; the end (or a failed read)
        la    t0, ofail                 ; the client is gone?
        ld    t0, 0(t0)                 ; ...
        bnez  t0, sf_done               ; ...
        la    a0, dirbuf                ; the chunk
        mv    a1, s5                    ; ...
        call  w_send                    ; ...
        mv    a0, s3                    ; the next one
        la    a1, dirbuf                ; ...
        li    a2, CHUNK                 ; ...
        call  sys_read                  ; ...
        mv    s5, a0                    ; ...
        j     sf_l                      ; ...
sf_done:
        mv    a0, s3                    ; ...
        call  sys_close                 ; ...
        li    a0, 0                     ; ...
sf_ret:
        ld    s5, 40(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; ...

; ctype(a0 = path, a1 = length, a2 = the file's first bytes, a3 = how many)
; -> a0, a1 = the content type: by the extension of the path's last
; component; with none, text/plain if those bytes look like text
ctype:
        add   t0, a0, a1                ; t0 = the end
        mv    t1, t0                    ; back to a '.' (not past a '/')
ct_b:
        beq   t1, a0, ct_none           ; ...
        addi  t1, t1, -1                ; ...
        lbu   t2, 0(t1)                 ; ...
        li    t3, '/'                   ; ...
        beq   t2, t3, ct_none           ; ...
        li    t3, '.'                   ; ...
        bne   t2, t3, ct_b              ; ...
        addi  t1, t1, 1                 ; t1 = the extension
        sub   t4, t0, t1                ; its length: 1..8
        beqz  t4, ct_bin                ; ...
        li    t3, 8                     ; ...
        bgtu  t4, t3, ct_bin            ; ...
        li    t5, 0                     ; t5 = it, packed in a word, lower case
        li    t6, 0                     ; t6 = shift
        li    a4, 26                    ; ...
ct_p:
        beq   t1, t0, ct_look           ; ...
        lbu   t2, 0(t1)                 ; ...
        addi  t1, t1, 1                 ; ...
        addi  t3, t2, -65               ; 'A'..'Z' -> 'a'..'z'
        bgeu  t3, a4, ct_pc             ; ...
        addi  t2, t2, 32                ; ...
ct_pc:
        sll   t2, t2, t6                ; ...
        or    t5, t5, t2                ; ...
        addi  t6, t6, 8                 ; ...
        j     ct_p                      ; ...
ct_look:
        la    t0, mimes                 ; in the table?
ct_ll:
        ld    t1, 0(t0)                 ; ...
        beqz  t1, ct_bin                ; ...
        beq   t1, t5, ct_hit            ; ...
        addi  t0, t0, 24                ; ...
        j     ct_ll                     ; ...
ct_hit:
        ld    a0, 8(t0)                 ; ...
        ld    a1, 16(t0)                ; ...
        ret                             ; ...
ct_none:
        li    t0, 0                     ; no extension: text?
ct_s:
        beq   t0, a3, ct_txt            ; ...
        add   t1, a2, t0                ; ...
        lbu   t1, 0(t1)                 ; ...
        addi  t0, t0, 1                 ; ...
        li    t2, 127                   ; DEL: no
        beq   t1, t2, ct_bin            ; ...
        li    t2, 32                    ; printable, or UTF-8
        bgeu  t1, t2, ct_s              ; ...
        li    t2, 9                     ; tab, newline, CR
        beq   t1, t2, ct_s              ; ...
        li    t2, 10                    ; ...
        beq   t1, t2, ct_s              ; ...
        li    t2, 13                    ; ...
        beq   t1, t2, ct_s              ; ...
ct_bin:
        la    a0, t_bin                 ; ...
        li    a1, t_bin_e - t_bin       ; ...
        ret                             ; ...
ct_txt:
        la    a0, t_text                ; ...
        li    a1, t_text_e - t_text     ; ...
        ret                             ; ...

