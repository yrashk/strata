_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        call  sys_init                  ; ...
        la    a0, ftbuf                 ; URLs are absolute: work from "/" whatever the
        li    a1, 0                     ;   current tag path of the shell that started us
        la    a2, ftbuf                 ;   (an empty path is "/"; the reply lands in ftbuf)
        call  sys_chdir                 ; ...
        call  sys_cmdline               ; s1 = cursor, s2 = end
        add   s2, a0, a1                ; ...
        mv    a1, s2                    ; skip the program's name
        call  arg_next                  ; ...
        mv    s1, a2                    ; ...
m_arg:
        mv    a0, s1                    ; the next word
        mv    a1, s2                    ; ...
        call  arg_next                  ; ...
        beqz  a1, m_go                  ; no more
        mv    s1, a2                    ; ...
        mv    s3, a0                    ; ...
        mv    s4, a1                    ; ...
        la    a2, s_p                   ; -p PORT
        li    a3, 2                     ; ...
        call  str_eq                    ; ...
        bnez  a0, m_port                ; ...
        mv    a0, s3                    ; -c CONNS
