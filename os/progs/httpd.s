        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        mv    a0, s1                    ; ...
        mv    a1, s2                    ; ...
        call  arg_next                  ; ...
        mv    s1, a2                    ; ...
        li    t0, -1                    ; (none)
        beqz  a1, nn_ret0               ; ...
        call  str_num                   ; ...
        j     nn_ret                    ; ...
nn_ret0:
        mv    a0, t0                    ; ...
nn_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

