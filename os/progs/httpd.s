        ret                             ; ...

; listing(a0 = tag path, a1 = length): the files carrying the path's tags,
; their sizes and tags, and the facets that narrow it; 404 if a tag is unknown
listing:
        addi  sp, sp, -96               ; frame (88: the listing's cursor)
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        sd    s5, 40(sp)                ; ...
        sd    s6, 48(sp)                ; ...
        sd    s7, 56(sp)                ; ...
        sd    s8, 64(sp)                ; ...
        sd    s9, 72(sp)                ; ...
        sd    s10, 80(sp)               ; ...
        mv    s1, a0                    ; s1, s2 = the path
        mv    s2, a1                    ; ...
        mv    a0, s1                    ; is there such a path? (and its facets, of
        mv    a1, s2                    ; every file; the files are listed below)
        call  sys_count                 ; ...
        bltz  a0, ls_404                ; ...
        call  sys_facets                ; s4 = the facets (read them at once)
        mv    s4, a0                    ; ...
        la    a0, tagbuf                ; s5 = every tag (for the facets' names)
        li    a1, 0                     ; ...
        li    a2, 0                     ; ...
        li    a3, 0                     ; ...
        call  sys_tags2                 ; ...
        mv    s5, a0                    ; ...
        bgez  s5, ls_d                  ; ...
        li    s5, 0                     ; ...
ls_d:
        mv    s6, s2                    ; s6 = the path's length in links (0 for /)
        li    t0, 1                     ; ...
        bne   s2, t0, ls_h              ; ...
        li    s6, 0                     ; ...
ls_h:
        li    a0, 200                   ; the headers
        call  w_status                  ; ...
        call  w_html                    ; ...
        call  w_endh                    ; ...
        bnez  a0, ls_ret                ; (HEAD)
        mv    a0, s1                    ; the title: the path
        mv    a1, s2                    ; ...
        li    a2, 1                     ; ...
        bnez  s6, ls_tt                 ; ...
        la    a0, l_all                 ; (or "every file")
        li    a1, l_alle - l_all        ; ...
ls_tt:
        call  page_top                  ; ...
        la    a0, l_root                ; the heading: the path, a link per tag
        li    a1, l_root_e - l_root     ; ...
        call  w_str                     ; ...
        li    s7, 1                     ; s7 = cursor (after the first '/')
ls_cr:
        bgeu  s7, s6, ls_cre            ; ...
        add   t0, s1, s7                ; empty components are skipped
        lbu   t0, 0(t0)                 ; ...
        li    t1, '/'                   ; ...
        bne   t0, t1, ls_c1             ; ...
        addi  s7, s7, 1                 ; ...
        j     ls_cr                     ; ...
ls_c1:
        mv    s8, s7                    ; s8 = the component's start
ls_c2:
        bgeu  s7, s6, ls_c3             ; its end
        add   t0, s1, s7                ; ...
        lbu   t0, 0(t0)                 ; ...
        li    t1, '/'                   ; ...
        beq   t0, t1, ls_c3             ; ...
        addi  s7, s7, 1                 ; ...
        j     ls_c2                     ; ...
ls_c3:
        la    a0, l_a1                  ; <a href="/path/up/to/it/">it</a>/
        li    a1, l_a1e - l_a1          ; ...
        call  w_str                     ; ...
        mv    a0, s1                    ; ...
        mv    a1, s7                    ; ...
        call  w_url                     ; ...
        la    a0, l_sl                  ; ...
        li    a1, l_sle - l_sl          ; ...
        call  w_str                     ; ...
        add   a0, s1, s8                ; ...
        sub   a1, s7, s8                ; ...
        call  w_esc                     ; ...
        la    a0, l_a3                  ; ...
        li    a1, l_a3e - l_a3          ; ...
        call  w_str                     ; ...
        li    a0, '/'                   ; ...
        call  w_chr                     ; ...
        j     ls_cr                     ; ...
ls_cre:
        la    a0, p_h1e                 ; ...
        li    a1, p_h1ee - p_h1e        ; ...
        call  w_str                     ; ...
        beqz  s4, ls_tab                ; facets: links that add a tag
        la    a0, l_fac                 ; ...
        li    a1, l_face - l_fac        ; ...
        call  w_str                     ; ...
        li    s7, 0                     ; s7 = tag number
ls_f:
        li    t0, 64                    ; ...
        beq   s7, t0, ls_fe             ; ...
        srl   t0, s4, s7                ; in the set?
        andi  t0, t0, 1                 ; ...
        beqz  t0, ls_fn                 ; ...
        mv    a0, s7                    ; its name
        mv    a1, s5                    ; ...
        call  tagname                   ; ...
        beqz  a0, ls_fn                 ; ...
        mv    s8, a0                    ; s8 = the name
        mv    s9, a1                    ; s9 = its length
        la    a0, l_a1                  ; <a href="/path/tag/">tag/</a>
        li    a1, l_a1e - l_a1          ; ...
        call  w_str                     ; ...
        mv    a0, s1                    ; ...
        mv    a1, s6                    ; ...
        call  w_url                     ; ...
        li    a0, '/'                   ; ...
        call  w_chr                     ; ...
        mv    a0, s8                    ; ...
        mv    a1, s9                    ; ...
        call  w_url                     ; ...
        la    a0, l_sl                  ; ...
        li    a1, l_sle - l_sl          ; ...
        call  w_str                     ; ...
        mv    a0, s8                    ; ...
        mv    a1, s9                    ; ...
        call  w_esc                     ; ...
        li    a0, '/'                   ; ...
        call  w_chr                     ; ...
        la    a0, l_a3                  ; ...
        li    a1, l_a3e - l_a3          ; ...
        call  w_str                     ; ...
        li    a0, ' '                   ; ...
        call  w_chr                     ; ...
ls_fn:
        addi  s7, s7, 1                 ; ...
        j     ls_f                      ; ...
ls_fe:
        la    a0, l_pe                  ; ...
        li    a1, l_pee - l_pe          ; ...
        call  w_str                     ; ...
ls_tab:
        la    a0, l_tab                 ; the table
        li    a1, l_tabe - l_tab        ; ...
        call  w_str                     ; ...
        li    s3, 0                     ; s3 = files listed
        sd    zero, 88(sp)              ; the files, part by part (sys_list): whole
ls_part:
        la    a0, dirbuf                ; names, however many files
        mv    a1, s1                    ; ...
        mv    a2, s2                    ; ...
        ld    a3, 88(sp)                ; ...
        call  sys_list                  ; a0 = files in this part, a1 = the cursor
        sd    a1, 88(sp)                ; ...
        blez  a0, ls_re                 ; ...
        mv    s8, a0                    ; s8 = records left
        la    s7, dirbuf                ; s7 = a record's name: after the path's own
        ld    t0, 0(s7)                 ; tags, and the record's 16 bytes
        slli  t0, t0, 2                 ; ...
        addi  t0, t0, 15                ; ...
        srli  t0, t0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        add   s7, s7, t0                ; ...
        addi  s7, s7, 16                ; ...
ls_r:
        beqz  s8, ls_pe                 ; ...
        lhu   s9, -14(s7)               ; s9 = the name's length
        la    a0, l_tr                  ; <tr><td><a href="/path/name">name</a></td>
        li    a1, l_tre - l_tr          ; ...
        call  w_str                     ; ...
        la    a0, l_a1                  ; ...
        li    a1, l_a1e - l_a1          ; ...
        call  w_str                     ; ...
        mv    a0, s1                    ; ...
        mv    a1, s6                    ; ...
        call  w_url                     ; ...
        li    a0, '/'                   ; ...
        call  w_chr                     ; ...
        mv    a0, s7                    ; ...
        mv    a1, s9                    ; ...
        call  w_url                     ; ...
        la    a0, l_a2                  ; ...
        li    a1, l_a2e - l_a2          ; ...
        call  w_str                     ; ...
        mv    a0, s7                    ; ...
        mv    a1, s9                    ; ...
        call  w_esc                     ; ...
        la    a0, l_a3                  ; ...
        li    a1, l_a3e - l_a3          ; ...
        call  w_str                     ; ...
        la    a0, l_tde                 ; ...
        li    a1, l_tdee - l_tde        ; ...
        call  w_str                     ; ...
        ld    a0, -8(s7)                ; <td class="n">size</td>
        call  w_tdn                     ; ...
        la    a0, l_td                  ; <td> the tags </td></tr>
        li    a1, l_tdz - l_td          ; ...
        call  w_str                     ; ...
        la    a0, ftbuf                 ; the file's tags
        mv    a1, s7                    ; ...
        mv    a2, s9                    ; ...
        li    a3, 0                     ; ...
        call  sys_tags2                 ; ...
        mv    s10, a0                   ; s10 = tags left
        la    s9, ftbuf                 ; s9 = tag record
ls_g:
        blez  s10, ls_ge                ; ...
        addi  a0, s9, 16                ; <a href="/tag/">tag</a>
        lhu   a1, 2(s9)                 ; ...
        call  w_tag                     ; ...
        lhu   t0, 0(s9)                 ; ...
        add   s9, s9, t0                ; ...
        addi  s10, s10, -1              ; ...
        j     ls_g                      ; ...
ls_ge:
        la    a0, l_trn                 ; ...
        li    a1, l_trne - l_trn        ; ...
        call  w_str                     ; ...
        lhu   t0, -16(s7)               ; next file
        add   s7, s7, t0                ; ...
        addi  s3, s3, 1                 ; ...
        addi  s8, s8, -1                ; ...
        j     ls_r                      ; ...
ls_pe:
        ld    t0, 88(sp)                ; more parts?
        bnez  t0, ls_part               ; ...
ls_re:
        la    a0, l_te                  ; </table> N files
        li    a1, l_tee - l_te          ; ...
        call  w_str                     ; ...
        mv    a0, s3                    ; ...
        call  w_dec                     ; ...
        la    a0, l_nf                  ; ...
        li    a1, l_nfe - l_nf          ; ...
        call  w_str                     ; ...
        call  w_foot                    ; ...
        j     ls_ret                    ; ...
ls_404:
        li    a0, 404                   ; ...
        call  reply_err                 ; ...
ls_ret:
        ld    s10, 80(sp)               ; ...
        ld    s9, 72(sp)                ; ...
        ld    s8, 64(sp)                ; ...
        ld    s7, 56(sp)                ; ...
        ld    s6, 48(sp)                ; ...
        ld    s5, 40(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 96                ; ...
        ret                             ; ...

; tagname(a0 = tag id, a1 = records in tagbuf) -> a0 = that tag's name, a1 =
; its length; a0 = 0 if none
tagname:
        la    t0, tagbuf                ; ...
tn_l:
        blez  a1, tn_no                 ; ...
        lwu   t1, 4(t0)                 ; its id
        beq   t1, a0, tn_yes            ; ...
        lhu   t1, 0(t0)                 ; ...
        add   t0, t0, t1                ; ...
        addi  a1, a1, -1                ; ...
        j     tn_l                      ; ...
tn_yes:
        addi  a0, t0, 16                ; ...
        lhu   a1, 2(t0)                 ; ...
        ret                             ; ...
tn_no:
        li    a0, 0                     ; ...
        ret                             ; ...

