; page_top(a0 = title, a1 = length, a2 = 1 to escape it): the start of a
; page up to and including <h1>
page_top:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        sd    a2, 24(sp)                ; ...
        la    a0, p_1                   ; ...
        li    a1, p_1e - p_1            ; ...
        call  w_str                     ; ...
        ld    a0, 8(sp)                 ; the title
        ld    a1, 16(sp)                ; ...
        ld    t0, 24(sp)                ; ...
        beqz  t0, ptp_raw               ; ...
