; =============================================================================
; tags.s: list the tags
; =============================================================================
;
;   tags                  every tag: name (padded to 18 columns), files carrying it
;   tags FILE...          each file's tags: "FILE: tag tag ..."
;
; Asks the file server with sys_tags2, part by part (per tag: u16 record
; bytes, u16 name length, u32 id, u64 files carrying it, the name): names
; are whole and there may be any number of tags. Prints
; "(no tags)" when there are none; "tags: no such file: FILE" (exit code 1).

        .data                           ; data Local Store
        .align 8                        ; aligned buffers
tagbuf: .space 4032                     ; tag records (one message's worth)
args:   .space 512                      ; the argument text
m_none: .ascii "(no tags)\n"            ; output text
m_none_e:                               ; end of the text above
m_no:   .ascii "tags: no such file: "   ; error text
m_no_e:                                 ; end of the text above
m_col:  .ascii ":"                      ; after a file's name

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        call  sys_init                  ; handles and arguments
        li    s4, 0                     ; s4 = exit code
        la    a0, args                  ; the arguments ...
        call  sys_args                  ; ... a0 = their length
        beqz  a0, all                   ; none: every tag
        la    s0, args                  ; s0 = cursor
        add   s1, s0, a0                ; s1 = end
file:
        mv    a0, s0                    ; the next file
        mv    a1, s1                    ; ...
        call  arg_next                  ; a0 = start, a1 = length, a2 = cursor after
        beqz  a1, done                  ; no more
        mv    s0, a2                    ; advance the cursor
        mv    s2, a0                    ; s2, s3 = the file
        mv    s3, a1                    ; ...
        li    s6, 0                     ; s6 = the cursor; s7 = 0 until "FILE:" is out
        li    s7, 0                     ; ...
f_part:
        la    a0, tagbuf                ; its tags, a part of them
        mv    a1, s2                    ; ...
        mv    a2, s3                    ; ...
        mv    a3, s6                    ; ...
        call  sys_tags2                 ; a0 = how many, or < 0; a1 = the cursor
        bltz  a0, f_no                  ; no such file
        mv    s5, a0                    ; s5 = tags left
        mv    s6, a1                    ; ...
        bnez  s7, f_recs                ; ...
        li    s7, 1                     ; ...
        mv    a0, s2                    ; "FILE:"
        mv    a1, s3                    ; ...
        call  out_str                   ; ...
        la    a0, m_col                 ; ...
        li    a1, 1                     ; ...
        call  out_str                   ; ...
f_recs:
        la    s8, tagbuf                ; s8 = record
f_l:
        blez  s5, f_more                ; no more in this part
        li    a0, 1                     ; a space, then the name
        call  out_pad                   ; ...
        addi  a0, s8, 16                ; ...
        lhu   a1, 2(s8)                 ; ...
        call  out_str                   ; ...
        lhu   t0, 0(s8)                 ; next tag
        add   s8, s8, t0                ; ...
        addi  s5, s5, -1                ; ...
        j     f_l                       ; ...
f_more:
        bnez  s6, f_part                ; another part
f_end:
        call  out_nl                    ; end the line
        j     file                      ; next file
f_no:
        li    s4, 1                     ; remember the failure
        la    a0, m_no                  ; "tags: no such file: "
        li    a1, m_no_e - m_no         ; ...
        call  err_str                   ; ...
        mv    a0, s2                    ; the file
        mv    a1, s3                    ; ...
        call  err_str                   ; ...
        la    a0, sys_nl                ; a newline
        li    a1, 1                     ; ...
        call  err_str                   ; ...
        j     file                      ; next file
all:
        li    s6, 0                     ; s6 = the cursor, s7 = tags shown
        li    s7, 0                     ; ...
a_part:
        la    a0, tagbuf                ; every tag, a part of them
        li    a1, 0                     ; ...
        li    a2, 0                     ; ...
        mv    a3, s6                    ; ...
        call  sys_tags2                 ; a0 = how many, a1 = the cursor
        mv    s6, a1                    ; ...
        blez  a0, a_end                 ; ...
        mv    s5, a0                    ; s5 = tags left
        add   s7, s7, a0                ; ...
        la    s2, tagbuf                ; s2 = record
a_l:
        addi  a0, s2, 16                ; the name
        lhu   a1, 2(s2)                 ; ...
        mv    s3, a1                    ; ...
        call  out_str                   ; ...
        li    a0, 18                    ; pad it to 18 columns (a longer one: a space)
        sub   a0, a0, s3                ; ...
        bgtz  a0, a_pad                 ; ...
        li    a0, 1                     ; ...
a_pad:
        call  out_pad                   ; ...
        ld    a0, 8(s2)                 ; the files carrying it
        call  out_dec                   ; ...
        call  out_nl                    ; ...
        lhu   t0, 0(s2)                 ; next tag
        add   s2, s2, t0                ; ...
        addi  s5, s5, -1                ; ...
        bnez  s5, a_l                   ; ...
        bnez  s6, a_part                ; another part
a_end:
        bnez  s7, done                  ; ...
none:
        la    a0, m_none                ; "(no tags)"
        li    a1, m_none_e - m_none     ; ...
        call  out_str                   ; ...
done:
        mv    a0, s4                    ; exit code
        call  sys_exit                  ; flush stdout, end the process

        .include "../lib/sys.s"         ; the system interface
