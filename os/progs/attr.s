; =============================================================================
; attr.s: a file's attributes
; =============================================================================
;
;   attr FILE             its attributes, one a line: NAME = VALUE
;   attr FILE NAME VALUE  give it one (or change it): a value in digits is a
;                         number, any other a string (up to 255 bytes)
;   attr -d FILE NAME     take it away
;
; An attribute is a name and a value a file carries besides its tags; the
; file server keeps them in the file's record and in its index (SETATTR,
; GETATTR: os/servers/fsattr.s). A path can ask about them: a component
; NAME=VALUE, NAME<VALUE or NAME>VALUE keeps the files for which it holds
; (quoted in the shell when it has < or >), and so do size and modified:
;   ls /src/lang=asm      ls '/src/size>100000'     ls 'year<1990'
; Errors: "attr: no such file: FILE", "attr: cannot set NAME" (exit code 1).

        .data                           ; data Local Store
        .align 8                        ; aligned buffers
args:   .space 512                      ; the argument text
rq:     .space 1024                     ; a request: path, 0, name, 0, value
recs:   .space 4096                     ; the attributes
m_d:    .ascii "-d"                     ; the option
m_eq:   .ascii " = "                    ; between name and value
m_nof:  .ascii "attr: no such file: "   ; error texts
m_nof_e:
m_set:  .ascii "attr: cannot set "      ; ...
m_set_e:
m_use:  .ascii "usage: attr FILE [NAME VALUE] | attr -d FILE NAME\n"
m_use_e:

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        call  sys_init                  ; handles and arguments
        la    a0, args                  ; the arguments ...
        call  sys_args                  ; ... a0 = their length
        la    t0, args                  ; ...
        add   s1, t0, a0                ; s1 = the end
        mv    a0, t0                    ; the first word
        mv    a1, s1                    ; ...
        call  arg_next                  ; ...
        beqz  a1, usage                 ; ...
        mv    s2, a0                    ; s2, s3 = the word
        mv    s3, a1                    ; ...
        mv    s4, a2                    ; s4 = after it
        li    s7, 0                     ; s7 = 1: take away
        la    a2, m_d                   ; -d?
        li    a3, 2                     ; ...
        call  str_eq                    ; ...
        beqz  a0, file                  ; ...
        li    s7, 1                     ; ...
        mv    a0, s4                    ; ...
        mv    a1, s1                    ; ...
        call  arg_next                  ; ...
        beqz  a1, usage                 ; ...
        mv    s2, a0                    ; ...
        mv    s3, a1                    ; ...
        mv    s4, a2                    ; ...
file:
        mv    a0, s4                    ; NAME?
        mv    a1, s1                    ; ...
        call  arg_next                  ; ...
        beqz  a1, list                  ; none: its attributes
        mv    s5, a0                    ; s5, s6 = the name
        mv    s6, a1                    ; ...
        mv    s4, a2                    ; ...
        la    a0, rq                    ; the request: path, 0, name, 0
        mv    a1, s2                    ; ...
        mv    a2, s3                    ; ...
        call  put                       ; ...
        sb    zero, 0(a0)               ; ...
        addi  a0, a0, 1                 ; ...
        mv    a1, s5                    ; ...
        mv    a2, s6                    ; ...
        call  put                       ; ...
        sb    zero, 0(a0)               ; ...
        addi  s0, a0, 1                 ; s0 = where the value goes
        bnez  s7, send                  ; (taking away: none)
        mv    a0, s4                    ; VALUE
        mv    a1, s1                    ; ...
        call  arg_next                  ; ...
        beqz  a1, usage                 ; ...
        mv    a2, a1                    ; ...
        mv    a1, a0                    ; ...
        mv    a0, s0                    ; ...
        call  put                       ; ...
        mv    s0, a0                    ; ...
send:
        la    a0, rq                    ; ...
        sub   s0, s0, a0                ; ...
        mv    a1, s0                    ; ...
        call  sys_put                   ; ...
        li    a0, 2                     ; fs
        li    a1, 42                    ; SETATTR
        li    a2, 0                     ; ...
        mv    a3, s0                    ; ...
        li    a4, 0                     ; ...
        call  sys_msg                   ; ...
        beqz  a0, done                  ; ...
        li    t0, -4                    ; ...
        beq   a0, t0, nofile            ; ...
        la    a0, m_set                 ; ...
        li    a1, m_set_e - m_set       ; ...
        mv    s2, s5                    ; ...
        mv    s3, s6                    ; ...
        j     fail                      ; ...
list:
        bnez  s7, usage                 ; ...
        mv    a0, s2                    ; the path -> the request
        mv    a1, s3                    ; ...
        call  sys_put                   ; ...
        li    a0, 2                     ; fs
        li    a1, 43                    ; GETATTR
        li    a2, 0                     ; ...
        mv    a3, s3                    ; ...
        li    a4, 0                     ; ...
        call  sys_msg                   ; a0 = how many
        bltz  a0, nofile                ; ...
        mv    s0, a0                    ; s0 = records left
        la    t0, sys_hdr               ; (the reply's length word: the data's bytes)
        ld    a1, 16(t0)                ; ...
        la    a0, recs                  ; ...
        call  sys_get                   ; ...
        la    s1, recs                  ; s1 = the record
l_l:
        beqz  s0, done                  ; ...
        addi  a0, s1, 8                 ; its name
        lhu   a1, 2(s1)                 ; ...
        call  out_str                   ; ...
        la    a0, m_eq                  ; ...
        li    a1, 3                     ; ...
        call  out_str                   ; ...
        lhu   t0, 2(s1)                 ; its value: after the name, padded
        addi  t0, t0, 7                 ; ...
        srli  t0, t0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        add   a0, s1, t0                ; ...
        addi  a0, a0, 8                 ; ...
        lbu   t1, 4(s1)                 ; a number?
        bnez  t1, l_s                   ; ...
        ld    a0, 0(a0)                 ; ...
        call  out_dec                   ; ...
        j     l_n                       ; ...
l_s:
        lbu   a1, 5(s1)                 ; ...
        call  out_str                   ; ...
l_n:
        call  out_nl                    ; ...
        lhu   t0, 0(s1)                 ; ...
        add   s1, s1, t0                ; ...
        addi  s0, s0, -1                ; ...
        j     l_l                       ; ...
done:
        li    a0, 0                     ; exit code
        call  sys_exit                  ; flush stdout, end the process

; put(a0 = to, a1 = from, a2 = bytes) -> a0 = after them
put:
        beqz  a2, put_r                 ; ...
        lbu   t0, 0(a1)                 ; ...
        sb    t0, 0(a0)                 ; ...
        addi  a0, a0, 1                 ; ...
        addi  a1, a1, 1                 ; ...
        addi  a2, a2, -1                ; ...
        j     put                       ; ...
put_r:
        ret                             ; ...

nofile:
        la    a0, m_nof                 ; ...
        li    a1, m_nof_e - m_nof       ; ...
fail:
        call  err_str                   ; the message, the word, a newline
        mv    a0, s2                    ; ...
        mv    a1, s3                    ; ...
        call  err_str                   ; ...
        la    a0, sys_nl                ; ...
        li    a1, 1                     ; ...
        call  err_str                   ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...
usage:
        la    a0, m_use                 ; ...
        li    a1, m_use_e - m_use       ; ...
        call  err_str                   ; ...
        li    a0, 2                     ; ...
        call  sys_exit                  ; ...

        .include "../lib/sys.s"         ; the system interface
