; =============================================================================
; render.s: wdoom's renderer: a textured grid raycaster drawn in slabs
; =============================================================================
;
; The view is 320 x 168 pixels of 8-bit palette indices, far more than a
; D-LS holds beside everything else, so a frame is drawn in ten SLABS of 32
; columns. For each slab:
;   r_col      casts a ray per column through the level's grid (DDA; a door
;              is a plane in the middle of its cell that slides sideways),
;              fetches the one texture column it hit from the arena (`tget`,
;              128 bytes) and draws ceiling, wall and floor, shaded through
;              the colour map by distance;
;   r_sprites  draws the things that reach into the slab, far to near, each
;              column scaled and clipped against the walls' depths (zbuf);
;   r_over     the weapon, the message line and the end-of-level figures;
;   r_push     turns each row into XRGB8888 through the palette, scaled by
;              the window's factor, and sends it into the band (`tput`).
; The status bar is drawn the same way, 32 rows at a time (r_bar).
;
; Fixed point: positions and distances are 16.16 (1.0 = a cell); angles are
; 0..2047 around the circle.

VIEW_W    = 320                         ; the view's columns
VIEW_H    = 168                         ; its rows
HORIZON   = 84                          ; the row of the eye
BAR_H     = 32                          ; the status bar's rows
SLAB_W    = 32                          ; columns per slab
NSLAB     = 10                          ; slabs in the view
PROJ      = 160                         ; pixels per cell at distance 1

; ---- a visible thing (r_project) ----------------------------------------------
V_X1      = 0                           ; first column (signed)
V_X2      = 4                           ; past the last
V_Y1      = 8                           ; first row (signed)
V_Y2      = 12                          ; past the last
V_DEPTH   = 16                          ; distance along the view, 16.16
V_INV     = 20                          ; texels per pixel, 16.16
V_SPR     = 24                          ; its sprite's directory entry
V_TH      = 32                          ; the thing
V_LP      = 40                          ; its row of the colour map
V_SIZE    = 48                          ; bytes
MAXVIS    = 40                          ; visible things at most

; ---- a sprite's directory entry (dat.s: R_SPR) ---------------------------------
SD_OFF    = 0                           ; far offset (u32)
SD_W      = 4                           ; columns
SD_H      = 6                           ; rows
SD_OX     = 8                           ; the origin's column
SD_OY     = 10                          ; ... and row
SD_CS     = 12                          ; bytes per column
SD_SIZE   = 16                          ; bytes

        .data                           ; D-LS
        .align 8                        ; dwords
slab:     .space SLAB_W * VIEW_H        ; the slab: palette indices, row-major
rowbuf:   .space SLAB_W * 4 * 4         ; a row of it as pixels, at up to 4 x
colbuf:   .space 128                    ; a texture or sprite column
zbuf:     .space VIEW_W * 4             ; the wall's distance in every column
vis:      .space MAXVIS * V_SIZE        ; the visible things
visord:   .space MAXVIS * 8             ; ... far to near
        .text                           ; code

; fsin(a0 = angle) -> a0 = its sine, 16.16; fcos likewise. Clobber t0, t1.
fcos:   addi  a0, a0, 512               ; cos a = sin (a + a quarter)
fsin:   andi  a0, a0, 2047              ; one circle
        srli  t0, a0, 9                 ; t0 = the quadrant
        andi  a0, a0, 511               ; the angle in it
        andi  t1, t0, 1                 ; quadrants 1 and 3 run backwards
        beqz  t1, fs_1                  ; ...
        li    t1, 512                   ; ...
        sub   a0, t1, a0                ; ...
fs_1:   slli  a0, a0, 2                 ; the table's entry
        la    t1, res + R_SIN           ; ...
        add   a0, a0, t1                ; ...
        lwu   a0, 0(a0)                 ; ...
        andi  t0, t0, 2                 ; quadrants 2 and 3 are negative
        beqz  t0, fs_r                  ; ...
        neg   a0, a0                    ; ...
fs_r:   ret                             ; done

; r_view(): the view's direction and its screen plane from the angle
r_view: addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        ld    a0, g_ang - g(gp)         ; dir = (cos, sin)
        call  fcos                      ; ...
        sd    a0, g_dirx - g(gp)        ; ...
        sd    a0, g_ply - g(gp)         ; the plane is the direction turned a quarter
        ld    a0, g_ang - g(gp)         ;   towards larger angles: (-sin, cos), so that
        call  fsin                      ;   the screen's right is the turn to the right
        sd    a0, g_diry - g(gp)        ; ...
        neg   a0, a0                    ; ...
        sd    a0, g_plx - g(gp)         ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; r_col(s0 = column 0..319, s1 = that column's first byte in the slab): cast
; its ray and draw the column. Keeps s0, s1; clobbers everything else.
r_col:  addi  sp, sp, -16               ; frame
        sd    s0, 0(sp)                 ; keep the column
        sd    s1, 8(sp)                 ; ... and its place
        slli  t0, s0, 1                 ; where the column is on the plane: -1 .. 1
        addi  t0, t0, -(VIEW_W - 1)     ;   = (2 x - 319) / 320, 16.16
        li    t1, 205                   ;   (65536 / 320)
        mul   t0, t0, t1                ; ...
        ld    t1, g_plx - g(gp)         ; the ray = dir + plane * that
        mul   t1, t1, t0                ; ...
        srai  t1, t1, 16                ; ...
        ld    s2, g_dirx - g(gp)        ; ...
        add   s2, s2, t1                ; s2 = ray x
        ld    t1, g_ply - g(gp)         ; ...
        mul   t1, t1, t0                ; ...
        srai  t1, t1, 16                ; ...
        ld    s3, g_diry - g(gp)        ; ...
        add   s3, s3, t1                ; s3 = ray y
        ld    t5, g_px - g(gp)          ; t5, t6 = where we stand
        ld    t6, g_py - g(gp)          ; ...
        srli  s4, t5, 16                ; s4, s5 = our cell
        srli  s5, t6, 16                ; ...
        li    t4, 1                     ; t4 = 2^32
        slli  t4, t4, 32                ; ...
        li    t3, 0xffff                ; t3 = the fraction's mask
        li    s6, 0x40000000            ; a ray along y never crosses an x line:
        mv    s8, s6                    ;   s6 = distance between x lines, s8 = to the next
        li    s10, 1                    ; s10 = the step in x
        beqz  s2, rc_y                  ; ...
        mv    t1, s2                    ; |ray x|
        bgez  t1, rc_ax                 ; ...
        neg   t1, t1                    ; ...
rc_ax:  divu  s6, t4, t1                ; 1 / |ray x|
        and   t2, t5, t3                ; how far into the cell we are
        bltz  s2, rc_nx                 ; going west: that far to the line
        xor   t2, t2, t3                ; going east: the rest of the cell
        addi  t2, t2, 1                 ; (65536 - the fraction)
        j     rc_sx                     ; ...
rc_nx:  li    s10, -1                   ; ...
rc_sx:  mul   s8, t2, s6                ; the distance to the first x line
        srli  s8, s8, 16                ; ...
rc_y:   li    s7, 0x40000000            ; the same for y: s7 between lines, s9 to the next
        mv    s9, s7                    ; ...
        li    s11, 1                    ; s11 = the step in y
        beqz  s3, rc_go                 ; ...
        mv    t1, s3                    ; |ray y|
        bgez  t1, rc_ay                 ; ...
        neg   t1, t1                    ; ...
rc_ay:  divu  s7, t4, t1                ; 1 / |ray y|
        and   t2, t6, t3                ; ...
        bltz  s3, rc_ny                 ; ...
        xor   t2, t2, t3                ; ...
        addi  t2, t2, 1                 ; ...
        j     rc_sy                     ; ...
rc_ny:  li    s11, -1                   ; ...
rc_sy:  mul   s9, t2, s7                ; ...
        srli  s9, s9, 16                ; ...
rc_go:  la    a4, res + R_MAP           ; a4 = the level
rc_dda: bltu  s9, s8, rc_dy             ; the nearer line: x ...
        add   s8, s8, s6                ; ...
        add   s4, s4, s10               ; into the next cell
        li    a6, 0                     ; a6 = the side hit: 0 an x line
        j     rc_cell                   ; ...
rc_dy:  add   s9, s9, s7                ; ... or y
        add   s5, s5, s11               ; ...
        li    a6, 1                     ; 1 a y line
rc_cell:
        slli  t0, s5, 5                 ; the cell: 32 to a row
        add   t0, t0, s4                ; ...
        add   t0, t0, a4                ; ...
        lbu   a7, 0(t0)                 ; a7 = what is in it
        beqz  a7, rc_dda                ; nothing: on
        andi  t0, a7, C_DOOR            ; a door?
        bnez  t0, rc_door               ; ...
        sub   a5, s8, s6                ; a wall: a5 = the distance to the line crossed
        beqz  a6, rc_wx                 ; ...
        sub   a5, s9, s7                ; ...
        mul   t0, a5, s2                ; a y line: where along x
        srai  t0, t0, 16                ; ...
        add   t0, t0, t5                ; ...
        srli  t0, t0, 9                 ; the texture's column, 128 to a cell
        andi  a3, t0, 127               ; a3 = the column
        bgez  s3, rc_tex                ; seen from the other side: mirrored
        xori  a3, a3, 127               ; ...
        j     rc_tex                    ; ...
rc_wx:  mul   t0, a5, s3                ; an x line: where along y
        srai  t0, t0, 16                ; ...
        add   t0, t0, t6                ; ...
        srli  t0, t0, 9                 ; ...
        andi  a3, t0, 127               ; ...
        blez  s2, rc_tex                ; ...
        xori  a3, a3, 127               ; ...
        j     rc_tex                    ; ...

; a door: a plane across the middle of its cell. The ray meets it half a
; line's distance before the cell's far line, if it is inside the cell then;
; the part of the plane the door has slid away from lets the ray through.
rc_door:
        andi  t0, a7, 0x7f              ; the door's record
        slli  t0, t0, 4                 ; ...
        la    t1, doors                 ; ...
        add   t0, t0, t1                ; ...
        lbu   t1, D_FLAGS(t0)           ; which way it stands
        lwu   t4, D_OPEN(t0)            ; t4 = how far it is open, 0 .. 65536
        lbu   a7, D_TEX(t0)             ; its texture
        andi  t1, t1, 1                 ; ...
        bnez  t1, rc_dn                 ; ...
        srli  t0, s6, 1                 ; crossed going east or west: the plane is an
        sub   a5, s8, t0                ;   x line and a half
        sub   t0, s9, s7                ; inside the cell there?
        blt   a5, t0, rc_dda            ; (before the y line it came in by: no)
        bgt   a5, s9, rc_dda            ; (after the y line it leaves by: no)
        mul   t0, a5, s3                ; where along y
        srai  t0, t0, 16                ; ...
        add   t0, t0, t6                ; ...
        li    a6, 0                     ; (lit as an x side)
        j     rc_dt                     ; ...
rc_dn:  srli  t0, s7, 1                 ; crossed going north or south
        sub   a5, s9, t0                ; ...
        sub   t0, s8, s6                ; ...
        blt   a5, t0, rc_dda            ; ...
        bgt   a5, s8, rc_dda            ; ...
        mul   t0, a5, s2                ; ...
        srai  t0, t0, 16                ; ...
        add   t0, t0, t5                ; ...
        li    a6, 1                     ; ...
rc_dt:  and   t0, t0, t3                ; the fraction along the plane
        bltu  t0, t4, rc_dda            ; the open part: through
        sub   t0, t0, t4                ; the door's texture slides with it
        srli  a3, t0, 9                 ; ...

; the hit: a5 = distance, a3 = texture column, a7 = texture, a6 = side
rc_tex: li    t0, 1024                  ; (never nearer than 1/64)
        bge   a5, t0, rc_t1             ; ...
        mv    a5, t0                    ; ...
rc_t1:  slli  t0, s0, 2                 ; the depth, for the sprites
        la    t1, zbuf                  ; ...
        add   t0, t0, t1                ; ...
        sw    a5, 0(t0)                 ; ...
        addi  a7, a7, -1                ; the texture's entry
        slli  a7, a7, 3                 ; ...
        la    t0, res + R_TEX           ; ...
        add   a7, a7, t0                ; ...
        lhu   t0, 4(a7)                 ; its columns repeat
        and   a3, a3, t0                ; ...
        lwu   t0, 0(a7)                 ; the column, in the arena
        slli  a3, a3, 7                 ; ...
        add   t0, t0, a3                ; ...
        ld    t1, g_keepb - g(gp)       ; ...
        add   t0, t0, t1                ; ...
        la    a2, colbuf                ; a2 = the column
        li    t1, 128                   ; ...
        tget  tg8, a2, c0, t0, t1       ; fetch it (the first load from it waits)
        li    t0, PROJ << 16            ; the wall's height in pixels
        divu  a0, t0, a5                ; ...
        srli  a0, a0, 1                 ; a0 = half of it, at least a pixel
        bnez  a0, rc_h1                 ; ...
        li    a0, 1                     ; ...
rc_h1:  li    t0, 64 << 16              ; texels per pixel, 16.16
        divu  a1, t0, a0                ; a1 = the step down the texture
        li    s4, 0                     ; s4 = the place in the texture
        li    t0, HORIZON               ; the first row
        sub   s5, t0, a0                ; s5 = it
        bgez  s5, rc_h2                 ; above the view: start lower in the texture
        neg   t1, s5                    ; ...
        mul   s4, t1, a1                ; ...
        li    s5, 0                     ; ...
        li    a0, HORIZON               ; (the wall fills the column)
rc_h2:  slli  t0, a5, 3                 ; the light: darker with distance (13 / 8 a cell),
        add   t0, t0, a5                ;   and the y sides a step darker
        slli  t1, a5, 2                 ; ...
        add   t0, t0, t1                ; ...
        srli  t0, t0, 19                ; ...
        add   t0, t0, a6                ; ...
        li    t1, NLIGHT - 1            ; ...
        bleu  t0, t1, rc_h3             ; ...
        mv    t0, t1                    ; ...
rc_h3:  slli  t0, t0, 8                 ; a6 = that row of the colour map
        la    a6, res + R_CMAP          ; ...
        add   a6, a6, t0                ; ...
        slli  t0, s5, 5                 ; t2 = the first byte to draw
        add   t2, s1, t0                ; ...
        slli  t3, a0, 1                 ; t3 = rows of wall
rc_w:   srli  t0, s4, 16                ; the texel
        add   t0, t0, a2                ; ...
        lbu   t0, 0(t0)                 ; ...
        add   t0, t0, a6                ; shaded
        lbu   t0, 0(t0)                 ; ...
        sb    t0, 0(t2)                 ; ...
        add   s4, s4, a1                ; down the texture
        addi  t2, t2, SLAB_W            ; down the slab
        addi  t3, t3, -1                ; ...
        bnez  t3, rc_w                  ; ...

; floor and ceiling: row k below the horizon is at distance rowd[k] along the
; view, whatever the column; the ray gives the place on the floor, and the
; ceiling's row above the horizon is its mirror
        li    t0, HORIZON               ; rows left under the wall
        bge   a0, t0, rc_ret            ; none
        la    s6, res + R_ROWD          ; s6 = the row's distance
        slli  t0, a0, 2                 ; ...
        add   s6, s6, t0                ; ...
        la    s7, res + R_ROWL          ; s7 = its light
        add   s7, s7, a0                ; ...
        la    s8, out_buf               ; s8 = the floor's flat
        la    s9, in_buf                ; s9 = the ceiling's
        la    s10, res + R_CMAP         ; s10 = the colour map
        li    t0, HORIZON - 1           ; s5 = the ceiling's byte
        sub   t0, t0, a0                ; ...
        slli  t0, t0, 5                 ; ...
        add   s5, s1, t0                ; ...
        li    s11, HORIZON              ; s11 = rows to do
        sub   s11, s11, a0              ; ...
rc_f:   lwu   t0, 0(s6)                 ; the distance
        mul   t1, t0, s2                ; the place: x ...
        srai  t1, t1, 16                ; ...
        add   t1, t1, t5                ; ...
        mul   t0, t0, s3                ; ... and y
        srai  t0, t0, 16                ; ...
        add   t0, t0, t6                ; ...
        srli  t1, t1, 9                 ; the texel: 64 x 64, twice across a cell
        andi  t1, t1, 63                ; ...
        srli  t0, t0, 3                 ; ...
        andi  t0, t0, 0xfc0             ; ...
        or    t1, t1, t0                ; ...
        lbu   t3, 0(s7)                 ; the row's light
        slli  t3, t3, 8                 ; ...
        add   t3, t3, s10               ; ...
        add   t0, s8, t1                ; the floor
        lbu   t0, 0(t0)                 ; ...
        add   t0, t0, t3                ; ...
        lbu   t0, 0(t0)                 ; ...
        sb    t0, 0(t2)                 ; ...
        add   t0, s9, t1                ; the ceiling
        lbu   t0, 0(t0)                 ; ...
        add   t0, t0, t3                ; ...
        lbu   t0, 0(t0)                 ; ...
        sb    t0, 0(s5)                 ; ...
        addi  s6, s6, 4                 ; the next row out
        addi  s7, s7, 1                 ; ...
        addi  t2, t2, SLAB_W            ; ...
        addi  s5, s5, -SLAB_W           ; ...
        addi  s11, s11, -1              ; ...
        bnez  s11, rc_f                 ; ...
rc_ret: ld    s0, 0(sp)                 ; the column
        ld    s1, 8(sp)                 ; ...
        addi  sp, sp, 16                ; pop the frame
        ret                             ; done

; r_project(): the things in view, as scaled rectangles on the screen, far
; to near (vis, visord, g_nvis)
r_project:
        addi  sp, sp, -32               ; frame
        sd    s0, 0(sp)                 ; s0 = thing
        sd    s1, 8(sp)                 ; s1 = things left
        sd    s2, 16(sp)                ; s2 = the next vis entry
        sd    s3, 24(sp)                ; s3 = entries so far
        la    s0, things                ; ...
        li    s1, MAXTHINGS             ; ...
        la    s2, vis                   ; ...
        li    s3, 0                     ; ...
rp_l:   lbu   t0, T_KIND(s0)            ; a thing?
        beqz  t0, rp_n                  ; ...
        lw    a0, T_X(s0)               ; where it is from us
        ld    t1, g_px - g(gp)          ; ...
        sub   a0, a0, t1                ; a0 = x
        lw    a1, T_Y(s0)               ; ...
        ld    t1, g_py - g(gp)          ; ...
        sub   a1, a1, t1                ; a1 = y
        ld    t1, g_dirx - g(gp)        ; along the view: the depth
        mul   t1, t1, a0                ; ...
        ld    t2, g_diry - g(gp)        ; ...
        mul   t2, t2, a1                ; ...
        add   t1, t1, t2                ; ...
        srai  a2, t1, 16                ; a2 = depth
        li    t1, 0x2000                ; behind us, or in our face: not drawn
        blt   a2, t1, rp_n              ; ...
        ld    t1, g_plx - g(gp)         ; across the view
        mul   t1, t1, a0                ; ...
        ld    t2, g_ply - g(gp)         ; ...
        mul   t2, t2, a1                ; ...
        add   t1, t1, t2                ; ...
        srai  t1, t1, 16                ; t1 = across
        li    t2, PROJ                  ; its column: 160 + 160 * across / depth
        mul   t1, t1, t2                ; ...
        div   t1, t1, a2                ; ...
        addi  a3, t1, VIEW_W / 2        ; a3 = the column of its origin
        li    t1, 81920 << 16           ; pixels per texel: 160 / 128 / depth
        divu  a4, t1, a2                ; a4 = the scale, 16.16
        lhu   t0, T_SPR(s0)             ; its sprite
        slli  t0, t0, 4                 ; ...
        la    t1, res + R_SPR           ; ...
        add   a5, t0, t1                ; a5 = the directory entry
        lh    t0, SD_OX(a5)             ; the left edge
        mul   t0, t0, a4                ; ...
        srai  t0, t0, 16                ; ...
        sub   t0, a3, t0                ; t0 = x1
        lhu   t1, SD_W(a5)              ; the right edge
        mul   t1, t1, a4                ; ...
        srai  t1, t1, 16                ; ...
        add   t1, t0, t1                ; t1 = x2
        blez  t1, rp_n                  ; off the screen
        li    t2, VIEW_W                ; ...
        bge   t0, t2, rp_n              ; ...
        beq   t0, t1, rp_n              ; (too far to have a column)
        sw    t0, V_X1(s2)              ; ...
        sw    t1, V_X2(s2)              ; ...
        li    t0, (PROJ / 2) << 16      ; the floor under it: 84 + 80 / depth
        divu  t0, t0, a2                ; ...
        addi  t0, t0, HORIZON           ; ...
        lbu   t1, T_KIND(s0)            ; a fireball flies at the height of the eye
        li    t2, K_BALL                ; ...
        blt   t1, t2, rp_y              ; ...
        li    t2, 28                    ; (so its origin is 28 texels under the horizon)
        mul   t2, t2, a4                ; ...
        srai  t2, t2, 16                ; ...
        addi  t0, t2, HORIZON           ; ...
rp_y:   lh    t1, SD_OY(a5)             ; the top edge
        mul   t1, t1, a4                ; ...
        srai  t1, t1, 16                ; ...
        sub   t0, t0, t1                ; t0 = y1
        lhu   t1, SD_H(a5)              ; the bottom edge
        mul   t1, t1, a4                ; ...
        srai  t1, t1, 16                ; ...
        add   t1, t0, t1                ; t1 = y2
        sw    t0, V_Y1(s2)              ; ...
        sw    t1, V_Y2(s2)              ; ...
        sw    a2, V_DEPTH(s2)           ; ...
        li    t0, 52429                 ; texels per pixel: depth * 128 / 160
        mul   t0, t0, a2                ; ...
        srli  t0, t0, 16                ; ...
        sw    t0, V_INV(s2)             ; ...
        sd    a5, V_SPR(s2)             ; ...
        sd    s0, V_TH(s2)              ; ...
        slli  t0, a2, 3                 ; its light, as a wall's; a fireball is bright
        add   t0, t0, a2                ; ...
        slli  t1, a2, 2                 ; ...
        add   t0, t0, t1                ; ...
        srli  t0, t0, 19                ; ...
        li    t1, NLIGHT - 1            ; ...
        bleu  t0, t1, rp_l1             ; ...
        mv    t0, t1                    ; ...
rp_l1:  lbu   t1, T_KIND(s0)            ; ...
        li    t2, K_BALL                ; ...
        blt   t1, t2, rp_l2             ; ...
        li    t0, 0                     ; ...
rp_l2:  slli  t0, t0, 8                 ; ...
        la    t1, res + R_CMAP          ; ...
        add   t0, t0, t1                ; ...
        sd    t0, V_LP(s2)              ; ...
        slli  t0, s3, 3                 ; into the order: before every nearer one
        la    t1, visord                ; ...
        add   t0, t0, t1                ; t0 = the place after the last
rp_s:   beq   t0, t1, rp_put            ; ...
        ld    t2, -8(t0)                ; the one before
        lw    t3, V_DEPTH(t2)           ; farther or as far: stay behind it
        bge   t3, a2, rp_put            ; ...
        sd    t2, 0(t0)                 ; nearer: it moves up
        addi  t0, t0, -8                ; ...
        j     rp_s                      ; ...
rp_put: sd    s2, 0(t0)                 ; ...
        addi  s2, s2, V_SIZE            ; ...
        addi  s3, s3, 1                 ; ...
        li    t0, MAXVIS                ; (no more than fit)
        beq   s3, t0, rp_d              ; ...
rp_n:   addi  s0, s0, T_SIZE            ; the next thing
        addi  s1, s1, -1                ; ...
        bnez  s1, rp_l                  ; ...
rp_d:   sd    s3, g_nvis - g(gp)        ; ...
        ld    s0, 0(sp)                 ; restore
        ld    s1, 8(sp)                 ; ...
        ld    s2, 16(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

; r_sprites(): the visible things' columns that fall into the slab
; (g_sx0 .. g_sx0 + 31), far to near, behind the walls
r_sprites:
        addi  sp, sp, -56               ; frame
        sd    s0, 0(sp)                 ; s0 = place in the order
        sd    s1, 8(sp)                 ; s1 = things left
        sd    s2, 16(sp)                ; s2 = the entry
        sd    s3, 24(sp)                ; s3 = column
        sd    s4, 32(sp)                ; s4 = past the last column
        sd    s5, 40(sp)                ; s5 = the texture column in colbuf
        sd    s6, 48(sp)                ; s6 = the slab's first column
        la    s0, visord                ; ...
        ld    s1, g_nvis - g(gp)        ; ...
        ld    s6, g_sx0 - g(gp)         ; ...
rs_l:   beqz  s1, rs_d                  ; ...
        ld    s2, 0(s0)                 ; ...
        lw    s3, V_X1(s2)              ; its columns, clipped to the slab
        bge   s3, s6, rs_1              ; ...
        mv    s3, s6                    ; ...
rs_1:   lw    s4, V_X2(s2)              ; ...
        addi  t0, s6, SLAB_W            ; ...
        ble   s4, t0, rs_2              ; ...
        mv    s4, t0                    ; ...
rs_2:   li    s5, -1                    ; (no column fetched yet)
rs_c:   bge   s3, s4, rs_n              ; ...
        slli  t0, s3, 2                 ; behind the wall here?
        la    t1, zbuf                  ; ...
        add   t0, t0, t1                ; ...
        lwu   t0, 0(t0)                 ; ...
        lw    t1, V_DEPTH(s2)           ; ...
        bge   t1, t0, rs_cn             ; yes
        lw    t0, V_X1(s2)              ; the sprite's column for this one
        sub   t0, s3, t0                ; ...
        lwu   a3, V_INV(s2)             ; a3 = texels per pixel
        mul   t0, t0, a3                ; ...
        srli  t0, t0, 16                ; ...
        ld    a4, V_SPR(s2)             ; a4 = the sprite
        lhu   t1, SD_W(a4)              ; (inside it)
        bltu  t0, t1, rs_3              ; ...
        addi  t0, t1, -1                ; ...
rs_3:   beq   t0, s5, rs_4              ; already in colbuf
        mv    s5, t0                    ; fetch it
        lhu   t1, SD_CS(a4)             ; ...
        mul   t0, t0, t1                ; ...
        lwu   t2, SD_OFF(a4)            ; ...
        add   t0, t0, t2                ; ...
        ld    t2, g_keepb - g(gp)       ; ...
        add   t0, t0, t2                ; ...
        la    t2, colbuf                ; ...
        tget  tg8, t2, c0, t0, t1       ; ...
rs_4:   lw    t0, V_Y1(s2)              ; its rows, clipped to the view
        li    t3, 0                     ; t3 = the place in the sprite's column, 16.16
        bgez  t0, rs_5                  ; ...
        neg   t3, t0                    ; ...
        mul   t3, t3, a3                ; ...
        li    t0, 0                     ; ...
rs_5:   lw    t1, V_Y2(s2)              ; ...
        li    t2, VIEW_H                ; ...
        ble   t1, t2, rs_6              ; ...
        mv    t1, t2                    ; ...
rs_6:   sub   t1, t1, t0                ; t1 = rows
        blez  t1, rs_cn                 ; ...
        slli  t0, t0, 5                 ; t0 = the byte in the slab
        la    t2, slab                  ; ...
        add   t0, t0, t2                ; ...
        add   t0, t0, s3                ; ...
        sub   t0, t0, s6                ; ...
        lhu   a5, SD_H(a4)              ; a5 = the sprite's rows
        ld    a6, V_LP(s2)              ; a6 = its light
        la    a7, colbuf                ; a7 = the column
        li    t5, 255                   ; t5 = "transparent"
rs_y:   srli  t2, t3, 16                ; the texel
        bgeu  t2, a5, rs_cn             ; (past the sprite's end)
        add   t2, t2, a7                ; ...
        lbu   t2, 0(t2)                 ; ...
        beq   t2, t5, rs_yn             ; ...
        add   t2, t2, a6                ; shaded
        lbu   t2, 0(t2)                 ; ...
        sb    t2, 0(t0)                 ; ...
rs_yn:  add   t3, t3, a3                ; ...
        addi  t0, t0, SLAB_W            ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, rs_y                  ; ...
rs_cn:  addi  s3, s3, 1                 ; the next column
        j     rs_c                      ; ...
rs_n:   addi  s0, s0, 8                 ; the next thing
        addi  s1, s1, -1                ; ...
        j     rs_l                      ; ...
rs_d:   ld    s0, 0(sp)                 ; restore
        ld    s1, 8(sp)                 ; ...
        ld    s2, 16(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        ld    s5, 40(sp)                ; ...
        ld    s6, 48(sp)                ; ...
        addi  sp, sp, 56                ; pop the frame
        ret                             ; done

; r_blit(a0 = sprite, a1 = x, a2 = y of its top left corner on the 320 x 200
; screen): the part of it in the slab and in the pass's rows (g_py0, g_ph),
; unscaled and unshaded
r_blit: slli  a0, a0, 4                 ; the sprite
        la    t0, res + R_SPR           ; ...
        add   a0, a0, t0                ; a0 = its entry
        ld    a3, g_sx0 - g(gp)         ; a3 = the slab's first column
        mv    a4, a1                    ; a4 = column, from the later of the two starts
        bge   a4, a3, rb_1              ; ...
        mv    a4, a3                    ; ...
rb_1:   lhu   a5, SD_W(a0)              ; a5 = past the last column: the earlier end
        add   a5, a5, a1                ; ...
        addi  t0, a3, SLAB_W            ; ...
        ble   a5, t0, rb_2              ; ...
        mv    a5, t0                    ; ...
rb_2:   ld    t4, g_py0 - g(gp)         ; t4 = the pass's first row
        mv    a6, a2                    ; a6 = the first row drawn
        bge   a6, t4, rb_3              ; ...
        mv    a6, t4                    ; ...
rb_3:   lhu   a7, SD_H(a0)              ; a7 = rows drawn: to the earlier end
        add   a7, a7, a2                ; ...
        ld    t0, g_ph - g(gp)          ; ...
        add   t0, t0, t4                ; ...
        ble   a7, t0, rb_4              ; ...
        mv    a7, t0                    ; ...
rb_4:   sub   a7, a7, a6                ; ...
        blez  a7, rb_r                  ; none
        li    t5, 255                   ; t5 = "transparent"
rb_c:   bge   a4, a5, rb_r              ; ...
        sub   t0, a4, a1                ; fetch the column
        lhu   t1, SD_CS(a0)             ; ...
        mul   t0, t0, t1                ; ...
        lwu   t2, SD_OFF(a0)            ; ...
        add   t0, t0, t2                ; ...
        ld    t2, g_keepb - g(gp)       ; ...
        add   t0, t0, t2                ; ...
        la    t2, colbuf                ; ...
        tget  tg8, t2, c0, t0, t1       ; ...
        sub   t0, a6, a2                ; t2 = the first texel
        add   t2, t2, t0                ; ...
        sub   t0, a6, t4                ; t0 = the byte in the slab
        slli  t0, t0, 5                 ; ...
        la    t1, slab                  ; ...
        add   t0, t0, t1                ; ...
        add   t0, t0, a4                ; ...
        sub   t0, t0, a3                ; ...
        mv    t1, a7                    ; t1 = rows
rb_y:   lbu   t3, 0(t2)                 ; ...
        beq   t3, t5, rb_yn             ; ...
        sb    t3, 0(t0)                 ; ...
rb_yn:  addi  t2, t2, 1                 ; ...
        addi  t0, t0, SLAB_W            ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, rb_y                  ; ...
        addi  a4, a4, 1                 ; the next column
        j     rb_c                      ; ...
rb_r:   ret                             ; done

; r_num(a0 = number 0..999, a1 = x of its right edge, a2 = y): in the bar's
; digits, 14 pixels each
r_num:  addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = what is left of the number
        sd    s1, 16(sp)                ; s1 = x
        sd    s2, 24(sp)                ; s2 = y
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        mv    s2, a2                    ; ...
rn_l:   addi  s1, s1, -14               ; a digit to the left
        li    t0, 10                    ; ...
        remu  a0, s0, t0                ; ...
        divu  s0, s0, t0                ; ...
        addi  a0, a0, SP_NUM0           ; ...
        mv    a1, s1                    ; ...
        mv    a2, s2                    ; ...
        call  r_blit                    ; ...
        bnez  s0, rn_l                  ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

; r_over(): what lies over the view: the weapon, the message, the figures
r_over: addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        ld    t0, g_state - g(gp)       ; no weapon in a dead hand
        li    t1, ST_DEAD               ; ...
        beq   t0, t1, ro_msg            ; ...
        ld    t0, g_wst - g(gp)         ; the weapon's frame: ready ...
        li    a0, SP_GUN0               ; ...
        li    a1, 135                   ; (where Freedoom's offsets put it)
        li    a2, 116                   ; ...
        beqz  t0, ro_gun                ; ...
        li    a0, SP_GUN2               ; ... back from the recoil ...
        li    a2, 108                   ; ...
        li    a1, 134                   ; ...
        addi  t1, t0, -(W_FIRE - 5)     ; ...
        blez  t1, ro_g1                 ; ...
        j     ro_g2                     ; ... or kicked up by the shot
ro_g1:  addi  t1, t0, -5                ; ...
        bgtz  t1, ro_gun                ; ...
ro_g2:  li    a0, SP_GUN1               ; ...
ro_gun: call  r_blit                    ; ...
        ld    t0, g_wst - g(gp)         ; the flash, for the shot's first tics
        addi  t0, t0, -(W_FIRE - 3)     ; ...
        blez  t0, ro_msg                ; ...
        li    a0, SP_FLASH              ; ...
        li    a1, 145                   ; ...
        li    a2, 95                    ; ...
        call  r_blit                    ; ...
ro_msg: ld    a0, g_msg - g(gp)         ; the message
        bltz  a0, ro_win                ; ...
        li    a1, 2                     ; ...
        li    a2, 2                     ; ...
        call  r_blit                    ; ...
ro_win: ld    t0, g_state - g(gp)       ; the level is done: the kills, in per cent
        li    t1, ST_WON                ; ...
        bne   t0, t1, ro_r              ; ...
        li    a0, SP_M_KILLS            ; ...
        li    a1, 110                   ; ...
        li    a2, 64                    ; ...
        call  r_blit                    ; ...
        ld    a0, g_kills - g(gp)       ; ...
        li    t0, 100                   ; ...
        mul   a0, a0, t0                ; ...
        ld    t0, g_nmon - g(gp)        ; ...
        divu  a0, a0, t0                ; ...
        li    a1, 200                   ; ...
        li    a2, 60                    ; ...
        call  r_num                     ; ...
        li    a0, SP_PCT                ; ...
        li    a1, 200                   ; ...
        li    a2, 60                    ; ...
        call  r_blit                    ; ...
ro_r:   ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; r_push(a0 = the slab's number in its group): the pass's rows as pixels,
; g_scale times as wide and as high, into the band (rows g_stride apart)
r_push: addi  sp, sp, -8                ; frame
        sd    s0, 0(sp)                 ; s0 = rows left
        ld    a1, g_scale - g(gp)       ; a1 = the factor
        slli  a2, a1, 7                 ; a2 = bytes of a row of the slab on the screen
        mul   a0, a0, a2                ; a0 = where the row starts in the band
        ld    a3, g_stride - g(gp)      ; a3 = the band's stride
        la    a4, slab                  ; a4 = the row
        la    a5, res + R_PAL           ; a5 = the palette
        ld    s0, g_ph - g(gp)          ; ...
        la    a7, rowbuf                ; a7 = the row as pixels
rq_r:   mv    t0, a7                    ; t0 = the next pixel
        addi  t1, a4, SLAB_W            ; t1 = the row's end
rq_p:   lbu   t2, 0(a4)                 ; an index ...
        slli  t2, t2, 2                 ; ...
        add   t2, t2, a5                ; ...
        lwu   t2, 0(t2)                 ; ... its colour ...
        mv    t3, a1                    ; ... as many times as the factor
rq_s:   sw    t2, 0(t0)                 ; ...
        addi  t0, t0, 4                 ; ...
        addi  t3, t3, -1                ; ...
        bnez  t3, rq_s                  ; ...
        addi  a4, a4, 1                 ; ...
        bne   a4, t1, rq_p              ; ...
        mv    t3, a1                    ; the row, as many times as the factor
rq_t:   tput  tg9, a7, c0, a0, a2       ; (the next row's stores wait for it)
        add   a0, a0, a3                ; ...
        addi  t3, t3, -1                ; ...
        bnez  t3, rq_t                  ; ...
        addi  s0, s0, -1                ; ...
        bnez  s0, rq_r                  ; ...
        ld    s0, 0(sp)                 ; restore
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; r_damage(a0 = first slab, a1 = slabs, a2 = first row on the 320 x 200
; screen, a3 = rows): lend the band: those slabs' pixels are in it
r_damage:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        twait (1 << 8) | (1 << 9)       ; our transfers are done
        ld    t1, g_scale - g(gp)       ; the rectangle in the window
        la    t0, wc_d                  ; data: x, y, w, h, stride
        slli  a0, a0, 5                 ; x
        mul   a0, a0, t1                ; ...
        ld    t2, g_ox - g(gp)          ; ...
        add   a0, a0, t2                ; ...
        sd    a0, 0(t0)                 ; ...
        mul   a2, a2, t1                ; y
        ld    t2, g_oy - g(gp)          ; ...
        add   a2, a2, t2                ; ...
        sd    a2, 8(t0)                 ; ...
        slli  a1, a1, 5                 ; w
        mul   a1, a1, t1                ; ...
        sd    a1, 16(t0)                ; ...
        mul   a3, a3, t1                ; h
        sd    a3, 24(t0)                ; ...
        ld    t2, g_stride - g(gp)      ; ...
        sd    t2, 32(t0)                ; ...
        mv    a0, t0                    ; ...
        li    a1, 40                    ; ...
        call  sys_put                   ; ...
        li    a0, WC_EP                 ; DAMAGE, with the arena (c0) attached
        li    a1, OP_WDAMAGE            ; ...
        la    t0, wc_id                 ; ...
        ld    a2, 0(t0)                 ; ...
        li    a3, 40                    ; ...
        li    a4, 0                     ; ...
        li    a5, 0                     ; (register 0)
        call  sys_msga                  ; a0 = result; the arena is back in c6
        cvalid t0, c6                   ; ...
        beqz  t0, rd_r                  ; (nothing was sent)
        cmov  c0, c6                    ; home
rd_r:   ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; r_frame(): the whole view, in groups of as many slabs as the band holds
; (g_grp), each group lent to the server as it is done; then the bar if it
; changed
r_frame:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = column
        sd    s1, 16(sp)                ; s1 = its byte in the slab
        sd    s2, 24(sp)                ; s2 = the group's first slab
        sd    s3, 32(sp)                ; s3 = slabs in the group
        sd    s4, 40(sp)                ; s4 = the slab in the group
        ld    t0, g_scale - g(gp)       ; (a window too small for it: nothing)
        beqz  t0, rf_r                  ; ...
        call  r_view                    ; ...
        call  r_project                 ; ...
        sd    zero, g_py0 - g(gp)       ; the pass: the view's rows
        li    t0, VIEW_H                ; ...
        sd    t0, g_ph - g(gp)          ; ...
        li    s2, 0                     ; ...
rf_g:   li    s3, NSLAB                 ; the group: what is left, at most g_grp
        sub   s3, s3, s2                ; ...
        ld    t0, g_grp - g(gp)         ; ...
        ble   s3, t0, rf_g1             ; ...
        mv    s3, t0                    ; ...
rf_g1:  ld    t0, g_scale - g(gp)       ; its stride in the band
        mul   t0, t0, s3                ; ...
        slli  t0, t0, 7                 ; ...
        sd    t0, g_stride - g(gp)      ; ...
        li    s4, 0                     ; ...
rf_s:   add   s0, s2, s4                ; the slab's columns
        slli  s0, s0, 5                 ; ...
        sd    s0, g_sx0 - g(gp)         ; ...
        la    s1, slab                  ; ...
        addi  sp, sp, -24               ; (r_col keeps s0 and s1 only)
        sd    s2, 0(sp)                 ; ...
        sd    s3, 8(sp)                 ; ...
        sd    s4, 16(sp)                ; ...
rf_c:   call  r_col                     ; ...
        addi  s0, s0, 1                 ; ...
        addi  s1, s1, 1                 ; ...
        andi  t0, s0, SLAB_W - 1        ; ...
        bnez  t0, rf_c                  ; ...
        ld    s2, 0(sp)                 ; ...
        ld    s3, 8(sp)                 ; ...
        ld    s4, 16(sp)                ; ...
        addi  sp, sp, 24                ; ...
        call  r_sprites                 ; ...
        call  r_over                    ; ...
        mv    a0, s4                    ; ...
        call  r_push                    ; ...
        addi  s4, s4, 1                 ; ...
        bne   s4, s3, rf_s              ; ...
        mv    a0, s2                    ; the group is drawn: show it
        mv    a1, s3                    ; ...
        li    a2, 0                     ; ...
        li    a3, VIEW_H                ; ...
        call  r_damage                  ; ...
        add   s2, s2, s3                ; ...
        li    t0, NSLAB                 ; ...
        blt   s2, t0, rf_g              ; ...
        ld    t0, g_bardirty - g(gp)    ; the bar?
        beqz  t0, rf_r                  ; ...
        sd    zero, g_bardirty - g(gp)  ; ...
        call  r_bar                     ; ...
rf_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        addi  sp, sp, 48                ; pop the frame
        ret                             ; done

; r_bar(): the status bar: its picture (ten pieces, one per slab), then the
; ammunition, the health, the face and the key over it; one group
r_bar:  addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = slab
        li    t0, VIEW_H                ; the pass: the bar's rows
        sd    t0, g_py0 - g(gp)         ; ...
        li    t0, BAR_H                 ; ...
        sd    t0, g_ph - g(gp)          ; ...
        ld    t0, g_scale - g(gp)       ; all ten slabs in the band
        li    t1, NSLAB * SLAB_W * 4    ; ...
        mul   t0, t0, t1                ; ...
        sd    t0, g_stride - g(gp)      ; ...
        li    s0, 0                     ; ...
rr_s:   slli  t0, s0, 5                 ; ...
        sd    t0, g_sx0 - g(gp)         ; ...
        slli  t0, s0, 10                ; the piece: 1024 bytes
        li    t1, F_BAR                 ; ...
        add   t0, t0, t1                ; ...
        ld    t1, g_keepb - g(gp)       ; ...
        add   t0, t0, t1                ; ...
        la    t1, slab                  ; ...
        li    t2, 1024                  ; ...
        tget  tg8, t1, c0, t0, t2       ; ...
        ld    a0, g_ammo - g(gp)        ; the ammunition
        li    a1, 44                    ; ...
        li    a2, 171                   ; ...
        call  r_num                     ; ...
        ld    a0, g_health - g(gp)      ; the health, in per cent
        li    a1, 90                    ; ...
        li    a2, 171                   ; ...
        call  r_num                     ; ...
        li    a0, SP_PCT                ; ...
        li    a1, 90                    ; ...
        li    a2, 171                   ; ...
        call  r_blit                    ; ...
        li    a0, 0                     ; no armour here
        li    a1, 221                   ; ...
        li    a2, 171                   ; ...
        call  r_num                     ; ...
        li    a0, SP_PCT                ; ...
        li    a1, 221                   ; ...
        li    a2, 171                   ; ...
        call  r_blit                    ; ...
        ld    t0, g_health - g(gp)      ; the face: bloodier in steps of 20
        li    a0, SP_FACEX              ; (dead)
        beqz  t0, rr_f                  ; ...
        li    t1, 99                    ; ...
        ble   t0, t1, rr_f1             ; ...
        mv    t0, t1                    ; ...
rr_f1:  li    t1, 20                    ; ...
        divu  t0, t0, t1                ; ...
        li    a0, SP_FACE0 + 4          ; ...
        sub   a0, a0, t0                ; ...
rr_f:   li    a1, 148                   ; ...
        li    a2, 169                   ; ...
        call  r_blit                    ; ...
        ld    t0, g_key - g(gp)         ; the key, once it is ours
        beqz  t0, rr_p                  ; ...
        li    a0, SP_KEYICON            ; ...
        li    a1, 239                   ; ...
        li    a2, 171                   ; ...
        call  r_blit                    ; ...
rr_p:   mv    a0, s0                    ; ...
        call  r_push                    ; ...
        addi  s0, s0, 1                 ; ...
        li    t0, NSLAB                 ; ...
        blt   s0, t0, rr_s              ; ...
        li    a0, 0                     ; ...
        li    a1, NSLAB                 ; ...
        li    a2, VIEW_H                ; ...
        li    a3, BAR_H                 ; ...
        call  r_damage                  ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 16                ; pop the frame
        ret                             ; done
