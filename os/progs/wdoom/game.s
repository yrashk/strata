; =============================================================================
; game.s: wdoom's world: the player, doors, monsters, missiles and pickups
; =============================================================================
;
; Time is counted in tics of 1/35 s (g_tic); everything here advances one
; tic per call of g_step. The level is a 32 x 32 grid of cells (dat.s:
; R_MAP): 0 is floor, 1..15 a wall with that texture, 0x80 | n door n.
; Positions are 16.16 with a cell as the unit; there is no height.

TIC_US    = 28571                       ; a tic in the clock's ticks (microseconds)
ST_PLAY   = 0                           ; g_state: playing
ST_DEAD   = 1                           ; dead: Space starts the level again
ST_WON    = 2                           ; the exit switch was thrown
C_DOOR    = 0x80                        ; a door cell: 0x80 | its number

; ---- things ---------------------------------------------------------------------
K_ZOMBIE  = 1                           ; kinds: a zombie (shoots)
K_IMP     = 2                           ; an imp (throws fireballs)
K_DEMON   = 3                           ; a demon (bites)
K_CLIP    = 4                           ; a clip
K_STIM    = 5                           ; a stimpack
K_MEDI    = 6                           ; a medikit
K_KEY     = 7                           ; the blue key
K_BALL    = 8                           ; a fireball in flight
K_BOOM    = 9                           ; ... and bursting
T_X       = 0                           ; position (u32, 16.16)
T_Y       = 4                           ; ...
T_KIND    = 8                           ; kind (0: free)
T_ST      = 9                           ; a monster's state (M_*)
T_TIC     = 10                          ; tics in that state, or left of it (u16)
T_HP      = 12                          ; health; a clip's rounds (s16)
T_SPR     = 14                          ; the sprite drawn for it (u16)
T_VX      = 16                          ; a fireball's velocity (s32, 16.16 a tic)
T_VY      = 20                          ; ...
T_CD      = 24                          ; tics until a monster may attack again (s16)
T_SIZE    = 32                          ; bytes
M_IDLE    = 0                           ; has not seen the player
M_CHASE   = 1                           ; walks towards the player
M_ATK     = 2                           ; attacks
M_PAIN    = 3                           ; flinches
M_DYING   = 4                           ; falls
M_DEAD    = 5                           ; lies there

; ---- a kind of monster (mt) -------------------------------------------------------
MT_SPEED  = 0                           ; cells a tic, 16.16 (u16)
MT_HP     = 2                           ; health
MT_SPR    = 4                           ; first sprite: 4 walk, attack, pain, death frames
MT_NATK   = 6                           ; attack frames
MT_NDIE   = 7                           ; death frames
MT_ATK    = 8                           ; 0 shoots, 1 throws, 2 bites
MT_PAIN   = 9                           ; chance of flinching when hurt, of 256
MT_DMG    = 10                          ; damage: this ...
MT_DMASK  = 11                          ; ... plus random bits under this mask
MT_SDIE   = 12                          ; the sound of its death
MT_SATK   = 13                          ; ... and of its attack
MT_SIZE   = 16                          ; bytes

; ---- doors ---------------------------------------------------------------------
D_CELL    = 0                           ; its cell: y * 32 + x (u16)
D_TEX     = 2                           ; texture
D_FLAGS   = 3                           ; bit 0: crossed going north or south; 1: needs the key
D_STATE   = 4                           ; 0 shut, 1 opening, 2 open, 3 shutting
D_TIMER   = 6                           ; tics left open (u16)
D_OPEN    = 8                           ; how far open: 0 .. 65536 (u32)
D_SIZE    = 16                          ; bytes
D_STEP    = 3072                        ; opened by this much a tic (0.6 s in all)
D_WAIT    = 140                         ; tics it stays open (4 s)

; ---- the player -----------------------------------------------------------------
P_RADIUS  = 14418                       ; 0.22 of a cell
P_ACC     = 560                         ; forward thrust a tic
P_SIDE    = 460                         ; sideways thrust
P_TURN    = 22                          ; angle units a tic (135 degrees a second)
W_FIRE    = 15                          ; tics a shot takes
H_FWD     = 0                           ; g_hold: forward until that tic
H_BACK    = 8                           ; back
H_LEFT    = 16                          ; step left
H_RIGHT   = 24                          ; step right
H_TL      = 32                          ; turn left
H_TR      = 40                          ; turn right

        .data                           ; D-LS
        .align 8                        ; dwords
things:   .space MAXTHINGS * T_SIZE     ; the things
doors:    .space MAXDOORS * D_SIZE      ; the doors
mt:                                     ; the monsters: zombie, imp, demon
        .half 1300, 20, SP_Z            ; speed, health, sprites
        .byte NZ_ATK, NZ_DIE, 0, 200    ; attack and death frames, shoots, flinches
        .byte 3, 7, SN_ZDIE, SN_PISTOL  ; damage 3..10, its sounds
        .half 0                         ; ...
        .half 1300, 60, SP_I            ; ...
        .byte NI_ATK, NI_DIE, 1, 180    ; throws (the fireball does the damage)
        .byte 0, 0, SN_IDIE, SN_FIRE    ; ...
        .half 0                         ; ...
        .half 2700, 150, SP_D           ; ...
        .byte ND_ATK, ND_DIE, 2, 160    ; bites
        .byte 6, 15, SN_DDIE, SN_BITE   ; damage 6..21
        .half 0                         ; ...
item_spr:                               ; the sprites of kinds 4..9
        .byte SP_CLIP, SP_STIM, SP_MEDI ; ...
        .byte SP_KEY, SP_BALL0, SP_BOOM ; ...
        .align 8                        ; ...
        .text                           ; code

; rnd() -> a0 = 0 .. 32767. Clobbers t0.
rnd:    ld    a0, g_seed - g(gp)        ; the usual linear congruence
        li    t0, 1103515245            ; ...
        mul   a0, a0, t0                ; ...
        addi  a0, a0, 12345             ; ...
        sd    a0, g_seed - g(gp)        ; ...
        srli  a0, a0, 16                ; ...
        li    t0, 0x7fff                ; ...
        and   a0, a0, t0                ; ...
        ret                             ; done

; cell_at(a0 = x, a1 = y) -> a0 = 1 if nothing can stand there (a wall, a
; door less than three quarters open), a1 = the cell's value, a2 = its door
; record or 0, a3 = the cell's address. Clobbers t0, t1.
cell_at:
        srli  t0, a0, 16                ; the cell
        srli  t1, a1, 16                ; ...
        slli  t1, t1, 5                 ; ...
        add   t0, t0, t1                ; ...
        la    a3, res + R_MAP           ; ...
        add   a3, a3, t0                ; ...
        lbu   a1, 0(a3)                 ; ...
        li    a2, 0                     ; ...
        li    a0, 0                     ; floor
        beqz  a1, ca_r                  ; ...
        li    a0, 1                     ; a wall
        andi  t0, a1, C_DOOR            ; ...
        beqz  t0, ca_r                  ; ...
        andi  t0, a1, 0x7f              ; a door: how far open?
        slli  t0, t0, 4                 ; ...
        la    a2, doors                 ; ...
        add   a2, a2, t0                ; ...
        lwu   t0, D_OPEN(a2)            ; ...
        li    t1, 0xC000                ; ...
        sltu  a0, t0, t1                ; ...
ca_r:   ret                             ; done

; t_spawn(a0 = kind, a1 = x, a2 = y) -> a0 = the new thing, or 0 if there
; is no room. Clobbers t0..t2.
t_spawn:
        la    t0, things                ; a free record
        li    t1, MAXTHINGS             ; ...
ts_l:   lbu   t2, T_KIND(t0)            ; ...
        beqz  t2, ts_f                  ; ...
        addi  t0, t0, T_SIZE            ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, ts_l                  ; ...
        li    a0, 0                     ; none
        ret                             ; ...
ts_f:   sd    zero, 8(t0)               ; clear it
        sd    zero, 16(t0)              ; ...
        sd    zero, 24(t0)              ; ...
        sw    a1, T_X(t0)               ; ...
        sw    a2, T_Y(t0)               ; ...
        sb    a0, T_KIND(t0)            ; ...
        li    t1, K_DEMON               ; a monster: its health and first sprite
        bgt   a0, t1, ts_i              ; ...
        addi  t1, a0, -1                ; ...
        slli  t1, t1, 4                 ; ...
        la    t2, mt                    ; ...
        add   t1, t1, t2                ; ...
        lhu   t2, MT_HP(t1)             ; ...
        sh    t2, T_HP(t0)              ; ...
        lhu   t2, MT_SPR(t1)            ; ...
        sh    t2, T_SPR(t0)             ; ...
        j     ts_r                      ; ...
ts_i:   la    t1, item_spr - K_CLIP     ; anything else: its sprite
        add   t1, t1, a0                ; ...
        lbu   t1, 0(t1)                 ; ...
        sh    t1, T_SPR(t0)             ; ...
        li    t1, 10                    ; (a clip found in the level has 10 rounds)
        sh    t1, T_HP(t0)              ; ...
ts_r:   mv    a0, t0                    ; ...
        ret                             ; done

; lvl_init(): the level as it starts
lvl_init:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the level's record
        sd    s1, 16(sp)                ; s1 = records left
        la    t0, g_zero                ; the player's state: all zero ...
        la    t1, g_zero_e              ; ...
li_z:   sd    zero, 0(t0)               ; ...
        addi  t0, t0, 8                 ; ...
        bne   t0, t1, li_z              ; ...
        la    t0, res + R_START         ; ... in the middle of the start cell,
        ld    t1, 0(t0)                 ; ...
        slli  t1, t1, 16                ; ...
        li    t2, 0x8000                ; ...
        add   t1, t1, t2                ; ...
        sd    t1, g_px - g(gp)          ; ...
        ld    t1, 8(t0)                 ; ...
        slli  t1, t1, 16                ; ...
        add   t1, t1, t2                ; ...
        sd    t1, g_py - g(gp)          ; ...
        li    t0, 100                   ; ... in good health, with a full pistol
        sd    t0, g_health - g(gp)      ; ...
        li    t0, 50                    ; ...
        sd    t0, g_ammo - g(gp)        ; ...
        li    t0, SP_M_START            ; the keys, for five seconds
        sd    t0, g_msg - g(gp)         ; ...
        li    t0, 175                   ; ...
        sd    t0, g_msgt - g(gp)        ; ...
        li    t0, -1                    ; (the palette is set again)
        sd    t0, g_palcur - g(gp)      ; ...
        li    t0, 1                     ; ...
        sd    t0, g_bardirty - g(gp)    ; ...
        la    t0, res + R_MAP           ; the exit switch is off
        li    t1, 1024                  ; ...
        li    t2, TX_SW_ON              ; ...
li_m:   lbu   t3, 0(t0)                 ; ...
        bne   t3, t2, li_m1             ; ...
        li    t3, TX_SW_OFF             ; ...
        sb    t3, 0(t0)                 ; ...
li_m1:  addi  t0, t0, 1                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, li_m                  ; ...
        la    t0, things                ; no things ...
        li    t1, MAXTHINGS * T_SIZE / 8 ; ...
li_t:   sd    zero, 0(t0)               ; ...
        addi  t0, t0, 8                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, li_t                  ; ...
        la    s0, res + R_THINGS        ; ... but the level's: x, y, kind
        la    t0, res + R_NTHING        ; ...
        ld    s1, 0(t0)                 ; ...
li_s:   beqz  s1, li_d                  ; ...
        lbu   a1, 0(s0)                 ; ...
        slli  a1, a1, 16                ; ...
        li    t0, 0x8000                ; ...
        add   a1, a1, t0                ; ...
        lbu   a2, 1(s0)                 ; ...
        slli  a2, a2, 16                ; ...
        add   a2, a2, t0                ; ...
        lbu   a0, 2(s0)                 ; ...
        li    t0, K_DEMON               ; (count the monsters)
        bgt   a0, t0, li_s1             ; ...
        ld    t0, g_nmon - g(gp)        ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, g_nmon - g(gp)        ; ...
li_s1:  call  t_spawn                   ; ...
        addi  s0, s0, 4                 ; ...
        addi  s1, s1, -1                ; ...
        j     li_s                      ; ...
li_d:   la    t0, res + R_DOORS         ; the doors, shut: cell, texture, flags
        la    t1, doors                 ; ...
        li    t2, MAXDOORS              ; ...
li_dl:  lwu   t3, 0(t0)                 ; ...
        sd    t3, 0(t1)                 ; (state 0, timer 0)
        sd    zero, 8(t1)               ; (shut)
        addi  t0, t0, 4                 ; ...
        addi  t1, t1, D_SIZE            ; ...
        addi  t2, t2, -1                ; ...
        bnez  t2, li_dl                 ; ...
        ld    t0, g_keepb - g(gp)       ; the two flats, into the buffers the library
        li    t1, F_FLOOR               ;   keeps for standard output and input (we
        add   t1, t1, t0                ;   use neither: see wdoom.s)
        la    t2, out_buf               ; ...
        li    t3, 4096                  ; ...
        tget  tg8, t2, c0, t1, t3       ; ...
        li    t1, F_CEIL                ; ...
        add   t1, t1, t0                ; ...
        la    t2, in_buf                ; ...
        tget  tg8, t2, c0, t1, t3       ; ...
        call  pal_update                ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; pal_update(): the palette the moment calls for: red while hurt (and dead),
; gold for a moment after a pickup; fetched from the arena when it changes
pal_update:
        ld    t0, g_flash - g(gp)       ; hurt?
        li    t1, 0                     ; t1 = the palette wanted
        beqz  t0, pu_b                  ; ...
        addi  t0, t0, -1                ; red, deeper with the damage
        srli  t0, t0, 3                 ; ...
        li    t1, 2                     ; ...
        bleu  t0, t1, pu_r              ; ...
        mv    t0, t1                    ; ...
pu_r:   addi  t1, t0, PAL_RED           ; ...
        j     pu_s                      ; ...
pu_b:   ld    t0, g_bonus - g(gp)       ; a pickup?
        beqz  t0, pu_s                  ; ...
        li    t1, PAL_GOLD              ; ...
pu_s:   ld    t0, g_palcur - g(gp)      ; a change?
        beq   t0, t1, pu_x              ; ...
        sd    t1, g_palcur - g(gp)      ; ...
        slli  t1, t1, 10                ; 1024 bytes each
        li    t0, F_PALS                ; ...
        add   t1, t1, t0                ; ...
        ld    t0, g_keepb - g(gp)       ; ...
        add   t1, t1, t0                ; ...
        la    t0, res + R_PAL           ; ...
        li    t2, 1024                  ; ...
        tget  tg8, t0, c0, t1, t2       ; ...
        li    t0, 1                     ; (the bar's colours change with it)
        sd    t0, g_bardirty - g(gp)    ; ...
pu_x:   ret                             ; done

; say(a0 = message sprite, a1 = tics, or -1 to keep it up)
say:    sd    a0, g_msg - g(gp)         ; ...
        sd    a1, g_msgt - g(gp)        ; ...
        ret                             ; done

; p_hurt(a0 = damage): the player is hit. Clobbers t0..t3, a0, a1.
p_hurt: ld    t0, g_state - g(gp)       ; (only while playing)
        bnez  t0, ph_r                  ; ...
        ld    t0, g_health - g(gp)      ; ...
        sub   t0, t0, a0                ; ...
        ld    t1, g_flash - g(gp)       ; the screen goes red with it
        slli  a0, a0, 1                 ; ...
        add   t1, t1, a0                ; ...
        li    t2, 24                    ; ...
        ble   t1, t2, ph_1              ; ...
        mv    t1, t2                    ; ...
ph_1:   sd    t1, g_flash - g(gp)       ; ...
        li    t1, 1                     ; ...
        sd    t1, g_bardirty - g(gp)    ; ...
        bgtz  t0, ph_2                  ; ...
        sd    zero, g_health - g(gp)    ; dead
        li    t0, 24                    ; (the red stays)
        sd    t0, g_flash - g(gp)       ; ...
        li    t0, ST_DEAD               ; ...
        sd    t0, g_state - g(gp)       ; ...
        li    t0, SP_M_DEAD             ; ...
        sd    t0, g_msg - g(gp)         ; ...
        li    t0, -1                    ; ...
        sd    t0, g_msgt - g(gp)        ; ...
        li    a0, SN_DEATH              ; ...
        j     snd_play                  ; ...
ph_2:   sd    t0, g_health - g(gp)      ; ...
        li    a0, SN_HURT               ; ...
        j     snd_play                  ; ...
ph_r:   ret                             ; done

; p_blocked(a0 = x, a1 = y) -> a0 = 1 if the player cannot stand there: a
; corner of the player's square in a wall, or closer to a monster than now
p_blocked:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = x
        sd    s1, 16(sp)                ; s1 = y
        sd    s2, 24(sp)                ; s2 = corner
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        li    s2, 3                     ; ...
pb_c:   li    t0, P_RADIUS              ; the corner: x - r or x + r,
        andi  t1, s2, 1                 ; ...
        bnez  t1, pb_c1                 ; ...
        neg   t0, t0                    ; ...
pb_c1:  add   a0, s0, t0                ; ...
        li    t0, P_RADIUS              ; ... y - r or y + r
        andi  t1, s2, 2                 ; ...
        bnez  t1, pb_c2                 ; ...
        neg   t0, t0                    ; ...
pb_c2:  add   a1, s1, t0                ; ...
        call  cell_at                   ; ...
        bnez  a0, pb_r                  ; a wall
        addi  s2, s2, -1                ; ...
        bgez  s2, pb_c                  ; ...
        la    t0, things                ; the monsters that stand
        li    t1, MAXTHINGS             ; ...
pb_m:   lbu   t2, T_KIND(t0)            ; ...
        beqz  t2, pb_n                  ; ...
        li    t3, K_DEMON               ; ...
        bgt   t2, t3, pb_n              ; ...
        lbu   t2, T_ST(t0)              ; ...
        li    t3, M_DYING               ; ...
        bge   t2, t3, pb_n              ; ...
        lwu   t2, T_X(t0)               ; within half a cell in x ...
        sub   t3, t2, s0                ; ...
        bgez  t3, pb_m1                 ; ...
        neg   t3, t3                    ; ...
pb_m1:  li    t4, 0x8000                ; ...
        bge   t3, t4, pb_n              ; ...
        lwu   t5, T_Y(t0)               ; ... and in y?
        sub   t6, t5, s1                ; ...
        bgez  t6, pb_m2                 ; ...
        neg   t6, t6                    ; ...
pb_m2:  bge   t6, t4, pb_n              ; ...
        add   t3, t3, t6                ; and nearer than where the player is now
        ld    t4, g_px - g(gp)          ;   (walking away from one is always possible)
        sub   t2, t2, t4                ; ...
        bgez  t2, pb_m3                 ; ...
        neg   t2, t2                    ; ...
pb_m3:  ld    t4, g_py - g(gp)          ; ...
        sub   t5, t5, t4                ; ...
        bgez  t5, pb_m4                 ; ...
        neg   t5, t5                    ; ...
pb_m4:  add   t2, t2, t5                ; ...
        li    a0, 1                     ; ...
        blt   t3, t2, pb_r              ; ...
pb_n:   addi  t0, t0, T_SIZE            ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, pb_m                  ; ...
        li    a0, 0                     ; free
pb_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

; d_use(a0 = door): open it, if the player may
d_use:  lbu   t0, D_STATE(a0)           ; shut, or shutting? (open or opening: nothing)
        li    t2, 2                     ; ...
        beq   t0, t2, du_r              ; ...
        li    t2, 1                     ; ...
        beq   t0, t2, du_r              ; ...
        lbu   t0, D_FLAGS(a0)           ; the key?
        andi  t0, t0, 2                 ; ...
        beqz  t0, du_o                  ; ...
        ld    t0, g_key - g(gp)         ; ...
        bnez  t0, du_o                  ; ...
        li    a0, SP_M_NEED             ; no
        li    a1, 90                    ; ...
        sd    a0, g_msg - g(gp)         ; ...
        sd    a1, g_msgt - g(gp)        ; ...
        li    a0, SN_NOWAY              ; ...
        j     snd_play                  ; ...
du_o:   li    t0, 1                     ; opening
        sb    t0, D_STATE(a0)           ; ...
        li    a0, SN_DOOROPEN           ; ...
        j     snd_play                  ; ...
du_r:   ret                             ; done

; d_busy(a0 = door) -> a1 = 1 if the player or a standing monster is in
; its cell or near enough to be caught by it. Keeps a0; clobbers t0..t5.
d_busy: lhu   t0, D_CELL(a0)            ; the cell's middle
        andi  t1, t0, 31                ; ...
        slli  t1, t1, 16                ; ...
        li    t2, 0x8000                ; ...
        add   t1, t1, t2                ; t1 = x
        srli  t0, t0, 5                 ; ...
        slli  t0, t0, 16                ; ...
        add   t2, t0, t2                ; t2 = y
        li    t5, 0xC000                ; t5 = three quarters of a cell
        li    a1, 1                     ; ...
        ld    t3, g_px - g(gp)          ; the player
        sub   t3, t3, t1                ; ...
        bgez  t3, db_1                  ; ...
        neg   t3, t3                    ; ...
db_1:   bge   t3, t5, db_m              ; ...
        ld    t3, g_py - g(gp)          ; ...
        sub   t3, t3, t2                ; ...
        bgez  t3, db_2                  ; ...
        neg   t3, t3                    ; ...
db_2:   blt   t3, t5, db_r              ; ...
db_m:   la    t0, things                ; the monsters
        li    t4, MAXTHINGS             ; ...
db_l:   lbu   t3, T_KIND(t0)            ; ...
        beqz  t3, db_n                  ; ...
        addi  t3, t3, -(K_DEMON + 1)    ; ...
        bgez  t3, db_n                  ; ...
        lbu   t3, T_ST(t0)              ; ...
        addi  t3, t3, -M_DYING          ; ...
        bgez  t3, db_n                  ; ...
        lwu   t3, T_X(t0)               ; ...
        sub   t3, t3, t1                ; ...
        bgez  t3, db_3                  ; ...
        neg   t3, t3                    ; ...
db_3:   bge   t3, t5, db_n              ; ...
        lwu   t3, T_Y(t0)               ; ...
        sub   t3, t3, t2                ; ...
        bgez  t3, db_4                  ; ...
        neg   t3, t3                    ; ...
db_4:   blt   t3, t5, db_r              ; ...
db_n:   addi  t0, t0, T_SIZE            ; ...
        addi  t4, t4, -1                ; ...
        bnez  t4, db_l                  ; ...
        li    a1, 0                     ; nobody
db_r:   ret                             ; done

; d_step(): the doors move
d_step: addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = door
        sd    s1, 16(sp)                ; s1 = doors left
        la    s0, doors                 ; ...
        la    t0, res + R_NDOOR         ; ...
        ld    s1, 0(t0)                 ; ...
ds_l:   beqz  s1, ds_r                  ; ...
        lbu   t0, D_STATE(s0)           ; ...
        beqz  t0, ds_n                  ; shut: nothing
        li    t1, 1                     ; ...
        bne   t0, t1, ds_2              ; ...
        lwu   t0, D_OPEN(s0)            ; opening
        addi  t0, t0, D_STEP            ; ...
        li    t1, 0x10000               ; ...
        blt   t0, t1, ds_1              ; ...
        mv    t0, t1                    ; open
        li    t2, 2                     ; ...
        sb    t2, D_STATE(s0)           ; ...
        li    t2, D_WAIT                ; ...
        sh    t2, D_TIMER(s0)           ; ...
ds_1:   sw    t0, D_OPEN(s0)            ; ...
        j     ds_n                      ; ...
ds_2:   li    t1, 2                     ; ...
        bne   t0, t1, ds_3              ; ...
        lhu   t0, D_TIMER(s0)           ; open: for a while
        addi  t0, t0, -1                ; ...
        sh    t0, D_TIMER(s0)           ; ...
        bnez  t0, ds_n                  ; ...
        mv    a0, s0                    ; then it shuts, unless someone is in the way
        call  d_busy                    ; ...
        li    t0, 20                    ; ...
        sh    t0, D_TIMER(s0)           ; ...
        bnez  a1, ds_n                  ; ...
        li    t0, 3                     ; ...
        sb    t0, D_STATE(s0)           ; ...
        li    a0, SN_DOORSHUT           ; ...
        call  snd_play                  ; ...
        j     ds_n                      ; ...
ds_3:   mv    a0, s0                    ; shutting: someone walks in: open again
        call  d_busy                    ; ...
        beqz  a1, ds_4                  ; ...
        li    t0, 1                     ; ...
        sb    t0, D_STATE(s0)           ; ...
        j     ds_n                      ; ...
ds_4:   lwu   t0, D_OPEN(s0)            ; ...
        addi  t0, t0, -D_STEP           ; ...
        bgtz  t0, ds_5                  ; ...
        li    t0, 0                     ; shut
        sb    zero, D_STATE(s0)         ; ...
ds_5:   sw    t0, D_OPEN(s0)            ; ...
ds_n:   addi  s0, s0, D_SIZE            ; ...
        addi  s1, s1, -1                ; ...
        j     ds_l                      ; ...
ds_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; p_step(): the player's tic: turn, walk, shoot, open
p_step: addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = thrust forward (-1, 0, 1)
        sd    s1, 16(sp)                ; s1 = thrust to the right
        ld    t0, g_tic - g(gp)         ; t0 = now
        la    t1, g_hold                ; t1 = the keys held
        ld    t2, g_ang - g(gp)         ; turning
        ld    t3, H_TL(t1)              ; ...
        ble   t3, t0, ps_1              ; ...
        addi  t2, t2, -P_TURN           ; ...
ps_1:   ld    t3, H_TR(t1)              ; ...
        ble   t3, t0, ps_2              ; ...
        addi  t2, t2, P_TURN            ; ...
ps_2:   andi  t2, t2, 2047              ; ...
        sd    t2, g_ang - g(gp)         ; ...
        ld    t3, H_FWD(t1)             ; forward less back
        slt   s0, t0, t3                ; ...
        ld    t3, H_BACK(t1)            ; ...
        slt   t3, t0, t3                ; ...
        sub   s0, s0, t3                ; ...
        ld    t3, H_RIGHT(t1)           ; right less left
        slt   s1, t0, t3                ; ...
        ld    t3, H_LEFT(t1)            ; ...
        slt   t3, t0, t3                ; ...
        sub   s1, s1, t3                ; ...
        call  r_view                    ; the direction we face now
        li    t0, P_ACC                 ; the thrust, along the view ...
        mul   t0, t0, s0                ; ...
        li    t1, P_SIDE                ; ... and across it
        mul   t1, t1, s1                ; ...
        ld    t2, g_dirx - g(gp)        ; x
        mul   t2, t2, t0                ; ...
        ld    t3, g_plx - g(gp)         ; ...
        mul   t3, t3, t1                ; ...
        add   t2, t2, t3                ; ...
        srai  t2, t2, 16                ; ...
        ld    t3, g_vx - g(gp)          ; ...
        add   t2, t2, t3                ; ...
        li    t4, 232                   ; and friction: 232 / 256 a tic
        mul   t2, t2, t4                ; ...
        srai  t2, t2, 8                 ; ...
        sd    t2, g_vx - g(gp)          ; ...
        ld    t2, g_diry - g(gp)        ; y
        mul   t2, t2, t0                ; ...
        ld    t3, g_ply - g(gp)         ; ...
        mul   t3, t3, t1                ; ...
        add   t2, t2, t3                ; ...
        srai  t2, t2, 16                ; ...
        ld    t3, g_vy - g(gp)          ; ...
        add   t2, t2, t3                ; ...
        mul   t2, t2, t4                ; ...
        srai  t2, t2, 8                 ; ...
        sd    t2, g_vy - g(gp)          ; ...
        ld    a0, g_px - g(gp)          ; the step in x, if nothing is there
        ld    t0, g_vx - g(gp)          ; ...
        beqz  t0, ps_y                  ; ...
        add   a0, a0, t0                ; ...
        mv    s0, a0                    ; ...
        ld    a1, g_py - g(gp)          ; ...
        call  p_blocked                 ; ...
        bnez  a0, ps_bx                 ; ...
        sd    s0, g_px - g(gp)          ; ...
        j     ps_y                      ; ...
ps_bx:  sd    zero, g_vx - g(gp)        ; (stopped)
ps_y:   ld    a1, g_py - g(gp)          ; the step in y
        ld    t0, g_vy - g(gp)          ; ...
        beqz  t0, ps_f                  ; ...
        add   a1, a1, t0                ; ...
        mv    s0, a1                    ; ...
        ld    a0, g_px - g(gp)          ; ...
        call  p_blocked                 ; ...
        bnez  a0, ps_by                 ; ...
        sd    s0, g_py - g(gp)          ; ...
        j     ps_f                      ; ...
ps_by:  sd    zero, g_vy - g(gp)        ; ...
ps_f:   ld    t0, g_wst - g(gp)         ; the weapon: busy with the last shot?
        beqz  t0, ps_f1                 ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, g_wst - g(gp)         ; ...
        j     ps_u                      ; ...
ps_f1:  ld    t0, g_fire - g(gp)        ; the trigger?
        beqz  t0, ps_u                  ; ...
        ld    t0, g_ammo - g(gp)        ; ...
        beqz  t0, ps_u                  ; (empty)
        addi  t0, t0, -1                ; ...
        sd    t0, g_ammo - g(gp)        ; ...
        li    t0, W_FIRE                ; ...
        sd    t0, g_wst - g(gp)         ; ...
        li    t0, 1                     ; ...
        sd    t0, g_bardirty - g(gp)    ; ...
        li    a0, SN_PISTOL             ; ...
        call  snd_play                  ; ...
        call  p_shoot                   ; ...
ps_u:   ld    t0, g_use - g(gp)         ; opening something?
        beqz  t0, ps_r                  ; ...
        li    s0, 0x9000                ; what is 0.56 of a cell ahead, then 1.12, then 1.69
ps_u1:  ld    a0, g_dirx - g(gp)        ; ...
        mul   a0, a0, s0                ; ...
        srai  a0, a0, 16                ; ...
        ld    t0, g_px - g(gp)          ; ...
        add   a0, a0, t0                ; ...
        ld    a1, g_diry - g(gp)        ; ...
        mul   a1, a1, s0                ; ...
        srai  a1, a1, 16                ; ...
        ld    t0, g_py - g(gp)          ; ...
        add   a1, a1, t0                ; ...
        call  cell_at                   ; ...
        beqz  a2, ps_u2                 ; a door
        mv    a0, a2                    ; ...
        call  d_use                     ; ...
        j     ps_r                      ; ...
ps_u2:  li    t0, TX_SW_OFF             ; the exit switch
        bne   a1, t0, ps_u3             ; ...
        li    t0, TX_SW_ON              ; ...
        sb    t0, 0(a3)                 ; ...
        li    t0, ST_WON                ; ...
        sd    t0, g_state - g(gp)       ; ...
        li    a0, SP_M_WIN              ; ...
        li    a1, -1                    ; ...
        call  say                       ; ...
        li    a0, SN_SWITCH             ; ...
        call  snd_play                  ; ...
        j     ps_r                      ; ...
ps_u3:  bnez  a1, ps_r                  ; (a wall: nothing behind it)
        li    t0, 0x9000                ; ...
        add   s0, s0, t0                ; ...
        li    t0, 0x1B000               ; ...
        ble   s0, t0, ps_u1             ; ...
ps_r:   sd    zero, g_fire - g(gp)      ; (both taken)
        sd    zero, g_use - g(gp)       ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; p_shoot(): the bullet hits the nearest standing monster drawn across the
; middle of the last frame and in front of the wall there; every monster
; near enough hears the shot
p_shoot:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the one hit
        li    s0, 0                     ; ...
        la    t0, zbuf + (VIEW_W / 2) * 4 ; t6 = the nearest so far: the wall
        lwu   t6, 0(t0)                 ; ...
        la    t0, vis                   ; the things in view
        ld    t1, g_nvis - g(gp)        ; ...
sh_l:   beqz  t1, sh_d                  ; ...
        ld    t2, V_TH(t0)              ; a monster on its feet?
        lbu   t3, T_KIND(t2)            ; ...
        beqz  t3, sh_n                  ; ...
        addi  t3, t3, -(K_DEMON + 1)    ; ...
        bgez  t3, sh_n                  ; ...
        lbu   t3, T_ST(t2)              ; ...
        addi  t3, t3, -M_DYING          ; ...
        bgez  t3, sh_n                  ; ...
        lw    t3, V_X1(t0)              ; the middle column in its inner three quarters?
        lw    t4, V_X2(t0)              ; ...
        sub   t5, t4, t3                ; ...
        srai  t5, t5, 3                 ; ...
        add   t3, t3, t5                ; ...
        sub   t4, t4, t5                ; ...
        li    t5, VIEW_W / 2            ; ...
        blt   t5, t3, sh_n              ; ...
        bge   t5, t4, sh_n              ; ...
        lw    t3, V_DEPTH(t0)           ; nearer than the best?
        bge   t3, t6, sh_n              ; ...
        mv    t6, t3                    ; ...
        mv    s0, t2                    ; ...
sh_n:   addi  t0, t0, V_SIZE            ; ...
        addi  t1, t1, -1                ; ...
        j     sh_l                      ; ...
sh_d:   beqz  s0, sh_w                  ; a miss
        call  rnd                       ; 12 .. 27
        andi  a0, a0, 15                ; ...
        addi  a0, a0, 12                ; ...
        call  m_hurt                    ; ...
sh_w:   la    t0, things                ; the noise wakes those within 9 cells
        li    t1, MAXTHINGS             ; ...
sh_wl:  lbu   t2, T_KIND(t0)            ; ...
        beqz  t2, sh_wn                 ; ...
        addi  t2, t2, -(K_DEMON + 1)    ; ...
        bgez  t2, sh_wn                 ; ...
        lbu   t2, T_ST(t0)              ; ...
        bnez  t2, sh_wn                 ; ...
        lwu   t2, T_X(t0)               ; ...
        ld    t3, g_px - g(gp)          ; ...
        sub   t2, t2, t3                ; ...
        bgez  t2, sh_w1                 ; ...
        neg   t2, t2                    ; ...
sh_w1:  lwu   t3, T_Y(t0)               ; ...
        ld    t4, g_py - g(gp)          ; ...
        sub   t3, t3, t4                ; ...
        bgez  t3, sh_w2                 ; ...
        neg   t3, t3                    ; ...
sh_w2:  add   t2, t2, t3                ; ...
        li    t3, 9 << 16               ; ...
        bge   t2, t3, sh_wn             ; ...
        li    t2, M_CHASE               ; ...
        sb    t2, T_ST(t0)              ; ...
        li    t2, 30                    ; ...
        sh    t2, T_CD(t0)              ; ...
sh_wn:  addi  t0, t0, T_SIZE            ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, sh_wl                 ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 16                ; pop the frame
        ret                             ; done

; m_hurt(s0 = monster, a0 = damage). Clobbers t0..t3, a0..a2.
m_hurt: addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        lbu   t0, T_KIND(s0)            ; its kind's record
        addi  t0, t0, -1                ; ...
        slli  t0, t0, 4                 ; ...
        la    t1, mt                    ; ...
        add   t1, t1, t0                ; ...
        lh    t0, T_HP(s0)              ; ...
        sub   t0, t0, a0                ; ...
        sh    t0, T_HP(s0)              ; ...
        bgtz  t0, mh_p                  ; ...
        li    t0, M_DYING               ; it falls
        sb    t0, T_ST(s0)              ; ...
        sh    zero, T_TIC(s0)           ; ...
        ld    t0, g_kills - g(gp)       ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, g_kills - g(gp)       ; ...
        lbu   a0, MT_SDIE(t1)           ; ...
        call  snd_play                  ; ...
        lbu   t0, T_KIND(s0)            ; a zombie drops its clip: five rounds
        li    t1, K_ZOMBIE              ; ...
        bne   t0, t1, mh_r              ; ...
        li    a0, K_CLIP                ; ...
        lwu   a1, T_X(s0)               ; ...
        lwu   a2, T_Y(s0)               ; ...
        call  t_spawn                   ; ...
        beqz  a0, mh_r                  ; ...
        li    t0, 5                     ; ...
        sh    t0, T_HP(a0)              ; ...
        j     mh_r                      ; ...
mh_p:   lbu   t0, T_ST(s0)              ; hurt: it knows where we are now ...
        bnez  t0, mh_p1                 ; ...
        li    t0, M_CHASE               ; ...
        sb    t0, T_ST(s0)              ; ...
mh_p1:  lbu   t2, MT_PAIN(t1)           ; ... and may flinch
        call  rnd                       ; (keeps t2)
        andi  a0, a0, 255               ; ...
        mv    t0, t2                    ; ...
        bge   a0, t0, mh_r              ; ...
        li    t0, M_PAIN                ; ...
        sb    t0, T_ST(s0)              ; ...
        li    t0, 6                     ; ...
        sh    t0, T_TIC(s0)             ; ...
        li    a0, SN_MPAIN              ; ...
        call  snd_play                  ; ...
mh_r:   ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; m_dist(s0 = thing) -> a0, a1 = the player's x and y from it, a2 = about
; how far that is (the longer side plus half the shorter). Clobbers t0.
m_dist: ld    a0, g_px - g(gp)          ; ...
        lwu   t0, T_X(s0)               ; ...
        sub   a0, a0, t0                ; ...
        ld    a1, g_py - g(gp)          ; ...
        lwu   t0, T_Y(s0)               ; ...
        sub   a1, a1, t0                ; ...
        mv    a2, a0                    ; |x|
        bgez  a2, md_1                  ; ...
        neg   a2, a2                    ; ...
md_1:   mv    t0, a1                    ; |y|
        bgez  t0, md_2                  ; ...
        neg   t0, t0                    ; ...
md_2:   bge   a2, t0, md_3              ; a2 = the longer, t0 = the shorter
        xor   a2, a2, t0                ; ...
        xor   t0, a2, t0                ; ...
        xor   a2, a2, t0                ; ...
md_3:   srli  t0, t0, 1                 ; ...
        add   a2, a2, t0                ; ...
        ret                             ; done

; m_see(s0 = thing) -> a0 = 1 if nothing stands between it and the player:
; the straight line is walked in steps of a quarter cell at most
m_see:  addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s1, 8(sp)                 ; s1 = x
        sd    s2, 16(sp)                ; s2 = y
        sd    s3, 24(sp)                ; s3 = the step in x
        sd    s4, 32(sp)                ; s4 = ... in y
        sd    s5, 40(sp)                ; s5 = steps left
        call  m_dist                    ; ...
        srli  s5, a2, 14                ; ...
        addi  s5, s5, 1                 ; ...
        div   s3, a0, s5                ; ...
        div   s4, a1, s5                ; ...
        lwu   s1, T_X(s0)               ; ...
        lwu   s2, T_Y(s0)               ; ...
ms_l:   addi  s5, s5, -1                ; ...
        li    a0, 1                     ; (there: seen)
        blez  s5, ms_r                  ; ...
        add   s1, s1, s3                ; ...
        add   s2, s2, s4                ; ...
        mv    a0, s1                    ; ...
        mv    a1, s2                    ; ...
        call  cell_at                   ; ...
        beqz  a0, ms_l                  ; ...
        li    a0, 0                     ; a wall
ms_r:   ld    ra, 0(sp)                 ; restore
        ld    s1, 8(sp)                 ; ...
        ld    s2, 16(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        ld    s5, 40(sp)                ; ...
        addi  sp, sp, 48                ; pop the frame
        ret                             ; done

; m_walk(s0 = monster, a0 = step in x, a1 = step in y): each if nothing is
; in the way a third of a cell ahead; a shut door without a lock is opened
m_walk: addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s1, 8(sp)                 ; s1 = the step in x
        sd    s2, 16(sp)                ; s2 = ... in y
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        beqz  s1, mw_y                  ; ...
        li    t0, 0x5000                ; the probe: ahead of the step
        bgez  s1, mw_1                  ; ...
        neg   t0, t0                    ; ...
mw_1:   lwu   a0, T_X(s0)               ; ...
        add   a0, a0, s1                ; ...
        add   a0, a0, t0                ; ...
        lwu   a1, T_Y(s0)               ; ...
        call  cell_at                   ; ...
        bnez  a0, mw_dx                 ; ...
        lwu   t0, T_X(s0)               ; ...
        add   t0, t0, s1                ; ...
        sw    t0, T_X(s0)               ; ...
        j     mw_y                      ; ...
mw_dx:  call  mw_door                   ; ...
mw_y:   beqz  s2, mw_r                  ; ...
        li    t0, 0x5000                ; ...
        bgez  s2, mw_2                  ; ...
        neg   t0, t0                    ; ...
mw_2:   lwu   a1, T_Y(s0)               ; ...
        add   a1, a1, s2                ; ...
        add   a1, a1, t0                ; ...
        lwu   a0, T_X(s0)               ; ...
        call  cell_at                   ; ...
        bnez  a0, mw_dy                 ; ...
        lwu   t0, T_Y(s0)               ; ...
        add   t0, t0, s2                ; ...
        sw    t0, T_Y(s0)               ; ...
        j     mw_r                      ; ...
mw_dy:  call  mw_door                   ; ...
mw_r:   ld    ra, 0(sp)                 ; restore
        ld    s1, 8(sp)                 ; ...
        ld    s2, 16(sp)                ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done
mw_door:                                ; a2 = the door in the way, if it is one
        beqz  a2, mwd_r                 ; ...
        lbu   t0, D_FLAGS(a2)           ; (not the locked one)
        andi  t0, t0, 2                 ; ...
        bnez  t0, mwd_r                 ; ...
        mv    a0, a2                    ; ...
        j     d_use                     ; ...
mwd_r:  ret                             ; ...

; m_step(s0 = monster): its tic
m_step: addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s1, 8(sp)                 ; s1 = its kind's record
        sd    s2, 16(sp)                ; s2 = the distance to the player
        sd    s3, 24(sp)                ; s3 = the player's x from it
        sd    s4, 32(sp)                ; s4 = ... and y
        lbu   t0, T_KIND(s0)            ; ...
        addi  t0, t0, -1                ; ...
        slli  t0, t0, 4                 ; ...
        la    s1, mt                    ; ...
        add   s1, s1, t0                ; ...
        lbu   t0, T_ST(s0)              ; by state
        beqz  t0, mo_idle               ; ...
        addi  t0, t0, -1                ; ...
        beqz  t0, mo_chase              ; ...
        addi  t0, t0, -1                ; ...
        beqz  t0, mo_atk                ; ...
        addi  t0, t0, -1                ; ...
        beqz  t0, mo_pain               ; ...
        addi  t0, t0, -1                ; ...
        bnez  t0, mo_r                  ; (dead)
        lhu   t0, T_TIC(s0)             ; ---- falling: a frame every four tics
        addi  t0, t0, 1                 ; ...
        sh    t0, T_TIC(s0)             ; ...
        srli  t0, t0, 2                 ; ...
        lbu   t1, MT_NDIE(s1)           ; ...
        blt   t0, t1, mo_d1             ; ...
        addi  t0, t1, -1                ; the last one: it stays
        li    t2, M_DEAD                ; ...
        sb    t2, T_ST(s0)              ; ...
mo_d1:  lbu   t1, MT_NATK(s1)           ; ...
        add   t0, t0, t1                ; ...
        addi  t0, t0, 5                 ; (after 4 walk, the attack and 1 pain frames)
        j     mo_spr                    ; ...
mo_idle:                                ; ---- idle: look every eighth tic
        ld    t0, g_tic - g(gp)         ; ...
        srli  t1, s0, 5                 ; (not all in the same one)
        add   t0, t0, t1                ; ...
        andi  t0, t0, 7                 ; ...
        bnez  t0, mo_r                  ; ...
        ld    t0, g_state - g(gp)       ; (nobody to see)
        bnez  t0, mo_r                  ; ...
        call  m_dist                    ; within 14 cells ...
        li    t0, 14 << 16              ; ...
        bgt   a2, t0, mo_r              ; ...
        call  m_see                     ; ... and in sight?
        beqz  a0, mo_r                  ; ...
        li    t0, M_CHASE               ; ...
        sb    t0, T_ST(s0)              ; ...
        call  rnd                       ; (it takes a moment to aim)
        andi  a0, a0, 31                ; ...
        addi  a0, a0, 20                ; ...
        sh    a0, T_CD(s0)              ; ...
        li    a0, SN_SIGHT              ; ...
        call  snd_play                  ; ...
        j     mo_r                      ; ...
mo_chase:                               ; ---- walking: a frame every eight tics
        lhu   t0, T_TIC(s0)             ; ...
        addi  t0, t0, 1                 ; ...
        sh    t0, T_TIC(s0)             ; ...
        srli  t0, t0, 3                 ; ...
        andi  t0, t0, 3                 ; ...
        lhu   t1, MT_SPR(s1)            ; ...
        add   t0, t0, t1                ; ...
        sh    t0, T_SPR(s0)             ; ...
        ld    t0, g_state - g(gp)       ; (nobody to chase)
        bnez  t0, mo_r                  ; ...
        call  m_dist                    ; ...
        mv    s3, a0                    ; ...
        mv    s4, a1                    ; ...
        mv    s2, a2                    ; ...
        lbu   t0, MT_ATK(s1)            ; ...
        li    t1, 2                     ; ...
        bne   t0, t1, mo_c1             ; ...
        li    t0, 0x10000               ; a biter: bites within a cell
        blt   s2, t0, mo_a              ; ...
        j     mo_mv                     ; ...
mo_c1:  lh    t0, T_CD(s0)              ; a shooter: when it may again,
        addi  t0, t0, -1                ; ...
        sh    t0, T_CD(s0)              ; ...
        bgtz  t0, mo_mv                 ; ...
        li    t0, 16                    ; (else it looks again in 16 tics)
        sh    t0, T_CD(s0)              ; ...
        li    t0, 12 << 16              ; ... within 12 cells,
        bgt   s2, t0, mo_mv             ; ...
        call  m_see                     ; ... and in sight
        beqz  a0, mo_mv                 ; ...
mo_a:   li    t0, M_ATK                 ; attack: eight tics a frame
        sb    t0, T_ST(s0)              ; ...
        lbu   t0, MT_NATK(s1)           ; ...
        slli  t0, t0, 3                 ; ...
        sh    t0, T_TIC(s0)             ; ...
        j     mo_r                      ; ...
mo_mv:  li    t0, 0xB000                ; walk, unless it is upon us already
        blt   s2, t0, mo_r              ; ...
        lhu   t0, MT_SPEED(s1)          ; its speed along the line to the player
        mul   a0, s3, t0                ; ...
        div   a0, a0, s2                ; ...
        mul   a1, s4, t0                ; ...
        div   a1, a1, s2                ; ...
        call  m_walk                    ; ...
        j     mo_r                      ; ...
mo_atk: lhu   t0, T_TIC(s0)             ; ---- attacking
        addi  t0, t0, -1                ; ...
        sh    t0, T_TIC(s0)             ; ...
        bnez  t0, mo_a1                 ; ...
        li    t1, M_CHASE               ; done: walk again, attack again in 1 to 2.5 s
        sb    t1, T_ST(s0)              ; ...
        call  rnd                       ; ...
        andi  a0, a0, 63                ; ...
        addi  a0, a0, 30                ; ...
        sh    a0, T_CD(s0)              ; ...
        j     mo_r                      ; ...
mo_a1:  li    t1, 7                     ; the blow falls as the last frame starts
        bne   t0, t1, mo_a2             ; ...
        call  m_hit                     ; ...
        lhu   t0, T_TIC(s0)             ; ...
mo_a2:  srli  t0, t0, 3                 ; the frame
        lbu   t1, MT_NATK(s1)           ; ...
        addi  t1, t1, -1                ; ...
        sub   t0, t1, t0                ; ...
        addi  t0, t0, 4                 ; ...
        j     mo_spr                    ; ...
mo_pain:                                ; ---- flinching
        lhu   t0, T_TIC(s0)             ; ...
        addi  t0, t0, -1                ; ...
        sh    t0, T_TIC(s0)             ; ...
        bnez  t0, mo_p1                 ; ...
        li    t1, M_CHASE               ; ...
        sb    t1, T_ST(s0)              ; ...
mo_p1:  lbu   t0, MT_NATK(s1)           ; ...
        addi  t0, t0, 4                 ; ...
mo_spr: lhu   t1, MT_SPR(s1)            ; the sprite: the kind's first plus the frame
        add   t0, t0, t1                ; ...
        sh    t0, T_SPR(s0)             ; ...
mo_r:   ld    ra, 0(sp)                 ; restore
        ld    s1, 8(sp)                 ; ...
        ld    s2, 16(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        addi  sp, sp, 40                ; pop the frame
        ret                             ; done

; m_hit(s0 = monster, s1 = its kind): its attack lands, or flies
m_hit:  addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        lbu   a0, MT_SATK(s1)           ; ...
        call  snd_play                  ; ...
        call  m_dist                    ; ...
        mv    s2, a2                    ; ...
        mv    s3, a0                    ; ...
        mv    s4, a1                    ; ...
        lbu   t0, MT_ATK(s1)            ; ...
        beqz  t0, mi_gun                ; ...
        addi  t0, t0, -1                ; ...
        beqz  t0, mi_ball               ; ...
        li    t0, 0x13000               ; a bite: if we are still within reach
        bgt   s2, t0, mi_r              ; ...
        j     mi_dmg                    ; ...
mi_gun: call  m_see                     ; a shot: misses more with the distance
        beqz  a0, mi_r                  ; ...
        call  rnd                       ; ...
        andi  a0, a0, 255               ; ...
        srli  t0, s2, 13                ; (8 of 256 a cell)
        addi  t0, t0, 110               ; ...
        blt   a0, t0, mi_r              ; ...
mi_dmg: call  rnd                       ; ...
        lbu   t0, MT_DMASK(s1)          ; ...
        and   a0, a0, t0                ; ...
        lbu   t0, MT_DMG(s1)            ; ...
        add   a0, a0, t0                ; ...
        call  p_hurt                    ; ...
        j     mi_r                      ; ...
mi_ball:                                ; a fireball: towards where we are now, 0.13 a tic
        li    a0, K_BALL                ; ...
        lwu   a1, T_X(s0)               ; ...
        lwu   a2, T_Y(s0)               ; ...
        call  t_spawn                   ; ...
        beqz  a0, mi_r                  ; ...
        li    t0, 8500                  ; ...
        mul   t1, s3, t0                ; ...
        div   t1, t1, s2                ; ...
        sw    t1, T_VX(a0)              ; ...
        mul   t1, s4, t0                ; ...
        div   t1, t1, s2                ; ...
        sw    t1, T_VY(a0)              ; ...
mi_r:   ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; t_step(): every thing's tic
t_step: addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = thing
        sd    s1, 16(sp)                ; s1 = things left
        la    s0, things                ; ...
        li    s1, MAXTHINGS             ; ...
tt_l:   lbu   t0, T_KIND(s0)            ; ...
        beqz  t0, tt_n                  ; ...
        li    t1, K_DEMON               ; ...
        bgt   t0, t1, tt_1              ; ...
        call  m_step                    ; a monster
        j     tt_n                      ; ...
tt_1:   li    t1, K_BALL                ; ...
        blt   t0, t1, tt_item           ; ...
        bne   t0, t1, tt_boom           ; ...
        lwu   a0, T_X(s0)               ; ---- a fireball flies
        lw    t0, T_VX(s0)              ; ...
        add   a0, a0, t0                ; ...
        sw    a0, T_X(s0)               ; ...
        lwu   a1, T_Y(s0)               ; ...
        lw    t0, T_VY(s0)              ; ...
        add   a1, a1, t0                ; ...
        sw    a1, T_Y(s0)               ; ...
        lhu   t0, T_TIC(s0)             ; (two frames)
        addi  t0, t0, 1                 ; ...
        sh    t0, T_TIC(s0)             ; ...
        srli  t0, t0, 2                 ; ...
        andi  t0, t0, 1                 ; ...
        addi  t0, t0, SP_BALL0          ; ...
        sh    t0, T_SPR(s0)             ; ...
        call  cell_at                   ; into a wall: it bursts
        bnez  a0, tt_b1                 ; ...
        call  m_dist                    ; into us: it burns, and bursts
        li    t0, 0x6000                ; ...
        bgt   a2, t0, tt_n              ; ...
        call  rnd                       ; 5 .. 20
        andi  a0, a0, 15                ; ...
        addi  a0, a0, 5                 ; ...
        call  p_hurt                    ; ...
tt_b1:  li    t0, K_BOOM                ; ...
        sb    t0, T_KIND(s0)            ; ...
        li    t0, 8                     ; ...
        sh    t0, T_TIC(s0)             ; ...
        li    t0, SP_BOOM               ; ...
        sh    t0, T_SPR(s0)             ; ...
        li    a0, SN_BOOM               ; ...
        call  snd_play                  ; ...
        j     tt_n                      ; ...
tt_boom:                                ; ---- ... and is gone a moment later
        lhu   t0, T_TIC(s0)             ; ...
        addi  t0, t0, -1                ; ...
        sh    t0, T_TIC(s0)             ; ...
        bnez  t0, tt_n                  ; ...
        sb    zero, T_KIND(s0)          ; ...
        j     tt_n                      ; ...
tt_item:                                ; ---- something to pick up: are we on it?
        ld    t0, g_state - g(gp)       ; ...
        bnez  t0, tt_n                  ; ...
        call  m_dist                    ; ...
        li    t0, 0x9000                ; ...
        bgt   a2, t0, tt_n              ; ...
        lbu   t0, T_KIND(s0)            ; ...
        li    t1, K_CLIP                ; ...
        bne   t0, t1, tt_i1             ; ...
        ld    t0, g_ammo - g(gp)        ; a clip
        lh    t1, T_HP(s0)              ; ...
        add   t0, t0, t1                ; ...
        li    t1, 200                   ; ...
        ble   t0, t1, tt_c1             ; ...
        mv    t0, t1                    ; ...
tt_c1:  sd    t0, g_ammo - g(gp)        ; ...
        li    a0, SP_M_CLIP             ; ...
        j     tt_got                    ; ...
tt_i1:  li    t1, K_KEY                 ; ...
        bne   t0, t1, tt_i2             ; ...
        li    t0, 1                     ; the key
        sd    t0, g_key - g(gp)         ; ...
        li    a0, SP_M_KEY              ; ...
        j     tt_got                    ; ...
tt_i2:  ld    t2, g_health - g(gp)      ; health: only if some is missing
        li    t3, 100                   ; ...
        bge   t2, t3, tt_n              ; ...
        li    a0, SP_M_STIM             ; a stimpack: 10
        addi  t2, t2, 10                ; ...
        li    t1, K_STIM                ; ...
        beq   t0, t1, tt_i3             ; ...
        li    a0, SP_M_MEDI             ; a medikit: 25
        addi  t2, t2, 15                ; ...
tt_i3:  ble   t2, t3, tt_i4             ; ...
        mv    t2, t3                    ; ...
tt_i4:  sd    t2, g_health - g(gp)      ; ...
tt_got: li    a1, 90                    ; say so
        call  say                       ; ...
        sb    zero, T_KIND(s0)          ; it is gone
        li    t0, 6                     ; a golden moment
        sd    t0, g_bonus - g(gp)       ; ...
        li    t0, 1                     ; ...
        sd    t0, g_bardirty - g(gp)    ; ...
        li    a0, SN_ITEM               ; ...
        call  snd_play                  ; ...
tt_n:   addi  s0, s0, T_SIZE            ; ...
        addi  s1, s1, -1                ; ...
        bnez  s1, tt_l                  ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; g_step(): one tic of the world
g_step: addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        ld    t0, g_tic - g(gp)         ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, g_tic - g(gp)         ; ...
        ld    t0, g_state - g(gp)       ; ...
        bnez  t0, gs_over               ; ...
        call  p_step                    ; ...
        j     gs_w                      ; ...
gs_over:                                ; dead, or done: Space starts the level again
        ld    t0, g_fire - g(gp)        ; ...
        sd    zero, g_fire - g(gp)      ; ...
        sd    zero, g_use - g(gp)       ; ...
        beqz  t0, gs_w                  ; ...
        call  lvl_init                  ; ...
gs_w:   call  d_step                    ; ...
        call  t_step                    ; ...
        ld    t0, g_flash - g(gp)       ; the red fades (but not from a dead eye)
        beqz  t0, gs_1                  ; ...
        ld    t1, g_state - g(gp)       ; ...
        addi  t1, t1, -ST_DEAD          ; ...
        bnez  t1, gs_f                  ; ...
        li    t1, 9                     ; ...
        ble   t0, t1, gs_1              ; ...
gs_f:   addi  t0, t0, -1                ; ...
        sd    t0, g_flash - g(gp)       ; ...
gs_1:   ld    t0, g_bonus - g(gp)       ; the gold too
        beqz  t0, gs_2                  ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, g_bonus - g(gp)       ; ...
gs_2:   ld    t0, g_msgt - g(gp)        ; the message goes after its time
        blez  t0, gs_3                  ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, g_msgt - g(gp)        ; ...
        bnez  t0, gs_3                  ; ...
        li    t0, -1                    ; ...
        sd    t0, g_msg - g(gp)         ; ...
gs_3:   call  pal_update                ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done
