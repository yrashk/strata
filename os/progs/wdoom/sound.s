; =============================================================================
; sound.s: wdoom's sounds: a four-channel mixer for the sound device
; =============================================================================
;
; The sound device (doc/strataos.md 1.2; a machine may have none) plays a
; queue of mono signed 16-bit samples at 11025 a second. The sounds are
; signed 8-bit samples in the arena (dat.s: R_SND). snd_play gives a sound
; a channel; snd_pump, called once a frame, asks the device how much it
; still has queued and tops the queue up, a block of 256 samples at a time:
; each sounding channel's next 256 bytes are fetched from the arena and
; added, times 128, into the block, which goes to the device's PCM port.
; How much is kept queued follows the frame rate: twice what the device
; played since the last frame (a slow frame must not leave a gap), no less
; than 512 samples and no more than 4096.
;
; The device's capability (from dev's GETSND) is kept in c4, the register
; of the pipe server's endpoint, which this program does not use once its
; window is open. There is no sound while the demo plays (its tics do not
; follow the clock).

OP_GETSND = 22                          ; dev: the sound device's ports
SND_NCH   = 4                           ; channels
SND_BLOCK = 256                         ; samples mixed at a time
SND_R_RATE = 8                          ; the device's ports: RATE
SND_R_STAT = 16                         ; ... and STATUS (PCM is 0)
CH_POS    = 0                           ; a channel: arena offset of its next sample
CH_LEFT   = 8                           ; samples left (0: free)
CH_SIZE   = 16                          ; bytes

        .data                           ; D-LS
        .align 8                        ; dwords
snd_on:   .dword 0                      ; there is a device
snd_last: .dword 0                      ; the clock at the last pump
snd_reg:  .dword 0                      ; a device register read or written
snd_ch:   .space SND_NCH * CH_SIZE      ; the channels
snd_in:   .space SND_BLOCK              ; a channel's samples
snd_mix:  .space SND_BLOCK * 2          ; the block being mixed
snd_ndev: .ascii "dev"                  ; the device manager's name
        .align 8                        ; ...
        .text                           ; code

; snd_open(): ask dev for the sound device; set its rate
snd_open:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        la    a0, snd_ndev              ; "dev" into c6
        li    a1, 3                     ; ...
        li    a2, 6                     ; ...
        call  sys_lookup                ; ...
        bnez  a0, so_r                  ; no device manager
        li    a0, 6                     ; GETSND
        li    a1, OP_GETSND             ; ...
        li    a2, 0                     ; ...
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        call  sys_msg                   ; 0: the ports replaced the endpoint in c6
        beqz  a0, so_1                  ; ...
        cclear c6                       ; no device: drop the endpoint copy
        j     so_r                      ; ...
so_1:   cclear c4                       ; the device lives in c4 (see above)
        cmov  c4, c6                    ; ...
        la    t0, snd_reg               ; its rate
        li    t1, SND_RATE              ; ...
        sd    t1, 0(t0)                 ; ...
        li    t1, SND_R_RATE            ; ...
        li    t2, 8                     ; ...
        tput  tg9, t0, c4, t1, t2       ; ...
        twait 1 << 9                    ; (snd_reg is used again)
        li    t0, 1                     ; ...
        la    t1, snd_on                ; ...
        sd    t0, 0(t1)                 ; ...
so_r:   ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; snd_play(a0 = sound): start it on a free channel, or on the one nearest
; its end. Clobbers t0..t5, a0.
snd_play:
        la    t0, snd_on                ; a device?
        ld    t0, 0(t0)                 ; ...
        beqz  t0, sp_r                  ; ...
        ld    t0, g_demo - g(gp)        ; (not in the demo)
        bnez  t0, sp_r                  ; ...
        la    t0, snd_ch                ; t2 = the channel with the least left
        mv    t2, t0                    ; ...
        ld    t3, CH_LEFT(t0)           ; ...
        li    t1, SND_NCH - 1           ; ...
sp_l:   addi  t0, t0, CH_SIZE           ; ...
        ld    t4, CH_LEFT(t0)           ; ...
        bgeu  t4, t3, sp_n              ; ...
        mv    t3, t4                    ; ...
        mv    t2, t0                    ; ...
sp_n:   addi  t1, t1, -1                ; ...
        bnez  t1, sp_l                  ; ...
        slli  a0, a0, 3                 ; the sound: far offset, samples
        la    t0, res + R_SND           ; ...
        add   a0, a0, t0                ; ...
        lwu   t0, 0(a0)                 ; ...
        ld    t1, g_keepb - g(gp)       ; ...
        add   t0, t0, t1                ; ...
        sd    t0, CH_POS(t2)            ; ...
        lwu   t0, 4(a0)                 ; ...
        sd    t0, CH_LEFT(t2)           ; ...
sp_r:   ret                             ; done

; snd_pump(): top up the device's queue (once a frame)
snd_pump:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = samples to keep queued
        sd    s1, 16(sp)                ; s1 = blocks this call may still mix
        sd    s2, 24(sp)                ; s2 = channel
        la    t0, snd_on                ; a device?
        ld    t0, 0(t0)                 ; ...
        beqz  t0, sm_r                  ; ...
        call  sys_now                   ; what the device played since the last pump:
        la    t0, snd_last              ;   microseconds / 91 (11025 a second)
        ld    t1, 0(t0)                 ; ...
        sd    a0, 0(t0)                 ; ...
        sub   s0, a0, t1                ; ...
        li    t1, 45                    ; twice that (/ 45)
        divu  s0, s0, t1                ; ...
        li    t1, 512                   ; no less than 512 ...
        bgeu  s0, t1, sm_1              ; ...
        mv    s0, t1                    ; ...
sm_1:   li    t1, 4096                  ; ... no more than 4096
        bleu  s0, t1, sm_2              ; ...
        mv    s0, t1                    ; ...
sm_2:   li    s1, 16                    ; ...
sm_b:   la    t0, snd_ch                ; anything sounding?
        li    t1, SND_NCH               ; ...
        li    t2, 0                     ; ...
sm_a:   ld    t3, CH_LEFT(t0)           ; ...
        or    t2, t2, t3                ; ...
        addi  t0, t0, CH_SIZE           ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, sm_a                  ; ...
        beqz  t2, sm_r                  ; no: the queue runs out into silence
        la    t0, snd_reg               ; the device's STATUS: samples queued
        li    t1, SND_R_STAT            ; ...
        li    t2, 8                     ; ...
        tget  tg8, t0, c4, t1, t2       ; ...
        lwu   t1, 0(t0)                 ; (waits for the read)
        bgeu  t1, s0, sm_r              ; enough
        la    t0, snd_mix               ; a block of silence ...
        li    t1, SND_BLOCK / 4         ; ...
sm_z:   sd    zero, 0(t0)               ; ...
        addi  t0, t0, 8                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, sm_z                  ; ...
        la    s2, snd_ch                ; ... and every sounding channel added to it
sm_c:   ld    t1, CH_LEFT(s2)           ; ...
        beqz  t1, sm_n                  ; ...
        li    t2, SND_BLOCK             ; t1 = samples of it in this block (whole words:
        bleu  t1, t2, sm_c1             ;   the sounds' lengths are)
        mv    t1, t2                    ; ...
sm_c1:  ld    t2, CH_POS(s2)            ; fetch them
        la    t3, snd_in                ; ...
        tget  tg8, t3, c0, t2, t1       ; ...
        add   t2, t2, t1                ; ...
        sd    t2, CH_POS(s2)            ; ...
        ld    t2, CH_LEFT(s2)           ; ...
        sub   t2, t2, t1                ; ...
        sd    t2, CH_LEFT(s2)           ; ...
        la    t4, snd_mix               ; ...
        li    a0, 32767                 ; a0, a1 = the limits of a sample
        li    a1, -32768                ; ...
sm_s:   lb    t5, 0(t3)                 ; a sample, times 128, added and clipped
        slli  t5, t5, 7                 ; ...
        lh    t6, 0(t4)                 ; ...
        add   t6, t6, t5                ; ...
        ble   t6, a0, sm_s1             ; ...
        mv    t6, a0                    ; ...
sm_s1:  bge   t6, a1, sm_s2             ; ...
        mv    t6, a1                    ; ...
sm_s2:  sh    t6, 0(t4)                 ; ...
        addi  t3, t3, 1                 ; ...
        addi  t4, t4, 2                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, sm_s                  ; ...
sm_n:   addi  s2, s2, CH_SIZE           ; ...
        la    t0, snd_ch + SND_NCH * CH_SIZE ; ...
        bne   s2, t0, sm_c              ; ...
        la    t0, snd_mix               ; the block, to the device's PCM port
        li    t1, SND_BLOCK * 2         ; ...
        tput  tg9, t0, c4, zero, t1     ; (the next block's stores wait for it)
        addi  s1, s1, -1                ; ...
        bnez  s1, sm_b                  ; ...
sm_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done
