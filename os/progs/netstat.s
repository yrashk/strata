; =============================================================================
; netstat.s: the network server's sockets
; =============================================================================
;
;   netstat
;
; One line per socket: protocol, local and remote address and port, the TCP
; state, bytes received and not yet read, bytes sent and not yet
; acknowledged, retransmissions, and the owner's pid. Starts the network
; server if none runs (os/lib/sys.s net_init).

        .data                           ; data Local Store
        .align 8                        ; ...
st:     .space 64 + 32 * 8              ; STAT's data
s_nonet: .ascii "netstat: no network server\n" ; ...
s_nonet_e:
s_head: .ascii "proto local                 remote                state        recv  send  rexmit  pid\n" ; ...
s_head_e:
s_tcp:  .ascii "tcp   "                 ; ...
s_udp:  .ascii "udp   "                 ; ...
s_any:  .ascii "*"                      ; ...
s_states: .ascii "?          "          ; 11 bytes per state name (0..12)
        .ascii "CLOSED     "            ; (11 shown)
        .ascii "-          "            ; ...
        .ascii "LISTEN     "            ; ...
        .ascii "SYN-SENT   "            ; ...
        .ascii "SYN-RCVD   "            ; ...
        .ascii "ESTABLISHED"            ; ...
        .ascii "FIN-WAIT-1 "            ; ...
        .ascii "FIN-WAIT-2 "            ; ...
        .ascii "CLOSE-WAIT "            ; ...
        .ascii "CLOSING    "            ; ...
        .ascii "LAST-ACK   "            ; ...
        .ascii "TIME-WAIT  "            ; ...
        .align 8                        ; ...

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        call  sys_init                  ; ...
        call  net_init                  ; the network server
        bnez  a0, m_nonet               ; ...
        la    a0, st                    ; ...
        call  net_stat                  ; s2 = sockets
        bltz  a0, m_nonet               ; ...
        mv    s2, a0                    ; ...
        la    a0, s_head                ; ...
        li    a1, s_head_e - s_head     ; ...
        call  out_str                   ; ...
        la    s1, st + 64               ; s1 = the record
m_l:
        beqz  s2, m_end                 ; ...
        lbu   t0, 2(s1)                 ; protocol
        la    a0, s_tcp                 ; ...
        li    t1, 17                    ; ...
        bne   t0, t1, m_p               ; ...
        la    a0, s_udp                 ; ...
m_p:
        li    a1, 6                     ; ...
        call  out_str                   ; ...
        la    t0, st                    ; local: our address and port, 22 columns
        ld    a0, 0(t0)                 ; ...
        lwu   t1, 8(s1)                 ; (to 127.x.x.x: that address talks to itself)
        srli  t2, t1, 24                ; ...
        li    t3, 127                   ; ...
        bne   t2, t3, m_lo              ; ...
        mv    a0, t1                    ; ...
m_lo:
        lhu   a1, 4(s1)                 ; ...
        call  pr_addr                   ; ...
        li    a0, 22                    ; ...
        call  pad_to                    ; ...
        lwu   a0, 8(s1)                 ; remote, 22 columns (* for none)
        lhu   a1, 6(s1)                 ; ...
        call  pr_addr                   ; ...
        li    a0, 22                    ; ...
        call  pad_to                    ; ...
        lbu   t0, 1(s1)                 ; the state
        li    t1, 12                    ; ...
        bleu  t0, t1, m_s               ; ...
        li    t0, 0                     ; ...
m_s:
        li    t1, 11                    ; ...
        mul   t0, t0, t1                ; ...
        la    a0, s_states              ; ...
        add   a0, a0, t0                ; ...
        li    a1, 11                    ; ...
        call  out_str                   ; ...
        lwu   a0, 16(s1)                ; received, not read
        li    a1, 6                     ; ...
        call  out_decw                  ; ...
        lwu   a0, 20(s1)                ; sent, not acknowledged
        li    a1, 6                     ; ...
        call  out_decw                  ; ...
        lwu   a0, 28(s1)                ; retransmissions
        li    a1, 8                     ; ...
        call  out_decw                  ; ...
        lwu   a0, 12(s1)                ; the owner
        li    a1, 5                     ; ...
        call  out_decw                  ; ...
        call  out_nl                    ; ...
        addi  s1, s1, 32                ; ...
        addi  s2, s2, -1                ; ...
        j     m_l                       ; ...
m_end:
        li    a0, 0                     ; ...
        call  sys_exit                  ; ...
m_nonet:
        la    a0, s_nonet               ; ...
        li    a1, s_nonet_e - s_nonet   ; ...
        call  err_str                   ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...

; pr_addr(a0 = address, a1 = port): "a.b.c.d:port", "*" for 0; counts its columns
pr_addr:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a1, 8(sp)                 ; ...
        sd    a0, 16(sp)                ; ...
        call  out_flush                 ; (the columns are counted from the buffer)
        ld    a0, 16(sp)                ; ...
        beqz  a0, pa_any                ; ...
        call  out_ip                    ; ...
        j     pa_p                      ; ...
pa_any:
        la    a0, s_any                 ; ...
        li    a1, 1                     ; ...
        call  out_str                   ; ...
pa_p:
        li    a0, ':'                   ; ...
        call  out_chr                   ; ...
        ld    a0, 8(sp)                 ; ...
        beqz  a0, pa_pany               ; ...
        call  out_dec                   ; ...
        j     pa_ret                    ; ...
pa_pany:
        la    a0, s_any                 ; ...
        li    a1, 1                     ; ...
        call  out_str                   ; ...
pa_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; pad_to(a0 = width): spaces up to that many columns since pr_addr began
pad_to:
        la    t0, out_len               ; columns written since the flush
        ld    t0, 0(t0)                 ; ...
        sub   a0, a0, t0                ; ...
        j     out_pad                   ; (tail call)

        .include "../lib/sys.s"         ; the program library
