; rd_byte() -> a0 = the next input byte, -1 at the end of input, -2 interrupted
rd_byte:
        ld    t0, kb_pos(zero)          ; one waiting?
        ld    t1, kb_len(zero)          ; ...
        bltu  t0, t1, rb_have           ; yes
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save ra
        call  out_flush                 ; the screen is up to date before we wait
        li    a0, 0                     ; read standard input (raw: what is there)
        li    a1, kbuf                  ; ...
        li    a2, 64                    ; ...
        call  sys_read                  ; a0 = bytes, 0 the end, -2 interrupted
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 8                 ; release the frame
        sd    zero, kb_pos(zero)        ; the buffer starts again
        sd    zero, kb_len(zero)        ; ...
        bgtz  a0, rb_got                ; bytes
        li    t0, -2                    ; interrupted: -2
        beq   a0, t0, rb_r              ; ...
        li    a0, -1                    ; the end of input
rb_r:   ret                             ; done
rb_got: sd    a0, kb_len(zero)          ; ...
        li    t0, 0                     ; the first
rb_have:
        lbu   a0, kbuf(t0)              ; the byte
        addi  t0, t0, 1                 ; consumed
        sd    t0, kb_pos(zero)          ; ...
        ret                             ; done

; rd_wait(a0 = polls) -> a0 = 1 if an input byte is waiting (asking without
; blocking up to a0 times more, 2 ms apart), 0 if none came
rd_wait:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = polls left
        mv    s0, a0                    ; ...
rw_l:   ld    t0, kb_pos(zero)          ; one waiting?
        ld    t1, kb_len(zero)          ; ...
        li    a0, 1                     ; ...
        bltu  t0, t1, rw_r              ; yes
        call  out_flush                 ; (the screen first)
        li    a0, 0                     ; ask standard input without blocking
        li    a1, kbuf                  ; ...
        li    a2, 64                    ; ...
        call  sys_readnb                ; a0 = bytes, -3 none yet, 0 the end, -2
        blez  a0, rw_no                 ; ...
        sd    a0, kb_len(zero)          ; bytes
        sd    zero, kb_pos(zero)        ; ...
        li    a0, 1                     ; ...
        j     rw_r                      ; ...
rw_no:  li    t0, -3                    ; nothing yet: wait and ask again
        bne   a0, t0, rw_0              ; (the end, an interrupt: stop)
        beqz  s0, rw_0                  ; no polls left
        addi  s0, s0, -1                ; ...
        li    a0, 2000                  ; 2 ms
        call  sys_sleep                 ; -8, or -2 interrupted
        li    t0, -2                    ; interrupted: that is a Ctrl-C for getkey
        bne   a0, t0, rw_l              ; ...
        li    t0, 1                     ; ...
        sd    t0, sys_intrf(zero)       ; ...
rw_0:   li    a0, 0                     ; none
rw_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 16                ; release the frame
        ret                             ; done

; getkey() -> a0 = the next key: a byte, or K_* for the arrows and editing
; keys (escape sequences), K_EOF at the end of input, K_SIZE after a size
; report (the size is set). An interrupt is the key 3 (Ctrl-C). The keys of
; . come first; every key is recorded (recbuf) for . to repeat.
getkey:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0, s1 = numbers of a sequence
        sd    s1, 16(sp)                ; ...
gk_top: ld    a0, k_pend(zero)          ; a key put back?
        beqz  a0, gk_rq                 ; ...
        sd    zero, k_pend(zero)        ; once
        j     gk_got                    ; ...
gk_rq:  ld    t0, rq_pos(zero)          ; replaying .?
        ld    t1, rq_len(zero)          ; ...
        bltu  t0, t1, gk_rp             ; yes
        ld    t2, v_dotn(zero)          ; again (a count before .)?
        beqz  t2, gk_in                 ; no
        addi  t2, t2, -1                ; ...
        sd    t2, v_dotn(zero)          ; ...
        li    t0, 0                     ; from the first key
gk_rp:  slli  t2, t0, 1                 ; the key
        lhu   a0, dotbuf(t2)            ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, rq_pos(zero)          ; ...
        j     gk_got                    ; ...
gk_in:  ld    t0, sys_intrf(zero)       ; an interrupt came while we were busy?
        beqz  t0, gk_rd                 ; ...
        sd    zero, sys_intrf(zero)     ; ...
        li    a0, 3                     ; Ctrl-C
        j     gk_got                    ; ...
gk_rd:  call  rd_byte                   ; a byte
        li    t0, -2                    ; interrupted: Ctrl-C
        bne   a0, t0, gk_b              ; ...
        sd    zero, sys_intrf(zero)     ; (seen)
        li    a0, 3                     ; ...
        j     gk_got                    ; ...
gk_b:   bgez  a0, gk_nd                 ; the end of input (a pipe's writer is gone)
        li    a0, K_EOF                 ; ...
        j     gk_got                    ; ...
gk_nd:  li    t0, 27                    ; ESC: the start of a sequence?
        bne   a0, t0, gk_got            ; ...
        li    a0, 15                    ; a byte within 30 ms ...
        call  rd_wait                   ; ...
        beqz  a0, gk_esc                ; ...
        call  rd_byte                   ; ... that is "["
        li    t0, '['                   ; ...
        beq   a0, t0, gk_csi            ; ...
        ld    t0, kb_pos(zero)          ; no: that byte is the next key
        addi  t0, t0, -1                ; ...
        sd    t0, kb_pos(zero)          ; ...
gk_esc: li    a0, 27                    ; the Esc key
        j     gk_got                    ; ...
gk_csi: li    s0, 0                     ; ESC [: s0 = the number being read
        li    s1, 0                     ; s1 = the one before it
gk_cn:  call  rd_byte                   ; the next byte of the sequence
        bltz  a0, gk_top                ; (the end, an interrupt: the sequence is dropped)
        addi  t0, a0, -'0'              ; a digit?
        li    t1, 10                    ; ...
        bgeu  t0, t1, gk_cs             ; ...
        mul   s0, s0, t1                ; ...
        add   s0, s0, t0                ; ...
        j     gk_cn                     ; ...
gk_cs:  li    t1, ';'                   ; a separator
        bne   a0, t1, gk_cf             ; ...
        mv    s1, s0                    ; ...
        li    s0, 0                     ; ...
        j     gk_cn                     ; ...
gk_cf:  li    t1, 0x40                  ; other bytes below the final one ("?"): skipped
        blt   a0, t1, gk_cn             ; ...
        li    t1, 'R'                   ; ESC [ rows ; columns R: the size
        bne   a0, t1, gk_ct             ; ...
        mv    a0, s1                    ; ...
        mv    a1, s0                    ; ...
        call  set_size                  ; ...
        li    a0, K_SIZE                ; ...
        j     gk_got                    ; ...
gk_ct:  li    t1, '~'                   ; ESC [ n ~: Home End Delete PgUp PgDn
        bne   a0, t1, gk_cl             ; ...
        li    t1, 9                     ; ...
        bgeu  s0, t1, gk_top            ; ...
        lbu   a0, tildes(s0)            ; ...
        beqz  a0, gk_top                ; ...
        addi  a0, a0, 0x100             ; ...
        j     gk_got                    ; ...
gk_cl:  li    t1, 0                     ; ESC [ A..D H F: arrows, Home, End
gk_cl1: lbu   t2, csilet(t1)            ; ...
        addi  t1, t1, 1                 ; ...
        beq   t2, a0, gk_cl2            ; ...
        li    t3, 6                     ; ...
        blt   t1, t3, gk_cl1            ; ...
        j     gk_top                    ; anything else: ignored
gk_cl2: addi  a0, t1, 0x100             ; K_UP + index
gk_got: ld    t0, rec_len(zero)         ; recorded
        li    t1, 256                   ; ...
        bgeu  t0, t1, gk_ret            ; ...
        slli  t1, t0, 1                 ; ...
        sh    a0, recbuf(t1)            ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, rec_len(zero)         ; ...
gk_ret: ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; release the frame
        ret                             ; done

; readline(a0 = prompt character) -> a0 = the length of the line typed on the
; status row (in cmdbuf), -1 if it was abandoned (Esc, Ctrl-C, Backspace on
; an empty line)
readline:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = the prompt
        sd    s1, 16(sp)                ; s1 = length
        mv    s0, a0                    ; ...
        li    s1, 0                     ; ...
rl_dr:  ld    a0, v_rows(zero)          ; the status row: prompt, the line, cursor at its end
        addi  a0, a0, -1                ; ...
        li    a1, 0                     ; ...
        call  o_goto                    ; ...
        mv    a0, s0                    ; ...
        call  out_chr                   ; ...
        li    a0, cmdbuf                ; ...
        mv    a1, s1                    ; ...
        call  out_str                   ; ...
        call  o_el                      ; ...
rl_k:   call  getkey                    ; a key
        li    t0, 10                    ; Enter: done
        beq   a0, t0, rl_ok             ; ...
        li    t0, 13                    ; ...
        beq   a0, t0, rl_ok             ; ...
        li    t0, 27                    ; Esc, Ctrl-C: abandoned
        beq   a0, t0, rl_no             ; ...
        li    t0, 3                     ; ...
        beq   a0, t0, rl_no             ; ...
        li    t0, K_EOF                 ; ...
        beq   a0, t0, rl_no             ; ...
        li    t0, 127                   ; Backspace
        beq   a0, t0, rl_bs             ; ...
        li    t0, 8                     ; ...
        beq   a0, t0, rl_bs             ; ...
        addi  t0, a0, -32               ; printable: appended
        li    t1, 95                    ; ...
        bgeu  t0, t1, rl_k              ; (anything else: ignored)
        li    t0, 120                   ; (room?)
        bgeu  s1, t0, rl_k              ; ...
        sb    a0, cmdbuf(s1)            ; ...
        addi  s1, s1, 1                 ; ...
        call  out_chr                   ; (shown)
        j     rl_k                      ; ...
rl_bs:  beqz  s1, rl_no                 ; nothing left: abandoned
        addi  s1, s1, -1                ; ...
        j     rl_dr                     ; ...
rl_no:  li    s1, -1                    ; ...
rl_ok:  mv    a0, s1                    ; the result (refresh draws the status row again)
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; release the frame
        ret                             ; done

