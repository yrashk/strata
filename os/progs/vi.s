; o_s(a0 = string: a length byte, then the bytes)
o_s:    lbu   a1, 0(a0)                 ; the length
        addi  a0, a0, 1                 ; the bytes
        j     out_str                   ; (tail call)

; o_el(): erase to the end of the row
o_el:   li    a0, s_el                  ; ESC [ K
        j     o_s                       ; (tail call)

; o_goto(a0 = row, a1 = column, both from 0): ESC [ r ; c H
o_goto:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    a0, 8(sp)                 ; row
        sd    a1, 16(sp)                ; column
        li    a0, s_csi                 ; ESC [
        call  o_s                       ; ...
        ld    a0, 8(sp)                 ; row + 1
        addi  a0, a0, 1                 ; ...
        call  out_dec                   ; ...
        li    a0, ';'                   ; ...
        call  out_chr                   ; ...
        ld    a0, 16(sp)                ; column + 1
        addi  a0, a0, 1                 ; ...
        call  out_dec                   ; ...
        li    a0, 'H'                   ; ...
        call  out_chr                   ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 24                ; release the frame
        ret                             ; done

; o_sgr(a0 = n): ESC [ n m (a colour)
o_sgr:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    a0, 8(sp)                 ; n
        li    a0, s_csi                 ; ESC [
        call  o_s                       ; ...
        ld    a0, 8(sp)                 ; n
        call  out_dec                   ; ...
        li    a0, 'm'                   ; ...
        call  out_chr                   ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 16                ; release the frame
        ret                             ; done

; msg_s(a0 = string with its length byte): the message is that
msg_s:  sd    zero, v_msgl(zero)        ; a new message
; m_s(a0 = string with its length byte): appended to the message
m_s:    lbu   a1, 0(a0)                 ; ...
        addi  a0, a0, 1                 ; ...
; m_add(a0 = bytes, a1 = length): appended to the message (120 bytes at most)
m_add:  ld    t0, v_msgl(zero)          ; ...
ma_l:   beqz  a1, ma_r                  ; ...
        li    t1, 120                   ; ...
        bgeu  t0, t1, ma_r              ; ...
        lbu   t2, 0(a0)                 ; ...
        sb    t2, msgbuf(t0)            ; ...
        addi  t0, t0, 1                 ; ...
        addi  a0, a0, 1                 ; ...
        addi  a1, a1, -1                ; ...
        j     ma_l                      ; ...
ma_r:   sd    t0, v_msgl(zero)          ; ...
        ret                             ; done

; m_chr(a0 = byte): appended to the message
m_chr:  li    t0, tbuf                  ; (one byte of scratch: tbuf's last)
        addi  t0, t0, LMAX + 15         ; ...
        sb    a0, 0(t0)                 ; ...
        mv    a0, t0                    ; ...
        li    a1, 1                     ; ...
        j     m_add                     ; (tail call)

; m_dec(a0 = n): its decimal digits appended to the message
m_dec:  li    t0, sys_num_end           ; build them right to left (the library's scratch)
        li    t1, 10                    ; ...
md_l:   remu  t2, a0, t1                ; ...
        divu  a0, a0, t1                ; ...
        addi  t2, t2, '0'               ; ...
        addi  t0, t0, -1                ; ...
        sb    t2, 0(t0)                 ; ...
        bnez  a0, md_l                  ; ...
        mv    a0, t0                    ; ...
        li    a1, sys_num_end           ; ...
        sub   a1, a1, t0                ; ...
        j     m_add                     ; (tail call)

; m_name(): the message is "NAME" (the file's name in quotes)
m_name: addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    zero, v_msgl(zero)        ; a new message
        li    a0, '"'                   ; ...
        call  m_chr                     ; ...
        li    a0, fname                 ; ...
        ld    a1, v_fnl(zero)           ; ...
        call  m_add                     ; ...
        li    a0, '"'                   ; ...
        call  m_chr                     ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 8                 ; release the frame
        ret                             ; done

; m_size(): " N lines, B bytes" appended to the message
m_size: addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save ra
        li    a0, ' '                   ; ...
        call  m_chr                     ; ...
        ld    a0, v_nl(zero)            ; ...
        call  m_dec                     ; ...
        li    a0, s_lines               ; ...
        call  m_s                       ; ...
        li    a0, ' '                   ; ...
        call  m_chr                     ; ...
        call  buf_bytes                 ; ...
        call  m_dec                     ; ...
        li    a0, s_bytes               ; ...
        call  m_s                       ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 8                 ; release the frame
        ret                             ; done

