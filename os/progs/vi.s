; =============================================================================
; vi.s: a text editor in the manner of vi, with Strata syntax highlighting
; =============================================================================
;
;   vi [FILE]           edit FILE (a path: /src/hello.s, or under the current
;                       tag path); a FILE that does not exist is created by :w
;
; It runs on the console (an ANSI terminal: `make boot`, the browser's
; terminal) and in the window server's terminal (`term`). The screen is the
; text, one row per line (long lines scroll sideways, as with vim's
; nowrap), and a status line at the bottom: the mode, the file name, [+]
; when modified, and line,column; messages and the : and / lines take its
; place.
;
; Keys (a count before a command repeats it or scales it: 3dd, 5j, 2dw):
;   moving       h j k l (and the arrows), w b e, 0 ^ $, gg G, NG, %,
;                Enter + -, Space, Backspace, Ctrl-D/U (half a screen),
;                Ctrl-F/B (a screen), Home/End, PgUp/PgDn
;   inserting    i a I A o O; in insert mode Enter splits the line,
;                Backspace and Delete erase, the arrows move; Esc (or
;                Ctrl-C) ends it
;   changing     x X r D C s S J, d c y with a motion (dw, cw, d$, c$, dG,
;                y3j ...) or doubled (dd cc yy: whole lines), Y, p P
;                (characters into the line, lines below / above), u (undo,
;                many levels), Ctrl-R (redo), . (the last change again)
;   searching    /text ?text (plain text, not a pattern), n N
;   :commands    :w  :w NAME  :q  :q!  :wq  :x  ZZ  :e NAME  :e!  :N (line N)
;                :set nu / :set nonu (line numbers), :syntax on / off
;   other        Ctrl-L (ask the terminal its size, draw everything again),
;                Ctrl-G (file name and lines). Ctrl-C does not end vi: it
;                cancels what is being typed (and ends insert mode).
;
; Highlighting. A file whose name ends in .s is Strata assembly, .fs Strata
; Forth; another name is plain text unless the file carries the tag src
; (assembly) or forth. The rules are the site's (site/hl.js): assembly
; colours comments, labels, NAME = constants and CAPITALS, mnemonics by
; category (ALU, memory, branch, transfer, capability, system, paging,
; pseudo-instructions), directives (a word starting with "."), x and c
; registers and transfer tags, CSR names after csrr / csrw, numbers and
; strings; Forth colours \ and ( ) comments (a ( comment may go on over
; lines: the state at the start of each row is kept), : ; and the other
; defining words and the names they define, control words, the Strata
; words, numbers, strings and locals. The keyword tables are generated at
; build time (tools/vi-syntax.py writes build/vi-syntax.s) from asm/sasm.c,
; lang/forth/README.md and site/hl.js, the sources the site uses, and the
; site's colours are mapped to the terminal's 16 (sgrtab below).
;
; Screen size. vi asks the terminal: it moves the cursor to row 999, column
; 999 and sends ESC [ 6 n; an ANSI terminal, the browser's and the window
; server's (os/ws/term.s) answer ESC [ row ; column R with where the cursor
; stopped, the bottom right corner. Without an answer within 0.2 s (or
; when a key comes first, as from a script) it is 80 x 24. Ctrl-L asks
; again, and an answer that comes at any time resizes the screen.
;
; Drawing. Only what changed is sent: the rows of lines that changed (the
; ones below too when lines come or go) and the status line; a move within
; the screen sends just the status line and the cursor. Scrolling draws the
; text rows again: the two terminals vi runs in have no cheaper common way
; (the window server's terminal redraws every row of its grid on a scroll
; anyway). The cursor is hidden while a frame is drawn (ESC [ ? 25 l / h).
;
; Keys arrive one byte at a time on the console, so an Esc is told from
; the start of an escape sequence (an arrow: ESC [ A) by time: a "[" within
; 30 ms makes a sequence. The console server reads one byte ahead for a
; reader that polls in raw mode (os/servers/tty.s), which is what lets vi
; wait for it; in a window, the server's terminal gets a key's bytes
; together. (The window server's Alt bindings have bytes of their own,
; ESC [ 27 ; 3 ; code ~, spec 1.4: Esc and then p is Esc and p in vi.)
;
; Ctrl-C: vi catches interrupts (sys_catch), so the tty's or the window
; server's interrupt makes its read return -2 instead of ending it; that is
; the key Ctrl-C to vi, as in the shell.
;
; Where the text lives. The D-LS holds only the line being edited, one chunk
; and the screen's state; the text is in far memory, the program's arena,
; moved with transfers (tag tg1), as the terminal keeps its far scrollback:
;   [0, 0x80000)        the text: 256 chunks of 2 KiB, each a run of whole
;                       lines ending in newlines, in the order of the chunk
;                       table (ctab: store number, bytes, lines); a chunk
;                       that fills is split, one that empties is freed, a
;                       small one takes in the next
;   [0x80000, 0xB8000)  the undo history (224 KiB): a record per change,
;                       {size, first line, old count, new count, cursor},
;                       the old lines and the new ones, size again; the
;                       oldest records go when it is full
;   [0xB8000, 0xD0000)  the register (96 KiB): the lines or the characters
;                       that y, d, c, x took
; Limits: about 500 KiB of text (the text pool, less the unused ends of
; chunks), lines of at most 1000 bytes (a longer line is split when the
; file is read), 96 KiB in the register, changes that fit in the 224 KiB of
; undo history (a bigger one cannot be undone, and the history before it
; goes). The file server holds a file being written in 128 KiB, so :w
; refuses a bigger buffer before touching the file. A file is written with
; a newline after every line.

