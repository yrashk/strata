; syn_detect(): the highlighting for the file: by its name (.s, .fs), else
; by its tags (src, forth)
syn_detect:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = records left
        sd    s1, 16(sp)                ; s1 = record
        li    t0, 1                     ; draw again
        sd    t0, v_dall(zero)          ; ...
        sd    zero, v_syn(zero)         ; ...
        ld    t0, v_fnl(zero)           ; ...
        li    t1, 3                     ; ".fs"
        blt   t0, t1, sy_s              ; ...
        lbu   t2, fname-3(t0)           ; ...
        li    t3, '.'                   ; ...
        bne   t2, t3, sy_s              ; ...
        lbu   t2, fname-2(t0)           ; ...
        li    t3, 'f'                   ; ...
        bne   t2, t3, sy_s              ; ...
        lbu   t2, fname-1(t0)           ; ...
        li    t3, 's'                   ; ...
        bne   t2, t3, sy_s              ; ...
        li    t4, 2                     ; ...
        j     sy_set                    ; ...
sy_s:   li    t1, 2                     ; ".s"
        blt   t0, t1, sy_t              ; ...
        lbu   t2, fname-2(t0)           ; ...
        li    t3, '.'                   ; ...
        bne   t2, t3, sy_t              ; ...
        lbu   t2, fname-1(t0)           ; ...
        li    t3, 's'                   ; ...
        bne   t2, t3, sy_t              ; ...
        li    t4, 1                     ; ...
        j     sy_set                    ; ...
sy_t:   beqz  t0, sy_r                  ; the file's tags
        li    a0, sbuf                  ; (64 records of 32 bytes: sbuf holds them)
        li    a1, fname                 ; ...
        mv    a2, t0                    ; ...
        call  sys_tags                  ; ...
        mv    s0, a0                    ; ...
        li    s1, sbuf                  ; ...
sy_l:   blez  s0, sy_r                  ; ...
        mv    a0, s1                    ; its name
        li    a1, 16                    ; ...
        call  str_len                   ; ...
        mv    a1, a0                    ; forth?
        mv    a0, s1                    ; ...
        li    a2, s_forth + 1           ; ...
        li    a3, 5                     ; ...
        call  str_eq                    ; ...
        li    t4, 2                     ; ...
        bnez  a0, sy_set                ; ...
        mv    a0, s1                    ; src?
        li    a1, 16                    ; ...
        call  str_len                   ; ...
        mv    a1, a0                    ; ...
        mv    a0, s1                    ; ...
        li    a2, s_src + 1             ; ...
        li    a3, 3                     ; ...
        call  str_eq                    ; ...
        li    t4, 1                     ; ...
        bnez  a0, sy_set                ; ...
        addi  s1, s1, 32                ; ...
        addi  s0, s0, -1                ; ...
        j     sy_l                      ; ...
sy_set: sd    t4, v_syn(zero)           ; ...
sy_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 32                ; release the frame
        ret                             ; done

; do_load(a0 = name, a1 = length; 0: none): the buffer is that file (one
; that does not exist: empty, written by :w)
do_load:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = handle
        sd    s1, 16(sp)                ; s1 = bytes read into in_buf
        sd    s2, 24(sp)                ; s2 = the next of them
        sd    s3, 32(sp)                ; s3 = 1: the pool filled up
        sd    a1, v_fnl(zero)           ; the name
        mv    a2, a1                    ; ...
        mv    a1, a0                    ; ...
        li    a0, fname                 ; ...
        call  bmove                     ; ...
        call  buf_reset                 ; no text
        li    s3, 0                     ; ...
        sd    zero, v_lblen(zero)       ; the line being read (in lbuf)
        ld    a1, v_fnl(zero)           ; a file?
        beqz  a1, dl_e                  ; ...
        li    a0, fname                 ; ...
        li    a2, 0                     ; ...
        call  sys_open                  ; ...
        mv    s0, a0                    ; ...
        bgez  a0, dl_r                  ; ...
        call  m_name                    ; none: a new file
        li    a0, s_newf                ; ...
        call  m_s                       ; ...
        j     dl_e                      ; ...
dl_r:   mv    a0, s0                    ; a piece of it
        la    a1, in_buf                ; (the library's input buffer: unused by vi)
        li    a2, 4032                  ; ...
        call  sys_read                  ; ...
        blez  a0, dl_eof                ; ...
        mv    s1, a0                    ; ...
        li    s2, 0                     ; ...
dl_b:   bge   s2, s1, dl_r              ; each byte
        la    t0, in_buf                ; ...
        add   t0, t0, s2                ; ...
        lbu   t0, 0(t0)                 ; ...
        addi  s2, s2, 1                 ; ...
        li    t1, 10                    ; a newline ends a line
        beq   t0, t1, dl_ln             ; ...
        ld    t1, v_lblen(zero)         ; ...
        sb    t0, lbuf(t1)              ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, v_lblen(zero)         ; ...
        li    t2, LMAX                  ; (so does LMAX bytes of it)
        blt   t1, t2, dl_b              ; ...
dl_ln:  call  dl_add                    ; ...
        beqz  a0, dl_b                  ; ...
        li    s3, 1                     ; the pool is full
dl_eof: ld    t0, v_lblen(zero)         ; a last line without a newline
        beqz  t0, dl_c                  ; ...
        bnez  s3, dl_c                  ; ...
        call  dl_add                    ; ...
        snez  s3, a0                    ; ...
dl_c:   mv    a0, s0                    ; ...
        call  sys_close                 ; ...
        call  m_name                    ; "NAME" N lines, B bytes
        call  m_size                    ; ...
        beqz  s3, dl_e                  ; ...
        call  m_name                    ; (or that it did not all fit)
        li    a0, s_cut                 ; ...
        call  m_s                       ; ...
dl_e:   call  fixempty                  ; at least a line
        call  syn_detect                ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        addi  sp, sp, 40                ; release the frame
        ret                             ; done
dl_add: ld    a0, v_nl(zero)            ; lbuf -> a new last line
        li    a1, lbuf                  ; ...
        ld    a2, v_lblen(zero)         ; ...
        sd    zero, v_lblen(zero)       ; ...
        j     ln_ins                    ; (tail call)

; do_write(a0 = name, a1 = length) -> a0 = 0 / -1: the text into that file
do_write:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = name
        sd    s1, 16(sp)                ; s1 = its length
        sd    s2, 24(sp)                ; s2 = handle
        sd    s3, 32(sp)                ; s3 = line
        sd    s4, 40(sp)                ; s4 = bytes waiting in in_buf
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        call  buf_bytes                 ; more than the file server takes?
        li    t0, WMAX                  ; ...
        bleu  a0, t0, dw_o              ; ...
        li    a0, s_big                 ; ...
        call  msg_s                     ; ...
        j     dw_no                     ; ...
dw_o:   mv    a0, s0                    ; open it for writing
        mv    a1, s1                    ; ...
        li    a2, 1                     ; ...
        call  sys_open                  ; ...
        mv    s2, a0                    ; ...
        bltz  a0, dw_cant               ; ...
        li    s3, 0                     ; ...
        li    s4, 0                     ; ...
dw_l:   ld    t0, v_nl(zero)            ; every line
        bge   s3, t0, dw_end            ; ...
        mv    a0, s3                    ; ...
        call  ln_find                   ; ...
        add   t0, s4, a1                ; room for it and its newline?
        addi  t0, t0, 1                 ; ...
        li    t1, 4032                  ; ...
        bleu  t0, t1, dw_cp             ; ...
        call  dw_out                    ; no: what waits goes first
        bnez  a0, dw_wf                 ; ...
        mv    a0, s3                    ; (the line again)
        call  ln_find                   ; ...
dw_cp:  mv    a2, a1                    ; ...
        mv    a1, a0                    ; ...
        la    a0, in_buf                ; ...
        add   a0, a0, s4                ; ...
        add   s4, s4, a2                ; ...
        call  bmove                     ; ...
        la    t0, in_buf                ; ...
        add   t0, t0, s4                ; ...
        li    t1, 10                    ; ...
        sb    t1, 0(t0)                 ; ...
        addi  s4, s4, 1                 ; ...
        addi  s3, s3, 1                 ; ...
        j     dw_l                      ; ...
dw_end: call  dw_out                    ; the last piece
        bnez  a0, dw_wf                 ; ...
        mv    a0, s2                    ; done: the file server saves it
        call  sys_close                 ; ...
        sd    zero, v_msgl(zero)        ; "NAME" N lines, B bytes written
        li    a0, '"'                   ; ...
        call  m_chr                     ; ...
        mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        call  m_add                     ; ...
        li    a0, '"'                   ; ...
        call  m_chr                     ; ...
        call  m_size                    ; ...
        li    a0, s_wrtn                ; ...
        call  m_s                       ; ...
        li    a0, 0                     ; ...
        j     dw_r                      ; ...
dw_wf:  mv    a0, s2                    ; a write failed
        call  sys_close                 ; ...
dw_cant:
        li    a0, s_cant                ; ...
        call  msg_s                     ; ...
        mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        call  m_add                     ; ...
dw_no:  li    a0, -1                    ; ...
dw_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        addi  sp, sp, 48                ; release the frame
        ret                             ; done
dw_out: addi  sp, sp, -8                ; what waits in in_buf -> the file: a0 = 0 / -1
        sd    ra, 0(sp)                 ; ...
        mv    a0, s2                    ; ...
        la    a1, in_buf                ; ...
        mv    a2, s4                    ; ...
        call  sys_write                 ; ...
        sub   a0, a0, s4                ; all of it?
        snez  a0, a0                    ; ...
        neg   a0, a0                    ; ...
        li    s4, 0                     ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; done
