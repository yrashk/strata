c_slash:
        li    a0, 1                     ; / forward
        j     c_find                    ; ...
c_quest:
        li    a0, -1                    ; ? backward
c_find: addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = direction
        mv    s0, a0                    ; ...
        li    a0, '/'                   ; the text to look for
        bgtz  s0, cf_1                  ; ...
        li    a0, '?'                   ; ...
cf_1:   call  readline                  ; ...
        bltz  a0, cf_r                  ; ...
        beqz  a0, cf_2                  ; (nothing typed: the last one again)
        sd    a0, v_patl(zero)          ; ...
        mv    a2, a0                    ; ...
        li    a0, patbuf                ; ...
        li    a1, cmdbuf                ; ...
        call  bmove                     ; ...
cf_2:   sd    s0, v_sdir(zero)          ; ...
        mv    a0, s0                    ; ...
        call  search                    ; ...
        beqz  a0, cf_r                  ; ...
        ld    t0, mv_y(zero)            ; found: the cursor there
        sd    t0, v_cy(zero)            ; ...
        ld    t0, mv_x(zero)            ; ...
        sd    t0, v_cx(zero)            ; ...
cf_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 16                ; release the frame
        ret                             ; done

; c_colon(): a : command line: a line number, or a command [!] [argument]
c_colon:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = cursor
        sd    s1, 16(sp)                ; s1 = end
        sd    s2, 24(sp)                ; s2 = the command's start
        sd    s3, 32(sp)                ; s3 = its length
        li    a0, ':'                   ; ...
        call  readline                  ; ...
        blez  a0, cc_r                  ; ...
        li    s0, cmdbuf                ; ...
        add   s1, s0, a0                ; ...
        mv    a0, s0                    ; past blanks
        sub   a1, s1, s0                ; ...
        li    a2, 0                     ; ...
        call  skip_bl                   ; ...
        add   s0, s0, a0                ; ...
        mv    a0, s0                    ; a number: that line
        sub   a1, s1, s0                ; ...
        call  str_num                   ; ...
        bltz  a0, cc_w                  ; ...
        addi  t0, a0, -1                ; ...
        call  mo_line                   ; ...
        ld    a0, mv_y(zero)            ; ...
        sd    a0, v_cy(zero)            ; ...
        call  fnb                       ; ...
        sd    a0, v_cx(zero)            ; ...
        j     cc_r                      ; ...
cc_w:   mv    s2, s0                    ; the command: letters
cc_w1:  bgeu  s0, s1, cc_w2             ; ...
        lbu   t0, 0(s0)                 ; ...
        lbu   t0, ctype(t0)             ; ...
        andi  t0, t0, 1                 ; ...
        beqz  t0, cc_w2                 ; ...
        addi  s0, s0, 1                 ; ...
        j     cc_w1                     ; ...
cc_w2:  sub   s3, s0, s2                ; ...
        sd    zero, x_bang(zero)        ; "!"
        bgeu  s0, s1, cc_a              ; ...
        lbu   t0, 0(s0)                 ; ...
        li    t1, '!'                   ; ...
        bne   t0, t1, cc_a              ; ...
        li    t1, 1                     ; ...
        sd    t1, x_bang(zero)          ; ...
        addi  s0, s0, 1                 ; ...
cc_a:   mv    a0, s0                    ; the argument: after blanks, to the end
        sub   a1, s1, s0                ; ...
        li    a2, 0                     ; ...
        call  skip_bl                   ; ...
        add   t0, s0, a0                ; ...
        sd    t0, x_arg(zero)           ; ...
        sub   t1, s1, t0                ; ...
        sd    t1, x_argl(zero)          ; ...
        li    t0, 6                     ; which command? (6 letters at most)
        bgtu  s3, t0, cc_bad            ; ...
        beqz  s3, cc_bad                ; ...
        li    t0, extab                 ; ...
cc_t:   lbu   t1, 0(t0)                 ; ...
        beqz  t1, cc_bad                ; ...
        li    t2, 0                     ; the letters, and nothing after them
cc_t1:  add   t3, t0, t2                ; ...
        lbu   t3, 0(t3)                 ; ...
        beq   t2, s3, cc_t2             ; ...
        add   t4, s2, t2                ; ...
        lbu   t4, 0(t4)                 ; ...
        bne   t3, t4, cc_tn             ; ...
        addi  t2, t2, 1                 ; ...
        j     cc_t1                     ; ...
cc_t2:  li    t4, 6                     ; (all six used, or a zero next)
        beq   t2, t4, cc_go             ; ...
        beqz  t3, cc_go                 ; ...
cc_tn:  addi  t0, t0, 8                 ; ...
        j     cc_t                      ; ...
cc_go:  lhu   t1, 6(t0)                 ; ...
        jalr  ra, t1, 0                 ; ...
        j     cc_r                      ; ...
cc_bad: li    a0, s_notcmd              ; ...
        call  msg_s                     ; ...
        mv    a0, s2                    ; ...
        sub   a1, s1, s2                ; ...
        call  m_add                     ; ...
cc_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        addi  sp, sp, 40                ; release the frame
        ret                             ; done

; x_name() -> a0 = the file a : command names (its argument, else the
; buffer's), a1 = its length (0: none)
x_name: ld    a0, x_arg(zero)           ; ...
        ld    a1, x_argl(zero)          ; ...
        bnez  a1, xn_r                  ; ...
        li    a0, fname                 ; ...
        ld    a1, v_fnl(zero)           ; ...
xn_r:   ret                             ; done

; ex_w() -> a0 = 0 written / -1: :w [NAME]
ex_w:   addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save ra
        call  x_name                    ; which file?
        bnez  a1, xw_1                  ; ...
        li    a0, s_noname2             ; none
        call  msg_s                     ; ...
        li    a0, -1                    ; ...
        j     xw_r                      ; ...
xw_1:   call  do_write                  ; ...
        bnez  a0, xw_r                  ; ...
        ld    t0, v_fnl(zero)           ; the buffer's own file (or it had none)?
        beqz  t0, xw_nm                 ; ...
        ld    t0, x_argl(zero)          ; ...
        bnez  t0, xw_0                  ; ...
xw_s:   ld    t0, u_end(zero)           ; then the buffer is as written
        sd    t0, u_saved(zero)         ; ...
xw_0:   li    a0, 0                     ; ...
xw_r:   ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 8                 ; release the frame
        ret                             ; done
xw_nm:  li    a0, fname                 ; it takes the name
        ld    a1, x_arg(zero)           ; ...
        ld    a2, x_argl(zero)          ; ...
        sd    a2, v_fnl(zero)           ; ...
        call  bmove                     ; ...
        call  syn_detect                ; ...
        j     xw_s                      ; ...

; ex_wq: :wq; ex_x: :x and ZZ (written only if modified); ex_q: :q, :q!
ex_wq:  addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save ra
        call  ex_w                      ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 8                 ; release the frame
        bnez  a0, xq_r                  ; not written: stay
        j     xq_go                     ; ...
ex_x:   addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save ra
        call  is_mod                    ; ...
        beqz  a0, xx_q                  ; ...
        call  ex_w                      ; ...
xx_q:   ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 8                 ; release the frame
        bnez  a0, xq_r                  ; ...
        j     xq_go                     ; ...
ex_q:   ld    t0, x_bang(zero)          ; :q! leaves anyway
        bnez  t0, xq_go                 ; ...
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save ra
        call  is_mod                    ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 8                 ; release the frame
        beqz  a0, xq_go                 ; ...
        li    a0, s_nowr                ; modified: not without !
        j     msg_s                     ; (tail call)
xq_go:  li    t0, 1                     ; ...
        sd    t0, v_quit(zero)          ; ...
xq_r:   ret                             ; done

; ex_e: :e [NAME], :e! (a modified buffer needs the !)
ex_e:   ld    t0, x_bang(zero)          ; ...
        bnez  t0, xe_go                 ; ...
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save ra
        call  is_mod                    ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 8                 ; release the frame
        beqz  a0, xe_go                 ; ...
        li    a0, s_nowr                ; ...
        j     msg_s                     ; (tail call)
xe_go:  addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save ra
        call  x_name                    ; ...
        call  do_load                   ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 8                 ; release the frame
        ret                             ; done

; ex_set: :set nu | number | nonu | nonumber
ex_set: addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save ra
        li    a0, s_nu                  ; ...
        call  x_is                      ; ...
        li    t0, NUMW                  ; ...
        bnez  a0, xs_set                ; ...
        li    a0, s_number              ; ...
        call  x_is                      ; ...
        li    t0, NUMW                  ; ...
        bnez  a0, xs_set                ; ...
        li    a0, s_nonu                ; ...
        call  x_is                      ; ...
        li    t0, 0                     ; ...
        bnez  a0, xs_set                ; ...
        li    a0, s_nonumber            ; ...
        call  x_is                      ; ...
        li    t0, 0                     ; ...
        bnez  a0, xs_set                ; ...
        li    a0, s_noopt               ; ...
        call  msg_s                     ; ...
        ld    a0, x_arg(zero)           ; ...
        ld    a1, x_argl(zero)          ; ...
        call  m_add                     ; ...
        j     xs_r                      ; ...
xs_set: sd    t0, v_numw(zero)          ; ...
        call  size_upd                  ; ...
xs_r:   ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 8                 ; release the frame
        ret                             ; done

; ex_syn: :syntax on | off
ex_syn: addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save ra
        li    a0, s_on                  ; ...
        call  x_is                      ; ...
        li    t0, 1                     ; ...
        bnez  a0, xy_set                ; ...
        li    a0, s_off                 ; ...
        call  x_is                      ; ...
        li    t0, 0                     ; ...
        bnez  a0, xy_set                ; ...
        li    a0, s_noopt               ; ...
        call  msg_s                     ; ...
        j     xy_r                      ; ...
xy_set: sd    t0, v_synon(zero)         ; ...
        li    t0, 1                     ; ...
        sd    t0, v_dall(zero)          ; ...
xy_r:   ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 8                 ; release the frame
        ret                             ; done

; x_is(a0 = string with its length byte) -> a0 = 1 if the argument is it
x_is:   lbu   a3, 0(a0)                 ; ...
        addi  a2, a0, 1                 ; ...
        ld    a0, x_arg(zero)           ; ...
        ld    a1, x_argl(zero)          ; ...
        j     str_eq                    ; (tail call)

