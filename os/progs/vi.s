; set_size(a0 = rows, a1 = columns): the terminal's size (from its report)
set_size:
        li    t0, 3                     ; nonsense is ignored
        blt   a0, t0, ss_r              ; ...
        li    t0, 20                    ; ...
        blt   a1, t0, ss_r              ; ...
        li    t0, NROWS                 ; at most NROWS x NCOLS are used
        ble   a0, t0, ss_1              ; ...
        mv    a0, t0                    ; ...
ss_1:   li    t0, NCOLS                 ; ...
        ble   a1, t0, ss_2              ; ...
        mv    a1, t0                    ; ...
ss_2:   sd    a0, v_rows(zero)          ; ...
        sd    a1, v_cols(zero)          ; ...
        li    t0, 1                     ; the screen is cleared and drawn again
        sd    t0, v_clear(zero)         ; ...
size_upd:                               ; (also after :set nu)
        ld    t0, v_rows(zero)          ; text rows: all but the status line
        addi  t0, t0, -1                ; ...
        sd    t0, v_trows(zero)         ; ...
        ld    t0, v_cols(zero)          ; text columns: what the line numbers leave
        ld    t1, v_numw(zero)          ; ...
        sub   t0, t0, t1                ; ...
        sd    t0, v_tcols(zero)         ; ...
        li    t0, 1                     ; everything is drawn again
        sd    t0, v_dall(zero)          ; ...
ss_r:   ret                             ; done

; mark_row(a0 = line): its row (if it is on the screen) is drawn again
mark_row:
        ld    t0, v_top(zero)           ; row = line - top
        sub   t0, a0, t0                ; ...
        bltz  t0, mr_r                  ; above the screen
        ld    t1, v_trows(zero)         ; below it
        bge   t0, t1, mr_r              ; ...
        li    t1, 1                     ; ...
        sll   t1, t1, t0                ; ...
        ld    t2, v_dirty(zero)         ; ...
        or    t2, t2, t1                ; ...
        sd    t2, v_dirty(zero)         ; ...
mr_r:   ret                             ; done

; mark_from(a0 = line): its row and every row below are drawn again
mark_from:
        ld    t0, v_top(zero)           ; row = line - top (at least 0)
        sub   t0, a0, t0                ; ...
        bgez  t0, mf_1                  ; ...
        li    t0, 0                     ; ...
mf_1:   li    t1, 63                    ; ...
        bgtu  t0, t1, mf_r              ; ...
        li    t1, -1                    ; bits t0 .. 63
        sll   t1, t1, t0                ; ...
        ld    t2, v_dirty(zero)         ; ...
        or    t2, t2, t1                ; ...
        sd    t2, v_dirty(zero)         ; ...
mf_r:   ret                             ; done

; cur_text() -> a0 = the cursor's line, a1 = its length (lbuf in insert mode)
cur_text:
        ld    t0, v_lblive(zero)        ; being edited?
        beqz  t0, ct_f                  ; ...
        li    a0, lbuf                  ; ...
        ld    a1, v_lblen(zero)         ; ...
        ret                             ; done
ct_f:   ld    a0, v_cy(zero)            ; the stored line
        j     ln_find                   ; (tail call)

; fix_cursor(): the cursor within the text (normal mode: on a character)
fix_cursor:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save ra
        ld    t0, v_nl(zero)            ; line in [0, lines)
        ld    t1, v_cy(zero)            ; ...
        blt   t1, t0, fc_1              ; ...
        addi  t1, t0, -1                ; ...
fc_1:   bgez  t1, fc_2                  ; ...
        li    t1, 0                     ; ...
fc_2:   sd    t1, v_cy(zero)            ; ...
        call  cur_text                  ; a1 = its length
        ld    t0, v_ins(zero)           ; insert mode: up to the end; normal: the last byte
        bnez  t0, fc_3                  ; ...
        beqz  a1, fc_3                  ; ...
        addi  a1, a1, -1                ; ...
fc_3:   ld    t1, v_cx(zero)            ; ...
        ble   t1, a1, fc_4              ; ...
        mv    t1, a1                    ; ...
fc_4:   bgez  t1, fc_5                  ; ...
        li    t1, 0                     ; ...
fc_5:   sd    t1, v_cx(zero)            ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 8                 ; release the frame
        ret                             ; done

; view(): the screen follows the cursor: v_top (a jump far away centres the
; cursor's line), v_lcol; v_dcur = the cursor's column; v_want if asked
view:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save ra
        ld    t0, v_top(zero)           ; t0 = top, t1 = cursor line, t2 = text rows
        ld    t1, v_cy(zero)            ; ...
        ld    t2, v_trows(zero)         ; ...
        bge   t1, t0, vw_1              ; above the screen?
        add   t3, t1, t2                ; more than a screen above: centred
        blt   t3, t0, vw_mid            ; ...
        mv    t0, t1                    ; just above: at the top
        j     vw_set                    ; ...
vw_1:   add   t3, t0, t2                ; below it?
        blt   t1, t3, vw_h              ; no: on the screen
        add   t3, t3, t2                ; far below: centred
        bge   t1, t3, vw_mid            ; ...
        sub   t0, t1, t2                ; just below: at the bottom
        addi  t0, t0, 1                 ; ...
        j     vw_set                    ; ...
vw_mid: srli  t3, t2, 1                 ; the cursor's line in the middle
        sub   t0, t1, t3                ; ...
        bgez  t0, vw_set                ; ...
        li    t0, 0                     ; ...
vw_set: sd    t0, v_top(zero)           ; a new top: every row
        li    t3, 1                     ; ...
        sd    t3, v_dall(zero)          ; ...
vw_h:   call  cur_text                  ; the cursor's column
        ld    a1, v_cx(zero)            ; ...
        call  dcol                      ; ...
        sd    a0, v_dcur(zero)          ; ...
        ld    t0, v_setw(zero)          ; the column j and k aim for, from now on?
        beqz  t0, vw_h1                 ; ...
        sd    a0, v_want(zero)          ; ...
vw_h1:  ld    t0, v_lcol(zero)          ; within the columns shown?
        ld    t1, v_tcols(zero)         ; ...
        blt   a0, t0, vw_2              ; ...
        add   t2, t0, t1                ; ...
        blt   a0, t2, vw_r              ; ...
vw_2:   srli  t1, t1, 1                 ; no: half a screen to its left
        sub   t0, a0, t1                ; ...
        bgez  t0, vw_3                  ; ...
        li    t0, 0                     ; ...
vw_3:   sd    t0, v_lcol(zero)          ; ...
        li    t3, 1                     ; every row
        sd    t3, v_dall(zero)          ; ...
vw_r:   ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 8                 ; release the frame
        ret                             ; done

; dcol(a0 = text, a1 = byte index) -> a0 = that byte's column (tabs: to the
; next multiple of 8)
dcol:   li    t0, 0                     ; column
        li    t1, 0                     ; index
dc_l:   bge   t1, a1, dc_r              ; ...
        add   t2, a0, t1                ; ...
        lbu   t2, 0(t2)                 ; ...
        addi  t1, t1, 1                 ; ...
        li    t3, 9                     ; a tab
        bne   t2, t3, dc_1              ; ...
        ori   t0, t0, 7                 ; ...
dc_1:   addi  t0, t0, 1                 ; ...
        j     dc_l                      ; ...
dc_r:   mv    a0, t0                    ; ...
        ret                             ; done

; xcol(a0 = text, a1 = length, a2 = column) -> a0 = the last byte that starts
; at or before that column (0 for an empty line)
xcol:   li    t0, 0                     ; t0 = column of byte t1
        li    t1, 0                     ; ...
xc_l:   addi  t4, t1, 1                 ; the next byte exists?
        bge   t4, a1, xc_r              ; ...
        add   t2, a0, t1                ; its column
        lbu   t2, 0(t2)                 ; ...
        li    t3, 9                     ; ...
        mv    t5, t0                    ; ...
        bne   t2, t3, xc_1              ; ...
        ori   t5, t5, 7                 ; ...
xc_1:   addi  t5, t5, 1                 ; ...
        blt   a2, t5, xc_r              ; past the column: stop
        mv    t0, t5                    ; ...
        mv    t1, t4                    ; ...
        j     xc_l                      ; ...
xc_r:   mv    a0, t1                    ; ...
        ret                             ; done

; refresh(): bring the screen up to date: the rows marked, the status line,
; the cursor
refresh:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = row
        call  fix_cursor                ; ...
        call  view                      ; ...
        li    a0, s_hide                ; no cursor while drawing
        call  o_s                       ; ...
        ld    t0, v_clear(zero)         ; clear first (a new size)?
        beqz  t0, rf_a                  ; ...
        sd    zero, v_clear(zero)       ; ...
        li    a0, s_cls                 ; ...
        call  o_s                       ; ...
rf_a:   ld    t0, v_dall(zero)          ; every row?
        beqz  t0, rf_p                  ; ...
        sd    zero, v_dall(zero)        ; ...
        li    t0, -1                    ; ...
        sd    t0, v_dirty(zero)         ; ...
        call  fstate_top                ; (Forth: the state at the top line)
        sb    a0, rowst(zero)           ; ...
rf_p:   li    s0, 0                     ; the rows marked, from the top (drawing one may mark the next)
rf_l:   ld    t0, v_trows(zero)         ; ...
        bge   s0, t0, rf_s              ; ...
        ld    t1, v_dirty(zero)         ; ...
        srl   t1, t1, s0                ; ...
        andi  t1, t1, 1                 ; ...
        beqz  t1, rf_n                  ; ...
        mv    a0, s0                    ; ...
        call  draw_row                  ; ...
rf_n:   addi  s0, s0, 1                 ; ...
        j     rf_l                      ; ...
rf_s:   sd    zero, v_dirty(zero)       ; ...
        call  draw_status               ; the status line
        ld    t0, v_cy(zero)            ; the cursor
        ld    t1, v_top(zero)           ; ...
        sub   a0, t0, t1                ; ...
        ld    t0, v_dcur(zero)          ; ...
        ld    t1, v_lcol(zero)          ; ...
        sub   a1, t0, t1                ; ...
        ld    t0, v_numw(zero)          ; ...
        add   a1, a1, t0                ; ...
        call  o_goto                    ; ...
        li    a0, s_show                ; ...
        call  o_s                       ; ...
        sd    zero, v_setw(zero)        ; (asked once)
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 16                ; release the frame
        ret                             ; done

; draw_row(a0 = text row): its line (or "~" past the end), highlighted
draw_row:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = row
        sd    s1, 16(sp)                ; s1 = line
        sd    s2, 24(sp)                ; s2 = text
        sd    s3, 32(sp)                ; s3 = length
        mv    s0, a0                    ; ...
        li    a1, 0                     ; to its start
        call  o_goto                    ; ...
        ld    t0, v_top(zero)           ; the line
        add   s1, t0, s0                ; ...
        ld    t1, v_nl(zero)            ; past the end?
        blt   s1, t1, dr_l              ; ...
        li    a0, s_tilde               ; "~"
        call  o_s                       ; ...
        j     dr_el                     ; ...
dr_l:   ld    t0, v_numw(zero)          ; its number
        beqz  t0, dr_t                  ; ...
        li    a0, 33                    ; (yellow)
        call  o_sgr                     ; ...
        addi  a0, s1, 1                 ; ...
        li    a1, NUMW - 1              ; ...
        call  out_decw                  ; ...
        li    a0, s_nrst                ; ...
        call  o_s                       ; ...
dr_t:   ld    t0, v_cy(zero)            ; the cursor's line in insert mode: lbuf
        bne   t0, s1, dr_f              ; ...
        ld    t0, v_lblive(zero)        ; ...
        beqz  t0, dr_f                  ; ...
        li    s2, lbuf                  ; ...
        ld    s3, v_lblen(zero)         ; ...
        j     dr_h                      ; ...
dr_f:   mv    a0, s1                    ; the stored line
        call  ln_find                   ; ...
        mv    s2, a0                    ; ...
        mv    s3, a1                    ; ...
dr_h:   call  hl_on                     ; highlighting?
        mv    a2, a0                    ; (0: none)
        beqz  a0, dr_e                  ; ...
        mv    a0, s2                    ; the classes of its bytes; a0 = the state after it
        mv    a1, s3                    ; ...
        lbu   a2, rowst(s0)             ; ...
        call  hl_line                   ; ...
        lbu   t0, rowst+1(s0)           ; the next row starts in another state:
        beq   a0, t0, dr_e1             ;   it is drawn again too
        sb    a0, rowst+1(s0)           ; ...
        addi  t1, s0, 1                 ; ...
        li    t2, 1                     ; ...
        sll   t2, t2, t1                ; ...
        ld    t3, v_dirty(zero)         ; ...
        or    t3, t3, t2                ; ...
        sd    t3, v_dirty(zero)         ; ...
dr_e1:  li    a2, 1                     ; in colour
dr_e:   mv    a0, s2                    ; the text
        mv    a1, s3                    ; ...
        call  emit                      ; ...
dr_el:  call  o_el                      ; the rest of the row
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        addi  sp, sp, 40                ; release the frame
        ret                             ; done

; emit(a0 = text, a1 = length, a2 = 1: in the colours of cls): the columns
; of the view (v_lcol and v_tcols on), tabs as spaces, control bytes as "?"
emit:
        addi  sp, sp, -88               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = text
        sd    s1, 16(sp)                ; s1 = length
        sd    s2, 24(sp)                ; s2 = colours
        sd    s3, 32(sp)                ; s3 = byte index
        sd    s4, 40(sp)                ; s4 = column
        sd    s5, 48(sp)                ; s5 = the class shown
        sd    s6, 56(sp)                ; s6 = the first column shown
        sd    s7, 64(sp)                ; s7 = past the last
        sd    s8, 72(sp)                ; s8 = the byte shown
        sd    s9, 80(sp)                ; s9 = columns it takes
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        mv    s2, a2                    ; ...
        li    s3, 0                     ; ...
        li    s4, 0                     ; ...
        li    s5, 0                     ; (the row starts in the default colour)
        ld    s6, v_lcol(zero)          ; ...
        ld    t0, v_tcols(zero)         ; ...
        add   s7, s6, t0                ; ...
em_l:   bge   s3, s1, em_d              ; every byte
        add   t0, s0, s3                ; ...
        lbu   s8, 0(t0)                 ; ...
        li    s9, 1                     ; one column ...
        li    t0, 9                     ; ... or a tab's
        bne   s8, t0, em_c              ; ...
        ori   t1, s4, 7                 ; ...
        addi  t1, t1, 1                 ; ...
        sub   s9, t1, s4                ; ...
        li    s8, ' '                   ; ...
em_c:   addi  t0, s8, -32               ; printable?
        li    t1, 95                    ; ...
        bltu  t0, t1, em_cell           ; ...
        li    s8, '?'                   ; no
em_cell:
        bge   s4, s7, em_d              ; past the right edge: done
        blt   s4, s6, em_nx             ; left of the view
        beqz  s2, em_o                  ; a colour change?
        lbu   t0, cls(s3)               ; ...
        beq   t0, s5, em_o              ; ...
        mv    s5, t0                    ; ...
        lbu   a0, sgrtab(t0)            ; ...
        call  o_sgr                     ; ...
em_o:   mv    a0, s8                    ; the byte
        call  out_chr                   ; ...
em_nx:  addi  s4, s4, 1                 ; next column
        addi  s9, s9, -1                ; ...
        bnez  s9, em_cell               ; ...
        addi  s3, s3, 1                 ; next byte
        j     em_l                      ; ...
em_d:   beqz  s5, em_r                  ; a colour is on: back to the default
        li    a0, 0                     ; ...
        call  o_sgr                     ; ...
em_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        ld    s5, 48(sp)                ; ...
        ld    s6, 56(sp)                ; ...
        ld    s7, 64(sp)                ; ...
        ld    s8, 72(sp)                ; ...
        ld    s9, 80(sp)                ; ...
        addi  sp, sp, 88                ; release the frame
        ret                             ; done

; draw_status(): the bottom row: the message, or the mode, the file, [+],
; and line,column at the right
draw_status:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save ra
        ld    a0, v_rows(zero)          ; the last row
        addi  a0, a0, -1                ; ...
        li    a1, 0                     ; ...
        call  o_goto                    ; ...
        ld    a1, v_msgl(zero)          ; a message?
        beqz  a1, ds_s                  ; ...
        ld    t0, v_cols(zero)          ; (not into the last column)
        addi  t0, t0, -1                ; ...
        ble   a1, t0, ds_m              ; ...
        mv    a1, t0                    ; ...
ds_m:   li    a0, msgbuf                ; ...
        call  out_str                   ; ...
        j     ds_el                     ; ...
ds_s:   ld    t0, v_ins(zero)           ; -- INSERT --
        beqz  t0, ds_n                  ; ...
        li    a0, s_insm                ; ...
        call  o_s                       ; ...
ds_n:   li    a0, fname                 ; the file's name ...
        ld    a1, v_fnl(zero)           ; ...
        bnez  a1, ds_n2                 ; ...
        li    a0, s_noname              ; ... or [No Name]
        call  o_s                       ; ...
        j     ds_mod                    ; ...
ds_n2:  li    t0, 40                    ; (40 bytes of it)
        ble   a1, t0, ds_n3             ; ...
        mv    a1, t0                    ; ...
ds_n3:  call  out_str                   ; ...
ds_mod: call  is_mod                    ; [+]
        beqz  a0, ds_pos                ; ...
        li    a0, s_plus                ; ...
        call  o_s                       ; ...
ds_pos: call  o_el                      ; (what was there before goes)
        ld    a0, v_rows(zero)          ; line,column near the right
        addi  a0, a0, -1                ; ...
        ld    a1, v_cols(zero)          ; ...
        addi  a1, a1, -18               ; ...
        call  o_goto                    ; ...
        ld    a0, v_cy(zero)            ; ...
        addi  a0, a0, 1                 ; ...
        call  out_dec                   ; ...
        li    a0, ','                   ; ...
        call  out_chr                   ; ...
        ld    a0, v_cx(zero)            ; ...
        addi  a0, a0, 1                 ; ...
        call  out_dec                   ; ...
ds_el:  call  o_el                      ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 8                 ; release the frame
        ret                             ; done

; is_mod() -> a0 = 1 if the text differs from the file as last written (or
; is being changed: insert mode)
is_mod: ld    t0, u_end(zero)           ; the undo position then and now
        ld    t1, u_saved(zero)         ; ...
        sub   a0, t0, t1                ; ...
        snez  a0, a0                    ; ...
        ld    t0, v_ins(zero)           ; ...
        or    a0, a0, t0                ; ...
        ret                             ; done

