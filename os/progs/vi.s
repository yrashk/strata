; hl_on() -> a0 = the highlighting in effect (0 none, 1 asm, 2 Forth)
hl_on:  ld    a0, v_syn(zero)           ; the file's ...
        ld    t0, v_synon(zero)         ; ... unless :syntax off
        bnez  t0, ho_r                  ; ...
        li    a0, 0                     ; ...
ho_r:   ret                             ; done

; hl_line(a0 = text, a1 = length, a2 = state at its start) -> a0 = the state
; after it; cls[] = the class of each byte
hl_line:
        ld    t0, v_syn(zero)           ; Forth?
        li    t1, 2                     ; ...
        beq   t0, t1, hl_forth          ; (tail call)
        j     hl_asm                    ; (tail call: assembly has no state)

; paint(a0 = from, a1 = to, a2 = class): cls[from, to) = class
paint:  bge   a0, a1, pt_r              ; ...
        sb    a2, cls(a0)               ; ...
        addi  a0, a0, 1                 ; ...
        j     paint                     ; ...
pt_r:   ret                             ; done

; kw_find(a0 = table, a1 = word, a2 = its length) -> a0 = its class byte (0:
; not in the table). Case is folded.
kw_find:
        beqz  a2, kf_no                 ; ...
        lbu   t0, 0(a1)                 ; the first byte, lower case
        lbu   t1, ctype(t0)             ; ...
        andi  t1, t1, 32                ; ...
        or    t0, t0, t1                ; (capitals have bit 5 clear: 32 sets it)
        addi  t0, t0, -0x21             ; its index entry
        li    t1, 94                    ; ...
        bgeu  t0, t1, kf_no             ; ...
        slli  t0, t0, 1                 ; ...
        add   t0, a0, t0                ; ...
        lhu   t1, 0(t0)                 ; its entries: [first, end)
        lhu   t2, 2(t0)                 ; ...
        addi  a0, a0, 192               ; (after the index)
        add   t1, a0, t1                ; ...
        add   t2, a0, t2                ; ...
kf_e:   bgeu  t1, t2, kf_no             ; none left
        lbu   t3, 0(t1)                 ; its length
        bne   t3, a2, kf_nx             ; ...
        li    t4, 0                     ; the same letters?
kf_c:   beq   t4, a2, kf_yes            ; ...
        add   t5, a1, t4                ; ...
        lbu   t5, 0(t5)                 ; ...
        lbu   t6, ctype(t5)             ; (lower case)
        andi  t6, t6, 32                ; ...
        or    t5, t5, t6                ; ...
        add   t6, t1, t4                ; ...
        lbu   t6, 2(t6)                 ; ...
        bne   t5, t6, kf_nx             ; ...
        addi  t4, t4, 1                 ; ...
        j     kf_c                      ; ...
kf_yes: lbu   a0, 1(t1)                 ; the class
        ret                             ; done
kf_nx:  addi  t1, t1, 2                 ; the next entry
        add   t1, t1, t3                ; ...
        j     kf_e                      ; ...
kf_no:  li    a0, 0                     ; ...
        ret                             ; done

; scan_id(a0 = text, a1 = length, a2 = index) -> a0 = past the identifier
; that starts there ([A-Za-z_.$][A-Za-z0-9_.$]*), a2 if none
scan_id:
        bge   a2, a1, si_no             ; ...
        add   t0, a0, a2                ; an identifier's first byte?
        lbu   t0, 0(t0)                 ; ...
        lbu   t0, ctype(t0)             ; ...
        andi  t0, t0, 1 | 4 | 8         ; ...
        beqz  t0, si_no                 ; ...
si_l:   addi  a2, a2, 1                 ; the rest
        bge   a2, a1, si_no             ; ...
        add   t0, a0, a2                ; ...
        lbu   t0, 0(t0)                 ; ...
        lbu   t0, ctype(t0)             ; ...
        andi  t0, t0, 1 | 2 | 4 | 8     ; ...
        bnez  t0, si_l                  ; ...
si_no:  mv    a0, a2                    ; ...
        ret                             ; done

; skip_bl(a0 = text, a1 = length, a2 = index) -> a0 = the first non-blank
; at or after it
skip_bl:
        bge   a2, a1, sb_r              ; ...
        add   t0, a0, a2                ; ...
        lbu   t0, 0(t0)                 ; ...
        lbu   t0, ctype(t0)             ; ...
        andi  t0, t0, 16                ; ...
        beqz  t0, sb_r                  ; ...
        addi  a2, a2, 1                 ; ...
        j     skip_bl                   ; ...
sb_r:   mv    a0, a2                    ; ...
        ret                             ; done

; bfind(a0 = text, a1 = length, a2 = from, a3 = byte) -> a0 = its first
; index at or after from, -1 if none
bfind:  bge   a2, a1, bf_no             ; ...
        add   t0, a0, a2                ; ...
        lbu   t0, 0(t0)                 ; ...
        beq   t0, a3, bf_r              ; ...
        addi  a2, a2, 1                 ; ...
        j     bfind                     ; ...
bf_no:  li    a2, -1                    ; ...
bf_r:   mv    a0, a2                    ; ...
        ret                             ; done

; hl_asm(a0 = text, a1 = length) -> a0 = 0; cls[] filled (the rules of
; site/hl.js: a comment line; labels; NAME = or a mnemonic or a directive;
; then the operands)
hl_asm:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = text
        sd    s1, 16(sp)                ; s1 = length
        sd    s2, 24(sp)                ; s2 = index
        sd    s3, 32(sp)                ; s3 = start of a word
        sd    s4, 40(sp)                ; s4 = 1 after csrr / csrw (CSR names count)
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        li    s4, 0                     ; ...
        li    a0, 0                     ; nothing coloured yet
        li    a2, H_TEXT                ; ...
        call  paint                     ; ...
        li    s2, 0                     ; ...
ha_lab: mv    a0, s0                    ; ---- labels: NAME:
        mv    a1, s1                    ; ...
        mv    a2, s2                    ; ...
        call  skip_bl                   ; ...
        mv    s2, a0                    ; ...
        mv    s3, a0                    ; ...
        bge   s2, s1, ha_done           ; ...
        add   t0, s0, s2                ; a comment line (; # //)?
        lbu   t0, 0(t0)                 ; ...
        li    t1, ';'                   ; ...
        beq   t0, t1, ha_com            ; ...
        li    t1, '#'                   ; ...
        beq   t0, t1, ha_com            ; ...
        li    t1, '/'                   ; ...
        bne   t0, t1, ha_l1             ; ...
        addi  t2, s2, 1                 ; ...
        bge   t2, s1, ha_l1             ; ...
        add   t2, s0, t2                ; ...
        lbu   t2, 0(t2)                 ; ...
        beq   t2, t1, ha_com            ; ...
ha_l1:  mv    a0, s0                    ; a word
        mv    a1, s1                    ; ...
        mv    a2, s2                    ; ...
        call  scan_id                   ; ...
        beq   a0, s3, ha_ops            ; none: operands
        mv    s2, a0                    ; ...
        bge   s2, s1, ha_word           ; followed by ":"?
        add   t0, s0, s2                ; ...
        lbu   t0, 0(t0)                 ; ...
        li    t1, ':'                   ; ...
        bne   t0, t1, ha_word           ; ...
        mv    a0, s3                    ; a label
        mv    a1, s2                    ; ...
        li    a2, H_LABEL               ; ...
        call  paint                     ; ...
        addi  s2, s2, 1                 ; (after the ":"), and another may follow
        j     ha_lab                    ; ...
ha_word:
        mv    a0, s0                    ; NAME = (not ==)?
        mv    a1, s1                    ; ...
        mv    a2, s2                    ; ...
        call  skip_bl                   ; ...
        bge   a0, s1, ha_mn             ; ...
        add   t0, s0, a0                ; ...
        lbu   t1, 0(t0)                 ; ...
        li    t2, '='                   ; ...
        bne   t1, t2, ha_mn             ; ...
        addi  t3, a0, 1                 ; ...
        bge   t3, s1, ha_eq             ; ...
        lbu   t1, 1(t0)                 ; ...
        beq   t1, t2, ha_mn             ; ...
ha_eq:  addi  s2, a0, 1                 ; a constant: the operands after the "="
        mv    a0, s3                    ; ...
        mv    a1, s2                    ; ...
        addi  a1, a1, -1                ; ...
        li    a2, H_CONST               ; (the spaces before "=" too: harmless)
        call  paint                     ; ...
        j     ha_ops                    ; ...
ha_mn:  add   t0, s0, s3                ; a directive: a word starting with "."
        lbu   t0, 0(t0)                 ; ...
        li    t1, '.'                   ; ...
        li    a2, H_DIR                 ; ...
        beq   t0, t1, ha_mp             ; ...
        li    a0, kw_asm                ; a mnemonic?
        add   a1, s0, s3                ; ...
        sub   a2, s2, s3                ; ...
        call  kw_find                   ; ...
        mv    a2, a0                    ; ...
        addi  t0, a0, -H_ALU            ; (one of the mnemonic classes)
        li    t1, H_PSEUDO - H_ALU + 1  ; ...
        bltu  t0, t1, ha_m2             ; ...
        mv    s2, s3                    ; no: the word is an operand
        j     ha_ops                    ; ...
ha_m2:  li    t0, H_SYS                 ; csrr / csrw: CSR names follow
        bne   a2, t0, ha_mp             ; ...
        sub   t0, s2, s3                ; (the system mnemonics of 4 letters starting "cs")
        li    t1, 4                     ; ...
        bne   t0, t1, ha_mp             ; ...
        add   t0, s0, s3                ; ...
        lbu   t0, 0(t0)                 ; ...
        li    t1, 'c'                   ; ...
        bne   t0, t1, ha_mp             ; ...
        li    s4, 1                     ; ...
ha_mp:  mv    a0, s3                    ; the mnemonic or directive
        mv    a1, s2                    ; ...
        call  paint                     ; ...
ha_ops: bge   s2, s1, ha_done           ; ---- operands
        add   t0, s0, s2                ; t1 = the byte
        lbu   t1, 0(t0)                 ; ...
        li    t2, ';'                   ; a comment
        beq   t1, t2, ha_com            ; ...
        li    t2, '#'                   ; ...
        beq   t1, t2, ha_com            ; ...
        li    t2, '/'                   ; //
        bne   t1, t2, ha_o1             ; ...
        addi  t3, s2, 1                 ; ...
        bge   t3, s1, ha_o1             ; ...
        lbu   t3, 1(t0)                 ; ...
        beq   t3, t2, ha_com            ; ...
ha_o1:  li    t2, '"'                   ; a string
        beq   t1, t2, ha_str            ; ...
        li    t2, '\''                  ; a character
        beq   t1, t2, ha_chr            ; ...
        lbu   t2, ctype(t1)             ; a number (digits, letters after)
        andi  t3, t2, 2                 ; ...
        bnez  t3, ha_num                ; ...
        andi  t3, t2, 1 | 4 | 8         ; an identifier
        bnez  t3, ha_id                 ; ...
        addi  s2, s2, 1                 ; anything else
        j     ha_ops                    ; ...
ha_str: addi  s3, s2, 1                 ; to the closing quote (\ escapes)
ha_s1:  bge   s3, s1, ha_s3             ; ...
        add   t0, s0, s3                ; ...
        lbu   t0, 0(t0)                 ; ...
        addi  s3, s3, 1                 ; ...
        li    t1, '"'                   ; ...
        beq   t0, t1, ha_s3             ; ...
        li    t1, '\\'                  ; ...
        bne   t0, t1, ha_s1             ; ...
        addi  s3, s3, 1                 ; ...
        j     ha_s1                     ; ...
ha_chr: addi  s3, s2, 1                 ; 'x' or '\x'
        bge   s3, s1, ha_s3             ; ...
        add   t0, s0, s3                ; ...
        lbu   t0, 0(t0)                 ; ...
        addi  s3, s3, 1                 ; ...
        li    t1, '\\'                  ; ...
        bne   t0, t1, ha_c1             ; ...
        addi  s3, s3, 1                 ; ...
ha_c1:  bge   s3, s1, ha_s3             ; the closing quote
        add   t0, s0, s3                ; ...
        lbu   t0, 0(t0)                 ; ...
        li    t1, '\''                  ; ...
        bne   t0, t1, ha_s3             ; ...
        addi  s3, s3, 1                 ; ...
ha_s3:  ble   s3, s1, ha_s4             ; (not past the end)
        mv    s3, s1                    ; ...
ha_s4:  li    a2, H_STR                 ; ...
        j     ha_tok                    ; ...
ha_num: mv    s3, s2                    ; digits and letters
ha_n1:  addi  s3, s3, 1                 ; ...
        bge   s3, s1, ha_n2             ; ...
        add   t0, s0, s3                ; ...
        lbu   t0, 0(t0)                 ; ...
        lbu   t0, ctype(t0)             ; ...
        andi  t0, t0, 1 | 2             ; ...
        bnez  t0, ha_n1                 ; ...
ha_n2:  li    a2, H_NUM                 ; ...
        j     ha_tok                    ; ...
ha_id:  mv    a0, s0                    ; an identifier
        mv    a1, s1                    ; ...
        mv    a2, s2                    ; ...
        call  scan_id                   ; ...
        mv    s3, a0                    ; ...
        li    a0, kw_asm                ; a register? a CSR?
        add   a1, s0, s2                ; ...
        sub   a2, s3, s2                ; ...
        call  kw_find                   ; ...
        mv    a2, a0                    ; ...
        li    t0, H_XREG                ; ...
        beq   a2, t0, ha_tok            ; ...
        li    t0, H_CREG                ; ...
        beq   a2, t0, ha_tok            ; ...
        li    t0, H_CSR                 ; (only after csrr / csrw)
        bne   a2, t0, ha_caps           ; ...
        bnez  s4, ha_tok                ; ...
ha_caps:
        li    a2, H_TEXT                ; CAPITALS: [A-Z][A-Z0-9_]*[A-Z0-9]
        sub   t0, s3, s2                ; (two bytes at least)
        li    t1, 2                     ; ...
        blt   t0, t1, ha_tok            ; ...
        add   t0, s0, s2                ; the first: a capital
        lbu   t1, 0(t0)                 ; ...
        lbu   t1, ctype(t1)             ; ...
        andi  t1, t1, 32                ; ...
        beqz  t1, ha_tok                ; ...
        add   t2, s0, s3                ; the last: a capital or a digit
        lbu   t1, -1(t2)                ; ...
        lbu   t1, ctype(t1)             ; ...
        andi  t1, t1, 32 | 2            ; ...
        beqz  t1, ha_tok                ; ...
ha_k1:  addi  t0, t0, 1                 ; the rest: capitals, digits, _
        bgeu  t0, t2, ha_k2             ; ...
        lbu   t1, 0(t0)                 ; ...
        lbu   t1, ctype(t1)             ; ...
        andi  t1, t1, 32 | 2 | 64       ; ...
        bnez  t1, ha_k1                 ; ...
        j     ha_tok                    ; ...
ha_k2:  li    a2, H_CONST               ; ...
ha_tok: mv    a0, s2                    ; the token [s2, s3) in class a2
        mv    a1, s3                    ; ...
        call  paint                     ; ...
        mv    s2, s3                    ; ...
        j     ha_ops                    ; ...
ha_com: mv    a0, s2                    ; a comment: to the end
        mv    a1, s1                    ; ...
        li    a2, H_COM                 ; ...
        call  paint                     ; ...
ha_done:
        li    a0, 0                     ; no state
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        addi  sp, sp, 48                ; release the frame
        ret                             ; done

; hl_forth(a0 = text, a1 = length, a2 = 1 if a ( comment is open) -> a0 = the
; same after the line; cls[] filled (site/hl.js: \ and ( ) comments,
; strings, the table's words and what they want next, numbers)
hl_forth:
        addi  sp, sp, -56               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = text
        sd    s1, 16(sp)                ; s1 = length
        sd    s2, 24(sp)                ; s2 = index (past the word)
        sd    s3, 32(sp)                ; s3 = the word's start
        sd    s4, 40(sp)                ; s4 = what the next word is: 0, 1 a name, 2 a character, 3 locals
        sd    s5, 48(sp)                ; s5 = the state at the start
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        mv    s5, a2                    ; ...
        li    s4, 0                     ; ...
        li    a0, 0                     ; nothing coloured yet
        li    a2, H_TEXT                ; ...
        call  paint                     ; ...
        li    s2, 0                     ; ...
        beqz  s5, hf_l                  ; in a ( comment: up to its ")"
        li    s3, 0                     ; ...
        j     hf_par                    ; ...
hf_l:   mv    a0, s0                    ; ---- the next word
        mv    a1, s1                    ; ...
        mv    a2, s2                    ; ...
        call  skip_bl                   ; ...
        mv    s3, a0                    ; ...
        mv    s2, a0                    ; ...
        bge   s2, s1, hf_end            ; none: the line is done
hf_w:   addi  s2, s2, 1                 ; to its end
        bge   s2, s1, hf_got            ; ...
        add   t0, s0, s2                ; ...
        lbu   t0, 0(t0)                 ; ...
        lbu   t0, ctype(t0)             ; ...
        andi  t0, t0, 16                ; ...
        beqz  t0, hf_w                  ; ...
hf_got: add   t0, s0, s3                ; t1 = its first byte, t2 = its length
        lbu   t1, 0(t0)                 ; ...
        sub   t2, s2, s3                ; ...
        beqz  s4, hf_k                  ; a word asked for by the one before?
        li    a2, H_FLOC                ; locals, up to "}"
        li    t3, 3                     ; ...
        beq   s4, t3, hf_loc            ; ...
        li    a2, H_FNAME               ; a name
        li    t3, 1                     ; ...
        beq   s4, t3, hf_one            ; ...
        li    a2, H_STR                 ; a character
hf_one: li    s4, 0                     ; ...
        j     hf_tok                    ; ...
hf_loc: li    t3, 1                     ; ...
        bne   t2, t3, hf_tok            ; ...
        li    t3, '}'                   ; ...
        bne   t1, t3, hf_tok            ; ...
        li    s4, 0                     ; ...
        j     hf_tok                    ; ...
hf_k:   li    t3, 1                     ; one byte: \ or (
        bne   t2, t3, hf_q              ; ...
        li    t3, '\\'                  ; \: the rest of the line
        bne   t1, t3, hf_p              ; ...
        mv    a0, s3                    ; ...
        mv    a1, s1                    ; ...
        li    a2, H_COM                 ; ...
        call  paint                     ; ...
        j     hf_end                    ; ...
hf_p:   li    t3, '('                   ; (: up to ")"
        bne   t1, t3, hf_q              ; ...
hf_par: mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        mv    a2, s2                    ; ...
        li    a3, ')'                   ; ...
        call  bfind                     ; ...
        bltz  a0, hf_open               ; none: open to the next line
        addi  s2, a0, 1                 ; ...
        mv    a0, s3                    ; ...
        mv    a1, s2                    ; ...
        li    a2, H_COM                 ; ...
        call  paint                     ; ...
        j     hf_l                      ; ...
hf_open:
        mv    a0, s3                    ; ...
        mv    a1, s1                    ; ...
        li    a2, H_COM                 ; ...
        call  paint                     ; ...
        li    a0, 1                     ; still open
        j     hf_ret                    ; ...
hf_q:   li    a3, '"'                   ; a string: X" ... " (X" being 2 bytes at least) ...
        li    t3, 2                     ; ...
        blt   t2, t3, hf_kw             ; ...
        add   t0, s0, s2                ; ...
        lbu   t4, -1(t0)                ; ...
        beq   t4, a3, hf_s              ; ...
        bne   t2, t3, hf_kw             ; ... or .( ... )
        li    t3, '.'                   ; ...
        bne   t1, t3, hf_kw             ; ...
        li    t3, '('                   ; ...
        bne   t4, t3, hf_kw             ; ...
        li    a3, ')'                   ; ...
hf_s:   mv    a0, s0                    ; from one byte after the word
        mv    a1, s1                    ; ...
        addi  a2, s2, 1                 ; ...
        call  bfind                     ; ...
        addi  s2, a0, 1                 ; past it ...
        bgez  a0, hf_s1                 ; ...
        mv    s2, s1                    ; ... or to the end
hf_s1:  li    a2, H_STR                 ; ...
        j     hf_tok                    ; ...
hf_kw:  li    a0, kw_fth                ; a word of the table?
        add   a1, s0, s3                ; ...
        sub   a2, s2, s3                ; ...
        call  kw_find                   ; ...
        beqz  a0, hf_num                ; ...
        srli  s4, a0, 6                 ; what it wants next
        andi  a2, a0, 0x3f              ; its class
        j     hf_tok                    ; ...
hf_num: add   a0, s0, s3                ; a number?
        sub   a1, s2, s3                ; ...
        call  fnum                      ; ...
        li    a2, H_TEXT                ; ...
        beqz  a0, hf_tok                ; ...
        li    a2, H_NUM                 ; ...
hf_tok: mv    a0, s3                    ; [s3, s2) in class a2
        mv    a1, s2                    ; ...
        call  paint                     ; ...
        j     hf_l                      ; ...
hf_end: li    a0, 0                     ; no comment open
hf_ret: ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        ld    s5, 48(sp)                ; ...
        addi  sp, sp, 56                ; release the frame
        ret                             ; done

; fnum(a0 = word, a1 = length) -> a0 = 1 if it is a Forth number:
; -?($-?hex | #-?dec | %-?bin | dec.? | 'c')
fnum:   li    t0, 0                     ; t0 = index
        lbu   t1, 0(a0)                 ; a sign
        li    t2, '-'                   ; ...
        bne   t1, t2, fn_1              ; ...
        li    t0, 1                     ; ...
fn_1:   bge   t0, a1, fn_no             ; ...
        add   t3, a0, t0                ; t1 = the next byte
        lbu   t1, 0(t3)                 ; ...
        li    t2, '\''                  ; 'c'
        bne   t1, t2, fn_2              ; ...
        sub   t4, a1, t0                ; ...
        li    t5, 3                     ; ...
        bne   t4, t5, fn_no             ; ...
        lbu   t1, 2(t3)                 ; ...
        bne   t1, t2, fn_no             ; ...
        j     fn_yes                    ; ...
fn_2:   li    a2, 1                     ; a2 = 1: a trailing "." is allowed (plain decimal)
        li    t6, 10                    ; t6 = the base
        li    t2, '$'                   ; prefixes
        li    t5, 16                    ; ...
        beq   t1, t2, fn_px             ; ...
        li    t2, '#'                   ; ...
        li    t5, 10                    ; ...
        beq   t1, t2, fn_px             ; ...
        li    t2, '%'                   ; ...
        li    t5, 2                     ; ...
        bne   t1, t2, fn_d              ; ...
fn_px:  mv    t6, t5                    ; ...
        li    a2, 0                     ; ...
        addi  t0, t0, 1                 ; ...
        bge   t0, a1, fn_no             ; ...
        add   t3, a0, t0                ; a sign after the prefix
        lbu   t1, 0(t3)                 ; ...
        li    t2, '-'                   ; ...
        bne   t1, t2, fn_d              ; ...
        addi  t0, t0, 1                 ; ...
fn_d:   li    a3, 0                     ; a3 = digits seen
fn_dl:  bge   t0, a1, fn_end            ; ...
        add   t3, a0, t0                ; ...
        lbu   t1, 0(t3)                 ; ...
        lbu   t2, ctype(t1)             ; lower case
        andi  t2, t2, 32                ; ...
        or    t1, t1, t2                ; ...
        addi  t2, t1, -'0'              ; its value
        li    t4, 10                    ; ...
        bltu  t2, t4, fn_dv             ; ...
        addi  t2, t1, -'a' + 10         ; ...
        li    t4, 10                    ; (a..f: 10..15)
        bltu  t2, t4, fn_dot            ; ...
fn_dv:  bgeu  t2, t6, fn_dot            ; a digit of the base?
        addi  a3, a3, 1                 ; ...
        addi  t0, t0, 1                 ; ...
        j     fn_dl                     ; ...
fn_dot: beqz  a2, fn_no                 ; a "." as the last byte, after digits
        li    t4, '.'                   ; ...
        bne   t1, t4, fn_no             ; ...
        addi  t0, t0, 1                 ; ...
        bne   t0, a1, fn_no             ; ...
fn_end: beqz  a3, fn_no                 ; ...
fn_yes: li    a0, 1                     ; ...
        ret                             ; done
fn_no:  li    a0, 0                     ; ...
        ret                             ; done

; fstate_top() -> a0 = the Forth ( state at the start of the top line (0 when
; not Forth): from the line remembered (hs_n) or from the first
fstate_top:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = line
        sd    s1, 16(sp)                ; s1 = state
        li    s1, 0                     ; ...
        call  hl_on                     ; Forth?
        li    t0, 2                     ; ...
        bne   a0, t0, fs_r              ; ...
        ld    s0, hs_n(zero)            ; from the line remembered ...
        ld    s1, hs_s(zero)            ; ...
        ld    t0, v_top(zero)           ; ...
        ble   s0, t0, fs_l              ; ...
        li    s0, 0                     ; ... or from the start
        li    s1, 0                     ; ...
fs_l:   ld    t0, v_top(zero)           ; up to the top line
        bge   s0, t0, fs_d              ; ...
        mv    a0, s0                    ; ...
        call  ln_find                   ; ...
        mv    a2, s1                    ; ...
        call  hl_forth                  ; ...
        mv    s1, a0                    ; ...
        addi  s0, s0, 1                 ; ...
        j     fs_l                      ; ...
fs_d:   sd    s0, hs_n(zero)            ; remembered
        sd    s1, hs_s(zero)            ; ...
fs_r:   mv    a0, s1                    ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; release the frame
        ret                             ; done

; =============================================================================
; The text: chunks of whole lines in far memory
; =============================================================================

; bmove(a0 = destination, a1 = source, a2 = bytes): a copy (they may overlap)
bmove:  beqz  a2, bm_r                  ; ...
        bltu  a1, a0, bm_back           ; the source below: from the end
bm_f:   lbu   t0, 0(a1)                 ; ...
        sb    t0, 0(a0)                 ; ...
        addi  a0, a0, 1                 ; ...
        addi  a1, a1, 1                 ; ...
        addi  a2, a2, -1                ; ...
        bnez  a2, bm_f                  ; ...
        ret                             ; done
bm_back:
        add   a0, a0, a2                ; ...
        add   a1, a1, a2                ; ...
bm_b:   addi  a0, a0, -1                ; ...
        addi  a1, a1, -1                ; ...
        lbu   t0, 0(a1)                 ; ...
        sb    t0, 0(a0)                 ; ...
        addi  a2, a2, -1                ; ...
        bnez  a2, bm_b                  ; ...
bm_r:   ret                             ; done

; ch_xfer(a0 = chunk index, a1 = D-LS buffer, a2 = 0 read / 1 write): that
; chunk's bytes (whole words) between the store and the buffer
ch_xfer:
        slli  t0, a0, 3                 ; its entry
        lhu   t1, ctab(t0)              ; store number -> far offset
        slli  t1, t1, CHSH              ; ...
        lhu   t2, ctab+2(t0)            ; bytes, whole words
        addi  t2, t2, 7                 ; ...
        srli  t2, t2, 3                 ; ...
        slli  t2, t2, 3                 ; ...
        bnez  a2, cx_w                  ; ...
        tget  tg1, a1, c0, t1, t2       ; read
        twait 1 << 1                    ; ...
        ret                             ; done
cx_w:   tput  tg1, a1, c0, t1, t2       ; write
        twait 1 << 1                    ; ...
        ret                             ; done

; ch_flush(): cbuf back to its chunk if it changed
ch_flush:
        ld    t0, v_cdirty(zero)        ; ...
        beqz  t0, chf_r                 ; ...
        sd    zero, v_cdirty(zero)      ; ...
        ld    a0, v_cidx(zero)          ; ...
        li    a1, cbuf                  ; ...
        li    a2, 1                     ; ...
        j     ch_xfer                   ; (tail call)
chf_r:  ret                             ; done

; ch_load(a0 = chunk index): that chunk in cbuf
ch_load:
        ld    t0, v_cidx(zero)          ; there already?
        beq   t0, a0, chl_r             ; ...
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    a0, 8(sp)                 ; ...
        call  ch_flush                  ; the one there goes back
        ld    a0, 8(sp)                 ; ...
        sd    a0, v_cidx(zero)          ; ...
        li    a1, cbuf                  ; ...
        li    a2, 0                     ; ...
        call  ch_xfer                   ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 16                ; release the frame
chl_r:  ret                             ; done

; ch_new(a0 = index) -> a0 = 0, or -1 when no chunk is free: an empty chunk
; at that place in the table (the ones from there on move up)
ch_new: ld    t0, v_nfree(zero)         ; a free store number
        beqz  t0, chn_no                ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, v_nfree(zero)         ; ...
        lbu   t1, fstk(t0)              ; ...
        ld    t2, v_nch(zero)           ; the entries [index, count) up by one
        addi  t3, t2, 1                 ; ...
        sd    t3, v_nch(zero)           ; ...
chn_m:  ble   t2, a0, chn_p             ; ...
        slli  t4, t2, 3                 ; ...
        ld    t5, ctab-8(t4)            ; ...
        sd    t5, ctab(t4)              ; ...
        addi  t2, t2, -1                ; ...
        j     chn_m                     ; ...
chn_p:  slli  t4, a0, 3                 ; the new entry: no bytes, no lines
        sd    t1, ctab(t4)              ; ...
        ld    t0, v_cidx(zero)          ; the chunk in cbuf moved up too
        blt   t0, a0, chn_r             ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, v_cidx(zero)          ; ...
chn_r:  li    a0, 0                     ; ...
        ret                             ; done
chn_no: li    a0, -1                    ; ...
        ret                             ; done

; ch_del(a0 = index): that chunk leaves the table; its store is free
ch_del: slli  t4, a0, 3                 ; its store number -> the free stack
        lhu   t1, ctab(t4)              ; ...
        ld    t0, v_nfree(zero)         ; ...
        sb    t1, fstk(t0)              ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, v_nfree(zero)         ; ...
        ld    t2, v_nch(zero)           ; the entries after it down by one
        addi  t2, t2, -1                ; ...
        sd    t2, v_nch(zero)           ; ...
        mv    t6, a0                    ; ...
chd_m:  bge   t6, t2, chd_c             ; ...
        slli  t4, t6, 3                 ; ...
        ld    t5, ctab+8(t4)            ; ...
        sd    t5, ctab(t4)              ; ...
        addi  t6, t6, 1                 ; ...
        j     chd_m                     ; ...
chd_c:  ld    t0, v_cidx(zero)          ; the chunk in cbuf: moved down, or gone
        blt   t0, a0, chd_r             ; (before it: as it was)
        addi  t1, t0, -1                ; ...
        sd    t1, v_cidx(zero)          ; ...
        bne   t0, a0, chd_r             ; ...
        li    t0, -1                    ; it was this one: none, nothing to write
        sd    t0, v_cidx(zero)          ; ...
        sd    zero, v_cdirty(zero)      ; ...
chd_r:  ret                             ; done

; ln_touch(a0 = line): something there changes: what was found goes, and
; the Forth state remembered after it
ln_touch:
        li    t0, -1                    ; ...
        sd    t0, lc_n(zero)            ; ...
        ld    t0, hs_n(zero)            ; ...
        bge   a0, t0, lt_r              ; ...
        sd    zero, hs_n(zero)          ; ...
        sd    zero, hs_s(zero)          ; ...
lt_r:   ret                             ; done

; ln_find(a0 = line, below v_nl) -> a0 = its text in cbuf, a1 = its length
; (f_c, f_b, f_o, f_len too). The next line after the last one found is
; quick: the scan goes on from there.
ln_find:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = the line
        sd    s1, 16(sp)                ; s1 = offset in cbuf
        sd    s2, 24(sp)                ; s2 = lines to skip
        mv    s0, a0                    ; ...
        ld    t0, lc_n(zero)            ; the line found last?
        beq   t0, s0, lf_hit            ; ...
        bltz  t0, lf_walk               ; nothing known
        blt   s0, t0, lf_walk           ; before it: from the start
        ld    t1, f_c(zero)             ; after it, in the same chunk?
        slli  t2, t1, 3                 ; ...
        lwu   t3, ctab+4(t2)            ; ...
        ld    t4, f_b(zero)             ; ...
        add   t3, t3, t4                ; ...
        bge   s0, t3, lf_walk           ; ...
        ld    s1, f_o(zero)             ; yes: from that line
        sub   s2, s0, t0                ; ...
        mv    a0, t1                    ; (it is in cbuf)
        call  ch_load                   ; ...
        j     lf_sc                     ; ...
lf_walk:
        li    t1, 0                     ; the chunk holding it
        li    t4, 0                     ; t4 = its first line
        ld    t5, v_nch(zero)           ; ...
        addi  t5, t5, -1                ; (the last one, at most)
lf_w:   bge   t1, t5, lf_got            ; ...
        slli  t2, t1, 3                 ; ...
        lwu   t3, ctab+4(t2)            ; ...
        add   t6, t4, t3                ; ...
        blt   s0, t6, lf_got            ; ...
        mv    t4, t6                    ; ...
        addi  t1, t1, 1                 ; ...
        j     lf_w                      ; ...
lf_got: sd    t1, f_c(zero)             ; ...
        sd    t4, f_b(zero)             ; ...
        sub   s2, s0, t4                ; lines to skip in it
        li    s1, 0                     ; ...
        mv    a0, t1                    ; ...
        call  ch_load                   ; ...
lf_sc:  li    t2, 10                    ; skip s2 lines
lf_s1:  beqz  s2, lf_len                ; ...
lf_s2:  lbu   t1, cbuf(s1)              ; ...
        addi  s1, s1, 1                 ; ...
        bne   t1, t2, lf_s2             ; ...
        addi  s2, s2, -1                ; ...
        j     lf_s1                     ; ...
lf_len: mv    t3, s1                    ; its length: up to its newline
lf_l1:  lbu   t1, cbuf(t3)              ; ...
        beq   t1, t2, lf_l2             ; ...
        addi  t3, t3, 1                 ; ...
        j     lf_l1                     ; ...
lf_l2:  sub   t3, t3, s1                ; ...
        sd    s1, f_o(zero)             ; ...
        sd    t3, f_len(zero)           ; ...
        sd    s0, lc_n(zero)            ; ...
lf_hit: ld    a0, f_o(zero)             ; ...
        addi  a0, a0, cbuf              ; ...
        ld    a1, f_len(zero)           ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; release the frame
        ret                             ; done

; ln_get(a0 = line, a1 = buffer) -> a0 = its length; its text copied there
ln_get: addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    a1, 8(sp)                 ; ...
        call  ln_find                   ; ...
        sd    a1, f_len(zero)           ; (kept: bmove counts it down)
        mv    a2, a1                    ; ...
        mv    a1, a0                    ; ...
        ld    a0, 8(sp)                 ; ...
        call  bmove                     ; ...
        ld    a0, f_len(zero)           ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 16                ; release the frame
        ret                             ; done

; ln_del(a0 = line): it goes. An emptied chunk is freed; a small one takes
; in the next if both fit in one.
ln_del: addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 16(sp)                ; s0 = its chunk
        sd    a0, 24(sp)                ; the line
        call  ln_touch                  ; (a0 is kept)
        call  ln_find                   ; a0 = text, a1 = length
        ld    s0, f_c(zero)             ; ...
        slli  t0, s0, 3                 ; t1 = the chunk's bytes, t2 = its lines
        lhu   t1, ctab+2(t0)            ; ...
        lwu   t2, ctab+4(t0)            ; ...
        addi  t3, a1, 1                 ; with its newline
        sub   t1, t1, t3                ; ...
        sh    t1, ctab+2(t0)            ; ...
        addi  t2, t2, -1                ; ...
        sw    t2, ctab+4(t0)            ; ...
        li    t4, 1                     ; cbuf changes
        sd    t4, v_cdirty(zero)        ; ...
        ld    t4, v_nl(zero)            ; one line fewer
        addi  t4, t4, -1                ; ...
        sd    t4, v_nl(zero)            ; ...
        li    t4, -1                    ; (what was found is gone)
        sd    t4, lc_n(zero)            ; ...
        bnez  t2, ld_keep               ; no lines left: the chunk goes
        mv    a0, s0                    ; ...
        j     ld_free                   ; ...
ld_keep:
        ld    t4, f_o(zero)             ; the bytes after it come down
        sub   a2, t1, t4                ; ...
        add   a1, a0, t3                ; ...
        call  bmove                     ; ...
        slli  t0, s0, 3                 ; small now?
        lhu   t1, ctab+2(t0)            ; ...
        li    t2, CHSZ / 4              ; ...
        bgeu  t1, t2, ld_r              ; ...
        addi  t3, s0, 1                 ; and the next one fits in with it?
        ld    t4, v_nch(zero)           ; ...
        bge   t3, t4, ld_r              ; ...
        lhu   t5, ctab+10(t0)           ; ...
        add   t6, t1, t5                ; ...
        li    t2, CHSZ                  ; ...
        bgtu  t6, t2, ld_r              ; ...
        sd    t1, 8(sp)                 ; (the frame's spare word: this chunk's bytes)
        mv    a0, t3                    ; yes: the next chunk's bytes -> sbuf
        li    a1, sbuf                  ; ...
        li    a2, 0                     ; ...
        call  ch_xfer                   ; ...
        ld    t1, 8(sp)                 ; ... -> after this chunk's in cbuf
        addi  a0, t1, cbuf              ; ...
        li    a1, sbuf                  ; ...
        slli  t0, s0, 3                 ; ...
        lhu   a2, ctab+10(t0)           ; ...
        call  bmove                     ; ...
        slli  t0, s0, 3                 ; its bytes and lines are this chunk's now
        lhu   t1, ctab+2(t0)            ; ...
        lhu   t5, ctab+10(t0)           ; ...
        add   t1, t1, t5                ; ...
        sh    t1, ctab+2(t0)            ; ...
        lwu   t2, ctab+4(t0)            ; ...
        lwu   t5, ctab+12(t0)           ; ...
        add   t2, t2, t5                ; ...
        sw    t2, ctab+4(t0)            ; ...
        li    t4, 1                     ; ...
        sd    t4, v_cdirty(zero)        ; ...
        addi  a0, s0, 1                 ; and it goes
        call  ch_del                    ; ...
ld_r:   ld    t0, f_o(zero)             ; the line after it starts where it did: what
        slli  t1, s0, 3                 ;   ln_find would find for the same number
        lhu   t1, ctab+2(t1)            ;   (deleting lines one after another is quick)
        bgeu  t0, t1, ld_x              ; (it was the chunk's last)
        mv    t2, t0                    ; its length
        li    t4, 10                    ; ...
ld_n:   lbu   t3, cbuf(t2)              ; ...
        beq   t3, t4, ld_n2             ; ...
        addi  t2, t2, 1                 ; ...
        j     ld_n                      ; ...
ld_n2:  sub   t2, t2, t0                ; ...
        sd    t2, f_len(zero)           ; ...
        ld    t0, 24(sp)                ; ...
        sd    t0, lc_n(zero)            ; ...
        j     ld_x                      ; ...
ld_free:
        call  ch_del                    ; ...
ld_x:   ld    ra, 0(sp)                 ; restore
        ld    s0, 16(sp)                ; ...
        addi  sp, sp, 32                ; release the frame
        ret                             ; done

; ln_ins(a0 = line, 0..v_nl, a1 = text, a2 = length) -> a0 = 0, or -1 when
; the pool is full: a new line before that one (at v_nl: after the last).
; It goes where the line starts, or at the end of the chunk before; a full
; chunk is split there, or a new chunk follows it.
ln_ins: addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = line
        sd    s1, 16(sp)                ; s1 = text
        sd    s2, 24(sp)                ; s2 = length
        sd    s3, 32(sp)                ; s3 = chunk
        sd    s4, 40(sp)                ; s4 = offset in it
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        mv    s2, a2                    ; ...
        call  ln_room                   ; two chunks free (a split and a new one at most)?
        bnez  a0, li_ret                ; ...
        mv    a0, s0                    ; ...
        call  ln_touch                  ; ...
        ld    t0, v_nch(zero)           ; no chunk yet: the first
        bnez  t0, li_have               ; ...
        li    a0, 0                     ; ...
        call  ch_new                    ; ...
        bnez  a0, li_ret                ; ...
        sd    zero, v_cidx(zero)        ; (cbuf is it: no bytes to read)
        sd    zero, v_cdirty(zero)      ; ...
        li    s3, 0                     ; ...
        li    s4, 0                     ; ...
        j     li_try                    ; ...
li_have:
        ld    t0, v_nl(zero)            ; after the last line: the last chunk's end
        blt   s0, t0, li_mid            ; ...
        ld    s3, v_nch(zero)           ; ...
        addi  s3, s3, -1                ; ...
        j     li_end                    ; ...
li_mid: mv    a0, s0                    ; where the line is
        call  ln_find                   ; ...
        ld    s3, f_c(zero)             ; ...
        ld    s4, f_o(zero)             ; ...
        bnez  s4, li_try                ; (at a chunk's start: the end of the one before)
        beqz  s3, li_try                ; ...
        addi  s3, s3, -1                ; ...
li_end: mv    a0, s3                    ; ...
        call  ch_load                   ; ...
        slli  t0, s3, 3                 ; ...
        lhu   s4, ctab+2(t0)            ; ...
li_try: slli  t0, s3, 3                 ; does it fit?
        lhu   t1, ctab+2(t0)            ; ...
        add   t2, t1, s2                ; ...
        addi  t2, t2, 1                 ; ...
        li    t3, CHSZ                  ; ...
        bleu  t2, t3, li_put            ; ...
        beqz  s4, li_new                ; in the middle: split there
        bgeu  s4, t1, li_new2           ; ...
        call  li_split                  ; ...
        bnez  a0, li_ret                ; ...
        slli  t0, s3, 3                 ; at the end of the first half now: fits?
        lhu   t1, ctab+2(t0)            ; ...
        add   t2, t1, s2                ; ...
        addi  t2, t2, 1                 ; ...
        li    t3, CHSZ                  ; ...
        bleu  t2, t3, li_put            ; ...
li_new2:
        addi  s3, s3, 1                 ; a new chunk after this one
li_new: call  ch_flush                  ; (at s3)
        mv    a0, s3                    ; ...
        call  ch_new                    ; ...
        bnez  a0, li_ret                ; ...
        sd    s3, v_cidx(zero)          ; (cbuf is it)
        li    s4, 0                     ; ...
li_put: slli  t0, s3, 3                 ; the bytes from s4 up to make room
        lhu   t1, ctab+2(t0)            ; ...
        addi  a0, s4, cbuf              ; ...
        add   a0, a0, s2                ; ...
        addi  a0, a0, 1                 ; ...
        addi  a1, s4, cbuf              ; ...
        sub   a2, t1, s4                ; ...
        call  bmove                     ; ...
        addi  a0, s4, cbuf              ; the line
        mv    a1, s1                    ; ...
        mv    a2, s2                    ; ...
        call  bmove                     ; ...
        add   t0, s4, s2                ; its newline
        li    t1, 10                    ; ...
        sb    t1, cbuf(t0)              ; ...
        slli  t0, s3, 3                 ; the chunk: more bytes, a line more
        lhu   t1, ctab+2(t0)            ; ...
        add   t1, t1, s2                ; ...
        addi  t1, t1, 1                 ; ...
        sh    t1, ctab+2(t0)            ; ...
        lwu   t1, ctab+4(t0)            ; ...
        addi  t1, t1, 1                 ; ...
        sw    t1, ctab+4(t0)            ; ...
        li    t1, 1                     ; ...
        sd    t1, v_cdirty(zero)        ; ...
        ld    t1, v_nl(zero)            ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, v_nl(zero)            ; ...
        sd    s3, f_c(zero)             ; found: the new line (inserting lines one
        sd    s4, f_o(zero)             ;   after another is quick)
        sd    s2, f_len(zero)           ; ...
        sd    s0, lc_n(zero)            ; ...
        li    t0, 0                     ; its chunk's first line: the lines before it
        li    t1, 0                     ; ...
li_b:   bge   t1, s3, li_b2             ; ...
        slli  t2, t1, 3                 ; ...
        lwu   t2, ctab+4(t2)            ; ...
        add   t0, t0, t2                ; ...
        addi  t1, t1, 1                 ; ...
        j     li_b                      ; ...
li_b2:  sd    t0, f_b(zero)             ; ...
        li    a0, 0                     ; ...
li_ret: ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        addi  sp, sp, 48                ; release the frame
        ret                             ; done

; ln_room() -> a0 = 0 if a line can be added (two chunks are free), -1 and
; a message if the pool is full
ln_room:
        ld    t0, v_nfree(zero)         ; ...
        li    a0, 0                     ; ...
        li    t1, 2                     ; ...
        bge   t0, t1, lr_r              ; ...
        li    a0, s_full                ; ...
        j     msg_s                     ; (tail call: a0 stays nonzero)
lr_r:   ret                             ; done

; li_split() (ln_ins's s3 = chunk in cbuf, s4 = a line's offset inside it)
; -> a0 = 0 / -1: the bytes from s4 on become a new chunk after it
li_split:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save ra
        addi  a0, s3, 1                 ; the new chunk
        call  ch_new                    ; ...
        bnez  a0, ls_r                  ; ...
        li    t0, 0                     ; the lines before s4
        li    t1, 0                     ; ...
        li    t3, 10                    ; ...
ls_c:   bgeu  t1, s4, ls_m              ; ...
        lbu   t2, cbuf(t1)              ; ...
        addi  t1, t1, 1                 ; ...
        bne   t2, t3, ls_c              ; ...
        addi  t0, t0, 1                 ; ...
        j     ls_c                      ; ...
ls_m:   slli  t4, s3, 3                 ; the two entries
        lhu   t1, ctab+2(t4)            ; ...
        lwu   t2, ctab+4(t4)            ; ...
        sub   t1, t1, s4                ; the new one: the rest
        sh    t1, ctab+10(t4)           ; ...
        sub   t2, t2, t0                ; ...
        sw    t2, ctab+12(t4)           ; ...
        sh    s4, ctab+2(t4)            ; this one: up to s4
        sw    t0, ctab+4(t4)            ; ...
        li    t0, 1                     ; ...
        sd    t0, v_cdirty(zero)        ; ...
        li    a0, sbuf                  ; the rest -> sbuf -> its store
        addi  a1, s4, cbuf              ; ...
        mv    a2, t1                    ; ...
        call  bmove                     ; ...
        addi  a0, s3, 1                 ; ...
        li    a1, sbuf                  ; ...
        li    a2, 1                     ; ...
        call  ch_xfer                   ; ...
        li    a0, 0                     ; ...
ls_r:   ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 8                 ; release the frame
        ret                             ; done

; ln_put(a0 = line, a1 = text, a2 = length) -> a0 = 0 / -1: the line's
; text replaced (in its chunk if it fits there)
ln_put: addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = line
        sd    s1, 16(sp)                ; s1 = text
        sd    s2, 24(sp)                ; s2 = length
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        mv    s2, a2                    ; ...
        call  ln_touch                  ; ...
        mv    a0, s0                    ; ...
        call  ln_find                   ; a1 = the old length
        ld    t0, f_c(zero)             ; the chunk's bytes after the change
        slli  t0, t0, 3                 ; ...
        lhu   t1, ctab+2(t0)            ; ...
        sub   t2, s2, a1                ; (t2 = how much longer)
        add   t3, t1, t2                ; ...
        li    t4, CHSZ                  ; ...
        bgtu  t3, t4, lp_move           ; no room: elsewhere
        sh    t3, ctab+2(t0)            ; ...
        ld    t4, f_o(zero)             ; the rest of the chunk moves by t2
        add   a1, t4, a1                ; (from the old end of the line)
        sub   a2, t1, a1                ; ...
        addi  a1, a1, cbuf              ; ...
        add   a0, a1, t2                ; ...
        call  bmove                     ; ...
        ld    a0, f_o(zero)             ; the text
        addi  a0, a0, cbuf              ; ...
        mv    a1, s1                    ; ...
        mv    a2, s2                    ; ...
        call  bmove                     ; ...
        sd    s2, f_len(zero)           ; (what was found stays right)
        sd    s0, lc_n(zero)            ; ...
        li    t0, 1                     ; ...
        sd    t0, v_cdirty(zero)        ; ...
        li    a0, 0                     ; ...
        j     lp_r                      ; ...
lp_move:
        call  ln_room                   ; (not out unless it can come in again)
        bnez  a0, lp_r                  ; ...
        mv    a0, s0                    ; out, and in again
        call  ln_del                    ; ...
        mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        mv    a2, s2                    ; ...
        call  ln_ins                    ; ...
lp_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; release the frame
        ret                             ; done

; fixempty() -> a0 = 1 if the text was empty and now has an empty line
; (there is always one), 0 if it had lines
fixempty:
        ld    t0, v_nl(zero)            ; ...
        li    a0, 0                     ; ...
        bnez  t0, fe_r                  ; ...
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save ra
        li    a0, 0                     ; ...
        li    a1, lbuf                  ; ...
        li    a2, 0                     ; ...
        call  ln_ins                    ; ...
        li    a0, 1                     ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 8                 ; release the frame
fe_r:   ret                             ; done

; buf_reset(): no text, every chunk free, no history, the cursor home
buf_reset:
        li    t0, NCHMAX                ; the free stack: 255 .. 0 (0 is taken first)
        sd    t0, v_nfree(zero)         ; ...
        li    t1, 0                     ; ...
br_f:   sub   t2, t0, t1                ; ...
        addi  t2, t2, -1                ; ...
        sb    t2, fstk(t1)              ; ...
        addi  t1, t1, 1                 ; ...
        blt   t1, t0, br_f              ; ...
        li    t0, -1                    ; ...
        sd    t0, v_cidx(zero)          ; ...
        sd    t0, lc_n(zero)            ; ...
        sd    zero, v_cdirty(zero)      ; ...
        sd    zero, v_nch(zero)         ; ...
        sd    zero, v_nl(zero)          ; ...
        sd    zero, v_cy(zero)          ; ...
        sd    zero, v_cx(zero)          ; ...
        sd    zero, v_top(zero)         ; ...
        sd    zero, v_lcol(zero)        ; ...
        sd    zero, hs_n(zero)          ; ...
        sd    zero, hs_s(zero)          ; ...
        sd    zero, u_end(zero)         ; ...
        sd    zero, u_top(zero)         ; ...
        sd    zero, u_saved(zero)       ; ...
        li    t0, 1                     ; ...
        sd    t0, v_dall(zero)          ; ...
        sd    t0, v_setw(zero)          ; ...
        ret                             ; done

; buf_bytes() -> a0 = the bytes of the text as a file (a newline after
; every line)
buf_bytes:
        li    a0, 0                     ; ...
        li    t0, 0                     ; ...
        ld    t1, v_nch(zero)           ; ...
bb_l:   bge   t0, t1, bb_r              ; ...
        slli  t2, t0, 3                 ; ...
        lhu   t2, ctab+2(t2)            ; ...
        add   a0, a0, t2                ; ...
        addi  t0, t0, 1                 ; ...
        j     bb_l                      ; ...
bb_r:   ret                             ; done

; fnb(a0 = line) -> a0 = its first non-blank byte
fnb:    addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save ra
        call  ln_find                   ; ...
        li    a2, 0                     ; ...
        call  skip_bl                   ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 8                 ; release the frame
        ret                             ; done

; =============================================================================
; Undo and the register: lines in far memory, {u64 length, the bytes}
; =============================================================================

; fl_put(a0 = far offset, a1 = length; the bytes at tbuf + 8) -> a0 = the
; bytes the record takes
fl_put: sd    a1, tbuf(zero)            ; the length first
        addi  t1, a1, 15                ; 8 + the bytes in whole words
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        li    t0, tbuf                  ; ...
        tput  tg1, t0, c0, a0, t1       ; ...
        twait 1 << 1                    ; ...
        mv    a0, t1                    ; ...
        ret                             ; done

; fl_get(a0 = far offset) -> a0 = length (the bytes at tbuf + 8), a1 = the
; bytes the record takes
fl_get: li    t0, tbuf                  ; the length
        li    t1, 8                     ; ...
        tget  tg1, t0, c0, a0, t1       ; ...
        twait 1 << 1                    ; ...
        ld    t2, tbuf(zero)            ; ...
        addi  t3, t2, 7                 ; the bytes, whole words
        srli  t3, t3, 3                 ; ...
        slli  t3, t3, 3                 ; ...
        beqz  t3, fg_r                  ; ...
        addi  t4, a0, 8                 ; ...
        li    t0, tbuf + 8              ; ...
        tget  tg1, t0, c0, t4, t3       ; ...
        twait 1 << 1                    ; ...
fg_r:   mv    a0, t2                    ; ...
        addi  a1, t3, 8                 ; ...
        ret                             ; done

; fmove(a0 = far destination, a1 = far source above it, a2 = bytes): far
; memory moved down, a chunk at a time through sbuf
fmove:  beqz  a2, fm_r                  ; ...
        li    t1, CHSZ                  ; ...
        bleu  t1, a2, fm_1              ; ...
        mv    t1, a2                    ; ...
fm_1:   li    t0, sbuf                  ; ...
        tget  tg1, t0, c0, a1, t1       ; ...
        twait 1 << 1                    ; ...
        tput  tg1, t0, c0, a0, t1       ; ...
        twait 1 << 1                    ; ...
        add   a0, a0, t1                ; ...
        add   a1, a1, t1                ; ...
        sub   a2, a2, t1                ; ...
        j     fmove                     ; ...
fm_r:   ret                             ; done

; u_room(a0 = bytes) -> a0 = 1 if they fit after u_w (with the trailer):
; the oldest records go to make room; 0 if they cannot
u_room: addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = bytes
        mv    s0, a0                    ; ...
ur_l:   ld    t0, u_w(zero)             ; room?
        add   t0, t0, s0                ; ...
        addi  t0, t0, 8                 ; ...
        li    t1, USZ                   ; ...
        bleu  t0, t1, ur_yes            ; ...
        ld    t0, u_rec(zero)           ; an older record to drop?
        beqz  t0, ur_no                 ; ...
        li    t0, hdrb                  ; its size: its first word
        li    t1, 8                     ; ...
        li    t2, UBASE                 ; ...
        tget  tg1, t0, c0, t2, t1       ; ...
        twait 1 << 1                    ; ...
        ld    t3, hdrb(zero)            ; t3 = size
        ld    t4, u_rec(zero)           ; everything after it moves down
        sub   t4, t4, t3                ; ...
        sd    t4, u_rec(zero)           ; ...
        ld    t4, u_w(zero)             ; ...
        sub   a2, t4, t3                ; ...
        sd    a2, u_w(zero)             ; ...
        ld    t4, u_saved(zero)         ; (the state written is earlier still: lost)
        sub   t4, t4, t3                ; ...
        bgez  t4, ur_s                  ; ...
        li    t4, -1                    ; ...
ur_s:   sd    t4, u_saved(zero)         ; ...
        li    a0, UBASE                 ; ...
        add   a1, a0, t3                ; ...
        call  fmove                     ; ...
        j     ur_l                      ; ...
ur_yes: li    a0, 1                     ; ...
        j     ur_r                      ; ...
ur_no:  li    a0, 0                     ; ...
ur_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 16                ; release the frame
        ret                             ; done

; u_line(a0 = line): its text into the record being written
u_line: addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        ld    t0, u_ok(zero)            ; (not if it did not fit)
        beqz  t0, ul_r                  ; ...
        li    a1, tbuf + 8              ; ...
        call  ln_get                    ; a0 = length
        sd    a0, 8(sp)                 ; ...
        addi  a0, a0, 15                ; room for it?
        srli  a0, a0, 3                 ; ...
        slli  a0, a0, 3                 ; ...
        call  u_room                    ; ...
        bnez  a0, ul_w                  ; ...
        sd    zero, u_ok(zero)          ; no: this change cannot be undone
        j     ul_r                      ; ...
ul_w:   ld    a0, u_w(zero)             ; ...
        li    t0, UBASE                 ; ...
        add   a0, a0, t0                ; ...
        ld    a1, 8(sp)                 ; ...
        call  fl_put                    ; ...
        ld    t0, u_w(zero)             ; ...
        add   t0, t0, a0                ; ...
        sd    t0, u_w(zero)             ; ...
ul_r:   ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 16                ; release the frame
        ret                             ; done

; chg_begin(a0 = first line, a1 = lines): a change replaces those lines (0:
; it only adds); their text goes into a new undo record (what could be
; redone is gone)
chg_begin:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = line
        sd    s1, 16(sp)                ; s1 = past the last
        sd    a0, chg_a(zero)           ; ...
        sd    a1, chg_n(zero)           ; ...
        mv    s0, a0                    ; ...
        add   s1, a0, a1                ; ...
        ld    t0, u_end(zero)           ; the record starts where undoing stands
        sd    t0, u_rec(zero)           ; ...
        sd    t0, u_top(zero)           ; ...
        addi  t1, t0, 48                ; (after its header)
        sd    t1, u_w(zero)             ; ...
        ld    t1, u_saved(zero)         ; the state written was one that could be redone:
        bleu  t1, t0, cb_1              ;   it cannot be reached any more
        li    t1, -1                    ; ...
        sd    t1, u_saved(zero)         ; ...
cb_1:   li    t0, 1                     ; ...
        sd    t0, u_ok(zero)            ; ...
        ld    t0, v_cy(zero)            ; the cursor, for undo
        sd    t0, chg_y(zero)           ; ...
        ld    t0, v_cx(zero)            ; ...
        sd    t0, chg_x(zero)           ; ...
        li    a0, 0                     ; (room for the header)
        call  u_room                    ; ...
        sd    a0, u_ok(zero)            ; ...
cb_l:   bge   s0, s1, cb_r              ; the old lines
        mv    a0, s0                    ; ...
        call  u_line                    ; ...
        addi  s0, s0, 1                 ; ...
        j     cb_l                      ; ...
cb_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; release the frame
        ret                             ; done

; chg_end(a0 = lines): the change made that many lines from chg_a; they go
; into the record, which is complete (or, if it did not fit, the history is
; cleared). The command is the one . repeats.
chg_end:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = line
        sd    s1, 16(sp)                ; s1 = past the last
        li    t0, 1                     ; ...
        sd    t0, v_chg(zero)           ; ...
        sd    a0, hdrb+24(zero)         ; (the header: new count)
        ld    s0, chg_a(zero)           ; ...
        add   s1, s0, a0                ; ...
ce_l:   bge   s0, s1, ce_h              ; the new lines
        mv    a0, s0                    ; ...
        call  u_line                    ; ...
        addi  s0, s0, 1                 ; ...
        j     ce_l                      ; ...
ce_h:   ld    t0, u_ok(zero)            ; did it fit?
        beqz  t0, ce_lost               ; ...
        ld    t0, u_w(zero)             ; the size, with the trailer
        addi  t0, t0, 8                 ; ...
        ld    t1, u_rec(zero)           ; ...
        sub   t2, t0, t1                ; ...
        sd    t2, hdrb(zero)            ; the header: size, first line, old count, new
        ld    t3, chg_a(zero)           ; count, the cursor
        sd    t3, hdrb+8(zero)          ; ...
        ld    t3, chg_n(zero)           ; ...
        sd    t3, hdrb+16(zero)         ; ...
        ld    t3, chg_y(zero)           ; ...
        sd    t3, hdrb+32(zero)         ; ...
        ld    t3, chg_x(zero)           ; ...
        sd    t3, hdrb+40(zero)         ; ...
        li    t3, UBASE                 ; ...
        add   t4, t1, t3                ; ...
        li    t5, hdrb                  ; ...
        li    t6, 48                    ; ...
        tput  tg1, t5, c0, t4, t6       ; ...
        twait 1 << 1                    ; ...
        sd    t2, hdrb(zero)            ; the trailer: the size again
        ld    t4, u_w(zero)             ; ...
        add   t4, t4, t3                ; ...
        li    t6, 8                     ; ...
        tput  tg1, t5, c0, t4, t6       ; ...
        twait 1 << 1                    ; ...
        sd    t0, u_end(zero)           ; it can be undone now
        sd    t0, u_top(zero)           ; ...
        j     ce_r                      ; ...
ce_lost:
        sd    zero, u_end(zero)         ; too big: the history goes
        sd    zero, u_top(zero)         ; ...
        li    t0, -1                    ; ...
        sd    t0, u_saved(zero)         ; ...
        li    a0, s_ulost               ; ...
        call  msg_s                     ; ...
ce_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; release the frame
        ret                             ; done

; u_apply(a0 = record offset, a1 = 0 undo / 1 redo): the lines it changed
; go back to how they were (undo) or again become what it made (redo)
u_apply:
        addi  sp, sp, -56               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = the far offset of a line record
        sd    s1, 16(sp)                ; s1 = 1 redo
        sd    s2, 24(sp)                ; s2 = the first line
        sd    s3, 32(sp)                ; s3 = lines to delete
        sd    s4, 40(sp)                ; s4 = lines to insert
        sd    s5, 48(sp)                ; s5 = lines inserted
        mv    s1, a1                    ; ...
        li    t0, UBASE                 ; the header
        add   s0, a0, t0                ; ...
        li    t1, hdrb                  ; ...
        li    t2, 48                    ; ...
        tget  tg1, t1, c0, s0, t2       ; ...
        twait 1 << 1                    ; ...
        addi  s0, s0, 48                ; the old lines follow it
        ld    s2, hdrb+8(zero)          ; ...
        ld    s3, hdrb+24(zero)         ; undo: the new lines go, the old come back
        ld    s4, hdrb+16(zero)         ; ...
        beqz  s1, ua_d                  ; ...
        mv    t0, s3                    ; redo: the other way, from the new lines
        mv    s3, s4                    ; ...
        mv    s4, t0                    ; ...
        mv    s5, s3                    ; (skip the old ones)
ua_sk:  beqz  s5, ua_d                  ; ...
        mv    a0, s0                    ; ...
        call  fl_get                    ; ...
        add   s0, s0, a1                ; ...
        addi  s5, s5, -1                ; ...
        j     ua_sk                     ; ...
ua_d:   beqz  s3, ua_i                  ; delete
        mv    a0, s2                    ; ...
        call  ln_del                    ; ...
        addi  s3, s3, -1                ; ...
        j     ua_d                      ; ...
ua_i:   li    s5, 0                     ; insert
ua_il:  bge   s5, s4, ua_c              ; ...
        mv    a0, s0                    ; ...
        call  fl_get                    ; ...
        add   s0, s0, a1                ; ...
        mv    a2, a0                    ; ...
        add   a0, s2, s5                ; ...
        li    a1, tbuf + 8              ; ...
        call  ln_ins                    ; ...
        addi  s5, s5, 1                 ; ...
        j     ua_il                     ; ...
ua_c:   call  fixempty                  ; ...
        ld    t0, hdrb+32(zero)         ; the cursor where it was before the change
        sd    t0, v_cy(zero)            ; ...
        ld    t0, hdrb+40(zero)         ; ...
        sd    t0, v_cx(zero)            ; ...
        li    t0, 1                     ; every row
        sd    t0, v_dall(zero)          ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        ld    s5, 48(sp)                ; ...
        addi  sp, sp, 56                ; release the frame
        ret                             ; done

; u_size(a0 = offset of a record's end) -> a0 = that record's size (its trailer)
u_size: li    t0, UBASE - 8             ; ...
        add   t0, a0, t0                ; ...
        li    t1, hdrb                  ; ...
        li    t2, 8                     ; ...
        tget  tg1, t1, c0, t0, t2       ; ...
        twait 1 << 1                    ; ...
        ld    a0, hdrb(zero)            ; ...
        ret                             ; done

; y_lines(a0 = first line, a1 = lines): their text is the register's
y_lines:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = line
        sd    s1, 16(sp)                ; s1 = past the last
        sd    s2, 24(sp)                ; s2 = offset in the register
        mv    s0, a0                    ; ...
        add   s1, a0, a1                ; ...
        sub   t0, s1, s0                ; ...
        sd    t0, y_cnt(zero)           ; ...
        li    t0, 1                     ; ...
        sd    t0, y_kind(zero)          ; ...
        li    s2, 0                     ; ...
yl_l:   bge   s0, s1, yl_r              ; ...
        mv    a0, s0                    ; ...
        li    a1, tbuf + 8              ; ...
        call  ln_get                    ; ...
        mv    a1, a0                    ; does it fit?
        addi  t0, a0, 15                ; ...
        add   t0, t0, s2                ; ...
        li    t1, YSZ                   ; ...
        bgtu  t0, t1, yl_big            ; ...
        li    a0, YBASE                 ; ...
        add   a0, a0, s2                ; ...
        call  fl_put                    ; ...
        add   s2, s2, a0                ; ...
        addi  s0, s0, 1                 ; ...
        j     yl_l                      ; ...
yl_big: sd    zero, y_cnt(zero)         ; too much: the register is empty
        li    a0, s_ybig                ; ...
        call  msg_s                     ; ...
yl_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; release the frame
        ret                             ; done

; y_chars(a0 = bytes, a1 = length): they are the register's
y_chars:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    a1, 8(sp)                 ; ...
        mv    a2, a1                    ; -> tbuf + 8
        mv    a1, a0                    ; ...
        li    a0, tbuf + 8              ; ...
        call  bmove                     ; ...
        li    a0, YBASE                 ; ...
        ld    a1, 8(sp)                 ; ...
        call  fl_put                    ; ...
        sd    zero, y_kind(zero)        ; ...
        li    t0, 1                     ; ...
        sd    t0, y_cnt(zero)           ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 16                ; release the frame
        ret                             ; done

