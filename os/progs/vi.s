main:
        li    sp, 65536                 ; stack at the top of the D-LS
        call  sys_init                  ; handles, arguments
        li    a0, 1                     ; Ctrl-C makes a read return -2 (it does not end us)
        call  sys_catch                 ; ...
        li    a0, 0                     ; standard input: the console?
        call  sys_hdesc                 ; (server register << 32 | id)
        srli  a0, a0, 32                ; 3 = tty
        addi  a0, a0, -3                ; ...
        seqz  a0, a0                    ; ...
        sd    a0, v_con(zero)           ; ...
        beqz  a0, mn_args               ; a pipe (a window's terminal): raw already
        li    a0, 1                     ; the console: raw mode (keys as they come, no echo)
        call  sys_conmode               ; ...
mn_args:
        li    a0, cmdbuf                ; our arguments: the file name
        call  sys_args                  ; a0 = their length
        li    t0, cmdbuf                ; the first word
        add   a1, t0, a0                ; ...
        mv    a0, t0                    ; ...
        call  arg_next                  ; a0 = start, a1 = length
        li    t0, 120                   ; (a path is at most 120 bytes)
        bleu  a1, t0, mn_n              ; ...
        mv    a1, t0                    ; ...
mn_n:   mv    s0, a0                    ; keep it
        mv    s1, a1                    ; ...
        li    a0, s_ask                 ; ask the terminal its size now: the answer
        call  o_s                       ;   comes while the file is read
        call  out_flush                 ; ...
        mv    a0, s0                    ; the file (none: an empty buffer)
        mv    a1, s1                    ; ...
        call  do_load                   ; ...
        li    a0, 100                   ; the size: an answer within 0.2 s
        call  rd_wait                   ; ...
        beqz  a0, ml_top                ; none: 80 x 24
        ld    t0, kb_pos(zero)          ; a key first (a script): no answer is coming
        lbu   t0, kbuf(t0)              ; ...
        li    t1, 27                    ; ...
        bne   t0, t1, ml_top            ; ...
        call  getkey                    ; a report sets the size; a key waits for its command
        li    t0, K_SIZE                ; ...
        beq   a0, t0, ml_top            ; ...
        sd    a0, k_pend(zero)          ; ...
ml_top: call  refresh                   ; ---- the main loop: show, then one command
        ld    t0, rq_pos(zero)          ; keys from . still to come?
        ld    t1, rq_len(zero)          ; ...
        bltu  t0, t1, ml_cmd            ; yes
        ld    t0, v_dotn(zero)          ; ...
        bnez  t0, ml_cmd                ; ...
        sd    zero, v_rep(zero)         ; no: what is typed is recorded again
ml_cmd: sd    zero, rec_len(zero)       ; a new command's keys
        sd    zero, v_chg(zero)         ; ...
        call  ncmd                      ; one command
        ld    t0, v_chg(zero)           ; a change, typed (not replayed)? It is what . repeats
        beqz  t0, ml_q                  ; ...
        ld    t0, v_rep(zero)           ; ...
        bnez  t0, ml_q                  ; ...
        ld    a2, rec_len(zero)         ; its keys -> dotbuf
        sd    a2, dot_len(zero)         ; ...
        slli  a2, a2, 1                 ; (two bytes a key)
        li    a0, dotbuf                ; ...
        li    a1, recbuf                ; ...
        call  bmove                     ; ...
ml_q:   ld    t0, v_quit(zero)          ; leaving?
        beqz  t0, ml_top                ; no
        li    a0, s_bye                 ; clear the screen for the shell
        call  o_s                       ; ...
        call  out_flush                 ; ...
        ld    t0, v_con(zero)           ; the console back to cooked mode
        beqz  t0, ml_x                  ; ...
        li    a0, 0                     ; ...
        call  sys_conmode               ; ...
ml_x:   li    a0, 0                     ; exit code
        call  sys_exit                  ; flush stdout, end the process

