; ncmd(): one command: a count, a key, and what it does
ncmd:   addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = key
        sd    s1, 16(sp)                ; s1 = count
        li    s1, 0                     ; ...
nc_k:   call  getkey                    ; ...
        mv    s0, a0                    ; ...
        sd    zero, v_msgl(zero)        ; (a key clears the message)
        addi  t0, s0, -'0'              ; a digit of the count? (0 first is a motion)
        li    t1, 10                    ; ...
        bgeu  t0, t1, nc_d              ; ...
        bnez  t0, nc_dg                 ; ...
        beqz  s1, nc_d                  ; ...
nc_dg:  mul   s1, s1, t1                ; ...
        add   s1, s1, t0                ; ...
        j     nc_k                      ; ...
nc_d:   sd    s1, v_cnt(zero)           ; the count
        mv    t0, s1                    ; ...
        bnez  t0, nc_d1                 ; ...
        li    t0, 1                     ; ...
nc_d1:  sd    t0, v_cnt1(zero)          ; ...
        li    t0, 1                     ; the cursor's column is aimed for after it
        sd    t0, v_setw(zero)          ; ...
        mv    a0, s0                    ; keys that are not bytes: as letters
        call  kmapk                     ; ...
        mv    s0, a0                    ; ...
        li    t0, cmdtab                ; a command?
nc_f:   lbu   t1, 0(t0)                 ; ...
        beqz  t1, nc_mo                 ; ...
        addi  t0, t0, 4                 ; ...
        bne   t1, s0, nc_f              ; ...
        lhu   t1, -2(t0)                ; ...
        mv    a0, s0                    ; ...
        jalr  ra, t1, 0                 ; ...
        j     nc_r                      ; ...
nc_mo:  mv    a0, s0                    ; a motion: the cursor goes there
        call  motion                    ; ...
        bltz  a0, nc_r                  ; ...
        ld    t0, mv_y(zero)            ; ...
        sd    t0, v_cy(zero)            ; ...
        ld    t0, mv_x(zero)            ; ...
        sd    t0, v_cx(zero)            ; ...
        ld    t0, mv_w(zero)            ; j and k keep the column aimed for
        beqz  t0, nc_r                  ; ...
        sd    zero, v_setw(zero)        ; ...
        li    t1, 2                     ; $: the end, from now on
        bne   t0, t1, nc_r              ; ...
        li    t1, BIGCOL                ; ...
        sd    t1, v_want(zero)          ; ...
nc_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; release the frame
        ret                             ; done

; kmapk(a0 = key) -> a0 = the normal-mode letter for the arrows and editing
; keys (K_UP: k ...), the key itself for a byte, 0 for anything else
kmapk:  li    t0, 0x100                 ; ...
        blt   a0, t0, km_r              ; ...
        addi  t1, a0, -0x101            ; ...
        li    t2, 10                    ; ...
        li    a0, 0                     ; ...
        bgeu  t1, t2, km_r              ; ...
        lbu   a0, kmap(t1)              ; ...
km_r:   ret                             ; done

; ---- inserting -----------------------------------------------------------------
c_a:    addi  sp, sp, -8                ; a: after the cursor (if there is a character)
        sd    ra, 0(sp)                 ; (the frame is c_ins's)
        call  cur_text                  ; ...
        beqz  a1, c_ins                 ; ...
        ld    t0, v_cx(zero)            ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, v_cx(zero)            ; ...
        j     c_ins                     ; ...
c_A:    addi  sp, sp, -8                ; A: at the end
        sd    ra, 0(sp)                 ; ...
        call  cur_text                  ; ...
        sd    a1, v_cx(zero)            ; ...
        j     c_ins                     ; ...
c_I:    addi  sp, sp, -8                ; I: at the first non-blank
        sd    ra, 0(sp)                 ; ...
        ld    a0, v_cy(zero)            ; ...
        call  fnb                       ; ...
        sd    a0, v_cx(zero)            ; ...
        j     c_ins                     ; ...
c_i:    addi  sp, sp, -8                ; i: before the cursor
        sd    ra, 0(sp)                 ; ...
c_ins:  ld    a0, v_cy(zero)            ; the change is this line
        li    a1, 1                     ; ...
        call  chg_begin                 ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 8                 ; release the frame
        j     ins_run                   ; (tail call)
c_o:    ld    a0, v_cy(zero)            ; o: a new line below
        addi  a0, a0, 1                 ; ...
        j     c_open                    ; ...
c_O:    ld    a0, v_cy(zero)            ; O: above
c_open: addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    a0, 8(sp)                 ; the new line's number
        li    a1, 0                     ; the change adds it
        call  chg_begin                 ; ...
        ld    a0, 8(sp)                 ; ...
        li    a1, lbuf                  ; ...
        li    a2, 0                     ; ...
        call  ln_ins                    ; ...
        ld    a0, 8(sp)                 ; the cursor on it
        sd    a0, v_cy(zero)            ; ...
        sd    zero, v_cx(zero)          ; ...
        call  mark_from                 ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 16                ; release the frame
        j     ins_run                   ; (tail call)

; ins_run(): insert mode on the cursor's line, in a change begun by the
; caller (from chg_a); Esc or Ctrl-C ends it. The line is edited in lbuf.
ins_run:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = key
        li    t0, 1                     ; ...
        sd    t0, v_ins(zero)           ; ...
        call  ir_load                   ; ...
ir_l:   li    t0, 1                     ; (j and k aim for the column typing reaches)
        sd    t0, v_setw(zero)          ; ...
        call  refresh                   ; ...
        call  getkey                    ; ...
        mv    s0, a0                    ; ...
        li    t0, 27                    ; Esc, Ctrl-C: done
        beq   s0, t0, ir_end            ; ...
        li    t0, 3                     ; ...
        beq   s0, t0, ir_end            ; ...
        li    t0, K_EOF                 ; the end of input: done, and leave
        beq   s0, t0, ir_eof            ; ...
        li    t0, 10                    ; Enter: a new line
        beq   s0, t0, ir_nl             ; ...
        li    t0, 13                    ; ...
        beq   s0, t0, ir_nl             ; ...
        li    t0, 127                   ; Backspace
        beq   s0, t0, ir_bs             ; ...
        li    t0, 8                     ; ...
        beq   s0, t0, ir_bs             ; ...
        li    t0, K_DEL                 ; Delete
        beq   s0, t0, ir_del            ; ...
        li    t0, K_END                 ; the arrows, Home, End (other keys: ignored)
        bgt   s0, t0, ir_l              ; ...
        li    t0, 0x100                 ; ...
        bge   s0, t0, ir_mv             ; ...
        li    t0, 9                     ; a tab
        beq   s0, t0, ir_ch             ; ...
        li    t0, 32                    ; other control characters: ignored
        blt   s0, t0, ir_l              ; ...
ir_ch:  ld    t0, v_lblen(zero)         ; room?
        li    t1, LMAX                  ; ...
        bge   t0, t1, ir_l              ; ...
        ld    t1, v_cx(zero)            ; the bytes from the cursor up one
        addi  a1, t1, lbuf              ; ...
        addi  a0, a1, 1                 ; ...
        sub   a2, t0, t1                ; ...
        call  bmove                     ; ...
        ld    t1, v_cx(zero)            ; the byte
        sb    s0, lbuf(t1)              ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, v_cx(zero)            ; ...
        ld    t0, v_lblen(zero)         ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, v_lblen(zero)         ; ...
        j     ir_mk                     ; ...
ir_bs:  ld    t0, v_cx(zero)            ; Backspace: the byte before (not past the start)
        beqz  t0, ir_l                  ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, v_cx(zero)            ; ...
        j     ir_dl                     ; ...
ir_del: ld    t0, v_cx(zero)            ; Delete: the byte under the cursor
        ld    t1, v_lblen(zero)         ; ...
        bge   t0, t1, ir_l              ; ...
ir_dl:  ld    t0, v_cx(zero)            ; the bytes after it down one
        addi  a0, t0, lbuf              ; ...
        addi  a1, a0, 1                 ; ...
        ld    t1, v_lblen(zero)         ; ...
        addi  t1, t1, -1                ; ...
        sd    t1, v_lblen(zero)         ; ...
        sub   a2, t1, t0                ; ...
        call  bmove                     ; ...
ir_mk:  ld    a0, v_cy(zero)            ; its row again
        call  mark_row                  ; ...
        j     ir_l                      ; ...
ir_nl:  ld    a0, v_cy(zero)            ; Enter: the line up to the cursor stays
        li    a1, lbuf                  ; ...
        ld    a2, v_cx(zero)            ; ...
        call  ln_put                    ; ...
        ld    a0, v_cy(zero)            ; the rest is a new line after it
        addi  a0, a0, 1                 ; ...
        ld    t0, v_cx(zero)            ; ...
        addi  a1, t0, lbuf              ; ...
        ld    a2, v_lblen(zero)         ; ...
        sub   a2, a2, t0                ; ...
        call  ln_ins                    ; ...
        ld    t0, v_cx(zero)            ; ... and lbuf
        li    a0, lbuf                  ; ...
        addi  a1, t0, lbuf              ; ...
        ld    a2, v_lblen(zero)         ; ...
        sub   a2, a2, t0                ; ...
        sd    a2, v_lblen(zero)         ; ...
        call  bmove                     ; ...
        ld    a0, v_cy(zero)            ; the rows from here
        call  mark_from                 ; ...
        ld    t0, v_cy(zero)            ; the cursor at its start
        addi  t0, t0, 1                 ; ...
        sd    t0, v_cy(zero)            ; ...
        sd    zero, v_cx(zero)          ; ...
        j     ir_l                      ; ...
ir_mv:  call  ir_commit                 ; an arrow: this change ends here
        li    t0, K_UP                  ; ...
        li    t1, -1                    ; ...
        beq   s0, t0, ir_ud             ; ...
        li    t0, K_DOWN                ; ...
        li    t1, 1                     ; ...
        beq   s0, t0, ir_ud             ; ...
        ld    t2, v_cx(zero)            ; ...
        li    t0, K_LEFT                ; ...
        addi  t3, t2, -1                ; ...
        beq   s0, t0, ir_x              ; ...
        li    t0, K_RIGHT               ; ...
        addi  t3, t2, 1                 ; ...
        beq   s0, t0, ir_x              ; ...
        li    t0, K_HOME                ; ...
        li    t3, 0                     ; ...
        beq   s0, t0, ir_x              ; ...
        li    t0, K_END                 ; ...
        li    t3, BIGCOL                ; ...
        bne   s0, t0, ir_go             ; ...
ir_x:   sd    t3, v_cx(zero)            ; ...
        j     ir_go                     ; ...
ir_ud:  ld    t0, v_cy(zero)            ; ...
        add   t0, t0, t1                ; ...
        sd    t0, v_cy(zero)            ; ...
ir_go:  call  fix_cursor                ; ... and another begins where the cursor is
        ld    a0, v_cy(zero)            ; ...
        li    a1, 1                     ; ...
        call  chg_begin                 ; ...
        call  ir_load                   ; ...
        j     ir_l                      ; ...
ir_eof: sd    s0, k_pend(zero)          ; (the end goes on to normal mode: leave)
ir_end: call  ir_commit                 ; the line back, the change done
        sd    zero, v_ins(zero)         ; ...
        li    t0, 1                     ; ...
        sd    t0, v_setw(zero)          ; ...
        ld    t0, v_cx(zero)            ; the cursor back onto the last byte typed
        beqz  t0, ir_r                  ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, v_cx(zero)            ; ...
ir_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 16                ; release the frame
        ret                             ; done

; ir_load(): the cursor's line into lbuf, to be edited there
ir_load:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save ra
        ld    a0, v_cy(zero)            ; ...
        li    a1, lbuf                  ; ...
        call  ln_get                    ; ...
        sd    a0, v_lblen(zero)         ; ...
        li    t0, 1                     ; ...
        sd    t0, v_lblive(zero)        ; ...
        ld    a0, v_cy(zero)            ; ...
        call  mark_row                  ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 8                 ; release the frame
        ret                             ; done

; ir_commit(): lbuf back into the text; the change ends with the cursor's
; line as its last
ir_commit:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save ra
        ld    a0, v_cy(zero)            ; ...
        li    a1, lbuf                  ; ...
        ld    a2, v_lblen(zero)         ; ...
        call  ln_put                    ; ...
        sd    zero, v_lblive(zero)      ; ...
        ld    a0, v_cy(zero)            ; ...
        call  mark_row                  ; ...
        ld    t0, v_cy(zero)            ; ...
        ld    t1, chg_a(zero)           ; ...
        sub   a0, t0, t1                ; ...
        addi  a0, a0, 1                 ; ...
        call  chg_end                   ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 8                 ; release the frame
        ret                             ; done

; ---- changing ---------------------------------------------------------------------
c_x:    addi  sp, sp, -8                ; x: count characters from the cursor
        sd    ra, 0(sp)                 ; ...
        call  cur_text                  ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        beqz  a1, cx_r                  ; ...
        ld    a0, v_cx(zero)            ; ...
        ld    t1, v_cnt1(zero)          ; ...
        add   t1, a0, t1                ; ...
        ble   t1, a1, cx_1              ; ...
        mv    t1, a1                    ; ...
cx_1:   mv    a1, t1                    ; ...
        li    a2, 'd'                   ; ...
        j     op_chars                  ; ...
cx_r:   ret                             ; done
c_X:    ld    a1, v_cx(zero)            ; X: count characters before it
        beqz  a1, cx_r                  ; ...
        ld    t0, v_cnt1(zero)          ; ...
        sub   a0, a1, t0                ; ...
        bgez  a0, cX_1                  ; ...
        li    a0, 0                     ; ...
cX_1:   li    a2, 'd'                   ; ...
        j     op_chars                  ; ...
c_D:    li    a2, 'd'                   ; D: to the end of the line
        j     c_DC                      ; ...
c_C:    li    a2, 'c'                   ; C: the same, then insert
c_DC:   addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    a2, 8(sp)                 ; ...
        call  cur_text                  ; ...
        ld    a2, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 16                ; release the frame
        ld    a0, v_cx(zero)            ; [cursor, end)
        j     op_chars                  ; ...
c_s:    addi  sp, sp, -8                ; s: count characters, then insert
        sd    ra, 0(sp)                 ; ...
        call  cur_text                  ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ld    a0, v_cx(zero)            ; ...
        ld    t1, v_cnt1(zero)          ; ...
        add   t1, a0, t1                ; ...
        ble   t1, a1, cs_1              ; ...
        mv    t1, a1                    ; ...
cs_1:   mv    a1, t1                    ; ...
        li    a2, 'c'                   ; ...
        j     op_chars                  ; ...
c_S:    li    a0, 'c'                   ; S: as cc
        j     op_lcnt                   ; ...
c_Y:    li    a0, 'y'                   ; Y: as yy
        j     op_lcnt                   ; ...

; op_chars(a0 = from, a1 = to, a2 = 'd' / 'c' / 'y'): the cursor's line's
; bytes [from, to): into the register, and (d, c) out of the line (c: then
; insert mode)
op_chars:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = from
        sd    s1, 16(sp)                ; s1 = to
        sd    s2, 24(sp)                ; s2 = the operator
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        mv    s2, a2                    ; ...
        sd    s0, v_cx(zero)            ; the cursor at the start
        ld    a0, v_cy(zero)            ; the line
        li    a1, lbuf                  ; ...
        call  ln_get                    ; ...
        sd    a0, v_lblen(zero)         ; ...
        addi  a0, s0, lbuf              ; the register
        sub   a1, s1, s0                ; ...
        call  y_chars                   ; ...
        li    t0, 'y'                   ; y: that is all
        beq   s2, t0, oc_r              ; ...
        ld    a0, v_cy(zero)            ; the change: this line
        li    a1, 1                     ; ...
        call  chg_begin                 ; ...
        addi  a0, s0, lbuf              ; the bytes after them come down
        addi  a1, s1, lbuf              ; ...
        ld    a2, v_lblen(zero)         ; ...
        sub   a2, a2, s1                ; ...
        call  bmove                     ; ...
        ld    t0, v_lblen(zero)         ; ...
        sub   t0, t0, s1                ; ...
        add   t0, t0, s0                ; ...
        sd    t0, v_lblen(zero)         ; ...
        ld    a0, v_cy(zero)            ; ...
        li    a1, lbuf                  ; ...
        mv    a2, t0                    ; ...
        call  ln_put                    ; ...
        ld    a0, v_cy(zero)            ; ...
        call  mark_row                  ; ...
        li    t0, 'c'                   ; c: insert mode goes on with the change
        beq   s2, t0, oc_ins            ; ...
        li    a0, 1                     ; d: the change is one line
        call  chg_end                   ; ...
oc_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; release the frame
        ret                             ; done
oc_ins: ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; release the frame
        j     ins_run                   ; (tail call)

; op_lcnt(a0 = operator): count lines from the cursor's (dd cc yy)
op_lcnt:
        ld    a1, v_cy(zero)            ; [cursor, cursor + count - 1], within the text
        ld    t1, v_cnt1(zero)          ; ...
        add   a2, a1, t1                ; ...
        addi  a2, a2, -1                ; ...
        ld    t2, v_nl(zero)            ; ...
        blt   a2, t2, op_lines          ; ...
        addi  a2, t2, -1                ; ...
; op_lines(a0 = 'd' / 'c' / 'y', a1 = first line, a2 = last): those lines
; into the register and (d) out of the text, or (c) replaced by an empty
; line in insert mode
op_lines:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = operator
        sd    s1, 16(sp)                ; s1 = first line
        sd    s2, 24(sp)                ; s2 = lines
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        sub   s2, a2, a1                ; ...
        addi  s2, s2, 1                 ; ...
        mv    a0, s1                    ; the register
        mv    a1, s2                    ; ...
        call  y_lines                   ; ...
        sd    s1, v_cy(zero)            ; the cursor on the first
        li    t0, 'y'                   ; y: that is all
        beq   s0, t0, ol_r              ; ...
        mv    a0, s1                    ; the change
        mv    a1, s2                    ; ...
        call  chg_begin                 ; ...
ol_d:   mv    a0, s1                    ; out
        call  ln_del                    ; ...
        addi  s2, s2, -1                ; ...
        bnez  s2, ol_d                  ; ...
        mv    a0, s1                    ; the rows from there
        call  mark_from                 ; ...
        li    t0, 'c'                   ; c: an empty line, insert mode
        beq   s0, t0, ol_c              ; ...
        call  fixempty                  ; d: (an empty text gets its empty line)
        call  chg_end                   ; ...
        ld    t0, v_nl(zero)            ; the cursor on the line after (or the last)
        blt   s1, t0, ol_f              ; ...
        addi  s1, t0, -1                ; ...
ol_f:   sd    s1, v_cy(zero)            ; ...
        mv    a0, s1                    ; ...
        call  fnb                       ; ...
        sd    a0, v_cx(zero)            ; ...
ol_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; release the frame
        ret                             ; done
ol_c:   mv    a0, s1                    ; ...
        li    a1, lbuf                  ; ...
        li    a2, 0                     ; ...
        call  ln_ins                    ; ...
        sd    zero, v_cx(zero)          ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; release the frame
        j     ins_run                   ; (tail call)

; c_op(a0 = 'd' / 'c' / 'y'): an operator: doubled (dd) for lines, or a
; motion (a count may come between: d3w)
c_op:   addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = operator
        sd    s1, 16(sp)                ; s1 = the second count
        sd    s2, 24(sp)                ; s2 = key
        mv    s0, a0                    ; ...
        li    s1, 0                     ; ...
co_k:   call  getkey                    ; ...
        mv    s2, a0                    ; ...
        addi  t0, s2, -'0'              ; a count?
        li    t1, 10                    ; ...
        bgeu  t0, t1, co_c              ; ...
        bnez  t0, co_dg                 ; ...
        beqz  s1, co_c                  ; ...
co_dg:  mul   s1, s1, t1                ; ...
        add   s1, s1, t0                ; ...
        j     co_k                      ; ...
co_c:   beqz  s1, co_1                  ; the counts multiply
        ld    t0, v_cnt1(zero)          ; ...
        mul   t0, t0, s1                ; ...
        sd    t0, v_cnt1(zero)          ; ...
        sd    t0, v_cnt(zero)           ; ...
co_1:   mv    a0, s2                    ; keys that are not bytes: as letters
        call  kmapk                     ; ...
        mv    s2, a0                    ; ...
        bne   s2, s0, co_cw             ; doubled: lines
        mv    a0, s0                    ; ...
        call  op_lcnt                   ; ...
        j     co_r                      ; ...
co_cw:  li    t0, 'c'                   ; cw on a word: as ce (the blanks after it stay)
        bne   s0, t0, co_m              ; ...
        li    t0, 'w'                   ; ...
        bne   s2, t0, co_m              ; ...
        call  cur_text                  ; ...
        ld    t0, v_cx(zero)            ; ...
        bgeu  t0, a1, co_m              ; ...
        add   t1, a0, t0                ; ...
        lbu   t1, 0(t1)                 ; ...
        lbu   t1, ctype(t1)             ; ...
        andi  t1, t1, 16                ; ...
        bnez  t1, co_m                  ; ...
        li    s2, 'e'                   ; ...
co_m:   mv    a0, s2                    ; the motion
        call  motion                    ; ...
        bltz  a0, co_r                  ; (none: nothing happens)
        li    t0, 2                     ; to a line: lines
        beq   a0, t0, co_ln             ; ...
        mv    s1, a0                    ; s1 = the kind (the second count is used up)
        call  cur_text                  ; a1 = the line's length
        ld    t0, v_cx(zero)            ; t0, t1 = the two ends
        ld    t1, mv_x(zero)            ; ...
        ld    t2, v_cy(zero)            ; ...
        ld    t3, mv_y(zero)            ; ...
        blt   t2, t3, co_fw             ; to a later line: to the end of this one
        bgt   t2, t3, co_bk             ; to an earlier one: from the start of this one
        ble   t0, t1, co_or             ; the same line: in order
        mv    t4, t0                    ; ...
        mv    t0, t1                    ; ...
        mv    t1, t4                    ; ...
co_or:  beqz  s1, co_go                 ; inclusive: one more
        addi  t1, t1, 1                 ; ...
        j     co_go                     ; ...
co_fw:  mv    t1, a1                    ; ...
        j     co_go                     ; ...
co_bk:  mv    t1, t0                    ; ...
        li    t0, 0                     ; ...
co_go:  ble   t1, a1, co_g2             ; (not past the end)
        mv    t1, a1                    ; ...
co_g2:  mv    a0, t0                    ; ...
        mv    a1, t1                    ; ...
        mv    a2, s0                    ; ...
        call  op_chars                  ; ...
        j     co_r                      ; ...
co_ln:  ld    a1, v_cy(zero)            ; lines from the cursor's to the motion's
        ld    a2, mv_y(zero)            ; ...
        ble   a1, a2, co_l2             ; ...
        mv    t0, a1                    ; ...
        mv    a1, a2                    ; ...
        mv    a2, t0                    ; ...
co_l2:  mv    a0, s0                    ; ...
        call  op_lines                  ; ...
co_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; release the frame
        ret                             ; done

; c_r(): r: count characters replaced by the next key
c_r:    addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = the byte
        sd    s1, 16(sp)                ; s1 = past the last replaced
        call  getkey                    ; ...
        mv    s0, a0                    ; ...
        li    t0, 9                     ; a tab, or printable
        beq   s0, t0, cr_1              ; ...
        addi  t0, s0, -32               ; ...
        li    t1, 95                    ; ...
        bgeu  t0, t1, cr_r              ; (anything else: nothing)
cr_1:   call  cur_text                  ; enough characters?
        ld    t0, v_cx(zero)            ; ...
        ld    t1, v_cnt1(zero)          ; ...
        add   s1, t0, t1                ; ...
        bgt   s1, a1, cr_r              ; ...
        ld    a0, v_cy(zero)            ; the change
        li    a1, 1                     ; ...
        call  chg_begin                 ; ...
        ld    a0, v_cy(zero)            ; ...
        li    a1, lbuf                  ; ...
        call  ln_get                    ; ...
        sd    a0, v_lblen(zero)         ; ...
        ld    t0, v_cx(zero)            ; ...
cr_l:   sb    s0, lbuf(t0)              ; ...
        addi  t0, t0, 1                 ; ...
        blt   t0, s1, cr_l              ; ...
        addi  t0, s1, -1                ; the cursor on the last
        sd    t0, v_cx(zero)            ; ...
        ld    a0, v_cy(zero)            ; ...
        li    a1, lbuf                  ; ...
        ld    a2, v_lblen(zero)         ; ...
        call  ln_put                    ; ...
        li    a0, 1                     ; ...
        call  chg_end                   ; ...
        ld    a0, v_cy(zero)            ; ...
        call  mark_row                  ; ...
cr_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; release the frame
        ret                             ; done

; c_J(): J: the count of lines (two at least) joined into one: the leading
; blanks of each go, and a space comes between (unless the line ends in a
; blank, or the next starts with ")")
c_J:    addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = joins left
        sd    s1, 16(sp)                ; s1 = the next line's length
        sd    s2, 24(sp)                ; s2 = its first non-blank
        ld    s0, v_cnt1(zero)          ; joins: count - 1, one at least
        addi  s0, s0, -1                ; ...
        bgtz  s0, cj_1                  ; ...
        li    s0, 1                     ; ...
cj_1:   ld    t0, v_cy(zero)            ; (not past the last line)
        ld    t1, v_nl(zero)            ; ...
        sub   t1, t1, t0                ; ...
        addi  t1, t1, -1                ; ...
        ble   s0, t1, cj_2              ; ...
        mv    s0, t1                    ; ...
cj_2:   blez  s0, cj_r                  ; ...
        ld    a0, v_cy(zero)            ; the change
        addi  a1, s0, 1                 ; ...
        call  chg_begin                 ; ...
        ld    a0, v_cy(zero)            ; ...
        li    a1, lbuf                  ; ...
        call  ln_get                    ; ...
        sd    a0, v_lblen(zero)         ; ...
cj_l:   ld    a0, v_cy(zero)            ; the next line
        addi  a0, a0, 1                 ; ...
        li    a1, tbuf + 8              ; ...
        call  ln_get                    ; ...
        mv    s1, a0                    ; ...
        li    a0, tbuf + 8              ; past its blanks
        mv    a1, s1                    ; ...
        li    a2, 0                     ; ...
        call  skip_bl                   ; ...
        mv    s2, a0                    ; ...
        ld    t0, v_lblen(zero)         ; the cursor where they meet
        sd    t0, v_cx(zero)            ; ...
        beqz  t0, cj_cp                 ; a space between?
        bgeu  s2, s1, cj_cp             ; ...
        lbu   t1, lbuf-1(t0)            ; ...
        lbu   t1, ctype(t1)             ; ...
        andi  t1, t1, 16                ; ...
        bnez  t1, cj_cp                 ; ...
        addi  t1, s2, tbuf + 8          ; ...
        lbu   t1, 0(t1)                 ; ...
        li    t2, ')'                   ; ...
        beq   t1, t2, cj_cp             ; ...
        li    t1, ' '                   ; ...
        sb    t1, lbuf(t0)              ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, v_lblen(zero)         ; ...
cj_cp:  ld    t0, v_lblen(zero)         ; the rest of it, as much as fits
        sub   a2, s1, s2                ; ...
        add   t1, t0, a2                ; ...
        li    t2, LMAX                  ; ...
        ble   t1, t2, cj_c2             ; ...
        sub   a2, t2, t0                ; ...
        add   t1, t0, a2                ; ...
cj_c2:  sd    t1, v_lblen(zero)         ; ...
        addi  a0, t0, lbuf              ; ...
        addi  a1, s2, tbuf + 8          ; ...
        call  bmove                     ; ...
        ld    a0, v_cy(zero)            ; and that line goes
        addi  a0, a0, 1                 ; ...
        call  ln_del                    ; ...
        addi  s0, s0, -1                ; ...
        bnez  s0, cj_l                  ; ...
        ld    a0, v_cy(zero)            ; the joined line
        li    a1, lbuf                  ; ...
        ld    a2, v_lblen(zero)         ; ...
        call  ln_put                    ; ...
        li    a0, 1                     ; ...
        call  chg_end                   ; ...
        ld    a0, v_cy(zero)            ; ...
        call  mark_from                 ; ...
cj_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; release the frame
        ret                             ; done

; c_p / c_P: the register, count times: lines below (above) the cursor's
; line, or characters after (before) the cursor
c_p:    li    a0, 1                     ; after
        j     put                       ; ...
c_P:    li    a0, 0                     ; before
put:    addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = 1 after
        sd    s1, 16(sp)                ; s1 = repetitions left
        sd    s2, 24(sp)                ; s2 = where (line, or byte)
        sd    s3, 32(sp)                ; s3 = far offset / length
        sd    s4, 40(sp)                ; s4 = lines of the register left / lines put
        mv    s0, a0                    ; ...
        ld    s1, v_cnt1(zero)          ; ...
        ld    t0, y_cnt(zero)           ; anything?
        beqz  t0, pu_r                  ; ...
        ld    t0, y_kind(zero)          ; characters?
        beqz  t0, pu_ch                 ; ...
        ld    s2, v_cy(zero)            ; lines: below or above
        add   s2, s2, s0                ; ...
        mv    a0, s2                    ; the change adds them
        li    a1, 0                     ; ...
        call  chg_begin                 ; ...
        ld    a0, v_cy(zero)            ; (the cursor goes to the first)
        add   a0, a0, s0                ; ...
        sd    a0, v_cy(zero)            ; ...
        call  mark_from                 ; ...
pu_rep: li    s3, YBASE                 ; one copy of the register
        ld    s4, y_cnt(zero)           ; ...
pu_ln:  mv    a0, s3                    ; a line of it
        call  fl_get                    ; ...
        add   s3, s3, a1                ; ...
        mv    a2, a0                    ; ...
        mv    a0, s2                    ; ...
        li    a1, tbuf + 8              ; ...
        call  ln_ins                    ; ...
        bnez  a0, pu_le                 ; (the pool is full)
        addi  s2, s2, 1                 ; ...
        addi  s4, s4, -1                ; ...
        bnez  s4, pu_ln                 ; ...
        addi  s1, s1, -1                ; again?
        bnez  s1, pu_rep                ; ...
pu_le:  ld    t0, v_cy(zero)            ; the change made s2 - first lines
        sub   a0, s2, t0                ; ...
        call  chg_end                   ; ...
        ld    a0, v_cy(zero)            ; the cursor at the first non-blank
        call  fnb                       ; ...
        sd    a0, v_cx(zero)            ; ...
        j     pu_r                      ; ...
pu_ch:  ld    a0, v_cy(zero)            ; characters: the change is this line
        li    a1, 1                     ; ...
        call  chg_begin                 ; ...
        li    a0, YBASE                 ; the register's text -> tbuf + 8
        call  fl_get                    ; ...
        mv    s3, a0                    ; ...
        ld    a0, v_cy(zero)            ; the line -> lbuf
        li    a1, lbuf                  ; ...
        call  ln_get                    ; ...
        sd    a0, v_lblen(zero)         ; ...
        ld    s2, v_cx(zero)            ; after the cursor (if the line has a byte there)
        beqz  a0, pu_c1                 ; ...
        add   s2, s2, s0                ; ...
pu_c1:  ld    t0, v_lblen(zero)         ; room?
        add   t1, t0, s3                ; ...
        li    t2, LMAX                  ; ...
        bgt   t1, t2, pu_c2             ; ...
        sd    t1, v_lblen(zero)         ; ...
        addi  a1, s2, lbuf              ; the bytes after the place up
        add   a0, a1, s3                ; ...
        sub   a2, t0, s2                ; ...
        call  bmove                     ; ...
        addi  a0, s2, lbuf              ; the text
        li    a1, tbuf + 8              ; ...
        mv    a2, s3                    ; ...
        call  bmove                     ; ...
        add   s2, s2, s3                ; ...
        addi  s1, s1, -1                ; again?
        bnez  s1, pu_c1                 ; ...
pu_c2:  addi  t0, s2, -1                ; the cursor on the last byte put
        bgez  t0, pu_c3                 ; ...
        li    t0, 0                     ; ...
pu_c3:  sd    t0, v_cx(zero)            ; ...
        ld    a0, v_cy(zero)            ; ...
        li    a1, lbuf                  ; ...
        ld    a2, v_lblen(zero)         ; ...
        call  ln_put                    ; ...
        li    a0, 1                     ; ...
        call  chg_end                   ; ...
        ld    a0, v_cy(zero)            ; ...
        call  mark_row                  ; ...
pu_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        addi  sp, sp, 48                ; release the frame
        ret                             ; done

; c_u / c_redo: undo / redo, count times
c_u:    addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = times left
        ld    s0, v_cnt1(zero)          ; ...
cu_l:   ld    a0, u_end(zero)           ; anything to undo?
        bnez  a0, cu_1                  ; ...
        li    a0, s_oldest              ; ...
        call  msg_s                     ; ...
        j     cu_r                      ; ...
cu_1:   call  u_size                    ; the last record: its start
        ld    t0, u_end(zero)           ; ...
        sub   a0, t0, a0                ; ...
        sd    a0, u_end(zero)           ; (undone)
        li    a1, 0                     ; ...
        call  u_apply                   ; ...
        addi  s0, s0, -1                ; ...
        bnez  s0, cu_l                  ; ...
cu_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 16                ; release the frame
        ret                             ; done
c_redo: addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = times left
        ld    s0, v_cnt1(zero)          ; ...
cr2_l:  ld    a0, u_end(zero)           ; anything to redo?
        ld    t0, u_top(zero)           ; ...
        bne   a0, t0, cr2_1             ; ...
        li    a0, s_newest              ; ...
        call  msg_s                     ; ...
        j     cu_r                      ; ...
cr2_1:  li    a1, 1                     ; ...
        call  u_apply                   ; ...
        ld    t0, u_end(zero)           ; its size: its first word (in hdrb)
        ld    t1, hdrb(zero)            ; ...
        add   t0, t0, t1                ; ...
        sd    t0, u_end(zero)           ; (redone)
        addi  s0, s0, -1                ; ...
        bnez  s0, cr2_l                 ; ...
        j     cu_r                      ; ...

; c_dot(): . : the last change's keys again (count times)
c_dot:  ld    t0, dot_len(zero)         ; ...
        beqz  t0, cd_r                  ; ...
        sd    zero, rq_pos(zero)        ; ...
        sd    t0, rq_len(zero)          ; ...
        ld    t1, v_cnt1(zero)          ; ...
        addi  t1, t1, -1                ; ...
        sd    t1, v_dotn(zero)          ; ...
        li    t0, 1                     ; ...
        sd    t0, v_rep(zero)           ; ...
cd_r:   ret                             ; done

; ---- scrolling and the rest ---------------------------------------------------------
c_cd:   ld    a0, v_trows(zero)         ; Ctrl-D: half a screen down
        srli  a0, a0, 1                 ; ...
        mv    a1, a0                    ; ...
        j     scroll                    ; ...
c_cu:   ld    a0, v_trows(zero)         ; Ctrl-U: half a screen up
        srli  a0, a0, 1                 ; ...
        neg   a0, a0                    ; ...
        mv    a1, a0                    ; ...
        j     scroll                    ; ...
c_cf:   ld    a0, v_trows(zero)         ; Ctrl-F: a screen down (two lines stay)
        addi  a0, a0, -2                ; ...
        li    a1, -1                    ; (the cursor: on the new top line)
        j     scroll                    ; ...
c_cb:   ld    a0, v_trows(zero)         ; Ctrl-B: a screen up
        addi  a0, a0, -2                ; ...
        neg   a0, a0                    ; ...
        li    a1, -2                    ; (the cursor: on the new bottom line)
; scroll(a0 = lines the screen moves, a1 = lines the cursor moves; -1: to
; the top line, -2: to the bottom one)
scroll: addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save ra
        ld    t0, v_top(zero)           ; the top: within the text
        add   t0, t0, a0                ; ...
        ld    t1, v_nl(zero)            ; ...
        blt   t0, t1, sc_1              ; ...
        addi  t0, t1, -1                ; ...
sc_1:   bgez  t0, sc_2                  ; ...
        li    t0, 0                     ; ...
sc_2:   sd    t0, v_top(zero)           ; ...
        mv    t2, t0                    ; the cursor
        li    t3, -1                    ; ...
        beq   a1, t3, sc_3              ; ...
        ld    t3, v_trows(zero)         ; ...
        add   t2, t0, t3                ; ...
        addi  t2, t2, -1                ; ...
        li    t3, -2                    ; ...
        beq   a1, t3, sc_3              ; ...
        ld    t2, v_cy(zero)            ; ...
        add   t2, t2, a1                ; ...
sc_3:   sd    t2, v_cy(zero)            ; (fix_cursor keeps it in the text)
        li    t0, 1                     ; ...
        sd    t0, v_dall(zero)          ; ...
        call  fix_cursor                ; ...
        ld    a0, v_cy(zero)            ; at the first non-blank
        call  fnb                       ; ...
        sd    a0, v_cx(zero)            ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 8                 ; release the frame
        ret                             ; done

c_cl:   li    t0, 1                     ; Ctrl-L: clear, draw everything, ask the size
        sd    t0, v_clear(zero)         ; ...
        sd    t0, v_dall(zero)          ; ...
        li    a0, s_ask                 ; (the answer comes as a key: K_SIZE)
        j     o_s                       ; (tail call)
c_cg:   addi  sp, sp, -8                ; Ctrl-G: the file and its size
        sd    ra, 0(sp)                 ; ...
        call  m_name                    ; ...
        call  m_size                    ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; done
c_Z:    addi  sp, sp, -8                ; ZZ: as :x
        sd    ra, 0(sp)                 ; ...
        call  getkey                    ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        li    t0, 'Z'                   ; ...
        bne   a0, t0, cz_r              ; ...
        sd    zero, x_bang(zero)        ; ...
        sd    zero, x_argl(zero)        ; ...
        j     ex_x                      ; ...
cz_r:   ret                             ; done
c_ctlc: li    a0, s_ctlc                ; Ctrl-C: how to leave
        j     msg_s                     ; (tail call)
c_eof:  li    t0, 1                     ; the end of input: leave
        sd    t0, v_quit(zero)          ; ...
        ret                             ; done

