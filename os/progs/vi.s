; motion(a0 = key) -> a0 = -1 (not a motion, or it failed), 0 to a
; character (exclusive), 1 to a character (inclusive), 2 to a line; the
; place in mv_y, mv_x (mv_w: 1 j and k, 2 $). The count is v_cnt1.
motion: addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = key
        sd    s1, 16(sp)                ; s1 = count
        mv    s0, a0                    ; ...
        ld    s1, v_cnt1(zero)          ; ...
        ld    t0, v_cy(zero)            ; from the cursor
        sd    t0, mv_y(zero)            ; ...
        sd    t0, p_y(zero)             ; ...
        ld    t0, v_cx(zero)            ; ...
        sd    t0, mv_x(zero)            ; ...
        sd    t0, p_x(zero)             ; ...
        sd    zero, mv_w(zero)          ; ...
        li    t0, mvtab                 ; which?
mo_f:   lbu   t1, 0(t0)                 ; ...
        beqz  t1, mo_no                 ; ...
        addi  t0, t0, 4                 ; ...
        bne   t1, s0, mo_f              ; ...
        lhu   t1, -2(t0)                ; ...
        jr    t1                        ; (each ends at mo_ret with a0 = the kind)
mo_no:  li    a0, -1                    ; ...
mo_ret: ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; release the frame
        ret                             ; done
mo_h:   ld    t0, mv_x(zero)            ; left
        sub   t0, t0, s1                ; ...
        bgez  t0, mo_x0                 ; ...
        li    t0, 0                     ; ...
mo_x0:  sd    t0, mv_x(zero)            ; ...
        li    a0, 0                     ; ...
        j     mo_ret                    ; ...
mo_l:   call  cur_text                  ; right (up to the end: for d, c, y)
        ld    t0, mv_x(zero)            ; ...
        add   t0, t0, s1                ; ...
        ble   t0, a1, mo_x0             ; ...
        mv    t0, a1                    ; ...
        j     mo_x0                     ; ...
mo_j:   ld    t0, mv_y(zero)            ; down
        add   t0, t0, s1                ; ...
        j     mo_jk                     ; ...
mo_k:   ld    t0, mv_y(zero)            ; up
        sub   t0, t0, s1                ; ...
mo_jk:  call  mo_line                   ; ...
        li    t0, 1                     ; (the column aimed for stays)
        sd    t0, mv_w(zero)            ; ...
        ld    a0, mv_y(zero)            ; the byte at that column
        call  ln_find                   ; ...
        ld    a2, v_want(zero)          ; ...
        call  xcol                      ; ...
        sd    a0, mv_x(zero)            ; ...
        li    a0, 2                     ; ...
        j     mo_ret                    ; ...
mo_nl:  ld    t0, mv_y(zero)            ; down, to the first non-blank
        add   t0, t0, s1                ; ...
        j     mo_fl                     ; ...
mo_minus:
        ld    t0, mv_y(zero)            ; up, ...
        sub   t0, t0, s1                ; ...
        j     mo_fl                     ; ...
mo_G:   ld    t0, v_cnt(zero)           ; line N, or the last
        addi  t0, t0, -1                ; ...
        bgez  t0, mo_fl                 ; ...
        ld    t0, v_nl(zero)            ; ...
        addi  t0, t0, -1                ; ...
        j     mo_fl                     ; ...
mo_g:   call  getkey                    ; gg: line N, or the first
        li    t0, 'g'                   ; ...
        bne   a0, t0, mo_no             ; ...
        ld    t0, v_cnt(zero)           ; ...
        addi  t0, t0, -1                ; ...
        bgez  t0, mo_fl                 ; ...
        li    t0, 0                     ; ...
mo_fl:  call  mo_line                   ; (t0 = the line)
        ld    a0, mv_y(zero)            ; ...
        call  fnb                       ; ...
        sd    a0, mv_x(zero)            ; ...
        li    a0, 2                     ; ...
        j     mo_ret                    ; ...
mo_0:   sd    zero, mv_x(zero)          ; the start of the line
        li    a0, 0                     ; ...
        j     mo_ret                    ; ...
mo_hat: ld    a0, mv_y(zero)            ; its first non-blank
        call  fnb                       ; ...
        sd    a0, mv_x(zero)            ; ...
        li    a0, 0                     ; ...
        j     mo_ret                    ; ...
mo_dol: call  cur_text                  ; its last byte (inclusive)
        addi  a1, a1, -1                ; ...
        bgez  a1, mo_d1                 ; ...
        li    a1, 0                     ; ...
mo_d1:  sd    a1, mv_x(zero)            ; ...
        li    t0, 2                     ; (j and k go to the end from now on)
        sd    t0, mv_w(zero)            ; ...
        li    a0, 1                     ; ...
        j     mo_ret                    ; ...
mo_w:   call  w_fwd                     ; words
        addi  s1, s1, -1                ; ...
        bnez  s1, mo_w                  ; ...
        li    a0, 0                     ; ...
        j     mo_p                      ; ...
mo_b:   call  w_back                    ; ...
        addi  s1, s1, -1                ; ...
        bnez  s1, mo_b                  ; ...
        li    a0, 0                     ; ...
        j     mo_p                      ; ...
mo_e:   call  w_end                     ; ...
        addi  s1, s1, -1                ; ...
        bnez  s1, mo_e                  ; ...
        li    a0, 1                     ; ...
mo_p:   ld    t0, p_y(zero)             ; the position walked to
        sd    t0, mv_y(zero)            ; ...
        ld    t0, p_x(zero)             ; ...
        sd    t0, mv_x(zero)            ; ...
        j     mo_ret                    ; ...
mo_pct: call  m_pair                    ; the matching bracket
        beqz  a0, mo_no                 ; ...
        li    a0, 1                     ; ...
        j     mo_p                      ; ...
mo_n:   ld    a0, v_sdir(zero)          ; the next match
        j     mo_s                      ; ...
mo_N:   ld    a0, v_sdir(zero)          ; the other way
        neg   a0, a0                    ; ...
mo_s:   call  search                    ; ...
        beqz  a0, mo_no                 ; ...
        li    a0, 0                     ; ...
        j     mo_ret                    ; ...

; mo_line(t0 = a line, maybe out of range): mv_y = it, within the text
mo_line:
        ld    t1, v_nl(zero)            ; ...
        blt   t0, t1, ml_1              ; ...
        addi  t0, t1, -1                ; ...
ml_1:   bgez  t0, ml_2                  ; ...
        li    t0, 0                     ; ...
ml_2:   sd    t0, mv_y(zero)            ; ...
        ret                             ; done

; pos_get() -> a0 = the byte at (p_y, p_x) (10 at a line's end), a1 = the
; line's length
pos_get:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save ra
        ld    a0, p_y(zero)             ; ...
        call  ln_find                   ; ...
        ld    t0, p_x(zero)             ; ...
        add   t1, a0, t0                ; ...
        li    a0, 10                    ; ...
        bgeu  t0, a1, pg_r              ; ...
        lbu   a0, 0(t1)                 ; ...
pg_r:   ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 8                 ; release the frame
        ret                             ; done

; pos_cls() -> a0 = the class of the byte at the position: 0 blank (a line's
; end too), 1 a word's (letters, digits, _), 2 other, 3 an empty line
pos_cls:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save ra
        call  pos_get                   ; ...
        li    t0, 10                    ; a line's end
        bne   a0, t0, pcl_1             ; ...
        li    a0, 3                     ; (an empty line)
        beqz  a1, pcl_r                 ; ...
        li    a0, 0                     ; ...
        j     pcl_r                     ; ...
pcl_1:  lbu   t0, ctype(a0)             ; ...
        li    a0, 0                     ; ...
        andi  t1, t0, 16                ; ...
        bnez  t1, pcl_r                 ; ...
        li    a0, 1                     ; ...
        andi  t1, t0, 3                 ; ...
        bnez  t1, pcl_r                 ; ...
        li    a0, 2                     ; ...
pcl_r:  ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 8                 ; release the frame
        ret                             ; done

; pos_next() -> a0 = 0 at the end of the text: one byte on (a line's end
; counts as one)
pos_next:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save ra
        call  pos_get                   ; a1 = the length
        ld    t0, p_x(zero)             ; ...
        li    a0, 1                     ; ...
        bgeu  t0, a1, pnx_nl            ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, p_x(zero)             ; ...
        j     pnx_r                     ; ...
pnx_nl: ld    t1, p_y(zero)             ; the next line's start
        addi  t1, t1, 1                 ; ...
        ld    t2, v_nl(zero)            ; ...
        li    a0, 0                     ; ...
        bge   t1, t2, pnx_r             ; ...
        sd    t1, p_y(zero)             ; ...
        sd    zero, p_x(zero)           ; ...
        li    a0, 1                     ; ...
pnx_r:  ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 8                 ; release the frame
        ret                             ; done

; pos_prev() -> a0 = 0 at the start of the text: one byte back
pos_prev:
        ld    t0, p_x(zero)             ; ...
        beqz  t0, ppv_up                ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, p_x(zero)             ; ...
        li    a0, 1                     ; ...
        ret                             ; done
ppv_up: ld    t1, p_y(zero)             ; the line before's end
        li    a0, 0                     ; ...
        beqz  t1, ppv_r                 ; ...
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save ra
        addi  a0, t1, -1                ; ...
        sd    a0, p_y(zero)             ; ...
        call  ln_find                   ; ...
        sd    a1, p_x(zero)             ; ...
        li    a0, 1                     ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 8                 ; release the frame
ppv_r:  ret                             ; done

; w_fwd(): the position to the start of the next word (w)
w_fwd:  addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = the class it starts in
        call  pos_cls                   ; ...
        mv    s0, a0                    ; ...
        beqz  s0, wf_bl                 ; on a blank: skip the blanks
        li    t0, 3                     ; on an empty line: one on
        beq   s0, t0, wf_st             ; ...
wf_same:
        call  pos_next                  ; past the word
        beqz  a0, wf_r                  ; ...
        call  pos_cls                   ; ...
        beq   a0, s0, wf_same           ; ...
        j     wf_b2                     ; ...
wf_st:  call  pos_next                  ; ...
        beqz  a0, wf_r                  ; ...
wf_bl:  call  pos_cls                   ; blanks (and line ends)
wf_b2:  bnez  a0, wf_r                  ; a word, or an empty line: there
        call  pos_next                  ; ...
        bnez  a0, wf_bl                 ; ...
wf_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 16                ; release the frame
        ret                             ; done

; w_end(): the position to the end of the word (e)
w_end:  addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = the word's class
        call  pos_next                  ; one on
        beqz  a0, we_r                  ; ...
we_bl:  call  pos_cls                   ; past blanks and empty lines
        beqz  a0, we_sk                 ; ...
        li    t0, 3                     ; ...
        bne   a0, t0, we_w              ; ...
we_sk:  call  pos_next                  ; ...
        bnez  a0, we_bl                 ; ...
        j     we_r                      ; ...
we_w:   mv    s0, a0                    ; then while the next byte is of the word
we_l:   ld    t0, p_y(zero)             ; ...
        sd    t0, 16(sp)                ; ...
        ld    t0, p_x(zero)             ; ...
        sd    t0, 24(sp)                ; ...
        call  pos_next                  ; ...
        beqz  a0, we_bk                 ; ...
        call  pos_cls                   ; ...
        beq   a0, s0, we_l              ; ...
we_bk:  ld    t0, 16(sp)                ; (back to its last byte)
        sd    t0, p_y(zero)             ; ...
        ld    t0, 24(sp)                ; ...
        sd    t0, p_x(zero)             ; ...
we_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 32                ; release the frame
        ret                             ; done

; w_back(): the position to the start of this word or the one before (b)
w_back: addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = the word's class
        call  pos_prev                  ; one back
        beqz  a0, wb_r                  ; ...
wb_bl:  call  pos_cls                   ; back past blanks
        bnez  a0, wb_w                  ; ...
        call  pos_prev                  ; ...
        bnez  a0, wb_bl                 ; ...
        j     wb_r                      ; ...
wb_w:   mv    s0, a0                    ; an empty line is a word of its own
        li    t0, 3                     ; ...
        beq   s0, t0, wb_r              ; ...
wb_l:   ld    t0, p_x(zero)             ; back while the byte before is of the word
        beqz  t0, wb_r                  ; (not over a line's start)
        ld    t0, p_y(zero)             ; ...
        sd    t0, 16(sp)                ; ...
        ld    t0, p_x(zero)             ; ...
        sd    t0, 24(sp)                ; ...
        call  pos_prev                  ; ...
        call  pos_cls                   ; ...
        beq   a0, s0, wb_l              ; ...
        ld    t0, 16(sp)                ; (forward again)
        sd    t0, p_y(zero)             ; ...
        ld    t0, 24(sp)                ; ...
        sd    t0, p_x(zero)             ; ...
wb_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 32                ; release the frame
        ret                             ; done

; m_pair() -> a0 = 1 with the position on the bracket matching the first
; one at or after the cursor on its line (%), 0 if none
m_pair: addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = the bracket
        sd    s1, 16(sp)                ; s1 = its match
        sd    s2, 24(sp)                ; s2 = 1 forward, 0 backward
        sd    s3, 32(sp)                ; s3 = depth
        call  pos_get                   ; a bracket at or after the cursor
mp_f:   ld    t0, p_x(zero)             ; ...
        bgeu  t0, a1, mp_no             ; none on the line
        call  pos_get                   ; ...
        li    t1, 0                     ; which one?
mp_b:   lbu   t2, brk(t1)               ; ...
        beq   t2, a0, mp_got            ; ...
        addi  t1, t1, 1                 ; ...
        li    t3, 6                     ; ...
        blt   t1, t3, mp_b              ; ...
        ld    t0, p_x(zero)             ; not a bracket: the next byte
        addi  t0, t0, 1                 ; ...
        sd    t0, p_x(zero)             ; ...
        j     mp_f                      ; ...
mp_got: mv    s0, a0                    ; ...
        xori  t2, t1, 1                 ; its pair
        lbu   s1, brk(t2)               ; ...
        andi  s2, t1, 1                 ; even: opening (forward)
        xori  s2, s2, 1                 ; ...
        li    s3, 0                     ; ...
mp_l:   call  pos_get                   ; the byte here
        bne   a0, s0, mp_l2             ; ...
        addi  s3, s3, 1                 ; ...
mp_l2:  bne   a0, s1, mp_st             ; ...
        addi  s3, s3, -1                ; ...
        beqz  s3, mp_yes                ; ...
mp_st:  beqz  s2, mp_bk                 ; one step
        call  pos_next                  ; ...
        j     mp_s2                     ; ...
mp_bk:  call  pos_prev                  ; ...
mp_s2:  bnez  a0, mp_l                  ; ...
mp_no:  li    a0, 0                     ; ...
        j     mp_r                      ; ...
mp_yes: li    a0, 1                     ; ...
mp_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        addi  sp, sp, 40                ; release the frame
        ret                             ; done

; search(a0 = 1 forward / -1 backward) -> a0 = 1 with the match in mv_y,
; mv_x (from the cursor, round the end of the text), 0 if there is none
search: addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; s0 = direction
        sd    s1, 16(sp)                ; s1 = line
        sd    s2, 24(sp)                ; s2 = from this byte
        sd    s3, 32(sp)                ; s3 = lines left to look in
        sd    s4, 40(sp)                ; s4 = 1 when it went round
        mv    s0, a0                    ; ...
        ld    t0, v_patl(zero)          ; something to look for?
        bnez  t0, se_go                 ; ...
        li    a0, s_nopat               ; ...
        call  msg_s                     ; ...
        li    a0, 0                     ; ...
        j     se_r                      ; ...
se_go:  ld    s1, v_cy(zero)            ; from the byte after (before) the cursor
        ld    s2, v_cx(zero)            ; ...
        add   s2, s2, s0                ; ...
        ld    s3, v_nl(zero)            ; every line, and this one again
        addi  s3, s3, 1                 ; ...
        li    s4, 0                     ; ...
se_l:   mv    a0, s1                    ; this line
        call  ln_find                   ; ...
        mv    a2, s2                    ; ...
        mv    a3, s0                    ; ...
        call  sfind                     ; ...
        bgez  a0, sr_yes                ; ...
        addi  s3, s3, -1                ; ...
        beqz  s3, sr_no                 ; ...
        add   s1, s1, s0                ; the next line (round the end)
        li    s2, 0                     ; (forward: from its start)
        bltz  s0, se_bk                 ; ...
        ld    t0, v_nl(zero)            ; ...
        blt   s1, t0, se_l              ; ...
        li    s1, 0                     ; ...
        li    s4, 1                     ; ...
        j     se_l                      ; ...
se_bk:  li    s2, BIGCOL                ; (backward: from its end)
        bgez  s1, se_l                  ; ...
        ld    s1, v_nl(zero)            ; ...
        addi  s1, s1, -1                ; ...
        li    s4, 1                     ; ...
        j     se_l                      ; ...
sr_yes: sd    s1, mv_y(zero)            ; found
        sd    a0, mv_x(zero)            ; ...
        beqz  s4, se_1                  ; went round: say so
        li    a0, s_wrapb               ; ...
        bgez  s0, se_w                  ; ...
        li    a0, s_wrapt               ; ...
se_w:   call  msg_s                     ; ...
se_1:   li    a0, 1                     ; ...
        j     se_r                      ; ...
sr_no:  li    a0, s_nofind              ; "Pattern not found: text"
        call  msg_s                     ; ...
        li    a0, patbuf                ; ...
        ld    a1, v_patl(zero)          ; ...
        call  m_add                     ; ...
        li    a0, 0                     ; ...
se_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        addi  sp, sp, 48                ; release the frame
        ret                             ; done

; sfind(a0 = text, a1 = length, a2 = from, a3 = 1 forward / -1 backward)
; -> a0 = where the search text starts, the first at or after (the last at
; or before) from, or -1
sfind:  ld    t5, v_patl(zero)          ; the last place it can start
        sub   t4, a1, t5                ; ...
        bltz  a3, sf_bk                 ; ...
        bgez  a2, sf_l                  ; forward: from max(from, 0)
        li    a2, 0                     ; ...
        j     sf_l                      ; ...
sf_bk:  ble   a2, t4, sf_l              ; backward: from min(from, last)
        mv    a2, t4                    ; ...
sf_l:   bltz  a2, sf_no                 ; ...
        bgt   a2, t4, sf_no             ; ...
        li    t0, 0                     ; does it match here?
sf_c:   beq   t0, t5, sf_yes            ; ...
        add   t1, a0, a2                ; ...
        add   t1, t1, t0                ; ...
        lbu   t1, 0(t1)                 ; ...
        lbu   t2, patbuf(t0)            ; ...
        bne   t1, t2, sf_nx             ; ...
        addi  t0, t0, 1                 ; ...
        j     sf_c                      ; ...
sf_nx:  add   a2, a2, a3                ; ...
        j     sf_l                      ; ...
sf_yes: mv    a0, a2                    ; ...
        ret                             ; done
sf_no:  li    a0, -1                    ; ...
        ret                             ; done

