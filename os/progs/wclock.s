; =============================================================================
; wclock.s: a clock in a window
; =============================================================================
;
;   wclock          (from a shell in a terminal, or the palette: Alt+Space)
;
; A client of the window server (os/lib/wsclient.s) that shows timers and
; damage: once a second it draws the digits, the second ticks and the small
; line (os/ws/wclock.s) into its band and lends the band to the server, then
; waits in EVENT with a timeout that ends at the next second. A resize draws
; again at the new size; `q` or a close event ends the program. StrataOS has
; no calendar: the time shown is the time since boot.

        .text                           ; instruction Local Store
_start: j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program

        .include "../ws/theme.s"        ; the palette
        .include "../lib/gfx.s"         ; surfaces and display lists
        .include "../lib/font/font.s"   ; the small font
        .include "../ws/fmt.s"          ; numbers into text
        .include "../ws/wclock.s"       ; the renderer
        .include "../lib/sys.s"         ; the program library
        .include "../lib/wsclient.s"    ; the window server's protocol

        .data                           ; D-LS
        .align 8                        ; dwords
wk_ck:    .space CK_SIZE                ; the renderer's state
wk_title: .ascii "WCLOCK\0\0"           ; the window's title
wk_nows:  .ascii "wclock: no window server (run ws first)\n"
wk_nows_e:                              ; (its end)
        .text                           ; code

main:
        call  sys_init                  ; handles
        la    a0, wk_title              ; our window
        li    a1, 0                     ; ...
        call  wc_open                   ; ...
        bgtz  a0, wk_go                 ; ...
        la    a0, wk_nows               ; no server
        li    a1, wk_nows_e - wk_nows   ; ...
        call  err_str                   ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...
wk_go:  la    t0, wk_ck                 ; the renderer draws through the band
        la    t1, wc_surf               ; ...
        sd    t1, CK_SURF(t0)           ; ...
wk_loop:
        call  sys_now                   ; the time since boot
        mv    s0, a0                    ; s0 = microseconds
        la    t0, wc_surf               ; the rows that change: from 2 above the digits
        ld    t1, S_H(t0)               ;   to under the small line (as ck_draw places
        addi  s1, t1, -CK_DH            ;   them: digits at (H - DH) / 2 - 18)
        srai  s1, s1, 1                 ; ...
        addi  s1, s1, -20               ; s1 = first row
        addi  s2, s1, CK_DH + 68        ; s2 = past the last
        bgez  s1, wk_1                  ; (clipped to the window)
        li    s1, 0                     ; ...
wk_1:   ble   s2, t1, wk_2              ; ...
        mv    s2, t1                    ; ...
wk_2:   mv    a0, s1                    ; the band holds those rows
        call  wc_band                   ; ...
        la    a0, wk_ck                 ; draw them
        li    t0, 1000000               ; seconds
        divu  a2, s0, t0                ; (uptime)
        li    t0, 86400                 ; ...
        remu  a1, a2, t0                ; (of the day)
        li    a3, 0                     ; the changing band only: the server filled the rest
        call  ck_draw                   ; ...
        mv    a0, s1                    ; lend them
        sub   a1, s2, s1                ; ...
        call  wc_damage                 ; ...
        bltz  a0, wk_end                ; the window is gone
        call  sys_now                   ; wait until the next second begins
        li    t0, 1000000               ; ...
        remu  t1, a0, t0                ; ...
        sub   a1, t0, t1                ; ...
        addi  a1, a1, 2000              ; (just inside it)
wk_ev:  li    a0, 0                     ; an event, or the timeout
        call  wc_event                  ; ...
        li    t0, -8                    ; the second is over
        beq   a0, t0, wk_loop           ; ...
        bnez  a0, wk_end                ; the window is gone
        la    t0, wc_ev                 ; its kind
        ld    t1, 0(t0)                 ; ...
        li    t2, WE_SIZE               ; a resize: draw at the new size
        beq   t1, t2, wk_loop           ; ...
        li    t2, WE_CLOSE              ; close: end
        beq   t1, t2, wk_end            ; ...
        li    t2, WE_KEY                ; a key: q ends
        bne   t1, t2, wk_loop           ; ...
        ld    t4, 8(t0)                 ; (its first byte)
        andi  t4, t4, 0xff              ; ...
        li    t6, 'q'                   ; ...
        bne   t4, t6, wk_loop           ; ...
wk_end: call  wc_close                  ; the window goes
        li    a0, 0                     ; ...
        call  sys_exit                  ; ...
