; =============================================================================
; nc.s: a tiny netcat over the network server
; =============================================================================
;
;   nc ADDRESS PORT        TCP: connect, send standard input until its end,
;                          then print what comes back until the peer closes
;   nc -l PORT             TCP: wait for one connection, print what arrives
;                          until the peer closes
;   nc -u ADDRESS PORT     UDP: each read of standard input is one datagram;
;                          then answers are printed for half a second
;   nc -u -l PORT          UDP: wait for one datagram and print it
;
; A refused connection is tried again for ten seconds (the listener may be
; starting). What arrives while standard input is still being sent is
; printed as it comes. Exit status 0, 1 on failure, 2 on bad arguments.

        .data                           ; data Local Store
        .align 8                        ; ...
ibuf:   .space 4096                     ; standard input
nbuf:   .space 4096                     ; from the network
ip:     .dword -1                       ; the address
port:   .dword 0                        ; the port
udp:    .dword 0                        ; -u
lsn:    .dword 0                        ; -l
sock:   .dword -1                       ; the socket's handle
s_use:  .ascii "usage: nc [-u] ADDRESS PORT | nc [-u] -l PORT\n" ; ...
s_use_e:
s_nonet: .ascii "nc: no network server\n" ; ...
s_nonet_e:
s_fail: .ascii "nc: failed: "           ; ...
s_fail_e:
s_from: .ascii "from "                  ; ...
s_from_e:
s_u:    .ascii "-u"                     ; options
s_l:    .ascii "-l"                     ; ...
        .align 8                        ; ...

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        li    sp, 65536                 ; stack at the top of the D-LS
        call  sys_init                  ; ...
        call  sys_cmdline               ; s1 = cursor, s2 = end
        add   s2, a0, a1                ; ...
        mv    a1, s2                    ; skip the program's name
        call  arg_next                  ; ...
        mv    s1, a2                    ; ...
        li    s5, 0                     ; s5 = plain words seen
m_arg:
        mv    a0, s1                    ; the next word
        mv    a1, s2                    ; ...
        call  arg_next                  ; ...
        beqz  a1, m_go                  ; no more
        mv    s1, a2                    ; ...
        mv    s3, a0                    ; ...
        mv    s4, a1                    ; ...
        la    a2, s_u                   ; -u
        li    a3, 2                     ; ...
        call  str_eq                    ; ...
        beqz  a0, m_a1                  ; ...
        la    t0, udp                   ; ...
        li    t1, 1                     ; ...
        sd    t1, 0(t0)                 ; ...
        j     m_arg                     ; ...
m_a1:
        mv    a0, s3                    ; -l
        mv    a1, s4                    ; ...
        la    a2, s_l                   ; ...
        li    a3, 2                     ; ...
        call  str_eq                    ; ...
        beqz  a0, m_a2                  ; ...
        la    t0, lsn                   ; ...
        li    t1, 1                     ; ...
        sd    t1, 0(t0)                 ; ...
        j     m_arg                     ; ...
m_a2:
        mv    a0, s3                    ; a number: the port; else the address
        mv    a1, s4                    ; ...
        call  str_num                   ; ...
        bltz  a0, m_a3                  ; ...
        li    t1, 65535                 ; ...
        bgtu  a0, t1, m_use             ; ...
        la    t0, port                  ; ...
        sd    a0, 0(t0)                 ; ...
        j     m_arg                     ; ...
m_a3:
        mv    a0, s3                    ; ...
        mv    a1, s4                    ; ...
        call  net_aton                  ; ...
        bltz  a0, m_use                 ; ...
        la    t0, ip                    ; ...
        sd    a0, 0(t0)                 ; ...
        j     m_arg                     ; ...
m_use:
        la    a0, s_use                 ; ...
        li    a1, s_use_e - s_use       ; ...
        call  err_str                   ; ...
        li    a0, 2                     ; ...
        call  sys_exit                  ; ...
m_go:
        la    t0, port                  ; a port is needed
        ld    t0, 0(t0)                 ; ...
        beqz  t0, m_use                 ; ...
        la    t0, lsn                   ; and an address unless listening
        ld    t0, 0(t0)                 ; ...
        bnez  t0, m_net                 ; ...
        la    t0, ip                    ; ...
        ld    t0, 0(t0)                 ; ...
        bltz  t0, m_use                 ; ...
m_net:
        call  net_init                  ; the network server
        bnez  a0, m_nonet               ; ...
        la    t0, udp                   ; which mode
        ld    t0, 0(t0)                 ; ...
        la    t1, lsn                   ; ...
        ld    t1, 0(t1)                 ; ...
        bnez  t0, m_udp                 ; ...
        bnez  t1, tcp_listen            ; ...
        j     tcp_client                ; ...
m_udp:
        bnez  t1, udp_listen            ; ...
        j     udp_client                ; ...
m_nonet:
        la    a0, s_nonet               ; ...
        li    a1, s_nonet_e - s_nonet   ; ...
        call  err_str                   ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...

; fail(a0 = the error): report it, exit 1
fail:
        mv    s3, a0                    ; ...
        la    a0, s_fail                ; ...
        li    a1, s_fail_e - s_fail     ; ...
        call  out_str                   ; ...
        mv    a0, s3                    ; ...
        call  out_sdec                  ; ...
        call  out_nl                    ; ...
        call  out_flush                 ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...

; ---- TCP client --------------------------------------------------------------------------
tcp_client:
        li    s3, 100                   ; s3 = tries (a refusal: 100 ms, again)
tc_conn:
        la    a0, ip                    ; ...
        ld    a0, 0(a0)                 ; ...
        la    a1, port                  ; ...
        ld    a1, 0(a1)                 ; ...
        call  net_connect               ; a0 = handle
        bgez  a0, tc_up                 ; ...
        li    t0, -1                    ; refused: again for a while
        bne   a0, t0, fail              ; ...
        addi  s3, s3, -1                ; ...
        blez  s3, fail                  ; ...
        li    a0, 100000                ; ...
        call  sys_sleep                 ; ...
        j     tc_conn                   ; ...
tc_up:
        la    t0, sock                  ; ...
        sd    a0, 0(t0)                 ; ...
tc_in:
        li    a0, 0                     ; standard input -> the connection
        la    a1, ibuf                  ; ...
        li    a2, 4032                  ; ...
        call  sys_read                  ; ...
        blez  a0, tc_eof                ; its end
        mv    a2, a0                    ; ...
        la    t0, sock                  ; ...
        ld    a0, 0(t0)                 ; ...
        la    a1, ibuf                  ; ...
        call  sys_write                 ; ...
        bltz  a0, tc_close              ; the connection is gone
tc_drain:
        la    t0, sock                  ; what came meanwhile -> standard output
        ld    a0, 0(t0)                 ; ...
        la    a1, nbuf                  ; ...
        li    a2, 4032                  ; ...
        call  sys_readnb                ; ...
        blez  a0, tc_in                 ; (nothing yet, -3)
        mv    a2, a0                    ; ...
        li    a0, 1                     ; ...
        la    a1, nbuf                  ; ...
        call  sys_write                 ; ...
        j     tc_drain                  ; ...
tc_eof:
        la    t0, sock                  ; no more to send: FIN
        ld    a0, 0(t0)                 ; ...
        call  net_shutdown              ; ...
        call  copy_out                  ; the rest, until the peer closes
tc_close:
        la    t0, sock                  ; ...
        ld    a0, 0(t0)                 ; ...
        call  sys_close                 ; ...
        li    a0, 0                     ; ...
        call  sys_exit                  ; ...

; copy_out(): the connection -> standard output, until its end
copy_out:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
co_l:
        la    t0, sock                  ; ...
        ld    a0, 0(t0)                 ; ...
        la    a1, nbuf                  ; ...
        li    a2, 4032                  ; ...
        call  sys_read                  ; ...
        blez  a0, co_ret                ; the end (or an error)
        mv    a2, a0                    ; ...
        li    a0, 1                     ; ...
        la    a1, nbuf                  ; ...
        call  sys_write                 ; ...
        j     co_l                      ; ...
co_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; ---- TCP listener --------------------------------------------------------------------------
tcp_listen:
        la    a0, port                  ; ...
        ld    a0, 0(a0)                 ; ...
        call  net_listen                ; s3 = the listener
        bltz  a0, fail                  ; ...
        mv    s3, a0                    ; ...
        li    a1, 0                     ; one connection
        call  net_accept                ; ...
        bltz  a0, fail                  ; ...
        la    t0, sock                  ; ...
        sd    a0, 0(t0)                 ; ...
        mv    a0, s3                    ; no more listening
        call  sys_close                 ; ...
        call  copy_out                  ; what arrives
        j     tc_close                  ; ...

; ---- UDP -----------------------------------------------------------------------------------
udp_client:
        li    a0, 0                     ; any local port
        call  net_udp                   ; ...
        bltz  a0, fail                  ; ...
        la    t0, sock                  ; ...
        sd    a0, 0(t0)                 ; ...
uc_l:
        li    a0, 0                     ; a read of standard input ...
        la    a1, ibuf                  ; ...
        li    a2, 1472                  ; ...
        call  sys_read                  ; ...
        blez  a0, uc_ans                ; ...
        mv    a4, a0                    ; ... is a datagram
        la    t0, sock                  ; ...
        ld    a0, 0(t0)                 ; ...
        la    a1, ip                    ; ...
        ld    a1, 0(a1)                 ; ...
        la    a2, port                  ; ...
        ld    a2, 0(a2)                 ; ...
        la    a3, ibuf                  ; ...
        call  net_sendto                ; ...
        bltz  a0, fail                  ; ...
        j     uc_l                      ; ...

uc_ans:
        li    s6, 5                     ; answers, for half a second
uc_al:
        la    t0, sock                  ; one there?
        ld    a0, 0(t0)                 ; ...
        la    a1, nbuf                  ; ...
        li    a2, 1472                  ; ...
        li    a3, 1                     ; (do not block)
        call  net_recvfrom              ; ...
        bltz  a0, uc_aw                 ; no
        call  pr_dgram                  ; ...
        j     uc_al                     ; ...
uc_aw:
        addi  s6, s6, -1                ; wait a little
        blez  s6, tc_close              ; ...
        li    a0, 100000                ; ...
        call  sys_sleep                 ; ...
        j     uc_al                     ; ...

udp_listen:
        la    a0, port                  ; ...
        ld    a0, 0(a0)                 ; ...
        call  net_udp                   ; ...
        bltz  a0, fail                  ; ...
        la    t0, sock                  ; ...
        sd    a0, 0(t0)                 ; ...
        la    a1, nbuf                  ; one datagram
        li    a2, 1472                  ; ...
        li    a3, 0                     ; ...
        call  net_recvfrom              ; a0 = bytes, a1 = address, a2 = port
        bltz  a0, fail                  ; ...
        call  pr_dgram                  ; ...
        j     tc_close                  ; ...

; pr_dgram(a0 = bytes in nbuf, a1 = sender, a2 = its port): "from 10.0.0.2:49152: " and the bytes
pr_dgram:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        mv    s3, a0                    ; ...
        mv    s4, a1                    ; ...
        mv    s5, a2                    ; ...
        la    a0, s_from                ; "from 10.0.0.2:49152: " then the bytes
        li    a1, s_from_e - s_from     ; ...
        call  out_str                   ; ...
        mv    a0, s4                    ; ...
        call  out_ip                    ; ...
        li    a0, ':'                   ; ...
        call  out_chr                   ; ...
        mv    a0, s5                    ; ...
        call  out_dec                   ; ...
        li    a0, ':'                   ; ...
        call  out_chr                   ; ...
        li    a0, ' '                   ; ...
        call  out_chr                   ; ...
        la    a0, nbuf                  ; ...
        mv    a1, s3                    ; ...
        call  out_str                   ; ...
        call  out_flush                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

        .include "../lib/sys.s"         ; the program library
