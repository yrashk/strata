; =============================================================================
; term.s: a terminal window: `sh -i` behind two pipes
; =============================================================================
;
;   term            (started by ws: Alt+Enter, or the palette)
;   term COMMAND    the same, with COMMAND typed into the shell first
;
; A client of the window server (os/lib/wsclient.s). It creates a window,
; starts `sh -i` with a pipe as its standard input and another as its
; standard output and error, and then does two things:
;   - what the shell and its programs write comes out of the output pipe:
;     the bytes go through the terminal grid (os/ws/term.s: the 2.6 subset)
;     and the rows that changed are drawn into the band and lent to the
;     server (DAMAGE); when a program asks where the cursor is (ESC [ 6 n:
;     how vi learns the window's size), the answer ESC [ row ; column R
;     goes into the shell's input pipe, as a terminal would type it;
;   - keys arrive as events from the server and are written to the shell's
;     input pipe; Ctrl-C (the key 0x03) becomes SIGNAL to the shell, which
;     interrupts its foreground job.
; A process blocks in one call at a time, and this one blocks in READ on the
; output pipe. So it asks the server (CREATE flag 1) to interrupt it when
; events wait: the SIGNAL makes the READ return -2, and the events are
; fetched without blocking. Nothing is polled.
;
; D-LS: the library's buffers 13 KiB, strips 5 KiB, fonts 3 KiB, and the
; grid: 50 rows of 160 cells (a full-screen window at 1280 x 800), 16 KiB:
; with it the data ends 304 bytes below 0xA000, the end of a program's D-LS.
; Scrollback: 512 rows in far memory, the top 160 KiB of the arena (which
; is the band otherwise: wc_keep).

GRID_CAP  = 50                          ; ring rows of the grid
GRID_STR  = 160                         ; cells per ring row (a row: 320 bytes, whole words)
FAR_ROWS  = 512                         ; scrollback kept in far memory (the arena's top 160 KiB)
RDMAX     = 512                         ; bytes read from the shell at a time

        .text                           ; instruction Local Store
_start: j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program

        .include "../ws/theme.s"        ; the palette (panel, cursor colours)
        .include "../lib/gfx.s"         ; surfaces and display lists
        .include "../lib/font/font.s"   ; the 8 x 16 font
        .include "../ws/term.s"         ; the terminal grid and its renderer
        .include "../lib/sys.s"         ; the program library
        .include "../lib/wsclient.s"    ; the window server's protocol

        .data                           ; D-LS
        .align 8                        ; dwords
tm_ts:    .space TS_SIZE                ; the terminal
tm_sh:    .dword 0                      ; the shell's pid
tm_in:    .dword 0                      ; write end of the shell's input pipe
tm_out:   .dword 0                      ; read end of its output pipe
tm_quit:  .dword 0                      ; 1: the window is closing
tm_args:  .space 448                    ; our arguments: a command for the shell
tm_buf:   .space RDMAX                  ; bytes from the shell
tm_keys:  .space 16                     ; a key event's bytes
tm_rep:   .space 24                     ; a cursor position report
tm_title: .ascii "TERM\0\0\0\0"         ; the window's title
tm_cmd:   .ascii "sh -i"                ; the shell
tm_nl:    .ascii "\n"                   ; Enter
tm_nows:  .ascii "term: no window server (run ws first)\n"
tm_nows_e:                              ; (its end)
        .align 8                        ; transfer buffers
tm_grid:  .space GRID_CAP * GRID_STR * 2 ; the cells
tm_rbuf:  .space GRID_STR * 2           ; a row of far history, being drawn
        .text                           ; code

main:
        call  sys_init                  ; handles and arguments
        li    a0, 1                     ; interrupts make our calls return -2
        call  sys_catch                 ; ...
        la    a0, tm_args               ; a command to type first?
        call  sys_args                  ; a0 = its length
        mv    s3, a0                    ; s3 = that
        la    t0, wc_keep               ; the arena's top: far history, not band
        li    t1, FAR_ROWS * GRID_STR * 2 ; ...
        sd    t1, 0(t0)                 ; ...
        la    a0, tm_title              ; our window; the server interrupts us
        li    a1, 1                     ;   when events wait
        call  wc_open                   ; ...
        bgtz  a0, tm_win                ; ...
        la    a0, tm_nows               ; no server
        li    a1, tm_nows_e - tm_nows   ; ...
        call  err_str                   ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...
tm_win: la    a0, tm_ts                 ; the grid, drawn through the band
        la    a1, tm_grid               ; ...
        li    a2, GRID_CAP              ; ...
        li    a3, GRID_STR              ; ...
        la    a4, wc_surf               ; ...
        call  term_init                 ; ...
        la    a0, tm_ts                 ; the scrollback in the arena's top
        li    a1, 0                     ; (c0)
        clen  a2, c0                    ; ...
        li    t0, FAR_ROWS * GRID_STR * 2 ; ...
        sub   a2, a2, t0                ; ...
        li    a3, FAR_ROWS              ; ...
        la    a4, tm_rbuf               ; ...
        call  term_far                  ; ...
        call  tm_resize                 ; columns and rows from the window's size
        call  sys_pipe                  ; the shell's input: a0 read, a1 write
        bltz  a0, tm_end                ; ...
        mv    s0, a0                    ; s0 = its read end
        la    t0, tm_in                 ; ...
        sd    a1, 0(t0)                 ; ...
        call  sys_pipe                  ; its output
        bltz  a0, tm_end                ; ...
        mv    s1, a1                    ; s1 = its write end
        la    t0, tm_out                ; ...
        sd    a0, 0(t0)                 ; ...
        li    a0, 0                     ; SPAWN "sh -i": one thread ...
        li    a1, 0                     ; ...
        la    a2, tm_cmd                ; ...
        li    a3, 5                     ; ...
        mv    a4, s0                    ; ... reading the input pipe ...
        mv    a5, s1                    ; ... writing the output pipe
        mv    a6, s1                    ; ...
        call  sys_spawn                 ; a0 = its pid
        blez  a0, tm_end                ; ...
        la    t0, tm_sh                 ; ...
        sd    a0, 0(t0)                 ; ...
        mv    a0, s0                    ; our copies of the shell's ends: closed (the
        call  sys_close                 ;   output pipe ends when the shell's side does)
        mv    a0, s1                    ; ...
        call  sys_close                 ; ...
        beqz  s3, tm_loop               ; a command: type it, and Enter
        la    t0, tm_in                 ; ...
        ld    a0, 0(t0)                 ; ...
        la    a1, tm_args               ; ...
        mv    a2, s3                    ; ...
        call  sys_write                 ; ...
        la    t0, tm_in                 ; ...
        ld    a0, 0(t0)                 ; ...
        la    a1, tm_nl                 ; ...
        li    a2, 1                     ; ...
        call  sys_write                 ; ...
tm_loop:
        call  tm_events                 ; keys, resizes, close (without blocking)
        call  tm_flush                  ; show what changed
        la    t0, tm_quit               ; closing?
        ld    t0, 0(t0)                 ; ...
        bnez  t0, tm_end                ; ...
        la    t0, tm_out                ; wait for the shell's output
        ld    a0, 0(t0)                 ; ...
        la    a1, tm_buf                ; ...
        li    a2, RDMAX                 ; ...
        call  sys_read                  ; a0 = bytes, 0 the end, -2 interrupted
        beqz  a0, tm_end                ; the shell is gone
        bltz  a0, tm_loop               ; interrupted: the server has events for us
        mv    a2, a0                    ; into the grid
        la    a0, tm_ts                 ; ...
        la    a1, tm_buf                ; ...
        call  term_write                ; ...
        call  tm_dsr                    ; (a report asked for: answered)
        j     tm_loop                   ; ...
tm_end: la    t0, tm_sh                 ; the shell goes with its terminal
        ld    a0, 0(t0)                 ; ...
        beqz  a0, tm_e1                 ; ...
        call  sys_kill                  ; ...
tm_e1:  call  wc_close                  ; the window too
        li    a0, 0                     ; ...
        call  sys_exit                  ; ...

; tm_resize(): the grid takes the window's size; everything is drawn again
tm_resize:                              ; routine entry
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        la    t0, wc_surf               ; columns = width / 8, rows = height / 16
        la    a0, tm_ts                 ; ...
        ld    a1, S_W(t0)               ; ...
        srli  a1, a1, 3                 ; ...
        ld    a2, S_H(t0)               ; ...
        srli  a2, a2, 4                 ; ...
        call  term_resize               ; ...
        la    a0, tm_ts                 ; ...
        call  term_all                  ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; tm_dsr(): the program asked where the cursor is (ESC [ 6 n): ESC [ row ;
; column R (from 1) into its input
tm_dsr:                                 ; routine entry
        la    a0, tm_ts                 ; asked?
        ld    t0, TS_DSR(a0)            ; ...
        beqz  t0, td_r                  ; ...
        sd    zero, TS_DSR(a0)          ; ...
        la    t6, tm_rep                ; t6 = where the report goes
        li    t0, 0x1b                  ; ESC [
        sb    t0, 0(t6)                 ; ...
        li    t0, '['                   ; ...
        sb    t0, 1(t6)                 ; ...
        addi  t6, t6, 2                 ; ...
        ld    t1, TS_CY(a0)             ; the row
        addi  t1, t1, 1                 ; ...
        li    t2, ';'                   ; ...
        jal   t5, td_num                ; ...
        ld    t1, TS_CX(a0)             ; the column (one waiting to wrap: the last)
        ld    t0, TS_COLS(a0)           ; ...
        blt   t1, t0, td_c              ; ...
        addi  t1, t0, -1                ; ...
td_c:   addi  t1, t1, 1                 ; ...
        li    t2, 'R'                   ; ...
        jal   t5, td_num                ; ...
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        la    t0, tm_in                 ; -> the shell's input pipe
        ld    a0, 0(t0)                 ; ...
        la    a1, tm_rep                ; ...
        sub   a2, t6, a1                ; ...
        call  sys_write                 ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
td_r:   ret                             ; done
td_num: li    t3, 100                   ; (t1 = 1..999 -> digits at t6, then t2; back to t5)
        li    t4, 0                     ; t4 = 1 once a digit is written
td_d:   divu  t0, t1, t3                ; this digit
        remu  t1, t1, t3                ; ...
        or    t4, t4, t0                ; (no leading zeros)
        beqz  t4, td_n                  ; ...
        addi  t0, t0, '0'               ; ...
        sb    t0, 0(t6)                 ; ...
        addi  t6, t6, 1                 ; ...
        li    t4, 1                     ; ...
td_n:   li    t0, 10                    ; the next power of ten down
        divu  t3, t3, t0                ; ...
        bnez  t3, td_d                  ; ...
        sb    t2, 0(t6)                 ; the byte after the number
        addi  t6, t6, 1                 ; ...
        jr    t5                        ; ...

; tm_events(): every event that waits
tm_events:                              ; routine entry
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = key bytes left
        sd    s1, 16(sp)                ; s1 = bytes for the shell so far
te_l:   li    a0, 1                     ; do not block
        li    a1, 0                     ; ...
        call  wc_event                  ; ...
        li    t0, -3                    ; none left
        beq   a0, t0, te_r              ; ...
        bnez  a0, te_quit               ; the window is gone
        la    t0, wc_ev                 ; its kind
        ld    t1, 0(t0)                 ; ...
        li    t2, WE_KEY                ; ...
        beq   t1, t2, te_key            ; ...
        li    t2, WE_SIZE               ; ...
        beq   t1, t2, te_size           ; ...
        li    t2, WE_CLOSE              ; ...
        beq   t1, t2, te_quit           ; ...
        li    t2, WE_WHEEL              ; the wheel: scrollback
        beq   t1, t2, te_wheel          ; ...
        li    t2, WE_PTR                ; other pointer events: nothing to do
        beq   t1, t2, te_l              ; ...
        li    t3, C_ACCENT              ; focus in: a bright cursor
        li    t2, WE_FOCUS              ; ...
        beq   t1, t2, te_cur            ; ...
        li    t3, C_EDGE                ; focus out: a dim one
te_cur: la    a0, tm_ts                 ; ...
        sd    t3, TS_CURON(a0)          ; ...
        ld    a1, TS_CY(a0)             ; its row is drawn again
        call  term_dirty                ; ...
        j     te_l                      ; ...
te_size:
        call  tm_resize                 ; (wc_event has set the new size)
        j     te_l                      ; ...
te_wheel:
        ld    t1, 8(t0)                 ; wheel y (> 0: away from the user: back)
        slli  t1, t1, 16                ; ...
        srai  t1, t1, 56                ; ...
        slli  a1, t1, 1                 ; three rows a notch
        add   a1, a1, t1                ; ...
        la    a0, tm_ts                 ; ...
        call  term_scroll               ; (the rows it marked are drawn as usual)
        j     te_l                      ; ...
te_key: ld    s0, 16(t0)                ; the number of bytes
        ld    t1, 8(t0)                 ; the bytes, first in the low byte
        la    t2, tm_keys               ; ...
        sd    t1, 0(t2)                 ; ...
        li    s1, 0                     ; ...
        li    t3, 0                     ; index
te_k:   bge   t3, s0, te_kw             ; ...
        add   t4, t2, t3                ; ...
        lbu   t5, 0(t4)                 ; ...
        addi  t3, t3, 1                 ; ...
        li    t6, 3                     ; Ctrl-C: not a byte for the shell
        beq   t5, t6, te_kc             ; ...
        add   t4, t2, s1                ; keep it
        sb    t5, 8(t4)                 ; ...
        addi  s1, s1, 1                 ; ...
        j     te_k                      ; ...
te_kc:  la    t0, tm_sh                 ; SIGNAL the shell (it interrupts its job)
        ld    a0, 0(t0)                 ; ...
        call  sys_signal                ; ...
        j     te_l                      ; (the event's other bytes are dropped)
te_kw:  beqz  s1, te_l                  ; nothing for the shell
        la    t0, tm_in                 ; into its input pipe
        ld    a0, 0(t0)                 ; ...
        la    a1, tm_keys + 8           ; ...
        mv    a2, s1                    ; ...
        call  sys_write                 ; ...
        j     te_l                      ; ...
te_quit:
        la    t0, tm_quit               ; ...
        li    t1, 1                     ; ...
        sd    t1, 0(t0)                 ; ...
te_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; tm_flush(): draw the dirty rows, a band's worth at a time, and lend each
; band to the server
tm_flush:                               ; routine entry
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the terminal
        sd    s1, 16(sp)                ; s1 = first row of the run
        sd    s2, 24(sp)                ; s2 = dirty rows not in this run
        sd    s3, 32(sp)                ; s3 = text rows a band holds
        la    s0, tm_ts                 ; ...
        la    t0, wc_rows               ; the band holds that many pixel rows; the last
        ld    s3, 0(t0)                 ;   text row may draw up to 15 more (the pixels
        addi  s3, s3, -15               ;   under the grid)
        srai  s3, s3, 4                 ; ...
        bgtz  s3, tf_l                  ; ...
        li    s3, 1                     ; ...
tf_l:   ld    t0, TS_DIRTY(s0)          ; dirty rows that exist
        ld    t1, TS_ROWS(s0)           ; ...
        li    s1, 0                     ; find the first
tf_f:   bge   s1, t1, tf_r              ; none: done
        srl   t2, t0, s1                ; ...
        andi  t2, t2, 1                 ; ...
        bnez  t2, tf_run                ; ...
        addi  s1, s1, 1                 ; ...
        j     tf_f                      ; ...
tf_run: li    t3, 0                     ; the run: at most a band's rows
        li    t4, 0                     ; its mask
tf_e:   add   t5, s1, t3                ; ...
        bge   t5, t1, tf_d              ; ...
        bge   t3, s3, tf_d              ; ...
        srl   t2, t0, t5                ; ...
        andi  t2, t2, 1                 ; ...
        beqz  t2, tf_d                  ; ...
        li    t6, 1                     ; ...
        sll   t6, t6, t5                ; ...
        or    t4, t4, t6                ; ...
        addi  t3, t3, 1                 ; ...
        j     tf_e                      ; ...
tf_d:   xor   s2, t0, t4                ; the others wait
        sd    t4, TS_DIRTY(s0)          ; only the run is drawn now
        slli  a0, s1, 4                 ; the band starts at its first pixel row
        call  wc_band                   ; ...
        mv    a0, s0                    ; draw: a0 = first pixel row, a1 = past the last
        call  term_render               ; ...
        sd    s2, TS_DIRTY(s0)          ; ...
        sub   a1, a1, a0                ; lend them
        blez  a1, tf_l                  ; ...
        call  wc_damage                 ; ...
        bltz  a0, tf_q                  ; the window is gone
        j     tf_l                      ; ...
tf_q:   la    t0, tm_quit               ; ...
        li    t1, 1                     ; ...
        sd    t1, 0(t0)                 ; ...
        sd    zero, TS_DIRTY(s0)        ; ...
tf_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        addi  sp, sp, 40                ; pop the frame
        ret                             ; done
