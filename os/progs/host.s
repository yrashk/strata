; =============================================================================
; host.s: look a name up (DNS through the network server)
; =============================================================================
;
;   host NAME
;
; Prints "NAME is an alias for CANONICAL" when the answer went through
; CNAMEs, then "CANONICAL has address a.b.c.d" for each address (four at
; most). Exit status 0; 1 if there is no such name or no resolver answered
; (`ifconfig` shows the resolvers, `ifconfig dns A B` sets them); 2 on bad
; arguments. Starts the network server if none runs.

        .data                           ; data Local Store
        .align 8                        ; ...
pad0:   .dword 0                        ; (keeps res off address 0, which means "no buffer")
res:    .space 168                      ; the answer: count, 4 addresses, canonical name
s_use:  .ascii "usage: host NAME\n"     ; ...
s_use_e:
s_alias: .ascii " is an alias for "     ; ...
s_alias_e:
s_has:  .ascii " has address "          ; ...
s_has_e:
s_host: .ascii "host "                  ; ...
s_host_e:
s_nf:   .ascii " not found\n"           ; ...
s_nf_e:
s_to:   .ascii ": no answer from the resolvers\n" ; ...
s_to_e:
s_nonet: .ascii "host: no network server\n" ; ...
s_nonet_e:
        .align 8                        ; ...

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        call  sys_init                  ; ...
        call  sys_cmdline               ; the name: s1, s2
        add   s2, a0, a1                ; ...
        mv    a1, s2                    ; (the program's name)
        call  arg_next                  ; ...
        mv    a0, a2                    ; ...
        mv    a1, s2                    ; ...
        call  arg_next                  ; ...
        beqz  a1, m_use                 ; ...
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        call  net_init                  ; the network server
        bnez  a0, m_nonet               ; ...
        mv    a0, s1                    ; look it up
        mv    a1, s2                    ; ...
        la    a2, res                   ; ...
        call  net_resolve               ; ...
        bltz  a0, m_fail                ; ...
        la    s3, res + 40              ; s3 = the canonical name
        mv    a0, s3                    ; ...
        li    a1, 127                   ; ...
        call  str_len                   ; s4 = its length
        mv    s4, a0                    ; ...
        mv    a0, s1                    ; the same as asked (case aside)?
        mv    a1, s2                    ; ...
        mv    a2, s3                    ; ...
        mv    a3, s4                    ; ...
        call  name_same                 ; ...
        bnez  a0, m_addr                ; ...
        mv    a0, s1                    ; "NAME is an alias for CANONICAL"
        mv    a1, s2                    ; ...
        call  out_str                   ; ...
        la    a0, s_alias               ; ...
        li    a1, s_alias_e - s_alias   ; ...
        call  out_str                   ; ...
        mv    a0, s3                    ; ...
        mv    a1, s4                    ; ...
        call  out_str                   ; ...
        call  out_nl                    ; ...
m_addr:
        li    s5, 0                     ; each address
m_al:
        la    t0, res                   ; ...
        ld    t0, 0(t0)                 ; ...
        bgeu  s5, t0, m_ok              ; ...
        mv    a0, s3                    ; "CANONICAL has address a.b.c.d"
        mv    a1, s4                    ; ...
        call  out_str                   ; ...
        la    a0, s_has                 ; ...
        li    a1, s_has_e - s_has       ; ...
        call  out_str                   ; ...
        la    t0, res + 8               ; ...
        slli  t1, s5, 3                 ; ...
        add   t0, t0, t1                ; ...
        ld    a0, 0(t0)                 ; ...
        call  out_ip                    ; ...
        call  out_nl                    ; ...
        addi  s5, s5, 1                 ; ...
        j     m_al                      ; ...
m_ok:
        li    a0, 0                     ; ...
        call  sys_exit                  ; ...
m_fail:
        mv    s5, a0                    ; "host NAME not found" / "...: no answer"
        la    a0, s_host                ; ...
        li    a1, s_host_e - s_host     ; ...
        call  out_str                   ; ...
        mv    a0, s1                    ; ...
        mv    a1, s2                    ; ...
        call  out_str                   ; ...
        la    a0, s_nf                  ; ...
        li    a1, s_nf_e - s_nf         ; ...
        li    t0, E_TIMEOUT             ; ...
        bne   s5, t0, m_f2              ; ...
        la    a0, s_to                  ; ...
        li    a1, s_to_e - s_to         ; ...
m_f2:
        call  out_str                   ; ...
        call  out_flush                 ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...
m_use:
        la    a0, s_use                 ; ...
        li    a1, s_use_e - s_use       ; ...
        call  err_str                   ; ...
        li    a0, 2                     ; ...
        call  sys_exit                  ; ...
m_nonet:
        la    a0, s_nonet               ; ...
        li    a1, s_nonet_e - s_nonet   ; ...
        call  err_str                   ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...

; name_same(a0 = name, a1 = length, a2 = other, a3 = its length) -> a0 = 1 if
; equal ignoring case and a final dot on the first
name_same:
        beqz  a1, nsm_c                 ; ...
        add   t0, a0, a1                ; a final dot does not count
        lbu   t0, -1(t0)                ; ...
        li    t1, '.'                   ; ...
        bne   t0, t1, nsm_c             ; ...
        addi  a1, a1, -1                ; ...
nsm_c:
        bne   a1, a3, nsm_no            ; ...
        li    t0, 0                     ; ...
nsm_l:
        beq   t0, a1, nsm_yes           ; ...
        add   t1, a0, t0                ; ...
        lbu   t1, 0(t1)                 ; ...
        addi  t2, t1, -65               ; lower case
        sltiu t2, t2, 26                ; ...
        slli  t2, t2, 5                 ; ...
        add   t1, t1, t2                ; ...
        add   t2, a2, t0                ; ...
        lbu   t2, 0(t2)                 ; ...
        bne   t1, t2, nsm_no            ; ...
        addi  t0, t0, 1                 ; ...
        j     nsm_l                     ; ...
nsm_yes:
        li    a0, 1                     ; ...
        ret                             ; ...
nsm_no:
        li    a0, 0                     ; ...
        ret                             ; ...

        .include "../lib/sys.s"         ; the program library
