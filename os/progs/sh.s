; bi_lookup(a0 = command text, a1 = its length) -> a0 = the builtin number
; (1..NBI) of its first word, 0 if none; a2 = the text after that word
bi_lookup:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        add   a1, a0, a1                ; the first word
        call  arg_next                  ; a0 = word, a1 = length, a2 = after it
        sd    a2, 8(sp)                 ; ...
        beqz  a1, blk_none              ; none
        li    t0, 8                     ; names are at most 8 characters
        bgtu  a1, t0, blk_none          ; ...
        la    t2, bi_names              ; t2 = table entry
        li    t3, 1                     ; t3 = its number
blk_ent:
        li    t4, NBI                   ; all compared?
        bgtu  t3, t4, blk_none          ; yes
        li    t5, 0                     ; t5 = index
blk_cmp:
        beq   t5, a1, blk_tail          ; the word matched so far
        add   a3, a0, t5                ; ...
        lbu   a3, 0(a3)                 ; ...
        add   a4, t2, t5                ; ...
        lbu   a4, 0(a4)                 ; ...
        bne   a3, a4, blk_next          ; differ
        addi  t5, t5, 1                 ; ...
        j     blk_cmp                   ; ...
blk_tail:
        li    a3, 8                     ; the whole entry?
        beq   a1, a3, blk_hit           ; ...
        add   a4, t2, a1                ; or the entry's name ends here
        lbu   a4, 0(a4)                 ; ...
        li    a3, ' '                   ; ...
        beq   a4, a3, blk_hit           ; ...
blk_next:
        addi  t2, t2, 8                 ; next entry
        addi  t3, t3, 1                 ; ...
        j     blk_ent                   ; ...
blk_hit:
        mv    a0, t3                    ; its number
        j     blk_ret                   ; ...
blk_none:
        li    a0, 0                     ; not a builtin
blk_ret:
        ld    a2, 8(sp)                 ; after the word
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 16                ; release the frame
        ret                             ; done

; find_bi() -> a0 = builtin number of stage 0's first word, 0 if none; sets
; g_bap / g_bae to the rest of the stage's text (the arguments)
find_bi:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        la    a0, stxt                  ; stage 0's text
        la    t0, stg                   ; ...
        ld    a1, 0(t0)                 ; ...
        add   t1, a0, a1                ; the arguments end with it
        la    t2, g_bae                 ; ...
        sd    t1, 0(t2)                 ; ...
        call  bi_lookup                 ; a0 = number, a2 = after the name
        la    t0, g_bap                 ; the arguments start there
        sd    a2, 0(t0)                 ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 16                ; release the frame
        ret                             ; done

; run_bi(a0 = builtin number): run it, with stdout sent to the > file if any
; (by pointing our handle 1 at the file for the duration)
run_bi:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; save s0..s2
        sd    s1, 16(sp)                ; ...
        sd    s2, 24(sp)                ; ...
        mv    s0, a0                    ; s0 = builtin
        li    s1, -1                    ; s1 = our stdout's descriptor (saved)
        li    s2, -1                    ; s2 = the file's handle
        la    t0, g_outl                ; > file?
        ld    a1, 0(t0)                 ; ...
        beqz  a1, rb_run                ; no
        la    t0, g_outp                ; open it
        ld    a0, 0(t0)                 ; ...
        la    t0, g_outm                ; ...
        ld    a2, 0(t0)                 ; ...
        call  sys_open                  ; a0 = handle or < 0
        bltz  a0, rb_nofile             ; cannot
        mv    s2, a0                    ; keep it
        call  out_flush                 ; what is buffered goes to the old stdout
        li    a0, 1                     ; save handle 1
        call  sys_hdesc                 ; ...
        mv    s1, a0                    ; ...
        mv    a0, s2                    ; handle 1 = the file
        call  sys_hdesc                 ; ...
        mv    a1, a0                    ; ...
        li    a0, 1                     ; ...
        call  sys_hset                  ; ...
rb_run:
        mv    a0, s0                    ; run the builtin
        call  bi_call                   ; ...
        bltz  s2, rb_ret                ; no file: done
        call  out_flush                 ; the output into the file
        li    a0, 1                     ; handle 1 back to our stdout
        mv    a1, s1                    ; ...
        call  sys_hset                  ; ...
        mv    a0, s2                    ; close the file
        call  sys_close                 ; ...
        j     rb_ret                    ; done
rb_nofile:
        la    t0, g_outp                ; "sh: cannot open NAME"
        ld    a0, 0(t0)                 ; ...
        la    t0, g_outl                ; ...
        ld    a1, 0(t0)                 ; ...
        call  cant_open                 ; (status 1)
rb_ret:
        ld    s2, 24(sp)                ; restore s0..s2
        ld    s1, 16(sp)                ; ...
        ld    s0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 32                ; release the frame
        ret                             ; done

; bi_call(a0 = builtin number): jump to it (each one returns to our caller)
bi_call:
        la    t0, bi_jt                 ; one jump per builtin
        slli  t1, a0, 2                 ; ...
        add   t0, t0, t1                ; ...
        jr    t0                        ; ...
bi_jt:
        ret                             ; 0: none
        j     bi_help                   ; 1 help
        j     bi_echo                   ; 2 echo
        j     bi_set                    ; 3 set
        j     bi_unset                  ; 4 unset
        j     bi_hist                   ; 5 history
        j     bi_jobs                   ; 6 jobs
        j     bi_fg                     ; 7 fg
        j     bi_wait                   ; 8 wait
        j     bi_kill                   ; 9 kill
        j     bi_sleep                  ; 10 sleep
        j     bi_clear                  ; 11 clear
        j     bi_source                 ; 12 source
        j     bi_exit                   ; 13 exit
        j     sys_halt                  ; 14 halt
        j     bi_true                   ; 15 true
        j     bi_false                  ; 16 false
        j     bi_cd                     ; 17 cd
        j     bi_pwd                    ; 18 pwd

; set_stat(a0 = value): $? = a0
set_stat:
        la    t0, g_stat                ; ...
        sd    a0, 0(t0)                 ; ...
        ret                             ; done

; bi_arg() -> a0 = the first argument, a1 = its length (0 = none), a2 = after it
bi_arg:
        la    t0, g_bap                 ; the argument text
        ld    a0, 0(t0)                 ; ...
        la    t0, g_bae                 ; ...
        ld    a1, 0(t0)                 ; ...
        j     arg_next                  ; (tail call)

; bi_err(a0 = message, a1 = length, a2 = status): an error on stderr, $? = a2
bi_err:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    a2, 8(sp)                 ; ...
        call  err_str                   ; ...
        ld    a0, 8(sp)                 ; ...
        call  set_stat                  ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 16                ; release the frame
        ret                             ; done

; true / false: status 0 / 1
bi_true:
        li    a0, 0                     ; ...
        j     set_stat                  ; (tail call)
bi_false:
        li    a0, 1                     ; ...
        j     set_stat                  ; (tail call)

; help: what the shell understands
bi_help:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        la    a0, m_help                ; the help text
        li    a1, m_help_e - m_help     ; ...
        call  out_str                   ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 16                ; release the frame
        j     bi_true                   ; status 0 (tail call)

; clear: clear the screen
bi_clear:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        la    a0, m_cls                 ; ESC [ 2 J ESC [ H
        li    a1, m_cls_e - m_cls       ; ...
        call  out_str                   ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 16                ; release the frame
        j     bi_true                   ; status 0 (tail call)

; echo ARGS: the arguments, separated by single spaces, and a newline
bi_echo:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        la    t0, g_bap                 ; the argument text
        ld    a0, 0(t0)                 ; ...
        la    t0, g_bae                 ; ...
        ld    a1, 0(t0)                 ; ...
be_sp:
        bgeu  a0, a1, be_out            ; skip the spaces before it
        lbu   t0, 0(a0)                 ; ...
        li    t1, ' '                   ; ...
        bne   t0, t1, be_out            ; ...
        addi  a0, a0, 1                 ; ...
        j     be_sp                     ; ...
be_out:
        sub   a1, a1, a0                ; print the rest
        call  out_str                   ; ...
        call  out_nl                    ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 16                ; release the frame
        j     bi_true                   ; status 0 (tail call)

; exit [N]: end the shell with N (default: the last status)
bi_exit:
        call  bi_arg                    ; N?
        beqz  a1, bx_last               ; none
        call  str_atoi                  ; its value
        call  sys_exit                  ; does not return
bx_last:
        la    t0, g_stat                ; the last status
        ld    a0, 0(t0)                 ; ...
        call  sys_exit                  ; does not return

; set [NAME [VALUE...]]: list the variables, or give NAME the rest of the
; arguments as its value (VNMAX / VVMAX bytes at most)
; s0 = name, s1 = its length, s2 = value, s3 = its length
bi_set:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; save s0..s3
        sd    s1, 16(sp)                ; ...
        sd    s2, 24(sp)                ; ...
        sd    s3, 32(sp)                ; ...
        call  bi_arg                    ; NAME?
        beqz  a1, bst_list              ; none: list them
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        mv    s2, a2                    ; the value: the rest, after spaces
        la    t0, g_bae                 ; ...
        ld    t1, 0(t0)                 ; ...
bst_sp:
        bgeu  s2, t1, bst_vl            ; ...
        lbu   t2, 0(s2)                 ; ...
        li    t3, ' '                   ; ...
        bne   t2, t3, bst_vl            ; ...
        addi  s2, s2, 1                 ; ...
        j     bst_sp                    ; ...
bst_vl:
        sub   s3, t1, s2                ; its length, at most VVMAX
        li    t0, VVMAX                 ; ...
        bleu  s3, t0, bst_chk           ; ...
        mv    s3, t0                    ; ...
bst_chk:
        mv    a0, s0                    ; a valid name?
        mv    a1, s1                    ; ...
        call  name_ok                   ; ...
        beqz  a0, bst_use               ; no
        mv    a0, s0                    ; set already?
        mv    a1, s1                    ; ...
        call  var_find                  ; a0 = entry or 0
        bnez  a0, bst_put               ; yes: replace its value
        la    a0, vars                  ; no: a free entry
        li    t0, NVAR                  ; ...
bst_free:
        beqz  t0, bst_full              ; none
        ld    t1, 0(a0)                 ; ...
        beqz  t1, bst_put               ; ...
        addi  a0, a0, VSZ               ; ...
        addi  t0, t0, -1                ; ...
        j     bst_free                  ; ...
bst_put:
        sd    a0, 40(sp)                ; the entry
        sd    s1, 0(a0)                 ; name length
        sd    s3, 8(a0)                 ; value length
        addi  a0, a0, 16                ; the name
        mv    a1, s0                    ; ...
        mv    a2, s1                    ; ...
        call  bcopy                     ; ...
        ld    a0, 40(sp)                ; the value
        addi  a0, a0, 32                ; ...
        mv    a1, s2                    ; ...
        mv    a2, s3                    ; ...
        call  bcopy                     ; ...
        li    a0, 0                     ; status 0
        call  set_stat                  ; ...
        j     bst_ret                   ; ...
bst_list:
        la    s0, vars                  ; s0 = entry
        li    s1, NVAR                  ; s1 = entries left
bst_ll:
        beqz  s1, bst_ok                ; ...
        ld    a1, 0(s0)                 ; in use?
        beqz  a1, bst_ln                ; ...
        addi  a0, s0, 16                ; NAME=VALUE
        call  out_str                   ; ...
        li    a0, '='                   ; ...
        call  out_chr                   ; ...
        addi  a0, s0, 32                ; ...
        ld    a1, 8(s0)                 ; ...
        call  out_str                   ; ...
        call  out_nl                    ; ...
bst_ln:
        addi  s0, s0, VSZ               ; next
        addi  s1, s1, -1                ; ...
        j     bst_ll                    ; ...
bst_ok:
        li    a0, 0                     ; status 0
        call  set_stat                  ; ...
        j     bst_ret                   ; ...
bst_full:
        la    a0, m_vfull               ; "sh: set: too many variables"
        li    a1, m_vfull_e - m_vfull   ; ...
        li    a2, 1                     ; ...
        call  bi_err                    ; ...
        j     bst_ret                   ; ...
bst_use:
        la    a0, m_vuse                ; usage
        li    a1, m_vuse_e - m_vuse     ; ...
        li    a2, 2                     ; ...
        call  bi_err                    ; ...
bst_ret:
        ld    s3, 32(sp)                ; restore s0..s3
        ld    s2, 24(sp)                ; ...
        ld    s1, 16(sp)                ; ...
        ld    s0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 48                ; release the frame
        ret                             ; done

; name_ok(a0 = name, a1 = length) -> a0 = 1 if it is a variable name: a letter
; or _, then letters, digits, _; at most VNMAX characters
name_ok:
        beqz  a1, nok_no                ; empty
        li    t0, VNMAX                 ; too long
        bgtu  a1, t0, nok_no            ; ...
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    a0, 8(sp)                 ; cursor
        add   t0, a0, a1                ; end
        sd    t0, 16(sp)                ; ...
        lbu   a0, 0(a0)                 ; the first character
        call  is_nch                    ; ...
        li    t0, 2                     ; must be a letter or _
        bne   a0, t0, nok_bad           ; ...
nok_l:
        ld    t0, 8(sp)                 ; next
        addi  t0, t0, 1                 ; ...
        sd    t0, 8(sp)                 ; ...
        ld    t1, 16(sp)                ; all checked?
        bgeu  t0, t1, nok_good          ; ...
        lbu   a0, 0(t0)                 ; ...
        call  is_nch                    ; ...
        bnez  a0, nok_l                 ; ...
nok_bad:
        li    a0, 0                     ; ...
        j     nok_ret                   ; ...
nok_good:
        li    a0, 1                     ; ...
nok_ret:
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 32                ; release the frame
        ret                             ; done
nok_no:
        li    a0, 0                     ; ...
        ret                             ; done

; unset NAME: forget a variable
bi_unset:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        call  bi_arg                    ; NAME
        beqz  a1, bun_use               ; missing
        call  var_find                  ; a0 = entry or 0
        beqz  a0, bun_ok                ; not set: fine
        sd    zero, 0(a0)               ; the entry is free
bun_ok:
        li    a0, 0                     ; status 0
        call  set_stat                  ; ...
        j     bun_ret                   ; ...
bun_use:
        la    a0, m_vuse                ; usage
        li    a1, m_vuse_e - m_vuse     ; ...
        li    a2, 2                     ; ...
        call  bi_err                    ; ...
bun_ret:
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 16                ; release the frame
        ret                             ; done

; history: the remembered lines, numbered from the first line ever typed
bi_hist:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; save s0, s1
        sd    s1, 16(sp)                ; ...
        la    t0, g_hcnt                ; s1 = lines so far
        ld    s1, 0(t0)                 ; ...
        addi  s0, s1, -NHIST            ; s0 = the oldest kept
        bgez  s0, bhs_l                 ; ...
        li    s0, 0                     ; ...
bhs_l:
        bgeu  s0, s1, bhs_d             ; all shown
        addi  a0, s0, 1                 ; "    N  line"
        li    a1, 5                     ; ...
        call  out_decw                  ; ...
        la    a0, m_2sp                 ; ...
        li    a1, 2                     ; ...
        call  out_str                   ; ...
        mv    a0, s0                    ; ...
        la    a1, dirbuf                ; ...
        call  hist_get                  ; a0 = length
        mv    a1, a0                    ; ...
        la    a0, dirbuf                ; ...
        call  out_str                   ; ...
        call  out_nl                    ; ...
        addi  s0, s0, 1                 ; next
        j     bhs_l                     ; ...
bhs_d:
        ld    s1, 16(sp)                ; restore s0, s1
        ld    s0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 24                ; release the frame
        j     bi_true                   ; status 0 (tail call)

; source FILE: run the lines of FILE in this shell
bi_source:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save ra
        call  bi_arg                    ; FILE
        beqz  a1, bso_use               ; missing
        sd    a0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        call  run_file                  ; a0 = 0, < 0 if it cannot be opened
        bgez  a0, bso_ret               ; ran: $? is its last command's
        ld    a0, 8(sp)                 ; "sh: cannot open FILE"
        ld    a1, 16(sp)                ; ...
        call  cant_open                 ; (status 1)
        j     bso_ret                   ; ...
bso_use:
        la    a0, m_srcuse              ; usage
        li    a1, m_srcuse_e - m_srcuse ; ...
        li    a2, 2                     ; ...
        call  bi_err                    ; ...
bso_ret:
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 24                ; release the frame
        ret                             ; done

; cd [PATH]: the current tag path (kept by the file server, per process: a
; child starts in ours). TAG or a/b appends, /x/y replaces, .. drops the
; last component, none or / is the root. A tag no file carries (or a view
; with no file in it) is refused: "sh: cd: no such tag: PATH", status 1
bi_cd:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save ra
        call  bi_arg                    ; PATH (none: the root)
        sd    a0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        la    a2, g_cwd                 ; the new path comes back
        call  sys_chdir                 ; a0 = its length, or < 0
        bltz  a0, bcd_err               ; ...
        la    t0, g_cwdl                ; ...
        sd    a0, 0(t0)                 ; ...
        call  bi_true                   ; status 0
        j     bcd_ret                   ; ...
bcd_err:
        li    t0, -4                    ; no such tag?
        la    t1, m_cdno                ; ...
        li    t2, m_cdno_e - m_cdno     ; ...
        beq   a0, t0, bcd_say           ; ...
        la    t1, m_cdbad               ; anything else (too long, no room)
        li    t2, m_cdbad_e - m_cdbad   ; ...
bcd_say:
        mv    a0, t1                    ; the message
        mv    a1, t2                    ; ...
        call  err_str                   ; ...
        ld    a0, 8(sp)                 ; PATH
        ld    a1, 16(sp)                ; ...
        call  err_str                   ; ...
        la    a0, sys_nl                ; ...
        li    a1, 1                     ; ...
        li    a2, 1                     ; status 1
        call  bi_err                    ; ...
bcd_ret:
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 24                ; release the frame
        ret                             ; done

; pwd: the current tag path ("/" at the root)
bi_pwd:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        call  cwd_get                   ; (asked again: it is the file server's)
        la    a0, g_cwd                 ; ...
        la    t0, g_cwdl                ; ...
        ld    a1, 0(t0)                 ; ...
        call  out_str                   ; ...
        call  out_nl                    ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 16                ; release the frame
        j     bi_true                   ; status 0 (tail call)

; cwd_get(): the current tag path -> g_cwd, g_cwdl (0 if the server has none)
cwd_get:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        la    a0, g_cwd                 ; ...
        call  sys_cwd                   ; a0 = its length, or < 0
        bgez  a0, cwg_set               ; ...
        li    a0, 0                     ; ...
cwg_set:
        la    t0, g_cwdl                ; ...
        sd    a0, 0(t0)                 ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 16                ; release the frame
        ret                             ; done

; jobs: list the background jobs still running: "[J] PID  CMD"
bi_jobs:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; save s0, s1
        sd    s1, 16(sp)                ; ...
        call  poll_jobs                 ; report those that ended
        li    s0, 0                     ; s0 = slot
        la    s1, jtab                  ; s1 = entry
bj_l:
        li    t0, NJOB                  ; all?
        bge   s0, t0, bj_ret            ; ...
        ld    t0, 0(s1)                 ; used?
        beqz  t0, bj_n                  ; no
        li    a0, '['                   ; "[J] "
        call  out_chr                   ; ...
        addi  a0, s0, 1                 ; ...
        call  out_dec                   ; ...
        la    a0, m_rb                  ; ...
        li    a1, 2                     ; ...
        call  out_str                   ; ...
        mv    a0, s1                    ; PID
        call  job_lastpid               ; ...
        call  out_dec                   ; ...
        la    a0, m_2sp                 ; "  CMD"
        li    a1, 2                     ; ...
        call  out_str                   ; ...
        addi  a0, s1, 72                ; ...
        ld    a1, 64(s1)                ; ...
        call  out_str                   ; ...
        call  out_nl                    ; ...
bj_n:
        addi  s0, s0, 1                 ; next
        addi  s1, s1, JSZ               ; ...
        j     bj_l                      ; ...
bj_ret:
        ld    s1, 16(sp)                ; restore s0, s1
        ld    s0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 24                ; release the frame
        j     bi_true                   ; status 0 (tail call)

; job_arg(a0 = text, a1 = length) -> a0 = the job entry it names ("%J" or
; "J"; none = the highest-numbered job), or 0 if there is no such job
job_arg:
        bnez  a1, jga_n                 ; a number given?
        li    t0, NJOB                  ; no: the highest-numbered one in use
jga_hi:
        beqz  t0, jga_no                ; ...
        addi  t0, t0, -1                ; ...
        li    t1, JSZ                   ; ...
        mul   t1, t0, t1                ; ...
        la    a0, jtab                  ; ...
        add   a0, a0, t1                ; ...
        ld    t2, 0(a0)                 ; ...
        beqz  t2, jga_hi                ; ...
        ret                             ; ...
jga_n:
        lbu   t0, 0(a0)                 ; skip a %
        li    t1, '%'                   ; ...
        bne   t0, t1, jga_num           ; ...
        addi  a0, a0, 1                 ; ...
        addi  a1, a1, -1                ; ...
jga_num:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save ra
        call  str_num                   ; the number
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 8                 ; release the frame
        blez  a0, jga_no                ; not a number
        li    t0, NJOB                  ; 1..NJOB
        bgt   a0, t0, jga_no            ; ...
        addi  a0, a0, -1                ; its entry
        li    t0, JSZ                   ; ...
        mul   a0, a0, t0                ; ...
        la    t0, jtab                  ; ...
        add   a0, a0, t0                ; ...
        ld    t0, 0(a0)                 ; in use?
        beqz  t0, jga_no                ; ...
        ret                             ; ...
jga_no:
        li    a0, 0                     ; no such job
        ret                             ; ...

; fg [%J]: bring a background job to the foreground: the console goes to it,
; Ctrl-C interrupts it, and the shell waits for it
bi_fg:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; save s0
        call  bi_arg                    ; %J?
        call  job_arg                   ; a0 = entry or 0
        beqz  a0, bfg_no                ; none
        mv    s0, a0                    ; s0 = entry
        addi  a0, s0, 72                ; say which: its command
        ld    a1, 64(s0)                ; ...
        call  out_str                   ; ...
        call  out_nl                    ; ...
        call  out_flush                 ; ...
        ld    t0, 8(s0)                 ; its stages become the foreground job
        la    t1, g_nst                 ; ...
        sd    t0, 0(t1)                 ; ...
        la    t1, stg                   ; t1 = stage entry
        li    t2, 0                     ; t2 = stage
bfg_st:
        bge   t2, t0, bfg_go            ; all copied
        slli  t3, t2, 3                 ; the pid
        add   t3, s0, t3                ; ...
        ld    t3, 24(t3)                ; ...
        sd    t3, 24(t1)                ; ...
        ld    t3, 56(s0)                ; still running?
        srl   t3, t3, t2                ; ...
        andi  t3, t3, 1                 ; ...
        sd    t3, 40(t1)                ; ...
        ld    t3, 16(s0)                ; the job's status (the last stage's, if it ended)
        sd    t3, 32(t1)                ; ...
        addi  t1, t1, 64                ; next
        addi  t2, t2, 1                 ; ...
        j     bfg_st                    ; ...
bfg_go:
        sd    zero, 0(s0)               ; it is no longer a background job
        call  fg_wait                   ; wait for it; sets $?
        j     bfg_ret                   ; ...
bfg_no:
        la    a0, m_fno                 ; "sh: fg: no such job"
        li    a1, m_fno_e - m_fno       ; ...
        li    a2, 1                     ; ...
        call  bi_err                    ; ...
bfg_ret:
        ld    s0, 8(sp)                 ; restore s0
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 16                ; release the frame
        ret                             ; done

; wait_job(a0 = job entry) -> a0 = 0, or E_INTR if Ctrl-C ended the wait:
; collect every stage of the job still running
wait_job:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; save s0, s1
        sd    s1, 16(sp)                ; ...
        mv    s0, a0                    ; s0 = entry
        li    s1, 0                     ; s1 = stage
wjb_st:
        ld    t0, 8(s0)                 ; all stages?
        bge   s1, t0, wjb_ok            ; yes
        ld    t1, 56(s0)                ; still running?
        srl   t1, t1, s1                ; ...
        andi  t1, t1, 1                 ; ...
        beqz  t1, wjb_ns                ; no
        slli  t0, s1, 3                 ; wait for it
        add   t0, s0, t0                ; ...
        ld    a0, 24(t0)                ; ...
        li    a1, 0                     ; (blocking)
        call  sys_wait                  ; a0 = status
        li    t0, E_INTR                ; Ctrl-C: stop waiting
        beq   a0, t0, wjb_ret           ; ...
        li    t0, -16                   ; an error: count it as status 0
        blt   a0, t0, wjb_rec           ; ...
        bgez  a0, wjb_rec               ; ...
        li    a0, 0                     ; ...
wjb_rec:
        mv    a2, a0                    ; that stage has ended
        mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        call  jb_clear                  ; ...
wjb_ns:
        addi  s1, s1, 1                 ; next stage
        j     wjb_st                    ; ...
wjb_ok:
        li    a0, 0                     ; all collected
wjb_ret:
        ld    s1, 16(sp)                ; restore s0, s1
        ld    s0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 24                ; release the frame
        ret                             ; done

; wait [%J|PID]: wait for one job, one child, or every background job
bi_wait:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; save s0..s2
        sd    s1, 16(sp)                ; ...
        sd    s2, 24(sp)                ; ...
        call  bi_arg                    ; an argument?
        beqz  a1, bw_all                ; no: every job
        lbu   t0, 0(a0)                 ; %J?
        li    t1, '%'                   ; ...
        beq   t0, t1, bw_job            ; ...
        call  str_num                   ; the pid
        blez  a0, bw_use                ; not a number
        mv    s0, a0                    ; s0 = pid
        li    a1, 0                     ; wait for it
        call  sys_wait                  ; a0 = status
        li    t0, E_INTR                ; Ctrl-C: stop waiting
        beq   a0, t0, bw_intr           ; ...
        li    t0, -16                   ; an error?
        blt   a0, t0, bw_ok             ; ...
        bltz  a0, bw_no                 ; yes: no such child
bw_ok:
        mv    s1, a0                    ; s1 = status
        mv    a0, s0                    ; a background stage?
        mv    a1, s1                    ; ...
        call  job_reaped                ; ...
        call  poll_jobs                 ; report finished jobs
        mv    a0, s1                    ; $? = its code
        j     bw_code                   ; ...
bw_job:
        call  job_arg                   ; a0 = entry or 0
        beqz  a0, bw_no                 ; ...
        mv    s0, a0                    ; ...
        call  wait_job                  ; ...
        bnez  a0, bw_intr               ; interrupted
        ld    s1, 16(s0)                ; its status
        call  poll_jobs                 ; report it (and free it)
        mv    a0, s1                    ; $? = its code
bw_code:
        call  code_of                   ; ...
        call  set_stat                  ; ...
        j     bw_ret                    ; done
bw_all:
        li    s0, NJOB                  ; s0 = jobs left
        la    s1, jtab                  ; s1 = entry
bw_jl:
        beqz  s0, bw_done               ; all
        ld    t0, 0(s1)                 ; used?
        beqz  t0, bw_jn                 ; ...
        mv    a0, s1                    ; wait for it
        call  wait_job                  ; ...
        bnez  a0, bw_intr               ; interrupted
bw_jn:
        addi  s0, s0, -1                ; next
        addi  s1, s1, JSZ               ; ...
        j     bw_jl                     ; ...
bw_done:
        call  poll_jobs                 ; report them all
        li    a0, 0                     ; status 0
        call  set_stat                  ; ...
        j     bw_ret                    ; done
bw_intr:
        li    t0, 1                     ; interrupted (scripts stop)
        la    t1, g_intr                ; ...
        sd    t0, 0(t1)                 ; ...
        call  poll_jobs                 ; report what has ended anyway
        li    a0, 130                   ; status 130
        call  set_stat                  ; ...
        j     bw_ret                    ; done
bw_use:
        la    a0, m_wuse                ; "usage: wait [%JOB|PID]"
        li    a1, m_wuse_e - m_wuse     ; ...
        li    a2, 2                     ; ...
        call  bi_err                    ; ...
        j     bw_ret                    ; done
bw_no:
        la    a0, m_wno                 ; "sh: wait: no such child"
        li    a1, m_wno_e - m_wno       ; ...
        li    a2, 1                     ; ...
        call  bi_err                    ; ...
bw_ret:
        ld    s2, 24(sp)                ; restore s0..s2
        ld    s1, 16(sp)                ; ...
        ld    s0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 32                ; release the frame
        ret                             ; done

; kill PID|%J: end a process, or every stage of a background job
bi_kill:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; save s0, s1
        sd    s1, 16(sp)                ; ...
        call  bi_arg                    ; the pid, or %J for a background job
        beqz  a1, bk_use                ; missing
        lbu   t0, 0(a0)                 ; %J?
        li    t1, '%'                   ; ...
        beq   t0, t1, bk_job            ; ...
        call  str_num                   ; ...
        blez  a0, bk_use                ; not a number
        call  sys_kill                  ; kill it
        bltz  a0, bk_no                 ; no such process
        j     bk_ok                     ; ...
bk_job:
        call  job_arg                   ; a0 = entry or 0
        beqz  a0, bk_no                 ; ...
        mv    s0, a0                    ; s0 = entry
        ld    t1, 56(s0)                ; stages still running?
        beqz  t1, bk_no                 ; ...
        li    s1, 0                     ; s1 = stage
bk_jl:
        ld    t3, 8(s0)                 ; all stages?
        bge   s1, t3, bk_ok             ; ...
        ld    t1, 56(s0)                ; running?
        srl   t1, t1, s1                ; ...
        andi  t1, t1, 1                 ; ...
        beqz  t1, bk_jn                 ; ...
        slli  t1, s1, 3                 ; its pid
        add   t1, s0, t1                ; ...
        ld    a0, 24(t1)                ; ...
        call  sys_kill                  ; ...
bk_jn:
        addi  s1, s1, 1                 ; next stage
        j     bk_jl                     ; ...
bk_ok:
        li    a0, 0                     ; status 0
        call  set_stat                  ; ...
        j     bk_ret                    ; done
bk_use:
        la    a0, m_kuse                ; "usage: kill PID|%JOB"
        li    a1, m_kuse_e - m_kuse     ; ...
        li    a2, 2                     ; ...
        call  bi_err                    ; ...
        j     bk_ret                    ; done
bk_no:
        la    a0, m_kno                 ; "sh: kill: no such process"
        li    a1, m_kno_e - m_kno       ; ...
        li    a2, 1                     ; ...
        call  bi_err                    ; ...
bk_ret:
        ld    s1, 16(sp)                ; restore s0, s1
        ld    s0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 24                ; release the frame
        ret                             ; done

; sleep SECONDS: wait that long (decimal, like 2 or 0.25) with a timed wait;
; Ctrl-C ends it (status 130)
bi_sleep:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        call  bi_arg                    ; the duration
        beqz  a1, bs_use                ; missing
        add   t1, a0, a1                ; t1 = end, a0 = cursor
        li    t2, 0                     ; t2 = whole seconds
        li    t6, 0                     ; t6 = fraction in microseconds
        li    t3, 10                    ; base
bs_int:
        bgeu  a0, t1, bs_sum            ; the end
        lbu   t4, 0(a0)                 ; next character
        addi  a0, a0, 1                 ; ...
        li    t5, '.'                   ; the fraction follows
        beq   t4, t5, bs_dot            ; ...
        addi  t4, t4, -48               ; a digit?
        bgeu  t4, t3, bs_use            ; no
        mul   t2, t2, t3                ; ...
        add   t2, t2, t4                ; ...
        j     bs_int                    ; ...
bs_dot:
        li    t5, 100000                ; t5 = microseconds of the next digit
bs_frac:
        bgeu  a0, t1, bs_sum            ; the end
        lbu   t4, 0(a0)                 ; next digit
        addi  a0, a0, 1                 ; ...
        addi  t4, t4, -48               ; ...
        bgeu  t4, t3, bs_use            ; not a digit
        mul   t4, t4, t5                ; its weight
        add   t6, t6, t4                ; ...
        divu  t5, t5, t3                ; the next digit weighs a tenth (0 past 6)
        j     bs_frac                   ; ...
bs_sum:
        li    t4, 1000000               ; ticks = seconds * 1000000 + fraction
        mul   t2, t2, t4                ; ...
        add   a0, t2, t6                ; ...
        beqz  a0, bs_ok                 ; nothing to wait for
        call  sys_sleep                 ; -8 when the time is up, -2 if interrupted
        li    t0, E_INTR                ; interrupted?
        bne   a0, t0, bs_ok             ; no
        li    t0, 1                     ; yes (scripts and lists stop)
        la    t1, g_intr                ; ...
        sd    t0, 0(t1)                 ; ...
        li    a0, 130                   ; status 130
        call  set_stat                  ; ...
        j     bs_ret                    ; done
bs_ok:
        li    a0, 0                     ; status 0
        call  set_stat                  ; ...
        j     bs_ret                    ; done
bs_use:
        la    a0, m_suse                ; "usage: sleep SECONDS"
        li    a1, m_suse_e - m_suse     ; ...
        li    a2, 2                     ; ...
        call  bi_err                    ; ...
bs_ret:
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 16                ; release the frame
        ret                             ; done

