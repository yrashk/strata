; Scripts: sh FILE, source FILE, rc
; =============================================================================

; run_file(a0 = name, a1 = length) -> a0 = 0, or < 0 if it cannot be opened.
; The file (at most 64 KiB) is copied into the arena region of the next
; nesting depth; each line is brought back into that depth's line window and
; run. The script stops when one of its commands was interrupted (Ctrl-C).
; s0 = depth, s1 = handle, s2 = arena offset of the region, s3 = bytes in the
; arena, s4 = bytes staged / the position of the next line, s5 = window
run_file:
        addi  sp, sp, -64               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; save s0..s5
        sd    s1, 16(sp)                ; ...
        sd    s2, 24(sp)                ; ...
        sd    s3, 32(sp)                ; ...
        sd    s4, 40(sp)                ; ...
        sd    s5, 48(sp)                ; ...
        la    t0, g_depth               ; s0 = the new depth
        ld    s0, 0(t0)                 ; ...
        addi  s0, s0, 1                 ; ...
        li    t1, FDEPTH                ; too deep?
        bltu  s0, t1, rf_open           ; no
        la    a0, m_deep                ; "sh: scripts nested too deep"
        li    a1, m_deep_e - m_deep     ; ...
        call  err_str                   ; ...
        li    a0, 1                     ; status 1
        call  set_stat                  ; ...
        li    a0, 0                     ; (the file itself is fine)
        j     rf_ret                    ; ...
rf_open:
        li    a2, 0                     ; open for reading
        call  sys_open                  ; a0 = handle or < 0
        bltz  a0, rf_ret                ; cannot
        mv    s1, a0                    ; s1 = handle
        addi  s2, s0, -1                ; s2 = FILE_OFF + (depth - 1) * FILE_MAX
        li    t0, FILE_MAX              ; ...
        mul   s2, s2, t0                ; ...
        li    t0, FILE_OFF              ; ...
        add   s2, s2, t0                ; ...
        li    s3, 0                     ; nothing in the arena yet
        li    s4, 0                     ; nothing staged
rf_rd:
        li    t0, NDIR * 32             ; room in the staging buffer?
        sub   a2, t0, s4                ; ...
        bnez  a2, rf_r1                 ; yes
        la    t0, dirbuf                ; full: 4 KiB -> the arena
        add   t1, s2, s3                ; ...
        li    t2, NDIR * 32             ; ...
        tput  tg1, t0, c0, t1, t2       ; ...
        twait 1 << 1                    ; (the buffer is reused at once)
        add   s3, s3, t2                ; ...
        li    s4, 0                     ; ...
        li    t0, FILE_MAX              ; the region is full: the rest is ignored
        bgeu  s3, t0, rf_cl             ; ...
        j     rf_rd                     ; read on
rf_r1:
        mv    a0, s1                    ; read more after what is staged
        la    a1, dirbuf                ; ...
        add   a1, a1, s4                ; ...
        call  sys_read                  ; a0 = bytes, 0 at the end
        blez  a0, rf_cl                 ; the end (or an error)
        add   s4, s4, a0                ; count them
        j     rf_rd                     ; continue
rf_cl:
        mv    a0, s1                    ; close the file
        call  sys_close                 ; ...
        beqz  s4, rf_go                 ; nothing staged
        la    t0, dirbuf                ; the staged rest -> the arena
        add   t1, s2, s3                ; ...
        addi  t2, s4, 7                 ; whole words
        srli  t2, t2, 3                 ; ...
        slli  t2, t2, 3                 ; ...
        tput  tg1, t0, c0, t1, t2       ; ...
        twait 1 << 1                    ; ...
        add   s3, s3, s4                ; s3 = the file's length
rf_go:
        la    t0, g_depth               ; we are one level deeper
        sd    s0, 0(t0)                 ; ...
        li    t0, LBSZ                  ; s5 = this depth's line window
        mul   t0, s0, t0                ; ...
        la    s5, lbufs                 ; ...
        add   s5, s5, t0                ; ...
        li    s4, 0                     ; s4 = position of the next line
rf_line:
        bgeu  s4, s3, rf_ok             ; all lines run
        srli  t1, s4, 3                 ; the 8-aligned window around it
        slli  t1, t1, 3                 ; ...
        mv    t0, s5                    ; ...
        add   t1, s2, t1                ; ...
        li    t2, LWIN                  ; ...
        tget  tg1, t0, c0, t1, t2       ; arena -> D-LS
        twait 1 << 1                    ; ...
        andi  t3, s4, 7                 ; t3 = the line's offset in the window
        add   a0, s5, t3                ; a0 = the line
        li    t4, LWIN                  ; t4 = bytes of it the window holds
        sub   t4, t4, t3                ; ...
        sub   t5, s3, s4                ; t5 = bytes left in the file
        bleu  t4, t5, rf_cap            ; ...
        mv    t4, t5                    ; ...
rf_cap:
        li    a1, 0                     ; a1 = the line's length
rf_nl:
        bgeu  a1, t4, rf_cut            ; the window (or the file) ends: cut here
        add   t0, a0, a1                ; newline?
        lbu   t0, 0(t0)                 ; ...
        li    t1, 10                    ; ...
        beq   t0, t1, rf_run            ; ...
        addi  a1, a1, 1                 ; ...
        j     rf_nl                     ; ...
rf_cut:
        add   s4, s4, a1                ; the next line starts right after it
        j     rf_r                      ; ...
rf_run:
        add   s4, s4, a1                ; the next line starts after the newline
        addi  s4, s4, 1                 ; ...
rf_r:
        call  run_line                  ; run it
        la    t0, g_intr                ; a script stops after an interrupt
        ld    t0, 0(t0)                 ; ...
        beqz  t0, rf_line               ; none: go on
rf_ok:
        addi  t1, s0, -1                ; back to the outer depth
        la    t0, g_depth               ; ...
        sd    t1, 0(t0)                 ; ...
        li    a0, 0                     ; done
rf_ret:
        ld    s5, 48(sp)                ; restore s0..s5
        ld    s4, 40(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s1, 16(sp)                ; ...
        ld    s0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 64                ; release the frame
        ret                             ; done

; =============================================================================
; Line editor (interactive input; raw console while a line is typed)
; =============================================================================

; getkey() -> a0 = the next input byte, -1 at the end of input, -2 if interrupted
getkey:
        la    t0, g_kneg                ; a pushed-back end / interrupt?
        ld    a0, 0(t0)                 ; ...
        beqz  a0, gk_buf                ; no
        sd    zero, 0(t0)               ; yes: once
        ret                             ; ...
gk_buf:
        la    t0, g_kpos                ; a byte read ahead?
        ld    t1, 0(t0)                 ; ...
        la    t2, g_klen                ; ...
        ld    t3, 0(t2)                 ; ...
        bltu  t1, t3, gk_byte           ; yes
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save ra
        call  out_flush                 ; show the echo before waiting
        li    a0, 0                     ; read standard input (raw console: what is there)
        la    a1, kbuf                  ; ...
        li    a2, 16                    ; ...
        call  sys_read                  ; a0 = bytes, 0 at the end, < 0 error
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 8                 ; release the frame
        la    t0, g_kpos                ; the key buffer restarts
        sd    zero, 0(t0)               ; ...
        la    t2, g_klen                ; ...
        sd    zero, 0(t2)               ; ...
        li    t1, E_INTR                ; interrupted?
        beq   a0, t1, gk_ret            ; yes: -2
        blez  a0, gk_end                ; nothing: the end of input
        sd    a0, 0(t2)                 ; got some
        j     gk_buf                    ; hand out the first
gk_end:
        li    a0, -1                    ; end of input
gk_ret:
        ret                             ; done
gk_byte:
        la    t4, kbuf                  ; the next byte
        add   t4, t4, t1                ; ...
        lbu   a0, 0(t4)                 ; ...
        addi  t1, t1, 1                 ; consumed
        sd    t1, 0(t0)                 ; ...
        ret                             ; done

; read_line() -> a0 = the length of the line typed (in ebuf), -1 at the end
; of input, -2 if Ctrl-C abandoned it. s0 = the key / the result
read_line:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; save s0
        call  own_con                   ; on the console: raw mode while typing
        beqz  a0, rl_init               ; ...
        li    a0, 1                     ; ...
        call  sys_conmode               ; ...
rl_init:
        la    t0, g_elen                ; an empty line, cursor at 0
        sd    zero, 0(t0)               ; ...
        la    t0, g_ecur                ; ...
        sd    zero, 0(t0)               ; ...
        la    t0, g_tabs                ; no Tab, no Ctrl-D before
        sd    zero, 0(t0)               ; ...
        la    t0, g_ctld                ; ...
        sd    zero, 0(t0)               ; ...
        la    t0, g_hcnt                ; the history shows the new line
        ld    t1, 0(t0)                 ; ...
        la    t0, g_hpos                ; ...
        sd    t1, 0(t0)                 ; ...
        call  prompt                    ; "strata$ "
rl_key:
        call  getkey                    ; s0 = the next key
        mv    s0, a0                    ; ...
        li    t0, 9                     ; a key other than Tab ends a Tab sequence
        beq   s0, t0, rl_nt             ; ...
        la    t1, g_tabs                ; ...
        sd    zero, 0(t1)               ; ...
rl_nt:
        li    t0, 4                     ; a key other than Ctrl-D ends a Ctrl-D sequence
        beq   s0, t0, rl_nd             ; ...
        la    t1, g_ctld                ; ...
        sd    zero, 0(t1)               ; ...
rl_nd:
        bltz  s0, rl_neg                ; the end of input or an interrupt
        li    t0, 32                    ; a control character?
        bltu  s0, t0, rl_ctl            ; yes
        li    t0, 127                   ; DEL: Backspace
        beq   s0, t0, rl_bs             ; ...
        mv    a0, s0                    ; anything else is inserted
        call  ed_ins                    ; ...
        j     rl_key                    ; next key
rl_bs:
        call  ed_bs                     ; erase left of the cursor
        j     rl_key                    ; next key
rl_ctl:
        la    t0, rl_tab                ; control characters: through the table
        slli  t1, s0, 2                 ; (one jump per character)
        add   t0, t0, t1                ; ...
        jalr  ra, t0, 0                 ; a handler returns here ...
        j     rl_key                    ; ... and the next key is read
rl_tab:
        ret                             ; 0  ^@: ignored
        j     ed_home                   ; 1  ^A: start of the line
        j     ed_lft                    ; 2  ^B: left
        j     rl_cc                     ; 3  ^C (as a byte): abandon the line
        j     rl_ctld                   ; 4  ^D: end of input / delete
        j     ed_end                    ; 5  ^E: end of the line
        j     ed_rgt                    ; 6  ^F: right
        ret                             ; 7  ^G: ignored
        j     ed_bs                     ; 8  ^H: Backspace
        j     ed_tab                    ; 9  Tab: completion
        j     rl_enter                  ; 10 LF: the line is done
        j     ed_kend                   ; 11 ^K: erase to the end
        j     ed_clear                  ; 12 ^L: clear the screen
        j     rl_enter                  ; 13 CR: the line is done
        j     ed_down                   ; 14 ^N: next history line
        ret                             ; 15 ^O: ignored
        j     ed_up                     ; 16 ^P: previous history line
        ret                             ; 17 ^Q: ignored
        ret                             ; 18 ^R: ignored
        ret                             ; 19 ^S: ignored
        ret                             ; 20 ^T: ignored
        j     ed_kbeg                   ; 21 ^U: erase to the start
        ret                             ; 22 ^V: ignored
        j     ed_kword                  ; 23 ^W: erase the word before the cursor
        ret                             ; 24 ^X: ignored
        ret                             ; 25 ^Y: ignored
        ret                             ; 26 ^Z: ignored
        j     ed_esc                    ; 27 ESC: an escape sequence
        ret                             ; 28: ignored
        ret                             ; 29: ignored
        ret                             ; 30: ignored
        ret                             ; 31: ignored
rl_neg:
        li    t0, E_INTR                ; interrupted (Ctrl-C)?
        beq   s0, t0, rl_intr           ; yes
        la    t0, g_elen                ; the end of input: a last line without newline?
        ld    t1, 0(t0)                 ; ...
        bnez  t1, rl_enter              ; yes: take it (the next read ends)
        li    s0, -1                    ; no: the end
        call  out_nl                    ; finish the prompt's line
        j     rl_out                    ; ...
rl_intr:
        call  own_con                   ; the tty echoed "^C" on the console
        bnez  a0, rl_i2                 ; ...
rl_cc:
        la    a0, m_cc                  ; otherwise we do
        li    a1, 3                     ; ...
        call  out_str                   ; ...
rl_i2:
        li    s0, E_INTR                ; the line is abandoned
        j     rl_out                    ; ...
rl_ctld:
        la    t0, g_elen                ; Ctrl-D on an empty line: the end
        ld    t1, 0(t0)                 ; ...
        bnez  t1, rl_cd2                ; not empty
        li    s0, -1                    ; ...
        call  out_nl                    ; finish the prompt's line
        j     rl_out                    ; ...
rl_cd2:
        la    t0, g_ecur                ; a character under the cursor: delete it
        ld    t2, 0(t0)                 ; ...
        bltu  t2, t1, ed_del            ; (a handler: returns to rl_key)
        la    t0, g_ctld                ; at the end: a second Ctrl-D takes the line
        ld    t3, 0(t0)                 ; (the console repeats 0x04 at the end of input)
        bnez  t3, rl_enter              ; ...
        li    t3, 1                     ; remember this one
        sd    t3, 0(t0)                 ; ...
        ret                             ; next key
rl_enter:
        call  ed_end                    ; cursor to the end of the line
        call  out_nl                    ; ...
        la    t0, g_elen                ; the result: the length
        ld    s0, 0(t0)                 ; ...
rl_out:
        call  out_flush                 ; everything shown
        call  own_con                   ; back to cooked mode for what runs next
        beqz  a0, rl_ret                ; ...
        li    a0, 0                     ; ...
        call  sys_conmode               ; ...
rl_ret:
        mv    a0, s0                    ; the result
        ld    s0, 8(sp)                 ; restore s0
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 16                ; release the frame
        ret                             ; done

; ed_left(a0 = n): move the cursor n columns left on the screen (ESC [ n D)
ed_left:
        blez  a0, elf_r                 ; nothing to do
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    a0, 8(sp)                 ; n
        li    a0, 27                    ; ESC
        call  out_chr                   ; ...
        li    a0, '['                   ; [
        call  out_chr                   ; ...
        ld    a0, 8(sp)                 ; n
        call  out_dec                   ; ...
        li    a0, 'D'                   ; D
        call  out_chr                   ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 16                ; release the frame
elf_r:
        ret                             ; done

; ed_tail(): redraw from the cursor to the end of the line, erase the rest of
; the old line (ESC [ K) and put the cursor back
ed_tail:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        la    t0, g_ecur                ; the text after the cursor
        ld    t1, 0(t0)                 ; ...
        la    t2, g_elen                ; ...
        ld    t3, 0(t2)                 ; ...
        la    a0, ebuf                  ; ...
        add   a0, a0, t1                ; ...
        sub   a1, t3, t1                ; ...
        sd    a1, 8(sp)                 ; (its length)
        call  out_str                   ; ...
        la    a0, m_el                  ; erase what is left
        li    a1, 3                     ; ...
        call  out_str                   ; ...
        ld    a0, 8(sp)                 ; back to the cursor
        call  ed_left                   ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 16                ; release the frame
        ret                             ; done

; ed_redraw(): the prompt and the whole line again, cursor in its place
ed_redraw:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        call  prompt                    ; ...
        la    a0, ebuf                  ; the line
        la    t0, g_elen                ; ...
        ld    a1, 0(t0)                 ; ...
        call  out_str                   ; ...
        la    t0, g_elen                ; back from the end to the cursor
        ld    t1, 0(t0)                 ; ...
        la    t2, g_ecur                ; ...
        ld    t3, 0(t2)                 ; ...
        sub   a0, t1, t3                ; ...
        call  ed_left                   ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 16                ; release the frame
        ret                             ; done

; ed_ins(a0 = character): insert it at the cursor
ed_ins:
        la    t0, g_elen                ; t1 = length
        ld    t1, 0(t0)                 ; ...
        li    t2, LINEMAX               ; full?
        bgeu  t1, t2, ein_r             ; yes: ignored
        la    t3, g_ecur                ; t4 = cursor
        ld    t4, 0(t3)                 ; ...
        la    t5, ebuf                  ; shift [cursor, end) right by one
        mv    t6, t1                    ; (from the end)
ein_sh:
        bleu  t6, t4, ein_put           ; done
        add   a1, t5, t6                ; ...
        lbu   a2, -1(a1)                ; ...
        sb    a2, 0(a1)                 ; ...
        addi  t6, t6, -1                ; ...
        j     ein_sh                    ; ...
ein_put:
        add   a1, t5, t4                ; the character
        sb    a0, 0(a1)                 ; ...
        addi  t1, t1, 1                 ; one longer
        sd    t1, 0(t0)                 ; ...
        addi  t4, t4, 1                 ; cursor after it
        sd    t4, 0(t3)                 ; ...
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        sub   t6, t1, t4                ; characters after the cursor
        sd    t6, 8(sp)                 ; ...
        call  out_chr                   ; show it
        ld    t6, 8(sp)                 ; inserted inside the line?
        beqz  t6, ein_d                 ; no
        call  ed_tail                   ; yes: redraw the rest
ein_d:
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 16                ; release the frame
ein_r:
        ret                             ; done

; ed_cut(a0 = position, a1 = count): remove characters from the line (not the screen)
ed_cut:
        la    t0, g_elen                ; t2 = the new length
        ld    t1, 0(t0)                 ; ...
        sub   t2, t1, a1                ; ...
        la    t5, ebuf                  ; shift the rest left
        mv    t3, a0                    ; ...
ect_l:
        bgeu  t3, t2, ect_d             ; done
        add   t4, t5, t3                ; ...
        add   t6, t4, a1                ; ...
        lbu   t6, 0(t6)                 ; ...
        sb    t6, 0(t4)                 ; ...
        addi  t3, t3, 1                 ; ...
        j     ect_l                     ; ...
ect_d:
        sd    t2, 0(t0)                 ; ...
        ret                             ; done

; ed_erase(a0 = position, a1 = count): erase the count characters before the
; cursor (position = cursor - count), on the screen too
ed_erase:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    a0, 8(sp)                 ; position
        sd    a1, 16(sp)                ; count
        mv    a0, a1                    ; the cursor moves left over them
        call  ed_left                   ; ...
        ld    a0, 8(sp)                 ; out of the line
        ld    a1, 16(sp)                ; ...
        call  ed_cut                    ; ...
        ld    t1, 8(sp)                 ; the cursor is at the position
        la    t0, g_ecur                ; ...
        sd    t1, 0(t0)                 ; ...
        call  ed_tail                   ; redraw the rest
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 24                ; release the frame
        ret                             ; done

; ed_bs(): Backspace: erase the character left of the cursor
ed_bs:
        la    t0, g_ecur                ; at the start?
        ld    t1, 0(t0)                 ; ...
        beqz  t1, ebs_r                 ; yes: nothing
        addi  a0, t1, -1                ; one character
        li    a1, 1                     ; ...
        j     ed_erase                  ; (tail call)
ebs_r:
        ret                             ; done

; ed_del(): Delete: erase the character under the cursor
ed_del:
        la    t0, g_ecur                ; at the end?
        ld    t1, 0(t0)                 ; ...
        la    t2, g_elen                ; ...
        ld    t3, 0(t2)                 ; ...
        bgeu  t1, t3, edl_r             ; yes: nothing
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save ra
        mv    a0, t1                    ; out of the line
        li    a1, 1                     ; ...
        call  ed_cut                    ; ...
        call  ed_tail                   ; redraw the rest
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 8                 ; release the frame
edl_r:
        ret                             ; done

; ed_kbeg(): Ctrl-U: erase from the start of the line to the cursor
ed_kbeg:
        la    t0, g_ecur                ; count = cursor
        ld    a1, 0(t0)                 ; ...
        li    a0, 0                     ; from the start
        beqz  a1, ekb_r                 ; nothing
        j     ed_erase                  ; (tail call)
ekb_r:
        ret                             ; done

; ed_kword(): Ctrl-W: erase the word before the cursor (and the spaces after it)
ed_kword:
        la    t0, g_ecur                ; t1 = cursor
        ld    t1, 0(t0)                 ; ...
        la    t5, ebuf                  ; ...
        mv    t2, t1                    ; t2 = where the word starts
        li    t4, ' '                   ; ...
ekw_sp:
        beqz  t2, ekw_go                ; skip spaces leftwards
        add   t3, t5, t2                ; ...
        lbu   t3, -1(t3)                ; ...
        bne   t3, t4, ekw_w             ; ...
        addi  t2, t2, -1                ; ...
        j     ekw_sp                    ; ...
ekw_w:
        beqz  t2, ekw_go                ; then the word
        add   t3, t5, t2                ; ...
        lbu   t3, -1(t3)                ; ...
        beq   t3, t4, ekw_go            ; ...
        addi  t2, t2, -1                ; ...
        j     ekw_w                     ; ...
ekw_go:
        sub   a1, t1, t2                ; count
        beqz  a1, ekw_r                 ; nothing
        mv    a0, t2                    ; position
        j     ed_erase                  ; (tail call)
ekw_r:
        ret                             ; done

; ed_kend(): Ctrl-K: erase from the cursor to the end of the line
ed_kend:
        la    t0, g_ecur                ; the line ends at the cursor
        ld    t1, 0(t0)                 ; ...
        la    t2, g_elen                ; ...
        sd    t1, 0(t2)                 ; ...
        la    a0, m_el                  ; and on the screen
        li    a1, 3                     ; ...
        j     out_str                   ; (tail call)

; ed_home(): cursor to the start of the line
ed_home:
        la    t0, g_ecur                ; ...
        ld    a0, 0(t0)                 ; columns to go back
        sd    zero, 0(t0)               ; ...
        j     ed_left                   ; (tail call)

; ed_end(): cursor to the end of the line (by writing the rest again)
ed_end:
        la    t0, g_ecur                ; ...
        ld    t1, 0(t0)                 ; ...
        la    t2, g_elen                ; ...
        ld    t3, 0(t2)                 ; ...
        sd    t3, 0(t0)                 ; cursor = length
        la    a0, ebuf                  ; ...
        add   a0, a0, t1                ; ...
        sub   a1, t3, t1                ; ...
        j     out_str                   ; (tail call)

; ed_lft(): cursor one left
ed_lft:
        la    t0, g_ecur                ; at the start?
        ld    t1, 0(t0)                 ; ...
        beqz  t1, elt_r                 ; yes
        addi  t1, t1, -1                ; ...
        sd    t1, 0(t0)                 ; ...
        li    a0, 1                     ; ...
        j     ed_left                   ; (tail call)
elt_r:
        ret                             ; done

; ed_rgt(): cursor one right (by writing the character under it)
ed_rgt:
        la    t0, g_ecur                ; at the end?
        ld    t1, 0(t0)                 ; ...
        la    t2, g_elen                ; ...
        ld    t3, 0(t2)                 ; ...
        bgeu  t1, t3, ert_r             ; yes
        addi  t4, t1, 1                 ; ...
        sd    t4, 0(t0)                 ; ...
        la    t5, ebuf                  ; ...
        add   t5, t5, t1                ; ...
        lbu   a0, 0(t5)                 ; ...
        j     out_chr                   ; (tail call)
ert_r:
        ret                             ; done

; ed_clear(): Ctrl-L: clear the screen, then the prompt and the line at the top
ed_clear:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save ra
        la    a0, m_cls                 ; ESC [ 2 J ESC [ H
        li    a1, m_cls_e - m_cls       ; ...
        call  out_str                   ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 8                 ; release the frame
        j     ed_redraw                 ; (tail call)

; ed_esc(): an escape sequence: ESC [ (or ESC O) digits ; digits final
; A B C D = up down right left, H F = home end, n ~ = 1/7 home, 4/8 end,
; 3 delete. Anything else (Alt+key, Page Up...) is ignored.
ed_esc:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; save s0, s1
        sd    s1, 16(sp)                ; ...
        call  getkey                    ; the byte after ESC
        mv    s0, a0                    ; ...
        bltz  s0, ex_push               ; the end / an interrupt: keep it
        li    t0, '['                   ; CSI?
        beq   s0, t0, ex_csi            ; ...
        li    t0, 'O'                   ; SS3 (application cursor keys)?
        bne   s0, t0, ex_ret            ; no: Alt+key, ignored
ex_csi:
        li    s1, 0                     ; s1 = the number
ex_num:
        call  getkey                    ; s0 = the next byte
        mv    s0, a0                    ; ...
        bltz  s0, ex_push               ; ...
        addi  t0, s0, -48               ; a digit?
        li    t1, 10                    ; ...
        bgeu  t0, t1, ex_fin            ; no
        mul   s1, s1, t1                ; ...
        add   s1, s1, t0                ; ...
        j     ex_num                    ; ...
ex_fin:
        li    t0, ';'                   ; a parameter separator: keep the last number
        bne   s0, t0, ex_key            ; ...
        li    s1, 0                     ; ...
        j     ex_num                    ; ...
ex_key:
        li    t0, 'A'                   ; up
        bne   s0, t0, ex_b              ; ...
        call  ed_up                     ; ...
        j     ex_ret                    ; ...
ex_b:
        li    t0, 'B'                   ; down
        bne   s0, t0, ex_c              ; ...
        call  ed_down                   ; ...
        j     ex_ret                    ; ...
ex_c:
        li    t0, 'C'                   ; right
        bne   s0, t0, ex_d              ; ...
        call  ed_rgt                    ; ...
        j     ex_ret                    ; ...
ex_d:
        li    t0, 'D'                   ; left
        bne   s0, t0, ex_h              ; ...
        call  ed_lft                    ; ...
        j     ex_ret                    ; ...
ex_h:
        li    t0, 'H'                   ; home
        beq   s0, t0, ex_home           ; ...
        li    t0, 'F'                   ; end
        beq   s0, t0, ex_endk           ; ...
        li    t0, '~'                   ; ESC [ n ~
        bne   s0, t0, ex_ret            ; anything else: ignored
        li    t0, 1                     ; 1 or 7: home
        beq   s1, t0, ex_home           ; ...
        li    t0, 7                     ; ...
        beq   s1, t0, ex_home           ; ...
        li    t0, 4                     ; 4 or 8: end
        beq   s1, t0, ex_endk           ; ...
        li    t0, 8                     ; ...
        beq   s1, t0, ex_endk           ; ...
        li    t0, 3                     ; 3: delete
        bne   s1, t0, ex_ret            ; ...
        call  ed_del                    ; ...
        j     ex_ret                    ; ...
ex_home:
        call  ed_home                   ; ...
        j     ex_ret                    ; ...
ex_endk:
        call  ed_end                    ; ...
        j     ex_ret                    ; ...
ex_push:
        la    t0, g_kneg                ; getkey hands it out next
        sd    s0, 0(t0)                 ; ...
ex_ret:
        ld    s1, 16(sp)                ; restore s0, s1
        ld    s0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 24                ; release the frame
        ret                             ; done

; bcopy(a0 = destination, a1 = source, a2 = bytes)
bcopy:
        li    t0, 0                     ; index
bcp_l:
        bgeu  t0, a2, bcp_d             ; done
        add   t1, a1, t0                ; ...
        lbu   t1, 0(t1)                 ; ...
        add   t2, a0, t0                ; ...
        sb    t1, 0(t2)                 ; ...
        addi  t0, t0, 1                 ; ...
        j     bcp_l                     ; ...
bcp_d:
        ret                             ; done

; =============================================================================
; History: NHIST lines of HSZ bytes in the arena at HIST_OFF (a ring)
; =============================================================================

; hist_add(a0 = length): the line in ebuf becomes the newest history line
; (empty lines and repeats of the newest one are not added)
hist_add:
        beqz  a0, hda_r                 ; empty
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; save s0, s1
        sd    s1, 16(sp)                ; ...
        mv    s0, a0                    ; s0 = length
        la    t0, g_hcnt                ; s1 = lines so far
        ld    s1, 0(t0)                 ; ...
        beqz  s1, hda_put               ; none
        addi  a0, s1, -1                ; the newest one -> dirbuf
        la    a1, dirbuf                ; ...
        call  hist_get                  ; a0 = its length
        bne   a0, s0, hda_put           ; different
        la    a0, ebuf                  ; the same text?
        mv    a1, s0                    ; ...
        la    a2, dirbuf                ; ...
        mv    a3, s0                    ; ...
        call  str_eq                    ; ...
        bnez  a0, hda_ret               ; yes: not again
hda_put:
        andi  t0, s1, NHIST - 1         ; its slot
        slli  t1, t0, 3                 ; its length
        la    t2, hlen                  ; ...
        add   t2, t2, t1                ; ...
        sd    s0, 0(t2)                 ; ...
        slli  t1, t0, 8                 ; its text: HIST_OFF + slot * HSZ
        li    t2, HIST_OFF              ; ...
        add   t1, t1, t2                ; ...
        la    t0, ebuf                  ; ...
        li    t2, HSZ                   ; ...
        tput  tg1, t0, c0, t1, t2       ; D-LS -> arena
        twait 1 << 1                    ; ...
        addi  s1, s1, 1                 ; one more line
        la    t0, g_hcnt                ; ...
        sd    s1, 0(t0)                 ; ...
hda_ret:
        ld    s1, 16(sp)                ; restore s0, s1
        ld    s0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 24                ; release the frame
hda_r:
        ret                             ; done

; hist_get(a0 = line number (0 = the first ever), a1 = 256-byte destination)
; -> a0 = its length
hist_get:
        andi  t0, a0, NHIST - 1         ; its slot
        slli  t1, t0, 8                 ; arena -> D-LS
        li    t2, HIST_OFF              ; ...
        add   t1, t1, t2                ; ...
        li    t2, HSZ                   ; ...
        tget  tg1, a1, c0, t1, t2       ; ...
        twait 1 << 1                    ; ...
        slli  t1, t0, 3                 ; its length
        la    t2, hlen                  ; ...
        add   t2, t2, t1                ; ...
        ld    a0, 0(t2)                 ; ...
        ret                             ; done

; ed_up(): the previous history line (the new line is kept aside first)
ed_up:
        la    t0, g_hpos                ; t1 = shown
        ld    t1, 0(t0)                 ; ...
        la    t2, g_hcnt                ; t3 = count
        ld    t3, 0(t2)                 ; ...
        addi  t4, t3, -NHIST            ; t4 = the oldest kept
        bgez  t4, eup_1                 ; ...
        li    t4, 0                     ; ...
eup_1:
        bleu  t1, t4, eup_r             ; nothing older
        addi  t5, t1, -1                ; the one before
        sd    t5, 0(t0)                 ; ...
        bne   t1, t3, eup_go            ; leaving the new line?
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    t5, 8(sp)                 ; ...
        la    t0, g_elen                ; yes: keep it in hsave
        ld    a2, 0(t0)                 ; ...
        la    t0, g_hsvl                ; ...
        sd    a2, 0(t0)                 ; ...
        la    a0, hsave                 ; ...
        la    a1, ebuf                  ; ...
        call  bcopy                     ; ...
        ld    t5, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 16                ; release the frame
eup_go:
        mv    a0, t5                    ; show it
        j     ed_hist                   ; (tail call)
eup_r:
        ret                             ; done

; ed_down(): the next history line, or back to the new line
ed_down:
        la    t0, g_hpos                ; t1 = shown
        ld    t1, 0(t0)                 ; ...
        la    t2, g_hcnt                ; t3 = count
        ld    t3, 0(t2)                 ; ...
        bgeu  t1, t3, edn_r             ; already the new line
        addi  t1, t1, 1                 ; the next one
        sd    t1, 0(t0)                 ; ...
        mv    a0, t1                    ; ...
        bne   t1, t3, ed_hist           ; a history line (tail call)
        li    a0, -1                    ; the new line (tail call)
        j     ed_hist                   ; ...
edn_r:
        ret                             ; done

; ed_hist(a0 = history line number, or -1 for the new line): replace the line
; being edited with it; the cursor goes to its end
ed_hist:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    a0, 8(sp)                 ; which
        la    t0, g_ecur                ; cursor to the start on the screen
        ld    a0, 0(t0)                 ; ...
        call  ed_left                   ; ...
        ld    a0, 8(sp)                 ; a history line?
        bltz  a0, ehs_new               ; no
        la    a1, ebuf                  ; arena -> ebuf
        call  hist_get                  ; a0 = length
        j     ehs_set                   ; ...
ehs_new:
        la    t0, g_hsvl                ; the saved new line
        ld    a2, 0(t0)                 ; ...
        sd    a2, 8(sp)                 ; ...
        la    a0, ebuf                  ; ...
        la    a1, hsave                 ; ...
        call  bcopy                     ; ...
        ld    a0, 8(sp)                 ; its length
ehs_set:
        la    t0, g_elen                ; length and cursor
        sd    a0, 0(t0)                 ; ...
        la    t0, g_ecur                ; ...
        sd    a0, 0(t0)                 ; ...
        mv    a1, a0                    ; show it
        la    a0, ebuf                  ; ...
        call  out_str                   ; ...
        la    a0, m_el                  ; erase what is left of the old one
        li    a1, 3                     ; ...
        call  out_str                   ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 16                ; release the frame
        ret                             ; done

; =============================================================================
; Tab completion
; =============================================================================

; ed_tab(): complete the word before the cursor. In command position the
; candidates are the builtins and the programs on the disk (files that start
; with "STX2", from the whole disk: proc runs them from "/"); elsewhere the
; file names of the current tag path (every file at "/"). In a tag path
; ("/doc/mo", "/sr", or relative: "sub/c") the files carrying the path's
; tags, and its facets (the other tags they carry) as "tag/": tags work like
; folders; away from "/" a plain argument gets the current path's facets
; too. One candidate: completed, and a
; space added (none after a tag's "/"). Several: completed as far as they
; agree; a second Tab lists them in columns and draws the prompt and the
; line again.
; s0 = word start, s1 = prefix length, s2 = command position, s3 = candidates,
; s4 = the length all candidates agree on, s5 = scratch; 56(sp) = a length
ed_tab:
        addi  sp, sp, -64               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; save s0..s5
        sd    s1, 16(sp)                ; ...
        sd    s2, 24(sp)                ; ...
        sd    s3, 32(sp)                ; ...
        sd    s4, 40(sp)                ; ...
        sd    s5, 48(sp)                ; ...
        la    t0, g_ecur                ; the word ends at the cursor
        ld    s0, 0(t0)                 ; ...
etb_ws:
        beqz  s0, etb_w1                ; and starts after a separator
        la    t0, ebuf                  ; ...
        add   t0, t0, s0                ; ...
        lbu   a0, -1(t0)                ; ...
        call  is_sep                    ; ...
        bnez  a0, etb_w1                ; ...
        addi  s0, s0, -1                ; ...
        j     etb_ws                    ; ...
etb_w1:
        la    t0, g_ecur                ; s1 = the prefix length
        ld    t1, 0(t0)                 ; ...
        sub   s1, t1, s0                ; ...
        la    t0, g_cpfx                ; the prefix, for cand_add
        la    t2, ebuf                  ; ...
        add   t2, t2, s0                ; ...
        sd    t2, 0(t0)                 ; ...
        la    t0, g_cpl                 ; ...
        sd    s1, 0(t0)                 ; ...
        la    t0, g_ncand               ; no candidates yet
        sd    zero, 0(t0)               ; ...
        mv    a0, s0                    ; command position?
        call  cmd_pos                   ; ...
        mv    s2, a0                    ; ...
        la    t0, g_cdirl               ; a tag path ("/doc/mo")?
        sd    zero, 0(t0)               ; ...
        la    t1, ebuf                  ; t2 = after its last "/"
        add   t2, t1, s0                ; ...
        add   t3, t2, s1                ; ...
        mv    t4, t2                    ; ...
        li    t5, '/'                   ; ...
etb_sl:
        bgeu  t4, t3, etb_sld           ; ...
        lbu   t6, 0(t4)                 ; ...
        addi  t4, t4, 1                 ; ...
        bne   t6, t5, etb_sl            ; ...
        mv    t2, t4                    ; ...
        j     etb_sl                    ; ...
etb_sld:
        add   t4, t1, s0                ; the tag path: [word start, t2)
        sub   t5, t2, t4                ; ...
        beqz  t5, etb_nosl              ; none
        la    t6, g_cdir                ; ...
        sd    t4, 0(t6)                 ; ...
        sd    t5, 0(t0)                 ; ...
        add   s0, s0, t5                ; the name after it is completed
        sub   s1, s1, t5                ; ...
        la    t0, g_cpfx                ; ...
        sd    t2, 0(t0)                 ; ...
        la    t0, g_cpl                 ; ...
        sd    s1, 0(t0)                 ; ...
        j     etb_files                 ; (files only)
etb_nosl:
        beqz  s2, etb_files             ; not in command position: file names only
        li    s5, 0                     ; the builtins (and time, run)
etb_bl:
        li    t0, NBIC                  ; all?
        bgeu  s5, t0, etb_files         ; ...
        la    a0, bi_names              ; the name
        slli  t1, s5, 3                 ; ...
        add   a0, a0, t1                ; ...
        li    a1, 8                     ; ...
        call  ntrim                     ; a1 = its length
        li    a2, 0                     ; not a file
        call  cand_add                  ; ...
        addi  s5, s5, 1                 ; next
        j     etb_bl                    ; ...
etb_files:
        la    a0, dirbuf                ; the files: the current path's, or those
        la    a1, g_cdir                ; with the path's tags (relative to it)
        ld    a1, 0(a1)                 ; ...
        la    a2, g_cdirl               ; ...
        ld    a2, 0(a2)                 ; ...
        bnez  a2, etb_q                 ; ...
        beqz  s2, etb_q                 ; a command: every program, from the root
        la    a1, m_root                ; (they are looked for there)
        li    a2, 5                     ; ...
etb_q:
        mv    s3, a1                    ; s3 = the path, s4 = its length
        mv    s4, a2                    ; ...
        mv    a0, a1                    ; ...
        mv    a1, a2                    ; ...
        call  sys_count                 ; (asked for its facets)
        call  sys_facets                ; the other tags its files carry
        la    t0, g_cfac                ; (kept: is_prog sends requests)
        sd    a0, 0(t0)                 ; ...
        la    t0, g_cpl                 ; the files: the path, the prefix, "*": the
        ld    t1, 0(t0)                 ; file server answers the names that begin
        add   t2, s4, t1                ; so, whole, however many files there are
        li    t3, NCPATH - 1            ; ...
        bgeu  t2, t3, etb_fac           ; (too long a word: no names)
        la    t4, cpath                 ; t4 = where it is put together
etb_qp:
        beqz  s4, etb_qx                ; the path
        lbu   t5, 0(s3)                 ; ...
        sb    t5, 0(t4)                 ; ...
        addi  s3, s3, 1                 ; ...
        addi  t4, t4, 1                 ; ...
        addi  s4, s4, -1                ; ...
        j     etb_qp                    ; ...
etb_qx:
        la    t0, g_cpfx                ; the prefix
        ld    t0, 0(t0)                 ; ...
etb_qc:
        beqz  t1, etb_qs                ; ...
        lbu   t5, 0(t0)                 ; ...
        sb    t5, 0(t4)                 ; ...
        addi  t0, t0, 1                 ; ...
        addi  t4, t4, 1                 ; ...
        addi  t1, t1, -1                ; ...
        j     etb_qc                    ; ...
etb_qs:
        li    t5, '*'                   ; ...
        sb    t5, 0(t4)                 ; ...
        la    a0, dirbuf                ; ...
        la    a1, cpath                 ; ...
        addi  a2, t2, 1                 ; ...
        li    a3, 0                     ; (the first part: more than fill a screen)
        call  sys_list                  ; a0 = files (< 0: none)
        mv    s5, a0                    ; s5 = their number
        la    s3, dirbuf                ; s3 = the record: after the path's own tags
        ld    t0, 0(s3)                 ; ...
        slli  t0, t0, 2                 ; ...
        addi  t0, t0, 15                ; ...
        srli  t0, t0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        add   s3, s3, t0                ; ...
etb_fl:
        blez  s5, etb_fac               ; all seen (also if the listing failed)
        addi  a0, s3, 16                ; its name
        lhu   a1, 2(s3)                 ; ...
        lhu   t0, 0(s3)                 ; (next)
        add   s3, s3, t0                ; ...
        addi  s5, s5, -1                ; ...
        mv    a2, s2                    ; in command position: programs only
        call  cand_add                  ; ...
        j     etb_fl                    ; ...
etb_fac:
        la    t0, g_cdirl               ; in a tag path: its facets, as "tag/"
        ld    t0, 0(t0)                 ; ...
        bnez  t0, etb_fc                ; in one
        bnez  s2, etb_got               ; a command: none
        la    t0, g_cwdl                ; an argument away from the root: the
        ld    t0, 0(t0)                 ; current path's facets
        li    t1, 1                     ; ...
        bleu  t0, t1, etb_got           ; at the root: none
etb_fc:
        la    t0, g_cfac                ; ...
        ld    t0, 0(t0)                 ; ...
        beqz  t0, etb_got               ; none
        la    a0, ctags                 ; every tag, with its id (sys_tags2: the first
        li    a1, 0                     ; part, which has the ids a facet can have)
        li    a2, 0                     ; ...
        li    a3, 0                     ; ...
        call  sys_tags2                 ; a0 = how many
        mv    s5, a0                    ; s5 = records left
        la    s3, ctags                 ; s3 = record: u16 bytes, u16 name length, u32
etb_tl:
        blez  s5, etb_got               ; id, u64 files, the name
        mv    a0, s3                    ; ...
        lhu   t0, 0(s3)                 ; (next)
        add   s3, s3, t0                ; ...
        addi  s5, s5, -1                ; ...
        lwu   t0, 4(a0)                 ; a facet?
        li    t1, 64                    ; ...
        bgeu  t0, t1, etb_tl            ; ...
        la    t1, g_cfac                ; ...
        ld    t1, 0(t1)                 ; ...
        srl   t1, t1, t0                ; ...
        andi  t1, t1, 1                 ; ...
        beqz  t1, etb_tl                ; no
        lhu   a1, 2(a0)                 ; its name, moved a byte down over the record's
        addi  a0, a0, 15                ; own words to make room for "/" after it
        li    t0, 0                     ; ...
etb_tm:
        bgeu  t0, a1, etb_ts            ; ...
        add   t1, a0, t0                ; ...
        lbu   t2, 1(t1)                 ; ...
        sb    t2, 0(t1)                 ; ...
        addi  t0, t0, 1                 ; ...
        j     etb_tm                    ; ...
etb_ts:
        add   t0, a0, a1                ; ...
        li    t1, '/'                   ; ...
        sb    t1, 0(t0)                 ; ...
        addi  a1, a1, 1                 ; ...
        li    a2, 0                     ; any tag will do
        call  cand_add                  ; ...
        j     etb_tl                    ; ...
etb_got:
        la    t0, g_ncand               ; s3 = candidates
        ld    s3, 0(t0)                 ; ...
        beqz  s3, etb_ret               ; none: nothing happens
        call  cand_sort                 ; in order, without repeats
        la    t0, g_ncand               ; ...
        ld    s3, 0(t0)                 ; ...
        la    t0, cand                  ; s4 = the first one's length,
        ld    t1, 0(t0)                 ; s5 = its text
        srli  s4, t1, 32                ; ...
        slli  s5, t1, 32                ; ...
        srli  s5, s5, 32                ; ...
        li    t6, 1                     ; t6 = the next candidate
etb_lcp:
        bgeu  t6, s3, etb_ins           ; all compared
        la    t0, cand                  ; t2 = its text, t3 = its length
        slli  t1, t6, 3                 ; ...
        add   t0, t0, t1                ; ...
        ld    t1, 0(t0)                 ; ...
        srli  t3, t1, 32                ; ...
        slli  t2, t1, 32                ; ...
        srli  t2, t2, 32                ; ...
        li    t4, 0                     ; t4 = how far they agree
etb_lc:
        bgeu  t4, s4, etb_ln            ; ...
        bgeu  t4, t3, etb_ln            ; ...
        add   t0, s5, t4                ; ...
        lbu   t0, 0(t0)                 ; ...
        add   t1, t2, t4                ; ...
        lbu   t1, 0(t1)                 ; ...
        bne   t0, t1, etb_ln            ; ...
        addi  t4, t4, 1                 ; ...
        j     etb_lc                    ; ...
etb_ln:
        mv    s4, t4                    ; the agreement shrinks
        addi  t6, t6, 1                 ; next candidate
        j     etb_lcp                   ; ...
etb_ins:
        bgeu  s1, s4, etb_insd          ; insert what they agree on beyond the prefix
        add   t0, s5, s1                ; ...
        lbu   a0, 0(t0)                 ; ...
        call  ed_ins                    ; ...
        addi  s1, s1, 1                 ; ...
        j     etb_ins                   ; ...
etb_insd:
        li    t0, 1                     ; a single candidate?
        bne   s3, t0, etb_many          ; no
        add   t0, s5, s4                ; a tag ("src/")? the path goes on
        lbu   t0, -1(t0)                ; ...
        li    t1, '/'                   ; ...
        beq   t0, t1, etb_ret           ; ...
        li    a0, ' '                   ; no: the word is complete
        call  ed_ins                    ; ...
        j     etb_ret                   ; ...
etb_many:
        la    t0, g_tabs                ; the second Tab in a row lists them
        ld    t1, 0(t0)                 ; ...
        li    t2, 1                     ; ...
        sd    t2, 0(t0)                 ; ...
        beqz  t1, etb_ret               ; the first: done
        call  out_nl                    ; below the line
        li    s4, 0                     ; s4 = the column width: longest + 2
        li    t6, 0                     ; ...
etb_wl:
        bgeu  t6, s3, etb_wd            ; ...
        la    t0, cand                  ; ...
        slli  t1, t6, 3                 ; ...
        add   t0, t0, t1                ; ...
        ld    t1, 0(t0)                 ; ...
        srli  t1, t1, 32                ; ...
        bleu  t1, s4, etb_wn            ; ...
        mv    s4, t1                    ; ...
etb_wn:
        addi  t6, t6, 1                 ; ...
        j     etb_wl                    ; ...
etb_wd:
        addi  s4, s4, 2                 ; ...
        li    t0, TERMW                 ; s5 = columns (at least 1)
        divu  s5, t0, s4                ; ...
        bnez  s5, etb_rows              ; ...
        li    s5, 1                     ; ...
etb_rows:
        add   t0, s3, s5                ; s0 = rows = ceil(candidates / columns)
        addi  t0, t0, -1                ; ...
        divu  s0, t0, s5                ; ...
        li    s1, 0                     ; s1 = row
etb_row:
        bgeu  s1, s0, etb_ldone         ; all rows
        li    s2, 0                     ; s2 = column
etb_col:
        bgeu  s2, s5, etb_eol           ; all columns
        mul   t0, s2, s0                ; candidate = column * rows + row
        add   t0, t0, s1                ; ...
        bgeu  t0, s3, etb_eol           ; none: the row ends
        la    t1, cand                  ; its text and length
        slli  t0, t0, 3                 ; ...
        add   t1, t1, t0                ; ...
        ld    t1, 0(t1)                 ; ...
        srli  a1, t1, 32                ; ...
        sd    a1, 56(sp)                ; ...
        slli  a0, t1, 32                ; ...
        srli  a0, a0, 32                ; ...
        call  out_str                   ; ...
        addi  s2, s2, 1                 ; the next column
        mul   t0, s2, s0                ; is there one in this row?
        add   t0, t0, s1                ; ...
        bgeu  t0, s3, etb_eol           ; no: no padding
        bgeu  s2, s5, etb_eol           ; ...
        ld    t1, 56(sp)                ; pad to the column width
        sub   a0, s4, t1                ; ...
        call  out_pad                   ; ...
        j     etb_col                   ; ...
etb_eol:
        call  out_nl                    ; the row is done
        addi  s1, s1, 1                 ; ...
        j     etb_row                   ; ...
etb_ldone:
        call  ed_redraw                 ; prompt and line again
etb_ret:
        ld    s5, 48(sp)                ; restore s0..s5
        ld    s4, 40(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s1, 16(sp)                ; ...
        ld    s0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 64                ; release the frame
        ret                             ; done

; is_sep(a0 = character) -> a0 = 1 if it separates words: space, tab, | ; & < >
is_sep:
        li    t6, ' '                   ; ...
        beq   a0, t6, isp_y             ; ...
        li    t6, 9                     ; ...
        beq   a0, t6, isp_y             ; ...
        li    t6, '|'                   ; ...
        beq   a0, t6, isp_y             ; ...
        li    t6, ';'                   ; ...
        beq   a0, t6, isp_y             ; ...
        li    t6, '&'                   ; ...
        beq   a0, t6, isp_y             ; ...
        li    t6, '<'                   ; ...
        beq   a0, t6, isp_y             ; ...
        li    t6, '>'                   ; ...
        beq   a0, t6, isp_y             ; ...
        li    a0, 0                     ; a word character
        ret                             ; ...
isp_y:
        li    a0, 1                     ; a separator
        ret                             ; ...

; ntrim(a0 = text, a1 = maximum) -> a1 = its length up to the first space or
; zero byte (a0 is kept)
ntrim:
        li    t0, 0                     ; length
ntr_l:
        beq   t0, a1, ntr_d             ; the maximum
        add   t1, a0, t0                ; ...
        lbu   t1, 0(t1)                 ; ...
        beqz  t1, ntr_d                 ; zero
        li    t2, ' '                   ; space
        beq   t1, t2, ntr_d             ; ...
        addi  t0, t0, 1                 ; ...
        j     ntr_l                     ; ...
ntr_d:
        mv    a1, t0                    ; ...
        ret                             ; done

; cmd_pos(a0 = index of a word in ebuf) -> a0 = 1 if the word is a command
; name: only `run`, `time`, `-n N`, `-c N`, `-m N` stand before it in its command (the
; text after the last ; | &), and it does not follow < or >
cmd_pos:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; save s0..s3
        sd    s1, 16(sp)                ; ...
        sd    s2, 24(sp)                ; ...
        sd    s3, 32(sp)                ; ...
        mv    s0, a0                    ; s0 = the word
        mv    t0, s0                    ; the character before it (spaces skipped)
cps_b:
        beqz  t0, cps_seg               ; none
        la    t1, ebuf                  ; ...
        add   t1, t1, t0                ; ...
        lbu   t2, -1(t1)                ; ...
        li    t3, ' '                   ; ...
        bne   t2, t3, cps_nb            ; ...
        addi  t0, t0, -1                ; ...
        j     cps_b                     ; ...
cps_nb:
        li    t3, '<'                   ; a redirection's file name
        beq   t2, t3, cps_no            ; ...
        li    t3, '>'                   ; ...
        beq   t2, t3, cps_no            ; ...
cps_seg:
        mv    s1, s0                    ; s1 = the start of its command
cps_s:
        beqz  s1, cps_go                ; ...
        la    t1, ebuf                  ; ...
        add   t1, t1, s1                ; ...
        lbu   t2, -1(t1)                ; ...
        li    t3, ';'                   ; ...
        beq   t2, t3, cps_go            ; ...
        li    t3, '|'                   ; ...
        beq   t2, t3, cps_go            ; ...
        li    t3, '&'                   ; ...
        beq   t2, t3, cps_go            ; ...
        addi  s1, s1, -1                ; ...
        j     cps_s                     ; ...
cps_go:
        li    s2, 0                     ; s2 = 1: the next word is an option's number
cps_w:
        la    t0, ebuf                  ; the next word before ours
        add   a0, t0, s1                ; ...
        add   a1, t0, s0                ; ...
        call  arg_next                  ; a0 = word, a1 = length, a2 = after it
        beqz  a1, cps_yes               ; none left: ours is the command
        la    t0, ebuf                  ; continue after it
        sub   s1, a2, t0                ; ...
        bnez  s2, cps_skip              ; an option's number
        mv    s3, a0                    ; s3 = the word
        sd    a1, 40(sp)                ; (its length)
        mv    a2, a0                    ; ...
        la    a0, w_run                 ; "run"?
        li    a1, 3                     ; ...
        ld    a3, 40(sp)                ; ...
        call  str_eq                    ; ...
        bnez  a0, cps_w                 ; yes: keep looking
        la    a0, w_time                ; "time"?
        li    a1, 4                     ; ...
        mv    a2, s3                    ; ...
        ld    a3, 40(sp)                ; ...
        call  str_eq                    ; ...
        bnez  a0, cps_w                 ; ...
        la    a0, w_n                   ; "-n"?
        li    a1, 2                     ; ...
        mv    a2, s3                    ; ...
        ld    a3, 40(sp)                ; ...
        call  str_eq                    ; ...
        bnez  a0, cps_opt               ; ...
        la    a0, w_c                   ; "-c"?
        li    a1, 2                     ; ...
        mv    a2, s3                    ; ...
        ld    a3, 40(sp)                ; ...
        call  str_eq                    ; ...
        bnez  a0, cps_opt               ; ...
        la    a0, w_m                   ; "-m"?
        li    a1, 2                     ; ...
        mv    a2, s3                    ; ...
        ld    a3, 40(sp)                ; ...
        call  str_eq                    ; ...
        beqz  a0, cps_no                ; anything else: a command came before
cps_opt:
        li    s2, 1                     ; its number follows
        j     cps_w                     ; ...
cps_skip:
        li    s2, 0                     ; the number is skipped
        j     cps_w                     ; ...
cps_yes:
        li    a0, 1                     ; command position
        j     cps_ret                   ; ...
cps_no:
        li    a0, 0                     ; an argument
cps_ret:
        ld    s3, 32(sp)                ; restore s0..s3
        ld    s2, 24(sp)                ; ...
        ld    s1, 16(sp)                ; ...
        ld    s0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 48                ; release the frame
        ret                             ; done

; cand_add(a0 = name, a1 = length, a2 = 1: only if it is a program): add it to
; the candidates if it starts with the prefix (g_cpfx, g_cpl)
cand_add:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    a0, 8(sp)                 ; name
        sd    a1, 16(sp)                ; length
        beqz  a1, cad_ret               ; an empty name
        la    t0, g_cpl                 ; t1 = prefix length
        ld    t1, 0(t0)                 ; ...
        bltu  a1, t1, cad_ret           ; shorter than the prefix
        la    t2, g_cpfx                ; t2 = prefix
        ld    t2, 0(t2)                 ; ...
        li    t3, 0                     ; compare
cad_cmp:
        bgeu  t3, t1, cad_ok            ; it starts with the prefix
        add   t4, a0, t3                ; ...
        lbu   t4, 0(t4)                 ; ...
        add   t5, t2, t3                ; ...
        lbu   t5, 0(t5)                 ; ...
        bne   t4, t5, cad_ret           ; it does not
        addi  t3, t3, 1                 ; ...
        j     cad_cmp                   ; ...
cad_ok:
        beqz  a2, cad_push              ; any file will do
        call  is_prog                   ; a program?
        beqz  a0, cad_ret               ; no
cad_push:
        la    t0, g_ncand               ; room?
        ld    t1, 0(t0)                 ; ...
        li    t2, NCAND                 ; ...
        bgeu  t1, t2, cad_ret           ; no
        ld    a0, 8(sp)                 ; address | length << 32
        ld    a1, 16(sp)                ; ...
        slli  t3, a1, 32                ; ...
        or    t3, t3, a0                ; ...
        la    t4, cand                  ; ...
        slli  t5, t1, 3                 ; ...
        add   t4, t4, t5                ; ...
        sd    t3, 0(t4)                 ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, 0(t0)                 ; ...
cad_ret:
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 32                ; release the frame
        ret                             ; done

; is_prog(a0 = name, a1 = length) -> a0 = 1 if the file is a program image
; (it starts with the magic "STX2")
is_prog:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; save s0
        la    t0, pnbuf                 ; its path: the directory being completed (the
        la    t5, g_cdirl               ; word's, else /bin/), then the name
        ld    t5, 0(t5)                 ; ...
        la    t6, g_cdir                ; ...
        ld    t6, 0(t6)                 ; ...
        bnez  t5, ipg_d                 ; ...
        la    t6, m_root                ; ...
        li    t5, 5                     ; ...
ipg_d:
        li    t2, 0                     ; ...
ipg_p:
        bgeu  t2, t5, ipg_n             ; ...
        add   t3, t6, t2                ; ...
        lbu   t3, 0(t3)                 ; ...
        add   t4, t0, t2                ; ...
        sb    t3, 0(t4)                 ; ...
        addi  t2, t2, 1                 ; ...
        j     ipg_p                     ; ...
ipg_n:
        add   t0, t0, t5                ; ...
        li    t2, 0                     ; ...
ipg_c:
        bgeu  t2, a1, ipg_o             ; ...
        add   t3, a0, t2                ; ...
        lbu   t3, 0(t3)                 ; ...
        add   t4, t0, t2                ; ...
        sb    t3, 0(t4)                 ; ...
        addi  t2, t2, 1                 ; ...
        j     ipg_c                     ; ...
ipg_o:
        la    a0, pnbuf                 ; open it
        add   a1, a1, t5                ; ...
        li    a2, 0                     ; ...
        call  sys_open                  ; ...
        bltz  a0, ipg_no                ; cannot
        mv    s0, a0                    ; s0 = handle
        la    a1, numbuf                ; its first 4 bytes
        sd    zero, 0(a1)               ; ...
        li    a2, 4                     ; ...
        call  sys_read                  ; ...
        mv    a0, s0                    ; close it
        call  sys_close                 ; ...
        la    t0, numbuf                ; "STX2"?
        ld    t1, 0(t0)                 ; ...
        li    t2, 0x32585453            ; ...
        sub   t1, t1, t2                ; ...
        seqz  a0, t1                    ; ...
        j     ipg_ret                   ; ...
ipg_no:
        li    a0, 0                     ; not a program
ipg_ret:
        ld    s0, 8(sp)                 ; restore s0
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 16                ; release the frame
        ret                             ; done

; cand_cmp(a0 = candidate, a1 = candidate) -> a0 < 0, 0, > 0 as the first
; sorts before, equal to, after the second
cand_cmp:
        slli  t0, a0, 32                ; t0, t1 = the first's text and length
        srli  t0, t0, 32                ; ...
        srli  t1, a0, 32                ; ...
        slli  t2, a1, 32                ; t2, t3 = the second's
        srli  t2, t2, 32                ; ...
        srli  t3, a1, 32                ; ...
        li    t4, 0                     ; index
ccp_l:
        bgeu  t4, t1, ccp_end           ; the first ended
        bgeu  t4, t3, ccp_gt            ; the second ended: the first is longer
        add   t5, t0, t4                ; ...
        lbu   t5, 0(t5)                 ; ...
        add   t6, t2, t4                ; ...
        lbu   t6, 0(t6)                 ; ...
        sub   a0, t5, t6                ; ...
        bnez  a0, ccp_r                 ; they differ here
        addi  t4, t4, 1                 ; ...
        j     ccp_l                     ; ...
ccp_end:
        sub   a0, t1, t3                ; 0 if equal, < 0 if the first is shorter
ccp_r:
        ret                             ; done
ccp_gt:
        li    a0, 1                     ; ...
        ret                             ; done

; cand_sort(): sort the candidates (insertion sort) and drop repeats
cand_sort:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; save s0..s3
        sd    s1, 16(sp)                ; ...
        sd    s2, 24(sp)                ; ...
        sd    s3, 32(sp)                ; ...
        la    t0, g_ncand               ; s0 = count
        ld    s0, 0(t0)                 ; ...
        li    s1, 1                     ; s1 = the next to place
csr_i:
        bgeu  s1, s0, csr_dd            ; all placed
        la    t0, cand                  ; s2 = it
        slli  t1, s1, 3                 ; ...
        add   t0, t0, t1                ; ...
        ld    s2, 0(t0)                 ; ...
        mv    s3, s1                    ; s3 = where it goes
csr_j:
        beqz  s3, csr_put               ; the front
        la    t0, cand                  ; compare with the one before
        slli  t1, s3, 3                 ; ...
        add   t0, t0, t1                ; ...
        ld    a1, -8(t0)                ; ...
        mv    a0, s2                    ; ...
        call  cand_cmp                  ; ...
        bgez  a0, csr_put               ; not before it: here
        la    t0, cand                  ; move that one up
        slli  t1, s3, 3                 ; ...
        add   t0, t0, t1                ; ...
        ld    t2, -8(t0)                ; ...
        sd    t2, 0(t0)                 ; ...
        addi  s3, s3, -1                ; ...
        j     csr_j                     ; ...
csr_put:
        la    t0, cand                  ; ...
        slli  t1, s3, 3                 ; ...
        add   t0, t0, t1                ; ...
        sd    s2, 0(t0)                 ; ...
        addi  s1, s1, 1                 ; ...
        j     csr_i                     ; ...
csr_dd:
        beqz  s0, csr_ret               ; nothing
        li    s1, 1                     ; s1 = read index
        li    s3, 1                     ; s3 = write index
csr_d:
        bgeu  s1, s0, csr_dn            ; ...
        la    t0, cand                  ; s2 = this one
        slli  t1, s1, 3                 ; ...
        add   t0, t0, t1                ; ...
        ld    s2, 0(t0)                 ; ...
        la    t0, cand                  ; the last one kept
        slli  t1, s3, 3                 ; ...
        add   t0, t0, t1                ; ...
        ld    a1, -8(t0)                ; ...
        mv    a0, s2                    ; ...
        call  cand_cmp                  ; the same?
        beqz  a0, csr_sk                ; yes: drop it
        la    t0, cand                  ; keep it
        slli  t1, s3, 3                 ; ...
        add   t0, t0, t1                ; ...
        sd    s2, 0(t0)                 ; ...
        addi  s3, s3, 1                 ; ...
csr_sk:
        addi  s1, s1, 1                 ; ...
        j     csr_d                     ; ...
csr_dn:
        la    t0, g_ncand               ; the new count
        sd    s3, 0(t0)                 ; ...
csr_ret:
        ld    s3, 32(sp)                ; restore s0..s3
        ld    s2, 24(sp)                ; ...
        ld    s1, 16(sp)                ; ...
        ld    s0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 40                ; release the frame
        ret                             ; done

; =============================================================================
; Running a line: a list of commands joined by ; && || &
; =============================================================================

; run_line(a0 = text, a1 = length): run one line; sets g_stat. Commands are
; split at ; && || & outside quotes; # at the start of a word ends the line.
; A command after && runs only if $? is 0, after || only if it is not. An
; interrupted command stops the rest of the line.
; s0 = cursor, s1 = end, s2 = connector before the command (OPC_*), s3 = the
; command's end, s4 = quote character inside it, s5 = the operator after it
; (0 ;, 1 &&, 2 ||, 3 &, -1 none), s6 = the operator's length
run_line:
        addi  sp, sp, -64               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; save s0..s6
        sd    s1, 16(sp)                ; ...
        sd    s2, 24(sp)                ; ...
        sd    s3, 32(sp)                ; ...
        sd    s4, 40(sp)                ; ...
        sd    s5, 48(sp)                ; ...
        sd    s6, 56(sp)                ; ...
        mv    s0, a0                    ; ...
        add   s1, a0, a1                ; ...
        li    s2, OPC_SEMI              ; the first command always runs
rln_cmd:
        bgeu  s0, s1, rln_ret           ; the line is done
        mv    s3, s0                    ; find the command's end
        li    s4, 0                     ; not inside quotes
rln_sc:
        bgeu  s3, s1, rln_eol           ; the end of the line
        lbu   t0, 0(s3)                 ; ...
        li    t1, 92                    ; \ (outside '...') hides the next character
        bne   t0, t1, rln_nb            ; ...
        li    t1, 39                    ; ...
        beq   s4, t1, rln_nx            ; ...
        addi  s3, s3, 1                 ; ...
        j     rln_nx                    ; ...
rln_nb:
        beqz  s4, rln_nq                ; outside quotes?
        bne   t0, s4, rln_nx            ; inside: only the closing quote matters
        li    s4, 0                     ; ...
        j     rln_nx                    ; ...
rln_nq:
        li    t1, 39                    ; ' or " opens quotes
        beq   t0, t1, rln_q             ; ...
        li    t1, 34                    ; ...
        beq   t0, t1, rln_q             ; ...
        li    t1, '#'                   ; a comment?
        beq   t0, t1, rln_hash          ; ...
        li    s6, 1                     ; one-character operators
        li    s5, 0                     ; ;
        li    t1, ';'                   ; ...
        beq   t0, t1, rln_found         ; ...
        li    t1, '&'                   ; & or &&
        beq   t0, t1, rln_amp           ; ...
        li    t1, '|'                   ; || (| is a pipe, part of the command)
        beq   t0, t1, rln_bar           ; ...
rln_nx:
        addi  s3, s3, 1                 ; next character
        j     rln_sc                    ; ...
rln_q:
        mv    s4, t0                    ; inside quotes now
        j     rln_nx                    ; ...
rln_hash:
        beq   s3, s0, rln_cmt           ; at the start of the command
        lbu   a0, -1(s3)                ; or after a separator: a comment
        call  is_sep                    ; ...
        beqz  a0, rln_nx                ; inside a word: just a character
rln_cmt:
        mv    s1, s3                    ; the line ends here
rln_eol:
        li    s5, -1                    ; no operator
        li    s6, 0                     ; ...
        j     rln_found                 ; ...
rln_amp:
        li    s5, 3                     ; & ...
        addi  t2, s3, 1                 ; ... or &&?
        bgeu  t2, s1, rln_found         ; ...
        lbu   t2, 0(t2)                 ; ...
        bne   t2, t1, rln_found         ; ...
        li    s5, 1                     ; &&
        li    s6, 2                     ; ...
        j     rln_found                 ; ...
rln_bar:
        addi  t2, s3, 1                 ; ||?
        bgeu  t2, s1, rln_nx            ; ...
        lbu   t2, 0(t2)                 ; ...
        bne   t2, t1, rln_nx            ; a pipe
        li    s5, 2                     ; ||
        li    s6, 2                     ; ...
rln_found:
        mv    a0, s0                    ; is the command empty?
        mv    a1, s3                    ; ...
        call  blank                     ; ...
        beqz  a0, rln_run               ; no
        bltz  s5, rln_ret               ; nothing at the end of the line: fine
        la    a0, m_syn                 ; an operator without a command
        li    a1, m_syn_e - m_syn       ; ...
        call  err_str                   ; ...
        li    a0, 2                     ; status 2
        call  set_stat                  ; ...
        j     rln_ret                   ; ...
rln_run:
        la    t0, g_stat                ; t1 = $? = 0
        ld    t1, 0(t0)                 ; ...
        seqz  t1, t1                    ; ...
        li    t0, OPC_AND               ; after &&: only if $? = 0
        bne   s2, t0, rln_or            ; ...
        beqz  t1, rln_next              ; ...
        j     rln_go                    ; ...
rln_or:
        li    t0, OPC_OR                ; after ||: only if $? != 0
        bne   s2, t0, rln_go            ; ...
        bnez  t1, rln_next              ; ...
rln_go:
        mv    a0, s0                    ; run it
        sub   a1, s3, s0                ; ...
        addi  a2, s5, -3                ; in the background if followed by &
        seqz  a2, a2                    ; ...
        call  run_seg                   ; ...
        la    t0, g_intr                ; interrupted: the rest of the line is dropped
        ld    t0, 0(t0)                 ; ...
        bnez  t0, rln_ret               ; ...
rln_next:
        bltz  s5, rln_ret               ; the end of the line
        mv    s2, s5                    ; the connector for the next command
        li    t0, 3                     ; (& works like ;)
        bne   s2, t0, rln_n2            ; ...
        li    s2, OPC_SEMI              ; ...
rln_n2:
        add   s0, s3, s6                ; past the operator
        j     rln_cmd                   ; the next command
rln_ret:
        ld    s6, 56(sp)                ; restore s0..s6
        ld    s5, 48(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s1, 16(sp)                ; ...
        ld    s0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 64                ; release the frame
        ret                             ; done

; blank(a0 = start, a1 = end) -> a0 = 1 if there are only spaces and tabs
blank:
        bgeu  a0, a1, blk_y             ; nothing left
        lbu   t0, 0(a0)                 ; ...
        li    t1, ' '                   ; ...
        beq   t0, t1, blk_n             ; ...
        li    t1, 9                     ; ...
        beq   t0, t1, blk_n             ; ...
        li    t1, 13                    ; ...
        beq   t0, t1, blk_n             ; ...
        li    a0, 0                     ; something
        ret                             ; ...
blk_n:
        addi  a0, a0, 1                 ; next
        j     blank                     ; ...
blk_y:
        li    a0, 1                     ; blank
        ret                             ; ...

; run_seg(a0 = text, a1 = length, a2 = 1: in the background): run one
; command (a pipeline); sets g_stat. `time CMD` times the rest.
; s0 = text, s1 = end, s2 = background, s3 = the text after `time`
run_seg:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; save s0..s3
        sd    s1, 16(sp)                ; ...
        sd    s2, 24(sp)                ; ...
        sd    s3, 32(sp)                ; ...
        mv    s0, a0                    ; ...
        add   s1, a0, a1                ; ...
        mv    s2, a2                    ; ...
        mv    a1, s1                    ; the first word: "time"?
        call  arg_next                  ; a0 = word, a1 = length, a2 = after it
        mv    s3, a2                    ; ...
        la    a2, w_time                ; ...
        li    a3, 4                     ; ...
        call  str_eq                    ; ...
        beqz  a0, rsg_go                ; no
        call  sys_now                   ; the time before
        sd    a0, 40(sp)                ; ...
        mv    a0, s3                    ; run the rest
        sub   a1, s1, s3                ; ...
        mv    a2, s2                    ; ...
        call  run_seg                   ; ...
        call  sys_now                   ; the time after
        ld    t0, 40(sp)                ; ...
        sub   a0, a0, t0                ; ticks taken
        call  time_rep                  ; "time: S.UUUUUU s"
        j     rsg_ret                   ; done
rsg_go:
        la    t0, g_segp                ; the command's text (for the job table)
        sd    s0, 0(t0)                 ; ...
        sub   t1, s1, s0                ; ...
        la    t0, g_segl                ; ...
        sd    t1, 0(t0)                 ; ...
        mv    a0, s0                    ; words and operators
        mv    a1, t1                    ; ...
        call  tokenize                  ; a0 = 0, -1 too long, -2 open quote
        li    t0, -2                    ; an unterminated quote?
        beq   a0, t0, rsg_quote         ; ...
        bltz  a0, rsg_long              ; too long
        call  parse                     ; a0 = 0, -1 syntax error, -2 too long
        li    t0, -2                    ; too long?
        beq   a0, t0, rsg_long          ; ...
        bltz  a0, rsg_syn               ; syntax error
        la    t0, g_nst                 ; stages
        ld    t0, 0(t0)                 ; ...
        beqz  t0, rsg_ret               ; an empty command: nothing to do
        la    t1, g_bg                  ; in the background?
        sd    s2, 0(t1)                 ; ...
        bnez  s2, rsg_pipe              ; yes: never a builtin in the shell itself
        li    t1, 1                     ; a single command may be a builtin
        bne   t0, t1, rsg_pipe          ; a pipeline is not
        call  find_bi                   ; a0 = builtin number, 0 = none
        beqz  a0, rsg_pipe              ; not a builtin
        call  run_bi                    ; run it here
        j     rsg_ret                   ; done
rsg_pipe:
        call  run_pipe                  ; start the programs (and wait)
        j     rsg_ret                   ; done
rsg_quote:
        la    a0, m_quote               ; "sh: unterminated quote"
        li    a1, m_quote_e - m_quote   ; ...
        j     rsg_err                   ; ...
rsg_long:
        la    a0, m_long                ; "sh: line too long"
        li    a1, m_long_e - m_long     ; ...
        j     rsg_err                   ; ...
rsg_syn:
        la    a0, m_syn                 ; "sh: syntax error"
        li    a1, m_syn_e - m_syn       ; ...
rsg_err:
        call  err_str                   ; ...
        li    a0, 2                     ; status 2
        call  set_stat                  ; ...
rsg_ret:
        ld    s3, 32(sp)                ; restore s0..s3
        ld    s2, 24(sp)                ; ...
        ld    s1, 16(sp)                ; ...
        ld    s0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 48                ; release the frame
        ret                             ; done

; time_rep(a0 = ticks): "time: S.UUUUUU s" on stderr (1 tick = 1 us)
time_rep:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    a0, 8(sp)                 ; ticks
        la    a0, m_time                ; "time: "
        li    a1, m_time_e - m_time     ; ...
        call  err_str                   ; ...
        ld    t0, 8(sp)                 ; whole seconds
        li    t1, 1000000               ; ...
        divu  a0, t0, t1                ; ...
        call  err_num                   ; ...
        ld    t0, 8(sp)                 ; "." and six digits of microseconds
        li    t1, 1000000               ; ...
        remu  t0, t0, t1                ; ...
        la    t2, numend                ; right to left
        li    t3, 6                     ; ...
        li    t1, 10                    ; ...
trp_l:
        remu  t4, t0, t1                ; a digit
        divu  t0, t0, t1                ; ...
        addi  t4, t4, '0'               ; ...
        addi  t2, t2, -1                ; ...
        sb    t4, 0(t2)                 ; ...
        addi  t3, t3, -1                ; ...
        bnez  t3, trp_l                 ; ...
        li    t4, '.'                   ; ...
        sb    t4, -1(t2)                ; ...
        addi  a0, t2, -1                ; ...
        li    a1, 7                     ; ...
        call  err_str                   ; ...
        la    a0, m_secs                ; " s"
        li    a1, 3                     ; ...
        call  err_str                   ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 16                ; release the frame
        ret                             ; done

; =============================================================================
; Tokenizer: a command -> tokens (words with quotes removed and $ expanded,
; and the operators | < > >>)
; =============================================================================

; tokenize(a0 = text, a1 = length) -> a0 = 0, -1 too many tokens or too much
; text, -2 an unterminated quote. A word may mix plain text, '...' (taken as
; it is) and "..." (with $ expanded); a word that expands to nothing and had
; no quotes is dropped.
; s0 = cursor, s1 = end, s2 = pool cursor, s3 = token entry, s4 = tokens,
; s5 = the open quote (0 none), s6 = the word had quotes
tokenize:
        addi  sp, sp, -64               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; save s0..s6
        sd    s1, 16(sp)                ; ...
        sd    s2, 24(sp)                ; ...
        sd    s3, 32(sp)                ; ...
        sd    s4, 40(sp)                ; ...
        sd    s5, 48(sp)                ; ...
        sd    s6, 56(sp)                ; ...
        mv    s0, a0                    ; ...
        add   s1, a0, a1                ; ...
        la    s2, pool                  ; ...
        la    s3, toks                  ; ...
        li    s4, 0                     ; ...
tk_skip:
        bgeu  s0, s1, tk_done           ; the end of the text
        lbu   t0, 0(s0)                 ; t0 = the next character
        li    t1, ' '                   ; spaces, tabs and CRs separate
        beq   t0, t1, tk_sp             ; ...
        li    t1, 9                     ; ...
        beq   t0, t1, tk_sp             ; ...
        li    t1, 13                    ; ...
        beq   t0, t1, tk_sp             ; ...
        li    t1, MAXTOK                ; room for another token?
        bgeu  s4, t1, tk_full           ; no
        li    t5, TK_PIPE               ; '|'
        li    t1, '|'                   ; ...
        beq   t0, t1, tk_op             ; ...
        li    t5, TK_LT                 ; '<'
        li    t1, '<'                   ; ...
        beq   t0, t1, tk_op             ; ...
        li    t1, '>'                   ; '>' or '>>'
        bne   t0, t1, tk_word           ; anything else starts a word
        li    t5, TK_GT                 ; ...
        addi  t2, s0, 1                 ; ...
        bgeu  t2, s1, tk_op             ; ...
        lbu   t2, 0(t2)                 ; ...
        bne   t2, t1, tk_op             ; ...
        li    t5, TK_GTGT               ; '>>'
        addi  s0, s0, 1                 ; one more character
tk_op:
        addi  s0, s0, 1                 ; past the operator
        sd    t5, 0(s3)                 ; an operator token
        sd    zero, 8(s3)               ; (no text)
        sd    zero, 16(s3)              ; ...
        addi  s3, s3, 24                ; next entry
        addi  s4, s4, 1                 ; one more token
        j     tk_skip                   ; ...
tk_sp:
        addi  s0, s0, 1                 ; skip a separator
        j     tk_skip                   ; ...
tk_word:
        li    t5, TK_WORD               ; a word token
        sd    t5, 0(s3)                 ; ...
        sd    s2, 8(s3)                 ; its text starts here in the pool
        li    s5, 0                     ; not in quotes
        li    s6, 0                     ; no quotes yet
tk_wl:
        bgeu  s0, s1, tk_wend           ; the text ends the word
        lbu   t0, 0(s0)                 ; the next character
        bnez  s5, tk_inq                ; inside quotes
        li    t1, ' '                   ; separators end the word
        beq   t0, t1, tk_wend           ; ...
        li    t1, 9                     ; ...
        beq   t0, t1, tk_wend           ; ...
        li    t1, 13                    ; ...
        beq   t0, t1, tk_wend           ; ...
        li    t1, '|'                   ; so do the operators
        beq   t0, t1, tk_wend           ; ...
        li    t1, '<'                   ; ...
        beq   t0, t1, tk_wend           ; ...
        li    t1, '>'                   ; ...
        beq   t0, t1, tk_wend           ; ...
        li    t1, 39                    ; ' opens quotes
        beq   t0, t1, tk_open           ; ...
        li    t1, 34                    ; " too
        beq   t0, t1, tk_open           ; ...
        li    t1, '$'                   ; $ expands
        beq   t0, t1, tk_dol            ; ...
        li    t1, 92                    ; \ takes the next character as it is
        beq   t0, t1, tk_esc            ; ...
        j     tk_put                    ; anything else is text
tk_inq:
        beq   t0, s5, tk_close          ; the closing quote
        li    t1, 34                    ; inside "...", $ expands and \ escapes
        bne   s5, t1, tk_put            ; ('...' keeps everything)
        li    t1, '$'                   ; ...
        beq   t0, t1, tk_dol            ; ...
        li    t1, 92                    ; ...
        bne   t0, t1, tk_put            ; ...
tk_esc:
        addi  t2, s0, 1                 ; a character after the \?
        bgeu  t2, s1, tk_put            ; no: the \ itself
        mv    s0, t2                    ; yes: that character, whatever it is
        lbu   t0, 0(s0)                 ; ...
tk_put:
        la    t1, pool_end              ; room in the pool?
        bgeu  s2, t1, tk_full           ; no
        sb    t0, 0(s2)                 ; keep the character
        addi  s2, s2, 1                 ; ...
        addi  s0, s0, 1                 ; next
        j     tk_wl                     ; ...
tk_open:
        mv    s5, t0                    ; in quotes
        li    s6, 1                     ; (the word exists even if empty)
        addi  s0, s0, 1                 ; the quote itself is dropped
        j     tk_wl                     ; ...
tk_close:
        li    s5, 0                     ; out of quotes
        addi  s0, s0, 1                 ; ...
        j     tk_wl                     ; ...
tk_dol:
        mv    a0, s0                    ; $?, $$, $NAME
        mv    a1, s1                    ; ...
        mv    a2, s2                    ; ...
        call  expand                    ; a0 = cursor after, a1 = pool cursor (-1 full)
        bltz  a1, tk_full               ; ...
        mv    s0, a0                    ; ...
        mv    s2, a1                    ; ...
        j     tk_wl                     ; ...
tk_wend:
        bnez  s5, tk_quote              ; the text ended inside quotes
        ld    t4, 8(s3)                 ; the word's length
        sub   t4, s2, t4                ; ...
        sd    t4, 16(s3)                ; ...
        bnez  t4, tk_keep               ; not empty
        beqz  s6, tk_skip               ; empty and unquoted: no word
tk_keep:
        addi  s3, s3, 24                ; next entry
        addi  s4, s4, 1                 ; one more token
        j     tk_skip                   ; ...
tk_done:
        la    t4, g_ntok                ; the token count
        sd    s4, 0(t4)                 ; ...
        li    a0, 0                     ; fine
        j     tk_ret                    ; ...
tk_quote:
        li    a0, -2                    ; an open quote
        j     tk_ret                    ; ...
tk_full:
        li    a0, -1                    ; too much
tk_ret:
        ld    s6, 56(sp)                ; restore s0..s6
        ld    s5, 48(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s1, 16(sp)                ; ...
        ld    s0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 64                ; release the frame
        ret                             ; done

; expand(a0 = cursor at a $, a1 = end, a2 = pool cursor) -> a0 = cursor after
; what was expanded, a1 = pool cursor after the value (-1 if the pool is full).
; $? the last status, $$ our pid, $NAME a variable (nothing if unset); a $
; followed by anything else is itself.
; s0 = cursor, s1 = end, s2 = pool cursor, s3 = the name
expand:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; save s0..s3
        sd    s1, 16(sp)                ; ...
        sd    s2, 24(sp)                ; ...
        sd    s3, 32(sp)                ; ...
        addi  s0, a0, 1                 ; past the $
        mv    s1, a1                    ; ...
        mv    s2, a2                    ; ...
        bgeu  s0, s1, xp_lit            ; a $ at the end
        lbu   a0, 0(s0)                 ; what follows
        li    t0, '?'                   ; $?
        bne   a0, t0, xp_pid            ; ...
        addi  s0, s0, 1                 ; ...
        la    t0, g_stat                ; ...
        ld    a0, 0(t0)                 ; ...
        call  fmt_dec                   ; a0 = digits, a1 = length
        j     xp_copy                   ; ...
xp_pid:
        li    t0, '$'                   ; $$
        bne   a0, t0, xp_name           ; ...
        addi  s0, s0, 1                 ; ...
        la    t0, g_pid                 ; ...
        ld    a0, 0(t0)                 ; ...
        call  fmt_dec                   ; ...
        j     xp_copy                   ; ...
xp_name:
        call  is_nch                    ; a name starts with a letter or _
        li    t0, 2                     ; ...
        bne   a0, t0, xp_lit            ; anything else: a plain $
        mv    s3, s0                    ; s3 = the name
xp_nl:
        addi  s0, s0, 1                 ; letters, digits, _
        bgeu  s0, s1, xp_look           ; ...
        lbu   a0, 0(s0)                 ; ...
        call  is_nch                    ; ...
        bnez  a0, xp_nl                 ; ...
xp_look:
        mv    a0, s3                    ; its value
        sub   a1, s0, s3                ; ...
        call  var_find                  ; a0 = entry or 0
        li    a1, 0                     ; unset: nothing
        beqz  a0, xp_copy               ; ...
        ld    a1, 8(a0)                 ; value length
        addi  a0, a0, 32                ; value
        j     xp_copy                   ; ...
xp_lit:
        la    a0, w_dollar              ; a $ as it is
        li    a1, 1                     ; ...
xp_copy:
        li    t0, 0                     ; copy a1 bytes from a0 into the pool
        la    t2, pool_end              ; ...
xp_cl:
        bgeu  t0, a1, xp_done           ; ...
        bgeu  s2, t2, xp_full           ; no room
        add   t1, a0, t0                ; ...
        lbu   t1, 0(t1)                 ; ...
        sb    t1, 0(s2)                 ; ...
        addi  s2, s2, 1                 ; ...
        addi  t0, t0, 1                 ; ...
        j     xp_cl                     ; ...
xp_full:
        li    s2, -1                    ; ...
xp_done:
        mv    a0, s0                    ; results
        mv    a1, s2                    ; ...
        ld    s3, 32(sp)                ; restore s0..s3
        ld    s2, 24(sp)                ; ...
        ld    s1, 16(sp)                ; ...
        ld    s0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 40                ; release the frame
        ret                             ; done

; is_nch(a0 = character) -> a0 = 2 letter or _, 1 digit, 0 anything else
is_nch:
        li    t6, '_'                   ; ...
        beq   a0, t6, inc_2             ; ...
        ori   t5, a0, 32                ; letters, either case
        addi  t5, t5, -97               ; ...
        li    t6, 26                    ; ...
        bltu  t5, t6, inc_2             ; ...
        addi  t5, a0, -48               ; digits
        li    t6, 10                    ; ...
        bltu  t5, t6, inc_1             ; ...
        li    a0, 0                     ; ...
        ret                             ; ...
inc_1:
        li    a0, 1                     ; ...
        ret                             ; ...
inc_2:
        li    a0, 2                     ; ...
        ret                             ; ...

; var_find(a0 = name, a1 = length) -> a0 = its variable entry, or 0
var_find:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; save s0..s2
        sd    s1, 16(sp)                ; ...
        sd    s2, 24(sp)                ; ...
        mv    s0, a0                    ; s0 = name
        mv    s1, a1                    ; s1 = length
        li    s2, 0                     ; s2 = entry number
vfd_l:
        li    t0, NVAR                  ; all?
        bgeu  s2, t0, vfd_no            ; ...
        la    t1, vars                  ; the entry
        slli  t2, s2, 7                 ; (VSZ = 128)
        add   t1, t1, t2                ; ...
        sd    t1, 32(sp)                ; ...
        ld    t3, 0(t1)                 ; the same length? (free entries: 0)
        bne   t3, s1, vfd_n             ; ...
        addi  a0, t1, 16                ; the same name?
        mv    a1, s1                    ; ...
        mv    a2, s0                    ; ...
        mv    a3, s1                    ; ...
        call  str_eq                    ; ...
        beqz  a0, vfd_n                 ; ...
        ld    a0, 32(sp)                ; found
        j     vfd_ret                   ; ...
vfd_n:
        addi  s2, s2, 1                 ; next
        j     vfd_l                     ; ...
vfd_no:
        li    a0, 0                     ; none
vfd_ret:
        ld    s2, 24(sp)                ; restore s0..s2
        ld    s1, 16(sp)                ; ...
        ld    s0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 40                ; release the frame
        ret                             ; done

; =============================================================================
; Parser: tokens -> stages (command texts) and redirections
; =============================================================================

; st_init(a0 = stage entry): clear it
st_init:
        li    t0, 8                     ; 8 words
sti_l:
        sd    zero, 0(a0)               ; clear one
        addi  a0, a0, 8                 ; next
        addi  t0, t0, -1                ; one fewer
        bnez  t0, sti_l                 ; continue
        ret                             ; done

; parse() -> a0 = 0 (g_nst stages, 0 for an empty command), -1 syntax error,
; -2 a command text too long
parse:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; save s0..s4
        sd    s1, 16(sp)                ; ...
        sd    s2, 24(sp)                ; ...
        sd    s3, 32(sp)                ; ...
        sd    s4, 40(sp)                ; ...
        la    t0, g_nst                 ; nothing parsed yet
        sd    zero, 0(t0)               ; ...
        la    t0, g_inl                 ; no < file
        sd    zero, 0(t0)               ; ...
        la    t0, g_outl                ; no > file
        sd    zero, 0(t0)               ; ...
        li    s0, 0                     ; s0 = token index
        la    t0, g_ntok                ; s1 = token count
        ld    s1, 0(t0)                 ; ...
        li    s2, 0                     ; s2 = stage index
        la    s3, stg                   ; s3 = stage entry
        mv    a0, s3                    ; a clean first stage
        call  st_init                   ; ...
        la    s4, toks                  ; s4 = token entry
pa_loop:
        bge   s0, s1, pa_end            ; all tokens seen
        ld    t0, 0(s4)                 ; its type
        li    t1, TK_WORD               ; dispatch
        beq   t0, t1, pa_word           ; ...
        li    t1, TK_PIPE               ; ...
        beq   t0, t1, pa_pipe           ; ...
        li    t1, TK_LT                 ; ...
        beq   t0, t1, pa_lt             ; ...
        j     pa_gt                     ; > or >>
pa_word:
        ld    t0, 48(s3)                ; before the program name?
        bnez  t0, pa_add                ; no: an argument
        ld    a0, 8(s4)                 ; "run" is ignored
        ld    a1, 16(s4)                ; ...
        la    a2, w_run                 ; ...
        li    a3, 3                     ; ...
        call  str_eq                    ; ...
        bnez  a0, pa_next               ; ...
        ld    a0, 8(s4)                 ; "-n N": N threads
        ld    a1, 16(s4)                ; ...
        la    a2, w_n                   ; ...
        li    a3, 2                     ; ...
        call  str_eq                    ; ...
        bnez  a0, pa_optn               ; ...
        ld    a0, 8(s4)                 ; "-c N": pin to a core
        ld    a1, 16(s4)                ; ...
        la    a2, w_c                   ; ...
        li    a3, 2                     ; ...
        call  str_eq                    ; ...
        bnez  a0, pa_optc               ; ...
        ld    a0, 8(s4)                 ; "-m N": an arena of N MiB
        ld    a1, 16(s4)                ; ...
        la    a2, w_m                   ; ...
        li    a3, 2                     ; ...
        call  str_eq                    ; ...
        bnez  a0, pa_optm               ; ...
pa_add:
        ld    t2, 0(s3)                 ; t2 = text length so far
        ld    t3, 16(s4)                ; t3 = word length
        add   t4, t2, t3                ; with a space, does it fit?
        addi  t4, t4, 1                 ; ...
        li    t5, TXTMAX                ; ...
        bgtu  t4, t5, pa_long           ; no
        li    t6, STXT                  ; t5 = this stage's text
        mul   t6, s2, t6                ; ...
        la    t5, stxt                  ; ...
        add   t5, t5, t6                ; ...
        ld    t6, 48(s3)                ; the first word needs no space
        beqz  t6, pa_cp0                ; ...
        add   t6, t5, t2                ; a space before the others
        li    a0, ' '                   ; ...
        sb    a0, 0(t6)                 ; ...
        addi  t2, t2, 1                 ; ...
pa_cp0:
        ld    t6, 8(s4)                 ; t6 = source
        add   t4, t5, t2                ; t4 = destination
        add   t2, t2, t3                ; the new length
        sd    t2, 0(s3)                 ; ...
pa_cp:
        beqz  t3, pa_cpd                ; copied
        lbu   a0, 0(t6)                 ; one byte
        sb    a0, 0(t4)                 ; ...
        addi  t6, t6, 1                 ; next
        addi  t4, t4, 1                 ; ...
        addi  t3, t3, -1                ; ...
        j     pa_cp                     ; continue
pa_cpd:
        mv    a0, s3                    ; the word, quoted, into qtxt too
        mv    a1, s2                    ; ...
        ld    a2, 8(s4)                 ; ...
        ld    a3, 16(s4)                ; ...
        call  q_add                     ; ...
        ld    t0, 48(s3)                ; one more word
        addi  t0, t0, 1                 ; ...
        sd    t0, 48(s3)                ; ...
        j     pa_next                   ; next token
pa_optn:
        addi  s0, s0, 1                 ; the number follows
        addi  s4, s4, 24                ; ...
        bge   s0, s1, pa_syn            ; missing
        ld    t0, 0(s4)                 ; a word?
        li    t1, TK_WORD               ; ...
        bne   t0, t1, pa_syn            ; no
        ld    a0, 8(s4)                 ; its value
        ld    a1, 16(s4)                ; ...
        call  str_num                   ; a0 = N or -1
        bltz  a0, pa_syn                ; not a number
        sd    a0, 8(s3)                 ; ncores = N
        j     pa_next                   ; next token
pa_optc:
        addi  s0, s0, 1                 ; the number follows
        addi  s4, s4, 24                ; ...
        bge   s0, s1, pa_syn            ; missing
        ld    t0, 0(s4)                 ; a word?
        li    t1, TK_WORD               ; ...
        bne   t0, t1, pa_syn            ; no
        ld    a0, 8(s4)                 ; its value
        ld    a1, 16(s4)                ; ...
        call  str_num                   ; a0 = N or -1
        bltz  a0, pa_syn                ; not a number
        slli  a0, a0, 8                 ; mode |= 2 (pin) | core << 8
        ori   a0, a0, 2                 ; ...
        ld    t0, 16(s3)                ; ...
        or    a0, a0, t0                ; ...
        sd    a0, 16(s3)                ; ...
        j     pa_next                   ; next token
pa_optm:
        addi  s0, s0, 1                 ; the number follows
        addi  s4, s4, 24                ; ...
        bge   s0, s1, pa_syn            ; missing
        ld    t0, 0(s4)                 ; a word?
        li    t1, TK_WORD               ; ...
        bne   t0, t1, pa_syn            ; no
        ld    a0, 8(s4)                 ; its value
        ld    a1, 16(s4)                ; ...
        call  str_num                   ; a0 = N or -1
        blez  a0, pa_syn                ; not a number, or 0
        li    t0, 255                   ; at most 255 MiB
        bgtu  a0, t0, pa_syn            ; ...
        slli  a0, a0, 16                ; mode |= N << 16
        ld    t0, 16(s3)                ; ...
        or    a0, a0, t0                ; ...
        sd    a0, 16(s3)                ; ...
        j     pa_next                   ; next token
pa_pipe:
        ld    t0, 48(s3)                ; the stage must have a program
        beqz  t0, pa_syn                ; ...
        la    t0, g_outl                ; > belongs to the last stage only
        ld    t0, 0(t0)                 ; ...
        bnez  t0, pa_syn                ; ...
        addi  s2, s2, 1                 ; the next stage
        li    t0, MAXST                 ; at most 4
        bge   s2, t0, pa_syn            ; ...
        addi  s3, s3, 64                ; its entry
        mv    a0, s3                    ; clean
        call  st_init                   ; ...
        j     pa_next                   ; next token
pa_lt:
        bnez  s2, pa_syn                ; < belongs to the first stage only
        la    t0, g_inl                 ; only one
        ld    t0, 0(t0)                 ; ...
        bnez  t0, pa_syn                ; ...
        addi  s0, s0, 1                 ; the name follows
        addi  s4, s4, 24                ; ...
        bge   s0, s1, pa_syn            ; missing
        ld    t0, 0(s4)                 ; a word?
        li    t1, TK_WORD               ; ...
        bne   t0, t1, pa_syn            ; no
        ld    t0, 8(s4)                 ; keep it
        la    t1, g_inp                 ; ...
        sd    t0, 0(t1)                 ; ...
        ld    t0, 16(s4)                ; ...
        beqz  t0, pa_syn                ; an empty name
        la    t1, g_inl                 ; ...
        sd    t0, 0(t1)                 ; ...
        j     pa_next                   ; next token
pa_gt:
        li    t2, 1                     ; t2 = open mode: 1 write
        li    t1, TK_GT                 ; ...
        beq   t0, t1, pa_gt1            ; '>'
        li    t2, 2                     ; '>>': 2 append
pa_gt1:
        la    t0, g_outl                ; only one
        ld    t0, 0(t0)                 ; ...
        bnez  t0, pa_syn                ; ...
        addi  s0, s0, 1                 ; the name follows
        addi  s4, s4, 24                ; ...
        bge   s0, s1, pa_syn            ; missing
        ld    t0, 0(s4)                 ; a word?
        li    t1, TK_WORD               ; ...
        bne   t0, t1, pa_syn            ; no
        ld    t0, 8(s4)                 ; keep it
        la    t1, g_outp                ; ...
        sd    t0, 0(t1)                 ; ...
        la    t1, g_outm                ; and the mode
        sd    t2, 0(t1)                 ; ...
        ld    t0, 16(s4)                ; ...
        beqz  t0, pa_syn                ; an empty name
        la    t1, g_outl                ; ...
        sd    t0, 0(t1)                 ; ...
        j     pa_next                   ; next token
pa_next:
        addi  s0, s0, 1                 ; next token
        addi  s4, s4, 24                ; ...
        j     pa_loop                   ; continue
pa_end:
        ld    t0, 48(s3)                ; does the last stage have a program?
        bnez  t0, pa_ok                 ; yes
        bnez  s2, pa_syn                ; "a |": no
        la    t0, g_inl                 ; an empty line is fine, but
        ld    t0, 0(t0)                 ;   not "< f", "> f" or "&" alone
        bnez  t0, pa_syn                ; ...
        la    t0, g_outl                ; ...
        ld    t0, 0(t0)                 ; ...
        bnez  t0, pa_syn                ; ...
        li    a0, 0                     ; empty: g_nst stays 0
        j     pa_ret                    ; ...
pa_ok:
        addi  t0, s2, 1                 ; the number of stages
        la    t1, g_nst                 ; ...
        sd    t0, 0(t1)                 ; ...
        li    a0, 0                     ; fine
        j     pa_ret                    ; ...
pa_syn:
        li    a0, -1                    ; syntax error
        j     pa_ret                    ; ...
pa_long:
        li    a0, -2                    ; too long
pa_ret:
        ld    s4, 40(sp)                ; restore s0..s4
        ld    s3, 32(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s1, 16(sp)                ; ...
        ld    s0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 48                ; release the frame
        ret                             ; done

; =============================================================================
; Runner: open redirections, make pipes, spawn the stages, wait or record
; =============================================================================

; run_pipe(): run the parsed stages; sets g_stat
; s0 = handle for the next stage's stdin (0 = ours), s1 = > file handle
; (-1 none), s2 = error code, s3 = stage index, s4 = stage entry,
; s5 = read end of the new pipe (-1 none), s6 = the stage's stdout handle
run_pipe:
        addi  sp, sp, -64               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; save s0..s6
        sd    s1, 16(sp)                ; ...
        sd    s2, 24(sp)                ; ...
        sd    s3, 32(sp)                ; ...
        sd    s4, 40(sp)                ; ...
        sd    s5, 48(sp)                ; ...
        sd    s6, 56(sp)                ; ...
        la    t0, g_bg                  ; background: is there a free job slot?
        ld    t0, 0(t0)                 ; ...
        beqz  t0, rp_go                 ; foreground: no slot needed
        call  job_free_slot             ; a0 = slot or -1
        bltz  a0, rp_full               ; none
        la    t0, g_jslot               ; keep it
        sd    a0, 0(t0)                 ; ...
rp_go:
        call  out_flush                 ; our output before theirs
        li    s0, 0                     ; first stdin: ours
        li    s1, -1                    ; no > file yet
        li    s5, -1                    ; no pipe yet
        la    t0, g_inl                 ; < file?
        ld    a1, 0(t0)                 ; ...
        beqz  a1, rp_out                ; no
        la    t0, g_inp                 ; open it for reading
        ld    a0, 0(t0)                 ; ...
        li    a2, 0                     ; ...
        call  sys_open                  ; a0 = handle or < 0
        bltz  a0, rp_inerr              ; cannot
        mv    s0, a0                    ; the first stage reads it
rp_out:
        la    t0, g_outl                ; > or >> file?
        ld    a1, 0(t0)                 ; ...
        beqz  a1, rp_l0                 ; no
        la    t0, g_outp                ; open it for writing / appending
        ld    a0, 0(t0)                 ; ...
        la    t0, g_outm                ; ...
        ld    a2, 0(t0)                 ; ...
        call  sys_open                  ; a0 = handle or < 0
        bltz  a0, rp_outerr             ; cannot
        mv    s1, a0                    ; the last stage writes it
rp_l0:
        li    s3, 0                     ; the first stage
        la    s4, stg                   ; ...
rp_loop:
        la    t0, g_nst                 ; all stages started?
        ld    t0, 0(t0)                 ; ...
        bge   s3, t0, rp_started        ; yes
        addi  t0, t0, -1                ; the last stage?
        bge   s3, t0, rp_last           ; yes
        call  sys_pipe                  ; no: a pipe to the next one
        bltz  a0, rp_pipeerr            ; none
        mv    s5, a0                    ; s5 = read end (for the next stage)
        mv    s6, a1                    ; s6 = write end (this stage's stdout)
        j     rp_sp                     ; spawn
rp_last:
        li    s5, -1                    ; no pipe after the last stage
        li    s6, 1                     ; stdout: ours ...
        bltz  s1, rp_sp                 ; ...
        mv    s6, s1                    ; ... or the > file
rp_sp:
        mv    a0, s3                    ; a builtin here runs as `sh -c`
        call  stage_wrap                ; ...
        ld    a0, 8(s4)                 ; ncores
        ld    a1, 16(s4)                ; mode
        li    t0, STXT                  ; the command text
        mul   t0, s3, t0                ; ...
        la    a2, stxt                  ; ...
        add   a2, a2, t0                ; ...
        ld    a3, 0(s4)                 ; its length
        mv    a4, s0                    ; the child's 0
        mv    a5, s6                    ; the child's 1
        li    a6, 2                     ; the child's 2: our stderr
        call  sys_spawn                 ; a0 = pid or < 0
        bltz  a0, rp_spawnerr           ; failed
        sd    a0, 24(s4)                ; the pid
        li    t0, 1                     ; alive
        sd    t0, 40(s4)                ; ...
        beqz  s0, rp_c1                 ; our stdin: keep it
        mv    a0, s0                    ; otherwise the child has its own reference
        call  sys_close                 ; ...
rp_c1:
        li    s0, 0                     ; (closed)
        bltz  s5, rp_c2                 ; no pipe: the last stage
        mv    a0, s6                    ; close our write end
        call  sys_close                 ; ...
        mv    s0, s5                    ; the read end feeds the next stage
        li    s5, -1                    ; (handed over)
        j     rp_next                   ; ...
rp_c2:
        bltz  s1, rp_next               ; no > file
        mv    a0, s1                    ; close our copy of it
        call  sys_close                 ; ...
        li    s1, -1                    ; (closed)
rp_next:
        addi  s3, s3, 1                 ; next stage
        addi  s4, s4, 64                ; ...
        j     rp_loop                   ; continue
rp_started:
        la    t0, g_bg                  ; background?
        ld    t0, 0(t0)                 ; ...
        beqz  t0, rp_fg                 ; no
        call  job_add                   ; record it and print "[J] PID"
        la    t0, g_stat                ; status 0
        sd    zero, 0(t0)               ; ...
        j     rp_ret                    ; done
rp_fg:
        call  fg_wait                   ; wait for the job
        j     rp_ret                    ; done
rp_spawnerr:
        mv    s2, a0                    ; s2 = the error
        bltz  s5, rp_se1                ; a pipe made for this stage?
        mv    a0, s5                    ; close both ends
        call  sys_close                 ; ...
        mv    a0, s6                    ; ...
        call  sys_close                 ; ...
rp_se1:
        la    a0, m_sh                  ; "sh: PROG: reason"
        li    a1, 4                     ; ...
        call  err_str                   ; ...
        li    t0, STXT                  ; the program name: the first word
        mul   t0, s3, t0                ; ...
        la    a0, stxt                  ; ...
        add   a0, a0, t0                ; ...
        ld    a1, 0(s4)                 ; ...
        add   a1, a0, a1                ; ...
        call  arg_next                  ; a0 = word, a1 = length
        call  err_str                   ; ...
        la    a0, m_colon               ; ": "
        li    a1, 2                     ; ...
        call  err_str                   ; ...
        la    a0, m_nostart             ; the reason
        li    a1, m_nostart_e - m_nostart ; ...
        li    t0, -4                    ; no such program?
        bne   s2, t0, rp_r5             ; ...
        la    a0, m_noprog              ; ...
        li    a1, m_noprog_e - m_noprog ; ...
        j     rp_rp                     ; ...
rp_r5:
        li    t0, -5                    ; no free core?
        bne   s2, t0, rp_r6             ; ...
        la    a0, m_nocore              ; ...
        li    a1, m_nocore_e - m_nocore ; ...
        j     rp_rp                     ; ...
rp_r6:
        li    t0, -6                    ; out of memory?
        bne   s2, t0, rp_rp             ; ...
        la    a0, m_nomem               ; ...
        li    a1, m_nomem_e - m_nomem   ; ...
rp_rp:
        call  err_str                   ; ...
        j     rp_clean                  ; undo the rest
rp_pipeerr:
        li    s2, -1                    ; the error
        la    a0, m_pipe                ; "sh: cannot make a pipe"
        li    a1, m_pipe_e - m_pipe     ; ...
        call  err_str                   ; ...
rp_clean:
        beqz  s0, rp_cl1                ; an open stdin for this stage?
        mv    a0, s0                    ; close it
        call  sys_close                 ; ...
rp_cl1:
        bltz  s1, rp_cl2                ; the > file still open?
        mv    a0, s1                    ; close it
        call  sys_close                 ; ...
rp_cl2:
        mv    a0, s3                    ; kill and collect the stages started
        call  abort_stages              ; ...
        li    t0, 1                     ; status 1 ...
        li    t1, -4                    ; ... or 127 for "no such program"
        bne   s2, t1, rp_st             ; ...
        li    t0, 127                   ; ...
rp_st:
        la    t1, g_stat                ; ...
        sd    t0, 0(t1)                 ; ...
        j     rp_ret                    ; done
rp_inerr:
        la    t0, g_inp                 ; "sh: cannot open NAME"
        ld    a0, 0(t0)                 ; ...
        la    t0, g_inl                 ; ...
        ld    a1, 0(t0)                 ; ...
        call  cant_open                 ; (status 1)
        j     rp_ret                    ; done
rp_outerr:
        beqz  s0, rp_oe1                ; the < file is open?
        mv    a0, s0                    ; close it
        call  sys_close                 ; ...
rp_oe1:
        la    t0, g_outp                ; "sh: cannot open NAME"
        ld    a0, 0(t0)                 ; ...
        la    t0, g_outl                ; ...
        ld    a1, 0(t0)                 ; ...
        call  cant_open                 ; (status 1)
        j     rp_ret                    ; done
rp_full:
        la    a0, m_full                ; "sh: too many background jobs"
        li    a1, m_full_e - m_full     ; ...
        call  err_str                   ; ...
        li    t0, 1                     ; status 1
        la    t1, g_stat                ; ...
        sd    t0, 0(t1)                 ; ...
rp_ret:
        ld    s6, 56(sp)                ; restore s0..s6
        ld    s5, 48(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s1, 16(sp)                ; ...
        ld    s0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 64                ; release the frame
        ret                             ; done

; abort_stages(a0 = n): kill stages 0..n-1 and collect them
abort_stages:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; save s0..s2
        sd    s1, 16(sp)                ; ...
        sd    s2, 24(sp)                ; ...
        mv    s2, a0                    ; s2 = how many
        la    s0, stg                   ; s0 = stage entry
        li    s1, 0                     ; s1 = index
ab_loop:
        bge   s1, s2, ab_ret            ; all done
        ld    a0, 24(s0)                ; kill it
        call  sys_kill                  ; ...
ab_w:
        ld    a0, 24(s0)                ; collect it
        li    a1, 0                     ; (blocking)
        call  sys_wait                  ; ...
        li    t0, E_INTR                ; interrupted: wait again
        beq   a0, t0, ab_w              ; ...
        sd    zero, 40(s0)              ; no longer alive
        addi  s0, s0, 64                ; next
        addi  s1, s1, 1                 ; ...
        j     ab_loop                   ; continue
ab_ret:
        ld    s2, 24(sp)                ; restore s0..s2
        ld    s1, 16(sp)                ; ...
        ld    s0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 32                ; release the frame
        ret                             ; done

; each_alive(a0 = 1 kill / 0 interrupt): sys_kill or sys_signal every stage
; of the foreground job that has not been collected yet
each_alive:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; save s0..s2
        sd    s1, 16(sp)                ; ...
        sd    s2, 24(sp)                ; ...
        mv    s2, a0                    ; s2 = kill?
        la    s0, stg                   ; s0 = stage entry
        li    s1, 0                     ; s1 = index
ea_loop:
        la    t0, g_nst                 ; all stages?
        ld    t0, 0(t0)                 ; ...
        bge   s1, t0, ea_ret            ; yes
        ld    t0, 40(s0)                ; alive?
        beqz  t0, ea_next               ; no
        ld    a0, 24(s0)                ; its pid
        beqz  s2, ea_sig                ; interrupt it
        call  sys_kill                  ; or kill it
        j     ea_next                   ; ...
ea_sig:
        call  sys_signal                ; an interrupt (Ctrl-C) for it
ea_next:
        addi  s0, s0, 64                ; next
        addi  s1, s1, 1                 ; ...
        j     ea_loop                   ; continue
ea_ret:
        ld    s2, 24(sp)                ; restore s0..s2
        ld    s1, 16(sp)                ; ...
        ld    s0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 32                ; release the frame
        ret                             ; done

; fg_wait(): wait for every stage of the foreground job, then report the
; last stage's status. Waits for any child, so a background job that ends
; meanwhile is recorded in the job table instead.
; s0 = stages still running, s1 = status, s2 = pid
fg_wait:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; save s0..s2
        sd    s1, 16(sp)                ; ...
        sd    s2, 24(sp)                ; ...
        call  n_alive                   ; s0 = stages not collected yet
        mv    s0, a0                    ; ...
        call  own_con                   ; interactive: hand over the console
        beqz  a0, fw_loop               ; (a script leaves it to its parent)
        la    t0, g_nst                 ; to the last stage
        ld    t0, 0(t0)                 ; ...
        addi  t0, t0, -1                ; ...
        slli  t0, t0, 6                 ; ...
        la    t1, stg                   ; ...
        add   t1, t1, t0                ; ...
        ld    a0, 24(t1)                ; ...
        call  sys_setfg                 ; Ctrl-C now goes to it
fw_loop:
        beqz  s0, fw_done               ; all collected
        li    a0, 0                     ; any child
        li    a1, 0                     ; blocking
        call  sys_wait                  ; a0 = status, a1 = pid
        li    t0, E_INTR                ; we were interrupted?
        beq   a0, t0, fw_intr           ; pass it on to the job
        li    t0, -16                   ; an error (-1..-16)? fault statuses are
        blt   a0, t0, fw_got            ;   far more negative (bit 63)
        bgez  a0, fw_got                ; ...
        j     fw_gone                   ; no children left: stop waiting
fw_got:
        mv    s1, a0                    ; s1 = status
        mv    s2, a1                    ; s2 = pid
        la    t0, stg                   ; which stage is it?
        li    t1, 0                     ; ...
        la    t2, g_nst                 ; ...
        ld    t2, 0(t2)                 ; ...
fw_find:
        bge   t1, t2, fw_other          ; none: a background job
        ld    t3, 40(t0)                ; alive?
        beqz  t3, fw_fn                 ; no
        ld    t3, 24(t0)                ; this pid?
        bne   t3, s2, fw_fn             ; no
        sd    zero, 40(t0)              ; collected
        sd    s1, 32(t0)                ; its status
        addi  s0, s0, -1                ; one fewer running
        srli  t3, s1, 62                ; killed (bit 62)?
        andi  t3, t3, 1                 ; ...
        beqz  t3, fw_loop               ; no
        li    a0, 1                     ; yes: kill the rest of the job
        call  each_alive                ; ...
        j     fw_loop                   ; and collect them
fw_fn:
        addi  t0, t0, 64                ; next stage
        addi  t1, t1, 1                 ; ...
        j     fw_find                   ; ...
fw_other:
        mv    a0, s2                    ; a background stage ended
        mv    a1, s1                    ; ...
        call  job_reaped                ; record it
        j     fw_loop                   ; keep waiting
fw_intr:
        li    t0, 1                     ; remember (scripts stop)
        la    t1, g_intr                ; ...
        sd    t0, 0(t1)                 ; ...
        li    a0, 0                     ; interrupt every running stage
        call  each_alive                ; ...
        j     fw_loop                   ; keep waiting
fw_gone:
        la    t0, stg                   ; nothing left to wait for:
        li    t1, MAXST                 ;   mark every stage collected
fw_g1:
        sd    zero, 40(t0)              ; ...
        addi  t0, t0, 64                ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, fw_g1                 ; ...
fw_done:
        call  own_con                   ; take the console back
        beqz  a0, fw_rep                ; ...
        la    t0, g_pid                 ; ...
        ld    a0, 0(t0)                 ; ...
        call  sys_setfg                 ; ...
fw_rep:
        la    t0, g_nst                 ; the last stage's status
        ld    t0, 0(t0)                 ; ...
        addi  t0, t0, -1                ; ...
        slli  t0, t0, 6                 ; ...
        la    t1, stg                   ; ...
        add   t1, t1, t0                ; ...
        ld    a0, 32(t1)                ; ...
        call  report                    ; print it, set $?
        ld    s2, 24(sp)                ; restore s0..s2
        ld    s1, 16(sp)                ; ...
        ld    s0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 32                ; release the frame
        ret                             ; done

