; =============================================================================
; sh.s: the StrataOS shell
; =============================================================================
;
;   sh                    interactive when standard input is the console:
;                         prompt, line editing, history, Tab completion
;   sh -i                 interactive even if standard input is a pipe (term)
;   sh -l                 login shell: run the script `rc` first (if it
;                         exists); at end of input, halt the machine
;   sh -c "ls | wc"       run one command line, exit with its status
;   sh FILE               run each line of FILE (at most 64 KiB), then exit
;   (otherwise: lines from standard input, no prompt, no editing)
;
; Line syntax:
;   a ; b                 run a, then b
;   \x                    the character x as it is (outside '...')
;   a && b    a || b      run b only if a succeeded / failed ($? = 0 / not 0)
;   a & b                 run a in the background: "[J] PID", later "[J] done  a"
;   a | b | c | d         a pipeline of up to 4 stages
;   < file  > file  >> file   redirect stdin of the first stage / stdout of
;                         the last stage (read, write, append)
;   'text'  "text"        one word; $ is expanded inside "..." but not '...'
;   $?  $$  $NAME         the last status, the shell's pid, a variable (set)
;   -n N prog             run prog as N threads on N cores (also run -n N prog)
;   -c N prog             pin prog to core N
;   -m N prog             give prog an arena of N MiB (default 1; at most 255)
;   run prog              the same as `prog`
;   time cmd              run cmd, then print the wall time it took
;   # comment             the rest of the line is ignored
; $? is the exit code, 130 when killed by Ctrl-C, 128 + cause after a fault.
; A non-zero status shows in the prompt: "[130] strata$ ".
;
; The current tag path: `cd TAG` (or a/b, -x, /x/y, .., nothing for "/") and
; `pwd`. The file server keeps it, per process (a child starts in its
; parent's), and reads every name without a leading "/" under it: `ls` lists
; it, `cat f` opens f if it carries its tags, `echo hi > f` gives f its tags.
; Away from "/" the prompt shows it: "strata:/src/demo$ ".
;
; Line editing (the console in raw mode while a line is being typed):
;   Left/Right Ctrl-B/F  move        Home/End Ctrl-A/E   start / end
;   Backspace            erase left  Delete              erase under the cursor
;   Ctrl-K / Ctrl-U      erase to the end / to the start
;   Ctrl-W               erase the word before the cursor
;   Up/Down Ctrl-P/N     history (32 lines)      Ctrl-L  clear the screen
;   Tab                  complete a command (first word: builtins and programs
;                        on the disk) or a file name (and facets, as tag/, in
;                        a tag path or under the current one); a second Tab
;                        lists the candidates in columns
;   Ctrl-D               on an empty line: end of input (exit)
;   Ctrl-C               abandon the line (it arrives as an interrupt: the
;                        shell catches interrupts, so the read returns -2)
; The redraws use the terminal subset of the spec (ESC [ K, ESC [ n D).
;
; How a command runs: each stage's command text ("prog args", with the
; redirections and operators taken out, quotes removed and $ expanded) goes
; to the process server with sys_spawn, together with the three handles that
; become the child's 0, 1 and 2 (the shell's own, pipe ends from sys_pipe, or
; files from sys_open). The shell closes its copies right after each spawn
; (the child holds its own references), gives the console to the last stage
; with sys_setfg, and waits for every stage; if it is interrupted (Ctrl-C)
; while it waits, it SIGNALs the job. A builtin that is a pipeline stage or
; runs in the background is run by a child `sh -c`.
;
; Where things live: the history (32 x 256 bytes) and the scripts being run
; (one 64 KiB region per nesting level) are in the shell's arena, far memory
; reached with transfers (tag tg1); the D-LS holds the lines being worked on.

