; job_free_slot() -> a0 = a free job slot, or -1
job_free_slot:
        la    t0, jtab                  ; t0 = entry
        li    a0, 0                     ; a0 = slot
jfs_l:
        li    t1, NJOB                  ; all taken?
        bge   a0, t1, jfs_none          ; ...
        ld    t1, 0(t0)                 ; used?
        beqz  t1, jfs_ret               ; no: this one
        addi  t0, t0, JSZ               ; next
        addi  a0, a0, 1                 ; ...
        j     jfs_l                     ; ...
jfs_none:
        li    a0, -1                    ; none
jfs_ret:
        ret                             ; done

; job_add(): record the stages just started in slot g_jslot; print "[J] PID"
job_add:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; save s0, s1
        sd    s1, 16(sp)                ; ...
        la    t0, g_jslot               ; s0 = slot
        ld    s0, 0(t0)                 ; ...
        li    t0, JSZ                   ; s1 = its entry
        mul   t0, s0, t0                ; ...
        la    s1, jtab                  ; ...
        add   s1, s1, t0                ; ...
        li    t0, 1                     ; used
        sd    t0, 0(s1)                 ; ...
        la    t0, g_nst                 ; t2 = stages
        ld    t2, 0(t0)                 ; ...
        sd    t2, 8(s1)                 ; ...
        sd    zero, 16(s1)              ; no status yet
        li    t0, 1                     ; mask: all stages running
        sll   t0, t0, t2                ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, 56(s1)                ; ...
        la    t0, stg                   ; copy the pids
        addi  t1, s1, 24                ; ...
        mv    t3, t2                    ; ...
ja_pid:
        ld    t4, 24(t0)                ; ...
        sd    t4, 0(t1)                 ; ...
        addi  t0, t0, 64                ; ...
        addi  t1, t1, 8                 ; ...
        addi  t3, t3, -1                ; ...
        bnez  t3, ja_pid                ; ...
        la    t0, g_segp                ; the command text, without spaces around it
        ld    t0, 0(t0)                 ; t0 = cursor
        la    t1, g_segl                ; ...
        ld    t1, 0(t1)                 ; ...
        add   t1, t0, t1                ; t1 = end
ja_sp:
        bgeu  t0, t1, ja_tr             ; ...
        lbu   t3, 0(t0)                 ; ...
        li    t4, ' '                   ; ...
        bne   t3, t4, ja_tr             ; ...
        addi  t0, t0, 1                 ; ...
        j     ja_sp                     ; ...
ja_tr:
        bgeu  t0, t1, ja_cp0            ; and trailing ones
        lbu   t3, -1(t1)                ; ...
        li    t4, ' '                   ; ...
        bne   t3, t4, ja_cp0            ; ...
        addi  t1, t1, -1                ; ...
        j     ja_tr                     ; ...
ja_cp0:
        sub   t3, t1, t0                ; t3 = its length, at most JCMD
        li    t4, JCMD                  ; ...
        bleu  t3, t4, ja_cl             ; ...
        mv    t3, t4                    ; ...
ja_cl:
        sd    t3, 64(s1)                ; ...
        addi  t1, s1, 72                ; copy it
ja_cp:
        beqz  t3, ja_print              ; copied
        lbu   t4, 0(t0)                 ; ...
        sb    t4, 0(t1)                 ; ...
        addi  t0, t0, 1                 ; ...
        addi  t1, t1, 1                 ; ...
        addi  t3, t3, -1                ; ...
        j     ja_cp                     ; ...
ja_print:
        li    a0, '['                   ; "[J] PID"
        call  out_chr                   ; ...
        addi  a0, s0, 1                 ; job numbers start at 1
        call  out_dec                   ; ...
        la    a0, m_rb                  ; ...
        li    a1, 2                     ; ...
        call  out_str                   ; ...
        mv    a0, s1                    ; the last stage's pid
        call  job_lastpid               ; ...
        call  out_dec                   ; ...
        call  out_nl                    ; ...
        ld    s1, 16(sp)                ; restore s0, s1
        ld    s0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 24                ; release the frame
        ret                             ; done

; job_lastpid(a0 = job entry) -> a0 = the pid of its last stage
job_lastpid:
        ld    t0, 8(a0)                 ; stages
        addi  t0, t0, -1                ; the last one
        slli  t0, t0, 3                 ; ...
        add   t0, a0, t0                ; ...
        ld    a0, 24(t0)                ; ...
        ret                             ; done

; jb_clear(a0 = job entry, a1 = stage, a2 = status): that stage has ended
jb_clear:
        li    t0, 1                     ; its bit
        sll   t0, t0, a1                ; ...
        ld    t1, 56(a0)                ; clear it in the mask
        and   t2, t1, t0                ; (only if set)
        xor   t1, t1, t2                ; ...
        sd    t1, 56(a0)                ; ...
        ld    t2, 8(a0)                 ; the last stage?
        addi  t2, t2, -1                ; ...
        bne   a1, t2, jbc_ret           ; no
        sd    a2, 16(a0)                ; its status is the job's
jbc_ret:
        ret                             ; done

; job_reaped(a0 = pid, a1 = status) -> a0 = 1 if it was a background stage
job_reaped:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; save s0..s3
        sd    s1, 16(sp)                ; ...
        sd    s2, 24(sp)                ; ...
        sd    s3, 32(sp)                ; ...
        mv    s2, a0                    ; s2 = pid
        mv    s3, a1                    ; s3 = status
        la    s0, jtab                  ; s0 = job entry
        li    s1, 0                     ; s1 = job index
jr_job:
        li    t0, NJOB                  ; all jobs?
        bge   s1, t0, jr_no             ; yes: not ours
        ld    t0, 0(s0)                 ; used?
        beqz  t0, jr_nj                 ; no
        li    t1, 0                     ; t1 = stage
jr_st:
        ld    t0, 8(s0)                 ; all stages?
        bge   t1, t0, jr_nj             ; yes
        ld    t2, 56(s0)                ; still running?
        srl   t2, t2, t1                ; ...
        andi  t2, t2, 1                 ; ...
        beqz  t2, jr_ns                 ; no
        slli  t2, t1, 3                 ; its pid
        add   t2, s0, t2                ; ...
        ld    t2, 24(t2)                ; ...
        bne   t2, s2, jr_ns             ; not this one
        mv    a0, s0                    ; found: it has ended
        mv    a1, t1                    ; ...
        mv    a2, s3                    ; ...
        call  jb_clear                  ; ...
        li    a0, 1                     ; ours
        j     jr_ret                    ; ...
jr_ns:
        addi  t1, t1, 1                 ; next stage
        j     jr_st                     ; ...
jr_nj:
        addi  s0, s0, JSZ               ; next job
        addi  s1, s1, 1                 ; ...
        j     jr_job                    ; ...
jr_no:
        li    a0, 0                     ; not ours
jr_ret:
        ld    s3, 32(sp)                ; restore s0..s3
        ld    s2, 24(sp)                ; ...
        ld    s1, 16(sp)                ; ...
        ld    s0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 40                ; release the frame
        ret                             ; done

; poll_jobs(): collect background stages that have ended (without
; blocking); report and free every job whose stages have all ended
poll_jobs:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; save s0..s2
        sd    s1, 16(sp)                ; ...
        sd    s2, 24(sp)                ; ...
        la    s1, jtab                  ; s1 = job entry
        li    s0, 0                     ; s0 = job index
pj_job:
        li    t0, NJOB                  ; all jobs?
        bge   s0, t0, pj_ret            ; yes
        ld    t0, 0(s1)                 ; used?
        beqz  t0, pj_nj                 ; no
        li    s2, 0                     ; s2 = stage
pj_st:
        ld    t0, 8(s1)                 ; all stages?
        bge   s2, t0, pj_chk            ; yes
        ld    t1, 56(s1)                ; still running?
        srl   t1, t1, s2                ; ...
        andi  t1, t1, 1                 ; ...
        beqz  t1, pj_ns                 ; no
        slli  t0, s2, 3                 ; ask without blocking
        add   t0, s1, t0                ; ...
        ld    a0, 24(t0)                ; ...
        li    a1, 1                     ; ...
        call  sys_wait                  ; a0 = status, -3 still running
        li    t0, -3                    ; still running?
        beq   a0, t0, pj_ns             ; ...
        li    t0, E_INTR                ; interrupted: ask next time
        beq   a0, t0, pj_ns             ; ...
        li    t0, -16                   ; another error (no such child):
        blt   a0, t0, pj_rec            ;   count it as ended with status 0
        bgez  a0, pj_rec                ; ...
        li    a0, 0                     ; ...
pj_rec:
        mv    a2, a0                    ; it has ended
        mv    a0, s1                    ; ...
        mv    a1, s2                    ; ...
        call  jb_clear                  ; ...
pj_ns:
        addi  s2, s2, 1                 ; next stage
        j     pj_st                     ; ...
pj_chk:
        ld    t0, 56(s1)                ; anything still running?
        bnez  t0, pj_nj                 ; yes
        mv    a0, s1                    ; no: report the job and free it
        mv    a1, s0                    ; ...
        call  job_done                  ; ...
pj_nj:
        addi  s1, s1, JSZ               ; next job
        addi  s0, s0, 1                 ; ...
        j     pj_job                    ; ...
pj_ret:
        ld    s2, 24(sp)                ; restore s0..s2
        ld    s1, 16(sp)                ; ...
        ld    s0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 32                ; release the frame
        ret                             ; done

; job_done(a0 = job entry, a1 = slot): "[J] done  CMD" (or exit N / killed
; / fault), then free the entry
job_done:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; save s0, s1
        sd    s1, 16(sp)                ; ...
        mv    s0, a0                    ; s0 = entry
        mv    s1, a1                    ; s1 = slot
        li    a0, '['                   ; "[J] "
        call  out_chr                   ; ...
        addi  a0, s1, 1                 ; ...
        call  out_dec                   ; ...
        la    a0, m_rb                  ; ...
        li    a1, 2                     ; ...
        call  out_str                   ; ...
        ld    t0, 16(s0)                ; the status
        bnez  t0, jd_bad                ; not 0
        la    a0, m_done                ; "done"
        li    a1, m_done_e - m_done     ; ...
        call  out_str                   ; ...
        j     jd_cmd                    ; ...
jd_bad:
        bltz  t0, jd_fault              ; bit 63: a fault
        srli  t1, t0, 62                ; bit 62: killed
        bnez  t1, jd_kill               ; ...
        la    a0, m_jexit               ; "exit N"
        li    a1, m_jexit_e - m_jexit   ; ...
        call  out_str                   ; ...
        ld    a0, 16(s0)                ; ...
        call  out_dec                   ; ...
        j     jd_cmd                    ; ...
jd_kill:
        la    a0, m_killed              ; "killed"
        li    a1, m_killed_e - m_killed ; ...
        call  out_str                   ; ...
        j     jd_cmd                    ; ...
jd_fault:
        la    a0, m_jfault              ; "fault"
        li    a1, m_jfault_e - m_jfault ; ...
        call  out_str                   ; ...
jd_cmd:
        la    a0, m_2sp                 ; "  CMD"
        li    a1, 2                     ; ...
        call  out_str                   ; ...
        addi  a0, s0, 72                ; ...
        ld    a1, 64(s0)                ; ...
        call  out_str                   ; ...
        call  out_nl                    ; ...
        sd    zero, 0(s0)               ; the slot is free
        ld    s1, 16(sp)                ; restore s0, s1
        ld    s0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 32                ; release the frame
        ret                             ; done
; n_alive() -> a0 = stages of the foreground job not collected yet
n_alive:
        la    t0, g_nst                 ; t1 = stages
        ld    t1, 0(t0)                 ; ...
        la    t2, stg                   ; ...
        li    a0, 0                     ; ...
nal_l:
        beqz  t1, nal_r                 ; ...
        ld    t3, 40(t2)                ; alive?
        add   a0, a0, t3                ; ...
        addi  t2, t2, 64                ; ...
        addi  t1, t1, -1                ; ...
        j     nal_l                     ; ...
nal_r:
        ret                             ; done

; stage_wrap(a0 = stage index): a stage whose program is a builtin (in a
; pipeline or in the background) becomes `sh -c 'WORD' 'WORD'...`, quoted so
; that the child shell sees the same words (when it fits)
stage_wrap:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; save s0..s2
        sd    s1, 16(sp)                ; ...
        sd    s2, 24(sp)                ; ...
        li    t0, STXT                  ; s0 = the stage's text
        mul   s2, a0, t0                ; (s2 = its offset in stxt / qtxt)
        la    s0, stxt                  ; ...
        add   s0, s0, s2                ; ...
        slli  t1, a0, 6                 ; s1 = the stage
        la    s1, stg                   ; ...
        add   s1, s1, t1                ; ...
        mv    a0, s0                    ; a builtin?
        ld    a1, 0(s1)                 ; ...
        call  bi_lookup                 ; ...
        beqz  a0, swr_ret               ; no
        ld    t0, 56(s1)                ; the quoted text
        addi  t1, t0, 6                 ; with "sh -c " in front: does it fit?
        li    t2, TXTMAX                ; ...
        bgtu  t1, t2, swr_ret           ; no: it will fail to start
        sd    t1, 0(s1)                 ; the new length
        mv    a0, s0                    ; "sh -c "
        la    a1, w_shc                 ; ...
        li    a2, 6                     ; ...
        call  bcopy                     ; ...
        addi  a0, s0, 6                 ; then the quoted words
        la    a1, qtxt                  ; ...
        add   a1, a1, s2                ; ...
        ld    a2, 56(s1)                ; ...
        call  bcopy                     ; ...
swr_ret:
        ld    s2, 24(sp)                ; restore s0..s2
        ld    s1, 16(sp)                ; ...
        ld    s0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 32                ; release the frame
        ret                             ; done

; q_add(a0 = stage entry, a1 = stage index, a2 = word, a3 = its length):
; append the word to the stage's quoted text as 'WORD' (a ' inside becomes
; '"'"'), after a space unless it is the first word
q_add:
        ld    t0, 56(a0)                ; t0 = quoted length so far
        li    t1, STXT                  ; t1 = the stage's quoted text
        mul   t1, a1, t1                ; ...
        la    t2, qtxt                  ; ...
        add   t1, t1, t2                ; ...
        li    t6, STXT - 8              ; t6 = the room (a word may add 5 + 2 bytes)
        ld    t2, 48(a0)                ; not the first word: a space
        beqz  t2, qad_o                 ; ...
        li    t3, ' '                   ; ...
        jal   t5, qad_b                 ; ...
qad_o:
        li    t3, 39                    ; the opening '
        jal   t5, qad_b                 ; ...
qad_l:
        beqz  a3, qad_c                 ; the whole word
        lbu   t3, 0(a2)                 ; a character
        addi  a2, a2, 1                 ; ...
        addi  a3, a3, -1                ; ...
        li    t4, 39                    ; a '?
        beq   t3, t4, qad_q             ; ...
        jal   t5, qad_b                 ; anything else as it is
        j     qad_l                     ; ...
qad_q:
        jal   t5, qad_b                 ; ' then "'" then ' : close, a quoted ', reopen
        li    t3, 34                    ; ...
        jal   t5, qad_b                 ; ...
        li    t3, 39                    ; ...
        jal   t5, qad_b                 ; ...
        li    t3, 34                    ; ...
        jal   t5, qad_b                 ; ...
        li    t3, 39                    ; ...
        jal   t5, qad_b                 ; ...
        j     qad_l                     ; ...
qad_c:
        li    t3, 39                    ; the closing '
        jal   t5, qad_b                 ; ...
        sd    t0, 56(a0)                ; the new length
        ret                             ; done
qad_b:
        bgeu  t0, t6, qad_full          ; (a local helper, link in t5) one byte, if it fits
        add   t4, t1, t0                ; ...
        sb    t3, 0(t4)                 ; ...
qad_full:
        addi  t0, t0, 1                 ; counted even when it does not fit
        jr    t5                        ; (so stage_wrap sees the overflow)

