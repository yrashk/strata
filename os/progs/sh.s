; Stage entry (64 bytes): 0 text length, 8 ncores, 16 spawn mode, 24 pid,
; 32 exit status, 40 alive (not yet waited for), 48 words, 56 length of the
; quoted text (qtxt; > STXT if it did not fit).
; Job entry (JSZ bytes): 0 used, 8 stages, 16 status of the last stage,
; 24 pids (4 x 8), 56 mask of stages still running, 64 text length,
; 72 command text (JCMD bytes).
; Token entry (24 bytes): 0 type, 8 text address, 16 text length.
; Candidate (8 bytes): address | length << 32.

