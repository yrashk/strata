; =============================================================================
; Start-up: arguments, then -c, FILE or the input loop
; =============================================================================
main:
        call  sys_init                  ; handles and arguments
        call  sys_pid                   ; remember our pid (for sys_setfg)
        la    t0, g_pid                 ; ...
        sd    a0, 0(t0)                 ; ...
        call  cwd_get                   ; the current tag path (for the prompt)
        li    a0, 1                     ; the shell catches interrupts:
        call  sys_catch                 ;   blocking calls return -2 instead
        li    a0, 0                     ; is standard input the console?
        call  sys_hdesc                 ; a0 = server register << 32 | id, or -1
        srli  a0, a0, 32                ; the server: 3 = tty
        addi  a0, a0, -3                ; ...
        seqz  a0, a0                    ; ...
        la    t0, g_con                 ; ...
        sd    a0, 0(t0)                 ; ...
        la    a0, argbuf                ; our arguments ...
        call  sys_args                  ; ... a0 = their length
        la    s0, argbuf                ; s0 = cursor
        add   s1, s0, a0                ; s1 = end
        li    s4, 0                     ; s4 = 1 once -i is seen
mn_arg:
        mv    a0, s0                    ; the next argument
        mv    a1, s1                    ; ...
        call  arg_next                  ; a0 = word, a1 = length, a2 = cursor after
        beqz  a1, mn_inter              ; no more: read standard input
        mv    s0, a2                    ; advance
        mv    s2, a0                    ; s2 = the word
        mv    s3, a1                    ; s3 = its length
        la    a2, w_l                   ; "-l"?
        li    a3, 2                     ; ...
        call  str_eq                    ; ...
        beqz  a0, mn_i                  ; no
        li    t0, 1                     ; yes: a login shell
        la    t1, g_login               ; ...
        sd    t0, 0(t1)                 ; ...
        j     mn_arg                    ; next argument
mn_i:
        mv    a0, s2                    ; "-i"?
        mv    a1, s3                    ; ...
        la    a2, w_i                   ; ...
        li    a3, 2                     ; ...
        call  str_eq                    ; ...
        beqz  a0, mn_c                  ; no
        li    s4, 1                     ; yes: interactive whatever stdin is
        j     mn_arg                    ; next argument
mn_c:
        mv    a0, s2                    ; "-c"?
        mv    a1, s3                    ; ...
        la    a2, w_c                   ; ...
        li    a3, 2                     ; ...
        call  str_eq                    ; ...
        bnez  a0, mn_cmd                ; yes: one command line
        mv    a0, s2                    ; otherwise a script FILE
        mv    a1, s3                    ; ...
        call  run_file                  ; a0 = 0, or < 0 if it cannot be read
        bgez  a0, mn_exit               ; ran: exit with the last status
        mv    a0, s2                    ; "sh: cannot open FILE"
        mv    a1, s3                    ; ...
        call  cant_open                 ; ...
        li    a0, 1                     ; exit code
        call  sys_exit                  ; end the process
mn_cmd:
        bgeu  s0, s1, mn_cq             ; the command is the rest of the text:
        lbu   t0, 0(s0)                 ;   skip the spaces before it
        li    t1, ' '                   ;   ...
        bne   t0, t1, mn_cq             ;   ...
        addi  s0, s0, 1                 ;   ...
        j     mn_cmd                    ;   ...
mn_cq:
        sub   t2, s1, s0                ; enclosed in double quotes?
        li    t3, 2                     ; (at least two characters)
        blt   t2, t3, mn_crun           ; no
        lbu   t0, 0(s0)                 ; first character
        li    t1, 34                    ; '"'
        bne   t0, t1, mn_crun           ; no
        lbu   t0, -1(s1)                ; last character
        bne   t0, t1, mn_crun           ; no
        addi  s0, s0, 1                 ; yes: drop them
        addi  s1, s1, -1                ; ...
mn_crun:
        mv    a0, s0                    ; run the line
        sub   a1, s1, s0                ; ...
        call  run_line                  ; ...
mn_exit:
        la    t0, g_stat                ; exit with the last status
        ld    a0, 0(t0)                 ; ...
        call  sys_exit                  ; end the process
mn_inter:
        la    t0, g_con                 ; interactive: stdin is the console, or -i
        ld    t0, 0(t0)                 ; ...
        or    t0, t0, s4                ; ...
        la    t1, g_inter               ; ...
        sd    t0, 0(t1)                 ; ...
        call  own_con                   ; do we own the console?
        beqz  a0, mn_rc                 ; no
        la    t0, g_pid                 ; the console's Ctrl-C comes to us
        ld    a0, 0(t0)                 ; ...
        call  sys_setfg                 ; ...
mn_rc:
        la    t0, g_login               ; a login shell runs rc first
        ld    t0, 0(t0)                 ; ...
        beqz  t0, lp_loop               ; not a login shell
        la    a0, w_rc                  ; does rc exist?
        li    a1, 7                     ; ...
        call  sys_stat                  ; a0 = size or < 0
        bltz  a0, lp_loop               ; no
        la    a0, w_rc                  ; run it
        li    a1, 7                     ; ...
        call  run_file                  ; ...
lp_loop:
        call  poll_jobs                 ; report finished background jobs
        la    t0, g_intr                ; a fresh line: nothing interrupted yet
        sd    zero, 0(t0)               ; ...
        call  sys_intr                  ; (and forget old interrupts)
        la    t0, g_inter               ; interactive?
        ld    t0, 0(t0)                 ; ...
        beqz  t0, lp_plain              ; no: plain lines
        call  read_line                 ; a0 = length (line in ebuf), -1 end, -2 interrupted
        li    t0, E_INTR                ; Ctrl-C?
        beq   a0, t0, lp_loop           ; yes: the line is abandoned
        bltz  a0, lp_eof                ; end of input
        mv    s0, a0                    ; s0 = length
        call  hist_add                  ; remember the line
        la    a0, ebuf                  ; run it
        mv    a1, s0                    ; ...
        call  run_line                  ; ...
        j     lp_loop                   ; next line
lp_plain:
        la    a0, lbufs                 ; a line of standard input (window 0)
        li    a1, SLMAX                 ; ...
        call  in_line                   ; a0 = length, -1 end, -2 interrupted
        li    t0, E_INTR                ; Ctrl-C?
        beq   a0, t0, lp_loop           ; yes: the next line
        bltz  a0, lp_eof                ; end of input
        mv    a1, a0                    ; run it
        la    a0, lbufs                 ; ...
        call  run_line                  ; ...
        j     lp_loop                   ; next line
lp_eof:
        la    t0, g_login               ; a login shell stops the machine
        ld    t0, 0(t0)                 ; ...
        beqz  t0, lp_quit               ; others just end
        call  sys_halt                  ; does not return
lp_quit:
        la    t0, g_inter               ; interactive: exit 0
        ld    t0, 0(t0)                 ; ...
        li    a0, 0                     ; ...
        bnez  t0, lp_q2                 ; ...
        la    t0, g_stat                ; otherwise the last status
        ld    a0, 0(t0)                 ; ...
lp_q2:
        call  sys_exit                  ; end the process

; own_con() -> a0 = 1 if the shell hands the console to its jobs (interactive
; with standard input on the console)
own_con:
        la    t0, g_inter               ; interactive
        ld    a0, 0(t0)                 ; ...
        la    t0, g_con                 ; and the console
        ld    t0, 0(t0)                 ; ...
        and   a0, a0, t0                ; ...
        ret                             ; done

; prompt(): "strata$ ", or "[N] strata$ " after a non-zero status; away from
; the root it shows the current tag path: "strata:/src/demo$ "
prompt:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        la    t0, g_stat                ; the last status
        ld    t0, 0(t0)                 ; ...
        beqz  t0, pr_p                  ; zero: nothing to show
        li    a0, '['                   ; "[N] "
        call  out_chr                   ; ...
        la    t0, g_stat                ; ...
        ld    a0, 0(t0)                 ; ...
        call  out_dec                   ; ...
        la    a0, m_rb                  ; ...
        li    a1, 2                     ; ...
        call  out_str                   ; ...
pr_p:
        la    t0, g_cwdl                ; away from the root?
        ld    t0, 0(t0)                 ; (the root is "/": one byte)
        li    t1, 1                     ; ...
        bgtu  t0, t1, pr_cwd            ; yes
        la    a0, m_prompt              ; "strata$ "
        li    a1, m_prompt_e - m_prompt ; ...
        call  out_str                   ; ...
        j     pr_ret                    ; ...
pr_cwd:
        la    a0, m_pcwd                ; "strata:/a/b$ "
        li    a1, 7                     ; ...
        call  out_str                   ; ...
        la    a0, g_cwd                 ; ...
        la    t0, g_cwdl                ; ...
        ld    a1, 0(t0)                 ; ...
        call  out_str                   ; ...
        la    a0, m_pend                ; ...
        li    a1, 2                     ; ...
        call  out_str                   ; ...
pr_ret:
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 16                ; release the frame
        ret                             ; done

