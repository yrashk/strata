; code_of(a0 = exit status) -> a0 = $?: the code; 130 if killed; 128 + cause
; after a fault
code_of:
        bgez  a0, co_nf                 ; bit 63 clear: not a fault
        andi  a0, a0, 255               ; the cause
        addi  a0, a0, 128               ; ...
        ret                             ; done
co_nf:
        srli  t0, a0, 62                ; killed (bit 62)?
        beqz  t0, co_ret                ; no: the code itself
        li    a0, 130                   ; yes
co_ret:
        ret                             ; done

; report(a0 = exit status): set $? and say how the job ended (on stderr):
; "[exit N]" or "[fault CAUSE]" (a kill says nothing: the tty echoed "^C")
report:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    s0, 8(sp)                 ; save s0
        mv    s0, a0                    ; s0 = status
        call  code_of                   ; $?
        la    t0, g_stat                ; ...
        sd    a0, 0(t0)                 ; ...
        beqz  s0, rep_ret               ; success: say nothing
        bltz  s0, rep_fault             ; bit 63: a fault
        srli  t0, s0, 62                ; bit 62: killed
        bnez  t0, rep_kill              ; ...
        la    a0, m_exit                ; "[exit N]"
        li    a1, m_exit_e - m_exit     ; ...
        call  err_str                   ; ...
        mv    a0, s0                    ; ...
        call  err_num                   ; ...
        j     rep_close                 ; ...
rep_kill:
        j     rep_ret                   ; killed: the console already echoed "^C"
        la    a0, m_cc                  ; (not printed again)
        li    a1, 3                     ; ...
        call  err_str                   ; ...
        j     rep_ret                   ; ...
rep_fault:
        la    a0, m_fault               ; "[fault CAUSE]"
        li    a1, m_fault_e - m_fault   ; ...
        call  err_str                   ; ...
        andi  a0, s0, 255               ; the cause's name
        call  fault_name                ; ...
rep_close:
        la    a0, m_close               ; "]"
        li    a1, 2                     ; ...
        call  err_str                   ; ...
rep_ret:
        ld    s0, 8(sp)                 ; restore s0
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 16                ; release the frame
        ret                             ; done

; fault_name(a0 = cause): its name on stderr (the number if unknown)
fault_name:
        li    t0, 15                    ; known causes: 0..14
        bgeu  a0, t0, err_num           ; unknown: the number (tail call)
        slli  a0, a0, 3                 ; 8 characters per name
        la    t0, f_names               ; ...
        add   a0, t0, a0                ; ...
        li    a1, 0                     ; its length: up to the first space
fn_len:
        li    t0, 8                     ; ...
        beq   a1, t0, fn_out            ; ...
        add   t1, a0, a1                ; ...
        lbu   t1, 0(t1)                 ; ...
        li    t0, ' '                   ; ...
        beq   t1, t0, fn_out            ; ...
        addi  a1, a1, 1                 ; ...
        j     fn_len                    ; ...
fn_out:
        j     err_str                   ; print it (tail call)

; fmt_dec(a0 = value) -> a0 = its decimal digits, a1 = their length
fmt_dec:
        la    t0, numend                ; right to left
        li    t1, 10                    ; ...
fd_loop:
        remu  t2, a0, t1                ; lowest digit
        divu  a0, a0, t1                ; drop it
        addi  t2, t2, '0'               ; ASCII
        addi  t0, t0, -1                ; ...
        sb    t2, 0(t0)                 ; ...
        bnez  a0, fd_loop               ; more
        mv    a0, t0                    ; the text
        la    t1, numend                ; its length
        sub   a1, t1, t0                ; ...
        ret                             ; done

; err_num(a0 = value): unsigned decimal on stderr
err_num:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        call  fmt_dec                   ; the digits
        call  err_str                   ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 16                ; release the frame
        ret                             ; done

; cant_open(a0 = name, a1 = length): "sh: cannot open NAME"; status 1
cant_open:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    a0, 8(sp)                 ; the name
        sd    a1, 16(sp)                ; ...
        la    a0, m_open                ; "sh: cannot open "
        li    a1, m_open_e - m_open     ; ...
        call  err_str                   ; ...
        ld    a0, 8(sp)                 ; the name
        ld    a1, 16(sp)                ; ...
        call  err_str                   ; ...
        la    a0, sys_nl                ; newline
        li    a1, 1                     ; ...
        call  err_str                   ; ...
        li    t0, 1                     ; status 1
        la    t1, g_stat                ; ...
        sd    t0, 0(t1)                 ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 24                ; release the frame
        ret                             ; done

