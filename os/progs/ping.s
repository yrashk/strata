; =============================================================================
; ping.s: ICMP echo through the network server
; =============================================================================
;
;   ping [-c COUNT] [-s BYTES] HOST          (HOST: a name, or a.b.c.d)
;
; Sends an echo request every second (BYTES of payload, 56 by default) and
; prints a line per reply with its round trip, measured by the server with
; the timer; a request with no reply within a second is reported as lost.
; Stops after COUNT requests, or on Ctrl-C, and prints a summary. Exit
; status 0 if any reply came, 1 if none did, 2 on bad arguments. Starts the
; network server if none runs (os/lib/sys.s net_init). A name is looked up
; first (DNS: net_resolve); the first line says what it became. `ping
; 127.0.0.1` or the machine's own address is answered by the server itself;
; another address needs a link (-N on the simulators): with `-N nat` the
; echo goes to the real host through an unprivileged ICMP socket (where the
; host has none, nothing answers); `-N peer` answers every address itself.

        .data                           ; data Local Store
        .align 8                        ; ...
ip:     .dword -1                       ; the address
hname:  .dword 0                        ; the host as given
hlen:   .dword 0                        ; ...
count:  .dword 0                        ; requests to send (0: until Ctrl-C)
bytes:  .dword 56                       ; payload bytes
sent:   .dword 0                        ; requests sent
rcvd:   .dword 0                        ; replies
s_use:  .ascii "usage: ping [-c COUNT] [-s BYTES] HOST\n" ; ...
s_unk:  .ascii "ping: cannot resolve "  ; ...
s_unk_e:
s_par:  .ascii " ("                     ; ...
s_par_e:
s_par2: .ascii "): "                    ; ...
s_par2_e:
s_use_e:
s_nonet: .ascii "ping: no network server\n" ; ...
s_nonet_e:
s_ping: .ascii "PING "                  ; ...
s_ping_e:
s_data: .ascii " data bytes\n"          ; ...
s_data_e:
s_from: .ascii " bytes from "           ; ...
s_from_e:
s_seq:  .ascii ": seq="                 ; ...
s_seq_e:
s_time: .ascii " time="                 ; ...
s_time_e:
s_ms:   .ascii " ms\n"                  ; ...
s_ms_e:
s_lost: .ascii "no answer from "        ; ...
s_lost_e:
s_err:  .ascii "ping: error "           ; ...
s_err_e:
s_sum:  .ascii "--- "                   ; ...
s_sum_e:
s_sent: .ascii ": "                     ; ...
s_sent_e:
s_sent2: .ascii " sent, "               ; ...
s_sent2_e:
s_rcvd: .ascii " received\n"            ; ...
s_rcvd_e:
s_c:    .ascii "-c"                     ; options
s_s:    .ascii "-s"                     ; ...
        .align 8                        ; ...

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        call  sys_init                  ; ...
        call  sys_cmdline               ; s1 = cursor, s2 = end
        add   s2, a0, a1                ; ...
        mv    a1, s2                    ; skip the program's name
        call  arg_next                  ; ...
        mv    s1, a2                    ; ...
m_arg:
        mv    a0, s1                    ; the next word
        mv    a1, s2                    ; ...
        call  arg_next                  ; a0 = word, a1 = length, a2 = after it
        beqz  a1, m_go                  ; no more
        mv    s1, a2                    ; ...
        mv    s3, a0                    ; s3, s4 = the word
        mv    s4, a1                    ; ...
        la    a2, s_c                   ; -c COUNT
        li    a3, 2                     ; ...
        call  str_eq                    ; ...
        bnez  a0, m_count               ; ...
        mv    a0, s3                    ; -s BYTES
        mv    a1, s4                    ; ...
        la    a2, s_s                   ; ...
        li    a3, 2                     ; ...
        call  str_eq                    ; ...
        bnez  a0, m_bytes               ; ...
        la    t0, hname                 ; else the host
        sd    s3, 0(t0)                 ; ...
        la    t0, hlen                  ; ...
        sd    s4, 0(t0)                 ; ...
        j     m_arg                     ; ...
m_count:
        call  m_num                     ; a0 = the number after it
        la    t0, count                 ; ...
        sd    a0, 0(t0)                 ; ...
        j     m_arg                     ; ...
m_bytes:
        call  m_num                     ; ...
        li    t1, 1400                  ; at most 1400
        bgtu  a0, t1, m_use             ; ...
        la    t0, bytes                 ; ...
        sd    a0, 0(t0)                 ; ...
        j     m_arg                     ; ...
m_num:
        mv    s5, ra                    ; (a leaf of main: keeps ra in s5)
        mv    a0, s1                    ; the next word, a number
        mv    a1, s2                    ; ...
        call  arg_next                  ; ...
        mv    s1, a2                    ; ...
        beqz  a1, m_use                 ; ...
        call  str_num                   ; ...
        bltz  a0, m_use                 ; ...
        mv    ra, s5                    ; ...
        ret                             ; ...
m_use:
        la    a0, s_use                 ; ...
        li    a1, s_use_e - s_use       ; ...
        call  err_str                   ; ...
        li    a0, 2                     ; ...
        call  sys_exit                  ; ...
m_go:
        la    t0, hlen                  ; a host is needed
        ld    t0, 0(t0)                 ; ...
        beqz  t0, m_use                 ; ...
        li    a0, 1                     ; Ctrl-C ends the run with the summary
        call  sys_catch                 ; ...
        call  net_init                  ; the network server
        bnez  a0, m_nonet               ; ...
        la    a0, hname                 ; its address
        ld    a0, 0(a0)                 ; ...
        la    a1, hlen                  ; ...
        ld    a1, 0(a1)                 ; ...
        li    a2, 0                     ; ...
        call  net_resolve               ; ...
        bltz  a0, m_unk                 ; ...
        la    t0, ip                    ; ...
        sd    a0, 0(t0)                 ; ...
        la    a0, s_ping                ; "PING example.com (93.184.215.14): 56 data bytes"
        li    a1, s_ping_e - s_ping     ; ...
        call  out_str                   ; ...
        call  pr_host                   ; ...
        la    a0, s_par                 ; ...
        li    a1, s_par_e - s_par       ; ...
        call  out_str                   ; ...
        call  pr_ip                     ; ...
        la    a0, s_par2                ; ...
        li    a1, s_par2_e - s_par2     ; ...
        call  out_str                   ; ...
        la    a0, bytes                 ; ...
        ld    a0, 0(a0)                 ; ...
        call  out_dec                   ; ...
        la    a0, s_data                ; ...
        li    a1, s_data_e - s_data     ; ...
        call  out_str                   ; ...
        call  out_flush                 ; ...
loop:
        la    t0, sent                  ; one more request
        ld    s3, 0(t0)                 ; s3 = its sequence number
        addi  s3, s3, 1                 ; ...
        sd    s3, 0(t0)                 ; ...
        la    a0, ip                    ; ...
        ld    a0, 0(a0)                 ; ...
        la    a1, bytes                 ; ...
        ld    a1, 0(a1)                 ; ...
        li    a2, 1000000               ; a second at most
        call  net_ping                  ; a0 = the round trip in ticks, or < 0
        bltz  a0, l_none                ; ...
        mv    s4, a0                    ; s4 = ticks (us)
        la    t0, rcvd                  ; ...
        ld    t1, 0(t0)                 ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, 0(t0)                 ; ...
        la    a0, bytes                 ; "64 bytes from 10.0.0.1: seq=1 time=0.123 ms"
        ld    a0, 0(a0)                 ; (the ICMP message: payload + 8)
        addi  a0, a0, 8                 ; ...
        call  out_dec                   ; ...
        la    a0, s_from                ; ...
        li    a1, s_from_e - s_from     ; ...
        call  out_str                   ; ...
        call  pr_ip                     ; ...
        call  pr_seq                    ; ...
        la    a0, s_time                ; ...
        li    a1, s_time_e - s_time     ; ...
        call  out_str                   ; ...
        li    t0, 1000                  ; milliseconds
        divu  a0, s4, t0                ; ...
        call  out_dec                   ; ...
        li    a0, '.'                   ; ...
        call  out_chr                   ; ...
        li    t0, 1000                  ; three decimals
        remu  s4, s4, t0                ; ...
        li    t0, 100                   ; ...
        divu  a0, s4, t0                ; ...
        addi  a0, a0, '0'               ; ...
        call  out_chr                   ; ...
        li    t0, 100                   ; ...
        remu  s4, s4, t0                ; ...
        li    t0, 10                    ; ...
        divu  a0, s4, t0                ; ...
        addi  a0, a0, '0'               ; ...
        call  out_chr                   ; ...
        li    t0, 10                    ; ...
        remu  a0, s4, t0                ; ...
        addi  a0, a0, '0'               ; ...
        call  out_chr                   ; ...
        la    a0, s_ms                  ; ...
        li    a1, s_ms_e - s_ms         ; ...
        call  out_str                   ; ...
        j     l_next                    ; ...
l_none:
        li    t0, -8                    ; no answer in time
        bne   a0, t0, l_err             ; ...
        la    a0, s_lost                ; "no answer from 10.0.0.1: seq=2"
        li    a1, s_lost_e - s_lost     ; ...
        call  out_str                   ; ...
        call  pr_ip                     ; ...
        call  pr_seq                    ; ...
        call  out_nl                    ; ...
        j     l_next                    ; ...
l_err:
        mv    s4, a0                    ; another error: say so, stop
        la    a0, s_err                 ; ...
        li    a1, s_err_e - s_err       ; ...
        call  out_str                   ; ...
        mv    a0, s4                    ; ...
        call  out_sdec                  ; ...
        call  out_nl                    ; ...
        j     done                      ; ...
l_next:
        call  out_flush                 ; ...
        call  sys_intr                  ; Ctrl-C while it waited?
        bnez  a0, done                  ; ...
        la    t0, count                 ; enough?
        ld    t0, 0(t0)                 ; ...
        beqz  t0, l_wait                ; (0: until Ctrl-C)
        bgeu  s3, t0, done              ; ...
l_wait:
        li    a0, 1000000               ; a second between requests
        call  sys_sleep                 ; -8 when it is up, -2 on Ctrl-C
        li    t0, E_INTR                ; ...
        beq   a0, t0, done              ; ...
        call  sys_intr                  ; ...
        bnez  a0, done                  ; ...
        j     loop                      ; ...
done:
        la    a0, s_sum                 ; "--- example.com: 4 sent, 4 received"
        li    a1, s_sum_e - s_sum       ; ...
        call  out_str                   ; ...
        call  pr_host                   ; ...
        la    a0, s_sent                ; ...
        li    a1, s_sent_e - s_sent     ; ...
        call  out_str                   ; ...
        la    a0, sent                  ; ...
        ld    a0, 0(a0)                 ; ...
        call  out_dec                   ; ...
        la    a0, s_sent2               ; ...
        li    a1, s_sent2_e - s_sent2   ; ...
        call  out_str                   ; ...
        la    a0, rcvd                  ; ...
        ld    a0, 0(a0)                 ; ...
        call  out_dec                   ; ...
        la    a0, s_rcvd                ; ...
        li    a1, s_rcvd_e - s_rcvd     ; ...
        call  out_str                   ; ...
        la    t0, rcvd                  ; status: 0 if anything came back
        ld    t0, 0(t0)                 ; ...
        li    a0, 0                     ; ...
        bnez  t0, d_exit                ; ...
        li    a0, 1                     ; ...
d_exit:
        call  sys_exit                  ; ...
m_nonet:
        la    a0, s_nonet               ; ...
        li    a1, s_nonet_e - s_nonet   ; ...
        call  err_str                   ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...

m_unk:
        la    a0, s_unk                 ; "ping: cannot resolve NAME"
        li    a1, s_unk_e - s_unk       ; ...
        call  out_str                   ; ...
        call  pr_host                   ; ...
        call  out_nl                    ; ...
        call  out_flush                 ; ...
        li    a0, 2                     ; ...
        call  sys_exit                  ; ...

; pr_host(): the host as given
pr_host:
        la    a0, hname                 ; ...
        ld    a0, 0(a0)                 ; ...
        la    a1, hlen                  ; ...
        ld    a1, 0(a1)                 ; ...
        j     out_str                   ; (tail call)

; pr_ip(): the address
pr_ip:
        la    a0, ip                    ; ...
        ld    a0, 0(a0)                 ; ...
        j     out_ip                    ; (tail call)

; pr_seq(): ": seq=N" (N = s3)
pr_seq:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        la    a0, s_seq                 ; ...
        li    a1, s_seq_e - s_seq       ; ...
        call  out_str                   ; ...
        mv    a0, s3                    ; ...
        call  out_dec                   ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

        .include "../lib/sys.s"         ; the program library
