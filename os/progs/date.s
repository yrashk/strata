; =============================================================================
; date.s: the date and the time of day
; =============================================================================
;
;   date
;   2026-11-14 08:45:12 +01:00
;
; The local date and time, and the time zone as an offset from UTC: the
; timer's EPOCH and ZONE (the host's wall clock and time zone, through dev:
; sys_time) plus NOW. A machine that does not know the time (virtual time,
; or no host clock) counts from 1970-01-01 00:00 at power-on.

        .data                           ; data Local Store
        .align 8                        ; ...
zone:   .dword 0                        ; the time zone, seconds

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        call  sys_init                  ; handles and arguments
        call  sys_time                  ; a0 = UTC microseconds, a1 = zone
        la    t0, zone                  ; ...
        sd    a1, 0(t0)                 ; ...
        li    t0, 1000000               ; seconds
        div   a0, a0, t0                ; ...
        add   a0, a0, a1                ; local
        bgez  a0, m_pos                 ; (before 1970: 1970)
        li    a0, 0                     ; ...
m_pos:  li    t0, 86400                 ; s0 = days, s1 = seconds of the day
        divu  s0, a0, t0                ; ...
        remu  s1, a0, t0                ; ...
; days since 1970-01-01 -> year, month, day (the proleptic Gregorian calendar,
; in 400-year eras from 0000-03-01)
        li    t0, 719468                ; z: days since 0000-03-01
        add   t0, s0, t0                ; ...
        li    t1, 146097                ; era = z / 146097
        divu  t2, t0, t1                ; ...
        mul   t3, t2, t1                ; doe = z - era * 146097 (day of the era)
        sub   t3, t0, t3                ; ...
        li    t1, 1460                  ; yoe = (doe - doe/1460 + doe/36524 - doe/146096) / 365
        divu  t4, t3, t1                ; ...
        sub   t4, t3, t4                ; ...
        li    t1, 36524                 ; ...
        divu  t5, t3, t1                ; ...
        add   t4, t4, t5                ; ...
        li    t1, 146096                ; ...
        divu  t5, t3, t1                ; ...
        sub   t4, t4, t5                ; ...
        li    t1, 365                   ; ...
        divu  t4, t4, t1                ; t4 = yoe
        li    t1, 400                   ; s2 = year (from March)
        mul   s2, t2, t1                ; ...
        add   s2, s2, t4                ; ...
        li    t1, 365                   ; doy = doe - (365 yoe + yoe/4 - yoe/100)
        mul   t5, t4, t1                ; ...
        srli  t6, t4, 2                 ; ...
        add   t5, t5, t6                ; ...
        li    t1, 100                   ; ...
        divu  t6, t4, t1                ; ...
        sub   t5, t5, t6                ; ...
        sub   t5, t3, t5                ; t5 = doy (from March 1)
        li    t1, 5                     ; mp = (5 doy + 2) / 153
        mul   t6, t5, t1                ; ...
        addi  t6, t6, 2                 ; ...
        li    t1, 153                   ; ...
        divu  t6, t6, t1                ; t6 = mp
        li    t1, 153                   ; day = doy - (153 mp + 2) / 5 + 1
        mul   t0, t6, t1                ; ...
        addi  t0, t0, 2                 ; ...
        li    t1, 5                     ; ...
        divu  t0, t0, t1                ; ...
        sub   s3, t5, t0                ; ...
        addi  s3, s3, 1                 ; s3 = day
        addi  s4, t6, 3                 ; s4 = month: mp + 3, or mp - 9 from January
        li    t1, 12                    ; ...
        ble   s4, t1, m_mon             ; ...
        addi  s4, s4, -12               ; ...
        addi  s2, s2, 1                 ; (January and February: the next year)
m_mon:
        mv    a0, s2                    ; YYYY-MM-DD
        call  out_dec                   ; ...
        li    a0, '-'                   ; ...
        call  out_chr                   ; ...
        mv    a0, s4                    ; ...
        call  dd                        ; ...
        li    a0, '-'                   ; ...
        call  out_chr                   ; ...
        mv    a0, s3                    ; ...
        call  dd                        ; ...
        li    a0, ' '                   ; hh:mm:ss
        call  out_chr                   ; ...
        li    t0, 3600                  ; ...
        divu  a0, s1, t0                ; ...
        call  dd                        ; ...
        li    a0, ':'                   ; ...
        call  out_chr                   ; ...
        li    t0, 60                    ; ...
        divu  a0, s1, t0                ; ...
        remu  a0, a0, t0                ; ...
        call  dd                        ; ...
        li    a0, ':'                   ; ...
        call  out_chr                   ; ...
        li    t0, 60                    ; ...
        remu  a0, s1, t0                ; ...
        call  dd                        ; ...
        li    a0, ' '                   ; +hh:mm
        call  out_chr                   ; ...
        la    t0, zone                  ; ...
        ld    s5, 0(t0)                 ; ...
        li    a0, '+'                   ; ...
        bgez  s5, m_sign                ; ...
        neg   s5, s5                    ; ...
        li    a0, '-'                   ; ...
m_sign: call  out_chr                   ; ...
        li    t0, 3600                  ; ...
        divu  a0, s5, t0                ; ...
        call  dd                        ; ...
        li    a0, ':'                   ; ...
        call  out_chr                   ; ...
        li    t0, 60                    ; ...
        divu  a0, s5, t0                ; ...
        remu  a0, a0, t0                ; ...
        call  dd                        ; ...
        call  out_nl                    ; ...
        li    a0, 0                     ; exit code
        call  sys_exit                  ; flush stdout, end the process

; dd(a0 = 0..99): two digits
dd:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save ra
        sd    a0, 8(sp)                 ; ...
        li    t0, 10                    ; tens
        divu  a0, a0, t0                ; ...
        addi  a0, a0, '0'               ; ...
        call  out_chr                   ; ...
        ld    a0, 8(sp)                 ; units
        li    t0, 10                    ; ...
        remu  a0, a0, t0                ; ...
        addi  a0, a0, '0'               ; ...
        ld    ra, 0(sp)                 ; restore ra
        addi  sp, sp, 16                ; release the frame
        j     out_chr                   ; (tail call)

        .include "../lib/sys.s"         ; the system interface
