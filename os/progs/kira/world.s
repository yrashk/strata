; =============================================================================
; world.s: kira's world: a new castle and garden for every game
; =============================================================================
;
; The world of Friends is 40 x 20 cells in an array 64 wide (dat.s: R_MAP; a
; cell: a wall 1..6 in bits 0..3, the floor's kind in bits 4..6, bit 7 = not
; walked on though it has no wall), and a list of the things that stand in
; it (R_THINGS). w_gen makes both anew:
;   the castle   rows 0..9: three rooms side by side, the walls between them
;                at random columns, each with a door at a random row; windows,
;                banners and shelves along the walls; carpets; two gates in
;                the south wall;
;   the garden   rows 10..19 inside a hedge with roses: a path from each
;                gate and one joining them, a pond, trees, bushes, a fountain,
;                and the picnic blanket.
; Every free cell can be reached from every other, whatever comes out: the
; rooms are joined by their doors and gates, and a thing (or the pond) is
; put only where all the cells around it are free, so nothing can close a
; way: the cells around it are a ring one can walk.

W_STONE   = 1                           ; walls (the map's codes; dat.s: R_TEX, the tiles)
W_WINDOW  = 2                           ; ...
W_BANNER  = 3                           ; ...
W_SHELF   = 4                           ; ...
W_HEDGE   = 5                           ; ...
W_ROSES   = 6                           ; ...
F_CASTLE  = 0x00                        ; floors (the kind, in its place)
F_CARPET  = 0x10                        ; ...
F_GRASS   = 0x20                        ; ...
F_PATH    = 0x30                        ; ...
F_WATER   = 0xc0                        ; (and not walked on)
C_BLOCK   = 0x80                        ; a cell that is not walked on
C_SOLID   = 0x8f                        ; what makes a cell so: a wall, or that bit
K_DECOR   = 1                           ; kinds of thing: one that stands in the way
K_PICNIC  = 2                           ; the picnic blanket
D_TREE    = 0                           ; things (dat.s: R_DECOR)
D_BUSH    = 1                           ; ...
D_FOUNT   = 2                           ; ...
D_BED     = 3                           ; ...
D_TABLE   = 4                           ; ...
D_THRONE  = 5                           ; ...
D_CHEST   = 6                           ; ...
D_PICNIC  = 7                           ; ...
MAXTHING  = 40                          ; things at most

        .data                           ; D-LS
        .align 8                        ; dwords
w_list:                                 ; what is put into the world: region (0 the castle,
        .byte 0, D_THRONE, 0, D_BED     ;   1 the garden), thing; 255 ends the list
        .byte 0, D_TABLE, 0, D_TABLE    ; ...
        .byte 0, D_CHEST, 0, D_CHEST    ; ...
        .byte 1, D_FOUNT, 1, D_TREE     ; ...
        .byte 1, D_TREE, 1, D_TREE      ; ...
        .byte 1, D_TREE, 1, D_TREE      ; ...
        .byte 1, D_TREE, 1, D_BUSH      ; ...
        .byte 1, D_BUSH, 1, D_BUSH      ; ...
        .byte 1, D_BUSH, 1, D_BUSH      ; ...
        .byte 255, 0, 0, 0              ; ...
        .align 8                        ; ...
        .text                           ; code

; rnd_n(a0 = n) -> a0 = 0 .. n - 1. Clobbers t0.
rnd_n:  addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    a0, 8(sp)                 ; n
        call  rnd                       ; ...
        ld    t0, 8(sp)                 ; ...
        remu  a0, a0, t0                ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 16                ; pop the frame
        ret                             ; done

; w_rect(a0 = x0, a1 = y0, a2 = x1, a3 = y1 (inclusive), a4 = cell): fill.
; Clobbers t0..t2, a1.
w_rect: la    t0, res + R_MAP           ; ...
wr_y:   slli  t1, a1, 6                 ; the row
        add   t1, t1, t0                ; ...
        add   t1, t1, a0                ; ...
        sub   t2, a2, a0                ; ...
wr_x:   sb    a4, 0(t1)                 ; ...
        addi  t1, t1, 1                 ; ...
        addi  t2, t2, -1                ; ...
        bgez  t2, wr_x                  ; ...
        addi  a1, a1, 1                 ; ...
        ble   a1, a3, wr_y              ; ...
        ret                             ; done

; w_put(a0 = x, a1 = y, a2 = cell). Clobbers t0.
w_put:  slli  t0, a1, 6                 ; ...
        add   t0, t0, a0                ; ...
        la    a1, res + R_MAP           ; ...
        add   t0, t0, a1                ; ...
        sb    a2, 0(t0)                 ; ...
        ret                             ; done

; w_free8(a0 = x, a1 = y) -> a0 = 1 if the cell and the eight around it can
; all be walked on. Clobbers t0..t3.
w_free8:
        slli  t0, a1, 6                 ; the cell up and left of it
        add   t0, t0, a0                ; ...
        la    t1, res + R_MAP - 65      ; ...
        add   t0, t0, t1                ; ...
        li    t1, 3                     ; three rows of three
        li    a0, 0                     ; ...
w8_r:   lbu   t2, 0(t0)                 ; ...
        lbu   t3, 1(t0)                 ; ...
        or    t2, t2, t3                ; ...
        lbu   t3, 2(t0)                 ; ...
        or    t2, t2, t3                ; ...
        andi  t2, t2, C_SOLID           ; ...
        bnez  t2, w8_n                  ; ...
        addi  t0, t0, 64                ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, w8_r                  ; ...
        li    a0, 1                     ; ...
w8_n:   ret                             ; done

; w_spot(a0 = region: 0 the castle, 1 the garden, 2 anywhere) -> a0 = x, a1 =
; y: a cell of it, at random (it may be a wall)
w_spot: addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the region
        sd    s1, 16(sp)                ; s1 = x
        mv    s0, a0                    ; ...
        li    a0, 38                    ; columns 1..38
        call  rnd_n                     ; ...
        addi  s1, a0, 1                 ; ...
        li    a0, 8                     ; the castle: rows 1..8
        li    t1, 1                     ; ...
        beqz  s0, ws_y                  ; ...
        li    a0, 9                     ; the garden: rows 10..18
        li    t1, 10                    ; ...
        li    t0, 1                     ; ...
        beq   s0, t0, ws_y              ; ...
        li    a0, 18                    ; anywhere: rows 1..18
        li    t1, 1                     ; ...
ws_y:   sd    t1, 24(sp)                ; ...
        call  rnd_n                     ; ...
        ld    t1, 24(sp)                ; ...
        add   a1, a0, t1                ; ...
        mv    a0, s1                    ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

; w_thing(a0 = region, a1 = which thing (D_*), a2 = its kind) -> a0 = x, a1 =
; y, or a0 = -1: put it in a cell of the region with free cells all around
; (60 tries); one that stands in the way closes its cell
w_thing:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = region
        sd    s1, 16(sp)                ; s1 = which
        sd    s2, 24(sp)                ; s2 = kind
        sd    s3, 32(sp)                ; s3 = tries left
        sd    s4, 40(sp)                ; s4 = x | y << 8
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        mv    s2, a2                    ; ...
        li    s3, 60                    ; ...
wt_l:   mv    a0, s0                    ; ...
        call  w_spot                    ; ...
        slli  s4, a1, 8                 ; ...
        or    s4, s4, a0                ; ...
        call  w_free8                   ; ...
        bnez  a0, wt_ok                 ; ...
        addi  s3, s3, -1                ; ...
        bnez  s3, wt_l                  ; ...
        li    a0, -1                    ; ...
        j     wt_r                      ; ...
wt_ok:  ld    t0, w_next - g(gp)        ; its record
        la    t1, res + R_THINGS + MAXTHING * 8 ; (if there is room)
        li    a0, -1                    ; ...
        bgeu  t0, t1, wt_r              ; ...
        sh    s4, 0(t0)                 ; x, y
        sb    s2, 2(t0)                 ; kind
        sb    s1, 3(t0)                 ; which
        slli  t1, s1, 2                 ; its two sprites
        la    t2, res + R_DECOR         ; ...
        add   t1, t1, t2                ; ...
        lwu   t1, 0(t1)                 ; ...
        sw    t1, 4(t0)                 ; ...
        addi  t0, t0, 8                 ; ...
        sd    zero, 0(t0)               ; (the list's end)
        sd    t0, w_next - g(gp)        ; ...
        andi  a0, s4, 0xff              ; ...
        srli  a1, s4, 8                 ; ...
        li    t0, K_DECOR               ; ...
        bne   s2, t0, wt_r              ; ...
        slli  t0, a1, 6                 ; it stands in the way
        add   t0, t0, a0                ; ...
        la    t1, res + R_MAP           ; ...
        add   t0, t0, t1                ; ...
        lbu   t1, 0(t0)                 ; ...
        ori   t1, t1, C_BLOCK           ; ...
        sb    t1, 0(t0)                 ; ...
wt_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        addi  sp, sp, 48                ; pop the frame
        ret                             ; done
; w_gen(): a new world; f_picx, f_picy = where the picnic blanket lies
w_gen:  addi  sp, sp, -56               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the first inner wall's column
        sd    s1, 16(sp)                ; s1 = the second's
        sd    s2, 24(sp)                ; s2 = the first gate's column
        sd    s3, 32(sp)                ; s3 = the second's
        sd    s4, 40(sp)                ; s4 = a counter; the pond's width
        sd    s5, 48(sp)                ; s5 = a place; the pond's height
        la    t0, res + R_MAP           ; stone everywhere
        li    t1, 2048 / 8              ; ...
        li    t2, 0x0101010101010101    ; ...
wg_z:   sd    t2, 0(t0)                 ; ...
        addi  t0, t0, 8                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, wg_z                  ; ...
        li    a0, 1                     ; the castle's floor
        li    a1, 1                     ; ...
        li    a2, 38                    ; ...
        li    a3, 8                     ; ...
        li    a4, F_CASTLE              ; ...
        call  w_rect                    ; ...
        li    a0, 0                     ; the garden: hedge ...
        li    a1, 10                    ; ...
        li    a2, 39                    ; ...
        li    a3, 19                    ; ...
        li    a4, W_HEDGE               ; ...
        call  w_rect                    ; ...
        li    a0, 1                     ; ... around grass
        li    a1, 10                    ; ...
        li    a2, 38                    ; ...
        li    a3, 18                    ; ...
        li    a4, F_GRASS               ; ...
        call  w_rect                    ; ...
        li    s4, 38                    ; the north wall: windows, banners, a shelf or two;
wg_n:   li    a0, 12                    ;   the south wall: a banner here and there
        call  rnd_n                     ; ...
        li    a2, W_WINDOW              ; ...
        li    t0, 3                     ; ...
        bltu  a0, t0, wg_n1             ; ...
        li    a2, W_BANNER              ; ...
        li    t0, 5                     ; ...
        bltu  a0, t0, wg_n1             ; ...
        li    a2, W_SHELF               ; ...
        beq   a0, t0, wg_n1             ; ...
        li    a2, W_STONE               ; ...
wg_n1:  mv    a0, s4                    ; ...
        li    a1, 0                     ; ...
        call  w_put                     ; ...
        li    a0, 6                     ; ...
        call  rnd_n                     ; ...
        bnez  a0, wg_n2                 ; ...
        mv    a0, s4                    ; ...
        li    a1, 9                     ; ...
        li    a2, W_BANNER              ; ...
        call  w_put                     ; ...
wg_n2:  li    a0, 5                     ; roses in the south hedge
        call  rnd_n                     ; ...
        bnez  a0, wg_n3                 ; ...
        mv    a0, s4                    ; ...
        li    a1, 19                    ; ...
        li    a2, W_ROSES               ; ...
        call  w_put                     ; ...
wg_n3:  addi  s4, s4, -1                ; ...
        bnez  s4, wg_n                  ; ...
        li    s4, 18                    ; the west and east walls: windows in the castle,
wg_w:   li    a0, 8                     ;   roses in the hedge (row 9 is the castle's corner)
        call  rnd_n                     ; ...
        li    t0, 3                     ; (three rows in eight)
        bgeu  a0, t0, wg_w2             ; ...
        andi  a0, a0, 1                 ; which side
        li    t0, 39                    ; ...
        mul   a0, a0, t0                ; ...
        mv    a1, s4                    ; ...
        li    a2, W_WINDOW              ; ...
        li    t0, 9                     ; ...
        beq   s4, t0, wg_w2             ; ...
        blt   s4, t0, wg_w1             ; ...
        li    a2, W_ROSES               ; ...
wg_w1:  call  w_put                     ; ...
wg_w2:  addi  s4, s4, -1                ; ...
        bnez  s4, wg_w                  ; ...

        li    a0, 6                     ; the inner walls: columns 10..15 and 23..29,
        call  rnd_n                     ;   a door in each at a row 2..7
        addi  s0, a0, 10                ; ...
        li    a0, 7                     ; ...
        call  rnd_n                     ; ...
        addi  s1, a0, 23                ; ...
        mv    s5, s0                    ; ...
wg_i:   mv    a0, s5                    ; ...
        li    a1, 1                     ; ...
        mv    a2, s5                    ; ...
        li    a3, 8                     ; ...
        li    a4, W_STONE               ; ...
        call  w_rect                    ; ...
        li    a0, 6                     ; ...
        call  rnd_n                     ; ...
        addi  a1, a0, 2                 ; ...
        mv    a0, s5                    ; ...
        li    a2, F_CASTLE              ; ...
        call  w_put                     ; ...
        beq   s5, s1, wg_i1             ; ...
        mv    s5, s1                    ; ...
        j     wg_i                      ; ...
wg_i1:  addi  a0, s0, 2                 ; a carpet down the middle room ...
        li    a1, 2                     ; ...
        addi  a2, s1, -2                ; ...
        li    a3, 7                     ; ...
        li    a4, F_CARPET              ; ...
        call  w_rect                    ; ...
        addi  a0, s0, -6                ; ... and one in the west room: 3..5 wide, from a
        call  rnd_n                     ;   column 2 .. s0 - 5
        addi  s5, a0, 2                 ; ...
        li    a0, 3                     ; ...
        call  rnd_n                     ; ...
        add   a2, a0, s5                ; ...
        addi  a2, a2, 2                 ; ...
        mv    a0, s5                    ; ...
        li    a1, 3                     ; ...
        li    a3, 6                     ; ...
        li    a4, F_CARPET              ; ...
        call  w_rect                    ; ...
        addi  a0, s0, -3                ; the gates: in the west room's south wall (column
        call  rnd_n                     ;   2 .. s0 - 2) and the east room's (s1 + 2 .. 37)
        addi  s2, a0, 2                 ; ...
        li    a0, 36                    ; ...
        sub   a0, a0, s1                ; ...
        call  rnd_n                     ; ...
        add   s3, a0, s1                ; ...
        addi  s3, s3, 2                 ; ...
        li    a0, 6                     ; the paths: down from each gate to a row 12..17,
        call  rnd_n                     ;   and along that row from one to the other
        addi  s5, a0, 12                ; ...
        mv    a0, s2                    ; ...
        li    a1, 9                     ; ...
        mv    a2, s2                    ; ...
        mv    a3, s5                    ; ...
        li    a4, F_PATH                ; ...
        call  w_rect                    ; ...
        mv    a0, s3                    ; ...
        li    a1, 9                     ; ...
        mv    a2, s3                    ; ...
        mv    a3, s5                    ; ...
        li    a4, F_PATH                ; ...
        call  w_rect                    ; ...
        mv    a0, s2                    ; ...
        mv    a1, s5                    ; ...
        mv    a2, s3                    ; ...
        mv    a3, s5                    ; ...
        li    a4, F_PATH                ; ...
        call  w_rect                    ; ...

        li    a0, 4                     ; the pond: 4..7 wide, 2..4 high, grass all around
        call  rnd_n                     ; ...
        addi  s4, a0, 4                 ; ...
        li    a0, 3                     ; ...
        call  rnd_n                     ; ...
        addi  s5, a0, 2                 ; ...
        li    a0, 37                    ; its left column: 2 .. 37 - width
        sub   a0, a0, s4                ; ...
        call  rnd_n                     ; ...
        addi  s0, a0, 2                 ; (the inner walls' columns are not needed again)
        li    a0, 8                     ; its top row: 11 .. 18 - height
        sub   a0, a0, s5                ; ...
        call  rnd_n                     ; ...
        addi  s1, a0, 11                ; ...
        mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        add   a2, s0, s4                ; ...
        addi  a2, a2, -1                ; ...
        add   a3, s1, s5                ; ...
        addi  a3, a3, -1                ; ...
        li    a4, F_WATER               ; ...
        call  w_rect                    ; ...
        li    t0, 3                     ; a pond three rows high or more has round corners
        blt   s5, t0, wg_t              ; ...
        mv    a0, s0                    ; ...
        mv    a1, s1                    ; ...
        li    a2, F_GRASS               ; ...
        call  w_put                     ; ...
        add   a0, s0, s4                ; ...
        addi  a0, a0, -1                ; ...
        mv    a1, s1                    ; ...
        li    a2, F_GRASS               ; ...
        call  w_put                     ; ...
        mv    a0, s0                    ; ...
        add   a1, s1, s5                ; ...
        addi  a1, a1, -1                ; ...
        li    a2, F_GRASS               ; ...
        call  w_put                     ; ...
        add   a0, s0, s4                ; ...
        addi  a0, a0, -1                ; ...
        add   a1, s1, s5                ; ...
        addi  a1, a1, -1                ; ...
        li    a2, F_GRASS               ; ...
        call  w_put                     ; ...

wg_t:   la    t0, res + R_THINGS        ; the things
        sd    zero, 0(t0)               ; ...
        sd    t0, w_next - g(gp)        ; ...
        la    s4, w_list                ; ...
wg_tl:  lbu   a0, 0(s4)                 ; ...
        li    t0, 255                   ; ...
        beq   a0, t0, wg_p              ; ...
        lbu   a1, 1(s4)                 ; ...
        li    a2, K_DECOR               ; ...
        call  w_thing                   ; ...
        addi  s4, s4, 2                 ; ...
        j     wg_tl                     ; ...
wg_p:   li    a0, 1                     ; the picnic blanket, in the garden
        li    a1, D_PICNIC              ; ...
        li    a2, K_PICNIC              ; ...
        call  w_thing                   ; ...
        bltz  a0, wg_p                  ; (there is room for it: again)
        sd    a0, f_picx - g(gp)        ; ...
        sd    a1, f_picy - g(gp)        ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        ld    s5, 48(sp)                ; ...
        addi  sp, sp, 56                ; pop the frame
        ret                             ; done
