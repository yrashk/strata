; =============================================================================
; eyes.s: kira's world seen through Kira's eyes: wdoom's raycaster, made gentle
; =============================================================================
;
; The same world as from above (world.s), drawn as wdoom draws its level
; (os/progs/wdoom/render.s has the method: a ray per column through the
; grid, one texture column fetched from the arena, floor and ceiling by
; rows, the things scaled and clipped against the walls' depths), with
; these differences:
;   - the map is 64 cells wide and has no doors: a door is a gap in a wall;
;   - textures are 64 x 64, and there are four light levels, not sixteen:
;     the castle is bright to its far end;
;   - every cell has its own floor (one of five 32 x 32 flats, by the
;     cell's kind), and its ceiling is the castle's, or, over grass, paths
;     and water, the sky: so the garden is out of doors.
; The flats live in the library's buffers for standard output and input
; (out_buf, in_buf: 4 KiB each): this program writes nothing to standard
; output and never reads standard input.
;
; Fixed point: positions and distances are 16.16 (1.0 = a cell); angles are
; 0..2047 around the circle.

HORIZON   = 84                          ; the row of the eye
PROJ      = 160                         ; pixels per cell at distance 1
NFLAT     = 6                           ; flats: floors 0..4, the ceiling

; ---- a visible thing (e_add) ----------------------------------------------------
V_X1      = 0                           ; first column (signed)
V_X2      = 4                           ; past the last
V_Y1      = 8                           ; first row (signed)
V_Y2      = 12                          ; past the last
V_DEPTH   = 16                          ; distance along the view, 16.16
V_INV     = 20                          ; texels per pixel, 16.16
V_SPR     = 24                          ; its sprite's directory entry
V_LP      = 32                          ; its row of the colour map
V_SIZE    = 40                          ; bytes
MAXVIS    = 32                          ; visible things at most

        .data                           ; D-LS
        .align 8                        ; dwords
zbuf:     .space VIEW_W * 4             ; the wall's distance in every column
vis:      .space MAXVIS * V_SIZE        ; the visible things
visord:   .space MAXVIS * 8             ; ... far to near
e_flatp:  .space 8 * 8                  ; where each kind of floor's flat is
        .text                           ; code

; e_init(): the flats, from the arena into the library's buffers
e_init: ld    t0, g_keepb - g(gp)       ; floors 0..3 ...
        li    t1, F_FLATS               ; ...
        add   t0, t0, t1                ; ...
        la    t2, out_buf               ; ...
        li    t3, 4096                  ; ...
        tget  tg8, t2, c0, t0, t3       ; ...
        add   t0, t0, t3                ; ... floor 4 and the ceiling
        la    t4, in_buf                ; ...
        li    t3, 2048                  ; ...
        tget  tg9, t4, c0, t0, t3       ; ...
        twait (1 << 8) | (1 << 9)       ; ...
        la    t0, e_flatp               ; ...
        li    t1, 4                     ; ...
ei_l:   sd    t2, 0(t0)                 ; ...
        addi  t2, t2, 1024              ; ...
        addi  t0, t0, 8                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, ei_l                  ; ...
        li    t1, 4                     ; (kinds 5..7 are not used: water's)
ei_m:   sd    t4, 0(t0)                 ; ...
        addi  t0, t0, 8                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, ei_m                  ; ...
        ret                             ; done

; fsin(a0 = angle) -> a0 = its sine, 16.16; fcos likewise. Clobber t0, t1.
fcos:   addi  a0, a0, 512               ; cos a = sin (a + a quarter)
fsin:   andi  a0, a0, 2047              ; one circle
        srli  t0, a0, 9                 ; t0 = the quadrant
        andi  a0, a0, 511               ; the angle in it
        andi  t1, t0, 1                 ; quadrants 1 and 3 run backwards
        beqz  t1, sn_1                  ; ...
        li    t1, 512                   ; ...
        sub   a0, t1, a0                ; ...
sn_1:   slli  a0, a0, 2                 ; the table's entry
        la    t1, res + R_SIN           ; ...
        add   a0, a0, t1                ; ...
        lwu   a0, 0(a0)                 ; ...
        andi  t0, t0, 2                 ; quadrants 2 and 3 are negative
        beqz  t0, sn_r                  ; ...
        neg   a0, a0                    ; ...
sn_r:   ret                             ; done

; e_begin(): before a frame: the view's direction and its screen plane from
; the angle; the things in view, far to near
e_begin:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = thing; friend
        sd    s1, 16(sp)                ; s1 = friends left; the friend's entry in R_FRIEND
        sd    s2, 24(sp)                ; s2 = the next vis entry
        sd    s3, 32(sp)                ; s3 = entries so far
        ld    a0, f_ang - g(gp)         ; dir = (cos, sin)
        call  fcos                      ; ...
        sd    a0, e_dirx - g(gp)        ; ...
        sd    a0, e_ply - g(gp)         ; the plane is the direction turned a quarter
        ld    a0, f_ang - g(gp)         ;   towards larger angles: (-sin, cos), so that
        call  fsin                      ;   the screen's right is the turn to the right
        sd    a0, e_diry - g(gp)        ; ...
        neg   a0, a0                    ; ...
        sd    a0, e_plx - g(gp)         ; ...
        la    s2, vis                   ; ...
        li    s3, 0                     ; ...
        la    s0, res + R_THINGS        ; the world's things, in the middle of their cells
eb_t:   lbu   t0, TH_KIND(s0)           ; ...
        beqz  t0, eb_f                  ; ...
        lbu   a0, TH_X(s0)              ; ...
        slli  a0, a0, 16                ; ...
        li    t0, 0x8000                ; ...
        add   a0, a0, t0                ; ...
        lbu   a1, TH_Y(s0)              ; ...
        slli  a1, a1, 16                ; ...
        add   a1, a1, t0                ; ...
        lhu   a5, TH_FP(s0)             ; ...
        call  e_add                     ; ...
        addi  s0, s0, TH_SIZE           ; ...
        j     eb_t                      ; ...
eb_f:   la    s0, fr                    ; the friends (they fidget)
        la    s1, res + R_FRIEND        ; ...
eb_fl:  lwu   a0, FR_X(s0)              ; ...
        lwu   a1, FR_Y(s0)              ; ...
        lhu   a5, 0(s1)                 ; ...
        ld    t0, g_tic - g(gp)         ; ...
        srli  t0, t0, 4                 ; ...
        andi  t0, t0, 1                 ; ...
        add   a5, a5, t0                ; ...
        call  e_add                     ; ...
        addi  s0, s0, FR_SIZE           ; ...
        addi  s1, s1, 16                ; ...
        la    t0, fr + NFRIEND * FR_SIZE ; ...
        bne   s0, t0, eb_fl             ; ...
        sd    s3, e_nvis - g(gp)        ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        addi  sp, sp, 40                ; pop the frame
        ret                             ; done

; e_add(a0 = x, a1 = y in the world, a5 = sprite; s2 = the next vis entry, s3
; = entries so far): if it is in view, its scaled rectangle on the screen,
; put into the order before every nearer one
e_add:  li    t0, MAXVIS                ; (no more than fit)
        bgeu  s3, t0, ea_r              ; ...
        ld    t1, f_px - g(gp)          ; where it is from us
        sub   a0, a0, t1                ; a0 = x
        ld    t1, f_py - g(gp)          ; ...
        sub   a1, a1, t1                ; a1 = y
        ld    t1, e_dirx - g(gp)        ; along the view: the depth
        mul   t1, t1, a0                ; ...
        ld    t2, e_diry - g(gp)        ; ...
        mul   t2, t2, a1                ; ...
        add   t1, t1, t2                ; ...
        srai  a2, t1, 16                ; a2 = depth
        li    t1, 0x3000                ; behind us, or in our face: not drawn
        blt   a2, t1, ea_r              ; ...
        ld    t1, e_plx - g(gp)         ; across the view
        mul   t1, t1, a0                ; ...
        ld    t2, e_ply - g(gp)         ; ...
        mul   t2, t2, a1                ; ...
        add   t1, t1, t2                ; ...
        srai  t1, t1, 16                ; t1 = across
        li    t2, PROJ                  ; its column: 160 + 160 * across / depth
        mul   t1, t1, t2                ; ...
        div   t1, t1, a2                ; ...
        addi  a3, t1, VIEW_W / 2        ; a3 = the column of its anchor
        li    t1, 163840 << 16          ; pixels per texel: 160 / 64 / depth
        divu  a4, t1, a2                ; a4 = the scale, 16.16
        slli  a5, a5, 4                 ; ...
        la    t1, res + R_SPR           ; ...
        add   a5, a5, t1                ; a5 = the sprite's directory entry
        lh    t0, SD_OX(a5)             ; the left edge
        mul   t0, t0, a4                ; ...
        srai  t0, t0, 16                ; ...
        sub   t0, a3, t0                ; t0 = x1
        lhu   t1, SD_W(a5)              ; the right edge
        mul   t1, t1, a4                ; ...
        srai  t1, t1, 16                ; ...
        add   t1, t0, t1                ; t1 = x2
        blez  t1, ea_r                  ; off the screen
        li    t2, VIEW_W                ; ...
        bge   t0, t2, ea_r              ; ...
        beq   t0, t1, ea_r              ; (too far to have a column)
        sw    t0, V_X1(s2)              ; ...
        sw    t1, V_X2(s2)              ; ...
        li    t0, (PROJ / 2) << 16      ; the floor under it: 84 + 80 / depth
        divu  t0, t0, a2                ; ...
        addi  t0, t0, HORIZON           ; ...
        lh    t1, SD_OY(a5)             ; the top edge
        mul   t1, t1, a4                ; ...
        srai  t1, t1, 16                ; ...
        sub   t0, t0, t1                ; t0 = y1
        lhu   t1, SD_H(a5)              ; the bottom edge
        mul   t1, t1, a4                ; ...
        srai  t1, t1, 16                ; ...
        add   t1, t0, t1                ; t1 = y2
        sw    t0, V_Y1(s2)              ; ...
        sw    t1, V_Y2(s2)              ; ...
        sw    a2, V_DEPTH(s2)           ; ...
        li    t0, 26214                 ; texels per pixel: depth * 64 / 160
        mul   t0, t0, a2                ; ...
        srli  t0, t0, 16                ; ...
        sw    t0, V_INV(s2)             ; ...
        sd    a5, V_SPR(s2)             ; ...
        srli  t0, a2, 18                ; its light: a level every four cells
        li    t1, NLIGHT - 1            ; ...
        bleu  t0, t1, ea_1              ; ...
        mv    t0, t1                    ; ...
ea_1:   slli  t0, t0, 8                 ; ...
        la    t1, res + R_CMAP          ; ...
        add   t0, t0, t1                ; ...
        sd    t0, V_LP(s2)              ; ...
        slli  t0, s3, 3                 ; into the order: before every nearer one
        la    t1, visord                ; ...
        add   t0, t0, t1                ; t0 = the place after the last
ea_s:   beq   t0, t1, ea_put            ; ...
        ld    t2, -8(t0)                ; the one before
        lw    t3, V_DEPTH(t2)           ; farther or as far: stay behind it
        bge   t3, a2, ea_put            ; ...
        sd    t2, 0(t0)                 ; nearer: it moves up
        addi  t0, t0, -8                ; ...
        j     ea_s                      ; ...
ea_put: sd    s2, 0(t0)                 ; ...
        addi  s2, s2, V_SIZE            ; ...
        addi  s3, s3, 1                 ; ...
ea_r:   ret                             ; done

; e_slab(): the slab (g_sx0) of the view through her eyes
e_slab: addi  sp, sp, -104              ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = column
        sd    s1, 16(sp)                ; s1 = its byte in the slab
        sd    s2, 24(sp)                ; (e_col uses every one of them)
        sd    s3, 32(sp)                ; ...
        sd    s4, 40(sp)                ; ...
        sd    s5, 48(sp)                ; ...
        sd    s6, 56(sp)                ; ...
        sd    s7, 64(sp)                ; ...
        sd    s8, 72(sp)                ; ...
        sd    s9, 80(sp)                ; ...
        sd    s10, 88(sp)               ; ...
        sd    s11, 96(sp)               ; ...
        ld    s0, g_sx0 - g(gp)         ; ...
        la    s1, slab                  ; ...
es_c:   call  e_col                     ; ...
        addi  s0, s0, 1                 ; ...
        addi  s1, s1, 1                 ; ...
        andi  t0, s0, SLAB_W - 1        ; ...
        bnez  t0, es_c                  ; ...
        call  e_sprites                 ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        ld    s5, 48(sp)                ; ...
        ld    s6, 56(sp)                ; ...
        ld    s7, 64(sp)                ; ...
        ld    s8, 72(sp)                ; ...
        ld    s9, 80(sp)                ; ...
        ld    s10, 88(sp)               ; ...
        ld    s11, 96(sp)               ; ...
        addi  sp, sp, 104               ; pop the frame
        ret                             ; done

; e_col(s0 = column 0..319, s1 = that column's first byte in the slab): cast
; its ray and draw the column. Keeps s0, s1; clobbers everything else.
e_col:  addi  sp, sp, -16               ; frame
        sd    s0, 0(sp)                 ; keep the column
        sd    s1, 8(sp)                 ; ... and its place
        slli  t0, s0, 1                 ; where the column is on the plane: -1 .. 1
        addi  t0, t0, -(VIEW_W - 1)     ;   = (2 x - 319) / 320, 16.16
        li    t1, 205                   ;   (65536 / 320)
        mul   t0, t0, t1                ; ...
        ld    t1, e_plx - g(gp)         ; the ray = dir + plane * that
        mul   t1, t1, t0                ; ...
        srai  t1, t1, 16                ; ...
        ld    s2, e_dirx - g(gp)        ; ...
        add   s2, s2, t1                ; s2 = ray x
        ld    t1, e_ply - g(gp)         ; ...
        mul   t1, t1, t0                ; ...
        srai  t1, t1, 16                ; ...
        ld    s3, e_diry - g(gp)        ; ...
        add   s3, s3, t1                ; s3 = ray y
        ld    t5, f_px - g(gp)          ; t5, t6 = where we stand
        ld    t6, f_py - g(gp)          ; ...
        srli  s4, t5, 16                ; s4, s5 = our cell
        srli  s5, t6, 16                ; ...
        li    t4, 1                     ; t4 = 2^32
        slli  t4, t4, 32                ; ...
        li    t3, 0xffff                ; t3 = the fraction's mask
        li    s6, 0x40000000            ; a ray along y never crosses an x line:
        mv    s8, s6                    ;   s6 = distance between x lines, s8 = to the next
        li    s10, 1                    ; s10 = the step in x
        beqz  s2, ec_y                  ; ...
        mv    t1, s2                    ; |ray x|
        bgez  t1, ec_ax                 ; ...
        neg   t1, t1                    ; ...
ec_ax:  divu  s6, t4, t1                ; 1 / |ray x|
        and   t2, t5, t3                ; how far into the cell we are
        bltz  s2, ec_nx                 ; going west: that far to the line
        xor   t2, t2, t3                ; going east: the rest of the cell
        addi  t2, t2, 1                 ; (65536 - the fraction)
        j     ec_sx                     ; ...
ec_nx:  li    s10, -1                   ; ...
ec_sx:  mul   s8, t2, s6                ; the distance to the first x line
        srli  s8, s8, 16                ; ...
ec_y:   li    s7, 0x40000000            ; the same for y: s7 between lines, s9 to the next
        mv    s9, s7                    ; ...
        li    s11, 1                    ; s11 = the step in y
        beqz  s3, ec_go                 ; ...
        mv    t1, s3                    ; |ray y|
        bgez  t1, ec_ay                 ; ...
        neg   t1, t1                    ; ...
ec_ay:  divu  s7, t4, t1                ; 1 / |ray y|
        and   t2, t6, t3                ; ...
        bltz  s3, ec_ny                 ; ...
        xor   t2, t2, t3                ; ...
        addi  t2, t2, 1                 ; ...
        j     ec_sy                     ; ...
ec_ny:  li    s11, -1                   ; ...
ec_sy:  mul   s9, t2, s7                ; ...
        srli  s9, s9, 16                ; ...
ec_go:  la    a4, res + R_MAP           ; a4 = the world
ec_dda: bltu  s9, s8, ec_dy             ; the nearer line: x ...
        add   s8, s8, s6                ; ...
        add   s4, s4, s10               ; into the next cell
        li    a6, 0                     ; a6 = the side hit: 0 an x line
        j     ec_cell                   ; ...
ec_dy:  add   s9, s9, s7                ; ... or y
        add   s5, s5, s11               ; ...
        li    a6, 1                     ; 1 a y line
ec_cell:
        slli  t0, s5, 6                 ; the cell: 64 to a row
        add   t0, t0, s4                ; ...
        andi  t0, t0, 2047              ; (never outside the array)
        add   t0, t0, a4                ; ...
        lbu   a7, 0(t0)                 ; ...
        andi  a7, a7, 15                ; a7 = its wall
        beqz  a7, ec_dda                ; none: on
        sub   a5, s8, s6                ; a5 = the distance to the line crossed
        beqz  a6, ec_wx                 ; ...
        sub   a5, s9, s7                ; ...
        mul   t0, a5, s2                ; a y line: where along x
        srai  t0, t0, 16                ; ...
        add   t0, t0, t5                ; ...
        srli  t0, t0, 10                ; the texture's column, 64 to a cell
        andi  a3, t0, 63                ; a3 = the column
        blez  s3, ec_tex                ; seen from the north: mirrored (so that pictures read)
        xori  a3, a3, 63                ; ...
        j     ec_tex                    ; ...
ec_wx:  mul   t0, a5, s3                ; an x line: where along y
        srai  t0, t0, 16                ; ...
        add   t0, t0, t6                ; ...
        srli  t0, t0, 10                ; ...
        andi  a3, t0, 63                ; ...
        bgez  s2, ec_tex                ; (seen from the east: mirrored)
        xori  a3, a3, 63                ; ...

; the hit: a5 = distance, a3 = texture column, a7 = wall, a6 = side
ec_tex: li    t0, 1024                  ; (never nearer than 1/64)
        bge   a5, t0, ec_t1             ; ...
        mv    a5, t0                    ; ...
ec_t1:  slli  t0, s0, 2                 ; the depth, for the things
        la    t1, zbuf                  ; ...
        add   t0, t0, t1                ; ...
        sw    a5, 0(t0)                 ; ...
        addi  a7, a7, -1                ; the texture's entry
        slli  a7, a7, 3                 ; ...
        la    t0, res + R_TEX           ; ...
        add   a7, a7, t0                ; ...
        lwu   t0, 0(a7)                 ; the column, in the arena
        slli  a3, a3, 6                 ; ...
        add   t0, t0, a3                ; ...
        ld    t1, g_keepb - g(gp)       ; ...
        add   t0, t0, t1                ; ...
        la    a2, colbuf                ; a2 = the column
        li    t1, 64                    ; ...
        tget  tg8, a2, c0, t0, t1       ; fetch it (the first load from it waits)
        li    t0, PROJ << 16            ; the wall's height in pixels
        divu  a0, t0, a5                ; ...
        srli  a0, a0, 1                 ; a0 = half of it, at least a pixel
        bnez  a0, ec_h1                 ; ...
        li    a0, 1                     ; ...
ec_h1:  li    t0, 32 << 16              ; texels per pixel, 16.16
        divu  a1, t0, a0                ; a1 = the step down the texture
        li    s4, 0                     ; s4 = the place in the texture
        li    t0, HORIZON               ; the first row
        sub   s5, t0, a0                ; s5 = it
        bgez  s5, ec_h2                 ; above the view: start lower in the texture
        neg   t1, s5                    ; ...
        mul   s4, t1, a1                ; ...
        li    s5, 0                     ; ...
        li    a0, HORIZON               ; (the wall fills the column)
ec_h2:  srli  t0, a5, 18                ; the light: a level every four cells, and the
        add   t0, t0, a6                ;   y sides a level darker
        li    t1, NLIGHT - 1            ; ...
        bleu  t0, t1, ec_h3             ; ...
        mv    t0, t1                    ; ...
ec_h3:  slli  t0, t0, 8                 ; a6 = that row of the colour map
        la    a6, res + R_CMAP          ; ...
        add   a6, a6, t0                ; ...
        slli  t0, s5, 5                 ; t2 = the first byte to draw
        add   t2, s1, t0                ; ...
        slli  t3, a0, 1                 ; t3 = rows of wall
        li    t4, 63                    ; (the texture's last row)
ec_w:   srli  t0, s4, 16                ; the texel
        bleu  t0, t4, ec_w1             ; ...
        mv    t0, t4                    ; ...
ec_w1:  add   t0, t0, a2                ; ...
        lbu   t0, 0(t0)                 ; ...
        add   t0, t0, a6                ; shaded
        lbu   t0, 0(t0)                 ; ...
        sb    t0, 0(t2)                 ; ...
        add   s4, s4, a1                ; down the texture
        addi  t2, t2, SLAB_W            ; down the slab
        addi  t3, t3, -1                ; ...
        bnez  t3, ec_w                  ; ...

; floor and ceiling: row k below the horizon is at distance rowd[k] along the
; view, whatever the column; the ray gives the place on the floor, the cell
; there its flat; the ceiling's row above the horizon is its mirror, and is
; sky where the floor is out of doors
        li    t0, HORIZON               ; rows left under the wall
        bge   a0, t0, ec_ret            ; none
        la    s6, res + R_ROWD          ; s6 = the row's distance
        slli  t0, a0, 2                 ; ...
        add   s6, s6, t0                ; ...
        la    s7, res + R_ROWL          ; s7 = its light
        add   s7, s7, a0                ; ...
        la    s8, e_flatp               ; s8 = the flats
        ld    s9, 5 * 8(s8)             ; s9 = the ceiling's (after the five floors:
        addi  s9, s9, 1024              ;   in_buf's second KiB)
        la    s10, res + R_CMAP         ; s10 = the colour map
        li    t0, HORIZON - 1           ; s5 = the ceiling's byte
        sub   t0, t0, a0                ; ...
        slli  t0, t0, 5                 ; ...
        add   s5, s1, t0                ; ...
        li    s11, HORIZON              ; s11 = rows to do
        sub   s11, s11, a0              ; ...
        li    a3, C_SKY                 ; a3 = the sky
ec_f:   lwu   t0, 0(s6)                 ; the distance
        mul   t1, t0, s2                ; the place: x ...
        srai  t1, t1, 16                ; ...
        add   t1, t1, t5                ; ...
        mul   t0, t0, s3                ; ... and y
        srai  t0, t0, 16                ; ...
        add   t0, t0, t6                ; ...
        srli  t3, t0, 10                ; the cell there
        andi  t3, t3, 0x7c0             ; ...
        srli  t4, t1, 16                ; ...
        andi  t4, t4, 63                ; ...
        or    t3, t3, t4                ; ...
        add   t3, t3, a4                ; ...
        lbu   t3, 0(t3)                 ; ...
        srli  t3, t3, 4                 ; a5 = its floor's kind
        andi  a5, t3, 7                 ; ...
        srli  t1, t1, 11                ; the texel: 32 x 32, once across a cell
        andi  t1, t1, 31                ; ...
        srli  t0, t0, 6                 ; ...
        andi  t0, t0, 0x3e0             ; ...
        or    t1, t1, t0                ; ...
        lbu   t3, 0(s7)                 ; the row's light
        slli  t3, t3, 8                 ; ...
        add   t3, t3, s10               ; ...
        slli  t0, a5, 3                 ; the floor
        add   t0, t0, s8                ; ...
        ld    t0, 0(t0)                 ; ...
        add   t0, t0, t1                ; ...
        lbu   t0, 0(t0)                 ; ...
        add   t0, t0, t3                ; ...
        lbu   t0, 0(t0)                 ; ...
        sb    t0, 0(t2)                 ; ...
        mv    t0, a3                    ; the ceiling: the sky over kinds 2 and up
        li    t4, 2                     ; ...
        bgeu  a5, t4, ec_c              ; ...
        add   t0, s9, t1                ; ...
        lbu   t0, 0(t0)                 ; ...
        add   t0, t0, t3                ; ...
        lbu   t0, 0(t0)                 ; ...
ec_c:   sb    t0, 0(s5)                 ; ...
        addi  s6, s6, 4                 ; the next row out
        addi  s7, s7, 1                 ; ...
        addi  t2, t2, SLAB_W            ; ...
        addi  s5, s5, -SLAB_W           ; ...
        addi  s11, s11, -1              ; ...
        bnez  s11, ec_f                 ; ...
ec_ret: ld    s0, 0(sp)                 ; the column
        ld    s1, 8(sp)                 ; ...
        addi  sp, sp, 16                ; pop the frame
        ret                             ; done

; e_sprites(): the visible things' columns that fall into the slab
; (g_sx0 .. g_sx0 + 31), far to near, behind the walls
e_sprites:
        addi  sp, sp, -56               ; frame
        sd    s0, 0(sp)                 ; s0 = place in the order
        sd    s1, 8(sp)                 ; s1 = things left
        sd    s2, 16(sp)                ; s2 = the entry
        sd    s3, 24(sp)                ; s3 = column
        sd    s4, 32(sp)                ; s4 = past the last column
        sd    s5, 40(sp)                ; s5 = the sprite's column in colbuf
        sd    s6, 48(sp)                ; s6 = the slab's first column
        la    s0, visord                ; ...
        ld    s1, e_nvis - g(gp)        ; ...
        ld    s6, g_sx0 - g(gp)         ; ...
ep_l:   beqz  s1, ep_d                  ; ...
        ld    s2, 0(s0)                 ; ...
        lw    s3, V_X1(s2)              ; its columns, clipped to the slab
        bge   s3, s6, ep_1              ; ...
        mv    s3, s6                    ; ...
ep_1:   lw    s4, V_X2(s2)              ; ...
        addi  t0, s6, SLAB_W            ; ...
        ble   s4, t0, ep_2              ; ...
        mv    s4, t0                    ; ...
ep_2:   li    s5, -1                    ; (no column fetched yet)
ep_c:   bge   s3, s4, ep_n              ; ...
        slli  t0, s3, 2                 ; behind the wall here?
        la    t1, zbuf                  ; ...
        add   t0, t0, t1                ; ...
        lwu   t0, 0(t0)                 ; ...
        lw    t1, V_DEPTH(s2)           ; ...
        bge   t1, t0, ep_cn             ; yes
        lw    t0, V_X1(s2)              ; the sprite's column for this one
        sub   t0, s3, t0                ; ...
        lwu   a3, V_INV(s2)             ; a3 = texels per pixel
        mul   t0, t0, a3                ; ...
        srli  t0, t0, 16                ; ...
        ld    a4, V_SPR(s2)             ; a4 = the sprite
        lhu   t1, SD_W(a4)              ; (inside it)
        bltu  t0, t1, ep_3              ; ...
        addi  t0, t1, -1                ; ...
ep_3:   beq   t0, s5, ep_4              ; already in colbuf
        mv    s5, t0                    ; fetch it
        lhu   t1, SD_CS(a4)             ; ...
        mul   t0, t0, t1                ; ...
        lwu   t2, SD_OFF(a4)            ; ...
        add   t0, t0, t2                ; ...
        ld    t2, g_keepb - g(gp)       ; ...
        add   t0, t0, t2                ; ...
        la    t2, colbuf                ; ...
        tget  tg8, t2, c0, t0, t1       ; ...
ep_4:   lw    t0, V_Y1(s2)              ; its rows, clipped to the view
        li    t3, 0                     ; t3 = the place in the sprite's column, 16.16
        bgez  t0, ep_5                  ; ...
        neg   t3, t0                    ; ...
        mul   t3, t3, a3                ; ...
        li    t0, 0                     ; ...
ep_5:   lw    t1, V_Y2(s2)              ; ...
        li    t2, VIEW_H                ; ...
        ble   t1, t2, ep_6              ; ...
        mv    t1, t2                    ; ...
ep_6:   sub   t1, t1, t0                ; t1 = rows
        blez  t1, ep_cn                 ; ...
        slli  t0, t0, 5                 ; t0 = the byte in the slab
        la    t2, slab                  ; ...
        add   t0, t0, t2                ; ...
        add   t0, t0, s3                ; ...
        sub   t0, t0, s6                ; ...
        lhu   a5, SD_H(a4)              ; a5 = the sprite's rows
        ld    a6, V_LP(s2)              ; a6 = its light
        la    a7, colbuf                ; a7 = the column
        li    t5, 255                   ; t5 = "transparent"
ep_y:   srli  t2, t3, 16                ; the texel
        bgeu  t2, a5, ep_cn             ; (past the sprite's end)
        add   t2, t2, a7                ; ...
        lbu   t2, 0(t2)                 ; ...
        beq   t2, t5, ep_yn             ; ...
        add   t2, t2, a6                ; shaded
        lbu   t2, 0(t2)                 ; ...
        sb    t2, 0(t0)                 ; ...
ep_yn:  add   t3, t3, a3                ; ...
        addi  t0, t0, SLAB_W            ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, ep_y                  ; ...
ep_cn:  addi  s3, s3, 1                 ; the next column
        j     ep_c                      ; ...
ep_n:   addi  s0, s0, 8                 ; the next thing
        addi  s1, s1, -1                ; ...
        j     ep_l                      ; ...
ep_d:   ld    s0, 0(sp)                 ; restore
        ld    s1, 8(sp)                 ; ...
        ld    s2, 16(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        ld    s5, 40(sp)                ; ...
        ld    s6, 48(sp)                ; ...
        addi  sp, sp, 56                ; pop the frame
        ret                             ; done
