; =============================================================================
; draw.s: kira's screen: 320 x 200 palette indices, drawn in slabs
; =============================================================================
;
; The screen is a 320 x 168 view over a 32-row bar, as wdoom's, and is drawn
; the same way: in ten SLABS of 32 columns, because a whole view does not fit
; the D-LS. For each slab of the view:
;   view_slab  the activity fills it: a run-length-coded picture (pic_slab),
;              the world's tiles (friends.s), ...
;   over_slab  what lies over every activity: the message, the hearts and
;              stars, the hand that the arrow keys move;
;   r_push     turns each row into XRGB8888 through the palette, scaled by
;              the window's factor, and sends it into the band (`tput`).
; The bar is drawn likewise, all ten slabs in one group (r_bar). Sprites are
; column-major in the arena and are fetched a column at a time (r_blit).

VIEW_W    = 320                         ; the view's columns
VIEW_H    = 168                         ; its rows
BAR_H     = 32                          ; the bar's rows
SLAB_W    = 32                          ; columns per slab
NSLAB     = 10                          ; slabs in the view

; ---- a sprite's directory entry (dat.s: R_SPR) ---------------------------------
SD_OFF    = 0                           ; far offset (u32)
SD_W      = 4                           ; columns
SD_H      = 6                           ; rows
SD_OX     = 8                           ; the anchor's column
SD_OY     = 10                          ; ... and row
SD_CS     = 12                          ; bytes per column
SD_SIZE   = 16                          ; bytes

; ---- a particle (a heart, a star) ----------------------------------------------
P_X       = 0                           ; position on the screen, 16.16 (s32)
P_Y       = 4                           ; ...
P_VX      = 8                           ; velocity, 16.16 a tic (s32)
P_VY      = 12                          ; ...
P_LIFE    = 16                          ; tics left (0: free)
P_SPR     = 20                          ; its sprite
P_SIZE    = 24                          ; bytes
NPART     = 20                          ; particles at most

        .data                           ; D-LS
        .align 8                        ; dwords
slab:     .space SLAB_W * VIEW_H        ; the slab: palette indices, row-major
rowbuf:   .space SLAB_W * 4 * 4         ; a row of it as pixels, at up to 4 x
colbuf:   .space 128                    ; a sprite column
scratch:  .space 2048                   ; a picture's coded slab; a tile; a queue
parts:    .space NPART * P_SIZE         ; the particles
        .text                           ; code

; pic_slab(a0 = picture): the slab (g_sx0) of that picture, decoded
pic_slab:
        li    t0, 80                    ; the picture's ten entries
        mul   a0, a0, t0                ; ...
        ld    t0, g_sx0 - g(gp)         ; the slab's
        srli  t0, t0, 2                 ; (8 bytes each)
        add   a0, a0, t0                ; ...
        la    t0, res + R_PIC           ; ...
        add   a0, a0, t0                ; ...
        lwu   t0, 0(a0)                 ; its far offset
        ld    t1, g_keepb - g(gp)       ; ...
        add   t0, t0, t1                ; ...
        lhu   t1, 4(a0)                 ; its bytes, in whole words
        addi  t1, t1, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        la    t2, scratch               ; ...
        tget  tg8, t2, c0, t0, t1       ; fetch it (the first load from it waits)
        la    t3, slab                  ; t3 = the next byte of the slab
        li    t4, SLAB_W * VIEW_H       ; t4 = its end
        add   t4, t4, t3                ; ...
ps_l:   lbu   t0, 0(t2)                 ; a run: how many, of what
        lbu   t1, 1(t2)                 ; ...
        addi  t2, t2, 2                 ; ...
ps_r:   sb    t1, 0(t3)                 ; ...
        addi  t3, t3, 1                 ; ...
        addi  t0, t0, -1                ; ...
        bnez  t0, ps_r                  ; ...
        bltu  t3, t4, ps_l              ; ...
        ret                             ; done

; r_put(a0 = sprite, a1 = x, a2 = y of its anchor on the 320 x 200 screen)
r_put:  slli  t0, a0, 4                 ; the sprite's entry
        la    t1, res + R_SPR           ; ...
        add   t0, t0, t1                ; ...
        lh    t1, SD_OX(t0)             ; its corner from its anchor
        sub   a1, a1, t1                ; ...
        lh    t1, SD_OY(t0)             ; ...
        sub   a2, a2, t1                ; ...
; r_blit(a0 = sprite, a1 = x, a2 = y of its top left corner on the 320 x 200
; screen): the part of it in the slab and in the pass's rows (g_py0, g_ph).
; With g_sil set every pixel of it has that colour (a silhouette).
r_blit: slli  a0, a0, 4                 ; the sprite
        la    t0, res + R_SPR           ; ...
        add   a0, a0, t0                ; a0 = its entry
        ld    a3, g_sx0 - g(gp)         ; a3 = the slab's first column
        mv    a4, a1                    ; a4 = column, from the later of the two starts
        bge   a4, a3, rb_1              ; ...
        mv    a4, a3                    ; ...
rb_1:   lhu   a5, SD_W(a0)              ; a5 = past the last column: the earlier end
        add   a5, a5, a1                ; ...
        addi  t0, a3, SLAB_W            ; ...
        ble   a5, t0, rb_2              ; ...
        mv    a5, t0                    ; ...
rb_2:   ld    t4, g_py0 - g(gp)         ; t4 = the pass's first row
        mv    a6, a2                    ; a6 = the first row drawn
        bge   a6, t4, rb_3              ; ...
        mv    a6, t4                    ; ...
rb_3:   lhu   a7, SD_H(a0)              ; a7 = rows drawn: to the earlier end
        add   a7, a7, a2                ; ...
        ld    t0, g_ph - g(gp)          ; ...
        add   t0, t0, t4                ; ...
        ble   a7, t0, rb_4              ; ...
        mv    a7, t0                    ; ...
rb_4:   sub   a7, a7, a6                ; ...
        blez  a7, rb_r                  ; none
        li    t5, 255                   ; t5 = "transparent"
        ld    t6, g_sil - g(gp)         ; t6 = the silhouette's colour (0: none)
rb_c:   bge   a4, a5, rb_r              ; ...
        sub   t0, a4, a1                ; fetch the column
        lhu   t1, SD_CS(a0)             ; ...
        mul   t0, t0, t1                ; ...
        lwu   t2, SD_OFF(a0)            ; ...
        add   t0, t0, t2                ; ...
        ld    t2, g_keepb - g(gp)       ; ...
        add   t0, t0, t2                ; ...
        la    t2, colbuf                ; ...
        tget  tg8, t2, c0, t0, t1       ; ...
        sub   t0, a6, a2                ; t2 = the first texel
        add   t2, t2, t0                ; ...
        sub   t0, a6, t4                ; t0 = the byte in the slab
        slli  t0, t0, 5                 ; ...
        la    t1, slab                  ; ...
        add   t0, t0, t1                ; ...
        add   t0, t0, a4                ; ...
        sub   t0, t0, a3                ; ...
        mv    t1, a7                    ; t1 = rows
rb_y:   lbu   t3, 0(t2)                 ; ...
        beq   t3, t5, rb_yn             ; ...
        beqz  t6, rb_ys                 ; ...
        mv    t3, t6                    ; ...
rb_ys:  sb    t3, 0(t0)                 ; ...
rb_yn:  addi  t2, t2, 1                 ; ...
        addi  t0, t0, SLAB_W            ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, rb_y                  ; ...
        addi  a4, a4, 1                 ; the next column
        j     rb_c                      ; ...
rb_r:   ret                             ; done

; spr_w(a0 = sprite) -> a0 = its width
spr_w:  slli  a0, a0, 4                 ; ...
        la    t0, res + R_SPR           ; ...
        add   a0, a0, t0                ; ...
        lhu   a0, SD_W(a0)              ; ...
        ret                             ; done

; p_spawn(a0 = x, a1 = y on the screen, a2 = vx, a3 = vy (16.16 a tic), a4 =
; sprite, a5 = tics it lives): a particle, if one is free
p_spawn:
        la    t0, parts                 ; a free one
        li    t1, NPART                 ; ...
pw_l:   lw    t2, P_LIFE(t0)            ; ...
        beqz  t2, pw_f                  ; ...
        addi  t0, t0, P_SIZE            ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, pw_l                  ; ...
        ret                             ; none
pw_f:   slli  a0, a0, 16                ; ...
        slli  a1, a1, 16                ; ...
        sw    a0, P_X(t0)               ; ...
        sw    a1, P_Y(t0)               ; ...
        sw    a2, P_VX(t0)              ; ...
        sw    a3, P_VY(t0)              ; ...
        sw    a5, P_LIFE(t0)            ; ...
        sw    a4, P_SPR(t0)             ; ...
        ret                             ; done

; p_step(): the particles move (and the picture changes while there are any)
p_step: la    t0, parts                 ; ...
        li    t1, NPART                 ; ...
pt_l:   lw    t2, P_LIFE(t0)            ; ...
        beqz  t2, pt_n                  ; ...
        addi  t2, t2, -1                ; ...
        sw    t2, P_LIFE(t0)            ; ...
        lw    t2, P_X(t0)               ; ...
        lw    t3, P_VX(t0)              ; ...
        add   t2, t2, t3                ; ...
        sw    t2, P_X(t0)               ; ...
        lw    t2, P_Y(t0)               ; ...
        lw    t3, P_VY(t0)              ; ...
        add   t2, t2, t3                ; ...
        sw    t2, P_Y(t0)               ; ...
        li    t2, 1                     ; ...
        sd    t2, g_dirty - g(gp)       ; ...
pt_n:   addi  t0, t0, P_SIZE            ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, pt_l                  ; ...
        ret                             ; done

; p_clear(): no particles
p_clear:
        la    t0, parts                 ; ...
        li    t1, NPART                 ; ...
pc_l:   sw    zero, P_LIFE(t0)          ; ...
        addi  t0, t0, P_SIZE            ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, pc_l                  ; ...
        ret                             ; done

; over_slab(): what lies over every activity, in the slab and the pass's
; rows: the message (a number and a word, or a word), the particles, the hand
over_slab:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = particle; the message's left edge
        sd    s1, 16(sp)                ; s1 = particles left
        ld    t0, g_mode - g(gp)        ; the message (not over the menu)
        beqz  t0, ov_p                  ; ...
        ld    a0, g_msg - g(gp)         ; ...
        bltz  a0, ov_p                  ; ...
        call  spr_w                     ; centred: the word alone ...
        li    s0, VIEW_W                ; ...
        sub   s0, s0, a0                ; ...
        ld    t0, g_msgn - g(gp)        ; ... or after its number (24 wide, 4 between)
        bltz  t0, ov_w                  ; ...
        addi  s0, s0, -28               ; ...
        srai  s0, s0, 1                 ; ...
        mv    a0, t0                    ; ...
        mv    a1, s0                    ; ...
        li    a2, 6                     ; ...
        call  r_blit                    ; ...
        addi  s0, s0, 28                ; ...
        j     ov_w1                     ; ...
ov_w:   srai  s0, s0, 1                 ; ...
ov_w1:  ld    a0, g_msg - g(gp)         ; ...
        mv    a1, s0                    ; ...
        li    a2, 10                    ; ...
        call  r_blit                    ; ...
ov_p:   la    s0, parts                 ; the particles
        li    s1, NPART                 ; ...
ov_pl:  lw    t0, P_LIFE(s0)            ; ...
        beqz  t0, ov_pn                 ; ...
        lw    a0, P_SPR(s0)             ; ...
        lw    a1, P_X(s0)               ; ...
        srai  a1, a1, 16                ; ...
        lw    a2, P_Y(s0)               ; ...
        srai  a2, a2, 16                ; ...
        call  r_blit                    ; ...
ov_pn:  addi  s0, s0, P_SIZE            ; ...
        addi  s1, s1, -1                ; ...
        bnez  s1, ov_pl                 ; ...
        ld    t0, g_curon - g(gp)       ; the hand (its fingertip is at 3, 1), where
        beqz  t0, ov_r                  ;   the arrows move it and not Kira
        ld    t0, g_mode - g(gp)        ; ...
        li    t1, M_FRIENDS             ; ...
        beq   t0, t1, ov_r              ; ...
        li    a0, SP_CURSOR             ; ...
        ld    a1, g_curx - g(gp)        ; ...
        addi  a1, a1, -3                ; ...
        ld    a2, g_cury - g(gp)        ; ...
        addi  a2, a2, -1                ; ...
        call  r_blit                    ; ...
ov_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; r_push(a0 = the slab's number in its group): the pass's rows as pixels,
; g_scale times as wide and as high, into the band (rows g_stride apart)
r_push: addi  sp, sp, -8                ; frame
        sd    s0, 0(sp)                 ; s0 = rows left
        ld    a1, g_scale - g(gp)       ; a1 = the factor
        slli  a2, a1, 7                 ; a2 = bytes of a row of the slab on the screen
        mul   a0, a0, a2                ; a0 = where the row starts in the band
        ld    a3, g_stride - g(gp)      ; a3 = the band's stride
        la    a4, slab                  ; a4 = the row
        la    a5, res + R_PAL           ; a5 = the palette
        ld    s0, g_ph - g(gp)          ; ...
        la    a7, rowbuf                ; a7 = the row as pixels
rq_r:   mv    t0, a7                    ; t0 = the next pixel
        addi  t1, a4, SLAB_W            ; t1 = the row's end
rq_p:   lbu   t2, 0(a4)                 ; an index ...
        slli  t2, t2, 2                 ; ...
        add   t2, t2, a5                ; ...
        lwu   t2, 0(t2)                 ; ... its colour ...
        mv    t3, a1                    ; ... as many times as the factor
rq_s:   sw    t2, 0(t0)                 ; ...
        addi  t0, t0, 4                 ; ...
        addi  t3, t3, -1                ; ...
        bnez  t3, rq_s                  ; ...
        addi  a4, a4, 1                 ; ...
        bne   a4, t1, rq_p              ; ...
        mv    t3, a1                    ; the row, as many times as the factor
rq_t:   tput  tg9, a7, c0, a0, a2       ; (the next row's stores wait for it)
        add   a0, a0, a3                ; ...
        addi  t3, t3, -1                ; ...
        bnez  t3, rq_t                  ; ...
        addi  s0, s0, -1                ; ...
        bnez  s0, rq_r                  ; ...
        ld    s0, 0(sp)                 ; restore
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; r_damage(a0 = first slab, a1 = slabs, a2 = first row on the 320 x 200
; screen, a3 = rows): lend the band: those slabs' pixels are in it
r_damage:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        twait (1 << 8) | (1 << 9)       ; our transfers are done
        ld    t1, g_scale - g(gp)       ; the rectangle in the window
        la    t0, wc_d                  ; data: x, y, w, h, stride
        slli  a0, a0, 5                 ; x
        mul   a0, a0, t1                ; ...
        ld    t2, g_ox - g(gp)          ; ...
        add   a0, a0, t2                ; ...
        sd    a0, 0(t0)                 ; ...
        mul   a2, a2, t1                ; y
        ld    t2, g_oy - g(gp)          ; ...
        add   a2, a2, t2                ; ...
        sd    a2, 8(t0)                 ; ...
        slli  a1, a1, 5                 ; w
        mul   a1, a1, t1                ; ...
        sd    a1, 16(t0)                ; ...
        mul   a3, a3, t1                ; h
        sd    a3, 24(t0)                ; ...
        ld    t2, g_stride - g(gp)      ; ...
        sd    t2, 32(t0)                ; ...
        mv    a0, t0                    ; ...
        li    a1, 40                    ; ...
        call  sys_put                   ; ...
        li    a0, WC_EP                 ; DAMAGE, with the arena (c0) attached
        li    a1, OP_WDAMAGE            ; ...
        la    t0, wc_id                 ; ...
        ld    a2, 0(t0)                 ; ...
        li    a3, 40                    ; ...
        li    a4, 0                     ; ...
        li    a5, 0                     ; (register 0)
        call  sys_msga                  ; a0 = result; the arena is back in c6
        cvalid t0, c6                   ; ...
        beqz  t0, rd_r                  ; (nothing was sent)
        cmov  c0, c6                    ; home
rd_r:   ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; r_frame(): the whole view, in groups of as many slabs as the band holds
; (g_grp), each group lent to the server as it is done; then the bar if it
; changed
r_frame:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s2, 8(sp)                 ; s2 = the group's first slab
        sd    s3, 16(sp)                ; s3 = slabs in the group
        sd    s4, 24(sp)                ; s4 = the slab in the group
        ld    t0, g_scale - g(gp)       ; (a window too small for it: nothing)
        beqz  t0, rf_r                  ; ...
        sd    zero, g_py0 - g(gp)       ; the pass: the view's rows
        li    t0, VIEW_H                ; ...
        sd    t0, g_ph - g(gp)          ; ...
        li    s2, 0                     ; ...
rf_g:   li    s3, NSLAB                 ; the group: what is left, at most g_grp
        sub   s3, s3, s2                ; ...
        ld    t0, g_grp - g(gp)         ; ...
        ble   s3, t0, rf_g1             ; ...
        mv    s3, t0                    ; ...
rf_g1:  ld    t0, g_scale - g(gp)       ; its stride in the band
        mul   t0, t0, s3                ; ...
        slli  t0, t0, 7                 ; ...
        sd    t0, g_stride - g(gp)      ; ...
        li    s4, 0                     ; ...
rf_s:   add   t0, s2, s4                ; the slab's columns
        slli  t0, t0, 5                 ; ...
        sd    t0, g_sx0 - g(gp)         ; ...
        call  view_slab                 ; ...
        call  over_slab                 ; ...
        mv    a0, s4                    ; ...
        call  r_push                    ; ...
        addi  s4, s4, 1                 ; ...
        bne   s4, s3, rf_s              ; ...
        mv    a0, s2                    ; the group is drawn: show it
        mv    a1, s3                    ; ...
        li    a2, 0                     ; ...
        li    a3, VIEW_H                ; ...
        call  r_damage                  ; ...
        add   s2, s2, s3                ; ...
        li    t0, NSLAB                 ; ...
        blt   s2, t0, rf_g              ; ...
        ld    t0, g_bardirty - g(gp)    ; the bar?
        beqz  t0, rf_r                  ; ...
        sd    zero, g_bardirty - g(gp)  ; ...
        call  r_bar                     ; ...
rf_r:   ld    ra, 0(sp)                 ; restore
        ld    s2, 8(sp)                 ; ...
        ld    s3, 16(sp)                ; ...
        ld    s4, 24(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

; r_bar(): the bar: its picture (ten pieces, one per slab), the activity's
; icons over it (bar_slab), the hand; one group
r_bar:  addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = slab
        li    t0, VIEW_H                ; the pass: the bar's rows
        sd    t0, g_py0 - g(gp)         ; ...
        li    t0, BAR_H                 ; ...
        sd    t0, g_ph - g(gp)          ; ...
        ld    t0, g_scale - g(gp)       ; all ten slabs in the band
        li    t1, NSLAB * SLAB_W * 4    ; ...
        mul   t0, t0, t1                ; ...
        sd    t0, g_stride - g(gp)      ; ...
        li    s0, 0                     ; ...
rr_s:   slli  t0, s0, 5                 ; ...
        sd    t0, g_sx0 - g(gp)         ; ...
        slli  t0, s0, 10                ; the piece: 1024 bytes
        li    t1, F_BAR                 ; ...
        add   t0, t0, t1                ; ...
        ld    t1, g_keepb - g(gp)       ; ...
        add   t0, t0, t1                ; ...
        la    t1, slab                  ; ...
        li    t2, 1024                  ; ...
        tget  tg8, t1, c0, t0, t2       ; ...
        twait 1 << 8                    ; (the icons' stores come after it)
        call  bar_slab                  ; ...
        call  over_slab                 ; ...
        mv    a0, s0                    ; ...
        call  r_push                    ; ...
        addi  s0, s0, 1                 ; ...
        li    t0, NSLAB                 ; ...
        blt   s0, t0, rr_s              ; ...
        li    a0, 0                     ; ...
        li    a1, NSLAB                 ; ...
        li    a2, VIEW_H                ; ...
        li    a3, BAR_H                 ; ...
        call  r_damage                  ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 16                ; pop the frame
        ret                             ; done
