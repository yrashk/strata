; fr_click(a0 = x, a1 = y in the view): she walks to that cell
fr_click:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    a0, 8(sp)                 ; x
        sd    a1, 16(sp)                ; y
        call  fr_again                  ; ...
        bnez  a0, fc_r                  ; ...
        ld    a0, 8(sp)                 ; the cell on the screen
        srli  a0, a0, 4                 ; ...
        ld    a1, 16(sp)                ; ...
        addi  a1, a1, -TILE_Y0          ; ...
        bgez  a1, fc_1                  ; ...
        li    a1, 0                     ; ...
fc_1:   srli  a1, a1, 4                 ; ...
        li    t0, SCR_H - 1             ; ...
        bleu  a1, t0, fc_2              ; ...
        mv    a1, t0                    ; ...
fc_2:   li    t0, 0                     ; a cell at the screen's edge: on to the next screen
        bnez  a0, fc_3                  ; ...
        li    t0, K_LEFT                ; ...
fc_3:   li    t1, SCR_W - 1             ; ...
        bne   a0, t1, fc_4              ; ...
        li    t0, K_RIGHT               ; ...
fc_4:   bnez  a1, fc_5                  ; ...
        li    t0, K_UP                  ; ...
fc_5:   li    t1, SCR_H - 1             ; ...
        bne   a1, t1, fc_6              ; ...
        li    t0, K_DOWN                ; ...
fc_6:   sd    t0, f_edge - g(gp)        ; ...
        call  fr_flow                   ; ...
        li    t0, 1                     ; ...
        sd    t0, f_path - g(gp)        ; ...
        sd    zero, f_want - g(gp)      ; ...
fc_r:   ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; fr_flow(a0 = x, a1 = y: a cell of the screen): flood the screen from that
; cell (from the cells around it, if it cannot be walked on): f_flow of
; every cell reached = the step from it that leads there (FL_HERE in the
; target itself), 0 where there is no way. The queue is in `scratch`.
fr_flow:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the queue's head
        sd    s1, 16(sp)                ; s1 = its tail
        sd    s2, 24(sp)                ; s2 = the cell taken from it: x
        sd    s3, 32(sp)                ; s3 = ... and y
        sd    s4, 40(sp)                ; s4 = direction
        mv    s2, a0                    ; ...
        mv    s3, a1                    ; ...
        la    t0, f_flow                ; no notes yet
        li    t1, SCR_W * SCR_H / 8     ; ...
fw_z:   sd    zero, 0(t0)               ; ...
        addi  t0, t0, 8                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, fw_z                  ; ...
        la    s0, scratch               ; ...
        mv    s1, s0                    ; ...
        mv    a0, s2                    ; the target ...
        mv    a1, s3                    ; ...
        li    a2, FL_HERE               ; ...
        call  fw_put                    ; ...
        bne   s0, s1, fw_l              ; ...
        li    s4, K_RIGHT               ; ... or, if it is a wall, the cells around it
fw_s:   la    t0, f_ddx                 ; ...
        add   t0, t0, s4                ; ...
        lb    a0, 0(t0)                 ; ...
        add   a0, a0, s2                ; ...
        lb    a1, f_ddy - f_ddx(t0)     ; ...
        add   a1, a1, s3                ; ...
        li    a2, FL_HERE               ; ...
        call  fw_put                    ; ...
        addi  s4, s4, -1                ; ...
        bnez  s4, fw_s                  ; ...
fw_l:   beq   s0, s1, fw_r              ; the queue is empty: done
        lbu   t0, 0(s0)                 ; a cell from it
        addi  s0, s0, 1                 ; ...
        li    t1, SCR_W                 ; ...
        remu  s2, t0, t1                ; ...
        divu  s3, t0, t1                ; ...
        li    s4, K_RIGHT               ; its four neighbours: the step back is the note
fw_n:   la    t0, f_ddx                 ; ...
        add   t0, t0, s4                ; ...
        lb    a0, 0(t0)                 ; ...
        add   a0, a0, s2                ; ...
        lb    a1, f_ddy - f_ddx(t0)     ; ...
        add   a1, a1, s3                ; ...
        lbu   a2, f_opp - f_ddx(t0)     ; ...
        call  fw_put                    ; ...
        addi  s4, s4, -1                ; ...
        bnez  s4, fw_n                  ; ...
        j     fw_l                      ; ...
fw_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        addi  sp, sp, 48                ; pop the frame
        ret                             ; done
; fw_put(a0 = x, a1 = y on the screen, a2 = note): if the cell is on the
; screen, has no note and can be walked on: note it and queue it (s1)
fw_put: li    t0, SCR_W                 ; on the screen?
        bgeu  a0, t0, fu_r              ; ...
        li    t1, SCR_H                 ; ...
        bgeu  a1, t1, fu_r              ; ...
        mul   t1, a1, t0                ; t1 = its number
        add   t1, t1, a0                ; ...
        la    t2, f_flow                ; ...
        add   t2, t2, t1                ; t2 = its note
        lbu   t3, 0(t2)                 ; ...
        bnez  t3, fu_r                  ; ...
        ld    t3, f_scry - g(gp)        ; the cell in the world
        add   t3, t3, a1                ; ...
        slli  t3, t3, 6                 ; ...
        add   t3, t3, a0                ; ...
        ld    t4, f_scrx - g(gp)        ; ...
        add   t3, t3, t4                ; ...
        la    t4, res + R_MAP           ; ...
        add   t3, t3, t4                ; ...
        lbu   t3, 0(t3)                 ; ...
        andi  t3, t3, 0x8f              ; ...
        bnez  t3, fu_r                  ; ...
        sb    a2, 0(t2)                 ; ...
        sb    t1, 0(s1)                 ; ...
        addi  s1, s1, 1                 ; ...
fu_r:   ret                             ; done

; td_slab(): the slab of the world seen from above: two columns of tiles,
; then the things, the friends and Kira, row by row from the back
td_slab:
        addi  sp, sp, -64               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = row of the screen
        sd    s1, 16(sp)                ; s1 = column of the slab (0, 1); a thing; a friend
        sd    s2, 24(sp)                ; s2 = the tile in `scratch` (-1: none)
        sd    s3, 32(sp)                ; s3 = the world's row
        sd    s4, 40(sp)                ; s4 = friends left
        sd    s5, 48(sp)                ; s5 = the friend's entry in dat.s's R_FRIEND
        la    t0, slab                  ; the strips above and below the tiles
        la    t3, slab + SLAB_W * (VIEW_H - TILE_Y0) ; ...
        li    t1, SLAB_W * TILE_Y0      ; ...
        li    t2, C_EDGE                ; ...
ts_e:   sb    t2, 0(t0)                 ; ...
        sb    t2, 0(t3)                 ; ...
        addi  t0, t0, 1                 ; ...
        addi  t3, t3, 1                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, ts_e                  ; ...
        li    s2, -1                    ; ...
        li    s0, 0                     ; ...
ts_j:   li    s1, 0                     ; ...
ts_i:   ld    t0, f_scry - g(gp)        ; the cell
        add   t0, t0, s0                ; ...
        slli  t0, t0, 6                 ; ...
        ld    t1, f_scrx - g(gp)        ; ...
        add   t0, t0, t1                ; ...
        ld    t1, g_sx0 - g(gp)         ; ...
        srli  t1, t1, 4                 ; ...
        add   t0, t0, t1                ; ...
        add   t0, t0, s1                ; ...
        la    t1, res + R_MAP           ; ...
        add   t0, t0, t1                ; ...
        lbu   t0, 0(t0)                 ; ...
        andi  t1, t0, 15                ; a wall: tiles 0..5
        addi  t1, t1, -1                ; ...
        bgez  t1, ts_t                  ; ...
        srli  t1, t0, 4                 ; a floor: tiles 6..10
        andi  t1, t1, 7                 ; ...
        addi  t1, t1, 6                 ; ...
ts_t:   la    t2, scratch               ; t2 = the tile
        beq   t1, s2, ts_c              ; (it is the one fetched last)
        mv    s2, t1                    ; ...
        slli  t1, t1, 8                 ; ...
        li    t0, F_TILES               ; ...
        add   t1, t1, t0                ; ...
        ld    t0, g_keepb - g(gp)       ; ...
        add   t1, t1, t0                ; ...
        li    t0, 256                   ; ...
        tget  tg8, t2, c0, t1, t0       ; ...
ts_c:   slli  t0, s0, 9                 ; its place in the slab: 16 rows of 32 a tile
        slli  t1, s1, 4                 ; ...
        add   t0, t0, t1                ; ...
        la    t1, slab + SLAB_W * TILE_Y0 ; ...
        add   t0, t0, t1                ; ...
        li    t1, 16                    ; ...
ts_r:   ld    t3, 0(t2)                 ; a row of it
        sd    t3, 0(t0)                 ; ...
        ld    t3, 8(t2)                 ; ...
        sd    t3, 8(t0)                 ; ...
        addi  t2, t2, 16                ; ...
        addi  t0, t0, SLAB_W            ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, ts_r                  ; ...
        addi  s1, s1, 1                 ; ...
        li    t0, 2                     ; ...
        blt   s1, t0, ts_i              ; ...
        addi  s0, s0, 1                 ; ...
        li    t0, SCR_H                 ; ...
        blt   s0, t0, ts_j              ; ...

        li    s0, 0                     ; what stands on the tiles, a row at a time
ts_y:   ld    s3, f_scry - g(gp)        ; ...
        add   s3, s3, s0                ; ...
        la    s1, res + R_THINGS        ; the things in this row of this screen
ts_th:  lbu   t0, TH_KIND(s1)           ; ...
        beqz  t0, ts_fr                 ; ...
        lbu   t0, TH_Y(s1)              ; ...
        bne   t0, s3, ts_tn             ; ...
        lbu   a1, TH_X(s1)              ; ...
        ld    t0, f_scrx - g(gp)        ; ...
        sub   a1, a1, t0                ; ...
        li    t0, SCR_W                 ; ...
        bgeu  a1, t0, ts_tn             ; ...
        slli  a1, a1, 4                 ; the middle of its cell's lower edge
        addi  a1, a1, 8                 ; ...
        slli  a2, s0, 4                 ; ...
        addi  a2, a2, TILE_Y0 + 16      ; ...
        lhu   a0, TH_TD(s1)             ; ...
        call  r_put                     ; ...
ts_tn:  addi  s1, s1, TH_SIZE           ; ...
        j     ts_th                     ; ...
ts_fr:  la    s1, fr                    ; the friends
        li    s4, NFRIEND               ; ...
        la    s5, res + R_FRIEND        ; ...
ts_f:   lwu   a2, FR_Y(s1)              ; ...
        srli  t0, a2, 16                ; ...
        bne   t0, s3, ts_fn             ; ...
        lwu   a1, FR_X(s1)              ; ...
        call  ts_xy                     ; ...
        lhu   a0, 2(s5)                 ; (it fidgets)
        ld    t0, g_tic - g(gp)         ; ...
        srli  t0, t0, 4                 ; ...
        andi  t0, t0, 1                 ; ...
        add   a0, a0, t0                ; ...
        call  r_put                     ; ...
ts_fn:  addi  s1, s1, FR_SIZE           ; ...
        addi  s5, s5, 16                ; ...
        addi  s4, s4, -1                ; ...
        bnez  s4, ts_f                  ; ...
        ld    a2, f_py - g(gp)          ; Kira
        srli  t0, a2, 16                ; ...
        bne   t0, s3, ts_yn             ; ...
        ld    a1, f_px - g(gp)          ; ...
        call  ts_xy                     ; ...
        ld    t0, f_dir - g(gp)         ; the way she faces
        la    t1, f_face                ; ...
        add   t0, t0, t1                ; ...
        lbu   a0, 0(t0)                 ; ...
        addi  a0, a0, SP_KIRA_TD_DOWN_0 ; ...
        ld    t0, f_move - g(gp)        ; her walk's two frames; at the party she dances
        srli  t0, t0, 2                 ; ...
        ld    t1, f_state - g(gp)       ; ...
        beqz  t1, ts_k                  ; ...
        ld    t0, g_tic - g(gp)         ; ...
        srli  t0, t0, 3                 ; ...
ts_k:   andi  t0, t0, 1                 ; ...
        add   a0, a0, t0                ; ...
        call  r_put                     ; ...
ts_yn:  addi  s0, s0, 1                 ; ...
        li    t0, SCR_H                 ; ...
        blt   s0, t0, ts_y              ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        ld    s5, 48(sp)                ; ...
        addi  sp, sp, 64                ; pop the frame
        ret                             ; done
; ts_xy(a1 = x, a2 = y in the world, 16.16) -> a1, a2 = that place's lower
; edge on the screen (what stands there is anchored at its feet)
ts_xy:  srli  a1, a1, 12                ; 16 pixels a cell
        ld    t0, f_scrx - g(gp)        ; ...
        slli  t0, t0, 4                 ; ...
        sub   a1, a1, t0                ; ...
        srli  a2, a2, 12                ; ...
        ld    t0, f_scry - g(gp)        ; ...
        slli  t0, t0, 4                 ; ...
        sub   a2, a2, t0                ; ...
        addi  a2, a2, TILE_Y0 + 8       ; ...
        ret                             ; done

