; =============================================================================
; friends.s: kira's first game: find the seven friends
; =============================================================================
;
; Kira walks through her castle and its garden (dat.s: R_MAP, 40 x 20 cells)
; a cell at a time. Seven friends hide in it, each in one of its three
; places; a friend she comes next to is found: it says hello, its name and
; the count appear, and it follows her, each friend a step behind the one
; before (f_hist: the cells she left). With all seven she walks to the
; picnic blanket, and there is a party; then they hide again.
;
; From above the world is four screens of 20 x 10 cells, 16 pixels a cell,
; and the screen flips when she leaves it. An arrow key is a step; a click
; on a cell walks her there: fr_flow floods the screen's cells from the
; target outwards, each cell noting the step that leads back, and she
; follows the notes.

MAPW      = 64                          ; cells in a row of the world's array
SCR_W     = 20                          ; cells across a screen
SCR_H     = 10                          ; ... and down
TILE_Y0   = 4                           ; the tiles' first row on the screen
STEP_TICS = 8                           ; tics a step takes
STEP_D    = 0x2000                      ; ... and what she moves in each, 16.16
K_UP      = 1                           ; keys: the arrows (also directions)
K_DOWN    = 2                           ; ...
K_LEFT    = 3                           ; ...
K_RIGHT   = 4                           ; ...
FL_HERE   = 5                           ; fr_flow: the target itself

; ---- a friend -------------------------------------------------------------------
FR_X      = 0                           ; position, 16.16 (u32)
FR_Y      = 4                           ; ...
FR_TX     = 8                           ; where it is going
FR_TY     = 12                          ; ...
FR_ST     = 16                          ; 0 hiding, 1 following
FR_ORD    = 17                          ; its place in the parade
FR_SIZE   = 24                          ; bytes

; ---- a thing of the world (dat.s: R_THINGS) --------------------------------------
TH_X      = 0                           ; cell
TH_Y      = 1                           ; ...
TH_KIND   = 2                           ; 0 ends the list
TH_FP     = 4                           ; sprite through her eyes
TH_TD     = 6                           ; sprite from above
TH_SIZE   = 8                           ; bytes

        .data                           ; D-LS
        .align 8                        ; dwords
fr:       .space 7 * FR_SIZE            ; the friends
f_flow:   .space SCR_W * SCR_H          ; the step from each cell of the screen towards the target
f_hist:   .space 16                     ; the eight cells she left last: x, y each, newest first
f_ddx:    .byte 0, 0, 0, -1, 1          ; a direction's step in x ...
f_ddy:    .byte 0, -1, 1, 0, 0          ; ... and y
f_opp:    .byte 0, 2, 1, 4, 3           ; the opposite direction
f_face:   .byte 0, 2, 0, 4, 6           ; her sprite for it: down, up, left, right, two frames each
f_ring:   .byte -14, -6, -7, -11, 7, -11 ; the party: each friend's place by the blanket,
          .byte 14, -6, -12, 5, 12, 5, 0, 9 ; in eighths of a cell
        .align 8                        ; ...
        .text                           ; code

; rnd() -> a0 = 0 .. 32767. Clobbers t0.
rnd:    ld    a0, g_seed - g(gp)        ; the usual linear congruence
        li    t0, 1103515245            ; ...
        mul   a0, a0, t0                ; ...
        addi  a0, a0, 12345             ; ...
        sd    a0, g_seed - g(gp)        ; ...
        srli  a0, a0, 16                ; ...
        li    t0, 0x7fff                ; ...
        and   a0, a0, t0                ; ...
        ret                             ; done

; fr_init(): a new game: Kira at her start, every friend in one of its places
fr_init:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = friend
        sd    s1, 16(sp)                ; s1 = its number
        li    t0, (START_X << 16) + 0x8000 ; the middle of her cell
        sd    t0, f_px - g(gp)          ; ...
        li    t0, (START_Y << 16) + 0x8000 ; ...
        sd    t0, f_py - g(gp)          ; ...
        li    t0, K_DOWN                ; ...
        sd    t0, f_dir - g(gp)         ; ...
        sd    zero, f_move - g(gp)      ; ...
        sd    zero, f_want - g(gp)      ; ...
        sd    zero, f_path - g(gp)      ; ...
        sd    zero, f_found - g(gp)     ; ...
        sd    zero, f_state - g(gp)     ; ...
        la    t0, f_hist                ; she has been nowhere else
        li    t1, 8                     ; ...
fi_h:   li    t2, START_X               ; ...
        sb    t2, 0(t0)                 ; ...
        li    t2, START_Y               ; ...
        sb    t2, 1(t0)                 ; ...
        addi  t0, t0, 2                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, fi_h                  ; ...
        la    s0, fr                    ; ...
        li    s1, 0                     ; ...
fi_f:   call  rnd                       ; one of its three places
        li    t0, 3                     ; ...
        remu  a0, a0, t0                ; ...
        slli  a0, a0, 1                 ; ...
        slli  t0, s1, 3                 ; ...
        add   a0, a0, t0                ; ...
        la    t0, res + R_SPOTS         ; ...
        add   a0, a0, t0                ; ...
        lbu   t0, 0(a0)                 ; ...
        slli  t0, t0, 16                ; ...
        li    t2, 0x8000                ; ...
        add   t0, t0, t2                ; ...
        sw    t0, FR_X(s0)              ; ...
        sw    t0, FR_TX(s0)             ; ...
        lbu   t0, 1(a0)                 ; ...
        slli  t0, t0, 16                ; ...
        add   t0, t0, t2                ; ...
        sw    t0, FR_Y(s0)              ; ...
        sw    t0, FR_TY(s0)             ; ...
        sb    zero, FR_ST(s0)           ; ...
        addi  s0, s0, FR_SIZE           ; ...
        addi  s1, s1, 1                 ; ...
        li    t0, NFRIEND               ; ...
        blt   s1, t0, fi_f              ; ...
        li    t0, -1                    ; (no screen yet: fr_scr sets it)
        sd    t0, f_scrx - g(gp)        ; ...
        call  fr_scr                    ; ...
        li    t0, 1                     ; ...
        sd    t0, g_bardirty - g(gp)    ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; fr_scr(): the screen she is on; when it is another, the picture changes
; and a walk to a clicked cell ends
fr_scr: ld    t0, f_px - g(gp)          ; ...
        srli  t0, t0, 16                ; ...
        li    t1, SCR_W                 ; ...
        divu  t0, t0, t1                ; ...
        mul   t0, t0, t1                ; t0 = the screen's first column
        ld    t2, f_py - g(gp)          ; ...
        srli  t2, t2, 16                ; ...
        li    t1, SCR_H                 ; ...
        divu  t2, t2, t1                ; ...
        mul   t2, t2, t1                ; t2 = its first row
        ld    t3, f_scrx - g(gp)        ; ...
        bne   t3, t0, fs_new            ; ...
        ld    t3, f_scry - g(gp)        ; ...
        beq   t3, t2, fs_r              ; ...
fs_new: sd    t0, f_scrx - g(gp)        ; ...
        sd    t2, f_scry - g(gp)        ; ...
        sd    zero, f_path - g(gp)      ; ...
        li    t0, 1                     ; ...
        sd    t0, g_dirty - g(gp)       ; ...
fs_r:   ret                             ; done

; fr_walk(a0 = x, a1 = y: a cell) -> a0 = 1 if it can be walked on. Clobbers t0.
fr_walk:
        slli  a1, a1, 6                 ; 64 to a row
        add   a0, a0, a1                ; ...
        la    t0, res + R_MAP           ; ...
        add   a0, a0, t0                ; ...
        lbu   a0, 0(a0)                 ; no wall, and not kept off
        andi  a0, a0, 0x8f              ; ...
        seqz  a0, a0                    ; ...
        ret                             ; done

; fr_try(a0 = direction): she turns that way, and steps if the cell is free
fr_try: addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the direction
        sd    s1, 16(sp)                ; s1 = her cell: x | y << 8
        mv    s0, a0                    ; ...
        sd    a0, f_dir - g(gp)         ; ...
        li    t0, 1                     ; ...
        sd    t0, g_dirty - g(gp)       ; ...
        ld    a0, f_px - g(gp)          ; the cell ahead
        srli  a0, a0, 16                ; ...
        ld    a1, f_py - g(gp)          ; ...
        srli  a1, a1, 16                ; ...
        slli  s1, a1, 8                 ; ...
        or    s1, s1, a0                ; ...
        la    t0, f_ddx                 ; ...
        add   t0, t0, s0                ; ...
        lb    t1, 0(t0)                 ; ...
        add   a0, a0, t1                ; ...
        lb    t1, f_ddy - f_ddx(t0)     ; ...
        add   a1, a1, t1                ; ...
        call  fr_walk                   ; ...
        bnez  a0, ft_go                 ; ...
        sd    zero, f_path - g(gp)      ; no: she stays (and a walk ends)
        j     ft_r                      ; ...
ft_go:  la    t0, f_hist + 14           ; the cell she leaves heads the parade's path
        la    t1, f_hist                ; ...
ft_h:   lhu   t2, -2(t0)                ; ...
        sh    t2, 0(t0)                 ; ...
        addi  t0, t0, -2                ; ...
        bne   t0, t1, ft_h              ; ...
        sh    s1, 0(t0)                 ; ...
        la    t0, f_ddx                 ; her step: an eighth of a cell a tic
        add   t0, t0, s0                ; ...
        lb    t1, 0(t0)                 ; ...
        slli  t1, t1, 13                ; ...
        sd    t1, f_dx - g(gp)          ; ...
        lb    t1, f_ddy - f_ddx(t0)     ; ...
        slli  t1, t1, 13                ; ...
        sd    t1, f_dy - g(gp)          ; ...
        li    t0, STEP_TICS             ; ...
        sd    t0, f_move - g(gp)        ; ...
        la    t0, fr                    ; every follower goes where the one before it was
        li    t1, NFRIEND               ; ...
ft_f:   lbu   t2, FR_ST(t0)             ; ...
        beqz  t2, ft_fn                 ; ...
        lbu   t2, FR_ORD(t0)            ; ...
        slli  t2, t2, 1                 ; ...
        la    t3, f_hist                ; ...
        add   t2, t2, t3                ; ...
        lbu   t3, 0(t2)                 ; ...
        slli  t3, t3, 16                ; ...
        li    t4, 0x8000                ; ...
        add   t3, t3, t4                ; ...
        sw    t3, FR_TX(t0)             ; ...
        lbu   t3, 1(t2)                 ; ...
        slli  t3, t3, 16                ; ...
        add   t3, t3, t4                ; ...
        sw    t3, FR_TY(t0)             ; ...
ft_fn:  addi  t0, t0, FR_SIZE           ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, ft_f                  ; ...
ft_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; fr_step(): a tic of the game
fr_step:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = friend
        sd    s1, 16(sp)                ; s1 = friends left
        ld    t0, g_tic - g(gp)         ; the friends fidget: a new picture every 16 tics
        andi  t0, t0, 15                ; ...
        bnez  t0, fp_1                  ; ...
        li    t0, 1                     ; ...
        sd    t0, g_dirty - g(gp)       ; ...
fp_1:   ld    t0, f_state - g(gp)       ; the party: hearts and stars come down
        beqz  t0, fp_2                  ; ...
        ld    t0, f_party - g(gp)       ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, f_party - g(gp)       ; ...
        andi  t0, t0, 3                 ; ...
        bnez  t0, fp_2                  ; ...
        call  rnd                       ; ...
        andi  a4, a0, 1                 ; a heart or a star
        slli  a4, a4, 1                 ; ...
        addi  a4, a4, SP_HEART_0        ; ...
        srli  a0, a0, 2                 ; ...
        li    t0, 300                   ; ...
        remu  a0, a0, t0                ; ...
        addi  a0, a0, 6                 ; ...
        li    a1, -8                    ; ...
        li    a2, 0                     ; ...
        li    a3, 0x1c000               ; ...
        li    a5, 100                   ; ...
        call  p_spawn                   ; ...
fp_2:   la    s0, fr                    ; the followers go towards their places
        li    s1, NFRIEND               ; ...
fp_f:   lbu   t0, FR_ST(s0)             ; ...
        beqz  t0, fp_fn                 ; ...
        lw    a0, FR_X(s0)              ; ...
        lw    a1, FR_TX(s0)             ; ...
        call  fr_near                   ; ...
        sw    a0, FR_X(s0)              ; ...
        lw    a0, FR_Y(s0)              ; ...
        lw    a1, FR_TY(s0)             ; ...
        call  fr_near                   ; ...
        sw    a0, FR_Y(s0)              ; ...
fp_fn:  addi  s0, s0, FR_SIZE           ; ...
        addi  s1, s1, -1                ; ...
        bnez  s1, fp_f                  ; ...
        ld    t0, f_move - g(gp)        ; in a step?
        beqz  t0, fp_idle               ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, f_move - g(gp)        ; ...
        ld    t1, f_px - g(gp)          ; ...
        ld    t2, f_dx - g(gp)          ; ...
        add   t1, t1, t2                ; ...
        sd    t1, f_px - g(gp)          ; ...
        ld    t1, f_py - g(gp)          ; ...
        ld    t2, f_dy - g(gp)          ; ...
        add   t1, t1, t2                ; ...
        sd    t1, f_py - g(gp)          ; ...
        li    t1, 1                     ; ...
        sd    t1, g_dirty - g(gp)       ; ...
        bnez  t0, fp_r                  ; ...
        call  fr_arrive                 ; the step is done
        j     fp_r                      ; ...
fp_idle:
        ld    a0, f_want - g(gp)        ; a key was pressed: that way
        beqz  a0, fp_p                  ; ...
        sd    zero, f_want - g(gp)      ; ...
        sd    zero, f_path - g(gp)      ; ...
        call  fr_try                    ; ...
        j     fp_r                      ; ...
fp_p:   ld    t0, f_path - g(gp)        ; a walk to a clicked cell: the next step of it
        beqz  t0, fp_r                  ; ...
        ld    t0, f_py - g(gp)          ; the note in her cell
        srli  t0, t0, 16                ; ...
        ld    t1, f_scry - g(gp)        ; ...
        sub   t0, t0, t1                ; ...
        li    t1, SCR_W                 ; ...
        mul   t0, t0, t1                ; ...
        ld    t1, f_px - g(gp)          ; ...
        srli  t1, t1, 16                ; ...
        add   t0, t0, t1                ; ...
        ld    t1, f_scrx - g(gp)        ; ...
        sub   t0, t0, t1                ; ...
        la    t1, f_flow                ; ...
        add   t0, t0, t1                ; ...
        lbu   a0, 0(t0)                 ; ...
        li    t0, FL_HERE               ; ...
        bltu  a0, t0, fp_p1             ; a step
        sd    zero, f_path - g(gp)      ; she is there: on over the screen's edge,
        ld    a0, f_edge - g(gp)        ;   if that is where she was sent
        sd    zero, f_edge - g(gp)      ; ...
fp_p1:  bnez  a0, fp_p2                 ; ...
        sd    zero, f_path - g(gp)      ; (no way there)
        j     fp_r                      ; ...
fp_p2:  call  fr_try                    ; ...
fp_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; fr_near(a0 = a coordinate, a1 = where it is going) -> a0 = a step nearer
; (and the picture changes if it moved). Clobbers t0.
fr_near:
        beq   a0, a1, fn_r              ; ...
        li    t0, 1                     ; ...
        sd    t0, g_dirty - g(gp)       ; ...
        li    t0, STEP_D                ; ...
        blt   a0, a1, fn_up             ; ...
        sub   a0, a0, t0                ; down, not past it
        bge   a0, a1, fn_r              ; ...
        mv    a0, a1                    ; ...
        ret                             ; ...
fn_up:  add   a0, a0, t0                ; up, not past it
        ble   a0, a1, fn_r              ; ...
        mv    a0, a1                    ; ...
fn_r:   ret                             ; done

; fr_arrive(): she stands in a new cell: the screen, friends next to her,
; the picnic
fr_arrive:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = friend
        sd    s1, 16(sp)                ; s1 = its number
        sd    s2, 24(sp)                ; s2 = her cell's x
        sd    s3, 32(sp)                ; s3 = ... and y
        call  fr_scr                    ; ...
        ld    s2, f_px - g(gp)          ; ...
        srli  s2, s2, 16                ; ...
        ld    s3, f_py - g(gp)          ; ...
        srli  s3, s3, 16                ; ...
        la    s0, fr                    ; ...
        li    s1, 0                     ; ...
fa_l:   lbu   t0, FR_ST(s0)             ; hiding ...
        bnez  t0, fa_n                  ; ...
        lwu   t0, FR_X(s0)              ; ... in her cell or one beside it?
        srli  t0, t0, 16                ; ...
        sub   t0, t0, s2                ; ...
        bgez  t0, fa_1                  ; ...
        neg   t0, t0                    ; ...
fa_1:   lwu   t1, FR_Y(s0)              ; ...
        srli  t1, t1, 16                ; ...
        sub   t1, t1, s3                ; ...
        bgez  t1, fa_2                  ; ...
        neg   t1, t1                    ; ...
fa_2:   add   t0, t0, t1                ; ...
        li    t1, 1                     ; ...
        bgt   t0, t1, fa_n              ; ...
        call  fr_find                   ; found
fa_n:   addi  s0, s0, FR_SIZE           ; ...
        addi  s1, s1, 1                 ; ...
        li    t0, NFRIEND               ; ...
        blt   s1, t0, fa_l              ; ...
        ld    t0, f_found - g(gp)       ; all seven, at the picnic: the party
        li    t1, NFRIEND               ; ...
        bne   t0, t1, fa_r              ; ...
        ld    t0, f_state - g(gp)       ; ...
        bnez  t0, fa_r                  ; ...
        li    t0, PICNIC_X              ; ...
        bne   s2, t0, fa_r              ; ...
        li    t0, PICNIC_Y              ; ...
        bne   s3, t0, fa_r              ; ...
        li    t0, 1                     ; ...
        sd    t0, f_state - g(gp)       ; ...
        sd    zero, f_party - g(gp)     ; ...
        sd    zero, f_path - g(gp)      ; ...
        sd    zero, f_want - g(gp)      ; ...
        li    t0, K_DOWN                ; ...
        sd    t0, f_dir - g(gp)         ; ...
        li    t0, SP_WORD_HOORAY        ; ...
        sd    t0, g_msg - g(gp)         ; ...
        li    t0, -1                    ; (it stays)
        sd    t0, g_msgn - g(gp)        ; ...
        sd    t0, g_msgt - g(gp)        ; ...
        sd    t0, g_msgq - g(gp)        ; ...
        la    t0, fr                    ; the friends gather round the blanket
        li    t1, NFRIEND               ; ...
fa_p:   lbu   t2, FR_ORD(t0)            ; ...
        slli  t2, t2, 1                 ; ...
        la    t3, f_ring                ; ...
        add   t2, t2, t3                ; ...
        lb    t3, 0(t2)                 ; (in eighths of a cell from its middle)
        slli  t3, t3, 13                ; ...
        li    t4, (PICNIC_X << 16) + 0x8000 ; ...
        add   t3, t3, t4                ; ...
        sw    t3, FR_TX(t0)             ; ...
        lb    t3, 1(t2)                 ; ...
        slli  t3, t3, 13                ; ...
        li    t4, (PICNIC_Y << 16) + 0x8000 ; ...
        add   t3, t3, t4                ; ...
        sw    t3, FR_TY(t0)             ; ...
        addi  t0, t0, FR_SIZE           ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, fa_p                  ; ...
        la    t0, res + R_FANFARE       ; ...
        sd    t0, g_tune - g(gp)        ; ...
        sd    zero, g_tunet - g(gp)     ; ...
        li    t0, 1                     ; ...
        sd    t0, g_bardirty - g(gp)    ; ...
fa_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        addi  sp, sp, 40                ; pop the frame
        ret                             ; done

; fr_find(s0 = friend, s1 = its number): it is found: its sound, its name
; and the count, hearts, and it joins the parade. Keeps the s registers.
fr_find:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s2, 8(sp)                 ; s2 = its entry in dat.s's R_FRIEND
        sd    s3, 16(sp)                ; s3 = hearts left
        li    t0, 1                     ; ...
        sb    t0, FR_ST(s0)             ; ...
        sd    t0, g_dirty - g(gp)       ; ...
        sd    t0, g_bardirty - g(gp)    ; ...
        sd    zero, f_path - g(gp)      ; ...
        sd    zero, f_want - g(gp)      ; ...
        ld    t0, f_found - g(gp)       ; its place: behind those found before
        sb    t0, FR_ORD(s0)            ; ...
        slli  t1, t0, 1                 ; ...
        la    t2, f_hist                ; ...
        add   t1, t1, t2                ; ...
        lbu   t2, 0(t1)                 ; ...
        slli  t2, t2, 16                ; ...
        li    t3, 0x8000                ; ...
        add   t2, t2, t3                ; ...
        sw    t2, FR_TX(s0)             ; ...
        lbu   t2, 1(t1)                 ; ...
        slli  t2, t2, 16                ; ...
        add   t2, t2, t3                ; ...
        sw    t2, FR_TY(s0)             ; ...
        addi  t0, t0, 1                 ; one more
        sd    t0, f_found - g(gp)       ; ...
        addi  t1, t0, SP_NUM_1 - 1      ; the count ...
        sd    t1, g_msgn - g(gp)        ; ...
        slli  s2, s1, 4                 ; ...
        la    t1, res + R_FRIEND        ; ...
        add   s2, s2, t1                ; ...
        lhu   t1, 6(s2)                 ; ... and its name
        sd    t1, g_msg - g(gp)         ; ...
        li    t1, 80                    ; ...
        sd    t1, g_msgt - g(gp)        ; ...
        li    t1, -1                    ; after the seventh: "picnic time!"
        li    t2, NFRIEND               ; ...
        bne   t0, t2, ff_1              ; ...
        li    t1, SP_WORD_PICNIC        ; ...
ff_1:   sd    t1, g_msgq - g(gp)        ; ...
        lhu   a0, 8(s2)                 ; its sound, and a chime
        call  snd_play                  ; ...
        li    a0, SN_CHIME              ; ...
        call  snd_play                  ; ...
        li    s3, 6                     ; hearts fly up from it
