; =============================================================================
; music.s: kira's fourth game: a xylophone and the friends' voices
; =============================================================================
;
; The picture (PIC_MUSIC) has a xylophone of eight bars, C to the C above
; (bar i is the rectangle x = 28 + 34 i .. 57 + 34 i, y = 64 + 3 i ..
; 160 - 3 i), and a shelf on which the seven friends sit (48 x 48 each, at
; x = 4 + 45 i, standing on row 56). A press on a bar strikes it: its note,
; the bar bright for a moment, a note floating up. A press on a friend
; makes it say its sound and hop. The bar's button plays one of four songs,
; chosen at random: the song's notes strike the bars, and at every note
; one of the friends, chosen at random, hops.

MU_NBAR   = 8                           ; bars
MU_BX0    = 28                          ; the first bar's left edge
MU_BDX    = 34                          ; from one to the next
MU_BW     = 30                          ; a bar's width
MU_BY0    = 64                          ; the first bar's top (each next one 3 lower)
MU_BY1    = 160                         ; ... and bottom (each next one 3 higher)
MU_FX0    = 4                           ; the first friend's left edge
MU_FDX    = 45                          ; from one to the next
MU_FY     = 56                          ; the shelf
MU_HIT    = 8                           ; tics a struck bar stays bright
MU_HOP    = 12                          ; tics a hop takes
NSONG     = 4                           ; songs

        .data                           ; D-LS
        .align 8                        ; dwords
mu_hit:   .space 8                      ; tics each bar is still bright
mu_hop:   .space 8                      ; tics left of each friend's hop
        .text                           ; code

; mu_slab(): the slab of the music room: the picture, the friends on their
; shelf, the bars that were just struck
mu_slab:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = friend; bar
        sd    s1, 16(sp)                ; s1 = its entry in dat.s's R_FRIEND; x
        li    a0, PIC_MUSIC             ; ...
        call  pic_slab                  ; ...
        li    s0, 0                     ; ...
        la    s1, res + R_FRIEND        ; ...
us_f:   la    t0, mu_hop                ; a hop: up for six tics, down for six
        add   t0, t0, s0                ; ...
        lbu   t0, 0(t0)                 ; ...
        lhu   a0, 0(s1)                 ; ...
        li    a2, MU_FY                 ; ...
        beqz  t0, us_f1                 ; ...
        addi  a0, a0, 1                 ; (its other picture)
        li    t1, MU_HOP / 2            ; ...
        ble   t0, t1, us_f0             ; ...
        li    t1, MU_HOP                ; ...
        sub   t0, t1, t0                ; ...
us_f0:  sub   a2, a2, t0                ; ...
us_f1:  li    t0, MU_FDX                ; ...
        mul   a1, s0, t0                ; ...
        addi  a1, a1, MU_FX0 + 24       ; ...
        call  r_put                     ; ...
        addi  s1, s1, 16                ; ...
        addi  s0, s0, 1                 ; ...
        li    t0, NFRIEND               ; ...
        blt   s0, t0, us_f              ; ...
        li    s0, 0                     ; ...
        li    s1, MU_BX0                ; ...
us_b:   la    t0, mu_hit                ; ...
        add   t0, t0, s0                ; ...
        lbu   t0, 0(t0)                 ; ...
        beqz  t0, us_bn                 ; ...
        addi  a0, s0, SP_XYLO_HIT_0     ; ...
        mv    a1, s1                    ; ...
        slli  a2, s0, 1                 ; ...
        add   a2, a2, s0                ; ...
        addi  a2, a2, MU_BY0            ; ...
        call  r_blit                    ; ...
us_bn:  addi  s1, s1, MU_BDX            ; ...
        addi  s0, s0, 1                 ; ...
        li    t0, MU_NBAR               ; ...
        blt   s0, t0, us_b              ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; mu_bar(): the bar's part of the slab: her face (delighted while a song
; plays), the button for a song
mu_bar: addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        li    a0, SP_KIRA_FACE_0        ; ...
        ld    t0, g_tune - g(gp)        ; ...
        beqz  t0, ub_1                  ; ...
        li    a0, SP_KIRA_FACE_2        ; ...
ub_1:   li    a1, 36                    ; ...
        li    a2, 170                   ; ...
        call  r_blit                    ; ...
        li    a0, SP_ICON_SONG          ; ...
        li    a1, 290                   ; ...
        li    a2, 172                   ; ...
        call  r_blit                    ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; mu_strike(a0 = bar): its note, the bar bright, a note floating up
mu_strike:
        li    t0, MU_NBAR               ; ...
        bgeu  a0, t0, uk_r              ; ...
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the bar
        mv    s0, a0                    ; ...
        la    t0, mu_hit                ; ...
        add   t0, t0, a0                ; ...
        li    t1, MU_HIT                ; ...
        sb    t1, 0(t0)                 ; ...
        li    t0, 1                     ; ...
        sd    t0, g_dirty - g(gp)       ; ...
        addi  a0, a0, SN_NOTE0          ; ...
        call  snd_play                  ; ...
        li    t0, MU_BDX                ; ...
        mul   a0, s0, t0                ; ...
        addi  a0, a0, MU_BX0 + 10       ; ...
        slli  a1, s0, 1                 ; ...
        add   a1, a1, s0                ; ...
        addi  a1, a1, MU_BY0 - 6        ; ...
        li    a2, 0x4000                ; ...
        li    a3, -0xc000               ; ...
        andi  a4, s0, 1                 ; ...
        addi  a4, a4, SP_NOTE_0         ; ...
        li    a5, 24                    ; ...
        call  p_spawn                   ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 16                ; pop the frame
uk_r:   ret                             ; done

; mu_note(a0 = bar): a note of the song: the bar is struck, and one of the
; friends hops
mu_note:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        call  mu_strike                 ; ...
        li    a0, NFRIEND               ; ...
        call  rnd_n                     ; ...
        la    t0, mu_hop                ; ...
        add   t0, t0, a0                ; ...
        li    t1, MU_HOP                ; ...
        sb    t1, 0(t0)                 ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; mu_song(): a song, chosen at random; or, while one plays, silence
mu_song:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        li    t0, 1                     ; ...
        sd    t0, g_bardirty - g(gp)    ; ...
        ld    t0, g_tune - g(gp)        ; ...
        sd    zero, g_tune - g(gp)      ; ...
        bnez  t0, ug_r                  ; ...
        li    a0, NSONG                 ; ...
        call  rnd_n                     ; ...
        slli  a0, a0, 1                 ; ...
        la    t0, res + R_SONGS         ; ...
        add   a0, a0, t0                ; ...
        lhu   a0, 0(a0)                 ; ...
        add   a0, a0, t0                ; ...
        sd    a0, g_tune - g(gp)        ; ...
        li    t0, 200                   ; (its first note comes at once)
        sd    t0, g_tunet - g(gp)       ; ...
ug_r:   ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; mu_barclick(a0 = x): a press in the bar: the song's button
mu_barclick:
        li    t0, 288                   ; ...
        bge   a0, t0, mu_song           ; ...
        ret                             ; done

; mu_key(a0 = key): 1..8 strike the bars, p plays a song
mu_key: li    t0, 'p'                   ; ...
        beq   a0, t0, mu_song           ; ...
        addi  a0, a0, -'1'              ; ...
        j     mu_strike                 ; ...

; mu_click(a0 = x, a1 = y in the view): a friend says its sound and hops; a
; bar is struck
mu_click:
        li    t0, MU_FY + 2             ; the shelf?
        bge   a1, t0, uc_b              ; ...
        addi  t0, a0, -MU_FX0           ; ...
        bltz  t0, uc_r                  ; ...
        li    t1, MU_FDX                ; ...
        divu  t0, t0, t1                ; ...
        li    t1, NFRIEND               ; ...
        bgeu  t0, t1, uc_r              ; ...
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the friend
        mv    s0, t0                    ; ...
        la    t1, mu_hop                ; ...
        add   t1, t1, t0                ; ...
        li    t2, MU_HOP                ; ...
        sb    t2, 0(t1)                 ; ...
        li    t2, 1                     ; ...
        sd    t2, g_dirty - g(gp)       ; ...
        slli  t0, t0, 4                 ; ...
        la    t1, res + R_FRIEND        ; ...
        add   t0, t0, t1                ; ...
        lhu   a0, 8(t0)                 ; ...
        call  snd_play                  ; ...
        li    t0, MU_FDX                ; a heart over it
        mul   a0, s0, t0                ; ...
        addi  a0, a0, MU_FX0 + 20       ; ...
        li    a1, 4                     ; ...
        li    a2, 0                     ; ...
        li    a3, -0x4000               ; ...
        li    a4, SP_HEART_0            ; ...
        li    a5, 24                    ; ...
        call  p_spawn                   ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 16                ; pop the frame
        ret                             ; ...
uc_b:   addi  t0, a0, -MU_BX0           ; a bar: its column ...
        bltz  t0, uc_r                  ; ...
        li    t1, MU_BDX                ; ...
        divu  t2, t0, t1                ; t2 = the bar
        remu  t0, t0, t1                ; ...
        li    t1, MU_BW                 ; (not between two)
        bgeu  t0, t1, uc_r              ; ...
        li    t1, MU_NBAR               ; ...
        bgeu  t2, t1, uc_r              ; ...
        slli  t0, t2, 1                 ; ... and its rows
        add   t0, t0, t2                ; ...
        addi  t1, t0, MU_BY0            ; ...
        blt   a1, t1, uc_r              ; ...
        li    t1, MU_BY1                ; ...
        sub   t1, t1, t0                ; ...
        bgt   a1, t1, uc_r              ; ...
        mv    a0, t2                    ; ...
        j     mu_strike                 ; ...
uc_r:   ret                             ; done

; mu_step(): a tic of the music room: struck bars dim, hops go on
mu_step:
        la    t0, mu_hit                ; (the two arrays follow one another)
        li    t1, 16                    ; ...
ut_l:   lbu   t2, 0(t0)                 ; ...
        beqz  t2, ut_n                  ; ...
        addi  t2, t2, -1                ; ...
        sb    t2, 0(t0)                 ; ...
        li    t2, 1                     ; ...
        sd    t2, g_dirty - g(gp)       ; ...
ut_n:   addi  t0, t0, 1                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, ut_l                  ; ...
        ret                             ; done
