; =============================================================================
; paint.s: kira's third game: colouring pages
; =============================================================================
;
; A colouring page is a picture (draw.s: pic_slab) whose "colours" are the
; numbers of its regions: 0 the black outline, 1.. the white areas, as
; tools/kira-assets.py numbered them. pt_tab maps a page's region numbers
; to palette indices; a slab is decoded and then translated through it. So
; filling a region is one store: the region under a press is found by
; decoding the press's slab without translating it, and no flood fill is
; needed. The three pages keep their colours while the program runs.
;
; The bar has ten paint pots (the one in use stands higher) and a button
; for the next page. A page with no region left unpainted gets stars: an
; unpainted region is C_PAPER, a white of its own beside the white paint.

PT_NPAGE  = 3                           ; pages
PT_NREG   = 64                          ; regions a page may have (with the outline)
PT_NPOT   = 10                          ; paints
PT_X0     = 36                          ; the pots' place in the bar
PT_DX     = 24                          ; ...

        .data                           ; D-LS
        .align 8                        ; dwords
pt_tab:   .space PT_NPAGE * PT_NREG     ; each page's regions' colours
        .text                           ; code

; pt_init(): every region of every page is paper; a page at random
pt_init:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        la    t0, pt_tab                ; ...
        li    t1, PT_NPAGE * PT_NREG    ; ...
        li    t2, C_PAPER               ; ...
pi_l:   sb    t2, 0(t0)                 ; ...
        andi  t3, t1, PT_NREG - 1       ; (a page's first: the outline)
        bnez  t3, pi_n                  ; ...
        li    t3, C_BLACK               ; ...
        sb    t3, 0(t0)                 ; ...
pi_n:   addi  t0, t0, 1                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, pi_l                  ; ...
        li    a0, PT_NPAGE              ; ...
        call  rnd_n                     ; ...
        sd    a0, pt_page - g(gp)       ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; pt_slab(): the slab of the page, in its colours
pt_slab:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        ld    a0, pt_page - g(gp)       ; ...
        addi  a0, a0, PIC_PAINT_1       ; ...
        call  pic_slab                  ; ...
        ld    t0, pt_page - g(gp)       ; the page's table
        slli  t0, t0, 6                 ; ...
        la    t1, pt_tab                ; ...
        add   t0, t0, t1                ; ...
        la    t1, slab                  ; ...
        li    t2, SLAB_W * VIEW_H / 4   ; (four pixels a round)
ql_l:   lbu   t3, 0(t1)                 ; ...
        add   t3, t3, t0                ; ...
        lbu   t3, 0(t3)                 ; ...
        sb    t3, 0(t1)                 ; ...
        lbu   t3, 1(t1)                 ; ...
        add   t3, t3, t0                ; ...
        lbu   t3, 0(t3)                 ; ...
        sb    t3, 1(t1)                 ; ...
        lbu   t3, 2(t1)                 ; ...
        add   t3, t3, t0                ; ...
        lbu   t3, 0(t3)                 ; ...
        sb    t3, 2(t1)                 ; ...
        lbu   t3, 3(t1)                 ; ...
        add   t3, t3, t0                ; ...
        lbu   t3, 0(t3)                 ; ...
        sb    t3, 3(t1)                 ; ...
        addi  t1, t1, 4                 ; ...
        addi  t2, t2, -1                ; ...
        bnez  t2, ql_l                  ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; pt_bar(): the bar's part of the slab: the pots, the one in use higher;
; the button for the next page
pt_bar: addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = pot
        sd    s1, 16(sp)                ; s1 = x
        li    s0, 0                     ; ...
        li    s1, PT_X0                 ; ...
qb_l:   addi  a0, s0, SP_POT_0          ; ...
        mv    a1, s1                    ; ...
        li    a2, 175                   ; ...
        ld    t0, pt_col - g(gp)        ; ...
        bne   t0, s0, qb_1              ; ...
        li    a2, 169                   ; ...
qb_1:   call  r_blit                    ; ...
        addi  s1, s1, PT_DX             ; ...
        addi  s0, s0, 1                 ; ...
        li    t0, PT_NPOT               ; ...
        blt   s0, t0, qb_l              ; ...
        li    a0, SP_ICON_NEXT          ; ...
        li    a1, 290                   ; ...
        li    a2, 172                   ; ...
        call  r_blit                    ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; pt_pick(a0 = pot): that paint is in use
pt_pick:
        li    t0, PT_NPOT               ; ...
        bgeu  a0, t0, qp_r              ; ...
        sd    a0, pt_col - g(gp)        ; ...
        li    t0, 1                     ; ...
        sd    t0, g_bardirty - g(gp)    ; ...
        li    a0, SN_POP                ; ...
        j     snd_play                  ; ...
qp_r:   ret                             ; done

; pt_next(): the next page
pt_next:
        ld    t0, pt_page - g(gp)       ; ...
        addi  t0, t0, 1                 ; ...
        li    t1, PT_NPAGE              ; ...
        blt   t0, t1, qn_1              ; ...
        li    t0, 0                     ; ...
qn_1:   sd    t0, pt_page - g(gp)       ; ...
        li    t0, 1                     ; ...
        sd    t0, g_dirty - g(gp)       ; ...
        li    a0, SN_POP                ; ...
        j     snd_play                  ; ...

; pt_barclick(a0 = x): a press in the bar: a pot, or the next page
pt_barclick:
        li    t0, 288                   ; ...
        bge   a0, t0, pt_next           ; ...
        addi  a0, a0, -(PT_X0 - 2)      ; ...
        bltz  a0, qp_r                  ; ...
        li    t0, PT_DX                 ; ...
        divu  a0, a0, t0                ; ...
        j     pt_pick                   ; ...

; pt_key(a0 = key): 1..9 and 0 are the pots, n the next page
pt_key: li    t0, 'n'                   ; ...
        beq   a0, t0, pt_next           ; ...
        li    t0, '0'                   ; ...
        bne   a0, t0, qk_1              ; ...
        li    a0, '1' + 9               ; ...
qk_1:   addi  a0, a0, -'1'              ; ...
        j     pt_pick                   ; ...

; pt_click(a0 = x, a1 = y in the view): the region there takes the paint
pt_click:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = x; the page's table; stars left
        sd    s1, 16(sp)                ; s1 = y; the region
        sd    s2, 24(sp)                ; s2 = the slab that was being drawn
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        ld    s2, g_sx0 - g(gp)         ; the press's slab, as region numbers
        srli  t0, a0, 5                 ; ...
        slli  t0, t0, 5                 ; ...
        sd    t0, g_sx0 - g(gp)         ; ...
        ld    a0, pt_page - g(gp)       ; ...
        addi  a0, a0, PIC_PAINT_1       ; ...
        call  pic_slab                  ; ...
        sd    s2, g_sx0 - g(gp)         ; ...
        slli  t0, s1, 5                 ; the region under it
        andi  t1, s0, SLAB_W - 1        ; ...
        add   t0, t0, t1                ; ...
        la    t1, slab                  ; ...
        add   t0, t0, t1                ; ...
        lbu   s1, 0(t0)                 ; ...
        beqz  s1, qc_r                  ; (the outline)
        ld    s0, pt_page - g(gp)       ; ...
        slli  s0, s0, 6                 ; ...
        la    t1, pt_tab                ; ...
        add   s0, s0, t1                ; ...
        ld    t0, pt_col - g(gp)        ; the paint
        la    t1, res + R_PAINT         ; ...
        add   t0, t0, t1                ; ...
        lbu   t0, 0(t0)                 ; ...
        add   t1, s0, s1                ; ...
        lbu   t2, 0(t1)                 ; t2 = what it was
        sb    t0, 0(t1)                 ; ...
        li    t0, 1                     ; ...
        sd    t0, g_dirty - g(gp)       ; ...
        li    t0, C_PAPER               ; (was it the page's last unpainted one?)
        bne   t2, t0, qc_s              ; ...
        ld    t1, pt_page - g(gp)       ; any region still paper?
        la    t2, res + R_NREG          ; ...
        add   t1, t1, t2                ; ...
        lbu   t1, 0(t1)                 ; t1 = the page's regions
qc_a:   add   t2, s0, t1                ; ...
        lbu   t2, 0(t2)                 ; ...
        beq   t2, t0, qc_s              ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, qc_a                  ; ...
        li    a0, SN_BLOOM              ; none: the page is done: a chime and stars
        call  snd_play                  ; ...
        li    s0, 12                    ; ...
qc_st:  li    a0, VIEW_W - 20           ; ...
        call  rnd_n                     ; ...
        addi  s1, a0, 6                 ; ...
        li    a0, VIEW_H - 40           ; ...
        call  rnd_n                     ; ...
        addi  a1, a0, 10                ; ...
        mv    a0, s1                    ; ...
        li    a2, 0                     ; ...
        li    a3, -0x6000               ; ...
        andi  a4, s0, 1                 ; ...
        addi  a4, a4, SP_STAR_0         ; ...
        li    a5, 50                    ; ...
        call  p_spawn                   ; ...
        addi  s0, s0, -1                ; ...
        bnez  s0, qc_st                 ; ...
        j     qc_r                      ; ...
qc_s:   li    a0, SN_PLANT              ; ...
        call  snd_play                  ; ...
qc_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done
