        addi  a0, a0, -2                ; ...
        ret                             ; ...
gn_2:   addi  a0, a0, 2                 ; ...
        ret                             ; done
; gt_aim(s1 = butterfly): it flies to a flower in bloom, chosen at random
; (to a patch chosen at random, and on from there to the next one that has
