; =============================================================================
; garden.s: kira's second game: a garden to plant
; =============================================================================
;
; Twelve patches of soil in two rows of six (the picture, PIC_GARDEN, has
; them at x = 40 + 48 c, y = 104 and 150). The bar has four packets of
; seeds and a watering can. A seed on an empty patch is a sprout; the can
; makes it grow, to a bud and then to a flower; a seed on a flower plants
; anew. For every flower in bloom (up to five) a butterfly comes and flits
; from flower to flower, and now and then one of the friends walks by:
; touch it and it says hello. Which friend, when, and where the
; butterflies go is left to chance, and so is the first garden: three
; patches are planted already.
;
; The garden is kept in the file /ws/kira.sav (16 bytes: a patch each, kind
; << 2 | stage). It is read before the window is opened and written when
; the garden is left: a window's client has the window server's endpoint
; where the file server's was (wsclient.s), so gd_save looks the file
; server up into that register, writes, and looks the window server up
; again.

GD_NPLOT  = 12                          ; patches
GD_COLS   = 6                           ; ... in a row
GD_X0     = 40                          ; the first patch's middle
GD_DX     = 48                          ; from one to the next
GD_Y0     = 104                         ; the back row's middle
GD_Y1     = 150                         ; the front row's
GD_CAN    = 4                           ; tools: 0..3 seeds, the can
GD_NTOOL  = 5                           ; ...
GD_TX0    = 76                          ; the tools' place in the bar
GD_TDX    = 40                          ; ...
GD_NBF    = 5                           ; butterflies at most
BF_X      = 0                           ; a butterfly: position on the screen (s32)
BF_Y      = 4                           ; ...
BF_TX     = 8                           ; where it is flying
BF_TY     = 12                          ; ...
BF_REST   = 16                          ; tics it still sits there
BF_ON     = 20                          ; it has come
BF_SIZE   = 24                          ; bytes

        .data                           ; D-LS
        .align 8                        ; dwords
gd_plot:  .space 16                     ; the patches (and four spare bytes): kind << 2 | stage
gd_bf:    .space GD_NBF * BF_SIZE       ; the butterflies
gd_name:  .ascii "/ws/kira.sav"         ; the file
gd_name_e:                              ; (its end)
gd_fs:    .ascii "fs"                   ; the file server's name
gd_ws:    .ascii "ws"                   ; the window server's
        .align 8                        ; ...
        .text                           ; code

; gd_load(): the garden from its file (before the window is opened); with
; no file, three patches planted at random
gd_load:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = handle; patches left to plant
        sd    s1, 16(sp)                ; s1 = the patch
        la    a0, gd_name               ; ...
        li    a1, gd_name_e - gd_name   ; ...
        li    a2, 0                     ; ...
        call  sys_open                  ; ...
        mv    s0, a0                    ; ...
        bltz  a0, gl_new                ; ...
        la    a1, gd_plot               ; ...
        li    a2, 16                    ; ...
        call  sys_read                  ; ...
        mv    a0, s0                    ; ...
        call  sys_close                 ; ...
        j     gl_r                      ; ...
gl_new: li    s0, 3                     ; ...
gl_l:   li    a0, GD_NPLOT              ; a patch
        call  rnd_n                     ; ...
        la    s1, gd_plot               ; ...
        add   s1, s1, a0                ; ...
        call  rnd                       ; a kind and a stage 1..3
        andi  t2, a0, 3 << 2            ; ...
        srli  a0, a0, 4                 ; ...
        li    t0, 3                     ; ...
        remu  a0, a0, t0                ; ...
        addi  a0, a0, 1                 ; ...
        or    t2, t2, a0                ; ...
        sb    t2, 0(s1)                 ; ...
        addi  s0, s0, -1                ; ...
        bnez  s0, gl_l                  ; ...
gl_r:   call  gd_count                  ; ...
        li    t0, -1                    ; (nobody walks by yet)
        sd    t0, gd_vis - g(gp)        ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; gd_save(): the garden into its file, if it changed
gd_save:
        ld    t0, gd_chg - g(gp)        ; ...
        beqz  t0, gv_r0                 ; ...
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = handle
        sd    zero, gd_chg - g(gp)      ; ...
        la    a0, gd_fs                 ; the file server, where the window server's
        li    a1, 2                     ;   endpoint is
        li    a2, WC_EP                 ; ...
        call  sys_lookup                ; ...
        bnez  a0, gv_ws                 ; ...
        la    a0, gd_name               ; ...
        li    a1, gd_name_e - gd_name   ; ...
        li    a2, 1                     ; ...
        call  sys_open                  ; ...
        mv    s0, a0                    ; ...
        bltz  a0, gv_ws                 ; ...
        la    a1, gd_plot               ; ...
        li    a2, 16                    ; ...
        call  sys_write                 ; ...
        mv    a0, s0                    ; ...
        call  sys_close                 ; ...
gv_ws:  la    a0, gd_ws                 ; the window server again
        li    a1, 2                     ; ...
        li    a2, WC_EP                 ; ...
        call  sys_lookup                ; ...
        cclear c6                       ; (c6 stays empty: the band comes back there)
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 16                ; pop the frame
gv_r0:  ret                             ; done

; gd_count() -> a0 = flowers in bloom (also in gd_nbl). Clobbers t0..t2.
gd_count:
        la    t0, gd_plot               ; ...
        li    t1, GD_NPLOT              ; ...
        li    a0, 0                     ; ...
gc_l:   lbu   t2, 0(t0)                 ; ...
        andi  t2, t2, 3                 ; ...
        addi  t2, t2, -3                ; ...
        bnez  t2, gc_n                  ; ...
        addi  a0, a0, 1                 ; ...
gc_n:   addi  t0, t0, 1                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, gc_l                  ; ...
        sd    a0, gd_nbl - g(gp)        ; ...
        ret                             ; done

; gd_xy(a0 = patch) -> a1 = x, a2 = y of its middle. Clobbers t0.
gd_xy:  li    a2, GD_Y0                 ; ...
        mv    a1, a0                    ; ...
        li    t0, GD_COLS               ; ...
        blt   a0, t0, gx_1              ; ...
        li    a2, GD_Y1                 ; ...
        sub   a1, a1, t0                ; ...
gx_1:   li    t0, GD_DX                 ; ...
        mul   a1, a1, t0                ; ...
        addi  a1, a1, GD_X0             ; ...
        ret                             ; done

; gd_slab(): the slab of the garden: the picture, the plants (the back row
; first), who walks by, the butterflies
gd_slab:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = patch; butterfly
        sd    s1, 16(sp)                ; s1 = its record
        li    a0, PIC_GARDEN            ; ...
        call  pic_slab                  ; ...
        li    s0, 0                     ; ...
gs_p:   la    t0, gd_plot               ; ...
        add   t0, t0, s0                ; ...
        lbu   t1, 0(t0)                 ; ...
        andi  t2, t1, 3                 ; its stage
        beqz  t2, gs_pn                 ; ...
        srli  t1, t1, 2                 ; its kind: three sprites each
        slli  t0, t1, 1                 ; ...
        add   t1, t1, t0                ; ...
        add   t1, t1, t2                ; ...
        mv    a0, s0                    ; ...
        call  gd_xy                     ; ...
        addi  a0, t1, SP_PLANT_TULIP_1 - 1 ; ...
        addi  a2, a2, 4                 ; (it stands 4 rows below the patch's middle)
        call  r_put                     ; ...
gs_pn:  addi  s0, s0, 1                 ; ...
        li    t0, GD_NPLOT              ; ...
        blt   s0, t0, gs_p              ; ...
        ld    t0, gd_vis - g(gp)        ; a friend walking by (it fidgets)
        bltz  t0, gs_b                  ; ...
        slli  t0, t0, 4                 ; ...
        la    t1, res + R_FRIEND        ; ...
        add   t0, t0, t1                ; ...
        lhu   a0, 0(t0)                 ; ...
        ld    t0, g_tic - g(gp)         ; ...
        srli  t0, t0, 3                 ; ...
        andi  t0, t0, 1                 ; ...
        add   a0, a0, t0                ; ...
        ld    a1, gd_vx - g(gp)         ; ...
        li    a2, VIEW_H - 1            ; ...
        call  r_put                     ; ...
gs_b:   li    s0, 0                     ; the butterflies: three colourings, wings
        la    s1, gd_bf                 ;   open and shut (shut while they sit)
gs_bl:  lw    t0, BF_ON(s1)             ; ...
        beqz  t0, gs_bn                 ; ...
        li    t0, 3                     ; ...
        remu  a0, s0, t0                ; ...
        slli  a0, a0, 1                 ; ...
        addi  a0, a0, SP_BUTTERFLY_A_0  ; ...
        ld    t0, g_tic - g(gp)         ; ...
        srli  t0, t0, 2                 ; ...
        lw    t1, BF_REST(s1)           ; ...
        beqz  t1, gs_b1                 ; ...
        srli  t0, t0, 3                 ; (slowly while it sits)
gs_b1:  andi  t0, t0, 1                 ; ...
        add   a0, a0, t0                ; ...
        lw    a1, BF_X(s1)              ; ...
        lw    a2, BF_Y(s1)              ; ...
        call  r_blit                    ; ...
gs_bn:  addi  s1, s1, BF_SIZE           ; ...
        addi  s0, s0, 1                 ; ...
        li    t0, GD_NBF                ; ...
        blt   s0, t0, gs_bl             ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; gd_bar(): the bar's part of the slab: her face, the seeds and the can,
; a frame around the one in her hand
gd_bar: addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = tool
        sd    s1, 16(sp)                ; s1 = x
        li    a0, SP_KIRA_FACE_0        ; delighted for a while after a flower opens
        ld    t0, gd_joy - g(gp)        ; ...
        beqz  t0, gb_1                  ; ...
        li    a0, SP_KIRA_FACE_2        ; ...
gb_1:   li    a1, 36                    ; ...
        li    a2, 170                   ; ...
        call  r_blit                    ; ...
        li    s0, 0                     ; ...
        li    s1, GD_TX0                ; ...
gb_l:   addi  a0, s0, SP_ICON_TULIP     ; (the four packets and the can follow one another)
        mv    a1, s1                    ; ...
        li    a2, 172                   ; ...
        call  r_blit                    ; ...
        ld    t0, gd_tool - g(gp)       ; ...
        bne   t0, s0, gb_n              ; ...
        li    a0, SP_SELECT             ; ...
        addi  a1, s1, -2                ; ...
        li    a2, 170                   ; ...
        call  r_blit                    ; ...
gb_n:   addi  s1, s1, GD_TDX            ; ...
        addi  s0, s0, 1                 ; ...
        li    t0, GD_NTOOL              ; ...
        blt   s0, t0, gb_l              ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; gd_pick(a0 = tool): it is in her hand
gd_pick:
        li    t0, GD_NTOOL              ; ...
        bgeu  a0, t0, gk_r              ; ...
        sd    a0, gd_tool - g(gp)       ; ...
        li    t0, 1                     ; ...
        sd    t0, g_bardirty - g(gp)    ; ...
        li    a0, SN_POP                ; ...
        j     snd_play                  ; ...
gk_r:   ret                             ; done

; gd_barclick(a0 = x): a press in the bar: a tool
gd_barclick:
        addi  a0, a0, -(GD_TX0 - 6)     ; (each has 40 pixels, the 24 of its picture in their middle)
        bltz  a0, gk_r                  ; ...
        li    t0, GD_TDX                ; ...
        divu  a0, a0, t0                ; ...
        j     gd_pick                   ; ...

; gd_key(a0 = key): 1..5 are the tools
gd_key: addi  a0, a0, -'1'              ; ...
        j     gd_pick                   ; ...

; gd_click(a0 = x, a1 = y in the view): the friend walking by says hello;
; a patch is planted, or watered
gd_click:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the patch
        sd    s1, 16(sp)                ; s1 = its byte
        sd    s2, 24(sp)                ; s2 = its middle: x
        sd    s3, 32(sp)                ; s3 = ... and y
        ld    t0, gd_vis - g(gp)        ; the friend: within 24 pixels of its middle,
        bltz  t0, gk_p                  ;   in the picture's lowest 48 rows
        li    t1, VIEW_H - 48           ; ...
        blt   a1, t1, gk_p              ; ...
        ld    t1, gd_vx - g(gp)         ; ...
        sub   t1, a0, t1                ; ...
        addi  t1, t1, 24                ; ...
        li    t2, 48                    ; ...
        bgeu  t1, t2, gk_p              ; ...
        slli  t0, t0, 4                 ; its sound, and a heart
        la    t1, res + R_FRIEND        ; ...
        add   t0, t0, t1                ; ...
        lhu   a0, 8(t0)                 ; ...
        call  snd_play                  ; ...
        ld    a0, gd_vx - g(gp)         ; ...
        addi  a0, a0, -4                ; ...
        li    a1, VIEW_H - 60           ; ...
        li    a2, 0                     ; ...
        li    a3, -0xc000               ; ...
        li    a4, SP_HEART_0            ; ...
        li    a5, 30                    ; ...
        call  p_spawn                   ; ...
        j     gk_d                      ; ...
gk_p:   addi  t0, a0, -(GD_X0 - GD_DX / 2) ; the patch: its column ...
        bltz  t0, gk_d                  ; ...
        li    t1, GD_DX                 ; ...
        divu  s0, t0, t1                ; ...
        li    t1, GD_COLS               ; ...
        bgeu  s0, t1, gk_d              ; ...
        li    t0, GD_Y0 - 40            ; ... and its row: the back one's plants reach
        blt   a1, t0, gk_d              ;   from 40 above its middle to 12 below, the
        li    t0, GD_Y0 + 12            ;   front one's are under that
        blt   a1, t0, gk_1              ; ...
        addi  s0, s0, GD_COLS           ; ...
gk_1:   mv    a0, s0                    ; ...
        call  gd_xy                     ; ...
        mv    s2, a1                    ; ...
        mv    s3, a2                    ; ...
        la    s1, gd_plot               ; ...
        add   s1, s1, s0                ; ...
        lbu   t0, 0(s1)                 ; t1 = its stage
        andi  t1, t0, 3                 ; ...
        ld    t2, gd_tool - g(gp)       ; ...
        li    t3, GD_CAN                ; ...
        beq   t2, t3, gk_w              ; ...
        beqz  t1, gk_s                  ; a seed: on an empty patch, or on a flower
        li    t3, 3                     ; ...
        beq   t1, t3, gk_s              ; ...
        li    a0, SN_POP                ; (something is growing there already)
        call  snd_play                  ; ...
        j     gk_d                      ; ...
gk_s:   slli  t2, t2, 2                 ; a sprout of that kind
        ori   t2, t2, 1                 ; ...
        sb    t2, 0(s1)                 ; ...
        li    a0, SN_PLANT              ; ...
        call  snd_play                  ; ...
        addi  a0, s2, -4                ; a star over it
        addi  a1, s3, -14               ; ...
        li    a2, 0                     ; ...
        li    a3, -0x8000               ; ...
        li    a4, SP_STAR_0             ; ...
        li    a5, 20                    ; ...
        call  p_spawn                   ; ...
        j     gk_c                      ; ...
gk_w:   li    s0, 3                     ; the can: three drops fall on the patch
gk_wd:  slli  a0, s0, 3                 ; ...
        add   a0, a0, s2                ; ...
        addi  a0, a0, -19               ; ...
        slli  a1, s0, 2                 ; ...
        add   a1, a1, s3                ; ...
        addi  a1, a1, -52               ; ...
        li    a2, 0                     ; ...
        li    a3, 0x28000               ; ...
        li    a4, SP_DROP               ; ...
        li    a5, 14                    ; ...
        call  p_spawn                   ; ...
        addi  s0, s0, -1                ; ...
        bnez  s0, gk_wd                 ; ...
        li    a0, SN_WATER              ; ...
        call  snd_play                  ; ...
        lbu   t0, 0(s1)                 ; a sprout or a bud grows
        andi  t1, t0, 3                 ; ...
        beqz  t1, gk_d                  ; ...
        li    t3, 3                     ; ...
        beq   t1, t3, gk_d              ; ...
        addi  t0, t0, 1                 ; ...
        sb    t0, 0(s1)                 ; ...
        andi  t1, t0, 3                 ; into a flower: a chime, hearts, her delight
        bne   t1, t3, gk_c              ; ...
        li    a0, SN_BLOOM              ; ...
        call  snd_play                  ; ...
        li    t0, 70                    ; ...
        sd    t0, gd_joy - g(gp)        ; ...
        li    s0, 3                     ; ...
gk_h:   call  rnd                       ; ...
        slli  a2, a0, 1                 ; ...
        li    t0, 0x8000                ; ...
        sub   a2, a2, t0                ; ...
        addi  a0, s2, -4                ; ...
        addi  a1, s3, -40               ; ...
        li    a3, -0xc000               ; ...
        li    a4, SP_HEART_0            ; ...
        li    a5, 30                    ; ...
        call  p_spawn                   ; ...
        addi  s0, s0, -1                ; ...
        bnez  s0, gk_h                  ; ...
gk_c:   call  gd_count                  ; the garden changed
        li    t0, 1                     ; ...
        sd    t0, gd_chg - g(gp)        ; ...
        sd    t0, g_bardirty - g(gp)    ; ...
gk_d:   li    t0, 1                     ; ...
        sd    t0, g_dirty - g(gp)       ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        addi  sp, sp, 40                ; pop the frame
        ret                             ; done

; gd_step(): a tic of the garden: her delight passes; on every second tic
; the butterflies and the friend walking by move
gd_step:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = butterfly
        sd    s1, 16(sp)                ; s1 = its record
        sd    s2, 24(sp)                ; s2 = the patch it chose
        ld    t0, gd_joy - g(gp)        ; ...
        beqz  t0, gt_1                  ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, gd_joy - g(gp)        ; ...
        bnez  t0, gt_1                  ; ...
        li    t0, 1                     ; ...
        sd    t0, g_bardirty - g(gp)    ; ...
gt_1:   ld    t0, g_tic - g(gp)         ; ...
        andi  t1, t0, 1                 ; ...
        bnez  t1, gt_r                  ; ...
        ld    t1, gd_vis - g(gp)        ; the friend: two pixels to the right, and away
        bltz  t1, gt_v                  ;   past the edge
        ld    t1, gd_vx - g(gp)         ; ...
        addi  t1, t1, 2                 ; ...
        sd    t1, gd_vx - g(gp)         ; ...
        li    t2, 1                     ; ...
        sd    t2, g_dirty - g(gp)       ; ...
        li    t2, VIEW_W + 30           ; ...
        blt   t1, t2, gt_b              ; ...
        li    t1, -1                    ; ...
        sd    t1, gd_vis - g(gp)        ; ...
        j     gt_b                      ; ...
gt_v:   andi  t1, t0, 255               ; nobody: every seven seconds, one time in two,
        bnez  t1, gt_b                  ;   one of them comes
        call  rnd                       ; ...
        andi  t0, a0, 1                 ; ...
        bnez  t0, gt_b                  ; ...
        srli  a0, a0, 3                 ; ...
        li    t0, NFRIEND               ; ...
        remu  a0, a0, t0                ; ...
        sd    a0, gd_vis - g(gp)        ; ...
        li    t0, -30                   ; ...
        sd    t0, gd_vx - g(gp)         ; ...
gt_b:   li    s0, 0                     ; the butterflies: as many as there are flowers
        la    s1, gd_bf                 ; ...
gt_bl:  ld    t0, gd_nbl - g(gp)        ; ...
        lw    t1, BF_ON(s1)             ; ...
        blt   s0, t0, gt_on             ; ...
        beqz  t1, gt_bn                 ; one too many: it flies off to the left, and is gone
        li    t0, -40                   ; ...
        sw    t0, BF_TX(s1)             ; ...
        sw    zero, BF_REST(s1)         ; ...
        lw    t0, BF_X(s1)              ; ...
        li    t2, -16                   ; ...
        bgt   t0, t2, gt_fly            ; ...
        sw    zero, BF_ON(s1)           ; ...
        j     gt_bn                     ; ...
gt_on:  bnez  t1, gt_fly                ; a new one comes in from the right
        li    t0, 1                     ; ...
        sw    t0, BF_ON(s1)             ; ...
        li    t0, VIEW_W + 4            ; ...
        sw    t0, BF_X(s1)              ; ...
        li    a0, 60                    ; ...
        call  rnd_n                     ; ...
        addi  a0, a0, 8                 ; ...
        sw    a0, BF_Y(s1)              ; ...
        sw    zero, BF_REST(s1)         ; ...
        call  gt_aim                    ; ...
gt_fly: lw    t0, BF_REST(s1)           ; sitting?
        beqz  t0, gt_mv                 ; ...
        addi  t0, t0, -1                ; ...
        sw    t0, BF_REST(s1)           ; ...
        andi  t1, t0, 15                ; (its wings move now and then)
        bnez  t1, gt_m1                 ; ...
        li    t1, 1                     ; ...
        sd    t1, g_dirty - g(gp)       ; ...
gt_m1:  bnez  t0, gt_bn                 ; ...
        call  gt_aim                    ; up again: to another flower
        j     gt_bn                     ; ...
gt_mv:  li    t1, 1                     ; flying: two pixels nearer in x and in y, and a
        sd    t1, g_dirty - g(gp)       ;   flutter up and down
        lw    a0, BF_X(s1)              ; ...
        lw    a1, BF_TX(s1)             ; ...
        call  gt_near                   ; ...
        sw    a0, BF_X(s1)              ; ...
        mv    t3, a2                    ; (there in x?)
        lw    a0, BF_Y(s1)              ; ...
        lw    a1, BF_TY(s1)             ; ...
        call  gt_near                   ; ...
        and   t3, t3, a2                ; (and in y?)
        bnez  t3, gt_sit                ; ...
        ld    t0, g_tic - g(gp)         ; ...
        add   t0, t0, s0                ; ...
        srli  t0, t0, 2                 ; ...
        andi  t0, t0, 3                 ; 0 1 2 3 -> -1 0 1 0
        addi  t1, t0, -1                ; ...
