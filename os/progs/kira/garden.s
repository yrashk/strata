; gt_near(a0 = a coordinate, a1 = where it is going) -> a0 = two nearer, a2
; = 1 if it is there. Clobbers t0.
gt_near:
        li    a2, 0                     ; ...
        sub   t0, a1, a0                ; ...
        addi  t0, t0, 2                 ; within two: there
        sltiu t0, t0, 5                 ; ...
