; =============================================================================
; ifconfig.s: the network interface's address and counters
; =============================================================================
;
;   ifconfig              show the address, the link, the packet counters
;   ifconfig ADDRESS      give the interface a new address
;   ifconfig dns A [B]    the resolvers (DNS servers): first A, then B
;
; Starts the network server if none runs (os/lib/sys.s net_init).

        .data                           ; data Local Store
        .align 8                        ; ...
st:     .space 64 + 32 * 8              ; STAT's data
s_nonet: .ascii "ifconfig: no network server\n" ; ...
s_nonet_e:
s_use:  .ascii "usage: ifconfig [ADDRESS | dns A [B]]\n" ; ...
s_use_e:
s_if:   .ascii "net0  inet "            ; ...
s_if_e:
s_mtu:  .ascii "  mtu 1500  link "      ; ...
s_mtu_e:
s_up:   .ascii "up\n"                   ; ...
s_up_e:
s_down: .ascii "down\n"                 ; ...
s_down_e:
s_in:   .ascii "      packets in "      ; ...
s_in_e:
s_out:  .ascii "  out "                 ; ...
s_out_e:
s_drop: .ascii "  dropped "             ; ...
s_drop_e:
s_q:    .ascii "      device: queued "  ; ...
s_q_e:
s_lost: .ascii "  lost "                ; ...
s_lost_e:
s_dns:  .ascii "      dns "             ; ...
s_dns_e:
s_dnsw: .ascii "dns"                    ; ...
s_none: .ascii "none"                   ; ...
        .align 8                        ; ...

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        call  sys_init                  ; ...
        call  net_init                  ; the network server
        bnez  a0, m_nonet               ; ...
        call  sys_cmdline               ; an address?
        add   s2, a0, a1                ; ...
        mv    a1, s2                    ; ...
        call  arg_next                  ; (the program's name)
        mv    a0, a2                    ; ...
        mv    a1, s2                    ; ...
        call  arg_next                  ; ...
        beqz  a1, m_show                ; none: show
        mv    s3, a2                    ; (the rest)
        mv    s4, a0                    ; "dns"?
        mv    s5, a1                    ; ...
        la    a2, s_dnsw                ; ...
        li    a3, 3                     ; ...
        call  str_eq                    ; ...
        bnez  a0, m_dns                 ; ...
        mv    a0, s4                    ; ...
        mv    a1, s5                    ; ...
        call  net_aton                  ; ...
        bltz  a0, m_use                 ; ...
        call  net_setip                 ; ...
m_show:
        la    a0, st                    ; ...
        call  net_stat                  ; ...
        bltz  a0, m_nonet               ; ...
        la    s1, st                    ; s1 = the data
        la    a0, s_if                  ; "net0  inet 10.0.0.1  mtu 1500  link up"
        li    a1, s_if_e - s_if         ; ...
        call  out_str                   ; ...
        ld    a0, 0(s1)                 ; ...
        call  out_ip                    ; ...
        la    a0, s_mtu                 ; ...
        li    a1, s_mtu_e - s_mtu       ; ...
        call  out_str                   ; ...
        ld    t0, 8(s1)                 ; the device's STATUS: bit 24 link
        srli  t0, t0, 24                ; ...
        andi  t0, t0, 1                 ; ...
        la    a0, s_up                  ; ...
        li    a1, s_up_e - s_up         ; ...
        bnez  t0, m_l                   ; ...
        la    a0, s_down                ; ...
        li    a1, s_down_e - s_down     ; ...
m_l:
        call  out_str                   ; ...
        la    a0, s_in                  ; "packets in 12  out 12  dropped 0"
        li    a1, s_in_e - s_in         ; ...
        call  out_str                   ; ...
        ld    a0, 16(s1)                ; ...
        call  out_dec                   ; ...
        la    a0, s_out                 ; ...
        li    a1, s_out_e - s_out       ; ...
        call  out_str                   ; ...
        ld    a0, 24(s1)                ; ...
        call  out_dec                   ; ...
        la    a0, s_drop                ; ...
        li    a1, s_drop_e - s_drop     ; ...
        call  out_str                   ; ...
        ld    a0, 32(s1)                ; ...
        call  out_dec                   ; ...
        call  out_nl                    ; ...
        la    a0, s_q                   ; "device: queued 0  lost 0"
        li    a1, s_q_e - s_q           ; ...
        call  out_str                   ; ...
        ld    a0, 8(s1)                 ; (STATUS bits 23..16)
        srli  a0, a0, 16                ; ...
        andi  a0, a0, 255               ; ...
        call  out_dec                   ; ...
        la    a0, s_lost                ; ...
        li    a1, s_lost_e - s_lost     ; ...
        call  out_str                   ; ...
        ld    a0, 8(s1)                 ; (bits 63..32)
        srli  a0, a0, 32                ; ...
        call  out_dec                   ; ...
        call  out_nl                    ; ...
        la    a0, s_dns                 ; "dns 8.8.8.8 1.1.1.1"
        li    a1, s_dns_e - s_dns       ; ...
        call  out_str                   ; ...
        ld    a0, 48(s1)                ; ...
        call  pr_srv                    ; ...
        li    a0, ' '                   ; ...
        call  out_chr                   ; ...
        ld    a0, 56(s1)                ; ...
        call  pr_srv                    ; ...
        call  out_nl                    ; ...
        li    a0, 0                     ; ...
        call  sys_exit                  ; ...
m_dns:
        li    s4, 0                     ; s4, s5 = the resolvers
        li    s5, 0                     ; ...
        mv    a0, s3                    ; ...
        mv    a1, s2                    ; ...
        call  arg_next                  ; ...
        beqz  a1, m_use                 ; ...
        mv    s3, a2                    ; ...
        call  net_aton                  ; ...
        bltz  a0, m_use                 ; ...
        mv    s4, a0                    ; ...
        mv    a0, s3                    ; a second?
        mv    a1, s2                    ; ...
        call  arg_next                  ; ...
        beqz  a1, m_dset                ; ...
        call  net_aton                  ; ...
        bltz  a0, m_use                 ; ...
        mv    s5, a0                    ; ...
m_dset:
        mv    a0, s4                    ; ...
        mv    a1, s5                    ; ...
        call  net_setdns                ; ...
        j     m_show                    ; ...
m_use:
        la    a0, s_use                 ; ...
        li    a1, s_use_e - s_use       ; ...
        call  err_str                   ; ...
        li    a0, 2                     ; ...
        call  sys_exit                  ; ...
m_nonet:
        la    a0, s_nonet               ; ...
        li    a1, s_nonet_e - s_nonet   ; ...
        call  err_str                   ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...

; pr_srv(a0 = a resolver, 0 none)
pr_srv:
        bnez  a0, out_ip                ; (tail call)
        la    a0, s_none                ; ...
        li    a1, 4                     ; ...
        j     out_str                   ; (tail call)

        .include "../lib/sys.s"         ; the program library
