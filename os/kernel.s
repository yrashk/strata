; =============================================================================
; kernel.s: StrataOS 0.1, a microkernel with preemptive multitasking
; =============================================================================
;
; Booted by the boot ROM on every core: code at I-LS 0x4000, data at D-LS
; 0xA000, entered with a0 = core number. Core 0 is the SYSTEM CORE; every
; other core is a WORKER. This file is the resident kernel (I-LS 0x4000..
; 0x7FFF on every core). The rest of the kernel is CODE UNITS in the image's
; .far section (os/kunits/*.s), paged by core 0 itself (see "Paging the
; kernel" below).
;
; ---- What the kernel does, and what it leaves to servers ---------------------
; The kernel creates and destroys processes and places them on cores, hands
; out memory (arenas: 1 MiB by default, revocable by address), runs the
; timer (a preemption tick every time slice, 2 ms by default; timeouts of timed waits) and moves
; messages between processes. Everything else is a user-mode server process:
;   proc  (pid 1) processes, names, exit statuses, signals; holds the kernel endpoint
;   dev   the device manager (platform table, framebuffer, halting)
;   fs    files: owns the block device
;   tty   the console: line discipline, Ctrl-C
;   pipe  pipes
; The kernel loads proc, dev and fs itself at boot (fs is needed to load
; anything else); proc starts tty, pipe and then `sh -l`.
;
; ---- Memory map ----------------------------------------------------------------
; Every core:  I-LS 0x0000 boot ROM | 0x4000 kernel | 0x8000..0xFFFF programs
;              D-LS 0x0000..0x9FFF program data | 0xA000 kernel data | 0xE000.. stack
; Core 0 runs no programs: its I-LS 0x8000..0xFFFF is the kernel code cache
; and its D-LS 0x0000..0x9FFF holds the kernel's tables (K0_* below).
;
; System memory (T3): [0, 32 KiB) the kernel shared table (KST, below);
; [32 KiB, 64 KiB) core 0's own message buffers; the ARENA POOL [16 MiB,
; 48 MiB) (c13 from the boot ROM; on a 16 MiB machine [1 MiB, 15 MiB));
; [48 MiB, 64 MiB) the framebuffer window (c14).
; The pool is one revocable region (cdom at boot); core 0 keeps its revoker
; (K_POOL) and a bitmap of its 256 KiB granules. An arena is any run of
; whole granules, 1 MiB unless proc asks MEMORY for more: core 0 cuts the
; revoker at the arena's bounds, `crevoke`s that piece (every older
; capability based there dies, and a fresh one comes out) and joins the
; revoker again. When the process ends its arena is revoked the same way
; (whatever it lent out dies) and its granules are free for the next one.
; The number of processes is limited by memory, and by the fixed tables
; (NARENA arenas, NKPROC process records, NSLOT threads per worker).
;
; Core 0's own resident code (event loop, paging trap) sits at I-LS 0x7700
; (K0TEXT) and up: workers never run it, so programs may overwrite that range
; of a worker's I-LS (the `overlay` example does) without harming its kernel.
;
; An arena (1 MiB + E: E bytes more than the default), for a process with N threads,
; at offsets from its LAYOUT BASE L = arena base + E (a 1 MiB arena: L = base):
;   [-E, P)       the program's memory (thread 0's c0), P = 0xD0000 - (N-1) * 48 KiB
;                 (0x7F000: the start-up block proc writes; 0x80000 / 0xC0000:
;                 the input / output of old bare-metal programs like `as`)
;   [P, 0xD0000)  the save areas of threads N-1 .. 1
;   [0xD0000, 0xF0000) the program image as fs loaded it (each thread's kernel
;                 keeps a read-only share: code is reloaded from it)
;   [0xF0000, 0xFC000) thread 0's save area     [0xFF000, ..) the message buffer (c5)
;                 (with one thread, the image and the save area are one capability)
; A save area (48 KiB) holds the D-LS a thread uses: its data extent at 0..
; (a StrataOS program's data section; for a bare-metal program, which may use
; any address, all of 0..0x9FFF), its live stack (sp..0x10000) at 0xA000..
; (address - 0x4000).
;
; ---- Processes and threads ------------------------------------------------------
; Every process time-shares worker cores; there are no exclusive cores. A
; StrataOS program (second code word "SYS2") run without -n is one thread with
; no core window. A bare-metal program, or one run with -n N, has N threads
; on N contiguous worker cores (no server cores), seen through the
; corebase/corecount window, so bare-metal examples run unchanged: each
; thread is scheduled on its own core, and `cgive` between threads is direct.
; Each core runs up to 16 threads of different processes (NSLOT; 11 with a 64-slot
; save table). A switched-out thread's c0..c7 stay in the core's capability save
; table (256 slots by default), whose slots are a pool shared with the queues
; (see "worker capability save table" below): only memory capabilities take
; slots (endpoints and device capabilities are rebuilt), so a thread typically
; holds 3: its memory c0, its buffer c5 and one capability for its image and
; save area. Every thread record has 10 slots reserved: all it could ever need.
; The worker's DISPATCHER (the supervisor code below) runs them: on every trap
; (svc, the preemption stop, a doorbell, a code-unit miss, halt, a
; fault, an inbox instruction to emulate) it saves the current thread's
; registers, and when it picks another one it saves c0..c7 into the save
; table and the used D-LS into the save area, and loads the next one: D-LS
; back, code reloaded from the image (or the SET_MIRROR copy), capabilities,
; registers. Switches and bytes moved are counted per process (ps shows them).
; A thread owns c0..c7 across switches; c8..c15 stay its own only while it is
; not switched out (the dispatcher borrows c8, c9 and gives them back).
; Trap-and-emulate: user-mode ctake, cpoll and tany (bit 16) trap (priv); the
; dispatcher performs them on the process's queue of gifts from its other
; threads, blocking the thread (and running another) while nothing is there.

; ---- Messages -------------------------------------------------------------------
; A message is a lent 4 KiB buffer capability: header 0 op, 8 handle, 16 length,
; 24 mode, 32 result, 40 sender pid (stamped here), data from 64. A process
; sends with `csend c5, cE` (user mode) and then `svc`:
;   a0 = 1 WAIT_REPLY  a1 doorbell core, a2 timeout (-1 none), a3 awaited base
;                      (0 = own buffer, -1 = nothing: a sleep), a4 register
;                      it arrives in -> 0, -2 interrupted, -8 timed out
;   a0 = 2 RECEIVE     (servers) a1 tag mask, a2 timeout -> a0 = token, c6 =
;                      request, c7 = its attachment; or -1 with a1 = idle tags; -8
;   a0 = 3 REPLY       a1 token, a2 bit2 send c4 first, bit0 send c7, bit1
;                      (privileged) mint an endpoint for core a3 and send it;
;                      then gives c6 back (the receiver gets them in c6, c7)
;   a0 = 4 YIELD       a0 = 5 EXIT (a1 code)    a0 = 6 NOTIFY_WAIT (a2 timeout)
;   a0 = 7 SET_MIRROR  a1 arena offset of a far copy of the I-LS program range,
;                      a2 length: code is reloaded from it on a switch-in (JITs)
;   a0 = 8 PARK (c6 -> a0 = id)   a0 = 9 UNPARK (a1 id -> c6)   a0 = 10 CLOCK (c7)
;   a0 = 11 SET_SCRATCH a1 D-LS start, a2 length (0: none): that range of the data
;                      is neither saved nor restored on a switch (undefined after one)
;   a0 = 12 SEND       a1 endpoint register (1..7), a5 attachment register (0..7,
;                      -1 none), a2..a4 as WAIT_REPLY: the dispatcher sends the
;                      attachment and then the buffer (c5) through the endpoint
;                      with nothing of this core in between, rings the doorbell
;                      and waits like WAIT_REPLY; -1: bad registers (nothing sent)
; Every capability arriving in a worker's inbox is taken by its dispatcher:
;   * one whose base is a local process's message buffer is that process's reply;
;   * one a local process waits for by base (WAIT_REPLY a3) goes to it;
;   * the pieces of a new process's arena (base known from its job record);
;   * one from a core in a local process's window is a gift between its
;     threads: queued for its emulated ctake;
;   * a 4 KiB buffer otherwise is a request for the core's server (or, with
;     no server here, is given back with result -1);
;   * anything else is an ATTACHMENT: it travels with the next message from
;     the same sender core and lands in the receiver's c6 (then c7). Senders
;     attach with svc SEND (the attachment and its message enter the inbox
;     with nothing of that core between them); a `csend` of one's own before
;     the message is only safe for a process alone on its core (proc).
; A process a server waits on may die, and a server may die (the window
; server is started and stopped by the user): the requests queued or parked
; at a server that ends go back to their senders with result -1.
; Doorbells: after a send the dispatcher writes "stop" into the destination
; core's core-control word, so its dispatcher runs at once.
;
; ---- The system core's endpoint ----------------------------------------------------
; Only proc (and dev, for HALT) hold it. Ops: 1 CREATE, 2 DESTROY, 3 MEMORY,
; 4 STATS, 5 TUNE, 6 FREE, 8 HALT, 9 NOTIFY (see os/kunits/ops.s). The kernel sends proc
; op 7 EXITED (handle = pid, length = status) when a process ends.
;
; ---- Paging the kernel ---------------------------------------------------------------
; Kernel units are 2 KiB slots of the far image (c12, from the boot ROM).
; Resident code calls one with `la t5, unit; xcall ra, c12, t5`; a miss traps
; to k_trap, which copies the unit into one of 16 cache slots at I-LS
; 0x8000..0xFFFF (round robin), maps it and retries. Code in a unit runs at a
; cache address, not where it was assembled, so: units call resident code
; with `la t6, f; jalr ra, t6, 0`, other units with xcall, and return with
; `xret ra` (a far return link pages the caller back in if it was evicted).
;
