; Core 0's own resident code, at I-LS K0TEXT (0x7700) and up. Workers never run
; it, so a program on a worker may overwrite this range of its I-LS (the
; bare-metal `overlay` example loads code at 0x7700..0x777F) without harming its
; kernel. (A worker's panic report calls the firmware here: a worker whose
; program overwrote it cannot report a kernel fault.)
; =============================================================================
        .org  K0TEXT                    ; (the worker code above must end below it)
; ---- the event loop: one tany for everything ---------------------------------------
k_loop:
        li    t0, 1                     ; wait for: a capability in the inbox (bit 16)
        slli  t0, t0, 16                ; ...
        ld    t1, k_tarmed-GPBASE(gp)   ; and the timer, while armed
        beqz  t1, kl_wait               ; ...
        ori   t0, t0, 1 << TG_TMR       ; ...
kl_wait:
        tany  t1, t0                    ; sleep until something happens
        andi  t2, t1, 1 << TG_TMR       ; the timer?
        beqz  t2, kl_msg                ; no
        ld    t3, k_tarmed-GPBASE(gp)   ; (only if it was armed)
        beqz  t3, kl_msg                ; ...
        sd    zero, k_tarmed-GPBASE(gp) ; it fired
        la    t5, u_tick                ; preemption ticks and timeouts
        xcall ra, c12, t5               ; ...
        j     k_loop                    ; next event
kl_msg:
        srli  t2, t1, 16                ; a capability?
        beqz  t2, k_loop                ; no
        ctake c8                        ; take it (oldest from the lowest sender)
        csrr  s1, takefrom              ; s1 = the sender
        cvalid t0, c8                   ; still alive?
        beqz  t0, kl_drop               ; no: drop it
        cperms t0, c8                   ; t0 = space << 8 | perms
        srli  t0, t0, 8                 ; space
        li    t1, 4                     ; device space: a worker's "look at my events" token
        beq   t0, t1, kl_event          ; ...
        li    t1, 3                     ; system memory?
        bne   t0, t1, kl_stash          ; no: an attachment
        clen  t1, c8                    ; a 4 KiB message buffer?
        li    t2, 4096                  ; ...
        bne   t1, t2, kl_stash          ; no: an attachment
        cbase t1, c8                    ; one of ours coming back?
        li    t2, MSGB                  ; ...
        bltu  t1, t2, kl_req            ; no
        li    t2, MSGB + NMSGB * 4096   ; ...
        bgeu  t1, t2, kl_req            ; no
        mv    a0, s1                    ; yes: a reply to the kernel
        la    t5, u_kreply              ; ...
        xcall ra, c12, t5               ; ...
        j     k_loop                    ; next event
kl_req:
        mv    a0, s1                    ; a request from a process
        la    t5, u_req                 ; ...
        xcall ra, c12, t5               ; ...
        j     k_loop                    ; next event
kl_event:
        cclear c8                       ; the token carries nothing
        mv    a0, s1                    ; the worker's exit events
        la    t5, u_events              ; ...
        xcall ra, c12, t5               ; ...
        j     k_loop                    ; next event
kl_stash:
        mv    a0, s1                    ; keep it for the sender's next message
        call  k_stash                   ; ...
        j     k_loop                    ; next event
kl_drop:
        cclear c8                       ; a dead capability
        j     k_loop                    ; next event

; k_stash(a0 = sender): c8 -> a free stash slot, tagged with its sender
k_stash:
        li    t0, 0                     ; t0 = stash slot
        li    t1, K0_STASHT             ; sender table
ks_find:
        li    t2, 4                     ; four slots
        bge   t0, t2, ks_full           ; none free
        slli  t3, t0, 3                 ; ...
        add   t3, t1, t3                ; ...
        ld    t4, 0(t3)                 ; free?
        beqz  t4, ks_put                ; yes
        addi  t0, t0, 1                 ; next
        j     ks_find                   ; ...
ks_put:
        addi  t4, a0, 1                 ; sender + 1
        sd    t4, 0(t3)                 ; ...
        addi  a0, t0, K_STASH           ; its save-table slot
        j     csv8                      ; c8 -> it (tail call)
ks_full:
        cclear c8                       ; nowhere to keep it
        ret                             ; done

; k_unstash(a0 = sender) -> a0 = 0 and the oldest attachment from it in c8, or -1
k_unstash:
        li    t0, 0                     ; slot
        li    t1, K0_STASHT             ; sender table
        addi  t5, a0, 1                 ; sender + 1
ku_find:
        li    t2, 4                     ; ...
        bge   t0, t2, ku_none           ; none
        slli  t3, t0, 3                 ; ...
        add   t3, t1, t3                ; ...
        ld    t4, 0(t3)                 ; ...
        beq   t4, t5, ku_get            ; from that sender
        addi  t0, t0, 1                 ; next
        j     ku_find                   ; ...
ku_get:
        sd    zero, 0(t3)               ; free the slot
        addi  a0, t0, K_STASH           ; restore it
        j     crs8                      ; (tail call: a0 = 0, or -1 if it died)
ku_none:
        li    a0, -1                    ; nothing
        ret                             ; done

; ---- core 0's trap handler: page kernel units in --------------------------------------
k_trap:
        csrw  sscratch, t0              ; free t0
        la    t0, w_probe               ; a probed crestore that failed?
        ld    t0, 0(t0)                 ; ...
        bnez  t0, probe_fail            ; yes: skip it (shared with the workers)
        la    t0, k_tsave               ; save what paging uses
        sd    t1, 0(t0)                 ; ...
        sd    t2, 8(t0)                 ; ...
        sd    t3, 16(t0)                ; ...
        sd    t4, 24(t0)                ; ...
        sd    t5, 32(t0)                ; ...
        sd    t6, 40(t0)                ; ...
        sd    a1, 48(t0)                ; ...
        sd    a2, 56(t0)                ; ...
        sd    ra, 64(t0)                ; ...
        csrr  t1, cause                 ; why?
        li    t2, 8                     ; xmiss: a unit is not resident
        bne   t1, t2, k_panic           ; anything else is a kernel bug
        csrr  t1, tval                  ; the missed far address (bit 63: a return link)
        slli  t1, t1, 1                 ; drop bit 63
        srli  t1, t1, 1                 ; ...
        cbase t2, c12                   ; offset within the far image
        sub   a2, t1, t2                ; ...
        srli  a2, a2, 11                ; round down to its 2 KiB unit
        slli  a2, a2, 11                ; ...
        clen  t3, c12                   ; inside the image?
        bgeu  a2, t3, k_panic           ; no: a bad call
        ld    t3, k_vict-GPBASE(gp)     ; the cache slot to replace, round robin,
        csrr  t4, epc                   ; but never the one the missing xcall / xret is in
        li    t5, PTEXT                 ; (the retry must find its own code there)
        sub   t4, t4, t5                ; ...
        srli  t4, t4, 11                ; its slot (resident code gives a slot >= 16)
        bne   t4, t3, kt_vok            ; ...
        addi  t3, t3, 1                 ; skip it
        andi  t3, t3, 15                ; ...
kt_vok:
        addi  t4, t3, 1                 ; the next victim
        andi  t4, t4, 15                ; ...
        sd    t4, k_vict-GPBASE(gp)     ; ...
        slli  a1, t3, 11                ; a1 = the slot's I-LS address
        li    t4, PTEXT                 ; ...
        add   a1, a1, t4                ; ...
        li    t4, 2048                  ; one unit
        tgetx tg0, a1, c12, a2, t4      ; far image -> I-LS (forgets the slot's old mapping)
        ld    t4, k_loads-GPBASE(gp)    ; count it
        addi  t4, t4, 1                 ; ...
        sd    t4, k_loads-GPBASE(gp)    ; ...
        la    t4, kxmap_tab             ; map entry t3: xmap t3, a1, c12, a2
        slli  t3, t3, 3                 ; 8 bytes per entry
        add   t4, t4, t3                ; ...
        jalr  ra, t4, 0                 ; ...
        la    t0, k_tsave               ; restore and retry
        ld    t1, 0(t0)                 ; ...
        ld    t2, 8(t0)                 ; ...
        ld    t3, 16(t0)                ; ...
        ld    t4, 24(t0)                ; ...
        ld    t5, 32(t0)                ; ...
        ld    t6, 40(t0)                ; ...
        ld    a1, 48(t0)                ; ...
        ld    a2, 56(t0)                ; ...
        ld    ra, 64(t0)                ; ...
        csrr  t0, sscratch              ; ...
        eret                            ; retry the xcall / xret: it hits now
kxmap_tab:
        xmap  0, a1, c12, a2            ; slot 0
        ret                             ; .
        xmap  1, a1, c12, a2            ; slot 1
        ret                             ; .
        xmap  2, a1, c12, a2            ; slot 2
        ret                             ; .
        xmap  3, a1, c12, a2            ; slot 3
        ret                             ; .
        xmap  4, a1, c12, a2            ; slot 4
        ret                             ; .
        xmap  5, a1, c12, a2            ; slot 5
        ret                             ; .
        xmap  6, a1, c12, a2            ; slot 6
        ret                             ; .
        xmap  7, a1, c12, a2            ; slot 7
        ret                             ; .
        xmap  8, a1, c12, a2            ; slot 8
        ret                             ; .
        xmap  9, a1, c12, a2            ; slot 9
        ret                             ; .
        xmap  10, a1, c12, a2           ; slot 10
        ret                             ; .
        xmap  11, a1, c12, a2           ; slot 11
        ret                             ; .
        xmap  12, a1, c12, a2           ; slot 12
        ret                             ; .
        xmap  13, a1, c12, a2           ; slot 13
        ret                             ; .
        xmap  14, a1, c12, a2           ; slot 14
        ret                             ; .
        xmap  15, a1, c12, a2           ; slot 15
        ret                             ; .

; k_ring(a0 = core): core 0 rings a worker's doorbell (core-control stop)
k_ring:
        blez  a0, kr_no                 ; never core 0
        ld    t0, w_ncores-GPBASE(gp)   ; a worker
        bgeu  a0, t0, kr_no             ; ...
        slli  t0, a0, 3                 ; its word
        la    t1, w_bell                ; 1 = stop
        li    t2, 1                     ; ...
        sd    t2, 0(t1)                 ; ...
        li    t2, 8                     ; ...
        tput  tg0, t1, c4, t0, t2       ; ...
kr_no:
        ret                             ; ...

; k_wake(a0 = core): doorbell and a token (wakes it whether it runs or idles)
k_wake:
        blez  a0, kr_no                 ; never core 0
        ld    t0, w_ncores-GPBASE(gp)   ; ...
        bgeu  a0, t0, kr_no             ; ...
        cgive c2, a0                    ; the token: a copy of the console capability
        j     k_ring                    ; and the doorbell

; kp_find(a0 = pid) -> a0 = its kernel process record, or 0
kp_find:
        li    t0, K0_PROC               ; ...
        li    t1, NKPROC                ; ...
kpf_l:
        beqz  t1, kpf_no                ; ...
        ld    t2, KP_PID(t0)            ; ...
        beq   t2, a0, kpf_yes           ; ...
        addi  t0, t0, KP_SIZE           ; ...
        addi  t1, t1, -1                ; ...
        j     kpf_l                     ; ...
kpf_yes:
        bnez  a0, kpf_ok                ; (pid 0 never matches)
kpf_no:
        li    a0, 0                     ; ...
        ret                             ; ...
kpf_ok:
        mv    a0, t0                    ; ...
        ret                             ; ...

; k_fputs(a0 = far address, a1 = length <= 240): print text kept in the far
; image (units keep their strings with their code)
k_fputs:
        srli  t2, a0, 3                ; clear the low 3 bits
        slli  t2, t2, 3                ; ...
        sub   t3, a0, t2                ; ...
        add   t1, a1, t3                ; ...
        addi  t1, t1, 7                 ; ...
        srli  t1, t1, 3                ; clear the low 3 bits
        slli  t1, t1, 3                ; ...
        la    t0, k_fbuf                ; ...
        tget  tg0, t0, c12, t2, t1      ; far image -> D-LS
        add   a0, t0, t3                ; the text
        j     fw_puts                   ; (the tput waits behind the tget)

