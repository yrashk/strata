; =============================================================================
; Entry
; =============================================================================
kentry:
        li    sp, STACKTOP              ; a stack for now
        la    gp, GPBASE                ; kernel data base
        cclear c10                      ; the boot ROM's image shares are not needed any more
        cclear c11                      ; (copyable capabilities: dropping them loses nothing)
        bnez  a0, wboot                 ; every core but 0 is a worker

; =============================================================================
; Core 0: the system core
; =============================================================================
        la    sp, k0stack_top           ; core 0's stack
        cmov  c15, c12                  ; the firmware clobbers c12..c14: keep the far image,
        cvalid t0, c13                  ;   the second heap piece
        beqz  t0, k0_nohigh             ;   ...
        cmov  c8, c13                   ;   ...
        li    a0, K_SPARE               ;   (in the save table for u_mem)
        call  csv8                      ;   ...
        li    t0, 1                     ;   ...
        sd    t0, k_hashigh-GPBASE(gp)  ;   ...
k0_nohigh:
        cvalid t0, c14                  ;   and the framebuffer window
        beqz  t0, k0_nofb               ;   ...
        cmov  c8, c14                   ;   ...
        li    a0, K_FB                  ;   ...
        call  csv8                      ;   ...
        li    t0, 1                     ;   ...
        sd    t0, k_hasfb-GPBASE(gp)    ;   ...
k0_nofb:
        call  fw_init                   ; platform table, console window
        call  fw_cores                  ; how many cores
        sd    a0, w_ncores-GPBASE(gp)   ; ...
        li    a0, 4                     ; the block device (the kernel reads it only at boot)
        li    a1, 0                     ; ...
        call  fw_find                   ; ...
        call  fw_blk_open               ; ...
        cmov  c12, c15                  ; the far image again
        la    t0, k_trap                ; core 0's own trap handler: pages kernel units
        csrw  tvec, t0                  ; ...
        li    t0, 11                    ; kernel units: 2 KiB slots
        csrw  xslot, t0                 ; ...
        la    t5, u_boot                ; start-up is a code unit
        xcall ra, c12, t5               ; (the first miss pages it in)
        j     k_loop                    ; then the event loop

; k_panic: a fault inside the kernel. Report it and stop this core.
k_panic:
        la    gp, GPBASE                ; (in case)
        sd    ra, k_pra-GPBASE(gp)      ; keep ra for the report
        la    sp, kpstack_top           ; a clean stack
        ld    t0, w_me-GPBASE(gp)       ; a worker keeps its console in the save table
        beqz  t0, kp_con                ; ...
        cclear c2                       ; ...
        crestore c2, T_CON              ; ...
kp_con:
        la    a0, s_panic               ; "kernel fault: cause "
        li    a1, s_panic_e - s_panic   ; ...
        call  fw_puts                   ; (c2 is the console on every core)
        csrr  a0, cause                 ; ...
        call  fw_putdec                 ; ...
        la    a0, s_pepc                ; " epc "
        li    a1, 5                     ; ...
        call  fw_puts                   ; ...
        csrr  a0, epc                   ; ...
        call  fw_puthex                 ; ...
        la    a0, s_pepc+5              ; " tval "
        li    a1, 6                     ; ...
        call  fw_puts                   ; ...
        csrr  a0, tval                  ; ...
        call  fw_puthex                 ; ...
        la    a0, s_pra                 ; " ra "
        li    a1, 4                     ; ...
        call  fw_puts                   ; ...
        ld    a0, k_pra-GPBASE(gp)      ; ...
        call  fw_puthex                 ; ...
        la    a0, s_pcore               ; " core "
        li    a1, 6                     ; ...
        call  fw_puts                   ; ...
        csrr  a0, coreid                ; ...
        call  fw_putdec                 ; ...
        call  fw_putnl                  ; ...
        li    a0, 99                    ; exit code
        halt                            ; stop this core

; probe_fail: a crestore of a dead capability trapped; skip it and say so
probe_fail:
        la    t0, w_probe               ; the probe is over
        sd    zero, 0(t0)               ; ...
        li    t0, 1                     ; it failed
        sd    t0, w_probefail-GPBASE(gp) ; (gp is always the kernel's in supervisor code)
        csrr  t0, epc                   ; skip the crestore
        addi  t0, t0, 4                 ; ...
        csrw  epc, t0                   ; ...
        csrr  t0, sscratch              ; ...
        eret                            ; back into the kernel

; =============================================================================
; Save-table helpers (the slot in a register: csavex / crestorex)
; =============================================================================

; csv8(a0 = slot): c8 -> save-table slot a0
csv8:
        csavex c8, a0                   ; ...
        ret                             ; ...

; crs8(a0 = slot) -> a0 = 0 and the capability in c8, or -1 if the slot was
; empty or its capability died (c8 then empty)
crs8:
        cclear c8                       ; c8 must be free
        sd    zero, w_probefail-GPBASE(gp) ; ...
        li    t0, 1                     ; arm the probe
        la    t1, w_probe               ; ...
        sd    t0, 0(t1)                 ; ...
        crestorex c8, a0                ; (skipped if it traps)
        la    t1, w_probe               ; disarm
        sd    zero, 0(t1)               ; ...
        ld    a0, w_probefail-GPBASE(gp) ; failed?
        sub   a0, zero, a0              ; 0 or -1
        ret                             ; done

; w_params(a0 = the save table's slots, CTAB) -> a0 = threads per worker core:
; the pool and its reservations (w_npool, w_pres, w_pbonus, w_ngen). Core 0
; calls it for placement, every worker for its own pool.
w_params:
        addi  a0, a0, -7                ; the pool: all but the dispatcher's 7
        sd    a0, w_npool-GPBASE(gp)    ; ...
        li    t0, NSLOT * PRES_B + 32   ; room to reserve every capability of NSLOT threads?
        blt   a0, t0, wpa_s             ; ...
        li    t1, PRES_B                ; yes: nothing can run out
        li    t2, 0                     ; ...
        li    t3, NSLOT                 ; ...
        j     wpa_set                   ; ...
wpa_s:
        li    t1, PRES_S                ; no (64 slots): 4 each, the server 5
        li    t2, 1                     ; ...
        li    t3, NSLOT_S               ; ...
wpa_set:
        sd    t1, w_pres-GPBASE(gp)     ; ...
        sd    t2, w_pbonus-GPBASE(gp)   ; ...
        mul   t4, t1, t3                ; general = pool - threads x reservation - bonus
        add   t4, t4, t2                ; ...
        sub   t4, a0, t4                ; ...
        sd    t4, w_ngen-GPBASE(gp)     ; ...
        mv    a0, t3                    ; ...
        ret                             ; ...

; ---- the save-table pool (worker) -------------------------------------------------------
; pool_get(a0 = thread record, or 0 for a queue entry) -> a0 = a free pool slot
; | charge << 8 (1: charged to the record's reservation, 0: the general part),
; taken; or -1 if none may be taken. Uses t0..t4.
pool_get:
        beqz  a0, pg_gen                ; a queue entry: the general part
        ld    t0, PR_NSL(a0)            ; slots charged to its reservation so far
        ld    t1, PR_FLAGS(a0)          ; its reservation: w_pres, the server's w_pbonus more
        andi  t1, t1, F_SERVER          ; ...
        srli  t1, t1, 1                 ; ...
        ld    t2, w_pbonus-GPBASE(gp)   ; ...
        and   t1, t1, t2                ; ...
        ld    t2, w_pres-GPBASE(gp)     ; ...
        add   t1, t1, t2                ; ...
        bge   t0, t1, pg_over           ; used up: an extra slot
        addi  t0, t0, 1                 ; charged to it
        sd    t0, PR_NSL(a0)            ; ...
        li    t4, 1 << 8                ; (charge 1)
        j     pg_find                   ; ...
pg_over:
        ld    t1, w_ngen-GPBASE(gp)     ; a thread leaves the last QRES to the queues
        addi  t1, t1, -QRES             ; ...
        j     pg_g2                     ; ...
pg_gen:
        ld    t1, w_ngen-GPBASE(gp)     ; queues may take all of the general part
pg_g2:
        ld    t0, w_gen-GPBASE(gp)      ; general slots taken
        bge   t0, t1, pg_none           ; no more
        addi  t0, t0, 1                 ; ...
        sd    t0, w_gen-GPBASE(gp)      ; ...
        li    t4, 0                     ; (charge 0)
pg_find:
        ld    t0, w_pused-GPBASE(gp)    ; one more taken
        addi  t0, t0, 1                 ; ...
        sd    t0, w_pused-GPBASE(gp)    ; ...
        li    a0, -1                    ; the lowest free pool entry (the counts make sure
pg_l:                                   ;   there is one: reservations + general = w_npool)
        addi  a0, a0, 1                 ; ...
        srli  t0, a0, 6                 ; its bitmap word
        slli  t0, t0, 3                 ; ...
        la    t1, w_pool                ; ...
        add   t0, t1, t0                ; ...
        ld    t1, 0(t0)                 ; ...
        andi  t2, a0, 63                ; its bit
        srl   t3, t1, t2                ; ...
        andi  t3, t3, 1                 ; ...
        bnez  t3, pg_l                  ; taken
        li    t3, 1                     ; mark it taken
        sll   t3, t3, t2                ; ...
        or    t1, t1, t3                ; ...
        sd    t1, 0(t0)                 ; ...
        li    t1, NPOOL0                ; entry -> slot: 0..56, then 64.. (past the dispatcher's)
        bltu  a0, t1, pg_s              ; ...
        addi  a0, a0, 7                 ; ...
pg_s:
        or    a0, a0, t4                ; slot | charge << 8
        ret                             ; ...
pg_none:
        li    a0, -1                    ; ...
        ret                             ; ...

; pool_put(a0 = slot | charge << 8, a1 = the record charged if charge 1): free it
pool_put:
        andi  t0, a0, 255               ; the slot -> its pool entry
        li    t1, NPOOL0                ; ...
        bltu  t0, t1, pp_e              ; ...
        addi  t0, t0, -7                ; ...
pp_e:
        srli  t2, t0, 6                 ; its bitmap word
        slli  t2, t2, 3                 ; ...
        la    t1, w_pool                ; ...
        add   t2, t1, t2                ; ...
        andi  t0, t0, 63                ; its bit
        li    t1, 1                     ; ...
        sll   t1, t1, t0                ; ...
        ld    t0, 0(t2)                 ; clear it
        or    t0, t0, t1                ; ...
        xor   t0, t0, t1                ; ...
        sd    t0, 0(t2)                 ; ...
        ld    t2, w_pused-GPBASE(gp)    ; one fewer taken
        addi  t2, t2, -1                ; ...
        sd    t2, w_pused-GPBASE(gp)    ; ...
        srli  t0, a0, 8                 ; whose?
        bnez  t0, pp_rec                ; the record's
        ld    t0, w_gen-GPBASE(gp)      ; the general part's
        addi  t0, t0, -1                ; ...
        sd    t0, w_gen-GPBASE(gp)      ; ...
        ret                             ; ...
pp_rec:
        ld    t0, PR_NSL(a1)            ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, PR_NSL(a1)            ; ...
        ret                             ; ...

; pool_take(a0 = slot | charge << 8, a1 = record charged): c8 = its capability
; (crs8), the slot freed -> a0 = 0, or -1 if it had died (c8 empty)
pool_take:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        andi  a0, a0, 255               ; ...
        call  crs8                      ; ...
        ld    t0, 8(sp)                 ; ...
        sd    a0, 8(sp)                 ; (the result)
        mv    a0, t0                    ; free the slot
        ld    a1, 16(sp)                ; ...
        call  pool_put                  ; ...
        ld    a0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; w_stow(a0 = record, a1 = register 0..7): c8 (live) becomes what that switched-out
; thread holds in the register (PR_CAP): an endpoint of length 1 and a device
; capability the device root (or the console capability) covers are described,
; not saved (c8 cleared); anything else goes into a pool slot. -> a0 = 0, or -1
; if no slot may be taken (c8 and PR_CAP unchanged)
w_stow:
        slli  t0, a1, 3                 ; t5 = the descriptor's address
        add   t5, a0, t0                ; ...
        addi  t5, t5, PR_CAP            ; ...
        cperms t0, c8                   ; t1 = space, t2 = perms
        srli  t1, t0, 8                 ; ...
        andi  t2, t0, 63                ; ...
        ld    t3, w_devperm-GPBASE(gp)  ; only what crestrict leaves of the root's (R, W, D)
        or    t4, t2, t3                ; ...
        bne   t4, t3, wsw_slot          ; ...
        slli  t6, t2, 2                 ; t6 = perms << 2
        li    t0, 6                     ; an endpoint?
        bne   t1, t0, wsw_dev           ; ...
        clen  t0, c8                    ; as cmkep makes them: length 1
        li    t3, 1                     ; ...
        bne   t0, t3, wsw_slot          ; ...
        cbase t0, c8                    ; 2 | perms << 2 | node << 8
        slli  t0, t0, 8                 ; ...
        or    t6, t6, t0                ; ...
        ori   t6, t6, 2                 ; ...
        j     wsw_desc                  ; ...
wsw_dev:
        li    t0, 4                     ; device space?
        bne   t1, t0, wsw_slot          ; ...
        cbase t0, c8                    ; t0 = base, t3 = length
        clen  t3, c8                    ; ...
        andi  t4, t3, 7                 ; a length csplit can cut (whole words)?
        beqz  t4, wsw_cut               ; ...
        bnez  t0, wsw_slot              ; no: only the console capability itself
        li    t4, 1                     ;   (base 0, length 1, W and D at most: T_CON)
        bne   t3, t4, wsw_slot          ; ...
        andi  t4, t2, 63 - 18           ; ...
        bnez  t4, wsw_slot              ; ...
        j     wsw_dd                    ; ...
wsw_cut:
        add   t4, t0, t3                ; inside the root?
        ld    t1, w_devlen-GPBASE(gp)   ; ...
        bgtu  t4, t1, wsw_slot          ; ...
wsw_dd:
        slli  t0, t0, 8                 ; 3 | perms << 2 | base << 8 | length << 32
        or    t6, t6, t0                ; ...
        slli  t3, t3, 32                ; ...
        or    t6, t6, t3                ; ...
        ori   t6, t6, 3                 ; ...
wsw_desc:
        sd    t6, 0(t5)                 ; described: nothing to keep
        cclear c8                       ; ...
        li    a0, 0                     ; ...
        ret                             ; ...
wsw_slot:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    t5, 8(sp)                 ; ...
        call  pool_get                  ; a slot for it
        bltz  a0, wsw_ret               ; none
        ld    t5, 8(sp)                 ; 1 | (slot | charge << 8) << 8
        slli  t0, a0, 8                 ; ...
        ori   t0, t0, 1                 ; ...
        sd    t0, 0(t5)                 ; ...
        andi  a0, a0, 255               ; c8 -> the slot
        call  csv8                      ; ...
        li    a0, 0                     ; ...
wsw_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; w_fetch(a0 = record, a1 = register 0..7) -> c8 = what that switched-out thread
; holds in the register (rebuilt, or restored and its slot freed; empty if
; nothing, or if it died); the descriptor is cleared. Uses c9.
w_fetch:
        cclear c8                       ; ...
        slli  t0, a1, 3                 ; the descriptor
        add   t5, a0, t0                ; ...
        ld    t6, PR_CAP(t5)            ; ...
        sd    zero, PR_CAP(t5)          ; ...
        beqz  t6, wft_ret               ; nothing
        andi  t0, t6, 3                 ; which kind?
        li    t1, 1                     ; saved in a slot
        bne   t0, t1, wft_ep            ; ...
        mv    a1, a0                    ; (the record it is charged to)
        srli  a0, t6, 8                 ; ...
        j     pool_take                 ; (tail call)
wft_ep:
        srli  t2, t6, 2                 ; t2 = perms
        andi  t2, t2, 63                ; ...
        li    t1, 2                     ; an endpoint: minted again
        bne   t0, t1, wft_dev           ; ...
        srli  t0, t6, 8                 ; ...
        cmkep c8, t0                    ; ...
        crestrict c8, c8, t2            ; ...
wft_ret:
        ret                             ; ...
wft_dev:
        srli  t3, t6, 32                ; t3 = length
        andi  t4, t3, 7                 ; the console capability (length 1)?
        beqz  t4, wft_cut               ; ...
        crestore c8, T_CON              ; a copy of it
        crestrict c8, c8, t2            ; ...
        ret                             ; ...
wft_cut:
        srli  t0, t6, 8                 ; t0 = base
        li    t1, 0xffffff              ; ...
        and   t0, t0, t1                ; ...
        cclear c9                       ; (the KST copy: the kst_* helpers restore it)
        crestore c9, T_DEVR             ; cut from the device root: [base, base + length)
        csplit c8, c9, t0               ; ...
        cclear c9                       ; ...
        csplit c9, c8, t3               ; ...
        cclear c9                       ; ...
        crestrict c8, c8, t2            ; ...
        ret                             ; ...

; preg_put(a0 = register 0..7): c8 -> that capability register. a0 = 0, or -1
; (c8 dropped) if the register holds a live linear capability
preg_put:
        la    t0, pput_tab              ; 24 bytes per entry
        li    t1, 24                    ; ...
        mul   t1, a0, t1                ; ...
        add   t0, t0, t1                ; ...
        jr    t0                        ; ...
pput_tab:
        cvalid t1, c0                   ; c0: empty?
        beqz  t1, pp_m0                 ; yes: just move
        cperms t1, c0                   ; what is there
        j     pp_chk                    ; may it be replaced?
pp_m0:  cmov  c0, c8                    ; deliver
        j     pp_ok                     ; .
        cvalid t1, c1                   ; c1: empty?
        beqz  t1, pp_m1                 ; yes: just move
        cperms t1, c1                   ; what is there
        j     pp_chk                    ; may it be replaced?
pp_m1:  cmov  c1, c8                    ; deliver
        j     pp_ok                     ; .
        cvalid t1, c2                   ; c2: empty?
        beqz  t1, pp_m2                 ; yes: just move
        cperms t1, c2                   ; what is there
        j     pp_chk                    ; may it be replaced?
pp_m2:  cmov  c2, c8                    ; deliver
        j     pp_ok                     ; .
        cvalid t1, c3                   ; c3: empty?
        beqz  t1, pp_m3                 ; yes: just move
        cperms t1, c3                   ; what is there
        j     pp_chk                    ; may it be replaced?
pp_m3:  cmov  c3, c8                    ; deliver
        j     pp_ok                     ; .
        cvalid t1, c4                   ; c4: empty?
        beqz  t1, pp_m4                 ; yes: just move
        cperms t1, c4                   ; what is there
        j     pp_chk                    ; may it be replaced?
pp_m4:  cmov  c4, c8                    ; deliver
        j     pp_ok                     ; .
        cvalid t1, c5                   ; c5: empty?
        beqz  t1, pp_m5                 ; yes: just move
        cperms t1, c5                   ; what is there
        j     pp_chk                    ; may it be replaced?
pp_m5:  cmov  c5, c8                    ; deliver
        j     pp_ok                     ; .
        cvalid t1, c6                   ; c6: empty?
        beqz  t1, pp_m6                 ; yes: just move
        cperms t1, c6                   ; what is there
        j     pp_chk                    ; may it be replaced?
pp_m6:  cmov  c6, c8                    ; deliver
        j     pp_ok                     ; .
        cvalid t1, c7                   ; c7: empty?
        beqz  t1, pp_m7                 ; yes: just move
        cperms t1, c7                   ; what is there
        j     pp_chk                    ; may it be replaced?
pp_m7:  cmov  c7, c8                    ; deliver
        j     pp_ok                     ; .
pp_chk:                                 ; t0 = the entry, t1 = perms of a live capability there
        andi  t2, t1, 16                ; copyable: may be replaced
        bnez  t2, pp_go                 ; ...
        cclear c8                       ; a live linear capability is there: drop the new one
        li    a0, -1                    ; ...
        ret                             ; ...
pp_go:
        addi  t0, t0, 16                ; the cmov
        jr    t0                        ; ...
pp_ok:
        li    a0, 0                     ; done
        ret                             ; ...

; preg_get(a0 = register 0..7): that capability register -> c8 (c8 empty if it was)
preg_get:
        cclear c8                       ; ...
        la    t0, pget_tab              ; 12 bytes per entry
        li    t1, 12                    ; ...
        mul   t1, a0, t1                ; ...
        add   t0, t0, t1                ; ...
        jr    t0                        ; ...
pget_tab:
        cvalid t1, c0                   ; c0
        bnez  t1, pg_0                  ; .
        ret                             ; .
        cvalid t1, c1                   ; c1
        bnez  t1, pg_1                  ; .
        ret                             ; .
        cvalid t1, c2                   ; c2
        bnez  t1, pg_2                  ; .
        ret                             ; .
        cvalid t1, c3                   ; c3
        bnez  t1, pg_3                  ; .
        ret                             ; .
        cvalid t1, c4                   ; c4
        bnez  t1, pg_4                  ; .
        ret                             ; .
        cvalid t1, c5                   ; c5
        bnez  t1, pg_5                  ; .
        ret                             ; .
        cvalid t1, c6                   ; c6
        bnez  t1, pg_6                  ; .
        ret                             ; .
        cvalid t1, c7                   ; c7
        bnez  t1, pg_7                  ; .
        ret                             ; .
pg_0:   cmov  c8, c0                    ; move it
        ret                             ; .
pg_1:   cmov  c8, c1                    ; .
        ret                             ; .
pg_2:   cmov  c8, c2                    ; .
        ret                             ; .
pg_3:   cmov  c8, c3                    ; .
        ret                             ; .
pg_4:   cmov  c8, c4                    ; .
        ret                             ; .
pg_5:   cmov  c8, c5                    ; .
        ret                             ; .
pg_6:   cmov  c8, c6                    ; .
        ret                             ; .
pg_7:   cmov  c8, c7                    ; .
        ret                             ; .

; kst_rd(a0 = KST offset) -> a0 = the word ; kst_wr(a0 = offset, a1 = value)
; kst_add(a0 = offset, a1 = amount) -> a0 = old ; kst_or(a0 = offset, a1 = bits)
; (core 0 holds the KST in c6; workers restore it from slot T_KST into c9)
kst_rd:
        li    a1, 0                     ; add nothing
kst_add:
        ld    t0, w_me-GPBASE(gp)       ; which core?
        bnez  t0, kad_w                 ; a worker
        tamo.add a0, c6, a0, a1         ; core 0: c6
        ret                             ; ...
kad_w:
        cvalid t0, c9                   ; workers keep the KST in c9 (from the save table
        bnez  t0, kad_wk                ;   when the dispatcher lent c9 out)
        crestore c9, T_KST              ; ...
kad_wk:
        tamo.add a0, c9, a0, a1         ; workers: c9 (restored on dispatcher entry)
        ret                             ; ...
kst_wr:
        ld    t0, w_me-GPBASE(gp)       ; which core?
        bnez  t0, kwr_w                 ; a worker
        tamo.swap a0, c6, a0, a1        ; core 0
        ret                             ; ...
kwr_w:
        cvalid t0, c9                   ; workers keep the KST in c9 (from the save table
        bnez  t0, kwr_wk                ;   when the dispatcher lent c9 out)
        crestore c9, T_KST              ; ...
kwr_wk:
        tamo.swap a0, c9, a0, a1        ; workers
        ret                             ; ...
kst_or:
        ld    t0, w_me-GPBASE(gp)       ; which core?
        bnez  t0, kor_w                 ; a worker
        tamo.or a0, c6, a0, a1          ; core 0
        ret                             ; ...
kor_w:
        cvalid t0, c9                   ; workers keep the KST in c9 (from the save table
        bnez  t0, kor_wk                ;   when the dispatcher lent c9 out)
        crestore c9, T_KST              ; ...
kor_wk:
        tamo.or a0, c9, a0, a1          ; workers
        ret                             ; ...
kst_xchg0:                              ; kst_xchg0(a0 = offset) -> a0 = old value, now 0
        li    a1, 0                     ; ...
        j     kst_wr                    ; ...

