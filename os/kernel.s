; ---- boot -------------------------------------------------------------------------------
wboot:
        sd    a0, w_me-GPBASE(gp)       ; our core
        la    sp, kstack_top            ; the dispatcher's own stack
        ctake c8, zero                  ; the KST, from core 0
        li    a0, T_KST                 ; keep it
        call  csv8                      ; ...
        ctake c8, zero                  ; core control, from core 0 (for doorbells)
        li    a0, T_CCTL                ; ...
        call  csv8                      ; ...
        cmov  c8, c3                    ; a clock for processes: [timer, timer + 16), read-only
        li    t0, TMR_PORT              ; ...
        csplit c9, c8, t0               ; c9 = from the timer on
        li    t0, 16                    ; NOW and FREQ
        csplit c10, c9, t0              ; c9 = the two registers
        cclear c8                       ; ...
        cclear c10                      ; ...
        li    t0, 1 | 16                ; read + copyable
        crestrict c8, c9, t0            ; ...
        li    a0, T_CLOCK               ; ...
        call  csv8                      ; ...
        clen  t0, c3                    ; the device root: its length and permissions
        sd    t0, w_devlen-GPBASE(gp)   ;   (w_stow, w_fetch cut device capabilities
        cperms t0, c3                   ;   from it again)
        andi  t0, t0, 63                ; ...
        sd    t0, w_devperm-GPBASE(gp)  ; ...
        cmov  c8, c3                    ; the device root (dev gets a copy)
        li    a0, T_DEVR                ; ...
        call  csv8                      ; ...
        cmov  c8, c2                    ; console output (bare-metal programs print with it)
        li    a0, T_CON                 ; ...
        call  csv8                      ; ...
        cclear c2                       ; the dispatcher keeps nothing in registers
        cclear c3                       ; ...
        cclear c4                       ; ...
        li    t0, -1                    ; nothing loaded, nothing running
        sd    t0, w_loaded-GPBASE(gp)   ; ...
        sd    t0, w_cur-GPBASE(gp)      ; ...
        sd    t0, w_server-GPBASE(gp)   ; no server here
        la    t0, w_trap                ; every user trap comes to w_trap
        csrw  tvec, t0                  ; ...
        li    a0, T_KST                 ; how many cores: from the KST
        call  crs8                      ; ...
        cmov  c9, c8                    ; ...
        li    a0, G_NCORES              ; ...
        call  kst_rd                    ; ...
        sd    a0, w_ncores-GPBASE(gp)   ; ...
        li    a0, G_CTAB                ; the save table's size: the pool
        call  kst_rd                    ; ...
        call  w_params                  ; ...
        j     w_sched                   ; and wait for work

; ---- the trap entry ---------------------------------------------------------------------
; Any trap from a user process: save its registers into its record.
w_trap:
        csrw  sscratch, t0              ; free t0
        csrr  t0, status                ; from supervisor mode?
        andi  t0, t0, 2                 ; (bit 1: the trap came from the kernel)
        bnez  t0, w_ktrap               ; yes
        la    t0, w_curp                ; the current process's record
        ld    t0, 0(t0)                 ; ...
        sd    x1, PR_REGS+8(t0)         ; save x1
        sd    x2, PR_REGS+16(t0)        ; save x2
        sd    x3, PR_REGS+24(t0)        ; save x3
        sd    x4, PR_REGS+32(t0)        ; save x4
        sd    x6, PR_REGS+48(t0)        ; save x6
        sd    x7, PR_REGS+56(t0)        ; save x7
        sd    x8, PR_REGS+64(t0)        ; save x8
        sd    x9, PR_REGS+72(t0)        ; save x9
        sd    x10, PR_REGS+80(t0)       ; save x10
        sd    x11, PR_REGS+88(t0)       ; save x11
        sd    x12, PR_REGS+96(t0)       ; save x12
        sd    x13, PR_REGS+104(t0)      ; save x13
        sd    x14, PR_REGS+112(t0)      ; save x14
        sd    x15, PR_REGS+120(t0)      ; save x15
        sd    x16, PR_REGS+128(t0)      ; save x16
        sd    x17, PR_REGS+136(t0)      ; save x17
        sd    x18, PR_REGS+144(t0)      ; save x18
        sd    x19, PR_REGS+152(t0)      ; save x19
        sd    x20, PR_REGS+160(t0)      ; save x20
        sd    x21, PR_REGS+168(t0)      ; save x21
        sd    x22, PR_REGS+176(t0)      ; save x22
        sd    x23, PR_REGS+184(t0)      ; save x23
        sd    x24, PR_REGS+192(t0)      ; save x24
        sd    x25, PR_REGS+200(t0)      ; save x25
        sd    x26, PR_REGS+208(t0)      ; save x26
        sd    x27, PR_REGS+216(t0)      ; save x27
        sd    x28, PR_REGS+224(t0)      ; save x28
        sd    x29, PR_REGS+232(t0)      ; save x29
        sd    x30, PR_REGS+240(t0)      ; save x30
        sd    x31, PR_REGS+248(t0)      ; save x31
        csrr  t1, sscratch              ; and t0 (x5)
        sd    t1, PR_REGS+40(t0)        ; ...
        csrr  t1, epc                   ; where it was
        sd    t1, PR_EPC(t0)            ; ...
        la    gp, GPBASE                ; kernel data base
        la    sp, kstack_top            ; kernel stack
        mv    s0, t0                    ; s0 = the record (callee-saved through the dispatcher)
        csrw  corebase, zero            ; the dispatcher numbers cores for real
        csrw  corecount, zero           ; ...
        csrr  s1, cause                 ; s1 = why
        li    t1, 8                     ; xmiss: a code unit
        beq   s1, t1, wt_page           ; ...
        call  stash                     ; the dispatcher borrows c8 and c9 from here on
        li    t1, 11                    ; priv: ctake / cpoll / tany on the inbox: emulate them
        beq   s1, t1, wt_priv           ; ...
        li    t1, 14                    ; svc
        beq   s1, t1, wt_svc            ; ...
        li    t1, 13                    ; stop: a tick, a doorbell or a kill
        beq   s1, t1, w_sched           ; just reschedule
        li    t1, 12                    ; halt: the program ended
        beq   s1, t1, wt_halt           ; ...
        li    a1, 1                     ; anything else: a fault
        slli  a1, a1, 63                ; status = 1 << 63 | cause
        or    a1, a1, s1                ; ...
        j     wt_exit                   ; ...
wt_halt:
        ld    a1, PR_REGS+80(s0)        ; status = its a0, the low 32 bits
        slli  a1, a1, 32                ; ...
        srli  a1, a1, 32                ; ...
wt_exit:
        ld    a0, w_cur-GPBASE(gp)      ; the current slot ends
        call  w_exit                    ; ...
        j     w_sched                   ; something else runs
wt_page:
        call  page_in                   ; load the unit, map it
        bnez  a0, wt_nopage             ; not possible: a fault
        mv    s2, s0                    ; resume at once: no switch, nothing else changes
        j     w_eret                    ; ...
wt_nopage:
        li    a1, 1                     ; fault: xmiss
        slli  a1, a1, 63                ; ...
        ori   a1, a1, 8                 ; ...
        j     wt_exit                   ; ...

; A trap inside the dispatcher: a probed crestore, or a bug.
w_ktrap:
        la    t0, w_probe               ; probing?
        ld    t0, 0(t0)                 ; ...
        bnez  t0, probe_fail            ; yes: skip the instruction
        j     k_panic                   ; no: report and stop the core

; ---- the running process's c8 and c9 ---------------------------------------------------------
; The dispatcher works in c8 and c9; a process owns c0..c7 across switches,
; but keeps c8..c15 as long as it is not switched out (bare-metal programs use
; them briefly). stash() moves its c8, c9 aside, unstash() puts them back.
stash:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        li    t0, 1                     ; stashed (even if empty)
        sd    t0, w_stashed-GPBASE(gp)  ; ...
        sd    zero, w_st8-GPBASE(gp)    ; ...
        sd    zero, w_st9-GPBASE(gp)    ; ...
        cvalid t0, c8                   ; c8 holds something?
        beqz  t0, st_9                  ; ...
        li    a0, T_P8                  ; ...
        call  csv8                      ; ...
        cclear c8                       ; (a copyable one stays behind otherwise)
        li    t0, 1                     ; ...
        sd    t0, w_st8-GPBASE(gp)      ; ...
st_9:
        cvalid t0, c9                   ; c9?
        beqz  t0, st_ret                ; ...
        csave c9, T_P9                  ; ...
        cclear c9                       ; ...
        li    t0, 1                     ; ...
        sd    t0, w_st9-GPBASE(gp)      ; ...
st_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...
unstash:
        ld    t0, w_stashed-GPBASE(gp)  ; borrowed?
        beqz  t0, us_ret                ; no (the paging path leaves them alone)
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        sd    zero, w_stashed-GPBASE(gp) ; ...
        cclear c9                       ; c9 first (crs8 works through c8)
        ld    t0, w_st9-GPBASE(gp)      ; ...
        beqz  t0, us_8                  ; ...
        li    a0, T_P9                  ; ...
        call  crs8                      ; ...
        cmov  c9, c8                    ; ...
us_8:
        cclear c8                       ; then c8
        ld    t0, w_st8-GPBASE(gp)      ; ...
        beqz  t0, us_done               ; ...
        li    a0, T_P8                  ; ...
        call  crs8                      ; ...
us_done:
        sd    zero, w_st8-GPBASE(gp)    ; ...
        sd    zero, w_st9-GPBASE(gp)    ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
us_ret:
        ret                             ; ...
; stash_drop(): the loaded process leaves: its borrowed c8, c9 go
stash_drop:
        ld    t0, w_stashed-GPBASE(gp)  ; ...
        beqz  t0, us_ret                ; ...
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        call  unstash                   ; back into c8, c9 ...
        cclear c8                       ; ... and dropped
        cclear c9                       ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; ---- trap-and-emulate: ctake, cpoll, tany on the inbox ----------------------------------------
; In user mode these trap (priv, tval = the instruction): the inbox belongs to
; the dispatcher, which keeps each process's gifts (from its other threads) in
; the queue. Emulated with the process's core window (corebase) as in hardware.
wt_priv:
        csrr  s3, tval                  ; s3 = the instruction
        srli  t1, s3, 26                ; its opcode
        li    t2, 0x34                  ; the capability group
        beq   t1, t2, em_cap            ; ...
        li    t2, 0x36                  ; tany
        beq   t1, t2, em_tany           ; ...
em_fault:
        li    a1, 1                     ; anything else: a privilege fault
        slli  a1, a1, 63                ; ...
        ori   a1, a1, 11                ; ...
        j     wt_exit                   ; ...
em_cap:
        andi  t2, s3, 15                ; which function?
        li    t3, 10                    ; ctake
        beq   t2, t3, em_take           ; ...
        li    t3, 15                    ; cpoll
        beq   t2, t3, em_poll           ; ...
        j     em_fault                  ; ...
em_take:
        li    s2, -1                    ; s2 = the sender wanted (-1: any)
        andi  t2, s3, 16                ; named (ctake cd, rs)?
        beqz  t2, et_find               ; ...
        srli  t3, s3, 11                ; rs
        andi  t3, t3, 31                ; ...
        slli  t3, t3, 3                 ; its value (x0 reads 0: never saved)
        add   t3, s0, t3                ; ...
        ld    t3, PR_REGS(t3)           ; ...
        ld    t4, PR_WIN(s0)            ; + corebase: a real core number
        andi  t4, t4, 255               ; ...
        add   s2, t3, t4                ; ...
et_find:
        ld    a0, w_cur-GPBASE(gp)      ; a gift for this process?
        mv    a1, s2                    ; ...
        call  gift_find                 ; a0 = queue index or -1
        bltz  a0, et_block              ; none yet: the thread waits
        call  att_take                  ; c8 = it
        bnez  a0, et_find               ; (it died: look again)
        srli  a0, s3, 21                ; cd
        andi  a0, a0, 15                ; ...
        call  put_any                   ; c8 -> c_cd
em_next:
        ld    t0, PR_EPC(s0)            ; past the instruction
        addi  t0, t0, 4                 ; ...
        sd    t0, PR_EPC(s0)            ; ...
        mv    s2, s0                    ; and on with the same process
        j     w_eret                    ; ...
et_block:
        sd    s2, PR_GSND(s0)           ; wait for a gift (the instruction is retried)
        li    t0, S_GIFT                ; ...
        sd    t0, PR_STATE(s0)          ; ...
        j     w_sched                   ; something else runs
em_poll:
        ld    a0, w_cur-GPBASE(gp)      ; senders (window-relative) with gifts for it
        call  gift_mask                 ; ...
        srli  t1, s3, 21                ; rd
        andi  t1, t1, 31                ; ...
        beqz  t1, em_next               ; (x0)
        slli  t1, t1, 3                 ; ...
        add   t1, s0, t1                ; ...
        sd    a0, PR_REGS(t1)           ; ...
        j     em_next                   ; ...
em_tany:
        srli  t1, s3, 16                ; rs1: what it waits for
        andi  t1, t1, 31                ; ...
        slli  t1, t1, 3                 ; ...
        add   t1, s0, t1                ; ...
        ld    s2, PR_REGS(t1)           ; ...
        li    t2, 0x1ffff               ; ...
        and   s2, s2, t2                ; ...
        call  tany_ready                ; a0 = the ready subset of s2
        bnez  a0, et_done               ; something
        beqz  s2, et_done               ; (an empty mask returns 0 at once)
        sd    s2, PR_TMASK(s0)          ; wait (the instruction is retried)
        li    t0, S_TANY                ; ...
        sd    t0, PR_STATE(s0)          ; ...
        j     w_sched                   ; ...
et_done:
        srli  t1, s3, 21                ; rd
        andi  t1, t1, 31                ; ...
        beqz  t1, em_next               ; ...
        slli  t1, t1, 3                 ; ...
        add   t1, s0, t1                ; ...
        sd    a0, PR_REGS(t1)           ; ...
        j     em_next                   ; ...

; tany_ready(s2 = mask, s0 = record) -> a0 = idle tags of the mask, and bit 16 if a gift waits
tany_ready:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        tpoll t0, 0xffff                ; busy tags
        sub   t0, zero, t0              ; invert every bit: -x
        addi  t0, t0, -1                ; ... - 1
        li    t1, 0xffff                ; ...
        and   t0, t0, t1                ; ...
        and   t0, t0, s2                ; ...
        sd    t0, w_tmp+16-GPBASE(gp)   ; ...
        srli  t1, s2, 16                ; a gift?
        andi  t1, t1, 1                 ; ...
        beqz  t1, tr_done               ; ...
        mv    a0, s0                    ; (the slot: from the record)
        la    t2, w_procs               ; ...
        sub   a0, a0, t2                ; ...
        li    t2, PR_SIZE               ; ...
        divu  a0, a0, t2                ; ...
        li    a1, -1                    ; ...
        call  gift_find                 ; ...
        bltz  a0, tr_done               ; ...
        ld    t0, w_tmp+16-GPBASE(gp)   ; ...
        li    t1, 1                     ; ...
        slli  t1, t1, 16                ; ...
        or    t0, t0, t1                ; ...
        sd    t0, w_tmp+16-GPBASE(gp)   ; ...
tr_done:
        ld    a0, w_tmp+16-GPBASE(gp)   ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; gift_find(a0 = slot, a1 = sender or -1) -> a0 = queue index of its gift (from
; that sender; or from the lowest-numbered sender with one), the oldest, or -1
gift_find:
        li    t0, 0                     ; index
        li    t5, -1                    ; best index
        li    t6, -1                    ; its sender (unsigned max)
        li    a2, -1                    ; its order
gf_l:
        li    t2, NATT                  ; ...
        bge   t0, t2, gf_done           ; ...
        la    t1, w_att                 ; used?
        slli  t3, t0, 4                 ; ...
        add   t3, t1, t3                ; ...
        ld    t4, 0(t3)                 ; sender + 1
        beqz  t4, gf_n                  ; ...
        addi  t4, t4, -1                ; ...
        la    t1, w_attown              ; owned by the slot?
        slli  t2, t0, 3                 ; ...
        add   t1, t1, t2                ; ...
        ld    t1, 0(t1)                 ; ...
        bne   t1, a0, gf_n              ; ...
        bltz  a1, gf_any                ; that sender?
        bne   t4, a1, gf_n              ; ...
gf_any:
        bltu  t4, t6, gf_take           ; a lower sender
        bne   t4, t6, gf_n              ; a higher one
        la    t1, w_attord              ; the same sender: the older one
        slli  t2, t0, 3                 ; ...
        add   t1, t1, t2                ; ...
        ld    t1, 0(t1)                 ; ...
        bgeu  t1, a2, gf_n              ; ...
gf_take:
        mv    t5, t0                    ; the best so far
        mv    t6, t4                    ; ...
        la    t1, w_attord              ; ...
        slli  t2, t0, 3                 ; ...
        add   t1, t1, t2                ; ...
        ld    a2, 0(t1)                 ; ...
gf_n:
        addi  t0, t0, 1                 ; ...
        j     gf_l                      ; ...
gf_done:
        mv    a0, t5                    ; ...
        ret                             ; ...

; gift_mask(a0 = slot) -> a0 = bit (sender - corebase) for each sender with a gift for it
gift_mask:
        li    a1, 0                     ; the mask
        li    t0, 0                     ; index
gm_l:
        li    t2, NATT                  ; ...
        bge   t0, t2, gm_done           ; ...
        la    t1, w_att                 ; used?
        slli  t3, t0, 4                 ; ...
        add   t3, t1, t3                ; ...
        ld    t4, 0(t3)                 ; ...
        beqz  t4, gm_n                  ; ...
        la    t1, w_attown              ; that slot's?
        slli  t2, t0, 3                 ; ...
        add   t1, t1, t2                ; ...
        ld    t1, 0(t1)                 ; ...
        bne   t1, a0, gm_n              ; ...
        addi  t4, t4, -1                ; sender - corebase
        ld    t5, PR_WIN(s0)            ; ...
        andi  t5, t5, 255               ; ...
        sub   t4, t4, t5                ; ...
        li    t5, 64                    ; ...
        bgeu  t4, t5, gm_n              ; ...
        li    t5, 1                     ; ...
        sll   t5, t5, t4                ; ...
        or    a1, a1, t5                ; ...
gm_n:
        addi  t0, t0, 1                 ; ...
        j     gm_l                      ; ...
gm_done:
        mv    a0, a1                    ; ...
        ret                             ; ...

; put_any(a0 = register 0..15): c8 -> that register of the running process
; (c8 and c9 are its stashed ones; c10..c15 it holds itself)
put_any:
        li    t0, 8                     ; c0..c7
        bltu  a0, t0, preg_put          ; (tail call)
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        li    t0, 10                    ; c8 / c9: replace the stashed one
        bgeu  a0, t0, pa_hi             ; ...
        sd    a0, 8(sp)                 ; ...
        cclear c9                       ; (the dispatcher's c9 is free here)
        cmov  c9, c8                    ; keep the new one in c9
        li    t0, 8                     ; which?
        ld    a0, 8(sp)                 ; ...
        bne   a0, t0, pa_9              ; ...
        ld    t0, w_st8-GPBASE(gp)      ; an old c8 goes
        beqz  t0, pa_8n                 ; ...
        li    a0, T_P8                  ; ...
        call  crs8                      ; ...
        cclear c8                       ; ...
pa_8n:
        cmov  c8, c9                    ; the new one is its c8
        li    a0, T_P8                  ; ...
        call  csv8                      ; ...
        cclear c8                       ; ...
        li    t0, 1                     ; ...
        sd    t0, w_st8-GPBASE(gp)      ; ...
        j     pa_ret                    ; ...
pa_9:
        ld    t0, w_st9-GPBASE(gp)      ; an old c9 goes
        beqz  t0, pa_9n                 ; ...
        li    a0, T_P9                  ; ...
        call  crs8                      ; ...
        cclear c8                       ; ...
pa_9n:
        csave c9, T_P9                  ; the new one is its c9
        cclear c9                       ; ...
        li    t0, 1                     ; ...
        sd    t0, w_st9-GPBASE(gp)      ; ...
        j     pa_ret                    ; ...
pa_hi:
        la    t0, phi_tab               ; c10..c15: straight in (if free)
        addi  t1, a0, -10               ; 8 bytes per entry
        slli  t1, t1, 3                 ; ...
        add   t0, t0, t1                ; ...
        jalr  ra, t0, 0                 ; ...
pa_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...
phi_tab:
        j     phi_10                    ; c10
        nop                             ; .
        j     phi_11                    ; c11
        nop                             ; .
        j     phi_12                    ; c12
        nop                             ; .
        j     phi_13                    ; c13
        nop                             ; .
        j     phi_14                    ; c14
        nop                             ; .
        j     phi_15                    ; c15
        nop                             ; .
phi_10: cvalid t0, c10                  ; occupied: the gift is dropped (hardware would trap)
        bnez  t0, phi_drop              ; .
        cmov  c10, c8                   ; .
        ret                             ; .
phi_11: cvalid t0, c11                  ; .
        bnez  t0, phi_drop              ; .
        cmov  c11, c8                   ; .
        ret                             ; .
phi_12: cvalid t0, c12                  ; .
        bnez  t0, phi_drop              ; .
        cmov  c12, c8                   ; .
        ret                             ; .
phi_13: cvalid t0, c13                  ; .
        bnez  t0, phi_drop              ; .
        cmov  c13, c8                   ; .
        ret                             ; .
phi_14: cvalid t0, c14                  ; .
        bnez  t0, phi_drop              ; .
        cmov  c14, c8                   ; .
        ret                             ; .
phi_15: cvalid t0, c15                  ; .
        bnez  t0, phi_drop              ; .
        cmov  c15, c8                   ; .
        ret                             ; .
phi_drop:
        cclear c8                       ; .
        ret                             ; .

; ---- svc ----------------------------------------------------------------------------------
wt_svc:
        li    t0, 1                     ; an svc keeps the core unless it blocks or yields
        sd    t0, w_keep-GPBASE(gp)     ; ...
        ld    t0, PR_EPC(s0)            ; return after the svc
        addi  t0, t0, 4                 ; ...
        sd    t0, PR_EPC(s0)            ; ...
        ld    t0, PR_REGS+80(s0)        ; a0 = the function
        li    t1, 1                     ; WAIT_REPLY
        beq   t0, t1, sv_wait           ; ...
        li    t1, 2                     ; RECEIVE
        beq   t0, t1, sv_recv           ; ...
        li    t1, 3                     ; REPLY
        beq   t0, t1, sv_reply          ; ...
        li    t1, 4                     ; YIELD
        beq   t0, t1, sv_yield          ; ...
        li    t1, 5                     ; EXIT
        beq   t0, t1, sv_exit           ; ...
        li    t1, 6                     ; NOTIFY_WAIT
        beq   t0, t1, sv_note           ; ...
        li    t1, 7                     ; SET_MIRROR
        beq   t0, t1, sv_mirror         ; ...
        li    t1, 8                     ; PARK
        beq   t0, t1, sv_park           ; ...
        li    t1, 9                     ; UNPARK
        beq   t0, t1, sv_unpark         ; ...
        li    t1, 10                    ; CLOCK
        beq   t0, t1, sv_clock          ; ...
        li    t1, 11                    ; SET_SCRATCH
        beq   t0, t1, sv_scratch        ; ...
        li    t1, 12                    ; SEND
        beq   t0, t1, sv_send           ; ...
        li    a0, -1                    ; unknown
sv_ret:
        sd    a0, PR_REGS+80(s0)        ; the result in its a0
        j     w_sched                   ; (the scheduler resumes it, or runs another)

sv_exit:
        ld    a1, PR_REGS+88(s0)        ; the code
        slli  a1, a1, 32                ; low 32 bits
        srli  a1, a1, 32                ; ...
        j     wt_exit                   ; ...

sv_yield:
        sd    zero, w_keep-GPBASE(gp)   ; let the others go first
        li    a0, 0                     ; ...
        j     sv_ret                    ; ...

; SET_MIRROR: a1 = arena offset of a far copy of the I-LS program range, a2 =
; its length: from now on the code is reloaded from there on a switch-in
sv_mirror:
        ld    t0, PR_REGS+88(s0)        ; offset
        ld    t1, PR_REGS+96(s0)        ; length (at most the program range)
        li    t2, STACKTOP - PTEXT      ; ...
        bleu  t1, t2, svm_l             ; ...
        mv    t1, t2                    ; ...
svm_l:
        addi  t1, t1, 7                 ; whole words
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        slli  t1, t1, 32                ; offset | length << 32 (0: none)
        or    t0, t0, t1                ; ...
        sd    t0, PR_MIRROR(s0)         ; ...
        li    a0, 0                     ; ...
        j     sv_ret                    ; ...

; SET_SCRATCH: a1 = D-LS start, a2 = length (0: none): not saved nor restored on a
; switch (its contents are undefined after a switch-in); kept word-aligned inside
sv_scratch:
        ld    t0, PR_REGS+88(s0)        ; start, rounded up to a word
        addi  t0, t0, 7                 ; ...
        srli  t0, t0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        ld    t1, PR_REGS+88(s0)        ; end = start + length, rounded down
        ld    t2, PR_REGS+96(s0)        ; ...
        add   t1, t1, t2                ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        bltu  t0, t1, svs_set           ; a range
        li    t0, 0                     ; empty: none
        li    t1, 0                     ; ...
svs_set:
        sd    t0, PR_SCRB(s0)           ; ...
        sd    t1, PR_SCRE(s0)           ; ...
        li    a0, 0                     ; ...
        j     sv_ret                    ; ...

sv_clock:
        li    a0, 7                     ; c7 ...
        call  preg_get                  ; (drop what is there: into c8, then cleared)
        cclear c8                       ; ...
        li    a0, T_CLOCK               ; the clock
        call  crs8                      ; ...
        li    a0, 7                     ; -> c7
        call  preg_put                  ; ...
        li    a0, 0                     ; ...
        j     sv_ret                    ; ...

; SEND: a1 endpoint register, a5 attachment register (-1 none); then as
; WAIT_REPLY (a2 timeout, a3 awaited base, a4 register). Both capabilities
; enter the destination's inbox here, in supervisor mode: no other process
; of this core can send between them, so the attachment rides with its own
; message. A send to this core's own server first empties the inbox (two
; entries per sender: the dispatcher must never wait on its own queue).
sv_send:
        ld    s2, PR_REGS+88(s0)        ; s2 = the endpoint's register
        ld    s3, PR_REGS+120(s0)       ; s3 = the attachment's register, -1 none
        li    t0, 8                     ; an endpoint register: 0..7, not the buffer's
        bgeu  s2, t0, svs_bad           ; ...
        li    t1, 5                     ; ...
        beq   s2, t1, svs_bad           ; ...
        cvalid t2, c5                   ; a buffer to send?
        beqz  t2, svs_bad               ; ...
        bltz  s3, svs_ep                ; no attachment
        bgeu  s3, t0, svs_bad           ; an attachment register: 0..7, not the buffer,
        beq   s3, t1, svs_bad           ;   not the endpoint
        beq   s3, s2, svs_bad           ; ...
svs_ep:
        mv    a0, s2                    ; look at the endpoint (in c8)
        call  preg_get                  ; ...
        cvalid t0, c8                   ; live?
        beqz  t0, svs_bad               ; ...
        cperms t0, c8                   ; space << 8 | perms: an endpoint (space 6)
        cbase s4, c8                    ; s4 = the core it names
        srli  t1, t0, 8                 ; ...
        andi  t0, t0, 2                 ; one we may send through (W)?
        addi  t1, t1, -6                ; ...
        mv    a0, s2                    ; (back into its register meanwhile)
        sd    t0, w_tmp+16-GPBASE(gp)   ; ...
        sd    t1, w_tmp+24-GPBASE(gp)   ; ...
        call  preg_put                  ; ...
        cclear c8                       ; (a copy, if it is copyable)
        ld    t0, w_tmp+16-GPBASE(gp)   ; ...
        ld    t1, w_tmp+24-GPBASE(gp)   ; ...
        beqz  t0, svs_bad               ; no
        bnez  t1, svs_bad               ; ...
        ld    t0, w_ncores-GPBASE(gp)   ; a core (not the block device's node)
        bgeu  s4, t0, svs_bad           ; ...
        ld    t0, w_me-GPBASE(gp)       ; to this core's own server?
        bne   s4, t0, svs_go            ; no
        call  w_drain                   ; yes: empty the inbox first
        ld    t0, PR_STATE(s0)          ; (a kill order may have come with it: then
        li    t1, S_ZOMBIE              ;   this process is gone)
        beq   t0, t1, w_sched           ; ...
        cpoll t0                        ; anything of ours still there (a full queue)?
        ld    t1, w_me-GPBASE(gp)       ; ...
        srl   t0, t0, t1                ; ...
        andi  t0, t0, 1                 ; ...
        beqz  t0, svs_go                ; no
        ld    t0, PR_EPC(s0)            ; yes: run the svc again later
        addi  t0, t0, -4                ; ...
        sd    t0, PR_EPC(s0)            ; ...
        sd    zero, w_keep-GPBASE(gp)   ; (the others go first)
        j     w_sched                   ; ...
svs_go:
        mv    a0, s4                    ; wake the destination (uses c9, not c8)
        call  w_ring                    ; ...
        mv    a0, s2                    ; the endpoint -> c9
        call  preg_get                  ; ...
        cclear c9                       ; ...
        cmov  c9, c8                    ; ...
        cclear c8                       ; (a copy, if it is copyable)
        bltz  s3, svs_buf               ; no attachment
        mv    a0, s3                    ; the attachment -> c8
        call  preg_get                  ; ...
        cvalid t0, c8                   ; something there?
        beqz  t0, svs_none              ; no: nothing is sent
        csend c8, c9                    ; the attachment first
        cclear c8                       ; (a copy, if it is copyable)
svs_buf:
        csend c5, c9                    ; then the message
        cmov  c8, c9                    ; the endpoint back into its register
        cclear c9                       ; ...
        mv    a0, s2                    ; ...
        call  preg_put                  ; ...
        cclear c8                       ; (a copy, if it is copyable)
        li    t0, -1                    ; (the doorbell has been rung)
        sd    t0, PR_REGS+88(s0)        ; ...
        j     sv_wait                   ; and wait for the answer
svs_none:
        cmov  c8, c9                    ; the endpoint back into its register
        cclear c9                       ; ...
        mv    a0, s2                    ; ...
        call  preg_put                  ; ...
        cclear c8                       ; (a copy, if it is copyable)
svs_bad:
        li    a0, -1                    ; ...
        j     sv_ret                    ; ...

; WAIT_REPLY: a1 doorbell core, a2 timeout, a3 awaited base (0 own buffer,
; -1 nothing), a4 register
sv_wait:
        ld    a0, PR_REGS+88(s0)        ; ring the destination's doorbell
        call  w_ring                    ; ...
        ld    t0, PR_REGS+104(s0)       ; awaited base
        bnez  t0, svw_b                 ; given
        ld    t0, PR_BUF(s0)            ; 0: our own buffer
svw_b:
        sd    t0, PR_AWAIT(s0)          ; ...
        ld    t1, PR_REGS+112(s0)       ; destination register
        andi  t1, t1, 7                 ; ...
        bnez  t1, svw_d                 ; (0 means the default, c5)
        li    t1, 5                     ; ...
svw_d:
        sd    t1, PR_DST(s0)            ; ...
        ld    t0, PR_REGS+96(s0)        ; timeout
        call  w_deadline                ; -> PR_DEADL
        li    t0, S_WAIT                ; blocked
        sd    t0, PR_STATE(s0)          ; ...
        ld    t1, PR_AWAIT(s0)          ; not our buffer: maybe it is already here
        ld    t2, PR_BUF(s0)            ; ...
        beq   t1, t2, w_sched           ; (our buffer: the arrival flag says so)
        bltz  t1, w_sched               ; (nothing awaited: a sleep)
        mv    a0, t1                    ; an attachment with that base?
        call  att_find                  ; a0 = queue index or -1
        bltz  a0, w_sched               ; not yet
        call  att_take                  ; c8 = it
        ld    a0, PR_DST(s0)            ; into the register
        call  preg_put                  ; ...
        li    t0, S_READY               ; done waiting
        sd    t0, PR_STATE(s0)          ; ...
        li    a0, 0                     ; ...
        j     sv_ret                    ; ...

; RECEIVE: a1 tag mask, a2 timeout
sv_recv:
        ld    t0, PR_REGS+88(s0)        ; the tags
        sd    t0, PR_TAGS(s0)           ; ...
        ld    t0, PR_REGS+96(s0)        ; timeout
        call  w_deadline                ; ...
        li    t0, S_RECV                ; blocked (the scheduler completes it)
        sd    t0, PR_STATE(s0)          ; ...
        j     w_sched                   ; ...

; NOTIFY_WAIT: a2 timeout
sv_note:
        ld    t0, PR_REGS+96(s0)        ; timeout
        call  w_deadline                ; ...
        li    t0, S_NOTE                ; blocked
        sd    t0, PR_STATE(s0)          ; ...
        j     w_sched                   ; ...

; REPLY: a1 token (sender core), a2 bit0 send c7 first, bit1 mint an endpoint for core a3
sv_reply:
        call  kcaps                     ; c9 = KST
        ld    s2, PR_REGS+88(s0)        ; s2 = the core to answer
        andi  s2, s2, 255               ; ...
        ld    t0, w_ncores-GPBASE(gp)   ; a real core?
        bgeu  s2, t0, svr_bad           ; no
        mv    a0, s2                    ; wake it
        call  w_ring                    ; ...
        ld    t0, PR_REGS+96(s0)        ; attach c4 first?
        andi  t0, t0, 4                 ; ...
        beqz  t0, svr_c7                ; no
        cvalid t0, c4                   ; something there?
        beqz  t0, svr_c7                ; no
        cgive c4, s2                    ; send it
svr_c7:
        ld    t0, PR_REGS+96(s0)        ; attach c7?
        andi  t0, t0, 1                 ; ...
        beqz  t0, svr_mint              ; no
        cvalid t0, c7                   ; something there?
        beqz  t0, svr_mint              ; no
        cgive c7, s2                    ; send it first
svr_mint:
        ld    t0, PR_REGS+96(s0)        ; mint an endpoint?
        andi  t0, t0, 2                 ; ...
        beqz  t0, svr_buf               ; no
        ld    t0, PR_FLAGS(s0)          ; allowed?
        andi  t0, t0, F_PRIV            ; ...
        beqz  t0, svr_buf               ; no: silently not
        ld    t0, PR_REGS+104(s0)       ; for which core
        ld    t1, w_ncores-GPBASE(gp)   ; (the block device is node ncores)
        bgtu  t0, t1, svr_buf           ; no such node
        cmkep c8, t0                    ; an endpoint for it
        li    t0, 2 | 16                ; send-only, copyable
        crestrict c8, c8, t0            ; ...
        cgive c8, s2                    ; send it
        cclear c8                       ; (our copy)
svr_buf:
        cvalid t0, c6                   ; the request buffer
        beqz  t0, svr_dead              ; died meanwhile: nothing to give
        cgive c6, s2                    ; give it back
        li    a0, 0                     ; done
        j     sv_ret                    ; ...
svr_dead:
        cclear c6                       ; ...
        li    a0, 0                     ; (its owner is gone)
        j     sv_ret                    ; ...
svr_bad:
        li    a0, -1                    ; bad token
        j     sv_ret                    ; ...

; PARK: c6 -> a park slot, a0 = its id (-1: no room; c6 stays)
sv_park:
        li    s2, 0                     ; find a free park slot
svp_f:
        li    t0, NPARK                 ; ...
        bge   s2, t0, svp_full          ; none
        slli  t2, s2, 3                 ; ...
        la    t1, w_park                ; ...
        add   t1, t1, t2                ; ...
        ld    t2, 0(t1)                 ; used?
        beqz  t2, svp_take              ; no
        addi  s2, s2, 1                 ; next
        j     svp_f                     ; ...
svp_take:
        li    a0, 0                     ; a pool slot for it (general part)
        call  pool_get                  ; ...
        bltz  a0, svp_full              ; none
        slli  t2, s2, 3                 ; keep it
        la    t1, w_pslot               ; ...
        add   t1, t1, t2                ; ...
        sd    a0, 0(t1)                 ; ...
        mv    s3, a0                    ; ...
        la    t1, w_park                ; used now: the request's sender + 1
        add   t1, t1, t2                ; ...
        ld    t2, w_c6from-GPBASE(gp)   ; ...
        addi  t2, t2, 1                 ; ...
        sd    t2, 0(t1)                 ; ...
        li    a0, 6                     ; c6 -> c8
        call  preg_get                  ; ...
        andi  a0, s3, 255               ; -> the pool slot
        call  csv8                      ; ...
        mv    a0, s2                    ; the id
        j     sv_ret                    ; ...
svp_full:
        li    a0, -1                    ; no room
        j     sv_ret                    ; ...

; UNPARK: a1 id -> c6 ; a0 = 0, or -1 if it died (or was not there)
sv_unpark:
        ld    s2, PR_REGS+88(s0)        ; the id
        li    t0, NPARK                 ; valid?
        bgeu  s2, t0, svu_bad           ; no
        la    t1, w_park                ; used?
        slli  t2, s2, 3                 ; ...
        add   t1, t1, t2                ; ...
        ld    t2, 0(t1)                 ; ...
        beqz  t2, svu_bad               ; no
        addi  t2, t2, -1                ; (its sender: the request in c6 is from it again)
        sd    t2, w_c6from-GPBASE(gp)   ; ...
        sd    zero, 0(t1)               ; free now
        slli  t2, s2, 3                 ; restore it from its pool slot (freed)
        la    t1, w_pslot               ; ...
        add   t1, t1, t2                ; ...
        ld    a0, 0(t1)                 ; ...
        call  pool_take                 ; ...
        bnez  a0, svu_bad               ; it died
        li    a0, 6                     ; -> c6
        call  preg_put                  ; ...
        j     sv_ret                    ; (a0 = 0 or -1)
svu_bad:
        li    a0, -1                    ; ...
        j     sv_ret                    ; ...

; w_deadline(t0 = timeout ticks, -1 none): s0's deadline
w_deadline:
        bltz  t0, wd_none               ; no timeout
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    t0, 8(sp)                 ; ...
        call  w_now                     ; a0 = NOW
        ld    t0, 8(sp)                 ; ...
        add   a0, a0, t0                ; deadline
        bnez  a0, wd_set                ; (0 means none)
        li    a0, 1                     ; ...
wd_set:
        sd    a0, PR_DEADL(s0)          ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...
wd_none:
        sd    zero, PR_DEADL(s0)        ; no deadline
        ret                             ; ...

; w_now() -> a0 = the timer's NOW
w_now:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        li    a0, T_CLOCK               ; the clock
        call  crs8                      ; c8 = it
        la    t0, w_tmp                 ; 8 bytes of D-LS
        li    t1, 8                     ; NOW
        tget  tg14, t0, c8, zero, t1    ; read it
        ld    a0, 0(t0)                 ; (waits)
        cclear c8                       ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; w_ring(a0 = core): a doorbell: stop that core so its dispatcher looks at its inbox.
; It works through c9 (the KST helpers restore c9 when they need it), never
; c8: callers ring the doorbell while they hold the capability to give in c8.
w_ring:
        ld    t0, w_me-GPBASE(gp)       ; not ourselves,
        beq   a0, t0, wr_no             ; ...
        blez  a0, wr_no                 ; not core 0 (it never sleeps in user code), not -1
        ld    t0, w_ncores-GPBASE(gp)   ; a worker
        bgeu  a0, t0, wr_no             ; ...
        cclear c9                       ; (the KST copy: restored on its next use)
        crestore c9, T_CCTL             ; core control (copyable: the slot keeps it)
        slli  t0, a0, 3                 ; that core's word
        la    t1, w_bell                ; a word holding 1 = stop
        li    t2, 1                     ; ...
        sd    t2, 0(t1)                 ; ...
        li    t2, 8                     ; ...
        tput  tg14, t1, c9, t0, t2      ; ...
        cclear c9                       ; ...
wr_no:
        ret                             ; ...

; kcaps(): c9 = the KST (for the kst_* helpers)
kcaps:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        cvalid t0, c9                   ; already there?
        bnez  t0, kc_ok                 ; ...
        li    a0, T_KST                 ; ...
        call  crs8                      ; ...
        cmov  c9, c8                    ; ...
kc_ok:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; carea(a0 = field) -> a0 = KST offset of that field in our core's area
carea:
        ld    t0, w_me-GPBASE(gp)       ; our core
        slli  t0, t0, 10                ; * CA_SIZE
        add   a0, a0, t0                ; ...
        addi  a0, a0, CAREA             ; ...
        ret                             ; ...

; ---- the scheduler -------------------------------------------------------------------------
; Takes everything from the inbox, applies the kernel's commands, completes
; waits that can complete, and runs the next process (or idles).
w_sched:
        la    sp, kstack_top            ; a fresh stack (nothing is pending on it)
        call  kcaps                     ; c9 = KST
        call  w_cmds                    ; kills, notifications, new jobs, freed zombies
        call  w_drain                   ; the inbox
        call  w_poll                    ; waits that are over
        call  w_pick                    ; a0 = the slot to run, or -1
        bltz  a0, w_idle                ; nothing to run
        mv    s3, a0                    ; s3 = it
        ld    t0, w_loaded-GPBASE(gp)   ; already loaded?
        beq   t0, s3, ws_go             ; yes: no switch
        bltz  t0, ws_in                 ; nothing loaded
        mv    a0, t0                    ; save the loaded one
        call  w_out                     ; ...
        beqz  a0, ws_in                 ; ...
        ld    s3, w_loaded-GPBASE(gp)   ; no room in the pool: it stays, and runs if it can
        mv    a0, s3                    ; ...
        call  w_runnable                ; ...
        beqz  a0, w_idle                ; (or nothing runs until a slot is free)
        j     ws_go                     ; ...
ws_in:
        mv    a0, s3                    ; load the new one
        call  w_in                      ; ...
ws_go:
        mv    a0, s3                    ; complete what it was waiting for
        call  w_complete                ; ...
        mv    a0, s3                    ; and run it
        j     w_resume                  ; ...

; Nothing to run: wait for the inbox (or a server's device tags), then look again.
w_idle:
        call  w_publish                 ; runnable = 0
        li    a0, CA_CUR                ; nobody runs here now
        call  carea                     ; ...
        li    a1, 0                     ; ...
        call  kst_wr                    ; ...
        li    t0, -1                    ; nothing running
        sd    t0, w_cur-GPBASE(gp)      ; ...
        sd    zero, w_curp-GPBASE(gp)   ; ...
        cclear c8                       ; drop the dispatcher's capabilities before sleeping
        cclear c9                       ; ...
        li    t0, 1                     ; the inbox,
        slli  t0, t0, 16                ; and the device tags processes wait on
        li    t1, 0                     ; (RECEIVE of a server, an emulated tany)
        la    t2, w_procs               ; ...
wi_tl:
        li    t3, NSLOT                 ; ...
        bge   t1, t3, wi_wait           ; ...
        ld    t3, PR_STATE(t2)          ; ...
        li    t4, S_RECV                ; ...
        bne   t3, t4, wi_tt             ; ...
        ld    t4, PR_TAGS(t2)           ; ...
        j     wi_tor                    ; ...
wi_tt:
        li    t4, S_TANY                ; ...
        bne   t3, t4, wi_tn             ; ...
        ld    t4, PR_TMASK(t2)          ; ...
wi_tor:
        li    t5, 0xffff                ; ...
        and   t4, t4, t5                ; ...
        or    t0, t0, t4                ; ...
wi_tn:
        addi  t1, t1, 1                 ; ...
        addi  t2, t2, PR_SIZE           ; ...
        j     wi_tl                     ; ...
wi_wait:
        tany  t1, t0                    ; sleep
        csrr  t0, ipend                 ; a doorbell rang meanwhile: not needed now
        csrw  ipend, zero               ; (we are about to look anyway)
        j     w_sched                   ; look again

; w_pick() -> a0 = the next slot to run (round robin after the current one), or -1
w_pick:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        ld    s1, w_cur-GPBASE(gp)      ; start after the current one
        ld    t0, w_keep-GPBASE(gp)     ; (after an svc that did not block, keep it)
        sd    zero, w_keep-GPBASE(gp)   ; ...
        beqz  t0, wp_rr                 ; ...
        bltz  s1, wp_rr                 ; ...
        mv    a0, s1                    ; still runnable?
        call  w_runnable                ; ...
        beqz  a0, wp_rr                 ; no
        mv    a0, s1                    ; yes: it goes on
        j     wp_ret                    ; ...
wp_rr:
        li    s2, 0                     ; s2 = tries
wp_loop:
        li    t0, NSLOT                 ; all tried?
        bgt   s2, t0, wp_none           ; (NSLOT + 1: the current one last)
        addi  s1, s1, 1                 ; next slot
        li    t0, NSLOT                 ; wrap
        blt   s1, t0, wp_chk            ; ...
        li    s1, 0                     ; ...
wp_chk:
        addi  s2, s2, 1                 ; one more try
        mv    a0, s1                    ; runnable?
        call  w_runnable                ; ...
        beqz  a0, wp_loop               ; no
        mv    a0, s1                    ; this one
        j     wp_ret                    ; ...
wp_none:
        li    a0, -1                    ; nothing
wp_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; prec(a0 = slot) -> a0 = its record
prec:
        li    t0, PR_SIZE               ; ...
        mul   t0, a0, t0                ; ...
        la    a0, w_procs               ; ...
        add   a0, a0, t0                ; ...
        ret                             ; ...

; w_runnable(a0 = slot) -> a0 = 1 if it can run now
w_runnable:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        call  prec                      ; its record
        ld    t0, PR_STATE(a0)          ; state
        li    t1, S_READY               ; ready
        beq   t0, t1, wr_yes            ; ...
        li    t1, S_TANY                ; in an emulated tany: one of its tags went idle
        bne   t0, t1, wr_recv           ; (a gift makes it ready when it arrives)
        ld    t1, PR_TMASK(a0)          ; ...
        li    t2, 0xffff                ; ...
        and   t1, t1, t2                ; ...
        j     wr_tags                   ; ...
wr_recv:
        li    t1, S_RECV                ; in RECEIVE: a request, or an idle tag
        bne   t0, t1, wr_no2            ; ...
        ld    t1, w_nreq-GPBASE(gp)     ; requests queued?
        bnez  t1, wr_yes                ; ...
        ld    t1, PR_TAGS(a0)           ; tags it waits on
wr_tags:
        beqz  t1, wr_no2                ; none
        tpoll t2, 0xffff                ; busy tags
        sub   t2, zero, t2     ; invert every bit: -x
        addi   t2, t2, -1              ; ... - 1
        and   t1, t1, t2                ; any of them?
        bnez  t1, wr_yes                ; ...
wr_no2:
        li    a0, 0                     ; not runnable
        j     wrn_ret                   ; ...
wr_yes:
        li    a0, 1                     ; runnable
wrn_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; w_publish(): runnable count and slot states -> KST (core 0 ticks us if > 1)
w_publish:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        li    s1, 0                     ; slot
        li    s2, 0                     ; runnable count
wpb_loop:
        li    t0, NSLOT                 ; all?
        bge   s1, t0, wpb_done          ; ...
        mv    a0, s1                    ; runnable?
        call  w_runnable                ; ...
        add   s2, s2, a0                ; ...
        mv    a0, s1                    ; its pid and state -> KST
        call  prec                      ; ...
        ld    t0, PR_PID(a0)            ; ...
        ld    t1, PR_STATE(a0)          ; ...
        slli  t1, t1, 8                 ; ...
        or    a1, t0, t1                ; ...
        slli  a0, s1, 3                 ; ...
        addi  a0, a0, CA_SLOT           ; ...
        call  carea                     ; ...
        call  kst_wr                    ; ...
        addi  s1, s1, 1                 ; next
        j     wpb_loop                  ; ...
wpb_done:
        li    s1, 0                     ; a thread waiting for a gift or a tag?
        la    t2, w_procs               ; (core 0 then stops us now and then, so that
        li    t3, 0                     ;  we look at the inbox even while another
wpb_g:                                  ;  process keeps the core busy)
        li    t4, NSLOT                 ; ...
        bge   t3, t4, wpb_gd            ; ...
        ld    t4, PR_STATE(t2)          ; ...
        li    t5, S_GIFT                ; ...
        beq   t4, t5, wpb_gy            ; ...
        li    t5, S_TANY                ; ...
        bne   t4, t5, wpb_gn            ; ...
wpb_gy:
        li    s1, 1                     ; ...
wpb_gn:
        addi  t3, t3, 1                 ; ...
        addi  t2, t2, PR_SIZE           ; ...
        j     wpb_g                     ; ...
wpb_gd:
        li    a0, CA_GIFTW              ; ...
        call  carea                     ; ...
        mv    a1, s1                    ; ...
        call  kst_wr                    ; ...
        li    a0, CA_RUN                ; runnable count
        call  carea                     ; ...
        mv    a1, s2                    ; ...
        call  kst_wr                    ; ...
        li    a0, CA_POOL               ; free pool slots (STATS, `cores`)
        call  carea                     ; ...
        ld    t0, w_pused-GPBASE(gp)    ; ...
        ld    a1, w_npool-GPBASE(gp)    ; ...
        sub   a1, a1, t0                ; ...
        call  kst_wr                    ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; ---- the inbox ---------------------------------------------------------------------------
; w_drain(): take every capability in the inbox and hand it to its process
w_drain:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
wdr_loop:
        cpoll t0                        ; senders with something for us
        ld    t1, w_hold-GPBASE(gp)     ; minus senders held back (full queue)
        sub   t1, zero, t1     ; invert every bit: -x
        addi   t1, t1, -1              ; ... - 1
        and   t0, t0, t1                ; ...
        beqz  t0, wdr_done              ; nothing
        li    s1, 0                     ; s1 = the lowest such sender
wdr_low:
        andi  t1, t0, 1                 ; ...
        bnez  t1, wdr_take              ; ...
        srli  t0, t0, 1                 ; ...
        addi  s1, s1, 1                 ; ...
        j     wdr_low                   ; ...
wdr_take:
        ctake c8, s1                    ; take it
        mv    a0, s1                    ; and place it
        call  w_place                   ; ...
        j     wdr_loop                  ; next
wdr_done:
        sd    zero, w_hold-GPBASE(gp)   ; try held senders again next time
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; w_place(a0 = sender): where does the capability in c8 go?
w_place:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        mv    s1, a0                    ; s1 = sender
        cvalid t0, c8                   ; alive?
        beqz  t0, wpl_drop              ; no: drop it
        cbase s2, c8                    ; s2 = base
        cperms t0, c8                   ; s3 = space
        srli  s3, t0, 8                 ; ...
        li    t1, 4                     ; device space, from core 0, base 0 length 1:
        bne   s3, t1, wpl_job           ;   core 0's "look at your commands" token
        bnez  s1, wpl_job               ; ...
        bnez  s2, wpl_job               ; ...
        clen  t1, c8                    ; ...
        li    t2, 1                     ; ...
        bne   t1, t2, wpl_job           ; ...
        cclear c8                       ; nothing to keep
        call  w_cmds                    ; (read the job records now)
        j     wpl_ret                   ; ...
wpl_job:
        bnez  s1, wpl_rep               ; job pieces come from core 0 only
        call  w_jobcap                  ; a0 = 1 if it was one
        bnez  a0, wpl_ret               ; ...
        call  w_jobs                    ; maybe its job record is new: read them
        call  w_jobcap                  ; and try again
        bnez  a0, wpl_ret               ; ...
wpl_rep:
        li    s4, 0                     ; a local process's buffer, or awaited capability?
wpl_slot:
        li    t0, NSLOT                 ; all slots?
        bge   s4, t0, wpl_other         ; ...
        mv    a0, s4                    ; its record
        call  prec                      ; ...
        ld    t0, PR_STATE(a0)          ; in use?
        beqz  t0, wpl_next              ; no
        ld    t1, PR_BUF(a0)            ; its buffer?
        beq   t1, s2, wpl_buf           ; yes
        li    t1, S_WAIT                ; waiting for this base?
        bne   t0, t1, wpl_next          ; ...
        ld    t1, PR_AWAIT(a0)          ; ...
        beq   t1, s2, wpl_awaited       ; yes
wpl_next:
        addi  s4, s4, 1                 ; next
        j     wpl_slot                  ; ...
wpl_buf:
        li    t1, S_ZOMBIE              ; its process is gone: drop it
        beq   t0, t1, wpl_drop          ; ...
        ld    t1, w_me-GPBASE(gp)       ; from this very core: a request to our own
        bne   s1, t1, wpl_reply         ;   server, or that server's reply? They alternate:
        ld    t1, PR_OUTL(a0)           ;   the buffer goes out as a request, comes back
        bnez  t1, wpl_back              ;   as a reply
        ld    t1, w_server-GPBASE(gp)   ; a request (there must be a server here)
        bltz  t1, wpl_reply             ; ...
        li    t1, 1                     ; ...
        sd    t1, PR_OUTL(a0)           ; ...
        j     wpl_other                 ; (queued below like any request)
wpl_back:
        sd    zero, PR_OUTL(a0)         ; the reply
wpl_reply:
        mv    a0, s4                    ; deliver into its c5
        li    a1, 5                     ; ...
        call  w_give                    ; ...
        mv    a0, s4                    ; attachments from that sender: c6, c7
        mv    a1, s1                    ; ...
        call  w_attach                  ; ...
        mv    a0, s4                    ; it has arrived
        call  prec                      ; ...
        li    t0, 1                     ; ...
        sd    t0, PR_ARRIVED(a0)        ; ...
        j     wpl_ret                   ; ...
wpl_awaited:
        ld    a1, PR_DST(a0)            ; into its chosen register
        mv    a0, s4                    ; ...
        call  w_give                    ; ...
        mv    a0, s4                    ; done waiting
        call  prec                      ; ...
        li    t0, S_READY               ; ...
        sd    t0, PR_STATE(a0)          ; ...
        sd    zero, PR_REGS+80(a0)      ; result 0
        j     wpl_ret                   ; ...
wpl_other:
        li    s4, 0                     ; from a core of a local process's window: a gift
wpl_sib:                                ;   between its threads (cgive is direct in user mode)
        li    t0, NSLOT                 ; ...
        bge   s4, t0, wpl_req           ; none
        mv    a0, s4                    ; ...
        call  prec                      ; ...
        ld    t0, PR_STATE(a0)          ; alive?
        beqz  t0, wpl_sn                ; ...
        li    t1, S_ZOMBIE              ; ...
        beq   t0, t1, wpl_sn            ; ...
        ld    t1, PR_WIN(a0)            ; its window: base, count
        andi  t2, t1, 255               ; ...
        srli  t3, t1, 8                 ; ...
        andi  t3, t3, 255               ; ...
        li    t4, 2                     ; (threads only)
        blt   t3, t4, wpl_sn            ; ...
        bltu  s1, t2, wpl_sn            ; sender in [base, base + count)?
        add   t3, t2, t3                ; ...
        bgeu  s1, t3, wpl_sn            ; ...
        mv    a0, s1                    ; yes: queue it for that process
        mv    a1, s4                    ; ...
        call  att_put                   ; ...
        mv    a0, s4                    ; and wake it if it waits for one
        call  prec                      ; ...
        ld    t0, PR_STATE(a0)          ; ...
        li    t1, S_GIFT                ; an emulated ctake: from any sender or this one
        bne   t0, t1, wpl_st            ; ...
        ld    t1, PR_GSND(a0)           ; ...
        bltz  t1, wpl_wake              ; ...
        bne   t1, s1, wpl_ret           ; ...
        j     wpl_wake                  ; ...
wpl_st:
        li    t1, S_TANY                ; an emulated tany with bit 16
        bne   t0, t1, wpl_ret           ; ...
        ld    t1, PR_TMASK(a0)          ; ...
        srli  t1, t1, 16                ; ...
        andi  t1, t1, 1                 ; ...
        beqz  t1, wpl_ret               ; ...
wpl_wake:
        li    t0, S_READY               ; it runs again (and retries the instruction)
        sd    t0, PR_STATE(a0)          ; ...
        j     wpl_ret                   ; ...
wpl_sn:
        addi  s4, s4, 1                 ; next slot
        j     wpl_sib                   ; ...
wpl_req:
        li    t1, 3                     ; a 4 KiB buffer in system memory: a request
        bne   s3, t1, wpl_att           ; ...
        clen  t1, c8                    ; ...
        li    t2, 4096                  ; ...
        bne   t1, t2, wpl_att           ; ...
        ld    t0, w_server-GPBASE(gp)   ; a server here?
        bltz  t0, wpl_bounce            ; no: give it back with -1
        ld    t0, w_nreq-GPBASE(gp)     ; room in the queue?
        li    t1, NREQ                  ; ...
        bge   t0, t1, wpl_bounce        ; no: refuse it (-1)
        li    a0, 0                     ; and a pool slot (general part)?
        call  pool_get                  ; ...
        bltz  a0, wpl_bounce            ; no: refuse it (-1)
        mv    a1, a0                    ; queue it
        mv    a0, s1                    ; ...
        call  w_enq                     ; ...
        j     wpl_ret                   ; ...
wpl_bounce:
        la    t0, w_tmp                 ; result -1 into its header
        li    t1, -1                    ; ...
        sd    t1, 0(t0)                 ; ...
        li    t1, 32                    ; ...
        li    t2, 8                     ; ...
        tput  tg14, t0, c8, t1, t2      ; ...
        mv    a0, s1                    ; wake the sender
        call  w_ring                    ; ...
        cgive c8, s1                    ; and give it back
        j     wpl_ret                   ; ...
wpl_att:
        mv    a0, s1                    ; an attachment: keep it for its message
        li    a1, -1                    ; (not a gift)
        call  att_put                   ; ...
        j     wpl_ret                   ; ...
wpl_drop:
        cclear c8                       ; ...
wpl_ret:
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; ...

; w_give(a0 = slot, a1 = register): c8 -> that process's capability register
; (the register itself if the process is loaded, else what it holds there while
; switched out: w_stow). As preg_put does for a loaded process, a dead or
; copyable capability there is replaced and a live linear one stays (the new
; one is dropped); so is the new one if no pool slot may be taken for it.
w_give:
        ld    t0, w_loaded-GPBASE(gp)   ; loaded?
        bne   t0, a0, wg_save           ; no
        mv    a0, a1                    ; yes: straight into the register
        j     preg_put                  ; (tail call)
wg_save:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a1, 8(sp)                 ; the register
        call  prec                      ; its record
        sd    a0, 16(sp)                ; ...
        ld    a1, 8(sp)                 ; its descriptor
        slli  t0, a1, 3                 ; ...
        add   t0, a0, t0                ; ...
        addi  t0, t0, PR_CAP            ; ...
        sd    t0, 24(sp)                ; ...
        ld    t1, 0(t0)                 ; something there?
        beqz  t1, wg_put                ; no
        andi  t2, t1, 3                 ; rebuilt (an endpoint, a device capability)?
        li    t3, 1                     ; ...
        beq   t2, t3, wg_slot           ; no: saved
        andi  t2, t1, 16 << 2           ; copyable?
        beqz  t2, wg_drop               ; no: it stays
        sd    zero, 0(t0)               ; yes: replaced
        j     wg_put                    ; ...
wg_slot:
        cclear c9                       ; the new one waits in c9
        cmov  c9, c8                    ; ...
        srli  a0, t1, 8                 ; look at the saved one
        andi  a0, a0, 255               ; ...
        call  crs8                      ; ...
        bnez  a0, wg_repl               ; dead: replaced
        cperms t0, c8                   ; copyable?
        andi  t0, t0, 16                ; ...
        bnez  t0, wg_repl               ; yes: replaced
        ld    t0, 24(sp)                ; linear: back into its slot
        ld    a0, 0(t0)                 ; ...
        srli  a0, a0, 8                 ; ...
        andi  a0, a0, 255               ; ...
        call  csv8                      ; ...
        j     wg_drop9                  ; and the new one is dropped (keep c5..c7 free)
wg_repl:
        cclear c8                       ; the old one goes, its slot is free
        ld    t0, 24(sp)                ; ...
        ld    a0, 0(t0)                 ; ...
        sd    zero, 0(t0)               ; ...
        srli  a0, a0, 8                 ; ...
        ld    a1, 16(sp)                ; ...
        call  pool_put                  ; ...
        cmov  c8, c9                    ; the new one
        cclear c9                       ; ...
wg_put:
        ld    a0, 16(sp)                ; c8 -> the register's descriptor (or a slot)
        ld    a1, 8(sp)                 ; ...
        call  w_stow                    ; ...
        beqz  a0, wg_ret                ; ...
wg_drop9:
        cclear c9                       ; ...
wg_drop:
        cclear c8                       ; dropped
wg_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; ---- attachments: capabilities that travel with the next message from their sender -------
; The queue (each entry in a pool slot): each entry has a sender, a base and an
; owner: -1 an attachment waiting for its message, s a gift for slot s's
; emulated ctake, 100 + q the attachment of queued request q.
; att_put(a0 = sender, a1 = owner): c8 -> the queue (dropped if there is no room)
att_put:
        li    t0, 0                     ; find a free entry
        la    t1, w_att                 ; entries: sender + 1, base
apu_f:
        li    t2, NATT                  ; ...
        bge   t0, t2, apu_full          ; none
        slli  t3, t0, 4                 ; ...
        add   t3, t1, t3                ; ...
        ld    t4, 0(t3)                 ; free?
        beqz  t4, apu_put               ; ...
        addi  t0, t0, 1                 ; ...
        j     apu_f                     ; ...
apu_put:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; sender
        sd    a1, 16(sp)                ; owner
        sd    t0, 24(sp)                ; entry
        li    a0, 0                     ; a pool slot (general part)
        call  pool_get                  ; ...
        mv    t6, a0                    ; ...
        ld    t0, 24(sp)                ; ...
        ld    a1, 16(sp)                ; ...
        ld    a0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        bltz  t6, apu_full              ; none
        la    t1, w_aslot               ; keep it
        slli  t2, t0, 3                 ; ...
        add   t1, t1, t2                ; ...
        sd    t6, 0(t1)                 ; ...
        la    t1, w_att                 ; ...
        slli  t3, t0, 4                 ; ...
        add   t3, t1, t3                ; ...
        addi  t4, a0, 1                 ; ...
        sd    t4, 0(t3)                 ; sender + 1
        cbase t4, c8                    ; base (0 for a capability without one)
        sd    t4, 8(t3)                 ; ...
        la    t5, w_attown              ; owner
        add   t5, t5, t2                ; ...
        sd    a1, 0(t5)                 ; ...
        ld    t4, w_attseq-GPBASE(gp)   ; arrival order
        addi  t4, t4, 1                 ; ...
        sd    t4, w_attseq-GPBASE(gp)   ; ...
        la    t5, w_attord              ; ...
        add   t5, t5, t2                ; ...
        sd    t4, 0(t5)                 ; ...
        andi  a0, t6, 255               ; save it
        j     csv8                      ; (tail call)
apu_full:
        cclear c8                       ; no room: dropped
        ret                             ; ...

; att_find(a0 = base) -> a0 = queue index of an attachment with that base, or -1
att_find:
        li    t0, 0                     ; ...
        la    t1, w_att                 ; ...
afi_l:
        li    t2, NATT                  ; ...
        bge   t0, t2, afi_none          ; ...
        slli  t3, t0, 4                 ; ...
        add   t3, t1, t3                ; ...
        ld    t4, 0(t3)                 ; used?
        beqz  t4, afi_n                 ; ...
        ld    t4, 8(t3)                 ; base
        beq   t4, a0, afi_yes           ; ...
afi_n:
        addi  t0, t0, 1                 ; ...
        j     afi_l                     ; ...
afi_yes:
        mv    a0, t0                    ; ...
        ret                             ; ...
afi_none:
        li    a0, -1                    ; ...
        ret                             ; ...

; att_oldest(a0 = sender) -> a0 = queue index of its oldest attachment, or -1
; att_owned(a0 = sender, a7 = owner): the same for entries of that owner
att_oldest:
        li    a7, -1                    ; attachments
att_owned:
        li    t0, 0                     ; ...
        la    t1, w_att                 ; ...
        addi  t5, a0, 1                 ; sender + 1
        li    a0, -1                    ; best so far
        li    t6, -1                    ; its order (unsigned max)
aol_l:
        li    t2, NATT                  ; ...
        bge   t0, t2, aol_done          ; ...
        slli  t3, t0, 4                 ; ...
        add   t3, t1, t3                ; ...
        ld    t4, 0(t3)                 ; from that sender?
        bne   t4, t5, aol_n             ; ...
        la    t4, w_attown              ; an attachment (not a gift)?
        slli  t2, t0, 3                 ; ...
        add   t4, t4, t2                ; ...
        ld    t4, 0(t4)                 ; ...
        bne   t4, a7, aol_n             ; ...
        la    t4, w_attord              ; its order
        slli  t2, t0, 3                 ; ...
        add   t4, t4, t2                ; ...
        ld    t4, 0(t4)                 ; ...
        bgeu  t4, t6, aol_n             ; not older
        mv    t6, t4                    ; the oldest so far
        mv    a0, t0                    ; ...
aol_n:
        addi  t0, t0, 1                 ; ...
        j     aol_l                     ; ...
aol_done:
        ret                             ; ...

; att_take(a0 = queue index) -> c8 = it, a0 = 0 (or -1: it died), the entry freed
att_take:
        la    t1, w_att                 ; free the entry
        slli  t3, a0, 4                 ; ...
        add   t3, t1, t3                ; ...
        sd    zero, 0(t3)               ; ...
        la    t1, w_aslot               ; restore it from its pool slot (freed)
        slli  t3, a0, 3                 ; ...
        add   t1, t1, t3                ; ...
        ld    a0, 0(t1)                 ; ...
        j     pool_take                 ; (tail call)

; w_attach(a0 = slot, a1 = sender): its waiting attachments -> the slot's c6, c7
w_attach:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        mv    a0, a1                    ; the first
        call  att_oldest                ; ...
        bltz  a0, wat_ret               ; none
        call  att_take                  ; ...
        bnez  a0, wat_ret               ; (died)
        ld    a0, 8(sp)                 ; -> c6
        li    a1, 6                     ; ...
        call  w_give                    ; ...
        ld    a0, 16(sp)                ; a second one?
        call  att_oldest                ; ...
        bltz  a0, wat_ret               ; no
        call  att_take                  ; ...
        bnez  a0, wat_ret               ; ...
        ld    a0, 8(sp)                 ; -> c7 (it replaces the clock: copyable)
        li    a1, 7                     ; ...
        call  w_give                    ; ...
wat_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; ---- requests for this core's server -------------------------------------------------------
; w_enq(a0 = sender, a1 = its pool slot): c8 = a request: queue it with its attachment (if any)
w_enq:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; sender
        ld    t0, w_rhead-GPBASE(gp)    ; tail = (head + count) mod NREQ
        ld    t1, w_nreq-GPBASE(gp)     ; ...
        add   t0, t0, t1                ; ...
        andi  t0, t0, NREQ - 1          ; ...
        sd    t0, 16(sp)                ; ...
        addi  t1, t1, 1                 ; one more
        sd    t1, w_nreq-GPBASE(gp)     ; ...
        slli  t2, t0, 3                 ; ...
        la    t1, w_rfrom               ; its sender
        add   t1, t1, t2                ; ...
        sd    a0, 0(t1)                 ; ...
        la    t1, w_rslot               ; its slot
        add   t1, t1, t2                ; ...
        sd    a1, 0(t1)                 ; ...
        andi  a0, a1, 255               ; the request
        call  csv8                      ; ...
        ld    a0, 8(sp)                 ; an attachment from that sender?
        call  att_oldest                ; ...
        bltz  a0, weq_ret               ; no
        la    t1, w_attown              ; it belongs to the request now
        slli  t2, a0, 3                 ; ...
        add   t1, t1, t2                ; ...
        ld    t0, 16(sp)                ; ...
        addi  t0, t0, 100               ; ...
        sd    t0, 0(t1)                 ; ...
weq_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; ---- kernel commands (from core 0, through the KST) ------------------------------------------
; w_cmds(): kills, notifications, new job records
w_cmds:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        li    a0, G_HALT                ; the machine is stopping?
        call  kst_rd                    ; ...
        bnez  a0, w_halt                ; yes
        li    a0, CA_KILL               ; slots to destroy
        call  carea                     ; ...
        call  kst_xchg0                 ; ...
        mv    s1, a0                    ; s1 = their bits
        li    s2, 0                     ; slot
wc_kill:
        li    t0, NSLOT                 ; ...
        bge   s2, t0, wc_note           ; ...
        srl   t0, s1, s2                ; this one?
        andi  t0, t0, 1                 ; ...
        beqz  t0, wc_kn                 ; ...
        mv    a0, s2                    ; is a process there?
        call  prec                      ; ...
        ld    t0, PR_STATE(a0)          ; ...
        beqz  t0, wc_kn                 ; no
        li    t1, S_ZOMBIE              ; already gone
        beq   t0, t1, wc_kn             ; ...
        mv    a0, s2                    ; destroy it: status "killed"
        li    a1, 1                     ; ...
        slli  a1, a1, 62                ; ...
        call  w_exit                    ; ...
wc_kn:
        addi  s2, s2, 1                 ; next
        j     wc_kill                   ; ...
wc_note:
        li    a0, CA_FREE               ; zombies whose arena core 0 revoked: free
        call  carea                     ; (their late replies are dead capabilities now,
        call  kst_xchg0                 ;  and their arena may already serve another process)
        mv    s1, a0                    ; ...
        li    s2, 0                     ; ...
wc_fl:
        li    t0, NSLOT                 ; ...
        bge   s2, t0, wc_note2          ; ...
        srl   t0, s1, s2                ; ...
        andi  t0, t0, 1                 ; ...
        beqz  t0, wc_fn                 ; ...
        mv    a0, s2                    ; ...
        call  prec                      ; ...
        ld    t0, PR_STATE(a0)          ; ...
        li    t1, S_ZOMBIE              ; ...
        bne   t0, t1, wc_fn             ; ...
        sd    zero, PR_STATE(a0)        ; free
        sd    zero, PR_BUF(a0)          ; ...
        sd    zero, PR_PID(a0)          ; ...
wc_fn:
        addi  s2, s2, 1                 ; ...
        j     wc_fl                     ; ...
wc_note2:
        li    s2, 0                     ; notifications
wc_nl:
        li    t0, NSLOT                 ; ...
        bge   s2, t0, wc_jobs           ; ...
        slli  a0, s2, 3                 ; this slot's word
        addi  a0, a0, CA_NOTE           ; ...
        call  carea                     ; ...
        call  kst_xchg0                 ; ...
        beqz  a0, wc_nn                 ; nothing
        mv    t5, a0                    ; ...
        mv    a0, s2                    ; ...
        call  prec                      ; ...
        ld    t0, PR_NOTES(a0)          ; add them
        or    t0, t0, t5                ; ...
        sd    t0, PR_NOTES(a0)          ; ...
wc_nn:
        addi  s2, s2, 1                 ; ...
        j     wc_nl                     ; ...
wc_jobs:
        call  w_jobs                    ; new job records
wc_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; w_jobs(): read the job records core 0 posted (uses no capability register:
; w_place calls it while it holds the arriving capability in c8). A record's
; state is the slot + 1 it is for; it is cleared once the record is read, and
; core 0 may then post the next job in it.
w_jobs:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s2, 8(sp)                 ; ...
        li    s2, 0                     ; job record
wj_l:
        li    t0, NJOB                  ; ...
        bge   s2, t0, wj_ret            ; ...
        mv    a0, s2                    ; posted?
        li    a1, J_STATE               ; ...
        call  jfield                    ; ...
        beqz  a0, wj_n                  ; no
        addi  a0, a0, -1                ; set up the slot
        mv    a1, s2                    ; ...
        call  w_newjob                  ; ...
        li    t0, J_SIZE                ; read: the record is free again
        mul   a0, s2, t0                ; ...
        addi  a0, a0, CA_JOB + J_STATE  ; ...
        call  carea                     ; ...
        li    a1, 0                     ; ...
        call  kst_wr                    ; ...
wj_n:
        addi  s2, s2, 1                 ; ...
        j     wj_l                      ; ...
wj_ret:
        ld    s2, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; w_halt: the machine is stopping
; `halt` drains the core's transfers, device reads included (tty's break
; read): core 0 completes those once every worker is counted here, that is,
; in supervisor mode for good (no process can issue another read).
w_halt:
        li    a0, G_HALTED              ; count this core in
        li    a1, 1                     ; ...
        call  kst_add                   ; ...
        li    a0, 0                     ; ...
        halt                            ; this core stops (after its pending reads complete)

; jfield(a0 = job record, a1 = job field) -> a0 = the value
jfield:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        li    t0, J_SIZE                ; ...
        mul   a0, a0, t0                ; ...
        add   a0, a0, a1                ; ...
        addi  a0, a0, CA_JOB            ; ...
        call  carea                     ; ...
        call  kst_rd                    ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; w_newjob(a0 = slot, a1 = job record): a job was posted for it: copy it into the record
w_newjob:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        mv    s1, a0                    ; s1 = slot
        mv    s3, a1                    ; s3 = job record
        call  prec                      ; s2 = its record
        mv    s2, a0                    ; ...
        mv    t0, s2                    ; clear it
        li    t1, PR_SIZE / 8           ; ...
wnj_z:
        sd    zero, 0(t0)               ; ...
        addi  t0, t0, 8                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, wnj_z                 ; ...
        mv    a0, s3                    ; pid
        li    a1, J_PID                 ; ...
        call  jfield                    ; ...
        sd    a0, PR_PID(s2)            ; ...
        mv    a0, s3                    ; flags
        li    a1, J_FLAGS               ; ...
        call  jfield                    ; ...
        sd    a0, PR_FLAGS(s2)          ; ...
        mv    a0, s3                    ; arena layout base
        li    a1, J_ARENA               ; ...
        call  jfield                    ; ...
        sd    a0, PR_ARENA(s2)          ; ...
        li    t0, A_BUF                 ; its buffer
        add   t0, a0, t0                ; ...
        sd    t0, PR_BUF(s2)            ; ...
        mv    a0, s3                    ; the arena's base: the program's memory
        li    a1, J_MEM                 ; ...
        call  jfield                    ; ...
        sd    a0, PR_MEM(s2)            ; ...
        mv    a0, s3                    ; window
        li    a1, J_WIN                 ; ...
        call  jfield                    ; ...
        sd    a0, PR_WIN(s2)            ; ...
        mv    a0, s3                    ; code
        li    a1, J_CODE                ; ...
        call  jfield                    ; ...
        sd    a0, PR_CODE(s2)           ; ...
        mv    a0, s3                    ; data
        li    a1, J_DATA                ; ...
        call  jfield                    ; ...
        sd    a0, PR_DATA(s2)           ; ...
        mv    a0, s3                    ; its save area's offset
        li    a1, J_SAVE                ; ...
        call  jfield                    ; ...
        sd    a0, PR_SOFF(s2)           ; ...
        mv    a0, s3                    ; a0..a2 for the program
        li    a1, J_A0                  ; ...
        call  jfield                    ; ...
        sd    a0, PR_REGS+80(s2)        ; ...
        mv    a0, s3                    ; ...
        li    a1, J_A1                  ; ...
        call  jfield                    ; ...
        sd    a0, PR_REGS+88(s2)        ; ...
        mv    a0, s3                    ; ...
        li    a1, J_A2                  ; ...
        call  jfield                    ; ...
        sd    a0, PR_REGS+96(s2)        ; ...
        ld    t0, PR_FLAGS(s2)          ; a StrataOS program's thread 0: endpoints in
        andi  t0, t0, F_SYS             ;   c1..c4, described (w_stow) as cmkep makes them,
        beqz  t0, wnj_sp                ;   restricted to W D: rebuilt when it is loaded
        ld    t0, PR_WIN(s2)            ; ...
        srli  t0, t0, 16                ; ...
        andi  t0, t0, 255               ; ...
        bnez  t0, wnj_sp                ; ...
        mv    a0, s3                    ; the cores for c1..c4
        li    a1, J_EPS                 ; ...
        call  jfield                    ; ...
        addi  t1, s2, PR_CAP + 8        ; t1 = c1's descriptor
        li    t2, 4                     ; ...
wnj_ep:
        andi  t3, a0, 255               ; this one's core (255: none)
        li    t4, 255                   ; ...
        beq   t3, t4, wnj_epn           ; ...
        slli  t3, t3, 8                 ; 2 | (W | D) << 2 | node << 8
        ori   t3, t3, 2 | (2 | 16) << 2 ; ...
        sd    t3, 0(t1)                 ; ...
wnj_epn:
        srli  a0, a0, 8                 ; next
        addi  t1, t1, 8                 ; ...
        addi  t2, t2, -1                ; ...
        bnez  t2, wnj_ep                ; ...
wnj_sp:
        li    t0, STACKTOP              ; sp
        sd    t0, PR_REGS+16(s2)        ; ...
        la    t0, u_exit                ; ra: returning ends the program like halt
        sd    t0, PR_REGS+8(s2)         ; ...
        ld    t0, PR_CODE(s2)           ; entry: the start of its code
        li    t1, 0xffff                ; ...
        and   t0, t0, t1                ; ...
        sd    t0, PR_EPC(s2)            ; ...
        li    t0, -1                    ; awaiting nothing
        sd    t0, PR_AWAIT(s2)          ; ...
        ld    t0, PR_FLAGS(s2)          ; which pieces come?
        li    t1, NEED_S | NEED_I       ; every thread: its save area and the image
        ld    t2, PR_WIN(s2)            ; (one capability for both if it is alone in its
        srli  t3, t2, 8                 ;   process: the save area follows the image)
        andi  t3, t3, 255               ; ...
        li    t4, 1                     ; ...
        bgtu  t3, t4, wnj_thr           ; ...
        li    t1, NEED_I                ; ...
        li    t4, A_SAVE0 - A_IMG       ; ...
        sd    t4, PR_SOB(s2)            ; ...
wnj_thr:
        srli  t2, t2, 16                ; thread 0: the memory, and a StrataOS program's buffer
        andi  t2, t2, 255               ; ...
        bnez  t2, wnj_need              ; another thread: no more
        ori   t1, t1, NEED_P            ; its memory
        andi  t3, t0, F_SYS             ; and a StrataOS program its message buffer
        beqz  t3, wnj_fb                ; ...
        ori   t1, t1, NEED_B            ; ...
wnj_fb:                                 ; (the framebuffer is lent by FBLEND now, not given at start)
wnj_need:
        sd    t1, PR_NEED(s2)           ; ...
        andi  t3, t0, F_SERVER          ; the core's server?
        beqz  t3, wnj_state             ; ...
        sd    s1, w_server-GPBASE(gp)   ; yes
wnj_state:
        li    t0, S_LOAD                ; its pieces are coming
        sd    t0, PR_STATE(s2)          ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; w_jobcap() -> a0 = 1 if c8 (from core 0) was a piece of a new process's arena
w_jobcap:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        cbase t5, c8                    ; its base
        li    s1, 0                     ; slot
wjc_l:
        li    t0, NSLOT                 ; ...
        bge   s1, t0, wjc_no            ; ...
        mv    a0, s1                    ; ...
        call  prec                      ; ...
        mv    s2, a0                    ; ...
        ld    t0, PR_STATE(s2)          ; loading?
        li    t1, S_LOAD                ; ...
        bne   t0, t1, wjc_n             ; ...
        ld    t0, PR_MEM(s2)            ; which piece?
        li    a1, 0                     ; P: at the arena's base -> c0
        li    t2, NEED_P                ; ...
        beq   t5, t0, wjc_have          ; ...
        ld    t0, PR_ARENA(s2)          ; the rest: at offsets from the layout base
        ld    t1, PR_SOFF(s2)           ; S: the save area (the kernel keeps it)
        add   t1, t0, t1                ; ...
        li    a1, -1                    ; ...
        li    t2, NEED_S                ; ...
        beq   t5, t1, wjc_have          ; ...
        li    t1, A_IMG                 ; I: the image share (the kernel keeps it)
        add   t1, t0, t1                ; ...
        li    a1, -2                    ; ...
        li    t2, NEED_I                ; ...
        beq   t5, t1, wjc_have          ; ...
        ld    t1, PR_BUF(s2)            ; B -> c5
        li    a1, 5                     ; ...
        li    t2, NEED_B                ; ...
        beq   t5, t1, wjc_have          ; ...
        li    t1, FB_BASE0              ; the framebuffer (dev) -> c2
        li    a1, 2                     ; ...
        li    t2, NEED_FB               ; ...
        ld    t3, PR_NEED(s2)           ; (only if dev)
        and   t3, t3, t2                ; ...
        beqz  t3, wjc_n                 ; ...
        beq   t5, t1, wjc_have          ; ...
wjc_n:
        addi  s1, s1, 1                 ; next
        j     wjc_l                     ; ...
wjc_have:
        ld    t3, PR_GOT(s2)            ; record it
        or    t3, t3, t2                ; ...
        sd    t3, PR_GOT(s2)            ; ...
        li    t3, -1                    ; S or I: the kernel keeps them
        beq   a1, t3, wjc_s             ; ...
        li    t3, -2                    ; ...
        beq   a1, t3, wjc_i             ; ...
        mv    a0, s1                    ; into its save table
        call  w_give                    ; ...
        j     wjc_chk                   ; ...
wjc_s:
        mv    a0, s2                    ; a pool slot for it (its reservation: never fails)
        call  pool_get                  ; ...
        sd    a0, PR_SSL(s2)            ; ...
        j     wjc_sv                    ; ...
wjc_i:
        mv    a0, s2                    ; ...
        call  pool_get                  ; ...
        sd    a0, PR_ISL(s2)            ; ...
        ld    t0, PR_NEED(s2)           ; alone in its process: it is the save area too
        andi  t0, t0, NEED_S            ; ...
        bnez  t0, wjc_sv                ; ...
        sd    a0, PR_SSL(s2)            ; ...
wjc_sv:
        andi  a0, a0, 255               ; ...
        call  csv8                      ; ...
wjc_chk:
        ld    t0, PR_GOT(s2)            ; all there?
        ld    t1, PR_NEED(s2)           ; ...
        bne   t0, t1, wjc_yes           ; not yet
        mv    a0, s1                    ; complete: it can start
        call  w_start                   ; ...
wjc_yes:
        li    a0, 1                     ; it was a job piece
        j     wjc_ret                   ; ...
wjc_no:
        li    a0, 0                     ; not one
wjc_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; w_start(a0 = slot): every piece is here: give it its other capabilities and make it ready
w_start:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        mv    s1, a0                    ; s1 = slot
        call  prec                      ; s2 = record
        mv    s2, a0                    ; ...
        ld    t0, PR_FLAGS(s2)          ; a StrataOS program?
        andi  t0, t0, F_SYS             ; ...
        beqz  t0, wst_bare              ; no: bare metal
        ld    t0, PR_WIN(s2)            ; vcore 0 only
        srli  t0, t0, 16                ; ...
        andi  t0, t0, 255               ; ...
        bnez  t0, wst_ready             ; ...
        ; (c1..c4: w_newjob described them)
wst_clock:
        li    a0, T_CLOCK               ; c7 = the clock
        call  crs8                      ; ...
        mv    a0, s1                    ; ...
        li    a1, 7                     ; ...
        call  w_give                    ; ...
        ld    t0, PR_FLAGS(s2)          ; dev: c6 = the device root
        andi  t0, t0, F_DEVCAPS         ; ...
        beqz  t0, wst_ready             ; ...
        li    a0, T_DEVR                ; ...
        call  crs8                      ; ...
        mv    a0, s1                    ; ...
        li    a1, 6                     ; ...
        call  w_give                    ; ...
        j     wst_ready                 ; ...
wst_bare:
        li    a0, T_CON                 ; bare metal: c2 = the console output
        call  crs8                      ; ...
        mv    a0, s1                    ; ...
        li    a1, 2                     ; ...
        call  w_give                    ; ...
wst_ready:
        li    t0, S_READY               ; it can run
        sd    t0, PR_STATE(s2)          ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; ---- waits that end -------------------------------------------------------------------------------
; w_poll(): replies that arrived, notifications, timeouts
w_poll:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        call  w_now                     ; s3 = NOW
        mv    s3, a0                    ; ...
        li    s1, 0                     ; slot
        li    s4, 0                     ; earliest deadline still pending
wpo_l:
        li    t0, NSLOT                 ; ...
        bge   s1, t0, wpo_done          ; ...
        mv    a0, s1                    ; ...
        call  prec                      ; ...
        mv    s2, a0                    ; ...
        ld    t0, PR_STATE(s2)          ; ...
        li    t1, S_WAIT                ; WAIT_REPLY
        beq   t0, t1, wpo_wait          ; ...
        li    t1, S_NOTE                ; NOTIFY_WAIT
        beq   t0, t1, wpo_note          ; ...
        li    t1, S_RECV                ; RECEIVE: only its timeout here
        beq   t0, t1, wpo_time          ; ...
        j     wpo_n                     ; ...
wpo_wait:
        ld    t1, PR_AWAIT(s2)          ; our own buffer and it is back?
        ld    t2, PR_BUF(s2)            ; ...
        bne   t1, t2, wpo_wint          ; ...
        ld    t3, PR_ARRIVED(s2)        ; ...
        beqz  t3, wpo_wint              ; ...
        sd    zero, PR_ARRIVED(s2)      ; collected
        li    a0, 0                     ; result 0
        j     wpo_wake                  ; ...
wpo_wint:
        bgez  t1, wpo_time              ; a sleep (nothing awaited) can be interrupted
        ld    t3, PR_NOTES(s2)          ; ...
        andi  t4, t3, 1                 ; ...
        beqz  t4, wpo_time              ; ...
        srli  t3, t3, 1                ; clear bit 0
        slli  t3, t3, 1                ; ...
        sd    t3, PR_NOTES(s2)          ; ...
        li    a0, -2                    ; interrupted
        j     wpo_wake                  ; ...
wpo_note:
        ld    t3, PR_NOTES(s2)          ; any?
        beqz  t3, wpo_time              ; ...
        sd    zero, PR_NOTES(s2)        ; delivered
        mv    a0, t3                    ; the bits
        j     wpo_wake                  ; ...
wpo_time:
        ld    t3, PR_DEADL(s2)          ; a deadline?
        beqz  t3, wpo_n                 ; no
        bltu  s3, t3, wpo_later         ; not yet
        sd    zero, PR_DEADL(s2)        ; over
        li    a0, -8                    ; timed out
        j     wpo_wake                  ; (RECEIVE, WAIT_REPLY, NOTIFY_WAIT alike)
wpo_later:
        beqz  s4, wpo_set               ; earliest?
        bgeu  t3, s4, wpo_n             ; ...
wpo_set:
        mv    s4, t3                    ; ...
        j     wpo_n                     ; ...
wpo_wake:
        sd    a0, PR_REGS+80(s2)        ; the result
        sd    zero, PR_DEADL(s2)        ; ...
        li    t0, S_READY               ; ...
        sd    t0, PR_STATE(s2)          ; ...
wpo_n:
        addi  s1, s1, 1                 ; next
        j     wpo_l                     ; ...
wpo_done:
        li    a0, CA_DEADL              ; tell core 0 when to wake us
        call  carea                     ; ...
        mv    a1, s4                    ; ...
        call  kst_wr                    ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; w_complete(a0 = slot): it is loaded and about to run; finish a RECEIVE
w_complete:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        call  prec                      ; ...
        mv    s1, a0                    ; s1 = record
        ld    t0, PR_STATE(s1)          ; in RECEIVE?
        li    t1, S_RECV                ; ...
        bne   t0, t1, wcm_ready         ; no
        sd    zero, PR_DEADL(s1)        ; ...
        ld    t0, w_nreq-GPBASE(gp)     ; a request?
        beqz  t0, wcm_tags              ; no: idle tags
        ld    t2, w_rhead-GPBASE(gp)    ; the oldest
        addi  t3, t2, 1                 ; pop it
        andi  t3, t3, NREQ - 1          ; ...
        sd    t3, w_rhead-GPBASE(gp)    ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, w_nreq-GPBASE(gp)     ; ...
        sd    t2, w_tmp+8-GPBASE(gp)    ; (keep the index)
        li    a0, 6                     ; c6 must be free: drop what is there
        call  preg_get                  ; ...
        cclear c8                       ; ...
        li    a0, 7                     ; c7 too (it gets the attachment or nothing)
        call  preg_get                  ; ...
        cclear c8                       ; ...
        ld    t2, w_tmp+8-GPBASE(gp)    ; the request -> c6 (its pool slot is free again)
        slli  t2, t2, 3                 ; ...
        la    t1, w_rslot               ; ...
        add   t1, t1, t2                ; ...
        ld    a0, 0(t1)                 ; ...
        call  pool_take                 ; ...
        bnez  a0, wcm_dead              ; it died in the queue: try again later
        cmov  c6, c8                    ; ...
        ld    t2, w_tmp+8-GPBASE(gp)    ; its attachment -> c7
        la    t1, w_rfrom               ; (from the request's sender)
        slli  t3, t2, 3                 ; ...
        add   t1, t1, t3                ; ...
        ld    a0, 0(t1)                 ; ...
        addi  a7, t2, 100               ; owner: the request
        call  att_owned                 ; ...
        bltz  a0, wcm_stamp             ; none
        call  att_take                  ; ...
        bnez  a0, wcm_stamp             ; ...
        cmov  c7, c8                    ; ...
wcm_stamp:
        cbase a0, c6                    ; the sender's pid, from its buffer's arena
        call  pid_of                    ; ...
        la    t0, w_tmp                 ; -> header byte 40
        sd    a0, 0(t0)                 ; ...
        li    t1, 40                    ; ...
        li    t2, 8                     ; ...
        tput  tg14, t0, c6, t1, t2      ; ...
        twait 1 << TG_K                 ; ...
        ld    t2, w_tmp+8-GPBASE(gp)    ; the token: the sender core | pid << 8
        la    t1, w_rfrom               ; ...
        slli  t3, t2, 3                 ; ...
        add   t1, t1, t3                ; ...
        ld    t0, 0(t1)                 ; ...
        sd    t0, w_c6from-GPBASE(gp)   ; (PARK remembers it with the request)
        ld    t4, w_tmp-GPBASE(gp)      ; ...
        slli  t4, t4, 8                 ; ...
        or    t0, t0, t4                ; ...
        sd    t0, PR_REGS+80(s1)        ; a0 = token
        j     wcm_ready                 ; ...
wcm_dead:
        li    t0, S_RECV                ; still receiving
        sd    t0, PR_STATE(s1)          ; ...
        li    t0, -1                    ; report "nothing" this time: tags -1, idle none
        sd    t0, PR_REGS+80(s1)        ; ...
        sd    zero, PR_REGS+88(s1)      ; ...
        j     wcm_ready                 ; (a server tolerates a spurious -1 with no tags)
wcm_tags:
        tpoll t2, 0xffff                ; idle tags it asked about
        sub   t2, zero, t2     ; invert every bit: -x
        addi   t2, t2, -1              ; ... - 1
        ld    t1, PR_TAGS(s1)           ; ...
        and   t1, t1, t2                ; ...
        li    t0, -1                    ; a0 = -1, a1 = the idle tags
        sd    t0, PR_REGS+80(s1)        ; ...
        sd    t1, PR_REGS+88(s1)        ; ...
wcm_ready:
        li    t0, S_READY               ; running now
        sd    t0, PR_STATE(s1)          ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; pid_of(a0 = a buffer's base) -> a0 = the pid owning the arena granule it lies in (0: the kernel)
pid_of:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        mv    s1, a0                    ; s1 = the address
        li    a0, G_PBASE               ; minus the pool's base
        call  kst_rd                    ; ...
        sub   s1, s1, a0                ; ...
        srli  s1, s1, GSHIFT            ; s1 = its pool granule
        li    a0, G_PGRAN               ; inside the pool? (below it: a huge number)
        call  kst_rd                    ; ...
        bgeu  s1, a0, pof_none          ; no: the kernel's own memory
        slli  a0, s1, 3                 ; the granule's owner
        addi  a0, a0, G_GPID            ; ...
        call  kst_rd                    ; ...
        j     pof_ret                   ; ...
pof_none:
        li    a0, 0                     ; the kernel
pof_ret:
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; ---- exit -------------------------------------------------------------------------------------
; w_exit(a0 = slot, a1 = status): the process ends on this core
w_exit:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        mv    s1, a0                    ; s1 = slot
        mv    s3, a1                    ; s3 = status
        call  prec                      ; s2 = record
        mv    s2, a0                    ; ...
        ld    t1, w_loaded-GPBASE(gp)   ; loaded: drop its registers
        bne   t1, s1, wex_saved         ; ...
        cclear c0                       ; every capability it held
        cclear c1                       ; .
        cclear c2                       ; .
        cclear c3                       ; .
        cclear c4                       ; .
        cclear c5                       ; .
        cclear c6                       ; .
        cclear c7                       ; .
        cclear c10                      ; (and whatever it kept in c8..c15)
        cclear c11                      ; .
        cclear c12                      ; .
        cclear c13                      ; .
        cclear c14                      ; .
        cclear c15                      ; .
        csrw  xslot, zero               ; ...
        csrw  utvec, zero               ; ...
        call  stash_drop                ; its c8, c9
wex_unload:
        li    t0, -1                    ; nothing loaded now
        sd    t0, w_loaded-GPBASE(gp)   ; ...
        cclear c8                       ; (the dispatcher's own are restored when needed)
        cclear c9                       ; ...
        call  kcaps                     ; c9 = KST again
        j     wex_k                     ; ...
wex_saved:
        li    s4, 0                     ; what it holds while switched out: dropped
wex_s:
        li    t0, 8                     ; ...
        bge   s4, t0, wex_k             ; ...
        mv    a0, s2                    ; (its slots are free again)
        mv    a1, s4                    ; ...
        call  w_fetch                   ; ...
        cclear c8                       ; ...
        addi  s4, s4, 1                 ; ...
        j     wex_s                     ; ...
wex_k:
        ld    t0, PR_GOT(s2)            ; its save area, if it came
        andi  t0, t0, NEED_S            ; ...
        beqz  t0, wex_ki                ; ...
        ld    a0, PR_SSL(s2)            ; ...
        mv    a1, s2                    ; ...
        call  pool_take                 ; ...
        cclear c8                       ; ...
wex_ki:
        ld    t0, PR_GOT(s2)            ; its image share (and save area, if alone), if it came
        andi  t0, t0, NEED_I            ; ...
        beqz  t0, wex_g                 ; ...
        ld    a0, PR_ISL(s2)            ; ...
        mv    a1, s2                    ; ...
        call  pool_take                 ; ...
        cclear c8                       ; ...
        sd    zero, PR_GOT(s2)          ; (nothing left)
wex_g:
        li    a0, -1                    ; gifts queued for it: dropped
        li    t0, 0                     ; (any sender: find one owned by the slot)
        la    t1, w_att                 ; ...
wex_gl:
        li    t2, NATT                  ; ...
        bge   t0, t2, wex_gd            ; ...
        slli  t3, t0, 4                 ; used?
        add   t3, t1, t3                ; ...
        ld    t4, 0(t3)                 ; ...
        beqz  t4, wex_gn                ; ...
        la    t4, w_attown              ; owned by it?
        slli  t5, t0, 3                 ; ...
        add   t4, t4, t5                ; ...
        ld    t4, 0(t4)                 ; ...
        bne   t4, s1, wex_gn            ; ...
        mv    a0, t0                    ; drop it
        call  att_take                  ; ...
        cclear c8                       ; ...
        j     wex_g                     ; (look again from the start)
wex_gn:
        addi  t0, t0, 1                 ; ...
        j     wex_gl                    ; ...
wex_gd:
        ld    t0, w_server-GPBASE(gp)   ; the server? its queue and parks go too
        bne   t0, s1, wex_ev            ; ...
        li    t0, -1                    ; ...
        sd    t0, w_server-GPBASE(gp)   ; ...
        call  w_flushq                  ; ...
wex_ev:
        ld    t0, w_cur-GPBASE(gp)      ; not running any more
        bne   t0, s1, wex_z             ; ...
        li    t0, -1                    ; ...
        sd    t0, w_cur-GPBASE(gp)      ; ...
wex_z:
        li    t0, S_ZOMBIE              ; until the kernel revokes its arena
        sd    t0, PR_STATE(s2)          ; ...
        ld    a0, PR_PID(s2)            ; tell core 0: an exit event
        mv    a1, s3                    ; ...
        call  w_event                   ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; w_flushq(): the server ended: its queued and parked requests go back to
; their senders with result -1 (a replacement server starts clean)
w_flushq:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
wfq_l:
        ld    t0, w_nreq-GPBASE(gp)     ; queued requests: back with -1
        beqz  t0, wfq_p                 ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, w_nreq-GPBASE(gp)     ; ...
        ld    t2, w_rhead-GPBASE(gp)    ; ...
        addi  t3, t2, 1                 ; ...
        andi  t3, t3, NREQ - 1          ; ...
        sd    t3, w_rhead-GPBASE(gp)    ; ...
        mv    s1, t2                    ; ...
        slli  t2, t2, 3                 ; its pool slot is free again
        la    t1, w_rslot               ; ...
        add   t1, t1, t2                ; ...
        ld    a0, 0(t1)                 ; ...
        call  pool_take                 ; ...
        bnez  a0, wfq_l                 ; died
        la    t1, w_rfrom               ; its sender
        slli  t2, s1, 3                 ; ...
        add   t1, t1, t2                ; ...
        ld    a0, 0(t1)                 ; ...
        call  wpl_bounce2               ; result -1, back to it
        j     wfq_l                     ; ...
wfq_p:
        li    s1, 0                     ; parked ones: back with -1 too
wfq_pl:
        li    t0, NPARK                 ; ...
        bge   s1, t0, wfq_ret           ; ...
        la    t1, w_park                ; ...
        slli  t2, s1, 3                 ; ...
        add   t1, t1, t2                ; ...
        ld    t2, 0(t1)                 ; ...
        beqz  t2, wfq_pn                ; ...
        sd    zero, 0(t1)               ; ...
        addi  t2, t2, -1                ; its sender
        sd    t2, w_tmp+16-GPBASE(gp)   ; ...
        slli  t2, s1, 3                 ; its pool slot is free again
        la    t1, w_pslot               ; ...
        add   t1, t1, t2                ; ...
        ld    a0, 0(t1)                 ; ...
        call  pool_take                 ; ...
        bnez  a0, wfq_pn                ; it died
        ld    a0, w_tmp+16-GPBASE(gp)   ; ...
        call  wpl_bounce2               ; result -1, back to it
        cclear c8                       ; (if it could not be given)
wfq_pn:
        addi  s1, s1, 1                 ; ...
        j     wfq_pl                    ; ...
wfq_ret:
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; wpl_bounce2(a0 = core): c8 = a request: result -1, give it back
wpl_bounce2:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        la    t0, w_tmp                 ; -1 at offset 32
        li    t1, -1                    ; ...
        sd    t1, 0(t0)                 ; ...
        li    t1, 32                    ; ...
        li    t2, 8                     ; ...
        tput  tg14, t0, c8, t1, t2      ; ...
        call  w_ring                    ; ...
        ld    t0, 8(sp)                 ; ...
        cgive c8, t0                    ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; w_event(a0 = pid, a1 = status): an exit event for core 0
w_event:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
wev_room:
        li    a0, CA_TAIL               ; room in the ring? (8 entries)
        call  carea                     ; ...
        call  kst_rd                    ; ...
        sd    a0, 24(sp)                ; tail
        li    a0, CA_HEAD               ; ...
        call  carea                     ; ...
        call  kst_rd                    ; ...
        ld    t0, 24(sp)                ; ...
        sub   t0, t0, a0                ; entries waiting
        li    t1, 8                     ; ...
        bltu  t0, t1, wev_put           ; room
        call  w_token                   ; full: remind core 0 and look again
        j     wev_room                  ; ...
wev_put:
        ld    t0, 24(sp)                ; entry tail mod 8
        andi  t0, t0, 7                 ; ...
        slli  t0, t0, 4                 ; ...
        addi  a0, t0, CA_RING           ; pid
        call  carea                     ; ...
        ld    a1, 8(sp)                 ; ...
        call  kst_wr                    ; ...
        ld    t0, 24(sp)                ; status
        andi  t0, t0, 7                 ; ...
        slli  t0, t0, 4                 ; ...
        addi  a0, t0, CA_RING + 8       ; ...
        call  carea                     ; ...
        ld    a1, 16(sp)                ; ...
        call  kst_wr                    ; ...
        li    a0, CA_TAIL               ; published
        call  carea                     ; ...
        li    a1, 1                     ; ...
        call  kst_add                   ; ...
        call  w_token                   ; and tell core 0
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; w_token(): give core 0 a "look at my events" token (a copy of the console capability)
w_token:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        li    a0, T_CON                 ; ...
        call  crs8                      ; ...
        cgive c8, zero                  ; ...
        cclear c8                       ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; ---- context switch ----------------------------------------------------------------------
; w_out(a0 = slot): save the loaded process: capabilities, D-LS, CSRs -> a0 = 0,
; or -1 if a capability of its c0..c7 found no pool slot: then nothing is
; saved and it stays loaded (the general part of the pool is used up)
w_out:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        mv    s1, a0                    ; s1 = slot
        call  prec                      ; s2 = record
        mv    s2, a0                    ; ...
        li    t0, -1                    ; nothing loaded after this
        sd    t0, w_loaded-GPBASE(gp)   ; ...
        ld    t0, PR_STATE(s2)          ; a zombie has nothing left to save
        li    t1, S_ZOMBIE              ; ...
        beq   t0, t1, wo_ok             ; ...
        twait 0xbfff                    ; its transfers are done (all tags but the kernel's)
        li    s3, 0                     ; its capabilities c0..c7: described or saved (w_stow)
wo_cap:
        li    t0, 8                     ; ...
        bge   s3, t0, wo_csr            ; ...
        mv    a0, s3                    ; c_r -> c8
        call  preg_get                  ; ...
        cvalid t0, c8                   ; something?
        beqz  t0, wo_cn                 ; no
        mv    a0, s2                    ; ...
        mv    a1, s3                    ; ...
        call  w_stow                    ; ...
        bnez  a0, wo_full               ; no room
wo_cn:
        addi  s3, s3, 1                 ; ...
        j     wo_cap                    ; ...
wo_full:
        mv    a0, s3                    ; c_r back
        call  preg_put                  ; ...
wof_l:
        addi  s3, s3, -1                ; and those stowed before it
        bltz  s3, wof_done              ; ...
        mv    a0, s2                    ; ...
        mv    a1, s3                    ; ...
        call  w_fetch                   ; ...
        cvalid t0, c8                   ; ...
        beqz  t0, wof_l                 ; ...
        mv    a0, s3                    ; ...
        call  preg_put                  ; ...
        j     wof_l                     ; ...
wof_done:
        sd    s1, w_loaded-GPBASE(gp)   ; it stays loaded
        li    a0, -1                    ; ...
        j     wo_ret                    ; ...
wo_csr:
        csrr  t0, utvec                 ; its CSRs
        sd    t0, PR_UTVEC(s2)          ; ...
        csrr  t0, uepc                  ; ...
        sd    t0, PR_UEPC(s2)           ; ...
        csrr  t0, ucause                ; ...
        sd    t0, PR_UCAUSE(s2)         ; ...
        csrr  t0, utval                 ; ...
        sd    t0, PR_UTVAL(s2)          ; ...
        csrr  t0, xslot                 ; ...
        sd    t0, PR_XSLOT(s2)          ; ...
        csrr  t0, ccr                   ; ...
        sd    t0, PR_CCR(s2)            ; ...
        csrr  t0, scratch               ; ...
        sd    t0, PR_SCR(s2)            ; ...
        csrr  t0, ttag                  ; ...
        sd    t0, PR_TTAG(s2)           ; ...
        csrr  t0, tdata                 ; ...
        sd    t0, PR_TDATA(s2)          ; ...
        csrr  t0, tgeom                 ; ...
        sd    t0, PR_TGEOM(s2)          ; ...
        call  stash_drop                ; (its c8, c9 do not survive a switch)
        ld    a0, PR_SSL(s2)            ; its save area: data at 0, the stack at
        andi  a0, a0, 255               ;   (address - 0x4000), i.e. 0xA000.. for 0xE000..
        call  crs8                      ;   (from PR_SOB on in the capability)
        li    a0, 0                     ; data -> save area (minus a scratch range)
        call  dls_data                  ; a0 = bytes moved
        mv    t5, a0                    ; ...
        call  dls_extent                ; a1 = stack start
        mv    t6, a1                    ; ...
wo_stack:
        li    t1, STACKTOP              ; stack -> save area
        sub   t2, t1, t6                ; ...
        beqz  t2, wo_saved              ; ...
        li    t3, STACKLO - DATAMAX     ; (its offset there)
        sub   t3, t6, t3                ; ...
        ld    t4, PR_SOB(s2)            ; ...
        add   t3, t3, t4                ; ...
        tput  tg14, t6, c8, t3, t2      ; ...
wo_saved:
        twait 1 << TG_K                 ; (the next process's loads must not overtake)
        li    t1, STACKTOP              ; bytes moved out
        sub   t1, t1, t6                ; ...
        add   t1, t1, t5                ; ...
        sd    t1, w_tmp+16-GPBASE(gp)   ; ...
        ld    a0, PR_SSL(s2)            ; the save area back into its slot
        andi  a0, a0, 255               ; ...
        call  csv8                      ; ...
        ld    a0, w_tmp+16-GPBASE(gp)   ; count the bytes
        call  w_count                   ; ...
wo_ok:
        li    a0, 0                     ; saved
wo_ret:
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; dls_data(a0 = 0 save / 1 restore) (s2 = record, c8 = its save area) -> a0 =
; bytes moved: its data extent [0, end), without its scratch range (SET_SCRATCH)
dls_data:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; direction
        call  dls_extent                ; a0 = data end
        mv    t5, a0                    ; t5 = end
        ld    t3, PR_SCRB(s2)           ; t3, t4 = the scratch range (empty: 0, 0)
        ld    t4, PR_SCRE(s2)           ; ...
        bgeu  t3, t4, dd_whole          ; none
        bgeu  t3, t5, dd_whole          ; beyond the extent
        bleu  t4, t5, dd_two            ; inside it: two pieces
        mv    t4, t5                    ; (it reaches the end)
dd_two:
        mv    a1, t3                    ; [0, start)
        li    a2, 0                     ; ...
        call  dd_move                   ; ...
        sub   t6, t5, t4                ; [end of the range, end)
        mv    a1, t6                    ; ...
        mv    a2, t4                    ; ...
        call  dd_move                   ; ...
        sub   a0, t5, t4                ; bytes moved
        add   a0, a0, t3                ; ...
        j     dd_ret                    ; ...
dd_whole:
        mv    a1, t5                    ; all of [0, end)
        li    a2, 0                     ; ...
        call  dd_move                   ; ...
        mv    a0, t5                    ; ...
dd_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...
dd_move:                                ; (local) a1 bytes at D-LS a2 = save-area offset a2
        beqz  a1, dm_ret                ; ...
        ld    t1, PR_SOB(s2)            ; (where the save area starts in c8)
        add   t1, a2, t1                ; ...
        ld    t0, 8(sp)                 ; (the caller's frame: the direction)
        bnez  t0, dm_in                 ; ...
        tput  tg14, a2, c8, t1, a1      ; D-LS -> save area
        ret                             ; ...
dm_in:
        tget  tg14, a2, c8, t1, a1      ; save area -> D-LS
dm_ret:
        ret                             ; ...

; dls_extent() (s2 = record) -> a0 = end of its data extent, a1 = its stack's start
dls_extent:
        ld    a0, PR_DEND(s2)           ; data end (computed at load)
        ld    a1, PR_REGS+16(s2)        ; sp
        srli  a1, a1, 3                ; clear the low 3 bits
        slli  a1, a1, 3                ; ...
        li    t0, STACKLO               ; within 0xE000..0x10000
        bgeu  a1, t0, de_hi             ; ...
        mv    a1, t0                    ; ...
de_hi:
        li    t0, STACKTOP              ; ...
        bleu  a1, t0, de_ok             ; ...
        mv    a1, t0                    ; ...
de_ok:
        ret                             ; ...

; w_count(a0 = bytes): one more switch for the process in s2, and bytes moved
w_count:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        ld    t0, PR_BYTES(s2)          ; per process
        add   t0, t0, a0                ; ...
        sd    t0, PR_BYTES(s2)          ; ...
        ld    t0, PR_PID(s2)            ; KST per pid: bytes
        andi  t0, t0, 255               ; ...
        slli  t0, t0, 4                 ; ...
        li    t1, PSTATS + 8            ; ...
        add   a0, t0, t1                ; ...
        ld    a1, 8(sp)                 ; ...
        call  kst_add                   ; ...
        ld    a1, 8(sp)                 ; KST per core: KiB
        srli  a1, a1, 10                ; ...
        li    a0, CA_KIB                ; ...
        call  carea                     ; ...
        call  kst_add                   ; ...
        ld    a1, 8(sp)                 ; all cores: KiB
        srli  a1, a1, 10                ; ...
        li    a0, G_KIB                 ; ...
        call  kst_add                   ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; w_count_sw(): one more context switch for the process in s2
w_count_sw:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        ld    t0, PR_SW(s2)             ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, PR_SW(s2)             ; ...
        ld    t0, PR_PID(s2)            ; KST per pid
        andi  t0, t0, 255               ; ...
        slli  t0, t0, 4                 ; ...
        li    t1, PSTATS                ; ...
        add   a0, t0, t1                ; ...
        li    a1, 1                     ; ...
        call  kst_add                   ; ...
        li    a0, CA_SW                 ; per core
        call  carea                     ; ...
        li    a1, 1                     ; ...
        call  kst_add                   ; ...
        li    a0, G_SWITCH              ; all cores
        li    a1, 1                     ; ...
        call  kst_add                   ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; w_in(a0 = slot): load a process: D-LS, code from its image, capabilities, CSRs
w_in:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        mv    s1, a0                    ; s1 = slot
        call  prec                      ; s2 = record
        mv    s2, a0                    ; ...
        li    s4, 0                     ; s4 = bytes moved in
        call  stash_drop                ; whatever the previous process left in c8, c9
        ld    t1, PR_STARTED(s2)        ; first time?
        bnez  t1, wi_restore            ; no: from the save area
        li    t2, 0                     ; first time: its data area starts as zeros
        li    t3, DATAMAX               ; ...
wi_z:
        sd    zero, 0(t2)               ; ...
        addi  t2, t2, 8                 ; ...
        bltu  t2, t3, wi_z              ; ...
        ld    a0, PR_ISL(s2)            ; the image's data section
        andi  a0, a0, 255               ; ...
        call  crs8                      ; ...
        ld    t1, PR_DATA(s2)           ; ...
        li    t2, 0xffff                ; address
        and   t3, t1, t2                ; ...
        srli  t4, t1, 16                ; length
        and   t4, t4, t2                ; ...
        srli  t5, t1, 32                ; image offset (arena offset)
        li    t0, A_IMG                 ; relative to the image share
        sub   t5, t5, t0                ; ...
        add   t6, t3, t4                ; its end: the data extent
        addi  t6, t6, 7                 ; ...
        srli  t6, t6, 3                 ; ...
        slli  t6, t6, 3                 ; ...
        li    t2, DATAMAX               ; (at most 40 KiB)
        bleu  t6, t2, wi_de             ; ...
        mv    t6, t2                    ; ...
wi_de:
        ld    t0, PR_FLAGS(s2)          ; a bare-metal program may use all of its D-LS
        andi  t0, t0, F_SYS             ; (as keeps tables beyond its data section): its
        bnez  t0, wi_de2                ; extent is the whole program area
        li    t6, DATAMAX               ; ...
wi_de2:
        sd    t6, PR_DEND(s2)           ; ...
        beqz  t4, wi_ib                 ; no data
        tget  tg14, t3, c8, t5, t4      ; image -> D-LS
        add   s4, s4, t4                ; ...
wi_ib:
        ld    a0, PR_ISL(s2)            ; the share back (copyable: it stayed anyway,
        andi  a0, a0, 255               ;   unless it is the save area too)
        call  csv8                      ; ...
        j     wi_code                   ; ...
wi_restore:
        ld    a0, PR_SSL(s2)            ; the save area
        andi  a0, a0, 255               ; ...
        call  crs8                      ; ...
        li    a0, 1                     ; save area -> data (minus a scratch range)
        call  dls_data                  ; a0 = bytes moved
        add   s4, s4, a0                ; ...
        call  dls_extent                ; a1 = stack start
wi_rst:
        li    t1, STACKTOP              ; ...
        sub   t2, t1, a1                ; ...
        beqz  t2, wi_sd                 ; ...
        li    t3, STACKLO - DATAMAX     ; (its offset in the save area)
        sub   t3, a1, t3                ; ...
        ld    t4, PR_SOB(s2)            ; ...
        add   t3, t3, t4                ; ...
        tget  tg14, a1, c8, t3, t2      ; save area -> stack
        add   s4, s4, t2                ; ...
wi_sd:
        ld    a0, PR_SSL(s2)            ; the save area back
        andi  a0, a0, 255               ; ...
        call  csv8                      ; ...
wi_code:
        li    t1, 1                     ; (started now)
        sd    t1, PR_STARTED(s2)        ; ...
        ld    a0, PR_ISL(s2)            ; code: reloaded from the image, never saved
        andi  a0, a0, 255               ; ...
        call  crs8                      ; ...
        ld    t1, PR_CODE(s2)           ; address, length, offset
        li    t2, 0xffff                ; ...
        and   t3, t1, t2                ; ...
        srli  t4, t1, 16                ; ...
        and   t4, t4, t2                ; ...
        srli  t5, t1, 32                ; ...
        li    t0, A_IMG                 ; relative to the image share
        sub   t5, t5, t0                ; ...
        add   t6, t3, t4                ; the code cache starts after it
        sd    t6, PR_CEND(s2)           ; ...
        tgetx tg14, t3, c8, t5, t4      ; image -> I-LS
        add   s4, s4, t4                ; ...
        ld    a0, PR_ISL(s2)            ; ...
        andi  a0, a0, 255               ; ...
        call  csv8                      ; ...
        xunmap 0                        ; forget the previous process's code units
        xunmap 1                        ; .
        xunmap 2                        ; .
        xunmap 3                        ; .
        xunmap 4                        ; .
        xunmap 5                        ; .
        xunmap 6                        ; .
        xunmap 7                        ; .
        xunmap 8                        ; .
        xunmap 9                        ; .
        xunmap 10                       ; .
        xunmap 11                       ; .
        xunmap 12                       ; .
        xunmap 13                       ; .
        xunmap 14                       ; .
        xunmap 15                       ; .
        sd    zero, PR_VICT(s2)         ; (units come back on demand)
        li    s3, 0                     ; capabilities: rebuilt or restored (w_fetch)
wi_cap:
        li    t0, 8                     ; ...
        bge   s3, t0, wi_csr            ; ...
        mv    a0, s3                    ; drop what the register holds
        call  preg_get                  ; ...
        cclear c8                       ; ...
        mv    a0, s2                    ; ...
        mv    a1, s3                    ; ...
        call  w_fetch                   ; ...
        cvalid t0, c8                   ; (nothing, or it died meanwhile)
        beqz  t0, wi_cn                 ; ...
        mv    a0, s3                    ; ...
        call  preg_put                  ; ...
wi_cn:
        addi  s3, s3, 1                 ; ...
        j     wi_cap                    ; ...
wi_csr:
        cclear c9                       ; (w_fetch may have used it)
        ld    t0, PR_MIRROR(s2)         ; generated code: reload it from its mirror
        beqz  t0, wi_csr2               ; (none)
        cvalid t1, c0                   ; the mirror is in the program's memory (c0)
        beqz  t1, wi_csr2               ; ...
        slli  t1, t0, 32                ; arena offset
        srli  t1, t1, 32                ; ...
        srli  t2, t0, 32                ; length
        ld    t3, PR_MEM(s2)            ; offset within c0
        add   t1, t1, t3                ; ...
        cbase t3, c0                    ; ...
        sub   t1, t1, t3                ; ...
        clen  t3, c0                    ; inside c0?
        bgtu  t1, t3, wi_csr2           ; ...
        sub   t3, t3, t1                ; ...
        bgtu  t2, t3, wi_csr2           ; ...
        li    t3, PTEXT                 ; -> I-LS 0x8000
        tgetx tg14, t3, c0, t1, t2      ; ...
        add   s4, s4, t2                ; (counted with the switch)
wi_csr2:
        ld    t0, PR_UTVEC(s2)          ; CSRs
        csrw  utvec, t0                 ; ...
        ld    t0, PR_UEPC(s2)           ; ...
        csrw  uepc, t0                  ; ...
        ld    t0, PR_UCAUSE(s2)         ; ...
        csrw  ucause, t0                ; ...
        ld    t0, PR_UTVAL(s2)          ; ...
        csrw  utval, t0                 ; ...
        ld    t0, PR_XSLOT(s2)          ; ...
        csrw  xslot, t0                 ; ...
        ld    t0, PR_CCR(s2)            ; ...
        csrw  ccr, t0                   ; ...
        ld    t0, PR_SCR(s2)            ; ...
        csrw  scratch, t0               ; ...
        ld    t0, PR_TTAG(s2)           ; ...
        csrw  ttag, t0                  ; ...
        ld    t0, PR_TDATA(s2)          ; ...
        csrw  tdata, t0                 ; ...
        ld    t0, PR_TGEOM(s2)          ; ...
        csrw  tgeom, t0                 ; ...
        sd    s1, w_loaded-GPBASE(gp)   ; loaded
        cclear c10                      ; nothing of the kernel's stays in c10..c15
        cclear c11                      ; .
        cclear c12                      ; .
        cclear c13                      ; .
        cclear c14                      ; .
        cclear c15                      ; .
        ld    t0, w_nsw-GPBASE(gp)      ; the first load of the core is not a switch
        addi  t1, t0, 1                 ; ...
        sd    t1, w_nsw-GPBASE(gp)      ; ...
        beqz  t0, wi_ret                ; ...
        mv    a0, s4                    ; count the switch and its bytes
        call  w_count                   ; ...
        call  w_count_sw                ; ...
wi_ret:
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 40                ; ...
        ret                             ; ...

; w_resume(a0 = slot): run it: window, registers, eret into user mode
w_resume:
        sd    a0, w_cur-GPBASE(gp)      ; running
        call  prec                      ; ...
        mv    s2, a0                    ; ...
        sd    s2, w_curp-GPBASE(gp)     ; (for the trap entry)
        call  w_publish                 ; runnable count, states -> KST
        ld    a1, PR_PID(s2)            ; who runs
        li    a0, CA_CUR                ; ...
        call  carea                     ; ...
        call  kst_wr                    ; ...
        cclear c8                       ; the dispatcher's capabilities must not leak
        cclear c9                       ; ...
w_eret:                                 ; (s2 = the record)
        call  unstash                   ; its c8, c9 back (if the dispatcher borrowed them)
        ld    t0, PR_WIN(s2)            ; its core window (threads, bare metal)
        andi  t1, t0, 255               ; base
        srli  t2, t0, 8                 ; count
        andi  t2, t2, 255               ; ...
        csrw  corebase, t1              ; ...
        csrw  corecount, t2             ; (0, 0: none)
wr_regs:
        ld    t0, PR_EPC(s2)            ; where it continues
        csrw  epc, t0                   ; ...
        csrw  status, zero              ; in user mode
        mv    t0, s2                    ; its registers
        ld    x1, PR_REGS+8(t0)         ; restore x1
        ld    x2, PR_REGS+16(t0)        ; restore x2
        ld    x3, PR_REGS+24(t0)        ; restore x3
        ld    x4, PR_REGS+32(t0)        ; restore x4
        ld    x6, PR_REGS+48(t0)        ; restore x6
        ld    x7, PR_REGS+56(t0)        ; restore x7
        ld    x8, PR_REGS+64(t0)        ; restore x8
        ld    x9, PR_REGS+72(t0)        ; restore x9
        ld    x10, PR_REGS+80(t0)       ; restore x10
        ld    x11, PR_REGS+88(t0)       ; restore x11
        ld    x12, PR_REGS+96(t0)       ; restore x12
        ld    x13, PR_REGS+104(t0)      ; restore x13
        ld    x14, PR_REGS+112(t0)      ; restore x14
        ld    x15, PR_REGS+120(t0)      ; restore x15
        ld    x16, PR_REGS+128(t0)      ; restore x16
        ld    x17, PR_REGS+136(t0)      ; restore x17
        ld    x18, PR_REGS+144(t0)      ; restore x18
        ld    x19, PR_REGS+152(t0)      ; restore x19
        ld    x20, PR_REGS+160(t0)      ; restore x20
        ld    x21, PR_REGS+168(t0)      ; restore x21
        ld    x22, PR_REGS+176(t0)      ; restore x22
        ld    x23, PR_REGS+184(t0)      ; restore x23
        ld    x24, PR_REGS+192(t0)      ; restore x24
        ld    x25, PR_REGS+200(t0)      ; restore x25
        ld    x26, PR_REGS+208(t0)      ; restore x26
        ld    x27, PR_REGS+216(t0)      ; restore x27
        ld    x28, PR_REGS+224(t0)      ; restore x28
        ld    x29, PR_REGS+232(t0)      ; restore x29
        ld    x30, PR_REGS+240(t0)      ; restore x30
        ld    x31, PR_REGS+248(t0)      ; restore x31
        ld    t0, PR_REGS+40(t0)        ; and t0 itself
        eret                            ; into the process

; A program that returns from its entry lands here, in user mode: halt ends it.
u_exit:
        halt                            ; -> the dispatcher with cause "halt"

; ---- paging a program's code units (xslot, xmiss) -------------------------------------------
; page_in() (s0 = record) -> a0 = 0 after loading the unit holding the missed
; address into the code cache (the I-LS after its resident code), or 1
page_in:
        csrr  t0, tval                  ; the missed far address (bit 63: a return link)
        slli  t0, t0, 1                 ; drop bit 63
        srli  t0, t0, 1                 ; ...
        csrr  t1, xslot                 ; log2 slot size
        beqz  t1, pi_no                 ; the program did not ask for paging
        cvalid t2, c0                   ; units live in the program's memory (c0)
        beqz  t2, pi_no                 ; ...
        cbase t2, c0                    ; offset within c0
        sub   a2, t0, t2                ; ...
        srl   a2, a2, t1                ; round down to its unit
        sll   a2, a2, t1                ; ...
        clen  t3, c0                    ; ...
        li    t4, 1                     ; t4 = slot size
        sll   t4, t4, t1                ; ...
        bgeu  a2, t3, pi_no             ; outside
        sub   t3, t3, a2                ; a whole slot must fit
        bltu  t3, t4, pi_no             ; ...
        ld    t5, PR_CEND(s0)           ; the cache starts after the resident code,
        add   t5, t5, t4                ;   rounded up to a slot
        addi  t5, t5, -1                ; ...
        srl   t5, t5, t1                ; ...
        sll   t5, t5, t1                ; ...
        li    t6, STACKTOP              ; and ends at 64 KiB
        sub   t6, t6, t5                ; ...
        srl   t6, t6, t1                ; slots that fit
        li    t3, 16                    ; at most 16 map entries
        bleu  t6, t3, pi_n              ; ...
        mv    t6, t3                    ; ...
pi_n:
        beqz  t6, pi_no                 ; no room
        ld    t3, PR_VICT(s0)           ; the slot to replace, round robin, but never
        ld    t2, PR_EPC(s0)            ;   the one the missing xcall / xret is in
        sub   t2, t2, t5                ;   (its slot index from the cache start)
        srl   t2, t2, t1                ;   ...
        bne   t2, t3, pi_vok            ;   ...
        addi  t3, t3, 1                 ;   skip it
        bltu  t3, t6, pi_vok            ;   ...
        li    t3, 0                     ;   ...
pi_vok:
        addi  t2, t3, 1                 ; the next victim
        bltu  t2, t6, pi_wrap           ; ...
        li    t2, 0                     ; ...
pi_wrap:
        sd    t2, PR_VICT(s0)           ; ...
        sll   a1, t3, t1                ; its I-LS address
        add   a1, a1, t5                ; ...
        tgetx tg14, a1, c0, a2, t4      ; image -> I-LS
        ld    t0, PR_LOADS(s0)          ; count it
        addi  t0, t0, 1                 ; ...
        sd    t0, PR_LOADS(s0)          ; ...
        la    t0, xmap_tab              ; xmap slot, a1, c0, a2
        slli  t3, t3, 3                 ; ...
        add   t0, t0, t3                ; ...
        mv    t6, ra                    ; ...
        jalr  ra, t0, 0                 ; ...
        mv    ra, t6                    ; ...
        li    a0, 0                     ; ...
        ret                             ; ...
pi_no:
        li    a0, 1                     ; cannot
        ret                             ; ...
xmap_tab:
        xmap  0, a1, c0, a2             ; slot 0
        ret                             ; .
        xmap  1, a1, c0, a2             ; slot 1
        ret                             ; .
        xmap  2, a1, c0, a2             ; slot 2
        ret                             ; .
        xmap  3, a1, c0, a2             ; slot 3
        ret                             ; .
        xmap  4, a1, c0, a2             ; slot 4
        ret                             ; .
        xmap  5, a1, c0, a2             ; slot 5
        ret                             ; .
        xmap  6, a1, c0, a2             ; slot 6
        ret                             ; .
        xmap  7, a1, c0, a2             ; slot 7
        ret                             ; .
        xmap  8, a1, c0, a2             ; slot 8
        ret                             ; .
        xmap  9, a1, c0, a2             ; slot 9
        ret                             ; .
        xmap  10, a1, c0, a2            ; slot 10
        ret                             ; .
        xmap  11, a1, c0, a2            ; slot 11
        ret                             ; .
        xmap  12, a1, c0, a2            ; slot 12
        ret                             ; .
        xmap  13, a1, c0, a2            ; slot 13
        ret                             ; .
        xmap  14, a1, c0, a2            ; slot 14
        ret                             ; .
        xmap  15, a1, c0, a2            ; slot 15
        ret                             ; .

