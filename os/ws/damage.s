; =============================================================================
; damage.s: what must be drawn again, and drawing it
; =============================================================================
;
; Anything that changes on screen adds its rectangle (dmg_add). Rectangles
; that overlap or touch are merged as they arrive, so the list stays a set
; of disjoint areas; when it is full the new one joins whichever rectangle
; grows least. dmg_commit draws every rectangle from the scene (the display
; list scene.s builds) and then writes PRESENT once: one frame, one batch.
;
; Counters for the performance numbers: dmg_px (pixels drawn by the last
; commit), dmg_ir (instructions it took, from `instret`).

DMAX      = 16                          ; rectangles in the list

        .data                           ; D-LS
        .align 8                        ; dwords
dmg_n:    .dword 0                      ; rectangles in the list
dmg_px:   .dword 0                      ; pixels drawn by the last commit
dmg_ir:   .dword 0                      ; instructions the last commit took
dmg_r:    .space DMAX * 32              ; x0, y0, x1, y1 each
dmg_new:  .space 32                     ; the rectangle being added
        .text                           ; code

; dmg_add(a0 = x0, a1 = y0, a2 = x1, a3 = y1): x1, y1 exclusive
dmg_add:                                ; routine entry
        la    t5, m_w                   ; clip to the screen
        ld    t0, 0(t5)                 ; width
        ld    t1, m_h - m_w(t5)         ; height
        bgez  a0, da_1                  ; x0 >= 0
        li    a0, 0                     ; ...
da_1:   bgez  a1, da_2                  ; y0 >= 0
        li    a1, 0                     ; ...
da_2:   ble   a2, t0, da_3              ; x1 <= width
        mv    a2, t0                    ; ...
da_3:   ble   a3, t1, da_4              ; y1 <= height
        mv    a3, t1                    ; ...
da_4:   bge   a0, a2, da_ret            ; empty
        bge   a1, a3, da_ret            ; empty
        srli  a0, a0, 1                 ; x0 down to even (transfers are 8-byte words)
        slli  a0, a0, 1                 ; ...
        addi  a2, a2, 1                 ; x1 up to even
        srli  a2, a2, 1                 ; ...
        slli  a2, a2, 1                 ; ...
da_merge:                               ; merge with any rectangle it meets, repeatedly
        la    t5, dmg_n                 ; the list
        ld    t6, 0(t5)                 ; count
        la    t4, dmg_r                 ; first rectangle
da_scan:
        beqz  t6, da_append             ; met none: append
        ld    t0, 0(t4)                 ; its x0
        bgt   t0, a2, da_next           ; right of us (touching counts as meeting)
        ld    t0, 16(t4)                ; x1
        blt   t0, a0, da_next           ; left of us
        ld    t0, 8(t4)                 ; y0
        bgt   t0, a3, da_next           ; below
        ld    t0, 24(t4)                ; y1
        blt   t0, a1, da_next           ; above
        ld    t0, 0(t4)                 ; met: take the union ...
        ble   a0, t0, da_u1             ; ...
        mv    a0, t0                    ; ...
da_u1:  ld    t0, 8(t4)                 ; ...
        ble   a1, t0, da_u2             ; ...
        mv    a1, t0                    ; ...
da_u2:  ld    t0, 16(t4)                ; ...
        bge   a2, t0, da_u3             ; ...
        mv    a2, t0                    ; ...
da_u3:  ld    t0, 24(t4)                ; ...
        bge   a3, t0, da_u4             ; ...
        mv    a3, t0                    ; ...
da_u4:  ld    t0, 0(t5)                 ; ... and remove it: the last one takes its place
        addi  t0, t0, -1                ; one fewer
        sd    t0, 0(t5)                 ; ...
        slli  t0, t0, 5                 ; the last rectangle
        la    t1, dmg_r                 ; ...
        add   t1, t1, t0                ; ...
        ld    t0, 0(t1)                 ; moved down
        sd    t0, 0(t4)                 ; ...
        ld    t0, 8(t1)                 ; ...
        sd    t0, 8(t4)                 ; ...
        ld    t0, 16(t1)                ; ...
        sd    t0, 16(t4)                ; ...
        ld    t0, 24(t1)                ; ...
        sd    t0, 24(t4)                ; ...
        j     da_merge                  ; the union may meet others: start over
da_next:
        addi  t4, t4, 32                ; next rectangle
        addi  t6, t6, -1                ; one fewer
        j     da_scan                   ; continue
da_append:
        ld    t6, 0(t5)                 ; count
        li    t0, DMAX                  ; full?
        bge   t6, t0, da_full           ; yes
        slli  t0, t6, 5                 ; its slot
        la    t1, dmg_r                 ; ...
        add   t1, t1, t0                ; ...
        sd    a0, 0(t1)                 ; store it
        sd    a1, 8(t1)                 ; ...
        sd    a2, 16(t1)                ; ...
        sd    a3, 24(t1)                ; ...
        addi  t6, t6, 1                 ; one more
        sd    t6, 0(t5)                 ; ...
da_ret: ret                             ; done
da_full:                                ; full: merge into rectangle 0 (rare; a bigger
        la    t4, dmg_r                 ;   but still correct area)
        ld    t0, 0(t4)                 ; union with it ...
        ble   a0, t0, da_f1             ; ...
        mv    a0, t0                    ; ...
da_f1:  ld    t0, 8(t4)                 ; ...
        ble   a1, t0, da_f2             ; ...
        mv    a1, t0                    ; ...
da_f2:  ld    t0, 16(t4)                ; ...
        bge   a2, t0, da_f3             ; ...
        mv    a2, t0                    ; ...
da_f3:  ld    t0, 24(t4)                ; ...
        bge   a3, t0, da_f4             ; ...
        mv    a3, t0                    ; ...
da_f4:  j     da_u4                     ; remove it and add the union again

; dmg_addr(a0 = x, a1 = y, a2 = w, a3 = h): dmg_add by size
dmg_addr:                               ; routine entry
        add   a2, a0, a2                ; x1
        add   a3, a1, a3                ; y1
        j     dmg_add                   ; add it

; dmg_all(): the whole screen
dmg_all:                                ; routine entry
        li    a0, 0                     ; from the top left
        li    a1, 0                     ; ...
        la    t0, m_w                   ; to the bottom right
        ld    a2, 0(t0)                 ; ...
        ld    a3, m_h - m_w(t0)         ; ...
        j     dmg_add                   ; add it

; dmg_commit(a0 = items, a1 = count) -> a0 = 1 if a frame was presented:
; draws every damaged rectangle from the scene, then PRESENT
dmg_commit:                             ; routine entry
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = rectangle cursor
        sd    s1, 16(sp)                ; s1 = rectangles left
        sd    s2, 24(sp)                ; s2 = items
        sd    s3, 32(sp)                ; s3 = count
        sd    s4, 40(sp)                ; s4 = pixels, then instret at the start
        mv    s2, a0                    ; keep the scene
        mv    s3, a1                    ; ...
        la    t0, dmg_n                 ; anything to draw?
        ld    s1, 0(t0)                 ; ...
        li    a0, 0                     ; (nothing: no frame)
        beqz  s1, dc_ret                ; nothing
        la    s0, dmg_r                 ; first rectangle
        li    t1, 0                     ; count the pixels
dc_px:  ld    t2, 0(s0)                 ; x0
        ld    t3, 16(s0)                ; x1
        sub   t3, t3, t2                ; width
        ld    t2, 8(s0)                 ; y0
        ld    t4, 24(s0)                ; y1
        sub   t4, t4, t2                ; height
        mul   t3, t3, t4                ; area
        add   t1, t1, t3                ; summed
        addi  s0, s0, 32                ; next
        addi  s1, s1, -1                ; ...
        bnez  s1, dc_px                 ; ...
        la    t0, dmg_px                ; keep the total
        sd    t1, 0(t0)                 ; ...
        csrr  s4, instret               ; start counting instructions
        la    t0, dmg_n                 ; draw them all
        ld    s1, 0(t0)                 ; ...
        la    s0, dmg_r                 ; ...
dc_l:   la    t0, m_scr                 ; the screen
        ld    a0, 0(t0)                 ; ...
        mv    a1, s0                    ; this rectangle
        mv    a2, s2                    ; the scene
        mv    a3, s3                    ; ...
        call  gfx_draw                  ; draw it
        addi  s0, s0, 32                ; next
        addi  s1, s1, -1                ; ...
        bnez  s1, dc_l                  ; ...
        la    t0, dmg_n                 ; the list is empty again
        sd    zero, 0(t0)               ; ...
        call  hw_present                ; one PRESENT for the whole batch
        csrr  t1, instret               ; instructions taken
        sub   t1, t1, s4                ; ...
        la    t0, dmg_ir                ; keep them
        sd    t1, 0(t0)                 ; ...
        li    a0, 1                     ; a frame went out
dc_ret: ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        addi  sp, sp, 48                ; pop the frame
        ret                             ; done
