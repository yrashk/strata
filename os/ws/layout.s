; =============================================================================
; layout.s: where the tiles go, and how they get there
; =============================================================================
;
; Tiles fill the screen below the status strip with M_GAP pixels between
; them and around them: 1 tile full; 2 side by side; 3 one left, two
; stacked right; 4 a 2 x 2 grid. Every x and width is even (a blit moves
; 8-byte words: two pixels).
;
; lay_retile() after windows come or go: computes every tile's target; a
; new tile (current width 0) appears there at once and fades in; the others
; start sliding from where they are. lay_step() once per frame (VSYNC paced)
; moves the slides and fades along, damaging exactly the area a tile left
; and the area it now covers. When a slide ends the client is told
; (WE_RESIZE) to draw its surface at the new size.
;
; lay_content(a0 = window) -> a0..a3 = x, y, w, h of its client area.

LAY_STEPS = 12                          ; frames a slide takes
LAY_FADE  = 24                          ; fade-in added per frame (of 256)

        .data                           ; D-LS
        .align 8                        ; dwords
lay_area: .space 32                     ; x, y, w, h of the tile area
lay_t:    .space MAXWIN * 32            ; targets, in tile order
        .text                           ; code

; lay_split(a0 = start, a1 = length) -> a0 = first length, a1 = second
; start, a2 = second length
lay_split:                              ; routine entry
        addi  t0, a1, -M_GAP            ; length minus the gap ...
        srli  t0, t0, 2                 ; ... halved, rounded down to even
        slli  t0, t0, 1                 ; ...
        add   t1, a0, t0                ; second start = start + first + gap
        addi  t1, t1, M_GAP             ; ...
        sub   a2, a1, t0                ; second length = length - first - gap
        addi  a2, a2, -M_GAP            ; ...
        mv    a1, t1                    ; ...
        mv    a0, t0                    ; ...
        ret                             ; done

; lay_put(a0 = tile index, a1 = x, a2 = y, a3 = w, a4 = h): a target
lay_put:                                ; routine entry
        slli  t0, a0, 5                 ; its slot
        la    t1, lay_t                 ; ...
        add   t1, t1, t0                ; ...
        sd    a1, 0(t1)                 ; x
        sd    a2, 8(t1)                 ; y
        sd    a3, 16(t1)                ; w
        sd    a4, 24(t1)                ; h
        ret                             ; done

; lay_targets(): lay_t[] for m_nwin tiles
lay_targets:                            ; routine entry
        addi  sp, sp, -64               ; frame
        sd    ra, 0(sp)                 ; save the return address
        la    t0, m_w                   ; the area: below the strip, inside the gaps
        ld    t1, 0(t0)                 ; screen width
        ld    t2, m_h - m_w(t0)         ; screen height
        li    t3, M_GAP                 ; x
        sd    t3, 8(sp)                 ; ...
        li    t3, M_STRIP + M_GAP       ; y
        sd    t3, 16(sp)                ; ...
        addi  t1, t1, -2 * M_GAP        ; w
        sd    t1, 24(sp)                ; ...
        addi  t2, t2, -(M_STRIP + 2 * M_GAP) ; h
        sd    t2, 32(sp)                ; ...
        ld    a0, 8(sp)                 ; split the width: left w, right x, right w
        ld    a1, 24(sp)                ; ...
        call  lay_split                 ; ...
        sd    a0, 40(sp)                ; left width
        sd    a1, 48(sp)                ; right x
        sd    a2, 56(sp)                ; right width
        la    t0, m_nwin                ; how many tiles
        ld    t0, 0(t0)                 ; ...
        li    t1, 1                     ; one: everything
        beq   t0, t1, lt_1              ; ...
        li    t1, 2                     ; two: side by side
        beq   t0, t1, lt_2              ; ...
        li    t1, 3                     ; three: left, and two on the right
        beq   t0, t1, lt_3              ; ...
        li    t1, 4                     ; four: a grid
        beq   t0, t1, lt_4              ; ...
        j     lt_ret                    ; none
lt_1:   li    a0, 0                     ; tile 0
        ld    a1, 8(sp)                 ; the whole area
        ld    a2, 16(sp)                ; ...
        ld    a3, 24(sp)                ; ...
        ld    a4, 32(sp)                ; ...
        call  lay_put                   ; ...
        j     lt_ret                    ; done
lt_2:   li    a0, 0                     ; tile 0: left, full height
        ld    a1, 8(sp)                 ; ...
        ld    a2, 16(sp)                ; ...
        ld    a3, 40(sp)                ; ...
        ld    a4, 32(sp)                ; ...
        call  lay_put                   ; ...
        li    a0, 1                     ; tile 1: right, full height
        ld    a1, 48(sp)                ; ...
        ld    a2, 16(sp)                ; ...
        ld    a3, 56(sp)                ; ...
        ld    a4, 32(sp)                ; ...
        call  lay_put                   ; ...
        j     lt_ret                    ; done
lt_3:   li    a0, 0                     ; tile 0: left, full height
        ld    a1, 8(sp)                 ; ...
        ld    a2, 16(sp)                ; ...
        ld    a3, 40(sp)                ; ...
        ld    a4, 32(sp)                ; ...
        call  lay_put                   ; ...
        li    a1, 1                     ; tiles 1 and 2: the right column, split
        li    a2, 2                     ; ...
        call  lt_col                    ; ...
        j     lt_ret                    ; done
lt_4:   li    a1, 0                     ; tiles 0 and 2: the left column
        li    a2, 2                     ; ...
        ld    t0, 8(sp)                 ; (its x and width)
        ld    t1, 40(sp)                ; ...
        call  lt_colx                   ; ...
        li    a1, 1                     ; tiles 1 and 3: the right column
        li    a2, 3                     ; ...
        call  lt_col                    ; ...
lt_ret: ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 64                ; pop the frame
        ret                             ; done
; lt_col(a1 = top tile, a2 = bottom tile): the right column, split in height
; (a helper reading lay_targets' frame, which `call` leaves at sp)
lt_col:
        ld    t0, 48(sp)                ; right x
        ld    t1, 56(sp)                ; right width
lt_colx:                                ; t0 = column x, t1 = column width
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    a1, 8(sp)                 ; top tile
        sd    a2, 16(sp)                ; bottom tile
        sd    t0, 24(sp)                ; column x
        sd    t1, 32(sp)                ; column width
        ld    a0, 48 + 16(sp)           ; split the height (lay_targets' y, h) ...
        ld    a1, 48 + 32(sp)           ; ...
        call  lay_split                 ; a0 = top h, a1 = bottom y, a2 = bottom h
        sd    a1, 40(sp)                ; bottom y
        mv    a4, a0                    ; top: h
        ld    a0, 8(sp)                 ; tile
        ld    a1, 24(sp)                ; x
        ld    a2, 48 + 16(sp)           ; y
        ld    a3, 32(sp)                ; w
        call  lay_put                   ; top tile placed
        ld    a0, 16(sp)                ; bottom tile
        ld    a1, 24(sp)                ; x
        ld    a2, 40(sp)                ; y
        ld    a3, 32(sp)                ; w
        la    t0, m_h                   ; h = area bottom - y
        ld    a4, 0(t0)                 ; ...
        addi  a4, a4, -M_GAP            ; ...
        sub   a4, a4, a2                ; ...
        call  lay_put                   ; bottom tile placed
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 48                ; pop the frame
        ret                             ; done

; lay_retile(): new targets; new tiles appear there, the others slide
lay_retile:                             ; routine entry
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = tile index
        sd    s1, 16(sp)                ; s1 = its record
        call  lay_targets               ; where everything goes
        li    s0, 0                     ; first tile
lr_l:   la    t0, m_nwin                ; all done?
        ld    t0, 0(t0)                 ; ...
        bge   s0, t0, lr_ret            ; ...
        mv    a0, s0                    ; its record
        call  m_win                     ; ...
        mv    s1, a0                    ; ...
        slli  t0, s0, 5                 ; its target
        la    t1, lay_t                 ; ...
        add   t1, t1, t0                ; ...
        ld    t2, 0(t1)                 ; copy it to WN_TO
        sd    t2, WN_TO(s1)             ; ...
        ld    t2, 8(t1)                 ; ...
        sd    t2, WN_TO + 8(s1)         ; ...
        ld    t2, 16(t1)                ; ...
        sd    t2, WN_TO + 16(s1)        ; ...
        ld    t2, 24(t1)                ; ...
        sd    t2, WN_TO + 24(s1)        ; ...
        ld    t2, WN_CUR + 16(s1)       ; a new tile?
        bnez  t2, lr_slide              ; no: slide
        ld    t2, 0(t1)                 ; yes: it is already there ...
        sd    t2, WN_CUR(s1)            ; ...
        ld    t2, 8(t1)                 ; ...
        sd    t2, WN_CUR + 8(s1)        ; ...
        ld    t2, 16(t1)                ; ...
        sd    t2, WN_CUR + 16(s1)       ; ...
        ld    t2, 24(t1)                ; ...
        sd    t2, WN_CUR + 24(s1)       ; ...
        sd    zero, WN_FADE(s1)         ; ... and fades in
        sd    zero, WN_ANIM(s1)         ; no slide
        li    t2, WE_RESIZE             ; its client draws at this size
        sd    t2, WN_EVT(s1)            ; ...
        mv    a0, s1                    ; damage it
        call  lay_damage                ; ...
        j     lr_next                   ; next tile
lr_slide:
        ld    t2, WN_CUR(s1)            ; from where it is now
        sd    t2, WN_FROM(s1)           ; ...
        ld    t2, WN_CUR + 8(s1)        ; ...
        sd    t2, WN_FROM + 8(s1)       ; ...
        ld    t2, WN_CUR + 16(s1)       ; ...
        sd    t2, WN_FROM + 16(s1)      ; ...
        ld    t2, WN_CUR + 24(s1)       ; ...
        sd    t2, WN_FROM + 24(s1)      ; ...
        li    t2, 1                     ; the slide starts
        sd    t2, WN_ANIM(s1)           ; ...
lr_next:
        addi  s0, s0, 1                 ; next tile
        j     lr_l                      ; continue
lr_ret: ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; lay_damage(a0 = window): damage its current place, with the glow around
; it and the tag above it
lay_damage:                             ; routine entry
        ld    t0, WN_CUR(a0)            ; x
        ld    t1, WN_CUR + 8(a0)        ; y
        ld    t2, WN_CUR + 16(a0)       ; w
        ld    t3, WN_CUR + 24(a0)       ; h
        addi  a0, t0, -4                ; x - 4
        addi  a1, t1, -6                ; y - 6 (the tag sits on the top edge)
        add   a2, t0, t2                ; x + w + 4
        addi  a2, a2, 4                 ; ...
        add   a3, t1, t3                ; y + h + 4
        addi  a3, a3, 4                 ; ...
        j     dmg_add                   ; add it

; lay_step() -> a0 = 1 while anything moves or fades
lay_step:                               ; routine entry
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = tile index
        sd    s1, 16(sp)                ; s1 = its record
        sd    s2, 24(sp)                ; s2 = anything moving?
        li    s0, 0                     ; first tile
        li    s2, 0                     ; nothing yet
ls_l:   la    t0, m_nwin                ; all done?
        ld    t0, 0(t0)                 ; ...
        bge   s0, t0, ls_ret            ; ...
        mv    a0, s0                    ; its record
        call  m_win                     ; ...
        mv    s1, a0                    ; ...
        ld    t0, WN_FADE(s1)           ; fading in?
        li    t1, OPAQUE                ; ...
        bge   t0, t1, ls_slide          ; no
        addi  t0, t0, LAY_FADE          ; further in
        ble   t0, t1, ls_f              ; at most opaque
        mv    t0, t1                    ; ...
ls_f:   sd    t0, WN_FADE(s1)           ; ...
        li    s2, 1                     ; something changes
        mv    a0, s1                    ; redraw it
        call  lay_damage                ; ...
ls_slide:
        ld    t0, WN_ANIM(s1)           ; sliding?
        beqz  t0, ls_next               ; no
        li    s2, 1                     ; something moves
        mv    a0, s1                    ; the place it leaves
        call  lay_damage                ; ...
        ld    t0, WN_ANIM(s1)           ; t = frame * 256 / steps
        slli  t1, t0, 8                 ; ...
        li    t2, LAY_STEPS             ; ...
        divu  t1, t1, t2                ; ...
        li    t2, 256                   ; ease out: e = 256 - (256 - t)^3 / 65536
        sub   t3, t2, t1                ; ...
        mul   t4, t3, t3                ; ...
        mul   t4, t4, t3                ; ...
        srli  t4, t4, 16                ; ...
        sub   t5, t2, t4                ; t5 = eased progress 0..256
        li    t6, 0                     ; the four coordinates
ls_c:   slli  t0, t6, 3                 ; offset of this one
        add   t0, s1, t0                ; ...
        ld    t1, WN_FROM(t0)           ; from
        ld    t2, WN_TO(t0)             ; to
        sub   t2, t2, t1                ; distance
        mul   t2, t2, t5                ; times progress
        srai  t2, t2, 8                 ; / 256
        add   t1, t1, t2                ; now
        srli  t1, t1, 1                 ; even (blits need it)
        slli  t1, t1, 1                 ; ...
        sd    t1, WN_CUR(t0)            ; ...
        addi  t6, t6, 1                 ; next coordinate
        li    t0, 4                     ; ...
        blt   t6, t0, ls_c              ; ...
        ld    t0, WN_ANIM(s1)           ; one frame further
        addi  t0, t0, 1                 ; ...
        li    t1, LAY_STEPS             ; finished?
        ble   t0, t1, ls_more           ; no
        li    t0, 0                     ; yes: still
        ld    t1, WN_TO(s1)             ; exactly at the target
        sd    t1, WN_CUR(s1)            ; ...
        ld    t1, WN_TO + 8(s1)         ; ...
        sd    t1, WN_CUR + 8(s1)        ; ...
        ld    t1, WN_TO + 16(s1)        ; ...
        sd    t1, WN_CUR + 16(s1)       ; ...
        ld    t1, WN_TO + 24(s1)        ; ...
        sd    t1, WN_CUR + 24(s1)       ; ...
        ld    t1, WN_EVT(s1)            ; the client draws at the new size
        ori   t1, t1, WE_RESIZE         ; ...
        sd    t1, WN_EVT(s1)            ; ...
ls_more:
        sd    t0, WN_ANIM(s1)           ; ...
        mv    a0, s1                    ; the place it covers now
        call  lay_damage                ; ...
ls_next:
        addi  s0, s0, 1                 ; next tile
        j     ls_l                      ; continue
ls_ret: mv    a0, s2                    ; moving?
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

; lay_content(a0 = window) -> a0 = x, a1 = y, a2 = w, a3 = h of the client area
lay_content:                            ; routine entry
        ld    t0, WN_CUR(a0)            ; tile
        ld    t1, WN_CUR + 8(a0)        ; ...
        ld    t2, WN_CUR + 16(a0)       ; ...
        ld    t3, WN_CUR + 24(a0)       ; ...
        addi  a0, t0, M_PADX            ; inset
        addi  a1, t1, M_PADT            ; ...
        addi  a2, t2, -2 * M_PADX       ; ...
        addi  a3, t3, -(M_PADT + M_PADB) ; ...
        ret                             ; done
