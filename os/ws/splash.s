; =============================================================================
; splash.s: the boot splash: STRATA as layered bands that settle
; =============================================================================
;
; The word is drawn from eight horizontal bands (its letters are 8 x 8
; blocks, each block row one band: strata). The bands start far off to
; alternate sides and slide in one after another, easing out, faint while
; they travel; when the last one lands a rule draws out under the word and
; the subtitle fades up. m_splash counts frames from 1; 0 = no splash.
;
; splash_emit() adds the items (the screen's background included: the
; splash is drawn alone); splash_damage() the rows that change.

SPL_CS    = 13                          ; block width
SPL_BH    = 13                          ; band height
SPL_BP    = 17                          ; band pitch
SPL_LG    = 28                          ; gap between letters
SPL_LW    = 8 * SPL_CS                  ; letter width
SPL_WW    = 6 * SPL_LW + 5 * SPL_LG     ; word width
SPL_WH    = 7 * SPL_BP + SPL_BH         ; word height
SPL_DELAY = 5                           ; frames between bands starting
SPL_RUN   = 34                          ; frames a band travels
SPL_DONE  = 7 * SPL_DELAY + SPL_RUN     ; the last band lands
SPL_END   = SPL_DONE + 40               ; the splash ends

        .data                           ; D-LS
spl_word: .ascii "STRATA"               ; the letters, in order
spl_sub:  .ascii "STRATAOS 0.1 \x81 WINDOW SERVER \x81 MEMORY IS EXPLICIT I/O"
spl_sub_e:                              ; (its end)
spl_bits:                               ; 8 rows of 8 blocks per letter (bit 7 = left):
spl_S:    .byte 0x7f, 0xff, 0xc0, 0xfe, 0x7f, 0x03, 0xff, 0xfe ; S  bold letters, cut
spl_T:    .byte 0xff, 0xff, 0x18, 0x18, 0x18, 0x18, 0x18, 0x18 ; T  into strata by the
spl_R:    .byte 0xfe, 0xff, 0xc3, 0xff, 0xfe, 0xcc, 0xc6, 0xc3 ; R  gaps between the
spl_A:    .byte 0x3c, 0x7e, 0xc3, 0xc3, 0xff, 0xff, 0xc3, 0xc3 ; A  bands
        .align 8                        ; dwords
        .text                           ; code

; spl_letter(a0 = character) -> a0 = its 8 rows
spl_letter:                             ; routine entry
        la    t0, spl_S                 ; S
        li    t1, 'S'                   ; ...
        beq   a0, t1, sl_r              ; ...
        la    t0, spl_T                 ; T
        li    t1, 'T'                   ; ...
        beq   a0, t1, sl_r              ; ...
        la    t0, spl_R                 ; R
        li    t1, 'R'                   ; ...
        beq   a0, t1, sl_r              ; ...
        la    t0, spl_A                 ; A
sl_r:   mv    a0, t0                    ; ...
        ret                             ; done

; spl_origin() -> a0 = x, a1 = y of the word's top-left
spl_origin:                             ; routine entry
        la    t0, m_w                   ; centred
        ld    a0, 0(t0)                 ; ...
        addi  a0, a0, -SPL_WW           ; ...
        srai  a0, a0, 1                 ; ...
        ld    a1, m_h - m_w(t0)         ; a little above the middle
        addi  a1, a1, -SPL_WH           ; ...
        srai  a1, a1, 1                 ; ...
        addi  a1, a1, -30               ; ...
        ret                             ; done

; spl_band(a0 = band 0..7) -> a0 = x offset now, a1 = progress 0..256 (eased)
spl_band:                               ; routine entry
        la    t0, m_splash              ; frame
        ld    t1, 0(t0)                 ; ...
        li    t2, SPL_DELAY             ; minus this band's delay
        mul   t2, t2, a0                ; ...
        sub   t1, t1, t2                ; ...
        bgtz  t1, sb_1                  ; started?
        li    t1, 0                     ; not yet
sb_1:   slli  t1, t1, 8                 ; t = frames * 256 / SPL_RUN
        li    t2, SPL_RUN               ; ...
        divu  t1, t1, t2                ; ...
        li    t2, 256                   ; at most 1
        ble   t1, t2, sb_2              ; ...
        mv    t1, t2                    ; ...
sb_2:   sub   t3, t2, t1                ; ease out: e = 256 - (256 - t)^3 / 65536
        mul   t4, t3, t3                ; ...
        mul   t4, t4, t3                ; ...
        srli  t4, t4, 16                ; ...
        sub   a1, t2, t4                ; a1 = e
        sub   t3, t2, a1                ; offset = (256 - e) * width * 3/4 / 256 ...
        la    t0, m_w                   ; ...
        ld    t4, 0(t0)                 ; ...
        mul   t3, t3, t4                ; ...
        srli  t3, t3, 8                 ; ...
        srli  t4, t3, 2                 ; ...
        sub   t3, t3, t4                ; ...
        andi  t4, a0, 1                 ; ... from the left for even bands, the right for odd
        beqz  t4, sb_3                  ; ...
        neg   t3, t3                    ; ...
sb_3:   neg   a0, t3                    ; (even bands come from the left: negative offset)
        ret                             ; done

; spl_h_bands: the handler drawing the word. P0 = x, P1 = y of the word.
spl_h_bands:                            ; handler entry
        addi  sp, sp, -104              ; frame
        sd    a2, 72(sp)                ; the row base (gfx_lerp below needs a2)
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = band
        sd    s1, 16(sp)                ; s1 = x of the current letter
        sd    s2, 24(sp)                ; s2 = letter index
        sd    s3, 32(sp)                ; s3 = block bits
        sd    s4, 40(sp)                ; s4 = offset
        ld    t0, I_P1(a0)              ; rows into the word
        sub   t0, a1, t0                ; ...
        li    t1, SPL_BP                ; which band, and where in it
        divu  s0, t0, t1                ; ...
        remu  t2, t0, t1                ; ...
        li    t3, SPL_BH                ; in the gap between bands?
        bge   t2, t3, sh_ret            ; yes: nothing
        li    t3, 8                     ; past the last band?
        bge   s0, t3, sh_ret            ; ...
        ld    s1, I_P0(a0)              ; the word's x
        mv    a0, s0                    ; this band's offset and progress
        call  spl_band                  ; ...
        add   s1, s1, a0                ; x of the first letter, shifted
        sd    a0, 80(sp)                ; (the offset: trails point back along it)
        mv    s4, a1                    ; progress
        li    t0, 7                     ; colour: cyan at the top, teal at the bottom
        li    a0, C_ACCENT              ; ...
        li    a1, C_EDGE                ; ...
        slli  a2, s0, 8                 ; band * 256 / 7 ...
        divu  a2, a2, t0                ; ...
        srli  a2, a2, 1                 ; ... halved: the bottom stays bright
        call  gfx_lerp                  ; ...
        ld    a2, 72(sp)                ; the row base again
        mv    a7, a0                    ; colour
        mv    t6, s4                    ; alpha = progress: faint while travelling ...
        srli  t6, t6, 1                 ; ... (half, plus half)
        addi  t6, t6, 128               ; ...
        li    t0, 256                   ; landed: opaque
        bne   s4, t0, sh_a              ; ...
        li    t6, OPAQUE                ; ...
sh_a:   li    s2, 0                     ; letter 0
        sd    a7, 48(sp)                ; keep the colour and alpha
        sd    t6, 56(sp)                ; ...
sh_l:   li    t0, 6                     ; all letters?
        bge   s2, t0, sh_ret            ; ...
        la    t0, spl_word              ; the letter
        add   t0, t0, s2                ; ...
        lbu   a0, 0(t0)                 ; ...
        call  spl_letter                ; its rows
        add   a0, a0, s0                ; this band's row
        lbu   s3, 0(a0)                 ; s3 = 8 bits
        li    t5, 7                     ; t5 = bit index, left to right
sh_b:   bltz  t5, sh_next               ; row done
        srl   t0, s3, t5                ; this block set?
        andi  t0, t0, 1                 ; ...
        beqz  t0, sh_bn                 ; no
        mv    t1, t5                    ; a run: extend while the next bits are set
sh_run: addi  t1, t1, -1                ; ...
        bltz  t1, sh_draw               ; ...
        srl   t0, s3, t1                ; ...
        andi  t0, t0, 1                 ; ...
        bnez  t0, sh_run                ; ...
sh_draw:                                ; blocks (7 - t5) .. (7 - t1 - 1)
        li    t0, 7                     ; start x = letter x + (7 - t5) * CS
        sub   t0, t0, t5                ; ...
        li    t2, SPL_CS                ; ...
        mul   t0, t0, t2                ; ...
        add   a5, s1, t0                ; ...
        sub   t3, t5, t1                ; run length (blocks) * CS
        mul   t3, t3, t2                ; ...
        add   a6, a5, t3                ; end x
        mv    t5, t1                    ; continue after the run
        sd    t5, 64(sp)                ; (keep the bit index across the calls)
        sd    a5, 88(sp)                ; (and the run)
        sd    a6, 96(sp)                ; ...
        ld    t0, 80(sp)                ; still travelling: a faint trail behind it,
        beqz  t0, sh_run2               ;   half as long as the way still to go
        ld    a7, 48(sp)                ; ...
        li    t6, 36                    ; ...
        bgtz  t0, sh_tr                 ; coming from the right: the trail is to the right
        neg   t0, t0                    ; from the left: to the left
        srli  t0, t0, 1                 ; ...
        sub   a5, a5, t0                ; ...
        ld    a6, 88(sp)                ; ...
        j     sh_tr2                    ; ...
sh_tr:  srli  t0, t0, 1                 ; ...
        mv    a5, a6                    ; ...
        add   a6, a6, t0                ; ...
sh_tr2: call  gfx_dspan                 ; the trail
        ld    a5, 88(sp)                ; the run
        ld    a6, 96(sp)                ; ...
sh_run2:
        ld    a7, 48(sp)                ; colour
        ld    t6, 56(sp)                ; alpha
        call  gfx_dspan                 ; the run
        ld    t5, 64(sp)                ; ...
        j     sh_b                      ; continue
sh_bn:  addi  t5, t5, -1                ; next block
        j     sh_b                      ; ...
sh_next:
        addi  s1, s1, SPL_LW + SPL_LG   ; next letter
        addi  s2, s2, 1                 ; ...
        j     sh_l                      ; continue
sh_ret: ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        addi  sp, sp, 104               ; pop the frame
        ret                             ; done

; splash_emit(): background, the bands, the rule and the subtitle
splash_emit:                            ; routine entry
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = word x
        sd    s1, 16(sp)                ; s1 = word y
        sd    s2, 24(sp)                ; s2 = frames since landing
        la    t0, m_splash              ; the background: the grid fades in once the
        ld    s2, 0(t0)                 ;   word has landed
        addi  s2, s2, -SPL_DONE         ; ...
        slli  s2, s2, 4                 ; 16 a frame
        bgez  s2, se_g1                 ; ...
        li    s2, 0                     ; ...
se_g1:  li    t0, 256                   ; ...
        ble   s2, t0, se_g2             ; ...
        mv    s2, t0                    ; ...
se_g2:  la    a0, gfx_h_grid            ; ...
        li    a1, 0                     ; ...
        li    a2, 0                     ; ...
        la    t0, m_w                   ; ...
        ld    a3, 0(t0)                 ; ...
        ld    a4, m_h - m_w(t0)         ; ...
        call  gfx_add                   ; ...
        mv    s0, a0                    ; ...
        li    t0, C_BG                  ; ...
        sd    t0, I_P0(s0)              ; ...
        li    t0, 16                    ; ...
        sd    t0, I_P2(s0)              ; ...
        li    t0, M_GAP                 ; (the desktop's grid, exactly)
        sd    t0, I_P4(s0)              ; ...
        li    t0, M_STRIP + M_GAP       ; ...
        sd    t0, I_P5(s0)              ; ...
        li    a0, C_BG                  ; lines
        li    a1, C_GRID                ; ...
        mv    a2, s2                    ; ...
        call  gfx_lerp                  ; ...
        sd    a0, I_P1(s0)              ; ...
        li    a0, C_BG                  ; crosses
        li    a1, C_GRIDX               ; ...
        mv    a2, s2                    ; ...
        call  gfx_lerp                  ; ...
        sd    a0, I_P3(s0)              ; ...
        call  spl_origin                ; the word
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        la    a0, spl_h_bands           ; its handler, over the full width of its rows
        li    a1, 0                     ; ...
        mv    a2, s1                    ; ...
        la    t0, m_w                   ; ...
        ld    a3, 0(t0)                 ; ...
        addi  a4, s1, SPL_WH            ; ...
        call  gfx_add                   ; ...
        sd    s0, I_P0(a0)              ; ...
        sd    s1, I_P1(a0)              ; ...
        la    t0, m_splash              ; frames since the last band landed
        ld    s2, 0(t0)                 ; ...
        addi  s2, s2, -SPL_DONE         ; ...
        blez  s2, se_ret                ; not yet
        slli  t0, s2, 5                 ; the rule: grows from the centre, 32 px a frame
        li    t1, SPL_WW / 2 + 40       ; at most this half-width
        ble   t0, t1, se_r              ; ...
        mv    t0, t1                    ; ...
se_r:   srli  t0, t0, 1                 ; (even)
        slli  t0, t0, 1                 ; ...
        la    t1, m_w                   ; centre x
        ld    a1, 0(t1)                 ; ...
        srli  a1, a1, 1                 ; ...
        sub   a1, a1, t0                ; ...
        addi  a2, s1, SPL_WH + 22       ; under the word
        slli  a3, t0, 1                 ; ...
        li    a4, 1                     ; ...
        li    a5, C_FOCUS               ; amber
        li    a6, OPAQUE                ; ...
        call  gfx_add_rect              ; ...
        li    a0, C_BG                  ; the subtitle fades up
        li    a1, C_DIM                 ; ...
        slli  a2, s2, 4                 ; 16 per frame
        li    t0, 256                   ; ...
        ble   a2, t0, se_s              ; ...
        mv    a2, t0                    ; ...
se_s:   call  gfx_lerp                  ; ...
        mv    a6, a0                    ; ...
        la    t0, m_w                   ; centred
        ld    a1, 0(t0)                 ; ...
        li    t1, (spl_sub_e - spl_sub) * 6 ; ...
        sub   a1, a1, t1                ; ...
        srai  a1, a1, 1                 ; ...
        addi  a2, s1, SPL_WH + 34       ; ...
        la    a3, spl_sub               ; ...
        li    a4, spl_sub_e - spl_sub   ; ...
        la    a5, font_mini             ; ...
        li    a7, NOBG                  ; ...
        call  gfx_add_text              ; ...
se_ret: ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

; splash_damage(): the rows of the word, the rule and the subtitle
splash_damage:                          ; routine entry
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        call  spl_origin                ; ...
        li    a0, 0                     ; full width (bands travel across it)
        la    t0, m_w                   ; ...
        ld    a2, 0(t0)                 ; ...
        addi  a3, a1, SPL_WH + 44       ; down to the subtitle
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        j     dmg_add                   ; add it
