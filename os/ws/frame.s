; =============================================================================
; frame.s: a tile: panel, luminous edge with cut corners, glow, HUD tags
; =============================================================================
;
; frame_emit(a0 = window, a1 = 1 if focused) adds the tile's items to the
; display list being built, back to front:
;   outer glow (focused: two 1-pixel amber lines at falling alpha),
;   the panel (cut corners), the client's surface blitted into the client
;   area, a veil over it while the tile fades in,
;   the edge (teal; amber when focused) and a faint inner line inside it,
;   the tag cut into the top edge, "▸ TERM · PID 7 · CORE 3",
;   and at the right end of the top edge the switch-cost readout
;   "CTX · 148.2 KIB": KiB moved by this process's context switches.
; A tile fading in draws its edge first, then its contents come up: "a new
; tile fades in from its edge lines".
; frame_text(a0 = window) formats the two HUD strings from the model; a
; tile shown alone (FM_ONE) says so at the end of its tag: "· SINGLE".
;
; The full-screen window (layout.s) has none of that: its surface covers
; the screen (over a plain panel while it slides: the surface still has its
; old size), and for FULL_TAG frames after it became full screen a sign in
; the top right corner says so and names the key that leaves (it fades out
; over its last 16 frames). full_tag_damage() damages the sign's place.

FR_TAGX   = 14                          ; tag: inset from the tile's left (and right) edge
FR_PAD    = 5                           ; padding on each side of a tag's text
FS_N      = 28                          ; the full-screen sign: its characters,
FS_W      = FS_N * 6 + 16               ;   width,
FS_H      = 17                          ;   height,
FS_M      = 10                          ;   and distance from the screen's top and right

        .data                           ; D-LS
m_pid_s:  .ascii " \x81 PID "           ; tag pieces
m_core_s: .ascii " \x81 CORE "          ; ...
m_ctx_s:  .ascii "CTX \x81 "            ; readout pieces
m_kib_s:  .ascii " KIB"                 ; ...
m_one_s:  .ascii " \x81 SINGLE"         ; a single tile's tag ends with it
m_full_s: .ascii "FULL SCREEN \x81 ALT+F TO LEAVE" ; the sign (FS_N characters)
        .align 8                        ; dwords
        .text                           ; code

; frame_text(a0 = window): WN_TAG and WN_KIBS from the model
frame_text:                             ; routine entry
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the window
        mv    s0, a0                    ; ...
        addi  a0, s0, WN_TAG            ; the tag: ▸ NAME
        li    a1, 0x80                  ; ▸
        call  fmt_ch                    ; ...
        li    a1, ' '                   ; ...
        call  fmt_ch                    ; ...
        addi  a1, s0, WN_NAME           ; the name
        li    a2, 8                     ; ...
        call  fmt_cstr                  ; ...
        la    a1, m_pid_s               ; " · PID "
        li    a2, m_core_s - m_pid_s    ; ...
        call  fmt_str                   ; ...
        ld    a1, WN_PID(s0)            ; pid
        li    a2, 1                     ; ...
        call  fmt_dec                   ; ...
        la    a1, m_core_s              ; " · CORE "
        li    a2, m_ctx_s - m_core_s    ; ...
        call  fmt_str                   ; ...
        ld    a1, WN_CORE(s0)           ; core
        li    a2, 1                     ; ...
        call  fmt_dec                   ; ...
        la    t0, m_full                ; shown alone (only that tile is drawn)?
        ld    t0, 0(t0)                 ; ...
        li    t1, FM_ONE                ; ...
        bne   t0, t1, ft_t              ; ...
        la    a1, m_one_s               ; " · SINGLE"
        li    a2, m_full_s - m_one_s    ; ...
        call  fmt_str                   ; ...
ft_t:   addi  t0, s0, WN_TAG            ; length
        sub   t0, a0, t0                ; ...
        sd    t0, WN_TAGN(s0)           ; ...
        addi  a0, s0, WN_KIBS           ; the readout: CTX · 148.2 KIB
        la    a1, m_ctx_s               ; ...
        li    a2, m_kib_s - m_ctx_s     ; ...
        call  fmt_str                   ; ...
        sd    a0, 16(sp)                ; keep the cursor
        ld    a0, WN_PID(s0)            ; the process's figure
        call  m_proc_by_pid             ; ...
        li    a1, 0                     ; (none known: 0)
        beqz  a0, ft_k                  ; ...
        ld    a1, PR_KIB10(a0)          ; tenths of KiB
ft_k:   ld    a0, 16(sp)                ; cursor
        call  fmt_tenths                ; 148.2
        la    a1, m_kib_s               ; " KIB"
        li    a2, 4                     ; ...
        call  fmt_str                   ; ...
        addi  t0, s0, WN_KIBS           ; length
        sub   t0, a0, t0                ; ...
        sd    t0, WN_KIBN(s0)           ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

; frame_emit(a0 = window, a1 = 1 if focused)
; Frame slots: 0 ra, 8 s0 (window), 16 s1 (focused), 24 s2 (edge colour),
; 32 s3 (edge alpha), 40..64 x, y, w, h
frame_emit:                             ; routine entry
        addi  sp, sp, -80               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; ...
        sd    s1, 16(sp)                ; ...
        sd    s2, 24(sp)                ; ...
        sd    s3, 32(sp)                ; ...
        mv    s0, a0                    ; s0 = window
        mv    s1, a1                    ; s1 = focused
        call  lay_isfull                ; full screen?
        beqz  t0, fe_tile               ; no
        li    s1, 2                     ; yes (s1 = 2): no frame; a panel under the
        ld    t0, WN_ANIM(s0)           ;   surface while it slides
        beqz  t0, fe_surf               ; ...
        ld    a1, WN_CUR(s0)            ; ...
        ld    a2, WN_CUR + 8(s0)        ; ...
        ld    a3, WN_CUR + 16(s0)       ; ...
        ld    a4, WN_CUR + 24(s0)       ; ...
        li    a5, C_PANEL               ; ...
        li    a6, OPAQUE                ; ...
        call  gfx_add_rect              ; ...
        j     fe_surf                   ; ...
fe_tile:
        mv    a0, s0                    ; ...
        call  frame_text                ; the HUD strings, fresh
        ld    t0, WN_CUR(s0)            ; x, y, w, h into the frame
        sd    t0, 40(sp)                ; ...
        ld    t0, WN_CUR + 8(s0)        ; ...
        sd    t0, 48(sp)                ; ...
        ld    t0, WN_CUR + 16(s0)       ; ...
        sd    t0, 56(sp)                ; ...
        ld    t0, WN_CUR + 24(s0)       ; ...
        sd    t0, 64(sp)                ; ...
        li    s2, C_EDGE                ; edge colour: teal ...
        beqz  s1, fe_c                  ; ...
        li    s2, C_FOCUS               ; ... amber when focused
fe_c:   ld    s3, WN_FADE(s0)           ; edge alpha = 2 x fade, at most opaque
        slli  s3, s3, 1                 ; ...
        li    t0, OPAQUE                ; ...
        ble   s3, t0, fe_a              ; ...
        mv    s3, t0                    ; ...
fe_a:   beqz  s1, fe_panel              ; ---- glow (focused only)
        ld    a1, 40(sp)                ; two pixels out
        addi  a1, a1, -2                ; ...
        ld    a2, 48(sp)                ; ...
        addi  a2, a2, -2                ; ...
        ld    a3, 56(sp)                ; ...
        addi  a3, a3, 4                 ; ...
        ld    a4, 64(sp)                ; ...
        addi  a4, a4, 4                 ; ...
        mv    a5, s2                    ; amber
        li    a6, 40                    ; faint
        mul   a6, a6, s3                ; (times the fade)
        srli  a6, a6, 8                 ; ...
        li    a7, M_CHAMF + 1           ; the corner cut grows with the offset
        call  gfx_add_cframe            ; ...
        ld    a1, 40(sp)                ; one pixel out
        addi  a1, a1, -1                ; ...
        ld    a2, 48(sp)                ; ...
        addi  a2, a2, -1                ; ...
        ld    a3, 56(sp)                ; ...
        addi  a3, a3, 2                 ; ...
        ld    a4, 64(sp)                ; ...
        addi  a4, a4, 2                 ; ...
        mv    a5, s2                    ; amber
        li    a6, 110                   ; brighter
        mul   a6, a6, s3                ; (times the fade)
        srli  a6, a6, 8                 ; ...
        li    a7, M_CHAMF               ; ...
        call  gfx_add_cframe            ; ...
fe_panel:                               ; ---- the panel
        ld    a1, 40(sp)                ; the tile
        ld    a2, 48(sp)                ; ...
        ld    a3, 56(sp)                ; ...
        ld    a4, 64(sp)                ; ...
        li    a5, C_PANEL               ; panel colour
        li    a6, OPAQUE                ; ...
        li    a7, M_CHAMF               ; cut corners
        call  gfx_add_cpanel            ; ...
fe_surf:
        mv    a0, s0                    ; ---- the client's surface
        call  lay_content               ; a0..a3 = client area
        addi  t0, s0, WN_SURF           ; the surface
        ld    t1, S_W(t0)               ; at most its size
        ble   a2, t1, fe_w              ; ...
        mv    a2, t1                    ; ...
fe_w:   ld    t1, S_H(t0)               ; ...
        ble   a3, t1, fe_h              ; ...
        mv    a3, t1                    ; ...
fe_h:   mv    a4, a3                    ; h
        mv    a3, a2                    ; w
        mv    a2, a1                    ; y
        mv    a1, a0                    ; x
        mv    a5, t0                    ; source
        li    a6, 0                     ; from its top-left
        li    a7, 0                     ; ...
        beqz  a3, fe_veil               ; (no surface yet)
        call  gfx_add_blit              ; ...
fe_veil:                                ; ---- the veil while fading in
        ld    t0, WN_FADE(s0)           ; fade
        li    a6, OPAQUE                ; veil alpha = 256 - fade
        sub   a6, a6, t0                ; ...
        blez  a6, fe_edge               ; fully in: no veil
        mv    a0, s0                    ; over the client area
        call  lay_content               ; ...
        mv    a4, a3                    ; h
        mv    a3, a2                    ; w
        mv    a2, a1                    ; y
        mv    a1, a0                    ; x
        li    a5, C_PANEL               ; panel colour
        ld    t0, WN_FADE(s0)           ; (alpha again: a6 was set before the call)
        li    a6, OPAQUE                ; ...
        sub   a6, a6, t0                ; ...
        call  gfx_add_rect              ; ...
fe_edge:                                ; ---- the edge and the inner line
        li    t0, 2                     ; (full screen: the sign instead)
        beq   s1, t0, fe_sign           ; ...
        ld    a1, 40(sp)                ; the tile
        ld    a2, 48(sp)                ; ...
        ld    a3, 56(sp)                ; ...
        ld    a4, 64(sp)                ; ...
        mv    a5, s2                    ; edge colour
        mv    a6, s3                    ; alpha
        li    a7, M_CHAMF               ; ...
        call  gfx_add_cframe            ; ...
        ld    a1, 40(sp)                ; one pixel in
        addi  a1, a1, 1                 ; ...
        ld    a2, 48(sp)                ; ...
        addi  a2, a2, 1                 ; ...
        ld    a3, 56(sp)                ; ...
        addi  a3, a3, -2                ; ...
        ld    a4, 64(sp)                ; ...
        addi  a4, a4, -2                ; ...
        mv    a5, s2                    ; edge colour
        li    a6, 48                    ; faint
        mul   a6, a6, s3                ; (times the fade)
        srli  a6, a6, 8                 ; ...
        li    a7, M_CHAMF               ; ...
        call  gfx_add_cframe            ; ...
        ; ---- the tag: a gap cut into the top edge, text in it
        ld    t0, WN_TAGN(s0)           ; text width = length * 6
        li    t1, 6                     ; ...
        mul   t0, t0, t1                ; ...
        ld    a1, 40(sp)                ; x + FR_TAGX
        addi  a1, a1, FR_TAGX           ; ...
        ld    a2, 48(sp)                ; y - 5
        addi  a2, a2, -5                ; ...
        addi  a3, t0, 2 * FR_PAD        ; text + padding
        li    a4, 11                    ; 11 rows: the edge runs through the middle
        li    a5, C_BG                  ; the background shows through: a gap
        li    a6, OPAQUE                ; ...
        li    a7, 3                     ; small cut corners
        call  gfx_add_cpanel            ; ...
        ld    a1, 40(sp)                ; text
        addi  a1, a1, FR_TAGX + FR_PAD  ; ...
        ld    a2, 48(sp)                ; centred on the edge
        addi  a2, a2, -3                ; ...
        addi  a3, s0, WN_TAG            ; the tag
        ld    a4, WN_TAGN(s0)           ; ...
        la    a5, font_mini             ; small caps
        li    a0, C_BG                  ; colour: accent (amber when focused), faded
        li    a1, C_ACCENT              ; ...
        beqz  s1, fe_tc                 ; ...
        li    a1, C_FOCUS               ; ...
fe_tc:  mv    a2, s3                    ; ...
        call  gfx_lerp                  ; ...
        mv    a6, a0                    ; ...
        ld    a1, 40(sp)                ; (x again: gfx_lerp used a1)
        addi  a1, a1, FR_TAGX + FR_PAD  ; ...
        ld    a2, 48(sp)                ; ...
        addi  a2, a2, -3                ; ...
        li    a7, NOBG                  ; transparent
        call  gfx_add_text              ; ...
        ; ---- the readout at the right end of the top edge
        ld    t0, WN_KIBN(s0)           ; width = length * 6
        li    t1, 6                     ; ...
        mul   t0, t0, t1                ; ...
        sd    t0, 72(sp)                ; keep it
        ld    a1, 40(sp)                ; x + w - FR_TAGX - width - 2 pad
        ld    t1, 56(sp)                ; ...
        add   a1, a1, t1                ; ...
        addi  a1, a1, -(FR_TAGX + 2 * FR_PAD) ; ...
        sub   a1, a1, t0                ; ...
        ld    a2, 48(sp)                ; y - 5
        addi  a2, a2, -5                ; ...
        addi  a3, t0, 2 * FR_PAD        ; ...
        li    a4, 11                    ; ...
        li    a5, C_BG                  ; a gap in the edge
        li    a6, OPAQUE                ; ...
        li    a7, 3                     ; ...
        call  gfx_add_cpanel            ; ...
        li    a0, C_BG                  ; colour: dim, faded
        li    a1, C_DIM                 ; ...
        beqz  s1, fe_kc                 ; (focused: brighter)
        li    a1, C_TEXT                ; ...
fe_kc:  mv    a2, s3                    ; ...
        call  gfx_lerp                  ; ...
        mv    a6, a0                    ; ...
        ld    a1, 40(sp)                ; text x
        ld    t1, 56(sp)                ; ...
        add   a1, a1, t1                ; ...
        addi  a1, a1, -(FR_TAGX + FR_PAD) ; ...
        ld    t0, 72(sp)                ; ...
        sub   a1, a1, t0                ; ...
        ld    a2, 48(sp)                ; ...
        addi  a2, a2, -3                ; ...
        addi  a3, s0, WN_KIBS           ; the readout
        ld    a4, WN_KIBN(s0)           ; ...
        la    a5, font_mini             ; small caps
        li    a7, NOBG                  ; transparent
        call  gfx_add_text              ; ...
fe_ret: ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        addi  sp, sp, 80                ; pop the frame
        ret                             ; done
fe_sign:                                ; ---- the full-screen sign, while it is shown
        la    t0, m_fulltag             ; frames left
        ld    s3, 0(t0)                 ; ...
        beqz  s3, fe_ret                ; none
        slli  s3, s3, 4                 ; s3 = its alpha: it fades over the last 16
        li    t0, OPAQUE                ; ...
        ble   s3, t0, fs_1              ; ...
        mv    s3, t0                    ; ...
fs_1:   la    t0, m_w                   ; s2 = its x
        ld    s2, 0(t0)                 ; ...
        addi  s2, s2, -(FS_W + FS_M)    ; ...
        mv    a1, s2                    ; the body
        li    a2, FS_M                  ; ...
        li    a3, FS_W                  ; ...
        li    a4, FS_H                  ; ...
        li    a5, C_BG                  ; ...
        mv    a6, s3                    ; ...
        li    a7, 3                     ; ...
        call  gfx_add_cpanel            ; ...
        mv    a1, s2                    ; the edge
        li    a2, FS_M                  ; ...
        li    a3, FS_W                  ; ...
        li    a4, FS_H                  ; ...
        li    a5, C_FOCUS               ; ...
        mv    a6, s3                    ; ...
        li    a7, 3                     ; ...
        call  gfx_add_cframe            ; ...
        li    a0, C_BG                  ; the text: amber, faded
        li    a1, C_FOCUS               ; ...
        mv    a2, s3                    ; ...
        call  gfx_lerp                  ; ...
        mv    a6, a0                    ; ...
        addi  a1, s2, 8                 ; ...
        li    a2, FS_M + 5              ; ...
        la    a3, m_full_s              ; ...
        li    a4, FS_N                  ; ...
        la    a5, font_mini             ; small caps
        li    a7, NOBG                  ; transparent
        call  gfx_add_text              ; ...
        j     fe_ret                    ; ...

; full_tag_damage(): damage the place of the full-screen sign
full_tag_damage:                        ; routine entry
        la    t0, m_w                   ; the top right corner
        ld    a2, 0(t0)                 ; ...
        addi  a0, a2, -(FS_W + FS_M)    ; ...
        li    a1, FS_M                  ; ...
        li    a3, FS_M + FS_H           ; ...
        j     dmg_add                   ; add it

; frame_tag_damage(a0 = window): damage just the strip of its top edge where
; the tags are (when the KiB readout changes)
frame_tag_damage:                       ; routine entry
        ld    t0, WN_CUR(a0)            ; x
        ld    t1, WN_CUR + 8(a0)        ; y
        ld    t2, WN_CUR + 16(a0)       ; w
        addi  a1, t1, -5                ; the tag rows
        addi  a3, t1, 6                 ; ...
        add   a2, t0, t2                ; the right half of the edge
        srli  t3, t2, 1                 ; ...
        add   a0, t0, t3                ; ...
        j     dmg_add                   ; add it
