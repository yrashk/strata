; =============================================================================
; ws.s: the StrataOS window server
; =============================================================================
;
; `ws`, started from a shell, becomes the server "ws" of its core (proc
; creates it as one), takes the framebuffer from dev (GRANT_FB) and the
; keyboard from tty (raw mode, foreground), shows the splash and then runs
; one loop for ever:
;
;   wait      RECEIVE with a timeout: a client's request, a key (the
;             keyboard buffer coming back from tty, see hw_os.s), or the next
;             thing due (a frame of an animation, the 4 Hz look at the cores)
;   serve     the protocol below; a key goes through the Alt bindings, the
;             palette, or to the focused window as an event
;   tick      slides, fades, pulses, the splash; cores / processes / slice
;             from proc; windows whose process is gone; pending closes
;   deliver   events to the clients that wait for them (parked EVENT requests)
;   draw      the damaged rectangles from the scene, one PRESENT
;
; It never busy-waits: with nothing moving it sleeps until the next look at
; the cores (250 ms) or an EVENT's timeout. While it waits, the strips and
; the scene (24 KiB of its D-LS) are declared scratch (SET_SCRATCH), so a
; context switch away and back does not copy them.
;
; ---- Surfaces: a server-side store, clients lend bands ----------------------
; Memory capabilities are linear: a surface cannot be writable by a client
; and readable by the server at once. So each window's surface lives in the
; server (in the framebuffer window, after the screen: 2 MiB per window, or
; the last 4 MiB for a single full-size tile), and a client draws into a
; *band* of its own arena and lends it with DAMAGE: the server copies the
; band's rows into the surface (a blit: tget, tput) and gives the band back
; with the reply. The server can always redraw any window (slides, the
; palette's dim) without asking its client.
;
; ---- The protocol (requests to the endpoint LOOKUP "ws" gives) --------------
;  40 CREATE  mode bit0 = interrupt me (SIGNAL) when events wait and I am not
;             in EVENT; data: u64 w, h (ignored: the tile decides), title (8
;             bytes) -> window id; data: u64 width, height of the surface
;  41 DAMAGE  handle = id; data: u64 x, y, w, h, stride; attached: the band
;             holding those w x h pixels from its offset 0 (rows `stride`
;             bytes apart; 0 = w * 4). Without a band: just redraw the rect.
;  42 TEXT    handle = id; data: u64 x, y, fg, bg (-1 none), then the string
;             (length = 32 + its bytes): drawn into the surface, 8 x 16 font
;  43 FILL    handle = id; data: u64 x, y, w, h, colour
;  44 EVENT   handle = id; mode bit0 = do not block (-3); length = timeout in
;             ticks (0 none, -8 when it passes) -> 0; data: u64 kind (1 key,
;             2 resize, 3 close, 4 focus in, 5 focus out, 6 pointer, 7
;             wheel), u64 value (key bytes, first in the low byte; pointer
;             and wheel: u16 x, u16 y in the surface, u8 buttons, s8 wheel
;             y (> 0: away from the user), s8 wheel x, u8 the device's kind:
;             1 move, 2 button), u64 width (keys: the number of bytes), u64
;             height. Pointer events go to the window under the pointer:
;             presses and releases, moves while a button is held, and the
;             wheel.
;  45 DESTROY handle = id          46 TITLE   handle = id; data = 8 bytes
; Results: -1 no such window (of yours), -7 no room (4 windows).
;
; ---- Keys (spec 1.4: Alt+key is ESC [ 27 ; 3 ; code ~, Alt+arrow ESC [ 1 ; 3 X)
; Alt+Enter a terminal; Alt+P or Alt+Space the palette (type, Tab, Up/Down,
; Enter, Esc); Alt+1..4 and Alt+arrows focus; Alt+Q close the focused window (a
; close event, then KILL after 400 ms); Ctrl-C interrupts the focused
; window's process; Alt+Shift+Q quit to the shell; Alt+Shift+H halt the
; machine. Alt+Shift+W makes the server ignore the keyboard for a second
; (for scripted input: tests and demos); Alt+? shows the key help (it is
; also shown when the splash ends; any key or click dismisses it, and is
; not passed on). Everything else is a key event: Esc then a key is just
; that (keys.s), and an Alt+key not bound here reaches the client as ESC and
; the key, Alt+Home, End, Delete, Page Up or Down as the key alone.
;
; ---- The pointer (tty hands its events over with the keys) ------------------
; A cursor follows it. A click focuses the tile under it; in the palette a
; click runs a program (outside it: closes it) and the wheel moves the
; selection. Clients get pointer events (above).

        .text                           ; instruction Local Store
_start: j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program

        .include "theme.s"              ; palette and metrics
        .include "gfx.s"                ; os/lib/gfx.s: surfaces, display lists
        .include "scene.s"              ; the display list of the screen
        .data                           ; (the scratch range ends here: gfx.s's
ws_scr_end:                             ;  buffers and scene.s's items, in that order)
        .text                           ; ...
        .include "font/font.s"          ; os/lib/font/font.s: the fonts
        .include "hw_os.s"              ; the machine layer and our kernel interface
        .include "model.s"              ; what is shown
        .include "fmt.s"                ; text formatting
        .include "damage.s"             ; damage list, commit
        .include "layout.s"             ; tiling and slides
        .include "frame.s"              ; tile frames
        .include "lattice.s"            ; the status strip
        .include "palette.s"            ; the command palette
        .include "splash.s"             ; the boot splash
        .include "pointer.s"            ; the cursor and the key help
        .include "keys.s"               ; the keyboard's bytes as keys

OP_WCREATE = 40                         ; the protocol
OP_WDAMAGE = 41                         ; ...
OP_WTEXT  = 42                          ; ...
OP_WFILL  = 43                          ; ...
OP_WEVENT = 44                          ; ...
OP_WDESTROY = 45                        ; ...
OP_WTITLE = 46                          ; ...
OP_CLEANUP = 37                         ; proc -> servers: a process ended
PTR_K_MOVE = 1                          ; the pointer device's event kinds (platform.h)
PTR_K_BUTTON = 2                        ; ...
PTR_K_WHEEL = 3                         ; ...
PTR_K_LEAVE = 5                         ; ...
EV_KEY    = 1                           ; event kinds
EV_RESIZE = 2                           ; ...
EV_CLOSE  = 3                           ; ...
EV_FOCUS  = 4                           ; ...
EV_BLUR   = 5                           ; ...
EV_PTR    = 6                           ; ...
EV_WHEEL  = 7                           ; ...
WX_ID     = 0                           ; per-window server state: window id (0: free)
WX_PARK   = 8                           ; park id of its waiting EVENT (-1: none)
WX_TOK    = 16                          ; that request's reply token
WX_DEADL  = 24                          ; when that EVENT times out (0: never)
WX_QN     = 32                          ; events queued
WX_FLAGS  = 40                          ; bit 0: SIGNAL the client when events wait
WX_SIGT   = 48                          ; when it was last signalled (0: not since it drained)
WX_CLOSE  = 56                          ; when to kill it (0: not closing)
WX_KIB    = 64                          ; the KiB figure its tag shows
WX_Q      = 72                          ; 8 events: kind, value, count
WX_NQ     = 8                           ; ...
WX_SIZE   = 72 + 8 * 24                 ; bytes
SURF_SLOT = 0x200000                    ; 2 MiB of the framebuffer window per surface
SURF_BIG  = 0xC00000                    ; the last 4 MiB: a single full-size tile
T_FRAME   = 15000                       ; ticks between animation frames (at least)
T_STATS   = 250000                      ; between looks at the cores
T_CLOSE   = 400000                      ; from a close event to KILL
T_SIGNAL  = 200000                      ; between reminders to a client with events
T_ESC     = 100000                      ; an ESC with nothing after it is the Esc key (not ESC [)
T_SPAWN   = 3000000                     ; a spawned terminal should have a window by then

        .data                           ; D-LS
        .align 8                        ; dwords
ws_now:   .dword 0                      ; NOW at the top of this turn of the loop
ws_tframe: .dword 0                     ; the last animation frame
ws_tstat: .dword 0                      ; the last look at the cores
ws_nstat: .dword 0                      ; looks so far (every 4th: processes, clock)
ws_anim:  .dword 0                      ; something is moving: frames are due
ws_esct:  .dword 0                      ; when an ESC came (keys.s: kp_st 1)
ws_wait:  .dword 0                      ; the keyboard is ignored until then
ws_eofs:  .dword 0                      ; 0x04 bytes in a row (16: the input ended)
ws_quit:  .dword 0                      ; quitting: 1 to the shell, 2 halt
ws_spawnt: .dword 0                     ; a terminal was spawned: no other before then
ws_psnow: .dword 0                      ; look at the processes now
ws_pev:   .dword 0                      ; pointer events in the keyboard's answer
ws_core:  .dword -1                     ; the core we run on (from PS)
ws_src:   .space S_SIZE                 ; a client's band as a surface
ws_wx:    .space MAXWIN * WX_SIZE       ; per-window state
ws_sw:    .space MAXCORE * 8            ; each core's switch count at the last look
ws_cmd:   .space 48                     ; a command line being built
ws_hues:                                ; a hue per program name ...
        .dword 0x636f7270, 0x4D9DFF     ; proc
        .dword 0x766564, 0x8CC2FF       ; dev
        .dword 0x7366, 0x3DF5A6         ; fs
        .dword 0x797474, 0xFFD166       ; tty
        .dword 0x65706970, 0xC77DFF     ; pipe
        .dword 0x7377, 0x4DE1FF         ; ws
        .dword 0x6873, 0x7FB8FF         ; sh
        .dword 0x6d726574, 0x5CF2C4     ; term
        .dword 0x6c65646e616d77, 0xFF6F91 ; wmandel
        .dword 0x6b636f6c6377, 0xFF9A5C ; wclock
ws_hues_e:                              ; ... and for the others, by their letters:
        .dword 0xB48CFF, 0xE6E37A, 0xFF8FA3, 0x7FD4FF ; violet, yellow, rose, sky
        .dword 0x9CF27A, 0xFFB86B, 0xD3A0FF, 0x6BE3D6 ; green, orange, lilac, aqua
ws_m_srv: .ascii "ws: not started as a server (proc refused REGISTER)\n"
ws_m_fb:  .ascii "ws: no framebuffer (none, or another ws holds it)\n"
ws_m_bye: .ascii "ws: stopped\n"        ; said when it quits to the shell
ws_m_end:                               ; (end of the messages)
ws_n_term: .ascii "term "               ; the terminal's program name (and a space)
        .align 8                        ; ...
        .text                           ; code

main:
        call  hw_init                   ; server name, framebuffer, keyboard buffer
        beqz  a0, ws_up                 ; ...
        li    t0, -2                    ; which failure?
        la    a1, ws_m_srv              ; not a server
        li    a2, ws_m_fb - ws_m_srv    ; ...
        beq   a0, t0, ws_die            ; ...
        la    a1, ws_m_fb               ; no framebuffer
        li    a2, ws_m_bye - ws_m_fb    ; ...
ws_die: mv    a0, a1                    ; say it
        mv    a1, a2                    ; ...
        call  os_say                    ; ...
        li    a0, 1                     ; and fail
        call  os_exit                   ; ...
ws_up:  la    t0, hw_fb                 ; the model's screen
        la    t1, m_scr                 ; ...
        sd    t0, 0(t1)                 ; ...
        ld    t2, S_W(t0)               ; ...
        sd    t2, m_w - m_scr(t1)       ; ...
        ld    t2, S_H(t0)               ; ...
        sd    t2, m_h - m_scr(t1)       ; ...
        li    a0, 3                     ; the keyboard: raw ...
        li    a1, OP_CONMODE            ; ...
        li    a2, 1                     ; ...
        call  os_call                   ; ...
        li    a0, 3                     ; ... and Ctrl-C comes to us
        li    a1, OP_SETFG              ; ...
        la    t0, os_pid                ; ...
        ld    a2, 0(t0)                 ; ...
        call  os_call                   ; ...
        li    a0, 1                     ; as an interrupt we catch
        li    a1, OP_CATCH              ; ...
        li    a2, 1                     ; ...
        call  os_call                   ; ...
        la    t0, ws_wx                 ; no window waits for events
        li    t1, MAXWIN                ; ...
        li    t2, -1                    ; ...
ws_i1:  sd    t2, WX_PARK(t0)           ; ...
        addi  t0, t0, WX_SIZE           ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, ws_i1                 ; ...
        call  hw_now                    ; the time
        la    t0, ws_now                ; ...
        sd    a0, 0(t0)                 ; ...
        sd    a0, ws_tframe - ws_now(t0) ; ...
        sd    a0, ws_tstat - ws_now(t0) ; ...
        call  ds_procs                  ; the machine as it is now
        call  ds_cores                  ; ...
        la    t0, m_splash              ; the splash starts
        li    t1, 1                     ; ...
        sd    t1, 0(t0)                 ; ...
        la    t0, ws_anim               ; (frames are due)
        sd    t1, 0(t0)                 ; ...
        call  hw_key_arm                ; listen to the keyboard

; ---- the loop ---------------------------------------------------------------
ws_loop:
        call  ws_timeout                ; a0 = how long we may sleep
        mv    s0, a0                    ; ...
        la    a0, gfx_buf               ; strips and scene: scratch while we wait
        la    a1, ws_scr_end            ; ...
        sub   a1, a1, a0                ; ...
        call  os_scratch                ; ...
        mv    a0, s0                    ; wait
        call  os_recv                   ; a0 = 1 request, 2 keys, 0 nothing
        mv    s0, a0                    ; ...
        li    a0, 0                     ; everything is kept again
        li    a1, 0                     ; ...
        call  os_scratch                ; ...
        li    t0, 1                     ; what came?
        beq   s0, t0, ws_req            ; a request
        li    t0, 2                     ; ...
        bne   s0, t0, ws_turn           ; nothing
        call  ky_in                     ; keys
        j     ws_turn                   ; ...
ws_req: call  rq_serve                  ; (it replies, or parks the request)
ws_turn:
        call  hw_clock                  ; c7 = the clock again
        call  hw_now                    ; the time
        la    t0, ws_now                ; ...
        sd    a0, 0(t0)                 ; ...
        call  ws_tick                   ; what is due
        call  ev_pump                   ; events to waiting clients
        call  scn_frame                 ; draw the damage, PRESENT
        la    t0, ws_quit               ; quitting, and every window gone?
        ld    t0, 0(t0)                 ; ...
        beqz  t0, ws_loop               ; no
        la    t1, m_nwin                ; ...
        ld    t1, 0(t1)                 ; ...
        bnez  t1, ws_loop               ; not yet
        j     ws_stop                   ; yes

; ws_timeout() -> a0 = ticks until something is due
ws_timeout:                             ; routine entry
        la    t6, ws_now                ; now
        ld    t5, 0(t6)                 ; ...
        ld    a0, ws_tstat - ws_now(t6) ; the next look at the cores
        li    t0, T_STATS               ; ...
        add   a0, a0, t0                ; a0 = the earliest time so far
        ld    t0, ws_anim - ws_now(t6)  ; a frame?
        beqz  t0, wt_1                  ; ...
        ld    t1, ws_tframe - ws_now(t6) ; ...
        li    t0, T_FRAME + 1000        ; ...
        add   t1, t1, t0                ; ...
        bgeu  t1, a0, wt_1              ; ...
        mv    a0, t1                    ; ...
wt_1:   ld    t1, ws_wait - ws_now(t6)  ; the keyboard comes back
        beqz  t1, wt_2                  ; ...
        bgeu  t1, a0, wt_2              ; ...
        mv    a0, t1                    ; ...
wt_2:   la    t2, m_wins                ; every window's timers
        la    t3, m_nwin                ; ...
        ld    t3, 0(t3)                 ; ...
wt_w:   beqz  t3, wt_d                  ; ...
        ld    t4, WN_CLIENT(t2)         ; ...
        ld    t1, WX_DEADL(t4)          ; an EVENT's timeout
        beqz  t1, wt_w1                 ; ...
        bgeu  t1, a0, wt_w1             ; ...
        mv    a0, t1                    ; ...
wt_w1:  ld    t1, WX_CLOSE(t4)          ; a close's deadline
        beqz  t1, wt_w2                 ; ...
        bgeu  t1, a0, wt_w2             ; ...
        mv    a0, t1                    ; ...
wt_w2:  ld    t1, WX_QN(t4)             ; events waiting for a reminder
        beqz  t1, wt_w3                 ; ...
        ld    t1, WX_FLAGS(t4)          ; ...
        beqz  t1, wt_w3                 ; ...
        li    t1, T_SIGNAL              ; ...
        add   t1, t5, t1                ; ...
        bgeu  t1, a0, wt_w3             ; ...
        mv    a0, t1                    ; ...
wt_w3:  addi  t2, t2, WN_SIZE           ; next window
        addi  t3, t3, -1                ; ...
        j     wt_w                      ; ...
wt_d:   sub   a0, a0, t5                ; from now
        li    t0, 500                   ; at least half a millisecond
        bge   a0, t0, wt_r              ; ...
        mv    a0, t0                    ; ...
wt_r:   ret                             ; done

; ws_stop: everything is closed: give the console back and end
ws_stop:
        la    t0, ws_quit               ; (halting: the last frame stays on the screen)
        ld    t0, 0(t0)                 ; ...
        li    t1, 2                     ; ...
        beq   t0, t1, ws_s1             ; ...
        la    a0, hw_fb                 ; a dark screen
        li    a1, 0                     ; ...
        li    a2, 0                     ; ...
        ld    a3, S_W(a0)               ; ...
        ld    a4, S_H(a0)               ; ...
        li    a5, 0                     ; ...
        call  gfx_fill                  ; ...
        twait 1 << 8                    ; ...
        call  hw_present                ; ...
ws_s1:  li    a0, 3                     ; the console is cooked again
        li    a1, OP_CONMODE            ; ...
        li    a2, 0                     ; ...
        call  os_call                   ; ...
        call  ds_reap                   ; collect our children
        la    t0, ws_quit               ; halt the machine?
        ld    t0, 0(t0)                 ; ...
        li    t1, 2                     ; ...
        bne   t0, t1, ws_bye            ; no: back to the shell
        la    t0, os_buf                ; LOOKUP "dev"
        la    t1, os_n_dev              ; ...
        ld    t1, 0(t1)                 ; ...
        sd    t1, 0(t0)                 ; ...
        li    a0, 8                     ; ...
        call  os_put                    ; ...
        li    a0, 1                     ; ...
        li    a1, OP_LOOKUP             ; ...
        li    a2, 0                     ; ...
        li    a3, 3                     ; ...
        li    a4, 0                     ; ...
        call  os_msg                    ; c6 = dev
        bnez  a0, ws_bye                ; (none: just end)
        li    a0, 6                     ; HALT: does not return
        li    a1, 24                    ; ...
        li    a2, 0                     ; ...
        call  os_call                   ; ...
ws_bye: la    a0, ws_m_bye              ; "ws: stopped"
        li    a1, ws_m_end - ws_m_bye   ; ...
        call  os_say                    ; ...
        li    a0, 0                     ; ...
        call  os_exit                   ; (the kernel takes the framebuffer back)

; ---------------------------------------------------------------------------
; ws_tick(): everything that happens because time passed
; ---------------------------------------------------------------------------
ws_tick:                                ; routine entry
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = index / scratch
        sd    s1, 16(sp)                ; s1 = record
        sd    s2, 24(sp)                ; s2 = moving?
        la    t6, ws_now                ; a frame due?
        ld    t0, 0(t6)                 ; ...
        ld    t1, ws_tframe - ws_now(t6) ; ...
        sub   t1, t0, t1                ; ...
        li    t2, T_FRAME               ; ...
        blt   t1, t2, tk_esc            ; not yet
        sd    t0, ws_tframe - ws_now(t6) ; ---- one animation frame
        li    s2, 0                     ; nothing moves so far
        la    t0, m_splash              ; the splash?
        ld    s0, 0(t0)                 ; ...
        beqz  s0, tk_lay                ; no
        li    s2, 1                     ; yes: it moves
        li    t0, 1                     ; its first frame: everything
        bne   s0, t0, tk_s1             ; ...
        call  dmg_all                   ; ...
tk_s1:  addi  t0, s0, -SPL_DONE         ; the grid fading in: everything
        blez  t0, tk_s2                 ; ...
        li    t1, 17                    ; ...
        bge   t0, t1, tk_s2             ; ...
        call  dmg_all                   ; ...
tk_s2:  call  splash_damage             ; the bands move
        addi  s0, s0, 1                 ; the next frame
        li    t0, SPL_END               ; over?
        ble   s0, t0, tk_s3             ; ...
        li    s0, 0                     ; yes: the desktop, and the key help over it
        la    t0, m_help                ; ...
        li    t1, 1                     ; ...
        sd    t1, 0(t0)                 ; ...
        call  dmg_all                   ; ...
tk_s3:  la    t0, m_splash              ; ...
        sd    s0, 0(t0)                 ; ...
        j     tk_pulse                  ; ...
tk_lay: call  lay_step                  ; slides and fades
        or    s2, s2, a0                ; ...
        li    s0, 0                     ; tiles that reached a new size: a new surface
tk_rs:  la    t0, m_nwin                ; ...
        ld    t0, 0(t0)                 ; ...
        bge   s0, t0, tk_pulse          ; ...
        mv    a0, s0                    ; ...
        call  m_win                     ; ...
        mv    s1, a0                    ; ...
        ld    t0, WN_EVT(s1)            ; ...
        beqz  t0, tk_rn                 ; ...
        sd    zero, WN_EVT(s1)          ; ...
        mv    a0, s1                    ; (only if the size really changed)
        call  wn_size                   ; a0 = w, a1 = h
        ld    t0, WN_SURF + S_W(s1)     ; ...
        ld    t1, WN_SURF + S_H(s1)     ; ...
        bne   a0, t0, tk_rz             ; ...
        beq   a1, t1, tk_rn             ; ...
tk_rz:  mv    a0, s1                    ; ...
        call  wn_surface                ; ...
        mv    a0, s1                    ; and its client draws again
        li    a1, EV_RESIZE             ; ...
        li    a2, 0                     ; ...
        call  ev_put                    ; ...
        mv    a0, s1                    ; ...
        call  lay_damage                ; ...
tk_rn:  addi  s0, s0, 1                 ; ...
        j     tk_rs                     ; ...
tk_pulse:
        li    s0, 0                     ; pulses fade
tk_p:   la    t0, m_ncores              ; ...
        ld    t0, 0(t0)                 ; ...
        bge   s0, t0, tk_pd             ; ...
        slli  t0, s0, 5                 ; the core
        la    t1, m_cores               ; ...
        add   t1, t1, t0                ; ...
        ld    t2, CO_PULSE(t1)          ; pulsing?
        beqz  t2, tk_pn                 ; ...
        addi  t2, t2, -1                ; fainter
        sd    t2, CO_PULSE(t1)          ; ...
        li    s2, 1                     ; ...
        mv    a0, s0                    ; redraw the cell
        call  lat_cell_damage           ; ...
tk_pn:  addi  s0, s0, 1                 ; ...
        j     tk_p                      ; ...
tk_pd:  la    t0, ws_anim               ; frames are due while anything moves
        sd    s2, 0(t0)                 ; ...
tk_esc: la    t2, kp_st                 ; ---- an ESC with nothing after it (yet)
        ld    t0, 0(t2)                 ; ...
        li    t1, 1                     ; ...
        bne   t0, t1, tk_stat           ; ...
        la    t6, ws_now                ; ...
        ld    t0, 0(t6)                 ; ...
        ld    t1, ws_esct - ws_now(t6)  ; ...
        sub   t0, t0, t1                ; ...
        li    t1, T_ESC                 ; ...
        blt   t0, t1, tk_stat           ; ...
        sd    zero, 0(t2)               ; not the start of a sequence: the Esc key
        call  ky_esc                    ; ...
tk_stat:
        la    t6, ws_now                ; ---- a look at the machine
        ld    t0, 0(t6)                 ; ...
        ld    t1, ws_psnow - ws_now(t6) ; (asked for: a window was created)
        bnez  t1, tk_ps                 ; ...
        ld    t1, ws_tstat - ws_now(t6) ; ...
        sub   t1, t0, t1                ; ...
        li    t2, T_STATS               ; ...
        blt   t1, t2, tk_close          ; not yet
        sd    t0, ws_tstat - ws_now(t6) ; ...
        call  ds_cores                  ; what the cores run, pulses
        la    t6, ws_now                ; every fourth look: the rest
        ld    t0, ws_nstat - ws_now(t6) ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, ws_nstat - ws_now(t6) ; ...
        andi  t0, t0, 3                 ; ...
        bnez  t0, tk_close              ; ...
tk_ps:  la    t6, ws_psnow              ; ...
        sd    zero, 0(t6)               ; ...
        call  ds_procs                  ; processes, switch rates, the clock
        call  ds_reap                   ; children that ended
tk_close:
        li    s0, 0                     ; ---- windows whose time is up
tk_c:   la    t0, m_nwin                ; ...
        ld    t0, 0(t0)                 ; ...
        bge   s0, t0, tk_key            ; ...
        mv    a0, s0                    ; ...
        call  m_win                     ; ...
        mv    s1, a0                    ; ...
        ld    t0, WN_CLIENT(s1)         ; ...
        ld    t1, WX_CLOSE(t0)          ; closing?
        beqz  t1, tk_cn                 ; ...
        la    t2, ws_now                ; due?
        ld    t2, 0(t2)                 ; ...
        bltu  t2, t1, tk_cn             ; ...
        li    a0, 1                     ; KILL its process (gone already: no harm)
        li    a1, OP_KILL               ; ...
        ld    a2, WN_PID(s1)            ; ...
        call  os_call                   ; ...
        mv    a0, s0                    ; and the window goes
        call  wn_remove                 ; ...
        j     tk_c                      ; (the same index again: the records moved down)
tk_cn:  addi  s0, s0, 1                 ; ...
        j     tk_c                      ; ...
tk_key: la    t6, ws_now                ; ---- the keyboard after a pause
        ld    t0, ws_wait - ws_now(t6)  ; ...
        beqz  t0, tk_k1                 ; ...
        ld    t1, 0(t6)                 ; ...
        bltu  t1, t0, tk_term           ; still paused
        sd    zero, ws_wait - ws_now(t6) ; ...
tk_k1:  ld    t0, ws_quit - ws_now(t6)  ; (not while quitting)
        bnez  t0, tk_term               ; ...
        call  hw_key_arm                ; (nothing if the buffer is out already)
tk_term:
        la    t0, m_nwin                ; ---- no window: a terminal
        ld    t0, 0(t0)                 ; ...
        bnez  t0, tk_ret                ; ...
        la    t0, m_splash              ; (after the splash,
        ld    t0, 0(t0)                 ; ...
        bnez  t0, tk_ret                ; ...
        la    t6, ws_now                ;  not while quitting,
        ld    t0, ws_quit - ws_now(t6)  ; ...
        bnez  t0, tk_ret                ; ...
        ld    t0, 0(t6)                 ;  and not while one is on its way)
        ld    t1, ws_spawnt - ws_now(t6) ; ...
        bltu  t0, t1, tk_ret            ; ...
        la    a0, os_arg                ; `ws PROGRAM`: that program, the first time
        lbu   t1, 0(a0)                 ; ...
        beqz  t1, tk_trm                ; ...
        li    t2, T_SPAWN               ; (no other until it has its window, or 3 s)
        add   t0, t0, t2                ; ...
        sd    t0, ws_spawnt - ws_now(t6) ; ...
        call  pa_launch                 ; ...
        la    a0, os_arg                ; ...
        sb    zero, 0(a0)               ; ...
        j     tk_ret                    ; ...
tk_trm:
        call  pa_term                   ; ...
tk_ret: ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

