; ev_put(a0 = window, a1 = kind, a2 = value): queue an event for its client
; (a second resize is not queued; a full queue drops the event, but a close
; replaces the last one)
ev_put:                                 ; routine entry
        ld    t0, WN_CLIENT(a0)         ; its state
        ld    t1, WX_QN(t0)             ; events queued
        addi  t2, t0, WX_Q              ; first event
        li    t3, EV_RESIZE             ; a resize: is one queued already?
        bne   a1, t3, ep_room           ; ...
        mv    t4, t1                    ; ...
        mv    t5, t2                    ; ...
ep_s:   beqz  t4, ep_room               ; ...
        ld    t6, 0(t5)                 ; ...
        beq   t6, t3, ep_ret            ; yes: it will carry the latest size
        addi  t5, t5, 24                ; ...
        addi  t4, t4, -1                ; ...
        j     ep_s                      ; ...
ep_room:
        li    t3, WX_NQ                 ; room?
        blt   t1, t3, ep_add            ; ...
        li    t3, EV_CLOSE              ; no: only a close gets in (over the last one)
        bne   a1, t3, ep_ret            ; ...
        addi  t1, t1, -1                ; ...
ep_add: li    t3, 24                    ; its place
        mul   t3, t3, t1                ; ...
        add   t3, t2, t3                ; ...
        sd    a1, 0(t3)                 ; kind
        sd    a2, 8(t3)                 ; value
        sd    zero, 16(t3)              ; count
        addi  t1, t1, 1                 ; one more
        sd    t1, WX_QN(t0)             ; ...
ep_ret: ret                             ; done

; ev_key(a0 = window, a1 = byte): a key for its client; bytes that follow
; each other share an event, up to 8
ev_key:                                 ; routine entry
        ld    t0, WN_CLIENT(a0)         ; its state
        ld    t1, WX_QN(t0)             ; events queued
        beqz  t1, ek_new                ; none
        li    t3, 24                    ; the last one
        mul   t3, t3, t1                ; ...
        add   t3, t0, t3                ; ...
        addi  t3, t3, WX_Q - 24         ; ...
        ld    t4, 0(t3)                 ; a key event ...
        li    t5, EV_KEY                ; ...
        bne   t4, t5, ek_new            ; ...
        ld    t4, 16(t3)                ; ... with room?
        li    t5, 8                     ; ...
        bge   t4, t5, ek_new            ; ...
        slli  t5, t4, 3                 ; the byte joins it
        sll   t5, a1, t5                ; ...
        ld    t6, 8(t3)                 ; ...
        or    t6, t6, t5                ; ...
        sd    t6, 8(t3)                 ; ...
        addi  t4, t4, 1                 ; ...
        sd    t4, 16(t3)                ; ...
        ret                             ; done
ek_new: li    t3, WX_NQ                 ; room for a new event?
        bge   t1, t3, ek_ret            ; no: the key is dropped
        li    t3, 24                    ; ...
        mul   t3, t3, t1                ; ...
        add   t3, t0, t3                ; ...
        addi  t3, t3, WX_Q              ; ...
        li    t4, EV_KEY                ; ...
        sd    t4, 0(t3)                 ; kind
        sd    a1, 8(t3)                 ; the byte
        li    t4, 1                     ; ...
        sd    t4, 16(t3)                ; one so far
        addi  t1, t1, 1                 ; ...
        sd    t1, WX_QN(t0)             ; ...
ek_ret: ret                             ; done

; ev_take(a0 = window): its first event -> os_buf (kind, value, width or the
; key count, height) and off the queue
ev_take:                                ; routine entry
        ld    t0, WN_CLIENT(a0)         ; its state
        la    t1, os_buf                ; the reply data
        ld    t2, WX_Q(t0)              ; kind
        sd    t2, 0(t1)                 ; ...
        ld    t3, WX_Q + 8(t0)          ; value
        sd    t3, 8(t1)                 ; ...
        ld    t3, WN_SURF + S_W(a0)     ; the surface's size as it is now
        ld    t4, WN_SURF + S_H(a0)     ; ...
        li    t5, EV_KEY                ; (a key: the number of bytes instead)
        bne   t2, t5, et_1              ; ...
        ld    t3, WX_Q + 16(t0)         ; ...
et_1:   sd    t3, 16(t1)                ; ...
        sd    t4, 24(t1)                ; ...
        ld    t1, WX_QN(t0)             ; the others move up
        addi  t1, t1, -1                ; ...
        sd    t1, WX_QN(t0)             ; ...
        li    t2, 3                     ; three words each
        mul   t1, t1, t2                ; ...
        addi  t2, t0, WX_Q              ; ...
et_m:   beqz  t1, et_r                  ; ...
        ld    t3, 24(t2)                ; ...
        sd    t3, 0(t2)                 ; ...
        addi  t2, t2, 8                 ; ...
        addi  t1, t1, -1                ; ...
        j     et_m                      ; ...
et_r:   ret                             ; done

; ev_pump(): answer the EVENT requests that can be answered (an event, or
; the timeout); remind clients that asked for it (SIGNAL) that events wait
ev_pump:                                ; routine entry
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = index
        sd    s1, 16(sp)                ; s1 = window
        sd    s2, 24(sp)                ; s2 = its state
        sd    s3, 32(sp)                ; s3 = the result
        li    s0, 0                     ; every window
ev_l:   la    t0, m_nwin                ; ...
        ld    t0, 0(t0)                 ; ...
        bge   s0, t0, ev_r              ; ...
        mv    a0, s0                    ; ...
        call  m_win                     ; ...
        mv    s1, a0                    ; ...
        ld    s2, WN_CLIENT(s1)         ; ...
        ld    t0, WX_PARK(s2)           ; an EVENT waiting?
        bltz  t0, ev_sig                ; no
        li    s3, 0                     ; an event for it?
        ld    t1, WX_QN(s2)             ; ...
        bnez  t1, ev_ans                ; yes
        li    s3, -8                    ; its time is up?
        ld    t1, WX_DEADL(s2)          ; ...
        beqz  t1, ev_n                  ; (it has no timeout)
        la    t2, ws_now                ; ...
        ld    t2, 0(t2)                 ; ...
        bltu  t2, t1, ev_n              ; not yet
ev_ans: ld    a0, WX_PARK(s2)           ; the request back
        li    t0, -1                    ; ...
        sd    t0, WX_PARK(s2)           ; ...
        sd    zero, WX_DEADL(s2)        ; ...
        call  os_unpark                 ; ...
        beqz  a0, ev_a1                 ; ...
        li    t0, 1                     ; its owner died: the window goes at the next tick
        sd    t0, WX_CLOSE(s2)          ; ...
        j     ev_n                      ; ...
ev_a1:  ld    t0, WX_TOK(s2)            ; its token
        la    t1, rq_tok                ; ...
        sd    t0, 0(t1)                 ; ...
        bnez  s3, ev_a2                 ; (a timeout carries no event)
        mv    a0, s1                    ; the event
        call  ev_take                   ; ...
        li    a0, 32                    ; ...
        call  rq_put                    ; ...
ev_a2:  mv    a0, s3                    ; answer
        li    a1, 0                     ; ...
        call  os_reply                  ; ...
        j     ev_n                      ; ...
ev_sig: ld    t1, WX_QN(s2)             ; events, and the client wants reminding?
        beqz  t1, ev_n                  ; ...
        ld    t1, WX_FLAGS(s2)          ; ...
        andi  t1, t1, 1                 ; ...
        beqz  t1, ev_n                  ; ...
        la    t2, ws_now                ; not more often than every T_SIGNAL
        ld    t2, 0(t2)                 ; ...
        ld    t1, WX_SIGT(s2)           ; ...
        beqz  t1, ev_s1                 ; (not yet since the queue drained)
        sub   t3, t2, t1                ; ...
        li    t4, T_SIGNAL              ; ...
        blt   t3, t4, ev_n              ; ...
ev_s1:  ori   t2, t2, 1                 ; (never 0)
        sd    t2, WX_SIGT(s2)           ; ...
        li    a0, 1                     ; SIGNAL its process
        li    a1, OP_SIGNAL             ; ...
        ld    a2, WN_PID(s1)            ; ...
        call  os_call                   ; ...
ev_n:   addi  s0, s0, 1                 ; next window
        j     ev_l                      ; ...
ev_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        addi  sp, sp, 40                ; pop the frame
        ret                             ; done

; ---------------------------------------------------------------------------
; rq_serve(): the request in c6 (header in rq_hdr): answer it, or park it
; ---------------------------------------------------------------------------
rq_serve:                               ; routine entry
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the window
        sd    s1, 16(sp)                ; s1 = its state / scratch
        sd    s2, 24(sp)                ; s2 = scratch
        la    t0, rq_hdr                ; the op
        ld    t1, 0(t0)                 ; ...
        li    t2, OP_WCREATE            ; CREATE needs no window
        beq   t1, t2, rq_create         ; ...
        li    t2, OP_CLEANUP            ; from proc: a process ended
        beq   t1, t2, rq_clean          ; ...
        addi  t2, t1, -OP_WDAMAGE       ; the others name one of the caller's windows
        li    t3, OP_WTITLE - OP_WDAMAGE ; ...
        li    a0, -1                    ; (anything else: refused; proc's DUPS and
        bgtu  t2, t3, rq_ans            ;  CANCEL get -1 too: nothing to do)
        ld    a0, 8(t0)                 ; handle = id
        ld    a1, 40(t0)                ; the sender
        call  wn_find                   ; ...
        mv    s0, a0                    ; ...
        li    a0, -1                    ; no such window
        beqz  s0, rq_ans                ; ...
        ld    s1, WN_CLIENT(s0)         ; ...
        la    t0, rq_hdr                ; ...
        ld    t1, 0(t0)                 ; ...
        li    t2, OP_WDAMAGE            ; ...
        beq   t1, t2, rq_damage         ; ...
        li    t2, OP_WTEXT              ; ...
        beq   t1, t2, rq_text           ; ...
        li    t2, OP_WFILL              ; ...
        beq   t1, t2, rq_fill           ; ...
        li    t2, OP_WEVENT             ; ...
        beq   t1, t2, rq_event          ; ...
        li    t2, OP_WDESTROY           ; ...
        beq   t1, t2, rq_destroy        ; ...
        li    a0, 16                    ; ---- TITLE: 8 bytes
        call  rq_get                    ; ...
        la    t0, os_buf                ; ...
        ld    t0, 0(t0)                 ; ...
        sd    t0, WN_NAME(s0)           ; ...
        mv    a0, s0                    ; its tag and the strip's list change
        call  lay_damage                ; ...
        call  lat_stats_damage          ; ...
        li    a0, 0                     ; ...
rq_ans: call  rq_band                   ; a band that came with it goes back
        call  os_reply                  ; ...
rq_ret: ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

; rq_band() -> a1 = 1 if c7 holds a client's band (memory; RECEIVE leaves
; the clock there when nothing was attached); a0 is kept
rq_band:                                ; routine entry
        cvalid a1, c7                   ; anything?
        beqz  a1, rb_r                  ; ...
        cperms t0, c7                   ; space << 8 | permissions
        srli  t0, t0, 8                 ; system memory is space 3
        addi  t0, t0, -3                ; ...
        seqz  a1, t0                    ; ...
rb_r:   ret                             ; done

rq_clean:                               ; ---- CLEANUP: that process's windows go
        ld    t1, 8(t0)                 ; the pid
        la    t2, m_wins                ; ...
        la    t3, m_nwin                ; ...
        ld    t3, 0(t3)                 ; ...
rc_l:   beqz  t3, rc_d                  ; ...
        ld    t4, WN_PID(t2)            ; ...
        bne   t4, t1, rc_n              ; ...
        ld    t4, WN_CLIENT(t2)         ; at the next tick
        li    t5, 1                     ; ...
        sd    t5, WX_CLOSE(t4)          ; ...
rc_n:   addi  t2, t2, WN_SIZE           ; ...
        addi  t3, t3, -1                ; ...
        j     rc_l                      ; ...
rc_d:   li    a0, 0                     ; ...
        j     rq_ans                    ; ...

rq_create:                              ; ---- CREATE
        li    a0, 24                    ; data: w, h, title
        call  rq_get                    ; ...
        la    t0, m_nwin                ; room for a tile?
        ld    t0, 0(t0)                 ; ...
        li    t1, MAXWIN                ; ...
        li    a0, -7                    ; (no)
        bge   t0, t1, rq_ans            ; ...
        la    t0, m_splash              ; (and not during the splash)
        ld    t0, 0(t0)                 ; ...
        bnez  t0, rq_ans                ; ...
        la    s1, ws_wx                 ; a free state record
        li    s2, 1                     ; its id
rcr_f:  ld    t0, WX_ID(s1)             ; ...
        beqz  t0, rcr_g                 ; ...
        addi  s1, s1, WX_SIZE           ; ...
        addi  s2, s2, 1                 ; ...
        j     rcr_f                     ; (one is free: fewer than MAXWIN windows)
rcr_g:  li    t0, WX_SIZE / 8           ; cleared
        mv    t1, s1                    ; ...
rcr_c:  sd    zero, 0(t1)               ; ...
        addi  t1, t1, 8                 ; ...
        addi  t0, t0, -1                ; ...
        bnez  t0, rcr_c                 ; ...
        sd    s2, WX_ID(s1)             ; ...
        li    t0, -1                    ; ...
        sd    t0, WX_PARK(s1)           ; ...
        la    t0, rq_hdr                ; mode bit 0: SIGNAL when events wait
        ld    t1, 24(t0)                ; ...
        andi  t1, t1, 1                 ; ...
        sd    t1, WX_FLAGS(s1)          ; ...
        la    t0, m_nwin                ; the new tile's record
        ld    a0, 0(t0)                 ; ...
        addi  t1, a0, 1                 ; ...
        sd    t1, 0(t0)                 ; ...
        call  m_win                     ; ...
        mv    s0, a0                    ; ...
        li    t0, WN_SIZE / 8           ; cleared
        mv    t1, s0                    ; ...
rcr_z:  sd    zero, 0(t1)               ; ...
        addi  t1, t1, 8                 ; ...
        addi  t0, t0, -1                ; ...
        bnez  t0, rcr_z                 ; ...
        sd    s1, WN_CLIENT(s0)         ; ...
        ld    t0, WX_FLAGS(s1)          ; kind: a terminal asks for reminders
        li    t1, WK_GFX                ; ...
        sub   t1, t1, t0                ; ...
        sd    t1, WN_KIND(s0)           ; ...
        la    t0, rq_hdr                ; its process
        ld    a0, 40(t0)                ; ...
        sd    a0, WN_PID(s0)            ; ...
        call  m_proc_by_pid             ; its core, if we know it already
        beqz  a0, rcr_n                 ; ...
        ld    t0, PR_CORE(a0)           ; ...
        sd    t0, WN_CORE(s0)           ; ...
rcr_n:  la    t0, os_buf                ; the title
        ld    t0, 16(t0)                ; ...
        sd    t0, WN_NAME(s0)           ; ...
        call  lay_retile                ; everything moves; the new tile is in place
        sd    zero, WN_EVT(s0)          ; (its surface is made here)
        mv    a0, s0                    ; ...
        call  wn_surface                ; ...
        mv    a0, s0                    ; it gets the focus
        call  wn_index                  ; ...
        call  wn_focus                  ; ...
        la    t0, ws_anim               ; frames are due; look at the processes soon;
        li    t1, 1                     ;   the terminal we waited for has come
        sd    t1, 0(t0)                 ; ...
        sd    t1, ws_psnow - ws_anim(t0) ; ...
        sd    zero, ws_spawnt - ws_anim(t0) ; ...
        la    t0, os_buf                ; data: the surface's size
        ld    t1, WN_SURF + S_W(s0)     ; ...
        sd    t1, 0(t0)                 ; ...
        ld    t1, WN_SURF + S_H(s0)     ; ...
        sd    t1, 8(t0)                 ; ...
        li    a0, 16                    ; ...
        call  rq_put                    ; ...
        mv    a0, s2                    ; the id
        j     rq_ans                    ; ...

rq_damage:                              ; ---- DAMAGE: x, y, w, h, stride (+ the band)
        li    a0, 40                    ; ...
        call  rq_get                    ; ...
        la    s2, os_buf                ; ...
        call  rq_band                   ; a band?
        beqz  a1, rd_dmg                ; no: just redraw
        ld    t0, 0(s2)                 ; x, w even; inside the surface
        ld    t2, 16(s2)                ; ...
        or    t4, t0, t2                ; ...
        andi  t4, t4, 1                 ; ...
        bnez  t4, rd_bad                ; ...
        blez  t2, rd_bad                ; ...
        ld    t1, 8(s2)                 ; ...
        ld    t3, 24(s2)                ; ...
        blez  t3, rd_bad                ; ...
        add   t4, t0, t2                ; x + w <= W (a band drawn for another size:
        ld    t5, WN_SURF + S_W(s0)     ;   ignored; the client is redrawing anyway)
        bgtu  t4, t5, rd_ok             ; ...
        add   t4, t1, t3                ; y + h <= H
        ld    t5, WN_SURF + S_H(s0)     ; ...
        bgtu  t4, t5, rd_ok             ; ...
        ld    t5, 32(s2)                ; stride (0: w * 4)
        slli  t6, t2, 2                 ; ...
        bnez  t5, rd_s1                 ; ...
        mv    t5, t6                    ; ...
rd_s1:  bltu  t5, t6, rd_bad            ; ...
        andi  t4, t5, 7                 ; (whole words)
        bnez  t4, rd_bad                ; ...
        mul   t4, t5, t3                ; the band must hold h rows
        clen  t6, c7                    ; ...
        bgtu  t4, t6, rd_bad            ; ...
        la    t4, ws_src                ; the band as a surface
        li    t6, 7                     ; (through c7)
        sd    t6, S_CAP(t4)             ; ...
        sd    zero, S_OFF(t4)           ; ...
        sd    t2, S_W(t4)               ; ...
        sd    t3, S_H(t4)               ; ...
        sd    t5, S_STRIDE(t4)          ; ...
        la    t5, gfx_tmp               ; one item: a blit of all of it
        la    t6, gfx_h_blit            ; ...
        sd    t6, I_FN(t5)              ; ...
        sd    t4, I_P0(t5)              ; source
        sd    zero, I_P1(t5)            ; from its (0, 0)
        sd    zero, I_P2(t5)            ; ...
        la    t6, gfx_rect              ; box and rect: x, y, x + w, y + h
        sd    t0, I_X0(t5)              ; ...
        sd    t0, 0(t6)                 ; ...
        sd    t1, I_Y0(t5)              ; ...
        sd    t1, 8(t6)                 ; ...
        add   t0, t0, t2                ; ...
        sd    t0, I_X1(t5)              ; ...
        sd    t0, 16(t6)                ; ...
        add   t1, t1, t3                ; ...
        sd    t1, I_Y1(t5)              ; ...
        sd    t1, 24(t6)                ; ...
        addi  a0, s0, WN_SURF           ; into the window's surface
        mv    a1, t6                    ; ...
        mv    a2, t5                    ; ...
        li    a3, 1                     ; ...
        call  gfx_draw                  ; ...
rd_dmg: mv    a0, s0                    ; on the screen
        ld    a1, 0(s2)                 ; ...
        ld    a2, 8(s2)                 ; ...
        ld    a3, 16(s2)                ; ...
        ld    a4, 24(s2)                ; ...
        call  wn_damage                 ; ...
rd_ok:  li    a0, 0                     ; ...
        j     rq_ans                    ; ...
rd_bad: li    a0, -1                    ; ...
        j     rq_ans                    ; ...

rq_text:                                ; ---- TEXT: x, y, fg, bg, string
        la    t0, rq_hdr                ; its length
        ld    s2, 16(t0)                ; ...
        li    t1, 32 + 160              ; (at most 160 characters)
        bleu  s2, t1, rt_1              ; ...
        mv    s2, t1                    ; ...
rt_1:   mv    a0, s2                    ; ...
        call  rq_get                    ; ...
        addi  s2, s2, -32               ; the string's length
        li    a0, -1                    ; ...
        blez  s2, rq_ans                ; ...
        la    t0, os_buf                ; ...
        addi  a0, s0, WN_SURF           ; ...
        ld    a1, 0(t0)                 ; x
        ld    a2, 8(t0)                 ; y
        addi  a3, t0, 32                ; the string
        mv    a4, s2                    ; ...
        la    a5, font_body             ; 8 x 16
        ld    a6, 16(t0)                ; fg
        ld    a7, 24(t0)                ; bg
        call  gfx_text                  ; ...
        la    t0, os_buf                ; damage it
        mv    a0, s0                    ; ...
        ld    a1, 0(t0)                 ; ...
        ld    a2, 8(t0)                 ; ...
        slli  a3, s2, 3                 ; ...
        li    a4, 16                    ; ...
        call  wn_damage                 ; ...
        li    a0, 0                     ; ...
        j     rq_ans                    ; ...

rq_fill:                                ; ---- FILL: x, y, w, h, colour
        li    a0, 40                    ; ...
        call  rq_get                    ; ...
        la    s2, os_buf                ; ...
        addi  a0, s0, WN_SURF           ; ...
        ld    a1, 0(s2)                 ; ...
        ld    a2, 8(s2)                 ; ...
        ld    a3, 16(s2)                ; ...
        ld    a4, 24(s2)                ; ...
        ld    a5, 32(s2)                ; ...
        call  gfx_fill                  ; ...
        mv    a0, s0                    ; damage it
        ld    a1, 0(s2)                 ; ...
        ld    a2, 8(s2)                 ; ...
        ld    a3, 16(s2)                ; ...
        ld    a4, 24(s2)                ; ...
        call  wn_damage                 ; ...
        li    a0, 0                     ; ...
        j     rq_ans                    ; ...

rq_event:                               ; ---- EVENT
        ld    t1, WX_QN(s1)             ; one waiting?
        beqz  t1, rv_none               ; no
        mv    a0, s0                    ; yes: it is the answer
        call  ev_take                   ; ...
        li    a0, 32                    ; ...
        call  rq_put                    ; ...
        li    a0, 0                     ; ...
        j     rq_ans                    ; ...
rv_none:
        sd    zero, WX_SIGT(s1)         ; the queue is drained: the next event signals at once
        la    t0, rq_hdr                ; do not block?
        ld    t1, 24(t0)                ; ...
        andi  t1, t1, 1                 ; ...
        li    a0, -3                    ; ...
        bnez  t1, rq_ans                ; ...
        ld    t1, WX_PARK(s1)           ; (one EVENT at a time)
        li    a0, -7                    ; ...
        bgez  t1, rq_ans                ; ...
        ld    s2, 16(t0)                ; its timeout
        call  os_park                   ; the request waits in the kernel
        mv    t0, a0                    ; ...
        li    a0, -7                    ; (no room: refused)
        bltz  t0, rq_ans                ; ...
        sd    t0, WX_PARK(s1)           ; ...
        la    t1, rq_tok                ; ...
        ld    t1, 0(t1)                 ; ...
        sd    t1, WX_TOK(s1)            ; ...
        sd    zero, WX_DEADL(s1)        ; ...
        beqz  s2, rq_ret                ; no timeout
        la    t1, ws_now                ; ...
        ld    t1, 0(t1)                 ; ...
        add   t1, t1, s2                ; ...
        sd    t1, WX_DEADL(s1)          ; ...
        j     rq_ret                    ; (no answer yet)

rq_destroy:                             ; ---- DESTROY
        li    a0, 0                     ; answer first (c6 must be free for the rest)
        call  rq_band                   ; ...
        call  os_reply                  ; ...
        mv    a0, s0                    ; ...
        call  wn_index                  ; ...
        call  wn_remove                 ; ...
        j     rq_ret                    ; ...

