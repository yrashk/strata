; ky_in(): the keyboard buffer came back (in c6): its bytes, one by one
ky_in:                                  ; routine entry
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = cursor
        sd    s1, 16(sp)                ; s1 = bytes left
        call  hw_key_take               ; a0 = bytes, or < 0; a1 = pointer events
        mv    s1, a0                    ; ...
        la    t0, ws_pev                ; ...
        sd    a1, 0(t0)                 ; ...
        li    t0, -2                    ; interrupted: the break key
        bne   s1, t0, ki_1              ; ...
        call  ky_ctrlc                  ; ...
        j     ki_arm                    ; ...
ki_1:   la    s0, hw_kb + 96            ; the pointer's events first
ki_p:   la    t0, ws_pev                ; ...
        ld    t1, 0(t0)                 ; ...
        beqz  t1, ki_pd                 ; ...
        addi  t1, t1, -1                ; ...
        sd    t1, 0(t0)                 ; ...
        ld    a0, 0(s0)                 ; ...
        call  ptr_event                 ; ...
        addi  s0, s0, 8                 ; ...
        j     ki_p                      ; ...
ki_pd:  bgtz  s1, ki_2                  ; key bytes?
        la    t0, hw_kb + 96            ; none, after pointer events (s0 moved): not
        bne   s0, t0, ki_arm            ;   the end of the input
        la    t0, ws_eofs               ; the end of the console's input: quit
        la    t0, ws_eofs               ; ...
        li    t1, 16                    ; ...
        sd    t1, 0(t0)                 ; ...
        call  ky_quit                   ; ...
        j     ki_ret                    ; (and listen no more)
ki_2:   li    t0, 32                    ; (at most what we asked for)
        ble   s1, t0, ki_3              ; ...
        mv    s1, t0                    ; ...
ki_3:   la    s0, hw_kb + 64            ; ...
ki_l:   beqz  s1, ki_arm                ; all handled
        lbu   a0, 0(s0)                 ; ...
        call  ky_byte                   ; ...
        addi  s0, s0, 1                 ; ...
        addi  s1, s1, -1                ; ...
        j     ki_l                      ; ...
ki_arm: la    t0, ws_wait               ; listen again, unless a pause was asked for
        ld    t0, 0(t0)                 ; ...
        bnez  t0, ki_ret                ; ...
        la    t0, ws_quit               ; (or we are quitting: no read is left at tty)
        ld    t0, 0(t0)                 ; ...
        bnez  t0, ki_ret                ; ...
        la    t0, ws_eofs               ; (or the input has ended)
        ld    t0, 0(t0)                 ; ...
        li    t1, 16                    ; ...
        bge   t0, t1, ki_ret            ; ...
        call  hw_key_arm                ; ...
ki_ret: ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; ky_byte(a0 = byte): the keyboard's bytes as keys (keys.s, spec 1.4): only
; the Alt forms (ESC [ 27 ; 3 ; code ~, ESC [ 1 ; 3 X) are our bindings; an
; ESC followed by a key is the Esc key and then that key
; frame: 0 ra, 8 the byte, 16 give it again?, 24 a1, 32 a3, 40 a cursor
ky_byte:                                ; routine entry
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    a0, 8(sp)                 ; the byte
        la    t6, ws_eofs               ; 0x04 for ever is the end of a script's input
        li    t0, 4                     ; ...
        beq   a0, t0, kb_eof            ; ...
        sd    zero, 0(t6)               ; ...
        j     kb_st                     ; ...
kb_eof: ld    t1, 0(t6)                 ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, 0(t6)                 ; ...
        li    t0, 16                    ; ...
        blt   t1, t0, kb_st             ; ...
        call  ky_quit                   ; sixteen in a row: quit
        j     kb_ret                    ; ...
kb_st:  ld    a0, 8(sp)                 ; the byte: what key is it?
        call  kp_byte                   ; ...
        sd    a2, 16(sp)                ; ...
        sd    a1, 24(sp)                ; ...
        sd    a3, 32(sp)                ; ...
        li    t0, KP_KEY                ; ...
        beq   a0, t0, kb_plain          ; ...
        li    t0, KP_ESC                ; ...
        beq   a0, t0, kb_esc            ; ...
        li    t0, KP_ALT                ; ...
        beq   a0, t0, kb_alt            ; ...
        li    t0, KP_AKEY               ; ...
        beq   a0, t0, kb_akey           ; ...
        li    t0, KP_CSI                ; ...
        beq   a0, t0, kb_csi            ; ...
        la    t0, kp_st                 ; nothing yet: an ESC?
        ld    t0, 0(t0)                 ; ...
        li    t1, 1                     ; ...
        bne   t0, t1, kb_ret            ; ...
        la    t0, ws_now                ; (when: with nothing after it, the Esc key)
        ld    t1, 0(t0)                 ; ...
        sd    t1, ws_esct - ws_now(t0)  ; ...
        la    t0, ws_anim               ; (the tick must look soon)
        li    t1, 1                     ; ...
        sd    t1, 0(t0)                 ; ...
        j     kb_ret                    ; ...
kb_plain:
        call  help_eat                  ; the help takes the first key
        bnez  a0, kb_ret                ; ...
        ld    a0, 24(sp)                ; ...
        li    t2, 3                     ; Ctrl-C
        bne   a0, t2, kb_p1             ; ...
        call  ky_ctrlc                  ; ...
        j     kb_ret                    ; ...
kb_p1:  la    t1, m_pal_open            ; the palette takes the keys while open
        ld    t1, 0(t1)                 ; ...
        beqz  t1, kb_p2                 ; ...
        call  pa_key                    ; ...
        j     kb_ret                    ; ...
kb_p2:  call  ky_focus                  ; the focused window
        j     kb_ret                    ; ...
kb_esc: call  ky_esc                    ; ---- the Esc key, then the byte after it
        j     kb_again                  ; ...
kb_alt: ld    a0, 24(sp)                ; ---- Alt+ a character
        li    t2, 'W'                   ; (Alt+Shift+W, the scripts' pause, even then)
        beq   a0, t2, kb_e5             ; ...
        call  help_eat                  ; the help takes the first key
        bnez  a0, kb_ret                ; ...
        ld    a0, 24(sp)                ; ...
        li    t2, ' '                   ; Alt+Space or Alt+P: the palette
        beq   a0, t2, kb_pal            ; ...
        ori   t1, a0, 0x20              ; (p or P)
        li    t2, 'p'                   ; ...
        bne   t1, t2, kb_e3             ; ...
kb_pal: call  pa_toggle                 ; ...
        j     kb_ret                    ; ...
kb_e3:  li    t2, 'Q'                   ; Alt+Shift+Q: quit
        bne   a0, t2, kb_e4             ; ...
        call  ky_quit                   ; ...
        j     kb_ret                    ; ...
kb_e4:  li    t2, 'H'                   ; Alt+Shift+H: halt the machine
        bne   a0, t2, kb_e6             ; ...
        la    t0, ws_quit               ; (at once, with the screen as it is: the
        li    t1, 2                     ;   kernel stops every process)
        sd    t1, 0(t0)                 ; ...
        j     ws_stop                   ; (does not return)
kb_e5:  la    t0, ws_wait               ; Alt+Shift+W: no keyboard for a second
        ld    t1, 0(t0)                 ; (after the pause already asked for, if any)
        la    t2, ws_now                ; ...
        ld    t2, 0(t2)                 ; ...
        bgeu  t1, t2, kb_w1             ; ...
        mv    t1, t2                    ; ...
kb_w1:  li    t2, 1000000               ; ...
        add   t1, t1, t2                ; ...
        sd    t1, 0(t0)                 ; ...
        j     kb_ret                    ; ...
kb_e6:  li    t2, '?'                   ; Alt+?: the key help
        bne   a0, t2, kb_e6b            ; ...
        la    t0, m_help                ; ...
        li    t1, 1                     ; ...
        sd    t1, 0(t0)                 ; ...
        call  dmg_all                   ; ...
        j     kb_ret                    ; ...
kb_e6b: la    t1, m_pal_open            ; (the rest: not while the palette is open)
        ld    t1, 0(t1)                 ; ...
        bnez  t1, kb_ret                ; ...
        li    t2, 'q'                   ; Alt+Q: close
        bne   a0, t2, kb_e7             ; ...
        call  ky_close                  ; ...
        j     kb_ret                    ; ...
kb_e7:  li    t2, 13                    ; Alt+Enter (13, or 10): a terminal
        beq   a0, t2, kb_e7b            ; ...
        li    t2, '\n'                  ; ...
        bne   a0, t2, kb_e8             ; ...
kb_e7b: call  pa_term                   ; ...
        j     kb_ret                    ; ...
kb_e8:  addi  t1, a0, -'1'              ; Alt+1..4: focus
        li    t2, 4                     ; ...
        bgeu  t1, t2, kb_e9             ; ...
        mv    a0, t1                    ; ...
        call  wn_focus                  ; ...
        j     kb_ret                    ; ...
kb_e9:  li    a0, 0x1b                  ; any other Alt+key belongs to the client, as
        call  ky_focus                  ;   terminals send it: ESC, then the key
        ld    a0, 24(sp)                ; ...
        call  ky_utf8                   ; ...
        j     kb_ret                    ; ...
kb_akey:
        call  help_eat                  ; ---- Alt+ an arrow, Home, End, Delete ...
        bnez  a0, kb_ret                ; (the help takes the first key)
        ld    a0, 24(sp)                ; the final byte
        addi  t0, a0, -'A'              ; an arrow?
        li    t1, 4                     ; ...
        bgeu  t0, t1, kb_ak2            ; ...
        la    t1, m_focus               ; Alt+arrow: focus to the next / previous tile
        ld    t1, 0(t1)                 ; ...
        la    t2, m_nwin                ; ...
        ld    t2, 0(t2)                 ; ...
        beqz  t2, kb_ret                ; ...
        li    t3, 'C'                   ; right / down: next
        beq   a0, t3, kb_nx             ; ...
        li    t3, 'B'                   ; ...
        beq   a0, t3, kb_nx             ; ...
        add   t1, t1, t2                ; left / up: previous
        addi  t1, t1, -1                ; ...
        j     kb_fm                     ; ...
kb_nx:  addi  t1, t1, 1                 ; ...
kb_fm:  remu  a0, t1, t2                ; ...
        call  wn_focus                  ; ...
        j     kb_ret                    ; ...
kb_ak2: la    t1, m_pal_open            ; the others: not while the palette is open
        ld    t1, 0(t1)                 ; ...
        bnez  t1, kb_ret                ; ...
        li    a0, 0x1b                  ; the client gets the key without Alt:
        call  ky_focus                  ;   ESC [, the number for ~, the final byte
        li    a0, '['                   ; ...
        call  ky_focus                  ; ...
        sd    zero, 40(sp)              ; ...
        ld    t0, 24(sp)                ; ...
        li    t1, '~'                   ; ...
        bne   t0, t1, kb_ak4            ; ...
kb_ak3: ld    t0, 40(sp)                ; the number: kp_raw up to ";"
        la    t1, kp_raw                ; ...
        add   t1, t1, t0                ; ...
        lbu   a0, 0(t1)                 ; ...
        li    t2, ';'                   ; ...
        beq   a0, t2, kb_ak4            ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, 40(sp)                ; ...
        call  ky_focus                  ; ...
        j     kb_ak3                    ; ...
kb_ak4: ld    a0, 24(sp)                ; ...
        call  ky_focus                  ; ...
        j     kb_ret                    ; ...
kb_csi: call  help_eat                  ; ---- ESC [ ...: the palette's up / down ...
        bnez  a0, kb_again              ; (the help takes the first key)
        la    t1, m_pal_open            ; ...
        ld    t1, 0(t1)                 ; ...
        beqz  t1, kb_c1                 ; ...
        ld    a0, 24(sp)                ; ...
        li    t2, 'A'                   ; up
        li    t3, -1                    ; ...
        beq   a0, t2, kb_mv             ; ...
        li    t2, 'B'                   ; down
        li    t3, 1                     ; ...
        bne   a0, t2, kb_again          ; ...
kb_mv:  mv    a0, t3                    ; ...
        call  pa_move                   ; ...
        j     kb_again                  ; ...
kb_c1:  li    a0, 0x1b                  ; ... or the client's arrows and editing keys,
        call  ky_focus                  ;   as they came
        li    a0, '['                   ; ...
        call  ky_focus                  ; ...
        sd    zero, 40(sp)              ; ...
kb_c2:  ld    t0, 40(sp)                ; ...
        la    t1, kp_nraw               ; ...
        ld    t1, 0(t1)                 ; ...
        bge   t0, t1, kb_again          ; ...
        la    t1, kp_raw                ; ...
        add   t1, t1, t0                ; ...
        lbu   a0, 0(t1)                 ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, 40(sp)                ; ...
        call  ky_focus                  ; ...
        j     kb_c2                     ; ...
kb_again:
        ld    t0, 16(sp)                ; the byte again (after an Esc, or a sequence
        bnez  t0, kb_st                 ;   cut short)?
kb_ret: ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 48                ; pop the frame
        ret                             ; done

; ky_esc(): the Esc key: it dismisses the help, closes the palette or goes to
; the focused window
ky_esc:                                 ; routine entry
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        call  help_eat                  ; the help ...
        bnez  a0, ke_r                  ; ...
        la    t0, m_pal_open            ; ... the palette ...
        ld    t0, 0(t0)                 ; ...
        beqz  t0, ke_1                  ; ...
        call  pa_toggle                 ; ...
        j     ke_r                      ; ...
ke_1:   li    a0, 0x1b                  ; ... or the focused window
        call  ky_focus                  ; ...
ke_r:   ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; ky_utf8(a0 = a character's code): its UTF-8 bytes for the focused window
ky_utf8:                                ; routine entry
        li    t0, 0x80                  ; ASCII: the byte
        bltu  a0, t0, ky_focus          ; (tail call)
        li    t0, 0x110000              ; past Unicode: nothing
        bgeu  a0, t0, ku_ret0           ; ...
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    a0, 8(sp)                 ; the code
        li    t0, 0x800                 ; two bytes?
        bgeu  a0, t0, ku_3              ; ...
        srli  a0, a0, 6                 ; 110xxxxx
        ori   a0, a0, 0xC0              ; ...
        call  ky_focus                  ; ...
        j     ku_l1                     ; ...
ku_3:   li    t0, 0x10000               ; three?
        bgeu  a0, t0, ku_4              ; ...
        srli  a0, a0, 12                ; 1110xxxx
        ori   a0, a0, 0xE0              ; ...
        call  ky_focus                  ; ...
        j     ku_l2                     ; ...
ku_4:   srli  a0, a0, 18                ; four: 11110xxx
        ori   a0, a0, 0xF0              ; ...
        call  ky_focus                  ; ...
        ld    a0, 8(sp)                 ; 10xxxxxx
        srli  a0, a0, 12                ; ...
        andi  a0, a0, 0x3F              ; ...
        ori   a0, a0, 0x80              ; ...
        call  ky_focus                  ; ...
ku_l2:  ld    a0, 8(sp)                 ; 10xxxxxx
        srli  a0, a0, 6                 ; ...
        andi  a0, a0, 0x3F              ; ...
        ori   a0, a0, 0x80              ; ...
        call  ky_focus                  ; ...
ku_l1:  ld    a0, 8(sp)                 ; 10xxxxxx
        andi  a0, a0, 0x3F              ; ...
        ori   a0, a0, 0x80              ; ...
        call  ky_focus                  ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 16                ; pop the frame
ku_ret0:
        ret                             ; done

; ptr_event(a0 = an event as the device gives it: u16 x, u16 y, u8 buttons,
; s8 wheel y, s8 wheel x, u8 kind): the cursor follows; a press dismisses the
; help, works the palette or focuses the tile under it; the window under the
; pointer gets presses, releases, drags and the wheel
; frame: 0 ra, 8 s0 (event), 16 s1 (x), 24 s2 (y), 32 s3 (pressed), 40 s4
ptr_event:                              ; routine entry
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; ...
        sd    s1, 16(sp)                ; ...
        sd    s2, 24(sp)                ; ...
        sd    s3, 32(sp)                ; ...
        sd    s4, 40(sp)                ; ...
        mv    s0, a0                    ; s0 = the event
        call  ptr_damage                ; where the cursor was
        li    t0, 0xffff                ; s1 = x, s2 = y
        and   s1, s0, t0                ; ...
        srli  s2, s0, 16                ; ...
        and   s2, s2, t0                ; ...
        la    t0, m_ptr_on              ; the cursor moves
        sd    s1, m_ptr_x - m_ptr_on(t0) ; ...
        sd    s2, m_ptr_y - m_ptr_on(t0) ; ...
        srli  t1, s0, 56                ; shown unless it left the screen
        addi  t1, t1, -PTR_K_LEAVE      ; ...
        snez  t1, t1                    ; ...
        sd    t1, 0(t0)                 ; ...
        srli  t1, s0, 32                ; s3 = buttons newly pressed
        andi  t1, t1, 0xff              ; ...
        ld    t2, m_ptr_btn - m_ptr_on(t0) ; ...
        sd    t1, m_ptr_btn - m_ptr_on(t0) ; ...
        xori  t2, t2, 0xff              ; (the buttons not held before)
        and   s3, t1, t2                ; ...
        call  ptr_damage                ; where it is now
        la    t0, m_help                ; the help: a press dismisses it
        ld    t1, 0(t0)                 ; ...
        beqz  t1, pv_1                  ; ...
        beqz  s3, pv_ret                ; ...
        sd    zero, 0(t0)               ; ...
        call  dmg_all                   ; ...
        j     pv_ret                    ; ...
pv_1:   la    t0, m_splash              ; the splash: nothing else
        ld    t0, 0(t0)                 ; ...
        bnez  t0, pv_ret                ; ...
        la    t0, m_pal_open            ; the palette?
        ld    t0, 0(t0)                 ; ...
        beqz  t0, pv_desk               ; ...
        srli  t1, s0, 56                ; the wheel moves its selection
        li    t2, PTR_K_WHEEL           ; ...
        bne   t1, t2, pv_pc             ; ...
        slli  t1, s0, 16                ; wheel y (signed)
        srai  t1, t1, 56                ; ...
        beqz  t1, pv_ret                ; ...
        li    a0, 1                     ; towards the user: down
        bltz  t1, pv_pm                 ; ...
        li    a0, -1                    ; away: up
pv_pm:  call  pa_move                   ; ...
        j     pv_ret                    ; ...
pv_pc:  andi  t0, s3, 1                 ; a left press
        beqz  t0, pv_ret                ; ...
        mv    a0, s1                    ; ...
        mv    a1, s2                    ; ...
        call  pal_click                 ; ...
        j     pv_ret                    ; ...
pv_desk:
        mv    a0, s1                    ; the tile under the pointer
        mv    a1, s2                    ; ...
        call  wn_at                     ; ...
        bltz  a0, pv_ret                ; none
        mv    s4, a0                    ; ...
        beqz  s3, pv_cl                 ; a press focuses it
        la    t0, m_focus               ; ...
        ld    t0, 0(t0)                 ; ...
        beq   t0, s4, pv_cl             ; ...
        call  wn_focus                  ; (a0 = its index)
pv_cl:  srli  t1, s0, 56                ; for its client: presses and releases, the
        li    t2, PTR_K_BUTTON          ;   wheel, and moves while a button is held
        beq   t1, t2, pv_cl2            ; ...
        li    t2, PTR_K_WHEEL           ; ...
        beq   t1, t2, pv_cl2            ; ...
        li    t2, PTR_K_MOVE            ; ...
        bne   t1, t2, pv_ret            ; ...
        la    t0, m_ptr_btn             ; ...
        ld    t0, 0(t0)                 ; ...
        beqz  t0, pv_ret                ; ...
pv_cl2: mv    a0, s4                    ; inside its client area?
        call  m_win                     ; ...
        mv    s4, a0                    ; s4 = the window
        call  lay_content               ; a0..a3 = x, y, w, h
        sub   t0, s1, a0                ; t0 = x in it
        sub   t1, s2, a1                ; t1 = y in it
        bltz  t0, pv_ret                ; ...
        bltz  t1, pv_ret                ; ...
        bge   t0, a2, pv_ret            ; ...
        bge   t1, a3, pv_ret            ; ...
        slli  t1, t1, 16                ; the value: x, y, then the device's bytes 4..7
        or    t0, t0, t1                ; ...
        srli  t2, s0, 32                ; ...
        slli  t2, t2, 32                ; ...
        or    a2, t0, t2                ; ...
        li    a1, EV_PTR                ; ...
        srli  t1, s0, 56                ; (the wheel: its own kind)
        li    t2, PTR_K_WHEEL           ; ...
        bne   t1, t2, pv_q              ; ...
        li    a1, EV_WHEEL              ; ...
pv_q:   mv    a0, s4                    ; a move after a move replaces it
        li    t2, PTR_K_MOVE            ; ...
        bne   t1, t2, pv_put            ; ...
        ld    t0, WN_CLIENT(a0)         ; ...
        ld    t3, WX_QN(t0)             ; ...
        beqz  t3, pv_put                ; ...
        li    t4, 24                    ; the last event
        mul   t4, t4, t3                ; ...
        add   t4, t0, t4                ; ...
        addi  t4, t4, WX_Q - 24         ; ...
        ld    t5, 0(t4)                 ; a pointer event ...
        li    t6, EV_PTR                ; ...
        bne   t5, t6, pv_put            ; ...
        ld    t5, 8(t4)                 ; ... that was a move
        srli  t5, t5, 56                ; ...
        bne   t5, t2, pv_put            ; ...
        sd    a2, 8(t4)                 ; ...
        j     pv_ret                    ; ...
pv_put: call  ev_put                    ; ...
pv_ret: ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        addi  sp, sp, 48                ; pop the frame
        ret                             ; done

; wn_at(a0 = x, a1 = y) -> a0 = the index of the tile there, or -1
wn_at:                                  ; routine entry
        la    t0, m_nwin                ; ...
        ld    t1, 0(t0)                 ; t1 = tiles
        la    t2, m_wins                ; t2 = record
        li    t3, 0                     ; t3 = index
wa_l:   bge   t3, t1, wa_no             ; ...
        ld    t4, WN_CUR(t2)            ; x0
        blt   a0, t4, wa_n              ; ...
        ld    t5, WN_CUR + 16(t2)       ; x1
        add   t5, t4, t5                ; ...
        bge   a0, t5, wa_n              ; ...
        ld    t4, WN_CUR + 8(t2)        ; y0
        blt   a1, t4, wa_n              ; ...
        ld    t5, WN_CUR + 24(t2)       ; y1
        add   t5, t4, t5                ; ...
        bge   a1, t5, wa_n              ; ...
        mv    a0, t3                    ; this one
        ret                             ; done
wa_n:   addi  t2, t2, WN_SIZE           ; next
        addi  t3, t3, 1                 ; ...
        j     wa_l                      ; ...
wa_no:  li    a0, -1                    ; none
        ret                             ; done

; pal_click(a0 = x, a1 = y): on a program's row: run it; outside the panel:
; close the palette
pal_click:                              ; routine entry
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    a0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        call  pal_match                 ; the rows as they are
        call  pal_geom                  ; a0 = x, a1 = y, a2 = height
        ld    t0, 8(sp)                 ; the point
        ld    t1, 16(sp)                ; ...
        blt   t0, a0, pk_out            ; outside?
        addi  t2, a0, PAL_W             ; ...
        bge   t0, t2, pk_out            ; ...
        blt   t1, a1, pk_out            ; ...
        add   t2, a1, a2                ; ...
        bge   t1, t2, pk_out            ; ...
        addi  t1, t1, -50               ; the row: (y - top - 50) / row height
        sub   t1, t1, a1                ; ...
        bltz  t1, pk_r                  ; (the input line)
        li    t2, PAL_ROW               ; ...
        divu  t1, t1, t2                ; ...
        la    t2, pal_nm                ; ...
        ld    t2, 0(t2)                 ; ...
        bge   t1, t2, pk_r              ; (below the last)
        la    t2, m_pal_sel             ; select it and run it, as Enter does
        sd    t1, 0(t2)                 ; ...
        li    a0, '\n'                  ; ...
        call  pa_key                    ; ...
        j     pk_r                      ; ...
pk_out: call  pa_toggle                 ; close
pk_r:   ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; help_eat() -> a0 = 1 if the help was shown: a key (a whole Alt+key or
; escape sequence) dismisses it and goes no further
help_eat:                               ; routine entry
        la    t0, m_help                ; shown?
        ld    a0, 0(t0)                 ; ...
        beqz  a0, hx_r                  ; ...
        sd    zero, 0(t0)               ; ...
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        call  dmg_all                   ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        li    a0, 1                     ; ...
hx_r:   ret                             ; done

; ky_focus(a0 = byte): a key for the focused window
ky_focus:                               ; routine entry
        mv    a1, a0                    ; the byte
        la    t0, m_nwin                ; any window?
        ld    t0, 0(t0)                 ; ...
        beqz  t0, kf_r                  ; ...
        la    t0, m_focus               ; the focused one
        ld    t0, 0(t0)                 ; ...
        li    t1, WN_SIZE               ; ...
        mul   t0, t0, t1                ; ...
        la    a0, m_wins                ; ...
        add   a0, a0, t0                ; ...
        j     ev_key                    ; ...
kf_r:   ret                             ; done

; ky_ctrlc(): Ctrl-C: close the palette, or interrupt the focused window's
; process (a client that asked for reminders gets it as the key 0x03: a
; terminal passes the interrupt on to its shell)
ky_ctrlc:                               ; routine entry
        la    t0, m_pal_open            ; the palette?
        ld    t0, 0(t0)                 ; ...
        bnez  t0, pa_toggle             ; close it
        la    t0, m_nwin                ; any window?
        ld    t0, 0(t0)                 ; ...
        beqz  t0, kc_r                  ; ...
        la    t0, m_focus               ; the focused one
        ld    t0, 0(t0)                 ; ...
        li    t1, WN_SIZE               ; ...
        mul   t0, t0, t1                ; ...
        la    a0, m_wins                ; ...
        add   a0, a0, t0                ; ...
        ld    t1, WN_CLIENT(a0)         ; ...
        ld    t1, WX_FLAGS(t1)          ; ...
        andi  t1, t1, 1                 ; ...
        li    a1, 3                     ; (as a key)
        bnez  t1, ev_key                ; ...
        ld    a2, WN_PID(a0)            ; SIGNAL it
        li    a0, 1                     ; ...
        li    a1, OP_SIGNAL             ; ...
        j     os_call                   ; ...
kc_r:   ret                             ; done

; ky_close(): Alt+Q: the focused window's client is told, and killed if it
; has not gone T_CLOSE later
ky_close:                               ; routine entry
        la    t0, m_nwin                ; any window?
        ld    t0, 0(t0)                 ; ...
        beqz  t0, kq_r                  ; ...
        la    t0, m_focus               ; the focused one
        ld    t0, 0(t0)                 ; ...
        li    t1, WN_SIZE               ; ...
        mul   t0, t0, t1                ; ...
        la    a0, m_wins                ; ...
        add   a0, a0, t0                ; ...
ky_close1:                              ; (a0 = the window)
        ld    t1, WN_CLIENT(a0)         ; ...
        ld    t2, WX_CLOSE(t1)          ; closing already?
        bnez  t2, kq_r                  ; ...
        la    t2, ws_now                ; ...
        ld    t2, 0(t2)                 ; ...
        li    t3, T_CLOSE               ; ...
        add   t2, t2, t3                ; ...
        sd    t2, WX_CLOSE(t1)          ; ...
        li    a1, EV_CLOSE              ; ...
        li    a2, 0                     ; ...
        j     ev_put                    ; ...
kq_r:   ret                             ; done

; ky_quit(): every window closes; the loop ends when they are gone
ky_quit:                                ; routine entry
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = index
        la    t0, ws_quit               ; quitting
        li    t1, 1                     ; ...
        sd    t1, 0(t0)                 ; ...
        la    t0, m_pal_open            ; (no palette)
        sd    zero, 0(t0)               ; ...
        li    s0, 0                     ; ...
kqt_l:  la    t0, m_nwin                ; ...
        ld    t0, 0(t0)                 ; ...
        bge   s0, t0, kqt_r             ; ...
        mv    a0, s0                    ; ...
        call  m_win                     ; ...
        call  ky_close1                 ; ...
        addi  s0, s0, 1                 ; ...
        j     kqt_l                     ; ...
kqt_r:  ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 16                ; pop the frame
        ret                             ; done

