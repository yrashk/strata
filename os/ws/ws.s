; pa_toggle(): open or close the palette (the dim covers everything)
pa_toggle:                              ; routine entry
        la    t0, m_pal_open            ; flip
        ld    t1, 0(t0)                 ; ...
        xori  t1, t1, 1                 ; ...
        sd    t1, 0(t0)                 ; ...
        la    t0, m_pal_len             ; empty input
        sd    zero, 0(t0)               ; ...
        la    t0, m_pal_sel             ; ...
        sd    zero, 0(t0)               ; ...
        j     dmg_all                   ; the whole screen

; pa_key(a0 = byte): typing into the palette
pa_key:                                 ; routine entry
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        li    t0, 0x7f                  ; backspace
        beq   a0, t0, pk_bs             ; ...
        li    t0, '\t'                  ; tab: complete to the selection
        beq   a0, t0, pk_tab            ; ...
        li    t0, '\n'                  ; enter: launch
        beq   a0, t0, pk_enter          ; ...
        li    t0, 32                    ; other control bytes: ignored
        blt   a0, t0, pk_d              ; ...
        la    t0, m_pal_len             ; append (up to 24)
        ld    t1, 0(t0)                 ; ...
        li    t2, 24                    ; ...
        bge   t1, t2, pk_d              ; ...
        la    t2, m_pal_buf             ; ...
        add   t2, t2, t1                ; ...
        sb    a0, 0(t2)                 ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, 0(t0)                 ; ...
        la    t0, m_pal_sel             ; the first match
        sd    zero, 0(t0)               ; ...
        j     pk_d                      ; ...
pk_bs:  la    t0, m_pal_len             ; one fewer
        ld    t1, 0(t0)                 ; ...
        beqz  t1, pk_d                  ; ...
        addi  t1, t1, -1                ; ...
        sd    t1, 0(t0)                 ; ...
        j     pk_d                      ; ...
pk_tab: call  pal_match                 ; the selected name into the input
        call  pal_choice                ; ...
        beqz  a0, pk_d                  ; ...
        mv    a1, a0                    ; ...
        la    a0, m_pal_buf             ; ...
        li    a2, 12                    ; ...
        call  fmt_cstr                  ; ...
        la    t0, m_pal_buf             ; ...
        sub   t1, a0, t0                ; ...
        la    t0, m_pal_len             ; ...
        sd    t1, 0(t0)                 ; ...
        j     pk_d                      ; ...
pk_enter:
        call  pal_match                 ; the choice, or else what was typed
        call  pal_choice                ; a0 = a name (NUL-terminated) or 0
        bnez  a0, pk_go                 ; ...
        la    t0, m_pal_len             ; ...
        ld    t1, 0(t0)                 ; ...
        beqz  t1, pk_close              ; nothing: just close
        la    a0, m_pal_buf             ; ...
        add   t1, a0, t1                ; (terminated)
        sb    zero, 0(t1)               ; ...
pk_go:  call  pa_launch                 ; ...
pk_close:
        call  pa_toggle                 ; close
        j     pk_ret                    ; ...
pk_d:   call  pal_damage                ; the panel changed
pk_ret: ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 16                ; pop the frame
        ret                             ; done

; pa_move(a0 = +1 down / -1 up): the selection
pa_move:                                ; routine entry
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    a0, 8(sp)                 ; ...
        call  pal_match                 ; how many
        ld    a0, 8(sp)                 ; ...
        la    t0, m_pal_sel             ; ...
        ld    t1, 0(t0)                 ; ...
        add   t1, t1, a0                ; ...
        bltz  t1, pm2_r                 ; not above the first
        la    t2, pal_nm                ; not below the last
        ld    t2, 0(t2)                 ; ...
        bge   t1, t2, pm2_r             ; ...
        sd    t1, 0(t0)                 ; ...
        call  pal_damage                ; ...
pm2_r:  ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 16                ; pop the frame
        ret                             ; done

; pa_launch(a0 = command, NUL-terminated): graphics programs (term, wmandel,
; wclock, wdoom: they make their own window) are started as they are;
; anything else runs in a terminal: "term COMMAND"
pa_launch:                              ; routine entry
        la    t0, ws_cmd                ; build the command line
        lbu   t1, 0(a0)                 ; "w" + "m" / "c" / "d": wmandel, wclock, wdoom
        lbu   t2, 1(a0)                 ; ...
        li    t3, 'w'                   ; ...
        bne   t1, t3, pl_t              ; ...
        li    t3, 'm'                   ; ...
        beq   t2, t3, pl_cp             ; ...
        li    t3, 'c'                   ; ...
        beq   t2, t3, pl_cp             ; ...
        li    t3, 'd'                   ; ...
        beq   t2, t3, pl_cp             ; ...
pl_t:   li    t3, 't'                   ; "te...": term itself
        bne   t1, t3, pl_pre            ; ...
        li    t3, 'e'                   ; ...
        beq   t2, t3, pl_cp             ; ...
pl_pre: la    t1, ws_n_term             ; "term " first
        li    t2, 5                     ; ...
pl_p:   lbu   t3, 0(t1)                 ; ...
        sb    t3, 0(t0)                 ; ...
        addi  t1, t1, 1                 ; ...
        addi  t0, t0, 1                 ; ...
        addi  t2, t2, -1                ; ...
        bnez  t2, pl_p                  ; ...
pl_cp:  li    t2, 40                    ; then the command (at most 40 bytes)
pl_c:   lbu   t3, 0(a0)                 ; ...
        beqz  t3, pl_go                 ; ...
        beqz  t2, pl_go                 ; ...
        sb    t3, 0(t0)                 ; ...
        addi  a0, a0, 1                 ; ...
        addi  t0, t0, 1                 ; ...
        addi  t2, t2, -1                ; ...
        j     pl_c                      ; ...
pl_go:  la    a0, ws_cmd                ; ...
        sub   a1, t0, a0                ; ...
        j     pa_spawn                  ; ...

; pa_term(): a new terminal
pa_term:                                ; routine entry
        la    t0, ws_now                ; (no other until it has its window, or 3 s)
        ld    t1, 0(t0)                 ; ...
        li    t2, T_SPAWN               ; ...
        add   t1, t1, t2                ; ...
        sd    t1, ws_spawnt - ws_now(t0) ; ...
        la    a0, ws_n_term             ; "term"
        li    a1, 4                     ; ...
; pa_spawn(a0 = command line, a1 = its length): SPAWN it with our console
; handles (unless every tile is taken) -> a0 = pid or < 0
pa_spawn:                               ; routine entry
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    a1, 8(sp)                 ; the length
        la    t0, m_nwin                ; a tile left?
        ld    t0, 0(t0)                 ; ...
        li    t1, MAXWIN                ; ...
        li    t2, -7                    ; ...
        bge   t0, t1, ps_r              ; no
        la    t0, os_buf                ; data: ncores, three handles, the text
        sd    zero, 0(t0)               ; one thread
        la    t1, os_hd                 ; our console handles
        ld    t2, 0(t1)                 ; ...
        sd    t2, 8(t0)                 ; ...
        ld    t2, 8(t1)                 ; ...
        sd    t2, 16(t0)                ; ...
        ld    t2, 16(t1)                ; ...
        sd    t2, 24(t0)                ; ...
        addi  t0, t0, 32                ; the text
        mv    t1, a1                    ; ...
ps_c:   beqz  t1, ps_z                  ; ...
        lbu   t2, 0(a0)                 ; ...
        sb    t2, 0(t0)                 ; ...
        addi  a0, a0, 1                 ; ...
        addi  t0, t0, 1                 ; ...
        addi  t1, t1, -1                ; ...
        j     ps_c                      ; ...
ps_z:   sb    zero, 0(t0)               ; terminated
        ld    a0, 8(sp)                 ; -> the buffer
        addi  a0, a0, 33                ; ...
        call  os_put                    ; ...
        li    a0, 1                     ; proc
        li    a1, OP_SPAWN              ; ...
        li    a2, 0                     ; ...
        ld    a3, 8(sp)                 ; ...
        li    a4, 0                     ; ...
        call  os_msg                    ; a0 = pid or an error
        mv    t2, a0                    ; ...
ps_r:   mv    a0, t2                    ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 16                ; pop the frame
        ret                             ; done

