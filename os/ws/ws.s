; wn_size(a0 = window) -> a0 = width, a1 = height of the client area at its target
wn_size:                                ; routine entry
        ld    a1, WN_TO + 24(a0)        ; the tile's height ...
        addi  a1, a1, -(M_PADT + M_PADB) ; ... less the padding
        ld    a0, WN_TO + 16(a0)        ; its width ...
        addi  a0, a0, -2 * M_PADX       ; ... less the padding
        ret                             ; done

; wn_surface(a0 = window): a surface of its target size, filled with the
; panel colour: in the window's own 2 MiB, or the last 4 MiB if it is larger
; (a single full-size tile)
wn_surface:                             ; routine entry
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = window
        mv    s0, a0                    ; ...
        call  wn_size                   ; a0 = w, a1 = h
        sd    a0, WN_SURF + S_W(s0)     ; ...
        sd    a1, WN_SURF + S_H(s0)     ; ...
        slli  t0, a0, 2                 ; stride = w * 4
        sd    t0, WN_SURF + S_STRIDE(s0) ; ...
        li    t1, HW_FBCAP              ; in the framebuffer window
        sd    t1, WN_SURF + S_CAP(s0)   ; ...
        mul   t0, t0, a1                ; its bytes
        li    t1, SURF_BIG              ; (large: the big area)
        li    t2, SURF_SLOT             ; ...
        bgtu  t0, t2, ws_so             ; ...
        ld    t1, WN_CLIENT(s0)         ; its own slot: after the screen, by id
        ld    t1, WX_ID(t1)             ; ...
        addi  t1, t1, -1                ; ...
        mul   t1, t1, t2                ; ...
        li    t2, HW_SCRMAX             ; ...
        add   t1, t1, t2                ; ...
ws_so:  sd    t1, WN_SURF + S_OFF(s0)   ; ...
        addi  a0, s0, WN_SURF           ; fill it
        li    a1, 0                     ; ...
        li    a2, 0                     ; ...
        ld    a3, S_W(a0)               ; ...
        ld    a4, S_H(a0)               ; ...
        li    a5, C_PANEL               ; ...
        call  gfx_fill                  ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 16                ; pop the frame
        ret                             ; done

; wn_find(a0 = id, a1 = pid) -> a0 = that process's window with that id, or 0
wn_find:                                ; routine entry
        la    t0, m_wins                ; first window
        la    t1, m_nwin                ; how many
        ld    t1, 0(t1)                 ; ...
wf_l:   beqz  t1, wf_no                 ; none
        ld    t2, WN_PID(t0)            ; its process
        bne   t2, a1, wf_n              ; ...
        ld    t2, WN_CLIENT(t0)         ; its id
        ld    t2, WX_ID(t2)             ; ...
        beq   t2, a0, wf_yes            ; ...
wf_n:   addi  t0, t0, WN_SIZE           ; next
        addi  t1, t1, -1                ; ...
        j     wf_l                      ; ...
wf_yes: mv    a0, t0                    ; ...
        ret                             ; done
wf_no:  li    a0, 0                     ; ...
        ret                             ; done

; wn_index(a0 = window) -> a0 = its tile index
wn_index:                               ; routine entry
        la    t0, m_wins                ; ...
        sub   a0, a0, t0                ; ...
        li    t0, WN_SIZE               ; ...
        divu  a0, a0, t0                ; ...
        ret                             ; done

; wn_focus(a0 = index): move the focus (both tiles' frames change, both
; clients are told)
wn_focus:                               ; routine entry
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = the new index
        sd    s1, 16(sp)                ; s1 = a record
        mv    s0, a0                    ; ...
        la    t0, m_nwin                ; an existing tile?
        ld    t0, 0(t0)                 ; ...
        bgeu  s0, t0, wfo_r             ; ...
        la    t1, m_focus               ; the old one
        ld    a0, 0(t1)                 ; ...
        beq   a0, s0, wfo_in            ; (the same: only "focus in")
        bgeu  a0, t0, wfo_in            ; (none)
        call  m_win                     ; ...
        mv    s1, a0                    ; ...
        call  lay_damage                ; ...
        mv    a0, s1                    ; ...
        li    a1, EV_BLUR               ; ...
        li    a2, 0                     ; ...
        call  ev_put                    ; ...
wfo_in: la    t0, m_focus               ; the new one
        sd    s0, 0(t0)                 ; ...
        mv    a0, s0                    ; ...
        call  m_win                     ; ...
        mv    s1, a0                    ; ...
        call  lay_damage                ; ...
        mv    a0, s1                    ; ...
        li    a1, EV_FOCUS              ; ...
        li    a2, 0                     ; ...
        call  ev_put                    ; ...
        call  lat_stats_damage          ; the strip's window list
wfo_r:  ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; wn_remove(a0 = index): the window goes (c6 must be free: a waiting EVENT
; is answered -1 first); the others close ranks
wn_remove:                              ; routine entry
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = index
        sd    s1, 16(sp)                ; s1 = record / server state
        mv    s0, a0                    ; ...
        call  m_win                     ; ...
        ld    s1, WN_CLIENT(a0)         ; ...
        ld    a0, WX_PARK(s1)           ; a waiting EVENT?
        bltz  a0, wrm_1                 ; ...
        call  os_unpark                 ; ...
        bnez  a0, wrm_1                 ; (its owner died)
        ld    t0, WX_TOK(s1)            ; answer it: no such window
        la    t1, rq_tok                ; ...
        sd    t0, 0(t1)                 ; ...
        li    a0, -1                    ; ...
        li    a1, 0                     ; ...
        call  os_reply                  ; ...
wrm_1:  sd    zero, WX_ID(s1)           ; its state is free
        li    t0, -1                    ; ...
        sd    t0, WX_PARK(s1)           ; ...
        mv    t5, s0                    ; the later records move down one
wrm_mv: la    t0, m_nwin                ; ...
        ld    t0, 0(t0)                 ; ...
        addi  t0, t0, -1                ; ...
        bge   t5, t0, wrm_dn            ; ...
        li    t1, WN_SIZE               ; ...
        mul   t1, t1, t5                ; ...
        la    t2, m_wins                ; ...
        add   t1, t1, t2                ; ...
        li    t0, WN_SIZE / 8           ; ...
wrm_c:  ld    t2, WN_SIZE(t1)           ; ...
        sd    t2, 0(t1)                 ; ...
        addi  t1, t1, 8                 ; ...
        addi  t0, t0, -1                ; ...
        bnez  t0, wrm_c                 ; ...
        addi  t5, t5, 1                 ; ...
        j     wrm_mv                    ; ...
wrm_dn: la    t0, m_nwin                ; one fewer
        ld    t1, 0(t0)                 ; ...
        addi  t1, t1, -1                ; ...
        sd    t1, 0(t0)                 ; ...
        la    t0, m_focus               ; the focus follows its window, or stays in range
        ld    t2, 0(t0)                 ; ...
        ble   t2, s0, wrm_f1            ; (it was before the gap, or in it)
        addi  t2, t2, -1                ; ...
wrm_f1: blt   t2, t1, wrm_f2            ; ...
        addi  t2, t1, -1                ; ...
        bgez  t2, wrm_f2                ; ...
        li    t2, 0                     ; ...
wrm_f2: sd    t2, 0(t0)                 ; ...
        beqz  t1, wrm_rt                ; (no window left)
        mv    a0, t2                    ; the focused one is told
        call  m_win                     ; ...
        li    a1, EV_FOCUS              ; ...
        li    a2, 0                     ; ...
        call  ev_put                    ; ...
wrm_rt: call  lay_retile                ; everything moves
        call  dmg_all                   ; ...
        la    t0, ws_anim               ; (frames are due)
        li    t1, 1                     ; ...
        sd    t1, 0(t0)                 ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

; wn_damage(a0 = window, a1 = x, a2 = y, a3 = w, a4 = h in its surface):
; damage that part of it on the screen (clipped to the client area)
wn_damage:                              ; routine entry
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    a1, 8(sp)                 ; ...
        sd    a2, 16(sp)                ; ...
        sd    a3, 24(sp)                ; ...
        sd    a4, 32(sp)                ; ...
        call  lay_content               ; a0..a3 = the client area on the screen
        ld    t0, 8(sp)                 ; x0
        add   t0, t0, a0                ; ...
        ld    t1, 16(sp)                ; y0
        add   t1, t1, a1                ; ...
        ld    t2, 24(sp)                ; x1
        add   t2, t2, t0                ; ...
        ld    t3, 32(sp)                ; y1
        add   t3, t3, t1                ; ...
        add   t4, a0, a2                ; clip to the client area
        ble   t2, t4, wd_1              ; ...
        mv    t2, t4                    ; ...
wd_1:   add   t4, a1, a3                ; ...
        ble   t3, t4, wd_2              ; ...
        mv    t3, t4                    ; ...
wd_2:   mv    a0, t0                    ; ...
        mv    a1, t1                    ; ...
        mv    a2, t2                    ; ...
        mv    a3, t3                    ; ...
        call  dmg_add                   ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 40                ; pop the frame
        ret                             ; done

