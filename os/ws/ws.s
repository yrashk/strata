; ds_cores(): what every core runs; a core whose switch count moved pulses
ds_cores:                               ; routine entry
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = core
        sd    s1, 16(sp)                ; s1 = its record from proc
        sd    s2, 24(sp)                ; s2 = cores
        sd    s3, 32(sp)                ; s3 = its model record
        li    a0, 1                     ; CORES
        li    a1, OP_CORES              ; ...
        li    a2, 0                     ; ...
        call  os_call                   ; a0 = cores
        blez  a0, dc2_r                 ; ...
        li    t0, MAXCORE               ; ...
        ble   a0, t0, dc2_1             ; ...
        mv    a0, t0                    ; ...
dc2_1:  mv    s2, a0                    ; ...
        slli  a0, a0, 5                 ; 32 bytes each
        call  os_get                    ; ...
        la    t0, m_ncores              ; the first look: no pulses, draw every cell
        ld    t1, 0(t0)                 ; ...
        sd    s2, 0(t0)                 ; ...
        sd    t1, 40(sp)                ; (0 the first time)
        li    s0, 0                     ; ...
        la    s1, os_buf                ; ...
        la    s3, m_cores               ; ...
dc2_l:  bge   s0, s2, dc2_r             ; ...
        lbu   t0, 1(s1)                 ; the pid running there
        li    t1, 1                     ; (proc runs only because we asked it: the
        bne   t0, t1, dc2_o             ;   observer is not shown ...
        li    t0, 0                     ; ...
dc2_o:  la    t1, ws_core               ; ... and on our own core it is us who run,
        ld    t1, 0(t1)                 ;   though we wait for proc's answer just now)
        bne   t1, s0, dc2_m             ; ...
        la    t0, os_pid                ; ...
        ld    t0, 0(t0)                 ; ...
dc2_m:
        lbu   t1, 4(s1)                 ; flags: 2 = a server's core
        andi  t1, t1, 2                 ; ...
        bnez  s0, dc2_2                 ; core 0: the system core
        li    t1, CF_SYS                ; ...
dc2_2:  ld    t2, CO_PID(s3)            ; changed?
        ld    t3, CO_FLAGS(s3)          ; ...
        sd    t0, CO_PID(s3)            ; ...
        sd    t1, CO_FLAGS(s3)          ; ...
        sub   t2, t2, t0                ; ...
        sub   t3, t3, t1                ; ...
        or    t4, t2, t3                ; t4 = redraw?
        lwu   t0, 8(s1)                 ; its switch count
        slli  t1, s0, 3                 ; ...
        la    t2, ws_sw                 ; ...
        add   t2, t2, t1                ; ...
        ld    t3, 0(t2)                 ; ...
        sd    t0, 0(t2)                 ; ...
        beq   t0, t3, dc2_3             ; the same: no switch since
        ld    t5, 40(sp)                ; (the first look: no pulse)
        beqz  t5, dc2_3                 ; ...
        li    t5, PULSE_MAX             ; a pulse
        sd    t5, CO_PULSE(s3)          ; ...
        li    t4, 1                     ; ...
        la    t5, ws_anim               ; (frames are due)
        sd    t4, 0(t5)                 ; ...
dc2_3:  beqz  t4, dc2_n                 ; ...
        mv    a0, s0                    ; ...
        call  lat_cell_damage           ; ...
dc2_n:  addi  s0, s0, 1                 ; next core
        addi  s1, s1, 32                ; ...
        addi  s3, s3, CO_SIZE           ; ...
        j     dc2_l                     ; ...
dc2_r:  ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        addi  sp, sp, 48                ; pop the frame
        ret                             ; done

; ds_hue(a0 = a name's first 8 bytes) -> a0 = its colour
ds_hue:                                 ; routine entry
        la    t0, ws_hues               ; the known names
        la    t1, ws_hues_e             ; ...
dh_l:   bgeu  t0, t1, dh_o              ; not one of them
        ld    t2, 0(t0)                 ; ...
        beq   t2, a0, dh_y              ; ...
        addi  t0, t0, 16                ; ...
        j     dh_l                      ; ...
dh_y:   ld    a0, 8(t0)                 ; ...
        ret                             ; done
dh_o:   srli  t0, a0, 8                 ; by its first letters
        xor   t0, t0, a0                ; ...
        srli  t2, a0, 16                ; ...
        xor   t0, t0, t2                ; ...
        andi  t0, t0, 7                 ; ...
        slli  t0, t0, 3                 ; ...
        add   t0, t1, t0                ; ...
        ld    a0, 0(t0)                 ; ...
        ret                             ; done

; ds_procs(): the processes (names, cores, KiB moved), the time slice and
; the switch rate, the clock; windows whose process is gone are closed
ds_procs:                               ; routine entry
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = records left / index
        sd    s1, 16(sp)                ; s1 = record from proc / window
        sd    s2, 24(sp)                ; s2 = model record
        sd    s3, 32(sp)                ; s3 = count in the model
        li    a0, 1                     ; PS
        li    a1, OP_PS                 ; ...
        li    a2, 0                     ; ...
        call  os_call                   ; a0 = records
        blez  a0, dp_sch                ; ...
        li    t0, MAXPROC               ; ...
        ble   a0, t0, dp_1              ; ...
        mv    a0, t0                    ; ...
dp_1:   mv    s0, a0                    ; ...
        slli  a0, a0, 5                 ; 32 bytes each
        call  os_get                    ; ...
        la    s1, os_buf                ; ...
        la    s2, m_procs               ; ...
        li    s3, 0                     ; ...
dp_l:   beqz  s0, dp_d                  ; ...
        lbu   t0, 1(s1)                 ; state 4: a zombie, not shown
        li    t1, 4                     ; ...
        beq   t0, t1, dp_n              ; ...
        lbu   t0, 0(s1)                 ; pid
        sd    t0, PR_PID(s2)            ; ...
        lbu   t0, 2(s1)                 ; core
        sd    t0, PR_CORE(s2)           ; ...
        ld    t1, PR_PID(s2)            ; (our own core: for the lattice)
        la    t2, os_pid                ; ...
        ld    t2, 0(t2)                 ; ...
        bne   t1, t2, dp_c              ; ...
        la    t2, ws_core               ; ...
        sd    t0, 0(t2)                 ; ...
dp_c:
        lbu   t0, 4(s1)                 ; flags: 2 = a server
        srli  t0, t0, 1                 ; ...
        andi  t0, t0, 1                 ; ...
        sd    t0, PR_FLAGS(s2)          ; (PF_SRV = 1)
        lwu   t0, 12(s1)                ; KiB moved by its switches
        li    t1, 10                    ; in tenths
        mul   t0, t0, t1                ; ...
        sd    t0, PR_KIB10(s2)          ; ...
        ld    a0, 16(s1)                ; name
        sd    a0, PR_NAME(s2)           ; ...
        call  ds_hue                    ; ...
        sd    a0, PR_HUE(s2)            ; ...
        addi  s2, s2, PR_SIZE           ; ...
        addi  s3, s3, 1                 ; ...
dp_n:   addi  s1, s1, 32                ; next record
        addi  s0, s0, -1                ; ...
        j     dp_l                      ; ...
dp_d:   la    t0, m_nproc               ; ...
        sd    s3, 0(t0)                 ; ...
        li    s0, 0                     ; ---- the windows' processes
dp_w:   la    t0, m_nwin                ; ...
        ld    t0, 0(t0)                 ; ...
        bge   s0, t0, dp_sch            ; ...
        mv    a0, s0                    ; ...
        call  m_win                     ; ...
        mv    s1, a0                    ; ...
        ld    s2, WN_CLIENT(s1)         ; ...
        ld    a0, WN_PID(s1)            ; ...
        call  m_proc_by_pid             ; ...
        bnez  a0, dp_w1                 ; alive
        ld    t0, WX_CLOSE(s2)          ; gone: the window closes at the next tick
        bnez  t0, dp_wn                 ; ...
        li    t0, 1                     ; ...
        sd    t0, WX_CLOSE(s2)          ; ...
        j     dp_wn                     ; ...
dp_w1:  ld    t0, PR_CORE(a0)           ; its core and KiB figure: the tag
        ld    t1, PR_KIB10(a0)          ; ...
        ld    t2, WN_CORE(s1)           ; ...
        ld    t3, WX_KIB(s2)            ; ...
        sd    t0, WN_CORE(s1)           ; ...
        sd    t1, WX_KIB(s2)            ; ...
        sub   t0, t0, t2                ; ...
        sub   t1, t1, t3                ; ...
        or    t0, t0, t1                ; ...
        beqz  t0, dp_wn                 ; the same
        mv    a0, s1                    ; ...
        call  frame_tag_damage          ; ...
dp_wn:  addi  s0, s0, 1                 ; ...
        j     dp_w                      ; ...
dp_sch: li    a0, 1                     ; ---- SCHED: slice, switches per second
        li    a1, OP_SCHED              ; ...
        li    a2, 0                     ; (read)
        call  os_call                   ; ...
        bnez  a0, dp_clk                ; ...
        li    a0, 24                    ; ...
        call  os_get                    ; ...
        la    t0, os_buf                ; ...
        ld    t1, 0(t0)                 ; the slice in ticks = microseconds
        la    t2, m_slice               ; ...
        sd    t1, 0(t2)                 ; ...
        ld    t1, 8(t0)                 ; switches per second
        la    t2, m_swps                ; ...
        sd    t1, 0(t2)                 ; ...
dp_clk: la    t0, ws_now                ; ---- the clock: there is no calendar, so the
        ld    t0, 0(t0)                 ;   time of day is the time since boot
        li    t1, 1000000               ; ...
        divu  t0, t0, t1                ; ...
        la    t2, m_uptime              ; ...
        sd    t0, 0(t2)                 ; ...
        li    t1, 86400                 ; ...
        remu  t0, t0, t1                ; ...
        la    t2, m_clock               ; ...
        sd    t0, 0(t2)                 ; ...
        call  lat_stats_damage          ; the figures changed
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        addi  sp, sp, 40                ; pop the frame
        ret                             ; done

; ds_reap(): collect children that ended (so they do not stay zombies)
ds_reap:                                ; routine entry
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = tries left
        li    s0, 6                     ; ...
dr_l:   li    a0, 1                     ; WAIT, any child, do not block
        li    a1, OP_WAIT               ; ...
        li    a2, 0                     ; ...
        li    a3, 0                     ; ...
        li    a4, 1                     ; ...
        call  os_msg                    ; a0 = a status, -3 none ended, -1 no child
        li    t0, -1                    ; ...
        beq   a0, t0, dr_r              ; ...
        li    t0, -3                    ; ...
        beq   a0, t0, dr_r              ; ...
        addi  s0, s0, -1                ; (-2: an interrupt was remembered: again)
        bnez  s0, dr_l                  ; ...
dr_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 16                ; pop the frame
        ret                             ; done
