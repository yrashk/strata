; =============================================================================
; scene.s: the whole screen as one display list
; =============================================================================
;
; scn_build() turns the model into the display list, back to front:
;   the grid background (below the strip), the status strip (lattice.s),
;   every tile (frame.s), the command palette when it is open, the key help
;   when it is shown, and the pointer's cursor over everything (pointer.s);
;   or, while the splash runs, only the splash (splash.s).
; It is rebuilt before every commit (a few hundred items: tens of thousands
; of instructions, a small fraction of drawing even one terminal line), so
; the list is always exactly the model; damage says which pixels to draw.
; scn_frame() = build + dmg_commit: one frame.

SCN_MAX   = 160                         ; items in the scene

        .data                           ; D-LS
        .align 8                        ; items are dwords
scn_items: .space SCN_MAX * I_SIZE      ; the display list
        .text                           ; code

; scn_build() -> a0 = items, a1 = count
scn_build:                              ; routine entry
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = window index
        la    a0, scn_items             ; a new list
        li    a1, SCN_MAX               ; ...
        call  gfx_list                  ; ...
        la    t0, m_splash              ; the splash?
        ld    t0, 0(t0)                 ; ...
        beqz  t0, sb_desk               ; no
        call  splash_emit               ; yes: only the splash
        j     sb_ret                    ; ...
sb_desk:
        la    a0, gfx_h_grid            ; the grid background
        li    a1, 0                     ; ...
        li    a2, M_STRIP               ; ...
        la    t0, m_w                   ; ...
        ld    a3, 0(t0)                 ; ...
        ld    a4, m_h - m_w(t0)         ; ...
        call  gfx_add                   ; ...
        li    t0, C_BG                  ; background
        sd    t0, I_P0(a0)              ; ...
        li    t0, C_GRID                ; lines
        sd    t0, I_P1(a0)              ; ...
        li    t0, 16                    ; every 16 pixels
        sd    t0, I_P2(a0)              ; ...
        li    t0, C_GRIDX               ; crosses every 64
        sd    t0, I_P3(a0)              ; ...
        li    t0, M_GAP                 ; aligned with the tile area
        sd    t0, I_P4(a0)              ; ...
        li    t0, M_STRIP + M_GAP       ; ...
        sd    t0, I_P5(a0)              ; ...
        call  lat_emit                  ; the strip
        li    s0, 0                     ; the tiles
sb_w:   la    t0, m_nwin                ; ...
        ld    t0, 0(t0)                 ; ...
        bge   s0, t0, sb_pal            ; ...
        mv    a0, s0                    ; its record
        call  m_win                     ; ...
        la    t0, m_focus               ; focused?
        ld    t0, 0(t0)                 ; ...
        sub   a1, t0, s0                ; ...
        seqz  a1, a1                    ; ...
        call  frame_emit                ; ...
        addi  s0, s0, 1                 ; next
        j     sb_w                      ; ...
sb_pal: la    t0, m_pal_open            ; the palette?
        ld    t0, 0(t0)                 ; ...
        beqz  t0, sb_hp                 ; no
        call  pal_emit                  ; yes
sb_hp:  call  help_emit                 ; the help, if shown
        call  cur_emit                  ; the cursor, on top
sb_ret: la    a0, scn_items             ; the list
        call  gfx_count                 ; ...
        mv    a1, a0                    ; ...
        la    a0, scn_items             ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 16                ; pop the frame
        ret                             ; done

; scn_frame() -> a0 = 1 if a frame was presented
scn_frame:                              ; routine entry
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        la    t0, dmg_n                 ; any damage?
        ld    t0, 0(t0)                 ; ...
        li    a0, 0                     ; (no: no frame)
        beqz  t0, sf_ret                ; ...
        call  scn_build                 ; the scene
        call  dmg_commit                ; draw the damage, PRESENT
sf_ret: ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done
