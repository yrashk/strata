; =============================================================================
; lattice.s: the status strip: the core lattice, the windows, the figures
; =============================================================================
;
; The top M_STRIP rows are the machine's heartbeat:
;   STRATA 0.1 | the core lattice: one cell per core, lit in the hue of the
;   process running there (dark when idle; the system core marked K; a
;   server's core carries a bright corner mark); a context switch makes a
;   cell pulse (brighter, with a halo) for PULSE_MAX frames
;   | the windows, 1..4, the focused one in amber
;   | SLICE 2.0MS  UP 0:12:44  PROC 14  SW/S 1204   21:47:03
;   (on a narrow screen the figures that would reach the window list are
;   left out, from the left: SLICE first; the clock always stays)
; lat_emit() adds the strip's items; lat_cell_damage(i) and
; lat_stats_damage() damage just a cell or the figures.

LAT_X     = 134                         ; first cell's x
LAT_Y     = 7                           ; cells' top
LAT_CW    = 24                          ; cell width
LAT_CH    = 14                          ; cell height
LAT_CG    = 4                           ; gap between cells

        .data                           ; D-LS
lat_word: .ascii "STRATA"               ; the wordmark
lat_ver:  .ascii "0.1"                  ; the version
lat_up_l: .ascii "UP"                   ; labels
lat_pr_l: .ascii "PROC"                 ; ...
lat_sw_l: .ascii "SW/S"                 ; ...
lat_sl_l: .ascii "SLICE"                ; ...
lat_ms:   .ascii "MS"                   ; the slice's unit
lat_k:    .ascii "K"                    ; the system core's mark
lat_end:                                ; (end of the strings above)
        .align 8                        ; dwords
lat_clk:  .space 16                     ; the clock, formatted
lat_up:   .space 16                     ; uptime
lat_pr:   .space 8                      ; process count
lat_sw:   .space 16                     ; switches per second
lat_sl:   .space 16                     ; the time slice
lat_num:  .space MAXCORE * 2            ; core numbers, two characters each
lat_wn:   .space MAXWIN * 12            ; window list entries: "1 TERM"
lat_wnn:  .space MAXWIN * 8             ; their lengths
lat_tmp:  .space 64                     ; scratch
        .text                           ; code

; lat_cell_x(a0 = core) -> a0 = x of its cell
lat_cell_x:                             ; routine entry
        li    t0, LAT_CW + LAT_CG       ; pitch
        mul   a0, a0, t0                ; ...
        addi  a0, a0, LAT_X             ; ...
        ret                             ; done

; lat_cell_damage(a0 = core): the cell and its halo
lat_cell_damage:                        ; routine entry
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        call  lat_cell_x                ; x
        addi  a0, a0, -2                ; halo
        li    a1, LAT_Y - 2             ; ...
        addi  a2, a0, LAT_CW + 4        ; ...
        li    a3, LAT_Y + LAT_CH + 2    ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        j     dmg_add                   ; add it

; lat_stats_damage(): the figures and the clock at the right end, and the
; window list in the middle
lat_stats_damage:                       ; routine entry
        la    t0, m_ncores              ; from the end of the lattice ...
        ld    a0, 0(t0)                 ; ...
        li    t1, LAT_CW + LAT_CG       ; ...
        mul   a0, a0, t1                ; ...
        addi  a0, a0, LAT_X + 8         ; ...
        li    a1, 0                     ; ... the strip's rows above its bottom line
        la    t0, m_w                   ; ... to the right edge
        ld    a2, 0(t0)                 ; ...
        li    a3, M_STRIP - 2           ; ...
        j     dmg_add                   ; add it

; lat_emit(): the strip's items
lat_emit:                               ; routine entry
        addi  sp, sp, -64               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = core / window index
        sd    s1, 16(sp)                ; s1 = core record / x cursor
        sd    s2, 24(sp)                ; s2 = colour
        sd    s3, 32(sp)                ; s3 = pulse / scratch
        sd    s4, 40(sp)                ; s4 = x cursor (right to left)
        ; ---- background, bottom line, wordmark
        la    a0, gfx_h_vgrad           ; a gradient ...
        li    a1, 0                     ; ... over the strip
        li    a2, 0                     ; ...
        la    t0, m_w                   ; ...
        ld    a3, 0(t0)                 ; ...
        li    a4, M_STRIP               ; ...
        call  gfx_add                   ; ...
        li    t0, 0x0D1526              ; top
        sd    t0, I_P0(a0)              ; ...
        li    t0, C_BG                  ; bottom
        sd    t0, I_P1(a0)              ; ...
        li    t0, OPAQUE                ; ...
        sd    t0, I_P2(a0)              ; ...
        li    a1, 0                     ; the bottom line
        li    a2, M_STRIP - 1           ; ...
        la    t0, m_w                   ; ...
        ld    a3, 0(t0)                 ; ...
        li    a4, 1                     ; ...
        li    a5, C_EDGE                ; teal
        li    a6, 150                   ; ...
        call  gfx_add_rect              ; ...
        li    a1, 0                     ; and a faint glow under it
        li    a2, M_STRIP               ; ...
        la    t0, m_w                   ; ...
        ld    a3, 0(t0)                 ; ...
        li    a4, 1                     ; ...
        li    a5, C_EDGE                ; ...
        li    a6, 40                    ; ...
        call  gfx_add_rect              ; ...
        li    a1, 14                    ; STRATA
        li    a2, 6                     ; ...
        la    a3, lat_word              ; ...
        li    a4, 6                     ; ...
        la    a5, font_body             ; ...
        li    a6, C_ACCENT              ; cyan
        li    a7, NOBG                  ; ...
        call  gfx_add_text              ; ...
        li    t0, 1                     ; bold
        sd    t0, I_P5(a0)              ; ...
        li    a1, 14 + 6 * 8 + 6        ; 0.1
        li    a2, 11                    ; ...
        la    a3, lat_ver               ; ...
        li    a4, 3                     ; ...
        la    a5, font_mini             ; ...
        li    a6, C_DIM                 ; ...
        li    a7, NOBG                  ; ...
        call  gfx_add_text              ; ...
        li    a1, LAT_X - 12            ; a divider before the lattice
        li    a2, 7                     ; ...
        li    a3, 1                     ; ...
        li    a4, 14                    ; ...
        li    a5, C_FAINT               ; ...
        li    a6, OPAQUE                ; ...
        call  gfx_add_rect              ; ...
        ; ---- the cells
        li    s0, 0                     ; core 0
le_cell:
        la    t0, m_ncores              ; all cores?
        ld    t0, 0(t0)                 ; ...
        bge   s0, t0, le_wins           ; ...
        slli  t0, s0, 5                 ; the core's record (CO_SIZE = 32)
        la    s1, m_cores               ; ...
        add   s1, s1, t0                ; ...
        ld    s3, CO_PULSE(s1)          ; pulse
        ld    a0, CO_PID(s1)            ; the process there
        li    s2, 0                     ; (idle: no colour)
        beqz  a0, le_idle               ; idle
        call  m_proc_by_pid             ; its record
        beqz  a0, le_idle               ; (unknown: idle)
        ld    s2, PR_HUE(a0)            ; its hue
        beqz  s3, le_lit                ; pulsing?
        mv    a0, s2                    ; brighter towards white
        li    a1, 0xFFFFFF              ; ...
        li    a2, 22                    ; by pulse * 22 / 256
        mul   a2, a2, s3                ; ...
        call  gfx_lerp                  ; ...
        mv    s2, a0                    ; ...
        mv    a0, s0                    ; and a halo
        call  lat_cell_x                ; ...
        mv    a1, a0                    ; ...
        addi  a1, a1, -2                ; ...
        li    a2, LAT_Y - 2             ; ...
        li    a3, LAT_CW + 4            ; ...
        li    a4, LAT_CH + 4            ; ...
        mv    a5, s2                    ; ...
        li    a6, 16                    ; alpha pulse * 16
        mul   a6, a6, s3                ; ...
        li    a7, 4                     ; ...
        call  gfx_add_cframe            ; ...
le_lit: mv    a0, s0                    ; the lit cell
        call  lat_cell_x                ; ...
        mv    a1, a0                    ; ...
        li    a2, LAT_Y                 ; ...
        li    a3, LAT_CW                ; ...
        li    a4, LAT_CH                ; ...
        mv    a5, s2                    ; in the hue
        li    a6, OPAQUE                ; ...
        li    a7, 3                     ; cut corners
        call  gfx_add_cpanel            ; ...
        ld    t0, CO_FLAGS(s1)          ; a server's core?
        andi  t0, t0, CF_SRV            ; ...
        beqz  t0, le_num_dark           ; no
        mv    a0, s0                    ; yes: a bright mark in the top-right corner
        call  lat_cell_x                ; ...
        addi  a1, a0, LAT_CW - 6        ; ...
        li    a2, LAT_Y + 2             ; ...
        li    a3, 3                     ; ...
        li    a4, 2                     ; ...
        li    a5, 0xFFFFFF              ; ...
        li    a6, 200                   ; ...
        call  gfx_add_rect              ; ...
le_num_dark:
        li    s3, C_BG                  ; the number in the background colour
        j     le_num                    ; ...
le_idle:
        mv    a0, s0                    ; an idle cell: dark, outlined
        call  lat_cell_x                ; ...
        mv    a1, a0                    ; ...
        li    a2, LAT_Y                 ; ...
        li    a3, LAT_CW                ; ...
        li    a4, LAT_CH                ; ...
        li    a5, C_PANEL               ; ...
        li    a6, OPAQUE                ; ...
        li    a7, 3                     ; ...
        call  gfx_add_cpanel            ; ...
        mv    a0, s0                    ; outline
        call  lat_cell_x                ; ...
        mv    a1, a0                    ; ...
        li    a2, LAT_Y                 ; ...
        li    a3, LAT_CW                ; ...
        li    a4, LAT_CH                ; ...
        li    a5, C_FAINT               ; ...
        ld    t0, CO_FLAGS(s1)          ; the system core: brighter
        andi  t0, t0, CF_SYS            ; ...
        beqz  t0, le_i2                 ; ...
        li    a5, C_EDGE                ; ...
le_i2:  li    a6, OPAQUE                ; ...
        li    a7, 3                     ; ...
        call  gfx_add_cframe            ; ...
        li    s3, C_DIM                 ; the number dim
le_num:                                 ; the core's number (K for the system core), centred
        slli  t0, s0, 1                 ; its two characters
        la    s4, lat_num               ; ...
        add   s4, s4, t0                ; ...
        li    t1, 10                    ; tens ...
        divu  t2, s0, t1                ; ...
        remu  t3, s0, t1                ; ... and units
        addi  t3, t3, '0'               ; ...
        li    a4, 1                     ; one digit ...
        mv    a3, s4                    ; ...
        sb    t3, 0(s4)                 ; ...
        beqz  t2, le_n1                 ; ... below 10
        addi  t2, t2, '0'               ; two digits
        sb    t2, 0(s4)                 ; ...
        sb    t3, 1(s4)                 ; ...
        li    a4, 2                     ; ...
le_n1:  ld    t0, CO_FLAGS(s1)          ; the system core?
        andi  t0, t0, CF_SYS            ; ...
        beqz  t0, le_n2                 ; ...
        la    a3, lat_k                 ; "K"
        li    a4, 1                     ; ...
le_n2:  sd    a3, 48(sp)                ; keep string and length
        sd    a4, 56(sp)                ; ...
        mv    a0, s0                    ; centre it: x = cell x + (CW - 6n) / 2
        call  lat_cell_x                ; ...
        ld    a4, 56(sp)                ; ...
        li    t0, 6                     ; ...
        mul   t0, t0, a4                ; ...
        li    t1, LAT_CW                ; ...
        sub   t1, t1, t0                ; ...
        srli  t1, t1, 1                 ; ...
        add   a1, a0, t1                ; ...
        li    a2, LAT_Y + 4             ; ...
        ld    a3, 48(sp)                ; ...
        la    a5, font_mini             ; ...
        mv    a6, s3                    ; colour
        li    a7, NOBG                  ; ...
        call  gfx_add_text              ; ...
        addi  s0, s0, 1                 ; next core
        j     le_cell                   ; continue
        ; ---- the windows: "1 TERM", focused in amber
le_wins:
        mv    a0, s0                    ; x after the lattice
        call  lat_cell_x                ; ...
        addi  s1, a0, 20                ; s1 = x cursor
        mv    a1, s1                    ; a divider
        addi  a1, a1, -12               ; ...
        li    a2, 7                     ; ...
        li    a3, 1                     ; ...
        li    a4, 14                    ; ...
        li    a5, C_FAINT               ; ...
        li    a6, OPAQUE                ; ...
        call  gfx_add_rect              ; ...
        li    s0, 0                     ; window 0
le_w:   la    t0, m_nwin                ; all of them?
        ld    t0, 0(t0)                 ; ...
        bge   s0, t0, le_right          ; ...
        mv    a0, s0                    ; its record
        call  m_win                     ; ...
        mv    s3, a0                    ; ...
        li    t0, 12                    ; its entry
        mul   t0, t0, s0                ; ...
        la    a0, lat_wn                ; ...
        add   a0, a0, t0                ; ...
        sd    a0, 48(sp)                ; keep the start
        addi  a1, s0, '1'               ; the number
        call  fmt_ch                    ; ...
        li    a1, ' '                   ; ...
        call  fmt_ch                    ; ...
        addi  a1, s3, WN_NAME           ; the name
        li    a2, 8                     ; ...
        call  fmt_cstr                  ; ...
        ld    a3, 48(sp)                ; the string
        sub   a4, a0, a3                ; its length
        sd    a4, 56(sp)                ; ...
        la    t0, m_focus               ; focused?
        ld    t0, 0(t0)                 ; ...
        li    a6, C_DIM                 ; (no: dim)
        bne   t0, s0, le_wt             ; ...
        li    a6, C_FOCUS               ; yes: amber, with a bar under it
        mv    a1, s1                    ; ...
        li    a2, LAT_Y + LAT_CH - 1    ; ...
        li    t0, 6                     ; ...
        mul   a3, t0, a4                ; ...
        addi  a3, a3, -1                ; ...
        li    a4, 1                     ; ...
        li    a5, C_FOCUS               ; ...
        li    a6, 180                   ; ...
        call  gfx_add_rect              ; ...
        ld    a3, 48(sp)                ; (again)
        ld    a4, 56(sp)                ; ...
        li    a6, C_FOCUS               ; ...
le_wt:  mv    a1, s1                    ; the text
        li    a2, LAT_Y + 3             ; ...
        la    a5, font_mini             ; ...
        li    a7, NOBG                  ; ...
        call  gfx_add_text              ; ...
        ld    a4, 56(sp)                ; advance: length * 6 + 16
        li    t0, 6                     ; ...
        mul   t0, t0, a4                ; ...
        add   s1, s1, t0                ; ...
        addi  s1, s1, 16                ; ...
        addi  s0, s0, 1                 ; next window
        j     le_w                      ; continue
        ; ---- the right end, laid out right to left: clock, SW/S, PROC, UP
le_right:
        la    a0, lat_clk               ; the clock
        la    t0, m_clock               ; ...
        ld    a1, 0(t0)                 ; ...
        call  fmt_hms                   ; HH:MM:SS
        la    t0, m_w                   ; x = width - 14 - 64
        ld    s4, 0(t0)                 ; ...
        addi  s4, s4, -(14 + 64)        ; ...
        mv    a1, s4                    ; ...
        li    a2, 6                     ; ...
        la    a3, lat_clk               ; ...
        li    a4, 8                     ; ...
        la    a5, font_body             ; ...
        li    a6, C_TEXT                ; ...
        li    a7, NOBG                  ; ...
        call  gfx_add_text              ; ...
        addi  s4, s4, -22               ; a gap before the figures
        la    a0, lat_sw                ; SW/S
        la    t0, m_swps                ; ...
        ld    a1, 0(t0)                 ; ...
        li    a2, 1                     ; ...
        call  fmt_dec                   ; ...
        la    a1, lat_sw                ; ...
        sub   a2, a0, a1                ; ...
        la    a3, lat_sw_l              ; ...
        li    a4, 4                     ; ...
        call  le_pair                   ; ...
        la    a0, lat_pr                ; PROC
        la    t0, m_nproc               ; ...
        ld    a1, 0(t0)                 ; ...
        li    a2, 1                     ; ...
        call  fmt_dec                   ; ...
        la    a1, lat_pr                ; ...
        sub   a2, a0, a1                ; ...
        la    a3, lat_pr_l              ; ...
        li    a4, 4                     ; ...
        call  le_pair                   ; ...
        la    a0, lat_up                ; UP
        la    t0, m_uptime              ; ...
        ld    a1, 0(t0)                 ; ...
        call  fmt_hms                   ; ...
        la    a1, lat_up                ; ...
        sub   a2, a0, a1                ; ...
        la    a3, lat_up_l              ; ...
        li    a4, 2                     ; ...
        call  le_pair                   ; ...
        la    t0, m_slice               ; SLICE: the scheduler's time slice, "2.0MS"
        ld    a1, 0(t0)                 ; (microseconds)
        beqz  a1, le_done               ; not known: not shown
        li    t0, 100                   ; in tenths of a millisecond
        divu  a1, a1, t0                ; ...
        la    a0, lat_sl                ; ...
        call  fmt_tenths                ; ...
        la    a1, lat_ms                ; ...
        li    a2, 2                     ; ...
        call  fmt_str                   ; ...
        la    a1, lat_sl                ; ...
        sub   a2, a0, a1                ; ...
        la    a3, lat_sl_l              ; ...
        li    a4, 5                     ; ...
        call  le_pair                   ; ...
le_done:
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        addi  sp, sp, 64                ; pop the frame
        ret                             ; done

; le_pair(a1 = value, a2 = its length, a3 = label, a4 = its length): a label
; and a value ending at x = s4 (mini font), and s4 moves left past them; if
; they would reach the window list (which ends at s1), nothing is drawn and
; s4 drops to 0, so no pair after them is drawn either.
le_pair:
        add   t0, a2, a4                ; their width: 6 * (both lengths) + 5
        li    t1, 6                     ; ...
        mul   t0, t0, t1                ; ...
        addi  t0, t0, 5 + 8             ; (and a margin)
        sub   t0, s4, t0                ; where they would start
        bge   t0, s1, lp_go             ; clear of the window list
        li    s4, 0                     ; no room: none from here on
        ret                             ; ...
lp_go:  addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    a1, 8(sp)                 ; value
        sd    a2, 16(sp)                ; ...
        sd    a3, 24(sp)                ; label
        sd    a4, 32(sp)                ; ...
        li    t0, 6                     ; value x = s4 - 6 * length
        mul   t0, t0, a2                ; ...
        sub   s4, s4, t0                ; ...
        mv    a3, a1                    ; the value, bright
        mv    a4, a2                    ; ...
        mv    a1, s4                    ; ...
        li    a2, 11                    ; ...
        la    a5, font_mini             ; ...
        li    a6, C_TEXT                ; ...
        li    a7, NOBG                  ; ...
        call  gfx_add_text              ; ...
        ld    a4, 32(sp)                ; label x = s4 - 5 - 6 * length
        li    t0, 6                     ; ...
        mul   t0, t0, a4                ; ...
        sub   s4, s4, t0                ; ...
        addi  s4, s4, -5                ; ...
        mv    a1, s4                    ; the label, dim
        li    a2, 11                    ; ...
        ld    a3, 24(sp)                ; ...
        la    a5, font_mini             ; ...
        li    a6, C_DIM                 ; ...
        li    a7, NOBG                  ; ...
        call  gfx_add_text              ; ...
        addi  s4, s4, -18               ; space before the next pair
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 40                ; pop the frame
        ret                             ; done
