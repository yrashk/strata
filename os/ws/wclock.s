; =============================================================================
; wclock.s: the clock client's renderer (surface side)
; =============================================================================
;
; Big segment digits with cut ends (every unlit segment faintly visible, as
; on an instrument), a row of 60 second ticks under them, and a line of
; small text. Once a second only what changed is drawn: the digits' rect
; and the tick row, so the client DAMAGEs two small rects, not its window.
;
;   ck_draw(a0 = state, a1 = seconds of the day, a2 = uptime, a3 = full)
;       -> a0..a3 = the rect drawn (x, y, x1, y1) in surface coordinates
;
; The segment handler (ck_h_seg) is general: P0 = string of digits and
; colons, P1 = length, P2 = lit colour, P3 = unlit colour, P4 = digit
; width | height << 16 | thickness << 32 (odd), P5 = gap between characters.

CK_SURF   = 0                           ; state: the surface
CK_TXT    = 8                           ; "HH:MM:SS" (8 bytes)
CK_SUB    = 16                          ; the small line (48 bytes)
CK_SUBN   = 64                          ; its length
CK_ITEMS  = 72                          ; items: background, digits, ticks, line (4 x I_SIZE)
CK_SIZE   = 72 + 4 * I_SIZE             ; bytes of state
CK_DW     = 46                          ; digit width
CK_DH     = 86                          ; digit height
CK_T      = 9                           ; segment thickness (odd)
CK_SP     = 12                          ; gap between characters
CK_CW     = 11                          ; colon width

        .data                           ; D-LS
ck_segs:  .byte 0x3f, 0x06, 0x5b, 0x4f, 0x66 ; segments of 0..4 (bit 0 = a ... bit 6 = g)
        .byte 0x6d, 0x7d, 0x07, 0x7f, 0x6f ; segments of 5..9
ck_up_s:  .ascii "UPTIME "              ; the small line's pieces
ck_mid_s: .ascii "  \x81  VSYNC 60 HZ  \x81  1 S TIMER"
ck_end_s:                               ; (end)
        .align 8                        ; dwords
        .text                           ; code

; ck_width() -> a0 = width of "HH:MM:SS" in pixels
ck_width:                               ; routine entry
        li    a0, 6 * CK_DW + 2 * CK_CW + 7 * CK_SP ; six digits, two colons, seven gaps
        ret                             ; done

; ck_h_seg: segment digits (see above)
ck_h_seg:                               ; handler entry
        addi  sp, sp, -96               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = item
        sd    s1, 16(sp)                ; s1 = character x
        sd    s2, 24(sp)                ; s2 = characters left / cursor
        sd    s3, 32(sp)                ; s3 = row within the digit
        sd    s4, 40(sp)                ; s4 = segment mask of this character
        sd    s5, 48(sp)                ; s5 = string cursor
        sd    s6, 56(sp)                ; s6 = digit width
        sd    s7, 64(sp)                ; s7 = height
        sd    s8, 72(sp)                ; s8 = thickness / 2
        sd    a2, 80(sp)                ; the row base (the segment helpers reload it)
        mv    s0, a0                    ; ...
        ld    t0, I_Y0(s0)              ; row within the digits
        sub   s3, a1, t0                ; ...
        ld    t0, I_P4(s0)              ; geometry
        li    t1, 0xffff                ; ...
        and   s6, t0, t1                ; width
        srli  s7, t0, 16                ; height
        and   s7, s7, t1                ; ...
        srli  s8, t0, 32                ; thickness ...
        srli  s8, s8, 1                 ; ... / 2
        ld    s1, I_X0(s0)              ; first character's x
        ld    s5, I_P0(s0)              ; string
        ld    s2, I_P1(s0)              ; length
ck_ch:  beqz  s2, ck_ret                ; all drawn
        lbu   t0, 0(s5)                 ; the character
        li    t1, ':'                   ; a colon?
        beq   t0, t1, ck_colon          ; ...
        addi  t0, t0, -'0'              ; a digit's segments
        la    t1, ck_segs               ; ...
        add   t1, t1, t0                ; ...
        lbu   s4, 0(t1)                 ; ...
        ; horizontal segments a (bit 0), g (bit 6), d (bit 3) at centre rows
        mv    a0, s8                    ; a: centre row = T/2
        li    a1, 0                     ; bit 0
        call  ck_hseg                   ; ...
        srli  a0, s7, 1                 ; g: the middle
        li    a1, 6                     ; ...
        call  ck_hseg                   ; ...
        addi  a0, s7, -1                ; d: height - 1 - T/2
        sub   a0, a0, s8                ; ...
        li    a1, 3                     ; ...
        call  ck_hseg                   ; ...
        ; vertical segments: f (5) and b (1) between a and g; e (4) and c (2)
        ; between g and d
        mv    a0, s8                    ; top half: from a's centre ...
        srli  a1, s7, 1                 ; ... to g's
        li    a2, 5                     ; f, at the left
        li    a7, 0                     ; ...
        call  ck_vseg                   ; ...
        mv    a0, s8                    ; ...
        srli  a1, s7, 1                 ; ...
        li    a2, 1                     ; b, at the right
        li    a7, 1                     ; ...
        call  ck_vseg                   ; ...
        srli  a0, s7, 1                 ; bottom half: from g's centre ...
        addi  a1, s7, -1                ; ... to d's
        sub   a1, a1, s8                ; ...
        li    a2, 4                     ; e, left
        li    a7, 0                     ; ...
        call  ck_vseg                   ; ...
        srli  a0, s7, 1                 ; ...
        addi  a1, s7, -1                ; ...
        sub   a1, a1, s8                ; ...
        li    a2, 2                     ; c, right
        li    a7, 1                     ; ...
        call  ck_vseg                   ; ...
        add   s1, s1, s6                ; next character
        j     ck_next                   ; ...
ck_colon:                               ; two squares, at a third and two thirds of the height
        li    t0, 3                     ; ...
        divu  t1, s7, t0                ; ...
        sub   t2, s3, t1                ; rows from the upper dot's centre
        bgez  t2, ck_c1                 ; |.|
        neg   t2, t2                    ; ...
ck_c1:  ble   t2, s8, ck_cdot           ; within it
        slli  t1, t1, 1                 ; the lower dot
        sub   t2, s3, t1                ; ...
        bgez  t2, ck_c2                 ; ...
        neg   t2, t2                    ; ...
ck_c2:  bgt   t2, s8, ck_cskip          ; not within either
ck_cdot:
        addi  a5, s1, 1                 ; a square T wide, centred in the colon's width
        slli  a6, s8, 1                 ; ...
        addi  a6, a6, 1                 ; ...
        add   a6, a5, a6                ; ...
        ld    a7, I_P2(s0)              ; lit
        li    t6, OPAQUE                ; ...
        ld    a2, 80(sp)                ; (row base, kept below)
        call  gfx_dspan                 ; ...
ck_cskip:
        addi  s1, s1, CK_CW             ; past the colon
ck_next:
        ld    t0, I_P5(s0)              ; the gap
        add   s1, s1, t0                ; ...
        addi  s5, s5, 1                 ; next character
        addi  s2, s2, -1                ; ...
        j     ck_ch                     ; ...
ck_ret: ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        ld    s5, 48(sp)                ; ...
        ld    s6, 56(sp)                ; ...
        ld    s7, 64(sp)                ; ...
        ld    s8, 72(sp)                ; ...
        addi  sp, sp, 96                ; pop the frame
        ret                             ; done

; ck_hseg(a0 = centre row, a1 = segment bit): a horizontal segment, if
; this row is within T/2 of its centre; ends cut at 45 degrees
ck_hseg:
        sub   t0, s3, a0                ; distance from the centre row
        bgez  t0, ckh_1                 ; ...
        neg   t0, t0                    ; ...
ckh_1:  bgt   t0, s8, ckh_ret           ; not on this row
        addi  t1, t0, 2                 ; inset = distance + 2
        add   a5, s1, t1                ; from x + inset ...
        add   a6, s1, s6                ; ... to x + width - inset
        sub   a6, a6, t1                ; ...
        srl   t2, s4, a1                ; lit?
        andi  t2, t2, 1                 ; ...
        ld    a7, I_P3(s0)              ; (unlit colour)
        beqz  t2, ckh_2                 ; ...
        ld    a7, I_P2(s0)              ; lit colour
ckh_2:  li    t6, OPAQUE                ; ...
        ld    a2, 80(sp)                ; the row base (the helpers run in ck_h_seg's frame)
        j     gfx_dspan                 ; draw (returns to ck_h_seg)
ckh_ret:
        ret                             ; done

; ck_vseg(a0 = top centre row, a1 = bottom centre row, a2 = segment bit,
; a7 = 0 left / 1 right): a vertical segment, tapered at both ends
ck_vseg:
        sub   t0, s3, a0                ; distance from the top end
        sub   t1, a1, s3                ; and from the bottom end
        ble   t0, t1, ckv_1             ; the nearer
        mv    t0, t1                    ; ...
ckv_1:  addi  t0, t0, -2                ; half-width = min(T/2, distance - 2)
        bltz  t0, ckv_ret               ; too near an end: nothing on this row
        ble   t0, s8, ckv_2             ; ...
        mv    t0, s8                    ; ...
ckv_2:  add   t1, s1, s8                ; centre x: x + T/2 (left) ...
        beqz  a7, ckv_3                 ; ...
        add   t1, s1, s6                ; ... or x + width - 1 - T/2 (right)
        addi  t1, t1, -1                ; ...
        sub   t1, t1, s8                ; ...
ckv_3:  sub   a5, t1, t0                ; span = centre +- half-width
        add   a6, t1, t0                ; ...
        addi  a6, a6, 1                 ; ...
        srl   t2, s4, a2                ; lit?
        andi  t2, t2, 1                 ; ...
        ld    a7, I_P3(s0)              ; ...
        beqz  t2, ckv_4                 ; ...
        ld    a7, I_P2(s0)              ; ...
ckv_4:  li    t6, OPAQUE                ; ...
        ld    a2, 80(sp)                ; the row base
        j     gfx_dspan                 ; draw
ckv_ret:
        ret                             ; done

; ck_h_ticks: 60 second ticks. P0 = the current second. Every fifth tick is
; taller; past seconds teal, the current one amber, the rest faint.
ck_h_ticks:                             ; handler entry
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = tick
        sd    s1, 16(sp)                ; s1 = item
        sd    s2, 24(sp)                ; s2 = row within the ticks
        mv    s1, a0                    ; ...
        ld    t0, I_Y0(s1)              ; ...
        sub   s2, a1, t0                ; ...
        li    s0, 0                     ; tick 0
ckt_l:  li    t0, 60                    ; all ticks?
        bge   s0, t0, ckt_ret           ; ...
        li    t0, 5                     ; a short tick starts 4 rows down
        remu  t0, s0, t0                ; ...
        li    t1, 0                     ; ...
        beqz  t0, ckt_t                 ; (every fifth: from the top)
        li    t1, 4                     ; ...
ckt_t:  blt   s2, t1, ckt_n             ; above this tick
        ld    t0, I_P0(s1)              ; the colour by second
        li    a7, C_FAINT               ; future: faint
        blt   t0, s0, ckt_c             ; ...
        li    a7, C_EDGE                ; past: teal
        bne   t0, s0, ckt_c             ; ...
        li    a7, C_FOCUS               ; now: amber
ckt_c:  li    t0, 6                     ; x = x0 + tick * 6
        mul   t0, t0, s0                ; ...
        ld    a5, I_X0(s1)              ; ...
        add   a5, a5, t0                ; ...
        addi  a6, a5, 4                 ; 4 wide
        li    t6, OPAQUE                ; ...
        call  gfx_dspan                 ; ...
ckt_n:  addi  s0, s0, 1                 ; next tick
        j     ckt_l                     ; ...
ckt_ret:
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

; ck_draw(a0 = state, a1 = seconds of the day, a2 = uptime seconds, a3 =
; 1: the whole surface, 0: only the band that changes) -> a0..a3 = rect drawn
; frame: 0 ra, 8 s0 state, 16 s1 surface, 24 s2 digits x, 32 s3 digits y,
; 40 seconds, 48 uptime, 56 full
ck_draw:                                ; routine entry
        addi  sp, sp, -64               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; ...
        sd    s1, 16(sp)                ; ...
        sd    s2, 24(sp)                ; ...
        sd    s3, 32(sp)                ; ...
        sd    a1, 40(sp)                ; ...
        sd    a2, 48(sp)                ; ...
        sd    a3, 56(sp)                ; ...
        mv    s0, a0                    ; ...
        ld    s1, CK_SURF(s0)           ; ...
        addi  a0, s0, CK_TXT            ; the time
        call  fmt_hms                   ; ...
        addi  a0, s0, CK_SUB            ; the small line
        la    a1, ck_up_s               ; ...
        li    a2, ck_mid_s - ck_up_s    ; ...
        call  fmt_str                   ; ...
        ld    a1, 48(sp)                ; ...
        call  fmt_hms                   ; ...
        la    a1, ck_mid_s              ; ...
        li    a2, ck_end_s - ck_mid_s   ; ...
        call  fmt_str                   ; ...
        addi  t0, s0, CK_SUB            ; ...
        sub   t0, a0, t0                ; ...
        sd    t0, CK_SUBN(s0)           ; ...
        call  ck_width                  ; digits x = (W - width) / 2
        ld    t0, S_W(s1)               ; ...
        sub   s2, t0, a0                ; ...
        srai  s2, s2, 1                 ; ...
        ld    t0, S_H(s1)               ; digits y = (H - DH) / 2 - 18
        addi  s3, t0, -CK_DH            ; ...
        srai  s3, s3, 1                 ; ...
        addi  s3, s3, -18               ; ...
        addi  a0, s0, CK_ITEMS          ; the items
        li    a1, 4                     ; ...
        call  gfx_list                  ; ...
        la    a0, gfx_h_rect            ; 0: background
        li    a1, 0                     ; ...
        li    a2, 0                     ; ...
        ld    a3, S_W(s1)               ; ...
        ld    a4, S_H(s1)               ; ...
        call  gfx_add                   ; ...
        li    t0, C_PANEL               ; ...
        sd    t0, I_P0(a0)              ; ...
        li    t0, OPAQUE                ; ...
        sd    t0, I_P1(a0)              ; ...
        call  ck_width                  ; 1: the digits
        add   a3, s2, a0                ; ...
        la    a0, ck_h_seg              ; ...
        mv    a1, s2                    ; ...
        mv    a2, s3                    ; ...
        addi  a4, s3, CK_DH             ; ...
        call  gfx_add                   ; ...
        addi  t0, s0, CK_TXT            ; ...
        sd    t0, I_P0(a0)              ; ...
        li    t0, 8                     ; ...
        sd    t0, I_P1(a0)              ; ...
        li    t0, C_ACCENT              ; lit
        sd    t0, I_P2(a0)              ; ...
        li    t0, 0x0F1B2B              ; unlit: just visible
        sd    t0, I_P3(a0)              ; ...
        li    t0, CK_T                  ; geometry
        slli  t0, t0, 32                ; ...
        li    t1, CK_DH << 16 | CK_DW   ; ...
        or    t0, t0, t1                ; ...
        sd    t0, I_P4(a0)              ; ...
        li    t0, CK_SP                 ; ...
        sd    t0, I_P5(a0)              ; ...
        ld    a1, S_W(s1)               ; 2: the ticks, centred, 28 below the digits
        addi  a1, a1, -358              ; (60 ticks of 6, minus the last gap)
        srai  a1, a1, 1                 ; ...
        addi  a2, s3, CK_DH + 28        ; ...
        addi  a3, a1, 358               ; ...
        addi  a4, a2, 12                ; ...
        la    a0, ck_h_ticks            ; ...
        call  gfx_add                   ; ...
        ld    t0, 40(sp)                ; the second
        li    t1, 60                    ; ...
        remu  t0, t0, t1                ; ...
        sd    t0, I_P0(a0)              ; ...
        ld    t0, CK_SUBN(s0)           ; 3: the small line, centred, under the ticks
        li    t1, 6                     ; ...
        mul   t0, t0, t1                ; ...
        ld    a1, S_W(s1)               ; ...
        sub   a1, a1, t0                ; ...
        srai  a1, a1, 1                 ; ...
        addi  a2, s3, CK_DH + 56        ; ...
        addi  a3, s0, CK_SUB            ; ...
        ld    a4, CK_SUBN(s0)           ; ...
        la    a5, font_mini             ; ...
        li    a6, C_DIM                 ; ...
        li    a7, NOBG                  ; ...
        call  gfx_add_text              ; ...
        la    t0, gfx_rect              ; the rect: everything, or the band
        sd    zero, 0(t0)               ; ...
        ld    t1, S_W(s1)               ; ...
        sd    t1, 16(t0)                ; ...
        ld    t2, 56(sp)                ; full?
        beqz  t2, ckd_band              ; ...
        sd    zero, 8(t0)               ; ...
        ld    t1, S_H(s1)               ; ...
        sd    t1, 24(t0)                ; ...
        j     ckd_draw                  ; ...
ckd_band:
        addi  t1, s3, -2                ; from the digits' top ...
        sd    t1, 8(t0)                 ; ...
        addi  t1, s3, CK_DH + 66        ; ... to under the small line
        sd    t1, 24(t0)                ; ...
ckd_draw:
        mv    a0, s1                    ; draw
        mv    a1, t0                    ; ...
        addi  a2, s0, CK_ITEMS          ; ...
        li    a3, 4                     ; ...
        call  gfx_draw                  ; ...
        la    t0, gfx_rect              ; the rect drawn
        ld    a0, 0(t0)                 ; ...
        ld    a1, 8(t0)                 ; ...
        ld    a2, 16(t0)                ; ...
        ld    a3, 24(t0)                ; ...
        ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        addi  sp, sp, 64                ; pop the frame
        ret                             ; done
