; =============================================================================
; fake.s: the demo's data source (a pretend StrataOS)
; =============================================================================
;
; The real window server fills the model from the kernel (STATS: what each
; core runs, switches, KiB moved) and from proc (PS, INFO). This file fills
; it with a believable machine instead, deterministically (a fixed-seed
; generator, time counted in frames), so the screenshots can be reproduced:
;   12 cores: 0 the system core; 1..6 the servers proc dev fs tty pipe ws;
;   7..11 time-shared by shells, terminals, wmandel, wclock and spinners.
; fake_tick(frame) runs the pretend scheduler: on a contended core a
; context switch now and then (the cell pulses, the incoming process's KiB
; moved grows by its save area, its tile's readout is damaged), pulses
; fade, and once a second the clock, uptime and switches-per-second change.

FK_NCORE  = 12                          ; cores
FK_CLOCK0 = 21 * 3600 + 47 * 60 + 3     ; the clock at frame 0: 21:47:03
FK_UP0    = 12 * 60 + 41                ; uptime at frame 0: 0:12:41
FQ_N      = 3                           ; run-queue slots per core

        .data                           ; D-LS
        .align 8                        ; dwords
fk_seed:  .dword 0x2545F4914F6CDD1D     ; the generator's state
fk_sw:    .dword 0                      ; switches this second
fk_lastsec: .dword -1                   ; the second last shown
fk_q:     .space FK_NCORE * 32          ; per core: count, index, pids (3)
fk_procs:                               ; pid, name, hue, core, KiB moved (tenths), switch cost (tenths), flags
        .dword 1, 0x636f7270, 0x4D9DFF, 1, 0, 0, PF_SRV          ; proc
        .dword 2, 0x766564, 0x8CC2FF, 2, 0, 0, PF_SRV            ; dev
        .dword 3, 0x7366, 0x3DF5A6, 3, 0, 0, PF_SRV              ; fs
        .dword 4, 0x797474, 0xFFD166, 4, 0, 0, PF_SRV            ; tty
        .dword 5, 0x65706970, 0xC77DFF, 5, 0, 0, PF_SRV          ; pipe
        .dword 6, 0x7377, 0x4DE1FF, 6, 0, 0, PF_SRV              ; ws
        .dword 7, 0x6873, 0x7FB8FF, 7, 1934, 96, 0               ; sh
        .dword 8, 0x6d726574, 0x5CF2C4, 7, 1482, 142, 0          ; term
        .dword 9, 0x6873, 0x7FB8FF, 8, 611, 96, 0                ; sh
        .dword 11, 0x6c65646e616d77, 0xFF6F91, 9, 2207, 188, 0   ; wmandel
        .dword 12, 0x6b636f6c6377, 0xFF9A5C, 10, 304, 64, 0      ; wclock
        .dword 13, 0x6d726574, 0x5CF2C4, 8, 1179, 142, 0         ; term
        .dword 14, 0x6e697073, 0xB48CFF, 9, 3550, 40, 0          ; spin
        .dword 15, 0x716573, 0xE6E37A, 11, 128, 32, 0            ; seq
fk_procs_e:                             ; (end of the table)
fk_qinit:                               ; run queues: core, count, pids
        .dword 7, 2, 8, 7, 0            ; core 7: term, sh
        .dword 8, 2, 13, 9, 0           ; core 8: term, sh
        .dword 9, 2, 11, 14, 0          ; core 9: wmandel, spin
        .dword 10, 2, 12, 0, 0          ; core 10: wclock, idle
        .dword 11, 2, 15, 0, 0          ; core 11: seq, idle
fk_qinit_e:                             ; (end)
        .text                           ; code

; fk_rand() -> a0 = 64 random bits (xorshift)
fk_rand:                                ; routine entry
        la    t0, fk_seed               ; state
        ld    a0, 0(t0)                 ; ...
        slli  t1, a0, 13                ; x ^= x << 13
        xor   a0, a0, t1                ; ...
        srli  t1, a0, 7                 ; x ^= x >> 7
        xor   a0, a0, t1                ; ...
        slli  t1, a0, 17                ; x ^= x << 17
        xor   a0, a0, t1                ; ...
        sd    a0, 0(t0)                 ; ...
        ret                             ; done

; fake_init(): the cores and processes
fake_init:                              ; routine entry
        la    t0, m_ncores              ; 12 cores
        li    t1, FK_NCORE              ; ...
        sd    t1, 0(t0)                 ; ...
        la    t0, m_cores               ; core 0: the system core
        li    t1, CF_SYS                ; ...
        sd    t1, CO_FLAGS(t0)          ; ...
        li    t2, 1                     ; cores 1..6: one server each
fi_srv: slli  t3, t2, 5                 ; its record
        add   t3, t0, t3                ; ...
        sd    t2, CO_PID(t3)            ; server pid = core number
        li    t1, CF_SRV                ; ...
        sd    t1, CO_FLAGS(t3)          ; ...
        addi  t2, t2, 1                 ; next
        li    t1, 7                     ; ...
        blt   t2, t1, fi_srv            ; ...
        la    t0, fk_procs              ; the process table, copied into the model
        la    t1, m_procs               ; ...
        li    t2, 0                     ; count
fi_p:   la    t3, fk_procs_e            ; all?
        bgeu  t0, t3, fi_pd             ; ...
        ld    t3, 0(t0)                 ; pid
        sd    t3, PR_PID(t1)            ; ...
        ld    t3, 8(t0)                 ; name (8 bytes)
        sd    t3, PR_NAME(t1)           ; ...
        ld    t3, 16(t0)                ; hue
        sd    t3, PR_HUE(t1)            ; ...
        ld    t3, 24(t0)                ; core
        sd    t3, PR_CORE(t1)           ; ...
        ld    t3, 32(t0)                ; KiB moved
        sd    t3, PR_KIB10(t1)          ; ...
        ld    t3, 40(t0)                ; switch cost (kept in the flags' high bits)
        slli  t3, t3, 8                 ; ...
        ld    t4, 48(t0)                ; flags
        or    t3, t3, t4                ; ...
        sd    t3, PR_FLAGS(t1)          ; ...
        addi  t0, t0, 56                ; next
        addi  t1, t1, PR_SIZE           ; ...
        addi  t2, t2, 1                 ; ...
        j     fi_p                      ; ...
fi_pd:  la    t0, m_nproc               ; ...
        sd    t2, 0(t0)                 ; ...
        la    t0, m_slice               ; the default time slice: 2 ms
        li    t1, 2000                  ; ...
        sd    t1, 0(t0)                 ; ...
        la    t0, fk_qinit              ; the run queues
fi_q:   la    t1, fk_qinit_e            ; all?
        bgeu  t0, t1, fi_ret            ; ...
        ld    t1, 0(t0)                 ; core
        slli  t2, t1, 5                 ; its queue
        la    t3, fk_q                  ; ...
        add   t3, t3, t2                ; ...
        ld    t2, 8(t0)                 ; count
        sd    t2, 0(t3)                 ; ...
        sd    zero, 8(t3)               ; index 0
        ld    t2, 16(t0)                ; pids
        sd    t2, 16(t3)                ; ...
        ld    t4, 24(t0)                ; ...
        sd    t4, 24(t3)                ; ...
        slli  t1, t1, 5                 ; the core runs the first one
        la    t4, m_cores               ; ...
        add   t4, t4, t1                ; ...
        sd    t2, CO_PID(t4)            ; ...
        addi  t0, t0, 40                ; next queue
        j     fi_q                      ; ...
fi_ret: ret                             ; done

; fake_tick(a0 = frame)
; frame: 0 ra, 8 s0 core, 16 s1 frame, 24 s2 queue
fake_tick:                              ; routine entry
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; ...
        sd    s1, 16(sp)                ; ...
        sd    s2, 24(sp)                ; ...
        mv    s1, a0                    ; ...
        li    s0, 0                     ; ---- pulses fade
ft_f:   li    t0, FK_NCORE              ; ...
        bge   s0, t0, ft_sched          ; ...
        slli  t0, s0, 5                 ; the core
        la    t1, m_cores               ; ...
        add   t1, t1, t0                ; ...
        ld    t2, CO_PULSE(t1)          ; pulsing?
        beqz  t2, ft_f_n                ; ...
        addi  t2, t2, -1                ; fainter
        sd    t2, CO_PULSE(t1)          ; ...
        mv    a0, s0                    ; redraw the cell
        call  lat_cell_damage           ; ...
ft_f_n: addi  s0, s0, 1                 ; next
        j     ft_f                      ; ...
ft_sched:                               ; ---- the pretend scheduler
        li    s0, 7                     ; contended cores 7..11
ft_s:   li    t0, FK_NCORE              ; ...
        bge   s0, t0, ft_clock          ; ...
        call  fk_rand                   ; a switch now? about one frame in 9
        srli  a0, a0, 40                ; ...
        li    t0, 9                     ; ...
        remu  a0, a0, t0                ; ...
        bnez  a0, ft_s_n                ; no
        slli  t0, s0, 5                 ; the queue
        la    s2, fk_q                  ; ...
        add   s2, s2, t0                ; ...
        ld    t0, 8(s2)                 ; next index
        addi  t0, t0, 1                 ; ...
        ld    t1, 0(s2)                 ; ...
        remu  t0, t0, t1                ; ...
        sd    t0, 8(s2)                 ; ...
        slli  t0, t0, 3                 ; the pid there
        add   t0, s2, t0                ; ...
        ld    a0, 16(t0)                ; ...
        slli  t1, s0, 5                 ; the core now runs it
        la    t2, m_cores               ; ...
        add   t2, t2, t1                ; ...
        sd    a0, CO_PID(t2)            ; ...
        li    t1, PULSE_MAX             ; and pulses
        sd    t1, CO_PULSE(t2)          ; ...
        la    t1, fk_sw                 ; a switch
        ld    t2, 0(t1)                 ; ...
        addi  t2, t2, 1                 ; ...
        sd    t2, 0(t1)                 ; ...
        beqz  a0, ft_s_d                ; switched to idle: nothing moves in
        call  m_proc_by_pid             ; the incoming process ...
        beqz  a0, ft_s_d                ; ...
        ld    t0, PR_FLAGS(a0)          ; ... moved its save area in
        srli  t0, t0, 8                 ; ...
        ld    t1, PR_KIB10(a0)          ; ...
        add   t1, t1, t0                ; ...
        sd    t1, PR_KIB10(a0)          ; ...
        ld    a0, PR_PID(a0)            ; its tile's readout changed
        call  fk_win_by_pid             ; ...
        beqz  a0, ft_s_d                ; ...
        call  frame_tag_damage          ; ...
ft_s_d: mv    a0, s0                    ; redraw the cell
        call  lat_cell_damage           ; ...
ft_s_n: addi  s0, s0, 1                 ; next core
        j     ft_s                      ; ...
ft_clock:                               ; ---- the clock, once a second
        li    t0, 60                    ; seconds = frame / 60
        divu  t1, s1, t0                ; ...
        la    t2, fk_lastsec            ; a new second?
        ld    t3, 0(t2)                 ; ...
        beq   t1, t3, ft_ret            ; no
        sd    t1, 0(t2)                 ; ...
        li    t3, FK_CLOCK0             ; clock
        add   t3, t3, t1                ; ...
        la    t4, m_clock               ; ...
        sd    t3, 0(t4)                 ; ...
        li    t3, FK_UP0                ; uptime
        add   t3, t3, t1                ; ...
        la    t4, m_uptime              ; ...
        sd    t3, 0(t4)                 ; ...
        la    t2, fk_sw                 ; switches per second: this second's, scaled to a
        ld    t3, 0(t2)                 ;   10 ms scheduler tick (pretend: x 17), plus noise
        sd    zero, 0(t2)               ; ...
        li    t4, 17                    ; ...
        mul   t3, t3, t4                ; ...
        addi  t3, t3, 900               ; ...
        la    t4, m_swps                ; ...
        sd    t3, 0(t4)                 ; ...
        call  lat_stats_damage          ; the figures changed
ft_ret: ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

; fk_win_by_pid(a0 = pid) -> a0 = its window or 0
fk_win_by_pid:                          ; routine entry
        la    t0, m_wins                ; first window
        la    t1, m_nwin                ; how many
        ld    t1, 0(t1)                 ; ...
fw_l:   beqz  t1, fw_no                 ; none
        ld    t2, WN_PID(t0)            ; its pid
        beq   t2, a0, fw_yes            ; ...
        addi  t0, t0, WN_SIZE           ; next
        addi  t1, t1, -1                ; ...
        j     fw_l                      ; ...
fw_yes: mv    a0, t0                    ; ...
        ret                             ; done
fw_no:  li    a0, 0                     ; ...
        ret                             ; done
