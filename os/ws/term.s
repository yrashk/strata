; =============================================================================
; term.s: a terminal surface: character grid, the 2.6 subset, rendering
; =============================================================================
;
; The part of `term` that does not depend on the kernel: bytes in (what the
; shell writes), a character grid, and pixels out into a surface. The
; window server's demo uses it for its terminal tiles; the `term` client
; uses the same code with its own surface and the bytes from its pipe.
;
; Interpreted (spec 2.6): \n (new line, column 0), \r, \b, \t, ESC [ K,
; ESC [ n C / D, ESC [ 2 J, ESC [ H, ESC [ r ; c H, ESC [ ... m with 0, 1,
; 30-37, 90-97, 40-47 (and 39, 49). Everything else is ignored.
;
; The grid is a ring of TS_CAP rows of TS_STRIDE cells (2 bytes: character,
; attribute = fg 0..15 | bg 0..7 << 4 | 0x80 when a bg is set); TS_ROWS x
; TS_COLS of it is visible, from row TS_TOP. Scrolling moves TS_TOP: no cell
; is copied. Rows that changed are marked in TS_DIRTY (bit r = visible row
; r); term_render draws just those rows, one strip each run of them, and
; reports the pixel rows it touched so the caller can damage exactly them.
; A resize keeps the cursor's line in view (rows above it come back from
; the ring when the terminal grows). Scrollback: term_scroll moves the view
; TS_VIEW rows back into the history (the cursor is not drawn then); output
; brings it back to the bottom.

TS_COLS   = 0                           ; visible columns
TS_ROWS   = 8                           ; visible rows
TS_CX     = 16                          ; cursor column
TS_CY     = 24                          ; cursor row (visible)
TS_ATTR   = 32                          ; current attribute
TS_TOP    = 40                          ; ring row of visible row 0
TS_ESC    = 48                          ; parser state: 0 text, 1 ESC, 2 CSI
TS_NP     = 56                          ; CSI: index of the parameter being read
TS_P      = 64                          ; CSI: 4 parameters (64..95)
TS_DIRTY  = 96                          ; rows to draw (bit per visible row)
TS_CURON  = 104                         ; cursor colour (0: hidden)
TS_GRID   = 112                         ; the cells (D-LS)
TS_SURF   = 120                         ; the surface it draws into
TS_BOLD   = 128                         ; SGR 1 in effect
TS_CAP    = 136                         ; ring rows
TS_STRIDE = 144                         ; cells per ring row
TS_HIST   = 152                         ; rows of history above the view
TS_ITEM   = 160                         ; its display-list item (I_SIZE)
TS_VIEW   = 160 + I_SIZE                ; rows the view is scrolled back (0: at the bottom)
TS_SIZE   = 168 + I_SIZE                ; bytes per terminal

TA_DEF    = 7                           ; default attribute: fg 7, no bg

        .data                           ; D-LS
        .align 8                        ; words
term_pal: .word 0x2A3A50, 0xFF5C7A, 0x2EDB94, 0xF2B94B ; black red green yellow
        .word 0x3F8CFF, 0xB46CFF, 0x22B8E0, 0xCFE8FF ; blue magenta cyan white
        .word 0x5B7088, 0xFF8FA3, 0x5CF2B4, 0xFFD27A ; bright: black red green yellow
        .word 0x7FB2FF, 0xD3A0FF, 0x4DE1FF, 0xFFFFFF ; blue magenta cyan white
        .text                           ; code

; term_init(a0 = terminal, a1 = grid, a2 = ring rows, a3 = cells per ring
; row, a4 = surface): an empty terminal; size it with term_resize
term_init:                              ; routine entry
        sd    a1, TS_GRID(a0)           ; grid
        sd    a2, TS_CAP(a0)            ; ring rows
        sd    a3, TS_STRIDE(a0)         ; stride
        sd    a4, TS_SURF(a0)           ; surface
        sd    zero, TS_COLS(a0)         ; nothing visible yet
        sd    zero, TS_ROWS(a0)         ; ...
        sd    zero, TS_CX(a0)           ; cursor home
        sd    zero, TS_CY(a0)           ; ...
        sd    zero, TS_TOP(a0)          ; ...
        sd    zero, TS_ESC(a0)          ; parser idle
        sd    zero, TS_DIRTY(a0)        ; ...
        sd    zero, TS_BOLD(a0)         ; ...
        sd    zero, TS_HIST(a0)         ; ...
        sd    zero, TS_VIEW(a0)         ; ...
        li    t0, C_ACCENT              ; cursor on, in cyan
        sd    t0, TS_CURON(a0)          ; ...
        li    t0, TA_DEF                ; default colours
        sd    t0, TS_ATTR(a0)           ; ...
        mul   t0, a2, a3                ; clear every cell: spaces, default attribute
        li    t1, 0x0720                ; ' ' | TA_DEF << 8
tin_c:  beqz  t0, tin_i                 ; done
        sh    t1, 0(a1)                 ; a blank cell
        addi  a1, a1, 2                 ; next
        addi  t0, t0, -1                ; ...
        j     tin_c                     ; ...
tin_i:  addi  t0, a0, TS_ITEM           ; the item that draws the grid
        la    t1, term_h_grid           ; ...
        sd    t1, I_FN(t0)              ; ...
        sd    zero, I_X0(t0)            ; covering the whole surface
        sd    zero, I_Y0(t0)            ; ...
        li    t1, 0x7fffffff            ; ...
        sd    t1, I_X1(t0)              ; ...
        sd    t1, I_Y1(t0)              ; ...
        sd    a0, I_P0(t0)              ; the terminal
        ret                             ; done

; term_cell(a0 = terminal, a1 = visible row, a2 = column) -> a0 = cell address
term_cell:                              ; routine entry
        ld    t0, TS_TOP(a0)            ; ring row = (top + row) mod cap
        add   t0, t0, a1                ; ...
        ld    t1, TS_CAP(a0)            ; ...
        remu  t0, t0, t1                ; ...
        ld    t1, TS_STRIDE(a0)         ; times the stride
        mul   t0, t0, t1                ; ...
        add   t0, t0, a2                ; plus the column
        slli  t0, t0, 1                 ; 2 bytes a cell
        ld    t1, TS_GRID(a0)           ; ...
        add   a0, t1, t0                ; ...
        ret                             ; done

; term_vcell(a0 = terminal, a1 = row of the view, a2 = column) -> a0 = the
; cell shown there (TS_VIEW rows back)
term_vcell:                             ; routine entry
        ld    t0, TS_TOP(a0)            ; ring row = (top + cap - view + row) mod cap
        ld    t1, TS_CAP(a0)            ; ...
        add   t0, t0, t1                ; ...
        ld    t2, TS_VIEW(a0)           ; ...
        sub   t0, t0, t2                ; ...
        add   t0, t0, a1                ; ...
        remu  t0, t0, t1                ; ...
        ld    t1, TS_STRIDE(a0)         ; times the stride
        mul   t0, t0, t1                ; ...
        add   t0, t0, a2                ; plus the column
        slli  t0, t0, 1                 ; 2 bytes a cell
        ld    t1, TS_GRID(a0)           ; ...
        add   a0, t1, t0                ; ...
        ret                             ; done

; term_scroll(a0 = terminal, a1 = rows back (> 0) or forward (< 0)): move
; the view within the history -> a0 = 1 if it moved
term_scroll:                            ; routine entry
        ld    t0, TS_VIEW(a0)           ; new view, 0..TS_HIST
        add   t1, t0, a1                ; ...
        bgez  t1, tsc_1                 ; ...
        li    t1, 0                     ; ...
tsc_1:  ld    t2, TS_HIST(a0)           ; ...
        ble   t1, t2, tsc_2             ; ...
        mv    t1, t2                    ; ...
tsc_2:  sd    t1, TS_VIEW(a0)           ; ...
        sub   t0, t1, t0                ; moved?
        snez  t0, t0                    ; ...
        beqz  t0, tsc_r                 ; ...
        li    t1, -1                    ; every row is drawn again
        sd    t1, TS_DIRTY(a0)          ; ...
tsc_r:  mv    a0, t0                    ; ...
        ret                             ; done

; term_dirty(a0 = terminal, a1 = visible row): mark it
term_dirty:                             ; routine entry
        li    t0, 1                     ; bit row
        sll   t0, t0, a1                ; ...
        ld    t1, TS_DIRTY(a0)          ; ...
        or    t1, t1, t0                ; ...
        sd    t1, TS_DIRTY(a0)          ; ...
        ret                             ; done

; term_all(a0 = terminal): every row
term_all:                               ; routine entry
        li    t0, -1                    ; all bits
        sd    t0, TS_DIRTY(a0)          ; ...
        ret                             ; done

; term_clear_row(a0 = terminal, a1 = visible row, a2 = from column): blank
; to the end of the row (in the current background)
term_clear_row:                         ; routine entry
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    a0, 8(sp)                 ; terminal
        sd    a1, 16(sp)                ; row
        sd    a2, 24(sp)                ; column
        call  term_cell                 ; the first cell
        ld    t2, 8(sp)                 ; terminal
        ld    t3, TS_STRIDE(t2)         ; cells to clear: stride - column
        ld    t4, 24(sp)                ; ...
        sub   t3, t3, t4                ; ...
        ld    t4, TS_ATTR(t2)           ; blank in the current colours (fg 7)
        andi  t4, t4, 0xf0              ; ...
        ori   t4, t4, TA_DEF            ; ...
        slli  t4, t4, 8                 ; ...
        ori   t4, t4, ' '               ; ...
tcr_l:  blez  t3, tcr_d                 ; done
        sh    t4, 0(a0)                 ; blank
        addi  a0, a0, 2                 ; next
        addi  t3, t3, -1                ; ...
        j     tcr_l                     ; ...
tcr_d:  ld    a0, 8(sp)                 ; mark the row
        ld    a1, 16(sp)                ; ...
        call  term_dirty                ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

; term_newline(a0 = terminal): down a row, scrolling at the bottom
term_newline:                           ; routine entry
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    a0, 8(sp)                 ; terminal
        ld    a1, TS_CY(a0)             ; the cursor's row: its cursor goes
        call  term_dirty                ; ...
        ld    a0, 8(sp)                 ; ...
        sd    zero, TS_CX(a0)           ; column 0
        ld    t0, TS_CY(a0)             ; next row
        addi  t0, t0, 1                 ; ...
        ld    t1, TS_ROWS(a0)           ; past the bottom?
        bge   t0, t1, tnl_scroll        ; yes: scroll
        sd    t0, TS_CY(a0)             ; no: just move
        mv    a1, t0                    ; ...
        call  term_dirty                ; ...
        j     tnl_ret                   ; ...
tnl_scroll:
        ld    t0, TS_TOP(a0)            ; the ring turns one row
        addi  t0, t0, 1                 ; ...
        ld    t1, TS_CAP(a0)            ; ...
        remu  t0, t0, t1                ; ...
        sd    t0, TS_TOP(a0)            ; ...
        ld    t0, TS_HIST(a0)           ; one more row of history
        addi  t0, t0, 1                 ; (term_resize keeps it within the ring)
        ld    t1, TS_CAP(a0)            ; ...
        ld    t2, TS_ROWS(a0)           ; ...
        sub   t1, t1, t2                ; ...
        ble   t0, t1, tnl_h             ; ...
        mv    t0, t1                    ; ...
tnl_h:  sd    t0, TS_HIST(a0)           ; ...
        ld    a1, TS_ROWS(a0)           ; the new bottom row is blank
        addi  a1, a1, -1                ; ...
        li    a2, 0                     ; ...
        call  term_clear_row            ; ...
        ld    a0, 8(sp)                 ; every row moved
        call  term_all                  ; ...
tnl_ret:
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 16                ; pop the frame
        ret                             ; done

; term_write(a0 = terminal, a1 = bytes, a2 = length)
term_write:                             ; routine entry
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = terminal
        sd    s1, 16(sp)                ; s1 = cursor
        sd    s2, 24(sp)                ; s2 = bytes left
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        mv    s2, a2                    ; ...
        beqz  s2, tw_l                  ; output: the view back at the bottom
        mv    a0, s0                    ; ...
        ld    a1, TS_VIEW(s0)           ; ...
        neg   a1, a1                    ; ...
        call  term_scroll               ; ...
tw_l:   beqz  s2, tw_ret                ; done
        lbu   a1, 0(s1)                 ; a byte
        mv    a0, s0                    ; ...
        call  term_putc                 ; ...
        addi  s1, s1, 1                 ; next
        addi  s2, s2, -1                ; ...
        j     tw_l                      ; ...
tw_ret: ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

; term_putc(a0 = terminal, a1 = byte)
term_putc:                              ; routine entry
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = terminal
        sd    s1, 16(sp)                ; s1 = byte
        mv    s0, a0                    ; ...
        mv    s1, a1                    ; ...
        ld    t0, TS_ESC(s0)            ; parser state
        li    t1, 1                     ; after ESC?
        beq   t0, t1, tp_esc            ; ...
        li    t1, 2                     ; in a CSI?
        beq   t0, t1, tp_csi            ; ...
        li    t1, 0x1b                  ; ---- text: ESC
        beq   s1, t1, tp_go_esc         ; ...
        li    t1, '\n'                  ; new line
        beq   s1, t1, tp_nl             ; ...
        li    t1, '\r'                  ; carriage return
        beq   s1, t1, tp_cr             ; ...
        li    t1, 8                     ; backspace
        beq   s1, t1, tp_bs             ; ...
        li    t1, '\t'                  ; tab
        beq   s1, t1, tp_tab            ; ...
        li    t1, 32                    ; other control bytes: ignored
        blt   s1, t1, tp_ret            ; ...
        ld    t0, TS_CX(s0)             ; past the last column?
        ld    t1, TS_COLS(s0)           ; ...
        blt   t0, t1, tp_put            ; no
        mv    a0, s0                    ; yes: wrap
        call  term_newline              ; ...
tp_put: mv    a0, s0                    ; the cell under the cursor
        ld    a1, TS_CY(s0)             ; ...
        ld    a2, TS_CX(s0)             ; ...
        call  term_cell                 ; ...
        sb    s1, 0(a0)                 ; character
        ld    t0, TS_ATTR(s0)           ; attribute
        sb    t0, 1(a0)                 ; ...
        ld    t0, TS_CX(s0)             ; cursor right
        addi  t0, t0, 1                 ; ...
        sd    t0, TS_CX(s0)             ; ...
        j     tp_dirty                  ; the row changed
tp_nl:  mv    a0, s0                    ; new line
        call  term_newline              ; ...
        j     tp_ret                    ; ...
tp_cr:  sd    zero, TS_CX(s0)           ; column 0
        j     tp_dirty                  ; (the cursor moved)
tp_bs:  ld    t0, TS_CX(s0)             ; one left, not past column 0
        beqz  t0, tp_ret                ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, TS_CX(s0)             ; ...
        j     tp_dirty                  ; ...
tp_tab: ld    t0, TS_CX(s0)             ; to the next multiple of 8
        addi  t0, t0, 8                 ; ...
        srli  t0, t0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        ld    t1, TS_COLS(s0)           ; but not past the last column
        addi  t1, t1, -1                ; ...
        ble   t0, t1, tp_t2             ; ...
        mv    t0, t1                    ; ...
tp_t2:  sd    t0, TS_CX(s0)             ; ...
        j     tp_dirty                  ; ...
tp_go_esc:
        li    t0, 1                     ; ESC seen
        sd    t0, TS_ESC(s0)            ; ...
        j     tp_ret                    ; ...
tp_esc: li    t0, '['                   ; ---- after ESC: only CSI is ours
        sd    zero, TS_ESC(s0)          ; (anything else: back to text)
        bne   s1, t0, tp_ret            ; ...
        li    t0, 2                     ; CSI
        sd    t0, TS_ESC(s0)            ; ...
        sd    zero, TS_NP(s0)           ; no parameters yet
        sd    zero, TS_P(s0)            ; ...
        sd    zero, TS_P + 8(s0)        ; ...
        sd    zero, TS_P + 16(s0)       ; ...
        sd    zero, TS_P + 24(s0)       ; ...
        j     tp_ret                    ; ...
tp_csi: addi  t0, s1, -'0'              ; ---- CSI: a digit?
        li    t1, 10                    ; ...
        bgeu  t0, t1, tp_c_semi         ; no
        ld    t2, TS_NP(s0)             ; parameter = parameter * 10 + digit
        slli  t2, t2, 3                 ; ...
        add   t2, s0, t2                ; ...
        ld    t3, TS_P(t2)              ; ...
        mul   t3, t3, t1                ; ...
        add   t3, t3, t0                ; ...
        sd    t3, TS_P(t2)              ; ...
        j     tp_ret                    ; ...
tp_c_semi:
        li    t0, ';'                   ; next parameter
        bne   s1, t0, tp_final          ; ...
        ld    t0, TS_NP(s0)             ; (at most 4)
        li    t1, 3                     ; ...
        bge   t0, t1, tp_ret            ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, TS_NP(s0)             ; ...
        j     tp_ret                    ; ...
tp_final:                               ; the final byte: act
        sd    zero, TS_ESC(s0)          ; back to text afterwards
        mv    a0, s0                    ; the old cursor row will need drawing
        ld    a1, TS_CY(s0)             ; ...
        call  term_dirty                ; ...
        li    t0, 'K'                   ; erase to end of line
        beq   s1, t0, tp_K              ; ...
        li    t0, 'C'                   ; cursor right
        beq   s1, t0, tp_C              ; ...
        li    t0, 'D'                   ; cursor left
        beq   s1, t0, tp_D              ; ...
        li    t0, 'J'                   ; erase display
        beq   s1, t0, tp_J              ; ...
        li    t0, 'H'                   ; cursor position
        beq   s1, t0, tp_H              ; ...
        li    t0, 'm'                   ; colours
        beq   s1, t0, tp_m              ; ...
        j     tp_ret                    ; anything else: ignored
tp_K:   mv    a0, s0                    ; from the cursor to the end
        ld    a1, TS_CY(s0)             ; ...
        ld    a2, TS_CX(s0)             ; ...
        call  term_clear_row            ; ...
        j     tp_ret                    ; ...
tp_C:   ld    t0, TS_P(s0)              ; n, at least 1
        bnez  t0, tp_C1                 ; ...
        li    t0, 1                     ; ...
tp_C1:  ld    t1, TS_CX(s0)             ; right by n ...
        add   t1, t1, t0                ; ...
        ld    t2, TS_COLS(s0)           ; ... within the row
        addi  t2, t2, -1                ; ...
        ble   t1, t2, tp_C2             ; ...
        mv    t1, t2                    ; ...
tp_C2:  sd    t1, TS_CX(s0)             ; ...
        j     tp_dirty                  ; ...
tp_D:   ld    t0, TS_P(s0)              ; n, at least 1
        bnez  t0, tp_D1                 ; ...
        li    t0, 1                     ; ...
tp_D1:  ld    t1, TS_CX(s0)             ; left by n ...
        sub   t1, t1, t0                ; ...
        bgez  t1, tp_D2                 ; ... not past column 0
        li    t1, 0                     ; ...
tp_D2:  sd    t1, TS_CX(s0)             ; ...
        j     tp_dirty                  ; ...
tp_J:   ld    t0, TS_P(s0)              ; only 2 J: the whole screen
        li    t1, 2                     ; ...
        bne   t0, t1, tp_ret            ; ...
        sd    zero, 24(sp)              ; row 0
tp_J1:  ld    a1, 24(sp)                ; each visible row
        ld    t0, TS_ROWS(s0)           ; ...
        bge   a1, t0, tp_ret            ; ...
        mv    a0, s0                    ; blank it
        li    a2, 0                     ; ...
        call  term_clear_row            ; ...
        ld    t0, 24(sp)                ; next row
        addi  t0, t0, 1                 ; ...
        sd    t0, 24(sp)                ; ...
        j     tp_J1                     ; ...
tp_H:   ld    t0, TS_P(s0)              ; row (1-based, 0 = 1)
        addi  t0, t0, -1                ; ...
        bgez  t0, tp_H1                 ; ...
        li    t0, 0                     ; ...
tp_H1:  ld    t1, TS_ROWS(s0)           ; within the screen
        addi  t1, t1, -1                ; ...
        ble   t0, t1, tp_H2             ; ...
        mv    t0, t1                    ; ...
tp_H2:  sd    t0, TS_CY(s0)             ; ...
        ld    t0, TS_P + 8(s0)          ; column
        addi  t0, t0, -1                ; ...
        bgez  t0, tp_H3                 ; ...
        li    t0, 0                     ; ...
tp_H3:  ld    t1, TS_COLS(s0)           ; ...
        addi  t1, t1, -1                ; ...
        ble   t0, t1, tp_H4             ; ...
        mv    t0, t1                    ; ...
tp_H4:  sd    t0, TS_CX(s0)             ; ...
        j     tp_dirty                  ; ...
tp_m:   sd    zero, 24(sp)              ; ---- SGR: each parameter in turn
tp_m1:  ld    t0, 24(sp)                ; this parameter
        ld    t1, TS_NP(s0)             ; past the last?
        bgt   t0, t1, tp_ret            ; ...
        slli  t2, t0, 3                 ; its value
        add   t2, s0, t2                ; ...
        ld    t2, TS_P(t2)              ; ...
        addi  t0, t0, 1                 ; (next one after this)
        sd    t0, 24(sp)                ; ...
        ld    t3, TS_ATTR(s0)           ; t3 = attribute
        bnez  t2, tp_m_b                ; 0: reset
        li    t3, TA_DEF                ; ...
        sd    zero, TS_BOLD(s0)         ; ...
        j     tp_m_set                  ; ...
tp_m_b: li    t4, 1                     ; 1: bold (bright foreground)
        bne   t2, t4, tp_m_39           ; ...
        sd    t4, TS_BOLD(s0)           ; ...
        ori   t3, t3, 8                 ; ...
        j     tp_m_set                  ; ...
tp_m_39:
        li    t4, 39                    ; 39: default foreground
        bne   t2, t4, tp_m_49           ; ...
        andi  t3, t3, 0xf0              ; ...
        ori   t3, t3, TA_DEF            ; ...
        j     tp_m_set                  ; ...
tp_m_49:
        li    t4, 49                    ; 49: default background
        bne   t2, t4, tp_m_fg           ; ...
        andi  t3, t3, 0x0f              ; ...
        j     tp_m_set                  ; ...
tp_m_fg:
        addi  t4, t2, -30               ; 30..37: foreground
        li    t5, 8                     ; ...
        bgeu  t4, t5, tp_m_bg           ; ...
        ld    t5, TS_BOLD(s0)           ; (bright while bold)
        beqz  t5, tp_m_f2               ; ...
        ori   t4, t4, 8                 ; ...
tp_m_f2:
        andi  t3, t3, 0xf0              ; ...
        or    t3, t3, t4                ; ...
        j     tp_m_set                  ; ...
tp_m_bg:
        addi  t4, t2, -40               ; 40..47: background
        li    t5, 8                     ; ...
        bgeu  t4, t5, tp_m_br           ; ...
        andi  t3, t3, 0x0f              ; ...
        slli  t4, t4, 4                 ; ...
        or    t3, t3, t4                ; ...
        ori   t3, t3, 0x80              ; (a background is set)
        j     tp_m_set                  ; ...
tp_m_br:
        addi  t4, t2, -90               ; 90..97: bright foreground
        li    t5, 8                     ; ...
        bgeu  t4, t5, tp_m1             ; anything else: ignored
        andi  t3, t3, 0xf0              ; ...
        or    t3, t3, t4                ; ...
        ori   t3, t3, 8                 ; ...
tp_m_set:
        sd    t3, TS_ATTR(s0)           ; the new attribute
        j     tp_m1                     ; next parameter
tp_dirty:
        mv    a0, s0                    ; the cursor's row changed
        ld    a1, TS_CY(s0)             ; ...
        call  term_dirty                ; ...
tp_ret: ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

; term_resize(a0 = terminal, a1 = columns, a2 = rows): the visible size
; (clipped to the ring). Shrinking drops blank rows under the cursor first,
; then rows at the top (they go to the history); growing brings history
; rows back at the top. The cursor's line stays in view.
term_resize:                            ; routine entry
        ld    t0, TS_STRIDE(a0)         ; columns: at most the stride
        ble   a1, t0, trs_1             ; ...
        mv    a1, t0                    ; ...
trs_1:  ld    t0, TS_CAP(a0)            ; rows: at most the ring
        ble   a2, t0, trs_2             ; ...
        mv    a2, t0                    ; ...
trs_2:  sd    a1, TS_COLS(a0)           ; ...
        ld    t1, TS_ROWS(a0)           ; old rows
        sd    a2, TS_ROWS(a0)           ; ...
        ld    t2, TS_CY(a0)             ; cursor row
        ld    t5, TS_HIST(a0)           ; history rows above the view
        sub   t3, a2, t1                ; grown by t3 rows?
        bltz  t3, trs_shr               ; shrunk
        beqz  t3, trs_h                 ; neither
        beqz  t1, trs_h                 ; (first sizing: nothing to move)
        ble   t3, t5, trs_g             ; grown: bring back min(t3, history) rows
        mv    t3, t5                    ; ...
trs_g:  sub   t5, t5, t3                ; ...
        ld    t4, TS_TOP(a0)            ; top - t3, mod cap
        add   t4, t4, t0                ; ...
        sub   t4, t4, t3                ; ...
        remu  t4, t4, t0                ; ...
        sd    t4, TS_TOP(a0)            ; ...
        add   t2, t2, t3                ; the cursor moves down with its line
        sd    t2, TS_CY(a0)             ; ...
        j     trs_h                     ; ...
trs_shr:
        neg   t3, t3                    ; shrunk by t3 rows
        sub   t4, t1, t2                ; blank rows under the cursor: old - 1 - cy
        addi  t4, t4, -1                ; ...
        sub   t3, t3, t4                ; the rest come off the top
        blez  t3, trs_h                 ; (none)
        add   t5, t5, t3                ; into the history
        ld    t4, TS_TOP(a0)            ; top + t3, mod cap
        add   t4, t4, t3                ; ...
        remu  t4, t4, t0                ; ...
        sd    t4, TS_TOP(a0)            ; ...
        sub   t2, t2, t3                ; ...
        sd    t2, TS_CY(a0)             ; ...
trs_h:  sub   t4, t0, a2                ; history fits in the rest of the ring
        ble   t5, t4, trs_h2            ; ...
        mv    t5, t4                    ; ...
trs_h2: sd    t5, TS_HIST(a0)           ; ...
trs_x:  ld    t0, TS_CX(a0)             ; the cursor column within the row
        blt   t0, a1, trs_d             ; ...
        addi  t0, a1, -1                ; ...
        sd    t0, TS_CX(a0)             ; ...
trs_d:  j     term_all                  ; draw everything

; term_render(a0 = terminal) -> a0 = first pixel row drawn, a1 = past the
; last (a0 = a1: nothing). Draws the dirty rows into the surface.
term_render:                            ; routine entry
        addi  sp, sp, -64               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = terminal
        sd    s1, 16(sp)                ; s1 = row
        sd    s2, 24(sp)                ; s2 = first pixel row drawn
        sd    s3, 32(sp)                ; s3 = past the last
        mv    s0, a0                    ; ...
        li    s1, 0                     ; from row 0
        li    s2, -1                    ; nothing drawn yet
        li    s3, 0                     ; ...
trn_l:  ld    t0, TS_ROWS(s0)           ; all rows?
        bge   s1, t0, trn_done          ; ...
        ld    t1, TS_DIRTY(s0)          ; dirty?
        srl   t1, t1, s1                ; ...
        andi  t1, t1, 1                 ; ...
        bnez  t1, trn_run               ; yes: a run starts
        addi  s1, s1, 1                 ; no: next
        j     trn_l                     ; ...
trn_run:
        mv    t2, s1                    ; the run's end
trn_e:  addi  t2, t2, 1                 ; ...
        bge   t2, t0, trn_draw          ; (the last row)
        ld    t1, TS_DIRTY(s0)          ; ...
        srl   t1, t1, t2                ; ...
        andi  t1, t1, 1                 ; ...
        bnez  t1, trn_e                 ; ...
trn_draw:                               ; rows s1 .. t2 - 1: one rect
        la    t3, gfx_rect              ; the rect
        sd    zero, 0(t3)               ; full width of the surface
        slli  t4, s1, 4                 ; y0 = row * 16
        sd    t4, 8(t3)                 ; ...
        bgez  s2, trn_d1                ; first drawn?
        mv    s2, t4                    ; ...
trn_d1: ld    t5, TS_SURF(s0)           ; ...
        ld    t5, S_W(t5)               ; ...
        sd    t5, 16(t3)                ; ...
        slli  t4, t2, 4                 ; y1 ...
        ld    t5, TS_ROWS(s0)           ; ... the run ends at the last row: down to the
        bne   t2, t5, trn_d2            ;     surface's bottom (the pixels below the grid)
        ld    t5, TS_SURF(s0)           ; ...
        ld    t5, S_H(t5)               ; ...
        ble   t5, t4, trn_d2            ; ...
        mv    t4, t5                    ; ...
trn_d2: sd    t4, 24(t3)                ; ...
        mv    s3, t4                    ; ...
        mv    s1, t2                    ; continue after the run
        ld    a0, TS_SURF(s0)           ; draw
        mv    a1, t3                    ; ...
        addi  a2, s0, TS_ITEM           ; ...
        li    a3, 1                     ; ...
        call  gfx_draw                  ; ...
        j     trn_l                     ; next run
trn_done:
        sd    zero, TS_DIRTY(s0)        ; all clean
        mv    a0, s2                    ; ...
        mv    a1, s3                    ; ...
        bgez  a0, trn_r                 ; (nothing drawn: 0, 0)
        li    a0, 0                     ; ...
trn_r:  ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        addi  sp, sp, 64                ; pop the frame
        ret                             ; done

; term_h_grid: the handler drawing a row of pixels of the grid. P0 = the
; terminal. Pixel row y is text row y / 16, glyph row y mod 16. The cell
; under the cursor is drawn inverted in the cursor colour (TS_CURON).
; Columns past TS_COLS and rows past TS_ROWS are panel background.
term_h_grid:                            ; handler entry
        addi  sp, sp, -80               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = terminal
        sd    s1, 16(sp)                ; s1 = cell cursor
        sd    s2, 24(sp)                ; s2 = column
        sd    s3, 32(sp)                ; s3 = glyph table at this glyph row
        sd    s4, 40(sp)                ; s4 = cursor column on this row (-1: none)
        sd    s5, 48(sp)                ; s5 = x of the column
        sd    s6, 56(sp)                ; s6 = palette
        sd    a2, 64(sp)                ; the row base
        ld    s0, I_P0(a0)              ; the terminal
        srli  t0, a1, 4                 ; text row
        andi  t1, a1, 15                ; glyph row
        la    s3, glyphs_body           ; glyph table at this row
        add   s3, s3, t1                ; ...
        la    s6, term_pal              ; palette
        ld    t2, TS_ROWS(s0)           ; below the last row?
        bge   t0, t2, th_blank          ; yes: background
        li    s4, -1                    ; the cursor on this row?
        ld    t2, TS_CURON(s0)          ; ...
        beqz  t2, th_nc                 ; ...
        ld    t2, TS_VIEW(s0)           ; (not while scrolled back)
        bnez  t2, th_nc                 ; ...
        ld    t2, TS_CY(s0)             ; ...
        bne   t2, t0, th_nc             ; ...
        ld    s4, TS_CX(s0)             ; ...
th_nc:  srli  s2, a3, 3                 ; first column: clip x0 / 8
        mv    a0, s0                    ; its cell
        mv    a1, t0                    ; ...
        mv    a2, s2                    ; ...
        call  term_vcell                ; (as the view shows it)
        mv    s1, a0                    ; ...
        ld    a2, 64(sp)                ; the row base again
th_col: slli  s5, s2, 3                 ; x of this column
        bge   s5, a4, th_ret            ; past the clip: done
        ld    t0, TS_COLS(s0)           ; past the last column?
        bge   s2, t0, th_rest           ; yes: background to the end
        lbu   t1, 0(s1)                 ; character
        lbu   t2, 1(s1)                 ; attribute
        andi  t3, t2, 15                ; foreground
        slli  t3, t3, 2                 ; ...
        add   t3, s6, t3                ; ...
        lwu   t3, 0(t3)                 ; t3 = fg colour
        li    t4, C_PANEL               ; background: the panel ...
        andi  t5, t2, 0x80              ; ... unless one is set
        beqz  t5, th_bg                 ; ...
        srli  t4, t2, 4                 ; ...
        andi  t4, t4, 7                 ; ...
        slli  t4, t4, 2                 ; ...
        add   t4, s6, t4                ; ...
        lwu   t4, 0(t4)                 ; t4 = bg colour
th_bg:  bne   s2, s4, th_gl             ; the cursor's cell?
        li    t3, C_BG                  ; inverted: dark on the cursor colour
        ld    t4, TS_CURON(s0)          ; ...
th_gl:  addi  t1, t1, -FONT_FIRST       ; the glyph
        li    t5, FONT_COUNT            ; ...
        bltu  t1, t5, th_g2             ; ...
        li    t1, '?' - FONT_FIRST      ; ...
th_g2:  slli  t1, t1, 4                 ; 16 bytes a glyph
        add   t1, s3, t1                ; ...
        lbu   t5, 0(t1)                 ; t5 = 8 pixels
        slli  t5, t5, 56                ; bit 7 to the sign bit
        slli  t6, s5, 2                 ; t6 = address of the first pixel
        add   t6, a2, t6                ; ...
        li    a5, 8                     ; a5 = pixels left
        mv    a6, s5                    ; a6 = x
        blt   s5, a3, th_slow           ; cut by the clip?
        addi  t0, s5, 8                 ; ...
        bgt   t0, a4, th_slow           ; ...
        bnez  t5, th_fast               ; no ink in this glyph row (blank cells, the rows
        slli  t0, t4, 32                ;   above and below letters): 8 pixels of
        or    t0, t0, t4                ;   background, two at a time
        sd    t0, 0(t6)                 ; ...
        sd    t0, 8(t6)                 ; ...
        sd    t0, 16(t6)                ; ...
        sd    t0, 24(t6)                ; ...
        j     th_next                   ; next cell
th_fast:                                ; loop: one pixel
        bltz  t5, th_f_fg               ; ink?
        sw    t4, 0(t6)                 ; no: background
        j     th_f_n                    ; ...
th_f_fg:
        sw    t3, 0(t6)                 ; ink
th_f_n: slli  t5, t5, 1                 ; next bit
        addi  t6, t6, 4                 ; next pixel
        addi  a5, a5, -1                ; ...
        bnez  a5, th_fast               ; ...
        j     th_next                   ; next cell
th_slow:                                ; loop: one pixel, clipped
        blt   a6, a3, th_s_n            ; left of the clip
        bge   a6, a4, th_next           ; right of it
        mv    t0, t4                    ; background ...
        bgez  t5, th_s_w                ; ... or ink
        mv    t0, t3                    ; ...
th_s_w: sw    t0, 0(t6)                 ; ...
th_s_n: slli  t5, t5, 1                 ; next bit
        addi  t6, t6, 4                 ; next pixel
        addi  a6, a6, 1                 ; ...
        addi  a5, a5, -1                ; ...
        bnez  a5, th_slow               ; ...
th_next:
        addi  s1, s1, 2                 ; next cell
        addi  s2, s2, 1                 ; ...
        j     th_col                    ; ...
th_rest:
        mv    a5, s5                    ; background from here to the clip's end
        mv    a6, a4                    ; ...
        li    a7, C_PANEL               ; ...
        li    t6, OPAQUE                ; ...
        call  gfx_dspan                 ; ...
        j     th_ret                    ; ...
th_blank:
        mv    a5, a3                    ; the whole clip in the panel colour
        mv    a6, a4                    ; ...
        li    a7, C_PANEL               ; ...
        li    t6, OPAQUE                ; ...
        call  gfx_dspan                 ; ...
th_ret: ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        ld    s3, 32(sp)                ; ...
        ld    s4, 40(sp)                ; ...
        ld    s5, 48(sp)                ; ...
        ld    s6, 56(sp)                ; ...
        addi  sp, sp, 80                ; pop the frame
        ret                             ; done
