; =============================================================================
; wmandel.s: the Mandelbrot client's renderer (surface side)
; =============================================================================
;
; What `wmandel` draws, independent of how it gets its surface: the set,
; rendered a few rows at a time into the surface (each batch is one
; gfx_render of one item whose handler computes a row of points), so that
; the client can DAMAGE each batch as it lands. In the demo the window
; server calls it in its own loop; the real client calls it between EVENT
; polls and sends DAMAGE.
;
;   md_start(a0 = state, a1 = surface)   start a new picture at its size
;   md_step(a0 = state, a1 = rows) -> a0 = first row drawn, a1 = past the
;                                     last (a0 = a1: the picture is done)

MD_SURF   = 0                           ; state: the surface
MD_ROW    = 8                           ; next row to draw
MD_STEP   = 16                          ; distance between points (fixed point)
MD_X0     = 24                          ; cx of column 0
MD_Y0     = 32                          ; cy of row 0
MD_ITEM   = 40                          ; the item (I_SIZE)
MD_SIZE   = 40 + I_SIZE                 ; bytes of state
MD_FRAC   = 24                          ; fixed-point fraction bits
MD_MAXIT  = 120                         ; iteration limit

        .data                           ; D-LS
        .align 8                        ; words
md_pal:   .word 0x0B1A33, 0x0E2A4A, 0x103B5E, 0x125070 ; escape-time colours: deep blue ...
        .word 0x166A86, 0x1F8AA0, 0x2FAFC0, 0x4DE1FF ; ... through teal to the accent cyan ...
        .word 0x8CF0FF, 0xD8FAFF, 0xFFE9B8, 0xFFC872 ; ... to white and into amber ...
        .word 0xFFB347, 0xF08A3A, 0xC9603A, 0x8A3A48 ; ... and down to a deep rose
        .text                           ; code

; md_start(a0 = state, a1 = surface)
md_start:                               ; routine entry
        sd    a1, MD_SURF(a0)           ; the surface
        sd    zero, MD_ROW(a0)          ; from the top
        ld    t0, S_W(a1)               ; width
        ld    t1, S_H(a1)               ; height
        li    t2, 3 << MD_FRAC          ; step if the width decides: 3.0 / width
        divu  t2, t2, t0                ; ...
        li    t3, 9 << (MD_FRAC - 2)    ; step if the height decides: 2.25 / height
        divu  t3, t3, t1                ; ...
        bgeu  t2, t3, mds_s             ; the larger: all of it fits
        mv    t2, t3                    ; ...
mds_s:  sd    t2, MD_STEP(a0)           ; ...
        mul   t3, t2, t0                ; x0 = -0.75 - step * width / 2
        srai  t3, t3, 1                 ; ...
        li    t4, -3 << (MD_FRAC - 2)   ; ...
        sub   t4, t4, t3                ; ...
        sd    t4, MD_X0(a0)             ; ...
        mul   t3, t2, t1                ; y0 = -step * height / 2
        srai  t3, t3, 1                 ; ...
        neg   t3, t3                    ; ...
        sd    t3, MD_Y0(a0)             ; ...
        addi  t0, a0, MD_ITEM           ; the item: the whole surface
        la    t1, md_h_row              ; ...
        sd    t1, I_FN(t0)              ; ...
        sd    zero, I_X0(t0)            ; ...
        sd    zero, I_Y0(t0)            ; ...
        ld    t1, S_W(a1)               ; ...
        sd    t1, I_X1(t0)              ; ...
        ld    t1, S_H(a1)               ; ...
        sd    t1, I_Y1(t0)              ; ...
        sd    a0, I_P0(t0)              ; the state
        ret                             ; done

; md_step(a0 = state, a1 = rows) -> a0, a1 = the rows drawn
md_step:                                ; routine entry
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = state
        sd    s1, 16(sp)                ; s1 = first row
        sd    s2, 24(sp)                ; s2 = past the last
        mv    s0, a0                    ; ...
        ld    s1, MD_ROW(s0)            ; from the next row
        add   s2, s1, a1                ; a1 more ...
        ld    t0, MD_SURF(s0)           ; ... but not past the bottom
        ld    t0, S_H(t0)               ; ...
        ble   s2, t0, mdp_1             ; ...
        mv    s2, t0                    ; ...
mdp_1:  bge   s1, s2, mdp_ret           ; nothing left
        sd    s2, MD_ROW(s0)            ; ...
        la    t1, gfx_rect              ; the rect: those rows, full width
        sd    zero, 0(t1)               ; ...
        sd    s1, 8(t1)                 ; ...
        ld    t0, MD_SURF(s0)           ; ...
        ld    t0, S_W(t0)               ; ...
        sd    t0, 16(t1)                ; ...
        sd    s2, 24(t1)                ; ...
        ld    a0, MD_SURF(s0)           ; draw
        mv    a1, t1                    ; ...
        addi  a2, s0, MD_ITEM           ; ...
        li    a3, 1                     ; ...
        call  gfx_draw                  ; ...
mdp_ret:
        mv    a0, s1                    ; the rows
        mv    a1, s2                    ; ...
        ble   s1, s2, mdp_r2            ; (none: equal)
        mv    a1, s1                    ; ...
mdp_r2: ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

; md_h_row: the handler: a row of points. P0 = the state.
md_h_row:                               ; handler entry
        addi  sp, sp, -48               ; frame
        sd    s0, 0(sp)                 ; s0 = step
        sd    s1, 8(sp)                 ; s1 = cy
        sd    s2, 16(sp)                ; s2 = cx
        sd    s3, 24(sp)                ; s3 = pixel address
        sd    s4, 32(sp)                ; s4 = x
        sd    s5, 40(sp)                ; s5 = palette
        ld    t0, I_P0(a0)              ; the state
        ld    s0, MD_STEP(t0)           ; step
        mul   s1, a1, s0                ; cy = y0 + y * step
        ld    t1, MD_Y0(t0)             ; ...
        add   s1, s1, t1                ; ...
        mul   s2, a3, s0                ; cx of the first pixel = x0 + clip x0 * step
        ld    t1, MD_X0(t0)             ; ...
        add   s2, s2, t1                ; ...
        slli  s3, a3, 2                 ; its address
        add   s3, a2, s3                ; ...
        mv    s4, a3                    ; x
        la    s5, md_pal                ; palette
        mul   a5, s1, s1                ; a5 = cy^2 (constant along the row)
        srai  a5, a5, MD_FRAC           ; ...
mh_px:  bge   s4, a4, mh_ret            ; the row is done
        li    t3, 1 << (MD_FRAC - 2)    ; in the main cardioid? q = (cx - 1/4)^2 + cy^2
        sub   t3, s2, t3                ; ...
        mul   t4, t3, t3                ; ...
        srai  t4, t4, MD_FRAC           ; ...
        add   t4, t4, a5                ; ...
        add   t3, t4, t3                ; q (q + cx - 1/4) <= cy^2 / 4
        mul   t3, t3, t4                ; ...
        srai  t3, t3, MD_FRAC           ; ...
        srai  t5, a5, 2                 ; ...
        bge   t5, t3, mh_in             ; inside
        li    t3, 1 << MD_FRAC          ; in the period-2 bulb? (cx + 1)^2 + cy^2 <= 1/16
        add   t3, s2, t3                ; ...
        mul   t3, t3, t3                ; ...
        srai  t3, t3, MD_FRAC           ; ...
        add   t3, t3, a5                ; ...
        li    t4, 1 << (MD_FRAC - 4)    ; ...
        bge   t4, t3, mh_in             ; inside
        li    t0, 0                     ; zx
        li    t1, 0                     ; zy
        li    t2, 0                     ; iterations
        li    a6, 4 << MD_FRAC          ; escape radius squared
        li    a7, MD_MAXIT              ; limit
mh_it:  mul   t3, t0, t0                ; zx^2
        srai  t3, t3, MD_FRAC           ; ...
        mul   t4, t1, t1                ; zy^2
        srai  t4, t4, MD_FRAC           ; ...
        add   t5, t3, t4                ; |z|^2
        blt   a6, t5, mh_out            ; escaped
        mul   t1, t0, t1                ; zy = 2 zx zy + cy
        srai  t1, t1, MD_FRAC - 1       ; ...
        add   t1, t1, s1                ; ...
        sub   t0, t3, t4                ; zx = zx^2 - zy^2 + cx
        add   t0, t0, s2                ; ...
        addi  t2, t2, 1                 ; one more
        blt   t2, a7, mh_it             ; up to the limit
mh_in:  li    t3, 0x05080F              ; inside: almost black
        j     mh_put                    ; ...
mh_out: srli  t3, t2, 1                 ; escape time / 2 picks the colour ...
        li    t4, 15                    ; ... (the last one past 30)
        ble   t3, t4, mh_c              ; ...
        mv    t3, t4                    ; ...
mh_c:   slli  t3, t3, 2                 ; ...
        add   t3, s5, t3                ; ...
        lwu   t3, 0(t3)                 ; ...
mh_put: sw    t3, 0(s3)                 ; the pixel
        addi  s3, s3, 4                 ; next
        add   s2, s2, s0                ; ...
        addi  s4, s4, 1                 ; ...
        j     mh_px                     ; ...
mh_ret: ld    s0, 0(sp)                 ; restore
        ld    s1, 8(sp)                 ; ...
        ld    s2, 16(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        ld    s5, 40(sp)                ; ...
        addi  sp, sp, 48                ; pop the frame
        ret                             ; done
