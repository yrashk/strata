; =============================================================================
; keys.s: the window keyboard's bytes as keys (spec 1.4)
; =============================================================================
;
; Shared by the real `ws` and the bare-metal demo. The console's input is a
; byte stream; the window's keyboard sends Alt+key in the xterm modified-key
; forms, which a person cannot type by hand: Alt+ a character is
; ESC [ 27 ; 3 ; code ~ (code in decimal: Alt+Shift+Q is 81, Alt+Enter 13),
; Alt+ an arrow, Home or End ESC [ 1 ; 3 X, Alt+ Delete, Page Up or Down
; ESC [ n ; 3 ~. So an ESC followed by a key is the Esc key and then that
; key, whatever the timing; only an ESC with nothing after it yet is
; undecided (it may start a sequence): the caller decides it by time, and
; then clears kp_st.
;
;   kp_byte(a0 = byte) -> a0 = KP_*, a1, a3 (below); a2 = 1: this byte was
;                         not used up, give it again (after an Esc, or a
;                         sequence cut short)
;   kp_st               0 between keys, 1 after an ESC, 2 within ESC [
;   kp_raw, kp_nraw     the bytes of the last ESC [ sequence after the "["

KP_NONE   = 0                           ; nothing yet: within a sequence
KP_KEY    = 1                           ; a1 = a byte, as it came
KP_ESC    = 2                           ; the Esc key (and a2 = 1)
KP_ALT    = 3                           ; Alt+ a character: a1 = its code
KP_AKEY   = 4                           ; Alt+ a key with a sequence: a1 = its final
                                        ;   byte (A-D arrows, H F ~), a3 = the number
KP_CSI    = 5                           ; any other ESC [ sequence, in kp_raw: a1 = its
                                        ;   final byte (0: cut short, a2 = 1)
KP_RAWN   = 16                          ; the longest sequence kept

        .data                           ; D-LS
        .align 8                        ; dwords
kp_st:    .dword 0                      ; 0 between keys, 1 after ESC, 2 within ESC [
kp_nraw:  .dword 0                      ; bytes in kp_raw
kp_np:    .dword 0                      ; the parameter being read (3: too many)
kp_p:     .dword 0, 0, 0                ; the parameters
kp_raw:   .space KP_RAWN                ; the sequence after "["
        .text                           ; code

kp_byte:                                ; routine entry
        li    a2, 0                     ; used up, unless said otherwise
        la    t0, kp_st                 ; state
        ld    t1, 0(t0)                 ; ...
        li    t2, 1                     ; after ESC
        beq   t1, t2, kp_e              ; ...
        li    t2, 2                     ; within ESC [
        beq   t1, t2, kp_c              ; ...
        li    t2, 0x1b                  ; ESC: undecided
        bne   a0, t2, kp_key            ; ...
        li    t1, 1                     ; ...
        sd    t1, 0(t0)                 ; ...
        li    a0, KP_NONE               ; ...
        ret                             ; done
kp_key: mv    a1, a0                    ; any other byte is a key
        li    a0, KP_KEY                ; ...
        ret                             ; done
kp_e:   sd    zero, 0(t0)               ; ---- after ESC
        li    t2, '['                   ; a sequence?
        beq   a0, t2, kp_e1             ; ...
        li    a2, 1                     ; no: Esc, then this byte again
        li    a0, KP_ESC                ; ...
        ret                             ; done
kp_e1:  li    t1, 2                     ; ESC [: collect it
        sd    t1, 0(t0)                 ; ...
        sd    zero, kp_nraw - kp_st(t0) ; ...
        sd    zero, kp_np - kp_st(t0)   ; ...
        sd    zero, kp_p - kp_st(t0)    ; ...
        sd    zero, kp_p + 8 - kp_st(t0) ; ...
        sd    zero, kp_p + 16 - kp_st(t0) ; ...
        li    a0, KP_NONE               ; ...
        ret                             ; done
kp_c:   ld    t1, kp_nraw - kp_st(t0)   ; ---- within ESC [
        li    t2, KP_RAWN               ; too long, or not a sequence's byte: cut short
        bge   t1, t2, kp_cut            ; ...
        li    t2, 0x20                  ; ...
        blt   a0, t2, kp_cut            ; ...
        li    t2, 0x7e                  ; ...
        bgt   a0, t2, kp_cut            ; ...
        la    t2, kp_raw                ; kept
        add   t2, t2, t1                ; ...
        sb    a0, 0(t2)                 ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, kp_nraw - kp_st(t0)   ; ...
        ld    t3, kp_np - kp_st(t0)     ; the parameter being read
        addi  t4, a0, -'0'              ; a digit?
        li    t5, 10                    ; ...
        bgeu  t4, t5, kp_c1             ; ...
        li    t5, 3                     ; (one too many: not kept)
        bge   t3, t5, kp_more           ; ...
        slli  t3, t3, 3                 ; parameter = parameter * 10 + digit
        add   t3, t0, t3                ; ...
        ld    t5, kp_p - kp_st(t3)      ; ...
        li    t6, 10                    ; ...
        mul   t5, t5, t6                ; ...
        add   t5, t5, t4                ; ...
        sd    t5, kp_p - kp_st(t3)      ; ...
        j     kp_more                   ; ...
kp_c1:  li    t2, ';'                   ; the next parameter
        bne   a0, t2, kp_c2             ; ...
        li    t5, 3                     ; (at most 3; then "too many")
        bge   t3, t5, kp_more           ; ...
        addi  t3, t3, 1                 ; ...
        sd    t3, kp_np - kp_st(t0)     ; ...
        j     kp_more                   ; ...
kp_c2:  li    t2, 0x40                  ; other parameter and intermediate bytes
        blt   a0, t2, kp_more           ; ...
        sd    zero, 0(t0)               ; ---- the final byte: the sequence is whole
        mv    a1, a0                    ; ...
        li    t2, '~'                   ; ESC [ 27 ; 3 ; code ~: Alt+ a character
        bne   a0, t2, kp_c3             ; ...
        li    t2, 2                     ; ...
        bne   t3, t2, kp_c3             ; ...
        ld    t4, kp_p - kp_st(t0)      ; ...
        li    t2, 27                    ; ...
        bne   t4, t2, kp_c3             ; ...
        ld    t4, kp_p + 8 - kp_st(t0)  ; ...
        li    t2, 3                     ; ...
        bne   t4, t2, kp_c3             ; ...
        ld    a1, kp_p + 16 - kp_st(t0) ; ...
        li    a0, KP_ALT                ; ...
        ret                             ; done
kp_c3:  li    t2, 1                     ; ESC [ n ; 3 X: Alt+ that key
        bne   t3, t2, kp_csi            ; ...
        ld    t4, kp_p + 8 - kp_st(t0)  ; ...
        li    t2, 3                     ; ...
        bne   t4, t2, kp_csi            ; ...
        ld    a3, kp_p - kp_st(t0)      ; ...
        li    a0, KP_AKEY               ; ...
        ret                             ; done
kp_csi: li    a0, KP_CSI                ; anything else: as it came
        ret                             ; done
kp_cut: sd    zero, 0(t0)               ; cut short: what came so far, then this
        li    a1, 0                     ;   byte again
        li    a2, 1                     ; ...
        li    a0, KP_CSI                ; ...
        ret                             ; done
kp_more:
        li    a0, KP_NONE               ; more to come
        ret                             ; done
