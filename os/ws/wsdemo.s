        ld    a1, 8(sp)                 ; the byte
        li    t2, 0x7f                  ; backspace: back, blank, back
        beq   a1, t2, ktt_bs            ; ...
        ld    a0, TC_TERM(t0)           ; echo it
        call  term_putc                 ; ...
        ld    a1, 8(sp)                 ; Enter: a new prompt
        li    t2, '\n'                  ; ...
        bne   a1, t2, ktt_r             ; ...
        ld    t0, 16(sp)                ; ...
        ld    a0, TC_TERM(t0)           ; ...
        ld    a1, TC_PROMPT(t0)         ; ...
        ld    a2, TC_PROMPTN(t0)        ; ...
        call  term_write                ; ...
        j     ktt_r                     ; ...
ktt_bs: ld    a0, TC_TERM(t0)           ; ...
        la    a1, d_bs                  ; ...
        li    a2, 3                     ; ...
        call  term_write                ; ...
ktt_r:  ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

