; pal_toggle(): open or close the palette (the dim covers everything)
pal_toggle:                             ; routine entry
        la    t0, m_pal_open            ; flip
        ld    t1, 0(t0)                 ; ...
        xori  t1, t1, 1                 ; ...
        sd    t1, 0(t0)                 ; ...
        la    t0, m_pal_len             ; empty input
        sd    zero, 0(t0)               ; ...
        la    t0, m_pal_sel             ; ...
        sd    zero, 0(t0)               ; ...
        j     dmg_all                   ; the whole screen

; pal_key(a0 = byte): typing into the palette
pal_key:                                ; routine entry
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        li    t0, 0x7f                  ; backspace
        beq   a0, t0, pk_bs             ; ...
        li    t0, '\t'                  ; tab: complete to the selection
        beq   a0, t0, pk_tab            ; ...
        li    t0, '\n'                  ; enter: launch
        beq   a0, t0, pk_enter          ; ...
        li    t0, 32                    ; other control bytes: ignored
        blt   a0, t0, pk_d              ; ...
        la    t0, m_pal_len             ; append (up to 24)
        ld    t1, 0(t0)                 ; ...
        li    t2, 24                    ; ...
        bge   t1, t2, pk_d              ; ...
        la    t2, m_pal_buf             ; ...
        add   t2, t2, t1                ; ...
        sb    a0, 0(t2)                 ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, 0(t0)                 ; ...
        la    t0, m_pal_sel             ; the first match
        sd    zero, 0(t0)               ; ...
        j     pk_d                      ; ...
pk_bs:  la    t0, m_pal_len             ; one fewer
        ld    t1, 0(t0)                 ; ...
        beqz  t1, pk_d                  ; ...
        addi  t1, t1, -1                ; ...
        sd    t1, 0(t0)                 ; ...
        j     pk_d                      ; ...
pk_tab: call  pal_match                 ; the selected name into the input
        call  pal_choice                ; ...
        beqz  a0, pk_d                  ; ...
        mv    a1, a0                    ; ...
        la    a0, m_pal_buf             ; ...
        li    a2, 12                    ; ...
        call  fmt_cstr                  ; ...
        la    t0, m_pal_buf             ; ...
        sub   t1, a0, t0                ; ...
        la    t0, m_pal_len             ; ...
        sd    t1, 0(t0)                 ; ...
        j     pk_d                      ; ...
pk_enter:
        call  pal_match                 ; launch the choice (the demo knows three)
        call  pal_choice                ; ...
        beqz  a0, pk_close              ; ...
        lbu   t0, 1(a0)                 ; wmandel / wclock / anything else: a terminal
        li    t1, 'm'                   ; ...
        beq   t0, t1, pk_md             ; ...
        li    t1, 'c'                   ; ...
        lbu   t2, 0(a0)                 ; ...
        li    t3, 'w'                   ; ...
        bne   t2, t3, pk_t              ; ...
        beq   t0, t1, pk_ck             ; ...
pk_t:   call  new_term                  ; ...
        j     pk_close                  ; ...
pk_md:  call  open_mandel               ; ...
        j     pk_close                  ; ...
pk_ck:  call  open_clock                ; ...
pk_close:
        call  pal_toggle                ; close
        j     pk_ret                    ; ...
pk_d:   call  pal_damage                ; the panel changed
pk_ret: ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 16                ; pop the frame
        ret                             ; done

; pal_move(a0 = +1 down / -1 up): the selection
pal_move:                               ; routine entry
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    a0, 8(sp)                 ; ...
        call  pal_match                 ; how many
        ld    a0, 8(sp)                 ; ...
        la    t0, m_pal_sel             ; ...
        ld    t1, 0(t0)                 ; ...
        add   t1, t1, a0                ; ...
        bltz  t1, pm2_r                 ; not above the first
        la    t2, pal_nm                ; not below the last
        ld    t2, 0(t2)                 ; ...
        bge   t1, t2, pm2_r             ; ...
        sd    t1, 0(t0)                 ; ...
        call  pal_damage                ; ...
pm2_r:  ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 16                ; pop the frame
        ret                             ; done

; new_term(): a terminal tile for whichever terminal is not shown
new_term:                               ; routine entry
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; save the return address
        li    a0, 8                     ; terminal A's pid
        call  fk_win_by_pid             ; shown?
        li    t0, 0                     ; (no: open A)
        beqz  a0, nt_o                  ; ...
        li    a0, 13                    ; B?
        call  fk_win_by_pid             ; ...
        bnez  a0, nt_r                  ; both shown: nothing
        li    t0, 1                     ; ...
nt_o:   mv    a0, t0                    ; ...
        call  open_term                 ; ...
nt_r:   ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 8                 ; pop the frame
        ret                             ; done

; close_focused(): Alt+Q
close_focused:                          ; routine entry
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = index
        la    t0, m_nwin                ; any?
        ld    t1, 0(t0)                 ; ...
        beqz  t1, cf_r                  ; ...
        la    t0, m_focus               ; the focused one
        ld    s0, 0(t0)                 ; ...
        mv    a0, s0                    ; free its surface slot
        call  m_win                     ; ...
        ld    t0, WN_SURF + S_OFF(a0)   ; ...
        li    t1, SLOT                  ; ...
        divu  t0, t0, t1                ; ...
        li    t1, 1                     ; ...
        sll   t1, t1, t0                ; ...
        la    t2, d_slots               ; ...
        ld    t3, 0(t2)                 ; ...
        xor   t3, t3, t1                ; ...
        sd    t3, 0(t2)                 ; ...
cf_mv:  la    t0, m_nwin                ; the later records move down one
        ld    t0, 0(t0)                 ; ...
        addi  t0, t0, -1                ; ...
        bge   s0, t0, cf_dn             ; ...
        mv    a0, s0                    ; ...
        call  m_win                     ; ...
        li    t0, WN_SIZE / 8           ; ...
cf_c:   ld    t1, WN_SIZE(a0)           ; ...
        sd    t1, 0(a0)                 ; ...
        addi  a0, a0, 8                 ; ...
        addi  t0, t0, -1                ; ...
        bnez  t0, cf_c                  ; ...
        addi  s0, s0, 1                 ; ...
        j     cf_mv                     ; ...
cf_dn:  la    t0, m_nwin                ; one fewer
        ld    t1, 0(t0)                 ; ...
        addi  t1, t1, -1                ; ...
        sd    t1, 0(t0)                 ; ...
        la    t0, m_focus               ; focus stays in range
        ld    t2, 0(t0)                 ; ...
        blt   t2, t1, cf_f              ; ...
        addi  t2, t1, -1                ; ...
        bgez  t2, cf_f                  ; ...
        li    t2, 0                     ; ...
cf_f:   sd    t2, 0(t0)                 ; ...
        call  fix_term_surfaces         ; terminals follow their records
        call  lay_retile                ; ...
        call  dmg_all                   ; ...
cf_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; fix_term_surfaces(): after records moved, point terminals at their surface
fix_term_surfaces:                      ; routine entry
        la    t0, m_wins                ; ...
        la    t1, m_nwin                ; ...
        ld    t1, 0(t1)                 ; ...
fts_l:  beqz  t1, fts_r                 ; ...
        ld    t2, WN_KIND(t0)           ; ...
        li    t3, WK_TERM               ; ...
        bne   t2, t3, fts_n             ; ...
        ld    t2, WN_CLIENT(t0)         ; ...
        ld    t2, TC_TERM(t2)           ; ...
        addi  t3, t0, WN_SURF           ; ...
        sd    t3, TS_SURF(t2)           ; ...
fts_n:  addi  t0, t0, WN_SIZE           ; ...
        addi  t1, t1, -1                ; ...
        j     fts_l                     ; ...
fts_r:  la    t0, m_wins                ; and the graphics clients
        la    t1, m_nwin                ; ...
        ld    t1, 0(t1)                 ; ...
fts_g:  beqz  t1, fts_x                 ; ...
        ld    t2, WN_CLIENT(t0)         ; ...
        addi  t3, t0, WN_SURF           ; ...
        la    t4, d_md                  ; ...
        bne   t2, t4, fts_g2            ; ...
        sd    t3, MD_SURF(t2)           ; ...
fts_g2: la    t4, d_ck                  ; ...
        bne   t2, t4, fts_g3            ; ...
        sd    t3, CK_SURF(t2)           ; ...
fts_g3: addi  t0, t0, WN_SIZE           ; ...
        addi  t1, t1, -1                ; ...
        j     fts_g                     ; ...
fts_x:  ret                             ; done

; key(a0 = byte): Alt = ESC prefix (spec 1.4)
key:                                    ; routine entry
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        la    t0, d_esc                 ; parser state
        ld    t1, 0(t0)                 ; ...
        li    t2, 1                     ; after ESC
        beq   t1, t2, k_esc             ; ...
        li    t2, 2                     ; ESC [
        beq   t1, t2, k_csi             ; ...
        li    t2, 3                     ; ESC ESC (Alt+arrow follows)
        beq   t1, t2, k_ee              ; ...
        li    t2, 4                     ; ESC ESC [
        beq   t1, t2, k_acsi            ; ...
        li    t2, 0x1b                  ; ESC
        bne   a0, t2, k_plain           ; ...
        li    t1, 1                     ; ...
        sd    t1, 0(t0)                 ; ...
        j     k_ret                     ; ...
k_plain:
        la    t1, m_pal_open            ; the palette takes the keys while open
        ld    t1, 0(t1)                 ; ...
        beqz  t1, k_term                ; ...
        call  pal_key                   ; ...
        j     k_ret                     ; ...
k_term: call  k_to_term                 ; the focused terminal
        j     k_ret                     ; ...
k_esc:  sd    zero, 0(t0)               ; ---- Alt+key
        li    t2, '['                   ; a CSI (arrows)
        bne   a0, t2, k_e1              ; ...
        li    t1, 2                     ; ...
        sd    t1, 0(t0)                 ; ...
        j     k_ret                     ; ...
k_e1:   li    t2, 0x1b                  ; ESC ESC
        bne   a0, t2, k_e2              ; ...
        li    t1, 3                     ; ...
        sd    t1, 0(t0)                 ; ...
        j     k_ret                     ; ...
k_e2:   li    t2, ' '                   ; Alt+Space or Alt+P: the palette
        beq   a0, t2, k_pal             ; ...
        ori   t1, a0, 0x20              ; (p or P)
        li    t2, 'p'                   ; ...
        bne   t1, t2, k_e3              ; ...
k_pal:  call  pal_toggle                ; ...
        j     k_ret                     ; ...
k_e3:   li    t2, 'Q'                   ; Alt+Shift+Q: quit
        bne   a0, t2, k_e4              ; ...
        la    t1, d_quit                ; ...
        li    t2, 1                     ; ...
        sd    t2, 0(t1)                 ; ...
        j     k_ret                     ; ...
k_e4:   li    t2, 'q'                   ; Alt+Q: close
        bne   a0, t2, k_e5              ; ...
        call  close_focused             ; ...
        j     k_ret                     ; ...
k_e5:   li    t2, '\n'                  ; Alt+Enter: a terminal
        bne   a0, t2, k_e6              ; ...
        call  new_term                  ; ...
        j     k_ret                     ; ...
k_e6:   addi  a0, a0, -'1'              ; Alt+1..4: focus
        li    t2, 4                     ; ...
        bgeu  a0, t2, k_ret             ; ...
        call  focus_to                  ; ...
        j     k_ret                     ; ...
k_csi:  sd    zero, 0(t0)               ; ---- ESC [ x: arrows (the palette's up/down)
        la    t1, m_pal_open            ; ...
        ld    t1, 0(t1)                 ; ...
        beqz  t1, k_ret                 ; ...
        li    t2, 'A'                   ; up
        li    t3, -1                    ; ...
        beq   a0, t2, k_mv              ; ...
        li    t2, 'B'                   ; down
        li    t3, 1                     ; ...
        bne   a0, t2, k_ret             ; ...
k_mv:   mv    a0, t3                    ; ...
        call  pal_move                  ; ...
        j     k_ret                     ; ...
k_ee:   li    t1, 4                     ; ESC ESC [
        li    t2, '['                   ; ...
        beq   a0, t2, k_ee2             ; ...
        li    t1, 0                     ; ...
k_ee2:  sd    t1, 0(t0)                 ; ...
        j     k_ret                     ; ...
k_acsi: sd    zero, 0(t0)               ; Alt+arrow: focus to the next / previous tile
        la    t1, m_focus               ; ...
        ld    t1, 0(t1)                 ; ...
        la    t2, m_nwin                ; ...
        ld    t2, 0(t2)                 ; ...
        beqz  t2, k_ret                 ; ...
        li    t3, 'C'                   ; right / down: next
        beq   a0, t3, k_nx              ; ...
        li    t3, 'B'                   ; ...
        beq   a0, t3, k_nx              ; ...
        add   t1, t1, t2                ; left / up: previous
        addi  t1, t1, -1                ; ...
        j     k_fm                      ; ...
k_nx:   addi  t1, t1, 1                 ; ...
k_fm:   remu  a0, t1, t2                ; ...
        call  focus_to                  ; ...
k_ret:  ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 16                ; pop the frame
        ret                             ; done

; k_to_term(a0 = byte): echo into the focused terminal (no shell yet: Enter
; gives a fresh prompt)
k_to_term:                              ; routine entry
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    a0, 8(sp)                 ; the byte
        la    t0, m_focus               ; the focused window
        ld    a0, 0(t0)                 ; ...
        la    t0, m_nwin                ; (any?)
        ld    t0, 0(t0)                 ; ...
        bge   a0, t0, ktt_r             ; ...
        call  m_win                     ; ...
        ld    t0, WN_KIND(a0)           ; a terminal?
        li    t1, WK_TERM               ; ...
