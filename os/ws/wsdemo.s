; =============================================================================
; wsdemo.s: the window server's renderers, bare metal, with a pretend OS
; =============================================================================
;
; Everything the StrataOS window server draws, running on core 0 of a bare
; machine: the boot splash, then four tiles opening one after another (a
; terminal with a scripted shell session, wmandel, wclock, a second
; terminal), the core lattice pulsing with a pretend scheduler (fake.s), a
; focus change and the command palette. The data is fake; the drawing code
; is what the real `ws` uses (os/ws/README.md has the module map).
;
; Like the real server it is a single thread: one loop that, per frame,
; updates the model, lets the clients draw into their surfaces, moves the
; slides, draws the damaged rectangles and writes PRESENT once, then waits
; for VSYNC (and, interactively, for keys at the same time: `tany`).
;
; Build-time knobs (a wrapper file sets them before including this one;
; see the Makefile's ws-shots):
;   SHOT = 0   interactive: runs until Alt+Shift+Q or the window is closed
;   SHOT = N   draw frames 1..N as fast as possible (no VSYNC wait), then
;              halt: the frame captured by -F is frame N
;   PERF = 1   at frame SHOT, also measure and print the cost of a full
;              frame, a terminal line and a lattice pulse
;   PERF = 2   at frame SHOT, redraw the whole screen once more (ws-check
;              compares that with the damage-driven frame: they must match)
; Keys (interactive): Alt+1..4 focus, Alt+P or Alt+Space palette (type, Tab, arrows,
; Enter), Alt+Enter a new terminal, Alt+Q close the focused tile,
; Alt+Shift+Q quit; other keys go to the focused terminal.

        .text                           ; instruction Local Store
_start: j     main                      ; skip the library code

        .include "theme.s"              ; palette and metrics
        .include "gfx.s"                ; os/lib/gfx.s: surfaces, display lists
        .include "font/font.s"          ; os/lib/font/font.s: the fonts
        .include "hw_bare.s"            ; the machine layer (bare metal)
        .include "model.s"              ; what is shown
        .include "fmt.s"                ; text formatting
        .include "damage.s"             ; damage list, commit
        .include "layout.s"             ; tiling and slides
        .include "frame.s"              ; tile frames
        .include "lattice.s"            ; the status strip
        .include "palette.s"            ; the command palette
        .include "splash.s"             ; the boot splash
        .include "pointer.s"            ; the cursor and the key help
        .include "scene.s"              ; the display list of the screen
        .include "term.s"               ; terminal surfaces
        .include "wmandel.s"            ; the Mandelbrot client's renderer
        .include "wclock.s"             ; the clock client's renderer
        .include "fake.s"               ; the pretend OS
        .include "demo_script.s"        ; the terminals' scripted sessions

SLOT      = 0x400000                    ; 4 MiB of the pool per surface
D_OPEN0   = SPL_END + 1                 ; frames at which things happen
D_OPEN1   = D_OPEN0 + 46                ; ...
D_OPEN2   = D_OPEN1 + 46                ; ...
D_OPEN3   = D_OPEN2 + 46                ; ...
D_FOCUS   = D_OPEN3 + 210               ; focus moves to wmandel
D_PAL     = D_FOCUS + 40                ; the palette opens
D_PALW    = D_PAL + 14                  ; "w" typed
D_PALDN   = D_PALW + 10                 ; down: the second match
D_PALX    = D_PALDN + 60                ; the palette closes
D_KEYS    = D_PALX + 30                 ; scripted keys start
TC_TERM   = 0                           ; term client: the terminal
TC_SC     = 8                           ; script cursor
TC_WAIT   = 16                          ; frames to wait
TC_MODE   = 24                          ; 0 line start, 1 typing a command
TC_PROMPT = 32                          ; prompt string
TC_PROMPTN = 40                         ; its length
TC_SIZE   = 48                          ; bytes
GRID_CAP  = 32                          ; ring rows of a demo terminal
GRID_STR  = 96                          ; cells per ring row

        .data                           ; D-LS
        .align 8                        ; dwords
d_frame:  .dword 0                      ; frame number
d_slots:  .dword 0                      ; surface slots in use (bits)
d_esc:    .dword 0                      ; key parser: 0, 1 after ESC, 2 ESC [, 3 ESC ESC, 4 ESC ESC [
d_quit:   .dword 0                      ; Alt+Shift+Q seen
d_eof:    .dword 0                      ; the console input has ended
d_termA:  .space TS_SIZE                ; the two terminals
d_termB:  .space TS_SIZE                ; ...
d_tcA:    .space TC_SIZE                ; their scripts
d_tcB:    .space TC_SIZE                ; ...
d_md:     .space MD_SIZE                ; wmandel's renderer
d_ck:     .space CK_SIZE                ; wclock's renderer
d_cksec:  .dword -1                     ; the second the clock shows
d_gridA:  .space GRID_CAP * GRID_STR * 2 ; terminal grids
d_gridB:  .space GRID_CAP * GRID_STR * 2 ; ...
d_nm_term: .asciz "TERM"                ; window names
d_nm_md:  .asciz "WMANDEL"              ; ...
d_nm_ck:  .asciz "WCLOCK"               ; ...
d_m_bad:  .ascii "no framebuffer\n"     ; messages
d_m_bad_e:                              ; ...
d_m_full: .ascii "@ full frame (1280x800, every item): instructions "
d_m_full_e:                             ; ...
d_m_line: .ascii "@ terminal line (render into surface + composite): instructions "
d_m_line_e:                             ; ...
d_m_puls: .ascii "@ lattice pulse (one cell + halo): instructions "
d_m_puls_e:                             ; ...
d_m_px:   .ascii ", pixels "            ; ...
d_m_px_e:                               ; ...
d_m_ln:   .ascii "\x1b[93mstrata\x1b[0m: one more line of output for the perf test\n"
d_m_ln_e:                               ; ...
        .align 8                        ; ...
        .text                           ; code

main:
        li    sp, 65536                 ; stack at the top of the D-LS
        csrr  t0, coreid                ; only core 0 runs the server
        bnez  t0, idle                  ; ...
        call  hw_init                   ; the framebuffer
        bnez  a0, bad                   ; ...
        la    t0, hw_fb                 ; the model's screen
        la    t1, m_scr                 ; ...
        sd    t0, 0(t1)                 ; ...
        ld    t2, S_W(t0)               ; ...
        sd    t2, m_w - m_scr(t1)       ; ...
        ld    t2, S_H(t0)               ; ...
        sd    t2, m_h - m_scr(t1)       ; ...
        call  fake_init                 ; the pretend OS
        la    a0, d_termA               ; the terminals (sized when their tiles open)
        la    a1, d_gridA               ; ...
        li    a2, GRID_CAP              ; ...
        li    a3, GRID_STR              ; ...
        li    a4, 0                     ; (surface set when the tile opens)
        call  term_init                 ; ...
        la    a0, d_termB               ; ...
        la    a1, d_gridB               ; ...
        li    a2, GRID_CAP              ; ...
        li    a3, GRID_STR              ; ...
        li    a4, 0                     ; ...
        call  term_init                 ; ...
        la    a0, d_tcA                 ; their scripts
        la    a1, d_termA               ; ...
        la    a2, script_a              ; ...
        la    a3, prompt_a              ; ...
        li    a4, prompt_a_e - prompt_a ; ...
        call  tc_init                   ; ...
        la    a0, d_tcB                 ; ...
        la    a1, d_termB               ; ...
        la    a2, script_b              ; ...
        la    a3, prompt_b              ; ...
        li    a4, prompt_b_e - prompt_b ; ...
        call  tc_init                   ; ...
        li    t0, SHOT                  ; interactive: listen to the keyboard
        bnez  t0, loop                  ; ...
        call  hw_key_issue              ; ...
loop:                                   ; ---- one frame
        call  hw_vsync_issue            ; the next refresh (waited for below)
        la    t0, d_frame               ; frame number
        ld    a0, 0(t0)                 ; ...
        addi  a0, a0, 1                 ; ...
        sd    a0, 0(t0)                 ; ...
        call  timeline                  ; scripted events
        la    t0, d_frame               ; the pretend OS
        ld    a0, 0(t0)                 ; ...
        call  fake_tick                 ; ...
        call  clients_tick              ; clients draw into their surfaces
        call  lay_step                  ; slides and fades
        call  scn_frame                 ; draw the damage, PRESENT
        li    t0, SHOT                  ; screenshot mode: stop at frame SHOT
        beqz  t0, wait                  ; ...
        la    t1, d_frame               ; ...
        ld    t1, 0(t1)                 ; ...
        blt   t1, t0, loop              ; not yet: next frame, no waiting
        li    t0, PERF                  ; measure?
        beqz  t0, done                  ; ...
        li    t1, 2                     ; PERF = 2: redraw everything (the check that
        bne   t0, t1, d_perf            ;   damage-driven drawing left the same picture)
        call  dmg_all                   ; ...
        call  scn_frame                 ; ...
        j     done                      ; ...
d_perf: call  perf                      ; ...
done:   li    a0, 0                     ; exit code
        halt                            ; the -F frame is the last one presented
wait:                                   ; interactive: VSYNC or a key, whichever comes
        la    t0, d_eof                 ; no more keys?
        ld    t0, 0(t0)                 ; ...
        bnez  t0, wait_vs               ; ...
        li    t0, (1 << 11) | (1 << 12) ; tags 11 (key) and 12 (VSYNC)
        tany  t1, t0                    ; wait for either
        andi  t2, t1, 1 << 11           ; a key?
        beqz  t2, w_vs                  ; no
        call  hw_key_get                ; the byte
        li    t0, 4                     ; end of a -i file (0x04 for ever): stop listening
        beq   a0, t0, w_eof             ; ...
        call  key                       ; handle it
        la    t0, d_quit                ; quit?
        ld    t0, 0(t0)                 ; ...
        bnez  t0, done                  ; ...
        call  hw_key_issue              ; the next key
        j     wait                      ; keep waiting
w_eof:  la    t0, d_eof                 ; ...
        li    t1, 1                     ; ...
        sd    t1, 0(t0)                 ; ...
        call  hw_vsync_wait             ; from now on only the refresh
        j     loop                      ; ...
wait_vs:                                ; (after end of input: VSYNC alone)
        call  hw_vsync_wait             ; ...
        j     loop                      ; ...
w_vs:   call  hw_vsync_wait             ; the refresh came
        j     loop                      ; next frame
bad:    la    a0, d_m_bad               ; no framebuffer
        li    a1, d_m_bad_e - d_m_bad   ; ...
        call  print_str                 ; ...
        li    a0, 1                     ; ...
        halt                            ; ...
idle:   li    a0, 0                     ; other cores: nothing to do
        halt                            ; ...

; ---------------------------------------------------------------------------
; timeline(a0 = frame): the scripted part of the demo
; ---------------------------------------------------------------------------
timeline:                               ; routine entry
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = frame
        mv    s0, a0                    ; ...
        li    t0, SPL_END               ; the splash?
        bgt   s0, t0, tl_desk           ; over
        la    t1, m_splash              ; frame of the splash
        sd    s0, 0(t1)                 ; ...
        li    t0, 1                     ; the first frame: everything
        bne   s0, t0, tl_spl            ; ...
        call  dmg_all                   ; ...
tl_spl: addi  t0, s0, -SPL_DONE         ; the grid fading in: everything
        blez  t0, tl_sp2                ; ...
        li    t1, 17                    ; ...
        bge   t0, t1, tl_sp2            ; ...
        call  dmg_all                   ; ...
tl_sp2: call  splash_damage             ; the bands move
        j     tl_ret                    ; ...
tl_desk:
        li    t0, D_OPEN0               ; the desktop appears with the first tile
        bne   s0, t0, tl_1              ; ...
        la    t1, m_splash              ; no more splash
        sd    zero, 0(t1)               ; ...
        call  dmg_all                   ; ...
        li    a0, 0                     ; open: TERM (pid 8, core 7), terminal A
        call  open_term                 ; ...
        j     tl_ret                    ; ...
tl_1:   li    t0, D_OPEN1               ; wmandel
        bne   s0, t0, tl_2              ; ...
        call  open_mandel               ; ...
        j     tl_ret                    ; ...
tl_2:   li    t0, D_OPEN2               ; wclock
        bne   s0, t0, tl_3              ; ...
        call  open_clock                ; ...
        j     tl_ret                    ; ...
tl_3:   li    t0, D_OPEN3               ; the second terminal
        bne   s0, t0, tl_4              ; ...
        li    a0, 1                     ; ...
        call  open_term                 ; ...
        j     tl_ret                    ; ...
tl_4:   li    t0, D_FOCUS               ; focus to wmandel
        bne   s0, t0, tl_5              ; ...
        li    a0, 1                     ; ...
        call  focus_to                  ; ...
        j     tl_ret                    ; ...
tl_5:   li    t0, D_PAL                 ; the palette
        bne   s0, t0, tl_6              ; ...
        call  pal_toggle                ; ...
        j     tl_ret                    ; ...
tl_6:   li    t0, D_PALW                ; "w"
        bne   s0, t0, tl_7              ; ...
        li    a0, 'w'                   ; ...
        call  pal_key                   ; ...
        j     tl_ret                    ; ...
tl_7:   li    t0, D_PALDN               ; down
        bne   s0, t0, tl_8              ; ...
        li    a0, 1                     ; ...
        call  pal_move                  ; ...
        j     tl_ret                    ; ...
tl_8:   li    t0, D_PALX                ; close it
        bne   s0, t0, tl_9              ; ...
        call  pal_toggle                ; ...
        j     tl_ret                    ; ...
tl_9:   addi  t0, s0, -D_KEYS           ; then keys, one a frame, as if typed: the
        bltz  t0, tl_ret                ;   keyboard paths of the interactive demo
        li    t1, d_keys_e - d_keys     ; ...
        bge   t0, t1, tl_ret            ; ...
        la    t1, d_keys                ; ...
        add   t1, t1, t0                ; ...
        lbu   a0, 0(t1)                 ; ...
        call  key                       ; ...
tl_ret: ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 16                ; pop the frame
        ret                             ; done

; ---------------------------------------------------------------------------
; Windows
; ---------------------------------------------------------------------------

; win_new(a0 = kind, a1 = name, a2 = pid, a3 = core, a4 = client state) ->
; a0 = the new window record (0 if there are 4); allocates a surface slot
win_new:                                ; routine entry
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    a0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        sd    a2, 24(sp)                ; ...
        sd    a3, 32(sp)                ; ...
        sd    a4, 40(sp)                ; ...
        la    t0, m_nwin                ; room?
        ld    t1, 0(t0)                 ; ...
        li    t2, MAXWIN                ; ...
        li    a0, 0                     ; (no)
        bge   t1, t2, wn_ret            ; ...
        addi  t2, t1, 1                 ; one more
        sd    t2, 0(t0)                 ; ...
        mv    a0, t1                    ; its record
        call  m_win                     ; ...
        li    t0, WN_SIZE / 8           ; cleared
        mv    t1, a0                    ; ...
wn_c:   sd    zero, 0(t1)               ; ...
        addi  t1, t1, 8                 ; ...
        addi  t0, t0, -1                ; ...
        bnez  t0, wn_c                  ; ...
        ld    t0, 8(sp)                 ; kind
        sd    t0, WN_KIND(a0)           ; ...
        ld    t0, 24(sp)                ; pid
        sd    t0, WN_PID(a0)            ; ...
        ld    t0, 32(sp)                ; core
        sd    t0, WN_CORE(a0)           ; ...
        ld    t0, 40(sp)                ; client
        sd    t0, WN_CLIENT(a0)         ; ...
        ld    t1, 16(sp)                ; name (up to 8 bytes, NUL-padded)
        li    t2, 0                     ; ...
wn_n:   li    t3, 8                     ; ...
        bge   t2, t3, wn_s              ; ...
        add   t3, t1, t2                ; ...
        lbu   t4, 0(t3)                 ; ...
        add   t5, a0, t2                ; ...
        sb    t4, WN_NAME(t5)           ; ...
        beqz  t4, wn_s                  ; ...
        addi  t2, t2, 1                 ; ...
        j     wn_n                      ; ...
wn_s:   la    t0, d_slots               ; a free surface slot
        ld    t1, 0(t0)                 ; ...
        li    t2, 0                     ; ...
wn_sl:  srl   t3, t1, t2                ; ...
        andi  t3, t3, 1                 ; ...
        beqz  t3, wn_sf                 ; ...
        addi  t2, t2, 1                 ; ...
        j     wn_sl                     ; ...
wn_sf:  li    t3, 1                     ; take it
        sll   t3, t3, t2                ; ...
        or    t1, t1, t3                ; ...
        sd    t1, 0(t0)                 ; ...
        li    t3, SLOT                  ; the surface: in the pool, sized later
        mul   t3, t3, t2                ; ...
        sd    t3, WN_SURF + S_OFF(a0)   ; ...
        li    t3, HW_POOLCAP            ; ...
        sd    t3, WN_SURF + S_CAP(a0)   ; ...
        sd    a0, 8(sp)                 ; keep the record
        call  lay_retile                ; everything moves
        call  lat_stats_damage          ; the window list in the strip
        ld    a0, 8(sp)                 ; ...
wn_ret: ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 48                ; pop the frame
        ret                             ; done

; open_term(a0 = 0: terminal A, 1: terminal B)
open_term:                              ; routine entry
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        la    a4, d_tcA                 ; A: pid 8 on core 7
        li    a2, 8                     ; ...
        li    a3, 7                     ; ...
        beqz  a0, ot_1                  ; ...
        la    a4, d_tcB                 ; B: pid 13 on core 8
        li    a2, 13                    ; ...
        li    a3, 8                     ; ...
ot_1:   ld    t0, TC_TERM(a4)           ; the terminal draws into the window's surface
        sd    t0, 8(sp)                 ; ...
        li    a0, WK_TERM               ; ...
        la    a1, d_nm_term             ; ...
        call  win_new                   ; ...
        beqz  a0, ot_ret                ; ...
        ld    t0, 8(sp)                 ; terminal ...
        addi  t1, a0, WN_SURF           ; ... -> surface
        sd    t1, TS_SURF(t0)           ; ...
ot_ret: ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 16                ; pop the frame
        ret                             ; done

; open_mandel(), open_clock()
open_mandel:                            ; routine entry
        li    a0, WK_GFX                ; a graphics client
        la    a1, d_nm_md               ; WMANDEL, pid 11 on core 9
        li    a2, 11                    ; ...
        li    a3, 9                     ; ...
        la    a4, d_md                  ; ...
        j     win_new                   ; ...
open_clock:                             ; routine entry
        li    a0, WK_GFX                ; ...
        la    a1, d_nm_ck               ; WCLOCK, pid 12 on core 10
        li    a2, 12                    ; ...
        li    a3, 10                    ; ...
        la    a4, d_ck                  ; ...
        j     win_new                   ; ...

; focus_to(a0 = index): move the focus (both tiles' frames change)
focus_to:                               ; routine entry
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    a0, 8(sp)                 ; ...
        la    t0, m_nwin                ; an existing tile?
        ld    t0, 0(t0)                 ; ...
        bge   a0, t0, ftg_ret           ; ...
        la    t0, m_focus               ; the old one
        ld    a0, 0(t0)                 ; ...
        call  m_win                     ; ...
        call  lay_damage                ; ...
        call  focus_cursor              ; (its cursor dims)
        ld    a0, 8(sp)                 ; the new one
        la    t0, m_focus               ; ...
        sd    a0, 0(t0)                 ; ...
        call  m_win                     ; ...
        call  lay_damage                ; ...
        call  focus_cursor              ; ...
        call  lat_stats_damage          ; the strip's window list
ftg_ret:
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 16                ; pop the frame
        ret                             ; done

; focus_cursor(): every terminal's cursor: cyan when focused, dim otherwise
focus_cursor:                           ; routine entry
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = index
        li    s0, 0                     ; ...
fc_l:   la    t0, m_nwin                ; all?
        ld    t0, 0(t0)                 ; ...
        bge   s0, t0, fc_r              ; ...
        mv    a0, s0                    ; ...
        call  m_win                     ; ...
        ld    t0, WN_KIND(a0)           ; a terminal?
        li    t1, WK_TERM               ; ...
        bne   t0, t1, fc_n              ; ...
        ld    t0, WN_CLIENT(a0)         ; its terminal
        ld    a0, TC_TERM(t0)           ; ...
        li    t1, C_EDGE                ; dim ...
        la    t2, m_focus               ; ...
        ld    t2, 0(t2)                 ; ...
        bne   t2, s0, fc_c              ; ...
        li    t1, C_ACCENT              ; ... or cyan
fc_c:   sd    t1, TS_CURON(a0)          ; ...
        ld    a1, TS_CY(a0)             ; its row needs drawing
        call  term_dirty                ; ...
fc_n:   addi  s0, s0, 1                 ; next
        j     fc_l                      ; ...
fc_r:   ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; ---------------------------------------------------------------------------
; Clients: each draws into its own surface and damages what it drew
; ---------------------------------------------------------------------------
clients_tick:                           ; routine entry
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = index
        sd    s1, 16(sp)                ; s1 = window
        sd    s2, 24(sp)                ; s2 = client
        call  tc_tick_all               ; the scripted sessions write
        li    s0, 0                     ; every window
ct_l:   la    t0, m_nwin                ; ...
        ld    t0, 0(t0)                 ; ...
        bge   s0, t0, ct_ret            ; ...
        mv    a0, s0                    ; ...
        call  m_win                     ; ...
        mv    s1, a0                    ; ...
        ld    s2, WN_CLIENT(s1)         ; ...
        ld    t0, WN_EVT(s1)            ; a resize?
        andi  t0, t0, WE_RESIZE         ; ...
        beqz  t0, ct_draw               ; no
        sd    zero, WN_EVT(s1)          ; yes: the surface takes the client area's size
        mv    a0, s1                    ; ...
        call  lay_content               ; ...
        sd    a2, WN_SURF + S_W(s1)     ; ...
        sd    a3, WN_SURF + S_H(s1)     ; ...
        slli  t0, a2, 2                 ; ...
        sd    t0, WN_SURF + S_STRIDE(s1) ; ...
        la    t0, d_md                  ; and the client starts over at that size
        beq   s2, t0, ct_md0            ; ...
        la    t0, d_ck                  ; ...
        beq   s2, t0, ct_ck0            ; ...
        ld    a0, TC_TERM(s2)           ; a terminal: new rows and columns
        srli  a1, a2, 3                 ; ...
        srli  a2, a3, 4                 ; ...
        call  term_resize               ; ...
        j     ct_draw                   ; ...
ct_md0: mv    a0, s2                    ; wmandel: a new picture
        addi  a1, s1, WN_SURF           ; ...
        call  md_start                  ; ...
        j     ct_draw                   ; ...
ct_ck0: addi  t0, s1, WN_SURF           ; wclock: all of it
        sd    t0, CK_SURF(s2)           ; ...
        mv    a0, s2                    ; ...
        la    t0, m_clock               ; ...
        ld    a1, 0(t0)                 ; ...
        la    t0, m_uptime              ; ...
        ld    a2, 0(t0)                 ; ...
        li    a3, 1                     ; ...
        call  ck_draw                   ; ...
        la    t0, m_clock               ; (that second is shown)
        ld    t0, 0(t0)                 ; ...
        la    t1, d_cksec               ; ...
        sd    t0, 0(t1)                 ; ...
        mv    a1, a1                    ; damage the rect drawn
        call  ct_damage                 ; ...
        j     ct_next                   ; ...
ct_draw:
        ld    t0, WN_SURF + S_W(s1)     ; no surface yet?
        beqz  t0, ct_next               ; ...
        la    t0, d_md                  ; who draws?
        beq   s2, t0, ct_md             ; ...
        la    t0, d_ck                  ; ...
        beq   s2, t0, ct_ck             ; ...
        ld    a0, TC_TERM(s2)           ; a terminal: its dirty rows
        call  term_render               ; ...
        beq   a0, a1, ct_next           ; nothing
        mv    a3, a1                    ; damage those rows, full width
        mv    a1, a0                    ; ...
        li    a0, 0                     ; ...
        ld    a2, WN_SURF + S_W(s1)     ; ...
        call  ct_damage                 ; ...
        j     ct_next                   ; ...
ct_md:  mv    a0, s2                    ; wmandel: 10 more rows
        li    a1, 10                    ; ...
        call  md_step                   ; ...
        beq   a0, a1, ct_next           ; done already
        mv    a3, a1                    ; damage them
        mv    a1, a0                    ; ...
        li    a0, 0                     ; ...
        ld    a2, WN_SURF + S_W(s1)     ; ...
        call  ct_damage                 ; ...
        j     ct_next                   ; ...
ct_ck:  la    t0, m_clock               ; wclock: a new second?
        ld    a1, 0(t0)                 ; ...
        la    t1, d_cksec               ; ...
        ld    t2, 0(t1)                 ; ...
        beq   a1, t2, ct_next           ; no
        sd    a1, 0(t1)                 ; yes: the band that changes
        mv    a0, s2                    ; ...
        la    t0, m_uptime              ; ...
        ld    a2, 0(t0)                 ; ...
        li    a3, 0                     ; ...
        call  ck_draw                   ; ...
        call  ct_damage                 ; ...
ct_next:
        addi  s0, s0, 1                 ; next window
        j     ct_l                      ; ...
ct_ret: ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        ld    s2, 24(sp)                ; ...
        addi  sp, sp, 32                ; pop the frame
        ret                             ; done

; ct_damage(a0..a3 = x0, y0, x1, y1 in the surface of window s1): damage it
; on the screen (what the server does for a client's DAMAGE)
ct_damage:                              ; routine entry
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    a0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        sd    a2, 24(sp)                ; ...
        sd    a3, 32(sp)                ; ...
        mv    a0, s1                    ; the client area's origin
        call  lay_content               ; ...
        ld    t0, 8(sp)                 ; translate
        add   t0, t0, a0                ; ...
        ld    t1, 16(sp)                ; ...
        add   t1, t1, a1                ; ...
        ld    t2, 24(sp)                ; ...
        add   t2, t2, a0                ; ...
        ld    t3, 32(sp)                ; ...
        add   t3, t3, a1                ; ...
        add   t4, a0, a2                ; clip to the client area
        ble   t2, t4, cd_1              ; ...
        mv    t2, t4                    ; ...
cd_1:   add   t4, a1, a3                ; ...
        ble   t3, t4, cd_2              ; ...
        mv    t3, t4                    ; ...
cd_2:   mv    a0, t0                    ; ...
        mv    a1, t1                    ; ...
        mv    a2, t2                    ; ...
        mv    a3, t3                    ; ...
        call  dmg_add                   ; ...
        ld    ra, 0(sp)                 ; restore the return address
        addi  sp, sp, 40                ; pop the frame
        ret                             ; done

; ---------------------------------------------------------------------------
; Scripted terminal sessions (the scripts are in demo_script.s)
;   a line "$ cmd" prints the prompt and types cmd, a character a frame;
;   a line "~" waits half a second; "#" ends; other lines are output, one
;   line a frame.
; ---------------------------------------------------------------------------

; tc_init(a0 = client, a1 = terminal, a2 = script, a3 = prompt, a4 = length)
tc_init:                                ; routine entry
        sd    a1, TC_TERM(a0)           ; ...
        sd    a2, TC_SC(a0)             ; ...
        sd    a3, TC_PROMPT(a0)         ; ...
        sd    a4, TC_PROMPTN(a0)        ; ...
        sd    zero, TC_WAIT(a0)         ; ...
        sd    zero, TC_MODE(a0)         ; ...
        ret                             ; done

; tc_tick_all(): advance the scripts of terminals that have a tile
tc_tick_all:                            ; routine entry
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = index
        li    s0, 0                     ; ...
tta_l:  la    t0, m_nwin                ; ...
        ld    t0, 0(t0)                 ; ...
        bge   s0, t0, tta_r             ; ...
        mv    a0, s0                    ; ...
        call  m_win                     ; ...
        ld    t0, WN_KIND(a0)           ; a terminal with a surface?
        li    t1, WK_TERM               ; ...
        bne   t0, t1, tta_n             ; ...
        ld    t0, WN_SURF + S_W(a0)     ; ...
        beqz  t0, tta_n                 ; ...
        ld    a0, WN_CLIENT(a0)         ; ...
        call  tc_tick                   ; ...
tta_n:  addi  s0, s0, 1                 ; ...
        j     tta_l                     ; ...
tta_r:  ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

; tc_tick(a0 = client): one step of its script
tc_tick:                                ; routine entry
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; save the return address
        sd    s0, 8(sp)                 ; s0 = client
        sd    s1, 16(sp)                ; s1 = script cursor
        mv    s0, a0                    ; ...
        ld    t0, TC_WAIT(s0)           ; waiting?
        beqz  t0, tt_go                 ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, TC_WAIT(s0)           ; ...
        j     tt_ret                    ; ...
tt_go:  ld    s1, TC_SC(s0)             ; ...
        ld    t0, TC_MODE(s0)           ; typing a command?
        bnez  t0, tt_type               ; ...
        lbu   t0, 0(s1)                 ; the line's first byte
        li    t1, '#'                   ; the end
        beq   t0, t1, tt_ret            ; ...
        li    t1, '%'                   ; the prompt, and the end
        bne   t1, t0, tt_pause          ; ...
        ld    a0, TC_TERM(s0)           ; ...
        ld    a1, TC_PROMPT(s0)         ; ...
        ld    a2, TC_PROMPTN(s0)        ; ...
        call  term_write                ; ...
        la    s1, tc_end                ; (from now on: the end)
        j     tt_save                   ; ...
tt_pause:
        li    t1, '~'                   ; a pause
        bne   t0, t1, tt_cmd            ; ...
        li    t0, 30                    ; ...
        sd    t0, TC_WAIT(s0)           ; ...
        addi  s1, s1, 2                 ; (past "~\n")
        j     tt_save                   ; ...
tt_cmd: li    t1, '$'                   ; a command?
        bne   t0, t1, tt_out            ; ...
        ld    a0, TC_TERM(s0)           ; the prompt
        ld    a1, TC_PROMPT(s0)         ; ...
        ld    a2, TC_PROMPTN(s0)        ; ...
        call  term_write                ; ...
        addi  s1, s1, 2                 ; (past "$ ")
        li    t0, 1                     ; now type it
        sd    t0, TC_MODE(s0)           ; ...
        li    t0, 12                    ; after a moment
        sd    t0, TC_WAIT(s0)           ; ...
        j     tt_save                   ; ...
tt_type:
        lbu   a1, 0(s1)                 ; the next character
        addi  s1, s1, 1                 ; ...
        ld    a0, TC_TERM(s0)           ; ...
        call  term_putc                 ; ...
        lbu   t0, -1(s1)                ; the end of the command?
        li    t1, '\n'                  ; ...
        bne   t0, t1, tt_t2             ; ...
        sd    zero, TC_MODE(s0)         ; yes: it "runs" for a moment
        li    t0, 8                     ; ...
        sd    t0, TC_WAIT(s0)           ; ...
        j     tt_save                   ; ...
tt_t2:  li    t0, 1                     ; one frame per character (two now and then)
        sd    t0, TC_WAIT(s0)           ; ...
        andi  t0, s1, 3                 ; ...
        beqz  t0, tt_save               ; ...
        sd    zero, TC_WAIT(s0)         ; ...
        j     tt_save                   ; ...
tt_out: mv    a1, s1                    ; an output line: up to its newline
tt_o1:  lbu   t0, 0(s1)                 ; ...
        addi  s1, s1, 1                 ; ...
        li    t1, '\n'                  ; ...
        bne   t0, t1, tt_o1             ; ...
        sub   a2, s1, a1                ; ...
        ld    a0, TC_TERM(s0)           ; ...
        call  term_write                ; ...
tt_save:
        sd    s1, TC_SC(s0)             ; ...
tt_ret: ld    ra, 0(sp)                 ; restore
        ld    s0, 8(sp)                 ; ...
        ld    s1, 16(sp)                ; ...
        addi  sp, sp, 24                ; pop the frame
        ret                             ; done

