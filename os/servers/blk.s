; =============================================================================
; blk.s: the block device server
; =============================================================================
;
; A user-mode server (pid 4, created by the kernel at boot as the second
; server of pipe's core, index 1: doc/fs-split.md). It is the only program
; that talks to the block device: at start it asks dev for a window on the
; device's ports and an endpoint to the device's node (GETDISK); in a guest
; StrataOS dev gives it memory instead, the RAM disk, whose blocks are copied.
; It keeps no cache: the store's pages are cached by db, which is the one
; program that reads and writes through it.
;
;   1 BREAD   handle = first block, length = blocks, mode = byte offset in the
;             attachment (a buffer lent with the request) -> 0, or the
;             device's status; the buffer goes back with the reply
;   2 BWRITE  the same, from the buffer to the disk
;   3 FLUSH   -> 0: what the device holds back is on the disk
;   5 WRITEV  data = runs {u64 first block, u64 blocks, u64 byte offset}, each
;             written from the attachment, then (mode bit 0) a FLUSH -> 0, or
;             the first status that is not; the buffer goes back
;   4 INFO    -> 2; data: u64 blocks, u64 1 for a RAM disk
;  33 READBLK handle = block -> 512; data: the block (anyone)
;  36 DUPS / 37 CLEANUP / 38 CANCEL from proc: nothing to do
; BREAD, BWRITE and FLUSH are taken from db only (its pid, a0 at start).
; A run of blocks goes to the device in commands of at most 256 blocks; the
; device moves the bytes straight into the lent buffer (db's page frames, or
; the arena of a program being loaded), so nothing is copied here.
;
; Capability registers: c0 the rest of the arena, c1 the device window (or
; the RAM disk), c2 the device endpoint, c4 a buffer of our own (READBLK),
; c5 the message buffer, c6 the request, c7 its attachment.

SVC_WAIT = 1                            ; svc: wait for a buffer to come back
SVC_RECV = 2                            ; svc: receive a request
SVC_REPLY = 3                           ; svc: answer one
BLK_SQ  = 0x100                         ; submission port
BLK_CQ  = 0x200                         ; completion port
RDB     = 128                           ; the RAM disk's bounce buffer

        .data                           ; data Local Store
        .align 8                        ; ...
dbpid:  .dword 0                        ; db's pid: the one that may read and write
rdisk:  .dword 0                        ; 1: a RAM disk (c1: memory, no endpoint)
total:  .dword 0                        ; disk blocks
cid:    .dword 0                        ; command counter
cmd:    .space 32                       ; a block-device command
cqe:    .space 16                       ; its completion
ident:  .space 64                       ; the device's identify data
sys_buf: .space 64                      ; (srv.s: DUPS's data)
rdbuf:  .space RDB                      ; the RAM disk's bounce buffer
blkb:   .space 512                      ; READBLK's block
wvb:    .space 4032                     ; WRITEV's runs

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        andi  t0, a0, 255               ; db's pid
        sd    t0, dbpid(zero)           ; ...
        cclear c7                       ; (the clock: not used here; c7 is a request's attachment)
gd_ask:
        la    t0, srv_hdr               ; one message of our own: GETDISK to dev (c1)
        li    t1, 30                    ; ...
        sd    t1, 0(t0)                 ; ...
        sd    zero, 8(t0)               ; ...
        sd    zero, 16(t0)              ; ...
        sd    zero, 24(t0)              ; ...
        sd    zero, 32(t0)              ; ...
        li    t1, 64                    ; the header -> our message buffer
        tput  tg10, t0, c5, zero, t1    ; ...
        twait 1 << 10                   ; ...
        li    a0, 12                    ; SEND through c1, nothing attached
        li    a1, 1                     ; ...
        li    a2, -1                    ; ...
        li    a3, 0                     ; ...
        li    a4, 5                     ; ...
        li    a5, -1                    ; ...
        svc                             ; ...
        bnez  a0, gd_ask                ; (woken early: ask again)
        la    t0, srv_hdr               ; answered?
        li    t1, 64                    ; ...
        tget  tg10, t0, c5, zero, t1    ; ...
        twait 1 << 10                   ; ...
        ld    t1, 32(t0)                ; ...
        beqz  t1, gd_got                ; ...
        li    a0, SVC_WAIT              ; -1: dev was not there yet (it is made at
        li    a1, -1                    ;   the same time): a tick, then again
        li    a2, 1                     ; ...
        li    a3, -1                    ; ...
        svc                             ; ...
        j     gd_ask                    ; ...
gd_got:
        cclear c1                       ; dev's endpoint is not needed any more
        cmov  c1, c6                    ; c1 = the device window
        cvalid t0, c7                   ; (a RAM disk comes alone)
        beqz  t0, m_noep                ; ...
        cmov  c2, c7                    ; c2 = the device endpoint
m_noep:
        cperms t0, c1                   ; memory, not a device: a RAM disk
        srli  t0, t0, 8                 ; ...
        li    t1, 3                     ; ...
        bne   t0, t1, m_dev             ; ...
        li    t0, 1                     ; ...
        sd    t0, rdisk(zero)           ; ...
m_dev:
        li    t0, 0x40000               ; a buffer of our own: the top of our memory
        csplit c4, c0, t0               ; c0 = [0, 0x40000), c4 = the rest
        clen  t1, c1                    ; capacity: a RAM disk's length,
        srli  t1, t1, 9                 ; ...
        ld    t0, rdisk(zero)           ; ...
        bnez  t0, m_total               ; ...
        la    t0, ident                 ;   or from the identify data
        li    t1, 64                    ; ...
        tget  tg1, t0, c1, zero, t1     ; ...
        twait 1 << 1                    ; ...
        ld    t1, 8(t0)                 ; ...
m_total:
        sd    t1, total(zero)           ; ...
        la    a0, loop                  ; a fault on a dead request returns to the loop
        call  srv_guard                 ; ...
loop:
        li    a0, 0                     ; no device tags
        li    a1, -1                    ; no timeout
        call  srv_recv                  ; ...
        bltz  a0, loop                  ; ...
        la    t0, srv_hdr               ; dispatch
        ld    t1, 0(t0)                 ; ...
        li    t2, 33                    ; READBLK
        beq   t1, t2, op_readblk        ; ...
        li    t2, 4                     ; INFO
        beq   t1, t2, op_info           ; ...
        li    t2, OP_DUPS               ; nothing to count
        beq   t1, t2, ok                ; ...
        li    t2, OP_CLEANUP            ; ...
        beq   t1, t2, ok                ; ...
        li    t2, OP_CANCEL             ; ...
        beq   t1, t2, ok                ; ...
        ld    t3, 40(t0)                ; the rest: db only
        ld    t4, dbpid(zero)           ; ...
        bne   t3, t4, bad               ; ...
        li    t2, 3                     ; FLUSH
        beq   t1, t2, op_flush          ; ...
        li    t2, 1                     ; BREAD, BWRITE
        beq   t1, t2, op_rw             ; ...
        li    t2, 2                     ; ...
        beq   t1, t2, op_rw             ; ...
        li    t2, 5                     ; WRITEV
        beq   t1, t2, op_wv             ; ...
bad:
        li    a0, -1                    ; unknown, or refused
reply:
        li    a1, 0                     ; no attachment
        cvalid t0, c7                   ; (one that came goes back)
        beqz  t0, rp_go                 ; ...
        li    a1, 1                     ; ...
rp_go:
        call  srv_reply                 ; ...
        j     loop                      ; ...
ok:
        li    a0, 0                     ; ...
        j     reply                     ; ...

; ---- BREAD / BWRITE: a run of blocks, into or out of the attachment ----------------
op_rw:
        cvalid t2, c7                   ; a buffer must come with it
        beqz  t2, bad                   ; ...
        mv    a0, t1                    ; op
        ld    a1, 8(t0)                 ; first block
        ld    a2, 16(t0)                ; blocks
        ld    a3, 24(t0)                ; offset in the buffer
        add   t2, a1, a2                ; inside the disk?
        ld    t3, total(zero)           ; ...
        bltu  t2, a1, bad               ; ...
        bgtu  t2, t3, bad               ; ...
        li    a4, 7                     ; the attachment
        call  blkn                      ; ...
        j     reply                     ; ...

; ---- WRITEV: runs of blocks out of the attachment, then a flush ------------------------
op_wv:
        cvalid t2, c7                   ; the buffer must come with it
        beqz  t2, bad                   ; ...
        ld    s1, 16(t0)                ; s1 = the runs' bytes
        li    t1, 4032                  ; ...
        bgtu  s1, t1, bad               ; ...
        la    a0, wvb                   ; ...
        mv    a1, s1                    ; ...
        call  srv_get                   ; ...
        la    s2, wvb                   ; s2 = the run
        add   s1, s1, s2                ; s1 = the end
owv_l:
        addi  t0, s2, 24                ; ...
        bgtu  t0, s1, owv_f             ; ...
        ld    a1, 0(s2)                 ; ...
        ld    a2, 8(s2)                 ; ...
        ld    a3, 16(s2)                ; ...
        add   t2, a1, a2                ; inside the disk?
        ld    t3, total(zero)           ; ...
        bltu  t2, a1, bad               ; ...
        bgtu  t2, t3, bad               ; ...
        li    a0, 2                     ; ...
        li    a4, 7                     ; ...
        call  blkn                      ; ...
        bnez  a0, reply                 ; ...
        addi  s2, s2, 24                ; ...
        j     owv_l                     ; ...
owv_f:
        la    t0, srv_hdr               ; then a flush?
        ld    t1, 24(t0)                ; ...
        andi  t1, t1, 1                 ; ...
        li    a0, 0                     ; ...
        beqz  t1, reply                 ; ...

; ---- FLUSH --------------------------------------------------------------------------
op_flush:
        li    a0, 3                     ; ...
        li    a1, 0                     ; ...
        li    a2, 0                     ; ...
        li    a3, 0                     ; ...
        li    a4, 4                     ; (our own buffer: no bytes move)
        call  blk                       ; ...
        j     reply                     ; ...

; ---- INFO ---------------------------------------------------------------------------
op_info:
        la    t0, ident                 ; blocks, RAM disk
        ld    t1, total(zero)           ; ...
        sd    t1, 0(t0)                 ; ...
        ld    t1, rdisk(zero)           ; ...
        sd    t1, 8(t0)                 ; ...
        mv    a0, t0                    ; ...
        li    a1, 16                    ; ...
        call  srv_put                   ; ...
        la    t0, srv_hdr               ; ...
        li    t1, 16                    ; ...
        sd    t1, 16(t0)                ; ...
        li    a0, 2                     ; ...
        j     reply                     ; ...

; ---- READBLK: one block, raw ----------------------------------------------------------
op_readblk:
        ld    a1, 8(t0)                 ; the block
        ld    t1, total(zero)           ; ...
        bgeu  a1, t1, bad               ; ...
        li    a0, 1                     ; read it into our buffer (c4)
        li    a2, 1                     ; ...
        li    a3, 0                     ; ...
        li    a4, 4                     ; ...
        call  blk                       ; ...
        bnez  a0, rb_fail               ; ...
        la    t0, blkb                  ; -> the reply
        li    t1, 512                   ; ...
        tget  tg1, t0, c4, zero, t1     ; ...
        twait 1 << 1                    ; ...
        mv    a0, t0                    ; ...
        li    a1, 512                   ; ...
        call  srv_put                   ; ...
        la    t0, srv_hdr               ; ...
        li    t1, 512                   ; ...
        sd    t1, 16(t0)                ; ...
        li    a0, 512                   ; ...
        j     reply                     ; ...
rb_fail:
        li    a0, -5                    ; ...
        j     reply                     ; ...

; =============================================================================
; The device
; =============================================================================

; blk(a0 = op 1 read / 2 write / 3 flush, a1 = first block, a2 = blocks (<=
; 256), a3 = byte offset in the buffer, a4 = 4: our own buffer (c4) / 7: the
; attachment) -> a0 = status (0 = ok)
blk:
        ld    t0, rdisk(zero)           ; a RAM disk?
        bnez  t0, blk_ram               ; ...
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a4, 8(sp)                 ; ...
        la    t0, cmd                   ; build the command
        sb    a0, 0(t0)                 ; op
        csrr  t1, coreid                ; the buffer comes back to this core
        sb    t1, 1(t0)                 ; ...
        la    t2, cid                   ; command id
        ld    t1, 0(t2)                 ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, 0(t2)                 ; ...
        sh    t1, 2(t0)                 ; ...
        sw    a2, 4(t0)                 ; blocks
        sd    a1, 8(t0)                 ; first block
        sd    a3, 16(t0)                ; offset in the buffer
        sd    zero, 24(t0)              ; ...
        li    t1, BLK_SQ                ; -> the submission port
        li    t2, 32                    ; ...
        tput  tg1, t0, c1, t1, t2       ; ...
        twait 1 << 1                    ; (the command first)
        li    t0, 7                     ; which buffer?
        beq   a4, t0, blk_att           ; ...
        cbase a3, c4                    ; our own: lend it
        csend c4, c2                    ; ...
        j     blk_wait                  ; ...
blk_att:
        cbase a3, c7                    ; the attachment: lend it on
        csend c7, c2                    ; ...
blk_wait:
        li    a0, SVC_WAIT              ; wait until the device gives it back
        li    a1, -1                    ; (no doorbell: the device is not a core)
        li    a2, -1                    ; no timeout
        ld    a4, 8(sp)                 ; back into the same register
        svc                             ; ...
        la    t0, cqe                   ; the completion
        li    t1, BLK_CQ                ; ...
        li    t2, 16                    ; ...
        tget  tg1, t0, c1, t1, t2       ; ...
        twait 1 << 1                    ; ...
        lhu   a0, 2(t0)                 ; status
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; the RAM disk (c1): its blocks to or from the buffer, through rdbuf
blk_ram:
        slli  t0, a1, 9                 ; t0 = where on the disk
        slli  t1, a2, 9                 ; t1 = bytes left
        mv    t2, a3                    ; t2 = where in the buffer
        la    t3, rdbuf                 ; ...
        li    t4, RDB                   ; RDB bytes at a time
brm_l:
        beqz  t1, brm_done              ; (a flush: nothing)
        li    t5, 2                     ; a write?
        beq   a0, t5, brm_w             ; ...
        tget  tg1, t3, c1, t0, t4       ; read: disk -> D-LS -> buffer (in issue order)
        li    t5, 7                     ; ...
        beq   a4, t5, brm_r7            ; ...
        tput  tg1, t3, c4, t2, t4       ; ...
        j     brm_n                     ; ...
brm_r7:
        tput  tg1, t3, c7, t2, t4       ; ...
        j     brm_n                     ; ...
brm_w:
        li    t5, 7                     ; write: buffer -> D-LS -> disk
        beq   a4, t5, brm_w7            ; ...
        tget  tg1, t3, c4, t2, t4       ; ...
        j     brm_wd                    ; ...
brm_w7:
        tget  tg1, t3, c7, t2, t4       ; ...
brm_wd:
        tput  tg1, t3, c1, t0, t4       ; ...
brm_n:
        add   t0, t0, t4                ; ...
        add   t2, t2, t4                ; ...
        sub   t1, t1, t4                ; ...
        j     brm_l                     ; ...
brm_done:
        twait 1 << 1                    ; ...
        li    a0, 0                     ; ...
        ret                             ; ...

; blkn(a0 = op, a1 = first block, a2 = blocks (any), a3 = offset, a4 = buffer)
; -> a0 = status: several commands of at most 256 blocks
blkn:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        sd    a2, 24(sp)                ; ...
        sd    a3, 32(sp)                ; ...
        sd    a4, 40(sp)                ; ...
bn_l:
        ld    a2, 24(sp)                ; blocks left
        li    a0, 0                     ; (none: ok)
        beqz  a2, bn_ret                ; ...
        li    t0, 256                   ; at most 256
        bleu  a2, t0, bn_n              ; ...
        mv    a2, t0                    ; ...
bn_n:
        ld    t0, 24(sp)                ; ...
        sub   t0, t0, a2                ; ...
        sd    t0, 24(sp)                ; ...
        ld    a0, 8(sp)                 ; ...
        ld    a1, 16(sp)                ; ...
        add   t0, a1, a2                ; ...
        sd    t0, 16(sp)                ; ...
        ld    a3, 32(sp)                ; ...
        slli  t0, a2, 9                 ; ...
        add   t0, a3, t0                ; ...
        sd    t0, 32(sp)                ; ...
        ld    a4, 40(sp)                ; ...
        call  blk                       ; ...
        beqz  a0, bn_l                  ; ...
bn_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; ...

        .include "../lib/srv.s"         ; the server loop's helpers
