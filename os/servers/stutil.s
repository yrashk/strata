        .text                           ; instruction Local Store

; bswap(a0) -> a0: its eight bytes in the other order
bswap:
        li    t0, 8                     ; ...
        li    t1, 0                     ; ...
bsw_l:
        slli  t1, t1, 8                 ; ...
        andi  t2, a0, 255               ; ...
        or    t1, t1, t2                ; ...
        srli  a0, a0, 8                 ; ...
        addi  t0, t0, -1                ; ...
        bnez  t0, bsw_l                 ; ...
        mv    a0, t1                    ; ...
        ret                             ; ...

; wcopy(a0 = to, a1 = from, a2 = bytes, a multiple of 8): forwards, by words
wcopy:
        add   a2, a2, a1                ; the end
wc_l:
        beq   a1, a2, wc_ret            ; ...
        ld    t0, 0(a1)                 ; ...
        sd    t0, 0(a0)                 ; ...
        addi  a1, a1, 8                 ; ...
        addi  a0, a0, 8                 ; ...
        j     wc_l                      ; ...
wc_ret:
        ret                             ; ...

; wzero(a0 = address, a1 = bytes, a multiple of 8)
wzero:
        add   a1, a1, a0                ; the end
wz_l:
        beq   a0, a1, wz_ret            ; ...
        sd    zero, 0(a0)               ; ...
        addi  a0, a0, 8                 ; ...
        j     wz_l                      ; ...
wz_ret:
        ret                             ; ...

; kcmp(a0 = a key, a1 = its length, a2 = another, a3 = its length) -> a0 < 0,
; 0, > 0: as bytes, the shorter first when one begins the other
kcmp:
        mv    t0, a1                    ; the shorter length
        bleu  a1, a3, kc_l              ; ...
        mv    t0, a3                    ; ...
kc_l:
        beqz  t0, kc_len                ; equal so far
        lbu   t1, 0(a0)                 ; ...
        lbu   t2, 0(a2)                 ; ...
        bne   t1, t2, kc_diff           ; ...
        addi  a0, a0, 1                 ; ...
        addi  a2, a2, 1                 ; ...
        addi  t0, t0, -1                ; ...
        j     kc_l                      ; ...
kc_len:
        sub   a0, a1, a3                ; ...
        ret                             ; ...
kc_diff:
        sub   a0, t1, t2                ; ...
        ret                             ; ...

