; =============================================================================
; pipe.s: the pipe server
; =============================================================================
;
; A user-mode server (started by proc at boot). It owns up to 8 pipes, each
; a 2 KiB ring buffer in this server's own data memory. Handles: the read end
; of pipe p is id 2p + 1, the write end 2p + 2.
;
;   8 PIPE   -> read id | write id << 8
;   1 READ   handle, length, mode bit0 = do not block -> bytes (0 = end: no
;            writer left); a reader with nothing to read waits (parked)
;   2 WRITE  handle, length, data -> bytes taken (at least 1; the library
;            writes the rest); -1 if no reader is left; a writer waits while full
;   4 CLOSE  handle -> 0
;   36 DUPS / 37 CLEANUP / 38 CANCEL from proc (see srv.s)
;
; The ends are reference counted per (process, id): the pipe sees end of
; input when no write reference is left, and a writer gets -1 when no read
; reference is left. Each pipe holds at most one waiting reader and one
; waiting writer (another one gets -7, busy).

NPIPE = 8                               ; pipes
RING  = 2048                            ; bytes per pipe
P_USED = 0                              ; pipe record (64 bytes): in use
P_RPOS = 8                              ; read position in the ring
P_CNT  = 16                             ; bytes in the ring
P_RPARK = 24                            ; parked reader: park id + 1 (0 = none)
P_RTOK = 32                             ; its token
P_RPID = 40                             ; its pid
P_RLEN = 48                             ; its wanted length
P_WPARK = 56                            ; parked writer: park id + 1
P_WTOK = 64                             ; its token
P_WPID = 72                             ; its pid
P_SIZE = 80                             ; ...

        .data                           ; data Local Store
        .align 8                        ; ...
pipes:  .space NPIPE * P_SIZE           ; the pipe records
rings:  .space NPIPE * RING             ; the ring buffers
bounce: .space 4096                     ; staging for message data
cur_p:  .dword 0                        ; the pipe being served
cur_end: .dword 0                       ; 0 read end, 1 write end

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        li    sp, 65536                 ; stack at the top of the D-LS
        call  sys_init                  ; (handles: none needed)
        la    a0, loop                  ; a fault on a dead request returns to the loop
        call  srv_guard                 ; ...
loop:
        li    a0, 0                     ; no device tags
        li    a1, -1                    ; no timeout
        call  srv_recv                  ; a0 = token
        bltz  a0, loop                  ; (nothing: again)
        la    t0, srv_hdr               ; dispatch on the op
        ld    t1, 0(t0)                 ; ...
        li    t2, 8                     ; PIPE
        beq   t1, t2, op_pipe           ; ...
        li    t2, 1                     ; READ
        beq   t1, t2, op_read           ; ...
        li    t2, 2                     ; WRITE
        beq   t1, t2, op_write          ; ...
        li    t2, 4                     ; CLOSE
        beq   t1, t2, op_close          ; ...
        li    t2, OP_DUPS               ; DUPS
        beq   t1, t2, op_dups           ; ...
        li    t2, OP_CLEANUP            ; CLEANUP
        beq   t1, t2, op_cleanup        ; ...
        li    t2, OP_CANCEL             ; CANCEL
        beq   t1, t2, op_cancel         ; ...
        li    a0, -1                    ; unknown
reply:
        li    a1, 0                     ; no attachments
        call  srv_reply                 ; ...
        j     loop                      ; next request

; ---- helpers -----------------------------------------------------------------------------
; precp(a0 = pipe) -> a0 = its record
precp:
        li    t0, P_SIZE                ; ...
        mul   a0, a0, t0                ; ...
        la    t0, pipes                 ; ...
        add   a0, a0, t0                ; ...
        ret                             ; ...

; decode(a0 = id) -> a0 = 0 and cur_p / cur_end set, or -1 if not a pipe end in use
decode:
        addi  a0, a0, -1                ; id - 1 = 2p + end
        li    t0, NPIPE * 2             ; ...
        bgeu  a0, t0, dc_bad            ; ...
        srli  t1, a0, 1                 ; p
        andi  t2, a0, 1                 ; end
        la    t3, cur_p                 ; ...
        sd    t1, 0(t3)                 ; ...
        la    t3, cur_end               ; ...
        sd    t2, 0(t3)                 ; ...
        li    t0, P_SIZE                ; in use?
        mul   t1, t1, t0                ; ...
        la    t0, pipes                 ; ...
        add   t1, t1, t0                ; ...
        ld    t2, P_USED(t1)            ; ...
        beqz  t2, dc_bad                ; ...
        li    a0, 0                     ; ...
        ret                             ; ...
dc_bad:
        li    a0, -1                    ; ...
        ret                             ; ...

; ends(a0 = pipe) -> a0 = read references, a1 = write references
ends:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        slli  a0, a0, 1                 ; read id 2p + 1
        addi  a0, a0, 1                 ; ...
        call  ref_count                 ; ...
        sd    a0, 16(sp)                ; ...
        ld    a0, 8(sp)                 ; write id 2p + 2
        slli  a0, a0, 1                 ; ...
        addi  a0, a0, 2                 ; ...
        call  ref_count                 ; ...
        mv    a1, a0                    ; ...
        ld    a0, 16(sp)                ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; ---- PIPE ------------------------------------------------------------------------------------
op_pipe:
        li    s1, 0                     ; a free pipe
pp_f:
        li    t0, NPIPE                 ; ...
        bge   s1, t0, pp_none           ; none
        mv    a0, s1                    ; ...
        call  precp                     ; ...
        ld    t0, P_USED(a0)            ; ...
        beqz  t0, pp_take               ; ...
        addi  s1, s1, 1                 ; ...
        j     pp_f                      ; ...
pp_take:
        mv    s2, a0                    ; s2 = its record
        li    t0, P_SIZE / 8            ; clear it
        mv    t1, s2                    ; ...
pp_z:
        sd    zero, 0(t1)               ; ...
        addi  t1, t1, 8                 ; ...
        addi  t0, t0, -1                ; ...
        bnez  t0, pp_z                  ; ...
        li    t0, 1                     ; in use
        sd    t0, P_USED(s2)            ; ...
        call  srv_pid                   ; the caller holds both ends
        mv    s3, a0                    ; ...
        slli  a1, s1, 1                 ; read id
        addi  a1, a1, 1                 ; ...
        call  ref_add                   ; ...
        bltz  a0, pp_full               ; ...
        mv    a0, s3                    ; write id
        slli  a1, s1, 1                 ; ...
        addi  a1, a1, 2                 ; ...
        call  ref_add                   ; ...
        bltz  a0, pp_full               ; ...
        slli  a0, s1, 1                 ; result: read id | write id << 8
        addi  a0, a0, 1                 ; ...
        addi  t0, a0, 1                 ; ...
        slli  t0, t0, 8                 ; ...
        or    a0, a0, t0                ; ...
        j     reply                     ; ...
pp_full:
        mv    a0, s3                    ; undo
        slli  a1, s1, 1                 ; ...
        addi  a1, a1, 1                 ; ...
        call  ref_del                   ; ...
        sd    zero, P_USED(s2)          ; ...
pp_none:
        li    a0, -6                    ; no pipe left
        j     reply                     ; ...

; ---- READ -----------------------------------------------------------------------------------
op_read:
        la    t0, srv_hdr               ; the end
        ld    a0, 8(t0)                 ; ...
        call  decode                    ; ...
        bltz  a0, reply                 ; not a pipe (-1)
        la    t0, cur_end        ; (address)
        ld    t0, 0(t0)                             ; must be a read end
        bnez  t0, rd_bad                ; ...
        la    s1, cur_p          ; (address)
        ld    s1, 0(s1)                               ; s1 = pipe
        mv    a0, s1                    ; s2 = record
        call  precp                     ; ...
        mv    s2, a0                    ; ...
        la    t0, srv_hdr               ; wanted length
        ld    a0, 16(t0)                ; ...
        call  try_read                  ; a0 = bytes, 0 at end, -3 nothing yet
        li    t0, -3                    ; nothing yet?
        bne   a0, t0, rd_done           ; no: answered
        la    t0, srv_hdr               ; do-not-block?
        ld    t1, 24(t0)                ; ...
        andi  t1, t1, 1                 ; ...
        bnez  t1, rd_done               ; yes: -3
        ld    t0, P_RPARK(s2)           ; one waiting reader per pipe
        bnez  t0, rd_busy               ; ...
        la    t0, srv_hdr               ; remember what it wants
        ld    t1, 16(t0)                ; ...
        sd    t1, P_RLEN(s2)            ; ...
        ld    t1, 40(t0)                ; ...
        sd    t1, P_RPID(s2)            ; ...
        la    t1, srv_tok        ; (address)
        ld    t1, 0(t1)                             ; ...
        sd    t1, P_RTOK(s2)            ; ...
        call  srv_park                  ; the kernel keeps the buffer
        bltz  a0, rd_busy               ; no room
        addi  a0, a0, 1                 ; ...
        sd    a0, P_RPARK(s2)           ; ...
        j     loop                      ; no answer yet
rd_done:
        call  srv_reply0                ; answer
        mv    a0, s1                    ; a waiting writer may go on
        call  wake_writer               ; ...
        j     loop                      ; ...
rd_busy:
        li    a0, -7                    ; busy
        j     reply                     ; ...
rd_bad:
        li    a0, -1                    ; ...
        j     reply                     ; ...

; srv_reply0(a0 = result): reply without attachments
srv_reply0:
        li    a1, 0                     ; ...
        j     srv_reply                 ; (tail call)

; try_read(a0 = wanted) (s1 = pipe, s2 = record, request in c6) -> a0 = bytes
; copied into the request's data, 0 at end of input, -3 if nothing to read yet
try_read:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s3, 8(sp)                 ; ...
        sd    s4, 16(sp)                ; ...
        mv    s3, a0                    ; s3 = wanted
        ld    t0, P_CNT(s2)             ; anything?
        bnez  t0, tr_data               ; yes
        mv    a0, s1                    ; a writer left?
        call  ends                      ; ...
        li    a0, 0                     ; no: end of input
        beqz  a1, tr_ret                ; ...
        li    a0, -3                    ; yes: wait
        j     tr_ret                    ; ...
tr_data:
        li    t1, SYS_MAX               ; at most one message
        bleu  s3, t1, tr_m              ; ...
        mv    s3, t1                    ; ...
tr_m:
        bleu  s3, t0, tr_n              ; and what is there
        mv    s3, t0                    ; ...
tr_n:
        beqz  s3, tr_zero               ; (asked for 0 bytes)
        li    s4, 0                     ; copy byte by byte out of the ring
tr_c:
        beq   s4, s3, tr_put            ; ...
        ld    t0, P_RPOS(s2)            ; ...
        slli  t1, s1, 11                ; ring p: rings + p * 2048
        la    t2, rings                 ; ...
        add   t1, t1, t2                ; ...
        add   t1, t1, t0                ; ...
        lbu   t1, 0(t1)                 ; ...
        la    t2, bounce                ; ...
        add   t2, t2, s4                ; ...
        sb    t1, 0(t2)                 ; ...
        addi  t0, t0, 1                 ; advance (wrapping)
        andi  t0, t0, RING - 1          ; ...
        sd    t0, P_RPOS(s2)            ; ...
        addi  s4, s4, 1                 ; ...
        j     tr_c                      ; ...
tr_put:
        ld    t0, P_CNT(s2)             ; fewer bytes in the ring
        sub   t0, t0, s3                ; ...
        sd    t0, P_CNT(s2)             ; ...
        la    a0, bounce                ; -> the request's data
        mv    a1, s3                    ; ...
        call  srv_put                   ; ...
tr_zero:
        mv    a0, s3                    ; ...
tr_ret:
        ld    s4, 16(sp)                ; ...
        ld    s3, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; ---- WRITE ----------------------------------------------------------------------------------
op_write:
        la    t0, srv_hdr               ; the end
        ld    a0, 8(t0)                 ; ...
        call  decode                    ; ...
        bltz  a0, reply                 ; ...
        la    t0, cur_end        ; (address)
        ld    t0, 0(t0)                             ; must be a write end
        beqz  t0, rd_bad                ; ...
        la    s1, cur_p          ; (address)
        ld    s1, 0(s1)                               ; ...
        mv    a0, s1                    ; ...
        call  precp                     ; ...
        mv    s2, a0                    ; ...
        la    t0, srv_hdr               ; length
        ld    a0, 16(t0)                ; ...
        call  try_write                 ; a0 = taken, -1 no reader, -3 full
        li    t0, -3                    ; full?
        bne   a0, t0, wr_done           ; no: answered
        la    t0, srv_hdr               ; do-not-block?
        ld    t1, 24(t0)                ; ...
        andi  t1, t1, 1                 ; ...
        bnez  t1, wr_done               ; ...
        ld    t0, P_WPARK(s2)           ; one waiting writer per pipe
        bnez  t0, rd_busy               ; ...
        la    t0, srv_hdr               ; ...
        ld    t1, 40(t0)                ; ...
        sd    t1, P_WPID(s2)            ; ...
        la    t1, srv_tok        ; (address)
        ld    t1, 0(t1)                             ; ...
        sd    t1, P_WTOK(s2)            ; ...
        call  srv_park                  ; ...
        bltz  a0, rd_busy               ; ...
        addi  a0, a0, 1                 ; ...
        sd    a0, P_WPARK(s2)           ; ...
        j     loop                      ; ...
wr_done:
        call  srv_reply0                ; answer
        mv    a0, s1                    ; a waiting reader may go on
        call  wake_reader               ; ...
        j     loop                      ; ...

; try_write(a0 = length) (s1, s2, request in c6) -> a0 = bytes taken, -1 no reader, -3 full
try_write:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s3, 8(sp)                 ; ...
        sd    s4, 16(sp)                ; ...
        mv    s3, a0                    ; s3 = length
        mv    a0, s1                    ; a reader left?
        call  ends                      ; ...
        bnez  a0, tw_room               ; yes
        li    a0, -1                    ; no: broken pipe
        j     tw_ret                    ; ...
tw_room:
        li    t1, SYS_MAX               ; at most one message
        bleu  s3, t1, tw_m              ; ...
        mv    s3, t1                    ; ...
tw_m:
        ld    t0, P_CNT(s2)             ; free space
        li    t1, RING                  ; ...
        sub   t1, t1, t0                ; ...
        bnez  t1, tw_some               ; ...
        li    a0, -3                    ; full
        bnez  s3, tw_ret                ; (a 0-byte write is always fine)
tw_some:
        bleu  s3, t1, tw_n              ; take what fits
        mv    s3, t1                    ; ...
tw_n:
        la    a0, bounce                ; the data -> D-LS
        mv    a1, s3                    ; ...
        call  srv_get                   ; ...
        li    s4, 0                     ; copy into the ring
tw_c:
        beq   s4, s3, tw_done           ; ...
        ld    t0, P_RPOS(s2)            ; write position = read position + count
        ld    t1, P_CNT(s2)             ; ...
        add   t0, t0, t1                ; ...
        andi  t0, t0, RING - 1          ; ...
        slli  t1, s1, 11                ; ...
        la    t2, rings                 ; ...
        add   t1, t1, t2                ; ...
        add   t1, t1, t0                ; ...
        la    t2, bounce                ; ...
        add   t2, t2, s4                ; ...
        lbu   t2, 0(t2)                 ; ...
        sb    t2, 0(t1)                 ; ...
        ld    t1, P_CNT(s2)             ; one more
        addi  t1, t1, 1                 ; ...
        sd    t1, P_CNT(s2)             ; ...
        addi  s4, s4, 1                 ; ...
        j     tw_c                      ; ...
tw_done:
        mv    a0, s3                    ; ...
tw_ret:
        ld    s4, 16(sp)                ; ...
        ld    s3, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; ---- waking parked requests ------------------------------------------------------------------
; wake_reader(a0 = pipe): retry its waiting reader (data arrived or the writers left)
wake_reader:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        mv    s1, a0                    ; ...
        call  precp                     ; ...
        mv    s2, a0                    ; ...
        ld    t0, P_USED(s2)            ; ...
        beqz  t0, wkr_ret               ; ...
        ld    t0, P_RPARK(s2)           ; a reader waits?
        beqz  t0, wkr_ret               ; no
        ld    t1, P_CNT(s2)             ; can it be answered now?
        bnez  t1, wkr_go                ; data
        mv    a0, s1                    ; or no writer left
        call  ends                      ; ...
        bnez  a1, wkr_ret               ; still writers, still empty
wkr_go:
        ld    a0, P_RPARK(s2)           ; take it back
        addi  a0, a0, -1                ; ...
        sd    zero, P_RPARK(s2)         ; ...
        call  srv_unpark                ; ...
        bnez  a0, wkr_ret               ; its owner died
        ld    t0, P_RTOK(s2)            ; its token
        la    t1, srv_tok               ; ...
        sd    t0, 0(t1)                 ; ...
        ld    a0, P_RLEN(s2)            ; read for it
        call  try_read                  ; ...
        call  srv_reply0                ; ...
        mv    a0, s1                    ; that made room for a writer
        call  wake_writer               ; ...
wkr_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; wake_writer(a0 = pipe): retry its waiting writer (room appeared or the readers left)
wake_writer:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        mv    s1, a0                    ; ...
        call  precp                     ; ...
        mv    s2, a0                    ; ...
        ld    t0, P_USED(s2)            ; ...
        beqz  t0, wkw_ret               ; ...
        ld    t0, P_WPARK(s2)           ; a writer waits?
        beqz  t0, wkw_ret               ; no
        ld    t1, P_CNT(s2)             ; room, or no reader left?
        li    t2, RING                  ; ...
        bltu  t1, t2, wkw_go            ; room
        mv    a0, s1                    ; ...
        call  ends                      ; ...
        bnez  a0, wkw_ret               ; readers, no room
wkw_go:
        ld    a0, P_WPARK(s2)           ; take it back
        addi  a0, a0, -1                ; ...
        sd    zero, P_WPARK(s2)         ; ...
        call  srv_unpark                ; ...
        bnez  a0, wkw_ret               ; gone
        ld    t0, P_WTOK(s2)            ; ...
        la    t1, srv_tok               ; ...
        sd    t0, 0(t1)                 ; ...
        la    t0, srv_hdr               ; its length
        ld    a0, 16(t0)                ; ...
        call  try_write                 ; ...
        call  srv_reply0                ; ...
        mv    a0, s1                    ; a reader may go on now
        call  wake_reader               ; ...
wkw_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; ---- CLOSE, DUPS, CLEANUP, CANCEL ---------------------------------------------------------------
op_close:
        call  srv_pid                   ; drop the caller's reference
        la    t0, srv_hdr               ; ...
        ld    a1, 8(t0)                 ; ...
        call  drop_ref                  ; ...
        li    a0, 0                     ; answer first,
        call  srv_reply0                ; ...
        j     after                     ; then wake the other end's waiters

; drop_ref(a0 = pid, a1 = id): remove one reference; the other end's waiter
; is answered after the current reply (wake_* use c6)
drop_ref:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a1, 8(sp)                 ; ...
        call  ref_del                   ; ...
        beqz  a0, drr_ret               ; it held none
        ld    a0, 8(sp)                 ; the pipe
        call  decode                    ; ...
        bltz  a0, drr_ret               ; ...
        la    t0, cur_p          ; (address)
        ld    t0, 0(t0)                               ; to wake after the reply
        la    t1, pend_wake             ; ...
        ld    t2, 0(t1)                 ; (a bit per pipe)
        li    t3, 1                     ; ...
        sll   t3, t3, t0                ; ...
        or    t2, t2, t3                ; ...
        sd    t2, 0(t1)                 ; ...
drr_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

op_dups:
        call  ref_dups                  ; ...
        j     reply                     ; ...

op_cleanup:
        la    t0, srv_hdr               ; the dead process
        ld    s1, 8(t0)                 ; ...
oc_l:
        mv    a0, s1                    ; any reference left?
        call  ref_first                 ; ...
        bltz  a0, oc_done               ; no
        mv    a1, a0                    ; drop it
        mv    a0, s1                    ; ...
        call  drop_ref                  ; ...
        j     oc_l                      ; ...
oc_done:
        li    a0, 0                     ; ...
        call  srv_reply0                ; answer
        j     after                     ; then the waiters

op_cancel:
        la    t0, srv_hdr               ; held requests of that process return -2
        ld    s3, 8(t0)                 ; s3 = pid
        li    a0, 0                     ; answer proc first
        call  srv_reply0                ; ...
        li    s1, 0                     ; every pipe
ocn_l:
        li    t0, NPIPE                 ; ...
        bge   s1, t0, loop              ; ...
        mv    a0, s1                    ; ...
        call  precp                     ; ...
        mv    s2, a0                    ; ...
        ld    t0, P_USED(s2)            ; ...
        beqz  t0, ocn_n                 ; ...
        ld    t0, P_RPARK(s2)           ; its reader?
        beqz  t0, ocn_w                 ; ...
        ld    t1, P_RPID(s2)            ; ...
        bne   t1, s3, ocn_w             ; ...
        addi  a0, t0, -1                ; ...
        sd    zero, P_RPARK(s2)         ; ...
        call  srv_unpark                ; ...
        bnez  a0, ocn_w                 ; ...
        ld    t0, P_RTOK(s2)            ; ...
        la    t1, srv_tok               ; ...
        sd    t0, 0(t1)                 ; ...
        li    a0, -2                    ; interrupted
        call  srv_reply0                ; ...
ocn_w:
        ld    t0, P_WPARK(s2)           ; its writer?
        beqz  t0, ocn_n                 ; ...
        ld    t1, P_WPID(s2)            ; ...
        bne   t1, s3, ocn_n             ; ...
        addi  a0, t0, -1                ; ...
        sd    zero, P_WPARK(s2)         ; ...
        call  srv_unpark                ; ...
        bnez  a0, ocn_n                 ; ...
        ld    t0, P_WTOK(s2)            ; ...
        la    t1, srv_tok               ; ...
        sd    t0, 0(t1)                 ; ...
        li    a0, -2                    ; ...
        call  srv_reply0                ; ...
ocn_n:
        addi  s1, s1, 1                 ; ...
        j     ocn_l                     ; ...

; after: wake the waiters of pipes whose references changed; free unused pipes
after:
        li    s1, 0                     ; every pipe marked
af_l:
        li    t0, NPIPE                 ; ...
        bge   s1, t0, af_done           ; ...
