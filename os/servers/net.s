        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        li    sp, 65536                 ; stack at the top of the D-LS
        call  sys_init                  ; ...
        call  sys_cmdline               ; the address: the second word
        add   s2, a0, a1                ; s2 = end
        mv    a1, s2                    ; skip the program's name
        call  arg_next                  ; ...
        mv    a0, a2                    ; ...
        mv    a1, s2                    ; ...
        call  arg_next                  ; a0 = word, a1 = length
        beqz  a1, m_use                 ; none
        call  net_aton                  ; ...
        bltz  a0, m_use                 ; not an address
        la    t0, myip                  ; ...
        sd    a0, 0(t0)                 ; ...
        la    a0, s_name                ; become "net"
        li    a1, 3                     ; ...
        call  sys_register              ; ...
        bnez  a0, m_busy                ; (another one runs)
        la    a0, sys_ndev              ; dev's endpoint into c4 (pipe is not needed)
        li    a1, 3                     ; ...
        li    a2, 4                     ; ...
        call  sys_lookup                ; ...
        bnez  a0, m_nodev               ; ...
        li    a0, 4                     ; GETNET: the interface's ports -> c6
        li    a1, OP_GETNET             ; ...
        li    a2, 0                     ; ...
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        call  sys_msg                   ; ...
        bnez  a0, m_nodev               ; ...
        cclear c4                       ; c4 = the ports (dev's endpoint is no longer needed)
        cmov  c4, c6                    ; ...
        cclear c6                       ; (c6 receives requests)
        la    a0, s_up                  ; "net: 10.0.0.1, link up"
        li    a1, s_up_e - s_up         ; ...
        call  out_str                   ; ...
        la    a0, myip                  ; (its address)
        ld    a0, 0(a0)                 ; ...
        call  out_ip                    ; ...
        call  nic_status                ; link?
        srli  t0, a0, 24                ; ...
        andi  t0, t0, 1                 ; ...
        la    a0, s_link                ; ...
        li    a1, s_link_e - s_link     ; ...
        bnez  t0, m_ban2                ; up
        la    a0, s_nolink              ; down
        li    a1, s_nolink_e - s_nolink ; ...
m_ban2:
        call  out_str                   ; ...
        call  out_flush                 ; ...
        la    a0, loop                  ; a fault on a dead request returns to the loop
        call  srv_guard                 ; ...
loop:
        la    t0, rxarm                 ; the RX read in flight (unless halting)
        ld    t0, 0(t0)                 ; ...
        bnez  t0, lp_w                  ; ...
        la    t0, rxstop                ; ...
        ld    t0, 0(t0)                 ; ...
        bnez  t0, lp_w                  ; ...
        call  arm_rx                    ; ...
lp_w:
        call  next_to                   ; a0 = ticks to the next timer, or -1
        mv    a1, a0                    ; ...
        la    t0, rxarm                 ; wait for: requests, a packet, the timer
        ld    a0, 0(t0)                 ; ...
        call  srv_recv                  ; ...
        bgez  a0, request               ; a request
        li    t0, -1                    ; device tags?
        bne   a0, t0, lp_tm             ; (no: the timer)
        andi  t0, a1, 1 << TG_RX        ; a packet?
        beqz  t0, lp_tm                 ; ...
        la    t0, rxarm                 ; (only if the read was in flight)
        ld    t1, 0(t0)                 ; ...
        beqz  t1, lp_tm                 ; ...
        sd    zero, 0(t0)               ; it completed
        call  ip_input                  ; handle it
lp_tm:
        call  timers                    ; whatever is due
        j     loop                      ; ...

m_use:
        la    a0, s_use                 ; ...
        li    a1, s_use_e - s_use       ; ...
        j     m_fail                    ; ...
m_busy:
        la    a0, s_busy                ; ...
        li    a1, s_busy_e - s_busy     ; ...
        j     m_fail                    ; ...
m_nodev:
        la    a0, s_nodev               ; ...
        li    a1, s_nodev_e - s_nodev   ; ...
m_fail:
        call  err_str                   ; ...
        li    a0, 1                     ; ...
        call  sys_exit                  ; ...

; ---- the device -----------------------------------------------------------------------------
; arm_rx(): a read of the RX port into rxpkt, completing when a packet arrives
arm_rx:
        la    t0, rxpkt                 ; ...
        li    t1, N_RX                  ; ...
        li    t2, RXLEN                 ; ...
        tget  tg1, t0, c4, t1, t2       ; stays in flight until a packet is there
        la    t0, rxarm                 ; ...
        li    t1, 1 << TG_RX            ; ...
        sd    t1, 0(t0)                 ; ...
        ret                             ; ...

; nic_status() -> a0 = the interface's STATUS register
nic_status:
        la    t0, stbuf                 ; ...
        li    t1, N_ST                  ; ...
        li    t2, 8                     ; ...
        tget  tg3, t0, c4, t1, t2       ; latched at byte 0
        twait 1 << TG_TX                ; ...
        ld    a0, 0(t0)                 ; ...
        ret                             ; ...

; now() -> a0 = ticks
now:
        j     sys_now                   ; (the clock in c7)

; ---- requests ---------------------------------------------------------------------------------
request:
        cclear c7                       ; (an attachment would be here: none is used)
        call  sys_clock                 ; the clock in c7 again
        la    t0, srv_hdr               ; dispatch on the op
        ld    t1, 0(t0)                 ; ...
        li    t2, OP_READ               ; ...
        beq   t1, t2, op_read           ; ...
        li    t2, OP_WRITE              ; ...
        beq   t1, t2, op_write          ; ...
        li    t2, OP_CLOSE              ; ...
        beq   t1, t2, op_close          ; ...
        li    t2, OP_NSTAT              ; ...
        beq   t1, t2, op_stat           ; ...
        li    t2, OP_NSETIP             ; ...
        beq   t1, t2, op_setip          ; ...
        li    t2, OP_NPING              ; ...
        beq   t1, t2, op_ping           ; ...
        li    t2, OP_NCONN              ; ...
        beq   t1, t2, op_conn           ; ...
        li    t2, OP_NLISTEN            ; ...
        beq   t1, t2, op_listen         ; ...
        li    t2, OP_NACCEPT            ; ...
        beq   t1, t2, op_accept         ; ...
        li    t2, OP_NUBIND             ; ...
        beq   t1, t2, op_ubind          ; ...
        li    t2, OP_NUSEND             ; ...
        beq   t1, t2, op_usend          ; ...
        li    t2, OP_NURECV             ; ...
        beq   t1, t2, op_urecv          ; ...
        li    t2, OP_DUPS               ; (sockets are not passed to children)
        beq   t1, t2, ok                ; ...
        li    t2, OP_CLEANUP            ; ...
        beq   t1, t2, op_cleanup        ; ...
        li    t2, OP_CANCEL             ; ...
        beq   t1, t2, op_cancel         ; ...
bad:
        li    a0, -1                    ; unknown / not yours
reply:
        li    a1, 0                     ; no attachments
        call  srv_reply                 ; ...
        j     loop                      ; ...
ok:
        li    a0, 0                     ; ...
        j     reply                     ; ...

; hdr_sock() -> a0 = the caller's socket named by the request's handle, or 0
hdr_sock:
        la    t0, srv_hdr               ; the id
        ld    a0, 8(t0)                 ; ...
        addi  t0, a0, -1                ; 1..NSOCK
        li    t1, NSOCK                 ; ...
        bgeu  t0, t1, hs_no             ; ...
        la    t1, socks                 ; its record
        slli  t0, t0, SSHIFT            ; ...
        add   t0, t1, t0                ; ...
        ld    t1, S_STATE(t0)           ; in use
        beqz  t1, hs_no                 ; ...
        ld    t1, S_FLAGS(t0)           ; not closed
        andi  t1, t1, SF_CLOSE          ; ...
        bnez  t1, hs_no                 ; ...
        la    t2, srv_hdr               ; the caller's
        ld    t2, 40(t2)                ; ...
        ld    t1, S_OWNER(t0)           ; ...
        bne   t1, t2, hs_no             ; ...
        mv    a0, t0                    ; ...
        ret                             ; ...
hs_no:
        li    a0, 0                     ; ...
        ret                             ; ...

; READ, WRITE, ACCEPT, RECVFROM: try now; if it would block, wait (park)
op_read:
        call  hdr_sock                  ; s1 = the socket
        beqz  a0, bad                   ; ...
        mv    s1, a0                    ; ...
        li    s2, OP_READ               ; ...
        call  try_read                  ; ...
        j     op_block                  ; ...
op_write:
        call  hdr_sock                  ; ...
        beqz  a0, bad                   ; ...
        mv    s1, a0                    ; ...
        li    s2, OP_WRITE              ; ...
        call  try_write                 ; ...
        j     op_block                  ; ...
op_accept:
        call  hdr_sock                  ; ...
        beqz  a0, bad                   ; ...
        mv    s1, a0                    ; ...
        li    s2, OP_NACCEPT            ; ...
        call  try_accept                ; ...
        j     op_block                  ; ...
op_urecv:
        call  hdr_sock                  ; ...
        beqz  a0, bad                   ; ...
        mv    s1, a0                    ; ...
        li    s2, OP_NURECV             ; ...
        call  try_urecv                 ; ...
op_block:
        li    t0, -3                    ; would block?
        bne   a0, t0, reply             ; no: answered
        la    t0, srv_hdr               ; do-not-block?
        ld    t1, 24(t0)                ; ...
        andi  t1, t1, 1                 ; ...
        bnez  t1, reply                 ; -3
        mv    a0, s1                    ; wait (s2 = the op to try again)
        mv    a1, s2                    ; ...
        call  park_on                   ; ...
        bnez  a0, reply                 ; (-7: busy)
        j     loop                      ; answered later

; CLOSE: answer first (c6 is then free for whatever closing wakes)
op_close:
        call  hdr_sock                  ; ...
        beqz  a0, bad                   ; ...
        mv    s1, a0                    ; ...
        la    t0, srv_hdr               ; shutdown only?
        ld    s2, 24(t0)                ; ...
        li    a0, 0                     ; ...
        li    a1, 0                     ; ...
        call  srv_reply                 ; ...
        andi  t0, s2, 1                 ; ...
        bnez  t0, ocl_shut              ; ...
        mv    a0, s1                    ; ...
        call  close_sock                ; ...
        j     loop                      ; ...
ocl_shut:
        ld    t0, S_PROTO(s1)           ; TCP only
        li    t1, 6                     ; ...
        bne   t0, t1, loop              ; ...
        ld    t0, S_FLAGS(s1)           ; no more sending
        ori   t0, t0, SF_SHUT           ; ...
        sd    t0, S_FLAGS(s1)           ; ...
        mv    a0, s1                    ; the FIN goes after the data
        call  tcp_output                ; ...
        j     loop                      ; ...

; SETIP
op_setip:
        la    t0, srv_hdr               ; ...
        ld    t1, 8(t0)                 ; ...
        slli  t1, t1, 32                ; 32 bits
        srli  t1, t1, 32                ; ...
        la    t0, myip                  ; ...
        sd    t1, 0(t0)                 ; ...
        j     ok                        ; ...

; LISTEN (handle = port)
op_listen:
        la    t0, srv_hdr               ; the port
        ld    s2, 8(t0)                 ; ...
        addi  t0, s2, -1                ; 1..65535
        li    t1, 65535                 ; ...
        bgeu  t0, t1, bad               ; ...
        mv    a0, s2                    ; in use?
        call  find_listen               ; ...
        bnez  a0, ol_busy               ; ...
        call  sock_alloc                ; ...
        beqz  a0, ol_full               ; ...
        mv    s1, a0                    ; ...
        li    t0, ST_LISTEN             ; ...
        sd    t0, S_STATE(s1)           ; ...
        li    t0, 6                     ; ...
        sd    t0, S_PROTO(s1)           ; ...
        sd    s2, S_LPORT(s1)           ; ...
        call  srv_pid                   ; ...
        sd    a0, S_OWNER(s1)           ; ...
        ld    a0, S_ID(s1)              ; the id
        j     reply                     ; ...
ol_busy:
        li    a0, -7                    ; ...
        j     reply                     ; ...
ol_full:
        li    a0, -6                    ; ...
        j     reply                     ; ...

; UDP (handle = port, 0 = any)
op_ubind:
        la    t0, srv_hdr               ; the port
        ld    s2, 8(t0)                 ; ...
        bnez  s2, oub_p                 ; ...
        call  new_port                  ; any: an ephemeral one
        mv    s2, a0                    ; ...
oub_p:
        li    t1, 65535                 ; ...
        bgtu  s2, t1, bad               ; ...
        mv    a0, s2                    ; in use?
        call  find_udp                  ; ...
        bnez  a0, ol_busy               ; ...
        call  sock_alloc                ; ...
        beqz  a0, ol_full               ; ...
        mv    s1, a0                    ; ...
        li    t0, ST_UDP                ; ...
        sd    t0, S_STATE(s1)           ; ...
        li    t0, 17                    ; ...
        sd    t0, S_PROTO(s1)           ; ...
        sd    s2, S_LPORT(s1)           ; ...
        call  srv_pid                   ; ...
        sd    a0, S_OWNER(s1)           ; ...
        ld    a0, S_ID(s1)              ; ...
        j     reply                     ; ...

; SENDTO: data u64 address, u64 port, payload
op_usend:
        call  hdr_sock                  ; ...
        beqz  a0, bad                   ; ...
        mv    s1, a0                    ; ...
        ld    t0, S_STATE(s1)           ; a UDP socket
        li    t1, ST_UDP                ; ...
        bne   t0, t1, bad               ; ...
        la    t0, srv_hdr               ; s2 = payload bytes
        ld    s2, 16(t0)                ; ...
        addi  s2, s2, -16               ; ...
        li    t1, 1472                  ; ...
        bgtu  s2, t1, bad               ; (also: less than 16 in all)
        la    a0, txpkt + 64            ; the data -> D-LS (aligned)
        addi  a1, s2, 16                ; ...
        call  srv_get                   ; ...
        la    t0, txpkt                 ; s3 = address, s4 = port
        ld    s3, 64(t0)                ; ...
        slli  s3, s3, 32                ; ...
        srli  s3, s3, 32                ; ...
        ld    s4, 72(t0)                ; ...
        la    a0, txpkt + 28            ; the payload after the IP and UDP headers
        la    a1, txpkt + 80            ; (an upward copy: the ranges overlap safely)
        mv    a2, s2                    ; ...
        call  srv_bcopy                 ; ...
        mv    a0, s1                    ; the header, the checksum, out
        mv    a1, s3                    ; ...
        mv    a2, s4                    ; ...
        mv    a3, s2                    ; ...
        call  udp_send                  ; ...
        mv    a0, s2                    ; ...
        j     reply                     ; ...

; CONNECT (handle = address, length = port)
op_conn:
        la    t0, srv_hdr               ; ...
        ld    s2, 8(t0)                 ; s2 = address
        slli  s2, s2, 32                ; ...
        srli  s2, s2, 32                ; ...
        ld    s3, 16(t0)                ; s3 = port
        addi  t1, s3, -1                ; 1..65535
        li    t2, 65535                 ; ...
        bgeu  t1, t2, bad               ; ...
        call  sock_alloc                ; ...
        beqz  a0, ol_full               ; ...
        mv    s1, a0                    ; ...
        li    t0, 6                     ; ...
        sd    t0, S_PROTO(s1)           ; ...
        sd    s2, S_RIP(s1)             ; ...
        sd    s3, S_RPORT(s1)           ; ...
        call  new_port                  ; ...
        sd    a0, S_LPORT(s1)           ; ...
        call  srv_pid                   ; ...
        sd    a0, S_OWNER(s1)           ; ...
        mv    a0, s1                    ; our sequence numbers
        call  new_iss                   ; ...
        li    t0, ST_SYNSENT            ; ...
        sd    t0, S_STATE(s1)           ; ...
        mv    a0, s1                    ; SYN
        li    a1, TF_SYN                ; ...
        ld    a2, S_ISS(s1)             ; ...
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        call  tcp_send                  ; ...
        mv    a0, s1                    ; the retransmission timer
        call  arm_rto                   ; ...
        mv    a0, s1                    ; wait for the answer
        li    a1, OP_NCONN              ; ...
        call  park_on                   ; ...
        beqz  a0, loop                  ; answered when established (or not)
        mv    s2, a0                    ; no room to wait: give up
        mv    a0, s1                    ; ...
        call  sock_free                 ; ...
        mv    a0, s2                    ; ...
        j     reply                     ; ...

; PING (handle = address, length = payload bytes, mode = timeout)
op_ping:
        la    t0, srv_hdr               ; s3 = payload bytes
        ld    s3, 16(t0)                ; ...
        li    t1, 1400                  ; ...
        bgtu  s3, t1, bad               ; ...
        la    s1, pings                 ; a free slot
        li    t0, NPING                 ; ...
opg_f:
        beqz  t0, ol_busy               ; none
        ld    t1, P_PK(s1)              ; ...
        beqz  t1, opg_take              ; ...
        addi  s1, s1, P_SIZE            ; ...
        addi  t0, t0, -1                ; ...
        j     opg_f                     ; ...
opg_take:
        la    t0, srv_hdr               ; destination, deadline
        ld    t1, 8(t0)                 ; ...
        slli  t1, t1, 32                ; ...
        srli  t1, t1, 32                ; ...
        sd    t1, P_IP(s1)              ; ...
        ld    t1, 40(t0)                ; asker
        sd    t1, P_PID(s1)             ; ...
        la    t0, pseq                  ; the next sequence number
        ld    t1, 0(t0)                 ; ...
        addi  t1, t1, 1                 ; ...
        andi  t1, t1, 0xffff            ; ...
        sd    t1, 0(t0)                 ; ...
        sd    t1, P_SEQ(s1)             ; ...
        la    s2, txpkt + 20            ; the echo request
        li    t0, 8                     ; type 8, code 0
        sb    t0, 0(s2)                 ; ...
        sb    zero, 1(s2)               ; ...
        sb    zero, 2(s2)               ; checksum 0 for now
        sb    zero, 3(s2)               ; ...
        addi  a0, s2, 4                 ; identifier
        li    a1, PING_ID               ; ...
        call  put16                     ; ...
        addi  a0, s2, 6                 ; sequence number
        ld    a1, P_SEQ(s1)             ; ...
        call  put16                     ; ...
        li    t0, 0                     ; payload: 0, 1, 2, ...
opg_d:
        beq   t0, s3, opg_s             ; ...
        add   t1, s2, t0                ; ...
        sb    t0, 8(t1)                 ; ...
        addi  t0, t0, 1                 ; ...
        j     opg_d                     ; ...
opg_s:
        mv    a0, s2                    ; checksum
        addi  a1, s3, 8                 ; ...
        li    a2, 0                     ; ...
        call  csum                      ; ...
        xori  a1, a0, 0xffff            ; ...
        addi  a0, s2, 2                 ; ...
        call  put16                     ; ...
        li    a0, 1                     ; out
        ld    a1, P_IP(s1)              ; ...
        addi  a2, s3, 8                 ; ...
        call  ip_send                   ; ...
        call  now                       ; sent at, deadline
        sd    a0, P_SENT(s1)            ; ...
        la    t0, srv_hdr               ; timeout (0: 1 s)
        ld    t1, 24(t0)                ; ...
        bnez  t1, opg_t                 ; ...
        li    t1, 1000000               ; ...
opg_t:
        add   t1, a0, t1                ; ...
        sd    t1, P_DL(s1)              ; ...
        call  srv_park                  ; wait for the reply
        bltz  a0, ol_busy               ; (no room: -7)
        addi  a0, a0, 1                 ; ...
        sd    a0, P_PK(s1)              ; ...
        la    t0, srv_tok               ; ...
        ld    t0, 0(t0)                 ; ...
        sd    t0, P_TOK(s1)             ; ...
        j     loop                      ; ...

; STAT
op_stat:
        la    s2, txpkt                 ; the data
        la    t0, myip                  ; header
        ld    t0, 0(t0)                 ; ...
        sd    t0, 0(s2)                 ; ...
        call  nic_status                ; ...
        sd    a0, 8(s2)                 ; ...
        la    t0, n_in                  ; ...
        ld    t0, 0(t0)                 ; ...
        sd    t0, 16(s2)                ; ...
        la    t0, n_out                 ; ...
        ld    t0, 0(t0)                 ; ...
        sd    t0, 24(s2)                ; ...
        la    t0, n_err                 ; ...
        ld    t0, 0(t0)                 ; ...
        sd    t0, 32(s2)                ; ...
        li    t0, NSOCK                 ; ...
        sd    t0, 40(s2)                ; ...
        sd    zero, 48(s2)              ; ...
        sd    zero, 56(s2)              ; ...
        li    s3, 0                     ; s3 = records
        la    s1, socks                 ; ...
        li    s4, NSOCK                 ; ...
ost_l:
        beqz  s4, ost_d                 ; ...
        ld    t0, S_STATE(s1)           ; in use?
        beqz  t0, ost_n                 ; ...
        slli  t1, s3, 5                 ; the record
        add   t1, s2, t1                ; ...
        addi  t1, t1, 64                ; ...
        ld    t2, S_ID(s1)              ; u8 id, state, protocol, flags
        sb    t2, 0(t1)                 ; ...
        sb    t0, 1(t1)                 ; ...
        ld    t2, S_PROTO(s1)           ; ...
        sb    t2, 2(t1)                 ; ...
        ld    t2, S_FLAGS(s1)           ; ...
        sb    t2, 3(t1)                 ; ...
        ld    t2, S_LPORT(s1)           ; u16 ports
        sh    t2, 4(t1)                 ; ...
        ld    t2, S_RPORT(s1)           ; ...
        sh    t2, 6(t1)                 ; ...
        ld    t2, S_RIP(s1)             ; u32 address, owner
        sw    t2, 8(t1)                 ; ...
        ld    t2, S_OWNER(s1)           ; ...
        sw    t2, 12(t1)                ; ...
        ld    t2, S_RXN(s1)             ; u32 received, unacknowledged
        sw    t2, 16(t1)                ; ...
        ld    t2, S_TXN(s1)             ; ...
        sw    t2, 20(t1)                ; ...
        ld    t2, S_WND(s1)             ; u32 peer window, retransmissions
        sw    t2, 24(t1)                ; ...
        ld    t2, S_NREX(s1)            ; ...
        sw    t2, 28(t1)                ; ...
        addi  s3, s3, 1                 ; ...
ost_n:
        addi  s1, s1, 256               ; ...
        addi  s4, s4, -1                ; ...
        j     ost_l                     ; ...
ost_d:
        mv    a0, s2                    ; -> the request
        slli  a1, s3, 5                 ; ...
        addi  a1, a1, 64                ; ...
        call  srv_put                   ; ...
        mv    a0, s3                    ; ...
        j     reply                     ; ...

; CLEANUP (handle = pid): its sockets are closed. CANCEL: its waits return -2
op_cleanup:
        li    s3, 0                     ; s3 = 0 close, 1 cancel
        j     ocx                       ; ...
op_cancel:
        li    s3, 1                     ; ...
ocx:
        la    t0, srv_hdr               ; s4 = the pid
        ld    s4, 8(t0)                 ; ...
        li    a0, 0                     ; answer proc first
        li    a1, 0                     ; ...
        call  srv_reply                 ; ...
        la    s1, socks                 ; ...
        li    s2, NSOCK                 ; ...
ocx_l:
        beqz  s2, ocx_p                 ; ...
        ld    t0, S_STATE(s1)           ; in use, that owner's
        beqz  t0, ocx_n                 ; ...
        ld    t0, S_OWNER(s1)           ; ...
        bne   t0, s4, ocx_n             ; ...
        ld    t0, S_FLAGS(s1)           ; (not already closed)
        andi  t0, t0, SF_CLOSE          ; ...
        bnez  t0, ocx_n                 ; ...
        mv    a0, s1                    ; ...
        bnez  s3, ocx_c                 ; ...
        call  close_sock                ; ...
        j     ocx_n                     ; ...
ocx_c:
        li    a1, -2                    ; its waiting request: -2
        call  answer_pk                 ; ...
ocx_n:
        addi  s1, s1, 256               ; ...
        addi  s2, s2, -1                ; ...
        j     ocx_l                     ; ...
ocx_p:
        la    s1, pings                 ; and its pings
        li    s2, NPING                 ; ...
ocx_pl:
        beqz  s2, loop                  ; ...
        ld    t0, P_PK(s1)              ; ...
        beqz  t0, ocx_pn                ; ...
        ld    t0, P_PID(s1)             ; ...
        bne   t0, s4, ocx_pn            ; ...
        mv    a0, s1                    ; -2 (or dropped)
        li    a1, -2                    ; ...
        call  ping_answer               ; ...
ocx_pn:
        addi  s1, s1, P_SIZE            ; ...
        addi  s2, s2, -1                ; ...
        j     ocx_pl                    ; ...

; ---- waiting requests ------------------------------------------------------------------------
; park_on(a0 = socket, a1 = op) -> a0 = 0: the request in c6 waits on the
; socket (to be tried again with that op); -7 one is waiting already, or no room
park_on:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        ld    t0, S_PK(a0)              ; one per socket
        bnez  t0, pk_busy               ; ...
        call  srv_park                  ; ...
        bltz  a0, pk_busy               ; ...
        ld    t0, 8(sp)                 ; ...
        addi  a0, a0, 1                 ; ...
        sd    a0, S_PK(t0)              ; ...
        la    t1, srv_tok               ; ...
        ld    t1, 0(t1)                 ; ...
        sd    t1, S_PKTOK(t0)           ; ...
        ld    t1, 16(sp)                ; ...
        sd    t1, S_PKOP(t0)            ; ...
        li    a0, 0                     ; ...
        j     pk_ret                    ; ...
pk_busy:
        li    a0, -7                    ; ...
pk_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; wake(a0 = socket): its waiting request (if any) is tried again: answered, or it waits again
wake:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        mv    s1, a0                    ; ...
        ld    t0, S_PK(s1)              ; anyone?
        beqz  t0, wk_ret                ; ...
        sd    zero, S_PK(s1)            ; ...
        addi  a0, t0, -1                ; the request back in c6
        call  srv_unpark                ; ...
        bnez  a0, wk_ret                ; its owner is gone
        ld    t0, S_PKTOK(s1)           ; its token
        la    t1, srv_tok               ; ...
        sd    t0, 0(t1)                 ; ...
        mv    a0, s1                    ; try again
        ld    t0, S_PKOP(s1)            ; ...
        li    t1, OP_READ               ; ...
        beq   t0, t1, wk_rd             ; ...
        li    t1, OP_WRITE              ; ...
        beq   t0, t1, wk_wr             ; ...
        li    t1, OP_NCONN              ; ...
        beq   t0, t1, wk_cn             ; ...
        li    t1, OP_NACCEPT            ; ...
        beq   t0, t1, wk_ac             ; ...
        call  try_urecv                 ; (RECVFROM)
        j     wk_got                    ; ...
wk_rd:
        call  try_read                  ; ...
        j     wk_got                    ; ...
wk_wr:
        call  try_write                 ; ...
        j     wk_got                    ; ...
wk_cn:
        call  try_conn                  ; ...
        j     wk_got                    ; ...
wk_ac:
        call  try_accept                ; ...
wk_got:
        li    t0, -3                    ; still not?
        bne   a0, t0, wk_ans            ; ...
        mv    a0, s1                    ; wait again
        ld    a1, S_PKOP(s1)            ; ...
        call  park_on                   ; ...
        beqz  a0, wk_ret                ; ...
        li    a0, -7                    ; (no room)
wk_ans:
        li    a1, 0                     ; ...
        call  srv_reply                 ; ...
wk_ret:
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; answer_pk(a0 = socket, a1 = result): its waiting request (if any) is answered with that
answer_pk:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        ld    t0, S_PK(a0)              ; anyone?
        beqz  t0, apk_ret               ; ...
        sd    zero, S_PK(a0)            ; ...
        addi  a0, t0, -1                ; ...
        call  srv_unpark                ; ...
        bnez  a0, apk_ret               ; gone
        ld    t0, 8(sp)                 ; ...
        ld    t0, S_PKTOK(t0)           ; ...
        la    t1, srv_tok               ; ...
        sd    t0, 0(t1)                 ; ...
        ld    a0, 16(sp)                ; ...
        li    a1, 0                     ; ...
        call  srv_reply                 ; ...
apk_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; ping_answer(a0 = ping slot, a1 = result): answer it and free the slot
ping_answer:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        ld    t0, P_PK(a0)              ; ...
        sd    zero, P_PK(a0)            ; free
        beqz  t0, pa_ret                ; ...
        addi  a0, t0, -1                ; ...
        call  srv_unpark                ; ...
        bnez  a0, pa_ret                ; gone
        ld    t0, 8(sp)                 ; ...
        ld    t0, P_TOK(t0)             ; ...
        la    t1, srv_tok               ; ...
        sd    t0, 0(t1)                 ; ...
        ld    a0, 16(sp)                ; ...
        li    a1, 0                     ; ...
        call  srv_reply                 ; ...
pa_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; ---- the tries (a0 = socket; the request in c6, header in srv_hdr) -> a0 = result, -3 not yet
; try_read: TCP data
try_read:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        mv    s1, a0                    ; ...
        ld    t0, S_PROTO(s1)           ; TCP only
        li    t1, 6                     ; ...
        li    a0, -1                    ; ...
        bne   t0, t1, trd_ret           ; ...
        ld    s2, S_RXN(s1)             ; something there?
        bnez  s2, trd_take              ; ...
        ld    t0, S_FLAGS(s1)           ; reset: -1
        andi  t1, t0, SF_RESET          ; ...
        li    a0, -1                    ; ...
        bnez  t1, trd_ret               ; ...
        andi  t1, t0, SF_FINRCV         ; the end: 0
        li    a0, 0                     ; ...
        bnez  t1, trd_ret               ; ...
        ld    t0, S_STATE(s1)           ; ...
        li    t1, ST_CLOSED             ; ...
        beq   t0, t1, trd_ret           ; ...
        ld    t0, S_STATE(s1)           ; a listener has no data
        li    t1, ST_LISTEN             ; ...
        li    a0, -1                    ; ...
        beq   t0, t1, trd_ret           ; ...
        li    a0, -3                    ; not yet
        j     trd_ret                   ; ...
trd_take:
        la    t0, srv_hdr               ; s2 = min(there, wanted, MSS)
        ld    t1, 16(t0)                ; ...
        bleu  s2, t1, trd_a             ; ...
        mv    s2, t1                    ; ...
trd_a:
        li    t1, MSS                   ; ...
        bleu  s2, t1, trd_b             ; ...
        mv    s2, t1                    ; ...
trd_b:
        mv    a0, s1                    ; ring -> txpkt -> the request
        la    a1, txpkt                 ; ...
        mv    a2, s2                    ; ...
        call  ring_get                  ; ...
        la    a0, txpkt                 ; ...
        mv    a1, s2                    ; ...
        call  srv_put                   ; ...
        ld    t0, S_ADVW(s1)            ; the window we advertised was small: say it opened
        li    t1, MSS                   ; ...
        bgeu  t0, t1, trd_n             ; ...
        ld    t0, S_STATE(s1)           ; (in a state that still receives)
        li    t1, ST_EST                ; ...
        beq   t0, t1, trd_w             ; ...
        li    t1, ST_FINW1              ; ...
        beq   t0, t1, trd_w             ; ...
        li    t1, ST_FINW2              ; ...
        bne   t0, t1, trd_n             ; ...
trd_w:
        ld    t0, S_FLAGS(s1)           ; ...
        ori   t0, t0, SF_ACKNOW         ; ...
        sd    t0, S_FLAGS(s1)           ; ...
        mv    a0, s1                    ; ...
        call  tcp_output                ; ...
trd_n:
        mv    a0, s2                    ; bytes
trd_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; try_write: TCP data into the send buffer
try_write:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        mv    s1, a0                    ; ...
        li    a0, -1                    ; ...
        ld    t0, S_PROTO(s1)           ; TCP
        li    t1, 6                     ; ...
        bne   t0, t1, twr_ret           ; ...
        ld    t0, S_FLAGS(s1)           ; not reset, not shut down
        andi  t0, t0, SF_RESET | SF_SHUT ; ...
        bnez  t0, twr_ret               ; ...
        ld    t0, S_STATE(s1)           ; established (or the peer has closed its side)
        li    t1, ST_EST                ; ...
        beq   t0, t1, twr_ok            ; ...
        li    t1, ST_CLOSEW             ; ...
        bne   t0, t1, twr_ret           ; ...
twr_ok:
        ld    t0, S_TXN(s1)             ; room?
        li    s2, TXB                   ; ...
        sub   s2, s2, t0                ; ...
        li    a0, -3                    ; ...
        beqz  s2, twr_ret               ; full: wait
        la    t0, srv_hdr               ; s2 = min(room, offered, MSS)
        ld    t1, 16(t0)                ; ...
        bleu  s2, t1, twr_a             ; ...
        mv    s2, t1                    ; ...
twr_a:
        li    t1, MSS                   ; ...
        bleu  s2, t1, twr_b             ; ...
        mv    s2, t1                    ; ...
twr_b:
        li    a0, 0                     ; nothing offered
        beqz  s2, twr_ret               ; ...
        la    a0, txpkt                 ; the request's data -> txpkt
        mv    a1, s2                    ; ...
        call  srv_get                   ; ...
        mv    a0, s1                    ; -> the send buffer
        call  txbp                      ; ...
        ld    t0, S_TXN(s1)             ; ...
        add   a0, a0, t0                ; ...
        la    a1, txpkt                 ; ...
        mv    a2, s2                    ; ...
        call  srv_bcopy                 ; ...
        ld    t0, S_TXN(s1)             ; ...
        add   t0, t0, s2                ; ...
        sd    t0, S_TXN(s1)             ; ...
        mv    a0, s1                    ; send what the window allows
        call  tcp_output                ; ...
        mv    a0, s2                    ; bytes taken
twr_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; try_conn: established -> its id; given up / refused -> the error (and the socket goes)
try_conn:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        mv    s1, a0                    ; ...
        ld    t0, S_STATE(s1)           ; ...
        li    t1, ST_SYNSENT            ; still trying
        li    a0, -3                    ; ...
        beq   t0, t1, tcn_ret           ; ...
        li    t1, ST_CLOSED             ; failed
        beq   t0, t1, tcn_fail          ; ...
        ld    a0, S_ID(s1)              ; established
        j     tcn_ret                   ; ...
tcn_fail:
        ld    t0, S_FLAGS(s1)           ; -8 no answer, -1 refused
        andi  t0, t0, SF_TMO            ; ...
        li    a0, -1                    ; ...
        beqz  t0, tcn_f2                ; ...
        li    a0, -8                    ; ...
tcn_f2:
        addi  sp, sp, -16               ; (keep the result)
        sd    a0, 0(sp)                 ; ...
        mv    a0, s1                    ; the socket goes
        call  sock_free                 ; ...
        ld    a0, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
tcn_ret:
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; try_accept (a0 = the listener): the next established connection
try_accept:
        ld    t0, S_STATE(a0)           ; a listener
        li    t1, ST_LISTEN             ; ...
        bne   t0, t1, tac_bad           ; ...
        ld    t2, S_ID(a0)              ; t2 = its id
        la    t3, socks                 ; a child of it, established
        li    t4, NSOCK                 ; ...
tac_l:
        beqz  t4, tac_none              ; ...
        ld    t0, S_PARENT(t3)          ; ...
        bne   t0, t2, tac_n             ; ...
        ld    t0, S_FLAGS(t3)           ; ...
        andi  t1, t0, SF_UNACC          ; ...
        beqz  t1, tac_n                 ; ...
        xori  t0, t0, SF_UNACC          ; it is the caller's now
        sd    t0, S_FLAGS(t3)           ; ...
        sd    zero, S_PARENT(t3)        ; ...
        la    t0, srv_hdr               ; ...
        ld    t0, 40(t0)                ; ...
        sd    t0, S_OWNER(t3)           ; ...
        ld    a0, S_ID(t3)              ; ...
        ret                             ; ...
tac_n:
        addi  t3, t3, 256               ; ...
        addi  t4, t4, -1                ; ...
        j     tac_l                     ; ...
tac_none:
        li    a0, -3                    ; not yet
        ret                             ; ...
tac_bad:
        li    a0, -1                    ; ...
        ret                             ; ...

; try_urecv: the next datagram: data u64 address, u64 port, payload
try_urecv:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        mv    s1, a0                    ; ...
        ld    t0, S_STATE(s1)           ; UDP only
        li    t1, ST_UDP                ; ...
        li    a0, -1                    ; ...
        bne   t0, t1, tur_ret           ; ...
        ld    t0, S_RXN(s1)             ; a datagram?
        li    a0, -3                    ; ...
        beqz  t0, tur_ret               ; ...
        mv    a0, s1                    ; its record: length | port << 16 | address << 32
        la    a1, urec                  ; ...
        li    a2, 8                     ; ...
        call  ring_get                  ; ...
        la    t0, urec                  ; ...
        ld    t1, 0(t0)                 ; ...
        andi  s2, t1, 0xffff            ; s2 = its length
        la    t2, txpkt                 ; address, port
        srli  t3, t1, 32                ; ...
        sd    t3, 0(t2)                 ; ...
        srli  t3, t1, 16                ; ...
        andi  t3, t3, 0xffff            ; ...
        sd    t3, 8(t2)                 ; ...
        la    t0, srv_hdr               ; s3 = min(length, wanted)
        ld    s3, 16(t0)                ; ...
        bleu  s3, s2, tur_a             ; ...
        mv    s3, s2                    ; ...
tur_a:
        mv    a0, s1                    ; the payload
        la    a1, txpkt + 16            ; ...
        mv    a2, s3                    ; ...
        call  ring_get                  ; ...
        sub   a2, s2, s3                ; the rest of it is lost
        mv    a0, s1                    ; ...
        la    a1, txpkt + 16            ; (read over: it is not sent)
        call  ring_get                  ; ...
        la    a0, txpkt                 ; -> the request
        addi  a1, s3, 16                ; ...
        call  srv_put                   ; ...
        mv    a0, s3                    ; ...
tur_ret:
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 40                ; ...
        ret                             ; ...

; ---- sockets --------------------------------------------------------------------------------
; sock_alloc() -> a0 = a free socket, cleared (state still 0), or 0
sock_alloc:
        la    t0, socks                 ; ...
        li    t1, NSOCK                 ; ...
        li    t3, 1                     ; id
sa_l:
        beqz  t1, sa_none               ; ...
        ld    t2, S_STATE(t0)           ; ...
        beqz  t2, sa_take               ; ...
        addi  t0, t0, 256               ; ...
        addi  t1, t1, -1                ; ...
        addi  t3, t3, 1                 ; ...
        j     sa_l                      ; ...
sa_take:
        li    t1, 32                    ; clear the record
        mv    t2, t0                    ; ...
sa_z:
        sd    zero, 0(t2)               ; ...
        addi  t2, t2, 8                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, sa_z                  ; ...
        sd    t3, S_ID(t0)              ; ...
        li    t1, 536                   ; the peer's MSS until it says otherwise
        sd    t1, S_MSS(t0)             ; ...
        li    t1, RTO0                  ; ...
        sd    t1, S_RTOV(t0)            ; ...
        li    t1, ST_CLOSED             ; (taken)
        sd    t1, S_STATE(t0)           ; ...
        mv    a0, t0                    ; ...
        ret                             ; ...
sa_none:
        li    a0, 0                     ; ...
        ret                             ; ...

; sock_free(a0 = socket): a waiting request gets -1, the slot is free
sock_free:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        li    a1, -1                    ; ...
        call  answer_pk                 ; ...
        ld    t0, 8(sp)                 ; ...
        sd    zero, S_STATE(t0)         ; ...
        sd    zero, S_RTO(t0)           ; ...
        sd    zero, S_PARENT(t0)        ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; close_sock(a0 = socket): the owner is done with it
close_sock:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        mv    s1, a0                    ; ...
        li    a1, -1                    ; a waiting request (another thread's): -1
        call  answer_pk                 ; ...
        ld    t0, S_FLAGS(s1)           ; closed
        ori   t0, t0, SF_CLOSE          ; ...
        sd    t0, S_FLAGS(s1)           ; ...
        ld    t0, S_STATE(s1)           ; ...
        li    t1, ST_EST                ; established: FIN after the data
        beq   t0, t1, cs_fin            ; ...
        li    t1, ST_CLOSEW             ; ...
        beq   t0, t1, cs_fin            ; ...
        li    t1, ST_SYNRCVD            ; (not possible for an owner)
        beq   t0, t1, cs_free           ; ...
        li    t1, ST_FINW1              ; closing already: it finishes on its own
        beq   t0, t1, cs_ret            ; ...
        li    t1, ST_CLOSING            ; ...
        beq   t0, t1, cs_ret            ; ...
        li    t1, ST_LASTACK            ; ...
        beq   t0, t1, cs_ret            ; ...
        li    t1, ST_TIMEW              ; ...
        beq   t0, t1, cs_ret            ; ...
        li    t1, ST_FINW2              ; the peer has yet to close: not for ever
        beq   t0, t1, cs_fw2            ; ...
        li    t1, ST_LISTEN             ; a listener: its connections not accepted go too
        bne   t0, t1, cs_free           ; (UDP, SYN-SENT, closed: just free it)
        ld    s2, S_ID(s1)              ; ...
        la    a0, socks                 ; ...
        li    t2, NSOCK                 ; ...
cs_l:
        beqz  t2, cs_free               ; ...
        ld    t0, S_STATE(a0)           ; ...
        beqz  t0, cs_n                  ; ...
        ld    t0, S_PARENT(a0)          ; ...
        bne   t0, s2, cs_n              ; ...
        addi  sp, sp, -16               ; (keep the cursor)
        sd    a0, 0(sp)                 ; ...
        sd    t2, 8(sp)                 ; ...
        li    a1, TF_RST | TF_ACK       ; reset it
        ld    a2, S_NXT(a0)             ; ...
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        call  tcp_send                  ; ...
        ld    a0, 0(sp)                 ; ...
        call  sock_free                 ; ...
        ld    a0, 0(sp)                 ; ...
        ld    t2, 8(sp)                 ; ...
        addi  sp, sp, 16                ; ...
cs_n:
        addi  a0, a0, 256               ; ...
        addi  t2, t2, -1                ; ...
        j     cs_l                      ; ...
cs_fin:
        mv    a0, s1                    ; the FIN goes when the data has
        call  tcp_output                ; ...
        j     cs_ret                    ; ...
cs_fw2:
        call  now                       ; ...
        li    t0, FW2T                  ; ...
        add   a0, a0, t0                ; ...
        sd    a0, S_RTO(s1)             ; ...
        j     cs_ret                    ; ...
cs_free:
        mv    a0, s1                    ; ...
        call  sock_free                 ; ...
cs_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

