TXB      = 2048                         ; send buffer per socket
MSS      = 1024                         ; largest segment we send or take
NPING    = 4                            ; pings in flight
RTO0     = 250000                       ; first retransmission timeout (ticks)
RTOMAX   = 8000000                      ; longest one
TMAX     = 8                            ; retransmissions before giving up
