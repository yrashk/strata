S_UNA    = 48                           ; oldest unacknowledged sequence number
S_NXT    = 56                           ; next sequence number to send
S_RCV    = 64                           ; next sequence number expected
S_WND    = 72                           ; the peer's window
S_RTO    = 80                           ; timer: absolute tick (0 = none)
