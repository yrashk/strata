S_ISS    = 128                          ; our initial sequence number
S_RXH    = 136                          ; receive ring: first byte
S_RXN    = 144                          ; bytes in it
S_TXN    = 152                          ; send buffer: bytes from snd_una on
S_MSS    = 160                          ; the peer's MSS (capped at MSS)
S_ADVW   = 168                          ; the window we advertised last
S_RTOV   = 176                          ; the current retransmission timeout
S_ID     = 184                          ; index + 1
S_PROTO  = 192                          ; 6 TCP, 17 UDP
S_NREX   = 200                          ; retransmissions in all (netstat)

TF_FIN   = 1                            ; TCP header flags
