; ring_put(a0 = socket, a1 = source, a2 = bytes): append to the receive ring (room checked by the caller)
ring_put:
        mv    t5, a0                    ; ...
        ld    t3, S_RXH(t5)             ; t3 = head
        ld    t4, S_RXN(t5)             ; t4 = count
        ld    t0, S_ID(t5)              ; t6 = the ring
        addi  t0, t0, -1                ; ...
        slli  t0, t0, 11                ; ...
        la    t6, rxring                ; ...
        add   t6, t6, t0                ; ...
rp_l:
        beqz  a2, rp_d                  ; ...
        lbu   t0, 0(a1)                 ; ...
        add   t1, t3, t4                ; position (head + count) mod RXB
        andi  t1, t1, RXB - 1           ; ...
        add   t1, t6, t1                ; ...
        sb    t0, 0(t1)                 ; ...
        addi  t4, t4, 1                 ; ...
        addi  a1, a1, 1                 ; ...
        addi  a2, a2, -1                ; ...
        j     rp_l                      ; ...
rp_d:
        sd    t4, S_RXN(t5)             ; ...
        ret                             ; ...

; ring_get(a0 = socket, a1 = destination, a2 = bytes): take from the receive ring
ring_get:
        mv    t5, a0                    ; ...
        ld    t3, S_RXH(t5)             ; t3 = head
        ld    t4, S_RXN(t5)             ; t4 = count
        ld    t0, S_ID(t5)              ; t6 = the ring
        addi  t0, t0, -1                ; ...
        slli  t0, t0, 11                ; ...
        la    t6, rxring                ; ...
        add   t6, t6, t0                ; ...
rg_l:
        beqz  a2, rg_d                  ; ...
        beqz  t4, rg_d                  ; (never past what is there)
        add   t1, t6, t3                ; ...
        lbu   t0, 0(t1)                 ; ...
        sb    t0, 0(a1)                 ; ...
        addi  t3, t3, 1                 ; ...
        andi  t3, t3, RXB - 1           ; ...
        addi  t4, t4, -1                ; ...
        addi  a1, a1, 1                 ; ...
        addi  a2, a2, -1                ; ...
        j     rg_l                      ; ...
rg_d:
        sd    t3, S_RXH(t5)             ; ...
        sd    t4, S_RXN(t5)             ; ...
        ret                             ; ...

; ---- timers -------------------------------------------------------------------------------
; arm_rto(a0 = socket): the retransmission timer, if it is not running
arm_rto:
        ld    t0, S_RTO(a0)             ; ...
        bnez  t0, ar_ret                ; ...
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        call  now                       ; ...
        ld    t0, 8(sp)                 ; ...
        ld    t1, S_RTOV(t0)            ; ...
        add   a0, a0, t1                ; ...
        sd    a0, S_RTO(t0)             ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
ar_ret:
        ret                             ; ...

; next_to() -> a0 = ticks until the next timer (at least 1), or -1 if none
next_to:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        call  now                       ; s2 = now
        mv    s2, a0                    ; ...
        li    s1, -1                    ; s1 = the earliest (unsigned)
        la    t0, socks                 ; sockets' timers; any open socket?
        li    t1, NSOCK                 ; ...
        li    t4, 0                     ; t4 = an open socket that a process owns
nt_s:
        beqz  t1, nt_p                  ; ...
        ld    t2, S_STATE(t0)           ; ...
        beqz  t2, nt_sn                 ; ...
        ld    t2, S_RTO(t0)             ; ...
        beqz  t2, nt_so                 ; ...
        bgeu  t2, s1, nt_so             ; ...
        mv    s1, t2                    ; ...
nt_so:
        ld    t2, S_FLAGS(t0)           ; open, and not a connection waiting to be accepted
        andi  t2, t2, SF_CLOSE          ; ...
        bnez  t2, nt_sn                 ; ...
        ld    t2, S_PARENT(t0)          ; ...
        bnez  t2, nt_sn                 ; ...
        li    t4, 1                     ; ...
nt_sn:
        addi  t0, t0, 256               ; ...
        addi  t1, t1, -1                ; ...
        j     nt_s                      ; ...
nt_p:
        la    t0, pings                 ; pings' deadlines
        li    t1, NPING                 ; ...
nt_pl:
        beqz  t1, nt_g                  ; ...
        ld    t2, P_PK(t0)              ; ...
        beqz  t2, nt_pn                 ; ...
        ld    t2, P_DL(t0)              ; ...
        bgeu  t2, s1, nt_pn             ; ...
        mv    s1, t2                    ; ...
nt_pn:
        addi  t0, t0, P_SIZE            ; ...
        addi  t1, t1, -1                ; ...
        j     nt_pl                     ; ...
nt_g:
        la    t0, gcnext                ; the owner check, while sockets are open
        bnez  t4, nt_g1                 ; ...
        sd    zero, 0(t0)               ; none open: none due
        j     nt_d                      ; ...
nt_g1:
        ld    t2, 0(t0)                 ; ...
        bnez  t2, nt_g2                 ; ...
        li    t2, GCT                   ; due in a while
        add   t2, s2, t2                ; ...
        sd    t2, 0(t0)                 ; ...
nt_g2:
        bgeu  t2, s1, nt_d              ; ...
        mv    s1, t2                    ; ...
nt_d:
        li    a0, -1                    ; nothing?
        beq   s1, a0, nt_ret            ; ...
        sub   a0, s1, s2                ; ticks from now
        bgtz  a0, nt_ret                ; ...
        li    a0, 1                     ; due: at once
nt_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; timers(): whatever is due
timers:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        call  now                       ; s3 = now
        mv    s3, a0                    ; ...
        la    s1, socks                 ; sockets
        li    s2, NSOCK                 ; ...
tm_s:
        beqz  s2, tm_p                  ; ...
        ld    t0, S_STATE(s1)           ; ...
        beqz  t0, tm_sn                 ; ...
        ld    t0, S_RTO(s1)             ; ...
        beqz  t0, tm_sn                 ; ...
        bgtu  t0, s3, tm_sn             ; ...
        mv    a0, s1                    ; ...
        call  tcp_timer                 ; ...
tm_sn:
        addi  s1, s1, 256               ; ...
        addi  s2, s2, -1                ; ...
        j     tm_s                      ; ...
tm_p:
        la    s1, pings                 ; pings that got no answer: -8
        li    s2, NPING                 ; ...
tm_pl:
        beqz  s2, tm_g                  ; ...
        ld    t0, P_PK(s1)              ; ...
        beqz  t0, tm_pn                 ; ...
        ld    t0, P_DL(s1)              ; ...
        bgtu  t0, s3, tm_pn             ; ...
        mv    a0, s1                    ; ...
        li    a1, -8                    ; ...
        call  ping_answer               ; ...
tm_pn:
        addi  s1, s1, P_SIZE            ; ...
        addi  s2, s2, -1                ; ...
        j     tm_pl                     ; ...
tm_g:
        la    t0, gcnext                ; the owner check
        ld    t0, 0(t0)                 ; ...
        beqz  t0, tm_ret                ; ...
        bgtu  t0, s3, tm_ret            ; ...
        call  gc                        ; ...
tm_ret:
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; gc(): close the sockets whose owners have ended (proc's process list)
gc:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        la    t0, gcnext                ; the next check is computed again (next_to)
        sd    zero, 0(t0)               ; ...
        la    a0, txpkt                 ; PS: 32-byte records, u8 pid, u8 state
        call  sys_ps                    ; a0 = records
        blez  a0, gc_ret                ; (none: leave everything)
        mv    s3, a0                    ; ...
        la    s1, socks                 ; ...
        li    s2, NSOCK                 ; ...
gc_l:
        beqz  s2, gc_ret                ; ...
        ld    t0, S_STATE(s1)           ; open, owned
        beqz  t0, gc_n                  ; ...
        ld    t0, S_FLAGS(s1)           ; ...
        andi  t0, t0, SF_CLOSE          ; ...
        bnez  t0, gc_n                  ; ...
        ld    t0, S_PARENT(s1)          ; ...
        bnez  t0, gc_n                  ; ...
        ld    s4, S_OWNER(s1)           ; is it alive?
        andi  s4, s4, 255               ; (PS has 8-bit pids)
        la    t1, txpkt                 ; ...
        mv    t2, s3                    ; ...
gc_f:
        beqz  t2, gc_dead               ; not in the list
        lbu   t3, 0(t1)                 ; ...
        bne   t3, s4, gc_fn             ; ...
        lbu   t3, 1(t1)                 ; a zombie has ended too
        li    t4, 4                     ; ...
        bne   t3, t4, gc_n              ; alive
        j     gc_dead                   ; ...
gc_fn:
        addi  t1, t1, 32                ; ...
        addi  t2, t2, -1                ; ...
        j     gc_f                      ; ...
gc_dead:
        mv    a0, s1                    ; ...
        call  close_sock                ; ...
gc_n:
        addi  s1, s1, 256               ; ...
        addi  s2, s2, -1                ; ...
        j     gc_l                      ; ...
gc_ret:
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 40                ; ...
        ret                             ; ...

; tcp_timer(a0 = socket): its timer is due
tcp_timer:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        mv    s1, a0                    ; ...
        sd    zero, S_RTO(s1)           ; ...
        ld    t0, S_STATE(s1)           ; TIME-WAIT, FIN-WAIT-2: over
        li    t1, ST_TIMEW              ; ...
        beq   t0, t1, tt_end            ; ...
        li    t1, ST_FINW2              ; ...
        beq   t0, t1, tt_end            ; ...
        li    t1, ST_SYNSENT            ; (only connections retransmit)
        bltu  t0, t1, tt_ret            ; ...
        ld    t0, S_TRIES(s1)           ; one more try
        addi  t0, t0, 1                 ; ...
        sd    t0, S_TRIES(s1)           ; ...
        li    t1, TMAX                  ; too many: give up
        bgtu  t0, t1, tt_give           ; ...
        ld    t0, S_NREX(s1)            ; (counted for netstat)
        addi  t0, t0, 1                 ; ...
        sd    t0, S_NREX(s1)            ; ...
        ld    t0, S_RTOV(s1)            ; back off: twice as long, up to RTOMAX
        slli  t0, t0, 1                 ; ...
        li    t1, RTOMAX                ; ...
        bleu  t0, t1, tt_b              ; ...
        mv    t0, t1                    ; ...
tt_b:
        sd    t0, S_RTOV(s1)            ; ...
        mv    a0, s1                    ; ...
        call  arm_rto                   ; ...
        mv    a0, s1                    ; the oldest segment again
        call  tcp_rexmit                ; ...
        j     tt_ret                    ; ...
tt_give:
        mv    a0, s1                    ; ...
        li    a1, SF_TMO                ; ...
        call  tcp_abort                 ; ...
        j     tt_ret                    ; ...
tt_end:
        ld    t0, S_FLAGS(s1)           ; closed by its owner: free
        andi  t0, t0, SF_CLOSE          ; ...
        beqz  t0, tt_keep               ; ...
        mv    a0, s1                    ; ...
        call  sock_free                 ; ...
        j     tt_ret                    ; ...
tt_keep:
        li    t0, ST_CLOSED             ; (shut down but not closed: the data stays readable)
        sd    t0, S_STATE(s1)           ; ...
tt_ret:
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; tcp_abort(a0 = socket, a1 = more flags): reset or given up: closed; its waiting request learns it
tcp_abort:
        ld    t0, S_FLAGS(a0)           ; ...
        or    t0, t0, a1                ; ...
        ori   t0, t0, SF_RESET          ; ...
        sd    t0, S_FLAGS(a0)           ; ...
        li    t1, ST_CLOSED             ; ...
        sd    t1, S_STATE(a0)           ; ...
        sd    zero, S_RTO(a0)           ; ...
        andi  t1, t0, SF_CLOSE          ; nobody will close it: free
        bnez  t1, sock_free             ; (tail call)
        ld    t1, S_PARENT(a0)          ; (not accepted yet)
        bnez  t1, sock_free             ; ...
        j     wake                      ; (tail call) the error goes to the waiting request

; ---- IP ------------------------------------------------------------------------------------
; ip_input(): the packet in rxpkt
ip_input:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        la    s1, rxpkt                 ; ...
        ld    t0, 0(s1)                 ; an all-zero header: a CANCEL (the kernel halts)
        ld    t1, 8(s1)                 ; ...
        or    t0, t0, t1                ; ...
        lwu   t1, 16(s1)                ; ...
        or    t0, t0, t1                ; ...
        bnez  t0, ipi_v                 ; ...
        la    t0, rxstop                ; do not read again
        li    t1, 1                     ; ...
        sd    t1, 0(t0)                 ; ...
        j     ipi_ret                   ; ...
ipi_v:
        lbu   t0, 0(s1)                 ; version 4
        srli  t1, t0, 4                 ; ...
        li    t2, 4                     ; ...
        bne   t1, t2, ipi_bad           ; ...
        andi  s2, t0, 15                ; s2 = header length
        slli  s2, s2, 2                 ; ...
        li    t2, 20                    ; ...
        bltu  s2, t2, ipi_bad           ; ...
        addi  a0, s1, 2                 ; s3 = total length
        call  be16                      ; ...
        mv    s3, a0                    ; ...
        bltu  s3, s2, ipi_bad           ; ...
        li    t0, RXLEN                 ; ...
        bgtu  s3, t0, ipi_bad           ; ...
        mv    a0, s1                    ; the header's checksum
        mv    a1, s2                    ; ...
        li    a2, 0                     ; ...
        call  csum                      ; ...
        li    t0, 0xffff                ; ...
        bne   a0, t0, ipi_bad           ; ...
        addi  a0, s1, 6                 ; no fragments
        call  be16                      ; ...
        andi  a0, a0, 0x3fff            ; ...
        bnez  a0, ipi_bad               ; ...
        addi  a0, s1, 16                ; for us (or broadcast)?
        call  be32                      ; ...
        la    t0, g_dst                 ; ...
        sd    a0, 0(t0)                 ; ...
        la    t1, myip                  ; ...
        ld    t1, 0(t1)                 ; ...
        beq   a0, t1, ipi_us            ; ...
        li    t1, 0xffffffff            ; ...
        bne   a0, t1, ipi_bad           ; ...
ipi_us:
        addi  a0, s1, 12                ; the source
        call  be32                      ; ...
        la    t0, g_src                 ; ...
        sd    a0, 0(t0)                 ; ...
        la    t0, n_in                  ; counted
        ld    t1, 0(t0)                 ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, 0(t0)                 ; ...
        lbu   t0, 9(s1)                 ; the protocol
        add   a0, s1, s2                ; a0 = payload, a1 = its length
        sub   a1, s3, s2                ; ...
        li    t1, 1                     ; ICMP
        beq   t0, t1, ipi_icmp          ; ...
        li    t1, 6                     ; TCP
        beq   t0, t1, ipi_tcp           ; ...
        li    t1, 17                    ; UDP
        beq   t0, t1, ipi_udp           ; ...
        j     ipi_ret                   ; (others are ignored)
ipi_icmp:
        call  icmp_input                ; ...
        j     ipi_ret                   ; ...
ipi_tcp:
        call  tcp_input                 ; ...
        j     ipi_ret                   ; ...
ipi_udp:
        call  udp_input                 ; ...
        j     ipi_ret                   ; ...
ipi_bad:
        call  count_err                 ; ...
ipi_ret:
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; count_err(): one more packet dropped
count_err:
        la    t0, n_err                 ; ...
        ld    t1, 0(t0)                 ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, 0(t0)                 ; ...
        ret                             ; ...

; ip_send(a0 = protocol, a1 = destination, a2 = payload bytes (at txpkt + 20)): header, out
ip_send:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        addi  s3, a2, 20                ; s3 = total length
        la    t0, txpkt                 ; version 4, 20-byte header, TOS 0
        li    t1, 0x45                  ; ...
        sb    t1, 0(t0)                 ; ...
        sb    zero, 1(t0)               ; ...
        addi  a0, t0, 2                 ; total length
        mv    a1, s3                    ; ...
        call  put16                     ; ...
        la    t0, ipid                  ; identification
        ld    a1, 0(t0)                 ; ...
        addi  t1, a1, 1                 ; ...
        sd    t1, 0(t0)                 ; ...
        la    a0, txpkt + 4             ; ...
        call  put16                     ; ...
        la    a0, txpkt + 6             ; don't fragment
        li    a1, 0x4000                ; ...
        call  put16                     ; ...
        la    t0, txpkt                 ; TTL 64, protocol, checksum 0 for now
        li    t1, 64                    ; ...
        sb    t1, 8(t0)                 ; ...
        sb    s1, 9(t0)                 ; ...
        sb    zero, 10(t0)              ; ...
        sb    zero, 11(t0)              ; ...
        la    a0, txpkt + 12            ; source
        la    a1, myip                  ; ...
        ld    a1, 0(a1)                 ; ...
        call  put32                     ; ...
        la    a0, txpkt + 16            ; destination
        mv    a1, s2                    ; ...
        call  put32                     ; ...
        la    a0, txpkt                 ; the checksum
        li    a1, 20                    ; ...
        li    a2, 0                     ; ...
        call  csum                      ; ...
        xori  a1, a0, 0xffff            ; ...
        la    a0, txpkt + 10            ; ...
        call  put16                     ; ...
        la    t0, txpkt                 ; one transfer, one packet
        li    t1, N_TX                  ; ...
        tput  tg3, t0, c4, t1, s3       ; ...
        twait 1 << TG_TX                ; ...
        la    t0, n_out                 ; counted
        ld    t1, 0(t0)                 ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, 0(t0)                 ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; ---- ICMP ----------------------------------------------------------------------------------
; icmp_input(a0 = message, a1 = length)
icmp_input:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        li    t0, 8                     ; a header at least
        bltu  s2, t0, ic_bad            ; ...
        li    a2, 0                     ; the checksum
        call  csum                      ; ...
        li    t0, 0xffff                ; ...
        bne   a0, t0, ic_bad            ; ...
        lbu   t0, 0(s1)                 ; the type
        li    t1, 8                     ; echo request
        beq   t0, t1, ic_echo           ; ...
        bnez  t0, ic_ret                ; (0: echo reply; others are ignored)
        addi  a0, s1, 4                 ; ours?
        call  be16                      ; ...
        li    t0, PING_ID               ; ...
        bne   a0, t0, ic_ret            ; ...
        addi  a0, s1, 6                 ; s3 = its sequence number
        call  be16                      ; ...
        mv    s3, a0                    ; ...
        la    s1, pings                 ; the ping waiting for it
        li    s2, NPING                 ; ...
ic_pl:
        beqz  s2, ic_ret                ; none (late, or a stranger's)
        ld    t0, P_PK(s1)              ; ...
        beqz  t0, ic_pn                 ; ...
        ld    t0, P_SEQ(s1)             ; ...
        bne   t0, s3, ic_pn             ; ...
        ld    t0, P_IP(s1)              ; ...
        la    t1, g_src                 ; ...
        ld    t1, 0(t1)                 ; ...
        bne   t0, t1, ic_pn             ; ...
        call  now                       ; the round trip
        ld    t0, P_SENT(s1)            ; ...
        sub   a1, a0, t0                ; ...
        mv    a0, s1                    ; ...
        call  ping_answer               ; ...
        j     ic_ret                    ; ...
ic_pn:
        addi  s1, s1, P_SIZE            ; ...
        addi  s2, s2, -1                ; ...
        j     ic_pl                     ; ...
ic_echo:
        li    t0, RXLEN - 20            ; the reply: the same message, type 0
        bgtu  s2, t0, ic_bad            ; ...
        la    a0, txpkt + 20            ; ...
        mv    a1, s1                    ; ...
        mv    a2, s2                    ; ...
        call  srv_bcopy                 ; ...
        la    s3, txpkt + 20            ; ...
        sb    zero, 0(s3)               ; type 0
        sb    zero, 2(s3)               ; checksum 0 for now
        sb    zero, 3(s3)               ; ...
        mv    a0, s3                    ; ...
        mv    a1, s2                    ; ...
        li    a2, 0                     ; ...
        call  csum                      ; ...
        xori  a1, a0, 0xffff            ; ...
        addi  a0, s3, 2                 ; ...
        call  put16                     ; ...
        li    a0, 1                     ; back to the sender
        la    a1, g_src                 ; ...
        ld    a1, 0(a1)                 ; ...
        mv    a2, s2                    ; ...
        call  ip_send                   ; ...
        j     ic_ret                    ; ...
ic_bad:
        call  count_err                 ; ...
ic_ret:
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; ---- UDP -----------------------------------------------------------------------------------
; udp_input(a0 = datagram, a1 = length)
udp_input:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        li    t0, 8                     ; a header at least
        bltu  s2, t0, ud_bad            ; ...
        addi  a0, s1, 4                 ; s3 = its length
        call  be16                      ; ...
        mv    s3, a0                    ; ...
        li    t0, 8                     ; ...
        bltu  s3, t0, ud_bad            ; ...
        bgtu  s3, s2, ud_bad            ; ...
        addi  a0, s1, 6                 ; a checksum (0: none)?
        call  be16                      ; ...
        beqz  a0, ud_ok                 ; ...
        li    a0, 17                    ; ...
        la    a1, g_src                 ; ...
        ld    a1, 0(a1)                 ; ...
        la    a2, g_dst                 ; ...
        ld    a2, 0(a2)                 ; ...
        mv    a3, s1                    ; ...
        mv    a4, s3                    ; ...
        call  l4sum                     ; 0 if right
        bnez  a0, ud_bad                ; ...
ud_ok:
        addi  a0, s1, 2                 ; the socket on its port
        call  be16                      ; ...
        call  find_udp                  ; ...
        beqz  a0, ud_ret                ; none: dropped
        mv    s4, a0                    ; ...
        addi  s3, s3, -8                ; s3 = payload bytes
        ld    t0, S_RXN(s4)             ; room for the record and the payload?
        li    t1, RXB - 8               ; ...
        sub   t1, t1, t0                ; ...
        bltu  t1, s3, ud_bad            ; no: dropped
        mv    a0, s1                    ; record: length | port << 16 | address << 32
        call  be16                      ; ...
        slli  a0, a0, 16                ; ...
        or    t0, a0, s3                ; ...
        la    t1, g_src                 ; ...
        ld    t1, 0(t1)                 ; ...
        slli  t1, t1, 32                ; ...
        or    t0, t0, t1                ; ...
        la    t1, urec                  ; ...
        sd    t0, 0(t1)                 ; ...
        mv    a0, s4                    ; ...
        la    a1, urec                  ; ...
        li    a2, 8                     ; ...
        call  ring_put                  ; ...
        mv    a0, s4                    ; the payload
        addi  a1, s1, 8                 ; ...
        mv    a2, s3                    ; ...
        call  ring_put                  ; ...
        mv    a0, s4                    ; a reader waiting?
        call  wake                      ; ...
        j     ud_ret                    ; ...
ud_bad:
        call  count_err                 ; ...
ud_ret:
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 40                ; ...
        ret                             ; ...

; udp_send(a0 = socket, a1 = address, a2 = port, a3 = payload bytes (at txpkt + 28))
udp_send:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        mv    s2, a1                    ; ...
        addi  s3, a3, 8                 ; s3 = UDP length
        ld    a1, S_LPORT(a0)           ; source port
        mv    s1, a2                    ; ...
        la    a0, txpkt + 20            ; ...
        call  put16                     ; ...
        la    a0, txpkt + 22            ; destination port
        mv    a1, s1                    ; ...
        call  put16                     ; ...
        la    a0, txpkt + 24            ; length
        mv    a1, s3                    ; ...
        call  put16                     ; ...
        la    t0, txpkt                 ; checksum 0 for now
        sb    zero, 26(t0)              ; ...
        sb    zero, 27(t0)              ; ...
        li    a0, 17                    ; ...
        la    a1, myip                  ; ...
        ld    a1, 0(a1)                 ; ...
        mv    a2, s2                    ; ...
        la    a3, txpkt + 20            ; ...
        mv    a4, s3                    ; ...
        call  l4sum                     ; ...
        bnez  a0, us_c                  ; (0 is sent as 0xffff)
        li    a0, 0xffff                ; ...
us_c:
        mv    a1, a0                    ; ...
        la    a0, txpkt + 26            ; ...
        call  put16                     ; ...
        li    a0, 17                    ; out
        mv    a1, s2                    ; ...
        mv    a2, s3                    ; ...
        call  ip_send                   ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; ---- TCP -----------------------------------------------------------------------------------
; tcp_input(a0 = segment, a1 = length)
tcp_input:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        mv    s2, a0                    ; s2 = segment, s3 = length
        mv    s3, a1                    ; ...
        li    t0, 20                    ; a header at least
        bltu  s3, t0, ti_bad            ; ...
        li    a0, 6                     ; the checksum
        la    a1, g_src                 ; ...
        ld    a1, 0(a1)                 ; ...
        la    a2, g_dst                 ; ...
        ld    a2, 0(a2)                 ; ...
        mv    a3, s2                    ; ...
        mv    a4, s3                    ; ...
        call  l4sum                     ; ...
        bnez  a0, ti_bad                ; ...
        mv    a0, s2                    ; ports
        call  be16                      ; ...
        la    t0, g_sport               ; ...
        sd    a0, 0(t0)                 ; ...
        addi  a0, s2, 2                 ; ...
        call  be16                      ; ...
        la    t0, g_dport               ; ...
        sd    a0, 0(t0)                 ; ...
        addi  a0, s2, 4                 ; sequence and acknowledgment numbers
        call  be32                      ; ...
        la    t0, g_seq                 ; ...
        sd    a0, 0(t0)                 ; ...
        addi  a0, s2, 8                 ; ...
        call  be32                      ; ...
        la    t0, g_ack                 ; ...
        sd    a0, 0(t0)                 ; ...
        lbu   s4, 12(s2)                ; s4 = header length
        srli  s4, s4, 4                 ; ...
        slli  s4, s4, 2                 ; ...
        li    t0, 20                    ; ...
        bltu  s4, t0, ti_bad            ; ...
        bgtu  s4, s3, ti_bad            ; ...
        lbu   t0, 13(s2)                ; flags
        andi  t0, t0, 0x3f              ; ...
        la    t1, g_flags               ; ...
        sd    t0, 0(t1)                 ; ...
        addi  a0, s2, 14                ; window
        call  be16                      ; ...
        la    t0, g_wnd                 ; ...
        sd    a0, 0(t0)                 ; ...
        add   t0, s2, s4                ; data, its length
        la    t1, g_data                ; ...
        sd    t0, 0(t1)                 ; ...
        sub   t0, s3, s4                ; ...
        la    t1, g_len                 ; ...
        sd    t0, 0(t1)                 ; ...
        li    t0, 536                   ; options: the MSS (536 without one)
        la    t1, g_mss                 ; ...
        sd    t0, 0(t1)                 ; ...
        li    s1, 20                    ; s1 = option offset
ti_opt:
        bgeu  s1, s4, ti_find           ; end of the options
        add   t0, s2, s1                ; the kind
        lbu   t1, 0(t0)                 ; ...
        beqz  t1, ti_find               ; end of list
        li    t2, 1                     ; no-op
        bne   t1, t2, ti_o2             ; ...
        addi  s1, s1, 1                 ; ...
        j     ti_opt                    ; ...
ti_o2:
        lbu   t3, 1(t0)                 ; its length
        li    t2, 2                     ; (at least 2)
        bltu  t3, t2, ti_find           ; ...
        bne   t1, t2, ti_on             ; kind 2: the MSS
        li    t2, 4                     ; ...
        bne   t3, t2, ti_on             ; ...
        addi  a0, t0, 2                 ; ...
        call  be16                      ; ...
        la    t1, g_mss                 ; ...
        sd    a0, 0(t1)                 ; ...
        add   t0, s2, s1                ; (again)
        lbu   t3, 1(t0)                 ; ...
ti_on:
        add   s1, s1, t3                ; the next option
        j     ti_opt                    ; ...
ti_find:
        call  find_conn                 ; a connection?
        bnez  a0, ti_conn               ; ...
        la    a0, g_dport               ; a listener?
        ld    a0, 0(a0)                 ; ...
        call  find_listen               ; ...
        beqz  a0, ti_stray              ; no: reset
        mv    s1, a0                    ; s1 = the listener
        la    t0, g_flags               ; RST: ignored; ACK: reset; SYN: a new connection
        ld    t0, 0(t0)                 ; ...
        andi  t1, t0, TF_RST            ; ...
        bnez  t1, ti_ret                ; ...
        andi  t1, t0, TF_ACK            ; ...
        bnez  t1, ti_stray              ; ...
        andi  t1, t0, TF_SYN            ; ...
        beqz  t1, ti_ret                ; ...
        call  sock_alloc                ; room?
        beqz  a0, ti_ret                ; no: dropped (it will be sent again)
        mv    s3, a0                    ; s3 = the new connection
        li    t0, 6                     ; ...
        sd    t0, S_PROTO(s3)           ; ...
        li    t0, ST_SYNRCVD            ; ...
        sd    t0, S_STATE(s3)           ; ...
        ld    t0, S_LPORT(s1)           ; ...
        sd    t0, S_LPORT(s3)           ; ...
        la    t0, g_sport               ; ...
        ld    t0, 0(t0)                 ; ...
        sd    t0, S_RPORT(s3)           ; ...
        la    t0, g_src                 ; ...
        ld    t0, 0(t0)                 ; ...
        sd    t0, S_RIP(s3)             ; ...
        ld    t0, S_ID(s1)              ; the listener's, until accepted
        sd    t0, S_PARENT(s3)          ; ...
        ld    t0, S_OWNER(s1)           ; ...
        sd    t0, S_OWNER(s3)           ; ...
        la    t0, g_seq                 ; rcv_nxt = their ISS + 1
        ld    t0, 0(t0)                 ; ...
        addi  t0, t0, 1                 ; ...
        slli  t0, t0, 32                ; ...
        srli  t0, t0, 32                ; ...
        sd    t0, S_RCV(s3)             ; ...
        mv    a0, s3                    ; ...
        call  take_peer                 ; window, MSS
        mv    a0, s3                    ; ours
        call  new_iss                   ; ...
        mv    a0, s3                    ; SYN-ACK
        li    a1, TF_SYN | TF_ACK       ; ...
        ld    a2, S_ISS(s3)             ; ...
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        call  tcp_send                  ; ...
        mv    a0, s3                    ; ...
        call  arm_rto                   ; ...
        j     ti_ret                    ; ...
ti_conn:
        mv    s1, a0                    ; s1 = the connection
        ld    t0, S_STATE(s1)           ; ...
        li    t1, ST_SYNSENT            ; ...
        bne   t0, t1, ti_sync           ; ...
        call  tcp_synsent               ; (s1)
        j     ti_ret                    ; ...
ti_sync:
        call  tcp_sync                  ; (s1)
        j     ti_ret                    ; ...
ti_stray:
        call  send_rst                  ; ...
        j     ti_ret                    ; ...
ti_bad:
        call  count_err                 ; ...
ti_ret:
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 40                ; ...
        ret                             ; ...

; take_peer(a0 = socket): the segment's window and MSS option become the peer's
take_peer:
        la    t0, g_wnd                 ; ...
        ld    t0, 0(t0)                 ; ...
        sd    t0, S_WND(a0)             ; ...
        la    t0, g_mss                 ; at most ours
        ld    t0, 0(t0)                 ; ...
        li    t1, MSS                   ; ...
        bleu  t0, t1, tp_s              ; ...
        mv    t0, t1                    ; ...
tp_s:
        bnez  t0, tp_s2                 ; (never 0)
        li    t0, 536                   ; ...
tp_s2:
        sd    t0, S_MSS(a0)             ; ...
        ret                             ; ...

; send_rst(): answer the segment (g_*), which no connection wants, with a reset
send_rst:
        la    t0, g_flags               ; never answer a reset
        ld    t0, 0(t0)                 ; ...
        andi  t1, t0, TF_RST            ; ...
        bnez  t1, sr_ret                ; ...
        la    a0, tmps                  ; a socket made up for it
        la    t1, g_dport               ; ...
        ld    t1, 0(t1)                 ; ...
        sd    t1, S_LPORT(a0)           ; ...
        la    t1, g_sport               ; ...
        ld    t1, 0(t1)                 ; ...
        sd    t1, S_RPORT(a0)           ; ...
        la    t1, g_src                 ; ...
        ld    t1, 0(t1)                 ; ...
        sd    t1, S_RIP(a0)             ; ...
        sd    zero, S_RXN(a0)           ; ...
        li    t1, 1                     ; (its rings: socket 1's, unused here)
        sd    t1, S_ID(a0)              ; ...
        andi  t1, t0, TF_ACK            ; with an ACK: seq = its ack
        beqz  t1, sr_na                 ; ...
        li    a1, TF_RST                ; ...
        la    a2, g_ack                 ; ...
        ld    a2, 0(a2)                 ; ...
        j     sr_go                     ; ...
sr_na:
        la    t1, g_seq                 ; else ack = its seq + length (+ SYN, FIN)
        ld    t1, 0(t1)                 ; ...
        la    t2, g_len                 ; ...
        ld    t2, 0(t2)                 ; ...
        add   t1, t1, t2                ; ...
        andi  t2, t0, TF_SYN            ; ...
        beqz  t2, sr_f                  ; ...
        addi  t1, t1, 1                 ; ...
sr_f:
        andi  t2, t0, TF_FIN            ; ...
        beqz  t2, sr_s                  ; ...
        addi  t1, t1, 1                 ; ...
sr_s:
        slli  t1, t1, 32                ; ...
        srli  t1, t1, 32                ; ...
        sd    t1, S_RCV(a0)             ; ...
        li    a1, TF_RST | TF_ACK       ; ...
        li    a2, 0                     ; ...
sr_go:
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        j     tcp_send                  ; (tail call)
sr_ret:
        ret                             ; ...

; tcp_synsent(s1 = the connection): an answer to our SYN?
tcp_synsent:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        la    t0, g_flags               ; s4 = flags
        ld    s4, 0(t0)                 ; ...
        andi  t1, s4, TF_ACK            ; an ACK must be for our SYN
        beqz  t1, tss_r                 ; ...
        la    t0, g_ack                 ; ...
        ld    t0, 0(t0)                 ; ...
        ld    t1, S_NXT(s1)             ; ...
        beq   t0, t1, tss_r             ; ...
        call  send_rst                  ; (not: reset it, unless it is a reset)
        j     tss_ret                   ; ...
tss_r:
        andi  t1, s4, TF_RST            ; a reset (with a good ACK): refused
        beqz  t1, tss_s                 ; ...
        andi  t1, s4, TF_ACK            ; ...
        beqz  t1, tss_ret               ; ...
        mv    a0, s1                    ; ...
        li    a1, 0                     ; ...
        call  tcp_abort                 ; ...
        j     tss_ret                   ; ...
tss_s:
        andi  t1, s4, TF_SYN            ; a SYN
        beqz  t1, tss_ret               ; ...
        la    t0, g_seq                 ; rcv_nxt = their ISS + 1
        ld    t0, 0(t0)                 ; ...
        addi  t0, t0, 1                 ; ...
        slli  t0, t0, 32                ; ...
        srli  t0, t0, 32                ; ...
        sd    t0, S_RCV(s1)             ; ...
        mv    a0, s1                    ; ...
        call  take_peer                 ; ...
        andi  t1, s4, TF_ACK            ; SYN-ACK: established
        beqz  t1, tss_simul             ; ...
        la    t0, g_ack                 ; ...
        ld    t0, 0(t0)                 ; ...
        sd    t0, S_UNA(s1)             ; ...
        li    t0, ST_EST                ; ...
        sd    t0, S_STATE(s1)           ; ...
        sd    zero, S_RTO(s1)           ; ...
        sd    zero, S_TRIES(s1)         ; ...
        li    t0, RTO0                  ; ...
        sd    t0, S_RTOV(s1)            ; ...
        mv    a0, s1                    ; the third step
        li    a1, TF_ACK                ; ...
        ld    a2, S_NXT(s1)             ; ...
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        call  tcp_send                  ; ...
        mv    a0, s1                    ; CONNECT is answered
        call  wake                      ; ...
        j     tss_ret                   ; ...
tss_simul:
        li    t0, ST_SYNRCVD            ; both sent SYNs at once
        sd    t0, S_STATE(s1)           ; ...
        mv    a0, s1                    ; ...
        li    a1, TF_SYN | TF_ACK       ; ...
        ld    a2, S_ISS(s1)             ; ...
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        call  tcp_send                  ; ...
tss_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; tcp_sync(s1 = the connection): a segment in a synchronized state (or SYN-RECEIVED)
tcp_sync:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s2, 8(sp)                 ; ...
        sd    s3, 16(sp)                ; ...
        sd    s4, 24(sp)                ; ...
        sd    s5, 32(sp)                ; ...
        sd    s6, 40(sp)                ; ...
        la    t0, g_flags               ; s4 = flags
        ld    s4, 0(t0)                 ; ...
        la    t0, g_data                ; s2 = data, s3 = its length
        ld    s2, 0(t0)                 ; ...
        la    t0, g_len                 ; ...
        ld    s3, 0(t0)                 ; ...
        ld    t0, S_RCV(s1)             ; s5 = rcv_nxt - seq: how much of it is old
        la    t1, g_seq                 ; ...
        ld    t1, 0(t1)                 ; ...
        sub   s5, t0, t1                ; ...
        slli  s5, s5, 32                ; (signed 32 bits)
        srai  s5, s5, 32                ; ...
        bgez  s5, tsy_inw               ; ...
        andi  t0, s4, TF_RST            ; ahead of what we expect: dropped (and
        bnez  t0, tsy_ret               ;   acknowledged, so the peer resends)
        j     tsy_acknow                ; ...
tsy_inw:
        andi  t0, s4, TF_SYN            ; a SYN again?
        beqz  t0, tsy_rst               ; ...
        ld    t0, S_STATE(s1)           ; our SYN-ACK was lost: again
        li    t1, ST_SYNRCVD            ; ...
        bne   t0, t1, tsy_acknow        ; (otherwise: an old SYN, acknowledge)
        mv    a0, s1                    ; ...
        li    a1, TF_SYN | TF_ACK       ; ...
        ld    a2, S_ISS(s1)             ; ...
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        call  tcp_send                  ; ...
        j     tsy_ret                   ; ...
tsy_rst:
        andi  t0, s4, TF_RST            ; a reset (exactly at rcv_nxt)
        beqz  t0, tsy_trim              ; ...
        bnez  s5, tsy_ret               ; (elsewhere: ignored)
        mv    a0, s1                    ; (one not yet accepted just goes)
        li    a1, 0                     ; ...
        call  tcp_abort                 ; ...
        j     tsy_ret                   ; ...
tsy_trim:
        beqz  s5, tsy_ack               ; old bytes at its start: skip them
        ld    t0, S_FLAGS(s1)           ; (and acknowledge: the peer resent)
        ori   t0, t0, SF_ACKNOW         ; ...
        sd    t0, S_FLAGS(s1)           ; ...
        bgt   s5, s3, tsy_old           ; all of it old, its FIN too
        add   s2, s2, s5                ; ...
        sub   s3, s3, s5                ; ...
        j     tsy_ack                   ; ...
tsy_old:
        li    s3, 0                     ; no data
        andi  s4, s4, 0x3e              ; no (new) FIN
tsy_ack:
        andi  t0, s4, TF_ACK            ; the acknowledgment
        beqz  t0, tsy_ret               ; (none: nothing more to do)
        ld    t0, S_STATE(s1)           ; SYN-RECEIVED: our SYN acknowledged?
        li    t1, ST_SYNRCVD            ; ...
        bne   t0, t1, tsy_a2            ; ...
        la    t0, g_ack                 ; ...
        ld    t0, 0(t0)                 ; ...
        ld    t1, S_NXT(s1)             ; ...
        beq   t0, t1, tsy_est           ; ...
        call  send_rst                  ; no
        j     tsy_ret                   ; ...
tsy_est:
        sd    t0, S_UNA(s1)             ; established
        li    t0, ST_EST                ; ...
        sd    t0, S_STATE(s1)           ; ...
        sd    zero, S_RTO(s1)           ; ...
        sd    zero, S_TRIES(s1)         ; ...
        li    t0, RTO0                  ; ...
        sd    t0, S_RTOV(s1)            ; ...
        la    t0, g_wnd                 ; ...
        ld    t0, 0(t0)                 ; ...
        sd    t0, S_WND(s1)             ; ...
        ld    t0, S_PARENT(s1)          ; waiting to be accepted
        beqz  t0, tsy_data              ; (a simultaneous open has no listener)
        ld    t1, S_FLAGS(s1)           ; ...
        ori   t1, t1, SF_UNACC          ; ...
        sd    t1, S_FLAGS(s1)           ; ...
        mv    a0, t0                    ; the listener's ACCEPT
        call  sock_by_id                ; ...
        beqz  a0, tsy_data              ; ...
        call  wake                      ; ...
        j     tsy_data                  ; ...
tsy_a2:
        la    t0, g_ack                 ; t2 = ack - una, t3 = ack - nxt (signed 32)
        ld    t0, 0(t0)                 ; ...
        ld    t1, S_UNA(s1)             ; ...
        sub   t2, t0, t1                ; ...
        slli  t2, t2, 32                ; ...
        srai  t2, t2, 32                ; ...
        ld    t1, S_NXT(s1)             ; ...
        sub   t3, t0, t1                ; ...
        slli  t3, t3, 32                ; ...
        srai  t3, t3, 32                ; ...
        blez  t3, tsy_a3                ; acknowledges what was never sent: say so
        j     tsy_acknow                ; ...
tsy_a3:
        la    t1, g_wnd                 ; the window
        ld    t1, 0(t1)                 ; ...
        sd    t1, S_WND(s1)             ; ...
        blez  t2, tsy_data              ; nothing new acknowledged
        sd    t0, S_UNA(s1)             ; snd_una = ack
        li    s5, 0                     ; s5 = our FIN acknowledged (the offset is done with)
        mv    s6, t2                    ; s6 = data bytes acknowledged
        ld    t1, S_FLAGS(s1)           ; ...
        andi  t1, t1, SF_FINSENT        ; ...
        beqz  t1, tsy_a4                ; ...
        bnez  t3, tsy_a4                ; ...
        li    s5, 1                     ; ...
        addi  s6, s6, -1                ; (the FIN is not data)
tsy_a4:
        ld    t1, S_TXN(s1)             ; data acknowledged: out of the send buffer
        bleu  s6, t1, tsy_a5            ; ...
        mv    s6, t1                    ; ...
tsy_a5:
        sub   t1, t1, s6                ; ...
        sd    t1, S_TXN(s1)             ; ...
        mv    a0, s1                    ; move the rest down
        call  txbp                      ; a0 = the buffer (destination)
        add   a1, a0, s6                ; ...
        ld    a2, S_TXN(s1)             ; ...
        call  srv_bcopy                 ; (downward: safe)
        sd    zero, S_TRIES(s1)         ; the timer starts over
        li    t0, RTO0                  ; ...
        sd    t0, S_RTOV(s1)            ; ...
        sd    zero, S_RTO(s1)           ; ...
        ld    t0, S_UNA(s1)             ; still something in flight: run it again
        ld    t1, S_NXT(s1)             ; ...
        beq   t0, t1, tsy_a6            ; ...
        mv    a0, s1                    ; ...
        call  arm_rto                   ; ...
tsy_a6:
        beqz  s5, tsy_aw                ; our FIN acknowledged:
        ld    t0, S_STATE(s1)           ; ...
        li    t1, ST_FINW1              ; FIN-WAIT-1 -> FIN-WAIT-2
        bne   t0, t1, tsy_a7            ; ...
        li    t0, ST_FINW2              ; ...
        sd    t0, S_STATE(s1)           ; ...
        call  now                       ; (not for ever)
        li    t0, FW2T                  ; ...
        add   a0, a0, t0                ; ...
        sd    a0, S_RTO(s1)             ; ...
        j     tsy_aw                    ; ...
tsy_a7:
        li    t1, ST_CLOSING            ; CLOSING -> TIME-WAIT
        bne   t0, t1, tsy_a8            ; ...
        mv    a0, s1                    ; ...
        call  enter_tw                  ; ...
        j     tsy_aw                    ; ...
tsy_a8:
        li    t1, ST_LASTACK            ; LAST-ACK -> gone
        bne   t0, t1, tsy_aw            ; ...
        mv    a0, s1                    ; ...
        call  sock_free                 ; ...
        j     tsy_ret                   ; ...
tsy_aw:
        mv    a0, s1                    ; a writer waiting for room
        call  wake                      ; ...
        ld    t0, S_STATE(s1)           ; (wake may have answered with a close? no: it
        beqz  t0, tsy_ret               ;   never frees; but be safe)
tsy_data:
        beqz  s3, tsy_fin               ; data?
        ld    t0, S_STATE(s1)           ; only while we still receive
        li    t1, ST_EST                ; ...
        beq   t0, t1, tsy_d1            ; ...
        li    t1, ST_FINW1              ; ...
        beq   t0, t1, tsy_d1            ; ...
        li    t1, ST_FINW2              ; ...
        bne   t0, t1, tsy_fin           ; ...
tsy_d1:
        ld    t0, S_RXN(s1)             ; what fits in the ring
        li    t1, RXB                   ; ...
        sub   t1, t1, t0                ; ...
        mv    t2, s3                    ; ...
        bleu  t2, t1, tsy_d2            ; ...
        mv    t2, t1                    ; (the rest is dropped: beyond the window)
        andi  s4, s4, 0x3e              ; (and a FIN after it is not seen yet)
tsy_d2:
        ld    t0, S_RCV(s1)             ; rcv_nxt += taken
        add   t0, t0, t2                ; ...
        slli  t0, t0, 32                ; ...
        srli  t0, t0, 32                ; ...
        sd    t0, S_RCV(s1)             ; ...
        ld    t0, S_FLAGS(s1)           ; acknowledge it
        ori   t0, t0, SF_ACKNOW         ; ...
        sd    t0, S_FLAGS(s1)           ; ...
        mv    a0, s1                    ; into the ring
        mv    a1, s2                    ; ...
        mv    a2, t2                    ; ...
        call  ring_put                  ; ...
        mv    a0, s1                    ; a reader waiting
        call  wake                      ; ...
tsy_fin:
        andi  t0, s4, TF_FIN            ; the peer's FIN
        beqz  t0, tsy_out               ; ...
        ld    t0, S_STATE(s1)           ; (in a state where it means something)
        li    t1, ST_EST                ; ...
        bltu  t0, t1, tsy_out           ; ...
        ld    t0, S_FLAGS(s1)           ; once
        andi  t1, t0, SF_FINRCV         ; ...
        bnez  t1, tsy_acknow            ; ...
        ori   t0, t0, SF_FINRCV | SF_ACKNOW ; ...
        sd    t0, S_FLAGS(s1)           ; ...
        ld    t0, S_RCV(s1)             ; it takes a sequence number
        addi  t0, t0, 1                 ; ...
        slli  t0, t0, 32                ; ...
        srli  t0, t0, 32                ; ...
        sd    t0, S_RCV(s1)             ; ...
        ld    t0, S_STATE(s1)           ; ESTABLISHED -> CLOSE-WAIT
        li    t1, ST_EST                ; ...
        bne   t0, t1, tsy_f1            ; ...
        li    t0, ST_CLOSEW             ; ...
        sd    t0, S_STATE(s1)           ; ...
        j     tsy_fw                    ; ...
tsy_f1:
        li    t1, ST_FINW1              ; FIN-WAIT-1 -> CLOSING (our FIN is not acknowledged yet)
        bne   t0, t1, tsy_f2            ; ...
        li    t0, ST_CLOSING            ; ...
        sd    t0, S_STATE(s1)           ; ...
        j     tsy_fw                    ; ...
tsy_f2:
        li    t1, ST_FINW2              ; FIN-WAIT-2 -> TIME-WAIT
        bne   t0, t1, tsy_fw            ; ...
        mv    a0, s1                    ; ...
        call  enter_tw                  ; ...
tsy_fw:
        mv    a0, s1                    ; a reader sees the end
        call  wake                      ; ...
        j     tsy_out                   ; ...
tsy_acknow:
        ld    t0, S_FLAGS(s1)           ; an ACK is due
        ori   t0, t0, SF_ACKNOW         ; ...
        sd    t0, S_FLAGS(s1)           ; ...
tsy_out:
        ld    t0, S_STATE(s1)           ; (still there?)
        beqz  t0, tsy_ret               ; ...
        mv    a0, s1                    ; send what is due
        call  tcp_output                ; ...
tsy_ret:
        ld    s6, 40(sp)                ; ...
        ld    s5, 32(sp)                ; ...
        ld    s4, 24(sp)                ; ...
        ld    s3, 16(sp)                ; ...
        ld    s2, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; ...

; enter_tw(a0 = socket): TIME-WAIT, for a while
enter_tw:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        li    t0, ST_TIMEW              ; ...
        sd    t0, S_STATE(a0)           ; ...
        call  now                       ; ...
        li    t0, TWAIT                 ; ...
        add   a0, a0, t0                ; ...
        ld    t0, 8(sp)                 ; ...
        sd    a0, S_RTO(t0)             ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; tcp_output(a0 = socket): send what the window allows, the FIN when due, an ACK if due
tcp_output:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        mv    s1, a0                    ; ...
        li    s4, 0                     ; s4 = something sent
        ld    t0, S_STATE(s1)           ; states that send data
        li    t1, ST_EST                ; ...
        beq   t0, t1, to_l              ; ...
        li    t1, ST_CLOSEW             ; ...
        beq   t0, t1, to_l              ; ...
        li    t1, ST_FINW1              ; ...
        beq   t0, t1, to_l              ; ...
        li    t1, ST_CLOSING            ; ...
        beq   t0, t1, to_l              ; ...
        li    t1, ST_LASTACK            ; ...
        beq   t0, t1, to_l              ; ...
        j     to_ack                    ; (others: an ACK at most)
to_l:
        ld    t0, S_NXT(s1)             ; s2 = data in flight = nxt - una (- the FIN)
        ld    t1, S_UNA(s1)             ; ...
        sub   s2, t0, t1                ; ...
        slli  s2, s2, 32                ; ...
        srli  s2, s2, 32                ; ...
        ld    t0, S_FLAGS(s1)           ; ...
        andi  t0, t0, SF_FINSENT        ; ...
        beqz  t0, to_l1                 ; ...
        beqz  s2, to_l1                 ; ...
        addi  s2, s2, -1                ; ...
to_l1:
        ld    s3, S_TXN(s1)             ; s3 = not sent yet
        sub   s3, s3, s2                ; ...
        blez  s3, to_fin                ; nothing
        ld    t0, S_WND(s1)             ; room in the peer's window?
        bgeu  s2, t0, to_probe          ; no
        sub   t0, t0, s2                ; at most the window, the MSS, what there is
        bleu  s3, t0, to_m1             ; ...
        mv    s3, t0                    ; ...
to_m1:
        ld    t0, S_MSS(s1)             ; ...
        bleu  s3, t0, to_m2             ; ...
        mv    s3, t0                    ; ...
to_m2:
        mv    a0, s1                    ; the segment
        call  txbp                      ; ...
        add   a3, a0, s2                ; data from the send buffer at the first unsent byte
        mv    a0, s1                    ; ...
        li    a1, TF_ACK | TF_PSH       ; ...
        ld    a2, S_NXT(s1)             ; ...
        mv    a4, s3                    ; ...
        call  tcp_send                  ; ...
        ld    t0, S_NXT(s1)             ; nxt += sent
        add   t0, t0, s3                ; ...
        slli  t0, t0, 32                ; ...
        srli  t0, t0, 32                ; ...
        sd    t0, S_NXT(s1)             ; ...
        li    s4, 1                     ; ...
        mv    a0, s1                    ; the timer runs
        call  arm_rto                   ; ...
        j     to_l                      ; more?
to_probe:
        mv    a0, s1                    ; a closed window: the timer probes it
        call  arm_rto                   ; ...
        j     to_ack                    ; ...
to_fin:
        ld    t0, S_FLAGS(s1)           ; closed or shut down, all data sent, no FIN yet
        andi  t1, t0, SF_CLOSE | SF_SHUT ; ...
        beqz  t1, to_ack                ; ...
        andi  t1, t0, SF_FINSENT        ; ...
        bnez  t1, to_ack                ; ...
        ld    t1, S_STATE(s1)           ; (from ESTABLISHED or CLOSE-WAIT)
        li    t2, ST_EST                ; ...
        beq   t1, t2, to_f1             ; ...
        li    t2, ST_CLOSEW             ; ...
        bne   t1, t2, to_ack            ; ...
        li    t1, ST_LASTACK            ; CLOSE-WAIT -> LAST-ACK
        j     to_f2                     ; ...
to_f1:
        li    t1, ST_FINW1              ; ESTABLISHED -> FIN-WAIT-1
to_f2:
        sd    t1, S_STATE(s1)           ; ...
        ori   t0, t0, SF_FINSENT        ; ...
        sd    t0, S_FLAGS(s1)           ; ...
        mv    a0, s1                    ; FIN
        li    a1, TF_FIN | TF_ACK       ; ...
        ld    a2, S_NXT(s1)             ; ...
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        call  tcp_send                  ; ...
        ld    t0, S_NXT(s1)             ; it takes a sequence number
        addi  t0, t0, 1                 ; ...
        slli  t0, t0, 32                ; ...
        srli  t0, t0, 32                ; ...
        sd    t0, S_NXT(s1)             ; ...
        li    s4, 1                     ; ...
        mv    a0, s1                    ; ...
        call  arm_rto                   ; ...
to_ack:
        ld    t0, S_FLAGS(s1)           ; an ACK due and nothing sent carried it
        andi  t1, t0, SF_ACKNOW         ; ...
        beqz  t1, to_ret                ; ...
        xori  t0, t0, SF_ACKNOW         ; ...
        sd    t0, S_FLAGS(s1)           ; ...
        bnez  s4, to_ret                ; ...
        ld    t0, S_STATE(s1)           ; (only once synchronized)
        li    t1, ST_EST                ; ...
        bltu  t0, t1, to_ret            ; ...
        mv    a0, s1                    ; ...
        li    a1, TF_ACK                ; ...
        ld    a2, S_NXT(s1)             ; ...
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        call  tcp_send                  ; ...
to_ret:
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; ...

; tcp_rexmit(a0 = socket): the timer ran out: the oldest thing in flight again
tcp_rexmit:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        mv    s1, a0                    ; ...
        ld    t0, S_STATE(s1)           ; SYN-SENT: the SYN
        li    t1, ST_SYNSENT            ; ...
        bne   t0, t1, trx_sr            ; ...
        li    a1, TF_SYN                ; ...
        j     trx_syn                   ; ...
trx_sr:
        li    t1, ST_SYNRCVD            ; SYN-RECEIVED: the SYN-ACK
        bne   t0, t1, trx_d             ; ...
        li    a1, TF_SYN | TF_ACK       ; ...
trx_syn:
        mv    a0, s1                    ; ...
        ld    a2, S_ISS(s1)             ; ...
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        call  tcp_send                  ; ...
        j     trx_ret                   ; ...
trx_d:
        ld    t2, S_TXN(s1)             ; data: up to an MSS from snd_una (also a window probe)
        beqz  t2, trx_f                 ; ...
        ld    t0, S_MSS(s1)             ; ...
        bleu  t2, t0, trx_d2            ; ...
        mv    t2, t0                    ; ...
trx_d2:
        addi  sp, sp, -8                ; (keep the length)
        sd    t2, 0(sp)                 ; ...
        mv    a0, s1                    ; ...
        call  txbp                      ; ...
        mv    a3, a0                    ; ...
        mv    a0, s1                    ; ...
        li    a1, TF_ACK | TF_PSH       ; ...
        ld    a2, S_UNA(s1)             ; ...
        ld    a4, 0(sp)                 ; ...
        call  tcp_send                  ; ...
        ld    t2, 0(sp)                 ; nxt is at least una + that
        addi  sp, sp, 8                 ; ...
        ld    t0, S_UNA(s1)             ; ...
        add   t0, t0, t2                ; ...
        slli  t0, t0, 32                ; ...
        srli  t0, t0, 32                ; ...
        ld    t1, S_NXT(s1)             ; ...
        sub   t3, t0, t1                ; ...
        slli  t3, t3, 32                ; ...
        srai  t3, t3, 32                ; ...
        blez  t3, trx_ret               ; ...
        sd    t0, S_NXT(s1)             ; ...
        j     trx_ret                   ; ...
trx_f:
        ld    t0, S_FLAGS(s1)           ; only the FIN is in flight
        andi  t0, t0, SF_FINSENT        ; ...
        beqz  t0, trx_ret               ; ...
        ld    t0, S_UNA(s1)             ; (not yet acknowledged)
        ld    t1, S_NXT(s1)             ; ...
        beq   t0, t1, trx_ret           ; ...
        mv    a0, s1                    ; ...
        li    a1, TF_FIN | TF_ACK       ; ...
        mv    a2, t0                    ; ...
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        call  tcp_send                  ; ...
trx_ret:
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; tcp_send(a0 = socket, a1 = flags, a2 = sequence number, a3 = data (D-LS) or 0, a4 = bytes)
tcp_send:
        addi  sp, sp, -56               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        sd    s5, 40(sp)                ; ...
        sd    s6, 48(sp)                ; ...
        mv    s1, a0                    ; s1 socket, s2 flags, s3 seq, s4 data, s5 bytes
        mv    s2, a1                    ; ...
        mv    s3, a2                    ; ...
        mv    s4, a3                    ; ...
        mv    s5, a4                    ; ...
        li    s6, 20                    ; s6 = header length (24 with the MSS option)
        andi  t0, s2, TF_SYN            ; ...
        beqz  t0, tsd_h                 ; ...
        li    s6, 24                    ; ...
tsd_h:
        la    a0, txpkt + 20            ; ports
        ld    a1, S_LPORT(s1)           ; ...
        call  put16                     ; ...
        la    a0, txpkt + 22            ; ...
        ld    a1, S_RPORT(s1)           ; ...
        call  put16                     ; ...
        la    a0, txpkt + 24            ; sequence number
        mv    a1, s3                    ; ...
        call  put32                     ; ...
        li    a1, 0                     ; acknowledgment (with ACK)
        andi  t0, s2, TF_ACK            ; ...
        beqz  t0, tsd_a                 ; ...
        ld    a1, S_RCV(s1)             ; ...
tsd_a:
        la    a0, txpkt + 28            ; ...
        call  put32                     ; ...
        la    t0, txpkt                 ; header length, flags
        slli  t1, s6, 2                 ; (words << 4)
        sb    t1, 32(t0)                ; ...
        sb    s2, 33(t0)                ; ...
        ld    t1, S_RXN(s1)             ; the window: room in the ring
        li    a1, RXB                   ; ...
        sub   a1, a1, t1                ; ...
        sd    a1, S_ADVW(s1)            ; ...
        la    a0, txpkt + 34            ; ...
        call  put16                     ; ...
        la    t0, txpkt                 ; checksum 0 for now, urgent 0
        sw    zero, 36(t0)              ; ...
        li    t1, 24                    ; the MSS option
        bne   s6, t1, tsd_d             ; ...
        li    t1, 2                     ; kind 2, length 4
        sb    t1, 40(t0)                ; ...
        li    t1, 4                     ; ...
        sb    t1, 41(t0)                ; ...
        la    a0, txpkt + 42            ; ...
        li    a1, MSS                   ; ...
        call  put16                     ; ...
tsd_d:
        beqz  s5, tsd_c                 ; the data
        la    a0, txpkt + 20            ; ...
        add   a0, a0, s6                ; ...
        mv    a1, s4                    ; ...
        mv    a2, s5                    ; ...
        call  srv_bcopy                 ; ...
tsd_c:
        li    a0, 6                     ; the checksum
        la    a1, myip                  ; ...
        ld    a1, 0(a1)                 ; ...
        ld    a2, S_RIP(s1)             ; ...
        la    a3, txpkt + 20            ; ...
        add   a4, s6, s5                ; ...
        call  l4sum                     ; ...
        mv    a1, a0                    ; ...
        la    a0, txpkt + 36            ; ...
        call  put16                     ; ...
        li    a0, 6                     ; out
        ld    a1, S_RIP(s1)             ; ...
        add   a2, s6, s5                ; ...
        call  ip_send                   ; ...
        ld    s6, 48(sp)                ; ...
        ld    s5, 40(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 56                ; ...
        ret                             ; ...

; ---- checksums and network byte order ----------------------------------------------------------
; csum(a0 = address, a1 = bytes, a2 = sum so far) -> a0 = the ones' complement sum, folded to 16 bits
csum:
        li    t2, 2                     ; ...
cks_l:
        bltu  a1, t2, cks_odd           ; pairs of bytes, big-endian
        lbu   t0, 0(a0)                 ; ...
        lbu   t1, 1(a0)                 ; ...
        slli  t0, t0, 8                 ; ...
        or    t0, t0, t1                ; ...
        add   a2, a2, t0                ; ...
        addi  a0, a0, 2                 ; ...
        addi  a1, a1, -2                ; ...
        j     cks_l                     ; ...
cks_odd:
        beqz  a1, cks_f                 ; a last byte: padded with zero
        lbu   t0, 0(a0)                 ; ...
        slli  t0, t0, 8                 ; ...
        add   a2, a2, t0                ; ...
cks_f:
        srli  t0, a2, 16                ; fold the carries in
        beqz  t0, cks_ret               ; ...
        andi  a2, a2, 0xffff            ; ...
        add   a2, a2, t0                ; ...
        j     cks_f                     ; ...
cks_ret:
        mv    a0, a2                    ; ...
        ret                             ; ...

; l4sum(a0 = protocol, a1 = source, a2 = destination, a3 = address, a4 = bytes) -> a0 =
; the TCP/UDP checksum over the pseudo-header and the bytes (0 when checking a correct one)
l4sum:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        srli  t0, a1, 16                ; the pseudo-header: addresses, protocol, length
        andi  t1, a1, 0xffff            ; ...
        add   t0, t0, t1                ; ...
        srli  t1, a2, 16                ; ...
        add   t0, t0, t1                ; ...
        andi  t1, a2, 0xffff            ; ...
        add   t0, t0, t1                ; ...
        add   t0, t0, a0                ; ...
        add   a2, t0, a4                ; ...
        mv    a0, a3                    ; ...
        mv    a1, a4                    ; ...
        call  csum                      ; ...
        xori  a0, a0, 0xffff            ; complemented
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; be16(a0 = address) -> a0 = the big-endian u16 there; be32: u32
be16:
        lbu   t0, 0(a0)                 ; ...
        lbu   t1, 1(a0)                 ; ...
        slli  t0, t0, 8                 ; ...
        or    a0, t0, t1                ; ...
        ret                             ; ...
be32:
        lbu   t0, 0(a0)                 ; ...
        lbu   t1, 1(a0)                 ; ...
        slli  t0, t0, 8                 ; ...
        or    t0, t0, t1                ; ...
        lbu   t1, 2(a0)                 ; ...
        slli  t0, t0, 8                 ; ...
        or    t0, t0, t1                ; ...
        lbu   t1, 3(a0)                 ; ...
        slli  t0, t0, 8                 ; ...
        or    a0, t0, t1                ; ...
        ret                             ; ...

; put16(a0 = address, a1 = value): big-endian; put32: u32
put16:
        srli  t0, a1, 8                 ; ...
        sb    t0, 0(a0)                 ; ...
        sb    a1, 1(a0)                 ; ...
        ret                             ; ...
put32:
        srli  t0, a1, 24                ; ...
        sb    t0, 0(a0)                 ; ...
        srli  t0, a1, 16                ; ...
        sb    t0, 1(a0)                 ; ...
        srli  t0, a1, 8                 ; ...
        sb    t0, 2(a0)                 ; ...
        sb    a1, 3(a0)                 ; ...
        ret                             ; ...

