; =============================================================================
; net.s: the network server (IPv4, ICMP echo, UDP, TCP)
; =============================================================================
;
; `net ADDRESS` (e.g. `net 10.0.0.1 &` in rc or at a shell) starts it: proc
; creates a program named exactly `net` as the server of the lowest empty
; core, alone on it (it keeps a device read in flight, like tty). It
; registers "net", gets the network interface's ports from dev (GETNET, only
; for the process registered as "net") and serves programs through
; os/lib/sys.s (net_*). The interface carries raw IPv4 packets (no link
; layer, so no ARP and no routing: every address is on the link); its
; address is the one given at start (SETIP changes it).
;
; Like tty it never blocks on the device: a read of the RX port (tag 1) is
; always in flight, and svc RECEIVE waits for a request, that tag, or the
; next timer (TCP retransmission, TIME-WAIT, pings, the owner check), read
; from the clock (c7). Requests (handle = socket id unless said otherwise):
;
;   1 READ    TCP: length = most bytes, mode bit0 = do not block -> bytes; 0
;             once the peer has closed and everything was read; waits while
;             nothing is there (-3 with mode bit0); -1 after a reset
;   2 WRITE   TCP: the data -> bytes taken (at least 1: the library writes
;             the rest); waits while the send buffer is full; -1 if closed
;   4 CLOSE   -> 0. TCP: the data still buffered is sent, then FIN; the
;             connection finishes on its own. mode bit0: only stop sending
;             (FIN after the data), the socket stays readable (shutdown)
;  50 STAT    -> sockets in use; data: u64 ip, u64 device STATUS, u64 packets
;             in, out, dropped, u64 socket slots, 2 reserved; then 32 bytes
;             per socket (see net_stat in os/lib/sys.s)
;  51 SETIP   handle = the new address -> 0
;  52 PING    handle = address, length = payload bytes (<= 1400), mode =
;             timeout in ticks (0: 1 s) -> the round trip in ticks, -8
;  53 CONNECT handle = address, length = port -> socket id once established;
;             -1 refused (RST), -8 no answer (8 tries), -6 no free socket
;  54 LISTEN  handle = port -> socket id; -7 port in use
;  55 ACCEPT  handle = listening socket, mode bit0 = do not block -> the id
;             of the next established connection (it belongs to the caller)
;  56 UDP     handle = port (0: any) -> socket id; -7 port in use
;  57 SENDTO  data: u64 address, u64 port, payload; length = 16 + payload
;             (<= 1472) -> payload bytes sent
;  58 RECVFROM length = most bytes, mode bit0 = do not block -> bytes; data:
;             u64 address, u64 port, payload; waits while none is queued
;  36 DUPS / 37 CLEANUP (its sockets are closed) / 38 CANCEL (its waiting
;  requests return -2): the usual operations from proc
;
; A socket belongs to the process that made it (ACCEPT: the one that accepted
; it); other processes get -1. Every 2 s while sockets are open, net asks
; proc for the process list and closes the sockets of processes that ended.
;
; TCP: 4 sockets (TCP or UDP), each with a 2 KiB receive ring (the window it
; advertises) and a 2 KiB send buffer; segments of at most 1024 bytes (MSS
; option); in-order receive only (out-of-order segments are dropped and
; acknowledged); retransmission of the oldest unacknowledged segment after
; 250 ms, doubling up to 8 s, at most 8 times, then the connection is reset;
; TIME-WAIT 500 ms; FIN-WAIT-2 gives up after 10 s. ICMP: echo requests are
; answered; echo replies complete PINGs. Checksums are checked and made.
;
; Halting: the kernel writes the interface's CANCEL port once every core's
; dispatcher has stopped its processes (u_halt); the RX read then completes
; with zeros (an all-zero header), and net does not read again.
;
; Capability registers: c0 the arena (unused), c1 proc, c2 fs (unused), c3
; tty, c4 the network interface's ports (0x4200..), c5 our buffer, c6
; requests, c7 the clock (an attachment would replace it: sys_clock).
; D-LS: about 34 KiB of data with the library (doc/strataos-0.2.md 2.2).

TG_RX    = 1                            ; transfer tag of the RX read
TG_TX    = 3                            ; transfer tag of TX and STATUS
N_TX     = 0x00                         ; interface ports (offsets in the window)
N_RX     = 0x08                         ; ...
