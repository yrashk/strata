; =============================================================================
; storew.s: changing the store: trees, free space, the commit (included by fs.s)
; =============================================================================
;
; Copy-on-write: a page that the commit under way did not write is never
; changed; `touch` gives a copy of it at a new page and frees the old one.
; A commit is: every changed page to the disk (they are at free pages), a
; FLUSH, the meta block (the one not written last time), a FLUSH.
;
; Free space (the routines follow tools/stdb/store.c). Free extents taken
; into memory are in `av`; the keys of the free records they came from are
; in `ldk`, to be deleted from the free tree; what the commit frees is in
; `fr`, to go into the pending tree. All three are small: `relief`, called
; where no tree change is under way, writes them out when they fill, and
; `finalize` at the commit until nothing is left over.
;
; Snapshots. A snapshot is a commit whose catalog root is kept under a name
; (the file server does that: fsops.s). What it costs is the pages it keeps
; from being reused: a page born no later than the newest snapshot
; (st_deadlim) is not freed when the store stops using it, but recorded in
; the pending tree under that snapshot's commit with the top bit set: its
; dead list. Deleting a snapshot goes through its dead list: what was born
; after the snapshot before it is free, the rest moves to that one's list.

NAV     = 48                            ; free extents in memory
NFR     = 48                            ; extents freed, not yet in the pending tree
NLD     = 64                            ; free records taken, not yet deleted
NPL     = 32                            ; pending records taken, not yet deleted
NTT     = 8                             ; trees open
TT_SIZE = 96                            ; a tree's entry: 0 root, 8 height,
TT_SR   = 16                            ;   16, 24 as the catalog has them,
TT_FL   = 32                            ;   32 bit 0 used, bit 1 not yet in the catalog,
TT_KL   = 40                            ;   40 its catalog key's length,
TT_KEY  = 48                            ;   48 the key: namespace (4 bytes), name
ST_RES  = 64                            ; pages kept back for the allocator's own trees

        .data                           ; data Local Store
        .align 8                        ; ...
st_npages: .dword 0                     ; pages on the disk
st_first:  .dword 0                     ; the first page the store manages
st_cmt:    .dword 0                     ; the last commit on the disk
t_cat:     .space 16                    ; the catalog
t_fre:     .space 16                    ; free space
t_pend:    .space 16                    ; pending frees
st_manif:  .dword 0                     ; the boot manifest's page
st_nextns: .dword 0                     ; the next namespace id
st_nextid: .dword 0                     ; the next stream id
st_nfree:  .dword 0                     ; free pages (pending ones too)
st_spare:  .space 16                    ; the spare extent: start, pages
st_began:  .dword 0                     ; a commit is under way
in_ft:     .dword 0                     ; the free tree is being changed: no reading it
in_b:      .dword 0                     ; `av` is being written back
in_fin:    .dword 0                     ; in finalize
in_rel:    .dword 0                     ; in relief
st_txfreed: .dword 0                    ; pages freed by this commit (not reusable yet)
st_last:   .dword 0                     ; the page allocated last
st_deadlim: .dword 0                    ; the newest snapshot's commit (0: none): pages born up
                                        ;   to it are not freed but kept on its dead list
navail:    .dword 0                     ; ...
av:        .space NAV * 16              ; start, pages (sorted, except while written back)
nfreed:    .dword 0                     ; ...
fr:        .space NFR * 24              ; start, pages, birth
nld:       .dword 0                     ; ...
ldk:       .space NLD * 8               ; a free record's key: its extent's end
npld:      .dword 0                     ; ...
pldk:      .space NPL * 16              ; a pending record's key
lkey:      .space 16                    ; a free record's key and value at work
lval:      .space 24                    ; ...
pkey:      .space 16                    ; a pending record's
pval:      .space 16                    ; ...
ckey:      .space 48                    ; a catalog key
cval:      .space 16                    ; ...
tt:        .space NTT * TT_SIZE         ; the trees open
rb_pl:     .dword 0                     ; rebalance: the pages being joined
rb_pr:     .dword 0                     ; ...
rb_c:      .dword 0                     ; ...
s_magic:   .ascii "STDBMETA"            ; a meta block's mark

        .text                           ; instruction Local Store

; ---- pages of the commit under way ---------------------------------------------------

; touch(a0 = page) -> a0 = the page to change in its place: itself if this
; commit wrote it, else a copy at a new page (the old one is freed). It is in
; a buffer, marked changed.
touch:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        mv    s1, a0                    ; s1 = the page
        call  P                         ; ...
        ld    s3, 16(a0)                ; s3 = the commit that wrote it
        ld    t1, st_txn(zero)          ; ...
        bne   s3, t1, tc_cow            ; ...
        mv    a0, s1                    ; ours: it will be changed
        call  PW                        ; ...
        mv    a0, s1                    ; ...
        j     tc_ret                    ; ...
tc_cow:
        call  alloc1                    ; s2 = its new place
        mv    s2, a0                    ; ...
        mv    a0, s1                    ; the buffer holding it becomes the new page's
        call  PW                        ; ...
        la    t0, bufs                  ; ...
        sub   t1, a0, t0                ; ...
        srli  t1, t1, 12                ; ...
        slli  t1, t1, 3                 ; ...
        sd    s2, b_no(t1)              ; ...
        sd    s2, 8(a0)                 ; its number
        ld    t0, st_txn(zero)          ; written by this commit
        sd    t0, 16(a0)                ; ...
        mv    a0, s1                    ; the old page is free
        li    a1, 1                     ; ...
        mv    a2, s3                    ; ...
        call  pfree                     ; ...
        mv    a0, s2                    ; ...
tc_ret:
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; newpage(a0 = kind, a1 = level) -> a0 = a new, empty tree page (in a buffer)
newpage:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        mv    s2, a0                    ; ...
        mv    s3, a1                    ; ...
        call  alloc1                    ; ...
        mv    s1, a0                    ; ...
        call  PN                        ; ...
        sd    s1, 8(a0)                 ; its number
        ld    t0, st_txn(zero)          ; ...
        sd    t0, 16(a0)                ; ...
        sb    s2, 24(a0)                ; ...
        sb    s3, 25(a0)                ; ...
        ld    t0, st_ps(zero)           ; no cells: they start at the end
        sh    t0, 28(a0)                ; ...
        mv    a0, s1                    ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; ---- changing a tree ---------------------------------------------------------------

; descend_w(a0 = tree, a1 = key, a2 = its length) -> a0 = the key's place in
; its leaf, a1 = 1 if it is there: the way down in wpath, every page on it
; this commit's own
descend_w:
        addi  sp, sp, -56               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        sd    s5, 40(sp)                ; ...
        sd    s6, 48(sp)                ; ...
        mv    s1, a0                    ; s1 = the tree
        mv    s2, a1                    ; s2 = the key
        mv    s3, a2                    ; s3 = its length
        sd    s1, w_tree(zero)          ; ...
        li    s4, 0                     ; s4 = the level
        ld    s5, 0(s1)                 ; s5 = the page
dw_l:
        mv    a0, s5                    ; ...
        call  touch                     ; ...
        beq   a0, s5, dw_same           ; ...
        mv    s5, a0                    ; it moved: whoever points at it follows
        bnez  s4, dw_par                ; ...
        sd    s5, 0(s1)                 ; the root
        j     dw_same                   ; ...
dw_par:
        addi  t0, s4, -1                ; its parent's cell
        slli  t0, t0, 4                 ; ...
        ld    a0, wpath(t0)             ; ...
        call  PW                        ; ...
        addi  t0, s4, -1                ; ...
        slli  t0, t0, 4                 ; ...
        ld    t1, wpath+8(t0)           ; ...
        slli  t1, t1, 1                 ; ...
        add   t1, t1, a0                ; ...
        lhu   t1, 32(t1)                ; ...
        add   t1, t1, a0                ; ...
        sd    s5, 8(t1)                 ; ...
dw_same:
        slli  t0, s4, 4                 ; ...
        sd    s5, wpath(t0)             ; ...
        mv    a0, s5                    ; ...
        call  P                         ; ...
        mv    s6, a0                    ; ...
        mv    a1, s2                    ; ...
        mv    a2, s3                    ; ...
        call  nsearch                   ; ...
        slli  t0, s4, 4                 ; ...
        sd    a0, wpath+8(t0)           ; ...
        lbu   t0, 24(s6)                ; ...
        li    t1, K_LEAF                ; ...
        beq   t0, t1, dw_ret            ; ...
        mv    a1, a0                    ; down
        mv    a0, s6                    ; ...
        call  child                     ; ...
        mv    s5, a0                    ; ...
        addi  s4, s4, 1                 ; ...
        li    t0, 16                    ; (a tree is never that high)
        bgeu  s4, t0, st_die            ; ...
        j     dw_l                      ; ...
dw_ret:
        ld    s6, 48(sp)                ; ...
        ld    s5, 40(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 56                ; ...
        ret                             ; ...

; vcell(a0 = index) -> a0 = a cell, a1 = its bytes: the cells of the page
; being split (its copy in in_buf) with the new cell (cellbuf) at ia_idx
vcell:
        ld    t0, ia_idx(zero)          ; ...
        bne   a0, t0, vc_old            ; ...
        la    a0, cellbuf               ; the new one
        ld    a1, ia_len(zero)          ; ...
        ret                             ; ...
vc_old:
        bltu  a0, t0, vc_get            ; ...
        addi  a0, a0, -1                ; after it: one less in the page
vc_get:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        la    t1, in_buf                ; ...
        slli  a0, a0, 1                 ; ...
        add   a0, a0, t1                ; ...
        lhu   a0, 32(a0)                ; ...
        add   a1, t1, a0                ; ...
        sd    a1, 8(sp)                 ; ...
        mv    a0, t1                    ; ...
        call  csize                     ; ...
        mv    a1, a0                    ; ...
        ld    a0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; ins_at(): the cell in cellbuf (ia_len bytes) goes into the page at level
; ia_lvl of wpath, at index ia_idx. A page with no room is split: its upper
; cells go to a new page, whose cell goes into the level above the same way.
ins_at:
        addi  sp, sp, -72               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        sd    s5, 40(sp)                ; ...
        sd    s6, 48(sp)                ; ...
        sd    s7, 56(sp)                ; ...
        sd    s8, 64(sp)                ; ...
ia_top:
        ld    s1, ia_lvl(zero)          ; s1 = the level
        slli  t0, s1, 4                 ; ...
        ld    s2, wpath(t0)             ; s2 = the page
        mv    a0, s2                    ; ...
        call  PW                        ; ...
        mv    s3, a0                    ; ...
        lhu   t0, 26(s3)                ; room for the cell and its slot?
        lhu   t1, 28(s3)                ; ...
        slli  t2, t0, 1                 ; ...
        addi  t2, t2, 32                ; ...
        sub   t1, t1, t2                ; ...
        ld    t3, ia_len(zero)          ; ...
        addi  t4, t3, 2                 ; ...
        blt   t1, t4, ia_split          ; ...
        mv    a0, s3                    ; yes
        ld    a1, ia_idx(zero)          ; ...
        la    a2, cellbuf               ; ...
        mv    a3, t3                    ; ...
        call  node_ins                  ; ...
        j     ia_ret                    ; ...
ia_split:
        la    a0, in_buf                ; a copy of the page
        mv    a1, s3                    ; ...
        li    a2, 4096                  ; ...
        call  wcopy                     ; ...
        la    t0, in_buf                ; ...
        lhu   s4, 26(t0)                ; s4 = its cells (one more with the new one)
        ld    t1, st_ps(zero)           ; s6 = half the bytes of them all
        lhu   t2, 28(t0)                ; ...
        sub   t1, t1, t2                ; ...
        slli  t2, s4, 1                 ; ...
        add   t1, t1, t2                ; ...
        ld    t2, ia_len(zero)          ; ...
        add   t1, t1, t2                ; ...
        addi  t1, t1, 2                 ; ...
        srli  s6, t1, 1                 ; ...
        ld    t0, ia_idx(zero)          ; s5 = the cells that stay
        mv    s5, s4                    ; appending: the full page stays as it is
        beq   t0, s4, ia_k              ; ...
        li    s5, 0                     ; else about half the bytes
        li    s7, 0                     ; ...
ia_kl:
        bgeu  s5, s4, ia_k              ; ...
        mv    a0, s5                    ; ...
        call  vcell                     ; ...
        add   s7, s7, a1                ; ...
        addi  s7, s7, 2                 ; ...
        addi  s5, s5, 1                 ; ...
        bltu  s7, s6, ia_kl             ; ...
ia_k:
        la    t0, in_buf                ; s6 = the new page, of the same kind and level
        lbu   a0, 24(t0)                ; ...
        lbu   a1, 25(t0)                ; ...
        call  newpage                   ; ...
        mv    s6, a0                    ; ...
        la    a0, bcbuf                 ; its cell for the level above
        li    a1, 528                   ; ...
        call  wzero                     ; ...
        mv    a0, s5                    ; s7 = the new page's first cell
        call  vcell                     ; ...
        mv    s7, a0                    ; ...
        lhu   s8, 0(s7)                 ; s8 = the separator's length: its whole key,
        la    t0, in_buf                ; ...
        lbu   t1, 24(t0)                ; ...
        li    t2, K_LEAF                ; ...
        bne   t1, t2, ia_sep            ; ...
        addi  a0, s5, -1                ; or, between leaves, the shortest that is
        call  vcell                     ; above the old page's last key
        lhu   t1, 0(a0)                 ; ...
        addi  t2, a0, 8                 ; ...
        addi  t3, s7, 8                 ; ...
        li    t4, 0                     ; ...
ia_cp:
        bgeu  t4, t1, ia_cpe            ; ...
        bgeu  t4, s8, ia_cpe            ; ...
        add   t5, t2, t4                ; ...
        lbu   t5, 0(t5)                 ; ...
        add   t6, t3, t4                ; ...
        lbu   t6, 0(t6)                 ; ...
        bne   t5, t6, ia_cpe            ; ...
        addi  t4, t4, 1                 ; ...
        j     ia_cp                     ; ...
ia_cpe:
        addi  s8, t4, 1                 ; ...
ia_sep:
        la    t0, bcbuf                 ; ...
        sh    s8, 0(t0)                 ; ...
        sd    s6, 8(t0)                 ; ...
        addi  a1, s7, 8                 ; the key's bytes
        la    t1, in_buf                ; ...
        lbu   t1, 24(t1)                ; ...
        li    t2, K_LEAF                ; ...
        beq   t1, t2, ia_kc             ; ...
        addi  a1, s7, 16                ; ...
ia_kc:
        addi  a0, t0, 16                ; ...
        mv    a2, s8                    ; ...
        call  srv_bcopy                 ; ...
        mv    a0, s2                    ; the old page: the cells that stay
        call  PW                        ; ...
        mv    s3, a0                    ; ...
        sh    zero, 26(s3)              ; ...
        ld    t0, st_ps(zero)           ; ...
        sh    t0, 28(s3)                ; ...
        li    s7, 0                     ; ...
ia_ll:
        bgeu  s7, s5, ia_r              ; ...
        mv    a0, s7                    ; ...
        call  vcell                     ; ...
        mv    a2, a0                    ; ...
        mv    a3, a1                    ; ...
        mv    a0, s3                    ; ...
        mv    a1, s7                    ; ...
        call  node_ins                  ; ...
        addi  s7, s7, 1                 ; ...
        j     ia_ll                     ; ...
ia_r:
        mv    a0, s6                    ; the new page: the rest
        call  PW                        ; ...
        mv    s3, a0                    ; ...
ia_rl:
        bgtu  s7, s4, ia_up             ; ...
        mv    a0, s7                    ; ...
        call  vcell                     ; ...
        mv    a2, a0                    ; ...
        mv    a3, a1                    ; ...
        bne   s7, s5, ia_rn             ; a branch's first cell: its key went up
        lbu   t0, 24(s3)                ; ...
        li    t1, K_BRANCH              ; ...
        bne   t0, t1, ia_rn             ; ...
        la    t0, first16               ; ...
        sd    zero, 0(t0)               ; ...
        ld    t1, 8(a2)                 ; ...
        sd    t1, 8(t0)                 ; ...
        mv    a2, t0                    ; ...
        li    a3, 16                    ; ...
ia_rn:
        mv    a0, s3                    ; ...
        sub   a1, s7, s5                ; ...
        call  node_ins                  ; ...
        addi  s7, s7, 1                 ; ...
        j     ia_rl                     ; ...
ia_up:
        addi  t0, s8, 7                 ; s8 = the bytes of the cell going up
        srli  t0, t0, 3         ; (down to a whole word)
        slli  t0, t0, 3         ; ...
        addi  s8, t0, 16                ; ...
        bnez  s1, ia_par                ; ...
        la    t0, in_buf                ; the root was split: a new root over both
        lbu   a1, 25(t0)                ; ...
        addi  a1, a1, 1                 ; ...
        li    a0, K_BRANCH              ; ...
        call  newpage                   ; ...
        mv    s7, a0                    ; ...
        call  PW                        ; ...
        mv    s3, a0                    ; ...
        la    a2, first16               ; ...
        sd    zero, 0(a2)               ; ...
        sd    s2, 8(a2)                 ; ...
        li    a1, 0                     ; ...
        li    a3, 16                    ; ...
        call  node_ins                  ; ...
        mv    a0, s3                    ; ...
        li    a1, 1                     ; ...
        la    a2, bcbuf                 ; ...
        mv    a3, s8                    ; ...
        call  node_ins                  ; ...
        ld    t0, w_tree(zero)          ; ...
        sd    s7, 0(t0)                 ; ...
        ld    t1, 8(t0)                 ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, 8(t0)                 ; ...
        j     ia_ret                    ; ...
ia_par:
        la    a0, cellbuf               ; into the page above, after the old page's cell
        la    a1, bcbuf                 ; ...
        mv    a2, s8                    ; ...
        call  wcopy                     ; ...
        sd    s8, ia_len(zero)          ; ...
        addi  s1, s1, -1                ; ...
        sd    s1, ia_lvl(zero)          ; ...
        slli  t0, s1, 4                 ; ...
        ld    t1, wpath+8(t0)           ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, ia_idx(zero)          ; ...
        j     ia_top                    ; ...
ia_ret:
        ld    s8, 64(sp)                ; ...
        ld    s7, 56(sp)                ; ...
        ld    s6, 48(sp)                ; ...
        ld    s5, 40(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 72                ; ...
        ret                             ; ...

; st_put(a0 = tree, a1 = key, a2 = its length, a3 = value, a4 = its length, a5
; = its flag (0, 1)) -> a0 = 1 added, 0 replaced, -1 too long. The key and the
; value are not in a page buffer.
st_put:
        addi  sp, sp, -64               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        sd    s5, 40(sp)                ; ...
        sd    s6, 48(sp)                ; ...
        sd    s7, 56(sp)                ; ...
        mv    s1, a0                    ; s1 = the tree
        mv    s2, a1                    ; s2 = the key
        mv    s3, a2                    ; s3 = its length
        mv    s4, a3                    ; s4 = the value
        mv    s5, a4                    ; s5 = its length
        mv    s6, a5                    ; s6 = its flag
        li    a0, -1                    ; a key: 1 byte to an eighth of a page less 32
        beqz  s3, sp_ret                ; ...
        ld    t0, st_ps(zero)           ; ...
        srli  t0, t0, 3                 ; ...
        addi  t0, t0, -32               ; ...
        bgtu  s3, t0, sp_ret            ; ...
        ld    t0, st_ps(zero)           ; a cell: a quarter of a page at most
        addi  t0, t0, -32               ; ...
        srli  t0, t0, 2                 ; ...
        addi  t0, t0, -2                ; ...
        srli  t0, t0, 3         ; (down to a whole word)
        slli  t0, t0, 3         ; ...
        addi  t0, t0, -8                ; ...
        addi  t1, s3, 7                 ; ...
        srli  t1, t1, 3         ; (down to a whole word)
        slli  t1, t1, 3         ; ...
        sub   t0, t0, t1                ; ...
        bgt   s5, t0, sp_ret            ; ...
        call  relief                    ; ...
        call  begin                     ; ...
        ld    t0, 0(s1)                 ; an empty tree: a leaf
        bnez  t0, sp_d                  ; ...
        li    a0, K_LEAF                ; ...
        li    a1, 0                     ; ...
        call  newpage                   ; ...
        sd    a0, 0(s1)                 ; ...
        li    t0, 1                     ; ...
        sd    t0, 8(s1)                 ; ...
sp_d:
        mv    a0, s1                    ; ...
        mv    a1, s2                    ; ...
        mv    a2, s3                    ; ...
        call  descend_w                 ; ...
        mv    s7, a1                    ; s7 = it is there already
        sd    a0, ia_idx(zero)          ; ...
        addi  t0, s3, 7                 ; the cell: lengths, key, value, each padded
        srli  t0, t0, 3         ; (down to a whole word)
        slli  t0, t0, 3         ; ...
        addi  t1, s5, 7                 ; ...
        srli  t1, t1, 3         ; (down to a whole word)
        slli  t1, t1, 3         ; ...
        add   t2, t0, t1                ; ...
        addi  t2, t2, 8                 ; ...
        sd    t2, ia_len(zero)          ; ...
        la    a0, cellbuf               ; ...
        mv    a1, t2                    ; ...
        call  wzero                     ; ...
        la    t0, cellbuf               ; ...
        sh    s3, 0(t0)                 ; ...
        slli  t1, s6, 15                ; ...
        or    t1, t1, s5                ; ...
        sh    t1, 2(t0)                 ; ...
        addi  a0, t0, 8                 ; ...
        mv    a1, s2                    ; ...
        mv    a2, s3                    ; ...
        call  srv_bcopy                 ; ...
        la    a0, cellbuf + 8           ; ...
        addi  t0, s3, 7                 ; ...
        srli  t0, t0, 3         ; (down to a whole word)
        slli  t0, t0, 3         ; ...
        add   a0, a0, t0                ; ...
        mv    a1, s4                    ; ...
        mv    a2, s5                    ; ...
        call  srv_bcopy                 ; ...
        ld    t0, 8(s1)                 ; into the leaf
        addi  t0, t0, -1                ; ...
        sd    t0, ia_lvl(zero)          ; ...
        beqz  s7, sp_i                  ; (the old cell goes first)
        slli  t0, t0, 4                 ; ...
        ld    a0, wpath(t0)             ; ...
        call  PW                        ; ...
        ld    a1, ia_idx(zero)          ; ...
        call  node_rm                   ; ...
sp_i:
        call  ins_at                    ; ...
        xori  a0, s7, 1                 ; ...
sp_ret:
        ld    s7, 56(sp)                ; ...
        ld    s6, 48(sp)                ; ...
        ld    s5, 40(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 64                ; ...
        ret                             ; ...

; used(a0 = page) -> a0 = the bytes its cells and slots take
used:
        ld    t0, st_ps(zero)           ; ...
        lhu   t1, 28(a0)                ; ...
        sub   t0, t0, t1                ; ...
        lhu   t1, 26(a0)                ; ...
        slli  t1, t1, 1                 ; ...
        add   a0, t0, t1                ; ...
        ret                             ; ...

; rebalance(a0 = level): after a cell left the page at that level of wpath: an
; empty page goes; one under a quarter full joins a neighbour when both fit
; in one page; and so on up
rebalance:
        addi  sp, sp, -72               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        sd    s5, 40(sp)                ; ...
        sd    s6, 48(sp)                ; ...
        sd    s7, 56(sp)                ; ...
        sd    s8, 64(sp)                ; ...
        mv    s1, a0                    ; s1 = the level
rb_top:
        slli  t0, s1, 4                 ; s2 = the page
        ld    s2, wpath(t0)             ; ...
        mv    a0, s2                    ; ...
        call  P                         ; ...
        mv    s7, a0                    ; ...
        bnez  s1, rb_in                 ; ...
rb_root:
        lhu   t0, 26(s7)                ; the root: empty, the tree is empty
        bnez  t0, rb_r1                 ; ...
        mv    a0, s2                    ; ...
        li    a1, 1                     ; ...
        ld    a2, 16(s7)                ; ...
        call  pfree                     ; ...
        ld    t0, w_tree(zero)          ; ...
        sd    zero, 0(t0)               ; ...
        sd    zero, 8(t0)               ; ...
        j     rb_ret                    ; ...
rb_r1:
        lbu   t1, 24(s7)                ; with one child: the child is the root
        li    t2, K_BRANCH              ; ...
        bne   t1, t2, rb_ret            ; ...
        li    t2, 1                     ; ...
        bne   t0, t2, rb_ret            ; ...
        mv    a0, s7                    ; ...
        li    a1, 0                     ; ...
        call  child                     ; ...
        mv    s3, a0                    ; ...
        ld    t0, w_tree(zero)          ; ...
        sd    s3, 0(t0)                 ; ...
        ld    t1, 8(t0)                 ; ...
        addi  t1, t1, -1                ; ...
        sd    t1, 8(t0)                 ; ...
        mv    a0, s2                    ; ...
        li    a1, 1                     ; ...
        ld    a2, 16(s7)                ; ...
        call  pfree                     ; ...
        mv    s2, s3                    ; ...
        mv    a0, s2                    ; ...
        call  P                         ; ...
        mv    s7, a0                    ; ...
        j     rb_root                   ; ...
rb_in:
        addi  t0, s1, -1                ; s3 = its parent, s4 = its place there
        slli  t0, t0, 4                 ; ...
        ld    s3, wpath(t0)             ; ...
        ld    s4, wpath+8(t0)           ; ...
        lhu   t0, 26(s7)                ; ...
        bnez  t0, rb_fill               ; ...
        mv    a0, s2                    ; empty: it goes, and its cell above
        li    a1, 1                     ; ...
        ld    a2, 16(s7)                ; ...
        call  pfree                     ; ...
        mv    a0, s3                    ; ...
        call  PW                        ; ...
        mv    a1, s4                    ; ...
        call  node_rm                   ; ...
        addi  s1, s1, -1                ; ...
        j     rb_top                    ; ...
rb_fill:
        mv    a0, s7                    ; a quarter full or more: enough
        call  used                      ; ...
        ld    t1, st_ps(zero)           ; ...
        addi  t1, t1, -32               ; ...
        srli  t1, t1, 2                 ; ...
        bgeu  a0, t1, rb_ret            ; ...
        mv    a0, s3                    ; a neighbour: the next one, or the one before
        call  P                         ; ...
        mv    s7, a0                    ; s7 = the parent's buffer
        lhu   t0, 26(s7)                ; ...
        addi  t1, s4, 1                 ; ...
        mv    s5, s4                    ; s5 = the left one's place in the parent
        bltu  t1, t0, rb_sib            ; ...
        beqz  s4, rb_ret                ; an only child: nothing to join
        addi  s5, s4, -1                ; ...
rb_sib:
        mv    a0, s7                    ; s6 = the left page, s8 = the right one
        mv    a1, s5                    ; ...
        call  child                     ; ...
        mv    s6, a0                    ; ...
        mv    a0, s7                    ; ...
        addi  a1, s5, 1                 ; ...
        call  child                     ; ...
        mv    s8, a0                    ; ...
        addi  t0, s5, 1                 ; the right one's cell in the parent -> bcbuf
        slli  t0, t0, 1                 ; ...
        add   t0, t0, s7                ; ...
        lhu   t0, 32(t0)                ; ...
        add   a1, s7, t0                ; ...
        lhu   t1, 0(a1)                 ; ...
        addi  t1, t1, 7                 ; ...
        srli  t1, t1, 3         ; (down to a whole word)
        slli  t1, t1, 3         ; ...
        addi  a2, t1, 16                ; ...
        la    a0, bcbuf                 ; ...
        call  wcopy                     ; ...
        mv    a0, s6                    ; s7 = the bytes of both
        call  P                         ; ...
        call  used                      ; ...
        mv    s7, a0                    ; ...
        mv    a0, s8                    ; ...
        call  P                         ; ...
        sd    a0, rb_pr(zero)           ; ...
        call  used                      ; ...
        add   s7, s7, a0                ; ...
        ld    a0, rb_pr(zero)           ; a branch's first cell gets the separator as its key
        lbu   t0, 24(a0)                ; ...
        li    t1, K_BRANCH              ; ...
        bne   t0, t1, rb_fit            ; ...
        lhu   t0, bcbuf(zero)           ; ...
        addi  t0, t0, 7                 ; ...
        srli  t0, t0, 3         ; (down to a whole word)
        slli  t0, t0, 3         ; ...
        add   s7, s7, t0                ; ...
        lhu   t1, 32(a0)                ; ...
        add   t1, t1, a0                ; ...
        lhu   t1, 0(t1)                 ; ...
        addi  t1, t1, 7                 ; ...
        srli  t1, t1, 3         ; (down to a whole word)
        slli  t1, t1, 3         ; ...
        sub   s7, s7, t1                ; ...
rb_fit:
        ld    t1, st_ps(zero)           ; do they fit in one page?
        addi  t1, t1, -32               ; ...
        bgtu  s7, t1, rb_ret            ; ...
        mv    a0, s6                    ; the left one takes the right one's cells
        call  touch                     ; ...
        beq   a0, s6, rb_m              ; ...
        mv    s6, a0                    ; (it moved)
        mv    a0, s3                    ; ...
        call  PW                        ; ...
        slli  t0, s5, 1                 ; ...
        add   t0, t0, a0                ; ...
        lhu   t0, 32(t0)                ; ...
        add   t0, t0, a0                ; ...
        sd    s6, 8(t0)                 ; ...
rb_m:
        li    s7, 0                     ; s7 = the cell of the right page
rb_ml:
        mv    a0, s8                    ; ...
        call  P                         ; ...
        sd    a0, rb_pr(zero)           ; ...
        mv    a0, s6                    ; ...
        call  PW                        ; ...
        sd    a0, rb_pl(zero)           ; ...
        ld    t0, rb_pr(zero)           ; ...
        lhu   t1, 26(t0)                ; ...
        bgeu  s7, t1, rb_md             ; ...
        slli  t1, s7, 1                 ; ...
        add   t1, t1, t0                ; ...
        lhu   t1, 32(t1)                ; ...
        add   a1, t0, t1                ; its cell
        sd    a1, rb_c(zero)            ; ...
        bnez  s7, rb_mc                 ; ...
        lbu   t1, 24(t0)                ; ...
        li    t2, K_BRANCH              ; ...
        bne   t1, t2, rb_mc             ; ...
        ld    t1, 8(a1)                 ; a branch's first: the separator with its child
        sd    t1, bcbuf+8(zero)         ; ...
        lhu   a3, bcbuf(zero)           ; ...
        addi  a3, a3, 7                 ; ...
        srli  a3, a3, 3         ; (down to a whole word)
        slli  a3, a3, 3         ; ...
        addi  a3, a3, 16                ; ...
        la    a2, bcbuf                 ; ...
        j     rb_mi                     ; ...
rb_mc:
        mv    a0, t0                    ; ...
        call  csize                     ; ...
        mv    a3, a0                    ; ...
        ld    a2, rb_c(zero)            ; ...
rb_mi:
        ld    a0, rb_pl(zero)           ; ...
        lhu   a1, 26(a0)                ; ...
        call  node_ins                  ; ...
        addi  s7, s7, 1                 ; ...
        j     rb_ml                     ; ...
rb_md:
        mv    a0, s8                    ; the right page is free
        li    a1, 1                     ; ...
        ld    a2, 16(t0)                ; ...
        call  pfree                     ; ...
        mv    a0, s3                    ; and its cell in the parent goes
        call  PW                        ; ...
        addi  a1, s5, 1                 ; ...
        call  node_rm                   ; ...
        addi  s1, s1, -1                ; ...
        j     rb_top                    ; ...
rb_ret:
        ld    s8, 64(sp)                ; ...
        ld    s7, 56(sp)                ; ...
        ld    s6, 48(sp)                ; ...
        ld    s5, 40(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 72                ; ...
        ret                             ; ...

; st_del(a0 = tree, a1 = key, a2 = its length) -> a0 = 1 deleted, 0 not there
st_del:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        mv    s3, a2                    ; ...
        li    a3, 0                     ; there?
        call  st_get                    ; ...
        bltz  a0, sdl_no                ; ...
        call  relief                    ; ...
        call  begin                     ; ...
        mv    a0, s1                    ; ...
        mv    a1, s2                    ; ...
        mv    a2, s3                    ; ...
        call  descend_w                 ; ...
        mv    s2, a0                    ; its place in the leaf
        ld    s3, 8(s1)                 ; ...
        addi  s3, s3, -1                ; ...
        slli  t0, s3, 4                 ; ...
        ld    a0, wpath(t0)             ; ...
        call  PW                        ; ...
        mv    a1, s2                    ; ...
        call  node_rm                   ; ...
        mv    a0, s3                    ; ...
        call  rebalance                 ; ...
        li    a0, 1                     ; ...
        j     sdl_ret                   ; ...
sdl_no:
        li    a0, 0                     ; ...
sdl_ret:
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

