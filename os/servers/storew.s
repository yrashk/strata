; av_rm(a0 = offset of an entry in av): it goes
av_rm:
        ld    t0, navail(zero)          ; ...
        slli  t1, t0, 4                 ; ...
avr_l:
        addi  t2, a0, 16                ; ...
        bgeu  t2, t1, avr_e             ; ...
        ld    t3, av(t2)                ; ...
        sd    t3, av(a0)                ; ...
        ld    t3, av+8(t2)              ; ...
        sd    t3, av+8(a0)              ; ...
        mv    a0, t2                    ; ...
        j     avr_l                     ; ...
avr_e:
        addi  t0, t0, -1                ; ...
        sd    t0, navail(zero)          ; ...
        ret                             ; ...

; avail_add(a0 = start, a1 = pages): a free extent into av, joined with its
; neighbours there (not while av is written back). When av is full it waits
; in the pending tree like a page freed by this commit.
avail_add:
        beqz  a1, aa_ret                ; ...
        ld    t0, navail(zero)          ; ...
        ld    t1, in_b(zero)            ; ...
        bnez  t1, aa_app                ; ...
        li    t2, 0                     ; t2 = the first entry not before it
        slli  t3, t0, 4                 ; ...
aa_f:
        bgeu  t2, t3, aa_at             ; ...
        ld    t4, av(t2)                ; ...
        bgeu  t4, a0, aa_at             ; ...
        addi  t2, t2, 16                ; ...
        j     aa_f                      ; ...
aa_at:
        beqz  t2, aa_nx                 ; the one before ends where it starts?
        ld    t4, av-16(t2)             ; ...
        ld    t5, av-8(t2)              ; ...
        add   t4, t4, t5                ; ...
        bne   t4, a0, aa_nx             ; ...
        add   t5, t5, a1                ; ...
        sd    t5, av-8(t2)              ; ...
        bgeu  t2, t3, aa_ret            ; and the next one starts where it ends?
        ld    t4, av(t2)                ; ...
        add   t6, a0, a1                ; ...
        bne   t4, t6, aa_ret            ; ...
        ld    t4, av+8(t2)              ; ...
        add   t5, t5, t4                ; ...
        sd    t5, av-8(t2)              ; ...
        mv    a0, t2                    ; ...
        j     av_rm                     ; ...
aa_nx:
        bgeu  t2, t3, aa_ins            ; the next one starts where it ends?
        ld    t4, av(t2)                ; ...
        add   t6, a0, a1                ; ...
        bne   t4, t6, aa_ins            ; ...
        sd    a0, av(t2)                ; ...
        ld    t5, av+8(t2)              ; ...
        add   t5, t5, a1                ; ...
        sd    t5, av+8(t2)              ; ...
        ret                             ; ...
aa_ins:
        li    t4, NAV                   ; an entry of its own
        bgeu  t0, t4, aa_full           ; ...
        mv    t4, t3                    ; ...
aa_su:
        bleu  t4, t2, aa_put            ; ...
        ld    t5, av-16(t4)             ; ...
        sd    t5, av(t4)                ; ...
        ld    t5, av-8(t4)              ; ...
        sd    t5, av+8(t4)              ; ...
        addi  t4, t4, -16               ; ...
        j     aa_su                     ; ...
aa_app:
        li    t4, NAV                   ; ...
        bgeu  t0, t4, aa_full           ; ...
        slli  t2, t0, 4                 ; ...
aa_put:
        sd    a0, av(t2)                ; ...
        sd    a1, av+8(t2)              ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, navail(zero)          ; ...
aa_ret:
        ret                             ; ...
aa_full:
        ld    a2, st_txn(zero)          ; ...
; freed_put(a0 = start, a1 = pages, a2 = birth): into fr
freed_put:
        ld    t0, nfreed(zero)          ; ...
        li    t1, NFR                   ; ...
        bgeu  t0, t1, st_die            ; (relief keeps this from happening)
        li    t1, 24                    ; ...
        mul   t1, t0, t1                ; ...
        sd    a0, fr(t1)                ; ...
        sd    a1, fr+8(t1)              ; ...
        sd    a2, fr+16(t1)             ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, nfreed(zero)          ; ...
        ld    t0, st_txfreed(zero)      ; ...
        add   t0, t0, a1                ; ...
        sd    t0, st_txfreed(zero)      ; ...
        ret                             ; ...

; avail_total() -> a0 = the pages in av
avail_total:
        li    a0, 0                     ; ...
        ld    t0, navail(zero)          ; ...
        slli  t0, t0, 4                 ; ...
        li    t1, 0                     ; ...
avt_l:
        bgeu  t1, t0, avt_ret           ; ...
        ld    t2, av+8(t1)              ; ...
        add   a0, a0, t2                ; ...
        addi  t1, t1, 16                ; ...
        j     avt_l                     ; ...
avt_ret:
        ret                             ; ...

; avail_end(a0 = end) -> a0 = the offset in av of the extent that ends there
; (a1 = its pages), or -1 (a1 = 0)
avail_end:
        ld    t0, navail(zero)          ; ...
        slli  t0, t0, 4                 ; ...
        li    t1, 0                     ; ...
ave_l:
        bgeu  t1, t0, ave_no            ; ...
        ld    t2, av(t1)                ; ...
        ld    a1, av+8(t1)              ; ...
        add   t2, t2, a1                ; ...
        beq   t2, a0, ave_yes           ; ...
        addi  t1, t1, 16                ; ...
        j     ave_l                     ; ...
ave_yes:
        mv    a0, t1                    ; ...
        ret                             ; ...
ave_no:
        li    a0, -1                    ; ...
        li    a1, 0                     ; ...
        ret                             ; ...

; av_first(a0 = pages) -> a0 = the offset in av of the first extent of at
; least that many, or -1
av_first:
        ld    t0, navail(zero)          ; ...
        slli  t0, t0, 4                 ; ...
        li    t1, 0                     ; ...
avf_l:
        bgeu  t1, t0, avf_no            ; ...
        ld    t2, av+8(t1)              ; ...
        bgeu  t2, a0, avf_yes           ; ...
        addi  t1, t1, 16                ; ...
        j     avf_l                     ; ...
avf_yes:
        mv    a0, t1                    ; ...
        ret                             ; ...
avf_no:
        li    a0, -1                    ; ...
        ret                             ; ...

; ld_has(a0 = end) -> a0 = 1 if the free record with that key was taken
ld_has:
        ld    t0, nld(zero)             ; ...
        slli  t0, t0, 3                 ; ...
        li    t1, 0                     ; ...
ldh_l:
        bgeu  t1, t0, ldh_no            ; ...
        ld    t2, ldk(t1)               ; ...
        beq   t2, a0, ldh_yes           ; ...
        addi  t1, t1, 8                 ; ...
        j     ldh_l                     ; ...
ldh_yes:
        li    a0, 1                     ; ...
        ret                             ; ...
ldh_no:
        li    a0, 0                     ; ...
        ret                             ; ...

; ld_take(a0 = end, a1 = pages): a free record is taken: its key to ldk, its
; extent into av (the caller saw that ldk has room)
ld_take:
        ld    t0, nld(zero)             ; ...
        slli  t1, t0, 3                 ; ...
        sd    a0, ldk(t1)               ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, nld(zero)             ; ...
        sub   a0, a0, a1                ; ...
        j     avail_add                 ; ...

; load_fit(a0 = pages) -> a0 = 1 if a free record not yet taken was: the first
; of at least that many pages among the first 64 looked at, else the largest
; of those. Records of no pages are taken on the way (and so deleted).
load_fit:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        sd    s5, 40(sp)                ; ...
        mv    s1, a0                    ; s1 = the pages wanted
        li    s2, 0                     ; s2 = records looked at
        li    s3, 0                     ; s3, s4 = the largest so far: end, pages
        li    s4, 0                     ; ...
        sd    zero, lkey(zero)          ; ...
lf_l:
        ld    t0, nld(zero)             ; room in ldk?
        li    t1, NLD                   ; ...
        bgeu  t0, t1, lf_no             ; ...
        li    t0, 64                    ; ...
        bgeu  s2, t0, lf_end            ; ...
        la    a0, t_fre                 ; ...
        la    a1, lkey                  ; ...
        li    a2, 8                     ; ...
        li    a3, ST_GT                 ; ...
        la    a4, lkey                  ; ...
        la    a5, lval                  ; ...
        call  st_seek                   ; ...
        beqz  a0, lf_end                ; ...
        ld    a0, lkey(zero)            ; ...
        call  bswap                     ; ...
        mv    s5, a0                    ; s5 = its end
        call  ld_has                    ; ...
        bnez  a0, lf_l                  ; ...
        ld    t0, lval(zero)            ; ...
        bnez  t0, lf_c                  ; ...
        mv    a0, s5                    ; no pages: taken, to be deleted
        li    a1, 0                     ; ...
        call  ld_take                   ; ...
        j     lf_l                      ; ...
lf_c:
        addi  s2, s2, 1                 ; ...
        bltu  t0, s1, lf_b              ; ...
        mv    a0, s5                    ; it fits
        mv    a1, t0                    ; ...
        call  ld_take                   ; ...
        j     lf_yes                    ; ...
lf_b:
        bleu  t0, s4, lf_l              ; ...
        mv    s3, s5                    ; ...
        mv    s4, t0                    ; ...
        j     lf_l                      ; ...
lf_end:
        beqz  s4, lf_no                 ; ...
        mv    a0, s3                    ; ...
        mv    a1, s4                    ; ...
        call  ld_take                   ; ...
lf_yes:
        li    a0, 1                     ; ...
        j     lf_ret                    ; ...
lf_no:
        li    a0, 0                     ; ...
lf_ret:
        ld    s5, 40(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; ...

; load_at(a0 = start): the free record whose extent starts there, if there is
; one -> memory
load_at:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        mv    s1, a0                    ; ...
        ld    t0, nld(zero)             ; ...
        li    t1, NLD                   ; ...
        bgeu  t0, t1, la_ret            ; ...
        call  bswap                     ; ...
        sd    a0, lkey(zero)            ; ...
        la    a0, t_fre                 ; ...
        la    a1, lkey                  ; ...
        li    a2, 8                     ; ...
        li    a3, ST_GT                 ; ...
        la    a4, lkey                  ; ...
        la    a5, lval                  ; ...
        call  st_seek                   ; ...
        beqz  a0, la_ret                ; ...
        ld    a0, lkey(zero)            ; ...
        call  bswap                     ; ...
        mv    s2, a0                    ; its end
        ld    t0, lval(zero)            ; ...
        beqz  t0, la_ret                ; ...
        sub   t1, s2, t0                ; ...
        bne   t1, s1, la_ret            ; ...
        call  ld_has                    ; ...
        bnez  a0, la_ret                ; ...
        mv    a0, s2                    ; ...
        ld    a1, lval(zero)            ; ...
        call  ld_take                   ; ...
la_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; load_end(a0 = end) -> a0 = 1 if the free record whose extent ends there was taken
load_end:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        mv    s1, a0                    ; ...
        ld    t0, nld(zero)             ; ...
        li    t1, NLD                   ; ...
        bgeu  t0, t1, le_no             ; ...
        call  ld_has                    ; ...
        bnez  a0, le_no                 ; ...
        mv    a0, s1                    ; ...
        call  bswap                     ; ...
        sd    a0, lkey(zero)            ; ...
        la    a0, t_fre                 ; ...
        la    a1, lkey                  ; ...
        li    a2, 8                     ; ...
        la    a3, lval                  ; ...
        call  st_get                    ; ...
        bltz  a0, le_no                 ; ...
        mv    a0, s1                    ; ...
        ld    a1, lval(zero)            ; ...
        call  ld_take                   ; ...
        li    a0, 1                     ; ...
        j     le_ret                    ; ...
le_no:
        li    a0, 0                     ; ...
le_ret:
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; begin(): the start of a commit: the spare extent, and what the commits on
; the disk freed, can be used
begin:
        ld    t0, st_began(zero)        ; ...
        bnez  t0, aa_ret                ; ...
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        li    t0, 1                     ; ...
        sd    t0, st_began(zero)        ; ...
        ld    a0, st_spare(zero)        ; ...
        ld    a1, st_spare+8(zero)      ; ...
        sd    zero, st_spare+8(zero)    ; ...
        call  avail_add                 ; ...
        sd    zero, pkey(zero)          ; the pending records of earlier commits
        sd    zero, pkey+8(zero)        ; ...
bgn_l:
        ld    t0, npld(zero)            ; (what does not fit waits for the next commit)
        li    t1, NPL                   ; ...
        bgeu  t0, t1, bgn_ret           ; ...
        la    a0, t_pend                ; ...
        la    a1, pkey                  ; ...
        li    a2, 16                    ; ...
        li    a3, ST_GT                 ; ...
        la    a4, pkey                  ; ...
        la    a5, pval                  ; ...
        call  st_seek                   ; ...
        beqz  a0, bgn_ret               ; ...
        ld    a0, pkey(zero)            ; its commit
        call  bswap                     ; ...
        ld    t0, st_txn(zero)          ; ...
        bgeu  a0, t0, bgn_ret           ; ...
        ld    t0, npld(zero)            ; ...
        slli  t1, t0, 4                 ; ...
        ld    t2, pkey(zero)            ; ...
        sd    t2, pldk(t1)              ; ...
        ld    t2, pkey+8(zero)          ; ...
        sd    t2, pldk+8(t1)            ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, npld(zero)            ; ...
        ld    a0, pkey+8(zero)          ; its extent
        call  bswap                     ; ...
        ld    a1, pval(zero)            ; ...
        call  avail_add                 ; ...
        j     bgn_l                     ; ...
bgn_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; take(a0 = offset of an entry in av, a1 = pages) -> a0 = the first page, a1 =
; how many (as many of the wanted as the extent has), from its front
take:
        ld    t0, av(a0)                ; ...
        ld    t1, av+8(a0)              ; ...
        mv    t2, a1                    ; ...
        bleu  t2, t1, tk_1              ; ...
        mv    t2, t1                    ; ...
tk_1:
        add   t3, t0, t2                ; ...
        sd    t3, av(a0)                ; ...
        sub   t1, t1, t2                ; ...
        sd    t1, av+8(a0)              ; ...
        ld    t3, st_nfree(zero)        ; ...
        sub   t3, t3, t2                ; ...
        sd    t3, st_nfree(zero)        ; ...
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    t0, 8(sp)                 ; ...
        sd    t2, 16(sp)                ; ...
        bnez  t1, tk_r                  ; used up: the entry goes
        call  av_rm                     ; ...
tk_r:
        ld    a0, 8(sp)                 ; ...
        ld    a1, 16(sp)                ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; alloc(a0 = pages, a1 = hint or 0) -> a0 = the first page, a1 = how many: in
; one run if there is one (at the hint if that is free), else the front of
; the first free extent
alloc:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        mv    s1, a0                    ; s1 = the pages
        mv    s2, a1                    ; s2 = the hint
        call  begin                     ; ...
        ld    t0, in_fin(zero)          ; the allocator's own trees may use the reserve
        bnez  t0, al_go                 ; ...
        ld    t0, st_nfree(zero)        ; ...
        ld    t1, st_txfreed(zero)      ; ...
        sub   t0, t0, t1                ; ...
        addi  t1, s1, ST_RES            ; ...
        bltu  t0, t1, st_full           ; ...
al_go:
        ld    t0, in_b(zero)            ; while av is written back: from its largest
        beqz  t0, al_h                  ; ...
        ld    t0, navail(zero)          ; ...
        beqz  t0, st_full               ; ...
        slli  t0, t0, 4                 ; ...
        li    t1, 0                     ; ...
        li    t2, 16                    ; ...
al_bl:
        bgeu  t2, t0, al_bt             ; ...
        ld    t3, av+8(t2)              ; ...
        ld    t4, av+8(t1)              ; ...
        bleu  t3, t4, al_bn             ; ...
        mv    t1, t2                    ; ...
al_bn:
        addi  t2, t2, 16                ; ...
        j     al_bl                     ; ...
al_bt:
        mv    a0, t1                    ; ...
        j     al_take                   ; ...
al_h:
        beqz  s2, al_f                  ; at the hint?
        li    s3, 0                     ; ...
al_hp:
        ld    t0, navail(zero)          ; ...
        slli  t0, t0, 4                 ; ...
        li    a0, 0                     ; ...
al_hs:
        bgeu  a0, t0, al_hn             ; ...
        ld    t2, av(a0)                ; ...
        beq   t2, s2, al_take           ; ...
        addi  a0, a0, 16                ; ...
        j     al_hs                     ; ...
al_hn:
        bnez  s3, al_f8                 ; ...
        ld    t0, in_ft(zero)           ; ...
        bnez  t0, al_f8                 ; ...
        li    s3, 1                     ; ...
        mv    a0, s2                    ; ...
        call  load_at                   ; ...
        j     al_hp                     ; ...
al_f8:
        slli  a0, s1, 3                 ; no: from the first run of some length, so
        call  av_first                  ; that what a commit writes lies together
        bgez  a0, al_take               ; ...
al_f:
        mv    a0, s1                    ; the first extent that holds them all
        call  av_first                  ; ...
        bgez  a0, al_take               ; ...
        ld    t0, in_ft(zero)           ; ...
        bnez  t0, al_any                ; ...
        mv    a0, s1                    ; ...
        call  load_fit                  ; ...
        bnez  a0, al_f                  ; ...
al_any:
        ld    t0, navail(zero)          ; none: what the first one has
        beqz  t0, st_full               ; ...
        li    a0, 0                     ; ...
al_take:
        mv    a1, s1                    ; ...
        call  take                      ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; alloc1() -> a0 = one page, after the one allocated last when that is free
alloc1:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        li    a0, 1                     ; ...
        ld    a1, st_last(zero)         ; ...
        addi  a1, a1, 1                 ; ...
        call  alloc                     ; ...
        sd    a0, st_last(zero)         ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; pfree(a0 = start, a1 = pages, a2 = birth): the store stops using them. Born
; in this commit: free at once. Older: reusable when this commit is on the disk.
pfree:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        mv    s3, a2                    ; ...
        ld    t1, st_deadlim(zero)      ; a snapshot still shows them: not free
        bgeu  t1, s3, pfr_held          ; ...
        ld    t0, st_nfree(zero)        ; ...
        add   t0, t0, s2                ; ...
        sd    t0, st_nfree(zero)        ; ...
pfr_held:
        li    s4, 0                     ; the cache forgets them
pfr_d:
        bgeu  s4, s2, pfr_dd             ; ...
        add   a0, s1, s4                ; ...
        call  b_drop                    ; ...
        addi  s4, s4, 1                 ; ...
        j     pfr_d                     ; ...
pfr_dd:
        mv    a0, s1                    ; ...
        mv    a1, s2                    ; ...
        ld    t0, st_txn(zero)          ; ...
        bne   s3, t0, pfr_old            ; ...
        call  avail_add                 ; ...
        j     pfr_ret                    ; ...
pfr_old:
        mv    a2, s3                    ; ...
        call  freed_put                 ; ...
        ld    t1, st_deadlim(zero)      ; (kept for a snapshot: not on its way to being free)
        bltu  t1, s3, pfr_ret           ; ...
        ld    t0, st_txfreed(zero)      ; ...
        sub   t0, t0, s2                ; ...
        sd    t0, st_txfreed(zero)      ; ...
pfr_ret:
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 40                ; ...
        ret                             ; ...

; drain_ld(): the free records taken are deleted from the free tree (each
; delete may need pages: a few are kept at hand)
drain_ld:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
dld_l:
        ld    t0, nld(zero)             ; ...
        beqz  t0, dld_ret               ; ...
dld_t:
        call  avail_total               ; ...
        li    t0, 8                     ; ...
        bgeu  a0, t0, dld_d             ; ...
        li    a0, 1                     ; ...
        call  load_fit                  ; ...
        bnez  a0, dld_t                 ; ...
dld_d:
        ld    t0, nld(zero)             ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, nld(zero)             ; ...
        slli  t0, t0, 3                 ; ...
        ld    a0, ldk(t0)               ; ...
        call  bswap                     ; ...
        sd    a0, lkey(zero)            ; ...
        li    t0, 1                     ; ...
        sd    t0, in_ft(zero)           ; ...
        la    a0, t_fre                 ; ...
        la    a1, lkey                  ; ...
        li    a2, 8                     ; ...
        call  st_del                    ; ...
        sd    zero, in_ft(zero)         ; ...
        j     dld_l                     ; ...
dld_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; drain_pld(): the pending records taken are deleted from the pending tree
drain_pld:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
dpl_l:
        ld    t0, npld(zero)            ; ...
        beqz  t0, dld_ret               ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, npld(zero)            ; ...
        slli  t0, t0, 4                 ; ...
        ld    t1, pldk(t0)              ; ...
        sd    t1, pkey(zero)            ; ...
        ld    t1, pldk+8(t0)            ; ...
        sd    t1, pkey+8(zero)          ; ...
        la    a0, t_pend                ; ...
        la    a1, pkey                  ; ...
        li    a2, 16                    ; ...
        call  st_del                    ; ...
        j     dpl_l                     ; ...

; drain_fr(): what was freed is recorded in the pending tree under this commit
drain_fr:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
dfr_l:
        ld    t0, nfreed(zero)          ; ...
        beqz  t0, dld_ret               ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, nfreed(zero)          ; ...
        li    t1, 24                    ; ...
        mul   t1, t0, t1                ; ...
        ld    t2, fr+8(t1)              ; ...
        sd    t2, pval(zero)            ; ...
        ld    t2, fr+16(t1)             ; ...
        sd    t2, pval+8(zero)          ; ...
        ld    a0, fr(t1)                ; ...
        call  bswap                     ; ...
        sd    a0, pkey+8(zero)          ; ...
        ld    a0, st_txn(zero)          ; under this commit; or, born no later than the
        ld    t0, st_deadlim(zero)      ; newest snapshot, on that snapshot's dead list:
        ld    t1, pval+8(zero)          ; its commit with the top bit set, which no
        bltu  t0, t1, dfr_k             ; commit ever reaches
        li    a0, 1                     ; ...
        slli  a0, a0, 63                ; ...
        or    a0, a0, t0                ; ...
dfr_k:
        call  bswap                     ; ...
        sd    a0, pkey(zero)            ; ...
        la    a0, t_pend                ; ...
        la    a1, pkey                  ; ...
        li    a2, 16                    ; ...
        la    a3, pval                  ; ...
        li    a4, 16                    ; ...
        li    a5, 0                     ; ...
        call  st_put                    ; ...
        j     dfr_l                     ; ...

; relief(): where no tree change is under way: the lists are written out when
; they are filling
relief:
        ld    t0, in_fin(zero)          ; ...
        ld    t1, in_rel(zero)          ; ...
        or    t0, t0, t1                ; ...
        bnez  t0, aa_ret                ; ...
        ld    t0, st_began(zero)        ; ...
        beqz  t0, aa_ret                ; ...
        li    t1, 24                    ; ...
        ld    t0, nld(zero)             ; ...
        bgeu  t0, t1, rl_go             ; ...
        ld    t0, nfreed(zero)          ; ...
        bltu  t0, t1, aa_ret            ; ...
rl_go:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        li    t0, 1                     ; ...
        sd    t0, in_rel(zero)          ; ...
        call  drain_ld                  ; ...
        call  drain_fr                  ; ...
        sd    zero, in_rel(zero)        ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; finalize(): the free and pending trees are brought up to date with what
; this commit took and freed. Changing those trees itself takes and frees
; pages, so this repeats until a pass leaves nothing over: the records taken
; are deleted, what was freed goes into the pending tree, and what is left in
; av goes back into the free tree, the smallest extents first; the pages
; this needs come from the largest, and the last extent left is not put into
; the tree (that could need more pages than it has): it is the spare extent.
finalize:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        li    t0, 1                     ; ...
        sd    t0, in_fin(zero)          ; ...
        li    s1, 0                     ; s1 = passes
fz_top:
        addi  s1, s1, 1                 ; ...
        li    t0, 50                    ; (it settles in two or three)
        bgeu  s1, t0, st_die            ; ...
fz_res:
        call  avail_total               ; some pages at hand
        li    t0, ST_RES                ; ...
        bgeu  a0, t0, fz_nb             ; ...
        ld    t0, nld(zero)             ; ...
        li    t1, NLD - 8               ; ...
        bgeu  t0, t1, fz_nb             ; ...
        li    a0, 1                     ; ...
        call  load_fit                  ; ...
        bnez  a0, fz_res                ; ...
fz_nb:
        li    s2, 0                     ; the neighbours still in the tree join them
fz_nl:
        ld    t0, navail(zero)          ; ...
        slli  t0, t0, 4                 ; ...
        bgeu  s2, t0, fz_a              ; ...
        ld    s3, nld(zero)             ; ...
        ld    a0, av(s2)                ; ...
        ld    s4, av+8(s2)              ; ...
        add   s4, s4, a0                ; ...
        call  load_end                  ; ...
        mv    a0, s4                    ; ...
        call  load_at                   ; ...
        addi  s2, s2, 16                ; ...
        ld    t0, nld(zero)             ; ...
        beq   t0, s3, fz_nl             ; ...
        li    s2, 0                     ; (av changed: from its start again)
        j     fz_nl                     ; ...
fz_a:
        call  drain_ld                  ; ...
        call  drain_pld                 ; ...
        call  drain_fr                  ; ...
        ld    t0, nld(zero)             ; those took more: they go first
        ld    t1, npld(zero)            ; ...
        or    t0, t0, t1                ; ...
        bnez  t0, fz_top                ; ...
        li    t0, 1                     ; ...
        sd    t0, in_ft(zero)           ; ...
        sd    t0, in_b(zero)            ; ...
fz_b:
        ld    t0, navail(zero)          ; all but one go back
        li    t1, 2                     ; ...
        bltu  t0, t1, fz_be             ; ...
        slli  t0, t0, 4                 ; t1 = the largest
        li    t1, 0                     ; ...
        li    t2, 16                    ; ...
fz_bg:
        bgeu  t2, t0, fz_sm             ; ...
        ld    t3, av+8(t2)              ; ...
        ld    t4, av+8(t1)              ; ...
        bleu  t3, t4, fz_bn             ; ...
        mv    t1, t2                    ; ...
fz_bn:
        addi  t2, t2, 16                ; ...
        j     fz_bg                     ; ...
fz_sm:
        li    t2, 0                     ; t5 = the smallest of the others
        li    t5, -1                    ; ...
fz_sl:
        bgeu  t2, t0, fz_sd             ; ...
        beq   t2, t1, fz_sn             ; ...
        bltz  t5, fz_st                 ; ...
        ld    t3, av+8(t2)              ; ...
        ld    t4, av+8(t5)              ; ...
        bgeu  t3, t4, fz_sn             ; ...
fz_st:
        mv    t5, t2                    ; ...
fz_sn:
        addi  t2, t2, 16                ; ...
        j     fz_sl                     ; ...
fz_sd:
        ld    s2, av(t5)                ; s2 = where it ends: its record's key
        ld    t3, av+8(t5)              ; ...
        add   s2, s2, t3                ; ...
fz_put:
        mv    a0, s2                    ; (the insert may take pages from this very extent)
        call  avail_end                 ; ...
        mv    s3, a1                    ; ...
        sd    s3, lval(zero)            ; ...
        mv    a0, s2                    ; ...
        call  bswap                     ; ...
        sd    a0, lkey(zero)            ; ...
        la    a0, t_fre                 ; ...
        la    a1, lkey                  ; ...
        li    a2, 8                     ; ...
        la    a3, lval                  ; ...
        li    a4, 8                     ; ...
        li    a5, 0                     ; ...
        call  st_put                    ; ...
        mv    a0, s2                    ; ...
        call  avail_end                 ; ...
        bne   a1, s3, fz_put            ; ...
        bltz  a0, fz_b                  ; ...
        call  av_rm                     ; ...
        j     fz_b                      ; ...
fz_be:
        sd    zero, in_ft(zero)         ; ...
        sd    zero, in_b(zero)          ; ...
        ld    t0, nfreed(zero)          ; that freed pages: once more
        bnez  t0, fz_top                ; ...
        sd    zero, st_spare(zero)      ; what is left is the spare extent
        sd    zero, st_spare+8(zero)    ; ...
        ld    t0, navail(zero)          ; ...
        beqz  t0, fz_ret                ; ...
        ld    t0, av(zero)              ; ...
        sd    t0, st_spare(zero)        ; ...
        ld    t0, av+8(zero)            ; ...
        sd    t0, st_spare+8(zero)      ; ...
        sd    zero, navail(zero)        ; ...
fz_ret:
        sd    zero, in_fin(zero)        ; ...
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 40                ; ...
        ret                             ; ...

