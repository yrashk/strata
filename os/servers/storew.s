; st_tree(a0 = namespace, a1 = name, a2 = its length (<= 28), a3 = 1: make it
; if it is not there) -> a0 = the tree (its entry in tt), or 0
st_tree:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        sd    s5, 40(sp)                ; ...
        mv    s3, a3                    ; s3 = make it?
        addi  s2, a2, 4                 ; s2 = the key's length
        la    t0, ckey                  ; its catalog key: the namespace, the name
        sd    zero, 0(t0)               ; ...
        sd    zero, 8(t0)               ; ...
        sd    zero, 16(t0)              ; ...
        sd    zero, 24(t0)              ; ...
        srli  t1, a0, 24                ; ...
        sb    t1, 0(t0)                 ; ...
        srli  t1, a0, 16                ; ...
        sb    t1, 1(t0)                 ; ...
        srli  t1, a0, 8                 ; ...
        sb    t1, 2(t0)                 ; ...
        sb    a0, 3(t0)                 ; ...
        addi  a0, t0, 4                 ; ...
        call  srv_bcopy                 ; ...
        la    s1, tt                    ; open already?
        li    s4, 0                     ; s4 = a free entry
        li    s5, NTT                   ; ...
stt_l:
        ld    t0, TT_FL(s1)             ; ...
        bnez  t0, stt_u                 ; ...
        mv    s4, s1                    ; ...
        j     stt_n                     ; ...
stt_u:
        ld    t0, TT_KL(s1)             ; ...
        bne   t0, s2, stt_n             ; ...
        addi  a0, s1, TT_KEY            ; ...
        mv    a1, s2                    ; ...
        la    a2, ckey                  ; ...
        mv    a3, s2                    ; ...
        call  kcmp                      ; ...
        beqz  a0, stt_yes               ; ...
stt_n:
        addi  s1, s1, TT_SIZE           ; ...
        addi  s5, s5, -1                ; ...
        bnez  s5, stt_l                 ; ...
        beqz  s4, st_die                ; no entry left
        mv    s1, s4                    ; ...
        la    a0, t_cat                 ; in the catalog?
        la    a1, ckey                  ; ...
        mv    a2, s2                    ; ...
        la    a3, cval                  ; ...
        call  st_get                    ; ...
        li    t2, 1                     ; ...
        bgez  a0, stt_have              ; ...
        beqz  s3, stt_no                ; ...
        sd    zero, cval(zero)          ; a new, empty tree
        sd    zero, cval+8(zero)        ; ...
        li    t2, 3                     ; ...
stt_have:
        sd    t2, TT_FL(s1)             ; ...
        ld    t0, cval(zero)            ; ...
        sd    t0, 0(s1)                 ; ...
        sd    t0, TT_SR(s1)             ; ...
        ld    t0, cval+8(zero)          ; ...
        sd    t0, 8(s1)                 ; ...
        sd    t0, TT_SR+8(s1)           ; ...
        sd    s2, TT_KL(s1)             ; ...
        addi  a0, s1, TT_KEY            ; ...
        la    a1, ckey                  ; ...
        li    a2, 32                    ; ...
        call  wcopy                     ; ...
stt_yes:
        mv    a0, s1                    ; ...
        j     stt_ret                   ; ...
stt_no:
        li    a0, 0                     ; ...
stt_ret:
        ld    s5, 40(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; ...

; tt_save(): the roots that changed -> the catalog
tt_save:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        la    s1, tt                    ; ...
        li    s2, NTT                   ; ...
tts_l:
        ld    t0, TT_FL(s1)             ; ...
        beqz  t0, tts_n                 ; ...
        andi  t0, t0, 2                 ; not there yet?
        bnez  t0, tts_put               ; ...
        ld    t0, 0(s1)                 ; or moved?
        ld    t1, TT_SR(s1)             ; ...
        bne   t0, t1, tts_put           ; ...
        ld    t0, 8(s1)                 ; ...
        ld    t1, TT_SR+8(s1)           ; ...
        beq   t0, t1, tts_n             ; ...
tts_put:
        ld    t0, 0(s1)                 ; (the tree's words change under the put when
        sd    t0, cval(zero)            ; it is the catalog's own: a copy)
        sd    t0, TT_SR(s1)             ; ...
        ld    t0, 8(s1)                 ; ...
        sd    t0, cval+8(zero)          ; ...
        sd    t0, TT_SR+8(s1)           ; ...
        li    t0, 1                     ; ...
        sd    t0, TT_FL(s1)             ; ...
        la    a0, t_cat                 ; ...
        addi  a1, s1, TT_KEY            ; ...
        ld    a2, TT_KL(s1)             ; ...
        la    a3, cval                  ; ...
        li    a4, 16                    ; ...
        li    a5, 0                     ; ...
        call  st_put                    ; ...
tts_n:
        addi  s1, s1, TT_SIZE           ; ...
        addi  s2, s2, -1                ; ...
        bnez  s2, tts_l                 ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; ---- mount, commit, abort ----------------------------------------------------------

; meta_load() -> a0 = 0, or -1 when neither meta block is good: the newer
; good one's words -> the store's
meta_load:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        li    a0, 1                     ; both, into the scratch
        ld    a1, st_bpp(zero)          ; ...
        li    a2, 1                     ; ...
        li    a3, 0                     ; ...
        li    a4, 5                     ; ...
        call  blk                       ; ...
        li    a0, 1                     ; ...
        ld    a1, st_bpp(zero)          ; ...
        slli  a1, a1, 1                 ; ...
        li    a2, 1                     ; ...
        li    a3, 512                   ; ...
        li    a4, 5                     ; ...
        call  blk                       ; ...
        la    t0, out_buf               ; -> D-LS
        li    t1, 1024                  ; ...
        tget  tg1, t0, c5, zero, t1     ; ...
        twait 1 << 1                    ; ...
        li    s1, 1                     ; s1 = the meta page looked at
        li    s2, 0                     ; s2 = the best one's block
        li    s3, 0                     ; s3 = its commit + 1
ml_l:
        addi  a0, s1, -1                ; ...
        slli  a0, a0, 9                 ; ...
        la    t0, out_buf               ; ...
        add   a0, a0, t0                ; ...
        li    a1, 512                   ; ...
        mv    a2, s1                    ; ...
        call  sum                       ; ...
        addi  t1, s1, -1                ; ...
        slli  t1, t1, 9                 ; ...
        la    t0, out_buf               ; ...
        add   t1, t1, t0                ; ...
        ld    t0, 0(t1)                 ; as the block says?
        bne   t0, a0, ml_n              ; ...
        ld    t0, 8(t1)                 ; and a meta block?
        ld    t2, s_magic(zero)         ; ...
        bne   t0, t2, ml_n              ; ...
        ld    t0, 16(t1)                ; the newer one counts
        addi  t0, t0, 1                 ; ...
        bleu  t0, s3, ml_n              ; ...
        mv    s3, t0                    ; ...
        mv    s2, t1                    ; ...
ml_n:
        addi  s1, s1, 1                 ; ...
        li    t0, 3                     ; ...
        bne   s1, t0, ml_l              ; ...
        li    a0, -1                    ; ...
        beqz  s2, ml_ret                ; ...
        ld    t0, 16(s2)                ; ...
        sd    t0, st_cmt(zero)       ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, st_txn(zero)          ; ...
        ld    t0, 24(s2)                ; ...
        sd    t0, st_npages(zero)       ; ...
        ld    t0, 32(s2)                ; ...
        sd    t0, st_first(zero)        ; ...
        ld    t0, 40(s2)                ; ...
        sd    t0, t_cat(zero)           ; ...
        ld    t0, 48(s2)                ; ...
        sd    t0, t_cat+8(zero)         ; ...
        ld    t0, 56(s2)                ; ...
        sd    t0, t_fre(zero)           ; ...
        ld    t0, 64(s2)                ; ...
        sd    t0, t_fre+8(zero)         ; ...
        ld    t0, 72(s2)                ; ...
        sd    t0, t_pend(zero)          ; ...
        ld    t0, 80(s2)                ; ...
        sd    t0, t_pend+8(zero)        ; ...
        ld    t0, 88(s2)                ; ...
        sd    t0, st_manif(zero)        ; ...
        ld    t0, 96(s2)                ; ...
        sd    t0, st_nextns(zero)       ; ...
        ld    t0, 104(s2)               ; ...
        sd    t0, st_nfree(zero)        ; ...
        ld    t0, 120(s2)               ; ...
        sd    t0, st_spare(zero)        ; ...
        ld    t0, 128(s2)               ; ...
        sd    t0, st_spare+8(zero)      ; ...
        ld    t0, 136(s2)               ; ...
        sd    t0, st_nextid(zero)       ; ...
        li    a0, 0                     ; ...
ml_ret:
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; meta_write(): this commit's meta block -> the meta page not written last
meta_write:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        la    a0, out_buf               ; ...
        li    a1, 512                   ; ...
        call  wzero                     ; ...
        la    t1, out_buf               ; ...
        ld    t0, s_magic(zero)         ; ...
        sd    t0, 8(t1)                 ; ...
        ld    t0, st_txn(zero)          ; ...
        sd    t0, 16(t1)                ; ...
        andi  s1, t0, 1                 ; s1 = the meta page: 1 + (commit & 1)
        addi  s1, s1, 1                 ; ...
        ld    t0, st_npages(zero)       ; ...
        sd    t0, 24(t1)                ; ...
        ld    t0, st_first(zero)        ; ...
        sd    t0, 32(t1)                ; ...
        ld    t0, t_cat(zero)           ; ...
        sd    t0, 40(t1)                ; ...
        ld    t0, t_cat+8(zero)         ; ...
        sd    t0, 48(t1)                ; ...
        ld    t0, t_fre(zero)           ; ...
        sd    t0, 56(t1)                ; ...
        ld    t0, t_fre+8(zero)         ; ...
        sd    t0, 64(t1)                ; ...
        ld    t0, t_pend(zero)          ; ...
        sd    t0, 72(t1)                ; ...
        ld    t0, t_pend+8(zero)        ; ...
        sd    t0, 80(t1)                ; ...
        ld    t0, st_manif(zero)        ; ...
        sd    t0, 88(t1)                ; ...
        ld    t0, st_nextns(zero)       ; ...
        sd    t0, 96(t1)                ; ...
        ld    t0, st_nfree(zero)        ; ...
        sd    t0, 104(t1)               ; ...
        ld    t0, st_ps(zero)           ; ...
        sd    t0, 112(t1)               ; ...
        ld    t0, st_spare(zero)        ; ...
        sd    t0, 120(t1)               ; ...
        ld    t0, st_spare+8(zero)      ; ...
        sd    t0, 128(t1)               ; ...
        ld    t0, st_nextid(zero)       ; ...
        sd    t0, 136(t1)               ; ...
        mv    a0, t1                    ; its checksum
        li    a1, 512                   ; ...
        mv    a2, s1                    ; ...
        call  sum                       ; ...
        la    t1, out_buf               ; ...
        sd    a0, 0(t1)                 ; ...
        li    t2, 512                   ; -> the scratch -> the disk
        tput  tg1, t1, c5, zero, t2     ; ...
        twait 1 << 1                    ; ...
        li    a0, 2                     ; ...
        ld    a1, st_bpp(zero)          ; ...
        mul   a1, a1, s1                ; ...
        li    a2, 1                     ; ...
        li    a3, 0                     ; ...
        li    a4, 5                     ; ...
        call  blk                       ; ...
        bnez  a0, st_die                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; dev_flush(): what the device holds back goes to the disk
dev_flush:
        li    a0, 3                     ; ...
        li    a1, 0                     ; ...
        li    a2, 0                     ; ...
        li    a3, 0                     ; ...
        li    a4, 5                     ; ...
        j     blk                       ; ...

; st_clear(): nothing of a commit under way is kept: the lists, the flags,
; the cache, the trees open
st_clear:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        sd    zero, navail(zero)        ; ...
        sd    zero, nfreed(zero)        ; ...
        sd    zero, nld(zero)           ; ...
        sd    zero, npld(zero)          ; ...
        sd    zero, st_began(zero)      ; ...
        sd    zero, in_ft(zero)         ; ...
        sd    zero, in_b(zero)          ; ...
        sd    zero, in_fin(zero)        ; ...
        sd    zero, in_rel(zero)        ; ...
        sd    zero, st_txfreed(zero)    ; ...
        la    a0, tt                    ; ...
        li    a1, NTT * TT_SIZE         ; ...
        call  wzero                     ; ...
        call  c_reset                   ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; st_mount() -> a0 = 0, or -1 when the disk is not a store: the boot header's
; page size, the newer good meta block
st_mount:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        li    a0, 1                     ; block 0
        li    a1, 0                     ; ...
        li    a2, 1                     ; ...
        li    a3, 0                     ; ...
        li    a4, 5                     ; ...
        call  blk                       ; ...
        la    t0, out_buf               ; ...
        li    t1, 512                   ; ...
        tget  tg1, t0, c5, zero, t1     ; ...
        twait 1 << 1                    ; ...
        li    a0, -1                    ; ...
        lwu   t1, 56(t0)                ; "STDB"
        li    t2, 0x42445453            ; ...
        bne   t1, t2, stm_ret           ; ...
        lwu   t1, 60(t0)                ; ...
        sd    t1, st_ps(zero)           ; ...
        srli  t1, t1, 9                 ; ...
        sd    t1, st_bpp(zero)          ; ...
        call  st_clear                  ; ...
        call  meta_load                 ; ...
stm_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; st_commit(): everything changed since the last commit is on the disk, or
; (the power going before the meta block is written) none of it is
st_commit:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        call  tt_save                   ; ...
        ld    t0, st_began(zero)        ; nothing changed
        beqz  t0, stc_ret               ; ...
        call  finalize                  ; ...
        call  b_sync                    ; ...
        call  c_write                   ; ...
        call  dev_flush                 ; ...
        call  meta_write                ; ...
        call  dev_flush                 ; ...
        ld    t0, st_txn(zero)          ; ...
        sd    t0, st_cmt(zero)       ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, st_txn(zero)          ; ...
        sd    zero, st_began(zero)      ; ...
        sd    zero, st_txfreed(zero)    ; ...
stc_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; st_abort(): back to the last commit (the trees open are forgotten: the
; caller opens its own again)
st_abort:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        call  st_clear                  ; ...
        call  meta_load                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...
