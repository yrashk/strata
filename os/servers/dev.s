; =============================================================================
; dev.s: the device manager
; =============================================================================
;
; A user-mode server (pid 2, created by the kernel at boot). It holds the
; device root (given in c6, moved to c7) and hands out device capabilities:
;
;  23 DEVS     -> entries; data: the platform table's 32-byte entries
;  24 HALT     -> asks the kernel to stop every core (does not return)
;  26 GRANT_FB -> 0; the framebuffer memory (in c6 of the caller) and a
;               capability for the controller's ports 0x4000..0x400F (c7);
;               -5 if the caller is not the process registered as "ws"
;               (proc's WHOIS); -7 if a live process holds it; -1 if there
;               is none
;  30 GETDISK  -> 0; a window on the block device's ports (c6) and a
;               send-only endpoint to the device's node (c7) (for fs)
;  31 GETCON   -> 0; a window on the console's ports 0x0000..0x00FF (c6) (for tty)
;  21 GETPTR   -> 0; a window on the pointer's ports 0x4100..0x410F (c6) (for
;               tty, which hands its events to ws); -1 if the machine has none
;  36/37/38    DUPS / CLEANUP / CANCEL from proc: nothing to do
;
; The framebuffer memory is the kernel's: it sits in a revocation domain of
; its own, and the kernel's FBLEND (op 10, dev only) records the new holder,
; revokes every older capability and sends a fresh one, which dev passes on.
; When the holder ends (exit, kill, fault), the kernel revokes it again, so
; the capability (and anything cut from it) dies and the next "ws" can have it.
;
; Capability registers here: c0 scratch, c1 proc, c2 unused,
; c3 the kernel's endpoint, c4 scratch (a window being made), c5 buffer,
; c6 requests, c7 the device root (moved from c6 at start).

PLAT     = 0x1000                       ; the platform table's offset in device space
PLATMAX  = 512                          ; its largest size
FBCTL    = 0x4000                       ; framebuffer controller ports
FBCTL_N  = 0x10                         ; ...

        .data                           ; data Local Store
        .align 8                        ; ...
plat:   .space PLATMAX                  ; the platform table
n_ws:   .ascii "ws\0\0\0\0\0\0"           ; the only name GRANT_FB serves
fbpid:  .dword 0                        ; GRANT_FB: the caller's pid
fbpark: .dword 0                        ; GRANT_FB: its parked request

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        li    sp, 65536                 ; stack at the top of the D-LS
        call  sys_init                  ; ...
        cclear c0                       ; the arena is not needed: c0 is scratch
        cclear c7                       ; the clock is not needed here
        cmov  c7, c6                    ; c7 = the device root (c6 receives requests)
        li    a0, PLAT                  ; read the platform table once
        li    a1, PLATMAX               ; ...
        call  window                    ; c4 = it
        la    t0, plat                  ; the header first (its length)
        li    t1, 32                    ; ...
        tget  tg1, t0, c4, zero, t1     ; ...
        twait 1 << 1                    ; ...
        lwu   t2, 12(t0)                ; total length
        li    t3, PLATMAX               ; ...
        bleu  t2, t3, m_len             ; ...
        mv    t2, t3                    ; ...
m_len:
        tget  tg1, t0, c4, zero, t2     ; all of it
        twait 1 << 1                    ; ...
        cclear c4                       ; ...
        la    a0, loop                  ; a fault on a dead request returns to the loop
        call  srv_guard                 ; ...
loop:
        li    a0, 0                     ; no device tags
        li    a1, -1                    ; ...
        call  srv_recv                  ; ...
        bltz  a0, loop                  ; ...
        la    t0, srv_hdr               ; dispatch
        ld    t1, 0(t0)                 ; ...
        li    t2, 23                    ; DEVS
        beq   t1, t2, op_devs           ; ...
        li    t2, 24                    ; HALT
        beq   t1, t2, op_halt           ; ...
        li    t2, 26                    ; GRANT_FB
        beq   t1, t2, op_fb             ; ...
        li    t2, 30                    ; GETDISK
        beq   t1, t2, op_disk           ; ...
        li    t2, 31                    ; GETCON
        beq   t1, t2, op_con            ; ...
        li    t2, 21                    ; GETPTR
        beq   t1, t2, op_ptr            ; ...
        li    t2, OP_DUPS               ; nothing to count
        beq   t1, t2, ok                ; ...
        li    t2, OP_CLEANUP            ; ...
        beq   t1, t2, ok                ; ...
        li    t2, OP_CANCEL             ; ...
        beq   t1, t2, ok                ; ...
        li    a0, -1                    ; unknown
reply:
        li    a1, 0                     ; no attachments
        call  srv_reply                 ; ...
        j     loop                      ; ...
ok:
        li    a0, 0                     ; ...
        j     reply                     ; ...

; window(a0 = base, a1 = size) -> c4 = that part of device space (from the
; root c7; device capabilities are copyable, so cutting a copy loses nothing)
window:
        cclear c4                       ; ...
        cclear c0                       ; c0 is scratch here
        cmov  c4, c7                    ; a copy of the root
        csplit c0, c4, a0               ; c4 = [0, base), c0 = [base, end)
        cclear c4                       ; ...
        csplit c4, c0, a1               ; c0 = [base, base + size), c4 = the rest
        cclear c4                       ; ...
        cmov  c4, c0                    ; the window
        cclear c0                       ; ...
        ret                             ; ...

; ---- DEVS ------------------------------------------------------------------------------------
op_devs:
        li    a0, PLAT                  ; read the table again (it is small)
        li    a1, PLATMAX               ; ...
        call  window                    ; c4 = it
        la    t0, plat                  ; ...
        li    t1, PLATMAX               ; all of it (zero past its end)
        tget  tg1, t0, c4, zero, t1     ; ...
        twait 1 << 1                    ; ...
        cclear c4                       ; ...
        la    t0, plat                  ; entries
        lhu   s1, 8(t0)                 ; ...
        slli  a1, s1, 5                 ; their bytes
        addi  a0, t0, 32                ; ...
        call  srv_put                   ; -> the request's data
        mv    a0, s1                    ; the count
        j     reply                     ; ...

; ---- HALT ------------------------------------------------------------------------------------
op_halt:
        li    a0, 3                     ; the kernel (c3): HALT
        li    a1, 8                     ; ...
        li    a2, 0                     ; ...
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        call  sys_msg                   ; does not come back
        li    a0, -1                    ; (if it did)
        j     reply                     ; ...

; ---- GETCON / GETDISK ----------------------------------------------------------------------------
op_con:
        li    a0, 0                     ; the console window
        li    a1, 0x100                 ; ...
        call  window                    ; c4
        li    a0, 0                     ; ...
        li    a1, 4                     ; send c4 with the reply
        call  srv_reply                 ; ...
        j     loop                      ; ...

op_ptr:
        li    a0, 7                     ; the pointer's entry (type 7)
        call  find                      ; a0 = entry or 0
        beqz  a0, od_none               ; ...
        ld    a1, 24(a0)                ; its window
        ld    a0, 16(a0)                ; ...
        call  window                    ; c4
        li    a0, 0                     ; ...
        li    a1, 4                     ; send c4 with the reply
        call  srv_reply                 ; ...
        j     loop                      ; ...

op_disk:
        li    a0, 4                     ; the block device's entry (type 4)
        call  find                      ; a0 = entry or 0
        beqz  a0, od_none               ; ...
        mv    s1, a0                    ; ...
        ld    a1, 24(s1)                ; its window
        ld    a0, 16(s1)                ; ...
        call  window                    ; c4
        lhu   a2, 6(s1)                 ; its node: mint an endpoint to it too
        li    a0, 0                     ; ...
        li    a1, 4 | 2                 ; c4, then the endpoint
        call  srv_reply                 ; ...
        j     loop                      ; ...
od_none:
        li    a0, -1                    ; ...
        j     reply                     ; ...

; ---- GRANT_FB --------------------------------------------------------------------------------------
op_fb:
        call  srv_pid                   ; who asks
        la    t0, fbpid                 ; ...
        sd    a0, 0(t0)                 ; ...
        la    a0, n_ws                  ; proc: who is "ws"?
        li    a1, 8                     ; ...
        call  sys_put                   ; ...
        li    a0, 1                     ; ...
        li    a1, OP_WHOIS              ; ...
        li    a2, 0                     ; ...
        li    a3, 2                     ; ...
        li    a4, 0                     ; ...
        call  sys_msg                   ; a0 = its pid, -4 none
        la    t0, fbpid                 ; only that process
        ld    t0, 0(t0)                 ; ...
        blez  a0, ofb_deny              ; (none, or a boot server)
        bne   a0, t0, ofb_deny          ; ...
        call  srv_park                  ; the request out of c6: the memory arrives there
        bltz  a0, ofb_busy              ; (the kernel has no room)
        la    t0, fbpark                ; ...
        sd    a0, 0(t0)                 ; ...
        li    a0, 3                     ; the kernel (c3): FBLEND for that pid
        li    a1, 10                    ; ...
        la    t0, fbpid                 ; ...
        ld    a2, 0(t0)                 ; ...
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        call  sys_msg                   ; a0 = 0 and the memory in c6; -7 held; -1 none
        mv    s1, a0                    ; ...
        cclear c4                       ; c4 = the memory (if any)
        cvalid t0, c6                   ; ...
        beqz  t0, ofb_none              ; ...
        cmov  c4, c6                    ; ...
ofb_none:
        la    t0, fbpark                ; the request back in c6
        ld    a0, 0(t0)                 ; ...
        call  srv_unpark                ; ...
        bnez  a0, ofb_gone              ; its owner died meanwhile
        mv    a0, s1                    ; refused: say so
        bnez  a0, ofb_fail              ; ...
        cclear c2                       ; keep the memory aside in c2
        cmov  c2, c4                    ; ...
        li    a0, FBCTL                 ; the controller's ports
        li    a1, FBCTL_N               ; ...
        call  window                    ; c4 = them (window uses c0 and c4 only)
        cmov  c0, c7                    ; keep a copy of the root aside
        cclear c7                       ; ...
        cmov  c7, c4                    ; c7 = the ports (sent second)
        cclear c4                       ; ...
        cmov  c4, c2                    ; c4 = the memory (sent first)
        li    a0, 0                     ; ...
        li    a1, 4 | 1                 ; send c4, then c7, then the reply
        call  srv_reply                 ; (the caller gets c6 = memory, c7 = ports)
        cclear c7                       ; (gone anyway)
        cmov  c7, c0                    ; the root back
        cclear c0                       ; ...
        j     loop                      ; ...
ofb_gone:
        cclear c4                       ; nobody to give it to (the kernel revokes it at the exit)
        j     loop                      ; ...
ofb_fail:
        cclear c4                       ; ...
        j     reply                     ; a0 = the kernel's answer
ofb_deny:
        li    a0, -5                    ; not the window server
        j     reply                     ; ...
ofb_busy:
        li    a0, -7                    ; busy
        j     reply                     ; ...

; find(a0 = type) -> a0 = the first platform entry of that type, or 0
find:
        la    t0, plat                  ; ...
        lhu   t1, 8(t0)                 ; entries
        addi  t0, t0, 32                ; ...
fd_l:
        beqz  t1, fd_no                 ; ...
        lhu   t2, 0(t0)                 ; ...
        beq   t2, a0, fd_yes            ; ...
        addi  t0, t0, 32                ; ...
        addi  t1, t1, -1                ; ...
        j     fd_l                      ; ...
fd_yes:
        mv    a0, t0                    ; ...
        ret                             ; ...
fd_no:
        li    a0, 0                     ; ...
        ret                             ; ...

        .include "../lib/sys.s"         ; the program library
        .include "../lib/srv.s"         ; server helpers
