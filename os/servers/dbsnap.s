        ld    t0, e_off(zero)           ; ...
        sub   t0, s5, t0                ; ...
        add   a0, a0, t0                ; ...
        call  PR                        ; ...
        mv    a1, a0                    ; ...
        la    a0, pgcopy                ; ...
        li    a2, 4096                  ; ...
        call  wcopy                     ; ...
bfx_w:
        add   a0, s4, s5                ; ...
        call  PRN                       ; ...
        la    a1, pgcopy                ; ...
        li    a2, 4096                  ; ...
        call  wcopy                     ; ...
        addi  s5, s5, 1                 ; ...
