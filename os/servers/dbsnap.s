        mv    a0, s2                    ; ...
        li    a1, 0                     ; ...
        call  s_trim                    ; ...
        mv    a0, s2                    ; ...
        li    a1, 0                     ; ...
        mv    a2, s4                    ; ...
        mv    a3, s3                    ; ...
        ld    a4, st_txn(zero)          ; ...
        call  ext_put                   ; ...
bfx_man:
        call  alloc1                    ; the manifest anew: a page of this commit
        mv    s3, a0                    ; s3 = it
        call  PN                        ; ...
        sd    s3, 8(a0)                 ; ...
        ld    t0, st_txn(zero)          ; ...
        sd    t0, 16(a0)                ; ...
        li    t0, 3                     ; ...
        sb    t0, 24(a0)                ; ...
        li    t0, 0x464D544F4F425453    ; "STBOOTMF"
        sd    t0, 32(a0)                ; ...
