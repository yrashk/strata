; =============================================================================
; dbsnap.s: snapshots and the boot manifest (included by db.s)
; =============================================================================
;
; A snapshot is the whole store as of one commit, under a name: taking one
; records that commit's catalog root in the tree "snap" of namespace 0 (u64
; commit, big-endian -> u64 catalog root, u64 height, the name) and copies
; nothing. From then on the store keeps the pages that commit used (storew.s:
; st_deadlim and the dead lists). A client reads a snapshot through handles
; to its trees (SNAPT); a restore gives live trees the snapshot's roots.

        .data                           ; data Local Store
        .align 8                        ; ...
sx_n:   .dword 0                        ; trees in sx
        .text                           ; instruction Local Store

; snap_find(a0 = name, a1 = its length) -> a0 = the commit of the snapshot of
; that name, or 0 (its record is then in rkey, tnbuf)
snap_find:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        sd    zero, rkey(zero)          ; ...
snf_l:
        ld    a0, x_snap(zero)          ; ...
        la    a1, rkey                  ; ...
        li    a2, 8                     ; ...
        li    a3, ST_GT                 ; ...
        la    a4, rkey                  ; ...
        la    a5, tnbuf                 ; ...
        call  st_seek                   ; ...
        beqz  a0, snf_ret               ; ...
        la    a0, tnbuf + 16            ; ...
        ld    a1, sk_vl(zero)           ; ...
        addi  a1, a1, -16               ; ...
        mv    a2, s1                    ; ...
        mv    a3, s2                    ; ...
        call  kcmp                      ; ...
        bnez  a0, snf_l                 ; ...
        ld    a0, rkey(zero)            ; ...
        call  bswap                     ; ...
snf_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; snap_roots(a0 = a snapshot's commit, a1 = live handles (D-LS), a2 = how
; many, <= 8) -> a0 = 0, or -1 if there is no such snapshot: sx[i] = the root
; and height of the tree that handle i names (its namespace and name) as the
; snapshot has it (0, 0: it had none)
snap_roots:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        mv    s1, a1                    ; ...
        mv    s2, a2                    ; ...
        sd    a2, sx_n(zero)            ; ...
        call  bswap                     ; its record
        sd    a0, rkey(zero)            ; ...
        ld    a0, x_snap(zero)          ; ...
        la    a1, rkey                  ; ...
        li    a2, 8                     ; ...
        la    a3, tnbuf                 ; ...
        call  st_get                    ; ...
        bltz  a0, snr_ret               ; (a0 = -1)
        ld    t0, tnbuf(zero)           ; its catalog
        sd    t0, scat(zero)            ; ...
        ld    t0, tnbuf+8(zero)         ; ...
        sd    t0, scat+8(zero)          ; ...
        la    s3, sx                    ; ...
snr_l:
        beqz  s2, snr_ok                ; ...
        sd    zero, 0(s3)               ; (a tree the snapshot does not have: empty)
        sd    zero, 8(s3)               ; ...
        ld    t0, 0(s1)                 ; the live tree's catalog key
        la    a0, scat                  ; ...
        addi  a1, t0, TT_KEY            ; ...
        ld    a2, TT_KL(t0)             ; ...
        mv    a3, s3                    ; ...
        call  st_get                    ; ...
        addi  s1, s1, 8                 ; ...
        addi  s3, s3, 16                ; ...
        addi  s2, s2, -1                ; ...
        j     snr_l                     ; ...
snr_ok:
        li    a0, 0                     ; ...
snr_ret:
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; live_handles(a0 = the handles in the request's data, a1 = how many) -> to
; bad unless each is a live tree (tt) and they are at most 8
live_handles:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        li    t0, 8                     ; ...
        bgtu  a1, t0, lh_bad            ; ...
lh_l:
        beqz  s2, lh_ret                ; ...
        ld    a0, 0(s1)                 ; ...
        la    t0, sx                    ; (not a snapshot's)
        sub   t0, a0, t0                ; ...
        li    t1, 16 * 8                ; ...
        bltu  t0, t1, lh_bad            ; ...
        call  handle_ok                 ; ...
        beqz  a0, lh_bad                ; ...
        addi  s1, s1, 8                 ; ...
        addi  s2, s2, -1                ; ...
        j     lh_l                      ; ...
lh_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...
lh_bad:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        j     bad                       ; ...

; SNAPT: handle = a snapshot's commit, data = {u64 count, count live handles}
; -> count; data: a handle each to that tree as the snapshot has it
op_snapt:
        call  get_data                  ; ...
        li    t0, 8                     ; ...
        bltu  a1, t0, bad               ; ...
        ld    s2, 0(a0)                 ; s2 = count
        slli  t0, s2, 3                 ; ...
        addi  t0, t0, 8                 ; ...
        bgtu  t0, a1, bad               ; ...
        addi  a0, a0, 8                 ; ...
        mv    a1, s2                    ; ...
        call  live_handles              ; ...
        la    t0, srv_hdr               ; ...
        ld    a0, 8(t0)                 ; ...
        la    a1, rqd + 8               ; ...
        mv    a2, s2                    ; ...
        call  snap_roots                ; ...
        bltz  a0, reply                 ; ...
        la    t0, sxh                   ; the handles
        la    t1, sx                    ; ...
        li    t2, 0                     ; ...
snt_h:
        beq   t2, s2, snt_d             ; ...
        sd    t1, 0(t0)                 ; ...
        addi  t0, t0, 8                 ; ...
        addi  t1, t1, 16                ; ...
        addi  t2, t2, 1                 ; ...
        j     snt_h                     ; ...
snt_d:
        mv    a0, s2                    ; ...
        la    a1, sxh                   ; ...
        slli  a2, s2, 3                 ; ...
        j     reply_data                ; ...

; SNAP: mode 0 take (data = a name of 1..32 bytes) -> 0 / -1 (a bad name, or
; taken already); mode 1 delete (data = the name) -> 0 / -4; mode 2 list ->
; snapshots; data: 40-byte records {u64 commit, name[32]}; mode 3 restore
; (data = {u64 name length, name[32], u64 count, count live handles: the
; last one the namespace's extents}) -> 0 / -4, not committed. Take and
; delete commit what is under way first.
op_snap:
        la    t0, srv_hdr               ; ...
        ld    s4, 24(t0)                ; s4 = the mode
        li    t1, 2                     ; ...
        beq   s4, t1, osn_list          ; ...
        li    t1, 3                     ; ...
        beq   s4, t1, osn_rest          ; ...
        call  get_data                  ; the name
        mv    s2, a1                    ; ...
        blez  s2, bad                   ; ...
        li    t0, 32                    ; ...
        bgtu  s2, t0, bad               ; ...
        la    a0, rbuf                  ; ...
        la    a1, rqd                   ; ...
        mv    a2, s2                    ; ...
        call  srv_bcopy                 ; ...
        la    a0, rbuf                  ; ...
        mv    a1, s2                    ; ...
        call  snap_find                 ; ...
        mv    s1, a0                    ; s1 = its commit, if it is there
        bnez  s4, osn_del               ; ...
        bnez  s1, bad                   ; take: not twice
        call  st_commit                 ; what is committed now is the snapshot
        ld    s1, st_cmt(zero)          ; ...
        la    a0, tnbuf                 ; its record: the catalog as committed, the name
        li    a1, 48                    ; ...
        call  wzero                     ; ...
        ld    t0, t_cat(zero)           ; ...
        sd    t0, tnbuf(zero)           ; ...
        ld    t0, t_cat+8(zero)         ; ...
        sd    t0, tnbuf+8(zero)         ; ...
        la    a0, tnbuf + 16            ; ...
        la    a1, rbuf                  ; ...
        mv    a2, s2                    ; ...
        call  srv_bcopy                 ; ...
        sd    s1, st_deadlim(zero)      ; from now on that commit's pages are kept
        mv    a0, s1                    ; ...
        call  bswap                     ; ...
        sd    a0, rkey(zero)            ; ...
        ld    a0, x_snap(zero)          ; ...
        la    a1, rkey                  ; ...
        li    a2, 8                     ; ...
        la    a3, tnbuf                 ; ...
        addi  a4, s2, 16                ; ...
        li    a5, 0                     ; ...
        call  st_put                    ; ...
        call  st_commit                 ; ...
        j     ok                        ; ...
osn_del:
        beqz  s1, nofile                ; delete: it must be there
        call  st_commit                 ; ...
        mv    a0, s1                    ; s2 = the snapshot before it (0: none)
        call  bswap                     ; ...
        sd    a0, rkey(zero)            ; ...
        li    s2, 0                     ; ...
        ld    a0, x_snap(zero)          ; ...
        la    a1, rkey                  ; ...
        li    a2, 8                     ; ...
        li    a3, ST_LT                 ; ...
        la    a4, dval                  ; ...
        li    a5, 0                     ; ...
        call  st_seek                   ; ...
        beqz  a0, osn_d1                ; ...
        ld    a0, dval(zero)            ; ...
        call  bswap                     ; ...
        mv    s2, a0                    ; ...
osn_d1:
        ld    s5, st_deadlim(zero)      ; s5 = the newest snapshot once this one is gone
        bne   s5, s1, osn_d2            ; ...
        mv    s5, s2                    ; ...
osn_d2:
        sd    s2, st_deadlim(zero)      ; its dead list: what was born after the one before
        li    s3, 1                     ; is free, the rest goes on that one's list
        slli  s3, s3, 63                ; ...
        or    a0, s3, s1                ; ...
        call  bswap                     ; ...
        mv    s3, a0                    ; s3 = the list's key, as stored
osn_dl:
        sd    s3, rkey(zero)            ; ...
        sd    zero, rkey+8(zero)        ; ...
        la    a0, t_pend                ; ...
        la    a1, rkey                  ; ...
        li    a2, 16                    ; ...
        li    a3, ST_GT                 ; ...
        la    a4, rkey                  ; ...
        la    a5, dval                  ; ...
        call  st_seek                   ; ...
        beqz  a0, osn_dd                ; ...
        ld    t0, rkey(zero)            ; ...
        bne   t0, s3, osn_dd            ; ...
        call  relief                    ; ...
        li    t0, 1                     ; (the pending tree's own pages: no snapshot's)
        sd    t0, in_rel(zero)          ; ...
        la    a0, t_pend                ; ...
        la    a1, rkey                  ; ...
        li    a2, 16                    ; ...
        call  st_del                    ; ...
        sd    zero, in_rel(zero)        ; ...
        ld    a0, rkey+8(zero)          ; ...
        call  bswap                     ; ...
        ld    a1, dval(zero)            ; the pages, as their namespace's again
        srli  t0, a1, 32                ; ...
        sd    t0, st_owner(zero)        ; ...
        lwu   a1, dval(zero)            ; ...
        ld    a2, dval+8(zero)          ; ...
        call  pfree                     ; ...
        j     osn_dl                    ; ...
osn_dd:
        li    t0, 1                     ; that is recorded by the rule of the one before;
        sd    t0, in_rel(zero)          ; everything else by the newest one's
        call  drain_fr                  ; ...
        sd    zero, in_rel(zero)        ; ...
        sd    s5, st_deadlim(zero)      ; ...
        mv    a0, s1                    ; its record goes
        call  bswap                     ; ...
        sd    a0, rkey(zero)            ; ...
        ld    a0, x_snap(zero)          ; ...
        la    a1, rkey                  ; ...
        li    a2, 8                     ; ...
        call  st_del                    ; ...
        call  st_commit                 ; ...
        j     ok                        ; ...
osn_list:
        li    s3, 0                     ; s3 = records
        la    s5, sys_buf               ; ...
        sd    zero, rkey(zero)          ; ...
osn_l:
        li    t0, 100                   ; ...
        bgeu  s3, t0, osn_ld            ; ...
        la    a0, tnbuf                 ; (a record is 16 bytes and the name: the rest
        li    a1, 48                    ;   of the name field stays zero)
        call  wzero                     ; ...
        ld    a0, x_snap(zero)          ; ...
        la    a1, rkey                  ; ...
        li    a2, 8                     ; ...
        li    a3, ST_GT                 ; ...
        la    a4, rkey                  ; ...
        la    a5, tnbuf                 ; ...
        call  st_seek                   ; ...
        beqz  a0, osn_ld                ; ...
        ld    a0, rkey(zero)            ; ...
        call  bswap                     ; ...
        sd    a0, 0(s5)                 ; ...
        addi  a0, s5, 8                 ; ...
        la    a1, tnbuf + 16            ; (zero-padded to 32 above)
        li    a2, 32                    ; ...
        call  wcopy                     ; ...
        addi  s5, s5, 40                ; ...
        addi  s3, s3, 1                 ; ...
        j     osn_l                     ; ...
osn_ld:
        mv    a0, s3                    ; ...
        la    a1, sys_buf               ; ...
        sub   a2, s5, a1                ; ...
        j     reply_data                ; ...

; ---- restoring a snapshot ------------------------------------------------------------
; The trees named become what the snapshot shows: they take the snapshot's
; roots. (The snapshots stay, the one restored too; other trees are not
; touched.) Two things keep the pages right:
;   - what only the state given up used is freed: its pages born after the
;     snapshot (a page born before it is the snapshot's too; and since a
;     page's children are never younger than it, such a page ends the walk);
;   - what the snapshot shows and the state given up had dropped is in use
;     again: those pages (the namespace's, born no later than the snapshot,
;     on the dead list of it or of a later one) leave the dead lists.

; drop_tree(a0 = a tree, a1 = 1: its records are extents, to be freed with
; it): its pages born after commit s1 are freed (s1 is the caller's)
drop_tree:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s2, 8(sp)                 ; ...
        sd    s3, 16(sp)                ; ...
        sd    s4, 24(sp)                ; ...
        sd    s5, 32(sp)                ; ...
        mv    s5, a1                    ; s5 = extents?
        ld    t0, 0(a0)                 ; ...
        beqz  t0, dt_ret                ; ...
        li    s2, 0                     ; s2 = the level (times 16)
        sd    t0, wpath(zero)           ; (no tree change is under way: its path serves)
        sd    zero, wpath+8(zero)       ; ...
dt_l:
        call  relief                    ; (the lists of freed pages are written out as they fill)
        ld    a0, wpath(s2)             ; ...
        call  P                         ; ...
        mv    s3, a0                    ; s3 = the page
        ld    s4, 16(s3)                ; s4 = its birth
        bleu  s4, s1, dt_up             ; the snapshot's too: so is all below it
        lbu   t0, 24(s3)                ; ...
        li    t1, K_LEAF                ; ...
        beq   t0, t1, dt_leaf           ; ...
        ld    a1, wpath+8(s2)           ; a branch: its next child, or it is done
        lhu   t0, 26(s3)                ; ...
        bgeu  a1, t0, dt_free           ; ...
        addi  t0, a1, 1                 ; ...
        sd    t0, wpath+8(s2)           ; ...
        call  child                     ; ...
        addi  s2, s2, 16                ; ...
        sd    a0, wpath(s2)             ; ...
        sd    zero, wpath+8(s2)         ; ...
        j     dt_l                      ; ...
dt_leaf:
        beqz  s5, dt_free               ; extents born after the snapshot go with it
        ld    a1, wpath+8(s2)           ; ...
        lhu   t0, 26(s3)                ; ...
        bgeu  a1, t0, dt_free           ; ...
        addi  t0, a1, 1                 ; ...
        sd    t0, wpath+8(s2)           ; ...
        slli  a1, a1, 1                 ; its cell: key 16 bytes, value {start, pages, birth}
        add   a1, a1, s3                ; ...
        lhu   a1, 32(a1)                ; ...
        add   a1, a1, s3                ; ...
        ld    a2, 40(a1)                ; ...
        bleu  a2, s1, dt_l              ; ...
        ld    t0, fs_ns(zero)           ; ...
        sd    t0, st_owner(zero)        ; ...
        ld    a0, 24(a1)                ; ...
        ld    a1, 32(a1)                ; ...
        call  pfree                     ; ...
        j     dt_l                      ; ...
dt_free:
        ld    t0, fs_ns(zero)           ; ...
        sd    t0, st_owner(zero)        ; ...
        ld    a0, wpath(s2)             ; the page itself
        li    a1, 1                     ; ...
        mv    a2, s4                    ; ...
        call  pfree                     ; ...
dt_up:
        beqz  s2, dt_ret                ; ...
        addi  s2, s2, -16               ; ...
        j     dt_l                      ; ...
dt_ret:
        ld    s5, 32(sp)                ; ...
        ld    s4, 24(sp)                ; ...
        ld    s3, 16(sp)                ; ...
        ld    s2, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 40                ; ...
        ret                             ; ...

osn_rest:
        call  get_data                  ; {u64 name length, name[32], u64 count, handles}
        li    t0, 48                    ; ...
        bltu  a1, t0, bad               ; ...
        ld    s2, 0(a0)                 ; s2 = the name's length
        blez  s2, bad                   ; ...
        li    t0, 32                    ; ...
        bgtu  s2, t0, bad               ; ...
        ld    s3, 40(a0)                ; s3 = trees
        beqz  s3, bad                   ; ...
        slli  t0, s3, 3                 ; ...
        addi  t0, t0, 48                ; ...
        bgtu  t0, a1, bad               ; ...
        addi  a0, a0, 48                ; ...
        mv    a1, s3                    ; ...
        call  live_handles              ; ...
        la    t0, rqd                   ; the namespace: the first tree's
        ld    t0, 48(t0)                ; ...
        lwu   t0, TT_KEY(t0)            ; (big-endian in the key)
        mv    a0, t0                    ; ...
        call  bswap                     ; ...
        srli  a0, a0, 32                ; ...
        sd    a0, fs_ns(zero)           ; ...
        la    a0, rbuf                  ; the snapshot
        la    a1, rqd + 8               ; ...
        mv    a2, s2                    ; ...
        call  srv_bcopy                 ; ...
        la    a0, rbuf                  ; ...
        mv    a1, s2                    ; ...
        call  snap_find                 ; ...
        mv    s1, a0                    ; s1 = its commit
        beqz  s1, nofile                ; ...
        mv    a0, s1                    ; its roots -> sx
        la    a1, rqd + 48              ; ...
        mv    a2, s3                    ; ...
        call  snap_roots                ; ...
        bltz  a0, nofile                ; ...
        call  begin                     ; ...
        li    s2, 0                     ; every tree: what only the live state used goes,
osr_t:
        slli  t0, s2, 3                 ; ...
        la    t1, rqd + 48              ; ...
        add   t0, t0, t1                ; ...
        ld    s4, 0(t0)                 ; s4 = the live tree
        mv    a0, s4                    ; ...
        addi  a1, s2, 1                 ; (the last is the extents' tree)
        sub   a1, a1, s3                ; ...
        seqz  a1, a1                    ; ...
        call  drop_tree                 ; ...
        slli  t1, s2, 4                 ; and it takes the snapshot's root
        la    t0, sx                    ; ...
        add   t1, t1, t0                ; ...
        ld    t2, 0(t1)                 ; ...
        sd    t2, 0(s4)                 ; ...
        ld    t2, 8(t1)                 ; ...
        sd    t2, 8(s4)                 ; ...
        addi  s2, s2, 1                 ; ...
        bne   s2, s3, osr_t             ; ...
        li    s3, 1                     ; the dead lists of this snapshot and the later ones:
        slli  s3, s3, 63                ; what was born no later than it is in use again
        or    a0, s3, s1                ; ...
        call  bswap                     ; ...
        sd    a0, rkey(zero)            ; ...
        sd    zero, rkey+8(zero)        ; ...
osr_d:
        la    a0, t_pend                ; ...
        la    a1, rkey                  ; ...
        li    a2, 16                    ; ...
        li    a3, ST_GT                 ; ...
        la    a4, rkey                  ; ...
        la    a5, dval                  ; ...
        call  st_seek                   ; ...
        beqz  a0, ok                    ; ...
        ld    t0, dval+8(zero)          ; ...
        bgtu  t0, s1, osr_d             ; ...
        ld    t0, dval(zero)            ; (the namespace's own pages only: the catalog's
        srli  t0, t0, 32                ; old pages are the snapshots' still)
        ld    t1, fs_ns(zero)           ; ...
        bne   t0, t1, osr_d             ; ...
        li    t0, 1                     ; ...
        sd    t0, in_rel(zero)          ; ...
        la    a0, t_pend                ; ...
        la    a1, rkey                  ; ...
        li    a2, 16                    ; ...
        call  st_del                    ; ...
        sd    zero, in_rel(zero)        ; ...
        j     osr_d                     ; ...

; =============================================================================
; The boot manifest
; =============================================================================
;
; The kernel loads the first servers before any server runs: it reads no
; tree, only the boot manifest, a page the meta block points at: a header as
; a tree page's (kind 3), "STBOOTMF" at 32, a u32 count at 40, and from 64
; entries of {name[16], u64 first page, u64 bytes}, each object in one run
; of pages. Which values are boot objects is the client's to say (fs: the
; files with the boot flag).

; BOOT: handle = the data tree | the extents' tree << 16, data = {u64 the key
; (8 bytes) of a value to make one run (0: none), u64 count, count entries
; {name[16], u64 key, u64 size}} -> 0: the manifest anew, at a new page, in
; the commit under way (not committed here)
op_boot:
        call  get_data                  ; ...
        li    t0, 16                    ; ...
        bltu  a1, t0, bad               ; ...
        ld    t1, 8(a0)                 ; all the entries there?
        slli  t2, t1, 5                 ; ...
        addi  t2, t2, 16                ; ...
        bgtu  t2, a1, bad               ; ...
        li    t2, 64                    ; (a page holds the header and 126 at least)
        bgtu  t1, t2, bad               ; ...
        la    t0, srv_hdr               ; the trees
        ld    t1, 8(t0)                 ; ...
        srli  a0, t1, 16                ; ...
        li    t2, 0xffff                ; ...
        and   a0, a0, t2                ; ...
        sd    a0, bl_ext(zero)          ; ...
        call  handle_ok                 ; ...
        beqz  a0, bad                   ; ...
        call  req_tree                  ; s1 = the data tree
        la    t0, rqd                   ; a value to make one run?
        ld    t0, 0(t0)                 ; ...
        beqz  t0, bfx_man               ; ...
        sd    t0, vkey(zero)            ; ...
        mv    a0, s1                    ; ...
        la    a1, vkey                  ; ...
        li    a2, 8                     ; ...
        call  st_bsize                  ; ...
        ld    t0, bl_fl(zero)           ; a stream already?
        bltz  a0, bfx_in                ; (none: an empty one is made)
        bnez  t0, bfx_one               ; ...
bfx_in:
        mv    s2, a0                    ; inline (or none): written again as a stream
        bgez  s2, bfx_c                 ; ...
        li    s2, 0                     ; ...
bfx_c:
        la    a0, sys_buf               ; ...
        la    a1, bval                  ; ...
        addi  a2, s2, 7                 ; ...
        srli  a2, a2, 3                 ; ...
        slli  a2, a2, 3                 ; ...
        call  wcopy                     ; ...
        mv    a0, s1                    ; ...
        la    a1, vkey                  ; ...
        li    a2, 8                     ; ...
        call  st_bdel                   ; ...
        li    t0, 1                     ; ...
        sd    t0, bw_force(zero)        ; ...
        mv    a0, s1                    ; ...
        la    a1, vkey                  ; ...
        li    a2, 8                     ; ...
        li    a3, 0                     ; ...
        la    a4, sys_buf               ; ...
        mv    a5, s2                    ; ...
        call  st_bwrite                 ; ...
        sd    zero, bw_force(zero)      ; ...
        mv    a0, s1                    ; ...
        la    a1, vkey                  ; ...
        li    a2, 8                     ; ...
        call  st_bsize                  ; ...
bfx_one:
        ld    s2, bval+8(zero)          ; s2 = the stream
        ld    t0, st_ps(zero)           ; s3 = its pages
        add   s3, a0, t0                ; ...
        addi  s3, s3, -1                ; ...
        ld    t0, st_ps(zero)           ; (the page size's log2)
        li    t1, 0                     ; ...
bfx_sh:
        srli  t0, t0, 1                 ; ...
        beqz  t0, bfx_shd               ; ...
        addi  t1, t1, 1                 ; ...
        j     bfx_sh                    ; ...
