        srl   s3, s3, t1                ; ...
        beqz  s3, bfx_man               ; ...
        mv    a0, s2                    ; one extent from its start holding them all?
        li    a1, 0                     ; ...
        call  ext_find                  ; ...
        beqz  a0, bfx_move              ; ...
        ld    t0, e_pages(zero)         ; ...
        bgeu  t0, s3, bfx_man           ; ...
bfx_move:
        mv    a0, s3                    ; no: a run of that many pages, the contents copied
        li    a1, 0                     ; into it page by page, the old pages freed
        call  alloc                     ; ...
        mv    s4, a0                    ; s4 = the run
        bne   a1, s3, st_full           ; (no such run on the disk)
