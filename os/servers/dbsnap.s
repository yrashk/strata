        addi  a1, s2, 16                ; ...
        li    a2, 8                     ; ...
        call  st_bsize                  ; ...
        li    s5, 0                     ; s5 = the first page (none: empty)
        blez  a0, bfx_e                 ; ...
        ld    a0, bval+8(zero)          ; ...
        li    a1, 0                     ; ...
        call  ext_find                  ; ...
        beqz  a0, bfx_e                 ; ...
        ld    s5, e_start(zero)         ; ...
bfx_e:
        mv    a0, s3                    ; its entry in the manifest
        call  PW                        ; ...
        slli  t0, s4, 5                 ; ...
        add   t1, a0, t0                ; ...
        addi  t1, t1, 64                ; ...
        addi  s4, s4, 1                 ; ...
        sw    s4, 40(a0)                ; ...
        ld    t0, 0(s2)                 ; the name
        sd    t0, 0(t1)                 ; ...
        ld    t0, 8(s2)                 ; ...
        sd    t0, 8(t1)                 ; ...
        sd    s5, 16(t1)                ; ...
        ld    t0, 24(s2)                ; the size
        sd    t0, 24(t1)                ; ...
        addi  s2, s2, 32                ; ...
        j     bfx_l                     ; ...
bfx_end:
        ld    s2, st_manif(zero)        ; the old manifest's page is free
        sd    s3, st_manif(zero)        ; ...
        beqz  s2, ok                    ; ...
        mv    a0, s2                    ; ...
