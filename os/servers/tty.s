; =============================================================================
; tty.s: the console server
; =============================================================================
;
; A user-mode server (started by proc at boot, alone on its core). It owns the
; console device: output, input, the break port (Ctrl-C), and the pointer
; (mouse), whose events it hands to the window server: device reads that
; wait belong on a core no other process shares. It asks dev for windows on
; the console's and the pointer's ports at start.
;
; It never blocks on the device: reads stay in flight while it waits for
; requests, the break port (tag 1) always, and one byte of console input (tag
; 2) while a reader waits, and svc RECEIVE wakes it when either completes (a1
; = the idle tags). Input is not read (nor echoed) before a program asks.
;
;   1 READ   handle 0 (the console), length, mode bit0 = do not block.
;            Cooked mode: input is echoed and edited (Backspace); a READ
;            returns one line (with its newline), or what was typed before
;            Ctrl-D (0x04); 0 = end of input. Raw mode: no echo, whatever is
;            there (at least one byte), in whole keys: an escape sequence
;            (ESC [ ... final, ESC O x) is never cut between two READs, by
;            the length asked for or by its bytes coming one at a time. One
;            begun at the end of what came (an ESC, ESC [ 1 ;) waits for its
;            rest, T_HOLD at most with no byte coming: then it goes as it
;            is (an ESC alone is the Esc key). A READ that does not block
;            and finds nothing (-3) has one byte read ahead, so a reader
;            that polls (vi telling Esc from an arrow's ESC [ A) gets it. CR
;            becomes LF in both.
;            Mode bit1 = pointer events too (raw mode, ws): the READ is also
;            answered when pointer events wait; the answer's mode field says
;            how many (0..8), and they follow the data at offset 32 of it, 8
;            bytes each as the device gives them (platform.h: u16 x, u16 y,
;            u8 buttons, s8 wheel y, s8 wheel x, u8 kind); the result is the
;            number of key bytes (32 at most), which may then be 0 (not the
;            end of input). An answer with data, or the end of input, has
;            mode 0 when no events come with it (no pointer, or bit1 clear).
;   2 WRITE  data to the console
;   4 CLOSE  0 (the console is never closed)
;  18 SETFG  handle = pid: Ctrl-C now interrupts that process
;  19 CONMODE handle = 0 cooked, 1 raw
;  20 ATTACH handle = a guest id: the console's input goes to that guest
;            (below); answered when it comes back to StrataOS, with 0 (Ctrl-]
;            was typed), 1 (the guest closed the console), 2 (the guest was
;            stopped) or -2 (the attaching process was interrupted); -7 if the
;            console is attached already, -1 if the requester is a guest or
;            the id is not a guest's
;  36 DUPS / 37 CLEANUP / 38 CANCEL from proc
;
; Console rings (doc/strataos.md 2.3). The kernel gives every StrataOS
; program that is not a server a ring in T2 at its start (in c6): one per
; arena slot, after the KST, all of them lent to this server once (RINGS from
; dev, kept in c4). The program's library fills its ring with records
; (os/lib/chan.s) instead of sending WRITEs. Before acting on any request the
; server writes out every ring, so a process's bytes come out before
; whatever it asks next (a READ after a prompt), and before proc learns of
; its end (CLEANUP). Between requests it looks at the rings every RPOLL
; ticks, RPOLLS times after the last output; then it sets every ring's SLEEP
; word and waits for requests only, and a writer that sees SLEEP wakes it
; with an empty WRITE. A WRITE whose mode has bit 1 set (the writer's c6 is
; free again: something replaced its ring) is answered with a copy of its
; ring (found by the owner word the kernel writes). Rings are never revoked;
; positions only grow, so the server keeps each ring's TAIL itself and reads
; one word (HEAD) per ring in use to see whether it holds anything; lengths
; and positions in a ring are checked, never trusted. Guests get no ring.
;
; Guests (doc/strataos.md, "Guests"). A guest OS talks to the console with the
; same READ and WRITE through its console endpoint; its requests carry its
; guest id (240..255) as their pid. Output is written as anyone's. Input goes
; to one side at a time: while the console is ATTACHed to a guest (the `guest`
; command does it, and waits), only that guest's READs are answered and the
; READs of StrataOS's processes wait; otherwise only StrataOS's are, and a
; guest's READ waits until the console is attached to it. Input is read only
; while a reader that may have it waits, so nothing typed for one side reaches
; the other. The console comes back to StrataOS (the ATTACH is answered) when
; Ctrl-] is typed, when the guest CLOSEs the console (Forth's BYE), when the
; guest is stopped (proc's CLEANUP for its id), and when the attaching process
; is interrupted (CANCEL: Ctrl-C) or ends (CLEANUP).
GUEST_ID0 = 240                         ; guest ids: 240.. (process pids are below)
;
; Ctrl-C: "^C" is echoed, a partial line is dropped, and proc is asked to
; SIGNAL the foreground process. The tty does not wait for proc's answer
; (proc may itself be calling the tty): its buffer comes back later, and a
; Ctrl-C while one is still outstanding is not sent again.
;
; Halting: `halt` waits for a core's pending device reads. The break read is
; armed again after a Ctrl-C (it reads 3) but not after a release (it reads
; 0): the kernel writes the release port once every core's dispatcher has
; stopped its processes (u_halt), so this core can halt. The same write
; completes an input read still in flight (a reader was waiting for a key;
; it reads 0), and the pointer's EVENT read is completed by the kernel's
; write to that port (it reads 0: not armed again).

CON_OUT  = 0x00                         ; console ports (offsets in the window)
CON_IN   = 0x08                         ; ...
CON_BRK  = 0x10                         ; ...
TG_BRK   = 1                            ; transfer tag of the break read
TG_IN    = 2                            ; transfer tag of the input read
TG_PTR   = 4                            ; transfer tag of the pointer's EVENT read (tg5: STATE)
PQMAX    = 8                            ; pointer events kept for the reader
NWAIT    = 8                            ; waiting readers
LMAX     = 255                          ; longest cooked line
RMAX     = 1024                         ; input ready for readers
NRING    = 64                           ; console rings (c4: a header of RHDR, then the rings)
RHDR     = 64                           ; (the header's first word: rings in use so far)
RPOLL    = 500                          ; ticks between looks at the rings while output flows
RPOLLS   = 20                           ; looks after the last output before sleeping
T_HOLD   = 50000                        ; ticks an escape sequence's start waits for its rest

        .data                           ; data Local Store
        .align 8                        ; ...
brkb:   .space 8                        ; the break byte
brkarm: .dword 0                        ; 1 << TG_BRK while the break read is in flight
inb:    .space 8                        ; the input byte
ptrb:   .space 8                        ; a pointer event
ptrst:  .space 8                        ; the pointer's STATE
ptrarm: .dword 0                        ; 1 << TG_PTR while the EVENT read is in flight
ptron:  .dword 0                        ; 1: there is a pointer (c3 = its ports)
ptrwant: .dword 0                       ; 1: a reader has asked for its events (read it)
ptroff: .dword 0                        ; 1: released (the machine is halting): read no more
rdptr:  .dword 0                        ; the reader being answered wants pointer events
pqn:    .dword 0                        ; pointer events queued
pq:     .space PQMAX * 8                ; ... the events
bounce: .space 4096                     ; staging for output / reads
lbuf:   .space 256                      ; the cooked line being edited
llen:   .dword 0                        ; its length
rbuf:   .space RMAX                     ; input ready for readers
rlen:   .dword 0                        ; bytes in it
rlines: .dword 0                        ; complete units in it (lines, or EOF marks)
eofs:   .dword 0                        ; end-of-input marks pending (each answers one READ with 0)
rawm:   .dword 0                        ; 1 = raw mode
fgpid:  .dword 1                        ; the foreground process
inarm:  .dword 0                        ; the input read is in flight
waitq:  .space NWAIT * 32               ; waiting readers: park id + 1, token, pid, length
gatt:   .dword 0                        ; the guest id the console's input goes to (0: StrataOS)
gapark: .dword 0                        ; the ATTACH request waiting for the console back: park id + 1
gatok:  .dword 0                        ; ... its token
gapid:  .dword 0                        ; ... and its sender
rdok:   .dword 0                        ; the reader being asked about may have input now
rtail:  .space NRING * 8                ; each ring's TAIL (only this server moves it)
rsz:    .dword 0                        ; a ring's size (0: no rings)
rawake: .dword 0                        ; looks at the rings left before sleeping
rslept: .dword 0                        ; 1: the rings' SLEEP words are set
rtmo:   .dword -1                       ; the next RECEIVE's timeout (the rings')
rtmx:   .dword -1                       ; ... with the hold's
rheld:  .dword 0                        ; 1: raw input ends in a sequence's start, held back
rhdl:   .dword 0                        ; ... until then (NOW; 0: not timed yet)
rlook:  .dword 0                        ; 1: the deadline passed, one more look for a byte
rrel:   .dword 0                        ; 1: it goes as it is (no byte came in time)
s_ctlb: .ascii "^]\n"                   ; echo of Ctrl-]
s_ctlc: .ascii "^C\n"                   ; echo of Ctrl-C
s_bs:   .ascii "\x08 \x08"              ; erase a character
s_ndev: .ascii "dev"                    ; the device manager's name

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        call  sys_init                  ; ...
        li    a0, 2                     ; dev (c2): a window on the pointer
        li    a1, 21                    ; GETPTR
        li    a2, 0                     ; ...
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        call  sys_msg                   ; -> c6, or -1: none
        bnez  a0, m_con                 ; ...
        cclear c3                       ; c3 = the pointer's ports
        cmov  c3, c6                    ; ...
        cclear c6                       ; ...
        la    t0, ptron                 ; ...
        li    t1, 1                     ; ...
        sd    t1, 0(t0)                 ; ...
m_con:
        li    a0, 2                     ; the console rings, from dev (RINGS) -> c4
        li    a1, 46                    ;   (no pipes are used here)
        li    a2, 0                     ; ...
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        call  sys_msg                   ; ...
        bnez  a0, m_nor                 ; none
        cclear c4                       ; ...
        cmov  c4, c6                    ; ...
        clen  t0, c4                    ; a ring's size
        addi  t0, t0, -RHDR             ; ...
        srli  t0, t0, 6                 ; (NRING = 64)
        la    t1, rsz                   ; ...
        sd    t0, 0(t1)                 ; ...
m_nor:
        li    a0, 2                     ; dev (c2): a window on the console
        li    a1, 31                    ; GETCON
        li    a2, 0                     ; ...
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        call  sys_msg                   ; -> c6
        cclear c2                       ; the dev endpoint is no longer needed:
        cmov  c2, c6                    ; c2 = the console window
        cperms t0, c2                   ; an endpoint instead: a guest StrataOS, whose
        srli  t0, t0, 8                 ;   console is the host's tty (g_loop)
        li    t1, 6                     ; ...
        beq   t0, t1, g_main            ; ...
        call  arm_brk                   ; the break read
        la    a0, loop                  ; a fault on a dead request returns to the loop
        call  srv_guard                 ; ...
loop:
        call  ring_tick                 ; the rings: write them out, decide the timeout
        call  ptr_arm                   ; the pointer's EVENT read, if wanted
        call  hold_tick                 ; a held sequence's start: a0 = its timeout
        la    t0, rtmo                  ; the sooner of it and the rings'
        ld    t1, 0(t0)                 ; ...
        bltz  a0, lp_t                  ; (no hold)
        bltz  t1, lp_h                  ; (no look at the rings)
        bgeu  a0, t1, lp_t              ; ...
lp_h:
        mv    t1, a0                    ; ...
lp_t:
        la    t0, rtmx                  ; ...
        sd    t1, 0(t0)                 ; ...
        la    t0, brkarm                ; wait for: requests, the break port (while
        ld    a0, 0(t0)                 ;   its read is in flight: brkarm = 1 << TG_BRK),
        la    t0, inarm           ; (its address)
        ld    t0, 0(t0)              ; and input if a read is in flight
        beqz  t0, lp_r                  ; ...
        ori   a0, a0, 1 << TG_IN        ; ...
lp_r:
        la    t0, ptrarm                ; and the pointer while its read is in flight
        ld    t0, 0(t0)                 ; ...
        or    a0, a0, t0                ; ...
        la    a1, rtmx                  ; a timeout while the rings are looked at, or
        ld    a1, 0(a1)                 ;   a sequence's start is held
        call  srv_recv                  ; ...
        bgez  a0, request               ; a request
        li    t0, -1                    ; device tags?
        bne   a0, t0, loop              ; (no)
        mv    s1, a1                    ; s1 = idle tags
        andi  t0, s1, 1 << TG_BRK       ; the break port?
        beqz  t0, lp_in                 ; ...
        la    t0, brkarm                ; (only if its read was in flight)
        ld    t1, 0(t0)                 ; ...
        beqz  t1, lp_in                 ; ...
        sd    zero, 0(t0)               ; it completed
        la    t1, brkb            ; (its address)
        lbu   t1, 0(t1)              ; 3 = Ctrl-C (0 = a release)
        li    t2, 3                     ; ...
        bne   t1, t2, lp_in             ; a release: the kernel is halting the machine, and
        call  ctrl_c                    ;   `halt` waits for pending reads: do not read again
        call  arm_brk                   ; Ctrl-C: read it again
lp_in:
        andi  t0, s1, 1 << TG_PTR       ; a pointer event?
        beqz  t0, lp_in2                ; ...
        la    t0, ptrarm                ; (only if its read was in flight)
        ld    t1, 0(t0)                 ; ...
        beqz  t1, lp_in2                ; ...
        sd    zero, 0(t0)               ; it completed
        call  ptr_in                    ; queue it (and what else waits), answer the reader
lp_in2:
        andi  t0, s1, 1 << TG_IN        ; input?
        beqz  t0, loop                  ; ...
        la    t0, inarm           ; (its address)
        ld    t0, 0(t0)              ; (only if one was in flight)
        beqz  t0, loop                  ; ...
        la    t0, inarm                 ; it completed
        sd    zero, 0(t0)               ; ...
        la    a0, inb             ; (its address)
        lbu   a0, 0(a0)              ; the byte
        call  input                     ; line discipline
        call  serve_waiters             ; answer readers that can be answered
        call  maybe_arm                 ; read more if there is room
        j     loop                      ; ...

; ---- device reads ------------------------------------------------------------------------
arm_brk:
        la    t0, brkb                  ; one byte from the break port
        li    t1, CON_BRK               ; ...
        li    t2, 1                     ; ...
        tget  tg1, t0, c2, t1, t2       ; completes when Ctrl-C is pressed
        la    t0, brkarm                ; in flight
        li    t1, 1 << TG_BRK           ; ...
        sd    t1, 0(t0)                 ; ...
        ret                             ; ...
arm_in:
        la    t0, inb                   ; one byte of input
        li    t1, CON_IN                ; ...
        li    t2, 1                     ; ...
        tget  tg2, t0, c2, t1, t2       ; completes when a key arrives
        la    t0, inarm                 ; ...
        li    t1, 1                     ; ...
        sd    t1, 0(t0)                 ; ...
        ret                             ; ...
; ptr_arm(): the pointer's EVENT read, while there is a pointer, a reader has
; asked for its events, the queue has room and the machine is not halting
ptr_arm:
        la    t0, ptrarm                ; already in flight?
        ld    t1, 0(t0)                 ; ...
        bnez  t1, pa_no                 ; ...
        ld    t1, ptron - ptrarm(t0)    ; a pointer?
        beqz  t1, pa_no                 ; ...
        ld    t1, ptrwant - ptrarm(t0)  ; wanted?
        beqz  t1, pa_no                 ; ...
        ld    t1, ptroff - ptrarm(t0)   ; released?
        bnez  t1, pa_no                 ; ...
        ld    t1, pqn - ptrarm(t0)      ; room?
        li    t2, PQMAX                 ; ...
        bgeu  t1, t2, pa_no             ; ...
        li    t1, 1 << TG_PTR           ; in flight from now on
        sd    t1, 0(t0)                 ; ...
        la    t0, ptrb                  ; EVENT: completes when the pointer does something
        li    t1, 8                     ; ...
        tget  tg4, t0, c3, zero, t1     ; ...
pa_no:
        ret                             ; ...

; ptr_in(): the EVENT read completed: queue the event and every event the
; device still holds (STATE says how many: those reads complete at once),
; then answer a reader that wants them
ptr_in:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        la    t0, ptrb                  ; the event
        lbu   t1, 7(t0)                 ; its kind
        bnez  t1, pi_q                  ; ...
        la    t0, ptroff                ; 0: a release (the kernel is halting the
        li    t1, 1                     ;   machine): do not read again
        sd    t1, 0(t0)                 ; ...
        j     pi_ret                    ; ...
pi_q:
        ld    a0, 0(t0)                 ; queue it
        call  pq_push                   ; ...
pi_more:
        la    t0, pqn                   ; room for more?
        ld    t0, 0(t0)                 ; ...
        li    t1, PQMAX                 ; ...
        bgeu  t0, t1, pi_ans            ; ...
        la    t0, ptrst                 ; STATE: byte 5 = events the device holds
        li    t1, 8                     ; ...
        li    t2, 8                     ; ...
        tget  tg5, t0, c3, t1, t2       ; ...
        twait 1 << 5                    ; ...
        lbu   t1, 5(t0)                 ; ...
        beqz  t1, pi_ans                ; none
        la    t0, ptrb                  ; the next one (there: completes at once)
        li    t1, 8                     ; ...
        tget  tg5, t0, c3, zero, t1     ; ...
        twait 1 << 5                    ; ...
        ld    a0, 0(t0)                 ; ...
        call  pq_push                   ; ...
        j     pi_more                   ; ...
pi_ans:
        call  serve_waiters             ; a reader that wants them
pi_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; (the loop reads again: ptr_arm)

; pq_push(a0 = event): a move after a move replaces it (only where the
; pointer is now matters); with no room the event is dropped
pq_push:
        la    t0, pqn                   ; ...
        ld    t1, 0(t0)                 ; ...
        la    t2, pq                    ; ...
        beqz  t1, pp_add                ; empty
        srli  t3, a0, 56                ; a move?
        li    t4, 1                     ; ...
        bne   t3, t4, pp_add            ; ...
        slli  t3, t1, 3                 ; after a move?
        add   t3, t2, t3                ; ...
        ld    t4, -8(t3)                ; ...
        srli  t4, t4, 56                ; ...
        li    t5, 1                     ; ...
        bne   t4, t5, pp_add            ; ...
        sd    a0, -8(t3)                ; replace it
        ret                             ; ...
pp_add:
        li    t3, PQMAX                 ; room?
        bgeu  t1, t3, pp_ret            ; ...
        slli  t3, t1, 3                 ; ...
        add   t3, t2, t3                ; ...
        sd    a0, 0(t3)                 ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, 0(t0)                 ; ...
pp_ret:
        ret                             ; ...

; ptr_give(): the answer's mode field = how many pointer events follow the
; data at 32, for a reader that wants them (rdptr); 0 for any other
ptr_give:
        la    t2, srv_hdr               ; (none)
        sd    zero, 24(t2)              ; ...
        la    t0, rdptr                 ; wanted?
        ld    t0, 0(t0)                 ; ...
        beqz  t0, pg_ret                ; ...
        la    t0, pqn                   ; how many
        ld    t1, 0(t0)                 ; ...
        sd    zero, 0(t0)               ; (all of them go)
        la    t2, srv_hdr               ; -> the mode field
        sd    t1, 24(t2)                ; ...
        beqz  t1, pg_ret                ; ...
        slli  t1, t1, 3                 ; the events -> the request's data at 32
        la    t0, pq                    ; ...
        li    t2, 64 + 32               ; ...
        tput  tg10, t0, c6, t2, t1      ; (srv_reply waits for tg10)
pg_ret:
        ret                             ; ...

; maybe_arm(): read input again unless readers have plenty waiting or an end is pending
maybe_arm:
        la    t0, inarm                 ; already?
        ld    t0, 0(t0)                 ; ...
        bnez  t0, ma_no                 ; ...
        la    t3, waitq                 ; only while a reader waits that may have input
        li    t4, NWAIT                 ;   (its side, guest or StrataOS, has the console):
ma_w:                                   ;   input is not read (nor echoed) ahead of the
        beqz  t4, ma_no                 ;   program that wants it. Nobody waits
        ld    t2, 0(t3)                 ; ...
        beqz  t2, ma_wn                 ; ...
        ld    a0, 16(t3)                ; its pid
        mv    t5, ra                    ; (elig is a leaf: t0, a0)
        call  elig                      ; ...
        mv    ra, t5                    ; ...
        bnez  a0, ma_rd                 ; someone does
ma_wn:
        addi  t3, t3, 32                ; ...
        addi  t4, t4, -1                ; ...
        j     ma_w                      ; ...
ma_rd:
        la    t0, eofs            ; (its address)
        ld    t0, 0(t0)              ; an end of input not yet taken by a reader:
        bnez  t0, ma_no                 ;   (the device returns 0x04 forever at the end)
        la    t0, rlen            ; (its address)
        ld    t0, 0(t0)              ; room?
        li    t1, RMAX - 2              ; ...
        bgeu  t0, t1, ma_no             ; ...
        j     arm_in                    ; ...
ma_no:
        ret                             ; ...

; out(a0 = address, a1 = length): to the console
out:
        beqz  a1, out_r                 ; ...
        li    t0, CON_OUT               ; ...
        tput  tg3, a0, c2, t0, a1       ; ...
        twait 1 << 3                    ; (the caller may reuse the bytes)
out_r:
        ret                             ; ...

; ---- console rings ---------------------------------------------------------------------------
; ring_tick(): at the top of the loop: write the rings out, and set rtmo: a
; look again in RPOLL ticks while output flows, else (SLEEP set in every
; ring, and a last look) no timeout
ring_tick:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        call  rings_out                 ; ...
        la    t0, rawake                ; looking still?
        ld    t1, 0(t0)                 ; ...
        beqz  t1, rt_sleep              ; no
        addi  t1, t1, -1                ; one look fewer
        sd    t1, 0(t0)                 ; ...
        li    a1, 0                     ; the writers need not wake us
        call  rings_sleep               ; ...
        li    t1, RPOLL                 ; ...
        j     rt_set                    ; ...
rt_sleep:
        li    a1, 1                     ; SLEEP in every ring, then one more look
        call  rings_sleep               ; ...
        call  rings_out                 ; ...
        la    t0, rawake                ; anything (it woke us up again)?
        ld    t1, 0(t0)                 ; ...
        beqz  t1, rt_none               ; no
        li    a1, 0                     ; ...
        call  rings_sleep               ; ...
        li    t1, RPOLL                 ; ...
        j     rt_set                    ; ...
rt_none:
        li    t1, -1                    ; no timeout
rt_set:
        la    t0, rtmo                  ; ...
        sd    t1, 0(t0)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; rings_sleep(a1 = 0 or 1): every ring's SLEEP word (if it changes): all of
; them, so that a ring the kernel hands out meanwhile says so too
rings_sleep:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        la    t0, rsz                   ; no rings?
        ld    t0, 0(t0)                 ; ...
        beqz  t0, rsl_ret               ; ...
        la    t0, rslept                ; already so?
        ld    t1, 0(t0)                 ; ...
        beq   t1, a1, rsl_ret           ; ...
        sd    a1, 0(t0)                 ; ...
        mv    s2, a1                    ; ...
        cclear c10                      ; the rings (chan.s works through c10)
        cmov  c10, c4                   ; ...
        li    s1, 0                     ; ...
rsl_l:
        li    t0, NRING                 ; ...
        bge   s1, t0, rsl_c             ; ...
        mv    a0, s1                    ; ...
        call  ring_off                  ; ...
        mv    a1, s2                    ; ...
        call  chan_sleep                ; ...
        addi  s1, s1, 1                 ; ...
        j     rsl_l                     ; ...
rsl_c:
        cclear c10                      ; ...
rsl_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; ring_off(a0 = ring) -> a0 = its offset in c4 (t0, t1 only)
ring_off:
        la    t0, rsz                   ; ...
        ld    t0, 0(t0)                 ; ...
        mul   a0, a0, t0                ; ...
        addi  a0, a0, RHDR              ; ...
        ret                             ; ...

; rings_out(): every ring in use whose HEAD moved -> the console, lowest
; first; if there was anything, the rings are looked at RPOLLS more times
rings_out:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        la    t0, rsz                   ; no rings?
        ld    t0, 0(t0)                 ; ...
        beqz  t0, ro_ret                ; ...
        cclear c10                      ; ...
        cmov  c10, c4                   ; ...
        tamo.add s2, c10, zero, zero    ; s2 = rings in use (the header's first word)
        li    t0, NRING                 ; (checked)
        bleu  s2, t0, ro_go             ; ...
        mv    s2, t0                    ; ...
ro_go:
        li    s1, 0                     ; ...
ro_l:
        bge   s1, s2, ro_ret            ; ...
        mv    a0, s1                    ; its HEAD
        call  ring_off                  ; ...
        tamo.add t2, c10, a0, zero      ; ...
        la    t0, rtail                 ; = the TAIL we left it at?
        slli  t1, s1, 3                 ; ...
        add   t0, t0, t1                ; ...
        ld    t0, 0(t0)                 ; ...
        beq   t2, t0, ro_n              ; nothing new
        mv    a0, s1                    ; ...
        call  ring_out                  ; ...
        cclear c10                      ; ...
        cmov  c10, c4                   ; ...
ro_n:
        addi  s1, s1, 1                 ; ...
        j     ro_l                      ; ...
ro_ret:
        cclear c10                      ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; ring_out(a0 = ring): its records -> the console (a damaged ring is emptied)
ring_out:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        mv    s2, a0                    ; s2 = the ring
        call  ring_off                  ; s1 = its offset in c4
        mv    s1, a0                    ; ...
rou_l:
        cclear c10                      ; c10 = the rings (again: out may trap)
        cmov  c10, c4                   ; ...
        mv    a0, s1                    ; a record
        la    a1, rsz                   ; ...
        ld    a1, 0(a1)                 ; ...
        la    a2, bounce                ; ...
        mv    a3, a1                    ; ...
        call  chan_get                  ; a0 = its length, 0 none, -1 damaged; a1 = TAIL
        bltz  a0, rou_bad               ; ...
        la    t0, rtail                 ; TAIL as it is now
        slli  t1, s2, 3                 ; ...
        add   t0, t0, t1                ; ...
        sd    a1, 0(t0)                 ; ...
        beqz  a0, rou_ret               ; empty
        mv    a1, a0                    ; -> the console
        la    a0, bounce                ; ...
        call  out                       ; ...
        la    t0, rawake                ; output flows: keep looking
        li    t1, RPOLLS                ; ...
        sd    t1, 0(t0)                 ; ...
        j     rou_l                     ; ...
rou_bad:
        mv    a0, s1                    ; damaged: start it again
        call  chan_reset                ; ...
        la    t0, rtail                 ; ...
        slli  t1, s2, 3                 ; ...
        add   t0, t0, t1                ; ...
        sd    zero, 0(t0)               ; ...
rou_ret:
        cclear c10                      ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; ring_for(a0 = pid) -> a0 = its ring (the one whose owner word is the pid),
; or -1
ring_for:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        mv    s2, a0                    ; s2 = the pid
        li    s1, -1                    ; (none)
        la    t0, rsz                   ; no rings?
        ld    t0, 0(t0)                 ; ...
        beqz  t0, rf_ret                ; ...
        cclear c10                      ; ...
        cmov  c10, c4                   ; ...
        li    s1, 0                     ; ...
rf_l:
        li    t0, NRING                 ; ...
        bge   s1, t0, rf_none           ; ...
        mv    a0, s1                    ; its owner word
        call  ring_off                  ; ...
        addi  a0, a0, 24                ; ...
        tamo.add t2, c10, a0, zero      ; ...
        beq   t2, s2, rf_ret            ; this one
        addi  s1, s1, 1                 ; ...
        j     rf_l                      ; ...
rf_none:
        li    s1, -1                    ; ...
rf_ret:
        cclear c10                      ; ...
        mv    a0, s1                    ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; ring_cut(a0 = ring): c7 = a copy of that ring alone
ring_cut:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        call  ring_off                  ; its offset
        mv    t0, a0                    ; ...
        cclear c7                       ; a copy of all of them (copyable: c4 stays)
        cmov  c7, c4                    ; ...
        cclear c11                      ; c7 = [0, offset), c11 = the ring and the rest
        csplit c11, c7, t0              ; ...
        la    t0, rsz                   ; c11 = the ring, c12 = the rest
        ld    t0, 0(t0)                 ; ...
        cclear c12                      ; ...
        csplit c12, c11, t0             ; ...
        cclear c12                      ; ...
        cclear c7                       ; ...
        cmov  c7, c11                   ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; ---- line discipline -------------------------------------------------------------------------
; input(a0 = byte)
input:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        mv    s1, a0                    ; s1 = the byte
        li    t0, 0x1d                  ; Ctrl-] while a guest has the console: it comes back
        bne   s1, t0, in_cr             ; ...
        la    t0, gatt                  ; ...
        ld    t0, 0(t0)                 ; ...
        beqz  t0, in_cr                 ; (otherwise an ordinary control character)
        la    a0, s_ctlb                ; "^]"
        li    a1, 3                     ; ...
        call  out                       ; ...
        la    t0, llen                  ; the guest's partial line is dropped
        sd    zero, 0(t0)               ; ...
        li    a0, 0                     ; the ATTACH's answer: Ctrl-]
        call  detach                    ; ...
        j     in_ret                    ; ...
in_cr:
        li    t0, 13                    ; CR -> LF
        bne   s1, t0, in_nl             ; ...
        li    s1, 10                    ; ...
in_nl:
        la    t0, rawm            ; (its address)
        ld    t0, 0(t0)              ; raw?
        bnez  t0, in_raw                ; ...
        li    t0, 4                     ; Ctrl-D / end of input
        beq   s1, t0, ti_eof            ; ...
        li    t0, 127                   ; Backspace (DEL or BS)
        beq   s1, t0, in_bs             ; ...
        li    t0, 8                     ; ...
        beq   s1, t0, in_bs             ; ...
        li    t0, 10                    ; newline: the line is done
        beq   s1, t0, ti_line           ; ...
        li    t0, 32                    ; other control characters are ignored
        bltu  s1, t0, in_ret            ; ...
        la    t0, llen            ; (its address)
        ld    t0, 0(t0)              ; room?
        li    t1, LMAX                  ; ...
        bgeu  t0, t1, in_ret            ; ...
        la    t1, lbuf                  ; append
        add   t1, t1, t0                ; ...
        sb    s1, 0(t1)                 ; ...
        addi  t0, t0, 1                 ; ...
        la    t1, llen                  ; ...
        sd    t0, 0(t1)                 ; ...
        la    a0, inb                   ; echo it (inb still holds it unless CR)
        sb    s1, 0(a0)                 ; ...
        li    a1, 1                     ; ...
        call  out                       ; ...
        j     in_ret                    ; ...
in_bs:
        la    t0, llen            ; (its address)
        ld    t0, 0(t0)              ; something to erase?
        beqz  t0, in_ret                ; ...
        addi  t0, t0, -1                ; ...
        la    t1, llen                  ; ...
        sd    t0, 0(t1)                 ; ...
        la    a0, s_bs                  ; on screen too
        li    a1, 3                     ; ...
        call  out                       ; ...
        j     in_ret                    ; ...
ti_line:
        la    t0, llen            ; (its address)
        ld    t0, 0(t0)              ; add the newline
        la    t1, lbuf                  ; ...
        add   t1, t1, t0                ; ...
        sb    s1, 0(t1)                 ; ...
        addi  t0, t0, 1                 ; ...
        la    t1, llen                  ; ...
        sd    t0, 0(t1)                 ; ...
        la    a0, inb                   ; echo the newline
        sb    s1, 0(a0)                 ; ...
        li    a1, 1                     ; ...
        call  out                       ; ...
        call  commit                    ; the line is ready for readers
        j     in_ret                    ; ...
ti_eof:
        la    t0, llen            ; (its address)
        ld    t0, 0(t0)              ; a partial line goes as it is
        beqz  t0, ti_eof2               ; ...
        call  commit                    ; ...
        j     in_ret                    ; (the next Ctrl-D is the end)
ti_eof2:
        la    t0, eofs                  ; an end-of-input mark
        ld    t1, 0(t0)                 ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, 0(t0)                 ; ...
        j     in_ret                    ; ...
in_raw:
        la    t0, rlen            ; (its address)
        ld    t0, 0(t0)              ; raw: straight into the ready buffer
        li    t1, RMAX                  ; ...
        bgeu  t0, t1, in_ret            ; full: dropped
        la    t1, rbuf                  ; ...
        add   t1, t1, t0                ; ...
        sb    s1, 0(t1)                 ; ...
        addi  t0, t0, 1                 ; ...
        la    t1, rlen                  ; ...
        sd    t0, 0(t1)                 ; ...
        la    t0, rheld                 ; a byte came: a held start is looked at again
        sd    zero, 0(t0)               ; ...
        sd    zero, rhdl - rheld(t0)    ; ...
        sd    zero, rlook - rheld(t0)   ; ...
        sd    zero, rrel - rheld(t0)    ; ...
in_ret:
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; commit(): the cooked line -> the ready buffer (one unit)
commit:
        la    t0, llen            ; (its address)
        ld    t0, 0(t0)              ; ...
        la    t1, rlen            ; (its address)
        ld    t1, 0(t1)              ; room?
        add   t2, t0, t1                ; ...
        li    t3, RMAX                  ; ...
        bgtu  t2, t3, cm_drop           ; no: the line is lost
        li    t4, 0                     ; copy
cm_c:
        beq   t4, t0, cm_done           ; ...
        la    t5, lbuf                  ; ...
        add   t5, t5, t4                ; ...
        lbu   t5, 0(t5)                 ; ...
        la    t6, rbuf                  ; ...
        add   t6, t6, t1                ; ...
        add   t6, t6, t4                ; ...
        sb    t5, 0(t6)                 ; ...
        addi  t4, t4, 1                 ; ...
        j     cm_c                      ; ...
cm_done:
        la    t5, rlen                  ; ...
        sd    t2, 0(t5)                 ; ...
        la    t5, rlines                ; one more unit
        ld    t6, 0(t5)                 ; ...
        addi  t6, t6, 1                 ; ...
        sd    t6, 0(t5)                 ; ...
cm_drop:
        la    t5, llen                  ; the line buffer is empty again
        sd    zero, 0(t5)               ; ...
        ret                             ; ...

; ctrl_c(): echo, drop the partial line, ask proc to interrupt the foreground process
ctrl_c:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        la    a0, s_ctlc                ; "^C"
        li    a1, 3                     ; ...
        call  out                       ; ...
        la    t0, llen                  ; the partial line is gone
        sd    zero, 0(t0)               ; ...
        cvalid t0, c5                   ; our buffer at home? (else a signal is still on its way)
        beqz  t0, cc_ret                ; ...
        la    t0, sys_hdr               ; SIGNAL fg, sent without waiting
        li    t1, 17                    ; ...
        sd    t1, 0(t0)                 ; ...
        la    t1, fgpid           ; (its address)
        ld    t1, 0(t1)              ; ...
        sd    t1, 8(t0)                 ; ...
        sd    zero, 16(t0)              ; ...
        sd    zero, 24(t0)              ; ...
        li    t1, 64                    ; ...
        tput  tg10, t0, c5, zero, t1    ; ...
        twait 1 << 10                   ; ...
        csend c5, c1                    ; to proc; the reply comes back into c5 by itself
cc_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; ---- requests ---------------------------------------------------------------------------------
request:
        call  rings_out                 ; first what the rings hold (the sender's bytes
        la    t0, srv_hdr               ;   before its request); dispatch on the op
        ld    t1, 0(t0)                 ; ...
        li    t2, 1                     ; READ
        beq   t1, t2, op_read           ; ...
        li    t2, 2                     ; WRITE
        beq   t1, t2, op_write          ; ...
        li    t2, 4                     ; CLOSE
        beq   t1, t2, op_close          ; ...
        li    t2, 20                    ; ATTACH
        beq   t1, t2, op_attach         ; ...
        li    t2, 18                    ; SETFG
        beq   t1, t2, op_setfg          ; ...
        li    t2, 19                    ; CONMODE
        beq   t1, t2, op_mode           ; ...
        li    t2, OP_DUPS               ; DUPS (the console needs no counting)
        beq   t1, t2, ok                ; ...
        li    t2, OP_CLEANUP            ; CLEANUP: drop its waiting reads
        beq   t1, t2, op_cleanup        ; ...
        li    t2, OP_CANCEL             ; CANCEL: its waiting reads return -2
        beq   t1, t2, op_cancel         ; ...
        li    a0, -1                    ; unknown
reply:
        li    a1, 0                     ; ...
reply_a:
        call  srv_reply                 ; ...
        cclear c7                       ; (a ring's copy, if one went)
        j     loop                      ; ...
ok:
        li    a0, 0                     ; ...
        j     reply                     ; ...

op_write:
        la    t0, srv_hdr               ; length
        ld    s1, 16(t0)                ; ...
        li    t1, SYS_MAX               ; ...
        bleu  s1, t1, ow_n              ; ...
        mv    s1, t1                    ; ...
ow_n:
        la    a0, bounce                ; data -> D-LS
        mv    a1, s1                    ; ...
        call  srv_get                   ; ...
        la    a0, bounce                ; -> the console
        mv    a1, s1                    ; ...
        call  out                       ; ...
        la    t0, srv_hdr               ; a ring wanted (mode bit 1)?
        ld    t1, 24(t0)                ; ...
        andi  t1, t1, 2                 ; ...
        beqz  t1, ow_r                  ; ...
        ld    a0, 40(t0)                ; (not by a guest)
        li    t1, GUEST_ID0             ; ...
        bgeu  a0, t1, ow_r              ; ...
        call  ring_for                  ; a0 = its ring, or -1
        bltz  a0, ow_r                  ; none free
        call  ring_cut                  ; c7 = a copy of it
        mv    a0, s1                    ; all of it, and the ring
        li    a1, 1                     ; ...
        j     reply_a                   ; ...
ow_r:
        mv    a0, s1                    ; all of it
        j     reply                     ; ...

op_setfg:
        la    t0, srv_hdr               ; ...
        ld    t1, 8(t0)                 ; ...
        la    t2, fgpid                 ; ...
        sd    t1, 0(t2)                 ; ...
        j     ok                        ; ...

op_mode:
        la    t0, srv_hdr               ; 0 cooked, 1 raw
        ld    t1, 8(t0)                 ; ...
        andi  t1, t1, 1                 ; ...
        la    t2, rawm                  ; ...
        sd    t1, 0(t2)                 ; ...
        j     ok                        ; ...

op_read:
        la    t0, srv_hdr               ; pointer events too?
        ld    t1, 24(t0)                ; ...
        srli  t1, t1, 1                 ; (mode bit1)
        andi  t1, t1, 1                 ; ...
        la    t2, ptron                 ; (only if there is a pointer)
        ld    t2, 0(t2)                 ; ...
        and   t1, t1, t2                ; ...
        la    t2, rdptr                 ; ...
        sd    t1, 0(t2)                 ; ...
        beqz  t1, or_r                  ; ...
        la    t2, ptrwant               ; from now on the pointer is read
        sd    t1, 0(t2)                 ; ...
or_r:
        ld    a0, 40(t0)                ; the reader: may it have input now (does its
        call  elig                      ;   side have the console)?
        la    t0, rdok                  ; ...
        sd    a0, 0(t0)                 ; ...
        beqz  a0, or_wt                 ; no: it waits
        la    t0, srv_hdr               ; ...
        ld    a0, 16(t0)                ; wanted
        call  try_read                  ; a0 = bytes, 0 end, -3 nothing yet
        li    t0, -3                    ; ...
        bne   a0, t0, reply             ; answered
or_wt:
        la    t0, srv_hdr               ; do-not-block?
        ld    t1, 24(t0)                ; ...
        andi  t1, t1, 1                 ; ...
        bnez  t1, or_nb                 ; -3
        li    s1, 0                     ; a free wait entry
or_f:
        li    t0, NWAIT                 ; ...
        bge   s1, t0, or_busy           ; none
        la    t1, waitq                 ; ...
        slli  t2, s1, 5                 ; ...
        add   s2, t1, t2                ; ...
        ld    t3, 0(s2)                 ; ...
        beqz  t3, or_take               ; ...
        addi  s1, s1, 1                 ; ...
        j     or_f                      ; ...
or_take:
        la    t0, srv_tok         ; (its address)
        ld    t0, 0(t0)              ; token
        sd    t0, 8(s2)                 ; ...
        la    t1, srv_hdr               ; pid, length
        ld    t0, 40(t1)                ; ...
        sd    t0, 16(s2)                ; ...
        ld    t0, 16(t1)                ; ...
        la    t2, rdptr                 ; (bit 62: it wants pointer events)
        ld    t2, 0(t2)                 ; ...
        slli  t2, t2, 62                ; ...
        or    t0, t0, t2                ; ...
        sd    t0, 24(s2)                ; ...
        call  srv_park                  ; the kernel keeps the buffer
        bltz  a0, or_busy               ; ...
        addi  a0, a0, 1                 ; ...
        sd    a0, 0(s2)                 ; ...
        call  maybe_arm                 ; input is wanted now
        j     loop                      ; (answered later, lowest entry first)
or_busy:
        li    a0, -7                    ; too many waiting readers
        j     reply                     ; ...
or_nb:  li    a0, -3                    ; nothing yet, and the reader does not wait
        la    t0, rdok                  ; (nothing is read ahead for a reader whose
        ld    t0, 0(t0)                 ;   side does not have the console)
        beqz  t0, reply                 ; ...
        la    t0, rawm                  ; Raw
        ld    t0, 0(t0)                 ;   mode (nothing is echoed): one byte is read
        beqz  t0, reply                 ;   ahead, so a reader that polls sees the rest
        la    t0, inarm                 ;   of an escape sequence (vi, after an ESC)
        ld    t0, 0(t0)                 ; (not twice, nor after the end of input)
        bnez  t0, reply                 ; ...
        la    t0, eofs                  ; ...
        ld    t0, 0(t0)                 ; ...
        bnez  t0, reply                 ; ...
        call  arm_in                    ; ...
        li    a0, -3                    ; nothing yet
        j     reply                     ; ...

; try_read(a0 = wanted) -> a0 = bytes copied into the request (c6), 0 at end
; of input, -3 if nothing yet
try_read:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s3, 8(sp)                 ; ...
        sd    s4, 16(sp)                ; ...
        mv    s3, a0                    ; s3 = wanted
        li    t0, SYS_MAX               ; ...
        la    t1, rdptr                 ; (a pointer reader: 32 at most, its events
        ld    t1, 0(t1)                 ;   follow at 32)
        beqz  t1, tr_0                  ; ...
        li    t0, 32                    ; ...
tr_0:
        bleu  s3, t0, tr_w              ; ...
        mv    s3, t0                    ; ...
tr_w:
        la    t0, rlen            ; (its address)
        ld    t0, 0(t0)              ; something ready?
        la    t1, rawm            ; (its address)
        ld    t1, 0(t1)              ; (cooked: only complete lines)
        bnez  t1, tr_raw                ; ...
        la    t1, rlines          ; (its address)
        ld    t1, 0(t1)              ; ...
        bnez  t1, tr_line               ; ...
        j     tr_end                    ; ...
tr_raw:
        mv    a0, s3                    ; raw: whole keys, as many as fit
        call  raw_cut                   ; ...
        mv    s3, a0                    ; ...
        bnez  s3, tr_n                  ; ...
        la    t1, rdptr                 ; or pointer events, for a reader that wants them
        ld    t1, 0(t1)                 ; ...
        beqz  t1, tr_end                ; ...
        la    t1, pqn                   ; ...
        ld    t1, 0(t1)                 ; ...
        beqz  t1, tr_end                ; ...
        j     tr_n                      ; (no key bytes: 0 of them)
tr_line:
        li    t2, 0                     ; cooked: up to and including the first newline
tr_ls:
        bgeu  t2, t0, tr_lone           ; (a unit without a newline: all of it)
        la    t3, rbuf                  ; ...
        add   t3, t3, t2                ; ...
        lbu   t3, 0(t3)                 ; ...
        addi  t2, t2, 1                 ; ...
        li    t4, 10                    ; ...
        bne   t3, t4, tr_ls             ; ...
tr_lone:
        mv    t0, t2                    ; the line's length
        la    t5, rlines                ; one unit fewer
        ld    t6, 0(t5)                 ; ...
        addi  t6, t6, -1                ; ...
        sd    t6, 0(t5)                 ; ...
tr_take:
        bleu  s3, t0, tr_n              ; take min(wanted, available)
        mv    s3, t0                    ; ...
tr_n:
        la    a0, bounce                ; rbuf[0..s3) -> bounce
        la    a1, rbuf                  ; ...
        mv    a2, s3                    ; ...
        call  srv_bcopy                 ; ...
        la    t0, rlen            ; (its address)
        ld    t0, 0(t0)              ; shift the rest down
        sub   a2, t0, s3                ; ...
        la    t1, rlen                  ; ...
        sd    a2, 0(t1)                 ; ...
        la    a0, rbuf                  ; ...
        la    a1, rbuf                  ; ...
        add   a1, a1, s3                ; ...
        call  srv_bcopy                 ; ...
        la    a0, bounce                ; -> the request
        mv    a1, s3                    ; ...
        call  srv_put                   ; ...
        call  ptr_give                  ; and the pointer's events, if wanted
        mv    a0, s3                    ; ...
        j     tr_ret                    ; ...
tr_end:
        la    t0, eofs            ; (its address)
        ld    t0, 0(t0)              ; an end-of-input mark?
        beqz  t0, tr_none               ; no: nothing yet
        addi  t0, t0, -1                ; consumed
        la    t1, eofs                  ; ...
        sd    t0, 0(t1)                 ; ...
        la    t1, srv_hdr               ; (no pointer events with it)
        sd    zero, 24(t1)              ; ...
        li    a0, 0                     ; end of input
        j     tr_ret                    ; ...
tr_none:
        li    a0, -3                    ; ...
tr_ret:
        ld    s4, 16(sp)                ; ...
        ld    s3, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; raw_cut(a0 = wanted) -> a0 = how many of rbuf's bytes a raw READ takes:
; whole keys, as many as fit in wanted (a key longer than that alone is cut).
; A key is a byte, or an escape sequence: ESC [, parameter and intermediate
; bytes (0x20..0x3F), a final byte (0x40..); ESC O and a byte. An ESC with
; another byte after it is a key alone (the Esc key, then that key). A
; sequence begun at the end of rbuf waits for its rest (rheld: hold_tick
; times it), unless rrel says it goes as it is. A leaf; keeps t3.
raw_cut:
        la    t0, rlen                  ; t1 = bytes there
        ld    t1, 0(t0)                 ; ...
        la    t2, rbuf                  ; t2 = rbuf
        li    t4, 0                     ; t4 = the end of the whole keys so far
rc_u:
        bgeu  t4, t1, rc_ret            ; all of it
        add   t5, t2, t4                ; the next key's first byte
        lbu   t6, 0(t5)                 ; ...
        addi  t5, t4, 1                 ; t5 = its end so far
        li    t0, 0x1b                  ; not ESC: one byte
        bne   t6, t0, rc_k              ; ...
        bgeu  t5, t1, rc_part           ; ESC, and nothing after it yet
        add   t6, t2, t5                ; ...
        lbu   t6, 0(t6)                 ; ...
        li    t0, '['                   ; ESC [
        beq   t6, t0, rc_csi            ; ...
        li    t0, 'O'                   ; ESC O x
        bne   t6, t0, rc_k              ; (ESC and another key: ESC alone)
        addi  t5, t5, 1                 ; ...
        bgeu  t5, t1, rc_part           ; ...
        addi  t5, t5, 1                 ; ...
        j     rc_k                      ; ...
rc_csi:
        addi  t5, t5, 1                 ; past the [
rc_c:
        bgeu  t5, t1, rc_part           ; not ended yet
        add   t6, t2, t5                ; ...
        lbu   t6, 0(t6)                 ; ...
        addi  t5, t5, 1                 ; ...
        li    t0, 0x20                  ; a control character ends it before
        bltu  t6, t0, rc_bad            ;   itself (as keys.s cuts it)
        li    t0, 0x40                  ; parameters and intermediates
        bltu  t6, t0, rc_c              ; ...
        j     rc_k                      ; the final byte
rc_bad:
        addi  t5, t5, -1                ; ...
rc_k:
        bgtu  t5, a0, rc_full           ; [t4, t5): does it fit?
        mv    t4, t5                    ; ...
        j     rc_u                      ; ...
rc_full:
        bnez  t4, rc_ret                ; the keys before it
        mv    t4, a0                    ; one alone longer than wanted: cut
        j     rc_ret                    ; ...
rc_part:
        la    t0, rrel                  ; begun, not ended: goes as it is?
        ld    t0, 0(t0)                 ; ...
        bnez  t0, rc_rel                ; ...
        la    t0, rheld                 ; no: held back, the keys before it go
        li    t6, 1                     ; ...
        sd    t6, 0(t0)                 ; ...
        j     rc_ret                    ; ...
rc_rel:
        mv    t5, t1                    ; ...
        j     rc_k                      ; ...
rc_ret:
        mv    a0, t4                    ; ...
        ret                             ; ...

; hold_tick() -> a0 = ticks to wait at most, -1 for no limit: while raw input
; ends in a sequence's start (rheld), it waits T_HOLD from when this first
; sees it; then one more look for a byte that came with the deadline (a
; RECEIVE that waits a tick), and then it goes as it is (rrel), to the
; readers waiting. Every byte that comes starts this again (in_raw). NOW is
; read from the clock (sys_clock: a RECEIVE may have replaced c7).
hold_tick:
        la    t0, rheld                 ; held?
        ld    t0, 0(t0)                 ; ...
        bnez  t0, ht_on                 ; ...
        li    a0, -1                    ; no
        ret                             ; ...
ht_on:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        call  sys_clock                 ; a0 = NOW
        call  sys_now                   ; ...
        la    t0, rhdl                  ; timed yet?
        ld    t1, 0(t0)                 ; ...
        bnez  t1, ht_1                  ; ...
        li    t2, T_HOLD                ; no: from now
        add   t1, a0, t2                ; ...
        sd    t1, 0(t0)                 ; ...
        li    a0, T_HOLD                ; ...
        j     ht_ret                    ; ...
ht_1:
        bgeu  a0, t1, ht_2              ; not yet: the rest of the wait
        sub   a0, t1, a0                ; ...
        j     ht_ret                    ; ...
ht_2:
        la    t0, rlook                 ; the deadline: one more look
        ld    t1, 0(t0)                 ; ...
        bnez  t1, ht_go                 ; ...
        li    t1, 1                     ; ...
        sd    t1, 0(t0)                 ; ...
        li    a0, 1                     ; ...
        j     ht_ret                    ; ...
ht_go:
        la    t0, rheld                 ; nothing came: it goes as it is
        sd    zero, 0(t0)               ; ...
        sd    zero, rhdl - rheld(t0)    ; ...
        sd    zero, rlook - rheld(t0)   ; ...
        li    t1, 1                     ; ...
        sd    t1, rrel - rheld(t0)      ; ...
        call  serve_waiters             ; ...
        call  maybe_arm                 ; ...
        li    a0, -1                    ; ...
ht_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; serve_waiters(): answer waiting readers while input is there
serve_waiters:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        li    s1, 0                     ; ...
sv_l:
        li    t0, NWAIT                 ; ...
        bge   s1, t0, sv_ret            ; ...
        la    t1, waitq                 ; ...
        slli  t2, s1, 5                 ; ...
        add   s2, t1, t2                ; ...
        ld    t3, 0(s2)                 ; waiting?
        beqz  t3, sv_n                  ; ...
        ld    a0, 16(s2)                ; on the side that has the console?
        call  elig                      ; (t3 is kept)
        beqz  a0, sv_n                  ; no: it waits
        la    t0, rawm            ; (its address)
        ld    t0, 0(t0)              ; can it be answered?
        bnez  t0, sv_rawc               ; ...
        la    t0, rlines          ; (its address)
        ld    t0, 0(t0)              ; cooked: a line, or an end mark
        bnez  t0, sv_go                 ; ...
        la    t0, eofs            ; (its address)
        ld    t0, 0(t0)              ; ...
        bnez  t0, sv_go                 ; ...
        j     sv_ret                    ; nothing to give
sv_rawc:
        li    a0, RMAX                  ; whole keys (raw_cut keeps t3)
        call  raw_cut                   ; ...
        bnez  a0, sv_go                 ; ...
        la    t0, eofs            ; (its address)
        ld    t0, 0(t0)              ; ...
        bnez  t0, sv_go                 ; ...
        ld    t0, 24(s2)                ; a pointer reader, and events?
        srli  t0, t0, 62                ; ...
        beqz  t0, sv_n                  ; (not this one: maybe the next)
        la    t0, pqn                   ; ...
        ld    t0, 0(t0)                 ; ...
        beqz  t0, sv_n                  ; ...
sv_go:
        addi  a0, t3, -1                ; take its request back
        sd    zero, 0(s2)               ; ...
        call  srv_unpark                ; ...
        bnez  a0, sv_n                  ; its owner is gone
        ld    t0, 8(s2)                 ; its token
        la    t1, srv_tok               ; ...
        sd    t0, 0(t1)                 ; ...
        ld    a0, 24(s2)                ; read for it
        srli  t0, a0, 62                ; (bit 62: pointer events too)
        la    t1, rdptr                 ; ...
        sd    t0, 0(t1)                 ; ...
        slli  a0, a0, 2                 ; the length
        srli  a0, a0, 2                 ; ...
        call  try_read                  ; ...
        li    a1, 0                     ; answer
        call  srv_reply                 ; ...
sv_n:
        addi  s1, s1, 1                 ; ...
        j     sv_l                      ; ...
sv_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; op_close: CLOSE. From the guest the console is attached to: it gives the
; console back (Forth's BYE); from anyone else nothing happens.
op_close:
        la    t0, srv_hdr               ; the sender
        ld    t1, 40(t0)                ; ...
        la    t0, gatt                  ; the attached guest?
        ld    t0, 0(t0)                 ; ...
        beqz  t0, ok                    ; ...
        bne   t0, t1, ok                ; ...
        li    a0, 0                     ; answer it first (detach takes c6 for the ATTACH)
        li    a1, 0                     ; ...
        call  srv_reply                 ; ...
        li    a0, 1                     ; the ATTACH's answer: the guest closed it
        call  detach                    ; ...
        j     loop                      ; ...

; op_attach: ATTACH handle = guest id. The console's input goes to that guest
; until it comes back (detach answers this request).
op_attach:
        la    t0, srv_hdr               ; ...
        ld    t1, 40(t0)                ; the sender: a StrataOS process
        li    t2, GUEST_ID0             ; ...
        bgeu  t1, t2, oa_bad            ; (a guest cannot take the console)
        ld    t2, 8(t0)                 ; the guest id
        li    t3, GUEST_ID0             ; ...
        bltu  t2, t3, oa_bad            ; ...
        li    t3, 256                   ; ...
        bgeu  t2, t3, oa_bad            ; ...
        la    t3, gatt                  ; attached already?
        ld    t4, 0(t3)                 ; ...
        bnez  t4, oa_busy               ; ...
        sd    t2, 0(t3)                 ; the guest has the console now
        la    t3, gapid                 ; who asked
        sd    t1, 0(t3)                 ; ...
        la    t0, srv_tok               ; the request waits (its token)
        ld    t0, 0(t0)                 ; ...
        la    t3, gatok                 ; ...
        sd    t0, 0(t3)                 ; ...
        call  srv_park                  ; the kernel keeps the buffer
        bltz  a0, oa_nopark             ; ...
        addi  a0, a0, 1                 ; ...
        la    t0, gapark                ; ...
        sd    a0, 0(t0)                 ; ...
        call  serve_waiters             ; the guest's waiting READ may be answered now
        call  maybe_arm                 ; and input read for it
        j     loop                      ; ...
oa_nopark:
        la    t0, gatt                  ; not attached after all
        sd    zero, 0(t0)               ; ...
        la    t0, gapid                 ; ...
        sd    zero, 0(t0)               ; ...
oa_busy:
        li    a0, -7                    ; ...
        j     reply                     ; ...
oa_bad:
        li    a0, -1                    ; ...
        j     reply                     ; ...

; detach(a0 = the ATTACH's answer): the console's input goes back to
; StrataOS, and the ATTACH request is answered (if its sender still lives).
; It takes c6 and srv_tok: a request being handled must be answered first.
detach:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        mv    s1, a0                    ; s1 = the answer
        la    t0, gatt                  ; StrataOS has the console again
        sd    zero, 0(t0)               ; ...
        la    t0, gapid                 ; ...
        sd    zero, 0(t0)               ; ...
        la    t0, gapark                ; the ATTACH
        ld    a0, 0(t0)                 ; ...
        sd    zero, 0(t0)               ; ...
        beqz  a0, dt_ret                ; (none)
        addi  a0, a0, -1                ; ...
        call  srv_unpark                ; ...
        bnez  a0, dt_ret                ; its owner is gone
        la    t0, gatok                 ; its token
        ld    t0, 0(t0)                 ; ...
        la    t1, srv_tok               ; ...
        sd    t0, 0(t1)                 ; ...
        mv    a0, s1                    ; answer it
        li    a1, 0                     ; ...
        call  srv_reply                 ; ...
dt_ret:
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; elig(a0 = a reader's pid) -> a0 = 1 if input may go to it now: it is the
; guest the console is attached to, or, while none is, a StrataOS process.
; Clobbers t0 only.
elig:
        la    t0, gatt                  ; ...
        ld    t0, 0(t0)                 ; ...
        beqz  t0, el_os                 ; ...
        xor   a0, a0, t0                ; that guest?
        sltiu a0, a0, 1                 ; ...
        ret                             ; ...
el_os:
        sltiu a0, a0, GUEST_ID0         ; a process, not a guest
        ret                             ; ...

; op_cleanup / op_cancel: waiting reads of a process (handle = pid): dropped / -2
op_cleanup:
        li    s3, 0                     ; s3 = 0: drop (its buffers died with it)
        j     ocx                       ; ...
op_cancel:
        li    s3, 1                     ; s3 = 1: answer -2
ocx:
        la    t0, srv_hdr               ; s4 = the pid
        ld    s4, 8(t0)                 ; ...
        li    a0, 0                     ; answer proc first
        li    a1, 0                     ; ...
        call  srv_reply                 ; ...
        la    t0, gatt                  ; the guest that has the console is gone?
        ld    t0, 0(t0)                 ; ...
        beqz  t0, ocx_p                 ; ...
        bne   t0, s4, ocx_a             ; ...
        li    a0, 2                     ; the console comes back: answer 2
        call  detach                    ; ...
        j     ocx_p                     ; ...
ocx_a:
        la    t0, gapid                 ; or the process that attached it?
        ld    t0, 0(t0)                 ; ...
        bne   t0, s4, ocx_p             ; ...
        li    a0, -2                    ; the console comes back (it was interrupted)
        call  detach                    ; ...
ocx_p:
        li    s1, 0                     ; ...
ocx_l:
        li    t0, NWAIT                 ; ...
        bge   s1, t0, loop              ; ...
        la    t1, waitq                 ; ...
        slli  t2, s1, 5                 ; ...
        add   s2, t1, t2                ; ...
        ld    t3, 0(s2)                 ; waiting?
        beqz  t3, ocx_n                 ; ...
        ld    t4, 16(s2)                ; that process?
        bne   t4, s4, ocx_n             ; ...
        addi  a0, t3, -1                ; ...
        sd    zero, 0(s2)               ; ...
        call  srv_unpark                ; ...
        bnez  a0, ocx_n                 ; gone
        beqz  s3, ocx_drop              ; ...
        ld    t0, 8(s2)                 ; answer -2
        la    t1, srv_tok               ; ...
        sd    t0, 0(t1)                 ; ...
        li    a0, -2                    ; ...
        li    a1, 0                     ; ...
        call  srv_reply                 ; ...
        j     ocx_n                     ; ...
ocx_drop:
        cclear c6                       ; ...
ocx_n:
        addi  s1, s1, 1                 ; ...
        j     ocx_l                     ; ...

; =============================================================================
; A guest StrataOS (doc/strataos.md, "StrataOS as a guest"): the console is the
; host's tty, reached through the endpoint dev gave us (c2). A READ or a WRITE
; is passed on to it as it came, one at a time (the host takes one request at
; a time from each of a guest's cores) and answered with what the host's tty
; answered: the host echoes and edits the line, and gives the input to the
; guest only while the console is attached to it. So is CONMODE: the console
; has one mode, and while the guest has it, it is the guest's (the host's shell
; sets its own again before it reads a line). The rest is not passed on: SETFG
; and Ctrl-C (the host's Ctrl-C detaches the console), the pointer, ATTACH (-1).
; =============================================================================
GMAX     = 4096 - 64                    ; the most one message carries

g_main:
        la    a0, g_loop                ; a fault on a dead request returns to the loop
        call  srv_guard                 ; ...
g_loop:
        li    a0, 0                     ; no device tags
        li    a1, -1                    ; no timeout
        call  srv_recv                  ; ...
        bltz  a0, g_loop                ; ...
        la    t0, srv_hdr               ; dispatch
        ld    t1, 0(t0)                 ; ...
        li    t2, OP_READ               ; ...
        beq   t1, t2, g_read            ; ...
        li    t2, OP_WRITE              ; ...
        beq   t1, t2, g_write           ; ...
        li    t2, OP_CONMODE            ; ...
        beq   t1, t2, g_mode            ; ...
        li    a0, -1                    ; ATTACH: not here
        li    t2, 20                    ; ...
        beq   t1, t2, g_reply           ; ...
        li    a0, 0                     ; the rest: nothing to do
g_reply:
        li    a1, 0                     ; ...
        call  srv_reply                 ; ...
        j     g_loop                    ; ...

g_mode:
        ld    a3, 8(t0)                 ; raw or cooked: the console's mode while the guest
        li    a0, OP_CONMODE            ;   has it (the host's shell sets its own again)
        li    a1, 0                     ; ...
        li    a2, 0                     ; ...
        call  g_send                    ; ...
        j     g_reply                   ; ...

g_write:
        ld    s1, 16(t0)                ; s1 = its length (at most GMAX)
        li    t2, GMAX                  ; ...
        bleu  s1, t2, gw_n              ; ...
        mv    s1, t2                    ; ...
gw_n:
        la    a0, bounce                ; its data
        mv    a1, s1                    ; ...
        call  srv_get                   ; ...
        la    a0, bounce                ; -> our buffer, after the header
        addi  a1, s1, 7                 ; ...
        srli  a1, a1, 3                 ; ...
        slli  a1, a1, 3                 ; ...
        li    t1, 64                    ; ...
        tput  tg10, a0, c5, t1, a1      ; (g_send waits for it)
        li    a0, OP_WRITE              ; ...
        mv    a1, s1                    ; ...
        li    a2, 0                     ; ...
        li    a3, 0                     ; ...
        call  g_send                    ; a0 = its result
        j     g_reply                   ; ...

g_read:
        ld    s1, 16(t0)                ; s1 = how much (at most GMAX)
        li    t2, GMAX                  ; ...
        bleu  s1, t2, gr_n              ; ...
        mv    s1, t2                    ; ...
gr_n:
        ld    a2, 24(t0)                ; its mode: not blocking, or blocking (no pointer)
        andi  a2, a2, 1                 ; ...
        li    a0, OP_READ               ; ...
        mv    a1, s1                    ; ...
        li    a3, 0                     ; ...
        call  g_send                    ; a0 = bytes, 0 end of input, or an error
        mv    s2, a0                    ; ...
        blez  s2, gr_r                  ; ...
        la    a0, bounce                ; the bytes: our buffer -> the request
        addi  a1, s2, 7                 ; ...
        srli  a1, a1, 3                 ; ...
        slli  a1, a1, 3                 ; ...
        li    t1, 64                    ; ...
        tget  tg10, a0, c5, t1, a1      ; ...
        twait 1 << 10                   ; ...
        mv    a1, s2                    ; ...
        call  srv_put                   ; ...
gr_r:
        mv    a0, s2                    ; ...
        j     g_reply                   ; ...

; g_send(a0 = op, a1 = length, a2 = mode, a3 = handle) -> a0 = the host's tty's
; result: our buffer (c5; its data is there already) goes to it and comes back
g_send:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        la    t0, sys_hdr               ; the header
        sd    a0, 0(t0)                 ; op
        sd    a3, 8(t0)                 ; handle (0: the console; CONMODE's mode)
        sd    a1, 16(t0)                ; length
        sd    a2, 24(t0)                ; mode
        sd    zero, 32(t0)              ; ...
        li    t1, 64                    ; ...
        tput  tg10, t0, c5, zero, t1    ; ...
        twait 1 << 10                   ; ...
        csend c5, c2                    ; to the host's tty
gs_w:
        li    a0, 1                     ; WAIT_REPLY: until our buffer is back
        li    a1, -1                    ; (no doorbell: not a core of ours)
        li    a2, -1                    ; no timeout
        li    a3, 0                     ; ...
        li    a4, 5                     ; ...
        svc                             ; ...
        bnez  a0, gs_w                  ; (woken early: wait on)
        la    t0, sys_hdr               ; its result
        li    t1, 64                    ; ...
        tget  tg10, t0, c5, zero, t1    ; ...
        twait 1 << 10                   ; ...
        ld    a0, 32(t0)                ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

        .include "../lib/sys.s"         ; the program library
        .include "../lib/srv.s"         ; server helpers
