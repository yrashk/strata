; =============================================================================
; dbprog.s: the store for programs (included by db.s)
; =============================================================================
;
; DBGET (64), DBSCAN (65), DBBATCH (66): trees of keys and values in
; namespaces of their own, made by the first write; such namespaces are
; public, and "fs" is not (doc/strataos.md, "The store for programs").
; Programs send them to fs, which hands them on; db answers them for anyone
; that reaches it. A batch is one commit (what fs had not committed yet goes
; in it too: fs commits a writer's bytes before it hands a batch on).

        .text                           ; instruction Local Store

; db_parse(a0 = 1: make the namespace and the tree if missing) -> a0 = 0 and
; s1 = the tree, s2 = what follows the names in rqd, s3 = the key length;
; or a0 = -1 / -4
db_parse:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s4, 8(sp)                 ; ...
        sd    s5, 16(sp)                ; ...
        mv    s4, a0                    ; s4 = make?
        la    t0, srv_hdr               ; the data
        ld    s5, 16(t0)                ; s5 = its length
        li    a0, -1                    ; ...
        li    t1, 8                     ; ...
        bltu  s5, t1, dbp_ret           ; ...
        li    t1, SYS_MAX               ; ...
        bgtu  s5, t1, dbp_ret           ; ...
        la    a0, rqd                   ; ...
        mv    a1, s5                    ; ...
        call  srv_get                   ; ...
        la    t0, rqd                   ; ...
        lbu   t1, 0(t0)                 ; the names' lengths
        lbu   t2, 1(t0)                 ; ...
        lhu   s3, 2(t0)                 ; ...
        li    a0, -1                    ; ...
        beqz  t1, dbp_ret               ; ...
        beqz  t2, dbp_ret               ; ...
        li    t3, 32                    ; ...
        bgtu  t1, t3, dbp_ret           ; ...
        li    t3, 28                    ; ...
        bgtu  t2, t3, dbp_ret           ; ...
        add   t3, t1, t2                ; all inside the data?
        addi  t3, t3, 8                 ; ...
        bgtu  t3, s5, dbp_ret           ; ...
        add   s2, t0, t3                ; ...
        add   t3, t0, t1                ; (the tree's name)
        lbu   t4, 8(t3)                 ; ...
        li    t5, '.'                   ; ...
        beq   t4, t5, dbp_ret           ; ...
        ld    a0, x_nst(zero)           ; the namespace
        addi  a1, t0, 8                 ; ...
        mv    a2, t1                    ; ...
        la    a3, dval                  ; ...
        call  st_get                    ; ...
        bgez  a0, dbp_have              ; ...
        li    a0, -4                    ; ...
        beqz  s4, dbp_ret               ; ...
        ld    t0, st_nextns(zero)       ; a new one: public
        sd    t0, dval(zero)            ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, st_nextns(zero)       ; ...
        li    t0, 1                     ; ...
        sd    t0, dval+8(zero)          ; ...
        ld    a0, x_nst(zero)           ; ...
        la    a1, rqd + 8               ; ...
        la    a2, rqd                   ; ...
        lbu   a2, 0(a2)                 ; ...
        la    a3, dval                  ; ...
        li    a4, 16                    ; ...
        li    a5, 0                     ; ...
        call  st_put                    ; ...
dbp_have:
        ld    t0, dval+8(zero)          ; public?
        andi  t0, t0, 1                 ; ...
        li    a0, -1                    ; ...
        beqz  t0, dbp_ret               ; ...
        ld    a0, dval(zero)            ; its tree
        la    t0, rqd                   ; ...
        lbu   t1, 0(t0)                 ; ...
        add   a1, t0, t1                ; ...
        addi  a1, a1, 8                 ; ...
        lbu   a2, 1(t0)                 ; ...
        mv    a3, s4                    ; ...
        call  st_tree                   ; ...
        mv    s1, a0                    ; ...
        li    a0, -4                    ; ...
        beqz  s1, dbp_ret               ; ...
        li    a0, 0                     ; ...
dbp_ret:
        ld    s5, 16(sp)                ; ...
        ld    s4, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; db_key() (after db_parse) -> a0 = 0 when the key (s2, s3 bytes) lies inside
; the request's data, or -1 (and the tree is not kept open)
db_key:
        la    t0, srv_hdr               ; the data's end
        ld    t1, 16(t0)                ; ...
        la    t0, rqd                   ; ...
        add   t1, t1, t0                ; ...
        add   t2, s2, s3                ; the key's end
        li    a0, 0                     ; ...
        bleu  t2, t1, dbk_ret           ; ...
        sd    zero, TT_FL(s1)           ; ...
        li    a0, -1                    ; ...
dbk_ret:
        ret                             ; ...

op_dbget:
        li    a0, 0                     ; ...
        call  db_parse                  ; ...
        bltz  a0, reply                 ; ...
        call  db_key                    ; ...
        bltz  a0, reply                 ; ...
        mv    a0, s1                    ; ...
        mv    a1, s2                    ; ...
        mv    a2, s3                    ; ...
        la    a3, sys_buf               ; ...
        call  st_get                    ; ...
        sd    zero, TT_FL(s1)           ; (the tree is not kept open)
        bltz  a0, nofile                ; ...
        bnez  a1, bad                   ; (a stream: not through this call)
        mv    s3, a0                    ; ...
        la    a0, sys_buf               ; ...
        mv    a1, s3                    ; ...
        call  srv_put                   ; ...
        mv    a0, s3                    ; ...
        j     reply                     ; ...

op_dbscan:
        li    a0, 0                     ; ...
        call  db_parse                  ; ...
        bltz  a0, reply                 ; ...
        call  db_key                    ; ...
        bltz  a0, reply                 ; ...
        la    a0, pgcopy                ; the key at hand (pgcopy), a value (pgcopy + 512)
        mv    a1, s2                    ; ...
        mv    a2, s3                    ; ...
        call  srv_bcopy                 ; ...
        la    t0, srv_hdr               ; s4 = the side of the key for the first one
        ld    s4, 24(t0)                ; ...
        li    s6, 0                     ; s6 = records
        la    s5, sys_buf               ; s5 = output
odb_l:
        mv    a0, s1                    ; ...
        la    a1, pgcopy                ; ...
        mv    a2, s3                    ; ...
        mv    a3, s4                    ; ...
        la    a4, pgcopy                ; ...
        la    a5, pgcopy + 512          ; ...
        call  st_seek                   ; ...
        beqz  a0, odb_done              ; ...
        ld    s3, sk_kl(zero)           ; ...
        li    s4, ST_GT                 ; (the ones after it follow)
        ld    t1, sk_vl(zero)           ; room for it?
        addi  t2, s3, 7                 ; ...
        srli  t2, t2, 3                 ; ...
        slli  t2, t2, 3                 ; ...
        addi  t3, t1, 7                 ; ...
        srli  t3, t3, 3                 ; ...
        slli  t3, t3, 3                 ; ...
        add   t4, t2, t3                ; ...
        addi  t4, t4, 8                 ; ...
        add   t4, t4, s5                ; ...
        la    t5, sys_buf + SYS_MAX     ; ...
        bgtu  t4, t5, odb_done          ; ...
        sd    zero, 0(s5)               ; ...
        sh    s3, 0(s5)                 ; ...
        sh    t1, 2(s5)                 ; ...
        addi  a0, s5, 8                 ; ...
        la    a1, pgcopy                ; ...
        mv    a2, t2                    ; ...
        add   s5, a0, t2                ; ...
        call  wcopy                     ; ...
        mv    a0, s5                    ; ...
        la    a1, pgcopy + 512          ; ...
        ld    a2, sk_vl(zero)           ; ...
        addi  a2, a2, 7                 ; ...
        srli  a2, a2, 3                 ; ...
        slli  a2, a2, 3                 ; ...
        add   s5, s5, a2                ; ...
        call  wcopy                     ; ...
        addi  s6, s6, 1                 ; ...
        j     odb_l                     ; ...
odb_done:
        sd    zero, TT_FL(s1)           ; ...
        la    a0, sys_buf               ; ...
        sub   a1, s5, a0                ; ...
        la    t0, srv_hdr               ; ...
        sd    a1, 16(t0)                ; ...
        call  srv_put                   ; ...
        mv    a0, s6                    ; ...
        j     reply                     ; ...

op_dbbatch:
                li    a0, 1                     ; ...
        call  db_parse                  ; ...
        bltz  a0, reply                 ; ...
        la    t0, rqd                   ; s2 = the first item: at a multiple of 8
        sub   s2, s2, t0                ; ...
        addi  s2, s2, 7                 ; ...
        srli  s2, s2, 3                 ; ...
        slli  s2, s2, 3                 ; ...
        add   s2, s2, t0                ; ...
        la    t0, srv_hdr               ; s6 = the end of the data
        ld    s6, 16(t0)                ; ...
        la    t1, rqd                   ; ...
        add   s6, s6, t1                ; ...
        ld    s7, 8(t0)                 ; s7 = items
        li    s5, 0                     ; first every item is looked at (s5 = 0), then done (1)
obb_pass:
        mv    s3, s2                    ; s3 = the item
        mv    s4, s7                    ; s4 = items left
obb_l:
        beqz  s4, obb_next              ; ...
        addi  t0, s3, 8                 ; inside the data?
        bgtu  t0, s6, obb_bad           ; ...
        lhu   a2, 2(s3)                 ; the key's length, the value's
        lhu   a4, 4(s3)                 ; ...
        addi  t1, a2, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        addi  t2, a4, 7                 ; ...
        srli  t2, t2, 3                 ; ...
        slli  t2, t2, 3                 ; ...
        add   t3, t0, t1                ; t3 = the value, t4 = the next item
        add   t4, t3, t2                ; ...
        bgtu  t4, s6, obb_bad           ; ...
        lbu   t5, 0(s3)                 ; ...
        addi  t5, t5, -1                ; ...
        li    t6, 2                     ; ...
        bgeu  t5, t6, obb_bad           ; ...
        bnez  s5, obb_do                ; ...
        beqz  a2, obb_bad               ; a key and a value of a size the store takes?
        ld    t6, st_ps(zero)           ; ...
        srli  t0, t6, 3                 ; ...
        addi  t0, t0, -32               ; ...
        bgtu  a2, t0, obb_bad           ; ...
        addi  t6, t6, -32               ; ...
        srli  t6, t6, 2                 ; ...
        addi  t6, t6, -10               ; ...
        srli  t6, t6, 3                 ; ...
        slli  t6, t6, 3                 ; ...
        sub   t6, t6, t1                ; ...
        bgt   a4, t6, obb_bad           ; ...
        j     obb_n                     ; ...
obb_do:
        sd    t4, rb_c(zero)            ; (kept: the next item)
        mv    a0, s1                    ; ...
        mv    a1, t0                    ; ...
        bnez  t5, obb_del               ; ...
        mv    a3, t3                    ; ...
        li    a5, 0                     ; ...
        call  st_put                    ; ...
        j     obb_dn                    ; ...
obb_del:
        call  st_del                    ; ...
obb_dn:
        ld    t4, rb_c(zero)            ; ...
obb_n:
        mv    s3, t4                    ; ...
        addi  s4, s4, -1                ; ...
        j     obb_l                     ; ...
obb_next:
        addi  s5, s5, 1                 ; ...
        li    t0, 2                     ; ...
        bne   s5, t0, obb_pass          ; ...
        call  st_commit                 ; ...
        sd    zero, TT_FL(s1)           ; ...
        j     ok                        ; ...
obb_bad:
        call  st_commit                 ; ...
        sd    zero, TT_FL(s1)           ; ...
        j     bad                       ; ...
