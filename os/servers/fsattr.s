; =============================================================================
; fsattr.s: attributes, and the terms of a path that ask about them (included by fs.s)
; =============================================================================
;
; A file carries attributes besides its tags: a name and a value each, the
; value an unsigned number (given in digits) or a string (up to 255 bytes).
; They are in the file's record after its tag ids ({u32 id, u8 type: 0
; number / 1 string, u8 length, u16 0, the value padded to a word} each) and
; in the index (attribute id, value, object: a number as 8 bytes big-endian,
; a string with a zero byte after it, so that the index's order is the
; values' order). An attribute's name has an id in the dictionary ("a" name
; -> u32 id, u32 type; "A" id -> name), made by its first use.
;
;  42 SETATTR data = path, a zero byte, the attribute's name, a zero byte,
;             the value (none: the attribute goes) -> 0 / -4 / -1 (a bad
;             name: tag, size, modified, boot, or with one of = < > * /) / -6
;  43 GETATTR data = path -> attributes; data: per attribute {u16 record
;             bytes, u16 name length, u8 type, u8 value length, u16 0, the
;             name, the value}, name and value each padded to 8 bytes (a
;             number: 8 bytes); the reply's length word is the data's bytes
;
; Terms. A component of a path that holds =, < or > is not a tag but a
; condition on the files: NAME=VALUE, NAME<VALUE, NAME>VALUE, where NAME is
; an attribute, or size (bytes), or modified (the commit that changed the
; file last). A value in digits is compared as a number, any other as bytes.
; A file without the attribute matches none of them. In a listing the last
; component may also be PREFIX*: the files whose names begin so. Terms
; narrow what the tags give: they are checked against each file's record.
; A path without tags that has a term NAME=VALUE is answered from the index
; (q_next in fs.s): only the files with that value are looked at. A path of
; only < and > terms, or PREFIX*, still looks at every file. A path that
; creates cannot hold a term (-1). In the shell a term with < or > is quoted.

T_PRE   = 1                             ; a term's subject: the name's beginning,
T_SIZE  = 2                             ;   the size,
T_MOD   = 3                             ;   the last change; from 16 on an attribute's id
T_NONE  = 0xFFFF                        ;   an attribute nobody has: nothing matches

; p_num(a0 = text, a1 = its length) -> a0 = the number, a1 = 1; or a1 = 0
; when it is not all digits (or empty)
p_num:
        li    t0, 0                     ; ...
        beqz  a1, pn_no                 ; ...
        add   t1, a0, a1                ; ...
        li    t4, 10                    ; ...
pnm_l:
        lbu   t2, 0(a0)                 ; ...
        addi  t2, t2, -48               ; ...
        bgeu  t2, t4, pn_no             ; ...
        mul   t0, t0, t4                ; ...
        add   t0, t0, t2                ; ...
        addi  a0, a0, 1                 ; ...
        bne   a0, t1, pnm_l             ; ...
        mv    a0, t0                    ; ...
        li    a1, 1                     ; ...
        ret                             ; ...
pn_no:
        li    a1, 0                     ; ...
        ret                             ; ...

; attr_find(a0 = name, a1 = its length) -> a0 = the attribute's id, or -1
attr_find:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        li    t0, NAMEMAX               ; ...
        bgtu  a1, t0, af_no             ; ...
        beqz  a1, af_no                 ; ...
        call  dk_tag                    ; ("t", name: the same key with "a")
        li    t0, 'a'                   ; ...
        sb    t0, dkey(zero)            ; ...
        ld    a0, x_dict(zero)          ; ...
        la    a1, dkey                  ; ...
        ld    a2, dk_len(zero)          ; ...
        la    a3, dval                  ; ...
        call  st_get                    ; ...
        bltz  a0, af_no                 ; ...
        lwu   a0, dval(zero)            ; ...
        j     af_ret                    ; ...
af_no:
        li    a0, -1                    ; ...
af_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; rec_attr(a0 = attribute id) -> a0 = its entry in rec, or 0
rec_attr:
        la    t0, rec                   ; ...
        lhu   t1, R_NTAGS(t0)           ; ...
        slli  t1, t1, 2                 ; ...
        addi  t1, t1, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        add   t1, t1, t0                ; ...
        addi  t1, t1, R_TAGS            ; ...
        lhu   t2, R_NATTR(t0)           ; ...
rat_l:
        beqz  t2, rat_no                ; ...
        lwu   t3, 0(t1)                 ; ...
        beq   t3, a0, rat_yes           ; ...
        lbu   t3, 5(t1)                 ; ...
        addi  t3, t3, 7                 ; ...
        srli  t3, t3, 3                 ; ...
        slli  t3, t3, 3                 ; ...
        add   t1, t1, t3                ; ...
        addi  t1, t1, 8                 ; ...
        addi  t2, t2, -1                ; ...
        j     rat_l                     ; ...
rat_yes:
        mv    a0, t1                    ; ...
        ret                             ; ...
rat_no:
        li    a0, 0                     ; ...
        ret                             ; ...

; idx_attr(a0 = 1 put / 0 delete, a1 = an attribute's entry in rec): rec's
; object under that attribute and value in the index
idx_attr:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        sd    s1, 16(sp)                ; ...
        mv    s1, a1                    ; ...
        lbu   t0, 4(s1)                 ; ...
        bnez  t0, ia_str                ; ...
        ld    a0, 8(s1)                 ; a number: big-endian
        call  bswap                     ; ...
        sd    a0, ib8(zero)             ; ...
        la    a1, ib8                   ; ...
        li    a2, 8                     ; ...
        j     ia_key                    ; ...
ia_str:
        la    a0, tnbuf                 ; a string: with a zero byte after it
        addi  a1, s1, 8                 ; ...
        lbu   a2, 5(s1)                 ; ...
        call  srv_bcopy                 ; ...
        sb    zero, 0(a0)               ; ...
        la    a1, tnbuf                 ; ...
        lbu   a2, 5(s1)                 ; ...
        addi  a2, a2, 1                 ; ...
ia_key:
        lwu   a0, 0(s1)                 ; ...
        call  idx_key                   ; ...
        ld    a0, 8(sp)                 ; ...
        call  idx_do                    ; ...
        ld    s1, 16(sp)                ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; attrs_unindex(): every attribute of rec's file leaves the index (the file goes)
attrs_unindex:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        la    t0, rec                   ; ...
        lhu   s2, R_NATTR(t0)           ; ...
        lhu   t1, R_NTAGS(t0)           ; ...
        slli  t1, t1, 2                 ; ...
        addi  t1, t1, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        add   s1, t1, t0                ; ...
        addi  s1, s1, R_TAGS            ; ...
aui_l:
        beqz  s2, aui_ret               ; ...
        li    a0, 0                     ; ...
        mv    a1, s1                    ; ...
        call  idx_attr                  ; ...
        lbu   t3, 5(s1)                 ; ...
        addi  t3, t3, 7                 ; ...
        srli  t3, t3, 3                 ; ...
        slli  t3, t3, 3                 ; ...
        add   s1, s1, t3                ; ...
        addi  s1, s1, 8                 ; ...
        addi  s2, s2, -1                ; ...
        j     aui_l                     ; ...
aui_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; term_add(a0 = subject, a1 = how: 0 =, 1 <, 2 >, a2 = value text, a3 = its
; length) -> a0 = 1, or -1 when a path holds more terms than NQA
term_add:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        ld    t0, nqa(zero)             ; ...
        li    t1, NQA                   ; ...
        bgeu  t0, t1, ta_full           ; ...
        addi  t1, t0, 1                 ; ...
        sd    t1, nqa(zero)             ; ...
        slli  s1, t0, 5                 ; ...
        la    t1, qa                    ; ...
        add   s1, s1, t1                ; ...
        sd    a0, 0(s1)                 ; ...
        sd    a1, 8(s1)                 ; ...
        sd    a2, 16(s1)                ; a string: its text and length;
        sd    a3, 24(s1)                ; ...
        mv    a0, a2                    ; in digits: the number, and no length
        mv    a1, a3                    ; ...
        call  p_num                     ; ...
        beqz  a1, ta_ok                 ; ...
        ld    t0, 0(s1)                 ; (not for a name's beginning)
        li    t1, T_PRE                 ; ...
        beq   t0, t1, ta_ok             ; ...
        sd    a0, 16(s1)                ; ...
        li    t0, -1                    ; ...
        sd    t0, 24(s1)                ; ...
ta_ok:
        li    a0, 1                     ; ...
        j     ta_ret                    ; ...
ta_full:
        li    a0, -1                    ; ...
ta_ret:
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; term_try(a0 = a path's component, a1 = its length) -> a0 = 1 it was a term
; (NAME=VALUE, NAME<VALUE, NAME>VALUE) and is taken, 0 it is none, -1 one
; too many
term_try:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        li    s3, 1                     ; s3 = where the sign is (not first)
tt_l:
        li    a0, 0                     ; ...
        bgeu  s3, s2, tt_ret            ; none
        add   t0, s1, s3                ; ...
        lbu   t0, 0(t0)                 ; ...
        li    s4, 0                     ; s4 = how
        li    t1, '='                   ; ...
        beq   t0, t1, tt_have           ; ...
        li    s4, 1                     ; ...
        li    t1, '<'                   ; ...
        beq   t0, t1, tt_have           ; ...
        li    s4, 2                     ; ...
        li    t1, '>'                   ; ...
        beq   t0, t1, tt_have           ; ...
        addi  s3, s3, 1                 ; ...
        j     tt_l                      ; ...
tt_have:
        mv    a0, s1                    ; its subject: size, modified, or an attribute
        mv    a1, s3                    ; ...
        la    a2, s_size                ; ...
        li    a3, 4                     ; ...
        call  kcmp                      ; ...
        li    t0, T_SIZE                ; ...
        beqz  a0, tt_add                ; ...
        mv    a0, s1                    ; ...
        mv    a1, s3                    ; ...
        la    a2, s_mod                 ; ...
        li    a3, 8                     ; ...
        call  kcmp                      ; ...
        li    t0, T_MOD                 ; ...
        beqz  a0, tt_add                ; ...
        mv    a0, s1                    ; ...
        mv    a1, s3                    ; ...
        call  attr_find                 ; ...
        mv    t0, a0                    ; ...
        bgez  t0, tt_add                ; ...
        li    t0, T_NONE                ; ...
tt_add:
        mv    a0, t0                    ; ...
        mv    a1, s4                    ; ...
        add   a2, s1, s3                ; ...
        addi  a2, a2, 1                 ; ...
        sub   a3, s2, s3                ; ...
        addi  a3, a3, -1                ; ...
        call  term_add                  ; ...
tt_ret:
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 40                ; ...
        ret                             ; ...

; terms_match() -> a0 = 1 if rec's file meets every term of the path
terms_match:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        li    s2, 0                     ; ...
tm_l:
        ld    t0, nqa(zero)             ; ...
        li    a0, 1                     ; ...
        bgeu  s2, t0, tm_ret            ; ...
        slli  s1, s2, 5                 ; s1 = the term
        la    t0, qa                    ; ...
        add   s1, s1, t0                ; ...
        addi  s2, s2, 1                 ; ...
        ld    t0, 0(s1)                 ; ...
        li    t1, T_PRE                 ; ...
        bne   t0, t1, tm_val            ; ...
        call  rec_name                  ; the name begins with the term's text?
        ld    a3, 24(s1)                ; ...
        bltu  a1, a3, tm_no             ; ...
        mv    a1, a3                    ; ...
        ld    a2, 16(s1)                ; ...
        call  kcmp                      ; ...
        beqz  a0, tm_l                  ; ...
        j     tm_no                     ; ...
tm_val:
        la    t2, rec                   ; the file's value: a number in t3, or a string
        ld    t3, R_SIZE(t2)            ; ...
        li    t1, T_SIZE                ; ...
        beq   t0, t1, tm_num            ; ...
        ld    t3, R_MOD(t2)             ; ...
        li    t1, T_MOD                 ; ...
        beq   t0, t1, tm_num            ; ...
        mv    a0, t0                    ; ...
        call  rec_attr                  ; ...
        beqz  a0, tm_no                 ; the file has no such attribute
        lbu   t0, 4(a0)                 ; ...
        ld    t3, 8(a0)                 ; ...
        beqz  t0, tm_num                ; ...
        ld    a3, 24(s1)                ; a string: against a string, as bytes
        bltz  a3, tm_no                 ; ...
        lbu   a1, 5(a0)                 ; ...
        addi  a0, a0, 8                 ; ...
        ld    a2, 16(s1)                ; ...
        call  kcmp                      ; ...
        j     tm_cmp                    ; ...
tm_num:
        ld    t0, 24(s1)                ; a number: against a number
        bgez  t0, tm_no                 ; ...
        ld    t1, 16(s1)                ; ...
        sltu  a0, t1, t3                ; a0 = 1 greater, -1 less, 0 equal
        sltu  t2, t3, t1                ; ...
        sub   a0, a0, t2                ; ...
tm_cmp:
        ld    t0, 8(s1)                 ; how: 0 =, 1 <, 2 >
        beqz  t0, tm_eq                 ; ...
        li    t1, 1                     ; ...
        beq   t0, t1, tm_lt             ; ...
        bgtz  a0, tm_l                  ; ...
        j     tm_no                     ; ...
tm_lt:
        bltz  a0, tm_l                  ; ...
        j     tm_no                     ; ...
tm_eq:
        beqz  a0, tm_l                  ; ...
tm_no:
        li    a0, 0                     ; ...
tm_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

