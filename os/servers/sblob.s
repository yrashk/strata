; =============================================================================
; sblob.s: blobs: values of any length (included by fs.s)
; =============================================================================
;
; A value under a key is inline bytes (up to about a quarter page), or, with
; its flag set, a stream: u64 length, u64 stream id. A stream's pages are in
; the extent tree bl_ext points at (its namespace's ".ext"): u64 id, u64
; offset in pages (big-endian) -> u64 first page, u64 pages, u64 birth. A
; range with no extent reads as zeros. Stream pages go through the cache as
; tree pages do, without a header; pages this commit wrote are written again
; in place, older ones are replaced by new pages (tools/stdb/store.c, whose
; routines these follow).

        .data                           ; data Local Store
        .align 8                        ; ...
bl_ext:    .dword 0                     ; the extent tree of the blobs at work
st_sh:     .dword 0                     ; log2 of the page size
bl_vl:     .dword 0                     ; the value fetched: its length,
bl_fl:     .dword 0                     ;   its flag
bw_force:  .dword 0                     ; st_bwrite: a stream even when short
e_off:     .dword 0                     ; the extent ext_find found: offset in pages,
e_start:   .dword 0                     ;   first page,
e_pages:   .dword 0                     ;   pages,
e_birth:   .dword 0                     ;   the commit that wrote it
ek:        .space 16                    ; an extent's key and value at work
ek2:       .space 16                    ; ...
ev:        .space 24                    ; ...
bd:        .space 16                    ; a stream's value: length, id
bval:      .space 1024                  ; a value fetched

        .text                           ; instruction Local Store

; ext_key(a0 = id, a1 = offset in pages): -> ek
ext_key:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a1, 8(sp)                 ; ...
        call  bswap                     ; ...
        sd    a0, ek(zero)              ; ...
        ld    a0, 8(sp)                 ; ...
        call  bswap                     ; ...
        sd    a0, ek+8(zero)            ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; ext_got(): the record st_seek found (ek2, ev) -> e_off, e_start, e_pages, e_birth
ext_got:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        ld    a0, ek2+8(zero)           ; ...
        call  bswap                     ; ...
        sd    a0, e_off(zero)           ; ...
        ld    t0, ev(zero)              ; ...
        sd    t0, e_start(zero)         ; ...
        ld    t0, ev+8(zero)            ; ...
        sd    t0, e_pages(zero)         ; ...
        ld    t0, ev+16(zero)           ; ...
        sd    t0, e_birth(zero)         ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; ext_find(a0 = id, a1 = page of the stream) -> a0 = 1 and e_*: the extent that
; holds it; or 0, and e_off is where the next extent begins (-1: none does)
ext_find:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        mv    s1, a1                    ; ...
        call  ext_key                   ; ...
        ld    a0, bl_ext(zero)          ; the last extent at or before it
        la    a1, ek                    ; ...
        li    a2, 16                    ; ...
        li    a3, ST_LE                 ; ...
        la    a4, ek2                   ; ...
        la    a5, ev                    ; ...
        call  st_seek                   ; ...
        beqz  a0, xf_next               ; ...
        ld    t0, ek2(zero)             ; of this stream?
        ld    t1, ek(zero)              ; ...
        bne   t0, t1, xf_next           ; ...
        call  ext_got                   ; ...
        ld    t0, e_off(zero)           ; and reaching it?
        ld    t1, e_pages(zero)         ; ...
        add   t0, t0, t1                ; ...
        li    a0, 1                     ; ...
        bltu  s1, t0, xf_ret            ; ...
xf_next:
        li    t0, -1                    ; no: where does the next one begin?
        sd    t0, e_off(zero)           ; ...
        ld    a0, bl_ext(zero)          ; ...
        la    a1, ek                    ; ...
        li    a2, 16                    ; ...
        li    a3, ST_GT                 ; ...
        la    a4, ek2                   ; ...
        li    a5, 0                     ; ...
        call  st_seek                   ; ...
        beqz  a0, xf_ret                ; ...
        ld    t0, ek2(zero)             ; ...
        ld    t1, ek(zero)              ; ...
        li    a0, 0                     ; ...
        bne   t0, t1, xf_ret            ; ...
        ld    a0, ek2+8(zero)           ; ...
        call  bswap                     ; ...
        sd    a0, e_off(zero)           ; ...
        li    a0, 0                     ; ...
xf_ret:
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; ext_put(a0 = id, a1 = offset, a2 = first page, a3 = pages, a4 = birth)
ext_put:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a2, ev(zero)              ; ...
        sd    a3, ev+8(zero)            ; ...
        sd    a4, ev+16(zero)           ; ...
        call  ext_key                   ; ...
        ld    a0, bl_ext(zero)          ; ...
        la    a1, ek                    ; ...
        li    a2, 16                    ; ...
        la    a3, ev                    ; ...
        li    a4, 24                    ; ...
        li    a5, 0                     ; ...
        call  st_put                    ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; ext_cut(a0 = id, a1 = from, a2 = to): pages [from, to) of the stream leave
; the extent in e_*: the parts before and after stay
ext_cut:
        addi  sp, sp, -72               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        sd    s5, 40(sp)                ; ...
        sd    s6, 48(sp)                ; ...
        sd    s7, 56(sp)                ; ...
        mv    s1, a0                    ; s1 = the stream
        mv    s2, a1                    ; s2 = from
        mv    s3, a2                    ; s3 = to
        ld    s4, e_off(zero)           ; s4.. = the extent
        ld    s5, e_start(zero)         ; ...
        ld    s6, e_pages(zero)         ; ...
        ld    s7, e_birth(zero)         ; ...
        bleu  s2, s4, xc_del            ; a part before?
        mv    a0, s1                    ; ...
        mv    a1, s4                    ; ...
        mv    a2, s5                    ; ...
        sub   a3, s2, s4                ; ...
        mv    a4, s7                    ; ...
        call  ext_put                   ; ...
        j     xc_after                  ; ...
xc_del:
        mv    a0, s1                    ; no: its record goes
        mv    a1, s4                    ; ...
        call  ext_key                   ; ...
        ld    a0, bl_ext(zero)          ; ...
        la    a1, ek                    ; ...
        li    a2, 16                    ; ...
        call  st_del                    ; ...
xc_after:
        add   t0, s4, s6                ; a part after?
        bgeu  s3, t0, xc_free           ; ...
        mv    a0, s1                    ; ...
        mv    a1, s3                    ; ...
        sub   t1, s3, s4                ; ...
        add   a2, s5, t1                ; ...
        sub   a3, t0, s3                ; ...
        mv    a4, s7                    ; ...
        call  ext_put                   ; ...
xc_free:
        sub   t1, s2, s4                ; ...
        add   a0, s5, t1                ; ...
        sub   a1, s3, s2                ; ...
        mv    a2, s7                    ; ...
        call  pfree                     ; ...
        ld    s7, 56(sp)                ; ...
        ld    s6, 48(sp)                ; ...
        ld    s5, 40(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 72                ; ...
        ret                             ; ...

; bzero(a0 = address, a1 = bytes)
bzero:
        beqz  a1, bz_ret                ; ...
        sb    zero, 0(a0)               ; ...
        addi  a0, a0, 1                 ; ...
        addi  a1, a1, -1                ; ...
        j     bzero                     ; ...
bz_ret:
        ret                             ; ...

; s_write(a0 = id, a1 = the stream's length before, a2 = offset, a3 = bytes
; (in the D-LS, not in a page buffer or pgcopy), a4 = their count)
SW_ID   = 80                            ; s_write's frame: the stream,
SW_OLD  = 88                            ;   its length before,
SW_SRC  = 96                            ;   the first old page of the run (0: none),
SW_HAVE = 104                           ;   the extent found, kept while another is looked for
SW_HOFF = 112                           ;   ...
SW_HST  = 120                           ;   ...
SW_CNT  = 128                           ;   the bytes of this run
SW_J    = 136                           ;   the page of the run at work
SW_A    = 144                           ;   its part: from,
SW_B    = 152                           ;   to

s_write:
        addi  sp, sp, -160              ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        sd    s5, 40(sp)                ; ...
        sd    s6, 48(sp)                ; ...
        sd    s7, 56(sp)                ; ...
        sd    s8, 64(sp)                ; ...
        sd    a0, SW_ID(sp)             ; ...
        sd    a1, SW_OLD(sp)            ; ...
        mv    s1, a2                    ; s1 = the offset
        mv    s2, a3                    ; s2 = the bytes
        mv    s3, a4                    ; s3 = how many are left
swr_l:
        beqz  s3, swr_ret                ; ...
        ld    t0, st_sh(zero)           ; s4 = the stream's page
        srl   s4, s1, t0                ; ...
        ld    t1, st_ps(zero)           ; s5 = the offset in it
        addi  t2, t1, -1                ; ...
        and   s5, s1, t2                ; ...
        add   t2, s5, s3                ; s6 = the pages the bytes reach
        add   t2, t2, t1                ; ...
        addi  t2, t2, -1                ; ...
        srl   s6, t2, t0                ; ...
        ld    a0, SW_ID(sp)             ; ...
        mv    a1, s4                    ; ...
        call  ext_find                  ; ...
        sd    a0, SW_HAVE(sp)           ; ...
        sd    zero, SW_SRC(sp)          ; ...
        beqz  a0, swr_new                ; ...
        ld    t0, e_off(zero)           ; s7 = the pages of it from here on
        ld    t1, e_pages(zero)         ; ...
        add   s7, t0, t1                ; ...
        sub   s7, s7, s4                ; ...
        ld    t2, e_start(zero)         ; the old pages
        sub   t3, s4, t0                ; ...
        add   t2, t2, t3                ; ...
        sd    t2, SW_SRC(sp)            ; ...
        ld    t3, e_birth(zero)         ; this commit's: in place
        ld    t4, st_txn(zero)          ; ...
        bne   t3, t4, swr_cow            ; ...
        mv    s8, t2                    ; s8 = where the pages go
        bleu  s7, s6, swr_data           ; ...
        mv    s7, s6                    ; ...
        j     swr_data                   ; ...
swr_cow:
        bleu  s7, s6, swr_c1             ; older: new pages take their place
        mv    s7, s6                    ; ...
swr_c1:
        mv    a0, s7                    ; ...
        li    a1, 0                     ; ...
        call  alloc                     ; ...
        mv    s8, a0                    ; ...
        mv    s7, a1                    ; ...
        ld    a0, SW_ID(sp)             ; ...
        mv    a1, s4                    ; ...
        add   a2, s4, s7                ; ...
        call  ext_cut                   ; ...
        ld    a0, SW_ID(sp)             ; ...
        mv    a1, s4                    ; ...
        mv    a2, s8                    ; ...
        mv    a3, s7                    ; ...
        ld    a4, st_txn(zero)          ; ...
        call  ext_put                   ; ...
        j     swr_data                   ; ...
swr_new:
        mv    s7, s6                    ; a hole: up to the next extent
        ld    t0, e_off(zero)           ; ...
        li    t1, -1                    ; ...
        beq   t0, t1, swr_n1             ; ...
        sub   t0, t0, s4                ; ...
        bleu  s7, t0, swr_n1             ; ...
        mv    s7, t0                    ; ...
swr_n1:
        li    a1, 0                     ; after the extent before it, when that ends here
        sd    zero, SW_HOFF(sp)         ; ...
        beqz  s4, swr_n2                 ; ...
        ld    a0, SW_ID(sp)             ; ...
        addi  a1, s4, -1                ; ...
        call  ext_find                  ; ...
        li    a1, 0                     ; ...
        beqz  a0, swr_n2                 ; ...
        ld    a1, e_start(zero)         ; ...
        ld    t0, e_pages(zero)         ; ...
        add   a1, a1, t0                ; ...
        sd    a1, SW_HOFF(sp)           ; ...
swr_n2:
        mv    a0, s7                    ; ...
        call  alloc                     ; ...
        mv    s8, a0                    ; ...
        mv    s7, a1                    ; ...
        ld    t0, SW_HOFF(sp)           ; they follow it, and it is this commit's: it grows
        beqz  t0, swr_n3                 ; ...
        bne   t0, s8, swr_n3             ; ...
        ld    t0, e_birth(zero)         ; ...
        ld    t1, st_txn(zero)          ; ...
        bne   t0, t1, swr_n3             ; ...
        ld    a0, SW_ID(sp)             ; ...
        ld    a1, e_off(zero)           ; ...
        ld    a2, e_start(zero)         ; ...
        ld    a3, e_pages(zero)         ; ...
        add   a3, a3, s7                ; ...
        mv    a4, t1                    ; ...
        call  ext_put                   ; ...
        j     swr_data                   ; ...
swr_n3:
        ld    a0, SW_ID(sp)             ; an extent of their own
        mv    a1, s4                    ; ...
        mv    a2, s8                    ; ...
        mv    a3, s7                    ; ...
        ld    a4, st_txn(zero)          ; ...
        call  ext_put                   ; ...
swr_data:
        ld    t0, st_sh(zero)           ; the bytes of this run
        sll   t1, s7, t0                ; ...
        sub   t1, t1, s5                ; ...
        bleu  t1, s3, swr_d1             ; ...
        mv    t1, s3                    ; ...
swr_d1:
        sd    t1, SW_CNT(sp)            ; ...
        sd    zero, SW_J(sp)            ; ...
swr_pl:
        ld    t5, SW_J(sp)              ; every page of the run
        bgeu  t5, s7, swr_pd             ; ...
        ld    t0, st_sh(zero)           ; t2 = where the page starts in the stream
        add   t2, s4, t5                ; ...
        sll   t2, t2, t0                ; ...
        mv    t3, s1                    ; its part of the bytes: from,
        bgeu  t3, t2, swr_p1             ; ...
        mv    t3, t2                    ; ...
swr_p1:
        ld    t4, SW_CNT(sp)            ; to
        add   t4, t4, s1                ; ...
        ld    t1, st_ps(zero)           ; ...
        add   t6, t2, t1                ; ...
        bleu  t4, t6, swr_p2             ; ...
        mv    t4, t6                    ; ...
swr_p2:
        sd    t3, SW_A(sp)              ; ...
        sd    t4, SW_B(sp)              ; ...
        sub   t6, t4, t3                ; the whole page: nothing of the old one is kept
        beq   t6, t1, swr_whole          ; ...
        ld    t0, SW_SRC(sp)            ; an old page?
        beqz  t0, swr_whole              ; ...
        add   a0, t0, t5                ; ...
        beq   t0, s8, swr_inpl           ; ...
        call  PR                        ; a copy of it, in the new page
        mv    a1, a0                    ; ...
        la    a0, pgcopy                ; ...
        li    a2, 4096                  ; ...
        call  wcopy                     ; ...
        ld    t5, SW_J(sp)              ; ...
        add   a0, s8, t5                ; ...
        call  PRN                       ; ...
        mv    s6, a0                    ; s6 = the page's buffer
        la    a1, pgcopy                ; ...
        li    a2, 4096                  ; ...
        call  wcopy                     ; ...
        j     swr_tail                   ; ...
swr_inpl:
        call  PRW                       ; ...
        mv    s6, a0                    ; ...
        j     swr_tail                   ; ...
swr_whole:
        ld    t5, SW_J(sp)              ; ...
        add   a0, s8, t5                ; ...
        call  PRN                       ; ...
        mv    s6, a0                    ; ...
swr_tail:
        ld    t5, SW_J(sp)              ; nothing beyond the old end is kept
        ld    t0, st_sh(zero)           ; ...
        add   t2, s4, t5                ; ...
        sll   t2, t2, t0                ; ...
        ld    t1, st_ps(zero)           ; ...
        add   t6, t2, t1                ; ...
        ld    t3, SW_OLD(sp)            ; ...
        bgeu  t3, t6, swr_copy           ; ...
        li    t4, 0                     ; ...
        bleu  t3, t2, swr_z              ; ...
        sub   t4, t3, t2                ; ...
swr_z:
        add   a0, s6, t4                ; ...
        sub   a1, t1, t4                ; ...
        call  bzero                     ; ...
swr_copy:
        ld    t5, SW_J(sp)              ; the bytes
        ld    t0, st_sh(zero)           ; ...
        add   t2, s4, t5                ; ...
        sll   t2, t2, t0                ; ...
        ld    t3, SW_A(sp)              ; ...
        ld    t4, SW_B(sp)              ; ...
        sub   a0, t3, t2                ; ...
        add   a0, a0, s6                ; ...
        sub   a1, t3, s1                ; ...
        add   a1, a1, s2                ; ...
        sub   a2, t4, t3                ; ...
        call  srv_bcopy                 ; ...
        ld    t5, SW_J(sp)              ; ...
        addi  t5, t5, 1                 ; ...
        sd    t5, SW_J(sp)              ; ...
        j     swr_pl                     ; ...
swr_pd:
        ld    t1, SW_CNT(sp)            ; ...
        add   s1, s1, t1                ; ...
        add   s2, s2, t1                ; ...
        sub   s3, s3, t1                ; ...
        j     swr_l                      ; ...
swr_ret:
        ld    s8, 64(sp)                ; ...
        ld    s7, 56(sp)                ; ...
        ld    s6, 48(sp)                ; ...
        ld    s5, 40(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 160               ; ...
        ret                             ; ...

; s_trim(a0 = id, a1 = pages): the stream keeps its first pages
s_trim:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        beqz  s2, st_l                  ; an extent across the new end: cut there
        addi  a1, s2, -1                ; ...
        call  ext_find                  ; ...
        beqz  a0, st_l                  ; ...
        ld    t0, e_off(zero)           ; ...
        ld    t1, e_pages(zero)         ; ...
        add   a2, t0, t1                ; ...
        bleu  a2, s2, st_l              ; ...
        mv    a0, s1                    ; ...
        mv    a1, s2                    ; ...
        call  ext_cut                   ; ...
st_l:
        mv    a0, s1                    ; every extent from there on goes
        mv    a1, s2                    ; ...
        call  ext_key                   ; ...
        ld    a0, bl_ext(zero)          ; ...
        la    a1, ek                    ; ...
        li    a2, 16                    ; ...
        li    a3, ST_GE                 ; ...
        la    a4, ek2                   ; ...
        la    a5, ev                    ; ...
        call  st_seek                   ; ...
        beqz  a0, st_ret                ; ...
        ld    t0, ek2(zero)             ; ...
        ld    t1, ek(zero)              ; ...
        bne   t0, t1, st_ret            ; ...
        call  ext_got                   ; ...
        mv    a0, s1                    ; ...
        ld    a1, e_off(zero)           ; ...
        ld    a2, e_pages(zero)         ; ...
        add   a2, a2, a1                ; ...
        call  ext_cut                   ; ...
        j     st_l                      ; ...
st_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; st_bsize(a0 = tree, a1 = key, a2 = its length) -> a0 = the blob's length, or
; -1 if it is not there. The value is left in bval (bl_vl, bl_fl).
st_bsize:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        la    a3, bval                  ; ...
        call  st_get                    ; ...
        sd    a0, bl_vl(zero)           ; ...
        sd    a1, bl_fl(zero)           ; ...
        bltz  a0, bsz_ret               ; ...
        beqz  a1, bsz_ret               ; ...
        ld    a0, bval(zero)            ; a stream: its length
bsz_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; st_bread(a0 = tree, a1 = key, a2 = its length, a3 = offset, a4 = where the
; bytes go (D-LS), a5 = how many) -> a0 = how many were read (0 at the end),
; or -1 if the blob is not there
st_bread:
        addi  sp, sp, -72               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        sd    s5, 40(sp)                ; ...
        sd    s6, 48(sp)                ; ...
        sd    s7, 56(sp)                ; ...
        mv    s1, a3                    ; s1 = the offset
        mv    s2, a4                    ; s2 = the bytes' place
        mv    s3, a5                    ; s3 = how many
        call  st_bsize                  ; ...
        bltz  a0, br_ret                ; ...
        mv    t0, a0                    ; no more than there are
        li    a0, 0                     ; ...
        bgeu  s1, t0, br_ret            ; ...
        sub   t0, t0, s1                ; ...
        bleu  s3, t0, br_1              ; ...
        mv    s3, t0                    ; ...
br_1:
        ld    t0, bl_fl(zero)           ; ...
        bnez  t0, br_s                  ; ...
        mv    a0, s2                    ; inline
        la    a1, bval                  ; ...
        add   a1, a1, s1                ; ...
        mv    a2, s3                    ; ...
        call  srv_bcopy                 ; ...
        mv    a0, s3                    ; ...
        j     br_ret                    ; ...
br_s:
        ld    s4, bval+8(zero)          ; s4 = the stream
        li    s5, 0                     ; s5 = bytes done
br_l:
        bgeu  s5, s3, br_done           ; ...
        add   t0, s1, s5                ; s6 = the offset in the page, s7 = the bytes from it
        ld    t1, st_ps(zero)           ; ...
        addi  t2, t1, -1                ; ...
        and   s6, t0, t2                ; ...
        sub   s7, t1, s6                ; ...
        sub   t2, s3, s5                ; ...
        bleu  s7, t2, br_2              ; ...
        mv    s7, t2                    ; ...
br_2:
        mv    a0, s4                    ; ...
        ld    t1, st_sh(zero)           ; ...
        srl   a1, t0, t1                ; ...
        sd    a1, 64(sp)                ; ...
        call  ext_find                  ; ...
        beqz  a0, br_hole               ; ...
        ld    a0, 64(sp)                ; its page
        ld    t0, e_off(zero)           ; ...
        sub   a0, a0, t0                ; ...
        ld    t0, e_start(zero)         ; ...
        add   a0, a0, t0                ; ...
        call  PR                        ; ...
        add   a1, a0, s6                ; ...
        add   a0, s2, s5                ; ...
        mv    a2, s7                    ; ...
        call  srv_bcopy                 ; ...
        j     br_n                      ; ...
br_hole:
        add   a0, s2, s5                ; no extent: zeros
        mv    a1, s7                    ; ...
        call  bzero                     ; ...
br_n:
        add   s5, s5, s7                ; ...
        j     br_l                      ; ...
br_done:
        mv    a0, s3                    ; ...
br_ret:
        ld    s7, 56(sp)                ; ...
        ld    s6, 48(sp)                ; ...
        ld    s5, 40(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 72                ; ...
        ret                             ; ...

; st_bwrite(a0 = tree, a1 = key, a2 = its length, a3 = offset, a4 = bytes
; (D-LS; not bval, pgcopy or a page buffer), a5 = how many): the blob is made
; if it is not there; short ones stay in the tree unless bw_force is set
st_bwrite:
        addi  sp, sp, -80               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        sd    s5, 40(sp)                ; ...
        sd    s6, 48(sp)                ; ...
        sd    s7, 56(sp)                ; ...
        sd    s8, 64(sp)                ; ...
        mv    s1, a0                    ; s1 = the tree
        mv    s2, a1                    ; s2 = the key
        mv    s3, a2                    ; s3 = its length
        mv    s4, a3                    ; s4 = the offset
        mv    s5, a4                    ; s5 = the bytes
        mv    s6, a5                    ; s6 = how many
        call  begin                     ; ...
        mv    a0, s1                    ; ...
        mv    a1, s2                    ; ...
        mv    a2, s3                    ; ...
        call  st_bsize                  ; ...
        mv    s7, a0                    ; s7 = its length now
        bgez  s7, bw_1                  ; ...
        li    s7, 0                     ; (not there: empty, inline)
        sd    zero, bl_fl(zero)         ; ...
bw_1:
        add   s8, s4, s6                ; s8 = its length after
        bgeu  s8, s7, bw_2              ; ...
        mv    s8, s7                    ; ...
bw_2:
        ld    t0, bl_fl(zero)           ; ...
        bnez  t0, bw_stream             ; ...
        ld    t0, bw_force(zero)        ; ...
        bnez  t0, bw_conv               ; ...
        ld    t0, st_ps(zero)           ; short enough to stay inline?
        addi  t0, t0, -32               ; ...
        srli  t0, t0, 2                 ; ...
        addi  t0, t0, -2                ; ...
        srli  t0, t0, 3         ; (down to a whole word)
        slli  t0, t0, 3         ; ...
        addi  t0, t0, -8                ; ...
        addi  t1, s3, 7                 ; ...
        srli  t1, t1, 3         ; (down to a whole word)
        slli  t1, t1, 3         ; ...
        sub   t0, t0, t1                ; ...
        bgtu  s8, t0, bw_conv           ; ...
        la    a0, bval                  ; yes: zeros up to the offset, the bytes
        add   a0, a0, s7                ; ...
        sub   a1, s8, s7                ; ...
        call  bzero                     ; ...
        la    a0, bval                  ; ...
        add   a0, a0, s4                ; ...
        mv    a1, s5                    ; ...
        mv    a2, s6                    ; ...
        call  srv_bcopy                 ; ...
        mv    a0, s1                    ; ...
        mv    a1, s2                    ; ...
        mv    a2, s3                    ; ...
        la    a3, bval                  ; ...
        mv    a4, s8                    ; ...
        li    a5, 0                     ; ...
        call  st_put                    ; ...
        j     bw_ret                    ; ...
bw_conv:
        ld    t0, st_nextid(zero)       ; it becomes a stream: what it holds goes first
        sd    t0, 72(sp)                ; ...
        addi  t1, t0, 1                 ; ...
        sd    t1, st_nextid(zero)       ; ...
        beqz  s7, bw_w                  ; ...
        mv    a0, t0                    ; ...
        li    a1, 0                     ; ...
        li    a2, 0                     ; ...
        la    a3, bval                  ; ...
        mv    a4, s7                    ; ...
        call  s_write                   ; ...
        j     bw_w                      ; ...
bw_stream:
        ld    t0, bval+8(zero)          ; ...
        sd    t0, 72(sp)                ; ...
bw_w:
        ld    a0, 72(sp)                ; ...
        mv    a1, s7                    ; ...
        mv    a2, s4                    ; ...
        mv    a3, s5                    ; ...
        mv    a4, s6                    ; ...
        call  s_write                   ; ...
        sd    s8, bd(zero)              ; its value: length, id
        ld    t0, 72(sp)                ; ...
        sd    t0, bd+8(zero)            ; ...
        mv    a0, s1                    ; ...
        mv    a1, s2                    ; ...
        mv    a2, s3                    ; ...
        la    a3, bd                    ; ...
        li    a4, 16                    ; ...
        li    a5, 1                     ; ...
        call  st_put                    ; ...
bw_ret:
        ld    s8, 64(sp)                ; ...
        ld    s7, 56(sp)                ; ...
        ld    s6, 48(sp)                ; ...
        ld    s5, 40(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 80                ; ...
        ret                             ; ...

; st_btrunc(a0 = tree, a1 = key, a2 = its length, a3 = the blob's new length)
st_btrunc:
        addi  sp, sp, -56               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        sd    s5, 40(sp)                ; ...
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        mv    s3, a2                    ; ...
        mv    s4, a3                    ; s4 = the new length
        call  st_bsize                  ; ...
        bltz  a0, bt_ret                ; ...
        bleu  s4, a0, bt_cut            ; ...
        la    t0, reqbuf               ; longer: a zero byte at its new end
        sd    zero, 0(t0)               ; ...
        mv    a0, s1                    ; ...
        mv    a1, s2                    ; ...
        mv    a2, s3                    ; ...
        addi  a3, s4, -1                ; ...
        mv    a4, t0                    ; ...
        li    a5, 1                     ; ...
        call  st_bwrite                 ; ...
        j     bt_ret                    ; ...
bt_cut:
        ld    t0, bl_fl(zero)           ; ...
        bnez  t0, bt_s                  ; ...
        mv    a0, s1                    ; inline: fewer bytes
        mv    a1, s2                    ; ...
        mv    a2, s3                    ; ...
        la    a3, bval                  ; ...
        mv    a4, s4                    ; ...
        li    a5, 0                     ; ...
        call  st_put                    ; ...
        j     bt_ret                    ; ...
bt_s:
        ld    s5, bval+8(zero)          ; s5 = the stream
        mv    a0, s5                    ; its pages beyond go
        ld    t0, st_ps(zero)           ; ...
        add   a1, s4, t0                ; ...
        addi  a1, a1, -1                ; ...
        ld    t1, st_sh(zero)           ; ...
        srl   a1, a1, t1                ; ...
        call  s_trim                    ; ...
        ld    t0, st_ps(zero)           ; zeros after the new end in its last page
        addi  t0, t0, -1                ; ...
        and   t0, t0, s4                ; ...
        beqz  t0, bt_d                  ; ...
        mv    a0, s5                    ; ...
        ld    t1, st_sh(zero)           ; ...
        srl   a1, s4, t1                ; ...
        call  ext_find                  ; ...
        beqz  a0, bt_d                  ; ...
        la    a0, reqbuf               ; ...
        li    a1, 4096                  ; ...
        call  wzero                     ; ...
        mv    a0, s5                    ; ...
        mv    a1, s4                    ; ...
        mv    a2, s4                    ; ...
        la    a3, reqbuf               ; ...
        ld    t0, st_ps(zero)           ; ...
        addi  t1, t0, -1                ; ...
        and   t1, t1, s4                ; ...
        sub   a4, t0, t1                ; ...
        call  s_write                   ; ...
bt_d:
        sd    s4, bd(zero)              ; ...
        sd    s5, bd+8(zero)            ; ...
        mv    a0, s1                    ; ...
        mv    a1, s2                    ; ...
        mv    a2, s3                    ; ...
        la    a3, bd                    ; ...
        li    a4, 16                    ; ...
        li    a5, 1                     ; ...
        call  st_put                    ; ...
bt_ret:
        ld    s5, 40(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 56                ; ...
        ret                             ; ...

; st_bdel(a0 = tree, a1 = key, a2 = its length) -> a0 = 1 deleted, 0 not there
st_bdel:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        mv    s3, a2                    ; ...
        call  st_bsize                  ; ...
        li    t0, 0                     ; ...
        bltz  a0, bdl_no                ; ...
        ld    t0, bl_fl(zero)           ; ...
        beqz  t0, bdl_d                 ; ...
        ld    a0, bval+8(zero)          ; a stream: its pages go
        li    a1, 0                     ; ...
        call  s_trim                    ; ...
bdl_d:
        mv    a0, s1                    ; ...
        mv    a1, s2                    ; ...
        mv    a2, s3                    ; ...
        call  st_del                    ; ...
        j     bdl_ret                   ; ...
bdl_no:
        li    a0, 0                     ; ...
bdl_ret:
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; st_bload(a0 = tree, a1 = key, a2 = its length, a3 = offset in the attached
; arena (c7), a4 = the most bytes) -> a0 = the blob's length, all of it copied
; in; -4 not there; -1 longer than that. A stream's pages are read by the
; device straight into the arena, whole pages.
st_bload:
        addi  sp, sp, -56               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        sd    s5, 40(sp)                ; ...
        sd    s6, 48(sp)                ; ...
        mv    s1, a3                    ; s1 = the arena offset
        mv    s2, a4                    ; s2 = the most
        call  st_bsize                  ; ...
        mv    s3, a0                    ; s3 = its length
        li    a0, -4                    ; ...
        bltz  s3, bld_ret               ; ...
        ld    t0, st_ps(zero)           ; s4 = its pages
        add   s4, s3, t0                ; ...
        addi  s4, s4, -1                ; ...
        ld    t1, st_sh(zero)           ; ...
        srl   s4, s4, t1                ; ...
        sll   t2, s4, t1                ; whole pages must fit
        li    a0, -1                    ; ...
        bgtu  t2, s2, bld_ret           ; ...
        ld    t0, bl_fl(zero)           ; ...
        bnez  t0, bld_s                 ; ...
        beqz  s3, bld_ok                ; inline: by words
        la    t0, bval                  ; ...
        addi  t1, s3, 7                 ; ...
        srli  t1, t1, 3         ; (down to a whole word)
        slli  t1, t1, 3         ; ...
        tput  tg1, t0, c7, s1, t1       ; ...
        twait 1 << 1                    ; ...
        j     bld_ok                    ; ...
bld_s:
        ld    s5, bval+8(zero)          ; s5 = the stream
        call  b_sync                    ; what this commit wrote of it must be on the disk
        call  c_write                   ; ...
        li    s6, 0                     ; s6 = the page
bld_l:
        bgeu  s6, s4, bld_ok            ; ...
        mv    a0, s5                    ; ...
        mv    a1, s6                    ; ...
        call  ext_find                  ; ...
        beqz  a0, bld_hole              ; ...
        ld    t0, e_off(zero)           ; as many pages as the extent has from here
        ld    t1, e_pages(zero)         ; ...
        add   t1, t1, t0                ; ...
        sub   a2, t1, s6                ; ...
        sub   t2, s4, s6                ; ...
        bleu  a2, t2, bld_1             ; ...
        mv    a2, t2                    ; ...
bld_1:
        ld    a1, e_start(zero)         ; ...
        sub   t0, s6, t0                ; ...
        add   a1, a1, t0                ; ...
        ld    t1, st_bpp(zero)          ; ...
        mul   a1, a1, t1                ; ...
        add   t3, s6, a2                ; ...
        mul   a2, a2, t1                ; ...
        ld    t2, st_sh(zero)           ; ...
        sll   a3, s6, t2                ; ...
        add   a3, a3, s1                ; ...
        mv    s6, t3                    ; ...
        li    a0, 1                     ; ...
        li    a4, 7                     ; ...
        call  blkn                      ; ...
        bnez  a0, st_die                ; ...
        j     bld_l                     ; ...
bld_hole:
        la    a0, reqbuf               ; a page of zeros
        li    a1, 4096                  ; ...
        call  wzero                     ; ...
        la    t0, reqbuf               ; ...
        ld    t2, st_sh(zero)           ; ...
        sll   t1, s6, t2                ; ...
        add   t1, t1, s1                ; ...
        ld    t2, st_ps(zero)           ; ...
        tput  tg1, t0, c7, t1, t2       ; ...
        twait 1 << 1                    ; ...
        addi  s6, s6, 1                 ; ...
        j     bld_l                     ; ...
bld_ok:
        mv    a0, s3                    ; ...
bld_ret:
        ld    s6, 48(sp)                ; ...
        ld    s5, 40(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 56                ; ...
        ret                             ; ...
