; dbc_v(a0 = op, a1 = tree, a2 = key, a3 = its length, a4 = mode, a5 = the
; data's length after the key, which is at 64 + a6 of c5 already ... ) ->
; a0 = the result. The handle carries the extents' tree (bl_ext) and the
; key's length; a short key goes in word 56, a long one first in the data.
; (a6 = bytes of data put after the key; called with the key not yet put)
dbc_v:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        sd    a3, 24(sp)                ; ...
        sd    a4, 32(sp)                ; ...
        sd    a5, 40(sp)                ; ...
        mv    a0, a2                    ; ...
        mv    a1, a3                    ; ...
        call  dbc_key                   ; a0 = word 56, a1 = the data the key takes
        mv    a4, a0                    ; ...
        ld    a2, 40(sp)                ; the length: the key's data and the rest
        add   a2, a2, a1                ; ...
        ld    a1, 16(sp)                ; the handle
        ld    t0, bl_ext(zero)          ; ...
        slli  t0, t0, 16                ; ...
        or    a1, a1, t0                ; ...
        ld    t0, 24(sp)                ; ...
        slli  t0, t0, 32                ; ...
        or    a1, a1, t0                ; ...
        ld    a0, 8(sp)                 ; ...
        ld    a3, 32(sp)                ; ...
        call  dbc                       ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; ...

; dbc_koff(a1 = the key's length) -> a0 = where the data after a key starts
; (0 for a short key: it goes in word 56)
dbc_koff:
        li    a0, 0                     ; ...
        li    t0, 8                     ; ...
        bleu  a1, t0, dko_ret           ; ...
        addi  a0, a1, 7                 ; ...
        srli  a0, a0, 3                 ; ...
        slli  a0, a0, 3                 ; ...
dko_ret:
        ret                             ; ...

; st_bsize(a0 = tree, a1 = key, a2 = its length) -> a0 = the value's length,
; or -1 if it is not there. The value as the tree holds it is left in bval
; (bl_vl, bl_fl).
st_bsize:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        mv    a3, a2                    ; ...
        mv    a2, a1                    ; ...
        mv    a1, a0                    ; ...
        li    a0, DB_VSIZE              ; ...
        li    a4, 0                     ; ...
        li    a5, 0                     ; ...
        call  dbc_v                     ; ...
        sd    a0, 8(sp)                 ; ...
        la    t0, dbh                   ; ...
        ld    t1, 24(t0)                ; ...
        sd    t1, bl_fl(zero)           ; ...
        li    t1, -1                    ; ...
        sd    t1, bl_vl(zero)           ; ...
        bltz  a0, bsz_ret               ; ...
        ld    a1, 16(t0)                ; ...
        sd    a1, bl_vl(zero)           ; ...
        la    a0, bval                  ; ...
        li    a2, 0                     ; ...
        call  dbc_get                   ; ...
bsz_ret:
        ld    a0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; st_bread(a0 = tree, a1 = key, a2 = its length, a3 = offset, a4 = where the
; bytes go (D-LS), a5 = how many, <= 4032) -> a0 = how many were read (0 at
; the end), or -1 if the value is not there
st_bread:
        addi  sp, sp, -64               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a4, 8(sp)                 ; where the bytes go
        sd    a0, 24(sp)                ; (its length word is a count: the batch first)
        sd    a1, 32(sp)                ; ...
        sd    a2, 40(sp)                ; ...
        sd    a3, 48(sp)                ; ...
        sd    a5, 56(sp)                ; ...
        call  wb_flush                  ; ...
        ld    a1, 24(sp)                ; ...
        ld    a2, 32(sp)                ; ...
        ld    a3, 40(sp)                ; ...
        ld    a4, 48(sp)                ; mode = offset
        ld    a5, 56(sp)                ; length = bytes (no data)
        li    a0, DB_VREAD              ; ...
        call  dbc_vn                    ; ...
        sd    a0, 16(sp)                ; ...
        blez  a0, brd_ret               ; ...
        mv    a1, a0                    ; ...
        ld    a0, 8(sp)                 ; ...
        li    a2, 0                     ; ...
        call  dbc_get                   ; ...
brd_ret:
        ld    a0, 16(sp)                ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 64                ; ...
        ret                             ; ...

; dbc_vn(a0 = op, a1 = tree, a2 = key, a3 = its length, a4 = mode, a5 = the
; length word: a count, not the data's bytes (VREAD, VLOAD); a long key is
; the data) -> a0
dbc_vn:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a5, 8(sp)                 ; ...
        call  dbc_vpre                  ; ...
        ld    a2, 8(sp)                 ; ...
        call  dbc_vgo                   ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; dbc_vpre / dbc_vgo: dbc_v in two halves, so that the length word can be
; something else than the data's bytes (VREAD, VLOAD)
dbc_vpre:
        la    t1, db_a                  ; keep the arguments
        sd    a0, 0(t1)                 ; ...
        sd    a1, 8(t1)                 ; ...
        sd    a3, 16(t1)                ; ...
        sd    a4, 24(t1)                ; ...
        addi  sp, sp, -8                ; ...
        sd    ra, 0(sp)                 ; ...
        mv    a0, a2                    ; ...
        mv    a1, a3                    ; ...
        call  dbc_key                   ; ...
        la    t1, db_a                  ; ...
        sd    a0, 32(t1)                ; word 56
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...
dbc_vgo:
        addi  sp, sp, -8                ; (a2 = the length word)
        sd    ra, 0(sp)                 ; ...
        la    t1, db_a                  ; ...
        ld    a0, 0(t1)                 ; ...
        ld    a1, 8(t1)                 ; the handle: tree | extents << 16 | key length << 32
        ld    t0, bl_ext(zero)          ; ...
        slli  t0, t0, 16                ; ...
        or    a1, a1, t0                ; ...
        ld    t0, 16(t1)                ; ...
        slli  t0, t0, 32                ; ...
        or    a1, a1, t0                ; ...
        ld    a3, 24(t1)                ; ...
        ld    a4, 32(t1)                ; ...
        call  dbc                       ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; st_bwrite(a0 = tree, a1 = key, a2 = its length, a3 = offset, a4 = bytes
; (D-LS), a5 = how many): the value is made if it is not there; short ones
; stay in the tree unless bw_force is set. Parts of DB_CHUNK bytes at most
; (less the key's) go in a message each.
st_bwrite:
        addi  sp, sp, -64               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        sd    s5, 40(sp)                ; ...
        sd    s6, 48(sp)                ; ...
        sd    s7, 56(sp)                ; ...
        mv    s1, a0                    ; s1 = tree, s2 = key, s3 = its length,
        mv    s2, a1                    ;   s4 = offset, s5 = bytes, s6 = left
        mv    s3, a2                    ; ...
        mv    s4, a3                    ; ...
        mv    s5, a4                    ; ...
        mv    s6, a5                    ; ...
        mv    a1, s3                    ; s7 = the most per message
        call  dbc_koff                  ; ...
        li    s7, DB_CHUNK              ; ...
        sub   s7, s7, a0                ; ...
        ld    t0, wb_len(zero)          ; the batch goes with it if both fit, else first
        addi  t1, s6, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        add   t1, t1, t0                ; ...
        bleu  t1, s7, bw_l              ; ...
        call  wb_flush                  ; ...
bw_l:
        mv    a1, s3                    ; where the bytes go in the data
        call  dbc_koff                  ; ...
        mv    a2, a0                    ; ...
        mv    a1, s6                    ; this part
        bleu  a1, s7, bw_n              ; ...
        mv    a1, s7                    ; ...
bw_n:
        sd    a1, db_a+40(zero)         ; ...
        mv    a0, s5                    ; ...
        call  dbc_put                   ; ...
        li    a0, DB_VWRITE             ; ...
        mv    a1, s1                    ; ...
        mv    a2, s2                    ; ...
        mv    a3, s3                    ; ...
        mv    a4, s4                    ; mode: offset, and a stream even when short
        ld    t0, bw_force(zero)        ; ...
        slli  t0, t0, 63                ; ...
        or    a4, a4, t0                ; ...
        ld    a5, db_a+40(zero)         ; ...
        call  dbc_v                     ; ...
        ld    t0, db_a+40(zero)         ; ...
        add   s4, s4, t0                ; ...
        add   s5, s5, t0                ; ...
        sub   s6, s6, t0                ; ...
        bnez  s6, bw_l                  ; ...
        ld    s7, 56(sp)                ; ...
        ld    s6, 48(sp)                ; ...
        ld    s5, 40(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 64                ; ...
        ret                             ; ...

; st_btrunc(a0 = tree, a1 = key, a2 = its length, a3 = the value's new length)
st_btrunc:
        mv    a4, a3                    ; mode = the new length
        mv    a3, a2                    ; ...
        mv    a2, a1                    ; ...
        mv    a1, a0                    ; ...
        li    a0, DB_VTRUNC             ; ...
        li    a5, 0                     ; ...
        j     dbc_v                     ; ...

; st_bdel(a0 = tree, a1 = key, a2 = its length) -> a0 = 1 deleted, 0 not there
st_bdel:
        mv    a3, a2                    ; ...
        mv    a2, a1                    ; ...
        mv    a1, a0                    ; ...
        li    a0, DB_VDEL               ; ...
        li    a4, 0                     ; ...
        li    a5, 0                     ; ...
        j     dbc_v                     ; ...

; st_bload(a0 = tree, a1 = key, a2 = its length, a3 = offset in the attached
; arena (c7), a4 = the most bytes) -> a0 = the value's length, all of it
; copied in; -4 not there; -1 longer than that. The arena is lent to db (and
; by it to blk, and by blk to the device); the request we serve waits in c4.
st_bload:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a4, 8(sp)                 ; ...
        sd    a0, 16(sp)                ; (its length word is a count: the batch first)
        sd    a1, 24(sp)                ; ...
        sd    a2, 32(sp)                ; ...
        sd    a3, 40(sp)                ; ...
        call  wb_flush                  ; ...
        ld    a0, 16(sp)                ; ...
        ld    a1, 24(sp)                ; ...
        ld    a2, 32(sp)                ; ...
        ld    a3, 40(sp)                ; ...
        ld    a4, 8(sp)                 ; ...
        mv    a4, a3                    ; mode = the offset
        mv    a3, a2                    ; ...
        mv    a2, a1                    ; ...
        mv    a1, a0                    ; ...
        li    a0, DB_VLOAD              ; ...
        call  dbc_vpre                  ; ...
        la    t1, db_a                  ; the header (dbc's first half)
        ld    a0, 0(t1)                 ; ...
        ld    a1, 8(t1)                 ; ...
        ld    t0, bl_ext(zero)          ; ...
        slli  t0, t0, 16                ; ...
        or    a1, a1, t0                ; ...
        ld    t0, 16(t1)                ; ...
        slli  t0, t0, 32                ; ...
        or    a1, a1, t0                ; ...
        ld    a2, 8(sp)                 ; ...
        ld    a3, 24(t1)                ; ...
        ld    a4, 32(t1)                ; ...
        la    t0, dbh                   ; ...
        sd    a0, 0(t0)                 ; ...
        sd    a1, 8(t0)                 ; ...
        sd    a2, 16(t0)                ; ...
        sd    a3, 24(t0)                ; ...
        sd    zero, 32(t0)              ; ...
        ld    t1, dbsel(zero)           ; ...
        sd    t1, 48(t0)                ; ...
        sd    a4, 56(t0)                ; ...
        li    t1, 64                    ; ...
        tput  tg10, t0, c5, zero, t1    ; ...
        twait 1 << 10                   ; ...
        cvalid t0, c6                   ; the request aside: the arena comes back in c6
        beqz  t0, bl_q                  ; ...
        cmov  c4, c6                    ; ...
bl_q:
        li    a0, SVC_SEND              ; through c1, c7 attached
        li    a1, 1                     ; ...
        li    a2, -1                    ; ...
        li    a3, 0                     ; ...
        li    a4, 5                     ; ...
        li    a5, 7                     ; ...
        svc                             ; ...
bl_w:
        beqz  a0, bl_back               ; ...
        li    t1, -1                    ; ...
        beq   a0, t1, bl_back           ; (not sent: the header says -1)
        li    a0, 1                     ; woken early: wait on
        li    a1, -1                    ; ...
        li    a2, -1                    ; ...
        li    a3, 0                     ; ...
        li    a4, 5                     ; ...
        svc                             ; ...
        j     bl_w                      ; ...
bl_back:
        cvalid t0, c6                   ; the arena back in c7
        beqz  t0, bl_r                  ; ...
        cmov  c7, c6                    ; ...
bl_r:
        cvalid t0, c4                   ; the request back in c6
        beqz  t0, bl_h                  ; ...
        cmov  c6, c4                    ; ...
bl_h:
        call  dbc_back                  ; the answer (dbc's second half)
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; ...

; ---- commits ------------------------------------------------------------------------

; st_commit(): everything changed since the last commit is on the disk, or
; (the power going before the meta block is written) none of it is
st_commit:
        li    a0, DB_COMMIT             ; ...
dbc_0:
        li    a1, 0                     ; ...
        li    a2, 0                     ; ...
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        j     dbc                       ; ...

; st_abort(): back to the last commit (every tree is to be opened again)
st_abort:
        li    a0, DB_ABORT              ; ...
        j     dbc_0                     ; ...

; st_info() -> a0 = 0, or -5: db's INFO -> st_ps, st_bpp, st_npages,
; st_nfree, st_cmt, st_deadlim, st_total (st_txn comes with every answer)
st_info:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        li    a0, DB_INFO               ; ...
        call  dbc_0                     ; ...
        li    t0, 8                     ; ...
        bne   a0, t0, sti_ret           ; ...
        la    a0, dbs                   ; ...
        li    a1, 64                    ; ...
        li    a2, 0                     ; ...
        call  dbc_get                   ; ...
        la    t0, dbs                   ; ...
        ld    t1, 0(t0)                 ; ...
        sd    t1, st_ps(zero)           ; ...
        ld    t1, 8(t0)                 ; ...
        sd    t1, st_bpp(zero)          ; ...
        ld    t1, 16(t0)                ; ...
        sd    t1, st_npages(zero)       ; ...
        ld    t1, 24(t0)                ; ...
        sd    t1, st_nfree(zero)        ; ...
        ld    t1, 40(t0)                ; ...
        sd    t1, st_cmt(zero)          ; ...
        ld    t1, 48(t0)                ; ...
        sd    t1, st_deadlim(zero)      ; ...
        ld    t1, 56(t0)                ; ...
        sd    t1, st_total(zero)        ; ...
        li    a0, 0                     ; ...
sti_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...
