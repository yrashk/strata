; =============================================================================
; dbcall.s: the store, from fs: calls to db (included by fs.s)
; =============================================================================
;
; The store is db's (os/servers/db.s; doc/fs-split.md). These routines have
; the names and the arguments of the store's own (store.s, storew.s,
; sblob.s), so the file system's code calls them as it did when the store
; was part of it; each is a message to db. A tree is db's handle for it.
; What the store's routines left in variables (sk_kl, bl_vl, bval ...) is
; left there here too.
;
; Read-ahead. A walk over a tree (st_seek after st_seek, or st_get of keys
; that grow) is answered from records db sent in one SCAN: up to 4 KiB of
; them, kept for two trees at a time. Any call that may change something
; (anything but GET, SEEK, VSIZE, VREAD, INFO, SCAN, DBGET, DBSCAN) drops
; them, so nothing older than the last change is ever answered.
;
; Writes later. st_put and st_del (whose answers the file system does not
; look at) send nothing: they are items of a batch, which goes with the next
; call to db, after its data (header word 48 says how many bytes); db applies
; it first. A call whose data is long (st_bwrite, the store for programs,
; BOOT) sends the batch alone first (FLUSH).
;
; A call that db answers with a failure of the store (the reply's count of
; aborts changed: it gave up the commit under way; or -5: the disk cannot be
; read) goes to st_full (-1) or st_die (-5), as it did inside the store.
;
; Capability registers: c1 the endpoint to db's core, c5 our message buffer;
; VLOAD lends the attachment (c7) and keeps the request (c6) in c4 meanwhile.

ST_GE   = 0                             ; st_seek: at or after the key
ST_GT   = 1                             ; after
ST_LE   = 2                             ; at or before
ST_LT   = 3                             ; before
SVC_SEND = 12                           ; svc: send, with an attachment or not
SEL     = 0x53 << 56                    ; header word 48: a server's index on its core
DB_TREE = 70                            ; db's calls
DB_GET  = 71                            ; ...
DB_SEEK = 72                            ; ...
DB_PUT  = 73                            ; ...
DB_DEL  = 74                            ; ...
DB_VSIZE = 75                           ; ...
DB_VREAD = 76                           ; ...
DB_VWRITE = 77                          ; ...
DB_VTRUNC = 78                          ; ...
DB_VDEL = 79                            ; ...
DB_VLOAD = 80                           ; ...
DB_COMMIT = 81                          ; ...
DB_ABORT = 82                           ; ...
DB_INFO = 83                            ; ...
DB_SNAP = 84                            ; ...
DB_SNAPT = 85                           ; ...
DB_BOOT = 86                            ; ...
DB_SCAN = 87                            ; ...
DB_FLUSH = 88                           ; ...
WB_MAX  = 2400                          ; a batch's most bytes (what a call's data leaves)
DB_READS = (1 << 0) | (1 << 1) | (1 << 7) | (1 << 8) | (1 << 11) | (1 << 12) | (1 << 19) | (1 << 23) ; (op - 64): no change
RC_TREE = 0                             ; a read-ahead slot: its tree (0: none),
RC_N    = 8                             ;   records,
RC_EOT  = 16                            ;   1: the tree has none after the last,
RC_SKL  = 24                            ;   the key it starts from: its length,
RC_SS   = 32                            ;   1: after it (ST_GT), 0: at or after it,
RC_USE  = 40                            ;   when it was last used,
RC_LAST = 48                            ;   the last record (its address),
RC_SKEY = 56                            ;   the key (480 bytes at most),
RC_POS  = 536                           ;   the record answered last, and how many from it on
RC_PN   = 544                           ;   ...
RC_BUF  = 552                           ;   the records, as SCAN answers them
RC_SIZE = 552 + 4032                    ; ...
DB_CHUNK = 4032                         ; a message's data

        .data                           ; data Local Store
        .align 8                        ; ...
dbsel:     .dword 0                     ; header word 48 for db
db_ab:     .dword 0                     ; db's count of aborts, as last seen
dbh:       .space 64                    ; a request to db, then its answer
dbk:       .space 8                     ; a short key
st_ps:     .dword 0                     ; the page size
st_bpp:    .dword 0                     ; blocks per page
st_sh:     .dword 0                     ; log2 of the page size
st_txn:    .dword 0                     ; the commit under way
st_cmt:    .dword 0                     ; the last commit on the disk
st_npages: .dword 0                     ; pages on the disk
st_nfree:  .dword 0                     ; free pages
st_deadlim: .dword 0                    ; the newest snapshot's commit
st_total:  .dword 0                     ; the disk's blocks
sk_kl:     .dword 0                     ; st_seek's answer: key length,
sk_vl:     .dword 0                     ;   value length,
sk_fl:     .dword 0                     ;   the value's flag
bl_ext:    .dword 0                     ; the extent tree of the values at work
bl_vl:     .dword 0                     ; st_bsize: the value's length as the tree holds it,
bl_fl:     .dword 0                     ;   its flag
bw_force:  .dword 0                     ; st_bwrite: a stream even when short
db_a:      .space 48                    ; a call's arguments
rc_k:      .dword 0                     ; rc_covers: the key,
rc_kl:     .dword 0                     ;   its length
rc_slot:   .dword 0                     ; rc_first: the slot
wb_len:    .dword 0                     ; the batch: its bytes (wb)
bval:      .space 1024                  ; st_bsize: the value as the tree holds it
rc_clock:  .dword 0                     ; read-ahead: the count of uses

        .text                           ; instruction Local Store

; dbc(a0 = op, a1 = handle, a2 = length, a3 = mode, a4 = word 56) -> a0 =
; the result; the answer's header in dbh. The data is at 64 of c5 already.
dbc:
        addi  t1, a0, -64               ; a call that may change something: the
        li    t2, 64                    ;   read-ahead goes
        bgeu  t1, t2, dbc_clr           ; ...
        li    t2, DB_READS              ; ...
        srl   t2, t2, t1                ; ...
        andi  t2, t2, 1                 ; ...
        bnez  t2, dbc_go                ; ...
dbc_clr:
        la    t1, rcs                   ; ...
        sd    zero, RC_TREE(t1)         ; ...
        li    t2, RC_SIZE               ; ...
        add   t1, t1, t2                ; ...
        sd    zero, RC_TREE(t1)         ; ...
dbc_go:
        ld    t3, wb_len(zero)          ; a batch: after the data, its length in word 48
        beqz  t3, dbc_hd                ; ...
        addi  t4, a2, 7                 ; ...
        srli  t4, t4, 3                 ; ...
        slli  t4, t4, 3                 ; ...
        addi  t4, t4, 64                ; ...
        la    t5, wb                    ; ...
        tput  tg10, t5, c5, t4, t3      ; ...
        sd    zero, wb_len(zero)        ; ...
dbc_hd:
        la    t0, dbh                   ; the header
        sd    a0, 0(t0)                 ; ...
        sd    a1, 8(t0)                 ; ...
        sd    a2, 16(t0)                ; ...
        sd    a3, 24(t0)                ; ...
        sd    zero, 32(t0)              ; ...
        ld    t1, dbsel(zero)           ; ...
        slli  t3, t3, 16                ; ...
        or    t1, t1, t3                ; ...
        sd    t1, 48(t0)                ; ...
        sd    a4, 56(t0)                ; ...
        li    t1, 64                    ; ...
        tput  tg10, t0, c5, zero, t1    ; ...
        twait 1 << 10                   ; ...
        li    a5, -1                    ; nothing attached
dbc_send:
        li    a0, SVC_SEND              ; through c1
        li    a1, 1                     ; ...
        li    a2, -1                    ; ...
        li    a3, 0                     ; ...
        li    a4, 5                     ; ...
        svc                             ; ...
dbc_w:
        beqz  a0, dbc_back              ; ...
        li    t1, -1                    ; not sent: as -5 (the store is out of reach)
        beq   a0, t1, dbc_lost          ; ...
        li    a0, 1                     ; woken early: wait on
        li    a1, -1                    ; ...
        li    a2, -1                    ; ...
        li    a3, 0                     ; ...
        li    a4, 5                     ; ...
        svc                             ; ...
        j     dbc_w                     ; ...
dbc_lost:
        j     st_die                    ; ...
dbc_back:
        la    t0, dbh                   ; the answer
        li    t1, 64                    ; ...
        tget  tg10, t0, c5, zero, t1    ; ...
        twait 1 << 10                   ; ...
        ld    t1, 56(t0)                ; the commit under way, db's aborts
        slli  t2, t1, 16                ; ...
        srli  t2, t2, 16                ; ...
        sd    t2, st_txn(zero)          ; ...
        srli  t1, t1, 48                ; ...
        ld    t2, db_ab(zero)           ; ...
        ld    a0, 32(t0)                ; ...
        bne   t1, t2, dbc_ab            ; ...
        li    t1, -5                    ; ...
        beq   a0, t1, st_die            ; ...
        ret                             ; ...
dbc_ab:
        sd    t1, db_ab(zero)           ; db gave up the commit under way
        li    t1, -1                    ; ...
        beq   a0, t1, st_full           ; ...
        j     st_die                    ; ...

; dbc_put(a0 = D-LS address, a1 = bytes, a2 = offset in the data): more of
; the request's data; an address not on a word goes through dbs
dbc_put:
        beqz  a1, dbp_ret               ; ...
        andi  t0, a0, 7                 ; ...
        beqz  t0, dbp_go                ; ...
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a1, 8(sp)                 ; ...
        sd    a2, 16(sp)                ; ...
        mv    t0, a0                    ; ...
        la    a0, dbs                   ; ...
        mv    a2, a1                    ; ...
        mv    a1, t0                    ; ...
        call  srv_bcopy                 ; ...
        la    a0, dbs                   ; ...
        ld    a1, 8(sp)                 ; ...
        ld    a2, 16(sp)                ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
dbp_go:
        addi  a1, a1, 7                 ; whole words
        srli  a1, a1, 3                 ; ...
        slli  a1, a1, 3                 ; ...
        addi  t1, a2, 64                ; ...
        tput  tg10, a0, c5, t1, a1      ; ...
        twait 1 << 10                   ; (before the buffer leaves, or dbs is used again)
dbp_ret:
        ret                             ; ...

; dbc_get(a0 = D-LS address, a1 = bytes, a2 = offset in the data): the
; answer's data -> there (a whole word more may be written: padded)
dbc_get:
        j     dbc_getat                 ; ...

; dbc_key(a0 = key, a1 = its length) -> a0 = what goes in word 56 when the
; key is 8 bytes or shorter (the key itself), else 0 and the key is the
; data's start (padded); a1 = the bytes of data the key takes
dbc_key:
        li    t0, 8                     ; ...
        bgtu  a1, t0, dbk_long          ; ...
        sd    zero, dbk(zero)           ; short: a word
        beqz  a1, dbk_s                 ; ...
        mv    t1, a0                    ; ...
        la    t2, dbk                   ; ...
        mv    t3, a1                    ; ...
dbk_c:
        lbu   t4, 0(t1)                 ; ...
        sb    t4, 0(t2)                 ; ...
        addi  t1, t1, 1                 ; ...
        addi  t2, t2, 1                 ; ...
        addi  t3, t3, -1                ; ...
        bnez  t3, dbk_c                 ; ...
dbk_s:
        ld    a0, dbk(zero)             ; ...
        li    a1, 0                     ; ...
        ret                             ; ...
dbk_long:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a1, 8(sp)                 ; ...
        li    a2, 0                     ; ...
        call  dbc_put                   ; ...
        li    a0, 0                     ; ...
        ld    a1, 8(sp)                 ; ...
        addi  a1, a1, 7                 ; ...
        srli  a1, a1, 3                 ; ...
        slli  a1, a1, 3                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; ---- the trees -------------------------------------------------------------------------

; st_tree(a0 = namespace, a1 = name, a2 = its length (<= 28), a3 = 1: make it
; if it is not there) -> a0 = the tree, or 0
st_tree:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        sd    a2, 16(sp)                ; ...
        sd    a3, 24(sp)                ; ...
        mv    a0, a1                    ; the name
        mv    a1, a2                    ; ...
        li    a2, 0                     ; ...
        call  dbc_put                   ; ...
        li    a0, DB_TREE               ; ...
        ld    a1, 8(sp)                 ; ...
        ld    a2, 16(sp)                ; ...
        ld    a3, 24(sp)                ; ...
        li    a4, 0                     ; ...
        call  dbc                       ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; st_get(a0 = tree, a1 = key, a2 = its length, a3 = where the value goes (0:
; nowhere; padded to a word)) -> a0 = the value's length, or -1 if the key is
; not there; a1 = its flag. From the read-ahead when it holds the key's place;
; a key past what it holds of that tree reads ahead from there
st_get:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        sd    a2, 24(sp)                ; ...
        sd    a3, 32(sp)                ; ...
        call  rc_find                   ; a slot for the tree?
        beqz  a0, sg_one                ; no: a GET, and a slot that remembers the key
        sd    a0, 40(sp)                ; ...
        ld    a1, 16(sp)                ; past it?
        ld    a2, 24(sp)                ; ...
        call  rc_past                   ; ...
        bnez  a0, sg_scan               ; yes: read ahead from the key
        ld    a0, 40(sp)                ; held?
        ld    a1, 16(sp)                ; ...
        ld    a2, 24(sp)                ; ...
        li    a3, ST_GE                 ; ...
        call  rc_covers                 ; ...
        beqz  a0, sg_one                ; ...
sg_cache:
        ld    a0, 40(sp)                ; the first record at or after the key
        ld    a1, 16(sp)                ; ...
        ld    a2, 24(sp)                ; ...
        li    a3, ST_GE                 ; ...
        call  rc_first                  ; ...
        beqz  a0, sg_no                 ; (none: not there)
        sd    a0, 40(sp)                ; that very key?
        addi  a0, a0, 8                 ; ...
        lhu   a1, -8(a0)                ; ...
        ld    a2, 16(sp)                ; ...
        ld    a3, 24(sp)                ; ...
        call  kcmp                      ; ...
        bnez  a0, sg_no                 ; ...
        ld    t0, 40(sp)                ; yes: its value
        lhu   t1, 0(t0)                 ; ...
        addi  t1, t1, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        addi  a1, t0, 8                 ; ...
        add   a1, a1, t1                ; ...
        lhu   a2, 2(t0)                 ; ...
        ld    a0, 32(sp)                ; ...
        beqz  a0, sg_fl                 ; ...
        call  rc_copy                   ; ...
sg_fl:
        ld    t0, 40(sp)                ; ...
        lhu   a0, 2(t0)                 ; ...
        lwu   a1, 4(t0)                 ; ...
        j     sg_ret                    ; ...
sg_no:
        li    a0, -1                    ; ...
        li    a1, 0                     ; ...
        j     sg_ret                    ; ...
sg_scan:
        ld    a0, 8(sp)                 ; SCAN from the key into a slot
        ld    a1, 16(sp)                ; ...
        ld    a2, 24(sp)                ; ...
        li    a3, ST_GE                 ; ...
        call  rc_scan                   ; ...
        sd    a0, 40(sp)                ; ...
        j     sg_cache                  ; ...
sg_one:
        ld    a0, 8(sp)                 ; a slot that remembers the key (no records)
        ld    a1, 16(sp)                ; ...
        ld    a2, 24(sp)                ; ...
        li    a3, ST_GE                 ; ...
        call  rc_new                    ; ...
        ld    a0, 16(sp)                ; the key
        ld    a1, 24(sp)                ; ...
        li    a2, 0                     ; ...
        call  dbc_put                   ; ...
        li    a0, DB_GET                ; ...
        ld    a1, 8(sp)                 ; ...
        ld    a2, 24(sp)                ; ...
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        call  dbc                       ; ...
        bltz  a0, sg_f                  ; ...
        ld    t0, 32(sp)                ; the value
        beqz  t0, sg_f                  ; ...
        sd    a0, 24(sp)                ; ...
        mv    a1, a0                    ; ...
        mv    a0, t0                    ; ...
        li    a2, 0                     ; ...
        call  dbc_get                   ; ...
        ld    a0, 24(sp)                ; ...
sg_f:
        la    t0, dbh                   ; ...
        ld    a1, 24(t0)                ; the flag
sg_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; ...

; st_seek(a0 = tree, a1 = key, a2 = its length, a3 = ST_GE / GT / LE / LT, a4 =
; where the found key goes, a5 = where its value goes (either 0: nowhere;
; each padded to a word; a4 may be the key's own place) -> a0 = 1 and
; sk_kl, sk_vl, sk_fl, or 0: the nearest record on that side of the key.
; ST_GE and ST_GT from the read-ahead (a SCAN when it does not hold it)
st_seek:
        addi  sp, sp, -64               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        sd    a2, 24(sp)                ; ...
        sd    a3, 32(sp)                ; ...
        sd    a4, 40(sp)                ; ...
        sd    a5, 48(sp)                ; ...
        li    t0, ST_GT                 ; backwards: one SEEK
        bgtu  a3, t0, ssk_one           ; ...
        call  rc_find                   ; ...
        beqz  a0, ssk_scan              ; ...
        sd    a0, 56(sp)                ; ...
        ld    a1, 16(sp)                ; held?
        ld    a2, 24(sp)                ; ...
        ld    a3, 32(sp)                ; ...
        call  rc_covers                 ; ...
        beqz  a0, ssk_scan              ; ...
ssk_cache:
        ld    a0, 56(sp)                ; ...
        ld    a1, 16(sp)                ; ...
        ld    a2, 24(sp)                ; ...
        ld    a3, 32(sp)                ; ...
        call  rc_first                  ; ...
        bnez  a0, ssk_rec               ; ...
        ld    t0, 56(sp)                ; none held: none at all if the tree ends there
        ld    t1, RC_EOT(t0)            ; ...
        bnez  t1, ssk_none              ; ...
        j     ssk_scan                  ; ...
ssk_rec:
        sd    a0, 56(sp)                ; the record
        lhu   t1, 0(a0)                 ; ...
        sd    t1, sk_kl(zero)           ; ...
        lhu   t1, 2(a0)                 ; ...
        sd    t1, sk_vl(zero)           ; ...
        lwu   t1, 4(a0)                 ; ...
        sd    t1, sk_fl(zero)           ; ...
        ld    a0, 40(sp)                ; its key
        beqz  a0, ssk_v                 ; ...
        ld    a1, 56(sp)                ; ...
        addi  a1, a1, 8                 ; ...
        ld    a2, sk_kl(zero)           ; ...
        call  rc_copy                   ; ...
ssk_v:
        ld    a0, 48(sp)                ; its value
        beqz  a0, ssk_yes               ; ...
        ld    a1, 56(sp)                ; ...
        ld    t0, sk_kl(zero)           ; ...
        addi  t0, t0, 7                 ; ...
        srli  t0, t0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        addi  a1, a1, 8                 ; ...
        add   a1, a1, t0                ; ...
        ld    a2, sk_vl(zero)           ; ...
        call  rc_copy                   ; ...
ssk_yes:
        li    a0, 1                     ; ...
        j     ssk_ret                   ; ...
ssk_none:
        li    a0, 0                     ; ...
        j     ssk_ret                   ; ...
ssk_scan:
        ld    a0, 8(sp)                 ; SCAN from the key: its first record is the answer
        ld    a1, 16(sp)                ; ...
        ld    a2, 24(sp)                ; ...
        ld    a3, 32(sp)                ; ...
        call  rc_scan                   ; ...
        sd    a0, 56(sp)                ; ...
        ld    t0, RC_N(a0)              ; none: the tree ends there
        beqz  t0, ssk_none              ; ...
        la    a0, RC_BUF                ; ...
        ld    t0, 56(sp)                ; ...
        add   a0, a0, t0                ; ...
        j     ssk_rec                   ; ...
ssk_one:
        ld    a0, 16(sp)                ; the key
        ld    a1, 24(sp)                ; ...
        li    a2, 0                     ; ...
        call  dbc_put                   ; ...
        li    a0, DB_SEEK               ; ...
        ld    a1, 8(sp)                 ; ...
        ld    a2, 24(sp)                ; ...
        ld    a3, 32(sp)                ; ...
        li    a4, 0                     ; ...
        call  dbc                       ; ...
        beqz  a0, ssk_ret               ; ...
        la    t0, dbh                   ; the key's and the value's lengths, the flag
        ld    t1, 16(t0)                ; ...
        sd    t1, sk_kl(zero)           ; ...
        ld    t1, 24(t0)                ; ...
        slli  t2, t1, 32                ; ...
        srli  t2, t2, 32                ; ...
        sd    t2, sk_vl(zero)           ; ...
        srli  t1, t1, 32                ; ...
        sd    t1, sk_fl(zero)           ; ...
        ld    a0, 40(sp)                ; the key
        beqz  a0, ssk_ov                ; ...
        ld    a1, sk_kl(zero)           ; ...
        li    a2, 0                     ; ...
        call  dbc_get                   ; ...
ssk_ov:
        ld    a0, 48(sp)                ; the value, after the key (padded)
        beqz  a0, ssk_yes               ; ...
        ld    a1, sk_vl(zero)           ; ...
        ld    a2, sk_kl(zero)           ; ...
        addi  a2, a2, 7                 ; ...
        srli  a2, a2, 3                 ; ...
        slli  a2, a2, 3                 ; ...
        call  dbc_getat                 ; ...
        j     ssk_yes                   ; ...
ssk_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 64                ; ...
        ret                             ; ...

; ---- read-ahead --------------------------------------------------------------------------

; rc_find(a0 = tree) -> a0 = its slot, or 0
rc_find:
        la    t0, rcs                   ; ...
        li    t1, 2                     ; ...
rcf_l:
        ld    t2, RC_TREE(t0)           ; ...
        beq   t2, a0, rcf_y             ; ...
        li    t2, RC_SIZE               ; ...
        add   t0, t0, t2                ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, rcf_l                 ; ...
        li    a0, 0                     ; ...
        ret                             ; ...
rcf_y:
        ld    t1, rc_clock(zero)        ; used now
        addi  t1, t1, 1                 ; ...
        sd    t1, rc_clock(zero)        ; ...
        sd    t1, RC_USE(t0)            ; ...
        mv    a0, t0                    ; ...
        ret                             ; ...

; rc_new(a0 = tree, a1 = key, a2 = its length, a3 = ST_GE / ST_GT) -> a0 =
; a slot for that tree (its own, else the one used longest ago), holding no
; records yet, starting at the key
rc_new:
        la    t0, rcs                   ; its own slot, or the older one
        ld    t1, RC_TREE(t0)           ; ...
        beq   t1, a0, rcn_s             ; ...
        li    t2, RC_SIZE               ; ...
        add   t3, t0, t2                ; ...
        ld    t1, RC_TREE(t3)           ; ...
        beq   t1, a0, rcn_t3            ; ...
        ld    t1, RC_USE(t0)            ; ...
        ld    t2, RC_USE(t3)            ; ...
        bleu  t1, t2, rcn_s             ; ...
rcn_t3:
        mv    t0, t3                    ; ...
rcn_s:
        sd    a0, RC_TREE(t0)           ; ...
        sd    zero, RC_N(t0)            ; ...
        sd    zero, RC_PN(t0)           ; ...
        sd    zero, RC_EOT(t0)          ; ...
        sd    a2, RC_SKL(t0)            ; ...
        sd    a3, RC_SS(t0)             ; ...
        ld    t1, rc_clock(zero)        ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, rc_clock(zero)        ; ...
        sd    t1, RC_USE(t0)            ; ...
        addi  sp, sp, -16               ; the key
        sd    ra, 0(sp)                 ; ...
        sd    t0, 8(sp)                 ; ...
        addi  a0, t0, RC_SKEY           ; ...
        call  srv_bcopy                 ; ...
        ld    a0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; rc_scan(a0 = tree, a1 = key, a2 = its length, a3 = ST_GE / ST_GT) -> a0 =
; a slot holding what SCAN answers from there
rc_scan:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        sd    a2, 24(sp)                ; ...
        sd    a3, 32(sp)                ; ...
        mv    a0, a1                    ; the key
        mv    a1, a2                    ; ...
        li    a2, 0                     ; ...
        call  dbc_put                   ; ...
        li    a0, DB_SCAN               ; ...
        ld    a1, 8(sp)                 ; ...
        ld    a2, 24(sp)                ; ...
        ld    a3, 32(sp)                ; ...
        li    a4, 0                     ; ...
        call  dbc                       ; ...
        sd    a0, 40(sp)                ; (records)
        ld    a0, 8(sp)                 ; a slot for them
        ld    a1, 16(sp)                ; ...
        ld    a2, 24(sp)                ; ...
        ld    a3, 32(sp)                ; ...
        call  rc_new                    ; ...
        sd    a0, 8(sp)                 ; ...
        ld    t1, 40(sp)                ; ...
        sd    t1, RC_N(a0)              ; ...
        la    t2, dbh                   ; ...
        ld    t1, 24(t2)                ; ...
        sd    t1, RC_EOT(a0)            ; ...
        ld    a1, 16(t2)                ; the records
        addi  a0, a0, RC_BUF            ; ...
        li    a2, 0                     ; ...
        call  dbc_get                   ; ...
        ld    a0, 8(sp)                 ; the last one's place
        ld    t1, RC_N(a0)              ; ...
        addi  t2, a0, RC_BUF            ; ...
        sd    t2, RC_LAST(a0)           ; ...
        sd    t2, RC_POS(a0)            ; (a walk starts at the first)
        sd    t1, RC_PN(a0)             ; ...
rcs_l:
        addi  t1, t1, -1                ; ...
        blez  t1, rcs_d                 ; ...
        lhu   t3, 0(t2)                 ; ...
        addi  t3, t3, 7                 ; ...
        srli  t3, t3, 3                 ; ...
        slli  t3, t3, 3                 ; ...
        lhu   t4, 2(t2)                 ; ...
        addi  t4, t4, 7                 ; ...
        srli  t4, t4, 3                 ; ...
        slli  t4, t4, 3                 ; ...
        add   t2, t2, t3                ; ...
        add   t2, t2, t4                ; ...
        addi  t2, t2, 8                 ; ...
        sd    t2, RC_LAST(a0)           ; ...
        j     rcs_l                     ; ...
rcs_d:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; ...

; rc_covers(a0 = slot, a1 = key, a2 = its length, a3 = ST_GE / ST_GT) -> a0 =
; 1 when the slot's records answer that question: the key is after where it
; starts (or at it, asked the way it started), and before its last record
; or the tree's end
rc_covers:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        mv    s1, a0                    ; ...
        mv    s2, a3                    ; ...
        ld    t0, RC_N(s1)              ; nothing held: nothing answered
        beqz  t0, rcc_no                ; ...
        sd    a1, rc_k(zero)            ; ...
        sd    a2, rc_kl(zero)           ; ...
        mv    a0, a1                    ; after the start?
        mv    a1, a2                    ; ...
        addi  a2, s1, RC_SKEY           ; ...
        ld    a3, RC_SKL(s1)            ; ...
        call  kcmp                      ; ...
        bltz  a0, rcc_no                ; ...
        bgtz  a0, rcc_end               ; ...
        ld    t0, RC_SS(s1)             ; at it: asked as it started, or it started
        beqz  t0, rcc_end               ;   at the key and this is after it
        beqz  s2, rcc_no                ; ...
rcc_end:
        ld    t0, RC_EOT(s1)            ; up to the tree's end: yes
        bnez  t0, rcc_yes               ; ...
        ld    a0, rc_k(zero)            ; before the last record (a GT at it: the
        ld    a1, rc_kl(zero)           ;   next is not held)
        ld    a2, RC_LAST(s1)           ; ...
        lhu   a3, 0(a2)                 ; ...
        addi  a2, a2, 8                 ; ...
        call  kcmp                      ; ...
        bltz  a0, rcc_yes               ; ...
        bgtz  a0, rcc_no                ; ...
        bnez  s2, rcc_no                ; ...
rcc_yes:
        li    a0, 1                     ; ...
        j     rcc_ret                   ; ...
rcc_no:
        li    a0, 0                     ; ...
rcc_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; rc_past(a0 = slot, a1 = key, a2 = its length) -> a0 = 1 when the key is
; after everything the slot holds (its last record, or its start when it
; holds none), and the tree does not end there: a walk going on
rc_past:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        ld    t0, RC_EOT(a0)            ; ...
        bnez  t0, rcp_no                ; ...
        mv    t1, a0                    ; ...
        mv    a0, a1                    ; ...
        mv    a1, a2                    ; ...
        ld    t0, RC_N(t1)              ; ...
        bnez  t0, rcp_last              ; ...
        addi  a2, t1, RC_SKEY           ; ...
        ld    a3, RC_SKL(t1)            ; ...
        j     rcp_c                     ; ...
rcp_last:
        ld    a2, RC_LAST(t1)           ; ...
        lhu   a3, 0(a2)                 ; ...
        addi  a2, a2, 8                 ; ...
rcp_c:
        call  kcmp                      ; ...
        blez  a0, rcp_no                ; ...
        li    a0, 1                     ; ...
        j     rcp_ret                   ; ...
rcp_no:
        li    a0, 0                     ; ...
rcp_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; rc_first(a0 = slot, a1 = key, a2 = its length, a3 = ST_GE / ST_GT) -> a0 =
; the first record it holds at or after (after) the key, or 0
rc_first:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        sd    s5, 40(sp)                ; ...
        ld    s1, RC_N(a0)              ; s1 = records left
        addi  s2, a0, RC_BUF            ; s2 = the record
        mv    s3, a1                    ; s3, s4 = the key
        mv    s4, a2                    ; ...
        mv    s5, a3                    ; ...
        sd    a0, rc_slot(zero)         ; ...
        ld    t0, RC_PN(a0)             ; from the record answered last, when the key
        beqz  t0, rcfi_l                ;   is not before it (a walk: no search from
        ld    t1, RC_POS(a0)            ;   the start each time)
        sd    t0, rc_k(zero)            ; ...
        sd    t1, rc_kl(zero)           ; ...
        addi  a0, t1, 8                 ; ...
        lhu   a1, 0(t1)                 ; ...
        mv    a2, s3                    ; ...
        mv    a3, s4                    ; ...
        call  kcmp                      ; ...
        bgtz  a0, rcfi_l                ; ...
        ld    s1, rc_k(zero)            ; ...
        ld    s2, rc_kl(zero)           ; ...
rcfi_l:
        beqz  s1, rcfi_no               ; ...
        addi  a0, s2, 8                 ; ...
        lhu   a1, 0(s2)                 ; ...
        mv    a2, s3                    ; ...
        mv    a3, s4                    ; ...
        call  kcmp                      ; ...
        bgtz  a0, rcfi_y                ; after: yes
        bltz  a0, rcfi_n                ; ...
        beqz  s5, rcfi_y                ; at it, asked at or after: yes
rcfi_n:
        lhu   t3, 0(s2)                 ; the next
        addi  t3, t3, 7                 ; ...
        srli  t3, t3, 3                 ; ...
        slli  t3, t3, 3                 ; ...
        lhu   t4, 2(s2)                 ; ...
        addi  t4, t4, 7                 ; ...
        srli  t4, t4, 3                 ; ...
        slli  t4, t4, 3                 ; ...
        add   s2, s2, t3                ; ...
        add   s2, s2, t4                ; ...
        addi  s2, s2, 8                 ; ...
        addi  s1, s1, -1                ; ...
        j     rcfi_l                    ; ...
rcfi_y:
        ld    t0, rc_slot(zero)         ; remembered
        sd    s2, RC_POS(t0)            ; ...
        sd    s1, RC_PN(t0)             ; ...
        mv    a0, s2                    ; ...
        j     rcfi_ret                  ; ...
rcfi_no:
        li    a0, 0                     ; ...
rcfi_ret:
        ld    s5, 40(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; ...

; rc_copy(a0 = to, a1 = from (a record's key or value: on a word), a2 =
; bytes): by words when the destination is on one too (padded), else by bytes
rc_copy:
        andi  t0, a0, 7                 ; ...
        bnez  t0, srv_bcopy             ; (tail calls)
        addi  a2, a2, 7                 ; ...
        srli  a2, a2, 3                 ; ...
        slli  a2, a2, 3                 ; ...
        j     wcopy                     ; ...

; dbc_getat(a0 = D-LS address, a1 = bytes, a2 = offset in the data): as
; dbc_get, at any offset (a multiple of 8)
dbc_getat:
        beqz  a1, dga_ret               ; ...
        andi  t0, a0, 7                 ; ...
        bnez  t0, dga_un                ; ...
        addi  a1, a1, 7                 ; ...
        srli  a1, a1, 3                 ; ...
        slli  a1, a1, 3                 ; ...
        addi  t1, a2, 64                ; ...
        tget  tg10, a0, c5, t1, a1      ; ...
        twait 1 << 10                   ; ...
dga_ret:
        ret                             ; ...
dga_un:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        addi  t2, a1, 7                 ; ...
        srli  t2, t2, 3                 ; ...
        slli  t2, t2, 3                 ; ...
        addi  t1, a2, 64                ; ...
        la    t0, dbs                   ; ...
        tget  tg10, t0, c5, t1, t2      ; ...
        twait 1 << 10                   ; ...
        ld    a0, 8(sp)                 ; ...
        la    a1, dbs                   ; ...
        ld    a2, 16(sp)                ; ...
        call  srv_bcopy                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; st_put(a0 = tree, a1 = key, a2 = its length, a3 = value, a4 = its length, a5
; = its flag (0, 1)) -> a0 = 1: an item of the batch {u8 1, u8 flag, u16 key
; length, u16 value length, u16 0, u64 tree, key, value}, each padded
st_put:
        li    t6, 1                     ; ...
        j     wb_item                   ; ...

; st_del(a0 = tree, a1 = key, a2 = its length) -> a0 = 1: an item {u8 2, ...}
st_del:
        li    t6, 2                     ; ...
        li    a4, 0                     ; ...
        li    a5, 0                     ; ...
; wb_item(t6 = 1 put / 2 delete, a0 = tree, a1 = key, a2 = its length, a3 =
; value, a4 = its length, a5 = flag) -> a0 = 1
wb_item:
        addi  sp, sp, -64               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        sd    a2, 24(sp)                ; ...
        sd    a3, 32(sp)                ; ...
        sd    a4, 40(sp)                ; ...
        sd    t6, 48(sp)                ; ...
        sd    a5, 56(sp)                ; ...
        la    t1, rcs                   ; a change: the read-ahead goes
        sd    zero, RC_TREE(t1)         ; ...
        li    t2, RC_SIZE               ; ...
        add   t1, t1, t2                ; ...
        sd    zero, RC_TREE(t1)         ; ...
        addi  t0, a2, 7                 ; its bytes
        srli  t0, t0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        addi  t1, a4, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        add   t0, t0, t1                ; ...
        addi  t0, t0, 16                ; ...
        ld    t1, wb_len(zero)          ; room?
        add   t1, t1, t0                ; ...
        li    t2, WB_MAX                ; ...
        bleu  t1, t2, wbi_put           ; ...
        call  wb_flush                  ; no: the batch goes now
wbi_put:
        ld    a5, 56(sp)                ; ...
        ld    t1, wb_len(zero)          ; the item's head
        la    t2, wb                    ; ...
        add   t2, t2, t1                ; ...
        ld    t0, 48(sp)                ; ...
        sb    t0, 0(t2)                 ; ...
        sb    a5, 1(t2)                 ; ...
        ld    t0, 24(sp)                ; ...
        sh    t0, 2(t2)                 ; ...
        ld    t0, 40(sp)                ; ...
        sh    t0, 4(t2)                 ; ...
        sh    zero, 6(t2)               ; ...
        ld    t0, 8(sp)                 ; ...
        sd    t0, 8(t2)                 ; ...
        addi  a0, t2, 16                ; the key
        ld    a1, 16(sp)                ; ...
        ld    a2, 24(sp)                ; ...
        call  srv_bcopy                 ; ...
        ld    t1, wb_len(zero)          ; the value, after it
        la    t2, wb                    ; ...
        add   t2, t2, t1                ; ...
        ld    t0, 24(sp)                ; ...
        addi  t0, t0, 7                 ; ...
        srli  t0, t0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        addi  a0, t2, 16                ; ...
        add   a0, a0, t0                ; ...
        ld    a1, 32(sp)                ; ...
        ld    a2, 40(sp)                ; ...
        call  srv_bcopy                 ; ...
        ld    t0, 24(sp)                ; the batch grows by the item
        addi  t0, t0, 7                 ; ...
        srli  t0, t0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        ld    t1, 40(sp)                ; ...
        addi  t1, t1, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        add   t0, t0, t1                ; ...
        addi  t0, t0, 16                ; ...
        ld    t1, wb_len(zero)          ; ...
        add   t1, t1, t0                ; ...
        sd    t1, wb_len(zero)          ; ...
        li    a0, 1                     ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 64                ; ...
        ret                             ; ...

; wb_flush(): the batch goes to db now (alone: FLUSH)
wb_flush:
        ld    t0, wb_len(zero)          ; ...
        beqz  t0, wbf_ret               ; ...
        li    a0, DB_FLUSH              ; ...
        j     dbc_0                     ; ...
wbf_ret:
        ret                             ; ...

; dbc_k(a0 = tree, a1 = key, a2 = its length, a3 = op): a call with the key
; as its data -> a0 = the result
dbc_k:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        sd    a2, 16(sp)                ; ...
        sd    a3, 24(sp)                ; ...
        mv    a0, a1                    ; ...
        mv    a1, a2                    ; ...
        li    a2, 0                     ; ...
        call  dbc_put                   ; ...
        ld    a0, 24(sp)                ; ...
        ld    a1, 8(sp)                 ; ...
        ld    a2, 16(sp)                ; ...
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        call  dbc                       ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

