; =============================================================================
; dbcall.s: the store, from fs: calls to db (included by fs.s)
; =============================================================================
;
; The store is db's (os/servers/db.s; doc/fs-split.md). These routines have
; the names and the arguments of the store's own (store.s, storew.s,
; sblob.s), so the file system's code calls them as it did when the store
; was part of it; each is a message to db. A tree is db's handle for it.
; What the store's routines left in variables (sk_kl, bl_vl, bval ...) is
; left there here too.
;
; A call that db answers with a failure of the store (the reply's count of
; aborts changed: it gave up the commit under way; or -5: the disk cannot be
; read) goes to st_full (-1) or st_die (-5), as it did inside the store.
;
; Capability registers: c1 the endpoint to db's core, c5 our message buffer;
; VLOAD lends the attachment (c7) and keeps the request (c6) in c4 meanwhile.

ST_GE   = 0                             ; st_seek: at or after the key
ST_GT   = 1                             ; after
ST_LE   = 2                             ; at or before
ST_LT   = 3                             ; before
SVC_SEND = 12                           ; svc: send, with an attachment or not
SEL     = 0x53 << 56                    ; header word 48: a server's index on its core
DB_TREE = 70                            ; db's calls
DB_GET  = 71                            ; ...
DB_SEEK = 72                            ; ...
DB_PUT  = 73                            ; ...
DB_DEL  = 74                            ; ...
DB_VSIZE = 75                           ; ...
DB_VREAD = 76                           ; ...
DB_VWRITE = 77                          ; ...
DB_VTRUNC = 78                          ; ...
DB_VDEL = 79                            ; ...
DB_VLOAD = 80                           ; ...
DB_COMMIT = 81                          ; ...
DB_ABORT = 82                           ; ...
DB_INFO = 83                            ; ...
DB_SNAP = 84                            ; ...
DB_SNAPT = 85                           ; ...
DB_BOOT = 86                            ; ...
DB_CHUNK = 4032                         ; a message's data

        .data                           ; data Local Store
        .align 8                        ; ...
dbsel:     .dword 0                     ; header word 48 for db
db_ab:     .dword 0                     ; db's count of aborts, as last seen
dbh:       .space 64                    ; a request to db, then its answer
dbk:       .space 8                     ; a short key
st_ps:     .dword 0                     ; the page size
st_bpp:    .dword 0                     ; blocks per page
st_sh:     .dword 0                     ; log2 of the page size
st_txn:    .dword 0                     ; the commit under way
st_cmt:    .dword 0                     ; the last commit on the disk
st_npages: .dword 0                     ; pages on the disk
st_nfree:  .dword 0                     ; free pages
st_deadlim: .dword 0                    ; the newest snapshot's commit
st_total:  .dword 0                     ; the disk's blocks
sk_kl:     .dword 0                     ; st_seek's answer: key length,
sk_vl:     .dword 0                     ;   value length,
sk_fl:     .dword 0                     ;   the value's flag
bl_ext:    .dword 0                     ; the extent tree of the values at work
bl_vl:     .dword 0                     ; st_bsize: the value's length as the tree holds it,
bl_fl:     .dword 0                     ;   its flag
bw_force:  .dword 0                     ; st_bwrite: a stream even when short
db_a:      .space 48                    ; a call's arguments
bval:      .space 1024                  ; st_bsize: the value as the tree holds it

        .text                           ; instruction Local Store

; dbc(a0 = op, a1 = handle, a2 = length, a3 = mode, a4 = word 56) -> a0 =
; the result; the answer's header in dbh. The data is at 64 of c5 already.
dbc:
        la    t0, dbh                   ; the header
        sd    a0, 0(t0)                 ; ...
        sd    a1, 8(t0)                 ; ...
        sd    a2, 16(t0)                ; ...
        sd    a3, 24(t0)                ; ...
        sd    zero, 32(t0)              ; ...
        ld    t1, dbsel(zero)           ; ...
        sd    t1, 48(t0)                ; ...
        sd    a4, 56(t0)                ; ...
        li    t1, 64                    ; ...
        tput  tg10, t0, c5, zero, t1    ; ...
        twait 1 << 10                   ; ...
        li    a5, -1                    ; nothing attached
dbc_send:
        li    a0, SVC_SEND              ; through c1
        li    a1, 1                     ; ...
        li    a2, -1                    ; ...
        li    a3, 0                     ; ...
        li    a4, 5                     ; ...
        svc                             ; ...
dbc_w:
        beqz  a0, dbc_back              ; ...
        li    t1, -1                    ; not sent: as -5 (the store is out of reach)
        beq   a0, t1, dbc_lost          ; ...
        li    a0, 1                     ; woken early: wait on
        li    a1, -1                    ; ...
        li    a2, -1                    ; ...
        li    a3, 0                     ; ...
        li    a4, 5                     ; ...
        svc                             ; ...
        j     dbc_w                     ; ...
dbc_lost:
        j     st_die                    ; ...
dbc_back:
        la    t0, dbh                   ; the answer
        li    t1, 64                    ; ...
        tget  tg10, t0, c5, zero, t1    ; ...
        twait 1 << 10                   ; ...
        ld    t1, 56(t0)                ; the commit under way, db's aborts
        slli  t2, t1, 16                ; ...
        srli  t2, t2, 16                ; ...
        sd    t2, st_txn(zero)          ; ...
        srli  t1, t1, 48                ; ...
        ld    t2, db_ab(zero)           ; ...
        ld    a0, 32(t0)                ; ...
        bne   t1, t2, dbc_ab            ; ...
        li    t1, -5                    ; ...
        beq   a0, t1, st_die            ; ...
        ret                             ; ...
dbc_ab:
        sd    t1, db_ab(zero)           ; db gave up the commit under way
        li    t1, -1                    ; ...
        beq   a0, t1, st_full           ; ...
        j     st_die                    ; ...

; dbc_put(a0 = D-LS address, a1 = bytes, a2 = offset in the data): more of
; the request's data; an address not on a word goes through dbs
dbc_put:
        beqz  a1, dbp_ret               ; ...
        andi  t0, a0, 7                 ; ...
        beqz  t0, dbp_go                ; ...
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a1, 8(sp)                 ; ...
        sd    a2, 16(sp)                ; ...
        mv    t0, a0                    ; ...
        la    a0, dbs                   ; ...
        mv    a2, a1                    ; ...
        mv    a1, t0                    ; ...
        call  srv_bcopy                 ; ...
        la    a0, dbs                   ; ...
        ld    a1, 8(sp)                 ; ...
        ld    a2, 16(sp)                ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
dbp_go:
        addi  a1, a1, 7                 ; whole words
        srli  a1, a1, 3                 ; ...
        slli  a1, a1, 3                 ; ...
        addi  t1, a2, 64                ; ...
        tput  tg10, a0, c5, t1, a1      ; ...
        twait 1 << 10                   ; (before the buffer leaves, or dbs is used again)
dbp_ret:
        ret                             ; ...

; dbc_get(a0 = D-LS address, a1 = bytes, a2 = offset in the data): the
; answer's data -> there (a whole word more may be written: padded)
dbc_get:
        j     dbc_getat                 ; ...

; dbc_key(a0 = key, a1 = its length) -> a0 = what goes in word 56 when the
; key is 8 bytes or shorter (the key itself), else 0 and the key is the
; data's start (padded); a1 = the bytes of data the key takes
dbc_key:
        li    t0, 8                     ; ...
        bgtu  a1, t0, dbk_long          ; ...
        sd    zero, dbk(zero)           ; short: a word
        beqz  a1, dbk_s                 ; ...
        mv    t1, a0                    ; ...
        la    t2, dbk                   ; ...
        mv    t3, a1                    ; ...
dbk_c:
        lbu   t4, 0(t1)                 ; ...
        sb    t4, 0(t2)                 ; ...
        addi  t1, t1, 1                 ; ...
        addi  t2, t2, 1                 ; ...
        addi  t3, t3, -1                ; ...
        bnez  t3, dbk_c                 ; ...
dbk_s:
        ld    a0, dbk(zero)             ; ...
        li    a1, 0                     ; ...
        ret                             ; ...
dbk_long:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a1, 8(sp)                 ; ...
        li    a2, 0                     ; ...
        call  dbc_put                   ; ...
        li    a0, 0                     ; ...
        ld    a1, 8(sp)                 ; ...
        addi  a1, a1, 7                 ; ...
        srli  a1, a1, 3                 ; ...
        slli  a1, a1, 3                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; ---- the trees -------------------------------------------------------------------------

; st_tree(a0 = namespace, a1 = name, a2 = its length (<= 28), a3 = 1: make it
; if it is not there) -> a0 = the tree, or 0
st_tree:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        sd    a2, 16(sp)                ; ...
        sd    a3, 24(sp)                ; ...
        mv    a0, a1                    ; the name
        mv    a1, a2                    ; ...
        li    a2, 0                     ; ...
        call  dbc_put                   ; ...
        li    a0, DB_TREE               ; ...
        ld    a1, 8(sp)                 ; ...
        ld    a2, 16(sp)                ; ...
        ld    a3, 24(sp)                ; ...
        li    a4, 0                     ; ...
        call  dbc                       ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; st_get(a0 = tree, a1 = key, a2 = its length, a3 = where the value goes (0:
; nowhere; padded to a word)) -> a0 = the value's length, or -1 if the key is
; not there; a1 = its flag
st_get:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        sd    a2, 16(sp)                ; ...
        sd    a3, 24(sp)                ; ...
        mv    a0, a1                    ; the key
        mv    a1, a2                    ; ...
        li    a2, 0                     ; ...
        call  dbc_put                   ; ...
        li    a0, DB_GET                ; ...
        ld    a1, 8(sp)                 ; ...
        ld    a2, 16(sp)                ; ...
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        call  dbc                       ; ...
        bltz  a0, sg_ret                ; ...
        ld    t0, 24(sp)                ; the value
        beqz  t0, sg_ret                ; ...
        sd    a0, 16(sp)                ; ...
        mv    a1, a0                    ; ...
        mv    a0, t0                    ; ...
        li    a2, 0                     ; ...
        call  dbc_get                   ; ...
        ld    a0, 16(sp)                ; ...
sg_ret:
        la    t0, dbh                   ; ...
        ld    a1, 24(t0)                ; the flag
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; st_seek(a0 = tree, a1 = key, a2 = its length, a3 = ST_GE / GT / LE / LT, a4 =
; where the found key goes, a5 = where its value goes (either 0: nowhere;
; each padded to a word; a4 may be the key's own place) -> a0 = 1 and
; sk_kl, sk_vl, sk_fl, or 0: the nearest record on that side of the key
st_seek:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        sd    a2, 16(sp)                ; ...
        sd    a3, 24(sp)                ; ...
        sd    a4, 32(sp)                ; ...
        sd    a5, 40(sp)                ; ...
        mv    a0, a1                    ; the key
        mv    a1, a2                    ; ...
        li    a2, 0                     ; ...
        call  dbc_put                   ; ...
        li    a0, DB_SEEK               ; ...
        ld    a1, 8(sp)                 ; ...
        ld    a2, 16(sp)                ; ...
        ld    a3, 24(sp)                ; ...
        li    a4, 0                     ; ...
        call  dbc                       ; ...
        beqz  a0, ssk_ret               ; ...
        la    t0, dbh                   ; the key's and the value's lengths, the flag
        ld    t1, 16(t0)                ; ...
        sd    t1, sk_kl(zero)           ; ...
        ld    t1, 24(t0)                ; ...
        slli  t2, t1, 32                ; ...
        srli  t2, t2, 32                ; ...
        sd    t2, sk_vl(zero)           ; ...
        srli  t1, t1, 32                ; ...
        sd    t1, sk_fl(zero)           ; ...
        ld    a0, 32(sp)                ; the key
        beqz  a0, ssk_v                 ; ...
        ld    a1, sk_kl(zero)           ; ...
        li    a2, 0                     ; ...
        call  dbc_get                   ; ...
ssk_v:
        ld    a0, 40(sp)                ; the value, after the key (padded)
        beqz  a0, ssk_one               ; ...
        ld    a1, sk_vl(zero)           ; ...
        ld    a2, sk_kl(zero)           ; ...
        addi  a2, a2, 7                 ; ...
        srli  a2, a2, 3                 ; ...
        slli  a2, a2, 3                 ; ...
        call  dbc_getat                 ; ...
ssk_one:
        li    a0, 1                     ; ...
ssk_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; ...

; dbc_getat(a0 = D-LS address, a1 = bytes, a2 = offset in the data): as
; dbc_get, at any offset (a multiple of 8)
dbc_getat:
        beqz  a1, dga_ret               ; ...
        andi  t0, a0, 7                 ; ...
        bnez  t0, dga_un                ; ...
        addi  a1, a1, 7                 ; ...
        srli  a1, a1, 3                 ; ...
        slli  a1, a1, 3                 ; ...
        addi  t1, a2, 64                ; ...
        tget  tg10, a0, c5, t1, a1      ; ...
        twait 1 << 10                   ; ...
dga_ret:
        ret                             ; ...
dga_un:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        addi  t2, a1, 7                 ; ...
        srli  t2, t2, 3                 ; ...
        slli  t2, t2, 3                 ; ...
        addi  t1, a2, 64                ; ...
        la    t0, dbs                   ; ...
        tget  tg10, t0, c5, t1, t2      ; ...
        twait 1 << 10                   ; ...
        ld    a0, 8(sp)                 ; ...
        la    a1, dbs                   ; ...
        ld    a2, 16(sp)                ; ...
        call  srv_bcopy                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; st_put(a0 = tree, a1 = key, a2 = its length, a3 = value, a4 = its length, a5
; = its flag (0, 1)) -> a0 = 1 added, 0 replaced, -1 too long
st_put:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        sd    a3, 16(sp)                ; ...
        sd    a4, 24(sp)                ; ...
        sd    a5, 32(sp)                ; ...
        addi  t0, a2, 7                 ; the key's bytes, padded
        srli  t0, t0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        sd    t0, 40(sp)                ; ...
        la    t0, db_a                  ; {u16 key length, u16 value length, u32 0}
        sd    zero, 0(t0)               ; ...
        sh    a2, 0(t0)                 ; ...
        sh    a4, 2(t0)                 ; ...
        mv    a0, a1                    ; the key, at 8
        mv    a1, a2                    ; ...
        li    a2, 8                     ; ...
        call  dbc_put                   ; ...
        la    a0, db_a                  ; ...
        li    a1, 8                     ; ...
        li    a2, 0                     ; ...
        call  dbc_put                   ; ...
        ld    a0, 16(sp)                ; the value, after the key
        ld    a1, 24(sp)                ; ...
        ld    a2, 40(sp)                ; ...
        addi  a2, a2, 8                 ; ...
        call  dbc_put                   ; ...
        li    a0, DB_PUT                ; ...
        ld    a1, 8(sp)                 ; ...
        ld    a2, 40(sp)                ; ...
        addi  a2, a2, 8                 ; ...
        ld    t0, 24(sp)                ; ...
        add   a2, a2, t0                ; ...
        ld    a3, 32(sp)                ; ...
        li    a4, 0                     ; ...
        call  dbc                       ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; ...

; st_del(a0 = tree, a1 = key, a2 = its length) -> a0 = 1 deleted, 0 not there
st_del:
        li    a3, DB_DEL                ; ...
; dbc_k(a0 = tree, a1 = key, a2 = its length, a3 = op): a call with the key
; as its data -> a0 = the result
dbc_k:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        sd    a2, 16(sp)                ; ...
        sd    a3, 24(sp)                ; ...
        mv    a0, a1                    ; ...
        mv    a1, a2                    ; ...
        li    a2, 0                     ; ...
        call  dbc_put                   ; ...
        ld    a0, 24(sp)                ; ...
        ld    a1, 8(sp)                 ; ...
        ld    a2, 16(sp)                ; ...
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        call  dbc                       ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; ---- values by part -------------------------------------------------------------------

; dbc_v(a0 = op, a1 = tree, a2 = key, a3 = its length, a4 = mode, a5 = the
; data's length after the key, which is at 64 + a6 of c5 already ... ) ->
; a0 = the result. The handle carries the extents' tree (bl_ext) and the
; key's length; a short key goes in word 56, a long one first in the data.
; (a6 = bytes of data put after the key; called with the key not yet put)
dbc_v:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        sd    a3, 24(sp)                ; ...
        sd    a4, 32(sp)                ; ...
        sd    a5, 40(sp)                ; ...
        mv    a0, a2                    ; ...
        mv    a1, a3                    ; ...
        call  dbc_key                   ; a0 = word 56, a1 = the data the key takes
        mv    a4, a0                    ; ...
        ld    a2, 40(sp)                ; the length: the key's data and the rest
        add   a2, a2, a1                ; ...
        ld    a1, 16(sp)                ; the handle
        ld    t0, bl_ext(zero)          ; ...
        slli  t0, t0, 16                ; ...
        or    a1, a1, t0                ; ...
        ld    t0, 24(sp)                ; ...
        slli  t0, t0, 32                ; ...
        or    a1, a1, t0                ; ...
        ld    a0, 8(sp)                 ; ...
        ld    a3, 32(sp)                ; ...
        call  dbc                       ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; ...

; dbc_koff(a1 = the key's length) -> a0 = where the data after a key starts
; (0 for a short key: it goes in word 56)
dbc_koff:
        li    a0, 0                     ; ...
        li    t0, 8                     ; ...
        bleu  a1, t0, dko_ret           ; ...
        addi  a0, a1, 7                 ; ...
        srli  a0, a0, 3                 ; ...
        slli  a0, a0, 3                 ; ...
dko_ret:
        ret                             ; ...

; st_bsize(a0 = tree, a1 = key, a2 = its length) -> a0 = the value's length,
; or -1 if it is not there. The value as the tree holds it is left in bval
; (bl_vl, bl_fl).
st_bsize:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        mv    a3, a2                    ; ...
        mv    a2, a1                    ; ...
        mv    a1, a0                    ; ...
        li    a0, DB_VSIZE              ; ...
        li    a4, 0                     ; ...
        li    a5, 0                     ; ...
        call  dbc_v                     ; ...
        sd    a0, 8(sp)                 ; ...
        la    t0, dbh                   ; ...
        ld    t1, 24(t0)                ; ...
        sd    t1, bl_fl(zero)           ; ...
        li    t1, -1                    ; ...
        sd    t1, bl_vl(zero)           ; ...
        bltz  a0, bsz_ret               ; ...
        ld    a1, 16(t0)                ; ...
        sd    a1, bl_vl(zero)           ; ...
        la    a0, bval                  ; ...
        li    a2, 0                     ; ...
        call  dbc_get                   ; ...
bsz_ret:
        ld    a0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; st_bread(a0 = tree, a1 = key, a2 = its length, a3 = offset, a4 = where the
; bytes go (D-LS), a5 = how many, <= 4032) -> a0 = how many were read (0 at
; the end), or -1 if the value is not there
st_bread:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a4, 8(sp)                 ; ...
        mv    a4, a3                    ; mode = offset
        mv    a3, a2                    ; ...
        mv    a2, a1                    ; ...
        mv    a1, a0                    ; ...
        li    a0, DB_VREAD              ; length = bytes (no data)
        call  dbc_vn                    ; ...
        sd    a0, 16(sp)                ; ...
        blez  a0, brd_ret               ; ...
        mv    a1, a0                    ; ...
        ld    a0, 8(sp)                 ; ...
        li    a2, 0                     ; ...
        call  dbc_get                   ; ...
brd_ret:
        ld    a0, 16(sp)                ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; dbc_vn(a0 = op, a1 = tree, a2 = key, a3 = its length, a4 = mode, a5 = the
; length word: a count, not the data's bytes (VREAD, VLOAD); a long key is
; the data) -> a0
dbc_vn:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a5, 8(sp)                 ; ...
        call  dbc_vpre                  ; ...
        ld    a2, 8(sp)                 ; ...
        call  dbc_vgo                   ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; dbc_vpre / dbc_vgo: dbc_v in two halves, so that the length word can be
; something else than the data's bytes (VREAD, VLOAD)
dbc_vpre:
        la    t1, db_a                  ; keep the arguments
        sd    a0, 0(t1)                 ; ...
        sd    a1, 8(t1)                 ; ...
        sd    a3, 16(t1)                ; ...
        sd    a4, 24(t1)                ; ...
        addi  sp, sp, -8                ; ...
        sd    ra, 0(sp)                 ; ...
        mv    a0, a2                    ; ...
        mv    a1, a3                    ; ...
        call  dbc_key                   ; ...
        la    t1, db_a                  ; ...
        sd    a0, 32(t1)                ; word 56
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...
dbc_vgo:
        addi  sp, sp, -8                ; (a2 = the length word)
        sd    ra, 0(sp)                 ; ...
        la    t1, db_a                  ; ...
        ld    a0, 0(t1)                 ; ...
        ld    a1, 8(t1)                 ; the handle: tree | extents << 16 | key length << 32
        ld    t0, bl_ext(zero)          ; ...
        slli  t0, t0, 16                ; ...
        or    a1, a1, t0                ; ...
        ld    t0, 16(t1)                ; ...
        slli  t0, t0, 32                ; ...
        or    a1, a1, t0                ; ...
        ld    a3, 24(t1)                ; ...
        ld    a4, 32(t1)                ; ...
        call  dbc                       ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; st_bwrite(a0 = tree, a1 = key, a2 = its length, a3 = offset, a4 = bytes
; (D-LS), a5 = how many): the value is made if it is not there; short ones
; stay in the tree unless bw_force is set. Parts of DB_CHUNK bytes at most
; (less the key's) go in a message each.
st_bwrite:
        addi  sp, sp, -64               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        sd    s5, 40(sp)                ; ...
        sd    s6, 48(sp)                ; ...
        sd    s7, 56(sp)                ; ...
        mv    s1, a0                    ; s1 = tree, s2 = key, s3 = its length,
        mv    s2, a1                    ;   s4 = offset, s5 = bytes, s6 = left
        mv    s3, a2                    ; ...
        mv    s4, a3                    ; ...
        mv    s5, a4                    ; ...
        mv    s6, a5                    ; ...
        mv    a1, s3                    ; s7 = the most per message
        call  dbc_koff                  ; ...
        li    s7, DB_CHUNK              ; ...
        sub   s7, s7, a0                ; ...
bw_l:
        mv    a1, s3                    ; where the bytes go in the data
        call  dbc_koff                  ; ...
        mv    a2, a0                    ; ...
        mv    a1, s6                    ; this part
        bleu  a1, s7, bw_n              ; ...
        mv    a1, s7                    ; ...
bw_n:
        sd    a1, db_a+40(zero)         ; ...
        mv    a0, s5                    ; ...
        call  dbc_put                   ; ...
        li    a0, DB_VWRITE             ; ...
        mv    a1, s1                    ; ...
        mv    a2, s2                    ; ...
        mv    a3, s3                    ; ...
        mv    a4, s4                    ; mode: offset, and a stream even when short
        ld    t0, bw_force(zero)        ; ...
        slli  t0, t0, 63                ; ...
        or    a4, a4, t0                ; ...
        ld    a5, db_a+40(zero)         ; ...
        call  dbc_v                     ; ...
        ld    t0, db_a+40(zero)         ; ...
        add   s4, s4, t0                ; ...
        add   s5, s5, t0                ; ...
        sub   s6, s6, t0                ; ...
        bnez  s6, bw_l                  ; ...
        ld    s7, 56(sp)                ; ...
        ld    s6, 48(sp)                ; ...
        ld    s5, 40(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 64                ; ...
        ret                             ; ...

; st_btrunc(a0 = tree, a1 = key, a2 = its length, a3 = the value's new length)
st_btrunc:
        mv    a4, a3                    ; mode = the new length
        mv    a3, a2                    ; ...
        mv    a2, a1                    ; ...
        mv    a1, a0                    ; ...
        li    a0, DB_VTRUNC             ; ...
        li    a5, 0                     ; ...
        j     dbc_v                     ; ...

; st_bdel(a0 = tree, a1 = key, a2 = its length) -> a0 = 1 deleted, 0 not there
st_bdel:
        mv    a3, a2                    ; ...
        mv    a2, a1                    ; ...
        mv    a1, a0                    ; ...
        li    a0, DB_VDEL               ; ...
        li    a4, 0                     ; ...
        li    a5, 0                     ; ...
        j     dbc_v                     ; ...

; st_bload(a0 = tree, a1 = key, a2 = its length, a3 = offset in the attached
; arena (c7), a4 = the most bytes) -> a0 = the value's length, all of it
; copied in; -4 not there; -1 longer than that. The arena is lent to db (and
; by it to blk, and by blk to the device); the request we serve waits in c4.
st_bload:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a4, 8(sp)                 ; ...
        mv    a4, a3                    ; mode = the offset
        mv    a3, a2                    ; ...
        mv    a2, a1                    ; ...
        mv    a1, a0                    ; ...
        li    a0, DB_VLOAD              ; ...
        call  dbc_vpre                  ; ...
        la    t1, db_a                  ; the header (dbc's first half)
        ld    a0, 0(t1)                 ; ...
        ld    a1, 8(t1)                 ; ...
        ld    t0, bl_ext(zero)          ; ...
        slli  t0, t0, 16                ; ...
        or    a1, a1, t0                ; ...
        ld    t0, 16(t1)                ; ...
        slli  t0, t0, 32                ; ...
        or    a1, a1, t0                ; ...
        ld    a2, 8(sp)                 ; ...
        ld    a3, 24(t1)                ; ...
        ld    a4, 32(t1)                ; ...
        la    t0, dbh                   ; ...
        sd    a0, 0(t0)                 ; ...
        sd    a1, 8(t0)                 ; ...
        sd    a2, 16(t0)                ; ...
        sd    a3, 24(t0)                ; ...
        sd    zero, 32(t0)              ; ...
        ld    t1, dbsel(zero)           ; ...
        sd    t1, 48(t0)                ; ...
        sd    a4, 56(t0)                ; ...
        li    t1, 64                    ; ...
        tput  tg10, t0, c5, zero, t1    ; ...
        twait 1 << 10                   ; ...
        cvalid t0, c6                   ; the request aside: the arena comes back in c6
        beqz  t0, bl_q                  ; ...
        cmov  c4, c6                    ; ...
bl_q:
        li    a0, SVC_SEND              ; through c1, c7 attached
        li    a1, 1                     ; ...
        li    a2, -1                    ; ...
        li    a3, 0                     ; ...
        li    a4, 5                     ; ...
        li    a5, 7                     ; ...
        svc                             ; ...
bl_w:
        beqz  a0, bl_back               ; ...
        li    t1, -1                    ; ...
        beq   a0, t1, bl_back           ; (not sent: the header says -1)
        li    a0, 1                     ; woken early: wait on
        li    a1, -1                    ; ...
        li    a2, -1                    ; ...
        li    a3, 0                     ; ...
        li    a4, 5                     ; ...
        svc                             ; ...
        j     bl_w                      ; ...
bl_back:
        cvalid t0, c6                   ; the arena back in c7
        beqz  t0, bl_r                  ; ...
        cmov  c7, c6                    ; ...
bl_r:
        cvalid t0, c4                   ; the request back in c6
        beqz  t0, bl_h                  ; ...
        cmov  c6, c4                    ; ...
bl_h:
        call  dbc_back                  ; the answer (dbc's second half)
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; ---- commits ------------------------------------------------------------------------

; st_commit(): everything changed since the last commit is on the disk, or
; (the power going before the meta block is written) none of it is
st_commit:
        li    a0, DB_COMMIT             ; ...
dbc_0:
        li    a1, 0                     ; ...
        li    a2, 0                     ; ...
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        j     dbc                       ; ...

; st_abort(): back to the last commit (every tree is to be opened again)
st_abort:
        li    a0, DB_ABORT              ; ...
        j     dbc_0                     ; ...

; st_info() -> a0 = 0, or -5: db's INFO -> st_ps, st_bpp, st_npages,
; st_nfree, st_cmt, st_deadlim, st_total (st_txn comes with every answer)
st_info:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        li    a0, DB_INFO               ; ...
        call  dbc_0                     ; ...
        li    t0, 8                     ; ...
        bne   a0, t0, sti_ret           ; ...
        la    a0, dbs                   ; ...
        li    a1, 64                    ; ...
        li    a2, 0                     ; ...
        call  dbc_get                   ; ...
        la    t0, dbs                   ; ...
        ld    t1, 0(t0)                 ; ...
        sd    t1, st_ps(zero)           ; ...
        ld    t1, 8(t0)                 ; ...
        sd    t1, st_bpp(zero)          ; ...
        ld    t1, 16(t0)                ; ...
        sd    t1, st_npages(zero)       ; ...
        ld    t1, 24(t0)                ; ...
        sd    t1, st_nfree(zero)        ; ...
        ld    t1, 40(t0)                ; ...
        sd    t1, st_cmt(zero)          ; ...
        ld    t1, 48(t0)                ; ...
        sd    t1, st_deadlim(zero)      ; ...
        ld    t1, 56(t0)                ; ...
        sd    t1, st_total(zero)        ; ...
        li    a0, 0                     ; ...
sti_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...
