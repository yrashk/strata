_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        li    t0, 11                    ; code units of 2 KiB (fsunits.s): the dispatcher pages
        csrw  xslot, t0                 ; them into the I-LS after this code
        la    t0, srv_hdr               ; one message of our own: GETDISK to dev (c2)
        li    t1, 30                    ; ...
        sd    t1, 0(t0)                 ; ...
        sd    zero, 8(t0)               ; ...
        sd    zero, 16(t0)              ; ...
        sd    zero, 24(t0)              ; ...
        sd    zero, 32(t0)              ; ...
        li    t1, 64                    ; the header -> our message buffer
        tput  tg10, t0, c5, zero, t1    ; ...
        twait 1 << 10                   ; ...
        csend c5, c2                    ; to dev
        cbase a1, c2                    ; (its core, for the doorbell)
gd_wait:
        li    a0, SVC_WAIT              ; until the buffer is back
        li    a2, -1                    ; ...
        li    a3, 0                     ; ...
        svc                             ; ...
        li    a1, -1                    ; (woken early: wait on, no doorbell)
        bnez  a0, gd_wait               ; c6 = the window, c7 = the endpoint
        cclear c1                       ; proc's endpoint is not needed
        cmov  c1, c6                    ; c1 = the device window
        cclear c2                       ; ...
        cmov  c2, c7                    ; c2 = the device endpoint
        cclear c5                       ; our message buffer is not needed any more
        li    t0, 0x40000               ; the I/O buffer: the top of our memory
        csplit c5, c0, t0               ; c0 = [0, 0x40000), c5 = [0x40000, 0xC0000)
        cbase t0, c5                    ; its base: the device gives it back by it
        sd    t0, iobase(zero)          ; ...
