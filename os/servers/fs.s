; idx_key(a0 = attribute id, a1 = value, a2 = its length): the key of rec's
; object under that attribute and value -> ikey, ik_len
idx_key:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        mv    s2, a2                    ; ...
        la    s1, ikey                  ; ...
        srli  t0, a0, 24                ; the attribute, big-endian
        sb    t0, 0(s1)                 ; ...
        srli  t0, a0, 16                ; ...
        sb    t0, 1(s1)                 ; ...
        srli  t0, a0, 8                 ; ...
        sb    t0, 2(s1)                 ; ...
        sb    a0, 3(s1)                 ; ...
        addi  a0, s1, 4                 ; the value
        call  srv_bcopy                 ; ...
        ld    a0, rec_oid(zero)         ; the object, big-endian
        add   t0, s1, s2                ; ...
        addi  t0, t0, 4                 ; ...
        li    t1, 56                    ; ...
ik_o:
        srl   t2, a0, t1                ; ...
        sb    t2, 0(t0)                 ; ...
        addi  t0, t0, 1                 ; ...
        addi  t1, t1, -8                ; ...
        bgez  t1, ik_o                  ; ...
        addi  t0, s2, 12                ; ...
        sd    t0, ik_len(zero)          ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; idx_do(a0 = 1 put / 0 delete): the entry ikey
idx_do:
        mv    t0, a0                    ; ...
        ld    a0, x_attr(zero)          ; ...
        la    a1, ikey                  ; ...
        ld    a2, ik_len(zero)          ; ...
        beqz  t0, st_del                ; ...
        la    a3, ikey                  ; ...
        li    a4, 0                     ; ...
        li    a5, 0                     ; ...
        j     st_put                    ; ...

; idx_tag(a0 = 1 put / 0 delete, a1 = tag id): rec's object under that tag
idx_tag:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        la    t0, ib8                   ; the tag id, big-endian
        srli  t1, a1, 24                ; ...
        sb    t1, 0(t0)                 ; ...
        srli  t1, a1, 16                ; ...
        sb    t1, 1(t0)                 ; ...
        srli  t1, a1, 8                 ; ...
        sb    t1, 2(t0)                 ; ...
        sb    a1, 3(t0)                 ; ...
        li    a0, A_TAG                 ; ...
        mv    a1, t0                    ; ...
        li    a2, 4                     ; ...
        call  idx_key                   ; ...
        ld    a0, 8(sp)                 ; ...
        call  idx_do                    ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; idx_u64(a0 = 1 put / 0 delete, a1 = attribute id, a2 = value): rec's object
; under that number
idx_u64:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        mv    a0, a2                    ; ...
        call  bswap                     ; ...
        sd    a0, ib8(zero)             ; ...
        ld    a0, 16(sp)                ; ...
        la    a1, ib8                   ; ...
        li    a2, 8                     ; ...
        call  idx_key                   ; ...
        ld    a0, 8(sp)                 ; ...
        call  idx_do                    ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

