; tag_find(a0 = name, a1 = length) -> a0 = the tag's number, or -1
tag_find:
        beqz  a1, tf_no                 ; 1..16 bytes
        li    t0, TAGLEN                ; ...
        bgtu  a1, t0, tf_no             ; ...
        la    t0, tagtab                ; t0 = slot, t1 = its number
        li    t1, 0                     ; ...
tf_e:
        li    t2, NTAGS                 ; all seen?
        bgeu  t1, t2, tf_no             ; ...
        lbu   t2, 0(t0)                 ; a free slot?
        beqz  t2, tf_n                  ; ...
        li    t2, 0                     ; compare
tf_c:
        beq   t2, a1, tf_end            ; ...
        add   t3, t0, t2                ; ...
        lbu   t3, 0(t3)                 ; ...
        add   t4, a0, t2                ; ...
        lbu   t4, 0(t4)                 ; ...
        bne   t3, t4, tf_n              ; ...
        addi  t2, t2, 1                 ; ...
        j     tf_c                      ; ...
tf_end:
        li    t3, TAGLEN                ; the slot's name ends here too?
        beq   t2, t3, tf_yes            ; ...
        add   t3, t0, t2                ; ...
        lbu   t3, 0(t3)                 ; ...
        beqz  t3, tf_yes                ; ...
tf_n:
        addi  t0, t0, TAGLEN            ; ...
        addi  t1, t1, 1                 ; ...
        j     tf_e                      ; ...
tf_yes:
        mv    a0, t1                    ; ...
        ret                             ; ...
tf_no:
        li    a0, -1                    ; ...
        ret                             ; ...

; tag_ref(a0 = name, a1 = length, a2 = 1: create it if missing) -> a0 = the
; tag's number, or -4 no such tag, -1 bad name, -6 no free slot
tag_ref:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        sd    a2, 24(sp)                ; ...
        call  tag_find                  ; ...
        bgez  a0, tr_ret                ; it exists
        ld    t0, 24(sp)                ; create it?
        li    a0, -4                    ; no: no such tag
        beqz  t0, tr_ret                ; ...
        li    a0, -1                    ; a bad name (tag_find took none)
        ld    a1, 16(sp)                ; ...
        beqz  a1, tr_ret                ; ...
        li    t0, TAGLEN                ; ...
        bgtu  a1, t0, tr_ret            ; ...
        ld    t0, 8(sp)                 ; it cannot start with "-" (an exclusion)
        lbu   t1, 0(t0)                 ; ...
        li    t2, '-'                   ; ...
        beq   t1, t2, tr_ret            ; ...
        li    t2, '/'                   ; no "/" in it
tr_sl:
        lbu   t1, 0(t0)                 ; ...
        beq   t1, t2, tr_ret            ; ...
        addi  t0, t0, 1                 ; ...
        addi  a1, a1, -1                ; ...
        bnez  a1, tr_sl                 ; ...
        la    t0, tagtab                ; a free slot
        li    t1, 0                     ; ...
tr_f:
        li    a0, -6                    ; none
        li    t2, NTAGS                 ; ...
        bgeu  t1, t2, tr_ret            ; ...
        lbu   t2, 0(t0)                 ; ...
        beqz  t2, tr_have               ; ...
        addi  t0, t0, TAGLEN            ; ...
        addi  t1, t1, 1                 ; ...
        j     tr_f                      ; ...
tr_have:
        sd    t1, 24(sp)                ; its number
        mv    a0, t0                    ; the name (a free slot is all zero)
        ld    a1, 8(sp)                 ; ...
        ld    a2, 16(sp)                ; ...
        call  srv_bcopy                 ; ...
        ld    a0, 24(sp)                ; ...
tr_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; tag_gc(): free the tags that no file carries and no file being written will get
tag_gc:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; (a0 is kept)
        sd    s8, 16(sp)                ; s8 = window
        sd    s9, 24(sp)                ; s9 = the window at the start (it stays)
        sd    s10, 32(sp)               ; s10 = every tag in use
        la    t0, wcur                  ; ...
        ld    s9, 0(t0)                 ; ...
        li    s8, 0                     ; ...
        li    s10, 0                    ; ...
tg_w:
        mv    a0, s8                    ; ...
        call  win                       ; ...
        la    t1, ftags                 ; the files'
        li    t2, WIN                   ; ...
tg_f:
        ld    t3, 0(t1)                 ; ...
        or    s10, s10, t3              ; ...
        addi  t1, t1, 8                 ; ...
        addi  t2, t2, -1                ; ...
        bnez  t2, tg_f                  ; ...
        addi  s8, s8, 1                 ; ...
        la    t0, nwin                  ; ...
        ld    t0, 0(t0)                 ; ...
        blt   s8, t0, tg_w              ; ...
        mv    a0, s9                    ; ...
        call  win                       ; ...
        mv    t0, s10                   ; t0 = every tag in use
        la    t1, opens                 ; the files being written
        li    t2, NOPEN                 ; ...
tg_ol:
        beqz  t2, tg_c                  ; ...
        ld    t3, O_USED(t1)            ; ...
        li    t4, 2                     ; ...
        bne   t3, t4, tg_on             ; ...
        ld    t3, O_TAGS(t1)            ; ...
        or    t0, t0, t3                ; ...
tg_on:
        addi  t1, t1, O_SIZEOF          ; ...
        addi  t2, t2, -1                ; ...
        j     tg_ol                     ; ...
tg_c:
        la    t1, tagtab                ; t1 = slot, t2 = its number
        li    t2, 0                     ; ...
tg_cl:
        li    t3, NTAGS                 ; all seen?
        bgeu  t2, t3, tg_ret            ; ...
        srl   t3, t0, t2                ; in use?
        andi  t3, t3, 1                 ; ...
        bnez  t3, tg_cn                 ; ...
        sd    zero, 0(t1)               ; no: the slot is free
        sd    zero, 8(t1)               ; ...
tg_cn:
        addi  t1, t1, TAGLEN            ; ...
        addi  t2, t2, 1                 ; ...
        j     tg_cl                     ; ...
tg_ret:
        ld    ra, 0(sp)                 ; ...
        ld    a0, 8(sp)                 ; ...
        ld    s8, 16(sp)                ; ...
        ld    s9, 24(sp)                ; ...
        ld    s10, 32(sp)               ; ...
        addi  sp, sp, 40                ; ...
        ret                             ; ...

