iobase: .dword 0                        ; base of the I/O buffer (what we wait for)
cid:    .dword 0                        ; command counter
cmd:    .space 32                       ; a block-device command
cqe:    .space 16                       ; its completion
ident:  .space 64                       ; the device's identify data
x_obj:  .dword 0                        ; the file system's trees: records,
x_data: .dword 0                        ;   contents,
x_name: .dword 0                        ;   names,
x_attr: .dword 0                        ;   the index,
x_dict: .dword 0                        ;   the dictionary,
x_ext:  .dword 0                        ;   and the namespace's extents
cnt:    .space 24                       ; the counters: next object id, objects, next tag id (u32), next attribute id (u32)
cnt_d:  .dword 0                        ; they changed
rec_oid: .dword 0                       ; the record at work: its object,
rec_len: .dword 0                       ;   its bytes,
rec_max: .dword 0                       ;   the most a record may be
okey:   .dword 0                        ; an object id as a key
dokey:  .dword 0                        ; another (a blob being written)
nval:   .dword 0                        ; a name's value: the object id
ib8:    .dword 0                        ; an index value at work
ik_len: .dword 0                        ; the index key's length
ikey:   .space 288                      ; an index key
ikey2:  .space 32                       ; one found
dk_len: .dword 0                        ; the dictionary key's length
dkey:   .space 264                      ; a dictionary key
dval:   .space 16                       ; its value
rkey:   .space 16                       ; a dictionary key by id; "w" and a blob being written
tnbuf:  .space 264                      ; a tag's name
nmlen:  .dword 0                        ; a name from a request: its length
nm:     .space 264                      ; ...
np:     .dword 0                        ; the tags the path names
ptags:  .space NQT * 8                  ; ...
nx:     .dword 0                        ; the tags it excludes
xtags:  .space NQT * 8                  ; ...
nnew:   .dword 0                        ; the tags this request made
newtags: .space NQT * 8                 ; ...
q_cur:  .dword 0                        ; a listing: the object it has reached
