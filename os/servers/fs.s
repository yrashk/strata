; dk_tag(a0 = name, a1 = its length): "t" and the name -> dkey, dk_len
dk_tag:
        la    t0, dkey                  ; ...
        li    t1, 't'                   ; ...
        sb    t1, 0(t0)                 ; ...
        addi  t1, a1, 1                 ; ...
        sd    t1, dk_len(zero)          ; ...
        mv    a2, a1                    ; ...
        mv    a1, a0                    ; ...
        addi  a0, t0, 1                 ; ...
        j     srv_bcopy                 ; ...

; rk_tag(a0 = tag id): "T" and the id, big-endian -> rkey
rk_tag:
        la    t0, rkey                  ; ...
        li    t1, 'T'                   ; ...
        sb    t1, 0(t0)                 ; ...
        srli  t1, a0, 24                ; ...
        sb    t1, 1(t0)                 ; ...
        srli  t1, a0, 16                ; ...
        sb    t1, 2(t0)                 ; ...
        srli  t1, a0, 8                 ; ...
        sb    t1, 3(t0)                 ; ...
        sb    a0, 4(t0)                 ; ...
        ret                             ; ...

; tag_find(a0 = name, a1 = length) -> a0 = the tag's id, or -1
tag_find:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        li    t0, NAMEMAX               ; ...
        bgtu  a1, t0, tf_no             ; ...
        beqz  a1, tf_no                 ; ...
        call  dk_tag                    ; ...
        ld    a0, x_dict(zero)          ; ...
        la    a1, dkey                  ; ...
        ld    a2, dk_len(zero)          ; ...
        la    a3, dval                  ; ...
        call  st_get                    ; ...
        bltz  a0, tf_no                 ; ...
        lwu   a0, dval(zero)            ; ...
        j     tf_ret                    ; ...
tf_no:
        li    a0, -1                    ; ...
tf_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; tag_name(a0 = tag id) -> a0 = its name's length (the name in tnbuf), or -1
tag_name:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        call  rk_tag                    ; ...
        ld    a0, x_dict(zero)          ; ...
        la    a1, rkey                  ; ...
        li    a2, 5                     ; ...
        la    a3, tnbuf                 ; ...
        call  st_get                    ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; tag_ref(a0 = name, a1 = length, a2 = 1: create it if missing) -> a0 = the
; tag's id, -4 no such tag, -1 bad name
tag_ref:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        mv    s3, a2                    ; ...
        li    a0, -1                    ; a name is 1..NAMEMAX bytes, not starting with "-"
        beqz  s2, tr_ret                ; ...
        li    t0, NAMEMAX               ; ...
        bgtu  s2, t0, tr_ret            ; ...
        lbu   t0, 0(s1)                 ; ...
        li    t1, '-'                   ; ...
        beq   t0, t1, tr_ret            ; ...
        mv    a0, s1                    ; ...
        mv    a1, s2                    ; ...
        call  tag_find                  ; ...
        bgez  a0, tr_ret                ; ...
        li    a0, -4                    ; ...
        beqz  s3, tr_ret                ; ...
        li    t0, 0                     ; a new tag: no "/" in its name
        li    t2, '/'                   ; ...
        li    a0, -1                    ; ...
tr_sl:
        add   t1, s1, t0                ; ...
        lbu   t1, 0(t1)                 ; ...
        beq   t1, t2, tr_ret            ; ...
        addi  t0, t0, 1                 ; ...
        bne   t0, s2, tr_sl             ; ...
        ld    t0, nnew(zero)            ; (no more than a path may name)
        li    t1, NQT                   ; ...
        li    a0, -6                    ; ...
        bgeu  t0, t1, tr_ret            ; ...
        lwu   s4, cnt+16(zero)          ; a new tag: the next id
        addi  t0, s4, 1                 ; ...
        sw    t0, cnt+16(zero)          ; ...
        li    t0, 1                     ; ...
        sd    t0, cnt_d(zero)           ; ...
        ld    t0, nnew(zero)            ; (remembered: should the request fail, it goes)
        slli  t1, t0, 3                 ; ...
        sd    s4, newtags(t1)           ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, nnew(zero)            ; ...
        sd    s4, dval(zero)            ; name -> id, no files yet
        sd    zero, dval+8(zero)        ; ...
        ld    a0, x_dict(zero)          ; (dkey is still "t", name)
        la    a1, dkey                  ; ...
        ld    a2, dk_len(zero)          ; ...
        la    a3, dval                  ; ...
        li    a4, 16                    ; ...
        li    a5, 0                     ; ...
        call  st_put                    ; ...
        mv    a0, s4                    ; id -> name
        call  rk_tag                    ; ...
        ld    a0, x_dict(zero)          ; ...
        la    a1, rkey                  ; ...
        li    a2, 5                     ; ...
        mv    a3, s1                    ; ...
        mv    a4, s2                    ; ...
        li    a5, 0                     ; ...
        call  st_put                    ; ...
        mv    a0, s4                    ; ...
tr_ret:
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 40                ; ...
        ret                             ; ...

; tag_count(a0 = tag id, a1 = change): the count of files carrying it; a tag
; that no file carries goes
tag_count:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        call  tag_name                  ; ...
        bltz  a0, tc_out                ; ...
        mv    a1, a0                    ; ...
        la    a0, tnbuf                 ; ...
        call  dk_tag                    ; ...
        ld    a0, x_dict(zero)          ; ...
        la    a1, dkey                  ; ...
        ld    a2, dk_len(zero)          ; ...
        la    a3, dval                  ; ...
        call  st_get                    ; ...
        bltz  a0, tc_out                ; ...
        ld    t0, dval+8(zero)          ; ...
        add   t0, t0, s2                ; ...
        sd    t0, dval+8(zero)          ; ...
        beqz  t0, tc_gone               ; ...
        ld    a0, x_dict(zero)          ; ...
        la    a1, dkey                  ; ...
        ld    a2, dk_len(zero)          ; ...
        la    a3, dval                  ; ...
        li    a4, 16                    ; ...
        li    a5, 0                     ; ...
        call  st_put                    ; ...
        j     tc_out                    ; ...
tc_gone:
        ld    a0, x_dict(zero)          ; ...
        la    a1, dkey                  ; ...
        ld    a2, dk_len(zero)          ; ...
        call  st_del                    ; ...
        mv    a0, s1                    ; ...
        call  rk_tag                    ; ...
        ld    a0, x_dict(zero)          ; ...
        la    a1, rkey                  ; ...
        li    a2, 5                     ; ...
        call  st_del                    ; ...
tc_out:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; tags_undo(): the tags this request made that no file carries go (the
; request failed, or made them for nothing). a0 is kept.
tags_undo:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
tu_l:
        ld    t0, nnew(zero)            ; ...
        beqz  t0, tu_ret                ; ...
        addi  t0, t0, -1                ; ...
        sd    t0, nnew(zero)            ; ...
        slli  t0, t0, 3                 ; ...
        ld    a0, newtags(t0)           ; ...
        li    a1, 0                     ; (no change: it goes if its count is 0)
        call  tag_count                 ; ...
        j     tu_l                      ; ...
tu_ret:
        ld    a0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

