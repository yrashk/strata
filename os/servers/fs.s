        mv    a0, s2                    ; ...
        li    a1, 1                     ; ...
        call  tag_count                 ; ...
        j     fat_l                     ; ...
fat_save:
        call  rec_save                  ; ...
fat_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; fs_remove() -> a0 = 0, or -1 (a boot object): rec's file goes: its index
; entries, its tags' counts, its name, its contents, its record
fs_remove:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        la    t0, rec                   ; ...
        lbu   t1, R_FLAGS(t0)           ; ...
        andi  t1, t1, 1                 ; ...
        li    a0, -1                    ; ...
        bnez  t1, frm_ret               ; ...
        li    a0, 0                     ; ...
        li    a1, A_SIZE                ; ...
        ld    a2, R_SIZE(t0)            ; ...
        call  idx_u64                   ; ...
        li    a0, 0                     ; ...
        li    a1, A_MOD                 ; ...
        la    t0, rec                   ; ...
        ld    a2, R_MOD(t0)             ; ...
        call  idx_u64                   ; ...
        li    s1, 0                     ; ...
frm_t:
        la    t0, rec                   ; ...
        lhu   t1, R_NTAGS(t0)           ; ...
        bgeu  s1, t1, frm_n             ; ...
        slli  t1, s1, 2                 ; ...
        add   t1, t1, t0                ; ...
        lwu   a1, R_TAGS(t1)            ; ...
        li    a0, 0                     ; ...
        call  idx_tag                   ; ...
        la    t0, rec                   ; ...
        slli  t1, s1, 2                 ; ...
        add   t1, t1, t0                ; ...
        lwu   a0, R_TAGS(t1)            ; ...
        li    a1, -1                    ; ...
        call  tag_count                 ; ...
        addi  s1, s1, 1                 ; ...
        j     frm_t                     ; ...
frm_n:
        call  rec_name                  ; ...
        mv    a2, a1                    ; ...
        mv    a1, a0                    ; ...
        la    a0, tnbuf                 ; (a copy: the key is not in a record at work)
        sd    a2, dk_len(zero)          ; ...
        call  srv_bcopy                 ; ...
        ld    a0, x_name(zero)          ; ...
        la    a1, tnbuf                 ; ...
        ld    a2, dk_len(zero)          ; ...
        call  st_del                    ; ...
        ld    a0, rec_oid(zero)         ; ...
        call  bswap                     ; ...
        sd    a0, okey(zero)            ; ...
        ld    a0, x_data(zero)          ; ...
        la    a1, okey                  ; ...
        li    a2, 8                     ; ...
        call  st_bdel                   ; ...
        ld    a0, x_obj(zero)           ; ...
        la    a1, okey                  ; ...
        li    a2, 8                     ; ...
        call  st_del                    ; ...
        ld    t0, cnt+8(zero)           ; one object less
        addi  t0, t0, -1                ; ...
        sd    t0, cnt+8(zero)           ; ...
        li    t0, 1                     ; ...
        sd    t0, cnt_d(zero)           ; ...
        li    a0, 0                     ; ...
frm_ret:
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; fs_resize(a0 = size): rec's file has that size, changed by this commit (the
; index follows; the record is saved)
fs_resize:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        mv    s1, a0                    ; ...
        li    a0, 0                     ; ...
        li    a1, A_SIZE                ; ...
        la    t0, rec                   ; ...
        ld    a2, R_SIZE(t0)            ; ...
        call  idx_u64                   ; ...
        li    a0, 0                     ; ...
        li    a1, A_MOD                 ; ...
        la    t0, rec                   ; ...
        ld    a2, R_MOD(t0)             ; ...
        call  idx_u64                   ; ...
        la    t0, rec                   ; ...
        sd    s1, R_SIZE(t0)            ; ...
        ld    t1, st_txn(zero)          ; ...
        sd    t1, R_MOD(t0)             ; ...
        li    a0, 1                     ; ...
        li    a1, A_SIZE                ; ...
        mv    a2, s1                    ; ...
        call  idx_u64                   ; ...
        li    a0, 1                     ; ...
        li    a1, A_MOD                 ; ...
        ld    a2, st_txn(zero)          ; ...
        call  idx_u64                   ; ...
        call  rec_save                  ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

