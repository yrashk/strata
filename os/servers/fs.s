; st_full: the disk has no room for what the request needs. st_die: a page
; failed its checksum, or the device refused. Reached from anywhere in the
; store: the commit under way is given up (what was not yet committed is
; lost: the bytes one open file had written since the last commit, and
; that file takes no more: fs_lost), and the request is answered -1 or -5.
st_full:
        li    s1, -1                    ; ...
        j     st_fail                   ; ...
st_die:
        li    s1, -5                    ; ...
st_fail:
        la    t0, srv_gsp               ; the loop's stack
        ld    sp, 0(t0)                 ; ...
        ld    t0, nofs(zero)            ; ...
        bnez  t0, sf_reply              ; ...
        li    t0, 1                     ; (a failure in here: no store any more)
        sd    t0, nofs(zero)            ; ...
        call  fs_lost                   ; ...
        call  st_abort                  ; ...
        bltz  a0, sf_reply              ; ...
        call  fs_trees                  ; ...
        sd    a0, nofs(zero)            ; ...
sf_reply:
        mv    a0, s1                    ; ...
        cvalid t0, c6                   ; (at start there is no request)
        beqz  t0, start                 ; ...
        cvalid t0, c7                   ; ...
        bnez  t0, reply_att             ; ...
        j     reply                     ; ...

; fs_trap: a trap in user mode. An xcall of a code unit that is not in the
; I-LS (cause 8, xmiss): the dispatcher pages it in (svc PAGE) and the xcall
; runs again; every register is as it was. Anything else is the guard's (a
; request whose owner died).
fs_trap:
        sd    a0, tr_sv(zero)           ; ...
        csrr  a0, cause                 ; ...
        addi  a0, a0, -8                ; ...
        bnez  a0, ftr_no                ; ...
        sd    a1, tr_sv+8(zero)         ; ...
        sd    a2, tr_sv+16(zero)        ; ...
        csrr  a1, tval                  ; the far address missed
        csrr  a2, epc                   ; where
        li    a0, 14                    ; PAGE
        svc                             ; ...
        ld    a2, tr_sv+16(zero)        ; ...
        ld    a1, tr_sv+8(zero)         ; ...
        bnez  a0, ftr_no                ; (it cannot: as a fault)
        ld    a0, tr_sv(zero)           ; ...
        eret                            ; the xcall again
ftr_no:
        ld    a0, tr_sv(zero)           ; ...
        j     srv_trap                  ; ...

