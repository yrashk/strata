; fs_create() -> a0 = a new, empty file named nm (its record in rec, saved)
fs_create:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        la    a0, rec                   ; ...
        li    a1, 1024                  ; ...
        call  wzero                     ; ...
        la    t0, rec                   ; ...
        li    t1, 1                     ; a file
        sb    t1, 0(t0)                 ; ...
        ld    t1, nmlen(zero)           ; ...
        sh    t1, R_NL(t0)              ; ...
        addi  t1, t1, R_TAGS            ; ...
        sd    t1, rec_len(zero)         ; ...
        ld    t1, st_txn(zero)          ; ...
        sd    t1, R_CRE(t0)             ; ...
        sd    t1, R_MOD(t0)             ; ...
        addi  a0, t0, R_TAGS            ; ...
        la    a1, nm                    ; ...
        ld    a2, nmlen(zero)           ; ...
        call  srv_bcopy                 ; ...
        ld    t0, cnt(zero)             ; the next object id
        sd    t0, rec_oid(zero)         ; ...
        sd    t0, nval(zero)            ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, cnt(zero)             ; ...
        ld    t0, cnt+8(zero)           ; one more object
        addi  t0, t0, 1                 ; ...
        sd    t0, cnt+8(zero)           ; ...
        li    t0, 1                     ; ...
        sd    t0, cnt_d(zero)           ; ...
        ld    a0, x_name(zero)          ; its name
        la    a1, nm                    ; ...
        ld    a2, nmlen(zero)           ; ...
        la    a3, nval                  ; ...
        li    a4, 8                     ; ...
        li    a5, 0                     ; ...
        call  st_put                    ; ...
        li    a0, 1                     ; indexed by size and by change
        li    a1, A_SIZE                ; ...
        li    a2, 0                     ; ...
        call  idx_u64                   ; ...
        li    a0, 1                     ; ...
        li    a1, A_MOD                 ; ...
        ld    a2, st_txn(zero)          ; ...
        call  idx_u64                   ; ...
        call  rec_save                  ; ...
        ld    a0, rec_oid(zero)         ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; fs_addtags() -> a0 = 0 / -6: rec's file gains the tags in ptags it does not
; carry yet (the record is saved)
fs_addtags:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        li    s1, 0                     ; ...
fat_l:
        ld    t0, np(zero)              ; ...
        bgeu  s1, t0, fat_save          ; ...
        slli  t0, s1, 3                 ; ...
        ld    s2, ptags(t0)             ; ...
        addi  s1, s1, 1                 ; ...
        mv    a0, s2                    ; ...
