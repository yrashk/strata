        call  st_put                    ; ...
        li    a0, 0                     ; ...
rsv_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; rec_name() -> a0 = the name in rec, a1 = its length: after the tag ids
; (padded to a word) and the attributes ({u32 id, u8 type, u8 length, u16 0,
; the value padded to a word} each)
rec_name:
        la    t0, rec                   ; ...
        lhu   t1, R_NTAGS(t0)           ; ...
        slli  t1, t1, 2                 ; ...
        addi  t1, t1, 7                 ; ...
        srli  t1, t1, 3         ; (down to a whole word)
        slli  t1, t1, 3         ; ...
        addi  a0, t1, R_TAGS            ; ...
        add   a0, a0, t0                ; ...
        lhu   t2, R_NATTR(t0)           ; ...
rn_l:
        beqz  t2, rn_ret                ; ...
        lbu   t3, 5(a0)                 ; ...
        addi  t3, t3, 7                 ; ...
        srli  t3, t3, 3         ; (down to a whole word)
        slli  t3, t3, 3         ; ...
        add   a0, a0, t3                ; ...
        addi  a0, a0, 8                 ; ...
        addi  t2, t2, -1                ; ...
        j     rn_l                      ; ...
rn_ret:
        lhu   a1, R_NL(t0)              ; ...
        ret                             ; ...

; rec_hastag(a0 = tag id) -> a0 = its index among rec's tags, or -1
rec_hastag:
        la    t0, rec                   ; ...
        lhu   t1, R_NTAGS(t0)           ; ...
        li    t2, 0                     ; ...
rh_l:
        bgeu  t2, t1, rh_no             ; ...
        slli  t3, t2, 2                 ; ...
        add   t3, t3, t0                ; ...
        lwu   t3, R_TAGS(t3)            ; ...
        beq   t3, a0, rh_yes            ; ...
        addi  t2, t2, 1                 ; ...
        j     rh_l                      ; ...
rh_yes:
        mv    a0, t2                    ; ...
        ret                             ; ...
rh_no:
        li    a0, -1                    ; ...
        ret                             ; ...

; rec_addtag(a0 = tag id): one more tag id in rec; what follows the ids moves
; up a word when they fill their last one
rec_addtag:
        la    t0, rec                   ; ...
        lhu   t1, R_NTAGS(t0)           ; ...
        andi  t2, t1, 1                 ; an odd count: the id fits in the padding
        bnez  t2, ra_put                ; ...
        slli  t3, t1, 2                 ; t3 = where the rest starts
        addi  t3, t3, R_TAGS            ; ...
        add   t3, t3, t0                ; ...
        ld    t4, rec_len(zero)         ; t5 = where it ends, in whole words
        addi  t5, t4, 7                 ; ...
        srli  t5, t5, 3         ; (down to a whole word)
        slli  t5, t5, 3         ; ...
        add   t5, t5, t0                ; ...
        addi  t4, t4, 8                 ; ...
        sd    t4, rec_len(zero)         ; ...
ra_m:
        beq   t5, t3, ra_z              ; ...
        addi  t5, t5, -8                ; ...
        ld    t6, 0(t5)                 ; ...
        sd    t6, 8(t5)                 ; ...
        j     ra_m                      ; ...
ra_z:
        sd    zero, 0(t3)               ; ...
ra_put:
        slli  t3, t1, 2                 ; ...
        add   t3, t3, t0                ; ...
        sw    a0, R_TAGS(t3)            ; ...
        addi  t1, t1, 1                 ; ...
        sh    t1, R_NTAGS(t0)           ; ...
        ret                             ; ...

; rec_deltag(a0 = index): that tag id leaves rec (the last one takes its
; place); what follows the ids moves down a word when a word of them empties
rec_deltag:
        la    t0, rec                   ; ...
        lhu   t1, R_NTAGS(t0)           ; ...
        addi  t1, t1, -1                ; ...
        sh    t1, R_NTAGS(t0)           ; ...
        slli  t2, t1, 2                 ; the last id
        add   t2, t2, t0                ; ...
        lwu   t3, R_TAGS(t2)            ; ...
        sw    zero, R_TAGS(t2)          ; ...
        beq   a0, t1, rd_sh             ; ...
        slli  t4, a0, 2                 ; ...
        add   t4, t4, t0                ; ...
        sw    t3, R_TAGS(t4)            ; ...
rd_sh:
        andi  t2, t1, 1                 ; an even count now: a word emptied
        bnez  t2, rd_ret                ; ...
        slli  t3, t1, 2                 ; t3 = where the rest goes
        addi  t3, t3, R_TAGS            ; ...
        add   t3, t3, t0                ; ...
        ld    t4, rec_len(zero)         ; ...
        addi  t5, t4, 7                 ; ...
        srli  t5, t5, 3         ; (down to a whole word)
        slli  t5, t5, 3         ; ...
        add   t5, t5, t0                ; t5 = where it ends now
        addi  t4, t4, -8                ; ...
        sd    t4, rec_len(zero)         ; ...
rd_m:
        addi  t6, t3, 8                 ; ...
        bgeu  t6, t5, rd_z              ; ...
        ld    t6, 8(t3)                 ; ...
        sd    t6, 0(t3)                 ; ...
        addi  t3, t3, 8                 ; ...
        j     rd_m                      ; ...
rd_z:
        sd    zero, 0(t3)               ; ...
rd_ret:
        ret                             ; ...

