        call  get_named                 ; ...
        bltz  a0, reply_att             ; ...
        call  lookup                    ; ...
        li    t1, -4                    ; no such program
        beqz  a0, oli_err               ; ...
        mv    s1, a0                    ; ...
        lwu   s2, 28(s1)                ; size
        addi  t0, s2, 511               ; whole blocks must fit
        srli  t0, t0, 9                 ; ...
        slli  t1, t0, 9                 ; ...
        la    t2, srv_hdr               ; (handle = the most bytes)
        ld    t3, 8(t2)                 ; ...
        li    t1, -1                    ; too big
        slli  t4, t0, 9                 ; ...
        bgtu  t4, t3, oli_err           ; ...
        li    a0, 1                     ; read
        lwu   a1, 24(s1)                ; ...
        mv    a2, t0                    ; ...
        ld    a3, 24(t2)                ; at the arena offset (mode)
        li    a4, 7                     ; into the attachment
        call  blkn                      ; ...
        mv    a0, s2                    ; the size
        j     reply_att                 ; the arena goes back with the reply
oli_err:
        mv    a0, t1                    ; ...
        j     reply_att                 ; ...

; READALL: an open file, whole, into the attached arena
op_readall:
        cvalid t0, c7                   ; ...
        beqz  t0, bad                   ; ...
        la    t0, srv_hdr               ; ...
        ld    a0, 8(t0)                 ; ...
        call  orec                      ; ...
        li    t1, -1                    ; ...
        beqz  a0, oli_err               ; ...
        mv    s1, a0                    ; ...
        ld    t0, O_USED(s1)            ; ...
        li    t2, 1                     ; ...
        bne   t0, t2, oli_err           ; ...
        ld    s2, O_SIZE(s1)            ; ...
        addi  t0, s2, 511               ; ...
        srli  t0, t0, 9                 ; ...
        slli  t4, t0, 9                 ; ...
        la    t2, srv_hdr               ; (length = the most bytes)
        ld    t3, 16(t2)                ; ...
        bgtu  t4, t3, oli_err           ; ...
        li    a0, 1                     ; ...
        ld    a1, O_LBA(s1)             ; ...
        mv    a2, t0                    ; ...
        ld    a3, 24(t2)                ; arena offset
        li    a4, 7                     ; ...
        call  blkn                      ; ...
        mv    a0, s2                    ; ...
        j     reply_att                 ; ...

; WRITEALL: bytes of the attached arena appended to a file being written
op_writeall:
        cvalid t0, c7                   ; ...
        beqz  t0, bad                   ; ...
        la    t0, srv_hdr               ; ...
        ld    a0, 8(t0)                 ; ...
        call  orec                      ; ...
        li    t1, -1                    ; ...
        beqz  a0, oli_err               ; ...
        mv    s1, a0                    ; ...
        ld    t0, O_USED(s1)            ; ...
        li    t2, 2                     ; ...
        bne   t0, t2, oli_err           ; ...
        la    t0, srv_hdr               ; s2 = offset, s3 = bytes left
        ld    s2, 24(t0)                ; ...
        ld    s3, 16(t0)                ; ...
        ld    t1, O_SIZE(s1)            ; at most what the region holds
        li    t2, REGSZ                 ; ...
        sub   t2, t2, t1                ; ...
        bleu  s3, t2, owa_l             ; ...
        mv    s3, t2                    ; ...
owa_l:
        beqz  s3, owa_done              ; ...
        li    s4, 4096                  ; a chunk
        bleu  s4, s3, owa_n             ; ...
        mv    s4, s3                    ; ...
owa_n:
        addi  t1, s4, 7                 ; arena -> D-LS (whole words)
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        la    t0, bounce2               ; ...
        tget  tg1, t0, c7, s2, t1       ; ...
        twait 1 << 1                    ; ...
        mv    a0, s1                    ; -> the region
        la    a1, bounce2               ; ...
        mv    a2, s4                    ; ...
        call  append                    ; ...
        add   s2, s2, s4                ; ...
        sub   s3, s3, s4                ; ...
        j     owa_l                     ; ...
owa_done:
        la    t0, srv_hdr               ; the bytes taken
        ld    a0, 16(t0)                ; ...
        j     reply_att                 ; ...

