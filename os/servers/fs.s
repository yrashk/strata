; tcount(): tcnt[t] = the files that carry tag t; the window stays
tcount:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s8, 8(sp)                 ; s8 = window
        sd    s9, 16(sp)                ; s9 = the window at the start
        la    t0, tcnt                  ; none yet
        li    t1, NTAGS                 ; ...
tc_z:
        sd    zero, 0(t0)               ; ...
        addi  t0, t0, 8                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, tc_z                  ; ...
        la    t0, wcur                  ; ...
        ld    s9, 0(t0)                 ; ...
        li    s8, 0                     ; ...
tc_w:
        mv    a0, s8                    ; ...
        call  win                       ; ...
        la    t0, ftags                 ; ...
        li    t1, WIN                   ; ...
tc_e:
        ld    t2, 0(t0)                 ; a file's tags: one more for each
        la    t3, tcnt                  ; ...
tc_b:
        beqz  t2, tc_n                  ; ...
        andi  t4, t2, 1                 ; ...
        ld    t5, 0(t3)                 ; ...
        add   t5, t5, t4                ; ...
        sd    t5, 0(t3)                 ; ...
        srli  t2, t2, 1                 ; ...
        addi  t3, t3, 8                 ; ...
        j     tc_b                      ; ...
tc_n:
        addi  t0, t0, 8                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, tc_e                  ; ...
        addi  s8, s8, 1                 ; ...
        la    t0, nwin                  ; ...
        ld    t0, 0(t0)                 ; ...
        blt   s8, t0, tc_w              ; ...
        mv    a0, s9                    ; ...
        call  win                       ; ...
        ld    ra, 0(sp)                 ; ...
        ld    s8, 8(sp)                 ; ...
        ld    s9, 16(sp)                ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; ftag_of(a0 = directory entry) -> a0 = the address of its tag set (t0 only)
ftag_of:
        la    t0, dir                   ; (entry - dir) / 32 * 8
        sub   a0, a0, t0                ; ...
        srli  a0, a0, 2                 ; ...
        la    t0, ftags                 ; ...
        add   a0, a0, t0                ; ...
        ret                             ; ...

; lookup() -> a0 = the entry named nm if it carries every tag in pmask and
; none in nmask, or 0
lookup:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        call  find                      ; ...
        beqz  a0, lk_ret                ; no such name
        sd    a0, 8(sp)                 ; ...
        call  ftag_of                   ; its tags
        ld    t1, 0(a0)                 ; ...
        la    t2, pmask                 ; ...
        ld    t2, 0(t2)                 ; ...
        and   t3, t1, t2                ; all of them?
        li    a0, 0                     ; (no)
        bne   t3, t2, lk_ret            ; ...
        la    t2, nmask                 ; and none of the excluded ones?
        ld    t2, 0(t2)                 ; ...
        and   t3, t1, t2                ; ...
        bnez  t3, lk_ret                ; (it carries one)
        ld    a0, 8(sp)                 ; yes
lk_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; give_back(a0 = entry): if its blocks end at the first free block, they are
; free again (the only reuse this simple file system does); a0 is kept
give_back:
        lwu   t0, 24(a0)                ; first block
        lwu   t1, 28(a0)                ; size -> blocks
        addi  t1, t1, 511               ; ...
        srli  t1, t1, 9                 ; ...
        add   t2, t0, t1                ; its end
        la    t3, hdr                   ; the first free block
        lwu   t4, 40(t3)                ; ...
        bne   t2, t4, gb_ret            ; not the last file
        sw    t0, 40(t3)                ; it is: the space is free again
gb_ret:
        ret                             ; ...

; remove(a0 = entry): delete it, and its tags
remove:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        call  give_back                 ; its blocks
        sd    a0, 8(sp)                 ; ...
        call  ftag_of                   ; it carries no tags
        sd    zero, 0(a0)               ; ...
        ld    a0, 8(sp)                 ; clear the entry
        li    t1, 32                    ; ...
rm_z:
        sb    zero, 0(a0)               ; ...
        addi  a0, a0, 1                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, rm_z                  ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; save_file(a0 = open record): write its region as a file named in it -> a0 = 0 / -1.
; A file of that name is replaced in place: it keeps its directory entry and
; its tags, and gets the record's tags too.
save_file:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        mv    s1, a0                    ; s1 = the record
        ld    t0, O_NLEN(s1)            ; its name -> nm
        la    t1, nmlen                 ; ...
        sd    t0, 0(t1)                 ; ...
        la    a0, nm                    ; ...
        addi  a1, s1, O_NAME            ; ...
        li    a2, 24                    ; ...
        call  srv_bcopy                 ; ...
        call  find                      ; s2 = an old file of that name
        mv    s2, a0                    ; ...
        li    s4, 1                     ; s4 = 1: it is replaced
        beqz  s2, sf_new                ; none
        call  give_back                 ; its blocks may be reused
        j     sf_have                   ; ...
sf_new:
        li    s4, 0                     ; a new file
        call  dfree                     ; a free entry
        mv    s2, a0                    ; ...
        beqz  s2, sf_fail               ; none
        mv    a0, s2                    ; it has no tags yet
        call  ftag_of                   ; ...
        sd    zero, 0(a0)               ; ...
sf_have:
        la    t0, hdr                   ; it goes at the first free block
        lwu   s3, 40(t0)                ; ...
        ld    t1, O_SIZE(s1)            ; its blocks
        addi  t1, t1, 511               ; ...
        srli  t1, t1, 9                 ; ...
        add   t2, s3, t1                ; does it fit?
        la    t3, total           ; (its address)
        ld    t3, 0(t3)              ; ...
        bgtu  t2, t3, sf_drop           ; ...
        sw    t2, 40(t0)                ; the new first free block
        li    a0, 2                     ; write the region
        mv    a1, s3                    ; ...
        mv    a2, t1                    ; ...
        ld    t4, O_REG(s1)             ; ...
        li    t5, REGSZ                 ; ...
        mul   a3, t4, t5                ; ...
        li    t5, REG0                  ; ...
        add   a3, a3, t5                ; ...
        li    a4, 5                     ; ...
        call  blkn                      ; ...
        mv    a0, s2                    ; the directory entry
        la    a1, nm                    ; name
        la    a2, nmlen           ; (its address)
        ld    a2, 0(a2)              ; ...
        call  srv_bcopy                 ; ...
        sw    s3, 24(s2)                ; first block
        ld    t0, O_SIZE(s1)            ; size
        sw    t0, 28(s2)                ; ...
        mv    a0, s2                    ; the path's tags join its own
        call  ftag_of                   ; ...
        ld    t1, 0(a0)                 ; ...
        ld    t2, O_TAGS(s1)            ; ...
        or    t1, t1, t2                ; ...
        sd    t1, 0(a0)                 ; ...
        call  save_meta                 ; ...
        li    a0, 0                     ; ...
        j     sf_ret                    ; ...
sf_drop:
        beqz  s4, sf_fail               ; a file it replaces is gone (its blocks
        mv    a0, s2                    ; may already be free again)
        call  remove                    ; ...
        call  save_meta                 ; ...
sf_fail:
        li    a0, -1                    ; disk or directory full
sf_ret:
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; ...

