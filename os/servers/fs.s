; fs_tree(a0 = name, a1 = its length, a2 = 1: make it) -> a0 = the tree of
; namespace nval (kept there by fs_trees)
fs_tree:
        mv    a3, a2                    ; ...
        mv    a2, a1                    ; ...
        mv    a1, a0                    ; ...
        ld    a0, nval(zero)            ; ...
        j     st_tree                   ; ...

; fs_trees() -> a0 = 0, or 1 when the store holds no file system: the trees
; of namespace "fs", the counters
fs_trees:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        li    a0, 0                     ; the namespace's id: tree "ns" of namespace 0
        la    a1, s_ns                  ; ...
        li    a2, 2                     ; ...
        li    a3, 0                     ; ...
        call  st_tree                   ; ...
        beqz  a0, fst_no                ; ...
        sd    a0, x_nst(zero)           ; ...
        la    a1, s_fs                  ; ...
        li    a2, 2                     ; ...
        la    a3, dval                  ; ...
        call  st_get                    ; ...
        bltz  a0, fst_no                ; ...
        ld    t0, dval(zero)            ; ...
        sd    t0, nval(zero)            ; ...
        sd    t0, fs_ns(zero)           ; ...
        sd    zero, snap_on(zero)       ; ...
        li    a0, 0                     ; the snapshots, and the newest one's commit
        la    a1, s_snap                ; ...
        li    a2, 4                     ; ...
        li    a3, 1                     ; ...
        call  st_tree                   ; ...
        sd    a0, x_snap(zero)          ; ...
        li    t0, -1                    ; ...
        sd    t0, rkey(zero)            ; ...
        sd    zero, st_deadlim(zero)    ; ...
        la    a1, rkey                  ; ...
        li    a2, 8                     ; ...
        li    a3, ST_LT                 ; ...
        la    a4, rkey                  ; ...
        li    a5, 0                     ; ...
        call  st_seek                   ; ...
        beqz  a0, fst_ns                ; ...
        ld    a0, rkey(zero)            ; ...
        call  bswap                     ; ...
        sd    a0, st_deadlim(zero)      ; ...
fst_ns:
        la    a0, s_obj                 ; ...
        li    a1, 3                     ; ...
        li    a2, 0                     ; ...
        call  fs_tree                   ; ...
        beqz  a0, fst_no                ; ...
        sd    a0, x_obj(zero)           ; ...
        la    a0, s_data                ; ...
        li    a1, 4                     ; ...
        li    a2, 0                     ; ...
        call  fs_tree                   ; ...
        beqz  a0, fst_no                ; ...
        sd    a0, x_data(zero)          ; ...
        la    a0, s_name                ; ...
        li    a1, 4                     ; ...
        li    a2, 0                     ; ...
        call  fs_tree                   ; ...
        beqz  a0, fst_no                ; ...
        sd    a0, x_name(zero)          ; ...
        la    a0, s_attr                ; ...
        li    a1, 4                     ; ...
        li    a2, 0                     ; ...
        call  fs_tree                   ; ...
        beqz  a0, fst_no                ; ...
        sd    a0, x_attr(zero)          ; ...
        la    a0, s_dict                ; ...
        li    a1, 4                     ; ...
        li    a2, 0                     ; ...
        call  fs_tree                   ; ...
        beqz  a0, fst_no                ; ...
        sd    a0, x_dict(zero)          ; ...
        la    a0, s_ext                 ; (made by the first stream)
        li    a1, 4                     ; ...
        li    a2, 1                     ; ...
        call  fs_tree                   ; ...
        sd    a0, x_ext(zero)           ; ...
        sd    a0, bl_ext(zero)          ; ...
        la    t0, dkey                  ; the counters
        li    t1, '!'                   ; ...
        sb    t1, 0(t0)                 ; ...
        ld    a0, x_dict(zero)          ; ...
        mv    a1, t0                    ; ...
        li    a2, 1                     ; ...
        la    a3, cnt                   ; ...
        call  st_get                    ; ...
        bltz  a0, fst_no                ; ...
        sd    zero, cnt_d(zero)         ; ...
        ld    t0, st_ps(zero)           ; the most a record may be: an inline value
        addi  t0, t0, -32               ; under an 8-byte key
        srli  t0, t0, 2                 ; ...
        addi  t0, t0, -2                ; ...
        srli  t0, t0, 3         ; (down to a whole word)
        slli  t0, t0, 3         ; ...
        addi  t0, t0, -16               ; ...
        sd    t0, rec_max(zero)         ; ...
        li    a0, 0                     ; ...
        j     fst_ret                   ; ...
fst_no:
        li    a0, 1                     ; ...
fst_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; fs_mount() -> a0 = 0, or 1 when the disk holds no file system
fs_mount:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        call  st_mount                  ; ...
        li    t0, 1                     ; ...
        bltz  a0, fsm_ret               ; ...
        li    t1, 0                     ; log2 of the page size
        ld    t2, st_ps(zero)           ; ...
fsm_sh:
        srli  t2, t2, 1                 ; ...
        beqz  t2, fsm_shd               ; ...
        addi  t1, t1, 1                 ; ...
        j     fsm_sh                    ; ...
fsm_shd:
        sd    t1, st_sh(zero)           ; ...
        call  fs_trees                  ; ...
        mv    t0, a0                    ; ...
        bnez  t0, fsm_ret               ; ...
        li    s1, 0                     ; blobs that were being written when the machine
fsm_w:
        la    t0, rkey                  ; stopped: they belong to no file ("w", blob id)
        li    t1, 'w'                   ; ...
        sd    zero, 0(t0)               ; ...
        sd    zero, 8(t0)               ; ...
        sb    t1, 0(t0)                 ; ...
        ld    a0, x_dict(zero)          ; ...
        mv    a1, t0                    ; ...
        li    a2, 1                     ; ...
        li    a3, ST_GT                 ; ...
        la    a4, rkey                  ; ...
        li    a5, 0                     ; ...
        call  st_seek                   ; ...
        beqz  a0, fsm_wd                ; ...
        lbu   t0, rkey(zero)            ; ...
        li    t1, 'w'                   ; ...
        bne   t0, t1, fsm_wd            ; ...
        ld    t0, rkey+8(zero)          ; ...
        sd    t0, dokey(zero)           ; ...
        ld    a0, x_data(zero)          ; ...
        la    a1, dokey                 ; ...
        li    a2, 8                     ; ...
        call  st_bdel                   ; ...
        ld    a0, x_dict(zero)          ; ...
        la    a1, rkey                  ; ...
        li    a2, 16                    ; ...
        call  st_del                    ; ...
        li    s1, 1                     ; ...
        j     fsm_w                     ; ...
fsm_wd:
        beqz  s1, fsm_ok                ; ...
        call  fs_commit                 ; ...
fsm_ok:
        li    t0, 0                     ; ...
fsm_ret:
        mv    a0, t0                    ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; fs_commit(): the counters if they changed, and the commit
fs_commit:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        ld    t0, cnt_d(zero)           ; ...
        beqz  t0, fsc_c                 ; ...
        sd    zero, cnt_d(zero)         ; ...
        la    t0, dkey                  ; ...
        li    t1, '!'                   ; ...
        sb    t1, 0(t0)                 ; ...
        ld    a0, x_dict(zero)          ; ...
        mv    a1, t0                    ; ...
        li    a2, 1                     ; ...
        la    a3, cnt                   ; ...
        li    a4, 24                    ; ...
        li    a5, 0                     ; ...
        call  st_put                    ; ...
fsc_c:
        call  st_commit                 ; ...
        sd    zero, tx_w(zero)          ; (no writer has bytes not committed)
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; One writer at a time has bytes that are not committed (tx_w): bytes from
; another writer, or a request that changes anything else, commit them first
; (tx_sync). So when a commit is given up, one open file at most loses
; anything, and the others go on.

; fs_lost(): the commit under way is given up: the file whose bytes were in
; it is lost (2 write -> 4, 3 append -> 5: nothing more can be written to it)
fs_lost:
        ld    t0, tx_w(zero)            ; ...
        sd    zero, tx_w(zero)          ; ...
        beqz  t0, fl_n                  ; ...
        ld    t1, O_USED(t0)            ; ...
        addi  t1, t1, 2                 ; ...
        sd    t1, O_USED(t0)            ; ...
fl_n:
        ret                             ; ...

; tx_take(a0 = open record): bytes are about to be written to it: another
; writer's uncommitted bytes are committed first (a commit holds one
; writer's), and this one's are the uncommitted ones from here on. Before the
; bytes are fetched into reqbuf: a commit builds the meta block there.
tx_take:
        ld    t0, tx_w(zero)            ; ...
        beq   t0, a0, txt_ret           ; ...
        addi  sp, sp, -16               ; ...
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        call  tx_sync                   ; ...
        ld    a0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        sd    a0, tx_w(zero)            ; ...
txt_ret:
        ret                             ; ...

; tx_sync(): a writer's bytes that are not committed yet are
tx_sync:
        ld    t0, tx_w(zero)            ; ...
        bnez  t0, fs_commit             ; ...
        ret                             ; ...

