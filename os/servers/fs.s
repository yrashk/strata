; cwd_find(a0 = pid) -> a0 = its entry's index, or -1 (pid 0: a free entry)
cwd_find:
        li    t0, 0                     ; ...
        li    t1, NCWD * 8              ; ...
cwf_l:
        ld    t2, cwdp(t0)              ; ...
        beq   t2, a0, cwf_yes           ; ...
        addi  t0, t0, 8                 ; ...
        bne   t0, t1, cwf_l             ; ...
        li    a0, -1                    ; ...
        ret                             ; ...
cwf_yes:
        srli  a0, t0, 3                 ; ...
        ret                             ; ...

; cwd_load(a0 = index): the entry's text -> cwdt (length, text)
cwd_load:
        slli  t0, a0, 7                 ; ...
        li    t1, CWDFAR                ; ...
        add   t0, t0, t1                ; ...
        la    t1, cwdt                  ; ...
        li    t2, 128                   ; ...
        tget  tg1, t1, c5, t0, t2       ; ...
        twait 1 << 1                    ; ...
        ret                             ; ...

; cwd_store(a0 = index): cwdt -> the entry's text
cwd_store:
        slli  t0, a0, 7                 ; ...
        li    t1, CWDFAR                ; ...
        add   t0, t0, t1                ; ...
        la    t1, cwdt                  ; ...
        li    t2, 128                   ; ...
        tput  tg1, t1, c5, t0, t2       ; ...
        twait 1 << 1                    ; ...
        ret                             ; ...

; cwd_drop(a0 = pid): forget its current path (it is at "/" again)
cwd_drop:
        beqz  a0, cwd_r                 ; ...
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        call  cwd_find                  ; ...
        bltz  a0, cwd_d                 ; ...
        slli  a0, a0, 3                 ; ...
        sd    zero, cwdp(a0)            ; ...
cwd_d:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
cwd_r:
        ret                             ; ...

