; =============================================================================
; fs.s: the file server
; =============================================================================
;
; A user-mode server (pid 3, created by the kernel at boot). It owns the block
; device: at start it asks dev for a window on the device's ports and an
; endpoint to the device's node, then reads the boot header and the
; directory (128 entries of {name[24], u32 first block, u32 size}; files are
; contiguous runs of blocks; new files go at the first free block, header
; offset 40).
;
; Disk I/O: the server writes a command into the device's submission port,
; lends the device its I/O buffer (c5) with `csend` through the device
; endpoint, and waits for the buffer to come back (svc WAIT_REPLY on its
; base): the device DMAs into or out of it meanwhile. Program images are read
; straight into the arena proc lends with LOADIMG.
;
;   3 OPEN    data = name, length = its length, mode 0 read / 1 write / 2 append -> id
;   1 READ    handle = id, length -> bytes (0 at the end of the file)
;   2 WRITE   handle = id, length, data -> bytes (files written are kept in
;             a 128 KiB region and saved when the last reference closes)
;   4 CLOSE   handle = id -> 0
;  10 DIR     -> files; data: 32-byte records {name[24], u64 size}
;  11 UNLINK  data = name -> 0 / -4
;  27 STAT    data = name -> size / -4
;  28 LOADIMG data = name, handle = most bytes, mode = arena offset; the arena
;             as attachment (c7) -> size / -4 / -1; the arena goes back
;  32 STATFS  -> 3; data: u64 total blocks, used blocks, files
;  33 READBLK handle = block -> 512; data: the block
;  34 READALL handle = id (read), mode = arena offset, length = most bytes; the
;             arena as attachment -> size (the whole file is copied in)
;  35 WRITEALL handle = id (write), mode = arena offset, length = bytes; the
;             arena as attachment -> bytes (appended to the file)
;  36 DUPS / 37 CLEANUP / 38 CANCEL from proc (see srv.s)
;
; Capability registers: c0 the rest of the arena, c1 the device window,
; c2 the device endpoint, c5 the I/O buffer (512 KiB), c6 the request, c7
; its attachment.

IOSZ    = 0x80000                       ; the I/O buffer: arena [0x40000, 0xC0000)
SCR     = 0                             ; I/O buffer: scratch for reads (64 KiB)
REG0    = 0x10000                       ; three 128 KiB regions for files being written
REGSZ   = 0x20000                       ; ...
NREG    = 3                             ; ...
META    = 0x70000                       ; directory + header staging for writes
NOPEN   = 16                            ; open files
O_USED  = 0                             ; open record (64 bytes): 0 free, 1 read, 2 write
O_SIZE  = 8                             ; size
O_POS   = 16                            ; read position
O_LBA   = 24                            ; first block (read)
O_REG   = 32                            ; region (write)
O_NLEN  = 40                            ; name length (write)
O_NAME  = 48                            ; its name (24 bytes)
O_SIZEOF = 80                           ; bytes per open record
DIRENTS = 128                           ; directory entries
BLK_SQ  = 0x100                         ; submission port
BLK_CQ  = 0x200                         ; completion port

        .data                           ; data Local Store
        .align 8                        ; ...
hdr:    .space 512                      ; the boot header
dir:    .space DIRENTS * 32             ; the directory
opens:  .space NOPEN * O_SIZEOF         ; open files
regused: .space NREG * 8                ; regions in use
cmd:    .space 32                       ; a block-device command
cqe:    .space 16                       ; its completion
ident:  .space 64                       ; the device's identify data
nm:     .space 32                       ; a name from a request
nmlen:  .dword 0                        ; its length
total:  .dword 0                        ; disk blocks
iobase: .dword 0                        ; base of the I/O buffer (what we wait for)
cid:    .dword 0                        ; command counter
bounce: .space 4640                     ; staging (a read spans up to 9 blocks)
bounce2: .space 4096                    ; request data
s_ndev: .ascii "dev"                    ; ...

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        li    sp, 65536                 ; stack at the top of the D-LS
        call  sys_init                  ; ...
        li    a0, 2                     ; dev (c2): the disk
        li    a1, 30                    ; GETDISK
        li    a2, 0                     ; ...
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        call  sys_msg                   ; c6 = window, c7 = endpoint
        cclear c1                       ; proc's endpoint is not needed
        cmov  c1, c6                    ; c1 = the device window
        cclear c2                       ; ...
        cmov  c2, c7                    ; c2 = the device endpoint
        cclear c5                       ; our message buffer is not needed any more
        li    t0, 0x40000               ; the I/O buffer: the top of our memory
        csplit c5, c0, t0               ; c0 = [0, 0x40000), c5 = [0x40000, 0xC0000)
        cbase t0, c5                    ; its base: the device gives it back by it
        la    t1, iobase                ; ...
        sd    t0, 0(t1)                 ; ...
        la    t0, ident                 ; capacity, from the identify data
        li    t1, 64                    ; ...
        tget  tg1, t0, c1, zero, t1     ; ...
        twait 1 << 1                    ; ...
        ld    t1, 8(t0)                 ; ...
        la    t2, total                 ; ...
        sd    t1, 0(t2)                 ; ...
        call  load_meta                 ; header and directory
        la    a0, loop                  ; a fault on a dead request returns to the loop
        call  srv_guard                 ; ...
loop:
        li    a0, 0                     ; no device tags
        li    a1, -1                    ; no timeout
        call  srv_recv                  ; ...
        bltz  a0, loop                  ; ...
        la    t0, srv_hdr               ; dispatch
        ld    t1, 0(t0)                 ; ...
        li    t2, 1                     ; READ
        beq   t1, t2, op_read           ; ...
        li    t2, 2                     ; WRITE
        beq   t1, t2, op_write          ; ...
        li    t2, 3                     ; OPEN
        beq   t1, t2, op_open           ; ...
        li    t2, 4                     ; CLOSE
        beq   t1, t2, op_close          ; ...
        li    t2, 10                    ; DIR
        beq   t1, t2, op_dir            ; ...
        li    t2, 11                    ; UNLINK
        beq   t1, t2, op_unlink         ; ...
        li    t2, 27                    ; STAT
        beq   t1, t2, op_stat           ; ...
        li    t2, 28                    ; LOADIMG
        beq   t1, t2, op_loadimg        ; ...
        li    t2, 32                    ; STATFS
        beq   t1, t2, op_statfs         ; ...
        li    t2, 33                    ; READBLK
        beq   t1, t2, op_readblk        ; ...
        li    t2, 34                    ; READALL
        beq   t1, t2, op_readall        ; ...
        li    t2, 35                    ; WRITEALL
        beq   t1, t2, op_writeall       ; ...
        li    t2, OP_DUPS               ; DUPS
        beq   t1, t2, op_dups           ; ...
        li    t2, OP_CLEANUP            ; CLEANUP
        beq   t1, t2, op_cleanup        ; ...
        li    t2, OP_CANCEL             ; CANCEL: nothing here ever waits
        beq   t1, t2, ok                ; ...
        li    a0, -1                    ; unknown
reply:
        li    a1, 0                     ; no attachment
        call  srv_reply                 ; ...
        j     loop                      ; ...
reply_att:
        li    a1, 1                     ; the attachment (c7) goes back first
        call  srv_reply                 ; ...
        j     loop                      ; ...
ok:
        li    a0, 0                     ; ...
        j     reply                     ; ...

; =============================================================================
; The block device
; =============================================================================

; blk(a0 = op 1 read / 2 write, a1 = first block, a2 = blocks (<= 256), a3 =
; byte offset in the buffer, a4 = 5: the I/O buffer (c5) / 7: the attachment)
; -> a0 = status (0 = ok)
blk:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a4, 8(sp)                 ; ...
        la    t0, cmd                   ; build the command
        sb    a0, 0(t0)                 ; op
        csrr  t1, coreid                ; the buffer comes back to this core
        sb    t1, 1(t0)                 ; ...
        la    t2, cid                   ; command id
        ld    t1, 0(t2)                 ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, 0(t2)                 ; ...
        sh    t1, 2(t0)                 ; ...
        sw    a2, 4(t0)                 ; blocks
        sd    a1, 8(t0)                 ; first block
        sd    a3, 16(t0)                ; offset in the buffer
        sd    zero, 24(t0)              ; ...
        li    t1, BLK_SQ                ; -> the submission port
        li    t2, 32                    ; ...
        tput  tg1, t0, c1, t1, t2       ; ...
        twait 1 << 1                    ; (the command first)
        li    t0, 7                     ; which buffer?
        beq   a4, t0, blk_att           ; ...
        cbase a3, c5                    ; the I/O buffer: lend it
        csend c5, c2                    ; ...
        j     blk_wait                  ; ...
blk_att:
        cbase a3, c7                    ; the attachment: lend it
        csend c7, c2                    ; ...
blk_wait:
        li    a0, SVC_WAIT              ; wait until the device gives it back
        li    a1, -1                    ; (no doorbell: the device is not a core)
        li    a2, -1                    ; no timeout
        ld    a4, 8(sp)                 ; back into the same register
        svc                             ; ...
        la    t0, cqe                   ; the completion
        li    t1, BLK_CQ                ; ...
        li    t2, 16                    ; ...
        tget  tg1, t0, c1, t1, t2       ; ...
        twait 1 << 1                    ; ...
        lhu   a0, 2(t0)                 ; status
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; blkn(a0 = op, a1 = first block, a2 = blocks (any), a3 = offset, a4 = buffer)
; -> a0 = status: several commands of at most 256 blocks
blkn:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        sd    a2, 24(sp)                ; ...
        sd    a3, 32(sp)                ; ...
        sd    a4, 40(sp)                ; ...
bn_l:
        ld    a2, 24(sp)                ; blocks left
        li    a0, 0                     ; (none: ok)
        beqz  a2, bn_ret                ; ...
        li    t0, 256                   ; at most 256
        bleu  a2, t0, bn_n              ; ...
        mv    a2, t0                    ; ...
bn_n:
        ld    t0, 24(sp)                ; ...
        sub   t0, t0, a2                ; ...
        sd    t0, 24(sp)                ; ...
        ld    a0, 8(sp)                 ; ...
        ld    a1, 16(sp)                ; ...
        add   t0, a1, a2                ; ...
        sd    t0, 16(sp)                ; ...
        ld    a3, 32(sp)                ; ...
        slli  t0, a2, 9                 ; ...
        add   t0, a3, t0                ; ...
        sd    t0, 32(sp)                ; ...
        ld    a4, 40(sp)                ; ...
        call  blk                       ; ...
        beqz  a0, bn_l                  ; ...
bn_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; ...

; load_meta(): the header (block 0) and the directory (8 blocks) -> D-LS
load_meta:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        li    a0, 1                     ; read block 0
        li    a1, 0                     ; ...
        li    a2, 1                     ; ...
        li    a3, SCR                   ; ...
        li    a4, 5                     ; ...
        call  blk                       ; ...
        la    t0, hdr                   ; -> D-LS
        li    t1, 512                   ; ...
        li    t2, SCR                   ; ...
        tget  tg1, t0, c5, t2, t1       ; ...
        twait 1 << 1                    ; ...
        li    a0, 1                     ; the directory
        lwu   a1, 36(t0)                ; ...
        li    a2, DIRENTS * 32 / 512    ; ...
        li    a3, SCR                   ; ...
        li    a4, 5                     ; ...
        call  blk                       ; ...
        la    t0, dir                   ; -> D-LS
        li    t1, DIRENTS * 32          ; ...
        li    t2, SCR                   ; ...
        tget  tg1, t0, c5, t2, t1       ; ...
        twait 1 << 1                    ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; save_meta(): the directory and the header back to the disk
save_meta:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        la    t0, dir                   ; -> the I/O buffer
        li    t1, DIRENTS * 32          ; ...
        li    t2, META                  ; ...
        tput  tg1, t0, c5, t2, t1       ; ...
        la    t0, hdr                   ; ...
        li    t1, 512                   ; ...
        li    t2, META + DIRENTS * 32   ; ...
        tput  tg1, t0, c5, t2, t1       ; ...
        twait 1 << 1                    ; ...
        li    a0, 2                     ; write the directory
        la    t0, hdr                   ; ...
        lwu   a1, 36(t0)                ; ...
        li    a2, DIRENTS * 32 / 512    ; ...
        li    a3, META                  ; ...
        li    a4, 5                     ; ...
        call  blk                       ; ...
        li    a0, 2                     ; and the header
        li    a1, 0                     ; ...
        li    a2, 1                     ; ...
        li    a3, META + DIRENTS * 32   ; ...
        li    a4, 5                     ; ...
        call  blk                       ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; =============================================================================
; Names and the directory
; =============================================================================

; get_name(): the request's data (length = header word 16) -> nm, nmlen; a0 = 0 or -1
get_name:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        la    t0, srv_hdr               ; ...
        ld    t1, 16(t0)                ; length
        beqz  t1, gn_bad                ; 1..24
        li    t2, 24                    ; ...
        bgtu  t1, t2, gn_bad            ; ...
        la    t2, nmlen                 ; ...
        sd    t1, 0(t2)                 ; ...
        la    a0, nm                    ; ...
        li    a1, 24                    ; ...
        call  srv_get                   ; ...
        li    a0, 0                     ; ...
        j     gn_ret                    ; ...
gn_bad:
        li    a0, -1                    ; ...
gn_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; find() -> a0 = the directory entry named nm, or 0
find:
        la    t0, dir                   ; ...
        li    t1, DIRENTS               ; ...
        la    t3, nmlen           ; (its address)
        ld    t3, 0(t3)              ; ...
fi_e:
        beqz  t1, fi_no                 ; ...
        lbu   t2, 0(t0)                 ; used?
        beqz  t2, fi_n                  ; ...
        li    t2, 0                     ; compare
fi_c:
        beq   t2, t3, fi_end            ; ...
        add   t4, t0, t2                ; ...
        lbu   t4, 0(t4)                 ; ...
        la    t5, nm                    ; ...
        add   t5, t5, t2                ; ...
        lbu   t5, 0(t5)                 ; ...
        bne   t4, t5, fi_n              ; ...
        addi  t2, t2, 1                 ; ...
        j     fi_c                      ; ...
fi_end:
        li    t4, 24                    ; the entry's name ends here too?
        beq   t2, t4, fi_yes            ; ...
        add   t4, t0, t2                ; ...
        lbu   t4, 0(t4)                 ; ...
        beqz  t4, fi_yes                ; ...
fi_n:
        addi  t0, t0, 32                ; ...
        addi  t1, t1, -1                ; ...
        j     fi_e                      ; ...
fi_yes:
        mv    a0, t0                    ; ...
        ret                             ; ...
fi_no:
        li    a0, 0                     ; ...
        ret                             ; ...

; remove(a0 = entry): delete it; if its blocks end at the first free block,
; give them back (the only reuse this simple file system does)
remove:
        lwu   t0, 24(a0)                ; first block
        lwu   t1, 28(a0)                ; size -> blocks
        addi  t1, t1, 511               ; ...
        srli  t1, t1, 9                 ; ...
        add   t2, t0, t1                ; its end
        la    t3, hdr                   ; the first free block
        lwu   t4, 40(t3)                ; ...
        bne   t2, t4, rm_clr            ; not the last file
        sw    t0, 40(t3)                ; it is: the space is free again
rm_clr:
        li    t1, 32                    ; clear the entry
rm_z:
        sb    zero, 0(a0)               ; ...
        addi  a0, a0, 1                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, rm_z                  ; ...
        ret                             ; ...

; save_file(a0 = open record): write its region as a file named in it -> a0 = 0 / -1
save_file:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        mv    s1, a0                    ; s1 = the record
        ld    t0, O_NLEN(s1)            ; its name -> nm
        la    t1, nmlen                 ; ...
        sd    t0, 0(t1)                 ; ...
        la    a0, nm                    ; ...
        addi  a1, s1, O_NAME            ; ...
        li    a2, 24                    ; ...
        call  srv_bcopy                 ; ...
        call  find                      ; an old file of that name goes
        beqz  a0, sf_new                ; ...
        call  remove                    ; ...
sf_new:
        la    s2, dir                   ; a free entry
        li    t1, DIRENTS               ; ...
sf_f:
        beqz  t1, sf_fail               ; none
        lbu   t2, 0(s2)                 ; ...
        beqz  t2, sf_have               ; ...
        addi  s2, s2, 32                ; ...
        addi  t1, t1, -1                ; ...
        j     sf_f                      ; ...
sf_have:
        la    t0, hdr                   ; it goes at the first free block
        lwu   s3, 40(t0)                ; ...
        ld    t1, O_SIZE(s1)            ; its blocks
        addi  t1, t1, 511               ; ...
        srli  t1, t1, 9                 ; ...
        add   t2, s3, t1                ; does it fit?
        la    t3, total           ; (its address)
        ld    t3, 0(t3)              ; ...
        bgtu  t2, t3, sf_fail           ; ...
        sw    t2, 40(t0)                ; the new first free block
        li    a0, 2                     ; write the region
        mv    a1, s3                    ; ...
        mv    a2, t1                    ; ...
        ld    t4, O_REG(s1)             ; ...
        li    t5, REGSZ                 ; ...
        mul   a3, t4, t5                ; ...
        li    t5, REG0                  ; ...
        add   a3, a3, t5                ; ...
        li    a4, 5                     ; ...
        call  blkn                      ; ...
        mv    a0, s2                    ; the directory entry
        la    a1, nm                    ; name
        la    a2, nmlen           ; (its address)
        ld    a2, 0(a2)              ; ...
        call  srv_bcopy                 ; ...
        sw    s3, 24(s2)                ; first block
        ld    t0, O_SIZE(s1)            ; size
        sw    t0, 28(s2)                ; ...
        call  save_meta                 ; ...
        li    a0, 0                     ; ...
        j     sf_ret                    ; ...
sf_fail:
        li    a0, -1                    ; disk or directory full
sf_ret:
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 40                ; ...
        ret                             ; ...

; =============================================================================
; Open files
; =============================================================================

; orec(a0 = id) -> a0 = its open record, or 0 if not open
orec:
        addi  a0, a0, -1                ; ids are 1..NOPEN
        li    t0, NOPEN                 ; ...
        bgeu  a0, t0, or_no             ; ...
        li    t0, O_SIZEOF              ; ...
        mul   a0, a0, t0                ; ...
        la    t0, opens                 ; ...
        add   a0, a0, t0                ; ...
        ld    t0, O_USED(a0)            ; ...
        beqz  t0, or_no                 ; ...
        ret                             ; ...
or_no:
        li    a0, 0                     ; ...
        ret                             ; ...

; region_off(a0 = open record) -> a0 = I/O-buffer offset of its region
region_off:
        ld    t0, O_REG(a0)             ; ...
        li    t1, REGSZ                 ; ...
        mul   a0, t0, t1                ; ...
        li    t1, REG0                  ; ...
        add   a0, a0, t1                ; ...
        ret                             ; ...

; append(a0 = open record, a1 = D-LS bytes, a2 = count): add to its region
; (the region's end need not be word-aligned: its last word is merged)
append:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        mv    s1, a0                    ; s1 = record
        mv    s2, a1                    ; s2 = bytes
        mv    s3, a2                    ; s3 = count
        call  region_off                ; s4 = offset of the end, word-aligned
        ld    t0, O_SIZE(s1)            ; ...
        add   s4, a0, t0                ; ...
        andi  t5, s4, 7                 ; t5 = bytes of the last partial word
        sub   s4, s4, t5                ; ...
        sd    t5, 40(sp)                ; ...
        beqz  t5, ap_cp                 ; none
        la    t0, bounce                ; fetch that word
        li    t1, 8                     ; ...
        tget  tg1, t0, c5, s4, t1       ; ...
        twait 1 << 1                    ; ...
ap_cp:
        la    a0, bounce                ; the new bytes after it
        ld    t5, 40(sp)                ; ...
        add   a0, a0, t5                ; ...
        mv    a1, s2                    ; ...
        mv    a2, s3                    ; ...
        call  srv_bcopy                 ; ...
        ld    t5, 40(sp)                ; write back, whole words
        add   t1, t5, s3                ; ...
        addi  t1, t1, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        la    t0, bounce                ; ...
        tput  tg1, t0, c5, s4, t1       ; ...
        twait 1 << 1                    ; ...
        ld    t0, O_SIZE(s1)            ; the file grew
        add   t0, t0, s3                ; ...
        sd    t0, O_SIZE(s1)            ; ...
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; ...

; finish(a0 = id): its last reference closed: save a file being written, free it
finish:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        call  orec                      ; ...
        beqz  a0, fn_ret                ; ...
        sd    a0, 8(sp)                 ; ...
        ld    t0, O_USED(a0)            ; a file being written?
        li    t1, 2                     ; ...
        bne   t0, t1, fn_free           ; ...
        call  save_file                 ; save it
        ld    a0, 8(sp)                 ; its region is free
        ld    t0, O_REG(a0)             ; ...
        slli  t0, t0, 3                 ; ...
        la    t1, regused               ; ...
        add   t1, t1, t0                ; ...
        sd    zero, 0(t1)               ; ...
fn_free:
        ld    a0, 8(sp)                 ; the record is free
        sd    zero, O_USED(a0)          ; ...
fn_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; dropref(a0 = pid, a1 = id): one reference less; the last one finishes the file
dropref:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a1, 8(sp)                 ; ...
        call  ref_del                   ; ...
        beqz  a0, dr_ret                ; it held none
        ld    a0, 8(sp)                 ; any left?
        call  ref_count                 ; ...
        bnez  a0, dr_ret                ; ...
        ld    a0, 8(sp)                 ; no: finish it
        call  finish                    ; ...
dr_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

