op_open:
        call  get_name                  ; ...
        bltz  a0, reply                 ; bad name
        li    s1, 0                     ; a free open record
oo_f:
        li    t0, NOPEN                 ; ...
        bge   s1, t0, oo_full           ; ...
        li    t0, O_SIZEOF              ; ...
        mul   s2, s1, t0                ; ...
        la    t0, opens                 ; ...
        add   s2, s2, t0                ; ...
        ld    t0, O_USED(s2)            ; ...
        beqz  t0, oo_have               ; ...
        addi  s1, s1, 1                 ; ...
        j     oo_f                      ; ...
oo_have:
        sd    zero, O_POS(s2)           ; ...
        sd    zero, O_SIZE(s2)          ; ...
        call  find                      ; s3 = its directory entry, or 0
        mv    s3, a0                    ; ...
        la    t0, srv_hdr               ; mode
        ld    t1, 24(t0)                ; ...
        bnez  t1, oo_write              ; 1 write, 2 append
        beqz  s3, oo_nofile             ; read: it must exist
        lwu   t0, 24(s3)                ; ...
        sd    t0, O_LBA(s2)             ; ...
        lwu   t0, 28(s3)                ; ...
        sd    t0, O_SIZE(s2)            ; ...
        li    t0, 1                     ; open for reading
        sd    t0, O_USED(s2)            ; ...
        j     oo_ref                    ; ...
oo_write:
        li    t2, 0                     ; a free region
oo_rf:
        li    t3, NREG                  ; ...
        bge   t2, t3, oo_full           ; ...
        la    t4, regused               ; ...
        slli  t5, t2, 3                 ; ...
        add   t4, t4, t5                ; ...
        ld    t5, 0(t4)                 ; ...
        beqz  t5, oo_rh                 ; ...
        addi  t2, t2, 1                 ; ...
        j     oo_rf                     ; ...
oo_rh:
        li    t5, 1                     ; taken
        sd    t5, 0(t4)                 ; ...
        sd    t2, O_REG(s2)             ; ...
        la    t0, nmlen           ; (its address)
        ld    t0, 0(t0)              ; its name
        sd    t0, O_NLEN(s2)            ; ...
        addi  a0, s2, O_NAME            ; ...
        la    a1, nm                    ; ...
        li    a2, 24                    ; ...
        call  srv_bcopy                 ; ...
        li    t0, 2                     ; open for writing
        sd    t0, O_USED(s2)            ; ...
        la    t0, srv_hdr               ; append to an existing file?
        ld    t1, 24(t0)                ; ...
        li    t2, 2                     ; ...
        bne   t1, t2, oo_ref            ; no
        beqz  s3, oo_ref                ; nothing to append to
        lwu   t0, 28(s3)                ; its size
        li    t1, REGSZ                 ; must fit the region
        bgtu  t0, t1, oo_big            ; ...
        sd    t0, O_SIZE(s2)            ; ...
        li    a0, 1                     ; read it into the region
        lwu   a1, 24(s3)                ; ...
        addi  a2, t0, 511               ; ...
        srli  a2, a2, 9                 ; ...
        mv    a0, s2                    ; (region offset)
        call  region_off                ; ...
        mv    a3, a0                    ; ...
        li    a0, 1                     ; ...
        lwu   a1, 24(s3)                ; ...
        lwu   a2, 28(s3)                ; ...
        addi  a2, a2, 511               ; ...
        srli  a2, a2, 9                 ; ...
        li    a4, 5                     ; ...
        call  blkn                      ; ...
oo_ref:
        call  srv_pid                   ; the caller holds it
        addi  a1, s1, 1                 ; id
        call  ref_add                   ; ...
        addi  a0, s1, 1                 ; the id
        j     reply                     ; ...
oo_big:
        ld    t0, O_REG(s2)             ; give the region back
        slli  t0, t0, 3                 ; ...
        la    t1, regused               ; ...
        add   t1, t1, t0                ; ...
        sd    zero, 0(t1)               ; ...
        sd    zero, O_USED(s2)          ; ...
        li    a0, -1                    ; ...
        j     reply                     ; ...
oo_nofile:
        li    a0, -4                    ; no such file
        j     reply                     ; ...
oo_full:
        li    a0, -6                    ; no room
        j     reply                     ; ...

op_read:
        la    t0, srv_hdr               ; the file
        ld    a0, 8(t0)                 ; ...
        call  orec                      ; ...
        beqz  a0, bad                   ; ...
        mv    s1, a0                    ; ...
        ld    t0, O_USED(s1)            ; open for reading?
        li    t1, 1                     ; ...
        bne   t0, t1, bad               ; ...
        la    t0, srv_hdr               ; s2 = bytes: min(wanted, 4032, left)
        ld    s2, 16(t0)                ; ...
        li    t1, SYS_MAX               ; ...
        bleu  s2, t1, ord_1             ; ...
        mv    s2, t1                    ; ...
ord_1:
        ld    t0, O_SIZE(s1)            ; ...
        ld    t1, O_POS(s1)             ; ...
        sub   t0, t0, t1                ; ...
        bleu  s2, t0, ord_2             ; ...
        mv    s2, t0                    ; ...
ord_2:
        li    a0, 0                     ; nothing left: end of the file
        beqz  s2, reply                 ; ...
        ld    t1, O_POS(s1)             ; the blocks holding [pos, pos + n)
        srli  s3, t1, 9                 ; s3 = first
        add   t2, t1, s2                ; ...
        addi  t2, t2, -1                ; ...
        srli  t2, t2, 9                 ; last
        sub   a2, t2, s3                ; count
        addi  a2, a2, 1                 ; ...
        ld    a1, O_LBA(s1)             ; ...
        add   a1, a1, s3                ; ...
        li    a0, 1                     ; read them
        li    a3, SCR                   ; ...
        li    a4, 5                     ; ...
        call  blk                       ; ...
        ld    t1, O_POS(s1)             ; s4 = the position within the first block
        andi  s4, t1, 511               ; ...
        add   t1, s4, s2                ; -> D-LS, whole words
        addi  t1, t1, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        la    t0, bounce                ; ...
        li    t2, SCR                   ; ...
        tget  tg1, t0, c5, t2, t1       ; ...
        twait 1 << 1                    ; ...
        la    a0, bounce                ; shift the bytes to the start
        la    a1, bounce                ; ...
        add   a1, a1, s4                ; ...
        mv    a2, s2                    ; ...
        call  srv_bcopy                 ; ...
        la    a0, bounce                ; -> the request
        mv    a1, s2                    ; ...
        call  srv_put                   ; ...
        ld    t0, O_POS(s1)             ; advance
        add   t0, t0, s2                ; ...
        sd    t0, O_POS(s1)             ; ...
        mv    a0, s2                    ; ...
        j     reply                     ; ...
bad:
        li    a0, -1                    ; ...
        j     reply                     ; ...

op_write:
        la    t0, srv_hdr               ; the file
        ld    a0, 8(t0)                 ; ...
        call  orec                      ; ...
        beqz  a0, bad                   ; ...
        mv    s1, a0                    ; ...
        ld    t0, O_USED(s1)            ; open for writing?
        li    t1, 2                     ; ...
        bne   t0, t1, bad               ; ...
        la    t0, srv_hdr               ; s2 = bytes, clipped to the region
        ld    s2, 16(t0)                ; ...
        li    t1, SYS_MAX               ; ...
        bleu  s2, t1, owr_1             ; ...
        mv    s2, t1                    ; ...
owr_1:
        ld    t0, O_SIZE(s1)            ; ...
        li    t1, REGSZ                 ; ...
        sub   t1, t1, t0                ; room left
        bleu  s2, t1, owr_2             ; ...
        mv    s2, t1                    ; ...
owr_2:
        li    a0, -1                    ; full
        beqz  s2, reply                 ; ...
        la    a0, bounce2               ; the data -> D-LS
        mv    a1, s2                    ; ...
        call  srv_get                   ; ...
        mv    a0, s1                    ; -> the region
        la    a1, bounce2               ; ...
        mv    a2, s2                    ; ...
        call  append                    ; ...
        mv    a0, s2                    ; ...
        j     reply                     ; ...

op_close:
        call  srv_pid                   ; ...
        la    t0, srv_hdr               ; ...
        ld    a1, 8(t0)                 ; ...
        call  dropref                   ; ...
        j     ok                        ; ...

op_dups:
        call  ref_dups                  ; ...
        j     reply                     ; ...

op_cleanup:
        la    t0, srv_hdr               ; the dead process
        ld    s1, 8(t0)                 ; ...
ocl_l:
        mv    a0, s1                    ; its references, one by one
        call  ref_first                 ; ...
        bltz  a0, ok                    ; none left
        mv    a1, a0                    ; ...
        mv    a0, s1                    ; ...
        call  dropref                   ; ...
        j     ocl_l                     ; ...

op_dir:
        la    s1, dir                   ; s1 = entry
        li    s2, DIRENTS               ; s2 = left
        li    s3, 0                     ; s3 = files
        la    s4, bounce                ; s4 = output
od_l:
        beqz  s2, od_done               ; ...
        lbu   t0, 0(s1)                 ; used?
        beqz  t0, od_n                  ; ...
        li    t0, 126                   ; at most one message of records
        bge   s3, t0, od_done           ; ...
        mv    a0, s4                    ; name (24 bytes)
        mv    a1, s1                    ; ...
        li    a2, 24                    ; ...
        call  srv_bcopy                 ; ...
        lwu   t0, 28(s1)                ; size
        sd    t0, 24(s4)                ; ...
        addi  s4, s4, 32                ; ...
        addi  s3, s3, 1                 ; ...
od_n:
        addi  s1, s1, 32                ; ...
        addi  s2, s2, -1                ; ...
        j     od_l                      ; ...
od_done:
        la    a0, bounce                ; -> the request
        slli  a1, s3, 5                 ; ...
        call  srv_put                   ; ...
        mv    a0, s3                    ; ...
        j     reply                     ; ...

op_unlink:
        call  get_name                  ; ...
        bltz  a0, reply                 ; ...
        call  find                      ; ...
        beqz  a0, oo_nofile             ; ...
        call  remove                    ; ...
        call  save_meta                 ; ...
        j     ok                        ; ...

op_stat:
        call  get_name                  ; ...
        bltz  a0, reply                 ; ...
        call  find                      ; ...
        beqz  a0, oo_nofile             ; ...
        lwu   a0, 28(a0)                ; its size
        j     reply                     ; ...

op_statfs:
        la    t0, bounce                ; total, used, files
        la    t1, total           ; (its address)
        ld    t1, 0(t1)              ; ...
        sd    t1, 0(t0)                 ; ...
        la    t2, hdr                   ; ...
        lwu   t1, 40(t2)                ; ...
        sd    t1, 8(t0)                 ; ...
        la    t2, dir                   ; count the files
        li    t3, DIRENTS               ; ...
        li    t4, 0                     ; ...
osf_l:
        beqz  t3, osf_d                 ; ...
        lbu   t5, 0(t2)                 ; ...
        snez  t5, t5                    ; ...
        add   t4, t4, t5                ; ...
        addi  t2, t2, 32                ; ...
        addi  t3, t3, -1                ; ...
        j     osf_l                     ; ...
osf_d:
        sd    t4, 16(t0)                ; ...
        mv    a0, t0                    ; -> the request
        li    a1, 24                    ; ...
        call  srv_put                   ; ...
        li    a0, 3                     ; ...
        j     reply                     ; ...

op_readblk:
        la    t0, srv_hdr               ; the block
        ld    s1, 8(t0)                 ; ...
        la    t1, total           ; (its address)
        ld    t1, 0(t1)              ; on the disk?
        bgeu  s1, t1, bad               ; ...
        li    a0, 1                     ; read it
        mv    a1, s1                    ; ...
        li    a2, 1                     ; ...
        li    a3, SCR                   ; ...
        li    a4, 5                     ; ...
        call  blk                       ; ...
        la    t0, bounce                ; -> D-LS
        li    t1, 512                   ; ...
        li    t2, SCR                   ; ...
        tget  tg1, t0, c5, t2, t1       ; ...
        twait 1 << 1                    ; ...
        la    a0, bounce                ; -> the request
        li    a1, 512                   ; ...
        call  srv_put                   ; ...
        li    a0, 512                   ; ...
        j     reply                     ; ...

; LOADIMG: the named file's blocks straight into the attached arena
op_loadimg:
        cvalid t0, c7                   ; an arena must come with it
        beqz  t0, bad                   ; ...
        call  get_name                  ; ...
        bltz  a0, reply_att             ; ...
        call  find                      ; ...
        li    t1, -4                    ; no such program
        beqz  a0, oli_err               ; ...
        mv    s1, a0                    ; ...
        lwu   s2, 28(s1)                ; size
        addi  t0, s2, 511               ; whole blocks must fit
        srli  t0, t0, 9                 ; ...
        slli  t1, t0, 9                 ; ...
        la    t2, srv_hdr               ; (handle = the most bytes)
        ld    t3, 8(t2)                 ; ...
        li    t1, -1                    ; too big
        slli  t4, t0, 9                 ; ...
        bgtu  t4, t3, oli_err           ; ...
        li    a0, 1                     ; read
        lwu   a1, 24(s1)                ; ...
        mv    a2, t0                    ; ...
        ld    a3, 24(t2)                ; at the arena offset (mode)
        li    a4, 7                     ; into the attachment
        call  blkn                      ; ...
        mv    a0, s2                    ; the size
        j     reply_att                 ; the arena goes back with the reply
oli_err:
        mv    a0, t1                    ; ...
        j     reply_att                 ; ...

; READALL: an open file, whole, into the attached arena
op_readall:
        cvalid t0, c7                   ; ...
        beqz  t0, bad                   ; ...
        la    t0, srv_hdr               ; ...
        ld    a0, 8(t0)                 ; ...
        call  orec                      ; ...
        li    t1, -1                    ; ...
        beqz  a0, oli_err               ; ...
        mv    s1, a0                    ; ...
        ld    t0, O_USED(s1)            ; ...
        li    t2, 1                     ; ...
        bne   t0, t2, oli_err           ; ...
        ld    s2, O_SIZE(s1)            ; ...
        addi  t0, s2, 511               ; ...
        srli  t0, t0, 9                 ; ...
        slli  t4, t0, 9                 ; ...
        la    t2, srv_hdr               ; (length = the most bytes)
        ld    t3, 16(t2)                ; ...
        bgtu  t4, t3, oli_err           ; ...
        li    a0, 1                     ; ...
        ld    a1, O_LBA(s1)             ; ...
        mv    a2, t0                    ; ...
        ld    a3, 24(t2)                ; arena offset
        li    a4, 7                     ; ...
        call  blkn                      ; ...
        mv    a0, s2                    ; ...
        j     reply_att                 ; ...

; WRITEALL: bytes of the attached arena appended to a file being written
op_writeall:
        cvalid t0, c7                   ; ...
        beqz  t0, bad                   ; ...
        la    t0, srv_hdr               ; ...
        ld    a0, 8(t0)                 ; ...
        call  orec                      ; ...
        li    t1, -1                    ; ...
        beqz  a0, oli_err               ; ...
        mv    s1, a0                    ; ...
        ld    t0, O_USED(s1)            ; ...
        li    t2, 2                     ; ...
        bne   t0, t2, oli_err           ; ...
        la    t0, srv_hdr               ; s2 = offset, s3 = bytes left
        ld    s2, 24(t0)                ; ...
        ld    s3, 16(t0)                ; ...
        ld    t1, O_SIZE(s1)            ; at most what the region holds
        li    t2, REGSZ                 ; ...
        sub   t2, t2, t1                ; ...
        bleu  s3, t2, owa_l             ; ...
        mv    s3, t2                    ; ...
owa_l:
        beqz  s3, owa_done              ; ...
        li    s4, 4096                  ; a chunk
        bleu  s4, s3, owa_n             ; ...
        mv    s4, s3                    ; ...
owa_n:
        addi  t1, s4, 7                 ; arena -> D-LS (whole words)
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        la    t0, bounce2               ; ...
        tget  tg1, t0, c7, s2, t1       ; ...
        twait 1 << 1                    ; ...
        mv    a0, s1                    ; -> the region
        la    a1, bounce2               ; ...
        mv    a2, s4                    ; ...
        call  append                    ; ...
        add   s2, s2, s4                ; ...
        sub   s3, s3, s4                ; ...
        j     owa_l                     ; ...
owa_done:
        la    t0, srv_hdr               ; the bytes taken
        ld    a0, 16(t0)                ; ...
        j     reply_att                 ; ...

