op_open:
        la    t0, srv_hdr               ; writing creates the path's tags
        ld    a0, 24(t0)                ; ...
        snez  a0, a0                    ; ...
        call  get_named                 ; nm, nmlen, pmask
        bltz  a0, reply                 ; bad name, no such tag, no room
        li    s1, 0                     ; a free open record
oo_f:
        li    t0, NOPEN                 ; ...
        bge   s1, t0, oo_full           ; ...
        li    t0, O_SIZEOF              ; ...
        mul   s2, s1, t0                ; ...
        la    t0, opens                 ; ...
        add   s2, s2, t0                ; ...
        ld    t0, O_USED(s2)            ; ...
        beqz  t0, oo_have               ; ...
        addi  s1, s1, 1                 ; ...
        j     oo_f                      ; ...
oo_have:
        sd    zero, O_POS(s2)           ; ...
        sd    zero, O_SIZE(s2)          ; ...
        la    t0, srv_hdr               ; mode
        ld    t1, 24(t0)                ; ...
        bnez  t1, oo_wfind              ; 1 write, 2 append
        call  lookup                    ; s3 = its directory entry, or 0
        mv    s3, a0                    ; ...
        beqz  s3, oo_nofile             ; read: it must exist, with the path's tags
        lwu   t0, 24(s3)                ; ...
        sd    t0, O_LBA(s2)             ; ...
        lwu   t0, 28(s3)                ; ...
        sd    t0, O_SIZE(s2)            ; ...
        li    t0, 1                     ; open for reading
        sd    t0, O_USED(s2)            ; ...
        j     oo_ref                    ; ...
oo_wfind:
        call  find                      ; s3 = its directory entry, or 0
        mv    s3, a0                    ; ...
oo_write:
        li    t2, 0                     ; a free region
oo_rf:
        li    t3, NREG                  ; ...
        bge   t2, t3, oo_full           ; ...
        la    t4, regused               ; ...
        slli  t5, t2, 3                 ; ...
        add   t4, t4, t5                ; ...
        ld    t5, 0(t4)                 ; ...
        beqz  t5, oo_rh                 ; ...
        addi  t2, t2, 1                 ; ...
        j     oo_rf                     ; ...
oo_rh:
        li    t5, 1                     ; taken
        sd    t5, 0(t4)                 ; ...
        sd    t2, O_REG(s2)             ; ...
        la    t0, nmlen           ; (its address)
        ld    t0, 0(t0)              ; its name
        sd    t0, O_NLEN(s2)            ; ...
        addi  a0, s2, O_NAME            ; ...
        la    a1, nm                    ; ...
        li    a2, 24                    ; ...
        call  srv_bcopy                 ; ...
        la    t0, pmask                 ; the path's tags, for when it is saved
        ld    t0, 0(t0)                 ; ...
        sd    t0, O_TAGS(s2)            ; ...
        li    t0, 2                     ; open for writing
        sd    t0, O_USED(s2)            ; ...
        la    t0, srv_hdr               ; append to an existing file?
        ld    t1, 24(t0)                ; ...
        li    t2, 2                     ; ...
        bne   t1, t2, oo_ref            ; no
        beqz  s3, oo_ref                ; nothing to append to
        lwu   t0, 28(s3)                ; its size
        li    t1, REGSZ                 ; must fit the region
        bgtu  t0, t1, oo_big            ; ...
        sd    t0, O_SIZE(s2)            ; ...
        li    a0, 1                     ; read it into the region
        lwu   a1, 24(s3)                ; ...
        addi  a2, t0, 511               ; ...
        srli  a2, a2, 9                 ; ...
        mv    a0, s2                    ; (region offset)
        call  region_off                ; ...
        mv    a3, a0                    ; ...
        li    a0, 1                     ; ...
        lwu   a1, 24(s3)                ; ...
        lwu   a2, 28(s3)                ; ...
        addi  a2, a2, 511               ; ...
        srli  a2, a2, 9                 ; ...
        li    a4, 5                     ; ...
        call  blkn                      ; ...
oo_ref:
        call  srv_pid                   ; the caller holds it
        addi  a1, s1, 1                 ; id
        call  ref_add                   ; ...
        addi  a0, s1, 1                 ; the id
        j     reply                     ; ...
oo_big:
        ld    t0, O_REG(s2)             ; give the region back
        slli  t0, t0, 3                 ; ...
        la    t1, regused               ; ...
        add   t1, t1, t0                ; ...
        sd    zero, 0(t1)               ; ...
        sd    zero, O_USED(s2)          ; ...
        li    a0, -1                    ; ...
        j     reply                     ; ...
oo_nofile:
        li    a0, -4                    ; no such file
        j     reply                     ; ...
oo_full:
        li    a0, -6                    ; no room
        j     reply                     ; ...

op_read:
        la    t0, srv_hdr               ; the file
        ld    a0, 8(t0)                 ; ...
        call  orec                      ; ...
        beqz  a0, bad                   ; ...
        mv    s1, a0                    ; ...
        ld    t0, O_USED(s1)            ; open for reading?
        li    t1, 1                     ; ...
        bne   t0, t1, bad               ; ...
        la    t0, srv_hdr               ; s2 = bytes: min(wanted, 4032, left)
        ld    s2, 16(t0)                ; ...
        li    t1, SYS_MAX               ; ...
        bleu  s2, t1, ord_1             ; ...
        mv    s2, t1                    ; ...
ord_1:
        ld    t0, O_SIZE(s1)            ; ...
        ld    t1, O_POS(s1)             ; ...
        sub   t0, t0, t1                ; ...
        bleu  s2, t0, ord_2             ; ...
        mv    s2, t0                    ; ...
ord_2:
        li    a0, 0                     ; nothing left: end of the file
        beqz  s2, reply                 ; ...
        ld    t1, O_POS(s1)             ; the blocks holding [pos, pos + n)
        srli  s3, t1, 9                 ; s3 = first
        add   t2, t1, s2                ; ...
        addi  t2, t2, -1                ; ...
        srli  t2, t2, 9                 ; last
        sub   a2, t2, s3                ; count
        addi  a2, a2, 1                 ; ...
        ld    a1, O_LBA(s1)             ; ...
        add   a1, a1, s3                ; ...
        li    a0, 1                     ; read them
        li    a3, SCR                   ; ...
        li    a4, 5                     ; ...
        call  blk                       ; ...
        ld    t1, O_POS(s1)             ; s4 = the position within the first block
        andi  s4, t1, 511               ; ...
        add   t1, s4, s2                ; -> D-LS, whole words
        addi  t1, t1, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        la    t0, bounce                ; ...
        li    t2, SCR                   ; ...
        tget  tg1, t0, c5, t2, t1       ; ...
        twait 1 << 1                    ; ...
        la    a0, bounce                ; shift the bytes to the start
        la    a1, bounce                ; ...
        add   a1, a1, s4                ; ...
        mv    a2, s2                    ; ...
        call  srv_bcopy                 ; ...
        la    a0, bounce                ; -> the request
        mv    a1, s2                    ; ...
        call  srv_put                   ; ...
        ld    t0, O_POS(s1)             ; advance
        add   t0, t0, s2                ; ...
        sd    t0, O_POS(s1)             ; ...
        mv    a0, s2                    ; ...
        j     reply                     ; ...
bad:
        li    a0, -1                    ; ...
        j     reply                     ; ...

op_write:
        la    t0, srv_hdr               ; the file
        ld    a0, 8(t0)                 ; ...
        call  orec                      ; ...
        beqz  a0, bad                   ; ...
        mv    s1, a0                    ; ...
        ld    t0, O_USED(s1)            ; open for writing?
        li    t1, 2                     ; ...
        bne   t0, t1, bad               ; ...
        la    t0, srv_hdr               ; s2 = bytes, clipped to the region
        ld    s2, 16(t0)                ; ...
        li    t1, SYS_MAX               ; ...
        bleu  s2, t1, owr_1             ; ...
        mv    s2, t1                    ; ...
owr_1:
        ld    t0, O_SIZE(s1)            ; ...
        li    t1, REGSZ                 ; ...
        sub   t1, t1, t0                ; room left
        bleu  s2, t1, owr_2             ; ...
        mv    s2, t1                    ; ...
owr_2:
        li    a0, -1                    ; full
        beqz  s2, reply                 ; ...
        la    a0, bounce2               ; the data -> D-LS
        mv    a1, s2                    ; ...
        call  srv_get                   ; ...
        mv    a0, s1                    ; -> the region
        la    a1, bounce2               ; ...
        mv    a2, s2                    ; ...
        call  append                    ; ...
        mv    a0, s2                    ; ...
        j     reply                     ; ...

op_close:
        call  srv_pid                   ; ...
        la    t0, srv_hdr               ; ...
        ld    a1, 8(t0)                 ; ...
        call  dropref                   ; ...
        j     ok                        ; ...

op_dups:
        call  ref_dups                  ; ...
        j     reply                     ; ...

op_cleanup:
        la    t0, srv_hdr               ; the dead process
        ld    s1, 8(t0)                 ; ...
        mv    a0, s1                    ; its current tag path is forgotten
        call  cwd_drop                  ; ...
ocl_l:
        mv    a0, s1                    ; its references, one by one
        call  ref_first                 ; ...
        bltz  a0, ok                    ; none left
        mv    a1, a0                    ; ...
        mv    a0, s1                    ; ...
        call  dropref                   ; ...
        j     ocl_l                     ; ...

op_dir:
        li    a0, 0                     ; the path: tags (and maybe a file)
        call  get_file                  ; ...
        bltz  a0, reply                 ; ...
        la    t0, pmask                 ; s4 = the tags a file must carry
        ld    s4, 0(t0)                 ; ...
        la    t0, nmask                 ; s6 = the tags it must not carry
        ld    s6, 0(t0)                 ; ...
        li    s7, 0                     ; s7 = the facets (none yet)
        la    t0, nmlen                 ; a last component?
        ld    a1, 0(t0)                 ; ...
        beqz  a1, od_all                ; no
        la    a0, nm                    ; "-tag": an exclusion
        lbu   t0, 0(a0)                 ; ...
        li    t1, '-'                   ; ...
        beq   t0, t1, od_excl           ; ...
        call  tag_find                  ; a tag?
        bltz  a0, od_one                ; no: a file
        li    t0, 1                     ; ...
        sll   t0, t0, a0                ; ...
        or    s4, s4, t0                ; ...
        j     od_all                    ; ...
od_excl:
        addi  a0, a0, 1                 ; the tag after the "-"
        addi  a1, a1, -1                ; ...
        call  tag_find                  ; ...
        bltz  a0, od_all                ; none: it excludes nothing
        li    t0, 1                     ; ...
        sll   t0, t0, a0                ; ...
        or    s6, s6, t0                ; ...
od_all:
        li    s3, 0                     ; s3 = files
        la    s5, bounce                ; s5 = output
        la    t0, srv_hdr               ; s9 = matching files to skip (handle)
        ld    s9, 8(t0)                 ; ...
        li    s8, 0                     ; s8 = window
od_w:
        mv    a0, s8                    ; ...
        call  win                       ; ...
        la    s1, dir                   ; s1 = entry
        la    s2, ftags                 ; s2 = its tag set
od_l:
        la    t0, tagtab                ; the window's end?
        bgeu  s1, t0, od_wn             ; (the tag names follow it)
        lbu   t0, 0(s1)                 ; used?
        beqz  t0, od_n                  ; ...
        ld    t0, 0(s2)                 ; does it carry the tags?
        and   t1, t0, s4                ; ...
        bne   t1, s4, od_n              ; ...
        and   t1, t0, s6                ; and none of the excluded ones?
        bnez  t1, od_n                  ; ...
        or    s7, s7, t0                ; its tags are facets
        beqz  s9, od_tk                 ; one the requester has already
        addi  s9, s9, -1                ; ...
        j     od_n                      ; ...
od_tk:
        li    t0, 126                   ; at most one message of records
        bge   s3, t0, od_n              ; (the facets still count every file)
        mv    a0, s5                    ; the record
        mv    a1, s1                    ; ...
        call  od_rec                    ; ...
        addi  s5, s5, 32                ; ...
        addi  s3, s3, 1                 ; ...
od_n:
        addi  s1, s1, 32                ; ...
        addi  s2, s2, 8                 ; ...
        j     od_l                      ; ...
od_wn:
        addi  s8, s8, 1                 ; the next window
        la    t0, nwin                  ; ...
        ld    t0, 0(t0)                 ; ...
        blt   s8, t0, od_w              ; ...
        j     od_done                   ; ...
od_one:
        call  lookup                    ; the file, with the tags before it
        beqz  a0, oo_nofile             ; ...
        mv    a1, a0                    ; one record
        la    a0, bounce                ; ...
        call  od_rec                    ; ...
        li    s3, 1                     ; ...
        li    s7, 0                     ; (one file: no facets)
od_done:
        li    t0, -1                    ; facets: not the path's own tags
        xor   t0, s4, t0                ; ...
        and   s7, s7, t0                ; ...
        la    t0, srv_hdr               ; -> the reply's mode word
        sd    s7, 24(t0)                ; ...
        la    a0, bounce                ; -> the request
        slli  a1, s3, 5                 ; ...
        call  srv_put                   ; ...
        mv    a0, s3                    ; ...
        j     reply                     ; ...

; od_rec(a0 = record, a1 = directory entry): {name[24], u64 size}
od_rec:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        li    a2, 24                    ; name (24 bytes)
        call  srv_bcopy                 ; ...
        ld    a0, 8(sp)                 ; size
        ld    a1, 16(sp)                ; ...
        lwu   t0, 28(a1)                ; ...
        sd    t0, 24(a0)                ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

op_unlink:
        li    a0, 0                     ; the path's tags must exist
        call  get_named                 ; ...
        bltz  a0, reply                 ; ...
        call  lookup                    ; ...
        beqz  a0, oo_nofile             ; ...
        call  remove                    ; ...
        call  save_meta                 ; ...
        j     ok                        ; ...

; TAG / UNTAG: data = a path, a zero byte, a tag name
op_tag:
        li    s4, 1                     ; s4 = 1 tag, 0 untag
        j     otg_go                    ; ...
op_untag:
        li    s4, 0                     ; ...
otg_go:
        call  get_two                   ; the path, and the tag's name
        bltz  a0, reply                 ; ...
        mv    s2, a0                    ; s2 = the tag's name
        mv    s3, a1                    ; s3 = its length
        li    a0, 0                     ; the path's tags must exist
        call  parse_file                ; ...
        bltz  a0, reply                 ; ...
        la    t0, nmlen                 ; it must name a file
        ld    t0, 0(t0)                 ; ...
        li    a0, -1                    ; ...
        beqz  t0, reply                 ; ...
        call  lookup                    ; ...
        beqz  a0, oo_nofile             ; ...
        call  ftag_of                   ; s1 = its tag set
        mv    s1, a0                    ; ...
        mv    a0, s2                    ; the tag (created when tagging)
        mv    a1, s3                    ; ...
        mv    a2, s4                    ; ...
        call  tag_ref                   ; a0 = its number or < 0
        bltz  a0, reply                 ; ...
        li    t0, 1                     ; ...
        sll   t0, t0, a0                ; ...
        ld    t1, 0(s1)                 ; ...
        beqz  s4, otg_un                ; ...
        or    t1, t1, t0                ; tag
        j     otg_set                   ; ...
otg_un:
        li    t2, -1                    ; untag: clear the bit
        xor   t0, t0, t2                ; ...
        and   t1, t1, t0                ; ...
otg_set:
        sd    t1, 0(s1)                 ; ...
        call  save_meta                 ; (an unused tag goes)
        j     ok                        ; ...

; CWD: the requester's current tag path (mode 0 get, 1 set, 2 inherit)
op_cwd:
        la    t0, srv_hdr               ; mode
        ld    t1, 24(t0)                ; ...
        beqz  t1, ocw_get               ; 0: get
        li    t2, 2                     ; 2: inherit
        beq   t1, t2, ocw_inh           ; ...
        li    t2, 1                     ; 1: set
        bne   t1, t2, bad               ; ...
        call  get_raw                   ; a0 = the length of the new path
        bltz  a0, reply                 ; ...
        beqz  a0, ocw_root              ; none: "/"
        mv    a1, a0                    ; resolved (relative to the current one)
        la    a0, rbuf                  ; ...
        call  setpath                   ; ...
        li    s1, 0                     ; s1 = cursor
        li    s4, 0                     ; s4 = the tags of the view
        li    s5, 0                     ; s5 = the tags it excludes
ocw_c:
        mv    a0, s1                    ; every component: a tag, or "-" and a tag
        call  comp                      ; ...
        beqz  a1, ocw_chk               ; all seen
        mv    s1, a2                    ; ...
        li    s2, 0                     ; s2 = 1: an exclusion
        lbu   t0, 0(a0)                 ; ...
        li    t1, '-'                   ; ...
        bne   t0, t1, ocw_t             ; ...
        li    s2, 1                     ; ...
        addi  a0, a0, 1                 ; ...
        addi  a1, a1, -1                ; ...
ocw_t:
        call  tag_find                  ; a0 = its number, or -1
        bltz  a0, ocw_none              ; no such tag
        li    t0, 1                     ; ...
        sll   t0, t0, a0                ; ...
        bnez  s2, ocw_x                 ; ...
        or    s4, s4, t0                ; ...
        j     ocw_c                     ; ...
ocw_x:
        or    s5, s5, t0                ; ...
        j     ocw_c                     ; ...
ocw_chk:
        la    t0, plen                  ; ".." all the way: "/"
        ld    t1, 0(t0)                 ; ...
        beqz  t1, ocw_root              ; ...
        li    a0, -1                    ; too long to keep
        li    t2, CWDMAX                ; ...
        bgtu  t1, t2, reply             ; ...
        li    s8, 0                     ; a file in that view? (no empty views)
ocw_w:
        mv    a0, s8                    ; window by window
        call  win                       ; ...
        la    t0, dir                   ; ...
        la    t1, ftags                 ; ...
        la    t2, tagtab                ; (the window's end)
ocw_f:
        bgeu  t0, t2, ocw_wn            ; ...
        lbu   t3, 0(t0)                 ; used?
        beqz  t3, ocw_fn                ; ...
        ld    t3, 0(t1)                 ; every tag of the view, none excluded?
        and   t4, t3, s4                ; ...
        bne   t4, s4, ocw_fn            ; ...
        and   t4, t3, s5                ; ...
        beqz  t4, ocw_set               ; yes
ocw_fn:
        addi  t0, t0, 32                ; ...
        addi  t1, t1, 8                 ; ...
        j     ocw_f                     ; ...
ocw_wn:
        addi  s8, s8, 1                 ; ...
        la    t0, nwin                  ; ...
        ld    t0, 0(t0)                 ; ...
        blt   s8, t0, ocw_w             ; ...
ocw_none:
        li    a0, -4                    ; no such tag (or nothing carries them all)
        j     reply                     ; ...
ocw_set:
        call  srv_pid                   ; s1 = the requester
        mv    s1, a0                    ; ...
        call  cwd_find                  ; its entry, or a free one
        bnez  a0, ocw_have              ; ...
        call  cwd_free                  ; ...
        li    t0, -6                    ; none: the table is full
        beqz  a0, ocw_err               ; ...
ocw_have:
        sd    s1, C_PID(a0)             ; the new path
        la    t0, plen                  ; ...
        ld    a2, 0(t0)                 ; ...
        sd    a2, C_LEN(a0)             ; ...
        addi  a0, a0, C_TEXT            ; ...
        la    a1, pbuf                  ; ...
        call  srv_bcopy                 ; ...
        j     ocw_get                   ; answered as a get
ocw_root:
        call  srv_pid                   ; "/": no entry
        call  cwd_drop                  ; ...
ocw_get:
        call  srv_pid                   ; the requester's entry
        call  cwd_find                  ; ...
        beqz  a0, ocw_slash             ; none: "/"
        ld    s1, C_LEN(a0)             ; its text -> the request
        mv    a1, s1                    ; ...
        addi  a0, a0, C_TEXT            ; ...
        call  srv_put                   ; ...
        mv    a0, s1                    ; its length
        j     reply                     ; ...
ocw_slash:
        la    a0, bounce                ; "/"
        li    t0, '/'                   ; ...
        sd    t0, 0(a0)                 ; ...
        li    a1, 1                     ; ...
        call  srv_put                   ; ...
        li    a0, 1                     ; ...
        j     reply                     ; ...
ocw_err:
        mv    a0, t0                    ; ...
        j     reply                     ; ...
ocw_inh:
        call  srv_pid                   ; from proc only
        li    t0, PROC_PID              ; ...
        bne   a0, t0, bad               ; ...
        la    a0, bounce                ; parent, child
        li    a1, 16                    ; ...
        call  srv_get                   ; ...
        la    t0, bounce                ; a stale entry of the child's goes
        ld    a0, 8(t0)                 ; ...
        call  cwd_drop                  ; ...
        la    t0, bounce                ; (a child of pid 0: nothing)
        ld    t0, 8(t0)                 ; ...
        beqz  t0, ok                    ; ...
        la    t0, bounce                ; the parent's
        ld    a0, 0(t0)                 ; ...
        call  cwd_find                  ; ...
        beqz  a0, ok                    ; at "/": so is the child
        mv    s1, a0                    ; ...
        call  cwd_free                  ; a free entry
        beqz  a0, ok                    ; none: the child starts at "/"
        mv    s2, a0                    ; ...
        mv    a1, s1                    ; a copy of the parent's
        li    a2, C_SIZEOF              ; ...
        call  srv_bcopy                 ; ...
        la    t0, bounce                ; for the child
        ld    t0, 8(t0)                 ; ...
        sd    t0, C_PID(s2)             ; ...
        j     ok                        ; ...

; cwd_find(a0 = pid) -> a0 = its current-path entry, or 0 (pid 0: none)
cwd_find:
        beqz  a0, cwf_no                ; ...
cwd_look:
        la    t0, cwds                  ; ...
        li    t1, NCWD                  ; ...
cwf_l:
        beqz  t1, cwf_no                ; ...
        ld    t2, C_PID(t0)             ; ...
        beq   t2, a0, cwf_yes           ; ...
        addi  t0, t0, C_SIZEOF          ; ...
        addi  t1, t1, -1                ; ...
        j     cwf_l                     ; ...
cwf_yes:
        mv    a0, t0                    ; ...
        ret                             ; ...
cwf_no:
        li    a0, 0                     ; ...
        ret                             ; ...

; cwd_free() -> a0 = a free current-path entry (pid 0), or 0
cwd_free:
        li    a0, 0                     ; ...
        j     cwd_look                  ; ...

; cwd_drop(a0 = pid): forget its current path (it is at "/" again)
cwd_drop:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        call  cwd_find                  ; ...
        beqz  a0, cwd_r                 ; none
        sd    zero, C_PID(a0)           ; free
        sd    zero, C_LEN(a0)           ; ...
cwd_r:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; RENAME: data = a path, a zero byte, the new path
op_rename:
        call  get_two                   ; the path, and the new one
        bltz  a0, reply                 ; ...
        mv    s2, a0                    ; s2, s3 = the new path
        mv    s3, a1                    ; ...
        li    a0, 0                     ; the old path's tags must exist
        call  parse_file                ; ...
        bltz  a0, reply                 ; ...
        la    t0, nmlen                 ; it must name a file
        ld    t0, 0(t0)                 ; ...
        li    a0, -1                    ; ...
        beqz  t0, reply                 ; ...
        call  lookup                    ; s1 = the file, s5 = its window
        beqz  a0, oo_nofile             ; ...
        mv    s1, a0                    ; ...
        la    t0, wcur                  ; ...
        ld    s5, 0(t0)                 ; ...
        mv    a0, s2                    ; the new path -> pbuf, resolved (it is
        mv    a1, s3                    ; in rbuf, apart from pbuf)
        call  setpath                   ; ...
        li    a0, 1                     ; its tags are created if need be
        call  parse_file                ; ...
        bltz  a0, orn_fail              ; ...
        la    t0, nmlen                 ; it must name a file
        ld    t0, 0(t0)                 ; ...
        li    a0, -1                    ; ...
        beqz  t0, orn_fail              ; ...
        call  find                      ; another file of that name goes
        beqz  a0, orn_name              ; none
        la    t0, wcur                  ; (the file itself: the same entry of the
        ld    t0, 0(t0)                 ;   same window)
        bne   t0, s5, orn_rm            ; ...
        beq   a0, s1, orn_name          ; ...
orn_rm:
        call  remove                    ; ...
        mv    a0, s5                    ; the file's own window again
        call  win                       ; ...
orn_name:
        mv    a0, s1                    ; the new name
        li    t1, 24                    ; (cleared first)
orn_z:
        sb    zero, 0(a0)               ; ...
        addi  a0, a0, 1                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, orn_z                 ; ...
        mv    a0, s1                    ; ...
        la    a1, nm                    ; ...
        la    a2, nmlen                 ; ...
        ld    a2, 0(a2)                 ; ...
        call  srv_bcopy                 ; ...
        mv    a0, s1                    ; the new path's tags join its own
        call  ftag_of                   ; ...
        ld    t1, 0(a0)                 ; ...
        la    t2, pmask                 ; ...
        ld    t2, 0(t2)                 ; ...
        or    t1, t1, t2                ; ...
        sd    t1, 0(a0)                 ; ...
        call  save_meta                 ; ...
        j     ok                        ; ...
orn_fail:
        call  tag_gc                    ; tags it created for nothing go (a0 kept)
        j     reply                     ; ...

; TAGS: every tag, or (data = a path) the tags of that file
op_tags:
        li    a0, 0                     ; ...
        call  get_file                  ; ...
        bltz  a0, reply                 ; ...
        li    s4, -1                    ; s4 = which tags: all
        la    t0, nmlen                 ; a file?
        ld    t0, 0(t0)                 ; ...
        beqz  t0, ots_all               ; no
        call  lookup                    ; ...
        beqz  a0, oo_nofile             ; ...
        call  ftag_of                   ; its tags
        ld    s4, 0(a0)                 ; ...
ots_all:
        call  tag_gc                    ; (no unused tags)
        call  tcount                    ; the files carrying each
        la    s1, tagtab                ; s1 = slot
        li    s2, 0                     ; s2 = its number
        li    s3, 0                     ; s3 = records
ots_l:
        li    t0, NTAGS                 ; all seen?
        bgeu  s2, t0, ots_done          ; ...
        lbu   t0, 0(s1)                 ; a tag?
        beqz  t0, ots_n                 ; ...
        srl   t0, s4, s2                ; one we want?
        andi  t0, t0, 1                 ; ...
        beqz  t0, ots_n                 ; ...
        la    s5, bounce                ; s5 = the record
        slli  t0, s3, 5                 ; ...
        add   s5, s5, t0                ; ...
        mv    a0, s5                    ; name (16 bytes)
        mv    a1, s1                    ; ...
        li    a2, TAGLEN                ; ...
        call  srv_bcopy                 ; ...
        la    t0, tcnt                  ; the files carrying it
        slli  t1, s2, 3                 ; ...
        add   t0, t0, t1                ; ...
        ld    t2, 0(t0)                 ; ...
        sd    t2, 16(s5)                ; files
        sd    s2, 24(s5)                ; the tag's number
        addi  s3, s3, 1                 ; ...
ots_n:
        addi  s1, s1, TAGLEN            ; ...
        addi  s2, s2, 1                 ; ...
        j     ots_l                     ; ...
ots_done:
        la    a0, bounce                ; -> the request
        slli  a1, s3, 5                 ; ...
        call  srv_put                   ; ...
        mv    a0, s3                    ; ...
        j     reply                     ; ...

op_stat:
        li    a0, 0                     ; ...
        call  get_named                 ; ...
        bltz  a0, reply                 ; ...
        call  lookup                    ; ...
        beqz  a0, oo_nofile             ; ...
        lwu   a0, 28(a0)                ; its size
        j     reply                     ; ...

op_statfs:
        la    t0, bounce                ; total, used, files
        la    t1, total           ; (its address)
        ld    t1, 0(t1)              ; ...
        sd    t1, 0(t0)                 ; ...
        la    t2, hdr                   ; ...
        lwu   t1, 40(t2)                ; ...
        sd    t1, 8(t0)                 ; ...
        call  dcount                    ; the files
        la    t0, bounce                ; ...
        sd    a0, 16(t0)                ; ...
        mv    a0, t0                    ; -> the request
        li    a1, 24                    ; ...
        call  srv_put                   ; ...
        li    a0, 3                     ; ...
        j     reply                     ; ...

op_readblk:
        la    t0, srv_hdr               ; the block
        ld    s1, 8(t0)                 ; ...
        la    t1, total           ; (its address)
        ld    t1, 0(t1)              ; on the disk?
        bgeu  s1, t1, bad               ; ...
        li    a0, 1                     ; read it
        mv    a1, s1                    ; ...
        li    a2, 1                     ; ...
        li    a3, SCR                   ; ...
        li    a4, 5                     ; ...
