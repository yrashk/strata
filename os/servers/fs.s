        li    t2, SCR                   ; ...
        tget  tg1, t0, c5, t2, t1       ; ...
        twait 1 << 1                    ; ...
        la    a0, bounce                ; -> the request
        li    a1, 512                   ; ...
        call  srv_put                   ; ...
        li    a0, 512                   ; ...
        j     reply                     ; ...

