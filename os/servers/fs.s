bufs:   .space NB * 4096                ; the page buffers (store.s)

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        call  sys_init                  ; ...
        li    a0, 2                     ; dev (c2): the disk
        li    a1, 30                    ; GETDISK
        li    a2, 0                     ; ...
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        call  sys_msg                   ; c6 = window, c7 = endpoint
        cclear c1                       ; proc's endpoint is not needed
        cmov  c1, c6                    ; c1 = the device window
        cclear c2                       ; ...
        cmov  c2, c7                    ; c2 = the device endpoint
        cclear c5                       ; our message buffer is not needed any more
        li    t0, 0x40000               ; the I/O buffer: the top of our memory
        csplit c5, c0, t0               ; c0 = [0, 0x40000), c5 = [0x40000, 0xC0000)
        cbase t0, c5                    ; its base: the device gives it back by it
        sd    t0, iobase(zero)          ; ...
        la    t0, ident                 ; capacity, from the identify data
        li    t1, 64                    ; ...
        tget  tg1, t0, c1, zero, t1     ; ...
        twait 1 << 1                    ; ...
        ld    t1, 8(t0)                 ; ...
        sd    t1, total(zero)           ; ...
        la    a0, start                 ; (a disk that cannot be read: see st_die)
        call  srv_guard                 ; ...
        call  fs_mount                  ; the store, and the file system in it
        sd    a0, nofs(zero)            ; ...
start:
        la    a0, loop                  ; a fault on a dead request returns to the loop
        call  srv_guard                 ; ...
loop:
        li    a0, 0                     ; no device tags
        li    a1, -1                    ; no timeout
        call  srv_recv                  ; ...
        bltz  a0, loop                  ; ...
        sd    zero, nnew(zero)          ; (no tags made yet)
        la    t0, srv_hdr               ; dispatch
        ld    t1, 0(t0)                 ; ...
        li    t2, OP_DUPS               ; DUPS
        beq   t1, t2, op_dups           ; ...
        li    t2, OP_CLEANUP            ; CLEANUP
        beq   t1, t2, op_cleanup        ; ...
        li    t2, OP_CANCEL             ; CANCEL: nothing here ever waits
        beq   t1, t2, ok                ; ...
        li    t2, 33                    ; READBLK
        beq   t1, t2, op_readblk        ; ...
        ld    t2, nofs(zero)            ; no store: nothing else can be answered
        bnez  t2, st_die                ; ...
        li    t2, 1                     ; READ
        beq   t1, t2, op_read           ; ...
        li    t2, 2                     ; WRITE
        beq   t1, t2, op_write          ; ...
        li    t2, 3                     ; OPEN
        beq   t1, t2, op_open           ; ...
        li    t2, 4                     ; CLOSE
        beq   t1, t2, op_close          ; ...
        li    t2, 10                    ; DIR
        beq   t1, t2, op_dir            ; ...
        li    t2, 11                    ; UNLINK
        beq   t1, t2, op_unlink         ; ...
        li    t2, 12                    ; TAG
        beq   t1, t2, op_tag            ; ...
        li    t2, 13                    ; UNTAG
        beq   t1, t2, op_untag          ; ...
        li    t2, 14                    ; TAGS
        beq   t1, t2, op_tags           ; ...
        li    t2, 15                    ; RENAME
        beq   t1, t2, op_rename         ; ...
        li    t2, OP_CWD                ; CWD
        beq   t1, t2, op_cwd            ; ...
        li    t2, 27                    ; STAT
        beq   t1, t2, op_stat           ; ...
        li    t2, 28                    ; LOADIMG
        beq   t1, t2, op_loadimg        ; ...
        li    t2, 32                    ; STATFS
        beq   t1, t2, op_statfs         ; ...
        li    t2, 34                    ; READALL
        beq   t1, t2, op_readall        ; ...
        li    t2, 35                    ; WRITEALL
        beq   t1, t2, op_writeall       ; ...
bad:
        li    a0, -1                    ; unknown, or refused
reply:
        li    a1, 0                     ; no attachment
        call  srv_reply                 ; ...
        j     loop                      ; ...
reply_att:
        li    a1, 1                     ; the attachment (c7) goes back first
        call  srv_reply                 ; ...
        j     loop                      ; ...
ok:
        li    a0, 0                     ; ...
        j     reply                     ; ...
nofile:
        li    a0, -4                    ; no such file
        j     reply                     ; ...

; st_full: the disk has no room for what the request needs. st_die: a page
; failed its checksum, or the device refused. Reached from anywhere in the
; store: the commit under way is given up (what was not yet committed is
; lost: files being written are closed as they were), and the request is
; answered -1 or -5.
st_full:
        li    s1, -1                    ; ...
        j     st_fail                   ; ...
st_die:
        li    s1, -5                    ; ...
st_fail:
        la    t0, srv_gsp               ; the loop's stack
        ld    sp, 0(t0)                 ; ...
        ld    t0, nofs(zero)            ; ...
        bnez  t0, sf_reply              ; ...
        li    t0, 1                     ; (a failure in here: no store any more)
        sd    t0, nofs(zero)            ; ...
        call  fs_lost                   ; ...
        call  st_abort                  ; ...
        bltz  a0, sf_reply              ; ...
        call  fs_trees                  ; ...
        sd    a0, nofs(zero)            ; ...
sf_reply:
        mv    a0, s1                    ; ...
        cvalid t0, c6                   ; (at start there is no request)
        beqz  t0, start                 ; ...
        cvalid t0, c7                   ; ...
        bnez  t0, reply_att             ; ...
        j     reply                     ; ...

; =============================================================================
; The block device
; =============================================================================

; blk(a0 = op 1 read / 2 write, a1 = first block, a2 = blocks (<= 256), a3 =
; byte offset in the buffer, a4 = 5: the I/O buffer (c5) / 7: the attachment)
; -> a0 = status (0 = ok)
blk:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a4, 8(sp)                 ; ...
        la    t0, cmd                   ; build the command
        sb    a0, 0(t0)                 ; op
        csrr  t1, coreid                ; the buffer comes back to this core
        sb    t1, 1(t0)                 ; ...
        la    t2, cid                   ; command id
        ld    t1, 0(t2)                 ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, 0(t2)                 ; ...
        sh    t1, 2(t0)                 ; ...
        sw    a2, 4(t0)                 ; blocks
        sd    a1, 8(t0)                 ; first block
        sd    a3, 16(t0)                ; offset in the buffer
        sd    zero, 24(t0)              ; ...
        li    t1, BLK_SQ                ; -> the submission port
        li    t2, 32                    ; ...
        tput  tg1, t0, c1, t1, t2       ; ...
        twait 1 << 1                    ; (the command first)
        li    t0, 7                     ; which buffer?
        beq   a4, t0, blk_att           ; ...
        cbase a3, c5                    ; the I/O buffer: lend it
        csend c5, c2                    ; ...
        j     blk_wait                  ; ...
blk_att:
        cbase a3, c7                    ; the attachment: lend it
        csend c7, c2                    ; ...
blk_wait:
        li    a0, SVC_WAIT              ; wait until the device gives it back
        li    a1, -1                    ; (no doorbell: the device is not a core)
        li    a2, -1                    ; no timeout
        ld    a4, 8(sp)                 ; back into the same register
        svc                             ; ...
        la    t0, cqe                   ; the completion
        li    t1, BLK_CQ                ; ...
        li    t2, 16                    ; ...
        tget  tg1, t0, c1, t1, t2       ; ...
        twait 1 << 1                    ; ...
        lhu   a0, 2(t0)                 ; status
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; blkn(a0 = op, a1 = first block, a2 = blocks (any), a3 = offset, a4 = buffer)
; -> a0 = status: several commands of at most 256 blocks
blkn:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        sd    a2, 24(sp)                ; ...
        sd    a3, 32(sp)                ; ...
        sd    a4, 40(sp)                ; ...
bn_l:
        ld    a2, 24(sp)                ; blocks left
        li    a0, 0                     ; (none: ok)
        beqz  a2, bn_ret                ; ...
        li    t0, 256                   ; at most 256
        bleu  a2, t0, bn_n              ; ...
        mv    a2, t0                    ; ...
bn_n:
        ld    t0, 24(sp)                ; ...
        sub   t0, t0, a2                ; ...
        sd    t0, 24(sp)                ; ...
        ld    a0, 8(sp)                 ; ...
        ld    a1, 16(sp)                ; ...
        add   t0, a1, a2                ; ...
        sd    t0, 16(sp)                ; ...
        ld    a3, 32(sp)                ; ...
        slli  t0, a2, 9                 ; ...
        add   t0, a3, t0                ; ...
        sd    t0, 32(sp)                ; ...
        ld    a4, 40(sp)                ; ...
        call  blk                       ; ...
        beqz  a0, bn_l                  ; ...
bn_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; ...

