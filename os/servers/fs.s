; =============================================================================
; fs.s: the file server
; =============================================================================
;
; A user-mode server (pid 3, created by the kernel at boot). It owns the block
; device: at start it asks dev for a window on the device's ports and an
; endpoint to the device's node, then mounts the disk.
;
; The disk is a STORE (doc/strata-fs-proposal.md): ordered key-value trees,
; copy-on-write, in namespaces; a change is on the disk whole or not at all.
; The store is store.s, storew.s and sblob.s. The file system is one client
; of it: it keeps five trees in the namespace "fs" and nothing else on the
; disk (tools/stdb/fsl.h spells the trees out):
;
;   obj   object id -> the file's record: size, the commits that created and
;         last changed it, its tag ids, its attributes, its name
;   data  object id -> its contents (a blob: in the tree when short, else a
;         stream of extents)
;   name  name -> object id
;   attr  attribute id, value, object id -> nothing: the index. Attribute 1
;         is "tag" (value: a tag id), 2 the size, 3 the last change, 4 boot
;   dict  tag names <-> tag ids with the count of files carrying each, and
;         the counters ("!")
;
; Tags. The file system has no directories: a file has one name, unique on
; the disk, and carries tags; a "directory" is a set of tags. A tag is made
; by its first use and goes with the last file that carries it.
;
; Paths. A name in a request is a path: components separated by "/" (empty
; ones are skipped). The last component is the file's name; the ones before
; it are the tags of its directory. A file's directory is the set of its
; tags ("/src/demo" is "/demo/src"; no tag: the root), and a name is unique
; within a directory: "/doc/motd" is the motd whose only tag is doc, and
; "motd" the one of the current directory. Opening for writing makes the
; file there (creating tags that do not exist yet). QUERY takes a path of
; tags and lists that directory's files; its last component may instead
; name one file. A component "-tag" (in QUERY) is an exclusion: files that
; carry that tag do not count, so "/src/-demo" shows /src without its
; subdirectory demo. Paths that create (writing, the new name of RENAME)
; cannot exclude (-1), and a tag name cannot start with "-".
;
; Subdirectories: QUERY also answers the files of deeper directories, as
; records without a name, and in the reply's mode word the other tags they
; carry (bit t = tag id t, for the ids below 64). `ls` shows those tags as
; "tag/".
;
; The current tag path. Every process has one, the tag-system analogue of a
; working directory (none kept = "/", every file). A path that does not
; start with "/" is relative: it is read as the requester's current path, a
; "/", then the path; QUERY with no path lists the current one. Every path is
; then normalized: "." components go, ".." takes the one before it away
; (never above "/"). When creating, exclusions that come from the current
; path are dropped; one in the request's own text is -1. CWD (20) reads or
; sets the path: SET takes a path whose every component is a tag that exists
; or "-tag" of one, and at least one file must match (-4 otherwise: no empty
; views). The table keeps one entry per process not at "/" (NCWD = proc's
; process records; the texts are in far memory). When proc spawns, it sends
; CWD mode 2 (parent, child), and the child starts where its parent is;
; CLEANUP forgets the entry.
;
; Writing. Opening for writing (mode 1) makes the file if it is not there,
; and the bytes written go to a blob of their own; the close puts that blob
; in the place of the file's contents and commits, so that the disk holds
; the old contents or the new, never a mixture. Appending (mode 2) extends
; the contents where they are and commits at the close. Every other change
; (UNLINK, TAG, UNTAG, RENAME) is a commit of its own: when its reply
; arrives it is on the disk. A boot object (one the kernel loads from the
; boot manifest: proc, dev, fs) can be written: at its close its contents
; are brought into one run of pages and the manifest is written anew, in
; the same commit. It cannot be renamed or deleted here.
;
;   3 OPEN    data = path, length = its length, mode 0 read / 1 write / 2 append -> id
;   1 READ    handle = id, length -> bytes (0 at the end of the file)
;   2 WRITE   handle = id, length, data -> bytes
;   4 CLOSE   handle = id -> 0
;  11 UNLINK  data = path -> 0 / -4
;  12 TAG     data = path, a zero byte, a tag name -> 0 / -4 / -6 / -1
;  13 UNTAG   data = path, a zero byte, a tag name -> 0 / -4
;  15 RENAME  data = path, a zero byte, a new path -> 0 / -4 / -6 / -1: the
;             file takes the new path's name and gains its tags (created if
;             new); it keeps its tags and its contents. Another file of the
;             new name is deleted (as UNLINK)
;  20 CWD     mode 0 get: -> length; data: the current tag path ("/" at the
;             root). mode 1 set: data = a path (none: "/"; relative to the
;             current one; "..") -> the new one, as get / -4 (no such tag, or
;             no file in that view) / -1 (longer than CWDMAX) / -6 (table
;             full). mode 2 (from proc only): data = u64 parent pid, u64 child
;             pid: the child starts in the parent's path -> 0
;  27 STAT    data = path -> size / -4
;  28 LOADIMG data = path, handle = most bytes, mode = arena offset; the arena
;             as attachment (c7) -> size / -4 / -1; the arena goes back
;  32 STATFS  -> 3; data: u64 total blocks, used blocks, files
;  33 READBLK handle = block -> 512; data: the block
;  34 READALL handle = id (read), mode = arena offset, length = most bytes; the
;             arena as attachment -> size (the whole file is copied in)
;  35 WRITEALL handle = id (write), mode = arena offset, length = bytes; the
;             arena as attachment -> bytes (appended to the file)
;  40 QUERY   data = a tag path (none: the current one) -> the files that
;             carry its tags, part by part (a cursor), whole names, each
;             file's tags; mode word = the facets; mode 1: only the count
;             and the facets (fsops.s). 10 DIR, with 24-byte names, is gone
;  41 TAGS2   data = a path (none: every tag) -> tags, part by part: every
;             tag, or the tags of the file the path names (fsops.s). 14
;             TAGS, with 16-byte names, is gone
;  42 SETATTR / 43 GETATTR   a file's attributes (fsattr.s, which also has
;             the terms a path may hold: size>4096, colour=red, PREFIX*)
;  45 SNAP    snapshots (fsops.s): mode 0 take one (data = its name), 1 delete
;             it, 2 list them, 3 restore it (the file system becomes what it
;             shows). A snapshot is the whole disk as of a commit;
;             a path whose first component is "@NAME" reads it: OPEN for
;             reading, STAT, LOADIMG, QUERY, TAGS2
;  46 FIND    names across the whole file system: mode 0 the files whose
;             names begin with the data's text, mode 1 those whose names
;             hold it; records as QUERY's, with a cursor (fsunits.s, uf)
;  64 DBGET / 65 DBSCAN / 66 DBBATCH   the store for programs: trees of keys
;             and values in namespaces of their own (fsops.s)
;  36 DUPS / 37 CLEANUP / 38 CANCEL from proc (see srv.s)
; Every call answers -5 when the disk cannot be read as a store, or a page
; of it fails its checksum.
;
; Capability registers: c0 the rest of the arena, c1 the device window,
; c2 the device endpoint, c5 the I/O buffer (512 KiB: 4 KiB of scratch, the
; current tag paths, then the page cache's frames), c6 the request, c7 its
; attachment.
;
; The program library (os/lib/sys.s) is not part of this server: of all of
; it, it would use one message at start (GETDISK) and three buffers. What it
; needs is here: sys_buf holds a reply's data (srv.s uses it too), reqbuf a
; request's data and a meta block, pgcopy the copy of a page being split.

