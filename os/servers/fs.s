; orec(a0 = id) -> a0 = its open record, or 0 if not open
orec:
        addi  a0, a0, -1                ; ids are 1..NOPEN
        li    t0, NOPEN                 ; ...
        bgeu  a0, t0, or_no             ; ...
        li    t0, O_SIZEOF              ; ...
        mul   a0, a0, t0                ; ...
        la    t0, opens                 ; ...
        add   a0, a0, t0                ; ...
        ld    t0, O_USED(a0)            ; ...
        beqz  t0, or_no                 ; ...
        ret                             ; ...
or_no:
        li    a0, 0                     ; ...
        ret                             ; ...

; region_off(a0 = open record) -> a0 = I/O-buffer offset of its region
region_off:
        ld    t0, O_REG(a0)             ; ...
        li    t1, REGSZ                 ; ...
        mul   a0, t0, t1                ; ...
        li    t1, REG0                  ; ...
        add   a0, a0, t1                ; ...
        ret                             ; ...

; append(a0 = open record, a1 = D-LS bytes, a2 = count): add to its region
; (the region's end need not be word-aligned: its last word is merged)
append:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        mv    s1, a0                    ; s1 = record
        mv    s2, a1                    ; s2 = bytes
        mv    s3, a2                    ; s3 = count
        call  region_off                ; s4 = offset of the end, word-aligned
        ld    t0, O_SIZE(s1)            ; ...
        add   s4, a0, t0                ; ...
        andi  t5, s4, 7                 ; t5 = bytes of the last partial word
        sub   s4, s4, t5                ; ...
        sd    t5, 40(sp)                ; ...
        beqz  t5, ap_cp                 ; none
        la    t0, bounce                ; fetch that word
        li    t1, 8                     ; ...
        tget  tg1, t0, c5, s4, t1       ; ...
        twait 1 << 1                    ; ...
ap_cp:
        la    a0, bounce                ; the new bytes after it
        ld    t5, 40(sp)                ; ...
        add   a0, a0, t5                ; ...
        mv    a1, s2                    ; ...
        mv    a2, s3                    ; ...
        call  srv_bcopy                 ; ...
        ld    t5, 40(sp)                ; write back, whole words
        add   t1, t5, s3                ; ...
        addi  t1, t1, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        la    t0, bounce                ; ...
        tput  tg1, t0, c5, s4, t1       ; ...
        twait 1 << 1                    ; ...
        ld    t0, O_SIZE(s1)            ; the file grew
        add   t0, t0, s3                ; ...
        sd    t0, O_SIZE(s1)            ; ...
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; ...

; finish(a0 = id): its last reference closed: save a file being written, free it
finish:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        call  orec                      ; ...
        beqz  a0, fn_ret                ; ...
        sd    a0, 8(sp)                 ; ...
        ld    t0, O_USED(a0)            ; a file being written?
        li    t1, 2                     ; ...
        bne   t0, t1, fn_free           ; ...
        call  save_file                 ; save it
        ld    a0, 8(sp)                 ; its region is free
        ld    t0, O_REG(a0)             ; ...
        slli  t0, t0, 3                 ; ...
        la    t1, regused               ; ...
        add   t1, t1, t0                ; ...
        sd    zero, 0(t1)               ; ...
fn_free:
        ld    a0, 8(sp)                 ; the record is free
        sd    zero, O_USED(a0)          ; ...
fn_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; dropref(a0 = pid, a1 = id): one reference less; the last one finishes the file
dropref:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a1, 8(sp)                 ; ...
        call  ref_del                   ; ...
        beqz  a0, dr_ret                ; it held none
        ld    a0, 8(sp)                 ; any left?
        call  ref_count                 ; ...
        bnez  a0, dr_ret                ; ...
        ld    a0, 8(sp)                 ; no: finish it
        call  finish                    ; ...
dr_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

