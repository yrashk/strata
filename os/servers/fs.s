        ld    t0, rec_max(zero)         ; ...
        bgtu  a4, t0, rsv_ret           ; ...
        ld    a0, rec_oid(zero)         ; ...
        call  bswap                     ; ...
        sd    a0, okey(zero)            ; ...
        ld    a0, x_obj(zero)           ; ...
