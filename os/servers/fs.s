; =============================================================================
; fs.s: the file server
; =============================================================================
;
; A user-mode server (pid 3, created by the kernel at boot). It owns the block
; device: at start it asks dev for a window on the device's ports and an
; endpoint to the device's node, then reads the boot header, the directory
; (entries of {name[24], u32 first block, u32 size}; files are contiguous
; runs of blocks; new files go at the first free block, header offset 40) and
; the tag table (header offset 52; 0 = the disk has none).
;
; The directory has as many entries as the header says (offset 56: a
; multiple of 128, at most 1024; 0 = 128, a disk made before the field
; existed). A thousand entries are 32 KiB, more than this program's D-LS can
; spare, so the directory and the files' tag sets live in the I/O buffer
; (far memory), and the D-LS holds a WINDOW of 128 entries with their tag
; sets (`dir`, `ftags`). win(n) writes the window back and fetches another;
; routines that walk the whole directory go window by window and put back
; the window they found (dfree, tag_gc, tcount, dcount), so an entry's
; address stays good across them; find leaves the window of the entry it
; found.
;
; Tags. The file system has no directories: a file carries up to 64 tags, and
; a "directory" is a set of tags. The tag table holds 64 tag names of 16
; bytes (zero-padded; a zero first byte = a free slot), then a u64 tag set
; per directory entry: bit t of set f = file f carries tag t.
; A tag that no file carries any more is dropped when the table is saved.
;
; Paths. A name in a request is a path: components separated by "/" (empty
; ones are skipped). The last component is the file's name (unique on the
; disk); the ones before it are tags the file must carry. "motd", "/motd" and
; "/doc/motd" all name motd if it carries doc; "/bin/doc/motd" names nothing.
; Opening for writing adds the path's tags to the file (creating tags that do
; not exist yet). DIR takes a path of tags; its last component may instead
; name one file. A component "-tag" before the name (or last, in DIR) is an
; exclusion: the file must not carry that tag ("/notes/-work": tagged notes,
; not work; excluding a tag that does not exist excludes nothing). Paths
; that create (writing, the new name of RENAME) cannot exclude (-1), and a
; tag name cannot start with "-".
;
; Subdirectories are facets: DIR also answers, in the reply's mode word, the
; set of every other tag that at least one listed file carries (the OR of
; their tag sets without the path's own tags). Those are the ways to narrow
; the listing further, as subdirectories would be; `ls` shows them as "tag/".
;
; The current tag path. Every process has one, the tag-system analogue of a
; working directory (none kept = "/", every file). A path that does not
; start with "/" is relative: it is read as the requester's current path, a
; "/", then the path ("notes" in /src/demo is "/src/demo/notes"); DIR with no
; path lists the current one. Every path is then normalized: "." components
; go, ".." takes the one before it away (never above "/"). When creating
; (writing, RENAME's new name), exclusions that come from the current path
; are dropped (the file gets its tags); one in the request's own text is -1
; as before. CWD (20) reads or sets the path: SET takes a path (relative to
; the current one) whose every component is a tag that exists or "-tag" of
; one, and at least one file must match (-4 otherwise: no empty views). The
; table keeps one entry of at most CWDMAX bytes per process not at "/"
; (NCWD = proc's process records). Inheritance: when proc spawns, it sends
; CWD mode 2 (parent, child) between LOADIMG and CREATE, and the child starts
; where its parent is; CLEANUP (the process ended, or CREATE failed) forgets
; the entry.
;
; Disk I/O: the server writes a command into the device's submission port,
; lends the device its I/O buffer (c5) with `csend` through the device
; endpoint, and waits for the buffer to come back (svc WAIT_REPLY on its
; base): the device DMAs into or out of it meanwhile. Program images are read
; straight into the arena proc lends with LOADIMG.
;
;   3 OPEN    data = path, length = its length, mode 0 read / 1 write / 2 append -> id
;   1 READ    handle = id, length -> bytes (0 at the end of the file)
;   2 WRITE   handle = id, length, data -> bytes (files written are kept in
;             a 128 KiB region and saved when the last reference closes)
;   4 CLOSE   handle = id -> 0
;  10 DIR     data = a tag path (none or "/": every file), handle = matching
;             files to skip -> files; data: 32-byte records {name[24], u64
;             size} (126 at most: with 126, ask again skipping those); mode
;             word = the facets (a tag set: other tags the matching files
;             carry); -4 no such tag
;  11 UNLINK  data = path -> 0 / -4
;  12 TAG     data = path, a zero byte, a tag name -> 0 / -4 / -6 (64 tags) / -1
;  13 UNTAG   data = path, a zero byte, a tag name -> 0 / -4
;  14 TAGS    data = a path (none: every tag) -> tags; data: 32-byte records
;             {name[16], u64 files carrying it, u64 tag number}: every tag,
;             or the tags of the file the path names
;  15 RENAME  data = path, a zero byte, a new path -> 0 / -4 / -6 / -1: the
;             file takes the new path's name and gains its tags (created if
;             new); it keeps its tags, blocks and directory entry. Another
;             file of the new name is deleted (as UNLINK)
;  20 CWD     mode 0 get: -> length; data: the current tag path ("/" at the
;             root). mode 1 set: data = a path (none: "/"; relative to the
;             current one; "..") -> the new one, as get / -4 (no such tag, or
;             no file in that view) / -1 (longer than CWDMAX) / -6 (table
;             full). mode 2 (from proc only): data = u64 parent pid, u64 child
;             pid: the child starts in the parent's path -> 0
;  27 STAT    data = path -> size / -4
;  28 LOADIMG data = path, handle = most bytes, mode = arena offset; the arena
;             as attachment (c7) -> size / -4 / -1; the arena goes back
;  32 STATFS  -> 3; data: u64 total blocks, used blocks, files
;  33 READBLK handle = block -> 512; data: the block
;  34 READALL handle = id (read), mode = arena offset, length = most bytes; the
;             arena as attachment -> size (the whole file is copied in)
;  35 WRITEALL handle = id (write), mode = arena offset, length = bytes; the
;             arena as attachment -> bytes (appended to the file)
;  36 DUPS / 37 CLEANUP / 38 CANCEL from proc (see srv.s)
;
; Capability registers: c0 the rest of the arena, c1 the device window,
; c2 the device endpoint, c5 the I/O buffer (512 KiB), c6 the request, c7
; its attachment.

IOSZ    = 0x80000                       ; the I/O buffer: arena [0x40000, 0xC0000)
SCR     = 0                             ; I/O buffer: scratch for reads (64 KiB)
REG0    = 0x10000                       ; three 128 KiB regions for files being written
REGSZ   = 0x20000                       ; ...
NREG    = 3                             ; ...
META    = 0x70000                       ; the directory, the header and the tag table:
M_DIR   = META                          ;   the directory (DIRMAX entries: 32 KiB)
M_HDR   = META + 0x8000                 ;   the header, staged for writing
M_TAG   = META + 0x8200                 ;   the tag table: names, then a tag set per entry
NOPEN   = 16                            ; open files
O_USED  = 0                             ; open record (64 bytes): 0 free, 1 read, 2 write
O_SIZE  = 8                             ; size
O_POS   = 16                            ; read position
O_LBA   = 24                            ; first block (read)
O_REG   = 32                            ; region (write)
O_NLEN  = 40                            ; name length (write)
O_NAME  = 48                            ; its name (24 bytes)
O_TAGS  = 72                            ; tags it gets when saved (write)
O_SIZEOF = 80                           ; bytes per open record
DIRMAX  = 1024                          ; directory entries at most
WIN     = 128                           ; entries in the D-LS at a time
NTAGS   = 64                            ; tags
TAGLEN  = 16                            ; bytes of a tag name
PATHMAX = 120                           ; longest path in a request
CWDMAX  = 64                            ; longest current tag path ("/a/b")
NCWD    = 64                            ; current paths kept (as proc's NPROC)
C_PID   = 0                             ; current-path entry: pid (0 = free)
C_LEN   = 8                             ; length of its text
C_TEXT  = 16                            ; the text ("/a/-b": normalized, not "/")
C_SIZEOF = C_TEXT + CWDMAX              ; bytes per entry
PROC_PID = 1                            ; proc's pid (CWD mode 2 comes from it)
BLK_SQ  = 0x100                         ; submission port
BLK_CQ  = 0x200                         ; completion port

        .data                           ; data Local Store
        .align 8                        ; ...
hdr:    .space 512                      ; the boot header
dir:    .space WIN * 32                 ; the directory: a window of it
tagtab: .space NTAGS * TAGLEN           ; the tag table: tag names (must follow dir)
ftags:  .space WIN * 8                  ; the tag sets of the window's entries
ndir:   .dword 0                        ; directory entries on this disk
nwin:   .dword 0                        ; ... in windows
wcur:   .dword -1                       ; the window in the D-LS (-1: none yet)
tcnt:   .space NTAGS * 8                ; files carrying each tag (tcount)
rbuf:   .space PATHMAX + 8              ; a request's text as it came
pbuf:   .space PATHMAX + CWDMAX + 8     ; a path from a request, resolved
plen:   .dword 0                        ; its length
pcwdl:  .dword 0                        ; bytes at its start from the current path
cwds:   .space NCWD * C_SIZEOF          ; current tag paths: one per process not at "/"
pmask:  .dword 0                        ; the tags its components before the last name
nmask:  .dword 0                        ; the tags its "-tag" components exclude
opens:  .space NOPEN * O_SIZEOF         ; open files
regused: .space NREG * 8                ; regions in use
cmd:    .space 32                       ; a block-device command
cqe:    .space 16                       ; its completion
ident:  .space 64                       ; the device's identify data
nm:     .space 32                       ; a name from a request
nmlen:  .dword 0                        ; its length
total:  .dword 0                        ; disk blocks
iobase: .dword 0                        ; base of the I/O buffer (what we wait for)
cid:    .dword 0                        ; command counter
bounce: .space 4640                     ; staging (a read spans up to 9 blocks)
bounce2: .space 4096                    ; request data
s_ndev: .ascii "dev"                    ; ...

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        call  sys_init                  ; ...
        li    a0, 2                     ; dev (c2): the disk
        li    a1, 30                    ; GETDISK
        li    a2, 0                     ; ...
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        call  sys_msg                   ; c6 = window, c7 = endpoint
        cclear c1                       ; proc's endpoint is not needed
        cmov  c1, c6                    ; c1 = the device window
        cclear c2                       ; ...
        cmov  c2, c7                    ; c2 = the device endpoint
        cclear c5                       ; our message buffer is not needed any more
        li    t0, 0x40000               ; the I/O buffer: the top of our memory
        csplit c5, c0, t0               ; c0 = [0, 0x40000), c5 = [0x40000, 0xC0000)
        cbase t0, c5                    ; its base: the device gives it back by it
        la    t1, iobase                ; ...
        sd    t0, 0(t1)                 ; ...
        la    t0, ident                 ; capacity, from the identify data
        li    t1, 64                    ; ...
        tget  tg1, t0, c1, zero, t1     ; ...
        twait 1 << 1                    ; ...
        ld    t1, 8(t0)                 ; ...
        la    t2, total                 ; ...
        sd    t1, 0(t2)                 ; ...
        call  load_meta                 ; header and directory
        la    a0, loop                  ; a fault on a dead request returns to the loop
        call  srv_guard                 ; ...
loop:
        li    a0, 0                     ; no device tags
        li    a1, -1                    ; no timeout
        call  srv_recv                  ; ...
        bltz  a0, loop                  ; ...
        la    t0, srv_hdr               ; dispatch
        ld    t1, 0(t0)                 ; ...
        li    t2, 1                     ; READ
        beq   t1, t2, op_read           ; ...
        li    t2, 2                     ; WRITE
        beq   t1, t2, op_write          ; ...
        li    t2, 3                     ; OPEN
        beq   t1, t2, op_open           ; ...
        li    t2, 4                     ; CLOSE
        beq   t1, t2, op_close          ; ...
        li    t2, 10                    ; DIR
        beq   t1, t2, op_dir            ; ...
        li    t2, 11                    ; UNLINK
        beq   t1, t2, op_unlink         ; ...
        li    t2, 12                    ; TAG
        beq   t1, t2, op_tag            ; ...
        li    t2, 13                    ; UNTAG
        beq   t1, t2, op_untag          ; ...
        li    t2, 14                    ; TAGS
        beq   t1, t2, op_tags           ; ...
        li    t2, 15                    ; RENAME
        beq   t1, t2, op_rename         ; ...
        li    t2, OP_CWD                ; CWD
        beq   t1, t2, op_cwd            ; ...
        li    t2, 27                    ; STAT
        beq   t1, t2, op_stat           ; ...
        li    t2, 28                    ; LOADIMG
        beq   t1, t2, op_loadimg        ; ...
        li    t2, 32                    ; STATFS
        beq   t1, t2, op_statfs         ; ...
        li    t2, 33                    ; READBLK
        beq   t1, t2, op_readblk        ; ...
        li    t2, 34                    ; READALL
        beq   t1, t2, op_readall        ; ...
        li    t2, 35                    ; WRITEALL
        beq   t1, t2, op_writeall       ; ...
        li    t2, OP_DUPS               ; DUPS
        beq   t1, t2, op_dups           ; ...
        li    t2, OP_CLEANUP            ; CLEANUP
        beq   t1, t2, op_cleanup        ; ...
        li    t2, OP_CANCEL             ; CANCEL: nothing here ever waits
        beq   t1, t2, ok                ; ...
        li    a0, -1                    ; unknown
reply:
        li    a1, 0                     ; no attachment
        call  srv_reply                 ; ...
        j     loop                      ; ...
reply_att:
        li    a1, 1                     ; the attachment (c7) goes back first
        call  srv_reply                 ; ...
        j     loop                      ; ...
ok:
        li    a0, 0                     ; ...
        j     reply                     ; ...

; =============================================================================
; The block device
; =============================================================================

; blk(a0 = op 1 read / 2 write, a1 = first block, a2 = blocks (<= 256), a3 =
; byte offset in the buffer, a4 = 5: the I/O buffer (c5) / 7: the attachment)
; -> a0 = status (0 = ok)
blk:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a4, 8(sp)                 ; ...
        la    t0, cmd                   ; build the command
        sb    a0, 0(t0)                 ; op
        csrr  t1, coreid                ; the buffer comes back to this core
        sb    t1, 1(t0)                 ; ...
        la    t2, cid                   ; command id
        ld    t1, 0(t2)                 ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, 0(t2)                 ; ...
        sh    t1, 2(t0)                 ; ...
        sw    a2, 4(t0)                 ; blocks
        sd    a1, 8(t0)                 ; first block
        sd    a3, 16(t0)                ; offset in the buffer
        sd    zero, 24(t0)              ; ...
        li    t1, BLK_SQ                ; -> the submission port
        li    t2, 32                    ; ...
        tput  tg1, t0, c1, t1, t2       ; ...
        twait 1 << 1                    ; (the command first)
        li    t0, 7                     ; which buffer?
        beq   a4, t0, blk_att           ; ...
        cbase a3, c5                    ; the I/O buffer: lend it
        csend c5, c2                    ; ...
        j     blk_wait                  ; ...
blk_att:
        cbase a3, c7                    ; the attachment: lend it
        csend c7, c2                    ; ...
blk_wait:
        li    a0, SVC_WAIT              ; wait until the device gives it back
        li    a1, -1                    ; (no doorbell: the device is not a core)
        li    a2, -1                    ; no timeout
        ld    a4, 8(sp)                 ; back into the same register
        svc                             ; ...
        la    t0, cqe                   ; the completion
        li    t1, BLK_CQ                ; ...
        li    t2, 16                    ; ...
        tget  tg1, t0, c1, t1, t2       ; ...
        twait 1 << 1                    ; ...
        lhu   a0, 2(t0)                 ; status
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; blkn(a0 = op, a1 = first block, a2 = blocks (any), a3 = offset, a4 = buffer)
; -> a0 = status: several commands of at most 256 blocks
blkn:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        sd    a2, 24(sp)                ; ...
        sd    a3, 32(sp)                ; ...
        sd    a4, 40(sp)                ; ...
bn_l:
        ld    a2, 24(sp)                ; blocks left
        li    a0, 0                     ; (none: ok)
        beqz  a2, bn_ret                ; ...
        li    t0, 256                   ; at most 256
        bleu  a2, t0, bn_n              ; ...
        mv    a2, t0                    ; ...
bn_n:
        ld    t0, 24(sp)                ; ...
        sub   t0, t0, a2                ; ...
        sd    t0, 24(sp)                ; ...
        ld    a0, 8(sp)                 ; ...
        ld    a1, 16(sp)                ; ...
        add   t0, a1, a2                ; ...
        sd    t0, 16(sp)                ; ...
        ld    a3, 32(sp)                ; ...
        slli  t0, a2, 9                 ; ...
        add   t0, a3, t0                ; ...
        sd    t0, 32(sp)                ; ...
        ld    a4, 40(sp)                ; ...
        call  blk                       ; ...
        beqz  a0, bn_l                  ; ...
bn_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; ...

; load_meta(): the header (block 0) -> D-LS; the directory and the tag table
; -> their places in the I/O buffer; the tag names and window 0 -> D-LS
load_meta:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        li    a0, 1                     ; read block 0
        li    a1, 0                     ; ...
        li    a2, 1                     ; ...
        li    a3, SCR                   ; ...
        li    a4, 5                     ; ...
        call  blk                       ; ...
        la    t0, hdr                   ; -> D-LS
        li    t1, 512                   ; ...
        li    t2, SCR                   ; ...
        tget  tg1, t0, c5, t2, t1       ; ...
        twait 1 << 1                    ; ...
        lwu   t1, 56(t0)                ; the directory's entries: 128 on an older disk,
        bnez  t1, lm_n                  ;   whole windows, DIRMAX at most
        li    t1, WIN                   ; ...
lm_n:   li    t2, DIRMAX                ; ...
        bleu  t1, t2, lm_n1             ; ...
        mv    t1, t2                    ; ...
lm_n1:  srli  t2, t1, 7                 ; ...
        la    t3, nwin                  ; ...
        sd    t2, 0(t3)                 ; ...
        slli  t1, t2, 7                 ; ...
        la    t3, ndir                  ; ...
        sd    t1, 0(t3)                 ; ...
        li    a0, 1                     ; the directory, to its place
        lwu   a1, 36(t0)                ; ...
        srli  a2, t1, 4                 ; (16 entries a block)
        li    a3, M_DIR                 ; ...
        li    a4, 5                     ; ...
        call  blk                       ; ...
        la    t0, hdr                   ; the tag table, if the disk has one
        lwu   a1, 52(t0)                ; ...
        beqz  a1, lm_win                ; none: no tags yet (kept in memory only)
        li    a0, 1                     ; read it: two blocks of names, a block of
        la    t1, ndir                  ;   tag sets for every 64 entries
        ld    a2, 0(t1)                 ; ...
        srli  a2, a2, 6                 ; ...
        addi  a2, a2, 2                 ; ...
        li    a3, M_TAG                 ; ...
        li    a4, 5                     ; ...
        call  blk                       ; ...
        la    t0, tagtab                ; the names -> D-LS
        li    t1, NTAGS * TAGLEN        ; ...
        li    t2, M_TAG                 ; ...
        tget  tg1, t0, c5, t2, t1       ; ...
        twait 1 << 1                    ; ...
lm_win: li    a0, 0                     ; the first window
        call  win                       ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; wput(): the window in the D-LS -> its place in the I/O buffer. Keeps every
; register.
wput:   addi  sp, sp, -32               ; frame
        sd    t0, 0(sp)                 ; ...
        sd    t1, 8(sp)                 ; ...
        sd    t2, 16(sp)                ; ...
        sd    t3, 24(sp)                ; ...
        la    t0, wcur                  ; which?
        ld    t3, 0(t0)                 ; ...
        bltz  t3, wp_r                  ; none
        la    t0, dir                   ; its entries
        li    t1, WIN * 32              ; ...
        slli  t2, t3, 12                ; ...
        li    t3, M_DIR                 ; ...
        add   t2, t2, t3                ; ...
        tput  tg1, t0, c5, t2, t1       ; ...
        la    t0, wcur                  ; their tag sets
        ld    t3, 0(t0)                 ; ...
        la    t0, ftags                 ; ...
        li    t1, WIN * 8               ; ...
        slli  t2, t3, 10                ; ...
        li    t3, M_TAG + NTAGS * TAGLEN ; ...
        add   t2, t2, t3                ; ...
        tput  tg1, t0, c5, t2, t1       ; ...
        twait 1 << 1                    ; ...
wp_r:   ld    t0, 0(sp)                 ; ...
        ld    t1, 8(sp)                 ; ...
        ld    t2, 16(sp)                ; ...
        ld    t3, 24(sp)                ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; win(a0 = window): entries a0 * 128 .. are in `dir`, their tag sets in
; `ftags` (the window that was there is written back first). Keeps every
; register.
win:    addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    t0, 8(sp)                 ; ...
        sd    t1, 16(sp)                ; ...
        sd    t2, 24(sp)                ; ...
        sd    t3, 32(sp)                ; ...
        la    t0, wcur                  ; there already?
        ld    t1, 0(t0)                 ; ...
        beq   t1, a0, wn_r              ; ...
        call  wput                      ; the old one back
        sd    a0, 0(t0)                 ; ...
        la    t0, dir                   ; the entries
        li    t1, WIN * 32              ; ...
        slli  t2, a0, 12                ; ...
        li    t3, M_DIR                 ; ...
        add   t2, t2, t3                ; ...
        tget  tg1, t0, c5, t2, t1       ; ...
        la    t0, ftags                 ; their tag sets
        li    t1, WIN * 8               ; ...
        slli  t2, a0, 10                ; ...
        li    t3, M_TAG + NTAGS * TAGLEN ; ...
        add   t2, t2, t3                ; ...
        tget  tg1, t0, c5, t2, t1       ; ...
        twait 1 << 1                    ; ...
wn_r:   ld    ra, 0(sp)                 ; ...
        ld    t0, 8(sp)                 ; ...
        ld    t1, 16(sp)                ; ...
        ld    t2, 24(sp)                ; ...
        ld    t3, 32(sp)                ; ...
        addi  sp, sp, 40                ; ...
        ret                             ; ...

; save_meta(): the directory, the header and the tag table back to the disk
save_meta:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        call  tag_gc                    ; tags no file carries go
        call  wput                      ; the window, to the directory's place
        la    t0, tagtab                ; the tag names, to theirs
        li    t1, NTAGS * TAGLEN        ; ...
        li    t2, M_TAG                 ; ...
        tput  tg1, t0, c5, t2, t1       ; ...
        la    t0, hdr                   ; the header
        li    t1, 512                   ; ...
        li    t2, M_HDR                 ; ...
        tput  tg1, t0, c5, t2, t1       ; ...
        twait 1 << 1                    ; ...
        li    a0, 2                     ; write the directory
        la    t0, hdr                   ; ...
        lwu   a1, 36(t0)                ; ...
        la    t1, ndir                  ; ...
        ld    a2, 0(t1)                 ; ...
        srli  a2, a2, 4                 ; ...
        li    a3, M_DIR                 ; ...
        li    a4, 5                     ; ...
        call  blk                       ; ...
        li    a0, 2                     ; and the header
        li    a1, 0                     ; ...
        li    a2, 1                     ; ...
        li    a3, M_HDR                 ; ...
        li    a4, 5                     ; ...
        call  blk                       ; ...
        la    t0, hdr                   ; and the tag table, if the disk has one
        lwu   a1, 52(t0)                ; ...
        beqz  a1, svm_ret                ; ...
        li    a0, 2                     ; ...
        la    t1, ndir                  ; ...
        ld    a2, 0(t1)                 ; ...
        srli  a2, a2, 6                 ; ...
        addi  a2, a2, 2                 ; ...
        li    a3, M_TAG                 ; ...
        li    a4, 5                     ; ...
        call  blk                       ; ...
svm_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

