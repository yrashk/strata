; fs_create() -> a0 = a new, empty file named nm (its record in rec, saved)
fs_create:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        la    a0, rec                   ; ...
        li    a1, 1024                  ; ...
        call  wzero                     ; ...
        la    t0, rec                   ; ...
        li    t1, 1                     ; a file
        sb    t1, 0(t0)                 ; ...
        ld    t1, nmlen(zero)           ; ...
        sh    t1, R_NL(t0)              ; ...
        addi  t1, t1, R_TAGS            ; ...
        sd    t1, rec_len(zero)         ; ...
        ld    t1, st_txn(zero)          ; ...
        sd    t1, R_CRE(t0)             ; ...
        sd    t1, R_MOD(t0)             ; ...
        addi  a0, t0, R_TAGS            ; ...
        la    a1, nm                    ; ...
        ld    a2, nmlen(zero)           ; ...
        call  srv_bcopy                 ; ...
        ld    t0, cnt(zero)             ; the next object id
        sd    t0, rec_oid(zero)         ; ...
        sd    t0, nval(zero)            ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, cnt(zero)             ; ...
        ld    t0, cnt+8(zero)           ; one more object
        addi  t0, t0, 1                 ; ...
        sd    t0, cnt+8(zero)           ; ...
        li    t0, 1                     ; ...
        sd    t0, cnt_d(zero)           ; ...
        li    a0, 1                     ; indexed by size and by change
        li    a1, A_SIZE                ; ...
        li    a2, 0                     ; ...
        call  idx_u64                   ; ...
        li    a0, 1                     ; ...
        li    a1, A_MOD                 ; ...
        ld    a2, st_txn(zero)          ; ...
        call  idx_u64                   ; ...
        call  rec_save                  ; ...
        ld    a0, rec_oid(zero)         ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; fs_addtags() -> a0 = 0 / -6: rec's file gains the tags in ptags it does not
; carry yet (the record is saved). Its place among the names is the caller's
; to keep: fs_unplace before its tags or name change, fs_place after
fs_addtags:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        li    s1, 0                     ; ...
fat_l:
        ld    t0, np(zero)              ; ...
        bgeu  s1, t0, fat_save          ; ...
        slli  t0, s1, 3                 ; ...
        ld    s2, ptags(t0)             ; ...
        addi  s1, s1, 1                 ; ...
        mv    a0, s2                    ; ...
        call  rec_hastag                ; ...
        bgez  a0, fat_l                 ; ...
        ld    t0, rec_len(zero)         ; room for it?
        addi  t0, t0, 8                 ; ...
        ld    t1, rec_max(zero)         ; ...
        li    a0, -6                    ; ...
        bgtu  t0, t1, fat_ret           ; ...
        mv    a0, s2                    ; ...
        call  rec_addtag                ; ...
        li    a0, 1                     ; ...
        mv    a1, s2                    ; ...
        call  idx_tag                   ; ...
        mv    a0, s2                    ; ...
        li    a1, 1                     ; ...
        call  tag_count                 ; ...
        j     fat_l                     ; ...
fat_save:
        call  rec_save                  ; ...
fat_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; fs_remove() -> a0 = 0, or -1 (a boot object): rec's file goes: its index
; entries, its tags' counts, its name, its contents, its record
fs_remove:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        la    t0, rec                   ; ...
        lbu   t1, R_FLAGS(t0)           ; ...
        andi  t1, t1, 1                 ; ...
        li    a0, -1                    ; ...
        bnez  t1, frm_ret               ; ...
        call  fs_unplace                ; its name leaves its directory
        li    a0, 0                     ; ...
        li    a1, A_SIZE                ; ...
        la    t0, rec                   ; ...
        ld    a2, R_SIZE(t0)            ; ...
        call  idx_u64                   ; ...
        li    a0, 0                     ; ...
        li    a1, A_MOD                 ; ...
        la    t0, rec                   ; ...
        ld    a2, R_MOD(t0)             ; ...
        call  idx_u64                   ; ...
        li    s1, 0                     ; ...
frm_t:
        la    t0, rec                   ; ...
        lhu   t1, R_NTAGS(t0)           ; ...
        bgeu  s1, t1, frm_n             ; ...
        slli  t1, s1, 2                 ; ...
        add   t1, t1, t0                ; ...
        lwu   a1, R_TAGS(t1)            ; ...
        li    a0, 0                     ; ...
        call  idx_tag                   ; ...
        la    t0, rec                   ; ...
        slli  t1, s1, 2                 ; ...
        add   t1, t1, t0                ; ...
        lwu   a0, R_TAGS(t1)            ; ...
        li    a1, -1                    ; ...
        call  tag_count                 ; ...
        addi  s1, s1, 1                 ; ...
        j     frm_t                     ; ...
frm_n:
        call  attrs_unindex             ; ...
        ld    a0, rec_oid(zero)         ; ...
        call  bswap                     ; ...
        sd    a0, okey(zero)            ; ...
        ld    a0, x_data(zero)          ; ...
        la    a1, okey                  ; ...
        li    a2, 8                     ; ...
        call  st_bdel                   ; ...
        ld    a0, x_obj(zero)           ; ...
        la    a1, okey                  ; ...
        li    a2, 8                     ; ...
        call  st_del                    ; ...
        ld    t0, cnt+8(zero)           ; one object less
        addi  t0, t0, -1                ; ...
        sd    t0, cnt+8(zero)           ; ...
        li    t0, 1                     ; ...
        sd    t0, cnt_d(zero)           ; ...
        li    a0, 0                     ; ...
frm_ret:
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; fs_resize(a0 = size): rec's file has that size, changed by this commit (the
; index follows; the record is saved)
fs_resize:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        mv    s1, a0                    ; ...
        li    a0, 0                     ; ...
        li    a1, A_SIZE                ; ...
        la    t0, rec                   ; ...
        ld    a2, R_SIZE(t0)            ; ...
        call  idx_u64                   ; ...
        li    a0, 0                     ; ...
        li    a1, A_MOD                 ; ...
        la    t0, rec                   ; ...
        ld    a2, R_MOD(t0)             ; ...
        call  idx_u64                   ; ...
        la    t0, rec                   ; ...
        sd    s1, R_SIZE(t0)            ; ...
        ld    t1, st_txn(zero)          ; ...
        sd    t1, R_MOD(t0)             ; ...
        li    a0, 1                     ; ...
        li    a1, A_SIZE                ; ...
        mv    a2, s1                    ; ...
        call  idx_u64                   ; ...
        li    a0, 1                     ; ...
        li    a1, A_MOD                 ; ...
        ld    a2, st_txn(zero)          ; ...
        call  idx_u64                   ; ...
        call  rec_save                  ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

