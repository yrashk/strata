; orec(a0 = id) -> a0 = its open record, or 0 if not open
orec:
        addi  a0, a0, -1                ; ids are 1..NOPEN
        li    t0, NOPEN                 ; ...
        bgeu  a0, t0, or_no             ; ...
        slli  a0, a0, 5                 ; ...
        la    t0, opens                 ; ...
        add   a0, a0, t0                ; ...
        ld    t0, O_USED(a0)            ; ...
        beqz  t0, or_no                 ; ...
        ret                             ; ...
or_no:
        li    a0, 0                     ; ...
        ret                             ; ...

; wkey(a0 = blob id): "w" and the id -> rkey (16 bytes): the mark of a blob
; that is being written and is no file's contents yet
wkey:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        call  bswap                     ; ...
        sd    a0, rkey+8(zero)          ; ...
        li    t0, 'w'                   ; ...
        sd    t0, rkey(zero)            ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; finish(a0 = id): its last reference closed. A file that was written gets
; its new contents and size, and the change is committed.
finish:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        call  orec                      ; ...
        beqz  a0, fn_ret                ; ...
        mv    s1, a0                    ; ...
        ld    s2, O_USED(s1)            ; ...
        sd    zero, O_USED(s1)          ; the record is free
        li    t0, 2                     ; ...
        beq   s2, t0, fn_new            ; ...
        li    t0, 3                     ; ...
        beq   s2, t0, fn_size           ; ...
        j     fn_ret                    ; (read, or lost)
fn_new:
        ld    a0, O_DOID(s1)            ; the blob written: no longer marked
        call  wkey                      ; ...
        ld    a0, x_dict(zero)          ; ...
        la    a1, rkey                  ; ...
        li    a2, 16                    ; ...
        call  st_del                    ; ...
        ld    a0, O_DOID(s1)            ; ...
        call  bswap                     ; ...
        sd    a0, dokey(zero)           ; ...
        ld    a0, O_OID(s1)             ; the file still there?
        call  rec_load                  ; ...
        bgez  a0, fn_swap               ; ...
        ld    a0, x_data(zero)          ; no: what was written goes
        la    a1, dokey                 ; ...
        li    a2, 8                     ; ...
        call  st_bdel                   ; ...
        j     fn_commit                 ; ...
fn_swap:
        ld    a0, x_data(zero)          ; its old contents go
        la    a1, okey                  ; ...
        li    a2, 8                     ; ...
        call  st_bdel                   ; ...
        ld    a0, x_data(zero)          ; the blob's value moves under the file's id
        la    a1, dokey                 ; ...
        li    a2, 8                     ; ...
        call  st_bsize                  ; ...
        bltz  a0, fn_size               ; (nothing was written: an empty file)
        ld    a0, x_data(zero)          ; ...
        la    a1, okey                  ; ...
        li    a2, 8                     ; ...
        la    a3, bval                  ; ...
        ld    a4, bl_vl(zero)           ; ...
        ld    a5, bl_fl(zero)           ; ...
        call  st_put                    ; ...
        ld    a0, x_data(zero)          ; ...
        la    a1, dokey                 ; ...
        li    a2, 8                     ; ...
        call  st_del                    ; ...
fn_size:
        ld    a0, O_OID(s1)             ; ...
        call  rec_load                  ; ...
        bltz  a0, fn_commit             ; ...
        ld    a0, O_POS(s1)             ; ...
        call  fs_resize                 ; ...
fn_commit:
        call  fs_commit                 ; ...
fn_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; dropref(a0 = pid, a1 = id): one reference less; the last one finishes the file
dropref:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a1, 8(sp)                 ; ...
        call  ref_del                   ; ...
        beqz  a0, dr_ret                ; it held none
        ld    a0, 8(sp)                 ; any left?
        call  ref_count                 ; ...
        bnez  a0, dr_ret                ; ...
        ld    a0, 8(sp)                 ; no: finish it
        call  finish                    ; ...
dr_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

