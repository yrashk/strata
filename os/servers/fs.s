CWDMAX  = 120                           ; longest current tag path ("/a/b")
NCWD    = 64                            ; current paths kept (as proc's NPROC)
NAMEMAX = 255                           ; longest name of a file or a tag
NQT     = 16                            ; tags a path may name (and as many it may exclude)
PROC_PID = 1                            ; proc's pid (CWD mode 2 comes from it)
BLK_SQ  = 0x100                         ; submission port
BLK_CQ  = 0x200                         ; completion port
A_TAG   = 1                             ; attribute ids: a tag,
A_SIZE  = 2                             ;   the size,
A_MOD   = 3                             ;   the last change,
A_BOOT  = 4                             ;   a boot object
R_FLAGS = 1                             ; a record: flags (1 boot),
R_NTAGS = 2                             ;   tags,
R_NATTR = 4                             ;   attributes,
R_NL    = 6                             ;   the name's length,
R_SIZE  = 8                             ;   the size,
R_CRE   = 16                            ;   created,
R_MOD   = 24                            ;   changed,
R_TAGS  = 32                            ;   the tag ids (u32 each)

