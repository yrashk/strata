; get_raw(): the request's data (length = header word 16) -> rbuf; a0 = its
; length, or -1 if it is longer than PATHMAX
get_raw:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        la    t0, srv_hdr               ; ...
        ld    t1, 16(t0)                ; length
        li    a0, -1                    ; too long
        li    t2, PATHMAX               ; ...
        bgtu  t1, t2, grw_ret           ; ...
        sd    t1, 8(sp)                 ; ...
        la    a0, rbuf                  ; (srv_get does nothing for 0 bytes)
        mv    a1, t1                    ; ...
        call  srv_get                   ; ...
        ld    a0, 8(sp)                 ; the length
grw_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; get_path(): the request's data as a path, resolved -> pbuf, plen; a0 = 0,
; or -1 if it is longer than PATHMAX
get_path:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        call  get_raw                   ; a0 = its length
        bltz  a0, gp_ret                ; ...
        mv    a1, a0                    ; ...
        la    a0, rbuf                  ; ...
        call  setpath                   ; ...
        li    a0, 0                     ; ...
gp_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; get_two(): the request's data is a path, a zero byte and a second text ->
; pbuf, plen = the path, resolved; a0 = the second text's address (in rbuf),
; a1 = its length; a0 = -1 if there is no zero byte (or the data is too long)
get_two:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        call  get_raw                   ; a0 = the length
        bltz  a0, g2_ret                ; ...
        mv    t2, a0                    ; t2 = the length
        la    t0, rbuf                  ; find the zero byte
        li    t3, 0                     ; ...
g2_z:
        li    a0, -1                    ; none: a bad request
        bgeu  t3, t2, g2_ret            ; ...
        add   t4, t0, t3                ; ...
        lbu   t5, 0(t4)                 ; ...
        beqz  t5, g2_split              ; ...
        addi  t3, t3, 1                 ; ...
        j     g2_z                      ; ...
g2_split:
        addi  t5, t4, 1                 ; the second text follows it
        sd    t5, 8(sp)                 ; ...
        sub   t5, t2, t3                ; ...
        addi  t5, t5, -1                ; ...
        sd    t5, 16(sp)                ; ...
        mv    a0, t0                    ; the path is what comes before it
        mv    a1, t3                    ; ...
        call  setpath                   ; ...
        ld    a0, 8(sp)                 ; ...
        ld    a1, 16(sp)                ; ...
g2_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...


; setpath(a0 = text, a1 = length (<= PATHMAX)): the path -> pbuf, plen,
; resolved: a relative one (not starting with "/"; DIR's empty one too) gets
; the requester's current path and a "/" in front (pcwdl = the bytes that
; came from it), then pnorm. s registers are kept.
setpath:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        sd    zero, 24(sp)              ; 24(sp) = the output so far
        sd    zero, pcwdl(zero)         ; nothing from the current path yet
        beqz  a1, stp_empty             ; an empty path
        lbu   t0, 0(a0)                 ; absolute?
        li    t1, '/'                   ; ...
        beq   t0, t1, stp_text          ; yes: as it is
        j     stp_rel                   ; ...
stp_empty:
        la    t0, srv_hdr               ; only DIR's empty path is the current one
        ld    t0, 0(t0)                 ; ...
        li    t1, OP_DIR                ; ...
        bne   t0, t1, stp_text          ; ...
stp_rel:
        call  srv_pid                   ; the requester's current path
        call  cwd_find                  ; ...
        bltz  a0, stp_sl                ; none: "/"
        call  cwd_load                  ; ...
        ld    a2, cwdt(zero)            ; its text first
        sd    a2, 24(sp)                ; ...
        la    a1, cwdt + 8              ; ...
        la    a0, pbuf                  ; ...
        call  srv_bcopy                 ; ...
        ld    t0, 24(sp)                ; (with the "/" after it)
        addi  t0, t0, 1                 ; ...
        sd    t0, pcwdl(zero)           ; ...
stp_sl:
        la    t0, pbuf                  ; then a "/"
        ld    t1, 24(sp)                ; ...
        add   t0, t0, t1                ; ...
        li    t2, '/'                   ; ...
        sb    t2, 0(t0)                 ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, 24(sp)                ; ...
stp_text:
        la    a0, pbuf                  ; the text after it
        ld    t1, 24(sp)                ; ...
        add   a0, a0, t1                ; ...
        ld    a1, 8(sp)                 ; ...
        ld    a2, 16(sp)                ; ...
        add   t1, t1, a2                ; plen = all of it
        sd    t1, plen(zero)            ; ...
        call  srv_bcopy                 ; ...
        call  pnorm                     ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; pnorm(): pbuf, plen (empty, or starting with "/") normalized in place: one
; "/" before each component, "." components gone, ".." takes the one before
; it away (at "/" it stays there); the root is empty. pcwdl becomes what is
; left of the part that came from the current path. s registers are kept.
pnorm:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; s1 = input cursor
        sd    s2, 16(sp)                ; s2 = output length
        sd    s3, 24(sp)                ; s3 = where the current path's part ends
        la    t0, pcwdl                 ; ...
        ld    s3, 0(t0)                 ; ...
        li    s1, 0                     ; ...
        li    s2, 0                     ; ...
pn_l:
        mv    a0, s1                    ; the next component
        call  comp                      ; a0 = address, a1 = length, a2 = after it
        beqz  a1, pn_done               ; none left
        mv    s1, a2                    ; ...
        lbu   t1, 0(a0)                 ; "." or ".."?
        li    t2, '.'                   ; ...
        bne   t1, t2, pn_add            ; ...
        li    t0, 1                     ; ".": nothing
        beq   a1, t0, pn_pre            ; ...
        li    t0, 2                     ; ...
        bne   a1, t0, pn_add            ; ...
        lbu   t1, 1(a0)                 ; ...
        bne   t1, t2, pn_add            ; ...
        la    t3, pbuf                  ; "..": back to the "/" before the last one
        li    t6, '/'                   ; ...
pn_up:
        beqz  s2, pn_pre                ; at the root
        addi  s2, s2, -1                ; ...
        add   t4, t3, s2                ; ...
        lbu   t5, 0(t4)                 ; ...
        bne   t5, t6, pn_up             ; ...
        j     pn_pre                    ; ...
pn_add:
        la    t3, pbuf                  ; "/" and the component at the output's end
        add   t4, t3, s2                ; (never after the input cursor: the
        li    t5, '/'                   ; component had a "/" before it)
        sb    t5, 0(t4)                 ; ...
        addi  s2, s2, 1                 ; ...
        add   s2, s2, a1                ; ...
        mv    a2, a1                    ; ...
        mv    a1, a0                    ; ...
        addi  a0, t4, 1                 ; ...
        call  srv_bcopy                 ; (forward: the output is behind the input)
pn_pre:
        la    t0, pcwdl                 ; the current path's part:
        bgtu  s1, s3, pn_min            ; inside it, all of the output so far
        sd    s2, 0(t0)                 ; ...
        j     pn_l                      ; ...
pn_min:
        ld    t1, 0(t0)                 ; after it, ".." may cut it shorter
        bleu  t1, s2, pn_l              ; ...
        sd    s2, 0(t0)                 ; ...
        j     pn_l                      ; ...
pn_done:
        la    t0, plen                  ; ...
        sd    s2, 0(t0)                 ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; comp(a0 = index in pbuf) -> a0 = address of the next path component, a1 =
; its length (0: none left), a2 = the index after it. "/" separates.
comp:
        la    t0, plen                  ; t1 = the end
        ld    t1, 0(t0)                 ; ...
        la    t2, pbuf                  ; t2 = the text
        li    t4, '/'                   ; the separator
cp_skip:
        bgeu  a0, t1, cp_none           ; nothing left
        add   t3, t2, a0                ; ...
        lbu   t3, 0(t3)                 ; ...
        bne   t3, t4, cp_word           ; a component starts
        addi  a0, a0, 1                 ; skip a separator
        j     cp_skip                   ; ...
cp_word:
        mv    a2, a0                    ; find its end
cp_w:
        bgeu  a2, t1, cp_end            ; the end of the path
        add   t3, t2, a2                ; ...
        lbu   t3, 0(t3)                 ; ...
        beq   t3, t4, cp_end            ; a separator
        addi  a2, a2, 1                 ; ...
        j     cp_w                      ; ...
cp_end:
        sub   a1, a2, a0                ; length
        add   a0, t2, a0                ; address
        ret                             ; ...
cp_none:
        mv    a2, a0                    ; ...
        li    a1, 0                     ; no component
        ret                             ; ...

; qt_add(a0 = tag id, a1 = the list (its count before it)): one more tag in
; ptags or xtags -> a0 = 0, or -1 when the list is full
qt_add:
        ld    t0, 0(a1)                 ; ...
        li    t1, NQT                   ; ...
        bgeu  t0, t1, qa_full           ; ...
        slli  t1, t0, 3                 ; ...
        add   t1, t1, a1                ; ...
        sd    a0, 8(t1)                 ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, 0(a1)                 ; ...
        li    a0, 0                     ; ...
        ret                             ; ...
qa_full:
        li    a0, -1                    ; ...
        ret                             ; ...

; parse_file(a0 = 1: create missing tags): pbuf/plen as a path -> nm, nmlen
; (the last component; nmlen = 0 for an empty path), ptags (the tags named
; before it) and xtags (the tags its "-tag" components exclude) -> a0 = 0,
; -1 bad name (or an exclusion when creating), -4 no such tag, -6 no room
parse_file:
        addi  sp, sp, -56               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        mv    s4, a0                    ; s4 = create?
        sd    zero, np(zero)            ; no tags yet
        sd    zero, nx(zero)            ; no exclusions yet
        sd    zero, nmlen(zero)         ; no name yet
        li    s1, 0                     ; s1 = cursor
        li    s2, 0                     ; s2, s3 = the component before (none)
        li    s3, 0                     ; ...
pf_l:
        mv    a0, s1                    ; the next component
        call  comp                      ; ...
        beqz  a1, pf_last               ; none: the one before is the name
        mv    s1, a2                    ; ...
        sd    a0, 40(sp)                ; keep it
        sd    a1, 48(sp)                ; ...
        beqz  s3, pf_keep               ; the first one: nothing before it
        lbu   t0, 0(s2)                 ; the one before is a tag: excluded?
        li    t1, '-'                   ; ...
        beq   t0, t1, pf_excl           ; ...
        mv    a0, s2                    ; no: the file must carry it
        mv    a1, s3                    ; ...
        mv    a2, s4                    ; ...
        call  tag_ref                   ; a0 = its id or < 0
        bltz  a0, pf_ret                ; ...
        la    a1, np                    ; ...
        call  qt_add                    ; ...
        bltz  a0, pf_ret                ; ...
        j     pf_keep                   ; ...
pf_excl:
        li    a0, -1                    ; not a bare "-"
        li    t0, 1                     ; ...
        beq   s3, t0, pf_ret            ; ...
        beqz  s4, pf_x                  ; when creating: none of the request's own
        la    t0, pbuf                  ; (one of the current path's is dropped:
        ld    t1, pcwdl(zero)           ; the new file gets its tags)
        add   t0, t0, t1                ; ...
        bgeu  s2, t0, pf_ret            ; ...
        j     pf_keep                   ; ...
pf_x:
        addi  a0, s2, 1                 ; the tag after the "-"
        addi  a1, s3, -1                ; ...
        call  tag_find                  ; a0 = its id, or -1
        bltz  a0, pf_keep               ; none: it excludes nothing
        la    a1, nx                    ; ...
        call  qt_add                    ; ...
        bltz  a0, pf_ret                ; ...
pf_keep:
        ld    s2, 40(sp)                ; this one is now the one before
        ld    s3, 48(sp)                ; ...
        j     pf_l                      ; ...
pf_last:
        li    a0, 0                     ; an empty path: no name
        beqz  s3, pf_ret                ; ...
        li    a0, -1                    ; a name is 1..NAMEMAX bytes
        li    t0, NAMEMAX               ; ...
        bgtu  s3, t0, pf_ret            ; ...
        sd    s3, nmlen(zero)           ; -> nm, nmlen
        la    a0, nm                    ; ...
        mv    a1, s2                    ; ...
        mv    a2, s3                    ; ...
        call  srv_bcopy                 ; ...
        li    a0, 0                     ; ...
pf_ret:
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 56                ; ...
        ret                             ; ...

; get_file(a0 = create tags): the request's path -> nm, nmlen, ptags, xtags;
; a0 as parse_file (nmlen may be 0)
get_file:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        call  get_path                  ; ...
        bltz  a0, gf_ret                ; ...
        ld    a0, 8(sp)                 ; ...
        call  parse_file                ; ...
gf_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; get_named(a0 = create tags): get_file, and the path must name a file -> a0 = 0 / < 0
get_named:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        call  get_file                  ; ...
        bltz  a0, gnm_ret               ; ...
        ld    t0, nmlen(zero)           ; a name?
        snez  t0, t0                    ; a0 = 0 if so, -1 if not
        addi  a0, t0, -1                ; ...
gnm_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; find() -> a0 = the object named nm, or 0
find:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        ld    a0, x_name(zero)          ; ...
        la    a1, nm                    ; ...
        ld    a2, nmlen(zero)           ; ...
        la    a3, nval                  ; ...
        call  st_get                    ; ...
        mv    t0, a0                    ; ...
        li    a0, 0                     ; ...
        bltz  t0, fnd_ret               ; ...
        ld    a0, nval(zero)            ; ...
fnd_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; q_match() -> a0 = 1 if rec carries every tag in ptags and none in xtags
q_match:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        li    s1, 0                     ; ...
qm_p:
        ld    t0, np(zero)              ; ...
        bgeu  s1, t0, qm_x              ; ...
        slli  t0, s1, 3                 ; ...
        ld    a0, ptags(t0)             ; ...
        call  rec_hastag                ; ...
        bltz  a0, qm_no                 ; ...
        addi  s1, s1, 1                 ; ...
        j     qm_p                      ; ...
qm_x:
        li    s1, 0                     ; ...
qm_xl:
        ld    t0, nx(zero)              ; ...
        bgeu  s1, t0, qm_yes            ; ...
        slli  t0, s1, 3                 ; ...
        ld    a0, xtags(t0)             ; ...
        call  rec_hastag                ; ...
        bgez  a0, qm_no                 ; ...
        addi  s1, s1, 1                 ; ...
        j     qm_xl                     ; ...
qm_yes:
        li    a0, 1                     ; ...
        j     qm_ret                    ; ...
qm_no:
        li    a0, 0                     ; ...
qm_ret:
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; lookup() -> a0 = the object named nm if it carries every tag in ptags and
; none in xtags (its record is then in rec), or 0
lookup:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        call  find                      ; ...
        beqz  a0, lk_ret                ; ...
        call  rec_load                  ; ...
        bltz  a0, lk_no                 ; ...
        call  q_match                   ; ...
        beqz  a0, lk_ret                ; ...
        ld    a0, rec_oid(zero)         ; ...
        j     lk_ret                    ; ...
lk_no:
        li    a0, 0                     ; ...
lk_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; q_next() -> a0 = the next object after q_cur that matches ptags and xtags
; (its record in rec; q_cur moves to it), or 0: in object order, through the
; first tag's index entries when the path names a tag, else through every
; record
q_next:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
qn_l:
        ld    t0, np(zero)              ; ...
        beqz  t0, qn_all                ; ...
        la    t0, ikey                  ; the entries of the first tag, from the object on
        li    t1, A_TAG                 ; ...
        sb    zero, 0(t0)               ; ...
        sb    zero, 1(t0)               ; ...
        sb    zero, 2(t0)               ; ...
        sb    t1, 3(t0)                 ; ...
        ld    t1, ptags(zero)           ; ...
        srli  t2, t1, 24                ; ...
        sb    t2, 4(t0)                 ; ...
        srli  t2, t1, 16                ; ...
        sb    t2, 5(t0)                 ; ...
        srli  t2, t1, 8                 ; ...
        sb    t2, 6(t0)                 ; ...
        sb    t1, 7(t0)                 ; ...
        ld    a0, q_cur(zero)           ; ...
        call  bswap                     ; ...
        sd    a0, ikey+8(zero)          ; ...
        ld    a0, x_attr(zero)          ; ...
        la    a1, ikey                  ; ...
        li    a2, 16                    ; ...
        li    a3, ST_GT                 ; ...
        la    a4, ikey2                 ; ...
        li    a5, 0                     ; ...
        call  st_seek                   ; ...
        beqz  a0, qn_ret                ; ...
        ld    t0, sk_kl(zero)           ; still that tag's?
        li    t1, 16                    ; ...
        li    a0, 0                     ; ...
        bne   t0, t1, qn_ret            ; ...
        ld    t0, ikey2(zero)           ; ...
        ld    t1, ikey(zero)            ; ...
        bne   t0, t1, qn_ret            ; ...
        ld    a0, ikey2+8(zero)         ; ...
        call  bswap                     ; ...
        sd    a0, q_cur(zero)           ; ...
        call  rec_load                  ; ...
        bltz  a0, qn_l                  ; ...
        j     qn_m                      ; ...
qn_all:
        ld    a0, q_cur(zero)           ; every record, from the object on
        call  bswap                     ; ...
        sd    a0, okey(zero)            ; ...
        ld    a0, x_obj(zero)           ; ...
        la    a1, okey                  ; ...
        li    a2, 8                     ; ...
        li    a3, ST_GT                 ; ...
        la    a4, okey                  ; ...
        la    a5, rec                   ; ...
        call  st_seek                   ; ...
        beqz  a0, qn_ret                ; ...
        ld    t0, sk_vl(zero)           ; ...
        sd    t0, rec_len(zero)         ; ...
        ld    a0, okey(zero)            ; ...
        call  bswap                     ; ...
        sd    a0, q_cur(zero)           ; ...
        sd    a0, rec_oid(zero)         ; ...
qn_m:
        call  q_match                   ; ...
        beqz  a0, qn_l                  ; ...
        ld    a0, rec_oid(zero)         ; ...
qn_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

