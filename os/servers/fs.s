pcwdl:  .dword 0                        ; bytes at its start from the current path
rbuf:   .space PATHMAX + 8              ; a request's text as it came
pbuf:   .space PATHMAX + CWDMAX + 16    ; a path from a request, resolved
cwdp:   .space NCWD * 8                 ; current tag paths: the process of each entry (0 = free)
cwdt:   .space 128                      ; one entry's text: its length, the text
