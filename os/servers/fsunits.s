; =============================================================================
; fsunits.s: the file server's code units (included by fs.s)
; =============================================================================
;
; The file server's code does not fit the 32 KiB of a program's I-LS. What
; is used seldom (listings, attributes, moving files ...) is here, in the image's .far section: the kernel copies
; that into the server's memory (c0) at its own offset, and the dispatcher
; pages a unit into the I-LS when it is called (doc/strataos.md, "Code
; units"): `xcall` by the unit's far address misses, the dispatcher copies
; the unit into a slot of the code cache (the I-LS after the resident code,
; in slots of USLOT bytes; fs.s sets xslot) and maps it.
;
; The rules of a unit (tools/check-fsunits.py checks the first on the image):
;   - a unit is USLOT bytes at most, at a multiple of USLOT in .far (the
;     `.org` after each unit fails to assemble if it is longer);
;   - it runs in whatever slot it was paged into: a pc-relative jump, branch
;     or call may only go to a label of the same unit. Resident code is
;     called by its address (la ra, f / jalr ra, ra, 0) and jumped to by its
;     address (la t6, l / jalr zero, t6, 0: t6 holds nothing at a unit's
;     exits); a conditional branch out goes through such a jump at the
;     unit's end (uX_label);
;   - `la` of a label in a unit gives its far address, not where it runs:
;     only for xcall;
;   - data is in the D-LS as everywhere (absolute addresses);
;   - one unit is at work at a time: resident code that a unit calls never
;     enters another unit (it could take the caller's slot), and a unit does
;     not enter another. So the requests' handlers are units, and what they
;     share is resident;
;   - a unit entered by a jump (xcall zero: the handlers of fs.s's dispatch)
;     leaves by jumping to resident code (reply, ok, bad ...); one that is
;     called (xcall ra) returns with xret ra.
; A unit's entry in the resident code is three instructions: la t5, entry /
; xcall zero, c0, t5.

USLOT   = 2048                          ; a unit's most bytes: a slot of the code cache
UBASE   = 0                             ; where the units are in the server's memory (c0)

        .far                            ; the image's far section
        .org  UBASE                     ; ...

; ---- uq: listings: QUERY, TAGS2 (see fsops.s) --------------------------------------------------
u_q:
; QUERY: a listing. data = a tag path (its last component
; may name one file), handle = the cursor: the object the listing has reached
; (0 at first) -> files; in the reply the handle word is the cursor to ask
; with again (0: that was all), the mode word the facets (the other tags the files answered carry),
; and the data: u64 n, then n u32 ids of the path's own tags (padded to a
; word); then per file {u16 record bytes, u16 name length, u32 tags, u64
; size, the name, the file's tag ids (u32 each)}, name and ids each padded to
; a word (a path that names one file: no tag ids). A reply holds as many
; files as fit; its length word is the data's bytes. With mode 1 no file's
; record is answered: the count is of every file, the facets of them all.
uq_query:
        li    a0, 0                     ; ...
        la    ra, get_file              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, uq_reply              ; ...
        li    s7, 0                     ; s7 = the facets
        li    s3, 0                     ; s3 = files
        la    ra, last_tag              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, uq_reply              ; (more terms or tags than a path may hold)
        mv    s4, a0                    ; s4 = 1: the path names one file
        la    s5, sys_buf               ; s5 = output: the path's own tags first
        ld    t0, np(zero)              ; ...
        sd    t0, 0(s5)                 ; ...
        addi  s5, s5, 8                 ; ...
        li    t1, 0                     ; ...
oq_p:
        bgeu  t1, t0, oq_pd             ; ...
        slli  t2, t1, 3                 ; ...
        ld    t2, ptags(t2)             ; ...
        sw    t2, 0(s5)                 ; ...
        sw    zero, 4(s5)               ; ...
        addi  s5, s5, 4                 ; ...
        addi  t1, t1, 1                 ; ...
        j     oq_p                      ; ...
oq_pd:
        addi  s5, s5, 7                 ; ...
        srli  s5, s5, 3                 ; ...
        slli  s5, s5, 3                 ; ...
        la    t0, srv_hdr               ; the cursor
        ld    t1, 8(t0)                 ; ...
        sd    t1, q_cur(zero)           ; ...
        ld    t1, 24(t0)                ; mode bit 0: no records, only the count of every
        andi  t2, t1, 1                 ; file and the facets; bit 1: every file, wherever
        sd    t2, q_fonly(zero)         ; it is (not only the root's, with no directory
        srli  t1, t1, 1                 ; in the path)
        andi  t1, t1, 1                 ; ...
        sd    t1, q_all(zero)           ; ...
        sd    zero, 8(t0)               ; (the cursor answered: none unless more follows)
        beqz  s4, oq_l                  ; ...
        la    ra, lookup                ; one file, with the tags before it
        jalr  ra, ra, 0                 ; (resident code: by its address)
        beqz  a0, uq_nofile             ; ...
        mv    s1, s5                    ; ...
        call  oq_rec                    ; ...
        sw    zero, 4(s1)               ; (one file: no facets, so no tags said)
        li    s3, 1                     ; ...
        j     oq_out                    ; ...
oq_l:
        ld    s6, q_cur(zero)           ; s6 = the last file answered
        la    ra, q_next                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        beqz  a0, oq_out                ; ...
        li    s1, 0                     ; s1 = 1: a file of a deeper directory (it has tags
        ld    t0, q_tag0(zero)          ; besides the path's): not listed, but its tags are
        bltz  t0, oq_ex                 ; the subdirectories (no such thing when every
        la    t0, rec                   ; record is asked)
        lhu   t1, R_NTAGS(t0)           ; ...
        ld    t2, np(zero)              ; ...
        beq   t1, t2, oq_ex             ; ...
        li    s1, 1                     ; ...
        sh    zero, R_NL(t0)            ; (its record goes without its name)
oq_ex:
        ld    t0, q_fonly(zero)         ; ...
        bnez  t0, oq_cnt                ; ...
        la    t0, rec                   ; room for its record?
        lhu   t1, R_NL(t0)              ; ...
        addi  t1, t1, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        lhu   t2, R_NTAGS(t0)           ; ...
        slli  t2, t2, 2                 ; ...
        addi  t2, t2, 7                 ; ...
        srli  t2, t2, 3                 ; ...
        slli  t2, t2, 3                 ; ...
        add   t1, t1, t2                ; ...
        addi  t1, t1, 16                ; ...
        add   t1, t1, s5                ; ...
        la    t2, sys_buf + SYS_MAX     ; ...
        bgtu  t1, t2, oq_more           ; ...
        mv    s2, s5                    ; ...
        call  oq_rec                    ; ...
        beqz  s1, oq_cnt                ; a deeper one's record: no name, bit 31 of its
        lwu   t0, 4(s2)                 ; count of tags set
        li    t1, 1                     ; ...
        slli  t1, t1, 31                ; ...
        or    t0, t0, t1                ; ...
        sw    t0, 4(s2)                 ; ...
oq_cnt:
        la    ra, rec_bits              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        or    s7, s7, a0                ; ...
        ld    t0, q_fonly(zero)         ; (the count: the files in the directory, and in a
        and   t0, t0, s1                ; reply with records every record)
        bnez  t0, oq_l                  ; ...
        addi  s3, s3, 1                 ; ...
        j     oq_l                      ; ...
oq_more:
        la    t0, srv_hdr               ; more follows: from the last one answered
        sd    s6, 8(t0)                 ; ...
oq_out:
        ld    t0, np(zero)              ; the root's listing: every directory is a facet
        ld    t1, nqa(zero)             ; (all bits set)
        or    t0, t0, t1                ; ...
        ld    t1, q_all(zero)           ; ...
        or    t0, t0, t1                ; ...
        or    t0, t0, s4                ; (not for a single file)
        bnez  t0, oq_fx                 ; ...
        li    s7, -1                    ; ...
oq_fx:
        li    s1, 0                     ; facets: not the path's own tags
oq_m:
        ld    t0, np(zero)              ; ...
        bgeu  s1, t0, oq_put            ; ...
        slli  t0, s1, 3                 ; ...
        ld    t1, ptags(t0)             ; ...
        addi  s1, s1, 1                 ; ...
        li    t0, 64                    ; ...
        bgeu  t1, t0, oq_m              ; ...
        li    t0, 1                     ; ...
        sll   t0, t0, t1                ; ...
        li    t2, -1                    ; ...
        xor   t0, t0, t2                ; ...
        and   s7, s7, t0                ; ...
        j     oq_m                      ; ...
oq_put:
        la    t0, srv_hdr               ; ...
        sd    s7, 24(t0)                ; ...
        la    a0, sys_buf               ; ...
        sub   a1, s5, a0                ; ...
        sd    a1, 16(t0)                ; (the length word: the data's bytes)
        la    ra, srv_put               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    a0, s3                    ; ...
        la    t6, reply                 ; ...
        jalr  zero, t6, 0               ; (resident code: by its address)

; oq_rec(): rec's file as a QUERY record at s5, which moves past it
oq_rec:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        la    t0, rec                   ; ...
        lhu   t1, R_NL(t0)              ; ...
        sd    zero, 0(s5)               ; ...
        sh    t1, 2(s5)                 ; ...
        lhu   t2, R_NTAGS(t0)           ; ...
        sw    t2, 4(s5)                 ; ...
        ld    t3, R_SIZE(t0)            ; ...
        sd    t3, 8(s5)                 ; ...
        addi  s1, s5, 16                ; the name, padded with zeros
        addi  t1, t1, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        mv    a0, s1                    ; ...
        mv    a1, t1                    ; ...
        add   s1, s1, t1                ; ...
        la    ra, wzero                 ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    ra, rec_name              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    a2, a1                    ; ...
        mv    a1, a0                    ; ...
        addi  a0, s5, 16                ; ...
        la    ra, srv_bcopy             ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    t0, rec                   ; its tag ids
        lhu   t2, R_NTAGS(t0)           ; ...
        sd    zero, 0(s1)               ; ...
oqr_t:
        beqz  t2, oqr_d                 ; ...
        lwu   t3, R_TAGS(t0)            ; ...
        sw    t3, 0(s1)                 ; ...
        sw    zero, 4(s1)               ; ...
        addi  t0, t0, 4                 ; ...
        addi  s1, s1, 4                 ; ...
        addi  t2, t2, -1                ; ...
        j     oqr_t                     ; ...
oqr_d:
        addi  s1, s1, 7                 ; ...
        srli  s1, s1, 3                 ; ...
        slli  s1, s1, 3                 ; ...
        sub   t0, s1, s5                ; the record's bytes
        sh    t0, 0(s5)                 ; ...
        mv    s5, s1                    ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; TAGS2: as TAGS, without its limits. data = a path (none: every tag; a file:
; its tags), handle = the cursor (0 at first: every tag is listed by id, a
; file's tags in its record's order) -> tags; the reply's handle word is the
; cursor to ask with again (0: that was all); data: per tag {u16 record
; bytes, u16 name length, u32 id, u64 files carrying it, the name padded to
; a word}
uq_tags2:
        li    a0, 0                     ; ...
        la    ra, get_file              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, uq_reply              ; ...
        li    s3, 0                     ; s3 = records
        la    s5, sys_buf               ; s5 = the record
        la    t0, srv_hdr               ; s1 = the cursor
        ld    s1, 8(t0)                 ; ...
        sd    zero, 8(t0)               ; ...
        ld    t0, nmlen(zero)           ; a file?
        beqz  t0, o2_all                ; ...
        la    ra, lookup                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        beqz  a0, uq_nofile             ; ...
o2_f:
        la    t0, rec                   ; ...
        lhu   t1, R_NTAGS(t0)           ; ...
        bgeu  s1, t1, o2_done           ; ...
        slli  t1, s1, 2                 ; ...
        add   t1, t1, t0                ; ...
        lwu   s4, R_TAGS(t1)            ; s4 = the tag
        mv    a0, s4                    ; ...
        la    ra, tag_name              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    s2, a0                    ; ...
        addi  s1, s1, 1                 ; ...
        bltz  s2, o2_f                  ; ...
        call  o2_rec                    ; ...
        bnez  a0, o2_f                  ; ...
        addi  s1, s1, -1                ; no room: from this one next time
        j     o2_more                   ; ...
o2_all:
        mv    a0, s1                    ; the next tag by id
        la    ra, rk_tag                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        ld    a0, x_dict(zero)          ; ...
        la    a1, rkey                  ; ...
        li    a2, 5                     ; ...
        li    a3, ST_GT                 ; ...
        la    a4, rkey                  ; ...
        la    a5, tnbuf                 ; ...
        la    ra, st_seek               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        beqz  a0, o2_done               ; ...
        la    t0, rkey                  ; ...
        lbu   t1, 0(t0)                 ; ...
        li    t2, 'T'                   ; ...
        bne   t1, t2, o2_done           ; ...
        lbu   s4, 1(t0)                 ; its id
        slli  s4, s4, 8                 ; ...
        lbu   t1, 2(t0)                 ; ...
        or    s4, s4, t1                ; ...
        slli  s4, s4, 8                 ; ...
        lbu   t1, 3(t0)                 ; ...
        or    s4, s4, t1                ; ...
        slli  s4, s4, 8                 ; ...
        lbu   t1, 4(t0)                 ; ...
        or    s4, s4, t1                ; ...
        ld    s2, sk_vl(zero)           ; ...
        call  o2_rec                    ; ...
        beqz  a0, o2_more               ; ...
        mv    s1, s4                    ; ...
        j     o2_all                    ; ...
o2_more:
        la    t0, srv_hdr               ; ...
        sd    s1, 8(t0)                 ; ...
        bnez  s1, o2_done               ; (a cursor of 0 would mean the end: a file's
        li    t1, -1                    ; first tag did not fit, which cannot be)
        sd    t1, 8(t0)                 ; ...
o2_done:
        la    a0, sys_buf               ; ...
        sub   a1, s5, a0                ; ...
        la    t0, srv_hdr               ; (the length word: the data's bytes)
        sd    a1, 16(t0)                ; ...
        la    ra, srv_put               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    a0, s3                    ; ...
        la    t6, reply                 ; ...
        jalr  zero, t6, 0               ; (resident code: by its address)

; o2_rec(): the tag s4, named in tnbuf (s2 bytes), as a record at s5 -> a0 =
; 1 (s5 and s3 move on), or 0 when the reply has no room for it
o2_rec:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        addi  t0, s2, 7                 ; ...
        srli  t0, t0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        addi  t0, t0, 16                ; ...
        add   t1, t0, s5                ; ...
        la    t2, sys_buf + SYS_MAX     ; ...
        li    a0, 0                     ; ...
        bgtu  t1, t2, o2r_ret           ; ...
        sh    t0, 0(s5)                 ; ...
        sh    s2, 2(s5)                 ; ...
        sw    s4, 4(s5)                 ; ...
        la    a0, tnbuf                 ; its count
        mv    a1, s2                    ; ...
        la    ra, dk_tag                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        ld    a0, x_dict(zero)          ; ...
        la    a1, dkey                  ; ...
        ld    a2, dk_len(zero)          ; ...
        la    a3, dval                  ; ...
        la    ra, st_get                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        ld    t0, dval+8(zero)          ; ...
        sd    t0, 8(s5)                 ; ...
        lhu   t1, 0(s5)                 ; the name, padded with zeros
        add   t1, t1, s5                ; ...
        sd    zero, -8(t1)              ; ...
        addi  a0, s5, 16                ; ...
        la    a1, tnbuf                 ; ...
        mv    a2, s2                    ; ...
        mv    s5, t1                    ; ...
        la    ra, srv_bcopy             ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        addi  s3, s3, 1                 ; ...
        li    a0, 1                     ; ...
o2r_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

uq_reply:
        la    t6, reply                ; out of the unit: resident code by its address
        jalr  zero, t6, 0               ; ...
uq_nofile:
        la    t6, nofile               ; out of the unit: resident code by its address
        jalr  zero, t6, 0               ; ...
        .org  u_q + USLOT               ; (the unit must fit its slot)

; ---- ut: TAG, UNTAG, RENAME (see fsops.s) ------------------------------------------------------
u_t:
; TAG / UNTAG: data = a path, a zero byte, tag names with a zero byte between
; them. A file's directory is the set of its tags: TAG moves it into the
; directory of its tags and these, UNTAG into the one without these, in one
; step. Refused (-1) when that directory has a file of its name; -4 no such
; file; -6 too many tags.
ut_tag:
        li    s4, 1                     ; s4 = 1 tag, 0 untag
        j     otg_go                    ; ...
ut_untag:
        li    s4, 0                     ; ...
otg_go:
        la    ra, tx_sync               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    ra, get_two               ; the path, and the tags' names
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, ut_reply              ; ...
        mv    s2, a0                    ; s2 = the names, s3 = their end
        add   s3, a0, a1                ; ...
        li    a0, 0                     ; the path's tags must exist
        la    ra, parse_file            ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, ut_reply              ; ...
        ld    t0, nmlen(zero)           ; it must name a file
        li    a0, -1                    ; ...
        beqz  t0, ut_reply              ; ...
        la    ra, lookup                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        beqz  a0, ut_nofile             ; ...
        mv    s1, a0                    ; s1 = the file
        call  own_tags                  ; where it is now: its own tags -> ptags
        bltz  a0, ut_reply              ; ...
otg_n:
        bgeu  s2, s3, otg_do            ; the next name
        mv    s5, s2                    ; ...
otg_e:
        bgeu  s2, s3, otg_t             ; ...
        lbu   t0, 0(s2)                 ; ...
        beqz  t0, otg_t                 ; ...
        addi  s2, s2, 1                 ; ...
        j     otg_e                     ; ...
otg_t:
        sub   a1, s2, s5                ; ...
        mv    a0, s5                    ; ...
        addi  s2, s2, 1                 ; ...
        beqz  a1, otg_n                 ; ...
        li    t0, 1                     ; a name "/": from no tag at all (retag)
        bne   a1, t0, otg_r             ; ...
        lbu   t0, 0(a0)                 ; ...
        li    t1, '/'                   ; ...
        bne   t0, t1, otg_r             ; ...
        sd    zero, np(zero)            ; ...
        j     otg_n                     ; ...
otg_r:
        mv    a2, s4                    ; (made when tagging)
        la    ra, tag_ref               ; a0 = its id, or < 0
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bgez  a0, otg_h                 ; ...
        beqz  s4, otg_n                 ; (a tag that is not: nothing to take away)
        j     ut_undo                   ; ...
otg_h:
        li    t0, 0                     ; in the set already?
        ld    t1, np(zero)              ; ...
otg_f:
        bgeu  t0, t1, otg_a             ; ...
        slli  t2, t0, 3                 ; ...
        ld    t3, ptags(t2)             ; ...
        beq   t3, a0, otg_y             ; ...
        addi  t0, t0, 1                 ; ...
        j     otg_f                     ; ...
otg_y:
        bnez  s4, otg_n                 ; tag: it has it
        addi  t1, t1, -1                ; untag: the last one takes its place
        sd    t1, np(zero)              ; ...
        slli  t3, t1, 3                 ; ...
        ld    t3, ptags(t3)             ; ...
        sd    t3, ptags(t2)             ; ...
        j     otg_n                     ; ...
otg_a:
        beqz  s4, otg_n                 ; untag: it does not have it
        la    a1, np                    ; ...
        la    ra, qt_add                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, ut_six                ; ...
        j     otg_n                     ; ...
otg_do:
        mv    a0, s1                    ; its name stays
        la    ra, rec_load              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    ra, rec_name              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        sd    a1, nmlen(zero)           ; ...
        mv    a2, a1                    ; ...
        mv    a1, a0                    ; ...
        la    a0, nm                    ; ...
        la    ra, srv_bcopy             ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        li    s4, 0                     ; (a file that is there is not replaced)
        j     reloc                     ; ...

; own_tags() -> a0 = 0 and ptags = the tags of rec's file, or -6 (more than a
; path may name)
own_tags:
        la    t0, rec                   ; ...
        lhu   t1, R_NTAGS(t0)           ; ...
        li    a0, -6                    ; ...
        li    t2, NQT                   ; ...
        bgtu  t1, t2, own_r             ; ...
        sd    t1, np(zero)              ; ...
        li    t2, 0                     ; ...
own_l:
        bgeu  t2, t1, own_d             ; ...
        slli  t3, t2, 2                 ; ...
        add   t3, t3, t0                ; ...
        lwu   t3, R_TAGS(t3)            ; ...
        slli  t4, t2, 3                 ; ...
        sd    t3, ptags(t4)             ; ...
        addi  t2, t2, 1                 ; ...
        j     own_l                     ; ...
own_d:
        li    a0, 0                     ; ...
own_r:
        ret                             ; ...

; RENAME: data = a path, a zero byte, a new path. A move: the file gets the
; new path's name and directory (its tags, made if new; none: the root); a
; new path that is a name alone, without "/", changes only the name and
; leaves the file where it is. A file of that name there is replaced.
ut_rename:
        la    ra, tx_sync               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    ra, get_two               ; the path, and the new one
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, ut_reply              ; ...
        mv    s2, a0                    ; s2, s3 = the new path as it was written
        mv    s3, a1                    ; ...
        li    a0, 0                     ; the old path's tags must exist
        la    ra, parse_file            ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, ut_reply              ; ...
        ld    t0, nmlen(zero)           ; it must name a file
        li    a0, -1                    ; ...
        beqz  t0, ut_reply              ; ...
        la    ra, lookup                ; s1 = the file
        jalr  ra, ra, 0                 ; (resident code: by its address)
        beqz  a0, ut_nofile             ; ...
        mv    s1, a0                    ; ...
        la    t0, rec                   ; (not a boot object)
        lbu   t0, R_FLAGS(t0)           ; ...
        andi  t0, t0, 1                 ; ...
        bnez  t0, ut_bad                ; ...
        li    s4, 1                     ; s4 = 1: the new path is a name alone (no "/")
        mv    t0, s2                    ; ...
        add   t1, s2, s3                ; ...
orn_b:
        bgeu  t0, t1, orn_bd            ; ...
        lbu   t2, 0(t0)                 ; ...
        addi  t0, t0, 1                 ; ...
        li    t3, '/'                   ; ...
        bne   t2, t3, orn_b             ; ...
        li    s4, 0                     ; ...
orn_bd:
        mv    a0, s2                    ; the new path -> pbuf, resolved (it is in rbuf, apart from pbuf)
        mv    a1, s3                    ; ...
        la    ra, setpath               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        li    a0, 1                     ; its tags are created if need be
        la    ra, parse_file            ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, ut_oo_fail            ; ...
        ld    t0, nmlen(zero)           ; it must name a file
        li    a0, -1                    ; ...
        beqz  t0, ut_oo_fail            ; ...
        beqz  s4, orn_mv                ; ...
        mv    a0, s1                    ; a name alone: the directory is the file's own
        la    ra, rec_load              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        call  own_tags                  ; ...
        bltz  a0, ut_oo_fail            ; ...
orn_mv:
        li    s4, 1                     ; (a file that is there is replaced)

; reloc: the file s1 goes to the directory ptags under the name nm; s4 = 1: a
; file that is there is replaced, 0: the move is refused
reloc:
        la    ra, find                  ; who is there?
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    s5, a0                    ; ...
        beq   s5, s1, ut_ok             ; itself: nothing to do
        beqz  s5, rlc_hold               ; ...
        beqz  s4, rlc_fail               ; ...
rlc_hold:
        li    s6, 0                     ; the directory's tags are held while files leave them (a tag no file carries goes)
rlc_h:
        ld    t0, np(zero)              ; ...
        bgeu  s6, t0, rlc_hd             ; ...
        slli  t1, s6, 3                 ; ...
        ld    a0, ptags(t1)             ; ...
        li    a1, 1                     ; ...
        la    ra, tag_count             ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        addi  s6, s6, 1                 ; ...
        j     rlc_h                      ; ...
rlc_hd:
        beqz  s5, rlc_go                 ; ...
        mv    a0, s5                    ; the file that is there goes
        la    ra, rec_load              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    ra, fs_remove             ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, rlc_fail               ; ...
rlc_go:
        mv    a0, s1                    ; the file leaves where it is,
        la    ra, rec_load              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    ra, fs_unplace            ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        li    s6, 0                     ; its tags that are not the directory's go,
rlc_t:
        la    t0, rec                   ; ...
        lhu   t1, R_NTAGS(t0)           ; ...
        bgeu  s6, t1, rlc_name           ; ...
        slli  t2, s6, 2                 ; ...
        add   t2, t2, t0                ; ...
        lwu   s2, R_TAGS(t2)            ; ...
        ld    t1, np(zero)              ; ...
        li    t2, 0                     ; ...
rlc_ti:
        bgeu  t2, t1, rlc_td             ; ...
        slli  t3, t2, 3                 ; ...
        ld    t3, ptags(t3)             ; ...
        addi  t2, t2, 1                 ; ...
        bne   t3, s2, rlc_ti             ; ...
        addi  s6, s6, 1                 ; (kept)
        j     rlc_t                      ; ...
rlc_td:
        mv    a0, s6                    ; (the last tag takes its place: s6 stays)
        la    ra, rec_deltag            ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        li    a0, 0                     ; ...
        mv    a1, s2                    ; ...
        la    ra, idx_tag               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    a0, s2                    ; ...
        li    a1, -1                    ; ...
        la    ra, tag_count             ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        j     rlc_t                      ; ...
rlc_name:
        la    ra, rec_name              ; the name in the record, in the old one's place (zeros after it)
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    t0, rec                   ; ...
        sub   s3, a0, t0                ; s3 = where the name is in the record
        ld    t0, nmlen(zero)           ; it must fit the record
        add   t0, t0, s3                ; ...
        ld    t1, rec_max(zero)         ; ...
        bgtu  t0, t1, rlc_fail           ; ...
        sd    t0, rec_len(zero)         ; ...
        la    a0, rec                   ; ...
        add   a0, a0, s3                ; ...
        li    a1, 264                   ; ...
        la    ra, wzero                 ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    a0, rec                   ; ...
        add   a0, a0, s3                ; ...
        la    a1, nm                    ; ...
        ld    a2, nmlen(zero)           ; ...
        la    ra, srv_bcopy             ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    t0, rec                   ; ...
        ld    t1, nmlen(zero)           ; ...
        sh    t1, R_NL(t0)              ; ...
        la    ra, fs_addtags            ; the directory's tags it does not have yet (and it is saved),
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, rlc_fail               ; ...
        la    ra, fs_place              ; and it is there
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, rlc_fail               ; ...
        li    s6, 0                     ; (the hold on the directory's tags ends)
rlc_u:
        ld    t0, np(zero)              ; ...
        bgeu  s6, t0, rlc_ud             ; ...
        slli  t1, s6, 3                 ; ...
        ld    a0, ptags(t1)             ; ...
        li    a1, -1                    ; ...
        la    ra, tag_count             ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        addi  s6, s6, 1                 ; ...
        j     rlc_u                      ; ...
rlc_ud:
        la    ra, fs_commit             ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    t6, ok                    ; ...
        jalr  zero, t6, 0               ; (resident code: by its address)
rlc_fail:
        la    t6, st_full               ; (things may have been changed: the commit is given up, the answer is -1)
        jalr  zero, t6, 0               ; (resident code: by its address)
ut_six:
        li    a0, -6                    ; ...
ut_undo:
        la    ra, tags_undo             ; the tags this request made go (a0 kept)
        jalr  ra, ra, 0                 ; (resident code: by its address)
ut_reply:
        la    t6, reply                ; out of the unit: resident code by its address
        jalr  zero, t6, 0               ; ...
ut_nofile:
        la    t6, nofile               ; out of the unit: resident code by its address
        jalr  zero, t6, 0               ; ...
ut_ok:
        la    t6, ok                   ; out of the unit: resident code by its address
        jalr  zero, t6, 0               ; ...
ut_oo_fail:
        la    t6, oo_fail              ; out of the unit: resident code by its address
        jalr  zero, t6, 0               ; ...
ut_bad:
        la    t6, bad                  ; out of the unit: resident code by its address
        jalr  zero, t6, 0               ; ...
        .org  u_t + USLOT               ; (the unit must fit its slot)

; ---- ua: attributes: SETATTR, GETATTR (see fsattr.s) -------------------------------------------
u_a:
; SETATTR: data = path, a zero byte, the attribute's name, a zero byte, the value
ua_setattr:
        la    ra, tx_sync               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    ra, get_two               ; the path, and "name", 0, "value"
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, ua_reply              ; ...
        mv    s2, a0                    ; s2 = the name
        mv    s5, a1                    ; ...
        li    s3, 0                     ; s3 = its length: up to the zero byte
osa_z:
        bgeu  s3, s5, ua_bad            ; ...
        add   t0, s2, s3                ; ...
        lbu   t0, 0(t0)                 ; ...
        beqz  t0, osa_v                 ; ...
        li    t1, '='                   ; (no sign of a term in a name)
        beq   t0, t1, ua_bad            ; ...
        li    t1, '<'                   ; ...
        beq   t0, t1, ua_bad            ; ...
        li    t1, '>'                   ; ...
        beq   t0, t1, ua_bad            ; ...
        li    t1, '*'                   ; ...
        beq   t0, t1, ua_bad            ; ...
        li    t1, '/'                   ; ...
        beq   t0, t1, ua_bad            ; ...
        addi  s3, s3, 1                 ; ...
        j     osa_z                     ; ...
osa_v:
        beqz  s3, ua_bad                ; ...
        li    t0, NAMEMAX               ; (attr_find makes no key for a longer one)
        bgtu  s3, t0, ua_bad            ; ...
        add   s4, s2, s3                ; s4 = the value, s5 = its length
        addi  s4, s4, 1                 ; ...
        sub   s5, s5, s3                ; ...
        addi  s5, s5, -1                ; ...
        li    t0, 255                   ; ...
        bgtu  s5, t0, ua_bad            ; ...
        li    a0, 0                     ; the file
        la    ra, parse_file            ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, ua_reply              ; ...
        ld    t0, nmlen(zero)           ; ...
        beqz  t0, ua_bad                ; ...
        la    ra, lookup                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        beqz  a0, ua_nofile             ; ...
        la    s6, s_size                ; not one of the file system's own: size,
        li    s7, 4                     ; modified, tag, boot (their names are side by side)
osa_b:
        mv    a0, s2                    ; ...
        mv    a1, s3                    ; ...
        mv    a2, s6                    ; ...
        mv    a3, s7                    ; ...
        la    ra, kcmp                  ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        beqz  a0, ua_bad                ; ...
        add   s6, s6, s7                ; ...
        la    t0, s_size + 4            ; (after size: modified, 8 bytes)
        li    s7, 8                     ; ...
        beq   s6, t0, osa_b             ; ...
        la    t0, s_size + 12           ; (then tag, 3 bytes)
        li    s7, 3                     ; ...
        beq   s6, t0, osa_b             ; ...
        la    t0, s_size + 15           ; (then boot, 4 bytes)
        li    s7, 4                     ; ...
        beq   s6, t0, osa_b             ; ...
        mv    a0, s2                    ; the attribute's id (a new one for a new name)
        mv    a1, s3                    ; ...
        la    ra, attr_find             ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    s1, a0                    ; ...
        bgez  s1, osa_id                ; ...
        beqz  s5, ua_ok                 ; (taking away what nobody has)
        lwu   s1, cnt+20(zero)          ; ...
        addi  t0, s1, 1                 ; ...
        sw    t0, cnt+20(zero)          ; ...
        li    t0, 1                     ; ...
        sd    t0, cnt_d(zero)           ; ...
        sd    s1, dval(zero)            ; (dkey is still "a", name)
        ld    a0, x_dict(zero)          ; ...
        la    a1, dkey                  ; ...
        ld    a2, dk_len(zero)          ; ...
        la    a3, dval                  ; ...
        li    a4, 8                     ; ...
        li    a5, 0                     ; ...
        la    ra, st_put                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    a0, s1                    ; id -> name
        la    ra, rk_tag                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        li    t0, 'A'                   ; ...
        sb    t0, rkey(zero)            ; ...
        ld    a0, x_dict(zero)          ; ...
        la    a1, rkey                  ; ...
        li    a2, 5                     ; ...
        mv    a3, s2                    ; ...
        mv    a4, s3                    ; ...
        li    a5, 0                     ; ...
        la    ra, st_put                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
osa_id:
        mv    a0, s4                    ; s6 = 0 a number (s7 = it) / 1 a string
        mv    a1, s5                    ; ...
        la    ra, p_num                 ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    s7, a0                    ; ...
        xori  s6, a1, 1                 ; ...
        li    s2, 0                     ; s2 = the bytes the new entry takes (none: it goes)
        beqz  s5, osa_room              ; ...
        li    s2, 16                    ; ...
        beqz  s6, osa_room              ; ...
        addi  s2, s5, 7                 ; ...
        srli  s2, s2, 3                 ; ...
        slli  s2, s2, 3                 ; ...
        addi  s2, s2, 8                 ; ...
osa_room:
        mv    a0, s1                    ; the entry it has now, and its bytes
        la    ra, rec_attr              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    s3, a0                    ; s3 = it (0: none)
        li    t1, 0                     ; ...
        beqz  s3, osa_fit               ; ...
        lbu   t1, 5(s3)                 ; ...
        addi  t1, t1, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        addi  t1, t1, 8                 ; ...
osa_fit:
        ld    t0, rec_len(zero)         ; the record with the new one in the old one's place
        sub   t0, t0, t1                ; must fit
        add   t0, t0, s2                ; ...
        ld    t2, rec_max(zero)         ; ...
        li    a0, -6                    ; ...
        bgtu  t0, t2, ua_reply          ; ...
        beqz  s3, osa_new               ; ...
        li    a0, 0                     ; the old one: out of the index, out of the record
        mv    a1, s3                    ; ...
        la    ra, idx_attr              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        lbu   t1, 5(s3)                 ; ...
        addi  t1, t1, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        addi  t1, t1, 8                 ; t1 = its bytes
        ld    t2, rec_len(zero)         ; what follows it moves down
        sub   t3, t2, t1                ; ...
        sd    t3, rec_len(zero)         ; ...
        addi  t2, t2, 7                 ; ...
        srli  t2, t2, 3                 ; ...
        slli  t2, t2, 3                 ; ...
        la    t3, rec                   ; ...
        add   t2, t2, t3                ; t2 = the record's end
        mv    t4, s3                    ; ...
osa_dn:
        add   t5, t4, t1                ; ...
        bgeu  t5, t2, osa_dz            ; ...
        ld    t6, 0(t5)                 ; ...
        sd    t6, 0(t4)                 ; ...
        addi  t4, t4, 8                 ; ...
        j     osa_dn                    ; ...
osa_dz:
        bgeu  t4, t2, osa_dd            ; (zeros where the end was)
        sd    zero, 0(t4)               ; ...
        addi  t4, t4, 8                 ; ...
        j     osa_dz                    ; ...
osa_dd:
        lhu   t0, R_NATTR(t3)           ; ...
        addi  t0, t0, -1                ; ...
        sh    t0, R_NATTR(t3)           ; ...
osa_new:
        beqz  s2, osa_save              ; no new value: done
        la    ra, rec_name              ; the new entry goes where the name starts:
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    s3, a0                    ; the name moves up
        ld    t2, rec_len(zero)         ; ...
        add   t0, t2, s2                ; ...
        sd    t0, rec_len(zero)         ; ...
        addi  t2, t2, 7                 ; ...
        srli  t2, t2, 3                 ; ...
        slli  t2, t2, 3                 ; ...
        la    t3, rec                   ; ...
        add   t2, t2, t3                ; t2 = the record's end
osa_up:
        beq   t2, s3, osa_put           ; ...
        addi  t2, t2, -8                ; ...
        ld    t6, 0(t2)                 ; ...
        add   t5, t2, s2                ; ...
        sd    t6, 0(t5)                 ; ...
        j     osa_up                    ; ...
osa_put:
        mv    a0, s3                    ; the entry: zeros, then id, type, length, value
        mv    a1, s2                    ; ...
        la    ra, wzero                 ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        sw    s1, 0(s3)                 ; ...
        sb    s6, 4(s3)                 ; ...
        bnez  s6, osa_s                 ; ...
        li    t0, 8                     ; ...
        sb    t0, 5(s3)                 ; ...
        sd    s7, 8(s3)                 ; ...
        j     osa_cnt                   ; ...
osa_s:
        sb    s5, 5(s3)                 ; ...
        addi  a0, s3, 8                 ; ...
        mv    a1, s4                    ; ...
        mv    a2, s5                    ; ...
        la    ra, srv_bcopy             ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
osa_cnt:
        la    t3, rec                   ; ...
        lhu   t0, R_NATTR(t3)           ; ...
        addi  t0, t0, 1                 ; ...
        sh    t0, R_NATTR(t3)           ; ...
        li    a0, 1                     ; ...
        mv    a1, s3                    ; ...
        la    ra, idx_attr              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
osa_save:
        la    ra, rec_save              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    ra, fs_commit             ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    t6, ok                    ; ...
        jalr  zero, t6, 0               ; (resident code: by its address)

; GETATTR: data = path -> the file's attributes
ua_getattr:
        li    a0, 0                     ; ...
        la    ra, get_named             ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, ua_reply              ; ...
        la    ra, lookup                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        beqz  a0, ua_nofile             ; ...
        la    t0, rec                   ; s1 = the entry, s2 = entries left
        lhu   s2, R_NATTR(t0)           ; ...
        lhu   t1, R_NTAGS(t0)           ; ...
        slli  t1, t1, 2                 ; ...
        addi  t1, t1, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        add   s1, t1, t0                ; ...
        addi  s1, s1, R_TAGS            ; ...
        li    s3, 0                     ; s3 = records
        la    s5, sys_buf               ; s5 = output
oga_l:
        beqz  s2, oga_done              ; ...
        lwu   a0, 0(s1)                 ; its name
        la    ra, rk_tag                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        li    t0, 'A'                   ; ...
        sb    t0, rkey(zero)            ; ...
        ld    a0, x_dict(zero)          ; ...
        la    a1, rkey                  ; ...
        li    a2, 5                     ; ...
        la    a3, tnbuf                 ; ...
        la    ra, st_get                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    s4, a0                    ; s4 = its length
        bltz  s4, oga_n                 ; ...
        addi  s6, s4, 7                 ; s6 = the name, padded
        srli  s6, s6, 3                 ; ...
        slli  s6, s6, 3                 ; ...
        lbu   s7, 5(s1)                 ; s7 = the value, padded
        addi  s7, s7, 7                 ; ...
        srli  s7, s7, 3                 ; ...
        slli  s7, s7, 3                 ; ...
        add   t0, s6, s7                ; room?
        addi  t0, t0, 8                 ; ...
        add   t1, t0, s5                ; ...
        la    t2, sys_buf + SYS_MAX     ; ...
        bgtu  t1, t2, oga_done          ; ...
        sd    zero, 0(s5)               ; ...
        sh    t0, 0(s5)                 ; ...
        sh    s4, 2(s5)                 ; ...
        lbu   t0, 4(s1)                 ; ...
        sb    t0, 4(s5)                 ; ...
        lbu   t0, 5(s1)                 ; ...
        sb    t0, 5(s5)                 ; ...
        addi  a0, s5, 8                 ; ...
        la    a1, tnbuf                 ; ...
        mv    a2, s6                    ; ...
        la    ra, wcopy                 ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        add   a0, s5, s6                ; ...
        addi  a0, a0, 8                 ; ...
        addi  a1, s1, 8                 ; ...
        mv    a2, s7                    ; ...
        la    ra, wcopy                 ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        add   s5, s5, s6                ; ...
        add   s5, s5, s7                ; ...
        addi  s5, s5, 8                 ; ...
        addi  s3, s3, 1                 ; ...
oga_n:
        lbu   t3, 5(s1)                 ; ...
        addi  t3, t3, 7                 ; ...
        srli  t3, t3, 3                 ; ...
        slli  t3, t3, 3                 ; ...
        add   s1, s1, t3                ; ...
        addi  s1, s1, 8                 ; ...
        addi  s2, s2, -1                ; ...
        j     oga_l                     ; ...
oga_done:
        la    a0, sys_buf               ; ...
        sub   a1, s5, a0                ; ...
        la    t0, srv_hdr               ; ...
        sd    a1, 16(t0)                ; ...
        la    ra, srv_put               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    a0, s3                    ; ...
        la    t6, reply                 ; ...
        jalr  zero, t6, 0               ; (resident code: by its address)
ua_reply:
        la    t6, reply                ; out of the unit: resident code by its address
        jalr  zero, t6, 0               ; ...
ua_bad:
        la    t6, bad                  ; out of the unit: resident code by its address
        jalr  zero, t6, 0               ; ...
ua_nofile:
        la    t6, nofile               ; out of the unit: resident code by its address
        jalr  zero, t6, 0               ; ...
ua_ok:
        la    t6, ok                   ; out of the unit: resident code by its address
        jalr  zero, t6, 0               ; ...
        .org  u_a + USLOT               ; (the unit must fit its slot)

; ---- uc: CWD (see fsops.s) ------------------------------------------------------------
u_c:
; CWD: the requester's current tag path (mode 0 get, 1 set, 2 inherit)
uc_cwd:
        la    t0, srv_hdr               ; mode
        ld    t1, 24(t0)                ; ...
        beqz  t1, ocw_get               ; 0: get
        li    t2, 2                     ; 2: inherit
        beq   t1, t2, ocw_inh           ; ...
        li    t2, 1                     ; 1: set
        bne   t1, t2, uc_bad            ; ...
        la    ra, get_raw               ; a0 = the length of the new path
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, uc_reply              ; ...
        beqz  a0, ocw_root              ; none: "/"
        mv    a1, a0                    ; resolved (relative to the current one)
        la    a0, rbuf                  ; ...
        la    ra, setpath               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        li    s1, 0                     ; s1 = cursor
        sd    zero, np(zero)            ; the tags of the view, and those it excludes
        sd    zero, nx(zero)            ; ...
        sd    zero, nqa(zero)           ; (no terms: none from an earlier request)
ocw_c:
        mv    a0, s1                    ; every component: a tag, or "-" and a tag
        la    ra, comp                  ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        beqz  a1, ocw_chk               ; all seen
        mv    s1, a2                    ; ...
        la    s2, np                    ; s2 = the list it joins
        lbu   t0, 0(a0)                 ; ...
        li    t1, '-'                   ; ...
        bne   t0, t1, ocw_t             ; ...
        la    s2, nx                    ; ...
        addi  a0, a0, 1                 ; ...
        addi  a1, a1, -1                ; ...
ocw_t:
        la    ra, tag_find              ; a0 = its id, or -1
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, ocw_none              ; no such tag
        mv    a1, s2                    ; ...
        la    ra, qt_add                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, uc_reply              ; ...
        j     ocw_c                     ; ...
ocw_chk:
        ld    t1, plen(zero)            ; ".." all the way: "/"
        beqz  t1, ocw_root              ; ...
        li    a0, -1                    ; too long to keep
        li    t2, CWDMAX                ; ...
        bgtu  t1, t2, uc_reply          ; ...
        sd    zero, q_cur(zero)         ; a file in that view? (no empty views)
        la    ra, q_next                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bnez  a0, ocw_set               ; ...
ocw_none:
        li    a0, -4                    ; no such tag (or nothing carries them all)
        la    t6, reply                 ; ...
        jalr  zero, t6, 0               ; (resident code: by its address)
ocw_set:
        la    ra, srv_pid               ; s1 = the requester
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    s1, a0                    ; ...
        la    ra, cwd_find              ; its entry, or a free one
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bgez  a0, ocw_have              ; ...
        li    a0, 0                     ; ...
        la    ra, cwd_find              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    t0, a0                    ; ...
        li    a0, -6                    ; none: the table is full
        bltz  t0, uc_reply              ; ...
        mv    a0, t0                    ; ...
ocw_have:
        mv    s2, a0                    ; ...
        slli  t0, s2, 3                 ; ...
        sd    s1, cwdp(t0)              ; ...
        ld    a2, plen(zero)            ; the new path
        sd    a2, cwdt(zero)            ; ...
        la    a0, cwdt + 8              ; ...
        la    a1, pbuf                  ; ...
        la    ra, srv_bcopy             ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    a0, s2                    ; ...
        la    ra, cwd_store             ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        j     ocw_get                   ; answered as a get
ocw_root:
        la    ra, srv_pid               ; "/": no entry
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    ra, cwd_drop              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
ocw_get:
        la    ra, srv_pid               ; the requester's entry
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    ra, cwd_find              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, ocw_slash             ; none: "/"
        la    ra, cwd_load              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        ld    s1, cwdt(zero)            ; its text -> the request
        la    a0, cwdt + 8              ; ...
        mv    a1, s1                    ; ...
        la    ra, srv_put               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    a0, s1                    ; its length
        la    t6, reply                 ; ...
        jalr  zero, t6, 0               ; (resident code: by its address)
ocw_slash:
        la    a0, sys_buf               ; "/"
        li    t0, '/'                   ; ...
        sd    t0, 0(a0)                 ; ...
        li    a1, 1                     ; ...
        la    ra, srv_put               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        li    a0, 1                     ; ...
        la    t6, reply                 ; ...
        jalr  zero, t6, 0               ; (resident code: by its address)
ocw_inh:
        la    ra, srv_pid               ; from proc only
        jalr  ra, ra, 0                 ; (resident code: by its address)
        li    t0, PROC_PID              ; ...
        bne   a0, t0, uc_bad            ; ...
        la    a0, sys_buf               ; parent, child
        li    a1, 16                    ; ...
        la    ra, srv_get               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    t0, sys_buf               ; ...
        ld    s1, 0(t0)                 ; s1 = the parent
        ld    s2, 8(t0)                 ; s2 = the child
        mv    a0, s2                    ; a stale entry of the child's goes
        la    ra, cwd_drop              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        beqz  s2, uc_ok                 ; (a child of pid 0: nothing)
        beqz  s1, uc_ok                 ; ...
        mv    a0, s1                    ; the parent's
        la    ra, cwd_find              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, uc_ok                 ; at "/": so is the child
        la    ra, cwd_load              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        li    a0, 0                     ; a free entry
        la    ra, cwd_find              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, uc_ok                 ; none: the child starts at "/"
        slli  t0, a0, 3                 ; a copy of the parent's, for the child
        sd    s2, cwdp(t0)              ; ...
        la    ra, cwd_store             ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    t6, ok                    ; ...
        jalr  zero, t6, 0               ; (resident code: by its address)

uc_bad:
        la    t6, bad                  ; out of the unit: resident code by its address
        jalr  zero, t6, 0               ; ...
uc_ok:
        la    t6, ok                   ; out of the unit: resident code by its address
        jalr  zero, t6, 0               ; ...
uc_reply:
        la    t6, reply                ; out of the unit: resident code by its address
        jalr  zero, t6, 0               ; ...
        .org  u_c + USLOT               ; (the unit must fit its slot)

; ---- uf: FIND, names across the whole file system ------------------------------------
u_f:
; 46 FIND: data = a text (1..255 bytes), handle = a cursor (0 at first), mode
; 0: the files whose names begin with the text; mode 1: the files whose names
; hold it, in any case -> the files of this part, as QUERY answers them (u64
; 0, then per file {u16 record bytes, u16 name length, u32 tags, u64 size,
; the name, the tag ids}); the reply's handle word is the cursor to ask with
; again (0: that was all), its length word the data's bytes. Mode 0 seeks
; the names' tree (a directory's tag ids, a zero word, the name: one entry a
; file) at the text in each directory in turn, so it reads only the names
; that begin so and one key per directory. Mode 1 reads the records in
; object order, FSCAN of them at most per part: a part may hold no file and
; still have a cursor, so that the asker can give up between parts (a new
; key typed) instead of waiting for every record.
FSCAN   = 384                           ; records read at most in one part of mode 1
uf_find:
        la    t0, srv_hdr               ; the text
        ld    s5, 16(t0)                ; ...
        beqz  s5, uf_bad                ; ...
        li    t1, NAMEMAX               ; ...
        bgtu  s5, t1, uf_bad            ; ...
        sd    s5, nmlen(zero)           ; ...
        la    a0, nm                    ; ...
        mv    a1, s5                    ; ...
        la    ra, srv_get               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    t0, srv_hdr               ; the cursor; none answered unless more follows
        ld    s2, 8(t0)                 ; ...
        sd    zero, 8(t0)               ; ...
        ld    s7, 24(t0)                ; s7 = the mode
        li    s3, 0                     ; s3 = files
        la    s5, sys_buf               ; s5 = output: no path tags
        sd    zero, 0(s5)               ; ...
        addi  s5, s5, 8                 ; ...
        andi  t0, s7, 1                 ; ...
        bnez  t0, uf_sub                ; ...
        srli  s1, s2, 32                ; s1 = directories to pass (the cursor's)
        slli  s2, s2, 32                ; s2 = names of the next one answered already
        srli  s2, s2, 32                ; ...
        li    s6, 0                     ; s6 = directories passed
        li    s7, 4                     ; s7 = D's bytes; D (in reqbuf) = the root's:
        la    t0, reqbuf                ;   a zero word
        sw    zero, 0(t0)               ; ...
uf_skip:
        bgeu  s6, s1, uf_dir            ; ...
        call  uf_next                   ; ...
        beqz  a0, uf_out                ; ...
        addi  s6, s6, 1                 ; ...
        j     uf_skip                   ; ...
uf_dir:
        li    s4, 0                     ; s4 = its names that begin so, seen
        la    t0, reqbuf                ; the key: D, the text
        la    t1, nkb                   ; ...
        li    t2, 0                     ; ...
uf_kd:  bgeu  t2, s7, uf_kn             ; ...
        add   t3, t0, t2                ; ...
        lbu   t3, 0(t3)                 ; ...
        add   t4, t1, t2                ; ...
        sb    t3, 0(t4)                 ; ...
        addi  t2, t2, 1                 ; ...
        j     uf_kd                     ; ...
uf_kn:  la    t0, nm                    ; ...
        ld    t5, nmlen(zero)           ; ...
        li    t3, 0                     ; ...
uf_kn1: bgeu  t3, t5, uf_kk             ; ...
        add   t4, t0, t3                ; ...
        lbu   t4, 0(t4)                 ; ...
        add   t6, t1, t2                ; ...
        sb    t4, 0(t6)                 ; ...
        addi  t2, t2, 1                 ; ...
        addi  t3, t3, 1                 ; ...
        j     uf_kn1                    ; ...
uf_kk:  sd    t2, nk_len(zero)          ; ...
        li    a3, ST_GE                 ; ...
uf_seek:
        ld    a0, x_name(zero)          ; (the key found replaces the one asked with)
        la    a1, nkb                   ; ...
        ld    a2, nk_len(zero)          ; ...
        la    a4, nkb                   ; ...
        la    a5, nval                  ; ...
        la    ra, st_seek               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        beqz  a0, uf_out                ; ...
        ld    t0, sk_kl(zero)           ; ...
        sd    t0, nk_len(zero)          ; ...
        la    t1, nkb                   ; in D?
        la    t2, reqbuf                ; ...
        li    t3, 0                     ; ...
uf_ind: bgeu  t3, s7, uf_inn            ; ...
        add   t4, t1, t3                ; ...
        lbu   t4, 0(t4)                 ; ...
        add   t5, t2, t3                ; ...
        lbu   t5, 0(t5)                 ; ...
        bne   t4, t5, uf_newd           ; no: a later directory, the next one
        addi  t3, t3, 1                 ; ...
        j     uf_ind                    ; ...
uf_inn: ld    t2, nmlen(zero)           ; does the name begin with the text?
        sub   t3, t0, s7                ; ...
        bltu  t3, t2, uf_jump           ; ...
        add   t4, t1, s7                ; ...
        la    t3, nm                    ; ...
uf_pc:
        beqz  t2, uf_hit                ; ...
        lbu   t5, 0(t3)                 ; ...
        lbu   t6, 0(t4)                 ; ...
        bne   t5, t6, uf_jump           ; past the text: the next directory
        addi  t3, t3, 1                 ; ...
        addi  t4, t4, 1                 ; ...
        addi  t2, t2, -1                ; ...
        j     uf_pc                     ; ...
uf_jump:
        call  uf_next                   ; ...
        beqz  a0, uf_out                ; ...
        j     uf_nd                     ; ...
uf_newd:
        call  uf_setd                   ; ...
uf_nd:  addi  s6, s6, 1                 ; ...
        li    s2, 0                     ; ...
        j     uf_dir                    ; ...
uf_hit:
        addi  s4, s4, 1                 ; ...
        bleu  s4, s2, uf_gt             ; (answered in a part before)
        ld    a0, nval(zero)            ; ...
        la    ra, rec_load              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, uf_gt                 ; ...
        call  uf_room                   ; ...
        beqz  a0, uf_pmore              ; ...
        call  uf_rec                    ; ...
        addi  s3, s3, 1                 ; ...
uf_gt:
        li    a3, ST_GT                 ; ...
        j     uf_seek                   ; ...
uf_pmore:
        addi  t0, s4, -1                ; from this one next time
        slli  t1, s6, 32                ; ...
        or    t0, t0, t1                ; (never 0: the first file of a part fits)
        j     uf_cur                    ; ...

; uf_next() -> a0 = 1 and D the next directory in the names' tree (the one
; after D's last name), or 0: none
uf_next:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        la    t0, reqbuf                ; the key: D, then bytes 0xFF (past every name)
        la    t1, nkb                   ; ...
        li    t2, 0                     ; ...
un_d:   bgeu  t2, s7, un_f              ; ...
        add   t3, t0, t2                ; ...
        lbu   t3, 0(t3)                 ; ...
        add   t4, t1, t2                ; ...
        sb    t3, 0(t4)                 ; ...
        addi  t2, t2, 1                 ; ...
        j     un_d                      ; ...
un_f:   li    t3, 0xFF                  ; ...
        li    t5, 484                   ; (as far as the key's room)
un_f1:  bgeu  t2, t5, un_s              ; ...
        add   t4, t1, t2                ; ...
        sb    t3, 0(t4)                 ; ...
        addi  t2, t2, 1                 ; ...
        j     un_f1                     ; ...
un_s:   sd    t2, nk_len(zero)          ; ...
        ld    a0, x_name(zero)          ; ...
        la    a1, nkb                   ; ...
        mv    a2, t2                    ; ...
        li    a3, ST_GE                 ; ...
        la    a4, nkb                   ; ...
        la    a5, nval                  ; ...
        la    ra, st_seek               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        beqz  a0, un_r                  ; ...
        call  uf_setd                   ; ...
        li    a0, 1                     ; ...
un_r:   ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; uf_setd(): D = the directory of the key in nkb (its words up to and with
; the zero word)
uf_setd:
        la    t1, nkb                   ; ...
        ld    t5, sk_kl(zero)           ; ...
        li    t2, 0                     ; ...
us_l:   addi  t3, t2, 4                 ; ...
        bgtu  t3, t5, us_d              ; (no zero word: cannot be)
        add   t4, t1, t2                ; ...
        lwu   t4, 0(t4)                 ; ...
        mv    t2, t3                    ; ...
        bnez  t4, us_l                  ; ...
us_d:   mv    s7, t2                    ; ...
        la    t0, reqbuf                ; ...
        li    t2, 0                     ; ...
us_c:   bgeu  t2, s7, us_r              ; ...
        add   t3, t1, t2                ; ...
        lbu   t3, 0(t3)                 ; ...
        add   t4, t0, t2                ; ...
        sb    t3, 0(t4)                 ; ...
        addi  t2, t2, 1                 ; ...
        j     us_c                      ; ...
us_r:   ret                             ; ...
uf_sub:
        li    s4, FSCAN                 ; s4 = records left to read in this part
        mv    s1, s2                    ; s1 = the last object read
uf_sl:
        beqz  s4, uf_smore              ; ...
        mv    a0, s1                    ; the next record
        la    ra, bswap                 ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        sd    a0, okey(zero)            ; ...
        ld    a0, x_obj(zero)           ; ...
        la    a1, okey                  ; ...
        li    a2, 8                     ; ...
        li    a3, ST_GT                 ; ...
        la    a4, okey                  ; ...
        la    a5, rec                   ; ...
        la    ra, st_seek               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        beqz  a0, uf_out                ; ...
        ld    t0, sk_vl(zero)           ; ...
        sd    t0, rec_len(zero)         ; ...
        ld    a0, okey(zero)            ; ...
        la    ra, bswap                 ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    s1, a0                    ; ...
        sd    a0, rec_oid(zero)         ; ...
        addi  s4, s4, -1                ; ...
        la    ra, rec_name              ; does its name hold the text?
        jalr  ra, ra, 0                 ; (resident code: by its address)
        ld    t2, nmlen(zero)           ; ...
        sub   t6, a1, t2                ; t6 = the places it may start, less one
        bltz  t6, uf_sl                 ; ...
uf_sp:
        mv    t3, a0                    ; at a0?
        la    t4, nm                    ; ...
        mv    t5, t2                    ; ...
uf_sc:
        beqz  t5, uf_shit               ; ...
        lbu   a2, 0(t3)                 ; (both in lower case)
        addi  a3, a2, -65               ; ...
        sltiu a3, a3, 26                ; ...
        slli  a3, a3, 5                 ; ...
        or    a2, a2, a3                ; ...
        lbu   a4, 0(t4)                 ; ...
        addi  a3, a4, -65               ; ...
        sltiu a3, a3, 26                ; ...
        slli  a3, a3, 5                 ; ...
        or    a4, a4, a3                ; ...
        bne   a2, a4, uf_sn             ; ...
        addi  t3, t3, 1                 ; ...
        addi  t4, t4, 1                 ; ...
        addi  t5, t5, -1                ; ...
        j     uf_sc                     ; ...
uf_sn:
        addi  a0, a0, 1                 ; the next place
        addi  t6, t6, -1                ; ...
        bgez  t6, uf_sp                 ; ...
        j     uf_sl                     ; ...
uf_shit:
        call  uf_room                   ; ...
        beqz  a0, uf_sfull              ; ...
        call  uf_rec                    ; ...
        addi  s3, s3, 1                 ; ...
        j     uf_sl                     ; ...
uf_sfull:
        addi  s1, s1, -1                ; this one again next time
uf_smore:
        mv    t0, s1                    ; ...
uf_cur:
        la    t1, srv_hdr               ; ...
        sd    t0, 8(t1)                 ; ...
uf_out:
        la    a0, sys_buf               ; ...
        sub   a1, s5, a0                ; ...
        la    t0, srv_hdr               ; (the length word: the data's bytes)
        sd    a1, 16(t0)                ; ...
        la    ra, srv_put               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    a0, s3                    ; ...
        la    t6, reply                 ; ...
        jalr  zero, t6, 0               ; (resident code: by its address)

; uf_room() -> a0 = 1 if rec's file fits as a record at s5
uf_room:
        la    t0, rec                   ; ...
        lhu   t1, R_NL(t0)              ; ...
        addi  t1, t1, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        lhu   t2, R_NTAGS(t0)           ; ...
        slli  t2, t2, 2                 ; ...
        addi  t2, t2, 7                 ; ...
        srli  t2, t2, 3                 ; ...
        slli  t2, t2, 3                 ; ...
        add   t1, t1, t2                ; ...
        addi  t1, t1, 16                ; ...
        add   t1, t1, s5                ; ...
        la    t2, sys_buf + SYS_MAX     ; ...
        sltu  a0, t2, t1                ; ...
        xori  a0, a0, 1                 ; ...
        ret                             ; ...

; uf_rec(): rec's file as a QUERY record at s5, which moves past it (as oq_rec)
uf_rec:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        la    t0, rec                   ; ...
        lhu   t1, R_NL(t0)              ; ...
        sd    zero, 0(s5)               ; ...
        sh    t1, 2(s5)                 ; ...
        lhu   t2, R_NTAGS(t0)           ; ...
        sw    t2, 4(s5)                 ; ...
        ld    t3, R_SIZE(t0)            ; ...
        sd    t3, 8(s5)                 ; ...
        addi  s1, s5, 16                ; the name, padded with zeros
        addi  t1, t1, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        mv    a0, s1                    ; ...
        mv    a1, t1                    ; ...
        add   s1, s1, t1                ; ...
        la    ra, wzero                 ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    ra, rec_name              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    a2, a1                    ; ...
        mv    a1, a0                    ; ...
        addi  a0, s5, 16                ; ...
        la    ra, srv_bcopy             ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    t0, rec                   ; its tag ids
        lhu   t2, R_NTAGS(t0)           ; ...
        sd    zero, 0(s1)               ; ...
ufr_t:
        beqz  t2, ufr_d                 ; ...
        lwu   t3, R_TAGS(t0)            ; ...
        sw    t3, 0(s1)                 ; ...
        sw    zero, 4(s1)               ; ...
        addi  t0, t0, 4                 ; ...
        addi  s1, s1, 4                 ; ...
        addi  t2, t2, -1                ; ...
        j     ufr_t                     ; ...
ufr_d:
        addi  s1, s1, 7                 ; ...
        srli  s1, s1, 3                 ; ...
        slli  s1, s1, 3                 ; ...
        sub   t0, s1, s5                ; the record's bytes
        sh    t0, 0(s5)                 ; ...
        mv    s5, s1                    ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

uf_bad:
        la    t6, bad                  ; out of the unit: resident code by its address
        jalr  zero, t6, 0               ; ...
        .org  u_f + USLOT               ; (the unit must fit its slot)

        .text                           ; ...
