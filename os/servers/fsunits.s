; =============================================================================
; fsunits.s: the file server's code units (included by fs.s)
; =============================================================================
;
; The file server's code does not fit the 32 KiB of a program's I-LS. What
; is used seldom (the store's calls for programs, snapshots, attributes,
; boot objects ...) is here, in the image's .far section: the kernel copies
; that into the server's memory (c0) at its own offset, and the dispatcher
; pages a unit into the I-LS when it is called (doc/strataos.md, "Code
; units"): `xcall` by the unit's far address misses, the dispatcher copies
; the unit into a slot of the code cache (the I-LS after the resident code,
; in slots of USLOT bytes; fs.s sets xslot) and maps it.
;
; The rules of a unit (tools/check-fsunits.py checks the first on the image):
;   - a unit is USLOT bytes at most, at a multiple of USLOT in .far (the
;     `.org` after each unit fails to assemble if it is longer);
;   - it runs in whatever slot it was paged into: a pc-relative jump, branch
;     or call may only go to a label of the same unit. Resident code is
;     called by its address (la ra, f / jalr ra, ra, 0) and jumped to by its
;     address (la t6, l / jalr zero, t6, 0: t6 holds nothing at a unit's
;     exits); a conditional branch out goes through such a jump at the
;     unit's end (uX_label);
;   - `la` of a label in a unit gives its far address, not where it runs:
;     only for xcall;
;   - data is in the D-LS as everywhere (absolute addresses);
;   - one unit is at work at a time: resident code that a unit calls never
;     enters another unit (it could take the caller's slot), and a unit does
;     not enter another. So the requests' handlers are units, and what they
;     share is resident;
;   - a unit entered by a jump (xcall zero: the handlers of fs.s's dispatch)
;     leaves by jumping to resident code (reply, ok, bad ...); one that is
;     called (xcall ra) returns with xret ra.
; A unit's entry in the resident code is three instructions: la t5, entry /
; xcall zero, c0, t5.

USLOT   = 2048                          ; a unit's most bytes: a slot of the code cache
UBASE   = 0                             ; where the units are in the server's memory (c0)

        .far                            ; the image's far section
        .org  UBASE                     ; ...

; ---- ud: the store for programs (DBGET, DBSCAN, DBBATCH; see fsops.s) -----------------------
u_d:
; db_parse(a0 = 1: make the namespace and the tree if missing) -> a0 = 0 and
; s1 = the tree, s2 = what follows the names in reqbuf, s3 = the key length;
; or a0 = -1 / -4
db_parse:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s4, 8(sp)                 ; ...
        sd    s5, 16(sp)                ; ...
        mv    s4, a0                    ; s4 = make?
        la    t0, srv_hdr               ; the data
        ld    s5, 16(t0)                ; s5 = its length
        li    a0, -1                    ; ...
        li    t1, 8                     ; ...
        bltu  s5, t1, dbp_ret           ; ...
        li    t1, SYS_MAX               ; ...
        bgtu  s5, t1, dbp_ret           ; ...
        la    a0, reqbuf                ; ...
        mv    a1, s5                    ; ...
        la    ra, srv_get               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    t0, reqbuf                ; ...
        lbu   t1, 0(t0)                 ; the names' lengths
        lbu   t2, 1(t0)                 ; ...
        lhu   s3, 2(t0)                 ; ...
        li    a0, -1                    ; ...
        beqz  t1, dbp_ret               ; ...
        beqz  t2, dbp_ret               ; ...
        li    t3, 32                    ; ...
        bgtu  t1, t3, dbp_ret           ; ...
        li    t3, 28                    ; ...
        bgtu  t2, t3, dbp_ret           ; ...
        add   t3, t1, t2                ; all inside the data?
        addi  t3, t3, 8                 ; ...
        bgtu  t3, s5, dbp_ret           ; ...
        add   s2, t0, t3                ; ...
        add   t3, t0, t1                ; (the tree's name)
        lbu   t4, 8(t3)                 ; ...
        li    t5, '.'                   ; ...
        beq   t4, t5, dbp_ret           ; ...
        ld    a0, x_nst(zero)           ; the namespace
        addi  a1, t0, 8                 ; ...
        mv    a2, t1                    ; ...
        la    a3, dval                  ; ...
        la    ra, st_get                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bgez  a0, dbp_have              ; ...
        li    a0, -4                    ; ...
        beqz  s4, dbp_ret               ; ...
        ld    t0, st_nextns(zero)       ; a new one: public
        sd    t0, dval(zero)            ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, st_nextns(zero)       ; ...
        li    t0, 1                     ; ...
        sd    t0, dval+8(zero)          ; ...
        ld    a0, x_nst(zero)           ; ...
        la    a1, reqbuf + 8            ; ...
        lbu   a2, reqbuf(zero)          ; ...
        la    a3, dval                  ; ...
        li    a4, 16                    ; ...
        li    a5, 0                     ; ...
        la    ra, st_put                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
dbp_have:
        ld    t0, dval+8(zero)          ; public?
        andi  t0, t0, 1                 ; ...
        li    a0, -1                    ; ...
        beqz  t0, dbp_ret               ; ...
        ld    a0, dval(zero)            ; its tree
        la    t0, reqbuf                ; ...
        lbu   t1, 0(t0)                 ; ...
        add   a1, t0, t1                ; ...
        addi  a1, a1, 8                 ; ...
        lbu   a2, 1(t0)                 ; ...
        mv    a3, s4                    ; ...
        la    ra, st_tree               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    s1, a0                    ; ...
        li    a0, -4                    ; ...
        beqz  s1, dbp_ret               ; ...
        li    a0, 0                     ; ...
dbp_ret:
        ld    s5, 16(sp)                ; ...
        ld    s4, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

ud_dbget:
        li    a0, 0                     ; ...
        call  db_parse                  ; ...
        bltz  a0, ud_reply              ; ...
        mv    a0, s1                    ; ...
        mv    a1, s2                    ; ...
        mv    a2, s3                    ; ...
        la    a3, sys_buf               ; ...
        la    ra, st_get                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        sd    zero, TT_FL(s1)           ; (the tree is not kept open)
        bltz  a0, ud_nofile             ; ...
        bnez  a1, ud_bad                ; (a stream: not through this call)
        mv    s3, a0                    ; ...
        la    a0, sys_buf               ; ...
        mv    a1, s3                    ; ...
        la    ra, srv_put               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    a0, s3                    ; ...
        la    t6, reply                 ; ...
        jalr  zero, t6, 0               ; (resident code: by its address)

ud_dbscan:
        li    a0, 0                     ; ...
        call  db_parse                  ; ...
        bltz  a0, ud_reply              ; ...
        la    a0, pgcopy                ; the key at hand (pgcopy), a value (pgcopy + 512)
        mv    a1, s2                    ; ...
        mv    a2, s3                    ; ...
        la    ra, srv_bcopy             ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    t0, srv_hdr               ; s4 = the side of the key for the first one
        ld    s4, 24(t0)                ; ...
        li    s6, 0                     ; s6 = records
        la    s5, sys_buf               ; s5 = output
odb_l:
        mv    a0, s1                    ; ...
        la    a1, pgcopy                ; ...
        mv    a2, s3                    ; ...
        mv    a3, s4                    ; ...
        la    a4, pgcopy                ; ...
        la    a5, pgcopy + 512          ; ...
        la    ra, st_seek               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        beqz  a0, odb_done              ; ...
        ld    s3, sk_kl(zero)           ; ...
        li    s4, ST_GT                 ; (the ones after it follow)
        ld    t1, sk_vl(zero)           ; room for it?
        addi  t2, s3, 7                 ; ...
        srli  t2, t2, 3                 ; ...
        slli  t2, t2, 3                 ; ...
        addi  t3, t1, 7                 ; ...
        srli  t3, t3, 3                 ; ...
        slli  t3, t3, 3                 ; ...
        add   t4, t2, t3                ; ...
        addi  t4, t4, 8                 ; ...
        add   t4, t4, s5                ; ...
        la    t5, sys_buf + SYS_MAX     ; ...
        bgtu  t4, t5, odb_done          ; ...
        sd    zero, 0(s5)               ; ...
        sh    s3, 0(s5)                 ; ...
        sh    t1, 2(s5)                 ; ...
        addi  a0, s5, 8                 ; ...
        la    a1, pgcopy                ; ...
        mv    a2, t2                    ; ...
        add   s5, a0, t2                ; ...
        la    ra, wcopy                 ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    a0, s5                    ; ...
        la    a1, pgcopy + 512          ; ...
        ld    a2, sk_vl(zero)           ; ...
        addi  a2, a2, 7                 ; ...
        srli  a2, a2, 3                 ; ...
        slli  a2, a2, 3                 ; ...
        add   s5, s5, a2                ; ...
        la    ra, wcopy                 ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        addi  s6, s6, 1                 ; ...
        j     odb_l                     ; ...
odb_done:
        sd    zero, TT_FL(s1)           ; ...
        la    a0, sys_buf               ; ...
        sub   a1, s5, a0                ; ...
        la    t0, srv_hdr               ; ...
        sd    a1, 16(t0)                ; ...
        la    ra, srv_put               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    a0, s6                    ; ...
        la    t6, reply                 ; ...
        jalr  zero, t6, 0               ; (resident code: by its address)

ud_dbbatch:
        la    ra, tx_sync               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        li    a0, 1                     ; ...
        call  db_parse                  ; ...
        bltz  a0, ud_reply              ; ...
        la    t0, reqbuf                ; s2 = the first item: at a multiple of 8
        sub   s2, s2, t0                ; ...
        addi  s2, s2, 7                 ; ...
        srli  s2, s2, 3                 ; ...
        slli  s2, s2, 3                 ; ...
        add   s2, s2, t0                ; ...
        la    t0, srv_hdr               ; s6 = the end of the data
        ld    s6, 16(t0)                ; ...
        la    t1, reqbuf                ; ...
        add   s6, s6, t1                ; ...
        ld    s7, 8(t0)                 ; s7 = items
        li    s5, 0                     ; first every item is looked at (s5 = 0), then done (1)
obb_pass:
        mv    s3, s2                    ; s3 = the item
        mv    s4, s7                    ; s4 = items left
obb_l:
        beqz  s4, obb_next              ; ...
        addi  t0, s3, 8                 ; inside the data?
        bgtu  t0, s6, obb_bad           ; ...
        lhu   a2, 2(s3)                 ; the key's length, the value's
        lhu   a4, 4(s3)                 ; ...
        addi  t1, a2, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        addi  t2, a4, 7                 ; ...
        srli  t2, t2, 3                 ; ...
        slli  t2, t2, 3                 ; ...
        add   t3, t0, t1                ; t3 = the value, t4 = the next item
        add   t4, t3, t2                ; ...
        bgtu  t4, s6, obb_bad           ; ...
        lbu   t5, 0(s3)                 ; ...
        addi  t5, t5, -1                ; ...
        li    t6, 2                     ; ...
        bgeu  t5, t6, obb_bad           ; ...
        bnez  s5, obb_do                ; ...
        beqz  a2, obb_bad               ; a key and a value of a size the store takes?
        ld    t6, st_ps(zero)           ; ...
        srli  t0, t6, 3                 ; ...
        addi  t0, t0, -32               ; ...
        bgtu  a2, t0, obb_bad           ; ...
        addi  t6, t6, -32               ; ...
        srli  t6, t6, 2                 ; ...
        addi  t6, t6, -10               ; ...
        srli  t6, t6, 3                 ; ...
        slli  t6, t6, 3                 ; ...
        sub   t6, t6, t1                ; ...
        bgt   a4, t6, obb_bad           ; ...
        j     obb_n                     ; ...
obb_do:
        sd    t4, rb_c(zero)            ; (kept: the next item)
        mv    a0, s1                    ; ...
        mv    a1, t0                    ; ...
        bnez  t5, obb_del               ; ...
        mv    a3, t3                    ; ...
        li    a5, 0                     ; ...
        la    ra, st_put                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        j     obb_dn                    ; ...
obb_del:
        la    ra, st_del                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
obb_dn:
        ld    t4, rb_c(zero)            ; ...
obb_n:
        mv    s3, t4                    ; ...
        addi  s4, s4, -1                ; ...
        j     obb_l                     ; ...
obb_next:
        addi  s5, s5, 1                 ; ...
        li    t0, 2                     ; ...
        bne   s5, t0, obb_pass          ; ...
        la    ra, fs_commit             ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        sd    zero, TT_FL(s1)           ; ...
        la    t6, ok                    ; ...
        jalr  zero, t6, 0               ; (resident code: by its address)
obb_bad:
        la    ra, fs_commit             ; (a namespace or a tree it made stays, empty)
        jalr  ra, ra, 0                 ; (resident code: by its address)
        sd    zero, TT_FL(s1)           ; ...
        la    t6, bad                   ; ...
        jalr  zero, t6, 0               ; (resident code: by its address)

ud_reply:
        la    t6, reply                ; out of the unit: resident code by its address
        jalr  zero, t6, 0               ; ...
ud_nofile:
        la    t6, nofile               ; out of the unit: resident code by its address
        jalr  zero, t6, 0               ; ...
ud_bad:
        la    t6, bad                  ; out of the unit: resident code by its address
        jalr  zero, t6, 0               ; ...
        .org  u_d + USLOT               ; (the unit must fit its slot)

; ---- ub: boot objects: one run of pages, the boot manifest (see fsops.s) -----------------------
u_b:
; ub_man(): the manifest written anew from the files with the boot flag
ub_man:
        addi  sp, sp, -48               ; frame (ub_fix's: it ends there)
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        sd    s5, 40(sp)                ; ...
        j     bfx_man                   ; ...

; ub_fix(): rec's file (a boot object, just written; okey is its key): its
; contents a stream in one extent; then the manifest
ub_fix:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        sd    s5, 40(sp)                ; ...
        ld    a0, x_data(zero)          ; its contents
        la    a1, okey                  ; ...
        li    a2, 8                     ; ...
        la    ra, st_bsize              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        ld    t0, bl_fl(zero)           ; a stream already?
        bltz  a0, bfx_in                ; (none: an empty one is made)
        bnez  t0, bfx_one               ; ...
bfx_in:
        mv    s1, a0                    ; inline (or none): written again as a stream
        bgez  s1, bfx_c                 ; ...
        li    s1, 0                     ; ...
bfx_c:
        la    a0, reqbuf                ; ...
        la    a1, bval                  ; ...
        addi  a2, s1, 7                 ; ...
        srli  a2, a2, 3                 ; ...
        slli  a2, a2, 3                 ; ...
        la    ra, wcopy                 ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        ld    a0, x_data(zero)          ; ...
        la    a1, okey                  ; ...
        li    a2, 8                     ; ...
        la    ra, st_bdel               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        li    t0, 1                     ; ...
        sd    t0, bw_force(zero)        ; ...
        ld    a0, x_data(zero)          ; ...
        la    a1, okey                  ; ...
        li    a2, 8                     ; ...
        li    a3, 0                     ; ...
        la    a4, reqbuf                ; ...
        mv    a5, s1                    ; ...
        la    ra, st_bwrite             ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        sd    zero, bw_force(zero)      ; ...
        ld    a0, x_data(zero)          ; ...
        la    a1, okey                  ; ...
        li    a2, 8                     ; ...
        la    ra, st_bsize              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
bfx_one:
        ld    s1, bval+8(zero)          ; s1 = the stream
        ld    t0, st_ps(zero)           ; s2 = its pages
        add   s2, a0, t0                ; ...
        addi  s2, s2, -1                ; ...
        ld    t0, st_sh(zero)           ; ...
        srl   s2, s2, t0                ; ...
        beqz  s2, bfx_man               ; ...
        mv    a0, s1                    ; one extent from its start holding them all?
        li    a1, 0                     ; ...
        la    ra, ext_find              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        beqz  a0, bfx_move              ; ...
        ld    t0, e_pages(zero)         ; ...
        bgeu  t0, s2, bfx_man           ; ...
bfx_move:
        mv    a0, s2                    ; no: a run of that many pages, the contents copied
        li    a1, 0                     ; into it page by page, the old pages freed
        la    ra, alloc                 ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    s3, a0                    ; s3 = the run
        bne   a1, s2, ub_st_full        ; (no such run on the disk)
        li    s4, 0                     ; s4 = the page
bfx_cp:
        bgeu  s4, s2, bfx_cd            ; ...
        la    a0, pgcopy                ; ...
        li    a1, 4096                  ; ...
        la    ra, wzero                 ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    a0, s1                    ; ...
        mv    a1, s4                    ; ...
        la    ra, ext_find              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        beqz  a0, bfx_w                 ; (a hole: zeros)
        ld    a0, e_start(zero)         ; ...
        ld    t0, e_off(zero)           ; ...
        sub   t0, s4, t0                ; ...
        add   a0, a0, t0                ; ...
        la    ra, PR                    ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    a1, a0                    ; ...
        la    a0, pgcopy                ; ...
        li    a2, 4096                  ; ...
        la    ra, wcopy                 ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
bfx_w:
        add   a0, s3, s4                ; ...
        la    ra, PRN                   ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    a1, pgcopy                ; ...
        li    a2, 4096                  ; ...
        la    ra, wcopy                 ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        addi  s4, s4, 1                 ; ...
        j     bfx_cp                    ; ...
bfx_cd:
        mv    a0, s1                    ; ...
        li    a1, 0                     ; ...
        la    ra, s_trim                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    a0, s1                    ; ...
        li    a1, 0                     ; ...
        mv    a2, s3                    ; ...
        mv    a3, s2                    ; ...
        ld    a4, st_txn(zero)          ; ...
        la    ra, ext_put               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
bfx_man:
        la    ra, alloc1                ; the manifest anew: a page of this commit
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    s3, a0                    ; s3 = it
        la    ra, PN                    ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        sd    s3, 8(a0)                 ; ...
        ld    t0, st_txn(zero)          ; ...
        sd    t0, 16(a0)                ; ...
        li    t0, 3                     ; ...
        sb    t0, 24(a0)                ; ...
        li    t0, 0x464D544F4F425453    ; "STBOOTMF"
        sd    t0, 32(a0)                ; ...
        li    s4, 0                     ; s4 = entries
        sd    zero, ikey(zero)          ; every file with the boot flag: the index's
        sd    zero, ikey+8(zero)        ; entries of attribute 4
        li    t0, A_BOOT                ; ...
        sb    t0, ikey+3(zero)          ; ...
bfx_l:
        ld    a0, x_attr(zero)          ; ...
        la    a1, ikey                  ; ...
        li    a2, 12                    ; ...
        li    a3, ST_GT                 ; ...
        la    a4, ikey                  ; ...
        li    a5, 0                     ; ...
        la    ra, st_seek               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        beqz  a0, bfx_end               ; ...
        lwu   t0, ikey(zero)            ; still attribute 4?
        li    t1, 0x04000000            ; ...
        bne   t0, t1, bfx_end           ; ...
        ld    t0, sk_kl(zero)           ; ...
        li    t1, 12                    ; ...
        bne   t0, t1, bfx_end           ; ...
        li    a0, 0                     ; its object: the key's last eight bytes, big-endian
        li    t0, 4                     ; ...
bfx_o:
        slli  a0, a0, 8                 ; ...
        lbu   t1, ikey(t0)              ; ...
        or    a0, a0, t1                ; ...
        addi  t0, t0, 1                 ; ...
        li    t1, 12                    ; ...
        bne   t0, t1, bfx_o             ; ...
        la    ra, rec_load              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, bfx_l                 ; ...
        ld    a0, x_data(zero)          ; where its contents start
        la    a1, okey                  ; ...
        li    a2, 8                     ; ...
        la    ra, st_bsize              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        li    s5, 0                     ; s5 = the first page (none: empty)
        blez  a0, bfx_e                 ; ...
        ld    a0, bval+8(zero)          ; ...
        li    a1, 0                     ; ...
        la    ra, ext_find              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        beqz  a0, bfx_e                 ; ...
        ld    s5, e_start(zero)         ; ...
bfx_e:
        mv    a0, s3                    ; its entry
        la    ra, PW                    ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        slli  t0, s4, 5                 ; ...
        add   s2, a0, t0                ; ...
        addi  s2, s2, 64                ; s2 = the entry
        addi  s4, s4, 1                 ; ...
        sw    s4, 40(a0)                ; ...
        sd    s5, 16(s2)                ; ...
        la    t0, rec                   ; ...
        ld    t1, R_SIZE(t0)            ; ...
        sd    t1, 24(s2)                ; ...
        la    ra, rec_name              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    a2, a1                    ; (a boot object's name: 16 bytes at most)
        li    t0, 16                    ; ...
        bleu  a2, t0, bfx_n             ; ...
        mv    a2, t0                    ; ...
bfx_n:
        mv    a1, a0                    ; ...
        mv    a0, s2                    ; ...
        la    ra, srv_bcopy             ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        j     bfx_l                     ; ...
bfx_end:
        ld    s1, st_manif(zero)        ; the old manifest's page is free
        sd    s3, st_manif(zero)        ; ...
        beqz  s1, bfx_ret               ; ...
        mv    a0, s1                    ; ...
        la    ra, P                     ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        ld    a2, 16(a0)                ; ...
        sd    zero, st_owner(zero)      ; ...
        mv    a0, s1                    ; ...
        li    a1, 1                     ; ...
        la    ra, pfree                 ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
bfx_ret:
        ld    s5, 40(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; ...
ub_st_full:
        la    t6, st_full              ; out of the unit: resident code by its address
        jalr  zero, t6, 0               ; ...
        .org  u_b + USLOT               ; (the unit must fit its slot)

; ---- us: snapshots: SNAP, a restore (see fsops.s) ----------------------------------------------
u_s:
; SNAP: mode 0 take (data = a name of 1..32 bytes) -> 0 / -1 (a bad name, or
; taken already); mode 1 delete (data = the name) -> 0 / -4; mode 2 list ->
; snapshots; data: 40-byte records {u64 commit, name[32]}; mode 3 restore
; (data = the name) -> 0 / -4 / -1 (a file is open for writing)
us_snap:
        la    ra, tx_sync               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    t0, srv_hdr               ; ...
        ld    s4, 24(t0)                ; s4 = the mode
        li    t1, 2                     ; ...
        beq   s4, t1, osn_list          ; ...
        la    ra, get_raw               ; the name
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    s2, a0                    ; ...
        blez  s2, us_bad                ; ...
        li    t0, 32                    ; ...
        bgtu  s2, t0, us_bad            ; ...
        la    a0, rbuf                  ; ...
        mv    a1, s2                    ; ...
        la    ra, snap_find             ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    s1, a0                    ; s1 = its commit, if it is there
        li    t0, 3                     ; ...
        beq   s4, t0, osn_rest          ; ...
        bnez  s4, osn_del               ; ...
        bnez  s1, us_bad                ; take: not twice
        la    ra, fs_commit             ; what is committed now is the snapshot
        jalr  ra, ra, 0                 ; (resident code: by its address)
        ld    s1, st_cmt(zero)          ; ...
        la    a0, tnbuf                 ; its record: the catalog as committed, the name
        li    a1, 48                    ; ...
        la    ra, wzero                 ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        ld    t0, t_cat(zero)           ; ...
        sd    t0, tnbuf(zero)           ; ...
        ld    t0, t_cat+8(zero)         ; ...
        sd    t0, tnbuf+8(zero)         ; ...
        la    a0, tnbuf + 16            ; ...
        la    a1, rbuf                  ; ...
        mv    a2, s2                    ; ...
        la    ra, srv_bcopy             ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        sd    s1, st_deadlim(zero)      ; from now on that commit's pages are kept
        mv    a0, s1                    ; ...
        la    ra, bswap                 ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        sd    a0, rkey(zero)            ; ...
        ld    a0, x_snap(zero)          ; ...
        la    a1, rkey                  ; ...
        li    a2, 8                     ; ...
        la    a3, tnbuf                 ; ...
        addi  a4, s2, 16                ; ...
        li    a5, 0                     ; ...
        la    ra, st_put                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    ra, fs_commit             ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    t6, ok                    ; ...
        jalr  zero, t6, 0               ; (resident code: by its address)
osn_del:
        beqz  s1, us_nofile             ; delete: it must be there
        la    ra, fs_commit             ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    a0, s1                    ; s2 = the snapshot before it (0: none)
        la    ra, bswap                 ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        sd    a0, rkey(zero)            ; ...
        li    s2, 0                     ; ...
        ld    a0, x_snap(zero)          ; ...
        la    a1, rkey                  ; ...
        li    a2, 8                     ; ...
        li    a3, ST_LT                 ; ...
        la    a4, dval                  ; ...
        li    a5, 0                     ; ...
        la    ra, st_seek               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        beqz  a0, osn_d1                ; ...
        ld    a0, dval(zero)            ; ...
        la    ra, bswap                 ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    s2, a0                    ; ...
osn_d1:
        ld    s5, st_deadlim(zero)      ; s5 = the newest snapshot once this one is gone
        bne   s5, s1, osn_d2            ; ...
        mv    s5, s2                    ; ...
osn_d2:
        sd    s2, st_deadlim(zero)      ; its dead list: what was born after the one before
        li    s3, 1                     ; is free, the rest goes on that one's list
        slli  s3, s3, 63                ; ...
        or    a0, s3, s1                ; ...
        la    ra, bswap                 ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    s3, a0                    ; s3 = the list's key, as stored
osn_dl:
        sd    s3, rkey(zero)            ; ...
        sd    zero, rkey+8(zero)        ; ...
        la    a0, t_pend                ; ...
        la    a1, rkey                  ; ...
        li    a2, 16                    ; ...
        li    a3, ST_GT                 ; ...
        la    a4, rkey                  ; ...
        la    a5, dval                  ; ...
        la    ra, st_seek               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        beqz  a0, osn_dd                ; ...
        ld    t0, rkey(zero)            ; ...
        bne   t0, s3, osn_dd            ; ...
        la    ra, relief                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        li    t0, 1                     ; (the pending tree's own pages: no snapshot's)
        sd    t0, in_rel(zero)          ; ...
        la    a0, t_pend                ; ...
        la    a1, rkey                  ; ...
        li    a2, 16                    ; ...
        la    ra, st_del                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        sd    zero, in_rel(zero)        ; ...
        ld    a0, rkey+8(zero)          ; ...
        la    ra, bswap                 ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        ld    a1, dval(zero)            ; the pages, as their namespace's again
        srli  t0, a1, 32                ; ...
        sd    t0, st_owner(zero)        ; ...
        lwu   a1, dval(zero)            ; ...
        ld    a2, dval+8(zero)          ; ...
        la    ra, pfree                 ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        j     osn_dl                    ; ...
osn_dd:
        li    t0, 1                     ; that is recorded by the rule of the one before;
        sd    t0, in_rel(zero)          ; everything else by the newest one's
        la    ra, drain_fr              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        sd    zero, in_rel(zero)        ; ...
        sd    s5, st_deadlim(zero)      ; ...
        mv    a0, s1                    ; its record goes
        la    ra, bswap                 ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        sd    a0, rkey(zero)            ; ...
        ld    a0, x_snap(zero)          ; ...
        la    a1, rkey                  ; ...
        li    a2, 8                     ; ...
        la    ra, st_del                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    ra, fs_commit             ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    t6, ok                    ; ...
        jalr  zero, t6, 0               ; (resident code: by its address)
osn_list:
        li    s3, 0                     ; s3 = records
        la    s5, sys_buf               ; ...
        sd    zero, rkey(zero)          ; ...
osn_l:
        li    t0, 100                   ; ...
        bgeu  s3, t0, osn_ld            ; ...
        ld    a0, x_snap(zero)          ; ...
        la    a1, rkey                  ; ...
        li    a2, 8                     ; ...
        li    a3, ST_GT                 ; ...
        la    a4, rkey                  ; ...
        la    a5, tnbuf                 ; ...
        la    ra, st_seek               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        beqz  a0, osn_ld                ; ...
        ld    a0, rkey(zero)            ; ...
        la    ra, bswap                 ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        sd    a0, 0(s5)                 ; ...
        addi  a0, s5, 8                 ; ...
        la    a1, tnbuf + 16            ; (the name is zero-padded in its record)
        li    a2, 32                    ; ...
        la    ra, wcopy                 ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        addi  s5, s5, 40                ; ...
        addi  s3, s3, 1                 ; ...
        j     osn_l                     ; ...
osn_ld:
        la    a0, sys_buf               ; ...
        sub   a1, s5, a0                ; ...
        la    ra, srv_put               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    a0, s3                    ; ...
        la    t6, reply                 ; ...
        jalr  zero, t6, 0               ; (resident code: by its address)

; ---- restoring a snapshot ------------------------------------------------------------
; The file system becomes what the snapshot shows: its six trees take the
; snapshot's roots, in one commit. (The snapshots stay, the one restored
; too; other namespaces are not touched.) Two things keep the pages right:
;   - what only the state given up used is freed: its pages born after the
;     snapshot (a page born before it is the snapshot's too; and since a
;     page's children are never younger than it, such a page ends the walk);
;   - what the snapshot shows and the state given up had dropped is in use
;     again: those pages (the file system's, born no later than the
;     snapshot, on the dead list of it or of a later one) leave the dead
;     lists.

; drop_tree(a0 = a tree, a1 = 1: its records are extents, to be freed with
; it): its pages born after commit s1 are freed (s1 is the caller's)
drop_tree:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s2, 8(sp)                 ; ...
        sd    s3, 16(sp)                ; ...
        sd    s4, 24(sp)                ; ...
        sd    s5, 32(sp)                ; ...
        mv    s5, a1                    ; s5 = extents?
        ld    t0, 0(a0)                 ; ...
        beqz  t0, dt_ret                ; ...
        li    s2, 0                     ; s2 = the level (times 16)
        sd    t0, wpath(zero)           ; (no tree change is under way: its path serves)
        sd    zero, wpath+8(zero)       ; ...
dt_l:
        la    ra, relief                ; (the lists of freed pages are written out as they fill)
        jalr  ra, ra, 0                 ; (resident code: by its address)
        ld    a0, wpath(s2)             ; ...
        la    ra, P                     ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    s3, a0                    ; s3 = the page
        ld    s4, 16(s3)                ; s4 = its birth
        bleu  s4, s1, dt_up             ; the snapshot's too: so is all below it
        lbu   t0, 24(s3)                ; ...
        li    t1, K_LEAF                ; ...
        beq   t0, t1, dt_leaf           ; ...
        ld    a1, wpath+8(s2)           ; a branch: its next child, or it is done
        lhu   t0, 26(s3)                ; ...
        bgeu  a1, t0, dt_free           ; ...
        addi  t0, a1, 1                 ; ...
        sd    t0, wpath+8(s2)           ; ...
        la    ra, child                 ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        addi  s2, s2, 16                ; ...
        sd    a0, wpath(s2)             ; ...
        sd    zero, wpath+8(s2)         ; ...
        j     dt_l                      ; ...
dt_leaf:
        beqz  s5, dt_free               ; extents born after the snapshot go with it
        ld    a1, wpath+8(s2)           ; ...
        lhu   t0, 26(s3)                ; ...
        bgeu  a1, t0, dt_free           ; ...
        addi  t0, a1, 1                 ; ...
        sd    t0, wpath+8(s2)           ; ...
        slli  a1, a1, 1                 ; its cell: key 16 bytes, value {start, pages, birth}
        add   a1, a1, s3                ; ...
        lhu   a1, 32(a1)                ; ...
        add   a1, a1, s3                ; ...
        ld    a2, 40(a1)                ; ...
        bleu  a2, s1, dt_l              ; ...
        ld    t0, fs_ns(zero)           ; ...
        sd    t0, st_owner(zero)        ; ...
        ld    a0, 24(a1)                ; ...
        ld    a1, 32(a1)                ; ...
        la    ra, pfree                 ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        j     dt_l                      ; ...
dt_free:
        ld    t0, fs_ns(zero)           ; ...
        sd    t0, st_owner(zero)        ; ...
        ld    a0, wpath(s2)             ; the page itself
        li    a1, 1                     ; ...
        mv    a2, s4                    ; ...
        la    ra, pfree                 ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
dt_up:
        beqz  s2, dt_ret                ; ...
        addi  s2, s2, -16               ; ...
        j     dt_l                      ; ...
dt_ret:
        ld    s5, 32(sp)                ; ...
        ld    s4, 24(sp)                ; ...
        ld    s3, 16(sp)                ; ...
        ld    s2, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 40                ; ...
        ret                             ; ...

osn_rest:
        beqz  s1, us_nofile             ; restore: it must be there,
        la    t0, opens                 ; and no file open for writing
        li    t1, NOPEN                 ; ...
osr_o:
        ld    t2, O_USED(t0)            ; ...
        li    t3, 2                     ; ...
        bgeu  t2, t3, us_bad            ; ...
        addi  t0, t0, O_SIZEOF          ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, osr_o                 ; ...
        la    ra, fs_commit             ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    ra, begin                 ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    a0, s1                    ; the snapshot's six roots -> sx
        la    ra, snap_use              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, us_nofile             ; ...
        la    ra, snap_done             ; (the live trees are at hand again)
        jalr  ra, ra, 0                 ; (resident code: by its address)
        li    s2, 0                     ; every tree: what only the live state used goes,
osr_t:
        ld    a0, x_obj(s2)             ; ...
        addi  a1, s2, -40               ; (the sixth is the extents' tree)
        seqz  a1, a1                    ; ...
        call  drop_tree                 ; ...
        ld    t0, x_obj(s2)             ; and it takes the snapshot's root
        slli  t1, s2, 1                 ; ...
        ld    t2, sx(t1)                ; ...
        sd    t2, 0(t0)                 ; ...
        ld    t2, sx+8(t1)              ; ...
        sd    t2, 8(t0)                 ; ...
        addi  s2, s2, 8                 ; ...
        li    t0, 48                    ; ...
        bne   s2, t0, osr_t             ; ...
        li    s3, 1                     ; the dead lists of this snapshot and the later ones:
        slli  s3, s3, 63                ; what was born no later than it is in use again
        or    a0, s3, s1                ; ...
        la    ra, bswap                 ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        sd    a0, rkey(zero)            ; ...
        sd    zero, rkey+8(zero)        ; ...
osr_d:
        la    a0, t_pend                ; ...
        la    a1, rkey                  ; ...
        li    a2, 16                    ; ...
        li    a3, ST_GT                 ; ...
        la    a4, rkey                  ; ...
        la    a5, dval                  ; ...
        la    ra, st_seek               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        beqz  a0, osr_c                 ; ...
        ld    t0, dval+8(zero)          ; ...
        bgtu  t0, s1, osr_d             ; ...
        ld    t0, dval(zero)            ; (the file system's own pages only: the catalog's
        srli  t0, t0, 32                ; old pages are the snapshots' still)
        ld    t1, fs_ns(zero)           ; ...
        bne   t0, t1, osr_d             ; ...
        li    t0, 1                     ; ...
        sd    t0, in_rel(zero)          ; ...
        la    a0, t_pend                ; ...
        la    a1, rkey                  ; ...
        li    a2, 16                    ; ...
        la    ra, st_del                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        sd    zero, in_rel(zero)        ; ...
        j     osr_d                     ; ...
osr_c:
        la    t0, dkey                  ; the counters as the snapshot has them
        li    t1, '!'                   ; ...
        sb    t1, 0(t0)                 ; ...
        ld    a0, x_dict(zero)          ; ...
        mv    a1, t0                    ; ...
        li    a2, 1                     ; ...
        la    a3, cnt                   ; ...
        la    ra, st_get                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        sd    zero, cnt_d(zero)         ; ...
        la    t6, bm_tail               ; (the boot objects are where they were then)
        jalr  zero, t6, 0               ; (resident code: by its address)

us_bad:
        la    t6, bad                  ; out of the unit: resident code by its address
        jalr  zero, t6, 0               ; ...
us_nofile:
        la    t6, nofile               ; out of the unit: resident code by its address
        jalr  zero, t6, 0               ; ...
        .org  u_s + USLOT               ; (the unit must fit its slot)

; ---- uq: listings: QUERY, TAGS2 (see fsops.s) --------------------------------------------------
u_q:
; QUERY: a listing. data = a tag path (its last component
; may name one file), handle = the cursor: the object the listing has reached
; (0 at first) -> files; in the reply the handle word is the cursor to ask
; with again (0: that was all), the mode word the facets (the other tags the files answered carry),
; and the data: u64 n, then n u32 ids of the path's own tags (padded to a
; word); then per file {u16 record bytes, u16 name length, u32 tags, u64
; size, the name, the file's tag ids (u32 each)}, name and ids each padded to
; a word (a path that names one file: no tag ids). A reply holds as many
; files as fit; its length word is the data's bytes. With mode 1 no file's
; record is answered: the count is of every file, the facets of them all.
uq_query:
        li    a0, 0                     ; ...
        la    ra, get_file              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, uq_reply              ; ...
        li    s7, 0                     ; s7 = the facets
        li    s3, 0                     ; s3 = files
        la    ra, last_tag              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    s4, a0                    ; s4 = 1: the path names one file
        la    s5, sys_buf               ; s5 = output: the path's own tags first
        ld    t0, np(zero)              ; ...
        sd    t0, 0(s5)                 ; ...
        addi  s5, s5, 8                 ; ...
        li    t1, 0                     ; ...
oq_p:
        bgeu  t1, t0, oq_pd             ; ...
        slli  t2, t1, 3                 ; ...
        ld    t2, ptags(t2)             ; ...
        sw    t2, 0(s5)                 ; ...
        sw    zero, 4(s5)               ; ...
        addi  s5, s5, 4                 ; ...
        addi  t1, t1, 1                 ; ...
        j     oq_p                      ; ...
oq_pd:
        addi  s5, s5, 7                 ; ...
        srli  s5, s5, 3                 ; ...
        slli  s5, s5, 3                 ; ...
        la    t0, srv_hdr               ; the cursor
        ld    t1, 8(t0)                 ; ...
        sd    t1, q_cur(zero)           ; ...
        ld    t1, 24(t0)                ; mode bit 0: no records, only the count of every
        andi  t2, t1, 1                 ; file and the facets; bit 1: every file, wherever
        sd    t2, q_fonly(zero)         ; it is (not only the root's, with no directory
        srli  t1, t1, 1                 ; in the path)
        andi  t1, t1, 1                 ; ...
        sd    t1, q_all(zero)           ; ...
        sd    zero, 8(t0)               ; (the cursor answered: none unless more follows)
        beqz  s4, oq_l                  ; ...
        la    ra, lookup                ; one file, with the tags before it
        jalr  ra, ra, 0                 ; (resident code: by its address)
        beqz  a0, uq_nofile             ; ...
        mv    s1, s5                    ; ...
        call  oq_rec                    ; ...
        sw    zero, 4(s1)               ; (one file: no facets, so no tags said)
        li    s3, 1                     ; ...
        j     oq_out                    ; ...
oq_l:
        ld    s6, q_cur(zero)           ; s6 = the last file answered
        la    ra, q_next                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        beqz  a0, oq_out                ; ...
        ld    t0, q_fonly(zero)         ; ...
        bnez  t0, oq_cnt                ; ...
        la    t0, rec                   ; room for its record?
        lhu   t1, R_NL(t0)              ; ...
        addi  t1, t1, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        lhu   t2, R_NTAGS(t0)           ; ...
        slli  t2, t2, 2                 ; ...
        addi  t2, t2, 7                 ; ...
        srli  t2, t2, 3                 ; ...
        slli  t2, t2, 3                 ; ...
        add   t1, t1, t2                ; ...
        addi  t1, t1, 16                ; ...
        add   t1, t1, s5                ; ...
        la    t2, sys_buf + SYS_MAX     ; ...
        bgtu  t1, t2, oq_more           ; ...
        call  oq_rec                    ; ...
oq_cnt:
        la    ra, rec_bits              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        or    s7, s7, a0                ; ...
        addi  s3, s3, 1                 ; ...
        j     oq_l                      ; ...
oq_more:
        la    t0, srv_hdr               ; more follows: from the last one answered
        sd    s6, 8(t0)                 ; ...
oq_out:
        ld    t0, np(zero)              ; the root's listing: every directory is a facet
        ld    t1, nqa(zero)             ; (all bits set)
        or    t0, t0, t1                ; ...
        ld    t1, q_all(zero)           ; ...
        or    t0, t0, t1                ; ...
        or    t0, t0, s4                ; (not for a single file)
        bnez  t0, oq_fx                 ; ...
        li    s7, -1                    ; ...
oq_fx:
        li    s1, 0                     ; facets: not the path's own tags
oq_m:
        ld    t0, np(zero)              ; ...
        bgeu  s1, t0, oq_put            ; ...
        slli  t0, s1, 3                 ; ...
        ld    t1, ptags(t0)             ; ...
        addi  s1, s1, 1                 ; ...
        li    t0, 64                    ; ...
        bgeu  t1, t0, oq_m              ; ...
        li    t0, 1                     ; ...
        sll   t0, t0, t1                ; ...
        li    t2, -1                    ; ...
        xor   t0, t0, t2                ; ...
        and   s7, s7, t0                ; ...
        j     oq_m                      ; ...
oq_put:
        la    t0, srv_hdr               ; ...
        sd    s7, 24(t0)                ; ...
        la    a0, sys_buf               ; ...
        sub   a1, s5, a0                ; ...
        sd    a1, 16(t0)                ; (the length word: the data's bytes)
        la    ra, srv_put               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    a0, s3                    ; ...
        la    t6, reply                 ; ...
        jalr  zero, t6, 0               ; (resident code: by its address)

; oq_rec(): rec's file as a QUERY record at s5, which moves past it
oq_rec:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        la    t0, rec                   ; ...
        lhu   t1, R_NL(t0)              ; ...
        sd    zero, 0(s5)               ; ...
        sh    t1, 2(s5)                 ; ...
        lhu   t2, R_NTAGS(t0)           ; ...
        sw    t2, 4(s5)                 ; ...
        ld    t3, R_SIZE(t0)            ; ...
        sd    t3, 8(s5)                 ; ...
        addi  s1, s5, 16                ; the name, padded with zeros
        addi  t1, t1, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        mv    a0, s1                    ; ...
        mv    a1, t1                    ; ...
        add   s1, s1, t1                ; ...
        la    ra, wzero                 ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    ra, rec_name              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    a2, a1                    ; ...
        mv    a1, a0                    ; ...
        addi  a0, s5, 16                ; ...
        la    ra, srv_bcopy             ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    t0, rec                   ; its tag ids
        lhu   t2, R_NTAGS(t0)           ; ...
        sd    zero, 0(s1)               ; ...
oqr_t:
        beqz  t2, oqr_d                 ; ...
        lwu   t3, R_TAGS(t0)            ; ...
        sw    t3, 0(s1)                 ; ...
        sw    zero, 4(s1)               ; ...
        addi  t0, t0, 4                 ; ...
        addi  s1, s1, 4                 ; ...
        addi  t2, t2, -1                ; ...
        j     oqr_t                     ; ...
oqr_d:
        addi  s1, s1, 7                 ; ...
        srli  s1, s1, 3                 ; ...
        slli  s1, s1, 3                 ; ...
        sub   t0, s1, s5                ; the record's bytes
        sh    t0, 0(s5)                 ; ...
        mv    s5, s1                    ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; TAGS2: as TAGS, without its limits. data = a path (none: every tag; a file:
; its tags), handle = the cursor (0 at first: every tag is listed by id, a
; file's tags in its record's order) -> tags; the reply's handle word is the
; cursor to ask with again (0: that was all); data: per tag {u16 record
; bytes, u16 name length, u32 id, u64 files carrying it, the name padded to
; a word}
uq_tags2:
        li    a0, 0                     ; ...
        la    ra, get_file              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, uq_reply              ; ...
        li    s3, 0                     ; s3 = records
        la    s5, sys_buf               ; s5 = the record
        la    t0, srv_hdr               ; s1 = the cursor
        ld    s1, 8(t0)                 ; ...
        sd    zero, 8(t0)               ; ...
        ld    t0, nmlen(zero)           ; a file?
        beqz  t0, o2_all                ; ...
        la    ra, lookup                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        beqz  a0, uq_nofile             ; ...
o2_f:
        la    t0, rec                   ; ...
        lhu   t1, R_NTAGS(t0)           ; ...
        bgeu  s1, t1, o2_done           ; ...
        slli  t1, s1, 2                 ; ...
        add   t1, t1, t0                ; ...
        lwu   s4, R_TAGS(t1)            ; s4 = the tag
        mv    a0, s4                    ; ...
        la    ra, tag_name              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    s2, a0                    ; ...
        addi  s1, s1, 1                 ; ...
        bltz  s2, o2_f                  ; ...
        call  o2_rec                    ; ...
        bnez  a0, o2_f                  ; ...
        addi  s1, s1, -1                ; no room: from this one next time
        j     o2_more                   ; ...
o2_all:
        mv    a0, s1                    ; the next tag by id
        la    ra, rk_tag                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        ld    a0, x_dict(zero)          ; ...
        la    a1, rkey                  ; ...
        li    a2, 5                     ; ...
        li    a3, ST_GT                 ; ...
        la    a4, rkey                  ; ...
        la    a5, tnbuf                 ; ...
        la    ra, st_seek               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        beqz  a0, o2_done               ; ...
        la    t0, rkey                  ; ...
        lbu   t1, 0(t0)                 ; ...
        li    t2, 'T'                   ; ...
        bne   t1, t2, o2_done           ; ...
        lbu   s4, 1(t0)                 ; its id
        slli  s4, s4, 8                 ; ...
        lbu   t1, 2(t0)                 ; ...
        or    s4, s4, t1                ; ...
        slli  s4, s4, 8                 ; ...
        lbu   t1, 3(t0)                 ; ...
        or    s4, s4, t1                ; ...
        slli  s4, s4, 8                 ; ...
        lbu   t1, 4(t0)                 ; ...
        or    s4, s4, t1                ; ...
        ld    s2, sk_vl(zero)           ; ...
        call  o2_rec                    ; ...
        beqz  a0, o2_more               ; ...
        mv    s1, s4                    ; ...
        j     o2_all                    ; ...
o2_more:
        la    t0, srv_hdr               ; ...
        sd    s1, 8(t0)                 ; ...
        bnez  s1, o2_done               ; (a cursor of 0 would mean the end: a file's
        li    t1, -1                    ; first tag did not fit, which cannot be)
        sd    t1, 8(t0)                 ; ...
o2_done:
        la    a0, sys_buf               ; ...
        sub   a1, s5, a0                ; ...
        la    t0, srv_hdr               ; (the length word: the data's bytes)
        sd    a1, 16(t0)                ; ...
        la    ra, srv_put               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    a0, s3                    ; ...
        la    t6, reply                 ; ...
        jalr  zero, t6, 0               ; (resident code: by its address)

; o2_rec(): the tag s4, named in tnbuf (s2 bytes), as a record at s5 -> a0 =
; 1 (s5 and s3 move on), or 0 when the reply has no room for it
o2_rec:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        addi  t0, s2, 7                 ; ...
        srli  t0, t0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        addi  t0, t0, 16                ; ...
        add   t1, t0, s5                ; ...
        la    t2, sys_buf + SYS_MAX     ; ...
        li    a0, 0                     ; ...
        bgtu  t1, t2, o2r_ret           ; ...
        sh    t0, 0(s5)                 ; ...
        sh    s2, 2(s5)                 ; ...
        sw    s4, 4(s5)                 ; ...
        la    a0, tnbuf                 ; its count
        mv    a1, s2                    ; ...
        la    ra, dk_tag                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        ld    a0, x_dict(zero)          ; ...
        la    a1, dkey                  ; ...
        ld    a2, dk_len(zero)          ; ...
        la    a3, dval                  ; ...
        la    ra, st_get                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        ld    t0, dval+8(zero)          ; ...
        sd    t0, 8(s5)                 ; ...
        lhu   t1, 0(s5)                 ; the name, padded with zeros
        add   t1, t1, s5                ; ...
        sd    zero, -8(t1)              ; ...
        addi  a0, s5, 16                ; ...
        la    a1, tnbuf                 ; ...
        mv    a2, s2                    ; ...
        mv    s5, t1                    ; ...
        la    ra, srv_bcopy             ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        addi  s3, s3, 1                 ; ...
        li    a0, 1                     ; ...
o2r_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

uq_reply:
        la    t6, reply                ; out of the unit: resident code by its address
        jalr  zero, t6, 0               ; ...
uq_nofile:
        la    t6, nofile               ; out of the unit: resident code by its address
        jalr  zero, t6, 0               ; ...
        .org  u_q + USLOT               ; (the unit must fit its slot)

; ---- ut: TAG, UNTAG, RENAME, CWD (see fsops.s) ------------------------------------------------------
u_t:
; TAG / UNTAG: data = a path, a zero byte, a tag name
ut_tag:
        li    s4, 1                     ; s4 = 1 tag, 0 untag
        j     otg_go                    ; ...
ut_untag:
        li    s4, 0                     ; ...
otg_go:
        la    ra, tx_sync               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    ra, get_two               ; the path, and the tag's name
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, ut_reply              ; ...
        mv    s2, a0                    ; s2 = the tag's name
        mv    s3, a1                    ; s3 = its length
        li    a0, 0                     ; the path's tags must exist
        la    ra, parse_file            ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, ut_reply              ; ...
        ld    t0, nmlen(zero)           ; it must name a file
        li    a0, -1                    ; ...
        beqz  t0, ut_reply              ; ...
        la    ra, lookup                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        beqz  a0, ut_nofile             ; ...
        mv    a0, s2                    ; the tag (created when tagging)
        mv    a1, s3                    ; ...
        mv    a2, s4                    ; ...
        la    ra, tag_ref               ; a0 = its id or < 0
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, ut_reply              ; ...
        mv    s1, a0                    ; ...
        la    ra, rec_hastag            ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        beqz  s4, otg_un                ; ...
        bgez  a0, ut_ok                 ; it carries it already
        sd    zero, np(zero)            ; tag: the one tag joins its own
        mv    a0, s1                    ; ...
        la    a1, np                    ; ...
        la    ra, qt_add                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    ra, fs_addtags            ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, ut_oo_fail            ; ...
        j     otg_done                  ; ...
otg_un:
        bltz  a0, ut_ok                 ; it does not carry it
        mv    s3, a0                    ; s3 = where the tag is in its record
        la    t0, rec                   ; its last directory: it goes to the root, where
        lhu   s2, R_NTAGS(t0)           ; its name must be free
        addi  s2, s2, -1                ; s2 = 0: the last one
        bnez  s2, otg_u1                ; ...
        li    a0, 0                     ; ...
        la    ra, nm_at                 ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bnez  a0, ut_bad                ; ...
otg_u1:
        mv    a0, s1                    ; its name leaves the directory
        li    a1, 0                     ; ...
        la    ra, nm_set                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    a0, s3                    ; ...
        la    ra, rec_deltag            ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        li    a0, 0                     ; ...
        mv    a1, s1                    ; ...
        la    ra, idx_tag               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bnez  s2, otg_u2                ; ...
        li    a0, 1                     ; ...
        la    ra, root_set              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
otg_u2:
        la    ra, rec_save              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    a0, s1                    ; (an unused tag goes)
        li    a1, -1                    ; ...
        la    ra, tag_count             ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
otg_done:
        la    ra, fs_commit             ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    t6, ok                    ; ...
        jalr  zero, t6, 0               ; (resident code: by its address)

; CWD: the requester's current tag path (mode 0 get, 1 set, 2 inherit)
ut_cwd:
        la    t0, srv_hdr               ; mode
        ld    t1, 24(t0)                ; ...
        beqz  t1, ocw_get               ; 0: get
        li    t2, 2                     ; 2: inherit
        beq   t1, t2, ocw_inh           ; ...
        li    t2, 1                     ; 1: set
        bne   t1, t2, ut_bad            ; ...
        la    ra, get_raw               ; a0 = the length of the new path
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, ut_reply              ; ...
        beqz  a0, ocw_root              ; none: "/"
        mv    a1, a0                    ; resolved (relative to the current one)
        la    a0, rbuf                  ; ...
        la    ra, setpath               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        li    s1, 0                     ; s1 = cursor
        sd    zero, np(zero)            ; the tags of the view, and those it excludes
        sd    zero, nx(zero)            ; ...
ocw_c:
        mv    a0, s1                    ; every component: a tag, or "-" and a tag
        la    ra, comp                  ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        beqz  a1, ocw_chk               ; all seen
        mv    s1, a2                    ; ...
        la    s2, np                    ; s2 = the list it joins
        lbu   t0, 0(a0)                 ; ...
        li    t1, '-'                   ; ...
        bne   t0, t1, ocw_t             ; ...
        la    s2, nx                    ; ...
        addi  a0, a0, 1                 ; ...
        addi  a1, a1, -1                ; ...
ocw_t:
        la    ra, tag_find              ; a0 = its id, or -1
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, ocw_none              ; no such tag
        mv    a1, s2                    ; ...
        la    ra, qt_add                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, ut_reply              ; ...
        j     ocw_c                     ; ...
ocw_chk:
        ld    t1, plen(zero)            ; ".." all the way: "/"
        beqz  t1, ocw_root              ; ...
        li    a0, -1                    ; too long to keep
        li    t2, CWDMAX                ; ...
        bgtu  t1, t2, ut_reply          ; ...
        sd    zero, q_cur(zero)         ; a file in that view? (no empty views)
        la    ra, q_next                ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bnez  a0, ocw_set               ; ...
ocw_none:
        li    a0, -4                    ; no such tag (or nothing carries them all)
        la    t6, reply                 ; ...
        jalr  zero, t6, 0               ; (resident code: by its address)
ocw_set:
        la    ra, srv_pid               ; s1 = the requester
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    s1, a0                    ; ...
        la    ra, cwd_find              ; its entry, or a free one
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bgez  a0, ocw_have              ; ...
        li    a0, 0                     ; ...
        la    ra, cwd_find              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    t0, a0                    ; ...
        li    a0, -6                    ; none: the table is full
        bltz  t0, ut_reply              ; ...
        mv    a0, t0                    ; ...
ocw_have:
        mv    s2, a0                    ; ...
        slli  t0, s2, 3                 ; ...
        sd    s1, cwdp(t0)              ; ...
        ld    a2, plen(zero)            ; the new path
        sd    a2, cwdt(zero)            ; ...
        la    a0, cwdt + 8              ; ...
        la    a1, pbuf                  ; ...
        la    ra, srv_bcopy             ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    a0, s2                    ; ...
        la    ra, cwd_store             ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        j     ocw_get                   ; answered as a get
ocw_root:
        la    ra, srv_pid               ; "/": no entry
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    ra, cwd_drop              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
ocw_get:
        la    ra, srv_pid               ; the requester's entry
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    ra, cwd_find              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, ocw_slash             ; none: "/"
        la    ra, cwd_load              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        ld    s1, cwdt(zero)            ; its text -> the request
        la    a0, cwdt + 8              ; ...
        mv    a1, s1                    ; ...
        la    ra, srv_put               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        mv    a0, s1                    ; its length
        la    t6, reply                 ; ...
        jalr  zero, t6, 0               ; (resident code: by its address)
ocw_slash:
        la    a0, sys_buf               ; "/"
        li    t0, '/'                   ; ...
        sd    t0, 0(a0)                 ; ...
        li    a1, 1                     ; ...
        la    ra, srv_put               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        li    a0, 1                     ; ...
        la    t6, reply                 ; ...
        jalr  zero, t6, 0               ; (resident code: by its address)
ocw_inh:
        la    ra, srv_pid               ; from proc only
        jalr  ra, ra, 0                 ; (resident code: by its address)
        li    t0, PROC_PID              ; ...
        bne   a0, t0, ut_bad            ; ...
        la    a0, sys_buf               ; parent, child
        li    a1, 16                    ; ...
        la    ra, srv_get               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    t0, sys_buf               ; ...
        ld    s1, 0(t0)                 ; s1 = the parent
        ld    s2, 8(t0)                 ; s2 = the child
        mv    a0, s2                    ; a stale entry of the child's goes
        la    ra, cwd_drop              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        beqz  s2, ut_ok                 ; (a child of pid 0: nothing)
        beqz  s1, ut_ok                 ; ...
        mv    a0, s1                    ; the parent's
        la    ra, cwd_find              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, ut_ok                 ; at "/": so is the child
        la    ra, cwd_load              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        li    a0, 0                     ; a free entry
        la    ra, cwd_find              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, ut_ok                 ; none: the child starts at "/"
        slli  t0, a0, 3                 ; a copy of the parent's, for the child
        sd    s2, cwdp(t0)              ; ...
        la    ra, cwd_store             ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    t6, ok                    ; ...
        jalr  zero, t6, 0               ; (resident code: by its address)

; RENAME: data = a path, a zero byte, the new path
ut_rename:
        la    ra, tx_sync               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        la    ra, get_two               ; the path, and the new one
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, ut_reply              ; ...
        mv    s2, a0                    ; s2, s3 = the new path
        mv    s3, a1                    ; ...
        li    a0, 0                     ; the old path's tags must exist
        la    ra, parse_file            ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, ut_reply              ; ...
        ld    t0, nmlen(zero)           ; it must name a file
        li    a0, -1                    ; ...
        beqz  t0, ut_reply              ; ...
        la    ra, lookup                ; s1 = the file
        jalr  ra, ra, 0                 ; (resident code: by its address)
        beqz  a0, ut_nofile             ; ...
        mv    s1, a0                    ; ...
        la    t0, rec                   ; (not a boot object)
        lbu   t0, R_FLAGS(t0)           ; ...
        andi  t0, t0, 1                 ; ...
        bnez  t0, ut_bad                ; ...
        mv    a0, s2                    ; the new path -> pbuf, resolved (it is
        mv    a1, s3                    ; in rbuf, apart from pbuf)
        la    ra, setpath               ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        li    a0, 1                     ; its tags are created if need be
        la    ra, parse_file            ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
        bltz  a0, ut_oo_fail            ; ...
        ld    t0, nmlen(zero)           ; it must name a file
        li    a0, -1                    ; ...
        beqz  t0, ut_oo_fail            ; ...
        la    ra, find                  ; another file of the new name goes
        jalr  ra, ra, 0                 ; (resident code: by its address)
        beqz  a0, orn_name              ; none
        beq   a0, s1, orn_tags          ; the file itself: only tags to add
        la    ra, rec_load              ; ...
        jalr  ra, ra, 0                 ; (resident code: by its address)
