; =============================================================================
; store.s: the store's pages and trees (included by fs.s)
; =============================================================================
;
; The disk is a store (doc/strata-fs-proposal.md; the format is spelled out
; at the top of tools/stdb/store.c, whose routines these follow one for
; one): copy-on-write B+trees in pages of st_ps bytes.
;
; Pages in memory. The trees are larger than this program's D-LS, so a page
; is in one of three places:
;   - the disk;
;   - a FRAME of the cache, in far memory (the I/O buffer c5 from FBASE on:
;     NF frames of 4 KiB). The device reads and writes frames directly;
;   - one of NB page BUFFERS in the D-LS, where the code works on it.
; P(page) answers the address of a buffer holding the page, fetching it from
; its frame (and that from the disk) if need be, in place of the buffer used
; longest ago; a changed buffer goes back to its frame first, with its
; checksum. So an address P gave is good only until the second P after it:
; code that calls anything which may call P asks again. Frames of pages
; changed since the last commit are DIRTY: the commit writes them, and so
; does the cache when it has no clean frame left to give (they go to free
; pages, so writing them early changes nothing a reader of the disk sees).
;
; A tree is two words in the D-LS: its root page and its height (0, 0: empty).
;
; Registers: every routine keeps s1.. and sp; a0.., t0.. are the caller's to
; save. Scratch that is static (wpath, cellbuf, bcbuf, the page copy in
; in_buf): tree changes do not nest. Reading (st_get, st_seek) may happen
; inside a change, and has its own path.

NF      = 124                           ; cache frames in far memory
FBASE   = 0x4000                        ; the first frame's offset in c5
F_DIRTY = 1                             ; frame: changed since the last commit
F_REF   = 2                             ; frame: used lately (the clock's second chance)
K_BRANCH = 1                            ; page kinds
K_LEAF  = 2                             ; ...
ST_GE   = 0                             ; st_seek: at or after the key
ST_GT   = 1                             ; after
ST_LE   = 2                             ; at or before
ST_LT   = 3                             ; before
SUM_K   = 0x9E3779B97F4A7C15            ; the checksum: its seed's multiplier,
SUM_0   = 0xCBF29CE484222325            ;   its start,
SUM_M   = 0x100000001B3                 ;   and the multiplier of every word

        .data                           ; data Local Store
        .align 8                        ; ...
st_ps:     .dword 0                     ; the page size
st_bpp:    .dword 0                     ; blocks per page
st_txn:    .dword 0                     ; the commit being made
b_no:      .space NB * 8                ; page buffers: the page each holds (0: none)
b_fl:      .space NB * 8                ; bit 0: changed since it was fetched; bit 1: no header (stream data)
b_st:      .space NB * 8                ; when it was last asked for
b_clock:   .dword 0                     ; the count of askings
f_no:      .space NF * 8                ; frames: the page each holds (0: free)
f_fl:      .space NF + 4                ; F_DIRTY, F_REF
f_hand:    .dword 0                     ; the clock's hand
rpath:     .space 16 * 16               ; st_seek's way down: page, index
wpath:     .space 16 * 16               ; a change's way down
w_tree:    .dword 0                     ; the tree being changed
sk_kl:     .dword 0                     ; st_seek's answer: key length,
sk_vl:     .dword 0                     ;   value length,
sk_fl:     .dword 0                     ;   the value's flag
ia_lvl:    .dword 0                     ; ins_at: the level (index in wpath),
ia_idx:    .dword 0                     ;   the place in its page,
ia_len:    .dword 0                     ;   the cell's length (the cell is in cellbuf)
cellbuf:   .space 1024                  ; a cell being put
bcbuf:     .space 528                   ; a branch cell (a separator going up)
first16:   .space 16                    ; a branch's first cell: no key

        .text                           ; instruction Local Store

; ---- small things ------------------------------------------------------------------

; bswap(a0) -> a0: its eight bytes in the other order
bswap:
        li    t0, 8                     ; ...
        li    t1, 0                     ; ...
bsw_l:
        slli  t1, t1, 8                 ; ...
        andi  t2, a0, 255               ; ...
        or    t1, t1, t2                ; ...
        srli  a0, a0, 8                 ; ...
        addi  t0, t0, -1                ; ...
        bnez  t0, bsw_l                 ; ...
        mv    a0, t1                    ; ...
        ret                             ; ...

; wcopy(a0 = to, a1 = from, a2 = bytes, a multiple of 8): forwards, by words
wcopy:
        add   a2, a2, a1                ; the end
wc_l:
        beq   a1, a2, wc_ret            ; ...
        ld    t0, 0(a1)                 ; ...
        sd    t0, 0(a0)                 ; ...
        addi  a1, a1, 8                 ; ...
        addi  a0, a0, 8                 ; ...
        j     wc_l                      ; ...
wc_ret:
        ret                             ; ...

; wzero(a0 = address, a1 = bytes, a multiple of 8)
wzero:
        add   a1, a1, a0                ; the end
wz_l:
        beq   a0, a1, wz_ret            ; ...
        sd    zero, 0(a0)               ; ...
        addi  a0, a0, 8                 ; ...
        j     wz_l                      ; ...
wz_ret:
        ret                             ; ...

; sum(a0 = address, a1 = bytes, a2 = seed) -> a0: the checksum of a page or a
; meta block: every word but the first
sum:
        li    t0, SUM_K                 ; ...
        mul   t1, a2, t0                ; ...
        li    t0, SUM_0                 ; ...
        add   t1, t1, t0                ; ...
        li    t0, SUM_M                 ; ...
        addi  t2, a0, 8                 ; ...
        add   t3, a0, a1                ; ...
sum_l:
        ld    t4, 0(t2)                 ; ...
        xor   t1, t1, t4                ; ...
        mul   t1, t1, t0                ; ...
        addi  t2, t2, 8                 ; ...
        bne   t2, t3, sum_l             ; ...
        srli  t0, t1, 32                ; ...
        xor   a0, t1, t0                ; ...
        ret                             ; ...

; kcmp(a0 = a key, a1 = its length, a2 = another, a3 = its length) -> a0 < 0,
; 0, > 0: as bytes, the shorter first when one begins the other
kcmp:
        mv    t0, a1                    ; the shorter length
        bleu  a1, a3, kc_l              ; ...
        mv    t0, a3                    ; ...
kc_l:
        beqz  t0, kc_len                ; equal so far
        lbu   t1, 0(a0)                 ; ...
        lbu   t2, 0(a2)                 ; ...
        bne   t1, t2, kc_diff           ; ...
        addi  a0, a0, 1                 ; ...
        addi  a2, a2, 1                 ; ...
        addi  t0, t0, -1                ; ...
        j     kc_l                      ; ...
kc_len:
        sub   a0, a1, a3                ; ...
        ret                             ; ...
kc_diff:
        sub   a0, t1, t2                ; ...
        ret                             ; ...

; ---- the cache ---------------------------------------------------------------------

; f_find(a0 = page) -> a0 = its frame, or -1
f_find:
        li    t0, 0                     ; ...
        li    t1, NF * 8                ; ...
ff_l:
        ld    t2, f_no(t0)              ; ...
        beq   t2, a0, ff_yes            ; ...
        addi  t0, t0, 8                 ; ...
        bne   t0, t1, ff_l              ; ...
        li    a0, -1                    ; ...
        ret                             ; ...
ff_yes:
        srli  a0, t0, 3                 ; ...
        ret                             ; ...

; f_write(a0 = frame): its page goes to the disk; it is clean
f_write:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        mv    s1, a0                    ; ...
        slli  t0, s1, 3                 ; its page -> first block
        ld    a1, f_no(t0)              ; ...
        ld    a2, st_bpp(zero)          ; ...
        mul   a1, a1, a2                ; ...
        slli  a3, s1, 12                ; where the frame is
        li    t0, FBASE                 ; ...
        add   a3, a3, t0                ; ...
        li    a0, 2                     ; write
        li    a4, 5                     ; ...
        call  blk                       ; ...
        bnez  a0, st_die                ; the device refused
        lbu   t0, f_fl(s1)              ; clean
        andi  t0, t0, F_REF             ; ...
        sb    t0, f_fl(s1)              ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; f_alloc(a0 = page) -> a0 = a frame for it: a free one, else one the clock
; finds neither used lately nor dirty; when two rounds find none, a dirty one
; is written and taken
f_alloc:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        mv    s1, a0                    ; s1 = the page
        li    a0, 0                     ; a free frame?
        call  f_find                    ; ...
        mv    s2, a0                    ; ...
        bgez  s2, fa_take               ; ...
        li    s3, 0                     ; s3 = frames looked at
fa_l:
        ld    s2, f_hand(zero)          ; the next frame
        addi  t0, s2, 1                 ; ...
        li    t1, NF                    ; ...
        bltu  t0, t1, fa_h              ; ...
        li    t0, 0                     ; ...
fa_h:
        sd    t0, f_hand(zero)          ; ...
        addi  s3, s3, 1                 ; ...
        lbu   t0, f_fl(s2)              ; used lately: not this time
        andi  t1, t0, F_REF             ; ...
        beqz  t1, fa_d                  ; ...
        andi  t0, t0, F_DIRTY           ; ...
        sb    t0, f_fl(s2)              ; ...
        j     fa_l                      ; ...
fa_d:
        andi  t1, t0, F_DIRTY           ; clean: this one
        beqz  t1, fa_take               ; ...
        li    t1, 2 * NF                ; dirty: only when nothing else is left
        bltu  s3, t1, fa_l              ; ...
        mv    a0, s2                    ; ...
        call  f_write                   ; ...
fa_take:
        slli  t0, s2, 3                 ; it holds the page now
        sd    s1, f_no(t0)              ; ...
        li    t0, F_REF                 ; ...
        sb    t0, f_fl(s2)              ; ...
        mv    a0, s2                    ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; b_flush(a0 = buffer): a changed buffer -> its frame, with its checksum
b_flush:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        mv    s1, a0                    ; s1 = the buffer
        slli  s2, s1, 12                ; s2 = its address
        la    t0, bufs                  ; ...
        add   s2, s2, t0                ; ...
        slli  t0, s1, 3                 ; a tree page: its checksum
        ld    t1, b_fl(t0)              ; ...
        andi  t1, t1, 2                 ; ...
        bnez  t1, bf_frame              ; ...
        mv    a0, s2                    ; ...
        ld    a1, st_ps(zero)           ; ...
        ld    a2, b_no(t0)              ; ...
        call  sum                       ; ...
        sd    a0, 0(s2)                 ; ...
bf_frame:
        slli  t0, s1, 3                 ; its frame, or a new one
        ld    a0, b_no(t0)              ; ...
        call  f_find                    ; ...
        mv    s3, a0                    ; ...
        bgez  s3, bf_put                ; ...
        slli  t0, s1, 3                 ; ...
        ld    a0, b_no(t0)              ; ...
        call  f_alloc                   ; ...
        mv    s3, a0                    ; ...
bf_put:
        li    t0, F_DIRTY + F_REF       ; ...
        sb    t0, f_fl(s3)              ; ...
        slli  t1, s3, 12                ; ...
        li    t0, FBASE                 ; ...
        add   t1, t1, t0                ; ...
        ld    t2, st_ps(zero)           ; ...
        tput  tg1, s2, c5, t1, t2       ; ...
        twait 1 << 1                    ; ...
        slli  t0, s1, 3                 ; the buffer and the frame agree
        ld    t1, b_fl(t0)              ; ...
        andi  t1, t1, 2                 ; ...
        sd    t1, b_fl(t0)              ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; b_load(a0 = buffer): the page b_no names -> the buffer, from its frame, the
; frame from the disk if it is in none (a tree page is then checked)
b_load:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        mv    s1, a0                    ; s1 = the buffer
        slli  s2, s1, 12                ; s2 = its address
        la    t0, bufs                  ; ...
        add   s2, s2, t0                ; ...
        li    s4, 0                     ; s4 = 1: fresh from the disk
        slli  t0, s1, 3                 ; ...
        ld    a0, b_no(t0)              ; ...
        call  f_find                    ; ...
        mv    s3, a0                    ; s3 = the frame
        bgez  s3, bl_have               ; ...
        slli  t0, s1, 3                 ; a frame, and the page into it
        ld    a0, b_no(t0)              ; ...
        call  f_alloc                   ; ...
        mv    s3, a0                    ; ...
        li    s4, 1                     ; ...
        slli  t0, s1, 3                 ; ...
        ld    a1, b_no(t0)              ; ...
        ld    t1, st_npages(zero)       ; (on the disk?)
        bgeu  a1, t1, st_die            ; ...
        ld    a2, st_bpp(zero)          ; ...
        mul   a1, a1, a2                ; ...
        slli  a3, s3, 12                ; ...
        li    t0, FBASE                 ; ...
        add   a3, a3, t0                ; ...
        li    a0, 1                     ; read
        li    a4, 5                     ; ...
        call  blk                       ; ...
        bnez  a0, st_die                ; ...
bl_have:
        lbu   t0, f_fl(s3)              ; used
        ori   t0, t0, F_REF             ; ...
        sb    t0, f_fl(s3)              ; ...
        slli  t1, s3, 12                ; ...
        li    t0, FBASE                 ; ...
        add   t1, t1, t0                ; ...
        ld    t2, st_ps(zero)           ; ...
        tget  tg1, s2, c5, t1, t2       ; ...
        twait 1 << 1                    ; ...
        beqz  s4, bl_ret                ; it was in the cache: checked before
        slli  t0, s1, 3                 ; stream data has no checksum
        ld    t1, b_fl(t0)              ; ...
        andi  t1, t1, 2                 ; ...
        bnez  t1, bl_ret                ; ...
        mv    a0, s2                    ; ...
        ld    a1, st_ps(zero)           ; ...
        ld    a2, b_no(t0)              ; ...
        call  sum                       ; ...
        ld    t0, 0(s2)                 ; as the page says?
        bne   a0, t0, st_die            ; ...
        slli  t0, s1, 3                 ; and it is this page?
        ld    t1, b_no(t0)              ; ...
        ld    t0, 8(s2)                 ; ...
        bne   t0, t1, st_die            ; ...
bl_ret:
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 40                ; ...
        ret                             ; ...

; P(a0 = page) -> a0 = a buffer holding it. PW: and it will be changed. PN: a
; new page, all zeros, not fetched. PR, PRW, PRN: the same for stream data.
P:
        li    a1, 0                     ; ...
        j     b_get                     ; ...
PW:
        li    a1, 1                     ; ...
        j     b_get                     ; ...
PR:
        li    a1, 2                     ; ...
        j     b_get                     ; ...
PRW:
        li    a1, 3                     ; ...
        j     b_get                     ; ...
PN:
        li    a1, 5                     ; ...
        j     b_get                     ; ...
PRN:
        li    a1, 7                     ; ...
; b_get(a0 = page, a1 = bit 0 it will change, bit 1 stream data, bit 2 new)
b_get:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        mv    s1, a0                    ; s1 = the page
        mv    s2, a1                    ; s2 = how
        li    s3, 0                     ; in a buffer already?
bg_s:
        ld    t1, b_no(s3)              ; ...
        beq   t1, s1, bg_hit            ; ...
        addi  s3, s3, 8                 ; ...
        li    t0, NB * 8                ; ...
        bne   s3, t0, bg_s              ; ...
        li    s3, 0                     ; no: the buffer asked for longest ago
        li    t0, 8                     ; ...
        li    t2, NB * 8                ; ...
bg_v:
        ld    t1, b_st(t0)              ; ...
        ld    t3, b_st(s3)              ; ...
        bgeu  t1, t3, bg_vn             ; ...
        mv    s3, t0                    ; ...
bg_vn:
        addi  t0, t0, 8                 ; ...
        bne   t0, t2, bg_v              ; ...
        ld    t1, b_fl(s3)              ; what it holds goes back to its frame
        andi  t1, t1, 1                 ; ...
        beqz  t1, bg_new                ; ...
        srli  a0, s3, 3                 ; ...
        call  b_flush                   ; ...
bg_new:
        sd    s1, b_no(s3)              ; it holds the page now
        andi  t1, s2, 3                 ; ...
        sd    t1, b_fl(s3)              ; ...
        andi  t1, s2, 4                 ; a new page: zeros
        bnez  t1, bg_zero               ; ...
        srli  a0, s3, 3                 ; ...
        call  b_load                    ; ...
        j     bg_st                     ; ...
bg_zero:
        slli  a0, s3, 9                 ; ...
        la    t0, bufs                  ; ...
        add   a0, a0, t0                ; ...
        li    a1, 4096                  ; ...
        call  wzero                     ; ...
        j     bg_st                     ; ...
bg_hit:
        andi  t1, s2, 1                 ; to be changed?
        ld    t2, b_fl(s3)              ; ...
        or    t2, t2, t1                ; ...
        sd    t2, b_fl(s3)              ; ...
bg_st:
        ld    t0, b_clock(zero)         ; asked for now
        addi  t0, t0, 1                 ; ...
        sd    t0, b_clock(zero)         ; ...
        sd    t0, b_st(s3)              ; ...
        slli  a0, s3, 9                 ; its address
        la    t0, bufs                  ; ...
        add   a0, a0, t0                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; b_drop(a0 = page): the page is free: no buffer and no frame holds it
b_drop:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        li    t0, 0                     ; a buffer?
        li    t1, NB * 8                ; ...
bd_l:
        ld    t2, b_no(t0)              ; ...
        bne   t2, a0, bd_n              ; ...
        sd    zero, b_no(t0)            ; ...
        sd    zero, b_fl(t0)            ; ...
        sd    zero, b_st(t0)            ; ...
bd_n:
        addi  t0, t0, 8                 ; ...
        bne   t0, t1, bd_l              ; ...
        call  f_find                    ; a frame?
        bltz  a0, bd_ret                ; ...
        sb    zero, f_fl(a0)            ; ...
        slli  a0, a0, 3                 ; ...
        sd    zero, f_no(a0)            ; ...
bd_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; b_sync(): every changed buffer -> its frame (the buffers stay)
b_sync:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        li    s1, 0                     ; ...
bs_l:
        slli  t0, s1, 3                 ; ...
        ld    t1, b_fl(t0)              ; ...
        andi  t1, t1, 1                 ; ...
        beqz  t1, bs_n                  ; ...
        mv    a0, s1                    ; ...
        call  b_flush                   ; ...
bs_n:
        addi  s1, s1, 1                 ; ...
        li    t0, NB                    ; ...
        bne   s1, t0, bs_l              ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; c_write(): every dirty frame -> the disk
c_write:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        li    s1, 0                     ; ...
cw_l:
        lbu   t0, f_fl(s1)              ; ...
        andi  t0, t0, F_DIRTY           ; ...
        beqz  t0, cw_n                  ; ...
        mv    a0, s1                    ; ...
        call  f_write                   ; ...
cw_n:
        addi  s1, s1, 1                 ; ...
        li    t0, NF                    ; ...
        bne   s1, t0, cw_l              ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; c_reset(): the cache holds nothing (what it held of the commit under way is lost)
c_reset:
        li    t0, 0                     ; ...
        li    t1, NB * 8                ; ...
cr_b:
        sd    zero, b_no(t0)            ; ...
        sd    zero, b_fl(t0)            ; ...
        sd    zero, b_st(t0)            ; ...
        addi  t0, t0, 8                 ; ...
        bne   t0, t1, cr_b              ; ...
        li    t0, 0                     ; ...
        li    t1, NF                    ; ...
cr_f:
        slli  t2, t0, 3                 ; ...
        sd    zero, f_no(t2)            ; ...
        sb    zero, f_fl(t0)            ; ...
        addi  t0, t0, 1                 ; ...
        bne   t0, t1, cr_f              ; ...
        ret                             ; ...

; ---- a page's cells ----------------------------------------------------------------

; csize(a0 = page, a1 = cell) -> a0 = the cell's bytes
csize:
        lhu   t0, 0(a1)                 ; the key, padded
        addi  t0, t0, 7                 ; ...
        srli  t0, t0, 3         ; (down to a whole word)
        slli  t0, t0, 3         ; ...
        lbu   t1, 24(a0)                ; ...
        li    t2, K_LEAF                ; ...
        beq   t1, t2, cs_leaf           ; ...
        addi  a0, t0, 16                ; a branch cell
        ret                             ; ...
cs_leaf:
        lhu   t1, 2(a1)                 ; and the value, padded
        slli  t1, t1, 49                ; ...
        srli  t1, t1, 49                ; ...
        addi  t1, t1, 7                 ; ...
        srli  t1, t1, 3         ; (down to a whole word)
        slli  t1, t1, 3         ; ...
        add   a0, t0, t1                ; ...
        addi  a0, a0, 8                 ; ...
        ret                             ; ...

; node_ins(a0 = page, a1 = index, a2 = cell, a3 = its bytes): the cell goes in
; at the index; there must be room for it and its slot
node_ins:
        lhu   t0, 26(a0)                ; t0 = cells
        lhu   t1, 28(a0)                ; t1 = where the cell goes
        sub   t1, t1, a3                ; ...
        sh    t1, 28(a0)                ; ...
        add   t2, a0, t1                ; ...
        add   t3, a2, a3                ; ...
ni_c:
        beq   a2, t3, ni_s              ; ...
        ld    t4, 0(a2)                 ; ...
        sd    t4, 0(t2)                 ; ...
        addi  a2, a2, 8                 ; ...
        addi  t2, t2, 8                 ; ...
        j     ni_c                      ; ...
ni_s:
        slli  t2, t0, 1                 ; the slots from the index on move up
        add   t2, t2, a0                ; ...
        addi  t2, t2, 32                ; ...
        slli  t3, a1, 1                 ; ...
        add   t3, t3, a0                ; ...
        addi  t3, t3, 32                ; ...
ni_m:
        beq   t2, t3, ni_p              ; ...
        lhu   t4, -2(t2)                ; ...
        sh    t4, 0(t2)                 ; ...
        addi  t2, t2, -2                ; ...
        j     ni_m                      ; ...
ni_p:
        sh    t1, 0(t3)                 ; its slot
        addi  t0, t0, 1                 ; ...
        sh    t0, 26(a0)                ; ...
        ret                             ; ...

; node_rm(a0 = page, a1 = index): the cell there goes; the cells below it
; close the gap, so the free space stays in one piece
node_rm:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        mv    s1, a0                    ; ...
        slli  t0, a1, 1                 ; t3 = the cell's offset
        add   t0, t0, s1                ; ...
        lhu   t3, 32(t0)                ; ...
        sd    a1, 16(sp)                ; ...
        add   a1, s1, t3                ; t5 = its bytes
        mv    a0, s1                    ; ...
        call  csize                     ; ...
        mv    t5, a0                    ; ...
        ld    a1, 16(sp)                ; ...
        slli  t0, a1, 1                 ; ...
        add   t0, t0, s1                ; ...
        lhu   t3, 32(t0)                ; ...
        lhu   t0, 26(s1)                ; t0 = cells
        lhu   t1, 28(s1)                ; t1 = where the cells start
        add   t4, s1, t3                ; [start, cell) moves up by its bytes, from the top
        add   t6, t4, t5                ; ...
        add   a2, s1, t1                ; ...
nr_m:
        beq   t4, a2, nr_s              ; ...
        addi  t4, t4, -8                ; ...
        addi  t6, t6, -8                ; ...
        ld    a3, 0(t4)                 ; ...
        sd    a3, 0(t6)                 ; ...
        j     nr_m                      ; ...
nr_s:
        addi  t4, s1, 32                ; the slots: without this one, the moved ones adjusted
        mv    t6, t4                    ; ...
        li    a2, 0                     ; ...
nr_j:
        beq   a2, t0, nr_e              ; ...
        lhu   a3, 0(t4)                 ; ...
        beq   a2, a1, nr_k              ; ...
        bgeu  a3, t3, nr_w              ; ...
        add   a3, a3, t5                ; ...
nr_w:
        sh    a3, 0(t6)                 ; ...
        addi  t6, t6, 2                 ; ...
nr_k:
        addi  t4, t4, 2                 ; ...
        addi  a2, a2, 1                 ; ...
        j     nr_j                      ; ...
nr_e:
        addi  t0, t0, -1                ; ...
        sh    t0, 26(s1)                ; ...
        add   t1, t1, t5                ; ...
        sh    t1, 28(s1)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; nsearch(a0 = page, a1 = key, a2 = its length) -> in a leaf: a0 = the first
; cell whose key is not below the key, a1 = 1 if it is the key; in a branch:
; a0 = the child that holds the key
nsearch:
        addi  sp, sp, -72               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        sd    s5, 40(sp)                ; ...
        sd    s6, 48(sp)                ; ...
        sd    s7, 56(sp)                ; ...
        sd    s8, 64(sp)                ; ...
        mv    s1, a0                    ; s1 = the page
        mv    s2, a1                    ; s2 = the key
        mv    s3, a2                    ; s3 = its length
        lhu   s5, 26(s1)                ; s5 = the upper end
        li    s7, 0                     ; s7 = found exactly
        li    s4, 0                     ; s4 = the lower end
        li    s6, 8                     ; s6 = where a cell's key is
        lbu   t0, 24(s1)                ; ...
        li    t1, K_LEAF                ; ...
        beq   t0, t1, ns_l              ; ...
        li    s4, 1                     ; a branch: cell 0's key is not looked at
        li    s6, 16                    ; ...
ns_l:
        bgeu  s4, s5, ns_done           ; ...
        add   s8, s4, s5                ; s8 = the middle
        srli  s8, s8, 1                 ; ...
        slli  t0, s8, 1                 ; ...
        add   t0, t0, s1                ; ...
        lhu   t0, 32(t0)                ; ...
        add   t0, t0, s1                ; its cell
        add   a0, t0, s6                ; ...
        lhu   a1, 0(t0)                 ; ...
        mv    a2, s2                    ; ...
        mv    a3, s3                    ; ...
        call  kcmp                      ; ...
        bltz  a0, ns_up                 ; below the key: above the middle
        li    t0, 8                     ; ...
        beq   s6, t0, ns_lf             ; ...
        beqz  a0, ns_up                 ; a branch: at the key is also above
        mv    s5, s8                    ; ...
        j     ns_l                      ; ...
ns_lf:
        bnez  a0, ns_dn                 ; ...
        li    s7, 1                     ; the key itself
ns_dn:
        mv    s5, s8                    ; ...
        j     ns_l                      ; ...
ns_up:
        addi  s4, s8, 1                 ; ...
        j     ns_l                      ; ...
ns_done:
        mv    a0, s4                    ; ...
        mv    a1, s7                    ; ...
        li    t0, 8                     ; ...
        beq   s6, t0, ns_ret            ; ...
        addi  a0, s4, -1                ; a branch: the child before
ns_ret:
        ld    s8, 64(sp)                ; ...
        ld    s7, 56(sp)                ; ...
        ld    s6, 48(sp)                ; ...
        ld    s5, 40(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 72                ; ...
        ret                             ; ...

; child(a0 = page, a1 = index) -> a0 = the child page of that cell of a branch
child:
        slli  a1, a1, 1                 ; ...
        add   a1, a1, a0                ; ...
        lhu   a1, 32(a1)                ; ...
        add   a0, a0, a1                ; ...
        ld    a0, 8(a0)                 ; ...
        ret                             ; ...

; ---- reading a tree ----------------------------------------------------------------

; st_get(a0 = tree, a1 = key, a2 = its length, a3 = where the value goes (0:
; nowhere; padded to a word)) -> a0 = the value's length, or -1 if the key is
; not there; a1 = its flag
st_get:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        sd    s5, 40(sp)                ; ...
        mv    s1, a1                    ; s1 = the key
        mv    s2, a2                    ; s2 = its length
        mv    s3, a3                    ; s3 = the value's place
        ld    s4, 0(a0)                 ; s4 = the page
        beqz  s4, sg_none               ; an empty tree
sg_l:
        mv    a0, s4                    ; ...
        call  P                         ; ...
        mv    s5, a0                    ; ...
        mv    a1, s1                    ; ...
        mv    a2, s2                    ; ...
        call  nsearch                   ; ...
        lbu   t0, 24(s5)                ; ...
        li    t1, K_LEAF                ; ...
        beq   t0, t1, sg_leaf           ; ...
        mv    a1, a0                    ; down
        mv    a0, s5                    ; ...
        call  child                     ; ...
        mv    s4, a0                    ; ...
        j     sg_l                      ; ...
sg_leaf:
        beqz  a1, sg_none               ; ...
        slli  t0, a0, 1                 ; its cell
        add   t0, t0, s5                ; ...
        lhu   t0, 32(t0)                ; ...
        add   t0, t0, s5                ; ...
        lhu   t1, 0(t0)                 ; the key's length, padded
        addi  t1, t1, 7                 ; ...
        srli  t1, t1, 3         ; (down to a whole word)
        slli  t1, t1, 3         ; ...
        lhu   t2, 2(t0)                 ; the value's length and flag
        srli  s4, t2, 15                ; s4 = the flag
        slli  t2, t2, 49                ; ...
        srli  s5, t2, 49                ; s5 = the length
        beqz  s3, sg_ret                ; ...
        mv    a0, s3                    ; the value
        add   a1, t0, t1                ; ...
        addi  a1, a1, 8                 ; ...
        addi  a2, s5, 7                 ; ...
        srli  a2, a2, 3         ; (down to a whole word)
        slli  a2, a2, 3         ; ...
        call  wcopy                     ; ...
sg_ret:
        mv    a0, s5                    ; ...
        mv    a1, s4                    ; ...
        j     sg_out                    ; ...
sg_none:
        li    a0, -1                    ; ...
sg_out:
        ld    s5, 40(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; ...

; st_seek(a0 = tree, a1 = key, a2 = its length, a3 = ST_GE / GT / LE / LT, a4 =
; where the found key goes, a5 = where its value goes (either 0: nowhere;
; each padded to a word; a4 may be the key's own place) -> a0 = 1 and
; sk_kl, sk_vl, sk_fl, or 0: the nearest record on that side of the key
st_seek:
        addi  sp, sp, -72               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        sd    s5, 40(sp)                ; ...
        sd    s6, 48(sp)                ; ...
        sd    s7, 56(sp)                ; ...
        sd    s8, 64(sp)                ; ...
        mv    s1, a1                    ; s1 = the key
        mv    s2, a2                    ; s2 = its length
        mv    s3, a3                    ; s3 = the side
        mv    s4, a4                    ; s4 = the key's place
        mv    s5, a5                    ; s5 = the value's place
        ld    s8, 0(a0)                 ; s8 = the page
        beqz  s8, sk_none               ; an empty tree
        li    s6, 0                     ; s6 = the level
sk_d:
        mv    a0, s8                    ; ...
        call  P                         ; ...
        mv    s7, a0                    ; s7 = the page's buffer
        slli  t0, s6, 4                 ; ...
        sd    s8, rpath(t0)             ; ...
        mv    a1, s1                    ; ...
        mv    a2, s2                    ; ...
        call  nsearch                   ; ...
        lbu   t0, 24(s7)                ; ...
        li    t1, K_LEAF                ; ...
        beq   t0, t1, sk_leaf           ; ...
        slli  t0, s6, 4                 ; ...
        sd    a0, rpath+8(t0)           ; ...
        mv    a1, a0                    ; down
        mv    a0, s7                    ; ...
        call  child                     ; ...
        mv    s8, a0                    ; ...
        addi  s6, s6, 1                 ; ...
        j     sk_d                      ; ...
sk_leaf:
        mv    s8, a0                    ; s8 = the place in the leaf
        li    t0, ST_GT                 ; after the key: past it when it is there
        bne   s3, t0, sk_1              ; ...
        add   s8, s8, a1                ; ...
sk_1:
        li    t0, ST_LE                 ; at or before: the one before unless it is there
        bne   s3, t0, sk_2              ; ...
        addi  s8, s8, -1                ; ...
        add   s8, s8, a1                ; ...
sk_2:
        li    t0, ST_LT                 ; before
        bne   s3, t0, sk_3              ; ...
        addi  s8, s8, -1                ; ...
sk_3:
        bltz  s8, sk_prev               ; before this leaf's first
        lhu   t0, 26(s7)                ; ...
        blt   s8, t0, sk_out            ; in this leaf
sk_next:
        addi  s6, s6, -1                ; the first record of the next leaf: up to a
        bltz  s6, sk_none               ; page with a child after ours
        slli  t0, s6, 4                 ; ...
        ld    a0, rpath(t0)             ; ...
        call  P                         ; ...
        slli  t0, s6, 4                 ; ...
        ld    t1, rpath+8(t0)           ; ...
        addi  t1, t1, 1                 ; ...
        lhu   t2, 26(a0)                ; ...
        bgeu  t1, t2, sk_next           ; ...
        mv    a1, t1                    ; down that child, leftmost
        call  child                     ; ...
sk_nd:
        mv    s8, a0                    ; ...
        call  P                         ; ...
        mv    s7, a0                    ; ...
        lbu   t0, 24(s7)                ; ...
        li    t1, K_LEAF                ; ...
        beq   t0, t1, sk_nl             ; ...
        li    a1, 0                     ; ...
        call  child                     ; ...
        j     sk_nd                     ; ...
sk_nl:
        li    s8, 0                     ; ...
        j     sk_out                    ; ...
sk_prev:
        addi  s6, s6, -1                ; the last record of the leaf before: up to a
        bltz  s6, sk_none               ; page with a child before ours
        slli  t0, s6, 4                 ; ...
        ld    t1, rpath+8(t0)           ; ...
        beqz  t1, sk_prev               ; ...
        ld    a0, rpath(t0)             ; ...
        call  P                         ; ...
        slli  t0, s6, 4                 ; ...
        ld    a1, rpath+8(t0)           ; ...
        addi  a1, a1, -1                ; down that child, rightmost
        call  child                     ; ...
sk_pd:
        mv    s8, a0                    ; ...
        call  P                         ; ...
        mv    s7, a0                    ; ...
        lbu   t0, 24(s7)                ; ...
        li    t1, K_LEAF                ; ...
        beq   t0, t1, sk_pl             ; ...
        lhu   a1, 26(s7)                ; ...
        addi  a1, a1, -1                ; ...
        call  child                     ; ...
        j     sk_pd                     ; ...
sk_pl:
        lhu   s8, 26(s7)                ; ...
        addi  s8, s8, -1                ; ...
sk_out:
        bltz  s8, sk_none               ; (an empty page: there is none)
        lhu   t0, 26(s7)                ; ...
        bge   s8, t0, sk_none           ; ...
        slli  t0, s8, 1                 ; s6 = the cell
        add   t0, t0, s7                ; ...
        lhu   t0, 32(t0)                ; ...
        add   s6, t0, s7                ; ...
        lhu   t1, 0(s6)                 ; the key's length
        sd    t1, sk_kl(zero)           ; ...
        addi  t1, t1, 7                 ; s8 = padded
        srli  s8, t1, 3         ; (down to a whole word)
        slli  s8, s8, 3         ; ...
        lhu   t2, 2(s6)                 ; the value's length and flag
        srli  t3, t2, 15                ; ...
        sd    t3, sk_fl(zero)           ; ...
        slli  t2, t2, 49                ; ...
        srli  t2, t2, 49                ; ...
        sd    t2, sk_vl(zero)           ; ...
        beqz  s5, sk_k                  ; the value first: the key's place may be the key
        mv    a0, s5                    ; ...
        add   a1, s6, s8                ; ...
        addi  a1, a1, 8                 ; ...
        addi  a2, t2, 7                 ; ...
        srli  a2, a2, 3         ; (down to a whole word)
        slli  a2, a2, 3         ; ...
        call  wcopy                     ; ...
sk_k:
        beqz  s4, sk_yes                ; ...
        mv    a0, s4                    ; ...
        addi  a1, s6, 8                 ; ...
        mv    a2, s8                    ; ...
        call  wcopy                     ; ...
sk_yes:
        li    a0, 1                     ; ...
        j     sk_ret                    ; ...
sk_none:
        li    a0, 0                     ; ...
sk_ret:
        ld    s8, 64(sp)                ; ...
        ld    s7, 56(sp)                ; ...
        ld    s6, 48(sp)                ; ...
        ld    s5, 40(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 72                ; ...
        ret                             ; ...
