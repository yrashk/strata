; =============================================================================
; fsops.s: the file server's operations (included by fs.s)
; =============================================================================

op_open:
        la    t0, srv_hdr               ; writing creates the path's tags
        ld    s4, 24(t0)                ; s4 = the mode
        beqz  s4, oo_rd                 ; (it changes things: a writer's bytes are
        call  tx_sync                   ; committed first)
oo_rd:
        snez  a0, s4                    ; ...
        call  get_named                 ; nm, nmlen, ptags
        bltz  a0, oo_fail               ; bad name, no such tag, no room
        li    s1, 0                     ; a free open record
        la    s2, opens                 ; ...
oo_f:
        li    t0, NOPEN                 ; ...
        li    a0, -6                    ; ...
        bgeu  s1, t0, oo_fail           ; ...
        ld    t0, O_USED(s2)            ; ...
        beqz  t0, oo_have               ; ...
        addi  s1, s1, 1                 ; ...
        addi  s2, s2, O_SIZEOF          ; ...
        j     oo_f                      ; ...
oo_have:
        sd    zero, O_POS(s2)           ; ...
        bnez  s4, oo_write              ; 1 write, 2 append
        call  lookup                    ; read: it must exist, with the path's tags
        beqz  a0, nofile                ; ...
        sd    a0, O_OID(s2)             ; ...
        ld    t0, snap_on(zero)         ; (in a snapshot, if the path named one)
        sd    t0, O_DOID(s2)            ; ...
        li    t0, 1                     ; open for reading
        sd    t0, O_USED(s2)            ; ...
        j     oo_ref                    ; ...
oo_write:
        call  find                      ; the file of that name in the path's directory
        beqz  a0, oo_new                ; ...
        call  rec_load                  ; ...
        j     oo_tags                   ; ...
oo_new:
        call  fs_create                 ; a new one: with the path's tags, in that directory
        call  fs_addtags                ; ...
        bltz  a0, st_full               ; (-1: what was made of it is given up)
        call  fs_place                  ; ...
        bltz  a0, st_full               ; ...
oo_tags:
        ld    t0, rec_oid(zero)         ; ...
        sd    t0, O_OID(s2)             ; ...
        li    t1, 2                     ; ...
        beq   s4, t1, oo_app            ; ...
        ld    s3, cnt(zero)             ; writing: the bytes go to a blob of their own,
        addi  t0, s3, 1                 ; marked as being written
        sd    t0, cnt(zero)             ; ...
        li    t0, 1                     ; ...
        sd    t0, cnt_d(zero)           ; ...
        sd    s3, O_DOID(s2)            ; ...
        mv    a0, s3                    ; ...
        call  wkey                      ; ...
        ld    a0, x_dict(zero)          ; ...
        la    a1, rkey                  ; ...
        li    a2, 16                    ; ...
        la    a3, rkey                  ; ...
        li    a4, 0                     ; ...
        li    a5, 0                     ; ...
        call  st_put                    ; ...
        li    t0, 2                     ; ...
        sd    t0, O_USED(s2)            ; ...
        j     oo_ref                    ; ...
oo_app:
        sd    t0, O_DOID(s2)            ; appending: to the contents where they are
        la    t0, rec                   ; ...
        ld    t0, R_SIZE(t0)            ; ...
        sd    t0, O_POS(s2)             ; ...
        li    t0, 3                     ; ...
        sd    t0, O_USED(s2)            ; ...
oo_ref:
        call  srv_pid                   ; the caller holds it
        addi  a1, s1, 1                 ; id
        call  ref_add                   ; ...
        addi  a0, s1, 1                 ; the id
        j     reply                     ; ...
oo_fail:
        call  tags_undo                 ; (tags made for nothing go; a0 kept)
        j     reply                     ; ...

op_read:
        la    t0, srv_hdr               ; the file
        ld    a0, 8(t0)                 ; ...
        call  orec                      ; ...
        beqz  a0, bad                   ; ...
        mv    s1, a0                    ; ...
        ld    t0, O_USED(s1)            ; open for reading?
        li    t1, 1                     ; ...
        bne   t0, t1, bad               ; ...
        la    t0, srv_hdr               ; s2 = bytes: min(wanted, 4032)
        ld    s2, 16(t0)                ; ...
        li    t1, SYS_MAX               ; ...
        bleu  s2, t1, ord_1             ; ...
        mv    s2, t1                    ; ...
ord_1:
        ld    a0, O_DOID(s1)            ; opened in a snapshot: its trees
        beqz  a0, ord_live              ; ...
        call  snap_use                  ; ...
        bltz  a0, bad                   ; (the snapshot is gone)
ord_live:
        ld    a0, O_OID(s1)             ; ...
        call  bswap                     ; ...
        sd    a0, okey(zero)            ; ...
        ld    a0, x_data(zero)          ; ...
        la    a1, okey                  ; ...
        li    a2, 8                     ; ...
        ld    a3, O_POS(s1)             ; ...
        la    a4, sys_buf               ; ...
        mv    a5, s2                    ; ...
        call  st_bread                  ; ...
        bgtz  a0, ord_2                 ; ...
        li    a0, 0                     ; the end of the file (or an empty one)
        j     reply                     ; ...
ord_2:
        mv    s2, a0                    ; ...
        la    a0, sys_buf               ; -> the request
        mv    a1, s2                    ; ...
        call  srv_put                   ; ...
        ld    t0, O_POS(s1)             ; advance
        add   t0, t0, s2                ; ...
        sd    t0, O_POS(s1)             ; ...
        mv    a0, s2                    ; ...
        j     reply                     ; ...

; o_writer(a0 = id) -> a0 = its open record if it is open for writing, else 0
o_writer:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        call  orec                      ; ...
        beqz  a0, ow_ret                ; ...
        ld    t0, O_USED(a0)            ; ...
        addi  t0, t0, -2                ; (2 write, 3 append)
        li    t1, 2                     ; ...
        bltu  t0, t1, ow_ret            ; ...
        li    a0, 0                     ; ...
ow_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; o_put(a0 = open record, a1 = bytes in reqbuf): they go to the end of what
; it has written; every MiB is committed, so that no change grows without end
o_put:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        ld    t0, tx_w(zero)            ; another writer's bytes are committed first: a
        beq   t0, s1, op_own            ; commit holds one writer's
        call  tx_sync                   ; ...
        sd    s1, tx_w(zero)            ; ...
op_own:
        ld    a0, O_DOID(s1)            ; ...
        call  bswap                     ; ...
        sd    a0, dokey(zero)           ; ...
        sd    zero, bw_force(zero)      ; ...
        ld    a0, x_data(zero)          ; ...
        la    a1, dokey                 ; ...
        li    a2, 8                     ; ...
        ld    a3, O_POS(s1)             ; ...
        la    a4, reqbuf               ; ...
        mv    a5, s2                    ; ...
        call  st_bwrite                 ; ...
        ld    t0, O_POS(s1)             ; ...
        add   t1, t0, s2                ; ...
        sd    t1, O_POS(s1)             ; ...
        srli  t0, t0, 20                ; ...
        srli  t1, t1, 20                ; ...
        beq   t0, t1, op_ret            ; ...
        call  fs_commit                 ; ...
op_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

op_write:
        la    t0, srv_hdr               ; the file
        ld    a0, 8(t0)                 ; ...
        call  o_writer                  ; ...
        beqz  a0, bad                   ; ...
        mv    s1, a0                    ; ...
        la    t0, srv_hdr               ; s2 = bytes
        ld    s2, 16(t0)                ; ...
        li    t1, SYS_MAX               ; ...
        bleu  s2, t1, owr_1             ; ...
        mv    s2, t1                    ; ...
owr_1:
        li    a0, 0                     ; ...
        beqz  s2, reply                 ; ...
        la    a0, reqbuf               ; the data -> D-LS
        mv    a1, s2                    ; ...
        call  srv_get                   ; ...
        mv    a0, s1                    ; ...
        mv    a1, s2                    ; ...
        call  o_put                     ; ...
        mv    a0, s2                    ; ...
        j     reply                     ; ...

op_close:
        call  srv_pid                   ; ...
        la    t0, srv_hdr               ; ...
        ld    a1, 8(t0)                 ; ...
        call  dropref                   ; ...
        j     ok                        ; ...

op_dups:
        call  ref_dups                  ; ...
        j     reply                     ; ...

op_cleanup:
        la    t0, srv_hdr               ; the dead process
        ld    s1, 8(t0)                 ; ...
        mv    a0, s1                    ; its current tag path is forgotten
        call  cwd_drop                  ; ...
ocl_l:
        mv    a0, s1                    ; its references, one by one
        call  ref_first                 ; ...
        bltz  a0, ok                    ; none left
        mv    a1, a0                    ; ...
        mv    a0, s1                    ; ...
        call  dropref                   ; ...
        j     ocl_l                     ; ...

; last_tag() -> a0 = 0, or 1 when the path's last component (nm) names one
; file: a last component that is a tag joins ptags, "-tag" joins xtags
last_tag:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        ld    a1, nmlen(zero)           ; a last component?
        li    a0, 0                     ; ...
        beqz  a1, lt_ret                ; ...
        la    a0, nm                    ; "PREFIX*": the names that begin so
        add   t0, a0, a1                ; ...
        lbu   t0, -1(t0)                ; ...
        li    t1, '*'                   ; ...
        bne   t0, t1, lt_term           ; ...
        mv    a2, a0                    ; ...
        addi  a3, a1, -1                ; ...
        li    a0, T_PRE                 ; ...
        li    a1, 0                     ; ...
        call  term_add                  ; ...
        li    t0, 0                     ; ...
        j     lt_one                    ; ...
lt_term:
        call  term_try                  ; a term?
        li    t0, 0                     ; ...
        bnez  a0, lt_one                ; ...
        la    a0, nm                    ; "-tag": an exclusion
        ld    a1, nmlen(zero)           ; ...
        lbu   t0, 0(a0)                 ; ...
        li    t1, '-'                   ; ...
        beq   t0, t1, lt_excl           ; ...
        call  tag_find                  ; a tag?
        li    t0, 1                     ; no: a file
        bltz  a0, lt_one                ; ...
        la    a1, np                    ; ...
        call  qt_add                    ; ...
        li    a0, 0                     ; ...
        j     lt_ret                    ; ...
lt_excl:
        addi  a0, a0, 1                 ; the tag after the "-"
        addi  a1, a1, -1                ; ...
        call  tag_find                  ; ...
        li    t0, 0                     ; none: it excludes nothing
        bltz  a0, lt_one                ; ...
        la    a1, nx                    ; ...
        call  qt_add                    ; ...
        li    t0, 0                     ; ...
lt_one:
        mv    a0, t0                    ; ...
lt_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; rec_bits() -> a0 = rec's tags as a set: bit t for tag id t (ids below 64)
rec_bits:
        la    t0, rec                   ; ...
        lhu   t1, R_NTAGS(t0)           ; ...
        li    a0, 0                     ; ...
        li    t4, 64                    ; ...
        li    t5, 1                     ; ...
rb_l:
        beqz  t1, rb_r                  ; ...
        lwu   t3, R_TAGS(t0)            ; ...
        addi  t0, t0, 4                 ; ...
        addi  t1, t1, -1                ; ...
        bgeu  t3, t4, rb_l              ; ...
        sll   t3, t5, t3                ; ...
        or    a0, a0, t3                ; ...
        j     rb_l                      ; ...
rb_r:
        ret                             ; ...

op_unlink:
        call  tx_sync                   ; (a writer's bytes are committed first)
        li    a0, 0                     ; the path's tags must exist
        call  get_named                 ; ...
        bltz  a0, reply                 ; ...
        call  lookup                    ; ...
        beqz  a0, nofile                ; ...
        call  fs_remove                 ; ...
        bltz  a0, reply                 ; ...
        call  fs_commit                 ; ...
        j     ok                        ; ...

op_stat:
        li    a0, 0                     ; ...
        call  get_named                 ; ...
        bltz  a0, reply                 ; ...
        call  lookup                    ; ...
        beqz  a0, nofile                ; ...
        la    t0, rec                   ; its size
        ld    a0, R_SIZE(t0)            ; ...
        j     reply                     ; ...

op_statfs:
        la    t0, sys_buf               ; total, used, files
        ld    t1, total(zero)           ; ...
        sd    t1, 0(t0)                 ; ...
        ld    t1, st_npages(zero)       ; ...
        ld    t2, st_nfree(zero)        ; ...
        sub   t1, t1, t2                ; ...
        ld    t2, st_bpp(zero)          ; ...
        mul   t1, t1, t2                ; ...
        sd    t1, 8(t0)                 ; ...
        ld    t1, cnt+8(zero)           ; ...
        sd    t1, 16(t0)                ; ...
        mv    a0, t0                    ; -> the request
        li    a1, 24                    ; ...
        call  srv_put                   ; ...
        li    a0, 3                     ; ...
        j     reply                     ; ...

op_readblk:
        la    t0, srv_hdr               ; the block
        ld    s1, 8(t0)                 ; ...
        ld    t1, total(zero)           ; on the disk?
        bgeu  s1, t1, bad               ; ...
        li    a0, 1                     ; read it
        mv    a1, s1                    ; ...
        li    a2, 1                     ; ...
        li    a3, SCR                   ; ...
        li    a4, 5                     ; ...
        call  blk                       ; ...
        la    t0, sys_buf               ; -> D-LS
        li    t1, 512                   ; ...
        li    t2, SCR                   ; ...
        tget  tg1, t0, c5, t2, t1       ; ...
        twait 1 << 1                    ; ...
        la    a0, sys_buf               ; -> the request
        li    a1, 512                   ; ...
        call  srv_put                   ; ...
        li    a0, 512                   ; ...
        j     reply                     ; ...

; LOADIMG: the named file's contents straight into the attached arena
op_loadimg:
        cvalid t0, c7                   ; an arena must come with it
        beqz  t0, bad                   ; ...
        li    s2, 0                     ; s2 = the path the program was found by, if not the one asked
        la    t0, srv_hdr               ; the mode's upper half: the process that starts
        ld    t1, 24(t0)                ; the program: a path is read from where it is
        srli  t2, t1, 32                ; ...
        beqz  t2, oli_p                 ; ...
        sd    t2, path_pid(zero)        ; ...
        slli  t1, t1, 32                ; ...
        srli  t1, t1, 32                ; ...
        sd    t1, 24(t0)                ; ...
oli_p:
        li    a0, 0                     ; ...
        call  get_named                 ; ...
        bltz  a0, oli_nf                ; (the starter's directory may be gone)
        call  lookup                    ; ...
        bnez  a0, oli_have              ; ...
oli_nf:
        la    t0, srv_hdr               ; not there: a name without "/" is looked for in
        ld    t1, 16(t0)                ; /bin (the request's text is in rbuf)
        li    a0, -4                    ; ...
        li    t2, PATHMAX - 5           ; ...
        bgtu  t1, t2, reply_att         ; ...
        la    t0, rbuf                  ; ...
        add   t2, t0, t1                ; ...
oli_s:
        beq   t2, t0, oli_bin           ; (moved up five bytes, from its end, as it is looked at)
        addi  t2, t2, -1                ; ...
        lbu   t3, 0(t2)                 ; ...
        sb    t3, 5(t2)                 ; ...
        li    t4, '/'                   ; ...
        beq   t3, t4, reply_att         ; ...
        j     oli_s                     ; ...
oli_bin:
        li    t3, '/'                   ; ...
        sb    t3, 0(t0)                 ; ...
        sb    t3, 4(t0)                 ; ...
        li    t3, 'b'                   ; ...
        sb    t3, 1(t0)                 ; ...
        li    t3, 'i'                   ; ...
        sb    t3, 2(t0)                 ; ...
        li    t3, 'n'                   ; ...
        sb    t3, 3(t0)                 ; ...
        addi  s1, t1, 5                 ; s1 = the path's length
oli_try:
        la    a0, rbuf                  ; ...
        mv    a1, s1                    ; ...
        call  setpath                   ; ...
        li    a0, 0                     ; ...
        call  parse_file                ; ...
        bltz  a0, oli_sys               ; ...
        call  lookup                    ; ...
        mv    s2, s1                    ; ...
        bnez  a0, oli_have              ; ...
oli_sys:
        la    t0, rbuf                  ; not in /bin: in /sys (the servers: `net`)
        lbu   t1, 1(t0)                 ; ...
        li    t2, 'b'                   ; ...
        li    a0, -4                    ; no such program
        bne   t1, t2, reply_att         ; ...
        li    t1, 's'                   ; ...
        sb    t1, 1(t0)                 ; ...
        sb    t1, 3(t0)                 ; ...
        li    t1, 'y'                   ; ...
        sb    t1, 2(t0)                 ; ...
        j     oli_try                   ; ...
oli_have:
        la    t2, srv_hdr               ; (handle = the most bytes, mode = the arena offset)
        ld    a4, 8(t2)                 ; ...
        ld    a3, 24(t2)                ; ...
        ld    a0, x_data(zero)          ; ...
        la    a1, okey                  ; ...
        li    a2, 8                     ; ...
        call  st_bload                  ; ...
        li    t0, -4                    ; no contents: an empty file
        bne   a0, t0, oli_r             ; ...
        li    a0, 0                     ; ...
oli_r:
        bltz  a0, reply_att             ; ...
        beqz  s2, reply_att             ; found in /bin or /sys: the reply's data is the path it
        mv    s3, a0                    ; was found by (proc makes it the command's first word:
        la    t0, srv_hdr               ; a program finds what lies beside it by that)
        sd    s2, 16(t0)                ; ...
        la    a0, rbuf                  ; ...
        mv    a1, s2                    ; ...
        call  srv_put                   ; ...
        mv    a0, s3                    ; ...
        j     reply_att                 ; the arena goes back with the reply
oli_load:
        ld    a0, x_data(zero)          ; ...
        la    a1, okey                  ; ...
        li    a2, 8                     ; ...
        call  st_bload                  ; ...
        li    t0, -4                    ; no contents: an empty file
        bne   a0, t0, reply_att         ; ...
        li    a0, 0                     ; ...
        j     reply_att                 ; the arena goes back with the reply

; READALL: an open file, whole, into the attached arena
op_readall:
        cvalid t0, c7                   ; ...
        beqz  t0, bad                   ; ...
        la    t0, srv_hdr               ; ...
        ld    a0, 8(t0)                 ; ...
        call  orec                      ; ...
        mv    s1, a0                    ; ...
        li    a0, -1                    ; ...
        beqz  s1, reply_att             ; ...
        ld    t0, O_USED(s1)            ; ...
        li    t2, 1                     ; ...
        bne   t0, t2, reply_att         ; ...
        ld    a0, O_DOID(s1)            ; (opened in a snapshot: its trees)
        beqz  a0, ora_live              ; ...
        call  snap_use                  ; ...
        mv    t0, a0                    ; ...
        li    a0, -1                    ; ...
        bltz  t0, reply_att             ; ...
ora_live:
        ld    a0, O_OID(s1)             ; ...
        call  bswap                     ; ...
        sd    a0, okey(zero)            ; ...
        la    t2, srv_hdr               ; (length = the most bytes, mode = the arena offset)
        ld    a4, 16(t2)                ; ...
        ld    a3, 24(t2)                ; ...
        j     oli_load                  ; ...

; WRITEALL: bytes of the attached arena appended to a file being written
op_writeall:
        cvalid t0, c7                   ; ...
        beqz  t0, bad                   ; ...
        la    t0, srv_hdr               ; ...
        ld    a0, 8(t0)                 ; ...
        call  o_writer                  ; ...
        mv    s1, a0                    ; ...
        li    a0, -1                    ; ...
        beqz  s1, reply_att             ; ...
        la    t0, srv_hdr               ; s2 = offset, s3 = bytes left
        ld    s2, 24(t0)                ; ...
        ld    s3, 16(t0)                ; ...
owa_l:
        beqz  s3, owa_done              ; ...
        li    s4, 4096                  ; a chunk
        bleu  s4, s3, owa_n             ; ...
        mv    s4, s3                    ; ...
owa_n:
        addi  t1, s4, 7                 ; arena -> D-LS (whole words)
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        la    t0, reqbuf               ; ...
        tget  tg1, t0, c7, s2, t1       ; ...
        twait 1 << 1                    ; ...
        mv    a0, s1                    ; ...
        mv    a1, s4                    ; ...
        call  o_put                     ; ...
        add   s2, s2, s4                ; ...
        sub   s3, s3, s4                ; ...
        j     owa_l                     ; ...
owa_done:
        la    t0, srv_hdr               ; the bytes taken
        ld    a0, 16(t0)                ; ...
        j     reply_att                 ; ...

; =============================================================================
; Snapshots
; =============================================================================
;
; A snapshot is the whole store as of one commit, under a name: taking one
; records that commit's catalog root in the tree "snap" of namespace 0 (u64
; commit, big-endian -> u64 catalog root, u64 height, the name) and copies
; nothing. From then on the store keeps the pages that commit used (storew.s:
; st_deadlim and the dead lists). A request whose path begins with "@NAME"
; is served from the snapshot's trees: the file system's six trees as that
; catalog has them stand in for the live ones until the reply.

; snap_done(): the live trees again (a0 kept)
snap_done:
        ld    t0, snap_on(zero)         ; ...
        beqz  t0, snd_ret               ; ...
        sd    zero, snap_on(zero)       ; ...
        li    t0, 0                     ; ...
snd_l:
        ld    t1, xsave(t0)             ; ...
        sd    t1, x_obj(t0)             ; ...
        addi  t0, t0, 8                 ; ...
        li    t1, 48                    ; ...
        bne   t0, t1, snd_l             ; ...
        ld    t0, x_ext(zero)           ; ...
        sd    t0, bl_ext(zero)          ; ...
snd_ret:
        ret                             ; ...

; snap_use(a0 = a snapshot's commit) -> a0 = 0, or -1 when there is none of
; that commit: its trees stand in for the live ones until snap_done
snap_use:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        mv    s3, a0                    ; ...
        call  snap_done                 ; (one at a time)
        mv    a0, s3                    ; ...
        call  bswap                     ; ...
        sd    a0, rkey(zero)            ; ...
        ld    a0, x_snap(zero)          ; ...
        la    a1, rkey                  ; ...
        li    a2, 8                     ; ...
        la    a3, tnbuf                 ; ...
        call  st_get                    ; ...
        bltz  a0, snu_ret               ; (a0 = -1)
        ld    t0, tnbuf(zero)           ; its catalog
        sd    t0, scat(zero)            ; ...
        ld    t0, tnbuf+8(zero)         ; ...
        sd    t0, scat+8(zero)          ; ...
        li    s1, 0                     ; s1 = the tree (times 8)
        la    s2, s_obj                 ; s2 = its name: 3 bytes the first, 4 the others
snu_l:
        la    t0, ckey                  ; its catalog key: the namespace, the name
        sd    zero, 0(t0)               ; ...
        ld    t1, fs_ns(zero)           ; ...
        sb    t1, 3(t0)                 ; (the file system's namespace: below 256)
        addi  a0, t0, 4                 ; ...
        mv    a1, s2                    ; ...
        snez  a2, s1                    ; ...
        addi  a2, a2, 3                 ; ...
        add   s2, s2, a2                ; ...
        call  srv_bcopy                 ; ...
        sd    zero, cval(zero)          ; (a tree the snapshot does not have: empty)
        sd    zero, cval+8(zero)        ; ...
        la    a0, scat                  ; ...
        la    a1, ckey                  ; ...
        snez  a2, s1                    ; ...
        addi  a2, a2, 7                 ; ...
        la    a3, cval                  ; ...
        call  st_get                    ; ...
        slli  t0, s1, 1                 ; ...
        ld    t1, cval(zero)            ; ...
        sd    t1, sx(t0)                ; ...
        ld    t1, cval+8(zero)          ; ...
        sd    t1, sx+8(t0)              ; ...
        ld    t1, x_obj(s1)             ; the live tree's place is kept
        sd    t1, xsave(s1)             ; ...
        la    t1, sx                    ; ...
        add   t1, t1, t0                ; ...
        sd    t1, x_obj(s1)             ; ...
        addi  s1, s1, 8                 ; ...
        li    t0, 48                    ; ...
        bne   s1, t0, snu_l             ; ...
        ld    t0, x_ext(zero)           ; ...
        sd    t0, bl_ext(zero)          ; ...
        sd    s3, snap_on(zero)         ; ...
        li    a0, 0                     ; ...
snu_ret:
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; snap_find(a0 = name, a1 = its length) -> a0 = the commit of the snapshot of
; that name, or 0 (its record is then in rkey, tnbuf)
snap_find:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        sd    zero, rkey(zero)          ; ...
snf_l:
        ld    a0, x_snap(zero)          ; ...
        la    a1, rkey                  ; ...
        li    a2, 8                     ; ...
        li    a3, ST_GT                 ; ...
        la    a4, rkey                  ; ...
        la    a5, tnbuf                 ; ...
        call  st_seek                   ; ...
        beqz  a0, snf_ret               ; ...
        la    a0, tnbuf + 16            ; ...
        ld    a1, sk_vl(zero)           ; ...
        addi  a1, a1, -16               ; ...
        mv    a2, s1                    ; ...
        mv    a3, s2                    ; ...
        call  kcmp                      ; ...
        bnez  a0, snf_l                 ; ...
        ld    a0, rkey(zero)            ; ...
        call  bswap                     ; ...
snf_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; snap_path(): a resolved path (pbuf, plen) whose first component is "@NAME"
; is a path in that snapshot: the component goes, and the snapshot's trees
; are in use. Only for requests that read (OPEN, STAT, LOADIMG,
; QUERY, TAGS2); for the others, and for a snapshot that is not there,
; snap_bad is set and the path names nothing.
SNAP_OPS = (1 << 3) + (1 << 10) + (1 << 14) + (1 << 27) + (1 << 28) + (1 << 40) + (1 << 41)
snap_path:
        la    t0, pbuf                  ; ...
        ld    t1, plen(zero)            ; ...
        li    t2, 3                     ; ...
        bltu  t1, t2, snd_ret           ; ...
        lbu   t2, 1(t0)                 ; ...
        li    t3, '@'                   ; ...
        bne   t2, t3, snd_ret           ; ...
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        li    s1, 2                     ; s1 = where the component ends
        li    t3, '/'                   ; ...
snp_e:
        bgeu  s1, t1, snp_f             ; ...
        add   t2, t0, s1                ; ...
        lbu   t2, 0(t2)                 ; ...
        beq   t2, t3, snp_f             ; ...
        addi  s1, s1, 1                 ; ...
        j     snp_e                     ; ...
snp_f:
        la    t2, srv_hdr               ; a request that may read a snapshot?
        ld    t2, 0(t2)                 ; ...
        li    t3, SNAP_OPS              ; ...
        srl   t3, t3, t2                ; ...
        andi  t3, t3, 1                 ; ...
        beqz  t3, snp_bad               ; ...
        addi  a0, t0, 2                 ; ...
        addi  a1, s1, -2                ; ...
        call  snap_find                 ; ...
        beqz  a0, snp_bad               ; ...
        call  snap_use                  ; ...
        la    a0, pbuf                  ; the rest of the path moves to the front
        add   a1, a0, s1                ; ...
        ld    a2, plen(zero)            ; ...
        sub   a2, a2, s1                ; ...
        sd    a2, plen(zero)            ; ...
        sd    zero, pcwdl(zero)         ; ...
        call  srv_bcopy                 ; ...
        j     snp_ret                   ; ...
snp_bad:
        li    t0, 1                     ; ...
        sd    t0, snap_bad(zero)        ; ...
snp_ret:
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; =============================================================================
; The store for programs
; =============================================================================
;
; A program keeps its own data in the store beside the file system: in a
; NAMESPACE of its own, in named TREES of keys and values (bytes, compared
; as unsigned bytes: a key of 1 byte to an eighth of a page less 32, a value
; of up to about a quarter page). A namespace and a tree are made by the
; first write to them. A namespace is public (anyone names it) or private;
; the ones made here are public, and "fs" is private: these calls refuse it.
;
; Every request's data starts with: u8 namespace name length (1..32), u8
; tree name length (1..28; not starting with "."), u16 key length, u32 0;
; then the two names.
;  64 DBGET   then the key -> the value's length, data: the value; -4 no such
;             namespace, tree or key; -1 a bad request, or a private namespace
;  65 DBSCAN  then a key (none: from the start); mode = ST_GE (0: from the key
;             on), ST_GT (1: after it), ST_LE, ST_LT -> records, data: per
;             record {u16 key length, u16 value length, u32 0, the key, the
;             value}, key and value each padded to 8 bytes: the record on
;             that side of the key and those after it in key order, as many
;             as fit (ask again with the last key and mode 1); the reply's
;             length word is the data's bytes
;  66 DBBATCH handle = items; from the next multiple of 8 after the names,
;             per item {u8 1 put / 2 delete, u8 0, u16 key length, u16 value
;             length, u16 0, the key, the value}, key and value each padded
;             to 8 bytes -> 0: all of them are on the disk, or (-1, a bad
;             item) none is. One commit: the unit of atomic change.

