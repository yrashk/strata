; QUERY: as DIR, without its limits. data = a tag path (its last component
; may name one file), handle = the cursor: the object the listing has reached
; (0 at first) -> files; in the reply the handle word is the cursor to ask
; with again (0: that was all), the mode word the facets as DIR gives them,
; and the data: u64 n, then n u32 ids of the path's own tags (padded to a
; word); then per file {u16 record bytes, u16 name length, u32 tags, u64
; size, the name, the file's tag ids (u32 each)}, name and ids each padded to
; a word. A reply holds as many files as fit; its length word is the data's
; bytes.
op_query:
        li    a0, 0                     ; ...
        call  get_file                  ; ...
        bltz  a0, reply                 ; ...
        li    s7, 0                     ; s7 = the facets
        li    s3, 0                     ; s3 = files
        call  last_tag                  ; ...
        mv    s4, a0                    ; s4 = 1: the path names one file
        la    s5, sys_buf               ; s5 = output: the path's own tags first
        ld    t0, np(zero)              ; ...
        sd    t0, 0(s5)                 ; ...
        addi  s5, s5, 8                 ; ...
        li    t1, 0                     ; ...
oq_p:
        bgeu  t1, t0, oq_pd             ; ...
        slli  t2, t1, 3                 ; ...
        ld    t2, ptags(t2)             ; ...
        sw    t2, 0(s5)                 ; ...
        sw    zero, 4(s5)               ; ...
        addi  s5, s5, 4                 ; ...
        addi  t1, t1, 1                 ; ...
        j     oq_p                      ; ...
oq_pd:
        addi  s5, s5, 7                 ; ...
        srli  s5, s5, 3                 ; ...
        slli  s5, s5, 3                 ; ...
        la    t0, srv_hdr               ; the cursor
        ld    t1, 8(t0)                 ; ...
        sd    t1, q_cur(zero)           ; ...
        sd    zero, 8(t0)               ; (the cursor answered: none unless more follows)
        beqz  s4, oq_l                  ; ...
        call  lookup                    ; one file, with the tags before it
        beqz  a0, nofile                ; ...
        call  oq_rec                    ; ...
        li    s3, 1                     ; ...
        j     oq_out                    ; ...
oq_l:
        ld    s6, q_cur(zero)           ; s6 = the last file answered
        call  q_next                    ; ...
        beqz  a0, oq_out                ; ...
        la    t0, rec                   ; room for its record?
        lhu   t1, R_NL(t0)              ; ...
        addi  t1, t1, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        lhu   t2, R_NTAGS(t0)           ; ...
        slli  t2, t2, 2                 ; ...
        addi  t2, t2, 7                 ; ...
        srli  t2, t2, 3                 ; ...
        slli  t2, t2, 3                 ; ...
        add   t1, t1, t2                ; ...
        addi  t1, t1, 16                ; ...
        add   t1, t1, s5                ; ...
        la    t2, sys_buf + SYS_MAX     ; ...
        bgtu  t1, t2, oq_more           ; ...
        call  rec_bits                  ; ...
        or    s7, s7, a0                ; ...
        call  oq_rec                    ; ...
        addi  s3, s3, 1                 ; ...
        j     oq_l                      ; ...
oq_more:
        la    t0, srv_hdr               ; more follows: from the last one answered
        sd    s6, 8(t0)                 ; ...
oq_out:
        li    s1, 0                     ; facets: not the path's own tags
oq_m:
        ld    t0, np(zero)              ; ...
        bgeu  s1, t0, oq_put            ; ...
        slli  t0, s1, 3                 ; ...
        ld    t1, ptags(t0)             ; ...
        addi  s1, s1, 1                 ; ...
        li    t0, 64                    ; ...
        bgeu  t1, t0, oq_m              ; ...
        li    t0, 1                     ; ...
        sll   t0, t0, t1                ; ...
        li    t2, -1                    ; ...
        xor   t0, t0, t2                ; ...
        and   s7, s7, t0                ; ...
        j     oq_m                      ; ...
oq_put:
        la    t0, srv_hdr               ; ...
        sd    s7, 24(t0)                ; ...
        la    a0, sys_buf               ; ...
        sub   a1, s5, a0                ; ...
        sd    a1, 16(t0)                ; (the length word: the data's bytes)
        call  srv_put                   ; ...
        mv    a0, s3                    ; ...
        j     reply                     ; ...

; oq_rec(): rec's file as a QUERY record at s5, which moves past it
oq_rec:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        la    t0, rec                   ; ...
        lhu   t1, R_NL(t0)              ; ...
        sd    zero, 0(s5)               ; ...
        sh    t1, 2(s5)                 ; ...
        lhu   t2, R_NTAGS(t0)           ; ...
        sw    t2, 4(s5)                 ; ...
        ld    t3, R_SIZE(t0)            ; ...
        sd    t3, 8(s5)                 ; ...
        addi  s1, s5, 16                ; the name, padded with zeros
        addi  t1, t1, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        mv    a0, s1                    ; ...
        mv    a1, t1                    ; ...
        add   s1, s1, t1                ; ...
        call  wzero                     ; ...
        call  rec_name                  ; ...
        mv    a2, a1                    ; ...
        mv    a1, a0                    ; ...
        addi  a0, s5, 16                ; ...
        call  srv_bcopy                 ; ...
        la    t0, rec                   ; its tag ids
        lhu   t2, R_NTAGS(t0)           ; ...
        sd    zero, 0(s1)               ; ...
oqr_t:
        beqz  t2, oqr_d                 ; ...
        lwu   t3, R_TAGS(t0)            ; ...
        sw    t3, 0(s1)                 ; ...
        sw    zero, 4(s1)               ; ...
        addi  t0, t0, 4                 ; ...
        addi  s1, s1, 4                 ; ...
        addi  t2, t2, -1                ; ...
        j     oqr_t                     ; ...
oqr_d:
        addi  s1, s1, 7                 ; ...
        srli  s1, s1, 3                 ; ...
        slli  s1, s1, 3                 ; ...
        sub   t0, s1, s5                ; the record's bytes
        sh    t0, 0(s5)                 ; ...
        mv    s5, s1                    ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; TAGS2: as TAGS, without its limits. data = a path (none: every tag; a file:
; its tags), handle = the cursor (0 at first: every tag is listed by id, a
; file's tags in its record's order) -> tags; the reply's handle word is the
; cursor to ask with again (0: that was all); data: per tag {u16 record
; bytes, u16 name length, u32 id, u64 files carrying it, the name padded to
; a word}
op_tags2:
        li    a0, 0                     ; ...
        call  get_file                  ; ...
        bltz  a0, reply                 ; ...
        li    s3, 0                     ; s3 = records
        la    s5, sys_buf               ; s5 = the record
        la    t0, srv_hdr               ; s1 = the cursor
        ld    s1, 8(t0)                 ; ...
        sd    zero, 8(t0)               ; ...
        ld    t0, nmlen(zero)           ; a file?
        beqz  t0, o2_all                ; ...
        call  lookup                    ; ...
        beqz  a0, nofile                ; ...
o2_f:
        la    t0, rec                   ; ...
        lhu   t1, R_NTAGS(t0)           ; ...
        bgeu  s1, t1, o2_done           ; ...
        slli  t1, s1, 2                 ; ...
        add   t1, t1, t0                ; ...
        lwu   s4, R_TAGS(t1)            ; s4 = the tag
        mv    a0, s4                    ; ...
        call  tag_name                  ; ...
        mv    s2, a0                    ; ...
        addi  s1, s1, 1                 ; ...
        bltz  s2, o2_f                  ; ...
        call  o2_rec                    ; ...
        bnez  a0, o2_f                  ; ...
        addi  s1, s1, -1                ; no room: from this one next time
        j     o2_more                   ; ...
o2_all:
        mv    a0, s1                    ; the next tag by id
        call  rk_tag                    ; ...
        ld    a0, x_dict(zero)          ; ...
        la    a1, rkey                  ; ...
        li    a2, 5                     ; ...
        li    a3, ST_GT                 ; ...
        la    a4, rkey                  ; ...
        la    a5, tnbuf                 ; ...
        call  st_seek                   ; ...
        beqz  a0, o2_done               ; ...
        la    t0, rkey                  ; ...
        lbu   t1, 0(t0)                 ; ...
        li    t2, 'T'                   ; ...
        bne   t1, t2, o2_done           ; ...
        lbu   s4, 1(t0)                 ; its id
        slli  s4, s4, 8                 ; ...
        lbu   t1, 2(t0)                 ; ...
        or    s4, s4, t1                ; ...
        slli  s4, s4, 8                 ; ...
        lbu   t1, 3(t0)                 ; ...
        or    s4, s4, t1                ; ...
        slli  s4, s4, 8                 ; ...
        lbu   t1, 4(t0)                 ; ...
        or    s4, s4, t1                ; ...
        ld    s2, sk_vl(zero)           ; ...
        call  o2_rec                    ; ...
        beqz  a0, o2_more               ; ...
        mv    s1, s4                    ; ...
        j     o2_all                    ; ...
o2_more:
        la    t0, srv_hdr               ; ...
        sd    s1, 8(t0)                 ; ...
        bnez  s1, o2_done               ; (a cursor of 0 would mean the end: a file's
        li    t1, -1                    ; first tag did not fit, which cannot be)
        sd    t1, 8(t0)                 ; ...
o2_done:
        la    a0, sys_buf               ; ...
        sub   a1, s5, a0                ; ...
        la    t0, srv_hdr               ; (the length word: the data's bytes)
        sd    a1, 16(t0)                ; ...
        call  srv_put                   ; ...
        mv    a0, s3                    ; ...
        j     reply                     ; ...

; o2_rec(): the tag s4, named in tnbuf (s2 bytes), as a record at s5 -> a0 =
; 1 (s5 and s3 move on), or 0 when the reply has no room for it
o2_rec:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        addi  t0, s2, 7                 ; ...
        srli  t0, t0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        addi  t0, t0, 16                ; ...
        add   t1, t0, s5                ; ...
        la    t2, sys_buf + SYS_MAX     ; ...
        li    a0, 0                     ; ...
        bgtu  t1, t2, o2r_ret           ; ...
        sh    t0, 0(s5)                 ; ...
        sh    s2, 2(s5)                 ; ...
        sw    s4, 4(s5)                 ; ...
        la    a0, tnbuf                 ; its count
        mv    a1, s2                    ; ...
        call  dk_tag                    ; ...
        ld    a0, x_dict(zero)          ; ...
        la    a1, dkey                  ; ...
        ld    a2, dk_len(zero)          ; ...
        la    a3, dval                  ; ...
        call  st_get                    ; ...
        ld    t0, dval+8(zero)          ; ...
        sd    t0, 8(s5)                 ; ...
        lhu   t1, 0(s5)                 ; the name, padded with zeros
        add   t1, t1, s5                ; ...
        sd    zero, -8(t1)              ; ...
        addi  a0, s5, 16                ; ...
        la    a1, tnbuf                 ; ...
        mv    a2, s2                    ; ...
        mv    s5, t1                    ; ...
        call  srv_bcopy                 ; ...
        addi  s3, s3, 1                 ; ...
        li    a0, 1                     ; ...
o2r_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...
