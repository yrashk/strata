        bleu  a2, t0, otr_1             ; ...
        mv    a2, t0                    ; ...
otr_1:
        mv    a0, s5                    ; ...
        call  srv_bcopy                 ; ...
        addi  s5, s5, 32                ; ...
        addi  s3, s3, 1                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

