; TAGS: every tag, or (data = a path) the tags of that file
op_tags:
        li    a0, 0                     ; ...
        call  get_file                  ; ...
        bltz  a0, reply                 ; ...
        li    s3, 0                     ; s3 = records
        la    s5, sys_buf               ; s5 = the record
        ld    t0, nmlen(zero)           ; a file?
        bnez  t0, ots_file              ; ...
        la    t0, dkey                  ; every tag: the dictionary from "t" on
        li    t1, 't'                   ; ...
        sd    zero, 0(t0)               ; ...
        sb    t1, 0(t0)                 ; ...
        li    s1, 1                     ; s1 = the key's length
ots_l:
        li    t0, 126                   ; ...
        bgeu  s3, t0, ots_done          ; ...
        ld    a0, x_dict(zero)          ; ...
        la    a1, dkey                  ; ...
        mv    a2, s1                    ; ...
        li    a3, ST_GT                 ; ...
        la    a4, dkey                  ; ...
        la    a5, dval                  ; ...
        call  st_seek                   ; ...
        beqz  a0, ots_done              ; ...
        lbu   t0, dkey(zero)            ; still a tag?
        li    t1, 't'                   ; ...
        bne   t0, t1, ots_done          ; ...
        ld    s1, sk_kl(zero)           ; ...
        ld    t0, dval+8(zero)          ; one that files carry?
        beqz  t0, ots_l                 ; ...
        la    a1, dkey + 1              ; ...
        addi  a2, s1, -1                ; ...
        call  ots_rec                   ; ...
        j     ots_l                     ; ...
ots_file:
        call  lookup                    ; ...
        beqz  a0, nofile                ; ...
        li    s1, 0                     ; s1 = the tag of the record
ots_f:
        la    t0, rec                   ; ...
        lhu   t1, R_NTAGS(t0)           ; ...
        bgeu  s1, t1, ots_done          ; ...
        slli  t1, s1, 2                 ; ...
        add   t1, t1, t0                ; ...
        lwu   a0, R_TAGS(t1)            ; ...
        addi  s1, s1, 1                 ; ...
        call  tag_name                  ; ...
        bltz  a0, ots_f                 ; ...
        mv    s2, a0                    ; ...
        mv    a1, a0                    ; its count
        la    a0, tnbuf                 ; ...
        call  dk_tag                    ; ...
        ld    a0, x_dict(zero)          ; ...
        la    a1, dkey                  ; ...
        ld    a2, dk_len(zero)          ; ...
        la    a3, dval                  ; ...
        call  st_get                    ; ...
        bltz  a0, ots_f                 ; ...
        la    a1, tnbuf                 ; ...
        mv    a2, s2                    ; ...
        call  ots_rec                   ; ...
        j     ots_f                     ; ...
ots_done:
        la    a0, sys_buf               ; -> the request
        slli  a1, s3, 5                 ; ...
        call  srv_put                   ; ...
        mv    a0, s3                    ; ...
        j     reply                     ; ...

; ots_rec(a1 = name, a2 = its length): one record at s5 from the tag in dval:
; {name[16], u64 files carrying it, u64 tag id}; s5 and s3 move on
ots_rec:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        sd    zero, 0(s5)               ; ...
        sd    zero, 8(s5)               ; ...
        ld    t0, dval+8(zero)          ; ...
        sd    t0, 16(s5)                ; ...
        lwu   t0, dval(zero)            ; ...
        sd    t0, 24(s5)                ; ...
