; =============================================================================
; fsops.s: the file server's operations (included by fs.s)
; =============================================================================

op_open:
        la    t0, srv_hdr               ; writing creates the path's tags
        ld    s4, 24(t0)                ; s4 = the mode
        snez  a0, s4                    ; ...
        call  get_named                 ; nm, nmlen, ptags
        bltz  a0, oo_fail               ; bad name, no such tag, no room
        li    s1, 0                     ; a free open record
        la    s2, opens                 ; ...
oo_f:
        li    t0, NOPEN                 ; ...
        li    a0, -6                    ; ...
        bgeu  s1, t0, oo_fail           ; ...
        ld    t0, O_USED(s2)            ; ...
        beqz  t0, oo_have               ; ...
        addi  s1, s1, 1                 ; ...
        addi  s2, s2, O_SIZEOF          ; ...
        j     oo_f                      ; ...
oo_have:
        sd    zero, O_POS(s2)           ; ...
        bnez  s4, oo_write              ; 1 write, 2 append
        call  lookup                    ; read: it must exist, with the path's tags
        beqz  a0, nofile                ; ...
        sd    a0, O_OID(s2)             ; ...
        li    t0, 1                     ; open for reading
        sd    t0, O_USED(s2)            ; ...
        j     oo_ref                    ; ...
oo_write:
        call  find                      ; the file of that name, whatever its tags
        beqz  a0, oo_new                ; ...
        call  rec_load                  ; ...
        la    t0, rec                   ; (not a boot object)
        lbu   t0, R_FLAGS(t0)           ; ...
        andi  t0, t0, 1                 ; ...
        li    a0, -1                    ; ...
        bnez  t0, oo_fail               ; ...
        j     oo_tags                   ; ...
oo_new:
        call  fs_create                 ; ...
oo_tags:
        call  fs_addtags                ; the path's tags join its own
        bltz  a0, oo_fail               ; ...
        ld    t0, rec_oid(zero)         ; ...
        sd    t0, O_OID(s2)             ; ...
        li    t1, 2                     ; ...
        beq   s4, t1, oo_app            ; ...
        ld    s3, cnt(zero)             ; writing: the bytes go to a blob of their own,
        addi  t0, s3, 1                 ; marked as being written
        sd    t0, cnt(zero)             ; ...
        li    t0, 1                     ; ...
        sd    t0, cnt_d(zero)           ; ...
        sd    s3, O_DOID(s2)            ; ...
        mv    a0, s3                    ; ...
        call  wkey                      ; ...
        ld    a0, x_dict(zero)          ; ...
        la    a1, rkey                  ; ...
        li    a2, 16                    ; ...
        la    a3, rkey                  ; ...
        li    a4, 0                     ; ...
        li    a5, 0                     ; ...
        call  st_put                    ; ...
        li    t0, 2                     ; ...
        sd    t0, O_USED(s2)            ; ...
        j     oo_ref                    ; ...
oo_app:
        sd    t0, O_DOID(s2)            ; appending: to the contents where they are
        la    t0, rec                   ; ...
        ld    t0, R_SIZE(t0)            ; ...
        sd    t0, O_POS(s2)             ; ...
        li    t0, 3                     ; ...
        sd    t0, O_USED(s2)            ; ...
oo_ref:
        call  srv_pid                   ; the caller holds it
        addi  a1, s1, 1                 ; id
        call  ref_add                   ; ...
        addi  a0, s1, 1                 ; the id
        j     reply                     ; ...
oo_fail:
        call  tags_undo                 ; (tags made for nothing go; a0 kept)
        j     reply                     ; ...

op_read:
        la    t0, srv_hdr               ; the file
        ld    a0, 8(t0)                 ; ...
        call  orec                      ; ...
        beqz  a0, bad                   ; ...
        mv    s1, a0                    ; ...
        ld    t0, O_USED(s1)            ; open for reading?
        li    t1, 1                     ; ...
        bne   t0, t1, bad               ; ...
        la    t0, srv_hdr               ; s2 = bytes: min(wanted, 4032)
        ld    s2, 16(t0)                ; ...
        li    t1, SYS_MAX               ; ...
        bleu  s2, t1, ord_1             ; ...
        mv    s2, t1                    ; ...
ord_1:
        ld    a0, O_OID(s1)             ; ...
        call  bswap                     ; ...
        sd    a0, okey(zero)            ; ...
        ld    a0, x_data(zero)          ; ...
        la    a1, okey                  ; ...
        li    a2, 8                     ; ...
        ld    a3, O_POS(s1)             ; ...
        la    a4, sys_buf               ; ...
        mv    a5, s2                    ; ...
        call  st_bread                  ; ...
        bgtz  a0, ord_2                 ; ...
        li    a0, 0                     ; the end of the file (or an empty one)
        j     reply                     ; ...
ord_2:
        mv    s2, a0                    ; ...
        la    a0, sys_buf               ; -> the request
        mv    a1, s2                    ; ...
        call  srv_put                   ; ...
        ld    t0, O_POS(s1)             ; advance
        add   t0, t0, s2                ; ...
        sd    t0, O_POS(s1)             ; ...
        mv    a0, s2                    ; ...
        j     reply                     ; ...

; o_writer(a0 = id) -> a0 = its open record if it is open for writing, else 0
o_writer:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        call  orec                      ; ...
        beqz  a0, ow_ret                ; ...
        ld    t0, O_USED(a0)            ; ...
        addi  t0, t0, -2                ; (2 write, 3 append)
        li    t1, 2                     ; ...
        bltu  t0, t1, ow_ret            ; ...
        li    a0, 0                     ; ...
ow_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; o_put(a0 = open record, a1 = bytes in out_buf): they go to the end of what
; it has written; every MiB is committed, so that no change grows without end
o_put:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        ld    a0, O_DOID(s1)            ; ...
        call  bswap                     ; ...
        sd    a0, dokey(zero)           ; ...
        sd    zero, bw_force(zero)      ; ...
        ld    a0, x_data(zero)          ; ...
        la    a1, dokey                 ; ...
        li    a2, 8                     ; ...
        ld    a3, O_POS(s1)             ; ...
        la    a4, out_buf               ; ...
        mv    a5, s2                    ; ...
        call  st_bwrite                 ; ...
        ld    t0, O_POS(s1)             ; ...
        add   t1, t0, s2                ; ...
        sd    t1, O_POS(s1)             ; ...
        srli  t0, t0, 20                ; ...
        srli  t1, t1, 20                ; ...
        beq   t0, t1, op_ret            ; ...
        call  fs_commit                 ; ...
op_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

op_write:
        la    t0, srv_hdr               ; the file
        ld    a0, 8(t0)                 ; ...
        call  o_writer                  ; ...
        beqz  a0, bad                   ; ...
        mv    s1, a0                    ; ...
        la    t0, srv_hdr               ; s2 = bytes
        ld    s2, 16(t0)                ; ...
        li    t1, SYS_MAX               ; ...
        bleu  s2, t1, owr_1             ; ...
        mv    s2, t1                    ; ...
owr_1:
        li    a0, 0                     ; ...
        beqz  s2, reply                 ; ...
        la    a0, out_buf               ; the data -> D-LS
        mv    a1, s2                    ; ...
        call  srv_get                   ; ...
        mv    a0, s1                    ; ...
        mv    a1, s2                    ; ...
        call  o_put                     ; ...
        mv    a0, s2                    ; ...
        j     reply                     ; ...

op_close:
        call  srv_pid                   ; ...
        la    t0, srv_hdr               ; ...
        ld    a1, 8(t0)                 ; ...
        call  dropref                   ; ...
        j     ok                        ; ...

op_dups:
        call  ref_dups                  ; ...
        j     reply                     ; ...

op_cleanup:
        la    t0, srv_hdr               ; the dead process
        ld    s1, 8(t0)                 ; ...
        mv    a0, s1                    ; its current tag path is forgotten
        call  cwd_drop                  ; ...
ocl_l:
        mv    a0, s1                    ; its references, one by one
        call  ref_first                 ; ...
        bltz  a0, ok                    ; none left
        mv    a1, a0                    ; ...
        mv    a0, s1                    ; ...
        call  dropref                   ; ...
        j     ocl_l                     ; ...

; last_tag() -> a0 = 0, or 1 when the path's last component (nm) names one
; file: a last component that is a tag joins ptags, "-tag" joins xtags
last_tag:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        ld    a1, nmlen(zero)           ; a last component?
        li    a0, 0                     ; ...
        beqz  a1, lt_ret                ; ...
        la    a0, nm                    ; "-tag": an exclusion
        lbu   t0, 0(a0)                 ; ...
        li    t1, '-'                   ; ...
        beq   t0, t1, lt_excl           ; ...
        call  tag_find                  ; a tag?
        li    t0, 1                     ; no: a file
        bltz  a0, lt_one                ; ...
        la    a1, np                    ; ...
        call  qt_add                    ; ...
        li    a0, 0                     ; ...
        j     lt_ret                    ; ...
lt_excl:
        addi  a0, a0, 1                 ; the tag after the "-"
        addi  a1, a1, -1                ; ...
        call  tag_find                  ; ...
        li    t0, 0                     ; none: it excludes nothing
        bltz  a0, lt_one                ; ...
        la    a1, nx                    ; ...
        call  qt_add                    ; ...
        li    t0, 0                     ; ...
lt_one:
        mv    a0, t0                    ; ...
lt_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; rec_bits() -> a0 = rec's tags as a set: bit t for tag id t (ids below 64)
rec_bits:
        la    t0, rec                   ; ...
        lhu   t1, R_NTAGS(t0)           ; ...
        li    a0, 0                     ; ...
        li    t4, 64                    ; ...
        li    t5, 1                     ; ...
rb_l:
        beqz  t1, rb_r                  ; ...
        lwu   t3, R_TAGS(t0)            ; ...
        addi  t0, t0, 4                 ; ...
        addi  t1, t1, -1                ; ...
        bgeu  t3, t4, rb_l              ; ...
        sll   t3, t5, t3                ; ...
        or    a0, a0, t3                ; ...
        j     rb_l                      ; ...
rb_r:
        ret                             ; ...

op_dir:
        li    a0, 0                     ; the path: tags (and maybe a file)
        call  get_file                  ; ...
        bltz  a0, reply                 ; ...
        li    s7, 0                     ; s7 = the facets (none yet)
        li    s3, 0                     ; s3 = files
        la    s5, sys_buf               ; s5 = output
        la    t0, srv_hdr               ; s6 = matching files to skip
        ld    s6, 8(t0)                 ; ...
        call  last_tag                  ; ...
        bnez  a0, od_one                ; ...
        sd    zero, q_cur(zero)         ; ...
od_l:
        call  q_next                    ; ...
        beqz  a0, od_done               ; ...
        call  rec_bits                  ; its tags are facets
        or    s7, s7, a0                ; ...
        beqz  s6, od_put                ; ...
        addi  s6, s6, -1                ; ...
        j     od_l                      ; ...
od_put:
        li    t0, 126                   ; at most one message of records
        bgeu  s3, t0, od_l              ; (the facets still count every file)
        mv    a0, s5                    ; ...
        call  od_rec                    ; ...
        addi  s5, s5, 32                ; ...
        addi  s3, s3, 1                 ; ...
        j     od_l                      ; ...
od_one:
        call  lookup                    ; the file, with the tags before it
        beqz  a0, nofile                ; ...
        la    a0, sys_buf               ; one record
        call  od_rec                    ; ...
        li    s3, 1                     ; ...
        li    s7, 0                     ; (one file: no facets)
od_done:
        li    s1, 0                     ; facets: not the path's own tags
od_m:
        ld    t0, np(zero)              ; ...
        bgeu  s1, t0, od_out            ; ...
        slli  t0, s1, 3                 ; ...
        ld    t1, ptags(t0)             ; ...
        addi  s1, s1, 1                 ; ...
        li    t0, 64                    ; ...
        bgeu  t1, t0, od_m              ; ...
        li    t0, 1                     ; ...
        sll   t0, t0, t1                ; ...
        li    t2, -1                    ; ...
        xor   t0, t0, t2                ; ...
        and   s7, s7, t0                ; ...
        j     od_m                      ; ...
od_out:
        la    t0, srv_hdr               ; -> the reply's mode word
        sd    s7, 24(t0)                ; ...
        la    a0, sys_buf               ; -> the request
        slli  a1, s3, 5                 ; ...
        call  srv_put                   ; ...
        mv    a0, s3                    ; ...
        j     reply                     ; ...

; od_rec(a0 = record): rec's file as {name[24], u64 size}
od_rec:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        mv    s1, a0                    ; ...
        sd    zero, 0(s1)               ; ...
        sd    zero, 8(s1)               ; ...
        sd    zero, 16(s1)              ; ...
        la    t0, rec                   ; ...
        ld    t1, R_SIZE(t0)            ; ...
        sd    t1, 24(s1)                ; ...
        call  rec_name                  ; ...
        mv    a2, a1                    ; ...
        li    t0, 24                    ; (a longer name is cut)
        bleu  a2, t0, odr_1             ; ...
        mv    a2, t0                    ; ...
odr_1:
        mv    a1, a0                    ; ...
        mv    a0, s1                    ; ...
        call  srv_bcopy                 ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

op_unlink:
        li    a0, 0                     ; the path's tags must exist
        call  get_named                 ; ...
        bltz  a0, reply                 ; ...
        call  lookup                    ; ...
        beqz  a0, nofile                ; ...
        call  fs_remove                 ; ...
        bltz  a0, reply                 ; ...
        call  fs_commit                 ; ...
        j     ok                        ; ...

; TAG / UNTAG: data = a path, a zero byte, a tag name
op_tag:
        li    s4, 1                     ; s4 = 1 tag, 0 untag
        j     otg_go                    ; ...
op_untag:
        li    s4, 0                     ; ...
otg_go:
        call  get_two                   ; the path, and the tag's name
        bltz  a0, reply                 ; ...
        mv    s2, a0                    ; s2 = the tag's name
        mv    s3, a1                    ; s3 = its length
        li    a0, 0                     ; the path's tags must exist
        call  parse_file                ; ...
        bltz  a0, reply                 ; ...
        ld    t0, nmlen(zero)           ; it must name a file
        li    a0, -1                    ; ...
        beqz  t0, reply                 ; ...
        call  lookup                    ; ...
        beqz  a0, nofile                ; ...
        mv    a0, s2                    ; the tag (created when tagging)
        mv    a1, s3                    ; ...
        mv    a2, s4                    ; ...
        call  tag_ref                   ; a0 = its id or < 0
        bltz  a0, reply                 ; ...
        mv    s1, a0                    ; ...
        call  rec_hastag                ; ...
        beqz  s4, otg_un                ; ...
        bgez  a0, ok                    ; it carries it already
        sd    zero, np(zero)            ; tag: the one tag joins its own
        mv    a0, s1                    ; ...
        la    a1, np                    ; ...
        call  qt_add                    ; ...
        call  fs_addtags                ; ...
        bltz  a0, oo_fail               ; ...
        j     otg_done                  ; ...
otg_un:
        bltz  a0, ok                    ; it does not carry it
        call  rec_deltag                ; ...
        li    a0, 0                     ; ...
        mv    a1, s1                    ; ...
        call  idx_tag                   ; ...
        call  rec_save                  ; ...
        mv    a0, s1                    ; (an unused tag goes)
        li    a1, -1                    ; ...
        call  tag_count                 ; ...
otg_done:
        call  fs_commit                 ; ...
        j     ok                        ; ...

; CWD: the requester's current tag path (mode 0 get, 1 set, 2 inherit)
op_cwd:
        la    t0, srv_hdr               ; mode
        ld    t1, 24(t0)                ; ...
        beqz  t1, ocw_get               ; 0: get
        li    t2, 2                     ; 2: inherit
        beq   t1, t2, ocw_inh           ; ...
        li    t2, 1                     ; 1: set
        bne   t1, t2, bad               ; ...
        call  get_raw                   ; a0 = the length of the new path
        bltz  a0, reply                 ; ...
        beqz  a0, ocw_root              ; none: "/"
        mv    a1, a0                    ; resolved (relative to the current one)
        la    a0, rbuf                  ; ...
        call  setpath                   ; ...
        li    s1, 0                     ; s1 = cursor
        sd    zero, np(zero)            ; the tags of the view, and those it excludes
        sd    zero, nx(zero)            ; ...
ocw_c:
        mv    a0, s1                    ; every component: a tag, or "-" and a tag
        call  comp                      ; ...
        beqz  a1, ocw_chk               ; all seen
        mv    s1, a2                    ; ...
        la    s2, np                    ; s2 = the list it joins
        lbu   t0, 0(a0)                 ; ...
        li    t1, '-'                   ; ...
        bne   t0, t1, ocw_t             ; ...
        la    s2, nx                    ; ...
        addi  a0, a0, 1                 ; ...
        addi  a1, a1, -1                ; ...
ocw_t:
        call  tag_find                  ; a0 = its id, or -1
        bltz  a0, ocw_none              ; no such tag
        mv    a1, s2                    ; ...
        call  qt_add                    ; ...
        bltz  a0, reply                 ; ...
        j     ocw_c                     ; ...
ocw_chk:
        ld    t1, plen(zero)            ; ".." all the way: "/"
        beqz  t1, ocw_root              ; ...
        li    a0, -1                    ; too long to keep
        li    t2, CWDMAX                ; ...
        bgtu  t1, t2, reply             ; ...
        sd    zero, q_cur(zero)         ; a file in that view? (no empty views)
        call  q_next                    ; ...
        bnez  a0, ocw_set               ; ...
ocw_none:
        li    a0, -4                    ; no such tag (or nothing carries them all)
        j     reply                     ; ...
ocw_set:
        call  srv_pid                   ; s1 = the requester
        mv    s1, a0                    ; ...
        call  cwd_find                  ; its entry, or a free one
        bgez  a0, ocw_have              ; ...
        li    a0, 0                     ; ...
        call  cwd_find                  ; ...
        mv    t0, a0                    ; ...
        li    a0, -6                    ; none: the table is full
        bltz  t0, reply                 ; ...
        mv    a0, t0                    ; ...
ocw_have:
        mv    s2, a0                    ; ...
        slli  t0, s2, 3                 ; ...
        sd    s1, cwdp(t0)              ; ...
        ld    a2, plen(zero)            ; the new path
        sd    a2, cwdt(zero)            ; ...
        la    a0, cwdt + 8              ; ...
        la    a1, pbuf                  ; ...
        call  srv_bcopy                 ; ...
        mv    a0, s2                    ; ...
        call  cwd_store                 ; ...
        j     ocw_get                   ; answered as a get
ocw_root:
        call  srv_pid                   ; "/": no entry
        call  cwd_drop                  ; ...
ocw_get:
        call  srv_pid                   ; the requester's entry
        call  cwd_find                  ; ...
        bltz  a0, ocw_slash             ; none: "/"
        call  cwd_load                  ; ...
        ld    s1, cwdt(zero)            ; its text -> the request
        la    a0, cwdt + 8              ; ...
        mv    a1, s1                    ; ...
        call  srv_put                   ; ...
        mv    a0, s1                    ; its length
        j     reply                     ; ...
ocw_slash:
        la    a0, sys_buf               ; "/"
        li    t0, '/'                   ; ...
        sd    t0, 0(a0)                 ; ...
        li    a1, 1                     ; ...
        call  srv_put                   ; ...
        li    a0, 1                     ; ...
        j     reply                     ; ...
ocw_inh:
        call  srv_pid                   ; from proc only
        li    t0, PROC_PID              ; ...
        bne   a0, t0, bad               ; ...
        la    a0, sys_buf               ; parent, child
        li    a1, 16                    ; ...
        call  srv_get                   ; ...
        la    t0, sys_buf               ; ...
        ld    s1, 0(t0)                 ; s1 = the parent
        ld    s2, 8(t0)                 ; s2 = the child
        mv    a0, s2                    ; a stale entry of the child's goes
        call  cwd_drop                  ; ...
        beqz  s2, ok                    ; (a child of pid 0: nothing)
        beqz  s1, ok                    ; ...
        mv    a0, s1                    ; the parent's
        call  cwd_find                  ; ...
        bltz  a0, ok                    ; at "/": so is the child
        call  cwd_load                  ; ...
        li    a0, 0                     ; a free entry
        call  cwd_find                  ; ...
        bltz  a0, ok                    ; none: the child starts at "/"
        slli  t0, a0, 3                 ; a copy of the parent's, for the child
        sd    s2, cwdp(t0)              ; ...
        call  cwd_store                 ; ...
        j     ok                        ; ...

; RENAME: data = a path, a zero byte, the new path
op_rename:
        call  get_two                   ; the path, and the new one
        bltz  a0, reply                 ; ...
        mv    s2, a0                    ; s2, s3 = the new path
        mv    s3, a1                    ; ...
        li    a0, 0                     ; the old path's tags must exist
        call  parse_file                ; ...
        bltz  a0, reply                 ; ...
        ld    t0, nmlen(zero)           ; it must name a file
        li    a0, -1                    ; ...
        beqz  t0, reply                 ; ...
        call  lookup                    ; s1 = the file
        beqz  a0, nofile                ; ...
        mv    s1, a0                    ; ...
        la    t0, rec                   ; (not a boot object)
        lbu   t0, R_FLAGS(t0)           ; ...
        andi  t0, t0, 1                 ; ...
        bnez  t0, bad                   ; ...
        mv    a0, s2                    ; the new path -> pbuf, resolved (it is
        mv    a1, s3                    ; in rbuf, apart from pbuf)
        call  setpath                   ; ...
        li    a0, 1                     ; its tags are created if need be
        call  parse_file                ; ...
        bltz  a0, oo_fail               ; ...
        ld    t0, nmlen(zero)           ; it must name a file
        li    a0, -1                    ; ...
        beqz  t0, oo_fail               ; ...
        call  find                      ; another file of the new name goes
        beqz  a0, orn_name              ; none
        beq   a0, s1, orn_tags          ; the file itself: only tags to add
        call  rec_load                  ; ...
        call  fs_remove                 ; ...
        bltz  a0, oo_fail               ; ...
orn_name:
        mv    a0, s1                    ; the file's record
        call  rec_load                  ; ...
        call  rec_name                  ; its old name leaves the names
        sub   s4, a0, t0                ; s4 = where the name is in the record (t0 = rec)
        mv    a2, a1                    ; ...
        mv    a1, a0                    ; ...
        la    a0, tnbuf                 ; ...
        sd    a2, dk_len(zero)          ; ...
        call  srv_bcopy                 ; ...
        ld    t0, nmlen(zero)           ; the new one must fit the record
        add   t0, t0, s4                ; ...
        ld    t1, rec_max(zero)         ; ...
        li    a0, -6                    ; ...
        bgtu  t0, t1, oo_fail           ; ...
        sd    t0, rec_len(zero)         ; ...
