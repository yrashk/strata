        sd    t0, 8(s5)                 ; ...
        lhu   t1, 0(s5)                 ; the name, padded with zeros
        add   t1, t1, s5                ; ...
        sd    zero, -8(t1)              ; ...
        addi  a0, s5, 16                ; ...
        la    a1, tnbuf                 ; ...
        mv    a2, s2                    ; ...
        mv    s5, t1                    ; ...
        call  srv_bcopy                 ; ...
        addi  s3, s3, 1                 ; ...
        li    a0, 1                     ; ...
o2r_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; =============================================================================
; Snapshots
; =============================================================================
;
; A snapshot is the whole store as of one commit, under a name: taking one
; records that commit's catalog root in the tree "snap" of namespace 0 (u64
; commit, big-endian -> u64 catalog root, u64 height, the name) and copies
; nothing. From then on the store keeps the pages that commit used (storew.s:
; st_deadlim and the dead lists). A request whose path begins with "@NAME"
; is served from the snapshot's trees: the file system's six trees as that
; catalog has them stand in for the live ones until the reply.

; snap_done(): the live trees again (a0 kept)
snap_done:
        ld    t0, snap_on(zero)         ; ...
        beqz  t0, snd_ret               ; ...
        sd    zero, snap_on(zero)       ; ...
        li    t0, 0                     ; ...
snd_l:
        ld    t1, xsave(t0)             ; ...
        sd    t1, x_obj(t0)             ; ...
        addi  t0, t0, 8                 ; ...
        li    t1, 48                    ; ...
        bne   t0, t1, snd_l             ; ...
        ld    t0, x_ext(zero)           ; ...
        sd    t0, bl_ext(zero)          ; ...
snd_ret:
        ret                             ; ...

; snap_use(a0 = a snapshot's commit) -> a0 = 0, or -1 when there is none of
; that commit: its trees stand in for the live ones until snap_done
snap_use:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        mv    s3, a0                    ; ...
        call  snap_done                 ; (one at a time)
        mv    a0, s3                    ; ...
        call  bswap                     ; ...
        sd    a0, rkey(zero)            ; ...
        ld    a0, x_snap(zero)          ; ...
        la    a1, rkey                  ; ...
        li    a2, 8                     ; ...
        la    a3, tnbuf                 ; ...
        call  st_get                    ; ...
        bltz  a0, snu_ret               ; (a0 = -1)
        ld    t0, tnbuf(zero)           ; its catalog
        sd    t0, scat(zero)            ; ...
        ld    t0, tnbuf+8(zero)         ; ...
        sd    t0, scat+8(zero)          ; ...
        li    s1, 0                     ; s1 = the tree (times 8)
        la    s2, s_obj                 ; s2 = its name: 3 bytes the first, 4 the others
snu_l:
        la    t0, ckey                  ; its catalog key: the namespace, the name
        sd    zero, 0(t0)               ; ...
        ld    t1, fs_ns(zero)           ; ...
        sb    t1, 3(t0)                 ; (the file system's namespace: below 256)
        addi  a0, t0, 4                 ; ...
        mv    a1, s2                    ; ...
        snez  a2, s1                    ; ...
        addi  a2, a2, 3                 ; ...
        add   s2, s2, a2                ; ...
        call  srv_bcopy                 ; ...
        sd    zero, cval(zero)          ; (a tree the snapshot does not have: empty)
        sd    zero, cval+8(zero)        ; ...
        la    a0, scat                  ; ...
        la    a1, ckey                  ; ...
        snez  a2, s1                    ; ...
        addi  a2, a2, 7                 ; ...
        la    a3, cval                  ; ...
        call  st_get                    ; ...
        slli  t0, s1, 1                 ; ...
        ld    t1, cval(zero)            ; ...
        sd    t1, sx(t0)                ; ...
        ld    t1, cval+8(zero)          ; ...
        sd    t1, sx+8(t0)              ; ...
        ld    t1, x_obj(s1)             ; the live tree's place is kept
        sd    t1, xsave(s1)             ; ...
        la    t1, sx                    ; ...
        add   t1, t1, t0                ; ...
        sd    t1, x_obj(s1)             ; ...
        addi  s1, s1, 8                 ; ...
        li    t0, 48                    ; ...
        bne   s1, t0, snu_l             ; ...
        ld    t0, x_ext(zero)           ; ...
        sd    t0, bl_ext(zero)          ; ...
        sd    s3, snap_on(zero)         ; ...
        li    a0, 0                     ; ...
snu_ret:
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; snap_find(a0 = name, a1 = its length) -> a0 = the commit of the snapshot of
; that name, or 0 (its record is then in rkey, tnbuf)
snap_find:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        mv    s1, a0                    ; ...
        mv    s2, a1                    ; ...
        sd    zero, rkey(zero)          ; ...
snf_l:
        ld    a0, x_snap(zero)          ; ...
        la    a1, rkey                  ; ...
        li    a2, 8                     ; ...
        li    a3, ST_GT                 ; ...
        la    a4, rkey                  ; ...
        la    a5, tnbuf                 ; ...
        call  st_seek                   ; ...
        beqz  a0, snf_ret               ; ...
        la    a0, tnbuf + 16            ; ...
        ld    a1, sk_vl(zero)           ; ...
        addi  a1, a1, -16               ; ...
        mv    a2, s1                    ; ...
        mv    a3, s2                    ; ...
        call  kcmp                      ; ...
        bnez  a0, snf_l                 ; ...
        ld    a0, rkey(zero)            ; ...
        call  bswap                     ; ...
snf_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

; snap_path(): a resolved path (pbuf, plen) whose first component is "@NAME"
; is a path in that snapshot: the component goes, and the snapshot's trees
; are in use. Only for requests that read (OPEN, DIR, TAGS, STAT, LOADIMG,
; QUERY, TAGS2); for the others, and for a snapshot that is not there,
; snap_bad is set and the path names nothing.
SNAP_OPS = (1 << 3) + (1 << 10) + (1 << 14) + (1 << 27) + (1 << 28) + (1 << 40) + (1 << 41)
snap_path:
        la    t0, pbuf                  ; ...
        ld    t1, plen(zero)            ; ...
        li    t2, 3                     ; ...
        bltu  t1, t2, snd_ret           ; ...
        lbu   t2, 1(t0)                 ; ...
        li    t3, '@'                   ; ...
        bne   t2, t3, snd_ret           ; ...
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        li    s1, 2                     ; s1 = where the component ends
        li    t3, '/'                   ; ...
snp_e:
        bgeu  s1, t1, snp_f             ; ...
        add   t2, t0, s1                ; ...
        lbu   t2, 0(t2)                 ; ...
        beq   t2, t3, snp_f             ; ...
        addi  s1, s1, 1                 ; ...
        j     snp_e                     ; ...
snp_f:
        la    t2, srv_hdr               ; a request that may read a snapshot?
        ld    t2, 0(t2)                 ; ...
        li    t3, SNAP_OPS              ; ...
        srl   t3, t3, t2                ; ...
        andi  t3, t3, 1                 ; ...
        beqz  t3, snp_bad               ; ...
        addi  a0, t0, 2                 ; ...
        addi  a1, s1, -2                ; ...
        call  snap_find                 ; ...
        beqz  a0, snp_bad               ; ...
        call  snap_use                  ; ...
        la    a0, pbuf                  ; the rest of the path moves to the front
        add   a1, a0, s1                ; ...
        ld    a2, plen(zero)            ; ...
        sub   a2, a2, s1                ; ...
        sd    a2, plen(zero)            ; ...
        sd    zero, pcwdl(zero)         ; ...
        call  srv_bcopy                 ; ...
        j     snp_ret                   ; ...
snp_bad:
        li    t0, 1                     ; ...
        sd    t0, snap_bad(zero)        ; ...
snp_ret:
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; SNAP: mode 0 take (data = a name of 1..32 bytes) -> 0 / -1 (a bad name, or
; taken already); mode 1 delete (data = the name) -> 0 / -4; mode 2 list ->
; snapshots; data: 40-byte records {u64 commit, name[32]}; mode 3 restore
; (data = the name) -> 0 / -4 / -1 (a file is open for writing)
op_snap:
        la    t0, srv_hdr               ; ...
        ld    s4, 24(t0)                ; s4 = the mode
        li    t1, 2                     ; ...
        beq   s4, t1, osn_list          ; ...
        call  get_raw                   ; the name
        mv    s2, a0                    ; ...
        blez  s2, bad                   ; ...
        li    t0, 32                    ; ...
        bgtu  s2, t0, bad               ; ...
        la    a0, rbuf                  ; ...
        mv    a1, s2                    ; ...
        call  snap_find                 ; ...
        mv    s1, a0                    ; s1 = its commit, if it is there
        li    t0, 3                     ; ...
        beq   s4, t0, osn_rest          ; ...
        bnez  s4, osn_del               ; ...
        bnez  s1, bad                   ; take: not twice
        call  fs_commit                 ; what is committed now is the snapshot
        ld    s1, st_cmt(zero)          ; ...
        la    a0, tnbuf                 ; its record: the catalog as committed, the name
        li    a1, 48                    ; ...
        call  wzero                     ; ...
        ld    t0, t_cat(zero)           ; ...
        sd    t0, tnbuf(zero)           ; ...
        ld    t0, t_cat+8(zero)         ; ...
        sd    t0, tnbuf+8(zero)         ; ...
        la    a0, tnbuf + 16            ; ...
        la    a1, rbuf                  ; ...
        mv    a2, s2                    ; ...
        call  srv_bcopy                 ; ...
        sd    s1, st_deadlim(zero)      ; from now on that commit's pages are kept
        mv    a0, s1                    ; ...
        call  bswap                     ; ...
        sd    a0, rkey(zero)            ; ...
        ld    a0, x_snap(zero)          ; ...
        la    a1, rkey                  ; ...
        li    a2, 8                     ; ...
        la    a3, tnbuf                 ; ...
        addi  a4, s2, 16                ; ...
        li    a5, 0                     ; ...
        call  st_put                    ; ...
        call  fs_commit                 ; ...
        j     ok                        ; ...
osn_del:
        beqz  s1, nofile                ; delete: it must be there
        call  fs_commit                 ; ...
        mv    a0, s1                    ; s2 = the snapshot before it (0: none)
        call  bswap                     ; ...
        sd    a0, rkey(zero)            ; ...
        li    s2, 0                     ; ...
        ld    a0, x_snap(zero)          ; ...
        la    a1, rkey                  ; ...
        li    a2, 8                     ; ...
        li    a3, ST_LT                 ; ...
        la    a4, dval                  ; ...
        li    a5, 0                     ; ...
        call  st_seek                   ; ...
        beqz  a0, osn_d1                ; ...
        ld    a0, dval(zero)            ; ...
        call  bswap                     ; ...
        mv    s2, a0                    ; ...
osn_d1:
        ld    s5, st_deadlim(zero)      ; s5 = the newest snapshot once this one is gone
        bne   s5, s1, osn_d2            ; ...
        mv    s5, s2                    ; ...
osn_d2:
        sd    s2, st_deadlim(zero)      ; its dead list: what was born after the one before
        li    s3, 1                     ; is free, the rest goes on that one's list
        slli  s3, s3, 63                ; ...
        or    a0, s3, s1                ; ...
        call  bswap                     ; ...
        mv    s3, a0                    ; s3 = the list's key, as stored
osn_dl:
        sd    s3, rkey(zero)            ; ...
        sd    zero, rkey+8(zero)        ; ...
        la    a0, t_pend                ; ...
        la    a1, rkey                  ; ...
        li    a2, 16                    ; ...
        li    a3, ST_GT                 ; ...
        la    a4, rkey                  ; ...
        la    a5, dval                  ; ...
        call  st_seek                   ; ...
        beqz  a0, osn_dd                ; ...
        ld    t0, rkey(zero)            ; ...
        bne   t0, s3, osn_dd            ; ...
        call  relief                    ; ...
        li    t0, 1                     ; (the pending tree's own pages: no snapshot's)
        sd    t0, in_rel(zero)          ; ...
        la    a0, t_pend                ; ...
        la    a1, rkey                  ; ...
        li    a2, 16                    ; ...
        call  st_del                    ; ...
        sd    zero, in_rel(zero)        ; ...
        ld    a0, rkey+8(zero)          ; ...
        call  bswap                     ; ...
        ld    a1, dval(zero)            ; the pages, as their namespace's again
        srli  t0, a1, 32                ; ...
        sd    t0, st_owner(zero)        ; ...
        lwu   a1, dval(zero)            ; ...
        ld    a2, dval+8(zero)          ; ...
        call  pfree                     ; ...
        j     osn_dl                    ; ...
osn_dd:
        li    t0, 1                     ; that is recorded by the rule of the one before;
        sd    t0, in_rel(zero)          ; everything else by the newest one's
        call  drain_fr                  ; ...
        sd    zero, in_rel(zero)        ; ...
        sd    s5, st_deadlim(zero)      ; ...
        mv    a0, s1                    ; its record goes
        call  bswap                     ; ...
        sd    a0, rkey(zero)            ; ...
        ld    a0, x_snap(zero)          ; ...
        la    a1, rkey                  ; ...
        li    a2, 8                     ; ...
        call  st_del                    ; ...
        call  fs_commit                 ; ...
        j     ok                        ; ...
osn_list:
        li    s3, 0                     ; s3 = records
        la    s5, sys_buf               ; ...
        sd    zero, rkey(zero)          ; ...
osn_l:
        li    t0, 100                   ; ...
        bgeu  s3, t0, osn_ld            ; ...
        ld    a0, x_snap(zero)          ; ...
        la    a1, rkey                  ; ...
        li    a2, 8                     ; ...
        li    a3, ST_GT                 ; ...
        la    a4, rkey                  ; ...
        la    a5, tnbuf                 ; ...
        call  st_seek                   ; ...
        beqz  a0, osn_ld                ; ...
        ld    a0, rkey(zero)            ; ...
        call  bswap                     ; ...
        sd    a0, 0(s5)                 ; ...
        addi  a0, s5, 8                 ; ...
        la    a1, tnbuf + 16            ; (the name is zero-padded in its record)
        li    a2, 32                    ; ...
        call  wcopy                     ; ...
        addi  s5, s5, 40                ; ...
        addi  s3, s3, 1                 ; ...
        j     osn_l                     ; ...
osn_ld:
        la    a0, sys_buf               ; ...
        sub   a1, s5, a0                ; ...
        call  srv_put                   ; ...
        mv    a0, s3                    ; ...
        j     reply                     ; ...

; ---- restoring a snapshot ------------------------------------------------------------
; The file system becomes what the snapshot shows: its six trees take the
; snapshot's roots, in one commit. (The snapshots stay, the one restored
; too; other namespaces are not touched.) Two things keep the pages right:
;   - what only the state given up used is freed: its pages born after the
;     snapshot (a page born before it is the snapshot's too; and since a
;     page's children are never younger than it, such a page ends the walk);
;   - what the snapshot shows and the state given up had dropped is in use
;     again: those pages (the file system's, born no later than the
;     snapshot, on the dead list of it or of a later one) leave the dead
;     lists.

; drop_tree(a0 = a tree, a1 = 1: its records are extents, to be freed with
; it): its pages born after commit s1 are freed (s1 is the caller's)
drop_tree:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s2, 8(sp)                 ; ...
        sd    s3, 16(sp)                ; ...
        sd    s4, 24(sp)                ; ...
        sd    s5, 32(sp)                ; ...
        mv    s5, a1                    ; s5 = extents?
        ld    t0, 0(a0)                 ; ...
        beqz  t0, dt_ret                ; ...
        li    s2, 0                     ; s2 = the level (times 16)
        sd    t0, wpath(zero)           ; (no tree change is under way: its path serves)
        sd    zero, wpath+8(zero)       ; ...
dt_l:
        call  relief                    ; (the lists of freed pages are written out as they fill)
        ld    a0, wpath(s2)             ; ...
        call  P                         ; ...
        mv    s3, a0                    ; s3 = the page
        ld    s4, 16(s3)                ; s4 = its birth
        bleu  s4, s1, dt_up             ; the snapshot's too: so is all below it
        lbu   t0, 24(s3)                ; ...
        li    t1, K_LEAF                ; ...
        beq   t0, t1, dt_leaf           ; ...
        ld    a1, wpath+8(s2)           ; a branch: its next child, or it is done
        lhu   t0, 26(s3)                ; ...
        bgeu  a1, t0, dt_free           ; ...
        addi  t0, a1, 1                 ; ...
        sd    t0, wpath+8(s2)           ; ...
        call  child                     ; ...
        addi  s2, s2, 16                ; ...
        sd    a0, wpath(s2)             ; ...
        sd    zero, wpath+8(s2)         ; ...
        j     dt_l                      ; ...
dt_leaf:
        beqz  s5, dt_free               ; extents born after the snapshot go with it
        ld    a1, wpath+8(s2)           ; ...
        lhu   t0, 26(s3)                ; ...
        bgeu  a1, t0, dt_free           ; ...
        addi  t0, a1, 1                 ; ...
        sd    t0, wpath+8(s2)           ; ...
        slli  a1, a1, 1                 ; its cell: key 16 bytes, value {start, pages, birth}
        add   a1, a1, s3                ; ...
        lhu   a1, 32(a1)                ; ...
        add   a1, a1, s3                ; ...
        ld    a2, 40(a1)                ; ...
        bleu  a2, s1, dt_l              ; ...
        ld    t0, fs_ns(zero)           ; ...
        sd    t0, st_owner(zero)        ; ...
        ld    a0, 24(a1)                ; ...
        ld    a1, 32(a1)                ; ...
        call  pfree                     ; ...
        j     dt_l                      ; ...
dt_free:
        ld    t0, fs_ns(zero)           ; ...
        sd    t0, st_owner(zero)        ; ...
        ld    a0, wpath(s2)             ; the page itself
        li    a1, 1                     ; ...
        mv    a2, s4                    ; ...
        call  pfree                     ; ...
dt_up:
        beqz  s2, dt_ret                ; ...
        addi  s2, s2, -16               ; ...
        j     dt_l                      ; ...
dt_ret:
        ld    s5, 32(sp)                ; ...
        ld    s4, 24(sp)                ; ...
        ld    s3, 16(sp)                ; ...
        ld    s2, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 40                ; ...
        ret                             ; ...

osn_rest:
        beqz  s1, nofile                ; restore: it must be there,
        la    t0, opens                 ; and no file open for writing
        li    t1, NOPEN                 ; ...
osr_o:
        ld    t2, O_USED(t0)            ; ...
        li    t3, 2                     ; ...
        bgeu  t2, t3, bad               ; ...
        addi  t0, t0, O_SIZEOF          ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, osr_o                 ; ...
        call  fs_commit                 ; ...
        call  begin                     ; ...
        mv    a0, s1                    ; the snapshot's six roots -> sx
        call  snap_use                  ; ...
        bltz  a0, nofile                ; ...
        call  snap_done                 ; (the live trees are at hand again)
        li    s2, 0                     ; every tree: what only the live state used goes,
osr_t:
        ld    a0, x_obj(s2)             ; ...
        addi  a1, s2, -40               ; (the sixth is the extents' tree)
        seqz  a1, a1                    ; ...
        call  drop_tree                 ; ...
        ld    t0, x_obj(s2)             ; and it takes the snapshot's root
        slli  t1, s2, 1                 ; ...
        ld    t2, sx(t1)                ; ...
        sd    t2, 0(t0)                 ; ...
        ld    t2, sx+8(t1)              ; ...
        sd    t2, 8(t0)                 ; ...
        addi  s2, s2, 8                 ; ...
        li    t0, 48                    ; ...
        bne   s2, t0, osr_t             ; ...
        li    s3, 1                     ; the dead lists of this snapshot and the later ones:
        slli  s3, s3, 63                ; what was born no later than it is in use again
        or    a0, s3, s1                ; ...
        call  bswap                     ; ...
        sd    a0, rkey(zero)            ; ...
        sd    zero, rkey+8(zero)        ; ...
osr_d:
        la    a0, t_pend                ; ...
        la    a1, rkey                  ; ...
        li    a2, 16                    ; ...
        li    a3, ST_GT                 ; ...
        la    a4, rkey                  ; ...
        la    a5, dval                  ; ...
        call  st_seek                   ; ...
        beqz  a0, osr_c                 ; ...
        ld    t0, dval+8(zero)          ; ...
        bgtu  t0, s1, osr_d             ; ...
        ld    t0, dval(zero)            ; (the file system's own pages only: the catalog's
        srli  t0, t0, 32                ; old pages are the snapshots' still)
        ld    t1, fs_ns(zero)           ; ...
        bne   t0, t1, osr_d             ; ...
        li    t0, 1                     ; ...
        sd    t0, in_rel(zero)          ; ...
        la    a0, t_pend                ; ...
        la    a1, rkey                  ; ...
        li    a2, 16                    ; ...
        call  st_del                    ; ...
        sd    zero, in_rel(zero)        ; ...
        j     osr_d                     ; ...
osr_c:
        la    t0, dkey                  ; the counters as the snapshot has them
        li    t1, '!'                   ; ...
        sb    t1, 0(t0)                 ; ...
        ld    a0, x_dict(zero)          ; ...
        mv    a1, t0                    ; ...
        li    a2, 1                     ; ...
        la    a3, cnt                   ; ...
        call  st_get                    ; ...
        sd    zero, cnt_d(zero)         ; ...
        call  boot_man                  ; (the boot objects are where they were then)
        call  st_commit                 ; ...
        j     ok                        ; ...

; =============================================================================
; The store for programs
; =============================================================================
;
; A program keeps its own data in the store beside the file system: in a
; NAMESPACE of its own, in named TREES of keys and values (bytes, compared
; as unsigned bytes: a key of 1 byte to an eighth of a page less 32, a value
; of up to about a quarter page). A namespace and a tree are made by the
; first write to them. A namespace is public (anyone names it) or private;
; the ones made here are public, and "fs" is private: these calls refuse it.
;
; Every request's data starts with: u8 namespace name length (1..32), u8
; tree name length (1..28; not starting with "."), u16 key length, u32 0;
; then the two names.
;  64 DBGET   then the key -> the value's length, data: the value; -4 no such
;             namespace, tree or key; -1 a bad request, or a private namespace
;  65 DBSCAN  then a key (none: from the start); mode = ST_GE (0: from the key
;             on), ST_GT (1: after it), ST_LE, ST_LT -> records, data: per
;             record {u16 key length, u16 value length, u32 0, the key, the
;             value}, key and value each padded to 8 bytes: the record on
;             that side of the key and those after it in key order, as many
;             as fit (ask again with the last key and mode 1); the reply's
;             length word is the data's bytes
;  66 DBBATCH handle = items; from the next multiple of 8 after the names,
;             per item {u8 1 put / 2 delete, u8 0, u16 key length, u16 value
;             length, u16 0, the key, the value}, key and value each padded
;             to 8 bytes -> 0: all of them are on the disk, or (-1, a bad
;             item) none is. One commit: the unit of atomic change.

; db_parse(a0 = 1: make the namespace and the tree if missing) -> a0 = 0 and
; s1 = the tree, s2 = what follows the names in reqbuf, s3 = the key length;
; or a0 = -1 / -4
db_parse:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s4, 8(sp)                 ; ...
        sd    s5, 16(sp)                ; ...
        mv    s4, a0                    ; s4 = make?
        la    t0, srv_hdr               ; the data
        ld    s5, 16(t0)                ; s5 = its length
        li    a0, -1                    ; ...
        li    t1, 8                     ; ...
        bltu  s5, t1, dbp_ret           ; ...
        li    t1, SYS_MAX               ; ...
        bgtu  s5, t1, dbp_ret           ; ...
        la    a0, reqbuf                ; ...
        mv    a1, s5                    ; ...
        call  srv_get                   ; ...
        la    t0, reqbuf                ; ...
        lbu   t1, 0(t0)                 ; the names' lengths
        lbu   t2, 1(t0)                 ; ...
        lhu   s3, 2(t0)                 ; ...
        li    a0, -1                    ; ...
        beqz  t1, dbp_ret               ; ...
        beqz  t2, dbp_ret               ; ...
        li    t3, 32                    ; ...
        bgtu  t1, t3, dbp_ret           ; ...
        li    t3, 28                    ; ...
        bgtu  t2, t3, dbp_ret           ; ...
        add   t3, t1, t2                ; all inside the data?
        addi  t3, t3, 8                 ; ...
        bgtu  t3, s5, dbp_ret           ; ...
        add   s2, t0, t3                ; ...
        add   t3, t0, t1                ; (the tree's name)
        lbu   t4, 8(t3)                 ; ...
        li    t5, '.'                   ; ...
        beq   t4, t5, dbp_ret           ; ...
        ld    a0, x_nst(zero)           ; the namespace
        addi  a1, t0, 8                 ; ...
        mv    a2, t1                    ; ...
        la    a3, dval                  ; ...
        call  st_get                    ; ...
        bgez  a0, dbp_have              ; ...
        li    a0, -4                    ; ...
        beqz  s4, dbp_ret               ; ...
        ld    t0, st_nextns(zero)       ; a new one: public
        sd    t0, dval(zero)            ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, st_nextns(zero)       ; ...
        li    t0, 1                     ; ...
        sd    t0, dval+8(zero)          ; ...
        ld    a0, x_nst(zero)           ; ...
        la    a1, reqbuf + 8            ; ...
        lbu   a2, reqbuf(zero)          ; ...
        la    a3, dval                  ; ...
        li    a4, 16                    ; ...
        li    a5, 0                     ; ...
        call  st_put                    ; ...
dbp_have:
        ld    t0, dval+8(zero)          ; public?
        andi  t0, t0, 1                 ; ...
        li    a0, -1                    ; ...
        beqz  t0, dbp_ret               ; ...
        ld    a0, dval(zero)            ; its tree
        la    t0, reqbuf                ; ...
        lbu   t1, 0(t0)                 ; ...
        add   a1, t0, t1                ; ...
        addi  a1, a1, 8                 ; ...
        lbu   a2, 1(t0)                 ; ...
        mv    a3, s4                    ; ...
        call  st_tree                   ; ...
        mv    s1, a0                    ; ...
        li    a0, -4                    ; ...
        beqz  s1, dbp_ret               ; ...
        li    a0, 0                     ; ...
dbp_ret:
        ld    s5, 16(sp)                ; ...
        ld    s4, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        ret                             ; ...

op_dbget:
        li    a0, 0                     ; ...
        call  db_parse                  ; ...
        bltz  a0, reply                 ; ...
        mv    a0, s1                    ; ...
        mv    a1, s2                    ; ...
        mv    a2, s3                    ; ...
        la    a3, sys_buf               ; ...
        call  st_get                    ; ...
        sd    zero, TT_FL(s1)           ; (the tree is not kept open)
        bltz  a0, nofile                ; ...
        bnez  a1, bad                   ; (a stream: not through this call)
        mv    s3, a0                    ; ...
        la    a0, sys_buf               ; ...
        mv    a1, s3                    ; ...
        call  srv_put                   ; ...
        mv    a0, s3                    ; ...
        j     reply                     ; ...

op_dbscan:
        li    a0, 0                     ; ...
        call  db_parse                  ; ...
        bltz  a0, reply                 ; ...
        la    a0, pgcopy                ; the key at hand (pgcopy), a value (pgcopy + 512)
        mv    a1, s2                    ; ...
        mv    a2, s3                    ; ...
        call  srv_bcopy                 ; ...
        la    t0, srv_hdr               ; s4 = the side of the key for the first one
        ld    s4, 24(t0)                ; ...
        li    s6, 0                     ; s6 = records
        la    s5, sys_buf               ; s5 = output
odb_l:
        mv    a0, s1                    ; ...
        la    a1, pgcopy                ; ...
        mv    a2, s3                    ; ...
        mv    a3, s4                    ; ...
        la    a4, pgcopy                ; ...
        la    a5, pgcopy + 512          ; ...
        call  st_seek                   ; ...
        beqz  a0, odb_done              ; ...
        ld    s3, sk_kl(zero)           ; ...
        li    s4, ST_GT                 ; (the ones after it follow)
        ld    t1, sk_vl(zero)           ; room for it?
        addi  t2, s3, 7                 ; ...
        srli  t2, t2, 3                 ; ...
        slli  t2, t2, 3                 ; ...
        addi  t3, t1, 7                 ; ...
        srli  t3, t3, 3                 ; ...
        slli  t3, t3, 3                 ; ...
        add   t4, t2, t3                ; ...
        addi  t4, t4, 8                 ; ...
        add   t4, t4, s5                ; ...
        la    t5, sys_buf + SYS_MAX     ; ...
        bgtu  t4, t5, odb_done          ; ...
        sd    zero, 0(s5)               ; ...
        sh    s3, 0(s5)                 ; ...
        sh    t1, 2(s5)                 ; ...
        addi  a0, s5, 8                 ; ...
        la    a1, pgcopy                ; ...
        mv    a2, t2                    ; ...
        add   s5, a0, t2                ; ...
        call  wcopy                     ; ...
        mv    a0, s5                    ; ...
        la    a1, pgcopy + 512          ; ...
        ld    a2, sk_vl(zero)           ; ...
        addi  a2, a2, 7                 ; ...
        srli  a2, a2, 3                 ; ...
        slli  a2, a2, 3                 ; ...
        add   s5, s5, a2                ; ...
        call  wcopy                     ; ...
        addi  s6, s6, 1                 ; ...
        j     odb_l                     ; ...
odb_done:
        sd    zero, TT_FL(s1)           ; ...
        la    a0, sys_buf               ; ...
        sub   a1, s5, a0                ; ...
        la    t0, srv_hdr               ; ...
        sd    a1, 16(t0)                ; ...
        call  srv_put                   ; ...
        mv    a0, s6                    ; ...
        j     reply                     ; ...

op_dbbatch:
        li    a0, 1                     ; ...
        call  db_parse                  ; ...
        bltz  a0, reply                 ; ...
        la    t0, reqbuf                ; s2 = the first item: at a multiple of 8
        sub   s2, s2, t0                ; ...
        addi  s2, s2, 7                 ; ...
        srli  s2, s2, 3                 ; ...
        slli  s2, s2, 3                 ; ...
        add   s2, s2, t0                ; ...
        la    t0, srv_hdr               ; s6 = the end of the data
        ld    s6, 16(t0)                ; ...
        la    t1, reqbuf                ; ...
        add   s6, s6, t1                ; ...
        ld    s7, 8(t0)                 ; s7 = items
        li    s5, 0                     ; first every item is looked at (s5 = 0), then done (1)
obb_pass:
        mv    s3, s2                    ; s3 = the item
        mv    s4, s7                    ; s4 = items left
obb_l:
        beqz  s4, obb_next              ; ...
        addi  t0, s3, 8                 ; inside the data?
        bgtu  t0, s6, obb_bad           ; ...
        lhu   a2, 2(s3)                 ; the key's length, the value's
        lhu   a4, 4(s3)                 ; ...
        addi  t1, a2, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        addi  t2, a4, 7                 ; ...
        srli  t2, t2, 3                 ; ...
        slli  t2, t2, 3                 ; ...
        add   t3, t0, t1                ; t3 = the value, t4 = the next item
        add   t4, t3, t2                ; ...
        bgtu  t4, s6, obb_bad           ; ...
        lbu   t5, 0(s3)                 ; ...
        addi  t5, t5, -1                ; ...
        li    t6, 2                     ; ...
        bgeu  t5, t6, obb_bad           ; ...
        bnez  s5, obb_do                ; ...
        beqz  a2, obb_bad               ; a key and a value of a size the store takes?
        ld    t6, st_ps(zero)           ; ...
        srli  t0, t6, 3                 ; ...
        addi  t0, t0, -32               ; ...
        bgtu  a2, t0, obb_bad           ; ...
        addi  t6, t6, -32               ; ...
        srli  t6, t6, 2                 ; ...
        addi  t6, t6, -10               ; ...
        srli  t6, t6, 3                 ; ...
        slli  t6, t6, 3                 ; ...
        sub   t6, t6, t1                ; ...
        bgt   a4, t6, obb_bad           ; ...
        j     obb_n                     ; ...
obb_do:
        sd    t4, rb_c(zero)            ; (kept: the next item)
        mv    a0, s1                    ; ...
        mv    a1, t0                    ; ...
        bnez  t5, obb_del               ; ...
        mv    a3, t3                    ; ...
        li    a5, 0                     ; ...
        call  st_put                    ; ...
        j     obb_dn                    ; ...
obb_del:
        call  st_del                    ; ...
obb_dn:
        ld    t4, rb_c(zero)            ; ...
obb_n:
        mv    s3, t4                    ; ...
        addi  s4, s4, -1                ; ...
        j     obb_l                     ; ...
obb_next:
        addi  s5, s5, 1                 ; ...
        li    t0, 2                     ; ...
        bne   s5, t0, obb_pass          ; ...
        call  fs_commit                 ; ...
        sd    zero, TT_FL(s1)           ; ...
        j     ok                        ; ...
obb_bad:
        call  fs_commit                 ; (a namespace or a tree it made stays, empty)
        sd    zero, TT_FL(s1)           ; ...
        j     bad                       ; ...

; =============================================================================
; Boot objects
; =============================================================================
;
; The kernel loads the first servers before any server runs: it reads no
; tree, only the boot manifest, a page the meta block points at: a header as
; a tree page's (kind 3), "STBOOTMF" at 32, a u32 count at 40, and from 64
; entries of {name[16], u64 first page, u64 bytes}: the files with the boot
; flag (index attribute 4), each in one run of pages. So when such a file
; has been written, its contents are made one run again and the manifest is
; written anew, at a new page, in the commit of the close: the disk has the
; old server and the old manifest, or the new ones.

; boot_man(): the manifest written anew from the files with the boot flag
boot_man:
        addi  sp, sp, -48               ; frame (boot_fix's: it ends there)
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        sd    s5, 40(sp)                ; ...
        j     bfx_man                   ; ...

; boot_fix(): rec's file (a boot object, just written; okey is its key): its
; contents a stream in one extent; then the manifest
boot_fix:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        sd    s5, 40(sp)                ; ...
        ld    a0, x_data(zero)          ; its contents
        la    a1, okey                  ; ...
        li    a2, 8                     ; ...
        call  st_bsize                  ; ...
        ld    t0, bl_fl(zero)           ; a stream already?
        bltz  a0, bfx_in                ; (none: an empty one is made)
        bnez  t0, bfx_one               ; ...
bfx_in:
        mv    s1, a0                    ; inline (or none): written again as a stream
        bgez  s1, bfx_c                 ; ...
        li    s1, 0                     ; ...
bfx_c:
        la    a0, reqbuf                ; ...
        la    a1, bval                  ; ...
        addi  a2, s1, 7                 ; ...
        srli  a2, a2, 3                 ; ...
        slli  a2, a2, 3                 ; ...
        call  wcopy                     ; ...
        ld    a0, x_data(zero)          ; ...
        la    a1, okey                  ; ...
        li    a2, 8                     ; ...
        call  st_bdel                   ; ...
        li    t0, 1                     ; ...
        sd    t0, bw_force(zero)        ; ...
        ld    a0, x_data(zero)          ; ...
        la    a1, okey                  ; ...
        li    a2, 8                     ; ...
        li    a3, 0                     ; ...
        la    a4, reqbuf                ; ...
        mv    a5, s1                    ; ...
        call  st_bwrite                 ; ...
        sd    zero, bw_force(zero)      ; ...
        ld    a0, x_data(zero)          ; ...
        la    a1, okey                  ; ...
        li    a2, 8                     ; ...
        call  st_bsize                  ; ...
bfx_one:
        ld    s1, bval+8(zero)          ; s1 = the stream
        ld    t0, st_ps(zero)           ; s2 = its pages
        add   s2, a0, t0                ; ...
        addi  s2, s2, -1                ; ...
        ld    t0, st_sh(zero)           ; ...
        srl   s2, s2, t0                ; ...
        beqz  s2, bfx_man               ; ...
        mv    a0, s1                    ; one extent from its start holding them all?
        li    a1, 0                     ; ...
        call  ext_find                  ; ...
        beqz  a0, bfx_move              ; ...
        ld    t0, e_pages(zero)         ; ...
        bgeu  t0, s2, bfx_man           ; ...
bfx_move:
        mv    a0, s2                    ; no: a run of that many pages, the contents copied
        li    a1, 0                     ; into it page by page, the old pages freed
        call  alloc                     ; ...
        mv    s3, a0                    ; s3 = the run
        bne   a1, s2, st_full           ; (no such run on the disk)
        li    s4, 0                     ; s4 = the page
bfx_cp:
        bgeu  s4, s2, bfx_cd            ; ...
        la    a0, pgcopy                ; ...
        li    a1, 4096                  ; ...
        call  wzero                     ; ...
        mv    a0, s1                    ; ...
        mv    a1, s4                    ; ...
        call  ext_find                  ; ...
        beqz  a0, bfx_w                 ; (a hole: zeros)
        ld    a0, e_start(zero)         ; ...
        ld    t0, e_off(zero)           ; ...
        sub   t0, s4, t0                ; ...
        add   a0, a0, t0                ; ...
        call  PR                        ; ...
        mv    a1, a0                    ; ...
        la    a0, pgcopy                ; ...
        li    a2, 4096                  ; ...
        call  wcopy                     ; ...
bfx_w:
        add   a0, s3, s4                ; ...
        call  PRN                       ; ...
        la    a1, pgcopy                ; ...
        li    a2, 4096                  ; ...
        call  wcopy                     ; ...
        addi  s4, s4, 1                 ; ...
        j     bfx_cp                    ; ...
bfx_cd:
        mv    a0, s1                    ; ...
        li    a1, 0                     ; ...
        call  s_trim                    ; ...
        mv    a0, s1                    ; ...
        li    a1, 0                     ; ...
        mv    a2, s3                    ; ...
        mv    a3, s2                    ; ...
        ld    a4, st_txn(zero)          ; ...
        call  ext_put                   ; ...
bfx_man:
        call  alloc1                    ; the manifest anew: a page of this commit
        mv    s3, a0                    ; s3 = it
        call  PN                        ; ...
        sd    s3, 8(a0)                 ; ...
        ld    t0, st_txn(zero)          ; ...
        sd    t0, 16(a0)                ; ...
        li    t0, 3                     ; ...
        sb    t0, 24(a0)                ; ...
        li    t0, 0x464D544F4F425453    ; "STBOOTMF"
        sd    t0, 32(a0)                ; ...
        li    s4, 0                     ; s4 = entries
        sd    zero, ikey(zero)          ; every file with the boot flag: the index's
        sd    zero, ikey+8(zero)        ; entries of attribute 4
        li    t0, A_BOOT                ; ...
        sb    t0, ikey+3(zero)          ; ...
bfx_l:
        ld    a0, x_attr(zero)          ; ...
        la    a1, ikey                  ; ...
        li    a2, 12                    ; ...
        li    a3, ST_GT                 ; ...
        la    a4, ikey                  ; ...
        li    a5, 0                     ; ...
        call  st_seek                   ; ...
        beqz  a0, bfx_end               ; ...
        lwu   t0, ikey(zero)            ; still attribute 4?
        li    t1, 0x04000000            ; ...
        bne   t0, t1, bfx_end           ; ...
        ld    t0, sk_kl(zero)           ; ...
        li    t1, 12                    ; ...
        bne   t0, t1, bfx_end           ; ...
        li    a0, 0                     ; its object: the key's last eight bytes, big-endian
        li    t0, 4                     ; ...
bfx_o:
        slli  a0, a0, 8                 ; ...
        lbu   t1, ikey(t0)              ; ...
        or    a0, a0, t1                ; ...
        addi  t0, t0, 1                 ; ...
        li    t1, 12                    ; ...
        bne   t0, t1, bfx_o             ; ...
        call  rec_load                  ; ...
        bltz  a0, bfx_l                 ; ...
        ld    a0, x_data(zero)          ; where its contents start
        la    a1, okey                  ; ...
        li    a2, 8                     ; ...
        call  st_bsize                  ; ...
        li    s5, 0                     ; s5 = the first page (none: empty)
        blez  a0, bfx_e                 ; ...
        ld    a0, bval+8(zero)          ; ...
        li    a1, 0                     ; ...
        call  ext_find                  ; ...
        beqz  a0, bfx_e                 ; ...
        ld    s5, e_start(zero)         ; ...
bfx_e:
        mv    a0, s3                    ; its entry
        call  PW                        ; ...
        slli  t0, s4, 5                 ; ...
        add   s2, a0, t0                ; ...
        addi  s2, s2, 64                ; s2 = the entry
        addi  s4, s4, 1                 ; ...
        sw    s4, 40(a0)                ; ...
        sd    s5, 16(s2)                ; ...
        la    t0, rec                   ; ...
        ld    t1, R_SIZE(t0)            ; ...
        sd    t1, 24(s2)                ; ...
        call  rec_name                  ; ...
        mv    a2, a1                    ; (a boot object's name: 16 bytes at most)
        li    t0, 16                    ; ...
        bleu  a2, t0, bfx_n             ; ...
        mv    a2, t0                    ; ...
bfx_n:
        mv    a1, a0                    ; ...
        mv    a0, s2                    ; ...
        call  srv_bcopy                 ; ...
        j     bfx_l                     ; ...
bfx_end:
        ld    s1, st_manif(zero)        ; the old manifest's page is free
        sd    s3, st_manif(zero)        ; ...
        beqz  s1, bfx_ret               ; ...
        mv    a0, s1                    ; ...
        call  P                         ; ...
        ld    a2, 16(a0)                ; ...
        sd    zero, st_owner(zero)      ; ...
        mv    a0, s1                    ; ...
        li    a1, 1                     ; ...
        call  pfree                     ; ...
bfx_ret:
        ld    s5, 40(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; ...
