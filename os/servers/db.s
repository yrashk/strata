; v_args(): a value call's tree (s1), extents' tree (bl_ext), key (a1, a2);
; s2 = where the data after the key starts, s3 = its bytes; to bad if wrong
v_args:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        call  req_tree                  ; ...
        la    t0, srv_hdr               ; the extents' tree
        ld    t1, 8(t0)                 ; ...
        srli  a0, t1, 16                ; ...
        li    t2, 0xffff                ; ...
        and   a0, a0, t2                ; ...
        beqz  a0, va_k                  ; (none named: as it was)
        sd    a0, bl_ext(zero)          ; ...
        call  handle_ok                 ; ...
        beqz  a0, va_bad                ; ...
va_k:
        la    t0, srv_hdr               ; the key
        ld    t1, 8(t0)                 ; ...
        srli  t1, t1, 32                ; ...
        sd    t1, vkl(zero)             ; ...
        li    t2, 8                     ; short: in word 56
        bgtu  t1, t2, va_long           ; ...
        ld    t2, 56(t0)                ; ...
        sd    t2, vkey(zero)            ; ...
        la    t2, vkey                  ; ...
        sd    t2, vk(zero)              ; ...
        call  get_data                  ; the data: all of it after the key
        mv    s2, a0                    ; ...
        mv    s3, a1                    ; ...
        j     va_ret                    ; ...
va_long:
        call  get_data                  ; long: at the start of the data
        sd    a0, vk(zero)              ; ...
        ld    t1, vkl(zero)             ; ...
        addi  t1, t1, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        bgtu  t1, a1, va_bad            ; ...
        add   s2, a0, t1                ; ...
        sub   s3, a1, t1                ; ...
va_ret:
        ld    a1, vk(zero)              ; ...
        ld    a2, vkl(zero)             ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...
va_bad:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        j     bad                       ; ...

op_vsize:
        call  v_args                    ; ...
        mv    a0, s1                    ; ...
        call  st_bsize                  ; ...
        la    t0, srv_hdr               ; mode: the flag; data: the tree's value
        ld    t1, bl_fl(zero)           ; ...
        sd    t1, 24(t0)                ; ...
        bltz  a0, reply                 ; ...
        la    a1, bval                  ; (inline: the value itself; a stream: 16 bytes)
        ld    a2, bl_vl(zero)           ; ...
        j     reply_data                ; ...

op_vread:
        call  v_args                    ; ...
        la    t0, srv_hdr               ; ...
        ld    a3, 24(t0)                ; offset
        ld    a5, 16(t0)                ; bytes
        li    t1, SYS_MAX               ; ...
        bleu  a5, t1, vr_n              ; ...
        mv    a5, t1                    ; ...
vr_n:
        mv    a0, s1                    ; ...
        la    a4, sys_buf               ; ...
        call  st_bread                  ; ...
        blez  a0, reply                 ; ...
        mv    a2, a0                    ; ...
        la    a1, sys_buf               ; ...
        j     reply_data                ; ...

op_vwrite:
        call  v_args                    ; ...
        la    t0, srv_hdr               ; ...
        ld    a3, 24(t0)                ; offset, and "a stream even when short"
        srli  t1, a3, 63                ; ...
        sd    t1, bw_force(zero)        ; ...
        slli  a3, a3, 1                 ; ...
        srli  a3, a3, 1                 ; ...
        mv    a0, s1                    ; ...
        mv    a4, s2                    ; the bytes
        mv    a5, s3                    ; ...
        call  st_bwrite                 ; ...
        sd    zero, bw_force(zero)      ; ...
        li    a0, 0                     ; ...
        j     reply                     ; ...

op_vtrunc:
        call  v_args                    ; ...
        la    t0, srv_hdr               ; ...
        ld    a3, 24(t0)                ; the new length
        mv    a0, s1                    ; ...
        call  st_btrunc                 ; ...
        li    a0, 0                     ; ...
        j     reply                     ; ...

op_vdel:
        call  v_args                    ; ...
        mv    a0, s1                    ; ...
        call  st_bdel                   ; ...
        j     reply                     ; ...

op_vload:
        cvalid t0, c7                   ; an arena must come with it
        beqz  t0, bad                   ; ...
        call  v_args                    ; ...
        la    t0, srv_hdr               ; ...
        ld    a3, 24(t0)                ; offset in the arena
        ld    a4, 16(t0)                ; the most bytes
        mv    a0, s1                    ; ...
        call  st_bload                  ; ...
        j     reply                     ; ...

