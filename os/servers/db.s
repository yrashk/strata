; =============================================================================
; blk: the disk
; =============================================================================

; blk(a0 = op 1 read / 2 write / 3 flush / 4 INFO, a1 = first block, a2 =
; blocks, a3 = byte offset in the buffer, a4 = 5: the I/O buffer (c5) / 7:
; the attachment / -1: none) -> a0 = blk's answer (0 = ok). The request we
; serve waits in c4 meanwhile, our I/O buffer in c3 (lent from there when it
; is the one), and our message buffer is in c5 for the call; all of it as it
; was after.
blk:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a4, 8(sp)                 ; ...
        la    t0, bhdr                  ; the request
        sd    a0, 0(t0)                 ; ...
        sd    a1, 8(t0)                 ; ...
        sd    a2, 16(t0)                ; ...
        sd    a3, 24(t0)                ; ...
        sd    zero, 32(t0)              ; ...
        ld    t1, blksel(zero)          ; ...
        sd    t1, 48(t0)                ; ...
        cvalid t1, c6                   ; the request we serve: aside (the buffer comes
        beqz  t1, bk_q                  ;   back in c6)
        cmov  c4, c6                    ; ...
bk_q:
        cmov  c3, c5                    ; our I/O buffer: aside, as c3
        li    a5, -1                    ; the buffer to lend
        li    t1, 5                     ; ...
        bne   a4, t1, bk_a7             ; ...
        li    a5, 3                     ; ours
        j     bk_m                      ; ...
bk_a7:
        li    t1, 7                     ; ...
        bne   a4, t1, bk_m              ; ...
        li    a5, 7                     ; ...
bk_m:
        cmov  c5, c2                    ; our message buffer in c5
        la    t0, bhdr                  ; ...
        li    t1, 64                    ; ...
        tput  tg10, t0, c5, zero, t1    ; ...
        twait 1 << 10                   ; ...
        li    a0, SVC_SEND              ; through c1
        li    a1, 1                     ; ...
        li    a2, -1                    ; ...
        li    a3, 0                     ; ...
        li    a4, 5                     ; ...
        svc                             ; ...
bk_w:
        beqz  a0, bk_back               ; ...
        li    t1, -1                    ; not sent: as -1
        bne   a0, t1, bk_on             ; ...
        la    t0, bhdr                  ; ...
        sd    t1, 32(t0)                ; ...
        j     bk_nb                     ; ...
bk_on:
        li    a0, SVC_WAIT              ; woken early: wait on
        li    a1, -1                    ; ...
        li    a2, -1                    ; ...
        li    a3, 0                     ; ...
        li    a4, 5                     ; ...
        svc                             ; ...
        j     bk_w                      ; ...
bk_back:
        la    t0, bhdr                  ; the answer
        li    t1, 64                    ; ...
        tget  tg10, t0, c5, zero, t1    ; ...
        twait 1 << 10                   ; ...
bk_nb:
        cmov  c2, c5                    ; our message buffer back to c2
        ld    t1, 8(sp)                 ; the buffer lent: back where it was
        li    t2, 5                     ; ...
        bne   t1, t2, bk_r7             ; ...
        cmov  c5, c6                    ; ours came back in c6
        j     bk_rq                     ; ...
bk_r7:
        cmov  c5, c3                    ; ours stayed aside
        li    t2, 7                     ; ...
        bne   t1, t2, bk_rq             ; ...
        cmov  c7, c6                    ; the attachment came back in c6
bk_rq:
        cvalid t1, c4                   ; the request we serve
        beqz  t1, bk_ret                ; ...
        cmov  c6, c4                    ; ...
bk_ret:
        la    t0, bhdr                  ; ...
        ld    a0, 32(t0)                ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; blkn: blk takes runs of any length
blkn:
        j     blk                       ; ...

