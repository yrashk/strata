op_info:
        la    t0, sys_buf               ; ...
        ld    t1, st_ps(zero)           ; ...
        sd    t1, 0(t0)                 ; ...
        ld    t1, st_bpp(zero)          ; ...
        sd    t1, 8(t0)                 ; ...
        ld    t1, st_npages(zero)       ; ...
        sd    t1, 16(t0)                ; ...
        ld    t1, st_nfree(zero)        ; ...
        sd    t1, 24(t0)                ; ...
        ld    t1, st_txn(zero)          ; ...
        sd    t1, 32(t0)                ; ...
        ld    t1, st_cmt(zero)          ; ...
        sd    t1, 40(t0)                ; ...
        ld    t1, st_deadlim(zero)      ; ...
        sd    t1, 48(t0)                ; ...
        ld    t1, dtotal(zero)          ; ...
        sd    t1, 56(t0)                ; ...
        li    a0, 8                     ; ...
        mv    a1, t0                    ; ...
        li    a2, 64                    ; ...
