; srv_putat(a0 = D-LS address (8-aligned), a1 = length, a2 = offset in the
; data): more reply data
srv_putat:
        beqz  a1, spa_ret               ; ...
        addi  a1, a1, 7                 ; whole words
        srli  a1, a1, 3                 ; ...
        slli  a1, a1, 3                 ; ...
        addi  t1, a2, 64                ; ...
        tput  tg10, a0, c6, t1, a1      ; ...
spa_ret:
        ret                             ; ...

; =============================================================================
; blk: the disk
; =============================================================================

; blk(a0 = op 1 read / 2 write / 3 flush / 4 INFO, a1 = first block, a2 =
; blocks, a3 = byte offset in the buffer, a4 = 5: the I/O buffer (c5) / 7:
; the attachment / -1: none) -> a0 = 0 (ok), or what blk answered. A
; commit's writes (c_write, meta_write: pw_on) wait in a list (pw) and go
; together, in one WRITEV: with the next flush (as its flush), or before
; anything else is asked of blk. A frame written to make room in the cache
; is used again at once: that write goes at once.
blk:
        li    t0, 2                     ; a commit's write from the I/O buffer: listed
        bne   a0, t0, bk_now            ; ...
        li    t0, 5                     ; ...
        bne   a4, t0, bk_now            ; ...
        ld    t0, pw_on(zero)           ; ...
        beqz  t0, bk_other              ; ...
        ld    t1, pw_n(zero)            ; room?
        li    t2, PW_MAX                ; ...
        bltu  t1, t2, bk_list           ; ...
        addi  sp, sp, -40               ; no: the list goes first
        sd    ra, 0(sp)                 ; ...
        sd    a1, 8(sp)                 ; ...
        sd    a2, 16(sp)                ; ...
        sd    a3, 24(sp)                ; ...
        li    a0, 0                     ; ...
        call  pw_send                   ; ...
        ld    a3, 24(sp)                ; ...
        ld    a2, 16(sp)                ; ...
        ld    a1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 40                ; ...
        bnez  a0, bk_r                  ; ...
        ld    t1, pw_n(zero)            ; ...
bk_list:
        li    t2, 24                    ; ...
        mul   t2, t1, t2                ; ...
        la    t3, pwl                   ; ...
        add   t3, t3, t2                ; ...
        sd    a1, 0(t3)                 ; ...
        sd    a2, 8(t3)                 ; ...
        sd    a3, 16(t3)                ; ...
        addi  t1, t1, 1                 ; ...
        sd    t1, pw_n(zero)            ; ...
        li    a0, 0                     ; ...
bk_r:
        ret                             ; ...
bk_now:
        li    t0, 3                     ; a flush: the list, and the flush, in one
        bne   a0, t0, bk_other          ; ...
        li    a0, 1                     ; ...
        j     pw_send                   ; ...
bk_other:
        ld    t0, pw_n(zero)            ; anything else: the list first
        beqz  t0, blk1                  ; ...
        addi  sp, sp, -48               ; ...
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        sd    a2, 24(sp)                ; ...
        sd    a3, 32(sp)                ; ...
        sd    a4, 40(sp)                ; ...
        li    a0, 0                     ; ...
        call  pw_send                   ; ...
        mv    t0, a0                    ; ...
        ld    a4, 40(sp)                ; ...
        ld    a3, 32(sp)                ; ...
        ld    a2, 24(sp)                ; ...
        ld    a1, 16(sp)                ; ...
        ld    a0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        bnez  t0, bk_bad                ; ...
        j     blk1                      ; ...
bk_bad:
        mv    a0, t0                    ; ...
        ret                             ; ...

; pw_send(a0 = 1: then a flush) -> a0 = blk's answer: the listed writes, in
; one WRITEV, the I/O buffer lent
pw_send:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        ld    t1, pw_n(zero)            ; the runs -> the message's data (put by blk1:
        li    t2, 24                    ;   pw_len says how many bytes)
        mul   t1, t1, t2                ; ...
        sd    t1, pw_len(zero)          ; ...
        sd    zero, pw_n(zero)          ; ...
        sd    zero, pw_on(zero)         ; ...
        li    a0, 5                     ; WRITEV
        li    a1, 0                     ; ...
        mv    a2, t1                    ; ...
        ld    a3, 8(sp)                 ; mode bit 0: the flush
        li    a4, 5                     ; ...
        call  blk1                      ; ...
        sd    zero, pw_len(zero)        ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; blk1(a0 = op, a1 = handle, a2 = length, a3 = mode, a4 = 5: the I/O
; buffer (c5) / 7: the attachment / -1: none) -> a0 = blk's answer: one
; message. The request we serve waits in c4 meanwhile, our I/O buffer in c3
; (lent from there when it is the one), and our message buffer is in c5 for
; the call; all of it as it was after. WRITEV's runs (pw_len bytes of pwl)
; go as the data.
blk1:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a4, 8(sp)                 ; ...
        la    t0, bhdr                  ; the request
        sd    a0, 0(t0)                 ; ...
        sd    a1, 8(t0)                 ; ...
        sd    a2, 16(t0)                ; ...
        sd    a3, 24(t0)                ; ...
        sd    zero, 32(t0)              ; ...
        ld    t1, blksel(zero)          ; ...
        sd    t1, 48(t0)                ; ...
        cvalid t1, c6                   ; the request we serve: aside (the buffer comes
        beqz  t1, bk_q                  ;   back in c6)
        cmov  c4, c6                    ; ...
bk_q:
        cmov  c3, c5                    ; our I/O buffer: aside, as c3
        li    a5, -1                    ; the buffer to lend
        li    t1, 5                     ; ...
        bne   a4, t1, bk_a7             ; ...
        li    a5, 3                     ; ours
        j     bk_m                      ; ...
bk_a7:
        li    t1, 7                     ; ...
        bne   a4, t1, bk_m              ; ...
        li    a5, 7                     ; ...
bk_m:
        cmov  c5, c2                    ; our message buffer in c5
        la    t0, bhdr                  ; ...
        li    t1, 64                    ; ...
        tput  tg10, t0, c5, zero, t1    ; ...
        ld    t2, pw_len(zero)          ; (WRITEV's runs)
        beqz  t2, bk_m2                 ; ...
        la    t0, pwl                   ; ...
        tput  tg10, t0, c5, t1, t2      ; ...
bk_m2:
        twait 1 << 10                   ; ...
        li    a0, SVC_SEND              ; through c1
        li    a1, 1                     ; ...
        li    a2, -1                    ; ...
        li    a3, 0                     ; ...
        li    a4, 5                     ; ...
        svc                             ; ...
bk_w:
        beqz  a0, bk_back               ; ...
        li    t1, -1                    ; not sent: as -1
        bne   a0, t1, bk_on             ; ...
        la    t0, bhdr                  ; ...
        sd    t1, 32(t0)                ; ...
        j     bk_nb                     ; ...
bk_on:
        li    a0, SVC_WAIT              ; woken early: wait on
        li    a1, -1                    ; ...
        li    a2, -1                    ; ...
        li    a3, 0                     ; ...
        li    a4, 5                     ; ...
        svc                             ; ...
        j     bk_w                      ; ...
bk_back:
        la    t0, bhdr                  ; the answer
        li    t1, 64                    ; ...
        tget  tg10, t0, c5, zero, t1    ; ...
        twait 1 << 10                   ; ...
bk_nb:
        cmov  c2, c5                    ; our message buffer back to c2
        ld    t1, 8(sp)                 ; the buffer lent: back where it was
        li    t2, 5                     ; ...
        bne   t1, t2, bk_r7             ; ...
        cmov  c5, c6                    ; ours came back in c6
        j     bk_rq                     ; ...
bk_r7:
        cmov  c5, c3                    ; ours stayed aside
        li    t2, 7                     ; ...
        bne   t1, t2, bk_rq             ; ...
        cmov  c7, c6                    ; the attachment came back in c6
bk_rq:
        cvalid t1, c4                   ; the request we serve
        beqz  t1, bk_ret                ; ...
        cmov  c6, c4                    ; ...
bk_ret:
        la    t0, bhdr                  ; ...
        ld    a0, 32(t0)                ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

