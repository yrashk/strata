; =============================================================================
; db.s: the store server
; =============================================================================
;
; A user-mode server (pid 5, created by the kernel at boot as the second
; server of dev's core, index 1: doc/fs-split.md). It keeps the disk's STORE
; (doc/strata-fs-proposal.md): ordered key-value trees, copy-on-write, in
; namespaces; a change is on the disk whole or not at all. The store is
; store.s, storew.s and sblob.s, as they were in the one file server: the
; page cache (124 frames in far memory) and three page buffers are here. The
; disk is reached through blk only (a message per run of blocks, our frames
; lent to it); fs is the file system on top, a client of these calls.
;
; A tree is named by a handle: its entry in the table of open trees (tt), or
; one of a snapshot's trees (sx). Values are any length: one that does not
; fit a quarter page is a stream of extents, and the V calls reach part of
; it by offset (a file's contents are one such value).
;
;  70 TREE    handle = namespace id, mode 1 = make it, data = name -> handle / 0
;  71 GET     handle = tree, data = key -> the value's length (-1 none); data:
;             the value; mode: its flag
;  72 SEEK    handle = tree, mode = ST_GE/GT/LE/LT, data = key -> 1 / 0;
;             length = the key's length, mode = the value's length | flag << 32;
;             data: the key (padded to 8 bytes), the value
;  73 PUT     handle = tree, mode = flag, data = {u16 key length, u16 value
;             length, u32 0, key (padded), value} -> 1 added / 0 replaced / -1
;  74 DEL     handle = tree, data = key -> 1 / 0
; The value calls: handle = tree | the extents' tree << 16 | key length << 32
; (both trees are D-LS addresses); the key in word 56 when it is 8 bytes or
; shorter, else at the start of the data (padded):
;  75 VSIZE   -> the length / -1; data: the value as the tree holds it (a short
;             one itself, a stream's 16 bytes), mode: its flag
;  76 VREAD   mode = offset, length = bytes (<= 4032) -> bytes read; data: them
;  77 VWRITE  mode = offset | 1 << 63 (a stream even when short), data = the
;             bytes (length) -> 0
;  78 VTRUNC  mode = the new length -> 0
;  79 VDEL    -> 1 / 0
;  80 VLOAD   mode = offset in the attachment, length = the most bytes; an
;             arena as attachment -> the length, all of it copied in (-4 none,
;             -1 longer); the arena goes back
;  81 COMMIT  -> 0
;  82 ABORT   -> 0: back to the last commit; every handle is to be opened again
;  83 INFO    -> 8; data: page size, blocks per page, pages, free pages, the
;             commit under way, the last on the disk, the newest snapshot's,
;             the disk's blocks
;  84 SNAP    as fs's SNAP (45): mode 0 take, 1 delete, 2 list, 3 restore
;             (data = the name; restore: handle = the file system's namespace;
;             it is left uncommitted: fs writes the boot manifest and commits)
;  85 SNAPT   handle = a snapshot's commit, data = {u64 namespace, u64 count,
;             count names: u8 length, the name} -> count; data: a handle
;             each (until the next SNAPT), -1 no such snapshot
;  86 BOOT    handle = the data tree | the extents' tree << 16, data = {u64
;             the key made one run (0: none), u64 count, count entries
;             {name[16], u64 key, u64 size}} -> 0: the boot manifest anew
;  87 SCAN    handle = tree, mode = ST_GE / ST_GT, data = key -> records, the
;             first at or after (after) the key and those after it in key
;             order, as many as fit: data: per record {u16 key length, u16
;             value length, u32 flag, key, value}, key and value each padded
;             to 8 bytes; mode: 1 when the last is the tree's last
;  88 FLUSH   -> 0 (a batch alone: see below)
;  64 DBGET / 65 DBSCAN / 66 DBBATCH   the store for programs (dbprog.s)
; A request from fs may carry a batch of puts and deletes after its data
; (from the next multiple of 8; header word 48 bits 16..31: its bytes):
; items {u8 1 put / 2 delete / 3 a value deleted (VDEL) / 4 a value written
; (VWRITE: the item's value is {u64 offset, the bytes}; flag: a stream even
; when short) / 5 a value moved (the key's goes, the value of the key that
; is the item's value moves under it), u8 flag, u16 key length, u16 value
; length, u16 the extents' tree (3..5), u64 tree, key, value}, each padded
; to 8 bytes. They are applied, in order, before the request is answered
; (fs's st_put, st_del, st_bdel, short st_bwrite, st_bmove: dbcall.s).
;  36 DUPS / 37 CLEANUP / 38 CANCEL from proc: nothing to do
; Every reply's word 56: the commit under way | the count of aborts << 48.
; A call that fills the disk answers -1, one whose page fails its checksum
; (or that the device refuses) -5; either gives up the commit under way (the
; count of aborts says so). Calls by handle, COMMIT, ABORT, SNAP and BOOT are
; taken from fs only (its pid).
;
; Capability registers: c0 the rest of the arena, c1 an endpoint to blk's
; core, c2 our message buffer, c3 c4 kept aside during a call to blk, c5 the
; I/O buffer (16 KiB of scratch, then the cache's frames), c6 the request,
; c7 its attachment.

NB      = 3                             ; page buffers in the D-LS (store.s)
SVC_WAIT = 1                            ; svc: wait for a buffer to come back
SVC_RECV = 2                            ; svc: receive a request
SVC_REPLY = 3                           ; svc: answer one
SVC_SEND = 12                           ; svc: send with an attachment
SYS_MAX = 4032                          ; data bytes per message
SEL     = 0x53 << 56                    ; header word 48: the server's index
PW_MAX  = 40                            ; writes listed for blk (24 bytes each)
TTSAVE  = 0x2000                        ; in c5's scratch: the trees open, while a
                                        ;   program's batch runs (meta_load uses 0..1 KiB)
OP_DBGET = 64                           ; the store for programs
OP_DBSCAN = 65                          ; ...
OP_DBBATCH = 66                         ; ...

        .data                           ; data Local Store
        .align 8                        ; ...
nostore: .dword 0                       ; the disk is not a store: every call answers -5
blksel: .dword 0                        ; header word 48 for blk
fspid:  .dword 0                        ; fs's pid
fscore: .dword 0                        ; fs's core (fs is alone there: what comes from it is fs's)
fwd:    .dword 0                        ; 1: the request was forwarded by fs
pb_on:  .dword 0                        ; 1: a program's batch, after a commit of everything else
aborts: .dword 0                        ; commits given up
dtotal: .dword 0                        ; the disk's blocks (blk INFO)
pw_n:   .dword 0                        ; writes listed for blk
pw_len: .dword 0                        ; WRITEV's runs' bytes, while it is sent
pw_on:  .dword 0                        ; 1: a commit's writes, which may wait (store.s c_write)
rb_dl:  .dword 0                        ; a program's batch: 1 while every item deletes
rb_t:   .dword 0                        ; run_batch: an item's tree, key, value
rb_k:   .dword 0                        ; ...
rb_kl:  .dword 0                        ; ...
rb_v:   .dword 0                        ; ...
rb_vl:  .dword 0                        ; ...
x_nst:  .dword 0                        ; the store's namespaces (namespace 0)
x_snap: .dword 0                        ; the store's snapshots (namespace 0)
bhdr:   .space 64                       ; a request to blk
vkey:   .dword 0                        ; a value call's key when it is short
vkl:    .dword 0                        ; its length
vk:     .dword 0                        ; where the key is
sx:     .space 16 * 8                   ; a snapshot's trees: root, height each (SNAPT)
sxh:    .space 8 * 8                    ; their handles, for the reply
scat:   .space 16                       ; its catalog
xt:     .space 6 * 8                    ; SNAP restore: the file system's six trees
fs_ns:  .dword 0                        ; ... its namespace
rkey:   .space 16                       ; a key at work
dval:   .space 16                       ; a value at work
tnbuf:  .space 64                       ; a snapshot's record
rbuf:   .space 40                       ; a snapshot's name from a request
s_ns:   .ascii "ns"                     ; the tree of namespaces
s_snap: .ascii "snap"                   ; the tree of snapshots

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        andi  t0, a0, 255               ; blk's index on its core
        li    t1, SEL                   ; ...
        or    t0, t0, t1                ; ...
        sd    t0, blksel(zero)          ; ...
        srli  t0, a0, 8                 ; fs's pid
        andi  t0, t0, 255               ; ...
        sd    t0, fspid(zero)           ; ...
        srli  t0, a0, 16                ; fs's core
        andi  t0, t0, 255               ; ...
        sd    t0, fscore(zero)          ; ...
        cclear c7                       ; (the clock: not used here; c7 is a request's attachment)
        cmov  c2, c5                    ; c2 = our message buffer
        li    t0, 0x40000               ; the I/O buffer: the top of our memory
        csplit c5, c0, t0               ; c0 = [0, 0x40000), c5 = [0x40000, 0xC0000)
m_info:
        li    a0, 4                     ; blk INFO: is it there yet? (it is made at the
        li    a1, 0                     ;   same time: -1 until it is)
        li    a2, 0                     ; ...
        li    a3, 0                     ; ...
        li    a4, -1                    ; ...
        call  blk                       ; ...
        bgez  a0, m_tot                 ; ...
        li    a0, SVC_WAIT              ; a tick, then again
        li    a1, -1                    ; ...
        li    a2, 1                     ; ...
        li    a3, -1                    ; ...
        svc                             ; ...
        j     m_info                    ; ...
m_tot:
        la    t0, dtotal                ; the disk's blocks: INFO's first word
        li    t1, 64                    ; ...
        li    t2, 8                     ; ...
        tget  tg10, t0, c2, t1, t2      ; ...
        twait 1 << 10                   ; ...
m_mount:
        la    a0, start                 ; (a disk that cannot be read: see st_die)
        call  srv_guard                 ; ...
        call  st_mount                  ; the store
        bltz  a0, m_no                  ; ...
        li    t1, 0                     ; log2 of the page size
        ld    t2, st_ps(zero)           ; ...
m_sh:
        srli  t2, t2, 1                 ; ...
        beqz  t2, m_shd                 ; ...
        addi  t1, t1, 1                 ; ...
        j     m_sh                      ; ...
m_shd:
        sd    t1, st_sh(zero)           ; ...
        call  db_trees                  ; ...
        j     start                     ; ...
m_no:
        li    t0, 1                     ; not a store
        sd    t0, nostore(zero)         ; ...
start:
        la    a0, loop                  ; a fault on a dead request returns to the loop
        call  srv_guard                 ; ...
loop:
        li    a0, 0                     ; no device tags
        li    a1, -1                    ; no timeout
        call  srv_recv                  ; ...
        bltz  a0, loop                  ; ...
        sd    zero, fwd(zero)           ; ...
        andi  t1, a0, 255               ; forwarded by fs: from its core, not its own
        ld    t2, fscore(zero)          ;   (a program's buffer): answered to the core
        bne   t1, t2, lp_d              ;   fs names in word 56 (fsops.s op_dbget)
        la    t0, srv_hdr               ; ...
        ld    t1, 40(t0)                ; ...
        ld    t2, fspid(zero)           ; ...
        beq   t1, t2, lp_d              ; ...
        ld    t1, 56(t0)                ; ...
        andi  t1, t1, 255               ; ...
        srli  a0, a0, 8                 ; ...
        slli  a0, a0, 8                 ; ...
        or    a0, a0, t1                ; ...
        la    t0, srv_tok               ; ...
        sd    a0, 0(t0)                 ; ...
        li    t1, 1                     ; ...
        sd    t1, fwd(zero)             ; ...
lp_d:
        li    t1, ST_RES + ST_RESD      ; growth leaves ST_RESD more pages than a delete:
        la    t0, srv_hdr               ;   fs marks the calls of a change that frees
        ld    t2, 40(t0)                ;   (UNLINK, a snapshot deleted) with header
        ld    t3, fspid(zero)           ;   word 48 bit 32, so that a disk filled up to
        bne   t2, t3, lp_r              ;   the line can still be emptied
        ld    t2, 48(t0)                ; ...
        srli  t2, t2, 32                ; ...
        andi  t2, t2, 1                 ; ...
        beqz  t2, lp_r                  ; ...
        li    t1, ST_RES                ; ...
lp_r:
        sd    t1, st_resv(zero)         ; ...
        la    t0, srv_hdr               ; dispatch
        ld    t1, 0(t0)                 ; ...
        li    t2, OP_DUPS               ; DUPS, CLEANUP, CANCEL: nothing kept for anyone
        beq   t1, t2, ok                ; ...
        li    t2, OP_CLEANUP            ; ...
        beq   t1, t2, ok                ; ...
        li    t2, OP_CANCEL             ; ...
        beq   t1, t2, ok                ; ...
        ld    t2, nostore(zero)         ; no store: nothing else can be answered
        bnez  t2, st_die                ; ...
        ld    t2, 40(t0)                ; fs's writes may come first: a batch after the
        ld    t3, fspid(zero)           ;   data (word 48: its bytes << 16)
        bne   t2, t3, lp_nb             ; ...
        ld    a0, 48(t0)                ; ...
        srli  a0, a0, 16                ; ...
        li    t3, 0xffff                ; ...
        and   a0, a0, t3                ; ...
        beqz  a0, lp_nb                 ; ...
        call  run_batch                 ; ...
        la    t0, srv_hdr               ; ...
        ld    t1, 0(t0)                 ; ...
lp_nb:
        li    t2, OP_DBGET              ; the store for programs: anyone
        beq   t1, t2, op_dbget          ; ...
        li    t2, OP_DBSCAN             ; ...
        beq   t1, t2, op_dbscan         ; ...
        li    t2, OP_DBBATCH            ; ...
        beq   t1, t2, op_dbbatch        ; ...
        ld    t2, 40(t0)                ; the rest: fs only
        ld    t3, fspid(zero)           ; ...
        bne   t2, t3, bad               ; ...
        li    t2, 70                   ; TREE
        beq   t1, t2, op_tree            ; ...
        li    t2, 71                   ; GET
        beq   t1, t2, op_get             ; ...
        li    t2, 72                   ; SEEK
        beq   t1, t2, op_seek            ; ...
        li    t2, 73                   ; PUT
        beq   t1, t2, op_put             ; ...
        li    t2, 74                   ; DEL
        beq   t1, t2, op_del             ; ...
        li    t2, 75                   ; VSIZE
        beq   t1, t2, op_vsize           ; ...
        li    t2, 76                   ; VREAD
        beq   t1, t2, op_vread           ; ...
        li    t2, 77                   ; VWRITE
        beq   t1, t2, op_vwrite          ; ...
        li    t2, 78                   ; VTRUNC
        beq   t1, t2, op_vtrunc          ; ...
        li    t2, 79                   ; VDEL
        beq   t1, t2, op_vdel            ; ...
        li    t2, 80                   ; VLOAD
        beq   t1, t2, op_vload           ; ...
        li    t2, 81                   ; COMMIT
        beq   t1, t2, op_commit          ; ...
        li    t2, 82                   ; ABORT
        beq   t1, t2, op_abort           ; ...
        li    t2, 83                   ; INFO
        beq   t1, t2, op_info            ; ...
        li    t2, 84                   ; SNAP
        beq   t1, t2, op_snap            ; ...
        li    t2, 85                   ; SNAPT
        beq   t1, t2, op_snapt           ; ...
        li    t2, 86                   ; BOOT
        beq   t1, t2, op_boot            ; ...
        li    t2, 87                   ; SCAN
        beq   t1, t2, op_scan            ; ...
        li    t2, 88                   ; FLUSH
        beq   t1, t2, ok                 ; ...
bad:
        li    a0, -1                    ; unknown, or refused
reply:
        sd    zero, pb_on(zero)         ; (a program's batch is over)
        la    t0, srv_hdr               ; word 56: the commit under way, the aborts
        ld    t1, st_txn(zero)          ; ...
        ld    t2, aborts(zero)          ; ...
        slli  t2, t2, 48                ; ...
        or    t1, t1, t2                ; ...
        sd    t1, 56(t0)                ; ...
        ld    t1, 40(t0)                ; to a program: no server named (its next
        ld    t2, fspid(zero)           ;   message may go out with this header)
        beq   t1, t2, rp_fs             ; ...
        sd    zero, 48(t0)              ; ...
rp_fs:
        li    a1, 0                     ; the attachment, if one came, goes back
        cvalid t0, c7                   ; ...
        beqz  t0, rp_go                 ; ...
        li    a1, 1                     ; ...
rp_go:
        call  srv_reply                 ; ...
        j     loop                      ; ...
ok:
        li    a0, 0                     ; ...
        j     reply                     ; ...
nofile:
        li    a0, -4                    ; ...
        j     reply                     ; ...

; reply_data(a0 = result, a1 = D-LS address, a2 = bytes): the bytes as the
; reply's data, the length word their count
reply_data:
        addi  sp, sp, -16               ; frame
        sd    a0, 0(sp)                 ; ...
        sd    a2, 8(sp)                 ; ...
        mv    a0, a1                    ; ...
        mv    a1, a2                    ; ...
        call  srv_put                   ; ...
        la    t0, srv_hdr               ; ...
        ld    t1, 8(sp)                 ; ...
        sd    t1, 16(t0)                ; ...
        ld    a0, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        j     reply                     ; ...

; st_full: the disk has no room for what the request needs. st_die: a page
; failed its checksum, or the device refused. Reached from anywhere in the
; store: the commit under way is given up and the request is answered -1 or
; -5. A failure while giving it up: no store any more.
st_full:
        li    s1, -1                    ; ...
        j     st_fail                   ; ...
st_die:
        li    s1, -5                    ; ...
st_fail:
        la    t0, srv_gsp               ; the loop's stack
        ld    sp, 0(t0)                 ; ...
        ld    t0, nostore(zero)         ; ...
        bnez  t0, sf_reply              ; ...
        li    t0, 1                     ; (a failure in here: no store any more)
        sd    t0, nostore(zero)         ; ...
        ld    t0, pb_on(zero)           ; a program's batch alone: nothing of fs's is
        bnez  t0, sf_ab                 ;   given up, so fs is not told (no abort counted)
        ld    t0, aborts(zero)          ; one more given up
        addi  t0, t0, 1                 ; ...
        sd    t0, aborts(zero)          ; ...
sf_ab:
        call  st_abort                  ; ...
        bltz  a0, sf_reply              ; ...
        call  db_trees                  ; ...
        ld    t0, pb_on(zero)           ; ...
        beqz  t0, sf_ok                 ; ...
        la    t0, tt                    ; and fs's trees are open as they were (all of
        li    t1, TTSAVE                ;   them as committed: the batch began with a
        li    t2, NTT * TT_SIZE         ;   commit)
        tget  tg1, t0, c5, t1, t2       ; ...
        twait 1 << 1                    ; ...
        sd    zero, pb_on(zero)         ; ...
sf_ok:
        sd    zero, nostore(zero)       ; ...
sf_reply:
        mv    a0, s1                    ; ...
        cvalid t0, c6                   ; (at start there is no request)
        beqz  t0, start                 ; ...
        j     reply                     ; ...

; db_trees(): namespace 0's trees: the namespaces, the snapshots, and the
; newest snapshot's commit (pages born up to it are kept: st_deadlim)
db_trees:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        li    a0, 0                     ; ...
        la    a1, s_ns                  ; ...
        li    a2, 2                     ; ...
        li    a3, 1                     ; ...
        call  st_tree                   ; ...
        sd    a0, x_nst(zero)           ; ...
        li    a0, 0                     ; ...
        la    a1, s_snap                ; ...
        li    a2, 4                     ; ...
        li    a3, 1                     ; ...
        call  st_tree                   ; ...
        sd    a0, x_snap(zero)          ; ...
        li    t0, -1                    ; ...
        sd    t0, rkey(zero)            ; ...
        sd    zero, st_deadlim(zero)    ; ...
        la    a1, rkey                  ; ...
        li    a2, 8                     ; ...
        li    a3, ST_LT                 ; ...
        la    a4, rkey                  ; ...
        li    a5, 0                     ; ...
        call  st_seek                   ; ...
        beqz  a0, dbt_ret               ; ...
        ld    a0, rkey(zero)            ; ...
        call  bswap                     ; ...
        sd    a0, st_deadlim(zero)      ; ...
dbt_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; =============================================================================
; The calls by handle
; =============================================================================

; get_data() -> a0 = the request's data (rqd), a1 = its length (<= SYS_MAX)
get_data:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        la    t0, srv_hdr               ; ...
        ld    a1, 16(t0)                ; ...
        li    t1, SYS_MAX               ; ...
        bleu  a1, t1, gd_n              ; ...
        mv    a1, t1                    ; ...
gd_n:
        sd    a1, 8(sp)                 ; ...
        la    a0, rqd                   ; ...
        call  srv_get                   ; ...
        la    a0, rqd                   ; ...
        ld    a1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; handle_ok(a0 = handle) -> a0 = 1 if it is an entry of tt in use, or one of
; sx: the only trees a request may name
handle_ok:
        la    t0, tt                    ; tt: inside, at an entry's start, in use
        sub   t1, a0, t0                ; ...
        li    t2, NTT * TT_SIZE         ; ...
        bgeu  t1, t2, hok_sx            ; ...
        li    t2, TT_SIZE               ; ...
        remu  t2, t1, t2                ; ...
        bnez  t2, hok_no                ; ...
        ld    t1, TT_FL(a0)             ; ...
        snez  a0, t1                    ; ...
        ret                             ; ...
hok_sx:
        la    t0, sx                    ; sx: inside, at a 16-byte entry's start
        sub   t1, a0, t0                ; ...
        li    t2, 16 * 8                ; ...
        bgeu  t1, t2, hok_no            ; ...
        andi  t1, t1, 15                ; ...
        seqz  a0, t1                    ; ...
        ret                             ; ...
hok_no:
        li    a0, 0                     ; ...
        ret                             ; ...

; req_tree() -> s1 = the tree the request names (handle word, low 16 bits);
; to bad if it is none
req_tree:
        la    t0, srv_hdr               ; ...
        ld    a0, 8(t0)                 ; ...
        li    t1, 0xffff                ; ...
        and   a0, a0, t1                ; ...
        mv    s1, a0                    ; ...
        addi  sp, sp, -8                ; ...
        sd    ra, 0(sp)                 ; ...
        call  handle_ok                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        beqz  a0, bad                   ; ...
        ret                             ; ...

op_tree:
        call  get_data                  ; the name
        beqz  a1, bad                   ; ...
        li    t0, 28                    ; ...
        bgtu  a1, t0, bad               ; ...
        mv    a2, a1                    ; ...
        mv    a1, a0                    ; ...
        la    t0, srv_hdr               ; ...
        ld    a0, 8(t0)                 ; the namespace
        ld    a3, 24(t0)                ; make it?
        andi  a3, a3, 1                 ; ...
        call  st_tree                   ; ...
        j     reply                     ; ...

op_get:
        call  req_tree                  ; ...
        call  get_data                  ; the key
        mv    a2, a1                    ; ...
        mv    a1, a0                    ; ...
        mv    a0, s1                    ; ...
        la    a3, sys_buf               ; ...
        call  st_get                    ; ...
        la    t0, srv_hdr               ; the flag
        sd    a1, 24(t0)                ; ...
        bltz  a0, reply                 ; ...
        mv    a2, a0                    ; ...
        la    a1, sys_buf               ; ...
        j     reply_data                ; ...

op_seek:
        call  req_tree                  ; ...
        call  get_data                  ; the key (the one found goes in its place)
        mv    a2, a1                    ; ...
        mv    a1, a0                    ; ...
        mv    a0, s1                    ; ...
        la    t0, srv_hdr               ; ...
        ld    a3, 24(t0)                ; ...
        la    a4, rqd                   ; ...
        la    a5, sys_buf               ; ...
        call  st_seek                   ; ...
        beqz  a0, reply                 ; ...
        ld    s2, sk_kl(zero)           ; s2 = the key's bytes, padded
        addi  s2, s2, 7                 ; ...
        srli  s2, s2, 3                 ; ...
        slli  s2, s2, 3                 ; ...
        la    a0, rqd                   ; the key, then the value
        mv    a1, s2                    ; ...
        call  srv_put                   ; ...
        la    a0, sys_buf               ; ...
        ld    a1, sk_vl(zero)           ; ...
        mv    a2, s2                    ; ...
        call  srv_putat                 ; ...
        la    t0, srv_hdr               ; length: the key's, mode: the value's and its flag
        ld    t1, sk_kl(zero)           ; ...
        sd    t1, 16(t0)                ; ...
        ld    t1, sk_vl(zero)           ; ...
        ld    t2, sk_fl(zero)           ; ...
        slli  t2, t2, 32                ; ...
        or    t1, t1, t2                ; ...
        sd    t1, 24(t0)                ; ...
        li    a0, 1                     ; ...
        j     reply                     ; ...

op_put:
        call  req_tree                  ; ...
        call  get_data                  ; {u16 key length, u16 value length, u32 0, key, value}
        li    t0, 8                     ; ...
        bltu  a1, t0, bad               ; ...
        lhu   a2, 0(a0)                 ; ...
        lhu   a4, 2(a0)                 ; ...
        addi  t1, a2, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        addi  t2, t1, 8                 ; inside the data?
        add   t2, t2, a4                ; ...
        bgtu  t2, a1, bad               ; ...
        addi  a1, a0, 8                 ; the key
        add   a3, a1, t1                ; the value
        mv    a0, s1                    ; ...
        la    t0, srv_hdr               ; the flag
        ld    a5, 24(t0)                ; ...
        andi  a5, a5, 1                 ; ...
        call  st_put                    ; ...
        j     reply                     ; ...

op_del:
        call  req_tree                  ; ...
        call  get_data                  ; the key
        mv    a2, a1                    ; ...
        mv    a1, a0                    ; ...
        mv    a0, s1                    ; ...
        call  st_del                    ; ...
        j     reply                     ; ...

op_scan:
        call  req_tree                  ; ...
        call  get_data                  ; the key (each one found goes in its place)
        mv    s3, a1                    ; s3 = its length
        la    t0, srv_hdr               ; s4 = the side, the first time
        ld    s4, 24(t0)                ; ...
        andi  s4, s4, 1                 ; ...
        li    s5, 0                     ; s5 = records
        la    s6, sys_buf               ; s6 = where the next one goes
        li    s7, 0                     ; s7 = 1: the tree has no more
osc_l:
        mv    a0, s1                    ; ...
        la    a1, rqd                   ; ...
        mv    a2, s3                    ; ...
        mv    a3, s4                    ; ...
        la    a4, rqd                   ; ...
        la    a5, pgcopy                ; ...
        call  st_seek                   ; ...
        beqz  a0, osc_end               ; ...
        li    s4, ST_GT                 ; (the ones after it follow)
        ld    s3, sk_kl(zero)           ; ...
        addi  t2, s3, 7                 ; room for it?
        srli  t2, t2, 3                 ; ...
        slli  t2, t2, 3                 ; ...
        ld    t1, sk_vl(zero)           ; ...
        addi  t3, t1, 7                 ; ...
        srli  t3, t3, 3                 ; ...
        slli  t3, t3, 3                 ; ...
        add   t4, t2, t3                ; ...
        addi  t4, t4, 8                 ; ...
        add   t4, t4, s6                ; ...
        la    t5, sys_buf + SYS_MAX     ; ...
        bgtu  t4, t5, osc_done          ; ...
        sd    zero, 0(s6)               ; {u16 key length, u16 value length, u32 flag}
        sh    s3, 0(s6)                 ; ...
        sh    t1, 2(s6)                 ; ...
        ld    t0, sk_fl(zero)           ; ...
        sw    t0, 4(s6)                 ; ...
        addi  a0, s6, 8                 ; the key
        la    a1, rqd                   ; ...
        mv    a2, t2                    ; ...
        add   s6, a0, t2                ; ...
        call  wcopy                     ; ...
        mv    a0, s6                    ; the value
        la    a1, pgcopy                ; ...
        ld    a2, sk_vl(zero)           ; ...
        addi  a2, a2, 7                 ; ...
        srli  a2, a2, 3                 ; ...
        slli  a2, a2, 3                 ; ...
        add   s6, s6, a2                ; ...
        call  wcopy                     ; ...
        addi  s5, s5, 1                 ; ...
        j     osc_l                     ; ...
osc_end:
        li    s7, 1                     ; ...
osc_done:
        la    t0, srv_hdr               ; ...
        sd    s7, 24(t0)                ; ...
        mv    a0, s5                    ; ...
        la    a1, sys_buf               ; ...
        sub   a2, s6, a1                ; ...
        j     reply_data                ; ...

; run_batch(a0 = bytes): the batch after the request's data, applied
run_batch:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        li    t1, SYS_MAX               ; ...
        bgtu  a0, t1, rb_bad            ; ...
        la    t0, srv_hdr               ; where: after the data
        ld    t1, 16(t0)                ; ...
        addi  t1, t1, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        add   t2, t1, a0                ; (inside the buffer)
        li    t3, SYS_MAX               ; ...
        bgtu  t2, t3, rb_bad            ; ...
        addi  t1, t1, 64                ; ...
        addi  t2, a0, 7                 ; ...
        srli  t2, t2, 3                 ; ...
        slli  t2, t2, 3                 ; ...
        la    s1, sys_buf               ; s1 = the item, s2 = the end
        tget  tg10, s1, c6, t1, t2      ; ...
        twait 1 << 10                   ; ...
        add   s2, s1, a0                ; ...
rb_l:
        addi  t0, s1, 16                ; ...
        bgtu  t0, s2, rb_done           ; ...
        ld    a0, 8(s1)                 ; the tree
        call  handle_ok                 ; ...
        beqz  a0, rb_bad                ; ...
        lhu   a2, 2(s1)                 ; the key, the value
        lhu   a4, 4(s1)                 ; ...
        addi  t1, a2, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        addi  t2, a4, 7                 ; ...
        srli  t2, t2, 3                 ; ...
        slli  t2, t2, 3                 ; ...
        addi  a1, s1, 16                ; ...
        add   a3, a1, t1                ; ...
        add   s3, a3, t2                ; s3 = the next
        bgtu  s3, s2, rb_bad            ; ...
        lhu   t0, 6(s1)                 ; the extents' tree (value items), if named
        beqz  t0, rb_x                  ; ...
        sd    t0, bl_ext(zero)          ; ...
        sd    a1, rb_k(zero)            ; ...
        sd    a2, rb_kl(zero)           ; ...
        sd    a3, rb_v(zero)            ; ...
        sd    a4, rb_vl(zero)           ; ...
        mv    a0, t0                    ; ...
        call  handle_ok                 ; ...
        beqz  a0, rb_bad                ; ...
        ld    a1, rb_k(zero)            ; ...
        ld    a2, rb_kl(zero)           ; ...
        ld    a3, rb_v(zero)            ; ...
        ld    a4, rb_vl(zero)           ; ...
rb_x:
        ld    a0, 8(s1)                 ; ...
        lbu   t0, 0(s1)                 ; ...
        lbu   a5, 1(s1)                 ; ...
        li    t1, 2                     ; ...
        beq   t0, t1, rb_del            ; ...
        li    t1, 3                     ; ...
        beq   t0, t1, rb_vdel           ; ...
        li    t1, 4                     ; ...
        beq   t0, t1, rb_vw             ; ...
        li    t1, 5                     ; ...
        beq   t0, t1, rb_vmv            ; ...
        li    t1, 1                     ; ...
        bne   t0, t1, rb_bad            ; ...
        call  st_put                    ; ...
        j     rb_n                      ; ...
rb_vdel:
        call  st_bdel                   ; a value: its extents go too
        j     rb_n                      ; ...
rb_vw:
        li    t0, 8                     ; a value written: {u64 offset, the bytes}
        bltu  a4, t0, rb_bad            ; ...
        sd    a5, bw_force(zero)        ; ...
        addi  a5, a4, -8                ; ...
        addi  a4, a3, 8                 ; ...
        ld    a3, 0(a3)                 ; ...
        call  st_bwrite                 ; ...
        sd    zero, bw_force(zero)      ; ...
        j     rb_n                      ; ...
rb_vmv:
        sd    a0, rb_t(zero)            ; a value moved: the key's goes, the other key's
        sd    a1, rb_k(zero)            ;   (the item's value) moves under it
        sd    a2, rb_kl(zero)           ; ...
        sd    a3, rb_v(zero)            ; ...
        sd    a4, rb_vl(zero)           ; ...
        call  st_bdel                   ; ...
        ld    a0, rb_t(zero)            ; ...
        ld    a1, rb_v(zero)            ; ...
        ld    a2, rb_vl(zero)           ; ...
        call  st_bsize                  ; ...
        bltz  a0, rb_n                  ; (none: the key has no value now)
        ld    a0, rb_t(zero)            ; ...
        ld    a1, rb_k(zero)            ; ...
        ld    a2, rb_kl(zero)           ; ...
        la    a3, bval                  ; ...
        ld    a4, bl_vl(zero)           ; ...
        ld    a5, bl_fl(zero)           ; ...
        call  st_put                    ; ...
        ld    a0, rb_t(zero)            ; ...
        ld    a1, rb_v(zero)            ; ...
        ld    a2, rb_vl(zero)           ; ...
        call  st_del                    ; ...
        j     rb_n                      ; ...
rb_del:
        call  st_del                    ; ...
rb_n:
        mv    s1, s3                    ; ...
        j     rb_l                      ; ...
rb_done:
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...
rb_bad:
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        j     bad                       ; ...

