; addproc(a0 = pid, a1 = parent, a2 = core, a3 = name (8 bytes, zero padded)) -> a0 = record
addproc:
        la    t0, procs                 ; a free record
        li    t1, NPROC                 ; ...
ap_f:
        beqz  t1, ap_none               ; ...
        ld    t2, E_PID(t0)             ; ...
        beqz  t2, ap_take               ; ...
        addi  t0, t0, E_SIZE            ; ...
        addi  t1, t1, -1                ; ...
        j     ap_f                      ; ...
ap_take:
        li    t1, E_SIZE / 8            ; clear it
        mv    t2, t0                    ; ...
ap_z:
        sd    zero, 0(t2)               ; ...
        addi  t2, t2, 8                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, ap_z                  ; ...
        sd    a0, E_PID(t0)             ; ...
        sd    a1, E_PARENT(t0)          ; ...
        sd    a2, E_CORE(t0)            ; ...
        li    t1, 1                     ; running
        sd    t1, E_STATE(t0)           ; ...
        ld    t1, 0(a3)                 ; the name's first 8 bytes
        sd    t1, E_NAME(t0)            ; ...
        mv    a0, t0                    ; ...
        ret                             ; ...
ap_none:
        li    a0, 0                     ; table full
        ret                             ; ...

; findp(a0 = pid) -> a0 = its record, or 0
findp:
        beqz  a0, fp_no                 ; ...
        la    t0, procs                 ; ...
        li    t1, NPROC                 ; ...
fp_l:
        beqz  t1, fp_no                 ; ...
        ld    t2, E_PID(t0)             ; ...
        beq   t2, a0, fp_yes            ; ...
        addi  t0, t0, E_SIZE            ; ...
        addi  t1, t1, -1                ; ...
        j     fp_l                      ; ...
fp_yes:
        mv    a0, t0                    ; ...
        ret                             ; ...
fp_no:
        li    a0, 0                     ; ...
        ret                             ; ...

; regname(a0 = 8-byte name, a1 = core | pid << 8): add or replace a registry entry
regname:
        ld    t5, 0(a0)                 ; the name as one word
        la    t0, names                 ; same name or a free entry
        li    t1, NREG                  ; ...
        li    t3, 0                     ; first free entry
rn_l:
        beqz  t1, rn_new                ; ...
        ld    t2, 0(t0)                 ; ...
        beq   t2, t5, rn_set            ; the same name: replace
        bnez  t2, rn_n                  ; ...
        bnez  t3, rn_n                  ; ...
        mv    t3, t0                    ; ...
rn_n:
        addi  t0, t0, 16                ; ...
        addi  t1, t1, -1                ; ...
        j     rn_l                      ; ...
rn_new:
        beqz  t3, rn_ret                ; full
        mv    t0, t3                    ; ...
rn_set:
        sd    t5, 0(t0)                 ; ...
        sd    a1, 8(t0)                 ; ...
rn_ret:
        ret                             ; ...

; getname8() -> a0 = the request's name (data) as an 8-byte zero-padded word, or 0
getname8:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        la    t0, word                  ; clear
        sd    zero, 0(t0)               ; ...
        la    t0, srv_hdr               ; length 1..8
        ld    t1, 16(t0)                ; ...
        beqz  t1, gn8_no                ; ...
        li    t2, 8                     ; ...
        bgtu  t1, t2, gn8_no            ; ...
        la    a0, reqbuf                ; the data
        li    a1, 8                     ; ...
        call  srv_get                   ; ...
        la    t0, srv_hdr               ; keep only `length` bytes
        ld    t1, 16(t0)                ; ...
        la    t2, reqbuf                ; ...
        li    t3, 0                     ; ...
gn8_c:
        beq   t3, t1, gn8_d             ; ...
        add   t4, t2, t3                ; ...
        lbu   t5, 0(t4)                 ; ...
        la    t6, word                  ; ...
        add   t6, t6, t3                ; ...
        sb    t5, 0(t6)                 ; ...
        addi  t3, t3, 1                 ; ...
        j     gn8_c                     ; ...
gn8_d:
        la    a0, word            ; (its address)
        ld    a0, 0(a0)              ; ...
        j     gn8_ret                   ; ...
gn8_no:
        li    a0, 0                     ; ...
gn8_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

