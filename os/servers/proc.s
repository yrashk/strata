; get_stats() -> a0 = process records; the data in `stats`
get_stats:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        li    a0, 1                     ; STATS
        li    a1, K_STATS               ; ...
        li    a2, 0                     ; ...
        call  srvcall                   ; ...
        sd    a0, 8(sp)                 ; ...
        la    a0, stats                 ; the data
        li    a1, SYS_MAX               ; ...
        call  sys_get                   ; ...
        ld    a0, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

op_info:
        call  park                      ; ...
        call  get_stats                 ; ...
        la    t0, stats                 ; cores, free, total, processes, units, switches, KiB
        la    t1, outb                  ; ...
        ld    t2, 0(t0)                 ; ...
        sd    t2, 0(t1)                 ; ...
        ld    t2, 8(t0)                 ; ...
        sd    t2, 8(t1)                 ; ...
        ld    t2, 16(t0)                ; ...
        sd    t2, 16(t1)                ; ...
        ld    t2, 48(t0)                ; ...
        sd    t2, 24(t1)                ; ...
        ld    t2, 24(t0)                ; ...
        sd    t2, 32(t1)                ; ...
        ld    t2, 32(t0)                ; ...
        sd    t2, 40(t1)                ; ...
        ld    t2, 40(t0)                ; ...
        sd    t2, 48(t1)                ; ...
        sd    zero, 56(t1)              ; ...
        li    a0, 0                     ; ...
        la    a1, outb                  ; ...
        li    a2, 64                    ; ...
        call  unpark_reply              ; ...
        j     loop                      ; ...

; SCHED: read the slice and the switch rates, or set the slice
op_sched:
        call  park                      ; the kernel is asked: the request waits
        la    t0, srv_hdr               ; set?
        ld    t1, 8(t0)                 ; ...
        beqz  t1, osc_read              ; ...
        li    a0, 1                     ; TUNE (the kernel checks the range)
        li    a1, K_TUNE                ; ...
        li    a2, 0                     ; ...
        ld    a3, 16(t0)                ; the slice
        mv    s1, a3                    ; ...
        li    a4, 0                     ; ...
        call  sys_msg                   ; ...
        bnez  a0, osc_ans               ; refused
        la    t0, slice                 ; remember it
        sd    s1, 0(t0)                 ; ...
osc_ans:
        li    a1, 0                     ; ...
        li    a2, 0                     ; ...
        call  unpark_reply              ; ...
        j     loop                      ; ...
osc_read:
        call  get_stats                 ; totals: switches, KiB moved
        call  sys_clock                 ; (c7 carries attachments here: the clock again)
        call  sys_now                   ; s1 = elapsed since the last read
        la    t0, lnow                  ; ...
        ld    t1, 0(t0)                 ; ...
        sd    a0, 0(t0)                 ; ...
        sub   s1, a0, t1                ; ...
        bnez  s1, osc_e                 ; ...
        li    s1, 1                     ; (no division by zero)
osc_e:
        la    s2, stats                 ; ...
        la    s3, outb                  ; data: slice, switches/s, KiB/s
        la    t0, slice           ; (its address)
        ld    t0, 0(t0)              ; ...
        sd    t0, 0(s3)                 ; ...
        ld    t0, 32(s2)                ; switches now
        la    t1, lsw                   ; ...
        ld    t2, 0(t1)                 ; ...
        sd    t0, 0(t1)                 ; ...
        sub   t0, t0, t2                ; since then
        li    t3, 1000000               ; per second (ticks are microseconds)
        mul   t0, t0, t3                ; ...
        divu  t0, t0, s1                ; ...
        sd    t0, 8(s3)                 ; ...
        ld    t0, 40(s2)                ; KiB now
        la    t1, lkib                  ; ...
        ld    t2, 0(t1)                 ; ...
        sd    t0, 0(t1)                 ; ...
        sub   t0, t0, t2                ; ...
        li    t3, 1000000               ; ...
        mul   t0, t0, t3                ; ...
        divu  t0, t0, s1                ; ...
        sd    t0, 16(s3)                ; ...
        li    a0, 0                     ; ...
        la    a1, outb                  ; ...
        li    a2, 24                    ; ...
        call  unpark_reply              ; ...
        j     loop                      ; ...

op_cores:
        call  park                      ; ...
        call  get_stats                 ; ...
        la    s1, stats                 ; ...
        ld    s2, 0(s1)                 ; cores
        la    s3, outb                  ; ...
        li    s4, 0                     ; ...
oco_l:
        bge   s4, s2, oco_done          ; ...
        slli  t0, s4, 5                 ; its kernel record
        add   t0, t0, s1                ; ...
        ld    t1, 64(t0)                ; pid | runnable << 8 | processes << 16 | flags << 24
        sd    zero, 0(s3)               ; ...
        sd    zero, 8(s3)               ; ...
        sd    zero, 16(s3)              ; ...
        sd    zero, 24(s3)              ; ...
        sb    s4, 0(s3)                 ; core
        sb    t1, 1(s3)                 ; running pid
        srli  t2, t1, 8                 ; runnable
        sb    t2, 2(s3)                 ; ...
        srli  t2, t1, 16                ; processes
        sb    t2, 3(s3)                 ; ...
        srli  t2, t1, 24                ; flags
        sb    t2, 4(s3)                 ; ...
        ld    t2, 72(t0)                ; switches
        sw    t2, 8(s3)                 ; ...
        ld    t2, 80(t0)                ; KiB
        sw    t2, 12(s3)                ; ...
        addi  s3, s3, 32                ; ...
        addi  s4, s4, 1                 ; ...
        j     oco_l                     ; ...
oco_done:
        mv    a0, s2                    ; ...
        la    a1, outb                  ; ...
        slli  a2, s2, 5                 ; ...
        call  unpark_reply              ; ...
        j     loop                      ; ...

op_ps:
        call  park                      ; ...
        call  get_stats                 ; s4 = kernel process records
        mv    s4, a0                    ; ...
        la    s1, stats                 ; s1 = the first one
        ld    t0, 0(s1)                 ; (after the header and the cores)
        slli  t0, t0, 5                 ; ...
        addi  t0, t0, 64                ; ...
        add   s1, s1, t0                ; ...
        la    s2, outb                  ; s2 = output
        li    s3, 0                     ; s3 = records out
ops_l:
        beqz  s4, ops_z                 ; ...
        ld    t0, 0(s1)                 ; pid | core << 8 | state << 16 | flags << 24
        andi  a0, t0, 255               ; ...
        call  ps_rec                    ; ...
        addi  s1, s1, 32                ; ...
        addi  s4, s4, -1                ; ...
        j     ops_l                     ; ...
ops_z:
        la    s1, procs                 ; then the zombies proc remembers
        li    s4, NPROC                 ; ...
ops_zl:
        beqz  s4, ops_done              ; ...
        ld    t0, E_PID(s1)             ; ...
        beqz  t0, ops_zn                ; ...
        ld    t1, E_STATE(s1)           ; ...
        li    t2, 4                     ; ...
        bne   t1, t2, ops_zn            ; ...
        li    t3, 32                    ; at most 32 records
        bge   s3, t3, ops_done          ; ...
        sd    zero, 0(s2)               ; ...
        sd    zero, 8(s2)               ; ...
        sb    t0, 0(s2)                 ; pid
        sb    t2, 1(s2)                 ; zombie
        ld    t1, E_CORE(s1)            ; ...
        sb    t1, 2(s2)                 ; ...
        ld    t1, E_PARENT(s1)          ; ...
        sb    t1, 3(s2)                 ; ...
        ld    t1, E_NAME(s1)            ; ...
        sd    t1, 16(s2)                ; ...
        sd    zero, 24(s2)              ; ...
        addi  s2, s2, 32                ; ...
        addi  s3, s3, 1                 ; ...
ops_zn:
        addi  s1, s1, E_SIZE            ; ...
        addi  s4, s4, -1                ; ...
        j     ops_zl                    ; ...
ops_done:
        mv    a0, s3                    ; ...
        la    a1, outb                  ; ...
        slli  a2, s3, 5                 ; ...
        call  unpark_reply              ; ...
        j     loop                      ; ...

; ps_rec(a0 = pid) (s1 = kernel record, s2 = output, s3 = count): one PS record
ps_rec:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        li    t3, 32                    ; at most 32 records
        bge   s3, t3, pr_ret            ; ...
        sd    a0, 8(sp)                 ; ...
        call  findp                     ; proc's record: parent and name
        mv    t6, a0                    ; ...
        ld    t0, 0(s1)                 ; ...
        sd    zero, 0(s2)               ; ...
        sd    zero, 8(s2)               ; ...
        sd    zero, 16(s2)              ; ...
        sd    zero, 24(s2)              ; ...
        sb    t0, 0(s2)                 ; pid
        srli  t1, t0, 16                ; the kernel's state -> 1 running 2 ready 3 blocked 4 zombie
        andi  t1, t1, 255               ; ...
        li    t2, 2                     ; (loading: ready)
        li    t3, 1                     ; ...
        beq   t1, t3, pr_st             ; ...
        li    t3, 2                     ; ready: running if its core runs it now
        bne   t1, t3, pr_bl             ; ...
        srli  t4, t0, 8                 ; its core's record in the stats
        andi  t4, t4, 255               ; ...
        slli  t4, t4, 5                 ; ...
        la    t5, stats                 ; ...
        add   t4, t4, t5                ; ...
        lbu   t4, 64(t4)                ; the pid running there
        andi  t5, t0, 255               ; ...
        bne   t4, t5, pr_st             ; ...
        li    t2, 1                     ; running
        j     pr_st                     ; ...
pr_bl:
        li    t2, 3                     ; blocked
        li    t3, 6                     ; (ended)
        bne   t1, t3, pr_st             ; ...
        li    t2, 4                     ; ...
pr_st:
        sb    t2, 1(s2)                 ; state
        srli  t1, t0, 8                 ; core
        sb    t1, 2(s2)                 ; ...
        beqz  t6, pr_np                 ; parent and name
        ld    t1, E_PARENT(t6)          ; ...
        sb    t1, 3(s2)                 ; ...
        ld    t1, E_NAME(t6)            ; ...
        sd    t1, 16(s2)                ; ...
pr_np:
        srli  t1, t0, 24                ; flags: 2 server
        andi  t2, t1, 2                 ; ...
        sb    t2, 4(s2)                 ; ...
        ld    t1, 8(s1)                 ; cores
        sb    t1, 5(s2)                 ; ...
        ld    t1, 16(s1)                ; switches
        sw    t1, 8(s2)                 ; ...
        ld    t1, 24(s1)                ; KiB moved
        srli  t1, t1, 10                ; ...
        sw    t1, 12(s2)                ; ...
        addi  s2, s2, 32                ; ...
        addi  s3, s3, 1                 ; ...
pr_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

