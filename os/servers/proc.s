; boot_spawn(a0 = command, a1 = its length, a2 = kernel flags, a3 = endpoint
; cores) -> a0 = its core (a server's endpoint in c6); a server with no
; handles, child of proc
boot_spawn:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        la    t0, sp_cmd                ; ...
        sd    a0, 0(t0)                 ; ...
        la    t0, sp_clen               ; ...
        sd    a1, 0(t0)                 ; ...
        la    t0, sp_kfl                ; ...
        sd    a2, 0(t0)                 ; ...
        la    t0, sp_eps                ; ...
        sd    a3, 0(t0)                 ; ...
        la    t0, sp_nc                 ; time-shared
        sd    zero, 0(t0)               ; ...
        la    t0, sp_mode               ; ...
        sd    zero, 0(t0)               ; ...
        la    t0, sp_par                ; parent: proc
        li    t1, 1                     ; ...
        sd    t1, 0(t0)                 ; ...
        la    t0, sp_d                  ; no handles
        li    t1, -1                    ; ...
        sd    t1, 0(t0)                 ; ...
        sd    t1, 8(t0)                 ; ...
        sd    t1, 16(t0)                ; ...
        call  do_spawn                  ; a0 = pid
        blez  a0, bs_fail               ; it must work
        call  findp                     ; its core
        ld    a0, E_CORE(a0)            ; ...
        andi  a0, a0, 255               ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...
bs_fail:
        li    a0, 1                     ; without tty and pipe nothing works
        call  sys_exit                  ; (the kernel stops the machine when proc ends)

; start_sh(): the login shell, on the console
start_sh:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        la    t0, sp_cmd                ; "sh -l"
        la    t1, c_sh                  ; ...
        sd    t1, 0(t0)                 ; ...
        la    t0, sp_clen               ; ...
        li    t1, 5                     ; ...
        sd    t1, 0(t0)                 ; ...
        la    t0, sp_kfl                ; ...
        sd    zero, 0(t0)               ; ...
        call  std_eps                   ; ...
        la    t0, sp_nc                 ; ...
        sd    zero, 0(t0)               ; ...
        la    t0, sp_mode               ; ...
        sd    zero, 0(t0)               ; ...
        la    t0, sp_par                ; parent: proc
        li    t1, 1                     ; ...
        sd    t1, 0(t0)                 ; ...
        la    t0, sp_d                  ; 0, 1, 2 = the console (tty id 0)
        li    t1, 3                     ; ...
        slli  t1, t1, 32                ; ...
        sd    t1, 0(t0)                 ; ...
        sd    t1, 8(t0)                 ; ...
        sd    t1, 16(t0)                ; ...
        call  do_spawn                  ; ...
        blez  a0, ss_ret                ; (nothing to do about it)
        la    t0, loginpid              ; remember it
        sd    a0, 0(t0)                 ; ...
ss_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; std_eps(): sp_eps = proc | fs << 8 | tty << 16 | pipe << 24
std_eps:
        la    t0, mycore          ; (its address)
        ld    t0, 0(t0)              ; ...
        la    t1, fscore          ; (its address)
        ld    t1, 0(t1)              ; ...
        slli  t1, t1, 8                 ; ...
        or    t0, t0, t1                ; ...
        la    t1, ttycore         ; (its address)
        ld    t1, 0(t1)              ; ...
        slli  t1, t1, 16                ; ...
        or    t0, t0, t1                ; ...
        la    t1, pipecore        ; (its address)
        ld    t1, 0(t1)              ; ...
        slli  t1, t1, 24                ; ...
        or    t0, t0, t1                ; ...
        la    t1, sp_eps                ; ...
        sd    t0, 0(t1)                 ; ...
        ret                             ; ...

; do_spawn() (sp_* set) -> a0 = pid, or an error; a server's endpoint is left in c6
do_spawn:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        la    t0, sp_cmd          ; (its address)
        ld    t0, 0(t0)              ; the program's name: the first word
        la    t1, sp_clen         ; (its address)
        ld    t1, 0(t1)              ; ...
        li    t2, 0                     ; ...
ds_nm:
        beq   t2, t1, ds_nmd            ; ...
        add   t3, t0, t2                ; ...
        lbu   t3, 0(t3)                 ; ...
        li    t4, ' '                   ; ...
        beq   t3, t4, ds_nmd            ; ...
        addi  t2, t2, 1                 ; ...
        j     ds_nm                     ; ...
ds_nmd:
        li    a0, -4                    ; no name
        beqz  t2, ds_ret                ; ...
        li    t3, 24                    ; too long
        bgtu  t2, t3, ds_ret            ; ...
        la    t0, sp_nlen               ; ...
        sd    t2, 0(t0)                 ; ...
        call  newpid                    ; s1 = the pid
        mv    s1, a0                    ; ...
        la    t0, sp_pid                ; ...
        sd    s1, 0(t0)                 ; ...
        li    a0, -6                    ; no pid / record left
        beqz  s1, ds_ret                ; ...
        li    a0, 1                     ; MEMORY: an arena (c6)
        li    a1, K_MEMORY              ; ...
        li    a2, 0                     ; ...
        li    a3, 0x100000              ; ...
        li    a4, 0                     ; ...
        call  sys_msg                   ; ...
        bltz  a0, ds_ret                ; -6
        call  write_start               ; the start-up block -> the arena
        csend c6, c2                    ; LOADIMG: the arena (attachment) ...
        la    a0, sp_cmd          ; (its address)
        ld    a0, 0(a0)              ; ... and the name
        la    a1, sp_nlen         ; (its address)
        ld    a1, 0(a1)              ; ...
        call  sys_put                   ; ...
        li    a0, 2                     ; fs
        li    a1, 28                    ; LOADIMG
        li    a2, IMG_MAX               ; the most bytes
        la    a3, sp_nlen         ; (its address)
        ld    a3, 0(a3)              ; ...
        li    a4, A_IMG                 ; where
        call  sys_msg                   ; a0 = size; the arena back in c6
        bltz  a0, ds_free               ; not loaded
        call  image_kind                ; a0 = 1 if a StrataOS program
        mv    s2, a0                    ; s2 = that
        la    t0, sp_a0                 ; old protocol: a0 = input length, a1 = output?
        sd    zero, 0(t0)               ; ...
        la    t0, sp_a1                 ; ...
        sd    zero, 0(t0)               ; ...
        la    t0, sp_ef                 ; proc flags
        sd    zero, 0(t0)               ; ...
        bnez  s2, ds_dups               ; a StrataOS program uses its handles itself
        la    t0, sp_nc           ; (its address)
        ld    t0, 0(t0)              ; bare metal: exclusive
        bnez  t0, ds_x                  ; ...
        li    t0, 1                     ; (on one core unless -n)
        la    t1, sp_nc                 ; ...
        sd    t0, 0(t1)                 ; ...
ds_x:
        la    t0, sp_d            ; (its address)
        ld    t0, 0(t0)              ; `< file`: READALL into the arena
        srli  t1, t0, 32                ; (a file handle: server register 2)
        li    t2, 2                     ; ...
        bne   t1, t2, ds_out            ; ...
        csend c6, c2                    ; the arena ...
        li    a0, 2                     ; ... READALL
        li    a1, 34                    ; ...
        slli  a2, t0, 32                ; the id
        srli  a2, a2, 32                ; ...
        li    a3, A_OUT - A_IN          ; the most bytes
        li    a4, A_IN                  ; where
        call  sys_msg                   ; a0 = length
        bltz  a0, ds_out                ; (none: a0 = 0)
        la    t0, sp_a0                 ; ...
        sd    a0, 0(t0)                 ; ...
ds_out:
        la    t0, sp_d                  ; `> file`: output from the arena at exit
        ld    t0, 8(t0)                 ; (descriptor of handle 1)
        srli  t1, t0, 32                ; ...
        li    t2, 2                     ; ...
        bne   t1, t2, ds_dups           ; ...
        slli  t0, t0, 32                ; its id
        srli  t0, t0, 32                ; ...
        la    t1, sp_out                ; ...
        sd    t0, 0(t1)                 ; ...
        li    t0, 1                     ; a1 = 1
        la    t1, sp_a1                 ; ...
        sd    t0, 0(t1)                 ; ...
        la    t1, sp_ef                 ; ...
        li    t0, EF_OLDOUT             ; ...
        sd    t0, 0(t1)                 ; ...
        la    t0, sp_kfl          ; (its address)
        ld    t0, 0(t0)              ; the kernel keeps the arena for us
        ori   t0, t0, KF_KEEP           ; ...
        la    t1, sp_kfl                ; ...
        sd    t0, 0(t1)                 ; ...
ds_dups:
        li    s3, 2                     ; DUPS at fs (2), tty (3), pipe (4)
ds_dl:
        li    t0, 5                     ; ...
        bge   s3, t0, ds_create         ; ...
        mv    a0, s3                    ; ...
        call  dups                      ; ...
        addi  s3, s3, 1                 ; ...
        j     ds_dl                     ; ...
ds_create:
        la    t0, cdata                 ; CREATE: pid, ncores, flags, pin, eps, a0, a1, a2
        sd    s1, 0(t0)                 ; ...
        la    t1, sp_nc           ; (its address)
        ld    t1, 0(t1)              ; ...
        sd    t1, 8(t0)                 ; ...
        la    t1, sp_kfl          ; (its address)
        ld    t1, 0(t1)              ; ...
        sd    t1, 16(t0)                ; ...
        li    t1, -1                    ; pin?
        la    t2, sp_mode         ; (its address)
        ld    t2, 0(t2)              ; ...
        andi  t3, t2, 2                 ; ...
        beqz  t3, ds_pin                ; ...
        srli  t1, t2, 8                 ; ...
ds_pin:
        sd    t1, 24(t0)                ; ...
        la    t1, sp_eps          ; (its address)
        ld    t1, 0(t1)              ; endpoints (none for a sandboxed child)
        andi  t3, t2, 1                 ; ...
        beqz  t3, ds_eps                ; ...
        li    t1, -1                    ; ...
ds_eps:
        sd    t1, 32(t0)                ; ...
        la    t1, sp_a0           ; (its address)
        ld    t1, 0(t1)              ; ...
        sd    t1, 40(t0)                ; ...
        la    t1, sp_a1           ; (its address)
        ld    t1, 0(t1)              ; ...
        sd    t1, 48(t0)                ; ...
        sd    zero, 56(t0)              ; ...
        csend c6, c1                    ; the arena ...
        la    a0, cdata                 ; ... and the data
        li    a1, 64                    ; ...
        call  sys_put                   ; ...
        li    a0, 1                     ; ...
        li    a1, K_CREATE              ; ...
        li    a2, 0                     ; ...
        li    a3, 64                    ; ...
        li    a4, 0                     ; ...
        call  sys_msg                   ; a0 = 0, data[0] = its core
        bltz  a0, ds_undo               ; refused: the arena came back
        li    a0, 0                     ; its core
        call  sys_word                  ; ...
        mv    s4, a0                    ; ...
        la    t0, sp_nc           ; (its address)
        ld    t0, 0(t0)              ; record it
        slli  t0, t0, 8                 ; core | cores << 8
        or    a2, s4, t0                ; ...
        mv    a0, s1                    ; ...
        la    a1, sp_par          ; (its address)
        ld    a1, 0(a1)              ; ...
        la    a3, word                  ; its name (first 8 bytes of the command)
        la    t0, sp_cmd          ; (its address)
        ld    t0, 0(t0)              ; ...
        li    t1, 0                     ; ...
        sd    zero, 0(a3)               ; ...
        la    t2, sp_nlen         ; (its address)
        ld    t2, 0(t2)              ; ...
        li    t3, 8                     ; ...
        bleu  t2, t3, ds_n8             ; ...
        mv    t2, t3                    ; ...
ds_n8:
        beq   t1, t2, ds_add            ; ...
        add   t4, t0, t1                ; ...
        lbu   t4, 0(t4)                 ; ...
        add   t5, a3, t1                ; ...
        sb    t4, 0(t5)                 ; ...
        addi  t1, t1, 1                 ; ...
        j     ds_n8                     ; ...
ds_add:
        call  addproc                   ; ...
        beqz  a0, ds_ok                 ; (cannot happen: newpid checked)
        la    t0, sp_ef           ; (its address)
        ld    t0, 0(t0)              ; flags
        la    t1, sp_kfl          ; (its address)
        ld    t1, 0(t1)              ; ...
        andi  t1, t1, KF_SERVER         ; ...
        beqz  t1, ds_f2                 ; ...
        ori   t0, t0, EF_SERVER         ; ...
ds_f2:
        bnez  s2, ds_f3                 ; ...
        ori   t0, t0, EF_EXCL           ; ...
ds_f3:
        la    t1, sp_nc           ; (its address)
        ld    t1, 0(t1)              ; ...
        beqz  t1, ds_f4                 ; ...
        ori   t0, t0, EF_EXCL           ; ...
ds_f4:
        sd    t0, E_FLAGS(a0)           ; ...
        la    t1, sp_out          ; (its address)
        ld    t1, 0(t1)              ; ...
        sd    t1, E_OUTID(a0)           ; ...
ds_ok:
        mv    a0, s1                    ; the pid
        j     ds_ret                    ; ...
ds_undo:
        mv    s4, a0                    ; keep the error
        call  free_arena                ; ...
        li    s3, 2                     ; undo the DUPS
ds_ul:
        li    t0, 5                     ; ...
        bge   s3, t0, ds_uerr           ; ...
        mv    a0, s3                    ; ...
        li    a1, OP_CLEANUP            ; ...
        mv    a2, s1                    ; ...
        call  srvcall                   ; ...
        addi  s3, s3, 1                 ; ...
        j     ds_ul                     ; ...
ds_uerr:
        mv    a0, s4                    ; ...
        j     ds_ret                    ; ...
ds_free:
        mv    s4, a0                    ; not a program (or none)
        call  free_arena                ; ...
        mv    a0, s4                    ; ...
ds_ret:
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; ...

; newpid() -> a0 = an unused pid (4..255, round robin), or 0
newpid:
        li    t6, 252                   ; tries
np_l:
        beqz  t6, np_none               ; ...
        la    t0, nextpid         ; (its address)
        ld    t0, 0(t0)              ; ...
        addi  t1, t0, 1                 ; advance
        li    t2, 256                   ; ...
        bltu  t1, t2, np_w              ; ...
        li    t1, 4                     ; ...
np_w:
        la    t2, nextpid               ; ...
        sd    t1, 0(t2)                 ; ...
        la    t2, procs                 ; in use?
        li    t3, NPROC                 ; ...
        li    t5, 0                     ; (free records)
np_c:
        beqz  t3, np_free               ; not in use
        ld    t4, E_PID(t2)             ; ...
        beq   t4, t0, np_used           ; ...
        bnez  t4, np_cn                 ; ...
        addi  t5, t5, 1                 ; ...
np_cn:
        addi  t2, t2, E_SIZE            ; ...
        addi  t3, t3, -1                ; ...
        j     np_c                      ; ...
np_free:
        beqz  t5, np_none               ; no record to keep it in
        mv    a0, t0                    ; ...
        ret                             ; ...
np_used:
        addi  t6, t6, -1                ; ...
        j     np_l                      ; ...
np_none:
        li    a0, 0                     ; ...
        ret                             ; ...

; write_start(): the start-up block -> the arena (c6) at 0x7F000
write_start:
        la    t0, stbuf                 ; clear it
        li    t1, 64                    ; ...
ws_z:
        sd    zero, 0(t0)               ; ...
        addi  t0, t0, 8                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, ws_z                  ; ...
        la    t0, stbuf                 ; 0 pid, 8 parent, 16.. handles, 40 length, 64.. text
        la    t1, sp_pid          ; (its address)
        ld    t1, 0(t1)              ; ...
        sd    t1, 0(t0)                 ; ...
        la    t1, sp_par          ; (its address)
        ld    t1, 0(t1)              ; ...
        sd    t1, 8(t0)                 ; ...
        la    t2, sp_d                  ; ...
        ld    t1, 0(t2)                 ; ...
        sd    t1, 16(t0)                ; ...
        ld    t1, 8(t2)                 ; ...
        sd    t1, 24(t0)                ; ...
        ld    t1, 16(t2)                ; ...
        sd    t1, 32(t0)                ; ...
        la    t1, sp_clen         ; (its address)
        ld    t1, 0(t1)              ; ...
        li    t2, 440                   ; ...
        bleu  t1, t2, ws_l              ; ...
        mv    t1, t2                    ; ...
ws_l:
        sd    t1, 40(t0)                ; ...
        la    t3, sp_cmd          ; (its address)
        ld    t3, 0(t3)              ; the text
        li    t4, 0                     ; ...
ws_c:
        beq   t4, t1, ws_put            ; ...
        add   t5, t3, t4                ; ...
        lbu   t5, 0(t5)                 ; ...
        add   t6, t0, t4                ; ...
        sb    t5, 64(t6)                ; ...
        addi  t4, t4, 1                 ; ...
        j     ws_c                      ; ...
ws_put:
        li    t1, A_START               ; -> the arena
        li    t2, 512                   ; ...
        tput  tg9, t0, c6, t1, t2       ; ...
        twait 1 << 9                    ; ...
        ret                             ; ...

; image_kind() -> a0 = 1 if the image in the arena (c6) carries the "SYS2" marker
image_kind:
        la    t0, img                   ; STX header, first section header, first code words
        li    t1, A_IMG                 ; ...
        li    t2, 32                    ; ...
        tget  tg9, t0, c6, t1, t2       ; ...
        twait 1 << 9                    ; ...
        lwu   t1, 8(t0)                 ; the first section must be code (kind 1)
        li    t2, 1                     ; ...
        bne   t1, t2, ik_no             ; ...
        lwu   t1, 28(t0)                ; its second word
        li    t2, 0x32535953            ; "SYS2"
        bne   t1, t2, ik_no             ; ...
        li    a0, 1                     ; ...
        ret                             ; ...
ik_no:
        li    a0, 0                     ; bare metal
        ret                             ; ...

; dups(a0 = server register): DUPS of the handles (sp_d) that server owns, for sp_pid
dups:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        la    t0, dbuf                  ; owner, count, ids
        la    t1, sp_pid          ; (its address)
        ld    t1, 0(t1)              ; ...
        sd    t1, 0(t0)                 ; ...
        li    t2, 0                     ; count
        la    t3, sp_d                  ; ...
        li    t4, 3                     ; ...
du_l:
        beqz  t4, du_send               ; ...
        ld    t5, 0(t3)                 ; descriptor
        bltz  t5, du_n                  ; none
        srli  t6, t5, 32                ; this server's?
        bne   t6, a0, du_n              ; ...
        slli  t5, t5, 32                ; id
        srli  t5, t5, 32                ; ...
        slli  t6, t2, 3                 ; ...
        add   t6, t0, t6                ; ...
        sd    t5, 16(t6)                ; ...
        addi  t2, t2, 1                 ; ...
du_n:
        addi  t3, t3, 8                 ; ...
        addi  t4, t4, -1                ; ...
        j     du_l                      ; ...
du_send:
        beqz  t2, du_ret                ; nothing for it
        sd    t2, 8(t0)                 ; ...
        slli  a1, t2, 3                 ; bytes
        addi  a1, a1, 16                ; ...
        la    a0, dbuf                  ; ...
        call  sys_put                   ; ...
        ld    a0, 8(sp)                 ; ...
        li    a1, OP_DUPS               ; ...
        li    a2, 0                     ; ...
        li    a3, 64                    ; ...
        li    a4, 0                     ; ...
        call  sys_msg                   ; ...
du_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; ---- SPAWN ----------------------------------------------------------------------------------
op_spawn:
        la    a0, reqbuf                ; the data: ncores, h0..h2, text
        li    a1, 32 + 448              ; ...
        call  srv_get                   ; ...
        la    t0, reqbuf                ; ...
        ld    t1, 0(t0)                 ; ...
        la    t2, sp_nc                 ; ...
        sd    t1, 0(t2)                 ; ...
        la    t2, sp_d                  ; ...
        ld    t1, 8(t0)                 ; ...
        sd    t1, 0(t2)                 ; ...
        ld    t1, 16(t0)                ; ...
        sd    t1, 8(t2)                 ; ...
        ld    t1, 24(t0)                ; ...
        sd    t1, 16(t2)                ; ...
        addi  t1, t0, 32                ; the text
        la    t2, sp_cmd                ; ...
        sd    t1, 0(t2)                 ; ...
        la    t0, srv_hdr               ; its length, mode, the parent
        ld    t1, 16(t0)                ; ...
        li    t3, 440                   ; ...
        bleu  t1, t3, osp_l             ; ...
        mv    t1, t3                    ; ...
osp_l:
        la    t2, sp_clen               ; ...
        sd    t1, 0(t2)                 ; ...
        ld    t1, 24(t0)                ; ...
        la    t2, sp_mode               ; ...
        sd    t1, 0(t2)                 ; ...
        ld    t1, 40(t0)                ; ...
        la    t2, sp_par                ; ...
        sd    t1, 0(t2)                 ; ...
        la    t2, sp_kfl                ; ordinary process
        sd    zero, 0(t2)               ; ...
        la    t2, sp_cmd                ; except the window server, `ws`: it becomes its
        ld    t2, 0(t2)                 ;   core's server (on an empty core), so that
        lbu   t3, 0(t2)                 ;   requests sent to the name it REGISTERs reach
        li    t4, 'w'                   ;   its RECEIVE. It stays an ordinary child of its
        bne   t3, t4, osp_ord           ;   parent (WAIT, KILL and Ctrl-C work); when it
        lbu   t3, 1(t2)                 ;   ends, the kernel frees the core's server slot
        li    t4, 's'                   ;   and its name leaves the registry, so `ws` can
        bne   t3, t4, osp_ord           ;   be run again.
        la    t3, sp_clen               ; (the whole first word is "ws")
        ld    t3, 0(t3)                 ; ...
        li    t4, 2                     ; ...
        bltu  t3, t4, osp_ord           ; ...
        beq   t3, t4, osp_ws            ; ...
        lbu   t3, 2(t2)                 ; ...
        li    t4, ' '                   ; ...
        bne   t3, t4, osp_ord           ; ...
osp_ws:
        li    t3, KF_SERVER             ; ...
        la    t2, sp_kfl                ; ...
        sd    t3, 0(t2)                 ; ...
osp_ord:
        call  std_eps                   ; ...
        call  park                      ; the request waits in the kernel
        bltz  a0, osp_busy              ; ...
        call  do_spawn                  ; a0 = pid or an error
        mv    s1, a0                    ; ...
        cclear c6                       ; (the endpoint the kernel sends for a server: LOOKUP mints its own)
        blez  s1, osp_ans               ; not started
        mv    a0, s1                    ; a spawned server is not one of the boot servers:
        call  findp                     ;   it can be killed like any process
        beqz  a0, osp_ans               ; ...
        ld    t0, E_FLAGS(a0)           ; ...
        andi  t0, t0, 0xfffd            ; (EF_SERVER off; EF_USRV: it may REGISTER)
        ori   t0, t0, EF_USRV           ; ...
        sd    t0, E_FLAGS(a0)           ; ...
osp_ans:
        mv    a0, s1                    ; answer
        li    a1, 0                     ; ...
        li    a2, 0                     ; ...
        call  unpark_reply              ; ...
        j     loop                      ; ...
osp_busy:
        li    a0, -7                    ; ...
        j     reply                     ; ...

; =============================================================================
; WAIT, exits
; =============================================================================

; op_wait: handle = pid (0 any), mode bit0 = do not block
op_wait:
        call  srv_pid                   ; s1 = the parent's record
        call  findp                     ; ...
        beqz  a0, ow_none               ; ...
        mv    s1, a0                    ; ...
        la    t0, srv_hdr               ; s2 = wanted pid
        ld    s2, 8(t0)                 ; ...
        mv    a0, s1                    ; a finished child?
        mv    a1, s2                    ; ...
        call  zombie_of                 ; a0 = its record, or 0; a1 = 1 if any matching child
        bnez  a0, ow_reap               ; ...
        beqz  a1, ow_none               ; no such child
        ld    t0, E_FLAGS(s1)           ; an interrupt pending?
        andi  t1, t0, EF_INTR           ; ...
        beqz  t1, ow_nb                 ; ...
        andi  t0, t0, 0xffef            ; consumed
        sd    t0, E_FLAGS(s1)           ; ...
        li    a0, -2                    ; ...
        j     reply                     ; ...
ow_nb:
        la    t0, srv_hdr               ; do not block?
        ld    t1, 24(t0)                ; ...
        andi  t1, t1, 1                 ; ...
        beqz  t1, ow_park               ; ...
        li    a0, -3                    ; still running
        j     reply                     ; ...
ow_park:
        ld    t0, E_WAIT(s1)            ; one WAIT at a time
        bnez  t0, ow_busy               ; ...
        call  srv_park                  ; the request waits in the kernel
        bltz  a0, ow_busy               ; ...
        addi  a0, a0, 1                 ; park id + 1 | token << 8 | wanted << 32
        la    t0, srv_tok         ; (its address)
        ld    t0, 0(t0)              ; ...
        slli  t0, t0, 8                 ; ...
        or    a0, a0, t0                ; ...
        slli  t0, s2, 32                ; ...
        or    a0, a0, t0                ; ...
        sd    a0, E_WAIT(s1)            ; ...
        j     loop                      ; no answer yet
ow_busy:
        li    a0, -7                    ; ...
        j     reply                     ; ...
ow_reap:
        ld    t0, E_PID(a0)             ; data[0] = its pid
        la    t1, word                  ; ...
        sd    t0, 0(t1)                 ; ...
        ld    s3, E_STATUS(a0)          ; the status
        sd    zero, E_PID(a0)           ; the record is free
        la    a0, word                  ; ...
        li    a1, 8                     ; ...
        call  srv_put                   ; ...
        mv    a0, s3                    ; ...
        j     reply                     ; ...
ow_none:
        li    a0, -1                    ; no such child
        j     reply                     ; ...

; zombie_of(a0 = parent record, a1 = pid or 0) -> a0 = a finished matching
; child's record or 0; a1 = 1 if any matching child exists
zombie_of:
        ld    t5, E_PID(a0)             ; the parent's pid
        la    t0, procs                 ; ...
        li    t1, NPROC                 ; ...
        li    t6, 0                     ; any?
zo_l:
        beqz  t1, zo_no                 ; ...
        ld    t2, E_PID(t0)             ; used?
        beqz  t2, zo_n                  ; ...
        ld    t3, E_PARENT(t0)          ; a child?
        bne   t3, t5, zo_n              ; ...
        beqz  a1, zo_m                  ; any child
        bne   t2, a1, zo_n              ; that one
zo_m:
        li    t6, 1                     ; matching
        ld    t3, E_STATE(t0)           ; finished?
        li    t4, 4                     ; ...
        bne   t3, t4, zo_n              ; ...
        mv    a0, t0                    ; ...
        li    a1, 1                     ; ...
        ret                             ; ...
zo_n:
        addi  t0, t0, E_SIZE            ; ...
        addi  t1, t1, -1                ; ...
        j     zo_l                      ; ...
zo_no:
        li    a0, 0                     ; ...
        mv    a1, t6                    ; ...
        ret                             ; ...

; op_exited: from the kernel; handle = pid, length = status, attachment (c7) = the arena if kept
op_exited:
        la    t0, srv_hdr               ; ...
        ld    s1, 8(t0)                 ; s1 = pid
        ld    s2, 16(t0)                ; s2 = status
        call  park                      ; the kernel's buffer waits while we work
        mv    a0, s1                    ; s3 = its record
        call  findp                     ; ...
        mv    s3, a0                    ; ...
        cvalid t0, c7                   ; its arena came back?
        beqz  t0, oe_clean              ; no
        beqz  s3, oe_free               ; (unknown process: just free it)
        ld    t0, E_FLAGS(s3)           ; old-protocol output to save?
        andi  t0, t0, EF_OLDOUT         ; ...
        beqz  t0, oe_free               ; ...
        srli  t0, s2, 62                ; killed or faulted: nothing to save
        bnez  t0, oe_free               ; ...
        slli  t1, s2, 32                ; the code = the output's length
        srli  t1, t1, 32                ; ...
        beqz  t1, oe_free               ; ...
        li    t2, 0x10000               ; (at most 64 KiB: the output area)
        bleu  t1, t2, oe_w              ; ...
        mv    t1, t2                    ; ...
oe_w:
        csend c7, c2                    ; WRITEALL: the arena ...
        li    a0, 2                     ; ...
        li    a1, 35                    ; ...
        ld    a2, E_OUTID(s3)           ; the file
        mv    a3, t1                    ; length
        li    a4, A_OUT                 ; where
        call  sys_msg                   ; (the arena comes back in c6)
        li    s2, 0                     ; the code was the output's length: status 0
        j     oe_free2                  ; ...
oe_free:
        cclear c6                       ; ...
        cmov  c6, c7                    ; the arena
oe_free2:
        call  free_arena                ; back to the kernel
oe_clean:
        cclear c7                       ; ...
        li    s4, 2                     ; CLEANUP at fs, tty, pipe
oe_cl:
        li    t0, 5                     ; ...
        bge   s4, t0, oe_rec            ; ...
        mv    a0, s4                    ; ...
        li    a1, OP_CLEANUP            ; ...
        mv    a2, s1                    ; ...
        call  srvcall                   ; ...
        addi  s4, s4, 1                 ; ...
        j     oe_cl                     ; ...
oe_rec:
        mv    a0, s1                    ; its names die with it
        call  unregpid                  ; ...
        beqz  s3, oe_done               ; unknown process
        sd    s2, E_STATUS(s3)          ; finished
        li    t0, 4                     ; ...
        sd    t0, E_STATE(s3)           ; ...
        mv    a0, s1                    ; its children become orphans
        call  orphans                   ; ...
        la    t0, loginpid        ; (its address)
        ld    t0, 0(t0)              ; the login shell? start another
        bne   t0, s1, oe_parent         ; ...
        sd    zero, E_PID(s3)           ; (nobody waits for it)
        li    a0, 3                     ; (it may have died reading a line: the console
        li    a1, 19                    ;   back to cooked mode, CONMODE 0)
        li    a2, 0                     ; ...
        call  srvcall                   ; ...
        call  start_sh                  ; ...
        j     oe_done                   ; ...
oe_parent:
        ld    a0, E_PARENT(s3)          ; its parent
        call  findp                     ; ...
        beqz  a0, oe_orphan             ; gone: the status is discarded
        ld    t0, E_PID(a0)             ; proc itself is the parent: nobody waits
        li    t1, 1                     ; ...
        beq   t0, t1, oe_orphan         ; ...
        mv    s4, a0                    ; s4 = parent record
        ld    t0, E_WAIT(s4)            ; is it waiting for this one?
        beqz  t0, oe_done               ; no: a zombie until it asks
        srli  t1, t0, 32                ; wanted pid
        beqz  t1, oe_wake               ; any
        bne   t1, s1, oe_done           ; another one
oe_wake:
        sd    zero, E_WAIT(s4)          ; answer its WAIT now
        call  swap_pk                   ; (keep the kernel's parked buffer aside)
        andi  t1, t0, 255               ; its park id + 1
        addi  t1, t1, -1                ; ...
        la    t2, pk                    ; ...
        sd    t1, 0(t2)                 ; ...
        srli  t1, t0, 8                 ; its token
        li    t2, 0xffffff              ; ...
        and   t1, t1, t2                ; ...
        la    t2, pktok                 ; ...
        sd    t1, 0(t2)                 ; ...
        la    t0, word                  ; data[0] = pid
        sd    s1, 0(t0)                 ; ...
        mv    a0, s2                    ; the status
        la    a1, word                  ; ...
        li    a2, 8                     ; ...
        call  unpark_reply              ; ...
        call  unswap_pk                 ; the kernel's buffer again
oe_orphan:
        sd    zero, E_PID(s3)           ; reaped (or discarded)
oe_done:
        li    a0, 0                     ; answer the kernel
        li    a1, 0                     ; ...
        li    a2, 0                     ; ...
        call  unpark_reply              ; ...
        j     loop                      ; ...

; swap_pk() / unswap_pk(): keep pk and pktok aside while another parked request
; is answered (keeps t0)
swap_pk:
        la    t1, pk              ; (its address)
        ld    t1, 0(t1)              ; ...
        la    t2, svpk                  ; ...
        sd    t1, 0(t2)                 ; ...
        la    t1, pktok           ; (its address)
        ld    t1, 0(t1)              ; ...
        la    t2, svtok                 ; ...
        sd    t1, 0(t2)                 ; ...
        ret                             ; ...
unswap_pk:
        la    t1, svpk            ; (its address)
        ld    t1, 0(t1)              ; ...
        la    t2, pk                    ; ...
        sd    t1, 0(t2)                 ; ...
        la    t1, svtok           ; (its address)
        ld    t1, 0(t1)              ; ...
        la    t2, pktok                 ; ...
        sd    t1, 0(t2)                 ; ...
        ret                             ; ...

; orphans(a0 = pid): its children get no parent; finished ones are discarded
orphans:
        la    t0, procs                 ; ...
        li    t1, NPROC                 ; ...
or_l:
        beqz  t1, or_ret                ; ...
        ld    t2, E_PID(t0)             ; ...
        beqz  t2, or_n                  ; ...
        ld    t3, E_PARENT(t0)          ; ...
        bne   t3, a0, or_n              ; ...
        sd    zero, E_PARENT(t0)        ; ...
        ld    t3, E_STATE(t0)           ; ...
        li    t4, 4                     ; ...
        bne   t3, t4, or_n              ; ...
        sd    zero, E_PID(t0)           ; ...
or_n:
        addi  t0, t0, E_SIZE            ; ...
        addi  t1, t1, -1                ; ...
        j     or_l                      ; ...
or_ret:
        ret                             ; ...

