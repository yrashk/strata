; park(): the current request -> the kernel (pk, pktok) ; a0 = 0 / -1
park:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        call  srv_park                  ; ...
        la    t0, pk                    ; ...
        sd    a0, 0(t0)                 ; ...
        la    t1, srv_tok         ; (its address)
        ld    t1, 0(t1)              ; ...
        la    t0, pktok                 ; ...
        sd    t1, 0(t0)                 ; ...
        srai  a0, a0, 63                ; 0 / -1
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; unpark_reply(a0 = result, a1 = D-LS data or 0, a2 = data bytes): answer the parked request
unpark_reply:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        sd    a1, 16(sp)                ; ...
        sd    a2, 24(sp)                ; ...
        cclear c6                       ; (whatever is there)
        la    a0, pk              ; (its address)
        ld    a0, 0(a0)              ; ...
        call  srv_unpark                ; ...
        bnez  a0, ur_ret                ; its owner is gone
        la    t0, pktok           ; (its address)
        ld    t0, 0(t0)              ; its token
        la    t1, srv_tok               ; ...
        sd    t0, 0(t1)                 ; ...
        ld    a0, 16(sp)                ; data?
        beqz  a0, ur_rep                ; ...
        ld    a1, 24(sp)                ; ...
        call  srv_put                   ; ...
ur_rep:
        ld    a0, 8(sp)                 ; ...
        li    a1, 0                     ; ...
        call  srv_reply                 ; ...
ur_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; call(a0 = endpoint register, a1 = op, a2 = handle, a3 = length, a4 = mode) -> a0
; (sys_msg: the data must already be in the buffer)
call_ep:
        j     sys_msg                   ; ...

; free_arena(): the arena in c6 back to the kernel
free_arena:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        cvalid t0, c6                   ; anything?
        beqz  t0, fa_ret                ; ...
        csend c6, c1                    ; the arena first (an attachment) ...
        li    a0, 1                     ; ... then FREE
        li    a1, K_FREE                ; ...
        li    a2, 0                     ; ...
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        call  sys_msg                   ; ...
fa_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        ret                             ; ...

; srvcall(a0 = server register 2..4, a1 = op, a2 = handle): a request without data
srvcall:
        li    a3, 0                     ; ...
        li    a4, 0                     ; ...
        j     sys_msg                   ; ...

