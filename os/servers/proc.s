; =============================================================================
; proc.s: the process server (pid 1)
; =============================================================================
;
; The kernel creates proc first; proc holds the kernel's endpoint (c1) and is
; the only process that asks the kernel to create and destroy processes.
; Every other process is born with an endpoint to proc in its c1. proc keeps
; the process tree, exit statuses, interrupt flags and the name registry.
;
; At start (a0 = dev core | fs core << 8, a1 = dev pid | fs pid << 8 from the
; kernel) it starts the tty and pipe servers and then `sh -l` (pid of the
; login shell is remembered: when it ends, a new one starts).
;
;   5 SPAWN    data: u64 ncores, u64 h0, h1, h2 (handle descriptors: server
;              register << 32 | id, -1 none), "prog args\0"; length = text
;              length; mode bit0 = no server endpoints, bit1 = pin to core
;              mode >> 8 -> pid / -4 / -5 / -6
;   6 WAIT     handle = pid (0 = any child), mode bit0 = do not block ->
;              status, data[0] = pid; -3 still running; -2 interrupted; -1 no child
;   7 KILL     handle = pid -> 0     (from the kernel, op 7 is EXITED)
;   9 PS       -> count; 32-byte records (see os/lib/sys.s)
;  16 INFO     -> 0; data: cores, free heap, total, processes, kernel units
;              loaded, context switches, KiB moved
;  17 SIGNAL   handle = pid -> 0
;  22 CATCH    handle = 1 / 0 -> 0
;  25 LOOKUP   data = name -> 0 and an endpoint (in the caller's c6); -4
;  29 REGISTER data = name -> 0 (the entry dies with the process); -5 unless
;              the caller was started as its core's server (the boot servers,
;              and `ws`: SPAWN makes a program named `ws` its core's server,
;              on an empty core); -7 if another process holds the name
;  39 WHOIS    data = name -> the pid registered under it (0 for the boot
;              servers), -4 none (dev asks it before GRANT_FB: only "ws")
;  30 SCHED    handle 0: -> 0; data: u64 time slice (ticks), switches per second,
;              KiB moved per second (since the last SCHED read); handle 1: length =
;              the new slice (100..100000 ticks) -> 0 / -1 (forwarded to TUNE)
;  31 CORES    -> count; 32-byte records per core (see os/lib/sys.s)
;
; Spawning: MEMORY (an arena from the kernel, in a fresh revocation domain)
; -> the start-up block written into it -> fs LOADIMG (the image read into
; it) -> [old protocol: fs READALL of the `<` file] -> DUPS at the servers
; of the handles passed -> CREATE. While it waits for those answers, proc
; keeps the caller's request parked in the kernel.
;
; Exits: the kernel sends EXITED (handle = pid, length = status). proc tells
; the servers (CLEANUP: the process's handles are dropped), records the
; status for the parent's WAIT, and for an old-protocol program (bare metal,
; `> file`) appends its output (arena 0xC0000, exit code = length) to the file.
;
; Capability registers: c0 arena, c1 kernel, c2 fs, c3 tty, c4 pipe, c5 our
; message buffer, c6 the request / replies' attachments, c7 attachments.

K_CREATE = 1                            ; kernel operations
K_DESTROY = 2                           ; ...
K_MEMORY = 3                            ; ...
K_STATS  = 4                            ; ...
K_TUNE   = 5                            ; ...
K_NOTIFY = 9                            ; ...
K_FREE   = 6                            ; ...
K_EXITED = 7                            ; kernel -> proc
KF_SERVER = 2                           ; CREATE flags
KF_PRIV  = 8                            ; ...
KF_SOLO  = 32                           ; ...
KF_KEEP  = 64                           ; ...
A_START  = 0x7F000                      ; arena: start-up block
A_IN     = 0x80000                      ; arena: old-protocol input
A_OUT    = 0xC0000                      ; arena: old-protocol output
A_IMG    = 0xD0000                      ; arena: the image
IMG_MAX  = 0x20000                      ; its largest size
NPROC    = 32                           ; process records
E_PID    = 0                            ; record: pid (0 = free)
E_PARENT = 8                            ; parent pid
E_STATE  = 16                           ; 1 running, 4 zombie
E_STATUS = 24                           ; exit status
E_FLAGS  = 32                           ; EF_* below
E_CORE   = 40                           ; first core | cores << 8
E_OUTID  = 48                           ; old protocol: fs id of the output file
E_WAIT   = 56                           ; parked WAIT: park id + 1 | token << 8 | wanted pid << 32
E_NAME   = 64                           ; 16 bytes
E_SIZE   = 80                           ; ...
EF_CATCH = 1                            ; catches interrupts
EF_SERVER = 2                           ; a server
EF_EXCL  = 4                            ; threads on cores of its own window (bare metal, -n)
EF_OLDOUT = 8                           ; old-protocol output
EF_INTR  = 16                           ; an interrupt is pending
EF_LOGIN = 32                           ; the login shell
EF_USRV  = 64                           ; spawned as its core's server (`ws`): killable, may REGISTER
NREG     = 8                            ; names

        .data                           ; data Local Store
        .align 8                        ; ...
pad0:   .dword 0                        ; (keeps the table off address 0, which means "none")
procs:  .space NPROC * E_SIZE           ; the process table
names:  .space NREG * 16                ; registry: 8-byte name, core | pid << 8
nextpid: .dword 4                       ; next pid to try
mycore: .dword 0                        ; our core
devcore: .dword 0                       ; servers' cores
fscore: .dword 0                        ; ...
ttycore: .dword 255                     ; ...
pipecore: .dword 255                    ; ...
reqbuf: .space 512                      ; a SPAWN request's data
stbuf:  .space 512                      ; a start-up block being built
cdata:  .space 64                       ; CREATE data
dbuf:   .space 64                       ; DUPS data
img:    .space 32                       ; image header + first code word
stats:  .space 4096                     ; kernel STATS
outb:   .space 4096                     ; records being built
word:   .dword 0                        ; one word of reply data
sp_nc:  .dword 0                        ; spawn parameters: ncores
sp_mode: .dword 0                       ; mode
sp_kfl: .dword 0                        ; kernel flags
sp_eps: .dword 0                        ; endpoint cores
sp_par: .dword 0                        ; parent
sp_d:   .space 24                       ; handle descriptors
sp_cmd: .dword 0                        ; command line address
sp_clen: .dword 0                       ; its length
sp_pid: .dword 0                        ; the new pid
sp_nlen: .dword 0                       ; program name length
sp_a0:  .dword 0                        ; its a0, a1
sp_a1:  .dword 0                        ; ...
sp_ef:  .dword 0                        ; its proc flags
sp_out: .dword 0                        ; old protocol output id
pk:     .dword 0                        ; the parked request being worked on
pktok:  .dword 0                        ; its token
svpk:   .dword 0                        ; (kept aside)
svtok:  .dword 0                        ; ...
loginpid: .dword 0                      ; the login shell
slice:  .dword 2000                     ; the time slice (ticks), as last set
lnow:   .dword 0                        ; SCHED: NOW at the last read
lsw:    .dword 0                        ; SCHED: switches then
lkib:   .dword 0                        ; SCHED: KiB moved then
n_proc: .ascii "proc\0\0\0\0"           ; registry names (8 bytes each)
n_dev:  .ascii "dev\0\0\0\0\0"          ; ...
n_fs:   .ascii "fs\0\0\0\0\0\0"         ; ...
n_tty:  .ascii "tty\0\0\0\0\0"          ; ...
n_pipe: .ascii "pipe\0\0\0\0"           ; ...
c_tty:  .ascii "tty"                    ; command lines of what proc starts
c_pipe: .ascii "pipe"                   ; ...
c_sh:   .ascii "sh -l"                  ; ...

        .text                           ; instruction Local Store
_start:
        j     main                      ; skip the marker
        .word 0x32535953                ; "SYS2": a StrataOS 0.1 program
main:
        li    sp, 65536                 ; stack at the top of the D-LS
        mv    s1, a0                    ; dev core | fs core << 8
        mv    s2, a1                    ; dev pid | fs pid << 8
        call  sys_init                  ; ...
        csrr  t0, coreid                ; our core
        la    t1, mycore                ; ...
        sd    t0, 0(t1)                 ; ...
        andi  t0, s1, 255               ; dev's core
        la    t1, devcore               ; ...
        sd    t0, 0(t1)                 ; ...
        srli  t0, s1, 8                 ; fs's core
        andi  t0, t0, 255               ; ...
        la    t1, fscore                ; ...
        sd    t0, 0(t1)                 ; ...
        li    a0, 1                     ; the table: proc, dev, fs (made by the kernel)
        li    a1, 0                     ; ...
        la    a2, mycore          ; (its address)
        ld    a2, 0(a2)              ; ...
        la    a3, n_proc                ; ...
        call  addproc                   ; ...
        andi  a0, s2, 255               ; dev
        li    a1, 1                     ; ...
        la    a2, devcore         ; (its address)
        ld    a2, 0(a2)              ; ...
        la    a3, n_dev                 ; ...
        call  addproc                   ; ...
        srli  a0, s2, 8                 ; fs
        andi  a0, a0, 255               ; ...
        li    a1, 1                     ; ...
        la    a2, fscore          ; (its address)
        ld    a2, 0(a2)              ; ...
        la    a3, n_fs                  ; ...
        call  addproc                   ; ...
        la    a0, n_proc                ; and their names
        la    a1, mycore          ; (its address)
        ld    a1, 0(a1)              ; ...
        call  regname                   ; ...
        la    a0, n_dev                 ; ...
        la    a1, devcore         ; (its address)
        ld    a1, 0(a1)              ; ...
        call  regname                   ; ...
        la    a0, n_fs                  ; ...
        la    a1, fscore          ; (its address)
        ld    a1, 0(a1)              ; ...
        call  regname                   ; ...
        la    a0, c_tty                 ; tty: a server alone on its core,
        li    a1, 3                     ;   c1 proc, c2 dev
        li    a2, KF_SERVER | KF_SOLO   ; ...
        la    t0, devcore         ; (its address)
        ld    t0, 0(t0)              ; ...
        slli  t0, t0, 8                 ; ...
        la    t1, mycore          ; (its address)
        ld    t1, 0(t1)              ; ...
        or    a3, t0, t1                ; ...
        li    t0, 0xffff0000            ; ...
        or    a3, a3, t0                ; ...
        call  boot_spawn                ; a0 = core (its endpoint in c6)
        la    t1, ttycore               ; ...
        sd    a0, 0(t1)                 ; ...
        cclear c3                       ; c3 = tty
        cmov  c3, c6                    ; ...
        la    a0, n_tty                 ; ...
        la    a1, ttycore         ; (its address)
        ld    a1, 0(a1)              ; ...
        call  regname                   ; ...
        la    a0, c_pipe                ; pipe: a server, c1 proc
        li    a1, 4                     ; ...
        li    a2, KF_SERVER             ; ...
        la    t1, mycore          ; (its address)
        ld    t1, 0(t1)              ; ...
        li    t0, 0xffffff00            ; ...
        or    a3, t0, t1                ; ...
        call  boot_spawn                ; ...
        la    t1, pipecore              ; ...
        sd    a0, 0(t1)                 ; ...
        cclear c4                       ; c4 = pipe
        cmov  c4, c6                    ; ...
        la    a0, n_pipe                ; ...
        la    a1, pipecore        ; (its address)
        ld    a1, 0(a1)              ; ...
        call  regname                   ; ...
        call  start_sh                  ; and the login shell
        la    a0, loop                  ; a fault on a dead request returns to the loop
        call  srv_guard                 ; ...
loop:
        li    a0, 0                     ; requests only
        li    a1, -1                    ; ...
        call  srv_recv                  ; ...
        bltz  a0, loop                  ; ...
        la    t0, srv_hdr               ; dispatch
        ld    t1, 0(t0)                 ; op
        ld    t2, 40(t0)                ; from the kernel (pid 0)?
        bnez  t2, lp_proc               ; no
        li    t3, K_EXITED              ; EXITED
        beq   t1, t3, op_exited         ; ...
        li    a0, -1                    ; ...
        j     reply                     ; ...
lp_proc:
        li    t2, 5                     ; SPAWN
        beq   t1, t2, op_spawn          ; ...
        li    t2, 6                     ; WAIT
        beq   t1, t2, op_wait           ; ...
        li    t2, 7                     ; KILL
        beq   t1, t2, op_kill           ; ...
        li    t2, 9                     ; PS
        beq   t1, t2, op_ps             ; ...
        li    t2, 16                    ; INFO
        beq   t1, t2, op_info           ; ...
        li    t2, 17                    ; SIGNAL
        beq   t1, t2, op_signal         ; ...
        li    t2, 22                    ; CATCH
        beq   t1, t2, op_catch          ; ...
        li    t2, 25                    ; LOOKUP
        beq   t1, t2, op_lookup         ; ...
        li    t2, 29                    ; REGISTER
        beq   t1, t2, op_register       ; ...
        li    t2, 30                    ; SCHED
        beq   t1, t2, op_sched          ; ...
        li    t2, 31                    ; CORES
        beq   t1, t2, op_cores          ; ...
        li    t2, 39                    ; WHOIS
        beq   t1, t2, op_whois          ; ...
        li    a0, -1                    ; unknown
reply:
        li    a1, 0                     ; ...
        call  srv_reply                 ; ...
        j     loop                      ; ...

