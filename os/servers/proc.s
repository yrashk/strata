op_kill:
        la    t0, srv_hdr               ; the target
        ld    s1, 8(t0)                 ; ...
        li    t0, 3                     ; never proc, dev, fs
        bleu  s1, t0, ok_bad            ; ...
        mv    a0, s1                    ; ...
        call  findp                     ; ...
        beqz  a0, ok_bad                ; ...
        ld    t0, E_STATE(a0)           ; already finished
        li    t1, 4                     ; ...
        beq   t0, t1, ok_zero           ; ...
        call  park                      ; ...
        li    a0, 1                     ; DESTROY
        li    a1, K_DESTROY             ; ...
        mv    a2, s1                    ; ...
        call  srvcall                   ; ...
        li    a1, 0                     ; ...
        li    a2, 0                     ; ...
        call  unpark_reply              ; (the kernel's result)
        j     loop                      ; ...
ok_bad:
        li    a0, -1                    ; ...
        j     reply                     ; ...
ok_zero:
        li    a0, 0                     ; ...
        j     reply                     ; ...

op_signal:
        la    t0, srv_hdr               ; the target
        ld    s1, 8(t0)                 ; ...
        mv    a0, s1                    ; ...
        call  findp                     ; ...
        beqz  a0, ok_bad                ; ...
        mv    s2, a0                    ; ...
        ld    t0, E_STATE(s2)           ; finished already
        li    t1, 4                     ; ...
        beq   t0, t1, ok_zero           ; ...
        ld    t0, E_FLAGS(s2)           ; catches interrupts?
        andi  t1, t0, EF_CATCH          ; ...
        bnez  t1, os_catch              ; ...
        andi  t1, t0, EF_SERVER         ; servers are not killed this way
        bnez  t1, ok_bad                ; ...
        li    t1, 3                     ; ...
        bleu  s1, t1, ok_bad            ; ...
        j     op_kill                   ; no: it dies (the same as KILL)
os_catch:
        call  park                      ; the caller's request waits
        ld    t0, E_WAIT(s2)            ; blocked in WAIT here?
        beqz  t0, os_pend               ; ...
        sd    zero, E_WAIT(s2)          ; answer it -2
        call  swap_pk                   ; (our own parked request aside)
        andi  t1, t0, 255               ; its park id + 1
        addi  t1, t1, -1                ; ...
        la    t2, pk                    ; ...
        sd    t1, 0(t2)                 ; ...
        srli  t1, t0, 8                 ; its token
        li    t4, 0xffffff              ; ...
        and   t1, t1, t4                ; ...
        la    t2, pktok                 ; ...
        sd    t1, 0(t2)                 ; ...
        li    a0, -2                    ; interrupted
        li    a1, 0                     ; ...
        li    a2, 0                     ; ...
        call  unpark_reply              ; ...
        call  unswap_pk                 ; ours back
        j     os_tell                   ; ...
os_pend:
        ld    t0, E_FLAGS(s2)           ; not in WAIT: remember it for the next WAIT
        ori   t0, t0, EF_INTR           ; ...
        sd    t0, E_FLAGS(s2)           ; ...
os_tell:
        li    a0, 3                     ; tty: its waiting reads return -2
        li    a1, OP_CANCEL             ; ...
        mv    a2, s1                    ; ...
        call  srvcall                   ; ...
        li    a0, 4                     ; pipe: the same
        li    a1, OP_CANCEL             ; ...
        mv    a2, s1                    ; ...
        call  srvcall                   ; ...
        li    a0, 1                     ; the kernel: a notification (wakes a sleep)
        li    a1, K_NOTIFY              ; ...
        mv    a2, s1                    ; ...
        li    a3, 1                     ; bit 0: interrupt
        li    a4, 0                     ; ...
        call  sys_msg                   ; ...
        li    a0, 0                     ; ...
        li    a1, 0                     ; ...
        li    a2, 0                     ; ...
        call  unpark_reply              ; ...
        j     loop                      ; ...

op_catch:
        call  srv_pid                   ; the caller's record
        call  findp                     ; ...
        beqz  a0, ok_bad                ; ...
        ld    t0, E_FLAGS(a0)           ; ...
        andi  t0, t0, 0xfffe            ; ...
        la    t1, srv_hdr               ; ...
        ld    t2, 8(t1)                 ; ...
        snez  t2, t2                    ; ...
        or    t0, t0, t2                ; ...
        sd    t0, E_FLAGS(a0)           ; ...
        j     ok_zero                   ; ...

