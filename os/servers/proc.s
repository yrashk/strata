op_lookup:
        call  getname8                  ; ...
        beqz  a0, ol_none               ; ...
        la    t0, names                 ; ...
        li    t1, NREG                  ; ...
ol_l:
        beqz  t1, ol_none               ; ...
        ld    t2, 0(t0)                 ; ...
        beq   t2, a0, ol_yes            ; ...
        addi  t0, t0, 16                ; ...
        addi  t1, t1, -1                ; ...
        j     ol_l                      ; ...
ol_yes:
        ld    a2, 8(t0)                 ; its core: the kernel mints an endpoint with the reply
        andi  a2, a2, 255               ; (the pid above it stays here)
        li    a0, 0                     ; ...
        li    a1, 2                     ; ...
        call  srv_reply                 ; ...
        j     loop                      ; ...
ol_none:
        li    a0, -4                    ; ...
        j     reply                     ; ...

op_register:
        call  getname8                  ; ...
        beqz  a0, ok_bad                ; ...
        mv    s1, a0                    ; ...
        call  srv_pid                   ; the caller's core
        call  findp                     ; ...
        beqz  a0, ok_bad                ; ...
        ld    t0, E_FLAGS(a0)           ; only a process started as its core's server
        andi  t0, t0, EF_SERVER | EF_USRV ; (requests to the name go to that core's server)
        beqz  t0, org_deny              ; ...
        la    t0, names                 ; and not a name another process holds
        li    t1, NREG                  ; ...
org_l:
        beqz  t1, org_free              ; ...
        ld    t2, 0(t0)                 ; ...
        bne   t2, s1, org_n             ; ...
        ld    t2, 8(t0)                 ; held: by the caller itself?
        srli  t2, t2, 8                 ; ...
        ld    t3, E_PID(a0)             ; ...
        bne   t2, t3, org_busy          ; no
org_n:
        addi  t0, t0, 16                ; ...
        addi  t1, t1, -1                ; ...
        j     org_l                     ; ...
org_deny:
        li    a0, -5                    ; not permitted
        j     reply                     ; ...
org_busy:
        li    a0, -7                    ; busy
        j     reply                     ; ...
org_free:
        ld    a1, E_CORE(a0)            ; ...
        andi  a1, a1, 255               ; ...
        ld    t0, E_PID(a0)             ; and its pid above the core (WHOIS)
        slli  t0, t0, 8                 ; ...
        or    a1, a1, t0                ; ...
        la    a0, word                  ; ...
        sd    s1, 0(a0)                 ; ...
        call  regname                   ; ...
        j     ok_zero                   ; ...

op_whois:
        call  getname8                  ; ...
        beqz  a0, ol_none               ; ...
        la    t0, names                 ; ...
        li    t1, NREG                  ; ...
ow_l:
        beqz  t1, ol_none               ; ...
        ld    t2, 0(t0)                 ; ...
        beq   t2, a0, ow_yes            ; ...
        addi  t0, t0, 16                ; ...
        addi  t1, t1, -1                ; ...
        j     ow_l                      ; ...
ow_yes:
        ld    a0, 8(t0)                 ; the pid (0: a boot server)
        srli  a0, a0, 8                 ; ...
        j     reply                     ; ...

; unregpid(a0 = pid): drop the registry entries of a process that ended
unregpid:
        beqz  a0, urp_ret               ; (boot servers have pid 0 there)
        la    t0, names                 ; ...
        li    t1, NREG                  ; ...
urp_l:
        beqz  t1, urp_ret               ; ...
        ld    t2, 8(t0)                 ; ...
        srli  t2, t2, 8                 ; ...
        bne   t2, a0, urp_n             ; ...
        sd    zero, 0(t0)               ; free the entry
        sd    zero, 8(t0)               ; ...
urp_n:
        addi  t0, t0, 16                ; ...
        addi  t1, t1, -1                ; ...
        j     urp_l                     ; ...
urp_ret:
        ret                             ; ...

