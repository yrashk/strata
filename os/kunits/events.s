; =============================================================================
; kunits/events.s: exits, EXITED messages to proc, preemption ticks (units)
; =============================================================================

OP_EXITED = 7                           ; kernel -> proc: handle = pid, length = status

; ---- u_events(a0 = core): read that worker's exit events ------------------------------------
        .align 2048                     ; a unit of its own
u_events:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        mv    s1, a0                    ; s1 = the core
        slli  s2, s1, 10                ; s2 = its KST area
        addi  s2, s2, CAREA             ; ...
uev_l:
        addi  a0, s2, CA_TAIL           ; written
        la    t6, kst_rd                ; ...
        jalr  ra, t6, 0                 ; ...
        mv    s3, a0                    ; ...
        addi  a0, s2, CA_HEAD           ; read
        la    t6, kst_rd                ; ...
        jalr  ra, t6, 0                 ; ...
        bgeu  a0, s3, uev_done          ; all read
        andi  t0, a0, 7                 ; the entry
        slli  t0, t0, 4                 ; ...
        add   s4, s2, t0                ; ...
        addi  a0, s4, CA_RING           ; pid
        la    t6, kst_rd                ; ...
        jalr  ra, t6, 0                 ; ...
        sd    a0, k_evpid-GPBASE(gp)    ; ...
        addi  a0, s4, CA_RING + 8       ; status
        la    t6, kst_rd                ; ...
        jalr  ra, t6, 0                 ; ...
        sd    a0, k_evst-GPBASE(gp)     ; ...
        addi  a0, s2, CA_HEAD           ; consumed
        li    a1, 1                     ; ...
        la    t6, kst_add               ; ...
        jalr  ra, t6, 0                 ; ...
        mv    a0, s1                    ; handle it
        la    t5, u_exit1               ; ...
        xcall ra, c12, t5               ; ...
        j     uev_l                     ; ...
uev_done:
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        xret  ra                        ; ...
        .org  u_events + 2048           ; (the unit must fit its slot)

; ---- u_exit1(a0 = core): one core of process k_evpid ended with status k_evst ---------------
u_exit1:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        mv    s1, a0                    ; s1 = the core
        ld    a0, k_evpid-GPBASE(gp)    ; its record
        la    t6, kp_find               ; ...
        jalr  ra, t6, 0                 ; ...
        beqz  a0, ue1_ret               ; unknown: nothing to do
        mv    s2, a0                    ; s2 = record
        ld    t0, k_evst-GPBASE(gp)     ; the status
        li    t1, 1                     ; killed?
        slli  t1, t1, 62                ; ...
        ld    t2, KP_STAT(s2)           ; ...
        ld    t3, KP_CORE(s2)           ; from its first core: the process's status
        bne   t3, s1, ue1_other         ; ...
        and   t2, t2, t1                ; (keep a kill another core reported)
        or    t2, t2, t0                ; ...
        sd    t2, KP_STAT(s2)           ; ...
        j     ue1_core                  ; ...
ue1_other:
        and   t4, t0, t1                ; another core: only a kill counts
        or    t2, t2, t4                ; ...
        sd    t2, KP_STAT(s2)           ; ...
ue1_core:
        slli  t6, s1, 4                 ; the core's slot is free
        ld    t0, KP_SLOT(s2)           ; (this thread's: 4 bits each)
        ld    t1, KP_CORE(s2)           ; ...
        sub   t1, s1, t1                ; ...
        slli  t1, t1, 2                 ; ...
        srl   t0, t0, t1                ; ...
        andi  t0, t0, 15                ; ...
        li    t1, 1                     ; ...
        sll   t1, t1, t0                ; ...
        sub   t1, zero, t1     ; invert every bit: -x
        addi   t1, t1, -1              ; ... - 1
        ld    t2, K0_CORE(t6)           ; ...
        and   t2, t2, t1                ; ...
        sd    t2, K0_CORE(t6)           ; ...
        ld    t0, KP_FLAGS(s2)          ; a server / solo process leaves
        andi  t0, t0, F_SERVER | F_SOLO ; ...
        beqz  t0, ue1_left              ; ...
        ld    t1, K0_CORE+8(t6)         ; ...
        andi  t1, t1, 0xf9              ; (one per core: its flags go)
        sd    t1, K0_CORE+8(t6)         ; ...
ue1_left:
        ld    t0, KP_LEFT(s2)           ; one core fewer
        addi  t0, t0, -1                ; ...
        sd    t0, KP_LEFT(s2)           ; ...
        beqz  t0, ue1_fin               ; all done
        ld    t1, k_evst-GPBASE(gp)     ; others still run: a fault or a kill on one core
        srli  t1, t1, 62                ;   ends the whole gang (the others may wait for
        beqz  t1, ue1_ret               ;   it forever)
        ld    a0, KP_PID(s2)            ; ...
        la    t5, u_destroy             ; ...
        xcall ra, c12, t5               ; ...
        j     ue1_ret                   ; ...
ue1_fin:
        mv    a0, s2                    ; all done: dissolve it
        la    t5, u_finish              ; ...
        xcall ra, c12, t5               ; ...
ue1_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        xret  ra                        ; ...
        .org  u_exit1 + 2048            ; (the unit must fit its slot)

; ---- u_finish(a0 = record): revoke the arena, free it, queue EXITED -------------------------
u_finish:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        mv    s1, a0                    ; s1 = record
        ld    t0, KP_PID(s1)            ; proc itself died: nothing can go on
        li    t1, 1                     ; ...
        beq   t0, t1, ufi_fatal         ; ...
        ld    t0, KP_PID(s1)            ; the framebuffer's holder? revoke it
        ld    t1, k_fbpid-GPBASE(gp)    ; (everything cut from it dies too)
        bne   t0, t1, ufi_nofb          ; ...
        sd    zero, k_fbpid-GPBASE(gp)  ; ...
        li    a0, K_FB                  ; ...
        la    t6, crs8                  ; ...
        jalr  ra, t6, 0                 ; ...
        cclear c9                       ; ...
        crevoke c9, c8                  ; ...
        cclear c9                       ; (the next FBLEND makes a fresh one)
        li    a0, K_FB                  ; the revoker back
        la    t6, csv8                  ; ...
        jalr  ra, t6, 0                 ; ...
ufi_nofb:
        ld    s2, KP_ASLOT(s1)          ; s2 = its arena slot
        mv    a0, s2                    ; revoke it: every capability based in it dies,
        la    t5, u_arcap               ;   whoever holds it (buffers lent to servers,
        xcall ra, c12, t5               ;   ws bands, block-device buffers)
        cclear c13                      ; (the fresh one is not needed now)
        li    s3, 0                     ; its cores may forget it now (vcore s3)
ufi_fr:
        ld    t0, KP_N(s1)              ; ...
        bge   s3, t0, ufi_frd           ; ...
        ld    t0, KP_CORE(s1)           ; that core's CA_FREE: the slot's bit
        add   t0, t0, s3                ; ...
        slli  a0, t0, 10                ; ...
        addi  a0, a0, CAREA + CA_FREE   ; ...
        ld    t1, KP_SLOT(s1)           ; (this thread's slot)
        slli  t2, s3, 2                 ; ...
        srl   t1, t1, t2                ; ...
        andi  t1, t1, 15                ; ...
        li    a1, 1                     ; ...
        sll   a1, a1, t1                ; ...
        la    t6, kst_or                ; ...
        jalr  ra, t6, 0                 ; ...
        addi  s3, s3, 1                 ; ...
        j     ufi_fr                    ; ...
ufi_frd:
        ld    t3, KP_FLAGS(s1)          ; kept for proc, or free?
        andi  t3, t3, F_KEEP            ; ...
        beqz  t3, ufi_free              ; ...
        slli  t1, s2, 5                 ; kept: goes to proc with EXITED
        li    t2, K0_AR                 ; ...
        add   t1, t1, t2                ; ...
        li    t3, 3                     ; ...
        sd    t3, AR_STATE(t1)          ; ...
        mv    a0, s2                    ; no owner now
        li    a1, 0                     ; ...
        la    t5, u_own                 ; ...
        xcall ra, c12, t5               ; ...
        li    s3, 256                   ; (flag in the queue entry)
        j     ufi_q                     ; ...
ufi_free:
        mv    a0, s2                    ; free: its granules go back to the pool
        la    t5, u_arfree              ; ...
        xcall ra, c12, t5               ; ...
        li    s3, 0                     ; ...
ufi_q:
        ld    t0, k_outn-GPBASE(gp)     ; queue EXITED: pid, status, arena slot | keep
        li    t1, 10                    ; (at most 10 waiting)
        bgeu  t0, t1, ufi_rec           ; ...
        li    t1, 24                    ; 24 bytes per entry
        mul   t1, t0, t1                ; ...
        li    t2, K0_OUTQ               ; ...
        add   t1, t1, t2                ; ...
        ld    t2, KP_PID(s1)            ; ...
        sd    t2, 0(t1)                 ; ...
        ld    t2, KP_STAT(s1)           ; ...
        sd    t2, 8(t1)                 ; ...
        or    t2, s2, s3                ; ...
        sd    t2, 16(t1)                ; ...
        addi  t0, t0, 1                 ; ...
        sd    t0, k_outn-GPBASE(gp)     ; ...
ufi_rec:
        sd    zero, KP_PID(s1)          ; the record is free
        la    t5, u_sendexit            ; send what can be sent
        xcall ra, c12, t5               ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        xret  ra                        ; ...
ufi_fatal:
        la    a0, s_procdied            ; "proc died"
        li    a1, s_procdied_e - s_procdied ; ...
        la    t6, k_fputs               ; ...
        jalr  ra, t6, 0                 ; ...
        la    t5, u_halt                ; the machine stops
        xcall ra, c12, t5               ; ...
s_procdied: .ascii "\nStrataOS: proc (pid 1) ended; stopping.\n"
s_procdied_e:
        .org  u_finish + 2048           ; (the unit must fit its slot)

; ---- u_sendexit: send queued EXITED messages while message buffers are home -------------------
u_sendexit:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
use_l:
        ld    t0, k_outn-GPBASE(gp)     ; anything to send?
        beqz  t0, use_done              ; ...
        ld    t1, k_msgfree-GPBASE(gp)  ; a buffer at home?
        beqz  t1, use_done              ; not now (a reply will bring one back)
        li    s1, 0                     ; the lowest
use_f:
        andi  t2, t1, 1                 ; ...
        bnez  t2, use_take              ; ...
        srli  t1, t1, 1                 ; ...
        addi  s1, s1, 1                 ; ...
        j     use_f                     ; ...
use_take:
        li    t0, 1                     ; not home any more
        sll   t0, t0, s1                ; ...
        ld    t1, k_msgfree-GPBASE(gp)  ; ...
        xor   t1, t1, t0                ; ...
        sd    t1, k_msgfree-GPBASE(gp)  ; ...
        addi  a0, s1, K_MSG             ; the buffer -> c9
        la    t6, crs8                  ; ...
        jalr  ra, t6, 0                 ; ...
        cclear c9                       ; ...
        cmov  c9, c8                    ; ...
        li    t0, K0_OUTQ               ; the oldest entry
        ld    s2, 16(t0)                ; arena slot | keep
        la    t1, k_hdr2                ; header: EXITED, pid, status
        li    t2, OP_EXITED             ; ...
        sd    t2, 0(t1)                 ; ...
        ld    t2, 0(t0)                 ; ...
        sd    t2, 8(t1)                 ; ...
        ld    t2, 8(t0)                 ; ...
        sd    t2, 16(t1)                ; ...
        sd    zero, 24(t1)              ; ...
        sd    zero, 32(t1)              ; ...
        sd    zero, 40(t1)              ; ...
        li    t2, 64                    ; ...
        tput  tg0, t1, c9, zero, t2     ; ...
        twait 1                         ; ...
        ld    t0, k_outn-GPBASE(gp)     ; pop the queue
        addi  t0, t0, -1                ; ...
        sd    t0, k_outn-GPBASE(gp)     ; ...
        li    t1, K0_OUTQ               ; (move the rest down)
        li    t2, 0                     ; ...
use_mv:
        bge   t2, t0, use_mvd           ; ...
        ld    t3, 24(t1)                ; ...
        sd    t3, 0(t1)                 ; ...
        ld    t3, 32(t1)                ; ...
        sd    t3, 8(t1)                 ; ...
        ld    t3, 40(t1)                ; ...
        sd    t3, 16(t1)                ; ...
        addi  t1, t1, 24                ; ...
        addi  t2, t2, 1                 ; ...
        j     use_mv                    ; ...
use_mvd:
        ld    s1, k_proccore-GPBASE(gp) ; to proc's core
        andi  t0, s2, 256               ; the arena goes first?
        beqz  t0, use_send              ; ...
        andi  a0, s2, 255               ; a fresh capability for it (c13)
        la    t5, u_arcap               ; ...
        xcall ra, c12, t5               ; ...
        cgive c13, s1                   ; an attachment
        andi  t0, s2, 255               ; now with proc
        slli  t0, t0, 5                 ; ...
        li    t1, K0_AR                 ; ...
        add   t1, t1, t0                ; ...
        li    t2, 4                     ; ...
        sd    t2, AR_STATE(t1)          ; ...
use_send:
        cgive c9, s1                    ; the message
        mv    a0, s1                    ; wake proc's core
        la    t6, k_ring                ; ...
        jalr  ra, t6, 0                 ; ...
        j     use_l                     ; ...
use_done:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        xret  ra                        ; ...
        .org  u_sendexit + 2048         ; (the unit must fit its slot)

; ---- u_kreply(a0 = core): one of core 0's message buffers came back (in c8) ----------------
u_kreply:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        mv    s1, a0                    ; ...
        cbase t0, c8                    ; which buffer
        li    t1, MSGB                  ; ...
        sub   t0, t0, t1                ; ...
        srli  t0, t0, 12                ; ...
        sd    t0, k_tmpi-GPBASE(gp)     ; ...
        addi  a0, t0, K_MSG             ; home
        la    t6, csv8                  ; ...
        jalr  ra, t6, 0                 ; ...
        ld    t0, k_tmpi-GPBASE(gp)     ; ...
        li    t1, 1                     ; ...
        sll   t1, t1, t0                ; ...
        ld    t2, k_msgfree-GPBASE(gp)  ; ...
        or    t2, t2, t1                ; ...
        sd    t2, k_msgfree-GPBASE(gp)  ; ...
ukr_att:
        mv    a0, s1                    ; attachments with it are not expected: drop them
        la    t6, k_unstash             ; ...
        jalr  ra, t6, 0                 ; ...
        bnez  a0, ukr_q                 ; none
        cclear c8                       ; ...
        j     ukr_att                   ; ...
ukr_q:
        la    t5, u_sendexit            ; maybe something was waiting for a buffer
        xcall ra, c12, t5               ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        xret  ra                        ; ...
        .org  u_kreply + 2048           ; (the unit must fit its slot)

; ---- u_tick: every time slice: preempt crowded cores (never a core with one runnable), wake expired timed waits, re-arm -------------
u_tick:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        ld    s3, k_tbuf+16-GPBASE(gp)  ; NOW, as the WAIT returned it
        li    s1, 1                     ; every worker
uti_l:
        ld    t0, w_ncores-GPBASE(gp)   ; ...
        bge   s1, t0, uti_arm           ; ...
        slli  s2, s1, 10                ; its KST area
        addi  s2, s2, CAREA             ; ...
        li    a0, 0                     ; a thread waits for a gift while another runs:
        ld    t0, k_gwacc-GPBASE(gp)    ;   stop that core (at most every 10 ms) so that
        li    t1, GIFTPOLL              ;   its dispatcher looks at its inbox (an idle
        bltu  t0, t1, uti_nogw          ;   core wakes on its inbox itself)
        addi  a0, s2, CA_GIFTW          ; ...
        la    t6, kst_rd                ; ...
        jalr  ra, t6, 0                 ; ...
uti_nogw:
        sd    a0, k_tmpi-GPBASE(gp)     ; ...
        addi  a0, s2, CA_RUN            ; more than one runnable: preempt
        la    t6, kst_rd                ; ...
        jalr  ra, t6, 0                 ; ...
        li    t0, 1                     ; ...
        bgt   a0, t0, uti_ring          ; ...
        beqz  a0, uti_dl                ; nothing runs: nothing to stop
        ld    t0, k_tmpi-GPBASE(gp)     ; one runs, and a thread waits for a gift
        beqz  t0, uti_dl                ; ...
uti_ring:
        mv    a0, s1                    ; the stop makes its dispatcher switch
        la    t6, k_ring                ; ...
        jalr  ra, t6, 0                 ; ...
        j     uti_dl                    ; ...
uti_gw:
uti_dl:
        addi  a0, s2, CA_DEADL          ; a timed wait due?
        la    t6, kst_rd                ; ...
        jalr  ra, t6, 0                 ; ...
        beqz  a0, uti_n                 ; none
        bltu  s3, a0, uti_n             ; not yet
        mv    a0, s1                    ; wake it (it may be idle)
        la    t6, k_wake                ; ...
        jalr  ra, t6, 0                 ; ...
uti_n:
        addi  s1, s1, 1                 ; ...
        j     uti_l                     ; ...
uti_arm:
        ld    t0, k_gwacc-GPBASE(gp)    ; time towards the next gift poll
        li    t1, GIFTPOLL              ; ...
        bltu  t0, t1, uti_acc           ; ...
        li    t0, 0                     ; (polled this time)
uti_acc:
        ld    t1, k_slice-GPBASE(gp)    ; ...
        add   t0, t0, t1                ; ...
        sd    t0, k_gwacc-GPBASE(gp)    ; ...
        la    t5, u_arm                 ; the next tick
        xcall ra, c12, t5               ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        xret  ra                        ; ...
        .org  u_tick + 2048             ; (the unit must fit its slot)
