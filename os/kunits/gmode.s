; =============================================================================
; kunits/gmode.s: guest mode -- StrataOS as a guest of StrataOS (code units)
; =============================================================================
;
; Booted by a host StrataOS's `guest -p` (os/kunits/guest.s), the kernel finds,
; instead of what the boot ROM gives, what a guest gets: its memory, an
; endpoint to the host's tty, the clock (NOW and FREQ, read-only) and core
; control over its own cores (kentry tells the two apart by c3: core control
; over cores 8 * corebase.. is not the device root, which is at 0). It has no
; device of its own: no timer to wait on, no disk, no console port, no
; framebuffer. k0_guest (resident) and u_k0init put what it got where the boot
; ROM's would be; then these units stand in for the devices:
;   * the time slice: core 0 polls its inbox and the clock (u_gwait) instead
;     of waiting on the timer's WAIT (u_arm sets k_tdead instead of DEADLINE);
;   * the disk: a RAM disk, a section of the guest image that the host's loader
;     copied to RD_OFF in its memory. The kernel reads the boot manifest and
;     the first servers from it (u_blkrd); dev hands it to fs (GDISK), whose
;     blocks it then is;
;   * the console: dev hands tty the host's tty endpoint (GCON), and tty passes
;     its programs' reads and writes on (os/servers/tty.s); the kernel's own
;     few lines go the same way (u_puts);
;   * revocation: the pool of arenas lies in a range of the guest's memory that
;     the host made into units of their own (u_gpool); we cannot cdom (our
;     memory is revocable already), so the host revokes ranges of it for us
;     (u_ghrev).
; Core numbers stay ours (relative to the guest's window: corebase, corecount)
; everywhere but in endpoints, which name physical nodes: the dispatcher adds
; corebase when it mints one for a core of ours and takes it off when it
; reads one (w_cbase; see "Guest mode" in kernel.s).

k_gmsg   = K0_BOUNCE                    ; a message to the host being built (core 0 waits for
                                        ;   each answer: nothing else uses the bounce buffer then)

; ---- u_gwait -> a0 = 1 << 16 (something in the inbox) or 1 << TG_TMR (a tick due) --------
; Core 0 of a guest: what k_loop's tany waits for, by looking.
        .align 2048
u_gwait:
        cpoll t0                        ; anything from our cores?
        bnez  t0, ugw_in                ; ...
        ld    t0, k_tarmed-GPBASE(gp)   ; a tick armed?
        beqz  t0, u_gwait               ; ...
        la    t1, k_tbuf                ; NOW (c3: the clock)
        li    t2, 8                     ; ...
        tget  tg0, t1, c3, zero, t2     ; ...
        ld    t2, 0(t1)                 ; (waits for it)
        ld    t3, k_tdead-GPBASE(gp)    ; due?
        bltu  t2, t3, u_gwait           ; not yet
        li    a0, 1 << TG_TMR           ; ...
        xret  ra                        ; ...
ugw_in:
        li    a0, 1                     ; ...
        slli  a0, a0, 16                ; ...
        xret  ra                        ; ...
        .org  u_gwait + 2048            ; (the unit must fit its slot)

; ---- u_ghrev(a0 = base, a1 = bytes) -> c13 = a fresh capability for the range -------------
; The host revokes a range of our pool (u_ggift, GH_REVOKE): our last message
; buffer, kept for this and for the console (u_puts), carries the request; the
; host answers with the fresh capability and then the buffer (the buffer alone:
; refused, and c13 stays empty). Uses c13, c14, c15.
        .align 2048
u_ghrev:
        ld    t0, k_pbase-GPBASE(gp)    ; the range's offset in the pool
        sub   t1, a0, t0                ; ...
        la    t2, k_gmsg                ; the request: op, offset, bytes
        li    t3, GH_REVOKE             ; ...
        sd    t3, 0(t2)                 ; ...
        sd    t1, 8(t2)                 ; ...
        sd    a1, 16(t2)                ; ...
        cclear c13                      ; ...
        cclear c14                      ; c14 = the buffer
        crestore c14, K_MSG + NMSGB - 1 ; ...
        li    t3, 24                    ; ...
        tput  tg0, t2, c14, zero, t3    ; ...
        twait 1                         ; ...
        cbase t4, c14                   ; (to tell it from the answer)
        cclear c15                      ; c15 = an endpoint to the host's core 0
        cmkep c15, zero                 ; ...
        csend c14, c15                  ; ...
        crecv c13, c15                  ; the fresh capability (or the buffer: refused)
        cbase t0, c13                   ; ...
        beq   t0, t4, ughr_no           ; ...
        crecv c14, c15                  ; the buffer back
        j     ughr_ret                  ; ...
ughr_no:
        cmov  c14, c13                  ; (moves it: c13 is empty)
ughr_ret:
        csave c14, K_MSG + NMSGB - 1    ; ...
        cclear c15                      ; ...
        xret  ra                        ; ...
        .org  u_ghrev + 2048            ; (the unit must fit its slot)

; ---- u_puts(a0 = far address, a1 = length <= 240): print text kept in the far image ------
; (u_putdec, below, prints a number; u_gclose closes the console)
; k_fputs, or for a guest a WRITE to the host's tty (with the buffer u_ghrev
; uses: only core 0 sends with it, one request at a time, and the host's tty
; answers every WRITE). Uses c13, c14.
        .align 2048
u_puts:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        ld    t0, k_guest-GPBASE(gp)    ; a guest?
        bnez  t0, upu_g                 ; ...
        la    t6, k_fputs               ; no: the console
        jalr  ra, t6, 0                 ; ...
        j     upu_ret                   ; ...
upu_g:
        li    a6, 2                     ; a6 = WRITE
        srli  t2, a0, 3                 ; the text's words -> k_fbuf
        slli  t2, t2, 3                 ; ...
        sub   t3, a0, t2                ; t3 = where in them it begins
        add   t1, a1, t3                ; ...
        addi  t1, t1, 7                 ; ...
        srli  t1, t1, 3                 ; ...
        slli  t1, t1, 3                 ; ...
        la    t0, k_fbuf                ; ...
        tget  tg0, t0, c12, t2, t1      ; ...
        twait 1                         ; ...
        add   t0, t0, t3                ; t0 = the text in the D-LS, a1 = its length
upu_send:
        la    t4, k_gmsg                ; -> k_gmsg + 64, a byte at a time
        addi  t4, t4, 64                ; ...
        li    t5, 0                     ; ...
upu_cp:
        bgeu  t5, a1, upu_hdr           ; ...
        add   t6, t0, t5                ; ...
        lbu   t6, 0(t6)                 ; ...
        add   t2, t4, t5                ; ...
        sb    t6, 0(t2)                 ; ...
        addi  t5, t5, 1                 ; ...
        j     upu_cp                    ; ...
upu_hdr:
        la    t2, k_gmsg                ; the header: a6 (WRITE, CLOSE), the console, the length
        sd    a6, 0(t2)                 ; ...
        sd    zero, 8(t2)               ; ...
        sd    a1, 16(t2)                ; ...
        sd    zero, 24(t2)              ; ...
        sd    zero, 32(t2)              ; ...
        addi  t3, a1, 64 + 7            ; header and text, whole words
        srli  t3, t3, 3                 ; ...
        slli  t3, t3, 3                 ; ...
        cclear c13                      ; c13 = the buffer
        crestore c13, K_MSG + NMSGB - 1 ; ...
        tput  tg0, t2, c13, zero, t3    ; ...
        twait 1                         ; ...
        cclear c14                      ; c14 = the host's tty (copyable: the slot keeps it)
        crestore c14, K_GCON            ; ...
        csend c13, c14                  ; ...
        crecv c13, c14                  ; its answer: the buffer back
        csave c13, K_MSG + NMSGB - 1    ; ...
        cclear c14                      ; ...
upu_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        xret  ra                        ; ...

; u_putdec(a0 = unsigned value): fw_putdec, or for a guest the same WRITE
u_putdec:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        ld    t0, k_guest-GPBASE(gp)    ; a guest?
        bnez  t0, upd_g                 ; ...
        la    t6, fw_putdec             ; no: the console
        jalr  ra, t6, 0                 ; ...
        j     upu_ret                   ; ...
upd_g:
        li    a6, 2                     ; a6 = WRITE
        la    t0, k_fbuf + 32           ; the digits, from the last
        li    a1, 0                     ; a1 = how many
        li    t2, 10                    ; ...
upd_l:
        remu  t3, a0, t2                ; ...
        divu  a0, a0, t2                ; ...
        addi  t3, t3, '0'               ; ...
        addi  t0, t0, -1                ; ...
        sb    t3, 0(t0)                 ; ...
        addi  a1, a1, 1                 ; ...
        bnez  a0, upd_l                 ; ...
        j     upu_send                  ; t0 = them, a1 = how many

; u_gclose(): a guest that halts closes the host's console (a CLOSE to its tty):
; the console comes back to the host's shell, as after Forth's BYE
u_gclose:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        li    a1, 0                     ; no text
        li    a6, 4                     ; CLOSE
        j     upu_send                  ; ...
        .org  u_puts + 2048             ; (the unit must fit its slot)

; ---- u_blkrd(a0 = first block, a1 = blocks, a2 = offset in c9) -> a0 = status --------------
; fw_blk_read, or for a guest a copy from the RAM disk. Uses c14.
        .align 2048
u_blkrd:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        ld    t0, k_guest-GPBASE(gp)    ; a guest?
        bnez  t0, ubr_g                 ; ...
        la    t6, fw_blk_read           ; no: the block device
        jalr  ra, t6, 0                 ; ...
        j     ubr_ret                   ; ...
ubr_g:
        cclear c14                      ; c14 = the RAM disk
        crestore c14, K_RDISK           ; ...
        slli  a0, a0, 9                 ; bytes
        slli  a1, a1, 9                 ; ...
ubr_l:
        beqz  a1, ubr_done              ; all copied
        li    t3, 4096                  ; at most the bounce buffer
        bleu  t3, a1, ubr_n             ; ...
        mv    t3, a1                    ; ...
ubr_n:
        li    t2, K0_BOUNCE             ; RAM disk -> D-LS -> c9 (in issue order)
        tget  tg0, t2, c14, a0, t3      ; ...
        tput  tg0, t2, c9, a2, t3       ; ...
        add   a0, a0, t3                ; ...
        add   a2, a2, t3                ; ...
        sub   a1, a1, t3                ; ...
        j     ubr_l                     ; ...
ubr_done:
        twait 1                         ; ...
        csave c14, K_RDISK              ; ...
        li    a0, 0                     ; ...
ubr_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        xret  ra                        ; ...
        .org  u_blkrd + 2048            ; (the unit must fit its slot)

; ---- u_gdev(a0 = op): GDISK and GCON, dev's (u_req: s1 = its core, s2 = its pid) ----------
; GDISK (15): the RAM disk, as an attachment before the reply (once: it is
; linear; fs owns it then); GCON (16): a copy of the host's tty endpoint. -1
; when not a guest, or for anyone but dev.
        .align 2048
u_gdev:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        li    t0, 2                     ; only dev
        bne   s2, t0, ugd_bad           ; ...
        ld    t0, k_guest-GPBASE(gp)    ; only a guest
        beqz  t0, ugd_bad               ; ...
        mv    t1, a0                    ; which
        li    t0, 15                    ; ...
        li    a0, K_RDISK               ; GDISK
        beq   t1, t0, ugd_get           ; ...
        li    a0, K_GCON                ; GCON
ugd_get:
        la    t6, crs8                  ; c8 = it
        jalr  ra, t6, 0                 ; ...
        bnez  a0, ugd_bad               ; given away already
        cgive c8, s1                    ; the attachment
        cclear c8                       ; (a copy of a copyable one)
        li    a0, 0                     ; ...
        j     ugd_ret                   ; ...
ugd_bad:
        li    a0, -1                    ; ...
ugd_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        xret  ra                        ; ...
        .org  u_gdev + 2048             ; (the unit must fit its slot)
