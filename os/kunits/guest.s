; =============================================================================
; kunits/guest.s: guests -- whole worker cores running another OS (code units)
; =============================================================================
;
; A GUEST is N whole worker cores running a second operating system in
; supervisor mode, beside StrataOS. StrataOS takes those cores out of its own
; scheduling and hands the guest a bundle of capabilities:
;   * an arena (its memory, sized by the request, one revocation domain);
;   * a console endpoint to the tty server (its only I/O; see the console note);
;   * a read-only clock (the timer's NOW/FREQ);
;   * core control for its OWN cores only (to run its workers);
;   * nothing else: no KST, no device root, no core control over StrataOS, no
;     endpoint to proc or the kernel.
; The guest is NOT trusted. It can reach only what it was given. StrataOS ends
; it with one revoke (every capability the guest lent out dies) plus a RESET
; request to each of its cores (core control, bit 1): a reset restarts a core
; at the boot ROM even though it runs in supervisor mode, so a guest that will
; not yield is stopped anyway and its cores come back clean.
;
; Confinement of what the guest CAN send (its supervisor-mode cgive/cmkep reach
; any node) is enforced on the RECEIVING side by StrataOS: a worker's dispatcher
; and core 0 drop everything from a guest core except a 4 KiB request to a
; server the guest was given (G_GALLOW), and the block device pairs a buffer
; only with a command from the same core (an ISA rule). See doc/strataos.md.
;
; ---- The guest arena and the boot protocol ----------------------------------
; proc gets an arena from MEMORY, loads the guest image (a bare STX) into its
; TOP, and calls GSTART. The arena is split:
;   [0, imgoff)       writable guest memory  -> relative core 0's c0
;   [imgoff, size)    the image + platform table, a read+execute share -> every
;                     guest core's c5 (to load its Local Stores; core 0 also
;                     copies the image's T3 section into its writable memory)
; A guest platform table sits at arena offset size - GPT_END, inside the image
; region (so every core reads it through the share):
;   0  magic "GPLT"   8  corebase   16 corecount   24 imgoff   32 flags
; Each guest core is woken out of StrataOS idle by a gift (a loader code unit,
; which w_guest runs), then receives, as gifts from core 0 in this order:
;   c5 the image share, c1 the console endpoint, c2 the clock, c3 core control
;   (own cores); and, relative core 0 only, c0 the writable arena.
; The loader (u_gload) reads the platform table, sets corebase/corecount, copies
; the image's sections into the core's Local Stores (and, on core 0, its T3
; section into the writable arena), and jumps to the image entry in supervisor
; mode. The guest then sees itself as an N-core machine (coreid 0..N-1,
; ncores = N) and boots like bare metal.

GA_LOADER = 0xE000                      ; guest loader runs at this I-LS address (dead after boot)
GPT_END   = 0x1000                      ; the platform table sits GPT_END below the arena top
GPT_MAGIC = 0x544c5047                  ; "GPLT"
GUEST_ID0 = 240                         ; guest ids: 240 + index (process pids are 1..239: proc's newpid)

; ---- u_gstart: set up and launch a guest; data[0] = first core, data[1] = id -----
; k_cdata (from proc): u64 ncores, pin (-1 any), allow-mask (server cores it may
; reach), flags, console tty core, image offset. The arena arrived just before.
        .align 2048
u_gstart:
        addi  sp, sp, -32               ; frame (s1, s2 belong to u_req: the caller's
        sd    ra, 0(sp)                 ;   s1 is the sender core, used by ur_reply)
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        mv    s3, a0                    ; s3 = the sender core (proc), for the give-back paths
        la    t6, k_unstash             ; the arena proc sent just before
        jalr  ra, t6, 0                 ; c8 = it
        bnez  a0, ugs_bad               ; none
        cbase t0, c8                    ; find its arena slot (a MEMORY one, state 1)
        li    s1, 0                     ; slot
        li    t1, K0_AR                 ; ...
ugs_f:
        li    t2, NARENA                ; ...
        bge   s1, t2, ugs_back          ; not one of ours
        ld    t2, AR_STATE(t1)          ; ...
        li    t3, 1                     ; ...
        bne   t2, t3, ugs_fn            ; ...
        ld    t2, AR_BASE(t1)           ; ...
        beq   t2, t0, ugs_have          ; ...
ugs_fn:
        addi  s1, s1, 1                 ; ...
        addi  t1, t1, AR_SZ             ; ...
        j     ugs_f                     ; ...
ugs_have:
        sd    s1, g_aslot(zero)    ; the arena slot
        cclear c10                      ; c10 = the writable arena
        cmov  c10, c8                   ; ...
        la    t0, k_cdata               ; the parameters
        ld    t1, 0(t0)                 ; ncores
        sd    t1, g_n(zero)        ; ...
        ld    t1, 16(t0)                ; allow-mask
        sd    t1, g_allow(zero)    ; ...
        ld    t1, 24(t0)                ; flags
        sd    t1, g_flags(zero)    ; ...
        ld    t1, 40(t0)                ; image offset
        sd    t1, g_pt(zero)       ; (kept here for the split point)
        ld    a0, 0(t0)                 ; choose cores: pin, or a free run
        ld    a1, 8(t0)                 ; pin (-1 any)
        la    t5, u_gpick               ; -> g_core, a0 = 0 or -5
        xcall ra, c12, t5               ; ...
        bltz  a0, ugs_nocore            ; no room
        la    t5, u_grec                ; a guest record -> g_id, g_rec
        xcall ra, c12, t5               ; ...
        bltz  a0, ugs_nocore            ; no slot
        la    t5, u_gpt                 ; write the platform table into the arena (c10)
        xcall ra, c12, t5               ; ...
        la    t5, u_glaunch             ; split, mark the cores, give the pieces, wake them
        xcall ra, c12, t5               ; ...
        la    t0, k_cdata               ; reply: data[0] = first core, data[1] = id
        ld    t2, g_rec(zero)      ; (from the record, which outlives the scratch)
        ld    t1, GU_CORE(t2)           ; ...
        sd    t1, 0(t0)                 ; ...
        ld    t1, GU_PID(t2)            ; ...
        sd    t1, 8(t0)                 ; ...
        li    t2, 64                    ; ...
        li    t3, 16                    ; ...
        tput  tg0, t0, c11, t2, t3      ; ...
        twait 1                         ; (the reply data; ur_reply adds the header)
        li    a0, 0                     ; ...
        j     ugs_ret                   ; ...
ugs_nocore:
        cgive c10, s3                   ; give the arena back to proc (s3 = the sender core)
        li    a0, -5                    ; no room
        j     ugs_ret                   ; ...
ugs_back:
        cgive c8, s3                    ; not one of our arenas: back it goes
ugs_bad:
        li    a0, -1                    ; ...
ugs_ret:
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        xret  ra                        ; ...
        .org  u_gstart + 2048           ; (the unit must fit its slot)

; ---- u_gpick(a0 = ncores, a1 = pin): choose N contiguous empty worker cores --
; "empty" = no slots used and no flags (no server, solo, guest or lost). -> g_core, a0
        .align 2048
u_gpick:
        mv    a6, a0                    ; a6 = N
        bltz  a1, ugp_any               ; a pin?
        mv    t1, a1                    ; the run from it
        j     ugp_try                   ; ...
ugp_any:
        li    t1, 1                     ; search from core 1
ugp_scan:
        ld    t2, w_ncores-GPBASE(gp)   ; ...
        add   t3, t1, a6                ; the run must fit
        bgt   t3, t2, ugp_none          ; ...
ugp_try:
        li    t4, 0                     ; check N cores from t1
ugp_c:
        bge   t4, a6, ugp_ok            ; all empty
        add   t5, t1, t4                ; this core
        ld    t2, w_ncores-GPBASE(gp)   ; a worker (not core 0)
        bge   t5, t2, ugp_bad           ; ...
        beqz  t5, ugp_bad               ; ...
        slli  t6, t5, 4                 ; its record
        ld    t2, K0_CORE(t6)           ; used slots?
        bnez  t2, ugp_bad               ; not empty
        ld    t2, K0_CORE+8(t6)         ; flags?
        bnez  t2, ugp_bad               ; not empty
        addi  t4, t4, 1                 ; ...
        j     ugp_c                     ; ...
ugp_bad:
        bgez  a1, ugp_none              ; pinned and it does not fit
        addi  t1, t1, 1                 ; next start
        j     ugp_scan                  ; ...
ugp_ok:
        sd    t1, g_core(zero)     ; the first core
        li    a0, 0                     ; ...
        xret  ra                        ; ...
ugp_none:
        li    a0, -5                    ; ...
        xret  ra                        ; ...
        .org  u_gpick + 2048            ; (the unit must fit its slot)

; ---- u_grec: allocate a guest record -> g_id, g_rec; a0 = 0 or -5 ------------
        .align 2048
u_grec:
        addi  sp, sp, -8                ; frame
        sd    ra, 0(sp)                 ; ...
        li    t0, K0_GUEST              ; a free record
        li    t1, 0                     ; index
ugr_l:
        li    t2, NGUEST                ; ...
        bge   t1, t2, ugr_none          ; ...
        ld    t2, GU_PID(t0)            ; free?
        beqz  t2, ugr_ok                ; ...
        addi  t0, t0, GU_SIZE           ; ...
        addi  t1, t1, 1                 ; ...
        j     ugr_l                     ; ...
ugr_ok:
        addi  t2, t1, GUEST_ID0         ; id = 240 + index
        sd    t2, GU_PID(t0)            ; ...
        sd    t2, g_id(zero)       ; ...
        sd    t0, g_rec(zero)      ; ...
        ld    t3, g_core(zero)     ; ...
        sd    t3, GU_CORE(t0)           ; ...
        ld    t3, g_n(zero)        ; ...
        sd    t3, GU_N(t0)              ; ...
        sd    t3, GU_LEFT(t0)           ; ...
        ld    t3, g_aslot(zero)    ; ...
        sd    t3, GU_ASLOT(t0)          ; ...
        li    t3, F_GUEST               ; ...
        sd    t3, GU_FLAGS(t0)          ; ...
        ld    a0, g_aslot(zero)    ; the arena's granules belong to the guest id (pid_of)
        ld    a1, g_id(zero)       ; ...
        la    t5, u_own                 ; ...
        xcall ra, c12, t5               ; ...
        li    a0, 0                     ; ...
        j     ugr_ret                   ; ...
ugr_none:
        li    a0, -5                    ; ...
ugr_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 8                 ; ...
        xret  ra                        ; ...
        .org  u_grec + 2048             ; (the unit must fit its slot)

; ---- u_gpt: write the guest platform table into the arena (c10) --------------
        .align 2048
u_gpt:
        clen  t0, c10                   ; arena size
        li    t1, GPT_END               ; ...
        sub   t0, t0, t1                ; its offset: size - GPT_END
        li    t2, g_tmp                 ; build it in D-LS
        li    t3, GPT_MAGIC             ; magic
        sd    t3, 0(t2)                 ; ...
        ld    t3, g_core(zero)     ; corebase
        sd    t3, 8(t2)                 ; ...
        ld    t3, g_n(zero)        ; corecount
        sd    t3, 16(t2)                ; ...
        ld    t3, g_pt(zero)       ; image offset
        sd    t3, 24(t2)                ; ...
        ld    t3, g_flags(zero)    ; flags
        sd    t3, 32(t2)                ; ...
        li    t4, 40                    ; bytes
        tput  tg0, t2, c10, t0, t4      ; -> the arena
        twait 1                         ; ...
        xret  ra                        ; ...
        .org  u_gpt + 2048              ; (the unit must fit its slot)

; ---- u_glaunch: split the arena, mark the cores, give the pieces, wake them --
; c10 = the writable arena. Splits off the image region [imgoff, size) as a
; read+execute share and gives every core what the boot protocol says.
        .align 2048
u_glaunch:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        ld    t0, g_pt(zero)       ; split at the image offset
        csplit c13, c10, t0             ; c10 = writable [0, imgoff), c13 = image region
        cshare c14, c13                 ; c14 = a read+execute copyable share of the image region
        li    a0, K_STASH               ; keep the image share aside (c14 -> a save slot)
        cclear c8                       ; ...
        cmov  c8, c14                   ; ...
        la    t6, csv8                  ; ...
        jalr  ra, t6, 0                 ; ...
        li    s1, 0                     ; relative core 0..N-1
ugl_core:
        ld    t0, g_n(zero)        ; ...
        bge   s1, t0, ugl_done          ; ...
        ld    s2, g_core(zero)     ; physical core
        add   s2, s2, s1                ; ...
        slli  t6, s2, 4                 ; its K0_CORE record
        li    t0, CF_GUEST              ; flags |= guest (out of StrataOS scheduling)
        sd    t0, K0_CORE+8(t6)         ; ...
        li    t0, K0_GMASK              ; core 0's fast bitmask
        ld    t1, 0(t0)                 ; ...
        li    t2, 1                     ; ...
        sll   t2, t2, s2                ; ...
        or    t1, t1, t2                ; ...
        sd    t1, 0(t0)                 ; ...
        li    a0, G_GCORES              ; the KST bitmask (workers read it)
        mv    a1, t2                    ; ...
        la    t6, kst_or                ; ...
        jalr  ra, t6, 0                 ; ...
        slli  t3, s2, 3                 ; its per-core KST words
        li    a0, G_GALLOW              ; which servers it may reach
        add   a0, a0, t3                ; ...
        ld    a1, g_allow(zero)    ; ...
        la    t6, kst_wr                ; ...
        jalr  ra, t6, 0                 ; ...
        slli  t3, s2, 3                 ; ...
        li    a0, G_GOUT                ; no request out yet
        add   a0, a0, t3                ; ...
        li    a1, 0                     ; ...
        la    t6, kst_wr                ; ...
        jalr  ra, t6, 0                 ; ...
        slli  t3, s2, 10                ; its CA area: CA_GJOB = the loader address + 1
        addi  a0, t3, CAREA + CA_GJOB   ; ...
        li    a1, GA_LOADER + 1         ; ...
        la    t6, kst_wr                ; ...
        jalr  ra, t6, 0                 ; ...
        la    t5, u_gcaps               ; give the core its capabilities (s1, s2)
        xcall ra, c12, t5               ; ...
        addi  s1, s1, 1                 ; next core
        j     ugl_core                  ; ...
ugl_done:
        li    a0, K_STASH               ; drop our copy of the image share
        la    t6, crs8                  ; ...
        jalr  ra, t6, 0                 ; ...
        cclear c8                       ; ...
        cclear c10                      ; (the writable arena went to relative core 0)
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        xret  ra                        ; ...
        .org  u_glaunch + 2048          ; (the unit must fit its slot)

; ---- u_gcaps(s1 = relative core, s2 = physical core): give one core its caps --
; The loader (u_gload) ctakes in this order: loader (wake), image share -> c5,
; console endpoint -> c1, clock -> c2, core control (own) -> c3, and relative
; core 0 also the writable arena -> c0.
        .align 2048
u_gcaps:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        cclear c8                       ; the loader code unit: cut it from the far image
        cmov  c8, c12                   ; a copy of the far image (copyable)
        la    t0, u_gload               ; the loader's far offset
        csplit c9, c8, t0               ; c8 = below it, c9 = from it on
        li    t0, 2048                  ; one unit
        csplit c15, c9, t0              ; c9 = the loader, c15 = the rest
        cclear c8                       ; ...
        cclear c15                      ; ...
        cgive c9, s2                    ; the loader (the wake gift; w_guest runs it)
        li    a0, K_STASH               ; the image share -> c5
        la    t6, crs8                  ; ...
        jalr  ra, t6, 0                 ; c8 = it (copyable: the slot keeps it)
        cgive c8, s2                    ; ...
        cclear c8                       ; ...
        la    t0, k_cdata               ; the console endpoint -> c1 (to the tty server's core)
        ld    t0, 32(t0)                ; ...
        cmkep c8, t0                    ; an endpoint for it
        li    t0, 1 | 2 | 16            ; read + write + copyable
        crestrict c8, c8, t0            ; ...
        cgive c8, s2                    ; ...
        cclear c8                       ; ...
        cmov  c8, c3                    ; the clock -> c2 (cut from the device root)
        li    t0, TMR_PORT              ; ...
        csplit c9, c8, t0               ; c9 = from the timer on
        li    t0, 16                    ; NOW and FREQ
        csplit c15, c9, t0              ; c9 = the two registers
        cclear c8                       ; ...
        cclear c15                      ; ...
        li    t0, 1 | 16                ; read + copyable
        crestrict c8, c9, t0            ; ...
        cgive c8, s2                    ; ...
        cclear c8                       ; ...
        cmov  c8, c4                    ; core control for the guest's own cores -> c3
        ld    t0, g_core(zero)     ; [8*base, 8*(base+N))
        slli  t1, t0, 3                 ; ...
        csplit c9, c8, t1               ; c8 = below, c9 = from base on
        ld    t2, g_n(zero)        ; ...
        slli  t2, t2, 3                 ; ...
        csplit c15, c9, t2              ; c9 = the guest's cores, c15 = above
        cclear c8                       ; ...
        cclear c15                      ; ...
        cgive c9, s2                    ; ...
        bnez  s1, ugc_ret               ; workers get memory from the guest's core 0
        cgive c10, s2                   ; relative core 0: the writable arena [0, imgoff) -> c0
ugc_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        xret  ra                        ; ...
        .org  u_gcaps + 2048            ; (the unit must fit its slot)

; ---- u_gload: the LOADER. Runs on a guest core at GA_LOADER, relocated, so it
; uses only pc-relative addressing and the capabilities core 0 gives it. w_guest
; put it here and jumped. First, while the dispatcher's resident code and data
; are still there (it calls crs8 and kst_rd, as units call resident code), it
; scrubs the core of everything StrataOS keeps on it, which a supervisor-mode
; guest could otherwise take: every save-table entry (a worker keeps the KST,
; core control over EVERY core, the device root and the console output there;
; no instruction empties an entry, so each is taken out -- a linear capability
; leaves its entry, a probed restore of an empty one is skipped -- and
; overwritten with a copy of the read-only clock, which the guest is given
; anyway), every capability register, and the D-LS. After that it references
; no resident kernel code or data. --
        .align 2048
u_gload:
        li    sp, STACKTOP              ; a stack (D-LS top)
        la    t6, kcaps                 ; c9 = the KST: the save table's size
        jalr  ra, t6, 0                 ; ...
        li    a0, G_CTAB                ; ...
        la    t6, kst_rd                ; ...
        jalr  ra, t6, 0                 ; ...
        mv    s2, a0                    ; s2 = entries
        li    a0, T_CLOCK               ; the filler: the clock (copyable, read-only)
        la    t6, crs8                  ; ...
        jalr  ra, t6, 0                 ; c8 = it
        cclear c15                      ; ...
        cmov  c15, c8                   ; ...
        li    s3, 0                     ; s3 = entry
ugld_st:
        bgeu  s3, s2, ugld_cr           ; all of them
        mv    a0, s3                    ; take what is there (into c8; nothing if empty)
        la    t6, crs8                  ; ...
        jalr  ra, t6, 0                 ; ...
        cclear c8                       ; drop it
        csavex c15, s3                  ; and leave a copy of the clock instead
        addi  s3, s3, 1                 ; ...
        j     ugld_st                   ; ...
ugld_cr:
        cclear c0                       ; no capability register keeps anything
        cclear c1                       ; ...
        cclear c2                       ; ...
        cclear c3                       ; ...
        cclear c4                       ; ...
        cclear c5                       ; ...
        cclear c6                       ; ...
        cclear c7                       ; ...
        cclear c8                       ; ...
        cclear c9                       ; ...
        cclear c10                      ; ...
        cclear c11                      ; ...
        cclear c12                      ; ...
        cclear c13                      ; ...
        cclear c14                      ; ...
        cclear c15                      ; ...
        li    t0, 0                     ; scrub the D-LS but the scratch page at 0xC000:
        li    t1, 0x10000               ;   the dispatcher's data (its variables, the saved
ugld_z:                                 ;   registers of processes that ran here) are not
        sd    zero, 0(t0)               ;   the guest's to read
        addi  t0, t0, 8                 ; ...
        li    t2, 0xC000                ; ...
        bne   t0, t2, ugld_zn           ; ...
        li    t0, 0xC100                ; (skip the scratch page)
ugld_zn:
        bltu  t0, t1, ugld_z            ; ...
        ctake c5, zero                  ; the image share (read+execute), from core 0
        ctake c1, zero                  ; the console endpoint
        ctake c2, zero                  ; the clock
        ctake c3, zero                  ; core control (own cores)
        clen  t0, c5                    ; the platform table: GPT_END below the arena top,
        li    t1, GPT_END               ;   i.e. at share offset (clen c5) - GPT_END
        sub   t0, t0, t1                ; ...
        li    t2, 0xC000                ; a D-LS scratch page (above the D-LS image)
        li    t3, 40                    ; ...
        tget  tg0, t2, c5, t0, t3       ; -> D-LS
        csrr  s1, coreid                ; our physical core (corebase is still 0 here)
        ld    t3, 0x08(t2)              ; corebase from the table
        sub   s1, s1, t3               ; s1 = relative core
        bnez  s1, ugld_corebase         ; relative core 0 also takes the writable arena -> c0,
        ctake c0, zero                   ;   from core 0 -- BEFORE setting corebase, so the sender
ugld_corebase:                          ;   number is physical core 0, not 0 + corebase
        ld    t3, 0x10(t2)              ; corecount
        csrw  corecount, t3             ; the guest sees itself as an N-core machine
        ld    t3, 0x08(t2)              ; corebase
        csrw  corebase, t3              ; coreid now reads relative to it
ugld_hdr:
        li    t2, 0xC000                ; parse the STX image at share offset 0: the header
        li    t3, 8                     ; ...
        tget  tg0, t2, c5, zero, t3     ; ...
        lwu   s2, 4(t2)                 ; s2 = section count
        li    s3, 8                     ; s3 = share offset of the next section header
        li    s4, 0                     ; s4 = the entry (I-LS section base)
ugld_s:
        beqz  s2, ugld_go               ; all sections done
        li    t2, 0xC000                ; read this section header (16 bytes)
        li    t3, 16                    ; ...
        tget  tg0, t2, c5, s3, t3       ; ...
        lwu   t4, 0(t2)                 ; kind
        lwu   t5, 4(t2)                 ; base
        lwu   t6, 8(t2)                 ; size
        addi  s3, s3, 16                ; share offset of the section's bytes
        li    a7, 1                     ; kind 1: I-LS
        bne   t4, a7, ugld_d            ; ...
        tgetx tg0, t5, c5, s3, t6       ; image -> I-LS at base
        mv    s4, t5                    ; the entry is the I-LS base
        j     ugld_sn                   ; ...
ugld_d:
        li    a7, 2                     ; kind 2: D-LS
        bne   t4, a7, ugld_t            ; ...
        tget  tg0, t5, c5, s3, t6       ; image -> D-LS at base
        j     ugld_sn                   ; ...
ugld_t:
        li    a7, 3                     ; kind 3: T3 -> the writable arena (core 0 only)
        bne   t4, a7, ugld_sn           ; kind 4 (T2) is not used by a guest
        bnez  s1, ugld_sn               ; workers have no writable arena: skip
        mv    a0, t5                    ; dest arena offset
        mv    a1, s3                    ; src share offset
        mv    a2, t6                    ; bytes
ugld_cp:
        beqz  a2, ugld_sn               ; ...
        li    t2, 0xC000                ; bounce page
        li    t3, 0x1000                ; up to 4 KiB
        bltu  a2, t3, ugld_cl           ; ...
        j     ugld_cm                   ; ...
ugld_cl:
        mv    t3, a2                    ; ...
ugld_cm:
        tget  tg0, t2, c5, a1, t3       ; share -> D-LS
        tput  tg0, t2, c0, a0, t3       ; D-LS -> arena
        add   a0, a0, t3                ; ...
        add   a1, a1, t3                ; ...
        sub   a2, a2, t3                ; ...
        j     ugld_cp                   ; ...
ugld_sn:
        add   s3, s3, t6                ; past this section's bytes
        addi  s2, s2, -1                ; ...
        j     ugld_s                    ; ...
ugld_go:
        twait 1                         ; the transfers complete
        cclear c5                       ; drop the image share
        csrr  a0, coreid                ; a0 = relative core (bare images read coreid anyway)
        jr    s4                        ; into the guest in supervisor mode
        .org  u_gload + 2048            ; (the loader must fit one unit)

; ---- u_ggift(a0 = a guest core): a gift arrived from a guest core ------------
; Guest cores send nothing StrataOS wants here (requests go to the servers on
; their own cores, not to core 0). Drop it.
        .align 2048
u_ggift:
        cclear c8                       ; ...
        xret  ra                        ; ...
        .org  u_ggift + 2048            ; (the unit must fit its slot)

; ---- u_gstop(a0 = guest id, a1 = mode): end a guest ------------------------
; Revoke its arena (everything it holds and lent dies), reset each of its cores
; (so a supervisor that will not yield is stopped anyway and comes back clean),
; re-provision the reset cores as StrataOS workers, free the arena and record.
; mode is advisory (kill vs stop): a reset does both cleanly, so it is ignored.
        .align 2048
u_gstop:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        li    s1, K0_GUEST              ; find the record by id
        li    t1, 0                     ; ...
ugst_f:
        li    t2, NGUEST                ; ...
        bge   t1, t2, ugst_bad          ; ...
        ld    t2, GU_PID(s1)            ; ...
        beq   t2, a0, ugst_have         ; ...
        addi  s1, s1, GU_SIZE           ; ...
        addi  t1, t1, 1                 ; ...
        j     ugst_f                    ; ...
ugst_have:
        ld    s2, GU_CORE(s1)           ; first quiesce every core: a reset request restarts it
        ld    s3, GU_N(s1)              ;   at the boot ROM (even in supervisor mode), so it stops
        add   s3, s3, s2                ;   running the guest before we revoke its memory
ugst_kick:
        bge   s2, s3, ugst_rev          ; ...
        mv    a0, s2                    ; ...
        la    t5, u_greset              ; reset core s2 and clear its guest marks
        xcall ra, c12, t5               ; ...
        addi  s2, s2, 1                 ; ...
        j     ugst_kick                 ; ...
ugst_rev:
        ld    a0, GU_ASLOT(s1)          ; now revoke the arena: all its capabilities die
        la    t5, u_arcap               ; (c13 = a fresh one, which we drop)
        xcall ra, c12, t5               ; ...
        cclear c13                      ; ...
        ld    s2, GU_CORE(s1)           ; re-provision each reset core as a StrataOS worker
        ld    s3, GU_N(s1)              ; ...
        add   s3, s3, s2                ; ...
ugst_core:
        bge   s2, s3, ugst_free         ; ...
        mv    a0, s2                    ; ...
        la    t5, u_gprov               ; give it the OS shares again (boot ROM + wboot)
        xcall ra, c12, t5               ; ...
        addi  s2, s2, 1                 ; ...
        j     ugst_core                 ; ...
ugst_free:
        ld    a0, GU_ASLOT(s1)          ; free the arena (its caps are all dead now)
        la    t5, u_arfree              ; ...
        xcall ra, c12, t5               ; ...
        sd    zero, GU_PID(s1)          ; the record is free
        li    a0, 0                     ; ...
        j     ugst_ret                  ; ...
ugst_bad:
        li    a0, -1                    ; no such guest
ugst_ret:
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        xret  ra                        ; ...
        .org  u_gstop + 2048            ; (the unit must fit its slot)

; ---- u_greset(a0 = core): reset a guest core and re-provision it as a worker -
; A core-control reset (bit 1) restarts the core at the boot ROM even in
; supervisor mode; it then runs the boot ROM's secondary path and waits for the
; OS shares, exactly as at power-on, so core 0 re-gives them.
        .align 2048
u_greset:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        mv    s1, a0                    ; s1 = the core
        slli  t6, s1, 4                 ; clear its guest marks
        sd    zero, K0_CORE(t6)         ; no slots
        sd    zero, K0_CORE+8(t6)       ; no flags
        li    t0, K0_GMASK              ; core 0's fast bitmask
        ld    t1, 0(t0)                 ; ...
        li    t2, 1                     ; ...
        sll   t2, t2, s1                ; ...
        sub   t2, zero, t2              ; invert every bit (-x - 1)
        addi  t2, t2, -1                ; ...
        and   t1, t1, t2                ; ...
        sd    t1, 0(t0)                 ; ...
        li    a0, G_GCORES              ; the KST bitmask: clear the bit
        la    t6, kst_rd                ; ...
        jalr  ra, t6, 0                 ; ...
        li    t2, 1                     ; ...
        sll   t2, t2, s1                ; ...
        sub   t2, zero, t2              ; invert every bit (-x - 1)
        addi  t2, t2, -1                ; ...
        and   a1, a0, t2                ; ...
        li    a0, G_GCORES              ; ...
        la    t6, kst_wr                ; ...
        jalr  ra, t6, 0                 ; ...
        slli  t3, s1, 10                ; clear CA_GJOB (else the core would relaunch a guest)
        addi  a0, t3, CAREA + CA_GJOB   ; ...
        li    a1, 0                     ; ...
        la    t6, kst_wr                ; ...
        jalr  ra, t6, 0                 ; ...
        slli  t3, s1, 3                 ; clear its G_GOUT (server-request-outstanding) word
        li    a0, G_GOUT                ; ...
        add   a0, a0, t3                ; ...
        li    a1, 0                     ; ...
        la    t6, kst_wr                ; ...
        jalr  ra, t6, 0                 ; ...
        li    t0, g_tmp                 ; the reset request (core control, bit 1)
        li    t1, 2                     ; ...
        sd    t1, 0(t0)                 ; ...
        slli  t2, s1, 3                 ; its core-control doubleword
        li    t3, 8                     ; ...
        tput  tg0, t0, c4, t2, t3       ; reset it (un-halts it; it re-enters the boot ROM)
        twait 1                         ; ...
        ld    ra, 0(sp)                 ; ...
        ld    s1, 8(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        xret  ra                        ; ...
        .org  u_greset + 2048           ; (the unit must fit its slot)

; ---- u_gprov(a0 = core): give a reset core the OS shares, as the boot ROM did -
; The core is in the boot ROM's secondary path (reset by u_greset), waiting for
; c10 (code), c11 (data), c3 (device root); then wboot waits for the KST and
; core control.
        .align 2048
u_gprov:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        mv    s1, a0                    ; s1 = the core
        li    a0, K_KCODE               ; the OS code share
        la    t6, crs8                  ; ...
        jalr  ra, t6, 0                 ; ...
        cgive c8, s1                    ; ...
        cclear c8                       ; ...
        li    a0, K_KDATA               ; the OS data share
        la    t6, crs8                  ; ...
        jalr  ra, t6, 0                 ; ...
        cgive c8, s1                    ; ...
        cclear c8                       ; ...
        cmov  c8, c3                    ; the device root (copyable)
        cgive c8, s1                    ; ...
        cclear c8                       ; ...
        cmov  c8, c6                    ; then wboot wants the KST (atomic, copyable)
        cgive c8, s1                    ; ...
        cclear c8                       ; ...
        cmov  c8, c4                    ; and core control (copyable)
        cgive c8, s1                    ; ...
        cclear c8                       ; ...
        ld    ra, 0(sp)                 ; ...
        ld    s1, 8(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        xret  ra                        ; ...
        .org  u_gprov + 2048            ; (the unit must fit its slot)

; ---- u_ginfo: guest records into the request (c11) -> a0 = guest count -------
; data: u64 count, then 32 bytes per guest: u64 id, u64 first core | cores << 8,
;       u64 arena bytes, u64 state (1 live)
        .align 2048
u_ginfo:
        li    a6, K0_BOUNCE             ; build the data here (a6: s-registers belong to u_req)
        li    t0, K0_GUEST              ; ...
        li    t1, 0                     ; records written
        li    t2, 0                     ; index
ugi_l:
        li    t3, NGUEST                ; ...
        bge   t2, t3, ugi_out           ; ...
        ld    t4, GU_PID(t0)            ; in use?
        beqz  t4, ugi_n                 ; ...
        slli  t5, t1, 5                 ; its 32-byte record (after the count word)
        add   t5, a6, t5                ; ...
        addi  t5, t5, 8                 ; ...
        sd    t4, 0(t5)                 ; id
        ld    t4, GU_CORE(t0)           ; first core | cores << 8
        ld    t6, GU_N(t0)              ; ...
        slli  t6, t6, 8                 ; ...
        or    t4, t4, t6                ; ...
        sd    t4, 8(t5)                 ; ...
        ld    t4, GU_ASLOT(t0)          ; arena bytes
        slli  t4, t4, 5                 ; ...
        li    t6, K0_AR                 ; ...
        add   t4, t4, t6                ; ...
        ld    t4, AR_SIZE(t4)           ; ...
        sd    t4, 16(t5)                ; ...
        li    t4, 1                     ; state: live
        sd    t4, 24(t5)                ; ...
        addi  t1, t1, 1                 ; ...
ugi_n:
        addi  t0, t0, GU_SIZE           ; ...
        addi  t2, t2, 1                 ; ...
        j     ugi_l                     ; ...
ugi_out:
        sd    t1, 0(a6)                 ; the count
        slli  t3, t1, 5                 ; bytes: 8 + 32 * count
        addi  t3, t3, 8                 ; ...
        li    t0, K0_BOUNCE             ; -> the request buffer
        li    t2, 64                    ; after the header
        tput  tg0, t0, c11, t2, t3      ; ...
        twait 1                         ; ...
        mv    a0, t1                    ; a0 = guest count
        xret  ra                        ; ...
        .org  u_ginfo + 2048            ; (the unit must fit its slot)
