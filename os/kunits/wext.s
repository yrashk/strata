; =============================================================================
; kunits/wext.s: the worker extension: resident threads' Local Store slices
; =============================================================================
;
; Dispatcher code that does not fit the worker's resident part (I-LS
; 0x4000..0x76FF). It is in the kernel's far image, next to the code units;
; core 0 gives every worker a share of that image, and wboot copies the
; extension to XBASE (0x7700), over core 0's own resident code, which
; workers never run (at most 0x900 bytes). So, as in a code unit:
; branches and calls inside it are relative; it calls resident code with
; `la t6, f; jalr ra, t6, 0`; resident code calls its entries at XE_* (the
; jumps below) with `li t6, XE_x; jalr ra, t6, 0`. Its data is the kernel's,
; through gp.
;
; What it does (doc/ls-windows.md, step 3). A thread keeps the D-LS it was
; given while it is switched out: its data slice (as many 1 KiB units as its
; data extent, all 40 for a bare-metal program) and its stack slice (8
; units), anywhere in the program part of the D-LS (units 0..39 and 56..63).
; The windows wdata and wstack map its addresses 0.. and 0xE000.. onto them,
; so a switch to a resident thread moves nothing. A thread that is not
; resident gets free units; when there are not enough, the threads that ran
; least recently are evicted (their extent and live stack saved, as a switch
; did before) until there are. A new slice is filled whole from the save
; area, which holds zeros beyond what the thread saved, so it never shows
; another thread's bytes. The code is not relocated: it is loaded on every
; switch, as before (wcode stays [0x8000, 0x10000)).
;
; w_res[slot] (8 bytes per slot, in core 0's k_hdr: workers never use it):
;   bits 0..7    data unit + 1 (0: not resident)
;   bits 8..15   stack unit
;   bits 16..23  data units
;   bit 24       RS_EV: evicted by xplan, its save not issued yet (xevict)
;   bits 25..    w_tick when it last ran (least recently run goes first)
; A dead thread (a free or zombie slot, or one not started: a new job in the
; slot of a dead one) gives its units back without a save.

RS_EV    = 1 << 24                      ; evicted, to be saved
RS_LO    = 0xffffff                     ; the slice fields
DUNITS0  = 0xff0000ffffffffff           ; the program part of the D-LS: units 0..39, 56..63
SUNITS   = (STACKTOP - STACKLO) >> 10   ; a stack slice: 8 units

        .align 8                        ; (copied with tgetx: 8-byte aligned)
xstart:
        j     xinit                     ; XE_INIT
        j     xplan                     ; XE_PLAN
        j     xevict                    ; XE_EVICT
        j     xrestore                  ; XE_REST
        xmap  0, a1, c15, a2           ; XE_XMAP15: slot 0 (a unit of the image)
        ret                             ; .
        xmap  1, a1, c15, a2           ; XE_XMAP15: slot 1 (a unit of the image)
        ret                             ; .
        xmap  2, a1, c15, a2           ; XE_XMAP15: slot 2 (a unit of the image)
        ret                             ; .
        xmap  3, a1, c15, a2           ; XE_XMAP15: slot 3 (a unit of the image)
        ret                             ; .
        xmap  4, a1, c15, a2           ; XE_XMAP15: slot 4 (a unit of the image)
        ret                             ; .
        xmap  5, a1, c15, a2           ; XE_XMAP15: slot 5 (a unit of the image)
        ret                             ; .
        xmap  6, a1, c15, a2           ; XE_XMAP15: slot 6 (a unit of the image)
        ret                             ; .
        xmap  7, a1, c15, a2           ; XE_XMAP15: slot 7 (a unit of the image)
        ret                             ; .
        xmap  8, a1, c15, a2           ; XE_XMAP15: slot 8 (a unit of the image)
        ret                             ; .
        xmap  9, a1, c15, a2           ; XE_XMAP15: slot 9 (a unit of the image)
        ret                             ; .
        xmap  10, a1, c15, a2           ; XE_XMAP15: slot 10 (a unit of the image)
        ret                             ; .
        xmap  11, a1, c15, a2           ; XE_XMAP15: slot 11 (a unit of the image)
        ret                             ; .
        xmap  12, a1, c15, a2           ; XE_XMAP15: slot 12 (a unit of the image)
        ret                             ; .
        xmap  13, a1, c15, a2           ; XE_XMAP15: slot 13 (a unit of the image)
        ret                             ; .
        xmap  14, a1, c15, a2           ; XE_XMAP15: slot 14 (a unit of the image)
        ret                             ; .
        xmap  15, a1, c15, a2           ; XE_XMAP15: slot 15 (a unit of the image)
        ret                             ; .

; ---- xinit(): every unit of the program part free; the code window ---------------------------
xinit:
        li    t0, DUNITS0               ; ...
        sd    t0, w_dfree-GPBASE(gp)    ; ...
        ld    t0, w_wcode-GPBASE(gp)    ; wcode: [0x8000, 0x10000), not relocated
        csrw  wcode, t0                 ; ...
        ret                             ; ...

; ---- xplan(a0 = slot): before a switch's transfers ---------------------------------------
; Gives the thread its slices if it has none (evicting others: w_evm, their
; bytes counted now, while no transfer is in flight) and leaves in w_rbytes
; what xrestore will move into its D-LS (0: resident, nothing). A first load
; sets its data extent (PR_DEND) here.
xplan:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        sd    s5, 40(sp)                ; ...
        mv    s1, a0                    ; s1 = slot
        la    t6, prec                  ; s2 = record
        jalr  ra, t6, 0                 ; ...
        mv    s2, a0                    ; ...
        sd    zero, w_evm-GPBASE(gp)    ; no evictions yet
        sd    zero, w_rbytes-GPBASE(gp) ; ...
        ld    t0, w_tick-GPBASE(gp)     ; the clock
        addi  t0, t0, 1                 ; ...
        sd    t0, w_tick-GPBASE(gp)     ; ...
        slli  s3, s1, 3                 ; s3 = &w_res[slot]
        add   s3, s3, gp                ; ...
        addi  s3, s3, w_res-GPBASE      ; ...
        ld    t0, PR_STARTED(s2)        ; a first load?
        bnez  t0, xp_st                 ; no
        mv    a0, s1                    ; whatever the slot held belonged to a dead thread
        call  xrel                      ; ...
        ld    t1, PR_DATA(s2)           ; its data extent: the image's data section,
        li    t2, 0xffff                ;   8-byte aligned (a bare-metal program, which may
        and   t3, t1, t2                ;   use all of its D-LS: 40 KiB)
        srli  t4, t1, 16                ; t4 = the data section's length
        and   t4, t4, t2                ; ...
        add   t5, t3, t4                ; ...
        addi  t5, t5, 7                 ; ...
        srli  t5, t5, 3                 ; ...
        slli  t5, t5, 3                 ; ...
        li    t2, DATAMAX               ; ...
        bleu  t5, t2, xp_de             ; ...
        mv    t5, t2                    ; ...
xp_de:
        ld    t0, PR_FLAGS(s2)          ; ...
        andi  t0, t0, F_SYS             ; ...
        bnez  t0, xp_de2                ; ...
        li    t5, DATAMAX               ; ...
xp_de2:
        sd    t5, PR_DEND(s2)           ; ...
        sd    t4, w_rbytes-GPBASE(gp)   ; the image's data section comes in too
xp_st:
        ld    t0, 0(s3)                 ; resident?
        andi  t1, t0, 255               ; ...
        beqz  t1, xp_new                ; no
        li    t1, RS_LO                 ; yes: only its clock moves
        and   t0, t0, t1                ; ...
        ld    t1, w_tick-GPBASE(gp)     ; ...
        slli  t1, t1, 25                ; ...
        or    t0, t0, t1                ; ...
        sd    t0, 0(s3)                 ; ...
        j     xp_ret                    ; ...
xp_new:
        ld    t0, PR_DEND(s2)           ; s4 = its data units
        addi  t0, t0, 1023              ; ...
        srli  s4, t0, 10                ; ...
        bnez  s4, xp_try                ; ...
        li    s4, 1                     ; ...
xp_try:
        mv    a0, s4                    ; a data slice?
        call  xfind                     ; ...
        bltz  a0, xp_ev                 ; no room
        mv    s5, a0                    ; s5 = its first unit
        mv    a1, s4                    ; taken
        call  xtake                     ; ...
        li    a0, SUNITS                ; and a stack slice?
        call  xfind                     ; ...
        bgez  a0, xp_got                ; yes
        mv    a0, s5                    ; no: the data slice back
        mv    a1, s4                    ; ...
        call  xgive                     ; ...
xp_ev:
        mv    a0, s1                    ; evict the least recently run
        call  xvict                     ; ...
        bgez  a0, xp_try                ; and try again
        la    t6, k_panic               ; (nothing to evict: cannot be, alone it fits)
        jalr  zero, t6, 0               ; ...
xp_got:
        li    a1, SUNITS                ; its stack's units (a0) taken
        call  xtake                     ; (keeps a0)
        slli  t0, a0, 8                 ; its residency
        addi  t1, s5, 1                 ; ...
        or    t0, t0, t1                ; ...
        slli  t1, s4, 16                ; ...
        or    t0, t0, t1                ; ...
        ld    t1, w_tick-GPBASE(gp)     ; ...
        slli  t1, t1, 25                ; ...
        or    t0, t0, t1                ; ...
        sd    t0, 0(s3)                 ; ...
        slli  t0, s4, 10                ; xrestore fills both slices whole
        li    t1, STACKTOP - STACKLO    ; ...
        add   t0, t0, t1                ; ...
        ld    t1, w_rbytes-GPBASE(gp)   ; ...
        add   t0, t0, t1                ; ...
        sd    t0, w_rbytes-GPBASE(gp)   ; ...
xp_ret:
        ld    s5, 40(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; ...

; ---- xfind(a0 = n) -> a0 = the first of n free units in a row, or -1 ----------------------------
xfind:
        ld    t0, w_dfree-GPBASE(gp)    ; ...
        li    t1, 1                     ; t1 = n ones
        sll   t1, t1, a0                ; ...
        addi  t1, t1, -1                ; ...
        li    t2, 0                     ; t2 = first unit tried
        li    t3, 64                    ; t3 = the last one that can start n
        sub   t3, t3, a0                ; ...
xf_l:
        blt   t3, t2, xf_no             ; ...
        srl   t4, t0, t2                ; free from t2 on?
        and   t4, t4, t1                ; ...
        beq   t4, t1, xf_yes            ; ...
        addi  t2, t2, 1                 ; ...
        j     xf_l                      ; ...
xf_yes:
        mv    a0, t2                    ; ...
        ret                             ; ...
xf_no:
        li    a0, -1                    ; ...
        ret                             ; ...

; ---- xtake(a0 = unit, a1 = n), xgive(a0, a1): units taken / free again (keep a0) ----------
xtake:
        li    t0, 1                     ; t0 = the units
        sll   t0, t0, a1                ; ...
        addi  t0, t0, -1                ; ...
        sll   t0, t0, a0                ; ...
        ld    t1, w_dfree-GPBASE(gp)    ; cleared
        or    t1, t1, t0                ; ...
        xor   t1, t1, t0                ; ...
        sd    t1, w_dfree-GPBASE(gp)    ; ...
        ret                             ; ...
xgive:
        li    t0, 1                     ; t0 = the units
        sll   t0, t0, a1                ; ...
        addi  t0, t0, -1                ; ...
        sll   t0, t0, a0                ; ...
        ld    t1, w_dfree-GPBASE(gp)    ; set
        or    t1, t1, t0                ; ...
        sd    t1, w_dfree-GPBASE(gp)    ; ...
        ret                             ; ...

; ---- xslices(t0 = residency): its slices back to the free units --------------------------------
xslices:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    t0, 8(sp)                 ; ...
        andi  a0, t0, 255               ; data
        addi  a0, a0, -1                ; ...
        srli  a1, t0, 16                ; ...
        andi  a1, a1, 255               ; ...
        call  xgive                     ; ...
        ld    t0, 8(sp)                 ; stack
        srli  a0, t0, 8                 ; ...
        andi  a0, a0, 255               ; ...
        li    a1, SUNITS                ; ...
        call  xgive                     ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...

; ---- xrel(a0 = slot): a dead thread's slices free, nothing saved --------------------------------
xrel:
        slli  t1, a0, 3                 ; t1 = &w_res[slot]
        add   t1, t1, gp                ; ...
        addi  t1, t1, w_res-GPBASE      ; ...
        ld    t0, 0(t1)                 ; ...
        sd    zero, 0(t1)               ; not resident any more
        andi  t2, t0, 255               ; was it?
        beqz  t2, xr_ret                ; no
        li    t2, RS_EV                 ; (an evicted one gave its units back already)
        and   t2, t0, t2                ; ...
        bnez  t2, xr_ret                ; ...
        j     xslices                   ; (tail call)
xr_ret:
        ret                             ; ...

; ---- xvict(a0 = the slot being loaded) -> a0 = 0, or -1 if no other thread is resident ----------
; The thread to go: a dead one first, else the one that ran least recently.
; A dead one's units are free at once; a live one's too, and it is marked
; for xevict to save (its bytes counted now).
xvict:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        sd    s5, 40(sp)                ; ...
        mv    s1, a0                    ; s1 = the slot to keep
        li    s3, -1                    ; s3 = best so far, s4 = its key (lower goes first)
        li    s4, -1                    ; ...
        li    s5, 0                     ; s5 = slot
xv_l:
        li    t0, NSLOT                 ; ...
        bge   s5, t0, xv_pick           ; ...
        beq   s5, s1, xv_n              ; ...
        slli  t0, s5, 3                 ; resident (and not on its way out)?
        add   t0, t0, gp                ; ...
        ld    t0, w_res-GPBASE(t0)      ; ...
        andi  t1, t0, 255               ; ...
        beqz  t1, xv_n                  ; ...
        li    t1, RS_EV                 ; ...
        and   t1, t0, t1                ; ...
        bnez  t1, xv_n                  ; ...
        srli  s2, t0, 25                ; key: when it last ran, + 1
        addi  s2, s2, 1                 ; ...
        mv    a0, s5                    ; dead: key 0
        la    t6, prec                  ; ...
        jalr  ra, t6, 0                 ; ...
        ld    t0, PR_STARTED(a0)        ; ...
        beqz  t0, xv_dead               ; ...
        ld    t0, PR_STATE(a0)          ; ...
        beqz  t0, xv_dead               ; (S_FREE)
        li    t1, S_ZOMBIE              ; ...
        bne   t0, t1, xv_key            ; ...
xv_dead:
        li    s2, 0                     ; ...
xv_key:
        bgeu  s2, s4, xv_n              ; (s4 = -1: anything is better)
        mv    s3, s5                    ; ...
        mv    s4, s2                    ; ...
xv_n:
        addi  s5, s5, 1                 ; ...
        j     xv_l                      ; ...
xv_pick:
        li    a0, -1                    ; none
        bltz  s3, xv_ret                ; ...
        bnez  s4, xv_live               ; ...
        mv    a0, s3                    ; dead: its units free, nothing saved
        call  xrel                      ; ...
        li    a0, 0                     ; ...
        j     xv_ret                    ; ...
xv_live:
        slli  s5, s3, 3                 ; s5 = &w_res[victim]
        add   s5, s5, gp                ; ...
        addi  s5, s5, w_res-GPBASE      ; ...
        ld    t0, 0(s5)                 ; its units free now (its save is issued before
        call  xslices                   ;   anything else lands there: xevict comes first)
        ld    t0, 0(s5)                 ; marked: xevict saves it
        li    t1, RS_EV                 ; ...
        or    t0, t0, t1                ; ...
        sd    t0, 0(s5)                 ; ...
        ld    t0, w_evm-GPBASE(gp)      ; ...
        li    t1, 1                     ; ...
        sll   t1, t1, s3                ; ...
        or    t0, t0, t1                ; ...
        sd    t0, w_evm-GPBASE(gp)      ; ...
        mv    a0, s3                    ; s2 = its record: count what its save moves
        la    t6, prec                  ; ...
        jalr  ra, t6, 0                 ; ...
        mv    s2, a0                    ; ...
        ld    a1, 0(s5)                 ; ...
        li    a0, 0                     ; (count only)
        call  xsave                     ; ...
        la    t6, w_count               ; ...
        jalr  ra, t6, 0                 ; ...
        li    a0, 0                     ; ...
xv_ret:
        ld    s5, 40(sp)                ; ...
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        ret                             ; ...

; ---- xsave(s2 = record, a0 = 0 count / 1 save, a1 = its residency) -> a0 = bytes ----------------
; What an evicted thread keeps: its data extent [0, PR_DEND) without its
; scratch range (SET_SCRATCH), and its live stack [sp, 0x10000), from where
; its slices are to its save area (data at 0, the stack at 0xA000.. for
; 0xE000..), data on tg14, the stack on tg15. Not waited for: one core's
; transfers act in issue order (I2), so what lands in those units next
; cannot overtake the save, and a store that would overwrite bytes still
; being read waits (I1).
xsave:
        addi  sp, sp, -56               ; frame (48(sp): a scratch range's end)
        sd    ra, 0(sp)                 ; ...
        sd    s3, 8(sp)                 ; ...
        sd    s4, 16(sp)                ; ...
        sd    s5, 24(sp)                ; ...
        sd    a0, 32(sp)                ; 40(sp) = bytes so far
        sd    zero, 40(sp)              ; ...
        andi  s3, a1, 255               ; s3 = the data slice's address
        addi  s3, s3, -1                ; ...
        slli  s3, s3, 10                ; ...
        srli  s4, a1, 8                 ; s4 = the stack slice's address
        andi  s4, s4, 255               ; ...
        slli  s4, s4, 10                ; ...
        beqz  a0, xs_go                 ; counting: no capability
        ld    a0, PR_SSL(s2)            ; c8 = the save area
        andi  a0, a0, 255               ; ...
        la    t6, crs8                  ; ...
        jalr  ra, t6, 0                 ; ...
xs_go:
        ld    s5, PR_DEND(s2)           ; s5 = the extent's end
        ld    t3, PR_SCRB(s2)           ; the scratch range (none: 0, 0)
        ld    t4, PR_SCRE(s2)           ; ...
        bgeu  t3, t4, xs_whole          ; none
        bgeu  t3, s5, xs_whole          ; beyond the extent
        bleu  t4, s5, xs_two            ; inside it
        mv    t4, s5                    ; (it reaches the end)
xs_two:
        sd    t4, 48(sp)                ; (keep the range's end)
        li    a2, 0                     ; [0, start)
        mv    a3, t3                    ; ...
        call  xs_move                   ; ...
        ld    a2, 48(sp)                ; [end of the range, extent end)
        sub   a3, s5, a2                ; ...
        call  xs_move                   ; ...
        j     xs_stack                  ; ...
xs_whole:
        li    a2, 0                     ; all of [0, extent end)
        mv    a3, s5                    ; ...
        call  xs_move                   ; ...
xs_stack:
        ld    t0, PR_REGS+16(s2)        ; its sp, 8-aligned, inside [STACKLO, STACKTOP]
        srli  t0, t0, 3                 ; ...
        slli  t0, t0, 3                 ; ...
        li    t1, STACKLO               ; ...
        bgeu  t0, t1, xs_hi             ; ...
        mv    t0, t1                    ; ...
xs_hi:
        li    t1, STACKTOP              ; ...
        bleu  t0, t1, xs_sp             ; ...
        mv    t0, t1                    ; ...
xs_sp:
        sub   t2, t1, t0                ; t2 = its length
        beqz  t2, xs_done               ; ...
        ld    t1, 40(sp)                ; counted
        add   t1, t1, t2                ; ...
        sd    t1, 40(sp)                ; ...
        ld    t1, 32(sp)                ; saving?
        beqz  t1, xs_done               ; ...
        li    t1, STACKLO               ; t0 -> offset in the stack slice / the save area
        sub   t0, t0, t1                ; ...
        add   t1, s4, t0                ; the D-LS address
        li    t3, DATAMAX               ; the save area offset
        add   t3, t3, t0                ; ...
        ld    t4, PR_SOB(s2)            ; ...
        add   t3, t3, t4                ; ...
        tput  tg15, t1, c8, t3, t2      ; stack -> save area
xs_done:
        ld    t0, 32(sp)                ; saving: the save area back
        beqz  t0, xs_ret                ; ...
        ld    a0, PR_SSL(s2)            ; ...
        andi  a0, a0, 255               ; ...
        la    t6, csv8                  ; ...
        jalr  ra, t6, 0                 ; ...
xs_ret:
        ld    a0, 40(sp)                ; ...
        ld    s5, 24(sp)                ; ...
        ld    s4, 16(sp)                ; ...
        ld    s3, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 56                ; ...
        ret                             ; ...
xs_move:                                ; (local) a3 bytes at virtual a2 (in xsave's frame)
        beqz  a3, xm_ret                ; ...
        ld    t0, 40(sp)                ; counted (the caller's frame: no frame of our own)
        add   t0, t0, a3                ; ...
        sd    t0, 40(sp)                ; ...
        ld    t0, 32(sp)                ; saving?
        beqz  t0, xm_ret                ; ...
        add   t1, s3, a2                ; the D-LS address
        ld    t0, PR_SOB(s2)            ; the save area offset
        add   t0, t0, a2                ; ...
        tput  tg14, t1, c8, t0, a3      ; data -> save area
xm_ret:
        ret                             ; ...

; ---- xevict(): the saves xplan decided (w_evm), issued; those slots not resident ----------------
xevict:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        li    s1, 0                     ; s1 = slot
xe_l:
        ld    t0, w_evm-GPBASE(gp)      ; ...
        srl   t0, t0, s1                ; ...
        beqz  t0, xe_ret                ; none left
        andi  t0, t0, 1                 ; this one?
        beqz  t0, xe_n                  ; ...
        mv    a0, s1                    ; s2 = its record
        la    t6, prec                  ; ...
        jalr  ra, t6, 0                 ; ...
        mv    s2, a0                    ; ...
        slli  s3, s1, 3                 ; s3 = &w_res[slot]
        add   s3, s3, gp                ; ...
        addi  s3, s3, w_res-GPBASE      ; ...
        ld    a1, 0(s3)                 ; ...
        li    a0, 1                     ; save
        call  xsave                     ; ...
        sd    zero, 0(s3)               ; not resident
xe_n:
        addi  s1, s1, 1                 ; ...
        j     xe_l                      ; ...
xe_ret:
        sd    zero, w_evm-GPBASE(gp)    ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

; ---- xrestore(a0 = slot): its D-LS in, if xplan gave it new slices; its windows ------------------
; New slices take all of the data window and the stack window from the save
; area (tg12, tg13): beyond what it saved, the save area holds zeros (it is
; scrubbed with the arena, CREATE takes only scrubbed arenas, and only xsave
; writes there) or older bytes of this same thread, never another's. A
; first load then takes the image's data section on top (tg14; transfers act
; in issue order). None of it is waited for: the thread may run while its
; bytes arrive (a load or store that touches them waits).
xrestore:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s2, 8(sp)                 ; ...
        sd    s3, 16(sp)                ; ...
        sd    s4, 24(sp)                ; ...
        slli  t0, a0, 3                 ; s3 = its residency
        add   t0, t0, gp                ; ...
        ld    s3, w_res-GPBASE(t0)      ; ...
        la    t6, prec                  ; s2 = its record
        jalr  ra, t6, 0                 ; ...
        mv    s2, a0                    ; ...
        andi  s4, s3, 255               ; s4 = the data slice's address
        addi  s4, s4, -1                ; ...
        slli  s4, s4, 10                ; ...
        ld    t0, w_rbytes-GPBASE(gp)   ; new slices?
        beqz  t0, xr_win                ; no: resident, nothing moves
        ld    a0, PR_SSL(s2)            ; c8 = the save area
        andi  a0, a0, 255               ; ...
        la    t6, crs8                  ; ...
        jalr  ra, t6, 0                 ; ...
        ld    t3, PR_SOB(s2)            ; the data window: [0, units) <- save area 0..
        srli  t2, s3, 16                ; ...
        andi  t2, t2, 255               ; ...
        slli  t2, t2, 10                ; ...
        tget  tg12, s4, c8, t3, t2      ; ...
        srli  t1, s3, 8                 ; the stack window <- save area 0xA000..
        andi  t1, t1, 255               ; ...
        slli  t1, t1, 10                ; ...
        li    t2, DATAMAX               ; ...
        add   t3, t3, t2                ; ...
        li    t2, STACKTOP - STACKLO    ; ...
        tget  tg13, t1, c8, t3, t2      ; ...
        ld    a0, PR_SSL(s2)            ; the save area back
        andi  a0, a0, 255               ; ...
        la    t6, csv8                  ; ...
        jalr  ra, t6, 0                 ; ...
        ld    t0, PR_STARTED(s2)        ; a first load?
        bnez  t0, xr_win                ; no
        ld    a0, PR_ISL(s2)            ; c8 = the image share
        andi  a0, a0, 255               ; ...
        la    t6, crs8                  ; ...
        jalr  ra, t6, 0                 ; ...
        ld    t1, PR_DATA(s2)           ; the image's data section, over the zeros
        li    t2, 0xffff                ; address
        and   t3, t1, t2                ; ...
        srli  t4, t1, 16                ; length
        and   t4, t4, t2                ; ...
        srli  t5, t1, 32                ; image offset (arena offset)
        li    t0, A_IMG                 ; relative to the image share
        sub   t5, t5, t0                ; ...
        beqz  t4, xr_ib                 ; no data
        add   t3, t3, s4                ; (in the data slice)
        tget  tg14, t3, c8, t5, t4      ; image -> D-LS
xr_ib:
        ld    a0, PR_ISL(s2)            ; the share back
        andi  a0, a0, 255               ; ...
        la    t6, csv8                  ; ...
        jalr  ra, t6, 0                 ; ...
xr_win:
        li    t0, WIN_EN                ; wdata: [0, units) -> the data slice
        srli  t1, s3, 16                ; ...
        andi  t1, t1, 255               ; ...
        slli  t1, t1, 8                 ; ...
        or    t0, t0, t1                ; ...
        srli  t1, s4, 10                ; ...
        slli  t1, t1, 16                ; ...
        or    t0, t0, t1                ; ...
        csrw  wdata, t0                 ; ...
        li    t0, WIN_EN | (STACKLO >> 10) | (SUNITS << 8) ; wstack: [STACKLO, STACKTOP) -> its stack slice
        srli  t1, s3, 8                 ; ...
        andi  t1, t1, 255               ; ...
        slli  t1, t1, 16                ; ...
        or    t0, t0, t1                ; ...
        csrw  wstack, t0                ; ...
        ld    s4, 24(sp)                ; ...
        ld    s3, 16(sp)                ; ...
        ld    s2, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        ret                             ; ...

        .align 8                        ; ...
xend:                                   ; (at most xstart + 0x900: XBASE + 0x900 = 0x8000)
        .org  xstart + 0x900            ; (an error here: the extension is too large)
