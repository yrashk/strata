; =============================================================================
; kunits/ops.s: the system core's message operations (code units)
; =============================================================================
;
; Requests reach the system core through its endpoint, which only proc
; (and dev, for HALT) hold. Core 0 registers while serving: c11 = the
; request buffer, c10 = an arena being made into a process, c8/c9 scratch,
; c7 a message buffer piece. The reply is the buffer given back.
;
;   1 CREATE   attachment: an arena from MEMORY with the image at 0xD0000 and
;              the start-up block at 0x7F000; data: u64 pid, ncores (0 =
;              time-shared), flags (F_SERVER 2, F_PRIV 8, F_DEVCAPS 16,
;              F_SOLO 32, F_KEEP 64), pin core (-1 any), endpoint cores for
;              c1..c4 (bytes, 255 none), a0, a1, a2 -> 0, data[0] = first core
;              (on failure the arena comes back as an attachment; for a
;              server, an endpoint to its core comes with the reply)
;   2 DESTROY  handle = pid -> 0 (proc later gets EXITED, status bit 62)
;   3 MEMORY   length = the size wanted (0: 1 MiB; rounded up to whole 256 KiB
;              granules, at least 1 MiB) -> 0 and a fresh arena (attachment),
;              data[0] = its base, data[1] = its size; -6 no memory or no slot
;   4 STATS    -> process count; data: 8 words (cores, free heap, total heap,
;              units loaded, switches, KiB moved, processes, 0), 32 bytes per
;              core (pid running | runnable << 8 | processes << 16 | flags << 24 |
;              cycles per switch << 32, switches, KiB, free save-table slots |
;              cycles per trap << 32), then 32 bytes per process (pid | core << 8 |
;              state << 16 | flags << 24, ncores, switches, bytes)
;   5 TUNE     length = the time slice in ticks (100..100000) -> 0, -1 (proc only)
;   9 NOTIFY   handle = pid, length = bits -> 0 (wakes NOTIFY_WAIT / a sleep)
;   6 FREE     attachment: an arena (unused from MEMORY, or from EXITED) -> 0
;   8 HALT     stops every core (waits until the workers' dispatchers have stopped
;              their processes, then writes the console's release port, the
;              pointer's EVENT port and DEADLINE 0, so that no core halts with
;              a device read pending)
;  10 FBLEND   (dev only) handle = pid -> 0 and the framebuffer memory
;              (attachment): every older capability of its region is revoked
;              and that process is its holder until it ends (then the kernel
;              revokes it again); -7 a live process holds it; -1 none / bad pid

F_KEEP   = 64                           ; CREATE: give the arena to proc at exit (old-protocol output)

; ---- u_req: a request from core a0 (buffer in c8) -----------------------------------------
        .align 2048                     ; a unit of its own
u_req:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        mv    s1, a0                    ; s1 = the sender core
        cclear c11                      ; ...
        cmov  c11, c8                   ; c11 = the request
        la    t0, k_hdr                 ; header -> D-LS
        li    t1, 64                    ; ...
        tget  tg0, t0, c11, zero, t1    ; ...
        la    t0, k_cdata               ; first data words -> D-LS
        tget  tg0, t0, c11, t1, t1      ; ...
        twait 1                         ; ...
        cbase a0, c11                   ; who sent it
        la    t6, pid_of                ; ...
        jalr  ra, t6, 0                 ; ...
        mv    s2, a0                    ; s2 = requester pid
        ld    t0, k_hdr-GPBASE(gp)      ; op
        li    t1, 1                     ; CREATE
        beq   t0, t1, ur_create         ; ...
        li    t1, 2                     ; DESTROY
        beq   t0, t1, ur_destroy        ; ...
        li    t1, 3                     ; MEMORY
        beq   t0, t1, ur_memory         ; ...
        li    t1, 4                     ; STATS
        beq   t0, t1, ur_stats          ; ...
        li    t1, 5                     ; TUNE
        beq   t0, t1, ur_tune           ; ...
        li    t1, 9                     ; NOTIFY
        beq   t0, t1, ur_notify         ; ...
        li    t1, 6                     ; FREE
        beq   t0, t1, ur_free           ; ...
        li    t1, 8                     ; HALT
        beq   t0, t1, ur_halt           ; ...
        li    t1, 10                    ; FBLEND
        beq   t0, t1, ur_fblend         ; ...
        li    a0, -1                    ; unknown
        j     ur_reply                  ; ...
ur_create:
        mv    a0, s1                    ; the arena came just before
        la    t5, u_opcreate            ; ...
        xcall ra, c12, t5               ; ...
        j     ur_reply                  ; ...
ur_destroy:
        ld    a0, k_hdr+8-GPBASE(gp)    ; the pid
        la    t5, u_destroy             ; ...
        xcall ra, c12, t5               ; ...
        j     ur_reply                  ; ...
ur_memory:
        mv    a0, s2                    ; for the requester (its owner for now)
        ld    a1, k_hdr+16-GPBASE(gp)   ; the size it asks for
        la    t5, u_alloc               ; c10 = a fresh arena, a0 = slot
        xcall ra, c12, t5               ; ...
        bltz  a0, ur_nomem              ; none
        slli  t0, a0, 5                 ; its slot
        li    t1, K0_AR                 ; ...
        add   t0, t0, t1                ; ...
        la    t1, k_cdata               ; data[0] = its base, data[1] = its size
        ld    t2, AR_BASE(t0)           ; ...
        sd    t2, 0(t1)                 ; ...
        ld    t2, AR_SIZE(t0)           ; ...
        sd    t2, 8(t1)                 ; ...
        li    t2, 64                    ; ...
        li    t3, 16                    ; ...
        tput  tg0, t1, c11, t2, t3      ; ...
        cgive c10, s1                   ; the arena: an attachment before the reply
        li    a0, 0                     ; ...
        j     ur_reply                  ; ...
ur_nomem:
        li    a0, -6                    ; no memory
        j     ur_reply                  ; ...
ur_fblend:
        li    t0, 2                     ; only dev
        bne   s2, t0, ur_bad            ; ...
        ld    t0, k_hasfb-GPBASE(gp)    ; is there one?
        beqz  t0, ur_bad                ; ...
        ld    a0, k_fbpid-GPBASE(gp)    ; held by a live process?
        beqz  a0, ufb_free              ; ...
        la    t6, kp_find               ; ...
        jalr  ra, t6, 0                 ; ...
        li    t0, -7                    ; ...
        bnez  a0, ufb_ret               ; yes: busy
ufb_free:
        ld    a0, k_hdr+8-GPBASE(gp)    ; the new holder must exist
        la    t6, kp_find               ; ...
        jalr  ra, t6, 0                 ; ...
        beqz  a0, ur_bad                ; ...
        ld    t0, k_hdr+8-GPBASE(gp)    ; ...
        sd    t0, k_fbpid-GPBASE(gp)    ; ...
        li    a0, K_FB                  ; the revoker
        la    t6, crs8                  ; ...
        jalr  ra, t6, 0                 ; ...
        cclear c10                      ; ...
        crevoke c10, c8                 ; older capabilities die; c10 = a fresh one
        li    a0, K_FB                  ; the revoker back
        la    t6, csv8                  ; ...
        jalr  ra, t6, 0                 ; ...
        cgive c10, s1                   ; the memory: an attachment before the reply
        li    t0, 0                     ; ...
ufb_ret:
        mv    a0, t0                    ; ...
        j     ur_reply                  ; ...
ur_stats:
        la    t5, u_stats               ; ...
        xcall ra, c12, t5               ; ...
        j     ur_reply                  ; ...
ur_tune:
        li    t0, 1                     ; only proc
        bne   s2, t0, ur_bad            ; ...
        ld    t0, k_hdr+16-GPBASE(gp)   ; the slice (length field), 100 us .. 100 ms
        li    t1, 100                   ; ...
        bltu  t0, t1, ur_bad            ; ...
        li    t1, 100000                ; ...
        bgtu  t0, t1, ur_bad            ; ...
        sd    t0, k_slice-GPBASE(gp)    ; from the next tick on
        li    a0, 0                     ; ...
        j     ur_reply                  ; ...
ur_notify:
        ld    a0, k_hdr+8-GPBASE(gp)    ; pid
        la    t6, kp_find               ; ...
        jalr  ra, t6, 0                 ; ...
        beqz  a0, ur_bad                ; no such process
        mv    s2, a0                    ; ...
        ld    t0, KP_CORE(s2)           ; its (first) core's notification word for its slot
        slli  t0, t0, 10                ; ...
        ld    t1, KP_SLOT(s2)           ; (thread 0's slot: the low 4 bits)
        andi  t1, t1, 15                ; ...
        slli  t1, t1, 3                 ; ...
        add   a0, t0, t1                ; ...
        addi  a0, a0, CAREA + CA_NOTE   ; ...
        ld    a1, k_hdr+16-GPBASE(gp)   ; the bits
        la    t6, kst_or                ; ...
        jalr  ra, t6, 0                 ; ...
        ld    a0, KP_CORE(s2)           ; wake it
        la    t6, k_wake                ; ...
        jalr  ra, t6, 0                 ; ...
        li    a0, 0                     ; ...
        j     ur_reply                  ; ...
ur_free:
        mv    a0, s1                    ; the arena came just before
        la    t5, u_free                ; ...
        xcall ra, c12, t5               ; ...
        j     ur_reply                  ; ...
ur_halt:
        la    t5, u_halt                ; does not return
        xcall ra, c12, t5               ; ...
ur_bad:
        li    a0, -1                    ; ...
ur_reply:
        la    t0, k_hdr                 ; the result
        sd    a0, 32(t0)                ; ...
        li    t1, 64                    ; ...
        tput  tg0, t0, c11, zero, t1    ; ...
        twait 1                         ; ...
        cgive c11, s1                   ; the reply: the buffer goes back
        mv    a0, s1                    ; and its core looks at once
        la    t6, k_ring                ; ...
        jalr  ra, t6, 0                 ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        xret  ra                        ; ...
        .org  u_req + 2048              ; (the unit must fit its slot)

; ---- u_opcreate: CREATE from proc (a0 = its core) ------------------------------------------
u_opcreate:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        mv    s1, a0                    ; s1 = proc's core
        la    t6, k_unstash             ; the arena it sent just before
        jalr  ra, t6, 0                 ; ...
        bnez  a0, uoc_bad               ; none
        cbase t0, c8                    ; which arena slot?
        li    s2, 0                     ; ...
        li    t1, K0_AR                 ; ...
uoc_f:
        li    t2, NARENA                ; ...
        bge   s2, t2, uoc_back          ; not one of ours
        ld    t2, AR_STATE(t1)          ; one MEMORY gave out
        li    t3, 1                     ; ...
        bne   t2, t3, uoc_n             ; ...
        ld    t2, AR_BASE(t1)           ; at this base?
        beq   t2, t0, uoc_have          ; ...
uoc_n:
        addi  s2, s2, 1                 ; ...
        addi  t1, t1, AR_SZ             ; ...
        j     uoc_f                     ; ...
uoc_have:
        clen  t2, c8                    ; and whole
        ld    t3, AR_SIZE(t1)           ; ...
        bne   t2, t3, uoc_back          ; ...
        sd    s2, cr_aslot-GPBASE(gp)   ; ...
        cclear c10                      ; ...
        cmov  c10, c8                   ; c10 = the arena
        la    t0, k_cdata               ; the parameters
        ld    t1, 0(t0)                 ; pid
        sd    t1, cr_pid-GPBASE(gp)     ; ...
        ld    t1, 8(t0)                 ; ncores
        sd    t1, cr_ncores-GPBASE(gp)  ; ...
        ld    t1, 16(t0)                ; flags (only these may be asked for)
        andi  t1, t1, F_SERVER | F_PRIV | F_DEVCAPS | F_SOLO | F_KEEP ; ...
        sd    t1, cr_flags-GPBASE(gp)   ; ...
        ld    t1, 24(t0)                ; pin
        sd    t1, cr_pin-GPBASE(gp)     ; ...
        ld    t1, 32(t0)                ; endpoint cores
        sd    t1, cr_eps-GPBASE(gp)     ; ...
        ld    t1, 40(t0)                ; a0..a2
        sd    t1, cr_a0-GPBASE(gp)      ; ...
        ld    t1, 48(t0)                ; ...
        sd    t1, cr_a1-GPBASE(gp)      ; ...
        ld    t1, 56(t0)                ; ...
        sd    t1, cr_a2-GPBASE(gp)      ; ...
        ld    a0, cr_pid-GPBASE(gp)     ; the pid must be new
        beqz  a0, uoc_back1             ; ...
        la    t6, kp_find               ; ...
        jalr  ra, t6, 0                 ; ...
        bnez  a0, uoc_back1             ; in use
        la    t5, u_create              ; make it
        xcall ra, c12, t5               ; a0 = 0 or an error
        bnez  a0, uoc_fail              ; ...
        ld    t0, cr_flags-GPBASE(gp)   ; a server: proc gets an endpoint to it
        andi  t0, t0, F_SERVER          ; ...
        beqz  t0, uoc_data              ; ...
        ld    t0, cr_core-GPBASE(gp)    ; (send-only, as an attachment before the reply)
        cmkep c8, t0                    ; ...
        li    t0, 2 | 16                ; ...
        crestrict c8, c8, t0            ; ...
        cgive c8, s1                    ; ...
uoc_data:
        ld    t0, cr_core-GPBASE(gp)    ; data[0] = its core
        la    t1, k_cdata               ; ...
        sd    t0, 0(t1)                 ; ...
        li    t2, 64                    ; ...
        li    t3, 8                     ; ...
        tput  tg0, t1, c11, t2, t3      ; ...
        li    a0, 0                     ; ...
        j     uoc_ret                   ; ...
uoc_back1:
        li    a0, -1                    ; refused: the arena goes back
uoc_fail:
        cgive c10, s1                   ; (as an attachment before the reply)
        j     uoc_ret                   ; ...
uoc_back:
        cgive c8, s1                    ; not an arena we gave: back it goes
uoc_bad:
        li    a0, -1                    ; ...
uoc_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        xret  ra                        ; ...
        .org  u_opcreate + 2048         ; (the unit must fit its slot)

; ---- u_alloc(a0 = owner pid, a1 = size wanted) -> c10 = a fresh arena, a0 = slot (or -1) ----
; The size is rounded up to whole granules, 1 MiB at least; the arena is the
; first run of that many free granules of the pool (first fit).
u_alloc:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        mv    s4, a0                    ; s4 = the owner
        li    t0, GRAN - 1              ; whole granules
        add   a1, a1, t0                ; ...
        srli  s2, a1, GSHIFT            ; s2 = granules
        li    t0, ARENA >> GSHIFT       ; 1 MiB at least (the arena's layout needs it)
        bgeu  s2, t0, ual_sz            ; ...
        mv    s2, t0                    ; ...
ual_sz:
        li    s1, K0_AR                 ; a free slot
        li    t1, NARENA                ; ...
ual_sl:
        ld    t2, AR_STATE(s1)          ; ...
        beqz  t2, ual_run               ; ...
        addi  s1, s1, AR_SZ             ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, ual_sl                ; ...
        j     ual_none                  ; all in use
ual_run:
        li    s3, 0                     ; s3 = the next granule to look at
        li    t3, 0                     ; t3 = free granules in a row so far
        ld    t4, k_pgran-GPBASE(gp)    ; ...
ual_g:
        bgeu  t3, s2, ual_got           ; enough
        bgeu  s3, t4, ual_none          ; the end of the pool
        srli  t0, s3, 6                 ; its bit
        slli  t0, t0, 3                 ; ...
        ld    t0, K0_GMAP(t0)           ; ...
        srl   t0, t0, s3                ; (shifts are mod 64)
        andi  t0, t0, 1                 ; ...
        addi  s3, s3, 1                 ; ...
        addi  t3, t3, 1                 ; one more free ...
        beqz  t0, ual_g                 ; ...
        li    t3, 0                     ; ... or the row starts again
        j     ual_g                     ; ...
ual_got:
        sub   s3, s3, s2                ; s3 = the run's first granule
        mv    t0, s3                    ; mark the run used
        add   t1, s3, s2                ; ...
ual_m:
        srli  t2, t0, 6                 ; ...
        slli  t2, t2, 3                 ; ...
        ld    t4, K0_GMAP(t2)           ; ...
        li    t5, 1                     ; ...
        sll   t5, t5, t0                ; ...
        or    t4, t4, t5                ; ...
        sd    t4, K0_GMAP(t2)           ; ...
        addi  t0, t0, 1                 ; ...
        bltu  t0, t1, ual_m             ; ...
        ld    t0, k_pfree-GPBASE(gp)    ; fewer free
        sub   t0, t0, s2                ; ...
        sd    t0, k_pfree-GPBASE(gp)    ; ...
        slli  t0, s3, GSHIFT            ; the slot: base, size, issued
        ld    t1, k_pbase-GPBASE(gp)    ; ...
        add   t0, t0, t1                ; ...
        sd    t0, AR_BASE(s1)           ; ...
        slli  t0, s2, GSHIFT            ; ...
        sd    t0, AR_SIZE(s1)           ; ...
        li    t0, 1                     ; ...
        sd    t0, AR_STATE(s1)          ; ...
        li    t0, K0_AR                 ; s1 = the slot's number
        sub   s1, s1, t0                ; ...
        srli  s1, s1, 5                 ; ...
        mv    a0, s1                    ; its granules belong to the owner (pid_of)
        mv    a1, s4                    ; ...
        la    t5, u_own                 ; ...
        xcall ra, c12, t5               ; ...
        mv    a0, s1                    ; a fresh capability for it: whatever an
        la    t5, u_arcap               ;   earlier owner had there is dead
        xcall ra, c12, t5               ; ...
        cclear c10                      ; ...
        cmov  c10, c13                  ; ...
        li    t0, K0_BOUNCE             ; scrub it: nothing of its last owner may remain
        li    t1, 4096 / 8              ; (a zeroed bounce buffer, written over and over)
ual_z:
        sd    zero, 0(t0)               ; ...
        addi  t0, t0, 8                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, ual_z                 ; ...
        li    t0, K0_BOUNCE             ; ...
        li    t1, 4096                  ; ...
        li    t2, 0                     ; ...
        slli  t3, s2, GSHIFT            ; ...
ual_s:
        tput  tg0, t0, c10, t2, t1      ; zeros -> the arena
        add   t2, t2, t1                ; ...
        bltu  t2, t3, ual_s             ; ...
        twait 1                         ; ...
        mv    a0, s1                    ; the slot
        j     ual_ret                   ; ...
ual_none:
        li    a0, -1                    ; ...
ual_ret:
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        xret  ra                        ; ...
        .org  u_alloc + 2048            ; (the unit must fit its slot)

; ---- u_arcap(a0 = arena slot) -> c13 = a fresh capability for that arena ---------------------
; Revocation by address: the pool's revoker is cut at the arena's bounds, the
; piece revoked (every capability based in the arena dies, whoever holds it,
; and a fresh working capability comes out) and the revoker joined again.
; Uses c8 (must be free), c13, c14, c15.
u_arcap:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        slli  t0, a0, 5                 ; the slot
        li    t1, K0_AR                 ; ...
        add   t0, t0, t1                ; ...
        ld    s1, AR_BASE(t0)           ; s1 = its offset in its part of the pool
        ld    s2, AR_SIZE(t0)           ; s2 = its size
        sd    s3, 24(sp)                ; ...
        li    s3, K_POOL                ; s3 = that part's revoker: the low part ...
        ld    t1, k_pbase-GPBASE(gp)    ; ...
        ld    t2, k_p2base-GPBASE(gp)   ; ... or the high one
        beqz  t2, uac_lo                ; ...
        bltu  s1, t2, uac_lo            ; ...
        li    s3, K_POOL2               ; ...
        mv    t1, t2                    ; ...
uac_lo:
        sub   s1, s1, t1                ; ...
        mv    a0, s3                    ; c8 = the revoker
        la    t6, crs8                  ; ...
        jalr  ra, t6, 0                 ; ...
        cclear c13                      ; ...
        cclear c14                      ; ...
        cclear c15                      ; ...
        csplit c13, c8, s1              ; c8 = below the arena, c13 = from it on
        csplit c14, c13, s2             ; c13 = the arena's revoker, c14 = above it
        crevoke c15, c13                ; c15 = fresh; everything older dies
        cjoin c13, c14                  ; the revoker whole again
        cjoin c8, c13                   ; ...
        cmov  c13, c15                  ; the result
        mv    a0, s3                    ; the revoker back
        la    t6, csv8                  ; ...
        jalr  ra, t6, 0                 ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        xret  ra                        ; ...
        .org  u_arcap + 2048            ; (the unit must fit its slot)

; ---- u_own(a0 = arena slot, a1 = pid): its granules belong to pid (for pid_of) ----------------
u_own:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        mv    s3, a1                    ; s3 = the pid
        slli  t0, a0, 5                 ; the slot
        li    t1, K0_AR                 ; ...
        add   t0, t0, t1                ; ...
        ld    s1, AR_BASE(t0)           ; s1 = its first granule
        ld    t1, k_pbase-GPBASE(gp)    ; ...
        sub   s1, s1, t1                ; ...
        srli  s1, s1, GSHIFT            ; ...
        ld    s2, AR_SIZE(t0)           ; s2 = one past its last
        srli  s2, s2, GSHIFT            ; ...
        add   s2, s2, s1                ; ...
uow_l:
        bgeu  s1, s2, uow_d             ; ...
        slli  a0, s1, 3                 ; KST: the granule's owner
        addi  a0, a0, G_GPID            ; ...
        mv    a1, s3                    ; ...
        la    t6, kst_wr                ; ...
        jalr  ra, t6, 0                 ; ...
        addi  s1, s1, 1                 ; ...
        j     uow_l                     ; ...
uow_d:
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        xret  ra                        ; ...
        .org  u_own + 2048              ; (the unit must fit its slot)

; ---- u_arfree(a0 = arena slot): its granules are free again, the slot too ----------------------
; (its capabilities must have been revoked: u_arcap)
u_arfree:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        mv    s1, a0                    ; s1 = the slot
        li    a1, 0                     ; no owner
        la    t5, u_own                 ; ...
        xcall ra, c12, t5               ; ...
        slli  t0, s1, 5                 ; the slot
        li    t1, K0_AR                 ; ...
        add   t0, t0, t1                ; ...
        ld    t1, AR_BASE(t0)           ; t1 = its first granule
        ld    t2, k_pbase-GPBASE(gp)    ; ...
        sub   t1, t1, t2                ; ...
        srli  t1, t1, GSHIFT            ; ...
        ld    t2, AR_SIZE(t0)           ; t2 = its granules
        srli  t2, t2, GSHIFT            ; ...
        ld    t3, k_pfree-GPBASE(gp)    ; more free
        add   t3, t3, t2                ; ...
        sd    t3, k_pfree-GPBASE(gp)    ; ...
        add   t2, t2, t1                ; t2 = one past the last
uaf_l:
        bgeu  t1, t2, uaf_d             ; clear their bits
        srli  t3, t1, 6                 ; ...
        slli  t3, t3, 3                 ; ...
        ld    t4, K0_GMAP(t3)           ; ...
        li    t5, 1                     ; ...
        sll   t5, t5, t1                ; ...
        or    t4, t4, t5                ; (set, then flip: clear)
        xor   t4, t4, t5                ; ...
        sd    t4, K0_GMAP(t3)           ; ...
        addi  t1, t1, 1                 ; ...
        j     uaf_l                     ; ...
uaf_d:
        sd    zero, AR_STATE(t0)        ; the slot is free
        sd    zero, AR_BASE(t0)         ; ...
        sd    zero, AR_SIZE(t0)         ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        xret  ra                        ; ...
        .org  u_arfree + 2048           ; (the unit must fit its slot)

; ---- u_create: make the process (c10 = its arena, cr_* = parameters) -> a0 ----------------
; Every process time-shares cores. A StrataOS program without -n is one thread
; and has no core window; a bare-metal program, or any program run with -n N,
; has N threads (N >= 1) on N contiguous worker cores, seen through the
; corebase/corecount window.
u_create:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        ld    t0, cr_aslot-GPBASE(gp)   ; E = its arena's size - 1 MiB: the layout base's
        slli  t0, t0, 5                 ;   offset (the image, save areas and buffer
        li    t1, K0_AR                 ;   sit at the top; the program's memory grows)
        add   t0, t0, t1                ; ...
        ld    t0, AR_SIZE(t0)           ; ...
        li    t1, ARENA                 ; ...
        sub   t0, t0, t1                ; ...
        sd    t0, cr_aext-GPBASE(gp)    ; ...
        la    t5, u_parse               ; the image: valid? where is everything?
        xcall ra, c12, t5               ; ...
        bnez  a0, ucr_ret               ; -1: not a program
        ld    t0, cr_flags-GPBASE(gp)   ; one thread, or a window of N
        ld    t1, cr_ncores-GPBASE(gp)  ; ...
        li    t2, 1                     ; ...
        sd    t2, cr_n-GPBASE(gp)       ; (one unless -n)
        andi  t3, t0, F_SYS             ; a StrataOS program without -n: no window
        beqz  t3, ucr_thr               ; ...
        beqz  t1, ucr_place             ; ...
ucr_thr:
        ori   t0, t0, F_THR             ; a window
        sd    t0, cr_flags-GPBASE(gp)   ; ...
        beqz  t1, ucr_place             ; ...
        li    a0, -5                    ; at most MAXTHR threads
        li    t2, MAXTHR                ; ...
        bgtu  t1, t2, ucr_ret           ; ...
        sd    t1, cr_n-GPBASE(gp)       ; N threads
ucr_place:
        la    t5, u_place               ; which cores, which slots
        xcall ra, c12, t5               ; ...
        bnez  a0, ucr_ret               ; -5: no room
        la    t5, u_farcopy             ; far data to its place in the arena
        xcall ra, c12, t5               ; ...
        la    t5, u_launch              ; split the arena, post the jobs, give the pieces
        xcall ra, c12, t5               ; ...
        li    a0, 0                     ; ...
ucr_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        xret  ra                        ; ...
        .org  u_create + 2048           ; (the unit must fit its slot)

; ---- u_parse: read the STX headers of the image at arena 0xD0000 (+ E) ----------------------
; -> a0 = 0 and cr_code / cr_data / cr_far / cr_farof (offsets from the layout
; base), F_SYS in cr_flags if the program carries the "SYS2" marker; -1 if it
; is not a StrataOS program
u_parse:
        sd    zero, cr_code-GPBASE(gp)  ; nothing yet
        sd    zero, cr_data-GPBASE(gp)  ; ...
        sd    zero, cr_far-GPBASE(gp)   ; ...
        li    t0, K0_SCR                ; magic and section count
        ld    t1, cr_aext-GPBASE(gp)    ; ...
        li    t2, A_IMG                 ; ...
        add   t1, t1, t2                ; ...
        li    t2, 8                     ; ...
        tget  tg0, t0, c10, t1, t2      ; ...
        lwu   t3, K0_SCR(zero)          ; "STX2"
        li    t4, 0x32585453            ; ...
        bne   t3, t4, upa_bad           ; ...
        lwu   t5, K0_SCR+4(zero)        ; sections
        li    t4, 4                     ; at most four
        bgtu  t5, t4, upa_bad           ; ...
        li    t6, 8                     ; t6 = image offset of the next section header
upa_sect:
        beqz  t5, upa_check             ; all seen
        li    t0, K0_SCR                ; the header
        ld    t1, cr_aext-GPBASE(gp)    ; ...
        li    t2, A_IMG                 ; ...
        add   t1, t1, t2                ; ...
        add   t1, t1, t6                ; ...
        li    t2, 16                    ; ...
        tget  tg0, t0, c10, t1, t2      ; ...
        addi  t6, t6, 16                ; t6 = offset of its bytes
        lwu   a1, K0_SCR(zero)          ; kind
        lwu   a2, K0_SCR+4(zero)        ; address
        lwu   a3, K0_SCR+8(zero)        ; size
        add   t0, t6, a3                ; must lie inside the image area
        li    t1, IMG_MAX               ; ...
        bgtu  t0, t1, upa_bad           ; ...
        li    t1, A_IMG                 ; a4 = arena offset of the bytes
        add   a4, t1, t6                ; ...
        slli  a5, a4, 32                ; packed: addr | size << 16 | offset << 32
        slli  t0, a3, 16                ; ...
        or    a5, a5, t0                ; ...
        or    a5, a5, a2                ; ...
        li    t0, 1                     ; code
        beq   a1, t0, upa_code          ; ...
        li    t0, 2                     ; data
        beq   a1, t0, upa_data          ; ...
        li    t0, 3                     ; far data
        beq   a1, t0, upa_far           ; ...
        j     upa_bad                   ; nothing else
upa_code:
        li    t0, PTEXT                 ; at 0x8000 and up
        bltu  a2, t0, upa_bad           ; ...
        add   t0, a2, a3                ; within the I-LS
        li    t1, STACKTOP              ; ...
        bgtu  t0, t1, upa_bad           ; ...
        beqz  a3, upa_bad               ; some code
        sd    a5, cr_code-GPBASE(gp)    ; ...
        j     upa_next                  ; ...
upa_data:
        add   t0, a2, a3                ; below the kernel's data
        li    t1, DATAMAX               ; ...
        bgtu  t0, t1, upa_bad           ; ...
        sd    a5, cr_data-GPBASE(gp)    ; ...
        j     upa_next                  ; ...
upa_far:
        add   t0, a2, a3                ; below the start-up block
        li    t1, A_START               ; ...
        bgtu  t0, t1, upa_bad           ; ...
        slli  t0, a3, 32                ; addr | size << 32
        or    t0, t0, a2                ; ...
        sd    t0, cr_far-GPBASE(gp)     ; ...
        sd    a4, cr_farof-GPBASE(gp)   ; ...
upa_next:
        add   t6, t6, a3                ; the next header follows the bytes
        addi  t5, t5, -1                ; ...
        j     upa_sect                  ; ...
upa_check:
        ld    t0, cr_code-GPBASE(gp)    ; code is required
        beqz  t0, upa_bad               ; ...
        srli  t1, t0, 32                ; its first two words: is word 1 "SYS2"?
        ld    t2, cr_aext-GPBASE(gp)    ; ...
        add   t1, t1, t2                ; ...
        li    t2, K0_SCR                ; ...
        li    t3, 8                     ; ...
        tget  tg0, t2, c10, t1, t3      ; ...
        lwu   t4, K0_SCR+4(zero)        ; ...
        li    t5, 0x32535953            ; "SYS2"
        bne   t4, t5, upa_ok            ; a bare-metal program
        ld    t0, cr_flags-GPBASE(gp)   ; a StrataOS program
        ori   t0, t0, F_SYS             ; ...
        sd    t0, cr_flags-GPBASE(gp)   ; ...
upa_ok:
        li    a0, 0                     ; ...
        xret  ra                        ; ...
upa_bad:
        li    a0, -1                    ; not a program
        xret  ra                        ; ...
        .org  u_parse + 2048            ; (the unit must fit its slot)

; ---- u_place: choose cores and slots -> cr_core, cr_slot; a0 = 0 or -5 -------------------
; Core records (K0_CORE + 16 c): word 0 = used slot bits, word 1 = flags:
; 2 has a server, 4 solo (nothing else may join it). cr_slot packs the slot
; of each thread, 4 bits per thread.
;  * a server or solo process: the lowest empty core;
;  * N threads (a window): the N contiguous cores without servers with the
;    fewest processes on the busiest of them;
;  * one ordinary thread: the core with the lowest score (processes, + 1 if
;    the core has no server: empty cores are kept for threads);
;  * pinned (-c): that core (N threads: from it on), if they have room.
u_place:
        addi  sp, sp, -16               ; frame: ra (the local calls below use it)
        sd    ra, 0(sp)                 ; ...
        ld    t0, cr_flags-GPBASE(gp)   ; t0 = flags (kept through the leaf calls)
        ld    a6, cr_n-GPBASE(gp)       ; a6 = threads
        ld    t1, cr_pin-GPBASE(gp)     ; pinned?
        bltz  t1, upl_any               ; no
        beqz  t1, upl_none              ; (never core 0)
        mv    a2, t1                    ; the run from it
        call  upl_run                   ; a0 = 1 if it fits
        beqz  a0, upl_none              ; ...
        sd    t1, cr_core-GPBASE(gp)    ; ...
        j     upl_slots                 ; ...
upl_any:
        andi  t3, t0, F_SOLO | F_SERVER ; a server: the lowest empty core
        beqz  t3, upl_thr               ; ...
        li    t1, 1                     ; ...
upl_e:
        ld    t2, w_ncores-GPBASE(gp)   ; ...
        bge   t1, t2, upl_none          ; ...
        slli  t6, t1, 4                 ; empty?
        ld    a1, K0_CORE(t6)           ; ...
        bnez  a1, upl_en                ; ...
        ld    a1, K0_CORE+8(t6)         ; ...
        beqz  a1, upl_eok               ; ...
upl_en:
        addi  t1, t1, 1                 ; ...
        j     upl_e                     ; ...
upl_eok:
        sd    t1, cr_core-GPBASE(gp)    ; ...
        j     upl_slots                 ; ...
upl_thr:
        li    t2, 1                     ; a window of more than one: the best run
        beq   a6, t2, upl_ts            ; (one thread: as any process)
        andi  t3, t0, F_THR             ; ...
        beqz  t3, upl_ts                ; ...
        li    t1, 1                     ; candidate first core
        li    a3, 100                   ; best score (the busiest core of the run)
        li    a4, -1                    ; best first core
upl_tr:
        ld    t2, w_ncores-GPBASE(gp)   ; ...
        add   t3, t1, a6                ; ...
        bgt   t3, t2, upl_trd           ; no more runs
        mv    a2, t1                    ; does it fit? a1 = its busiest core's processes
        call  upl_run                   ; ...
        beqz  a0, upl_trn               ; ...
        bge   a1, a3, upl_trn           ; not better
        mv    a3, a1                    ; ...
        mv    a4, t1                    ; ...
upl_trn:
        addi  t1, t1, 1                 ; ...
        j     upl_tr                    ; ...
upl_trd:
        bltz  a4, upl_none              ; nowhere
        sd    a4, cr_core-GPBASE(gp)    ; ...
        j     upl_slots                 ; ...
upl_ts:
        li    t1, 1                     ; one ordinary thread: the best score
        li    a2, -1                    ; a2 = best core
        li    a3, 100                   ; a3 = its score
upl_tl:
        ld    t2, w_ncores-GPBASE(gp)   ; ...
        bge   t1, t2, upl_tdone         ; ...
        mv    a0, t1                    ; may it go there?
        call  upl_fits                  ; a0 = 1, a1 = processes there
        beqz  a0, upl_tn                ; no
        mv    a4, a1                    ; score: processes, + 1 if no server
        slli  t6, t1, 4                 ; ...
        ld    a1, K0_CORE+8(t6)         ; ...
        andi  a1, a1, 2                 ; ...
        bnez  a1, upl_sc                ; ...
        addi  a4, a4, 1                 ; ...
upl_sc:
        bge   a4, a3, upl_tn            ; not better
        mv    a3, a4                    ; the best so far
        mv    a2, t1                    ; ...
upl_tn:
        addi  t1, t1, 1                 ; ...
        j     upl_tl                    ; ...
upl_tdone:
        bltz  a2, upl_none              ; nowhere
        sd    a2, cr_core-GPBASE(gp)    ; ...
upl_slots:
        ld    t1, cr_core-GPBASE(gp)    ; each thread: the lowest free slot of its core
        li    a5, 0                     ; packed slots
        li    t3, 0                     ; thread
upl_sl:
        bge   t3, a6, upl_sld           ; ...
        add   t6, t1, t3                ; its core's record
        slli  t6, t6, 4                 ; ...
        ld    a1, K0_CORE(t6)           ; used slots
        li    t2, 0                     ; ...
upl_sf:
        srl   t4, a1, t2                ; ...
        andi  t4, t4, 1                 ; ...
        beqz  t4, upl_sfo               ; ...
        addi  t2, t2, 1                 ; ...
        j     upl_sf                    ; ...
upl_sfo:
        ld    t4, k_nslot-GPBASE(gp)    ; (the checks above made sure there is one)
        bge   t2, t4, upl_none          ; ...
        slli  t4, t3, 2                 ; slot << 4 * thread
        sll   t4, t2, t4                ; ...
        or    a5, a5, t4                ; ...
        addi  t3, t3, 1                 ; ...
        j     upl_sl                    ; ...
upl_sld:
        sd    a5, cr_slot-GPBASE(gp)    ; ...
        li    a0, 0                     ; ...
        j     upl_ret                   ; ...
upl_none:
        li    a0, -5                    ; no room
upl_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        xret  ra                        ; ...

; upl_run(a2 = first core, a6 = threads, t0 = flags) -> a0 = 1 if every core
; of the run takes one more (and, for a window of more than one, has no
; server), a1 = processes on its busiest core. Keeps t0, t1.
upl_run:
        mv    a7, ra                    ; (calls a leaf)
        li    a1, 0                     ; busiest so far
        li    t5, 0                     ; thread
upr_l:
        bge   t5, a6, upr_yes           ; all fit
        add   a0, a2, t5                ; its core
        ld    t2, w_ncores-GPBASE(gp)   ; a worker?
        bge   a0, t2, upr_no            ; ...
        mv    t6, a1                    ; ...
        mv    t3, a0                    ; ...
        call  upl_fits                  ; ...
        beqz  a0, upr_no                ; ...
        li    t2, 1                     ; more than one thread: no server cores
        beq   a6, t2, upr_c             ; ...
        slli  t3, t3, 4                 ; ...
        ld    t2, K0_CORE+8(t3)         ; ...
        bnez  t2, upr_no                ; ...
upr_c:
        bge   t6, a1, upr_k             ; the busiest
        mv    t6, a1                    ; ...
upr_k:
        mv    a1, t6                    ; ...
        addi  t5, t5, 1                 ; ...
        j     upr_l                     ; ...
upr_yes:
        li    a0, 1                     ; ...
        mv    ra, a7                    ; ...
        ret                             ; ...
upr_no:
        li    a0, 0                     ; ...
        mv    ra, a7                    ; ...
        ret                             ; ...

; upl_fits(a0 = core, t0 = flags) -> a0 = 1 if a thread may go there (not a
; solo core, a free slot and job record, no second server), a1 = processes
; there. Keeps t0, t1, t3, t5.
upl_fits:
        slli  a5, a0, 4                 ; its record
        ld    t4, K0_CORE(a5)           ; processes: count the slot bits
        li    a1, 0                     ; ...
upf_c:
        beqz  t4, upf_cd                ; ...
        andi  t2, t4, 1                 ; ...
        add   a1, a1, t2                ; ...
        srli  t4, t4, 1                 ; ...
        j     upf_c                     ; ...
upf_cd:
        ld    t4, K0_CORE+8(a5)         ; flags
        andi  t2, t4, 4                 ; solo: no
        bnez  t2, upf_no                ; ...
        andi  t2, t0, F_SOLO            ; solo itself: only an empty core
        beqz  t2, upf_srv               ; ...
        bnez  a1, upf_no                ; ...
upf_srv:
        andi  t2, t0, F_SERVER          ; a server where there is one: no
        beqz  t2, upf_slots             ; ...
        andi  t2, t4, 2                 ; ...
        bnez  t2, upf_no                ; ...
upf_slots:
        ld    t2, k_nslot-GPBASE(gp)    ; a free slot? (with it, its save-table slots:
        bge   a1, t2, upf_no            ;   the worker reserves them for every record)
        slli  a5, a0, 10                ; and a free job record (they are reused once the
        addi  a5, a5, CAREA + CA_JOB + J_STATE ; worker has read them)
        li    t4, NJOB                  ; ...
upf_j:
        tamo.add t2, c6, a5, zero       ; ...
        beqz  t2, upf_yes               ; ...
        addi  a5, a5, J_SIZE            ; ...
        addi  t4, t4, -1                ; ...
        bnez  t4, upf_j                 ; ...
        j     upf_no                    ; ...
upf_yes:
        li    a0, 1                     ; yes
        ret                             ; ...
upf_no:
        li    a0, 0                     ; no
        ret                             ; ...
        .org  u_place + 2048            ; (the unit must fit its slot)

; ---- u_farcopy: the image's far section -> its own offset in the arena (c10) ----------------
u_farcopy:
        ld    t0, cr_far-GPBASE(gp)     ; addr | size << 32
        srli  t1, t0, 32                ; size
        beqz  t1, ufc_done              ; none
        slli  t2, t0, 32                ; destination offset
        srli  t2, t2, 32                ; ...
        ld    t3, cr_farof-GPBASE(gp)   ; source offset (from the layout base)
        ld    t4, cr_aext-GPBASE(gp)    ; ...
        add   t3, t3, t4                ; ...
ufc_l:
        beqz  t1, ufc_done              ; ...
        li    t4, 4096                  ; a bounce buffer at a time
        bleu  t4, t1, ufc_n             ; ...
        mv    t4, t1                    ; ...
ufc_n:
        li    t5, K0_BOUNCE             ; arena -> D-LS -> arena
        tget  tg0, t5, c10, t3, t4      ; ...
        tput  tg0, t5, c10, t2, t4      ; (ordered after the tget by the Local Store hazard)
        add   t2, t2, t4                ; ...
        add   t3, t3, t4                ; ...
        sub   t1, t1, t4                ; ...
        j     ufc_l                     ; ...
ufc_done:
        twait 1                         ; ...
        xret  ra                        ; ...
        .org  u_farcopy + 2048          ; (the unit must fit its slot)

; ---- u_launch: split the arena, write the job records, give the pieces ------------------------
; The arena of a process with N threads, at offsets from its layout base (E above its base):
;   [-E, P)       the program's memory (thread 0's c0), P = 0xD0000 - (N-1) * 48 KiB
;   [P, 0xD0000)  the save areas of threads N-1 .. 1, 48 KiB each
;   [0xD0000, 0xF0000) the image (each thread gets a read-only share)
;   [0xF0000, 0xFC000) thread 0's save area     [0xFF000, ..) the message buffer
u_launch:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        cbase s4, c10                   ; s4 = arena base
        li    s1, K0_PROC               ; a kernel process record
        li    t1, NKPROC                ; ...
ula_rf:
        ld    t2, KP_PID(s1)            ; free?
        beqz  t2, ula_rok               ; ...
        addi  s1, s1, KP_SIZE           ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, ula_rf                ; ...
        li    s1, K0_PROC               ; (cannot happen: arenas run out first)
ula_rok:
        ld    t0, cr_pid-GPBASE(gp)     ; fill it
        sd    t0, KP_PID(s1)            ; ...
        ld    t0, cr_flags-GPBASE(gp)   ; ...
        sd    t0, KP_FLAGS(s1)          ; ...
        ld    t0, cr_core-GPBASE(gp)    ; ...
        sd    t0, KP_CORE(s1)           ; ...
        ld    t0, cr_n-GPBASE(gp)       ; ...
        sd    t0, KP_N(s1)              ; ...
        sd    t0, KP_LEFT(s1)           ; ...
        ld    t0, cr_slot-GPBASE(gp)    ; (packed: 4 bits per thread)
        sd    t0, KP_SLOT(s1)           ; ...
        ld    t0, cr_aslot-GPBASE(gp)   ; ...
        sd    t0, KP_ASLOT(s1)          ; ...
        sd    zero, KP_STAT(s1)         ; ...
        slli  t1, t0, 5                 ; the arena belongs to a process now
        li    t2, K0_AR                 ; ...
        add   t1, t1, t2                ; ...
        li    t2, 2                     ; ...
        sd    t2, AR_STATE(t1)          ; ...
        mv    a0, t0                    ; its owner (for the pid stamp of its messages)
        ld    a1, cr_pid-GPBASE(gp)     ; ...
        la    t5, u_own                 ; ...
        xcall ra, c12, t5               ; ...
        ld    a0, cr_pid-GPBASE(gp)     ; its switch counters start at zero
        andi  a0, a0, 255               ; ...
        slli  a0, a0, 4                 ; ...
        li    t0, PSTATS                ; ...
        add   s3, a0, t0                ; ...
        mv    a0, s3                    ; ...
        li    a1, 0                     ; ...
        la    t6, kst_wr                ; ...
        jalr  ra, t6, 0                 ; ...
        addi  a0, s3, 8                 ; ...
        li    a1, 0                     ; ...
        la    t6, kst_wr                ; ...
        jalr  ra, t6, 0                 ; ...
        li    s2, 0                     ; the job records, thread by thread
ula_j:
        ld    t0, cr_n-GPBASE(gp)       ; ...
        bge   s2, t0, ula_split         ; ...
        ld    s3, cr_core-GPBASE(gp)    ; its core
        add   s3, s3, s2                ; ...
        ld    t0, cr_slot-GPBASE(gp)    ; its slot
        slli  t1, s2, 2                 ; ...
        srl   t0, t0, t1                ; ...
        andi  t0, t0, 15                ; ...
        sd    t0, k_tmpi-GPBASE(gp)     ; ...
        slli  t6, s3, 4                 ; the core record: the slot is used; flags
        li    t1, 1                     ; ...
        sll   t1, t1, t0                ; ...
        ld    t2, K0_CORE(t6)           ; ...
        or    t2, t2, t1                ; ...
        sd    t2, K0_CORE(t6)           ; ...
        ld    t0, cr_flags-GPBASE(gp)   ; ...
        ld    t2, K0_CORE+8(t6)         ; ...
        andi  t1, t0, F_SERVER          ; server -> 2
        beqz  t1, ula_f3                ; ...
        ori   t2, t2, 2                 ; ...
ula_f3:
        andi  t1, t0, F_SOLO            ; solo -> 4
        beqz  t1, ula_f4                ; ...
        ori   t2, t2, 4                 ; ...
ula_f4:
        sd    t2, K0_CORE+8(t6)         ; ...
        mv    a0, s3                    ; the record: core, thread, arena layout base
        mv    a1, s2                    ; ...
        ld    a2, cr_aext-GPBASE(gp)    ; ...
        add   a2, a2, s4                ; ...
        la    t5, u_job                 ; ...
        xcall ra, c12, t5               ; ...
        addi  s2, s2, 1                 ; ...
        j     ula_j                     ; ...
ula_split:
        ld    t0, cr_n-GPBASE(gp)       ; P ends where the other threads' save areas begin
        addi  t0, t0, -1                ; ...
        li    t1, SAVESZ                ; ...
        mul   t0, t0, t1                ; ...
        li    t1, A_PEND                ; ...
        sub   t0, t1, t0                ; ...
        ld    t1, cr_aext-GPBASE(gp)    ; (+ E: the program has the extra memory)
        add   t0, t0, t1                ; ...
        csplit c9, c10, t0              ; c10 = P, c9 = the rest
        ld    s2, cr_n-GPBASE(gp)       ; threads N-1 .. 1: their save areas, lowest first
ula_s:
        addi  s2, s2, -1                ; ...
        blez  s2, ula_img               ; ...
        li    t0, SAVESZ                ; ...
        csplit c13, c9, t0              ; c9 = this save area, c13 = the rest
        ld    a0, cr_core-GPBASE(gp)    ; -> its core
        add   a0, a0, s2                ; ...
        cgive c9, a0                    ; ...
        cmov  c9, c13                   ; ...
        j     ula_s                     ; ...
ula_img:
        ld    t0, cr_n-GPBASE(gp)       ; one thread: the image and its save area, which
        li    t1, 1                     ;   follows it, are one capability (one save-table
        bne   t0, t1, ula_img2          ;   slot on its core)
        li    t0, IMG_MAX + SAVESZ      ; c9 = [0xD0000, 0xFC000), c14 = [0xFC000, ..)
        csplit c14, c9, t0              ; ...
        j     ula_gap                   ; ...
ula_img2:
        li    t0, IMG_MAX               ; c9 = [0xD0000, ..): the image
        csplit c13, c9, t0              ; c9 = the image, c13 = [0xF0000, ..)
        cshare c9, c9                   ; a read-only share every thread loads from
        li    t0, SAVESZ                ; thread 0's save area
        csplit c14, c13, t0             ; c13 = it, c14 = [0xFC000, ..)
ula_gap:
        li    t0, A_BUF - A_SAVE0 - SAVESZ ; the spare gap before the buffer
        csplit c15, c14, t0             ; c14 = the gap, c15 = B
        cclear c14                      ; (unused: revoked with the arena)
        ld    s3, cr_core-GPBASE(gp)    ; thread 0's core
        cgive c10, s3                   ; P
        ld    t0, cr_n-GPBASE(gp)       ; its save area (if it is not part of c9)
        li    t1, 1                     ; ...
        beq   t0, t1, ula_sv            ; ...
        cgive c13, s3                   ; ...
ula_sv:
        ld    t0, cr_flags-GPBASE(gp)   ; B: only a StrataOS program has a message buffer
        andi  t0, t0, F_SYS             ; ...
        beqz  t0, ula_nob               ; ...
        cgive c15, s3                   ; B
        j     ula_fb                    ; ...
ula_nob:
        cclear c15                      ; (a bare-metal program has none)
ula_fb:                                 ; (dev gets the framebuffer through FBLEND, not here)
ula_sh:
        ld    s2, cr_n-GPBASE(gp)       ; every thread: a share of the image, and a wake-up
ula_w:
        addi  s2, s2, -1                ; ...
        bltz  s2, ula_done              ; ...
        ld    a0, cr_core-GPBASE(gp)    ; ...
        add   a0, a0, s2                ; ...
        cgive c9, a0                    ; (copyable: we keep ours; one thread: linear, it goes)
        la    t6, k_wake                ; ...
        jalr  ra, t6, 0                 ; ...
        j     ula_w                     ; ...
ula_done:
        cclear c9                       ; (our copy of the share)
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        xret  ra                        ; ...
        .org  u_launch + 2048           ; (the unit must fit its slot)

; ---- u_job(a0 = core, a1 = thread, a2 = arena layout base; k_tmpi = its slot): a job record --
u_job:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        mv    s2, a1                    ; s2 = thread
        mv    s3, a2                    ; s3 = arena base
        slli  s1, a0, 10                ; s1 = KST offset of a free job record of that
        addi  s1, s1, CAREA + CA_JOB    ;   core (u_place made sure there is one)
uj_f:
        tamo.add t0, c6, s1, zero       ; (J_STATE = 0)
        beqz  t0, uj_ok                 ; ...
        addi  s1, s1, J_SIZE            ; ...
        j     uj_f                      ; ...
uj_ok:
        addi  a0, s1, J_PID             ; pid
        ld    a1, cr_pid-GPBASE(gp)     ; ...
        call  uj_w                      ; ...
        addi  a0, s1, J_FLAGS           ; flags
        ld    a1, cr_flags-GPBASE(gp)   ; ...
        call  uj_w                      ; ...
        addi  a0, s1, J_ARENA           ; arena layout base
        mv    a1, s3                    ; ...
        call  uj_w                      ; ...
        addi  a0, s1, J_MEM             ; arena base
        ld    t0, cr_aext-GPBASE(gp)    ; ...
        sub   a1, s3, t0                ; ...
        call  uj_w                      ; ...
        ld    t0, cr_flags-GPBASE(gp)   ; window: base | count << 8 | thread << 16
        li    a1, 0                     ; (none for a single StrataOS thread)
        andi  t0, t0, F_THR             ; ...
        beqz  t0, uj_win                ; ...
        ld    a1, cr_core-GPBASE(gp)    ; ...
        ld    t0, cr_n-GPBASE(gp)       ; ...
        slli  t0, t0, 8                 ; ...
        or    a1, a1, t0                ; ...
        slli  t0, s2, 16                ; ...
        or    a1, a1, t0                ; ...
uj_win:
        addi  a0, s1, J_WIN             ; ...
        call  uj_w                      ; ...
        addi  a0, s1, J_CODE            ; code
        ld    a1, cr_code-GPBASE(gp)    ; ...
        call  uj_w                      ; ...
        addi  a0, s1, J_DATA            ; data
        ld    a1, cr_data-GPBASE(gp)    ; ...
        call  uj_w                      ; ...
        addi  a0, s1, J_EPS             ; endpoints
        ld    a1, cr_eps-GPBASE(gp)     ; ...
        call  uj_w                      ; ...
        addi  a0, s1, J_A0              ; a0..a2
        ld    a1, cr_a0-GPBASE(gp)      ; ...
        call  uj_w                      ; ...
        addi  a0, s1, J_A1              ; ...
        ld    a1, cr_a1-GPBASE(gp)      ; ...
        call  uj_w                      ; ...
        addi  a0, s1, J_A2              ; ...
        ld    a1, cr_a2-GPBASE(gp)      ; ...
        call  uj_w                      ; ...
        li    a1, A_SAVE0               ; its save area: thread 0 at 0xF0000,
        beqz  s2, uj_sv                 ;   thread k at 0xD0000 - k * 48 KiB
        li    t0, SAVESZ                ; ...
        mul   t0, t0, s2                ; ...
        li    a1, A_PEND                ; ...
        sub   a1, a1, t0                ; ...
uj_sv:
        addi  a0, s1, J_SAVE            ; ...
        call  uj_w                      ; ...
        addi  a0, s1, J_STATE           ; posted (last): the slot + 1
        ld    a1, k_tmpi-GPBASE(gp)     ; ...
        addi  a1, a1, 1                 ; ...
        call  uj_w                      ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        xret  ra                        ; ...
uj_w:                                   ; (local) KST word a0 = a1
        tamo.swap zero, c6, a0, a1      ; ...
        ret                             ; ...
        .org  u_job + 2048              ; (the unit must fit its slot)

; ---- u_destroy(a0 = pid) -> a0: stop every core of it -------------------------------------
u_destroy:
        addi  sp, sp, -32               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        la    t6, kp_find               ; ...
        jalr  ra, t6, 0                 ; ...
        beqz  a0, ude_bad               ; no such process
        mv    s1, a0                    ; ...
        li    s2, 0                     ; vcore
ude_l:
        ld    t0, KP_N(s1)              ; ...
        bge   s2, t0, ude_ok            ; ...
        ld    t0, KP_CORE(s1)           ; its core's kill word: the slot's bit
        add   t0, t0, s2                ; ...
        slli  a0, t0, 10                ; ...
        addi  a0, a0, CAREA + CA_KILL   ; ...
        ld    t1, KP_SLOT(s1)           ; this thread's slot (4 bits each)
        slli  t2, s2, 2                 ; ...
        srl   t1, t1, t2                ; ...
        andi  t1, t1, 15                ; ...
        li    a1, 1                     ; ...
        sll   a1, a1, t1                ; ...
        la    t6, kst_or                ; ...
        jalr  ra, t6, 0                 ; ...
        ld    a0, KP_CORE(s1)           ; wake it
        add   a0, a0, s2                ; ...
        la    t6, k_wake                ; ...
        jalr  ra, t6, 0                 ; ...
        addi  s2, s2, 1                 ; ...
        j     ude_l                     ; ...
ude_ok:
        li    a0, 0                     ; ...
        j     ude_ret                   ; ...
ude_bad:
        li    a0, -1                    ; ...
ude_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 32                ; ...
        xret  ra                        ; ...
        .org  u_destroy + 2048          ; (the unit must fit its slot)

; ---- u_free(a0 = sender): an arena handed back ------------------------------------------------
u_free:
        addi  sp, sp, -24               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        la    t6, k_unstash             ; the arena
        jalr  ra, t6, 0                 ; ...
        bnez  a0, ufr_bad               ; none
        cbase s2, c8                    ; which slot?
        li    s1, 0                     ; ...
        li    t1, K0_AR                 ; ...
ufr_f:
        li    t2, NARENA                ; ...
        bge   s1, t2, ufr_drop          ; not ours
        ld    t2, AR_STATE(t1)          ; in use, at this base?
        beqz  t2, ufr_n                 ; ...
        ld    t2, AR_BASE(t1)           ; ...
        beq   t2, s2, ufr_have          ; ...
ufr_n:
        addi  s1, s1, 1                 ; ...
        addi  t1, t1, AR_SZ             ; ...
        j     ufr_f                     ; ...
ufr_have:
        ld    t2, AR_STATE(t1)          ; issued by MEMORY, or given to proc with EXITED
        li    t3, 1                     ; ...
        beq   t2, t3, ufr_ok            ; ...
        li    t3, 4                     ; ...
        bne   t2, t3, ufr_drop          ; anything else: not returnable
ufr_ok:
        clen  t2, c8                    ; whole?
        ld    t3, AR_SIZE(t1)           ; ...
        bne   t2, t3, ufr_drop          ; ...
        cclear c8                       ; revoke it: everything cut from it dies
        mv    a0, s1                    ; ...
        la    t5, u_arcap               ; ...
        xcall ra, c12, t5               ; ...
        cclear c13                      ; (the fresh capability is not needed)
        mv    a0, s1                    ; its granules are free again
        la    t5, u_arfree              ; ...
        xcall ra, c12, t5               ; ...
        li    a0, 0                     ; ...
        j     ufr_ret                   ; ...
ufr_drop:
        cclear c8                       ; ...
ufr_bad:
        li    a0, -1                    ; ...
ufr_ret:
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 24                ; ...
        xret  ra                        ; ...
        .org  u_free + 2048             ; (the unit must fit its slot)

; ---- u_halt: stop the machine --------------------------------------------------------------------
u_halt:
        la    a0, s_halted              ; "StrataOS: halted"
        li    a1, s_halted_e - s_halted ; ...
        la    t6, k_fputs               ; ...
        jalr  ra, t6, 0                 ; ...
        li    a0, G_HALT                ; every dispatcher stops when it sees this
        li    a1, 1                     ; ...
        la    t6, kst_wr                ; ...
        jalr  ra, t6, 0                 ; ...
        li    s1, 1                     ; wake them all
uha_l:
        ld    t0, w_ncores-GPBASE(gp)   ; ...
        bge   s1, t0, uha_me            ; ...
        mv    a0, s1                    ; ...
        la    t6, k_wake                ; ...
        jalr  ra, t6, 0                 ; ...
        addi  s1, s1, 1                 ; ...
        j     uha_l                     ; ...
uha_me:
        li    s1, 1 << 22               ; wait (bounded) until every worker is in w_halt:
uha_w:
        li    a0, G_HALTED              ;   from then on no process can start a device read
        la    t6, kst_rd                ; ...
        jalr  ra, t6, 0                 ; ...
        ld    t0, w_ncores-GPBASE(gp)   ; all but this core?
        addi  t0, t0, -1                ; ...
        bge   a0, t0, uha_rel           ; yes
        addi  s1, s1, -1                ; ...
        bnez  s1, uha_w                 ; ...
uha_rel:
        la    t0, k_tbuf                ; `halt` drains pending device reads: complete them.
        sd    zero, 0(t0)               ; One write to the console's release port (0x18)
        li    t1, 0x18                  ; completes every waiting break read (tty's) on
        li    t2, 1                     ; every core
        tput  tg0, t0, c3, t1, t2       ; ...
        twait 1                         ; ...
        li    t1, 0x4100                ; one write to the pointer's EVENT port completes
        li    t2, 1                     ; every waiting EVENT read (tty's) with 0
        tput  tg0, t0, c3, t1, t2       ; ...
        twait 1                         ; ...
        li    t1, 0x4218                ; the network interface's CANCEL completes every
        tput  tg0, t0, c3, t1, t2       ;   waiting RX read (the net server's) with zeros
        twait 1                         ; ...
        li    t1, TMR_PORT + 0x10       ; DEADLINE = 0: this core's timer WAIT (if one is
        li    t2, 8                     ; pending) completes at once
        tput  tg0, t0, c3, t1, t2       ; ...
        twait 1                         ; ...
        li    a0, 0                     ; and this core
        halt                            ; ...
s_halted: .ascii "StrataOS: all cores halted\n"
s_halted_e:
        .org  u_halt + 2048             ; (the unit must fit its slot)

; ---- u_stats: STATS into the request (c11) -> a0 = process records -------------------------------
u_stats:
        addi  sp, sp, -40               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        li    s1, K0_BOUNCE             ; s1 = where the data is built
        ld    t0, w_ncores-GPBASE(gp)   ; cores
        sd    t0, 0(s1)                 ; ...
        ld    t0, k_pfree-GPBASE(gp)    ; free heap: the pool's free granules
        slli  t0, t0, GSHIFT            ; bytes
        sd    t0, 8(s1)                 ; ...
        ld    t0, k_ptotal-GPBASE(gp)   ; total heap: the pool
        slli  t0, t0, GSHIFT            ; ...
        sd    t0, 16(s1)                ; ...
        ld    t0, k_loads-GPBASE(gp)    ; kernel units paged in
        sd    t0, 24(s1)                ; ...
        li    a0, G_SWITCH              ; switches
        la    t6, kst_rd                ; ...
        jalr  ra, t6, 0                 ; ...
        sd    a0, 32(s1)                ; ...
        li    a0, G_KIB                 ; KiB moved
        la    t6, kst_rd                ; ...
        jalr  ra, t6, 0                 ; ...
        sd    a0, 40(s1)                ; ...
        sd    zero, 48(s1)              ; processes (below)
        sd    zero, 56(s1)              ; ...
        li    s2, 0                     ; per core
ust_c:
        ld    t0, w_ncores-GPBASE(gp)   ; ...
        bge   s2, t0, ust_p             ; ...
        slli  s3, s2, 5                 ; its record
        add   s3, s3, s1                ; ...
        addi  s3, s3, 64                ; ...
        slli  s4, s2, 10                ; its KST area
        addi  s4, s4, CAREA             ; ...
        addi  a0, s4, CA_CUR            ; running pid
        la    t6, kst_rd                ; ...
        jalr  ra, t6, 0                 ; ...
        andi  t0, a0, 255               ; ...
        sd    t0, 0(s3)                 ; ...
        addi  a0, s4, CA_RUN            ; runnable
        la    t6, kst_rd                ; ...
        jalr  ra, t6, 0                 ; ...
        andi  a0, a0, 255               ; ...
        slli  a0, a0, 8                 ; ...
        ld    t0, 0(s3)                 ; ...
        or    t0, t0, a0                ; ...
        slli  t6, s2, 4                 ; processes there, flags
        ld    t1, K0_CORE(t6)           ; ...
        li    t2, 0                     ; ...
ust_bc:
        beqz  t1, ust_bd                ; ...
        andi  t3, t1, 1                 ; ...
        add   t2, t2, t3                ; ...
        srli  t1, t1, 1                 ; ...
        j     ust_bc                    ; ...
ust_bd:
        slli  t2, t2, 16                ; ...
        or    t0, t0, t2                ; ...
        ld    t1, K0_CORE+8(t6)         ; ...
        slli  t1, t1, 24                ; ...
        or    t0, t0, t1                ; ...
        sd    t0, 0(s3)                 ; ...
        addi  a0, s4, CA_SW             ; switches
        la    t6, kst_rd                ; ...
        jalr  ra, t6, 0                 ; ...
        sd    a0, 8(s3)                 ; ...
        addi  a0, s4, CA_KIB            ; KiB
        la    t6, kst_rd                ; ...
        jalr  ra, t6, 0                 ; ...
        sd    a0, 16(s3)                ; ...
        addi  a0, s4, CA_POOL           ; free save-table slots
        la    t6, kst_rd                ; ...
        jalr  ra, t6, 0                 ; ...
        sd    a0, 24(s3)                ; ...
        li    a0, CA_SWCYC              ; cycles per switch -> word 0's high half,
        call  ust_avg                   ;   (CA_SWCYC / CA_NSWP)
        ld    t0, 0(s3)                 ; ...
        or    t0, t0, a0                ; ...
        sd    t0, 0(s3)                 ; ...
        li    a0, CA_KCYC               ; cycles per trap -> word 3's high half
        call  ust_avg                   ;   (CA_KCYC / CA_NTRAP)
        ld    t0, 24(s3)                ; ...
        or    t0, t0, a0                ; ...
        sd    t0, 24(s3)                ; ...
        addi  s2, s2, 1                 ; ...
        j     ust_c                     ; ...
ust_p:
        ld    t0, w_ncores-GPBASE(gp)   ; processes after the cores
        slli  s3, t0, 5                 ; ...
        add   s3, s3, s1                ; ...
        addi  s3, s3, 64                ; s3 = the next process record
        li    s2, K0_PROC               ; ...
        li    s4, NKPROC                ; ...
ust_pl:
        beqz  s4, ust_out               ; ...
        ld    t0, KP_PID(s2)            ; in use?
        beqz  t0, ust_pn                ; ...
        ld    t1, KP_CORE(s2)           ; pid | core << 8 | state << 16 | flags << 24
        slli  t1, t1, 8                 ; ...
        or    t0, t0, t1                ; ...
        sd    t0, 0(s3)                 ; ...
        ld    t1, KP_CORE(s2)           ; its state from its core's slot word
        slli  a0, t1, 10                ; ...
        ld    t2, KP_SLOT(s2)           ; (thread 0's slot)
        andi  t2, t2, 15                ; ...
        slli  t2, t2, 3                 ; ...
        add   a0, a0, t2                ; ...
        addi  a0, a0, CAREA + CA_SLOT   ; ...
        la    t6, kst_rd                ; ...
        jalr  ra, t6, 0                 ; ...
        srli  a0, a0, 8                 ; ...
        andi  a0, a0, 255               ; ...
        slli  a0, a0, 16                ; ...
        ld    t0, 0(s3)                 ; ...
        or    t0, t0, a0                ; ...
        ld    t1, KP_FLAGS(s2)          ; ...
        andi  t1, t1, 255               ; ...
        slli  t1, t1, 24                ; ...
        or    t0, t0, t1                ; ...
        sd    t0, 0(s3)                 ; ...
        ld    t0, KP_N(s2)              ; cores
        sd    t0, 8(s3)                 ; ...
        ld    a0, KP_PID(s2)            ; switches and bytes
        andi  a0, a0, 255               ; ...
        slli  a0, a0, 4                 ; ...
        li    t0, PSTATS                ; ...
        add   a0, a0, t0                ; ...
        la    t6, kst_rd                ; ...
        jalr  ra, t6, 0                 ; ...
        sd    a0, 16(s3)                ; ...
        ld    a0, KP_PID(s2)            ; ...
        andi  a0, a0, 255               ; ...
        slli  a0, a0, 4                 ; ...
        li    t0, PSTATS + 8            ; ...
        add   a0, a0, t0                ; ...
        la    t6, kst_rd                ; ...
        jalr  ra, t6, 0                 ; ...
        sd    a0, 24(s3)                ; ...
        addi  s3, s3, 32                ; ...
        ld    t0, 48(s1)                ; count it
        addi  t0, t0, 1                 ; ...
        sd    t0, 48(s1)                ; ...
ust_pn:
        addi  s2, s2, KP_SIZE           ; ...
        addi  s4, s4, -1                ; ...
        j     ust_pl                    ; ...
ust_out:
        sub   t1, s3, s1                ; bytes built
        li    t2, 64                    ; -> the request's data
        tput  tg0, s1, c11, t2, t1      ; ...
        twait 1                         ; ...
        ld    a0, 48(s1)                ; result: processes
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 40                ; ...
        xret  ra                        ; ...
; ust_avg(a0 = a counter's field, the count after it; s4 = the core's area) -> a0 =
; counter / count, shifted to the high half (32 bits at most; 0 with no count). A
; call inside the unit: it makes no xcall, so its return link is an ordinary one.
ust_avg:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        add   a0, a0, s4                ; the count
        sd    a0, 8(sp)                 ; ...
        addi  a0, a0, 8                 ; ...
        la    t6, kst_rd                ; ...
        jalr  ra, t6, 0                 ; ...
        mv    t2, a0                    ; ...
        ld    a0, 8(sp)                 ; the counter
        sd    t2, 8(sp)                 ; ...
        la    t6, kst_rd                ; ...
        jalr  ra, t6, 0                 ; ...
        ld    t2, 8(sp)                 ; ...
        li    t0, 0                     ; nothing counted: 0
        beqz  t2, uav_ret               ; ...
        divu  t0, a0, t2                ; ...
uav_ret:
        slli  a0, t0, 32                ; (the low 32 bits of it)
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        ret                             ; ...
        .org  u_stats + 2048            ; (the unit must fit its slot)
