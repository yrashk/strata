; =============================================================================
; kunits/boot.s: kernel code units for start-up (system core only)
; =============================================================================
;
; Code units live in the kernel image's .far section and are paged into the
; system core's code cache on demand (see kernel.s). Rules for code here:
;   * every unit starts on a 2 KiB boundary and must fit in it (the closing
;     `.org` of each unit fails to assemble if it does not);
;   * resident code is called with `la t6, f` + `jalr ra, t6, 0` (a `call`
;     would be relative to where the unit was assembled, not where it runs);
;   * other units are called with `la t5, u; xcall ra, c12, t5`;
;   * a unit returns with `xret ra`, so ra is saved on the stack first.
;   * branches and `call`s inside one unit are fine (they move with it), as
;     long as the callee makes no xcall.

; ---- u_boot: memory, the KST, the workers, the first three servers -----------------
        .align 2048                     ; a unit of its own
u_boot:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; (a far return link)
        li    t0, 0                     ; clear core 0's tables (D-LS 0..K0_END)
        li    t1, K0_END                ; ...
ub_z:
        sd    zero, 0(t0)               ; ...
        addi  t0, t0, 8                 ; ...
        bltu  t0, t1, ub_z              ; ...
        la    t5, u_mem                 ; cut system memory up
        xcall ra, c12, t5               ; ...
        li    a0, G_NCORES              ; tell everyone the core count
        ld    a1, w_ncores-GPBASE(gp)   ; ...
        la    t6, kst_wr                ; ...
        jalr  ra, t6, 0                 ; ...
        lhu   a0, fw_plat+20-GPBASE(gp) ; the capability save table's slots (platform
        bnez  a0, ub_ct                 ;   table header; 0: an older platform, 64)
        li    a0, 64                    ; ...
ub_ct:
        sd    a0, k_ctab-GPBASE(gp)     ; ...
        mv    a1, a0                    ; -> the KST (each worker sizes its pool from it)
        li    a0, G_CTAB                ; ...
        la    t6, kst_wr                ; ...
        jalr  ra, t6, 0                 ; ...
        ld    a1, k_nxmap-GPBASE(gp)    ; the overlay map's entries -> the KST (page_in)
        li    a0, G_NXMAP               ; ...
        la    t6, kst_wr                ; ...
        jalr  ra, t6, 0                 ; ...
        ld    a0, k_ctab-GPBASE(gp)     ; how many threads a worker takes (placement)
        la    t6, w_params              ; ...
        jalr  ra, t6, 0                 ; ...
        sd    a0, k_nslot-GPBASE(gp)    ; ...
        mv    a1, a0                    ; ...
        li    a0, G_NSLOT               ; ...
        la    t6, kst_wr                ; ...
        jalr  ra, t6, 0                 ; ...
        li    s1, 1                     ; every worker: the KST and core control
ub_give:
        ld    t0, w_ncores-GPBASE(gp)   ; ...
        bge   s1, t0, ub_gave           ; ...
        cgive c6, s1                    ; the KST (atomic, copyable)
        cgive c4, s1                    ; core control (for doorbells)
        addi  s1, s1, 1                 ; ...
        j     ub_give                   ; ...
ub_gave:
        la    t5, u_disk                ; header and directory
        xcall ra, c12, t5               ; ...
        la    t5, u_servers             ; proc, dev, fs
        xcall ra, c12, t5               ; ...
        la    t5, u_banner              ; say hello
        xcall ra, c12, t5               ; ...
        la    t5, u_arm                 ; the first tick
        xcall ra, c12, t5               ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        xret  ra                        ; into the event loop
        .org  u_boot + 2048             ; (the unit must fit its slot)

; ---- u_mem: the KST, core 0's buffers, the arenas, the framebuffer -----------------------
; The KST goes into T2 (the cluster store, c1 from the boot ROM: 7 bus cycles
; an atomic there, 23 in T3), unless T2 is smaller than KST_SIZE; the rest of
; T2 waits in K_T2 for u_fart2. T2 is one revocation granule, so it holds
; only what is the kernel's for good. c1 may claim more than the platform
; table says T2 has (a small FPGA T2 behind the same reset capability): it
; is cut to the table's size.
u_mem:
        addi  sp, sp, -48               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    s1, 8(sp)                 ; ...
        sd    s2, 16(sp)                ; ...
        sd    s3, 24(sp)                ; ...
        sd    s4, 32(sp)                ; ...
        cvalid t0, c1                   ; T2?
        beqz  t0, um_kst3               ; ...
        li    a0, 2                     ; its size, from the platform table
        la    t6, fw_mem                ; ...
        jalr  ra, t6, 0                 ; ...
        clen  t1, c1                    ; (at most what c1 covers)
        bleu  t1, a0, um_t2l            ; ...
        csplit c7, c1, a0               ; c1 = [0, size), c7 = what is not there
        cclear c7                       ; ...
um_t2l:
        clen  t1, c1                    ; room for the KST?
        li    t0, KST_SIZE              ; ...
        bltu  t1, t0, um_kst3           ; no: it stays in T3
        csplit c7, c1, t0               ; c1 = the KST piece, c7 = the rest of T2
        catomic c6, c1                  ; c6 = the KST: atomic, copyable
        cmov  c8, c7                    ; the rest: kept for the paged code (u_fart2)
        li    a0, K_T2                  ; ...
        la    t6, csv8                  ; ...
        jalr  ra, t6, 0                 ; ...
        li    t0, KST_SIZE              ; T3's first 32 KiB stay unused
        csplit c7, c0, t0               ; c0 = them, c7 = the rest
        cclear c0                       ; ...
        j     um_msg                    ; ...
um_kst3:
        li    t0, KST_SIZE              ; c0 = [0, 15 MiB): the KST first
        csplit c7, c0, t0               ; c0 = the KST piece, c7 = the rest
        catomic c6, c0                  ; c6 = the KST: atomic, copyable
um_msg:
        li    t0, NMSGB * 4096          ; then core 0's message buffers
        csplit c0, c7, t0               ; c7 = the buffers, c0 = the rest
        li    s1, 0                     ; one by one into the save table
um_buf:
        li    t0, 4096                  ; ...
        csplit c8, c7, t0               ; c7 = one buffer, c8 = the rest
        cmov  c9, c8                    ; (keep the rest)
        cmov  c8, c7                    ; the buffer
        addi  a0, s1, K_MSG             ; ...
        la    t6, csv8                  ; ...
        jalr  ra, t6, 0                 ; ...
        cmov  c7, c9                    ; the rest
        addi  s1, s1, 1                 ; ...
        li    t0, NMSGB                 ; ...
        blt   s1, t0, um_buf            ; ...
        cclear c7                       ; (empty now)
        li    t0, (1 << NMSGB) - 1      ; all home
        sd    t0, k_msgfree-GPBASE(gp)  ; ...
        li    t0, ARENA - KST_SIZE - NMSGB * 4096 ; the low part of the arena pool: from 1 MiB
        csplit c13, c0, t0              ; c0 = [64 KiB, 1 MiB), c13 = [1 MiB, 15 MiB)
        cclear c0                       ; (the rest of the first MiB is not used)
        ld    t0, k_hasfb-GPBASE(gp)    ; the framebuffer: a revocable region of its own
        beqz  t0, um_nofb               ; ...
        li    a0, K_FB                  ; ...
        la    t6, crs8                  ; ...
        jalr  ra, t6, 0                 ; ...
        cclear c10                      ; ...
        cdom  c10, c8                   ; c10 = working capability, c8 = the revoker
        cclear c10                      ; (FBLEND makes fresh ones by crevoke)
        li    a0, K_FB                  ; keep the revoker
        la    t6, csv8                  ; ...
        jalr  ra, t6, 0                 ; ...
um_nofb:
        cbase s1, c13                   ; s1 = the pool's base (a granule boundary)
        sd    s1, k_pbase-GPBASE(gp)    ; ...
        clen  s2, c13                   ; s2 = the low part's granules
        srli  s2, s2, GSHIFT            ; ...
        slli  t0, s2, GSHIFT            ; (whole ones)
        csplit c9, c13, t0              ; c13 = the low part, c9 = the rest
        cclear c9                       ; ...
        li    a0, K_POOL                ; it becomes one revocable region; K_POOL its revoker
        la    t5, u_mkpool              ; ...
        xcall ra, c12, t5               ; ...
        ld    s4, k_p1end-GPBASE(gp)    ; s4 = one past its last granule
        mv    s3, s2                    ; s3 = the pool's granules so far
        sd    zero, k_p2base-GPBASE(gp) ; a high part?
        ld    t0, k_hashigh-GPBASE(gp)  ; ([16, 48) MiB: kentry kept it in the save table)
        beqz  t0, um_one                ; ...
        li    a0, K_SPARE               ; ...
        la    t6, crs8                  ; ...
        jalr  ra, t6, 0                 ; ...
        cmov  c13, c8                   ; ...
        cbase t1, c13                   ; its base
        sd    t1, k_p2base-GPBASE(gp)   ; ...
        sub   t2, t1, s1                ; s3 = the granules up to it (the gap between the parts,
        srli  s3, t2, GSHIFT            ;   the boot ROM's load area, is never handed out)
        li    t3, NGPID                 ; at most NGPID granules in all
        sub   t3, t3, s3                ; ...
        clen  t4, c13                   ; its whole granules
        srli  t4, t4, GSHIFT            ; ...
        bleu  t4, t3, um_h2             ; ...
        mv    t4, t3                    ; ...
um_h2:
        add   s2, s2, t4                ; s2 = free granules in all
        add   s3, s3, t4                ; s3 = the pool's span
        slli  t0, t4, GSHIFT            ; ...
        csplit c9, c13, t0              ; c13 = the high part, c9 = the rest
        cclear c9                       ; ...
        li    a0, K_POOL2               ; a revocable region too; K_POOL2 its revoker
        la    t5, u_mkpool              ; ...
        xcall ra, c12, t5               ; ...
        ld    t0, k_pbase-GPBASE(gp)    ; the gap's granules are in use for good
        ld    t1, k_p2base-GPBASE(gp)   ; ...
        sub   t1, t1, t0                ; ...
        srli  t1, t1, GSHIFT            ; t1 = the high part's first granule
        mv    t0, s4                    ; t0 = one past the low part's last
um_gap:
        bgeu  t0, t1, um_one            ; ...
        srli  t2, t0, 6                 ; ...
        slli  t2, t2, 3                 ; ...
        ld    t3, K0_GMAP(t2)           ; ...
        li    t4, 1                     ; ...
        sll   t4, t4, t0                ; ...
        or    t3, t3, t4                ; ...
        sd    t3, K0_GMAP(t2)           ; ...
        addi  t0, t0, 1                 ; ...
        j     um_gap                    ; ...
um_one:
        sd    s3, k_pgran-GPBASE(gp)    ; the span
        sd    s2, k_pfree-GPBASE(gp)    ; free granules
        sd    s2, k_ptotal-GPBASE(gp)   ; ...
        li    a0, G_PBASE               ; -> the KST, for pid_of on every core
        mv    a1, s1                    ; ...
        la    t6, kst_wr                ; ...
        jalr  ra, t6, 0                 ; ...
        li    a0, G_PGRAN               ; ...
        mv    a1, s3                    ; ...
        la    t6, kst_wr                ; ...
        jalr  ra, t6, 0                 ; ...
um_ret:
        ld    s4, 32(sp)                ; ...
        ld    s3, 24(sp)                ; ...
        ld    s2, 16(sp)                ; ...
        ld    s1, 8(sp)                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 48                ; ...
        xret  ra                        ; ...
        .org  u_mem + 2048              ; (the unit must fit its slot)

; ---- u_mkpool(a0 = save-table slot): c13 (a part of the arena pool) becomes a revocable region --
; Its revoker goes to the slot; the working capability is dropped (arenas get
; fresh ones by crevoke). k_p1end = one past its last granule (pool index).
u_mkpool:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a0, 8(sp)                 ; ...
        cbase t0, c13                   ; its end, as a pool granule
        clen  t1, c13                   ; ...
        add   t0, t0, t1                ; ...
        ld    t1, k_pbase-GPBASE(gp)    ; ...
        sub   t0, t0, t1                ; ...
        srli  t0, t0, GSHIFT            ; ...
        sd    t0, k_p1end-GPBASE(gp)    ; ...
        cclear c10                      ; ...
        cdom  c10, c13                  ; c10 = working capability, c13 = the revoker
        cclear c10                      ; ...
        cmov  c8, c13                   ; keep the revoker
        ld    a0, 8(sp)                 ; ...
        la    t6, csv8                  ; ...
        jalr  ra, t6, 0                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        xret  ra                        ; ...
        .org  u_mkpool + 2048           ; (the unit must fit its slot)

; ---- u_fart2: the kernel's code units into T2 ----------------------------------------------
; The far image (c12, in T3's load area) is copied into T2 after the KST and
; c12 becomes a read+execute share of the copy: copyable and not writable,
; and T2 is never revoked, so it is the kernel's for good. A unit then starts
; arriving after T2's 4 bus cycles instead of T3's 20. Only if it fits in
; what u_mem left of T2 (K_T2): not in a 64 KiB T2, where c12 stays. Called
; from resident code once start-up is over, so that no far link into the old
; image remains (the overlay map's entries for it are dropped as their slots
; are reused). There is no far-to-far transfer: the image is bounced through
; core 0's D-LS [K0_SCR, K0_OUTQ), which nothing uses before the event loop.
u_fart2:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        li    a0, K_T2                  ; what is left of T2
        la    t6, crs8                  ; ...
        jalr  ra, t6, 0                 ; ...
        bnez  a0, uft_ret               ; nothing
        clen  t3, c12                   ; t3 = the image's bytes (whole units)
        clen  t1, c8                    ; room?
        bltu  t1, t3, uft_keep          ; no: the units stay in T3
        csplit c7, c8, t3               ; c8 = the copy's place, c7 = the rest
        li    t2, 0                     ; t2 = offset
uft_l:
        bgeu  t2, t3, uft_done          ; all copied
        sub   t4, t3, t2                ; t4 = this piece, at most the bounce area
        li    t5, K0_OUTQ - K0_SCR      ; ...
        bleu  t4, t5, uft_n             ; ...
        mv    t4, t5                    ; ...
uft_n:
        li    t5, K0_SCR                ; far image -> D-LS -> T2 (in issue order)
        tget  tg0, t5, c12, t2, t4      ; ...
        tput  tg1, t5, c8, t2, t4       ; ...
        add   t2, t2, t4                ; ...
        j     uft_l                     ; ...
uft_done:
        cclear c12                      ; the old image (this unit runs on from its slot)
        cshare c12, c8                  ; c12 = the copy, read + execute (cshare waits for it)
        cclear c15                      ; (kentry's spare copy of the old share)
        cmov  c8, c7                    ; the rest of T2 back
uft_keep:
        li    a0, K_T2                  ; ...
        la    t6, csv8                  ; ...
        jalr  ra, t6, 0                 ; ...
uft_ret:
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        xret  ra                        ; (an ordinary link: resident code called us)
        .org  u_fart2 + 2048            ; (the unit must fit its slot)

; ---- u_disk: the boot header and the directory, into core 0's D-LS --------------------------
u_disk:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        li    a0, K_MSG                 ; core 0's first message buffer (4 KiB) as the disk buffer
        la    t6, crs8                  ; ...
        jalr  ra, t6, 0                 ; ...
        cmov  c9, c8                    ; (the firmware reads into c9)
        li    a0, 0                     ; block 0: the header
        li    a1, 1                     ; ...
        li    a2, 0                     ; ...
        la    t6, fw_blk_read           ; ...
        jalr  ra, t6, 0                 ; ...
        li    t0, K0_SCR                ; -> D-LS
        li    t1, 512                   ; ...
        tget  tg0, t0, c9, zero, t1     ; ...
        lwu   a0, K0_SCR+36(zero)       ; directory LBA
        li    a1, 8                     ; 8 blocks: 128 entries
        li    a2, 0                     ; ...
        la    t6, fw_blk_read           ; ...
        jalr  ra, t6, 0                 ; ...
        li    t0, K0_DIR                ; -> D-LS
        li    t1, 4096                  ; ...
        tget  tg0, t0, c9, zero, t1     ; ...
        cmov  c8, c9                    ; the buffer back
        li    a0, K_MSG                 ; ...
        la    t6, csv8                  ; ...
        jalr  ra, t6, 0                 ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        xret  ra                        ; ...
        .org  u_disk + 2048             ; (the unit must fit its slot)

; ---- u_servers: load and create proc (pid 1), dev (2) and fs (3) -----------------------
; The kernel reads the disk itself only here: fs must exist before anything
; else can be loaded. They are pinned to cores 1, 2 and 3.
u_servers:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        la    a0, n_proc                ; proc: the process server
        li    a1, 4                     ; ...
        li    a2, 1                     ; pid 1
        li    a3, 1                     ; core 1
        li    a4, F_SERVER | F_PRIV | F_SOLO ; it mints endpoints; alone on its core
        li    a5, 0x00ff0300            ; c1 kernel (0), c2 fs (3), c3 c4 none
        li    a6, 0x0302                ; its a0: dev core | fs core << 8
        li    a7, 0x0302                ; its a1: dev pid | fs pid << 8
        la    t5, u_loadsrv             ; ...
        xcall ra, c12, t5               ; ...
        la    a0, n_dev                 ; dev: the device manager
        li    a1, 3                     ; ...
        li    a2, 2                     ; pid 2
        li    a3, 2                     ; core 2
        li    a4, F_SERVER | F_PRIV | F_DEVCAPS ; device root and framebuffer
        li    a5, 0xff00ff01            ; c1 proc (1), c2 (the framebuffer), c3 kernel (0)
        li    a6, 0                     ; ...
        li    a7, 0                     ; ...
        la    t5, u_loadsrv             ; ...
        xcall ra, c12, t5               ; ...
        la    a0, n_fs                  ; fs: the file server
        li    a1, 2                     ; ...
        li    a2, 3                     ; pid 3
        li    a3, 3                     ; core 3
        li    a4, F_SERVER              ; ...
        li    a5, 0xffff0201            ; c1 proc (1), c2 dev (2)
        li    a6, 0                     ; ...
        li    a7, 0                     ; ...
        la    t5, u_loadsrv             ; ...
        xcall ra, c12, t5               ; ...
        li    t0, 1                     ; proc runs on core 1
        sd    t0, k_proccore-GPBASE(gp) ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        xret  ra                        ; ...
n_proc: .ascii "proc"                   ; file names (in the far image: read with
n_dev:  .ascii "dev"                    ;   tget through c12, see u_findfile)
n_fs:   .ascii "fs"                     ; ...
        .org  u_servers + 2048          ; (the unit must fit its slot)

; ---- u_loadsrv: load one server from the disk and create it ---------------------------
; a0 = name (a far address in this image), a1 = its length, a2 = pid, a3 = core,
; a4 = flags, a5 = endpoint cores, a6/a7 = its a0/a1
u_loadsrv:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        sd    a2, cr_pid-GPBASE(gp)     ; the creation parameters
        sd    zero, cr_ncores-GPBASE(gp) ; time-shared
        sd    a4, cr_flags-GPBASE(gp)   ; ...
        sd    a3, cr_pin-GPBASE(gp)     ; ...
        sd    a5, cr_eps-GPBASE(gp)     ; ...
        sd    a6, cr_a0-GPBASE(gp)      ; ...
        sd    a7, cr_a1-GPBASE(gp)      ; ...
        sd    zero, cr_a2-GPBASE(gp)    ; ...
        sd    a1, cr_nlen-GPBASE(gp)    ; the name -> D-LS (it is in the far image)
        la    t0, cr_name               ; ...
        li    t1, 8                     ; one word holds every server name here
        srli  t2, a0, 3                ; clear the low 3 bits
        slli  t2, t2, 3                ; ...
        sub   t3, a0, t2                ; offset within it
        sd    t3, cr_noff-GPBASE(gp)    ; ...
        li    t1, 16                    ; two words
        tget  tg0, t0, c12, t2, t1      ; far image -> D-LS
        twait 1                         ; ...
        la    t5, u_findfile            ; its directory entry -> a0 (D-LS), or 0
        xcall ra, c12, t5               ; ...
        beqz  a0, uls_missing           ; not on the disk
        mv    s1, a0                    ; s1 = the entry
        ld    a0, cr_pid-GPBASE(gp)     ; an arena (1 MiB) for it -> c10, a0 = slot
        li    a1, 0                     ; ...
        la    t5, u_alloc               ; ...
        xcall ra, c12, t5               ; ...
        bltz  a0, uls_missing           ; (cannot happen at boot)
        sd    a0, cr_aslot-GPBASE(gp)   ; ...
        cmov  c9, c10                   ; the disk reads into c9
        lwu   s2, 24(s1)                ; first block
        lwu   s3, 28(s1)                ; size
        addi  s3, s3, 511               ; blocks
        srli  s3, s3, 9                 ; ...
        li    s4, A_IMG                 ; arena offset
uls_rd:
        beqz  s3, uls_read              ; all read
        mv    a1, s3                    ; at most 256 blocks per command
        li    t0, 256                   ; ...
        bleu  a1, t0, uls_go            ; ...
        mv    a1, t0                    ; ...
uls_go:
        sub   s3, s3, a1                ; ...
        mv    a0, s2                    ; ...
        add   s2, s2, a1                ; ...
        mv    a2, s4                    ; ...
        slli  t0, a1, 9                 ; ...
        add   s4, s4, t0                ; ...
        la    t6, fw_blk_read           ; ...
        jalr  ra, t6, 0                 ; ...
        j     uls_rd                    ; ...
uls_read:
        cmov  c10, c9                   ; the arena, with the image in it
        la    t5, u_startblk            ; its start-up block: pid, no handles, its name
        xcall ra, c12, t5               ; ...
        la    t5, u_create              ; make the process
        xcall ra, c12, t5               ; ...
        bnez  a0, uls_bad               ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        xret  ra                        ; ...
uls_missing:
uls_bad:
        la    a0, s_nosrv               ; "cannot start a server" (fatal)
        li    a1, s_nosrv_e - s_nosrv   ; ...
        la    t6, k_fputs               ; ...
        jalr  ra, t6, 0                 ; ...
        li    a0, 1                     ; ...
        halt                            ; the machine cannot run without them
        .org  u_loadsrv + 2048          ; (the unit must fit its slot)

; ---- u_findfile: cr_name (offset cr_noff, length cr_nlen) in K0_DIR -> a0 = entry or 0 -------
u_findfile:
        li    t0, K0_DIR                ; the first entry
        li    t1, 128                   ; entries
uff_e:
        beqz  t1, uff_none              ; not found
        li    t2, 0                     ; compare names
        ld    t3, cr_nlen-GPBASE(gp)    ; ...
uff_c:
        beq   t2, t3, uff_end           ; all its characters matched
        add   t4, t0, t2                ; entry byte
        lbu   t4, 0(t4)                 ; ...
        la    t5, cr_name               ; name byte
        ld    t6, cr_noff-GPBASE(gp)    ; ...
        add   t5, t5, t6                ; ...
        add   t5, t5, t2                ; ...
        lbu   t5, 0(t5)                 ; ...
        bne   t4, t5, uff_n             ; differ
        addi  t2, t2, 1                 ; ...
        j     uff_c                     ; ...
uff_end:
        li    t4, 24                    ; the entry's name must end there too
        beq   t2, t4, uff_yes           ; ...
        add   t4, t0, t2                ; ...
        lbu   t4, 0(t4)                 ; ...
        beqz  t4, uff_yes               ; ...
uff_n:
        addi  t0, t0, 32                ; next entry
        addi  t1, t1, -1                ; ...
        j     uff_e                     ; ...
uff_yes:
        mv    a0, t0                    ; found
        xret  ra                        ; ...
uff_none:
        li    a0, 0                     ; ...
        xret  ra                        ; ...
        .org  u_findfile + 2048         ; (the unit must fit its slot)

; ---- u_startblk: a boot server's start-up block (c10 = its arena) -------------------------
u_startblk:
        li    t0, K0_SCR                ; build it in D-LS
        li    t1, 512 / 8               ; clear 512 bytes
        mv    t2, t0                    ; ...
usb_z:
        sd    zero, 0(t2)               ; ...
        addi  t2, t2, 8                 ; ...
        addi  t1, t1, -1                ; ...
        bnez  t1, usb_z                 ; ...
        ld    t1, cr_pid-GPBASE(gp)     ; 0 pid
        sd    t1, 0(t0)                 ; ...
        li    t1, -1                    ; 16..32 no handles
        sd    t1, 16(t0)                ; ...
        sd    t1, 24(t0)                ; ...
        sd    t1, 32(t0)                ; ...
        ld    t1, cr_nlen-GPBASE(gp)    ; 40 command line length
        sd    t1, 40(t0)                ; ...
        li    t2, 0                     ; 64.. the command line: its name
usb_c:
        beq   t2, t1, usb_put           ; ...
        la    t3, cr_name               ; ...
        ld    t4, cr_noff-GPBASE(gp)    ; ...
        add   t3, t3, t4                ; ...
        add   t3, t3, t2                ; ...
        lbu   t3, 0(t3)                 ; ...
        add   t4, t0, t2                ; ...
        sb    t3, 64(t4)                ; ...
        addi  t2, t2, 1                 ; ...
        j     usb_c                     ; ...
usb_put:
        li    t1, A_START               ; -> the arena
        li    t2, 512                   ; ...
        tput  tg0, t0, c10, t1, t2      ; ...
        twait 1                         ; ...
        xret  ra                        ; ...
        .org  u_startblk + 2048         ; (the unit must fit its slot)

