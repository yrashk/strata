; u_arm: write DEADLINE = NOW + the time slice and start a WAIT read (core 0, tag TG_TMR)
u_arm:
        addi  sp, sp, -16               ; frame
        sd    ra, 0(sp)                 ; ...
        la    t5, u_timer               ; c8 = the timer window
        xcall ra, c12, t5               ; ...
        la    t0, k_tbuf                ; NOW
        li    t1, 8                     ; ...
        tget  tg0, t0, c8, zero, t1     ; ...
        ld    t2, 0(t0)                 ; ...
        sd    t2, k_now-GPBASE(gp)      ; ...
        ld    t3, k_slice-GPBASE(gp)    ; the next tick: one time slice on
        add   t2, t2, t3                ; ...
        sd    t2, 8(t0)                 ; DEADLINE (written as 8 bytes)
        addi  t4, t0, 8                 ; ...
        li    t5, 0x10                  ; ...
        tput  tg0, t4, c8, t5, t1       ; ...
        twait 1                         ; (before the WAIT reads it)
        addi  t4, t0, 16                ; WAIT: completes when NOW >= DEADLINE
        li    t5, 0x18                  ; ...
        tget  tg11, t4, c8, t5, t1      ; (pending)
        cclear c8                       ; ...
        li    t0, 1                     ; armed
        sd    t0, k_tarmed-GPBASE(gp)   ; ...
        ld    ra, 0(sp)                 ; ...
        addi  sp, sp, 16                ; ...
        xret  ra                        ; ...

; u_timer: c8 = a window on the timer's registers (from the device root c3)
u_timer:
        cmov  c8, c3                    ; a copy of the device root
        li    t0, TMR_PORT              ; ...
        csplit c9, c8, t0               ; c9 = from the timer on
        li    t0, 0x20                  ; its four registers
        csplit c7, c9, t0               ; c9 = them
        cclear c7                       ; ...
        cclear c8                       ; ...
        cmov  c8, c9                    ; ...
        xret  ra                        ; ...
