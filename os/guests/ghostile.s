; =============================================================================
; os/guests/ghostile.s: a hostile guest, for the isolation tests
; =============================================================================
;
; A guest image (booted like os/guests/gdemo) that deliberately tries to reach
; beyond its grant. Each attack must FAULT (the capabilities it holds do not
; reach the target) or be refused. A supervisor-mode trap handler catches the
; faults, counts them and skips the offending instruction, so the guest can try
; the next one; it then reports how many were blocked through the console
; endpoint, and attempts the block-device attack (which the test harness checks
; from StrataOS's side: fs stays healthy, the guest's stray buffer is bounced).
;
; Boot registers (os/kunits/guest.s): a0 = relative core, c0 = arena (core 0),
; c1 = console endpoint, c2 = clock, c3 = core control (own cores).

OP_WRITE = 2                            ; tty write
STACKTOP = 0x10000                      ; D-LS top
NATTACK  = 4                            ; attacks that must fault

        .data                           ; D-LS
        .align 8                        ; ...
hdr:    .space 64                       ; message header
scratch: .space 64                      ; a landing area for reads that must fault
blocked: .dword 0                       ; attacks that faulted (caught)
s_ok:   .ascii "hostile: 4 of 4 out-of-grant attacks blocked; isolation holds.\n"
s_ok_e:
s_bad:  .ascii "hostile: ISOLATION FAILED (an out-of-grant access succeeded).\n"
s_bad_e:

        .text                           ; entry at 0
_start:
        li    sp, STACKTOP              ; a stack
        bnez  a0, spin                  ; workers just spin
        la    t0, handler               ; a supervisor trap handler for the faults
        csrw  tvec, t0                  ; ...
        clen  t0, c0                    ; carve a 4 KiB console buffer from the top of the arena
        addi  t0, t0, -4096             ; ...
        csplit c6, c0, t0               ; c6 = the last 4 KiB, c0 = the rest

        ; -- attack 1: read beyond the arena (past c0's length) --
        clen  t1, c0                    ; one past the end
        la    t0, scratch               ; ...
        li    t2, 8                      ; ...
        tget  tg0, t0, c0, t1, t2       ; must fault (bounds)

        ; -- attack 2: reach a core outside the guest's window via core control --
        la    t0, scratch               ; a stop/reset word
        li    t1, 1                      ; ...
        sd    t1, 0(t0)                  ; ...
        clen  t1, c3                     ; just past the guest's own cores
        li    t2, 8                      ; ...
        tput  tg0, t0, c3, t1, t2       ; must fault (bounds): cannot touch StrataOS's cores

        ; -- attack 3: read a device port the guest was not given (past the clock) --
        la    t0, scratch               ; ...
        li    t1, 64                     ; well past the 16-byte clock window
        li    t2, 8                      ; ...
        tget  tg0, t0, c2, t1, t2       ; must fault (bounds)

        ; -- attack 4: use a capability register it does not hold (c7 is empty) --
        la    t0, scratch               ; ...
        li    t1, 0                      ; ...
        li    t2, 8                      ; ...
        tget  tg0, t0, c7, t1, t2       ; must fault (capinv)

        ; -- report whether all four were blocked --
        la    t0, blocked                ; all four?
        ld    t0, 0(t0)                  ; ...
        li    t1, NATTACK                ; ...
        la    a0, s_ok                    ; "isolation holds."
        li    a1, s_ok_e - s_ok          ; ...
        beq   t0, t1, rep                ; ...
        la    a0, s_bad                   ; "ISOLATION FAILED."
        li    a1, s_bad_e - s_bad        ; ...
rep:
        mv    t3, a0                     ; t3 = text, t4 = length
        mv    t4, a1                     ; ...
        la    t0, hdr                    ; build the WRITE header
        sd    zero, 0(t0)                ; ...
        sd    zero, 8(t0)                ; ...
        sd    zero, 16(t0)               ; ...
        sd    zero, 24(t0)               ; ...
        sd    zero, 32(t0)               ; ...
        li    t1, OP_WRITE               ; ...
        sd    t1, 0(t0)                  ; ...
        sd    t4, 16(t0)                 ; ...
        li    t1, 64                     ; the header -> the buffer
        tput  tg0, t0, c6, zero, t1     ; ...
        li    t1, 64                     ; the text -> offset 64
        addi  t4, t4, 7                  ; (transfers to far memory are 8-aligned)
        srli  t4, t4, 3                  ; ...
        slli  t4, t4, 3                  ; ...
        tput  tg0, t3, c6, t1, t4       ; ...
        twait 1                          ; ...
        csend c6, c1                     ; lend the buffer to the tty server
        ctake c6                         ; the reply comes back

        ; -- attack 5: smuggle a buffer into the block device. cmkep an endpoint
        ;    to the block-device node and csend a buffer through it. The device
        ;    pairs a buffer only with a command from the same core, so this stray
        ;    buffer is bounced; fs's I/O is untouched (the harness checks that). --
        csrr  t0, ncores                 ; the block-device node is just above the cores
        cmkep c7, t0                     ; an endpoint for it
        csend c6, c7                     ; send it our buffer (it comes back, unused)
        ctake c6                         ; take the bounce
spin:
        j     spin                       ; spin forever (StrataOS ends us with a reset)

; supervisor trap handler: a fault we expected. Count it and skip the instruction.
        .align 2                         ; ...
handler:
        la    t0, blocked                ; one more blocked
        ld    t1, 0(t0)                  ; ...
        addi  t1, t1, 1                  ; ...
        sd    t1, 0(t0)                  ; ...
        csrr  t0, epc                    ; skip the faulting transfer
        addi  t0, t0, 4                  ; ...
        csrw  epc, t0                    ; ...
        eret                             ; back to the next attack
